"""
Stability Verification Module for Sensitivity Analysis (Task T028b).

This module reads the sensitivity analysis table generated by T028a,
counts the number of thresholds where the p-value indicates statistical
significance (p < 0.05), and reports a stability metric.

It does not fail the pipeline; it logs the finding and returns the metric
for inclusion in the final report.
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional

# Add project root to path if running as script
if __name__ == "__main__":
    project_root = Path(__file__).resolve().parent.parent
    if str(project_root) not in sys.path:
        sys.path.insert(0, str(project_root))

from config import ProjectConfig, setup_logging

def load_sensitivity_table(table_path: Path) -> List[Dict[str, Any]]:
    """
    Loads the sensitivity analysis table from a JSON or CSV file.
    
    Args:
        table_path: Path to the sensitivity table file.
        
    Returns:
        List of dictionaries representing rows in the table.
        
    Raises:
        FileNotFoundError: If the table file does not exist.
        ValueError: If the file format is unsupported or data is malformed.
    """
    if not table_path.exists():
        raise FileNotFoundError(f"Sensitivity table not found at: {table_path}")
    
    logger = logging.getLogger(__name__)
    
    if table_path.suffix == '.json':
        with open(table_path, 'r') as f:
            data = json.load(f)
            if isinstance(data, list):
                return data
            elif isinstance(data, dict) and 'results' in data:
                return data['results']
            else:
                raise ValueError("JSON format unexpected. Expected a list or dict with 'results' key.")
    elif table_path.suffix == '.csv':
        import pandas as pd
        df = pd.read_csv(table_path)
        return df.to_dict(orient='records')
    else:
        raise ValueError(f"Unsupported file format: {table_path.suffix}. Use .json or .csv")

def calculate_stability_metric(sensitivity_results: List[Dict[str, Any]], p_threshold: float = 0.05) -> Dict[str, Any]:
    """
    Analyzes sensitivity results to determine stability across thresholds.
    
    Counts how many thresholds have a p-value < p_threshold.
    
    Args:
        sensitivity_results: List of dicts containing 'threshold' and 'p_value'.
        p_threshold: The significance threshold (default 0.05).
        
    Returns:
        Dictionary containing the stability count, total thresholds, and a summary string.
    """
    significant_count = 0
    total_count = len(sensitivity_results)
    details = []
    
    if total_count == 0:
        return {
            "significant_count": 0,
            "total_count": 0,
            "stability_ratio": 0.0,
            "summary": "No sensitivity results found to evaluate stability.",
            "details": []
        }

    for row in sensitivity_results:
        # Handle potential float conversion issues or string values
        try:
            p_val = float(row.get('p_value', 1.0))
            threshold_val = row.get('threshold', 'unknown')
            is_significant = p_val < p_threshold
            
            if is_significant:
                significant_count += 1
            
            details.append({
                "threshold": threshold_val,
                "p_value": p_val,
                "significant": is_significant
            })
        except (ValueError, TypeError) as e:
            logging.warning(f"Could not parse p_value for row {row}: {e}")
            details.append({
                "threshold": row.get('threshold', 'unknown'),
                "p_value": None,
                "significant": False,
                "error": str(e)
            })

    stability_ratio = significant_count / total_count if total_count > 0 else 0.0
    
    summary = f"Stable at {significant_count}/{total_count} thresholds (p < {p_threshold})"
    
    return {
        "significant_count": significant_count,
        "total_count": total_count,
        "stability_ratio": stability_ratio,
        "summary": summary,
        "details": details
    }

def verify_stability(table_path: Path, output_path: Optional[Path] = None) -> Dict[str, Any]:
    """
    Main entry point to verify stability from a sensitivity table.
    
    Args:
        table_path: Path to the sensitivity analysis table (JSON/CSV).
        output_path: Optional path to write the stability report (JSON).
        
    Returns:
        The stability metric dictionary.
    """
    logger = logging.getLogger(__name__)
    logger.info(f"Verifying stability from table: {table_path}")
    
    try:
        results = load_sensitivity_table(table_path)
    except FileNotFoundError as e:
        logger.error(f"Table not found: {e}")
        # Return a failure state without crashing the pipeline
        return {
            "significant_count": 0,
            "total_count": 0,
            "stability_ratio": 0.0,
            "summary": f"Error: {e}",
            "status": "failed",
            "details": []
        }
    except ValueError as e:
        logger.error(f"Invalid table format: {e}")
        return {
            "significant_count": 0,
            "total_count": 0,
            "stability_ratio": 0.0,
            "summary": f"Error: {e}",
            "status": "failed",
            "details": []
        }

    metric = calculate_stability_metric(results)
    metric["status"] = "success"
    
    logger.info(f"Stability Verification Result: {metric['summary']}")
    
    if output_path:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, 'w') as f:
            json.dump(metric, f, indent=2)
        logger.info(f"Stability report written to: {output_path}")
        
    return metric

def main():
    """
    Script entry point. Reads the sensitivity table from T028a,
    computes the stability metric, and prints it.
    """
    config = ProjectConfig()
    setup_logging(level=config.log_level)
    logger = logging.getLogger(__name__)
    
    # Default paths based on project structure
    sensitivity_table_path = config.data_processed_dir / "sensitivity_analysis_table.json"
    stability_report_path = config.data_processed_dir / "stability_verification.json"
    
    # Allow override via environment variables or command line if needed
    if len(sys.argv) > 1:
        sensitivity_table_path = Path(sys.argv[1])
    if len(sys.argv) > 2:
        stability_report_path = Path(sys.argv[2])
        
    logger.info(f"Input Sensitivity Table: {sensitivity_table_path}")
    logger.info(f"Output Stability Report: {stability_report_path}")
    
    result = verify_stability(sensitivity_table_path, stability_report_path)
    
    print(f"\n--- Stability Verification Result ---")
    print(f"Summary: {result['summary']}")
    print(f"Significant Thresholds: {result['significant_count']}/{result['total_count']}")
    print(f"Status: {result['status']}")
    
    if result['status'] == 'success':
        print("The pipeline continues. This metric is reported as a finding.")
    else:
        print("Warning: Stability verification encountered an issue (e.g., missing file).")
        print("The pipeline continues as per T028b requirements.")

if __name__ == "__main__":
    main()
