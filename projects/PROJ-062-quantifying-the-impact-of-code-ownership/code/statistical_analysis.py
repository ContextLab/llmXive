def load_metric_data(results_dir: Optional[Path] = None) -> pd.DataFrame:
    """
    Load the aggregated metrics from the results directory.
    Expects a file named 'module_metrics.csv' or similar generated by metrics_calc.
    """
    if results_dir is None:
        output_dir = get_output_dir()
