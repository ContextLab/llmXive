import os
import sys
import pandas as pd
import numpy as np
from pathlib import Path
from datetime import datetime
from logging_config import get_logger, info, error, warning

# Project root relative to this file
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_RAW_DIR = PROJECT_ROOT / "data" / "raw"
DATA_PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
LOG_FILE = PROJECT_ROOT / "data" / "processed" / "exclusion_log.txt"

def load_raw_learner_data(input_path: str) -> pd.DataFrame:
    """
    Loads the raw learner data from the specified path.
    Expects a CSV file generated by the preprocess step.
    """
    path = Path(input_path)
    if not path.exists():
        error(f"Input file not found: {path}")
        raise FileNotFoundError(f"Input file not found: {path}")
    
    info(f"Loading raw learner data from {path}")
    try:
        df = pd.read_csv(path)
        info(f"Loaded {len(df)} records")
        return df
    except Exception as e:
        error(f"Failed to load data: {e}")
        raise

def filter_no_forum_interactions(df: pd.DataFrame, forum_column: str = "forum_events") -> tuple[pd.DataFrame, int]:
    """
    Filters out learners who have no recorded forum interactions.
    
    Args:
        df: The input DataFrame containing learner records.
        forum_column: The name of the column containing forum event counts or flags.
                      If the column contains counts, we filter where count == 0.
                      If it's a boolean or list-like, we check for emptiness/nulls.
    
    Returns:
        A tuple of (filtered_df, exclusion_count)
    """
    original_count = len(df)
    
    # Determine if the column represents a count or a list/flag
    # Assuming 'forum_events' might be a count (int) or a list of events.
    # Based on typical OULAD preprocessing, it's often a count or a boolean flag.
    # We will filter out rows where the value is 0, NaN, or empty string.
    
    if forum_column not in df.columns:
        warning(f"Column '{forum_column}' not found in dataframe. Attempting to filter based on common forum indicators.")
        # Fallback: try to find a column that looks like forum activity
        potential_cols = [c for c in df.columns if 'forum' in c.lower()]
        if potential_cols:
            forum_column = potential_cols[0]
            info(f"Using fallback column: {forum_column}")
        else:
            error("No forum-related column found to filter on. Returning original data.")
            return df, 0

    # Filter logic: Keep rows where forum activity is > 0 or not null
    # We assume 0 means no interaction.
    initial_mask = df[forum_column].notna()
    
    # Check if it's numeric
    if pd.api.types.is_numeric_dtype(df[forum_column]):
        # Keep rows where count > 0
        final_mask = initial_mask & (df[forum_column] > 0)
    else:
        # For non-numeric (e.g., lists, strings), keep non-empty
        # Convert to string to handle potential list representations safely
        final_mask = initial_mask & (df[forum_column].astype(str).str.strip() != "")
    
    filtered_df = df[final_mask].reset_index(drop=True)
    exclusion_count = original_count - len(filtered_df)
    
    info(f"Filtered out {exclusion_count} learners with no forum interactions.")
    return filtered_df, exclusion_count

def save_filtered_data(df: pd.DataFrame, output_path: str, excluded_count: int, log_path: str = None):
    """
    Saves the filtered DataFrame and logs the exclusion details.
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    info(f"Saving filtered data to {output_path}")
    df.to_csv(output_path, index=False)
    
    # Log exclusion details
    if log_path is None:
        log_path = LOG_FILE
    else:
        log_path = Path(log_path)
        
    log_path.parent.mkdir(parents=True, exist_ok=True)
    
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    log_entry = (
        f"Timestamp: {timestamp}\n"
        f"Task: T018 - Exclude learners with no forum interactions\n"
        f"Excluded Count: {excluded_count}\n"
        f"Output File: {output_path}\n"
        f"{'='*50}\n"
    )
    
    with open(log_path, "a") as f:
        f.write(log_entry)
    
    info(f"Exclusion log written to {log_path}")

def main():
    """
    Main entry point for the T018 exclusion logic.
    Reads from data/processed/learners_raw.csv (or similar intermediate)
    and writes to data/processed/learners_filtered.csv.
    """
    # Default paths relative to project root
    # Assuming the previous step (T017) generated learners_raw.csv
    input_file = DATA_PROCESSED_DIR / "learners_raw.csv"
    
    # If learners_raw.csv doesn't exist, check if there's a raw file from T016
    if not input_file.exists():
        # Fallback to a generic raw file if the specific one isn't there yet
        # This handles cases where the pipeline order might vary slightly in testing
        potential_files = list(DATA_PROCESSED_DIR.glob("*.csv"))
        if potential_files:
            input_file = potential_files[0]
            warning(f"learners_raw.csv not found. Using {input_file.name} as input.")
        else:
            error("No CSV files found in data/processed/. Cannot run exclusion.")
            sys.exit(1)

    output_file = DATA_PROCESSED_DIR / "learners_filtered_no_forum.csv"
    
    try:
        df = load_raw_learner_data(str(input_file))
        
        # Identify the column name for forum interactions
        # Common names: 'forum_events', 'num_forum_posts', 'has_forum_activity'
        # We'll try to detect it or use a default if the schema is known
        forum_col = "forum_events"
        if forum_col not in df.columns:
            # Try to find a column with 'forum' in the name
            forum_cols = [c for c in df.columns if 'forum' in c.lower()]
            if forum_cols:
                forum_col = forum_cols[0]
            else:
                # If no forum column exists, we might need to create one or fail
                # For T018, we assume the data has this info. If not, we log and exit.
                error(f"No forum interaction column found in {input_file}. Columns: {list(df.columns)}")
                sys.exit(1)
        
        filtered_df, count = filter_no_forum_interactions(df, forum_column=forum_col)
        save_filtered_data(filtered_df, str(output_file), count)
        
        info("T018 Exclusion complete.")
        return 0
        
    except Exception as e:
        error(f"Error during T018 execution: {e}")
        raise

if __name__ == "__main__":
    sys.exit(main())