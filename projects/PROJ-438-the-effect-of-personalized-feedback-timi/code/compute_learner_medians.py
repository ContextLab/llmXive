"""
compute_learner_medians.py

Implements median calculation per learner to determine their representative
feedback interval. This script reads the interval data generated by
`compute_intervals.py` and aggregates it to the learner level.

Output:
    data/processed/learner_medians.csv
    Contains: learner_id, median_feedback_interval_hours
"""
import os
import sys
import pandas as pd
import numpy as np
from pathlib import Path
from datetime import datetime

# Import logging utilities from sibling module
from logging_config import get_logger, info, error, warning

# Import data loading utilities from sibling module if available, 
# otherwise define local loader logic to match expected input from T023
# Expected input from compute_intervals.py (T023): data/processed/learner_intervals.csv
# Columns expected: learner_id, interval_hours (or similar)

INPUT_FILE = Path("data/processed/learner_intervals.csv")
OUTPUT_FILE = Path("data/processed/learner_medians.csv")

# Ensure output directory exists
OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)

logger = get_logger(__name__)

def load_learner_intervals(filepath: Path) -> pd.DataFrame:
    """
    Load the learner intervals data generated by compute_intervals.py.
    """
    if not filepath.exists():
        raise FileNotFoundError(
            f"Input file not found: {filepath}. "
            "Please run code/compute_intervals.py first."
        )
    
    df = pd.read_csv(filepath)
    logger.info(f"Loaded {len(df)} interval records from {filepath}")
    
    # Validate expected columns
    required_cols = ['learner_id', 'interval_hours']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(
            f"Input file missing required columns: {missing_cols}. "
            f"Found columns: {list(df.columns)}"
        )
    
    return df

def calculate_median_intervals(df: pd.DataFrame) -> pd.DataFrame:
    """
    Calculate the median feedback interval per learner.
    
    Parameters:
        df (pd.DataFrame): DataFrame with 'learner_id' and 'interval_hours'
    
    Returns:
        pd.DataFrame: Aggregated DataFrame with 'learner_id' and 'median_feedback_interval_hours'
    """
    if df.empty:
        raise ValueError("Input DataFrame is empty. Cannot calculate medians.")
    
    # Group by learner and calculate median
    # Use dropna=True to ignore NaN intervals if any exist
    median_df = df.groupby('learner_id')['interval_hours'].median().reset_index()
    median_df.rename(columns={'interval_hours': 'median_feedback_interval_hours'}, inplace=True)
    
    # Log statistics
    info(f"Calculated medians for {len(median_df)} unique learners.")
    
    # Log distribution of intervals for sanity check
    info(f"Median interval stats: Min={median_df['median_feedback_interval_hours'].min():.2f}h, "
         f"Max={median_df['median_feedback_interval_hours'].max():.2f}h, "
         f"Mean={median_df['median_feedback_interval_hours'].mean():.2f}h")
         
    return median_df

def save_median_data(df: pd.DataFrame, filepath: Path) -> None:
    """
    Save the calculated median intervals to a CSV file.
    """
    try:
        df.to_csv(filepath, index=False)
        info(f"Saved median data to {filepath}")
        logger.info(f"Output shape: {df.shape}")
    except Exception as e:
        error(f"Failed to save median data to {filepath}: {e}")
        raise

def main():
    """
    Main entry point for the median calculation task (T024).
    """
    logger.info("Starting T024: Compute Learner Medians")
    
    try:
        # 1. Load data
        df_intervals = load_learner_intervals(INPUT_FILE)
        
        # 2. Calculate medians
        df_medians = calculate_median_intervals(df_intervals)
        
        # 3. Save output
        save_median_data(df_medians, OUTPUT_FILE)
        
        logger.info("T024 completed successfully.")
        
    except FileNotFoundError as e:
        error(str(e))
        sys.exit(1)
    except ValueError as e:
        error(str(e))
        sys.exit(1)
    except Exception as e:
        error(f"Unexpected error during median calculation: {e}")
        raise

if __name__ == "__main__":
    main()