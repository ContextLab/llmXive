"""
Compute the median feedback interval per learner.

This script reads the interval-level data generated by `compute_intervals.py`
(specifically `data/processed/learner_intervals.csv`), calculates the median
feedback interval for each unique learner, and saves the result to
`data/processed/learner_medians.csv`.

This median value serves as the representative feedback interval for the learner,
which is subsequently used in `bin_feedback_groups.py` to assign timing groups.

Requirements:
- Input: data/processed/learner_intervals.csv (columns: student_code, interval_hours)
- Output: data/processed/learner_medians.csv (columns: student_code, median_interval_hours)
"""
import os
import sys
import pandas as pd
import numpy as np
from pathlib import Path
from datetime import datetime

# Project root relative to this file
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = PROJECT_ROOT / "data"
PROCESSED_DIR = DATA_DIR / "processed"

# Input/Output paths
INPUT_FILE = PROCESSED_DIR / "learner_intervals.csv"
OUTPUT_FILE = PROCESSED_DIR / "learner_medians.csv"

def load_learner_intervals(input_path: Path) -> pd.DataFrame:
    """
    Load the learner intervals dataframe.
    Validates that required columns exist.
    """
    if not input_path.exists():
        raise FileNotFoundError(
            f"Input file not found: {input_path}. "
            "Please run `code/compute_intervals.py` first."
        )

    df = pd.read_csv(input_path)

    required_cols = ["student_code", "interval_hours"]
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(
            f"Input file missing required columns: {missing_cols}. "
            f"Expected: {required_cols}"
        )

    return df

def calculate_median_intervals(df: pd.DataFrame) -> pd.DataFrame:
    """
    Calculate the median feedback interval per learner.

    Parameters:
    - df: DataFrame with columns ['student_code', 'interval_hours']

    Returns:
    - DataFrame with columns ['student_code', 'median_interval_hours']
    """
    # Ensure numeric type for calculation
    df["interval_hours"] = pd.to_numeric(df["interval_hours"], errors="coerce")

    # Group by student and calculate median
    # dropna=True ensures we don't include NaN intervals in the median calculation
    median_df = (
        df.groupby("student_code", as_index=False)["interval_hours"]
        .median()
        .rename(columns={"interval_hours": "median_interval_hours"})
    )

    # Log count of learners processed
    print(f"Calculated median for {len(median_df)} learners.")

    return median_df

def save_median_data(df: pd.DataFrame, output_path: Path) -> None:
    """
    Save the median intervals to a CSV file.
    Creates the parent directory if it does not exist.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    print(f"Saved median data to: {output_path}")

def main():
    """Main entry point."""
    print(f"Starting median calculation at {datetime.now().isoformat()}")
    print(f"Input: {INPUT_FILE}")
    print(f"Output: {OUTPUT_FILE}")

    try:
        # 1. Load data
        df_intervals = load_learner_intervals(INPUT_FILE)
        print(f"Loaded {len(df_intervals)} interval records.")

        # 2. Calculate medians
        df_medians = calculate_median_intervals(df_intervals)

        # 3. Save output
        save_median_data(df_medians, OUTPUT_FILE)

        print(f"Median calculation completed successfully.")

    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        sys.exit(1)
    except ValueError as e:
        print(f"DATA ERROR: {e}")
        sys.exit(1)
    except Exception as e:
        print(f"UNEXPECTED ERROR: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()