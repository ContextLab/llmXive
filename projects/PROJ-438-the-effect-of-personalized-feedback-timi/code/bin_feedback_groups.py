"""
Bin feedback groups based on median feedback intervals.

Implements FR-004: Assign "Immediate" (<2h), "Delayed" (2h–48h), or "Variable" (>48h) groups.
"""
import os
import sys
import pandas as pd
import numpy as np
from pathlib import Path
from logging_config import get_logger, info, warning, error

# Constants for binning boundaries (in hours)
IMMEDIATE_THRESHOLD = 2.0
DELAYED_THRESHOLD = 48.0

logger = get_logger(__name__)


def load_learner_intervals(input_path: str) -> pd.DataFrame:
    """
    Load the learner intervals data from the CSV file generated by compute_learner_medians.

    Args:
        input_path: Path to the CSV file containing learner median intervals.

    Returns:
        DataFrame with learner intervals.
    """
    path = Path(input_path)
    if not path.exists():
        error(f"Input file not found: {path}")
        raise FileNotFoundError(f"Input file not found: {path}")

    logger.info(f"Loading learner intervals from {path}")
    df = pd.read_csv(path)

    # Validate required columns
    required_cols = ['learner_id', 'median_interval_hours']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        error(f"Missing required columns: {missing_cols}")
        raise ValueError(f"Missing required columns: {missing_cols}")

    logger.info(f"Loaded {len(df)} learner records")
    return df


def assign_feedback_group(row: pd.Series) -> str:
    """
    Assign a feedback group to a single learner based on their median interval.

    Rules (FR-004):
    - Immediate: median_interval_hours < 2h
    - Delayed: 2h <= median_interval_hours <= 48h
    - Variable: median_interval_hours > 48h

    Args:
        row: A row from the learner intervals DataFrame.

    Returns:
        String label: "Immediate", "Delayed", or "Variable".
    """
    interval = row['median_interval_hours']

    if pd.isna(interval):
        return "Unknown"

    if interval < IMMEDIATE_THRESHOLD:
        return "Immediate"
    elif interval <= DELAYED_THRESHOLD:
        return "Delayed"
    else:
        return "Variable"


def bin_feedback_groups(df: pd.DataFrame) -> pd.DataFrame:
    """
    Apply the binning logic to the entire DataFrame.

    Args:
        df: DataFrame containing 'median_interval_hours'.

    Returns:
        DataFrame with an added 'feedback_group' column.
    """
    logger.info("Assigning feedback groups based on median intervals")
    df = df.copy()
    df['feedback_group'] = df.apply(assign_feedback_group, axis=1)

    # Log distribution
    group_counts = df['feedback_group'].value_counts()
    info("Feedback group distribution:")
    for group, count in group_counts.items():
        info(f"  {group}: {count} ({100*count/len(df):.1f}%)")

    return df


def save_binned_data(df: pd.DataFrame, output_path: str) -> None:
    """
    Save the binned learner data to a CSV file.

    Args:
        df: DataFrame with 'feedback_group' column.
        output_path: Path to save the output CSV.
    """
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    logger.info(f"Saving binned data to {path}")
    df.to_csv(path, index=False)
    info(f"Saved {len(df)} records to {path}")


def main():
    """
    Main entry point for the binning script.
    """
    # Define paths relative to project root
    project_root = Path(__file__).resolve().parent.parent
    input_file = project_root / "data" / "processed" / "learners_median_intervals.csv"
    output_file = project_root / "data" / "processed" / "learners_binned.csv"

    logger.info("Starting feedback group binning process")

    try:
        # Load data
        df = load_learner_intervals(str(input_file))

        # Bin groups
        df_binned = bin_feedback_groups(df)

        # Save output
        save_binned_data(df_binned, str(output_file))

        info("Binning process completed successfully")
        return 0

    except FileNotFoundError as e:
        error(f"File not found: {e}")
        return 1
    except ValueError as e:
        error(f"Data validation error: {e}")
        return 1
    except Exception as e:
        error(f"Unexpected error: {e}")
        raise


if __name__ == "__main__":
    sys.exit(main())
