import os
import sys
import pandas as pd
import numpy as np
from pathlib import Path
from logging_config import get_logger, info, warning, error
from config import load_config

def load_learner_intervals(input_path: str) -> pd.DataFrame:
    """
    Loads the learner intervals dataframe from the CSV generated by T024.
    
    Args:
        input_path: Path to the learners_medians.csv file.
        
    Returns:
        DataFrame containing learner_id, median_interval_hours, and other raw fields.
    """
    logger = get_logger(__name__)
    try:
        df = pd.read_csv(input_path)
        logger.info(f"Loaded {len(df)} records from {input_path}")
        return df
    except FileNotFoundError:
        error(f"File not found: {input_path}")
        raise
    except Exception as e:
        error(f"Error reading file {input_path}: {e}")
        raise

def assign_feedback_group(df: pd.DataFrame) -> pd.DataFrame:
    """
    Assigns a feedback group label to each learner based on their median interval.
    
    Rules (FR-004):
    - "Immediate": median < 2 hours
    - "Delayed": 2 hours <= median <= 48 hours
    - "Variable": median > 48 hours
    
    Args:
        df: DataFrame with 'median_interval_hours' column.
        
    Returns:
        DataFrame with a new 'feedback_group' column.
    """
    logger = get_logger(__name__)
    
    if 'median_interval_hours' not in df.columns:
        error("Input DataFrame missing 'median_interval_hours' column.")
        raise ValueError("Missing required column: median_interval_hours")
    
    def get_group(interval):
        if pd.isna(interval):
            return np.nan
        if interval < 2.0:
            return "Immediate"
        elif interval <= 48.0:
            return "Delayed"
        else:
            return "Variable"
    
    df = df.copy()
    df['feedback_group'] = df['median_interval_hours'].apply(get_group)
    
    info(f"Assigned groups: {df['feedback_group'].value_counts().to_dict()}")
    return df

def bin_feedback_groups(df: pd.DataFrame) -> pd.DataFrame:
    """
    Finalizes the binning process.
    Currently performs validation and ensures categorical types.
    
    Args:
        df: DataFrame with 'feedback_group' column.
        
    Returns:
        DataFrame with validated 'feedback_group' column.
    """
    logger = get_logger(__name__)
    
    valid_groups = ["Immediate", "Delayed", "Variable"]
    
    # Ensure column exists
    if 'feedback_group' not in df.columns:
        error("Cannot bin: 'feedback_group' column missing.")
        raise ValueError("Missing feedback_group column")
    
    # Optional: Convert to categorical for memory efficiency and validation
    # Note: We keep NaNs as NaN, not as a category, to handle missing data correctly
    df['feedback_group'] = pd.Categorical(
        df['feedback_group'], 
        categories=valid_groups, 
        ordered=True
    )
    
    missing_count = df['feedback_group'].isna().sum()
    if missing_count > 0:
        warning(f"Found {missing_count} records with missing feedback group (NaN intervals).")
    
    return df

def save_binned_data(df: pd.DataFrame, output_path: str) -> None:
    """
    Saves the binned dataframe to CSV.
    
    Args:
        df: DataFrame with binned data.
        output_path: Path to save the CSV file.
    """
    logger = get_logger(__name__)
    
    # Ensure parent directory exists
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    
    # Convert categorical to string for CSV export to avoid pandas warnings
    df_export = df.copy()
    if 'feedback_group' in df_export.columns:
        df_export['feedback_group'] = df_export['feedback_group'].astype(str).replace('nan', np.nan)
    
    df_export.to_csv(output_path, index=False)
    info(f"Saved binned data to {output_path} with {len(df_export)} records")

def main():
    """Entry point for running the binning process directly."""
    logger = get_logger(__name__)
    config = load_config()
    base_path = Path(config.get('base_path', '.'))
    
    # Default paths if not in config
    input_file = base_path / "data/processed/learners_medians.csv"
    output_file = base_path / "data/processed/learners_binned.csv"
    
    if not input_file.exists():
        error(f"Input file {input_file} does not exist. Run T024 first.")
        sys.exit(1)
        
    df = load_learner_intervals(str(input_file))
    df = assign_feedback_group(df)
    df = bin_feedback_groups(df)
    save_binned_data(df, str(output_file))
    info("Binning process complete.")

if __name__ == "__main__":
    main()
