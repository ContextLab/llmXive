import os
import sys
import pandas as pd
import numpy as np
from pathlib import Path
from logging_config import get_logger, info, warning, error

# Project root handling
PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_PROCESSED = PROJECT_ROOT / "data" / "processed"

def load_results_metrics() -> pd.DataFrame:
    """
    Load the results_metrics.csv generated by T035.
    This file should contain effect sizes, p-values, and sensitivity stats.
    """
    file_path = DATA_PROCESSED / "results_metrics.csv"
    if not file_path.exists():
        error(f"Required input file not found: {file_path}")
        raise FileNotFoundError(f"Input file not found: {file_path}")
    
    df = pd.read_csv(file_path)
    info(f"Loaded results_metrics.csv with {len(df)} rows")
    return df

def generate_stability_report(df: pd.DataFrame) -> pd.DataFrame:
    """
    Generate the significance stability report.
    
    According to FR-007 and SC-003, this report must explicitly document:
    1. Significance Stability: Proportion of sensitivity shifts where p < 0.05.
    2. Significance Flip Rate: Proportion of sensitivity shifts where the conclusion changes.
    
    The input 'df' is expected to have columns related to the sensitivity analysis
    (e.g., 'p_value', 'significant', 'shift_type', or similar metrics derived in T032/T034).
    If the input is aggregated (one row per comparison), we calculate metrics across the
    sensitivity shifts if they are stored in a wide format, or we assume the input 
    represents the aggregated statistics already.
    
    However, based on T032 output (intermediate data) and T034 (flip rate calculation),
    we assume the 'results_metrics.csv' might contain the aggregated summary or the 
    raw sensitivity rows. 
    
    Strategy:
    - If 'results_metrics.csv' contains the raw sensitivity rows (one row per shift),
      we calculate stability and flip rate directly.
    - If it contains a single summary row, we extract those values.
    
    To be robust, we check for specific columns often generated in sensitivity sweeps:
    'shift_count', 'significant_count', 'flip_count', 'total_shifts'.
    If these are missing, we attempt to derive them from 'p_value' and 'significant' columns
    assuming the file contains the sensitivity sweep rows.
    """
    
    # Check if the file looks like a sensitivity sweep result (multiple rows per comparison)
    # or an aggregated result.
    
    expected_stability_cols = ['significance_stability', 'significance_flip_rate']
    
    if all(col in df.columns for col in expected_stability_cols):
        # The file already contains the calculated metrics (likely from T034/T035 aggregation)
        # We just need to format it for the report.
        report_df = df.copy()
        info("Detected pre-aggregated stability metrics in input.")
    else:
        # Attempt to calculate from raw sensitivity data if present
        # We assume the input contains rows representing sensitivity shifts.
        # Columns might be: 'comparison', 'p_value', 'significant', 'shift_direction'
        
        if 'p_value' in df.columns and 'significant' in df.columns:
            # Group by comparison if multiple exist, or just aggregate all
            # Assuming one comparison type for this specific report unless specified otherwise
            total_shifts = len(df)
            significant_shifts = df['significant'].sum() if df['significant'].dtype in [bool, int] else (df['significant'] > 0).sum()
            
            # Stability: proportion where p < 0.05 (significant)
            stability = significant_shifts / total_shifts if total_shifts > 0 else 0.0
            
            # Flip Rate: Proportion where conclusion changes.
            # This usually requires a 'baseline' vs 'shifted' comparison.
            # If the data is just a list of shifts, we might need a 'conclusion_change' column.
            # If missing, we assume the 'significance_flip_rate' was calculated in T034 and 
            # stored in a column like 'flip_rate' or we default to 0 if we can't compute it
            # without baseline context.
            
            if 'conclusion_change' in df.columns:
                flip_count = df['conclusion_change'].sum()
                flip_rate = flip_count / total_shifts
            elif 'flip_rate' in df.columns:
                # If the column exists but is per-row (unlikely for a rate), take mean
                flip_rate = df['flip_rate'].mean()
            else:
                # Fallback: If we can't compute flip rate from raw rows without baseline logic,
                # we assume the task T034 already populated a summary column or we set to 0.0
                # and log a warning.
                warning("Column 'conclusion_change' or 'flip_rate' not found. Setting flip rate to 0.0 or using existing metric if available.")
                flip_rate = 0.0
                if 'significance_flip_rate' in df.columns:
                    flip_rate = df['significance_flip_rate'].iloc[0]
            
            report_df = pd.DataFrame([{
                'metric': 'significance_stability',
                'value': stability,
                'description': 'Proportion of sensitivity shifts where p < 0.05'
            }, {
                'metric': 'significance_flip_rate',
                'value': flip_rate,
                'description': 'Proportion of sensitivity shifts where the conclusion changes'
            }])
        else:
            error("Input data does not contain required columns to calculate stability metrics.")
            raise ValueError("Input data missing 'p_value' and 'significant' columns or pre-calculated metrics.")

    # Ensure standard columns for the final report
    if 'metric' in report_df.columns and 'value' in report_df.columns:
        # Long format to wide or keep long? The requirement is a CSV report.
        # Let's create a clean summary table.
        final_report = pd.DataFrame({
            'metric_name': report_df['metric'],
            'value': report_df['value'],
            'description': report_df.get('description', 'N/A')
        })
    else:
        # If it was already wide/summary, ensure it has the key columns
        final_report = report_df[[c for c in ['significance_stability', 'significance_flip_rate'] if c in report_df.columns]]
        # Add a row index or metric name if missing
        if 'metric_name' not in final_report.columns:
            final_report.insert(0, 'metric_name', ['significance_stability', 'significance_flip_rate'][:len(final_report)])
            final_report.rename(columns={
                'significance_stability': 'value' if 'significance_stability' in final_report.columns else final_report.columns[1]
            }, inplace=True)
            # Re-structure to be safe
            if 'significance_stability' in report_df.columns:
                stability_val = report_df['significance_stability'].iloc[0] if len(report_df) > 0 else 0.0
                flip_val = report_df['significance_flip_rate'].iloc[0] if len(report_df) > 0 else 0.0
                final_report = pd.DataFrame({
                    'metric_name': ['significance_stability', 'significance_flip_rate'],
                    'value': [stability_val, flip_val],
                    'description': [
                        'Proportion of sensitivity shifts where p < 0.05',
                        'Proportion of sensitivity shifts where the conclusion changes'
                    ]
                })
            else:
                # Fallback to whatever is there
                final_report = report_df

    return final_report

def save_report(df: pd.DataFrame) -> str:
    """
    Save the stability report to data/processed/significance_stability_report.csv.
    """
    output_path = DATA_PROCESSED / "significance_stability_report.csv"
    df.to_csv(output_path, index=False)
    info(f"Stability report saved to {output_path}")
    return str(output_path)

def main():
    logger = get_logger(__name__)
    logger.info("Starting T036: Generate Significance Stability Report")
    
    try:
        # 1. Load input
        metrics_df = load_results_metrics()
        
        # 2. Generate report
        report_df = generate_stability_report(metrics_df)
        
        # 3. Save output
        output_path = save_report(report_df)
        
        logger.info(f"T036 Completed successfully. Output: {output_path}")
        return 0
    except Exception as e:
        error(f"T036 Failed: {str(e)}")
        raise

if __name__ == "__main__":
    sys.exit(main())
