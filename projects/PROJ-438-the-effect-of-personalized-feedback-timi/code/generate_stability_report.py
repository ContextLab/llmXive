import os
import sys
import pandas as pd
import numpy as np
from pathlib import Path
from logging_config import get_logger, info, warning, error

# Project root relative to this file
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"

def load_results_metrics():
    """
    Load the results_metrics.csv generated by T035.
    Expected columns: 'metric_name', 'effect_size', 'p_value', 'significance_stability', 'significance_flip_rate'
    """
    input_path = DATA_PROCESSED_DIR / "results_metrics.csv"
    if not input_path.exists():
        raise FileNotFoundError(f"Required input file not found: {input_path}")
    
    df = pd.read_csv(input_path)
    return df

def generate_stability_report(results_df):
    """
    Generate a structured report documenting stability metrics and flip rates.
    
    This function extracts the stability and flip rate metrics from the input
    dataframe and formats them into a clear summary report.
    
    Args:
        results_df (pd.DataFrame): DataFrame containing analysis results.
    
    Returns:
        pd.DataFrame: A report dataframe with stability metrics.
    """
    if results_df.empty:
        raise ValueError("Input results dataframe is empty.")

    # Ensure we have the necessary columns
    required_cols = ['significance_stability', 'significance_flip_rate']
    missing_cols = [c for c in required_cols if c not in results_df.columns]
    if missing_cols:
        raise KeyError(f"Missing required columns in results_metrics.csv: {missing_cols}")

    # Extract the values (assuming single row summary or taking the first valid row)
    # The sensitivity analysis (T032) and metrics generation (T035) should produce
    # a summary row for the main analysis.
    summary_row = results_df.iloc[0]
    
    report_data = {
        "metric": [
            "Significance Stability",
            "Significance Flip Rate",
            "Stability Threshold Check",
            "Flip Rate Threshold Check"
        ],
        "value": [
            summary_row['significance_stability'],
            summary_row['significance_flip_rate'],
            summary_row['significance_stability'] >= 0.90, # Assuming 90% stability target
            summary_row['significance_flip_rate'] <= 0.10  # Assuming 10% flip rate max
        ],
        "description": [
          "Proportion of boundary shifts where p < 0.05 (FR-007, SC-003)",
          "Proportion of boundary shifts where the significance conclusion changes (SC-003)",
          "Checks if stability >= 0.90 (configurable)",
          "Checks if flip rate <= 0.10 (configurable)"
        ]
    }
    
    return pd.DataFrame(report_data)

def save_report(report_df):
    """
    Save the stability report to data/processed/significance_stability_report.csv.
    
    Args:
        report_df (pd.DataFrame): The report dataframe to save.
    """
    output_path = DATA_PROCESSED_DIR / "significance_stability_report.csv"
    report_df.to_csv(output_path, index=False)
    info(f"Stability report saved to {output_path}")

def main():
    """
    Main entry point for generating the significance stability report.
    """
    logger = get_logger(__name__)
    try:
        info("Loading results metrics...")
        results_df = load_results_metrics()
        
        info("Generating stability report...")
        report_df = generate_stability_report(results_df)
        
        info("Saving stability report...")
        save_report(report_df)
        
        info("Significance stability report generation completed successfully.")
        return 0
    except Exception as e:
        error(f"Failed to generate stability report: {e}")
        raise

if __name__ == "__main__":
    sys.exit(main())
