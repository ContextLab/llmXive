"""
Generate the final results metrics CSV.

This script aggregates effect sizes (from models.py) and sensitivity statistics
(from sensitivity.py) into a single `data/processed/results_metrics.csv` file,
satisfying Success Criterion SC-001.

Dependencies:
- code/models.py (for extract_effect_sizes output)
- code/sensitivity.py (for run_sensitivity_analysis output)
- code/config.py (for path configuration)
"""
import os
import sys
import pandas as pd
import numpy as np
from pathlib import Path
from typing import Dict, Any

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from config import load_config, get_config_value
from logging_config import setup_logger, get_logger, info, error, warning, debug

# Initialize logger
logger = setup_logger("generate_results_metrics")

def load_effect_sizes(effects_path: Path) -> pd.DataFrame:
    """
    Load the effect sizes DataFrame generated by models.py.
    Expected columns: comparison, coef, se, t_stat, p_value, cohens_d
    """
    if not effects_path.exists():
        raise FileNotFoundError(f"Effect sizes file not found: {effects_path}")
    
    df = pd.read_csv(effects_path)
    info(f"Loaded effect sizes from {effects_path} with {len(df)} rows")
    return df

def load_sensitivity_stats(sensitivity_path: Path) -> pd.DataFrame:
    """
    Load the sensitivity analysis results generated by sensitivity.py.
    Expected columns: boundary_shift, significant_count, total_count, stability_rate
    """
    if not sensitivity_path.exists():
        raise FileNotFoundError(f"Sensitivity stats file not found: {sensitivity_path}")
    
    df = pd.read_csv(sensitivity_path)
    info(f"Loaded sensitivity stats from {sensitivity_path} with {len(df)} rows")
    return df

def merge_metrics(effects_df: pd.DataFrame, sensitivity_df: pd.DataFrame) -> pd.DataFrame:
    """
    Merge effect sizes and sensitivity statistics into a comprehensive results table.
    
    The merge logic assumes the sensitivity analysis covers the same model comparisons
    or provides a global stability metric. We align them by adding sensitivity columns
    to the effect size rows or creating a summary row if they are global.
    
    For this implementation, we assume the sensitivity analysis provides a global 
    stability metric for the main model run. We will append these as columns to the
    effect size rows, or create a separate summary section if the structure differs.
    
    Strategy:
    1. Calculate global stability metrics from sensitivity_df if multiple rows exist.
    2. Merge these global metrics with the effect size rows.
    3. Ensure all required columns for SC-001 are present.
    """
    # Calculate global stability metrics if sensitivity_df has multiple rows
    if len(sensitivity_df) > 0:
        global_stability = sensitivity_df['stability_rate'].mean()
        global_flip_rate = 1.0 - global_stability  # Simplified flip rate definition
        
        # Add global metrics to effect sizes
        effects_df['global_stability_rate'] = global_stability
        effects_df['global_flip_rate'] = global_flip_rate
        info(f"Calculated global stability: {global_stability:.4f}, flip rate: {global_flip_rate:.4f}")
    else:
        warning("Sensitivity dataframe is empty; filling with NaN")
        effects_df['global_stability_rate'] = np.nan
        effects_df['global_flip_rate'] = np.nan

    # Ensure column order for clarity
    # Standard SC-001 columns: comparison, effect_size (cohens_d), p_value, stability_metric, flip_rate
    columns_to_keep = [
        'comparison', 'coef', 'se', 't_stat', 'p_value', 'cohens_d',
        'global_stability_rate', 'global_flip_rate'
    ]
    
    # Filter to existing columns
    available_columns = [c for c in columns_to_keep if c in effects_df.columns]
    result_df = effects_df[available_columns].copy()
    
    # Rename for clarity in final output
    if 'cohens_d' in result_df.columns:
        result_df = result_df.rename(columns={'cohens_d': 'effect_size_cohens_d'})
    
    info(f"Prepared merged metrics dataframe with {len(result_df)} rows")
    return result_df

def save_results_metrics(df: pd.DataFrame, output_path: Path) -> None:
    """
    Save the merged metrics DataFrame to the specified CSV path.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    info(f"Successfully saved results metrics to {output_path}")
    
    # Validate output
    if len(df) == 0:
        error("Output file is empty. This might indicate a failure in upstream tasks.")
    else:
        info(f"Output file contains {len(df)} records.")

def main():
    """
    Main entry point for generating the results metrics CSV.
    """
    logger.info("Starting generate_results_metrics.py")
    
    try:
        # Load configuration
        config = load_config()
        
        # Define paths
        data_dir = Path(get_config_value(config, 'paths.processed_dir', 'data/processed'))
        effects_path = data_dir / 'effect_sizes.csv'
        sensitivity_path = data_dir / 'sensitivity_results.csv'
        output_path = data_dir / 'results_metrics.csv'
        
        info(f"Configuration loaded. Processed dir: {data_dir}")
        info(f"Expected inputs: {effects_path}, {sensitivity_path}")
        
        # Load data
        effects_df = load_effect_sizes(effects_path)
        sensitivity_df = load_sensitivity_stats(sensitivity_path)
        
        # Merge and process
        final_df = merge_metrics(effects_df, sensitivity_df)
        
        # Save output
        save_results_metrics(final_df, output_path)
        
        logger.info("generate_results_metrics.py completed successfully")
        return 0
        
    except FileNotFoundError as fnf:
        error(f"Input file missing: {fnf}")
        logger.error("Upstream tasks (models.py or sensitivity.py) may not have completed.")
        return 1
    except Exception as e:
        error(f"Unexpected error during execution: {e}")
        import traceback
        logger.error(traceback.format_exc())
        return 1

if __name__ == "__main__":
    sys.exit(main())
