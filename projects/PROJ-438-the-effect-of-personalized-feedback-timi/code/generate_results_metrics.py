        out_dir.mkdir(parents=True, exist_ok=True)
        
        output_file = out_dir / "results_metrics.csv"
        
        # 4. Save
        save_results_metrics(final_df, output_file)
        
        # 5. Log summary
        info(f"Generated {output_file} with {len(final_df)} comparisons.")
        info(f"Columns: {list(final_df.columns)}")
        
        return 0
        
