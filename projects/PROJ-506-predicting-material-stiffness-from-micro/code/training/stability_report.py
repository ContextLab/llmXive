"""
Stability Reporting for Cross-Validation (Task T032)

Calculates and reports the variance/standard deviation of R-squared values
across the k-folds to satisfy SC-005.
"""
import json
import logging
import sys
from pathlib import Path
from typing import List, Dict, Any, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def load_fold_results(results_path: Path) -> List[Dict[str, Any]]:
    """
    Load the cross-validation results from the JSON file generated by train.py.
    Expects a file containing a list of fold results or a single dict with a 'folds' key.
    """
    if not results_path.exists():
        raise FileNotFoundError(f"Cross-validation results file not found: {results_path}")
    
    with open(results_path, 'r') as f:
        data = json.load(f)
    
    # Handle different possible structures from train.py
    if isinstance(data, list):
        return data
    elif isinstance(data, dict) and 'folds' in data:
        return data['folds']
    else:
        # Try to extract a list if the structure is nested differently
        # Assuming the train.py outputs a structure where 'results' or 'folds' is the key
        if 'results' in data:
            return data['results']
        raise ValueError(f"Unexpected JSON structure in {results_path}: {data}")

def calculate_stability_metrics(fold_results: List[Dict[str, Any]]) -> Dict[str, float]:
    """
    Calculate variance and standard deviation of R-squared values across folds.
    """
    if not fold_results:
        raise ValueError("No fold results provided for stability calculation.")
    
    r2_scores = []
    for fold in fold_results:
        if 'r2_score' in fold:
            r2_scores.append(fold['r2_score'])
        elif 'metrics' in fold and 'r2_score' in fold['metrics']:
            r2_scores.append(fold['metrics']['r2_score'])
        else:
            logger.warning(f"Skipping fold missing r2_score: {fold}")
    
    if len(r2_scores) < 2:
        logger.warning("Less than 2 folds found. Variance/StdDev cannot be meaningfully calculated.")
        return {
            'mean_r2': r2_scores[0] if r2_scores else 0.0,
            'variance_r2': 0.0,
            'std_dev_r2': 0.0,
            'n_folds': len(r2_scores)
        }

    import numpy as np
    r2_array = np.array(r2_scores)
    
    return {
        'mean_r2': float(np.mean(r2_array)),
        'variance_r2': float(np.var(r2_array)),
        'std_dev_r2': float(np.std(r2_array)),
        'n_folds': len(r2_scores),
        'min_r2': float(np.min(r2_array)),
        'max_r2': float(np.max(r2_array))
    }

def append_to_report(report_path: Path, metrics: Dict[str, float]) -> None:
    """
    Append the stability metrics to the analysis report markdown file.
    """
    report_path.parent.mkdir(parents=True, exist_ok=True)
    
    header = "\n### Cross-Validation Stability Analysis (SC-005)\n"
    content = (
        f"**R-squared Stability Metrics:**\n"
        f"- Number of Folds: {metrics['n_folds']}\n"
        f"- Mean R²: {metrics['mean_r2']:.6f}\n"
        f"- Variance R²: {metrics['variance_r2']:.6f}\n"
        f"- Standard Deviation R²: {metrics['std_dev_r2']:.6f}\n"
        f"- Min R²: {metrics['min_r2']:.6f}\n"
        f"- Max R²: {metrics['max_r2']:.6f}\n"
    )
    
    if metrics['std_dev_r2'] > 0.01:
        content += (
            f"\n*Note: The standard deviation ({metrics['std_dev_r2']:.4f}) suggests "
            f"moderate variability in model performance across folds.*\n"
        )
    else:
        content += (
            f"\n*Note: The low standard deviation ({metrics['std_dev_r2']:.4f}) indicates "
            f"stable model performance across folds.*\n"
        )

    # Append to file
    with open(report_path, 'a') as f:
        f.write(header)
        f.write(content)
    
    logger.info(f"Stability metrics appended to {report_path}")

def main():
    """
    Main entry point for T032: Stability Reporting.
    """
    # Define paths relative to project root
    project_root = Path(__file__).resolve().parent.parent.parent
    results_path = project_root / 'data' / 'processed' / 'cv_results.json'
    report_path = project_root / 'data' / 'processed' / 'analysis_report.md'
    
    # Fallback if results are stored in training dir (common pattern)
    if not results_path.exists():
        alt_results_path = project_root / 'code' / 'models' / 'cv_results.json'
        if alt_results_path.exists():
            results_path = alt_results_path
        else:
            # Check if there are any json files in data/processed
            processed_dir = project_root / 'data' / 'processed'
            json_files = list(processed_dir.glob('*.json'))
            if json_files:
                # Assume the most recently modified one is the results
                results_path = max(json_files, key=lambda p: p.stat().st_mtime)
                logger.info(f"Found results file at: {results_path}")
            else:
                raise FileNotFoundError(
                    "Could not locate cross-validation results JSON file. "
                    "Ensure T029 (Checkpointing) and T031 (Stratified K-Fold) have run successfully."
                )

    try:
        logger.info(f"Loading fold results from {results_path}")
        fold_results = load_fold_results(results_path)
        
        logger.info(f"Calculating stability metrics for {len(fold_results)} folds")
        metrics = calculate_stability_metrics(fold_results)
        
        logger.info(f"Stability Metrics: Mean={metrics['mean_r2']:.4f}, "
                    f"StdDev={metrics['std_dev_r2']:.4f}")
        
        logger.info(f"Appending results to {report_path}")
        append_to_report(report_path, metrics)
        
        print(f"Stability reporting complete. Report updated at: {report_path}")
        return 0
        
    except Exception as e:
        logger.error(f"Failed to generate stability report: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())