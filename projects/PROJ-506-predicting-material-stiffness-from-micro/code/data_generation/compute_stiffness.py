"""
Stiffness tensor calculator for microstructure images.

Implements FR-002: Compute effective elastic stiffness tensors using FFT-based
numerical homogenization for generated microstructure images.

Outputs:
    - JSON metadata file in data/raw/ containing stiffness tensors and validation flags.
"""
import numpy as np
from pathlib import Path
import json
import logging
from skimage import io

from code.utils.fft_homogenization import compute_effective_stiffness

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def load_microstructure(path: Path) -> np.ndarray:
    """
    Load a microstructure image from disk.

    Args:
        path: Path to the PNG image file.

    Returns:
        2D numpy array (grayscale) representing the microstructure.
        Values: 0 (void/void-like), 1 (matrix), 2 (inclusion).
    """
    if not path.exists():
        raise FileNotFoundError(f"Microstructure file not found: {path}")

    img = io.imread(str(path))

    # Ensure float64 for numerical stability in FFT
    if img.dtype != np.float64:
        img = img.astype(np.float64)

    # Normalize if necessary (skimage often returns 0-255 uint8)
    if img.max() > 1.0:
        img = img / 255.0

    return img

def compute_stiffness_tensor(img: np.ndarray) -> np.ndarray:
    """
    Compute the effective elastic stiffness tensor using the FFT solver.

    Args:
        img: 2D numpy array representing the microstructure (phase field).

    Returns:
        4x4 stiffness tensor in Voigt notation (plane strain assumption).
        Format: [[C11, C12, C16, 0], [C12, C22, C26, 0], [C16, C26, C66, 0], [0, 0, 0, C44]]
        (Simplified to 3x3 for plane stress/strain isotropic/orthotropic approximation in 2D)
        Specifically returns the 2D plane strain stiffness matrix (3x3).
    """
    logger.info(f"Computing stiffness tensor for image shape: {img.shape}")

    # Call the FFT homogenization solver
    # The solver expects a phase field image and material properties
    # Assuming default matrix/inclusion properties defined within fft_homogenization
    stiffness = compute_effective_stiffness(img)

    logger.info(f"Computed stiffness tensor:\n{stiffness}")

    return stiffness

def main():
    """
    Orchestrate the stiffness computation for all microstructures in data/raw/.
    Reads PNGs generated by generate_microstructures.py, computes stiffness,
    and saves results to data/raw/stiffness_metadata.json.
    """
    raw_dir = Path("data/raw")
    if not raw_dir.exists():
        logger.error(f"Data directory not found: {raw_dir}. Run T017 first.")
        return

    # Find all microstructure images
    image_files = sorted(raw_dir.glob("micro_*.png"))

    if not image_files:
        logger.warning("No microstructure images found in data/raw/.")
        return

    logger.info(f"Found {len(image_files)} microstructure images to process.")

    results = []
    failed_count = 0

    for img_path in image_files:
        seed = img_path.stem.replace("micro_", "")
        try:
            # Load image
            img = load_microstructure(img_path)

            # Compute stiffness
            stiffness = compute_stiffness_tensor(img)

            # Convert to list for JSON serialization
            stiffness_list = stiffness.tolist()

            # Calculate simple scalar metrics for quick validation (e.g., trace)
            trace_val = float(np.trace(stiffness[:3, :3])) if stiffness.shape[0] >= 3 else float(np.sum(stiffness))

            result_entry = {
                "seed": int(seed),
                "image_path": str(img_path),
                "stiffness_tensor": stiffness_list,
                "trace": trace_val,
                "status": "success"
            }
            results.append(result_entry)
            logger.info(f"Processed seed {seed}: Success")

        except Exception as e:
            failed_count += 1
            logger.error(f"Failed to process seed {seed}: {str(e)}", exc_info=True)
            results.append({
                "seed": int(seed),
                "image_path": str(img_path),
                "status": "failed",
                "error": str(e)
            })

    # Save results to JSON
    output_path = raw_dir / "stiffness_metadata.json"
    with open(output_path, "w") as f:
        json.dump({
            "total_processed": len(image_files),
            "successful": len(image_files) - failed_count,
            "failed": failed_count,
            "data": results
        }, f, indent=2)

    logger.info(f"Stiffness computation complete. Results saved to {output_path}")

if __name__ == "__main__":
    main()
