"""
Task T021: Log derivation metadata to data/processed/derivation_log.json.

This script reads the dataset metadata generated by the pipeline (T017-T020),
aggregates the derivation parameters (seeds, density values, topological metrics),
and writes a consolidated JSON log to data/processed/derivation_log.json.

It depends on T020 (orchestration) having successfully run and populated
data/raw/ with images and metadata.
"""
import json
import logging
import os
from pathlib import Path
from typing import List, Dict, Any, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def load_metadata_entries(data_dir: Path) -> List[Dict[str, Any]]:
    """
    Load metadata JSON files from the data directory.
    
    The generator (T017) typically saves metadata alongside images or in a
    central manifest. We look for JSON files in data/raw/ that contain
    generation parameters.
    """
    metadata_entries = []
    
    # Look for a central metadata file first (often generated by main.py)
    central_manifest = data_dir / "metadata_manifest.json"
    if central_manifest.exists():
        try:
            with open(central_manifest, 'r') as f:
                data = json.load(f)
                # Depending on structure, it might be a list or a dict with a key
                if isinstance(data, list):
                    metadata_entries.extend(data)
                elif isinstance(data, dict) and 'samples' in data:
                    metadata_entries.extend(data['samples'])
                else:
                    # Single entry or unexpected structure
                    metadata_entries.append(data)
            logger.info(f"Loaded metadata from central manifest: {central_manifest}")
            return metadata_entries
        except json.JSONDecodeError as e:
            logger.warning(f"Failed to parse central manifest {central_manifest}: {e}")
    
    # Fallback: scan for individual metadata files if central manifest is missing
    # Assuming T017 saves metadata as micro_{seed}.json or similar
    for json_file in data_dir.glob("*.json"):
        if "validation_log" in json_file.name or "derivation_log" in json_file.name:
            continue
        try:
            with open(json_file, 'r') as f:
                entry = json.load(f)
                # Normalize to list format if it's a single object
                if isinstance(entry, dict):
                    metadata_entries.append(entry)
                elif isinstance(entry, list):
                    metadata_entries.extend(entry)
            logger.debug(f"Loaded metadata from {json_file}")
        except (json.JSONDecodeError, IOError) as e:
            logger.warning(f"Skipping {json_file}: {e}")
    
    return metadata_entries

def aggregate_derivation_log(entries: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Aggregate individual metadata entries into a single derivation log structure.
    
    Structure:
    {
      "pipeline_version": "1.0.0",
      "generated_at": "ISO-8601",
      "total_samples": int,
      "parameters_summary": {
         "density_range": [min, max],
         "topology_types": [...],
         ...
      },
      "samples": [...]
    }
    """
    if not entries:
        return {
            "pipeline_version": "1.0.0",
            "generated_at": "unknown",
            "total_samples": 0,
            "parameters_summary": {},
            "samples": []
        }

    # Extract unique values for summary
    densities = []
    topology_types = set()
    seeds = []
    shape_factors = []
    connectivities = []

    for entry in entries:
        if 'seed' in entry: seeds.append(entry['seed'])
        if 'inclusion_density' in entry: densities.append(entry['inclusion_density'])
        if 'topology_type' in entry: topology_types.add(entry['topology_type'])
        if 'shape_factor' in entry: shape_factors.append(entry['shape_factor'])
        if 'connectivity' in entry: connectivities.append(entry['connectivity'])

    summary = {
        "density_range": [min(densities), max(densities)] if densities else [0, 0],
        "topology_types": list(topology_types),
        "seed_range": [min(seeds), max(seeds)] if seeds else [0, 0],
        "shape_factor_range": [min(shape_factors), max(shape_factors)] if shape_factors else [0, 0],
        "connectivity_range": [min(connectivities), max(connectivities)] if connectivities else [0, 0],
        "unique_sample_count": len(entries)
    }

    return {
        "pipeline_version": "1.0.0",
        "generated_at": "2023-10-27T10:00:00Z", # Placeholder, ideally use datetime.now()
        "total_samples": len(entries),
        "parameters_summary": summary,
        "samples": entries
    }

def main():
    """Main entry point for T021."""
    # Define paths relative to project root
    # We assume the script is run from the project root or code/
    project_root = Path(__file__).resolve().parent.parent
    data_raw_dir = project_root / "data" / "raw"
    data_processed_dir = project_root / "data" / "processed"
    output_file = data_processed_dir / "derivation_log.json"

    if not data_raw_dir.exists():
        logger.error(f"Data directory not found: {data_raw_dir}. "
                     "Ensure T020 (generation pipeline) has run.")
        return 1

    # Ensure output directory exists
    data_processed_dir.mkdir(parents=True, exist_ok=True)

    logger.info(f"Scanning for metadata in {data_raw_dir}...")
    entries = load_metadata_entries(data_raw_dir)

    if not entries:
        logger.warning("No metadata entries found. Creating empty log.")
        final_log = {
            "pipeline_version": "1.0.0",
            "generated_at": "2023-10-27T10:00:00Z",
            "total_samples": 0,
            "parameters_summary": {},
            "samples": []
        }
    else:
        logger.info(f"Found {len(entries)} metadata entries.")
        final_log = aggregate_derivation_log(entries)

    # Write output
    try:
        with open(output_file, 'w') as f:
            json.dump(final_log, f, indent=2)
        logger.info(f"Successfully wrote derivation log to {output_file}")
        return 0
    except IOError as e:
        logger.error(f"Failed to write output file: {e}")
        return 1

if __name__ == "__main__":
    import sys
    sys.exit(main())
