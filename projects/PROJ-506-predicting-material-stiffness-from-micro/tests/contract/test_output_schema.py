"""
Contract test for model output schema (T024).

This test validates that the model output generated by the training pipeline
conforms to the schema defined in specs/001-predict-stiffness-cnn/contracts/model-output.schema.yaml.

It implements Test-Driven Development (TDD) for the training pipeline:
1. This test is written first and expects the schema definition to exist.
2. It will fail initially if the schema or model outputs are not present/valid.
3. Implementation tasks T025/T026 must produce outputs that pass this test.
"""
import json
import yaml
import pytest
from pathlib import Path
from typing import Dict, Any, List

# Path constants relative to project root
SCHEMA_PATH = Path("specs/001-predict-stiffness-cnn/contracts/model-output.schema.yaml")
# Expected output path based on project structure (T029 saves to code/models/, 
# but evaluation loads predictions which are often JSON/CSV. 
# We test the schema definition itself and a sample output if available.
SAMPLE_OUTPUT_PATH = Path("data/processed/model_predictions.json")


def load_schema(schema_path: Path) -> Dict[str, Any]:
    """Load and parse the YAML schema definition."""
    if not schema_path.exists():
        raise FileNotFoundError(f"Schema file not found: {schema_path}")
    
    with open(schema_path, 'r') as f:
        return yaml.safe_load(f)


def validate_model_output_against_schema(output_data: Dict[str, Any], schema: Dict[str, Any]) -> List[str]:
    """
    Validate a model output record against the schema.
    
    Returns a list of error messages. Empty list means valid.
    """
    errors = []
    required_fields = schema.get("required_fields", [])
    
    for field in required_fields:
        if field not in output_data:
            errors.append(f"Missing required field: {field}")
    
    # Type checks based on schema description (simplified validation)
    # The schema YAML describes the types, we check them here.
    if "model_version" in output_data and not isinstance(output_data["model_version"], str):
        errors.append("Field 'model_version' must be a string")
    
    if "prediction" in output_data:
        if not isinstance(output_data["prediction"], list):
            errors.append("Field 'prediction' must be a list")
        else:
            # Check if all elements are floats
            if not all(isinstance(x, (int, float)) for x in output_data["prediction"]):
                errors.append("Field 'prediction' must contain only numeric values")
    
    if "error" in output_data and not isinstance(output_data["error"], (int, float)):
        errors.append("Field 'error' must be a number")
    
    if "density_bin" in output_data and not isinstance(output_data["density_bin"], str):
        errors.append("Field 'density_bin' must be a string")
        
    return errors


class TestModelOutputSchema:
    """Contract tests for model output schema compliance."""

    @pytest.fixture
    def schema(self) -> Dict[str, Any]:
        """Load the model output schema."""
        # T013 must have created this file
        return load_schema(SCHEMA_PATH)

    def test_schema_file_exists(self):
        """Verify the schema definition file exists (T013 prerequisite)."""
        assert SCHEMA_PATH.exists(), f"Schema file {SCHEMA_PATH} must exist. Run T013 first."

    def test_schema_has_required_fields(self, schema: Dict[str, Any]):
        """Verify the schema defines the required fields."""
        required_fields = schema.get("required_fields", [])
        expected_fields = ["model_version", "prediction", "error", "density_bin"]
        
        for field in expected_fields:
            assert field in required_fields, f"Schema must require field: {field}"

    def test_schema_structure_valid(self, schema: Dict[str, Any]):
        """Verify the schema structure is valid YAML and contains expected metadata."""
        assert "description" in schema or "fields" in schema, \
            "Schema should have a description or fields definition"
        
        # Check that required_fields is a list
        assert isinstance(schema.get("required_fields"), list), \
            "required_fields must be a list"

    def test_sample_output_conforms(self, schema: Dict[str, Any]):
        """
        Test that a sample model output (if it exists) conforms to the schema.
        
        This is the core contract test. It will fail if:
        1. No sample output exists (T025/T026 haven't run yet) - EXPECTED during TDD
        2. The existing output violates the schema
        """
        if not SAMPLE_OUTPUT_PATH.exists():
            # This is expected if T025/T026 haven't been implemented yet.
            # In a TDD workflow, this failure drives the implementation.
            pytest.skip(
                f"Sample output {SAMPLE_OUTPUT_PATH} not found. "
                "This is expected before implementing T025/T026. "
                "The test will pass once the training pipeline generates valid output."
            )

        with open(SAMPLE_OUTPUT_PATH, 'r') as f:
            # Try loading as JSON (single record or list)
            try:
                data = json.load(f)
            except json.JSONDecodeError:
                pytest.fail(f"Invalid JSON in {SAMPLE_OUTPUT_PATH}")

        # Handle case where file contains a list of records
        records = data if isinstance(data, list) else [data]
        
        assert len(records) > 0, "Sample output file must contain at least one record"

        all_errors = []
        for i, record in enumerate(records):
            errors = validate_model_output_against_schema(record, schema)
            if errors:
                all_errors.append(f"Record {i}: {errors}")

        if all_errors:
            pytest.fail(f"Schema validation failed for {len(all_errors)} records:\n" + "\n".join(all_errors))

    def test_schema_compliance_with_data_model(self):
        """
        Cross-check that the model output schema aligns with the dataset schema (T012).
        
        The model output should be compatible with the input data features.
        """
        # Load dataset schema
        dataset_schema_path = Path("specs/001-predict-stiffness-cnn/contracts/dataset.schema.yaml")
        if not dataset_schema_path.exists():
            pytest.skip("Dataset schema not found (T012). Cannot cross-check.")
        
        with open(dataset_schema_path, 'r') as f:
            dataset_schema = yaml.safe_load(f)
        
        with open(SCHEMA_PATH, 'r') as f:
            model_schema = yaml.safe_load(f)
        
        # Verify that 'inclusion_density' from dataset maps to 'density_bin' in output
        dataset_fields = dataset_schema.get("required_fields", [])
        model_fields = model_schema.get("required_fields", [])
        
        # The model output should have a density bin derived from dataset density
        assert "density_bin" in model_fields, \
            "Model output must include density_bin derived from dataset inclusion_density"
        
        assert "inclusion_density" in dataset_fields, \
            "Dataset must include inclusion_density for binning"