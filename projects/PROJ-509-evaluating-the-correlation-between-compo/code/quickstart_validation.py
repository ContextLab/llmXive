"""
Quickstart Validation Script for PROJ-509.

This script validates the end-to-end reproducibility of the research pipeline
by checking for the existence and validity of all required artifacts
generated by the main pipeline steps.
"""

import os
import sys
import json
import logging
import subprocess
from pathlib import Path
from typing import List, Dict, Any, Tuple

# Add project root to path if running as script
if __name__ == "__main__":
    project_root = Path(__file__).resolve().parent.parent
    sys.path.insert(0, str(project_root))
    os.chdir(project_root)

from utils.logging import setup_logging, get_logger
from config import load_paths

# Configure logging
logger = get_logger("quickstart_validation")

def run_step(description: str, command: List[str], check: bool = True) -> bool:
    """Run a shell command step and return success status."""
    logger.info(f"Running: {description}")
    try:
        result = subprocess.run(
            command,
            cwd=Path(__file__).parent,
            capture_output=True,
            text=True,
            check=check
        )
        if result.stdout:
            logger.debug(result.stdout)
        if result.stderr:
            logger.debug(result.stderr)
        return True
    except subprocess.CalledProcessError as e:
        logger.error(f"Step failed: {description}")
        logger.error(f"Stderr: {e.stderr}")
        if check:
            raise
        return False

def verify_artifacts(artifacts: Dict[str, str]) -> Tuple[bool, List[str]]:
    """
    Verify that all required artifacts exist at the specified paths.

    Args:
        artifacts: Dictionary of {relative_path: description}

    Returns:
        Tuple of (all_exist, list_of_missing_paths)
    """
    missing = []
    for rel_path, desc in artifacts.items():
        full_path = Path(project_root) / rel_path
        if not full_path.exists():
            missing.append(rel_path)
            logger.warning(f"Missing artifact: {rel_path} ({desc})")
        else:
            logger.info(f"Found artifact: {rel_path}")

    return len(missing) == 0, missing

def validate_metrics_content(file_path: str) -> bool:
    """
    Validate that a JSON metrics file contains expected keys and non-empty values.

    Args:
        file_path: Relative path to the JSON file

    Returns:
        True if valid, False otherwise
    """
    full_path = Path(project_root) / file_path
    if not full_path.exists():
        return False

    try:
        with open(full_path, 'r') as f:
            data = json.load(f)

        # Basic validation: ensure it's a dict and not empty
        if not isinstance(data, dict) or not data:
            logger.error(f"Invalid content in {file_path}: empty or not a dict")
            return False

        # Specific validation for model_metrics.json
        if "model_metrics.json" in file_path:
            required_keys = ["train_r2", "val_r2", "train_mae", "val_mae", "predictive_power"]
            for key in required_keys:
                if key not in data:
                    logger.warning(f"Missing key '{key}' in {file_path}")
                    # Not strictly failing if missing, just warning
            logger.info(f"Validated content structure in {file_path}")

        # Specific validation for feature_ranking.json
        if "feature_ranking.json" in file_path:
            if "ranked_features" not in data and "top_features" not in data:
                logger.warning(f"Missing expected ranking keys in {file_path}")

        return True
    except json.JSONDecodeError as e:
        logger.error(f"JSON decode error in {file_path}: {e}")
        return False
    except Exception as e:
        logger.error(f"Error reading {file_path}: {e}")
        return False

def main():
    """Main validation routine."""
    setup_logging()
    logger.info("Starting Quickstart Validation for PROJ-509")

    # Define required artifacts based on the pipeline specification
    required_artifacts = {
        "data/raw/mp-2020.12.1.csv": "Raw dataset download",
        "data/processed/computed_descriptors.csv": "Computed descriptors with mean/variance",
        "data/evaluation/model_rf.pkl": "Trained Random Forest model",
        "data/evaluation/model_gb.pkl": "Trained Gradient Boosting model",
        "data/evaluation/model_metrics.json": "Model performance metrics",
        "data/evaluation/feature_ranking.json": "Ranked feature importances",
        "data/evaluation/statistical_tests.json": "Paired t-test results",
        "data/evaluation/vif_scores.json": "Variance Inflation Factor scores",
        "data/evaluation/ale_metrics.json": "ALE plot non-linearity metrics",
        "research.md": "Final research summary document"
    }

    # 1. Verify Artifacts Existence
    logger.info("--- Phase 1: Artifact Existence Check ---")
    all_exist, missing_files = verify_artifacts(required_artifacts)

    if not all_exist:
        logger.error(f"Validation FAILED: Missing {len(missing_files)} required artifacts.")
        for f in missing_files:
            logger.error(f"  - {f}")
        sys.exit(1)

    # 2. Validate Content of JSON Metrics
    logger.info("--- Phase 2: Content Validation ---")
    json_files = [
        "data/evaluation/model_metrics.json",
        "data/evaluation/feature_ranking.json",
        "data/evaluation/statistical_tests.json",
        "data/evaluation/vif_scores.json",
        "data/evaluation/ale_metrics.json"
    ]

    content_valid = True
    for jf in json_files:
        if not validate_metrics_content(jf):
            content_valid = False

    if not content_valid:
        logger.error("Validation FAILED: One or more JSON files have invalid content.")
        sys.exit(1)

    # 3. Check research.md is not empty
    logger.info("--- Phase 3: Documentation Check ---")
    research_path = Path(project_root) / "research.md"
    if research_path.exists():
        size = research_path.stat().st_size
        if size < 100:
            logger.error(f"research.md exists but is too small ({size} bytes).")
            sys.exit(1)
        logger.info(f"research.md validated (size: {size} bytes).")
    else:
        logger.error("research.md missing.")
        sys.exit(1)

    logger.info("--------------------------------------------------")
    logger.info("SUCCESS: All quickstart validation checks passed.")
    logger.info("The pipeline has reproduced all required artifacts.")
    logger.info("--------------------------------------------------")
    return 0

if __name__ == "__main__":
    sys.exit(main())
