from pathlib import Path
from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field, field_validator
import json


class EditInstance(BaseModel):
    """
    Represents a single image editing instance from the Edit-Compass dataset.
    """
    source_image_path: str = Field(..., description="Path to the source image")
    edited_image_path: str = Field(..., description="Path to the edited image")
    instruction: str = Field(..., description="The text instruction for the edit")
    category: str = Field(..., description="Category of the edit task")
    human_judgment_score: float = Field(..., description="Human judgment score for the edit quality")

    @field_validator('human_judgment_score')
    @classmethod
    def validate_score_range(cls, v):
        if v < 0.0 or v > 10.0:
            raise ValueError('human_judgment_score must be between 0.0 and 10.0')
        return v


class ScoreRecord(BaseModel):
    """
    Represents the computed scores for a single EditInstance.
    """
    instance_id: str = Field(..., description="Unique identifier for the instance (derived from paths)")
    logic_score: float = Field(..., description="Logic consistency score (0-1)")
    fidelity_score: float = Field(..., description="Fidelity score (0-1)")
    ssim: float = Field(..., description="Structural Similarity Index Measure")
    lpips: float = Field(..., description="Learned Perceptual Image Patch Similarity")
    vllm_description: str = Field(..., description="Description generated by the VLM")

    @field_validator('logic_score', 'fidelity_score', 'ssim', 'lpips')
    @classmethod
    def validate_score_range(cls, v):
        if v < 0.0 or v > 1.0:
            raise ValueError(f'Score must be between 0.0 and 1.0, got {v}')
        return v


class RegressionResult(BaseModel):
    """
    Represents the results of the multiple linear regression analysis
    correlating Logic/Fidelity scores with Human Judgment scores.
    """
    model_r_squared: float = Field(..., description="R-squared value of the regression model")
    beta_logic: float = Field(..., description="Standardized beta coefficient for Logic Score")
    beta_fidelity: float = Field(..., description="Standardized beta coefficient for Fidelity Score")
    p_value_logic: float = Field(..., description="P-value for the Logic Score coefficient")
    p_value_fidelity: float = Field(..., description="P-value for the Fidelity Score coefficient")
    fdr_corrected_p_logic: Optional[float] = Field(None, description="FDR-corrected p-value for Logic Score")
    fdr_corrected_p_fidelity: Optional[float] = Field(None, description="FDR-corrected p-value for Fidelity Score")

    @field_validator('model_r_squared')
    @classmethod
    def validate_r_squared(cls, v):
        if v < 0.0 or v > 1.0:
            raise ValueError('model_r_squared must be between 0.0 and 1.0')
        return v

    @field_validator('p_value_logic', 'p_value_fidelity', 'fdr_corrected_p_logic', 'fdr_corrected_p_fidelity')
    @classmethod
    def validate_p_value(cls, v):
        if v is not None and (v < 0.0 or v > 1.0):
            raise ValueError('P-value must be between 0.0 and 1.0')
        return v