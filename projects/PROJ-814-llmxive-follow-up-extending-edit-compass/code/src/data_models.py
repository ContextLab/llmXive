from pathlib import Path
from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field, field_validator
import json


class EditInstance(BaseModel):
    """
    Represents a single image editing instance from the dataset.
    """
    source_image_path: str = Field(..., description="Path to the original source image")
    edited_image_path: str = Field(..., description="Path to the edited image")
    instruction: str = Field(..., description="The text instruction for the edit")
    category: str = Field(..., description="Category of the edit task")
    human_judgment_score: float = Field(..., ge=0.0, le=1.0, description="Human evaluation score (0-1)")

    @field_validator('source_image_path', 'edited_image_path')
    @classmethod
    def validate_path(cls, v: str) -> str:
        if not v:
            raise ValueError("Path cannot be empty")
        return v


class ScoreRecord(BaseModel):
    """
    Represents the computed scores for an EditInstance.
    """
    instance_id: str = Field(..., description="Unique identifier for the instance")
    logic_score: float = Field(..., ge=-1.0, le=1.0, description="Logic consistency score (cosine similarity)")
    fidelity_score: float = Field(..., ge=0.0, le=1.0, description="Image fidelity score (weighted SSIM/LPIPS)")
    ssim: float = Field(..., ge=-1.0, le=1.0, description="Structural Similarity Index")
    lpips: float = Field(..., ge=0.0, le=float('inf'), description="Learned Perceptual Image Patch Similarity")
    vllm_description: str = Field(..., description="Description generated by the VLM")

    @field_validator('logic_score')
    @classmethod
    def validate_logic_score(cls, v: float) -> float:
        if not (-1.0 <= v <= 1.0):
            raise ValueError(f"logic_score must be between -1 and 1, got {v}")
        return v

    @field_validator('fidelity_score', 'ssim', 'lpips')
    @classmethod
    def validate_scores(cls, v: float) -> float:
        if v < 0.0:
            raise ValueError(f"Score cannot be negative, got {v}")
        return v


class RegressionResult(BaseModel):
    """
    Represents the results of the multiple linear regression analysis
    and statistical tests performed on the scores.
    
    Note: The `fdr_corrected_p` fields are populated *after* the regression 
    and correction steps (T026), not at model instantiation.
    """
    model_r_squared: float = Field(..., ge=0.0, description="R-squared value of the regression model")
    beta_logic: float = Field(..., description="Standardized beta coefficient for Logic Score")
    beta_fidelity: float = Field(..., description="Standardized beta coefficient for Fidelity Score")
    p_value_logic: float = Field(..., ge=0.0, le=1.0, description="P-value for Logic Score coefficient")
    p_value_fidelity: float = Field(..., ge=0.0, le=1.0, description="P-value for Fidelity Score coefficient")
    fdr_corrected_p_logic: Optional[float] = Field(None, ge=0.0, le=1.0, description="FDR-corrected p-value for Logic Score")
    fdr_corrected_p_fidelity: Optional[float] = Field(None, ge=0.0, le=1.0, description="FDR-corrected p-value for Fidelity Score")