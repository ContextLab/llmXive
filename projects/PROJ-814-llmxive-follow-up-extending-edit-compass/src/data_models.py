"""
Data model definitions for the llmXive pipeline.

This module defines Pydantic models for:
- EditInstance: Represents a single image editing task instance.
- ScoreRecord: Represents the computed scores for an edit instance.
- RegressionResult: Represents the results of statistical regression analysis.
"""

from pathlib import Path
from typing import Optional, List, Dict, Any, Union
from pydantic import BaseModel, Field, field_validator
import json


class EditInstance(BaseModel):
    """
    Represents a single image editing task instance from the Edit-Compass dataset.
    
    Attributes:
        source_image_path: Path to the original source image.
        edited_image_path: Path to the edited image.
        instruction: The natural language instruction for the edit.
        category: The category of the editing task (e.g., "World Knowledge Reasoning").
        human_judgment_score: The human-annotated quality score for the edit.
    """
    source_image_path: str = Field(..., description="Path to the original source image")
    edited_image_path: str = Field(..., description="Path to the edited image")
    instruction: str = Field(..., description="Natural language instruction for the edit")
    category: str = Field(..., description="Category of the editing task")
    human_judgment_score: float = Field(..., ge=0.0, le=1.0, description="Human-annotated quality score (0-1)")

    @field_validator('source_image_path', 'edited_image_path')
    @classmethod
    def validate_path(cls, v: str) -> str:
        """Validate that the path string is not empty."""
        if not v or not v.strip():
            raise ValueError("Image path cannot be empty")
        return v

    @field_validator('human_judgment_score')
    @classmethod
    def validate_score_range(cls, v: float) -> float:
        """Ensure the score is within the valid 0-1 range."""
        if v < 0.0 or v > 1.0:
            raise ValueError(f"human_judgment_score must be between 0.0 and 1.0, got {v}")
        return v

    def to_dict(self) -> Dict[str, Any]:
        """Convert the instance to a dictionary for JSON serialization."""
        return self.model_dump()

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'EditInstance':
        """Create an EditInstance from a dictionary."""
        return cls(**data)

    def to_json(self, indent: Optional[int] = 2) -> str:
        """Serialize the instance to a JSON string."""
        return json.dumps(self.to_dict(), indent=indent)

    @classmethod
    def from_json(cls, json_str: str) -> 'EditInstance':
        """Create an EditInstance from a JSON string."""
        data = json.loads(json_str)
        return cls(**data)


class ScoreRecord(BaseModel):
    """
    Represents the computed scores for an edit instance.
    
    Attributes:
        instance_id: Unique identifier for the edit instance.
        logic_score: The logic consistency score (0-1 range).
        fidelity_score: The image fidelity score (0-1 range).
        ssim: Structural Similarity Index Measure value.
        lpips: Learned Perceptual Image Patch Similarity value.
        vllm_description: The text description generated by the VLM for the edited image.
    """
    instance_id: str = Field(..., description="Unique identifier for the edit instance")
    logic_score: float = Field(..., ge=-1.0, le=1.0, description="Logic consistency score (cosine similarity)")
    fidelity_score: float = Field(..., ge=0.0, le=1.0, description="Image fidelity score")
    ssim: float = Field(..., ge=0.0, le=1.0, description="SSIM value")
    lpips: float = Field(..., ge=0.0, le=1.0, description="LPIPS value")
    vllm_description: str = Field(..., description="VLM-generated description of the edited image")

    @field_validator('logic_score')
    @classmethod
    def validate_logic_range(cls, v: float) -> float:
        """Ensure logic score is in [-1, 1] (cosine similarity range)."""
        if v < -1.0 or v > 1.0:
            raise ValueError(f"logic_score must be between -1.0 and 1.0, got {v}")
        return v

    @field_validator('fidelity_score', 'ssim', 'lpips')
    @classmethod
    def validate_score_range_01(cls, v: float, field) -> float:
        """Ensure scores are in [0, 1] range."""
        if v < 0.0 or v > 1.0:
            raise ValueError(f"{field.field_name} must be between 0.0 and 1.0, got {v}")
        return v

    def to_dict(self) -> Dict[str, Any]:
        """Convert the record to a dictionary for JSON serialization."""
        return self.model_dump()

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'ScoreRecord':
        """Create a ScoreRecord from a dictionary."""
        return cls(**data)

    def to_json(self, indent: Optional[int] = 2) -> str:
        """Serialize the record to a JSON string."""
        return json.dumps(self.to_dict(), indent=indent)

    @classmethod
    def from_json(cls, json_str: str) -> 'ScoreRecord':
        """Create a ScoreRecord from a JSON string."""
        data = json.loads(json_str)
        return cls(**data)


class RegressionResult(BaseModel):
    """
    Represents the results of the multiple linear regression analysis.
    
    Attributes:
        model_r_squared: The R-squared value of the regression model.
        beta_logic: The standardized regression coefficient for the logic score.
        beta_fidelity: The standardized regression coefficient for the fidelity score.
        p_value_logic: The raw p-value for the logic coefficient.
        p_value_fidelity: The raw p-value for the fidelity coefficient.
        fdr_corrected_p_logic: The Benjamini-Hochberg corrected p-value for logic.
        fdr_corrected_p_fidelity: The Benjamini-Hochberg corrected p-value for fidelity.
    """
    model_r_squared: float = Field(..., ge=0.0, le=1.0, description="R-squared of the regression model")
    beta_logic: float = Field(..., description="Standardized coefficient for logic score")
    beta_fidelity: float = Field(..., description="Standardized coefficient for fidelity score")
    p_value_logic: float = Field(..., ge=0.0, le=1.0, description="Raw p-value for logic coefficient")
    p_value_fidelity: float = Field(..., ge=0.0, le=1.0, description="Raw p-value for fidelity coefficient")
    fdr_corrected_p_logic: float = Field(..., ge=0.0, le=1.0, description="FDR-corrected p-value for logic")
    fdr_corrected_p_fidelity: float = Field(..., ge=0.0, le=1.0, description="FDR-corrected p-value for fidelity")

    def to_dict(self) -> Dict[str, Any]:
        """Convert the result to a dictionary for JSON serialization."""
        return self.model_dump()

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'RegressionResult':
        """Create a RegressionResult from a dictionary."""
        return cls(**data)

    def to_json(self, indent: Optional[int] = 2) -> str:
        """Serialize the result to a JSON string."""
        return json.dumps(self.to_dict(), indent=indent)

    @classmethod
    def from_json(cls, json_str: str) -> 'RegressionResult':
        """Create a RegressionResult from a JSON string."""
        data = json.loads(json_str)
        return cls(**data)