logger = get_logger(__name__)

def run_validate_final():
    """
    T039: Final Sanity Check Script.
    Re-runs Fisher's r-to-z test logic and verifies the threshold_met boolean
    matches the correlation_difference and p_value_diff logic defined in T029.
    """
    logger.info("Starting Final Sanity Check (T039)...")
    
    # Paths
    scores_path = Path("data/scores/scores.json")
    filtered_path = Path("data/filtered/filtered_data.json")
    correlation_diff_path = Path("outputs/correlation_diff_test.json")
    
    if not scores_path.exists():
        logger.error("FATAL: Scores file not found at data/scores/scores.json. Cannot run sanity check.")
        sys.exit(1)
    
    if not filtered_path.exists():
        logger.error("FATAL: Filtered data not found at data/filtered/filtered_data.json. Cannot run sanity check.")
        sys.exit(1)
    
    if not correlation_diff_path.exists():
        logger.error("FATAL: Correlation diff test output not found at outputs/correlation_diff_test.json. Cannot validate.")
        sys.exit(1)

    try:
        # 1. Load Data
        scores = load_scores()
        filtered_data = load_filtered_instances()
        
        human_scores = extract_human_scores(filtered_data)
        logic_scores = extract_logic_scores(scores)
        fidelity_scores = extract_fidelity_scores(scores)
        
        # 2. Re-run Fisher's r-to-z test logic (imported from analysis)
        # We assume the function returns the same structure as the original run
        # or we can re-calculate it directly if the function is exposed.
        # Based on T028a, run_correlation_difference_test performs the logic.
        # We call it to get a fresh result for comparison.
        fresh_result = run_correlation_difference_test(
            human_scores, 
            logic_scores, 
            fidelity_scores
        )
        
        # 3. Load the existing result from disk (generated by T028a/T029)
        import json
        with open(correlation_diff_path, 'r') as f:
            existing_result = json.load(f)
        
        # 4. Verification Logic (T029 Definition)
        # T029 Logic: 
        # Primary: If (correlation_difference >= 0.1 AND p_value_diff < 0.05) -> threshold_met = True
        # We verify that the existing_result['threshold_met'] matches this condition.
        
        corr_diff = existing_result.get('correlation_difference')
        p_val_diff = existing_result.get('p_value_diff')
        existing_threshold_met = existing_result.get('threshold_met')
        
        if corr_diff is None or p_val_diff is None:
            logger.error("FATAL: Existing result missing required fields (correlation_difference or p_value_diff).")
            sys.exit(1)
        
        # Recalculate expected threshold_met
        # Thresholds from T029: 0.1 for diff, 0.05 for p-value
        expected_threshold_met = (corr_diff >= 0.1) and (p_val_diff < 0.05)
        
        logger.info(f"Existing correlation_difference: {corr_diff}")
        logger.info(f"Existing p_value_diff: {p_val_diff}")
        logger.info(f"Existing threshold_met: {existing_threshold_met}")
        logger.info(f"Calculated expected threshold_met: {expected_threshold_met}")
        
        # 5. Check Consistency
        if existing_threshold_met != expected_threshold_met:
            logger.error("FATAL: LOGIC INCONSISTENCY DETECTED.")
            logger.error(f"  The 'threshold_met' boolean ({existing_threshold_met}) does not match the logic: (corr_diff >= 0.1 AND p_val < 0.05).")
            logger.error(f"  Calculated logic: ({corr_diff} >= 0.1 AND {p_val_diff} < 0.05) = {expected_threshold_met}")
            sys.exit(1)
        
        # 6. Verify Fresh Result vs Existing Result (Optional but good for sanity)
        # We compare the fresh calculation to the stored one to ensure no drift/corruption
        fresh_corr_diff = fresh_result.get('correlation_difference')
        fresh_p_val_diff = fresh_result.get('p_value_diff')
        
        # Allow small floating point tolerance
        if abs(corr_diff - fresh_corr_diff) > 1e-6:
            logger.warning(f"WARNING: correlation_difference drift detected. Stored: {corr_diff}, Fresh: {fresh_corr_diff}")
        else:
            logger.info("SUCCESS: correlation_difference matches fresh calculation.")
            
        if abs(p_val_diff - fresh_p_val_diff) > 1e-6:
            logger.warning(f"WARNING: p_value_diff drift detected. Stored: {p_val_diff}, Fresh: {fresh_p_val_diff}")
        else:
            logger.info("SUCCESS: p_value_diff matches fresh calculation.")

        logger.info("Sanity Check PASSED: Logic is consistent and verified.")
        return 0

    except Exception as e:
        logger.error(f"FATAL: Sanity Check failed with exception: {e}")
        import traceback
        logger.debug(traceback.format_exc())
        sys.exit(1)

def main():
    parser = argparse.ArgumentParser(description="llmXive Pipeline CLI")
    subparsers = parser.add_subparsers(dest='command', help='Available commands')

    # Download & Filter
    p_down = subparsers.add_parser('download-filter', help='Download and filter dataset')
    p_score = subparsers.add_parser('score', help='Run scoring pipeline')
    p_analyze = subparsers.add_parser('analyze', help='Run statistical analysis')
    
    # T039: New Stage
    p_val = subparsers.add_parser('validate-final', help='Run final sanity check (T039)')

    args = parser.parse_args()

    if args.command == 'download-filter':
        download_main()
    elif args.command == 'score':
        scoring_main()
    elif args.command == 'analyze':
        analysis_main()
    elif args.command == 'validate-final':
        run_validate_final()
    else:
        parser.print_help()
        sys.exit(1)

if __name__ == '__main__':
    main()