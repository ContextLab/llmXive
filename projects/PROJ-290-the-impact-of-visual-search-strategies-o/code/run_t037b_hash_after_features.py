"""
Task T037b: Run hash_artifacts.py to update state/ with hashes after T019, T024a, T024b, T023a.

This script ensures that all feature extraction artifacts and clustering labels
generated in User Story 2 are checksummed for integrity verification.

Artifacts to hash:
- data/processed/features.csv (T019, T020)
- data/processed/labels_k2.csv (T024b)
- data/processed/labels_k3.csv (T024b)
- data/processed/bootstrap_stability.json (T023a)
- code/features/classification.py (modified in T020, T021, T023a, T024a, T024b)
- code/features/extraction.py (T018)
- code/utils/diagnostics.py (T024a)
"""

import os
import sys
import logging
from pathlib import Path

# Add project root to path to allow imports
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from utils.logging import setup_logging, get_logger
from utils.hash_artifacts import main as hash_main

def main():
    """
    Execute the artifact hashing pipeline for User Story 2 outputs.
    """
    # Setup logging
    log_dir = project_root / "logs"
    log_dir.mkdir(exist_ok=True)
    log_file = log_dir / "t037b_hash_features.log"
    
    logger = setup_logging(
        log_file=log_file,
        level=logging.INFO,
        name="T037B"
    )
    
    logger.info("Starting T037b: Hashing features and clustering artifacts")
    
    # Define the directories to hash
    # We hash the processed data directory and the code directory
    # as these contain the artifacts generated by US2 tasks.
    directories_to_hash = [
        "data/processed",
        "code/features",
        "code/utils"
    ]
    
    # Construct full paths
    hash_paths = [project_root / d for d in directories_to_hash]
    
    # Verify directories exist before hashing
    missing_paths = [p for p in hash_paths if not p.exists()]
    if missing_paths:
        logger.error(f"Missing directories required for hashing: {missing_paths}")
        logger.error("Ensure T019, T020, T021, T023a, T024a, T024b have been completed successfully.")
        # We do not exit immediately if code directories are missing, 
        # but processed data MUST exist for this task to be valid.
        if any("data/processed" in str(m) for m in missing_paths):
            logger.critical("Cannot proceed: data/processed directory is missing.")
            sys.exit(1)
    
    logger.info(f"Hashing directories: {[str(p) for p in hash_paths]}")
    
    # Run the hash_artifacts main function
    # We pass the specific paths to hash to ensure we capture the correct state
    try:
        hash_main(directories=directories_to_hash)
        logger.info("Successfully updated state/ with artifact hashes.")
    except Exception as e:
        logger.error(f"Failed to hash artifacts: {e}")
        sys.exit(1)
        
    logger.info("T037b completed successfully.")
    
    return 0

if __name__ == "__main__":
    sys.exit(main())