"""
Task T026: Save sensitivity analysis report to results/sensitivity_report.yaml (SC-006).

This script acts as the entry point to ensure the sensitivity analysis report
generated by T025 is properly saved and persisted to disk.

It relies on the `code/analysis/sensitivity_analysis.py` module which contains
the logic to run the analysis and save the report.
"""
import os
import sys
import logging
from pathlib import Path

# Add project root to path if not already present
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from config import get_config
from utils.logging import setup_logging, get_logger
from analysis.sensitivity_analysis import run_sensitivity_analysis, save_sensitivity_report

def main():
    """
    Main entry point for T026.
    Ensures the sensitivity report is generated and saved to results/sensitivity_report.yaml.
    """
    # Setup logging
    config = get_config()
    log_path = Path(config.LOG_DIR)
    log_path.mkdir(parents=True, exist_ok=True)
    logger = setup_logging(
        name="t026_sensitivity_save",
        log_file=log_path / "t026_sensitivity_save.log",
        level=logging.INFO
    )
    
    logger.info("Starting Task T026: Save Sensitivity Analysis Report")
    
    try:
        # Ensure output directory exists
        results_dir = Path(config.RESULTS_DIR)
        results_dir.mkdir(parents=True, exist_ok=True)
        
        output_path = results_dir / "sensitivity_report.yaml"
        logger.info(f"Target output path: {output_path}")
        
        # The run_sensitivity_analysis function in sensitivity_analysis.py
        # is responsible for computing the metrics and calling save_sensitivity_report.
        # We invoke it here to ensure the file is written.
        logger.info("Running sensitivity analysis logic to generate report...")
        report_data = run_sensitivity_analysis(logger=logger)
        
        if report_data is None:
            logger.warning("Sensitivity analysis returned no data. Attempting to save existing state if available.")
            # Fallback: try to load and re-save if the function didn't generate new data
            # but the file might exist from a previous partial run (though T025 should have done this)
            # For T026, we strictly rely on the analysis module to produce the content.
            if not output_path.exists():
                logger.error("No sensitivity report data generated and file does not exist. Task cannot complete.")
                return 1
        
        logger.info(f"Sensitivity report successfully saved to {output_path}")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"Required data files not found: {e}")
        logger.error("Ensure T025 (Sensitivity Analysis) and T024b (Clustering Labels) have been completed successfully.")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during T026 execution: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())