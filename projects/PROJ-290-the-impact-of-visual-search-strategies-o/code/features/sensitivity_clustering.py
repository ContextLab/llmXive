"""
Sensitivity Clustering Module (T024b)

Implements k-means clustering for k=2 and k=3 to generate labels for sensitivity analysis.
Outputs:
  - data/processed/labels_k2.csv
  - data/processed/labels_k3.csv
"""

import os
import sys
import json
import logging
import numpy as np
import pandas as pd
from pathlib import Path
from typing import Dict, Any, Optional, List, Tuple

# Import logging utility from the project's established API
from utils.logging import get_logger
from config import get_config

# Import the feature extraction logic if needed for preprocessing, 
# though we assume features are already in data/processed/features.csv per T019
# We will load features directly here to ensure independence for this specific task.

def get_logger_wrapper(func):
    """Decorator to inject logger into functions."""
    def wrapper(*args, **kwargs):
        logger = get_logger(func.__module__)
        return func(*args, logger=logger, **kwargs)
    return wrapper

@get_logger_wrapper
def load_processed_features(logger: logging.Logger) -> pd.DataFrame:
    """
    Loads the processed features dataset from data/processed/features.csv.
    This file is expected to be generated by T019 (save_features).
    """
    config = get_config()
    features_path = config.PROCESSED_DATA_DIR / "features.csv"
    
    if not features_path.exists():
        logger.error(f"Processed features file not found at {features_path}. "
                     "Please ensure T019 (save_features) has been run successfully.")
        raise FileNotFoundError(f"Missing required input file: {features_path}")
    
    logger.info(f"Loading processed features from {features_path}")
    df = pd.read_csv(features_path)
    
    # Verify required columns exist (fixation metrics derived in T018)
    required_cols = ['fixation_duration_eye', 'fixation_duration_mouth', 'participant_id', 'trial_id']
    missing_cols = [c for c in required_cols if c not in df.columns]
    
    if missing_cols:
        logger.error(f"Missing required columns for clustering: {missing_cols}")
        raise ValueError(f"Missing columns in features.csv: {missing_cols}")
    
    return df

@get_logger_wrapper
def perform_sensitivity_clustering(
    df: pd.DataFrame, 
    k_values: List[int], 
    logger: logging.Logger
) -> Dict[int, pd.DataFrame]:
    """
    Performs K-Means clustering on fixation duration metrics for specified k values.
    
    Args:
        df: DataFrame containing fixation features.
        k_values: List of k values to test (e.g., [2, 3]).
        logger: Logger instance.
        
    Returns:
        Dictionary mapping k -> DataFrame with added 'cluster_label' column.
    """
    from sklearn.cluster import KMeans
    from sklearn.preprocessing import StandardScaler
    
    # Select features for clustering
    # Based on T018/T020: eye and mouth fixation durations are the primary strategy indicators
    feature_cols = ['fixation_duration_eye', 'fixation_duration_mouth']
    
    X = df[feature_cols].copy()
    
    # Handle missing values if any (though T014 should have excluded these)
    if X.isnull().any().any():
        logger.warning("Missing values detected in features. Dropping rows with NaN for clustering.")
        valid_mask = ~X.isnull().any(axis=1)
        X_clean = X[valid_mask]
        df_clean = df[valid_mask].copy()
        logger.info(f"Dropped {X.shape[0] - X_clean.shape[0]} rows due to missing values.")
    else:
        X_clean = X
        df_clean = df.copy()

    # Standardize features (K-Means is sensitive to scale)
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X_clean)
    
    results = {}
    
    for k in k_values:
        logger.info(f"Running K-Means clustering with k={k}...")
        
        # Initialize KMeans
        # Using random_state for reproducibility
        kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
        cluster_labels = kmeans.fit_predict(X_scaled)
        
        # Create a copy of the dataframe to add labels
        result_df = df_clean.copy()
        result_df['cluster_label'] = cluster_labels
        
        # Log cluster sizes
        cluster_counts = result_df['cluster_label'].value_counts().sort_index()
        logger.info(f"k={k} cluster distribution:\n{cluster_counts}")
        
        # Calculate silhouette score for quality check (optional but good practice)
        from sklearn.metrics import silhouette_score
        if len(cluster_labels) > 1 and len(np.unique(cluster_labels)) > 1:
            score = silhouette_score(X_scaled, cluster_labels)
            logger.info(f"k={k} Silhouette Score: {score:.4f}")
        else:
            logger.warning(f"k={k} Silhouette Score could not be computed (single cluster or single point).")
        
        results[k] = result_df
    
    return results

@get_logger_wrapper
def save_clustering_results(
    results: Dict[int, pd.DataFrame], 
    output_dir: Path, 
    logger: logging.Logger
) -> List[str]:
    """
    Saves clustering results to CSV files.
    Expected outputs:
      - data/processed/labels_k2.csv
      - data/processed/labels_k3.csv
    """
    saved_files = []
    
    for k, df in results.items():
        filename = f"labels_k{k}.csv"
        filepath = output_dir / filename
        
        # Ensure only necessary columns are saved to keep file clean?
        # The task asks for labels, so we save the full record with the label appended.
        df.to_csv(filepath, index=False)
        saved_files.append(str(filepath))
        logger.info(f"Saved clustering results for k={k} to {filepath}")
    
    return saved_files

@get_logger_wrapper
def main(logger: logging.Logger) -> int:
    """
    Main entry point for T024b: Sensitivity Clustering.
    """
    try:
        # 1. Load processed features
        df = load_processed_features(logger)
        
        # 2. Perform clustering for k=2 and k=3
        k_values = [2, 3]
        results = perform_sensitivity_clustering(df, k_values, logger)
        
        # 3. Save results
        config = get_config()
        output_dir = config.PROCESSED_DATA_DIR
        
        if not output_dir.exists():
            output_dir.mkdir(parents=True, exist_ok=True)
        
        saved_files = save_clustering_results(results, output_dir, logger)
        
        logger.info(f"Sensitivity clustering completed successfully. Files saved: {saved_files}")
        return 0
        
    except Exception as e:
        logger.error(f"Error during sensitivity clustering: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())
