def get_logger_wrapper(func):
    """Decorator to add logger to function arguments."""
    def wrapper(*args, logger=None, **kwargs):
        if logger is None:
            logger = get_logger(func.__module__)
        return func(*args, logger=logger, **kwargs)
    return wrapper

@get_logger_wrapper
def load_cluster_labels(logger: logging.Logger, k: int = 2) -> Optional[pd.DataFrame]:
    """
    Load cluster labels generated by sensitivity clustering (T024b).
    Path: data/processed/labels_k{k}.csv
    """
    config = get_config()
    path = config.PROCESSED_DATA_DIR / f"labels_k{k}.csv"
    if not path.exists():
        logger.error(f"Cluster labels file not found: {path}")
        return None
    try:
        df = pd.read_csv(path)
        logger.info(f"Loaded {len(df)} records from {path}")
        return df
    except Exception as e:
        logger.error(f"Failed to load cluster labels: {e}")
        return None

