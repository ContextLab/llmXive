@get_logger_wrapper
def fit_descriptive_lmm(
    logger: logging.Logger,
    df: pd.DataFrame,
    cluster_col: str,
    outcome_col: str = "response_time",
    subject_col: str = "participant_id"
) -> Tuple[Optional[Any], Dict[str, Any]]:
    """
    Fit a descriptive LMM using cluster labels as fixed effect.
    Returns (model, results_dict).
    If model fails to converge, returns None and error dict.
    """
    if df.empty:
        logger.error("DataFrame is empty, cannot fit model.")
        return None, {"error": "Empty DataFrame"}

    # Basic validation
    required_cols = [cluster_col, outcome_col, subject_col]
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        logger.error(f"Missing required columns: {missing}")
        return None, {"error": f"Missing columns: {missing}"}

    # Drop rows with missing values in required columns
    clean_df = df.dropna(subset=required_cols)
    if len(clean_df) < 10:
        logger.warning(f"Too few records after dropping NaNs: {len(clean_df)}")
        return None, {"error": "Insufficient data after cleaning"}

    formula = f"{outcome_col} ~ C({cluster_col})"
    try:
        model = smf.mixedlm(formula, clean_df, groups=clean_df[subject_col])
        result = model.fit(maxiter=500)
        
        # Check convergence
        if not result.converged:
            logger.warning("LMM did not converge within max iterations.")
            # We still return it as a descriptive result, but flag it
        
        results_dict = {
            "converged": result.converged,
            "coefficients": result.params.to_dict(),
            "std_errors": result.bse.to_dict(),
            "t_values": result.tvalues.to_dict(),
            "p_values": result.pvalues.to_dict(),
            "loglike": result.llf,
            "aic": result.aic,
            "bic": result.bic
        }
        return result, results_dict
    except Exception as e:
        logger.error(f"Failed to fit LMM: {e}")
        return None, {"error": str(e)}

@get_logger_wrapper
def run_sensitivity_analysis(
    logger: logging.Logger,
    k_values: List[int] = [2, 3]
) -> Dict[str, Any]:
    """
    Run sensitivity analysis for different clustering k values.
    Loads labels, fits descriptive LMM, collects stats.
    """
    config = get_config()
    report = {
        "analysis_type": "Sensitivity Analysis (Cluster Stability)",
        "k_values_tested": k_values,
        "models": {}
    }

    # Load base features once
    features_df = load_processed_features(logger=logger)
    if features_df is None:
        logger.error("Cannot proceed without processed features.")
        return report

    for k in k_values:
        logger.info(f"Processing k={k}")
        labels_df = load_cluster_labels(logger=logger, k=k)
        if labels_df is None:
            logger.warning(f"Skipping k={k} due to missing labels.")
            continue

        # Merge features and labels
        # Assuming both have 'participant_id' or similar key. 
        # Based on T024b output, we need to ensure alignment.
        # Usually labels are at participant level or trial level.
        # If labels are participant level, we merge on participant_id.
        # If features are trial level, we might need to broadcast or aggregate.
        # For this implementation, we assume labels_df contains the same rows as features_df 
        # or can be merged on 'participant_id'.
        
        # Simple merge strategy: inner join on participant_id
        if 'participant_id' in labels_df.columns and 'participant_id' in features_df.columns:
            merged = pd.merge(features_df, labels_df, on='participant_id', how='inner')
        else:
            # Fallback: assume same order and index
            logger.warning("No common participant_id found, assuming row alignment.")
            merged = pd.concat([features_df, labels_df], axis=1)

        if merged.empty:
            logger.warning(f"Merged data empty for k={k}")
            continue

        # Determine cluster column name (usually 'cluster_label' or similar)
        cluster_col = None
        for c in labels_df.columns:
            if 'cluster' in c.lower() or 'label' in c.lower():
                cluster_col = c
                break
        
        if not cluster_col:
            logger.error(f"Could not identify cluster column in labels for k={k}")
            continue

        result, stats = fit_descriptive_lmm(
            logger=logger,
            df=merged,
            cluster_col=cluster_col,
            outcome_col="response_time"
        )

        report["models"][f"k_{k}"] = {
            "n_records": len(merged),
            "cluster_column": cluster_col,
            "stats": stats
        }

        if result:
            logger.info(f"Model k={k} converged: {stats.get('converged', False)}")
        else:
            logger.warning(f"Model k={k} failed to fit: {stats.get('error', 'Unknown')}")

    return report

@get_logger_wrapper
def save_sensitivity_report(
    logger: logging.Logger,
    report: Dict[str, Any],
    output_path: Optional[Path] = None
) -> Path:
    """
    Save sensitivity analysis report to YAML.
    Default path: results/sensitivity_report.yaml
    """
    if output_path is None:
        config = get_config()
        output_path = config.RESULTS_DIR / "sensitivity_report.yaml"
    
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        yaml.dump(report, f, default_flow_style=False, sort_keys=False)
    
    logger.info(f"Sensitivity report saved to {output_path}")
    return output_path

@get_logger_wrapper
def main(logger: logging.Logger) -> int:
    """
    Main entry point for T026: Save sensitivity analysis report.
    This task depends on T025 (Sensitivity Analysis logic) which generated the report.
    Since T025 is marked as completed, we assume the report might exist or needs regeneration.
    Per T026 description: "Save sensitivity analysis report to results/sensitivity_report.yaml"
    We will re-run the analysis to ensure the file exists and is fresh.
    """
    logger.info("Starting Sensitivity Analysis (T026)")
    
    # Run the analysis
    report = run_sensitivity_analysis(logger=logger)
    
    # Save the report
    if report["models"]:
        save_sensitivity_report(logger=logger, report=report)
        logger.info("T026 completed successfully.")
        return 0
    else:
        logger.error("No models were generated. Cannot save report.")
        return 1

if __name__ == "__main__":
    sys.exit(main())