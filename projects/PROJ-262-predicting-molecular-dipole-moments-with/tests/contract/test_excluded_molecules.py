"""
Contract test for excluded_molecules.csv generated by T019.
Verifies existence, schema columns, and updates state hash.
"""
import csv
import hashlib
import json
import os
import sys
from pathlib import Path

import pytest
import yaml

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT / "code"))

EXCLUDED_FILE = PROJECT_ROOT / "data" / "reports" / "excluded_molecules.csv"
STATE_FILE = PROJECT_ROOT / "state" / "projects" / "PROJ-262-predicting-molecular-dipole-moments-with.yaml"

REQUIRED_COLUMNS = ["molecule_id", "exclusion_reason", "exclusion_timestamp"]
VALID_REASONS = {"missing_3d", "invalid_structure"}


def get_file_hash(filepath: Path) -> str:
    """Compute SHA-256 hash of a file."""
    sha256_hash = hashlib.sha256()
    with open(filepath, "rb") as f:
        for byte_block in iter(lambda: f.read(4096), b""):
            sha256_hash.update(byte_block)
    return sha256_hash.hexdigest()


def load_state() -> dict:
    """Load the state YAML file."""
    if not STATE_FILE.exists():
        return {}
    with open(STATE_FILE, "r") as f:
        return yaml.safe_load(f) or {}


def save_state(state: dict) -> None:
    """Save the state YAML file."""
    with open(STATE_FILE, "w") as f:
        yaml.dump(state, f, default_flow_style=False)


class TestExcludedMoleculesSchema:
    """Tests for the excluded_molecules.csv contract."""

    def test_file_exists(self):
        """Assert that the excluded_molecules.csv file exists."""
        assert EXCLUDED_FILE.exists(), f"File not found: {EXCLUDED_FILE}"

    def test_has_required_columns(self):
        """Assert that the CSV has the required columns."""
        assert EXCLUDED_FILE.exists(), f"File not found: {EXCLUDED_FILE}"

        with open(EXCLUDED_FILE, newline="", encoding="utf-8") as csvfile:
            reader = csv.DictReader(csvfile)
            headers = reader.fieldnames

            assert headers is not None, "CSV file is empty or has no headers"
            for col in REQUIRED_COLUMNS:
                assert col in headers, f"Missing required column: {col}"

    def test_exclusion_reason_is_valid_enum(self):
        """Assert that exclusion_reason values are from the valid enum set."""
        assert EXCLUDED_FILE.exists(), f"File not found: {EXCLUDED_FILE}"

        with open(EXCLUDED_FILE, newline="", encoding="utf-8") as csvfile:
            reader = csv.DictReader(csvfile)
            for row_num, row in enumerate(reader, start=2):
                reason = row.get("exclusion_reason", "")
                assert reason in VALID_REASONS, (
                    f"Invalid exclusion_reason '{reason}' at row {row_num}. "
                    f"Must be one of {VALID_REASONS}"
                )

    def test_molecule_id_is_not_empty(self):
        """Assert that molecule_id is not empty for any row."""
        assert EXCLUDED_FILE.exists(), f"File not found: {EXCLUDED_FILE}"

        with open(EXCLUDED_FILE, newline="", encoding="utf-8") as csvfile:
            reader = csv.DictReader(csvfile)
            for row_num, row in enumerate(reader, start=2):
                mid = row.get("molecule_id", "")
                assert mid.strip(), f"Empty molecule_id at row {row_num}"

    def test_updates_state_hash(self):
        """Assert that the state file is updated with the artifact hash."""
        assert EXCLUDED_FILE.exists(), f"File not found: {EXCLUDED_FILE}"

        current_hash = get_file_hash(EXCLUDED_FILE)
        state = load_state()

        # Check if the hash exists in state, if not, update it
        artifacts = state.get("artifacts", {})
        excluded_artifact = artifacts.get("excluded_molecules.csv", {})
        
        if excluded_artifact.get("hash") != current_hash:
            # Update the state with the new hash
            if "artifacts" not in state:
                state["artifacts"] = {}
            state["artifacts"]["excluded_molecules.csv"] = {
                "path": str(EXCLUDED_FILE.relative_to(PROJECT_ROOT)),
                "hash": current_hash,
                "updated_at": "2026-01-01T00:00:00Z" # Placeholder for actual timestamp logic if needed
            }
            save_state(state)
        
        # Verify the update
        state_after = load_state()
        assert state_after.get("artifacts", {}).get("excluded_molecules.csv", {}).get("hash") == current_hash, \
            "State file was not updated with the correct hash."

if __name__ == "__main__":
    pytest.main([__file__, "-v"])