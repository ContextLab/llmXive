def calculate_rmse_variance(metrics_path: Path) -> float:
    """
    Reads the metrics CSV generated by the training script and calculates
    the variance of the RMSE column.
    """
    if not metrics_path.exists():
        raise FileNotFoundError(f"Metrics file not found: {metrics_path}")

    rmse_values = []
    with open(metrics_path, "r", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                rmse = float(row["rmse"])
                if not math.isnan(rmse):
                    rmse_values.append(rmse)
            except (ValueError, KeyError):
                continue

    if len(rmse_values) < 2:
        return 0.0

    mean_rmse = sum(rmse_values) / len(rmse_values)
    variance = sum((x - mean_rmse) ** 2 for x in rmse_values) / len(rmse_values)
    return variance

def test_rf_training_rmse_variance_under_10_percent():
    """
    Asserts that the Random Forest training pipeline produces stable results
    across multiple random seeds, with RMSE variance under 10%.
    """
    # Setup temporary directories for this test run
    temp_dir = tempfile.mkdtemp(prefix="rf_test_")
    data_dir = Path(temp_dir) / "data"
    results_dir = Path(temp_dir) / "results"
    data_dir.mkdir(parents=True, exist_ok=True)
    results_dir.mkdir(parents=True, exist_ok=True)

    metrics_file = results_dir / "metrics_rf.csv"

    try:
        # Simulate the training run for multiple seeds
        # We use a small number of seeds and epochs for the integration test
        seeds = [42, 123, 456]
        num_epochs = 5  # Reduced for speed in integration test

        # Run training for each seed
        for seed in seeds:
            set_seed(seed)
            # Construct args for the train_rf main function
            # We mock the dataset loading by ensuring the script can run
            # The actual data loading depends on T020 producing the parquet files.
            # If T020 hasn't run, this will fail, which is expected behavior
            # (the test environment must have the data ready).
            # We pass the paths dynamically.
            sys.argv = [
                "test_rf_training.py",
                "--data-path", str(data_dir),
                "--results-path", str(results_dir),
                "--seed", str(seed),
                "--epochs", str(num_epochs),
                "--n-jobs", "1"
            ]
            
            # Note: The actual train_rf.py expects the processed data to exist.
            # If the data is missing, the test fails here, indicating a prerequisite failure.
            # For the purpose of this task, we assume the data pipeline (T020) has run.
            # If the environment is clean, we might need to handle the case where data is missing,
            # but per constraints, we must not fake data. We assume the test runner provides the data.
            try:
                train_rf_main()
            except Exception as e:
                # If training fails due to missing data, we cannot test variance.
                # However, if the code itself has a bug, it should raise here.
                # We re-raise if it's not a missing data error we can handle.
                if "No such file" in str(e) or "FileNotFoundError" in str(e):
                    # This is a prerequisite failure, not a code logic failure for T108.
                    # But for the test to pass, we need the data.
                    # In a real CI, data would be pre-generated.
                    # We will assume data exists or the script handles it gracefully.
                    # If the script crashes, the test fails.
                    raise e
                raise

        # Verify the metrics file was created
        if not metrics_file.exists():
            raise FileNotFoundError(f"Training did not produce metrics file at {metrics_file}")

        # Calculate variance
        variance = calculate_rmse_variance(metrics_file)
        
        # Calculate mean to determine relative variance (coefficient of variation squared approx)
        # Or simply check if variance is "small" relative to the magnitude of RMSE.
        # The task asks for "variance under 10 percent". This usually implies
        # (Standard Deviation / Mean) < 0.10, i.e., Coefficient of Variation < 10%.
        # Or it could mean Variance / Mean < 0.10.
        # Let's interpret as Coefficient of Variation (CV) < 10%.
        
        rmse_values = []
        with open(metrics_file, "r", newline="") as f:
            reader = csv.DictReader(f)
            for row in reader:
                rmse_values.append(float(row["rmse"]))
        
        if not rmse_values:
            raise ValueError("No RMSE values found in metrics file")
            
        mean_rmse = sum(rmse_values) / len(rmse_values)
        std_rmse = math.sqrt(variance)
        
        if mean_rmse == 0:
            # Avoid division by zero
            cv = 0.0
        else:
            cv = std_rmse / mean_rmse

        # Assert stability
        # We expect a CV of less than 10% (0.10)
        assert cv < 0.10, (
            f"Random Forest training instability detected. "
            f"Mean RMSE: {mean_rmse:.4f}, Std RMSE: {std_rmse:.4f}, "
            f"Coefficient of Variation: {cv:.4f} (must be < 0.10)"
        )

    finally:
        # Cleanup
        if os.path.exists(temp_dir):
            shutil.rmtree(temp_dir)

if __name__ == "__main__":
    test_rf_training_rmse_variance_under_10_percent()
    print("Test passed: RMSE variance under 10% across seeds.")