"""Validate downloaded dataset integrity for US1.

Checks:
1. Image files are not corrupted and can be opened.
2. Metadata (yield_strength_mpa) exists for each image.
3. Ratio of invalid pairs < 1%.

Outputs: results/validation_report.json
Exits: 1 if invalid_ratio > 0.01, else 0.
"""
from __future__ import annotations

import csv
import json
import logging
import os
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent))

from utils.logging_config import get_logger, log_operation

# Import config utilities
from utils.config import get_raw_dir, get_results_dir


def setup_logging() -> logging.Logger:
    """Setup validation logging."""
    logger = get_logger("validate", log_file="results/validate.log", json_file="results/validate.json")
    return logger


def load_manifest(manifest_path: Path) -> List[Dict[str, Any]]:
    """Load the manifest CSV generated by preprocessing/splitting."""
    if not manifest_path.exists():
        raise FileNotFoundError(f"Manifest not found at {manifest_path}")

    data = []
    with open(manifest_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            data.append(row)
    return data


def validate_image_exists(image_path: Path) -> bool:
    """Check if image file exists."""
    return image_path.exists()


def validate_image_integrity(image_path: Path) -> Tuple[bool, str]:
    """
    Verify image integrity by attempting to open it.
    Returns (is_valid, error_message).
    """
    try:
        # Use PIL to open and verify the image
        from PIL import Image
        with Image.open(image_path) as img:
            img.verify() # Verify the image is not corrupted
        return True, ""
    except Exception as e:
        return False, str(e)


def validate_pair(image_path: Path, metadata: Dict[str, Any]) -> Tuple[bool, str]:
    """
    Validate a single image-metadata pair.
    Checks:
    1. Image exists.
    2. Image is not corrupted.
    3. Metadata contains 'yield_strength_mpa'.
    """
    if not validate_image_exists(image_path):
        return False, "Image file missing"

    is_valid, error = validate_image_integrity(image_path)
    if not is_valid:
        return False, f"Image corrupted: {error}"

    # Check for required metadata field
    if "yield_strength_mpa" not in metadata:
        return False, "Missing metadata: yield_strength_mpa"

    # Try to parse the value
    try:
        val = metadata["yield_strength_mpa"]
        if val is None or val == "":
            return False, "Metadata value is empty"
        float(val) # Ensure it's numeric
    except (ValueError, TypeError):
        return False, "Metadata value is not numeric"

    return True, ""


def run_validation(raw_dir: Path, manifest_path: Path) -> Dict[str, Any]:
    """
    Run validation on all entries in the manifest.
    Returns a report dict.
    """
    logger = setup_logging()
    log_operation("validation_start", path=str(manifest_path))

    if not raw_dir.exists():
        raise FileNotFoundError(f"Raw data directory not found: {raw_dir}")

    manifest_data = load_manifest(manifest_path)
    total_count = len(manifest_data)
    invalid_count = 0
    invalid_details = []

    for idx, row in enumerate(manifest_data):
        # Construct image path based on raw_dir and filename in manifest
        # Assuming manifest has 'image_filename' or similar key
        image_filename = row.get("image_filename") or row.get("filename") or row.get("image_id")

        if not image_filename:
            # If no filename key, skip or treat as invalid
            invalid_count += 1
            invalid_details.append({"index": idx, "reason": "No image filename in manifest row"})
            continue

        image_path = raw_dir / image_filename

        # If the manifest stores relative paths, join them correctly
        # Assuming the manifest is relative to raw_dir or processed_dir
        # For T042, we are validating `data/raw/` which should contain the original images.
        # The manifest from T041/T013 might point to processed images or original.
        # T042 spec says: "iterate through data/raw/".
        # If manifest points to processed, we need to map back or check raw.
        # Let's assume the manifest contains the original filename or relative path in raw.
        # If not, we might need to search raw_dir.
        # For robustness, if direct path fails, try to find file in raw_dir.
        if not image_path.exists():
            # Try to find file in raw_dir if direct path fails
            found = False
            for f in raw_dir.rglob(image_filename):
                image_path = f
                found = True
                break
            if not found:
                invalid_count += 1
                invalid_details.append({"index": idx, "reason": f"Image not found: {image_filename}"})
                continue

        is_valid, reason = validate_pair(image_path, row)
        if not is_valid:
            invalid_count += 1
            invalid_details.append({"index": idx, "image": str(image_filename), "reason": reason})

    invalid_ratio = invalid_count / total_count if total_count > 0 else 0.0

    report = {
        "invalid_count": invalid_count,
        "total_count": total_count,
        "invalid_ratio": invalid_ratio,
        "details": invalid_details[:10] # Limit details in report
    }

    log_operation("validation_complete", status="success" if invalid_ratio <= 0.01 else "failed", report=report)
    return report


def write_validation_report(report: Dict[str, Any], output_path: Path) -> None:
    """Write the validation report to JSON."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)


def main() -> None:
    """Main entry point for validation script."""
    logger = setup_logging()
    log_operation("main_start")

    try:
        raw_dir = get_raw_dir()
        results_dir = get_results_dir()

        # The manifest is typically generated after preprocessing/splitting.
        # T042 runs AFTER T040 (download) and BEFORE T041 (preprocess) according to strict order?
        # Wait, the task description says: "Must run immediately after T040 and BEFORE T041".
        # But T041 produces the processed images and manifest.
        # If we run BEFORE T041, there is no manifest.
        # However, T040 downloads to `data/raw/`. The manifest for raw data might be implicit
        # (all files in raw_dir) or generated by T040.
        # Let's assume T040 generates a `manifest.csv` in `data/raw/` or `data/processed/`.
        # If T040 doesn't generate a manifest, we must scan `data/raw/` directly.
        # The task says: "iterate through data/raw/".
        # Let's assume we scan all image files in data/raw/ and check for corresponding metadata.
        # Where is metadata? T040 downloads from HuggingFace. The dataset `Rxzh/ebsd-synthetic`
        # likely has metadata in a CSV or JSON file alongside images.
        # If no manifest exists, we generate a temporary one by scanning the directory.

        manifest_path = raw_dir / "manifest.csv"
        if not manifest_path.exists():
            # Fallback: scan raw_dir for images and assume metadata is embedded or missing
            # This is a degenerate case if T040 didn't produce a manifest.
            # For this implementation, we assume T040 produces a manifest or we scan.
            # Let's scan the directory if manifest is missing.
            logger.warning("Manifest not found, scanning raw directory directly.")
            # We need to construct a pseudo-manifest or validate files directly.
            # Since T042 requires checking 'yield_strength_mpa', and we don't have a manifest,
            # we might fail if metadata isn't in the filename or a sidecar.
            # However, the spec says T040 downloads the dataset. If the dataset has metadata,
            # it should be in a file like 'metadata.csv'.
            metadata_file = raw_dir / "metadata.csv"
            if metadata_file.exists():
                manifest_data = load_manifest(metadata_file)
            else:
                # If no metadata file, we can only check image integrity.
                # But T042 requires checking yield_strength_mpa.
                # If missing, we report as invalid.
                # Let's try to infer from filenames or just report all as invalid if no metadata.
                # For now, let's assume we just scan images and report missing metadata.
                import glob
                image_files = list(raw_dir.glob("*")) # Simplified
                manifest_data = [{"image_filename": str(f.name)} for f in image_files if f.is_file()]
        else:
            manifest_data = load_manifest(manifest_path)

        # If we are validating raw data, we need to ensure we have the metadata.
        # If the dataset from HF includes a metadata CSV, T040 should have downloaded it.
        # Let's assume the manifest is `data/raw/manifest.csv` or `data/raw/metadata.csv`.
        # If not, we try to find it.
        if not manifest_path.exists():
            manifest_path = raw_dir / "metadata.csv"

        report = run_validation(raw_dir, manifest_path)
        output_path = results_dir / "validation_report.json"
        write_validation_report(report, output_path)

        logger.info(f"Validation report written to {output_path}")

        # Exit with code 1 if invalid ratio > 1%
        if report["invalid_ratio"] > 0.01:
            logger.error(f"Invalid ratio {report['invalid_ratio']} exceeds 1% threshold.")
            sys.exit(1)
        else:
            logger.info("Validation passed.")
            sys.exit(0)

    except Exception as e:
        logger.error(f"Validation failed with error: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()