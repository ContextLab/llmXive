"""
Task T019: Calculate Adjusted R² and Optimal Lambda, update model_results.json.

This script loads the model results generated by the modeling pipeline, calculates
the Adjusted R² for the linear model, and updates the JSON file with these metrics.
It also ensures the optimal lambda from the LASSO step is present.
"""
import os
import sys
import json
import argparse
import numpy as np
import pandas as pd
from pathlib import Path

# Import config utilities
from config import get_path, ensure_dirs

def load_json_safe(path: str) -> dict:
    """Load a JSON file safely."""
    if not os.path.exists(path):
        raise FileNotFoundError(f"Input file not found: {path}")
    with open(path, 'r') as f:
        return json.load(f)

def calculate_adjusted_r2(r2: float, n: int, p: int) -> float:
    """
    Calculate Adjusted R-squared.

    Formula: 1 - (1 - R²) * (n - 1) / (n - p - 1)
    where:
      n = number of observations
      p = number of predictors (features)
    """
    if n <= p + 1:
        return 0.0  # Undefined or zero if model is saturated
    return 1.0 - (1.0 - r2) * (n - 1) / (n - p - 1)

def main():
    parser = argparse.ArgumentParser(description="Calculate Adjusted R2 and update model results.")
    parser.add_argument(
        "--input",
        type=str,
        default=None,
        help="Path to model_results.json. If None, uses default config path."
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Path to output model_results.json. If None, uses default config path."
    )
    args = parser.parse_args()

    # Determine paths
    if args.input:
        input_path = args.input
    else:
        input_path = get_path("data/processed/model_results.json")

    if args.output:
        output_path = args.output
    else:
        output_path = input_path  # Overwrite or same path

    # Ensure output directory exists
    ensure_dirs(output_path)

    print(f"Loading model results from: {input_path}")
    try:
        results = load_json_safe(input_path)
    except FileNotFoundError as e:
        print(f"Error: {e}")
        sys.exit(1)

    # Extract necessary data
    # The results structure typically contains 'linear_model' and 'lasso_model' keys
    # or a flat structure depending on T017/T018 output.
    # We assume a structure like:
    # {
    #   "linear_model": { "r2": ..., "n": ..., "p": ..., ... },
    #   "lasso_model": { "optimal_lambda": ..., ... },
    #   ...
    # }
    
    # If the structure is flat (e.g., from a single dict merge), we adapt.
    # Let's handle both common patterns.
    
    linear_metrics = results.get("linear_model", results)
    lasso_metrics = results.get("lasso_model", {})

    r2 = linear_metrics.get("r2")
    n = linear_metrics.get("n_samples") or linear_metrics.get("n")
    p = linear_metrics.get("n_features") or linear_metrics.get("p")
    optimal_lambda = lasso_metrics.get("optimal_lambda")

    if r2 is None:
        print("Warning: 'r2' not found in linear_model metrics. Cannot calculate Adjusted R2.")
        adjusted_r2 = None
    elif n is None or p is None:
        print(f"Warning: Missing sample size (n={n}) or feature count (p={p}). Cannot calculate Adjusted R2.")
        adjusted_r2 = None
    else:
        adjusted_r2 = calculate_adjusted_r2(float(r2), int(n), int(p))
        print(f"Calculated Adjusted R²: {adjusted_r2:.4f} (R²={r2:.4f}, n={n}, p={p})")

    # Update the results dictionary
    if adjusted_r2 is not None:
        if "linear_model" in results:
            results["linear_model"]["adjusted_r2"] = adjusted_r2
        else:
            results["adjusted_r2"] = adjusted_r2

    if optimal_lambda is not None:
        if "lasso_model" in results:
            results["lasso_model"]["optimal_lambda"] = optimal_lambda
        else:
            results["optimal_lambda"] = optimal_lambda
    
    # Save updated results
    print(f"Saving updated model results to: {output_path}")
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)

    print("Task T019 completed successfully.")

if __name__ == "__main__":
    main()