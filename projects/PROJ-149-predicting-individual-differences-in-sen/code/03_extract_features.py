def load_preprocessed_eeg(input_dir: str) -> Dict[str, mne.Epochs]:
    """
    Load preprocessed EEG data from the input directory.
    Expects .fif files generated by 02_preprocess_eeg.py.
    """
    subject_files = glob.glob(os.path.join(input_dir, "*.fif"))
    if not subject_files:
        raise FileNotFoundError(f"No preprocessed EEG files found in {input_dir}")

    data = {}
    for fpath in subject_files:
        subject_id = Path(fpath).stem
        # Load as epochs (if saved as epochs) or raw then convert
        try:
            raw = mne.io.read_raw_fif(fpath, preload=True)
            # If the file contains raw data, we need to create epochs or use continuous
            # The task asks for continuous 5-minute epochs. We assume the preprocessed
            # data is continuous raw data.
            data[subject_id] = raw
        except Exception as e:
            print(f"Warning: Could not load {fpath}: {e}")
    return data

def compute_welch_psd(raw: mne.io.Raw, window_sec: float, overlap_sec: float, band_freqs: Dict[str, Tuple[float, float]]) -> pd.DataFrame:
    """
    Compute Welch's PSD on continuous data.
    Aggregates power into specified bands.
    """
    sfreq = raw.info['sfreq']
    data = raw.get_data()
    ch_names = raw.ch_names
    n_channels = len(ch_names)

    # Welch parameters
    nperseg = int(window_sec * sfreq)
    noverlap = int(overlap_sec * sfreq)

    # Compute PSD for all channels
    # mne.time_frequency.psd_welch handles multi-channel arrays
    psds, freqs = mne.time_frequency.psd_welch(
        raw,
        fmin=0,
        fmax=None,
        n_fft=nperseg,
        n_overlap=noverlap,
        average='mean',
        verbose=False
    )

    # psds shape: (n_epochs, n_channels, n_freqs)
    # Since we are treating continuous data as one long epoch or split into non-overlapping for integration?
    # The task says "continuous 5-minute epochs". If raw is > 5 mins, we might need to slice.
    # However, standard Welch on the whole raw object averages over the windows.
    # Let's assume the input raw is roughly 5 mins or we process the whole thing as a "continuous" block.
    # If raw is much longer, we might want to slice to first 5 mins.
    # Let's slice to 5 minutes if longer, to be consistent with "5-minute epochs".
    duration = raw.times[-1]
    if duration > 300: # 5 minutes
        raw = raw.copy().crop(tmax=300)
        psds, freqs = mne.time_frequency.psd_welch(
            raw, fmin=0, fmax=None, n_fft=nperseg, n_overlap=noverlap, average='mean', verbose=False
        )

    # psds is now (n_channels, n_freqs) if average='mean' was used on the single epoch block
    # Actually, mne psd_welch on a Raw object returns (n_channels, n_freqs) if average='mean'
    # Wait, mne psd_welch on Raw returns (n_channels, n_freqs)
    
    # Aggregate into bands
    band_power = {}
    for band_name, (f_min, f_max) in band_freqs.items():
        band_mask = (freqs >= f_min) & (freqs <= f_max)
        if np.any(band_mask):
            # Average power in the band (intrinsic units: V^2/Hz * Hz = V^2)
            # mne returns power in V^2/Hz
            band_power[band_name] = np.mean(psds[:, band_mask], axis=1)
        else:
            band_power[band_name] = np.zeros(n_channels)

    # Create DataFrame: rows = channels, cols = bands
    df = pd.DataFrame(band_power, index=ch_names)
    # We need one row per participant. The task says "aggregate power".
    # Usually, this means averaging across channels or keeping channel-specific features.
    # Given the downstream modeling (T015, T017) expects "one row per participant",
    # we should aggregate across channels (e.g., mean power across all channels).
    # Let's compute the mean power across channels for each band.
    participant_power = {f"{b}_mean": df[b].mean() for b in band_freqs.keys()}
    participant_power["subject_id"] = raw.info['subject_info']['his_id'] if raw.info.get('subject_info') else "unknown"
    
    # If subject info is missing, try to infer from filename?
    # The function `load_preprocessed_eeg` doesn't pass subject_id from filename into raw.info necessarily.
    # We'll handle subject_id in the main loop.
    
    return pd.DataFrame([participant_power])

def aggregate_band_power(raw: mne.io.Raw, window_sec: float, overlap_sec: float) -> pd.DataFrame:
    """Wrapper to compute PSD and aggregate."""
    band_freqs = get_band_freqs()
    return compute_welch_psd(raw, window_sec, overlap_sec, band_freqs)

def extract_features_for_subject(subject_id: str, raw: mne.io.Raw, output_file: str) -> None:
    """Extract features for a single subject and append to output file."""
    window_sec = get_window_seconds()
    overlap_sec = get_overlap_seconds()
    
    features = aggregate_band_power(raw, window_sec, overlap_sec)
    features['subject_id'] = subject_id # Ensure subject_id is set correctly
    
    # Reorder columns to put subject_id first
    cols = ['subject_id'] + [c for c in features.columns if c != 'subject_id']
    features = features[cols]
    
    file_path = Path(output_file)
    file_path.parent.mkdir(parents=True, exist_ok=True)
    
    if file_path.exists():
        features.to_csv(file_path, mode='a', header=False, index=False)
    else:
        features.to_csv(file_path, index=False)

def main():
    """Main entry point for feature extraction."""
    parser = argparse.ArgumentParser(description="Extract EEG PSD features")
    parser.add_argument("--input-dir", type=str, default="data/interim/cleaned_eeg",
                        help="Directory containing preprocessed EEG files")
    parser.add_argument("--output-file", type=str, default="data/interim/eeg_psd.csv",
                        help="Output CSV file path")
    args = parser.parse_args()

    set_global_seed(get_seed())
    ensure_dirs()

    input_dir = args.input_dir
    output_file = args.output_file

    if not os.path.exists(input_dir):
        print(f"Error: Input directory {input_dir} does not exist.")
        sys.exit(1)

    # Load preprocessed data
    # The preprocessor saves .fif files. We need to map filenames to subject IDs.
    # Usually PhysioNet subject IDs are in the filename or metadata.
    # Let's assume the filename is subject_id.fif or similar.
    
    files = glob.glob(os.path.join(input_dir, "*.fif"))
    if not files:
        print(f"No .fif files found in {input_dir}.")
        sys.exit(1)

    # Clear output file if it exists to start fresh
    if os.path.exists(output_file):
        os.remove(output_file)

    for fpath in files:
        try:
            raw = mne.io.read_raw_fif(fpath, preload=True)
            # Extract subject ID from filename (stem)
            subject_id = Path(fpath).stem
            print(f"Processing {subject_id}...")
            extract_features_for_subject(subject_id, raw, output_file)
        except Exception as e:
            print(f"Error processing {fpath}: {e}")
            continue

    print(f"Feature extraction complete. Output saved to {output_file}")

if __name__ == "__main__":
    main()
