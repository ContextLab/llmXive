def load_exclusion_log() -> pd.DataFrame:
    """
    Load the exclusion log generated by T010a.
    Returns a DataFrame with 'participant_id' column.
    """
    exclusion_path = get_path("data/interim", "exclusion_log.csv")
    if not os.path.exists(exclusion_path):
        raise FileNotFoundError(f"Exclusion log not found at {exclusion_path}. Run T010a first.")

    df = pd.read_csv(exclusion_path)
    if "participant_id" not in df.columns:
        raise ValueError("Exclusion log must contain 'participant_id' column.")
    return df

def load_preprocessed_eeg(input_dir: str) -> Dict[str, mne.io.Raw]:
    """
    Load cleaned .fif files from the input directory.
    Returns a dict mapping participant_id -> mne.io.Raw object.
    """
    cleaned_dir = Path(input_dir)
    if not cleaned_dir.exists():
        raise FileNotFoundError(f"Cleaned EEG directory not found: {cleaned_dir}")

    fif_files = list(cleaned_dir.glob("*.fif"))
    if not fif_files:
        raise FileNotFoundError(f"No .fif files found in {cleaned_dir}")

    participants = {}
    for fif_file in fif_files:
        try:
            raw = mne.io.read_raw_fif(fif_file, preload=True)
            # Extract participant ID from filename (e.g., sub-001_ses-1_task-rest_clean.fif -> 001)
            name = fif_file.stem
            # Heuristic: remove common prefixes/suffixes to get ID
            # Assuming format like 'sub-XXX_ses-YYY_task-rest_clean' or similar
            # We'll store the raw object keyed by the stem for now
            # The downstream logic will map this to the CSV 'participant_id'
            # For PhysioNet, filenames often look like 'sub-001_ses-1_task-rest_clean.fif'
            # We'll try to extract the numeric ID
            import re
            match = re.search(r'sub-(\d+)', name)
            if match:
                pid = match.group(1)
                participants[pid] = raw
            else:
                # Fallback: use the whole stem if no ID found
                participants[name] = raw
                print(f"Warning: Could not extract numeric ID from {name}, using full stem.")
        except Exception as e:
            print(f"Error loading {fif_file}: {e}")
            continue

    return participants

def compute_welch_psd_chunked(raw: mne.io.Raw, window_sec: float, overlap_sec: float) -> Tuple[np.ndarray, np.ndarray]:
    """
    Compute Welch's PSD on the continuous data using specified window and overlap.
    Returns (frequencies, power_spectrum) where power_spectrum is averaged across channels.
    """
    # Extract data and sampling frequency
    data = raw.get_data()  # Shape: (n_channels, n_times)
    sfreq = raw.info['sfreq']

    # Ensure window and overlap are in samples
    window_samples = int(window_sec * sfreq)
    overlap_samples = int(overlap_sec * sfreq)

    if window_samples < 1 or overlap_samples < 0:
        raise ValueError("Invalid window or overlap duration.")

    # Compute PSD using MNE's welch which handles chunking internally
    # We use average across channels to get a global mean as per Constitution Principle VI
    freqs, psd = mne.time_frequency.psd_welch(
        raw,
        fmin=1.0,
        fmax=40.0,
        tmin=0,
        tmax=None,
        n_fft=window_samples,
        n_overlap=overlap_samples,
        average=True,  # Average across channels
        verbose=False
    )

    return freqs, psd

def aggregate_band_power(freqs: np.ndarray, psd: np.ndarray, bands: Dict[str, Tuple[float, float]]) -> Dict[str, float]:
    """
    Aggregate power into specified frequency bands.
    Returns a dict mapping band_name -> mean power in that band.
    """
    band_powers = {}
    for band_name, (low, high) in bands.items():
        # Find indices corresponding to the band
        idx = np.where((freqs >= low) & (freqs <= high))[0]
        if len(idx) == 0:
            # If no frequencies fall in the band, use 0 or a small epsilon
            band_powers[band_name] = 0.0
        else:
            # Mean power across the band
            band_powers[band_name] = float(np.mean(psd[idx]))
    return band_powers

def extract_features_for_subject(pid: str, raw: mne.io.Raw) -> Optional[Dict[str, Any]]:
    """
    Extract features for a single subject.
    Returns a dict with 'participant_id' and band powers.
    """
    try:
        # Compute PSD
        freqs, psd = compute_welch_psd_chunked(raw, WINDOW_SECONDS, OVERLAP_SECONDS)

        # Aggregate band powers
        band_powers = aggregate_band_power(freqs, psd, BAND_FREQS)

        # Add participant ID
        result = {"participant_id": pid}
        result.update(band_powers)

        # Validate no nulls
        for key, val in result.items():
            if val is None or (isinstance(val, float) and np.isnan(val)):
                print(f"Warning: Null value found for {pid} in {key}. Setting to 0.")
                result[key] = 0.0

        return result
    except Exception as e:
        print(f"Error processing subject {pid}: {e}")
        return None

def main():
    """
    Main entry point for T012.
    """
    parser = argparse.ArgumentParser(description="Extract EEG PSD features (T012)")
    parser.add_argument("--input-dir", type=str, default=None, help="Input directory for cleaned EEG files")
    parser.add_argument("--output-file", type=str, default=None, help="Output CSV file path")
    args = parser.parse_args()

    # Determine paths
    if args.input_dir:
        input_dir = args.input_dir
    else:
        input_dir = get_path("data/interim", "cleaned_eeg_final")

    if args.output_file:
        output_file = args.output_file
    else:
        output_file = get_path("data/interim", "eeg_psd.csv")

    print(f"Loading exclusion log from {get_path('data/interim', 'exclusion_log.csv')}...")
    exclusion_df = load_exclusion_log()
    excluded_pids = set(exclusion_df['participant_id'].astype(str).unique())
    print(f"Excluded participants: {len(excluded_pids)}")

    print(f"Loading preprocessed EEG from {input_dir}...")
    participants = load_preprocessed_eeg(input_dir)
    print(f"Loaded {len(participants)} participants.")

    # Filter out excluded participants
    valid_participants = {pid: raw for pid, raw in participants.items() if pid not in excluded_pids}
    print(f"Processing {len(valid_participants)} valid participants.")

    if len(valid_participants) == 0:
        print("No valid participants to process. Creating empty output file.")
        ensure_dirs(output_file)
        empty_df = pd.DataFrame(columns=["participant_id"] + list(BANDS))
        empty_df.to_csv(output_file, index=False)
        return

    # Process in chunks to manage memory
    chunk_size = 10  # Process 10 participants at a time
    all_features = []

    participant_ids = list(valid_participants.keys())
    for i in range(0, len(participant_ids), chunk_size):
        chunk_ids = participant_ids[i:i+chunk_size]
        print(f"Processing chunk {i//chunk_size + 1}: {chunk_ids}")

        for pid in chunk_ids:
            raw = valid_participants[pid]
            features = extract_features_for_subject(pid, raw)
            if features:
                all_features.append(features)

        # Free memory
        del chunk_ids

    if not all_features:
        print("No features extracted. Creating empty output file.")
        ensure_dirs(output_file)
        empty_df = pd.DataFrame(columns=["participant_id"] + list(BANDS))
        empty_df.to_csv(output_file, index=False)
        return

    # Create DataFrame
    df = pd.DataFrame(all_features)

    # Ensure all band columns exist (in case some were missing in extraction)
    for band in BANDS:
        if band not in df.columns:
            df[band] = 0.0

    # Select columns in order
    cols = ["participant_id"] + list(BANDS)
    df = df[cols]

    # Validate no nulls
    if df.isnull().any().any():
        print("Warning: Null values detected in output. Replacing with 0.")
        df = df.fillna(0)

    # Ensure output directory exists
    ensure_dirs(output_file)

    # Save to CSV
    df.to_csv(output_file, index=False)
    print(f"Features saved to {output_file}")
    print(f"Total participants processed: {len(df)}")

if __name__ == "__main__":
    main()
