def save_results(permutation_results):
    """Append permutation results to model_results.json."""
    path = get_path("model_results.json", "processed")
    
    if not os.path.exists(path):
        raise FileNotFoundError(f"Model results file not found at {path}. Run T019 first.")
    
    with open(path, 'r') as f:
        data = json.load(f)
    
    # Append permutation results
    data['permutation_test'] = permutation_results
    
    with open(path, 'w') as f:
        json.dump(data, f, indent=2)
    
    print(f"Permutation test results appended to {path}")

def main():
    parser = argparse.ArgumentParser(description="Perform permutation test for model significance.")
    parser.add_argument('--n-permutations', type=int, default=10000, help="Number of permutations")
    args = parser.parse_args()
    
    set_global_seed()
    seed = get_seed()
    
    print("Loading features...")
    features_df = load_features()
    
    print("Loading split indices...")
    split_indices = load_split_indices()
    
    print("Preparing test data...")
    X_test, y_test = prepare_test_data(features_df, split_indices)
    
    print("Loading original model results...")
    model_results_path = get_path("model_results.json", "processed")
    with open(model_results_path, 'r') as f:
        model_data = json.load(f)
    
    # Get the original R² (from the full model, likely LASSO or Linear)
    # The task says "assess significance of the full model's R²".
    # We assume the best model's R² is stored in model_data.
    # Let's look for 'r2' or 'adjusted_r2' in the top level or in a 'model' section.
    original_r2 = None
    if 'r2' in model_data:
        original_r2 = model_data['r2']
    elif 'adjusted_r2' in model_data:
        original_r2 = model_data['adjusted_r2']
    elif 'best_model' in model_data and 'r2' in model_data['best_model']:
        original_r2 = model_data['best_model']['r2']
    else:
        # Fallback: try to find any R² value
        for key, value in model_data.items():
            if isinstance(value, dict) and 'r2' in value:
                original_r2 = value['r2']
                break
            elif isinstance(value, (int, float)) and key.lower().find('r2') != -1:
                original_r2 = value
                break
    
    if original_r2 is None:
        raise ValueError("Could not find original R² in model_results.json")
    
    print(f"Original R²: {original_r2}")
    print(f"Running permutation test with {args.n_permutations} permutations...")
    
    permutation_results = run_permutation_test(
        X_test, y_test, 
        original_r2, 
        n_permutations=args.n_permutations, 
        random_state=seed
    )
    
    print(f"Permutation test complete. P-value: {permutation_results['p_value']}")
    
    save_results(permutation_results)
    
    print("Done.")

if __name__ == "__main__":
    main()