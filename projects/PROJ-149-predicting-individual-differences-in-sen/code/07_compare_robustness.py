"""
T027: Compare R² stability and report percentage difference in alpha power means.

This script compares the primary analysis results (with ICA, 4s windows) against
the robustness analysis results (without ICA, 2s windows) generated by T026.

It calculates:
1. R² stability: Percentage difference in R² between primary and robustness models.
2. Alpha power difference: Percentage difference in mean alpha power between conditions.

Outputs:
- data/processed/robustness_comparison.json: Detailed metrics and flags.
"""
import os
import sys
import json
import argparse
import pandas as pd
import numpy as np
from pathlib import Path

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from config import get_path

def load_model_results(file_path: str) -> dict:
    """Load model results JSON file."""
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Model results file not found: {file_path}")
    
    with open(file_path, 'r') as f:
        return json.load(f)

def load_robustness_data(file_path: str) -> pd.DataFrame:
    """Load robustness features CSV."""
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Robustness features file not found: {file_path}")
    
    return pd.read_csv(file_path)

def calculate_r2_stability(primary_r2: float, robust_r2: float) -> dict:
    """
    Calculate R² stability metrics.
    
    Args:
        primary_r2: R² from primary analysis (with ICA)
        robust_r2: R² from robustness analysis (without ICA)
        
    Returns:
        Dictionary with stability metrics
    """
    if primary_r2 == 0:
        pct_diff = float('inf') if robust_r2 != 0 else 0.0
    else:
        pct_diff = ((robust_r2 - primary_r2) / abs(primary_r2)) * 100
    
    # Determine stability flag (threshold: 10% change is considered unstable)
    is_stable = abs(pct_diff) <= 10.0
    
    return {
        "primary_r2": primary_r2,
        "robust_r2": robust_r2,
        "percentage_difference": pct_diff,
        "is_stable": is_stable,
        "stability_threshold_pct": 10.0
    }

def calculate_alpha_power_difference(primary_features: pd.DataFrame, 
                                     robust_features: pd.DataFrame) -> dict:
    """
    Calculate percentage difference in mean alpha power between conditions.
    
    Args:
        primary_features: Features from primary analysis (with ICA)
        robust_features: Features from robustness analysis (without ICA)
        
    Returns:
        Dictionary with alpha power comparison metrics
    """
    # Identify alpha column - could be 'alpha', 'alpha_relative', or 'alpha_clr'
    alpha_col = None
    possible_cols = ['alpha', 'alpha_relative', 'alpha_clr']
    
    for col in possible_cols:
        if col in primary_features.columns and col in robust_features.columns:
            alpha_col = col
            break
    
    if alpha_col is None:
        raise ValueError("Could not find alpha power column in either dataset")
    
    # Calculate means
    primary_mean = primary_features[alpha_col].mean()
    robust_mean = robust_features[alpha_col].mean()
    
    # Calculate percentage difference
    if primary_mean == 0:
        pct_diff = float('inf') if robust_mean != 0 else 0.0
    else:
        pct_diff = ((robust_mean - primary_mean) / abs(primary_mean)) * 100
    
    # Determine if difference is substantial (threshold: 15%)
    is_substantial = abs(pct_diff) > 15.0
    
    return {
        "primary_alpha_mean": primary_mean,
        "robust_alpha_mean": robust_mean,
        "percentage_difference": pct_diff,
        "is_substantial": is_substantial,
        "substantial_threshold_pct": 15.0,
        "column_used": alpha_col
    }

def main():
    parser = argparse.ArgumentParser(description="Compare robustness analysis results")
    parser.add_argument("--primary-model", type=str, default=None,
                      help="Path to primary model results JSON")
    parser.add_argument("--robust-features", type=str, default=None,
                      help="Path to robustness features CSV")
    parser.add_argument("--output", type=str, default=None,
                      help="Path to output JSON file")
    
    args = parser.parse_args()
    
    # Set defaults based on config
    if args.primary_model is None:
        args.primary_model = str(get_path("processed", "model_results.json"))
    if args.robust_features is None:
        args.robust_features = str(get_path("interim", "robustness", "robustness_features.csv"))
    if args.output is None:
        args.output = str(get_path("processed", "robustness_comparison.json"))
    
    print(f"Loading primary model results from: {args.primary_model}")
    print(f"Loading robustness features from: {args.robust_features}")
    
    # Load data
    try:
        primary_results = load_model_results(args.primary_model)
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        print("Primary model results not found. Ensure T019 completed successfully.")
        sys.exit(1)
    
    try:
        robust_features = load_robustness_data(args.robust_features)
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        print("Robustness features not found. Ensure T026 completed successfully.")
        sys.exit(1)
    
    # Load primary features for alpha comparison
    primary_features_path = get_path("processed", "features.csv")
    if not os.path.exists(primary_features_path):
        print(f"ERROR: Primary features file not found: {primary_features_path}")
        print("Ensure T015 completed successfully.")
        sys.exit(1)
    
    primary_features = pd.read_csv(primary_features_path)
    
    # Calculate metrics
    print("\nCalculating R² stability...")
    primary_r2 = primary_results.get("adjusted_r2", primary_results.get("r2", 0))
    robust_r2 = primary_results.get("robustness", {}).get("adjusted_r2", 
                                                          primary_results.get("robustness", {}).get("r2", 0))
    
    # If robustness R² is not in results, we might need to run modeling on robust features
    # For now, assume it's in the results from T026's modeling step
    if robust_r2 == 0 and "robustness" in primary_results:
        robust_r2 = primary_results["robustness"].get("adjusted_r2", 
                                                      primary_results["robustness"].get("r2", 0))
    
    r2_stability = calculate_r2_stability(primary_r2, robust_r2)
    
    print(f"  Primary R²: {primary_r2:.4f}")
    print(f"  Robust R²: {robust_r2:.4f}")
    print(f"  Percentage difference: {r2_stability['percentage_difference']:.2f}%")
    print(f"  Is stable: {r2_stability['is_stable']}")
    
    print("\nCalculating alpha power difference...")
    alpha_diff = calculate_alpha_power_difference(primary_features, robust_features)
    
    print(f"  Primary alpha mean: {alpha_diff['primary_alpha_mean']:.6f}")
    print(f"  Robust alpha mean: {alpha_diff['robust_alpha_mean']:.6f}")
    print(f"  Percentage difference: {alpha_diff['percentage_difference']:.2f}%")
    print(f"  Is substantial: {alpha_diff['is_substantial']}")
    
    # Compile results
    results = {
        "task": "T027 - Robustness Comparison",
        "timestamp": pd.Timestamp.now().isoformat(),
        "r2_stability": r2_stability,
        "alpha_power_difference": alpha_diff,
        "summary": {
            "r2_stable": r2_stability["is_stable"],
            "alpha_difference_substantial": alpha_diff["is_substantial"],
            "overall_robustness": "PASS" if (r2_stability["is_stable"] and not alpha_diff["is_substantial"]) else "WARNING"
        }
    }
    
    # Ensure output directory exists
    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Save results
    with open(args.output, 'w') as f:
        json.dump(results, f, indent=2)
    
    print(f"\nResults saved to: {args.output}")
    
    # Return exit code based on robustness
    if results["summary"]["overall_robustness"] == "WARNING":
        print("\nWARNING: Significant differences detected between primary and robustness analyses.")
        print("Review the metrics above to determine if results are reliable.")
    
    return 0

if __name__ == "__main__":
    sys.exit(main())