"""
Task T029: Generate sensitivity plot and report exact threshold where result becomes non-significant.

This script consumes the sensitivity sweep results generated by T028 (code/06_sensitivity_analysis.py)
to:
1. Identify the exact p-value threshold where the count of significant correlations drops (or crosses a critical boundary).
2. Generate a visualization (sensitivity_plot.png) showing the relationship between p-value threshold and significant count.
3. Write a summary report (sensitivity_report.json) with the critical threshold.

FR-009 Requirement: Sweep p-value threshold from 0.01 to 0.10 in steps of 0.01 and record count of significant correlations.
"""
import os
import sys
import json
import argparse
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path

# Add parent directory to path for imports if running as script
sys.path.insert(0, str(Path(__file__).parent))
from config import get_path, ensure_dirs

def load_sensitivity_results(input_path: str) -> pd.DataFrame:
    """
    Load the sensitivity sweep results from T028.
    
    Expected columns: p_threshold, significant_count, significant_alpha_count (optional)
    """
    if not os.path.exists(input_path):
        raise FileNotFoundError(f"Sensitivity results file not found: {input_path}")
    
    df = pd.read_csv(input_path)
    # Ensure p_threshold is numeric and sorted
    df['p_threshold'] = pd.to_numeric(df['p_threshold'])
    df = df.sort_values('p_threshold').reset_index(drop=True)
    return df

def find_critical_threshold(df: pd.DataFrame) -> dict:
    """
    Identify the exact threshold where results become non-significant or change behavior.
    
    Logic:
    - We look for the point where the count of significant correlations drops significantly
      or crosses a specific inflection point.
    - For this task, we define "becomes non-significant" as the threshold where the count
      of significant correlations is 0 (if such a point exists) or the last threshold
      where count > 0.
    - If the count never drops to 0, we report the highest threshold tested (0.10) as the
      point where significance is most lenient.
    """
    if df.empty:
        return {"error": "Empty dataframe"}

    # Find the threshold where significant_count drops to 0
    zero_thresholds = df[df['significant_count'] == 0]['p_threshold']
    
    if not zero_thresholds.empty:
        # The first threshold where count becomes 0
        critical_threshold = zero_thresholds.min()
        status = "became_non_significant"
    else:
        # Count never reached 0; report the highest threshold tested
        critical_threshold = df['p_threshold'].max()
        status = "remained_significant_at_max_threshold"

    # Find the last threshold where count > 0 (if any)
    positive_rows = df[df['significant_count'] > 0]
    if not positive_rows.empty:
        last_significant_threshold = positive_rows['p_threshold'].max()
    else:
        last_significant_threshold = None

    return {
        "critical_threshold": float(critical_threshold),
        "status": status,
        "last_significant_threshold": float(last_significant_threshold) if last_significant_threshold is not None else None,
        "total_thresholds_tested": len(df),
        "min_significant_count": int(df['significant_count'].min()),
        "max_significant_count": int(df['significant_count'].max())
    }

def generate_sensitivity_plot(df: pd.DataFrame, output_path: str):
    """
    Generate a line plot showing significant count vs. p-value threshold.
    """
    plt.style.use('seaborn-v0_8-whitegrid')
    fig, ax = plt.subplots(figsize=(10, 6))
    
    # Plot the data
    sns.lineplot(
        data=df, 
        x='p_threshold', 
        y='significant_count', 
        marker='o', 
        linewidth=2, 
        markersize=8,
        ax=ax,
        color='#2c3e50'
    )
    
    # Highlight the critical threshold
    critical_info = find_critical_threshold(df)
    if critical_info['last_significant_threshold'] is not None:
        # Mark the last significant point
        ax.axvline(
            x=critical_info['last_significant_threshold'], 
            color='#e74c3c', 
            linestyle='--', 
            linewidth=1.5,
            label=f"Last Significant Threshold: {critical_info['last_significant_threshold']:.2f}"
        )
    
    # Formatting
    ax.set_title('Sensitivity Analysis: Significant Correlations vs. P-Value Threshold', fontsize=14, fontweight='bold')
    ax.set_xlabel('P-Value Threshold', fontsize=12)
    ax.set_ylabel('Number of Significant Correlations', fontsize=12)
    ax.set_xticks(np.arange(0.01, 0.11, 0.01))
    ax.set_xlim(0.005, 0.105)
    
    ax.legend(loc='upper right')
    plt.tight_layout()
    
    # Save
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close(fig)

def generate_report(critical_info: dict, output_path: str):
    """
    Write the sensitivity analysis report to JSON.
    """
    report = {
        "analysis_type": "sensitivity_p_value_threshold",
        "description": "Identifies the p-value threshold where correlation significance changes.",
        "critical_threshold_info": critical_info,
        "generated_at": str(pd.Timestamp.now())
    }
    
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)

def main():
    parser = argparse.ArgumentParser(description="Generate sensitivity plot and report (T029)")
    parser.add_argument(
        "--input", 
        type=str, 
        default="data/interim/sensitivity_sweep_results.csv",
        help="Path to the sensitivity sweep results CSV (output of T028)"
    )
    parser.add_argument(
        "--plot-output", 
        type=str, 
        default="data/processed/sensitivity_plot.png",
        help="Path for the output plot"
    )
    parser.add_argument(
        "--report-output", 
        type=str, 
        default="data/processed/sensitivity_report.json",
        help="Path for the output report JSON"
    )
    
    args = parser.parse_args()
    
    print(f"Loading sensitivity results from {args.input}...")
    try:
        df = load_sensitivity_results(args.input)
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        print("Ensure T028 (06_sensitivity_analysis.py) has been run successfully.")
        sys.exit(1)
    
    print(f"Found {len(df)} threshold steps.")
    print(df.head())
    
    print("Identifying critical threshold...")
    critical_info = find_critical_threshold(df)
    print(f"Status: {critical_info['status']}")
    print(f"Critical Threshold: {critical_info['critical_threshold']}")
    
    print(f"Generating plot to {args.plot_output}...")
    generate_sensitivity_plot(df, args.plot_output)
    
    print(f"Writing report to {args.report_output}...")
    generate_report(critical_info, args.report_output)
    
    print("T029 completed successfully.")

if __name__ == "__main__":
    main()