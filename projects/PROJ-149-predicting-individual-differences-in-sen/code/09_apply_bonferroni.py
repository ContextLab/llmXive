"""
T021 / T020 Helper: Apply Bonferroni correction to correlations.
This script ensures that the correlations data is processed and saved to the expected location
if it hasn't been already, or re-processes it from the raw features if necessary.

This acts as the producer for T021, ensuring data/processed/correlations.csv exists for T025.
"""
import os
import sys
import argparse
import pandas as pd
from pathlib import Path
from config import bonferroni_correct, get_path, ensure_dirs

def load_correlations():
    """
    Loads correlations from the intermediate file generated by T020 (08_correlation_analysis.py).
    If not found, attempts to load from features and recompute (fallback for pipeline robustness).
    """
    # Try standard intermediate path first
    path = Path("data/interim/correlations_raw.csv")
    if path.exists():
        return pd.read_csv(path)
    
    # Fallback: Try to load features and compute on the fly if the raw file is missing
    # This handles cases where T020 ran but didn't save, or the path is different.
    features_path = Path("data/processed/features.csv")
    if not features_path.exists():
        raise FileNotFoundError("Features file not found. Cannot compute correlations.")
    
    df = pd.read_csv(features_path)
    # Expected columns: participant_id, median_rt, delta, theta, alpha, low_beta, high_beta, gamma (relative)
    # We need to compute Pearson correlation between each band and median_rt
    bands = ['delta', 'theta', 'alpha', 'low_beta', 'high_beta', 'gamma']
    results = []
    
    for band in bands:
        if band not in df.columns:
            continue
        corr, p_val = df[band].corr(df['median_rt'], method='pearson')
        results.append({
            'band': band,
            'correlation': corr,
            'p_value': p_val,
            'n': len(df)
        })
    
    return pd.DataFrame(results)

def apply_bonferroni_correction(df: pd.DataFrame, alpha: float = 0.05):
    """
    Applies Bonferroni correction to the p-values in the dataframe.
    """
    n_tests = len(df)
    corrected_alpha = alpha / n_tests if n_tests > 0 else alpha
    
    df['p_value_corrected'] = df['p_value'] * n_tests
    df['significant'] = df['p_value_corrected'] < alpha
    df['corrected_alpha_threshold'] = corrected_alpha
    
    return df, corrected_alpha

def save_corrected_results(df: pd.DataFrame, output_path: str):
    """
    Saves the corrected results to the specified path.
    """
    output = Path(output_path)
    ensure_dirs(output) # Use the tolerant ensure_dirs from config
    
    # Ensure no nulls
    if df.isnull().any().any():
        print("Warning: Dropping rows with nulls in correlations output.")
        df = df.dropna()
    
    df.to_csv(output, index=False)
    print(f"Saved Bonferroni-corrected correlations to {output_path}")

def main():
    parser = argparse.ArgumentParser(description="Apply Bonferroni correction to correlations (T021)")
    parser.add_argument('--output', default='data/processed/correlations.csv', help='Output path')
    args = parser.parse_args()

    print("Loading correlations...")
    try:
        corr_df = load_correlations()
    except FileNotFoundError as e:
        print(f"Error: {e}")
        sys.exit(1)

    print("Applying Bonferroni correction...")
    corrected_df, threshold = apply_bonferroni_correction(corr_df)
    print(f"Bonferroni threshold: {threshold}")

    print("Saving results...")
    save_corrected_results(corrected_df, args.output)

    print("T021 Complete.")

if __name__ == "__main__":
    main()
