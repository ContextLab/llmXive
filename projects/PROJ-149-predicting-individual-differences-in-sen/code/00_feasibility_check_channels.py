"""
T008d: Final Channel Rejection Gate.

Performs the channel rejection check *after* preprocessing (T010) and filters
the participant list based on the exclusion log generated by T010.

Logic:
1. Read `data/interim/feasibility_filtered.csv` (from T008b).
2. Read `data/interim/exclusion_log.csv` (from T010) containing `channels_rejected_ratio`.
3. Filter: Exclude participants if `channels_rejected_ratio > 0.30`.
4. Halt Condition: If no participants remain, write `data/interim/halt_signal.json` and exit(1).
5. Output:
   - `data/interim/final_participant_list.csv`
   - `data/interim/final_exclusion_log.csv` (appended with channel rejection reasons).
"""
import os
import sys
import csv
import json
from pathlib import Path
from datetime import datetime
from config import get_path, ensure_dirs

# Constants
CHANNEL_REJECTION_THRESHOLD = 0.30
INPUT_FILTERED_FILE = "interim/feasibility_filtered.csv"
INPUT_EXCLUSION_LOG = "interim/exclusion_log.csv"
OUTPUT_FINAL_LIST = "interim/final_participant_list.csv"
OUTPUT_FINAL_EXCLUSION = "interim/final_exclusion_log.csv"
HALT_SIGNAL_PATH = "interim/halt_signal.json"

def load_filtered_participants(filepath):
    """Load the participant list from the feasibility filtered file."""
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Input file not found: {filepath}")
    
    participants = []
    with open(filepath, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            participants.append(row)
    return participants

def load_preprocessing_exclusion_log(filepath):
    """Load the exclusion log generated by T010 (preprocessing)."""
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Preprocessing exclusion log not found: {filepath}. "
                                "Ensure T010 (02_preprocess_eeg.py) has run successfully.")
    
    log_entries = {} # Map participant_id -> entry
    with open(filepath, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            pid = row.get('participant_id')
            if pid:
                log_entries[pid] = row
    return log_entries

def check_channel_rejection(participants, exclusion_log):
    """
    Filter participants based on channels_rejected_ratio > 0.30.
    
    Returns:
      kept_participants (list): Participants passing the check.
      rejected_entries (list): List of dicts for the new exclusion log.
    """
    kept = []
    rejected = []
    
    for p in participants:
        pid = p.get('participant_id')
        entry = exclusion_log.get(pid, {})
        
        # Default to 0 if missing (though T010 should have written an entry for all processed)
        ratio_str = entry.get('channels_rejected_ratio', '0.0')
        try:
            ratio = float(ratio_str)
        except (ValueError, TypeError):
            ratio = 0.0
        
        if ratio > CHANNEL_REJECTION_THRESHOLD:
            rejected.append({
                'participant_id': pid,
                'reason': 'high_channel_rejection',
                'channels_rejected_ratio': ratio_str
            })
        else:
            kept.append(p)
            
    return kept, rejected

def write_final_participant_list(participants, filepath):
    """Write the final list of participants to CSV."""
    ensure_dirs(filepath)
    if not participants:
        # If empty, we still write the header
        with open(filepath, 'w', newline='', encoding='utf-8') as f:
            if participants:
                writer = csv.DictWriter(f, fieldnames=participants[0].keys())
                writer.writeheader()
                writer.writerows(participants)
            else:
                # Fallback header if list is empty but we know expected columns
                # Read from input if possible, or define standard
                fieldnames = ['participant_id', 'eeg_file', 'rt_file', 'segment_id', 'segment_duration']
                writer = csv.DictWriter(f, fieldnames=fieldnames)
                writer.writeheader()
    else:
        with open(filepath, 'w', newline='', encoding='utf-8') as f:
            fieldnames = list(participants[0].keys())
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(participants)

def update_exclusion_log(rejected_entries, output_filepath, existing_log_path=None):
    """
    Append new rejection entries to the final exclusion log.
    If existing_log_path is provided, we might want to merge, but task spec says
    'appended' to final_exclusion_log.csv. We treat this as creating/overwriting
    the final log with just these new entries or appending to a cumulative log if one exists.
    Given the flow, we create the final log with these entries.
    """
    ensure_dirs(output_filepath)
    
    fieldnames = ['participant_id', 'reason', 'channels_rejected_ratio']
    
    # Check if we should append to an existing file or start fresh
    # The task says "appended: participant_id, reason, channels_rejected_ratio"
    # implying we add to the log. If the file exists from previous steps (unlikely for this specific file name),
    # we append. Otherwise write new.
    write_mode = 'w'
    if os.path.exists(output_filepath):
        write_mode = 'a'
        
    with open(output_filepath, write_mode, newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        if write_mode == 'w':
            writer.writeheader()
        writer.writerows(rejected_entries)

def write_failure_report(reason, filepath):
    """Write a halt signal JSON file."""
    ensure_dirs(filepath)
    signal = {
        "status": "HALT",
        "reason": reason,
        "timestamp": datetime.now().isoformat(),
        "message": f"No participants remain after {reason} check."
    }
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(signal, f, indent=2)

def main():
    """Main execution entry point."""
    # Resolve paths
    base_dir = Path(__file__).resolve().parent.parent
    input_filtered = base_dir / "data" / INPUT_FILTERED_FILE
    input_exclusion = base_dir / "data" / INPUT_EXCLUSION_LOG
    output_list = base_dir / "data" / OUTPUT_FINAL_LIST
    output_exclusion = base_dir / "data" / OUTPUT_FINAL_EXCLUSION
    halt_signal = base_dir / "data" / HALT_SIGNAL_PATH

    print(f"[T008d] Starting channel rejection check...")
    print(f"[T008d] Input filtered: {input_filtered}")
    print(f"[T008d] Input exclusion log: {input_exclusion}")

    # 1. Load inputs
    try:
        participants = load_filtered_participants(str(input_filtered))
        print(f"[T008d] Loaded {len(participants)} participants from feasibility_filtered.csv.")
    except FileNotFoundError as e:
        print(f"[T008d] ERROR: {e}")
        sys.exit(1)

    try:
        exclusion_log = load_preprocessing_exclusion_log(str(input_exclusion))
        print(f"[T008d] Loaded {len(exclusion_log)} entries from exclusion_log.csv.")
    except FileNotFoundError as e:
        print(f"[T008d] ERROR: {e}")
        sys.exit(1)

    # 2. Check channel rejection
    kept, rejected = check_channel_rejection(participants, exclusion_log)
    print(f"[T008d] Kept: {len(kept)}, Rejected: {len(rejected)}")

    # 3. Handle Halt Condition
    if not kept:
        print(f"[T008d] HALT CONDITION: No participants remain after channel rejection.")
        write_failure_report("high_channel_rejection", str(halt_signal))
        print(f"[T008d] Wrote halt signal to {halt_signal}")
        sys.exit(1)

    # 4. Write outputs
    write_final_participant_list(kept, str(output_list))
    print(f"[T008d] Wrote final participant list to {output_list}")

    if rejected:
        # If there are existing entries in the output file (from previous runs?), we append.
        # However, usually this file is created fresh by this task in a clean run.
        # We append to be safe if the file exists.
        update_exclusion_log(rejected, str(output_exclusion))
        print(f"[T008d] Appended {len(rejected)} entries to {output_exclusion}")
    else:
        # Ensure the file exists even if empty (optional but good practice)
        if not os.path.exists(output_exclusion):
            ensure_dirs(output_exclusion)
            with open(output_exclusion, 'w', newline='', encoding='utf-8') as f:
                writer = csv.DictWriter(f, fieldnames=['participant_id', 'reason', 'channels_rejected_ratio'])
                writer.writeheader()

    print(f"[T008d] Channel rejection check completed successfully.")
    print(f"[T008d] Final participant count: {len(kept)}")
    return 0

if __name__ == "__main__":
    sys.exit(main())