"""
Task T035b: Validate schema of data/processed/model_results.json and data/processed/correlations.csv.

This script validates the structure and content of the model results and correlations outputs
generated by User Story 2. It ensures that all required fields are present, have correct types,
and contain valid values according to the project specifications.
"""
import os
import sys
import json
import pandas as pd
from pathlib import Path
from typing import Any, Dict, List, Set

# Add parent directory to path for imports
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from config import get_path, ensure_dirs


def load_json_safe(filepath: str) -> Dict[str, Any]:
    """Load a JSON file safely, returning None if it fails."""
    try:
        with open(filepath, 'r') as f:
            return json.load(f)
    except (FileNotFoundError, json.JSONDecodeError) as e:
        print(f"Error loading JSON file {filepath}: {e}")
        return None


def validate_model_results_json(filepath: str) -> bool:
    """
    Validate the schema of data/processed/model_results.json.

    Required fields:
    - model_type: str
    - r2: float
    - adjusted_r2: float
    - rmse: float
    - optimal_lambda: float (for LASSO)
    - permutation_p_value: float
    - bonferroni_significant: bool
    - bands: dict with delta, theta, alpha, low_beta, high_beta, gamma coefficients
    - cross_validation_folds: int
    - sample_size: int
    - mdes: float
    - hypothesis_supported: bool

    Returns True if valid, False otherwise.
    """
    print(f"Validating model results JSON: {filepath}")

    if not os.path.exists(filepath):
        print(f"ERROR: File not found: {filepath}")
        return False

    data = load_json_safe(filepath)
    if data is None:
        print("ERROR: Failed to parse JSON file")
        return False

    required_fields = {
        'model_type': str,
        'r2': (int, float),
        'adjusted_r2': (int, float),
        'rmse': (int, float),
        'optimal_lambda': (int, float),
        'permutation_p_value': (int, float),
        'bonferroni_significant': bool,
        'bands': dict,
        'cross_validation_folds': int,
        'sample_size': int,
        'mdes': (int, float),
        'hypothesis_supported': bool
    }

    errors = []

    # Check required fields
    for field, expected_type in required_fields.items():
        if field not in data:
            errors.append(f"Missing required field: {field}")
        elif not isinstance(data[field], expected_type):
            errors.append(f"Field '{field}' has wrong type. Expected {expected_type}, got {type(data[field])}")

    # Validate bands structure
    if 'bands' in data and isinstance(data['bands'], dict):
        required_bands = ['delta', 'theta', 'alpha', 'low_beta', 'high_beta', 'gamma']
        for band in required_bands:
            if band not in data['bands']:
                errors.append(f"Missing band coefficient: {band}")
            elif not isinstance(data['bands'][band], (int, float)):
                errors.append(f"Band coefficient '{band}' is not a number")

    # Validate numeric ranges
    if 'r2' in data and isinstance(data['r2'], (int, float)):
        if not (-1 <= data['r2'] <= 1):
            errors.append(f"R² value {data['r2']} is out of valid range [-1, 1]")

    if 'permutation_p_value' in data and isinstance(data['permutation_p_value'], (int, float)):
        if not (0 <= data['permutation_p_value'] <= 1):
            errors.append(f"Permutation p-value {data['permutation_p_value']} is out of valid range [0, 1]")

    if 'hypothesis_supported' in data:
        if not isinstance(data['hypothesis_supported'], bool):
            errors.append("hypothesis_supported must be a boolean")

    if errors:
        print("Validation errors found:")
        for error in errors:
            print(f"  - {error}")
        return False

    print("Model results JSON validation: PASSED")
    return True


def validate_correlations_csv(filepath: str) -> bool:
    """
    Validate the schema of data/processed/correlations.csv.

    Required columns:
    - band: str (one of delta, theta, alpha, low_beta, high_beta, gamma)
    - correlation: float
    - p_value: float
    - bonferroni_corrected_p: float
    - significant: bool
    - sample_size: int

    Returns True if valid, False otherwise.
    """
    print(f"Validating correlations CSV: {filepath}")

    if not os.path.exists(filepath):
        print(f"ERROR: File not found: {filepath}")
        return False

    try:
        df = pd.read_csv(filepath)
    except Exception as e:
        print(f"ERROR: Failed to read CSV file: {e}")
        return False

    required_columns = ['band', 'correlation', 'p_value', 'bonferroni_corrected_p', 'significant', 'sample_size']
    errors = []

    # Check required columns
    missing_cols = [col for col in required_columns if col not in df.columns]
    if missing_cols:
        errors.append(f"Missing required columns: {missing_cols}")

    if errors:
        print("Validation errors found:")
        for error in errors:
            print(f"  - {error}")
        return False

    # Validate band values
    valid_bands = ['delta', 'theta', 'alpha', 'low_beta', 'high_beta', 'gamma']
    invalid_bands = [b for b in df['band'].unique() if b not in valid_bands]
    if invalid_bands:
        errors.append(f"Invalid band values found: {invalid_bands}")

    # Validate numeric ranges
    if 'correlation' in df.columns:
        invalid_corr = df[(df['correlation'] < -1) | (df['correlation'] > 1)]
        if len(invalid_corr) > 0:
            errors.append(f"Found {len(invalid_corr)} rows with correlation outside [-1, 1]")

    if 'p_value' in df.columns:
        invalid_p = df[(df['p_value'] < 0) | (df['p_value'] > 1)]
        if len(invalid_p) > 0:
            errors.append(f"Found {len(invalid_p)} rows with p-value outside [0, 1]")

    if 'bonferroni_corrected_p' in df.columns:
        invalid_bp = df[(df['bonferroni_corrected_p'] < 0) | (df['bonferroni_corrected_p'] > 1)]
        if len(invalid_bp) > 0:
            errors.append(f"Found {len(invalid_bp)} rows with bonferroni_corrected_p outside [0, 1]")

    if 'significant' in df.columns:
        if not df['significant'].isin([True, False, 'True', 'False']).all():
            errors.append("significant column contains invalid boolean values")

    if 'sample_size' in df.columns:
        if not df['sample_size'].apply(lambda x: isinstance(x, (int, float)) and x > 0).all():
            errors.append("sample_size column contains invalid values")

    if errors:
        print("Validation errors found:")
        for error in errors:
            print(f"  - {error}")
        return False

    print("Correlations CSV validation: PASSED")
    return True


def main():
    """Main entry point for validation."""
    print("=" * 60)
    print("Task T035b: Schema Validation for Model Results and Correlations")
    print("=" * 60)

    # Define paths
    model_results_path = get_path("data/processed/model_results.json")
    correlations_path = get_path("data/processed/correlations.csv")

    # Ensure output directory exists for logs
    log_dir = get_path("data/processed")
    ensure_dirs(log_dir)

    validation_results = {
        'model_results_json': False,
        'correlations_csv': False,
        'overall': False
    }

    # Validate model results JSON
    validation_results['model_results_json'] = validate_model_results_json(model_results_path)

    # Validate correlations CSV
    validation_results['correlations_csv'] = validate_correlations_csv(correlations_path)

    # Determine overall result
    validation_results['overall'] = (
        validation_results['model_results_json'] and
        validation_results['correlations_csv']
    )

    # Write validation log
    log_path = os.path.join(log_dir, 'validation_log.json')
    with open(log_path, 'w') as f:
        json.dump(validation_results, f, indent=2)

    print("=" * 60)
    print(f"Overall Validation Result: {'PASSED' if validation_results['overall'] else 'FAILED'}")
    print(f"Validation log written to: {log_path}")
    print("=" * 60)

    # Exit with appropriate code
    sys.exit(0 if validation_results['overall'] else 1)


if __name__ == '__main__':
    main()
