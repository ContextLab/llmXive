"""
T026d: Robustness Modeling Script

Re-runs the modeling pipeline (T017/T04_modeling.py logic) on robustness features
generated by T026c (no-ica and window-2s variants) to generate robustness metrics.

Inputs:
  - data/interim/robustness/no_ica/features.csv
  - data/interim/robustness/window_2s/features.csv

Output:
  - data/interim/robustness/robustness_report.csv
    Columns: condition, r_squared, rmse, alpha_power_mean, alpha_power_diff_pct
"""
import os
import sys
import argparse
import json
import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.model_selection import KFold
from sklearn.metrics import r2_score, mean_squared_error
from pathlib import Path

# Add project root to path for imports if running as script
project_root = Path(__file__).parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from config import get_path, get_cv_folds, get_seed

def load_features(path_str: str) -> pd.DataFrame:
    """Load features from a robustness CSV path."""
    p = Path(path_str)
    if not p.exists():
        raise FileNotFoundError(f"Robustness features file not found: {p}")
    df = pd.read_csv(p)
    return df

def prepare_data(df: pd.DataFrame, feature_cols: list) -> tuple:
    """
    Prepare X (features) and y (target) from the dataframe.
    Returns X, y, and participant_ids.
    """
    if 'median_rt' not in df.columns:
        raise ValueError("Features file must contain 'median_rt' column.")
    
    # Filter to valid rows (no nulls in features or target)
    valid_cols = feature_cols + ['median_rt']
    clean_df = df[valid_cols].dropna()
    
    if clean_df.empty:
        raise ValueError("No valid data remaining after dropping nulls.")

    X = clean_df[feature_cols].values
    y = clean_df['median_rt'].values
    ids = clean_df['participant_id'].values
    return X, y, ids

def fit_model_with_cv(X: np.ndarray, y: np.ndarray, n_folds: int, seed: int) -> tuple:
    """
    Fit Linear Regression with K-Fold Cross Validation.
    Returns mean R2, mean RMSE, and the trained model on full data.
    """
    kf = KFold(n_splits=n_folds, shuffle=True, random_state=seed)
    r2_scores = []
    rmse_scores = []
    
    model = LinearRegression()
    
    for train_idx, test_idx in kf.split(X):
        X_train, X_test = X[train_idx], X[test_idx]
        y_train, y_test = y[train_idx], y[test_idx]
        
        model.fit(X_train, y_train)
        y_pred = model.predict(X_test)
        
        r2_scores.append(r2_score(y_test, y_pred))
        rmse_scores.append(np.sqrt(mean_squared_error(y_test, y_pred)))
    
    mean_r2 = np.mean(r2_scores)
    mean_rmse = np.mean(rmse_scores)
    
    # Retrain on full data for coefficient inspection if needed
    model.fit(X, y)
    
    return mean_r2, mean_rmse, model

def main():
    parser = argparse.ArgumentParser(description="T026d: Run robustness modeling")
    parser.add_argument("--no-ica-path", type=str, help="Path to no-ica features")
    parser.add_argument("--window-2s-path", type=str, help="Path to window-2s features")
    parser.add_argument("--output", type=str, help="Output robustness report path")
    args = parser.parse_args()

    # Default paths if not provided
    if not args.no_ica_path:
        args.no_ica_path = str(get_path("data/interim/robustness/no_ica/features.csv"))
    if not args.window_2s_path:
        args.window_2s_path = str(get_path("data/interim/robustness/window_2s/features.csv"))
    if not args.output:
        args.output = str(get_path("data/interim/robustness/robustness_report.csv"))

    # Ensure output directory exists
    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    conditions = [
        ("no_ica", args.no_ica_path),
        ("window_2s", args.window_2s_path)
    ]

    results = []
    primary_alpha_mean = None
    primary_r2 = None

    # Load primary features to establish baseline for comparison (if available)
    # We assume primary features are at standard location
    try:
        primary_features_path = str(get_path("data/processed/features.csv"))
        if os.path.exists(primary_features_path):
            primary_df = load_features(primary_features_path)
            # Identify alpha column (standard naming convention)
            alpha_col = 'alpha'
            if alpha_col not in primary_df.columns:
                # Try to find a column containing 'alpha'
                cols = [c for c in primary_df.columns if 'alpha' in c.lower()]
                if cols:
                    alpha_col = cols[0]
            
            if alpha_col in primary_df.columns:
                primary_alpha_mean = primary_df[alpha_col].mean()
            if 'median_rt' in primary_df.columns:
                # Calculate primary R2 for reference
                feature_cols = [c for c in primary_df.columns if c not in ['participant_id', 'median_rt']]
                if feature_cols:
                    X_p, y_p, _ = prepare_data(primary_df, feature_cols)
                    if len(X_p) > 1:
                        primary_r2, _, _ = fit_model_with_cv(X_p, y_p, get_cv_folds(), get_seed())
    except Exception as e:
        print(f"Warning: Could not load primary features for baseline comparison: {e}")

    for condition_name, path_str in conditions:
        print(f"Processing condition: {condition_name} from {path_str}")
        try:
            df = load_features(path_str)
            
            # Identify feature columns (exclude metadata)
            exclude_cols = ['participant_id', 'median_rt', 'n_trials', 'n_trials_excluded']
            feature_cols = [c for c in df.columns if c not in exclude_cols]
            
            if not feature_cols:
                print(f"  Error: No feature columns found in {path_str}")
                continue

            X, y, ids = prepare_data(df, feature_cols)
            
            if len(X) < 2:
                print(f"  Error: Insufficient data points ({len(X)}) for modeling in {condition_name}")
                continue

            r2, rmse, model = fit_model_with_cv(X, y, get_cv_folds(), get_seed())
            
            # Calculate alpha power mean for this condition
            alpha_col = 'alpha'
            if alpha_col not in df.columns:
                cols = [c for c in df.columns if 'alpha' in c.lower()]
                if cols:
                    alpha_col = cols[0]
            
            alpha_mean = df[alpha_col].mean() if alpha_col in df.columns else np.nan
            
            # Calculate percentage difference from primary
            alpha_diff_pct = np.nan
            if primary_alpha_mean is not None and not np.isnan(primary_alpha_mean):
                if primary_alpha_mean != 0:
                    alpha_diff_pct = ((alpha_mean - primary_alpha_mean) / primary_alpha_mean) * 100
                else:
                    alpha_diff_pct = np.nan

            results.append({
                'condition': condition_name,
                'r_squared': r2,
                'rmse': rmse,
                'alpha_power_mean': alpha_mean,
                'alpha_power_diff_pct': alpha_diff_pct,
                'n_samples': len(X)
            })
            
            print(f"  R2: {r2:.4f}, RMSE: {rmse:.4f}, Alpha Mean: {alpha_mean:.4f}")

        except Exception as e:
            print(f"  Error processing {condition_name}: {e}")
            import traceback
            traceback.print_exc()

    if not results:
        print("No results generated. Check input files.")
        # Write empty file with headers
        pd.DataFrame(columns=['condition', 'r_squared', 'rmse', 'alpha_power_mean', 'alpha_power_diff_pct']).to_csv(output_path, index=False)
        return

    # Create DataFrame and save
    report_df = pd.DataFrame(results)
    report_df.to_csv(output_path, index=False)
    print(f"Robustness report saved to: {output_path}")

if __name__ == "__main__":
    main()