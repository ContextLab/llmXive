"""
T018: Implement LASSO regression with lambda tuning to minimize RMSE.

This script loads the processed features, performs 5-fold cross-validated
LASSO regression tuning to find the optimal lambda (alpha) that minimizes
RMSE, and saves the results to data/processed/model_results.json.

Dependencies:
    - data/processed/features.csv (from T015)
    - data/interim/split_indices.json (from T017)
"""
import os
import sys
import json
import argparse
import numpy as np
import pandas as pd
from sklearn.linear_model import LassoCV
from sklearn.metrics import mean_squared_error, r2_score
from sklearn.preprocessing import StandardScaler
from config import get_path, ensure_dirs, get_seed

def load_features():
    """Load the processed features CSV."""
    path = get_path("data/processed/features.csv")
    if not os.path.exists(path):
        raise FileNotFoundError(f"Required input file not found: {path}")
    df = pd.read_csv(path)
    return df

def load_split_indices():
    """Load the split indices generated by T017."""
    path = get_path("data/interim/split_indices.json")
    if not os.path.exists(path):
        raise FileNotFoundError(f"Required input file not found: {path}")
    with open(path, 'r') as f:
        return json.load(f)

def prepare_data(df, split_indices):
    """
    Prepare X (features) and y (target) and apply splits.
    
    Returns:
      X_all, y_all, train_indices, test_indices
    """
    # Identify feature columns (exclude metadata columns)
    exclude_cols = ['participant_id', 'median_rt_ms']
    feature_cols = [c for c in df.columns if c not in exclude_cols]
    
    X = df[feature_cols].values
    y = df['median_rt_ms'].values
    
    # Convert split indices from string keys to integers if necessary
    train_indices = [int(i) for i in split_indices['train']]
    test_indices = [int(i) for i in split_indices['test']]
    
    return X, y, train_indices, test_indices

def fit_lasso_cv(X, y, n_folds=5):
    """
    Fit LASSO regression with cross-validation to find optimal alpha.
    
    Args:
        X: Feature matrix
        y: Target vector
        n_folds: Number of CV folds
        
    Returns:
        best_model: The fitted LassoCV model
        optimal_alpha: The alpha (lambda) that minimized CV error
        cv_mse: The mean CV MSE at optimal alpha
    """
    # Scale features for LASSO
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)
    
    # Define a range of alphas to test
    # LassoCV handles this internally if alphas=None, but we can provide a grid
    # to ensure we search a relevant range for RMSE minimization
    lasso_cv = LassoCV(
        alphas=None,  # Automatically generate a grid
        cv=n_folds,
        random_state=get_seed(),
        n_jobs=-1,
        max_iter=10000
    )
    
    lasso_cv.fit(X_scaled, y)
    
    optimal_alpha = lasso_cv.alpha_
    # Get the best CV score (MSE)
    best_cv_mse = lasso_cv.mse_path_.mean(axis=1).min()
    
    return lasso_cv, optimal_alpha, best_cv_mse, scaler

def evaluate_model(model, X_test, y_test, scaler):
    """
    Evaluate the model on the held-out test set.
    
    Returns:
        rmse: Root Mean Squared Error
        r2: R-squared score
        predictions: Predicted values
    """
    X_test_scaled = scaler.transform(X_test)
    predictions = model.predict(X_test_scaled)
    
    rmse = np.sqrt(mean_squared_error(y_test, predictions))
    r2 = r2_score(y_test, predictions)
    
    return rmse, r2, predictions

def save_results(results_dict):
    """Save results to data/processed/model_results.json."""
    output_dir = ensure_dirs("data/processed")
    output_path = os.path.join(output_dir, "model_results.json")
    
    # Load existing results if they exist (to append/merge)
    existing_results = {}
    if os.path.exists(output_path):
        with open(output_path, 'r') as f:
            try:
                existing_results = json.load(f)
            except json.JSONDecodeError:
                existing_results = {}
    
    # Merge new results
    existing_results['lasso'] = results_dict
    
    with open(output_path, 'w') as f:
        json.dump(existing_results, f, indent=2)
    
    print(f"Results saved to {output_path}")

def main():
    parser = argparse.ArgumentParser(description="LASSO Regression with Lambda Tuning")
    parser.parse_args()
    
    print("Loading features...")
    df = load_features()
    
    print("Loading split indices...")
    split_indices = load_split_indices()
    
    print("Preparing data...")
    X, y, train_indices, test_indices = prepare_data(df, split_indices)
    
    X_train = X[train_indices]
    y_train = y[train_indices]
    X_test = X[test_indices]
    y_test = y[test_indices]
    
    print(f"Training set size: {len(X_train)}")
    print(f"Test set size: {len(X_test)}")
    
    print("Fitting LASSO with CV...")
    model, optimal_alpha, cv_mse, scaler = fit_lasso_cv(X_train, y_train)
    
    print(f"Optimal alpha (lambda): {optimal_alpha:.6f}")
    print(f"Cross-validated MSE: {cv_mse:.6f}")
    
    print("Evaluating on test set...")
    rmse, r2, predictions = evaluate_model(model, X_test, y_test, scaler)
    
    print(f"Test RMSE: {rmse:.6f}")
    print(f"Test R²: {r2:.6f}")
    
    # Coefficients
    coef = model.coef_
    feature_names = [c for c in df.columns if c not in ['participant_id', 'median_rt_ms']]
    coef_dict = {name: float(val) for name, val in zip(feature_names, coef)}
    
    results = {
        "optimal_alpha": float(optimal_alpha),
        "cv_mse": float(cv_mse),
        "test_rmse": float(rmse),
        "test_r2": float(r2),
        "coefficients": coef_dict,
        "n_nonzero_coefs": int(np.sum(coef != 0)),
        "n_folds": 5
    }
    
    save_results(results)
    print("LASSO regression complete.")

if __name__ == "__main__":
    main()
