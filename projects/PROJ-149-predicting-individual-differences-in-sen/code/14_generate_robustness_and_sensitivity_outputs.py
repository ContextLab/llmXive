"""
T030: Generate robustness_report.csv and sensitivity_plot.png.

This script aggregates results from the robustness analysis (T026/T027)
and the sensitivity analysis (T028/T029) to produce the final artifacts
required for User Story 3.

Inputs:
  - data/interim/robustness/robustness_metrics.json (from T027)
  - data/interim/sensitivity/sensitivity_results.csv (from T029)

Outputs:
  - data/processed/robustness_report.csv
  - data/processed/sensitivity_plot.png
"""
import os
import sys
import argparse
import json
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from config import get_path, ensure_dirs, get_seed

def load_robustness_metrics(input_path: str) -> pd.DataFrame:
    """
    Load robustness metrics from the JSON file generated by T027.
    Expected structure: list of dicts with 'condition', 'r2', 'alpha_power_mean', etc.
    """
    if not os.path.exists(input_path):
        raise FileNotFoundError(f"Robustness metrics file not found: {input_path}")
    
    with open(input_path, 'r') as f:
        data = json.load(f)
    
    # Ensure it's a list of dicts
    if isinstance(data, dict):
        data = [data]
    
    df = pd.DataFrame(data)
    return df

def load_sensitivity_results(input_path: str) -> pd.DataFrame:
    """
    Load sensitivity results from the CSV generated by T029.
    Expected columns: 'threshold', 'significant_count', 'is_significant'
    """
    if not os.path.exists(input_path):
        raise FileNotFoundError(f"Sensitivity results file not found: {input_path}")
    
    df = pd.read_csv(input_path)
    return df

def generate_robustness_report(robustness_df: pd.DataFrame, output_path: str):
    """
    Generate the final robustness_report.csv.
    Ensures specific columns are present and formatted correctly.
    """
    required_cols = ['condition', 'r2', 'alpha_power_mean', 'r2_difference_pct']
    
    # Check if columns exist, add defaults if missing (shouldn't happen if T027 ran correctly)
    for col in required_cols:
        if col not in robustness_df.columns:
            robustness_df[col] = np.nan

    # Select and rename columns for final report if necessary
    report_cols = ['condition', 'r2', 'alpha_power_mean', 'r2_difference_pct']
    report_df = robustness_df[report_cols].copy()
    
    # Sort by condition to ensure consistent output
    report_df = report_df.sort_values('condition')
    
    # Save to CSV
    report_df.to_csv(output_path, index=False)
    print(f"Generated robustness report: {output_path}")

def generate_sensitivity_plot(sensitivity_df: pd.DataFrame, output_path: str):
    """
    Generate the sensitivity_plot.png showing significant correlation counts
    across p-value thresholds.
    """
    # Ensure data is sorted by threshold
    sensitivity_df = sensitivity_df.sort_values('threshold')
    
    # Set style
    sns.set_theme(style="whitegrid")
    plt.figure(figsize=(10, 6))
    
    # Plot
    plt.plot(sensitivity_df['threshold'], sensitivity_df['significant_count'], 
             marker='o', linestyle='-', color='#2c7bb6', linewidth=2, markersize=8)
    
    # Highlight the critical threshold if available (last significant point)
    if 'is_significant' in sensitivity_df.columns:
        # Find the last threshold where is_significant is True
        significant_rows = sensitivity_df[sensitivity_df['is_significant'] == True]
        if not significant_rows.empty:
            last_sig = significant_rows.iloc[-1]
            plt.axvline(x=last_sig['threshold'], color='r', linestyle='--', 
                        label=f"Critical Threshold: {last_sig['threshold']:.2f}")
    
    plt.title('Sensitivity Analysis: Significant Correlations vs. P-value Threshold', fontsize=14)
    plt.xlabel('P-value Threshold', fontsize=12)
    plt.ylabel('Count of Significant Correlations', fontsize=12)
    plt.xticks(sensitivity_df['threshold']) # Show all thresholds
    plt.legend()
    
    plt.tight_layout()
    plt.savefig(output_path, dpi=150)
    plt.close()
    print(f"Generated sensitivity plot: {output_path}")

def main():
    parser = argparse.ArgumentParser(description="Generate T030 outputs: robustness report and sensitivity plot.")
    parser.add_argument('--robustness-input', type=str, 
                        default=str(get_path('data_interim_robustness') / 'robustness_metrics.json'),
                        help='Path to robustness metrics JSON')
    parser.add_argument('--sensitivity-input', type=str,
                        default=str(get_path('data_interim') / 'sensitivity' / 'sensitivity_results.csv'),
                        help='Path to sensitivity results CSV')
    parser.add_argument('--robustness-output', type=str,
                        default=str(get_path('data_processed') / 'robustness_report.csv'),
                        help='Path for robustness report CSV')
    parser.add_argument('--sensitivity-output', type=str,
                        default=str(get_path('data_processed') / 'sensitivity_plot.png'),
                        help='Path for sensitivity plot PNG')
    
    args = parser.parse_args()

    # Set seed for reproducibility in any random operations (though none expected here)
    set_global_seed()

    # Ensure output directories exist
    ensure_dirs([args.robustness_output, args.sensitivity_output])

    try:
        # 1. Load Robustness Data
        print("Loading robustness metrics...")
        robustness_df = load_robustness_metrics(args.robustness_input)
        
        # 2. Load Sensitivity Data
        print("Loading sensitivity results...")
        sensitivity_df = load_sensitivity_results(args.sensitivity_input)

        # 3. Generate Robustness Report
        print("Generating robustness report...")
        generate_robustness_report(robustness_df, args.robustness_output)

        # 4. Generate Sensitivity Plot
        print("Generating sensitivity plot...")
        generate_sensitivity_plot(sensitivity_df, args.sensitivity_output)

        print("T030 completed successfully.")

    except FileNotFoundError as e:
        print(f"Error: Missing required input file. {e}")
        print("Ensure T027 (robustness) and T029 (sensitivity) have completed successfully.")
        sys.exit(1)
    except Exception as e:
        print(f"Error during execution: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()