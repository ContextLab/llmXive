"""
Contract test for T024a: Verify schema of data/interim/poly_features.csv
"""
import os
import sys
import pytest
import pandas as pd
from pathlib import Path

# Add project root to path
project_root = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(project_root))

from config import get_path

REQUIRED_COLUMNS = [
    'participant_id', 'median_rt', 
    'delta_rel', 'theta_rel', 'alpha_rel', 
    'low_beta_rel', 'high_beta_rel', 'gamma_rel',
    'alpha_rel_sq', 'low_beta_rel_sq', 'high_beta_rel_sq',
    'alpha_rel_low_beta_rel_interaction', 'alpha_rel_high_beta_rel_interaction'
]

def test_poly_features_schema_exists():
    """Test that the poly_features.csv file exists."""
    path = get_path("interim", "poly_features.csv")
    assert os.path.exists(path), f"File not found: {path}"

def test_poly_features_schema_columns():
    """Test that the file has all required columns."""
    path = get_path("interim", "poly_features.csv")
    df = pd.read_csv(path)
    
    missing = set(REQUIRED_COLUMNS) - set(df.columns)
    assert not missing, f"Missing required columns: {missing}"
    
    # Check for unexpected extra columns (optional, but good for strictness)
    # We allow extra columns if they are generated by degree > 2, but strict check for degree 2
    # For now, just ensure required are present.

def test_poly_features_schema_no_nulls():
    """Test that there are no null values in critical columns."""
    path = get_path("interim", "poly_features.csv")
    df = pd.read_csv(path)
    
    # Check critical columns for nulls
    critical_cols = ['participant_id', 'median_rt', 'alpha_rel_sq']
    for col in critical_cols:
        if col in df.columns:
            assert not df[col].isnull().any(), f"Null values found in column: {col}"

def test_poly_features_schema_types():
    """Test that numeric columns are numeric."""
    path = get_path("interim", "poly_features.csv")
    df = pd.read_csv(path)
    
    numeric_cols = ['median_rt', 'alpha_rel_sq', 'low_beta_rel_sq', 'high_beta_rel_sq']
    for col in numeric_cols:
        if col in df.columns:
            assert pd.api.types.is_numeric_dtype(df[col]), f"Column {col} is not numeric"
