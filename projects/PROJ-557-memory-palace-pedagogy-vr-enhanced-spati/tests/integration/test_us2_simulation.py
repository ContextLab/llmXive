"""
Integration test for User Story 2: Simulated Adaptive Text Rendering.

This test validates the full US-2 simulation pipeline on the derived data
generated by previous tasks (T015 for CLI, T021a/b for text data).

It verifies:
1. Successful loading of CLI time series and passage data.
2. Correct application of the `select_text_version` logic (High CLI -> Simplified, else Original).
3. Graceful degradation when simplified text is missing (defaults to original).
4. Generation of the final `adaptation_labels.parquet` artifact.
5. Statistical sanity checks on the output (e.g., proportion of adaptive labels).
"""
