def compute_file_hash(file_path: Path) -> str:
    """Compute SHA-256 hash of a file for integrity verification."""
    sha256_hash = hashlib.sha256()
    try:
        with open(file_path, "rb") as f:
            for byte_block in iter(lambda: f.read(4096), b""):
                sha256_hash.update(byte_block)
        return sha256_hash.hexdigest()
    except FileNotFoundError:
        logger.error(f"File not found for hashing: {file_path}")
        return "ERROR_FILE_NOT_FOUND"
    except Exception as e:
        logger.error(f"Error hashing file {file_path}: {e}")
        return f"ERROR_HASHING_{str(e)}"


def export_raw_data(
    source_dir: Path,
    target_dir: Path,
    chunk_id: str,
    dry_run: bool = False
) -> Dict[str, Any]:
    """
    Export labeled video frames and metadata to the target raw data directory.
    
    Args:
        source_dir: Directory containing generated/labelled chunk data (JSONL + video).
        target_dir: Target directory under data/raw/ for the final dataset.
        chunk_id: Unique identifier for this chunk (e.g., "chunk_001").
        dry_run: If True, perform operations in memory only (for testing).
    
    Returns:
        Dictionary containing export statistics and file paths.
    """
    stats = {
        "chunk_id": chunk_id,
        "source": str(source_dir),
        "target": str(target_dir),
        "frames_exported": 0,
        "labels_exported": 0,
        "files_created": [],
        "timestamp": datetime.utcnow().isoformat(),
        "success": False
    }

    logger.info(f"Starting export for chunk {chunk_id} from {source_dir} to {target_dir}")

    if not source_dir.exists():
        logger.error(f"Source directory does not exist: {source_dir}")
        return stats

    if not dry_run:
        target_dir.mkdir(parents=True, exist_ok=True)

    # Locate the labeled frames file (generated by visual_labeler.py)
    labeled_file = source_dir / f"{chunk_id}_labeled_frames.jsonl"
    if not labeled_file.exists():
        logger.error(f"Labeled frames file not found: {labeled_file}")
        return stats

    # Export the labeled frames JSONL
    target_jsonl = target_dir / f"{chunk_id}_frames.jsonl"
    
    try:
        with open(labeled_file, "r") as src, open(target_jsonl, "w") as dst:
            for line in src:
                data = json.loads(line)
                # Ensure schema compliance (basic validation)
                if "frame_id" in data and "label" in data:
                    dst.write(json.dumps(data) + "\n")
                    stats["frames_exported"] += 1
                    if data["label"] in ["critical", "silence"]:
                        stats["labels_exported"] += 1
        
        stats["files_created"].append(str(target_jsonl))
        logger.info(f"Exported {stats['frames_exported']} frames to {target_jsonl}")
        
    except Exception as e:
        logger.error(f"Failed to export frames for {chunk_id}: {e}")
        return stats

    # Copy any associated metadata or video snippets if present
    # (Assuming generator.py might have created temporary video files per chunk)
    video_src = source_dir / f"{chunk_id}_video.mp4"
    if video_src.exists():
        if not dry_run:
            video_dst = target_dir / f"{chunk_id}_video.mp4"
            shutil.copy2(video_src, video_dst)
            stats["files_created"].append(str(video_dst))
        else:
            logger.info(f"[DRY RUN] Would copy video: {video_src} -> {target_dir}")

    stats["success"] = True
    return stats


def generate_manifest(
    raw_data_dir: Path,
    output_path: Path,
    total_duration_seconds: Optional[float] = None
) -> Dict[str, Any]:
    """
    Generate the manifest.jsonl file aggregating all exported chunks.
    
    This function scans the raw data directory for all exported JSONL files,
    computes metadata (hashes, counts, durations), and writes a consolidated
    manifest file.
    
    Args:
        raw_data_dir: Path to data/raw/ directory containing chunk exports.
        output_path: Path for the final manifest.jsonl file.
        total_duration_seconds: Pre-calculated total duration (from verify_volume).
                               If None, will attempt to calculate from metadata.
    
    Returns:
        Dictionary containing manifest generation stats.
    """
    logger.info(f"Generating manifest at {output_path}")
    
    if not raw_data_dir.exists():
        logger.error(f"Raw data directory does not exist: {raw_data_dir}")
        return {"success": False, "error": "Directory not found"}

    manifest_entries = []
    total_frames = 0
    total_critical = 0
    total_silence = 0
    file_hashes = {}

    # Scan for all chunk JSONL files
    jsonl_files = sorted(raw_data_dir.glob("*_frames.jsonl"))
    
    if not jsonl_files:
        logger.warning(f"No chunk files found in {raw_data_dir}")
        # Even if empty, we might want an empty manifest or error out?
        # Let's create an empty manifest structure for now.
        pass

    for jsonl_file in jsonl_files:
        chunk_id = jsonl_file.stem.replace("_frames", "")
        frame_count = 0
        critical_count = 0
        silence_count = 0
        file_hash = compute_file_hash(jsonl_file)
        
        try:
            with open(jsonl_file, "r") as f:
                for line in f:
                    data = json.loads(line)
                    frame_count += 1
                    label = data.get("label", "unknown")
                    if label == "critical":
                        critical_count += 1
                    elif label == "silence":
                        silence_count += 1
        except Exception as e:
            logger.error(f"Error processing {jsonl_file}: {e}")
            continue

        entry = {
            "chunk_id": chunk_id,
            "file_path": str(jsonl_file),
            "frame_count": frame_count,
            "critical_count": critical_count,
            "silence_count": silence_count,
            "sha256": file_hash,
            "created_at": datetime.utcnow().isoformat()
        }
        manifest_entries.append(entry)
        
        total_frames += frame_count
        total_critical += critical_count
        total_silence += silence_count
        file_hashes[chunk_id] = file_hash

    # Construct the final manifest object
    manifest_data = {
        "version": "1.0",
        "created_at": datetime.utcnow().isoformat(),
        "total_chunks": len(manifest_entries),
        "total_frames": total_frames,
        "total_critical_labels": total_critical,
        "total_silence_labels": total_silence,
        "total_duration_seconds": total_duration_seconds,
        "chunks": manifest_entries
    }

    # Validate structure
    if not validate_manifest_structure(manifest_data):
        logger.warning("Manifest structure validation failed, but proceeding to write.")

    # Write manifest
    output_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        with open(output_path, "w") as f:
            json.dump(manifest_data, f, indent=2)
        logger.info(f"Manifest written to {output_path}")
        
        return {
            "success": True,
            "path": str(output_path),
            "total_frames": total_frames,
            "chunks": len(manifest_entries)
        }
    except Exception as e:
        logger.error(f"Failed to write manifest: {e}")
        return {"success": False, "error": str(e)}


def main():
    """
    Main entry point for the export pipeline.
    
    Usage:
        python -m src.data_synthesis.exporter --source <path> --target <path>
    """
    import argparse

    parser = argparse.ArgumentParser(description="Export labeled data to raw format and generate manifest.")
    parser.add_argument("--source", type=str, required=True, help="Source directory containing labeled chunks.")
    parser.add_argument("--target", type=str, required=True, help="Target raw data directory (e.g., data/raw).")
    parser.add_argument("--manifest", type=str, default="data/manifest.jsonl", help="Output path for manifest.jsonl.")
    parser.add_argument("--dry-run", action="store_true", help="Do not write files, just log actions.")
    parser.add_argument("--chunk", type=str, default=None, help="Process only a specific chunk ID if provided.")
    
    args = parser.parse_args()

    source_path = Path(args.source)
    target_path = Path(args.target)
    manifest_path = Path(args.manifest)

    if not args.dry_run:
        logger.info(f"Starting export to {target_path}")
    else:
        logger.warning("Running in DRY RUN mode")

    # Step 1: Export individual chunks
    # We assume the source directory contains subdirectories or files named by chunk_id
    # e.g., source/chunk_001_labeled_frames.jsonl
    
    export_stats = []
    
    # Find all labeled files in source
    labeled_files = list(source_path.glob("*_labeled_frames.jsonl"))
    
    if not labeled_files:
        logger.error(f"No labeled frames found in {source_path}")
        return 1

    for labeled_file in labeled_files:
        chunk_id = labeled_file.stem.replace("_labeled_frames", "")
        
        # Skip if specific chunk requested and this isn't it
        if args.chunk and chunk_id != args.chunk:
            continue

        chunk_stats = export_raw_data(
            source_dir=source_path,
            target_dir=target_path,
            chunk_id=chunk_id,
            dry_run=args.dry_run
        )
        export_stats.append(chunk_stats)

    # Step 2: Verify total volume if possible
    # We try to load a temporary manifest or estimate from stats if verify_volume is available
    # For now, we pass None to generate_manifest and let it calculate from the new files
    # OR if we have a pre-existing manifest from verify_volume, we could use that.
    # Since T013a runs verify_volume, we assume the data exists.
    
    total_duration = None
    # Attempt to load a manifest if one was created by verify_volume in a temp location
    # But verify_volume usually just reads the generator output. 
    # We will rely on generate_manifest to count frames and let downstream users handle duration if not explicit.
    # However, the task requires manifest.jsonl.
    
    manifest_result = generate_manifest(
        raw_data_dir=target_path,
        output_path=manifest_path,
        total_duration_seconds=total_duration
    )

    if not manifest_result.get("success"):
        logger.error("Manifest generation failed.")
        return 1

    logger.info("Export and manifest generation completed successfully.")
    return 0


if __name__ == "__main__":
    exit(main())
