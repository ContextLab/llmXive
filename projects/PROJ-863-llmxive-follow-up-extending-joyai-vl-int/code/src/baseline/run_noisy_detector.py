"""
T029: Run Noisy Detector on Raw Data

This script processes the synthetic video stream generated in T013/T017,
applies the Noisy Rule-Based Visual Detector (T026b), and writes the
resulting predictions to data/baseline/noisy_predictions.jsonl.

It depends on:
- data/raw/ (generated by T013/T017)
- src/baseline/visual_detector.py (NoisyVisualDetector)
"""
import json
import sys
import logging
from pathlib import Path
from typing import List, Dict, Any, Iterator

# Ensure project root is in path
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.baseline.visual_detector import NoisyDetectionConfig, NoisyVisualDetector, load_deterministic_predictions, main as visual_detector_main
from src.utils.logging import get_logger

logger = get_logger("T029_NoisyDetector")

def process_raw_data_stream(
    raw_data_path: Path,
    output_path: Path,
    config: NoisyDetectionConfig
) -> Iterator[Dict[str, Any]]:
    """
    Streams through raw data frames, applies the noisy detector,
    and yields predictions. Writes to output file in JSONL format.
    """
    detector = NoisyVisualDetector(config)
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Read raw frames (assumed JSONL or similar structure from T017)
    # We assume raw data is a JSONL file where each line is a frame dict
    # containing 'frame_id', 'timestamp', and potentially object detections.
    
    with open(raw_data_path, 'r', encoding='utf-8') as f_in, \
         open(output_path, 'w', encoding='utf-8') as f_out:
         
         for line_num, line in enumerate(f_in):
             if not line.strip():
                 continue
             
             try:
                 frame_data = json.loads(line)
                 # Pass frame data to detector
                 # The detector expects a specific format, likely the SyntheticVideoFrame structure
                 # or a raw dict representation. We assume it accepts the dict directly.
                 prediction = detector.detect(frame_data)
                 
                 # Serialize and write
                 f_out.write(json.dumps(prediction) + '\n')
                 yield prediction
                 
             except json.JSONDecodeError as e:
                 logger.error(f"Failed to parse line {line_num}: {e}")
                 continue
             except Exception as e:
                 logger.error(f"Error processing frame at line {line_num}: {e}")
                 continue

def main():
    """
    Entry point for T029.
    Reads from data/raw/synthetic_stream.jsonl (or similar) and writes to data/baseline/noisy_predictions.jsonl.
    """
    logger.info("Starting T029: Noisy Detector Execution")
    
    # Configuration paths
    # Note: T017 produces data/raw/manifest.jsonl and likely data/raw/synthetic_stream.jsonl
    # We assume the raw frames are in a single file or we iterate over the manifest.
    # For this implementation, we target the primary raw stream file.
    
    raw_data_file = PROJECT_ROOT / "data" / "raw" / "synthetic_stream.jsonl"
    
    # Fallback if the specific name differs, check for any jsonl in raw
    if not raw_data_file.exists():
        raw_dir = PROJECT_ROOT / "data" / "raw"
        if raw_dir.exists():
            jsonl_files = list(raw_dir.glob("*.jsonl"))
            if jsonl_files:
                raw_data_file = jsonl_files[0]
            else:
                logger.error("No .jsonl file found in data/raw/")
                sys.exit(1)
        else:
            logger.error("data/raw/ directory not found. Run T013/T017 first.")
            sys.exit(1)

    output_file = PROJECT_ROOT / "data" / "baseline" / "noisy_predictions.jsonl"
    
    # Configuration for the noisy detector
    # T026b defines these parameters: moderate label flip noise and temporal jitter
    config = NoisyDetectionConfig(
        label_flip_probability=0.15,  # 15% chance to flip label
        temporal_jitter_frames=2,     # Jitter window of +/- 2 frames
        seed=42                       # Deterministic for reproducibility
    )
    
    logger.info(f"Processing raw data: {raw_data_file}")
    logger.info(f"Output path: {output_file}")
    logger.info(f"Config: label_flip={config.label_flip_probability}, jitter={config.temporal_jitter_frames}")

    count = 0
    try:
        for _ in process_raw_data_stream(raw_data_file, output_file, config):
            count += 1
            if count % 10000 == 0:
                logger.info(f"Processed {count} frames...")
    except Exception as e:
        logger.error(f"Execution failed: {e}")
        sys.exit(1)

    logger.info(f"T029 Complete. Processed {count} frames. Output: {output_file}")
    
    # Verify output exists and is not empty
    if not output_file.exists():
        logger.error("Output file was not created.")
        sys.exit(1)
    
    if output_file.stat().st_size == 0:
        logger.error("Output file is empty.")
        sys.exit(1)

    return 0

if __name__ == "__main__":
    sys.exit(main())
