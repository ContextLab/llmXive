"""
T027 Implementation: Run Deterministic Detector on Raw Data.

This script executes the deterministic rule-based visual detector on the
synthetic dataset generated in Phase 3 (User Story 1) and produces the
baseline predictions file required for Phase 6 analysis.

Input:  data/raw/*.jsonl (Generated by T013/T017)
Output: data/baseline/deterministic_predictions.jsonl
"""
import json
import sys
import logging
from pathlib import Path
from typing import List, Dict, Any, Iterator

# Add project root to path for imports
project_root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(project_root))

from src.baseline.deterministic_detector import DeterministicVisualDetector, load_raw_frames
from src.utils.logging import get_logger

# Configure logging
logger = get_logger("T027_DeterministicRun")

def process_raw_data_stream(raw_dir: Path) -> Iterator[Dict[str, Any]]:
    """
    Iterates over all JSONL files in the raw data directory.
    Yields frame dictionaries one by one to support streaming processing.
    """
    if not raw_dir.exists():
        raise FileNotFoundError(f"Raw data directory not found: {raw_dir}")
    
    jsonl_files = sorted(raw_dir.glob("*.jsonl"))
    if not jsonl_files:
        raise FileNotFoundError(f"No .jsonl files found in {raw_dir}")

    logger.info(f"Found {len(jsonl_files)} raw data files to process.")

    for file_path in jsonl_files:
        logger.debug(f"Processing file: {file_path.name}")
        with open(file_path, 'r', encoding='utf-8') as f:
            for line_num, line in enumerate(f, 1):
                line = line.strip()
                if not line:
                    continue
                try:
                    frame_data = json.loads(line)
                    yield frame_data
                except json.JSONDecodeError as e:
                    logger.warning(f"Skipping invalid JSON at {file_path}:{line_num} - {e}")
                    continue

def main():
    # Define paths relative to project root
    raw_data_dir = project_root / "data" / "raw"
    output_dir = project_root / "data" / "baseline"
    output_file = output_dir / "deterministic_predictions.jsonl"

    # Ensure output directory exists
    output_dir.mkdir(parents=True, exist_ok=True)

    logger.info(f"Starting Deterministic Detector run.")
    logger.info(f"Input: {raw_data_dir}")
    logger.info(f"Output: {output_file}")

    # Initialize the detector
    # The deterministic detector uses strict visual thresholds (no noise)
    detector = DeterministicVisualDetector()

    processed_count = 0
    critical_count = 0

    try:
        with open(output_file, 'w', encoding='utf-8') as out_f:
            for frame in process_raw_data_stream(raw_data_dir):
                # Run detection
                # The detector returns a prediction object with label and metadata
                prediction = detector.detect(frame)
                
                # Convert prediction to dict for JSON serialization
                # Ensure we preserve the original frame ID for alignment
                result = {
                    "frame_id": frame.get("frame_id"),
                    "timestamp_ms": frame.get("timestamp_ms"),
                    "label": prediction.label,
                    "confidence": prediction.confidence,
                    "reason": prediction.reason,
                    "metadata": prediction.metadata
                }

                out_f.write(json.dumps(result) + "\n")
                processed_count += 1

                if prediction.label == "critical":
                    critical_count += 1

                # Log progress every 10,000 frames
                if processed_count % 10000 == 0:
                    logger.info(f"Processed {processed_count} frames...")

        logger.info(f"Detection complete.")
        logger.info(f"Total frames processed: {processed_count}")
        logger.info(f"Critical events detected: {critical_count}")
        logger.info(f"Output written to: {output_file}")

    except Exception as e:
        logger.error(f"Fatal error during detection: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()
