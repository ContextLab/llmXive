"""
Save generated synthetic data to data/synthetic/ with metadata flags.

This script loads the synthetic datasets generated by generate_data.py,
validates them, and saves them to the data/synthetic/ directory with
explicit "Simulation-based" metadata flags.
"""

import os
import sys
import json
import logging
import pandas as pd
from datetime import datetime
from typing import Dict, Any, List

# Import from sibling modules using the provided API surface
from generate_data import load_protocol, generate_synthetic_datasets
from logging_config import setup_logging

# Configure logging
logger = setup_logging()

def ensure_directory_exists(directory_path: str) -> None:
    """Ensure the target directory exists, creating it if necessary."""
    if not os.path.exists(directory_path):
        os.makedirs(directory_path)
        logger.info(f"Created directory: {directory_path}")

def add_simulation_metadata(df: pd.DataFrame, scenario_name: str, 
                             protocol_params: Dict[str, Any]) -> pd.DataFrame:
    """
    Add simulation metadata to the dataframe.
    
    Args:
        df: The dataframe to annotate
        scenario_name: Name of the scenario (e.g., 'positive_effect', 'null_effect')
        protocol_params: Parameters from the protocol.yaml
    
    Returns:
        DataFrame with added metadata columns
    """
    # Create a metadata dictionary
    metadata = {
        "data_source": "Simulation-based",
        "generation_timestamp": datetime.now().isoformat(),
        "scenario": scenario_name,
        "protocol_file": "data/protocols/protocol.yaml",
        "effect_size_d": protocol_params.get('effect_sizes', {}).get(scenario_name, 'unknown'),
        "sample_size": protocol_params.get('N', 200),
        "icc": protocol_params.get('ICC', 0.3)
    }
    
    # Add metadata as columns for traceability
    df['simulation_source'] = metadata["data_source"]
    df['simulation_scenario'] = metadata["scenario"]
    df['simulation_timestamp'] = metadata["generation_timestamp"]
    
    logger.info(f"Added simulation metadata to {scenario_name} dataset")
    return df

def save_synthetic_datasets(output_dir: str = "data/synthetic/", 
                             protocol_path: str = "data/protocols/protocol.yaml") -> List[str]:
    """
    Generate and save synthetic datasets with simulation metadata.
    
    Args:
        output_dir: Directory to save the synthetic data files
        protocol_path: Path to the protocol.yaml file
    
    Returns:
        List of paths to the saved files
    """
    ensure_directory_exists(output_dir)
    
    # Load protocol parameters
    protocol = load_protocol(protocol_path)
    logger.info(f"Loaded protocol from {protocol_path}")
    
    # Generate synthetic datasets
    datasets = generate_synthetic_datasets(protocol)
    
    saved_files = []
    
    for scenario_name, df in datasets.items():
        # Add simulation metadata
        df_with_metadata = add_simulation_metadata(df, scenario_name, protocol)
        
        # Validate required columns before saving
        required_cols = ['condition', 'recall', 'bizarreness', 'participant_id']
        missing_cols = [col for col in required_cols if col not in df_with_metadata.columns]
        
        if missing_cols:
            logger.error(f"Missing required columns in {scenario_name}: {missing_cols}")
            raise ValueError(f"Missing required columns: {missing_cols}")
        
        # Save to CSV
        filename = f"synthetic_{scenario_name}.csv"
        filepath = os.path.join(output_dir, filename)
        
        df_with_metadata.to_csv(filepath, index=False)
        saved_files.append(filepath)
        
        logger.info(f"Saved synthetic dataset to {filepath} "
                   f"(rows={len(df_with_metadata)}, columns={len(df_with_metadata.columns)})")
    
    # Save metadata file
    metadata_file = os.path.join(output_dir, "synthetic_metadata.json")
    metadata = {
        "generation_timestamp": datetime.now().isoformat(),
        "data_source": "Simulation-based",
        "protocol_used": protocol_path,
        "datasets": [
            {
                "filename": os.path.basename(f),
                "scenario": os.path.basename(f).replace("synthetic_", "").replace(".csv", ""),
                "description": f"Synthetic data for {os.path.basename(f).replace('synthetic_', '').replace('.csv', '')} scenario"
            }
            for f in saved_files
        ]
    }
    
    with open(metadata_file, 'w') as f:
        json.dump(metadata, f, indent=2)
    
    logger.info(f"Saved metadata to {metadata_file}")
    
    return saved_files

def main():
    """Main entry point for saving synthetic data."""
    logger.info("Starting synthetic data save process...")
    
    try:
        saved_files = save_synthetic_datasets()
        
        logger.info(f"Successfully saved {len(saved_files)} synthetic datasets:")
        for filepath in saved_files:
            logger.info(f"  - {filepath}")
        
        logger.info("Synthetic data save process completed successfully.")
        return 0
        
    except Exception as e:
        logger.error(f"Failed to save synthetic data: {str(e)}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())
