def generate_sensitivity_report(sensitivity_data: pd.DataFrame, output_path: Path) -> None:
    """
    Generate the sensitivity report CSV with schema: threshold, fpr, fnr, auc, model_id.
    
    Args:
        sensitivity_data: DataFrame containing sensitivity analysis results.
        output_path: Path to save the CSV file.
    """
    required_columns = ['threshold', 'fpr', 'fnr', 'auc', 'model_id']
    
    if not all(col in sensitivity_data.columns for col in required_columns):
        # If the loaded data doesn't match, we might need to aggregate or transform.
        # Assuming T031 produced a file with these columns or a subset.
        # If T031 produced a summary, we might need to expand it.
        # For now, we assume T031 output matches or we raise an error.
        missing = [col for col in required_columns if col not in sensitivity_data.columns]
        raise ValueError(f"Sensitivity data missing required columns: {missing}")
    
    # Ensure column order
    report_df = sensitivity_data[required_columns]
    
    # Sort for readability
    report_df = report_df.sort_values(by=['model_id', 'threshold'])
    
    # Write to CSV
    report_df.to_csv(output_path, index=False)
    logger.info(f"Sensitivity report saved to {output_path} with {len(report_df)} rows.")

