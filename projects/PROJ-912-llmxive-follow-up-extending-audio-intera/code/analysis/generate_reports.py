def plot_robustness_curve(
    correlation_data: List[Dict[str, Any]],
    breaking_point: Optional[Dict[str, Any]] = None,
    output_path: Optional[Path] = None
) -> Path:
    """
    Generate the AUC vs. Compression plot.
    
    Args:
        correlation_data: List of dicts with keys like 'bit_width', 'auc', 'params'
        breaking_point: Optional dict with 'bit_width' and 'threshold_violated'
        output_path: Destination path for the PNG file.
    
    Returns:
        Path to the generated PNG file.
    """
    if output_path is None:
        path_config = get_path_config()
        output_path = path_config.processed_dir / "robustness_curve.png"
    
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Prepare data
    # We expect correlation_data to have 'bit_width' (or similar) and 'auc'
    # Normalize keys just in case
    x_vals = []
    y_vals = []
    
    for record in correlation_data:
        # Handle potential variations in key names
        bit_key = next((k for k in ['bit_width', 'bits', 'bit'] if k in record), None)
        auc_key = next((k for k in ['auc', 'AUC', 'score'] if k in record), None)
        
        if bit_key and auc_key:
            x_vals.append(record[bit_key])
            y_vals.append(record[auc_key])
        else:
            logger.warning(f"Skipping record missing keys: {record}")
    
    if not x_vals or not y_vals:
        raise ValueError("No valid data points found for plotting.")
    
    # Sort by bit_width for consistent plotting
    sorted_indices = np.argsort(x_vals)
    x_sorted = [x_vals[i] for i in sorted_indices]
    y_sorted = [y_vals[i] for i in sorted_indices]
    
    # Create plot
    plt.figure(figsize=(10, 6))
    plt.plot(x_sorted, y_sorted, marker='o', linestyle='-', color='#1f77b4', label='AUC Score')
    
    # Mark breaking point if available
    if breaking_point:
        bp_bit = breaking_point.get('bit_width')
        bp_violated = breaking_point.get('threshold_violated', False)
        
        if bp_bit is not None:
            # Find index closest to breaking point
            try:
                bp_idx = x_sorted.index(bp_bit)
                bp_auc = y_sorted[bp_idx]
                
                plt.axvline(x=bp_bit, color='red', linestyle='--', linewidth=1.5, 
                            label=f"Breaking Point ({'Violated' if bp_violated else 'Safe'})")
                plt.scatter([bp_bit], [bp_auc], color='red', zorder=5, s=100, marker='x')
            except ValueError:
                logger.warning(f"Breaking point bit_width {bp_bit} not found in data points.")
    
    plt.title('Robustness Curve: AUC vs. Compression Intensity', fontsize=14, fontweight='bold')
    plt.xlabel('Bit Width (Compression)', fontsize=12)
    plt.ylabel('AUC Score', fontsize=12)
    plt.grid(True, which='both', linestyle='--', alpha=0.7)
    plt.legend()
    plt.tight_layout()
    
    # Save figure
    plt.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close()
    
    logger.info(f"Robustness curve plot saved to {output_path}")
    return output_path

