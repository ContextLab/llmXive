def plot_robustness_curve(correlation_data: List[Dict[str, Any]], output_path: Path) -> None:
    """
    Generate the robustness curve plot: AUC vs. Compression (bit-width).
    
    Args:
        correlation_data: List of dicts with keys 'bits', 'auc', etc.
        output_path: Path to save the PNG file.
    """
    if not correlation_data:
        raise ValueError("Correlation data is empty; cannot generate plot.")

    # Sort by bit-width for consistent plotting
    sorted_data = sorted(correlation_data, key=lambda x: x['bits'])
    
    bits = [item['bits'] for item in sorted_data]
    auc_values = [item['auc'] for item in sorted_data]
    
    # Create plot
    plt.figure(figsize=(10, 6))
    plt.plot(bits, auc_values, marker='o', linestyle='-', color='b', label='AUC')
    
    # Add labels and title
    plt.title('Robustness Curve: AUC vs. Compression (Bit-Width)', fontsize=14)
    plt.xlabel('Bit-Width', fontsize=12)
    plt.ylabel('AUC Score', fontsize=12)
    plt.grid(True, which='both', linestyle='--', alpha=0.7)
    plt.xticks(bits)  # Ensure all bit-widths are shown on x-axis
    
    # Annotate points with exact values
    for i, (b, a) in enumerate(zip(bits, auc_values)):
        plt.text(b, a + 0.01, f'{a:.4f}', ha='center', fontsize=10)
    
    # Save figure
    plt.tight_layout()
    plt.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close()
    
    logger.info(f"Robustness curve saved to {output_path}")

