"""
Tests for the validation stage (T005).

The test suite checks two aspects:
1. The CSV produced by the validation stage contains the required
   ``validation_significant`` column.
2. The Markdown report correctly reflects the contents of the CSV:
   - If any rows are flagged, each flagged pair appears exactly once
     in the report in the required format.
   - If no rows are flagged, the report contains the default
     explanatory sentence.
"""

import pathlib

import pandas as pd
import pytest

from llmxive_toolkit import paths

@pytest.fixture(scope="module")
def validation_csv():
    """Load the CSV generated by the validation stage."""
    csv_path = paths.results("validation_correlations.csv")
    assert csv_path.is_file(), f"Validation CSV not found at {csv_path}"
    return pd.read_csv(csv_path)

@pytest.fixture(scope="module")
def validation_report():
    """Load the Markdown report generated by the validation stage."""
    md_path = paths.results("validation_report.md")
    assert md_path.is_file(), f"Validation report not found at {md_path}"
    return md_path.read_text(encoding="utf-8")

def test_csv_has_validation_flag(validation_csv):
    """The CSV must contain the ``validation_significant`` boolean column."""
    assert "validation_significant" in validation_csv.columns, (
        "Column 'validation_significant' missing from validation CSV."
    )
    # Ensure the column is boolean (or can be interpreted as such)
    assert validation_csv["validation_significant"].dtype == bool, (
        "Column 'validation_significant' must be of boolean dtype."
    )

def test_report_contents_matches_csv(validation_csv, validation_report):
    """The Markdown report must reflect the flagged rows in the CSV."""
    flagged = validation_csv[validation_csv["validation_significant"]]

    if flagged.empty:
        # Expect the default sentence when no pair meets the criteria
        expected_sentence = (
            "No composition parameter achieved the pre‑registered effect‑size threshold; "
            "composition does not add predictive value beyond dynamic pressure."
        )
        assert expected_sentence in validation_report, (
            "Default sentence not found in validation report when no rows are significant."
        )
    else:
        # For each flagged row, construct the expected line and verify its presence
        for _, row in flagged.iterrows():
            comp = row["composition_parameter"].replace("_", " ").title()
            idx = row["geomagnetic_index"]
            lag = int(row["lag_hours"])
            r = round(row["pearson_r"], 3)
            expected_line = f"{comp} vs. {idx} at {lag} h lag: r = {r} (significant)"
            assert expected_line in validation_report, (
                f"Expected line not found in report: '{expected_line}'"
            )