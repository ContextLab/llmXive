"""
Module: output_validation_results.py

Purpose:
Generates the final `data/processed/validation_results.csv` artifact based on the
validation logic executed in T032a (accessible cohort) or T032b (skipped).

Logic:
1. Reads `results/validation_report.txt` (generated by T032a or T032b).
2. Parses the report to extract:
   - Cohort status (Accessible/Skipped)
   - Significant taxa count
   - Direction match percentage (if applicable)
   - Pass/Fail status against SC-003 threshold (80%)
3. Constructs a DataFrame with the following columns:
   - cohort_id: Identifier of the cohort (e.g., 'UKB', 'MetaHIT', or 'N/A')
   - status: 'Accessible' or 'Skipped'
   - significant_taxa_count: Number of taxa used for validation
   - direction_match_pct: Percentage of matching directions (float, 0.0 if skipped)
   - sc003_status: 'PASS', 'FAIL', or 'N/A'
   - details: Brief text summary from the report
4. Writes the DataFrame to `data/processed/validation_results.csv`.
"""

import os
import json
import logging
import pandas as pd
from pathlib import Path
from code.config import get_output_path, ensure_directories
from code.utils.logging import get_logger

# Configure logger
logger = get_logger(__name__)

def load_validation_report(report_path: str) -> dict:
    """
    Reads the validation report text file and extracts key metrics.
    
    Expects the report to contain lines with specific keywords:
    - "Cohort Status:"
    - "Significant Taxa Count:"
    - "Direction Match Percentage:"
    - "SC-003 Status:"
    - "Details:"
    """
    report_data = {
        "cohort_status": "Unknown",
        "significant_taxa_count": 0,
        "direction_match_pct": 0.0,
        "sc003_status": "N/A",
        "details": ""
    }

    try:
        if not os.path.exists(report_path):
            logger.warning(f"Validation report not found at {report_path}. "
                           "Assuming skipped status with no data.")
            report_data["cohort_status"] = "Skipped"
            report_data["details"] = "Report file missing."
            return report_data

        with open(report_path, 'r', encoding='utf-8') as f:
            content = f.read()

        lines = content.split('\n')
        for line in lines:
            line = line.strip()
            if line.startswith("Cohort Status:"):
                report_data["cohort_status"] = line.split(":", 1)[1].strip()
            elif line.startswith("Significant Taxa Count:"):
                try:
                    val = int(line.split(":", 1)[1].strip())
                    report_data["significant_taxa_count"] = val
                except ValueError:
                    pass
            elif line.startswith("Direction Match Percentage:"):
                try:
                    val = float(line.split(":", 1)[1].strip().rstrip('%'))
                    report_data["direction_match_pct"] = val
                except ValueError:
                    pass
            elif line.startswith("SC-003 Status:"):
                report_data["sc003_status"] = line.split(":", 1)[1].strip()
            elif line.startswith("Details:"):
                report_data["details"] = line.split(":", 1)[1].strip()
                
        # Fallback logic if parsing fails but file exists
        if report_data["cohort_status"] == "Unknown":
            if "Skipped" in content or "Not Accessible" in content:
                report_data["cohort_status"] = "Skipped"
                report_data["sc003_status"] = "N/A"
            else:
                report_data["cohort_status"] = "Accessible"
                
    except Exception as e:
        logger.error(f"Error parsing validation report: {e}")
        # Default to skipped on error to prevent pipeline crash
        report_data["cohort_status"] = "Skipped"
        report_data["details"] = f"Parse error: {str(e)}"

    return report_data

def parse_validation_results(report_data: dict) -> pd.DataFrame:
    """
    Converts the parsed report dictionary into a DataFrame row.
    """
    # Determine cohort ID based on status
    if report_data["cohort_status"] == "Skipped":
        cohort_id = "N/A"
    else:
        # Attempt to infer from details or default to "Unknown_Cohort"
        # In a real scenario, this might be passed as an argument or read from a config
        cohort_id = "Unknown_Cohort" 
        if "UKB" in report_data.get("details", ""):
            cohort_id = "UKB"
        elif "MetaHIT" in report_data.get("details", ""):
            cohort_id = "MetaHIT"

    row = {
        "cohort_id": cohort_id,
        "status": report_data["cohort_status"],
        "significant_taxa_count": report_data["significant_taxa_count"],
        "direction_match_pct": report_data["direction_match_pct"],
        "sc003_status": report_data["sc003_status"],
        "details": report_data["details"]
    }
    
    return pd.DataFrame([row])

def output_validation_results(df: pd.DataFrame, output_path: str) -> None:
    """
    Writes the DataFrame to CSV.
    """
    ensure_directories([output_path])
    df.to_csv(output_path, index=False)
    logger.info(f"Validation results written to {output_path}")

def main():
    """
    Main entry point for T034.
    """
    logger.info("Starting T034: Outputting validation results.")
    
    # Define paths
    report_path = get_output_path("results/validation_report.txt")
    output_csv_path = get_output_path("data/processed/validation_results.csv")
    
    # Load and parse
    report_data = load_validation_report(report_path)
    
    # Create DataFrame
    df = parse_validation_results(report_data)
    
    # Output
    output_validation_results(df, output_csv_path)
    
    logger.info("T034 completed successfully.")

if __name__ == "__main__":
    main()