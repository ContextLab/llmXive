    if cleaned_df.empty:
        logger.error("Cleaned dataset is empty. Cannot proceed.")
        return
    
    # Verify retention
    # We need the original count before the missing value filter.
    # Since we don't have it, we'll assume the preprocessed_table had the original count.
    original_count = len(preprocessed_table)
    verification_results = verify_retention(cleaned_df, min_rows=100, min_retention_rate=0.80)
    
    # The verification function above uses the wrong original count.
    # Let's recalculate with the correct original count.
    valid_rows = len(cleaned_df)
    retention_rate = valid_rows / original_count if original_count > 0 else 0.0
    
    logger.info(f"Final Verification: {valid_rows} valid rows, {retention_rate:.2%} retention rate.")
    
    if valid_rows < 100:
        logger.error(f"Dataset has fewer than 100 valid rows ({valid_rows}).")
    if retention_rate < 0.80:
        logger.warning(f"Retention rate is below 80% ({retention_rate:.2%}).")
    
    # Save the cleaned dataset
    output_path = get_output_path("cleaned_dataset.csv", sub_dir="processed")
