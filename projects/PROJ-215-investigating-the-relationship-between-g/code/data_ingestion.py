def exponential_backoff_retry(func, max_retries: int = RATE_LIMIT_RETRY_COUNT):
    """Decorator for exponential backoff retry logic."""
    def wrapper(*args, **kwargs):
        for attempt in range(max_retries):
            try:
                return func(*args, **kwargs)
            except requests.exceptions.RequestException as e:
                if attempt == max_retries - 1:
                    raise
                wait_time = RATE_LIMIT_BACKOFF_BASE ** attempt
                logger.warning(f"Request failed: {e}. Retrying in {wait_time}s...")
                time.sleep(wait_time)
        return None
    return wrapper

def compute_sha256(file_path: str) -> str:
    """
    Compute SHA-256 checksum for a file.
    
    Args:
        file_path: Path to the file to hash.
        
    Returns:
        Hexadecimal string of the SHA-256 hash.
        
    Raises:
        FileNotFoundError: If the file does not exist.
        IOError: If the file cannot be read.
    """
    sha256_hash = hashlib.sha256()
    try:
        with open(file_path, "rb") as f:
            for byte_block in iter(lambda: f.read(4096), b""):
                sha256_hash.update(byte_block)
        return sha256_hash.hexdigest()
    except FileNotFoundError:
        raise FileNotFoundError(f"File not found: {file_path}")
    except IOError as e:
        raise IOError(f"Error reading file {file_path}: {e}")

def save_checksums(checksums: Dict[str, str], output_path: str):
    """
    Save checksums to a text file.
    
    Args:
        checksums: Dictionary mapping filenames to their SHA-256 hashes.
        output_path: Path to the output file (e.g., data/raw/checksums.txt).
    """
    ensure_directories([output_path])
    with open(output_path, "w") as f:
        f.write("# SHA-256 Checksums for Raw Data Files\n")
        f.write(f"# Generated by data_ingestion.py\n")
        f.write("# Format: <hash>  <filename>\n")
        for filename, checksum in checksums.items():
            f.write(f"{checksum}  {filename}\n")
    logger.info(f"Checksums saved to {output_path}")

