"""
T025: Output association_results.csv

Aggregates partial Spearman correlation results for alpha diversity and taxa,
applies Benjamini-Hochberg correction (assuming T022 has already processed the
intermediate files or we re-apply here if T022 only logged), and writes the
final `data/processed/association_results.csv`.

This script relies on the unadjusted p-value files generated by T020 and T020a:
- data/interim/unadjusted_alpha_pvals.csv
- data/interim/unadjusted_taxa_pvals.csv

If T022 has already produced adjusted p-values in these files, they are used.
If not, this script performs the BH correction on the unadjusted values before
output.
"""
import os
import logging
import pandas as pd
import numpy as np
from pathlib import Path

# Import config for paths
from config import get_output_path, ensure_directories
from utils.logging import get_logger

logger = get_logger(__name__)

def load_unadjusted_alpha():
    """Load unadjusted alpha diversity p-values."""
    path = get_output_path("data/interim/unadjusted_alpha_pvals.csv")
    if not os.path.exists(path):
        raise FileNotFoundError(f"Required file missing: {path}")
    df = pd.read_csv(path)
    # Ensure expected columns exist
    required = ["variable", "correlation", "pval_unadjusted"]
    for col in required:
        if col not in df.columns:
            raise ValueError(f"Column '{col}' missing in {path}")
    return df

def load_unadjusted_taxa():
    """Load unadjusted taxa p-values."""
    path = get_output_path("data/interim/unadjusted_taxa_pvals.csv")
    if not os.path.exists(path):
        raise FileNotFoundError(f"Required file missing: {path}")
    df = pd.read_csv(path)
    # Ensure expected columns exist
    required = ["taxon", "correlation", "pval_unadjusted"]
    for col in required:
        if col not in df.columns:
            raise ValueError(f"Column '{col}' missing in {path}")
    return df

def apply_bh_correction(pvals):
    """Apply Benjamini-Hochberg correction to a list of p-values."""
    pvals = np.asarray(pvals)
    n = len(pvals)
    if n == 0:
        return np.array([])
    # Sort indices
    sorted_idx = np.argsort(pvals)
    sorted_pvals = pvals[sorted_idx]
    
    # Calculate BH critical values
    ranks = np.arange(1, n + 1)
    bh_values = (sorted_pvals * n) / ranks
    
    # Ensure monotonicity (cumulative min from right)
    bh_corrected = np.minimum.accumulate(bh_values[::-1])[::-1]
    
    # Clip to [0, 1]
    bh_corrected = np.clip(bh_corrected, 0.0, 1.0)
    
    # Restore original order
    result = np.empty(n)
    result[sorted_idx] = bh_corrected
    return result

def determine_direction(correlation):
    """Determine effect direction string."""
    if pd.isna(correlation):
        return "NA"
    if correlation > 0:
        return "positive"
    elif correlation < 0:
        return "negative"
    else:
        return "none"

def main():
    """Main entry point for T025."""
    ensure_directories()
    
    logger.info("Loading unadjusted alpha diversity results...")
    df_alpha = load_unadjusted_alpha()
    
    logger.info("Loading unadjusted taxa results...")
    df_taxa = load_unadjusted_taxa()
    
    # Check if adjusted p-values already exist (from T022)
    # If columns 'pval_adjusted' exist, we assume T022 ran. 
    # If not, we calculate them here to ensure the output is complete.
    if "pval_adjusted" not in df_alpha.columns:
        logger.info("Calculating BH correction for alpha diversity...")
        df_alpha["pval_adjusted"] = apply_bh_correction(df_alpha["pval_unadjusted"])
    else:
        logger.info("Using existing adjusted p-values for alpha diversity.")

    if "pval_adjusted" not in df_taxa.columns:
        logger.info("Calculating BH correction for taxa...")
        df_taxa["pval_adjusted"] = apply_bh_correction(df_taxa["pval_unadjusted"])
    else:
        logger.info("Using existing adjusted p-values for taxa.")
    
    # Add direction column
    df_alpha["direction"] = df_alpha["correlation"].apply(determine_direction)
    df_taxa["direction"] = df_taxa["correlation"].apply(determine_direction)
    
    # Standardize column names for final output
    # Alpha: variable -> taxon/feature, pval_unadjusted -> pval, pval_adjusted -> qval
    df_alpha_final = df_alpha.rename(columns={
        "variable": "feature",
        "pval_unadjusted": "pval",
        "pval_adjusted": "qval"
    })
    df_alpha_final["type"] = "alpha_diversity"
    
    df_taxa_final = df_taxa.rename(columns={
        "pval_unadjusted": "pval",
        "pval_adjusted": "qval"
    })
    df_taxa_final["type"] = "taxa_abundance"
    
    # Reorder columns to match spec: feature/taxon, correlation, pval, qval, direction, type
    cols = ["type", "feature", "correlation", "pval", "qval", "direction"]
    # Ensure feature column exists (it's 'taxon' in taxa, 'feature' in alpha)
    # We unified 'feature' above.
    
    df_alpha_final = df_alpha_final[cols]
    df_taxa_final = df_taxa_final[cols]
    
    # Concatenate
    final_df = pd.concat([df_alpha_final, df_taxa_final], ignore_index=True)
    
    # Sort by q-value
    final_df = final_df.sort_values(by="qval")
    
    # Output path
    output_path = get_output_path("data/processed/association_results.csv")
    logger.info(f"Writing final results to {output_path}")
    final_df.to_csv(output_path, index=False)
    
    logger.info(f"Successfully wrote {len(final_df)} association results.")
    logger.info(f"Significant findings (q < 0.05): {sum(final_df['qval'] < 0.05)}")
    
    return final_df

if __name__ == "__main__":
    main()