def load_primes_from_csv(filepath: str) -> List[int]:
    """
    Load primes from a CSV file generated by the sieve.
    Expected format: single column of integers, possibly with a header 'prime'.
    """
    primes = []
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Prime file not found: {filepath}. Run sieve generation first.")
    
    with open(filepath, 'r') as f:
        header = f.readline().strip()
        if header.lower() == 'prime':
            pass  # Skip header
        else:
            # If no header, the first line is a prime
            primes.append(int(header))
        
        for line in f:
            line = line.strip()
            if line:
                primes.append(int(line))
    
    return primes

def is_y_smooth(n: int, y: int, primes: List[int]) -> bool:
    """
    Check if integer n is y-smooth using the provided list of primes <= y.
    Returns True if all prime factors of n are <= y.
    """
    if n <= 1:
        return True
    
    # Optimization: if n is in primes, it's smooth if n <= y
    # But we need to check factorization.
    # We iterate through primes <= y to divide n.
    
    temp = n
    for p in primes:
        if p > y:
            break
        if p * p > temp:
            break
        while temp % p == 0:
            temp //= p
    
    # If temp is still > 1, it might be a prime > y or a composite of primes > y
    # We need to check if the remaining temp is <= y.
    # However, since we only have primes up to y in our list, if temp > y, 
    # it means n has a prime factor > y (unless temp is 1).
    # Wait, if temp > 1 and temp <= y, then temp is a prime <= y (since we divided out all smaller factors).
    # If temp > y, then n has a prime factor > y.
    
    if temp > 1 and temp > y:
        return False
    
    # One edge case: what if temp is a composite of primes > y? 
    # Since we divided by all primes <= y, any remaining factor must be > y.
    # So if temp > 1, it must be composed of primes > y.
    # Thus, if temp > 1, n is not y-smooth.
    # Correction: The logic above "if temp > 1 and temp > y" is slightly flawed if temp is a prime <= y that we missed?
    # No, we iterate all primes <= y. So if temp > 1 after division, it must be a prime > y (or product of primes > y).
    # Therefore, if temp > 1, return False.
    if temp > 1:
        return False
        
    return True

def count_smooth_in_interval(x: int, h: int, y: int, primes: List[int]) -> int:
    """
    Count the number of y-smooth integers in the interval [x, x+h].
    """
    count = 0
    # Ensure we don't go beyond 10^9 if that's a constraint, though the task implies general intervals.
    # The interval is [x, x+h-1] or [x, x+h]? Usually short intervals are [x, x+h).
    # Let's assume [x, x+h) i.e., h integers.
    # But the task says "intervals [x, x+h]". Let's assume inclusive [x, x+h] which is h+1 integers?
    # Standard definition in this context (e.g., de Bruijn) often uses [x, x+y] or [x, x+h).
    # Let's stick to the task description: "intervals [x, x+h]".
    # If h=1000, is that 1000 or 1001 numbers?
    # Let's assume the interval length is h, so we check x, x+1, ..., x+h-1.
    # However, the task says "density = count/h". If we check h+1 numbers, density = count/(h+1)?
    # Let's assume the interval is [x, x+h) (h numbers) for consistency with density = count/h.
    # Re-reading: "short intervals [x, x+h]". In math, [a,b] is inclusive.
    # But if h is large, the difference is negligible.
    # Let's assume the interval has length h, so we iterate h times.
    # If the user meant inclusive, h would be the difference.
    # Let's implement for h numbers: x to x+h-1.
    
    start = x
    end = x + h
    
    for n in range(start, end):
        if is_y_smooth(n, y, primes):
            count += 1
    
    return count

