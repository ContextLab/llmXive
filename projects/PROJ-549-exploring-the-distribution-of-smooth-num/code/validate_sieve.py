"""
validate_sieve.py

Validates the prime list generated by `sieve.py` (data/primes_1e9.csv).

Methodology:
1. Loads the generated CSV.
2. Computes a SHA-256 checksum of the file contents for reproducibility.
3. Performs a secondary, internal deterministic verification using a simple
   trial-division sieve on a random sample of primes.
4. Verifies the completeness of the list by checking the count against
   the theoretical pi(10^9) = 50,847,534.
5. Outputs a validation report (JSON) and logs the result.

Dependencies:
- data/primes_1e9.csv (generated by T012)
- code/utils.py (for checksum and logging)
- code/config.py (for project config)
"""

import argparse
import csv
import hashlib
import json
import logging
import math
import os
import random
import sys
from typing import List, Tuple, Optional, Dict, Any

# Import from project siblings
from utils import setup_logging, generate_checksum, get_file_size_human
from config import load_config

# Constants
EXPECTED_PRIME_COUNT = 50847534  # pi(10^9) from OEIS A006880
SAMPLE_SIZE = 1000  # Number of primes to verify via trial division
MAX_SAMPLE_CHECK = 1000000  # Max value for trial division check to keep it fast
OUTPUT_FILE = "data/validation_report.json"


def is_prime_trial_division(n: int) -> bool:
    """
    Deterministic primality test using trial division.
    Used for secondary verification of a sample.
    """
    if n <= 1:
        return False
    if n <= 3:
        return True
    if n % 2 == 0 or n % 3 == 0:
        return False
    i = 5
    while i * i <= n:
        if n % i == 0 or n % (i + 2) == 0:
            return False
        i += 6
    return True


def load_primes_from_csv(filepath: str) -> List[int]:
    """
    Loads primes from a CSV file (one prime per line or comma-separated).
    Returns a list of integers.
    """
    primes = []
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Input file not found: {filepath}")

    with open(filepath, 'r', newline='') as f:
        reader = csv.reader(f)
        for row in reader:
            if not row:
                continue
            # Handle both single column and potential header
            val_str = row[0].strip()
            if val_str.isdigit():
                primes.append(int(val_str))
            else:
                # Skip header if present
                continue
    return primes


def verify_primes_sample(primes: List[int], sample_size: int = SAMPLE_SIZE) -> Tuple[bool, int, int]:
    """
    Verifies a random sample of primes from the list using trial division.
    Returns (passed, verified_count, failed_count).
    """
    if len(primes) < sample_size:
        sample_size = len(primes)

    # Deterministic seed for reproducibility
    random.seed(42)
    sample_indices = random.sample(range(len(primes)), sample_size)

    verified = 0
    failed = 0

    for idx in sample_indices:
        p = primes[idx]
        # Only check primes up to MAX_SAMPLE_CHECK to keep verification fast
        # The sieve should have generated primes up to 10^9, but trial division
        # is slow for large numbers. We trust the sieve for large numbers
        # and verify the logic on smaller ones, or verify that the number
        # is indeed prime if we can afford it.
        # To be safe and fast, we verify the logic on the first N primes
        # and random samples from the lower range.
        
        # Strategy: Verify ALL primes in the list that are < MAX_SAMPLE_CHECK
        # and a random sample of larger primes (which is expensive, so we skip
        # full trial division for 10^9 and rely on the sieve logic for those,
        # but we MUST verify at least some logic).
        
        # Actually, the requirement is "verify a random sample".
        # We will verify the primality of the sampled numbers.
        # For numbers > 10^6, trial division takes ~1ms. 1000 samples * 1ms = 1s.
        # This is acceptable.
        
        if is_prime_trial_division(p):
            verified += 1
        else:
            failed += 1
            logging.error(f"Verification failed for prime: {p} (index {idx})")

    return (failed == 0), verified, failed


def verify_primes_completeness(primes: List[int]) -> Tuple[bool, str]:
    """
    Verifies the count of primes matches the expected count for 10^9.
    Also checks for duplicates and sorted order.
    """
    count = len(primes)
    expected = EXPECTED_PRIME_COUNT
    
    if count != expected:
        return False, f"Count mismatch: got {count}, expected {expected}"
    
    # Check sorted
    if primes != sorted(primes):
        return False, "Primes are not sorted"
    
    # Check duplicates (set length vs list length)
    if len(set(primes)) != count:
        return False, "Duplicates found in prime list"
    
    return True, "Count and order verified"


def compute_file_checksum(filepath: str) -> str:
    """
    Computes SHA-256 checksum of the file.
    """
    sha256_hash = hashlib.sha256()
    with open(filepath, "rb") as f:
        for byte_block in iter(lambda: f.read(4096), b""):
            sha256_hash.update(byte_block)
    return sha256_hash.hexdigest()


def main():
    """
    Main entry point for sieve validation.
    """
    parser = argparse.ArgumentParser(description="Validate the generated prime sieve.")
    parser.add_argument(
        "--input", 
        type=str, 
        default="data/primes_1e9.csv",
        help="Path to the generated primes CSV file."
    )
    parser.add_argument(
        "--output",
        type=str,
        default=OUTPUT_FILE,
        help="Path to save the validation report JSON."
    )
    parser.add_argument(
        "--sample-size",
        type=int,
        default=SAMPLE_SIZE,
        help="Number of primes to verify via trial division."
    )
    args = parser.parse_args()

    # Setup logging
    setup_logging()
    logger = logging.getLogger(__name__)

    logger.info(f"Starting validation of {args.input}")
    logger.info(f"Expected prime count: {EXPECTED_PRIME_COUNT}")

    report = {
        "input_file": args.input,
        "expected_count": EXPECTED_PRIME_COUNT,
        "sample_size": args.sample_size,
        "validation_passed": False,
        "checksum": None,
        "file_size_human": None,
        "details": {}
    }

    try:
        # 1. Check file existence and size
        if not os.path.exists(args.input):
            logger.error(f"Input file not found: {args.input}")
            print(json.dumps(report, indent=2))
            sys.exit(1)

        report["file_size_human"] = get_file_size_human(args.input)
        logger.info(f"File size: {report['file_size_human']}")

        # 2. Compute checksum
        checksum = compute_file_checksum(args.input)
        report["checksum"] = checksum
        logger.info(f"File checksum (SHA-256): {checksum}")

        # 3. Load primes
        logger.info("Loading primes from CSV...")
        start_load = os.times().elapsed
        primes = load_primes_from_csv(args.input)
        end_load = os.times().elapsed
        load_time = end_load - start_load
        logger.info(f"Loaded {len(primes)} primes in {load_time:.2f}s")

        # 4. Verify completeness (count, sorted, unique)
        logger.info("Verifying completeness (count, sorted, unique)...")
        completeness_ok, completeness_msg = verify_primes_completeness(primes)
        report["details"]["completeness"] = {
            "passed": completeness_ok,
            "message": completeness_msg
        }
        if not completeness_ok:
            logger.error(f"Completeness check failed: {completeness_msg}")
            report["validation_passed"] = False
            print(json.dumps(report, indent=2))
            sys.exit(1)
        logger.info("Completeness check passed.")

        # 5. Verify sample via trial division
        logger.info(f"Verifying random sample of {args.sample_size} primes via trial division...")
        sample_ok, verified_count, failed_count = verify_primes_sample(primes, args.sample_size)
        report["details"]["sample_verification"] = {
            "passed": sample_ok,
            "verified_count": verified_count,
            "failed_count": failed_count
        }
        if not sample_ok:
            logger.error(f"Sample verification failed: {failed_count} failures.")
            report["validation_passed"] = False
            print(json.dumps(report, indent=2))
            sys.exit(1)
        logger.info(f"Sample verification passed ({verified_count} verified).")

        # All checks passed
        report["validation_passed"] = True
        logger.info("VALIDATION PASSED: All checks successful.")

    except Exception as e:
        logger.error(f"Validation failed with exception: {e}", exc_info=True)
        report["validation_passed"] = False
        report["details"]["error"] = str(e)
        print(json.dumps(report, indent=2))
        sys.exit(1)

    finally:
        # Write report
        output_dir = os.path.dirname(args.output)
        if output_dir and not os.path.exists(output_dir):
            os.makedirs(output_dir)
        
        with open(args.output, 'w') as f:
            json.dump(report, f, indent=2)
        logger.info(f"Validation report saved to {args.output}")
        
        # Print summary to stdout for CI
        status = "PASS" if report["validation_passed"] else "FAIL"
        print(f"\n--- VALIDATION RESULT: {status} ---")
        print(f"Input: {args.input}")
        print(f"Checksum: {report['checksum']}")
        print(f"Count: {len(primes)} (Expected: {EXPECTED_PRIME_COUNT})")
        print(f"Sample Verified: {verified_count}")
        print(f"Report: {args.output}\n")

        sys.exit(0 if report["validation_passed"] else 1)


if __name__ == "__main__":
    main()