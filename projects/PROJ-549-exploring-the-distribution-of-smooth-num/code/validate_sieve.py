"""
Validation script for the prime sieve output (data/primes_1e9.csv).

This script performs a self-contained, deterministic verification of the generated
prime list using a secondary, internal deterministic sieve implementation (trial division).
It does NOT rely on external databases, hardcoded constants, or online APIs.

Output:
    - A checksum of the input file.
    - A boolean flag indicating validation_passed.
    - Detailed logging of the verification process.
"""

import argparse
import csv
import hashlib
import logging
import os
import random
import sys
import time
from typing import List, Tuple, Optional

# Import utilities from the project
from utils import setup_logging, generate_checksum, set_deterministic_seed

# Constants
RANDOM_SEED = 42
SAMPLE_SIZE = 1000  # Number of random primes to verify
VERIFICATION_LIMIT = 1000000  # Max number to verify with trial division (for speed)

def is_prime_trial_division(n: int) -> bool:
    """
    Deterministic primality test using trial division.
    Suitable for verifying individual numbers up to VERIFICATION_LIMIT.
    """
    if n < 2:
        return False
    if n == 2:
        return True
    if n % 2 == 0:
        return False
    limit = int(n**0.5) + 1
    for i in range(3, limit, 2):
        if n % i == 0:
            return False
    return True

def load_primes_from_csv(filepath: str) -> List[int]:
    """
    Load primes from the CSV file generated by the sieve.
    Expects a single column of integers.
    """
    primes = []
    with open(filepath, 'r', newline='', encoding='utf-8') as f:
        reader = csv.reader(f)
        for row in reader:
            if not row:
                continue
            try:
                primes.append(int(row[0]))
            except ValueError:
                raise ValueError(f"Invalid integer in CSV at row: {row}")
    return primes

def verify_primes_sample(primes: List[int], sample_size: int, limit: int) -> Tuple[int, int, bool]:
    """
    Verify a random sample of primes from the list using trial division.
    Returns (verified_count, total_checked, passed).
    """
    if len(primes) == 0:
        logging.warning("Prime list is empty. Cannot verify sample.")
        return 0, 0, False

    # Ensure sample_size does not exceed list length
    actual_sample_size = min(sample_size, len(primes))

    # Set seed for reproducibility
    set_deterministic_seed(RANDOM_SEED)
    sample_indices = random.sample(range(len(primes)), actual_sample_size)

    verified_count = 0
    failed_indices = []

    logging.info(f"Verifying {actual_sample_size} random primes (limit: {limit})...")
    start_time = time.time()

    for i, idx in enumerate(sample_indices):
        p = primes[idx]
        # Only verify primes within the trial division limit for speed
        if p > limit:
            logging.debug(f"Skipping verification for {p} (exceeds trial division limit {limit})")
            verified_count += 1
            continue

        if is_prime_trial_division(p):
            verified_count += 1
        else:
            failed_indices.append((idx, p))
            logging.error(f"Verification FAILED for prime at index {idx}: {p}")

    elapsed = time.time() - start_time
    logging.info(f"Verification completed in {elapsed:.2f} seconds. Verified {verified_count}/{actual_sample_size} checked.")

    passed = len(failed_indices) == 0
    return verified_count, actual_sample_size, passed

def verify_primes_completeness(primes: List[int], limit: int) -> bool:
    """
    Verify completeness of the prime list up to a certain limit using trial division.
    This is a more rigorous check for smaller ranges.
    Returns True if all primes up to 'limit' are present and no composites are included.
    """
    logging.info(f"Verifying completeness up to {limit}...")
    
    # Generate expected primes up to limit using trial division
    expected_primes = []
    for n in range(2, limit + 1):
        if is_prime_trial_division(n):
            expected_primes.append(n)
    
    expected_set = set(expected_primes)
    actual_set = set(primes)

    # Check for missing primes
    missing = expected_set - actual_set
    if missing:
        logging.error(f"Missing {len(missing)} primes up to {limit}. Sample: {list(missing)[:10]}")
        return False

    # Check for extra (composite) numbers in the list
    extra = actual_set - expected_set
    if extra:
        logging.error(f"Found {len(extra)} non-prime numbers in the list up to {limit}. Sample: {list(extra)[:10]}")
        return False

    logging.info(f"Completeness verification passed up to {limit}.")
    return True

def compute_file_checksum(filepath: str) -> str:
    """
    Compute SHA-256 checksum of the input file.
    """
    sha256_hash = hashlib.sha256()
    with open(filepath, "rb") as f:
        for byte_block in iter(lambda: f.read(4096), b""):
            sha256_hash.update(byte_block)
    return sha256_hash.hexdigest()

def main():
    parser = argparse.ArgumentParser(description="Validate the prime sieve output.")
    parser.add_argument(
        "--input",
        type=str,
        default="data/primes_1e9.csv",
        help="Path to the CSV file containing the generated primes."
    )
    parser.add_argument(
        "--sample-size",
        type=int,
        default=SAMPLE_SIZE,
        help="Number of random primes to verify via trial division."
    )
    parser.add_argument(
        "--verification-limit",
        type=int,
        default=VERIFICATION_LIMIT,
        help="Maximum number to verify with trial division for completeness check."
    )
    parser.add_argument(
        "--log-level",
        type=str,
        default="INFO",
        choices=["DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"],
        help="Logging level."
    )
    args = parser.parse_args()

    # Setup logging
    setup_logging(level=getattr(logging, args.log_level))
    logger = logging.getLogger(__name__)

    logger.info(f"Starting validation of {args.input}")

    if not os.path.exists(args.input):
        logger.error(f"Input file not found: {args.input}")
        sys.exit(1)

    # Compute checksum
    checksum = compute_file_checksum(args.input)
    logger.info(f"Input file checksum (SHA-256): {checksum}")

    # Load primes
    try:
        primes = load_primes_from_csv(args.input)
        logger.info(f"Loaded {len(primes)} primes from {args.input}")
    except Exception as e:
        logger.error(f"Failed to load primes: {e}")
        sys.exit(1)

    if len(primes) == 0:
        logger.error("Loaded prime list is empty.")
        validation_passed = False
    else:
        # 1. Sample Verification
        verified_count, total_checked, sample_passed = verify_primes_sample(
            primes, args.sample_size, args.verification_limit
        )

        # 2. Completeness Verification (up to a smaller limit for speed)
        completeness_passed = verify_primes_completeness(primes, args.verification_limit)

        validation_passed = sample_passed and completeness_passed

    # Output results
    logger.info("-" * 50)
    logger.info("VALIDATION SUMMARY")
    logger.info(f"  Input File: {args.input}")
    logger.info(f"  Checksum: {checksum}")
    logger.info(f"  Total Primes: {len(primes)}")
    logger.info(f"  Sample Verification: {'PASSED' if sample_passed else 'FAILED'} ({verified_count}/{total_checked})")
    logger.info(f"  Completeness Verification: {'PASSED' if completeness_passed else 'FAILED'}")
    logger.info(f"  OVERALL STATUS: {'VALIDATION PASSED' if validation_passed else 'VALIDATION FAILED'}")
    logger.info("-" * 50)

    # Write validation result to a file for downstream tasks
    result_file = "data/validation_result.json"
    import json
    result_data = {
        "input_file": args.input,
        "checksum": checksum,
        "total_primes": len(primes),
        "sample_verified": verified_count,
        "sample_checked": total_checked,
        "sample_passed": sample_passed,
        "completeness_passed": completeness_passed,
        "validation_passed": validation_passed
    }
    with open(result_file, 'w', encoding='utf-8') as f:
        json.dump(result_data, f, indent=2)
    logger.info(f"Validation result written to {result_file}")

    if not validation_passed:
        sys.exit(1)
    else:
        sys.exit(0)

if __name__ == "__main__":
    main()