import os
import json
import sys
from pathlib import Path
from datetime import datetime
from utils.constants import RESULTS_DIR, DATA_PROCESSED_DIR

def load_json_file(file_path: Path) -> dict:
    """Load and return JSON data from a file."""
    if not file_path.exists():
        raise FileNotFoundError(f"File not found: {file_path}")
    with open(file_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def save_json_file(data: dict, file_path: Path) -> None:
    """Save dictionary data to a JSON file."""
    file_path.parent.mkdir(parents=True, exist_ok=True)
    with open(file_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=2)

def main():
    """
    Execute T027: Save pathway mapping results to results/pathway_analysis.json.
    
    This task depends on T026 (interpret.py) which generates the pathway mapping data.
    It aggregates the pathway analysis results and ensures the mandatory framing field
    is included as per FR-011.
    """
    print("Starting T027: Saving pathway mapping results...")
    
    # Ensure results directory exists
    results_dir = Path(RESULTS_DIR)
    results_dir.mkdir(parents=True, exist_ok=True)
    
    # Path to the pathway analysis data generated by T026 (interpret.py)
    # This file should have been created by the save_pathway_analysis function in interpret.py
    pathway_input_path = results_dir / "pathway_analysis_temp.json"
    output_path = results_dir / "pathway_analysis.json"
    
    # If the temp file doesn't exist, check if the final file already exists
    # (in case of re-runs)
    if not pathway_input_path.exists():
        # Try to load from the final output path if it exists
        if output_path.exists():
            print(f"Output file {output_path} already exists. Skipping generation.")
            return
        else:
            # If neither exists, we need to run the interpretation step first
            # or assume the data comes from a previous run of T026
            # For this task, we assume T026 has been executed and produced the data
            # If it hasn't, we raise an error rather than fabricating data
            raise FileNotFoundError(
                f"Pathway analysis input file not found: {pathway_input_path}. "
                "Please ensure T026 (interpret.py) has been executed successfully."
            )
    
    # Load the pathway analysis data from T026
    pathway_data = load_json_file(pathway_input_path)
    
    # Ensure the mandatory framing field is present (FR-011)
    # The framing field must be set to "associational" with the exact string
    if "framing" not in pathway_data:
        pathway_data["framing"] = "associational"
    else:
        # Verify the existing framing value matches the requirement
        if pathway_data["framing"] != "associational":
            print(f"Warning: Existing framing value '{pathway_data['framing']}' does not match required 'associational'. Updating...")
            pathway_data["framing"] = "associational"
    
    # Ensure the framing description is present
    if "framing_description" not in pathway_data:
        pathway_data["framing_description"] = "These results represent associations, not causation"
    
    # Add metadata about when this file was generated
    pathway_data["generated_at"] = datetime.now().isoformat()
    pathway_data["task_id"] = "T027"
    
    # Save the final pathway analysis results
    save_json_file(pathway_data, output_path)
    
    print(f"Successfully saved pathway analysis results to {output_path}")
    
    # Verify the output file exists and has content
    if output_path.exists() and output_path.stat().st_size > 0:
        print("Verification: Output file exists and is non-empty.")
    else:
        raise RuntimeError("Failed to generate valid output file.")

if __name__ == "__main__":
    main()