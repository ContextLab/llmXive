# Import from existing project utilities
from utils.constants import (
    PROJECT_ROOT,
    DATA_PROCESSED_DIR,
    HOLD_OUT_FRACTION,
    MAX_DEPTH_GRID,
    RANDOM_STATE
)
from utils.io import compute_file_hash, log_artifact

# Import from existing modeling modules if needed (though we implement logic here)
# We assume data is pre-processed and available in data/processed/

def load_processed_data() -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Load the preprocessed feature matrix, labels, and split indices (if any).
    Reads from data/processed/ as generated by T017.
    
    Returns:
        Tuple of (features_df, labels_df, metadata_df)
    """
    features_path = DATA_PROCESSED_DIR / "batch_corrected_matrix.csv"
    labels_path = DATA_PROCESSED_DIR / "labels.csv"
    
    if not features_path.exists():
        raise FileNotFoundError(f"Processed features not found at {features_path}. Run T017 first.")
    if not labels_path.exists():
        raise FileNotFoundError(f"Processed labels not found at {labels_path}. Run T017 first.")
        
    features_df = pd.read_csv(features_path, index_col=0)
    labels_df = pd.read_csv(labels_path, index_col=0)
    
    # Ensure indices align
    common_idx = features_df.index.intersection(labels_df.index)
    features_df = features_df.loc[common_idx]
    labels_df = labels_df.loc[common_idx]
    
    return features_df, labels_df, None

def train_model() -> Dict[str, Any]:
    """
    Train a Random Forest classifier with stratified cross-validation and grid search.
    
    Steps:
    1. Load preprocessed data.
    2. Split data into train/hold-out (stratified on binary_label) BEFORE any CV.
    3. Save split indices to data/processed/split_indices.json.
    4. Perform GridSearchCV with max_depth grid on the training set.
    5. Train final model with best parameters.
    6. Save model and indices.
    
    Returns:
        Dict containing model path, best params, and split info.
    """
    print("Loading preprocessed data...")
    X, y, _ = load_processed_data()
    
    # Ensure y is binary (0/1) for stratification
    if 'binary_label' in y.columns:
        y_binary = y['binary_label']
    elif 'harmonized_score' in y.columns:
        # If only harmonized_score exists, binarize (simple threshold at median or mean)
        # Assuming 1 is resistant, 0 is susceptible
        threshold = y['harmonized_score'].median()
        y_binary = (y['harmonized_score'] >= threshold).astype(int)
    else:
        # Fallback: use first numeric column
        y_binary = y.iloc[:, 0]
        if y_binary.nunique() < 2:
            raise ValueError("Target variable must have at least 2 classes for stratification.")
    
    # Step 2: Stratified Split (Train/Hold-out) BEFORE CV
    # We implement a manual stratified split since sklearn is available
    from sklearn.model_selection import train_test_split
    
    train_idx, holdout_idx = train_test_split(
        X.index,
        test_size=HOLD_OUT_FRACTION,
        stratify=y_binary,
        random_state=RANDOM_STATE
    )
    
    X_train = X.loc[train_idx]
    y_train = y_binary.loc[train_idx]
    X_holdout = X.loc[holdout_idx]
    y_holdout = y_binary.loc[holdout_idx]
    
    print(f"Train size: {len(X_train)}, Hold-out size: {len(X_holdout)}")
    print(f"Train class distribution: {y_train.value_counts().to_dict()}")
    print(f"Hold-out class distribution: {y_holdout.value_counts().to_dict()}")
    
    # Save split indices
    split_indices_path = DATA_PROCESSED_DIR / "split_indices.json"
    split_data = {
        "train_indices": train_idx.tolist(),
        "holdout_indices": holdout_idx.tolist()
    }
    with open(split_indices_path, 'w') as f:
        json.dump(split_data, f, indent=2)
    print(f"Saved split indices to {split_indices_path}")
    
    # Step 3: GridSearchCV on Training Set
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.model_selection import StratifiedKFold, GridSearchCV
    from sklearn.metrics import balanced_accuracy_score, make_scorer
    
    param_grid = {
        'max_depth': MAX_DEPTH_GRID,
        'n_estimators': [500]
    }
    
    # Define scoring
    scorer = make_scorer(balanced_accuracy_score)
    
    # Cross-validation strategy
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)
    
    print("Starting GridSearchCV...")
    base_rf = RandomForestClassifier(
        n_estimators=500,
        random_state=RANDOM_STATE,
        n_jobs=-1,
        class_weight='balanced'
    )
    
    grid_search = GridSearchCV(
        estimator=base_rf,
        param_grid=param_grid,
        scoring=scorer,
        cv=cv,
        n_jobs=-1,
        verbose=1
    )
    
    grid_search.fit(X_train, y_train)
    
    print(f"Best parameters: {grid_search.best_params_}")
    print(f"Best cross-validated score: {grid_search.best_score_:.4f}")
    
    # Step 4: Train final model with best parameters on full training set
    best_model = grid_search.best_estimator_
    
    # Save model
    model_path = DATA_PROCESSED_DIR / "trained_model.pkl"
    with open(model_path, 'wb') as f:
        pickle.dump(best_model, f)
    print(f"Saved trained model to {model_path}")
    
    # Compute hash for artifact tracking
    model_hash = compute_file_hash(model_path)
    log_artifact(
        artifact_path=str(model_path),
        artifact_type="model",
        hash=model_hash,
        metadata={
            "best_params": grid_search.best_params_,
            "best_cv_score": grid_search.best_score_,
            "train_size": len(X_train),
            "holdout_size": len(X_holdout)
        }
    )
    
    return {
        "model_path": str(model_path),
        "split_indices_path": str(split_indices_path),
        "best_params": grid_search.best_params_,
        "best_cv_score": grid_search.best_score_,
        "train_size": len(X_train),
        "holdout_size": len(X_holdout)
    }

def main():
    """
    Entry point for T020: Model Training.
    """
    print("=" * 50)
    print("Starting T020: Model Training")
    print("=" * 50)
    
    try:
        results = train_model()
        print("T020 completed successfully.")
        print(f"Results: {json.dumps(results, indent=2)}")
    except Exception as e:
        print(f"ERROR in T020: {str(e)}")
        raise

if __name__ == "__main__":
    main()