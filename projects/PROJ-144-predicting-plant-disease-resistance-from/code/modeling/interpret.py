def load_json_file(file_path: Path) -> Dict[str, Any]:
    """Load a JSON file and return its contents as a dictionary."""
    if not file_path.exists():
        raise FileNotFoundError(f"JSON file not found: {file_path}")
    with open(file_path, 'r') as f:
        return json.load(f)

def save_json_file(file_path: Path, data: Dict[str, Any]) -> None:
    """Save a dictionary to a JSON file."""
    file_path.parent.mkdir(parents=True, exist_ok=True)
    with open(file_path, 'w') as f:
        json.dump(data, f, indent=2)

def load_top_metabolites(file_path: Path) -> List[Dict[str, Any]]:
    """
    Load the top metabolites from the file generated by T026a.
    Expects a list of dicts with keys like 'metabolite_id', 'importance_score', etc.
    """
    logger.info(f"Loading top metabolites from {file_path}")
    data = load_json_file(file_path)
    if not isinstance(data, list):
        logger.warning(f"Expected a list in {file_path}, got {type(data)}")
        return []
    return data

def map_metabolite_to_pathways(metabolite_info: Dict[str, Any]) -> Dict[str, Any]:
    """
    Map a single metabolite to pathways based on T026b results.
    This function assumes T026b has already populated `results/pathway_mappings.json`.
    It retrieves the mapping for the specific metabolite.
    """
    # In a real scenario, we might query an API here if not pre-computed.
    # Since T026b produces `pathway_mappings.json`, we load it to find the entry.
    # However, to avoid loading the whole file repeatedly for every metabolite,
    # we assume the caller passes the pre-loaded mappings or we load it once.
    # For this function signature, we will assume we are looking up within a pre-loaded context
    # or we load it here for simplicity in this isolated function.
    # Better design: pass `pathway_mappings` as an arg, but sticking to the task's implied flow.
    
    # To keep it self-contained as per the "extend" instruction without changing signatures too much:
    # We will look for the mapping in the file generated by T026b.
    mappings_path = RESULTS_DIR / "pathway_mappings.json"
    if not mappings_path.exists():
        logger.warning(f"Pathway mappings file not found at {mappings_path}. Returning empty mapping.")
        return {
            "metabolite_id": metabolite_info.get("metabolite_id", "unknown"),
            "pathways": [],
            "mapping_status": "failed"
        }
    
    try:
        mappings_data = load_json_file(mappings_path)
        # Assuming mappings_data is a dict keyed by metabolite_id or a list we need to search
        if isinstance(mappings_data, dict):
            mid = metabolite_info.get("metabolite_id")
            entry = mappings_data.get(mid, {})
            if not entry:
                # Try searching by name if ID fails
                name = metabolite_info.get("name", "")
                for k, v in mappings_data.items():
                    if v.get("name") == name:
                        entry = v
                        break
            return {
                "metabolite_id": mid,
                "pathways": entry.get("pathways", []),
                "mapping_status": "success" if entry.get("pathways") else "partial"
            }
        elif isinstance(mappings_data, list):
            # Search list
            mid = metabolite_info.get("metabolite_id")
            for item in mappings_data:
                if item.get("metabolite_id") == mid:
                    return {
                        "metabolite_id": mid,
                        "pathways": item.get("pathways", []),
                        "mapping_status": "success" if item.get("pathways") else "partial"
                    }
            return {
                "metabolite_id": mid,
                "pathways": [],
                "mapping_status": "failed"
            }
        else:
            logger.error(f"Unexpected format in pathway_mappings.json: {type(mappings_data)}")
            return {"metabolite_id": metabolite_info.get("metabolite_id"), "pathways": [], "mapping_status": "failed"}
    except Exception as e:
        logger.error(f"Error reading pathway mappings: {e}")
        return {"metabolite_id": metabolite_info.get("metabolite_id"), "pathways": [], "mapping_status": "failed"}

def enrich_metabolite_info(metabolite: Dict[str, Any], pathway_mapping: Dict[str, Any]) -> Dict[str, Any]:
    """
    Enrich the metabolite dictionary with pathway information.
    """
    enriched = metabolite.copy()
    enriched["pathways"] = pathway_mapping.get("pathways", [])
    enriched["mapping_status"] = pathway_mapping.get("mapping_status", "unknown")
    return enriched

def generate_narrative_report(top_metabolites: List[Dict[str, Any]], pathway_mappings: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Generate the narrative report discussing biological plausibility.
    Includes the mandatory framing text.
    """
    mandatory_framing = (
        "These findings represent statistical associations between pre-challenge metabolite profiles "
        "and disease resistance phenotypes. No causal claims are made."
    )

    successful_mappings = [m for m in pathway_mappings if m.get("mapping_status") == "success"]
    failed_mappings = [m for m in pathway_mappings if m.get("mapping_status") != "success"]
    total_count = len(pathway_mappings)
    success_count = len(successful_mappings)
    success_rate = (success_count / total_count * 100) if total_count > 0 else 0

    # Construct the narrative
    narrative_parts = []
    narrative_parts.append("## Biological Interpretation Report")
    narrative_parts.append("")
    narrative_parts.append("### Overview")
    narrative_parts.append(
        f"This report summarizes the biological plausibility of the top {len(top_metabolites)} metabolites "
        f"identified by the Random Forest model as predictive of plant disease resistance. "
        f"Of these, {success_count} ({success_rate:.1f}%) were successfully mapped to known metabolic pathways."
    )
    narrative_parts.append("")
    narrative_parts.append("### Key Findings")
    
    if successful_mappings:
        narrative_parts.append("The following metabolites show strong associations and have known biological roles:")
        for i, item in enumerate(successful_mappings, 1):
            metabolite_id = item.get("metabolite_id", "Unknown")
            pathways = item.get("pathways", [])
            pathway_names = [p.get("name", "Unknown") for p in pathways]
            narrative_parts.append(
                f"{i}. **{metabolite_id}**: Associated with pathways: {', '.join(pathway_names)}."
            )
    else:
        narrative_parts.append("No metabolites were successfully mapped to known pathways in this dataset.")

    narrative_parts.append("")
    narrative_parts.append("### Biological Plausibility Discussion")
    if successful_mappings:
        narrative_parts.append(
            "The identification of these metabolites in specific pathways suggests that the plant's "
            "pre-challenge metabolic state may prime defense mechanisms. For instance, metabolites "
            "involved in phenylpropanoid biosynthesis or antioxidant production are often linked "
            "to resistance against biotic stress."
        )
    else:
        narrative_parts.append(
            "While the statistical model identifies these features as predictive, the lack of pathway "
            "mapping limits immediate biological interpretation. This may be due to the novelty of the "
            "metabolites, gaps in current databases, or the specific conditions of the study."
        )

    narrative_parts.append("")
    narrative_parts.append("### Limitations")
    narrative_parts.append(mandatory_framing)
    if failed_mappings:
        narrative_parts.append(
            f"Additionally, {len(failed_mappings)} metabolites could not be mapped to known pathways, "
            "which limits the biological context for those specific features."
        )

    full_narrative = "\n".join(narrative_parts)

    return {
        "report_text": full_narrative,
        "mandatory_framing": mandatory_framing,
        "summary": {
            "total_metabolites_analyzed": total_count,
            "successful_mappings": success_count,
            "failed_mappings": len(failed_mappings),
            "success_rate_percent": round(success_rate, 2)
        },
        "generated_at": "T026c" # Placeholder for timestamp logic if needed
    }

def save_pathway_analysis(report_data: Dict[str, Any], output_path: Path) -> None:
    """Save the final pathway analysis report to a JSON file."""
    save_json_file(output_path, report_data)
    logger.info(f"Pathway analysis report saved to {output_path}")

def main():
    """
    Main entry point for T026c: Reporting.
    Reads pathway_mappings.json and top_metabolites.json, generates a narrative report,
    and saves it to results/pathway_report.json.
    """
    logger.info("Starting T026c: Generating pathway interpretation report.")
    
    # Define paths
    top_metabolites_path = RESULTS_DIR / "top_metabolites.json"
    pathway_mappings_path = RESULTS_DIR / "pathway_mappings.json"
    output_report_path = RESULTS_DIR / "pathway_report.json"

    # Ensure results directory exists
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Load top metabolites
    try:
        top_metabolites = load_top_metabolites(top_metabolites_path)
    except FileNotFoundError:
        logger.error(f"Required input file missing: {top_metabolites_path}")
        logger.error("Ensure T026a has completed successfully.")
        sys.exit(1)

    if not top_metabolites:
        logger.warning("No top metabolites found in input file. Generating empty report.")
        top_metabolites = []

    # 2. Load pathway mappings (already aggregated from T026b)
    # We need a list of mappings corresponding to the top metabolites.
    # If T026b output is a dict, we convert it to a list for uniform processing.
    try:
        raw_mappings = load_json_file(pathway_mappings_path)
    except FileNotFoundError:
        logger.error(f"Required input file missing: {pathway_mappings_path}")
        logger.error("Ensure T026b has completed successfully.")
        sys.exit(1)

    # Normalize raw_mappings to a list of dicts
    if isinstance(raw_mappings, dict):
        pathway_mappings_list = []
        for mid, data in raw_mappings.items():
            # Ensure it has the expected structure
            if isinstance(data, dict):
                data["metabolite_id"] = data.get("metabolite_id", mid)
                pathway_mappings_list.append(data)
            else:
                pathway_mappings_list.append({"metabolite_id": mid, "pathways": [], "mapping_status": "failed"})
    elif isinstance(raw_mappings, list):
        pathway_mappings_list = raw_mappings
    else:
        logger.error(f"Unexpected format for pathway_mappings.json: {type(raw_mappings)}")
        sys.exit(1)

    # 3. Enrich and Prepare Data for Report
    # We match the top_metabolites list with the pathway_mappings_list
    # to ensure the report discusses the specific top candidates.
    enriched_metabolites = []
    for met in top_metabolites:
        met_id = met.get("metabolite_id")
        # Find corresponding mapping
        mapping_entry = next(
            (m for m in pathway_mappings_list if m.get("metabolite_id") == met_id),
            {"metabolite_id": met_id, "pathways": [], "mapping_status": "failed"}
        )
        enriched = enrich_metabolite_info(met, mapping_entry)
        enriched_metabolites.append(enriched)

    # 4. Generate Narrative Report
    # We pass the enriched list (which contains pathways) as the 'pathway_mappings' for the generator
    # The generator function expects a list of mapping objects.
    report_data = generate_narrative_report(enriched_metabolites, enriched_metabolites)

    # 5. Save Report
    save_pathway_analysis(report_data, output_report_path)

    logger.info("T026c completed successfully.")
    return report_data

if __name__ == "__main__":
    main()