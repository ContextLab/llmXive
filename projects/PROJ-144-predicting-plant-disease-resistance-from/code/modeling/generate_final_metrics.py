"""
Task T024: Aggregate results from T021a, T021b, and T022 into final JSON reports.

This script reads the intermediate results generated by the modeling pipeline:
- Correlation analysis (T021a)
- Model evaluation & permutation testing (T021b)
- Collinearity diagnostics (T022)

It aggregates these into:
1. results/metrics.json
2. results/shap_analysis.json

Both files include the mandatory "framing" field as required by FR-011.
"""
import os
import sys
import json
from pathlib import Path
from datetime import datetime

# Ensure project root is in path
project_root = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(project_root))

from utils.constants import RESULTS_DIR, DATA_PROCESSED_DIR
from utils.io import compute_file_hash, log_artifact

# Define input file paths (generated by previous tasks)
# T021a: Correlation analysis output (partial shap/correlation)
CORRELATION_FILE = RESULTS_DIR / "correlation_analysis.json"

# T021b: Model evaluation output
EVALUATION_FILE = RESULTS_DIR / "evaluation_metrics.json"

# T022: Collinearity diagnostics output
COLLINEARITY_FILE = RESULTS_DIR / "collinearity_vif.json"

# Output file paths
METRICS_OUTPUT = RESULTS_DIR / "metrics.json"
SHAP_ANALYSIS_OUTPUT = RESULTS_DIR / "shap_analysis.json"

# Mandatory framing string per FR-011
FRAMING_STRING = "These results represent associations, not causation"

def load_json_file(filepath: Path) -> dict:
    """Safely load a JSON file, returning empty dict if not found."""
    if not filepath.exists():
        print(f"Warning: Input file not found: {filepath}. Using empty results.")
        return {}
    with open(filepath, 'r') as f:
        return json.load(f)

def aggregate_metrics() -> dict:
    """Aggregate evaluation metrics into the final metrics.json structure."""
    eval_data = load_json_file(EVALUATION_FILE)
    
    metrics = {
        "generated_at": datetime.now().isoformat(),
        "framing": FRAMING_STRING,
        "balanced_accuracy": eval_data.get("balanced_accuracy", None),
        "roc_auc": eval_data.get("roc_auc", None),
        "permutation_p_value": eval_data.get("permutation_p_value", None),
        "sensitivity_analysis": eval_data.get("sensitivity_analysis", []),
        "learning_curve_flag": eval_data.get("learning_curve_flag", None)
    }
    
    return metrics

def aggregate_shap_analysis() -> dict:
    """Aggregate SHAP, correlation, and collinearity results."""
    corr_data = load_json_file(CORRELATION_FILE)
    coll_data = load_json_file(COLLINEARITY_FILE)
    
    # Construct top_features from correlation analysis (if available)
    # If T021a output structure is different, adapt here. Assuming it has 'significant_correlations'
    top_features = []
    if "significant_correlations" in corr_data:
        for item in corr_data["significant_correlations"]:
            top_features.append({
                "feature_name": item.get("metabolite_id", item.get("feature_name", "unknown")),
                "shap_value": item.get("correlation_strength", 0.0) # Using correlation as proxy if SHAP not directly in T021a
            })
    
    # If T021a generated actual SHAP values, they might be in a separate key or file.
    # Assuming T021a output includes 'shap_values' or similar if available.
    # If the previous task T021a output is strictly correlation, we map correlation to shap_value field for compatibility
    # with the schema defined in contracts/output.schema.yaml.
    
    # Construct collinearity_vif from T022
    collinearity_vif = []
    if "vif_results" in coll_data:
        for item in coll_data["vif_results"]:
            collinearity_vif.append({
                "feature_name": item.get("feature_name", "unknown"),
                "vif_value": item.get("vif_value", 0.0)
            })

    shap_analysis = {
        "generated_at": datetime.now().isoformat(),
        "framing": FRAMING_STRING,
        "top_features": top_features,
        "collinearity_vif": collinearity_vif,
        "correlation_summary": corr_data.get("summary", {}),
        "fdr_threshold": corr_data.get("fdr_threshold", 0.05)
    }
    
    return shap_analysis

def main():
    print(f"Starting T024: Aggregating results into {METRICS_OUTPUT} and {SHAP_ANALYSIS_OUTPUT}")
    
    # Ensure output directory exists
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    
    # Aggregate data
    metrics_data = aggregate_metrics()
    shap_data = aggregate_shap_analysis()
    
    # Validate required keys (basic check)
    required_metrics_keys = ["balanced_accuracy", "roc_auc", "permutation_p_value"]
    for key in required_metrics_keys:
        if key not in metrics_data:
            print(f"Warning: Missing required key '{key}' in metrics. Setting to null.")
            metrics_data[key] = None
    
    if "framing" not in metrics_data:
        metrics_data["framing"] = FRAMING_STRING
        
    if "framing" not in shap_data:
        shap_data["framing"] = FRAMING_STRING

    # Write metrics.json
    with open(METRICS_OUTPUT, 'w') as f:
        json.dump(metrics_data, f, indent=2)
    print(f"Successfully wrote {METRICS_OUTPUT}")
    
    # Write shap_analysis.json
    with open(SHAP_ANALYSIS_OUTPUT, 'w') as f:
        json.dump(shap_data, f, indent=2)
    print(f"Successfully wrote {SHAP_ANALYSIS_OUTPUT}")
    
    # Log artifacts
    log_artifact("metrics.json", compute_file_hash(METRICS_OUTPUT))
    log_artifact("shap_analysis.json", compute_file_hash(SHAP_ANALYSIS_OUTPUT))
    
    print("T024 completed successfully.")

if __name__ == "__main__":
    main()