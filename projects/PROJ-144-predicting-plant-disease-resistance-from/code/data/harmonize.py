"""
T014b: Implement label harmonization (FR-013).

This module implements the harmonization logic for disease resistance labels
based on the heterogeneity report and raw phenotype data.

Logic:
1. If heterogeneity exists (including multi-study binary scenarios):
   - Stratify labels by `measurement_method` OR apply z-scoring within study ONLY for ORDINAL labels.
2. If binary labels are present:
   - Map directly to 0/1 (Susceptible/Resistant) without z-scoring.
3. If no heterogeneity (single binary method, single study):
   - Apply global alignment logic (0/1).

Output:
- data/processed/harmonized_labels.csv
"""

import os
import sys
import json
import glob
import pandas as pd
import numpy as np
from pathlib import Path

# Add project root to path to allow relative imports if running as script
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from utils.constants import DATA_RAW_DIR, DATA_PROCESSED_DIR
from utils.exceptions import DataUnavailableError

HETEROGENEITY_REPORT_PATH = DATA_PROCESSED_DIR / "heterogeneity_report.json"
OUTPUT_PATH = DATA_PROCESSED_DIR / "harmonized_labels.csv"


def load_phenotype_files(raw_dir: Path) -> dict:
    """
    Load all phenotype CSV files from the raw directory.
    Returns a dictionary mapping study_id -> DataFrame.
    """
    phenotype_files = glob.glob(str(raw_dir / "*_phenotype.csv"))
    studies = {}
    for f_path in phenotype_files:
        # Extract study_id from filename: {study_id}_phenotype.csv
        study_id = Path(f_path).stem.replace("_phenotype", "")
        try:
            df = pd.read_csv(f_path)
            studies[study_id] = df
        except Exception as e:
            print(f"Warning: Could not load {f_path}: {e}")
    return studies


def load_heterogeneity_report(report_path: Path) -> dict:
    """Load the heterogeneity report generated by T014a."""
    if not report_path.exists():
        raise DataUnavailableError(
            f"Heterogeneity report not found at {report_path}. "
            "Run T014a (detect_label_heterogeneity) first."
        )
    with open(report_path, 'r') as f:
        return json.load(f)


def harmonize_labels(studies: dict, heterogeneity_report: dict) -> pd.DataFrame:
    """
    Apply harmonization logic based on heterogeneity report.

    Returns a unified DataFrame with columns: study_id, original_label, harmonized_label (0/1 or float).
    """
    all_records = []

    # Determine global heterogeneity status
    has_heterogeneity = heterogeneity_report.get("has_heterogeneity", False)
    heterogeneity_details = heterogeneity_report.get("details", {})

    for study_id, df in studies.items():
        study_hetero = heterogeneity_details.get(study_id, {})
        is_binary = study_hetero.get("is_binary", True)
        measurement_method = study_hetero.get("primary_method", "unknown")
        
        # Identify label column
        label_col = None
        possible_cols = ['resistance_score', 'disease_status', 'phenotype', 'label', 'binary_label']
        for col in possible_cols:
            if col in df.columns:
                label_col = col
                break
        
        if label_col is None:
            # Fallback: assume last column or specific naming
            if 'resistance' in df.columns:
                label_col = 'resistance'
            elif df.shape[1] > 1:
                label_col = df.columns[-1]
            else:
                print(f"Skipping {study_id}: No label column found.")
                continue

        # Harmonization Logic
        harmonized_vals = []
        
        # Check if the label column is actually binary (0/1 or Susceptible/Resistant)
        unique_vals = df[label_col].dropna().unique()
        is_actually_binary = (
            len(unique_vals) <= 2 and 
            (set(unique_vals).issubset({0, 1, '0', '1', 'Susceptible', 'Resistant', 'S', 'R'}))
        )

        if is_actually_binary or is_binary:
            # Binary Logic: Map directly to 0/1
            # Define mapping
            mapping = {
                0: 0, 1: 1, 
                '0': 0, '1': 1,
                'S': 0, 'Susceptible': 0, 'Susceptible': 0,
                'R': 1, 'Resistant': 1, 'Resistant': 1,
                'susceptible': 0, 'resistant': 1,
                'S': 0, 'R': 1
            }
            
            # Normalize keys to handle mixed types
            final_mapping = {}
            for k, v in mapping.items():
                if isinstance(k, str):
                    final_mapping[k.lower()] = v
                else:
                    final_mapping[k] = v

            for val in df[label_col]:
                if pd.isna(val):
                    harmonized_vals.append(np.nan)
                else:
                    # Try direct lookup
                    if val in final_mapping:
                        harmonized_vals.append(final_mapping[val])
                    elif str(val).lower() in final_mapping:
                        harmonized_vals.append(final_mapping[str(val).lower()])
                    else:
                        # Fallback for unknown binary-like values
                        # If unique values are 2, assume 0 is one class, 1 is other
                        # This is a heuristic
                        harmonized_vals.append(0) # Default fallback
        else:
            # Ordinal/Continuous Logic: Z-score within study
            # Only if heterogeneity exists or it's ordinal
            col_data = df[label_col].astype(float)
            mean_val = col_data.mean()
            std_val = col_data.std()
            
            if std_val == 0:
                # If no variance, assign 0 (neutral) or handle as constant
                harmonized_vals = [0.0] * len(df)
            else:
                harmonized_vals = (col_data - mean_val) / std_val
                harmonized_vals = harmonized_vals.tolist()

        for idx, row in df.iterrows():
            record = {
                'study_id': study_id,
                'sample_id': row.get('sample_id', f"{study_id}_{idx}"),
                'original_label': row[label_col],
                'harmonized_label': harmonized_vals[idx],
                'measurement_method': measurement_method,
                'is_binary': is_actually_binary or is_binary
            }
            all_records.append(record)

    return pd.DataFrame(all_records)


def main():
    """Main entry point for T014b."""
    print("Starting T014b: Label Harmonization")
    
    raw_path = Path(DATA_RAW_DIR)
    if not raw_path.exists():
        raise DataUnavailableError(f"Raw data directory not found: {raw_path}. Run T012b first.")

    print(f"Loading phenotype files from {raw_path}...")
    studies = load_phenotype_files(raw_path)
    
    if not studies:
        raise DataUnavailableError("No phenotype files found. Ensure T012b has downloaded data.")

    print(f"Found {len(studies)} studies.")

    print(f"Loading heterogeneity report from {HETEROGENEITY_REPORT_PATH}...")
    report = load_heterogeneity_report(HETEROGENEITY_REPORT_PATH)

    print("Harmonizing labels...")
    df_harmonized = harmonize_labels(studies, report)

    # Ensure output directory exists
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)

    print(f"Writing harmonized labels to {OUTPUT_PATH}...")
    df_harmonized.to_csv(OUTPUT_PATH, index=False)

    print(f"Successfully wrote {len(df_harmonized)} records to {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())