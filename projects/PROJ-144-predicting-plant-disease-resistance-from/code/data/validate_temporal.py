import os
import glob
import json
import sys
import pandas as pd
from typing import List, Dict, Any, Optional
from pathlib import Path

# Ensure project root is in path for imports
PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from utils.constants import RESULTS_DIR, DATA_RAW_DIR
from utils.io import log_preprocessing_step

# Keywords indicating pre-challenge/baseline data
PRE_CHALLENGE_KEYWORDS = [
    'pre-challenge', 'prechallenge', 'baseline', 'pre-inoculation',
    'pre-infection', 'control', 'time_0', 't0', 't=0', 'before_challenge'
]

def validate_temporal_consistency(
    study_metadata: Dict[str, Any],
    study_id: str
) -> Dict[str, Any]:
    """
    Validates that the study metadata indicates pre-challenge or baseline measurements.
    
    Args:
        study_metadata: Dictionary containing study info (description, variables, etc.)
        study_id: The unique identifier for the study (e.g., 'C-STUDY-XXXX')
        
    Returns:
        Dictionary with validation status and details.
    """
    result = {
        "study_id": study_id,
        "status": "VERIFIED",
        "evidence": [],
        "warnings": []
    }

    # Check description field
    description = study_metadata.get("description", "").lower()
    variables = study_metadata.get("variables", [])
    variable_names = [str(v.get("variable_name", "")).lower() for v in variables]
    
    # Combine text sources to search
    text_to_search = f"{description} {' '.join(variable_names)}"
    
    found_keywords = []
    for keyword in PRE_CHALLENGE_KEYWORDS:
        if keyword in text_to_search:
            found_keywords.append(keyword)
    
    if found_keywords:
        result["evidence"] = [
            f"Found temporal indicator: '{kw}'" for kw in found_keywords
        ]
        result["status"] = "VERIFIED"
    else:
        # No explicit temporal markers found
        result["status"] = "UNVERIFIED"
        result["warnings"] = [
            "No explicit 'pre-challenge', 'baseline', or timestamp metadata found.",
            "Assuming all provided samples are pre-challenge based on project scope, "
            "but this cannot be programmatically verified from metadata."
        ]
        
    return result

def main():
    """
    Main entry point for temporal validation.
    
    Reads raw metadata files generated by download.py, validates temporal consistency,
    and writes results to results/temporal_verification.json.
    
    If metadata is missing or insufficient, it marks the study as UNVERIFIED
    and logs it, but does NOT halt the pipeline (as per task requirements).
    """
    log_preprocessing_step("Starting temporal consistency validation")
    
    # Ensure results directory exists
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    
    verification_results = []
    studies_processed = 0
    studies_verified = 0
    studies_unverified = 0
    
    # Locate downloaded metadata files
    # Expected pattern: data/raw/study_*/metadata.json or similar
    metadata_files = glob.glob(str(DATA_RAW_DIR / "*" / "metadata.json"))
    
    if not metadata_files:
        # Try alternative pattern if download.py used a different structure
        metadata_files = glob.glob(str(DATA_RAW_DIR / "study_*" / "*.json"))
        
    if not metadata_files:
        # Fallback: check for any JSON in data/raw
        metadata_files = glob.glob(str(DATA_RAW_DIR / "*.json"))
    
    if not metadata_files:
        log_preprocessing_step("No metadata files found in data/raw. Creating empty verification report.")
        empty_report = {
            "validation_status": "NO_DATA",
            "message": "No metadata files found. Please run download.py first.",
            "studies": []
        }
        output_path = RESULTS_DIR / "temporal_verification.json"
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(empty_report, f, indent=2)
        log_preprocessing_step(f"Empty verification report written to {output_path}")
        return empty_report
    
    for meta_file in metadata_files:
        try:
            with open(meta_file, 'r', encoding='utf-8') as f:
                metadata = json.load(f)
            
            # Extract study ID
            study_id = metadata.get("study_id", metadata.get("Study_ID", "UNKNOWN"))
            
            # Run validation
            validation_result = validate_temporal_consistency(metadata, study_id)
            verification_results.append(validation_result)
            
            studies_processed += 1
            if validation_result["status"] == "VERIFIED":
                studies_verified += 1
            else:
                studies_unverified += 1
                
            log_preprocessing_step(
                f"Study {study_id}: {validation_result['status']}"
            )
            
        except Exception as e:
            log_preprocessing_step(f"Error processing {meta_file}: {str(e)}")
            verification_results.append({
                "study_id": "UNKNOWN",
                "status": "ERROR",
                "error": str(e)
            })
    
    # Compile final report
    report = {
        "validation_timestamp": pd.Timestamp.now().isoformat(),
        "summary": {
            "total_studies_processed": studies_processed,
            "verified_studies": studies_verified,
            "unverified_studies": studies_unverified,
            "error_studies": len([r for r in verification_results if r.get("status") == "ERROR"])
        },
        "studies": verification_results
    }
    
    # Write output
    output_path = RESULTS_DIR / "temporal_verification.json"
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)
        
    log_preprocessing_step(f"Temporal verification report written to {output_path}")
    
    # Log summary
    if studies_unverified > 0:
        log_preprocessing_step(
            f"WARNING: {studies_unverified} study(ies) could not be verified for pre-challenge data. "
            "They are marked as UNVERIFIED but processing will continue."
        )
    
    return report

if __name__ == "__main__":
    main()
