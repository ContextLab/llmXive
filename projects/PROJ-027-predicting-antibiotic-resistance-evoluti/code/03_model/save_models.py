"""
T027: Save trained model weights and evaluation metrics to data/models/ with version hashes.

This module loads the trained models and evaluation metrics generated by the
training and evaluation pipeline (T023c, T025, T026) and persists them to
the data/models/ directory. It generates unique version hashes based on
the input artifacts to ensure reproducibility and traceability (Constitution Principle V).
"""

import os
import sys
import json
import logging
import argparse
import hashlib
from pathlib import Path
from typing import Dict, Any, Optional
import joblib
import pandas as pd

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from utils.logging import get_logger
from utils.config import load_config, get_paths
from utils.hash_artifacts import compute_file_hash

# Configure logger
logger = get_logger(__name__)

def load_model_artifacts(model_path: Path) -> Dict[str, Any]:
    """
    Load a trained model from a .joblib file.

    Args:
        model_path: Path to the .joblib model file.

    Returns:
        Dictionary containing the loaded model object.
    """
    if not model_path.exists():
        raise FileNotFoundError(f"Model file not found: {model_path}")
    
    logger.info(f"Loading model from {model_path}")
    model_data = joblib.load(model_path)
    return model_data

def load_metrics_artifacts(metrics_path: Path) -> Dict[str, Any]:
    """
    Load evaluation metrics from a JSON file.

    Args:
        metrics_path: Path to the metrics JSON file.

    Returns:
        Dictionary containing the metrics.
    """
    if not metrics_path.exists():
        raise FileNotFoundError(f"Metrics file not found: {metrics_path}")
    
    logger.info(f"Loading metrics from {metrics_path}")
    with open(metrics_path, 'r') as f:
        metrics = json.load(f)
    return metrics

def load_feature_importance(importance_path: Path) -> pd.DataFrame:
    """
    Load feature importance data from a CSV file.

    Args:
        importance_path: Path to the feature importance CSV file.

    Returns:
        DataFrame containing feature importance rankings.
    """
    if not importance_path.exists():
        raise FileNotFoundError(f"Feature importance file not found: {importance_path}")
    
    logger.info(f"Loading feature importance from {importance_path}")
    df = pd.read_csv(importance_path)
    return df

def compute_version_hash(model_path: Path, metrics_path: Path) -> str:
    """
    Compute a version hash based on the content of model and metrics files.
    This ensures that the saved archive is uniquely identified by its inputs.

    Args:
        model_path: Path to the model file.
        metrics_path: Path to the metrics file.

    Returns:
        Hex string of the SHA256 hash.
    """
    hasher = hashlib.sha256()
    
    # Hash model content
    with open(model_path, 'rb') as f:
        hasher.update(f.read())
    
    # Hash metrics content
    with open(metrics_path, 'rb') as f:
        hasher.update(f.read())
    
    return hasher.hexdigest()[:16]

def save_model_bundle(
    model_data: Dict[str, Any],
    metrics: Dict[str, Any],
    feature_importance: Optional[pd.DataFrame],
    version_hash: str,
    output_dir: Path,
    antibiotic_class: str
) -> Path:
    """
    Save the complete model bundle including weights, metrics, and metadata.

    Args:
        model_data: The trained model object(s).
        metrics: Evaluation metrics dictionary.
        feature_importance: Optional DataFrame of feature rankings.
        version_hash: Unique hash identifying this model version.
        output_dir: Directory to save the bundle.
        antibiotic_class: Name of the antibiotic class for the model.

    Returns:
        Path to the created model bundle directory.
    """
    bundle_dir = output_dir / antibiotic_class / version_hash
    bundle_dir.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Saving model bundle to {bundle_dir}")

    # 1. Save the model weights/object
    model_file = bundle_dir / f"model_{antibiotic_class}_{version_hash}.joblib"
    joblib.dump(model_data, model_file)
    logger.info(f"Saved model weights to {model_file}")

    # 2. Save metrics
    metrics_file = bundle_dir / f"metrics_{antibiotic_class}_{version_hash}.json"
    with open(metrics_file, 'w') as f:
        json.dump(metrics, f, indent=2, default=str)
    logger.info(f"Saved metrics to {metrics_file}")

    # 3. Save feature importance if available
    if feature_importance is not None:
        importance_file = bundle_dir / f"feature_importance_{antibiotic_class}_{version_hash}.csv"
        feature_importance.to_csv(importance_file, index=False)
        logger.info(f"Saved feature importance to {importance_file}")

    # 4. Save a manifest for easy loading
    manifest = {
        "antibiotic_class": antibiotic_class,
        "version_hash": version_hash,
        "model_file": model_file.name,
        "metrics_file": metrics_file.name,
        "importance_file": importance_file.name if feature_importance is not None else None,
        "created_at": str(bundle_dir.stat().st_mtime)
    }
    manifest_file = bundle_dir / "manifest.json"
    with open(manifest_file, 'w') as f:
        json.dump(manifest, f, indent=2)
    
    return bundle_dir

def main():
    """
    Main entry point for saving trained models and metrics.
    Expects models and metrics to be in the standard locations defined by the pipeline.
    """
    config = load_config()
    paths = get_paths()
    
    # Define input/output directories
    # Assuming training output structure based on T023c/T025/T026
    # Models are typically saved in data/models/raw/ or similar temporary location before archiving
    # Metrics are typically in data/processed/metrics/
    
    # We need to find the specific output files from previous steps.
    # Since the task implies running after training/evaluation, we look for the most recent outputs
    # or specific files named by the previous tasks.
    
    # Let's assume a standard structure:
    # data/models/training_outputs/model_<class>.joblib
    # data/processed/metrics/metrics_<class>.json
    # data/processed/metrics/feature_importance_<class>.csv
    
    training_output_dir = paths.get('model_training_output', paths['data_models'])
    metrics_dir = paths.get('metrics_output', paths['data_processed'])
    final_models_dir = paths['data_models']
    
    logger.info(f"Scanning for model artifacts in {training_output_dir}")
    logger.info(f"Scanning for metrics artifacts in {metrics_dir}")

    # Identify antibiotic classes present in the data
    # We look for files matching the pattern model_<class>.joblib
    model_files = list(Path(training_output_dir).glob("model_*.joblib"))
    
    if not model_files:
        logger.error(f"No model files found in {training_output_dir}. "
                     "Ensure T023c (train_models.py) has run successfully.")
        sys.exit(1)

    # Process each model
    saved_bundles = []
    for model_file in model_files:
        antibiotic_class = model_file.stem.replace("model_", "")
        logger.info(f"Processing model for antibiotic class: {antibiotic_class}")

        # Locate corresponding metrics and importance files
        metrics_file = Path(metrics_dir) / f"metrics_{antibiotic_class}.json"
        importance_file = Path(metrics_dir) / f"feature_importance_{antibiotic_class}.csv"

        if not metrics_file.exists():
            logger.warning(f"Metrics file not found for {antibiotic_class}: {metrics_file}. "
                           "Skipping this model.")
            continue

        # Load artifacts
        try:
            model_data = load_model_artifacts(model_file)
            metrics = load_metrics_artifacts(metrics_file)
            feature_importance = None
            if importance_file.exists():
                feature_importance = load_feature_importance(importance_file)
            else:
                logger.info(f"No feature importance file found for {antibiotic_class}, skipping.")
        except Exception as e:
            logger.error(f"Failed to load artifacts for {antibiotic_class}: {e}")
            continue

        # Compute version hash
        version_hash = compute_version_hash(model_file, metrics_file)
        logger.info(f"Computed version hash for {antibiotic_class}: {version_hash}")

        # Save bundle
        try:
            bundle_path = save_model_bundle(
                model_data=model_data,
                metrics=metrics,
                feature_importance=feature_importance,
                version_hash=version_hash,
                output_dir=final_models_dir,
                antibiotic_class=antibiotic_class
            )
            saved_bundles.append(str(bundle_path))
            logger.info(f"Successfully saved model bundle for {antibiotic_class} at {bundle_path}")
        except Exception as e:
            logger.error(f"Failed to save model bundle for {antibiotic_class}: {e}")
            continue

    # Summary
    logger.info(f"Pipeline complete. Saved {len(saved_bundles)} model bundles.")
    for bundle in saved_bundles:
        logger.info(f"  - {bundle}")

if __name__ == "__main__":
    main()