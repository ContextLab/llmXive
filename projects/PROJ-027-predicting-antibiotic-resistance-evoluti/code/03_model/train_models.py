def load_filtered_matrix(file_path: str) -> pd.DataFrame:
    """Load the mechanism-blind filtered feature matrix."""
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Filtered matrix not found at {file_path}. "
                                "Run mechanism_blind_filter.py first.")
    df = pd.read_csv(file_path, index_col=0)
    logger.info(f"Loaded filtered matrix with shape {df.shape}")
    return df

def load_split_metadata(file_path: str) -> Dict[str, Any]:
    """Load metadata from split_data.py."""
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Split metadata not found at {file_path}. "
                                "Run split_data.py first.")
    with open(file_path, 'r') as f:
        return json.load(f)

def load_phylogeny_clades(tree_path: str, snp_matrix_path: str) -> pd.DataFrame:
    """
    Load clade assignments for each isolate based on the phylogenetic tree.
    This function infers clades from the tree generated by T019.
    We assume the tree has isolate IDs as tip labels.
    For simplicity in this implementation, we load a pre-computed clade mapping
    if available, or derive it from the tree structure if dendropy is available.
    Given the constraints, we assume a 'clade_assignments.csv' exists in data/processed
    generated by generate_phylogeny.py (T019) or similar, mapping isolate_id -> clade_id.
    """
    clade_file = os.path.join(os.path.dirname(tree_path), "clade_assignments.csv")
    if os.path.exists(clade_file):
        df = pd.read_csv(clade_file)
        logger.info(f"Loaded clade assignments from {clade_file}")
        return df
    else:
        # Fallback: try to infer from tree if possible, but for now raise
        raise FileNotFoundError(
            f"Clade assignments file not found at {clade_file}. "
            "Ensure generate_phylogeny.py (T019) exports clade assignments."
        )

def train_logistic_regression(X: np.ndarray, y: np.ndarray, 
                                clade_ids: np.ndarray, 
                                random_state: int) -> Tuple[LogisticRegression, Dict[str, float]]:
    """
    Train a Logistic Regression model with Phylogenetically-Blocked Cross-Validation.
    
    Strategy:
    1. Group samples by clade_id.
    2. Perform StratifiedKFold on the GROUPS (clades), not individual samples.
       This ensures that all samples from a specific clade are either in train or test,
       preventing data leakage due to phylogenetic relatedness.
    3. Standardize features using fit on train, transform on test.
    """
    logger.info("Training Logistic Regression with Phylogenetically-Blocked CV...")
    
    # We need to perform CV on the clade level
    unique_clades = np.unique(clade_ids)
    n_clades = len(unique_clades)
    
    if n_clades < 5:
        logger.warning(f"Only {n_clades} clades found. Standard CV might be unstable.")
    
    # Create a mapping from clade_id to list of sample indices
    clade_to_indices = {}
    for i, cid in enumerate(clade_ids):
        if cid not in clade_to_indices:
            clade_to_indices[cid] = []
        clade_to_indices[cid].append(i)
    
    # Prepare data for GroupKFold-like logic
    # We will iterate through folds manually to ensure stratification by phenotype at the clade level
    # However, sklearn's GroupKFold doesn't stratify. 
    # We implement a custom loop: split clades into train/test groups, ensuring class balance in y if possible.
    
    # Simple approach for this task: Use GroupKFold logic but with StratifiedKFold on clade-aggregated labels?
    # Better: StratifiedKFold on the unique clades, where the label for a clade is the majority class of its samples?
    # Or just use GroupKFold and rely on the fact that if clades are large, leakage is minimized.
    # The requirement is "Phylogenetically-Blocked CV". The strictest interpretation is:
    # No sample from a clade in the training set appears in the test set.
    
    # Let's use a custom CV splitter that respects clades.
    # We will use StratifiedKFold on the unique clades, treating each clade as a "sample" with a label
    # (e.g., the proportion of resistant isolates in that clade).
    
    # For simplicity and robustness in this implementation:
    # We will use GroupKFold logic but ensure we don't leak.
    # Since we need to report a single metric, we will do 5-fold CV on clades.
    
    n_splits = min(5, n_clades)
    if n_splits < 2:
        raise ValueError("Not enough clades to perform cross-validation.")
    
    # Create a list of (train_clade_indices, test_clade_indices)
    # We want to stratify the clades by the dominant phenotype in the clade?
    # Let's compute a clade-level label: 1 if >50% resistant, else 0.
    clade_labels = {}
    for cid in unique_clades:
        indices = clade_to_indices[cid]
        y_clade = y[indices]
        clade_labels[cid] = 1 if np.mean(y_clade) > 0.5 else 0
    
    clade_ids_list = list(unique_clades)
    clade_labels_arr = np.array([clade_labels[cid] for cid in clade_ids_list])
    
    # StratifiedKFold on clades
    skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=random_state)
    
    auc_scores = []
    
    for fold, (train_clade_idxs, test_clade_idxs) in enumerate(skf.split(clade_ids_list, clade_labels_arr)):
        logger.debug(f"Fold {fold}: Train clades={len(train_clade_idxs)}, Test clades={len(test_clade_idxs)}")
        
        # Map clade indices back to sample indices
        train_sample_idxs = []
        test_sample_idxs = []
        
        for idx in train_clade_idxs:
            cid = clade_ids_list[idx]
            train_sample_idxs.extend(clade_to_indices[cid])
        
        for idx in test_clade_idxs:
            cid = clade_ids_list[idx]
            test_sample_idxs.extend(clade_to_indices[cid])
        
        train_sample_idxs = np.array(train_sample_idxs)
        test_sample_idxs = np.array(test_sample_idxs)
        
        X_train, X_test = X[train_sample_idxs], X[test_sample_idxs]
        y_train, y_test = y[train_sample_idxs], y[test_sample_idxs]
        
        # Scale
        scaler = StandardScaler()
        X_train_scaled = scaler.fit_transform(X_train)
        X_test_scaled = scaler.transform(X_test)
        
        # Train
        model = LogisticRegression(penalty='l1', solver='liblinear', random_state=random_state, max_iter=1000)
        model.fit(X_train_scaled, y_train)
        
        # Evaluate
        y_pred_proba = model.predict_proba(X_test_scaled)[:, 1]
        try:
            auc = roc_auc_score(y_test, y_pred_proba)
            auc_scores.append(auc)
            logger.debug(f"Fold {fold} AUC: {auc:.4f}")
        except Exception as e:
            logger.warning(f"Fold {fold} AUC calculation failed: {e}")
    
    avg_auc = np.mean(auc_scores)
    std_auc = np.std(auc_scores)
    logger.info(f"Logistic Regression CV AUC: {avg_auc:.4f} (+/- {std_auc:.4f})")
    
    # Retrain on full data for final model
    scaler_full = StandardScaler()
    X_scaled_full = scaler_full.fit_transform(X)
    final_model = LogisticRegression(penalty='l1', solver='liblinear', random_state=random_state, max_iter=1000)
    final_model.fit(X_scaled_full, y)
    
    metrics = {
        "cv_auc_mean": float(avg_auc),
        "cv_auc_std": float(std_auc),
        "n_folds": n_splits
    }
    
    return final_model, metrics

def train_random_forest(X: np.ndarray, y: np.ndarray,
                        clade_ids: np.ndarray,
                        random_state: int) -> Tuple[RandomForestClassifier, Dict[str, float]]:
    """
    Train a Random Forest model with Phylogenetically-Blocked Cross-Validation.
    Similar logic to Logistic Regression: split by clade.
    """
    logger.info("Training Random Forest with Phylogenetically-Blocked CV...")
    
    unique_clades = np.unique(clade_ids)
    n_clades = len(unique_clades)
    n_splits = min(5, n_clades)
    
    if n_splits < 2:
        raise ValueError("Not enough clades to perform cross-validation.")
    
    clade_to_indices = {}
    for i, cid in enumerate(clade_ids):
        if cid not in clade_to_indices:
            clade_to_indices[cid] = []
        clade_to_indices[cid].append(i)
    
    # Clade-level labels for stratification
    clade_labels = {}
    for cid in unique_clades:
        indices = clade_to_indices[cid]
        y_clade = y[indices]
        clade_labels[cid] = 1 if np.mean(y_clade) > 0.5 else 0
    
    clade_ids_list = list(unique_clades)
    clade_labels_arr = np.array([clade_labels[cid] for cid in clade_ids_list])
    
    skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=random_state)
    
    auc_scores = []
    
    for fold, (train_clade_idxs, test_clade_idxs) in enumerate(skf.split(clade_ids_list, clade_labels_arr)):
        train_sample_idxs = []
        test_sample_idxs = []
        
        for idx in train_clade_idxs:
            cid = clade_ids_list[idx]
            train_sample_idxs.extend(clade_to_indices[cid])
        
        for idx in test_clade_idxs:
            cid = clade_ids_list[idx]
            test_sample_idxs.extend(clade_to_indices[cid])
        
        train_sample_idxs = np.array(train_sample_idxs)
        test_sample_idxs = np.array(test_sample_idxs)
        
        X_train, X_test = X[train_sample_idxs], X[test_sample_idxs]
        y_train, y_test = y[train_sample_idxs], y[test_sample_idxs]
        
        # RF does not need scaling
        model = RandomForestClassifier(n_estimators=100, random_state=random_state, n_jobs=-1)
        model.fit(X_train, y_train)
        
        y_pred_proba = model.predict_proba(X_test)[:, 1]
        try:
            auc = roc_auc_score(y_test, y_pred_proba)
            auc_scores.append(auc)
            logger.debug(f"Fold {fold} AUC: {auc:.4f}")
        except Exception as e:
            logger.warning(f"Fold {fold} AUC calculation failed: {e}")
    
    avg_auc = np.mean(auc_scores)
    std_auc = np.std(auc_scores)
    logger.info(f"Random Forest CV AUC: {avg_auc:.4f} (+/- {std_auc:.4f})")
    
    # Retrain on full data
    final_model = RandomForestClassifier(n_estimators=100, random_state=random_state, n_jobs=-1)
    final_model.fit(X, y)
    
    metrics = {
        "cv_auc_mean": float(avg_auc),
        "cv_auc_std": float(std_auc),
        "n_folds": n_splits
    }
    
    return final_model, metrics

def train_models_for_class(antibiotic_class: str, 
                           feature_matrix: pd.DataFrame, 
                           clade_df: pd.DataFrame,
                           output_dir: str,
                           random_state: int) -> None:
    """
    Train models for a specific antibiotic class.
    """
    logger.info(f"Processing antibiotic class: {antibiotic_class}")
    
    # Filter for this class
    # Assume feature_matrix has columns: isolate_id, resistance_phenotype (for this class), gene_1, gene_2, ...
    # We need to find the column for the resistance phenotype of this class.
    # Based on build_feature_matrix.py, the phenotype column might be named like 'resistance_ciprofloxacin'
    # or we need to map the class name.
    # For this implementation, we assume the phenotype column is named 'resistance_phenotype_{class_name}'
    # or the dataframe is already subsetted per class. 
    # Given T016 output: "resistance_phenotype" column. If multiple classes exist, they might be in separate rows or columns?
    # T016 says: "Binary gene columns, Numeric SNP counts, Numeric CNV counts" and "resistance_phenotype".
    # If multiple classes, the pipeline likely runs this script multiple times or the dataframe has multiple phenotype columns.
    # Let's assume the dataframe has a column named 'resistance_phenotype' and we are training on one class at a time,
    # implying the dataframe passed here is already filtered or the phenotype column is specific.
    # To be safe, we look for a column matching the class name pattern.
    
    phenotype_col = None
    possible_cols = [c for c in feature_matrix.columns if 'resistance' in c.lower() and antibiotic_class.lower() in c.lower()]
    if not possible_cols:
        # Fallback to generic if only one exists
        possible_cols = [c for c in feature_matrix.columns if 'resistance' in c.lower()]
    
    if possible_cols:
        phenotype_col = possible_cols[0]
    else:
        raise ValueError(f"No phenotype column found for class {antibiotic_class}")
    
    # Prepare X and y
    # Drop phenotype and isolate_id for X
    X_cols = [c for c in feature_matrix.columns if c not in [phenotype_col, 'isolate_id']]
    X = feature_matrix[X_cols].values
    y = feature_matrix[phenotype_col].values
    isolate_ids = feature_matrix['isolate_id'].values
    
    # Map isolate_ids to clade_ids
    # clade_df should have 'isolate_id' and 'clade_id'
    clade_map = clade_df.set_index('isolate_id')['clade_id'].to_dict()
    clade_ids = np.array([clade_map.get(sid, -1) for sid in isolate_ids])
    
    if np.any(clade_ids == -1):
        logger.warning("Some isolates missing clade assignments. They will be excluded or assigned to a dummy clade.")
        # For now, assign missing to a unique dummy clade to avoid crashing
        # But better to exclude them from training to be safe?
        # We'll keep them but they might form their own clade.
    
    # Train LR
    try:
        lr_model, lr_metrics = train_logistic_regression(X, y, clade_ids, random_state)
        # Save LR model
        lr_path = os.path.join(output_dir, f"lr_model_{antibiotic_class}.pkl")
        import joblib
        joblib.dump(lr_model, lr_path)
        logger.info(f"Saved LR model to {lr_path}")
    except Exception as e:
        logger.error(f"Failed to train LR for {antibiotic_class}: {e}")
        lr_metrics = {}
    
    # Train RF
    try:
        rf_model, rf_metrics = train_random_forest(X, y, clade_ids, random_state)
        rf_path = os.path.join(output_dir, f"rf_model_{antibiotic_class}.pkl")
        import joblib
        joblib.dump(rf_model, rf_path)
        logger.info(f"Saved RF model to {rf_path}")
    except Exception as e:
        logger.error(f"Failed to train RF for {antibiotic_class}: {e}")
        rf_metrics = {}
    
    # Save metrics
    metrics_file = os.path.join(output_dir, f"metrics_{antibiotic_class}.json")
    with open(metrics_file, 'w') as f:
        json.dump({
            "logistic_regression": lr_metrics,
            "random_forest": rf_metrics
        }, f, indent=2)
    logger.info(f"Saved metrics to {metrics_file}")

def main():
    parser = argparse.ArgumentParser(description="Train models with Phylogenetically-Blocked CV")
    parser.add_argument("--config", type=str, default="config.yaml", help="Path to config file")
    parser.add_argument("--input-matrix", type=str, required=True, help="Path to mechanism-blind filtered matrix")
    parser.add_argument("--clade-file", type=str, required=True, help="Path to clade assignments CSV")
    parser.add_argument("--output-dir", type=str, required=True, help="Output directory for models and metrics")
    args = parser.parse_args()
    
    init_pipeline_logging()
    config = load_config(args.config)
    random_state = get_random_seed(config)
    
    os.makedirs(args.output_dir, exist_ok=True)
    
    logger.info(f"Loading data from {args.input_matrix}")
    feature_matrix = load_filtered_matrix(args.input_matrix)
    
    logger.info(f"Loading clade assignments from {args.clade_file}")
    clade_df = load_phylogeny_clades(args.clade_file, args.input_matrix)
    
    # Identify antibiotic classes
    # Assuming phenotype columns are named like 'resistance_ciprofloxacin', 'resistance_amoxicillin'
    phenotype_cols = [c for c in feature_matrix.columns if c.startswith('resistance_')]
    
    if not phenotype_cols:
        # Try to find a single 'resistance_phenotype' column if the data is already split per class in rows?
        # T016 says "resistance_phenotype". If it's a single column, we might need to know which class we are training on.
        # The task says "per antibiotic class".
        # We assume the matrix has multiple phenotype columns.
        raise ValueError("No resistance phenotype columns found in the matrix.")
    
    for col in phenotype_cols:
        class_name = col.replace('resistance_', '').replace('phenotype_', '')
        train_models_for_class(class_name, feature_matrix, clade_df, args.output_dir, random_state)
    
    logger.info("Model training completed.")

if __name__ == "__main__":
    main()