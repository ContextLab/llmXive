"""
Contract test for the feature matrix schema generated by US1.

Verifies that data/processed/feature_matrix.csv contains the required columns
and data types as specified in the project requirements.

Required columns:
- isolate_id (string)
- gene_presence_matrix (list or encoded string)
- snp_counts (numeric)
- cnv_counts (numeric)
- resistance_phenotype (string/boolean)
"""
import os
import sys
import pytest
import pandas as pd
from pathlib import Path

# Add code directory to path for imports if needed
code_dir = Path(__file__).parent.parent.parent / "code"
if str(code_dir) not in sys.path:
    sys.path.insert(0, str(code_dir))

from utils.logging import get_logger

logger = get_logger(__name__)

FEATURE_MATRIX_PATH = Path("data/processed/feature_matrix.csv")
REQUIRED_COLUMNS = [
    "isolate_id",
    "gene_presence_matrix",
    "snp_counts",
    "cnv_counts",
    "resistance_phenotype"
]

def check_file_exists():
    """Verify the feature matrix file exists."""
    assert FEATURE_MATRIX_PATH.exists(), f"Feature matrix file not found at {FEATURE_MATRIX_PATH}"

def load_feature_matrix():
    """Load the feature matrix CSV."""
    check_file_exists()
    try:
        df = pd.read_csv(FEATURE_MATRIX_PATH)
        return df
    except Exception as e:
        pytest.fail(f"Failed to load feature matrix: {e}")

def test_required_columns_present():
    """Test that all required columns are present in the schema."""
    df = load_feature_matrix()
    missing_columns = set(REQUIRED_COLUMNS) - set(df.columns)
    assert not missing_columns, f"Missing required columns: {missing_columns}"
    logger.info("All required columns present in feature matrix.")

def test_isolate_id_column_type():
    """Test that isolate_id column contains string values."""
    df = load_feature_matrix()
    assert df["isolate_id"].dtype == "object" or df["isolate_id"].dtype == "string", \
        f"isolate_id should be string type, got {df['isolate_id'].dtype}"
    assert not df["isolate_id"].isnull().any(), "isolate_id contains null values"

def test_resistance_phenotype_column_type():
    """Test that resistance_phenotype column exists and is non-null."""
    df = load_feature_matrix()
    assert df["resistance_phenotype"].notnull().all(), \
        "resistance_phenotype contains null values"
    logger.info("resistance_phenotype column validated.")

def test_numeric_columns_valid():
    """Test that snp_counts and cnv_counts are numeric."""
    df = load_feature_matrix()
    for col in ["snp_counts", "cnv_counts"]:
        assert pd.api.types.is_numeric_dtype(df[col]), \
            f"{col} should be numeric type, got {df[col].dtype}"
        assert not df[col].isnull().any(), f"{col} contains null values"
    logger.info("Numeric columns validated.")

def test_gene_presence_matrix_format():
    """Test that gene_presence_matrix column exists and is not empty."""
    df = load_feature_matrix()
    assert "gene_presence_matrix" in df.columns, "gene_presence_matrix column missing"
    # Check that it's not entirely empty/null
    assert not df["gene_presence_matrix"].isnull().all(), \
        "gene_presence_matrix column is entirely null"
    logger.info("gene_presence_matrix column validated.")

def test_row_count_matches_isolates():
    """Test that the number of rows matches the number of unique isolates."""
    df = load_feature_matrix()
    unique_isolates = df["isolate_id"].nunique()
    total_rows = len(df)
    assert unique_isolates == total_rows, \
        f"Row count ({total_rows}) does not match unique isolate count ({unique_isolates})"
    logger.info(f"Row count validated: {total_rows} isolates.")

if __name__ == "__main__":
    pytest.main([__file__, "-v"])
