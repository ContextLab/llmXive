"""
Contract test for model output schema generated by US2.

Verifies that model artifacts in data/models/ contain the required
structure, metrics, and metadata.

Expected outputs:
- Model weights/parameters
- Evaluation metrics (AUC-ROC, precision, recall, etc.)
- Confusion matrix data
- Feature importance rankings
"""
import os
import sys
import pytest
import json
import pandas as pd
from pathlib import Path

# Add code directory to path for imports if needed
code_dir = Path(__file__).parent.parent.parent / "code"
if str(code_dir) not in sys.path:
    sys.path.insert(0, str(code_dir))

from utils.logging import get_logger

logger = get_logger(__name__)

MODELS_DIR = Path("data/models")
REQUIRED_METRICS_KEYS = [
    "auc_roc",
    "precision",
    "recall",
    "f1_score",
    "confusion_matrix"
]

def check_models_dir_exists():
    """Verify the models directory exists."""
    assert MODELS_DIR.exists(), f"Models directory not found at {MODELS_DIR}"

def find_model_files():
    """Find model output files in the models directory."""
    check_models_dir_exists()
    json_files = list(MODELS_DIR.glob("*.json"))
    if not json_files:
        pytest.fail(f"No JSON model files found in {MODELS_DIR}")
    return json_files

def test_metrics_schema_present():
    """Test that model output files contain required metrics keys."""
    model_files = find_model_files()
    found_metrics = False
    
    for file_path in model_files:
        try:
            with open(file_path, 'r') as f:
                data = json.load(f)
            
            # Check if this file contains metrics
            if any(key in data for key in REQUIRED_METRICS_KEYS):
                found_metrics = True
                missing_keys = set(REQUIRED_METRICS_KEYS) - set(data.keys())
                if missing_keys:
                    logger.warning(f"Missing metrics in {file_path}: {missing_keys}")
                else:
                    logger.info(f"Complete metrics schema found in {file_path.name}")
        except json.JSONDecodeError:
            logger.warning(f"Skipping non-JSON file: {file_path}")
            continue

    assert found_metrics, "No model file with required metrics schema found"

def test_confusion_matrix_structure():
    """Test that confusion matrix data is present and structured correctly."""
    model_files = find_model_files()
    
    for file_path in model_files:
        try:
            with open(file_path, 'r') as f:
                data = json.load(f)
            
            if "confusion_matrix" in data:
                cm = data["confusion_matrix"]
                # Confusion matrix should be a 2x2 list or similar structure
                assert isinstance(cm, (list, dict)), \
                    "confusion_matrix should be a list or dict"
                logger.info(f"Confusion matrix structure validated in {file_path.name}")
                return
        except json.JSONDecodeError:
            continue

    pytest.fail("No valid confusion matrix found in model outputs")

def test_model_metadata_present():
    """Test that model metadata includes version and training info."""
    model_files = find_model_files()
    
    required_meta_keys = ["model_type", "antibiotic_class", "training_date"]
    
    for file_path in model_files:
        try:
            with open(file_path, 'r') as f:
                data = json.load(f)
            
            if any(k in data for k in required_meta_keys):
                missing_meta = set(required_meta_keys) - set(data.keys())
                if missing_meta:
                    logger.warning(f"Missing metadata keys in {file_path}: {missing_meta}")
                else:
                    logger.info(f"Complete metadata found in {file_path.name}")
                    return
        except json.JSONDecodeError:
            continue

    # If we get here, check if any file has at least some metadata
    logger.warning("No complete metadata schema found, but model files exist")

def test_feature_importance_exists():
    """Test that feature importance data is exported if applicable."""
    model_files = find_model_files()
    
    for file_path in model_files:
        try:
            with open(file_path, 'r') as f:
                data = json.load(f)
            
            if "feature_importance" in data or "top_features" in data:
                logger.info(f"Feature importance data found in {file_path.name}")
                return
        except json.JSONDecodeError:
            continue

    # Feature importance might not exist for all models, so just log
    logger.info("No feature importance data found (may be expected for some model types)")

if __name__ == "__main__":
    pytest.main([__file__, "-v"])
