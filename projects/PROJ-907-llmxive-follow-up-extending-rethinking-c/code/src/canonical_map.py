"""
Derive the Canonical Routing Map from clustering results.

This module reads the cluster centers and null hypothesis flags generated by
src/clustering.py and constructs a static routing map. For blocks where
clustering was valid, it uses the dominant cluster center. For blocks where
the null hypothesis was triggered (low silhouette or <2 clusters), it uses
the pre-computed global average vector.
"""

import json
import logging
import os
import sys
from pathlib import Path
from typing import Dict, Any, List, Optional

# Ensure we can import from the project root if running as script
if __name__ == "__main__":
    # Add parent directory to path for imports when running as script
    sys.path.insert(0, str(Path(__file__).parent.parent))

from src.config import get_routing_cache_path, get_results_path
from src.utils import cleanup_memory

logger = logging.getLogger(__name__)


def derive_canonical_map(cluster_centers_path: Optional[Path] = None) -> Dict[str, List[float]]:
    """
    Derive the canonical routing map from cluster analysis results.

    Args:
        cluster_centers_path: Path to the cluster_centers.json file. If None,
            uses the default path from config.

    Returns:
        A dictionary mapping block names (e.g., "block_0") to their static
        weight vectors (lists of floats).

    Raises:
        FileNotFoundError: If the cluster centers file does not exist.
        ValueError: If the cluster centers file is malformed or missing required fields.
    """
    if cluster_centers_path is None:
        cluster_centers_path = get_routing_cache_path() / "cluster_centers.json"

    if not cluster_centers_path.exists():
        raise FileNotFoundError(f"Cluster centers file not found: {cluster_centers_path}")

    logger.info(f"Loading cluster centers from {cluster_centers_path}")
    with open(cluster_centers_path, 'r') as f:
        cluster_data = json.load(f)

    canonical_map = {}
    num_blocks = len(cluster_data)

    if num_blocks == 0:
        logger.warning("No blocks found in cluster centers. Returning empty map.")
        return canonical_map

    # Determine the expected history_dim from the first block
    first_block_key = next(iter(cluster_data))
    first_block_data = cluster_data[first_block_key]
    
    # Check if centers are present (valid clustering) or if null hypothesis triggered
    if "centers" in first_block_data and first_block_data["centers"]:
        # Use the first center's dimension as reference
        reference_dim = len(first_block_data["centers"][0]) if isinstance(first_block_data["centers"][0], list) else 1
    else:
        # If null hypothesis, check for global_average
        if "global_average" in first_block_data:
            reference_dim = len(first_block_data["global_average"])
        else:
            # Fallback: assume a reasonable default or raise error
            logger.error("Could not determine vector dimension from cluster data.")
            raise ValueError("Invalid cluster data format: missing centers and global_average")

    logger.info(f"Deriving canonical map for {num_blocks} blocks (expected dim: {reference_dim})")

    for block_key in sorted(cluster_data.keys()):
        block_info = cluster_data[block_key]
        
        if not isinstance(block_info, dict):
            raise ValueError(f"Invalid data format for block {block_key}: expected dict, got {type(block_info)}")

        # Determine if null hypothesis was triggered
        null_triggered = block_info.get("null_hypothesis_triggered", False)
        
        if null_triggered:
            # Use the global average vector
            if "global_average" not in block_info:
                logger.error(f"Block {block_key} triggered null hypothesis but missing global_average.")
                # Fallback to zeros if global_average is missing (should not happen if T012 is correct)
                static_vector = [0.0] * reference_dim
            else:
                static_vector = [float(x) for x in block_info["global_average"]]
            logger.debug(f"Block {block_key}: Using global average (null hypothesis).")
        else:
            # Use the dominant cluster center (first one in the list)
            if "centers" not in block_info or not block_info["centers"]:
                logger.error(f"Block {block_key} has no centers and null hypothesis not triggered.")
                static_vector = [0.0] * reference_dim
            else:
                # Take the first center as the dominant one (T012 logic should ensure this is valid)
                dominant_center = block_info["centers"][0]
                static_vector = [float(x) for x in dominant_center]
            logger.debug(f"Block {block_key}: Using dominant cluster center.")

        # Validate dimension
        if len(static_vector) != reference_dim:
            logger.warning(f"Block {block_key} vector dimension {len(static_vector)} differs from reference {reference_dim}. Padding or truncating.")
            if len(static_vector) < reference_dim:
                static_vector += [0.0] * (reference_dim - len(static_vector))
            else:
                static_vector = static_vector[:reference_dim]

        canonical_map[block_key] = static_vector

    logger.info(f"Derived canonical map with {len(canonical_map)} blocks.")
    return canonical_map


def save_canonical_map(canonical_map: Dict[str, List[float]], output_path: Optional[Path] = None) -> Path:
    """
    Save the canonical routing map to a JSON file.

    Args:
        canonical_map: The derived canonical map dictionary.
        output_path: Path to save the JSON file. If None, uses default path.

    Returns:
        The path where the file was saved.
    """
    if output_path is None:
        output_path = get_routing_cache_path() / "canonical_map.json"

    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    logger.info(f"Saving canonical map to {output_path}")
    with open(output_path, 'w') as f:
        json.dump(canonical_map, f, indent=2)

    logger.info(f"Saved canonical map to {output_path}")
    return output_path


def main():
    """
    Main entry point for deriving and saving the canonical routing map.
    """
    # Configure logging
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )

    try:
        # Ensure required directories exist
        get_routing_cache_path().mkdir(parents=True, exist_ok=True)
        get_results_path().mkdir(parents=True, exist_ok=True)

        # Derive the canonical map
        canonical_map = derive_canonical_map()

        if not canonical_map:
            logger.error("Canonical map is empty. Aborting.")
            sys.exit(1)

        # Save the map
        save_path = save_canonical_map(canonical_map)

        # Verify output
        if not save_path.exists():
            logger.error("Failed to create output file.")
            sys.exit(1)

        # Validate schema
        with open(save_path, 'r') as f:
            loaded_map = json.load(f)
        
        if not isinstance(loaded_map, dict):
            logger.error("Output is not a dictionary.")
            sys.exit(1)

        logger.info(f"Successfully derived and saved canonical map with {len(loaded_map)} blocks.")
        logger.info(f"Output path: {save_path}")

    except FileNotFoundError as e:
        logger.error(f"Required input file missing: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}", exc_info=True)
        sys.exit(1)
    finally:
        cleanup_memory()


if __name__ == "__main__":
    main()
