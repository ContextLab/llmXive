"""
canonical_map.py

Derives the "Canonical Routing Map" (static weight vector per block) from the
dominant cluster or global average for each block, based on the clustering
results generated by T012.

This script reads `data/routing_cache/cluster_centers.json`, extracts the
representative vector for each block (either the dominant cluster center or
the global average if the null hypothesis was triggered), and saves the
resulting static map to `data/routing_cache/canonical_map.json`.
"""

import json
import logging
import os
import sys
from pathlib import Path
from typing import Dict, Any, List, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s",
    handlers=[logging.StreamHandler(sys.stdout)]
)
logger = logging.getLogger(__name__)

# Project paths
PROJECT_ROOT = Path(__file__).resolve().parent.parent
CLUSTER_CENTERS_PATH = PROJECT_ROOT / "data" / "routing_cache" / "cluster_centers.json"
CANONICAL_MAP_PATH = PROJECT_ROOT / "data" / "routing_cache" / "canonical_map.json"


def derive_canonical_map(
    cluster_centers_data: Dict[str, Any],
    num_blocks: Optional[int] = None
) -> Dict[str, List[float]]:
    """
    Derives the canonical routing map from clustering results.

    For each block:
    - If `null_hypothesis_triggered` is False, selects the dominant cluster center.
      (If multiple centers exist, we pick the first one as the representative
      static weight for this research phase, or could pick the largest cluster.
      Given the task description "dominant cluster or global average", and the
      output schema requiring a single vector, we select the first center listed
      if null_hypothesis is false, assuming it represents the primary mode.
      Alternatively, if the clustering logic in T012 produced a specific 'dominant'
      indicator, we would use that. Since T012 output structure is `{"block_X": {"centers": [...], ...}}`,
      and we need a single vector, we will select the first center in the list
      if null_hypothesis is False.
      *Correction*: The task says "dominant cluster". If T012 returns a list of centers,
      we need to know which one is dominant. If T012 didn't explicitly mark one,
      we assume the first one (or the one with the largest cluster size if that info exists).
      However, looking at the T012 verification: "centers field contains the exact global average vector".
      If null_hypothesis is false, we have multiple clusters. We will pick the first center
      as the representative for the static map, as is common when a specific "dominant"
      label isn't provided in the JSON structure described.
      *Refinement*: To be robust, if `centers` is a list, we take `centers[0]`.
      If `null_hypothesis_triggered` is True, we take the `centers` value (which should be the global average).

    Args:
        cluster_centers_data: Dictionary loaded from cluster_centers.json.
        num_blocks: Expected number of blocks (optional, for validation).

    Returns:
        Dictionary mapping block names to their static weight vectors.
    """
    canonical_map = {}
    expected_block_count = 0

    # Sort keys to ensure deterministic ordering (block_0, block_1, ...)
    sorted_keys = sorted(cluster_centers_data.keys())

    if num_blocks is not None:
        if len(sorted_keys) != num_blocks:
            logger.warning(
                f"Discrepancy in block count: Expected {num_blocks}, "
                f"found {len(sorted_keys)} in cluster_centers_data."
            )
        expected_block_count = num_blocks

    for block_key in sorted_keys:
        block_data = cluster_centers_data[block_key]
        centers = block_data.get("centers")
        null_triggered = block_data.get("null_hypothesis_triggered", False)
        null_reason = block_data.get("null_reason")

        if centers is None:
            raise ValueError(f"Missing 'centers' field for {block_key}")

        if null_triggered:
            # Use the global average vector provided in centers
            # The T012 spec says centers contains the global average vector in this case.
            # It might be a single vector or a list with one vector.
            if isinstance(centers, list):
                if len(centers) == 0:
                    raise ValueError(f"No centers found for {block_key} despite null hypothesis.")
                # If it's a list of vectors (unlikely for global avg), pick the first.
                # If it's a single vector, it might be wrapped in a list or just the vector.
                # T012 spec: "centers field contains the exact global average vector".
                # Assuming it's a list of vectors where the list has 1 item, or just the vector.
                # Let's handle both: if centers is a list of lists, take the first.
                # If centers is a list of floats, take it as is.
                if len(centers) > 0 and isinstance(centers[0], (int, float)):
                    # It's a single vector
                    vector = [float(x) for x in centers]
                else:
                    # It's a list of vectors, take the first one
                    vector = [float(x) for x in centers[0]]
            else:
                # It's a single vector directly
                vector = [float(x) for x in centers]
            
            logger.info(f"Block {block_key}: Null hypothesis triggered. Using global average.")
            if null_reason:
                logger.debug(f"  Reason: {null_reason}")
        else:
            # Use the dominant cluster center
            # Assuming centers is a list of vectors. We pick the first one as dominant.
            if isinstance(centers, list):
                if len(centers) == 0:
                    raise ValueError(f"No centers found for {block_key} despite valid clustering.")
                # Check if the first element is a vector or a list of vectors
                if isinstance(centers[0], (int, float)):
                    vector = [float(x) for x in centers]
                else:
                    # List of vectors, pick the first
                    vector = [float(x) for x in centers[0]]
            else:
                # Single vector
                vector = [float(x) for x in centers]
            
            logger.info(f"Block {block_key}: Using dominant cluster center (index 0).")

        canonical_map[block_key] = vector

    return canonical_map


def save_canonical_map(canonical_map: Dict[str, List[float]], output_path: Path) -> None:
    """
    Saves the canonical map to a JSON file.

    Args:
        canonical_map: The derived canonical map dictionary.
        output_path: Path to the output JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(canonical_map, f, indent=2)
    
    logger.info(f"Canonical map saved to {output_path}")


def main() -> int:
    """
    Main entry point for deriving and saving the canonical routing map.
    """
    logger.info("Starting Canonical Map derivation...")

    # Check input file existence
    if not CLUSTER_CENTERS_PATH.exists():
        logger.error(
            f"Input file not found: {CLUSTER_CENTERS_PATH}. "
            "Please ensure T012 (clustering.py) has been run successfully."
        )
        return 1

    # Load cluster centers
    try:
        with open(CLUSTER_CENTERS_PATH, 'r', encoding='utf-8') as f:
            cluster_centers_data = json.load(f)
        logger.info(f"Loaded cluster centers from {CLUSTER_CENTERS_PATH}")
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse JSON from {CLUSTER_CENTERS_PATH}: {e}")
        return 1
    except Exception as e:
        logger.error(f"Failed to load cluster centers: {e}")
        return 1

    # Determine number of blocks from the data
    num_blocks = len(cluster_centers_data)
    if num_blocks == 0:
        logger.error("No blocks found in cluster_centers_data.")
        return 1

    logger.info(f"Processing {num_blocks} blocks...")

    # Derive canonical map
    try:
        canonical_map = derive_canonical_map(cluster_centers_data, num_blocks)
    except Exception as e:
        logger.error(f"Failed to derive canonical map: {e}")
        return 1

    # Save canonical map
    try:
        save_canonical_map(canonical_map, CANONICAL_MAP_PATH)
    except Exception as e:
        logger.error(f"Failed to save canonical map: {e}")
        return 1

    logger.info("Canonical Map derivation completed successfully.")
    return 0


if __name__ == "__main__":
    sys.exit(main())