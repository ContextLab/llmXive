"""
Memory Report Generator for llmXive Project.

This script parses the memory profile data generated by T011 (tracing.py)
and generates a human-readable Markdown report at docs/memory_report.md.

It references data/results/memory_profile.json to summarize peak memory usage
and OOM prevention efficacy.
"""
import json
import os
import sys
from pathlib import Path
from typing import Dict, Any, Optional

# Project root relative to this script (assuming code/src/)
PROJECT_ROOT = Path(__file__).parent.parent
MEMORY_PROFILE_PATH = PROJECT_ROOT / "data" / "results" / "memory_profile.json"
OUTPUT_REPORT_PATH = PROJECT_ROOT / "docs" / "memory_report.md"

def load_memory_profile(path: Path) -> Optional[Dict[str, Any]]:
    """Load the memory profile JSON file."""
    if not path.exists():
        print(f"Error: Memory profile file not found at {path}", file=sys.stderr)
        return None
    
    try:
        with open(path, 'r', encoding='utf-8') as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        print(f"Error: Failed to parse JSON in {path}: {e}", file=sys.stderr)
        return None
    except Exception as e:
        print(f"Error: Failed to read {path}: {e}", file=sys.stderr)
        return None

def generate_markdown_report(profile: Dict[str, Any]) -> str:
    """Generate the Markdown report content based on the memory profile."""
    lines = []
    lines.append("# Memory Usage Report")
    lines.append("")
    lines.append("## Overview")
    lines.append("")
    lines.append("This report summarizes the memory usage statistics and OOM prevention efficacy")
    lines.append("for the SiT-XL tracing execution (Task T011) on the llmXive pipeline.")
    lines.append("")
    
    status = profile.get("status", "UNKNOWN")
    within_limit = profile.get("within_limit", False)
    
    lines.append("## Execution Status")
    lines.append("")
    if status == "PASS":
        lines.append(f"- **Status**: ✅ PASS")
        lines.append("- **Memory Limit**: The execution stayed within the 7GB RAM limit.")
    elif status == "FAIL":
        lines.append(f"- **Status**: ❌ FAIL")
        lines.append("- **Memory Limit**: The execution exceeded the 7GB RAM limit or encountered a MemoryError.")
    else:
        lines.append(f"- **Status**: ⚠️ {status}")
        lines.append("- **Memory Limit**: Status could not be determined.")
    
    lines.append("")
    lines.append("## Memory Statistics")
    lines.append("")
    
    # Extract specific metrics if available, otherwise provide placeholders based on status
    peak_memory_gb = profile.get("peak_memory_gb", None)
    average_memory_gb = profile.get("average_memory_gb", None)
    min_memory_gb = profile.get("min_memory_gb", None)
    max_memory_gb = profile.get("max_memory_gb", None)
    
    lines.append("| Metric | Value (GB) |")
    lines.append("| :--- | :--- |")
    
    if peak_memory_gb is not None:
        lines.append(f"| Peak Memory Usage | {peak_memory_gb:.4f} |")
    else:
        lines.append("| Peak Memory Usage | N/A |")
        
    if average_memory_gb is not None:
        lines.append(f"| Average Memory Usage | {average_memory_gb:.4f} |")
    else:
        lines.append("| Average Memory Usage | N/A |")

    if min_memory_gb is not None:
        lines.append(f"| Minimum Memory Usage | {min_memory_gb:.4f} |")
    else:
        lines.append("| Minimum Memory Usage | N/A |")

    if max_memory_gb is not None:
        lines.append(f"| Maximum Memory Usage | {max_memory_gb:.4f} |")
    else:
        lines.append("| Maximum Memory Usage | N/A |")

    lines.append("")
    lines.append("## OOM Prevention Efficacy")
    lines.append("")
    
    if within_limit:
        lines.append("The memory management strategy (batching, `memory_guard` checks, and explicit garbage collection)")
        lines.append("successfully prevented Out-Of-Memory (OOM) crashes during the tracing of 100 ImageNet validation images.")
        lines.append("")
        lines.append("### Key Observations")
        lines.append("- The `memory_guard(7.0)` threshold was respected throughout the execution.")
        lines.append("- No `MemoryError` exceptions were raised that halted the process.")
        lines.append("- Peak memory usage remained safely below the 7GB constraint.")
    else:
        lines.append("The execution encountered memory constraints that exceeded the configured 7GB limit.")
        lines.append("")
        lines.append("### Recommendations")
        lines.append("- Reduce `TRACE_SET_SIZE` environment variable.")
        lines.append("- Decrease batch size in `src/tracing.py`.")
        lines.append("- Ensure `torch.cuda.empty_cache()` or `gc.collect()` is called frequently.")
        lines.append("- Verify that the `bitsandbytes` 8-bit quantization is correctly applied to the model.")
    
    lines.append("")
    lines.append("## Conclusion")
    lines.append("")
    if status == "PASS":
        lines.append("✅ **Success**: The tracing pipeline demonstrated robust memory management and successfully completed")
        lines.append("the workload within the hardware constraints of the runner.")
    else:
        lines.append("❌ **Failure**: The tracing pipeline exceeded memory limits. Optimization of the data loading")
        lines.append("and model inference loops is required before proceeding to User Story 2.")
    
    lines.append("")
    lines.append("---")
    lines.append("*Generated by `src/memory_report_generator.py`*")
    
    return "\n".join(lines)

def main():
    """Main entry point to generate the memory report."""
    print(f"Loading memory profile from: {MEMORY_PROFILE_PATH}")
    
    profile = load_memory_profile(MEMORY_PROFILE_PATH)
    if profile is None:
        print("Failed to load memory profile. Aborting report generation.")
        sys.exit(1)
    
    print("Generating Markdown report...")
    report_content = generate_markdown_report(profile)
    
    # Ensure docs directory exists
    OUTPUT_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    
    with open(OUTPUT_REPORT_PATH, 'w', encoding='utf-8') as f:
        f.write(report_content)
    
    print(f"Report successfully generated at: {OUTPUT_REPORT_PATH}")

if __name__ == "__main__":
    main()
