def run_benchmark_with_seed(seed: int) -> Tuple[List[float], List[float]]:
    """
    Re-executes the benchmark script with a specific seed.
    Returns (dynamic_fids, static_fids) lists.
    """
    logger.info(f"Running benchmark with seed {seed}")
    
    # Override environment variable for this subprocess
    env = os.environ.copy()
    env['RANDOM_SEED'] = str(seed)
    
    # Run the benchmark script
    # We assume the script is at code/src/benchmark.py relative to project root
    # or we run it as a module. Since we are in code/, we run as module.
    cmd = [sys.executable, "-m", "src.benchmark"]
    
    try:
        result = subprocess.run(
            cmd,
            env=env,
            check=True,
            capture_output=True,
            text=True,
            timeout=3600  # 1 hour timeout per seed
        )
        logger.info(f"Benchmark for seed {seed} completed successfully")
    except subprocess.CalledProcessError as e:
        logger.error(f"Benchmark failed for seed {seed}: {e.stderr}")
        raise
    
    # Parse the results from the generated JSON file
    # The benchmark script should write to data/results/benchmark_results_seed_{N}.json
    # or we need to parse the main one if it's overwritten. 
    # Given T025 requirement for file management, we expect seed-specific files.
    # However, T019 writes to data/results/benchmark_results.json.
    # To be safe and follow T025's "save to seed-specific files", we assume 
    # the benchmark script was updated or we read the latest results if single file.
    # Let's assume the benchmark script in T019 writes to a file that we can read.
    # For robustness, we will look for the file generated by the specific seed.
    
    # If the benchmark script doesn't support seed-specific filenames natively,
    # we might need to rely on the fact that it overwrites. 
    # But T025 says "save to seed-specific files". 
    # Let's assume the benchmark script (T019) has been updated to handle this 
    # or we read the main file if it's the only one (which implies sequential overwrite).
    # Given the strict requirement to avoid data corruption, we assume the benchmark
    # script was modified to write `benchmark_results_seed_{seed}.json`.
    
    results_file = Path("data/results/benchmark_results_seed_{}.json".format(seed))
    if not results_file.exists():
        # Fallback if the file naming convention wasn't followed or main file used
        results_file = Path("data/results/benchmark_results.json")
        
    if not results_file.exists():
        raise FileNotFoundError(f"Results file not found for seed {seed}")
        
    with open(results_file, 'r') as f:
        data = json.load(f)
    
    dynamic_fids = []
    static_fids = []
    
    # The benchmark results are a list of runs (or aggregated). 
    # Assuming T019 output format: list of dicts with 'model_type' and 'fid_score'
    # We need to aggregate per model type for this seed.
    # If the file contains multiple entries for the same model type, we average them.
    
    current_dynamic = []
    current_static = []
    
    for entry in data:
        if entry.get('model_type') == 'dynamic':
            current_dynamic.append(entry.get('fid_score'))
        elif entry.get('model_type') == 'static':
            current_static.append(entry.get('fid_score'))
    
    if current_dynamic:
        dynamic_fids.append(np.mean(current_dynamic))
    if current_static:
        static_fids.append(np.mean(current_static))
        
    return dynamic_fids, static_fids

def compute_paired_difference_stats(dynamic_fids: List[float], static_fids: List[float]) -> Dict[str, float]:
    """
    Computes mean and std of paired differences (static - dynamic).
    """
    if len(dynamic_fids) != len(static_fids):
        raise ValueError("Dynamic and static FID lists must have the same length")
    
    if len(dynamic_fids) == 0:
        return {"mean": 0.0, "std": 0.0}
        
    differences = np.array(static_fids) - np.array(dynamic_fids)
    
    return {
        "mean": float(np.mean(differences)),
        "std": float(np.std(differences)),
        "differences": differences.tolist()
    }

def perform_bootstrap_test(differences: List[float], n_resamples: int = 10000, confidence: float = 0.95) -> Dict[str, Any]:
    """
    Performs non-parametric bootstrap test on paired differences.
    Uses the percentile method for confidence intervals.
    """
    if len(differences) == 0:
        raise ValueError("Differences list cannot be empty")
        
    n = len(differences)
    bootstrap_means = []
    
    logger.info(f"Performing bootstrap with {n_resamples} resamples on {n} data points")
    
    # Set seed for reproducibility of the bootstrap itself
    rng = np.random.default_rng(42)
    
    for _ in range(n_resamples):
        # Resample with replacement
        sample = rng.choice(differences, size=n, replace=True)
        bootstrap_means.append(np.mean(sample))
    
    bootstrap_means = np.array(bootstrap_means)
    
    # Calculate p-value (two-tailed test against 0)
    # P-value is the proportion of bootstrap means that are as extreme or more extreme than 0
    # relative to the observed mean.
    # However, standard bootstrap test for mean != 0:
    # If 0 is outside the confidence interval, we reject null.
    # P-value approximation: 2 * min(proportion < 0, proportion > 0) if centered?
    # Actually, for a two-sided test of H0: mean = 0:
    # p = 2 * min( (number of bootstrap means <= 0) / N, (number of bootstrap means >= 0) / N )
    # But this assumes the bootstrap distribution is centered at the observed mean.
    # A more robust way: count how many bootstrap means are on the "other side" of 0 than the observed mean?
    # Let's use the standard percentile method for CI and derive p-value from the distribution.
    
    observed_mean = np.mean(differences)
    
    # Count how many bootstrap samples are <= 0 and >= 0
    # If observed mean is positive, p-value is 2 * proportion of bootstrap means <= 0
    # If observed mean is negative, p-value is 2 * proportion of bootstrap means >= 0
    
    if observed_mean >= 0:
        p_val = 2 * np.mean(bootstrap_means <= 0)
    else:
        p_val = 2 * np.mean(bootstrap_means >= 0)
        
    p_val = min(p_val, 1.0)  # Cap at 1.0
    
    # Confidence interval using percentile method
    alpha = 1 - confidence
    lower_percentile = (alpha / 2) * 100
    upper_percentile = (1 - alpha / 2) * 100
    
    ci_lower = float(np.percentile(bootstrap_means, lower_percentile))
    ci_upper = float(np.percentile(bootstrap_means, upper_percentile))
    
    return {
        "p_value": float(p_val),
        "ci_lower": ci_lower,
        "ci_upper": ci_upper,
        "bootstrap_distribution": bootstrap_means.tolist()
    }

def run_statistical_analysis(n_seeds: int = 5) -> Dict[str, Any]:
    """
    Orchestrates the full statistical analysis:
    1. Runs benchmark for n_seeds
    2. Computes paired differences
    3. Performs bootstrap test
    4. Saves results to data/results/statistical_analysis.json
    """
    all_dynamic_fids = []
    all_static_fids = []
    
    # Generate seeds if not provided (or use a fixed set)
    # T025 says "Re-execute the benchmark script (T019) 5 times with different random seeds"
    # We'll use a simple sequence or random seeds. Let's use 10, 20, 30, 40, 50 to avoid 42 if used elsewhere.
    seeds = [10, 20, 30, 40, 50][:n_seeds]
    
    logger.info(f"Starting statistical analysis with seeds: {seeds}")
    
    for seed in seeds:
        try:
            dyn_fids, stat_fids = run_benchmark_with_seed(seed)
            all_dynamic_fids.extend(dyn_fids)
            all_static_fids.extend(stat_fids)
        except Exception as e:
            logger.error(f"Failed to run benchmark for seed {seed}: {e}")
            # Decide: fail loudly or skip? T025 says "Re-execute... to ensure independence".
            # If one fails, the whole analysis is compromised. We should fail.
            raise RuntimeError(f"Benchmark failed for seed {seed}, aborting analysis.")
    
    if len(all_dynamic_fids) != len(all_static_fids) or len(all_dynamic_fids) == 0:
        raise ValueError("Could not collect matching FID scores for all seeds")
        
    # Compute paired differences
    stats = compute_paired_difference_stats(all_dynamic_fids, all_static_fids)
    differences = stats.pop("differences") # Remove from stats dict, keep for bootstrap
    
    # Perform bootstrap test
    bootstrap_results = perform_bootstrap_test(differences)
    
    # Prepare final output
    # T026 Requirement: "Explicitly write a string field 'statistical_limitations' ... explaining the limitation of N=5"
    limitations = (
        "Statistical Limitations: The analysis is based on N=5 seeds. "
        "While the non-parametric bootstrap provides a robust estimate of the confidence interval "
        "and p-value without assuming a normal distribution, the small sample size (N=5) limits "
        "the power of the test and the precision of the estimated standard deviation. "
        "Parametric tests (e.g., t-test) are unreliable with N=5 due to the inability to "
        "verify normality assumptions. The results should be interpreted as preliminary evidence "
        "of significance rather than a definitive statistical conclusion. "
        "Increasing the number of seeds (e.g., to 10 or 20) would improve the robustness of the inference."
    )
    
    output = {
        "mean_difference": stats["mean"],
        "std_difference": stats["std"],
        "p_value": bootstrap_results["p_value"],
        "bootstrap_results": {
            "p_value": bootstrap_results["p_value"],
            "ci_lower": bootstrap_results["ci_lower"],
            "ci_upper": bootstrap_results["ci_upper"]
        },
        "bootstrap_distribution": bootstrap_results["bootstrap_distribution"],
        "statistical_limitations": limitations
    }
    
    # Save to file
    output_path = Path("data/results/statistical_analysis.json")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(output, f, indent=2)
        
    logger.info(f"Statistical analysis complete. Results saved to {output_path}")
    
    return output

def main():
    """Entry point for the script."""
    logger.info("Starting statistical analysis script")
    try:
        results = run_statistical_analysis(n_seeds=5)
        print(json.dumps(results, indent=2))
    except Exception as e:
        logger.error(f"Analysis failed: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
