"""
Unit tests for stimulus generation logic in code/data/stimuli.py.
Validates that:
1. Each stimulus ID has exactly two variants (Perspective-Taking and Control).
2. Sentiment scores are balanced across the two conditions.
"""
import pytest
import json
import os
import sys
from pathlib import Path

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from code.data.stimuli import generate_stimuli, load_stimuli_from_json
from code.config import PATH_PROCESSED


def _load_sample_stimuli():
    """Helper to load the stimuli generated by T018."""
    stimuli_path = PATH_PROCESSED / "stimuli.json"
    if not stimuli_path.exists():
        pytest.fail(f"Stimuli file not found at {stimuli_path}. Run T018 first.")
    return load_stimuli_from_json(stimuli_path)


class TestStimulusVariants:
    """Test that each stimulus has exactly two variants."""

    def test_two_variants_per_id(self):
        """Verify that every unique post ID has exactly two instruction variants."""
        stimuli = _load_sample_stimuli()
        items = stimuli.get("stimuli", [])

        assert len(items) > 0, "Stimuli list is empty."

        # Group by post_id
        variants_per_id = {}
        for item in items:
            post_id = item.get("post_id")
            if post_id not in variants_per_id:
                variants_per_id[post_id] = []
            variants_per_id[post_id].append(item)

        # Check count
        for post_id, variants in variants_per_id.items():
            assert len(variants) == 2, (
                f"Post ID {post_id} has {len(variants)} variants, expected 2. "
                f"Variants: {[v.get('condition') for v in variants]}"
            )

    def test_variant_conditions(self):
        """Verify that the two variants correspond to 'perspective_taking' and 'control_summarization'."""
        stimuli = _load_sample_stimuli()
        items = stimuli.get("stimuli", [])

        variants_per_id = {}
        for item in items:
            post_id = item.get("post_id")
            if post_id not in variants_per_id:
                variants_per_id[post_id] = []
            variants_per_id[post_id].append(item.get("condition"))

        expected_conditions = {"perspective_taking", "control_summarization"}

        for post_id, conditions in variants_per_id.items():
            assert set(conditions) == expected_conditions, (
                f"Post ID {post_id} has conditions {set(conditions)}, "
                f"expected {expected_conditions}."
            )


class TestSentimentBalance:
    """Test that sentiment scores are balanced across conditions."""

    def test_sentiment_balance_means(self):
        """
        Verify that the mean VADER composite score is approximately equal
        between the 'perspective_taking' and 'control_summarization' groups.
        Tolerance is set to 0.1 (10% of the -1 to 1 scale) to account for
        random sampling variance while ensuring stratification worked.
        """
        stimuli = _load_sample_stimuli()
        items = stimuli.get("stimuli", [])

        pt_scores = []
        control_scores = []

        for item in items:
            score = item.get("vader_composite")
            condition = item.get("condition")

            if score is None:
                pytest.fail(f"Missing vader_composite score for item {item.get('post_id')}")

            if condition == "perspective_taking":
                pt_scores.append(score)
            elif condition == "control_summarization":
                control_scores.append(score)
            else:
                pytest.fail(f"Unknown condition: {condition}")

        assert len(pt_scores) > 0, "No perspective_taking samples found."
        assert len(control_scores) > 0, "No control_summarization samples found."

        mean_pt = sum(pt_scores) / len(pt_scores)
        mean_control = sum(control_scores) / len(control_scores)

        diff = abs(mean_pt - mean_control)
        tolerance = 0.1

        assert diff <= tolerance, (
            f"Sentiment imbalance detected. Mean PT: {mean_pt:.4f}, "
            f"Mean Control: {mean_control:.4f}. Difference: {diff:.4f} (tolerance: {tolerance})"
        )

    def test_stratification_report_exists(self):
        """
        Verify that the stratification validation report generated by T051 exists
        and contains the required balance metrics.
        """
        report_path = PATH_PROCESSED / "stratification_report.json"
        assert report_path.exists(), (
            f"Stratification report not found at {report_path}. "
            "Ensure T051 has been executed."
        )

        with open(report_path, "r") as f:
            report = json.load(f)

        assert "mean_sentiment_pt" in report, "Missing 'mean_sentiment_pt' in report."
        assert "mean_sentiment_control" in report, "Missing 'mean_sentiment_control' in report."
        assert "difference" in report, "Missing 'difference' in report."
        assert "balanced" in report, "Missing 'balanced' flag in report."

        # Verify the report's 'balanced' flag aligns with the actual calculation
        diff = abs(report["mean_sentiment_pt"] - report["mean_sentiment_control"])
        assert (diff <= 0.1) == report["balanced"], (
            "Report's 'balanced' flag is inconsistent with the calculated difference."
        )