# Configure logging
logger = logging.getLogger(__name__)

def load_kinetic_results() -> pd.DataFrame:
    """
    Load kinetic fit results from the processed directory.
    Expects 'kinetic_fit_results.json' generated by kinetic_fit.py.
    
    Returns:
        DataFrame with columns: solvent, replicate_id, lifetime_ns, ci_lower, ci_upper, outlier_flag
    """
    processed_path = get_processed_data_path()
    results_file = processed_path / "kinetic_fit_results.json"
    
    if not results_file.exists():
        raise FileNotFoundError(
            f"Kinetic fit results not found at {results_file}. "
            "Please run 'code/analysis/kinetic_fit.py' first to generate this file."
        )
    
    with open(results_file, 'r') as f:
        data = json.load(f)
    
    df = pd.DataFrame(data)
    
    # Ensure required columns exist
    required_cols = ['solvent', 'replicate_id', 'lifetime_ns', 'ci_lower', 'ci_upper', 'outlier_flag']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in kinetic fit results: {missing}")
    
    return df

def load_outlier_flags() -> pd.DataFrame:
    """
    Load outlier flags from the processed directory.
    Expects 'outlier_flags.json' generated by kinetic_fit.py.
    
    Returns:
        DataFrame with columns: solvent, replicate_id, is_outlier, method, threshold
    """
    processed_path = get_processed_data_path()
    flags_file = processed_path / "outlier_flags.json"
    
    if not flags_file.exists():
        logger.warning(f"Outlier flags file not found at {flags_file}. "
                     "Returning empty DataFrame.")
        return pd.DataFrame(columns=['solvent', 'replicate_id', 'is_outlier', 'method', 'threshold'])
    
    with open(flags_file, 'r') as f:
        data = json.load(f)
    
    return pd.DataFrame(data)

def aggregate_metrics(df: pd.DataFrame) -> pd.DataFrame:
    """
    Aggregate kinetic metrics per solvent: mean lifetime, std dev, confidence intervals,
    and replicate statistics.
    
    Args:
        df: DataFrame from load_kinetic_results()
        
    Returns:
        DataFrame with aggregated metrics per solvent
    """
    # Filter out outliers for aggregate statistics if flag exists
    if 'outlier_flag' in df.columns:
        df_clean = df[df['outlier_flag'] == False].copy()
    else:
        df_clean = df.copy()
    
    if df_clean.empty:
        logger.warning("No valid data points found after outlier filtering.")
        return pd.DataFrame()
    
    # Group by solvent and calculate statistics
    stats = df_clean.groupby('solvent').agg(
        mean_lifetime_ns=('lifetime_ns', 'mean'),
        std_lifetime_ns=('lifetime_ns', 'std'),
        min_lifetime_ns=('lifetime_ns', 'min'),
        max_lifetime_ns=('lifetime_ns', 'max'),
        replicate_count=('replicate_id', 'count'),
        # Calculate mean CI width
        mean_ci_width=('lifetime_ns', lambda x: (df_clean.loc[x.index, 'ci_upper'] - df_clean.loc[x.index, 'ci_lower']).mean())
    ).reset_index()
    
    # Calculate 95% CI for the mean (t-distribution for small samples)
    def calculate_mean_ci(group):
        n = len(group)
        if n < 2:
            return np.nan, np.nan
        mean = group['lifetime_ns'].mean()
        std_err = group['lifetime_ns'].std() / np.sqrt(n)
        # Use t-distribution for small samples (n < 30)
        from scipy import stats
        t_val = stats.t.ppf(0.975, df=n-1)
        ci_lower = mean - t_val * std_err
        ci_upper = mean + t_val * std_err
        return ci_lower, ci_upper
    
    # Apply CI calculation
    ci_results = df_clean.groupby('solvent').apply(calculate_mean_ci).reset_index()
    ci_results.columns = ['solvent', 'ci_lower_mean', 'ci_upper_mean']
    
    # Merge CI results with stats
    stats = stats.merge(ci_results, on='solvent', how='left')
    
    # Add metadata
    stats['analysis_timestamp'] = datetime.now(timezone.utc).isoformat()
    stats['seed_hash'] = get_seed_hash()
    stats['data_source'] = 'kinetic_fit_results.json'
    
    return stats

def write_metrics_csv(metrics_df: pd.DataFrame, output_file: Optional[Path] = None) -> Path:
    """
    Write aggregated kinetic metrics to a CSV file.
    
    Args:
        metrics_df: DataFrame from aggregate_metrics()
        output_file: Optional path for output file. Defaults to data/processed/kinetic_metrics.csv
        
    Returns:
        Path to the written file
    """
    if output_file is None:
        processed_path = get_processed_data_path()
        ensure_directories()
        output_file = processed_path / "kinetic_metrics.csv"
    else:
        ensure_directories()
    
    metrics_df.to_csv(output_file, index=False)
    logger.info(f"Kinetic metrics written to {output_file}")
    return output_file

def main():
    """
    Main entry point for generating kinetic metrics CSV.
    
    Reads kinetic fit results, aggregates statistics per solvent,
    and writes the final metrics to data/processed/kinetic_metrics.csv
    """
    parser = argparse.ArgumentParser(description="Generate kinetic metrics CSV from fit results")
    parser.add_argument('--output', type=str, default=None,
                      help='Output file path (default: data/processed/kinetic_metrics.csv)')
    parser.add_argument('--verbose', '-v', action='store_true',
                      help='Enable verbose logging')
    
    args = parser.parse_args()
    
    if args.verbose:
        setup_logging(level=logging.DEBUG)
    else:
        setup_logging(level=logging.INFO)
    
    logger.info("Starting kinetic metrics aggregation...")
    
    try:
        # Load results
        logger.info("Loading kinetic fit results...")
        results_df = load_kinetic_results()
        logger.info(f"Loaded {len(results_df)} kinetic fit results")
        
        # Aggregate metrics
        logger.info("Aggregating metrics per solvent...")
        metrics_df = aggregate_metrics(results_df)
        
        if metrics_df.empty:
            logger.error("No metrics could be calculated. Check input data.")
            sys.exit(1)
        
        logger.info(f"Calculated metrics for {len(metrics_df)} solvents")
        
        # Write output
        output_path = None
        if args.output:
            output_path = Path(args.output)
        
        written_file = write_metrics_csv(metrics_df, output_path)
        
        logger.info("Kinetic metrics aggregation complete!")
        logger.info(f"Output file: {written_file}")
        
        # Print summary
        print("\n=== Kinetic Metrics Summary ===")
        print(metrics_df.to_string(index=False))
        print("==============================\n")
        
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    except Exception as e:
        logger.exception(f"Unexpected error during metrics generation: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
