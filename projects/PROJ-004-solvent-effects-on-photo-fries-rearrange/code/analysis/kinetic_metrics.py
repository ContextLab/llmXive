"""
Kinetic Metrics Aggregation Module

This module aggregates kinetic fitting results from replicate runs,
calculates statistics (mean, std, confidence intervals), and writes
the final metrics to `data/processed/kinetic_metrics.csv`.

It depends on the output of `code/analysis/kinetic_fit.py` which
performs the global kinetic analysis and writes raw results to
`data/processed/kinetic_results.json`.
"""
import os
import sys
import logging
import argparse
from datetime import datetime
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple
import json
import pandas as pd
import numpy as np

# Project imports
from config import get_processed_data_path, ensure_directories
from utils.logging import setup_logging

# Constants
LOG = logging.getLogger(__name__)

# Input/Output paths
KINETIC_RESULTS_FILE = "kinetic_results.json"
OUTLIER_FLAGS_FILE = "outlier_flags.json"
METRICS_CSV_FILE = "kinetic_metrics.csv"

def load_kinetic_results() -> List[Dict[str, Any]]:
    """
    Load the raw kinetic fitting results from the processed directory.

    Returns:
        List of dictionaries containing fit parameters for each run.

    Raises:
        FileNotFoundError: If the results file does not exist.
    """
    processed_path = get_processed_data_path()
    results_file = processed_path / KINETIC_RESULTS_FILE

    if not results_file.exists():
        LOG.error(f"Kinetic results file not found: {results_file}")
        raise FileNotFoundError(
            f"Required input file missing: {results_file}. "
            "Ensure T021 (kinetic_fit.py) has been run successfully."
        )

    with open(results_file, 'r') as f:
        data = json.load(f)

    LOG.info(f"Loaded {len(data)} kinetic result records from {results_file}")
    return data

def load_outlier_flags() -> Dict[str, bool]:
    """
    Load the outlier flags generated by T023.

    Returns:
        Dictionary mapping run_id to boolean (True if outlier).
        Returns empty dict if file is missing (treat all as non-outliers if T023 hasn't run).
    """
    processed_path = get_processed_data_path()
    flags_file = processed_path / OUTLIER_FLAGS_FILE

    if not flags_file.exists():
        LOG.warning(f"Outlier flags file not found: {flags_file}. "
                    "Proceeding without outlier filtering.")
        return {}

    with open(flags_file, 'r') as f:
        return json.load(f)

def aggregate_metrics(
    results: List[Dict[str, Any]],
    outlier_flags: Dict[str, bool]
) -> List[Dict[str, Any]]:
    """
    Aggregate kinetic results by solvent, calculating mean lifetime,
    standard deviation, confidence intervals, and replicate counts.

    Args:
        results: List of raw kinetic result dictionaries.
        outlier_flags: Dictionary of run_id -> is_outlier.

    Returns:
        List of aggregated metric dictionaries per solvent.
    """
    # Group by solvent
    solvent_groups: Dict[str, List[Dict[str, Any]]] = {}

    for record in results:
        solvent = record.get('solvent')
        if not solvent:
            LOG.warning(f"Skipping record with missing solvent: {record.get('run_id')}")
            continue

        # Filter out outliers if flags are present
        run_id = record.get('run_id')
        if outlier_flags.get(run_id, False):
            LOG.info(f"Skipping outlier run {run_id} for solvent {solvent}")
            continue

        if solvent not in solvent_groups:
            solvent_groups[solvent] = []
        solvent_groups[solvent].append(record)

    aggregated = []

    for solvent, runs in solvent_groups.items():
        if not runs:
            continue

        lifetimes = [r.get('lifetime_ns', np.nan) for r in runs]
        # Filter out NaNs for calculation
        valid_lifetimes = [t for t in lifetimes if not np.isnan(t)]
        n_replicates = len(valid_lifetimes)

        if n_replicates == 0:
            LOG.warning(f"No valid lifetimes for solvent {solvent}")
            continue

        mean_lifetime = np.mean(valid_lifetimes)
        std_lifetime = np.std(valid_lifetimes, ddof=1) if n_replicates > 1 else 0.0

        # Calculate 95% Confidence Interval using t-distribution
        # CI = mean ± t_crit * (std / sqrt(n))
        if n_replicates > 1:
            from scipy.stats import t
            confidence_level = 0.95
            dof = n_replicates - 1
            t_crit = t.ppf((1 + confidence_level) / 2, dof)
            margin_of_error = t_crit * (std_lifetime / np.sqrt(n_replicates))
            ci_lower = mean_lifetime - margin_of_error
            ci_upper = mean_lifetime + margin_of_error
        else:
            # Single replicate: CI is undefined or equal to the point estimate
            # We set it to the value itself to indicate high uncertainty
            ci_lower = mean_lifetime
            ci_upper = mean_lifetime
            LOG.warning(f"Only 1 replicate for {solvent}. CI set to point estimate.")

        aggregated.append({
            'solvent': solvent,
            'n_replicates': n_replicates,
            'mean_lifetime_ns': mean_lifetime,
            'std_lifetime_ns': std_lifetime,
            'ci_95_lower_ns': ci_lower,
            'ci_95_upper_ns': ci_upper,
            'min_lifetime_ns': min(valid_lifetimes),
            'max_lifetime_ns': max(valid_lifetimes),
            'timestamp': datetime.now(timezone.utc).isoformat()
        })

    return aggregated

def write_metrics_csv(aggregated: List[Dict[str, Any]]) -> Path:
    """
    Write the aggregated metrics to a CSV file.

    Args:
        aggregated: List of aggregated metric dictionaries.

    Returns:
        Path to the written CSV file.
    """
    ensure_directories()
    processed_path = get_processed_data_path()
    output_file = processed_path / METRICS_CSV_FILE

    if not aggregated:
        LOG.warning("No data to write to metrics CSV.")
        # Create an empty file with headers to prevent downstream crashes
        df = pd.DataFrame(columns=[
            'solvent', 'n_replicates', 'mean_lifetime_ns', 'std_lifetime_ns',
            'ci_95_lower_ns', 'ci_95_upper_ns', 'min_lifetime_ns', 'max_lifetime_ns', 'timestamp'
        ])
    else:
        df = pd.DataFrame(aggregated)
        # Ensure column order
        df = df[[
            'solvent', 'n_replicates', 'mean_lifetime_ns', 'std_lifetime_ns',
            'ci_95_lower_ns', 'ci_95_upper_ns', 'min_lifetime_ns', 'max_lifetime_ns', 'timestamp'
        ]]

    df.to_csv(output_file, index=False)
    LOG.info(f"Wrote {len(aggregated)} solvent metrics to {output_file}")
    return output_file

def main():
    """Main entry point for kinetic metrics aggregation."""
    parser = argparse.ArgumentParser(
        description="Aggregate kinetic fit results into a metrics CSV."
    )
    parser.add_argument(
        '--log-level',
        default='INFO',
        choices=['DEBUG', 'INFO', 'WARNING', 'ERROR'],
        help="Logging level"
    )
    args = parser.parse_args()

    setup_logging(level=args.log_level)
    LOG.info("Starting kinetic metrics aggregation (Task T026)")

    try:
        # 1. Load raw results
        results = load_kinetic_results()

        # 2. Load outlier flags
        outlier_flags = load_outlier_flags()

        # 3. Aggregate
        aggregated = aggregate_metrics(results, outlier_flags)

        # 4. Write CSV
        output_path = write_metrics_csv(aggregated)

        LOG.info(f"Task T026 completed successfully. Output: {output_path}")
        return 0

    except FileNotFoundError as e:
        LOG.error(f"Missing required data: {e}")
        return 1
    except Exception as e:
        LOG.exception(f"Unexpected error during aggregation: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
