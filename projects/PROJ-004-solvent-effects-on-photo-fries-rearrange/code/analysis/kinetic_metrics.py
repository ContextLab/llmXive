"""
Kinetic Metrics Aggregation and Export.

This module aggregates kinetic fitting results (lifetimes, confidence intervals,
replicate statistics) and writes them to a structured CSV file.

It reads intermediate results from the kinetic fit analysis, applies outlier
flags, and computes aggregate statistics (mean, std, CI) per solvent condition.
"""

