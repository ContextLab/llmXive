# Configure logging
logger = logging.getLogger(__name__)

# Output path constants
KINETIC_METRICS_PATH = "data/processed/kinetic_metrics.csv"
CALIBRATED_TRACES_PATH = "data/processed/calibrated_traces.csv"
OUTLIER_FLAGS_PATH = "data/processed/outlier_flags.json"

def load_kinetic_results() -> pd.DataFrame:
    """
    Load kinetic fitting results from the calibrated traces processing.

    This function expects `calibrated_traces.csv` to contain columns generated
    by the kinetic fit analysis: `solvent`, `tau_ns`, `tau_ci_lower`, `tau_ci_upper`,
    `r_squared`, `replicate_id`.

    Returns:
        pd.DataFrame: DataFrame containing kinetic fit results.

    Raises:
        FileNotFoundError: If the calibrated traces file is missing.
        ValueError: If required columns are missing.
    """
    processed_path = get_processed_data_path()
    input_file = processed_path / CALIBRATED_TRACES_PATH

    if not input_file.exists():
        raise FileNotFoundError(
            f"Calibrated traces file not found at {input_file}. "
            "Run the kinetic fit analysis (T021) before generating metrics."
        )

    df = pd.read_csv(input_file)

    required_cols = ['solvent', 'tau_ns', 'tau_ci_lower', 'tau_ci_upper', 'replicate_id']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in {input_file}: {missing}")

    return df

def load_outlier_flags() -> Dict[str, List[int]]:
    """
    Load outlier flags generated by the outlier detection task (T023).

    Returns:
        Dict[str, List[int]]: Mapping of solvent name to list of outlier replicate IDs.
    """
    processed_path = get_processed_data_path()
    input_file = processed_path / OUTLIER_FLAGS_PATH

    if not input_file.exists():
        logger.warning(f"Outlier flags file not found at {input_file}. Proceeding without outlier filtering.")
        return {}

    try:
        import json
        with open(input_file, 'r') as f:
            data = json.load(f)
        return data.get("outlier_flags", {})
    except Exception as e:
        logger.warning(f"Failed to parse outlier flags: {e}. Proceeding without outlier filtering.")
        return {}

def aggregate_metrics(df: pd.DataFrame, outlier_flags: Dict[str, List[int]]) -> pd.DataFrame:
    """
    Aggregate kinetic metrics per solvent, excluding flagged outliers.

    Calculates:
    - Mean lifetime
    - Standard deviation
    - 95% Confidence Interval (based on t-distribution for small N)
    - Number of valid replicates
    - Number of flagged outliers

    Args:
        df (pd.DataFrame): Kinetic results.
        outlier_flags (Dict[str, List[int]]): Outlier mapping.

    Returns:
        pd.DataFrame: Aggregated metrics per solvent.
    """
    # Filter out outliers
    mask = np.ones(len(df), dtype=bool)
    for solvent, outliers in outlier_flags.items():
        solvent_mask = df['solvent'] == solvent
        solvent_indices = df[solvent_mask].index
        valid_indices = [idx for idx in solvent_indices if df.loc[idx, 'replicate_id'] not in outliers]
        mask[solvent_mask] = False
        mask[valid_indices] = True

    filtered_df = df[mask]

    if filtered_df.empty:
        logger.error("No valid data remaining after outlier filtering. Cannot aggregate metrics.")
        return pd.DataFrame()

    # Group by solvent
    grouped = filtered_df.groupby('solvent')

    results = []
    for solvent, group in grouped:
        taus = group['tau_ns'].values
        n = len(taus)

        if n == 0:
            continue

        mean_tau = np.mean(taus)
        std_tau = np.std(taus, ddof=1) if n > 1 else 0.0

        # Calculate 95% CI using t-distribution (appropriate for n < 30)
        if n > 1:
            from scipy.stats import t
            conf_level = 0.95
            dof = n - 1
            t_val = t.ppf((1 + conf_level) / 2, dof)
            margin_error = t_val * (std_tau / np.sqrt(n))
            ci_lower = mean_tau - margin_error
            ci_upper = mean_tau + margin_error
        else:
            # If only one replicate, CI is undefined (or equal to the point estimate)
            ci_lower = mean_tau
            ci_upper = mean_tau
            logger.warning(f"Only 1 replicate for {solvent}. CI set to point estimate.")

        # Count outliers for this solvent
        outlier_count = len(outlier_flags.get(solvent, []))

        results.append({
            'solvent': solvent,
            'mean_lifetime_ns': mean_tau,
            'std_lifetime_ns': std_tau,
            'ci_95_lower_ns': ci_lower,
            'ci_95_upper_ns': ci_upper,
            'n_replicates': n,
            'n_outliers': outlier_count,
            'timestamp': datetime.now(timezone.utc).isoformat()
        })

    return pd.DataFrame(results)

def write_metrics_csv(metrics_df: pd.DataFrame, output_path: Optional[str] = None) -> str:
    """
    Write aggregated kinetic metrics to a CSV file.

    Args:
        metrics_df (pd.DataFrame): Aggregated metrics.
        output_path (str, optional): Path to write the CSV. Defaults to KINETIC_METRICS_PATH.

    Returns:
        str: Path to the written file.
    """
    if output_path is None:
        processed_path = get_processed_data_path()
        output_path = processed_path / KINETIC_METRICS_PATH
    else:
        output_path = Path(output_path)

    output_path.parent.mkdir(parents=True, exist_ok=True)

    metrics_df.to_csv(output_path, index=False)
    logger.info(f"Wrote kinetic metrics to {output_path}")

    return str(output_path)

def main():
    """
    Main entry point for generating kinetic metrics.

    This function orchestrates the loading of kinetic results, application of
    outlier filters, aggregation of statistics, and writing of the final CSV.
    """
    parser = argparse.ArgumentParser(
        description="Aggregate kinetic fitting results and write metrics CSV."
    )
    parser.add_argument(
        '--output',
        type=str,
        default=None,
        help=f"Output path for the metrics CSV (default: {KINETIC_METRICS_PATH})"
    )
    parser.add_argument(
        '--seed',
        type=int,
        default=42,
        help="Random seed for reproducibility (default: 42)"
    )

    args = parser.parse_args()
    set_seed(args.seed)

    # Setup logging
    log_file = get_processed_data_path() / "kinetic_metrics_run.log"
    setup_logging(log_file=log_file)

    logger.info("Starting kinetic metrics aggregation.")

    try:
        # 1. Load kinetic results
        logger.info("Loading kinetic results...")
        kinetic_df = load_kinetic_results()
        logger.info(f"Loaded {len(kinetic_df)} kinetic measurements.")

        # 2. Load outlier flags
        logger.info("Loading outlier flags...")
        outlier_flags = load_outlier_flags()
        total_outliers = sum(len(v) for v in outlier_flags.values())
        logger.info(f"Found {total_outliers} flagged outliers across solvents.")

        # 3. Aggregate metrics
        logger.info("Aggregating metrics...")
        metrics_df = aggregate_metrics(kinetic_df, outlier_flags)

        if metrics_df.empty:
            logger.error("Aggregation resulted in an empty DataFrame. Aborting.")
            sys.exit(1)

        # 4. Write output
        logger.info("Writing metrics CSV...")
        output_file = write_metrics_csv(metrics_df, args.output)

        logger.info(f"Successfully generated {output_file}")
        print(f"Kinetic metrics written to: {output_file}")

    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.exception(f"Unexpected error during aggregation: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
