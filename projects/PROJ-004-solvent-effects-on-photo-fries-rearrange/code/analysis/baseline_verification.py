"""Structural Baseline Verification Module.

Compares pre- and post-irradiation spectra to verify structural integrity.
Flags deviations exceeding 3x the baseline noise threshold.
"""
from __future__ import annotations

import argparse
import json
import logging
import os
import sys
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
import pandas as pd

# Import from local project structure
from config import get_processed_data_path, get_raw_data_path
from utils.logging import setup_logging, log_operation

# Constants
DEVIATION_THRESHOLD_MULTIPLIER = 3.0
OUTPUT_FILENAME = "baseline_verification_report.json"

logger = logging.getLogger(__name__)


def load_baseline_data(
    solvent: str,
    replicate: int,
    use_real_data: bool = False
) -> Tuple[Optional[pd.DataFrame], Optional[pd.DataFrame], Optional[pd.DataFrame]]:
    """Load pre-irradiation, post-irradiation, and ground state reference spectra.

    Args:
        solvent: Name of the solvent (e.g., 'water', 'methanol').
        replicate: Replicate identifier (integer).
        use_real_data: If True, attempt to load real data; else use synthetic logic
                       if real files are missing (for CI robustness).

    Returns:
        Tuple of (pre_irradiation_df, post_irradiation_df, ground_state_df).
        Returns None for any component if not found.
    """
    raw_path = get_raw_data_path()
    proc_path = get_processed_data_path()

    # Construct expected file paths
    pre_file = raw_path / f"baseline_{solvent}_{replicate}_pre.csv"
    post_file = raw_path / f"baseline_{solvent}_{replicate}_post.csv"
    # Ground state might be in processed if generated by T055
    ground_file = proc_path / f"ground_state_{solvent}.csv"

    pre_df = None
    post_df = None
    ground_df = None

    # Load Pre-Irradiation
    if pre_file.exists():
        try:
            pre_df = pd.read_csv(pre_file)
            logger.info(f"Loaded pre-irradiation data from {pre_file}")
        except Exception as e:
            logger.error(f"Failed to load pre-irradiation data: {e}")
    else:
        logger.warning(f"Pre-irradiation file not found: {pre_file}")

    # Load Post-Irradiation
    if post_file.exists():
        try:
            post_df = pd.read_csv(post_file)
            logger.info(f"Loaded post-irradiation data from {post_file}")
        except Exception as e:
            logger.error(f"Failed to load post-irradiation data: {e}")
    else:
        logger.warning(f"Post-irradiation file not found: {post_file}")

    # Load Ground State Reference
    if ground_file.exists():
        try:
            ground_df = pd.read_csv(ground_file)
            logger.info(f"Loaded ground state reference from {ground_file}")
        except Exception as e:
            logger.error(f"Failed to load ground state reference: {e}")
    else:
        logger.warning(f"Ground state reference not found: {ground_file}")

    return pre_df, post_df, ground_df


def calculate_baseline_deviation(
    pre_df: pd.DataFrame,
    post_df: pd.DataFrame
) -> Dict[str, Any]:
    """Calculate the deviation between pre- and post-irradiation spectra.

    Args:
        pre_df: DataFrame containing pre-irradiation spectrum (columns: wavelength, absorbance).
        post_df: DataFrame containing post-irradiation spectrum.

    Returns:
        Dictionary containing deviation metrics: max_deviation, mean_deviation,
        rms_deviation, and flag indicating if threshold is exceeded.
    """
    if pre_df is None or post_df is None:
        return {
            "max_deviation": None,
            "mean_deviation": None,
            "rms_deviation": None,
            "threshold_exceeded": None,
            "status": "missing_data"
        }

    # Align on wavelength
    merged = pd.merge(pre_df, post_df, on="wavelength", suffixes=("_pre", "_post"))
    if merged.empty:
        logger.warning("No overlapping wavelengths found between pre and post spectra.")
        return {
            "max_deviation": None,
            "mean_deviation": None,
            "rms_deviation": None,
            "threshold_exceeded": None,
            "status": "no_overlap"
        }

    pre_abs = merged["absorbance_pre"].values
    post_abs = merged["absorbance_post"].values

    # Calculate absolute difference
    diff = np.abs(post_abs - pre_abs)

    # Estimate baseline noise from pre-irradiation data (standard deviation of residuals)
    # Assuming a smooth spectrum, we can use a rolling window or simple std if flat
    # For robustness, use std of the pre-signal as a proxy for noise floor if no reference
    baseline_noise = np.std(pre_abs)
    if baseline_noise == 0:
        baseline_noise = 1e-6 # Avoid division by zero

    max_dev = float(np.max(diff))
    mean_dev = float(np.mean(diff))
    rms_dev = float(np.sqrt(np.mean(diff**2)))

    # Threshold: 3 * baseline_noise
    threshold = DEVIATION_THRESHOLD_MULTIPLIER * baseline_noise
    exceeded = max_dev > threshold

    return {
        "max_deviation": max_dev,
        "mean_deviation": mean_dev,
        "rms_deviation": rms_dev,
        "baseline_noise_estimate": baseline_noise,
        "threshold_value": threshold,
        "threshold_exceeded": exceeded,
        "status": "ok" if not exceeded else "deviation_detected"
    }


def flag_deviations(
    deviation_metrics: Dict[str, Any],
    solvent: str,
    replicate: int
) -> Dict[str, Any]:
    """Generate a flag record based on deviation metrics.

    Args:
        deviation_metrics: Output from calculate_baseline_deviation.
        solvent: Solvent name.
        replicate: Replicate ID.

    Returns:
        Flag record dictionary.
    """
    exceeded = deviation_metrics.get("threshold_exceeded")
    status = "PASS" if exceeded is False else ("FAIL" if exceeded is True else "SKIP")

    return {
        "solvent": solvent,
        "replicate": replicate,
        "status": status,
        "max_deviation": deviation_metrics.get("max_deviation"),
        "threshold": deviation_metrics.get("threshold_value"),
        "details": deviation_metrics
    }


def verify_baseline_integrity(
    results: List[Dict[str, Any]]
) -> Dict[str, Any]:
    """Verify overall integrity across all solvents/replicates.

    Args:
        results: List of flag records.

    Returns:
        Summary verification report.
    """
    total = len(results)
    passed = sum(1 for r in results if r["status"] == "PASS")
    failed = sum(1 for r in results if r["status"] == "FAIL")
    skipped = total - passed - failed

    pass_rate = (passed / total * 100) if total > 0 else 0.0

    return {
        "total_runs": total,
        "passed": passed,
        "failed": failed,
        "skipped": skipped,
        "pass_rate_percent": pass_rate,
        "integrity_verified": failed == 0,
        "timestamp": datetime.utcnow().isoformat()
    }


def write_verification_report(
    flags: List[Dict[str, Any]],
    summary: Dict[str, Any],
    output_path: Path
) -> None:
    """Write the final verification report to JSON.

    Args:
        flags: List of individual flag records.
        summary: Overall summary statistics.
        output_path: Path to write the JSON file.
    """
    report = {
        "report_metadata": {
            "generated_at": datetime.utcnow().isoformat(),
            "threshold_multiplier": DEVIATION_THRESHOLD_MULTIPLIER,
            "description": "Structural Baseline Verification Report comparing pre- and post-irradiation spectra."
        },
        "summary": summary,
        "individual_flags": flags
    }

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(report, f, indent=2)
    logger.info(f"Verification report written to {output_path}")


def run_baseline_verification(
    solvents: List[str],
    replicates: List[int],
    use_real_data: bool = False
) -> Dict[str, Any]:
    """Execute the full baseline verification pipeline.

    Args:
        solvents: List of solvent names to verify.
        replicates: List of replicate IDs.
        use_real_data: Flag to enforce real data loading.

    Returns:
        The summary report dictionary.
    """
    flags = []

    for solvent in solvents:
        for rep in replicates:
            logger.info(f"Verifying baseline for {solvent} (replicate {rep})")
            pre_df, post_df, _ = load_baseline_data(solvent, rep, use_real_data)

            if pre_df is not None and post_df is not None:
                metrics = calculate_baseline_deviation(pre_df, post_df)
                flag = flag_deviations(metrics, solvent, rep)
                flags.append(flag)
            else:
                # Handle missing data gracefully if not strictly enforcing real data
                if use_real_data:
                    logger.error(f"Real data missing for {solvent} {rep}, aborting verification.")
                    raise FileNotFoundError(f"Real data missing for {solvent} {rep}")
                else:
                    # In synthetic mode, we might just skip or record a skip
                    flag = flag_deviations(
                        {"threshold_exceeded": None, "status": "missing_data"},
                        solvent, rep
                    )
                    flags.append(flag)

    summary = verify_baseline_integrity(flags)
    output_path = get_processed_data_path() / OUTPUT_FILENAME
    write_verification_report(flags, summary, output_path)

    return summary


def main() -> None:
    """CLI entry point for baseline verification."""
    parser = argparse.ArgumentParser(
        description="Verify structural baselines by comparing pre/post irradiation spectra."
    )
    parser.add_argument(
        "--solvents",
        type=str,
        nargs="+",
        default=None,
        help="List of solvent names to verify (e.g., water methanol)."
    )
    parser.add_argument(
        "--replicates",
        type=int,
        nargs="+",
        default=[1],
        help="List of replicate IDs (default: [1])."
    )
    parser.add_argument(
        "--use-real-data",
        action="store_true",
        help="Enforce loading of real data; fail if missing."
    )
    parser.add_argument(
        "--log-level",
        type=str,
        default="INFO",
        choices=["DEBUG", "INFO", "WARNING", "ERROR"],
        help="Logging level."
    )

    args = parser.parse_args()
    setup_logging(level=args.log_level)

    # Default solvents if not provided
    if args.solvents is None:
        # Read from config if possible, else default
        from config import get_chemicals_path
        # Fallback to a standard list if config doesn't specify
        args.solvents = ["water", "methanol", "acetonitrile", "toluene", "cyclohexane"]

    log_operation("baseline_verification_start", solvents=args.solvents, replicates=args.replicates)

    try:
        summary = run_baseline_verification(
            solvents=args.solvents,
            replicates=args.replicates,
            use_real_data=args.use_real_data
        )
        log_operation("baseline_verification_complete", status=summary["integrity_verified"])
        print(json.dumps(summary, indent=2))
    except Exception as e:
        logger.exception("Baseline verification failed")
        sys.exit(1)


if __name__ == "__main__":
    main()
