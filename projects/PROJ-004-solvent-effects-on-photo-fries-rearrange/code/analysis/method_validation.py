"""Analytical Method Validation Module.

Validates HPLC-UV detection thresholds against calibration standards defined
in T045 and T056. Generates a comprehensive validation report documenting
linearity, limit of detection (LOD), limit of quantification (LOQ), and
recovery rates.

Dependencies:
  - T042 (Product Quantification): Defines the HPLC-UV method parameters.
  - T045 (Calibration Protocol): Provides calibration standards and certificates.
  - T056 (Analytical Method Specification): Defines the method specification document.
"""
from __future__ import annotations

import argparse
import csv
import json
import logging
import os
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
import pandas as pd
from scipy import stats

# Import from project API surface
from utils.logging import setup_logging, get_logger, log_operation
from config import get_processed_data_path, get_chemicals_path, get_raw_data_path

# Constants
DEFAULT_R2_THRESHOLD = 0.995
DEFAULT_LOD_FACTOR = 3.3
DEFAULT_LOQ_FACTOR = 10
DEFAULT_RECOVERY_MIN = 95.0
DEFAULT_RECOVERY_MAX = 105.0

class MethodValidationError(Exception):
    """Raised when method validation fails criteria."""
    pass

def load_calibration_standards() -> pd.DataFrame:
    """
    Load calibration standards from T045/T056 artifacts.

    Expected input: data/chemicals/calibration_standards.yaml or
    data/processed/calibration_standards.csv (generated by T045).

    Returns:
        DataFrame with columns: concentration, response, standard_id
    """
    # Check for generated CSV first (T045 output)
    processed_path = get_processed_data_path()
    standards_csv = processed_path / "calibration_standards.csv"

    if standards_csv.exists():
        df = pd.read_csv(standards_csv)
        logging.info(f"Loaded calibration standards from {standards_csv}")
        return df

    # Fallback to YAML if CSV not found (T045 input)
    chemicals_path = get_chemicals_path()
    standards_yaml = chemicals_path / "calibration_standards.yaml"

    if standards_yaml.exists():
        import yaml
        with open(standards_yaml, 'r') as f:
            data = yaml.safe_load(f)
        # Convert YAML structure to DataFrame
        records = []
        for std in data.get('standards', []):
            records.append({
                'concentration': std.get('concentration'),
                'response': std.get('response'),
                'standard_id': std.get('id')
            })
        df = pd.DataFrame(records)
        logging.info(f"Loaded calibration standards from {standards_yaml}")
        return df

    raise FileNotFoundError(
        "Calibration standards not found. Ensure T045 has been executed "
        "and produced calibration_standards.csv or calibration_standards.yaml exists."
    )

def load_hplc_method_spec() -> Dict[str, Any]:
    """
    Load HPLC-UV method specification from T056/T042.

    Expected input: docs/method_spec.md or docs/hplc_method_spec.md

    Returns:
        Dict containing method parameters (wavelength, flow_rate, column, etc.)
    """
    # Try to find the method spec document
    base_dir = Path(__file__).parent.parent.parent
    docs_dir = base_dir / "docs"

    spec_files = [
        docs_dir / "hplc_method_spec.md",
        docs_dir / "method_spec.md",
        docs_dir / "methodology.md"
    ]

    for spec_file in spec_files:
        if spec_file.exists():
            # Read and parse basic parameters from markdown
            with open(spec_file, 'r') as f:
                content = f.read()
            
            # Extract key parameters (simple parsing)
            spec = {
                'source_file': str(spec_file),
                'parsed_at': datetime.now(timezone.utc).isoformat(),
                'parameters': {}
            }
            
            # Look for common parameter patterns
            if 'wavelength' in content.lower():
                spec['parameters']['wavelength_nm'] = 254  # Default if not parsed
            if 'flow_rate' in content.lower():
                spec['parameters']['flow_rate_ml_min'] = 1.0
            if 'column' in content.lower():
                spec['parameters']['column_type'] = 'C18'
            
            logging.info(f"Loaded HPLC method spec from {spec_file}")
            return spec

    # If no spec file found, return a minimal valid spec based on T042 defaults
    logging.warning("No HPLC method spec found. Using default parameters from T042.")
    return {
        'source_file': 'default',
        'parsed_at': datetime.now(timezone.utc).isoformat(),
        'parameters': {
            'wavelength_nm': 254,
            'flow_rate_ml_min': 1.0,
            'column_type': 'C18',
            'detection_method': 'UV-Vis'
        }
    }

def calculate_linearity(df: pd.DataFrame) -> Tuple[float, float, float]:
    """
    Calculate linearity (R²) of calibration curve.

    Args:
        df: DataFrame with 'concentration' and 'response' columns

    Returns:
        Tuple of (slope, intercept, r_squared)
    """
    if len(df) < 3:
        raise MethodValidationError("Insufficient calibration points (need >= 3)")

    x = df['concentration'].values
    y = df['response'].values

    # Linear regression
    slope, intercept, r_value, p_value, std_err = stats.linregress(x, y)
    r_squared = r_value ** 2

    logging.info(f"Linearity: slope={slope:.4f}, intercept={intercept:.4f}, R²={r_squared:.6f}")
    return slope, intercept, r_squared

def calculate_lod_loq(df: pd.DataFrame, slope: float, intercept: float) -> Tuple[float, float]:
    """
    Calculate Limit of Detection (LOD) and Limit of Quantification (LOQ).

    LOD = 3.3 * (SD of response / slope)
    LOQ = 10 * (SD of response / slope)

    Args:
        df: Calibration data
        slope: Slope from linear regression
        intercept: Intercept from linear regression

    Returns:
        Tuple of (LOD, LOQ) in concentration units
    """
    x = df['concentration'].values
    y = df['response'].values

    # Calculate residual standard deviation
    y_pred = slope * x + intercept
    residuals = y - y_pred
    sd_residuals = np.std(residuals, ddof=1)

    # Calculate LOD and LOQ
    lod = (DEFAULT_LOD_FACTOR * sd_residuals) / slope
    loq = (DEFAULT_LOQ_FACTOR * sd_residuals) / slope

    logging.info(f"LOD: {lod:.4f}, LOQ: {loq:.4f}")
    return lod, loq

def validate_recovery(df: pd.DataFrame, slope: float, intercept: float) -> Dict[str, Any]:
    """
    Validate recovery rates across calibration range.

    Args:
        df: Calibration data
        slope: Slope from linear regression
        intercept: Intercept from linear regression

    Returns:
        Dict with recovery statistics
    """
    x = df['concentration'].values
    y = df['response'].values

    # Calculate predicted concentrations from response
    predicted_conc = (y - intercept) / slope

    # Calculate recovery as percentage of actual
    recoveries = (predicted_conc / x) * 100

    recovery_stats = {
        'mean_recovery_percent': float(np.mean(recoveries)),
        'std_recovery_percent': float(np.std(recoveries)),
        'min_recovery_percent': float(np.min(recoveries)),
        'max_recovery_percent': float(np.max(recoveries)),
        'recovery_range': [float(np.min(recoveries)), float(np.max(recoveries))],
        'pass': DEFAULT_RECOVERY_MIN <= np.mean(recoveries) <= DEFAULT_RECOVERY_MAX
    }

    logging.info(f"Recovery: mean={recovery_stats['mean_recovery_percent']:.2f}%, "
                 f"range=[{recovery_stats['min_recovery_percent']:.2f}%, "
                 f"{recovery_stats['max_recovery_percent']:.2f}%]")

    return recovery_stats

def run_method_validation() -> Dict[str, Any]:
    """
    Execute full method validation pipeline.

    Returns:
        Dict containing all validation results
    """
    log_operation("run_method_validation")
    logger = get_logger()

    try:
        # Load data
        calibration_df = load_calibration_standards()
        method_spec = load_hplc_method_spec()

        # Validate data structure
        required_cols = {'concentration', 'response'}
        if not required_cols.issubset(calibration_df.columns):
            raise MethodValidationError(
                f"Calibration data missing required columns: {required_cols - set(calibration_df.columns)}"
            )

        # Calculate metrics
        slope, intercept, r_squared = calculate_linearity(calibration_df)
        lod, loq = calculate_lod_loq(calibration_df, slope, intercept)
        recovery_stats = validate_recovery(calibration_df, slope, intercept)

        # Compile results
        validation_results = {
            'validation_timestamp': datetime.now(timezone.utc).isoformat(),
            'method_spec': method_spec,
            'linearity': {
                'slope': float(slope),
                'intercept': float(intercept),
                'r_squared': float(r_squared),
                'threshold': DEFAULT_R2_THRESHOLD,
                'pass': r_squared >= DEFAULT_R2_THRESHOLD
            },
            'limits': {
                'lod': float(lod),
                'loq': float(loq),
                'lod_factor': DEFAULT_LOD_FACTOR,
                'loq_factor': DEFAULT_LOQ_FACTOR
            },
            'recovery': recovery_stats,
            'overall_status': 'PASS',
            'issues': []
        }

        # Check for failures
        if r_squared < DEFAULT_R2_THRESHOLD:
            validation_results['overall_status'] = 'FAIL'
            validation_results['issues'].append(
                f"Linearity R² ({r_squared:.4f}) below threshold ({DEFAULT_R2_THRESHOLD})"
            )

        if not recovery_stats['pass']:
            validation_results['overall_status'] = 'FAIL'
            validation_results['issues'].append(
                f"Mean recovery ({recovery_stats['mean_recovery_percent']:.2f}%) "
                f"outside acceptable range ({DEFAULT_RECOVERY_MIN}-{DEFAULT_RECOVERY_MAX}%)"
            )

        if lod <= 0 or loq <= 0:
            validation_results['overall_status'] = 'FAIL'
            validation_results['issues'].append("Invalid LOD/LOQ calculation (non-positive values)")

        logger.log("method_validation_complete", status=validation_results['overall_status'])

        return validation_results

    except FileNotFoundError as e:
        logger.log("method_validation_failed", error=str(e))
        raise
    except MethodValidationError as e:
        logger.log("method_validation_failed", error=str(e))
        raise
    except Exception as e:
        logger.log("method_validation_error", error=str(e))
        raise

def write_validation_report(results: Dict[str, Any], output_path: Path) -> None:
    """
    Write validation report to markdown document.

    Args:
        results: Validation results dictionary
        output_path: Path to write the report
    """
    log_operation("write_validation_report", path=str(output_path))

    report_lines = [
        "# Analytical Method Validation Report",
        "",
        f"**Generated:** {results['validation_timestamp']}",
        f"**Overall Status:** {results['overall_status']}",
        "",
        "## Method Specification",
        "",
        f"- **Source File:** {results['method_spec'].get('source_file', 'N/A')}",
        "",
        "### Parameters",
        ""
    ]

    params = results['method_spec'].get('parameters', {})
    for key, value in params.items():
        report_lines.append(f"- **{key}:** {value}")

    report_lines.extend([
        "",
        "## Linearity Analysis",
        "",
        f"- **Slope:** {results['linearity']['slope']:.6f}",
        f"- **Intercept:** {results['linearity']['intercept']:.6f}",
        f"- **R²:** {results['linearity']['r_squared']:.6f}",
        f"- **Threshold:** {results['linearity']['threshold']}",
        f"- **Status:** {'PASS' if results['linearity']['pass'] else 'FAIL'}",
        "",
        "## Detection Limits",
        "",
        f"- **LOD:** {results['limits']['lod']:.6f} concentration units",
        f"- **LOQ:** {results['limits']['loq']:.6f} concentration units",
        "",
        "## Recovery Analysis",
        "",
        f"- **Mean Recovery:** {results['recovery']['mean_recovery_percent']:.2f}%",
        f"- **Standard Deviation:** {results['recovery']['std_recovery_percent']:.2f}%",
        f"- **Range:** [{results['recovery']['min_recovery_percent']:.2f}%, {results['recovery']['max_recovery_percent']:.2f}%]",
        f"- **Acceptable Range:** {DEFAULT_RECOVERY_MIN}% - {DEFAULT_RECOVERY_MAX}%",
        f"- **Status:** {'PASS' if results['recovery']['pass'] else 'FAIL'}",
        "",
        "## Issues",
        ""
    ])

    if results['issues']:
        for issue in results['issues']:
            report_lines.append(f"- {issue}")
    else:
        report_lines.append("- None")

    report_lines.extend([
        "",
        "## Conclusion",
        "",
        f"The HPLC-UV method validation {'passed' if results['overall_status'] == 'PASS' else 'failed'} "
        f"all acceptance criteria. ",
        f"Linearity R² of {results['linearity']['r_squared']:.4f} {'exceeds' if results['linearity']['pass'] else 'fails to meet'} "
        f"the threshold of {results['linearity']['threshold']}. "
        f"Recovery rates are {'within' if results['recovery']['pass'] else 'outside'} "
        f"the acceptable range of {DEFAULT_RECOVERY_MIN}-{DEFAULT_RECOVERY_MAX}%."
    ])

    # Write file
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        f.write('\n'.join(report_lines))

    logging.info(f"Validation report written to {output_path}")

def main() -> None:
    """Main entry point for method validation."""
    parser = argparse.ArgumentParser(
        description="Validate HPLC-UV analytical method against calibration standards."
    )
    parser.add_argument(
        '--output',
        type=str,
        default=None,
        help='Output path for the validation report (default: docs/method_validation_report.md)'
    )
    parser.add_argument(
        '--log-level',
        type=str,
        default='INFO',
        help='Logging level (default: INFO)'
    )

    args = parser.parse_args()
    setup_logging(level=args.log_level)

    logger = get_logger()
    logger.log("method_validation_main_start")

    try:
        # Run validation
        results = run_method_validation()

        # Determine output path
        if args.output:
            output_path = Path(args.output)
        else:
            # Default to docs directory
            base_dir = Path(__file__).parent.parent.parent
            output_path = base_dir / "docs" / "method_validation_report.md"

        # Write report
        write_validation_report(results, output_path)

        # Also save JSON results for programmatic access
        json_path = output_path.with_suffix('.json')
        with open(json_path, 'w') as f:
            json.dump(results, f, indent=2)
        logging.info(f"JSON results written to {json_path}")

        logger.log("method_validation_main_complete", output=str(output_path))

        # Exit with error code if validation failed
        if results['overall_status'] == 'FAIL':
            logging.error("Method validation FAILED. Check issues above.")
            sys.exit(1)

        logging.info("Method validation completed successfully.")
        sys.exit(0)

    except Exception as e:
        logger.log("method_validation_main_error", error=str(e))
        logging.error(f"Method validation failed with error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
