"""
Contract test for robustness results schema.

Validates the structure and data types of the robustness results JSON output
generated by code/analysis/robustness.py and code/analysis/generate_final_json.py.

This test ensures compliance with the schema defined for User Story 3 (US3).
"""

import os
import json
import pytest
from pathlib import Path
from typing import Any, Dict, List

# Project root relative to this test file
PROJECT_ROOT = Path(__file__).parent.parent.parent
DATA_PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"

# Expected output file
ROBUSTNESS_RESULTS_PATH = DATA_PROCESSED_DIR / "robustness_results.json"

# Schema definitions based on task descriptions
# T021: Subsample results
SUBSAMPLE_SCHEMA = {
    "language": str,
    "coefficient": (int, float, type(None)),  # Can be null if model fails to converge
    "std_err": (int, float, type(None)),
    "p_value_raw": (int, float),
    "n_rows": int
}

# T022: Entropy model results
ENTROPY_SCHEMA = {
    "model_type": str,
    "coefficient": (int, float),
    "std_err": (int, float),
    "p_value_raw": (int, float),
    "coefficient_diff": (int, float)
}

# T034: Lagged variable results (nested structure in JSON)
LAGGED_SCHEMA = {
    "author_count_lag_1year_coefficient": (int, float, type(None)),
    "author_count_lag_1year_p_value": (int, float, type(None)),
    "cve_count_lag_1year_coefficient": (int, float, type(None)),
    "cve_count_lag_1year_p_value": (int, float, type(None)),
    "excluded_repos_note": str,
    "sample_size": int
}

# T042: Interaction terms results
INTERACTION_SCHEMA = {
    "interaction_term": str,
    "coefficient": (int, float),
    "std_err": (int, float),
    "p_value_raw": (int, float)
}

# T023: Global BH correction results (top level)
GLOBAL_BH_SCHEMA = {
    "author_count_p_value_raw": (int, float),
    "author_count_p_value_adj": (int, float),
    "entropy_p_value_raw": (int, float, type(None)),
    "entropy_p_value_adj": (int, float, type(None)),
    # Interaction terms and subsamples are usually aggregated in arrays or separate keys
    # We check for the presence of the main keys expected in the final aggregation
}

def load_robustness_results() -> Dict[str, Any]:
    """Load the robustness results JSON file."""
    if not ROBUSTNESS_RESULTS_PATH.exists():
        pytest.fail(f"Robustness results file not found at {ROBUSTNESS_RESULTS_PATH}. "
                    "Ensure T017, T021, T022, T034, T042 are complete and T023 has run.")
    
    with open(ROBUSTNESS_RESULTS_PATH, 'r', encoding='utf-8') as f:
        return json.load(f)

def validate_schema(data: Dict[str, Any], schema: Dict[str, type], context: str) -> None:
    """Validate a dictionary against a schema."""
    for key, expected_type in schema.items():
        assert key in data, f"Missing key '{key}' in {context}"
        value = data[key]
        if isinstance(expected_type, tuple):
            assert isinstance(value, expected_type), \
                f"Type mismatch for '{key}' in {context}: expected {expected_type}, got {type(value)}"
        else:
            assert isinstance(value, expected_type), \
                f"Type mismatch for '{key}' in {context}: expected {expected_type}, got {type(value)}"

def validate_list_of_dicts(data: List[Dict[str, Any]], item_schema: Dict[str, type], context: str) -> None:
    """Validate a list of dictionaries against an item schema."""
    assert isinstance(data, list), f"Expected list in {context}, got {type(data)}"
    for i, item in enumerate(data):
        assert isinstance(item, dict), f"Item {i} in {context} is not a dict"
        validate_schema(item, item_schema, f"{context} item {i}")

class TestRobustnessResultsSchema:
    """Contract tests for the robustness results JSON schema."""

    def test_file_exists(self):
        """Assert the robustness results file exists."""
        assert ROBUSTNESS_RESULTS_PATH.exists(), \
            f"Robustness results file missing at {ROBUSTNESS_RESULTS_PATH}"

    def test_top_level_keys(self):
        """Assert top-level keys exist in the results."""
        data = load_robustness_results()
        assert isinstance(data, dict), "Root of robustness results must be a dict"
        
        # Expected top-level keys based on T023 aggregation
        required_keys = [
            "main_model_results",      # From T017
            "subsample_results",       # From T021
            "entropy_results",         # From T022
            "lagged_results",          # From T034
            "interaction_results",     # From T042
            "bh_adjusted_pvalues"      # From T023
        ]
        
        for key in required_keys:
            assert key in data, f"Missing required top-level key: {key}"

    def test_main_model_results_structure(self):
        """Validate the structure of the main model results (T017)."""
        data = load_robustness_results()
        main_results = data.get("main_model_results", {})
        
        # Check for expected fields from T017
        assert "author_count_coefficient" in main_results
        assert "std_err" in main_results
        assert "p_value" in main_results
        assert "ci_95_lower" in main_results
        assert "ci_95_upper" in main_results
        assert "convergence_status" in main_results
        assert "model_type" in main_results
        
        assert isinstance(main_results["convergence_status"], bool)
        assert main_results["model_type"] == "NegativeBinomial"

    def test_subsample_results_structure(self):
        """Validate the subsample results structure (T021)."""
        data = load_robustness_results()
        subsamples = data.get("subsample_results", [])
        
        # T021 output is a list of results per language
        if subsamples:
            validate_list_of_dicts(subsamples, SUBSAMPLE_SCHEMA, "subsample_results")

    def test_entropy_results_structure(self):
        """Validate the entropy model results structure (T022)."""
        data = load_robustness_results()
        entropy_results = data.get("entropy_results", {})
        
        if entropy_results:
            validate_schema(entropy_results, ENTROPY_SCHEMA, "entropy_results")

    def test_lagged_results_structure(self):
        """Validate the lagged variable results structure (T034)."""
        data = load_robustness_results()
        lagged_results = data.get("lagged_results", {})
        
        if lagged_results:
            validate_schema(lagged_results, LAGGED_SCHEMA, "lagged_results")

    def test_interaction_results_structure(self):
        """Validate the interaction terms results structure (T042)."""
        data = load_robustness_results()
        interactions = data.get("interaction_results", [])
        
        if interactions:
            validate_list_of_dicts(interactions, INTERACTION_SCHEMA, "interaction_results")

    def test_bh_adjusted_pvalues_structure(self):
        """Validate the Benjamini-Hochberg adjusted p-values structure (T023)."""
        data = load_robustness_results()
        bh_results = data.get("bh_adjusted_pvalues", {})
        
        # T023 aggregates all raw p-values and outputs adjusted ones
        # We check that the structure exists and contains adjusted values
        assert isinstance(bh_results, dict), "bh_adjusted_pvalues must be a dict"
        
        # Ensure at least one adjusted p-value exists to prove the step ran
        adjusted_keys = [k for k in bh_results.keys() if "adj" in k.lower()]
        assert len(adjusted_keys) > 0, "No adjusted p-values found in bh_adjusted_pvalues"

    def test_no_null_p_values_in_main_model(self):
        """Assert that the main model has valid p-values if converged."""
        data = load_robustness_results()
        main_results = data.get("main_model_results", {})
        
        if main_results.get("convergence_status", False):
            p_val = main_results.get("p_value")
            assert p_val is not None, "p_value should not be null if model converged"
            assert isinstance(p_val, (int, float)), "p_value must be numeric"
            assert 0 <= p_val <= 1, "p_value must be between 0 and 1"