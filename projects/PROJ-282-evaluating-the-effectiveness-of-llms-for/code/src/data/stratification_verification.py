def calculate_distribution_stats(df: pd.DataFrame) -> Dict[str, Dict[str, float]]:
    """
    Calculate the distribution of language and ground_truth_category in the sample.
    
    Returns a dictionary with counts and percentages for each category.
    """
    stats = {}
    
    # Language distribution
    if 'language' in df.columns:
        lang_counts = df['language'].value_counts(normalize=True)
        stats['language'] = {
            'counts': df['language'].value_counts().to_dict(),
            'percentages': lang_counts.to_dict()
        }
    else:
        logger.warning("Column 'language' not found in dataframe.")
        stats['language'] = {}

    # Vulnerability category distribution
    # The schema defines 'ground_truth_category'
    category_col = 'ground_truth_category'
    if category_col in df.columns:
        cat_counts = df[category_col].value_counts(normalize=True)
        stats['ground_truth_category'] = {
            'counts': df[category_col].value_counts().to_dict(),
            'percentages': cat_counts.to_dict()
        }
    else:
        logger.warning(f"Column '{category_col}' not found in dataframe.")
        stats['ground_truth_category'] = {}
        
    return stats

