import json
import sys
from pathlib import Path
from typing import Any, Dict, List

# Ensure project root is in path
project_root = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(project_root))

from src.utils.config import get_data_path

REQUIRED_FIELDS = [
    "mean_success_rate",
    "bh_corrected_primary",
    "bh_corrected_sensitivity",
    "linearity_correlation_coefficient",
    "reconstruction_error",
    "memory_footprint",
    "observed_success_rate_diff",
    "power_estimate",
    "bh_rejected_count",
    "status_linearity",
    "warnings",
    "data_integrity",
    "zero_variance_incidents",
    "statistical_power"
]

def load_report(path: Path) -> Dict[str, Any]:
    """Load the stats report JSON file."""
    if not path.exists():
        raise FileNotFoundError(f"Report file not found: {path}")
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)

def validate_structure(report: Dict[str, Any]) -> List[str]:
    """
    Validate that the report contains all required sections mandated by T077.
    Returns a list of missing or invalid fields.
    """
    errors = []
    
    # Check top-level required fields
    for field in REQUIRED_FIELDS:
        if field not in report:
            errors.append(f"Missing required field: {field}")
        elif field == "reconstruction_error" and not isinstance(report[field], dict):
            errors.append(f"Field 'reconstruction_error' must be a dictionary")
        elif field == "warnings" and not isinstance(report[field], list):
            errors.append(f"Field 'warnings' must be a list")
        elif field == "power_estimate" and not isinstance(report[field], (int, float)):
            errors.append(f"Field 'power_estimate' must be a number")

    # Specific T077 Mandates
    # 1. Statistical Power Section
    if "statistical_power" not in report:
        errors.append("Missing 'statistical_power' section (T077 requirement)")
    else:
        sp = report["statistical_power"]
        if not isinstance(sp, dict):
            errors.append("'statistical_power' must be a dictionary")
        else:
            if "power_estimate" not in sp:
                errors.append("'statistical_power' missing 'power_estimate'")
            if "threshold_met" not in sp:
                errors.append("'statistical_power' missing 'threshold_met'")
            if "limitations" not in sp:
                errors.append("'statistical_power' missing 'limitations'")

    # 2. Zero-Variance Incidents Section
    if "zero_variance_incidents" not in report:
        errors.append("Missing 'zero_variance_incidents' section (T077 requirement)")
    elif not isinstance(report["zero_variance_incidents"], list):
        errors.append("'zero_variance_incidents' must be a list")

    # 3. Data Integrity Section
    if "data_integrity" not in report:
        errors.append("Missing 'data_integrity' section (T077 requirement)")
    else:
        di = report["data_integrity"]
        if not isinstance(di, dict):
            errors.append("'data_integrity' must be a dictionary")
        else:
            if "sources_verified" not in di:
                errors.append("'data_integrity' missing 'sources_verified'")
            if "synthetic_data_detected" not in di:
                errors.append("'data_integrity' missing 'synthetic_data_detected'")

    return errors

def main():
    """
    Validates reports/final_report.md indirectly by validating the source stats_report.json
    which T080 requires to be complete.
    """
    print("Starting T080 Validation: Checking stats_report.json completeness...")
    
    # Path to the stats report generated by T032b
    stats_report_path = get_data_path("results") / "stats_report.json"
    
    if not stats_report_path.exists():
        print(f"ERROR: stats_report.json not found at {stats_report_path}")
        print("T080 cannot proceed: The report generator (T032b) did not produce the required file.")
        sys.exit(1)

    try:
        report = load_report(stats_report_path)
        errors = validate_structure(report)
        
        if errors:
            print(f"VALIDATION FAILED: {len(errors)} issues found in {stats_report_path}:")
            for err in errors:
                print(f"  - {err}")
            print("\nT080 Status: FAILED")
            sys.exit(1)
        else:
            print("VALIDATION PASSED: All required sections present.")
            print(f"  - Statistical Power: {report.get('statistical_power', {}).get('power_estimate', 'N/A')}")
            print(f"  - Zero-Variance Incidents: {len(report.get('zero_variance_incidents', []))} recorded")
            print(f"  - Data Integrity: {report.get('data_integrity', {}).get('synthetic_data_detected', 'N/A')}")
            print("\nT080 Status: COMPLETED")
            sys.exit(0)
            
    except json.JSONDecodeError as e:
        print(f"ERROR: Invalid JSON in stats_report.json: {e}")
        sys.exit(1)
    except Exception as e:
        print(f"ERROR: Unexpected error during validation: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()