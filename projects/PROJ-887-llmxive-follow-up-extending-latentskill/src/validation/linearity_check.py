"""
Linearity Check: FR-007

Calculates the Pearson correlation between text-space distances and weight-space distances
for a held-out set of known task pairs to validate the linearity assumption of the
LatentSkill retrieval geometry.

Output:
    data/results/linearity_check.json
        {
            "correlation": float,
            "validity": bool,  # True if correlation >= 0.6
            "sample_size": int,
            "threshold": 0.6
        }
"""
import json
import os
import time
from pathlib import Path

import numpy as np
from scipy.stats import pearsonr
from sentence_transformers import SentenceTransformer

# Project root resolution
PROJECT_ROOT = Path(__file__).resolve().parents[2]
DATA_PROCESSED = PROJECT_ROOT / "data" / "processed"
DATA_RESULTS = PROJECT_ROOT / "data" / "results"
SKILL_INDEX_PATH = DATA_PROCESSED / "skill_index.npz"
OUTPUT_PATH = DATA_RESULTS / "linearity_check.json"

# Configuration
THRESHOLD = 0.6
MODEL_NAME = "all-MiniLM-L6-v2"

def load_skill_index() -> tuple[np.ndarray, list[str]]:
    """
    Loads the skill index from the .npz file generated by T014.
    Returns the vectors and the list of task names (keys).
    """
    if not SKILL_INDEX_PATH.exists():
        raise FileNotFoundError(
            f"Skill index not found at {SKILL_INDEX_PATH}. "
            "Please ensure T014 (vector_db.py) has been executed successfully."
        )
    
    data = np.load(SKILL_INDEX_PATH)
    # The index is typically saved with a key like 'vectors' and 'names' or similar.
    # Based on T014 implementation, we expect 'vectors' and 'task_ids' or 'names'.
    # We will inspect keys to be robust.
    keys = list(data.keys())
    if 'vectors' not in keys:
        raise ValueError(f"Expected 'vectors' key in {SKILL_INDEX_PATH}, found: {keys}")
    
    vectors = data['vectors']
    
    # Determine names
    if 'task_ids' in keys:
        names = data['task_ids']
    elif 'names' in keys:
        names = data['names']
    else:
        # Fallback: generate generic names if not present
        names = [f"task_{i}" for i in range(len(vectors))]
    
    # Ensure names are a list of strings
    if isinstance(names, np.ndarray):
        names = [str(n) for n in names]
    
    return vectors, names

def get_text_embedding(text: str, model: SentenceTransformer) -> np.ndarray:
    """Generates a text embedding for a given string."""
    return model.encode(text, convert_to_numpy=True, show_progress_bar=False)[0]

def get_weight_distance(vec_a: np.ndarray, vec_b: np.ndarray) -> float:
    """Calculates the Euclidean distance (or cosine distance) between two weight vectors."""
    # Using Euclidean distance as a proxy for weight-space distance
    return np.linalg.norm(vec_a - vec_b)

def calculate_linearity() -> dict:
    """
    Main logic to calculate Pearson correlation between text and weight distances.
    """
    print(f"Loading skill index from {SKILL_INDEX_PATH}...")
    vectors, task_names = load_skill_index()
    
    if len(vectors) < 2:
        raise ValueError("Not enough vectors in the skill index to perform linearity check.")
    
    print(f"Loaded {len(vectors)} skill vectors.")
    
    # Load text embedding model
    print(f"Loading text embedding model: {MODEL_NAME}...")
    model = SentenceTransformer(MODEL_NAME)
    
    # Generate text embeddings for all tasks
    print("Generating text embeddings for all tasks...")
    text_embeddings = []
    for name in task_names:
        # We assume the task name itself is a reasonable proxy for the task description
        # In a real scenario, we might have a separate description file, but task names
        # from the dataset (e.g., "alfworld/put") are often descriptive enough for this check.
        emb = get_text_embedding(name, model)
        text_embeddings.append(emb)
    
    text_embeddings = np.array(text_embeddings)
    
    # We need to compare distances for pairs.
    # Strategy: For each pair (i, j), calculate:
    #   d_text = distance(text_emb_i, text_emb_j)
    #   d_weight = distance(weight_vec_i, weight_vec_j)
    # Then compute Pearson correlation between the list of d_text and d_weight.
    
    # To avoid O(N^2) explosion if N is large, we can sample pairs or use all if N is small.
    # Given the context of "held-out set of known task pairs", we will use all pairs
    # if N <= 50, otherwise sample 500 random pairs.
    n_tasks = len(vectors)
    if n_tasks <= 50:
        pairs = [(i, j) for i in range(n_tasks) for j in range(i + 1, n_tasks)]
    else:
        import random
        random.seed(42)
        all_pairs = [(i, j) for i in range(n_tasks) for j in range(i + 1, n_tasks)]
        pairs = random.sample(all_pairs, 500)
    
    print(f"Calculating distances for {len(pairs)} pairs...")
    
    text_distances = []
    weight_distances = []
    
    start_time = time.time()
    
    for i, j in pairs:
        # Text distance (Euclidean in embedding space)
        d_text = np.linalg.norm(text_embeddings[i] - text_embeddings[j])
        
        # Weight distance
        d_weight = get_weight_distance(vectors[i], vectors[j])
        
        text_distances.append(d_text)
        weight_distances.append(d_weight)
    
    elapsed = time.time() - start_time
    print(f"Distance calculation completed in {elapsed:.2f}s.")
    
    text_distances = np.array(text_distances)
    weight_distances = np.array(weight_distances)
    
    # Calculate Pearson correlation
    correlation, p_value = pearsonr(text_distances, weight_distances)
    
    validity = float(correlation) >= THRESHOLD
    
    result = {
        "correlation": float(correlation),
        "p_value": float(p_value),
        "validity": validity,
        "threshold": THRESHOLD,
        "sample_size": len(pairs),
        "num_tasks": n_tasks,
        "execution_time_seconds": elapsed
    }
    
    return result

def main():
    """Entry point for the linearity check script."""
    # Ensure output directory exists
    DATA_RESULTS.mkdir(parents=True, exist_ok=True)
    
    try:
        result = calculate_linearity()
        
        # Write output
        with open(OUTPUT_PATH, 'w') as f:
            json.dump(result, f, indent=2)
        
        print(f"Linearity check completed.")
        print(f"Correlation: {result['correlation']:.4f}")
        print(f"Validity (>= {THRESHOLD}): {result['validity']}")
        print(f"Results saved to {OUTPUT_PATH}")
        
    except Exception as e:
        print(f"Error during linearity check: {e}")
        raise

if __name__ == "__main__":
    main()
