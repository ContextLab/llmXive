def test_edge_case_empty_index():
    """
    Test behavior when the skill index is empty or missing.
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        empty_index_path = Path(tmpdir) / "empty_index.npz"
        # Create an empty npz file
        np.savez(empty_index_path, vectors=np.array([]), metadata={})
        
        with pytest.raises(Exception) as exc_info:
            load_skill_index(empty_index_path)
        
        assert "index is empty" in str(exc_info.value).lower() or "no vectors" in str(exc_info.value).lower()


def test_edge_case_synthesis_failure():
    """
    Test behavior when synthesis fails due to invalid strategy or indices.
    """
    # This test relies on the implementation in src/retrieval/strategies.py
    # We assume it raises a ValueError for invalid indices
    index_path = Path("data/processed/skill_index.npz")
    if not index_path.exists():
        pytest.skip("Skill index missing for edge case test.")
        
    index_data = load_skill_index(index_path)
    
    with pytest.raises(ValueError):
        synthesize_adapter(
            index_data=index_data,
            query_vector=np.zeros(10), # Invalid dim for test
            strategy_type=StrategyType.UNWEIGHTED_MEAN,
            k=100, # k > available neighbors
            neighbor_indices=[999],
            output_dir=Path("artifacts/synthesized_adapters")
        )

