"""
Feasibility Gate Enforcer for the Plant Disease Susceptibility Pipeline.

This module implements the logic to check the feasibility gate status
generated by T001a. If the status is FAIL, the pipeline halts immediately
with exit code 1. If PASS, it proceeds with exit code 0.

Dependency: T001a (must have generated data/processed/feasibility_gate_status.yaml)
"""
import sys
import yaml
from pathlib import Path

# Import logging utilities from the existing project surface
from src.utils.logger import get_logger, setup_logging_for_task

# Constants
GATE_STATUS_FILE = Path("data/processed/feasibility_gate_status.yaml")
TASK_ID = "T001c"

def main() -> int:
    """
    Main entry point for the feasibility gate enforcer.

    Returns:
        int: Exit code 0 if PASS, 1 if FAIL.
    """
    # Setup logging for this task
    logger = setup_logging_for_task(TASK_ID)
    logger.info("Starting Feasibility Gate Enforcer (T001c).")

    # Check if the status file exists
    if not GATE_STATUS_FILE.exists():
        logger.error(
            f"Feasibility Gate Status file not found at {GATE_STATUS_FILE}. "
            "T001a may not have completed successfully."
        )
        # Since the gate file is missing, we cannot proceed.
        # Treat this as a failure to prevent downstream errors.
        print("Feasibility Gate Failed: Halting pipeline.", file=sys.stderr)
        return 1

    try:
        with open(GATE_STATUS_FILE, "r", encoding="utf-8") as f:
            status_data = yaml.safe_load(f)
    except yaml.YAMLError as e:
        logger.error(f"Failed to parse YAML file {GATE_STATUS_FILE}: {e}")
        print("Feasibility Gate Failed: Invalid YAML format.", file=sys.stderr)
        return 1
    except Exception as e:
        logger.error(f"Unexpected error reading {GATE_STATUS_FILE}: {e}")
        print("Feasibility Gate Failed: Unable to read status file.", file=sys.stderr)
        return 1

    # Validate the structure
    if not isinstance(status_data, dict):
        logger.error("Feasibility Gate Status file does not contain a valid dictionary.")
        print("Feasibility Gate Failed: Invalid status structure.", file=sys.stderr)
        return 1

    status_value = status_data.get("status")

    if status_value is None:
        logger.error("Feasibility Gate Status file is missing the 'status' key.")
        print("Feasibility Gate Failed: Missing 'status' key.", file=sys.stderr)
        return 1

    status_str = str(status_value).upper()

    if status_str == "FAIL":
        logger.warning("Feasibility Gate Status is FAIL. Halting pipeline.")
        print("Feasibility Gate Failed: Halting pipeline.", file=sys.stderr)
        return 1

    elif status_str == "PASS":
        logger.info("Feasibility Gate Status is PASS. Proceeding.")
        return 0

    else:
        logger.error(f"Feasibility Gate Status has an unknown value: {status_value}")
        print(f"Feasibility Gate Failed: Unknown status value '{status_value}'.", file=sys.stderr)
        return 1

if __name__ == "__main__":
    exit_code = main()
    sys.exit(exit_code)
