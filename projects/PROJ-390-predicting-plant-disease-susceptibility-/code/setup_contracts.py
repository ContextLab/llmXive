"""
Setup script for schema validation contracts (Task T007).

This script ensures that the schema definition files exist in the
data/contracts/ directory. It does not validate data yet, but provides
the schema definitions required for T009, T017, T023, and T036.
"""
import os
import sys
from pathlib import Path

def setup_contracts():
    """Create the schema contract files if they don't exist."""
    # Determine project root relative to this script
    script_dir = Path(__file__).resolve().parent
    project_root = script_dir.parent
    contracts_dir = project_root / "data" / "contracts"
    
    # Ensure directory exists
    contracts_dir.mkdir(parents=True, exist_ok=True)
    
    schemas = {
        "feature_matrix.schema.yaml": """
$schema: http://json-schema.org/draft-07/schema#
title: Feature Matrix Schema
description: >
  Schema for the integrated feature matrix containing genomic variant frequencies
  and environmental metadata. Generated by the ingestion pipeline (T014).
type: object
required:
  - columns
  - data
properties:
  columns:
    type: array
    description: List of column names defining the feature space.
    items:
type: string
    minItems: 3
    contains:
const: "disease_susceptibility"
  data:
    type: array
    description: Row-wise data where each row represents a sample.
    items:
type: object
additionalProperties: true
required:
  - sample_id
  - species
  - disease_susceptibility
  metadata:
    type: object
    description: Optional metadata about the generation of this file.
    properties:
generated_by:
  type: string
source_files:
  type: array
  items:
    type: string
imputation_method:
  type: string
  enum: ["knn", "none"]
row_count:
  type: integer
  minimum: 0
additionalProperties: false
""",
        "model_output.schema.yaml": """
$schema: http://json-schema.org/draft-07/schema#
title: Model Output Schema
description: >
  Schema for model performance metrics and evaluation results.
  Generated by the modeling pipeline (T021).
type: object
required:
  - model_name
  - metrics
  - hyperparameters
properties:
  model_name:
    type: string
    enum: ["RandomForest", "SVM"]
  metrics:
    type: object
    required:
- auc_roc
- precision
- recall
- f1_score
    properties:
auc_roc:
  type: number
  minimum: 0
  maximum: 1
auc_pr:
  type: number
  minimum: 0
  maximum: 1
precision:
  type: number
  minimum: 0
  maximum: 1
recall:
  type: number
  minimum: 0
  maximum: 1
f1_score:
  type: number
  minimum: 0
  maximum: 1
accuracy:
  type: number
  minimum: 0
  maximum: 1
    additionalProperties: false
  hyperparameters:
    type: object
    description: The best hyperparameters found during grid search.
    additionalProperties: true
  feature_importance:
    type: array
    description: List of features with their importance scores.
    items:
type: object
required:
  - feature_name
  - importance_score
properties:
  feature_name:
    type: string
  importance_score:
    type: number
    minimum: 0
  train_test_split:
    type: object
    properties:
train_size:
  type: integer
test_size:
  type: integer
validation_size:
  type: integer
additionalProperties: false
""",
        "linkage_method.schema.yaml": """
$schema: http://json-schema.org/draft-07/schema#
title: Linkage Method Schema
description: >
  Schema documenting the method used to link genomic data with phenotypic labels.
  Generated by T015 (validate_labels).
type: object
required:
  - method_name
  - source_type
  - validation_status
properties:
  method_name:
    type: string
    description: Name of the linkage method used (e.g., 'independent_phenotyping').
  source_type:
    type: string
    description: Type of the phenotypic source (e.g., 'field-trial-db').
    enum:
- field-trial-db
- pathology-archive
- public-repository
  validation_status:
    type: string
    enum:
- verified
- ambiguous
- excluded
  description:
    type: string
    description: Detailed description of how the linkage was performed.
  excluded_samples_count:
    type: integer
    minimum: 0
    description: Number of samples excluded due to ambiguous linkage.
  included_samples_count:
    type: integer
    minimum: 0
    description: Number of samples successfully linked.
  timestamp:
    type: string
    format: date-time
    description: ISO 8601 timestamp of when the validation was run.
additionalProperties: false
""",
        "variance_decomposition.schema.yaml": """
$schema: http://json-schema.org/draft-07/schema#
title: Variance Decomposition Schema
description: >
  Schema for variance decomposition results using Redundancy Analysis (RDA).
  Generated by T027.
type: object
required:
  - total_variance_explained
  - group_percentages
properties:
  total_variance_explained:
    type: number
    minimum: 0
    maximum: 1
    description: Total proportion of variance in the response explained by all predictors.
  group_percentages:
    type: object
    required:
- genomic
- environmental
    properties:
genomic:
  type: number
  minimum: 0
  maximum: 1
  description: Proportion of variance explained by genomic features.
environmental:
  type: number
  minimum: 0
  maximum: 1
  description: Proportion of variance explained by environmental features.
shared:
  type: number
  minimum: 0
  maximum: 1
  description: Proportion of variance explained by the overlap of genomic and environmental features.
    additionalProperties: false
  method_details:
    type: object
    properties:
rda_method:
  type: string
  const: "Redundancy Analysis"
scaling:
  type: integer
  description: RDA scaling type used.
seed:
  type: integer
  const: 42
additionalProperties: false
"""
    }

    created_count = 0
    for filename, content in schemas.items():
        file_path = contracts_dir / filename
        if not file_path.exists():
            with open(file_path, 'w', encoding='utf-8') as f:
                f.write(content.strip() + '\n')
            print(f"Created: {file_path}")
            created_count += 1
        else:
            print(f"Exists (skipped): {file_path}")
    
    print(f"\nSetup complete. {created_count} new schema files created.")
    return created_count

if __name__ == "__main__":
    setup_contracts()