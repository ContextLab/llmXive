"""Sensitivity analysis for token limit sweeps.

Reads the raw sweep results generated by T018 (results_sweep_raw.csv),
aggregates metrics by token limit, and computes the maximum absolute change
between adjacent thresholds.

Output: results/sensitivity_trend.csv
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Dict, Any, Optional

# Ensure project root is in path for imports
project_root = Path(__file__).resolve().parent.parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from utils.logging import get_logger

logger = get_logger(__name__)

# Expected token limits in order
TOKEN_LIMITS = [128, 256, 512]


@dataclass
class SensitivityResult:
    """Single row of aggregated sensitivity data."""
    token_limit: int
    mean_specialization: float
    mean_retrieval: float
    max_absolute_change: float


@dataclass
class SensitivityAnalysisOutput:
    """Complete output of the sensitivity analysis."""
    results: List[SensitivityResult] = field(default_factory=list)
    input_file: str = ""
    output_file: str = ""


def load_sweep_raw_data(input_path: str) -> List[Dict[str, Any]]:
    """Load the raw sweep CSV generated by T018.

    Expected columns: game_id, specialization_index, retrieval_efficiency,
    context_condition, agent_count, token_limit (or similar).

    We expect a 'token_limit' column to exist. If not, we raise an error.
    """
    rows = []
    if not os.path.exists(input_path):
        raise FileNotFoundError(f"Sweep raw data not found: {input_path}")

    with open(input_path, "r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        # Validate required columns
        if "token_limit" not in reader.fieldnames:
            raise ValueError(
                f"Input file {input_path} missing required column 'token_limit'. "
                f"Available columns: {reader.fieldnames}"
            )
        if "specialization_index" not in reader.fieldnames:
            raise ValueError(
                f"Input file {input_path} missing required column 'specialization_index'."
            )
        if "retrieval_efficiency" not in reader.fieldnames:
            raise ValueError(
                f"Input file {input_path} missing required column 'retrieval_efficiency'."
            )

        for row in reader:
            try:
                token_limit = int(row["token_limit"])
                spec_idx = float(row["specialization_index"])
                ret_eff = float(row["retrieval_efficiency"])
                rows.append({
                    "token_limit": token_limit,
                    "specialization_index": spec_idx,
                    "retrieval_efficiency": ret_eff
                })
            except (ValueError, TypeError) as e:
                logger.warning(f"Skipping malformed row in {input_path}: {e}")
                continue

    if not rows:
        raise ValueError(f"No valid data rows found in {input_path}")

    return rows


def aggregate_by_token_limit(
    data: List[Dict[str, Any]],
    token_limits: List[int]
) -> Dict[int, Dict[str, float]]:
    """Aggregate metrics by token limit, computing means.

    Returns: { token_limit: { "mean_spec": float, "mean_ret": float } }
    """
    aggregates: Dict[int, List[Dict[str, float]]] = {lim: [] for lim in token_limits}

    for row in data:
        lim = row["token_limit"]
        if lim in aggregates:
            aggregates[lim].append({
                "spec": row["specialization_index"],
                "ret": row["retrieval_efficiency"]
            })

    results: Dict[int, Dict[str, float]] = {}
    for lim in token_limits:
        items = aggregates[lim]
        if not items:
            # If no data for a specific limit, we cannot compute a mean.
            # This might happen if the sweep didn't cover all limits.
            logger.warning(f"No data found for token limit {lim}. Skipping aggregation.")
            results[lim] = {"mean_spec": float("nan"), "mean_ret": float("nan")}
        else:
            mean_spec = sum(item["spec"] for item in items) / len(items)
            mean_ret = sum(item["ret"] for item in items) / len(items)
            results[lim] = {"mean_spec": mean_spec, "mean_ret": mean_ret}

    return results


def compute_max_absolute_change(
    aggregated: Dict[int, Dict[str, float]],
    token_limits: List[int]
) -> float:
    """Compute the maximum absolute difference in any metric between adjacent thresholds.

    We look at:
    |mean_128 - mean_256|
    |mean_256 - mean_512|
    For both specialization and retrieval.
    Returns the maximum of these absolute differences.
    """
    max_change = 0.0
    valid_pairs = []

    for i in range(len(token_limits) - 1):
        lim_curr = token_limits[i]
        lim_next = token_limits[i + 1]

        curr_data = aggregated.get(lim_curr)
        next_data = aggregated.get(lim_next)

        if not curr_data or not next_data:
            # Skip if data is missing for a limit
            continue

        # Check for NaN
        if (isinstance(curr_data["mean_spec"], float) and str(curr_data["mean_spec"]) == "nan") or \
           (isinstance(next_data["mean_spec"], float) and str(next_data["mean_spec"]) == "nan"):
            continue

        diff_spec = abs(curr_data["mean_spec"] - next_data["mean_spec"])
        diff_ret = abs(curr_data["mean_ret"] - next_data["mean_ret"])

        valid_pairs.append((lim_curr, lim_next, diff_spec, diff_ret))
        max_change = max(max_change, diff_spec, diff_ret)

    if not valid_pairs:
        logger.warning("No valid adjacent pairs found to compute max_absolute_change.")

    return max_change


def write_results_csv(
    output_path: str,
    results: List[SensitivityResult]
) -> None:
    """Write the sensitivity trend CSV."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=[
            "token_limit", "mean_specialization", "mean_retrieval", "max_absolute_change"
        ])
        writer.writeheader()
        for row in results:
            writer.writerow({
                "token_limit": row.token_limit,
                "mean_specialization": f"{row.mean_specialization:.6f}",
                "mean_retrieval": f"{row.mean_retrieval:.6f}",
                "max_absolute_change": f"{row.max_absolute_change:.6f}"
            })

    logger.info(f"Wrote sensitivity trend results to {output_path}")


def run_sensitivity_analysis(
    input_path: str,
    output_path: str,
    token_limits: Optional[List[int]] = None
) -> SensitivityAnalysisOutput:
    """Main entry point for sensitivity analysis."""
    if token_limits is None:
        token_limits = TOKEN_LIMITS

    logger.info(f"Loading sweep data from {input_path}")
    data = load_sweep_raw_data(input_path)
    logger.info(f"Loaded {len(data)} rows")

    logger.info(f"Aggregating by token limits: {token_limits}")
    aggregated = aggregate_by_token_limit(data, token_limits)

    # Compute max absolute change across the whole sweep
    max_change = compute_max_absolute_change(aggregated, token_limits)
    logger.info(f"Computed max_absolute_change: {max_change}")

    # Build output rows
    output_rows = []
    for lim in token_limits:
        agg = aggregated.get(lim)
        if not agg:
            continue
        # For each row, the max_absolute_change is the global max computed above
        # as per task requirement: "max_absolute_change must be the maximum absolute
        # difference in any metric between any two adjacent thresholds"
        output_rows.append(SensitivityResult(
            token_limit=lim,
            mean_specialization=agg["mean_spec"],
            mean_retrieval=agg["mean_ret"],
            max_absolute_change=max_change
        ))

    logger.info(f"Writing results to {output_path}")
    write_results_csv(output_path, output_rows)

    return SensitivityAnalysisOutput(
        results=output_rows,
        input_file=input_path,
        output_file=output_path
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Run sensitivity analysis on token limit sweep data."
    )
    parser.add_argument(
        "--input",
        type=str,
        default="results/results_sweep_raw.csv",
        help="Path to the raw sweep CSV (default: results/results_sweep_raw.csv)"
    )
    parser.add_argument(
        "--output",
        type=str,
        default="results/sensitivity_trend.csv",
        help="Path for the output trend CSV (default: results/sensitivity_trend.csv)"
    )
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    # Resolve paths relative to project root if they are not absolute
    input_path = args.input
    output_path = args.output

    if not os.path.isabs(input_path):
        input_path = os.path.join(project_root, input_path)
    if not os.path.isabs(output_path):
        output_path = os.path.join(project_root, output_path)

    try:
        run_sensitivity_analysis(input_path, output_path)
        logger.info("Sensitivity analysis completed successfully.")
    except Exception as e:
        logger.error(f"Sensitivity analysis failed: {e}", exc_info=True)
        sys.exit(1)


if __name__ == "__main__":
    main()