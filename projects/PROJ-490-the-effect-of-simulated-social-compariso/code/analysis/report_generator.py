import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional
from datetime import datetime

from data.config import get_config
from utils.logger import get_logger

logger = get_logger(__name__)

def load_model_results() -> Dict[str, Any]:
    """
    Load regression coefficients and model diagnostics from disk.
    Expects: data/processed/regression_coefficients.csv and data/processed/model_diagnostics.json
    """
    config = get_config()
    coeff_path = config.PROCESSED_DIR / "regression_coefficients.csv"
    diag_path = config.PROCESSED_DIR / "model_diagnostics.json"

    result = {
        "coefficients": [],
        "assumptions": {},
        "data_source_type": "unknown"
    }

    if coeff_path.exists():
        import pandas as pd
        df = pd.read_csv(coeff_path)
        result["coefficients"] = df.to_dict(orient="records")
    else:
        logger.warning(f"Coefficient file not found: {coeff_path}")

    if diag_path.exists():
        with open(diag_path, "r") as f:
            diag_data = json.load(f)
            result["assumptions"] = diag_data.get("assumptions", {})
            # Try to extract data_source_type from diagnostics if present
            if "data_source_type" in diag_data:
                result["data_source_type"] = diag_data["data_source_type"]
    else:
        logger.warning(f"Diagnostics file not found: {diag_path}")

    return result

def load_bootstrap_results() -> Dict[str, Any]:
    """
    Load bootstrap stability results.
    Expects: data/processed/bootstrap_results.json (generated by bootstrap.py)
    """
    config = get_config()
    path = config.PROCESSED_DIR / "bootstrap_results.json"

    if path.exists():
        with open(path, "r") as f:
            return json.load(f)
    else:
        logger.warning(f"Bootstrap results file not found: {path}")
        return {
            "ci_variance": 0.0,
            "iterations": 0,
            "stability_failed": True,
            "message": "No bootstrap results found"
        }

def load_sensitivity_results() -> Dict[str, Any]:
    """
    Load sensitivity sweep results.
    Expects: data/processed/sensitivity_sweep_results.csv
    """
    config = get_config()
    path = config.PROCESSED_DIR / "sensitivity_sweep_results.csv"

    if path.exists():
        import pandas as pd
        df = pd.read_csv(path)
        # Convert to list of dicts for JSON serialization
        return {
            "results": df.to_dict(orient="records"),
            "total_tests": len(df)
        }
    else:
        logger.warning(f"Sensitivity results file not found: {path}")
        return {
            "results": [],
            "total_tests": 0,
            "message": "No sensitivity results found"
        }

def load_data_path() -> str:
    """
    Load the decision state to determine data path used.
    Expects: state/data_path_decision.yaml
    """
    config = get_config()
    # The state file is in the project root's state directory
    state_path = config.PROJECT_ROOT / "state" / "data_path_decision.yaml"

    if state_path.exists():
        import yaml
        with open(state_path, "r") as f:
            data = yaml.safe_load(f)
            return data.get("source", "unknown")
    else:
        logger.warning(f"State decision file not found: {state_path}")
        return "unknown"

def determine_interpretation_label(data_source_type: str) -> str:
    """
    Determine the interpretation label based on data source type.
    """
    if data_source_type == "synthetic":
        return "Simulated Causal Effect"
    elif data_source_type == "real":
        return "Empirical Association"
    else:
        return "Unknown Data Source"

def generate_final_report(
    model_results: Dict[str, Any],
    bootstrap_results: Dict[str, Any],
    sensitivity_results: Dict[str, Any],
    data_source_type: str
) -> Dict[str, Any]:
    """
    Assemble the final report JSON structure.
    """
    # Extract parameter recovery bias if available (from sensitivity results or separate file)
    param_recovery_bias = 0.0
    # Try to load parameter recovery bias from a dedicated file if it exists
    config = get_config()
    recovery_path = config.PROCESSED_DIR / "parameter_recovery.json"
    if recovery_path.exists():
        with open(recovery_path, "r") as f:
            recovery_data = json.load(f)
            param_recovery_bias = recovery_data.get("bias", 0.0)

    report = {
        "data_source_type": data_source_type,
        "model_coefficients": model_results.get("coefficients", []),
        "bootstrap_ci_variance": bootstrap_results.get("ci_variance", 0.0),
        "parameter_recovery_bias": param_recovery_bias,
        "sensitivity_results": sensitivity_results.get("results", []),
        "stability_failed": bootstrap_results.get("stability_failed", False),
        "interpretation": determine_interpretation_label(data_source_type),
        "generated_at": datetime.utcnow().isoformat(),
        "assumptions": model_results.get("assumptions", {})
    }

    return report

def save_report(report: Dict[str, Any], output_path: Optional[Path] = None) -> Path:
    """
    Save the final report to disk.
    """
    config = get_config()
    if output_path is None:
        output_path = config.PROCESSED_DIR / "final_report.json"

    with open(output_path, "w") as f:
        json.dump(report, f, indent=2)

    logger.info(f"Final report saved to: {output_path}")
    return output_path

def run_report_generation() -> Path:
    """
    Main entry point to generate and save the final report.
    Orchestrates loading of all components and writing the final artifact.
    """
    log_execution_start("run_report_generation")

    try:
        # 1. Load Model Results
        logger.info("Loading model results...")
        model_results = load_model_results()

        # 2. Load Bootstrap Results
        logger.info("Loading bootstrap results...")
        bootstrap_results = load_bootstrap_results()

        # 3. Load Sensitivity Results
        logger.info("Loading sensitivity results...")
        sensitivity_results = load_sensitivity_results()

        # 4. Determine Data Source Type
        # Check model diagnostics first, then state file, then default
        data_source_type = model_results.get("data_source_type", "unknown")
        if data_source_type == "unknown":
            state_source = load_data_path()
            # Infer type from state source if it looks like a dataset id vs local path
            if "synthetic" in state_source.lower():
                data_source_type = "synthetic"
            elif state_source != "unknown":
                data_source_type = "real"
            else:
                data_source_type = "unknown"

        # 5. Generate Final Report
        logger.info("Generating final report...")
        report = generate_final_report(
            model_results,
            bootstrap_results,
            sensitivity_results,
            data_source_type
        )

        # 6. Save Report
        logger.info("Saving final report...")
        output_path = save_report(report)

        log_execution_end("run_report_generation")
        return output_path

    except Exception as e:
        logger.error(f"Error generating final report: {e}", exc_info=True)
        raise

def main():
    """
    CLI entry point for report generation.
    """
    run_report_generation()

if __name__ == "__main__":
    main()