import os
import csv
import logging
from pathlib import Path
from typing import List, Dict, Any, Tuple

from utils import get_project_root, get_data_dir, setup_logging, ProjectError

logger = logging.getLogger(__name__)

def validate_materials_csv(file_path: Path) -> Tuple[bool, List[str]]:
    """
    Validates the materials CSV file generated by T015.
    
    Checks:
    1. No missing values (empty strings or None) for 'valid' status materials.
    2. All 'cost' values are positive scalars for valid materials.
    
    Args:
        file_path: Path to the materials.csv file.
        
    Returns:
        Tuple of (is_valid, list_of_error_messages)
    """
    errors = []
    
    if not file_path.exists():
        return False, [f"File not found: {file_path}"]
    
    required_columns = {
        'material_id', 'thermal_conductivity', 'emissivity', 
        'specific_heat', 'density', 'unit_price', 'cost', 'status'
    }
    
    valid_materials_count = 0
    rows_checked = 0
    
    try:
        with open(file_path, 'r', newline='', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            
            # Check header
            if reader.fieldnames is None:
                return False, ["CSV file is empty or has no header"]
            
            header_set = set(reader.fieldnames)
            missing_cols = required_columns - header_set
            if missing_cols:
                return False, [f"Missing required columns: {missing_cols}"]
            
            for row_num, row in enumerate(reader, start=2): # Start at 2 because row 1 is header
                rows_checked += 1
                material_id = row.get('material_id', '').strip()
                status = row.get('status', '').strip().lower()
                
                # Only validate strict constraints for 'valid' materials
                if status == 'valid':
                    valid_materials_count += 1
                    
                    # Check for missing values in critical fields
                    critical_fields = ['thermal_conductivity', 'emissivity', 'specific_heat', 
                                     'density', 'unit_price', 'cost']
                    
                    for field in critical_fields:
                        val = row.get(field)
                        if val is None or val.strip() == '':
                            errors.append(f"Row {row_num}: Missing value for '{field}' in valid material '{material_id}'")
                    
                    # Check cost is positive scalar
                    try:
                        cost_val = float(row.get('cost', '0'))
                        if cost_val <= 0:
                            errors.append(f"Row {row_num}: Cost must be positive for valid material '{material_id}'. Found: {cost_val}")
                    except ValueError:
                        errors.append(f"Row {row_num}: Invalid cost value for valid material '{material_id}': '{row.get('cost')}'")
                    
                    # Check unit_price is positive scalar
                    try:
                        price_val = float(row.get('unit_price', '0'))
                        if price_val <= 0:
                            errors.append(f"Row {row_num}: Unit price must be positive for valid material '{material_id}'. Found: {price_val}")
                    except ValueError:
                        errors.append(f"Row {row_num}: Invalid unit price value for valid material '{material_id}': '{row.get('unit_price')}'")
                else:
                    # For non-valid materials, just ensure status field exists and is not empty
                    if status == '':
                        errors.append(f"Row {row_num}: Status field is empty")
                
    except csv.Error as e:
        return False, [f"CSV parsing error: {e}"]
    except Exception as e:
        return False, [f"Unexpected error reading CSV: {e}"]
    
    if valid_materials_count == 0:
        errors.append("No materials with 'valid' status found in the CSV")
    
    is_valid = len(errors) == 0
    return is_valid, errors

def main():
    """
    Main entry point to validate the materials.csv file.
    """
    setup_logging()
    project_root = get_project_root()
    csv_path = project_root / "data" / "processed" / "materials.csv"
    
    logger.info(f"Validating materials CSV at: {csv_path}")
    
    is_valid, errors = validate_materials_csv(csv_path)
    
    if is_valid:
        logger.info("Validation PASSED: All valid materials have no missing values and positive costs.")
        return 0
    else:
        logger.error("Validation FAILED:")
        for err in errors:
            logger.error(f"  - {err}")
        return 1

if __name__ == "__main__":
    exit(main())
