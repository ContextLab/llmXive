"""
Validation script for T016: Validate that the output CSV contains no missing values
for valid materials and that all costs are positive scalars.
"""
import os
import csv
import logging
from pathlib import Path
from typing import List, Dict, Any, Tuple

from utils import get_project_root, get_data_dir, setup_logging, ProjectError

logger = setup_logging(__name__)

def validate_materials_csv(csv_path: Path) -> Tuple[bool, List[str]]:
    """
    Validates the materials.csv file generated by T015.
    
    Checks:
    1. File exists and is readable.
    2. No missing values (empty strings or NaN) in columns for valid materials.
    3. All cost values are positive scalars (> 0).
    4. Status field correctly identifies valid vs invalid entries.
    
    Args:
        csv_path: Path to the materials.csv file
        
    Returns:
        Tuple of (is_valid, list_of_error_messages)
    """
    errors = []
    
    if not csv_path.exists():
        errors.append(f"File not found: {csv_path}")
        return False, errors
    
    try:
        with open(csv_path, 'r', newline='', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            rows = list(reader)
    except Exception as e:
        errors.append(f"Failed to read CSV: {e}")
        return False, errors
    
    if not rows:
        errors.append("CSV file is empty (no data rows)")
        return False, errors
    
    # Expected columns based on T015 specification
    expected_columns = {
        'material_id', 'thermal_conductivity', 'emissivity', 
        'specific_heat', 'density', 'unit_price', 'calculated_cost', 'status'
    }
    
    if not expected_columns.issubset(set(rows[0].keys())):
        missing = expected_columns - set(rows[0].keys())
        errors.append(f"Missing expected columns: {missing}")
        return False, errors
    
    valid_count = 0
    invalid_count = 0
    
    for i, row in enumerate(rows, start=1):
        material_id = row.get('material_id', '').strip()
        status = row.get('status', '').strip().lower()
        
        # Check status field
        if status not in ['valid', 'invalid_price']:
            errors.append(f"Row {i}: Invalid status '{status}' for material {material_id}")
        
        if status == 'invalid_price':
            invalid_count += 1
            # For invalid entries, we allow missing values in cost-related fields
            # but material_id and status should still be present
            if not material_id:
                errors.append(f"Row {i}: Missing material_id for invalid entry")
            continue
        
        valid_count += 1
        
        # For valid materials, check for missing values in critical fields
        critical_fields = [
            'thermal_conductivity', 'emissivity', 'specific_heat', 
            'density', 'unit_price', 'calculated_cost'
        ]
        
        for field in critical_fields:
            value = row.get(field, '').strip()
            if not value or value.lower() in ['nan', 'none', 'null', '']:
                errors.append(f"Row {i}: Missing value for '{field}' in valid material {material_id}")
        
        # Check that costs are positive scalars
        try:
            cost = float(row.get('calculated_cost', ''))
            if cost <= 0:
                errors.append(f"Row {i}: Cost must be positive (> 0), got {cost} for {material_id}")
            
            unit_price = float(row.get('unit_price', ''))
            if unit_price <= 0:
                errors.append(f"Row {i}: Unit price must be positive (> 0), got {unit_price} for {material_id}")
        except ValueError as e:
            errors.append(f"Row {i}: Non-numeric value in cost/price fields for {material_id}: {e}")
    
    # Summary checks
    if valid_count == 0:
        errors.append("No valid materials found in the CSV (all entries have invalid_price status)")
    
    logger.info(f"Validation complete: {valid_count} valid materials, {invalid_count} invalid entries")
    logger.info(f"Total errors found: {len(errors)}")
    
    is_valid = len(errors) == 0
    return is_valid, errors

def main():
    """Main entry point for the validation script."""
    project_root = get_project_root()
    csv_path = project_root / 'data' / 'processed' / 'materials.csv'
    
    logger.info(f"Validating materials CSV at: {csv_path}")
    
    is_valid, errors = validate_materials_csv(csv_path)
    
    if is_valid:
        logger.info("✅ Validation PASSED: All valid materials have complete data and positive costs.")
        return 0
    else:
        logger.error("❌ Validation FAILED:")
        for error in errors:
            logger.error(f"  - {error}")
        return 1

if __name__ == '__main__':
    exit(main())
