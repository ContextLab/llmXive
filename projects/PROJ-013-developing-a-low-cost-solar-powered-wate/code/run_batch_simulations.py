"""
Task T026: Run batch simulation for all material-geometry combinations.

Executes the 1D transient heat transfer simulation for:
- 4 Materials (Aluminum, Copper, Black-painted Steel, Plastic)
- 3 Geometries (Flat-plate, Single-slope, Double-slope)
Total: 12 combinations.

Prerequisites:
- T008: Solar irradiance profiles available
- T015: materials.csv with valid costs and properties
- T020-T024: Simulation and validation logic implemented

Output:
- data/processed/simulation_results.csv (generated by T025 logic called here)
- Runtime < 180 seconds on CPU.
"""
import os
import sys
import time
import logging
from pathlib import Path
from typing import List, Dict, Any, Tuple

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from data_ingestion import load_nist_materials, GeometryConfig, calculate_cost
from simulation import run_simulation, calculate_time_averaged_efficiency
from validation import validate_simulation_result, calculate_energy_balance_closure
from generate_simulation_results import save_simulation_results
from utils import get_project_root, get_data_dir, setup_logging

logger = setup_logging()

def get_material_geometries() -> List[Tuple[Dict[str, Any], GeometryConfig]]:
    """
    Loads materials from the processed CSV and pairs them with the 3 defined geometries.
    Returns a list of tuples: (material_dict, geometry_config).
    """
    materials_dir = get_data_dir() / "processed"
    materials_path = materials_dir / "materials.csv"

    if not materials_path.exists():
        raise FileNotFoundError(f"Required materials.csv not found at {materials_path}. "
                                "Run T015 (generate_materials_csv) first.")

    materials = []
    with open(materials_path, 'r', newline='', encoding='utf-8') as f:
        import csv
        reader = csv.DictReader(f)
        for row in reader:
            # Filter out invalid materials (status != 'valid')
            if row.get('status') != 'valid':
                logger.warning(f"Skipping material {row['material_id']} due to invalid status: {row.get('status')}")
                continue
            materials.append(row)

    if not materials:
        raise ValueError("No valid materials found in materials.csv. Cannot proceed with simulation.")

    # Define the 3 geometries as per spec (T020)
    geometries = [
        GeometryConfig(
            geometry_id="flat_plate",
            inclination_angle=0.0,
            surface_area=1.0,
            absorber_thickness=0.002, # 2mm
            cover_thickness=0.003,    # 3mm
            gap_height=0.05
        ),
        GeometryConfig(
            geometry_id="single_slope",
            inclination_angle=30.0,
            surface_area=1.0,
            absorber_thickness=0.002,
            cover_thickness=0.003,
            gap_height=0.05
        ),
        GeometryConfig(
            geometry_id="double_slope",
            inclination_angle=45.0,
            surface_area=1.0,
            absorber_thickness=0.002,
            cover_thickness=0.003,
            gap_height=0.05
        )
    ]

    combinations = []
    for mat in materials:
        for geom in geometries:
            combinations.append((mat, geom))

    return combinations

def run_single_simulation(material: Dict[str, Any], geometry: GeometryConfig) -> Dict[str, Any]:
    """
    Runs the simulation for a single material-geometry pair.
    Returns the result dictionary or None if validation fails.
    """
    try:
        # 1. Prepare material properties
        mat_id = material['material_id']
        # Convert string properties to float
        props = {
            'thermal_conductivity': float(material['thermal_conductivity']),
            'emissivity': float(material['emissivity']),
            'specific_heat': float(material['specific_heat']),
            'density': float(material['density']),
            'unit_price': float(material['unit_price'])
        }

        # 2. Calculate Cost (T014)
        cost = calculate_cost([material], geometry)

        # 3. Run Simulation (T021, T022)
        # The run_simulation function expects a material dict and geometry
        sim_result = run_simulation(material, geometry)

        if sim_result is None:
            logger.error(f"Simulation failed for {mat_id} / {geometry.geometry_id}")
            return None

        # 4. Calculate Efficiency
        efficiency = calculate_time_averaged_efficiency(sim_result)

        # 5. Validation (T023)
        is_valid, closure_status = validate_simulation_result(sim_result)

        if not is_valid:
            logger.warning(f"Validation failed (Energy Balance) for {mat_id} / {geometry.geometry_id}: {closure_status}")
            return None

        return {
            'material_id': mat_id,
            'geometry_id': geometry.geometry_id,
            'thermal_conductivity': props['thermal_conductivity'],
            'emissivity': props['emissivity'],
            'specific_heat': props['specific_heat'],
            'density': props['density'],
            'unit_price': props['unit_price'],
            'total_cost': cost,
            'steady_state_efficiency': efficiency,
            'convergence_status': 'passed' if is_valid else 'failed'
        }

    except Exception as e:
        logger.error(f"Error running simulation for {material.get('material_id')} / {geometry.geometry_id}: {e}", exc_info=True)
        return None

def main():
    """
    Entry point for T026: Batch simulation runner.
    """
    logger.info("Starting Batch Simulation (T026)...")
    start_time = time.time()

    try:
        # 1. Get all combinations
        combinations = get_material_geometries()
        logger.info(f"Found {len(combinations)} valid material-geometry combinations.")

        if len(combinations) != 12:
            logger.warning(f"Expected 12 combinations (4 materials * 3 geometries), found {len(combinations)}. "
                           "This may be due to previous filtering of invalid materials.")

        results = []
        failed_count = 0

        # 2. Run loop
        for i, (mat, geom) in enumerate(combinations):
            logger.info(f"Running [{i+1}/{len(combinations)}]: {mat['material_id']} - {geom.geometry_id}")
            result = run_single_simulation(mat, geom)
            if result:
                results.append(result)
            else:
                failed_count += 1

        # 3. Save Results (T025)
        if results:
            output_path = get_data_dir() / "processed" / "simulation_results.csv"
            save_simulation_results(results, output_path)
            logger.info(f"Saved {len(results)} successful results to {output_path}")
        else:
            logger.error("No successful simulations completed. No output file generated.")
            return 1

        # 4. Timing Check
        elapsed = time.time() - start_time
        logger.info(f"Batch simulation completed in {elapsed:.2f} seconds.")
        if elapsed > 180:
            logger.warning(f"Runtime exceeded 180s limit ({elapsed:.2f}s). Consider optimizing ODE solver.")
        else:
            logger.info("Runtime constraint (<180s) satisfied.")

        return 0

    except Exception as e:
        logger.error(f"Batch simulation failed: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())
