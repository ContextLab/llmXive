"""
Synthetic Data Pipeline Runner for T110 Integration Test.

This script orchestrates the full pipeline execution against synthetic data
generated by T107 (generate_synthetic_data.py). It verifies that all expected
output artifacts are created, satisfying the integration test requirement.

Execution: python code/run_synthetic_pipeline.py
"""
import os
import sys
import json
import argparse
import time
from pathlib import Path

# Import from existing modules in the API surface
from generate_synthetic_data import set_seeds, load_required_variables, generate_metagenomic_counts, generate_sleep_metrics, generate_synthetic_dataset, generate_synthetic_manifest, main as gen_main
from ingest import load_data, validate_variables, detect_outliers_iqr, save_outlier_report, filter_outliers, save_filtered_data, record_artifact_checksum
from analysis import set_analysis_seed, check_distribution, select_correlation_method, run_correlation_analysis, benjamini_hochberg_fdr, save_method_selection_log
from diagnostics import set_diagnostics_seed, detect_perfect_multicollinearity, calculate_vif, run_sensitivity_analysis, calculate_power
from report import generate_report, load_json_file

def ensure_dirs(base_path: Path):
    """Ensure all required output directories exist."""
    dirs = [
        base_path / "raw",
        base_path / "processed",
        base_path / "results",
        base_path / "metadata"
    ]
    for d in dirs:
        d.mkdir(parents=True, exist_ok=True)

def run_synthetic_generation(output_path: Path, config_path: Path):
    """Generate synthetic dataset and manifest."""
    print("Generating synthetic dataset...")
    set_seeds(42)
    
    # Load required variables from config
    required_vars = load_required_variables(config_path)
    
    # Generate data
    data = generate_synthetic_dataset(required_vars)
    
    # Save raw synthetic data
    raw_csv_path = output_path / "raw" / "synthetic_data.csv"
    data.to_csv(raw_csv_path, index=False)
    print(f"Synthetic data saved to {raw_csv_path}")
    
    # Generate and save manifest
    manifest = generate_synthetic_manifest(data, config_path)
    manifest_path = output_path / "raw" / "synthetic_manifest.json"
    with open(manifest_path, 'w') as f:
        json.dump(manifest, f, indent=2)
    print(f"Manifest saved to {manifest_path}")
    
    return raw_csv_path

def run_ingestion(input_path: Path, output_path: Path, config_path: Path):
    """Run ingestion, validation, outlier detection, and filtering."""
    print("Running ingestion and validation...")
    
    # Load and validate data
    df, metrics = load_data(input_path, config_path)
    
    # Save variable load metrics
    metrics_path = output_path / "results" / "variable_load_metrics.json"
    with open(metrics_path, 'w') as f:
        json.dump(metrics, f, indent=2)
    print(f"Variable load metrics saved to {metrics_path}")
    
    # Detect outliers
    outlier_report = detect_outliers_iqr(df)
    save_outlier_report(outlier_report, output_path / "results" / "outlier_report.json")
    print(f"Outlier report saved to {output_path / 'results' / 'outlier_report.json'}")
    
    # Filter outliers and save
    filtered_df, exclusion_log = filter_outliers(df, outlier_report)
    filtered_path = output_path / "processed" / "filtered_data.parquet"
    save_filtered_data(filtered_df, filtered_path)
    save_artifact_checksum(filtered_path, output_path / "results" / "artifact_checksums.json")
    
    # Save exclusion log
    exclusion_log_path = output_path / "results" / "outlier_exclusion_log.json"
    with open(exclusion_log_path, 'w') as f:
        json.dump(exclusion_log, f, indent=2)
    print(f"Exclusion log saved to {exclusion_log_path}")
    print(f"Filtered data saved to {filtered_path}")
    
    return filtered_df

def save_artifact_checksum(file_path: Path, state_path: Path):
    """Record checksum of an artifact."""
    import hashlib
    with open(file_path, 'rb') as f:
        content = f.read()
        checksum = hashlib.sha256(content).hexdigest()
    
    state = {"artifact_hashes": {}}
    if state_path.exists():
        with open(state_path, 'r') as f:
            state = json.load(f)
    
    state["artifact_hashes"][str(file_path)] = checksum
    
    with open(state_path, 'w') as f:
        json.dump(state, f, indent=2)

def run_analysis(input_path: Path, output_path: Path):
    """Run correlation analysis and diagnostics."""
    print("Running analysis...")
    
    # Load filtered data
    df = load_json_file(str(input_path)).replace("NaN", float('nan')) # Placeholder, need actual parquet loading
    import pandas as pd
    df = pd.read_parquet(input_path)
    
    # Check distribution
    dist_info = check_distribution(df)
    
    # Select method
    method = select_correlation_method(df, dist_info)
    save_method_selection_log(method, output_path / "metadata" / "method_selection_log.json")
    print(f"Method selection: {method}")
    
    # Run correlation analysis
    results = run_correlation_analysis(df, method)
    
    # Apply FDR correction
    corrected_results = benjamini_hochberg_fdr(results)
    
    # Save correlation matrix
    corr_matrix_path = output_path / "results" / "correlation_matrix.json"
    with open(corr_matrix_path, 'w') as f:
        json.dump(corrected_results, f, indent=2)
    print(f"Correlation matrix saved to {corr_matrix_path}")
    
    return corrected_results

def run_diagnostics(input_path: Path, output_path: Path):
    """Run diagnostics: collinearity, VIF, power, sensitivity."""
    print("Running diagnostics...")
    
    import pandas as pd
    df = pd.read_parquet(input_path)
    
    # Detect multicollinearity
    collinearity_map = detect_perfect_multicollinearity(df)
    
    # Calculate VIF
    vif_report = calculate_vif(df)
    vif_path = output_path / "results" / "vif_report.json"
    with open(vif_path, 'w') as f:
        json.dump(vif_report, f, indent=2)
    print(f"VIF report saved to {vif_path}")
    
    # Run sensitivity analysis
    sensitivity_results = run_sensitivity_analysis(df)
    sensitivity_path = output_path / "results" / "sensitivity_analysis.csv"
    sensitivity_results.to_csv(sensitivity_path, index=False)
    print(f"Sensitivity analysis saved to {sensitivity_path}")
    
    # Calculate power
    power_report = calculate_power(df)
    power_path = output_path / "results" / "power_analysis_report.json"
    with open(power_path, 'w') as f:
        json.dump(power_report, f, indent=2)
    print(f"Power analysis saved to {power_path}")
    
    # Save collinearity warnings
    warnings_path = output_path / "results" / "collinearity_warnings.json"
    with open(warnings_path, 'w') as f:
        json.dump({"collinearity_map": collinearity_map, "vif_flags": vif_report.get("flags", [])}, f, indent=2)
    print(f"Collinearity warnings saved to {warnings_path}")

def verify_outputs(output_path: Path):
    """Verify all required outputs exist."""
    required_files = [
        "raw/synthetic_data.csv",
        "raw/synthetic_manifest.json",
        "results/variable_load_metrics.json",
        "results/outlier_report.json",
        "processed/filtered_data.parquet",
        "results/outlier_exclusion_log.json",
        "metadata/method_selection_log.json",
        "results/correlation_matrix.json",
        "results/vif_report.json",
        "results/sensitivity_analysis.csv",
        "results/power_analysis_report.json",
        "results/collinearity_warnings.json"
    ]
    
    missing = []
    for rel_path in required_files:
        full_path = output_path / rel_path
        if not full_path.exists():
            missing.append(rel_path)
    
    if missing:
        print(f"ERROR: Missing required outputs: {missing}")
        return False
    
    print("SUCCESS: All required outputs generated.")
    return True

def run_full_pipeline(config_path: Path, output_path: Path):
    """Execute the full synthetic pipeline."""
    start_time = time.time()
    
    ensure_dirs(output_path)
    
    # 1. Generate Synthetic Data
    raw_data_path = run_synthetic_generation(output_path, config_path)
    
    # 2. Ingestion & Validation
    filtered_data_path = run_ingestion(raw_data_path, output_path, config_path)
    
    # 3. Analysis
    run_analysis(filtered_data_path, output_path)
    
    # 4. Diagnostics
    run_diagnostics(filtered_data_path, output_path)
    
    # 5. Timing Evidence
    end_time = time.time()
    timing = {"total_runtime_seconds": end_time - start_time, "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    timing_path = output_path / "results" / "timing_evidence.json"
    with open(timing_path, 'w') as f:
        json.dump(timing, f, indent=2)
    print(f"Timing evidence saved to {timing_path}")
    
    # 6. Verify
    return verify_outputs(output_path)

def main():
    parser = argparse.ArgumentParser(description="Run Synthetic Data Pipeline Integration Test (T110)")
    parser.add_argument("--config", type=str, default="data/config/required_variables.yaml", help="Path to required variables config")
    parser.add_argument("--output", type=str, default="data", help="Base output directory")
    args = parser.parse_args()
    
    config_path = Path(args.config)
    output_path = Path(args.output)
    
    if not config_path.exists():
        print(f"ERROR: Config file not found: {config_path}")
        sys.exit(1)
    
    success = run_full_pipeline(config_path, output_path)
    
    if not success:
        print("Pipeline execution completed but verification failed.")
        sys.exit(1)
    
    print("T110 Integration Test PASSED: Synthetic pipeline ran successfully and generated all outputs.")
    sys.exit(0)

if __name__ == "__main__":
    main()
