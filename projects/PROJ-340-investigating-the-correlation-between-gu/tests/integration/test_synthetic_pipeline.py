    def test_pipeline_halt_on_missing_variable_integration(self, temp_output_dir):
        """
        Verify that the pipeline halts when a required variable is missing.
        
        This re-tests the logic from test_missing_variable.py but in the context
        of the full pipeline execution flow.
        """
        raw_output = temp_output_dir / "data" / "raw"
        raw_output.mkdir(parents=True, exist_ok=True)
        
        # Create data missing a required column
        missing_df = pd.DataFrame({
            'subject_id': [1, 2],
            'other_col': [10, 20]
            # 'sleep_duration' missing
        })
        
        data_path = raw_output / "missing_data.csv"
        missing_df.to_csv(data_path, index=False)
        
        # Attempt to load (this should fail)
        try:
            # This simulates what main.py does
            # load_data would call validate_variables which should raise
            load_data(str(data_path), config_path="data/config/required_variables.yaml")
            pytest.fail("Pipeline should have halted on missing variable")
        except SystemExit:
            pass # Expected
        except ValueError as e:
            assert "missing" in str(e).lower() or "SWS duration" in str(e)
        except Exception:
            # Any other error related to missing columns is acceptable
            pass