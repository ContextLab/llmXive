def test_synthetic_pipeline_execution():
    """
    Run the full pipeline against synthetic data and verify all outputs.
    
    Steps:
    1. Ensure synthetic data exists (generated by T107).
    2. Run the main pipeline script (code/main.py) in synthetic mode.
    3. Verify the exit code is 0.
    4. Verify all expected output files exist and are non-empty.
    """
    # 1. Ensure synthetic data exists
    synthetic_input = DATA_DIR / "raw" / "synthetic_test_data.csv"
    if not synthetic_input.exists():
        # Attempt to generate it if missing (re-run T107 logic)
        # Note: In a real CI, T107 would have run first.
        # We invoke the generator script directly.
        generator_script = CODE_DIR / "generate_synthetic_data.py"
        if generator_script.exists():
            gen_cmd = [sys.executable, str(generator_script), "--output", str(synthetic_input)]
            gen_result = subprocess.run(gen_cmd, cwd=PROJECT_ROOT, capture_output=True, text=True)
            if gen_result.returncode != 0:
                pytest.fail(f"Failed to generate synthetic data: {gen_result.stderr}")
        else:
            pytest.fail(f"Synthetic data missing and generator script not found: {synthetic_input}")
    
    assert synthetic_input.exists(), "Synthetic input data missing before pipeline run."

    # 2. Run the main pipeline
    # We run main.py with the synthetic input. The --mode flag is handled inside.
    main_script = CODE_DIR / "main.py"
    
    # Construct command
    # Assuming main.py accepts --input and --output arguments as per typical patterns
    cmd = [
        sys.executable,
        str(main_script),
        "--input", str(synthetic_input),
        "--output", str(DATA_DIR / "results"),
        "--mode", "synthetic"
    ]
    
    # Run with timeout (6 hours limit enforced by code, but we set a safe timeout for test)
    # Using 300 seconds for the test to avoid hanging if logic is broken
    try:
        result = subprocess.run(
            cmd,
            cwd=PROJECT_ROOT,
            capture_output=True,
            text=True,
            timeout=300
        )
    except subprocess.TimeoutExpired:
        pytest.fail("Pipeline execution timed out (>300s).")

    # 3. Verify exit code
    # Note: If the pipeline fails due to missing real data config, that's expected in strict mode
    # unless we explicitly enable synthetic mode. The task requires the pipeline to run ON synthetic data.
    # We check if the run succeeded or failed for a non-fabrication reason.
    
    # If the code raises an error because real data is missing but synthetic mode wasn't triggered,
    # we need to ensure the command triggers synthetic mode correctly.
    # Based on T081a, there is a set_validation_mode logic.
    
    # Let's assume the command succeeded for the purpose of artifact check if RC is 0.
    # If RC is non-zero, we need to inspect why.
    if result.returncode != 0:
        # Check if it's a "No real data found" error that we need to bypass
        if "No required variables loaded" in result.stderr or "Real data fetch" in result.stderr:
            # The task is to run the pipeline on synthetic data.
            # If the main.py doesn't handle --mode synthetic correctly to bypass real-data checks,
            # we might need to adjust the command or the script.
            # However, T110 is an integration test. If the pipeline is broken, the test fails.
            # We assert failure here to report the issue.
            pytest.fail(f"Pipeline execution failed with RC {result.returncode}.\nSTDOUT: {result.stdout}\nSTDERR: {result.stderr}")
        else:
            pytest.fail(f"Pipeline execution failed with RC {result.returncode}.\nSTDOUT: {result.stdout}\nSTDERR: {result.stderr}")

    # 4. Verify all expected output files exist
    missing_files = []
    for f_path in EXPECTED_OUTPUTS:
        if not f_path.exists():
            missing_files.append(str(f_path.relative_to(PROJECT_ROOT)))
        elif f_path.stat().st_size == 0:
            missing_files.append(f"{f_path.relative_to(PROJECT_ROOT)} (empty)")
    
    if missing_files:
        pytest.fail(f"Missing or empty expected output files:\n - " + "\n - ".join(missing_files))

    # 5. Verify content validity of key JSON files (optional but good for integration)
    json_files = [f for f in EXPECTED_OUTPUTS if f.suffix == ".json"]
    for jf in json_files:
        try:
            with open(jf, 'r') as f:
                data = json.load(f)
                # Basic sanity check: not empty dict unless expected
                if not data and jf.name not in ["compositionality_flag.json"]:
                    # Allow empty if it's a specific case, but generally warn
                    pass 
        except json.JSONDecodeError as e:
            pytest.fail(f"Invalid JSON in {jf}: {e}")

def test_pipeline_timing_evidence():
    """Verify that timing evidence was recorded."""
    timing_file = DATA_DIR / "results" / "timing_evidence.json"
    if not timing_file.exists():
        pytest.fail("timing_evidence.json not found")
    
    with open(timing_file, 'r') as f:
        data = json.load(f)
    
    assert "elapsed_seconds" in data or "duration" in data, "timing_evidence.json missing duration field"
    assert data.get("elapsed_seconds", data.get("duration", 0)) < 21600, "Pipeline exceeded 6-hour limit"

def test_method_selection_log():
    """Verify method selection log exists and has content."""
    log_file = DATA_DIR / "metadata" / "method_selection_log.json"
    if not log_file.exists():
        pytest.fail("method_selection_log.json not found")
    
    with open(log_file, 'r') as f:
        data = json.load(f)
    
    assert isinstance(data, dict), "method_selection_log.json should be a dict"
    assert len(data) > 0, "method_selection_log.json is empty"

