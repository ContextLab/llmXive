"""
Contract test for MaAsLin2 output schema.

This test validates that the association results file generated by
src/analysis/correlation_maaslin2.py conforms to the expected schema.

Expected Schema:
- taxon (str)
- maaslin2_beta (float)
- maaslin2_se (float)
- maaslin2_p_value (float)
- maaslin2_q_value (float)
- spearman_rho (float)
- spearman_se (float)
- spearman_p_value (float)
"""
import os
import pytest
import pandas as pd
from pathlib import Path
from typing import List, Set

# Define the expected columns based on T021 specification
EXPECTED_COLUMNS: List[str] = [
    "taxon",
    "maaslin2_beta",
    "maaslin2_se",
    "maaslin2_p_value",
    "maaslin2_q_value",
    "spearman_rho",
    "spearman_se",
    "spearman_p_value"
]

# Define the expected output file path relative to project root
EXPECTED_OUTPUT_PATH: str = "data/processed/results/association_results.tsv"

def get_project_root() -> Path:
    """Determine the project root directory."""
    # Assume tests are in code/tests, root is code/
    return Path(__file__).resolve().parent.parent.parent

def load_association_results() -> pd.DataFrame:
    """
    Load the association results file.
    
    Raises:
        FileNotFoundError: If the file does not exist.
        ValueError: If the file cannot be parsed as TSV.
    """
    root = get_project_root()
    file_path = root / EXPECTED_OUTPUT_PATH
    
    if not file_path.exists():
        raise FileNotFoundError(
            f"Association results file not found at: {file_path}. "
            "Ensure T021 (correlation_maaslin2.py) has been executed successfully."
        )
    
    try:
        # MaAsLin2 typically outputs TSV
        return pd.read_csv(file_path, sep='\t')
    except Exception as e:
        raise ValueError(f"Failed to parse {file_path} as TSV: {e}")

class TestMaaslin2OutputSchema:
    """
    Contract tests for MaAsLin2 output schema.
    
    These tests verify that the output file exists and contains the
    exact columns required by the specification.
    """

    def test_output_file_exists(self):
        """Verify that the association results file exists."""
        root = get_project_root()
        file_path = root / EXPECTED_OUTPUT_PATH
        assert file_path.exists(), (
            f"Output file {file_path} does not exist. "
            "Run the analysis pipeline (T021) to generate this file."
        )

    def test_required_columns_present(self):
        """Verify that all required columns are present in the output."""
        df = load_association_results()
        actual_columns = set(df.columns)
        required_columns = set(EXPECTED_COLUMNS)
        
        missing_columns = required_columns - actual_columns
        extra_columns = actual_columns - required_columns
        
        assert not missing_columns, (
            f"Missing required columns in {EXPECTED_OUTPUT_PATH}: {missing_columns}. "
            f"Expected columns: {required_columns}, Found: {actual_columns}"
        )
        
        # Log extra columns for debugging but do not fail (schema allows extra)
        if extra_columns:
            pytest.warns(f"Extra columns found in {EXPECTED_OUTPUT_PATH}: {extra_columns}")

    def test_column_order(self):
        """Verify that columns appear in the expected order (optional but recommended)."""
        df = load_association_results()
        actual_columns = list(df.columns)
        
        # Check if the required columns appear in the correct relative order
        # We filter to only the expected columns to check ordering
        filtered_columns = [col for col in actual_columns if col in EXPECTED_COLUMNS]
        
        assert filtered_columns == EXPECTED_COLUMNS, (
            f"Columns are not in the expected order. "
            f"Expected: {EXPECTED_COLUMNS}, Found: {filtered_columns}"
        )

    def test_no_null_values_in_required_columns(self):
        """Verify that required numeric columns do not contain null values."""
        df = load_association_results()
        
        numeric_cols = [
            "maaslin2_beta", "maaslin2_se", "maaslin2_p_value", "maaslin2_q_value",
            "spearman_rho", "spearman_se", "spearman_p_value"
        ]
        
        for col in numeric_cols:
            if col in df.columns:
                assert not df[col].isnull().any(), (
                    f"Column '{col}' contains null values. "
                    "All association results must have computed values."
                )

    def test_taxon_column_is_non_empty(self):
        """Verify that the taxon column is not empty."""
        df = load_association_results()
        assert "taxon" in df.columns, "Taxon column is missing."
        assert df["taxon"].notnull().all(), "Taxon column contains null values."
        assert len(df["taxon"].unique()) > 0, "Taxon column is empty."

    def test_p_value_range(self):
        """Verify that p-values and q-values are within [0, 1]."""
        df = load_association_results()
        
        for col in ["maaslin2_p_value", "maaslin2_q_value", "spearman_p_value"]:
            if col in df.columns:
                assert (df[col] >= 0).all() and (df[col] <= 1).all(), (
                    f"Column '{col}' contains values outside the range [0, 1]."
                )

    def test_spearman_rho_range(self):
        """Verify that Spearman correlation coefficients are within [-1, 1]."""
        df = load_association_results()
        
        if "spearman_rho" in df.columns:
            assert (df["spearman_rho"] >= -1).all() and (df["spearman_rho"] <= 1).all(), (
                "Spearman rho values must be within [-1, 1]."
            )

    def test_se_positive(self):
        """Verify that Standard Error values are non-negative."""
        df = load_association_results()
        
        for col in ["maaslin2_se", "spearman_se"]:
            if col in df.columns:
                assert (df[col] >= 0).all(), (
                    f"Standard Error column '{col}' contains negative values."
                )

    def test_file_is_tsv(self):
        """Verify the file format is TSV (tab-separated)."""
        root = get_project_root()
        file_path = root / EXPECTED_OUTPUT_PATH
        
        with open(file_path, 'r') as f:
            first_line = f.readline()
            # Check for tab character
            assert '\t' in first_line, (
                f"File {file_path} does not appear to be tab-separated. "
                "Expected TSV format."
            )