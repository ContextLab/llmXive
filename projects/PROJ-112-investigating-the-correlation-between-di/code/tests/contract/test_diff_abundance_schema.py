"""
Contract tests for differential abundance analysis output schema.

This module validates that the output files generated by the differential
abundance analysis tasks (T028a2, T028a3, T028b2, T028b3) adhere to the
strict schema requirements defined in the project specification.

Expected Schema for ANCOM-II/DESeq2 outputs:
- taxon: string, taxon identifier
- method: string, "ANCOM-II" or "DESeq2"
- q_value: float, FDR-adjusted p-value (0.0 to 1.0)
- effect_size: float, log2 fold change or beta coefficient
- direction: string, "positive" or "negative"

Expected Schema for Replication Status (T029 output):
- taxon: string
- method: string
- agp_q_value: float
- ukbb_q_value: float
- agp_effect_size: float
- ukbb_effect_size: float
- replication_status: string ('replicated', 'non-replicable', 'cohort-specific')
- diff_abundance_replicated: boolean (for ANCOM/DESeq2 results)
"""

import pytest
import pandas as pd
import os
from pathlib import Path
from typing import List, Dict, Any


# Define expected schemas based on T028/T029 specifications
EXPECTED_DIFF_ABUNDANCE_COLUMNS = {
    "taxon", "method", "q_value", "effect_size", "direction"
}

EXPECTED_REPLICATION_STATUS_COLUMNS = {
    "taxon", "method", "agp_q_value", "ukbb_q_value",
    "agp_effect_size", "ukbb_effect_size", "replication_status",
    "diff_abundance_replicated"
}

VALID_METHODS = {"ANCOM-II", "DESeq2"}
VALID_DIRECTIONS = {"positive", "negative"}
VALID_REPLICATION_STATUSES = {"replicated", "non-replicable", "cohort-specific"}


def _load_tsv_or_raise(file_path: Path) -> pd.DataFrame:
    """
    Helper to load a TSV file or raise a clear error if missing/corrupt.
    """
    if not file_path.exists():
        raise FileNotFoundError(f"Required artifact not found: {file_path}")

    try:
        df = pd.read_csv(file_path, sep='\t')
        return df
    except Exception as e:
        raise RuntimeError(f"Failed to parse TSV {file_path}: {e}")


def _validate_columns(df: pd.DataFrame, required_columns: set, file_name: str) -> None:
    """
    Validates that the DataFrame contains all required columns.
    Raises AssertionError if schema is violated.
    """
    actual_columns = set(df.columns)
    missing = required_columns - actual_columns
    extra = actual_columns - required_columns

    if missing:
        raise AssertionError(
            f"Schema violation in {file_name}: Missing required columns: {missing}. "
            f"Found columns: {actual_columns}"
        )

    # Optional: warn about extra columns, but strictly enforce required ones
    if extra:
        # For contract tests, we usually enforce exact schema or at least required subset.
        # Here we enforce exact match for critical analysis outputs to prevent drift.
        raise AssertionError(
            f"Schema violation in {file_name}: Unexpected columns found: {extra}. "
            f"Expected exactly: {required_columns}"
        )


def _validate_data_types_and_ranges(df: pd.DataFrame, file_name: str) -> None:
    """
    Validates data types and logical ranges (e.g., q_value between 0 and 1).
    """
    # Check q_value range
    if 'q_value' in df.columns:
        if not df['q_value'].between(0, 1).all():
            raise AssertionError(
                f"Invalid q_value range in {file_name}. "
                f"Values must be between 0 and 1. Found: {df['q_value'].describe()}"
            )

    if 'agp_q_value' in df.columns:
        if not df['agp_q_value'].between(0, 1).all():
            raise AssertionError(
                f"Invalid agp_q_value range in {file_name}."
            )

    if 'ukbb_q_value' in df.columns:
        if not df['ukbb_q_value'].between(0, 1).all():
            raise AssertionError(
                f"Invalid ukbb_q_value range in {file_name}."
            )

    # Check direction validity
    if 'direction' in df.columns:
        invalid_dirs = set(df['direction'].unique()) - VALID_DIRECTIONS
        if invalid_dirs:
            raise AssertionError(
                f"Invalid direction values in {file_name}: {invalid_dirs}. "
                f"Allowed: {VALID_DIRECTIONS}"
            )

    # Check replication status validity
    if 'replication_status' in df.columns:
        invalid_statuses = set(df['replication_status'].unique()) - VALID_REPLICATION_STATUSES
        if invalid_statuses:
            raise AssertionError(
                f"Invalid replication_status values in {file_name}: {invalid_statuses}. "
                f"Allowed: {VALID_REPLICATION_STATUSES}"
            )

    # Check method validity
    if 'method' in df.columns:
        invalid_methods = set(df['method'].unique()) - VALID_METHODS
        if invalid_methods:
            raise AssertionError(
                f"Invalid method values in {file_name}: {invalid_methods}. "
                f"Allowed: {VALID_METHODS}"
            )

    # Check boolean column for replication
    if 'diff_abundance_replicated' in df.columns:
        if not df['diff_abundance_replicated'].isin([True, False, 0, 1]).all():
            raise AssertionError(
                f"diff_abundance_replicated column in {file_name} must be boolean-like."
            )


class TestDiffAbundanceSchema:
    """
    Contract tests for differential abundance output files.
    These tests ensure that the pipeline outputs strictly adhere to the
    defined schema before downstream tasks (like T029) attempt to consume them.
    """

    def test_diff_abundance_schema(self, results_dir: Path) -> None:
        """
        Validates the schema of a generic differential abundance output file.
        This test is parameterized to run against expected output paths.
        """
        # Simulate checking a specific output file structure
        # In a real CI, these would be passed as fixtures or env vars.
        # Here we verify the logic against a hypothetical file if it existed,
        # or check that the schema definition is sound.

        # Since we are testing the *schema definition* logic here, we create
        # a mock valid dataframe to ensure the validator works.
        mock_data = {
            "taxon": ["Bacteroides", "Firmicutes"],
            "method": ["ANCOM-II", "DESeq2"],
            "q_value": [0.01, 0.05],
            "effect_size": [1.2, -0.5],
            "direction": ["positive", "negative"]
        }
        mock_df = pd.DataFrame(mock_data)

        try:
            _validate_columns(mock_df, EXPECTED_DIFF_ABUNDANCE_COLUMNS, "mock_diff_abundance.tsv")
            _validate_data_types_and_ranges(mock_df, "mock_diff_abundance.tsv")
        except AssertionError as e:
            pytest.fail(f"Schema validation failed on valid mock data: {e}")


    def test_diff_abundance_file_exists(self, results_dir: Path) -> None:
        """
        Contract test to verify that expected differential abundance files
        are generated in the results directory.
        """
        # These are the expected files from T028a2, T028a3, T028b2, T028b3
        expected_files = [
            results_dir / "diff_abundance_agp_ancom.tsv",
            results_dir / "diff_abundance_agp_deseq2.tsv",
            results_dir / "diff_abundance_ukbb_ancom.tsv",
            results_dir / "diff_abundance_ukbb_deseq2.tsv"
        ]

        # Note: In a real run, these files might not exist yet if the pipeline
        # hasn't finished. This test asserts that if they are present, they
        # must be non-empty and valid. If the test runner is in "check" mode,
        # we might just assert existence.
        # For this contract test, we assert that the *pattern* of files is correct.
        # If the pipeline is expected to have run, we check existence.
        
        # We will check existence but allow the test to pass if the pipeline
        # hasn't run yet, by marking it as a "check" that fails only if file exists but is empty.
        # However, standard contract tests usually assume the artifact is produced.
        # Let's assume the pipeline has run for the sake of the contract.
        
        for file_path in expected_files:
            # If the file exists, it must be non-empty and valid
            if file_path.exists():
                assert file_path.stat().st_size > 0, f"File exists but is empty: {file_path}"
                # Run schema validation
                df = _load_tsv_or_raise(file_path)
                _validate_columns(df, EXPECTED_DIFF_ABUNDANCE_COLUMNS, file_path.name)
                _validate_data_types_and_ranges(df, file_path.name)
            else:
                # If the file doesn't exist, this test might be skipped or failed depending on context.
                # For a strict contract test, we fail if the file is missing.
                # But since this is a unit/contract test run in isolation, we might just warn.
                # Given the task is to "Implement the contract test", we assert the file MUST exist.
                pytest.fail(f"Expected differential abundance file not found: {file_path}")


    def test_diff_abundance_non_empty(self, results_dir: Path) -> None:
        """
        Ensures that if differential abundance files exist, they contain data rows.
        """
        # Re-use the logic from test_diff_abundance_file_exists but focus on row count
        expected_files = [
            results_dir / "diff_abundance_agp_ancom.tsv",
            results_dir / "diff_abundance_agp_deseq2.tsv",
            results_dir / "diff_abundance_ukbb_ancom.tsv",
            results_dir / "diff_abundance_ukbb_deseq2.tsv"
        ]

        for file_path in expected_files:
            if file_path.exists():
                df = _load_tsv_or_raise(file_path)
                assert len(df) > 0, f"File {file_path} exists but contains no data rows."
            else:
                pytest.fail(f"Expected file not found: {file_path}")


