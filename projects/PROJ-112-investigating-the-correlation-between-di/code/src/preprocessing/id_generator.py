"""
ID Generator Module for llmXive Pipeline.

Generates unique, deterministic SHA256 sample IDs by hashing
a combination of the cohort identifier and the original sample ID.
"""
import hashlib
import argparse
import logging
import sys
from pathlib import Path
from typing import List, Optional, Tuple, Dict, Any

import pandas as pd

# Import logger from project utils
from src.utils.logger import get_logger

def generate_sample_id(cohort: str, original_id: str) -> str:
    """
    Generate a unique SHA256 sample ID.

    The ID is generated by hashing the concatenation of the cohort
    and the original ID (separated by an underscore).

    Args:
        cohort: The cohort identifier (e.g., "AGP", "UKBB").
        original_id: The original sample ID from the source dataset.

    Returns:
        A 64-character hexadecimal SHA256 hash string.
    """
    if not cohort or not original_id:
        raise ValueError("Both 'cohort' and 'original_id' must be non-empty strings.")
    
    # Create a deterministic string for hashing
    raw_string = f"{cohort}_{original_id}"
    
    # Generate SHA256 hash
    hash_object = hashlib.sha256(raw_string.encode('utf-8'))
    return hash_object.hexdigest()

def generate_sample_ids_dataframe(
    df: pd.DataFrame, 
    cohort_col: str = 'cohort_id', 
    id_col: str = 'original_id', 
    output_col: str = 'sample_id'
) -> pd.DataFrame:
    """
    Generate sample IDs for an entire DataFrame.

    Applies `generate_sample_id` row-wise to create a new column
    containing the unique SHA256 ID.

    Args:
        df: The input DataFrame containing cohort and original ID columns.
        cohort_col: Name of the column containing the cohort identifier.
        id_col: Name of the column containing the original sample ID.
        output_col: Name of the new column to create for the generated ID.

    Returns:
        A copy of the DataFrame with the new 'sample_id' column added.
        
    Raises:
        ValueError: If specified columns are missing from the DataFrame.
    """
    if cohort_col not in df.columns:
        raise ValueError(f"Column '{cohort_col}' not found in DataFrame.")
    if id_col not in df.columns:
        raise ValueError(f"Column '{id_col}' not found in DataFrame.")

    new_df = df.copy()
    
    # Apply generation logic
    new_df[output_col] = new_df.apply(
        lambda row: generate_sample_id(str(row[cohort_col]), str(row[id_col])), 
        axis=1
    )
    
    return new_df

def build_arg_parser() -> argparse.ArgumentParser:
    """
    Build the argument parser for the command-line interface.
    """
    parser = argparse.ArgumentParser(
        description="Generate SHA256 sample IDs from cohort and original ID columns."
    )
    parser.add_argument(
        "--input", "-i",
        required=True,
        type=str,
        help="Path to the input TSV/CSV file containing sample data."
    )
    parser.add_argument(
        "--output", "-o",
        required=True,
        type=str,
        help="Path to the output TSV file with generated sample IDs."
    )
    parser.add_argument(
        "--cohort-col",
        default="cohort_id",
        type=str,
        help="Name of the column containing the cohort identifier (default: cohort_id)."
    )
    parser.add_argument(
        "--id-col",
        default="original_id",
        type=str,
        help="Name of the column containing the original sample ID (default: original_id)."
    )
    parser.add_argument(
        "--output-col",
        default="sample_id",
        type=str,
        help="Name of the new column for the generated ID (default: sample_id)."
    )
    parser.add_argument(
        "--delimiter",
        default="\t",
        type=str,
        help="Delimiter for input/output files (default: tab)."
    )
    return parser

def main() -> int:
    """
    Main entry point for the ID generation script.

    Reads a TSV/CSV file, generates SHA256 IDs, and writes the result.
    Returns 0 on success, 1 on failure.
    """
    parser = build_arg_parser()
    args = parser.parse_args()

    # Setup logging
    logger = get_logger("id_generator")
    logger.info(f"Starting ID generation for file: {args.input}")

    try:
        # Determine file format based on extension if delimiter not explicitly set,
        # but we rely on the explicit delimiter argument for safety.
        input_path = Path(args.input)
        output_path = Path(args.output)

        if not input_path.exists():
            logger.error(f"Input file not found: {args.input}")
            return 1

        # Load data
        logger.info(f"Loading data from {args.input}...")
        try:
            df = pd.read_csv(input_path, delimiter=args.delimiter)
        except Exception as e:
            logger.error(f"Failed to read input file: {e}")
            return 1

        logger.info(f"Loaded {len(df)} rows. Columns: {list(df.columns)}")

        # Generate IDs
        logger.info(f"Generating IDs using columns '{args.cohort_col}' and '{args.id_col}'...")
        df_processed = generate_sample_ids_dataframe(
            df, 
            cohort_col=args.cohort_col, 
            id_col=args.id_col, 
            output_col=args.output_col
        )

        # Ensure output directory exists
        output_path.parent.mkdir(parents=True, exist_ok=True)

        # Write output
        logger.info(f"Writing output to {args.output}...")
        df_processed.to_csv(output_path, sep=args.delimiter, index=False)

        logger.info(f"Successfully generated {len(df_processed)} sample IDs.")
        logger.info(f"Output saved to: {output_path}")
        
        return 0

    except ValueError as e:
        logger.error(f"Validation error: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during ID generation: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
