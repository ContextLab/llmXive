def generate_sample_id(cohort: str, original_id: str, salt: str = "llmXive_v1") -> str:
    """
    Generate a deterministic SHA256 sample ID.

    The ID is generated by hashing the concatenation of the cohort,
    original ID, and a project-specific salt.

    Args:
        cohort: The cohort identifier (e.g., "AGP", "UKBB").
        original_id: The original sample identifier from the source dataset.
        salt: A salt string to prevent rainbow table attacks.

    Returns:
        A hexadecimal SHA256 hash string.
    """
    # Normalize inputs to ensure consistency
    cohort_str = str(cohort).strip().upper()
    original_str = str(original_id).strip()
    salt_str = str(salt).strip()

    # Construct the input string
    input_string = f"{cohort_str}|{original_str}|{salt_str}"

    # Generate SHA256 hash
    hash_object = hashlib.sha256(input_string.encode('utf-8'))
    return hash_object.hexdigest()

def generate_sample_ids_dataframe(df: pd.DataFrame, 
                                  cohort_col: str, 
                                  id_col: str, 
                                  new_col_name: str = "sample_id",
                                  salt: str = "llmXive_v1") -> pd.DataFrame:
    """
    Generate sample IDs for an entire DataFrame.

    Args:
        df: The input pandas DataFrame containing cohort and ID columns.
        cohort_col: The name of the column containing cohort identifiers.
        id_col: The name of the column containing original sample IDs.
        new_col_name: The name for the new generated ID column.
        salt: The salt string for hashing.

    Returns:
        The DataFrame with the new sample_id column appended.
    """
    import pandas as pd

    if cohort_col not in df.columns:
        raise ValueError(f"Column '{cohort_col}' not found in DataFrame.")
    if id_col not in df.columns:
        raise ValueError(f"Column '{id_col}' not found in DataFrame.")

    # Apply the generation function row-wise
    df[new_col_name] = df.apply(
        lambda row: generate_sample_id(row[cohort_col], row[id_col], salt), 
        axis=1
    )
    
    return df

def run_id_generation(input_path: Path, 
                      output_path: Path, 
                      cohort_col: str = "cohort_id",
                      id_col: str = "original_id",
                      salt: str = "llmXive_v1") -> None:
    """
    Main entry point for generating IDs from a CSV/TSV file.

    Args:
        input_path: Path to the input data file.
        output_path: Path to write the output file with new IDs.
        cohort_col: Name of the cohort column.
        id_col: Name of the original ID column.
        salt: Salt for hashing.
    """
    import pandas as pd

    logger = get_logger(__name__)
    
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")

    logger.info(f"Loading data from {input_path}")
    # Infer delimiter based on extension, default to csv
    if input_path.suffix.lower() == '.tsv':
        df = pd.read_csv(input_path, sep='\t')
    else:
        df = pd.read_csv(input_path)

    logger.info(f"Generating IDs for {len(df)} samples")
    df_with_ids = generate_sample_ids_dataframe(
        df, 
        cohort_col=cohort_col, 
        id_col=id_col, 
        new_col_name="sample_id",
        salt=salt
    )

    logger.info(f"Writing output to {output_path}")
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Write based on extension
    if output_path.suffix.lower() == '.tsv':
        df_with_ids.to_csv(output_path, sep='\t', index=False)
    else:
        df_with_ids.to_csv(output_path, index=False)
    
    logger.info("ID generation complete.")

def build_arg_parser() -> argparse.ArgumentParser:
    """Build the argument parser for the CLI."""
    parser = argparse.ArgumentParser(
        description="Generate SHA256 sample IDs from cohort and original ID."
    )
    parser.add_argument(
        "--input", 
        type=Path, 
        required=True, 
        help="Path to the input CSV/TSV file."
    )
    parser.add_argument(
        "--output", 
        type=Path, 
        required=True, 
        help="Path to the output CSV/TSV file."
    )
    parser.add_argument(
        "--cohort-col", 
        type=str, 
        default="cohort_id", 
        help="Column name containing cohort identifiers."
    )
    parser.add_argument(
        "--id-col", 
        type=str, 
        default="original_id", 
        help="Column name containing original sample IDs."
    )
    parser.add_argument(
        "--salt", 
        type=str, 
        default="llmXive_v1", 
        help="Salt string for hashing."
    )
    return parser

def main() -> None:
    """Main function to run the ID generator from CLI."""
    parser = build_arg_parser()
    args = parser.parse_args()
    
    # Setup logging
    logger = get_logger(__name__)
    
    try:
        run_id_generation(
            input_path=args.input,
            output_path=args.output,
            cohort_col=args.cohort_col,
            id_col=args.id_col,
            salt=args.salt
        )
    except Exception as e:
        logger.error(f"ID generation failed: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
