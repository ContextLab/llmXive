"""
FDR Correction Report Generator (Task T022).

Reads the association results generated by T021 (correlation_maaslin2.py),
verifies that the Benjamini-Hochberg (BH) q-values are correctly calculated
and monotonically non-decreasing with respect to sorted p-values, and
writes a validation log.

Output: data/processed/results/fdr_validation_log.txt
"""
import argparse
import logging
import sys
import os
from pathlib import Path
from typing import List, Optional, Tuple, Dict, Any
import pandas as pd
import numpy as np

from src.utils.logger import get_logger


def get_project_root() -> Path:
    """Return the project root directory (parent of 'code')."""
    # Assumes this script is at code/src/analysis/fdr_validator.py
    return Path(__file__).resolve().parent.parent.parent.parent


def calculate_benjamini_hochberg(p_values: pd.Series) -> pd.Series:
    """
    Calculate Benjamini-Hochberg adjusted q-values.

    Parameters
    ----------
    p_values : pd.Series
        Series of raw p-values.

    Returns
    -------
    pd.Series
        Series of BH-adjusted q-values, same index as input.
    """
    n = len(p_values)
    if n == 0:
        return pd.Series([], dtype=float)

    # Sort p-values
    sorted_indices = p_values.argsort()
    sorted_p = p_values.iloc[sorted_indices]

    # Calculate BH q-values
    ranks = np.arange(1, n + 1)
    q_values = (sorted_p * n) / ranks

    # Ensure monotonicity (q-values should be non-decreasing)
    # Iterate backwards to enforce q_i <= q_{i+1}
    for i in range(n - 2, -1, -1):
        if q_values[i] > q_values[i + 1]:
            q_values[i] = q_values[i + 1]

    # Clip to [0, 1]
    q_values = np.clip(q_values, 0.0, 1.0)

    # Restore original order
    result = pd.Series(0.0, index=p_values.index, dtype=float)
    result.iloc[sorted_indices] = q_values

    return result


def validate_q_values(
    df: pd.DataFrame,
    p_col: str = "maaslin2_p_value",
    q_col: str = "maaslin2_q_value",
    tolerance: float = 1e-9
) -> Tuple[bool, List[str]]:
    """
    Validate that q-values in the dataframe are correctly calculated from p-values.

    Checks:
    1. q-values are monotonically non-decreasing when sorted by p-value.
    2. q-values are in [0, 1].
    3. q-values match the BH calculation (within tolerance).

    Returns
    -------
    (is_valid, messages)
    """
    messages = []
    is_valid = True

    if p_col not in df.columns:
        messages.append(f"ERROR: Column '{p_col}' not found in input dataframe.")
        return False, messages

    if q_col not in df.columns:
        messages.append(f"ERROR: Column '{q_col}' not found in input dataframe.")
        return False, messages

    # Check for NaNs in p-values
    if df[p_col].isna().any():
        messages.append(f"WARNING: Found {df[p_col].isna().sum()} NaN p-values. Skipping validation for those rows.")
        valid_mask = df[p_col].notna()
        df_valid = df[valid_mask]
    else:
        df_valid = df

    if len(df_valid) == 0:
        messages.append("No valid p-values to validate.")
        return True, messages

    # Check range [0, 1]
    if (df_valid[q_col] < 0).any() or (df_valid[q_col] > 1).any():
        messages.append("ERROR: Found q-values outside the range [0, 1].")
        is_valid = False

    # Check monotonicity and correctness
    sorted_df = df_valid.sort_values(by=p_col)
    sorted_p = sorted_df[p_col]
    sorted_q = sorted_df[q_col]

    # Calculate expected q-values
    calculated_q = calculate_benjamini_hochberg(sorted_p)

    # Check monotonicity
    if (np.diff(sorted_q) < -tolerance).any():
        messages.append("ERROR: q-values are not monotonically non-decreasing when sorted by p-value.")
        is_valid = False

    # Check correctness
    diff = np.abs(sorted_q.values - calculated_q.values)
    if (diff > tolerance).any():
        max_diff = diff.max()
        messages.append(f"ERROR: Calculated q-values differ from stored q-values by max {max_diff:.2e}.")
        is_valid = False
    else:
        messages.append("OK: q-values match Benjamini-Hochberg calculation within tolerance.")

    if is_valid:
        messages.append("VALIDATION PASSED: FDR correction appears correct.")
    else:
        messages.append("VALIDATION FAILED: FDR correction issues detected.")

    return is_valid, messages


def run_fdr_validation(
    input_path: Path,
    output_path: Path,
    p_col: str = "maaslin2_p_value",
    q_col: str = "maaslin2_q_value",
    log_level: int = logging.INFO
) -> bool:
    """
    Main routine to validate FDR correction and write a log.

    Parameters
    ----------
    input_path : Path
        Path to association_results.tsv.
    output_path : Path
        Path to write fdr_validation_log.txt.
    p_col : str
        Column name for raw p-values.
    q_col : str
        Column name for adjusted q-values.
    log_level : int
        Logging level.

    Returns
    -------
    bool
        True if validation passed, False otherwise.
    """
    logger = get_logger("fdr_validator", level=log_level)
    logger.info(f"Starting FDR validation for {input_path}")

    if not input_path.exists():
        logger.error(f"Input file not found: {input_path}")
        return False

    try:
        df = pd.read_csv(input_path, sep="\t")
    except Exception as e:
        logger.error(f"Failed to read input file: {e}")
        return False

    logger.info(f"Loaded {len(df)} rows from {input_path}")

    is_valid, messages = validate_q_values(df, p_col, q_col)

    # Write log
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("FDR Correction Validation Report\n")
        f.write("=" * 50 + "\n")
        f.write(f"Input file: {input_path}\n")
        f.write(f"Total rows: {len(df)}\n")
        f.write(f"P-value column: {p_col}\n")
        f.write(f"Q-value column: {q_col}\n")
        f.write("=" * 50 + "\n\n")
        for msg in messages:
            f.write(msg + "\n")
        f.write("\n" + "=" * 50 + "\n")
        f.write(f"Result: {'PASSED' if is_valid else 'FAILED'}\n")

    logger.info(f"Validation log written to {output_path}")
    return is_valid


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Validate FDR correction in association results and generate a report."
    )
    parser.add_argument(
        "--input",
        type=str,
        default="data/processed/results/association_results.tsv",
        help="Path to association results TSV (default: data/processed/results/association_results.tsv)"
    )
    parser.add_argument(
        "--output",
        type=str,
        default="data/processed/results/fdr_validation_log.txt",
        help="Path to output validation log (default: data/processed/results/fdr_validation_log.txt)"
    )
    parser.add_argument(
        "--p-col",
        type=str,
        default="maaslin2_p_value",
        help="Column name for raw p-values (default: maaslin2_p_value)"
    )
    parser.add_argument(
        "--q-col",
        type=str,
        default="maaslin2_q_value",
        help="Column name for adjusted q-values (default: maaslin2_q_value)"
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Enable debug logging"
    )
    return parser


def main() -> int:
    parser = build_arg_parser()
    args = parser.parse_args()

    log_level = logging.DEBUG if args.verbose else logging.INFO

    input_path = Path(args.input)
    output_path = Path(args.output)

    success = run_fdr_validation(
        input_path=input_path,
        output_path=output_path,
        p_col=args.p_col,
        q_col=args.q_col,
        log_level=log_level
    )

    return 0 if success else 1


if __name__ == "__main__":
    sys.exit(main())
