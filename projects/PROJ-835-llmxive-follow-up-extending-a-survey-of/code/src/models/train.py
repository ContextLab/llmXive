logger = get_module_logger(__name__)

def load_embeddings(embeddings_path: str) -> Tuple[np.ndarray, np.ndarray]:
    """
    Load embeddings and labels from the parquet file generated by T014.
    
    Args:
        embeddings_path: Path to data/embeddings.parquet
        
    Returns:
        Tuple of (embeddings_array, labels_array)
    """
    ensure_dir(embeddings_path)
    if not os.path.exists(embeddings_path):
        raise FileNotFoundError(f"Embeddings file not found: {embeddings_path}")
    
    df = pd.read_parquet(embeddings_path)
    
    # Expect columns: 'embedding' (list/array), 'label' (int)
    if 'embedding' not in df.columns or 'label' not in df.columns:
        raise ValueError("Embeddings parquet must contain 'embedding' and 'label' columns")
    
    # Convert list embeddings to numpy array
    embeddings = np.vstack(df['embedding'].values)
    labels = df['label'].values.astype(int)
    
    logger.info(f"Loaded {len(embeddings)} embeddings with shape {embeddings.shape}")
    return embeddings, labels

def perform_stratified_split(
    X: np.ndarray, 
    y: np.ndarray, 
    test_size: float = 0.2, 
    random_state: int = 42
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """
    Perform stratified train/test split.
    
    Args:
        X: Feature matrix (embeddings)
        y: Labels
        test_size: Proportion of data to hold out
        random_state: Random seed for reproducibility
        
    Returns:
        Tuple of (X_train, X_test, y_train, y_test)
    """
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, stratify=y, random_state=random_state
    )
    logger.info(f"Split data: Train={len(X_train)}, Test={len(X_test)}")
    return X_train, X_test, y_train, y_test

def train_logistic_regression(
    X_train: np.ndarray, 
    y_train: np.ndarray, 
    random_state: int = 42
) -> LogisticRegression:
    """
    Train a Logistic Regression classifier on CPU.
    
    Args:
        X_train: Training features
        y_train: Training labels
        random_state: Random seed
        
    Returns:
        Trained LogisticRegression model
    """
    model = LogisticRegression(
        random_state=random_state,
        max_iter=1000,
        solver='lbfgs',
        n_jobs=1  # Force single-threaded CPU for reproducibility
    )
    model.fit(X_train, y_train)
    logger.info(f"Model trained. Coefficients shape: {model.coef_.shape}")
    return model

def evaluate_model(
    model: LogisticRegression, 
    X_test: np.ndarray, 
    y_test: np.ndarray
) -> Dict[str, Any]:
    """
    Evaluate the model on the test set.
    
    Args:
        model: Trained classifier
        X_test: Test features
        y_test: Test labels
        
    Returns:
        Dictionary of evaluation metrics
    """
    y_pred = model.predict(X_test)
    y_proba = model.predict_proba(X_test)
    
    report = classification_report(y_test, y_pred, output_dict=True)
    accuracy = accuracy_score(y_test, y_pred)
    
    metrics = {
        "accuracy": accuracy,
        "classification_report": report,
        "predictions": y_pred.tolist(),
        "probabilities": y_proba.tolist()
    }
    
    logger.info(f"Test Accuracy: {accuracy:.4f}")
    return metrics

def calculate_benign_statistics_and_anomaly_scores(
    X_train: np.ndarray, 
    y_train: np.ndarray, 
    X_test: np.ndarray, 
    y_test: np.ndarray,
    benign_label: int = 0
) -> Tuple[Dict[str, np.ndarray], np.ndarray, np.ndarray]:
    """
    Calculate benign centroid/covariance from TRAIN set only,
    then compute Mahalanobis distance for ALL samples (train + test).
    
    Args:
        X_train: Training embeddings
        y_train: Training labels
        X_test: Test embeddings
        y_test: Test labels
        benign_label: Label value considered "benign" (default 0)
        
    Returns:
        Tuple of (benign_stats_dict, all_mahalanobis_distances, all_labels)
    """
    # 1. Extract benign samples from TRAINING set ONLY
    benign_mask = (y_train == benign_label)
    X_train_benign = X_train[benign_mask]
    
    if len(X_train_benign) == 0:
        raise ValueError("No benign samples found in training set to compute statistics.")
    
    logger.info(f"Computing statistics from {len(X_train_benign)} benign training samples.")
    
    # 2. Compute centroid and covariance using LedoitWolf
    benign_stats = compute_benign_statistics(X_train_benign)
    mu_benign = benign_stats['centroid']
    cov_inv = benign_stats['covariance_inv']
    
    # 3. Combine train and test for unified scoring
    X_all = np.vstack([X_train, X_test])
    y_all = np.concatenate([y_train, y_test])
    
    # 4. Calculate Mahalanobis distance for ALL samples
    mahal_distances = calculate_mahalanobis_distance(X_all, mu_benign, cov_inv)
    
    logger.info(f"Computed anomaly scores for {len(X_all)} total samples.")
    return benign_stats, mahal_distances, y_all

def save_model_artifact(
    model: LogisticRegression, 
    benign_stats: Dict[str, np.ndarray], 
    output_dir: str,
    artifact_name: str = "model_artifact"
) -> str:
    """
    Save the trained model and benign statistics to disk.
    
    Args:
        model: Trained LogisticRegression model
        benign_stats: Dictionary containing centroid and covariance_inv
        output_dir: Directory to save artifacts
        artifact_name: Base name for the artifact files
        
    Returns:
        Path to the saved model file
    """
    ensure_dir(output_dir)
    model_path = os.path.join(output_dir, f"{artifact_name}.pkl")
    stats_path = os.path.join(output_dir, f"{artifact_name}_stats.json")
    
    joblib.dump(model, model_path)
    
    # Convert numpy types to native Python types for JSON serialization
    stats_serializable = {
        "centroid": benign_stats['centroid'].tolist(),
        "covariance_inv": benign_stats['covariance_inv'].tolist()
    }
    
    with open(stats_path, 'w') as f:
        json.dump(stats_serializable, f, indent=2)
    
    logger.info(f"Saved model to {model_path}")
    logger.info(f"Saved statistics to {stats_path}")
    return model_path

def save_predictions(
    metrics: Dict[str, Any], 
    mahal_distances: np.ndarray, 
    labels: np.ndarray, 
    output_path: str
) -> None:
    """
    Save prediction probabilities and anomaly scores to CSV.
    
    Args:
        metrics: Dictionary from evaluate_model containing predictions and probabilities
        mahal_distances: Array of Mahalanobis distances for all samples
        labels: Array of true labels for all samples
        output_path: Path to save the predictions CSV
    """
    ensure_dir(output_path)
    
    # Reconstruct dataframe
    # metrics['probabilities'] is a list of [prob_class0, prob_class1]
    # metrics['predictions'] is the predicted class
    
    predictions = metrics['predictions']
    probabilities = metrics['probabilities']
    
    # Create DataFrame
    df = pd.DataFrame({
        'true_label': labels.tolist(),
        'predicted_label': predictions,
        'prob_benign': [p[0] for p in probabilities],
        'prob_jailbreak': [p[1] for p in probabilities],
        'anomaly_score': mahal_distances.tolist()
    })
    
    df.to_csv(output_path, index=False)
    logger.info(f"Saved predictions to {output_path}")

def main():
    """
    Main entry point for training and evaluation.
    Orchestrates loading, splitting, training, evaluating, and saving.
    """
    # Enforce CPU-only
    enforce_cpu_only()
    log_environment_config()
    
    parser = argparse.ArgumentParser(description="Train and evaluate jailbreak classifier")
    parser.add_argument("--embeddings_path", type=str, default="data/embeddings.parquet",
                        help="Path to embeddings parquet file")
    parser.add_argument("--output_dir", type=str, default="results",
                        help="Directory to save model and results")
    parser.add_argument("--test_size", type=float, default=0.2,
                        help="Proportion of data for testing")
    parser.add_argument("--seed", type=int, default=42,
                        help="Random seed")
    args = parser.parse_args()
    
    set_random_seed(args.seed)
    ensure_dir(args.output_dir)
    
    try:
        # 1. Load Data
        logger.info("Loading embeddings...")
        X, y = load_embeddings(args.embeddings_path)
        
        # 2. Split Data
        logger.info("Performing stratified split...")
        X_train, X_test, y_train, y_test = perform_stratified_split(
            X, y, test_size=args.test_size, random_state=args.seed
        )
        
        # 3. Train Model
        logger.info("Training Logistic Regression...")
        model = train_logistic_regression(X_train, y_train, random_state=args.seed)
        
        # 4. Evaluate Model
        logger.info("Evaluating model...")
        metrics = evaluate_model(model, X_test, y_test)
        
        # 5. Calculate Anomaly Scores (Benign stats from Train, Scores for All)
        logger.info("Calculating Mahalanobis anomaly scores...")
        benign_stats, all_mahal_distances, all_labels = calculate_benign_statistics_and_anomaly_scores(
            X_train, y_train, X_test, y_test
        )
        
        # 6. Save Model Artifacts
        logger.info("Saving model artifacts...")
        model_path = save_model_artifact(model, benign_stats, args.output_dir)
        
        # 7. Save Predictions CSV (T024 Requirement)
        predictions_path = os.path.join(args.output_dir, "predictions.csv")
        logger.info(f"Saving predictions to {predictions_path}...")
        save_predictions(metrics, all_mahal_distances, all_labels, predictions_path)
        
        logger.info("Training and evaluation pipeline completed successfully.")
        
    except Exception as e:
        logger.error(f"Pipeline failed: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()