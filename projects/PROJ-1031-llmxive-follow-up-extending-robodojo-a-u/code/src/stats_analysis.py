def load_oracle_results(filepath: str) -> Optional[pd.DataFrame]:
    """
    Load oracle execution results from the JSON file generated by T038.

    Args:
        filepath: Path to the oracle results JSON file.

    Returns:
        DataFrame containing oracle execution metrics, or None if file not found.
    """
    if not os.path.exists(filepath):
        logger.warning(f"Oracle results file not found: {filepath}. Skipping oracle analysis.")
        return None

    try:
        with open(filepath, 'r') as f:
            data = json.load(f)
        
        if isinstance(data, list):
            df = pd.DataFrame(data)
        else:
            df = pd.DataFrame([data])
        
        if df.empty:
            logger.warning("Oracle results file is empty.")
            return None
        
        logger.info(f"Loaded oracle results: {len(df)} rows")
        return df
    except Exception as e:
        logger.error(f"Error loading oracle results: {e}")
        return None


def calculate_success_rates(baseline_df: pd.DataFrame, symbolic_df: pd.DataFrame) -> Tuple[float, float]:
    """
    Calculate success rates for both baseline and symbolic approaches.

    Args:
        baseline_df: DataFrame with baseline results.
        symbolic_df: DataFrame with symbolic results.

    Returns:
        Tuple of (baseline_success_rate, symbolic_success_rate).
    """
    # Assuming 'success' column exists in both DataFrames (boolean or 0/1)
    baseline_success = baseline_df['success'].mean() if 'success' in baseline_df.columns else 0.0
    symbolic_success = symbolic_df['success'].mean() if 'success' in symbolic_df.columns else 0.0

    logger.info(f"Baseline success rate: {baseline_success:.4f}")
    logger.info(f"Symbolic success rate: {symbolic_success:.4f}")

    return baseline_success, symbolic_success


def perform_wilcoxon_test(baseline_df: pd.DataFrame, symbolic_df: pd.DataFrame) -> Tuple[float, float]:
    """
    Perform Wilcoxon signed-rank test to compare baseline and symbolic results.

    The null hypothesis is that the median difference between the two populations is zero.

    Args:
        baseline_df: DataFrame with baseline results (must have a 'success' or 'score' column).
        symbolic_df: DataFrame with symbolic results (must have a 'success' or 'score' column).

    Returns:
        Tuple of (statistic, p_value).
    """
    # Determine the metric column to use
    metric_col = 'success' if 'success' in baseline_df.columns else ('score' if 'score' in baseline_df.columns else None)
    
    if metric_col is None:
        raise ValueError("Neither 'success' nor 'score' column found in baseline DataFrame.")
    
    # Extract paired samples (assuming same task IDs or order)
    # If DataFrames are not paired by task ID, we assume they are ordered similarly
    baseline_vals = baseline_df[metric_col].values
    symbolic_vals = symbolic_df[metric_col].values

    if len(baseline_vals) != len(symbolic_vals):
        logger.warning(f"Baseline and symbolic samples have different lengths: {len(baseline_vals)} vs {len(symbolic_vals)}. Truncating to the shorter length.")
        min_len = min(len(baseline_vals), len(symbolic_vals))
        baseline_vals = baseline_vals[:min_len]
        symbolic_vals = symbolic_vals[:min_len]

    if len(baseline_vals) < 2:
        raise ValueError("Wilcoxon test requires at least 2 paired samples.")

    # Perform Wilcoxon signed-rank test
    statistic, p_value = stats.wilcoxon(baseline_vals, symbolic_vals)

    logger.info(f"Wilcoxon statistic: {statistic:.4f}, p-value: {p_value:.4f}")

    return statistic, p_value


def calculate_rank_biserial_correlation(baseline_vals: np.ndarray, symbolic_vals: np.ndarray) -> float:
    """
    Calculate the rank-biserial correlation effect size for the Wilcoxon test.

    The rank-biserial correlation is a measure of effect size for the Wilcoxon signed-rank test.
    It ranges from -1 to 1, where values closer to 1 or -1 indicate a stronger effect.

    Args:
        baseline_vals: Array of baseline values.
        symbolic_vals: Array of symbolic values.

    Returns:
        Rank-biserial correlation coefficient.
    """
    if len(baseline_vals) != len(symbolic_vals) or len(baseline_vals) < 2:
        raise ValueError("Rank-biserial correlation requires at least 2 paired samples of equal length.")

    # Calculate the rank-biserial correlation
    # Formula: r_rb = 1 - (2 * W) / (n * (n + 1))
    # where W is the sum of ranks of the smaller group (or the test statistic from Wilcoxon)
    # However, scipy's wilcoxon returns the statistic for the smaller sum of ranks
    # A more direct formula using the test statistic:
    # r_rb = (W - n*(n+1)/4) / (n*(n+1)/4)  [normalized]
    # But a common approximation is: r = Z / sqrt(n)
    
    # Let's use the Z-approximation for effect size
    # First, calculate the test statistic and its standard error
    diff = symbolic_vals - baseline_vals
    n = len(diff)
    
    # Sum of positive and negative ranks
    ranks = np.abs(diff).argsort() + 1
    pos_ranks = ranks[diff > 0].sum() if np.any(diff > 0) else 0
    neg_ranks = ranks[diff < 0].sum() if np.any(diff < 0) else 0
    
    W = min(pos_ranks, neg_ranks)
    
    # Rank-biserial correlation formula for Wilcoxon
    r_rb = 1 - (2 * W) / (n * (n + 1))
    
    logger.info(f"Rank-biserial correlation: {r_rb:.4f}")
    
    return r_rb


def calculate_compute_reduction(baseline_df: pd.DataFrame, symbolic_df: pd.DataFrame) -> float:
    """
    Calculate the percentage reduction in compute overhead.

    Args:
        baseline_df: DataFrame with baseline results (must have compute metrics).
        symbolic_df: DataFrame with symbolic results (must have compute metrics).

    Returns:
        Percentage reduction in compute overhead (positive if symbolic is faster/less resource-intensive).
    """
    # Identify compute metric columns
    time_col = 'wall_clock_s' if 'wall_clock_s' in baseline_df.columns else ('time_s' if 'time_s' in baseline_df.columns else None)
    
    if time_col is None:
        logger.warning("No time column found. Using success rate as a proxy for compute overhead.")
        # Fallback: use success rate difference as a proxy (not ideal, but prevents crash)
        baseline_rate = baseline_df['success'].mean() if 'success' in baseline_df.columns else 1.0
        symbolic_rate = symbolic_df['success'].mean() if 'success' in symbolic_df.columns else 1.0
        if baseline_rate == 0:
            return 0.0
        return ((symbolic_rate - baseline_rate) / baseline_rate) * 100

    baseline_time = baseline_df[time_col].mean()
    symbolic_time = symbolic_df[time_col].mean()

    if baseline_time == 0:
        logger.warning("Baseline time is zero. Cannot calculate reduction percentage.")
        return 0.0

    reduction = ((baseline_time - symbolic_time) / baseline_time) * 100
    logger.info(f"Compute overhead reduction: {reduction:.2f}%")

    return reduction


def calculate_catastrophic_failure_rate(symbolic_df: pd.DataFrame) -> float:
    """
    Calculate the catastrophic failure rate.

    Catastrophic failures are defined as "Hardware Error" or "Timeout".

    Args:
        symbolic_df: DataFrame with symbolic execution results (must have 'failure_mode' column).

    Returns:
        Catastrophic failure rate as a fraction (0.0 to 1.0).
    """
    if 'failure_mode' not in symbolic_df.columns:
        logger.warning("No 'failure_mode' column found. Assuming 0 catastrophic failures.")
        return 0.0

    catastrophic_modes = ["Hardware Error", "Timeout"]
    catastrophic_count = symbolic_df[symbolic_df['failure_mode'].isin(catastrophic_modes)].shape[0]
    total_count = symbolic_df.shape[0]

    if total_count == 0:
        return 0.0

    rate = catastrophic_count / total_count
    logger.info(f"Catastrophic failure rate: {rate:.4f} ({catastrophic_count}/{total_count})")

    return rate


def calculate_physics_fidelity_gap(oracle_df: Optional[pd.DataFrame], symbolic_df: pd.DataFrame) -> Optional[float]:
    """
    Calculate the Physics Fidelity Gap (Oracle success rate - Real-World success rate).

    Args:
        oracle_df: DataFrame with oracle results.
        symbolic_df: DataFrame with symbolic (real-world) results.

    Returns:
        Physics Fidelity Gap, or None if oracle data is unavailable.
    """
    if oracle_df is None:
        return None

    if 'success' not in oracle_df.columns or 'success' not in symbolic_df.columns:
        logger.warning("Missing 'success' column in oracle or symbolic data.")
        return None

    oracle_success = oracle_df['success'].mean()
    symbolic_success = symbolic_df['success'].mean()

    gap = oracle_success - symbolic_success
    logger.info(f"Physics Fidelity Gap: {gap:.4f} (Oracle: {oracle_success:.4f}, Symbolic: {symbolic_success:.4f})")

    return gap


