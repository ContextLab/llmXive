def load_baseline_results(filepath: str) -> pd.DataFrame:
    """
    Load baseline results from the parquet file generated by T000.

    Args:
        filepath: Path to the baseline results parquet file.

    Returns:
        DataFrame containing baseline execution metrics.

    Raises:
        FileNotFoundError: If the file does not exist.
        ValueError: If the file is empty or has invalid schema.
    """
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Baseline results file not found: {filepath}")

    try:
        df = pd.read_parquet(filepath)
        if df.empty:
            raise ValueError("Baseline results file is empty.")
        logger.info(f"Loaded baseline results: {len(df)} rows")
        return df
    except Exception as e:
        logger.error(f"Error loading baseline results: {e}")
        raise


