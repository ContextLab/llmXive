        f"   Symbolic Success Rate: {metrics.symbolic_success_rate:.2%}",
        f"   Compute Overhead Reduction: {metrics.compute_reduction_percent:.2f}%",
        f"   Catastrophic Failure Rate: {metrics.catastrophic_failure_rate:.2%} (Threshold: {metrics.catastrophic_failure_threshold:.2%})",
