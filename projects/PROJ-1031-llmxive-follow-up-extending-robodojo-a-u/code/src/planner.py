"""
Planner module for generating action sequences using A* algorithm.
Implements CPU-tractable symbolic planning with memory and time constraints.
"""

import time
import heapq
import logging
import tracemalloc
from typing import Dict, List, Any, Optional, Tuple, Set
from dataclasses import dataclass, field

from src.config import PLANNING_TIMEOUT_S, RAM_LIMIT_GB
from src.metrics_logger import ResourceLimitExceeded
from src.state_mapper import SymbolicState, AffordanceGraph

logger = logging.getLogger(__name__)


@dataclass
class ActionSequence:
    """Represents a sequence of discrete actions generated by the planner."""
    actions: List[str]
    sub_goals: List[Dict[str, Any]]
    planning_time_s: float
    memory_peak_mb: float
    success: bool
    error_message: Optional[str] = None


@dataclass
class AStarNode:
    """Node for A* search."""
    state_id: str
    g_cost: float  # Cost from start
    h_cost: float  # Heuristic estimate to goal
    parent: Optional['AStarNode'] = None
    action_taken: Optional[str] = None

    @property
    def f_cost(self) -> float:
        return self.g_cost + self.h_cost

    def __lt__(self, other: 'AStarNode') -> bool:
        return self.f_cost < other.f_cost


class AffordanceViolationError(Exception):
    """Raised when an action violates object affordances."""
    pass


class AStarPlanner:
    """A* planner for generating action sequences from symbolic states."""

    def __init__(self, affordance_graph: AffordanceGraph, timeout_s: float = PLANNING_TIMEOUT_S):
        self.graph = affordance_graph
        self.timeout_s = timeout_s
        self.start_time: Optional[float] = None

    def _check_time_limit(self) -> bool:
        """Check if planning has exceeded time limit."""
        if self.start_time is None:
            return False
        elapsed = time.time() - self.start_time
        if elapsed > self.timeout_s:
            logger.error(f"Planning exceeded time limit of {self.timeout_s}s")
            return True
        return False

    def _check_memory_limit(self) -> None:
        """Check if memory usage exceeds limit and raise if so."""
        current, peak = tracemalloc.get_traced_memory()
        peak_mb = peak / (1024 * 1024)
        if peak_mb > RAM_LIMIT_GB * 1024:
            raise ResourceLimitExceeded(
                f"Memory limit exceeded: {peak_mb:.2f}MB > {RAM_LIMIT_GB * 1024}MB"
            )

    def _heuristic(self, state_id: str, goal_ids: Set[str]) -> float:
        """
        Heuristic function: minimum BFS distance to any goal state.
        Uses unweighted BFS on the connectivity graph.
        """
        if state_id in goal_ids:
            return 0.0

        visited = {state_id}
        queue = [(state_id, 0)]
        min_dist = float('inf')

        while queue:
            current, dist = queue.pop(0)
            if dist >= min_dist:
                continue

            # Check neighbors in connectivity graph
            if current in self.graph.connectivity:
                for neighbor in self.graph.connectivity[current]:
                    if neighbor in goal_ids:
                        min_dist = min(min_dist, dist + 1)
                    elif neighbor not in visited:
                        visited.add(neighbor)
                        queue.append((neighbor, dist + 1))

        return min_dist if min_dist != float('inf') else float('inf')

    def _validate_action(self, state_id: str, action: str) -> None:
        """Validate that an action is valid for the current state's affordances."""
        if state_id not in self.graph.affordances:
            raise AffordanceViolationError(
                f"State {state_id} has no defined affordances"
            )

        state_affordances = self.graph.affordances[state_id]
        if action not in state_affordances.get('valid_actions', []):
            raise AffordanceViolationError(
                f"Action '{action}' not valid for state {state_id}. "
                f"Valid actions: {state_affordances.get('valid_actions', [])}"
            )

    def _get_next_state(self, state_id: str, action: str) -> Optional[str]:
        """Get the next state after applying an action."""
        if state_id not in self.graph.connectivity:
            return None

        # Check if action leads to a connected state
        for neighbor in self.graph.connectivity[state_id]:
            # Simple heuristic: if action is in the transition label or
            # if we have explicit transition rules
            # For now, assume any connected neighbor is reachable
            return neighbor
        return None

    def plan(self, start_state: SymbolicState, goal_states: List[SymbolicState]) -> ActionSequence:
        """
        Generate an action sequence from start state to any goal state.

        Args:
            start_state: Initial symbolic state
            goal_states: List of possible goal states

        Returns:
            ActionSequence with the planned actions and metadata
        """
        self.start_time = time.time()
        tracemalloc.start()

        try:
            goal_ids = {gs.state_id for gs in goal_states}
            start_id = start_state.state_id

            # Check if start is already a goal
            if start_id in goal_ids:
                return ActionSequence(
                    actions=[],
                    sub_goals=[],
                    planning_time_s=0.0,
                    memory_peak_mb=0.0,
                    success=True
                )

            # A* initialization
            open_heap: List[AStarNode] = []
            closed_set: Set[str] = set()
            g_costs: Dict[str, float] = {start_id: 0.0}

            initial_node = AStarNode(
                state_id=start_id,
                g_cost=0.0,
                h_cost=self._heuristic(start_id, goal_ids)
            )
            heapq.heappush(open_heap, initial_node)

            while open_heap:
                # Check constraints
                if self._check_time_limit():
                    return ActionSequence(
                        actions=[],
                        sub_goals=[],
                        planning_time_s=time.time() - self.start_time,
                        memory_peak_mb=tracemalloc.get_traced_memory()[1] / (1024 * 1024),
                        success=False,
                        error_message="Planning timeout"
                    )

                self._check_memory_limit()

                current = heapq.heappop(open_heap)

                if current.state_id in closed_set:
                    continue

                # Check if goal reached
                if current.state_id in goal_ids:
                    # Reconstruct path
                    actions = []
                    sub_goals = []
                    node = current
                    while node.parent is not None:
                        if node.action_taken:
                            actions.append(node.action_taken)
                        # Collect sub-goal information
                        sub_goals.append({
                            'state_id': node.state_id,
                            'predicates': node.state_id  # Simplified
                        })
                        node = node.parent

                    actions.reverse()
                    sub_goals.reverse()

                    return ActionSequence(
                        actions=actions,
                        sub_goals=sub_goals,
                        planning_time_s=time.time() - self.start_time,
                        memory_peak_mb=tracemalloc.get_traced_memory()[1] / (1024 * 1024),
                        success=True
                    )

                closed_set.add(current.state_id)

                # Explore neighbors
                if current.state_id in self.graph.connectivity:
                    for neighbor_id in self.graph.connectivity[current.state_id]:
                        if neighbor_id in closed_set:
                            continue

                        # Determine action to reach neighbor
                        # In a real implementation, this would come from transition rules
                        action = f"transition_{current.state_id}_to_{neighbor_id}"

                        try:
                            self._validate_action(current.state_id, action)
                        except AffordanceViolationError as e:
                            logger.warning(f"Skipping invalid action: {e}")
                            continue

                        tentative_g = current.g_cost + 1.0  # Uniform cost

                        if neighbor_id not in g_costs or tentative_g < g_costs[neighbor_id]:
                            g_costs[neighbor_id] = tentative_g
                            h = self._heuristic(neighbor_id, goal_ids)

                            if h == float('inf'):
                                continue

                            new_node = AStarNode(
                                state_id=neighbor_id,
                                g_cost=tentative_g,
                                h_cost=h,
                                parent=current,
                                action_taken=action
                            )
                            heapq.heappush(open_heap, new_node)

            # No path found
            return ActionSequence(
                actions=[],
                sub_goals=[],
                planning_time_s=time.time() - self.start_time,
                memory_peak_mb=tracemalloc.get_traced_memory()[1] / (1024 * 1024),
                success=False,
                error_message="No path found to goal"
            )

        finally:
            tracemalloc.stop()


def create_planner(affordance_graph: AffordanceGraph, timeout_s: float = PLANNING_TIMEOUT_S) -> AStarPlanner:
    """Factory function to create a planner instance."""
    return AStarPlanner(affordance_graph, timeout_s)


def run_planning_pipeline(
    start_state: SymbolicState,
    goal_states: List[SymbolicState],
    affordance_graph: AffordanceGraph,
    timeout_s: Optional[float] = None
) -> ActionSequence:
    """
    Run the full planning pipeline with logging and constraint checking.

    Args:
        start_state: Initial symbolic state
        goal_states: List of possible goal states
        affordance_graph: Graph defining state connectivity and affordances
        timeout_s: Optional timeout override

    Returns:
        ActionSequence with planning results and metrics
    """
    config_timeout = timeout_s if timeout_s is not None else PLANNING_TIMEOUT_S
    logger.info(f"Starting planning pipeline with timeout={config_timeout}s")

    planner = create_planner(affordance_graph, config_timeout)
    result = planner.plan(start_state, goal_states)

    # Log planning metrics
    logger.info(f"Planning completed: success={result.success}, "
               f"time={result.planning_time_s:.2f}s, "
               f"memory={result.memory_peak_mb:.2f}MB, "
               f"actions={len(result.actions)}")

    # Verify time constraint
    if result.planning_time_s > config_timeout:
        logger.warning(f"Planning time {result.planning_time_s:.2f}s exceeded limit {config_timeout}s")

    return result