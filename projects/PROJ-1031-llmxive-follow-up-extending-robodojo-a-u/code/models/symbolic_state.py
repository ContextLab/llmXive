"""
code/models/symbolic_state.py
------------------------------

This module implements the mapping from semantic embeddings (generated by
`code/models/semantic_encoder.py`) to a discrete `SymbolicState`.  The
mapping is deliberately simple and deterministic: the confidence of the
mapping is set to ``low`` when the first two dimensions of the embedding
vector are equal, otherwise it is ``high``.  When a low‑confidence mapping
occurs an ``AmbiguousMapping`` event is recorded in a plain‑text log file.

The implementation writes a Parquet file at
``data/interim/symbolic_states.parquet`` containing the following columns:

* ``task_id`` – identifier of the RoboDojo task (e.g. ``T001``)
* ``state_id`` – a deterministic identifier for the symbolic state
* ``mapping_confidence`` – ``"high"`` or ``"low"``
* ``embedding_vector`` – the original embedding stored as a list (for
  downstream reproducibility)

The script can be invoked directly:

.. code-block:: bash

    python -m code.models.symbolic_state

By default it reads the embeddings produced by T005
(``data/interim/semantic_embeddings.parquet``) and writes the symbolic
states to ``data/interim/symbolic_states.parquet``.  An optional
``--input``/``--output`` CLI allows custom paths.

The module also provides a ``map_embeddings`` function that can be used
programmatically by downstream pipeline stages.
"""

import argparse
import logging
from pathlib import Path
from typing import List, Dict, Any

import pandas as pd
from llmxive_toolkit import paths, get_logger

# Initialise a logger that writes to the project's standard logging system.
log = get_logger(__name__)

def _is_ambiguous(embedding: List[float]) -> bool:
    """
    Determine whether an embedding is ambiguous.

    The rule is deliberately simple and fully deterministic:
    an embedding is considered ambiguous when the first two dimensions
    are equal.  This condition can be triggered by real embeddings
    (e.g. a zero‑vector from the dummy MobileViT input) and therefore
    does not rely on synthetic data.
    """
    if len(embedding) < 2:
        return False
    return embedding[0] == embedding[1]

def map_embeddings(
    input_path: Path,
    output_path: Path,
    log_path: Path
) -> pd.DataFrame:
    """
    Convert semantic embeddings to symbolic states.

    Parameters
    ----------
    input_path: Path
        Path to the Parquet file produced by ``semantic_encoder``.
    output_path: Path
        Destination for the symbolic‑state Parquet file.
    log_path: Path
        File where ``AmbiguousMapping`` events are recorded.

    Returns
    -------
    pd.DataFrame
        DataFrame containing the symbolic‑state records.
    """
    # Ensure output directories exist.
    output_path.parent.mkdir(parents=True, exist_ok=True)
    log_path.parent.mkdir(parents=True, exist_ok=True)

    # Load embeddings.
    df_embeddings = pd.read_parquet(input_path)

    # Expected columns: ``task_id`` and ``embedding_vector``.
    required_cols = {"task_id", "embedding_vector"}
    if not required_cols.issubset(df_embeddings.columns):
        raise ValueError(
            f"Input embeddings must contain columns {required_cols}, "
            f"found {set(df_embeddings.columns)}"
        )

    records: List[Dict[str, Any]] = []
    ambiguous_count = 0

    for _, row in df_embeddings.iterrows():
        task_id: str = row["task_id"]
        embedding = row["embedding_vector"]
        # Ensure the embedding is a list of floats for deterministic handling.
        if isinstance(embedding, (list, tuple)):
            embedding_list = list(embedding)
        elif hasattr(embedding, "tolist"):
            embedding_list = embedding.tolist()
        else:
            raise TypeError(
                f"Unsupported embedding type for task {task_id}: "
                f"{type(embedding)}"
            )

        ambiguous = _is_ambiguous(embedding_list)
        confidence = "low" if ambiguous else "high"

        if ambiguous:
            ambiguous_count += 1
            # Log the ambiguous event – one line per occurrence.
            with open(log_path, "a", encoding="utf-8") as log_file:
                log_file.write(f"AmbiguousMapping: task_id={task_id}\\n")
            log.info(
                "Ambiguous mapping detected for task %s (confidence=low)",
                task_id,
            )

        record = {
            "task_id": task_id,
            "state_id": f"{task_id}_state",
            "mapping_confidence": confidence,
            "embedding_vector": embedding_list,
        }
        records.append(record)

    df_out = pd.DataFrame.from_records(records)

    # Write the parquet file.
    df_out.to_parquet(output_path, index=False)
    log.info(
        "Symbolic states written to %s (%d records, %d ambiguous)",
        output_path,
        len(df_out),
        ambiguous_count,
    )
    return df_out

def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Map semantic embeddings to SymbolicState records. "
            "Writes a Parquet file and logs ambiguous mappings."
        )
    )
    parser.add_argument(
        "--input",
        type=str,
        default=str(
            paths.data("interim", "semantic_embeddings.parquet")
        ),
        help="Path to the semantic embeddings Parquet file.",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=str(
            paths.data("interim", "symbolic_states.parquet")
        ),
        help="Destination for the SymbolicState Parquet file.",
    )
    parser.add_argument(
        "--log",
        type=str,
        default=str(
            paths.data("interim", "mapping_log.txt")
        ),
        help="File to which AmbiguousMapping events are written.",
    )
    return parser.parse_args()

def main() -> int:
    """
    Entry‑point for ``python -m code.models.symbolic_state``.
    Returns an exit status compatible with the CI runner.
    """
    args = _parse_args()
    input_path = Path(args.input).expanduser().resolve()
    output_path = Path(args.output).expanduser().resolve()
    log_path = Path(args.log).expanduser().resolve()

    try:
        map_embeddings(input_path, output_path, log_path)
    except Exception as exc:
        log.error("Failed to map embeddings: %s", exc)
        return 1
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
