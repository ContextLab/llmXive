"""
Schema definitions for ExecutionRun and RegressionModel validation.

These schemas define the expected structure for data generated by the
mesh network supercomputer pipeline. They are used by the contract
validation framework to ensure data integrity.
"""
from typing import Dict, Any

# ExecutionRun Schema
# Represents a single execution run of the benchmark across the mesh network
EXECUTION_RUN_SCHEMA: Dict[str, Any] = {
    "type": "object",
    "required": [
        "run_id",
        "timestamp_start",
        "timestamp_end",
        "node_count",
        "granularity",
        "injected_latency_ms",
        "packet_loss_rate",
        "throughput_ops_sec",
        "coordination_overhead_ratio",
        "status"
    ],
    "properties": {
        "run_id": {
            "type": "string",
            "description": "Unique identifier for the execution run"
        },
        "timestamp_start": {
            "type": "string",
            "format": "date-time",
            "description": "ISO 8601 timestamp of run start"
        },
        "timestamp_end": {
            "type": "string",
            "format": "date-time",
            "description": "ISO 8601 timestamp of run end"
        },
        "node_count": {
            "type": "integer",
            "minimum": 1,
            "description": "Number of physical nodes in the mesh"
        },
        "granularity": {
            "type": "string",
            "enum": ["fine", "medium", "coarse"],
            "description": "Task chunk size granularity"
        },
        "injected_latency_ms": {
            "type": "number",
            "minimum": 0,
            "description": "Simulated network latency in milliseconds"
        },
        "packet_loss_rate": {
            "type": "number",
            "minimum": 0,
            "maximum": 1,
            "description": "Fraction of packets lost (0.0 to 1.0)"
        },
        "throughput_ops_sec": {
            "type": "number",
            "minimum": 0,
            "description": "Measured throughput in operations per second"
        },
        "coordination_overhead_ratio": {
            "type": "number",
            "minimum": 0,
            "description": "Ratio of coordination time to compute time"
        },
        "status": {
            "type": "string",
            "enum": ["completed", "failed", "timeout", "partial"],
            "description": "Final status of the execution run"
        },
        "heterogeneity_index": {
            "type": "number",
            "minimum": 0,
            "maximum": 1,
            "description": "Measure of node performance variance (optional)"
        },
        "total_compute_time_sec": {
            "type": "number",
            "minimum": 0,
            "description": "Total wall-clock compute time (optional)"
        },
        "total_coordination_time_sec": {
            "type": "number",
            "minimum": 0,
            "description": "Total coordination overhead time (optional)"
        }
    }
}

# RegressionModel Schema
# Represents the output of statistical analysis on execution data
REGRESSION_MODEL_SCHEMA: Dict[str, Any] = {
    "type": "object",
    "required": [
        "model_id",
        "model_type",
        "r_squared",
        "coefficients",
        "p_values",
        "interaction_terms",
        "theoretical_bound",
        "bound_violation_flag"
    ],
    "properties": {
        "model_id": {
            "type": "string",
            "description": "Unique identifier for the regression model"
        },
        "model_type": {
            "type": "string",
            "enum": ["MLR", "GAM"],
            "description": "Type of regression model (Multiple Linear or Generalized Additive)"
        },
        "r_squared": {
            "type": "number",
            "minimum": 0,
            "maximum": 1,
            "description": "Coefficient of determination"
        },
        "coefficients": {
            "type": "object",
            "description": "Mapping of feature names to regression coefficients"
        },
        "p_values": {
            "type": "object",
            "description": "Mapping of feature names to p-values"
        },
        "interaction_terms": {
            "type": "array",
            "items": {
                "type": "string"
            },
            "description": "List of interaction terms included in the model"
        },
        "theoretical_bound": {
            "type": "number",
            "minimum": 0,
            "description": "Ong & Motani theoretical capacity limit"
        },
        "bound_violation_flag": {
            "type": "boolean",
            "description": "True if empirical performance exceeds theoretical bound"
        },
        "adjusted_r_squared": {
            "type": "number",
            "minimum": 0,
            "maximum": 1,
            "description": "Adjusted R-squared (optional)"
        },
        "aic": {
            "type": "number",
            "description": "Akaike Information Criterion (optional)"
        },
        "bic": {
            "type": "number",
            "description": "Bayesian Information Criterion (optional)"
        },
        "residual_std_error": {
            "type": "number",
            "minimum": 0,
            "description": "Standard error of residuals (optional)"
        },
        "sample_size": {
            "type": "integer",
            "minimum": 1,
            "description": "Number of observations used in fitting (optional)"
        }
    }
}
