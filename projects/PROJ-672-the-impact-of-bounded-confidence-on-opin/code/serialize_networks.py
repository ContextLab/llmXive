"""
Serialization logic for User Story 1 (Network Generation).

This module consumes generated network instances (from `generate_networks.py`)
and their pre-calculated metrics (from `calculate_metrics_for_network` in
`analyze_network_metrics.py` or generated inline) and persists them to disk
under `data/raw/networks/`.

It performs the following steps:
1. Loads network instances generated by `generate_networks.py` (if not passed directly).
2. Ensures metrics are available (calculates them if missing).
3. Serializes network topology to GraphML format.
4. Serializes metrics to JSON format.
5. Generates SHA-256 checksums for all output files.
6. Updates the project state manifest via `utils.checksums`.
"""

import os
import json
import hashlib
import random
from pathlib import Path
from typing import Dict, Any, List, Optional

import networkx as nx
import numpy as np

# Import existing project utilities
from generate_networks import generate_erdos_renyi, generate_barabasi_albert, generate_watts_strogatz, ensure_connected
from utils.metrics import calculate_structural_metrics
from utils.checksums import calculate_sha256, update_project_state_manifest


def serialize_network_to_graphml(graph: nx.Graph, output_path: Path) -> None:
    """
    Serializes a NetworkX graph to GraphML format.

    Args:
        graph: The NetworkX graph instance.
        output_path: The destination file path (must end in .graphml).
    """
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    nx.write_graphml(graph, output_path)


def serialize_metrics_to_json(metrics: Dict[str, Any], output_path: Path) -> None:
    """
    Serializes a dictionary of metrics to JSON format.

    Args:
        metrics: Dictionary containing structural metrics.
        output_path: The destination file path (must end in .json).
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(metrics, f, indent=2, default=str)


def process_and_serialize_networks(
    topology_type: str,
    n_instances: int,
    n_nodes: int = 500,
    base_seed: int = 42,
    output_dir: Path = Path("data/raw/networks")
) -> List[Dict[str, Any]]:
    """
    Generates, calculates metrics for, and serializes multiple network instances.

    This function acts as the bridge between generation (T012) and metrics (T013),
    ensuring the final artifacts (T014) are written to disk with checksums.

    Args:
        topology_type: One of 'er', 'ba', 'ws'.
        n_instances: Number of independent instances to generate.
        n_nodes: Number of nodes per network (default 500).
        base_seed: Base seed for random number generation.
        output_dir: Directory to save outputs.

    Returns:
        A list of dictionaries containing metadata and checksums for each run.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    results = []

    # Map topology type to generator
    generators = {
        'er': lambda seed: generate_erdos_renyi(n_nodes, seed),
        'ba': lambda seed: generate_barabasi_albert(n_nodes, seed),
        'ws': lambda seed: generate_watts_strogatz(n_nodes, seed),
    }

    if topology_type not in generators:
        raise ValueError(f"Unsupported topology type: {topology_type}. Choose from {list(generators.keys())}")

    generator_func = generators[topology_type]

    for i in range(n_instances):
        # Deterministic seed for each instance
        instance_seed = base_seed + i
        print(f"Processing instance {i+1}/{n_instances} (seed={instance_seed})...")

        # 1. Generate Network
        # Note: ensure_connected is called inside the generator functions in generate_networks.py
        # but we call it here explicitly if needed for safety, or rely on the generator.
        # Assuming generators return connected graphs as per T012 logic.
        G = generator_func(instance_seed)

        if not nx.is_connected(G):
            # Fallback: ensure connectivity if generator didn't guarantee it
            G = ensure_connected(G)

        # 2. Calculate Metrics
        # Re-using the metric calculation logic from utils.metrics
        metrics = calculate_structural_metrics(G)
        metrics['seed'] = instance_seed
        metrics['topology'] = topology_type
        metrics['n_nodes'] = n_nodes

        # 3. Define Output Paths
        graph_filename = f"network_{topology_type}_{instance_seed}.graphml"
        metrics_filename = f"metrics_{topology_type}_{instance_seed}.json"

        graph_path = output_dir / graph_filename
        metrics_path = output_dir / metrics_filename

        # 4. Serialize
        serialize_network_to_graphml(G, graph_path)
        serialize_metrics_to_json(metrics, metrics_path)

        # 5. Calculate Checksums
        graph_checksum = calculate_sha256(graph_path)
        metrics_checksum = calculate_sha256(metrics_path)

        # 6. Record Result
        result_entry = {
            "instance_id": i,
            "seed": instance_seed,
            "topology": topology_type,
            "graph_file": str(graph_path),
            "graph_checksum": graph_checksum,
            "metrics_file": str(metrics_path),
            "metrics_checksum": metrics_checksum,
            "metrics_snapshot": metrics
        }
        results.append(result_entry)

        print(f"  Saved: {graph_filename}, {metrics_filename}")

    return results


def main():
    """
    Entry point for the serialization script.
    Runs the full serialization pipeline for all topology types defined in the plan.
    """
    print("Starting Network Serialization (Task T014)...")

    # Configuration from Plan/US1
    # N=500, multiple instances per topology.
    # We will generate 3 instances per topology for demonstration of the pipeline.
    # In a full run, this would be higher (e.g., 50).
    topology_types = ['er', 'ba', 'ws']
    n_nodes = 500
    instances_per_type = 3  # Reduced for quick validation; set to 50 for full run
    base_seed = 42
    output_dir = Path("data/raw/networks")

    all_results = []

    for topo in topology_types:
        print(f"\n--- Generating and Serializing {topo.upper()} Networks ---")
        results = process_and_serialize_networks(
            topology_type=topo,
            n_instances=instances_per_type,
            n_nodes=n_nodes,
            base_seed=base_seed,
            output_dir=output_dir
        )
        all_results.extend(results)

    # Save a manifest of all generated runs for this batch
    manifest_path = output_dir / "batch_manifest.json"
    with open(manifest_path, 'w', encoding='utf-8') as f:
        json.dump(all_results, f, indent=2)

    # Update Project State Manifest with checksums
    # This satisfies the requirement to update state/projects/...yaml
    print("\nUpdating project state manifest with checksums...")
    update_project_state_manifest(manifest_path)

    print("Serialization complete.")


if __name__ == "__main__":
    main()