"""
T014b: Update project state artifact_hashes map with checksums from T014.

Reads data/checksums.csv generated by T014 and updates
state/projects/PROJ-533-evaluating-the-impact-of-data-transforma.yaml
"""
import os
import csv
import yaml
from pathlib import Path
import logging
from code.utils.logging_config import setup_pipeline_logger

# Initialize logger
logger = setup_pipeline_logger("update_artifact_hashes")

def load_checksums(checksum_path: str) -> dict:
    """
    Load checksums from CSV into a dictionary mapping filename -> sha256.
    Expected CSV headers: filename, sha256
    """
    checksums = {}
    if not os.path.exists(checksum_path):
        logger.warning(f"Checksum file not found: {checksum_path}")
        return checksums

    with open(checksum_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            filename = row.get('filename', '').strip()
            sha256 = row.get('sha256', '').strip()
            if filename and sha256:
                checksums[filename] = sha256
    return checksums

def update_project_state(project_state_path: str, checksums: dict):
    """
    Update the artifact_hashes map in the project state YAML file.
    If the file doesn't exist, create it with the checksums.
    """
    # Ensure directory exists
    state_dir = os.path.dirname(project_state_path)
    if state_dir and not os.path.exists(state_dir):
        os.makedirs(state_dir)
        logger.info(f"Created state directory: {state_dir}")

    state_data = {}
    if os.path.exists(project_state_path):
        with open(project_state_path, 'r', encoding='utf-8') as f:
            state_data = yaml.safe_load(f) or {}

    # Initialize artifact_hashes if missing
    if 'artifact_hashes' not in state_data:
        state_data['artifact_hashes'] = {}

    # Update with new checksums
    state_data['artifact_hashes'].update(checksums)
    state_data['last_updated'] = "auto-generated-by-t014b"

    # Write back
    with open(project_state_path, 'w', encoding='utf-8') as f:
        yaml.dump(state_data, f, default_flow_style=False, sort_keys=False)

    logger.info(f"Updated artifact_hashes in {project_state_path} with {len(checksums)} entries")

def main():
    project_root = Path(__file__).resolve().parent.parent
    checksums_path = project_root / "data" / "checksums.csv"
    state_path = project_root / "state" / "projects" / "PROJ-533-evaluating-the-impact-of-data-transforma.yaml"

    logger.info(f"Loading checksums from {checksums_path}")
    checksums = load_checksums(str(checksums_path))

    if not checksums:
        logger.warning("No checksums found. State file will be created/updated with empty hashes.")
    
    logger.info(f"Updating state file at {state_path}")
    update_project_state(str(state_path), checksums)
    
    logger.info("T014b completed successfully.")

if __name__ == "__main__":
    main()
