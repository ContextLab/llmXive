def load_model_and_features():
    """Load the trained model and feature names from the model artifact."""
    model_path = Path("data/models/random_forest.pkl")
    if not model_path.exists():
        raise FileNotFoundError(f"Model artifact not found at {model_path}. Run T024 first.")
    
    with open(model_path, 'rb') as f:
        data = pickle.load(f)
    
    model = data.get('model')
    feature_names = data.get('feature_names')
    if model is None or feature_names is None:
        raise ValueError("Model artifact is missing 'model' or 'feature_names' keys.")
    
    return model, feature_names

