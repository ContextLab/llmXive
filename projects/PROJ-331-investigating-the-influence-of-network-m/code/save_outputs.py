"""
T017: Save processed matrices with provenance metadata.

This script loads the processed structural and rsFC matrices generated by
the pipeline (T014, T015) and saves them to the designated output location
with a provenance JSON file documenting the source files, processing steps,
and execution metadata.
"""
import os
import sys
import json
import time
import hashlib
from pathlib import Path
from datetime import datetime
import numpy as np

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from config import ensure_dirs
from utils import (
    get_logger, 
    save_npy, 
    load_npy, 
    compute_sha256, 
    safe_write_json,
    ProcessingError
)

def compute_sha256_file(filepath: Path) -> str:
    """Compute SHA256 hash of a file."""
    if not filepath.exists():
        raise FileNotFoundError(f"File not found: {filepath}")
    return compute_sha256(filepath)

def load_provenance_info(input_file: Path) -> dict:
    """Load basic info from an input file for provenance."""
    if not input_file.exists():
        return {
            "path": str(input_file),
            "exists": False,
            "error": "File not found"
        }
    
    info = {
        "path": str(input_file),
        "exists": True,
        "size_bytes": input_file.stat().st_size,
        "sha256": compute_sha256_file(input_file),
        "modified_at": datetime.fromtimestamp(input_file.stat().st_mtime).isoformat()
    }
    
    if input_file.suffix == '.npy':
        try:
            arr = np.load(input_file)
            info["shape"] = list(arr.shape)
            info["dtype"] = str(arr.dtype)
            info["min"] = float(np.min(arr))
            info["max"] = float(np.max(arr))
            info["mean"] = float(np.mean(arr))
        except Exception as e:
            info["load_error"] = str(e)
    
    return info

def save_with_provenance(
    input_file: Path,
    output_file: Path,
    description: str,
    logger
) -> dict:
    """
    Load a processed matrix, save it to the output location, and generate
    provenance metadata.
    """
    logger.info(f"Processing {description}: {input_file}")
    
    if not input_file.exists():
        raise ProcessingError(f"Input file not found: {input_file}")
    
    # Load the data
    try:
        data = load_npy(input_file)
    except Exception as e:
        raise ProcessingError(f"Failed to load {input_file}: {e}")
    
    # Ensure output directory exists
    ensure_dirs([output_file.parent])
    
    # Save to output location
    try:
        save_npy(data, output_file)
        logger.info(f"Saved {description} to {output_file}")
    except Exception as e:
        raise ProcessingError(f"Failed to save {output_file}: {e}")
    
    # Compute output hash
    output_sha256 = compute_sha256_file(output_file)
    
    return {
        "description": description,
        "input": load_provenance_info(input_file),
        "output": {
            "path": str(output_file),
            "sha256": output_sha256,
            "size_bytes": output_file.stat().st_size,
            "shape": list(data.shape),
            "dtype": str(data.dtype)
        }
    }

def main():
    """Main entry point for T017."""
    logger = get_logger("save_outputs")
    logger.info("Starting T017: Save processed matrices with provenance")
    
    start_time = time.time()
    
    # Define paths based on project structure
    processed_dir = project_root / "data" / "processed"
    
    # Input files from T014 and T015
    structural_input = processed_dir / "weighted_adjacency.npy"
    rsfc_input = processed_dir / "rsfc.npy"
    
    # Output files (T017 requirement)
    structural_output = processed_dir / "structural.npy"
    rsfc_output = processed_dir / "rsfc.npy"  # Same name, but with provenance
    
    # Ensure directories exist
    ensure_dirs([processed_dir])
    
    provenance = {
        "task_id": "T017",
        "timestamp": datetime.now().isoformat(),
        "description": "Save processed matrices with provenance metadata",
        "artifacts": []
    }
    
    # Process structural matrix
    try:
        struct_info = save_with_provenance(
            structural_input, 
            structural_output, 
            "Structural Connectome (Weighted Adjacency)",
            logger
        )
        provenance["artifacts"].append(struct_info)
    except Exception as e:
        logger.error(f"Failed to process structural matrix: {e}")
        raise
    
    # Process rsFC matrix
    try:
        rsfc_info = save_with_provenance(
            rsfc_input, 
            rsfc_output, 
            "Resting-State Functional Connectivity",
            logger
        )
        provenance["artifacts"].append(rsfc_info)
    except Exception as e:
        logger.error(f"Failed to process rsFC matrix: {e}")
        raise
    
    # Add global metadata
    provenance["execution_time_seconds"] = time.time() - start_time
    provenance["input_files"] = [str(structural_input), str(rsfc_input)]
    provenance["output_files"] = [str(structural_output), str(rsfc_output)]
    
    # Save provenance metadata
    provenance_file = processed_dir / "provenance_T017.json"
    ensure_dirs([provenance_file.parent])
    
    try:
        safe_write_json(provenance, provenance_file)
        logger.info(f"Saved provenance metadata to {provenance_file}")
    except Exception as e:
        logger.error(f"Failed to save provenance: {e}")
        raise
    
    logger.info(f"T017 completed successfully in {provenance['execution_time_seconds']:.2f}s")
    return 0

if __name__ == "__main__":
    sys.exit(main())
