"""
test_quantize_config.py
========================

This test suite validates that each JSON configuration generated by
``code/utils/quantize.py`` conforms to the JSON schema defined in
``contracts/config.schema.yaml``.
"""

import json
from pathlib import Path

import pytest
import yaml
from jsonschema import Draft7Validator, ValidationError

# Resolve the project‑root relative paths
PROJECT_ROOT = Path(__file__).resolve().parents[2]
CONFIG_DIR = PROJECT_ROOT / "data" / "configs"
SCHEMA_PATH = PROJECT_ROOT / "contracts" / "config.schema.yaml"


@pytest.fixture(scope="module")
def schema():
    """Load the JSON schema used for validation."""
    with SCHEMA_PATH.open("r", encoding="utf-8") as f:
        raw = yaml.safe_load(f)
    # jsonschema expects a dict; ``Draft7Validator`` works with the loaded schema.
    return Draft7Validator(raw)


def test_all_config_files_validate(schema):
    """
    Ensure that every ``*.json`` file inside ``data/configs`` validates
    against the contract schema.
    """
    json_files = list(CONFIG_DIR.glob("*.json"))
    assert json_files, "No configuration JSON files found in data/configs/"

    for cfg_path in json_files:
        with cfg_path.open("r", encoding="utf-8") as f:
            config = json.load(f)

        # ``schema.validate`` raises a ``ValidationError`` if the instance is invalid.
        try:
            schema.validate(config)
        except ValidationError as exc:
            pytest.fail(f"Configuration {cfg_path.name} failed schema validation: {exc.message}")
