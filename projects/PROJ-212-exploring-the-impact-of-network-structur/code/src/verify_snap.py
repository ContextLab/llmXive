import os
import json
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional
from config import get_paths

# Configure logging
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def get_sorted_network_files(raw_dir: Path) -> List[str]:
    """
    Scans the raw data directory for network files (.mtx, .csv, .gml)
    and returns a sorted list of filenames alphabetically.
    """
    if not raw_dir.exists():
        logger.warning(f"Raw directory {raw_dir} does not exist.")
        return []

    extensions = {'.mtx', '.csv', '.gml'}
    files = []
    for f in raw_dir.iterdir():
        if f.is_file() and f.suffix.lower() in extensions:
            files.append(f.name)

    files.sort()
    logger.info(f"Found {len(files)} network files in {raw_dir}")
    return files

def load_simulation_results(results_path: Path) -> Dict[str, Any]:
    """
    Loads the simulation results JSON generated by T016.
    """
    if not results_path.exists():
        raise FileNotFoundError(f"Simulation results file not found: {results_path}")

    with open(results_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # Expected structure based on T016: list of results or a dict containing a list
    # Assuming T016 produces a list of results or a dict with a 'results' key
    # Adjust based on actual T016 output structure. 
    # Based on T016 description: "save results/sim_results.json" containing keys network_id, metrics, threshold.
    # It likely aggregates multiple runs. Let's assume it's a list of dicts or a dict with a 'networks' key.
    # If it's a single run, we might need to handle that, but T016 implies aggregation over the dataset.
    # Let's assume the structure is:
    # [ {"network_id": "...", "threshold": ...}, ... ]
    # or
    # { "networks": [ {"id": "...", "threshold": ...}, ... ] }
    
    # To be robust, let's try to extract a list of network results.
    if isinstance(data, list):
        return data
    elif isinstance(data, dict) and 'networks' in data:
        return data['networks']
    elif isinstance(data, dict) and 'results' in data:
        return data['results']
    else:
        # If it's a single object, wrap it in a list
        if 'network_id' in data or 'id' in data:
            return [data]
        logger.error(f"Unexpected simulation results structure: {type(data)}")
        return []

def generate_verification_report(sorted_files: List[str], sim_results: List[Dict], output_path: Path) -> None:
    """
    Generates verification_report.json containing the sorted IDs and their threshold values.
    Schema: {"networks": [{"id": "string", "threshold": "float | null"}]}
    """
    # Create a map from network_id to threshold
    # Network IDs in sim_results might be just the filename or a full path.
    # We assume they match the filename in sorted_files.
    result_map = {}
    for res in sim_results:
        # Try to find the ID key
        nid = res.get('network_id') or res.get('id')
        if nid:
            # Extract just the filename if it's a path
            if isinstance(nid, str):
                nid = os.path.basename(nid)
            threshold = res.get('threshold')
            result_map[nid] = threshold

    networks = []
    for fname in sorted_files:
        threshold = result_map.get(fname)
        networks.append({
            "id": fname,
            "threshold": threshold
        })

    report = {"networks": networks}

    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Verification report written to {output_path}")

def generate_manual_verification_log(sorted_files: List[str], output_path: Path) -> None:
    """
    Generates manual_verification_log.txt as a template for human sign-off
    on the first 5 networks to satisfy SC-003.
    """
    subset = sorted_files[:5]
    
    lines = [
        "Manual Verification Log",
        "=======================",
        "This log is for human sign-off on the first 5 networks processed.",
        "Per SC-003, a human must verify the correctness of the simulation results for these networks.",
        "",
        f"Date: {__import__('datetime').datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "",
        "Networks to Verify:",
        "-------------------"
    ]
    
    for i, fname in enumerate(subset, 1):
        lines.append(f"{i}. {fname}")
        lines.append(f"   [ ] Synchronization threshold verified manually")
        lines.append(f"   [ ] Topological metrics verified manually")
        lines.append(f"   [ ] Simulation parameters checked")
        lines.append("")
    
    lines.append("Sign-off:")
    lines.append("---------")
    lines.append("Verifier Name: _________________________")
    lines.append("Signature: _____________________________")
    lines.append("Date: _________________________________")
    lines.append("")
    lines.append("Notes:")
    lines.append("------")
    lines.append("")
    
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    
    logger.info(f"Manual verification log written to {output_path}")

def main():
    """
    Main entry point for T017b: Verification and Reporting.
    """
    paths = get_paths()
    raw_dir = paths['data_raw']
    sim_results_path = paths['results_dir'] / 'sim_results.json'
    verification_report_path = paths['results_dir'] / 'verification_report.json'
    manual_log_path = paths['results_dir'] / 'manual_verification_log.txt'

    # Ensure results directory exists
    paths['results_dir'].mkdir(parents=True, exist_ok=True)

    # 1. Get sorted network files
    sorted_files = get_sorted_network_files(raw_dir)
    
    if not sorted_files:
        logger.warning("No network files found in data/raw/. Generating empty report.")
        # Still generate the files to satisfy the task requirement of existence
        generate_verification_report([], [], verification_report_path)
        generate_manual_verification_log([], manual_log_path)
        return

    # 2. Load simulation results
    try:
        sim_results = load_simulation_results(sim_results_path)
    except FileNotFoundError as e:
        logger.error(str(e))
        # If results don't exist, we can't generate a meaningful report with thresholds
        # But we can still list the files with null thresholds
        sim_results = []

    # 3. Generate verification report
    generate_verification_report(sorted_files, sim_results, verification_report_path)

    # 4. Generate manual verification log
    generate_manual_verification_log(sorted_files, manual_log_path)

    logger.info("T017b verification process completed.")

if __name__ == '__main__':
    main()
