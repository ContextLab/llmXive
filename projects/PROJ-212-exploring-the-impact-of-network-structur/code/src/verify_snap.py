import os
import json
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional
from datetime import datetime

# Import from existing API surface
from config import get_paths

logger = logging.getLogger(__name__)

def get_sorted_network_files(raw_dir: Path) -> List[str]:
    """
    Filter data/raw/ for files matching SNAP naming pattern (snap_*.mtx)
    and return a sorted list of filenames.
    """
    if not raw_dir.exists():
        logger.error(f"Raw directory does not exist: {raw_dir}")
        return []

    snap_files = []
    for f in raw_dir.iterdir():
        if f.is_file() and f.name.startswith("snap_") and f.name.endswith(".mtx"):
            snap_files.append(f.name)

    snap_files.sort()
    logger.info(f"Found {len(snap_files)} SNAP files in {raw_dir}")
    return snap_files

def load_simulation_results(results_path: Path) -> Dict[str, Any]:
    """
    Load the simulation results JSON generated by T016.
    Returns a dictionary mapping network_id to result object.
    """
    if not results_path.exists():
        raise FileNotFoundError(f"Simulation results file not found: {results_path}")

    with open(results_path, 'r') as f:
        data = json.load(f)

    # Handle both list and dict formats if necessary, but assume list of dicts
    if isinstance(data, list):
        return {item.get('network_id'): item for item in data if 'network_id' in item}
    elif isinstance(data, dict):
        return data
    else:
        raise ValueError("Unexpected format in simulation results")

def generate_verification_report(
    sorted_files: List[str],
    sim_results: Dict[str, Any],
    output_path: Path
) -> None:
    """
    Generate results/verification_report.json containing sorted IDs and thresholds.
    Schema: {"networks": [{"id": "string", "threshold": "float | null"}]}
    """
    networks = []
    for filename in sorted_files:
        # Extract ID (remove .mtx extension)
        network_id = filename.replace(".mtx", "")
        result = sim_results.get(network_id)
        
        threshold = None
        if result:
            threshold = result.get('threshold')
            # Handle case where threshold might be a string representation of float or null
            if isinstance(threshold, str):
                if threshold.lower() in ('null', 'none', 'inf', 'infinity'):
                    threshold = None
                else:
                    try:
                        threshold = float(threshold)
                    except ValueError:
                        threshold = None
        
        networks.append({
            "id": network_id,
            "threshold": threshold
        })

    report = {"networks": networks}

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)

    logger.info(f"Verification report written to {output_path}")

def generate_manual_verification_log(
    sorted_files: List[str],
    sim_results: Dict[str, Any],
    output_path: Path,
    max_rows: int = 5
) -> None:
    """
    Generate results/manual_verification_log.csv with the first N SNAP networks.
    CSV headers: network_id,threshold,verified_by,timestamp
    Constraint: MUST use real data from T016. No synthetic population.
    """
    import csv

    # Select the first max_rows networks from the sorted list
    selected_files = sorted_files[:max_rows]
    
    if not selected_files:
        logger.warning("No SNAP files found to generate manual verification log.")
        # Still create the file with headers if no data
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, 'w', newline='') as f:
            writer = csv.writer(f)
            writer.writerow(['network_id', 'threshold', 'verified_by', 'timestamp'])
        return

    rows = []
    for filename in selected_files:
        network_id = filename.replace(".mtx", "")
        result = sim_results.get(network_id)
        
        threshold = None
        if result:
            threshold = result.get('threshold')
            if isinstance(threshold, str):
                if threshold.lower() in ('null', 'none', 'inf', 'infinity'):
                    threshold = ''
                else:
                    try:
                        threshold = float(threshold)
                    except ValueError:
                        threshold = ''
        
        # Leave verified_by and timestamp empty for human to fill
        rows.append({
            'network_id': network_id,
            'threshold': threshold if threshold is not None else '',
            'verified_by': '',
            'timestamp': ''
        })

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=['network_id', 'threshold', 'verified_by', 'timestamp'])
        writer.writeheader()
        writer.writerows(rows)

    logger.info(f"Manual verification log written to {output_path} with {len(rows)} rows")

def main():
    """
    Entry point for T017b: Verify SNAP files and generate reports.
    """
    paths = get_paths()
    raw_dir = paths.get('raw_data', paths['data_dir'] / 'raw')
    results_dir = paths['results_dir']
    
    sim_results_path = results_dir / 'sim_results.json'
    verification_report_path = results_dir / 'verification_report.json'
    manual_log_path = results_dir / 'manual_verification_log.csv'

    # 1. Filter and sort SNAP files
    sorted_files = get_sorted_network_files(raw_dir)
    
    if not sorted_files:
        logger.warning("No SNAP files found in data/raw/. Reports will be empty.")
    
    # 2. Load simulation results from T016
    try:
        sim_results = load_simulation_results(sim_results_path)
    except FileNotFoundError as e:
        logger.error(f"Cannot proceed: {e}")
        raise

    # 3. Generate verification report
    generate_verification_report(sorted_files, sim_results, verification_report_path)

    # 4. Generate manual verification log (first 5 networks)
    generate_manual_verification_log(sorted_files, sim_results, manual_log_path, max_rows=5)

    logger.info("T017b verification reports generated successfully.")

if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    main()
