import os
import json
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional
from datetime import datetime

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(),
        logging.FileHandler('logs/verify_snap.log')
    ]
)
logger = logging.getLogger(__name__)

def get_sorted_network_files(raw_dir: Path) -> List[str]:
    """
    Filter data/raw/ for files matching SNAP naming pattern (snap_*.mtx)
    and sort alphabetically by filename.
    """
    if not raw_dir.exists():
        logger.warning(f"Raw directory does not exist: {raw_dir}")
        return []

    snap_files = []
    # Check direct files in raw_dir
    for f in raw_dir.iterdir():
        if f.is_file() and f.name.startswith('snap_') and f.suffix == '.mtx':
            snap_files.append(f.name)
    
    # Check subdirectory data/raw/snap/ if it exists
    snap_subdir = raw_dir / 'snap'
    if snap_subdir.exists() and snap_subdir.is_dir():
        for f in snap_subdir.iterdir():
            if f.is_file() and f.name.startswith('snap_') and f.suffix == '.mtx':
                snap_files.append(f.name)

    snap_files.sort()
    logger.info(f"Found {len(snap_files)} SNAP files matching pattern.")
    return snap_files

def load_simulation_results(results_path: Path) -> Dict[str, Any]:
    """
    Read results/sim_results.json generated by T016.
    Returns a dict mapping network_id to its simulation data.
    """
    if not results_path.exists():
        raise FileNotFoundError(f"Simulation results file not found: {results_path}")

    with open(results_path, 'r') as f:
        data = json.load(f)

    # Expecting a list of results or a dict with a 'networks' key
    if isinstance(data, list):
        return {item.get('network_id'): item for item in data if 'network_id' in item}
    elif isinstance(data, dict) and 'networks' in data:
        return {item.get('network_id'): item for item in data['networks'] if 'network_id' in item}
    else:
        # Assume the dict keys are network_ids or try to extract 'network_id'
        # Fallback: treat the whole dict as one result if it has 'network_id'
        if 'network_id' in data:
            return {data['network_id']: data}
        return {}

def generate_verification_report(
    snap_ids: List[str],
    sim_results: Dict[str, Any],
    output_path: Path
) -> None:
    """
    Generate results/verification_report.json containing the sorted IDs
    and their threshold values (first 5 only).
    Schema: {"networks": [{"id": "string", "threshold": "float | null"}]}
    """
    networks = []
    # Take first 5 as per spec
    for snap_id in snap_ids[:5]:
        threshold = None
        if snap_id in sim_results:
            entry = sim_results[snap_id]
            # Try to find threshold in various possible locations
            if isinstance(entry, dict):
                threshold = entry.get('threshold') or entry.get('critical_coupling')
        
        networks.append({
            "id": snap_id,
            "threshold": float(threshold) if threshold is not None else None
        })

    report = {"networks": networks}

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Verification report written to {output_path}")

def generate_manual_verification_log(
    snap_ids: List[str],
    sim_results: Dict[str, Any],
    output_path: Path
) -> None:
    """
    Generate results/manual_verification_log.csv by executing the verification logic.
    CSV headers: network_id,threshold,verified_by,timestamp
    Populated with actual results, not just headers.
    """
    import csv
    
    output_path.parent.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().isoformat()
    verified_by = "Automated Pipeline (T017b)"

    with open(output_path, 'w', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['network_id', 'threshold', 'verified_by', 'timestamp'])
        
        for snap_id in snap_ids:
            threshold = None
            if snap_id in sim_results:
                entry = sim_results[snap_id]
                if isinstance(entry, dict):
                    threshold = entry.get('threshold') or entry.get('critical_coupling')
            
            threshold_str = str(threshold) if threshold is not None else 'null'
            writer.writerow([snap_id, threshold_str, verified_by, timestamp])
    
    logger.info(f"Manual verification log written to {output_path}")

def main():
    """
    Main entry point for T017b verification task.
    """
    base_path = Path('.')
    raw_dir = base_path / 'data' / 'raw'
    results_dir = base_path / 'results'
    sim_results_path = results_dir / 'sim_results.json'
    verification_report_path = results_dir / 'verification_report.json'
    manual_log_path = results_dir / 'manual_verification_log.csv'

    logger.info("Starting SNAP verification task (T017b)...")

    try:
        # 1. Filter and sort SNAP files
        snap_files = get_sorted_network_files(raw_dir)
        if not snap_files:
            logger.warning("No SNAP files found matching pattern 'snap_*.mtx'.")
            # Still generate empty reports to satisfy schema requirements
            snap_files = []

        # 2. Load simulation results from T016
        sim_results = load_simulation_results(sim_results_path)
        if not sim_results:
            logger.warning("No simulation results found in sim_results.json.")

        # 3. Generate verification report (first 5 only)
        generate_verification_report(snap_files, sim_results, verification_report_path)

        # 4. Generate manual verification log (populated rows)
        generate_manual_verification_log(snap_files, sim_results, manual_log_path)

        logger.info("T017b verification task completed successfully.")

    except Exception as e:
        logger.error(f"Error during T017b execution: {e}", exc_info=True)
        raise

if __name__ == "__main__":
    main()
