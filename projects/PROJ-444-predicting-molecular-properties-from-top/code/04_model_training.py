"""
Model Training Pipeline (Task T005)
-----------------------------------
Trains Ridge Regression (α=1.0) and Random Forest (100 trees, max_depth=10, seed=42)
on three feature sets: traditional, topological, combined.
Uses the scaffold‑based 5‑fold split generated by T001.
Enforces CPU‑only execution (GPU guard).
Writes a JSON report conforming to ``model_metrics.schema.yaml`` at
``reports/metrics/model_metrics.json`` and logs the run to
``data/logs/training.log``.
"""

import os
import sys
import json
import logging
import time
import pickle
import random
from pathlib import Path
from typing import List, Tuple, Dict, Any, Optional

import numpy as np
import pandas as pd
from sklearn.linear_model import Ridge
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import r2_score, mean_squared_error
from rdkit import Chem
from rdkit.Chem.Scaffolds.MurckoScaffold import GetScaffoldForMol

# ----------------------------------------------------------------------
# Configuration constants
# ----------------------------------------------------------------------
SEED = 42
N_FOLDS = 5
LINEAR_ALPHA = 1.0
RF_TREES = 100
RF_MAX_DEPTH = 10

# Project‑relative paths
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = PROJECT_ROOT / "data"
MODELS_DIR = DATA_DIR / "models"
PROCESSED_DIR = DATA_DIR / "processed"
LOGS_DIR = DATA_DIR / "logs"
REPORTS_DIR = PROJECT_ROOT / "reports" / "metrics"

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def setup_logging(log_file: Optional[Path] = None) -> logging.Logger:
    """Configure a logger that writes to stdout and optionally to a file."""
    logger = logging.getLogger("model_training")
    logger.setLevel(logging.INFO)
    formatter = logging.Formatter("%(asctime)s - %(levelname)s - %(message)s")

    # Stream handler (stdout)
    sh = logging.StreamHandler(sys.stdout)
    sh.setFormatter(formatter)
    logger.addHandler(sh)

    # Optional file handler
    if log_file:
        log_file.parent.mkdir(parents=True, exist_ok=True)
        fh = logging.FileHandler(log_file)
        fh.setFormatter(formatter)
        logger.addHandler(fh)

    return logger

def check_gpu_disabled() -> None:
    """Abort if any GPU device is detected (FR‑008)."""
    # CUDA environment variable guard
    if os.environ.get("CUDA_VISIBLE_DEVICES"):
        raise SystemExit("GPU detected via CUDA_VISIBLE_DEVICES – aborting (FR‑008).")

    # Torch guard (optional, safe import)
    try:
        import torch
        if torch.cuda.is_available():
            raise SystemExit("GPU detected via torch.cuda – aborting (FR‑008).")
    except ImportError:
        pass  # torch not installed – fine

def get_bemis_murcko_scaffold(smiles: str) -> Optional[str]:
    """Return the Bemis‑Murcko scaffold SMILES for a molecule."""
    try:
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            return None
        scaffold = GetScaffoldForMol(mol)
        return Chem.MolToSmiles(scaffold) if scaffold else None
    except Exception:
        return None

def stratified_scaffold_split(
    df: pd.DataFrame,
    n_splits: int = N_FOLDS,
    seed: int = SEED,
) -> List[Tuple[List[int], List[int]]]:
    """
    Perform scaffold‑based splitting (GroupKFold‑style) while preserving
    scaffold frequency distribution across folds.
    Returns a list of (train_idx, test_idx) tuples.
    """
    random.seed(seed)
    np.random.seed(seed)

    # Attach scaffold column
    df = df.copy()
    df["_scaffold"] = df["smiles"].apply(get_bemis_murcko_scaffold).fillna("unknown")

    # Group indices by scaffold
    scaffold_groups = df.groupby("_scaffold").indices

    # Randomly order scaffold groups
    scaffold_keys = list(scaffold_groups.keys())
    random.shuffle(scaffold_keys)

    # Assign each scaffold to a fold (round‑robin)
    fold_assignments = {k: i % n_splits for i, k in enumerate(scaffold_keys)}

    splits: List[Tuple[List[int], List[int]]] = []
    for fold in range(n_splits):
        test_scaffolds = [k for k, v in fold_assignments.items() if v == fold]
        test_idx, train_idx = [], []
        for scaffold, indices in scaffold_groups.items():
            if scaffold in test_scaffolds:
                test_idx.extend(indices)
            else:
                train_idx.extend(indices)
        splits.append((train_idx, test_idx))
    return splits

def train_and_evaluate(
    X_train: np.ndarray,
    y_train: np.ndarray,
    X_test: np.ndarray,
    y_test: np.ndarray,
    model_type: str,
) -> Tuple[float, float, Any]:
    """
    Train either a Ridge (``linear``) or RandomForest (``rf``) model
    and return (R², RMSE, fitted_model).
    """
    if model_type == "linear":
        model = Ridge(alpha=LINEAR_ALPHA, random_state=SEED)
    elif model_type == "rf":
        model = RandomForestRegressor(
            n_estimators=RF_TREES,
            max_depth=RF_MAX_DEPTH,
            random_state=SEED,
            n_jobs=-1,
        )
    else:
        raise ValueError(f"Unsupported model_type: {model_type}")

    model.fit(X_train, y_train)
    preds = model.predict(X_test)

    r2 = r2_score(y_test, preds)
    rmse = np.sqrt(mean_squared_error(y_test, preds))
    return r2, rmse, model

# ----------------------------------------------------------------------
# Core training loop
# ----------------------------------------------------------------------
def run_model_training(logger: logging.Logger) -> Dict[str, Any]:
    """
    Executes the full training pipeline:
    1. Verify GPU is disabled.
    2. Load scaffold splits.
    3. Load ``combined_features.csv``.
    4. For each feature set (traditional, topological, combined) train both
       Ridge and Random Forest on every fold.
    5. Aggregate per‑fold R² / RMSE, compute means/stds.
    6. Compute feature‑importance vectors (average across folds):
         * Ridge → |coefficients|
         * RF → mean of ``feature_importances_``.
    7. Write ``reports/metrics/model_metrics.json``.
    8. Persist each trained model under ``data/models/``.
    """
    check_gpu_disabled()
    random.seed(SEED)
    np.random.seed(SEED)

    # Ensure output directories exist
    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    LOGS_DIR.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # Load splits
    # ------------------------------------------------------------------
    splits_path = PROCESSED_DIR / "splits.json"
    if not splits_path.is_file():
        logger.error(f"Splits file not found at {splits_path}")
        raise FileNotFoundError("Missing splits.json – run T001 first.")
    with splits_path.open() as f:
        split_data = json.load(f)

    # ------------------------------------------------------------------
    # Load combined feature matrix
    # ------------------------------------------------------------------
    features_path = PROCESSED_DIR / "combined_features.csv"
    if not features_path.is_file():
        logger.error(f"Combined feature matrix not found at {features_path}")
        raise FileNotFoundError("Missing combined_features.csv – run T004 first.")
    df = pd.read_csv(features_path)

    if "logP" not in df.columns:
        logger.error("Target column 'logP' missing from combined_features.csv")
        raise ValueError("Target column 'logP' not present.")

    # ------------------------------------------------------------------
    # Identify column groups
    # ------------------------------------------------------------------
    all_feature_cols = [c for c in df.columns if c not in ("molecule_id", "logP")]
    tda_cols = [c for c in all_feature_cols if c.startswith("pixel_")]
    traditional_cols = [c for c in all_feature_cols if c not in tda_cols]

    feature_groups = {
        "traditional": traditional_cols,
        "topological": tda_cols,
        "combined": all_feature_cols,
    }

    logger.info(
        f"Feature column counts – Traditional: {len(traditional_cols)}, "
        f"Topological: {len(tda_cols)}, Combined: {len(all_feature_cols)}"
    )

    # ------------------------------------------------------------------
    # Data structures for results
    # ------------------------------------------------------------------
    results: Dict[str, Dict[str, Dict[str, Any]]] = {
        fg: {"linear": {"r2": [], "rmse": [], "importances": []},
             "rf": {"r2": [], "rmse": [], "importances": []}}
        for fg in feature_groups
    }

    # ------------------------------------------------------------------
    # Iterate over feature sets and folds
    # ------------------------------------------------------------------
    for feat_name, cols in feature_groups.items():
        logger.info(f"Training on feature set '{feat_name}' ({len(cols)} columns).")
        X = df[cols].values
        y = df["logP"].values

        for fold_idx, (train_idx, test_idx) in enumerate(split_data["splits"]):
            X_train, X_test = X[train_idx], X[test_idx]
            y_train, y_test = y[train_idx], y[test_idx]

            # Linear (Ridge)
            r2_lin, rmse_lin, lin_model = train_and_evaluate(
                X_train, y_train, X_test, y_test, "linear"
            )
            results[feat_name]["linear"]["r2"].append(r2_lin)
            results[feat_name]["linear"]["rmse"].append(rmse_lin)

            # Save linear model
            lin_path = MODELS_DIR / f"{feat_name}_linear_fold{fold_idx}.pkl"
            with lin_path.open("wb") as f:
                pickle.dump(lin_model, f)

            # Feature importance for Ridge → absolute coefficients
            # Align with column order
            lin_importance = np.abs(lin_model.coef_)
            results[feat_name]["linear"]["importances"].append(lin_importance.tolist())

            # Random Forest
            r2_rf, rmse_rf, rf_model = train_and_evaluate(
                X_train, y_train, X_test, y_test, "rf"
            )
            results[feat_name]["rf"]["r2"].append(r2_rf)
            results[feat_name]["rf"]["rmse"].append(rmse_rf)

            # Save RF model
            rf_path = MODELS_DIR / f"{feat_name}_rf_fold{fold_idx}.pkl"
            with rf_path.open("wb") as f:
                pickle.dump(rf_model, f)

            # Feature importance for RF
            rf_importance = rf_model.feature_importances_
            results[feat_name]["rf"]["importances"].append(rf_importance.tolist())

    # ------------------------------------------------------------------
    # Aggregate metrics and average importances
    # ------------------------------------------------------------------
    final_report: Dict[str, Any] = {}
    for feat_name, model_dict in results.items():
        final_report[feat_name] = {}
        for model_type, metrics in model_dict.items():
            r2_vals = metrics["r2"]
            rmse_vals = metrics["rmse"]
            # Average feature importance across folds
            if metrics["importances"]:
                avg_importance = np.mean(np.array(metrics["importances"]), axis=0).tolist()
            else:
                avg_importance = []

            final_report[feat_name][model_type] = {
                "r2_per_fold": [float(v) for v in r2_vals],
                "rmse_per_fold": [float(v) for v in rmse_vals],
                "r2_mean": float(np.mean(r2_vals)) if r2_vals else None,
                "r2_std": float(np.std(r2_vals)) if r2_vals else None,
                "rmse_mean": float(np.mean(rmse_vals)) if rmse_vals else None,
                "rmse_std": float(np.std(rmse_vals)) if rmse_vals else None,
                "feature_importance": avg_importance,
            }

    # ------------------------------------------------------------------
    # Write JSON report
    # ------------------------------------------------------------------
    report_path = REPORTS_DIR / "model_metrics.json"
    with report_path.open("w") as f:
        json.dump(final_report, f, indent=2)
    logger.info(f"Model‑performance report written to {report_path}")

    return final_report

# ----------------------------------------------------------------------
# Entry point
# ----------------------------------------------------------------------
def main() -> None:
    log_file = LOGS_DIR / "training.log"
    logger = setup_logging(log_file)
    logger.info("=== Baseline Model Training (Task T005) ===")
    start_time = time.time()
    try:
        run_model_training(logger)
        elapsed = time.time() - start_time
        logger.info(f"Training completed in {elapsed:.2f} seconds.")
    except Exception as exc:
        logger.exception(f"Training pipeline failed: {exc}")
        raise

if __name__ == "__main__":
    main()
