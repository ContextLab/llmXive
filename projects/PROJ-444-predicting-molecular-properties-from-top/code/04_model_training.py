"""
Model Training Pipeline (Task T005)
-----------------------------------
Trains Ridge Regression (alpha=1.0) and Random Forest (100 trees, max_depth=10,
seed=42) on three feature sets: traditional, topological, combined.
Uses the scaffold-based 5-fold split generated by T001 (data/processed/splits.json).
Enforces CPU-only execution (GPU guard checking /dev/nvidia* and nvidia-smi, FR-008).
Writes ``reports/metrics/model_metrics.json`` (plus a durable copy under
``data/results/``) and logs the run to ``data/logs/training.log``.

Root cause of the previous failure: ``combined_features.csv`` carries string
metadata columns (``target_property`` = 'logP', JSON ``features`` /
``feature_names`` blobs) that leaked into the "traditional" feature matrix and
crashed ``Ridge.fit`` with "could not convert string to float: 'logP'".
This version explicitly isolates numeric feature columns and coerces them.
"""

import glob
import json
import logging
import pickle
import random
import shutil
import subprocess
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.linear_model import Ridge
from sklearn.metrics import mean_squared_error, r2_score

# ----------------------------------------------------------------------
# Configuration constants
# ----------------------------------------------------------------------
SEED = 42
N_FOLDS = 5
LINEAR_ALPHA = 1.0
RF_TREES = 100
RF_MAX_DEPTH = 10

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = PROJECT_ROOT / "data"
MODELS_DIR = DATA_DIR / "models"
PROCESSED_DIR = DATA_DIR / "processed"
RESULTS_DIR = DATA_DIR / "results"
LOGS_DIR = DATA_DIR / "logs"
REPORTS_DIR = PROJECT_ROOT / "reports" / "metrics"

# Columns that are metadata (never features)
NON_FEATURE_COLUMNS = {
    "molecule_id",
    "smiles",
    "logP",
    "target_property",
    "target_value",
    "features",
    "feature_names",
    "scaffold",
    "_scaffold",
}

# ----------------------------------------------------------------------
# Logging
# ----------------------------------------------------------------------
def setup_logging(log_file: Optional[Path] = None) -> logging.Logger:
    """Configure a logger that writes to stdout and optionally to a file."""
    logger = logging.getLogger("model_training")
    logger.setLevel(logging.INFO)
    logger.propagate = False
    formatter = logging.Formatter("%(asctime)s - %(levelname)s - %(message)s")

    if not logger.handlers:
        sh = logging.StreamHandler(sys.stdout)
        sh.setFormatter(formatter)
        logger.addHandler(sh)

    if log_file is not None:
        log_file.parent.mkdir(parents=True, exist_ok=True)
        already = any(
            isinstance(h, logging.FileHandler)
            and Path(h.baseFilename) == log_file.resolve()
            for h in logger.handlers
        )
        if not already:
            fh = logging.FileHandler(log_file)
            fh.setFormatter(formatter)
            logger.addHandler(fh)
    return logger

# ----------------------------------------------------------------------
# GPU guard (FR-008) — dependency-free
# ----------------------------------------------------------------------
def check_gpu_disabled() -> None:
    """Abort if any GPU device is detected (FR-008).

    Checks, without third-party dependencies:
    * ``/dev/nvidia*`` device nodes
    * a runnable ``nvidia-smi`` binary
    * the ``CUDA_VISIBLE_DEVICES`` environment variable
    """
    if glob.glob("/dev/nvidia*"):
        raise SystemExit(
            "GPU device detected at /dev/nvidia* – aborting (FR-008, CPU-only)."
        )
    try:
        rc = subprocess.run(
            ["nvidia-smi"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            timeout=10,
        ).returncode
    except (FileNotFoundError, subprocess.TimeoutExpired):
        rc = 1
    if rc == 0:
        raise SystemExit(
            "nvidia-smi reported an available GPU – aborting (FR-008, CPU-only)."
        )
    if os_env_gpu := __import__("os").environ.get("CUDA_VISIBLE_DEVICES"):
        raise SystemExit(
            f"CUDA_VISIBLE_DEVICES={os_env_gpu} set – aborting (FR-008, CPU-only)."
        )

# ----------------------------------------------------------------------
# Feature-column isolation (root-cause fix)
# ----------------------------------------------------------------------
def select_feature_columns(df: pd.DataFrame) -> Tuple[List[str], List[str], List[str]]:
    """Return (all_feature_cols, topological_cols, traditional_cols).

    Only columns that are genuinely numeric are kept: metadata / string
    columns (``target_property``, JSON blobs, ids) are excluded and every
    retained column is coerced to float downstream.
    """
    candidate = [c for c in df.columns if c not in NON_FEATURE_COLUMNS]
    numeric_cols: List[str] = []
    for col in candidate:
        coerced = pd.to_numeric(df[col], errors="coerce")
        if coerced.notna().any():
            numeric_cols.append(col)
    tda_cols = [c for c in numeric_cols if c.startswith("pixel_")]
    trad_cols = [c for c in numeric_cols if c not in tda_cols]
    return numeric_cols, tda_cols, trad_cols

# ----------------------------------------------------------------------
# Model training
# ----------------------------------------------------------------------
def train_and_evaluate(
    X_train: np.ndarray,
    y_train: np.ndarray,
    X_test: np.ndarray,
    y_test: np.ndarray,
    model_type: str,
) -> Tuple[float, float, Any]:
    """Train Ridge (``linear``) or RandomForest (``rf``); return (R2, RMSE, model)."""
    if model_type == "linear":
        model = Ridge(alpha=LINEAR_ALPHA)
    elif model_type == "rf":
        model = RandomForestRegressor(
            n_estimators=RF_TREES,
            max_depth=RF_MAX_DEPTH,
            random_state=SEED,
            n_jobs=-1,
        )
    else:
        raise ValueError(f"Unsupported model_type: {model_type}")

    model.fit(X_train, y_train)
    preds = model.predict(X_test)
    r2 = float(r2_score(y_test, preds))
    rmse = float(np.sqrt(mean_squared_error(y_test, preds)))
    return r2, rmse, model

# ----------------------------------------------------------------------
# Split loading
# ----------------------------------------------------------------------
def load_splits(logger: logging.Logger) -> List[Tuple[np.ndarray, np.ndarray]]:
    """Load scaffold splits from data/processed/splits.json.

    Accepts the structure ``{"splits": [[train_idx, test_idx], ...]}`` or a
    list of ``{"train": [...], "test": [...]}`` dicts. Returns a list of
    (train_idx, test_idx) numpy arrays.
    """
    splits_path = PROCESSED_DIR / "splits.json"
    if not splits_path.is_file():
        raise FileNotFoundError(f"Missing {splits_path} – run T001 first.")
    with splits_path.open() as f:
        data = json.load(f)

    raw: List[Any]
    if isinstance(data, dict) and "splits" in data:
        raw = data["splits"]
    elif isinstance(data, dict) and "folds" in data:
        raw = data["folds"]
    elif isinstance(data, list):
        raw = data
    else:
        raise ValueError(f"Unrecognised splits.json structure with keys {list(data)}")

    splits: List[Tuple[np.ndarray, np.ndarray]] = []
    for i, entry in enumerate(raw):
        if isinstance(entry, (list, tuple)) and len(entry) == 2:
            train_idx, test_idx = entry
        elif isinstance(entry, dict):
            train_idx = entry.get("train", entry.get("train_idx"))
            test_idx = entry.get("test", entry.get("test_idx"))
        else:
            raise ValueError(f"Cannot parse fold {i} of splits.json")
        splits.append((np.asarray(train_idx, dtype=int), np.asarray(test_idx, dtype=int)))
    logger.info(
        f"Loaded {len(splits)} folds from {splits_path}; "
        f"fold test sizes: {[len(t) for _, t in splits]}"
    )
    return splits

# ----------------------------------------------------------------------
# Core training loop
# ----------------------------------------------------------------------
def run_model_training(logger: logging.Logger) -> Dict[str, Any]:
    """Execute the full training pipeline and write model_metrics.json."""
    check_gpu_disabled()
    random.seed(SEED)
    np.random.seed(SEED)

    for d in (MODELS_DIR, REPORTS_DIR, LOGS_DIR, RESULTS_DIR):
        d.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # Load data
    # ------------------------------------------------------------------
    features_path = PROCESSED_DIR / "combined_features.csv"
    if not features_path.is_file():
        raise FileNotFoundError(f"Missing {features_path} – run T004 first.")
    df = pd.read_csv(features_path, low_memory=False)
    df["molecule_id"] = df["molecule_id"].astype(str)
    logger.info(f"Loaded combined feature matrix: {df.shape[0]} rows x {df.shape[1]} cols")

    if "logP" not in df.columns:
        raise ValueError("Target column 'logP' not present in combined_features.csv")
    y = pd.to_numeric(df["logP"], errors="coerce")
    if y.isna().any():
        raise ValueError(
            f"{int(y.isna().sum())} non-numeric logP values – refusing to train."
        )
    y = y.values

    all_cols, tda_cols, trad_cols = select_feature_columns(df)
    feature_groups = {
        "traditional": trad_cols,
        "topological": tda_cols,
        "combined": all_cols,
    }
    logger.info(
        f"Feature column counts – Traditional: {len(trad_cols)}, "
        f"Topological: {len(tda_cols)}, Combined: {len(all_cols)}"
    )
    if not trad_cols or not tda_cols:
        raise ValueError("One of the feature groups is empty – cannot train.")

    splits = load_splits(logger)
    n = len(df)
    for tr, te in splits:
        if tr.max(initial=-1) >= n or te.max(initial=-1) >= n:
            raise ValueError("Split indices exceed combined_features.csv row count.")

    # ------------------------------------------------------------------
    # Train
    # ------------------------------------------------------------------
    results: Dict[str, Dict[str, Dict[str, Any]]] = {
        fg: {"linear": {"r2": [], "rmse": [], "importances": []},
             "rf": {"r2": [], "rmse": [], "importances": []}}
        for fg in feature_groups
    }

    for feat_name, cols in feature_groups.items():
        logger.info(f"Training on feature set '{feat_name}' ({len(cols)} columns).")
        X = df[cols].apply(pd.to_numeric, errors="coerce").astype(float).values
        if not np.isfinite(X).all():
            raise ValueError(f"Non-finite values in feature set '{feat_name}'.")

        for fold_idx, (train_idx, test_idx) in enumerate(splits):
            X_train, X_test = X[train_idx], X[test_idx]
            y_train, y_test = y[train_idx], y[test_idx]

            r2_lin, rmse_lin, lin_model = train_and_evaluate(
                X_train, y_train, X_test, y_test, "linear"
            )
            results[feat_name]["linear"]["r2"].append(r2_lin)
            results[feat_name]["linear"]["rmse"].append(rmse_lin)
            results[feat_name]["linear"]["importances"].append(
                np.abs(lin_model.coef_).tolist()
            )
            with (MODELS_DIR / f"{feat_name}_linear_fold{fold_idx}.pkl").open("wb") as f:
                pickle.dump(lin_model, f)

            r2_rf, rmse_rf, rf_model = train_and_evaluate(
                X_train, y_train, X_test, y_test, "rf"
            )
            results[feat_name]["rf"]["r2"].append(r2_rf)
            results[feat_name]["rf"]["rmse"].append(rmse_rf)
            results[feat_name]["rf"]["importances"].append(
                rf_model.feature_importances_.tolist()
            )
            with (MODELS_DIR / f"{feat_name}_rf_fold{fold_idx}.pkl").open("wb") as f:
                pickle.dump(rf_model, f)

            logger.info(
                f"  fold {fold_idx}: ridge R2={r2_lin:.4f} RMSE={rmse_lin:.4f} | "
                f"rf R2={r2_rf:.4f} RMSE={rmse_rf:.4f}"
            )

    # ------------------------------------------------------------------
    # Aggregate
    # ------------------------------------------------------------------
    final_report: Dict[str, Any] = {}
    for feat_name, model_dict in results.items():
        final_report[feat_name] = {}
        for model_type, metrics in model_dict.items():
            r2_vals, rmse_vals = metrics["r2"], metrics["rmse"]
            avg_imp = (
                np.mean(np.array(metrics["importances"]), axis=0).tolist()
                if metrics["importances"] else []
            )
            final_report[feat_name][model_type] = {
                "r2_per_fold": [float(v) for v in r2_vals],
                "rmse_per_fold": [float(v) for v in rmse_vals],
                "r2_mean": float(np.mean(r2_vals)),
                "r2_std": float(np.std(r2_vals)),
                "rmse_mean": float(np.mean(rmse_vals)),
                "rmse_std": float(np.std(rmse_vals)),
                "feature_importance": avg_imp,
            }

    # Top-level feature_importance block (per model_metrics contract):
    # importance vectors from the combined-feature RF model, split into the
    # traditional and topological descriptor positions.
    combined_rf_imp = final_report["combined"]["rf"]["feature_importance"]
    n_trad = len(feature_groups["traditional"])
    final_report["feature_importance"] = {
        "model": "random_forest_combined",
        "traditional": combined_rf_imp[:n_trad],
        "topological": combined_rf_imp[n_trad:],
        "traditional_feature_names": feature_groups["traditional"],
        "topological_feature_names": feature_groups["topological"],
    }
    final_report["metadata"] = {
        "seed": SEED,
        "n_folds": len(splits),
        "split_method": "scaffold_based_5fold",
        "target_property": "logP",
        "models": {
            "linear": {"type": "Ridge", "alpha": LINEAR_ALPHA},
            "rf": {"type": "RandomForestRegressor", "n_estimators": RF_TREES,
                   "max_depth": RF_MAX_DEPTH, "random_state": SEED},
        },
        "n_molecules": int(n),
        "n_traditional_features": int(n_trad),
        "n_topological_features": int(len(feature_groups["topological"])),
    }

    # ------------------------------------------------------------------
    # Write reports (canonical + durable copy outside gitignored caches)
    # ------------------------------------------------------------------
    report_path = REPORTS_DIR / "model_metrics.json"
    with report_path.open("w") as f:
        json.dump(final_report, f, indent=2)
    logger.info(f"Model-performance report written to {report_path}")

    durable_path = RESULTS_DIR / "model_metrics.json"
    with durable_path.open("w") as f:
        json.dump(final_report, f, indent=2)
    logger.info(f"Durable copy written to {durable_path}")

    return final_report

# ----------------------------------------------------------------------
# Entry point
# ----------------------------------------------------------------------
def main() -> None:
    log_file = LOGS_DIR / "training.log"
    logger = setup_logging(log_file)
    logger.info("=== Baseline Model Training (Task T005) ===")
    start_time = time.time()
    try:
        report = run_model_training(logger)
        elapsed = time.time() - start_time
        logger.info(f"Training completed in {elapsed:.2f} seconds.")
        for fg in ("traditional", "topological", "combined"):
            logger.info(
                f"  {fg}: ridge R2={report[fg]['linear']['r2_mean']:.4f}, "
                f"rf R2={report[fg]['rf']['r2_mean']:.4f}"
            )
    except Exception as exc:
        logger.exception(f"Training pipeline failed: {exc}")
        raise

if __name__ == "__main__":
    main()