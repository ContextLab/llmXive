"""
Task T031: Calculate Dataset Filtering Success Rate (SC-004).

This module calculates the ratio of retained sequences to total sequences
from the filtered dataset and writes the result to reconstruction_results.csv.
"""
import os
import csv
import logging
from pathlib import Path
from typing import Dict, Any, Optional

# Import config to handle paths
from config import get_path, load_config

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

def calculate_filtering_success_rate(filtered_csv_path: Path) -> Dict[str, Any]:
    """
    Reads the filtered sequences CSV to determine the number of retained sequences
    and calculates the success rate against the total unique sequences processed.
    
    Since the input is the *filtered* output, we must deduplicate by sequence_id
    to get the count of retained sequences.
    
    To calculate the *rate* (retained/total), we need the total count of sequences
    that were fed into the filter.
    
    However, T031 specifically asks to "Calculate Dataset Filtering Success Rate".
    In the context of the pipeline:
    1. T007/T008 loads the raw dataset.
    2. T009 filters it.
    3. T011 writes the filtered CSV.
    
    The filtered CSV only contains retained items. Without the raw count explicitly
    stored in a separate metadata file (which isn't in the artifact list), we have
    two options:
    a) Assume the 'randomized_depth' or other columns imply the original set if it was synthetic.
    b) Look for a metadata file generated by T007/T008.
    c) Re-read the raw zip if available to count total sequences.
    
    Given the strict constraints and the fact that T007 generates the raw zip:
    We will attempt to read the raw zip (if it exists) to count total unique sequence_ids,
    and compare against the unique sequence_ids in the filtered CSV.
    
    If the raw zip is missing (e.g., run in isolation), we will fall back to
    reading the filtered CSV and logging that the denominator is unknown (or 1.0 if
    we assume all input was retained, but that's unsafe).
    
    Actually, looking at T007/T008/T009 flow:
    T009 filters based on heuristics.
    If we can't access the raw source, we cannot calculate a true rate.
    
    However, T007's output schema mentions `randomized_depth`.
    Let's assume the standard behavior for this task:
    1. Load `data/processed/filtered_sequences.csv`.
    2. Count unique `sequence_id` -> `retained_count`.
    3. If `data/raw/omnidirector.zip` or `data/raw/synthetic_omnidirector.zip` exists,
       count unique sequences there -> `total_count`.
    4. Calculate rate.
    
    If raw data is missing, we cannot compute the rate accurately. We will raise an error
    or log a warning and set rate to -1.0 to indicate missing context, as per "Fail loudly".
    """
    
    if not filtered_csv_path.exists():
        raise FileNotFoundError(f"Filtered CSV not found at {filtered_csv_path}")
    
    # Count retained sequences from the filtered file
    retained_sequences = set()
    with open(filtered_csv_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            retained_sequences.add(row['sequence_id'])
    
    retained_count = len(retained_sequences)
    
    if retained_count == 0:
        logger.warning("No retained sequences found in filtered CSV.")
        return {
            "retained_count": 0,
            "total_count": 0,
            "success_rate": 0.0,
            "note": "No retained sequences"
        }

    # Attempt to find the raw source to determine total count
    raw_zip_path = get_path("raw_omnidirector_zip")
    if not raw_zip_path.exists():
        # Check for synthetic fallback
        synthetic_path = get_path("synthetic_omnidirector_zip")
        if synthetic_path.exists():
            raw_zip_path = synthetic_path
        else:
            # If we can't find the source, we can't calculate the rate.
            # We return what we have but flag it.
            logger.warning(
                f"Raw dataset zip not found at {get_path('raw_omnidirector_zip')} "
                f"or {get_path('synthetic_omnidirector_zip')}. "
                "Cannot calculate total sequence count for success rate. "
                "Setting success_rate to -1.0 to indicate missing context."
            )
            return {
                "retained_count": retained_count,
                "total_count": 0,
                "success_rate": -1.0,
                "note": "Raw source missing; rate indeterminate"
            }
    
    # Count total sequences from the raw zip
    # The raw zip contains the same schema as the filtered one (before filtering)
    # We need to iterate the CSV inside the zip.
    import zipfile
    import io
    
    total_sequences = set()
    try:
        with zipfile.ZipFile(raw_zip_path, 'r') as z:
            # Find the CSV file inside the zip
            csv_files = [f for f in z.namelist() if f.endswith('.csv')]
            if not csv_files:
                raise ValueError("No CSV file found inside the raw dataset zip.")
            
            csv_filename = csv_files[0]
            with z.open(csv_filename) as csv_file:
                # Decode bytes to string for csv.reader
                text_stream = io.TextIOWrapper(csv_file, encoding='utf-8')
                reader = csv.DictReader(text_stream)
                for row in reader:
                    total_sequences.add(row['sequence_id'])
                    
        total_count = len(total_sequences)
        
        if total_count == 0:
            logger.warning("Raw dataset contains 0 sequences.")
            success_rate = 0.0
        else:
            success_rate = retained_count / total_count
            
        return {
            "retained_count": retained_count,
            "total_count": total_count,
            "success_rate": success_rate,
            "note": "Calculated successfully"
        }
        
    except Exception as e:
        logger.error(f"Failed to read raw dataset zip: {e}")
        return {
            "retained_count": retained_count,
            "total_count": 0,
            "success_rate": -1.0,
            "note": f"Error reading raw source: {str(e)}"
        }

def write_reconstruction_results(results: Dict[str, Any], output_path: Path) -> None:
    """
    Writes the calculated metrics to the reconstruction_results.csv file.
    Format: metric_name, value, note
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow(["metric_name", "value", "note"])
        
        writer.writerow(["filtering_success_rate", results["success_rate"], results["note"]])
        writer.writerow(["retained_sequence_count", results["retained_count"], ""])
        writer.writerow(["total_sequence_count", results["total_count"], ""])

def main():
    """
    Entry point for T031.
    1. Locate filtered_sequences.csv (from T011).
    2. Locate raw dataset zip (from T007).
    3. Calculate success rate.
    4. Write to data/processed/reconstruction_results.csv.
    """
    config = load_config()
    filtered_csv = get_path("filtered_sequences_csv")
    output_csv = get_path("reconstruction_results_csv")
    
    logger.info(f"Starting T031: Calculating filtering success rate.")
    logger.info(f"Input: {filtered_csv}")
    logger.info(f"Output: {output_csv}")
    
    results = calculate_filtering_success_rate(filtered_csv)
    
    write_reconstruction_results(results, output_csv)
    
    logger.info(f"T031 Complete. Success Rate: {results['success_rate']}")
    print(f"T031 Results written to {output_csv}")
    print(f"  Retained: {results['retained_count']}")
    print(f"  Total: {results['total_count']}")
    print(f"  Rate: {results['success_rate']}")

if __name__ == "__main__":
    main()