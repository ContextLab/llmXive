import os
import json
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional

import numpy as np

from config import get_path, load_config
from geometry.reconstruction import process_poses_for_reconstruction, calculate_box_dimensions
from geometry.solver import process_filtered_sequences

logger = logging.getLogger(__name__)

def load_poses_from_solver_results(poses_file_path: Optional[str] = None) -> List[Dict[str, Any]]:
    """
    Loads the raw pose estimates generated by the solver (T017).
    In the current pipeline architecture, the solver writes intermediate results
    or we assume the solver process has been run and we are aggregating the data.
    
    Since T017 (solver) is marked as completed in the task list but T019 is the
    writer, we assume the solver has produced a JSON or we process the filtered
    sequences and run the solver logic here to generate the estimates if not present.
    
    However, to strictly follow the "Write pose estimates" task, we will:
    1. Check if a solver output exists (if T017 wrote one).
    2. If not, we re-run the solver logic on the filtered sequences to generate the estimates.
    
    For this implementation, we assume the `process_filtered_sequences` from solver.py
    returns the list of pose estimates directly or writes them to an intermediate file.
    Given the API surface, `process_filtered_sequences` in `code/geometry/solver.py`
    is the entry point.
    
    We will call `process_filtered_sequences` to get the data, then enrich it with
    reconstructed box dimensions from `reconstruction.py`.
    """
    config = load_config()
    filtered_csv_path = get_path("filtered_sequences_csv", config)
    
    if not os.path.exists(filtered_csv_path):
        raise FileNotFoundError(f"Required input file not found: {filtered_csv_path}. "
                                "Ensure T011 (filtered_sequences.csv) is completed.")
    
    logger.info(f"Loading filtered sequences from {filtered_csv_path}")
    
    # Run the solver logic to get pose estimates
    # This function is expected to return a list of dictionaries containing
    # sequence_id, frame_id, estimated R, t, and other metadata.
    try:
        pose_estimates = process_filtered_sequences(filtered_csv_path)
    except Exception as e:
        logger.error(f"Failed to process sequences for pose estimation: {e}")
        raise
    
    return pose_estimates

def enrich_poses_with_boxes(pose_estimates: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Enriches the pose estimates with reconstructed bounding box dimensions.
    Uses the logic from code/geometry/reconstruction.py.
    """
    logger.info("Enriching pose estimates with reconstructed box dimensions...")
    
    # The reconstruction module expects a list of poses or processes them in sequence.
    # We pass the pose estimates to the reconstruction function.
    # process_poses_for_reconstruction returns the enriched data or a new list.
    enriched_data = process_poses_for_reconstruction(pose_estimates)
    
    return enriched_data

def write_poses_estimated_json(enriched_poses: List[Dict[str, Any]], output_path: Optional[str] = None) -> str:
    """
    Writes the final enriched pose estimates and reconstructed boxes to a JSON file.
    Output: data/processed/poses_estimated.json
    """
    config = load_config()
    if output_path is None:
        output_path = get_path("poses_estimated_json", config)
    
    output_dir = os.path.dirname(output_path)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)
    
    logger.info(f"Writing {len(enriched_poses)} pose estimates to {output_path}")
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(enriched_poses, f, indent=2, default=str)
    
    logger.info(f"Successfully wrote poses_estimated.json to {output_path}")
    return output_path

def main():
    """
    Main entry point for T019: Write pose estimates and reconstructed boxes.
    """
    logging.basicConfig(level=logging.INFO)
    
    try:
        # 1. Load/Generate Pose Estimates from Solver
        # We call the solver's processing function to get the raw estimates.
        # Note: In a real pipeline, T017 might have written an intermediate file.
        # Here we invoke the logic directly to ensure data flow.
        pose_estimates = load_poses_from_solver_results()
        
        if not pose_estimates:
            logger.warning("No pose estimates generated. The output file will be empty.")
        
        # 2. Enrich with Reconstructed Box Dimensions
        enriched_poses = enrich_poses_with_boxes(pose_estimates)
        
        # 3. Write to JSON
        output_file = write_poses_estimated_json(enriched_poses)
        
        logger.info(f"Task T019 completed. Output: {output_file}")
        
    except FileNotFoundError as e:
        logger.error(f"Missing required input data: {e}")
        raise
    except Exception as e:
        logger.error(f"Error during pose estimation and writing: {e}")
        raise

if __name__ == "__main__":
    main()
