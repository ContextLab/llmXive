def procrustes_align(target: np.ndarray, source: np.ndarray) -> np.ndarray:
    """
    Aligns source eigenfunctions to target using Orthogonal Procrustes analysis.
    target: (n_components, n_timepoints)
    source: (n_components, n_timepoints)
    Returns: aligned source
    """
    # Procrustes expects (n, m) where n is observations. Here components are rows.
    # We want to rotate 'source' to match 'target'.
    # scipy.linalg.orthogonal_procrustes solves min ||A - RB||_F
    # A=target, B=source -> find R such that target ~ R * source
    # But usually eigenfunctions are compared component-wise or as a subspace.
    # For simplicity and stability, we align the subspace spanned by the top K components.
    
    if target.shape != source.shape:
        raise ValueError(f"Shape mismatch for Procrustes: target {target.shape} vs source {source.shape}")
    
    # Transpose to (n_timepoints, n_components) for standard Procrustes if needed,
    # but scipy handles (m, n). Let's treat rows as variables (timepoints) and cols as components.
    # Actually, standard PCA comparison aligns the matrix of loadings.
    
    R, _ = orthogonal_procrustes(target.T, source.T)
    aligned = source @ R
    return aligned

def calculate_stability_metrics(full_results: Dict[str, Any], loo_results: List[Dict[str, Any]]) -> List[float]:
    """
    Calculates stability metrics (correlations) between full and LOO eigenfunctions.
    Returns a list of mean correlations per LOO iteration.
    """
    correlations_per_run = []
    
    full_eigenfunctions = full_results.get('eigenfunctions') # (n_components, n_timepoints)
    
    if full_eigenfunctions is None:
        raise ValueError("Full FPCA results missing eigenfunctions.")

    for i, loo_run in enumerate(loo_results):
        loo_eigenfunctions = loo_run.get('eigenfunctions')
        if loo_eigenfunctions is None:
            logger.warning(f"LOO run {i} missing eigenfunctions.")
            correlations_per_run.append(0.0)
            continue

        # Align LOO eigenfunctions to full
        try:
            aligned_loo = procrustes_align(full_eigenfunctions, loo_eigenfunctions)
        except Exception as e:
            logger.warning(f"Procrustes alignment failed for run {i}: {e}. Using raw correlation.")
            aligned_loo = loo_eigenfunctions

        # Calculate correlation for each component
        run_correlations = []
        n_comp = min(full_eigenfunctions.shape[0], aligned_loo.shape[0])
        
        for k in range(n_comp):
            f_vec = full_eigenfunctions[k].flatten()
            l_vec = aligned_loo[k].flatten()
            
            # Normalize
            f_vec = f_vec / (np.linalg.norm(f_vec) + 1e-8)
            l_vec = l_vec / (np.linalg.norm(l_vec) + 1e-8)
            
            corr = np.dot(f_vec, l_vec)
            run_correlations.append(float(corr))

        mean_corr = np.mean(run_correlations) if run_correlations else 0.0
        correlations_per_run.append(mean_corr)
        
        logger.debug(f"LOO Run {i} (removed: {loo_run.get('removed_model', 'unknown')}): Mean Correlation = {mean_corr:.4f}")

    return correlations_per_run

