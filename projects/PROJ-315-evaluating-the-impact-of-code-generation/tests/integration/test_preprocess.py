import pytest
import pandas as pd
import json
from pathlib import Path
import sys
import os

# Add code to path
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', '..'))

from code.data.preprocess import (
    load_keywords, 
    filter_nulls, 
    check_completeness, 
    check_power_insufficiency, 
    compute_basic_stats,
    write_stats_report
)

class TestPreprocessIntegration:
    
    @pytest.fixture
    def sample_data(self):
        """Create a sample DataFrame for testing."""
        data = {
            'commit_message': [
                'Fix bug', 
                'Generated by Copilot', 
                'AI code update', 
                'Refactor module', 
                'Copilot generated',
                None, 
                'Another fix',
                'LLM generated code'
            ],
            'diff': ['diff1', 'diff2', 'diff3', 'diff4', 'diff5', None, 'diff7', 'diff8'],
            'review_comments': [1, 2, 3, 4, 5, 6, 7, 8],
            'merge_timestamp': ['2023-01-01'] * 8,
            'project_name': ['proj'] * 8
        }
        return pd.DataFrame(data)

    @pytest.fixture
    def keywords(self):
        return ['copilot', 'ai code', 'generated by llm']

    def test_filter_nulls(self, sample_data):
        """Test that filter_nulls removes rows with null values in required columns."""
        required_cols = ['commit_message', 'diff']
        df_filtered, orig, filt = filter_nulls(sample_data, required_cols)
        
        assert orig == 8
        assert filt == 6  # 2 rows have nulls
        assert df_filtered['commit_message'].isnull().sum() == 0
        assert df_filtered['diff'].isnull().sum() == 0

    def test_check_completeness_pass(self, sample_data):
        """Test completeness check passes when >95%."""
        # Filter first to ensure we have clean data for this test
        df_clean, _, _ = filter_nulls(sample_data, ['commit_message', 'diff'])
        # 100% complete
        assert check_completeness(df_clean, ['commit_message', 'diff'], threshold=0.95) is True

    def test_check_completeness_fail(self, sample_data):
        """Test completeness check fails when <95%."""
        # Create data with low completeness
        data = {
            'col1': [1, 2, None, None, None], # 60% complete
            'col2': [1, 2, 3, 4, 5]
        }
        df = pd.DataFrame(data)
        assert check_completeness(df, ['col1', 'col2'], threshold=0.95) is False

    def test_check_power_insufficiency_pass(self, sample_data):
        """Test power check passes when groups >= 500 (simulated with smaller threshold for test)."""
        # Create data with enough samples
        large_data = pd.DataFrame({
            'label': ['A'] * 500 + ['B'] * 500,
            'val': range(1000)
        })
        assert check_power_insufficiency(large_data, 'label', min_group_size=500) is True

    def test_check_power_insufficiency_fail(self, sample_data):
        """Test power check fails when group < 500."""
        small_data = pd.DataFrame({
            'label': ['A'] * 100 + ['B'] * 500, # A is too small
            'val': range(600)
        })
        assert check_power_insufficiency(small_data, 'label', min_group_size=500) is False

    def test_compute_basic_stats(self, sample_data):
        """Test basic stats computation."""
        df_clean, _, _ = filter_nulls(sample_data, ['commit_message', 'diff'])
        stats = compute_basic_stats(df_clean)
        
        assert 'total_records' in stats
        assert stats['total_records'] == 6
        assert 'columns' in stats
        assert 'numeric_summary' in stats # review_comments is numeric

    def test_write_stats_report(self, sample_data, tmp_path):
        """Test writing stats report to file."""
        df_clean, _, _ = filter_nulls(sample_data, ['commit_message', 'diff'])
        stats = compute_basic_stats(df_clean)
        output_file = tmp_path / "test_stats.json"
        
        write_stats_report(stats, str(output_file))
        
        assert output_file.exists()
        with open(output_file, 'r') as f:
            loaded = json.load(f)
        assert loaded['total_records'] == 6