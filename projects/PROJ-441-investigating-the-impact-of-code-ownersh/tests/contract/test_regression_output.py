"""
Contract test for regression output schema (T023).

This test validates that the Linear Mixed-Effects Model (LMM) output
generated by `code/analysis/regression.py` adheres to the strict schema
required by the research plan. It ensures:
1. The output is a valid JSON object.
2. Required top-level keys exist ('summary', 'coefficients', 'model_info').
3. The 'coefficients' list contains dictionaries with specific fields
   (term, estimate, std_error, t_value, p_value) for every predictor.
4. The 'p_value' is a float between 0 and 1.
5. The 'summary' contains the Likelihood Ratio Test result and VIF scores.
"""
import json
import math
from pathlib import Path
from typing import Any, Dict, List

import pytest


# Expected schema constants
REQUIRED_TOP_LEVEL_KEYS = {"summary", "coefficients", "model_info", "sensitivity_analysis"}
REQUIRED_COEFFICIENT_KEYS = {"term", "estimate", "std_error", "t_value", "p_value"}
REQUIRED_MODEL_INFO_KEYS = {"formula", "n_obs", "n_groups", "random_effects", "converged"}
REQUIRED_SUMMARY_KEYS = {"lmm_log_likelihood", "likelihood_ratio_test", "vif_scores", "ownership_significant"}


def load_regression_output() -> Dict[str, Any]:
    """
    Loads the regression output JSON file.
    Raises FileNotFoundError if the file does not exist (fail loud).
    Raises json.JSONDecodeError if the file is not valid JSON.
    """
    output_path = Path("data/results/regression_results.json")
    if not output_path.exists():
        raise FileNotFoundError(
            f"Regression output file not found at {output_path}. "
            "Ensure `code/analysis/regression.py` has been executed to generate this file."
        )
    
    with open(output_path, "r", encoding="utf-8") as f:
        return json.load(f)


def test_regression_output_file_exists_and_is_valid_json():
    """Contract: Output file must exist and be valid JSON."""
    try:
        data = load_regression_output()
        assert isinstance(data, dict), "Root element must be a JSON object."
    except (FileNotFoundError, json.JSONDecodeError) as e:
        pytest.fail(f"Regression output failed schema check: {e}")


def test_regression_output_has_required_top_level_keys():
    """Contract: Output must contain summary, coefficients, model_info, and sensitivity_analysis."""
    data = load_regression_output()
    missing_keys = REQUIRED_TOP_LEVEL_KEYS - set(data.keys())
    assert not missing_keys, f"Missing required top-level keys: {missing_keys}"


def test_regression_output_model_info_structure():
    """Contract: model_info must contain formula, n_obs, n_groups, random_effects, converged."""
    data = load_regression_output()
    model_info = data.get("model_info", {})
    
    missing_keys = REQUIRED_MODEL_INFO_KEYS - set(model_info.keys())
    assert not missing_keys, f"model_info missing keys: {missing_keys}"
    
    # Type checks for model_info
    assert isinstance(model_info.get("formula"), str), "formula must be a string"
    assert isinstance(model_info.get("n_obs"), int), "n_obs must be an integer"
    assert isinstance(model_info.get("n_groups"), int), "n_groups must be an integer"
    assert isinstance(model_info.get("converged"), bool), "converged must be a boolean"
    assert isinstance(model_info.get("random_effects"), list), "random_effects must be a list"


def test_regression_output_coefficients_structure():
    """Contract: coefficients must be a list of dicts with specific numeric fields."""
    data = load_regression_output()
    coefficients = data.get("coefficients", [])
    
    assert isinstance(coefficients, list), "coefficients must be a list"
    assert len(coefficients) > 0, "coefficients list cannot be empty"
    
    for i, coef in enumerate(coefficients):
        assert isinstance(coef, dict), f"Coefficient at index {i} must be a dict"
        
        missing_keys = REQUIRED_COEFFICIENT_KEYS - set(coef.keys())
        assert not missing_keys, f"Coefficient at index {i} missing keys: {missing_keys}"
        
        # Type and range checks
        assert isinstance(coef["term"], str), "term must be a string"
        assert isinstance(coef["estimate"], (int, float)), "estimate must be numeric"
        assert isinstance(coef["std_error"], (int, float)), "std_error must be numeric"
        assert isinstance(coef["t_value"], (int, float)), "t_value must be numeric"
        assert isinstance(coef["p_value"], (int, float)), "p_value must be numeric"
        
        # P-value range constraint [0, 1]
        if not (0.0 <= coef["p_value"] <= 1.0):
            pytest.fail(f"P-value for term '{coef['term']}' is out of bounds: {coef['p_value']}")


def test_regression_output_summary_structure():
    """Contract: summary must contain LMM stats, LRT, VIF, and significance flag."""
    data = load_regression_output()
    summary = data.get("summary", {})
    
    missing_keys = REQUIRED_SUMMARY_KEYS - set(summary.keys())
    assert not missing_keys, f"summary missing keys: {missing_keys}"
    
    # Type checks
    assert isinstance(summary.get("lmm_log_likelihood"), (int, float)), "lmm_log_likelihood must be numeric"
    assert isinstance(summary.get("likelihood_ratio_test"), dict), "likelihood_ratio_test must be a dict"
    assert isinstance(summary.get("vif_scores"), dict), "vif_scores must be a dict"
    assert isinstance(summary.get("ownership_significant"), bool), "ownership_significant must be a boolean"
    
    # Check LRT structure
    lrt = summary.get("likelihood_ratio_test", {})
    assert "chi2_stat" in lrt, "likelihood_ratio_test missing chi2_stat"
    assert "p_value" in lrt, "likelihood_ratio_test missing p_value"
    assert "linear_vs_nonlinear" in lrt, "likelihood_ratio_test missing linear_vs_nonlinear"


def test_regression_output_sensitivity_analysis_structure():
    """Contract: sensitivity_analysis must exist and contain window sweep results."""
    data = load_regression_output()
    sensitivity = data.get("sensitivity_analysis", {})
    
    assert isinstance(sensitivity, dict), "sensitivity_analysis must be a dict"
    assert "windows_tested" in sensitivity, "sensitivity_analysis missing windows_tested"
    assert "coefficient_stability" in sensitivity, "sensitivity_analysis missing coefficient_stability"
    
    windows = sensitivity["windows_tested"]
    assert isinstance(windows, list), "windows_tested must be a list"
    assert len(windows) > 0, "windows_tested cannot be empty"
    
    for w in windows:
        assert isinstance(w, dict), "Each window entry must be a dict"
        assert "window_size" in w, "window entry missing window_size"
        assert "ownership_coefficient" in w, "window entry missing ownership_coefficient"
        assert "p_value" in w, "window entry missing p_value"


def test_regression_output_ownership_term_exists():
    """Contract: There must be a coefficient entry for the ownership metric (Gini)."""
    data = load_regression_output()
    coefficients = data.get("coefficients", [])
    
    ownership_terms = [c for c in coefficients if "gini" in c["term"].lower()]
    assert len(ownership_terms) > 0, "No coefficient found for ownership metric (Gini)"


if __name__ == "__main__":
    pytest.main([__file__, "-v"])