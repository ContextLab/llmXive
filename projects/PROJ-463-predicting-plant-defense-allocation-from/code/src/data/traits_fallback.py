"""
Fallback trait data acquisition from Phenoscape and GBIF.

This module implements the secondary data acquisition strategy for defense traits
when the primary TRY database source is unavailable or incomplete.

Sources:
- Phenoscape: KB ontology and trait data for biological entities
- GBIF: Occurrence and trait data from global biodiversity network
"""

import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, List, Any, Optional
import requests
from requests.adapters import HTTPAdapter
from urllib3.util.retry import Retry

# Project imports
from src.utils.logger import get_logger
from src.utils.config import get_data_path
from src.data.traits_cache import cache_raw_response

# Configure logger
logger = get_logger(__name__)

# Constants
PHENOSCAPE_API_BASE = "https://api.phenoscape.org/v3"
GBIF_API_BASE = "https://api.gbif.org/v2"
TIMEOUT_SECONDS = 30
MAX_RETRIES = 3


def create_retry_session() -> requests.Session:
    """Create a requests session with retry logic."""
    session = requests.Session()
    retry = Retry(
        total=MAX_RETRIES,
        backoff_factor=1,
        status_forcelist=[429, 500, 502, 503, 504],
        allowed_methods=["GET", "POST"]
    )
    adapter = HTTPAdapter(max_retries=retry)
    session.mount("http://", adapter)
    session.mount("https://", adapter)
    return session


def load_fallback_input() -> Dict[str, Any]:
    """
    Load the input data for fallback processing.

    Reads:
    1. Target species list from post_qc_species_list.json
    2. Missing species list from trait_fallback_summary.json (generated by T025a)

    Returns:
        Dict containing target_species and missing_from_try lists
    """
    data_path = get_data_path()
    qc_path = data_path / "processed" / "post_qc_species_list.json"
    summary_path = data_path / "processed" / "trait_fallback_summary.json"

    # Load target species list
    if not qc_path.exists():
        raise FileNotFoundError(f"Target species list not found: {qc_path}")

    with open(qc_path, 'r') as f:
        qc_data = json.load(f)

    target_species = qc_data.get("species", [])
    if not target_species:
        logger.warning("No target species found in post_qc_species_list.json")
        target_species = []

    # Load existing summary to get missing_from_try list
    missing_from_try = []
    if summary_path.exists():
        with open(summary_path, 'r') as f:
            summary_data = json.load(f)
            missing_from_try = summary_data.get("missing_from_try", [])
            logger.info(f"Loaded {len(missing_from_try)} species missing from TRY")
    else:
        logger.warning(f"Summary file not found: {summary_path}. Using all target species as missing.")
        missing_from_try = target_species

    return {
        "target_species": target_species,
        "missing_from_try": missing_from_try
    }


def fetch_traits_from_phenoscape(species_name: str, session: requests.Session) -> Optional[Dict[str, Any]]:
    """
    Fetch trait data from Phenoscape API.

    Phenoscape provides trait data linked to biological entities using ontologies.
    We query for traits associated with the given species name.

    Args:
        species_name: Scientific name of the species (e.g., "Arabidopsis thaliana")
        session: Requests session with retry logic

    Returns:
        Dict containing trait data if found, None otherwise
    """
    try:
        # Normalize species name for API query
        # Phenoscape uses taxon IDs, so we first need to resolve the name
        taxon_search_url = f"{PHENOSCAPE_API_BASE}/taxon/search"
        params = {"query": species_name}

        logger.debug(f"Searching Phenoscape for taxon: {species_name}")
        response = session.get(taxon_search_url, params=params, timeout=TIMEOUT_SECONDS)

        if response.status_code != 200:
            logger.debug(f"Phenoscape taxon search failed for {species_name}: {response.status_code}")
            return None

        taxon_data = response.json()
        if not taxon_data or "results" not in taxon_data or len(taxon_data["results"]) == 0:
            logger.debug(f"No taxon found for {species_name} in Phenoscape")
            return None

        # Use the first matching taxon ID
        taxon_id = taxon_data["results"][0].get("id")
        if not taxon_id:
            return None

        # Fetch traits for this taxon
        traits_url = f"{PHENOSCAPE_API_BASE}/entities/taxon/{taxon_id}/traits"
        response = session.get(traits_url, timeout=TIMEOUT_SECONDS)

        if response.status_code != 200:
            logger.debug(f"Phenoscape traits fetch failed for {species_name}: {response.status_code}")
            return None

        traits_data = response.json()

        # Cache the raw response
        cache_raw_response("phenoscape", species_name, traits_data)

        # Process and extract relevant traits
        processed_traits = []
        if "results" in traits_data:
            for trait_entry in traits_data["results"]:
                trait_info = {
                    "source": "phenoscape",
                    "trait_id": trait_entry.get("id"),
                    "trait_label": trait_entry.get("label"),
                    "value": trait_entry.get("value"),
                    "unit": trait_entry.get("unit", {}).get("label") if "unit" in trait_entry else None,
                    "evidence": trait_entry.get("evidence", [])
                }
                processed_traits.append(trait_info)

        if processed_traits:
            logger.info(f"Found {len(processed_traits)} traits for {species_name} in Phenoscape")
            return {
                "species": species_name,
                "source": "phenoscape",
                "traits": processed_traits,
                "found": True
            }
        else:
            logger.debug(f"No traits found for {species_name} in Phenoscape")
            return None

    except requests.exceptions.RequestException as e:
        logger.warning(f"Phenoscape request failed for {species_name}: {e}")
        return None
    except Exception as e:
        logger.error(f"Unexpected error fetching from Phenoscape for {species_name}: {e}")
        return None


def fetch_traits_from_gbif(species_name: str, session: requests.Session) -> Optional[Dict[str, Any]]:
    """
    Fetch trait data from GBIF API.

    GBIF provides occurrence data and some trait information. We query for
    traits associated with the given species.

    Args:
        species_name: Scientific name of the species
        session: Requests session with retry logic

    Returns:
        Dict containing trait data if found, None otherwise
    """
    try:
        # GBIF uses a species key, so we first search for the species
        search_url = f"{GBIF_API_BASE}/species/search"
        params = {
            "q": species_name,
            "limit": 1
        }

        logger.debug(f"Searching GBIF for species: {species_name}")
        response = session.get(search_url, params=params, timeout=TIMEOUT_SECONDS)

        if response.status_code != 200:
            logger.debug(f"GBIF species search failed for {species_name}: {response.status_code}")
            return None

        search_data = response.json()
        if not search_data or "results" not in search_data or len(search_data["results"]) == 0:
            logger.debug(f"No species found for {species_name} in GBIF")
            return None

        species_key = search_data["results"][0].get("key")
        if not species_key:
            return None

        # Fetch traits for this species
        # GBIF trait endpoint: /species/{key}/traits
        traits_url = f"{GBIF_API_BASE}/species/{species_key}/traits"
        response = session.get(traits_url, timeout=TIMEOUT_SECONDS)

        if response.status_code != 200:
            logger.debug(f"GBIF traits fetch failed for {species_name}: {response.status_code}")
            return None

        traits_data = response.json()

        # Cache the raw response
        cache_raw_response("gbif", species_name, traits_data)

        # Process and extract relevant traits
        processed_traits = []
        if "results" in traits_data:
            for trait_entry in traits_data["results"]:
                trait_info = {
                    "source": "gbif",
                    "trait_id": trait_entry.get("traitId"),
                    "trait_label": trait_entry.get("traitLabel"),
                    "value": trait_entry.get("value"),
                    "unit": trait_entry.get("unit"),
                    "method": trait_entry.get("method")
                }
                processed_traits.append(trait_info)

        if processed_traits:
            logger.info(f"Found {len(processed_traits)} traits for {species_name} in GBIF")
            return {
                "species": species_name,
                "source": "gbif",
                "traits": processed_traits,
                "found": True
            }
        else:
            logger.debug(f"No traits found for {species_name} in GBIF")
            return None

    except requests.exceptions.RequestException as e:
        logger.warning(f"GBIF request failed for {species_name}: {e}")
        return None
    except Exception as e:
        logger.error(f"Unexpected error fetching from GBIF for {species_name}: {e}")
        return None


def fetch_traits_for_species(species_name: str, session: requests.Session) -> Optional[Dict[str, Any]]:
    """
    Attempt to fetch traits for a species from all fallback sources.

    Tries Phenoscape first, then GBIF if Phenoscape fails.

    Args:
        species_name: Scientific name of the species
        session: Requests session with retry logic

    Returns:
        Dict containing trait data from the first successful source, or None
    """
    logger.info(f"Fetching fallback traits for: {species_name}")

    # Try Phenoscape first
    result = fetch_traits_from_phenoscape(species_name, session)
    if result and result.get("found"):
        return result

    # Try GBIF if Phenoscape failed
    result = fetch_traits_from_gbif(species_name, session)
    if result and result.get("found"):
        return result

    logger.warning(f"All fallback sources failed for {species_name}")
    return None


def save_trait_fallback_summary(
    summary_path: Path,
    target_species: List[str],
    fallback_results: List[Dict[str, Any]],
    previously_missing: List[str]
) -> None:
    """
    Save the updated trait fallback summary.

    Args:
        summary_path: Path to the output JSON file
        target_species: List of all target species
        fallback_results: List of successful fallback results
        previously_missing: List of species missing from TRY
    """
    # Build set of species found via fallback
    found_species = {r["species"] for r in fallback_results}

    # Update the missing list: species that were missing from TRY AND not found in fallback
    still_missing = [s for s in previously_missing if s not in found_species]

    # Construct the summary
    summary = {
        "target_species": target_species,
        "primary_source_results": {},  # Empty as we only have fallback here
        "missing_from_try": previously_missing,
        "missing_from_all_sources": still_missing,
        "fallback_results": fallback_results,
        "fallback_summary": {
            "total_fallback_attempts": len(previously_missing),
            "successful_fallbacks": len(fallback_results),
            "still_missing": len(still_missing)
        }
    }

    # Ensure directory exists
    summary_path.parent.mkdir(parents=True, exist_ok=True)

    with open(summary_path, 'w') as f:
        json.dump(summary, f, indent=2)

    logger.info(f"Saved fallback summary to {summary_path}")
    logger.info(f"  - Successfully retrieved traits for {len(fallback_results)} species via fallback")
    logger.info(f"  - Still missing from all sources: {len(still_missing)} species")


def main() -> int:
    """
    Main entry point for the fallback trait data acquisition.

    Returns:
        0 on success, 1 on error
    """
    logger.info("Starting fallback trait data acquisition (T025b)")

    try:
        # Load input data
        input_data = load_fallback_input()
        target_species = input_data["target_species"]
        missing_from_try = input_data["missing_from_try"]

        if not missing_from_try:
            logger.info("No species missing from TRY. Skipping fallback.")
            return 0

        logger.info(f"Processing {len(missing_from_try)} species missing from TRY")

        # Create session with retry logic
        session = create_retry_session()

        # Fetch traits for each missing species
        fallback_results = []
        for species in missing_from_try:
            result = fetch_traits_for_species(species, session)
            if result:
                fallback_results.append(result)

        # Save the updated summary
        data_path = get_data_path()
        summary_path = data_path / "processed" / "trait_fallback_summary.json"
        save_trait_fallback_summary(
            summary_path,
            target_species,
            fallback_results,
            missing_from_try
        )

        logger.info("Fallback trait acquisition completed successfully")
        return 0

    except FileNotFoundError as e:
        logger.error(f"Input file not found: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error in fallback trait acquisition: {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
