"""
Data integrity validation script for raw benchmark CSVs.

Validates raw CSV files generated by the benchmark harness for:
- Presence of required columns
- Absence of NaN/Inf values
- Absence of missing values (empty cells)
- Schema compliance (types and value ranges)

This script is a neutral check and does not assert any hypothesis.
"""
import sys
import os
import glob
import argparse
from pathlib import Path
from typing import List, Dict, Any, Tuple
import pandas as pd
import numpy as np
from pydantic import ValidationError
import yaml

# Import schema from existing contracts
from analysis.contracts.benchmark_contracts import BenchmarkRun

def load_csv(filepath: str) -> pd.DataFrame:
    """Load a CSV file into a pandas DataFrame."""
    try:
        return pd.read_csv(filepath)
    except Exception as e:
        raise RuntimeError(f"Failed to load CSV {filepath}: {e}")

def check_required_columns(df: pd.DataFrame, filepath: str) -> List[str]:
    """Check if all required columns are present."""
    required_columns = {
        'thread_count',
        'configuration',
        'iteration_count',
        'wall_clock_time_ms'
    }
    missing = required_columns - set(df.columns)
    if missing:
        return [f"Missing columns in {filepath}: {missing}"]
    return []

def check_nan_values(df: pd.DataFrame, filepath: str) -> List[str]:
    """Check for NaN or Inf values in numeric columns."""
    issues = []
    numeric_cols = df.select_dtypes(include=[np.number]).columns
    
    for col in numeric_cols:
        if df[col].isna().any():
            count = df[col].isna().sum()
            issues.append(f"NaN values found in {filepath}, column '{col}': {count} occurrences")
        if np.isinf(df[col]).any():
            count = np.isinf(df[col]).sum()
            issues.append(f"Infinite values found in {filepath}, column '{col}': {count} occurrences")
    
    return issues

def check_missing_values(df: pd.DataFrame, filepath: str) -> List[str]:
    """Check for empty/missing values (non-numeric)."""
    issues = []
    non_numeric_cols = df.select_dtypes(exclude=[np.number]).columns
    
    for col in non_numeric_cols:
        if df[col].isna().any():
            count = df[col].isna().sum()
            issues.append(f"Missing values found in {filepath}, column '{col}': {count} occurrences")
        # Check for empty strings
        if (df[col] == '').any():
            count = (df[col] == '').sum()
            issues.append(f"Empty string values found in {filepath}, column '{col}': {count} occurrences")
    
    return issues

def check_schema_compliance(df: pd.DataFrame, filepath: str) -> List[str]:
    """
    Validate data against the BenchmarkRun schema constraints.
    Checks:
    - thread_count: positive integer
    - configuration: 'packed' or 'padded'
    - iteration_count: positive integer
    - wall_clock_time_ms: positive float
    """
    issues = []
    
    # Check thread_count
    if 'thread_count' in df.columns:
        invalid_rows = df[df['thread_count'] <= 0]
        if not invalid_rows.empty:
            issues.append(f"Invalid thread_count (<=0) in {filepath}: {len(invalid_rows)} rows")
        if not df['thread_count'].apply(lambda x: isinstance(x, (int, float)) and float(x).is_integer()).all():
            issues.append(f"Non-integer thread_count values in {filepath}")
    
    # Check configuration
    if 'configuration' in df.columns:
        valid_configs = {'packed', 'padded'}
        invalid_configs = set(df['configuration'].unique()) - valid_configs
        if invalid_configs:
            issues.append(f"Invalid configuration values in {filepath}: {invalid_configs}")
    
    # Check iteration_count
    if 'iteration_count' in df.columns:
        invalid_rows = df[df['iteration_count'] <= 0]
        if not invalid_rows.empty:
            issues.append(f"Invalid iteration_count (<=0) in {filepath}: {len(invalid_rows)} rows")
    
    # Check wall_clock_time_ms
    if 'wall_clock_time_ms' in df.columns:
        invalid_rows = df[df['wall_clock_time_ms'] <= 0]
        if not invalid_rows.empty:
            issues.append(f"Invalid wall_clock_time_ms (<=0) in {filepath}: {len(invalid_rows)} rows")
    
    return issues

def validate_single_file(filepath: str) -> Tuple[bool, List[str]]:
    """Validate a single CSV file."""
    print(f"Validating: {filepath}")
    issues = []
    
    try:
        df = load_csv(filepath)
        
        if df.empty:
            issues.append(f"File {filepath} is empty")
            return False, issues
        
        # Run all checks
        issues.extend(check_required_columns(df, filepath))
        issues.extend(check_nan_values(df, filepath))
        issues.extend(check_missing_values(df, filepath))
        issues.extend(check_schema_compliance(df, filepath))
        
        if issues:
            print(f"  ❌ Issues found: {len(issues)}")
            for issue in issues:
                print(f"    - {issue}")
        else:
            print(f"  ✅ Valid: {len(df)} rows")
        
        return len(issues) == 0, issues
        
    except Exception as e:
        issues.append(f"Error processing {filepath}: {str(e)}")
        print(f"  ❌ Error: {e}")
        return False, issues

def validate_all_csvs(pattern: str, verbose: bool = True) -> bool:
    """Validate all CSV files matching the pattern."""
    csv_files = glob.glob(pattern)
    
    if not csv_files:
        print(f"No CSV files found matching pattern: {pattern}")
        return False
    
    print(f"Found {len(csv_files)} CSV files to validate")
    print("-" * 50)
    
    all_valid = True
    total_issues = 0
    
    for filepath in csv_files:
        valid, issues = validate_single_file(filepath)
        if not valid:
            all_valid = False
            total_issues += len(issues)
    
    print("-" * 50)
    if all_valid:
        print(f"✅ All {len(csv_files)} files validated successfully")
    else:
        print(f"❌ Validation failed: {total_issues} issues found across {len(csv_files)} files")
    
    return all_valid

def main():
    parser = argparse.ArgumentParser(
        description='Validate raw benchmark CSV data for integrity and schema compliance'
    )
    parser.add_argument(
        '--input-dir',
        type=str,
        default='data/raw',
        help='Directory containing raw CSV files (default: data/raw)'
    )
    parser.add_argument(
        '--pattern',
        type=str,
        default='*.csv',
        help='Glob pattern for CSV files (default: *.csv)'
    )
    parser.add_argument(
        '--verbose',
        action='store_true',
        help='Enable verbose output'
    )
    
    args = parser.parse_args()
    
    # Construct full pattern
    pattern = os.path.join(args.input_dir, args.pattern)
    
    if not os.path.exists(args.input_dir):
        print(f"❌ Input directory does not exist: {args.input_dir}")
        sys.exit(1)
    
    success = validate_all_csvs(pattern, verbose=args.verbose)
    
    sys.exit(0 if success else 1)

if __name__ == '__main__':
    main()