import sys
from pathlib import Path

def extract_dataset_section(plan_content: str) -> dict:
    """
    Extracts the 'Dataset Variable Fit' section from the plan.md content.
    Returns a dictionary mapping variable names to their definitions.
    """
    lines = plan_content.split('\n')
    section_start = -1
    section_end = -1

    # Look for the section header
    for i, line in enumerate(lines):
        if 'Dataset Variable Fit' in line:
            section_start = i
            break

    if section_start == -1:
        return {}

    # Find the end of the section (next section header or end of file)
    for i in range(section_start + 1, len(lines)):
        if lines[i].startswith('#') or (lines[i].strip() and not lines[i].startswith(' ') and not lines[i].startswith('\t')):
            # Check if it looks like a new section (starts with # or significant indentation change)
            if lines[i].strip().startswith('#') or (lines[i].strip() and not lines[i].startswith(' ') and not lines[i].startswith('\t') and ':' not in lines[i]):
                section_end = i
                break

    if section_end == -1:
        section_end = len(lines)

    section_lines = lines[section_start:section_end]
    
    variables = {}
    current_var = None
    current_def = []

    for line in section_lines:
        stripped = line.strip()
        if not stripped:
            continue

        # Check if this is a variable definition (usually starts with a variable name or bullet)
        if stripped.startswith('-') or stripped.startswith('*') or (':' in stripped and not stripped.startswith('#')):
            # Save previous variable if exists
            if current_var:
                variables[current_var] = ' '.join(current_def)
            
            # Parse new variable
            if ':' in stripped:
                parts = stripped.split(':', 1)
                current_var = parts[0].strip().lstrip('-').lstrip('*').strip()
                current_def = [parts[1].strip()] if len(parts) > 1 else []
            else:
                current_var = stripped.lstrip('-').lstrip('*').strip()
                current_def = []
        else:
            # Continuation of definition
            if current_var:
                current_def.append(stripped)

    # Save last variable
    if current_var:
        variables[current_var] = ' '.join(current_def)

    return variables

def check_variable_definitions(plan_content: str) -> tuple:
    """
    Checks if all required variables are defined in the plan's 'Dataset Variable Fit' section.
    Returns (is_verified, missing_vars, found_vars)
    """
    required_vars = [
        'Condition ID',
        'Adherence Rate',
        'Trust Score',
        'Perceived Agency Score',
        'Attention Check Status'
    ]
    
    variables = extract_dataset_section(plan_content)
    
    found_vars = []
    missing_vars = []
    
    for var in required_vars:
        # Check if variable exists (case-insensitive partial match)
        var_lower = var.lower()
        found = False
        for defined_var in variables.keys():
            if var_lower in defined_var.lower():
                found = True
                found_vars.append(var)
                break
        
        if not found:
            missing_vars.append(var)
    
    is_verified = len(missing_vars) == 0
    return is_verified, missing_vars, found_vars

def generate_verification_report(is_verified: bool, missing_vars: list, found_vars: list, output_path: Path) -> None:
    """
    Generates the verification report markdown file.
    """
    report_lines = [
        "# Dataset Variable Fit Verification Report",
        "",
        f"**Status**: {'Verified' if is_verified else 'Not Verified'}",
        "",
        "## Required Variables Check",
        "",
    ]
    
    if is_verified:
        report_lines.append("All required variables are present and defined in the plan.md 'Dataset Variable Fit' section.")
        report_lines.append("")
        report_lines.append("### Verified Variables")
        report_lines.append("")
        for var in found_vars:
            report_lines.append(f"- {var}")
    else:
        report_lines.append("The following required variables are missing or undefined in the plan.md 'Dataset Variable Fit' section:")
        report_lines.append("")
        for var in missing_vars:
            report_lines.append(f"- {var}")
        
        report_lines.append("")
        report_lines.append("### Found Variables")
        report_lines.append("")
        for var in found_vars:
            report_lines.append(f"- {var}")
    
    report_lines.append("")
    report_lines.append("---")
    report_lines.append(f"Generated by verify_dataset_fit.py")
    
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text('\n'.join(report_lines))

def main():
    plan_path = Path('plan.md')
    output_path = Path('research/dataset_verification_report.md')
    
    if not plan_path.exists():
        print("Error: plan.md not found in the project root.")
        sys.exit(1)
    
    plan_content = plan_path.read_text()
    
    is_verified, missing_vars, found_vars = check_variable_definitions(plan_content)
    
    generate_verification_report(is_verified, missing_vars, found_vars, output_path)
    
    if is_verified:
        print("Dataset variable fit verification: PASSED")
        print(f"Report generated at: {output_path}")
    else:
        print("Dataset variable fit verification: FAILED")
        print(f"Missing variables: {missing_vars}")
        print(f"Report generated at: {output_path}")
        sys.exit(1)

if __name__ == '__main__':
    main()
