"""
T000b: Gate - Validate the existence of the Lee & See (2004) citation metadata.

This script validates the metadata (title, year, journal) of the Lee & See (2004)
citation by fetching it from the CrossRef API using the explicitly known DOI.
It verifies that the fetched metadata matches the expected publication details.

Input:
    - research/validation_report.json (generated by T000)
Output:
    - research/scale_text_validation.json

Dependencies:
    - requests
    - json
    - sys
    - pathlib
"""

import json
import sys
from pathlib import Path

import requests

# Constants
LEE_SEE_2004_DOI = "10.1518/hfes.46.1.50_30392"
EXPECTED_YEAR = 2004
EXPECTED_JOURNAL_KEYWORDS = ["Human Factors", "HFES"]
CROSSREF_API_URL = "https://api.crossref.org/works"

# Paths relative to project root
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
VALIDATION_REPORT_PATH = PROJECT_ROOT / "research" / "validation_report.json"
OUTPUT_PATH = PROJECT_ROOT / "research" / "scale_text_validation.json"


def load_json_file(path: Path) -> dict:
    """Load a JSON file from the given path."""
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        print(f"Error: File not found: {path}")
        sys.exit(1)
    except json.JSONDecodeError as e:
        print(f"Error: Invalid JSON in {path}: {e}")
        sys.exit(1)


def fetch_crossref_metadata(doi: str) -> dict:
    """
    Fetch metadata for a given DOI from the CrossRef API.

    Args:
        doi: The DOI string.

    Returns:
        A dictionary containing the metadata.

    Raises:
        SystemExit: If the request fails or the DOI is not found.
    """
    url = f"{CROSSREF_API_URL}/{doi}"
    headers = {"Accept": "application/json"}

    try:
        response = requests.get(url, headers=headers, timeout=10)
        response.raise_for_status()
        data = response.json()
        return data
    except requests.exceptions.RequestException as e:
        print(f"Error: Failed to fetch metadata from CrossRef for DOI {doi}: {e}")
        sys.exit(1)


def validate_metadata(metadata: dict, expected_year: int, expected_journal_keywords: list) -> dict:
    """
    Validate the metadata against expected values.

    Args:
        metadata: The metadata dictionary from CrossRef.
        expected_year: The expected publication year.
        expected_journal_keywords: List of keywords expected in the journal name.

    Returns:
        A dictionary with validation results.
    """
    item = metadata.get("message", {}).get("item", {}) or metadata.get("message", {})
    
    # Extract fields
    title = item.get("title", [""])[0] if item.get("title") else ""
    year = item.get("published-print", {}).get("date-parts", [[None]])[0][0]
    if year is None:
        year = item.get("published-online", {}).get("date-parts", [[None]])[0][0]
    
    container_title = item.get("container-title", [""])[0] if item.get("container-title") else ""
    
    # Validation checks
    year_match = year == expected_year
    journal_match = any(keyword.lower() in container_title.lower() for keyword in expected_journal_keywords)
    
    status = "verified" if (year_match and journal_match) else "mismatch"
    
    return {
        "doi": metadata.get("message", {}).get("DOI", doi),
        "title": title,
        "year": year,
        "journal": container_title,
        "year_match": year_match,
        "journal_match": journal_match,
        "status": status
    }


def main():
    """Main execution function for T000b."""
    print(f"Starting T000b: Validating metadata for Lee & See (2004) DOI: {LEE_SEE_2004_DOI}")

    # 1. Check input file existence (T000 output)
    if not VALIDATION_REPORT_PATH.exists():
        print(f"Error: Required input file not found: {VALIDATION_REPORT_PATH}")
        print("This task depends on T000 completing successfully.")
        sys.exit(1)

    # 2. Fetch metadata from CrossRef
    print(f"Fetching metadata from CrossRef API...")
    crossref_data = fetch_crossref_metadata(LEE_SEE_2004_DOI)

    # 3. Validate metadata
    validation_result = validate_metadata(
        crossref_data, 
        EXPECTED_YEAR, 
        EXPECTED_JOURNAL_KEYWORDS
    )

    # 4. Determine outcome
    if validation_result["status"] == "mismatch":
        print("Citation Metadata Mismatch detected.")
        print(f"Expected Year: {EXPECTED_YEAR}, Found: {validation_result['year']}")
        print(f"Expected Journal Keywords: {EXPECTED_JOURNAL_KEYWORDS}, Found: {validation_result['journal']}")
        sys.exit(1)

    # 5. Prepare output
    output_data = {
        "status": "verified",
        "structure_verified": True,
        "source_url": f"{CROSSREF_API_URL}/{LEE_SEE_2004_DOI}",
        "metadata": {
            "title": validation_result["title"],
            "year": validation_result["year"],
            "journal": validation_result["journal"]
        },
        "checks": {
            "year_match": validation_result["year_match"],
            "journal_match": validation_result["journal_match"]
        }
    }

    # 6. Write output file
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump(output_data, f, indent=2)

    print(f"Success: Metadata validated. Output written to {OUTPUT_PATH}")
    print(f"Title: {validation_result['title']}")
    print(f"Year: {validation_result['year']}, Journal: {validation_result['journal']}")


if __name__ == "__main__":
    main()
