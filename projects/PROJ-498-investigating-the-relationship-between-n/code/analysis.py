def butter_bandpass_filter(data, lowcut, highcut, fs, order=4):
    """Simple bandpass filter using scipy."""
    from scipy.signal import butter, filtfilt
    nyq = 0.5 * fs
    low = lowcut / nyq
    high = highcut / nyq
    b, a = butter(order, [low, high], btype='band')
    y = filtfilt(a, b, data)
    return y

def compute_wpli(sig1, sig2):
    """Compute weighted Phase-Lag Index."""
    # Cross-spectrum
    n = len(sig1)
    # FFT
    f1 = np.fft.rfft(sig1)
    f2 = np.fft.rfft(sig2)
    # Cross-spectrum
    cross = f1 * np.conj(f2)
    # wPLI = Im(cross) / |cross| (weighted)
    # Simplified: mean of Im(cross) / |cross|
    # Avoid division by zero
    denom = np.abs(cross)
    denom[denom == 0] = 1e-9
    wpli = np.mean(np.imag(cross) / denom)
    return wpli

