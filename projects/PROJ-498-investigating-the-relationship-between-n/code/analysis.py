def load_aggregated_data():
    """
    Loads synchrony metrics and behavioral data into a single dataframe.
    Assumes T019 (epochs) and T025 (synchrony metrics) are complete.
    """
    synchrony_file = METRICS_DIR / "synchrony_metrics.csv"
    if not synchrony_file.exists():
        logger.log("error_loading_synchrony", message=f"File not found: {synchrony_file}")
        raise FileNotFoundError(f"Required synchrony metrics file not found: {synchrony_file}")

    sync_df = pd.read_csv(synchrony_file)

    # Load behavioral data (Switching Costs) from T030/T031 logic
    # We assume a file `behavioral_switching_costs.csv` exists or is generated by T030
    behavioral_file = METRICS_DIR / "behavioral_switching_costs.csv"
    if not behavioral_file.exists():
        # Fallback: try to load from a standard location if T030 generated it elsewhere
        # For now, we assume the task T030 generated this file.
        raise FileNotFoundError(f"Behavioral data file not found: {behavioral_file}")

    behavioral_df = pd.read_csv(behavioral_file)

    # Merge on subject_id
    # Synchrony file has: subject_id, pair_id, band, value
    # We need mean synchrony per subject per band for the correlation.
    # Let's aggregate synchrony first.
    mean_sync = sync_df.groupby(['subject_id', 'band'])['value'].mean().reset_index()
    mean_sync.rename(columns={'value': 'mean_synchrony'}, inplace=True)

    merged = pd.merge(mean_sync, behavioral_df, on='subject_id', how='inner')

    if merged.empty:
        logger.log("no_data_for_correlation", message="No overlapping subjects found.")
        raise ValueError("No overlapping subjects between synchrony and behavioral data.")

    return merged

def run_permutation_test(data, n_iterations=1000, seed=42):
    """
    Runs permutation testing (shuffling subject vectors) to assess significance.
    Mandated by FR-005.
    """
    np.random.seed(seed)
    r_observed, p_observed = spearmanr(data['mean_synchrony'], data['switching_cost'])
    
    r_permuted = []
    for _ in range(n_iterations):
        shuffled_cost = np.random.permutation(data['switching_cost'].values)
        r_perm, _ = spearmanr(data['mean_synchrony'], shuffled_cost)
        r_permuted.append(r_perm)
    
    # Calculate p-value based on permutation distribution
    # Two-tailed test: proportion of permuted |r| >= observed |r|
    r_abs_obs = abs(r_observed)
    r_abs_perm = [abs(r) for r in r_permuted]
    p_perm = sum(1 for r in r_abs_perm if r >= r_abs_obs) / n_iterations

    return {
        "observed_r": r_observed,
        "observed_p": p_observed, # Note: spearmanr p-value is approximate, using permutation for robustness
        "permutation_p": p_perm,
        "n_iterations": n_iterations
    }

def run_mixed_effects_analysis(data):
    """
    Implements secondary trial-level analysis (if trial-level data is available)
    or subject-level mixed model if appropriate.
    For US3, we focus on the subject-level correlation primarily, but T035
    specifies a trial-level model. We will check for trial-level data.
    """
    trial_file = TRIAL_LEVEL_DIR / "per_trial_synchrony.csv"
    if not trial_file.exists():
        logger.log("trial_level_data_missing", message="Skipping trial-level mixed-effects model.")
        return None

    trial_df = pd.read_csv(trial_file)
    # Filter missing values
    trial_df = trial_df.dropna(subset=['synchrony', 'rt'])

    if trial_df.empty:
        logger.log("no_valid_trial_data", message="No valid trial data for mixed-effects model.")
        return None

    # Model: RT ~ Synchrony + (1|Subject)
    # Note: statsmodels lmer might not be available directly in older versions,
    # using statsmodels.formula.api.lmer or similar.
    # If lmer is not available, we fallback to standard OLS with subject dummies
    # or use a simplified approach if the environment is restricted.
    try:
        # Attempt to use lmer
        model = lmer('rt ~ synchrony + (1|subject_id)', data=trial_df)
        result = model.fit()
        return {
            "model_summary": str(result.summary()),
            "coefficients": result.params.to_dict(),
            "p_values": result.pvalues.to_dict()
        }
    except Exception as e:
        logger.log("mixed_model_error", message=str(e))
        return None

