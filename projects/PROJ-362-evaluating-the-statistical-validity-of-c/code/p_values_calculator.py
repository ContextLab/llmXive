import os
import csv
import json
import logging
from typing import List, Dict, Any, Optional
from pathlib import Path

from config import RESULTS_DIR, ensure_dirs

logger = logging.getLogger(__name__)

def load_permutation_state(state_path: Optional[str] = None) -> Dict[str, Any]:
    """
    Load the permutation state from the JSON file generated by T013.
    
    Args:
        state_path: Optional path to the state file. Defaults to RESULTS_DIR/config/permutation_state.json.
        
    Returns:
        Dictionary containing the permutation state, including 'N_actual'.
        
    Raises:
        FileNotFoundError: If the state file does not exist.
        KeyError: If 'N_actual' is missing from the state.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    if state_path is None:
        state_path = os.path.join(RESULTS_DIR, 'config', 'permutation_state.json')
    
    path_obj = Path(state_path)
    if not path_obj.exists():
        raise FileNotFoundError(f"Permutation state file not found: {state_path}")
    
    with open(path_obj, 'r') as f:
        state = json.load(f)
    
    if 'N_actual' not in state:
        raise KeyError("Permutation state file missing required key 'N_actual'. "
                       "Ensure T013 (permutation engine) has completed successfully.")
    
    logger.info(f"Loaded permutation state: N_actual = {state['N_actual']}")
    return state

def load_null_distributions(null_dist_dir: Optional[str] = None) -> List[Dict[str, Any]]:
    """
    Load all null distribution CSV files from the specified directory.
    
    Args:
        null_dist_dir: Optional directory path. Defaults to RESULTS_DIR/null_distributions/.
        
    Returns:
        List of dictionaries, each representing a row from the null distribution CSVs.
        
    Raises:
        FileNotFoundError: If the directory does not exist or contains no CSVs.
    """
    if null_dist_dir is None:
        null_dist_dir = os.path.join(RESULTS_DIR, 'null_distributions')
    
    path_obj = Path(null_dist_dir)
    if not path_obj.exists():
        raise FileNotFoundError(f"Null distributions directory not found: {null_dist_dir}")
    
    csv_files = list(path_obj.glob('*.csv'))
    if not csv_files:
        raise FileNotFoundError(f"No CSV files found in null distributions directory: {null_dist_dir}")
    
    all_records = []
    for csv_file in csv_files:
        with open(csv_file, 'r') as f:
            reader = csv.DictReader(f)
            for row in reader:
                # Convert score to float
                row['score'] = float(row['score'])
                row['metric'] = row['metric']
                row['query_id'] = row['query_id']
                all_records.append(row)
    
    logger.info(f"Loaded {len(all_records)} records from {len(csv_files)} null distribution files.")
    return all_records

def load_observed_scores(observed_scores_path: Optional[str] = None) -> Dict[str, Dict[str, float]]:
    """
    Load observed scores for each query and metric.
    This function assumes observed scores were saved by the permutation engine (T013)
    or are available in a specific file. For this implementation, we will derive
    observed scores from the permutation state or a dedicated file if available.
    However, since the task description implies we need to calculate p-values
    against null distributions, we assume the observed scores are stored
    in a file named 'observed_scores.json' or similar, or we calculate them
    if the permutation engine saved them.
    
    Given the current context, we will look for a file 'observed_scores.json'
    in RESULTS_DIR/config/ or derive them if T013 saved them there.
    If not found, we assume the permutation engine saved them in 'permutation_state.json'
    under a specific key, or we need to load them from a separate file.
    
    For robustness, we will check for 'observed_scores.json' first.
    """
    if observed_scores_path is None:
        observed_scores_path = os.path.join(RESULTS_DIR, 'config', 'observed_scores.json')
    
    path_obj = Path(observed_scores_path)
    if not path_obj.exists():
        # Fallback: check if T013 saved them in permutation_state.json under 'observed_scores'
        state_path = os.path.join(RESULTS_DIR, 'config', 'permutation_state.json')
        if Path(state_path).exists():
            try:
                with open(state_path, 'r') as f:
                    state = json.load(f)
                if 'observed_scores' in state:
                    logger.info("Loading observed scores from permutation_state.json")
                    return state['observed_scores']
            except (json.JSONDecodeError, KeyError) as e:
                logger.warning(f"Could not extract observed scores from state file: {e}")
        
        raise FileNotFoundError(f"Observed scores file not found: {observed_scores_path}. "
                                "Ensure the permutation engine (T013) saved observed scores.")
    
    with open(path_obj, 'r') as f:
        observed_scores = json.load(f)
    
    logger.info(f"Loaded observed scores for {len(observed_scores)} queries.")
    return observed_scores

def calculate_p_value(observed_score: float, null_scores: List[float]) -> float:
    """
    Calculate the p-value for an observed score against a null distribution.
    
    Formula: (r + 1) / (N_actual + 1)
    where r is the count of null scores >= observed_score.
    
    Args:
        observed_score: The observed metric score.
        null_scores: List of metric scores from the null distribution.
        
    Returns:
        The calculated p-value.
    """
    if not null_scores:
        raise ValueError("Null scores list is empty. Cannot calculate p-value.")
    
    # Count how many null scores are greater than or equal to the observed score
    # This assumes a one-tailed test where higher scores are better (typical for NDCG/MAP)
    r = sum(1 for score in null_scores if score >= observed_score)
    N_actual = len(null_scores)
    
    p_value = (r + 1) / (N_actual + 1)
    return p_value

def process_null_distributions(null_records: List[Dict[str, Any]], 
                               observed_scores: Dict[str, Dict[str, float]],
                               n_actual: int) -> List[Dict[str, Any]]:
    """
    Process null distributions to calculate p-values for each query and metric.
    
    Args:
        null_records: List of all null distribution records.
        observed_scores: Dictionary mapping query_id -> {metric: observed_score}.
        n_actual: The actual number of permutations performed (N_actual).
        
    Returns:
        List of dictionaries containing query_id, metric, raw_p, and other details.
    """
    p_values = []
    
    # Group null scores by query_id and metric
    null_distributions = {}
    for record in null_records:
        key = (record['query_id'], record['metric'])
        if key not in null_distributions:
            null_distributions[key] = []
        null_distributions[key].append(record['score'])
    
    # Calculate p-values
    for (query_id, metric), null_scores in null_distributions.items():
        if (query_id, metric) not in observed_scores:
            logger.warning(f"Observed score missing for query_id={query_id}, metric={metric}. Skipping.")
            continue
        
        observed_score = observed_scores[(query_id, metric)]
        p_value = calculate_p_value(observed_score, null_scores)
        
        p_values.append({
            'query_id': query_id,
            'metric': metric,
            'observed_score': observed_score,
            'n_null': len(null_scores),
            'n_actual': n_actual,
            'raw_p': p_value
        })
    
    logger.info(f"Calculated p-values for {len(p_values)} query-metric pairs.")
    return p_values

def save_raw_p_values(p_values: List[Dict[str, Any]], output_path: Optional[str] = None) -> None:
    """
    Save raw p-values to a CSV file.
    
    Args:
        p_values: List of p-value dictionaries.
        output_path: Optional path to the output file. Defaults to RESULTS_DIR/p_values/raw_p_values.csv.
    """
    if output_path is None:
        output_path = os.path.join(RESULTS_DIR, 'p_values', 'raw_p_values.csv')
    
    ensure_dirs(output_path)
    
    with open(output_path, 'w', newline='') as f:
        fieldnames = ['query_id', 'metric', 'observed_score', 'n_null', 'n_actual', 'raw_p']
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(p_values)
    
    logger.info(f"Saved raw p-values to {output_path}")

def run_p_value_calculation() -> None:
    """
    Main entry point for the p-value calculation task (T016).
    
    This function:
    1. Loads the permutation state to get N_actual.
    2. Loads null distributions from CSV files.
    3. Loads observed scores.
    4. Calculates p-values using the formula (r + 1) / (N_actual + 1).
    5. Saves the results to raw_p_values.csv.
    """
    logger.info("Starting p-value calculation (T016)...")
    
    # 1. Load permutation state to get N_actual
    state = load_permutation_state()
    n_actual = state['N_actual']
    
    # 2. Load null distributions
    null_records = load_null_distributions()
    
    # 3. Load observed scores
    observed_scores = load_observed_scores()
    
    # 4. Process and calculate p-values
    p_values = process_null_distributions(null_records, observed_scores, n_actual)
    
    # 5. Save results
    save_raw_p_values(p_values)
    
    logger.info("P-value calculation completed successfully.")

if __name__ == '__main__':
    logging.basicConfig(level=logging.INFO)
    run_p_value_calculation()