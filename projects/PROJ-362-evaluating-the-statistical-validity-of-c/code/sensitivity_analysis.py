"""
Sensitivity Analysis Module (T024)

Implements sensitivity analysis by sweeping alpha values across [0.01, 0.05, 0.10]
and reporting the count of queries where significance status changes between alpha values.

Output: results/sensitivity/alpha_sweep.csv with columns: alpha, significant_count
"""
import os
import csv
import logging
from typing import List, Dict, Tuple, Optional
from config import RESULTS_DIR

# Ensure the sensitivity directory exists
SENSITIVITY_DIR = os.path.join(RESULTS_DIR, "sensitivity")
ALPHA_SWEEP_FILE = os.path.join(SENSITIVITY_DIR, "alpha_sweep.csv")

def load_corrected_p_values(filepath: Optional[str] = None) -> List[Dict[str, any]]:
    """
    Load corrected p-values from the CSV file generated by T026.
    
    Args:
        filepath: Path to the corrected_p_values.csv file. Defaults to the standard location.
        
    Returns:
        List of dictionaries containing query_id, metric, raw_p, corrected_p, is_significant.
    """
    if filepath is None:
        filepath = os.path.join(RESULTS_DIR, "p_values", "corrected_p_values.csv")
    
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Corrected p-values file not found at {filepath}. "
                                "Ensure T026 (generate corrected p-values) has been completed.")
    
    data = []
    with open(filepath, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Convert string values to appropriate types
            row['query_id'] = int(row['query_id'])
            row['metric'] = row['metric']
            row['raw_p'] = float(row['raw_p'])
            row['corrected_p'] = float(row['corrected_p'])
            # is_significant is typically 'True' or 'False' string in CSV
            row['is_significant'] = row['is_significant'].strip().lower() == 'true'
            data.append(row)
    
    if not data:
        logging.warning("Corrected p-values file is empty.")
    
    return data

def determine_significance(p_value: float, alpha: float) -> bool:
    """
    Determine if a result is significant at the given alpha level.
    
    Args:
        p_value: The corrected p-value.
        alpha: The significance threshold.
        
    Returns:
        True if p_value <= alpha, False otherwise.
    """
    return p_value <= alpha

def run_sensitivity_analysis(
    alphas: List[float] = None,
    input_file: Optional[str] = None,
    output_file: Optional[str] = None
) -> List[Dict[str, any]]:
    """
    Run sensitivity analysis by iterating over alpha values and counting significant results.
    
    This function:
    1. Loads corrected p-values from the input file (default: results/p_values/corrected_p_values.csv).
    2. Iterates through the specified alpha values (default: [0.01, 0.05, 0.10]).
    3. For each alpha, counts how many query-metric pairs are significant.
    4. Saves the results to the output file (default: results/sensitivity/alpha_sweep.csv).
    
    Args:
        alphas: List of alpha values to sweep. Defaults to [0.01, 0.05, 0.10].
        input_file: Path to the corrected p-values CSV.
        output_file: Path to the output sensitivity analysis CSV.
        
    Returns:
        List of dictionaries with 'alpha' and 'significant_count'.
    """
    if alphas is None:
        alphas = [0.01, 0.05, 0.10]
    
    if input_file is None:
        input_file = os.path.join(RESULTS_DIR, "p_values", "corrected_p_values.csv")
    
    if output_file is None:
        # Ensure sensitivity directory exists
        os.makedirs(SENSITIVITY_DIR, exist_ok=True)
        output_file = ALPHA_SWEEP_FILE
    
    logging.info(f"Loading corrected p-values from {input_file}")
    corrected_data = load_corrected_p_values(input_file)
    
    if not corrected_data:
        raise ValueError("No corrected p-values found. Ensure T026 has been run successfully.")
    
    logging.info(f"Running sensitivity analysis for alphas: {alphas}")
    results = []
    
    for alpha in alphas:
        significant_count = sum(
            1 for row in corrected_data 
            if determine_significance(row['corrected_p'], alpha)
        )
        results.append({
            'alpha': alpha,
            'significant_count': significant_count
        })
        logging.info(f"Alpha={alpha}: {significant_count} significant results")
    
    # Write results to CSV
    logging.info(f"Writing sensitivity analysis results to {output_file}")
    with open(output_file, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=['alpha', 'significant_count'])
        writer.writeheader()
        writer.writerows(results)
    
    return results

def main():
    """
    Entry point for running sensitivity analysis as a standalone script.
    """
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(levelname)s - %(message)s'
    )
    
    try:
        results = run_sensitivity_analysis()
        logging.info("Sensitivity analysis completed successfully.")
        for r in results:
            logging.info(f"  Alpha {r['alpha']}: {r['significant_count']} significant")
    except FileNotFoundError as e:
        logging.error(str(e))
        raise
    except ValueError as e:
        logging.error(str(e))
        raise
    except Exception as e:
        logging.error(f"Unexpected error during sensitivity analysis: {e}")
        raise

if __name__ == "__main__":
    main()
