import os
import csv
import logging
from typing import List, Dict, Any, Optional
from config import RESULTS_DIR

logger = logging.getLogger(__name__)

def load_mdes_results() -> List[Dict[str, Any]]:
    """
    Load MDES results from the power analysis output.
    
    This function reads the MDES data generated by the power analysis module.
    The data is expected to be in a CSV format with columns:
    metric, mdes, power, ci_width
    
    Returns:
        List of dictionaries containing MDES results
    """
    mdes_file = os.path.join(RESULTS_DIR, "mdes", "mdes_summary.csv")
    
    if not os.path.exists(mdes_file):
        logger.error(f"MDES results file not found: {mdes_file}")
        return []
    
    results = []
    try:
        with open(mdes_file, 'r', newline='', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            for row in reader:
                # Convert numeric fields
                result = {
                    'metric': row['metric'],
                    'mdes': float(row['mdes']),
                    'power': float(row['power']),
                    'ci_width': float(row['ci_width'])
                }
                results.append(result)
        logger.info(f"Loaded {len(results)} MDES results from {mdes_file}")
    except Exception as e:
        logger.error(f"Error reading MDES results: {e}")
        return []
    
    return results

def generate_mdes_summary_csv(results: List[Dict[str, Any]]) -> bool:
    """
    Generate the MDES summary CSV file.
    
    Args:
        results: List of MDES result dictionaries
        
    Returns:
        True if successful, False otherwise
    """
    output_file = os.path.join(RESULTS_DIR, "mdes", "mdes_summary.csv")
    
    # Ensure directory exists
    os.makedirs(os.path.dirname(output_file), exist_ok=True)
    
    if not results:
        logger.warning("No MDES results to write")
        return False
    
    try:
        with open(output_file, 'w', newline='', encoding='utf-8') as f:
            fieldnames = ['metric', 'mdes', 'power', 'ci_width']
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(results)
        
        logger.info(f"Successfully wrote MDES summary to {output_file}")
        return True
    except Exception as e:
        logger.error(f"Error writing MDES summary: {e}")
        return False

def run_mdes_summary_generation() -> bool:
    """
    Main entry point for generating the MDES summary CSV.
    
    This function orchestrates the loading of MDES results and
    generation of the summary CSV file.
    
    Returns:
        True if successful, False otherwise
    """
    logger.info("Starting MDES summary generation")
    
    # Load existing MDES results
    results = load_mdes_results()
    
    if not results:
        logger.error("No MDES results found to generate summary")
        return False
    
    # Generate the summary CSV
    success = generate_mdes_summary_csv(results)
    
    if success:
        logger.info("MDES summary generation completed successfully")
    else:
        logger.error("MDES summary generation failed")
    
    return success

def run_mdes_summary_generation_main():
    """
    Command-line entry point for MDES summary generation.
    """
    import sys
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    success = run_mdes_summary_generation()
    sys.exit(0 if success else 1)

if __name__ == "__main__":
    run_mdes_summary_generation_main()
