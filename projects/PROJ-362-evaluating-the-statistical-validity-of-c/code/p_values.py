"""
p_values.py

Implements p-value calculation logic for permutation tests.
Calculates p-values by ranking observed scores within null distributions.
Formula: p = (r + 1) / (N + 1) where r is the count of null scores >= observed score.
"""
import os
import csv
import logging
from typing import List, Dict, Any, Tuple, Optional
from pathlib import Path
from config import RESULTS_DIR, ensure_dirs

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def calculate_p_value(observed_score: float, null_scores: List[float]) -> float:
    """
    Calculate the p-value for a single observed score against a null distribution.

    Uses the standard permutation test p-value formula:
    p = (r + 1) / (N + 1)
    where:
      - r is the number of permutations where the permuted score >= observed score
      - N is the total number of permutations

    Args:
        observed_score: The actual metric score (NDCG@10 or MAP) for the query.
        null_scores: List of metric scores from the permuted relevance labels.

    Returns:
        float: The calculated p-value.
    """
    if not null_scores:
        raise ValueError("Null scores list cannot be empty for p-value calculation.")

    N = len(null_scores)
    # Count how many permuted scores are greater than or equal to the observed score
    r = sum(1 for score in null_scores if score >= observed_score)

    # Calculate p-value with the +1 correction
    p_value = (r + 1) / (N + 1)
    return p_value

def process_null_distributions(
    null_dist_dir: Optional[Path] = None,
    observed_scores_file: Optional[Path] = None
) -> List[Dict[str, Any]]:
    """
    Process all null distribution CSV files to calculate p-values.

    Reads null distribution CSVs generated by T017 (or T013/T014),
    reads observed scores, and calculates p-values for each query-metric pair.

    Args:
        null_dist_dir: Directory containing null distribution CSVs. Defaults to RESULTS_DIR/null_distributions.
        observed_scores_file: Path to CSV containing observed scores. Defaults to inferred path.

    Returns:
        List of dictionaries containing query_id, metric, observed_score, p_value, N_permutations.
    """
    if null_dist_dir is None:
        null_dist_dir = RESULTS_DIR / "null_distributions"
    
    if not null_dist_dir.exists():
        raise FileNotFoundError(f"Null distribution directory not found: {null_dist_dir}")

    # Determine observed scores file path if not provided
    if observed_scores_file is None:
        observed_scores_file = RESULTS_DIR / "observed_scores.csv"
    
    if not observed_scores_file.exists():
        raise FileNotFoundError(f"Observed scores file not found: {observed_scores_file}")

    # Load observed scores into a dictionary
    observed_scores_map: Dict[Tuple[str, str], float] = {}
    with open(observed_scores_file, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            key = (row['query_id'], row['metric'])
            observed_scores_map[key] = float(row['observed_score'])

    p_values_results: List[Dict[str, Any]] = []

    # Process each null distribution file
    null_files = sorted(null_dist_dir.glob("*.csv"))
    if not null_files:
        logger.warning(f"No null distribution CSV files found in {null_dist_dir}")
        return []

    logger.info(f"Processing {len(null_files)} null distribution files...")

    for file_path in null_files:
        logger.info(f"Processing file: {file_path.name}")
        with open(file_path, 'r', newline='', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            rows = list(reader)
            
            if not rows:
                logger.warning(f"Empty null distribution file: {file_path.name}")
                continue

            # Extract query_id and metric from the first row (should be consistent)
            query_id = rows[0]['query_id']
            metric = rows[0]['metric']
            key = (query_id, metric)

            if key not in observed_scores_map:
                logger.warning(f"No observed score found for {key}. Skipping.")
                continue

            observed_score = observed_scores_map[key]
            null_scores = [float(row['score']) for row in rows]
            N = len(null_scores)

            p_value = calculate_p_value(observed_score, null_scores)

            p_values_results.append({
                'query_id': query_id,
                'metric': metric,
                'observed_score': observed_score,
                'p_value': p_value,
                'N_permutations': N
            })

    logger.info(f"Calculated p-values for {len(p_values_results)} query-metric pairs.")
    return p_values_results

def run_p_value_calculation(
    null_dist_dir: Optional[Path] = None,
    output_file: Optional[Path] = None
) -> str:
    """
    Main entry point to run p-value calculation and save results.

    Args:
        null_dist_dir: Directory containing null distribution CSVs.
        output_file: Path to save the raw p-values CSV. Defaults to RESULTS_DIR/p_values/raw_p_values.csv.

    Returns:
        Path to the output file.
    """
    if null_dist_dir is None:
        null_dist_dir = RESULTS_DIR / "null_distributions"
    
    if output_file is None:
        output_file = RESULTS_DIR / "p_values" / "raw_p_values.csv"

    ensure_dirs(output_file.parent)

    try:
        results = process_null_distributions(null_dist_dir)
        
        if not results:
            logger.warning("No p-values calculated. Output file will be empty.")
        
        # Save results
        with open(output_file, 'w', newline='', encoding='utf-8') as f:
            fieldnames = ['query_id', 'metric', 'observed_score', 'p_value', 'N_permutations']
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(results)

        logger.info(f"P-values saved to: {output_file}")
        return str(output_file)

    except Exception as e:
        logger.error(f"Error during p-value calculation: {e}", exc_info=True)
        raise

if __name__ == "__main__":
    # Simple test execution if run directly
    run_p_value_calculation()