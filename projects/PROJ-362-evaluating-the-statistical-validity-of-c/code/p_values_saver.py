import os
import csv
import logging
from typing import List, Dict, Any, Optional
from config import RESULTS_DIR
from p_values import process_null_distributions

def ensure_p_values_dir():
    """Ensure the p_values directory exists."""
    p_values_dir = os.path.join(RESULTS_DIR, "p_values")
    os.makedirs(p_values_dir, exist_ok=True)
    return p_values_dir

def save_raw_p_values(p_values_data: List[Dict[str, Any]], output_path: Optional[str] = None) -> str:
    """
    Save raw p-values to a CSV file.
    
    Args:
        p_values_data: List of dicts with keys: query_id, metric, raw_p
        output_path: Optional path to save the CSV. Defaults to results/p_values/raw_p_values.csv
        
    Returns:
        Path to the saved file
    """
    if output_path is None:
        ensure_p_values_dir()
        output_path = os.path.join(RESULTS_DIR, "p_values", "raw_p_values.csv")
    
    with open(output_path, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=['query_id', 'metric', 'raw_p'])
        writer.writeheader()
        writer.writerows(p_values_data)
    
    logging.info(f"Saved raw p-values to {output_path}")
    return output_path

def run_p_values_saving():
    """
    Main entry point to process null distributions and save raw p-values.
    
    This function:
    1. Loads null distributions from results/null_distributions/
    2. Calculates raw p-values using the (r+1)/(N+1) formula
    3. Saves the results to results/p_values/raw_p_values.csv
    """
    logging.info("Starting raw p-values saving process")
    
    # Process null distributions to get p-values
    # This relies on the null distributions being generated by T017
    p_values_data = process_null_distributions()
    
    if not p_values_data:
        logging.warning("No p-values data found. Ensure null distributions exist.")
        return None
    
    # Save to CSV
    output_path = save_raw_p_values(p_values_data)
    
    logging.info(f"Successfully saved {len(p_values_data)} raw p-values to {output_path}")
    return output_path
