def test_audit_logic_returns_failure_status():
    """
    Test that the audit logic correctly identifies missing 'Schandry' tasks
    and returns a 'Feasibility Failure' status using mocked inputs (not file I/O).
    
    This test asserts the internal state/logic of the audit flow, not the final
    file content generated by T014.
    """
    # Mock data representing an events.tsv content that lacks 'Schandry'
    # Format: list of dicts as pandas would read it
    mock_events_data = [
        {"task": "rest", "onset": 0.0, "duration": 10.0},
        {"task": "TSST", "onset": 10.0, "duration": 300.0},
        {"task": "baseline", "onset": 310.0, "duration": 60.0}
    ]
    
    # Define the required tasks per FR-002
    required_interoception_tasks = ['Schandry', 'heartbeat']
    required_stress_tasks = ['TSST']
    
    # Simulate the logic from code/02_audit_metadata.py
    found_tasks = set()
    for row in mock_events_data:
        if 'task' in row and row['task']:
            found_tasks.add(row['task'])
    
    # Check for interoception task presence
    has_interoception = any(task in found_tasks for task in required_interoception_tasks)
    
    # Check for stress task presence (TSST is present in mock)
    has_stress = any(task in found_tasks for task in required_stress_tasks)
    
    # Determine feasibility status
    if not has_interoception:
        feasibility_status = "Feasibility Failure"
        reason = "Missing Behavioral Task (Schandry/heartbeat)"
    elif not has_stress:
        feasibility_status = "Feasibility Failure"
        reason = "Missing Stress Task (TSST)"
    else:
        feasibility_status = "Feasibility Success"
        reason = "All required tasks present"
    
    # Assertions: Verify the logic correctly identifies the failure
    assert feasibility_status == "Feasibility Failure", \
        f"Expected 'Feasibility Failure', got '{feasibility_status}'"
    assert "Missing Behavioral Task" in reason, \
        f"Expected reason to mention missing task, got '{reason}'"
    
    # Verify that 'Schandry' is indeed missing from found_tasks
    assert 'Schandry' not in found_tasks, "Test setup error: Schandry should not be in mock data"

