import os
import sys
import json
import requests
import pandas as pd
from pathlib import Path
from typing import Dict, List, Any
import logging
import itertools
from datetime import datetime

# Configure logging
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

class DataUnavailableError(Exception):
    """Raised when a required data source is unavailable or returns a non-200 status."""
    pass

def ensure_directories():
    """Ensure required directories exist."""
    dirs = [
        "data/raw",
        "data/processed",
        "data/final",
        "docs"
    ]
    for d in dirs:
        Path(d).mkdir(parents=True, exist_ok=True)
    logger.info("Directories ensured.")

def load_verification_report():
    """Load the verification report generated by T012."""
    report_path = Path("data/verification_report.json")
    if not report_path.exists():
        raise FileNotFoundError("Verification report not found. Run T012 first.")
    
    with open(report_path, 'r') as f:
        return json.load(f)

def verify_url_status(url: str, method: str = "HEAD") -> bool:
    """
    Perform a pre-flight HEAD check on the given URL.
    Raises DataUnavailableError if the response is not 200 OK.
    """
    if not url or not url.startswith(("http://", "https://")):
        raise DataUnavailableError(f"Invalid URL format: {url}")
    
    try:
        logger.info(f"Performing pre-flight {method} check on: {url}")
        # Use a short timeout to fail fast if unreachable
        response = requests.head(url, timeout=10, allow_redirects=True)
        
        if response.status_code != 200:
            # Log the error details
            error_msg = f"URL check failed for {url}: Status {response.status_code}"
            logger.error(error_msg)
            # Raise the specific error to halt the pipeline
            raise DataUnavailableError(error_msg)
        
        logger.info(f"URL check passed for {url}: Status {response.status_code}")
        return True

    except requests.exceptions.RequestException as e:
        error_msg = f"Network error checking {url}: {str(e)}"
        logger.error(error_msg)
        raise DataUnavailableError(error_msg)

def verify_dataset_manifest(dataset_info: Dict[str, Any]):
    """
    Verify the manifest details for a dataset (placeholder for future manifest logic).
    Currently just logs the dataset name and source.
    """
    name = dataset_info.get("name", "Unknown")
    source = dataset_info.get("source", "Unknown")
    logger.info(f"Verifying manifest for dataset: {name} from {source}")

def save_manifest(manifest_data: Dict[str, Any]):
    """Save the dataset manifest to disk."""
    output_path = Path("data/raw/dataset_manifest.json")
    with open(output_path, 'w') as f:
        json.dump(manifest_data, f, indent=2)
    logger.info(f"Manifest saved to {output_path}")

def download_pilot_data():
    """
    Implement T013b: Atomic Pilot Download.
    Streams a small representative subset of Recipe1M and Ratings.
    Uses dataset_name="recipe1m-full" and split="train".
    Outputs: data/raw/pilot_data.parquet and data/raw/pilot_stats.json.
    """
    ensure_directories()
    
    # Load verification report to confirm source
    report = load_verification_report()
    logger.info("Verification report loaded.")

    # T046: Pre-flight HEAD checks (re-run for safety)
    urls_to_check = []
    if "datasets" in report:
        for ds in report["datasets"]:
            if "url" in ds:
                urls_to_check.append(ds["url"])
            if "sources" in ds:
                for src in ds["sources"]:
                    if "url" in src:
                        urls_to_check.append(src["url"])

    if urls_to_check:
        logger.info(f"Starting pre-flight HEAD checks for {len(urls_to_check)} URLs...")
        for url in urls_to_check:
            verify_url_status(url)
        logger.info("All pre-flight HEAD checks passed.")

    # Import datasets here to avoid heavy import if not needed
    try:
        from datasets import load_dataset
    except ImportError:
        raise DataUnavailableError("Required library 'datasets' not found. Install with: pip install datasets")

    # T013b Implementation: Stream pilot data
    dataset_name = "recipe1m-full"
    split_name = "train"
    pilot_size = 1000  # Small representative subset for pilot

    logger.info(f"Starting pilot download for {dataset_name} (split={split_name}, size={pilot_size})...")
    
    try:
        # Load dataset in streaming mode
        dataset = load_dataset(dataset_name, split=split_name, streaming=True)
        
        # Sample pilot data
        pilot_rows = list(itertools.islice(dataset, pilot_size))
        
        if not pilot_rows:
            raise DataUnavailableError("Pilot download yielded 0 rows. Dataset might be empty or inaccessible.")
        
        logger.info(f"Successfully streamed {len(pilot_rows)} rows.")
        
        # Convert to DataFrame
        df = pd.DataFrame(pilot_rows)
        
        # Save to Parquet
        output_path = Path("data/raw/pilot_data.parquet")
        df.to_parquet(output_path, index=False)
        logger.info(f"Pilot data saved to {output_path}")
        
        # Generate stats
        pilot_stats = {
            "task": "T013b",
            "status": "SUCCESS",
            "dataset_name": dataset_name,
            "split": split_name,
            "rows_sampled": len(pilot_rows),
            "columns": list(df.columns),
            "sample_shape": df.shape,
            "timestamp": datetime.now().isoformat(),
            "output_file": str(output_path)
        }
        
        # Add basic column type stats
        for col in df.columns:
            pilot_stats[f"{col}_type"] = str(df[col].dtype)
        
        stats_path = Path("data/raw/pilot_stats.json")
        with open(stats_path, 'w') as f:
            json.dump(pilot_stats, f, indent=2)
        logger.info(f"Pilot stats saved to {stats_path}")
        
        return True

    except Exception as e:
        logger.error(f"Failed to download pilot data: {e}")
        raise DataUnavailableError(f"Failed to download pilot data: {e}")

def download_datasets():
    """
    Main function to orchestrate the download process.
    1. Loads verification report.
    2. Performs HEAD checks on all verified URLs (T046 requirement).
    3. Executes T013b Pilot Download.
    """
    ensure_directories()
    
    # Load verification report
    report = load_verification_report()
    logger.info("Verification report loaded.")

    # T046: Pre-flight HEAD checks
    urls_to_check = []
    if "datasets" in report:
        for ds in report["datasets"]:
            if "url" in ds:
                urls_to_check.append(ds["url"])
            # Check nested sources if applicable
            if "sources" in ds:
                for src in ds["sources"]:
                    if "url" in src:
                        urls_to_check.append(src["url"])

    if not urls_to_check:
        logger.warning("No URLs found in verification report to check.")
    else:
        logger.info(f"Starting pre-flight HEAD checks for {len(urls_to_check)} URLs...")
        for url in urls_to_check:
            # This will raise DataUnavailableError if check fails
            verify_url_status(url)
        logger.info("All pre-flight HEAD checks passed.")

    # Verify dataset manifests (T051 requirement)
    if "datasets" in report:
        for ds in report["datasets"]:
            verify_dataset_manifest(ds)

    # Execute T013b: Atomic Pilot Download
    download_pilot_data()
    
    # Write a log indicating T046 success
    t046_log = {
        "task": "T046",
        "status": "SUCCESS",
        "urls_checked": len(urls_to_check),
        "timestamp": str(pd.Timestamp.now())
    }
    with open("data/t046_head_check_log.json", 'w') as f:
        json.dump(t046_log, f, indent=2)

def main():
    """Entry point for the script."""
    try:
        download_datasets()
        logger.info("Download process initiated successfully.")
    except DataUnavailableError as e:
        logger.error(f"Data unavailable: {e}")
        sys.exit(1)
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
