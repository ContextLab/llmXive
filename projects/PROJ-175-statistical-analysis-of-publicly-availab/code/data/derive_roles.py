# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler('data/logs/role_derivation.log')
    ]
)
logger = logging.getLogger(__name__)

def ensure_directories():
    """Ensure all required output directories exist."""
    dirs = [
        'data/processed',
        'data/logs'
    ]
    for d in dirs:
        Path(d).mkdir(parents=True, exist_ok=True)

def load_marginal_frequencies():
    """
    Load marginal frequencies from T014 output.
    Expected file: data/processed/normalized_ingredients.csv
    """
    file_path = Path('data/processed/normalized_ingredients.csv')
    if not file_path.exists():
        raise FileNotFoundError(f"Marginal frequencies file not found: {file_path}")
    
    df = pd.read_csv(file_path)
    required_cols = ['ingredient_id', 'canonical_name', 'functional_role', 'frequency']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in normalized_ingredients.csv: {missing_cols}")
    
    return df

def load_positional_ranks():
    """
    Load positional ranks.
    Expected file: data/processed/positional_ranks.csv (generated by T014)
    """
    file_path = Path('data/processed/positional_ranks.csv')
    if not file_path.exists():
        # Fallback: if not explicitly saved, derive from normalized_ingredients if frequency implies rank
        # For this implementation, we assume T014 saved this or we derive a proxy
        logger.warning("positional_ranks.csv not found. Deriving proxy from frequency rank.")
        df_freq = load_marginal_frequencies()
        # Higher frequency = lower rank (more primary)
        df_freq['positional_rank'] = df_freq['frequency'].rank(ascending=False, method='min')
        return df_freq[['ingredient_id', 'positional_rank']]
    
    df = pd.read_csv(file_path)
    if 'ingredient_id' not in df.columns or 'positional_rank' not in df.columns:
        raise ValueError("positional_ranks.csv must contain 'ingredient_id' and 'positional_rank'")
    return df

def load_co_occurrence_matrix():
    """
    Load co-occurrence matrix from T015 output.
    Expected file: data/processed/co_occurrence_matrix.parquet
    """
    file_path = Path('data/processed/co_occurrence_matrix.parquet')
    if not file_path.exists():
        raise FileNotFoundError(f"Co-occurrence matrix not found: {file_path}")
    
    try:
        df = pd.read_parquet(file_path)
    except Exception as e:
        raise RuntimeError(f"Failed to load co-occurrence matrix: {e}")
    return df

def load_reference_ingredients():
    """
    Load the list of reference ingredients to ensure we only derive roles for known items.
    """
    return load_marginal_frequencies()['ingredient_id'].tolist()

def verify_exclusion_of_co_occurrence(roles_df, co_occurrence_df):
    """
    Verify that functional role derivation did not circularly depend on the co-occurrence matrix
    being built in the same pipeline step (FR-005).
    We check that the role assignment logic (based on frequency/rank) is orthogonal to the
    specific pair counts in the matrix.
    """
    # This is a logic check. If roles were derived from co-occurrence, we'd see high correlation
    # between role and total co-occurrence count. We ensure this is low.
    # Calculate total co-occurrence per ingredient
    if isinstance(co_occurrence_df, pd.DataFrame):
        # Assuming matrix is in wide format or edge list.
        # If wide: sum rows. If edge: groupby.
        if 'ingredient_a' in co_occurrence_df.columns and 'ingredient_b' in co_occurrence_df.columns:
            # Edge list
            counts_a = co_occurrence_df.groupby('ingredient_a')['count'].sum().reset_index()
            counts_a.columns = ['ingredient_id', 'total_co_occurrence']
            counts_b = co_occurrence_df.groupby('ingredient_b')['count'].sum().reset_index()
            counts_b.columns = ['ingredient_id', 'total_co_occurrence_b']
            total_counts = pd.concat([counts_a, counts_b], ignore_index=True).groupby('ingredient_id')['total_co_occurrence'].sum().reset_index()
        else:
            # Wide matrix assumption
            total_counts = co_occurrence_df.set_index('ingredient_id').sum(axis=1).reset_index()
            total_counts.columns = ['ingredient_id', 'total_co_occurrence']
        
        merged = roles_df.merge(total_counts, on='ingredient_id', how='left')
        if 'total_co_occurrence' in merged.columns:
            merged['total_co_occurrence'] = merged['total_co_occurrence'].fillna(0)
            # Encode role as numeric
            role_map = {'primary': 3, 'secondary': 2, 'garnish': 1}
            merged['role_numeric'] = merged['functional_role'].map(role_map)
            
            corr, p_val = stats.pearsonr(merged['role_numeric'], merged['total_co_occurrence'])
            logger.info(f"Correlation between Role and Total Co-occurrence: {corr:.4f} (p={p_val:.4f})")
            
            # If correlation is too high (> 0.1), log warning but proceed (it's expected to some degree)
            if abs(corr) > 0.1:
                logger.warning(f"High correlation ({corr}) detected between functional role and co-occurrence. "
                               "This suggests potential circularity. Review derivation logic.")
                # Save audit log
                audit_log = {
                    "task": "T017",
                    "metric": "role_co_occurrence_correlation",
                    "value": corr,
                    "p_value": p_val,
                    "status": "WARNING" if abs(corr) > 0.1 else "OK"
                }
                with open('data/logs/role_independence_audit.json', 'w') as f:
                    json.dump(audit_log, f, indent=2)
    return True

def calculate_functional_role(df_freq, df_ranks):
    """
    Derive functional role based on positional rank and marginal frequency.
    Logic:
    - Primary: High frequency, low rank (appears early/often)
    - Secondary: Medium frequency/rank
    - Garnish: Low frequency, high rank
    
    We use quantiles to define thresholds.
    """
    # Merge data
    merged = df_freq.merge(df_ranks, on='ingredient_id', how='inner')
    
    if merged.empty:
        raise ValueError("No data to process after merging frequency and rank.")

    # Normalize metrics for scoring
    # Higher frequency -> better (primary)
    # Lower rank -> better (primary)
    merged['freq_score'] = (merged['frequency'] - merged['frequency'].min()) / (merged['frequency'].max() - merged['frequency'].min() + 1e-9)
    merged['rank_score'] = (merged['positional_rank'].max() - merged['positional_rank']) / (merged['positional_rank'].max() - merged['positional_rank'].min() + 1e-9)
    
    # Combined score: weighted average (e.g., 60% freq, 40% rank)
    merged['composite_score'] = 0.6 * merged['freq_score'] + 0.4 * merged['rank_score']
    
    # Define thresholds using quantiles
    p33 = merged['composite_score'].quantile(0.33)
    p66 = merged['composite_score'].quantile(0.66)
    
    def assign_role(score):
        if score >= p66:
            return 'primary'
        elif score >= p33:
            return 'secondary'
        else:
            return 'garnish'
    
    merged['functional_role'] = merged['composite_score'].apply(assign_role)
    
    # Verify against co-occurrence
    # Load co-occurrence matrix for validation
    try:
        co_occ_df = load_co_occurrence_matrix()
        verify_exclusion_of_co_occurrence(merged, co_occ_df)
    except FileNotFoundError:
        logger.warning("Co-occurrence matrix not found for validation check. Skipping correlation audit.")
    
    return merged[['ingredient_id', 'canonical_name', 'functional_role', 'frequency', 'positional_rank', 'composite_score']]

def save_output(df):
    """
    Save the final functional roles to parquet.
    Output: data/processed/functional_roles.parquet
    """
    output_path = Path('data/processed/functional_roles.parquet')
    try:
        df.to_parquet(output_path, index=False)
        logger.info(f"Successfully saved functional roles to {output_path}")
        
        # Save summary stats
        summary = {
            "total_ingredients": len(df),
            "role_distribution": df['functional_role'].value_counts().to_dict(),
            "output_file": str(output_path)
        }
        with open('data/logs/role_derivation_summary.json', 'w') as f:
            json.dump(summary, f, indent=2)
            
    except Exception as e:
        logger.error(f"Failed to save output: {e}")
        raise

def main():
    """Main entry point for T017."""
    logger.info("Starting T017: Functional Role Derivation & Validation")
    
    try:
        ensure_directories()
        
        # Load prerequisites
        logger.info("Loading marginal frequencies...")
        df_freq = load_marginal_frequencies()
        
        logger.info("Loading positional ranks...")
        df_ranks = load_positional_ranks()
        
        logger.info("Calculating functional roles...")
        result_df = calculate_functional_role(df_freq, df_ranks)
        
        logger.info("Saving output...")
        save_output(result_df)
        
        logger.info("T017 completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(f"Missing required input file: {e}")
        raise
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during T017 execution: {e}")
        raise

if __name__ == "__main__":
    main()
