# Import from belief_updater to access data loading utilities if needed
# Note: We assume the posterior samples are saved in a standard format by T024/T025
# The task description implies we use the output of T024 (belief_updater)
# We expect a file like data/models/posterior_samples.json or similar structure
# However, T027 (model_output) saves individual alpha parameters.
# We will load the alpha parameters from the model output generated by T027 (or T024 directly if T027 not run yet).
# Since T026 is before T027 in the dependency list provided in tasks.md (T026, then T028, then T027),
# we must rely on the raw posterior samples or intermediate results from T024.
# Let's assume T024 saves posterior samples to data/models/posterior_samples.json
# and we need to load the behavioral data to make predictions.

# Constants
ACCURACY_TARGET = 0.60

class PredictionError(Exception):
    """Custom exception for prediction failures."""
    pass

def load_posterior_samples(file_path: Path) -> Dict[str, Any]:
    """
    Load posterior samples from the model output.
    Expected format: JSON with participant IDs mapping to alpha samples.
    """
    if not file_path.exists():
        raise IOLoadError(f"Posterior samples file not found: {file_path}")
    
    try:
        with open(file_path, 'r') as f:
            data = json.load(f)
    except json.JSONDecodeError as e:
        raise IOLoadError(f"Failed to parse JSON from {file_path}: {e}")
    
    return data

def load_behavioral_data_for_prediction(file_path: Path) -> pd.DataFrame:
    """
    Load the behavioral data (choices, feedback, etc.) used for prediction.
    This should be the same data used for model fitting, but we only use the
    held-out portion for evaluation.
    """
    if not file_path.exists():
        raise IOLoadError(f"Behavioral data file not found: {file_path}")
    
    try:
        df = pd.read_csv(file_path)
    except Exception as e:
        raise IOLoadError(f"Failed to load CSV from {file_path}: {e}")
    
    return df

def predict_choice(alpha: float, discrepancy: float, choice_history: List[int]) -> int:
    """
    Predict the next choice based on alpha (learning rate), discrepancy, and history.
    
    This implements a simplified version of the belief updating rule:
    - Probability of choosing the option that matches the feedback tendency.
    - P(Choice=1) = sigmoid(alpha * discrepancy + bias)
    
    For simplicity in this prediction task, we use a deterministic threshold
    based on the learned alpha and the current discrepancy to simulate the participant's
    likely choice.
    
    Args:
        alpha: Learning rate parameter.
        discrepancy: The discrepancy between expected and actual feedback.
        choice_history: List of previous choices (0 or 1).
    
    Returns:
        Predicted choice (0 or 1).
    """
    # Simple logistic model for choice probability
    # P(choice=1) = 1 / (1 + exp(- (alpha * discrepancy)))
    # We add a small bias to avoid extreme probabilities if discrepancy is 0
    log_odds = alpha * discrepancy + 0.1
    prob_choice_1 = 1.0 / (1.0 + np.exp(-log_odds))
    
    # For held-out prediction, we can either sample or take the mode.
    # Taking the mode (most likely) is standard for accuracy calculation unless specified otherwise.
    # However, to be robust, we can simulate the stochasticity if the model is probabilistic.
    # Given the task is "generate held-out choice predictions", we'll use the probability directly
    # to make a deterministic prediction if prob > 0.5, else 0.
    return 1 if prob_choice_1 > 0.5 else 0

def generate_predictions(
    participant_id: str,
    alpha_samples: List[float],
    behavioral_data: pd.DataFrame,
    held_out_indices: Optional[List[int]] = None
) -> Tuple[List[int], List[int], List[float]]:
    """
    Generate choice predictions for held-out data.
    
    Args:
        participant_id: Unique identifier for the participant.
        alpha_samples: List of posterior samples for alpha.
        behavioral_data: DataFrame with choices, feedback, and discrepancy.
        held_out_indices: Indices of held-out trials. If None, use last 20% of trials.
    
    Returns:
        Tuple of (true_choices, predicted_choices, alpha_used)
    """
    if held_out_indices is None:
        n_total = len(behavioral_data)
        n_held_out = max(1, int(n_total * 0.2))
        held_out_indices = list(range(n_total - n_held_out, n_total))
    
    if not held_out_indices:
        raise PredictionError(f"No held-out indices for participant {participant_id}")
    
    # Use the mean of alpha samples for prediction
    alpha_mean = np.mean(alpha_samples)
    
    true_choices = []
    predicted_choices = []
    
    for idx in held_out_indices:
        row = behavioral_data.iloc[idx]
        
        # Extract necessary features
        # Assuming columns: 'choice', 'feedback', 'discrepancy'
        # If 'discrepancy' is not present, we might need to compute it from choice and feedback
        discrepancy = row.get('discrepancy', 0.0)
        true_choice = int(row['choice'])
        
        # Generate prediction
        pred_choice = predict_choice(alpha_mean, discrepancy, [])
        
        true_choices.append(true_choice)
        predicted_choices.append(pred_choice)
    
    return true_choices, predicted_choices, [alpha_mean] * len(true_choices)

def compute_accuracy(true_choices: List[int], predicted_choices: List[int]) -> float:
    """
    Compute prediction accuracy.
    
    Args:
        true_choices: List of actual choices.
        predicted_choices: List of predicted choices.
    
    Returns:
        Accuracy as a float between 0 and 1.
    """
    if not true_choices or not predicted_choices:
        return 0.0
    
    if len(true_choices) != len(predicted_choices):
        raise PredictionError("Mismatch in lengths of true and predicted choices")
    
    correct = sum(1 for t, p in zip(true_choices, predicted_choices) if t == p)
    return correct / len(true_choices)

def run_prediction_pipeline(
    config: Dict[str, Any],
    logger: logging.Logger
) -> Dict[str, Any]:
    """
    Run the full prediction pipeline for all participants.
    
    Args:
        config: Configuration dictionary.
        logger: Logger instance.
    
    Returns:
        Dictionary containing accuracy metrics and results.
    """
    data_dir = Path(config.get('data_dir', 'data'))
    model_dir = data_dir / 'models'
    results_dir = data_dir / 'predictions'
    ensure_dir(results_dir)
    
    # Load posterior samples (from T024/T025)
    posterior_file = model_dir / 'posterior_samples.json'
    if not posterior_file.exists():
        # Fallback: try to load from T027 output if T024 output is named differently
        # But per task order, T026 runs before T027, so we expect T024 output.
        # If T024 saved to a different location, we might need to adjust.
        # Let's assume standard location.
        logger.error(f"Posterior samples file not found at {posterior_file}")
        raise PredictionError("Posterior samples not found. Ensure T024/T025 completed.")
    
    posterior_data = load_posterior_samples(posterior_file)
    logger.info(f"Loaded posterior samples for {len(posterior_data)} participants")
    
    # Load behavioral data
    behavioral_file = data_dir / 'processed' / 'behavioral_data.csv'
    if not behavioral_file.exists():
        # Try raw if processed doesn't exist
        behavioral_file = data_dir / 'raw' / 'behavioral_data.csv'
    
    if not behavioral_file.exists():
        logger.error(f"Behavioral data file not found at {behavioral_file}")
        raise PredictionError("Behavioral data not found. Ensure T013/T014 completed.")
    
    behavioral_data = load_behavioral_data_for_prediction(behavioral_file)
    logger.info(f"Loaded behavioral data with {len(behavioral_data)} trials")
    
    results = {
        'participants': [],
        'global_accuracy': 0.0,
        'total_trials': 0,
        'correct_trials': 0,
        'target_met': False
    }
    
    all_true = []
    all_pred = []
    
    for participant_id, samples in posterior_data.items():
        if 'alpha' not in samples:
            logger.warning(f"Skipping participant {participant_id}: no alpha samples")
            continue
        
        alpha_samples = samples['alpha']
        
        # Filter behavioral data for this participant
        # Assuming 'participant_id' column exists
        if 'participant_id' not in behavioral_data.columns:
            # Try to infer from filename or assume single participant
            p_data = behavioral_data
        else:
            p_data = behavioral_data[behavioral_data['participant_id'] == participant_id]
        
        if p_data.empty:
            logger.warning(f"No behavioral data for participant {participant_id}")
            continue
        
        # Generate predictions
        try:
            true_choices, pred_choices, alphas_used = generate_predictions(
                participant_id, alpha_samples, p_data
            )
        except Exception as e:
            logger.error(f"Error generating predictions for {participant_id}: {e}")
            continue
        
        acc = compute_accuracy(true_choices, pred_choices)
        
        results['participants'].append({
            'participant_id': participant_id,
            'accuracy': acc,
            'n_trials': len(true_choices),
            'alpha_mean': float(np.mean(alphas_used))
        })
        
        all_true.extend(true_choices)
        all_pred.extend(pred_choices)
        
        logger.info(f"Participant {participant_id}: Accuracy = {acc:.3f} ({len(true_choices)} trials)")
    
    # Compute global accuracy
    if all_true and all_pred:
        global_acc = compute_accuracy(all_true, all_pred)
        results['global_accuracy'] = global_acc
        results['total_trials'] = len(all_true)
        results['correct_trials'] = sum(1 for t, p in zip(all_true, all_pred) if t == p)
        results['target_met'] = global_acc >= ACCURACY_TARGET
    else:
        logger.warning("No valid predictions generated across all participants.")
    
    return results

def main():
    """Main entry point for the prediction pipeline."""
    parser = argparse.ArgumentParser(description="Generate held-out choice predictions and compute accuracy.")
    parser.add_argument('--config', type=str, default='config.yaml', help='Path to config file')
    parser.add_argument('--seed', type=int, default=42, help='Random seed')
    args = parser.parse_args()
    
    # Setup logging
    log_dir = Path('data/logs')
    ensure_dir(log_dir)
    logger = get_logger('prediction')
    setup_file_logging(logger, log_dir / 'prediction.log')
    
    logger.info("Starting prediction pipeline (T026)")
    
    # Load config
    try:
        config = load_config_from_yaml(args.config)
    except Exception as e:
        logger.error(f"Failed to load config: {e}")
        sys.exit(1)
    
    # Set seed
    set_seed(config.get('seed', args.seed))
    
    try:
        results = run_prediction_pipeline(config, logger)
        
        # Save results
        output_file = Path('data/predictions/prediction_results.json')
        ensure_dir(output_file.parent)
        save_json(results, output_file)
        
        logger.info(f"Prediction results saved to {output_file}")
        logger.info(f"Global Accuracy: {results['global_accuracy']:.3f} (Target: {ACCURACY_TARGET})")
        logger.info(f"Target Met: {results['target_met']}")
        
        # Print summary to stdout for quick verification
        print(json.dumps(results, indent=2))
        
    except Exception as e:
        logger.exception("Prediction pipeline failed")
        sys.exit(1)

if __name__ == '__main__':
    main()