"""
QC Reporter for User Story 1.

Calculates the final exclusion rate against the SC-001 threshold (10% volumes > 3mm)
using the enforced set from T018, and generates data/reports/qc_summary.json
with stability metrics.
"""

import os
import json
import logging
from pathlib import Path
from typing import Dict, List, Optional, Any

import pandas as pd

# Import from existing API surface
from utils.io import ensure_dir, load_yaml, save_yaml, load_json, save_json
from utils.logger import get_logger

logger = get_logger(__name__)


class QCReportError(Exception):
    """Custom exception for QC reporting errors."""
    pass


def load_exclusion_data(exclusions_path: Path) -> Dict[str, Any]:
    """
    Load exclusion data from the state file generated by T013/T018.

    Args:
        exclusions_path: Path to state/exclusions.yaml

    Returns:
        Dictionary containing exclusion data.
    """
    if not exclusions_path.exists():
        raise QCReportError(f"Exclusions file not found: {exclusions_path}")

    try:
        data = load_yaml(exclusions_path)
        logger.info(f"Loaded exclusion data from {exclusions_path}")
        return data
    except Exception as e:
        raise QCReportError(f"Failed to load exclusions file: {e}")


def calculate_exclusion_rate(exclusions_data: Dict[str, Any], threshold: float = 0.10) -> Dict[str, Any]:
    """
    Calculate the exclusion rate against the SC-001 threshold.

    Args:
        exclusions_data: Dictionary containing exclusion data from T018.
        threshold: The exclusion threshold (default 10% = 0.10).

    Returns:
        Dictionary with exclusion metrics.
    """
    total_participants = exclusions_data.get('total_participants', 0)
    excluded_participants = exclusions_data.get('excluded_participants', [])
    included_participants = exclusions_data.get('included_participants', [])

    if total_participants == 0:
        logger.warning("Total participants is 0, cannot calculate exclusion rate.")
        return {
            'total_participants': 0,
            'excluded_count': 0,
            'included_count': 0,
            'exclusion_rate': 0.0,
            'threshold': threshold,
            'reasons': {}
        }

    excluded_count = len(excluded_participants)
    included_count = len(included_participants)

    # Verify counts match total
    if excluded_count + included_count != total_participants:
        logger.warning(
            f"Exclusion counts mismatch: excluded ({excluded_count}) + included ({included_count}) "
            f"!= total ({total_participants}). Using actual counts."
        )
        # Use the sum as the effective total for rate calculation
        effective_total = excluded_count + included_count
        exclusion_rate = excluded_count / effective_total if effective_total > 0 else 0.0
    else:
        exclusion_rate = excluded_count / total_participants if total_participants > 0 else 0.0

    # Aggregate exclusion reasons
    reasons: Dict[str, int] = {}
    for exc in excluded_participants:
        reason = exc.get('reason', 'unknown')
        reasons[reason] = reasons.get(reason, 0) + 1

    return {
        'total_participants': total_participants,
        'excluded_count': excluded_count,
        'included_count': included_count,
        'exclusion_rate': round(exclusion_rate, 4),
        'threshold': threshold,
        'threshold_exceeded': exclusion_rate > threshold,
        'reasons': reasons,
        'excluded_ids': [exc.get('participant_id') for exc in excluded_participants],
        'included_ids': [p.get('participant_id') for p in included_participants]
    }


def assess_stability(exclusions_data: Dict[str, Any]) -> Dict[str, Any]:
    """
    Assess stability metrics based on exclusion data.

    This calculates metrics to determine if the QC process is stable,
    e.g., consistency of exclusion rates across batches or time.

    Args:
        exclusions_data: Dictionary containing exclusion data.

    Returns:
        Dictionary with stability metrics.
    """
    # For this implementation, we assess stability based on the distribution
    # of motion metrics among excluded vs included participants.
    # We assume the exclusions_data contains per-participant motion metrics
    # if available from T018.

    metrics = {
        'stability_score': 1.0,  # Default to stable
        'notes': 'Initial stability assessment based on exclusion distribution.',
        'variance_in_exclusions': 0.0
    }

    excluded = exclusions_data.get('excluded_participants', [])
    included = exclusions_data.get('included_participants', [])

    if not excluded and not included:
        return metrics

    # Check if we have motion metrics in the exclusion data
    # Assuming T018 wrote motion metrics to the exclusions file
    motion_values_excluded = []
    motion_values_included = []

    for exc in excluded:
        # Try to extract motion metric (e.g., 'max_fd' or 'pct_high_motion')
        if 'motion_metrics' in exc:
            mm = exc['motion_metrics']
            if 'pct_high_motion' in mm:
                motion_values_excluded.append(mm['pct_high_motion'])
        elif 'pct_high_motion' in exc:
            motion_values_excluded.append(exc['pct_high_motion'])

    for inc in included:
        if 'motion_metrics' in inc:
            mm = inc['motion_metrics']
            if 'pct_high_motion' in mm:
                motion_values_included.append(mm['pct_high_motion'])
        elif 'pct_high_motion' in inc:
            motion_values_included.append(inc['pct_high_motion'])

    if motion_values_excluded and motion_values_included:
        # Calculate a simple stability score based on separation
        import numpy as np
        mean_excl = np.mean(motion_values_excluded)
        mean_incl = np.mean(motion_values_included)
        std_excl = np.std(motion_values_excluded) if len(motion_values_excluded) > 1 else 0.0
        std_incl = np.std(motion_values_included) if len(motion_values_included) > 1 else 0.0

        # If the means are well separated relative to standard deviations, it's stable
        if std_excl > 0 and std_incl > 0:
            separation = (mean_excl - mean_incl) / (std_excl + std_incl)
            metrics['separation_score'] = float(separation)
            if separation > 1.0:
                metrics['stability_score'] = 1.0
                metrics['notes'] = 'High separation between excluded and included motion metrics.'
            elif separation > 0.5:
                metrics['stability_score'] = 0.8
                metrics['notes'] = 'Moderate separation between excluded and included motion metrics.'
            else:
                metrics['stability_score'] = 0.5
                metrics['notes'] = 'Low separation; QC threshold may need review.'
        else:
            metrics['notes'] = 'Could not compute separation due to zero variance in motion metrics.'
    else:
        metrics['notes'] = 'Motion metrics not found in exclusion data for stability assessment.'

    return metrics


def generate_qc_summary(exclusions_path: Path, output_path: Path, threshold: float = 0.10) -> Dict[str, Any]:
    """
    Generate the QC summary report.

    Args:
        exclusions_path: Path to state/exclusions.yaml.
        output_path: Path to write data/reports/qc_summary.json.
        threshold: The exclusion threshold (default 0.10).

    Returns:
        The generated summary dictionary.
    """
    ensure_dir(output_path.parent)

    # Load exclusion data
    exclusions_data = load_exclusion_data(exclusions_path)

    # Calculate exclusion rate
    exclusion_metrics = calculate_exclusion_rate(exclusions_data, threshold)

    # Assess stability
    stability_metrics = assess_stability(exclusions_data)

    # Compile summary
    summary = {
        'report_type': 'QC_Exclusion_Summary',
        'threshold': threshold,
        'exclusion_metrics': exclusion_metrics,
        'stability_metrics': stability_metrics,
        'generated_at': pd.Timestamp.now().isoformat(),
        'source_file': str(exclusions_path)
    }

    # Save to JSON
    save_json(summary, output_path)
    logger.info(f"QC summary written to {output_path}")

    return summary


def main():
    """Main entry point for QC reporting."""
    import argparse

    parser = argparse.ArgumentParser(description="Generate QC exclusion summary report.")
    parser.add_argument(
        "--exclusions",
        type=str,
        default="state/exclusions.yaml",
        help="Path to exclusions file (default: state/exclusions.yaml)"
    )
    parser.add_argument(
        "--output",
        type=str,
        default="data/reports/qc_summary.json",
        help="Path to output JSON file (default: data/reports/qc_summary.json)"
    )
    parser.add_argument(
        "--threshold",
        type=float,
        default=0.10,
        help="Exclusion threshold (default: 0.10)"
    )

    args = parser.parse_args()

    logger.info("Starting QC reporting")

    exclusions_path = Path(args.exclusions)
    output_path = Path(args.output)

    try:
        summary = generate_qc_summary(exclusions_path, output_path, args.threshold)
        logger.info("QC reporting completed successfully")
        print(json.dumps(summary, indent=2))
    except QCReportError as e:
        logger.error(f"QC reporting failed: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during QC reporting: {e}")
        raise


if __name__ == "__main__":
    main()
