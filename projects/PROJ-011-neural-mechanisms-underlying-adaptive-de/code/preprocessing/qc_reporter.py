# Constants
SC_001_THRESHOLD = 0.10  # 10% volumes exceeding 3mm translation

logger = get_logger(__name__)


class QCReportError(Exception):
    """Custom exception for QC reporting failures."""
    pass


def load_exclusion_data(exclusions_path: Path) -> Dict[str, Any]:
    """
    Load exclusion data from the state/exclusions.yaml file generated by T013/T018.

    Args:
        exclusions_path: Path to state/exclusions.yaml

    Returns:
        Dictionary containing exclusion reasons and participant lists.

    Raises:
        IOLoadError: If the file cannot be loaded or parsed.
    """
    try:
        if not exclusions_path.exists():
            raise IOLoadError(f"Exclusions file not found: {exclusions_path}")
        
        data = load_yaml(exclusions_path)
        logger.info(f"Loaded exclusion data from {exclusions_path}")
        return data
    except Exception as e:
        raise IOLoadError(f"Failed to load exclusions data: {e}")


def calculate_exclusion_rate(exclusions_data: Dict[str, Any], threshold: float = SC_001_THRESHOLD) -> Dict[str, float]:
    """
    Calculate the exclusion rate based on SC-001 threshold.

    Args:
        exclusions_data: Dictionary containing exclusion information.
        threshold: The threshold fraction of high-motion volumes (default 0.10).

    Returns:
        Dictionary with 'total_participants', 'excluded_count', 'exclusion_rate',
        and 'threshold_used'.
    """
    # Extract participant counts
    all_participants = exclusions_data.get("all_participants", [])
    excluded_participants = exclusions_data.get("excluded_participants", [])
    
    total_count = len(all_participants)
    excluded_count = len(excluded_participants)
    
    if total_count == 0:
        logger.warning("No participants found in exclusion data. Rate is 0.0.")
        return {
            "total_participants": 0,
            "excluded_count": 0,
            "exclusion_rate": 0.0,
            "threshold_used": threshold
        }
    
    exclusion_rate = excluded_count / total_count
    
    logger.info(f"Exclusion Rate: {excluded_count}/{total_count} = {exclusion_rate:.4f}")
    
    return {
        "total_participants": total_count,
        "excluded_count": excluded_count,
        "exclusion_rate": exclusion_rate,
        "threshold_used": threshold
    }


def assess_stability(exclusions_data: Dict[str, Any], exclusion_rate: float, threshold: float = SC_001_THRESHOLD) -> Dict[str, Any]:
    """
    Assess the stability of the exclusion process.
    
    Stability is defined as:
    1. Whether the exclusion rate is within an acceptable range (not 100% or 0% unless expected).
    2. Whether the primary reason for exclusion is consistent (SC-001 motion).

    Args:
        exclusions_data: Dictionary containing exclusion details.
        exclusion_rate: Calculated exclusion rate.
        threshold: The SC-001 threshold.

    Returns:
        Dictionary with stability metrics and status.
    """
    reasons = exclusions_data.get("reasons", {})
    excluded_list = exclusions_data.get("excluded_participants", [])
    
    # Count exclusions specifically due to motion (SC-001)
    motion_exclusions = 0
    other_exclusions = 0
    
    for p_id, reason in reasons.items():
        if "motion" in str(reason).lower() or "SC-001" in str(reason):
            motion_exclusions += 1
        else:
            other_exclusions += 1
    
    total_excluded = motion_exclusions + other_exclusions
    
    stability_status = "STABLE"
    stability_notes = []

    # Check if all exclusions are due to motion (good stability for this specific task)
    if total_excluded > 0:
        motion_ratio = motion_exclusions / total_excluded
        if motion_ratio < 0.9:
            stability_status = "UNSTABLE"
            stability_notes.append(f"Only {motion_ratio:.2%} of exclusions are due to motion (SC-001).")
    else:
        stability_notes.append("No participants excluded.")

    # Check extreme rates
    if exclusion_rate == 1.0:
        stability_status = "CRITICAL"
        stability_notes.append("100% exclusion rate. Data quality may be insufficient.")
    elif exclusion_rate == 0.0 and len(exclusions_data.get("all_participants", [])) > 0:
        stability_notes.append("0% exclusion rate. Verify QC thresholds are active.")

    return {
        "status": stability_status,
        "notes": stability_notes,
        "motion_exclusion_count": motion_exclusions,
        "other_exclusion_count": other_exclusions,
        "motion_exclusion_ratio": motion_exclusions / total_excluded if total_excluded > 0 else 0.0
    }


def generate_qc_summary(
    exclusions_path: Path,
    output_path: Path,
    threshold: float = SC_001_THRESHOLD
) -> Path:
    """
    Generate the final QC summary report.

    Args:
        exclusions_path: Path to state/exclusions.yaml.
        output_path: Path where qc_summary.json will be written.
        threshold: The SC-001 threshold.

    Returns:
        Path to the generated report.

    Raises:
        QCReportError: If report generation fails.
    """
    ensure_dir(output_path.parent)
    
    try:
        # 1. Load Data
        exclusions_data = load_exclusion_data(exclusions_path)
        
        # 2. Calculate Metrics
        rate_metrics = calculate_exclusion_rate(exclusions_data, threshold)
        stability_metrics = assess_stability(exclusions_data, rate_metrics["exclusion_rate"], threshold)
        
        # 3. Compile Report
        report = {
            "report_type": "QC_Summary_SC001",
            "threshold": threshold,
            "exclusion_statistics": rate_metrics,
            "stability_assessment": stability_metrics,
            "excluded_participant_ids": exclusions_data.get("excluded_participants", []),
            "reasons": exclusions_data.get("reasons", {}),
            "generated_at": str(Path(output_path).parent.parent) # Placeholder for timestamp if needed, or use actual time
        }
        
        # Add specific SC-001 context
        report["sc_001_compliance"] = {
            "threshold_description": "Exclude participants with >10% volumes exceeding 3mm translation",
            "passed": rate_metrics["exclusion_rate"] < 0.50 # Arbitrary 'passed' logic for report, or just report rate
        }

        # 4. Write to Disk
        save_json(report, output_path)
        logger.info(f"QC Summary report generated at {output_path}")
        
        return output_path
        
    except IOLoadError as e:
        logger.error(f"Failed to load data for QC report: {e}")
        raise QCReportError(f"Data loading failed: {e}")
    except Exception as e:
        logger.error(f"Failed to generate QC report: {e}")
        raise QCReportError(f"Report generation failed: {e}")


