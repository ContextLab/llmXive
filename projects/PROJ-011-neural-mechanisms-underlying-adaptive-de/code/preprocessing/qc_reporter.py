"""
QC Reporter Module (Task T018b)

Calculates the final exclusion rate against the SC-001 threshold (10% volumes > 3mm)
and reports stability in data/reports/qc_summary.json.

This module consumes the exclusion metrics generated by `qc_filter.py` and
aggregates them into a final report.
"""
import os
import json
from pathlib import Path
from typing import Dict, List, Optional, Any

import pandas as pd

# Import from project utils
from utils.io import IOLoadError, ensure_dir, load_json, save_json, load_yaml
from utils.config import get_config
from utils.logger import get_logger

# Import from sibling preprocessing module
from preprocessing.qc_filter import calculate_motion_exclusion_metrics

logger = get_logger(__name__)

# Constants
SC_001_THRESHOLD_PERCENT = 10.0  # 10% volumes exceeding 3mm translation
TRANSLATION_THRESHOLD_MM = 3.0

def load_exclusion_data(qc_metrics_path: Path) -> Dict[str, Any]:
    """
    Load the exclusion metrics generated by qc_filter.py.
    
    Args:
        qc_metrics_path: Path to the qc_metrics.json file.
        
    Returns:
        Dictionary containing participant exclusion data.
        
    Raises:
        IOLoadError: If the file cannot be read or parsed.
    """
    if not qc_metrics_path.exists():
        raise IOLoadError(f"QC metrics file not found: {qc_metrics_path}")
    
    try:
        data = load_json(qc_metrics_path)
        return data
    except Exception as e:
        raise IOLoadError(f"Failed to load QC metrics from {qc_metrics_path}: {e}")

def calculate_exclusion_rate(metrics: Dict[str, Any]) -> float:
    """
    Calculate the percentage of participants excluded based on SC-001.
    
    SC-001: Exclude participants with >10% volumes exceeding 3mm translation.
    
    Args:
        metrics: The loaded QC metrics dictionary.
        
    Returns:
        The exclusion rate as a percentage (0.0 to 100.0).
    """
    participants = metrics.get("participants", [])
    
    if not participants:
        return 0.0
    
    total_count = len(participants)
    excluded_count = sum(1 for p in participants if p.get("excluded", False))
    
    if total_count == 0:
        return 0.0
        
    return (excluded_count / total_count) * 100.0

def assess_stability(metrics: Dict[str, Any]) -> Dict[str, Any]:
    """
    Assess the stability of the QC process.
    
    Checks if the exclusion rate is consistent with expectations and
    if the data distribution is stable.
    
    Args:
        metrics: The loaded QC metrics dictionary.
        
    Returns:
        Dictionary containing stability assessment results.
    """
    participants = metrics.get("participants", [])
    if not participants:
        return {
            "is_stable": False,
            "reason": "No participants found in metrics.",
            "exclusion_rate": 0.0
        }
    
    excluded_count = sum(1 for p in participants if p.get("excluded", False))
    total_count = len(participants)
    exclusion_rate = (excluded_count / total_count) * 100.0
    
    # Stability heuristic: 
    # If exclusion rate is extremely high (>50%) or extremely low (0%) 
    # with a large sample, it might indicate a data issue, but strictly
    # speaking, stability here refers to the reproducibility of the metric.
    # We mark it stable if we have enough data to make a decision.
    is_stable = True
    reason = "Exclusion rate calculated successfully."
    
    if total_count < 3:
        is_stable = False
        reason = "Insufficient sample size (N < 3) for stable exclusion rate estimation."
    elif exclusion_rate == 100.0:
        is_stable = False # Could be data quality issue
        reason = "100% exclusion rate detected; verify data integrity."
    elif exclusion_rate == 0.0 and total_count > 10:
        # Unusual to have 0% exclusion in a real fMRI dataset, but not impossible.
        # We flag it for review but don't necessarily mark unstable if it's a clean dataset.
        reason = "0% exclusion rate; verify that motion correction was applied correctly."
    
    return {
        "is_stable": is_stable,
        "reason": reason,
        "exclusion_rate": exclusion_rate,
        "total_participants": total_count,
        "excluded_participants": excluded_count
    }

def generate_qc_summary(qc_metrics_path: Path, output_path: Path) -> Dict[str, Any]:
    """
    Generate the final QC summary report.
    
    Args:
        qc_metrics_path: Path to the qc_metrics.json file from qc_filter.py.
        output_path: Path where qc_summary.json will be saved.
        
    Returns:
        The generated summary dictionary.
    """
    logger.info(f"Loading exclusion data from {qc_metrics_path}")
    metrics = load_exclusion_data(qc_metrics_path)
    
    exclusion_rate = calculate_exclusion_rate(metrics)
    stability_assessment = assess_stability(metrics)
    
    summary = {
        "task_id": "T018b",
        "threshold_sc_001": {
            "type": "motion",
            "description": "Exclude participants with >10% volumes exceeding 3mm translation",
            "volume_threshold_percent": SC_001_THRESHOLD_PERCENT,
            "translation_threshold_mm": TRANSLATION_THRESHOLD_MM
        },
        "results": {
            "total_participants_analyzed": stability_assessment["total_participants"],
            "excluded_participants": stability_assessment["excluded_participants"],
            "exclusion_rate_percent": round(exclusion_rate, 2),
            "passed_participants": stability_assessment["total_participants"] - stability_assessment["excluded_participants"]
        },
        "stability": {
            "is_stable": stability_assessment["is_stable"],
            "assessment_reason": stability_assessment["reason"]
        },
        "timestamp": metrics.get("timestamp", "unknown")
    }
    
    logger.info(f"Saving QC summary to {output_path}")
    ensure_dir(output_path)
    save_json(summary, output_path)
    
    logger.info(f"QC Summary Report Generated: {exclusion_rate:.2f}% exclusion rate")
    
    return summary

def main():
    """
    Entry point for the QC Reporter.
    
    Reads the qc_metrics.json generated by qc_filter.py and produces
    data/reports/qc_summary.json.
    """
    config = get_config()
    
    # Determine paths based on config or defaults
    base_dir = Path(config.get("data_dir", "data"))
    qc_metrics_path = base_dir / "processed" / "qc_metrics.json"
    output_dir = base_dir / "reports"
    output_path = output_dir / "qc_summary.json"
    
    # Allow override via environment or args if needed, but defaults are standard
    if os.environ.get("QC_METRICS_PATH"):
        qc_metrics_path = Path(os.environ["QC_METRICS_PATH"])
    if os.environ.get("QC_SUMMARY_PATH"):
        output_path = Path(os.environ["QC_SUMMARY_PATH"])
    
    logger.info("Starting QC Reporter (T018b)...")
    
    try:
        generate_qc_summary(qc_metrics_path, output_path)
        logger.info("QC Reporter completed successfully.")
    except IOLoadError as e:
        logger.error(f"Failed to load data: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during QC reporting: {e}")
        raise

if __name__ == "__main__":
    main()