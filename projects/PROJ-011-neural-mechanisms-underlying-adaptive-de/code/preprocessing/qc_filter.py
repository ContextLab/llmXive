"""
QC Filter Module for fMRI Preprocessing Pipeline.

This module implements Subject Criteria 001 (SC-001):
Exclude participants with >10% of volumes exceeding 3mm translation.

It reads the framewise displacement (FD) or motion parameter logs generated
by motion_correction.py, calculates the percentage of high-motion volumes,
and produces a filtered list of valid participants.
"""
import os
import numpy as np
import pandas as pd
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Any

from utils.io import IOLoadError, ensure_dir, file_exists, load_json, save_json, load_yaml, save_yaml
from utils.config import get_config
from utils.logger import get_logger

# Constants for SC-001
DEFAULT_THRESHOLD_PERCENTAGE = 0.10  # 10%
DEFAULT_THRESHOLD_TRANSLATION_MM = 3.0  # 3mm translation

logger = get_logger(__name__)


def calculate_motion_exclusion_metrics(
    motion_log_path: Path,
    threshold_percentage: float = DEFAULT_THRESHOLD_PERCENTAGE,
    threshold_translation_mm: float = DEFAULT_THRESHOLD_TRANSLATION_MM
) -> Tuple[bool, Dict[str, Any]]:
    """
    Analyze a participant's motion log to determine if they meet SC-001 criteria.

    Args:
        motion_log_path: Path to the motion parameters CSV (generated by motion_correction.py).
        threshold_percentage: Maximum allowed percentage of volumes exceeding threshold.
        threshold_translation_mm: Translation threshold in mm (combined or max axis).

    Returns:
        Tuple of (is_valid, metrics_dict)
        is_valid: True if the participant passes QC, False otherwise.
        metrics_dict: Contains total volumes, high_motion_volumes, percentage, and reason.
    """
    if not file_exists(motion_log_path):
        raise IOLoadError(f"Motion log not found: {motion_log_path}")

    try:
        df = pd.read_csv(motion_log_path)
    except Exception as e:
        raise IOLoadError(f"Failed to load motion log {motion_log_path}: {e}")

    # Identify motion columns. Expected columns from motion_correction.py:
    # 'trans_x', 'trans_y', 'trans_z', 'rot_x', 'rot_y', 'rot_z' or similar.
    # We look for translation columns specifically for the 3mm threshold.
    trans_cols = [c for c in df.columns if 'trans' in c.lower()]
    
    if not trans_cols:
        # Fallback: try to infer or use absolute displacement if available
        if 'fd' in df.columns or 'framewise_displacement' in df.columns:
            # If FD is available, we might use it, but SC-001 specifies translation.
            # We'll assume the presence of translation columns is mandatory for this specific check.
            # If not found, we treat it as a failure to validate.
            logger.warning(f"Translation columns not found in {motion_log_path}. Columns found: {df.columns}")
            raise IOLoadError("Translation columns (trans_x, trans_y, trans_z) not found in motion log.")
        else:
            raise IOLoadError("No motion data found in log.")

    # Calculate absolute displacement for each volume across the 3 translation axes
    # We check if ANY axis exceeds the threshold for a given volume
    max_translation = df[trans_cols].abs().max(axis=1)
    
    # Identify volumes exceeding the threshold
    high_motion_mask = max_translation > threshold_translation_mm
    total_volumes = len(df)
    high_motion_volumes = high_motion_mask.sum()
    
    if total_volumes == 0:
        raise IOLoadError(f"Motion log {motion_log_path} is empty.")

    percentage_high_motion = high_motion_volumes / total_volumes
    is_valid = percentage_high_motion <= threshold_percentage

    metrics = {
        "total_volumes": int(total_volumes),
        "high_motion_volumes": int(high_motion_volumes),
        "percentage_high_motion": float(percentage_high_motion),
        "threshold_percentage": threshold_percentage,
        "threshold_translation_mm": threshold_translation_mm,
        "is_valid": is_valid,
        "reason": "Pass" if is_valid else f"Exceeded {threshold_percentage*100}% high-motion volumes ({percentage_high_motion*100:.2f}% > {threshold_translation_mm}mm)"
    }

    return is_valid, metrics


def apply_qc_filter(
    participants_dir: Path,
    processed_dir: Path,
    exclusion_log_path: Path,
    threshold_percentage: float = DEFAULT_THRESHOLD_PERCENTAGE,
    threshold_translation_mm: float = DEFAULT_THRESHOLD_TRANSLATION_MM
) -> Dict[str, List[str]]:
    """
    Iterate through all participants, apply SC-001, and generate exclusion reports.

    Args:
        participants_dir: Path to the directory containing participant folders (e.g., data/processed/participants).
        processed_dir: Path to the directory where QC reports will be saved.
        exclusion_log_path: Path to the YAML file to store exclusion reasons.
        threshold_percentage: Max % of volumes allowed to exceed threshold.
        threshold_translation_mm: Translation threshold in mm.

    Returns:
        Dictionary with keys 'included' and 'excluded' containing lists of participant IDs.
    """
    ensure_dir(processed_dir)
    ensure_dir(exclusion_log_path.parent)

    participants = [p for p in participants_dir.iterdir() if p.is_dir()]
    included_ids = []
    excluded_ids = []
    exclusion_details = []

    logger.info(f"Scanning {len(participants)} participants for SC-001 QC filter...")

    for participant_path in sorted(participants):
        participant_id = participant_path.name
        motion_log_path = participant_path / "motion_parameters.csv"
        
        # Check if motion log exists (should be created by T014)
        if not file_exists(motion_log_path):
            logger.warning(f"Participant {participant_id}: Motion log missing. Skipping QC check (assuming exclusion).")
            excluded_ids.append(participant_id)
            exclusion_details.append({
                "participant_id": participant_id,
                "status": "excluded",
                "reason": "Motion log not found"
            })
            continue

        try:
            is_valid, metrics = calculate_motion_exclusion_metrics(
                motion_log_path, 
                threshold_percentage, 
                threshold_translation_mm
            )
            
            # Save individual QC report
            qc_report_path = processed_dir / f"qc_report_{participant_id}.json"
            save_json(metrics, qc_report_path)
            
            if is_valid:
                included_ids.append(participant_id)
                metrics["status"] = "included"
                exclusion_details.append(metrics)
                logger.info(f"Participant {participant_id}: INCLUDED (High motion: {metrics['percentage_high_motion']*100:.2f}%)")
            else:
                excluded_ids.append(participant_id)
                metrics["status"] = "excluded"
                exclusion_details.append(metrics)
                logger.info(f"Participant {participant_id}: EXCLUDED - {metrics['reason']}")

        except IOLoadError as e:
            logger.error(f"Participant {participant_id}: QC Check Failed - {e}")
            excluded_ids.append(participant_id)
            exclusion_details.append({
                "participant_id": participant_id,
                "status": "excluded",
                "reason": str(e)
            })
        except Exception as e:
            logger.error(f"Participant {participant_id}: Unexpected error during QC - {e}")
            excluded_ids.append(participant_id)
            exclusion_details.append({
                "participant_id": participant_id,
                "status": "excluded",
                "reason": f"Unexpected error: {str(e)}"
            })

    # Write final exclusion log
    summary = {
        "total_participants": len(participants),
        "included_count": len(included_ids),
        "excluded_count": len(excluded_ids),
        "threshold_percentage": threshold_percentage,
        "threshold_translation_mm": threshold_translation_mm,
        "details": exclusion_details
    }
    save_yaml(summary, exclusion_log_path)
    logger.info(f"QC Filter complete. Included: {len(included_ids)}, Excluded: {len(excluded_ids)}. Report saved to {exclusion_log_path}")

    return {
        "included": included_ids,
        "excluded": excluded_ids
    }


def main():
    """
    Entry point for running the QC Filter pipeline.
    Reads configuration from utils.config and executes the filter.
    """
    config = get_config()
    
    # Define paths based on config or defaults
    # Assuming standard project structure: data/processed/participants
    base_data_dir = Path(config.get("data_dir", "data"))
    processed_dir = base_data_dir / "processed"
    participants_dir = processed_dir / "participants"
    
    # Ensure directories exist
    ensure_dir(processed_dir)
    
    qc_output_dir = processed_dir / "qc_reports"
    exclusion_log_path = Path(config.get("state_dir", "state")) / "exclusions.yaml"
    
    # Ensure state directory exists
    ensure_dir(exclusion_log_path.parent)

    logger.info("Starting QC Filter (SC-001)...")
    
    try:
        result = apply_qc_filter(
            participants_dir=participants_dir,
            processed_dir=qc_output_dir,
            exclusion_log_path=exclusion_log_path,
            threshold_percentage=config.get("qc_threshold_percentage", DEFAULT_THRESHOLD_PERCENTAGE),
            threshold_translation_mm=config.get("qc_threshold_translation_mm", DEFAULT_THRESHOLD_TRANSLATION_MM)
        )
        
        logger.info(f"Pipeline finished. Valid participants: {result['included']}")
        return result

    except Exception as e:
        logger.error(f"QC Filter pipeline failed: {e}")
        raise

if __name__ == "__main__":
    main()
