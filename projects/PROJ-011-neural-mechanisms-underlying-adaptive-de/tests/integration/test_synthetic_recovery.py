"""
Integration test for synthetic data recovery (US2).

This test validates that the hierarchical Bayesian belief updater model
can recover ground-truth parameters from synthetic data generated by a
distinct process with different noise characteristics.

The test:
1. Generates synthetic behavioral data using a ground-truth alpha.
2. Fits the belief updater model to this data.
3. Verifies that the posterior mean of alpha is within a defined error margin
   of the ground truth.
"""
import os
import sys
import tempfile
from pathlib import Path
import numpy as np
import pytest

# Add project root to path for imports
project_root = Path(__file__).parent.parent.parent
sys.path.insert(0, str(project_root / "code"))

from utils.config import set_seed
from modeling.synthetic_data_generator import generate_synthetic_belief_data
from modeling.belief_updater import run_belief_updater_model
from modeling.validation import check_convergence


@pytest.fixture
def temp_output_dir():
    """Create a temporary directory for test outputs."""
    with tempfile.TemporaryDirectory() as tmpdir:
        yield Path(tmpdir)


def test_synthetic_alpha_recovery(temp_output_dir):
    """
    Test that the model recovers ground-truth alpha from synthetic data.

    This satisfies the requirement that the model be tested on synthetic data
    generated from a *different* generative process to ensure robustness.
    """
    # Set seed for reproducibility
    set_seed(42)

    # Ground truth parameters (known to the generator, unknown to the model)
    true_alpha = 0.75
    true_beta = 2.0
    n_trials = 100
    n_subjects = 5  # Small number for integration test speed

    # Generate synthetic data
    # Note: The generator uses a specific noise model; the fitting model
    # uses a different noise assumption (hierarchical Bayesian) to test robustness.
    synthetic_data = generate_synthetic_belief_data(
        n_subjects=n_subjects,
        n_trials=n_trials,
        true_alpha=true_alpha,
        true_beta=true_beta,
        output_dir=temp_output_dir
    )

    # Verify data was written
    assert synthetic_data["choices_file"].exists(), "Choices file not created"
    assert synthetic_data["feedback_file"].exists(), "Feedback file not created"

    # Run the belief updater model on the synthetic data
    model_output = run_belief_updater_model(
        choices_path=synthetic_data["choices_file"],
        feedback_path=synthetic_data["feedback_file"],
        output_dir=temp_output_dir,
        n_chains=2,
        n_samples=500,  # Reduced for test speed
        n_warmup=250,
        seed=42
    )

    # Check that the model produced output
    assert "alpha_samples" in model_output, "Model did not produce alpha samples"
    assert "convergence_data" in model_output, "Model did not produce convergence data"

    # Verify convergence
    convergence_result = check_convergence(model_output["convergence_data"])
    assert convergence_result["converged"], "Model failed to converge on synthetic data"

    # Extract posterior mean for alpha
    # The model returns a dictionary of samples per subject
    # We expect the mean of the posterior to be close to true_alpha
    alpha_posterior_mean = np.mean(model_output["alpha_samples"])

    # Define acceptable error margin (e.g., 15% relative error)
    # This accounts for the fact that we are using a different noise model
    # and a relatively small sample size for the test.
    error_margin = 0.15 * true_alpha
    recovered_alpha = alpha_posterior_mean

    # Assert recovery within margin
    assert abs(recovered_alpha - true_alpha) <= error_margin, (
        f"Failed to recover true alpha ({true_alpha}). "
        f"Recovered: {recovered_alpha:.3f}, Error: {abs(recovered_alpha - true_alpha):.3f}, "
        f"Margin: {error_margin:.3f}"
    )

    # Log results for manual inspection if needed
    print(f"Ground Truth Alpha: {true_alpha}")
    print(f"Recovered Alpha (Posterior Mean): {recovered_alpha:.3f}")
    print(f"Absolute Error: {abs(recovered_alpha - true_alpha):.3f}")
    print(f"Convergence Status: {convergence_result['converged']}")
    print(f"R-hat: {convergence_result.get('r_hat', 'N/A')}")

def test_synthetic_data_structure(temp_output_dir):
    """
    Test that the synthetic data generator produces correctly structured files.
    """
    set_seed(123)

    true_alpha = 0.5
    n_subjects = 2
    n_trials = 50

    synthetic_data = generate_synthetic_belief_data(
        n_subjects=n_subjects,
        n_trials=n_trials,
        true_alpha=true_alpha,
        true_beta=1.5,
        output_dir=temp_output_dir
    )

    # Check file existence
    assert synthetic_data["choices_file"].exists()
    assert synthetic_data["feedback_file"].exists()

    # Check file contents (basic validation)
    import pandas as pd
    choices_df = pd.read_csv(synthetic_data["choices_file"])
    feedback_df = pd.read_csv(synthetic_data["feedback_file"])

    # Verify columns
    assert "subject_id" in choices_df.columns
    assert "trial_id" in choices_df.columns
    assert "choice" in choices_df.columns

    assert "subject_id" in feedback_df.columns
    assert "trial_id" in feedback_df.columns
    assert "feedback" in feedback_df.columns

    # Verify row counts
    assert len(choices_df) == n_subjects * n_trials
    assert len(feedback_df) == n_subjects * n_trials

    # Verify choice values are binary (0 or 1)
    assert choices_df["choice"].isin([0, 1]).all()
    # Verify feedback values are binary (-1 or 1)
    assert feedback_df["feedback"].isin([-1, 1]).all()