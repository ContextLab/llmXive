def test_t028_filters_convergence_failures(temp_state_dir):
    """
    Test that T028 logic correctly excludes participants listed in failure_log.json.
    """
    state_dir, data_dir = temp_state_dir

    # Mock T025b Output: Convergence Report
    conv_report = {
        "participants": {
            "sub-01": {"converged": True, "r_hat": 1.0},
            "sub-02": {"converged": True, "r_hat": 1.0},
            "sub-03": {"converged": False, "r_hat": 1.5}, # Failed
            "sub-04": {"converged": True, "r_hat": 1.0}
        }
    }
    conv_path = data_dir / "convergence_report.json"
    with open(conv_path, "w") as f:
        json.dump(conv_report, f)

    # Mock T025c Output: Failure Log
    failure_log = {
        "failed_participants": ["sub-03"],
        "reason": "Max iterations exceeded"
    }
    fail_path = data_dir / "failure_log.json"
    with open(fail_path, "w") as f:
        json.dump(failure_log, f)

    # Mock T024a Output: N_valid
    n_valid_data = {"N_valid": 4}
    n_valid_path = state_dir / "n_valid.yaml"
    with open(n_valid_path, "w") as f:
        yaml.dump(n_valid_data, f)

    # Mock T018b Output: Exclusions (Motion)
    exclusions_data = {
        "excluded_participants": {} # No motion exclusions for this test
    }
    exc_path = state_dir / "exclusions.yaml"
    with open(exc_path, "w") as f:
        yaml.dump(exclusions_data, f)

    # --- Execute T028 Logic (Inline for test isolation) ---
    # This replicates the logic in main.py run_p2_integration() for T028
    import json as json_mod
    import yaml as yaml_mod
    from utils.io import load_json, load_yaml, save_yaml, ensure_dir

    # 1. Load Convergence Report
    conv_report_loaded = load_json(conv_path)
    
    # 2. Load Failure Log
    failed_ids = set()
    if fail_path.exists():
        failure_data = load_json(fail_path)
        failed_ids = set(failure_data.get("failed_participants", []))
    
    # 3. Load N_valid
    n_valid_data_loaded = load_yaml(n_valid_path)
    original_n = n_valid_data_loaded.get("N_valid", 0)

    # 4. Load Exclusions
    motion_excluded_ids = set()
    if exc_path.exists():
        exclusions_data_loaded = load_yaml(exc_path)
        motion_excluded_ids = set(exclusions_data_loaded.get("excluded_participants", {}).keys())
    
    # 5. Determine Valid Participants
    all_attempted = set(conv_report_loaded.get("participants", {}).keys())
    all_attempted = all_attempted - motion_excluded_ids
    valid_ids = list(all_attempted - failed_ids)
    valid_ids.sort()

    # 6. Write Output
    valid_path = state_dir / "valid_participants.yaml"
    output_data = {
        "valid_participants": valid_ids,
        "count": len(valid_ids),
        "original_n_valid": original_n,
        "excluded_by_motion": list(motion_excluded_ids),
        "excluded_by_convergence": list(failed_ids)
    }
    save_yaml(output_data, valid_path)

    # --- Verification ---
    assert valid_path.exists(), "valid_participants.yaml not created"
    result = load_yaml(valid_path)
    
    assert "sub-01" in result["valid_participants"]
    assert "sub-02" in result["valid_participants"]
    assert "sub-04" in result["valid_participants"]
    assert "sub-03" not in result["valid_participants"], "Failed participant sub-03 should be excluded"
    assert result["count"] == 3
    assert result["excluded_by_convergence"] == ["sub-03"]

def test_t028_filters_motion_exclusions(temp_state_dir):
    """
    Test that T028 logic correctly excludes participants listed in exclusions.yaml.
    """
    state_dir, data_dir = temp_state_dir

    # Mock Convergence Report (All converged)
    conv_report = {
        "participants": {
            "sub-01": {"converged": True},
            "sub-02": {"converged": True},
            "sub-05": {"converged": True} # Motion failed
        }
    }
    with open(data_dir / "convergence_report.json", "w") as f:
        json.dump(conv_report, f)
    
    with open(data_dir / "failure_log.json", "w") as f:
        json.dump({"failed_participants": []}, f)

    # Mock Motion Exclusions
    with open(state_dir / "exclusions.yaml", "w") as f:
        yaml.dump({"excluded_participants": {"sub-05": "motion > 3mm"}}, f)
    
    with open(state_dir / "n_valid.yaml", "w") as f:
        yaml.dump({"N_valid": 3}, f)

    # Execute Logic (Same as above)
    from utils.io import load_json, load_yaml, save_yaml

    conv_report_loaded = load_json(data_dir / "convergence_report.json")
    failed_ids = set()
    n_valid_data = load_yaml(state_dir / "n_valid.yaml")
    
    exclusions_data = load_yaml(state_dir / "exclusions.yaml")
    motion_excluded_ids = set(exclusions_data.get("excluded_participants", {}).keys())
    
    all_attempted = set(conv_report_loaded.get("participants", {}).keys())
    all_attempted = all_attempted - motion_excluded_ids
    valid_ids = list(all_attempted - failed_ids)
    valid_ids.sort()

    save_yaml({"valid_participants": valid_ids}, state_dir / "valid_participants.yaml")

    # Verification
    result = load_yaml(state_dir / "valid_participants.yaml")
    assert "sub-01" in result["valid_participants"]
    assert "sub-02" in result["valid_participants"]
    assert "sub-05" not in result["valid_participants"], "Motion excluded sub-05 should be excluded"
    assert result["count"] == 2