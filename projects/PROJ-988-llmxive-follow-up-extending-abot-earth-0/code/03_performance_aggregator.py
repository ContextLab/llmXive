"""
Performance Aggregator for User Story 2.

Reads staging performance logs generated by T024 (performance_logger) and T027 (ply_validator),
verifies execution time constraints against the GitHub Actions window, and writes the
consolidated per-sample performance log to data/results/performance_log.csv.

Dependencies:
- code/03_performance_logger.py (produces staging logs)
- code/03_ply_validator.py (produces validation reports)
"""

import os
import sys
import json
import logging
import argparse
import csv
import time
from pathlib import Path
from datetime import datetime

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from lib.logging_config import setup_logging, get_logger

# Configuration constants
GITHUB_ACTIONS_TIMEOUT_SECONDS = 300  # 5 minutes
STAGING_DIR_NAME = "staging"
RESULTS_DIR_NAME = "results"
PERFORMANCE_LOG_FILENAME = "performance_log.csv"
VALIDATION_REPORT_FILENAME = "validation_report.json"

def setup_directories():
    """Ensure necessary directories exist."""
    base_dir = Path(project_root) / "data"
    staging_dir = base_dir / STAGING_DIR_NAME
    results_dir = base_dir / RESULTS_DIR_NAME
    
    staging_dir.mkdir(parents=True, exist_ok=True)
    results_dir.mkdir(parents=True, exist_ok=True)
    
    return staging_dir, results_dir

def load_staging_logs(staging_dir):
    """
    Load performance records from staging JSON and CSV files generated by T024.
    
    Returns:
        list: List of dictionaries containing performance data.
    """
    records = []
    
    # Try loading from JSON staging file first (preferred format from T024)
    json_staging_path = staging_dir / "performance_staging.json"
    if json_staging_path.exists():
        try:
            with open(json_staging_path, 'r') as f:
                data = json.load(f)
                if isinstance(data, list):
                    records.extend(data)
                elif isinstance(data, dict):
                    # Handle single record or wrapped data
                    records.append(data)
            logging.info(f"Loaded {len(records)} records from JSON staging file.")
        except (json.JSONDecodeError, IOError) as e:
            logging.warning(f"Failed to load JSON staging file: {e}")
    
    # Also check for CSV staging file (fallback format)
    csv_staging_path = staging_dir / "performance_staging.csv"
    if csv_staging_path.exists():
        try:
            with open(csv_staging_path, 'r', newline='') as f:
                reader = csv.DictReader(f)
                csv_records = list(reader)
                if csv_records:
                    # Convert numeric strings to appropriate types
                    for rec in csv_records:
                        if 'peak_ram_mb' in rec and rec['peak_ram_mb']:
                            rec['peak_ram_mb'] = float(rec['peak_ram_mb'])
                        if 'wall_clock_time' in rec and rec['wall_clock_time']:
                            rec['wall_clock_time'] = float(rec['wall_clock_time'])
                    records.extend(csv_records)
                    logging.info(f"Loaded {len(csv_records)} records from CSV staging file.")
        except (IOError, csv.Error) as e:
            logging.warning(f"Failed to load CSV staging file: {e}")
    
    return records

def load_validation_reports(staging_dir):
    """
    Load validation reports from T027 to cross-reference status.
    
    Returns:
        dict: Mapping of sample_id to validation status.
    """
    validation_map = {}
    
    # Look for validation report in staging or results
    report_path = staging_dir / VALIDATION_REPORT_FILENAME
    if not report_path.exists():
        report_path = Path(project_root) / "data" / RESULTS_DIR_NAME / VALIDATION_REPORT_FILENAME
    
    if report_path.exists():
        try:
            with open(report_path, 'r') as f:
                report_data = json.load(f)
                # Handle different report structures
                if isinstance(report_data, list):
                    for item in report_data:
                        if 'sample_id' in item and 'status' in item:
                            validation_map[item['sample_id']] = item['status']
                elif isinstance(report_data, dict):
                    if 'results' in report_data and isinstance(report_data['results'], list):
                        for item in report_data['results']:
                            if 'sample_id' in item and 'status' in item:
                                validation_map[item['sample_id']] = item['status']
                    elif 'sample_id' in report_data and 'status' in report_data:
                        validation_map[report_data['sample_id']] = report_data['status']
            logging.info(f"Loaded validation data for {len(validation_map)} samples.")
        except (json.JSONDecodeError, IOError) as e:
            logging.warning(f"Failed to load validation report: {e}")
    
    return validation_map

def verify_time_constraints(records, max_time_seconds):
    """
    Verify that total execution time fits within the GitHub Actions window.
    
    Args:
        records: List of performance records.
        max_time_seconds: Maximum allowed total time in seconds.
        
    Returns:
        tuple: (is_within_budget, total_time, failed_samples)
    """
    total_time = 0.0
    failed_samples = []
    
    for record in records:
        wall_time = record.get('wall_clock_time', 0.0)
        if isinstance(wall_time, str):
            try:
                wall_time = float(wall_time)
            except ValueError:
                wall_time = 0.0
        
        total_time += wall_time
      
        # Check individual sample timeout (optional safety check)
        if wall_time > max_time_seconds:
            failed_samples.append({
                'sample_id': record.get('sample_id', 'unknown'),
                'wall_clock_time': wall_time,
                'reason': 'Individual sample exceeded timeout'
            })
    
    is_within_budget = total_time <= max_time_seconds
    
    if not is_within_budget:
        logging.warning(f"Total execution time ({total_time:.2f}s) exceeds budget ({max_time_seconds}s)")
    else:
        logging.info(f"Total execution time ({total_time:.2f}s) is within budget ({max_time_seconds}s)")
    
    return is_within_budget, total_time, failed_samples

def aggregate_performance_logs(records, validation_map, results_dir):
    """
    Consolidate performance records and write to final CSV.
    
    Args:
        records: List of performance records.
        validation_map: Validation status mapping from T027.
        results_dir: Directory to write output files.
        
    Returns:
        list: Final aggregated records.
    """
    aggregated = []
    
    for record in records:
        sample_id = record.get('sample_id', 'unknown')
        
        # Ensure consistent field names
        entry = {
            'sample_id': sample_id,
            'peak_ram_mb': record.get('peak_ram_mb', 0.0),
            'wall_clock_time': record.get('wall_clock_time', 0.0),
            'status': record.get('status', 'unknown')
        }
        
        # Cross-reference with validation status if available
        if sample_id in validation_map:
            val_status = validation_map[sample_id]
            if val_status != 'success':
                # Update status if validation failed
                if entry['status'] == 'success':
                    entry['status'] = f"VALIDATION_FAILED:{val_status}"
                elif entry['status'] != 'ERR_OOM_CPU':
                    entry['status'] = f"{entry['status']};VALIDATION_FAILED:{val_status}"
        
        # Ensure numeric fields are floats
        try:
            entry['peak_ram_mb'] = float(entry['peak_ram_mb']) if entry['peak_ram_mb'] else 0.0
            entry['wall_clock_time'] = float(entry['wall_clock_time']) if entry['wall_clock_time'] else 0.0
        except (ValueError, TypeError):
            entry['peak_ram_mb'] = 0.0
            entry['wall_clock_time'] = 0.0
        
        aggregated.append(entry)
    
    # Sort by sample_id for consistent output
    aggregated.sort(key=lambda x: x['sample_id'])
    
    return aggregated

def write_performance_log(aggregated_records, results_dir):
    """
    Write aggregated performance records to CSV.
    
    Args:
        aggregated_records: List of aggregated records.
        results_dir: Directory to write output file.
    """
    output_path = results_dir / PERFORMANCE_LOG_FILENAME
    
    fieldnames = ['sample_id', 'peak_ram_mb', 'wall_clock_time', 'status']
    
    with open(output_path, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(aggregated_records)
    
    logging.info(f"Wrote {len(aggregated_records)} records to {output_path}")
    return output_path

def main():
    """Main entry point for performance aggregation."""
    parser = argparse.ArgumentParser(description='Aggregate performance logs from staging.')
    parser.add_argument('--timeout', type=int, default=GITHUB_ACTIONS_TIMEOUT_SECONDS,
                      help=f'Maximum total execution time in seconds (default: {GITHUB_ACTIONS_TIMEOUT_SECONDS})')
    parser.add_argument('--verbose', action='store_true', help='Enable verbose logging')
    args = parser.parse_args()
    
    # Setup logging
    log_level = logging.DEBUG if args.verbose else logging.INFO
    setup_logging(level=log_level)
    logger = get_logger(__name__)
    
    logger.info("Starting performance aggregation process...")
    
    # Setup directories
    staging_dir, results_dir = setup_directories()
    
    # Load staging logs
    records = load_staging_logs(staging_dir)
    if not records:
        logger.warning("No performance records found in staging. Creating empty log.")
        # Create empty file
        write_performance_log([], results_dir)
        return 0
    
    logger.info(f"Found {len(records)} performance records to aggregate.")
    
    # Load validation reports
    validation_map = load_validation_reports(staging_dir)
    
    # Verify time constraints
    is_within_budget, total_time, failed_samples = verify_time_constraints(records, args.timeout)
    
    # Aggregate and write final log
    aggregated = aggregate_performance_logs(records, validation_map, results_dir)
    output_path = write_performance_log(aggregated, results_dir)
    
    # Summary report
    success_count = sum(1 for r in aggregated if r['status'] == 'success')
    error_count = len(aggregated) - success_count
    
    logger.info("=" * 50)
    logger.info("PERFORMANCE AGGREGATION SUMMARY")
    logger.info("=" * 50)
    logger.info(f"Total samples processed: {len(aggregated)}")
    logger.info(f"Successful samples: {success_count}")
    logger.info(f"Failed samples: {error_count}")
    logger.info(f"Total execution time: {total_time:.2f}s")
    logger.info(f"Time budget: {args.timeout}s")
    logger.info(f"Within budget: {'YES' if is_within_budget else 'NO'}")
    logger.info(f"Output file: {output_path}")
    
    if failed_samples:
        logger.warning(f"Samples exceeding individual timeout: {len(failed_samples)}")
        for fs in failed_samples[:5]:  # Show first 5
            logger.warning(f"  - {fs['sample_id']}: {fs['wall_clock_time']:.2f}s")
    
    if not is_within_budget or error_count > 0:
        logger.warning("Performance aggregation completed with warnings.")
        return 1
    
    logger.info("Performance aggregation completed successfully.")
    return 0

if __name__ == '__main__':
    sys.exit(main())