"""
Performance Logger for User Story 2 (US2).

Finalizes per-sample performance logs from the temporary buffer generated by
T021 (03_3dgs_baseline.py) and T023 (03_inpainting_restoration.py).

Reads the staging buffer, handles MemoryError statuses, and writes the final
performance log to data/results/staging_performance_log.json (or .csv depending on
downstream aggregation needs, here we write JSON for flexibility, then CSV in T026).

Handles:
- peak_ram_mb
- wall_clock_time
- status (success, ERR_OOM_CPU)
"""
import os
import sys
import json
import logging
import argparse
import csv
from pathlib import Path
from datetime import datetime
from typing import List, Dict, Any, Optional

# Add parent directory to path for imports if running as script
if __name__ == "__main__":
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from lib.logging_config import setup_logging, get_logger

# Constants
STAGING_BUFFER_DIR = "data/processed/performance_buffer"
OUTPUT_DIR = "data/results"
STAGING_FILE_NAME = "staging_performance_log.json"
CSV_OUTPUT_NAME = "performance_log_staging.csv"

def setup_directories():
    """Ensure required directories exist."""
    staging_dir = Path(STAGING_BUFFER_DIR)
    output_dir = Path(OUTPUT_DIR)
    staging_dir.mkdir(parents=True, exist_ok=True)
    output_dir.mkdir(parents=True, exist_ok=True)
    return staging_dir, output_dir

def load_buffer_files(staging_dir: Path) -> List[Dict[str, Any]]:
    """
    Load all JSON performance buffer files from the staging directory.
    
    Expects files named like: sample_<id>_perf.json or similar.
    Returns a list of parsed dictionaries.
    """
    records = []
    if not staging_dir.exists():
        logging.warning(f"Staging buffer directory {staging_dir} does not exist.")
        return records
    
    json_files = list(staging_dir.glob("*.json"))
    if not json_files:
        logging.warning(f"No JSON files found in {staging_dir}.")
        return records
    
    for file_path in json_files:
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
                # Ensure it's a list or dict
                if isinstance(data, list):
                    records.extend(data)
                elif isinstance(data, dict):
                    records.append(data)
                else:
                    logging.warning(f"Skipping unexpected format in {file_path}")
            logging.info(f"Loaded buffer: {file_path.name}")
        except json.JSONDecodeError as e:
            logging.error(f"Failed to parse JSON in {file_path}: {e}")
        except Exception as e:
            logging.error(f"Error reading {file_path}: {e}")
    
    return records

def finalize_records(records: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Finalize records: ensure required fields exist, normalize statuses.
    
    - If status is missing, default to 'success' (assuming no error was recorded).
    - If peak_ram_mb or wall_clock_time are missing, set to 0 or None (log warning).
    - Normalize 'MemoryError' or similar to 'ERR_OOM_CPU'.
    """
    finalized = []
    for i, rec in enumerate(records):
        # Ensure sample_id exists
        sample_id = rec.get("sample_id", f"unknown_{i}")
        
        # Normalize status
        status = rec.get("status", "").strip().lower()
        if "memory" in status and "error" in status:
            final_status = "ERR_OOM_CPU"
        elif status in ["success", "completed", "ok"]:
            final_status = "success"
        elif not status:
            # If no status recorded, assume success unless RAM/Time is 0?
            # We'll assume success if no error explicitly flagged
            final_status = "success"
        else:
            final_status = status  # Keep as is if custom status
        
        # Normalize metrics
        peak_ram = rec.get("peak_ram_mb")
        if peak_ram is None:
            peak_ram = 0.0
            logging.warning(f"Sample {sample_id}: missing peak_ram_mb, set to 0.0")
        else:
            try:
                peak_ram = float(peak_ram)
            except (ValueError, TypeError):
                peak_ram = 0.0
                logging.warning(f"Sample {sample_id}: invalid peak_ram_mb, set to 0.0")

        wall_time = rec.get("wall_clock_time")
        if wall_time is None:
            wall_time = 0.0
            logging.warning(f"Sample {sample_id}: missing wall_clock_time, set to 0.0")
        else:
            try:
                wall_time = float(wall_time)
            except (ValueError, TypeError):
                wall_time = 0.0
                logging.warning(f"Sample {sample_id}: invalid wall_clock_time, set to 0.0")

        finalized_rec = {
            "sample_id": sample_id,
            "peak_ram_mb": peak_ram,
            "wall_clock_time": wall_time,
            "status": final_status,
            "timestamp": datetime.now(timezone.utc).isoformat(),
            # Preserve any extra metadata from the buffer
            **{k: v for k, v in rec.items() if k not in ["sample_id", "peak_ram_mb", "wall_clock_time", "status"]}
        }
        finalized.append(finalized_rec)
    
    return finalized

def write_staging_json(finalized_records: List[Dict[str, Any]], output_path: Path):
    """Write the finalized records to a JSON staging file."""
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(finalized_records, f, indent=2, default=str)
    logging.info(f"Wrote {len(finalized_records)} records to {output_path}")

def write_staging_csv(finalized_records: List[Dict[str, Any]], output_path: Path):
    """Write the finalized records to a CSV staging file for T026 aggregation."""
    if not finalized_records:
        logging.warning("No records to write to CSV.")
        # Write empty file with headers
        with open(output_path, 'w', newline='', encoding='utf-8') as f:
            writer = csv.writer(f)
            writer.writerow(["sample_id", "peak_ram_mb", "wall_clock_time", "status", "timestamp"])
        return

    fieldnames = ["sample_id", "peak_ram_mb", "wall_clock_time", "status", "timestamp"]
    # Add any extra keys found in records
    extra_keys = set()
    for rec in finalized_records:
        extra_keys.update(k for k in rec.keys() if k not in fieldnames)
    fieldnames.extend(sorted(extra_keys))

    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction='ignore')
        writer.writeheader()
        writer.writerows(finalized_records)
    logging.info(f"Wrote {len(finalized_records)} records to {output_path}")

def main():
    """Main entry point for T024."""
    parser = argparse.ArgumentParser(description="Finalize performance logs from buffer.")
    parser.add_argument("--input-dir", type=str, default=STAGING_BUFFER_DIR,
                        help="Path to the staging buffer directory.")
    parser.add_argument("--output-dir", type=str, default=OUTPUT_DIR,
                        help="Path to the output directory for final logs.")
    parser.add_argument("--verbose", action="store_true", help="Enable verbose logging.")
    args = parser.parse_args()

    # Setup logging
    log_level = logging.DEBUG if args.verbose else logging.INFO
    setup_logging(level=log_level)
    logger = get_logger(__name__)

    logger.info("Starting performance logger finalization (T024).")

    # Setup directories
    staging_dir = Path(args.input_dir)
    output_dir = Path(args.output_dir)
    staging_dir.mkdir(parents=True, exist_ok=True)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Load buffer files
    records = load_buffer_files(staging_dir)
    if not records:
        logger.warning("No performance records found in buffer. Creating empty output.")
        # Still create empty files to signal completion
        write_staging_json([], output_dir / STAGING_FILE_NAME)
        write_staging_csv([], output_dir / CSV_OUTPUT_NAME)
        return

    # Finalize records
    finalized_records = finalize_records(records)

    # Write outputs
    json_path = output_dir / STAGING_FILE_NAME
    csv_path = output_dir / CSV_OUTPUT_NAME
    write_staging_json(finalized_records, json_path)
    write_staging_csv(finalized_records, csv_path)

    # Summary
    success_count = sum(1 for r in finalized_records if r["status"] == "success")
    error_count = len(finalized_records) - success_count
    logger.info(f"Finalization complete. Total: {len(finalized_records)}, Success: {success_count}, Errors: {error_count}")

    if error_count > 0:
        logger.warning(f"{error_count} samples failed with ERR_OOM_CPU or other status.")

    logger.info("T024 performance logger finalized successfully.")

if __name__ == "__main__":
    main()