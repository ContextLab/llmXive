def write_descriptors(results: List[Dict[str, Any]]) -> Path:
    """
    Write the calculated descriptors to a CSV file.

    Args:
        results: List of result dictionaries.

    Returns:
        Path: Path to the output file.
    """
    project_root = get_project_root()
    output_file = project_root / OUTPUT_PATH
    
    if not results:
        logger.error("No results to write.")
        raise ValueError("No valid descriptors calculated.")

    df = pd.DataFrame(results)
    
    # Ensure columns are in the correct order
    columns = ['smiles', 'bond_variance', 'angle_variance', 'dihedral_variance']
    # Filter to only existing columns to avoid errors
    existing_cols = [c for c in columns if c in df.columns]
    df = df[existing_cols]
    
    df.to_csv(output_file, index=False)
    logger.info(f"Wrote {len(df)} descriptors to {output_file}")
    
    return output_file


