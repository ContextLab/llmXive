"""
Preprocessing module for Caco-2 permeability data.
Filters raw data for non-NULL SMILES and logPapp, reports pass rate, and registers checksums.

This script implements T010: filtering raw data for non-NULL SMILES and logPapp,
reporting pass rate and excluded records due to protocol heterogeneity.
"""
import csv
import logging
import sys
from pathlib import Path
from typing import List, Dict, Any, Optional

from utils.logging import get_logger, configure_root_logger
from utils.config import get_project_root, get_data_path
from utils.checksum import write_checksums_to_pending

logger = get_logger(__name__)

# Constants
RAW_DATA_PATH = "data/raw/chembl_caco2_raw.csv"
PROCESSED_DATA_PATH = "data/processed/filtered_data.csv"
STATE_PATH = "state/projects/PROJ-266-exploring-the-correlation-between-molecu.yaml"
PENDING_CHECKSUM_PATH = "state/pending/checksums.yaml"

def load_raw_data() -> List[Dict[str, Any]]:
    """
    Load raw Caco-2 data from the CSV file generated by T009.
    
    Returns:
        List of dictionaries representing each row in the raw CSV.
        
    Raises:
        FileNotFoundError: If the raw data file does not exist.
    """
    project_root = get_project_root()
    input_path = project_root / RAW_DATA_PATH

    if not input_path.exists():
        raise FileNotFoundError(f"Raw data file not found at {input_path}. "
                                "Please run T009 (retrieval.py) first.")

    data = []
    with open(input_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            data.append(row)

    logger.info(f"Loaded {len(data)} raw records from {input_path}")
    return data

def preprocess_data(raw_data: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Filter raw data for non-NULL SMILES and logPapp.
    Reports pass rate and excluded records due to protocol heterogeneity (missing values).
    
    Args:
        raw_data: List of raw record dictionaries.
        
    Returns:
        List of filtered record dictionaries.
    """
    if not raw_data:
        logger.warning("Raw data is empty. No filtering performed.")
        return []

    filtered_data = []
    excluded_count = 0
    excluded_reasons = {
        "missing_smiles": 0,
        "missing_logpapp": 0,
        "invalid_logpapp": 0,
        "protocol_heterogeneity": 0
    }

    for i, record in enumerate(raw_data):
        smiles = record.get('smiles', '').strip()
        logpapp_str = record.get('logPapp', '').strip()

        # Check for missing SMILES
        if not smiles:
            excluded_count += 1
            excluded_reasons["missing_smiles"] += 1
            continue

        # Check for missing logPapp
        if not logpapp_str:
            excluded_count += 1
            excluded_reasons["missing_logpapp"] += 1
            continue

        # Validate logPapp is a number
        try:
            float(logpapp_str)
        except ValueError:
            excluded_count += 1
            excluded_reasons["invalid_logpapp"] += 1
            continue

        # Check protocol heterogeneity (missing required protocol_metadata fields)
        # The schema requires lab_id, temperature, passage in protocol_metadata
        protocol_metadata = record.get('protocol_metadata', {})
        if not isinstance(protocol_metadata, dict):
            try:
                import json
                protocol_metadata = json.loads(protocol_metadata)
            except:
                protocol_metadata = {}

        has_lab_id = bool(protocol_metadata.get('lab_id', '').strip())
        has_temperature = bool(protocol_metadata.get('temperature', '').strip())
        has_passage = bool(protocol_metadata.get('passage', '').strip())

        if not (has_lab_id and has_temperature and has_passage):
            excluded_count += 1
            excluded_reasons["protocol_heterogeneity"] += 1
            continue

        # Record is valid
        filtered_data.append(record)

    total = len(raw_data)
    passed = len(filtered_data)
    pass_rate = (passed / total * 100) if total > 0 else 0.0

    logger.info(f"Preprocessing complete:")
    logger.info(f"  Total records: {total}")
    logger.info(f"  Excluded records: {excluded_count}")
    logger.info(f"    - Missing SMILES: {excluded_reasons['missing_smiles']}")
    logger.info(f"    - Missing logPapp: {excluded_reasons['missing_logpapp']}")
    logger.info(f"    - Invalid logPapp: {excluded_reasons['invalid_logpapp']}")
    logger.info(f"    - Protocol heterogeneity: {excluded_reasons['protocol_heterogeneity']}")
    logger.info(f"  Passed records: {passed} ({pass_rate:.2f}%)")

    if excluded_count > 0:
        logger.warning(f"Excluded {excluded_count} records due to protocol heterogeneity (missing/invalid data).")

    return filtered_data

def write_clean_data(data: List[Dict[str, Any]], output_path: Path) -> None:
    """
    Write filtered data to a CSV file.
    
    Args:
        data: List of filtered record dictionaries.
        output_path: Path to the output CSV file.
    """
    if not data:
        logger.warning("No data to write.")
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, 'w', newline='', encoding='utf-8') as f:
            f.write("")
        return

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    fieldnames = data[0].keys()

    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(data)

    logger.info(f"Wrote {len(data)} clean records to {output_path}")

def main():
    """
    Main entry point for the preprocessing script.
    
    This function:
    1. Loads raw data from T009.
    2. Filters for non-NULL SMILES and logPapp.
    3. Writes the filtered data to data/processed/filtered_data.csv.
    4. Registers the checksum of the output file in the project state YAML.
    """
    configure_root_logger()
    logger.info("Starting data preprocessing (T010)...")

    try:
        # 1. Load raw data
        raw_data = load_raw_data()

        # 2. Preprocess (filter) data
        filtered_data = preprocess_data(raw_data)

        # 3. Write clean data
        project_root = get_project_root()
        output_path = project_root / PROCESSED_DATA_PATH
        write_clean_data(filtered_data, output_path)

        # 4. Register checksum
        # The write_checksums_to_pending function expects: file_path, pending_path, description
        pending_path = project_root / PENDING_CHECKSUM_PATH
        write_checksums_to_pending(output_path, pending_path, "Filtered Caco-2 dataset for US1")

        logger.info("Preprocessing completed successfully.")

    except FileNotFoundError as e:
        logger.error(f"File error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during preprocessing: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()