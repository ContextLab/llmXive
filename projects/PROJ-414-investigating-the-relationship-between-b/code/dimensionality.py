"""PCA dimensionality reduction (T005).

This module loads per‑subject window‑wise connectivity descriptor
CSVs generated by ``code/connectivity.py`` (stage ``metrics``),
performs a principal‑component analysis across all windows and
subjects, retains the smallest number of components that explain at
least ``config.PCA_VARIANCE_THRESHOLD`` (≥ 80 %) of the total variance,
and writes per‑subject mean PC scores to ``data/derived/pca_scores.csv``.
The output conforms to ``specs/001-investigating-the-relationship-between-b/contracts/pca_scores.schema.yaml``.
"""
import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.decomposition import PCA

import config
from llmxive_toolkit import get_logger, paths

log = get_logger(__name__)

def _load_descriptor_data(derived_dir: Path):
    """Load all ``metrics_*.csv`` files and return a DataFrame with
    columns ``subject_id`` and descriptor columns only.

    Returns
    -------
    df_all : pandas.DataFrame
        Concatenated descriptor rows from all subjects.
    subject_row_indices : dict
        Mapping from ``subject_id`` to slice indices in ``df_all``.
    """
    metric_files = sorted(derived_dir.glob("metrics_*.csv"))
    if not metric_files:
        raise RuntimeError(
            f"No metric files found in {derived_dir}. "
            "Run the ``metrics`` stage before the ``pca`` stage."
        )

    rows = []
    subject_row_indices = {}
    start = 0

    for mf in metric_files:
        df = pd.read_csv(mf)
        if "subject_id" not in df.columns:
            raise RuntimeError(f"'subject_id' column missing in {mf}")
        # Identify descriptor columns: everything except subject_id and window index.
        exclude_cols = {"subject_id", "window_index"}
        descriptor_cols = [c for c in df.columns if c not in exclude_cols]
        if not descriptor_cols:
            raise RuntimeError(f"No descriptor columns found in {mf}")

        # Keep only needed columns.
        df_desc = df[["subject_id"] + descriptor_cols].copy()
        rows.append(df_desc)

        n_rows = len(df_desc)
        subject_row_indices[df_desc["subject_id"].iloc[0]] = slice(start, start + n_rows)
        start += n_rows

    df_all = pd.concat(rows, ignore_index=True)
    return df_all, subject_row_indices

def _fit_pca(X: np.ndarray):
    """Fit PCA on ``X`` and return the fitted object and number of components
    needed to reach the variance threshold."""
    pca_full = PCA(svd_solver="full")
    pca_full.fit(X)
    cum_var = np.cumsum(pca_full.explained_variance_ratio_)
    n_retained = int(np.searchsorted(cum_var, config.PCA_VARIANCE_THRESHOLD) + 1)
    # Re‑fit with the retained number of components for a clean transform.
    pca = PCA(n_components=n_retained, svd_solver="full")
    pca.fit(X)
    variance_explained_total = float(cum_var[n_retained - 1])
    return pca, n_retained, variance_explained_total

def _compute_subject_scores(
    pca,
    X: np.ndarray,
    subject_row_indices: dict,
):
    """Transform ``X`` with ``pca`` and compute per‑subject mean scores."""
    X_pca = pca.transform(X)  # shape (n_samples, n_components)
    subject_scores = {}
    for sid, slc in subject_row_indices.items():
        subj_vals = X_pca[slc]  # rows belonging to this subject
        mean_vals = np.mean(subj_vals, axis=0)
        # Build a mapping ``pc_1`` → value, ``pc_2`` → value, …
        pc_map = {f"pc_{i+1}": float(v) for i, v in enumerate(mean_vals)}
        subject_scores[sid] = pc_map
    return subject_scores

def main(argv=None) -> int:
    """CLI entry point for the ``pca`` stage.

    ``argv`` may be a list of arguments (as from ``sys.argv[1:]``) or
    an ``argparse.Namespace`` passed by the orchestrator. In the latter
    case the arguments are ignored because the orchestrator supplies the
    required paths via the configuration.
    """
    if isinstance(argv, argparse.Namespace):
        argv = None
    parser = argparse.ArgumentParser(
        description="PCA dimensionality reduction (T005)"
    )
    parser.add_argument(
        "--derived_dir",
        type=Path,
        default=None,
        help="override derived directory (default: data/derived)",
    )
    args = parser.parse_args(argv)

    derived_dir = args.derived_dir or paths.data("derived")
    log.info("Loading descriptor data from %s", derived_dir)

    df_all, subject_row_indices = _load_descriptor_data(derived_dir)

    # Descriptor matrix (subjects × windows rows, descriptor columns)
    descriptor_cols = [c for c in df_all.columns if c != "subject_id"]
    X = df_all[descriptor_cols].to_numpy(dtype=np.float64)

    log.info("Fitting PCA on %d samples × %d features", X.shape[0], X.shape[1])
    pca, n_retained, var_explained = _fit_pca(X)

    log.info(
        "Retaining %d components (cumulative variance %.3f)",
        n_retained,
        var_explained,
    )
    subject_scores = _compute_subject_scores(pca, X, subject_row_indices)

    # Write results.
    out_path = paths.data("derived", "pca_scores.csv")
    out_path.parent.mkdir(parents=True, exist_ok=True)

    rows = []
    for sid, pc_map in subject_scores.items():
        rows.append(
            {
                "subject_id": sid,
                "n_components_retained": n_retained,
                "variance_explained_total": var_explained,
                "pc_scores": json.dumps(pc_map, separators=(",", ":")),
            }
        )
    pd.DataFrame(rows).to_csv(out_path, index=False)
    log.info("PCA scores written to %s", out_path)
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
