"""
Task T027b: Evaluate Convergence & Fallback for CLMM.

Logic:
1. Dependency: T027a. Read `project_status.json` from T027a.
2. Measure SC-003: Evaluate if convergence rate meets >= 95%.
   (Note: In a single-run context, we treat the single model's status as the rate.
    If the model failed to converge, rate is 0%. If success, 100%.)
3. Fallback Strategy: If convergence < 95% (i.e., primary model failed),
   attempt fallback to fixed-effects ordinal regression (remove random effects).
4. Record Status: Update `project_status.json` with fields:
   `status` ("success" | "fallback_used"), `sc003_met` (boolean), `sc003_note`.
5. Save Results: If fallback used, save results to `data/processed/clmm_fallback_results.csv`.
"""

