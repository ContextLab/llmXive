"""
Sensitivity Analysis for CLMM Results (Task T029)

This script performs a sensitivity analysis sweep across multiple significance
thresholds (p < 0.01, 0.05, 0.10) to explicitly report the range of variation
in headline significance rates for the fixed effects identified in the CLMM.

It reads the results from `data/processed/clmm_results.csv` (generated by T028),
applies the Benjamini-Hochberg corrected p-values, and calculates the proportion
of significant effects at each threshold.
"""

import os
import sys
import logging
import argparse
import json
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple

import pandas as pd
import numpy as np

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Constants
DEFAULT_INPUT_PATH = "data/processed/clmm_results.csv"
DEFAULT_OUTPUT_PATH = "data/processed/sensitivity_analysis_results.json"
SIGNIFICANCE_THRESHOLDS = [0.01, 0.05, 0.10]
HEADLINE_EFFECT = "politeness"  # The primary effect of interest

def ensure_directories(file_path: str) -> None:
    """Ensure the directory for the given file path exists."""
    path = Path(file_path)
    path.parent.mkdir(parents=True, exist_ok=True)

def load_clmm_results(input_path: str) -> pd.DataFrame:
    """
    Load the CLMM results from a CSV file.

    Expected columns:
    - term: The name of the fixed effect (e.g., 'politeness', 'conversation_length')
    - estimate: Coefficient estimate
    - std.error: Standard error
    - p.value: Raw p-value
    - p.adj: Benjamini-Hochberg adjusted p-value

    Args:
        input_path: Path to the CSV file.

    Returns:
        pd.DataFrame: The loaded results.
    """
    if not os.path.exists(input_path):
        raise FileNotFoundError(f"CLMM results file not found: {input_path}")

    df = pd.read_csv(input_path)

    required_cols = ['term', 'p.value', 'p.adj']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in {input_path}: {missing_cols}")

    logger.info(f"Loaded {len(df)} fixed effects from {input_path}")
    return df

def calculate_significance_rates(
    df: pd.DataFrame,
    p_col: str = 'p.adj',
    thresholds: List[float] = SIGNIFICANCE_THRESHOLDS
) -> Dict[str, Dict[str, Any]]:
    """
    Calculate the significance rate (proportion of significant effects)
    at each specified threshold.

    Args:
        df: DataFrame containing p-values.
        p_col: Column name to use for p-values (e.g., 'p.adj').
        thresholds: List of significance thresholds to test.

    Returns:
        Dictionary mapping each threshold to its significance rate and details.
    """
    results = {}

    for thresh in thresholds:
        # Count significant effects (p < threshold)
        significant_count = (df[p_col] < thresh).sum()
        total_count = len(df)
        rate = significant_count / total_count if total_count > 0 else 0.0

        # Identify specific significant terms for this threshold
        significant_terms = df.loc[df[p_col] < thresh, 'term'].tolist()

        results[str(thresh)] = {
            "threshold": thresh,
            "significant_count": int(significant_count),
            "total_count": int(total_count),
            "significance_rate": float(rate),
            "significant_terms": significant_terms
        }

    return results

def analyze_headline_variation(
    df: pd.DataFrame,
    headline_term: str = HEADLINE_EFFECT,
    p_col: str = 'p.adj'
) -> Dict[str, Any]:
    """
    Analyze the variation in significance status for the headline effect
    across the thresholds.

    Args:
        df: DataFrame containing p-values.
        headline_term: The specific term to track (e.g., 'politeness').
        p_col: Column name for p-values.

    Returns:
        Dictionary detailing the significance status of the headline term at each threshold.
    """
    if headline_term not in df['term'].values:
        logger.warning(f"Headline term '{headline_term}' not found in results. Skipping headline analysis.")
        return {"status": "term_not_found", "term": headline_term}

    term_row = df[df['term'] == headline_term].iloc[0]
    p_val = term_row[p_col]

    variation_details = {}
    is_significant_at_all = True
    is_significant_at_none = True

    for thresh in SIGNIFICANCE_THRESHOLDS:
        is_sig = p_val < thresh
        variation_details[str(thresh)] = {
            "p_value": float(p_val),
            "is_significant": bool(is_sig),
            "threshold": thresh
        }
        if not is_sig:
            is_significant_at_all = False
        else:
            is_significant_at_none = False

    return {
        "term": headline_term,
        "p_value": float(p_val),
        "variation": variation_details,
        "stable_significance": (is_significant_at_all or is_significant_at_none),
        "conclusion": "Significant across all thresholds" if is_significant_at_all else
                      "Not significant at any threshold" if is_significant_at_none else
                      "Significance varies by threshold"
    }

def run_sensitivity_analysis(
    input_path: str = DEFAULT_INPUT_PATH,
    output_path: str = DEFAULT_OUTPUT_PATH
) -> None:
    """
    Main function to run the sensitivity analysis.

    1. Load CLMM results.
    2. Calculate significance rates at 0.01, 0.05, 0.10.
    3. Analyze variation for the headline effect.
    4. Save results to JSON.
    """
    logger.info(f"Starting sensitivity analysis on {input_path}")

    try:
        # Load data
        df = load_clmm_results(input_path)

        # Calculate rates
        rates = calculate_significance_rates(df)

        # Analyze headline variation
        headline_analysis = analyze_headline_variation(df)

        # Compile final report
        report = {
            "description": "Sensitivity analysis of CLMM results across significance thresholds",
            "thresholds_tested": SIGNIFICANCE_THRESHOLDS,
            "significance_rates": rates,
            "headline_effect_analysis": headline_analysis,
            "range_of_variation": {
                "min_rate": min(r["significance_rate"] for r in rates.values()),
                "max_rate": max(r["significance_rate"] for r in rates.values()),
                "delta": max(r["significance_rate"] for r in rates.values()) - min(r["significance_rate"] for r in rates.values())
            }
        }

        # Save results
        ensure_directories(output_path)
        with open(output_path, 'w') as f:
            json.dump(report, f, indent=2)

        logger.info(f"Sensitivity analysis complete. Results saved to {output_path}")
        logger.info(f"Range of variation in significance rates: {report['range_of_variation']['delta']:.2%}")

    except Exception as e:
        logger.error(f"Error during sensitivity analysis: {e}", exc_info=True)
        raise

def main():
    parser = argparse.ArgumentParser(description="Run sensitivity analysis on CLMM results.")
    parser.add_argument(
        "--input",
        type=str,
        default=DEFAULT_INPUT_PATH,
        help=f"Path to CLMM results CSV (default: {DEFAULT_INPUT_PATH})"
    )
    parser.add_argument(
        "--output",
        type=str,
        default=DEFAULT_OUTPUT_PATH,
        help=f"Path to save sensitivity analysis JSON (default: {DEFAULT_OUTPUT_PATH})"
    )

    args = parser.parse_args()
    run_sensitivity_analysis(args.input, args.output)

if __name__ == "__main__":
    main()