"""
Task T027: Implement Benjamini-Hochberg correction for p-values across fixed effects.

This script loads the CLMM results generated by code/02_fit_clmm.py,
applies the Benjamini-Hochberg (BH) procedure to adjust p-values for
multiple comparisons, and saves the corrected results.

The BH correction controls the False Discovery Rate (FDR).
"""
import os
import sys
import logging
import argparse
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple
import pandas as pd
import numpy as np

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def ensure_directories(output_path: Path) -> None:
    """Ensure the directory for the output file exists."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    logger.info(f"Ensured directory exists: {output_path.parent}")

def load_clmm_results(input_path: Path) -> pd.DataFrame:
    """
    Load the CLMM results from the CSV file generated by 02_fit_clmm.py.

    Expected columns include: 'term', 'estimate', 'std.error', 'statistic', 'p.value', etc.
    """
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    df = pd.read_csv(input_path)
    logger.info(f"Loaded {len(df)} rows from {input_path}")
    
    # Validate required columns
    required_cols = ['term', 'p.value']
    missing = [col for col in required_cols if col not in df.columns]
    if missing:
        raise ValueError(f"Input file missing required columns: {missing}")
    
    return df

def benjamini_hochberg_correction(p_values: pd.Series) -> Tuple[pd.Series, pd.Series]:
    """
    Apply the Benjamini-Hochberg procedure to adjust p-values.

    Args:
        p_values: A pandas Series of raw p-values.

    Returns:
        A tuple containing:
        - adjusted_p_values: The BH-adjusted p-values (FDR).
        - is_significant: Boolean mask indicating significance at alpha=0.05.
    """
    if p_values.isna().all():
        logger.warning("All p-values are NaN. Returning NaNs.")
        return p_values.copy(), pd.Series([False] * len(p_values), index=p_values.index)

    # Sort p-values
    sorted_indices = p_values.argsort()
    sorted_p_values = p_values.iloc[sorted_indices]
    m = len(sorted_p_values)
    
    # Calculate BH critical values
    # The formula is: p_i * (m / i)
    # We use 1-based indexing for the rank i
    ranks = np.arange(1, m + 1)
    bh_thresholds = (ranks / m) * 0.05  # alpha = 0.05

    # Apply BH adjustment: p_adj = p * (m / rank)
    # To control FDR strictly, we often take the cumulative min from the largest rank downwards
    # But the standard "adjusted p-value" definition is:
    # p_adj(i) = min( (m/j) * p_j for j >= i )
    
    adjusted = sorted_p_values * (m / ranks)
    
    # Ensure monotonicity (cumulative min from the end)
    # This ensures that if p_i < p_j for i < j, then p_adj_i <= p_adj_j
    # We iterate backwards
    for i in range(m - 2, -1, -1):
        if adjusted.iloc[i] > adjusted.iloc[i+1]:
            adjusted.iloc[i] = adjusted.iloc[i+1]
    
    # Clamp values to [0, 1]
    adjusted = adjusted.clip(upper=1.0)
    
    # Restore original order
    # Create a series with the same index as the input
    result = pd.Series(index=p_values.index, dtype=float)
    result.iloc[sorted_indices] = adjusted.values
    
    # Determine significance
    is_sig = result <= 0.05
    
    return result, is_sig

def apply_correction(df: pd.DataFrame) -> pd.DataFrame:
    """
    Apply BH correction to the 'p.value' column and add new columns.
    """
    logger.info("Applying Benjamini-Hochberg correction...")
    
    adjusted_p_values, is_significant = benjamini_hochberg_correction(df['p.value'])
    
    df['p.value.bh_adjusted'] = adjusted_p_values
    df['is_significant_bh'] = is_significant
    
    logger.info(f"Correction complete. Significant terms (alpha=0.05): {is_significant.sum()}")
    
    return df

def save_results(df: pd.DataFrame, output_path: Path) -> None:
    """Save the corrected results to a CSV file."""
    df.to_csv(output_path, index=False)
    logger.info(f"Saved corrected results to {output_path}")

def main():
    parser = argparse.ArgumentParser(description="Apply Benjamini-Hochberg correction to CLMM results.")
    parser.add_argument(
        "--input", 
        type=str, 
        default="data/processed/clmm_results.csv",
        help="Path to the input CLMM results CSV."
    )
    parser.add_argument(
        "--output", 
        type=str, 
        default="data/processed/clmm_results_corrected.csv",
        help="Path to save the corrected results CSV."
    )
    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)

    try:
        ensure_directories(output_path)
        df = load_clmm_results(input_path)
        df_corrected = apply_correction(df)
        save_results(df_corrected, output_path)
        logger.info("Task T027 completed successfully.")
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()