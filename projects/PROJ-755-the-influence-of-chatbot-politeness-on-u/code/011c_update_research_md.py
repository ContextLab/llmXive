"""
Task T011c: Update research.md with MDE estimation results.

This script reads the MDE results generated by the pilot analysis (T011b2)
and appends them to the research.md file in a formatted section.

Logic:
1. Dependency: T011b2 (pilot_mde_results.json).
2. Read data/processed/pilot_mde_results.json.
3. Append section 'MDE_Estimation' to research.md with the JSON content formatted as a code block.
4. Verify: Check that research.md exists and contains the new section.
"""

import os
import sys
import json
import logging
from pathlib import Path
from typing import Optional, Dict, Any

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Define paths relative to project root
PROJECT_ROOT = Path(__file__).resolve().parent.parent
MDE_RESULTS_PATH = PROJECT_ROOT / "data" / "processed" / "pilot_mde_results.json"
RESEARCH_MD_PATH = PROJECT_ROOT / "research.md"

def load_mde_results(path: Path) -> Dict[str, Any]:
    """
    Load MDE results from a JSON file.

    Args:
        path: Path to the JSON file containing MDE results.

    Returns:
        Dictionary containing MDE results.

    Raises:
        FileNotFoundError: If the results file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    if not path.exists():
        raise FileNotFoundError(f"MDE results file not found at {path}")
    
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)

def format_mde_section(results: Dict[str, Any]) -> str:
    """
    Format the MDE results as a markdown section.

    Args:
        results: Dictionary containing MDE results.

    Returns:
        Formatted markdown string.
    """
    section = "\n## MDE_Estimation\n\n"
    section += "The following Minimum Detectable Effect (MDE) estimation results were obtained from the pilot analysis:\n\n"
    section += "```json\n"
    section += json.dumps(results, indent=2)
    section += "\n```\n"
    return section

def update_research_md(results_path: Path, output_path: Path) -> bool:
    """
    Update the research.md file with MDE estimation results.

    Args:
        results_path: Path to the MDE results JSON file.
        output_path: Path to the research.md file to update.

    Returns:
        True if the update was successful, False otherwise.
    """
    try:
        # Load MDE results
        mde_results = load_mde_results(results_path)
        logger.info(f"Loaded MDE results from {results_path}")

        # Format the section
        mde_section = format_mde_section(mde_results)

        # Check if research.md exists
        if not output_path.exists():
            logger.warning(f"research.md not found at {output_path}. Creating a new file.")
            # Create a new file with basic structure if it doesn't exist
            initial_content = "# Research Log\n\n"
            initial_content += "## Pilot_Results\n\n"
            initial_content += "## MDE_Estimation\n\n"
            initial_content += "## Proxy_Validation\n\n"
            with open(output_path, 'w', encoding='utf-8') as f:
                f.write(initial_content)
            logger.info(f"Created new research.md at {output_path}")

        # Read existing content
        with open(output_path, 'r', encoding='utf-8') as f:
            existing_content = f.read()

        # Check if MDE_Estimation section already exists
        if "## MDE_Estimation" in existing_content:
            logger.info("MDE_Estimation section already exists. Updating content.")
            # Find the start of the MDE_Estimation section
            start_index = existing_content.find("## MDE_Estimation")
            # Find the start of the next section (if any)
            next_section_markers = ["## ", "##"]
            end_index = len(existing_content)
            
            for marker in next_section_markers:
                idx = existing_content.find(marker, start_index + 1)
                if idx != -1 and idx < end_index:
                    end_index = idx

            # Replace the old section with the new one
            new_content = (
                existing_content[:start_index] + 
                mde_section + 
                existing_content[end_index:]
            )
        else:
            logger.info("MDE_Estimation section not found. Appending to end.")
            # Append to the end of the file
            new_content = existing_content + mde_section

        # Write the updated content
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(new_content)
        
        logger.info(f"Successfully updated {output_path} with MDE estimation results")
        return True

    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        return False
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in MDE results file: {e}")
        return False
    except Exception as e:
        logger.error(f"Unexpected error updating research.md: {e}")
        return False

def main():
    """Main entry point for the script."""
    logger.info("Starting T011c: Update research.md with MDE estimation results")
    
    success = update_research_md(MDE_RESULTS_PATH, RESEARCH_MD_PATH)
    
    if success:
        logger.info("T011c completed successfully")
        sys.exit(0)
    else:
        logger.error("T011c failed")
        sys.exit(1)

if __name__ == "__main__":
    main()
