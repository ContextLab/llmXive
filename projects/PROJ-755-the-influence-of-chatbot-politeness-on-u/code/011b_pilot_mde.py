import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional
import pandas as pd
import numpy as np
from statsmodels.stats.power import tt_ind_solve_power
from scipy import stats

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def find_dataset_file() -> Path:
    """
    Locate the raw HCI_P2 dataset file generated by T015.
    Looks in data/raw/hci_p2/ for parquet or csv files.
    """
    raw_dir = Path("data/raw/hci_p2")
    if not raw_dir.exists():
        raise FileNotFoundError(f"Raw data directory {raw_dir} does not exist. Run T015 first.")
    
    # Look for parquet files first
    parquet_files = list(raw_dir.glob("*.parquet"))
    if parquet_files:
        return parquet_files[0]
    
    # Fallback to csv
    csv_files = list(raw_dir.glob("*.csv"))
    if csv_files:
        return csv_files[0]
    
    raise FileNotFoundError(f"No dataset files found in {raw_dir}. Expected .parquet or .csv.")

def load_dataset_sample(file_path: Path, sample_size: int = 1000) -> pd.DataFrame:
    """
    Load a sample of the dataset.
    If the file is smaller than sample_size, load all rows.
    """
    logger.info(f"Loading dataset sample from {file_path}")
    
    if file_path.suffix == '.parquet':
        df = pd.read_parquet(file_path)
    elif file_path.suffix == '.csv':
        df = pd.read_csv(file_path)
    else:
        raise ValueError(f"Unsupported file format: {file_path.suffix}")
    
    total_rows = len(df)
    if total_rows < sample_size:
        logger.warning(f"Dataset has only {total_rows} rows, loading all.")
        sample = df.copy()
    else:
        # Take the first N rows as the pilot sample
        sample = df.head(sample_size).copy()
        logger.info(f"Loaded {len(sample)} rows (first {sample_size} of {total_rows})")
    
    return sample

def estimate_effect_size(df: pd.DataFrame) -> float:
    """
    Estimate Cohen's d effect size for the relationship between
    politeness_score and quality_rating.
    
    We dichotomize quality_rating into 'High' (>= 4) and 'Low' (< 4)
    for the purpose of effect size estimation in a pilot context.
    """
    if 'politeness_score' not in df.columns or 'quality_rating' not in df.columns:
        raise ValueError("Dataset must contain 'politeness_score' and 'quality_rating' columns.")
    
    # Remove rows with missing values for these columns
    valid_df = df.dropna(subset=['politeness_score', 'quality_rating'])
    
    if len(valid_df) < 2:
        raise ValueError("Not enough valid data points to estimate effect size.")
    
    # Dichotomize quality rating for pilot effect size estimation
    # High quality: rating >= 4, Low quality: rating < 4
    valid_df['quality_group'] = (valid_df['quality_rating'] >= 4).astype(int)
    
    group_high = valid_df[valid_df['quality_group'] == 1]['politeness_score']
    group_low = valid_df[valid_df['quality_group'] == 0]['politeness_score']
    
    if len(group_high) < 2 or len(group_low) < 2:
        logger.warning("Insufficient samples in one group for t-test. Using correlation-based effect size.")
        # Fallback to point-biserial correlation
        corr, _ = stats.pointbiserialr(valid_df['quality_group'], valid_df['politeness_score'])
        # Convert r to d: d = 2r / sqrt(1-r^2)
        if abs(corr) >= 1:
            d = 0.84 # Arbitrary small effect if correlation is perfect (edge case)
        else:
            d = (2 * corr) / np.sqrt(1 - corr**2)
        return abs(d)
    
    # Calculate Cohen's d
    mean_high = group_high.mean()
    mean_low = group_low.mean()
    std_pooled = np.sqrt(((group_high.std()**2 * (len(group_high)-1)) + 
                          (group_low.std()**2 * (len(group_low)-1))) / 
                         (len(group_high) + len(group_low) - 2))
    
    if std_pooled == 0:
        return 0.0
    
    d = (mean_high - mean_low) / std_pooled
    logger.info(f"Estimated Cohen's d: {d:.4f} (High: {mean_high:.2f}, Low: {mean_low:.2f}, Pooled SD: {std_pooled:.2f})")
    return abs(d)

def calculate_mde(effect_size: float, alpha: float = 0.05, power: float = 0.80) -> Dict[str, Any]:
    """
    Calculate Minimum Detectable Effect (MDE) given an estimated effect size,
    or calculate required sample size for a target power.
    
    Here we use the estimated effect size to report the MDE for the current pilot sample size,
    and also calculate what sample size would be needed to detect this effect with 80% power.
    """
    if effect_size == 0:
        logger.warning("Effect size is 0. Cannot calculate MDE.")
        return {
            "minimum_detectable_effect": None,
            "power": power,
            "sample_size": None,
            "note": "Effect size estimation resulted in zero."
        }
    
    # Calculate sample size needed to detect this effect size with given power
    # Using two-sided t-test
    n_per_group = tt_ind_solve_power(
        effect_size=effect_size, 
        alpha=alpha, 
        power=power, 
        ratio=1.0, 
        alternative='two-sided'
    )
    
    total_sample_size = int(np.ceil(n_per_group * 2))
    
    # The MDE for the current pilot sample size (1000)
    # We invert the power calculation: what effect size can we detect with N=1000?
    pilot_n = 1000
    pilot_n_per_group = pilot_n / 2
    mde = tt_ind_solve_power(
        nobs1=pilot_n_per_group,
        alpha=alpha,
        power=power,
        ratio=1.0,
        alternative='two-sided'
    )
    
    return {
        "estimated_effect_size": effect_size,
        "minimum_detectable_effect": mde,
        "power": power,
        "sample_size_for_power": total_sample_size,
        "pilot_sample_size": pilot_n,
        "alpha": alpha
    }

def run_pilot_analysis(df: pd.DataFrame) -> Dict[str, Any]:
    """
    Execute the pilot analysis: estimate effect size and calculate MDE.
    """
    logger.info("Running pilot analysis on first 1000 rows...")
    
    try:
        effect_size = estimate_effect_size(df)
        mde_results = calculate_mde(effect_size)
        mde_results["status"] = "success"
        return mde_results
    except Exception as e:
        logger.error(f"Pilot analysis failed: {e}")
        return {
            "status": "failed",
            "error": str(e),
            "minimum_detectable_effect": None,
            "power": None,
            "sample_size": None
        }

def save_results(results: Dict[str, Any], output_path: Path) -> None:
    """
    Save the pilot results to a JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    logger.info(f"Results saved to {output_path}")

def main():
    """
    Main entry point for the pilot MDE task (T011b).
    """
    output_path = Path("data/processed/pilot_mde_results.json")
    
    try:
        # 1. Find the raw dataset
        dataset_path = find_dataset_file()
        
        # 2. Load the first 1000 rows
        sample_df = load_dataset_sample(dataset_path, sample_size=1000)
        
        # 3. Run the pilot analysis
        results = run_pilot_analysis(sample_df)
        
        # 4. Save results
        save_results(results, output_path)
        
        if results["status"] == "success":
            logger.info("Pilot analysis completed successfully.")
            logger.info(f"MDE for pilot sample: {results['minimum_detectable_effect']:.4f}")
            logger.info(f"Estimated effect size: {results['estimated_effect_size']:.4f}")
            logger.info(f"Required sample size for 80% power: {results['sample_size_for_power']}")
        else:
            logger.error("Pilot analysis failed.")
            sys.exit(1)
            
    except FileNotFoundError as e:
        logger.error(f"Data source not found: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
