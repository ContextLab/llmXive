"""
Task T015a: HCI_P2 Validation

Verifies the validity of the HCI_P2 dataset for downstream tasks.
Reads the validation status generated by T015 and ensures the pipeline
proceeds only if the status is "valid".
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger("T015a_Validator")

def ensure_directories(base_path: Path) -> None:
    """Ensure required directories exist."""
    data_raw_path = base_path / "data" / "raw" / "hci_p2"
    data_raw_path.mkdir(parents=True, exist_ok=True)
    logger.info(f"Ensured directory exists: {data_raw_path}")

def load_validation_status(base_path: Path) -> Dict[str, Any]:
    """
    Load the validation status JSON generated by T015.
    
    Args:
        base_path: Project root path.
        
    Returns:
        Dictionary containing validation status.
        
    Raises:
        FileNotFoundError: If the validation status file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    status_file = base_path / "data" / "raw" / "hci_p2" / "validation_status.json"
    if not status_file.exists():
        raise FileNotFoundError(
            f"Validation status file not found: {status_file}. "
            "Ensure T015 has been executed successfully."
        )
    
    with open(status_file, 'r', encoding='utf-8') as f:
        return json.load(f)

def validate_hci_p2(status_data: Dict[str, Any]) -> bool:
    """
    Validate the HCI_P2 dataset status.
    
    Args:
        status_data: The loaded validation status dictionary.
        
    Returns:
        True if status is "valid".
        
    Raises:
        SystemExit: If status is "invalid" or missing required fields.
    """
    status = status_data.get("status")
    
    if status is None:
        logger.error("HCI_P2_INVALID: 'status' field missing in validation_status.json")
        raise SystemExit("HCI_P2_INVALID: Missing status field. Aborting pipeline.")
    
    if status == "valid":
        logger.info("HCI_P2 Validation PASSED. Status: valid")
        return True
    elif status == "invalid":
        logger.error("HCI_P2_INVALID: Status is 'invalid'. Stop Condition Met.")
        raise SystemExit("HCI_P2_INVALID: Stop Condition Met. Aborting pipeline.")
    else:
        logger.error(f"HCI_P2_INVALID: Unknown status '{status}'.")
        raise SystemExit(f"HCI_P2_INVALID: Unknown status '{status}'. Aborting pipeline.")

def save_validation_flag(base_path: Path, status: str) -> None:
    """
    Update the validation status file to reflect the final validation result.
    
    Args:
        base_path: Project root path.
        status: The final status string (e.g., "valid").
    """
    status_file = base_path / "data" / "raw" / "hci_p2" / "validation_status.json"
    data = {
        "status": status,
        "validated_by": "T015a",
        "message": "HCI_P2 validated successfully for downstream tasks."
    }
    
    with open(status_file, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=2)
    
    logger.info(f"Updated validation status file: {status_file}")

def main() -> None:
    """Main entry point for T015a."""
    base_path = Path(__file__).resolve().parent.parent
    logger.info(f"Starting HCI_P2 Validation (T015a) from {base_path}")
    
    try:
        ensure_directories(base_path)
        status_data = load_validation_status(base_path)
        
        if validate_hci_p2(status_data):
            save_validation_flag(base_path, "valid")
            logger.info("T015a completed successfully.")
        else:
            # This line should not be reached due to SystemExit in validate_hci_p2
            logger.error("Unexpected state: validation failed but did not exit.")
            sys.exit(1)
            
    except FileNotFoundError as e:
        logger.error(f"File Error: {e}")
        sys.exit(1)
    except json.JSONDecodeError as e:
        logger.error(f"JSON Error: {e}")
        sys.exit(1)
    except SystemExit as e:
        # Re-raise SystemExit to ensure the pipeline stops
        raise e
    except Exception as e:
        logger.error(f"Unexpected error during validation: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()