"""
T015a: HCI_P2 Validation
Verifies HCI_P2 validity for downstream tasks based on the validation status
generated by T015 (code/01_download_and_score.py).
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def ensure_directories():
    """Ensure output directories exist."""
    output_dir = Path("data/processed")
    output_dir.mkdir(parents=True, exist_ok=True)
    return output_dir

def load_validation_status(input_path: Path) -> Dict[str, Any]:
    """Load the validation status JSON generated by T015."""
    if not input_path.exists():
        raise FileNotFoundError(
            f"Validation status file not found at {input_path}. "
            "Ensure T015 (code/01_download_and_score.py) has been run successfully."
        )
    
    with open(input_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def validate_hci_p2(validation_data: Dict[str, Any]) -> str:
    """
    Determine HCI_P2 validity based on the validation status.
    
    Returns:
        str: 'HCI_P2_VALID' or 'HCI_P2_INVALID'
    """
    is_valid = validation_data.get('is_valid', False)
    
    if is_valid:
        logger.info("HCI_P2 validation status: VALID")
        return "HCI_P2_VALID"
    else:
        logger.warning("HCI_P2 validation status: INVALID")
        return "HCI_P2_INVALID"

def save_validation_flag(output_dir: Path, flag: str) -> Path:
    """Save the validation flag to a JSON file."""
    output_file = output_dir / "hci_p2_validation_flag.json"
    
    result = {
        "hci_p2_status": flag,
        "task_id": "T015a",
        "description": "HCI_P2 Validation Result"
    }
    
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(result, f, indent=2)
    
    logger.info(f"Validation flag saved to {output_file}")
    return output_file

def main():
    """Main entry point for T015a."""
    try:
        # Define paths
        input_path = Path("data/raw/hci_p2/validation_status.json")
        output_dir = ensure_directories()
        
        logger.info(f"Loading validation status from {input_path}...")
        validation_data = load_validation_status(input_path)
        
        logger.info("Validating HCI_P2...")
        flag = validate_hci_p2(validation_data)
        
        logger.info("Saving validation flag...")
        output_file = save_validation_flag(output_dir, flag)
        
        logger.info(f"T015a completed successfully. Flag: {flag}")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        logger.error("This task depends on T015 completing successfully.")
        return 1
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in validation status file: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during validation: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())