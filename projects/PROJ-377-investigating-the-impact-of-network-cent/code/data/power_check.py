import os
import json
import logging
from pathlib import Path
import pandas as pd
from utils.logging import setup_logger

def load_retention_metrics(retention_file_path: str) -> dict:
    """
    Load the retention metrics from the JSON file generated by T003.
    
    Args:
        retention_file_path: Path to retention_metrics.json
      
    Returns:
        Dictionary containing retention metrics.
      
    Raises:
        FileNotFoundError: If the retention metrics file does not exist.
        ValueError: If the file is not valid JSON or lacks required keys.
    """
    path = Path(retention_file_path)
    if not path.exists():
        raise FileNotFoundError(f"Retention metrics file not found: {retention_file_path}")
    
    with open(path, 'r') as f:
        data = json.load(f)
    
    # Validate required fields
    required_keys = ['retention_rate', 'total_subjects', 'retained_subjects']
    for key in required_keys:
        if key not in data:
            raise ValueError(f"Missing required key in retention metrics: {key}")
    
    return data

def check_power(retention_data: dict, threshold: int = 50) -> dict:
    """
    Calculate power metrics based on retained subjects count.
    
    Args:
        retention_data: Dictionary containing retention metrics (from load_retention_metrics).
        threshold: Minimum number of subjects required for adequate power (default 50).
      
    Returns:
        Dictionary containing power calculation results.
    """
    n_subjects = retention_data['retained_subjects']
    meets_threshold = n_subjects >= threshold
    
    return {
        'n_subjects': n_subjects,
        'threshold': threshold,
        'meets_threshold': meets_threshold
    }

def save_power_check_results(power_data: dict, output_path: str) -> None:
    """
    Save the power calculation results to a JSON file.
    
    Args:
        power_data: Dictionary containing power metrics.
        output_path: Path where the output JSON file will be saved.
    """
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(path, 'w') as f:
        json.dump(power_data, f, indent=2)
    
    logging.info(f"Power metrics saved to {output_path}")

def main():
    """
    Main entry point for the power check task (T004a).
    
    Reads retention metrics from T003, calculates power, and saves results.
    """
    logger = setup_logger(__name__)
    
    # Define paths based on project structure
    retention_file = "data/processed/behavioral/retention_metrics.json"
    output_file = "data/processed/behavioral/power_metrics.json"
    power_threshold = 50  # Spec threshold from T004a description
    
    try:
        # Load retention metrics (output of T003)
        logger.info(f"Loading retention metrics from {retention_file}")
        retention_data = load_retention_metrics(retention_file)
        
        # Perform power calculation
        logger.info(f"Calculating power with threshold {power_threshold}")
        power_data = check_power(retention_data, threshold=power_threshold)
        
        # Save results
        logger.info(f"Saving power metrics to {output_file}")
        save_power_check_results(power_data, output_file)
        
        # Log summary
        status = "PASS" if power_data['meets_threshold'] else "FAIL"
        logger.info(f"Power Check {status}: N={power_data['n_subjects']}, Threshold={power_data['threshold']}")
        
    except FileNotFoundError as e:
        logger.error(f"Critical error: {e}")
        logger.error("Cannot proceed with power calculation without retention metrics (T003).")
        raise
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during power calculation: {e}")
        raise

if __name__ == "__main__":
    main()
