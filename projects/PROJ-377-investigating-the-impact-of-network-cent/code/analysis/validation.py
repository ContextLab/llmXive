def run_freedman_lane_permutation(
    y: np.ndarray, 
    X: np.ndarray, 
    null_residuals: np.ndarray, 
    n_permutations: int = 1000, 
    seed: int = 42
) -> Dict[str, Union[float, np.ndarray]]:
    """
    Implements the Freedman-Lane permutation test.
    
    Steps:
    1. Fit the full model: Y ~ X + Covariates (we assume X here is the primary predictor of interest).
       However, the prompt specifies shuffling the NULL residuals.
       Standard Freedman-Lane for Y = X*beta + Z*gamma + eps:
       a. Fit reduced model (null model) Y = Z*gamma + r (where Z is covariates, r are null residuals).
          Here, T023.5 provided 'null_residuals' from an intercept-only model (Y ~ 1).
          So Z is just the intercept.
       b. Permute the residuals: r_perm = P * r (where P is a permutation matrix).
       c. Construct pseudo-Y: Y* = Z*gamma_hat + r_perm.
       d. Fit full model on Y*: Y* ~ X + Z. Get statistic (t or beta) for X.
       e. Repeat.
    
    In this specific context:
    - Null model is Intercept only. Z = [1, 1, ...].
    - Null residuals are provided.
    - We need to generate Y* by adding permuted residuals to the null prediction (mean of Y).
    - Then regress Y* on X (and potentially covariates if we had them, but the task focuses on the primary test).
    - Actually, the prompt says "shuffles the null residuals with a fixed random seed".
    
    Simplified interpretation for this pipeline:
    1. Calculate the observed t-statistic for the primary predictor in the original data (from T024).
       Since we don't have the full model coefficients here, we will re-calculate the observed statistic
       from the loaded data (assuming the model was Y ~ X + Covariates).
       Wait, T024 output summary is in CSV. We should load the observed t-stat from there if possible,
       or re-calculate it.
       To be self-contained in this script, we will re-calculate the observed statistic from the loaded data.
       We assume the model fitted in T024 was: Improvement ~ Predictor + Age + Sex + FD.
       We need to load covariates too for a proper Freedman-Lane.
       
    *Correction*: The task T032 description says: "Calculate empirical p-value for the primary coefficient."
    It references "null residuals" from T023.5.
    If we strictly follow Freedman-Lane:
    1. Fit Null Model: Y ~ 1 (Intercept). Residuals = r.
    2. Permute r -> r_perm.
    3. Construct Y_perm = mean(Y) + r_perm.
    4. Fit Full Model: Y_perm ~ X + Covariates.
    5. Record t-stat for X.
    
    We need the covariates (Age, Sex, FD) to do step 4 correctly.
    The function `load_regression_data` currently only returns Y and X.
    We need to extend loading to include covariates or assume the "null residuals" approach
    implies a simpler test if covariates are not available.
    However, T024 explicitly uses covariates.
    
    Let's assume the merged data file contains all columns.
    We will load Y, X, and Covariates.
    """
    config = get_config()
    data_path = config.output_paths.processed_dir / "regression" / "model_data.csv"
    
    if not data_path.exists():
        raise FileNotFoundError(f"Model data not found: {data_path}")
    
    df = pd.read_csv(data_path)
    
    # Identify columns
    y_col = 'Improvement'
    x_col = 'Global_Centrality' if 'Global_Centrality' in df.columns else next(c for c in df.columns if c.startswith('PCA_Component'))
    
    covariate_cols = [c for c in ['Age', 'Sex', 'Mean_FD'] if c in df.columns]
    
    y = df[y_col].values
    X = df[x_col].values.reshape(-1, 1)
    Z = df[covariate_cols].values if covariate_cols else np.ones((len(y), 1)) # Intercept handled in Z if needed
    
    # 1. Calculate Observed Statistic (t-stat for X in model Y ~ X + Z)
    # We use OLS: Y = X*beta + Z*gamma + eps
    # Design matrix for Full Model
    X_full = np.column_stack([X, Z])
    
    # OLS solution
    # beta_full = (X_full.T X_full)^-1 X_full.T Y
    try:
        beta_full = np.linalg.lstsq(X_full, y, rcond=None)[0]
    except np.linalg.LinAlgError:
        raise RuntimeError("Design matrix is singular. Cannot compute observed statistic.")
    
    # Standard error and t-stat for the first coefficient (X)
    # Residuals
    y_hat = X_full @ beta_full
    residuals = y - y_hat
    n = len(y)
    p = X_full.shape[1]
    mse = np.sum(residuals**2) / (n - p)
    
    # Covariance matrix of beta: MSE * (X'X)^-1
    try:
        XtX_inv = np.linalg.inv(X_full.T @ X_full)
    except np.linalg.LinAlgError:
        raise RuntimeError("Matrix inversion failed for covariance calculation.")
        
    var_beta = mse * XtX_inv
    se_beta = np.sqrt(var_beta[0, 0]) # Variance of the first coefficient (X)
    
    if se_beta == 0:
        t_obs = np.inf if beta_full[0] > 0 else -np.inf
    else:
        t_obs = beta_full[0] / se_beta
    
    logger.info(f"Observed t-statistic: {t_obs:.4f}")
    
    # 2. Permutation Loop (Freedman-Lane)
    rng = np.random.default_rng(seed)
    t_stats = np.zeros(n_permutations)
    
    # Null prediction (Intercept only)
    # Since T023.5 was intercept only, the 'null residuals' are Y - mean(Y).
    # So Y_null_pred = mean(Y).
    y_null_pred = np.mean(y)
    
    # We need to permute the NULL residuals provided
    # Note: The provided null_residuals array must match the length of y
    if len(null_residuals) != len(y):
        raise ValueError(f"Length of null_residuals ({len(null_residuals)}) does not match Y ({len(y)}).")
    
    for i in range(n_permutations):
        # a. Permute residuals
        # Use a random permutation of indices
        perm_indices = rng.permutation(len(null_residuals))
        r_perm = null_residuals[perm_indices]
        
        # b. Construct pseudo-Y
        y_perm = y_null_pred + r_perm
        
        # c. Fit full model on Y_perm
        # Y_perm = X*beta + Z*gamma + eps
        try:
            beta_perm = np.linalg.lstsq(X_full, y_perm, rcond=None)[0]
        except np.linalg.LinAlgError:
            t_stats[i] = 0.0
            continue
        
        # d. Calculate t-stat for X (first coeff)
        y_hat_perm = X_full @ beta_perm
        res_perm = y_perm - y_hat_perm
        mse_perm = np.sum(res_perm**2) / (n - p)
        
        # Reuse XtX_inv as X is fixed
        var_beta_perm = mse_perm * XtX_inv
        se_beta_perm = np.sqrt(var_beta_perm[0, 0])
        
        if se_beta_perm == 0:
            t_stats[i] = np.inf if beta_perm[0] > 0 else -np.inf
        else:
            t_stats[i] = beta_perm[0] / se_beta_perm
    
    # 3. Calculate Empirical P-value
    # Two-tailed test: P = (count(|t_perm| >= |t_obs|) + 1) / (n + 1)
    count_extreme = np.sum(np.abs(t_stats) >= np.abs(t_obs))
    p_value = (count_extreme + 1) / (n_permutations + 1)
    
    return {
        "observed_t_statistic": float(t_obs),
        "empirical_p_value": float(p_value),
        "null_distribution": t_stats.tolist(),
        "n_permutations": n_permutations,
        "seed": seed
    }

def save_permutation_results(results: Dict[str, Union[float, np.ndarray, list]], output_path: Path):
    """Saves permutation results to JSON."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    # Convert numpy types to native python for JSON serialization
    serializable = {}
    for k, v in results.items():
        if isinstance(v, np.ndarray):
            serializable[k] = v.tolist()
        elif isinstance(v, (np.float64, np.float32)):
            serializable[k] = float(v)
        elif isinstance(v, (np.int64, np.int32)):
            serializable[k] = int(v)
        else:
            serializable[k] = v
    
    with open(output_path, 'w') as f:
        json.dump(serializable, f, indent=2)
    logger.info(f"Permutation results saved to {output_path}")

def generate_null_distribution_histogram(
    null_distribution: np.ndarray, 
    observed_t: float,
    output_path: Path
):
    """
    Generates a histogram of the null distribution with the observed t-statistic marked.
    Saves the plot to the specified path.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    plt.figure(figsize=(10, 6))
    sns.histplot(null_distribution, kde=True, color='skyblue', edgecolor='black', alpha=0.7, bins=30)
    
    # Add vertical line for observed t
    plt.axvline(x=observed_t, color='red', linestyle='--', linewidth=2, label=f'Observed t = {observed_t:.3f}')
    
    plt.title('Null Distribution of T-Statistic (Freedman-Lane Permutation)')
    plt.xlabel('T-Statistic')
    plt.ylabel('Frequency')
    plt.legend()
    plt.grid(axis='y', alpha=0.3)
    
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()
    logger.info(f"Null distribution histogram saved to {output_path}")

def run_validation_analysis():
    """
    Orchestrates the validation analysis for T032.
    1. Loads null residuals (T023.5).
    2. Loads regression data (Y, X, Covariates).
    3. Runs Freedman-Lane permutation test.
    4. Saves results (JSON).
    5. Generates histogram (PNG).
    """
    logger.info("Starting validation analysis (T032)...")
    config = get_config()
    
    # Paths
    output_dir = config.output_paths.processed_dir / "validation"
    output_dir.mkdir(parents=True, exist_ok=True)
    
    results_json_path = output_dir / "permutation_results.json"
    histogram_path = output_dir / "null_distribution.png"
    
    try:
        # 1. Load Data
        logger.info("Loading null residuals...")
        null_residuals = load_null_residuals()
        
        logger.info("Loading regression data...")
        y, X = load_regression_data() # Note: This function currently returns only Y and X, 
                                      # but run_freedman_lane_permutation needs covariates.
                                      # We will fix the logic inside run_freedman_lane_permutation 
                                      # to load the full CSV itself to avoid API mismatch.
        
        # 2. Run Permutation
        n_perm = get_permutation_shuffles()
        seed = get_permutation_seed()
        
        logger.info(f"Running Freedman-Lane permutation test ({n_perm} shuffles, seed={seed})...")
        results = run_freedman_lane_permutation(
            y=y, 
            X=X, 
            null_residuals=null_residuals, 
            n_permutations=n_perm, 
            seed=seed
        )
        
        # 3. Save Results
        save_permutation_results(results, results_json_path)
        
        # 4. Generate Plot
        generate_null_distribution_histogram(
            null_distribution=np.array(results['null_distribution']),
            observed_t=results['observed_t_statistic'],
            output_path=histogram_path
        )
        
        logger.info("Validation analysis completed successfully.")
        return results
        
    except FileNotFoundError as e:
        logger.error(f"Missing required data file: {e}")
        raise
    except Exception as e:
        logger.error(f"Validation analysis failed: {e}")
        raise

def main():
    """Entry point for the validation script."""
    run_validation_analysis()

if __name__ == "__main__":
    main()
