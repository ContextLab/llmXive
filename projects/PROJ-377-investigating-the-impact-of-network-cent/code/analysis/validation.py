def load_null_residuals() -> np.ndarray:
    """
    Loads the null residuals generated by the intercept-only model (T023.5).
    Expected path: data/processed/validation/null_residuals.csv
    """
    config = get_config()
    input_path = config.output_paths.processed_dir / "validation" / "null_residuals.csv"
    
    if not input_path.exists():
        raise FileNotFoundError(
            f"Required artifact not found: {input_path}. "
            "Ensure T023.5 (Null Model Generation) has been executed successfully."
        )
    
    df = pd.read_csv(input_path)
    # Assuming the column is named 'residuals' based on standard regression output
    if 'residuals' in df.columns:
        return df['residuals'].values
    elif len(df.columns) == 1:
        return df.iloc[:, 0].values
    else:
        raise ValueError(f"Could not identify residual column in {input_path}. Columns: {df.columns.tolist()}")

def load_regression_data() -> Tuple[np.ndarray, np.ndarray]:
    """
    Loads the primary outcome (Improvement) and the primary predictor (Global_Centrality or PCA)
    used in the main model (T024).
    Expected path: data/processed/regression/model_data.csv (merged data from T024 logic)
    """
    config = get_config()
    # We assume the regression analysis in T024 saved the merged data used for fitting
    # If not explicitly saved, we reconstruct it or load from the standard output.
    # For robustness, we look for the merged dataset used in regression.
    input_path = config.output_paths.processed_dir / "regression" / "model_data.csv"
    
    if not input_path.exists():
        # Fallback to reconstructing from component files if model_data.csv isn't there,
        # but strictly speaking, T024 should have produced the merged data.
        # Let's try to load the linear model summary to see if we can infer, or fail.
        raise FileNotFoundError(
            f"Regression data file not found: {input_path}. "
            "Ensure T024 (Linear Regression) has been executed and saved model_data.csv."
        )
    
    df = pd.read_csv(input_path)
    
    # Identify columns based on standard naming in T024/T025
    y_col = 'Improvement'
    x_col = None
    
    # Prefer Global_Centrality if present, else the first PCA component
    if 'Global_Centrality' in df.columns:
        x_col = 'Global_Centrality'
    elif any(c.startswith('PCA_Component') for c in df.columns):
        x_col = next(c for c in df.columns if c.startswith('PCA_Component'))
    else:
        raise ValueError(f"Could not identify predictor column in {input_path}.")
    
    return df[y_col].values, df[x_col].values

