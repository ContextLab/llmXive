import os
import sys
import json
import logging
import csv
from pathlib import Path
import importlib.util
import subprocess
import time

from utils.logging import setup_logger

# Configure logging for the validation script
logger = setup_logger(__name__, "data/processed/logs/quickstart_validation.log")

def check_file_exists(path_str: str) -> bool:
    """Check if a file exists at the given path."""
    path = Path(path_str)
    exists = path.exists()
    if exists:
        logger.info(f"File exists: {path_str}")
    else:
        logger.error(f"File missing: {path_str}")
    return exists

def check_json_validity(path_str: str) -> bool:
    """Check if a JSON file is valid and readable."""
    path = Path(path_str)
    if not path.exists():
        logger.error(f"JSON file missing: {path_str}")
        return False
    try:
        with open(path, 'r') as f:
            json.load(f)
        logger.info(f"JSON valid: {path_str}")
        return True
    except json.JSONDecodeError as e:
        logger.error(f"JSON invalid ({e}): {path_str}")
        return False

def check_csv_validity(path_str: str) -> bool:
    """Check if a CSV file is valid and readable."""
    path = Path(path_str)
    if not path.exists():
        logger.error(f"CSV file missing: {path_str}")
        return False
    try:
        with open(path, 'r', newline='') as f:
            reader = csv.reader(f)
            header = next(reader, None)
            if header is None:
                logger.error(f"CSV empty (no header): {path_str}")
                return False
            # Try to read one more row to ensure it's not just a header
            row = next(reader, None)
            if row is None:
                logger.warning(f"CSV has header but no data rows: {path_str}")
                # Depending on strictness, this might be a failure. 
                # For validation of "existence of output", header is minimal proof of generation.
                # We will return True but log the warning.
            logger.info(f"CSV valid: {path_str}")
            return True
    except Exception as e:
        logger.error(f"CSV read error ({e}): {path_str}")
        return False

def check_dependencies() -> bool:
    """Check if required dependencies are installed."""
    required = [
        'pandas', 'numpy', 'networkx', 'scikit-learn', 
        'statsmodels', 'nilearn', 'matplotlib', 'seaborn'
    ]
    missing = []
    for pkg in required:
        try:
            importlib.import_module(pkg)
        except ImportError:
            missing.append(pkg)
    
    if missing:
        logger.error(f"Missing dependencies: {', '.join(missing)}")
        return False
    
    logger.info("All required dependencies installed.")
    return True

def check_local_modules() -> bool:
    """Check if local modules can be imported."""
    project_root = Path(__file__).parent.parent
    sys.path.insert(0, str(project_root))
    
    modules_to_check = [
        'analysis.centrality',
        'analysis.regression',
        'analysis.validation',
        'data.behavioral_extraction',
        'data.preprocess',
        'utils.config',
        'utils.metrics'
    ]
    
    failed_modules = []
    for mod_name in modules_to_check:
        try:
            importlib.import_module(mod_name)
            logger.info(f"Module importable: {mod_name}")
        except Exception as e:
            logger.error(f"Module import failed ({mod_name}): {e}")
            failed_modules.append(mod_name)
    
    if failed_modules:
        return False
    return True

def validate_artifacts() -> bool:
    """Validate all required artifacts generated by the pipeline."""
    required_artifacts = [
        # Phase 0
        ("data/processed/behavioral/retention_metrics.json", check_json_validity),
        ("data/processed/behavioral/subject_scores.csv", check_csv_validity),
        ("data/processed/logs/exclusion_log.csv", check_csv_validity),
        
        # Phase 2/3/4/5 Outputs
        ("data/processed/centrality/subject_id_metrics.csv", check_csv_validity),
        ("data/processed/centrality/global_scores.csv", check_csv_validity),
        ("data/processed/behavioral/fd_mean.csv", check_csv_validity),
        ("data/processed/centrality/vif_values.csv", check_csv_validity),
        ("data/processed/centrality/model_predictors.csv", check_csv_validity),
        ("data/processed/regression/linear_model_summary.csv", check_csv_validity),
        ("data/processed/validation/null_residuals.csv", check_csv_validity),
        ("data/processed/validation/baseline_r2.json", check_json_validity),
        ("data/processed/regression/nonlinearity_check.csv", check_csv_validity),
        ("data/processed/validation/null_distribution.csv", check_csv_validity),
        ("data/processed/validation/permutation_results.json", check_json_validity),
        ("data/processed/validation/cv_results.json", check_json_validity),
        
        # Reporting
        ("data/reproducibility_report.json", check_json_validity),
    ]
    
    all_valid = True
    for path, checker in required_artifacts:
        if not checker(path):
            all_valid = False
    
    return all_valid

def main():
    """Main entry point for quickstart validation."""
    logger.info("Starting Quickstart Validation...")
    start_time = time.time()
    
    results = {
        "dependencies": False,
        "modules": False,
        "artifacts": False,
        "overall": False
    }
    
    # 1. Check Dependencies
    logger.info("Checking dependencies...")
    results["dependencies"] = check_dependencies()
    
    # 2. Check Local Modules
    logger.info("Checking local modules...")
    results["modules"] = check_local_modules()
    
    # 3. Validate Artifacts
    logger.info("Validating artifacts...")
    results["artifacts"] = validate_artifacts()
    
    # Overall Result
    results["overall"] = all(results.values())
    
    end_time = time.time()
    duration = end_time - start_time
    
    # Log Summary
    logger.info("-" * 40)
    logger.info("VALIDATION SUMMARY")
    logger.info("-" * 40)
    logger.info(f"Dependencies Check: {'PASS' if results['dependencies'] else 'FAIL'}")
    logger.info(f"Modules Check:      {'PASS' if results['modules'] else 'FAIL'}")
    logger.info(f"Artifacts Check:    {'PASS' if results['artifacts'] else 'FAIL'}")
    logger.info(f"Overall Status:     {'PASS' if results['overall'] else 'FAIL'}")
    logger.info(f"Duration:           {duration:.2f}s")
    logger.info("-" * 40)
    
    # Save validation report
    report_path = Path("data/processed/logs/quickstart_validation_report.json")
    with open(report_path, 'w') as f:
        json.dump(results, f, indent=2)
    logger.info(f"Validation report saved to: {report_path}")
    
    if not results["overall"]:
        logger.error("Quickstart validation FAILED. Please review logs.")
        sys.exit(1)
    else:
        logger.info("Quickstart validation PASSED successfully.")
        sys.exit(0)

if __name__ == "__main__":
    main()
