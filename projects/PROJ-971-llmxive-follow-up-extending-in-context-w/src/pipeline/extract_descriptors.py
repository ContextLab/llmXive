"""
extract_descriptors.py
-----------------------

This script implements task **T003**: it extracts latent statistical descriptors
from each interaction clip generated by :pymod:`src.pipeline.generate_clips`.
For every ``clip_*.npz`` file found in ``data/raw/`` it:

1. Loads the ``states``, ``actions`` and ``observations`` arrays.
2. Passes them through the CPU‑only ICWM encoder
   (:pymod:`src.utils.icwm_encoder`) to obtain a latent token sequence.
3. Computes three time‑series statistics on the latent tokens:
   * **variance** – overall sample variance,
   * **lag‑1 autocorrelation** – average lag‑1 autocorrelation across token
     dimensions,
   * **spectral density** – mean power spectral density (Welch estimate) across
     dimensions.
4. Writes a CSV file ``data/processed/descriptors.csv`` that conforms to the
   JSON‑Schema located at
   ``specs/001-llmxive-follow-up-extending-in-context-w/contracts/descriptor.schema.yaml``.

The script is fully deterministic (fixed random seeds where applicable) and
logs progress using the project's ``llmxive_toolkit`` logger.

Usage
-----
The script can be invoked directly (no arguments are required) or with
optional CLI flags to customise input / output locations:

.. code-block:: bash

    python -m src.pipeline.extract_descriptors \\
        --input-dir data/raw \\
        --output data/processed/descriptors.csv

The CI quick‑start invokes the script without arguments, relying on the
default ``paths`` helpers.
"""

import argparse
import logging
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.signal import welch

from llmxive_toolkit import paths, get_logger

# Import the lightweight encoder we provide in ``src.utils.icwm_encoder``.
try:
    from src.utils.icwm_encoder import encode  # type: ignore
except ImportError as exc:
    raise ImportError(
        "The ICWM encoder could not be imported. Ensure that "
        "'src/utils/icwm_encoder.py' defines a function ``encode``."
    ) from exc

log = get_logger(__name__)

# ----------------------------------------------------------------------
# Descriptor helper functions
# ----------------------------------------------------------------------


def _variance(tokens: np.ndarray) -> float:
    """Return the overall sample variance of the token matrix."""
    return float(np.var(tokens))


def _lag1_autocorrelation(tokens: np.ndarray) -> float:
    """
    Compute the average lag‑1 autocorrelation across token dimensions.

    For each dimension ``d`` we compute the Pearson correlation between
    ``tokens[:-1, d]`` and ``tokens[1:, d]``.  The final descriptor is the
    mean of those correlations.  If a dimension has length < 2 the
    contribution is treated as 0.0 to avoid NaNs.
    """
    if tokens.shape[0] < 2:
        return 0.0

    corrs = []
    for dim in range(tokens.shape[1]):
        x = tokens[:-1, dim]
        y = tokens[1:, dim]
        # If the series is constant, correlation is undefined – treat as 0.
        if np.allclose(x, x[0]) and np.allclose(y, y[0]):
            corrs.append(0.0)
        else:
            corr = np.corrcoef(x, y)[0, 1]
            corrs.append(0.0 if np.isnan(corr) else float(corr))
    return float(np.mean(corrs))


def _mean_spectral_density(tokens: np.ndarray) -> float:
    """
    Compute the mean power spectral density using Welch's method.

    We apply ``scipy.signal.welch`` independently to each token dimension,
    then average the PSD values across frequencies and dimensions.
    """
    if tokens.shape[0] < 2:
        return 0.0

    psd_means = []
    for dim in range(tokens.shape[1]):
        f, pxx = welch(tokens[:, dim], nperseg=min(256, tokens.shape[0]))
        psd_means.append(float(np.mean(pxx)))
    return float(np.mean(psd_means))


# ----------------------------------------------------------------------
# Core processing
# ----------------------------------------------------------------------


def process_clip(clip_path: Path) -> dict:
    """
    Load a single ``.npz`` clip, run the encoder and compute descriptors.

    Parameters
    ----------
    clip_path: Path
        Path to the ``clip_{id}.npz`` file.

    Returns
    -------
    dict
        Mapping with keys ``clip_id``, ``variance``, ``autocorr_lag1``,
        ``spectral_density``.
    """
    try:
        data = np.load(clip_path)
    except Exception as exc:
        log.error(f"Failed to load clip {clip_path}: {exc}")
        raise

    states = data["states"]
    actions = data["actions"]
    observations = data["observations"]

    # Encode to latent tokens.
    tokens = encode(states, actions, observations)  # shape (T, D)

    # Compute descriptors.
    var = _variance(tokens)

    # Edge‑case handling: near‑zero variance → set dependent descriptors to 0.
    if var < 1e-8:
        ac1 = 0.0
        spec = 0.0
    else:
        ac1 = _lag1_autocorrelation(tokens)
        spec = _mean_spectral_density(tokens)

    return {
        "clip_id": clip_path.stem,
        "variance": var,
        "autocorr_lag1": ac1,
        "spectral_density": spec,
    }


def extract_all_descriptors(input_dir: Path, output_path: Path) -> None:
    """
    Iterate over all ``.npz`` files in ``input_dir`` and write the descriptor
    CSV to ``output_path``.
    """
    log.info(f"Scanning for clips in {input_dir}")
    npz_files = sorted(input_dir.glob("clip_*.npz"))
    if not npz_files:
        log.warning(f"No clip files found in {input_dir}. Writing empty descriptor CSV.")
        output_path.parent.mkdir(parents=True, exist_ok=True)
        pd.DataFrame(
            columns=["clip_id", "variance", "autocorr_lag1", "spectral_density"]
        ).to_csv(output_path, index=False)
        return

    records = []
    for npz_file in npz_files:
        log.debug(f"Processing {npz_file.name}")
        record = process_clip(npz_file)
        records.append(record)

    df = pd.DataFrame.from_records(records)
    df = df[["clip_id", "variance", "autocorr_lag1", "spectral_density"]]
    df = df.fillna(0.0)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    log.info(f"Wrote descriptors for {len(df)} clips to {output_path}")


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Extract latent statistical descriptors from ICWM clips."
    )
    parser.add_argument(
        "--input-dir",
        type=Path,
        default=paths.data("raw"),
        help="Directory containing ``clip_*.npz`` files (default: data/raw).",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=paths.data("processed", "descriptors.csv"),
        help="Path to the output CSV file (default: data/processed/descriptors.csv).",
    )
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    extract_all_descriptors(args.input_dir, args.output)


if __name__ == "__main__":
    main()
