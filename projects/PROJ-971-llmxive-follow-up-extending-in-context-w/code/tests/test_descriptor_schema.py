"""
Test that the descriptor CSV conforms to the JSON Schema contract.

The schema is located at:
    specs/001-llmxive-follow-up-extending-in-context-w/contracts/descriptor.schema.yaml

The CSV file to validate is:
    data/processed/descriptors.csv

The test loads the schema (YAML), parses the CSV with pandas, and validates
each record using jsonschema. It also performs a sanity check that the
highest variance descriptor is more than twice the lowest variance
descriptor, as required by the task specification.
"""

import pathlib

import pandas as pd
import yaml
from jsonschema import Draft7Validator, ValidationError

from llmxive_toolkit import paths, get_logger

log = get_logger(__name__)

def _load_schema() -> dict:
    """
    Load the descriptor JSON‑Schema from the contracts directory.

    Returns
    -------
    dict
        The parsed JSON schema.
    """
    # Correct path to the schema based on the repository layout.
    schema_path = (
        pathlib.Path(paths.root)
        / "specs"
        / "001-llmxive-follow-up-extending-in-context-w"
        / "contracts"
        / "descriptor.schema.yaml"
    )
    if not schema_path.is_file():
        raise FileNotFoundError(f"Descriptor schema not found at {schema_path}")
    with schema_path.open("r", encoding="utf-8") as f:
        schema = yaml.safe_load(f)
    return schema

def _load_descriptors() -> pd.DataFrame:
    """
    Load the descriptor CSV generated by the pipeline.

    Returns
    -------
    pandas.DataFrame
        DataFrame with the descriptor records.
    """
    csv_path = paths.data("processed", "descriptors.csv")
    if not csv_path.is_file():
        raise FileNotFoundError(f"Descriptor CSV not found at {csv_path}")
    df = pd.read_csv(csv_path, dtype=str)  # read everything as string; jsonschema will coerce numbers
    return df

def test_descriptors_schema():
    """
    Validate each row of the descriptor CSV against the JSON schema and
    perform the required sanity check on variance values.
    """
    schema = _load_schema()
    validator = Draft7Validator(schema)

    df = _load_descriptors()

    # Ensure required columns exist
    required_columns = {"clip_id", "variance", "autocorr_lag1", "spectral_density"}
    missing = required_columns - set(df.columns)
    assert not missing, f"Missing required columns in descriptors CSV: {missing}"

    errors = []

    for idx, row in df.iterrows():
        # Build a JSON‑compatible dict; convert numeric fields to appropriate types
        try:
            record = {
                "clip_id": row["clip_id"],
                "variance": float(row["variance"]),
                "autocorr_lag1": float(row["autocorr_lag1"]),
                "spectral_density": float(row["spectral_density"]),
            }
        except ValueError as exc:
            errors.append(f"Row {idx} conversion error: {exc}")
            continue

        try:
            validator.validate(record)
        except ValidationError as exc:
            errors.append(f"Row {idx} (clip_id={record['clip_id']}): {exc.message}")

    if errors:
        error_msg = "\n".join(errors)
        raise AssertionError(f"Descriptor schema validation failed:\\n{error_msg}")

    log.info("All %d descriptor records conform to the schema.", len(df))

    # Sanity check: variance_high > 2 * variance_low
    variances = df["variance"].astype(float)
    variance_high = variances.max()
    variance_low = variances.min()
    assert (
        variance_high > 2 * variance_low
    ), (
        f"Sanity check failed: max variance ({variance_high}) is not > 2 * "
        f"min variance ({variance_low})"
    )
    log.info(
        "Sanity check passed: max variance %.6f > 2 * min variance %.6f",
        variance_high,
        variance_low,
    )