def test_save_and_load_model(sample_data, tmp_path):
    """Test that a model can be saved to disk and loaded back."""
    target_col = 'time_to_peak_min'
    X = sample_data.drop(columns=[target_col])
    y = sample_data[target_col]
    
    X_train, X_test, y_train, y_test = split_data(sample_data)
    model = train_model(X_train, y_train)
    
    model_path = tmp_path / "test_model.pkl"
    save_model(model, str(model_path))
    
    assert model_path.exists()
    
    # Load the model back
    with open(model_path, 'rb') as f:
        loaded_model = pickle.load(f)
    
    # Verify it's the same type and can predict
    assert isinstance(loaded_model, RandomForestRegressor)
    pred_original = model.predict(X_test.head(5))
    pred_loaded = loaded_model.predict(X_test.head(5))
    
    np.testing.assert_array_almost_equal(pred_original, pred_loaded)

