import json
import os
import sys
import pickle
from pathlib import Path
from typing import Tuple, Dict, Any, Optional

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.model_selection import train_test_split, cross_val_score
from sklearn.metrics import mean_absolute_error, r2_score

# Constants
RANDOM_SEED = 42
MAX_ROWS = 10000
TEST_SIZE = 0.2

# Define target and feature columns based on previous tasks (US1)
TARGET_COL = "time_to_peak_minutes"
# Base features from ingestion
BASE_FEATURES = [
    "cold_work", "Mn_content", "Mg_content", "Si_content", "Cu_content",
    "annealing_temperature"
]
# Interaction features from US1 (T018)
INTERACTION_FEATURES = [
    "cold_work_Mn", "cold_work_Mg", "cold_work_Si", "cold_work_Cu"
]
ALL_FEATURES = BASE_FEATURES + INTERACTION_FEATURES

def load_final_dataset(path: str) -> pd.DataFrame:
    """Load the final dataset generated by US1."""
    df = pd.read_csv(path)
    return df

def split_data(df: pd.DataFrame) -> Tuple[pd.DataFrame, pd.DataFrame, pd.Series, pd.Series]:
    """
    Split data into training and test sets.
    Returns: X_train, X_test, y_train, y_test
    """
    X = df[ALL_FEATURES]
    y = df[TARGET_COL]

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=TEST_SIZE, random_state=RANDOM_SEED
    )
    return X_train, X_test, y_train, y_test

def train_model(X_train: pd.DataFrame, y_train: pd.Series) -> RandomForestRegressor:
    """
    Train a Random Forest Regressor (CPU-only).
    Ensures dataset size constraint (FR-003) is respected before training.
    """
    # Enforce row cap if necessary (FR-003)
    if len(X_train) > MAX_ROWS:
        # Deterministic sampling based on seed
        indices = np.random.RandomState(RANDOM_SEED).choice(len(X_train), MAX_ROWS, replace=False)
        X_train = X_train.iloc[indices]
        y_train = y_train.iloc[indices]

    model = RandomForestRegressor(
        n_estimators=100,
        max_depth=10,
        random_state=RANDOM_SEED,
        n_jobs=-1, # Use all CPU cores, but CPU-only
        verbose=1
    )
    model.fit(X_train, y_train)
    return model

def evaluate_model(model: RandomForestRegressor, X_test: pd.DataFrame, y_test: pd.Series) -> Dict[str, float]:
    """
    Evaluate model on test set.
    Returns: dict with 'mae' and 'r2'
    """
    y_pred = model.predict(X_test)
    mae = mean_absolute_error(y_test, y_pred)
    r2 = r2_score(y_test, y_pred)
    return {"mae": float(mae), "r2": float(r2)}

def save_model(model: RandomForestRegressor, path: str) -> None:
    """Save trained model to disk."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        pickle.dump(model, f)

def save_metrics(metrics: Dict[str, Any], path: str) -> None:
    """Save metrics to JSON."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(metrics, f, indent=2)

def run_training_pipeline(input_path: str, model_path: str, metrics_path: str) -> Dict[str, Any]:
    """
    Main pipeline: Load, Split, Train, Evaluate, Save.
    """
    print(f"Loading dataset from {input_path}...")
    df = load_final_dataset(input_path)

    # Verify dataset size constraint (FR-003) before splitting
    if len(df) > MAX_ROWS:
        print(f"Warning: Dataset size ({len(df)}) exceeds limit ({MAX_ROWS}). Truncating deterministically.")
        indices = np.random.RandomState(RANDOM_SEED).choice(len(df), MAX_ROWS, replace=False)
        df = df.iloc[indices]

    print(f"Splitting data (train/test)...")
    X_train, X_test, y_train, y_test = split_data(df)

    print(f"Training Random Forest Regressor (CPU-only)...")
    model = train_model(X_train, y_train)

    print(f"Evaluating on test set...")
    test_metrics = evaluate_model(model, X_test, y_test)

    # Perform 5-fold cross-validation on training set
    print(f"Performing 5-fold cross-validation...")
    cv_scores = cross_val_score(model, X_train, y_train, cv=5, scoring='r2', n_jobs=-1)
    cv_mean = float(np.mean(cv_scores))
    cv_std = float(np.std(cv_scores))

    print(f"Cross-Validation R²: {cv_mean:.4f} (+/- {cv_std:.4f})")
    print(f"Test MAE: {test_metrics['mae']:.4f}")
    print(f"Test R²: {test_metrics['r2']:.4f}")

    # Prepare full metrics report
    full_metrics = {
        "cv_r2_mean": cv_mean,
        "cv_r2_std": cv_std,
        "test_mae": test_metrics['mae'],
        "test_r2": test_metrics['r2'],
        "n_train_samples": len(X_train),
        "n_test_samples": len(X_test),
        "features_used": ALL_FEATURES
    }

    print(f"Saving model to {model_path}...")
    save_model(model, model_path)

    print(f"Saving metrics to {metrics_path}...")
    save_metrics(full_metrics, metrics_path)

    return full_metrics

def main():
    """Entry point for the training script."""
    # Paths relative to project root
    project_root = Path(__file__).resolve().parent.parent
    input_file = project_root / "data" / "processed" / "final_dataset.csv"
    model_file = project_root / "artifacts" / "models" / "kinetic_model.pkl"
    metrics_file = project_root / "artifacts" / "reports" / "training_metrics.json"

    if not input_file.exists():
        raise FileNotFoundError(f"Input dataset not found at {input_file}. "
                                "Please ensure US1 (T020) has completed successfully.")

    run_training_pipeline(
        input_path=str(input_file),
        model_path=str(model_file),
        metrics_path=str(metrics_file)
    )

if __name__ == "__main__":
    main()