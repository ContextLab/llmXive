"""
T012: Calculate synthetic baseline statistics.

Reads the raw, unclipped synthetic baseline data generated by T011
and calculates the mean of 'time_to_peak_min'.

Output: artifacts/reports/baseline_stats.json containing { "baseline_mean": float }
"""
import json
import os
import sys
from pathlib import Path
import pandas as pd
from config import get_project_root

def load_validated_data(raw_path: Path) -> pd.DataFrame:
    """Load the raw synthetic baseline data with strict validation."""
    if not raw_path.exists():
        raise FileNotFoundError(
            f"Required raw data file not found: {raw_path}. "
            "Ensure T011 (generate_synthetic.py) has run successfully."
        )
    
    try:
        df = pd.read_csv(raw_path)
    except Exception as e:
        raise RuntimeError(f"Failed to read CSV at {raw_path}: {e}")
    
    # Validate required columns exist
    required_cols = ['time_to_peak_min']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in raw data: {missing}")
    
    # Ensure numeric type for calculation
    if not pd.api.types.is_numeric_dtype(df['time_to_peak_min']):
        # Attempt conversion, but fail if impossible
        try:
            df['time_to_peak_min'] = pd.to_numeric(df['time_to_peak_min'], errors='raise')
        except (ValueError, TypeError) as e:
            raise ValueError(f"Column 'time_to_peak_min' contains non-numeric values: {e}")
    
    return df

def calculate_baseline_mean(df: pd.DataFrame) -> float:
    """Calculate the mean of time_to_peak_min from the raw dataframe."""
    if df.empty:
        raise ValueError("Input dataframe is empty; cannot calculate mean.")
    
    mean_val = df['time_to_peak_min'].mean()
    return float(mean_val)

def save_baseline_stats(baseline_mean: float, output_path: Path) -> None:
    """Save the baseline statistics to a JSON file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    stats = {
        "baseline_mean": baseline_mean
    }
    
    with open(output_path, 'w') as f:
        json.dump(stats, f, indent=2)
    
    print(f"Saved baseline statistics to {output_path}")

def main():
    """Main entry point for T012."""
    root = get_project_root()
    raw_data_path = root / "data" / "raw" / "synthetic_baseline.csv"
    output_path = root / "artifacts" / "reports" / "baseline_stats.json"
    
    print(f"T012: Loading raw synthetic data from {raw_data_path}...")
    df = load_validated_data(raw_data_path)
    
    print(f"T012: Calculating baseline mean for {len(df)} rows...")
    baseline_mean = calculate_baseline_mean(df)
    
    print(f"T012: Baseline mean (time_to_peak_min) = {baseline_mean:.4f}")
    
    save_baseline_stats(baseline_mean, output_path)
    print("T012: Complete.")

if __name__ == "__main__":
    main()
