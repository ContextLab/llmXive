"""
Calculate baseline statistics from the validated dataset.

This script reads the clipped/validated dataset generated by T021
and calculates the mean of the target variable (time_to_peak_min).
The result is stored in artifacts/reports/baseline_stats.json.

Dependency: T021 (validated.csv) must have completed successfully.
"""
import json
import os
import sys
from pathlib import Path

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from config import get_project_root


def load_validated_data():
    """Load the validated dataset from data/processed/validated.csv."""
    data_path = get_project_root() / "data" / "processed" / "validated.csv"
    
    if not data_path.exists():
        raise FileNotFoundError(
            f"Required input file not found: {data_path}. "
            "Ensure T021 (ingest.py) has completed successfully."
        )
    
    return data_path


def calculate_baseline_mean(df):
    """
    Calculate the mean of time_to_peak_min from the validated dataset.
    
    Args:
        df: pandas DataFrame containing the validated dataset.
        
    Returns:
        float: The mean value of time_to_peak_min.
    """
    if 'time_to_peak_min' not in df.columns:
        raise ValueError(
            "Column 'time_to_peak_min' not found in validated dataset. "
            "Check that T021 (ingest.py) correctly processed the data."
        )
    
    mean_value = df['time_to_peak_min'].mean()
    return float(mean_value)


def save_baseline_stats(baseline_mean, output_path):
    """
    Save baseline statistics to a JSON file.
    
    Args:
        baseline_mean: The calculated mean of time_to_peak_min.
        output_path: Path to the output JSON file.
    """
    stats = {
        "baseline_mean": baseline_mean,
        "description": "Mean time-to-peak softening from clipped validated data",
        "source_file": "data/processed/validated.csv"
    }
    
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(stats, f, indent=2)
    
    print(f"Baseline statistics saved to {output_path}")
    print(f"  baseline_mean: {baseline_mean:.4f}")


def main():
    """Main entry point for calculating baseline statistics."""
    project_root = get_project_root()
    
    # Define paths
    input_path = load_validated_data()
    output_path = project_root / "artifacts" / "reports" / "baseline_stats.json"
    
    print(f"Loading validated data from: {input_path}")
    
    try:
        import pandas as pd
        df = pd.read_csv(input_path)
        
        print(f"Loaded {len(df)} rows from validated dataset")
        
        # Calculate baseline mean
        baseline_mean = calculate_baseline_mean(df)
        
        # Save results
        save_baseline_stats(baseline_mean, output_path)
        
        print("Baseline statistics calculation completed successfully.")
        
    except Exception as e:
        print(f"Error processing validated data: {str(e)}")
        raise


if __name__ == "__main__":
    main()