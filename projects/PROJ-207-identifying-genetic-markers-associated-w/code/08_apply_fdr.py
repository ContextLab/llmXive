"""
Apply FDR correction to GWAS results and merge with raw statistics.

This script reads the raw GWAS results generated by PLINK, applies the
Benjamini-Hochberg FDR correction using the utility module, and merges
the results into the final artifact file.

Input: data/interim/gwas_raw.tsv
Output: data/processed/gwas_results_fdr.tsv
"""

import os
import sys
import argparse
import json
from pathlib import Path
import pandas as pd

# Add parent directory to path to allow imports from utils
sys.path.insert(0, str(Path(__file__).parent))

from utils.fdr_correction import apply_fdr_correction, write_output_with_disclaimer


def load_raw_gwas(input_path: str) -> pd.DataFrame:
    """
    Load raw GWAS results from PLINK output.

    Args:
        input_path: Path to the raw GWAS TSV file.

    Returns:
        DataFrame with raw GWAS statistics.
    """
    if not os.path.exists(input_path):
        raise FileNotFoundError(
            f"Raw GWAS results file not found: {input_path}. "
            "Ensure code/03_gwas.py (or equivalent) has been run successfully."
        )

    # PLINK --logistic output typically has columns: CHR, SNP, BP, A1, TEST, NMISS, BETA, SE, LRT, P, OR
    # We need at least: SNP, P
    df = pd.read_csv(input_path, sep='\t', comment='#')

    # Normalize column names (PLINK sometimes uses different casing)
    df.columns = df.columns.str.upper()

    required_cols = ['SNP', 'P']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(
            f"Missing required columns in {input_path}: {missing}. "
            f"Expected columns include: {required_cols}"
        )

    # Ensure P-values are numeric and formatted to 10 decimal places for FDR
    df['P'] = pd.to_numeric(df['P'], errors='coerce')
    df = df.dropna(subset=['P'])

    return df


def main():
    parser = argparse.ArgumentParser(
        description="Apply FDR correction to GWAS results and generate final output."
    )
    parser.add_argument(
        "--input",
        type=str,
        default="data/interim/gwas_raw.tsv",
        help="Path to raw GWAS results (default: data/interim/gwas_raw.tsv)"
    )
    parser.add_argument(
        "--output",
        type=str,
        default="data/processed/gwas_results_fdr.tsv",
        help="Path to output FDR-corrected results (default: data/processed/gwas_results_fdr.tsv)"
    )

    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    print(f"Loading raw GWAS results from: {input_path}")
    try:
        raw_df = load_raw_gwas(str(input_path))
        print(f"Loaded {len(raw_df)} SNPs.")
    except (FileNotFoundError, ValueError) as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)

    print("Applying Benjamini-Hochberg FDR correction...")
    # The FDR utility expects a DataFrame with a 'P' column
    fdr_df = apply_fdr_correction(raw_df)

    if fdr_df is None or fdr_df.empty:
        print("ERROR: FDR correction produced no results.", file=sys.stderr)
        sys.exit(1)

    print(f"Writing FDR-corrected results to: {output_path}")
    # Write the full dataframe with the disclaimer in the header or a separate file
    # per the spec, we write the TSV. The disclaimer is often in a sidecar or header.
    # The utility `write_output_with_disclaimer` handles the writing.
    write_output_with_disclaimer(fdr_df, str(output_path))

    # Log summary
    significant_count = fdr_df['significant'].sum() if 'significant' in fdr_df.columns else 0
    print(f"Analysis complete. {significant_count} SNPs pass FDR threshold (q < 0.05).")
    print(f"Output written to: {output_path}")


if __name__ == "__main__":
    main()