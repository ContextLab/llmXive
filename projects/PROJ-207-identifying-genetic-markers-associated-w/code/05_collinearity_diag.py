"""
Collinearity Diagnostics for GWAS Covariates (FR-010).

Implements FR-010: Calculate Variance Inflation Factors (VIF) and correlation
matrices for covariates (geographic region, sampling year, Varroa mite count)
to ensure model stability before regression.

Input: data/processed/phenotypes_cleaned.pheno (PLINK .pheno format)
Output: data/processed/collinearity_report.json
"""

import os
import sys
import argparse
import json
from pathlib import Path
import pandas as pd
import numpy as np

# Ensure the code directory is in the path for imports if running as script
# This handles cases where the script is run from the project root
code_dir = Path(__file__).parent
if str(code_dir) not in sys.path:
    sys.path.insert(0, str(code_dir))

from utils.collinearity_diag import calculate_vif, calculate_correlation_matrix, run_collinearity_diagnostics

def load_phenotype_data(pheno_path: Path) -> pd.DataFrame:
    """
    Load phenotype data from PLINK .pheno format.
    
    PLINK .pheno format:
    - First column: Family ID (FID)
    - Second column: Individual ID (IID)
    - Third column: Phenotype value (1=Control, 2=Case, -9=Missing)
    - Subsequent columns: Covariates
    
    Returns a DataFrame with covariates and phenotype.
    """
    if not pheno_path.exists():
        raise FileNotFoundError(f"Input file not found: {pheno_path}")
    
    # PLINK .pheno files are whitespace-delimited, no header
    df = pd.read_csv(pheno_path, delim_whitespace=True, header=None)
    
    # Rename columns for clarity
    # Assuming standard PLINK format: FID, IID, PHENO, [COV1, COV2, ...]
    # We need to identify which columns are covariates.
    # Based on T016 (preprocess_phenotype), covariates are added after PHENO.
    # Let's assume the structure matches what T016 produces.
    # If the file has a specific header or structure, adjust accordingly.
    # For now, we assume columns 3+ are covariates.
    
    # Check if the file has headers (unlikely for .pheno but possible if generated by custom script)
    # If it's a standard PLINK .pheno, it has no header.
    # Let's try to detect if the first row looks like a header (strings) or data (numbers/IDs)
    try:
        # Try reading as numeric to see if the first row is data
        first_row = df.iloc[0]
        # If FID/IID are strings, they won't parse as float, but that's fine.
        # We just need to know if the first row is a header.
        # Standard PLINK .pheno: FID IID PHENO [COV...]
        # If the first row contains "FID" or "IID", it's a header.
        if isinstance(first_row[0], str) and first_row[0].upper() in ['FID', 'ID', 'SAMPLE']:
            df.columns = ['FID', 'IID', 'PHENO'] + [f'COV_{i}' for i in range(len(df.columns)-3)]
        else:
            df.columns = ['FID', 'IID', 'PHENO'] + [f'COV_{i}' for i in range(len(df.columns)-3)]
    except Exception:
        # Fallback to default naming
        df.columns = ['FID', 'IID', 'PHENO'] + [f'COV_{i}' for i in range(len(df.columns)-3)]
    
    # Extract covariates (columns 3 onwards)
    covariates = df.iloc[:, 3:]
    
    # Convert to numeric, coercing errors to NaN
    covariates = covariates.apply(pd.to_numeric, errors='coerce')
    
    # Drop rows with all NaN covariates
    covariates = covariates.dropna(how='all')
    
    # Drop rows with any NaN in covariates (for VIF calculation)
    # Or impute? For diagnostics, we usually drop.
    covariates = covariates.dropna()
    
    if covariates.empty:
        raise ValueError("No valid covariate data found after cleaning.")
    
    return covariates

def main():
    parser = argparse.ArgumentParser(
        description="Perform collinearity diagnostics on GWAS covariates (FR-010)."
    )
    parser.add_argument(
        "--input",
        type=str,
        default="data/processed/phenotypes_cleaned.pheno",
        help="Path to the cleaned phenotype file (PLINK .pheno format)."
    )
    parser.add_argument(
        "--output",
        type=str,
        default="data/processed/collinearity_report.json",
        help="Path to the output JSON report."
    )
    
    args = parser.parse_args()
    
    input_path = Path(args.input)
    output_path = Path(args.output)
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    try:
        # Load data
        print(f"Loading phenotype data from {input_path}...")
        covariates = load_phenotype_data(input_path)
        
        print(f"Loaded {len(covariates)} samples with {len(covariates.columns)} covariates.")
        print(f"Covariates: {list(covariates.columns)}")
        
        # Run diagnostics
        print("Running collinearity diagnostics...")
        vif_results = calculate_vif(covariates)
        corr_matrix = calculate_correlation_matrix(covariates)
        
        # Prepare report
        report = {
            "status": "success",
            "input_file": str(input_path),
            "sample_count": len(covariates),
            "covariate_count": len(covariates.columns),
            "covariates": list(covariates.columns),
            "vif": vif_results,
            "correlation_matrix": corr_matrix,
            "max_vif": max(vif_results.values()) if vif_results else None,
            "threshold": 5.0,  # Standard VIF threshold
            "recommendation": "PASS" if max(vif_results.values()) < 5.0 else "WARNING: High collinearity detected"
        }
        
        # Write output
        with open(output_path, 'w') as f:
            json.dump(report, f, indent=2)
        
        print(f"Collinearity report written to {output_path}")
        print(f"Max VIF: {report['max_vif']:.2f}")
        print(f"Recommendation: {report['recommendation']}")
        
        # Exit with error if collinearity is too high (optional, but good for pipeline gating)
        if report['max_vif'] >= 10.0:
            print("ERROR: Severe collinearity detected (VIF >= 10). Pipeline halted.")
            sys.exit(1)
        
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        sys.exit(1)
    except ValueError as e:
        print(f"ERROR: {e}")
        sys.exit(1)
    except Exception as e:
        print(f"ERROR: Unexpected error during collinearity diagnostics: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()