"""
Collinearity Diagnostics for GWAS Covariates.

This script performs collinearity diagnostics (VIF and correlation matrix)
on the phenotype/covariate data to detect multicollinearity issues before
model fitting. It is invoked by the run-book (quickstart.md) as a
standalone step.

Input:
    data/processed/phenotypes_cleaned.pheno (or .fam if pheno not separate)
Output:
    data/processed/collinearity_report.tsv
    data/processed/model_config.yaml (updated if high collinearity found)
"""
import os
import sys
import argparse
import pandas as pd
import numpy as np
from pathlib import Path

# Ensure we can import from the utils directory
sys.path.insert(0, str(Path(__file__).parent / "utils"))
from collinearity_diag import calculate_vif, calculate_correlation_matrix, run_collinearity_diagnostics

def load_phenotype_data(pheno_path: Path):
    """Load phenotype data from PLINK .pheno file or .fam if combined."""
    if not pheno_path.exists():
        # Fallback to .fam if .pheno missing (common in PLINK workflows)
        fam_path = pheno_path.with_suffix('.fam')
        if fam_path.exists():
            # PLINK .fam: FID IID PID MID Sex Phenotype
            # We assume the phenotype is the last column, but we need covariates.
            # If .pheno is missing, we might need to extract from a separate source or error.
            # For this script, we expect a specific structure or a combined file.
            # Let's try to load a TSV/CSV if it exists with a known name, or error.
            # The task description implies we have a clean file from T016.
            raise FileNotFoundError(f"Phenotype file not found: {pheno_path} (or .fam)")
        
        # If .fam exists but .pheno doesn't, we might need to look for the specific
        # file generated by T016: data/processed/phenotypes_cleaned.pheno
        # If that is missing, we can't proceed.
        raise FileNotFoundError(f"Required phenotype file missing: {pheno_path}")
    
    # Load as whitespace-separated or tab-separated
    df = pd.read_csv(pheno_path, sep=r'\s+', header=None)
    # Assume standard PLINK .pheno format: FID IID Phenotype [Covariates...]
    # Or a custom header if T016 wrote headers.
    # T016 output: phenotypes_cleaned.pheno
    # Let's assume T016 writes a header or we infer columns.
    # If no header, we assume columns: FID, IID, Phenotype, Cov1, Cov2...
    # For safety, let's check if the first row looks like headers.
    try:
        # Try reading with header
        df = pd.read_csv(pheno_path, sep=r'\s+', comment='#')
    except Exception:
        # Fallback to no header
        df = pd.read_csv(pheno_path, sep=r'\s+', header=None, comment='#')
    
    return df

def main():
    parser = argparse.ArgumentParser(description="Run collinearity diagnostics on phenotype data.")
    parser.add_argument("--input", type=str, default="data/processed/phenotypes_cleaned.pheno",
                        help="Path to phenotype file (.pheno)")
    parser.add_argument("--output", type=str, default="data/processed/collinearity_report.tsv",
                        help="Path to output report TSV")
    parser.add_argument("--config", type=str, default="data/processed/model_config.yaml",
                        help="Path to model config YAML to update")
    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)
    config_path = Path(args.config)

    if not input_path.exists():
        print(f"Error: Input file not found: {input_path}")
        sys.exit(1)

    # Load data
    # We expect the file to have columns: FID, IID, Phenotype, Cov1, Cov2...
    # Or it might be a CSV with headers.
    # Let's try to load with headers first, assuming T016 wrote them.
    try:
        df = pd.read_csv(input_path, sep=r'\s+', comment='#')
    except Exception:
        df = pd.read_csv(input_path, sep=r'\s+', header=None, comment='#')
    
    # Identify covariate columns.
    # Assumption: The last few columns are covariates, or we have a known list.
    # From T016, we expect: geographic_region, sampling_year, Varroa_mite_count.
    # If headers exist, use them. If not, assume columns 3 onwards are covariates (after FID, IID, Phenotype).
    if df.shape[1] < 4:
        print("Error: Not enough columns in phenotype file to extract covariates.")
        sys.exit(1)

    if df.columns[0] in ['FID', 'IID', '#FID']:
        # Headers exist
        # Assume columns after Phenotype are covariates.
        # We need to know which column is Phenotype. Usually column 2 (0-indexed) or 3.
        # Let's assume standard: FID, IID, Phenotype, Cov1, Cov2...
        # If headers are present, we look for specific names or assume everything after 'Phenotype' is covariate.
        # For robustness, let's assume the user knows the structure or T016 wrote standard names.
        # If T016 wrote headers: FID, IID, Phenotype, geographic_region, sampling_year, Varroa_mite_count
        covariate_cols = [c for c in df.columns if c not in ['FID', 'IID', 'Phenotype', '#FID', '#IID']]
        if not covariate_cols:
            # Fallback: assume all columns after index 2 are covariates
            covariate_cols = df.columns[3:].tolist()
    else:
        # No headers: assume FID, IID, Phenotype, Cov1, Cov2...
        covariate_cols = df.columns[3:].tolist()

    if not covariate_cols:
        print("Error: Could not identify covariate columns.")
        sys.exit(1)

    # Convert to numeric, coerce errors to NaN
    df_numeric = df[covariate_cols].apply(pd.to_numeric, errors='coerce')
    df_numeric = df_numeric.dropna()

    if df_numeric.empty:
        print("Error: No valid numeric covariate data found after cleaning.")
        sys.exit(1)

    print(f"Running collinearity diagnostics on columns: {covariate_cols}")
    
    # Calculate VIF
    vif_data = calculate_vif(df_numeric)
    
    # Calculate Correlation Matrix
    corr_matrix = calculate_correlation_matrix(df_numeric)
    
    # Run full diagnostics
    diagnostics = run_collinearity_diagnostics(df_numeric)

    # Prepare report
    report = []
    high_vif_pairs = []
    
    for _, row in vif_data.iterrows():
        var = row['variable']
        vif_val = row['VIF']
        status = "High" if vif_val >= 5.0 else "Clear"
        report.append({
            'covariate': var,
            'vif': vif_val,
            'status': status
        })
        if vif_val >= 5.0:
            high_vif_pairs.append(var)

    # Identify pairs with high correlation
    high_corr_pairs = []
    for i in range(len(corr_matrix.columns)):
        for j in range(i + 1, len(corr_matrix.columns)):
            c1 = corr_matrix.columns[i]
            c2 = corr_matrix.columns[j]
            r = corr_matrix.iloc[i, j]
            if abs(r) > 0.8:
                high_corr_pairs.append({
                    'pair': f"{c1} vs {c2}",
                    'r_squared': r**2,
                    'correlation': r
                })

    # Write Report TSV
    report_df = pd.DataFrame(report)
    report_df.to_csv(output_path, sep='\t', index=False)
    print(f"Wrote collinearity report to {output_path}")

    # Update model_config.yaml if high collinearity found
    if high_vif_pairs or high_corr_pairs:
        import yaml
        config = {}
        if config_path.exists():
            with open(config_path, 'r') as f:
                config = yaml.safe_load(f) or {}
        
        config['collinearity_warning'] = "VIF >= 5 detected; covariates retained. Diagnostic report generated."
        config['collinearity_pairs'] = [p['pair'] for p in high_corr_pairs]
        
        with open(config_path, 'w') as f:
            yaml.dump(config, f, default_flow_style=False)
        
        print(f"Updated {config_path} with collinearity warnings.")

    print("Collinearity diagnostics complete.")

if __name__ == "__main__":
    main()