"""
Task T008c: Merge and Count Merged

Loads FAO and World Bank data (using chunked processing if necessary)
and performs the merge on `iso_code` and `year`. Counts the resulting
rows as `total_merged` and saves to `data/processed/counts_merged.json`.
"""
import json
import logging
import sys
from pathlib import Path
from typing import Dict, Any, Optional
import pandas as pd

# Add project root to path for imports
project_root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(project_root))

from data.clean import merge_datasets
from logging_config import get_logger

logger = get_logger(__name__)

# Configuration
FAO_DATA_PATH = Path("data/raw/fao_land_use.csv")
WB_DATA_PATH = Path("data/raw/wb_gdp_pop.csv") # Assuming this is the merged WB data path
CBNRM_PROXY_PATH = Path("data/raw/cbnrm_proxy.csv")
OUTPUT_PATH = Path("data/processed/counts_merged.json")
CHUNK_SIZE = 10000  # For chunked processing if needed

def load_data_chunked_or_full(file_path: Path, chunk_size: Optional[int] = None) -> pd.DataFrame:
    """
    Load a CSV file. If chunk_size is provided and file is large,
    process in chunks. Otherwise, load full file.
    """
    if not file_path.exists():
        logger.error(f"Data file not found: {file_path}")
        raise FileNotFoundError(f"Data file not found: {file_path}")
    
    try:
        if chunk_size and file_path.stat().st_size > 10 * 1024 * 1024: # If > 10MB
            logger.info(f"Loading {file_path} in chunks of {chunk_size}")
            chunks = []
            for chunk in pd.read_csv(file_path, chunksize=chunk_size):
                chunks.append(chunk)
            df = pd.concat(chunks, ignore_index=True)
        else:
            logger.info(f"Loading {file_path} fully")
            df = pd.read_csv(file_path)
        
        logger.info(f"Loaded {len(df)} rows from {file_path}")
        return df
    except Exception as e:
        logger.error(f"Failed to load {file_path}: {e}")
        raise

def merge_and_count(fao_df: pd.DataFrame, wb_df: pd.DataFrame) -> int:
    """
    Merge FAO and World Bank data on iso_code and year.
    Returns the count of merged rows.
    """
    logger.info("Merging datasets on 'iso_code' and 'year'...")
    
    # Ensure key columns exist and are standardized types
    required_cols = ['iso_code', 'year']
    for col in required_cols:
        if col not in fao_df.columns or col not in wb_df.columns:
            logger.error(f"Required column '{col}' missing in one of the datasets.")
            raise ValueError(f"Required column '{col}' missing in one of the datasets.")
    
    fao_df[col] = fao_df[col].astype(str)
    wb_df[col] = wb_df[col].astype(str)
    
    # Perform inner merge
    merged_df = pd.merge(fao_df, wb_df, on=['iso_code', 'year'], how='inner')
    
    total_merged = len(merged_df)
    logger.info(f"Merged dataset contains {total_merged} rows.")
    
    return total_merged, merged_df

def save_count(count: int, output_path: Path):
    """Save the merged count to a JSON file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    result = {
        "total_merged": count
    }
    with open(output_path, 'w') as f:
        json.dump(result, f, indent=2)
    logger.info(f"Saved merged count to {output_path}")

def main():
    logger.info("Starting T008c: Merge and Count Merged")
    
    try:
        # Load FAO data
        fao_df = load_data_chunked_or_full(FAO_DATA_PATH, CHUNK_SIZE)
        
        # Load World Bank data (GDP, Pop, and CBNRM proxy combined)
        # We assume T012 has produced a combined WB dataset or we need to load components.
        # Based on task T012: "load the specific CBNRM proxy data from the output file generated by T009"
        # and T013 merges everything.
        # For T008c, we need the pre-merged WB data (GDP/Pop + Proxy) to merge with FAO.
        # Let's assume the standard WB data path for GDP/Pop is wb_gdp_pop.csv
        # and we need to merge it with cbnrm_proxy.csv first if they are separate.
        # However, T012 says "Load GDP and Population Density data ... and load the specific CBNRM proxy data".
        # Let's assume there is a pre-processed WB file or we construct it.
        # To be safe and robust, we check for the existence of the expected combined WB file.
        # If not, we might need to merge GDP/Pop and Proxy ourselves here, but T013 usually does the final merge.
        # T008c is a counting task *before* full cleaning/classification (T013, T014).
        # It says "Load the FAO and World Bank data ... and perform the merge".
        # We will assume `data/raw/wb_gdp_pop.csv` contains the necessary WB variables (GDP, Pop)
        # and we need to ensure CBNRM proxy is also there or merge it.
        # Given T009 saves cbnrm_proxy.csv, and T012 loads GDP/Pop AND cbnrm_proxy.
        # Let's assume we need to merge wb_gdp_pop.csv and cbnrm_proxy.csv first to get the full WB side.
        
        wb_gdp_pop_path = Path("data/raw/wb_gdp_pop.csv")
        cbnrm_proxy_path = Path("data/raw/cbnrm_proxy.csv")
        
        if wb_gdp_pop_path.exists() and cbnrm_proxy_path.exists():
            logger.info("Merging WB GDP/Pop and CBNRM proxy first...")
            wb_gdp_pop = load_data_chunked_or_full(wb_gdp_pop_path, CHUNK_SIZE)
            cbnrm_proxy = load_data_chunked_or_full(cbnrm_proxy_path, CHUNK_SIZE)
            
            # Merge on iso_code and year
            wb_full = pd.merge(wb_gdp_pop, cbnrm_proxy, on=['iso_code', 'year'], how='inner')
            logger.info(f"Combined WB dataset has {len(wb_full)} rows")
            wb_df = wb_full
        elif wb_gdp_pop_path.exists():
            # Maybe cbnrm is already included? Or we proceed with just GDP/Pop if proxy is missing (though task says load proxy)
            # If proxy is missing, we can't do the full merge as expected.
            logger.warning("CBNRM proxy file missing. Attempting to proceed with GDP/Pop only, but this may be incomplete.")
            wb_df = load_data_chunked_or_full(wb_gdp_pop_path, CHUNK_SIZE)
        else:
            logger.error("World Bank data file (wb_gdp_pop.csv) not found.")
            raise FileNotFoundError("World Bank data file not found.")

        # Now merge FAO and the combined WB data
        total_merged, merged_df = merge_and_count(fao_df, wb_df)
        
        # Save result
        save_count(total_merged, OUTPUT_PATH)
        
        logger.info("T008c completed successfully.")
        
    except Exception as e:
        logger.error(f"Failed to complete T008c: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
