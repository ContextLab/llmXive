def merge_datasets(fao_df: pd.DataFrame, wb_df: pd.DataFrame, regime_df: pd.DataFrame) -> pd.DataFrame:
    """Merge FAO, WB, and Regime data on country_code and year."""
    logger.info("Merging datasets")
    
    # Standardize keys first
    fao_df = standardize_iso_code(fao_df)
    wb_df = standardize_iso_code(wb_df)
    regime_df = standardize_iso_code(regime_df)
    
    fao_df = standardize_year(fao_df)
    wb_df = standardize_year(wb_df)
    regime_df = standardize_year(regime_df)
    
    # Merge FAO and WB
    # Assume FAO has 'land_use_change_rate', WB has 'gdp_per_capita', 'population_density'
    # Merge on country_code, year
    merged = pd.merge(fao_df, wb_df, on=['country_code', 'year'], how='inner')
    
    # Merge with regime data
    merged = pd.merge(merged, regime_df, on=['country_code', 'year'], how='inner')
    
    logger.info(f"Merged dataset shape: {merged.shape}")
    return merged

