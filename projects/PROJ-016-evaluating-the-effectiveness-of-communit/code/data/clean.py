def apply_country_level_exclusion(df: pd.DataFrame) -> pd.DataFrame:
    """Apply country-level exclusion for Primary Variables if >20% missing."""
    logger.info("Applying country-level exclusion for primary variables")
    primary_vars = ['land_use_change_rate', 'regime_type']
    vars_present = [v for v in primary_vars if v in df.columns]
    
    if not vars_present:
        logger.warning("No primary variables found for country-level exclusion.")
        return df
    
    excluded_countries = []
    for var in vars_present:
        # Calculate missing percentage per country
        country_missing = df.groupby('country_code')[var].apply(lambda x: x.isna().sum() / len(x))
        to_exclude = country_missing[country_missing > 0.20].index.tolist()
        if to_exclude:
            logger.warning(f"Primary Variable '{var}': Excluding countries due to >20% missing: {to_exclude}")
            excluded_countries.extend(to_exclude)
    
    if excluded_countries:
        excluded_countries = list(set(excluded_countries))
        initial_count = len(df)
        df = df[~df['country_code'].isin(excluded_countries)]
        logger.info(f"Excluded {len(excluded_countries)} countries. New shape: {df.shape}")
    
    return df

def clean_and_merge_data() -> pd.DataFrame:
    """Orchestrate the cleaning and merging process."""
    logger.info("Starting clean_and_merge_data pipeline")
    
    fao_df = load_fao_data()
    wb_df = load_world_bank_data()
    regime_df = load_regime_data()
    
    merged = merge_datasets(fao_df, wb_df, regime_df)
    cleaned = drop_missing_primary_vars(merged)
    cleaned = apply_fr007_exclusion(cleaned)
    cleaned = apply_country_level_exclusion(cleaned)
    
    return cleaned

def calculate_coverage_rate() -> Dict[str, Any]:
    """
    Calculate coverage rate: total_merged / min(total_fao_available, total_wb_available).
    Loads raw counts from T011/T012 outputs and merged count from T013.
    Saves to data/processed/metrics.json.
    """
    logger.info("Calculating coverage rate (T015)")
    config = get_config()
    processed_dir = Path(config['DATA_PROCESSED_DIR'])
    
    # Load raw counts
    # T011 saves raw FAO to data/raw/fao_land_use.csv. We need the row count.
    # T012 saves raw WB to data/raw/wb_gdp_pop.csv.
    # We can count rows from the raw files directly if count files don't exist, 
    # or load the count JSONs if T008a/b were fixed.
    # Since T008a/b are marked as failed/rejected in the prompt, we must compute the count from the raw CSVs.
    
    fao_raw_path = Path(config['DATA_RAW_DIR']) / 'fao_land_use.csv'
    wb_raw_path = Path(config['DATA_RAW_DIR']) / 'wb_gdp_pop.csv'
    merged_raw_path = Path(config['DATA_PROCESSED_DIR']) / 'merged_panel.csv'
    
    if not fao_raw_path.exists():
        raise FileNotFoundError(f"FAO raw data missing: {fao_raw_path}. Run T011.")
    if not wb_raw_path.exists():
        raise FileNotFoundError(f"WB raw data missing: {wb_raw_path}. Run T012.")
    if not merged_raw_path.exists():
        raise FileNotFoundError(f"Merged panel missing: {merged_raw_path}. Run T013.")
    
    # Count rows (excluding header)
    # Using len(pd.read_csv) is safe for these sizes
    fao_count = len(pd.read_csv(fao_raw_path))
    wb_count = len(pd.read_csv(wb_raw_path))
    merged_count = len(pd.read_csv(merged_raw_path))
    
    logger.info(f"Raw counts - FAO: {fao_count}, WB: {wb_count}, Merged: {merged_count}")
    
    # Calculate min available
    min_available = min(fao_count, wb_count)
    
    if min_available == 0:
        coverage_rate = 0.0
    else:
        coverage_rate = merged_count / min_available
    
    metrics = {
        "total_fao_available": fao_count,
        "total_wb_available": wb_count,
        "total_merged": merged_count,
        "min_available": min_available,
        "coverage_rate": coverage_rate
    }
    
    # Save to metrics.json
    metrics_path = processed_dir / 'metrics.json'
    with open(metrics_path, 'w') as f:
        json.dump(metrics, f, indent=2)
    
    logger.info(f"Coverage rate calculated: {coverage_rate:.4f}. Saved to {metrics_path}")
    return metrics

