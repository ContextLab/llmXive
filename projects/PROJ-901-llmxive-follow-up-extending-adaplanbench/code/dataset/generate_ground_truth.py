"""
Generate ground truth file for human annotation.

This script reads the stratified annotation sample (generated by T033)
and prepares a CSV file with placeholder columns for human annotators to fill.

Output: data/processed/annotation_labels.csv
Columns: task_id, raw_prompt, constraint_list, constraint_count, is_violation, is_implicit
"""

import argparse
import csv
import os
import sys
from pathlib import Path

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent))

from config import Paths

def main():
    parser = argparse.ArgumentParser(
        description="Generate ground truth file for human annotation."
    )
    parser.add_argument(
        "--input",
        type=str,
        default=str(Paths.DATA_PROCESSED / "annotation_sample.csv"),
        help="Path to the input annotation sample CSV (default: data/processed/annotation_sample.csv)",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=str(Paths.DATA_PROCESSED / "annotation_labels.csv"),
        help="Path to the output annotation labels CSV (default: data/processed/annotation_labels.csv)",
    )
    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)

    # Ensure input file exists
    if not input_path.exists():
        print(f"Error: Input file not found: {input_path}")
        print("Please run the annotator script (T033) first to generate the annotation sample.")
        sys.exit(1)

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    print(f"Reading annotation sample from: {input_path}")
    print(f"Generating ground truth file at: {output_path}")

    # Read the input CSV
    rows = []
    with open(input_path, "r", newline="", encoding="utf-8") as infile:
        reader = csv.DictReader(infile)
        fieldnames = reader.fieldnames
        if not fieldnames:
            print("Error: Input CSV is empty or has no headers.")
            sys.exit(1)

        for row in reader:
            rows.append(row)

    if not rows:
        print("Warning: Input CSV has no data rows. Generating empty output file.")

    # Define output fieldnames
    # We preserve the original columns and add the placeholder columns
    output_fieldnames = list(fieldnames) + ["is_violation", "is_implicit"]

    # Write the output CSV
    with open(output_path, "w", newline="", encoding="utf-8") as outfile:
        writer = csv.DictWriter(outfile, fieldnames=output_fieldnames)
        writer.writeheader()

        for row in rows:
            # Create a new row with placeholder values for annotation
            new_row = {key: row.get(key, "") for key in fieldnames}
            new_row["is_violation"] = ""  # Placeholder for human annotation
            new_row["is_implicit"] = ""   # Placeholder for human annotation
            writer.writerow(new_row)

    print(f"Successfully generated {output_path}")
    print(f"  - Total rows: {len(rows)}")
    print(f"  - Columns: {', '.join(output_fieldnames)}")
    print("  - Placeholder columns 'is_violation' and 'is_implicit' are empty and ready for annotation.")

if __name__ == "__main__":
    main()
