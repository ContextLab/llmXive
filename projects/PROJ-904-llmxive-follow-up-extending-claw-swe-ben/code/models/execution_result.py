"""
ExecutionResult data model for storing LLM experiment outcomes.

This module defines the ExecutionResult dataclass and associated enums
used to capture the results of model inference runs across different
context strategies and model sizes.
"""
from dataclasses import dataclass, field
from typing import Dict, Any, List, Optional
from enum import Enum
import hashlib
import json
from datetime import datetime

from models.context_config import StrategyType


class ExecutionStatus(Enum):
    """Status of an execution attempt."""
    SUCCESS = "success"
    TIMEOUT = "timeout"
    ERROR = "error"
    SKIPPED = "skipped"
    PARTIAL = "partial"


class FailureCategory(Enum):
    """Categorized failure modes for analysis."""
    MISSING_CONTEXT = "missing_context"
    REASONING_ERROR = "reasoning_error"
    SYNTAX_ERROR = "syntax_error"
    TIMEOUT = "timeout"
    RESOURCE_EXHAUSTION = "resource_exhaustion"
    UNKNOWN = "unknown"


@dataclass
class ExecutionResult:
    """
    Represents the result of a single model execution on a task instance.

    Attributes:
        instance_id: Unique identifier for the task instance.
        model_id: Identifier of the model used (e.g., "llama-3-1b", "llama-3-7b").
        strategy: The context strategy applied (e.g., baseline, tfidf, diff_aware).
        status: Execution status (success, timeout, error, etc.).
        pass_label: Boolean indicating if the generated solution was correct (Pass@1).
        generated_text: The raw text generated by the model.
        log_output: Full log output from the execution environment.
        error_message: Error message if execution failed.
        execution_time_ms: Time taken for execution in milliseconds.
        context_tokens: Number of tokens in the processed context.
        generated_tokens: Number of tokens in the generated output.
        metadata: Additional arbitrary metadata for analysis.
        created_at: Timestamp of result creation.
    """
    instance_id: str
    model_id: str
    strategy: StrategyType
    status: ExecutionStatus
    pass_label: Optional[bool] = None
    generated_text: Optional[str] = None
    log_output: Optional[str] = None
    error_message: Optional[str] = None
    execution_time_ms: Optional[float] = None
    context_tokens: Optional[int] = None
    generated_tokens: Optional[int] = None
    failure_category: Optional[FailureCategory] = None
    metadata: Dict[str, Any] = field(default_factory=dict)
    created_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())

    def to_dict(self) -> Dict[str, Any]:
        """Convert the result to a dictionary for JSON serialization."""
        return {
            "instance_id": self.instance_id,
            "model_id": self.model_id,
            "strategy": self.strategy.value,
            "status": self.status.value,
            "pass_label": self.pass_label,
            "generated_text": self.generated_text,
            "log_output": self.log_output,
            "error_message": self.error_message,
            "execution_time_ms": self.execution_time_ms,
            "context_tokens": self.context_tokens,
            "generated_tokens": self.generated_tokens,
            "failure_category": self.failure_category.value if self.failure_category else None,
            "metadata": self.metadata,
            "created_at": self.created_at,
        }

    def to_json(self, indent: Optional[int] = None) -> str:
        """Serialize the result to a JSON string."""
        return json.dumps(self.to_dict(), indent=indent)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "ExecutionResult":
        """Create an ExecutionResult from a dictionary."""
        # Handle enum conversions
        strategy = StrategyType(data["strategy"]) if isinstance(data["strategy"], str) else data["strategy"]
        status = ExecutionStatus(data["status"]) if isinstance(data["status"], str) else data["status"]
        
        failure_cat = data.get("failure_category")
        if isinstance(failure_cat, str):
            failure_cat = FailureCategory(failure_cat)
        
        return cls(
            instance_id=data["instance_id"],
            model_id=data["model_id"],
            strategy=strategy,
            status=status,
            pass_label=data.get("pass_label"),
            generated_text=data.get("generated_text"),
            log_output=data.get("log_output"),
            error_message=data.get("error_message"),
            execution_time_ms=data.get("execution_time_ms"),
            context_tokens=data.get("context_tokens"),
            generated_tokens=data.get("generated_tokens"),
            failure_category=failure_cat,
            metadata=data.get("metadata", {}),
            created_at=data.get("created_at", datetime.utcnow().isoformat()),
        )

    def calculate_checksum(self) -> str:
        """Calculate a checksum of the core result fields for integrity verification."""
        core_data = {
            "instance_id": self.instance_id,
            "model_id": self.model_id,
            "strategy": self.strategy.value,
            "status": self.status.value,
            "pass_label": self.pass_label,
        }
        content = json.dumps(core_data, sort_keys=True)
        return hashlib.sha256(content.encode("utf-8")).hexdigest()
