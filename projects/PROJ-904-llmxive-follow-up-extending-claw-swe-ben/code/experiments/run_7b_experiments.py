# Model configuration for 7B
MODEL_NAME_7B = "Qwen/Qwen2.5-7B-Instruct-GGUF" 
MODEL_QUANT_7B = "q4_k_m"
MAX_CONTEXT_TOKENS = 8192
MAX_RUNTIME_PER_INSTANCE = 3600  # 60 minutes
TOTAL_WALL_CLOCK_BUDGET = 72 * 3600  # 72 hours

logger = setup_logger("run_7b_experiments", level=logging.INFO)

def load_filtered_instances() -> List[Dict[str, Any]]:
    """Load the filtered dataset generated by T012c."""
    if not FILTERED_DATA_PATH.exists():
        raise FileNotFoundError(
            f"Filtered dataset not found at {FILTERED_DATA_PATH}. "
            "Please run T012c (loader.py) first to generate data/filtered_swe_bench_v1.parquet."
        )
    
    try:
        import pandas as pd
        df = pd.read_parquet(FILTERED_DATA_PATH)
        # Convert to list of dicts
        instances = df.to_dict('records')
        logger.info(f"Loaded {len(instances)} filtered instances from {FILTERED_DATA_PATH}")
        return instances
    except Exception as e:
        log_error(e, "Failed to load filtered instances")
        raise

def get_strategy_function(strategy_name: str):
    """Map strategy name to retrieval function."""
    strategy_map = {
        "baseline": lambda ctx_cfg, instance: process_context(instance, strategy_name, ctx_cfg),
        "tfidf": lambda ctx_cfg, instance: process_context(instance, strategy_name, ctx_cfg),
        "diff_aware": lambda ctx_cfg, instance: process_context(instance, strategy_name, ctx_cfg),
        "summarization": lambda ctx_cfg, instance: process_context(instance, strategy_name, ctx_cfg),
    }
    if strategy_name not in strategy_map:
        raise ValueError(f"Unknown strategy: {strategy_name}")
    return strategy_map[strategy_name]

def process_instance(instance: Dict[str, Any], strategy: str, runner: ModelRunner) -> Optional[ExecutionResult]:
    """
    Process a single instance with the 7B model and a specific strategy.
    
    Returns ExecutionResult or None if timeout/failure.
    """
    start_time = time.time()
    instance_id = instance.get("instance_id", "unknown")
    
    try:
        # 1. Prepare Context Configuration
        ctx_cfg = {
            "strategy": strategy,
            "max_tokens": MAX_CONTEXT_TOKENS,
            "issue_description": instance.get("issue_description", ""),
            "file_contents": instance.get("file_contents", {}),
            "repo_name": instance.get("repo_name", ""),
            "version": instance.get("version", ""),
        }
        
        # 2. Retrieve Context based on strategy
        # The process_context function handles the specific retrieval logic
        processed_context = process_context(instance, strategy, ctx_cfg)
        
        if not processed_context or not processed_context.context_text:
            # Fallback if retrieval failed
            logger.warning(f"Instance {instance_id}: Context retrieval empty, using fallback.")
            processed_context = fallback_strategy(instance, ctx_cfg)
            
        if not processed_context or not processed_context.context_text:
            raise RuntimeError(f"Instance {instance_id}: Could not generate context for strategy {strategy}")

        # 3. Prepare Prompt
        # Construct a standard SWE-bench prompt
        prompt = f"""You are an expert software engineer. Solve the following issue in the repository context.
        
        Issue: {instance.get('issue_description', 'No description provided')}
        
        Repository Context:
        {processed_context.context_text}
        
        Provide the solution as a unified diff patch. Start with '---' and '+++'."""

        # 4. Execute Model
        # Enforce per-instance timeout
        execution_start = time.time()
        result = runner.generate(
            prompt=prompt,
            max_tokens=512, # Reasonable limit for a patch
            temperature=0.0 # Deterministic for baseline comparison
        )
        execution_duration = time.time() - execution_start

        if execution_duration > MAX_RUNTIME_PER_INSTANCE:
            raise TimeoutError(f"Instance {instance_id} exceeded {MAX_RUNTIME_PER_INSTANCE}s budget")

        # 5. Construct Result
        result_obj = ExecutionResult(
            instance_id=instance_id,
            model_size="7B",
            strategy=strategy,
            status=ExecutionStatus.SUCCESS if result.success else ExecutionStatus.FAILURE,
            prediction=result.text if result.text else "",
            execution_time=execution_duration,
            context_tokens=processed_context.token_count,
            timestamp=datetime.now().isoformat(),
            metadata={
                "quantization": "Q4_K_M",
                "device": "cpu",
                "prompt_length": len(prompt),
                "error": result.error_message if not result.success else None
            }
        )
        
        return result_obj

    except TimeoutError as te:
        log_error(te, f"Timeout on instance {instance_id}")
        return ExecutionResult(
            instance_id=instance_id,
            model_size="7B",
            strategy=strategy,
            status=ExecutionStatus.TIMEOUT,
            prediction="",
            execution_time=time.time() - start_time,
            context_tokens=0,
            timestamp=datetime.now().isoformat(),
            metadata={"error": str(te)}
        )
    except Exception as e:
        log_error(e, f"Failed to process instance {instance_id}")
        return ExecutionResult(
            instance_id=instance_id,
            model_size="7B",
            strategy=strategy,
            status=ExecutionStatus.ERROR,
            prediction="",
            execution_time=time.time() - start_time,
            context_tokens=0,
            timestamp=datetime.now().isoformat(),
            metadata={"error": str(e)}
        )

def run_strategy(instances: List[Dict[str, Any]], strategy: str, runner: ModelRunner) -> List[ExecutionResult]:
    """Run a specific strategy against all instances."""
    logger.info(f"Starting 7B model execution for strategy: {strategy}")
    results = []
    
    # Initialize BatchExecutor for parallel processing (if configured)
    # For CPU-only 7B, parallelism is limited by RAM. 
    # We use a simple sequential loop with timeout guard for stability on constrained hardware.
    enforcer = GlobalTimeBudgetEnforcer(max_duration=TOTAL_WALL_CLOCK_BUDGET)
    
    for i, instance in enumerate(instances):
        if enforcer.is_expired():
            logger.warning(f"Global time budget exceeded at instance {i}. Stopping.")
            break
        
        logger.info(f"Processing instance {i+1}/{len(instances)}: {instance.get('instance_id')} [{strategy}]")
        result = process_instance(instance, strategy, runner)
        if result:
            results.append(result)
            enforcer.record_instance(result.execution_time)
            
    logger.info(f"Completed strategy {strategy}. Total results: {len(results)}")
    return results

def save_results(results: List[ExecutionResult], output_path: Path):
    """Save results to JSONL."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        for r in results:
            # Convert dataclass to dict
            r_dict = {
                "instance_id": r.instance_id,
                "model_size": r.model_size,
                "strategy": r.strategy,
                "status": r.status.value,
                "prediction": r.prediction,
                "execution_time": r.execution_time,
                "context_tokens": r.context_tokens,
                "timestamp": r.timestamp,
                "metadata": r.metadata
            }
            f.write(json.dumps(r_dict) + '\n')
    
    logger.info(f"Results saved to {output_path}")

def main():
    """Main entry point for T027."""
    parser = argparse.ArgumentParser(description="Run 7B model experiments (T027)")
    parser.add_argument("--strategy", type=str, default="all", 
                        choices=["baseline", "tfidf", "diff_aware", "summarization", "all"],
                        help="Strategy to run. Default: all")
    parser.add_argument("--max-instances", type=int, default=None,
                        help="Limit number of instances to process (for testing)")
    parser.add_argument("--seed", type=int, default=42, help="Random seed")
    args = parser.parse_args()

    # Setup
    set_global_seeds(args.seed)
    random.seed(args.seed)
    
    # Determine strategies
    strategies = ["baseline", "tfidf", "diff_aware", "summarization"] if args.strategy == "all" else [args.strategy]
    
    # Load Model
    logger.info(f"Loading 7B model with Q4_K_M quantization on CPU...")
    try:
        # Ensure HF_TOKEN is available
        hf_token = get_env_var("HF_TOKEN")
        model_path = get_model_path(MODEL_NAME_7B, quantization=MODEL_QUANT_7B)
        
        runner = ModelRunner(
            model_id=model_path,
            device="cpu",
            quantization="q4_k_m",
            hf_token=hf_token,
            max_memory_limit_gb=7.0 # FR-007 constraint
        )
        runner.load()
        logger.info("Model loaded successfully.")
    except Exception as e:
        log_error(e, "Failed to load 7B model")
        raise

    # Load Data
    try:
        instances = load_filtered_instances()
        if args.max_instances:
            instances = instances[:args.max_instances]
            logger.info(f"Limiting to {args.max_instances} instances.")
    except Exception as e:
        log_error(e, "Failed to load data")
        raise

    # Run Experiments
    all_results = []
    for strategy in strategies:
        results = run_strategy(instances, strategy, runner)
        all_results.extend(results)
        
        # Save intermediate results per strategy to avoid losing progress
        interim_path = OUTPUT_DIR / f"hf_run_7b_{strategy}.jsonl"
        save_results(results, interim_path)

    # Final Save
    save_results(all_results, OUTPUT_FILE)
    
    logger.info(f"T027 Complete. Output: {OUTPUT_FILE}")

if __name__ == "__main__":
    main()