"""
Validation script for baseline results (T016).

Ensures that `baseline_results.csv` contains predicted formation energies
and metrics (MAE, RMSE) even if the error exceeds 0.1 eV/atom.

This script reads the results generated by `evaluate.py`, validates the
required columns exist, checks for data integrity, and logs a warning if
the error metrics are high (> 0.1 eV/atom) but ensures the file is
preserved and valid regardless of performance.
"""
import os
import sys
import logging
import pandas as pd
from pathlib import Path

# Add project root to path for imports
sys.path.insert(0, str(Path(__file__).parent))

from config import PROJECT_ROOT, OUTPUTS_DIR
from utils.logging import setup_logger

# Constants
RESULTS_FILE = OUTPUTS_DIR / "baseline_results.csv"
ERROR_THRESHOLD = 0.1  # eV/atom

def validate_results_file(filepath: Path) -> dict:
    """
    Validates the existence and content of the baseline results CSV.
    
    Args:
        filepath: Path to the baseline_results.csv file.
        
    Returns:
        dict: Validation status and details.
    """
    status = {
        "exists": False,
        "valid": False,
        "message": "",
        "high_error_warning": False
    }

    if not filepath.exists():
        status["message"] = f"File not found: {filepath}"
        return status

    status["exists"] = True

    try:
        df = pd.read_csv(filepath)
    except Exception as e:
        status["message"] = f"Failed to read CSV: {str(e)}"
        return status

    # Required columns
    required_cols = ["material_id", "true_energy", "predicted_energy", "mae", "rmse"]
    missing_cols = [col for col in required_cols if col not in df.columns]

    if missing_cols:
        status["message"] = f"Missing required columns: {missing_cols}"
        return status

    # Check for empty dataframe
    if df.empty:
        status["message"] = "DataFrame is empty."
        return status

    # Check for NaN values in critical columns
    critical_cols = ["true_energy", "predicted_energy", "mae", "rmse"]
    if df[critical_cols].isnull().any().any():
        status["message"] = "Critical columns contain NaN values."
        return status

    # Calculate overall MAE/RMSE from the file if not aggregated
    # The file might contain per-material metrics or aggregated ones.
    # We assume it contains per-material predictions and global metrics might be in the last row or separate.
    # For T016, we ensure the file exists and has the columns.
    
    # Check if error > 0.1 eV/atom (using the mean MAE from the file if it's a summary, 
    # or the mean of the 'mae' column if it's per-sample, though usually 'mae' is a scalar metric).
    # Assuming 'mae' and 'rmse' columns in the CSV represent the global metric repeated or the file has a summary row.
    # If the file has per-sample errors, we calculate the mean.
    
    # Strategy: If 'mae' column has 1 unique value (summary) or multiple (per sample), handle accordingly.
    # Usually evaluate.py outputs a summary row or a file with predictions and a separate summary.
    # Let's assume the file contains predictions and we calculate the actual MAE to verify.
    
    df["error"] = (df["true_energy"] - df["predicted_energy"]).abs()
    calculated_mae = df["error"].mean()
    
    status["calculated_mae"] = calculated_mae
    
    if calculated_mae > ERROR_THRESHOLD:
        status["high_error_warning"] = True
        status["message"] = (
            f"Validation passed. File exists with required columns. "
            f"WARNING: Calculated MAE ({calculated_mae:.4f} eV/atom) exceeds threshold ({ERROR_THRESHOLD} eV/atom). "
            f"Results are preserved as required."
        )
    else:
        status["message"] = f"Validation passed. MAE ({calculated_mae:.4f} eV/atom) is within acceptable range."

    status["valid"] = True
    return status

def main():
    """Main entry point for validation."""
    logger = setup_logger("validate_baseline")
    
    logger.info(f"Validating baseline results at: {RESULTS_FILE}")
    
    if not RESULTS_FILE.exists():
        logger.error(f"Results file not found: {RESULTS_FILE}")
        logger.error("T016 Validation FAILED: Output file missing.")
        sys.exit(1)
    
    validation_result = validate_results_file(RESULTS_FILE)
    
    if not validation_result["valid"]:
        logger.error(f"Validation failed: {validation_result['message']}")
        logger.error("T016 Validation FAILED.")
        sys.exit(1)
    
    if validation_result["high_error_warning"]:
        logger.warning(validation_result["message"])
    else:
        logger.info(validation_result["message"])
    
    logger.info("T016 Validation PASSED: baseline_results.csv contains required data regardless of error magnitude.")
    return 0

if __name__ == "__main__":
    sys.exit(main())
