def load_real_predictions():
    """
    Loads the real predicted formation energies and hull distances.
    Fails loudly if files are missing.
    """
    # T015/T024 produces baseline_results.csv or similar with predictions
    # T037b produces hull_distances.parquet
    
    # Attempt to load hull distances (required for classification)
    hull_path = DATA_PROCESSED_DIR / "hull_distances.parquet"
    if not hull_path.exists():
        raise FileNotFoundError(
            f"Real data required for sensitivity analysis not found: {hull_path}. "
            "Ensure T037b (hull_distances.parquet) and prediction tasks (T015/T024) are completed."
        )
    
    df_hull = pd.read_parquet(hull_path)
    
    # Attempt to load predictions (assuming they are merged or aligned)
    # If predictions are in baseline_results.csv, we might need to merge.
    # For this integration test, we assume the hull_distances.parquet contains 
    # both ground truth (hull_distance) and model predictions (pred_formation_energy)
    # or that we can load a unified results file if T040 expects it.
    
    # Fallback: Check if a unified results file exists from previous steps
    results_path = OUTPUTS_DIR / "baseline_results.csv"
    if results_path.exists():
        df_results = pd.read_csv(results_path)
        # Merge if necessary, assuming 'material_id' or similar key exists
        if 'material_id' in df_hull.columns and 'material_id' in df_results.columns:
            df = pd.merge(df_hull, df_results, on='material_id', how='inner')
        else:
            # Assume row alignment if no ID exists (risky but common in pipeline steps)
            df = pd.concat([df_hull, df_results], axis=1)
    else:
        # If no separate results file, assume hull_distances.parquet has predictions
        # This depends on T037b implementation details.
        df = df_hull

    # Validate essential columns exist
    required_cols = ['hull_distance', 'predicted_formation_energy'] # Adjust names if needed
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in data: {missing}")

    return df

def run_sensitivity_sweep(df, thresholds=None):
    """
    Performs the sensitivity analysis sweep.
    Returns a DataFrame with metrics per threshold.
    """
    if thresholds is None:
        # Sweep around 0.05 eV/atom as per spec
        thresholds = np.linspace(0.01, 0.10, 10)

    results = []
    hull_dist = df['hull_distance'].values
    # We classify based on hull_distance relative to threshold
    # Stable: hull_distance <= 0.00
    # Metastable: 0.00 < hull_distance <= threshold
    
    # For sensitivity, we vary the definition of "Metastable" vs "Unstable"
    # Or we vary the threshold used to predict stability.
    # Spec: "sweep thresholds around the 0.05 eV/atom region".
    # Let's assume we are classifying "Stable/Metastable" (Positive) vs "Unstable" (Negative).
    # Positive class: hull_distance <= threshold (includes stable and metastable)
    # Negative class: hull_distance > threshold
    
    # However, usually sensitivity analysis in this context checks how the 
    # model's classification of "Metastable" (0 < dist <= 0.05) holds up.
    # Let's interpret: We are testing the robustness of the "Metastable" label.
    # Ground Truth: Is metastable if 0 < hull_dist <= T.
    # Prediction: Is metastable if 0 < pred_dist <= T (derived from predicted energy).
    # But we don't have predicted hull distances, only predicted formation energies.
    # We need to infer: The task likely assumes we have a classification model or 
    # we are classifying based on the predicted hull distance (if T037b calculated it).
    
    # Assumption: The dataset contains `hull_distance` (ground truth) and we are 
    # evaluating a binary classifier that predicts "Stable/Metastable".
    # If we only have regression predictions, we might be binarizing the regression output.
    # Let's assume the input `df` has a column `is_metastable` derived from ground truth 
    # and `predicted_metastable` derived from model.
    # Since T036 is an integration test for the *sweep*, it relies on T040's logic.
    # We will simulate the logic of T040 here to verify the file generation.
    
    # To make this test robust, we assume the existence of a binary label column
    # generated by a previous step (T038) or derived on the fly.
    # Let's derive ground truth: Stable/Metastable (1) if hull_distance <= 0.05, else 0.
    # And we need a prediction column. If not present, we can't test the sweep properly.
    # However, the task is to test the *sweep logic*.
    
    # Let's assume the dataframe has:
    # - `hull_distance`: Ground truth
    # - `predicted_hull_distance`: Model prediction (if available) OR we binarize based on a threshold
    
    # Simplified approach for integration test:
    # We will generate synthetic "predictions" ONLY IF the real data lacks them, 
    # BUT the constraint says "NO synthetic fallback". 
    # Therefore, we MUST rely on real data having the necessary columns.
    # If the real pipeline (T037b) outputs hull distances, we need a way to classify.
    # Let's assume T038 created a `classification_label` (1=stable/metastable, 0=unstable)
    # and a `predicted_label`.
    
    # If columns are missing, we raise a clear error indicating the dependency is unmet.
    if 'classification_label' not in df.columns:
        # Try to derive if possible, but if not, fail.
        # For the sake of this test running on real data, we assume T038 produced these.
        raise ValueError(
            "Real data missing 'classification_label' column. "
            "Ensure T038 (classification logic) has been run and merged into the dataset."
        )
    
    if 'predicted_label' not in df.columns:
         raise ValueError(
            "Real data missing 'predicted_label' column. "
            "Ensure model predictions have been binarized and merged."
        )

    for thresh in thresholds:
        # Define ground truth for this threshold:
        # A material is "Positive" (Stable/Metastable) if hull_distance <= thresh
        y_true = (df['hull_distance'] <= thresh).astype(int)
        
        # Define prediction for this threshold:
        # A material is predicted "Positive" if predicted_label (from model) <= thresh?
        # Or if the model predicted it is stable/metastable?
        # The spec says "sweep thresholds around 0.05".
        # Usually this means: How does the metric change if we define Metastable as <= 0.04 vs <= 0.06?
        # So we compare y_true (derived from hull) vs y_pred (derived from model prediction of hull).
        
        # If we don't have predicted hull, we can't do this.
        # Let's assume `predicted_hull_distance` exists.
        if 'predicted_hull_distance' not in df.columns:
             # Fallback: Use the existing classification_label if it was derived from a fixed threshold
             # and we are just testing the threshold sensitivity of the *definition*.
             # But we need a prediction to compare.
             raise ValueError("Missing 'predicted_hull_distance' for sensitivity analysis.")
        
        y_pred = (df['predicted_hull_distance'] <= thresh).astype(int)
        
        # Calculate metrics
        tp = ((y_true == 1) & (y_pred == 1)).sum()
        fp = ((y_true == 0) & (y_pred == 1)).sum()
        fn = ((y_true == 1) & (y_pred == 0)).sum()
        tn = ((y_true == 0) & (y_pred == 0)).sum()
        
        recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
        precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
        f1 = 2 * (recall * precision) / (recall + precision) if (recall + precision) > 0 else 0.0
        
        # Variance metrics (simplified as deviation from mean or similar)
        # Spec asks for "variance_fp, variance_fn". 
        # This likely implies the variance of these rates across the sweep? 
        # Or the variance at this point? 
        # Let's output the rates themselves as "variance" proxy or calculate local variance.
        # Interpreting "variance_fp" as the rate of false positives at this threshold.
        variance_fp = fp / (fp + tn) if (fp + tn) > 0 else 0.0
        variance_fn = fn / (fn + tp) if (fn + tp) > 0 else 0.0
        
        results.append({
            'threshold': thresh,
            'recall': recall,
            'precision': precision,
            'F1': f1,
            'variance_fp': variance_fp,
            'variance_fn': variance_fn
        })
    
    return pd.DataFrame(results)

def test_sensitivity_analysis_sweep():
    """
    Integration test: Run the sensitivity sweep and verify output file.
    """
    set_seed(get_seed())
    
    # 1. Load real data
    logger.info("Loading real data for sensitivity analysis...")
    try:
        df = load_real_predictions()
        logger.info(f"Loaded {len(df)} entries.")
    except (FileNotFoundError, ValueError) as e:
        pytest.fail(f"Failed to load real data: {e}")
    
    # 2. Run sweep
    logger.info("Running sensitivity sweep...")
    try:
        result_df = run_sensitivity_sweep(df)
    except ValueError as e:
        pytest.fail(f"Sensitivity sweep failed: {e}")
    
    # 3. Ensure output directory exists
    SENSITIVITY_OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    
    # 4. Save results
    logger.info(f"Saving results to {SENSITIVITY_OUTPUT_PATH}")
    result_df.to_csv(SENSITIVITY_OUTPUT_PATH, index=False)
    
    # 5. Verify output file
    assert SENSITIVITY_OUTPUT_PATH.exists(), "Output file was not created."
    
    saved_df = pd.read_csv(SENSITIVITY_OUTPUT_PATH)
    
    # 6. Verify schema
    expected_cols = ['threshold', 'recall', 'precision', 'F1', 'variance_fp', 'variance_fn']
    assert list(saved_df.columns) == expected_cols, f"Columns mismatch. Expected {expected_cols}, got {list(saved_df.columns)}"
    
    # 7. Verify content (non-empty, reasonable values)
    assert len(saved_df) > 0, "Output file is empty."
    assert saved_df['threshold'].between(0.01, 0.10).all(), "Thresholds out of expected range."
    assert (saved_df['recall'] >= 0).all() and (saved_df['recall'] <= 1).all(), "Recall out of [0,1]."
    assert (saved_df['precision'] >= 0).all() and (saved_df['precision'] <= 1).all(), "Precision out of [0,1]."
    
    logger.info("Sensitivity analysis integration test PASSED.")

if __name__ == "__main__":
    test_sensitivity_analysis_sweep()