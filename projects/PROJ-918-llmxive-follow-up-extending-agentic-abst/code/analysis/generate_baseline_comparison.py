"""
T024: Generate baseline comparison metrics.

Reads simulation results from the execution of the Meta-Critic and Full-Context
baselines (produced by T022 and T021) and aggregates them into a single JSON
report at data/results/baseline_comparison.json.

Expected input files (generated by previous tasks):
- data/results/meta_critic_metrics.json
- data/results/full_context_metrics.json

Output:
- data/results/baseline_comparison.json
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(project_root))

from config import get_path, get_config
from logging_config import setup_logging

# Ensure output directory exists
RESULTS_DIR = get_path("results")
RESULTS_DIR.mkdir(parents=True, exist_ok=True)

METRICS_MC = RESULTS_DIR / "meta_critic_metrics.json"
METRICS_FC = RESULTS_DIR / "full_context_metrics.json"
OUTPUT_FILE = RESULTS_DIR / "baseline_comparison.json"

logger = setup_logging()

def load_json_safe(path: Path) -> Optional[Dict[str, Any]]:
    """Load JSON file, returning None if not found."""
    if not path.exists():
        logger.warning(f"Input file not found: {path}")
        return None
    try:
        with open(path, 'r', encoding='utf-8') as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse JSON in {path}: {e}")
        return None

def calculate_token_reduction(mc_tokens: float, fc_tokens: float) -> float:
    """Calculate percentage reduction in tokens."""
    if fc_tokens == 0:
        return 0.0
    return ((fc_tokens - mc_tokens) / fc_tokens) * 100.0

def calculate_effect_size(mc_val: float, fc_val: float, mc_std: float, fc_std: float) -> float:
    """
    Calculate Cohen's d effect size.
    d = (mean1 - mean2) / pooled_std
    """
    if mc_std == 0 and fc_std == 0:
        return 0.0
    # Pooled standard deviation
    pooled_std = ((mc_std ** 2) + (fc_std ** 2)) / 2.0
    if pooled_std == 0:
        return 0.0
    return (mc_val - fc_val) / (pooled_std ** 0.5)

def main():
    logger.info(f"Starting baseline comparison generation for {OUTPUT_FILE}")

    # Load metrics from previous steps
    mc_metrics = load_json_safe(METRICS_MC)
    fc_metrics = load_json_safe(METRICS_FC)

    if not mc_metrics or not fc_metrics:
        # Check if we have partial data to report
        if not mc_metrics and not fc_metrics:
            logger.error("Both input metric files are missing. Cannot generate comparison.")
            sys.exit(1)
        
        # If one is missing, we can still generate a partial report, but warn
        logger.warning("One or both input metric files are missing. Generating partial report.")

    comparison = {
        "meta_critic": {},
        "full_context": {},
        "summary": {}
    }

    # Process Meta-Critic Metrics
    if mc_metrics:
        comparison["meta_critic"] = mc_metrics
        # Ensure expected keys exist for calculation
        mc_tokens = mc_metrics.get("avg_token_consumption", 0.0)
        mc_latency = mc_metrics.get("avg_latency_seconds", 0.0)
        mc_recall = mc_metrics.get("timely_abstention_recall", 0.0)
        mc_std = mc_metrics.get("token_consumption_std", 0.0)
    else:
        mc_tokens = 0.0
        mc_latency = 0.0
        mc_recall = 0.0
        mc_std = 0.0

    # Process Full-Context Metrics
    if fc_metrics:
        comparison["full_context"] = fc_metrics
        fc_tokens = fc_metrics.get("avg_token_consumption", 0.0)
        fc_latency = fc_metrics.get("avg_latency_seconds", 0.0)
        fc_recall = fc_metrics.get("timely_abstention_recall", 0.0) # Usually N/A or 0 for baseline
        fc_std = fc_metrics.get("token_consumption_std", 0.0)
    else:
        fc_tokens = 0.0
        fc_latency = 0.0
        fc_recall = 0.0
        fc_std = 0.0

    # Calculate Derived Metrics
    token_reduction_pct = calculate_token_reduction(mc_tokens, fc_tokens)
    
    # Cohen's d calculation requires standard deviations which might not be in the base metrics
    # If not present, we estimate 0 or skip, but here we assume they are populated by T022
    if mc_std > 0 or fc_std > 0:
        cohens_d = calculate_effect_size(mc_tokens, fc_tokens, mc_std, fc_std)
    else:
        cohens_d = 0.0

    # Summary
    comparison["summary"] = {
        "token_reduction_percentage": round(token_reduction_pct, 2),
        "latency_difference_seconds": round(mc_latency - fc_latency, 4),
        "effect_size_cohens_d": round(cohens_d, 4),
        "meets_token_reduction_threshold": token_reduction_pct >= 40.0,
        "meets_effect_size_threshold": abs(cohens_d) >= 0.5,
        "comparison_generated_at": str(Path(OUTPUT_FILE).resolve()),
        "input_files": {
            "meta_critic": str(METRICS_MC),
            "full_context": str(METRICS_FC)
        }
    }

    # Write output
    try:
        with open(OUTPUT_FILE, 'w', encoding='utf-8') as f:
            json.dump(comparison, f, indent=2)
        logger.info(f"Successfully wrote baseline comparison to {OUTPUT_FILE}")
    except IOError as e:
        logger.error(f"Failed to write output file {OUTPUT_FILE}: {e}")
        sys.exit(1)

    # Print summary to stdout for quick verification
    print(f"Baseline Comparison Summary:")
    print(f"  Token Reduction: {token_reduction_pct:.2f}%")
    print(f"  Cohen's d: {cohens_d:.4f}")
    print(f"  Meets 40% Reduction Threshold: {comparison['summary']['meets_token_reduction_threshold']}")
    print(f"  Meets |d| >= 0.5 Threshold: {comparison['summary']['meets_effect_size_threshold']}")

    return comparison

if __name__ == "__main__":
    main()