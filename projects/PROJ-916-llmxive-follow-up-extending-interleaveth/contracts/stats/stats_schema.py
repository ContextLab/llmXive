"""
Contract for Statistical Results.

This module defines the expected structure (contract) for statistical
analysis results generated by the pipeline.
"""

from typing import List, Dict, Any, Optional


class StatsContract:
    """
    Contract defining the structure of Statistical Results.
    
    Expected fields:
    - metrics: Dictionary of metric names to values
    - tests: List of statistical test results (name, p_value, effect_size)
    - summary: High-level summary string
    - metadata: Run information
    """
    
    REQUIRED_KEYS = ["metrics", "tests", "summary"]
    
    @staticmethod
    def validate(data: Dict[str, Any]) -> None:
        """
        Validate that the input data conforms to the Stats Contract.
        
        Args:
            data: The dictionary to validate.
            
        Raises:
            ValueError: If the data does not conform to the contract.
        """
        if not isinstance(data, dict):
            raise ValueError("Stats data must be a dictionary.")
        
        for key in StatsContract.REQUIRED_KEYS:
            if key not in data:
                raise ValueError(f"Missing required key in Stats Contract: '{key}'")
        
        if not isinstance(data["metrics"], dict):
            raise ValueError("'metrics' must be a dictionary.")
        
        if not isinstance(data["tests"], list):
            raise ValueError("'tests' must be a list.")
        
        if not isinstance(data["summary"], str):
            raise ValueError("'summary' must be a string.")
        
        # Validate test structure
        for i, test in enumerate(data["tests"]):
            if not isinstance(test, dict):
                raise ValueError(f"Test at index {i} must be a dictionary.")
            if "name" not in test:
                raise ValueError(f"Test at index {i} missing key: 'name'")
    
    @staticmethod
    def get_example() -> Dict[str, Any]:
        """Return an example conforming to the contract."""
        return {
            "metrics": {
                "simulator_error_rate": 0.12,
                "generator_error_rate": 0.08,
                "mean_f1": 0.85
            },
            "tests": [
                {
                    "name": "paired_t_test",
                    "p_value": 0.03,
                    "effect_size": 0.5
                },
                {
                    "name": "wilcoxon",
                    "p_value": 0.04,
                    "effect_size": 0.45
                }
            ],
            "summary": "Significant improvement observed in agentic loop vs baseline.",
            "metadata": {
                "n_samples": 100,
                "seed": 42
            }
        }