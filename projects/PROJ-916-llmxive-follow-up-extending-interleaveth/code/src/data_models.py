"""
Data models for llmXive: SceneGraph and TrajectoryLog.

These models conform to the contracts defined in:
- specs/001-llmxive-interleave-structure-vs-modality/contracts/scene.schema.yaml
- specs/001-llmxive-interleave-structure-vs-modality/contracts/trajectory.schema.yaml

We use Pydantic v2 for validation and serialization.
"""

from datetime import datetime
from typing import Any, Dict, List, Optional
from uuid import UUID, uuid4

from pydantic import BaseModel, Field, field_validator


class ObjectNode(BaseModel):
    """Represents a single object in the scene graph."""
    id: str = Field(..., description="Unique identifier for the object")
    label: str = Field(..., description="Semantic label of the object (e.g., 'person', 'car')")
    attributes: Dict[str, Any] = Field(
        default_factory=dict,
        description="Key-value pairs describing object properties (e.g., color, size)"
    )
    bbox: Optional[List[float]] = Field(
        None,
        description="Bounding box [x, y, width, height] if available"
    )

class RelationshipEdge(BaseModel):
    """Represents a relationship between two objects in the scene graph."""
    id: str = Field(..., description="Unique identifier for the relationship")
    subject_id: str = Field(..., description="ID of the subject object")
    predicate: str = Field(..., description="Relationship predicate (e.g., 'on', 'next to')")
    object_id: str = Field(..., description="ID of the object object")
    attributes: Dict[str, Any] = Field(
        default_factory=dict,
        description="Optional attributes of the relationship"
    )

class SceneGraph(BaseModel):
    """
    Structured representation of a visual scene as a graph.

    Conforms to: specs/.../contracts/scene.schema.yaml
    """
    id: str = Field(default_factory=lambda: str(uuid4()), description="Unique scene identifier")
    source_dataset: Optional[str] = Field(None, description="Source dataset name (e.g., 'WISE', 'RISE')")
    image_id: Optional[str] = Field(None, description="Original image identifier if applicable")
    objects: List[ObjectNode] = Field(..., description="List of objects in the scene")
    relationships: List[RelationshipEdge] = Field(..., description="List of relationships between objects")
    caption: Optional[str] = Field(None, description="Optional natural language caption for the scene")
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Additional metadata (e.g., image dimensions, source URL)"
    )

    @field_validator('objects')
    @classmethod
    def validate_objects_unique(cls, v: List[ObjectNode]) -> List[ObjectNode]:
        ids = [obj.id for obj in v]
        if len(ids) != len(set(ids)):
            raise ValueError("Object IDs must be unique within a scene graph")
        return v

    @field_validator('relationships')
    @classmethod
    def validate_relationship_refs(cls, v: List[RelationshipEdge], info) -> List[RelationshipEdge]:
        # We can't easily access 'objects' here in a field_validator without using model_validator,
        # but for now we ensure basic structure. Full cross-validation happens in the loader/validator.
        for rel in v:
            if not rel.subject_id or not rel.object_id:
                raise ValueError("Relationships must have valid subject and object IDs")
        return v

class CritiqueStep(BaseModel):
    """A single step of critique or reasoning in the trajectory."""
    step_id: str = Field(..., description="Unique step identifier")
    agent_role: str = Field(..., description="Role of the agent (e.g., 'Planner', 'Generator', 'Critic')")
    intent: Optional[str] = Field(None, description="The intent or plan generated")
    output_json: Optional[Dict[str, Any]] = Field(None, description="JSON output generated by the agent")
    critique: Optional[str] = Field(None, description="Critique or feedback provided")
    score: Optional[float] = Field(None, description="Confidence or quality score (0.0-1.0)")
    timestamp: datetime = Field(default_factory=datetime.utcnow, description="Timestamp of the step")
    memory_snapshot: Optional[Dict[str, Any]] = Field(
        default_factory=dict,
        description="Snapshot of relevant memory/state at this step"
    )

class TrajectoryLog(BaseModel):
    """
    Log of the agentic reasoning trajectory for a single scene.

    Conforms to: specs/.../contracts/trajectory.schema.yaml
    """
    id: str = Field(default_factory=lambda: str(uuid4()), description="Unique trajectory identifier")
    scene_graph_id: str = Field(..., description="Reference to the SceneGraph this trajectory is for")
    start_time: datetime = Field(default_factory=datetime.utcnow, description="Start time of the trajectory")
    end_time: Optional[datetime] = Field(None, description="End time (if completed)")
    status: str = Field(
        default="in_progress",
        description="Status: 'in_progress', 'completed', 'aborted', 'error'"
    )
    steps: List[CritiqueStep] = Field(default_factory=list, description="Ordered list of agent steps")
    final_reasoning_score: Optional[float] = Field(
        None,
        description="Final computed reasoning score (e.g., F1, Graph Edit Distance)"
    )
    error_message: Optional[str] = Field(None, description="Error message if status is 'error'")
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Additional metadata (e.g., model version, hyperparameters)"
    )

    @field_validator('steps')
    @classmethod
    def validate_steps_ordered(cls, v: List[CritiqueStep]) -> List[CritiqueStep]:
        # Ensure steps are roughly ordered by timestamp or step_id if sortable
        # For simplicity, we just ensure the list is not None
        return v

    def add_step(self, step: CritiqueStep) -> None:
        """Helper to add a step and update timestamps if needed."""
        self.steps.append(step)
        if self.status == "in_progress":
            self.end_time = datetime.utcnow() if step.timestamp > (self.end_time or self.start_time) else self.end_time

    def mark_completed(self, score: Optional[float] = None) -> None:
        """Mark the trajectory as completed and set the final score."""
        self.status = "completed"
        self.end_time = datetime.utcnow()
        if score is not None:
            self.final_reasoning_score = score

    def mark_aborted(self, reason: str) -> None:
        """Mark the trajectory as aborted."""
        self.status = "aborted"
        self.end_time = datetime.utcnow()
        self.error_message = reason

    def mark_error(self, error: str) -> None:
        """Mark the trajectory as errored."""
        self.status = "error"
        self.end_time = datetime.utcnow()
        self.error_message = error