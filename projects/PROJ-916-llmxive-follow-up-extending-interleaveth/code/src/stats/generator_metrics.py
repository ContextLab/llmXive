"""
Generator Metrics Module.

Implements the calculation of 'Generator Error Rate' (FR-010),
distinct from the simulator's internal error rate.
"""
from typing import List, Dict, Any, Optional, Tuple
from dataclasses import dataclass, field

from src.data_models import SceneGraph, ObjectNode, RelationshipEdge
from src.simulator.parser import SceneDescription
from src.stats.simulator_metrics import calculate_graph_edit_distance


@dataclass
class GeneratorMetrics:
    """
    Container for metrics related to the Generator's performance.

    Attributes:
        generator_error_rate (float): The ratio of deviation between the
            generated JSON and the intended prompt (ground truth).
            Calculated as: 1 - (Similarity / Max_Similarity).
        total_samples (int): Total number of samples evaluated.
        failed_samples (int): Number of samples where generation failed completely.
        avg_edit_distance (float): Average Graph Edit Distance across samples.
    """
    generator_error_rate: float = 0.0
    total_samples: int = 0
    failed_samples: int = 0
    avg_edit_distance: float = 0.0
    edit_distances: List[float] = field(default_factory=list)

    def add_sample(self, edit_distance: float, is_success: bool = True) -> None:
        """
        Accumulate metrics for a single sample.

        Args:
            edit_distance: The calculated Graph Edit Distance for this sample.
            is_success: Whether the generation step was considered successful.
        """
        self.edit_distances.append(edit_distance)
        self.total_samples += 1
        if not is_success:
            self.failed_samples += 1

    def finalize(self) -> None:
        """
        Compute final aggregate metrics.
        """
        if not self.edit_distances:
            self.generator_error_rate = 0.0
            self.avg_edit_distance = 0.0
            return

        self.avg_edit_distance = sum(self.edit_distances) / len(self.edit_distances)

        # Normalize error rate: 0 distance = 0% error, max distance = 100% error.
        # For this implementation, we treat the raw normalized edit distance as the error rate.
        # If edit distance is normalized to [0, 1], then error_rate = edit_distance.
        # If raw, we might need a normalization factor based on graph size.
        # Assuming calculate_graph_edit_distance returns a normalized score or we normalize here.
        # Given the context of 'simulator_metrics', we assume the distance is comparable.
        # We will treat the average normalized edit distance as the error rate.
        # If the distance is raw (count of edits), we would divide by max possible edges/nodes.
        # For now, assuming the input edit_distance is normalized [0, 1] or we treat it as the error metric.
        
        # To be safe and consistent with 'error rate' semantics:
        # If the edit distance is a count, we need to normalize by graph size.
        # However, without access to the specific max-size here, we assume the input
        # is already a normalized similarity/distance metric or we treat the average
        # distance as the proxy for error.
        
        # Let's assume the input 'edit_distance' is a normalized value [0, 1] where 1 is max error.
        # If it is a raw count, this logic would need the graph size.
        # Based on T016a context, calculate_graph_edit_distance likely returns a normalized score.
        self.generator_error_rate = self.avg_edit_distance


def calculate_generator_error_rate(
    generated_graph: SceneGraph,
    intended_graph: SceneGraph,
    max_nodes: Optional[int] = None,
    max_edges: Optional[int] = None
) -> float:
    """
    Calculate the Generator Error Rate for a single sample.

    This measures the deviation between the JSON generated by the agent
    and the intended prompt (ground truth).

    Args:
        generated_graph: The SceneGraph produced by the Generator.
        intended_graph: The ground truth SceneGraph (from the prompt/intent).
        max_nodes: Optional max nodes for normalization. If None, uses intended graph size.
        max_edges: Optional max edges for normalization.

    Returns:
        float: A normalized error rate (0.0 to 1.0).
    """
    if not intended_graph.objects and not intended_graph.relationships:
        # If ground truth is empty, any generation is error (unless also empty)
        if generated_graph.objects or generated_graph.relationships:
            return 1.0
        return 0.0

    # Calculate raw edit distance
    raw_distance = calculate_graph_edit_distance(generated_graph, intended_graph)

    # Normalize the distance
    # Max possible edits = (max nodes in intended) + (max edges in intended)
    # We use the intended graph size as the baseline for "what was supposed to be there"
    intended_node_count = len(intended_graph.objects)
    intended_edge_count = len(intended_graph.relationships)
    
    # Avoid division by zero
    if intended_node_count == 0 and intended_edge_count == 0:
        return 0.0 if raw_distance == 0 else 1.0

    # Normalize by total elements in ground truth
    # This represents the fraction of the intended structure that was "wrong" or "missing"
    normalization_factor = intended_node_count + intended_edge_count
    
    if normalization_factor == 0:
        return 0.0

    error_rate = raw_distance / normalization_factor
    return min(1.0, error_rate)


def evaluate_generator_against_prompt(
    generated_graph: SceneGraph,
    intended_graph: SceneGraph
) -> GeneratorMetrics:
    """
    Evaluate a single generator output against the intended prompt.

    Args:
        generated_graph: The output from the Generator agent.
        intended_graph: The ground truth derived from the prompt.

    Returns:
        GeneratorMetrics: A metrics object containing the error rate for this sample.
    """
    error_rate = calculate_generator_error_rate(generated_graph, intended_graph)
    metrics = GeneratorMetrics()
    metrics.add_sample(error_rate, is_success=(error_rate == 0.0))
    metrics.finalize()
    return metrics


def aggregate_generator_metrics(
    samples: List[Tuple[SceneGraph, SceneGraph]]
) -> GeneratorMetrics:
    """
    Aggregate metrics across multiple samples.

    Args:
        samples: List of tuples (generated_graph, intended_graph).

    Returns:
        GeneratorMetrics: Aggregated statistics.
    """
    metrics = GeneratorMetrics()
    for gen_graph, int_graph in samples:
        error_rate = calculate_generator_error_rate(gen_graph, int_graph)
        metrics.add_sample(error_rate, is_success=(error_rate == 0.0))
    metrics.finalize()
    return metrics
