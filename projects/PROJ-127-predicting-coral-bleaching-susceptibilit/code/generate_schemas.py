def main():
    """Main entry point to generate the schema files."""
    ensure_directories()

    print("Generating dataset schema...")
    dataset_schema = generate_dataset_schema()
    with open(CONTRACTS_DIR / "dataset.schema.yaml", "w") as f:
        yaml.dump(dataset_schema, f, default_flow_style=False, sort_keys=False)
    print(f"Created: {CONTRACTS_DIR / 'dataset.schema.yaml'}")

    print("Generating output schema...")
    output_schema = generate_output_schema()
    with open(CONTRACTS_DIR / "output.schema.yaml", "w") as f:
        yaml.dump(output_schema, f, default_flow_style=False, sort_keys=False)
    print(f"Created: {CONTRACTS_DIR / 'output.schema.yaml'}")

    print("Schema generation complete.")

if __name__ == "__main__":
    main()