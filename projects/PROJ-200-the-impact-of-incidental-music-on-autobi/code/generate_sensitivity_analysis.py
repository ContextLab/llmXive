        summary_df = generate_sensitivity_summary(df)
        
        # Save final output
        save_sensitivity_analysis(summary_df, output_file)
        
        # Clean up temp file if it exists and was used
        if temp_file.exists():
            temp_file.unlink()
            logger.info(f"Removed temporary file: {temp_file}")

        logger.info("T039a completed successfully.")

