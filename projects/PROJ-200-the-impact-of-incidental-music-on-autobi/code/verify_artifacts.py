"""
Artifact Verification Script (T050).

Verifies the existence and checksums of all required pipeline outputs
against the state.yaml manifest.

Required Artifacts:
- data/processed/ingested_cohort.parquet
- data/processed/user_track_pairs.parquet
- data/final/regression_summary.csv
- data/final/sensitivity_analysis.csv
- data/final/bootstrap_results.csv

Dependencies:
- state.yaml (generated by previous tasks)
"""
import os
import sys
import logging
import hashlib
import yaml
from pathlib import Path
from typing import Dict, Any, List, Optional

# Add project root to path if running as script
if __name__ == "__main__":
    project_root = Path(__file__).resolve().parent.parent
    sys.path.insert(0, str(project_root))

from config import get_project_root, get_config_dict
