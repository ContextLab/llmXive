logger = get_logger(__name__)

REQUIRED_ARTIFACTS = [
    "data/processed/ingested_cohort.parquet",
    "data/processed/user_track_pairs.parquet",
    "data/final/regression_summary.csv",
    "data/final/sensitivity_analysis.csv",
    "data/final/bootstrap_results.csv",
]

def calculate_file_checksum(file_path: Path) -> Optional[str]:
    """Calculate SHA256 checksum of a file."""
    if not file_path.exists():
        return None
    
    sha256_hash = hashlib.sha256()
    try:
        with open(file_path, "rb") as f:
            for byte_block in iter(lambda: f.read(4096), b""):
                sha256_hash.update(byte_block)
        return sha256_hash.hexdigest()
    except Exception as e:
        logger.error(f"Error calculating checksum for {file_path}: {e}")
        return None

def verify_artifacts() -> bool:
    """
    Verify existence and checksums of all required artifacts.
    
    Returns:
        bool: True if all artifacts exist and checksums match, False otherwise.
    """
    project_root = get_project_root()
    state_path = project_root / "state.yaml"
    
    if not state_path.exists():
        logger.error("state.yaml not found. Cannot verify artifacts.")
        return False
    
    # Load state
    try:
        with open(state_path, 'r') as f:
            state_data = yaml.safe_load(f)
    except Exception as e:
        logger.error(f"Failed to load state.yaml: {e}")
        return False
    
    if not state_data or 'files' not in state_data:
        logger.error("state.yaml is missing 'files' section.")
        return False
    
    registered_files = state_data['files']
    all_valid = True
    
    logger.info("Starting artifact verification...")
    logger.info(f"Checking {len(REQUIRED_ARTIFACTS)} required artifacts.")
    
    for artifact_rel_path in REQUIRED_ARTIFACTS:
        artifact_path = project_root / artifact_rel_path
        
        # Check existence
        if not artifact_path.exists():
            logger.error(f"MISSING: {artifact_rel_path}")
            all_valid = False
            continue
        
        # Check checksum against state
        current_checksum = calculate_file_checksum(artifact_path)
        registered_info = registered_files.get(artifact_rel_path)
        
        if not registered_info:
            logger.warning(f"UNREGISTERED: {artifact_rel_path} exists but not in state.yaml")
            # We don't fail here, but log it. The file might be newly created.
            # However, for T050 strict verification, we might want to fail.
            # Let's assume if it's not in state.yaml, it's a mismatch with the spec.
            logger.error(f"VERIFICATION FAILED: {artifact_rel_path} not registered in state.yaml")
            all_valid = False
            continue
        
        registered_checksum = registered_info.get('checksum')
        
        if current_checksum != registered_checksum:
            logger.error(f"CHECKSUM MISMATCH: {artifact_rel_path}")
            logger.error(f"  Expected: {registered_checksum}")
            logger.error(f"  Found:    {current_checksum}")
            all_valid = False
        else:
            logger.info(f"VERIFIED: {artifact_rel_path} (checksum: {current_checksum[:8]}...)")
    
    # Additional check: Ensure no missing files in state that are required
    # (Already covered by the loop above)
    
    return all_valid

def main():
    """Entry point for artifact verification."""
    setup_logging(level=logging.INFO)
    
    success = verify_artifacts()
    
    if success:
        logger.info("SUCCESS: All artifacts verified successfully.")
        sys.exit(0)
    else:
        logger.error("FAILURE: Artifact verification failed.")
        sys.exit(1)

if __name__ == "__main__":
    main()