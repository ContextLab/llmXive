logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

def load_chip_overlap_stats(validation_report_path: Path) -> Dict[str, float]:
    """
    Load the validation report generated by T032/T030.
    Returns a dict mapping motif_id -> chip_overlap_pct.
    """
    if not validation_report_path.exists():
        raise FileNotFoundError(f"Validation report not found at {validation_report_path}. "
                                "Ensure T032 has run successfully.")
    
    with open(validation_report_path, 'r') as f:
        report = json.load(f)
    
    # Expected structure based on T032: {"motif_overlap_stats": {motif_id: pct, ...}}
    # Or potentially flattened in the report depending on T032 implementation details.
    # We assume the report contains a key 'motif_overlap_stats' or similar.
    # If T032 output structure is different, we adapt here.
    # Assuming T032 writes: {"motif_overlap_stats": {"MA0001.1": 85.5, ...}}
    
    overlap_data = report.get('motif_overlap_stats', {})
    
    # Normalize keys if necessary (ensure they are strings)
    return {str(k): float(v) for k, v in overlap_data.items()}

def generate_summary_table(enrichment_matrix_path: Path, 
                           validation_report_path: Path, 
                           output_path: Path) -> pd.DataFrame:
    """
    Merges enrichment results with ChIP-seq overlap percentages to create the final summary.
    """
    logger.info(f"Loading enrichment matrix from {enrichment_matrix_path}")
    if not enrichment_matrix_path.exists():
        raise FileNotFoundError(f"Enrichment matrix not found at {enrichment_matrix_path}. "
                                "Ensure T024/T025 has run successfully.")
    
    # Load enrichment matrix (expected columns: motif_id, cell_type, p_value_raw, q_value_adj, ...)
    # The exact structure depends on T024 output. Assuming it's a CSV with motif_id as a column.
    df_enrichment = pd.read_csv(enrichment_matrix_path)
    
    # Ensure motif_id is string for merging
    if 'motif_id' not in df_enrichment.columns:
        # Try to find a column that might be motif ID if named differently
        # Common names: 'motif', 'tf_id', 'jaspar_id'
        possible_cols = [c for c in df_enrichment.columns if 'motif' in c.lower() or 'tf' in c.lower()]
        if possible_cols:
            df_enrichment['motif_id'] = df_enrichment[possible_cols[0]]
            logger.warning(f"Column '{possible_cols[0]}' used as 'motif_id'.")
        else:
            raise ValueError("Could not find 'motif_id' column in enrichment matrix.")
    
    df_enrichment['motif_id'] = df_enrichment['motif_id'].astype(str)

    logger.info(f"Loading validation report from {validation_report_path}")
    overlap_map = load_chip_overlap_stats(validation_report_path)

    # Create a DataFrame from the overlap map to merge
    df_overlap = pd.DataFrame(list(overlap_map.items()), columns=['motif_id', 'chip_overlap_pct'])
    
    # Merge enrichment data with overlap data
    # Use left join to keep all enrichment entries, filling overlap with 0.0 if missing
    df_summary = pd.merge(df_enrichment, df_overlap, on='motif_id', how='left')
    
    # Fill missing overlap percentages with 0.0
    df_summary['chip_overlap_pct'] = df_summary['chip_overlap_pct'].fillna(0.0)

    # Select and order columns as required: motif_id, p_value_raw, q_value_adj, chip_overlap_pct
    required_cols = ['motif_id', 'p_value_raw', 'q_value_adj', 'chip_overlap_pct']
    
    # Handle potential column name mismatches (e.g., p_value vs p_value_raw)
    final_cols = []
    for col in required_cols:
        if col in df_summary.columns:
            final_cols.append(col)
        else:
            # Try to find a matching column
            matches = [c for c in df_summary.columns if col.replace('_', '') in c.replace('_', '')]
            if matches:
                final_cols.append(matches[0])
                logger.warning(f"Column '{col}' not found. Using '{matches[0]}' instead.")
            else:
                raise ValueError(f"Required column '{col}' not found in merged dataframe.")
    
    df_final = df_summary[final_cols]
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Save to CSV
    df_final.to_csv(output_path, index=False)
    logger.info(f"Summary table saved to {output_path}")
    
    return df_final

def main():
    """
    Entry point for T033.
    """
    # Define paths based on config and task description
    output_file = Path(DATA_PROCESSED_DIR) / "summary_table.csv"
    enrichment_file = Path(DATA_PROCESSED_DIR) / "enrichment_matrix.csv"
    validation_file = Path(DATA_PROCESSED_DIR) / "validation_report.json"

    try:
        df = generate_summary_table(enrichment_file, validation_file, output_file)
        logger.info(f"Successfully generated summary table with {len(df)} rows.")
        print(f"Summary table generated: {output_file}")
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error generating summary table: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
