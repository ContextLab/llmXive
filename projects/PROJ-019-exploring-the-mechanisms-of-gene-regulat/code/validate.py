def load_enrichment_results() -> pd.DataFrame:
    """
    Load the enrichment matrix generated by T024.
    Expected path: data/processed/enrichment_matrix.csv
    """
    input_path = Path(DATA_PROCESSED_DIR) / "enrichment_matrix.csv"
    if not input_path.exists():
        raise FileNotFoundError(f"Enrichment matrix not found at {input_path}. "
                                "Please ensure T024 (enrichment orchestration) has completed.")
    
    logger.info(f"Loading enrichment matrix from {input_path}")
    df = pd.read_csv(input_path)
    
    # Expected columns: cell_type, motif_id, p_value_raw, q_value_adj
    required_cols = {'cell_type', 'motif_id', 'q_value_adj'}
    if not required_cols.issubset(df.columns):
        raise ValueError(f"Enrichment matrix missing required columns. "
                         f"Found: {list(df.columns)}, Required: {required_cols}")
    
    return df


def get_top_motifs_per_cell_type(df: pd.DataFrame, top_n: int = 10) -> pd.DataFrame:
    """
    Select the top N motifs per cell type based on adjusted q-value.
    Used to reduce dimensionality for clustering if the matrix is too large.
    """
    # Sort by q-value ascending (most significant first)
    sorted_df = df.sort_values(by=['cell_type', 'q_value_adj'])
    # Group by cell_type and take top_n
    top_df = sorted_df.groupby('cell_type').head(top_n).reset_index(drop=True)
    return top_df


def calculate_silhouette_score(enrichment_df: pd.DataFrame) -> float:
    """
    Compute the silhouette score for cell types based on their motif enrichment profiles.
    
    1. Pivot the dataframe to create a matrix: Rows=Cell Types, Columns=Motifs, Values=q-value.
    2. Handle missing motifs (NaN) by filling with 1.0 (no enrichment) or mean.
    3. Compute pairwise distances.
    4. Perform hierarchical clustering to assign cluster labels (assuming K = number of cell types).
    5. Calculate silhouette score.
    
    Returns:
        float: Silhouette score between -1 and 1.
    """
    if enrichment_df.empty:
        logger.warning("Enrichment dataframe is empty. Cannot compute silhouette score.")
        return -1.0

    # Pivot to get matrix: index=cell_type, columns=motif_id, values=q_value_adj
    # We use q-value as the feature. Lower is better, but distance works on magnitude.
    # Alternatively, we could use -log10(q-value) to emphasize significant peaks.
    # Let's use -log10(q-value) to make significant enrichments larger numbers.
    # Add small epsilon to avoid log(0)
    epsilon = 1e-300
    enrichment_df['feature_val'] = -np.log10(enrichment_df['q_value_adj'] + epsilon)
    
    matrix = enrichment_df.pivot_table(
        index='cell_type', 
        columns='motif_id', 
        values='feature_val', 
        aggfunc='mean' # In case of duplicates
    )

    if matrix.empty or len(matrix) < 2:
        logger.warning("Not enough cell types (need >= 2) to compute silhouette score.")
        return -1.0

    # Fill missing values (motifs not found in some cell types) with 0 (no enrichment signal)
    matrix_filled = matrix.fillna(0)

    # Convert to numpy array
    X = matrix_filled.values

    # Calculate pairwise Euclidean distance
    # We need to pass this to silhouette_score which expects raw features, 
    # but silhouette_score internally computes distances.
    # However, sklearn's silhouette_score computes Euclidean distance by default if metric='euclidean'.
    
    try:
        # We assume the number of clusters is the number of unique cell types
        # This is a bit circular if we are validating the clustering, but for the test
        # we assume the "ground truth" is that each cell type is its own cluster.
        # The silhouette score measures how well separated these clusters are.
        labels = matrix_filled.index.astype(str) # Use index as labels directly if we assume 1 cluster per cell type?
        
        # Actually, silhouette score requires integer labels for clusters.
        # If we want to see if "Cell Type A" is distinct from "Cell Type B",
        # we treat each unique cell_type as a cluster ID.
        unique_cell_types = matrix_filled.index.unique()
        label_map = {ct: i for i, ct in enumerate(unique_cell_types)}
        cluster_labels = [label_map[ct] for ct in matrix_filled.index]
        
        score = silhouette_score(X, cluster_labels)
        return score
        
    except Exception as e:
        logger.error(f"Error computing silhouette score: {e}")
        return -1.0


def validate_motifs() -> Dict[str, Any]:
    """
    Main validation function for T031.
    1. Loads enrichment results.
    2. Computes silhouette score.
    3. Logs result.
    4. If score < 0.4, logs a warning but does NOT exit with error code 1.
    5. Returns a report dictionary.
    """
    logger.info("Starting T031: Silhouette Score Validation")
    
    report = {
        "task_id": "T031",
        "metric": "silhouette_score",
        "status": "completed",
        "message": "",
        "warning": False
    }

    try:
        # Load data
        df = load_enrichment_results()
        
        # Optional: Filter to top motifs if too many features (optional optimization)
        # For now, use all found motifs.
        
        score = calculate_silhouette_score(df)
        
        report["score"] = score
        report["message"] = f"Silhouette score calculated: {score:.4f}"
        
        # Threshold check as per US-3-SC1
        if score < 0.4:
            report["warning"] = True
            report["message"] += f" (Warning: Score < 0.4 threshold)"
            logger.warning(f"Silhouette score {score:.4f} is below the 0.4 threshold. "
                           "Clustering may not be distinct, but validation continues.")
        else:
            logger.info(f"Silhouette score {score:.4f} meets the >= 0.4 threshold.")
            
    except FileNotFoundError as e:
        report["status"] = "failed"
        report["message"] = str(e)
        logger.error(f"Validation failed due to missing data: {e}")
    except Exception as e:
        report["status"] = "failed"
        report["message"] = f"Error during calculation: {str(e)}"
        logger.error(f"Validation failed: {e}", exc_info=True)
    
    return report


def main():
    """
    Entry point for T031 execution.
    """
    logger.info("Running T031: Compute Silhouette Score")
    
    report = validate_motifs()
    
    # Log final status
    if report["status"] == "completed":
        if report.get("warning"):
            logger.warning(f"Task completed with warning: {report['message']}")
        else:
            logger.info(f"Task completed successfully: {report['message']}")
    else:
        logger.error(f"Task failed: {report['message']}")
        
    # Print report to stdout for easy parsing by orchestrator
    print(json.dumps(report, indent=2))
    
    # Do NOT exit with error code 1 even if score < 0.4, as per spec
    # Only exit 1 if a critical error occurred (e.g., file missing)
    if report["status"] == "failed":
        sys.exit(1)
    else:
        sys.exit(0)


if __name__ == "__main__":
    main()