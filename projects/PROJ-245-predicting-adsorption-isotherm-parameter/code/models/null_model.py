"""
T065: Implement Robust Null Model Baseline.

Logic:
1. Load `folds.json` from T022.
2. Load the preprocessed dataset.
3. For each fold index:
   - Map indices to row indices.
   - Train null model (predict mean) on training split.
   - Predict on test split.
   - Calculate RMSE for each fold.
4. Output `data/results/null_model_fold_rmses.json`.

Dependencies: T022 (folds.json generation).
"""
import os
import sys
import json
import logging
import numpy as np
from pathlib import Path
from typing import Dict, Any, List, Optional

# Add project root to path to ensure imports work when run as script
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from models.evaluate import load_test_data
from data.loader import load_and_preprocess_data

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def load_folds(folds_path: Path) -> List[Dict[str, List[int]]]:
    """Load fold indices from the JSON file generated by T022."""
    if not folds_path.exists():
        raise FileNotFoundError(f"Folds file not found at {folds_path}. "
                                "Ensure T022 has been run successfully.")
    
    with open(folds_path, 'r') as f:
        data = json.load(f)
    
    # Expected format: {"folds": [{"train": [...], "test": [...]}, ...]}
    if "folds" not in data:
        raise ValueError(f"Folds file at {folds_path} missing 'folds' key.")
    
    return data["folds"]

def calculate_rmse(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    """Calculate Root Mean Squared Error."""
    if len(y_true) == 0:
        return 0.0
    return float(np.sqrt(np.mean((y_true - y_pred) ** 2)))

def run_null_model_baseline(
    folds_path: Path,
    data_path: Path,
    output_path: Path,
    target_column: str = "langmuir_capacity"
) -> Dict[str, Any]:
    """
    Execute the null model baseline across all folds.
    
    Args:
        folds_path: Path to folds.json.
        data_path: Path to the preprocessed dataset (parquet or csv).
        output_path: Path to write the results JSON.
        target_column: Name of the target variable.
        
    Returns:
        Dictionary containing fold-level RMSEs and summary stats.
    """
    logger.info(f"Loading folds from {folds_path}")
    folds = load_folds(folds_path)
    
    logger.info(f"Loading dataset from {data_path}")
    # Ensure we load the data exactly as the training phase did
    # We assume load_and_preprocess_data or a similar loader is available.
    # Since T020/T021 use material_level_split, we need the full dataframe here
    # to slice by indices.
    try:
        # Attempt to load using the standard loader if available, 
        # or pandas directly if it's a CSV/Parquet.
        import pandas as pd
        if data_path.suffix == '.parquet':
            df = pd.read_parquet(data_path)
        elif data_path.suffix == '.csv':
            df = pd.read_csv(data_path)
        else:
            # Fallback: try parquet first, then csv
            try:
                df = pd.read_parquet(data_path)
            except:
                df = pd.read_csv(data_path)
    except Exception as e:
        logger.error(f"Failed to load dataset: {e}")
        raise

    if target_column not in df.columns:
        raise ValueError(f"Target column '{target_column}' not found in dataset. "
                         f"Available columns: {list(df.columns)}")

    results = {
        "folds": [],
        "summary": {}
    }

    logger.info(f"Running null model baseline on {len(folds)} folds...")
    
    for i, fold_data in enumerate(folds):
        train_indices = fold_data["train"]
        test_indices = fold_data["test"]
        
        # Extract training and test sets
        y_train = df.iloc[train_indices][target_column].values
        y_test = df.iloc[test_indices][target_column].values
        
        if len(y_train) == 0 or len(y_test) == 0:
            logger.warning(f"Fold {i} has empty train or test set. Skipping.")
            continue
        
        # Null Model: Predict the mean of the training set
        mean_train = np.mean(y_train)
        y_pred = np.full_like(y_test, mean_train, dtype=float)
        
        # Calculate RMSE
        rmse = calculate_rmse(y_test, y_pred)
        
        fold_result = {
            "fold_index": i,
            "train_size": len(train_indices),
            "test_size": len(test_indices),
            "train_mean": float(mean_train),
            "rmse": rmse
        }
        results["folds"].append(fold_result)
        
        logger.info(f"Fold {i}: Train Mean={mean_train:.4f}, Test RMSE={rmse:.4f}")

    # Summary statistics
    if results["folds"]:
        rmses = [f["rmse"] for f in results["folds"]]
        results["summary"] = {
            "mean_rmse": float(np.mean(rmses)),
            "std_rmse": float(np.std(rmses)),
            "min_rmse": float(np.min(rmses)),
            "max_rmse": float(np.max(rmses)),
            "num_folds": len(results["folds"])
        }
    else:
        results["summary"] = {"error": "No folds processed successfully"}

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    
    logger.info(f"Null model results saved to {output_path}")
    return results

def main():
    """Entry point for the null model baseline task."""
    # Default paths relative to project root
    folds_path = PROJECT_ROOT / "data" / "results" / "folds.json"
    data_path = PROJECT_ROOT / "data" / "processed" / "final_dataset.parquet"
    output_path = PROJECT_ROOT / "data" / "results" / "null_model_fold_rmses.json"
    
    # Allow overrides via environment or args if needed, but strict paths per spec
    if not os.path.exists(folds_path):
        logger.error(f"Required input file missing: {folds_path}")
        logger.error("T022 (Hyperparameter Tuning) must be run first to generate folds.json.")
        sys.exit(1)
        
    if not os.path.exists(data_path):
        # Fallback to common alternative names if exact path differs
        alt_paths = [
            PROJECT_ROOT / "data" / "processed" / "cleaned_dataset.parquet",
            PROJECT_ROOT / "data" / "processed" / "dataset.parquet",
            PROJECT_ROOT / "data" / "processed" / "final_dataset.csv"
        ]
        found = False
        for p in alt_paths:
            if os.path.exists(p):
                data_path = p
                found = True
                break
        if not found:
            logger.error(f"Required input dataset not found at {data_path} or alternatives.")
            sys.exit(1)

    logger.info(f"Starting Null Model Baseline (T065)...")
    logger.info(f"  Folds: {folds_path}")
    logger.info(f"  Data: {data_path}")
    logger.info(f"  Output: {output_path}")
    
    try:
        results = run_null_model_baseline(
            folds_path=folds_path,
            data_path=data_path,
            output_path=output_path
        )
        logger.info("T065 completed successfully.")
        print(json.dumps(results["summary"], indent=2))
    except Exception as e:
        logger.error(f"T065 failed: {e}")
        raise

if __name__ == "__main__":
    main()