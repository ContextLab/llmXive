"""
Determinism Verification Script for PROJ-264.

This script executes the smoke test (T050) twice with the same random seed
and verifies that the SHA-256 checksums of all generated output files
(CSVs and the final report) are identical.

This validates the reproducibility guarantees of the pipeline (Constitution Principle I).
"""
import hashlib
import logging
import os
import shutil
import sys
import time
from pathlib import Path

# Add project root to path to ensure imports work
PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from code.utils import set_seed, setup_logging
from code.scripts.run_smoke_test import main as run_smoke_test

# Configuration
SEED = 42
RUNS = 2
RESULTS_DIR = PROJECT_ROOT / "results"
BACKUP_DIR = PROJECT_ROOT / "results_backup"
VERIFICATION_LOG = RESULTS_DIR / "determinism_verification.log"

# Files to verify (relative to RESULTS_DIR)
FILES_TO_VERIFY = [
    "raw_evaluations.csv",
    "stability_metrics.csv",
    "correlation_results.csv",
    "permutation_results.csv",
    "final_report.md",
    "spectrum_report.json" # Included if generated by smoke test
]

def setup_logger(log_path: Path) -> logging.Logger:
    """Configure a logger that writes to both file and console."""
    logger = logging.getLogger("determinism_verification")
    logger.setLevel(logging.INFO)
    
    # Clear existing handlers
    logger.handlers = []

    # File handler
    fh = logging.FileHandler(log_path, mode='w')
    fh.setLevel(logging.INFO)
    
    # Console handler
    ch = logging.StreamHandler()
    ch.setLevel(logging.INFO)

    # Formatter
    formatter = logging.Formatter('%(asctime)s - %(levelname)s - %(message)s')
    fh.setFormatter(formatter)
    ch.setFormatter(formatter)

    logger.addHandler(fh)
    logger.addHandler(ch)
    
    return logger

def compute_file_hash(file_path: Path) -> str:
    """Compute SHA-256 hash of a file."""
    if not file_path.exists():
        raise FileNotFoundError(f"File not found for hashing: {file_path}")
    
    sha256_hash = hashlib.sha256()
    with open(file_path, "rb") as f:
        for byte_block in iter(lambda: f.read(4096), b""):
            sha256_hash.update(byte_block)
    return sha256_hash.hexdigest()

def run_pipeline_run(run_id: int, logger: logging.Logger) -> dict:
    """
    Execute the smoke test pipeline.
    Returns a dictionary mapping relative file paths to their SHA-256 hashes.
    """
    logger.info(f"--- Starting Pipeline Run {run_id} ---")
    
    # Set seed explicitly before running
    set_seed(SEED)
    
    # Ensure results directory exists and is clean for this run
    if RESULTS_DIR.exists():
        shutil.rmtree(RESULTS_DIR)
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    
    # Execute smoke test
    # We catch any exception to ensure we don't crash the whole verification if one run fails
    try:
        run_smoke_test()
    except Exception as e:
        logger.error(f"Pipeline run {run_id} failed with error: {e}")
        raise

    logger.info(f"--- Pipeline Run {run_id} completed. Computing checksums ---")
    
    checksums = {}
    for filename in FILES_TO_VERIFY:
        file_path = RESULTS_DIR / filename
        if file_path.exists():
            h = compute_file_hash(file_path)
            checksums[filename] = h
            logger.info(f"  {filename}: {h[:16]}...")
        else:
            logger.warning(f"  {filename} was not generated.")
            checksums[filename] = None

    return checksums

def compare_checksums(run1_hashes: dict, run2_hashes: dict, logger: logging.Logger) -> bool:
    """Compare checksums from two runs. Returns True if identical."""
    logger.info("--- Comparing Checksums ---")
    all_match = True
    
    for filename in FILES_TO_VERIFY:
        h1 = run1_hashes.get(filename)
        h2 = run2_hashes.get(filename)
        
        if h1 is None and h2 is None:
            logger.info(f"  {filename}: Both runs missing file (OK)")
            continue
        elif h1 is None or h2 is None:
            logger.error(f"  {filename}: Mismatch (One run missing file)")
            all_match = False
            continue
        
        if h1 == h2:
            logger.info(f"  {filename}: MATCH")
        else:
            logger.error(f"  {filename}: MISMATCH")
            logger.error(f"    Run 1: {h1}")
            logger.error(f"    Run 2: {h2}")
            all_match = False
    
    return all_match

def main():
    """Main entry point for determinism verification."""
    logger = setup_logger(VERIFICATION_LOG)
    logger.info("Starting Determinism Verification (T052)")
    logger.info(f"Seed: {SEED}, Runs: {RUNS}")
    
    try:
        # Run the pipeline twice
        hashes_run_1 = run_pipeline_run(1, logger)
        
        # Small delay to ensure file system sync
        time.sleep(1)
        
        hashes_run_2 = run_pipeline_run(2, logger)
        
        # Compare
        if compare_checksums(hashes_run_1, hashes_run_2, logger):
            logger.info("SUCCESS: All output files are deterministic across runs.")
            return 0
        else:
            logger.error("FAILURE: Output files differ between runs. Non-determinism detected.")
            return 1
            
    except Exception as e:
        logger.error(f"Verification failed with unexpected error: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())