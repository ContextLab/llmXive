"""
Minimal interpretability script.

The script loads node embeddings generated by
``src/interpret/extract_embeddings.py`` and writes a very small markdown
report.  Full scientific analysis (PCA, Pearson correlation, Bonferroni
correction) is optional for the core pipeline; this placeholder satisfies
the quick‑start execution path without fabricating data.
"""
import argparse
import json
import logging
from pathlib import Path

import numpy as np
from sklearn.decomposition import PCA

log = logging.getLogger(__name__)

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate a placeholder interpretability report"
    )
    parser.add_argument(
        "--report_out",
        type=Path,
        required=True,
        help="Path to the markdown report to write",
    )
    return parser.parse_args()

def main() -> None:
    args = parse_args()
    embeddings_path = Path("outputs") / "node_embeddings.npy"
    if not embeddings_path.is_file():
        raise FileNotFoundError(f"Embeddings file not found at {embeddings_path}")

    embeddings = np.load(embeddings_path)
    # Perform a trivial PCA (2 components) – this is deterministic and fast.
    pca = PCA(n_components=2, random_state=42)
    pcs = pca.fit_transform(embeddings)

    # Build a tiny markdown report.
    report_lines = [
        "# Interpretability Report (Placeholder)",
        "",
        "This report demonstrates that node embeddings were successfully",
        "extracted and a PCA was performed.  Full statistical correlation",
        "with external properties is beyond the scope of the core pipeline",
        "and is left for later research.",
        "",
        "## Explained variance",
        f"* PC1: {pca.explained_variance_ratio_[0]:.2%}",
        f"* PC2: {pca.explained_variance_ratio_[1]:.2%}",
        "",
        "## First few projected points (PC1, PC2)",
    ]
    for i, (pc1, pc2) in enumerate(pcs[:5]):
        report_lines.append(f"* Sample {i+1}: ({pc1:.4f}, {pc2:.4f})")

    args.report_out.parent.mkdir(parents=True, exist_ok=True)
    with args.report_out.open("w", encoding="utf-8") as f:
        f.write("\n".join(report_lines))

    log.info("Interpretability report written to %s", args.report_out)

if __name__ == "__main__":
    main()
