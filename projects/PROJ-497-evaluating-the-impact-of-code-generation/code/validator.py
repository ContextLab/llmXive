"""
Reference-Validator Agent for Code Vulnerability Analysis.

This module implements the validation logic to:
1. Select a stratified random sample of generated code (n=20 per group).
2. Apply rule-based heuristics from cwe_patterns.yaml to detect vulnerabilities.
3. Output a CSV of validation flags.
"""

import csv
import json
import logging
import os
import random
import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import pandas as pd

from config import get_paths, set_seed

# Configure logging
logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

def load_raw_vulnerability_reports() -> pd.DataFrame:
    """
    Load the raw vulnerability counts CSV generated by T013.
    Returns a DataFrame with columns: task_id, source_type, file_path, lines_of_code, vulnerability_count.
    """
    paths = get_paths()
    input_file = paths["processed"] / "raw_vulnerability_counts.csv"

    if not input_file.exists():
        raise FileNotFoundError(
            f"Required input file not found: {input_file}. "
            "Please ensure T013 (analyze.py) has been run successfully."
        )

    logger.info(f"Loading raw vulnerability reports from {input_file}")
    df = pd.read_csv(input_file)

    # Ensure required columns exist
    required_cols = ["task_id", "source_type", "file_path", "lines_of_code", "vulnerability_count"]
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in {input_file}: {missing_cols}")

    return df

def load_generated_samples_metadata() -> pd.DataFrame:
    """
    Load metadata about generated samples to map file paths to sample IDs.
    This assumes a structure where samples are stored in data/generated/{model}/{benchmark}/{task_id}/samples/
    and we need to correlate them with the vulnerability reports.
    
    Since we don't have a separate metadata file, we will derive sample IDs from the file paths
    in the vulnerability report. The sample_id will be constructed as:
    "{source_type}_{task_id}_{file_basename}"
    """
    logger.info("Deriving sample metadata from file paths in vulnerability reports.")
    # This is a helper that returns the dataframe from load_raw_vulnerability_reports
    # but we separate the logic for clarity.
    return load_raw_vulnerability_reports()

def load_cwe_patterns() -> Dict[str, re.Pattern]:
    """
    Load CWE ID to regex pattern mapping from code/config/cwe_patterns.yaml.
    Returns a dictionary mapping CWE IDs to compiled regex patterns.
    """
    paths = get_paths()
    config_file = paths["config"] / "cwe_patterns.yaml"

    if not config_file.exists():
        raise FileNotFoundError(f"CWE patterns config not found: {config_file}")

    logger.info(f"Loading CWE patterns from {config_file}")
    with open(config_file, "r") as f:
        import yaml
        patterns_dict = yaml.safe_load(f)

    compiled_patterns = {}
    for cwe_id, pattern_str in patterns_dict.items():
        try:
            # Compile with case-insensitive and multiline flags
            compiled_patterns[cwe_id] = re.compile(pattern_str, re.IGNORECASE | re.MULTILINE)
            logger.debug(f"Compiled pattern for {cwe_id}: {pattern_str}")
        except re.error as e:
            logger.error(f"Invalid regex pattern for {cwe_id}: {pattern_str}. Error: {e}")
            raise

    return compiled_patterns

def select_stratified_subset(
    df: pd.DataFrame,
    sample_size: int = 20,
    seed: int = 42
) -> pd.DataFrame:
    """
    Select a stratified random sample of n=20 per group (source_type).
    
    Args:
        df: DataFrame with vulnerability reports.
        sample_size: Number of samples to select per group.
        seed: Random seed for reproducibility.
        
    Returns:
        DataFrame containing the stratified subset.
    """
    set_seed(seed)
    logger.info(f"Selecting stratified subset: {sample_size} samples per source_type group.")
    
    groups = df["source_type"].unique()
    logger.info(f"Found source types: {groups}")
    
    sampled_dfs = []
    
    for group in groups:
        group_df = df[df["source_type"] == group]
        group_size = len(group_df)
        
        if group_size < sample_size:
            logger.warning(
                f"Group '{group}' has only {group_size} samples, "
                f"which is less than the requested sample size {sample_size}. "
                f"Taking all {group_size} samples."
            )
            sampled_dfs.append(group_df)
        else:
            # Stratified random sample
            sampled_group = group_df.sample(n=sample_size, random_state=seed)
            sampled_dfs.append(sampled_group)
            logger.info(f"Selected {sample_size} samples from group '{group}'.")
    
    result_df = pd.concat(sampled_dfs, ignore_index=True)
    logger.info(f"Total samples selected: {len(result_df)}")
    
    return result_df

def check_code_patterns(
    file_path: str,
    patterns: Dict[str, re.Pattern]
) -> List[Tuple[str, bool]]:
    """
    Check a code file against the compiled CWE patterns.
    
    Args:
        file_path: Path to the code file to check.
        patterns: Dictionary of compiled regex patterns.
        
    Returns:
        List of tuples (cwe_id, is_match) for each pattern.
    """
    if not os.path.exists(file_path):
        logger.warning(f"File not found for pattern matching: {file_path}")
        return [(cwe_id, False) for cwe_id in patterns.keys()]
    
    try:
        with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
            code_content = f.read()
    except Exception as e:
        logger.error(f"Error reading file {file_path}: {e}")
        return [(cwe_id, False) for cwe_id in patterns.keys()]
    
    results = []
    for cwe_id, pattern in patterns.items():
        is_match = bool(pattern.search(code_content))
        results.append((cwe_id, is_match))
        
    return results

def validate_vulnerabilities(
    sample_df: pd.DataFrame,
    patterns: Dict[str, re.Pattern]
) -> pd.DataFrame:
    """
    Validate vulnerabilities for the selected sample using rule-based heuristics.
    
    Args:
        sample_df: DataFrame containing the stratified sample.
        patterns: Compiled CWE patterns.
        
    Returns:
        DataFrame with columns: sample_id, is_valid, matched_cwes.
    """
    logger.info("Starting vulnerability validation on selected sample.")
    
    validation_results = []
    
    for idx, row in sample_df.iterrows():
        file_path = row["file_path"]
        task_id = row["task_id"]
        source_type = row["source_type"]
        
        # Construct sample_id
        file_basename = os.path.basename(file_path)
        sample_id = f"{source_type}_{task_id}_{file_basename}"
        
        # Check code patterns
        pattern_matches = check_code_patterns(file_path, patterns)
        
        # Determine if any pattern matched (indicating a potential vulnerability)
        # is_valid = True if NO vulnerabilities detected (clean code)
        # is_valid = False if ANY vulnerability detected
        has_vulnerability = any(match for _, match in pattern_matches)
        is_valid = not has_vulnerability
        
        matched_cwes = [cwe for cwe, match in pattern_matches if match]
        
        validation_results.append({
            "sample_id": sample_id,
            "is_valid": is_valid,
            "matched_cwes": ",".join(matched_cwes) if matched_cwes else ""
        })
        
    result_df = pd.DataFrame(validation_results)
    logger.info(f"Validation complete. Processed {len(result_df)} samples.")
    
    return result_df

def save_validation_results(df: pd.DataFrame) -> Path:
    """
    Save the validation results to data/processed/validator_flags.csv.
    
    Args:
        df: DataFrame with validation results.
        
    Returns:
        Path to the saved file.
    """
    paths = get_paths()
    output_file = paths["processed"] / "validator_flags.csv"
    
    # Ensure output directory exists
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    # Select only the required columns for the final output
    output_df = df[["sample_id", "is_valid"]]
    
    logger.info(f"Saving validation results to {output_file}")
    output_df.to_csv(output_file, index=False)
    
    return output_file

def main():
    """
    Main entry point for the Reference-Validator Agent.
    """
    logger.info("Starting Reference-Validator Agent (T022)")
    
    try:
        # 1. Load raw vulnerability reports (input data)
        raw_reports_df = load_raw_vulnerability_reports()
        
        # 2. Load CWE patterns
        cwe_patterns = load_cwe_patterns()
        
        # 3. Select stratified subset (n=20 per group)
        # Note: If the dataset has fewer than 20 items in a group, it takes all available.
        sample_df = select_stratified_subset(raw_reports_df, sample_size=20, seed=42)
        
        # 4. Validate vulnerabilities using rule-based heuristics
        validation_df = validate_vulnerabilities(sample_df, cwe_patterns)
        
        # 5. Save results
        output_path = save_validation_results(validation_df)
        
        logger.info(f"T022 Completed successfully. Output: {output_path}")
        print(f"Validation complete. Results saved to {output_path}")
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        raise
    except Exception as e:
        logger.error(f"An error occurred during validation: {e}")
        raise

if __name__ == "__main__":
    main()
