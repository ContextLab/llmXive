def load_aggregated_data(data_path: Path) -> pd.DataFrame:
    """
    Load the aggregated analysis dataset.
    Expects columns: task_id, source_type, mean_vuln_count, lines_of_code, etc.
    """
    if not data_path.exists():
        raise FileNotFoundError(f"Aggregated data file not found: {data_path}")
    
    df = pd.read_csv(data_path)
    logger.info(f"Loaded {len(df)} rows from {data_path}")
    return df

def prepare_boxplot_data(df: pd.DataFrame) -> pd.DataFrame:
    """
    Prepare data for boxplot visualization.
    Filters out rows with missing source_type or vulnerability counts.
    """
    # Ensure numeric types
    if 'mean_vuln_count' in df.columns:
        df['mean_vuln_count'] = pd.to_numeric(df['mean_vuln_count'], errors='coerce')
    elif 'vulnerability_count' in df.columns:
        df['vulnerability_count'] = pd.to_numeric(df['vulnerability_count'], errors='coerce')
    
    # Select appropriate count column
    count_col = 'mean_vuln_count' if 'mean_vuln_count' in df.columns else 'vulnerability_count'
    
    # Filter valid data
    valid_df = df.dropna(subset=[count_col, 'source_type'])
    valid_df = valid_df[valid_df['source_type'].isin(['LLM', 'Human'])]
    
    if valid_df.empty:
        logger.warning("No valid data found for boxplot after filtering.")
        return pd.DataFrame()
    
    return valid_df

def generate_boxplot(df: pd.DataFrame, output_path: Path, title: str = "Vulnerability Density Comparison"):
    """
    Generate a boxplot comparing LLM vs. Human vulnerability counts.
    """
    if df.empty:
        logger.error("Cannot generate boxplot: empty dataframe.")
        return

    count_col = 'mean_vuln_count' if 'mean_vuln_count' in df.columns else 'vulnerability_count'
    
    plt.figure(figsize=(10, 6))
    sns.set_style("whitegrid")
    
    # Create boxplot
    sns.boxplot(
        x='source_type',
        y=count_col,
        data=df,
        palette={'LLM': '#3498db', 'Human': '#e74c3c'},
        linewidth=2
    )
    
    plt.title(title, fontsize=16, fontweight='bold')
    plt.xlabel("Source Type", fontsize=12)
    plt.ylabel("Vulnerability Count", fontsize=12)
    plt.xticks(fontsize=10)
    plt.yticks(fontsize=10)
    
    # Add jittered strip plot to show distribution density
    sns.stripplot(
        x='source_type',
        y=count_col,
        data=df,
        color='black',
        size=4,
        alpha=0.3,
        jitter=True,
        linewidth=0.5
    )
    
    # Save plot
    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()
    
    logger.info(f"Boxplot saved to {output_path}")

def load_vulnerability_reports(report_path: Path) -> pd.DataFrame:
    """
    Load the vulnerability reports JSON generated by analyze.py.
    Expects columns: file_path, cwe_id, severity, line_number.
    """
    if not report_path.exists():
        raise FileNotFoundError(f"Vulnerability reports file not found: {report_path}")
    
    with open(report_path, 'r') as f:
        data = json.load(f)
    
    if not data:
        logger.warning("Vulnerability reports file is empty.")
        return pd.DataFrame()
    
    df = pd.DataFrame(data)
    logger.info(f"Loaded {len(df)} vulnerability records from {report_path}")
    return df

def prepare_bar_chart_data(df: pd.DataFrame) -> pd.DataFrame:
    """
    Prepare data for bar chart visualization.
    Aggregates vulnerability counts by CWE ID and Source Type.
    Filters to top 5 most frequent CWEs per source.
    """
    if df.empty:
        return pd.DataFrame()

    # Ensure we have the necessary columns
    required_cols = ['cwe_id', 'severity']
    # We need to infer source_type from file_path if not present
    # Assuming file_path contains 'LLM' or 'Human' or 'generated' vs 'human'
    
    # Extract source type from file_path
    if 'file_path' in df.columns:
        def infer_source(path_str):
            if pd.isna(path_str):
                return 'Unknown'
            path_lower = str(path_str).lower()
            if 'generated' in path_lower or 'llm' in path_lower:
                return 'LLM'
            elif 'human' in path_lower:
                return 'Human'
            return 'Unknown'
        
        df['source_type'] = df['file_path'].apply(infer_source)
    
    if 'source_type' not in df.columns:
        logger.error("Could not infer source_type from file_path. Column missing or malformed.")
        return pd.DataFrame()

    # Filter valid sources
    valid_df = df[df['source_type'].isin(['LLM', 'Human'])].copy()
    
    if valid_df.empty:
        logger.warning("No valid source types found in vulnerability reports.")
        return pd.DataFrame()

    # Aggregate counts by CWE and Source
    agg_df = valid_df.groupby(['source_type', 'cwe_id']).size().reset_index(name='count')
    
    # Get top 5 CWEs per source type
    top_cwes = []
    for source in ['LLM', 'Human']:
        source_df = agg_df[agg_df['source_type'] == source]
        if source_df.empty:
            continue
        top_5 = source_df.nlargest(5, 'count')
        top_5['rank'] = range(1, len(top_5) + 1)
        top_cwes.append(top_5)
    
    if not top_cwes:
        logger.warning("No CWE data found for bar chart.")
        return pd.DataFrame()
    
    result_df = pd.concat(top_cwes, ignore_index=True)
    
    # Sort for plotting: LLM first, then Human, or by rank?
    # Let's sort by source then rank to group them logically
    result_df = result_df.sort_values(by=['source_type', 'rank'])
    
    return result_df

def generate_bar_chart(df: pd.DataFrame, output_path: Path, title: str = "Top 5 Vulnerability Types by Source"):
    """
    Generate a bar chart for top 5 vulnerability types (CWE) by frequency per source.
    """
    if df.empty:
        logger.error("Cannot generate bar chart: empty dataframe.")
        return

    plt.figure(figsize=(12, 8))
    sns.set_style("whitegrid")
    
    # Plot grouped bar chart
    # We need to pivot or use catplot for grouped bars, but standard barplot with hue works
    # Ensure cwe_id is categorical to maintain order if needed, but here we just want top 5
    
    # Create a custom order for x-axis to interleave LLM and Human for same CWE?
    # Or just group by source? The requirement says "per source", so grouped by source is clearer.
    # Let's do: X = CWE, Hue = Source, but only for top 5 global? 
    # The task says "top 5 vulnerability types by frequency per source".
    # This implies we might have different top 5 for LLM and Human.
    # To visualize this cleanly, we can do two subplots or a grouped bar where we only show the union of top 5s.
    
    # Strategy: Show the union of top 5 CWEs from both sources.
    # If a CWE is in top 5 for LLM but not Human, its bar for Human will be 0 (or missing).
    
    # Get union of CWEs
    all_cwes = df['cwe_id'].unique()
    if len(all_cwes) == 0:
        return

    # Filter df to only these CWEs
    plot_df = df[df['cwe_id'].isin(all_cwes)]
    
    # Pivot for plotting if needed, or use catplot
    # Using barplot with hue
    sns.barplot(
        data=plot_df,
        x='cwe_id',
        y='count',
        hue='source_type',
        palette={'LLM': '#3498db', 'Human': '#e74c3c'},
        edgecolor='black'
    )
    
    plt.title(title, fontsize=16, fontweight='bold')
    plt.xlabel("CWE ID", fontsize=12)
    plt.ylabel("Frequency", fontsize=12)
    plt.xticks(rotation=45, ha='right')
    plt.legend(title="Source Type")
    
    # Save plot
    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()
    
    logger.info(f"Bar chart saved to {output_path}")

def main():
    """
    Main entry point for visualization generation.
    Reads aggregated data and vulnerability reports to generate boxplots and bar charts.
    """
    # Set random seed for reproducibility
    set_seed(42)
    
    # Get paths
    paths = get_paths()
    input_data_path = paths['data_processed'] / 'aggregated_analysis_dataset.csv'
    input_vuln_reports_path = paths['data_processed'] / 'vulnerability_reports.json'
    output_figures_dir = paths['results'] / 'figures'
    
    # Ensure output directory exists
    output_figures_dir.mkdir(parents=True, exist_ok=True)
    
    try:
        # 1. Generate Boxplot (existing functionality)
        if input_data_path.exists():
            df = load_aggregated_data(input_data_path)
            
            if not df.empty:
                plot_df = prepare_boxplot_data(df)
                
                if not plot_df.empty:
                    boxplot_path = output_figures_dir / 'vulnerability_boxplot.png'
                    generate_boxplot(plot_df, boxplot_path, title="LLM vs. Human Vulnerability Density")
                else:
                    logger.warning("No valid data for boxplot.")
            else:
                logger.warning("Aggregated data is empty. Skipping boxplot.")
        else:
            logger.warning(f"Aggregated data file not found: {input_data_path}. Skipping boxplot.")
        
        # 2. Generate Bar Chart (New functionality for T031)
        if input_vuln_reports_path.exists():
            vuln_df = load_vulnerability_reports(input_vuln_reports_path)
            
            if not vuln_df.empty:
                bar_df = prepare_bar_chart_data(vuln_df)
                
                if not bar_df.empty:
                    bar_chart_path = output_figures_dir / 'top_vulnerability_types_bar_chart.png'
                    generate_bar_chart(bar_df, bar_chart_path, title="Top 5 Vulnerability Types by Frequency per Source")
                else:
                    logger.warning("No valid data for bar chart.")
            else:
                logger.warning("Vulnerability reports are empty. Skipping bar chart.")
        else:
            logger.warning(f"Vulnerability reports file not found: {input_vuln_reports_path}. Skipping bar chart.")
        
        logger.info("Visualization generation completed.")
        
    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        raise
    except Exception as e:
        logger.error(f"Error during visualization generation: {e}")
        raise

if __name__ == '__main__':
    main()