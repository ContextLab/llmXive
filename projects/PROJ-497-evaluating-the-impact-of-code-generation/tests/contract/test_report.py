    def test_report_file_exists(self):
        """Contract: Report file must exist after generation."""
        # Note: This test assumes report.py has been run to generate the file.
        # In a real CI/CD pipeline, the report generation step would run before this test.
        report_path = RESULTS_DIR / "summary.md"
        
        # If the file doesn't exist, we check if the report generation script exists
        # and can be run to generate it
        if not report_path.exists():
            report_script = PROJECT_ROOT / "code" / "report.py"
            assert report_script.exists(), (
                "Report script code/report.py does not exist. "
                "Run the report generation script first."
            )
            # For this contract test, we expect the file to exist
            # If it doesn't, the test fails (contract not met)
            pytest.fail("Report file results/summary.md does not exist. "
                        "Ensure code/report.py has been executed to generate the report.")

