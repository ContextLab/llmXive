    def test_report_uses_processed_data_only(self):
        """Contract: Report must reference data exclusively from data/processed."""
        report_path = RESULTS_DIR / "summary.md"
        assert report_path.exists(), "Report file not found"

        with open(report_path, 'r', encoding='utf-8') as f:
            content = f.read()

        # Check that the report mentions or references data/processed
        # This is a soft contract - the report should indicate it's based on processed data
        processed_references = [
            "data/processed",
            "processed data",
            "aggregated analysis"
        ]

        found = False
        for ref in processed_references:
            if ref.lower() in content.lower():
                found = True
                break

        # This is a soft check - if the report doesn't explicitly mention the path,
        # it's still valid as long as it doesn't reference raw data
        # We check that it doesn't reference raw/unprocessed data
        raw_data_patterns = [
            r"data/raw",
            r"raw data",
            r"bandit_raw",
            r"vulnerability_reports\.json"
        ]

        raw_found = False
        for pattern in raw_data_patterns:
            if re.search(pattern, content, re.IGNORECASE):
                raw_found = True
                break

        assert not raw_found, (
            "Report should not reference raw/unprocessed data files directly"
        )

