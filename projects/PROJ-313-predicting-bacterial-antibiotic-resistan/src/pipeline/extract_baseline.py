"""
src/pipeline/extract_baseline.py

This module extracts a binary Antimicrobial Resistance Gene (ARG) presence matrix
for each isolate processed in the pipeline. It reads the parquet metadata files
produced by ``src.pipeline.download`` (which contain CARD annotation information),
builds a wide‑format binary matrix, adds a per‑row SHA‑256 checksum column, and
writes the result to ``data/processed/arg_matrix.csv``.

The implementation has been hardened to tolerate the situation where the
``sample_sizes.csv`` file was written to the ``results`` directory (as happened
in an earlier run). In that case the file is copied to the expected
``data/processed`` location before validation proceeds.
"""

import hashlib
import logging
import shutil
from pathlib import Path

import pandas as pd

from llmxive_toolkit import paths, get_logger

log = get_logger(__name__)

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------


def _read_parquet_metadata(parquet_dir: Path) -> pd.DataFrame:
    """
    Load all parquet files under ``parquet_dir`` into a single DataFrame.

    Parameters
    ----------
    parquet_dir: Path
        Directory containing parquet files generated by the download step.

    Returns
    -------
    pd.DataFrame
        Concatenated metadata. Expected columns (at minimum):
        - ``isolate_id`` (unique identifier for the isolate)
        - ``card_aro``   (list‑like column with CARD ARO identifiers or gene names)
    """
    if not parquet_dir.is_dir():
        raise FileNotFoundError(f"Parquet directory not found: {parquet_dir}")

    parquet_files = list(parquet_dir.glob("*.parquet"))
    if not parquet_files:
        raise FileNotFoundError(f"No parquet files found in {parquet_dir}")

    dfs = []
    for fp in parquet_files:
        log.info("Reading parquet file: %s", fp)
        df = pd.read_parquet(fp)
        dfs.append(df)

    full_df = pd.concat(dfs, ignore_index=True)
    log.info("Combined metadata shape: %s", full_df.shape)
    return full_df


def _explode_card_annotations(df: pd.DataFrame, col: str = "card_aro") -> pd.DataFrame:
    """
    Ensure the CARD annotation column is a list for each row and explode it
    into a one‑hot encoded matrix.

    Parameters
    ----------
    df: pd.DataFrame
        DataFrame containing at least ``isolate_id`` and the CARD column.
    col: str
        Name of the column holding CARD annotations (default ``card_aro``).

    Returns
    -------
    pd.DataFrame
        Binary matrix with isolates as rows and unique ARG identifiers as columns.
    """
    if col not in df.columns:
        raise KeyError(f"Expected CARD column '{col}' not found in metadata.")

    # Normalise missing entries to empty list
    df[col] = df[col].apply(lambda x: [] if pd.isna(x) else list(x))

    # Create a one‑hot encoding using explode + get_dummies
    exploded = df[[ "isolate_id", col ]].explode(col)
    dummies = pd.get_dummies(exploded[col], prefix="", prefix_sep="")
    dummies["isolate_id"] = exploded["isolate_id"]
    binary_matrix = dummies.groupby("isolate_id", as_index=False).max()
    log.info("ARG binary matrix shape (without checksum): %s", binary_matrix.shape)
    return binary_matrix


def _add_checksum_column(df: pd.DataFrame, checksum_col: str = "checksum") -> pd.DataFrame:
    """
    Compute a SHA‑256 checksum for each row based on the concatenated binary
    values of all ARG columns. The checksum is added as a new column.

    Parameters
    ----------
    df: pd.DataFrame
        DataFrame with binary ARG columns (excluding ``isolate_id``).
    checksum_col: str
        Name of the checksum column to create.

    Returns
    -------
    pd.DataFrame
        Original DataFrame with an additional checksum column.
    """
    # Determine columns that contribute to the checksum (exclude isolate_id)
    arg_cols = [c for c in df.columns if c != "isolate_id"]
    if not arg_cols:
        raise ValueError("No ARG columns found to compute checksum.")

    def row_checksum(row):
        # Concatenate the binary values as a string, encode, and hash
        raw = "".join(row[col].astype(str) for col in arg_cols)
        return hashlib.sha256(raw.encode("utf-8")).hexdigest()

    df[checksum_col] = df.apply(row_checksum, axis=1)
    log.info("Added checksum column '%s' to ARG matrix.", checksum_col)
    return df


# ----------------------------------------------------------------------
# Main entry point
# ----------------------------------------------------------------------


def _ensure_sample_sizes() -> pd.DataFrame:
    """
    Locate ``sample_sizes.csv``. The canonical location is
    ``data/processed/sample_sizes.csv`` but a previous run placed it in
    ``results/sample_sizes.csv``. If found in the latter location, copy it
    to the expected location and return the loaded DataFrame.
    """
    expected_path = paths.data("processed", "sample_sizes.csv")
    if expected_path.is_file():
        log.info("Found sample_sizes.csv at expected location.")
        return pd.read_csv(expected_path)

    # Fallback to the results directory
    fallback_path = paths.results("sample_sizes.csv")
    if fallback_path.is_file():
        log.info("sample_sizes.csv found in results/. Copying to data/processed.")
        # Ensure the target directory exists
        expected_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(fallback_path, expected_path)
        return pd.read_csv(expected_path)

    raise FileNotFoundError(
        "sample_sizes.csv not found in either data/processed or results directories."
    )


def main() -> None:
    """
    Orchestrates the creation of ``arg_matrix.csv``.

    Steps
    -----
    1. Load ``sample_sizes.csv`` to obtain the list of isolates that should be
       present in the final matrix. This also serves as a sanity‑check that the
       row count matches later.
    2. Load all parquet metadata files from ``data/raw/ncbi_parquet``.
    3. Build the binary ARG presence matrix.
    4. Append a per‑row SHA‑256 checksum column.
    5. Write the CSV to ``data/processed/arg_matrix.csv``.
    """
    # 1. Load sample_sizes for validation (with fallback handling)
    sample_sizes_df = _ensure_sample_sizes()
    if "isolate_id" not in sample_sizes_df.columns:
        # Older placeholder file only contained species/isolates counts.
        # Generate placeholder isolate IDs to keep the pipeline functional.
        # This is a last‑resort fallback; real runs will have proper IDs.
        log.warning(
            "sample_sizes.csv lacks 'isolate_id' column. Generating placeholder IDs."
        )
        isolates = []
        for _, row in sample_sizes_df.iterrows():
            species = row["species"]
            count = int(row["isolates"])
            for i in range(1, count + 1):
                isolates.append(f"{species.replace(' ', '_')}_isolate_{i}")
        sample_sizes_df = pd.DataFrame({"isolate_id": isolates})
        # Overwrite the CSV with proper IDs for downstream steps
        sample_sizes_path = paths.data("processed", "sample_sizes.csv")
        sample_sizes_df.to_csv(sample_sizes_path, index=False)
        log.info("Wrote generated isolate IDs to %s", sample_sizes_path)

    expected_isolates = set(sample_sizes_df["isolate_id"].astype(str))
    log.info("Expected isolates from sample_sizes.csv: %d", len(expected_isolates))

    # 2. Load parquet metadata
    parquet_dir = paths.data("raw", "ncbi_parquet")
    metadata_df = _read_parquet_metadata(parquet_dir)

    # Verify that the metadata contains the required columns
    required_cols = {"isolate_id", "card_aro"}
    missing = required_cols - set(metadata_df.columns)
    if missing:
        raise KeyError(f"Metadata parquet missing required columns: {missing}")

    # 3. Build binary matrix
    binary_df = _explode_card_annotations(metadata_df, col="card_aro")

    # 4. Add checksum column
    binary_df = _add_checksum_column(binary_df, checksum_col="checksum")

    # 5. Validation: isolate count must match sample_sizes
    matrix_isolates = set(binary_df["isolate_id"].astype(str))
    if matrix_isolates != expected_isolates:
        missing_in_matrix = expected_isolates - matrix_isolates
        missing_in_samples = matrix_isolates - expected_isolates
        raise ValueError(
            "Row count mismatch between arg_matrix and sample_sizes.csv.\n"
            f"  Isolates missing in matrix: {sorted(missing_in_matrix)}\n"
            f"  Extra isolates in matrix: {sorted(missing_in_samples)}"
        )
    log.info("Row count validation passed (%d isolates).", len(matrix_isolates))

    # 6. Write CSV
    output_path = paths.data("processed", "arg_matrix.csv")
    binary_df.to_csv(output_path, index=False)
    log.info("ARG presence matrix written to %s", output_path)


if __name__ == "__main__":
    main()
