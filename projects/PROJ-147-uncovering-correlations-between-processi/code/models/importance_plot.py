"""
T022: Implement importance_plot.png generation with ranked feature list.

Generates a bar chart visualizing feature importance from the RandomForest model,
sorted by importance value in descending order. Saves the output to data/figures/importance_plot.png.
"""
import os
import json
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from pathlib import Path
from typing import Dict, List, Optional, Any

# Import existing names from sibling modules
from models.importance import rank_features_by_importance, load_model_predictions
from config import ensure_dirs
from utils.logging import get_logger

logger = get_logger(__name__)


def load_importance_data(importance_json_path: str) -> pd.DataFrame:
    """
    Load feature importance data from the JSON report generated by T021.
    
    Args:
        importance_json_path: Path to the importance report JSON file.
        
    Returns:
        DataFrame with columns ['feature', 'importance', 'rank'].
    """
    path = Path(importance_json_path)
    if not path.exists():
        raise FileNotFoundError(f"Importance report not found at {path}")
        
    with open(path, 'r') as f:
        data = json.load(f)
        
    # Expected structure from T021: {"importances": [{"feature": ..., "importance": ...}, ...]}
    if "importances" not in data:
        raise ValueError(f"Invalid importance report format at {path}: missing 'importances' key")
        
    df = pd.DataFrame(data["importances"])
    if "feature" not in df.columns or "importance" not in df.columns:
        raise ValueError(f"Invalid importance report format at {path}: missing required columns")
        
    # Sort by importance descending and assign rank
    df = df.sort_values(by="importance", ascending=False).reset_index(drop=True)
    df["rank"] = df.index + 1
    
    return df


def plot_importance_ranking(
    df: pd.DataFrame,
    output_path: str,
    title: str = "Feature Importance Ranking",
    max_features: Optional[int] = None
) -> None:
    """
    Generate and save the importance ranking bar chart.
    
    Args:
        df: DataFrame with 'feature', 'importance', and 'rank' columns.
        output_path: Full path where the PNG file will be saved.
        title: Chart title.
        max_features: Maximum number of top features to plot (None for all).
    """
    if df.empty:
        raise ValueError("Cannot plot importance ranking: DataFrame is empty")
        
    # Limit features if requested
    if max_features is not None and max_features < len(df):
        df_plot = df.head(max_features)
        logger.info(f"Plotting top {max_features} features out of {len(df)} total")
    else:
        df_plot = df
        
    # Create figure
    fig, ax = plt.subplots(figsize=(10, 6))
    
    # Create bar chart
    bars = ax.barh(
        range(len(df_plot)),
        df_plot["importance"],
        color=plt.cm.viridis(np.linspace(0.2, 0.8, len(df_plot))),
        edgecolor='black'
    )
    
    # Set y-ticks and labels (feature names)
    ax.set_yticks(range(len(df_plot)))
    ax.set_yticklabels(df_plot["feature"], fontsize=9)
    
    # Set x-label
    ax.set_xlabel("Importance Score", fontsize=10)
    ax.set_title(title, fontsize=12, fontweight='bold')
    
    # Add rank labels on the bars
    for i, (idx, row) in enumerate(df_plot.iterrows()):
        ax.text(
            row["importance"] + max(df_plot["importance"]) * 0.01,
            i,
            f"#{int(row['rank'])}",
            va='center',
            fontsize=8,
            fontweight='bold'
        )
        
    # Invert y-axis so highest importance is at the top
    ax.invert_yaxis()
    
    # Add grid for readability
    ax.grid(axis='x', alpha=0.3)
    
    # Tight layout to prevent label clipping
    plt.tight_layout()
    
    # Save figure
    plt.savefig(output_path, dpi=150, bbox_inches='tight', facecolor='white')
    plt.close(fig)
    
    # Verify file size constraint (≤5 MB)
    file_size = os.path.getsize(output_path)
    size_mb = file_size / (1024 * 1024)
    if size_mb > 5:
        logger.warning(f"Generated plot exceeds 5MB limit: {size_mb:.2f} MB")
    else:
        logger.info(f"Successfully generated importance plot: {output_path} ({size_mb:.2f} MB)")


def run_importance_plot_generation(
    importance_json_path: str,
    output_dir: Optional[str] = None,
    filename: str = "importance_plot.png",
    max_features: Optional[int] = None
) -> str:
    """
    Main entry point to generate the importance plot.
    
    Args:
        importance_json_path: Path to the JSON report from T021.
        output_dir: Directory to save the plot (defaults to 'data/figures').
        filename: Output filename.
        max_features: Optional limit on number of features to plot.
        
    Returns:
        Absolute path to the generated PNG file.
    """
    # Ensure output directory exists
    if output_dir is None:
        output_dir = "data/figures"
        
    ensure_dirs([output_dir])
    output_path = str(Path(output_dir) / filename)
    
    logger.info(f"Generating importance plot from {importance_json_path}")
    
    # Load data
    df = load_importance_data(importance_json_path)
    
    # Generate plot
    plot_importance_ranking(
        df=df,
        output_path=output_path,
        title="Feature Importance Ranking (RandomForest)",
        max_features=max_features
    )
    
    return output_path


def main():
    """
    CLI entry point for T022.
    Expects the importance report from T021 at data/reports/importance_report.json.
    """
    import argparse
    
    parser = argparse.ArgumentParser(description="Generate feature importance plot")
    parser.add_argument(
        "--input",
        type=str,
        default="data/reports/importance_report.json",
        help="Path to importance report JSON"
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="data/figures",
        help="Output directory for the plot"
    )
    parser.add_argument(
        "--output-filename",
        type=str,
        default="importance_plot.png",
        help="Output filename"
    )
    parser.add_argument(
        "--max-features",
        type=int,
        default=None,
        help="Maximum number of features to plot"
    )
    
    args = parser.parse_args()
    
    try:
        output_path = run_importance_plot_generation(
            importance_json_path=args.input,
            output_dir=args.output_dir,
            filename=args.output_filename,
            max_features=args.max_features
        )
        print(f"SUCCESS: Importance plot generated at {output_path}")
    except Exception as e:
        logger.error(f"Failed to generate importance plot: {e}")
        raise


if __name__ == "__main__":
    main()