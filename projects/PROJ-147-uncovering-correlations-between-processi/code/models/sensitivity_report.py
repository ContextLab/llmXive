"""
Sensitivity Analysis Module for T025.

Generates sensitivity_report.json by sweeping R² and importance thresholds
from 0.01 to 0.50 in steps of 0.01.
"""
import os
import json
import pandas as pd
import numpy as np
from pathlib import Path
from typing import Dict, List, Any, Optional
from datetime import datetime

# Import from existing API surface
from code.models.evaluator import load_model_predictions, compute_metrics_per_texture
from code.models.importance import load_importance_data
from code.utils.logging import get_logger
from code.config import ensure_dirs

logger = get_logger(__name__)

# Constants for the sweep
THRESHOLD_START = 0.01
THRESHOLD_END = 0.50
THRESHOLD_STEP = 0.01

def load_evaluation_metrics() -> Optional[Dict[str, Any]]:
    """
    Load evaluation metrics from the existing evaluation report.
    Tries to load from data/processed/evaluation_report.json.
    """
    report_path = Path("data/processed/evaluation_report.json")
    if not report_path.exists():
        logger.error(f"Evaluation report not found at {report_path}. Cannot run sensitivity analysis.")
        return None
    
    try:
        with open(report_path, 'r') as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse evaluation report: {e}")
        return None

def load_importance_scores() -> Optional[pd.DataFrame]:
    """
    Load feature importance data.
    Tries to load from data/processed/importance_scores.csv (if generated by T021/T022).
    Falls back to computing from the model if available, but primarily relies on saved data.
    """
    # Check if importance data exists from previous steps
    importance_path = Path("data/processed/importance_scores.csv")
    if importance_path.exists():
        try:
            df = pd.read_csv(importance_path)
            logger.info(f"Loaded importance scores from {importance_path}")
            return df
        except Exception as e:
            logger.warning(f"Failed to load importance scores from file: {e}")
    
    # If not found, we might need to re-calculate or return None
    # For this task, we assume the importance data is available from T021/T022
    # If not, we return None and the report will reflect missing data
    logger.warning("Importance scores not found. Sensitivity analysis on importance thresholds may be limited.")
    return None

def run_sensitivity_analysis() -> Dict[str, Any]:
    """
    Perform the sensitivity sweep:
    - Sweep R² threshold from 0.01 to 0.50 (step 0.01)
    - Sweep Importance threshold from 0.01 to 0.50 (step 0.01)
    - Record stability metrics (e.g., number of features passing, model stability proxy)
    
    Returns a dictionary suitable for serialization to JSON.
    """
    logger.info("Starting sensitivity analysis sweep...")
    
    # Load base metrics
    eval_metrics = load_evaluation_metrics()
    importance_df = load_importance_scores()
    
    if not eval_metrics:
        logger.error("Cannot proceed without evaluation metrics.")
        return {"error": "Evaluation metrics not found"}
    
    # Initialize report structure
    report = {
        "metadata": {
            "generated_at": datetime.now().isoformat(),
            "task_id": "T025",
            "description": "Sensitivity analysis of R² and importance thresholds",
            "threshold_range": {
                "start": THRESHOLD_START,
                "end": THRESHOLD_END,
                "step": THRESHOLD_STEP
            }
        },
        "r2_sweep": [],
        "importance_sweep": [],
        "combined_sweep": [],
        "summary": {}
    }
    
    # --- R² Sweep ---
    # We simulate the stability by checking how many alloy families would pass
    # the threshold based on the existing metrics in eval_metrics.
    # Since we don't have the full distribution, we use the per-family metrics
    # to estimate stability.
    
    r2_thresholds = np.arange(THRESHOLD_START, THRESHOLD_END + 1e-9, THRESHOLD_STEP)
    r2_results = []
    
    # Extract per-family metrics if available
    per_family_metrics = eval_metrics.get("metrics_per_family", {})
    # Fallback if structure is different
    if not per_family_metrics and "per_family" in eval_metrics:
        per_family_metrics = eval_metrics["per_family"]
    
    for thresh in r2_thresholds:
        # Count how many families would meet this R² threshold
        passing_families = 0
        total_families = 0
        
        for family, metrics in per_family_metrics.items():
            total_families += 1
            # Check R² for this family (assuming 'r2' key exists)
            r2_val = metrics.get("r2", metrics.get("R2", 0))
            if r2_val >= thresh:
                passing_families += 1
        
        stability_ratio = passing_families / total_families if total_families > 0 else 0.0
        
        r2_results.append({
            "threshold": round(thresh, 2),
            "passing_families": passing_families,
            "total_families": total_families,
            "stability_ratio": round(stability_ratio, 4)
        })
    
    report["r2_sweep"] = r2_results
    
    # --- Importance Sweep ---
    importance_results = []
    
    if importance_df is not None and not importance_df.empty:
        # Assume the importance dataframe has a column 'importance' or 'score'
        imp_col = None
        for col in ['importance', 'score', 'mean_importance']:
            if col in importance_df.columns:
                imp_col = col
                break
        
        if imp_col:
            for thresh in r2_thresholds: # Reuse the same thresholds for simplicity
                # Count features above threshold
                passing_features = (importance_df[imp_col] >= thresh).sum()
                total_features = len(importance_df)
                
                importance_results.append({
                    "threshold": round(thresh, 2),
                    "passing_features": int(passing_features),
                    "total_features": total_features,
                    "retention_ratio": round(passing_features / total_features, 4) if total_features > 0 else 0.0
                })
        else:
            logger.warning("Could not find importance score column in dataframe.")
    else:
        logger.warning("No importance data available for importance sweep.")
    
    report["importance_sweep"] = importance_results
    
    # --- Combined Sweep (Optional: Cross-tabulation or specific joint analysis) ---
    # For this task, we record the point where both thresholds are met for a "stable" model state.
    # Since we have discrete family metrics and feature metrics, we create a synthetic joint analysis
    # based on the assumption that a model is "stable" if >50% families pass R² and >50% features pass importance.
    
    combined_results = []
    for r2_t in r2_thresholds:
        for imp_t in r2_thresholds:
            # Find corresponding r2 result
            r2_entry = next((r for r in r2_results if r["threshold"] == round(r2_t, 2)), None)
            imp_entry = next((i for i in importance_results if i["threshold"] == round(imp_t, 2)), None)
            
            if r2_entry and imp_entry:
                is_stable = (r2_entry["stability_ratio"] > 0.5) and (imp_entry["retention_ratio"] > 0.5)
                combined_results.append({
                    "r2_threshold": round(r2_t, 2),
                    "importance_threshold": round(imp_t, 2),
                    "is_stable": is_stable
                })
    
    # Limit combined results to avoid massive JSON if needed, but spec says 0.01 steps.
    # We keep all as requested.
    report["combined_sweep"] = combined_results
    
    # --- Summary ---
    # Find the "elbow" or optimal thresholds where stability starts to drop significantly
    # Simple heuristic: highest threshold where stability_ratio >= 0.8
    best_r2 = 0.0
    for entry in reversed(r2_results):
        if entry["stability_ratio"] >= 0.8:
            best_r2 = entry["threshold"]
            break
    
    best_imp = 0.0
    for entry in reversed(importance_results):
        if entry["retention_ratio"] >= 0.8:
            best_imp = entry["threshold"]
            break
    
    report["summary"] = {
        "recommended_r2_threshold": best_r2,
        "recommended_importance_threshold": best_imp,
        "total_sweep_points": len(r2_results) * len(importance_results),
        "data_source": eval_metrics.get("data_source_type", "Unknown")
    }
    
    logger.info("Sensitivity analysis completed.")
    return report

def save_report(report: Dict[str, Any], output_path: str = "data/processed/sensitivity_report.json") -> None:
    """
    Save the sensitivity report to a JSON file.
    """
    path = Path(output_path)
    ensure_dirs(path)
    
    with open(path, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Sensitivity report saved to {output_path}")

def main():
    """
    Main entry point for T025.
    """
    logger.info("Executing T025: Generate sensitivity_report.json")
    
    # Run analysis
    report = run_sensitivity_analysis()
    
    # Save report
    save_report(report)
    
    logger.info("T025 completed successfully.")

if __name__ == "__main__":
    main()