"""
Final Report Generation Module (T040).

Aggregates all metrics from previous stages (Data, Modeling, Visualization)
into a single `artifacts/results.json` file.
"""
import json
import logging
from pathlib import Path
from typing import Any, Dict, Optional

from config import get_path
from utils.reporting import load_results, save_results, update_results_with_hypothesis_test
from utils.state_manager import compute_file_hash

logger = logging.getLogger(__name__)


def load_model_metrics() -> Dict[str, Any]:
    """
    Loads metrics generated by the modeling stage (T028, T030, T031).
    Expected location: data/model_results.json (or similar intermediate state).
    If the modeling stage updated the main results dict directly, this
    attempts to retrieve the current state.
    """
    # Try to load from the standard results file first (accumulated state)
    results_path = get_path("artifacts", "results.json")
    if results_path.exists():
        try:
            with open(results_path, "r", encoding="utf-8") as f:
                data = json.load(f)
                # Return the whole dict as it likely contains accumulated metrics
                return data
        except (json.JSONDecodeError, IOError) as e:
            logger.warning(f"Could not load existing results.json: {e}. Starting fresh.")
    return {}


def load_visualization_metrics() -> Dict[str, Any]:
    """
    Loads metrics and sensitivity data from the visualization stage (T034-T038).
    Typically stored in artifacts/visualization_results.json or appended to results.json.
    """
    # Assuming visualization stage appends to the same results.json or writes a specific file.
    # We will rely on the main results file being the source of truth if it exists,
    # otherwise we look for specific visualization outputs.
    viz_path = get_path("artifacts", "visualization_results.json")
    if viz_path.exists():
        try:
            with open(viz_path, "r", encoding="utf-8") as f:
                return json.load(f)
        except (json.JSONDecodeError, IOError) as e:
            logger.warning(f"Could not load visualization results: {e}.")
    return {}


def consolidate_metrics(
    model_data: Dict[str, Any],
    viz_data: Dict[str, Any],
    current_results: Dict[str, Any]
) -> Dict[str, Any]:
    """
    Merges metrics from different stages into the final report structure.
    Ensures all required fields from SC-001, SC-002, SC-003 are present.
    """
    final_report = current_results.copy()

    # 1. Ensure Modeling Metrics (R2, MAE, p-value) are present
    # These should ideally be in current_results from T030/T031
    if "model_performance" not in final_report:
        final_report["model_performance"] = {}
    
    # Merge specific keys if they exist in model_data but not in final_report
    for key in ["baseline_r2", "baseline_mae", "augmented_r2", "augmented_mae", "p_value"]:
        if key in model_data and key not in final_report["model_performance"]:
            final_report["model_performance"][key] = model_data[key]
        elif key in final_report.get("model_performance", {}):
            pass # Already present
        elif key in model_data:
            final_report["model_performance"][key] = model_data[key]

    # 2. Ensure Hypothesis Test Flags (T031)
    if "hypothesis_test" not in final_report:
        final_report["hypothesis_test"] = {}
    
    if "null_result_flag" in model_data:
        final_report["hypothesis_test"]["null_result_flag"] = model_data["null_result_flag"]
    
    # 3. Ensure Sensitivity Analysis Data (T036, T038)
    if "sensitivity_analysis" not in final_report:
        final_report["sensitivity_analysis"] = {}
    
    if "threshold_sweep" in viz_data:
        final_report["sensitivity_analysis"]["threshold_sweep"] = viz_data["threshold_sweep"]
    if "robustness_summary" in viz_data:
        final_report["sensitivity_analysis"]["robustness_summary"] = viz_data["robustness_summary"]

    # 4. Add Study Metadata (from T019 validity check context)
    if "study_type" not in final_report:
        final_report["study_type"] = "Associational Only"

    # 5. Resource Usage (Placeholder if T044/045 haven't run, or load if available)
    # If T045 ran, it should have updated this.
    if "resource_usage" not in final_report:
        final_report["resource_usage"] = {
            "ram_peak_gb": None,
            "runtime_seconds": None,
            "limit_check": "pending"
        }

    return final_report


def generate_final_report() -> None:
    """
    Orchestrates the loading of all stage outputs and writes the final `artifacts/results.json`.
    """
    logger.info("Starting final report generation (T040)...")

    # Load accumulated results (likely updated by T030, T031, T038)
    current_results = load_model_metrics()
    
    # Load specific visualization outputs if they haven't been merged yet
    viz_data = load_visualization_metrics()

    # Consolidate
    final_report = consolidate_metrics({}, viz_data, current_results)

    # Ensure the directory exists
    output_path = get_path("artifacts", "results.json")
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Write the final report
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(final_report, f, indent=2)

    logger.info(f"Final report generated at: {output_path}")
    logger.info(f"Metrics included: R2={final_report.get('model_performance', {}).get('augmented_r2')}, "
                f"p-value={final_report.get('model_performance', {}).get('p_value')}")


def main() -> None:
    """Entry point for T040."""
    setup_logging = False
    try:
        from utils.logging_config import setup_logging as setup_log_func
        setup_log_func()
        setup_logging = True
    except ImportError:
        logging.basicConfig(level=logging.INFO)
    
    generate_final_report()


if __name__ == "__main__":
    main()
