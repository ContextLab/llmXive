# Constants
LOG_FILE = "data/raw/download_log.json"
CHECKSUM_FILE = "data/raw/checksums.json"
METADATA_FILE = "data/raw/phenotype_metadata.csv"
FILTERED_METADATA_FILE = "data/processed/phenotype_metadata_filtered.csv"
EXCLUSION_LOG_FILE = "data/processed/exclusion_log.json"

# Enum for download status
class DownloadStatus(str, Enum):
    SUCCESS = "success"
    FAILED = "failed"
    SKIPPED = "skipped"
    CHECKSUM_MISMATCH = "checksum_mismatch"

@dataclass
class DownloadRecord:
    sample_id: str
    fastq_path: Optional[str]
    status: DownloadStatus
    message: Optional[str]
    checksum_valid: Optional[bool] = None

class IngestionError(Exception):
    """Custom exception for ingestion pipeline errors."""
    pass

def load_download_log() -> List[Dict]:
    """Load the download log if it exists."""
    if not os.path.exists(LOG_FILE):
        return []
    try:
        with open(LOG_FILE, 'r') as f:
            return json.load(f)
    except (json.JSONDecodeError, IOError):
        return []

def save_download_log(records: List[Dict]) -> None:
    """Save the download log to disk."""
    ensure_directories()
    with open(LOG_FILE, 'w') as f:
        json.dump(records, f, indent=2)

def load_checksums() -> Dict:
    """Load the checksum verification results."""
    if not os.path.exists(CHECKSUM_FILE):
        raise IngestionError(f"Checksum file not found: {CHECKSUM_FILE}. Run T016 first.")
    try:
        with open(CHECKSUM_FILE, 'r') as f:
            return json.load(f)
    except (json.JSONDecodeError, IOError) as e:
        raise IngestionError(f"Failed to load checksum file: {e}")

def load_phenotype_metadata() -> List[Dict]:
    """
    Load phenotype metadata from the CSV file generated by the SRA download process.
    This assumes the SRA Toolkit or a helper script has produced a metadata CSV.
    """
    if not os.path.exists(METADATA_FILE):
        # Attempt to find a standard SRA metadata file or raise
        # In a real scenario, this might be generated by T015 or a separate metadata fetcher
        raise IngestionError(f"Phenotype metadata file not found: {METADATA_FILE}")
    
    records = []
    with open(METADATA_FILE, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            records.append(row)
    return records

def map_treatment_condition(raw_value: Optional[str]) -> Optional[TreatmentType]:
    """
    Map raw metadata string values to the standardized TreatmentType enum.
    Handles common variations in SRA metadata (e.g., 'heat', 'Heat', 'HEAT', 'control', 'Control').
    """
    if not raw_value or not isinstance(raw_value, str):
        return None
    
    val = raw_value.strip().lower()
    
    # Map heat stress conditions
    if val in ['heat', 'heated', 'thermal_stress', 'high_temp', 'elevated_temp']:
        return TreatmentType.HEAT
    
    # Map control conditions
    if val in ['control', 'ctrl', 'ambient', 'normal', 'baseline']:
        return TreatmentType.CONTROL
    
    # Map other potential categories if needed, or return None for unknown
    return None

def parse_and_filter_phenotypes(
    logger: logging.Logger,
    min_count_threshold: int,
    min_samples_for_filter: int
) -> Tuple[List[PhenotypeRecord], Dict]:
    """
    Parse phenotype metadata, map sample IDs to treatment conditions, and exclude
    samples with missing or invalid treatment status.
    
    Returns:
        Tuple of (List of valid PhenotypeRecord, Dict of exclusion statistics)
    """
    logger.info("Starting phenotype metadata parsing and filtering...")
    start_time = time.time()
    
    try:
        raw_metadata = load_phenotype_metadata()
    except IngestionError as e:
        logger.error(f"Failed to load metadata: {e}")
        raise
    
    if not raw_metadata:
        logger.warning("No metadata records found in the input file.")
        return [], {"total": 0, "excluded": 0, "valid": 0}
    
    valid_records = []
    excluded_samples = []
    
    # Counters for stats
    total_samples = len(raw_metadata)
    missing_treatment_count = 0
    invalid_treatment_count = 0
    
    # Load checksums to ensure we only process verified files
    try:
        checksums_data = load_checksums()
        verified_samples = set(checksums_data.keys())
    except IngestionError as e:
        logger.error(f"Cannot proceed without verified checksums: {e}")
        raise
    
    for record in raw_metadata:
        # Extract Sample ID (assuming column 'sample_id' or 'accession')
        sample_id = record.get('sample_id') or record.get('accession') or record.get('Run')
        
        if not sample_id:
            logger.warning(f"Record missing sample ID: {record}")
            excluded_samples.append({"record": record, "reason": "missing_sample_id"})
            continue
        
        # Check if this sample was verified in T016
        if sample_id not in verified_samples:
            logger.warning(f"Sample {sample_id} not found in verified checksums. Excluding.")
            excluded_samples.append({"sample_id": sample_id, "reason": "not_verified"})
            continue
        
        # Extract treatment info
        # Try common column names for treatment
        treatment_raw = (
            record.get('treatment') or 
            record.get('condition') or 
            record.get('treatment_condition') or 
            record.get('group')
        )
        
        treatment_type = map_treatment_condition(treatment_raw)
        
        if treatment_type is None:
            if treatment_raw is None or treatment_raw == '':
                logger.warning(f"Sample {sample_id}: Missing treatment status. Excluding.")
                missing_treatment_count += 1
            else:
                logger.warning(f"Sample {sample_id}: Invalid treatment value '{treatment_raw}'. Excluding.")
                invalid_treatment_count += 1
            
            excluded_samples.append({
                "sample_id": sample_id, 
                "reason": "missing_or_invalid_treatment",
                "raw_value": treatment_raw
            })
            continue
        
        # Create PhenotypeRecord
        # Assuming other fields like 'replicate_id', 'collection_date' might exist
        phenotype = PhenotypeRecord(
            sample_id=sample_id,
            treatment_type=treatment_type,
            raw_metadata=record
        )
        valid_records.append(phenotype)
    
    # Calculate statistics
    excluded_count = len(excluded_samples)
    valid_count = len(valid_records)
    
    stats = {
        "total_samples": total_samples,
        "verified_samples_in_metadata": total_samples - (total_samples - len([r for r in raw_metadata if (r.get('sample_id') or r.get('accession') or r.get('Run')) in verified_samples])),
        "missing_treatment_count": missing_treatment_count,
        "invalid_treatment_count": invalid_treatment_count,
        "total_excluded": excluded_count,
        "valid_samples": valid_count,
        "exclusion_details": excluded_samples
    }
    
    elapsed = time.time() - start_time
    logger.info(f"Phenotype parsing complete in {elapsed:.2f}s. Valid: {valid_count}, Excluded: {excluded_count}")
    
    return valid_records, stats

def save_filtered_metadata(
    records: List[PhenotypeRecord], 
    output_path: str,
    stats: Dict
) -> None:
    """
    Save the filtered phenotype records to a new CSV file and the exclusion log to JSON.
    """
    ensure_directories()
    
    # Save filtered CSV
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        # Header
        writer.writerow(['sample_id', 'treatment_type', 'raw_metadata_json'])
        
        for rec in records:
            # Convert treatment enum to string
            treatment_str = rec.treatment_type.value if rec.treatment_type else "UNKNOWN"
            # Store raw metadata as JSON string for traceability
            raw_json = json.dumps(rec.raw_metadata) if rec.raw_metadata else ""
            writer.writerow([rec.sample_id, treatment_str, raw_json])
    
    # Save exclusion log
    log_path = EXCLUSION_LOG_FILE
    with open(log_path, 'w') as f:
        json.dump(stats, f, indent=2)

def run_ingestion_phase_2() -> List[DownloadRecord]:
    """
    Execute the phenotype parsing and filtering step (T017).
    This function is called after T016 (checksum verification) completes.
    """
    logger = setup_logger("ingest_t017")
    ensure_directories()
    
    # Load config thresholds
    config = get_thresholds()
    min_count_threshold = config.get('MIN_COUNT_THRESHOLD', 10)
    min_samples_for_filter = config.get('MIN_SAMPLES_FOR_FILTER', 3)
    
    logger.info(f"Starting T017: Phenotype Parsing and Filtering.")
    logger.info(f"Config: MIN_COUNT_THRESHOLD={min_count_threshold}, MIN_SAMPLES_FOR_FILTER={min_samples_for_filter}")
    
    try:
        valid_records, stats = parse_and_filter_phenotypes(
            logger, 
            min_count_threshold, 
            min_samples_for_filter
        )
        
        save_filtered_metadata(valid_records, FILTERED_METADATA_FILE, stats)
        
        logger.info(f"T017 Complete. Saved {len(valid_records)} valid records to {FILTERED_METADATA_FILE}")
        
        # Return a dummy list of records for compatibility with the main runner if needed,
        # though T017's primary output is the file and log.
        return [] 
        
    except Exception as e:
        logger.error(f"T017 Failed: {e}", exc_info=True)
        raise IngestionError(f"Phenotype parsing failed: {e}")

def main():
    """Entry point for T017 execution."""
    try:
        run_ingestion_phase_2()
    except Exception as e:
        print(f"Error executing T017: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
