@dataclass
class McNemarResult:
    """Data class to hold McNemar's test results."""
    method_a: str
    method_b: str
    concordant_both_success: int
    concordant_both_failure: int
    discordant_a_success_b_failure: int
    discordant_a_failure_b_success: int
    chi2_statistic: float
    p_value: float
    confidence_interval: Tuple[float, float]
    conclusion: str

def load_simulation_results(csv_path: str) -> List[Dict[str, Any]]:
    """
    Load simulation results from a CSV file.
    
    Args:
        csv_path: Path to the CSV file generated by 05_simulate.py or 06_evaluate.py.
    
    Returns:
        List of dictionaries with simulation results.
    """
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Simulation results file not found at {csv_path}")
    
    results = []
    with open(csv_path, 'r', newline='') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Convert string booleans back to bool if necessary
            if 'success' in row:
                val = row['success']
                if isinstance(val, str):
                    row['success'] = val.lower() in ('true', '1', 'yes')
            results.append(row)
    
    if not results:
        raise ValueError(f"No results found in {csv_path}")
    
    return results

def pairwise_comparison(results: List[Dict[str, Any]], 
                        method_a: str, 
                        method_b: str, 
                        id_field: str = 'prompt_id') -> McNemarResult:
    """
    Perform McNemar's Test for binary success rates between two methods.
    
    This test is appropriate for paired nominal data (e.g., the same prompt run
    with two different models). It tests the null hypothesis that the marginal
    frequencies of the two methods are equal.
    
    Args:
        results: List of result dictionaries. Each must contain 'success' (bool)
                 and a field identifying the method (e.g., 'model_name' or 'method').
                 Also needs an ID field to pair results if they are separate rows.
                 Expected structure: [{'prompt_id': 'p1', 'method': 'A', 'success': True}, ...]
        method_a: Name of the first method to compare.
        method_b: Name of the second method to compare.
        id_field: Field name used to identify unique prompts (for pairing).
    
    Returns:
        McNemarResult object with statistics and conclusion.
    """
    # Filter results for the two methods
    data_a = [r for r in results if r.get('model_name', r.get('method', '')) == method_a]
    data_b = [r for r in results if r.get('model_name', r.get('method', '')) == method_b]
    
    if not data_a or not data_b:
        raise ValueError(f"Insufficient data for comparison. Found {len(data_a)} for {method_a}, {len(data_b)} for {method_b}")
    
    # Create a lookup for pairing
    # Assuming the same prompt_id exists in both lists
    lookup_b = {r[id_field]: r['success'] for r in data_b}
    
    # Contingency table counts
    # n_11: Both success
    # n_00: Both failure
    # n_10: A success, B failure
    # n_01: A failure, B success
    n_11 = 0
    n_00 = 0
    n_10 = 0
    n_01 = 0
    
    paired_count = 0
    for r_a in data_a:
        pid = r_a[id_field]
        if pid not in lookup_b:
            logger.warning(f"Prompt ID {pid} found in {method_a} but not in {method_b}. Skipping.")
            continue
        
        paired_count += 1
        success_a = r_a['success']
        success_b = lookup_b[pid]
        
        if success_a and success_b:
            n_11 += 1
        elif not success_a and not success_b:
            n_00 += 1
        elif success_a and not success_b:
            n_10 += 1
        elif not success_a and success_b:
            n_01 += 1
    
    if paired_count == 0:
        raise ValueError("No paired results found to compare.")
    
    logger.info(f"McNemar comparison ({method_a} vs {method_b}): {paired_count} pairs. "
                f"Both Success: {n_11}, Both Fail: {n_00}, "
                f"{method_a} only: {n_10}, {method_b} only: {n_01}")
    
    # McNemar's Test Statistic (with continuity correction)
    # chi2 = (|b - c| - 1)^2 / (b + c)
    # where b = n_10, c = n_01
    b = n_10
    c = n_01
    
    if b + c == 0:
        # Perfect agreement on discordant pairs (both 0). 
        # Chi2 is 0, p-value is 1.0.
        chi2_stat = 0.0
        p_val = 1.0
    else:
        abs_diff = abs(b - c)
        corrected_diff = abs_diff - 1.0
        if corrected_diff < 0:
            corrected_diff = 0.0
        chi2_stat = (corrected_diff ** 2) / (b + c)
        
        # Calculate p-value using binomial test (exact) or chi2 distribution
        # For large samples, chi2(1) is fine. For small, exact binomial is better.
        # scipy.stats.binom_test is the exact test for the null p=0.5
        try:
            # binom_test(k, n, p, alternative)
            # k = min(b, c), n = b + c, p = 0.5
            # We want the probability of observing a split as or more extreme than the one seen.
            # Since it's a two-sided test for symmetry:
            p_val = binom_test(min(b, c), b + c, p=0.5, alternative='two-sided')
        except TypeError:
            # Older scipy might not have 'alternative' kwarg or 'binom_test'
            # Fallback to chi2 approximation p-value
            from scipy.stats import chi2
            p_val = 1.0 - chi2.cdf(chi2_stat, 1)
    
    # Confidence Interval for the difference in proportions (approximate)
    # Difference = (b - c) / N
    # SE = sqrt((b + c) - (b - c)^2 / N) / N  <-- This is for the difference in proportions
    # A simpler approximation for the difference in marginal probabilities:
    # p_a = (n_11 + n_10) / N, p_b = (n_11 + n_01) / N
    # diff = p_a - p_b = (n_10 - n_01) / N
    # SE_diff = sqrt( (n_10 + n_01) - (n_10 - n_01)^2/N ) / N
    N = paired_count
    diff = (b - c) / N
    if b + c > 0:
        se_diff = (( (b + c) - ((b - c)**2) / N ) ** 0.5) / N
    else:
        se_diff = 0.0
    
    # 95% CI
    z_95 = 1.96
    ci_lower = diff - z_95 * se_diff
    ci_upper = diff + z_95 * se_diff
    
    # Conclusion
    alpha = 0.05
    if p_val < alpha:
        conclusion = f"Significant difference detected (p={p_val:.4f}). {method_a} and {method_b} have different success rates."
    else:
        conclusion = f"No significant difference detected (p={p_val:.4f}). Success rates are statistically similar."
    
    return McNemarResult(
        method_a=method_a,
        method_b=method_b,
        concordant_both_success=n_11,
        concordant_both_failure=n_00,
        discordant_a_success_b_failure=b,
        discordant_a_failure_b_success=c,
        chi2_statistic=chi2_stat,
        p_value=p_val,
        confidence_interval=(ci_lower, ci_upper),
        conclusion=conclusion
    )

def run_evaluation_pipeline(
    results: Optional[List[Dict[str, Any]]] = None,
    output_path: Optional[str] = None,
    comparison_pairs: Optional[List[Tuple[str, str]]] = None
) -> str:
    """
    Main pipeline function to log simulation results and perform McNemar's Test.
    
    Args:
        results: Optional list of result dictionaries. If None, loads from default CSV.
        output_path: Path for the output CSV (simulation logs).
        comparison_pairs: List of tuples (method_a, method_b) to compare.
                        Defaults to: [('non-neural', 'random'), ('non-neural', 'vla-proxy')]
    
    Returns:
        Path to the generated evaluation report JSON.
    """
    config = get_config()
    default_csv = config.get('output', {}).get('simulation_logs', 'data/results/simulation_logs.csv')
    default_report = config.get('output', {}).get('evaluation_report', 'data/results/evaluation_report.json')
    
    target_csv = output_path or default_csv
    target_report = config.get('output', {}).get('mcnemar_report', 'data/results/mcnemar_results.json')
    
    # 1. Load or Validate Results
    if results is None:
        if os.path.exists(target_csv):
            logger.info(f"Loading results from {target_csv}")
            results = load_simulation_results(target_csv)
        else:
            # Try the JSON intermediate if CSV is missing but JSON exists
            json_source = 'data/results/simulation_results.json'
            if os.path.exists(json_source):
                logger.info(f"Loading results from {json_source}")
                with open(json_source, 'r') as f:
                    results = json.load(f)
            else:
                raise FileNotFoundError(
                    f"No simulation results found at {target_csv} or {json_source}. "
                    "Please run code/05_simulate.py first."
                )
    
    # Ensure results have 'success' and 'model_name' (or 'method')
    required_keys = ['success', 'prompt_id']
    # Check if 'model_name' or 'method' exists
    method_key = None
    for key in ['model_name', 'method', 'model']:
        if key in results[0]:
            method_key = key
            break
    
    if not method_key:
        raise ValueError("Simulation results must contain a 'model_name' or 'method' field.")
    
    for i, r in enumerate(results):
        if 'success' not in r or 'prompt_id' not in r:
            raise ValueError(f"Result at index {i} missing 'success' or 'prompt_id'.")
        if not isinstance(r['success'], bool):
            # Try to coerce if it's a string
            if isinstance(r['success'], str):
                r['success'] = r['success'].lower() in ('true', '1', 'yes')
            else:
                raise ValueError(f"Result at index {i} 'success' is not boolean: {type(r['success'])}")
    
    # 2. Log to CSV (if not already done or to ensure format)
    # We call the existing log function to ensure the CSV is up to date
    log_simulation_results(results, target_csv)
    
    # 3. Perform McNemar's Tests
    if comparison_pairs is None:
        # Default comparisons based on task description
        comparison_pairs = [
            ('non-neural', 'random'),
            ('non-neural', 'vla-proxy')
        ]
    
    mcnemar_results = []
    for pair in comparison_pairs:
        try:
            res = pairwise_comparison(results, pair[0], pair[1])
            mcnemar_results.append(res)
            logger.info(f"Completed comparison: {pair[0]} vs {pair[1]}")
        except Exception as e:
            logger.error(f"Failed to compare {pair[0]} vs {pair[1]}: {e}")
            mcnemar_results.append({
                'method_a': pair[0],
                'method_b': pair[1],
                'error': str(e),
                'p_value': None,
                'conclusion': f"Comparison failed: {e}"
            })
    
    # 4. Generate Report
    report = {
        'timestamp': str(Path(target_report).parent), # Placeholder for actual timestamp logic
        'input_file': target_csv,
        'total_samples': len(results),
        'comparisons': [
            {
                'method_a': r.method_a,
                'method_b': r.method_b,
                'contingency_table': {
                    'both_success': r.concordant_both_success,
                    'both_failure': r.concordant_both_failure,
                    'a_success_b_failure': r.discordant_a_success_b_failure,
                    'a_failure_b_success': r.discordant_a_failure_b_success
                },
                'chi2_statistic': r.chi2_statistic,
                'p_value': r.p_value,
                'confidence_interval_95': list(r.confidence_interval),
                'conclusion': r.conclusion
            }
            if isinstance(r, McNemarResult) else r
            for r in mcnemar_results
        ]
    }
    
    # Ensure output directory exists
    Path(target_report).parent.mkdir(parents=True, exist_ok=True)
    
    with open(target_report, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Evaluation complete. McNemar results saved to: {target_report}")
    return target_report

def main():
    parser = argparse.ArgumentParser(description="Run McNemar's Test on simulation results")
    parser.add_argument(
        '--results',
        type=str,
        help="Path to simulation results JSON/CSV. If not provided, tries default locations."
    )
    parser.add_argument(
        '--output-csv',
        type=str,
        help="Path for the output CSV file."
    )
    parser.add_argument(
        '--output-report',
        type=str,
        help="Path for the JSON report file."
    )
    parser.add_argument(
        '--seed',
        type=int,
        default=42,
        help="Random seed for reproducibility"
    )
    parser.add_argument(
        '--compare',
        type=str,
        nargs='+',
        help="Pairs of methods to compare (e.g., --compare non-neural random vla-proxy). "
             "Format: method1 method2 [method3 method4 ...]"
    )

    args = parser.parse_args()
    set_global_seed(args.seed)

    results = None
    if args.results:
        if not os.path.exists(args.results):
            raise FileNotFoundError(f"Results file not found: {args.results}")
        if args.results.endswith('.json'):
            with open(args.results, 'r') as f:
                results = json.load(f)
        elif args.results.endswith('.csv'):
            results = load_simulation_results(args.results)
        else:
            raise ValueError("Results file must be .json or .csv")

    comparison_pairs = None
    if args.compare:
        if len(args.compare) % 2 != 0:
            raise ValueError("--compare requires pairs of arguments (method1 method2 ...)")
        comparison_pairs = [(args.compare[i], args.compare[i+1]) for i in range(0, len(args.compare), 2)]

    try:
        report_path = run_evaluation_pipeline(
            results=results,
            output_path=args.output_csv,
            comparison_pairs=comparison_pairs
        )
        logger.info(f"Evaluation complete. Report saved to: {report_path}")
    except Exception as e:
        logger.error(f"Evaluation failed: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()