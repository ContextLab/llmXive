# --- CPU-Only Enforcement Logic ---

def enforce_cpu_only() -> None:
    """
    Pre-flight check to ensure the script runs ONLY on CPU.
    
    Raises:
        RuntimeError: If torch.cuda.is_available() returns True.
    """
    if torch.cuda.is_available():
        raise RuntimeError(
            "GPU detected! This script enforces a strict CPU-only constraint "
            "to satisfy SC-003 and FR-003. Please disable CUDA or run on a CPU-only "
            "environment. Detected devices: " + str(torch.cuda.device_count())
        )
    
    # Explicitly set device to CPU to ensure no accidental GPU usage
    # even if CUDA is somehow available but disabled in config.
    logger.info("Enforcing CPU-only execution mode.")
    # We do not assign a global device here because we will do it per-model/encoder,
    # but we ensure the check passes.
    return

