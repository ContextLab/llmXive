import os
import sys
import pytest
import pandas as pd
from pathlib import Path

# Add parent directory to path
sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from code.config import get_wcst_variable_name

def test_behavioral_scores_schema():
    """
    Contract test to verify behavioral_scores.csv schema.
    Ensures the file exists and contains required columns.
    """
    project_root = Path(__file__).parent.parent.parent
    output_path = project_root / "data" / "processed" / "behavioral_scores.csv"
    
    # Skip if file doesn't exist (pipeline not run yet)
    if not output_path.exists():
        pytest.skip(f"Output file {output_path} does not exist. Run T012b first.")
    
    df = pd.read_csv(output_path)
    
    # Verify required columns
    required_cols = ['participant_id', 'age', get_wcst_variable_name()]
    missing_cols = [col for col in required_cols if col not in df.columns]
    
    assert not missing_cols, f"Missing required columns: {missing_cols}"
    
    # Verify data types
    assert df['age'].dtype in ['int64', 'int32', 'float64'], "Age column must be numeric"
    
    # Verify no NaN in critical columns
    assert df['participant_id'].notna().all(), "participant_id contains NaN"
    assert df['age'].notna().all(), "age contains NaN"
    assert df[get_wcst_variable_name()].notna().all(), "WCST column contains NaN"
    
    # Verify age constraint (should be >= min_age from config)
    from code.config import get_min_age
    min_age = get_min_age()
    assert (df['age'] >= min_age).all(), f"Some participants are younger than {min_age}"

