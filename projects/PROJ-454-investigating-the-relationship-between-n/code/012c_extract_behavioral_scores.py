"""
T012c: Extract and convert behavioral scores from raw parquet files.

Input: data/raw/*.parquet (generated by T012a, validated by T012b)
Output: data/processed/behavioral_scores.csv

Logic:
1. Load all parquet files from data/raw/
2. Verify that the required column 'wcst_perseverative_errors' exists (per T012b).
   - If missing, the file should have been flagged in logs/validation_status.json by T012b.
   - This script assumes T012b has already run and only processes valid datasets.
3. Extract participant ID and behavioral scores.
4. Aggregate if necessary (e.g., if multiple rows per participant exist, take the mean or first valid).
5. Save to data/processed/behavioral_scores.csv.

Dependencies:
- config.py for paths and variable names.
- utils/logging_config.py for logging.
- pandas for data manipulation.
"""
import os
import sys
import logging
import pandas as pd
from pathlib import Path
import json

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).parent))

from config import get_config, get_wcst_variable_name
from utils.logging_config import setup_data_flow_logger, get_logger
from utils.resource_monitor import check_resource_limits, log_resource_snapshot

def setup_logger(name):
    """Setup a logger for this module."""
    return setup_data_flow_logger(name)

def load_raw_parquet_files(raw_dir):
    """
    Load all parquet files from the raw directory.
    Returns a dictionary mapping filename to DataFrame.
    """
    raw_path = Path(raw_dir)
    if not raw_path.exists():
        raise FileNotFoundError(f"Raw data directory not found: {raw_path}")
    
    parquet_files = list(raw_path.glob("*.parquet"))
    if not parquet_files:
        raise ValueError(f"No parquet files found in {raw_path}")
    
    dataframes = {}
    for f in parquet_files:
        try:
            df = pd.read_parquet(f)
            dataframes[f.name] = df
        except Exception as e:
            logging.error(f"Failed to load {f.name}: {e}")
            continue
    
    if not dataframes:
        raise RuntimeError("No valid parquet files could be loaded.")
    
    return dataframes

def verify_variable_fit(dataframes, required_column):
    """
    Verify that all loaded dataframes contain the required column.
    Returns a list of valid dataframes (those with the column).
    """
    valid_dfs = {}
    for name, df in dataframes.items():
        if required_column in df.columns:
            valid_dfs[name] = df
        else:
            logging.warning(f"Dataset {name} missing required column '{required_column}'. Skipping.")
    
    if not valid_dfs:
        raise RuntimeError("No datasets contained the required column. Pipeline cannot proceed.")
    
    return valid_dfs

def extract_behavioral_scores(valid_dfs, output_path, wcst_var_name):
    """
    Extract behavioral scores from valid dataframes and save to CSV.
    
    Expected columns in output:
    - participant_id: Unique identifier
    - wcst_perseverative_errors: The primary behavioral score
    - dataset_source: Name of the source file (optional, for traceability)
    """
    all_scores = []
    
    for source_name, df in valid_dfs.items():
        # Ensure participant_id exists; if not, try to infer or raise error
        if 'participant_id' not in df.columns:
            # Attempt to find a similar column or use index
            if 'subject' in df.columns:
                id_col = 'subject'
            elif 'id' in df.columns:
                id_col = 'id'
            else:
                # Fallback: generate ID from index if absolutely necessary, but log warning
                logging.warning(f"Participant ID column not found in {source_name}. Generating temporary IDs.")
                df['participant_id'] = [f"{source_name.split('.')[0]}_{i}" for i in range(len(df))]
                id_col = 'participant_id'
        else:
            id_col = 'participant_id'
        
        # Select relevant columns
        # We need: participant_id, wcst_perseverative_errors
        # Also include any other behavioral columns if they exist and are relevant (optional)
        cols_to_keep = [id_col, wcst_var_name]
        
        # Filter to existing columns to avoid KeyError
        existing_cols = [c for c in cols_to_keep if c in df.columns]
        subset = df[existing_cols].copy()
        
        # Add source tracking
        subset['dataset_source'] = source_name
        
        # Drop rows with NaN in critical columns
        critical_cols = [id_col, wcst_var_name]
        subset = subset.dropna(subset=critical_cols)
        
        # If multiple rows per participant exist, aggregate (e.g., mean of errors)
        # Assuming one row per participant is ideal, but handle duplicates if present
        if subset[id_col].duplicated().any():
            logging.info(f"Found duplicate participant IDs in {source_name}. Aggregating by mean.")
            subset = subset.groupby(id_col, as_index=False).mean(numeric_only=True)
            # Re-add source if needed, or keep the first one? Let's keep 'first' source or 'multiple'
            subset['dataset_source'] = "aggregated"
        
        all_scores.append(subset)
    
    if not all_scores:
        raise RuntimeError("No valid behavioral scores extracted.")
    
    final_df = pd.concat(all_scores, ignore_index=True)
    
    # Ensure output directory exists
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Save to CSV
    final_df.to_csv(output_path, index=False)
    logging.info(f"Behavioral scores saved to {output_path}")
    
    return final_df

def extract_and_verify_behavioral_scores(raw_dir, output_path):
    """
    Main orchestration function for T012c.
    """
    config = get_config()
    wcst_var_name = get_wcst_variable_name()
    
    logging.info(f"Starting behavioral score extraction. Required column: {wcst_var_name}")
    
    # 1. Load raw data
    dataframes = load_raw_parquet_files(raw_dir)
    
    # 2. Verify variable fit
    valid_dfs = verify_variable_fit(dataframes, wcst_var_name)
    
    # 3. Extract and save
    result_df = extract_behavioral_scores(valid_dfs, output_path, wcst_var_name)
    
    return result_df

def main():
    """
    Entry point for the script.
    """
    setup_logger("behavioral_extraction")
    log_resource_snapshot()
    
    config = get_config()
    raw_dir = config.get('RAW_DATA_PATH', 'data/raw')
    output_path = config.get('BEHAVIORAL_OUTPUT_PATH', 'data/processed/behavioral_scores.csv')
    
    try:
        df = extract_and_verify_behavioral_scores(raw_dir, output_path)
        log_resource_snapshot()
        print(f"Successfully extracted {len(df)} participant records.")
        return 0
    except Exception as e:
        logging.error(f"Pipeline failed: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
