"""
Script: filter_labels.py
Task: T018 [US2]
Description:
  Filters alloy dataset to retain rows with 'phase_label' from experimental sources.
  Marks DFT-derived rows with confidence='low' and logs warnings.
  Outputs: data/derived/filtered_alloys.csv
Requirements:
  - FR-009: Experimental priority, lower-confidence DFT handling.
  - Real data only: Reads from data/samples/sample_dataset.csv (generated by T017).
"""
import argparse
import logging
import os
import sys
from datetime import datetime
from pathlib import Path

import pandas as pd

# Configure logging
LOG_DIR = Path("logs")
LOG_DIR.mkdir(exist_ok=True)
LOG_FILE = LOG_DIR / "filter_labels.log"

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s",
    handlers=[
        logging.FileHandler(LOG_FILE),
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)

def main():
    parser = argparse.ArgumentParser(description="Filter alloy labels based on source confidence.")
    parser.add_argument(
        "--input",
        type=str,
        default="data/samples/sample_dataset.csv",
        help="Path to input CSV (default: data/samples/sample_dataset.csv)"
    )
    parser.add_argument(
        "--output",
        type=str,
        default="data/derived/filtered_alloys.csv",
        help="Path to output CSV (default: data/derived/filtered_alloys.csv)"
    )
    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)

    if not input_path.exists():
        logger.error(f"Input file not found: {input_path}")
        sys.exit(1)

    output_path.parent.mkdir(parents=True, exist_ok=True)

    logger.info(f"Loading data from {input_path}...")
    try:
        df = pd.read_csv(input_path)
    except Exception as e:
        logger.error(f"Failed to read input CSV: {e}")
        sys.exit(1)

    required_columns = ["phase_label", "source_type"]
    missing_cols = [col for col in required_columns if col not in df.columns]
    if missing_cols:
        logger.error(f"Input CSV missing required columns: {missing_cols}")
        sys.exit(1)

    # Filter logic based on FR-009
    # 1. Retain rows with phase_label from experimental sources.
    #    Assumption: source_type == "experimental" indicates experimental data.
    #    Assumption: 'phase_label' must not be null/NaN for valid rows.
    
    logger.info("Filtering for experimental sources and valid phase labels...")
    
    # Create a mask for experimental sources
    experimental_mask = df["source_type"].str.lower() == "experimental"
    
    # Create a mask for valid phase labels (not null)
    valid_label_mask = df["phase_label"].notna()
    
    # Combined mask
    keep_mask = experimental_mask & valid_label_mask

    df_filtered = df[keep_mask].copy()
    
    # Log statistics
    total_rows = len(df)
    kept_rows = len(df_filtered)
    dropped_rows = total_rows - kept_rows
    
    logger.info(f"Total rows: {total_rows}")
    logger.info(f"Kept rows (experimental + valid label): {kept_rows}")
    logger.info(f"Dropped rows: {dropped_rows}")

    # Handle DFT-derived rows: Mark with confidence='low' and log warning
    # Identify DFT rows that were NOT kept (i.e., dropped) OR if we are keeping them but marking them.
    # The task says "Retains rows with phase_label from experimental sources."
    # This implies DFT rows are NOT retained in the primary filtered set, OR they are retained but marked.
    # Re-reading: "Retains rows with phase_label from experimental sources. Marks DFT-derived rows with confidence='low'..."
    # Interpretation A: Only keep experimental. DFT rows are dropped. The "marking" might be for a separate report or just logging.
    # Interpretation B: Keep everything, but mark DFT as low confidence.
    # Given "Retains rows with phase_label from experimental sources" usually implies exclusion of others in data filtering contexts,
    # but the "Marks DFT..." part suggests they might be in the dataset but flagged.
    # However, T017 (sample_dataset) creates a dataset. T018 filters it.
    # Let's assume the strict interpretation: Keep experimental.
    # But to satisfy "Marks DFT-derived rows", we will check if there are DFT rows in the *original* that we are dropping,
    # and log them as warnings. If the requirement implies keeping them in the output but flagged, we would need a 'confidence' column.
    # The prompt says "Outputs data/derived/filtered_alloys.csv".
    # Let's look at the phrasing again: "Retains rows with phase_label from experimental sources." -> This is the filter criteria.
    # "Marks DFT-derived rows with confidence='low' and logs a warning".
    # If we drop them, we can't mark them in the output file.
    # If we keep them, we violate "Retains rows with phase_label from experimental sources" (unless it means 'Retains [at least] rows...').
    # Most likely: The output should ONLY contain experimental rows. The "Marks" part refers to logging the dropped DFT rows as low confidence.
    # OR, the output contains all rows, but experimental are high confidence, DFT are low.
    # Let's assume the safer, more robust scientific approach: The "filtered" dataset is the high-quality experimental set.
    # The DFT rows are identified and logged as warnings (low confidence) but excluded from the final filtered CSV to ensure quality.
    # However, if the spec implies keeping them, we might fail.
    # Let's re-read carefully: "Retains rows with phase_label from experimental sources." (Implies exclusion of non-experimental).
    # "Marks DFT-derived rows with confidence='low'..." -> This action happens on the DFT rows. If they are dropped, we mark them in the log.
    # Let's implement: Keep only experimental. Log all DFT rows as warnings with confidence='low'.
    
    dft_rows = df[~experimental_mask]
    if not dft_rows.empty:
        logger.warning(f"Identified {len(dft_rows)} DFT-derived rows. These are marked as 'confidence=low' and excluded from the filtered dataset.")
        for idx, row in dft_rows.iterrows():
            logger.warning(f"DFT Row ID {row.get('sample_id', idx)}: source={row['source_type']}, confidence=low")
    
    # If the requirement implies keeping DFT rows but flagging them, we would need to add a 'confidence' column.
    # Since the task says "Retains rows with ... experimental sources", I will stick to keeping only experimental.
    # If the user intended to keep DFT but flag, the logic would be:
    # df['confidence'] = 'high'
    # df.loc[~experimental_mask, 'confidence'] = 'low'
    # But "Retains rows with..." is a filter verb.
    
    # Write output
    logger.info(f"Writing filtered data to {output_path}...")
    df_filtered.to_csv(output_path, index=False)
    
    logger.info("Filtering complete.")

if __name__ == "__main__":
    main()