"""
Contract test for SHAP output format.

This test verifies that the SHAP output generated by code/models/importance.py
conforms to the expected schema and data types. It ensures that the output
files (JSON summary and PNG plots) are generated correctly and contain the
required fields as per the project's data contracts and Constitution IV (Traceability).
"""

import json
import os
import glob
import numpy as np
import pytest
from pathlib import Path

# Constants for schema validation
EXPECTED_JSON_FIELDS = {
    "model_type",
    "feature_names",
    "shap_values_mean",
    "shap_values_std",
    "interaction_values",
    "data_source_id",
    "code_block_id",
    "generated_at"
}

EXPECTED_MODEL_TYPES = {"RandomForest", "GradientBoosting"}

SHAP_PLOT_PATTERN = "shap_summary_*.png"
SHAP_PLOT_DIR = "results/shap_plots"

def test_shap_json_schema_exists_and_valid():
    """
    Test that the SHAP JSON summary file exists and matches the expected schema.
    """
    shap_json_path = Path("results/shap_summary.json")
    
    assert shap_json_path.exists(), f"SHAP summary JSON file not found at {shap_json_path}"

    with open(shap_json_path, 'r') as f:
        data = json.load(f)

    # Check top-level keys
    missing_keys = EXPECTED_JSON_FIELDS - set(data.keys())
    assert not missing_keys, f"Missing required fields in SHAP JSON: {missing_keys}"

    # Validate specific field types and constraints
    assert data["model_type"] in EXPECTED_MODEL_TYPES, \
        f"Invalid model_type: {data['model_type']}. Expected one of {EXPECTED_MODEL_TYPES}"

    assert isinstance(data["feature_names"], list), "feature_names must be a list"
    assert len(data["feature_names"]) > 0, "feature_names cannot be empty"

    assert isinstance(data["shap_values_mean"], list), "shap_values_mean must be a list"
    assert len(data["shap_values_mean"]) == len(data["feature_names"]), \
        "shap_values_mean length must match feature_names"

    assert isinstance(data["shap_values_std"], list), "shap_values_std must be a list"
    assert len(data["shap_values_std"]) == len(data["feature_names"]), \
        "shap_values_std length must match feature_names"

    # Validate traceability fields (Constitution IV)
    assert "data_source_id" in data and isinstance(data["data_source_id"], str), \
        "data_source_id must be a non-empty string"
    assert "code_block_id" in data and isinstance(data["code_block_id"], str), \
        "code_block_id must be a non-empty string"
    
    # Validate timestamp format (ISO 8601)
    assert "generated_at" in data and isinstance(data["generated_at"], str), \
        "generated_at must be a string"
    
    # Verify numerical values are finite
    for val in data["shap_values_mean"]:
        assert np.isfinite(val), f"Non-finite value found in shap_values_mean: {val}"
    
    for val in data["shap_values_std"]:
        assert np.isfinite(val), f"Non-finite value found in shap_values_std: {val}"

def test_shap_plots_exist_and_valid():
    """
    Test that SHAP summary plots are generated for each trained model.
    """
    plot_dir = Path(SHAP_PLOT_DIR)
    assert plot_dir.exists(), f"SHAP plot directory not found at {plot_dir}"

    # Find all generated plots
    plots = list(plot_dir.glob(SHAP_PLOT_PATTERN))
    assert len(plots) > 0, f"No SHAP summary plots found in {plot_dir}"

    # Verify each plot is a valid image file (non-empty)
    for plot_path in plots:
        assert plot_path.stat().st_size > 0, f"SHAP plot {plot_path} is empty"
        # Basic check for PNG header
        with open(plot_path, 'rb') as f:
            header = f.read(8)
            assert header[:8] == b'\x89PNG\r\n\x1a\n', \
                f"File {plot_path} does not appear to be a valid PNG image"

def test_consistency_between_json_and_plots():
    """
    Test that the number of plots matches the number of models in the JSON summary.
    """
    shap_json_path = Path("results/shap_summary.json")
    if not shap_json_path.exists():
        pytest.skip("SHAP JSON summary not found, skipping consistency check")

    with open(shap_json_path, 'r') as f:
        data = json.load(f)

    model_type = data["model_type"]
    expected_plot_name = f"shap_summary_{model_type}.png"
    
    plot_path = Path(SHAP_PLOT_DIR) / expected_plot_name
    assert plot_path.exists(), f"Expected plot {expected_plot_name} not found for model {model_type}"