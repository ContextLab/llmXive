"""
code/main.py
------------

Orchestrator for the Transferability of DFT‑D3 Dispersion to Ionic Liquids
pipeline.  The original implementation (generated by the project scaffold)
simply chained a few scripts.  Here we extend it to include the newly
implemented ``download_il_benchmark`` step (Task T022) before any downstream
processing.

The orchestrator runs the following stages in order:

1. ``download_il_benchmark`` – fetches and extracts the benchmark dataset.
2. ``load_data``                – performs checksum validation (if any).
3. ``run_psi4``                – placeholder for Psi4 calculations.
4. ``analyze_energies``        – generates ``raw_energies.csv``.
5. ``derive_scaling``           – fits the D3 scaling factor.
6. ``correlate_bulk``          – computes bulk‑property correlations.
7. ``generate_reports``        – builds the markdown reports.

Each stage is imported and its ``main`` function is invoked.  Any exception
aborts the pipeline with a non‑zero exit code, ensuring that failures are
loud and visible to the CI runner.
"""

import sys
from llmxive_toolkit import get_logger

log = get_logger(__name__)

def _run_stage(stage_name: str, entrypoint):
    """Utility to run a stage and log success/failure."""
    log.info(f"=== Starting stage: {stage_name} ===")
    try:
        entrypoint()
        log.info(f"=== Finished stage: {stage_name} ===")
    except Exception as exc:
        log.error(f"Stage '{stage_name}' failed: {exc}")
        raise

def main():
    """
    Execute the full pipeline in the correct order.
    """
    # Import inside the function so that any import‑time side effects are
    # deferred until the orchestrator is actually run.
    from download_il_benchmark import main as download_main
    from load_data import main as load_main
    from run_psi4 import main as psi4_main
    from analyze_energies import main as analyze_main
    from derive_scaling import main as scaling_main
    from correlate_bulk import main as correlate_main
    from generate_reports import main as reports_main

    # 1. Dataset acquisition (Task T022)
    _run_stage("download_il_benchmark", download_main)

    # 2. Optional checksum validation – harmless if the function is a stub.
    _run_stage("load_data", load_main)

    # 3. Psi4 calculations (placeholder in this CI‑friendly repo)
    _run_stage("run_psi4", psi4_main)

    # 4. Energy analysis – creates data/derived/raw_energies.csv
    _run_stage("analyze_energies", analyze_main)

    # 5. Scaling factor derivation
    _run_stage("derive_scaling", scaling_main)

    # 6. Bulk‑property correlation analysis
    _run_stage("correlate_bulk", correlate_main)

    # 7. Report generation
    _run_stage("generate_reports", reports_main)

    log.info("=== Pipeline completed successfully ===")

if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        log.error(f"Pipeline terminated with error: {e}")
        sys.exit(1)