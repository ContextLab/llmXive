def load_scaling_factor(path: str = "data/derived/scaling_factor.txt") -> float:
    """Load the scaling factor from the derived file."""
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"Scaling factor file not found: {path}")
    
    content = p.read_text().strip()
    # Expected format: "s = <value>" or just "<value>"
    if "=" in content:
        val_str = content.split("=")[1].strip()
    else:
        val_str = content.split("\n")[0].strip()
    
    try:
        return float(val_str)
    except ValueError:
        raise ValueError(f"Could not parse scaling factor from: {content}")

