def power_law(N: np.ndarray, a: float, b: float) -> np.ndarray:
    """
    Power law function: Error = a * N^(-b)

    Args:
        N: Array of dataset sizes (number of training samples)
        a: Intercept parameter (scaling factor)
        b: Exponent parameter (scaling exponent)

    Returns:
        Predicted error values
    """
    # Avoid division by zero or negative powers of zero
    N_safe = np.where(N == 0, 1e-10, N)
    return a * (N_safe ** (-b))


def fit_power_law(
    sizes: np.ndarray,
    errors: np.ndarray,
    p0: Optional[Tuple[float, float]] = None
) -> Dict[str, Any]:
    """
    Fit a power law model to learning curve data.

    Args:
        sizes: Array of training set sizes (N)
        errors: Array of corresponding errors (e.g., RMSE)
        p0: Initial guess for (a, b) parameters. If None, uses heuristic.

    Returns:
        Dictionary containing:
            - 'a': Intercept parameter
            - 'b': Exponent parameter
            - 'r_squared': R-squared value of the fit
            - 'success': Boolean indicating if fit converged
            - 'message': Status message
    """
    # Filter out zero or negative sizes/errors
    valid_mask = (sizes > 0) & (errors > 0)
    sizes_valid = sizes[valid_mask]
    errors_valid = errors[valid_mask]

    if len(sizes_valid) < 2:
        return {
            'a': np.nan,
            'b': np.nan,
            'r_squared': np.nan,
            'success': False,
            'message': 'Insufficient valid data points for fitting'
        }

    # Use log-log transformation for linearization as initial guess
    # log(Error) = log(a) - b * log(N)
    log_sizes = np.log(sizes_valid)
    log_errors = np.log(errors_valid)

    try:
        # Linear regression on log-log data for initial guess
        coeffs = np.polyfit(log_sizes, log_errors, 1)
        b_guess = -coeffs[0]
        a_guess = np.exp(coeffs[1])

        # Ensure positive parameters
        if a_guess <= 0:
            a_guess = 1.0
        if b_guess <= 0:
            b_guess = 0.1  # Small positive value

        p0 = (a_guess, b_guess) if p0 is None else p0

        # Fit the power law model
        popt, pcov = curve_fit(
            power_law,
            sizes_valid,
            errors_valid,
            p0=p0,
            bounds=(0, np.inf),  # Parameters must be positive
            maxfev=10000
        )

        a_fit, b_fit = popt

        # Calculate R-squared
        y_pred = power_law(sizes_valid, a_fit, b_fit)
        ss_res = np.sum((errors_valid - y_pred) ** 2)
        ss_tot = np.sum((errors_valid - np.mean(errors_valid)) ** 2)

        if ss_tot == 0:
            r_squared = 1.0 if ss_res == 0 else 0.0
        else:
            r_squared = 1 - (ss_res / ss_tot)

        # Ensure R-squared is in valid range
        r_squared = max(0.0, min(1.0, r_squared))

        return {
            'a': a_fit,
            'b': b_fit,
            'r_squared': r_squared,
            'success': True,
            'message': 'Fit converged successfully'
        }

    except Exception as e:
        logger.warning(f"Power law fitting failed: {str(e)}")
        return {
            'a': np.nan,
            'b': np.nan,
            'r_squared': np.nan,
            'success': False,
            'message': f'Fitting error: {str(e)}'
        }


def load_learning_curve_data(
    data_dir: Path,
    property_name: str
) -> Optional[pd.DataFrame]:
    """
    Load learning curve data for a specific property.

    Args:
        data_dir: Path to the data directory
        property_name: Name of the property to load data for

    Returns:
        DataFrame with columns: 'size', 'error', 'seed'
        None if no data found
    """
    # Expected file path pattern from train_learning_curves.py
    # Files are named: learning_curve_{property_name}.csv
    file_path = data_dir / 'processed' / f'learning_curve_{property_name}.csv'

    if not file_path.exists():
        logger.debug(f"No learning curve data found for {property_name} at {file_path}")
        return None

    try:
        df = pd.read_csv(file_path)
        required_cols = {'size', 'error'}
        if not required_cols.issubset(df.columns):
            logger.warning(f"Missing required columns in {file_path}. Found: {df.columns.tolist()}")
            return None

        # Filter for positive sizes and errors
        df = df[(df['size'] > 0) & (df['error'] > 0)]

        if len(df) == 0:
            logger.warning(f"No valid data points in {file_path}")
            return None

        logger.info(f"Loaded {len(df)} data points for {property_name}")
        return df

    except Exception as e:
        logger.error(f"Error loading learning curve data for {property_name}: {str(e)}")
        return None


def process_property_scaling(
    property_name: str,
    data_dir: Path
) -> Optional[Dict[str, Any]]:
    """
    Process scaling analysis for a single property.

    Args:
        property_name: Name of the property
        data_dir: Path to the data directory

    Returns:
        Dictionary with scaling results or None if processing fails
    """
    # Load learning curve data
    df = load_learning_curve_data(data_dir, property_name)

    if df is None:
        return None

    # Get sizes and errors (average across seeds if multiple)
    sizes = df['size'].values
    errors = df['error'].values

    # If there are multiple seeds for the same size, average the errors
    unique_sizes = np.unique(sizes)
    avg_errors = []
    for size in unique_sizes:
        mask = sizes == size
        avg_errors.append(np.mean(errors[mask]))

    sizes_unique = unique_sizes
    errors_avg = np.array(avg_errors)

    # Fit power law
    fit_result = fit_power_law(sizes_unique, errors_avg)

    if not fit_result['success']:
        logger.warning(f"Scaling fit failed for {property_name}: {fit_result['message']}")
        return None

    # Determine fit status based on R-squared
    r_squared = fit_result['r_squared']
    if r_squared >= 0.9:
        fit_status = "power-law"
    else:
        fit_status = "non-power-law"

    return {
        'property_name': property_name,
        'exponent_b': fit_result['b'],
        'intercept_a': fit_result['a'],
        'r_squared': r_squared,
        'fit_status': fit_status
    }


def main():
    """
    Main function to process all properties and save scaling results.
    """
    logger.info("Starting scaling law fitting process")

    # Get configuration
    config = get_config()
    data_dir = require_data_dir(config)

    # Ensure output directory exists
    output_dir = data_dir / 'processed'
    output_dir.mkdir(parents=True, exist_ok=True)

    # Find all learning curve files
    lc_files = list(output_dir.glob('learning_curve_*.csv'))

    if not lc_files:
        logger.error("No learning curve files found. Run train_learning_curves.py first.")
        return

    # Extract property names from filenames
    property_names = []
    for f in lc_files:
        # filename: learning_curve_{property_name}.csv
        prop_name = f.stem.replace('learning_curve_', '')
        property_names.append(prop_name)

    logger.info(f"Found {len(property_names)} properties to process")

    # Process each property
    results = []
    for prop_name in property_names:
        logger.info(f"Processing {prop_name}...")
        result = process_property_scaling(prop_name, data_dir)

        if result is not None:
            results.append(result)
            logger.info(f"  -> {result['fit_status']} (R²={result['r_squared']:.4f}, b={result['exponent_b']:.4f})")
        else:
            logger.warning(f"  -> Skipped (no valid data or fit failed)")

    if not results:
        logger.error("No valid scaling results generated")
        return

    # Create DataFrame and save
    results_df = pd.DataFrame(results)
    output_path = output_dir / 'scaling_results.csv'
    results_df.to_csv(output_path, index=False)

    logger.info(f"Saved scaling results to {output_path}")
    logger.info(f"Total properties processed: {len(results)}")
    logger.info(f"Power-law fits: {len(results_df[results_df['fit_status'] == 'power-law'])}")
    logger.info(f"Non-power-law fits: {len(results_df[results_df['fit_status'] == 'non-power-law'])}")

    # Clean up
    del results_df, results
    gc.collect()


if __name__ == '__main__':
    main()