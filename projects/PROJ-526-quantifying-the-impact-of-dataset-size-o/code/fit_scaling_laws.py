# Constants
POWER_LAW_THRESHOLD = 0.9  # R^2 threshold for "power-law" classification

def power_law(x: np.ndarray, a: float, b: float) -> np.ndarray:
  """
  Power law function: Error = a * N^-b
  x: Dataset size (N)
  a: Intercept parameter
  b: Exponent parameter (scaling exponent)
  """
  # Prevent division by zero or negative values
  x = np.maximum(x, 1e-9)
  return a * np.power(x, -b)

def fit_power_law(
    dataset_sizes: np.ndarray,
    errors: np.ndarray,
    p0: Optional[Tuple[float, float]] = None
) -> Tuple[Optional[float], Optional[float], Optional[float], bool]:
  """
  Fit a power law to the given data points.

  Args:
      dataset_sizes: Array of dataset sizes (N)
      errors: Array of errors (e.g., RMSE) for each size
      p0: Initial guess for parameters (a, b)

  Returns:
      Tuple of (exponent_b, intercept_a, r_squared, success)
      If fitting fails, returns (None, None, None, False)
  """
  try:
      # Filter out any zero or negative values
      valid_mask = (dataset_sizes > 0) & (errors > 0)
      if not np.any(valid_mask):
          logger.warning("No valid data points for fitting.")
          return None, None, None, False

      x_data = dataset_sizes[valid_mask]
      y_data = errors[valid_mask]

      # Ensure we have enough points for fitting
      if len(x_data) < 2:
          logger.warning("Insufficient data points for fitting.")
          return None, None, None, False

      # Log-normal transformation for initial guess if needed
      # log(y) = log(a) - b * log(x)
      log_x = np.log(x_data)
      log_y = np.log(y_data)
      
      # Linear regression for initial guess
      if p0 is None:
          # Simple linear regression on log-log space
          slope, intercept, _, _, _ = np.polyfit(log_x, log_y, 1, full=True)
          # y = intercept + slope * x => log(a) - b * log(x)
          # So b = -slope, a = exp(intercept)
          b_init = -slope
          a_init = np.exp(intercept)
          p0 = (a_init, b_init)
      
      # Fit the power law
      try:
          popt, pcov = curve_fit(
              power_law, x_data, y_data, p0=p0, 
              maxfev=10000, 
              bounds=(0, np.inf)  # a > 0, b > 0
          )
          
          a_fit, b_fit = popt
          
          # Calculate R^2
          y_pred = power_law(x_data, a_fit, b_fit)
          ss_res = np.sum((y_data - y_pred) ** 2)
          ss_tot = np.sum((y_data - np.mean(y_data)) ** 2)
          
          if ss_tot == 0:
              r_squared = 0.0
          else:
              r_squared = 1 - (ss_res / ss_tot)
          
          return b_fit, a_fit, r_squared, True
          
      except Exception as e:
          logger.warning(f"curve_fit failed for power law: {e}")
          return None, None, None, False
          
  except Exception as e:
      logger.error(f"Error in fit_power_law: {e}")
      return None, None, None, False

def load_learning_curve_data(data_dir: Path) -> pd.DataFrame:
  """
  Load the learning curve results from the processed data directory.
  
  Expected file: data/processed/learning_curves.csv
  """
  lc_path = data_dir / "processed" / "learning_curves.csv"
  
  if not lc_path.exists():
      raise FileNotFoundError(
          f"Learning curve data not found at {lc_path}. "
          "Run train_learning_curves.py first."
      )
  
  logger.info(f"Loading learning curve data from {lc_path}")
  df = pd.read_csv(lc_path)
  
  # Validate required columns
  required_cols = ['property_name', 'dataset_size', 'error']
  missing_cols = [col for col in required_cols if col not in df.columns]
  if missing_cols:
      raise ValueError(f"Missing required columns in learning curve data: {missing_cols}")
  
  return df

def process_property_scaling(
    df: pd.DataFrame, 
    property_name: str
) -> Optional[ScalingResult]:
  """
  Fit scaling law for a single property.
  
  Args:
      df: Full learning curve dataframe
      property_name: Name of the property to process
      
  Returns:
      ScalingResult object or None if fitting fails
  """
  # Filter data for this property
  prop_df = df[df['property_name'] == property_name].copy()
  
  if prop_df.empty:
      logger.warning(f"No data found for property: {property_name}")
      return None
  
  # Sort by dataset size
  prop_df = prop_df.sort_values('dataset_size')
  
  dataset_sizes = prop_df['dataset_size'].values.astype(float)
  errors = prop_df['error'].values.astype(float)
  
  # Fit power law
  exponent_b, intercept_a, r_squared, success = fit_power_law(dataset_sizes, errors)
  
  if not success:
      logger.warning(f"Failed to fit power law for {property_name}")
      return None
  
  # Classify fit status
  if r_squared >= POWER_LAW_THRESHOLD:
      fit_status = "power-law"
  else:
      fit_status = "non-power-law"
  
  logger.info(
      f"Property: {property_name}, "
      f"Exponent: {exponent_b:.4f}, "
      f"R^2: {r_squared:.4f}, "
      f"Status: {fit_status}"
  )
  
  return ScalingResult(
      property_name=property_name,
      exponent_b=exponent_b,
      intercept_a=intercept_a,
      r_squared=r_squared,
      fit_status=fit_status
  )

