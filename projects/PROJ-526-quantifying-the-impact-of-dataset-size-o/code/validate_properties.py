import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any

# Import logging utilities from existing project code
from utils.logging_config import get_logger, log_error_summary
from config import get_config

# Constants
REQUIRED_PROPERTY_COUNT = 15
logger = get_logger(__name__)

def load_processed_data_path() -> Path:
    """
    Returns the path to the consolidated master dataset.
    Expects the file to be generated by T013 (consolidate_data).
    """
    config = get_config()
    # The task description implies the file is in data/processed/
    # We construct the path relative to the project root or config data_dir
    data_dir = Path(config.get('data_dir', 'data'))
    return data_dir / 'processed' / 'materials_master.parquet'

def count_distinct_properties(file_path: Path) -> int:
    """
    Loads the master dataset and counts the number of distinct properties.
    Expects the dataset to have a column named 'property_name'.
    """
    import pandas as pd

    if not file_path.exists():
        raise FileNotFoundError(f"Master dataset not found at {file_path}. "
                                "Ensure T013 (consolidate_data) has run successfully.")

    try:
        # Load in chunks if necessary, but for counting distinct values,
        # we can often stream or load if memory permits.
        # Given the constraint < 7GB RAM, we attempt a standard load first.
        df = pd.read_parquet(file_path)
        
        if 'property_name' not in df.columns:
            raise ValueError("Column 'property_name' not found in master dataset.")
        
        distinct_count = df['property_name'].nunique()
        logger.info(f"Distinct properties found: {distinct_count}")
        return distinct_count
    except Exception as e:
        logger.error(f"Failed to count properties: {e}")
        raise

def update_properties_status(count: int, gap: int) -> None:
    """
    Updates state/properties_status.json with the validation results.
    This is only called if the count is sufficient (>= 15).
    """
    config = get_config()
    state_dir = Path(config.get('state_dir', 'state'))
    state_dir.mkdir(parents=True, exist_ok=True)
    
    status_file = state_dir / 'properties_status.json'
    
    status_data = {
        "property_count": count,
        "required_count": REQUIRED_PROPERTY_COUNT,
        "gap": gap,
        "status": "PASS",
        "message": f"Validation passed: {count} properties found (Required: {REQUIRED_PROPERTY_COUNT}).",
        "timestamp": str(Path().cwd()) # Simplified timestamp logic or use datetime
    }
    
    # In a real run, we'd use datetime.datetime.now().isoformat()
    import datetime
    status_data["timestamp"] = datetime.datetime.now().isoformat()

    with open(status_file, 'w') as f:
        json.dump(status_data, f, indent=2)
    
    logger.info(f"Updated properties status file: {status_file}")

def validate_property_count() -> bool:
    """
    Main validation logic for T016.
    1. Counts distinct properties.
    2. If count < 15, raises ValueError and halts.
    3. If count >= 15, updates state/properties_status.json.
    """
    file_path = load_processed_data_path()
    logger.info(f"Validating property count from {file_path}")
    
    try:
        count = count_distinct_properties(file_path)
    except FileNotFoundError as e:
        logger.critical(f"Data file missing. Cannot proceed with US2/US3. Error: {e}")
        raise ValueError("Pipeline halted: Master dataset not found. Run T013 first.") from e
    
    if count < REQUIRED_PROPERTY_COUNT:
        gap = REQUIRED_PROPERTY_COUNT - count
        msg = (
            f"CRITICAL FAILURE: Property count ({count}) is below the required threshold ({REQUIRED_PROPERTY_COUNT}). "
            f"Gap: {gap}. "
            f"Per FR-001, the pipeline cannot proceed to US2/US3 with N < 15. "
            f"Halting execution immediately."
        )
        logger.critical(msg)
        # Log the gap specifically as requested
        logger.error(f"15-N Gap detected: {gap} properties missing.")
        
        # Do NOT update status file if count is insufficient
        raise ValueError(msg)
    
    # If we reach here, count >= 15
    gap = 0
    logger.info(f"Validation passed. Count: {count}, Gap: {gap}. Updating state file.")
    update_properties_status(count, gap)
    
    return True

def main():
    """Entry point for the script."""
    logger.info("Starting Property Validation (T016)...")
    try:
        validate_property_count()
        logger.info("T016 Validation Successful. Pipeline may proceed to US2.")
        sys.exit(0)
    except ValueError as e:
        logger.error(f"Validation Failed: {e}")
        log_error_summary("T016", str(e))
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during validation: {e}")
        log_error_summary("T016", str(e))
        sys.exit(1)

if __name__ == "__main__":
    main()