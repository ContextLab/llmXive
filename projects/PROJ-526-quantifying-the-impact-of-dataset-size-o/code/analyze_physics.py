def compute_valence_electron_variance(df: pd.DataFrame) -> float:
    """
    Compute the variance of valence electron counts as a proxy for spatial locality.
    
    Args:
        df: Master dataset with Magpie descriptors.
    
    Returns:
        float: Variance of valence electron features.
    """
    # Magpie descriptors typically include 'mean_valence_electrons' or similar
    # We look for columns related to valence electrons
    valence_cols = [c for c in df.columns if 'valence' in c.lower()]
    if not valence_cols:
        # Fallback to generic numeric columns if specific naming varies
        # Assuming standard Magpie output structure
        valence_cols = [c for c in df.columns if c.startswith('mean_') and 'electrons' in c.lower()]
    
    if not valence_cols:
        logger.warning("No valence electron columns found. Using all numeric features variance.")
        numeric_cols = df.select_dtypes(include=[np.number]).columns
        if len(numeric_cols) == 0:
            return 0.0
        return df[numeric_cols].var().mean()
    
    return df[valence_cols].var().mean()

def compute_spatial_locality(df: pd.DataFrame) -> float:
    """
    Compute a metric for spatial locality based on valence electron variance.
    
    Args:
        df: Master dataset.
    
    Returns:
        float: Spatial locality metric.
    """
    variance = compute_valence_electron_variance(df)
    # Inverse relationship or direct mapping depending on definition
    # Here we return the variance as the raw metric
    return variance

def compute_symmetry_sensitivity(df: pd.DataFrame) -> float:
    """
    Compute symmetry sensitivity as the coefficient of variation (CV) of key structural features.
    
    Args:
        df: Master dataset.
    
    Returns:
        float: Symmetry sensitivity metric.
    """
    # Identify structural/geometry related columns if available
    # If only composition data, use a proxy like standard deviation of atomic properties
    numeric_cols = df.select_dtypes(include=[np.number]).columns
    if len(numeric_cols) == 0:
        return 0.0
    
    # Calculate CV for each column and average
    cv_values = []
    for col in numeric_cols:
        mean_val = df[col].mean()
        std_val = df[col].std()
        if mean_val != 0:
            cv_values.append(std_val / abs(mean_val))
    
    return np.mean(cv_values) if cv_values else 0.0

def permutation_test(
    group_a: List[float], 
    group_b: List[float], 
    n_permutations: int = 10000, 
    seed: int = 42
) -> float:
    """
    Perform a two-sample permutation test to compare the means of two groups.
    This is the primary statistical method for N < 5 as per the project amendment.
    
    Args:
        group_a: List of scaling exponents for class A (e.g., electronic).
        group_b: List of scaling exponents for class B (e.g., mechanical).
        n_permutations: Number of permutations to run.
        seed: Random seed for reproducibility.
    
    Returns:
        float: The two-sided p-value.
    """
    set_seed(seed)
    n_a = len(group_a)
    n_b = len(group_b)
    n_total = n_a + n_b
    
    if n_total < 2:
        logger.warning("Insufficient data for permutation test.")
        return 1.0
    
    # Observed statistic: difference in means
    observed_diff = np.mean(group_a) - np.mean(group_b)
    combined = np.array(group_a + group_b)
    
    # Permutation distribution
    count_extreme = 0
    for _ in range(n_permutations):
        np.random.shuffle(combined)
        perm_a = combined[:n_a]
        perm_b = combined[n_a:]
        perm_diff = np.mean(perm_a) - np.mean(perm_b)
        
        if abs(perm_diff) >= abs(observed_diff):
            count_extreme += 1
    
    p_value = count_extreme / n_permutations
    logger.info(f"Permutation test completed. P-value: {p_value:.4f}")
    return p_value

def classify_property(property_name: str) -> str:
    """
    Classify a property into 'electronic', 'mechanical', or 'other'.
    
    Args:
        property_name: Name of the material property.
    
    Returns:
        str: Classification category.
    """
    name_lower = property_name.lower()
    electronic_keywords = ['band_gap', 'conductivity', 'dielectric', 'ferroelectric', 'magnetic']
    mechanical_keywords = ['elastic', 'bulk_modulus', 'shear_modulus', 'youngs_modulus', 'hardness', 'poisson']
    
    for kw in electronic_keywords:
        if kw in name_lower:
            return 'electronic'
    for kw in mechanical_keywords:
        if kw in name_lower:
            return 'mechanical'
    
    return 'other'

def main():
    """
    Main entry point for US3: Correlation Analysis and Statistical Validation.
    Performs the Permutation Test comparing electronic vs mechanical scaling exponents.
    """
    try:
        logger.info("Starting US3: Physics Analysis and Permutation Test")
        
        # 1. Load Data
        scaling_df = load_scaling_results()
        
        # Filter for valid exponents (exclude failed fits)
        valid_df = scaling_df[scaling_df['fit_status'] == 'success'].copy()
        if valid_df.empty:
            logger.error("No successful scaling fits found. Cannot proceed.")
            sys.exit(1)
        
        # 2. Classify Properties
        valid_df['class'] = valid_df['property_name'].apply(classify_property)
        
        # Extract groups
        electronic_exponents = valid_df[valid_df['class'] == 'electronic']['exponent_b'].tolist()
        mechanical_exponents = valid_df[valid_df['class'] == 'mechanical']['exponent_b'].tolist()
        
        logger.info(f"Found {len(electronic_exponents)} electronic properties")
        logger.info(f"Found {len(mechanical_exponents)} mechanical properties")
        
        if len(electronic_exponents) < 1 or len(mechanical_exponents) < 1:
            logger.warning("Insufficient properties in one or both classes for comparison.")
            # Still attempt to run if at least one exists in each, or handle gracefully
            if not electronic_exponents or not mechanical_exponents:
                logger.error("Cannot run permutation test with empty groups.")
                sys.exit(1)
        
        # 3. Compute Physical Metrics (Optional but required by US3 context)
        master_df = load_master_dataset()
        spatial_locality = compute_spatial_locality(master_df)
        symmetry_sensitivity = compute_symmetry_sensitivity(master_df)
        
        logger.info(f"Spatial Locality Metric: {spatial_locality}")
        logger.info(f"Symmetry Sensitivity Metric: {symmetry_sensitivity}")
        
        # 4. Perform Permutation Test
        p_value = permutation_test(electronic_exponents, mechanical_exponents)
        
        logger.info(f"Permutation Test P-value (Electronic vs Mechanical): {p_value}")
        
        # 5. Save Results
        config = get_config()
        data_dir = require_data_dir(config)
        output_path = data_dir / "processed" / "final_analysis.csv"
        
        # Prepare summary data
        summary_data = {
            'test_type': ['Permutation Test'],
            'comparison': ['Electronic vs Mechanical'],
            'n_electronic': [len(electronic_exponents)],
            'n_mechanical': [len(mechanical_exponents)],
            'p_value': [p_value],
            'spatial_locality_metric': [spatial_locality],
            'symmetry_sensitivity_metric': [symmetry_sensitivity],
            'significant_at_0.05': [p_value < 0.05]
        }
        
        summary_df = pd.DataFrame(summary_data)
        summary_df.to_csv(output_path, index=False)
        
        logger.info(f"Results saved to {output_path}")
        
        # Print summary to stdout
        print(f"\n=== US3 Analysis Complete ===")
        print(f"Electronic Properties: {len(electronic_exponents)}")
        print(f"Mechanical Properties: {len(mechanical_exponents)}")
        print(f"Permutation Test P-value: {p_value:.4f}")
        print(f"Significant (p < 0.05): {'Yes' if p_value < 0.05 else 'No'}")
        print(f"Output: {output_path}")
        
    except Exception as e:
        logger.error(f"US3 Analysis failed: {e}")
        traceback.print_exc()
        sys.exit(1)

if __name__ == "__main__":
    main()