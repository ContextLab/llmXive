"""
Contract test for statistical output schema (User Story 3).

This test validates the schema of the final statistical analysis outputs
generated by the physics analysis and correlation tasks (T025, T026, T027).

It ensures that:
1. The scaling results file (from T020) contains expected columns.
2. The final analysis CSV (from T029) contains correlation metrics,
   physical characteristics, and permutation test results.
3. Data types match the specification (floats for metrics, strings for flags).

Dependencies:
- data/processed/scaling_results.csv (generated by T020)
- data/processed/final_analysis.csv (generated by T029)
"""

import os
import sys
import pytest
import pandas as pd
from pathlib import Path

# Add project root to path for imports if running from tests/
project_root = Path(__file__).parent.parent.parent
sys.path.insert(0, str(project_root))

from config import get_config

CONFIG = get_config()
DATA_DIR = CONFIG.data_dir
PROCESSED_DIR = DATA_DIR / "processed"


class TestScalingResultsSchema:
    """Contract tests for data/processed/scaling_results.csv (Output of T020)"""

    @pytest.fixture(scope="class")
    def scaling_results_path(self):
        """Locate the scaling results file."""
        path = PROCESSED_DIR / "scaling_results.csv"
        if not path.exists():
            pytest.skip(
                f"scaling_results.csv not found at {path}. "
                "Run T020 (fit_scaling_laws.py) first."
            )
        return path

    @pytest.fixture(scope="class")
    def scaling_df(self, scaling_results_path):
        """Load the scaling results dataframe."""
        return pd.read_csv(scaling_results_path)

    def test_file_exists(self, scaling_results_path):
        """Verify the file exists on disk."""
        assert scaling_results_path.exists(), "scaling_results.csv must exist"

    def test_required_columns(self, scaling_df):
        """Verify all required columns are present."""
        required_columns = {
            "property_name",
            "exponent_b",
            "intercept_a",
            "r_squared",
            "fit_status"
        }
        actual_columns = set(scaling_df.columns)
        
        missing = required_columns - actual_columns
        assert not missing, f"Missing required columns: {missing}"

    def test_data_types(self, scaling_df):
        """Verify numeric columns are numeric and status is string."""
        assert pd.api.types.is_numeric_dtype(scaling_df["exponent_b"]), "exponent_b must be numeric"
        assert pd.api.types.is_numeric_dtype(scaling_df["intercept_a"]), "intercept_a must be numeric"
        assert pd.api.types.is_numeric_dtype(scaling_df["r_squared"]), "r_squared must be numeric"
        assert pd.api.types.is_string_dtype(scaling_df["fit_status"]), "fit_status must be string"

    def test_r_squared_range(self, scaling_df):
        """Verify R-squared is within [0, 1] or NaN."""
        valid_r2 = scaling_df["r_squared"].dropna()
        if len(valid_r2) > 0:
            assert (valid_r2 >= 0).all(), "R-squared cannot be negative"
            assert (valid_r2 <= 1.0001).all(), "R-squared cannot exceed 1"

    def test_fit_status_values(self, scaling_df):
        """Verify fit_status contains valid enum values."""
        valid_statuses = {"power_law", "non-power-law", "insufficient_data", "error"}
        actual_statuses = set(scaling_df["fit_status"].unique())
        invalid = actual_statuses - valid_statuses
        assert not invalid, f"Invalid fit_status values found: {invalid}"


class TestFinalAnalysisSchema:
    """Contract tests for data/processed/final_analysis.csv (Output of T029)"""

    @pytest.fixture(scope="class")
    def final_analysis_path(self):
        """Locate the final analysis file."""
        path = PROCESSED_DIR / "final_analysis.csv"
        if not path.exists():
            pytest.skip(
                f"final_analysis.csv not found at {path}. "
                "Run T029 (visualize_results.py / finalize) first."
            )
        return path

    @pytest.fixture(scope="class")
    def final_df(self, final_analysis_path):
        """Load the final analysis dataframe."""
        return pd.read_csv(final_analysis_path)

    def test_file_exists(self, final_analysis_path):
        """Verify the file exists on disk."""
        assert final_analysis_path.exists(), "final_analysis.csv must exist"

    def test_required_columns(self, final_df):
        """Verify all required columns for US3 analysis are present."""
        # Columns expected from T025 (physics), T026 (correlation), T027 (permutation)
        required_columns = {
            "property_name",
            "spatial_locality_score",
            "symmetry_sensitivity_cv",
            "scaling_exponent_b",
            "correlation_spatial_locality",
            "p_value_spatial_locality",
            "correlation_symmetry_sensitivity",
            "p_value_symmetry_sensitivity",
            "permutation_test_p_value",
            "class_label"
        }
        actual_columns = set(final_df.columns)
        
        missing = required_columns - actual_columns
        assert not missing, f"Missing required columns: {missing}"

    def test_data_types(self, final_df):
        """Verify numeric columns are numeric."""
        numeric_cols = [
            "spatial_locality_score",
            "symmetry_sensitivity_cv",
            "scaling_exponent_b",
            "correlation_spatial_locality",
            "p_value_spatial_locality",
            "correlation_symmetry_sensitivity",
            "p_value_symmetry_sensitivity",
            "permutation_test_p_value"
        ]
        
        for col in numeric_cols:
            if col in final_df.columns:
                assert pd.api.types.is_numeric_dtype(final_df[col]), f"{col} must be numeric"

    def test_p_value_range(self, final_df):
        """Verify p-values are within [0, 1]."""
        p_value_cols = [
            "p_value_spatial_locality",
            "p_value_symmetry_sensitivity",
            "permutation_test_p_value"
        ]
        
        for col in p_value_cols:
            if col in final_df.columns:
                valid_p = final_df[col].dropna()
                if len(valid_p) > 0:
                    assert (valid_p >= 0).all(), f"{col} cannot be negative"
                    assert (valid_p <= 1.0001).all(), f"{col} cannot exceed 1"

    def test_class_label_values(self, final_df):
        """Verify class labels are consistent with project scope."""
        if "class_label" in final_df.columns:
            # Based on project scope: electronic vs mechanical
            valid_labels = {"electronic", "mechanical", "unknown", "other"}
            actual_labels = set(final_df["class_label"].dropna().astype(str).str.lower())
            # Allow for slight variations, but check for obvious errors
            for label in actual_labels:
                assert label in valid_labels, f"Unexpected class label: {label}"

    def test_no_null_scaling_exponents(self, final_df):
        """Ensure we have scaling exponents for all analyzed properties."""
        if "scaling_exponent_b" in final_df.columns:
            null_count = final_df["scaling_exponent_b"].isna().sum()
            # Note: Some properties might be excluded if they failed fitting,
            # but we expect the majority to be present.
            assert null_count < len(final_df), "Most properties should have a scaling exponent"