"""
Integration test for learning curve generation on a small subset.

This test verifies that the learning curve pipeline (US2) can:
1. Load the master dataset generated by US1.
2. Select a small subset of data for rapid execution.
3. Generate learning curves for a specific property using the configured subset sizes.
4. Output results to a temporary file and validate the schema.

Prerequisites:
- T011, T012, T013 must have run to produce `data/processed/materials_master.parquet`.
- T019 must be implemented to provide the learning curve generation logic.
"""
import os
import sys
import tempfile
import shutil
import pytest
from pathlib import Path

# Add code directory to path for imports
code_dir = Path(__file__).parent.parent.parent / "code"
sys.path.insert(0, str(code_dir))

from train_learning_curves import generate_learning_curve_for_property, load_master_dataset
from models import LearningCurve
from config import get_config
from utils.seed import set_seed

# Constants for test
TEST_PROPERTY = "band_gap"  # Typical property name, will be validated
TEST_SUBSET_SIZES = [100, 500, 1000]  # Smaller sizes for integration test speed
TEST_SEED = 42
TEST_OUTPUT_FILE = "test_learning_curve_output.csv"


def setup_module(module):
    """Ensure required data files exist before running tests."""
    config = get_config()
    master_path = config.data_dir / "processed" / "materials_master.parquet"
    if not master_path.exists():
        raise RuntimeError(
            f"Integration test requires {master_path} to exist. "
            "Please run T013 (data consolidation) first."
        )


def test_learning_curve_generation():
    """
    Integration test: Generate a learning curve for a specific property.
    
    This test:
    1. Loads the master dataset.
    2. Filters for a specific property (or the first available property if TEST_PROPERTY is missing).
    3. Runs the learning curve generation logic with small subset sizes.
    4. Validates the output structure.
    """
    config = get_config()
    set_seed(TEST_SEED)

    # 1. Load Master Dataset
    df = load_master_dataset()
    assert df is not None and not df.empty, "Master dataset is empty or failed to load."

    # Determine the property to test
    # Check if TEST_PROPERTY exists, otherwise pick the first available property column
    available_properties = [col for col in df.columns if col not in ["material_id", "composition"]]
    assert len(available_properties) > 0, "No property columns found in master dataset."
    
    target_property = TEST_PROPERTY if TEST_PROPERTY in available_properties else available_properties[0]
    
    # Filter data to ensure we have enough for the largest subset size
    # We need at least max(TEST_SUBSET_SIZES) rows for the target property
    property_data = df[df[target_property].notna()].copy()
    max_needed = max(TEST_SUBSET_SIZES)
    
    if len(property_data) < max_needed:
        pytest.skip(
            f"Insufficient data for property '{target_property}'. "
            f"Need {max_needed} rows, found {len(property_data)}. "
            "Skipping integration test for this property."
        )

    # 2. Prepare a temporary output directory
    temp_dir = tempfile.mkdtemp()
    output_path = Path(temp_dir) / TEST_OUTPUT_FILE

    try:
        # 3. Generate Learning Curve
        # We pass the filtered dataframe directly to avoid re-loading logic
        # Note: The actual function signature might expect a file path or full df.
        # Based on T019 implementation assumptions, we assume it accepts a DataFrame or path.
        # If the function expects a file path, we would save 'property_data' to a temp parquet first.
        # Assuming the function `generate_learning_curve_for_property` can work with a DF or path.
        # To be safe and aligned with typical pipeline design:
        
        # Save subset to temp parquet to mimic real pipeline flow
        temp_input_path = Path(temp_dir) / "test_input.parquet"
        property_data.to_parquet(temp_input_path)
        
        # Call the function
        # The function should return a list of LearningCurve objects or a DataFrame
        result = generate_learning_curve_for_property(
            input_path=temp_input_path,
            property_name=target_property,
            subset_sizes=TEST_SUBSET_SIZES,
            seed=TEST_SEED,
            output_path=output_path
        )
        
        # 4. Validate Output
        assert output_path.exists(), f"Output file {output_path} was not created."
        
        # If the function returns data, validate it
        if isinstance(result, list):
            assert len(result) == len(TEST_SUBSET_SIZES), f"Expected {len(TEST_SUBSET_SIZES)} results, got {len(result)}"
            for i, item in enumerate(result):
                assert isinstance(item, LearningCurve), f"Item {i} is not a LearningCurve object"
                assert item.property_name == target_property
                assert item.n_samples == TEST_SUBSET_SIZES[i]
                assert hasattr(item, 'mae') or hasattr(item, 'rmse'), "Result missing error metric"
        elif isinstance(result, dict):
            # If it returns a dict (e.g., aggregated stats)
            assert "property_name" in result
            assert result["property_name"] == target_property
        elif isinstance(result, Path):
            # If it just returns the path
            pass
        else:
            # If it returns a DataFrame
            import pandas as pd
            if isinstance(result, pd.DataFrame):
                assert "n_samples" in result.columns
                assert "mae" in result.columns or "rmse" in result.columns
                assert len(result) == len(TEST_SUBSET_SIZES)

    finally:
        # Cleanup
        shutil.rmtree(temp_dir, ignore_errors=True)


def test_learning_curve_persistence():
    """
    Verify that the generated learning curve file can be read back and matches schema.
    """
    # This relies on the previous test creating the file, but to be independent,
    # we can re-run the generation logic or assume the previous test left a known state.
    # For strict isolation, we'll re-run the generation but with a unique name.
    
    config = get_config()
    set_seed(TEST_SEED + 1) # Different seed to avoid collisions if parallel
    
    df = load_master_dataset()
    available_properties = [col for col in df.columns if col not in ["material_id", "composition"]]
    if not available_properties:
        pytest.skip("No properties available.")
    
    target_property = available_properties[0]
    property_data = df[df[target_property].notna()].copy()
    
    if len(property_data) < max(TEST_SUBSET_SIZES):
        pytest.skip("Insufficient data.")

    temp_dir = tempfile.mkdtemp()
    output_path = Path(temp_dir) / "test_persistence_output.csv"
    
    try:
        # Generate
        temp_input_path = Path(temp_dir) / "test_persist_input.parquet"
        property_data.to_parquet(temp_input_path)
        
        generate_learning_curve_for_property(
            input_path=temp_input_path,
            property_name=target_property,
            subset_sizes=TEST_SUBSET_SIZES,
            seed=TEST_SEED,
            output_path=output_path
        )
        
        # Read back
        import pandas as pd
        result_df = pd.read_csv(output_path)
        
        # Validate columns
        required_cols = ["n_samples", "mae", "rmse", "property_name"]
        for col in required_cols:
            assert col in result_df.columns, f"Missing column: {col}"
        
        # Validate row count
        assert len(result_df) == len(TEST_SUBSET_SIZES), "Row count mismatch"
        
        # Validate monotonicity (usually error decreases as N increases, though not guaranteed)
        # Just check that n_samples are sorted
        assert result_df["n_samples"].is_monotonic_increasing, "n_samples should be sorted"
        
    finally:
        shutil.rmtree(temp_dir, ignore_errors=True)