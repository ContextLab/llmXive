"""
Data model for an expert rating of a generated proposal.
"""
import hashlib
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Dict, Optional

@dataclass
class Rating:
    """
    Represents a single expert rating for a proposal metric.

    Attributes
    ----------
    rating_id : str
        Deterministic identifier for the rating (hash‑based).
    proposal_id : str
        Identifier of the proposal being rated.
    metric : str
        The evaluation metric – e.g. ``feasibility``, ``bottleneck``,
        ``alignment``.
    score : int
        Likert‑scale score (1–5).
    rater_orcid : str
        ORCID identifier of the expert providing the rating.
    mock : bool
        ``True`` if this rating was generated by the deterministic mock‑rating
        routine (dry‑run); ``False`` for real expert data.
    created_at : datetime
        Timestamp when the rating was recorded.
    metadata : Dict[str, Any]
        Optional free‑form metadata (e.g. device info, provenance).
    _hash : Optional[str]
        Internal deterministic hash of the immutable fields.
    """

    rating_id: str
    proposal_id: str
    metric: str
    score: int
    rater_orcid: str
    mock: bool = False
    created_at: datetime = field(default_factory=datetime.utcnow)
    metadata: Dict[str, Any] = field(default_factory=dict)
    _hash: Optional[str] = field(default=None, repr=False, compare=False)

    def __post_init__(self) -> None:
        """Generate a deterministic hash if not supplied."""
        if self._hash is None:
            hash_input = (
                f"{self.rating_id}|{self.proposal_id}|{self.metric}|"
                f"{self.score}|{self.rater_orcid}|{self.mock}"
            )
            self._hash = hashlib.sha256(hash_input.encode('utf-8')).hexdigest()

    @property
    def hash(self) -> str:
        """Public accessor for the deterministic hash."""
        return self._hash

    def to_dict(self) -> Dict[str, Any]:
        """Serialize the rating to a dictionary suitable for CSV/JSONL output."""
        return {
            "rating_id": self.rating_id,
            "proposal_id": self.proposal_id,
            "metric": self.metric,
            "score": self.score,
            "rater_orcid": self.rater_orcid,
            "mock": self.mock,
            "created_at": self.created_at.isoformat(),
            "metadata": self.metadata,
            "hash": self._hash,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "Rating":
        """Create a Rating instance from a dictionary (e.g. CSV row)."""
        created_at = (
            datetime.fromisoformat(data["created_at"])
            if isinstance(data.get("created_at"), str)
            else datetime.utcnow()
        )

        # CSV rows may store booleans as strings; coerce safely
        mock_val = data.get("mock", False)
        if isinstance(mock_val, str):
            mock_val = mock_val.lower() in ("true", "1", "yes")

        return cls(
            rating_id=data["rating_id"],
            proposal_id=data["proposal_id"],
            metric=data["metric"],
            score=int(data["score"]),
            rater_orcid=data["rater_orcid"],
            mock=mock_val,
            created_at=created_at,
            metadata=data.get("metadata", {}),
            _hash=data.get("hash"),
        )
