import json
import os
from pathlib import Path
from typing import Dict, Any, List, Optional
from datetime import datetime
from config import Config
from utils.logger import get_logger

logger = get_logger(__name__)

def generate_interpretation(
    exp_mean: float,
    base_mean: float,
    diff: float,
    p_value: float,
    alpha: float = 0.05
) -> str:
    """
    Generates a human-readable interpretation of the statistical comparison.
    
    Args:
        exp_mean: Mean accuracy of the experimental (Dream) model.
        base_mean: Mean accuracy of the baseline (Continuous SFT) model.
        diff: Difference (exp - base).
        p_value: P-value from the Wilcoxon signed-rank test.
        alpha: Significance level.
        
    Returns:
        A string describing the statistical findings.
    """
    significance = "statistically significant" if p_value < alpha else "not statistically significant"
    direction = "outperformed" if diff > 0 else "underperformed" if diff < 0 else "matched"
    
    if abs(diff) < 1e-6:
        direction = "matched exactly"
        
    return (
        f"The experimental Dream-State model {direction} the baseline by {diff:.4f} accuracy points. "
        f"The difference is {significance} (p={p_value:.4f}, α={alpha}). "
        f"Experimental Mean: {exp_mean:.4f}, Baseline Mean: {base_mean:.4f}."
    )

def save_comparison_report(
    config: Config,
    exp_accuracies: List[float],
    base_accuracies: List[float],
    diff: float,
    p_value: float,
    wilcoxon_statistic: float,
    seeds: List[int],
    output_path: Optional[Path] = None
) -> Path:
    """
    Saves the comparative analysis report to a JSON file.
    
    This function aggregates the results from multiple seeds (as generated by T025)
    and saves a structured report to `data/results/comparison_report.json`.
    
    Args:
        config: The project configuration object.
        exp_accuracies: List of accuracies for the experimental model across seeds.
        base_accuracies: List of accuracies for the baseline model across seeds.
        diff: Mean accuracy difference (exp - base).
        p_value: P-value from the Wilcoxon test.
        wilcoxon_statistic: The W statistic from the Wilcoxon test.
        seeds: List of random seeds used for the experiments.
        output_path: Optional path to save the report. Defaults to config.paths.results / "comparison_report.json".
        
    Returns:
        The path where the report was saved.
    """
    if output_path is None:
        output_path = config.paths.results / "comparison_report.json"
        
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    exp_mean = sum(exp_accuracies) / len(exp_accuracies) if exp_accuracies else 0.0
    base_mean = sum(base_accuracies) / len(base_accuracies) if base_accuracies else 0.0
    
    interpretation = generate_interpretation(exp_mean, base_mean, diff, p_value)
    
    report = {
        "metadata": {
            "generated_at": datetime.utcnow().isoformat() + "Z",
            "config": {
                "model_name": config.model.name,
                "dataset": config.data.dataset_name,
                "num_seeds": len(seeds),
                "alpha": 0.05,
                "statistical_test": "Wilcoxon signed-rank"
            }
        },
        "results": {
            "seeds": seeds,
            "experimental": {
                "accuracies": exp_accuracies,
                "mean": exp_mean,
                "std": (sum((x - exp_mean)**2 for x in exp_accuracies) / len(exp_accuracies))**0.5 if exp_accuracies else 0.0
            },
            "baseline": {
                "accuracies": base_accuracies,
                "mean": base_mean,
                "std": (sum((x - base_mean)**2 for x in base_accuracies) / len(base_accuracies))**0.5 if base_accuracies else 0.0
            },
            "comparison": {
                "mean_difference": diff,
                "wilcoxon_statistic": wilcoxon_statistic,
                "p_value": p_value,
                "significant_at_0_05": p_value < 0.05
            },
            "interpretation": interpretation
        }
    }
    
    logger.info(f"Saving comparison report to {output_path}")
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)
        
    logger.info("Comparison report saved successfully.")
    return output_path

def load_report(report_path: Path) -> Dict[str, Any]:
    """
    Loads a comparison report from a JSON file.
    
    Args:
        report_path: Path to the JSON report file.
        
    Returns:
        The report data as a dictionary.
        
    Raises:
        FileNotFoundError: If the report file does not exist.
        json.JSONDecodeError: If the file contains invalid JSON.
    """
    with open(report_path, 'r', encoding='utf-8') as f:
        return json.load(f)
