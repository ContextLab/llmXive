"""
Script to generate the final comparative report for T026.

This script assumes that the statistical analysis (T025) has been run
and the results are available (either via direct computation or loading
from intermediate artifacts). For this task, it demonstrates the full
pipeline of generating the report by calling the statistical analysis
functions and saving the result.

Usage:
    python code/scripts/generate_final_report.py
"""
import os
import sys
import json
from pathlib import Path
from typing import List, Dict, Any

# Add project root to path
project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from config import Config
from eval.statistical_analysis import run_wilcoxon_test, compute_accuracy_difference
from eval.reporting import save_comparison_report
from utils.logger import get_logger

logger = get_logger(__name__)

def load_seed_results(seed: int) -> Dict[str, float]:
    """
    Loads accuracy results for a specific seed.
    In a real pipeline, this would read from a specific file generated by the training run.
    Here we simulate the existence of these files or load from a known structure if available.
    For the purpose of T026 implementation, we assume the existence of a 'seed_results'
    directory or generate a deterministic set for demonstration if files are missing,
    but strictly adhering to 'real data' constraints, we will attempt to load from
    expected paths. If files don't exist, we raise an error to prevent fabrication.
    """
    # Expected path pattern based on typical training output
    # e.g., data/results/seed_{seed}_exp.json, data/results/seed_{seed}_base.json
    exp_path = project_root / "data" / "results" / f"seed_{seed}_exp.json"
    base_path = project_root / "data" / "results" / f"seed_{seed}_base.json"
    
    if not exp_path.exists() or not base_path.exists():
        raise FileNotFoundError(
            f"Missing result files for seed {seed}. "
            f"Expected: {exp_path}, {base_path}. "
            "Please run the training experiments (T024/T025) first to generate these files."
        )
        
    with open(exp_path, 'r') as f:
        exp_data = json.load(f)
    with open(base_path, 'r') as f:
        base_data = json.load(f)
        
    return {
        "exp_accuracy": exp_data.get("accuracy"),
        "base_accuracy": base_data.get("accuracy")
    }

def main():
    config = Config()
    seeds = config.training.seeds  # Should be a list of 5 ints
    
    logger.info(f"Generating report for {len(seeds)} seeds: {seeds}")
    
    exp_accuracies: List[float] = []
    base_accuracies: List[float] = []
    
    for seed in seeds:
        try:
            results = load_seed_results(seed)
            exp_accuracies.append(results["exp_accuracy"])
            base_accuracies.append(results["base_accuracy"])
            logger.info(f"Loaded seed {seed}: Exp={results['exp_accuracy']:.4f}, Base={results['base_accuracy']:.4f}")
        except FileNotFoundError as e:
            logger.error(str(e))
            logger.error("Cannot proceed with report generation without real data.")
            sys.exit(1)
    
    if not exp_accuracies:
        logger.error("No data loaded. Aborting.")
        sys.exit(1)

    # Compute statistics
    diff = compute_accuracy_difference(exp_accuracies, base_accuracies)
    stat, p_value = run_wilcoxon_test(exp_accuracies, base_accuracies)
    
    logger.info(f"Statistical Analysis Complete: Diff={diff:.4f}, p={p_value:.4f}")
    
    # Save Report
    output_path = save_comparison_report(
        config=config,
        exp_accuracies=exp_accuracies,
        base_accuracies=base_accuracies,
        diff=diff,
        p_value=p_value,
        wilcoxon_statistic=stat,
        seeds=seeds
    )
    
    logger.info(f"Final Report saved to: {output_path}")
    
    # Verify the file exists and is valid JSON
    if not output_path.exists():
        raise RuntimeError("Report file was not created.")
        
    with open(output_path, 'r') as f:
        report = json.load(f)
        
    logger.info("Report verification successful.")
    print(f"Report generated at: {output_path}")

if __name__ == "__main__":
    main()