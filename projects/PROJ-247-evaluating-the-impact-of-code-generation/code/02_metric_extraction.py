class MetricExtractionError(Exception):
    """Custom exception for metric extraction failures."""
    pass

class RepositoryNotFoundError(Exception):
    """Exception raised when a repository is not found or inaccessible."""
    pass

class BlockHistory:
    """Represents the commit history and metrics for a specific code block."""
    def __init__(self, pair_id: str, repo_id: str, block_id: str, block_type: str):
        self.pair_id = pair_id
        self.repo_id = repo_id
        self.block_id = block_id
        self.block_type = block_type  # 'LLM' or 'Human'
        self.churn_metrics: List[Dict[str, Any]] = []
        self.latency_metrics: Optional[Dict[str, Any]] = None
        self.exclusion_reason: Optional[str] = None

def setup_output_directories():
    """Ensure all required output directories exist."""
    PROCESSED_PATH.mkdir(parents=True, exist_ok=True)
    LOG_PATH.mkdir(parents=True, exist_ok=True)

def load_matched_pairs(filepath: Path = METRICS_FILE.parent / "matched_pairs.csv") -> List[Dict[str, Any]]:
    """Load matched pairs from the CSV file generated by T015."""
    if not filepath.exists():
        raise FileNotFoundError(f"Matched pairs file not found: {filepath}")
    
    pairs = []
    with open(filepath, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            pairs.append(row)
    return pairs

def parse_date(date_str: str) -> datetime:
    """Parse ISO format date string to datetime object."""
    return datetime.fromisoformat(date_str.replace('Z', '+00:00'))

def clone_repo_shallow(repo_url: str, target_dir: Path) -> None:
    """Perform a shallow clone of the repository."""
    try:
        subprocess.run(
            ['git', 'clone', '--depth', '100', repo_url, str(target_dir)],
            check=True,
            capture_output=True,
            text=True
        )
    except subprocess.CalledProcessError as e:
        raise MetricExtractionError(f"Failed to clone repository {repo_url}: {e.stderr}")

def get_commit_history_for_block(repo_path: Path, file_path: str, block_start_line: int, block_end_line: int) -> List[Dict[str, Any]]:
    """
    Retrieve commit history for a specific block of code.
    Returns a list of commits that modified this block.
    """
    commits = []
    try:
        # Get log for the file
        result = subprocess.run(
            ['git', 'log', '--pretty=format:%H|%ai|%s', '--', file_path],
            cwd=str(repo_path),
            check=True,
            capture_output=True,
            text=True
        )
        
        if not result.stdout.strip():
            return []

        for line in result.stdout.splitlines():
            parts = line.split('|')
            if len(parts) >= 3:
                commit_hash = parts[0]
                date_str = parts[1]
                message = parts[2]
                commits.append({
                    'hash': commit_hash,
                    'date': parse_date(date_str),
                    'message': message
                })
    except subprocess.CalledProcessError:
        pass # Return empty list if no history found
    return commits

def calculate_code_churn(repo_path: Path, file_path: str, block_start_line: int, block_end_line: int, commits: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Calculate code churn (lines added/deleted) for a block over its commit history.
    Excludes the initial commit.
    """
    total_added = 0
    total_deleted = 0
    
    if not commits:
        return {'lines_added': 0, 'lines_deleted': 0, 'total_churn': 0}

    # Skip the first commit (initial introduction) if we are looking at history post-introduction
    # The task says "excluding initial commit". We assume the list is ordered newest first or oldest first?
    # git log is newest first. The "initial commit" in the context of the block's life is the oldest one.
    # We iterate all commits, but we might want to skip the very first one in the history of the file if it's the creation.
    # However, usually churn is calculated over the *lifetime* of the block after creation.
    # Let's assume we process all commits except the one that created the file if the block didn't exist before.
    # For simplicity and robustness, we will process all commits returned by git log, 
    # but the task says "excluding initial commit". 
    # We will sort commits by date ascending and skip the first one.
    
    sorted_commits = sorted(commits, key=lambda x: x['date'])
    if len(sorted_commits) > 1:
        # Skip the oldest commit (initial creation)
        commits_to_analyze = sorted_commits[1:]
    else:
        commits_to_analyze = [] # Only one commit, likely creation, so no churn after creation

    for commit in commits_to_analyze:
        # Get diff stats for this commit for the specific file
        try:
            result = subprocess.run(
                ['git', 'show', '--numstat', '--format=', commit['hash'], '--', file_path],
                cwd=str(repo_path),
                check=True,
                capture_output=True,
                text=True
            )
            
            for line in result.stdout.splitlines():
                if line.startswith('\t'):
                    continue # Binary or no stats
                parts = line.split('\t')
                if len(parts) >= 3:
                    added = parts[0]
                    deleted = parts[1]
                    if added != '-':
                        total_added += int(added)
                    if deleted != '-':
                        total_deleted += int(deleted)
        except subprocess.CalledProcessError:
            continue

    return {
        'lines_added': total_added,
        'lines_deleted': total_deleted,
        'total_churn': total_added + total_deleted
    }

def extract_bug_fix_latency(commit_message: str, file_path: str) -> Optional[int]:
    """
    Parse commit message for "Fixes #N" or "Closes #N".
    Logic: Map specific code block changes to issues.
    Returns days to fix (latency) if a fix is identified, else None.
    For this implementation, we return the latency in days if a fix keyword is found.
    Note: Actual mapping of block to issue requires complex diff analysis.
    Here we assume if the commit message has a fix keyword and modifies the file, it counts.
    The "days to fix" is calculated from the block's introduction date to this fix commit.
    However, this function only parses the message. The latency calculation happens in the caller.
    """
    import re
    # Pattern to find issue numbers
    pattern = r'(?:Fixes|Closes)\s+#(\d+)'
    match = re.search(pattern, commit_message, re.IGNORECASE)
    if match:
        return int(match.group(1))
    return None

def extract_metrics_for_pair(pair: Dict[str, Any], repo_cache: Dict[str, Path], logger: logging.Logger) -> Optional[BlockHistory]:
    """
    Extract churn and latency metrics for a single matched pair.
    Handles edge cases: null latency (excluded from latency analysis, retained for churn).
    """
    pair_id = pair.get('pair_id')
    repo_id = pair.get('repo_id')
    block_id = pair.get('block_id')
    block_type = pair.get('label') # 'LLM' or 'Human'
    file_path = pair.get('file_path')
    start_line = int(pair.get('start_line', 0))
    end_line = int(pair.get('end_line', 0))
    repo_url = pair.get('repo_url')
    introduction_date = pair.get('introduction_date') # ISO string

    if not all([pair_id, repo_id, block_id, file_path, repo_url, introduction_date]):
        logger.warning(f"Skipping pair {pair_id}: missing required fields.")
        return None

    history = BlockHistory(pair_id, repo_id, block_id, block_type)
    
    # Check if repo is in cache, if not clone
    if repo_id not in repo_cache:
        cache_dir = Path("data/repos")
        cache_dir.mkdir(parents=True, exist_ok=True)
        repo_path = cache_dir / repo_id
        
        if repo_path.exists():
            # Verify it's a valid git repo
            if not (repo_path / ".git").exists():
                shutil.rmtree(repo_path)
                repo_path.mkdir(parents=True, exist_ok=True)
                clone_repo_shallow(repo_url, repo_path)
        else:
            try:
                clone_repo_shallow(repo_url, repo_path)
            except MetricExtractionError as e:
                # T024: Handle repo deletion/private status
                logger.error(f"Repository {repo_id} ({repo_url}) not found or inaccessible: {e}")
                history.exclusion_reason = f"Repository not found: {e}"
                # Retain for churn? No, if repo is missing, we can't calculate churn either.
                # But the task says "retain for churn" only if latency is null.
                # If repo is missing, we can't do anything. We return the history with exclusion reason.
                return history
        
        repo_cache[repo_id] = repo_path

    repo_path = repo_cache[repo_id]
    
    try:
        commits = get_commit_history_for_block(repo_path, file_path, start_line, end_line)
        
        # Calculate Churn
        churn_stats = calculate_code_churn(repo_path, file_path, start_line, end_line, commits)
        history.churn_metrics = churn_stats
        
        # Calculate Latency
        latency_days = None
        fix_issue_id = None
        
        intro_dt = parse_date(introduction_date)
        
        # Find the first commit that is a bug fix
        sorted_commits = sorted(commits, key=lambda x: x['date'])
        for commit in sorted_commits:
            issue_num = extract_bug_fix_latency(commit['message'], file_path)
            if issue_num:
                fix_dt = commit['date']
                if fix_dt > intro_dt:
                    latency_days = (fix_dt - intro_dt).days
                    fix_issue_id = issue_num
                    break
        
        if latency_days is not None:
            history.latency_metrics = {
                'days_to_fix': latency_days,
                'issue_id': fix_issue_id,
                'fix_commit': sorted([c for c in commits if c['message'].lower().count('fix') > 0 or c['message'].lower().count('close') > 0], key=lambda x: x['date'])[0]['hash'] if any('fix' in c['message'].lower() or 'close' in c['message'].lower() for c in commits) else None
            }
        else:
            # Edge Case: Null Latency
            # Exclude from latency analysis, but retain for churn.
            history.exclusion_reason = "null_latency"
            logger.info(f"Pair {pair_id}: Null latency detected. Retained for churn analysis, excluded from latency analysis.")
            
    except Exception as e:
        logger.error(f"Error processing pair {pair_id}: {e}")
        history.exclusion_reason = f"processing_error: {str(e)}"
        return history

    return history

def validate_schema(record: Dict[str, Any]) -> bool:
    """Validate that a metric record has the required schema."""
    required_fields = ['pair_id', 'repo_id', 'block_id', 'block_type', 'lines_added', 'lines_deleted', 'total_churn']
    return all(field in record for field in required_fields)

def run_extraction_pipeline(logger: logging.Logger):
    """Main pipeline to extract metrics for all matched pairs."""
    setup_output_directories()
    
    pairs = load_matched_pairs()
    repo_cache: Dict[str, Path] = {}
    results = []
    exclusions = []

    logger.info(f"Processing {len(pairs)} matched pairs...")

    for pair in pairs:
        history = extract_metrics_for_pair(pair, repo_cache, logger)
        if not history:
            continue

        # Construct record for churn (always included if churn was calculated)
        record = {
            'pair_id': history.pair_id,
            'repo_id': history.repo_id,
            'block_id': history.block_id,
            'block_type': history.block_type,
            'lines_added': history.churn_metrics['lines_added'],
            'lines_deleted': history.churn_metrics['lines_deleted'],
            'total_churn': history.churn_metrics['total_churn'],
        }

        if history.latency_metrics:
            record['days_to_fix'] = history.latency_metrics['days_to_fix']
            record['issue_id'] = history.latency_metrics['issue_id']
            record['latency_excluded'] = False
        else:
            # Explicitly mark as null for clarity in analysis
            record['days_to_fix'] = None
            record['issue_id'] = None
            record['latency_excluded'] = True
            # Log exclusion reason
            exclusions.append({
                'pair_id': history.pair_id,
                'reason': history.exclusion_reason or 'null_latency',
                'timestamp': datetime.now().isoformat()
            })

        results.append(record)

    # Save metrics
    if results:
        with open(METRICS_FILE, 'w', newline='', encoding='utf-8') as f:
            fieldnames = ['pair_id', 'repo_id', 'block_id', 'block_type', 'lines_added', 'lines_deleted', 'total_churn', 'days_to_fix', 'issue_id', 'latency_excluded']
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(results)
        logger.info(f"Metrics saved to {METRICS_FILE}")
    else:
        logger.warning("No metrics extracted.")

    # Save exclusion log
    if exclusions:
        with open(EXCLUSIONS_LOG, 'w', encoding='utf-8') as f:
            for exc in exclusions:
                f.write(json.dumps(exc) + '\n')
        logger.info(f"Exclusion log saved to {EXCLUSIONS_LOG}")

def main():
    setup_logging()
    logger = get_logger(__name__)
    logger.info("Starting Metric Extraction Pipeline (T023: Edge Case Handling)")
    try:
        run_extraction_pipeline(logger)
        logger.info("Pipeline completed successfully.")
    except Exception as e:
        logger.error(f"Pipeline failed: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()
