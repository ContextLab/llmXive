def load_metrics_from_file(file_path: Path, required_cols: Set[str]) -> pd.DataFrame:
    """Load a CSV file and validate it has the required columns."""
    if not file_path.exists():
        raise FileNotFoundError(f"Required metrics file not found: {file_path}")
    
    df = pd.read_csv(file_path)
    missing_cols = required_cols - set(df.columns)
    if missing_cols:
        raise ValueError(f"File {file_path} missing required columns: {missing_cols}")
    
    # Ensure block_id is string for consistent joining
    df["block_id"] = df["block_id"].astype(str)
    return df


def merge_metrics(latency_df: pd.DataFrame, churn_df: pd.DataFrame) -> pd.DataFrame:
    """Merge latency and churn metrics on block_id."""
    # Outer join to keep all blocks, but we will filter later based on T023 logic
    merged = pd.merge(
        latency_df, 
        churn_df, 
        on="block_id", 
        how="outer"
    )
    return merged


