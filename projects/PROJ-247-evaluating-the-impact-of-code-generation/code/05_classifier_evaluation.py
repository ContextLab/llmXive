logger = get_logger(__name__)

def setup_output_directories():
    """Ensure output directories exist."""
    output_dir = Path("data/ground_truth")
    output_dir.mkdir(parents=True, exist_ok=True)
    return output_dir

def load_ground_truth_labels(file_path: str) -> List[Dict[str, Any]]:
    """
    Load the manually verified ground truth labels.
    Expected CSV columns: block_id, ground_truth_label (LLM or Human)
    """
    ground_truth_data = []
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Ground truth file not found: {file_path}")
    
    with open(file_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Normalize labels to match LabelType enum or string expectations
            label = row.get('ground_truth_label', '').strip().upper()
            if label not in ['LLM', 'HUMAN']:
                logger.warning(f"Invalid ground truth label '{label}' in row {row}")
                continue
            
            ground_truth_data.append({
                'block_id': row.get('block_id'),
                'label': label
            })
    return ground_truth_data

def load_predicted_labels(file_path: str) -> List[Dict[str, Any]]:
    """
    Load the predicted labels from the data curation process.
    This file is generated by code/01_data_curation.py (tag_blocks_with_classifier).
    Expected CSV columns: block_id, predicted_label, confidence
    """
    predicted_data = []
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Predicted labels file not found: {file_path}")
    
    with open(file_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            label = row.get('predicted_label', '').strip().upper()
            if label not in ['LLM', 'HUMAN']:
                continue # Skip invalid predictions
            
            try:
                confidence = float(row.get('confidence', 0.0))
            except ValueError:
                confidence = 0.0

            predicted_data.append({
                'block_id': row.get('block_id'),
                'label': label,
                'confidence': confidence
            })
    return predicted_data

def calculate_metrics(ground_truth: List[Dict], predicted: List[Dict]) -> Dict[str, Any]:
    """
    Calculate Precision and Recall for the LLM class.
    
    Metrics:
    - Precision: TP / (TP + FP) -> Of those predicted LLM, how many were actually LLM?
    - Recall: TP / (TP + FN) -> Of those actually LLM, how many did we catch?
    
    Note: Since this is a binary classification (LLM vs Human), we calculate
    metrics for the 'LLM' class specifically as per FR-007 requirements for
    code generation impact analysis.
    """
    # Create lookup for ground truth
    gt_map = {item['block_id']: item['label'] for item in ground_truth}
    pred_map = {item['block_id']: item['label'] for item in predicted}
    
    # Identify common block IDs
    common_ids = set(gt_map.keys()) & set(pred_map.keys())
    
    if not common_ids:
        raise ValueError("No matching block IDs between ground truth and predictions.")
    
    tp = 0 # True Positive: GT=LLM, Pred=LLM
    fp = 0 # False Positive: GT=Human, Pred=LLM
    fn = 0 # False Negative: GT=LLM, Pred=Human
    
    for block_id in common_ids:
        gt_label = gt_map[block_id]
        pred_label = pred_map[block_id]
        
        if gt_label == 'LLM':
            if pred_label == 'LLM':
                tp += 1
            else:
                fn += 1
        elif gt_label == 'HUMAN':
            if pred_label == 'LLM':
                fp += 1
            # True Negatives (TN) are not strictly needed for Precision/Recall of LLM class
            # but good to track if needed later: TN += 1
    
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1_score = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
    
    return {
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1_score": round(f1_score, 4),
        "true_positives": tp,
        "false_positives": fp,
        "false_negatives": fn,
        "total_evaluated": len(common_ids)
    }

def save_metrics(metrics: Dict[str, Any], output_path: str):
    """Save the calculated metrics to a JSON file."""
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(metrics, f, indent=2)
    logger.info(f"Classifier metrics saved to {output_path}")

def main():
    """
    Main entry point for T017b: Calculate classifier precision and recall.
    Depends on T017a (manual_labels.csv) and the output of T013 (predictions in blocks.csv).
    """
    setup_logging()
    setup_output_directories()
    
    # Paths relative to project root
    ground_truth_path = "data/ground_truth/manual_labels.csv"
    # The predictions are typically saved in the main blocks CSV generated by 01_data_curation.py
    # We assume the full block dataset with predictions is available there.
    # If 01_data_curation.py splits them, we might need a specific prediction file.
    # Based on T013 description, blocks are tagged and saved. Let's assume a standard location
    # or derive from the curation process. For robustness, we look for a specific prediction file
    # or the main blocks file.
    # The task T017b depends on T017a. T017a selects from the matched pairs/blocks.
    # We will look for the main blocks file generated by 01_data_curation.py.
    # If not found, we assume a specific file name if the pipeline splits it.
    # Standard convention from T013: save_blocks_to_csv.
    # Let's assume the file is data/processed/blocks.csv or similar. 
    # However, T013 says "save blocks to CSV". T017a selects from "matched pairs".
    # To be safe, we look for the file containing the 'predicted_label' column.
    # If the project follows T015 output (matched_pairs.csv), the predictions might be there.
    # Let's try to load from a standard location or the one generated by T013.
    # Assuming the main blocks file is data/processed/blocks.csv based on typical pipeline flow.
    # If the user ran T013, it should have created a file.
    # Let's check for data/processed/blocks.csv first, then data/processed/matched_pairs.csv.
    
    predicted_path_candidates = [
        "data/processed/blocks.csv",
        "data/processed/matched_pairs.csv",
        "data/raw/blocks.csv"
    ]
    
    predicted_path = None
    for candidate in predicted_path_candidates:
        if os.path.exists(candidate):
            predicted_path = candidate
            break
    
    if not predicted_path:
        # If no standard file found, we might need to check if the user specified a path
        # or if the file is in the data/ground_truth directory if T017a saved it there with predictions?
        # T017a says "save to data/ground_truth/manual_labels.csv". It doesn't say it saves predictions.
        # We must rely on the main blocks file.
        # If the file doesn't exist, we fail loudly as per constraints.
        raise FileNotFoundError(
            "Could not find predicted labels file. Expected one of: " + ", ".join(predicted_path_candidates) + 
            ". Ensure T013 (tag_blocks_with_classifier) has been run and saved blocks."
        )
    
    logger.info(f"Loading ground truth from {ground_truth_path}")
    logger.info(f"Loading predictions from {predicted_path}")
    
    try:
        gt_data = load_ground_truth_labels(ground_truth_path)
        pred_data = load_predicted_labels(predicted_path)
        
        if not gt_data:
            raise ValueError("Ground truth file is empty.")
        if not pred_data:
            raise ValueError("Predicted labels file is empty.")
        
        metrics = calculate_metrics(gt_data, pred_data)
        
        output_file = "data/ground_truth/classifier_metrics.json"
        save_metrics(metrics, output_file)
        
        print(f"Calculation complete. Metrics: {json.dumps(metrics, indent=2)}")
        
    except Exception as e:
        logger.error(f"Error calculating metrics: {e}")
        raise

if __name__ == "__main__":
    main()
