"""
Contract tests for src/config.py against contracts/config_schema.json.

Uses pytest-jsonschema to validate that the configuration generated by
src/config.py strictly adheres to the JSON Schema defined in
contracts/config_schema.json.

This ensures that paths, seeds, and API keys are correctly structured
and that no hardcoded secrets are present (as per contract).
"""
import json
import os
import pytest
from pathlib import Path
from typing import Any, Dict

# Import the config generator and the Config class
from src.config import Config, get_config

# Import jsonschema validator
try:
    import jsonschema
    from jsonschema import validate, ValidationError
except ImportError:
    pytest.skip("jsonschema is not installed", allow_module_level=True)

def get_project_root() -> Path:
    """Determine the project root directory."""
    # Assume the project root is 3 levels up from this file:
    # tests/contract -> tests -> code -> root
    # However, based on the API surface, tests are in 'code/tests'.
    # So: tests/contract -> tests -> code -> (root)
    current = Path(__file__).resolve()
    return current.parent.parent.parent

def load_schema() -> Dict[str, Any]:
    """Load the JSON schema from the contracts directory."""
    root = get_project_root()
    schema_path = root / "contracts" / "config_schema.json"
    
    if not schema_path.exists():
        pytest.fail(f"Schema file not found at {schema_path}. "
                    "Ensure contracts/config_schema.json exists.")
    
    with open(schema_path, "r", encoding="utf-8") as f:
        return json.load(f)

def load_config_dict() -> Dict[str, Any]:
    """
    Load the configuration as a dictionary.
    
    We use get_config() which returns a Config dataclass.
    We convert it to a dict for JSON Schema validation.
    """
    config_obj = get_config()
    # Convert dataclass to dict
    if hasattr(config_obj, '__dict__'):
        return config_obj.__dict__
    elif hasattr(config_obj, 'to_dict'):
        return config_obj.to_dict()
    else:
        # Fallback: attempt to serialize via json
        import dataclasses
        if dataclasses.is_dataclass(config_obj):
            return dataclasses.asdict(config_obj)
        raise ValueError("Config object is not serializable to dict")

@pytest.fixture(scope="module")
def config_schema():
    """Fixture to load the JSON schema once per module."""
    return load_schema()

@pytest.fixture(scope="module")
def config_data():
    """Fixture to load the current configuration data."""
    return load_config_dict()

class TestConfigContract:
    """
    Contract tests ensuring src/config.py output matches contracts/config_schema.json.
    """

    def test_config_schema_exists(self, config_schema):
        """Verify the schema itself is valid JSON and has required root keys."""
        assert isinstance(config_schema, dict), "Schema must be a dictionary"
        assert "type" in config_schema, "Schema must define a type"
        assert config_schema["type"] == "object", "Root schema must be an object"
        assert "properties" in config_schema, "Schema must define properties"

    def test_config_structure_matches_schema(self, config_schema, config_data):
        """
        Validate the entire config dictionary against the schema.
        
        This checks:
        - Required fields are present
        - Field types match (string, integer, object, etc.)
        - Nested structures match
        """
        try:
            validate(instance=config_data, schema=config_schema)
        except ValidationError as e:
            pytest.fail(f"Configuration does not match schema: {e.message} "
                        f"at path: {list(e.path)}")

    def test_no_hardcoded_secrets(self, config_data):
        """
        Contract check: Ensure no hardcoded secrets are present.
        
        The schema should ideally define patterns or enums that prevent
        obvious placeholders like 'YOUR_API_KEY' or 'secret'.
        We perform a runtime check for common placeholder patterns as a secondary safeguard.
        """
        secret_patterns = ["YOUR_", "XXX", "CHANGE_ME", "INSERT_", "PASTE_"]
        
        def check_value(obj, path=""):
            if isinstance(obj, dict):
                for k, v in obj.items():
                    check_value(v, f"{path}.{k}")
            elif isinstance(obj, str):
                for pattern in secret_patterns:
                    if pattern in obj.upper():
                        pytest.fail(f"Potential hardcoded secret found at {path}: '{obj}'")
        
        check_value(config_data)

    def test_required_paths_exist(self, config_data):
        """
        Verify that paths defined in the config actually exist on the filesystem.
        
        While the schema validates the *structure* of the path string,
        this contract test ensures the paths point to real directories/files
        as expected by the pipeline.
        """
        root = get_project_root()
        paths_to_check = []
        
        # Extract path fields from config based on common naming or schema inspection
        # We iterate through the config data to find fields that look like paths
        def collect_paths(obj, parent_key=""):
            for k, v in obj.items():
                current_key = f"{parent_key}.{k}" if parent_key else k
                if isinstance(v, str) and (v.endswith('/') or v.endswith('\\') or '.' in v):
                    # Heuristic: if it looks like a path, check it
                    # Exclude obvious non-paths like 'seed' or 'api_key' if they contain dots
                    if k.lower() not in ['seed', 'api_key', 'token', 'password']:
                        paths_to_check.append((current_key, v))
                elif isinstance(v, dict):
                    collect_paths(v, current_key)

        collect_paths(config_data)
        
        for key, path_str in paths_to_check:
            if path_str:
                full_path = root / path_str if not path_str.startswith('/') else Path(path_str)
                # Only check if the path is relative to project root or absolute
                # We skip checks for external absolute paths that might not exist in CI
                if not full_path.is_absolute() or full_path.exists():
                    if not full_path.exists():
                        # Allow some flexibility for optional paths if schema marks them optional
                        # But if the config explicitly set it, it should exist
                        # For this contract, we assert existence for core paths
                        if "data" in key.lower() or "output" in key.lower():
                            pytest.fail(f"Configured path does not exist: {key} -> {full_path}")
