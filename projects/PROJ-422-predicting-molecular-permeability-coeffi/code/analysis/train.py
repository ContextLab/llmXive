"""
Training orchestrator for the molecular permeability pipeline.

This script performs the following steps:
1. Loads the train / test CSV splits produced by ``code/data/split.py``.
2. Trains the GNN model (CPU‑only) using the utilities from ``models.gnn``.
3. Trains a Random Forest baseline using the utilities from ``models.rf``.
4. Evaluates both models on the validation split and records:
   - total training time (hours)
   - peak memory usage (GB)
   - ``no_significant_improvement`` flag (True if GNN validation RMSE ≥ RF validation RMSE)
5. Writes a simple hand‑off document ``results/results.md`` that references the
   key artefacts generated by the pipeline.

The script is intended to be executed as a module:
    python -m code.analysis.train
"""

import json
import logging
import time
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import psutil
import torch
from torch_geometric.loader import DataLoader
from sklearn.metrics import mean_squared_error

from models.gnn import (
    _build_graph_dataset,
    train_gnn,
    create_mpnn_model,
    validate_epoch,
)
from models.rf import train_random_forest, predict
from llmxive_toolkit import paths, get_logger

# ----------------------------------------------------------------------
# Logging
# ----------------------------------------------------------------------
log = get_logger(__name__)

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def _load_split(split_name: str) -> pd.DataFrame:
    """
    Load a train or test split CSV from ``data/processed``.
    """
    csv_path = paths.data("processed", f"{split_name}.csv")
    if not csv_path.is_file():
        raise FileNotFoundError(f"{split_name} split not found at {csv_path}")
    return pd.read_csv(csv_path)

def _determine_target_column(df: pd.DataFrame) -> str:
    """Return the recognised target column name."""
    for col in ["permeability", "permeability_coefficient", "target"]:
        if col in df.columns:
            return col
    raise ValueError("No recognised target column found in dataset.")

def _prepare_gnn_loaders(
    df_train: pd.DataFrame, target_col: str
) -> tuple[DataLoader, DataLoader, list[int]]:
    """
    Build PyTorch‑Geometric Data objects for the GNN and split a small
    validation set (10 % of the training data, at least one sample).

    Returns the training DataLoader, validation DataLoader, and the list of
    validation indices (relative to ``df_train``) for later RF evaluation.
    """
    graphs = _build_graph_dataset(df_train, target_col=target_col)

    val_size = max(1, int(0.1 * len(graphs)))
    np.random.seed(42)
    indices = np.random.permutation(len(graphs))
    val_idx, train_idx = indices[:val_size], indices[val_size:]

    train_subset = [graphs[i] for i in train_idx]
    val_subset = [graphs[i] for i in val_idx]

    train_loader = DataLoader(train_subset, batch_size=32, shuffle=True)
    val_loader = DataLoader(val_subset, batch_size=32, shuffle=False)

    return train_loader, val_loader, val_idx.tolist()

def _train_random_forest(df_train: pd.DataFrame, target_col: str) -> Path:
    """
    Train a RandomForestRegressor on the standard descriptor columns and
    write the pickle to ``code/models/rf.pkl``.
    """
    descriptor_cols = [
        c
        for c in df_train.columns
        if c
        not in [
            "smiles",
            "mol_valid",
            "mol_graph",
            "polymer_type",
            target_col,
        ]
    ]
    X = df_train[descriptor_cols].values.astype(np.float32)
    y = df_train[target_col].values.astype(np.float32)

    model = train_random_forest(X, y)

    rf_path = Path("code") / "models" / "rf.pkl"
    rf_path.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump(model, rf_path)
    log.info(f"Random Forest model saved to {rf_path}")
    return rf_path

def _evaluate_gnn_on_loader(
    checkpoint_path: Path, loader: DataLoader, target_col: str
) -> float:
    """
    Load the best GNN checkpoint and compute RMSE on the provided loader.
    """
    checkpoint = torch.load(checkpoint_path, map_location=torch.device("cpu"))
    model_config = checkpoint.get("model_config", {})
    # Re‑create model with the saved configuration
    model = create_mpnn_model(**model_config)
    model.load_state_dict(checkpoint["model_state_dict"])
    model.eval()

    all_preds = []
    all_trues = []

    with torch.no_grad():
        for batch in loader:
            batch = batch.to(torch.device("cpu"))
            out = model(batch.x, batch.edge_index, batch.batch).squeeze()
            all_preds.append(out.cpu().numpy())
            all_trues.append(batch.y.squeeze().cpu().numpy())

    y_pred = np.concatenate(all_preds)
    y_true = np.concatenate(all_trues)
    rmse = np.sqrt(mean_squared_error(y_true, y_pred))
    return float(rmse)

def _evaluate_rf_on_validation(
    rf_path: Path,
    df_train: pd.DataFrame,
    target_col: str,
    val_indices: list[int],
) -> float:
    """
    Load the RF model and compute RMSE on the validation rows.
    """
    model = joblib.load(rf_path)

    descriptor_cols = [
        c
        for c in df_train.columns
        if c
        not in [
            "smiles",
            "mol_valid",
            "mol_graph",
            "polymer_type",
            target_col,
        ]
    ]

    X_val = df_train.iloc[val_indices][descriptor_cols].values.astype(np.float32)
    y_val = df_train.iloc[val_indices][target_col].values.astype(np.float32)

    y_pred = predict(model, X_val)
    rmse = np.sqrt(mean_squared_error(y_val, y_pred))
    return float(rmse)

# ----------------------------------------------------------------------
# Main orchestration
# ----------------------------------------------------------------------
def main():
    log.info("=== GNN + RF training step (T007) ===")
    start_time = time.time()
    peak_memory = 0.0

    # ------------------------------------------------------------------
    # Load data splits
    # ------------------------------------------------------------------
    df_train = _load_split("train")
    # ``df_test`` is not needed for the current orchestration but loaded for completeness
    _ = _load_split("test")

    target_col = _determine_target_column(df_train)

    # ------------------------------------------------------------------
    # Train GNN
    # ------------------------------------------------------------------
    train_loader, val_loader, val_indices = _prepare_gnn_loaders(
        df_train, target_col
    )

    checkpoint_path = Path("code") / "models" / "gnn.pt"
    checkpoint_path.parent.mkdir(parents=True, exist_ok=True)

    train_gnn(
        train_loader=train_loader,
        val_loader=val_loader,
        checkpoint_path=checkpoint_path,
        max_epochs=50,
        patience=5,
        device=torch.device("cpu"),
    )
    log.info(f"GNN checkpoint written to {checkpoint_path}")

    # Record memory after GNN training
    peak_memory = max(
        peak_memory,
        psutil.Process().memory_info().rss / (1024 ** 3),
    )

    # ------------------------------------------------------------------
    # Train Random Forest baseline
    # ------------------------------------------------------------------
    rf_path = _train_random_forest(df_train, target_col)

    # Record memory after RF training
    peak_memory = max(
        peak_memory,
        psutil.Process().memory_info().rss / (1024 ** 3),
    )

    # ------------------------------------------------------------------
    # Evaluation on validation split
    # ------------------------------------------------------------------
    gnn_val_rmse = _evaluate_gnn_on_loader(
        checkpoint_path, val_loader, target_col
    )
    rf_val_rmse = _evaluate_rf_on_validation(
        rf_path, df_train, target_col, val_indices
    )
    log.info(f"GNN validation RMSE: {gnn_val_rmse:.4f}")
    log.info(f"RF validation RMSE: {rf_val_rmse:.4f}")

    no_significant_improvement = gnn_val_rmse >= rf_val_rmse
    log.info(
        f"no_significant_improvement flag set to {no_significant_improvement}"
    )

    # ------------------------------------------------------------------
    # Write training log (including the new flag)
    # ------------------------------------------------------------------
    total_hours = (time.time() - start_time) / 3600.0
    training_log = {
        "total_hours": total_hours,
        "peak_gb": peak_memory,
        "no_significant_improvement": no_significant_improvement,
    }
    log_path = paths.results("training_log.json")
    with log_path.open("w", encoding="utf-8") as f:
        json.dump(training_log, f, indent=2)
    log.info(f"Training log written to {log_path}")

    # ------------------------------------------------------------------
    # Hand‑off document
    # ------------------------------------------------------------------
    handoff_path = paths.results("results.md")
    handoff_content = f"""# Pipeline Hand‑off Document

- **Dataset source**: `data/raw/permeability_data.csv`
- **GNN checkpoint**: `code/models/gnn.pt`
- **Random Forest model**: `code/models/rf.pkl`
- **Training log**: `results/training_log.json`
- **Metrics (to be generated later)**: `results/metrics.json`

All files are stored relative to the project root.
"""
    with handoff_path.open("w", encoding="utf-8") as f:
        f.write(handoff_content)
    log.info(f"Hand‑off document written to {handoff_path}")

if __name__ == "__main__":
    main()