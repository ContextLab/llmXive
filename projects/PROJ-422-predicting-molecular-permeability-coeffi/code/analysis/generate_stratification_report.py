"""
Generate Stratification Report for US1.

This module loads split metadata and distribution statistics generated by
the data split pipeline (T017) and produces a markdown report confirming
the split strategy (stratified vs random), retention rates, and distribution
differences.

Artifacts:
    results/stratification_report.md
"""
import json
import logging
import sys
from pathlib import Path
from datetime import datetime
import pandas as pd

# Configure logging for this module
logger = logging.getLogger(__name__)

def load_split_metadata(metadata_path: Path) -> dict:
    """
    Load the split metadata generated by code/data/split.py.
    
    Expected keys:
        - split_strategy: 'stratified' or 'random'
        - stratification_column: name of column used for stratification (if any)
        - retention_rate: float (0-1)
        - total_rows: int
        - train_rows: int
        - test_rows: int
        - warning: str (optional, if fallback to random split)
        - config_mode: str (e.g., 'experimental', 'proxy')
    
    Args:
        metadata_path: Path to split_metadata.json
    
    Returns:
        Dictionary containing split metadata
    
    Raises:
        FileNotFoundError: If metadata file does not exist
        json.JSONDecodeError: If file is not valid JSON
    """
    if not metadata_path.exists():
        raise FileNotFoundError(f"Split metadata not found at {metadata_path}")
    
    with open(metadata_path, 'r') as f:
        return json.load(f)

def load_distribution_stats(stats_path: Path) -> dict:
    """
    Load distribution statistics for the stratification column.
    
    Expected keys:
        - classes: list of class values
        - train_distribution: dict mapping class -> proportion in train
        - test_distribution: dict mapping class -> proportion in test
        - max_diff: float (max absolute difference between train/test proportions)
        - threshold: float (threshold for acceptable difference, default 0.05)
    
    Args:
        stats_path: Path to distribution_stats.json
    
    Returns:
        Dictionary containing distribution statistics
    
    Raises:
        FileNotFoundError: If stats file does not exist
        json.JSONDecodeError: If file is not valid JSON
    """
    if not stats_path.exists():
        # Return empty stats if file doesn't exist (e.g., random split)
        return {
            "classes": [],
            "train_distribution": {},
            "test_distribution": {},
            "max_diff": 0.0,
            "threshold": 0.05,
            "note": "No stratification performed"
        }
    
    with open(stats_path, 'r') as f:
        return json.load(f)

def format_distribution(train_dist: dict, test_dist: dict, classes: list) -> str:
    """
    Format distribution statistics as a markdown table.
    
    Args:
        train_dist: Dictionary of class -> proportion in training set
        test_dist: Dictionary of class -> proportion in test set
        classes: List of class values
    
    Returns:
        Formatted markdown table string
    """
    lines = []
    lines.append("| Class | Train Proportion | Test Proportion | Difference |")
    lines.append("|-------|------------------|-----------------|------------|")
    
    for cls in classes:
        train_prop = train_dist.get(cls, 0.0)
        test_prop = test_dist.get(cls, 0.0)
        diff = abs(train_prop - test_prop)
        lines.append(f"| {cls} | {train_prop:.4f} | {test_prop:.4f} | {diff:.4f} |")
    
    return "\n".join(lines)

def generate_report(metadata: dict, distribution_stats: dict) -> str:
    """
    Generate the stratification report in Markdown format.
    
    Args:
        metadata: Split metadata dictionary
        distribution_stats: Distribution statistics dictionary
    
    Returns:
        Formatted markdown report string
    """
    report_lines = []
    
    # Header
    report_lines.append("# Stratification Report")
    report_lines.append("")
    report_lines.append(f"**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    report_lines.append("")
    
    # Split Strategy Section
    report_lines.append("## Split Strategy")
    report_lines.append("")
    strategy = metadata.get('split_strategy', 'unknown')
    report_lines.append(f"- **Strategy Used:** {strategy.upper()}")
    
    if metadata.get('config_mode'):
        report_lines.append(f"- **Data Mode:** {metadata['config_mode'].upper()}")
    
    if metadata.get('stratification_column'):
        report_lines.append(f"- **Stratification Column:** `{metadata['stratification_column']}`")
    
    if metadata.get('warning'):
        report_lines.append("")
        report_lines.append(f"> **⚠️ Warning:** {metadata['warning']}")
    
    report_lines.append("")
    
    # Retention Section
    report_lines.append("## Data Retention")
    report_lines.append("")
    report_lines.append(f"- **Total Rows:** {metadata.get('total_rows', 'N/A')}")
    report_lines.append(f"- **Training Set:** {metadata.get('train_rows', 'N/A')} rows")
    report_lines.append(f"- **Test Set:** {metadata.get('test_rows', 'N/A')} rows")
    report_lines.append(f"- **Retention Rate:** {metadata.get('retention_rate', 0):.2%}")
    report_lines.append("")
    
    # Distribution Section (only if stratified)
    if strategy == 'stratified' and distribution_stats.get('classes'):
        report_lines.append("## Class Distribution")
        report_lines.append("")
        report_lines.append(f"**Threshold:** {distribution_stats.get('threshold', 0.05):.2%} max difference allowed")
        report_lines.append(f"**Max Observed Difference:** {distribution_stats.get('max_diff', 0):.4f}")
        report_lines.append("")
        
        if distribution_stats.get('max_diff', 1.0) <= distribution_stats.get('threshold', 0.05):
            report_lines.append("✅ **Distribution Check PASSED:** All class differences are within the acceptable threshold.")
        else:
            report_lines.append("❌ **Distribution Check FAILED:** Some class differences exceed the acceptable threshold.")
        report_lines.append("")
        
        report_lines.append(format_distribution(
            distribution_stats.get('train_distribution', {}),
            distribution_stats.get('test_distribution', {}),
            distribution_stats.get('classes', [])
        ))
        report_lines.append("")
    elif strategy == 'random':
        report_lines.append("## Distribution Note")
        report_lines.append("")
        report_lines.append("Random split was performed. No stratification statistics are available.")
        report_lines.append("")
    
    # Summary Section
    report_lines.append("## Summary")
    report_lines.append("")
    
    if strategy == 'stratified':
        report_lines.append("The dataset was split using **stratified sampling** by polymer type, ensuring that")
        report_lines.append("the distribution of polymer types in the training and test sets differs by less than")
        report_lines.append("5% for each class. This minimizes bias in model evaluation due to class imbalance.")
    else:
        report_lines.append("The dataset was split using **random sampling**. Stratification by polymer type was")
        report_lines.append("not performed, likely due to missing metadata in the dataset (common in proxy mode).")
        report_lines.append("This may introduce some bias in evaluation, but provides a valid baseline.")
    
    report_lines.append("")
    report_lines.append("---")
    report_lines.append("*Generated by llmXive automated science pipeline*")
    
    return "\n".join(report_lines)

def main():
    """
    Main entry point to generate the stratification report.
    
    Reads split metadata and distribution stats from data/processed/,
    generates the report, and saves it to results/stratification_report.md.
    """
    # Set up paths
    project_root = Path(__file__).resolve().parents[2]
    processed_dir = project_root / "data" / "processed"
    results_dir = project_root / "results"
    
    # Ensure results directory exists
    results_dir.mkdir(parents=True, exist_ok=True)
    
    # Define input paths
    metadata_path = processed_dir / "split_metadata.json"
    stats_path = processed_dir / "distribution_stats.json"
    output_path = results_dir / "stratification_report.md"
    
    logger.info(f"Generating stratification report...")
    logger.info(f"  Metadata: {metadata_path}")
    logger.info(f"  Stats: {stats_path}")
    logger.info(f"  Output: {output_path}")
    
    try:
        # Load data
        metadata = load_split_metadata(metadata_path)
        distribution_stats = load_distribution_stats(stats_path)
        
        # Generate report
        report = generate_report(metadata, distribution_stats)
        
        # Write report
        with open(output_path, 'w') as f:
            f.write(report)
        
        logger.info(f"Stratification report generated successfully: {output_path}")
        print(f"✅ Report generated: {output_path}")
        
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"Missing required input file: {e}")
        print(f"❌ Error: {e}")
        return 1
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in input file: {e}")
        print(f"❌ Error: Invalid JSON - {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error generating report: {e}")
        print(f"❌ Error: {e}")
        return 1

if __name__ == "__main__":
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    sys.exit(main())
