#!/usr/bin/env python3
"""Update the project state file with SHA-256 hashes of all artifacts.

Implements task T013: artifact hashing and state file updates
(Constitution Principle V - Versioning, Principle III - Data Hygiene).

The script:
1. Walks the artifact directories (data/, models/, results/, config/)
   under the project code root.
2. Computes the SHA-256 checksum of every file found.
3. Writes/updates the state file at
   state/projects/PROJ-356-predicting-molecular-toxicity-from-struc.yaml
   with an `artifact_hashes` map (relative path -> sha256) plus a
   `last_updated` timestamp and `artifact_count`.

Usage:
    python scripts/update_state.py
"""

import argparse
import hashlib
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List

# Artifact directories to hash (relative to the code root)
ARTIFACT_DIRS = ["data", "models", "results", "config"]

# File extensions to skip (transient/editor artifacts)
SKIP_SUFFIXES = {".pyc", ".log", ".tmp"}

# Directories to skip entirely
SKIP_DIRS = {"__pycache__", ".pytest_cache", "venv", "state"}

STATE_RELATIVE_PATH = Path("state") / "projects" / "PROJ-356-predicting-molecular-toxicity-from-struc.yaml"


def compute_sha256(file_path: Path, chunk_size: int = 1 << 20) -> str:
    """Compute the SHA-256 checksum of a file, streaming in chunks."""
    sha256 = hashlib.sha256()
    with open(file_path, "rb") as fh:
        for chunk in iter(lambda: fh.read(chunk_size), b""):
            sha256.update(chunk)
    return sha256.hexdigest()


def collect_artifact_files(code_root: Path) -> List[Path]:
    """Collect all artifact files under the tracked artifact directories."""
    files: List[Path] = []
    for rel_dir in ARTIFACT_DIRS:
        dir_path = code_root / rel_dir
        if not dir_path.is_dir():
            continue
        for path in sorted(dir_path.rglob("*")):
            if not path.is_file():
                continue
            if path.suffix in SKIP_SUFFIXES:
                continue
            if any(part in SKIP_DIRS for part in path.parts):
                continue
            files.append(path)
    return files


def hash_artifacts(code_root: Path) -> Dict[str, str]:
    """Hash every artifact file and return {relative_path: sha256}."""
    hashes: Dict[str, str] = {}
    for file_path in collect_artifact_files(code_root):
        rel = file_path.relative_to(code_root).as_posix()
        hashes[rel] = compute_sha256(file_path)
    return hashes


def render_state_yaml(hashes: Dict[str, str], timestamp: str) -> str:
    """Render the state file content as YAML (no external deps needed)."""
    lines = [
        "# State file for PROJ-356-predicting-molecular-toxicity-from-struc",
        "# Auto-generated by scripts/update_state.py - do not edit by hand.",
        "project_id: PROJ-356-predicting-molecular-toxicity-from-struc",
        f"last_updated: {timestamp}",
        f"artifact_count: {len(hashes)}",
        "artifact_hashes:",
    ]
    if not hashes:
        lines.append("  {}")
    for rel_path in sorted(hashes):
        lines.append(f"  {rel_path}: {hashes[rel_path]}")
    return "\n".join(lines) + "\n"


def update_state_file(code_root: Path, state_path: Path) -> Dict[str, str]:
    """Hash artifacts and write the state file. Returns the hash map."""
    hashes = hash_artifacts(code_root)
    timestamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    state_path.parent.mkdir(parents=True, exist_ok=True)
    state_path.write_text(render_state_yaml(hashes, timestamp), encoding="utf-8")
    return hashes


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Hash artifacts and update the project state file."
    )
    parser.add_argument(
        "--code-root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="Root of the code directory (default: parent of this script)",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    code_root = args.code_root.resolve()
    if not code_root.is_dir():
        print(f"ERROR: code root does not exist: {code_root}", file=sys.stderr)
        return 1

    state_path = code_root / STATE_RELATIVE_PATH
    hashes = update_state_file(code_root, state_path)

    print(f"Hashed {len(hashes)} artifact(s) under {code_root}")
    for rel_path, digest in sorted(hashes.items()):
        print(f"  {rel_path}: {digest}")
    print(f"State file updated: {state_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())