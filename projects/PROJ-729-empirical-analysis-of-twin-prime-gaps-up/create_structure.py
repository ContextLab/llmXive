"""
Project Structure Creation Script

This script creates the directory layout required for the
empirical analysis of twin prime gaps as specified in the
implementation plan. It is idempotent and can be safely re‑run.
"""
import sys
from pathlib import Path

def main() -> int:
    # Base project directory (the directory containing this script)
    base_dir = Path(__file__).resolve().parent

    # Directories to create relative to the project base
    dirs = [
        base_dir / "code",
        base_dir / "data" / "raw",
        base_dir / "data" / "results",
        base_dir / "data" / "figures",
        base_dir / "tests" / "unit",
        base_dir / "tests" / "integration",
        base_dir / "specs",
        base_dir / "contracts",
    ]

    for d in dirs:
        d.mkdir(parents=True, exist_ok=True)

    # Ensure a minimal README exists
    readme_path = base_dir / "README.md"
    if not readme_path.exists():
        readme_path.write_text(
            "# Empirical Analysis of Twin Prime Gaps up to 10⁹\\n\\n"
            "Project scaffold generated by T001.\\n",
            encoding="utf-8"
        )

    # Ensure a minimal __init__.py in the code package for imports
    init_path = base_dir / "code" / "__init__.py"
    if not init_path.exists():
        init_path.touch()

    return 0

if __name__ == "__main__":
    sys.exit(main())
