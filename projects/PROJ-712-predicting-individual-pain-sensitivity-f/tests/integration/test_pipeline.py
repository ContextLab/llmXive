# Expected feature names as defined in FR-002 and T016
# Order: mean durations (4), occurrence rates (4), transition probabilities (16), spectral power (6)
EXPECTED_FEATURE_NAMES = [
    # Mean Durations (A, B, C, D)
    "MS_A_Duration", "MS_B_Duration", "MS_C_Duration", "MS_D_Duration",
    # Occurrence Rates (A, B, C, D)
    "MS_A_Occurrence", "MS_B_Occurrence", "MS_C_Occurrence", "MS_D_Occurrence",
    # Transition Probabilities (4x4 matrix flattened: A->A, A->B, ..., D->D)
    "Trans_AA", "Trans_AB", "Trans_AC", "Trans_AD",
    "Trans_BA", "Trans_BB", "Trans_BC", "Trans_BD",
    "Trans_CA", "Trans_CB", "Trans_CC", "Trans_CD",
    "Trans_DA", "Trans_DB", "Trans_DC", "Trans_DD",
    # Spectral Power (Delta, Theta, Alpha, Beta, Low-Gamma, High-Gamma)
    "Spectral_Delta_Power", "Spectral_Theta_Power", "Spectral_Alpha_Power",
    "Spectral_Beta_Power", "Spectral_LowGamma_Power", "Spectral_HighGamma_Power"
]

def create_dummy_eeg_data(output_dir: Path, num_participants: int = 3):
    """
    Create dummy EEG data files in the specified directory.
    
    Args:
        output_dir: Directory to create dummy data in
        num_participants: Number of dummy participants to create
        
    Returns:
        List of participant IDs
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Create a dummy subject folder structure
    # We'll create simple .npy files to simulate EEG data
    # Format: (n_channels, n_times)
    # 64 channels, 10000 time points (approx 20 seconds at 500Hz)
    n_channels = 64
    n_times = 10000
    sfreq = 500
    
    dummy_participants = []
    
    for i in range(num_participants):
        participant_id = f"sub-dummy{i:03d}"
        dummy_participants.append(participant_id)
        
        # Create participant directory
        participant_dir = output_dir / participant_id
        participant_dir.mkdir(exist_ok=True)
        
        # Create dummy EEG data
        eeg_data = np.random.randn(n_channels, n_times).astype(np.float32)
        
        # Save as .npy file
        eeg_file = participant_dir / "eeg_data.npy"
        np.save(eeg_file, eeg_data)
        
        # Create dummy channel info
        channel_names = [f"EEG{i:03d}" for i in range(n_channels)]
        channel_file = participant_dir / "channel_info.npy"
        np.save(channel_file, np.array(channel_names))
        
        # Create dummy event info (for microstate segmentation)
        events = np.array([[0, 0, 1]])  # Dummy event at time 0
        events_file = participant_dir / "events.npy"
        np.save(events_file, events)
        
        # Create dummy labels file (heat-pain threshold in Celsius)
        labels = {
            "participant_id": participant_id,
            "heat_pain_threshold_celsius": 42.5 + i * 0.5  # Vary slightly
        }
        labels_file = participant_dir / "labels.csv"
        pd.DataFrame([labels]).to_csv(labels_file, index=False)
        
    return dummy_participants

def test_full_preprocessing_pipeline():
    """
    Integration test: Run the full preprocessing pipeline on dummy data
    and verify the output feature matrix has exactly 30 columns with no NaN values.
    """
    # Create a temporary directory for test data
    with tempfile.TemporaryDirectory() as temp_dir:
        temp_path = Path(temp_dir)
        dummy_data_dir = temp_path / "data" / "dummy"
        processed_dir = temp_path / "data" / "processed"
        
        # Ensure directories exist
        ensure_directories()
        
        # Create dummy data
        participant_ids = create_dummy_eeg_data(dummy_data_dir, num_participants=3)
        
        # Run preprocessing on dummy data
        # This should extract microstate features and spectral power
        features_list = preprocess_all_participants(
            data_dir=dummy_data_dir,
            output_dir=processed_dir,
            participant_ids=participant_ids
        )
        
        # Aggregate features into a single DataFrame
        output_df = aggregate_features(features_list, output_path=processed_dir / "feature_matrix.csv")
        
        # ASSERTION 1: Check that the output has exactly 30 columns
        assert len(output_df.columns) == 30, (
            f"Expected 30 columns, but got {len(output_df.columns)}. "
            f"Columns: {output_df.columns.tolist()}"
        )
        
        # ASSERTION 2: Check that the column names match the expected set exactly
        actual_columns = set(output_df.columns)
        expected_columns = set(EXPECTED_FEATURE_NAMES)
        
        assert actual_columns == expected_columns, (
            f"Column mismatch. Missing: {expected_columns - actual_columns}, "
            f"Extra: {actual_columns - expected_columns}"
        )
        
        # ASSERTION 3: Check that there are no NaN values in the DataFrame
        nan_count = output_df.isna().sum().sum()
        assert nan_count == 0, (
            f"Found {nan_count} NaN values in the output DataFrame. "
            f"Columns with NaN: {output_df.columns[output_df.isna().any()].tolist()}"
        )
        
        # Additional check: Verify column order
        expected_order = EXPECTED_FEATURE_NAMES
        actual_order = output_df.columns.tolist()
        assert actual_order == expected_order, (
            f"Column order mismatch. Expected: {expected_order}, Got: {actual_order}"
        )
        
        print(f"✓ Test passed: Feature matrix has {len(output_df.columns)} columns with no NaN values.")
        print(f"✓ Columns: {output_df.columns.tolist()}")

if __name__ == "__main__":
    pytest.main([__file__, "-v"])