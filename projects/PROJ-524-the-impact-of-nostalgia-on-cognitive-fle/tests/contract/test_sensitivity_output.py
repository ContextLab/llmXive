"""
Contract test for sensitivity report schema (Task T024).

This test validates that the sensitivity report generated by the analysis pipeline
conforms to the expected schema defined in data/results/sensitivity_report.json.

It verifies:
1. The file exists at the expected path.
2. The top-level structure contains required keys.
3. The 'thresholds' list contains objects with expected fields.
4. The 'robustness_check' section contains expected fields.
5. Data types match the schema (e.g., p-values are floats, significance is bool).
"""
import os
import json
import pytest
from pathlib import Path
from typing import Any, Dict

# Import config to get the output path
from config import get_config


EXPECTED_SCHEMA_KEYS = {
    "thresholds",
    "robustness_check",
    "summary",
    "metadata"
}

EXPECTED_THRESHOLD_KEYS = {
    "alpha",
    "significant_errors",
    "significant_categories",
    "is_significant_errors",
    "is_significant_categories"
}

EXPECTED_ROBUSTNESS_KEYS = {
    "mmse_filter_applied",
    "mmse_threshold",
    "sample_size_before",
    "sample_size_after",
    "effect_size_change",
    "p_value_change"
}

EXPECTED_SUMMARY_KEYS = {
    "overall_stability",
    "sensitive_to_threshold",
    "recommendation"
}


def load_sensitivity_report() -> Dict[str, Any]:
    """Load the sensitivity report from the standard output location."""
    config = get_config()
    # Assuming the report is generated in data/results/ as per project structure
    report_path = Path(config.get("paths", {}).get("results_dir", "data/results")) / "sensitivity_report.json"
    
    if not report_path.exists():
        pytest.fail(f"Sensitivity report not found at {report_path}. "
                    "Ensure the sensitivity analysis pipeline (T026-T030) has run successfully.")
    
    with open(report_path, "r", encoding="utf-8") as f:
        return json.load(f)


def test_sensitivity_report_file_exists():
    """Contract: The sensitivity report file must exist."""
    config = get_config()
    report_path = Path(config.get("paths", {}).get("results_dir", "data/results")) / "sensitivity_report.json"
    assert report_path.exists(), f"Report file {report_path} does not exist."


def test_sensitivity_report_top_level_keys():
    """Contract: The report must contain all required top-level keys."""
    report = load_sensitivity_report()
    
    missing_keys = EXPECTED_SCHEMA_KEYS - set(report.keys())
    assert not missing_keys, f"Missing required top-level keys in sensitivity report: {missing_keys}"


def test_sensitivity_report_thresholds_structure():
    """Contract: The 'thresholds' list must contain valid threshold objects."""
    report = load_sensitivity_report()
    thresholds = report.get("thresholds", [])
    
    assert isinstance(thresholds, list), "The 'thresholds' field must be a list."
    assert len(thresholds) > 0, "The 'thresholds' list must not be empty."
    
    for i, threshold_entry in enumerate(thresholds):
        assert isinstance(threshold_entry, dict), f"Threshold entry {i} must be a dictionary."
        
        missing_keys = EXPECTED_THRESHOLD_KEYS - set(threshold_entry.keys())
        assert not missing_keys, f"Threshold entry {i} missing keys: {missing_keys}"
        
        # Type checks
        assert isinstance(threshold_entry["alpha"], (int, float)), f"Threshold entry {i}: 'alpha' must be a number."
        assert isinstance(threshold_entry["significant_errors"], (int, float)), f"Threshold entry {i}: 'significant_errors' must be a number."
        assert isinstance(threshold_entry["significant_categories"], (int, float)), f"Threshold entry {i}: 'significant_categories' must be a number."
        assert isinstance(threshold_entry["is_significant_errors"], bool), f"Threshold entry {i}: 'is_significant_errors' must be a boolean."
        assert isinstance(threshold_entry["is_significant_categories"], bool), f"Threshold entry {i}: 'is_significant_categories' must be a boolean."


def test_sensitivity_report_robustness_structure():
    """Contract: The 'robustness_check' section must contain valid data."""
    report = load_sensitivity_report()
    robustness = report.get("robustness_check", {})
    
    assert isinstance(robustness, dict), "The 'robustness_check' field must be a dictionary."
    
    missing_keys = EXPECTED_ROBUSTNESS_KEYS - set(robustness.keys())
    assert not missing_keys, f"Robustness check missing keys: {missing_keys}"
    
    # Type checks
    assert isinstance(robustness["mmse_filter_applied"], bool), "'mmse_filter_applied' must be a boolean."
    assert isinstance(robustness["mmse_threshold"], (int, float)), "'mmse_threshold' must be a number."
    assert isinstance(robustness["sample_size_before"], int), "'sample_size_before' must be an integer."
    assert isinstance(robustness["sample_size_after"], int), "'sample_size_after' must be an integer."
    assert isinstance(robustness["effect_size_change"], (int, float)), "'effect_size_change' must be a number."
    assert isinstance(robustness["p_value_change"], (int, float)), "'p_value_change' must be a number."


def test_sensitivity_report_summary_structure():
    """Contract: The 'summary' section must contain valid data."""
    report = load_sensitivity_report()
    summary = report.get("summary", {})
    
    assert isinstance(summary, dict), "The 'summary' field must be a dictionary."
    
    missing_keys = EXPECTED_SUMMARY_KEYS - set(summary.keys())
    assert not missing_keys, f"Summary missing keys: {missing_keys}"
    
    # Type checks
    assert isinstance(summary["overall_stability"], str), "'overall_stability' must be a string."
    assert isinstance(summary["sensitive_to_threshold"], bool), "'sensitive_to_threshold' must be a boolean."
    assert isinstance(summary["recommendation"], str), "'recommendation' must be a string."


def test_sensitivity_report_metadata_structure():
    """Contract: The 'metadata' section must exist and contain basic info."""
    report = load_sensitivity_report()
    metadata = report.get("metadata", {})
    
    assert isinstance(metadata, dict), "The 'metadata' field must be a dictionary."
    assert "generated_at" in metadata, "Metadata must contain 'generated_at' timestamp."
    assert "version" in metadata, "Metadata must contain 'version' string."