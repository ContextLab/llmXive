"""
Task T015a: Generate Metadata
Creates data/raw/metadata.json with dataset source, validation study DOI,
stimuli checksums, and simulation mode flag.
"""
import os
import json
import logging
import hashlib
from pathlib import Path
from typing import Optional, Dict, Any

from config import get_config, ensure_dirs
from utils import setup_logging, log_info, log_warning, log_error, get_timestamp

# Configure logger
logger = logging.getLogger(__name__)

def compute_file_checksum(file_path: Path) -> str:
    """Compute SHA-256 checksum of a file."""
    sha256_hash = hashlib.sha256()
    try:
        with open(file_path, "rb") as f:
            for byte_block in iter(lambda: f.read(4096), b""):
                sha256_hash.update(byte_block)
        return sha256_hash.hexdigest()
    except Exception as e:
        log_error(f"Failed to compute checksum for {file_path}: {e}")
        raise

def compute_stimuli_checksums(stimuli_dir: Path) -> Dict[str, str]:
    """Compute checksums for all files in the stimuli directory."""
    checksums = {}
    if not stimuli_dir.exists():
        log_warning(f"Stimuli directory does not exist: {stimuli_dir}")
        return checksums

    files = list(stimuli_dir.iterdir())
    if not files:
        log_warning(f"Stimuli directory is empty: {stimuli_dir}")
        return checksums

    for file_path in files:
        if file_path.is_file():
            try:
                checksum = compute_file_checksum(file_path)
                checksums[file_path.name] = checksum
                log_info(f"Computed checksum for {file_path.name}: {checksum}")
            except Exception as e:
                log_error(f"Skipping {file_path.name} due to error: {e}")

    return checksums

def load_raw_metadata(raw_data_path: Path) -> Optional[Dict[str, Any]]:
    """Attempt to load existing raw metadata if present."""
    if raw_data_path.exists():
        try:
            with open(raw_data_path, 'r', encoding='utf-8') as f:
                return json.load(f)
        except Exception as e:
            log_warning(f"Could not load existing metadata: {e}")
    return None

def generate_metadata(
    stimuli_dir: Path,
    raw_metadata_path: Path,
    simulation_mode: bool = False
) -> Dict[str, Any]:
    """
    Generate the metadata dictionary.
    - dataset_source: String identifier or URL (set to 'simulated' if simulation)
    - validation_study_doi: Extracted from raw metadata or None
    - stimuli_checksums: Dict of filename -> SHA-256
    - simulation_mode: Boolean flag
    """
    # Determine dataset source
    if simulation_mode:
        dataset_source = "simulated"
    else:
        # Try to infer from existing metadata or set a default canonical source
        existing = load_raw_metadata(raw_metadata_path)
        if existing and 'dataset_source' in existing:
            dataset_source = existing['dataset_source']
        else:
            dataset_source = "unknown_canonical_source"

    # Extract validation_study_doi
    validation_study_doi = None
    existing = load_raw_metadata(raw_metadata_path)
    if existing and 'validation_study_doi' in existing:
        validation_study_doi = existing['validation_study_doi']
    
    # Compute stimuli checksums
    stimuli_checksums = compute_stimuli_checksums(stimuli_dir)

    metadata = {
        "dataset_source": dataset_source,
        "validation_study_doi": validation_study_doi,
        "stimuli_checksums": stimuli_checksums,
        "simulation_mode": simulation_mode,
        "generated_at": get_timestamp()
    }

    return metadata

def save_metadata(metadata: Dict[str, Any], output_path: Path) -> None:
    """Save metadata dictionary to JSON file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(metadata, f, indent=2)
    log_info(f"Metadata saved to {output_path}")

def main() -> int:
    """Main entry point for T015a."""
    setup_logging()
    config = get_config()
    
    stimuli_dir = Path(config.get('paths.stimuli_dir', 'data/stimuli'))
    raw_data_dir = Path(config.get('paths.raw_data_dir', 'data/raw'))
    output_path = raw_data_dir / 'metadata.json'
    
    # Determine simulation mode by checking if we have a simulation flag in exclusion log
    # or by checking if raw_dataset.csv was generated by simulation (heuristic: check metadata if exists)
    # For this task, we assume the caller passes the flag or we check a specific indicator.
    # Since T010c sets the flag in metadata or exclusion log, we check exclusion_log first if metadata missing.
    simulation_mode = False
    exclusion_log_path = raw_data_dir / 'exclusion_log.json' # Note: T012c puts this in processed, but let's check processed
    exclusion_log_path_processed = Path(config.get('paths.processed_data_dir', 'data/processed')) / 'exclusion_log.json'
    
    if exclusion_log_path_processed.exists():
        try:
            with open(exclusion_log_path_processed, 'r') as f:
                data = json.load(f)
                simulation_mode = data.get('SIMULATION_FALLBACK', False)
        except Exception as e:
            log_warning(f"Could not read exclusion log for simulation flag: {e}")

    log_info(f"Starting metadata generation. Simulation mode: {simulation_mode}")
    
    try:
        metadata = generate_metadata(stimuli_dir, output_path, simulation_mode)
        save_metadata(metadata, output_path)
        log_info("Task T015a completed successfully.")
        return 0
    except Exception as e:
        log_error(f"Task T015a failed: {e}")
        return 1

if __name__ == "__main__":
    exit(main())
