"""
Task T021: Calculate statistical power and Minimum Detectable Effect Size (MDES).

This module reads the statistical report generated by T020 (effect sizes),
calculates the observed statistical power and MDES for the given sample sizes
and effect sizes, and appends these values to the report.

Dependencies:
    - T020 (effect sizes) must have been run to generate the base report.
    - Requires: numpy, scipy, pandas, statsmodels
"""

import os
import json
import logging
import numpy as np
import pandas as pd
from pathlib import Path
from statsmodels.stats.power import tt_ind_solve_power
from typing import Dict, Any, Optional

# Setup logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Paths
PROJECT_ROOT = Path(__file__).parent.parent
DATA_PROCESSED = PROJECT_ROOT / "data" / "processed"
DATA_RESULTS = PROJECT_ROOT / "data" / "results"

CLEANED_DATASET_PATH = DATA_PROCESSED / "final_cleaned_dataset.csv"
STATISTICAL_REPORT_PATH = DATA_RESULTS / "statistical_report.json"

# Ensure results directory exists
DATA_RESULTS.mkdir(parents=True, exist_ok=True)

def load_cleaned_dataset() -> Optional[pd.DataFrame]:
    """Load the final cleaned dataset."""
    if not CLEANED_DATASET_PATH.exists():
        logger.error(f"Cleaned dataset not found at {CLEANED_DATASET_PATH}")
        return None
    
    try:
        df = pd.read_csv(CLEANED_DATASET_PATH)
        logger.info(f"Loaded cleaned dataset with {len(df)} records")
        return df
    except Exception as e:
        logger.error(f"Error loading cleaned dataset: {e}")
        return None

def load_statistical_report() -> Optional[Dict[str, Any]]:
    """Load the statistical report from T020."""
    if not STATISTICAL_REPORT_PATH.exists():
        logger.error(f"Statistical report not found at {STATISTICAL_REPORT_PATH}")
        return None
    
    try:
        with open(STATISTICAL_REPORT_PATH, 'r') as f:
            report = json.load(f)
        logger.info("Loaded statistical report")
        return report
    except Exception as e:
        logger.error(f"Error loading statistical report: {e}")
        return None

def save_statistical_report(report: Dict[str, Any]) -> bool:
    """Save the updated statistical report."""
    try:
        with open(STATISTICAL_REPORT_PATH, 'w') as f:
            json.dump(report, f, indent=2)
        logger.info(f"Saved updated statistical report to {STATISTICAL_REPORT_PATH}")
        return True
    except Exception as e:
        logger.error(f"Error saving statistical report: {e}")
        return False

def calculate_power_and_mdes(
    effect_size: float,
    n1: int,
    n2: int,
    alpha: float = 0.05,
    power: float = 0.80
) -> Dict[str, float]:
    """
    Calculate statistical power and Minimum Detectable Effect Size (MDES).
    
    Args:
        effect_size: Observed Cohen's d effect size.
        n1: Sample size of group 1.
        n2: Sample size of group 2.
        alpha: Significance level (default 0.05).
        power: Target power for MDES calculation (default 0.80).
    
    Returns:
        Dictionary with 'statistical_power' and 'minimum_detectable_effect_size'.
    """
    # Calculate statistical power using the observed effect size
    # Use Welch's t-test approximation (unequal sample sizes)
    n_avg = (n1 + n2) / 2
    n_eff = (n1 * n2) / (n1 + n2)  # Effective sample size for unequal groups
    
    try:
        # Calculate power for two-sample t-test
        # tt_ind_solve_power: solves for any one argument of the power of a two independent sample t-test
        # nobs1, alpha, effect_size, power, ratio (n2/n1)
        ratio = n2 / n1
        
        # Calculate power
        statistical_power = tt_ind_solve_power(
            effect_size=abs(effect_size),
            nobs1=n1,
            alpha=alpha,
            ratio=ratio,
            alternative='two-sided'
        )
        
        # Calculate MDES (minimum detectable effect size) for target power
        minimum_detectable_effect_size = tt_ind_solve_power(
            effect_size=None,
            nobs1=n1,
            alpha=alpha,
            power=power,
            ratio=ratio,
            alternative='two-sided'
        )
        
        return {
            'statistical_power': float(statistical_power),
            'minimum_detectable_effect_size': float(minimum_detectable_effect_size),
            'alpha': alpha,
            'sample_size_nostalgia': n1,
            'sample_size_control': n2
        }
    except Exception as e:
        logger.warning(f"Power calculation failed: {e}. Using fallback values.")
        return {
            'statistical_power': 0.0,
            'minimum_detectable_effect_size': 0.0,
            'alpha': alpha,
            'sample_size_nostalgia': n1,
            'sample_size_control': n2
        }

def run_power_analysis(report: Dict[str, Any]) -> Dict[str, Any]:
    """
    Run power analysis for each comparison in the report.
    
    Args:
        report: Statistical report dictionary.
    
    Returns:
        Updated report with power analysis results appended.
    """
    if 'comparisons' not in report:
        logger.error("No comparisons found in statistical report")
        return report
    
    total_power = 0.0
    total_mdes = 0.0
    comparison_count = 0
    
    for comparison in report['comparisons']:
        metric = comparison.get('metric', 'unknown')
        group_nostalgia = comparison.get('group_nostalgia', {})
        group_control = comparison.get('group_control', {})
        effect_size_data = comparison.get('effect_size', {})
        
        n_nostalgia = group_nostalgia.get('n', 0)
        n_control = group_control.get('n', 0)
        cohen_d = effect_size_data.get('cohen_d', 0.0)
        
        if n_nostalgia <= 0 or n_control <= 0:
            logger.warning(f"Invalid sample sizes for {metric}: n_nostalgia={n_nostalgia}, n_control={n_control}")
            comparison['power_analysis'] = {
                'statistical_power': 0.0,
                'minimum_detectable_effect_size': 0.0,
                'alpha': 0.05,
                'sample_size_nostalgia': n_nostalgia,
                'sample_size_control': n_control
            }
            continue
        
        # Calculate power and MDES
        power_results = calculate_power_and_mdes(
            effect_size=cohen_d,
            n1=n_nostalgia,
            n2=n_control,
            alpha=0.05,
            power=0.80
        )
        
        # Append to comparison
        comparison['power_analysis'] = power_results
        
        # Accumulate for summary
        total_power += power_results['statistical_power']
        total_mdes += power_results['minimum_detectable_effect_size']
        comparison_count += 1
        
        logger.info(f"Power analysis for {metric}: power={power_results['statistical_power']:.3f}, MDES={power_results['minimum_detectable_effect_size']:.3f}")
    
    # Update summary if it exists
    if 'summary' in report:
        if comparison_count > 0:
            report['summary']['average_power'] = float(total_power / comparison_count)
            report['summary']['average_mdes'] = float(total_mdes / comparison_count)
        else:
            report['summary']['average_power'] = 0.0
            report['summary']['average_mdes'] = 0.0
        
        report['summary']['power_analyzed'] = True
    else:
        report['summary'] = {
            'total_comparisons': comparison_count,
            'power_analyzed': True,
            'average_power': float(total_power / comparison_count) if comparison_count > 0 else 0.0,
            'average_mdes': float(total_mdes / comparison_count) if comparison_count > 0 else 0.0
        }
    
    return report

def main():
    """Main entry point for T021."""
    logger.info("Starting T021: Power Analysis")
    
    # Load statistical report
    report = load_statistical_report()
    if report is None:
        logger.error("Failed to load statistical report. T021 cannot proceed.")
        return 1
    
    # Run power analysis
    updated_report = run_power_analysis(report)
    
    # Save updated report
    if not save_statistical_report(updated_report):
        logger.error("Failed to save updated statistical report")
        return 1
    
    logger.info("T021 completed successfully")
    return 0

if __name__ == "__main__":
    exit(main())