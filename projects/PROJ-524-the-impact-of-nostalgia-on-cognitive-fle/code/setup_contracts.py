"""
Task T007: Setup `contracts/` directory structure.

This script ensures the `contracts/` directory exists at the project root.
It does not generate the schema files (that is T020a), but prepares the
infrastructure so T020a can write files into it.
"""
import os
import sys
import logging
from pathlib import Path

# Import existing utilities from the project
from utils import setup_logging, log_info, log_warning, log_error, get_timestamp
from config import get_config, ensure_dirs

def create_contracts_directory():
    """
    Creates the `contracts/` directory if it does not exist.
    Returns the Path object for the directory.
    """
    # Determine project root (assuming code/ is at root level relative to contracts)
    # Based on T001, we assume the project root is the parent of 'code' or current dir
    # Let's use the standard project root logic: parent of 'code' if 'code' exists, else current
    current_dir = Path(__file__).resolve().parent
    project_root = current_dir.parent if current_dir.name == 'code' else current_dir
    
    contracts_dir = project_root / 'contracts'
    
    if not contracts_dir.exists():
        try:
            contracts_dir.mkdir(parents=True, exist_ok=True)
            log_info(f"Created contracts directory: {contracts_dir}")
        except OSError as e:
            log_error(f"Failed to create contracts directory: {e}")
            raise
    else:
        log_info(f"Contracts directory already exists: {contracts_dir}")
    
    # Create a README to document the purpose of this directory
    readme_path = contracts_dir / 'README.md'
    if not readme_path.exists():
        readme_content = """# Contracts Directory

This directory contains schema definitions and contract files for data validation.

## Generated Artifacts

- `dataset.schema.yaml`: Schema for input datasets (generated by T020a)
- `output.schema.yaml`: Schema for analysis output (generated by T020a)

## Purpose

These contracts enforce data integrity and schema compliance throughout the pipeline,
ensuring that all data processing steps adhere to the defined specifications.
"""
        readme_path.write_text(readme_content)
        log_info(f"Created contracts/README.md")
    
    return contracts_dir

def main():
    """Main entry point for T007."""
    # Setup logging
    setup_logging()
    
    try:
        log_info("Starting T007: Setup contracts directory structure")
        contracts_dir = create_contracts_directory()
        log_info(f"Successfully set up contracts directory at: {contracts_dir}")
        
        # Verify directory exists and is accessible
        if contracts_dir.exists() and contracts_dir.is_dir():
            log_info("Verification: contracts/ directory is valid")
            return 0
        else:
            log_error("Verification failed: contracts/ directory is not valid")
            return 1
            
    except Exception as e:
        log_error(f"Task T007 failed with exception: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())