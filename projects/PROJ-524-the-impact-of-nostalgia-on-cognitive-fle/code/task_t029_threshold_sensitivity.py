"""
Task T029: Add logic to flag "sensitive to threshold choice" if p-value is borderline (≈ 0.05).

This module reads the sensitivity report generated by T028, examines the p-values
for the primary comparisons (perseverative_errors, categories_completed), and adds
a 'threshold_sensitivity' flag indicating if the result is borderline (p-value within
a defined margin of the significance threshold, typically 0.05).

It updates the sensitivity report and saves it back to data/results/sensitivity_report.json.
"""
import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, List

# Import config utilities
from config import get_config, get_env_float
from utils import setup_logging, log_info, log_warning, get_timestamp

# Constants
DEFAULT_BORDERLINE_MARGIN = 0.01  # ±0.01 around 0.05
DEFAULT_SIGNIFICANCE_THRESHOLD = 0.05
SENSITIVITY_REPORT_PATH = "data/results/sensitivity_report.json"

def load_sensitivity_report(path: str) -> Dict[str, Any]:
    """Load the sensitivity report JSON file."""
    if not os.path.exists(path):
        raise FileNotFoundError(f"Sensitivity report not found at {path}")
    
    with open(path, 'r') as f:
        return json.load(f)

def save_sensitivity_report(data: Dict[str, Any], path: str) -> None:
    """Save the updated sensitivity report JSON file."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        json.dump(data, f, indent=2)

def is_borderline(p_value: float, threshold: float, margin: float) -> bool:
    """
    Check if a p-value is borderline (within margin of the threshold).
    
    A p-value is considered borderline if:
    threshold - margin <= p_value <= threshold + margin
    """
    if p_value is None:
        return False
    return (threshold - margin) <= p_value <= (threshold + margin)

def analyze_threshold_sensitivity(
    report: Dict[str, Any],
    threshold: float = DEFAULT_SIGNIFICANCE_THRESHOLD,
    margin: float = DEFAULT_BORDERLINE_MARGIN
) -> Dict[str, Any]:
    """
    Analyze the sensitivity report to flag borderline p-values.
    
    Args:
        report: The sensitivity report dictionary
        threshold: The significance threshold (default 0.05)
        margin: The margin for borderline detection (default 0.01)
    
    Returns:
        Updated report with threshold_sensitivity flags
    """
    log_info("Analyzing threshold sensitivity for borderline p-values")
    
    sensitivity_flags = {}
    borderline_count = 0
    
    # Check primary comparisons if they exist in the report
    comparisons = report.get('comparisons', {})
    
    for metric_name, metric_data in comparisons.items():
        # Look for p-values in the metric data
        p_value = metric_data.get('p_value')
        
        if p_value is not None:
            if is_borderline(p_value, threshold, margin):
                sensitivity_flags[metric_name] = {
                    'is_borderline': True,
                    'p_value': p_value,
                    'threshold': threshold,
                    'margin': margin,
                    'flag': 'SENSITIVE_TO_THRESHOLD',
                    'message': f"P-value {p_value:.4f} is within ±{margin} of threshold {threshold}"
                }
                borderline_count += 1
                log_warning(f"Borderline p-value detected for {metric_name}: {p_value:.4f}")
            else:
                sensitivity_flags[metric_name] = {
                    'is_borderline': False,
                    'p_value': p_value,
                    'threshold': threshold,
                    'margin': margin,
                    'flag': 'STABLE',
                    'message': f"P-value {p_value:.4f} is stable relative to threshold {threshold}"
                }
        
        # Also check threshold-specific results if available
        threshold_results = metric_data.get('threshold_results', {})
        for thresh_key, thresh_data in threshold_results.items():
            thresh_p = thresh_data.get('p_value')
            if thresh_p is not None:
                # Check if this specific threshold result is borderline
                if is_borderline(thresh_p, float(thresh_key), margin):
                    if f"{metric_name}_{thresh_key}" not in sensitivity_flags:
                        sensitivity_flags[f"{metric_name}_{thresh_key}"] = {
                            'is_borderline': True,
                            'p_value': thresh_p,
                            'threshold': float(thresh_key),
                            'margin': margin,
                            'flag': 'SENSITIVE_TO_THRESHOLD',
                            'message': f"P-value {thresh_p:.4f} at threshold {thresh_key} is borderline"
                        }
                        borderline_count += 1
    
    # Add overall summary
    report['threshold_sensitivity'] = {
        'analysis_timestamp': get_timestamp(),
        'threshold': threshold,
        'margin': margin,
        'borderline_count': borderline_count,
        'total_comparisons': len(comparisons),
        'is_sensitive': borderline_count > 0,
        'flags': sensitivity_flags,
        'summary': (
            f"Found {borderline_count} borderline result(s) out of {len(comparisons)} comparisons. "
            f"Results are {'SENSITIVE' if borderline_count > 0 else 'STABLE'} to threshold choice."
        )
    }
    
    return report

def run_threshold_sensitivity(
    report_path: str = SENSITIVITY_REPORT_PATH,
    threshold: float = DEFAULT_SIGNIFICANCE_THRESHOLD,
    margin: float = DEFAULT_BORDERLINE_MARGIN
) -> Dict[str, Any]:
    """
    Main function to run threshold sensitivity analysis.
    
    Args:
        report_path: Path to the sensitivity report
        threshold: Significance threshold to check against
        margin: Margin for borderline detection
    
    Returns:
        Updated sensitivity report dictionary
    """
    log_info(f"Starting threshold sensitivity analysis for {report_path}")
    
    # Load existing report
    report = load_sensitivity_report(report_path)
    
    # Analyze sensitivity
    updated_report = analyze_threshold_sensitivity(report, threshold, margin)
    
    # Save updated report
    save_sensitivity_report(updated_report, report_path)
    
    log_info(f"Threshold sensitivity analysis complete. Report saved to {report_path}")
    log_info(f"Summary: {updated_report['threshold_sensitivity']['summary']}")
    
    return updated_report

def main():
    """Entry point for the script."""
    # Setup logging
    log_level = logging.INFO
    setup_logging(level=log_level)
    
    log_info("Starting Task T029: Threshold Sensitivity Analysis")
    
    try:
        # Get configuration
        config = get_config()
        threshold = get_env_float('SIGNIFICANCE_THRESHOLD', DEFAULT_SIGNIFICANCE_THRESHOLD)
        margin = get_env_float('BORDERLINE_MARGIN', DEFAULT_BORDERLINE_MARGIN)
        
        # Run analysis
        result = run_threshold_sensitivity(
            threshold=threshold,
            margin=margin
        )
        
        # Print summary
        print("\n" + "="*60)
        print("THRESHOLD SENSITIVITY ANALYSIS RESULTS")
        print("="*60)
        print(f"Threshold: {result['threshold_sensitivity']['threshold']}")
        print(f"Margin: {result['threshold_sensitivity']['margin']}")
        print(f"Borderline Count: {result['threshold_sensitivity']['borderline_count']}")
        print(f"Is Sensitive: {result['threshold_sensitivity']['is_sensitive']}")
        print(f"Summary: {result['threshold_sensitivity']['summary']}")
        
        if result['threshold_sensitivity']['flags']:
            print("\nDetailed Flags:")
            for key, flag_data in result['threshold_sensitivity']['flags'].items():
                print(f"  {key}: {flag_data['flag']} - {flag_data['message']}")
        
        print("="*60)
        
    except FileNotFoundError as e:
        log_error(f"Report file not found: {e}")
        raise
    except Exception as e:
        log_error(f"Error during threshold sensitivity analysis: {e}")
        raise

if __name__ == "__main__":
    main()