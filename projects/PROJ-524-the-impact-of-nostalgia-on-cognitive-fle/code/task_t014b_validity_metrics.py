"""
T014b: VALIDITY METRICS
Calculate percentage of valid records (age >= 65, non-null metrics, MMSE >= 24 if available)
vs total raw input records from data/raw/raw_dataset.csv.
Write the calculated percentage to data/processed/validity_metrics.json.
Depends on: T012c (exclusion_log.json)
"""
import os
import json
import logging
import pandas as pd
from pathlib import Path
from typing import Dict, Any

from config import get_config
from utils import setup_logging, log_info, log_warning, log_error, get_timestamp

# Setup logging
logger = setup_logging(__name__)

def get_config_paths() -> Dict[str, str]:
    """Get standardized paths for this task."""
    config = get_config()
    return {
        'raw_dataset': config['paths']['data_raw'] + '/raw_dataset.csv',
        'exclusion_log': config['paths']['data_processed'] + '/exclusion_log.json',
        'output_file': config['paths']['data_processed'] + '/validity_metrics.json',
        'mmse_flag': config['paths']['data_processed'] + '/mmse_flag.json'
    }

def load_raw_count(paths: Dict[str, str]) -> int:
    """Count total records in the raw dataset."""
    try:
        df = pd.read_csv(paths['raw_dataset'])
        total_count = len(df)
        log_info(f"Loaded raw dataset: {total_count} records")
        return total_count
    except FileNotFoundError:
        log_error(f"Raw dataset not found at {paths['raw_dataset']}")
        raise
    except Exception as e:
        log_error(f"Error loading raw dataset: {str(e)}")
        raise

def load_exclusion_log(paths: Dict[str, str]) -> Dict[str, Any]:
    """Load the exclusion log generated by T012c."""
    try:
        with open(paths['exclusion_log'], 'r') as f:
            return json.load(f)
    except FileNotFoundError:
        log_error(f"Exclusion log not found at {paths['exclusion_log']}")
        raise
    except json.JSONDecodeError as e:
        log_error(f"Invalid JSON in exclusion log: {str(e)}")
        raise

def calculate_validity_metrics(total_raw: int, exclusion_log: Dict[str, Any], mmse_flag_path: str) -> Dict[str, Any]:
    """
    Calculate validity metrics based on exclusion log.
    
    Valid records = Total raw - (age exclusions + score exclusions + MMSE exclusions)
    Validity percentage = (Valid records / Total raw) * 100
    """
    # Extract exclusion counts
    age_exclusions = exclusion_log.get('ERR_MISSING_AGE_FIELD', 0)
    score_exclusions = exclusion_log.get('ERR_MISSING_SCORE', 0)
    mmse_exclusions = exclusion_log.get('ERR_MMSE_IMPAIRED', 0)
    
    # Calculate total exclusions
    total_exclusions = age_exclusions + score_exclusions + mmse_exclusions
    
    # Calculate valid records
    valid_records = max(0, total_raw - total_exclusions)
    
    # Calculate validity percentage
    if total_raw > 0:
        validity_percentage = (valid_records / total_raw) * 100
    else:
        validity_percentage = 0.0
    
    # Check if MMSE was available for exclusion
    has_mmse = False
    try:
        with open(mmse_flag_path, 'r') as f:
            mmse_data = json.load(f)
            has_mmse = mmse_data.get('has_mmse', False)
    except FileNotFoundError:
        log_warning(f"MMSE flag not found at {mmse_flag_path}, assuming MMSE not available")
    except json.JSONDecodeError:
        log_warning(f"Invalid JSON in MMSE flag file at {mmse_flag_path}")
    
    # Build metrics dictionary
    metrics = {
        'timestamp': get_timestamp(),
        'total_raw_records': total_raw,
        'valid_records': valid_records,
        'total_exclusions': total_exclusions,
        'validity_percentage': round(validity_percentage, 2),
        'exclusion_breakdown': {
            'ERR_MISSING_AGE_FIELD': age_exclusions,
            'ERR_MISSING_SCORE': score_exclusions,
            'ERR_MMSE_IMPAIRED': mmse_exclusions
        },
        'mmse_available_for_exclusion': has_mmse,
        'simulation_mode': exclusion_log.get('SIMULATION_FALLBACK', False)
    }
    
    log_info(f"Validity Metrics: {validity_percentage:.2f}% valid ({valid_records}/{total_raw})")
    return metrics

def save_validity_metrics(metrics: Dict[str, Any], output_path: str) -> None:
    """Save validity metrics to JSON file."""
    try:
        with open(output_path, 'w') as f:
            json.dump(metrics, f, indent=2)
        log_info(f"Validity metrics saved to {output_path}")
    except Exception as e:
        log_error(f"Failed to save validity metrics: {str(e)}")
        raise

def main():
    """Main entry point for T014b."""
    log_info("Starting T014b: Validity Metrics Calculation")
    
    # Get paths
    paths = get_config_paths()
    
    # Load raw dataset count
    total_raw = load_raw_count(paths)
    
    # Load exclusion log
    exclusion_log = load_exclusion_log(paths)
    
    # Calculate validity metrics
    metrics = calculate_validity_metrics(total_raw, exclusion_log, paths['mmse_flag'])
    
    # Save results
    save_validity_metrics(metrics, paths['output_file'])
    
    log_info("T014b completed successfully")
    return metrics

if __name__ == "__main__":
    main()
