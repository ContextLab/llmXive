"""
T014b: Calculate validity metrics for the dataset.

Calculates the percentage of valid records (age >= 65, non-null metrics, 
MMSE >= 24 if available) vs total raw input records from 
data/raw/raw_dataset.csv. Writes the calculated percentage to 
data/processed/validity_metrics.json.

Depends on: T012c (exclusion log generation)
"""
import os
import json
import logging
import pandas as pd
from pathlib import Path
from typing import Dict, Any

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def load_exclusion_log(exclusion_log_path: Path) -> Dict[str, Any]:
    """Load the exclusion log generated by T012c."""
    if not exclusion_log_path.exists():
        raise FileNotFoundError(f"Exclusion log not found at {exclusion_log_path}")
    
    with open(exclusion_log_path, 'r') as f:
        return json.load(f)

def load_raw_count(raw_dataset_path: Path) -> int:
    """Load the raw dataset and return the total number of records."""
    if not raw_dataset_path.exists():
        raise FileNotFoundError(f"Raw dataset not found at {raw_dataset_path}")
    
    df = pd.read_csv(raw_dataset_path)
    return len(df)

def calculate_validity_metrics(
    raw_count: int,
    exclusion_log: Dict[str, Any],
    mmse_flag_path: Path
) -> Dict[str, Any]:
    """
    Calculate validity metrics based on exclusion counts.
    
    Valid records = Total raw records - (age exclusions + score exclusions + MMSE exclusions)
    Validity percentage = (Valid records / Total raw records) * 100
    """
    # Get exclusion counts from the log
    age_exclusions = exclusion_log.get('ERR_MISSING_AGE_FIELD', 0)
    score_exclusions = exclusion_log.get('ERR_MISSING_SCORE', 0)
    mmse_exclusions = exclusion_log.get('ERR_MMSE_IMPAIRED', 0)
    
    # Check if MMSE was actually evaluated
    has_mmse = False
    if mmse_flag_path.exists():
        with open(mmse_flag_path, 'r') as f:
            mmse_flag = json.load(f)
            has_mmse = mmse_flag.get('has_mmse', False)
    
    # If MMSE column didn't exist or was all null, MMSE exclusions should be 0
    if not has_mmse:
        mmse_exclusions = 0
    
    total_exclusions = age_exclusions + score_exclusions + mmse_exclusions
    valid_records = raw_count - total_exclusions
    
    # Calculate validity percentage
    if raw_count == 0:
        validity_percentage = 0.0
        logger.warning("Raw dataset is empty, validity percentage is 0%")
    else:
        validity_percentage = (valid_records / raw_count) * 100
    
    return {
        'total_raw_records': raw_count,
        'total_exclusions': total_exclusions,
        'valid_records': valid_records,
        'validity_percentage': round(validity_percentage, 2),
        'breakdown': {
            'age_exclusions': age_exclusions,
            'score_exclusions': score_exclusions,
            'mmse_exclusions': mmse_exclusions if has_mmse else 0
        },
        'mmse_evaluated': has_mmse
    }

def save_validity_metrics(metrics: Dict[str, Any], output_path: Path) -> None:
    """Save the validity metrics to a JSON file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(metrics, f, indent=2)
    
    logger.info(f"Validity metrics saved to {output_path}")

def main():
    """Main entry point for T014b."""
    # Define paths
    project_root = Path(__file__).resolve().parent.parent
    raw_dataset_path = project_root / 'data' / 'raw' / 'raw_dataset.csv'
    exclusion_log_path = project_root / 'data' / 'processed' / 'exclusion_log.json'
    mmse_flag_path = project_root / 'data' / 'processed' / 'mmse_flag.json'
    output_path = project_root / 'data' / 'processed' / 'validity_metrics.json'
    
    try:
        # Load raw record count
        logger.info(f"Loading raw dataset from {raw_dataset_path}")
        raw_count = load_raw_count(raw_dataset_path)
        logger.info(f"Total raw records: {raw_count}")
        
        # Load exclusion log
        logger.info(f"Loading exclusion log from {exclusion_log_path}")
        exclusion_log = load_exclusion_log(exclusion_log_path)
        
        # Calculate validity metrics
        logger.info("Calculating validity metrics")
        metrics = calculate_validity_metrics(raw_count, exclusion_log, mmse_flag_path)
        
        # Save results
        logger.info(f"Saving validity metrics to {output_path}")
        save_validity_metrics(metrics, output_path)
        
        # Log summary
        logger.info(f"Validity metrics summary:")
        logger.info(f"  - Total raw records: {metrics['total_raw_records']}")
        logger.info(f"  - Valid records: {metrics['valid_records']}")
        logger.info(f"  - Validity percentage: {metrics['validity_percentage']}%")
        logger.info(f"  - MMSE evaluated: {metrics['mmse_evaluated']}")
        
        return metrics
        
    except FileNotFoundError as e:
        logger.error(f"Required file not found: {e}")
        raise
    except Exception as e:
        logger.error(f"Error calculating validity metrics: {e}")
        raise

if __name__ == "__main__":
    main()
