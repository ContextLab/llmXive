"""
Task T014a: Generate Cleaned Dataset

Consumes data/processed/cleaned_dataset_intermediate.csv (from T012e)
and produces data/processed/cleaned_dataset.csv with the required columns:
participant_id, stimulus_type, perseverative_errors, categories_completed, age.

Dependencies: T012c (exclusion log), T012e (intermediate dataset).
"""
import os
import json
import logging
import pandas as pd
from pathlib import Path
from typing import Optional, Dict, Any

# Import logging setup from utils as per API surface
from utils import setup_logging, log_info, log_warning, log_error, get_timestamp

# Configure logger
logger = logging.getLogger(__name__)

# Define paths relative to project root
PROJECT_ROOT = Path(__file__).resolve().parent.parent
INTERMEDIATE_PATH = PROJECT_ROOT / "data" / "processed" / "cleaned_dataset_intermediate.csv"
OUTPUT_PATH = PROJECT_ROOT / "data" / "processed" / "cleaned_dataset.csv"
EXCLUSION_LOG_PATH = PROJECT_ROOT / "data" / "processed" / "exclusion_log.json"
MMSE_FLAG_PATH = PROJECT_ROOT / "data" / "processed" / "mmse_flag.json"

def load_exclusion_log() -> Dict[str, Any]:
    """Load the exclusion log generated by T012c."""
    if not EXCLUSION_LOG_PATH.exists():
        log_error(f"Exclusion log not found at {EXCLUSION_LOG_PATH}.")
        raise FileNotFoundError(f"Exclusion log not found at {EXCLUSION_LOG_PATH}")
    
    with open(EXCLUSION_LOG_PATH, 'r', encoding='utf-8') as f:
        return json.load(f)

def load_mmse_flag() -> bool:
    """Load the MMSE flag generated by T012d."""
    if not MMSE_FLAG_PATH.exists():
        log_warning(f"MMSE flag not found at {MMSE_FLAG_PATH}. Assuming False.")
        return False
    
    with open(MMSE_FLAG_PATH, 'r', encoding='utf-8') as f:
        data = json.load(f)
        return data.get('has_mmse', False)

def create_cleaned_dataset(df_intermediate: pd.DataFrame) -> pd.DataFrame:
    """
    Select and ensure the correct columns for the final cleaned dataset.
    
    Required columns:
    - participant_id
    - stimulus_type (nostalgia/control)
    - perseverative_errors
    - categories_completed
    - age
    """
    required_columns = [
        'participant_id', 
        'stimulus_type', 
        'perseverative_errors', 
        'categories_completed', 
        'age'
    ]
    
    # Validate presence of required columns
    missing_cols = [col for col in required_columns if col not in df_intermediate.columns]
    if missing_cols:
        log_error(f"Missing required columns in intermediate dataset: {missing_cols}")
        raise ValueError(f"Missing required columns: {missing_cols}")
    
    # Select only the required columns
    df_cleaned = df_intermediate[required_columns].copy()
    
    # Ensure data types are appropriate (optional but good practice)
    # Assuming numeric columns are already numeric, but safe cast doesn't hurt if clean
    # df_cleaned['perseverative_errors'] = pd.to_numeric(df_cleaned['perseverative_errors'], errors='coerce')
    # df_cleaned['categories_completed'] = pd.to_numeric(df_cleaned['categories_completed'], errors='coerce')
    # df_cleaned['age'] = pd.to_numeric(df_cleaned['age'], errors='coerce')
    
    # Drop any rows that might have become NaN during casting (if we did coerce)
    # Since we are loading from a filtered CSV, we assume they are clean, but check for strictness
    df_cleaned = df_cleaned.dropna(subset=required_columns)
    
    log_info(f"Created cleaned dataset with {len(df_cleaned)} records.")
    return df_cleaned

def save_cleaned_dataset(df: pd.DataFrame) -> None:
    """Save the cleaned dataset to CSV."""
    # Ensure output directory exists
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    
    df.to_csv(OUTPUT_PATH, index=False)
    log_info(f"Saved cleaned dataset to {OUTPUT_PATH}")

def main() -> None:
    """Main entry point for Task T014a."""
    setup_logging()
    log_info(f"Starting Task T014a: Generate Cleaned Dataset at {get_timestamp()}")
    
    try:
        # 1. Load exclusion log (dependency check)
        exclusion_log = load_exclusion_log()
        log_info(f"Loaded exclusion log: {exclusion_log}")
        
        # 2. Load MMSE flag (dependency check)
        has_mmse = load_mmse_flag()
        log_info(f"MMSE flag (has_mmse): {has_mmse}")
        
        # 3. Load intermediate dataset
        if not INTERMEDIATE_PATH.exists():
            log_error(f"Intermediate dataset not found at {INTERMEDIATE_PATH}.")
            log_error("Ensure T012e has been executed successfully.")
            raise FileNotFoundError(f"Intermediate dataset not found at {INTERMEDIATE_PATH}")
        
        df_intermediate = pd.read_csv(INTERMEDIATE_PATH)
        log_info(f"Loaded intermediate dataset with {len(df_intermediate)} records.")
        
        # 4. Create final cleaned dataset
        df_cleaned = create_cleaned_dataset(df_intermediate)
        
        # 5. Save the result
        save_cleaned_dataset(df_cleaned)
        
        log_info(f"Task T014a completed successfully at {get_timestamp()}.")
        
    except Exception as e:
        log_error(f"Task T014a failed: {str(e)}")
        raise

if __name__ == "__main__":
    main()