"""
Task T014a: Create cleaned_dataset.csv

Depends on:
  - T012: exclusion_log.json (counts of excluded records)
  - T013b: has_mmse flag in config (for downstream filtering logic context)

Produces:
  - data/processed/cleaned_dataset.csv
"""
import os
import json
import logging
import pandas as pd
from pathlib import Path
from typing import Optional, Dict, Any

# Import from project API
from config import get_config, get_env_bool
from utils import setup_logging, log_info, log_warning, log_error
from ingestion import load_dataset, validate_and_filter_dataset

logger = logging.getLogger(__name__)

def load_exclusion_log(config: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """Load the exclusion log generated by T012."""
    exclusion_path = Path(config["paths"]["processed"]) / "exclusion_log.json"
    if not exclusion_path.exists():
        log_warning(f"Exclusion log not found at {exclusion_path}. Proceeding without exclusion counts.")
        return None
    
    with open(exclusion_path, 'r') as f:
        return json.load(f)

def load_mmse_flag(config: Dict[str, Any]) -> bool:
    """
    Load the has_mmse flag from config (set by T013b).
    Returns True if MMSE column was present in source, False otherwise.
    """
    # Check environment variable first (set by T013b)
    has_mmse = get_env_bool("HAS_MMSE", default=False)
    if not has_mmse:
        log_warning("MMSE column not found in source dataset (has_mmse=False). Downstream filtering requiring MMSE will be skipped.")
    return has_mmse

def create_cleaned_dataset(config: Dict[str, Any], has_mmse: bool) -> pd.DataFrame:
    """
    Load raw data, apply exclusions from T012, and produce the cleaned dataset.
    
    Columns required:
      - participant_id
      - stimulus_type (nostalgia/control)
      - perseverative_errors
      - categories_completed
      - age
    """
    log_info("Loading raw dataset...")
    
    # Load dataset using the ingestion module
    raw_df = load_dataset(config)
    
    if raw_df is None or raw_df.empty:
        log_error("Failed to load raw dataset. Cannot proceed with T014a.")
        raise ValueError("Raw dataset is empty or failed to load.")

    log_info(f"Raw dataset loaded with {len(raw_df)} records.")

    # Apply validation and filtering (T011 logic: age >= 65, non-null metrics)
    # This function also handles the exclusion logic internally or via logs
    filtered_df = validate_and_filter_dataset(raw_df, config)

    if filtered_df is None or filtered_df.empty:
        log_error("No valid records remain after filtering. Cannot produce cleaned dataset.")
        raise ValueError("No valid records remain after filtering.")

    log_info(f"Filtered dataset has {len(filtered_df)} valid records.")

    # Ensure required columns exist
    required_cols = [
        'participant_id', 
        'stimulus_type', 
        'perseverative_errors', 
        'categories_completed', 
        'age'
    ]
    
    missing_cols = [col for col in required_cols if col not in filtered_df.columns]
    if missing_cols:
        log_error(f"Missing required columns in dataset: {missing_cols}")
        raise ValueError(f"Dataset missing required columns: {missing_cols}")

    # Select only required columns
    cleaned_df = filtered_df[required_cols].copy()

    # Ensure data types are correct
    cleaned_df['age'] = pd.to_numeric(cleaned_df['age'], errors='coerce')
    cleaned_df['perseverative_errors'] = pd.to_numeric(cleaned_df['perseverative_errors'], errors='coerce')
    cleaned_df['categories_completed'] = pd.to_numeric(cleaned_df['categories_completed'], errors='coerce')

    # Drop any remaining rows with NaN in required columns (safety net)
    initial_count = len(cleaned_df)
    cleaned_df = cleaned_df.dropna(subset=required_cols)
    dropped_count = initial_count - len(cleaned_df)
    if dropped_count > 0:
        log_warning(f"Dropped {dropped_count} records due to NaN in required columns.")

    # Log MMSE context (from T013b)
    if has_mmse:
        log_info("MMSE column was present in source. Downstream tasks (T027) may filter by MMSE < 24.")
    else:
        log_info("MMSE column was NOT present in source. Downstream tasks (T027) will skip MMSE filtering.")

    return cleaned_df

def save_cleaned_dataset(df: pd.DataFrame, config: Dict[str, Any]) -> str:
    """Save the cleaned dataset to data/processed/cleaned_dataset.csv."""
    output_path = Path(config["paths"]["processed"]) / "cleaned_dataset.csv"
    df.to_csv(output_path, index=False)
    log_info(f"Cleaned dataset saved to {output_path} ({len(df)} records).")
    return str(output_path)

def main():
    """Main entry point for T014a."""
    config = get_config()
    setup_logging(config)

    try:
        # Load exclusion log context (T012)
        exclusion_log = load_exclusion_log(config)
        if exclusion_log:
            log_info(f"Exclusion log loaded: {exclusion_log}")

        # Load MMSE flag context (T013b)
        has_mmse = load_mmse_flag(config)

        # Create cleaned dataset
        cleaned_df = create_cleaned_dataset(config, has_mmse)

        # Save output
        output_path = save_cleaned_dataset(cleaned_df, config)

        log_info(f"T014a completed successfully. Output: {output_path}")
        return 0

    except Exception as e:
        log_error(f"T014a failed: {str(e)}")
        raise

if __name__ == "__main__":
    main()
