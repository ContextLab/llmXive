"""
Task T019: Bonferroni Correction Implementation

Implements multiple-comparison correction (Bonferroni) for the statistical results
generated in T018. It loads the uncorrected p-values for 'perseverative_errors'
and 'categories_completed', applies the Bonferroni correction using scipy.stats.multipletests,
and saves the corrected results to the data/results directory.

Dependencies:
- data/results/statistical_report.json (Output of T018)
"""
import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Tuple

import numpy as np
from scipy import stats
from scipy.stats import multipletests

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Project root relative to script location
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_RESULTS_DIR = PROJECT_ROOT / "data" / "results"
STATISTICAL_REPORT_PATH = DATA_RESULTS_DIR / "statistical_report.json"
BONFERRONI_OUTPUT_PATH = DATA_RESULTS_DIR / "bonferroni_corrected_results.json"

def load_statistical_results() -> Dict[str, Any]:
    """
    Loads the statistical report generated by T018.
    
    Returns:
        Dict containing p-values and other statistics.
        
    Raises:
        FileNotFoundError: If the statistical report does not exist.
        ValueError: If the file exists but is empty or malformed.
    """
    if not STATISTICAL_REPORT_PATH.exists():
        raise FileNotFoundError(
            f"Statistical report not found at {STATISTICAL_REPORT_PATH}. "
            "Ensure T018 (Welch's T-Test) has been completed successfully."
        )
    
    try:
        with open(STATISTICAL_REPORT_PATH, 'r') as f:
            data = json.load(f)
        if not data:
            raise ValueError("Statistical report is empty.")
        return data
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse JSON from {STATISTICAL_REPORT_PATH}: {e}")
        raise

def apply_bonferroni_correction(results: Dict[str, Any]) -> Dict[str, Any]:
    """
    Applies Bonferroni correction to the p-values found in the statistical results.
    
    The task requires correction for two primary metrics:
    1. perseverative_errors
    2. categories_completed
    
    Args:
        results: The dictionary containing uncorrected statistical results.
        
    Returns:
        A dictionary containing the original results plus the Bonferroni corrected p-values.
    """
    logger.info("Applying Bonferroni correction to statistical results.")
    
    # Extract p-values for the two metrics we are comparing
    # We expect the structure from T018 to have keys like 'perseverative_errors' and 'categories_completed'
    # Each should contain a 'p_value' key.
    
    p_values = []
    metric_names = []
    
    metrics_to_check = ['perseverative_errors', 'categories_completed']
    
    for metric in metrics_to_check:
        if metric in results:
            if 'p_value' in results[metric]:
                p_val = results[metric]['p_value']
                p_values.append(p_val)
                metric_names.append(metric)
                logger.debug(f"Found p-value for {metric}: {p_val}")
            else:
                logger.warning(f"Metric '{metric}' found in results but missing 'p_value' key.")
        else:
            logger.warning(f"Metric '{metric}' not found in statistical results.")
    
    if len(p_values) == 0:
        logger.error("No valid p-values found to correct. Cannot proceed with Bonferroni correction.")
        # Return results as is, but flag that correction couldn't happen
        results['bonferroni_status'] = 'failed_no_p_values'
        return results
    
    # Perform Bonferroni correction
    # multipletests returns: (reject, p_corrected, p_corrected_raw, alphac_sidak, alphac_bonf)
    # We use method='bonferroni'
    try:
        reject, p_corrected, _, _ = multipletests(p_values, method='bonferroni')
    except Exception as e:
        logger.error(f"Error during multipletests calculation: {e}")
        raise
    
    logger.info(f"Bonferroni correction applied to {len(p_values)} tests.")
    
    # Update the results dictionary with corrected values
    corrected_results = results.copy()
    corrected_results['bonferroni_status'] = 'success'
    corrected_results['bonferroni_method'] = 'bonferroni'
    corrected_results['bonferroni_metrics'] = []
    
    for i, metric in enumerate(metric_names):
        correction_entry = {
            'metric': metric,
            'uncorrected_p_value': p_values[i],
            'bonferroni_corrected_p_value': float(p_corrected[i]),
            'is_significant_at_0.05': bool(reject[i])
        }
        corrected_results['bonferroni_metrics'].append(correction_entry)
        
        # Also update the top-level metric for easy access if needed, 
        # or keep in the list. The task asks to "Report corrected p-values".
        # We will store it in the specific metric block if it exists there originally.
        if metric in corrected_results:
            corrected_results[metric]['bonferroni_corrected_p_value'] = float(p_corrected[i])
            corrected_results[metric]['is_significant_after_correction'] = bool(reject[i])
    
    return corrected_results

def save_bonferroni_results(corrected_results: Dict[str, Any]) -> str:
    """
    Saves the corrected results to the specified output file.
    
    Args:
        corrected_results: The dictionary with Bonferroni corrections applied.
        
    Returns:
        Path to the saved file.
    """
    # Ensure directory exists
    DATA_RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    
    try:
        with open(BONFERRONI_OUTPUT_PATH, 'w') as f:
            json.dump(corrected_results, f, indent=4)
        logger.info(f"Bonferroni corrected results saved to {BONFERRONI_OUTPUT_PATH}")
        return str(BONFERRONI_OUTPUT_PATH)
    except IOError as e:
        logger.error(f"Failed to save results to {BONFERRONI_OUTPUT_PATH}: {e}")
        raise

def main():
    """Main entry point for Task T019."""
    logger.info("Starting Task T019: Bonferroni Correction")
    
    try:
        # 1. Load statistical results from T018
        results = load_statistical_results()
        
        # 2. Apply Bonferroni correction
        corrected_results = apply_bonferroni_correction(results)
        
        # 3. Save the results
        output_path = save_bonferroni_results(corrected_results)
        
        logger.info("Task T019 completed successfully.")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"Data missing: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during T019 execution: {e}")
        return 1

if __name__ == "__main__":
    exit(main())
