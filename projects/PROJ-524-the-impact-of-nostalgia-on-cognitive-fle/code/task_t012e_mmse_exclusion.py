import os
import json
import logging
import pandas as pd
from pathlib import Path
from typing import Optional, Dict, Any

from utils import setup_logging, log_info, log_warning, log_error
from config import get_config

logger = logging.getLogger(__name__)

def load_score_filtered_dataset() -> pd.DataFrame:
    """Load the dataset filtered by age and score (T012b output)."""
    config = get_config()
    input_path = Path(config['data_processed_dir']) / 'cleaned_score_filtered.csv'
    
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}. "
                                "Ensure T012b (score exclusion) has been run.")
    
    df = pd.read_csv(input_path)
    log_info(f"Loaded {len(df)} records from {input_path}")
    return df

def load_mmse_flag() -> Dict[str, Any]:
    """Load the MMSE flag JSON generated by T012d."""
    config = get_config()
    flag_path = Path(config['data_processed_dir']) / 'mmse_flag.json'
    
    if not flag_path.exists():
        raise FileNotFoundError(f"MMSE flag file not found: {flag_path}. "
                                "Ensure T012d (MMSE flag) has been run.")
    
    with open(flag_path, 'r') as f:
        return json.load(f)

def update_exclusion_counts(counts: Dict[str, Any], key: str, count: int) -> Dict[str, Any]:
    """Update the exclusion counts dictionary and return it."""
    counts[key] = count
    return counts

def save_exclusion_counts(counts: Dict[str, Any]) -> None:
    """Save the updated exclusion counts to exclusion_counts.json."""
    config = get_config()
    output_path = Path(config['data_processed_dir']) / 'exclusion_counts.json'
    
    # Load existing counts if they exist (from T012a and T012b)
    if output_path.exists():
        with open(output_path, 'r') as f:
            counts = json.load(f)
    
    with open(output_path, 'w') as f:
        json.dump(counts, f, indent=2)
    
    log_info(f"Exclusion counts saved to {output_path}")

def filter_mmse(df: pd.DataFrame, threshold: int = 24) -> pd.DataFrame:
    """
    Filter the dataset for MMSE >= threshold.
    
    Args:
        df: The input dataframe (already filtered by age and score).
        threshold: The MMSE threshold (default 24).
    
    Returns:
        Filtered dataframe.
    """
    if 'MMSE' not in df.columns:
        log_warning("MMSE column not found in dataset. Returning original dataframe.")
        return df
    
    # Filter out records with MMSE < threshold (exclude impaired)
    # Keep records where MMSE >= threshold or MMSE is null (optional field)
    # Per spec: MMSE is optional, so we only exclude if MMSE is present AND < 24
    mask = (df['MMSE'].isna()) | (df['MMSE'] >= threshold)
    filtered_df = df[mask].copy()
    
    excluded_count = len(df) - len(filtered_df)
    log_info(f"MMSE exclusion: Excluded {excluded_count} records with MMSE < {threshold}")
    
    return filtered_df, excluded_count

def main():
    """
    Main entry point for T012e: MMSE Exclusion.
    
    Reads has_mmse from data/processed/mmse_flag.json.
    If has_mmse=True, filters records where MMSE < 24 and writes to 
    data/processed/cleaned_dataset_intermediate.csv.
    If has_mmse=False, copies cleaned_score_filtered.csv to 
    cleaned_dataset_intermediate.csv.
    Updates exclusion_counts.json with ERR_MMSE_IMPAIRED count.
    """
    setup_logging()
    config = get_config()
    
    log_info("Starting T012e: MMSE Exclusion...")
    
    try:
        # Load MMSE flag
        mmse_flag = load_mmse_flag()
        has_mmse = mmse_flag.get('has_mmse', False)
        
        if not has_mmse:
            log_info("SKIP_MMSE_EXCLUSION: MMSE column not present or all null. "
                     "Copying cleaned_score_filtered.csv to cleaned_dataset_intermediate.csv")
            
            # Copy the score-filtered dataset to intermediate
            input_path = Path(config['data_processed_dir']) / 'cleaned_score_filtered.csv'
            output_path = Path(config['data_processed_dir']) / 'cleaned_dataset_intermediate.csv'
            
            df = pd.read_csv(input_path)
            df.to_csv(output_path, index=False)
            
            # Update exclusion counts (no MMSE exclusions)
            counts_path = Path(config['data_processed_dir']) / 'exclusion_counts.json'
            counts = {}
            if counts_path.exists():
                with open(counts_path, 'r') as f:
                    counts = json.load(f)
            counts['ERR_MMSE_IMPAIRED'] = 0
            
            with open(counts_path, 'w') as f:
                json.dump(counts, f, indent=2)
            
            log_info(f"Exclusion counts updated: {counts}")
            log_info(f"Intermediate dataset saved to {output_path}")
            return
        
        # has_mmse is True - perform MMSE filtering
        log_info("MMSE column present with non-null values. Filtering for MMSE >= 24...")
        
        # Load score-filtered dataset
        df = load_score_filtered_dataset()
        
        # Filter by MMSE
        filtered_df, excluded_count = filter_mmse(df, threshold=24)
        
        # Save intermediate dataset
        output_path = Path(config['data_processed_dir']) / 'cleaned_dataset_intermediate.csv'
        filtered_df.to_csv(output_path, index=False)
        log_info(f"Filtered dataset saved to {output_path} ({len(filtered_df)} records)")
        
        # Update exclusion counts
        counts_path = Path(config['data_processed_dir']) / 'exclusion_counts.json'
        counts = {}
        if counts_path.exists():
            with open(counts_path, 'r') as f:
                counts = json.load(f)
        
        counts['ERR_MMSE_IMPAIRED'] = excluded_count
        
        with open(counts_path, 'w') as f:
            json.dump(counts, f, indent=2)
        
        log_info(f"Exclusion counts updated: ERR_MMSE_IMPAIRED = {excluded_count}")
        log_info("T012e: MMSE Exclusion completed successfully.")
        
    except FileNotFoundError as e:
        log_error(f"File not found: {e}")
        raise
    except Exception as e:
        log_error(f"MMSE exclusion failed: {e}")
        raise

if __name__ == "__main__":
    main()