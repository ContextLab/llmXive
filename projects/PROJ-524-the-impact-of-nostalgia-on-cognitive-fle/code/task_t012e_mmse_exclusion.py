import os
import json
import logging
import pandas as pd
from pathlib import Path
from typing import Optional, Dict, Any

from config import get_mmse_threshold
from utils import setup_logging, log_info, log_warning, log_error

# --- Configuration ---
MMSE_FLAG_PATH = Path("data/processed/mmse_flag.json")
SCORE_FILTERED_PATH = Path("data/processed/cleaned_score_filtered.csv")
CLEANED_DATASET_PATH = Path("data/processed/cleaned_dataset.csv")
NO_MMSE_DATASET_PATH = Path("data/processed/cleaned_dataset_no_mmse.csv")
EXCLUSION_COUNTS_PATH = Path("data/processed/exclusion_counts.json")

# --- Helper Functions ---

def load_score_filtered_dataset() -> pd.DataFrame:
    """Loads the dataset after score exclusion (T012b)."""
    if not SCORE_FILTERED_PATH.exists():
        raise FileNotFoundError(
            f"Required file not found: {SCORE_FILTERED_PATH}. "
            "Ensure T012b (Score Exclusion) has been completed."
        )
    log_info(f"Loading score-filtered dataset from {SCORE_FILTERED_PATH}")
    return pd.read_csv(SCORE_FILTERED_PATH)

def load_mmse_flag() -> Dict[str, Any]:
    """Loads the MMSE flag generated by T012d."""
    if not MMSE_FLAG_PATH.exists():
        raise FileNotFoundError(
            f"Required file not found: {MMSE_FLAG_PATH}. "
            "Ensure T012d (MMSE Flag) has been completed."
        )
    log_info(f"Loading MMSE flag from {MMSE_FLAG_PATH}")
    with open(MMSE_FLAG_PATH, 'r') as f:
        return json.load(f)

def update_exclusion_counts(
    current_counts: Dict[str, Any], 
    key: str, 
    count: int
) -> Dict[str, Any]:
    """Updates the exclusion counts dictionary."""
    current_counts[key] = count
    return current_counts

def save_exclusion_counts(counts: Dict[str, Any]) -> None:
    """Saves the updated exclusion counts to JSON."""
    log_info(f"Saving updated exclusion counts to {EXCLUSION_COUNTS_PATH}")
    with open(EXCLUSION_COUNTS_PATH, 'w') as f:
        json.dump(counts, f, indent=2)

def filter_mmse(df: pd.DataFrame, threshold: int) -> pd.DataFrame:
    """Filters the dataframe for MMSE >= threshold."""
    if 'MMSE' not in df.columns:
        log_error("Column 'MMSE' not found in dataframe during filter.")
        return df
    
    log_info(f"Filtering for MMSE >= {threshold}")
    original_len = len(df)
    filtered_df = df[df['MMSE'] >= threshold].copy()
    filtered_len = len(filtered_df)
    excluded_count = original_len - filtered_len
    
    log_info(f"MMSE Filter: Excluded {excluded_count} records (Total: {original_len} -> {filtered_len})")
    return filtered_df

def save_cleaned_dataset(df: pd.DataFrame, path: Path) -> None:
    """Saves the cleaned dataframe to CSV."""
    log_info(f"Saving cleaned dataset to {path}")
    df.to_csv(path, index=False)

def main() -> None:
    """
    T012e: MMSE Exclusion and Robustness Prep.
    
    1. Reads has_mmse from data/processed/mmse_flag.json.
    2. If has_mmse=True: Filters cleaned_score_filtered.csv for MMSE >= 24 -> cleaned_dataset.csv.
    3. If has_mmse=False: Copies cleaned_score_filtered.csv -> cleaned_dataset.csv.
    4. ALWAYS: Copies cleaned_score_filtered.csv -> cleaned_dataset_no_mmse.csv (for robustness).
    5. Updates exclusion_counts.json.
    """
    setup_logging()
    
    try:
        # Step 1: Load Inputs
        log_info("Starting T012e: MMSE Exclusion and Robustness Prep")
        df_score_filtered = load_score_filtered_dataset()
        mmse_flag_data = load_mmse_flag()
        
        has_mmse = mmse_flag_data.get('has_mmse', False)
        log_info(f"MMSE Flag Status: has_mmse = {has_mmse}")

        # Load existing exclusion counts if they exist
        exclusion_counts = {}
        if EXCLUSION_COUNTS_PATH.exists():
            with open(EXCLUSION_COUNTS_PATH, 'r') as f:
                exclusion_counts = json.load(f)

        # Step 2: Generate Robustness Dataset (No MMSE filter)
        # This file preserves the state before MMSE exclusion for sensitivity analysis
        log_info("Generating robustness dataset (cleaned_dataset_no_mmse.csv)...")
        save_cleaned_dataset(df_score_filtered, NO_MMSE_DATASET_PATH)

        # Step 3: Generate Primary Dataset (With MMSE filter if available)
        if has_mmse:
            log_info("MMSE data available. Applying MMSE filter for primary dataset.")
            threshold = get_mmse_threshold()
            df_cleaned = filter_mmse(df_score_filtered, threshold)
            
            # Calculate exclusion count for this step
            mmse_excluded_count = len(df_score_filtered) - len(df_cleaned)
            exclusion_counts = update_exclusion_counts(
                exclusion_counts, 
                'ERR_MMSE_IMPAIRED', 
                mmse_excluded_count
            )
        else:
            log_warning("MMSE data not available (has_mmse=False). Skipping MMSE filter.")
            log_warning("Primary dataset will be identical to robustness dataset.")
            df_cleaned = df_score_filtered.copy()
            # Ensure key exists with 0 if not set, though T012d should have set it
            if 'ERR_MMSE_IMPAIRED' not in exclusion_counts:
                exclusion_counts['ERR_MMSE_IMPAIRED'] = 0

        # Step 4: Save Primary Dataset
        save_cleaned_dataset(df_cleaned, CLEANED_DATASET_PATH)

        # Step 5: Save Updated Exclusion Counts
        save_exclusion_counts(exclusion_counts)

        log_info("T012e completed successfully.")

    except FileNotFoundError as e:
        log_error(f"Missing required input file: {e}")
        raise
    except Exception as e:
        log_error(f"Unexpected error during T012e execution: {e}")
        raise

if __name__ == "__main__":
    main()