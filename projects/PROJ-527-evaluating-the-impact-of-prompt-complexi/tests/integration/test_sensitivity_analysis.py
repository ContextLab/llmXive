"""
Integration test for sensitivity analysis (Task T032).

This test verifies that the sensitivity analysis logic correctly re-bins data
using shifted thresholds (±10 tokens) and reports the variance in pass rates,
satisfying FR-010.

It depends on the real execution results generated by previous tasks (T030).
"""
import os
import sys
import pytest
import pandas as pd
from pathlib import Path

# Add project root to path for imports
project_root = Path(__file__).parent.parent.parent
sys.path.insert(0, str(project_root / "code"))

from analysis.stats import run_sensitivity_analysis
from config import Paths


class TestSensitivityAnalysis:
    """Integration tests for the sensitivity analysis pipeline."""

    @pytest.fixture
    def execution_results_path(self):
        """Ensure execution results exist before running tests."""
        # The path is defined in config.py
        path = Paths.DATA_RESULTS / "execution_outcomes.csv"
        if not path.exists():
            pytest.fail(
                f"Execution results not found at {path}. "
                "Please run Phase 4 (User Story 2) tasks first to generate data."
            )
        return path

    def test_sensitivity_analysis_runs_and_produces_output(self, execution_results_path):
        """
        Test that the sensitivity analysis runs successfully on real data
        and produces the expected output file.

        FR-010: Sensitivity analysis re-bins data using shifted thresholds (±10 tokens)
        and reports variance in pass rates.
        """
        output_path = Paths.DATA_RESULTS / "sensitivity_analysis_results.csv"
        
        # Clean up any existing output to ensure we are testing fresh generation
        if output_path.exists():
            output_path.unlink()

        # Run the sensitivity analysis
        # This function should read execution_outcomes.csv, apply shifts, and write results
        result_df = run_sensitivity_analysis(
            input_path=str(execution_results_path),
            output_path=str(output_path),
            shift_tokens=10
        )

        # Assert the output file was created
        assert output_path.exists(), "Sensitivity analysis output file was not created."

        # Assert the result DataFrame is not empty
        assert len(result_df) > 0, "Sensitivity analysis produced an empty result."

        # Assert expected columns exist
        expected_columns = {
            "complexity_level",
            "shift_direction",
            "shift_amount",
            "pass_rate_original",
            "pass_rate_shifted",
            "variance"
        }
        assert set(result_df.columns) == expected_columns, (
            f"Expected columns {expected_columns}, got {set(result_df.columns)}"
        )

        # Assert variance is calculated correctly (|shifted - original|)
        # Allow for small floating point differences
        result_df["calculated_variance"] = abs(
            result_df["pass_rate_shifted"] - result_df["pass_rate_original"]
        )
        
        # Check that the stored variance matches the calculation (within tolerance)
        pd.testing.assert_series_equal(
            result_df["variance"],
            result_df["calculated_variance"],
            check_names=False
        )

        # Verify that we have results for both positive and negative shifts
        assert "positive" in result_df["shift_direction"].unique(), "Missing positive shift results."
        assert "negative" in result_df["shift_direction"].unique(), "Missing negative shift results."

        # Verify that we have results for all complexity levels present in the data
        # (at least one complexity level should be present)
        assert len(result_df["complexity_level"].unique()) >= 1, "No complexity levels found in results."

    def test_sensitivity_analysis_handles_edge_cases(self, execution_results_path):
        """
        Test that the sensitivity analysis handles edge cases gracefully,
        such as when a shift causes a bin to become empty.
        """
        output_path = Paths.DATA_RESULTS / "sensitivity_analysis_results.csv"
        
        # Run with a large shift to potentially cause edge cases
        # (e.g., shifting a "simple" bin into "moderate" territory completely)
        result_df = run_sensitivity_analysis(
            input_path=str(execution_results_path),
            output_path=str(output_path),
            shift_tokens=100  # Large shift
        )

        # The function should not raise an exception
        # It should handle empty bins by setting pass_rate to NaN or 0, depending on implementation
        assert result_df is not None
        assert len(result_df) > 0

        # Check for NaN values which indicate empty bins (handled gracefully)
        # If the implementation chooses to drop empty bins, this check might be skipped
        # but the test should still pass if the function doesn't crash.
        # Here we just ensure the function completes and returns a valid DataFrame.
        assert isinstance(result_df, pd.DataFrame)