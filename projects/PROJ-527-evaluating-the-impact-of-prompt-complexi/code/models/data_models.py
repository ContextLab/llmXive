from datetime import datetime
from typing import Any, Dict, List, Optional, TypedDict
from pydantic import BaseModel, Field, field_validator, model_validator
from enum import Enum
import json


class ComplexityLabel(str, Enum):
    SIMPLE = "simple"
    MODERATE = "moderate"
    COMPLEX = "complex"
    VERY_COMPLEX = "very_complex"
    DEGENERATE = "degenerate"


class ExecutionStatus(str, Enum):
    PASS = "pass"
    FAIL = "fail"
    TIMEOUT = "timeout"
    SYNTAX_ERROR = "syntax_error"
    RUNTIME_ERROR = "runtime_error"


class HumanEvalProblem(BaseModel):
    """
    Represents a single HumanEval problem instance.
    Fields:
      - problem_id: Unique identifier (e.g., 'HumanEval/0')
      - prompt: The original problem description text
      - canonical_solution: The reference solution code
      - test_list: List of test cases (strings)
    """
    problem_id: str
    prompt: str
    canonical_solution: str
    test_list: List[str]


class StructuralElementCount(BaseModel):
    """
    Counts of structural elements within a prompt.
    Fields:
      - examples: Number of code examples provided
      - constraints: Number of explicit constraints listed
      - steps: Number of sequential steps or instructions
    """
    examples: int
    constraints: int
    steps: int


class PromptVariant(BaseModel):
    """
    Represents a specific complexity variant of a HumanEval problem prompt.
    Fields:
      - variant_id: Unique identifier for this variant
      - problem_id: Reference to the source problem
      - complexity_label: The complexity category (simple, moderate, etc.)
      - prompt_text: The actual prompt text generated
      - token_count: Number of tokens in the prompt
      - structural_element_count: Dictionary with keys 'examples', 'constraints', 'steps'
      - dependency_depth: Maximum depth of instruction dependency chains
    """
    variant_id: str
    problem_id: str
    complexity_label: str
    prompt_text: str
    token_count: int
    structural_element_count: Dict[str, int]
    dependency_depth: int

    @field_validator('complexity_label')
    @classmethod
    def validate_label(cls, v: str) -> str:
        if v not in [e.value for e in ComplexityLabel]:
            raise ValueError(f"Invalid complexity_label: {v}. Must be one of {list(ComplexityLabel)}")
        return v

    @field_validator('structural_element_count')
    @classmethod
    def validate_structural_keys(cls, v: Dict[str, int]) -> Dict[str, int]:
        required_keys = {'examples', 'constraints', 'steps'}
        if not required_keys.issubset(set(v.keys())):
            missing = required_keys - set(v.keys())
            raise ValueError(f"structural_element_count missing keys: {missing}")
        return v


class GeneratedCode(BaseModel):
    """
    Represents code generated by an LLM for a specific prompt variant.
    Fields:
      - code_id: Unique identifier for this generation
      - variant_id: Reference to the prompt variant used
      - code: The generated code string
      - generation_metadata: Dictionary containing LLM response metadata (model, tokens, etc.)
    """
    code_id: str
    variant_id: str
    code: str
    generation_metadata: Dict[str, Any]


class ExecutionOutcome(BaseModel):
    """
    Represents the result of executing generated code against unit tests.
    Fields:
      - outcome_id: Unique identifier for this outcome
      - code_id: Reference to the generated code
      - pass_count: Number of passed tests
      - fail_count: Number of failed tests
      - error_details: String description of errors or None
      - timeout_flag: Boolean indicating if execution timed out
    """
    outcome_id: str
    code_id: str
    pass_count: int
    fail_count: int
    error_details: str
    timeout_flag: bool


class AnalysisResult(BaseModel):
    """
    Represents the result of a statistical analysis.
    Fields:
      - result_id: Unique identifier
      - test_type: Type of statistical test performed (e.g., 'lmm', 'anova')
      - statistic: The calculated test statistic value
      - p_value: The calculated p-value
      - effect_size: The calculated effect size (e.g., Cohen's d)
    """
    result_id: str
    test_type: str
    statistic: float
    p_value: float
    effect_size: float


def model_to_dict(model: BaseModel) -> Dict[str, Any]:
    """
    Converts a Pydantic model to a dictionary, handling nested models and enums.
    """
    return model.model_dump(mode='json')


def models_to_json(models: List[BaseModel]) -> str:
    """
    Serializes a list of Pydantic models to a JSON string.
    """
    return json.dumps([model_to_dict(m) for m in models], indent=2)