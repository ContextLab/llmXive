"""
Collinearity Detection Module (T020b).

Reads correlation/VIF data from T020a (analysis_summary.csv),
calculates Variance Inflation Factor (VIF) explicitly, and flags
samples for mitigation if VIF > 5.

Output: data/results/collinearity_report.csv
"""
import os
import csv
import sys
from pathlib import Path
from typing import List, Dict, Any, Optional

import pandas as pd
import numpy as np
from statsmodels.stats.outliers_influence import variance_inflation_factor

# Import shared config/paths
try:
    from config import Paths
except ImportError:
    # Fallback for direct execution if config is not in path
    from pathlib import Path
    class Paths:
        DATA_RAW = Path("data/raw")
        DATA_PROCESSED = Path("data/processed")
        DATA_RESULTS = Path("data/results")
        PROJECT_ROOT = Path(__file__).resolve().parent.parent

logger = None
def get_logger():
    global logger
    if logger is None:
        try:
            from utils.logger import get_logger as _get_logger
            logger = _get_logger("collinearity_detector")
        except ImportError:
            import logging
            logger = logging.getLogger("collinearity_detector")
    return logger

def load_analysis_summary() -> Optional[pd.DataFrame]:
    """
    Loads the analysis summary generated by T020a.
    Expected columns: test_type, statistic, p_value, effect_size, correlation_coefficient
    """
    path = Paths.DATA_RESULTS / "analysis_summary.csv"
    if not path.exists():
        get_logger().error(f"Analysis summary not found at {path}. T020a may not have run.")
        return None
    try:
        df = pd.read_csv(path)
        return df
    except Exception as e:
        get_logger().error(f"Failed to load analysis summary: {e}")
        return None

def load_prompt_variants() -> Optional[pd.DataFrame]:
    """
    Loads the prompt variants dataframe to calculate VIF on the fly
    if correlation data is insufficient or to provide detailed flags.
    Expected columns: token_count, structural_element_count (or expanded keys)
    """
    path = Paths.DATA_PROCESSED / "prompt_variants.parquet"
    if not path.exists():
        get_logger().error(f"Prompt variants not found at {path}. T018 may not have run.")
        return None
    try:
        df = pd.read_parquet(path)
        return df
    except Exception as e:
        get_logger().error(f"Failed to load prompt variants: {e}")
        return None

