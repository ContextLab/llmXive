def run_collinearity_detection() -> Dict[str, Any]:
    """
    Main logic:
    1. Load correlation data from T020a.
    2. Load raw data to calculate VIF.
    3. Determine if mitigation is needed (VIF > 5).
    4. Write report.
    """
    logger = get_logger()
    logger.info("Starting collinearity detection (T020b).")

    # Load data
    summary_df = load_analysis_summary()
    variants_df = load_prompt_variants()

    if variants_df is None:
        logger.error("Cannot proceed without prompt variants data.")
        return {"status": "failed", "reason": "Missing prompt variants"}

    # Identify relevant columns for collinearity
    # T020a likely calculated correlation between 'token_count' and 'structural_element_count'
    # or a specific structural metric. We assume standard columns based on T008 model.
    # If 'structural_element_count' is a dict, we need to flatten or use a specific metric.
    # For VIF, we need numeric columns. Let's assume we use 'token_count' and a flattened structural metric.
    
    # Check for flattened structural count or calculate a total
    structural_cols = [c for c in variants_df.columns if 'structural' in c.lower() and c != 'structural_element_count']
    token_col = 'token_count'
    
    if token_col not in variants_df.columns:
        logger.error(f"Token count column '{token_col}' not found.")
        return {"status": "failed", "reason": f"Missing column {token_col}"}

    # If 'structural_element_count' is a dict column, we need to extract a value or sum it.
    # Based on T008, it's a dict. We'll try to sum the values if it's a dict column.
    if 'structural_element_count' in variants_df.columns:
        # Try to sum the dict values
        try:
            variants_df['total_structural_count'] = variants_df['structural_element_count'].apply(
                lambda x: sum(x.values()) if isinstance(x, dict) else 0
            )
            feature_cols = [token_col, 'total_structural_count']
        except Exception as e:
            logger.warning(f"Could not sum structural_element_count: {e}. Trying other columns.")
            feature_cols = [token_col] + structural_cols[:1] if structural_cols else [token_col]
    else:
        feature_cols = [token_col] + structural_cols[:1] if structural_cols else [token_col]

    # Ensure we have at least 2 features to check collinearity
    if len(feature_cols) < 2:
        logger.warning("Less than 2 features found. Collinearity not applicable. Assuming low risk.")
        vif_results = {col: 0.0 for col in feature_cols}
        mitigation_needed = False
    else:
        vif_results = calculate_vif(variants_df, feature_cols)
        max_vif = max(vif_results.values()) if vif_results else 0
        mitigation_needed = max_vif > 5

    # Prepare report data
    report_rows = []
    for col, vif in vif_results.items():
        flag = "MITIGATION_REQUIRED" if (vif > 5 and mitigation_needed) else "OK"
        report_rows.append({
            "feature": col,
            "vif": vif,
            "threshold": 5.0,
            "flag": flag,
            "mitigation_needed": mitigation_needed
        })

    # Write to CSV
    output_path = Paths.DATA_RESULTS / "collinearity_report.csv"
    if report_rows:
        df_report = pd.DataFrame(report_rows)
        df_report.to_csv(output_path, index=False)
        logger.info(f"Collinearity report written to {output_path}")
    else:
        # Write empty file with headers if no features
        with open(output_path, 'w', newline='') as f:
            writer = csv.writer(f)
            writer.writerow(["feature", "vif", "threshold", "flag", "mitigation_needed"])
        logger.warning(f"No features to report. Empty report written to {output_path}")

    return {
        "status": "success",
        "max_vif": max(vif_results.values()) if vif_results else 0,
        "mitigation_needed": mitigation_needed,
        "output_path": str(output_path)
    }

def main():
    logger = get_logger()
    try:
        result = run_collinearity_detection()
        if result["status"] == "success":
            logger.info(f"Collinearity detection complete. Mitigation needed: {result['mitigation_needed']}")
            sys.exit(0)
        else:
            logger.error(f"Collinearity detection failed: {result.get('reason')}")
            sys.exit(1)
    except Exception as e:
        logger.exception(f"Unhandled exception in T020b: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()