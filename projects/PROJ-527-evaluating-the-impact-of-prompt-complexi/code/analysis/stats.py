def load_execution_results() -> pd.DataFrame:
    """
    Load execution results from the CSV generated by T030.

    Returns:
        DataFrame with columns: problem_id, complexity_label, pass_status, token_count, structural_count, etc.
    """
    input_path = Paths.data_results / "execution_outcomes.csv"
    if not input_path.exists():
        raise FileNotFoundError(f"Execution results not found at {input_path}. "
                                "Run T030 (execution pipeline) first.")

    df = pd.read_csv(input_path)
    # Ensure categorical types for complexity if needed
    if 'complexity_label' in df.columns:
        df['complexity_label'] = pd.Categorical(
            df['complexity_label'],
            categories=['simple', 'moderate', 'complex', 'very_complex', 'degenerate'],
            ordered=True
        )
    return df


def fit_lmm_with_covariate(df: pd.DataFrame) -> Any:
    """
    Fit a Linear Mixed Model (LMM) using statsmodels.

    Model: pass_rate ~ complexity_label + token_count + (1 | problem_id)
    This controls for prompt token count as a covariate (FR-012) and handles
    nested structure with random intercepts for problem difficulty.

    Args:
        df: DataFrame with execution results.

    Returns:
        Fitted LMM model object.
    """
    try:
        import statsmodels.api as sm
        import statsmodels.formula.api as smf
    except ImportError:
        raise ImportError("statsmodels is required. Install via 'pip install statsmodels'.")

    # Prepare data: ensure pass_status is numeric (1 for pass, 0 for fail)
    # Assuming 'pass_status' is boolean or string 'pass'/'fail'
    if 'pass_status' in df.columns:
        if df['pass_status'].dtype == bool:
            df['pass_numeric'] = df['pass_status'].astype(int)
        elif df['pass_status'].dtype == object:
            df['pass_numeric'] = df['pass_status'].apply(lambda x: 1 if x == 'pass' else 0)
        else:
            df['pass_numeric'] = df['pass_status']
    else:
        raise ValueError("DataFrame must contain 'pass_status' column.")

    # Filter out rows with missing values in key columns
    clean_df = df.dropna(subset=['complexity_label', 'token_count', 'problem_id', 'pass_numeric'])

    if len(clean_df) == 0:
        raise ValueError("No valid data to fit LMM after dropping NaNs.")

    # Formula: fixed effects for complexity and token_count, random intercept for problem
    # Note: For binary outcomes (pass/fail), a GLMM (logistic) would be theoretically better,
    # but the spec mandates LMM (Linear Mixed Model) in FR-005. We proceed with LMM on the binary score.
    formula = "pass_numeric ~ C(complexity_label, Treatment('simple')) + token_count"
    formula += " + (1 | problem_id)"

    model = smf.mixedlm(formula, clean_df, groups=clean_df["problem_id"])
    result = model.fit()

    logger.info(f"LMM fitted successfully. AIC: {result.aic:.2f}, BIC: {result.bic:.2f}")
    return result


def pairwise_comparisons(df: pd.DataFrame, correction_method: str = "holm") -> pd.DataFrame:
    """
    Perform pairwise comparisons between complexity levels with multiple-comparison correction.

    Uses t-tests between pairs of complexity levels and applies the specified correction
    (Bonferroni or Holm-Bonferroni) to control family-wise error rate.

    Args:
        df: DataFrame with execution results.
        correction_method: Method for p-value correction. Options: 'bonferroni', 'holm'.

    Returns:
        DataFrame with comparison details: group1, group2, mean_diff, p_value, p_corrected, significant.
    """
    if 'complexity_label' not in df.columns or 'pass_status' not in df.columns:
        raise ValueError("DataFrame must contain 'complexity_label' and 'pass_status' columns.")

    # Prepare numeric pass status
    if df['pass_status'].dtype == bool:
        df['pass_numeric'] = df['pass_status'].astype(int)
    elif df['pass_status'].dtype == object:
        df['pass_numeric'] = df['pass_status'].apply(lambda x: 1 if x == 'pass' else 0)
    else:
        df['pass_numeric'] = df['pass_status']

    # Get unique complexity levels
    levels = df['complexity_label'].unique()
    if len(levels) < 2:
        logger.warning("Less than 2 complexity levels found. Skipping pairwise comparisons.")
        return pd.DataFrame()

    # Generate all unique pairs
    pairs = []
    results_data = []

    for i in range(len(levels)):
        for j in range(i + 1, len(levels)):
            group1 = levels[i]
            group2 = levels[j]

            # Extract data for each group
            data1 = df[df['complexity_label'] == group1]['pass_numeric'].values
            data2 = df[df['complexity_label'] == group2]['pass_numeric'].values

            if len(data1) == 0 or len(data2) == 0:
                continue

            # Perform independent t-test
            t_stat, p_val = stats.ttest_ind(data1, data2, equal_var=False)  # Welch's t-test

            pairs.append((group1, group2))
            results_data.append({
                'group1': group1,
                'group2': group2,
                'mean_diff': float(np.mean(data1) - np.mean(data2)),
                'p_value': float(p_val)
            })

    if not results_data:
        return pd.DataFrame(columns=['group1', 'group2', 'mean_diff', 'p_value', 'p_corrected', 'significant'])

    results_df = pd.DataFrame(results_data)

    # Apply multiple-comparison correction
    # Options: 'bonferroni', 'holm' (Holm-Bonferroni)
    if correction_method == 'bonferroni':
        alpha = 0.05
        # Bonferroni correction: multiply p-values by number of tests
        n_tests = len(results_df)
        results_df['p_corrected'] = np.minimum(results_df['p_value'] * n_tests, 1.0)
        results_df['significant'] = results_df['p_corrected'] <= alpha
    elif correction_method == 'holm':
        # Holm-Bonferroni method
        p_values = results_df['p_value'].values
        n_tests = len(p_values)
        # Sort p-values
        sorted_indices = np.argsort(p_values)
        sorted_p_values = p_values[sorted_indices]

        # Calculate adjusted p-values
        adjusted_p_values = np.zeros(n_tests)
        for k in range(n_tests):
            # Holm step-down: max of (n - k) * p_(k) and previous adjusted
            raw_adj = (n_tests - k) * sorted_p_values[k]
            if k > 0:
                raw_adj = max(raw_adj, adjusted_p_values[sorted_indices[k-1]])
            adjusted_p_values[sorted_indices[k]] = min(raw_adj, 1.0)

        results_df['p_corrected'] = adjusted_p_values
        results_df['significant'] = results_df['p_corrected'] <= 0.05
    else:
        raise ValueError(f"Unknown correction method: {correction_method}. Use 'bonferroni' or 'holm'.")

    logger.info(f"Pairwise comparisons completed with {correction_method} correction. "
                f"Significant pairs: {results_df['significant'].sum()}")

    return results_df


def calculate_effect_sizes(df: pd.DataFrame) -> pd.DataFrame:
    """
    Calculate effect sizes (Cohen's d) for pairwise comparisons.

    Args:
        df: DataFrame with execution results.

    Returns:
        DataFrame with effect sizes: group1, group2, cohens_d, interpretation.
    """
    if 'complexity_label' not in df.columns or 'pass_status' not in df.columns:
        raise ValueError("DataFrame must contain 'complexity_label' and 'pass_status' columns.")

    # Prepare numeric pass status
    if df['pass_status'].dtype == bool:
        df['pass_numeric'] = df['pass_status'].astype(int)
    elif df['pass_status'].dtype == object:
        df['pass_numeric'] = df['pass_status'].apply(lambda x: 1 if x == 'pass' else 0)
    else:
        df['pass_numeric'] = df['pass_status']

    levels = df['complexity_label'].unique()
    if len(levels) < 2:
        return pd.DataFrame()

    results_data = []

    for i in range(len(levels)):
        for j in range(i + 1, len(levels)):
            group1 = levels[i]
            group2 = levels[j]

            data1 = df[df['complexity_label'] == group1]['pass_numeric'].values
            data2 = df[df['complexity_label'] == group2]['pass_numeric'].values

            if len(data1) == 0 or len(data2) == 0:
                continue

            # Calculate Cohen's d
            mean1, mean2 = np.mean(data1), np.mean(data2)
            std1, std2 = np.std(data1, ddof=1), np.std(data2, ddof=1)
            n1, n2 = len(data1), len(data2)

            # Pooled standard deviation
            pooled_std = np.sqrt(((n1 - 1) * std1**2 + (n2 - 1) * std2**2) / (n1 + n2 - 2))

            if pooled_std == 0:
                cohens_d = 0.0
            else:
                cohens_d = (mean1 - mean2) / pooled_std

            # Interpretation
            abs_d = abs(cohens_d)
            if abs_d < 0.2:
                interpretation = "negligible"
            elif abs_d < 0.5:
                interpretation = "small"
            elif abs_d < 0.8:
                interpretation = "medium"
            else:
                interpretation = "large"

            results_data.append({
                'group1': group1,
                'group2': group2,
                'cohens_d': float(cohens_d),
                'interpretation': interpretation
            })

    return pd.DataFrame(results_data)


def run_full_analysis(correction_method: str = "holm") -> Dict[str, Any]:
    """
    Run the full statistical analysis pipeline.

    Args:
        correction_method: Method for multiple-comparison correction ('bonferroni' or 'holm').

    Returns:
        Dictionary containing LMM results, pairwise comparisons, and effect sizes.
    """
    logger.info("Starting full statistical analysis...")

    # Load data
    df = load_execution_results()
    logger.info(f"Loaded {len(df)} execution results.")

    # Fit LMM
    lmm_result = fit_lmm_with_covariate(df)

    # Pairwise comparisons with correction
    comparisons = pairwise_comparisons(df, correction_method=correction_method)

    # Effect sizes
    effect_sizes = calculate_effect_sizes(df)

    return {
        'lmm_result': lmm_result,
        'pairwise_comparisons': comparisons,
        'effect_sizes': effect_sizes,
        'raw_data': df
    }


def write_analysis_summary_to_csv(analysis_results: Dict[str, Any], output_path: Optional[Path] = None):
    """
    Write analysis summary to CSV file.

    Args:
        analysis_results: Dictionary from run_full_analysis().
        output_path: Path to output CSV. Defaults to data/results/analysis_summary.csv.
    """
    if output_path is None:
        output_path = Paths.data_results / "analysis_summary.csv"

    output_path.parent.mkdir(parents=True, exist_ok=True)

    comparisons_df = analysis_results['pairwise_comparisons']
    effect_sizes_df = analysis_results['effect_sizes']
    lmm_result = analysis_results['lmm_result']

    # Combine comparisons and effect sizes for a unified summary
    summary_data = []

    if not comparisons_df.empty:
        merged = comparisons_df.merge(effect_sizes_df, on=['group1', 'group2'], how='left')
        for _, row in merged.iterrows():
            summary_data.append({
                'comparison': f"{row['group1']} vs {row['group2']}",
                'mean_diff': row['mean_diff'],
                'p_value': row['p_value'],
                'p_corrected': row['p_corrected'],
                'significant': row['significant'],
                'cohens_d': row.get('cohens_d', np.nan),
                'effect_size_interpretation': row.get('interpretation', 'N/A')
            })

    # Add LMM summary stats
    lmm_summary = {
        'comparison': 'LMM_Full_Model',
        'mean_diff': np.nan,
        'p_value': np.nan,
        'p_corrected': np.nan,
        'significant': np.nan,
        'cohens_d': np.nan,
        'effect_size_interpretation': 'LMM_AIC: {:.4f}, LMM_BIC: {:.4f}'.format(lmm_result.aic, lmm_result.bic)
    }
    summary_data.append(lmm_summary)

    summary_df = pd.DataFrame(summary_data)

    with open(output_path, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=summary_data[0].keys())
        writer.writeheader()
        writer.writerows(summary_data)

    logger.info(f"Analysis summary written to {output_path}")


def main():
    """Main entry point for statistical analysis."""
    logger.info("Running statistical analysis (T034, T035, T036, T038, T040)...")

    try:
        # Run full analysis with Holm-Bonferroni correction (default)
        results = run_full_analysis(correction_method="holm")

        # Write summary to CSV
        write_analysis_summary_to_csv(results)

        # Optional: Print key findings
        comparisons = results['pairwise_comparisons']
        if not comparisons.empty:
            significant = comparisons[comparisons['significant']]
            logger.info(f"Found {len(significant)} significant pairwise differences after correction.")
            for _, row in significant.iterrows():
                logger.info(f"  {row['group1']} vs {row['group2']}: "
                            f"diff={row['mean_diff']:.4f}, p={row['p_corrected']:.4f}")

        logger.info("Statistical analysis completed successfully.")

    except Exception as e:
        logger.error(f"Statistical analysis failed: {e}")
        raise


if __name__ == "__main__":
    main()