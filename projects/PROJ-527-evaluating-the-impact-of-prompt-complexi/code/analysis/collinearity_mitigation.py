"""
Collinearity Mitigation Module (Task T020c).

Reads the collinearity report (T020b).
If VIF > 5, applies PCA transformation to orthogonalize features.
If VIF <= 5, creates a 'no-op' status marker and copies original data.
"""
import os
import sys
import json
from pathlib import Path
from typing import List, Dict, Any, Optional

import pandas as pd
import numpy as np
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler

# Import from existing project modules
from config import Paths
from utils.logger import get_logger

logger = get_logger(__name__)

def load_collinearity_report() -> Optional[Dict[str, Any]]:
    """
    Loads the collinearity report generated by T020b.
    Returns None if file is missing or empty.
    """
    report_path = Paths.RESULTS_DIR / "collinearity_report.csv"
    if not report_path.exists():
        logger.warning(f"Collinearity report not found at {report_path}. Assuming no mitigation needed.")
        return None

    try:
        df = pd.read_csv(report_path)
        if df.empty:
            logger.warning("Collinearity report is empty.")
            return None
        
        # Expecting columns like 'feature', 'vif' or a single row summary
        # Based on T020b description, it likely has a row indicating the VIF for the main features
        # We look for the maximum VIF or a specific 'max_vif' column if T020b aggregated it.
        # If T020b wrote a table of VIFs per feature, we take the max.
        
        if 'vif' in df.columns:
            max_vif = df['vif'].max()
        elif 'max_vif' in df.columns:
            max_vif = df['max_vif'].iloc[0]
        else:
            # Fallback: try to infer from any numeric column if 'vif' is missing but expected
            numeric_cols = df.select_dtypes(include=[np.number]).columns
            if len(numeric_cols) > 0:
                max_vif = df[numeric_cols].max().max()
            else:
                logger.error("Could not find VIF values in collinearity report.")
                return None
        
        return {"max_vif": max_vif, "path": report_path}
    except Exception as e:
        logger.error(f"Failed to load collinearity report: {e}")
        return None

def load_prompt_variants() -> pd.DataFrame:
    """
    Loads the prompt variants dataset.
    """
    input_path = Paths.PROCESSED_DIR / "prompt_variants.parquet"
    if not input_path.exists():
        raise FileNotFoundError(f"Prompt variants not found at {input_path}. T018/T062 must run first.")
    return pd.read_parquet(input_path)

def apply_pca_transformation(df: pd.DataFrame, target_columns: List[str], n_components: int = 2) -> pd.DataFrame:
    """
    Applies PCA to the specified numeric columns to orthogonalize them.
    Returns a new DataFrame with transformed columns.
    """
    if not target_columns or not all(col in df.columns for col in target_columns):
        raise ValueError(f"Target columns {target_columns} not found in DataFrame.")

    # Extract data
    X = df[target_columns].values

    # Standardize
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)

    # Apply PCA
    pca = PCA(n_components=n_components)
    X_pca = pca.fit_transform(X_scaled)

    # Create new column names
    new_cols = [f"pca_{i}" for i in range(n_components)]
    
    # Create a copy of the original dataframe
    df_transformed = df.copy()
    
    # Add transformed columns
    for i, col in enumerate(new_cols):
        df_transformed[col] = X_pca[:, i]

    # Log explained variance
    logger.info(f"PCA explained variance ratio: {pca.explained_variance_ratio_}")
    
    return df_transformed

def run_collinearity_mitigation():
    """
    Main execution logic for T020c.
    """
    logger.info("Starting Collinearity Mitigation (T020c)...")

    # 1. Load Report
    report = load_collinearity_report()
    
    vif_threshold = 5.0
    needs_mitigation = False
    max_vif = 0.0

    if report:
        max_vif = report.get("max_vif", 0.0)
        if max_vif > vif_threshold:
            needs_mitigation = True
            logger.info(f"VIF ({max_vif:.2f}) > {vif_threshold}. Mitigation required.")
        else:
            logger.info(f"VIF ({max_vif:.2f}) <= {vif_threshold}. No mitigation needed.")
    else:
        logger.info("No collinearity report found. Assuming no mitigation needed.")

    # 2. Load Data
    try:
        df = load_prompt_variants()
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)

    # 3. Execute Logic
    output_path = Paths.PROCESSED_DIR / "prompt_variants_transformed.parquet"
    status_path = Paths.PROCESSED_DIR / "collinearity_status.json"

    if needs_mitigation:
        # Define columns to orthogonalize. 
        # Based on T020a/T020b, these are likely 'token_count' and 'structural_element_count' (or its components).
        # We need to select numeric columns that are likely collinear.
        # Assuming 'token_count' and 'dependency_depth' or specific structural counts.
        # Let's target 'token_count' and 'dependency_depth' as they are the main complexity metrics.
        # If 'structural_element_count' is a dict, we might need to flatten it first, 
        # but T018 likely stored it as a string or expanded columns. 
        # We will attempt to use 'token_count' and 'dependency_depth' if they exist.
        
        candidate_cols = ['token_count', 'dependency_depth']
        # Check for expanded structural counts if they exist (e.g. 'examples', 'constraints', 'steps' if flattened)
        # But to be safe, let's just use the explicit numeric complexity columns found in the data.
        available_cols = [c for c in candidate_cols if c in df.columns]
        
        if len(available_cols) < 2:
            logger.warning(f"Could not find enough candidate columns for PCA. Found: {available_cols}. Attempting to use all numeric cols.")
            available_cols = df.select_dtypes(include=[np.number]).columns.tolist()
            # Remove ID columns
            available_cols = [c for c in available_cols if 'id' not in c.lower() and 'count' not in c.lower() or c in ['token_count', 'dependency_depth']]

        if len(available_cols) >= 2:
            logger.info(f"Applying PCA to columns: {available_cols}")
            df_final = apply_pca_transformation(df, available_cols, n_components=2)
            
            # Save transformed data
            df_final.to_parquet(output_path, index=False)
            logger.info(f"Transformed data written to {output_path}")
            
            # Write status
            status = {
                "status": "mitigated",
                "method": "PCA",
                "original_vif": max_vif,
                "transformed_columns": available_cols,
                "output_file": str(output_path)
            }
            with open(status_path, 'w') as f:
                json.dump(status, f, indent=2)
        else:
            logger.error("Not enough numeric columns to perform PCA.")
            sys.exit(1)

    else:
        # No-op case
        logger.info("Creating no-op status marker and copying original data.")
        
        # Copy original to transformed path
        df.to_parquet(output_path, index=False)
        
        # Write status
        status = {
            "status": "no_mitigation_needed",
            "original_vif": max_vif,
            "threshold": vif_threshold,
            "reason": "VIF did not exceed threshold"
        }
        with open(status_path, 'w') as f:
            json.dump(status, f, indent=2)
        
        logger.info(f"No-op status written to {status_path}")

    logger.info("Collinearity Mitigation completed.")

def main():
    run_collinearity_mitigation()

if __name__ == "__main__":
    main()
