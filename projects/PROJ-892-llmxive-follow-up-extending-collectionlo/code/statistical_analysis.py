def load_results_data(results_path: str = "data/results.csv") -> pd.DataFrame:
    """Load the results CSV file generated by the main pipeline."""
    if not os.path.exists(results_path):
        raise FileNotFoundError(f"Results file not found at {results_path}. Run the main pipeline first.")
    df = pd.read_csv(results_path)
    logger.info(f"Loaded {len(df)} rows from {results_path}")
    return df

def load_subspace_ranks(ranks_path: str = "data/subspace_ranks.json") -> Dict[str, Any]:
    """Load the subspace ranks computed from the LoRA adapter."""
    if not os.path.exists(ranks_path):
        raise FileNotFoundError(f"Subspace ranks file not found at {ranks_path}. Run T009b first.")
    with open(ranks_path, 'r') as f:
        data = json.load(f)
    logger.info(f"Loaded subspace ranks for {len(data.get('ranks', {}))} effects")
    return data

def prepare_correlation_data(results_df: pd.DataFrame, ranks_data: Dict[str, Any]) -> pd.DataFrame:
    """Merge results with subspace ranks for correlation analysis."""
    ranks = ranks_data.get('ranks', {})
    # Create a mapping from effect name to rank
    rank_map = {k: v for k, v in ranks.items()}
    
    # Add rank column to results if effect is present
    results_df['subspace_rank'] = results_df['effect'].map(rank_map)
    
    # Drop rows where rank is missing (effect not in ranks data)
    results_df = results_df.dropna(subset=['subspace_rank'])
    logger.info(f"Prepared {len(results_df)} rows for correlation analysis")
    return results_df

def run_bayesian_hierarchical_model(
    data: pd.DataFrame,
    model_path: str = "state/bayesian_model.nc",
    posterior_samples: int = 1000,
    tune: int = 1000
) -> Dict[str, Any]:
    """
    Run the Bayesian Hierarchical Model to analyze quantization effects.
    Returns a dictionary containing model diagnostics and posterior statistics.
    """
    logger.info("Starting Bayesian Hierarchical Model...")
    
    # Prepare data for PyMC
    # We model: similarity_score ~ Normal(mu_quant, sigma)
    # where mu_quant = beta_0 + beta_quant * quantization_level
    # and we include random effects for prompts to account for nested structure
    
    # Extract unique levels
    quant_levels = data['quantization_level'].unique()
    prompt_levels = data['prompt'].unique()
    
    # Map to integers for PyMC
    data = data.copy()
    data['quant_idx'] = pd.Categorical(data['quantization_level']).codes
    data['prompt_idx'] = pd.Categorical(data['prompt']).codes
    
    # Define the model
    with pm.Model() as model:
        # Priors
        beta_0 = pm.Normal('beta_0', mu=0, sigma=1)  # Intercept
        beta_quant = pm.Normal('beta_quant', mu=0, sigma=1)  # Quantization effect
        sigma = pm.HalfNormal('sigma', sigma=1)  # Residual std
        
        # Random effects for prompts
        sigma_prompt = pm.HalfNormal('sigma_prompt', sigma=1)
        prompt_effects = pm.Normal('prompt_effects', mu=0, sigma=sigma_prompt, 
                                 shape=len(prompt_levels))
        
        # Linear predictor
        mu = (beta_0 + 
              beta_quant * data['quant_idx'].values + 
              prompt_effects[data['prompt_idx'].values])
        
        # Likelihood
        y_obs = pm.Normal('y_obs', mu=mu, sigma=sigma, observed=data['similarity_score'].values)
        
        # Sample
        logger.info(f"Sampling {posterior_samples} posterior samples with {tune} tune steps...")
        trace = pm.sample(
            draws=posterior_samples,
            tune=tune,
            chains=2,
            target_accept=0.9,
            random_seed=42,
            progressbar=True
        )
    
    # Compute diagnostics
    logger.info("Computing posterior statistics and diagnostics...")
    
    # Posterior width for the quantization effect (beta_quant)
    beta_quant_samples = trace.posterior['beta_quant'].values.flatten()
    posterior_width = np.ptp(beta_quant_samples)  # max - min
    # Or use credible interval width:
    ci = az.hdi(trace, var_names=['beta_quant'])
    credible_interval_width = float(ci['beta_quant']['beta_quant'].diff().values[0])
    
    # Store posterior width for T026 check
    posterior_stats = {
        'beta_quant_mean': float(np.mean(beta_quant_samples)),
        'beta_quant_std': float(np.std(beta_quant_samples)),
        'credible_interval_95': {
            'lower': float(ci['beta_quant']['beta_quant'].values[0]),
            'upper': float(ci['beta_quant']['beta_quant'].values[1])
        },
        'credible_interval_width': credible_interval_width,
        'posterior_width_max_minus_min': float(posterior_width),
        'r_hat': float(az.rhat(trace)['beta_quant'].values[0]),
        'n_eff': float(az.ess(trace)['beta_quant'].values[0])
    }
    
    # Check for underpowered result (FR-014)
    # Using credible interval width as the metric for "width"
    is_underpowered = credible_interval_width > 0.2
    
    model_info = {
        'model_path': model_path,
        'posterior_stats': posterior_stats,
        'underpowered': is_underpowered,
        'underpowered_reason': f"Credible interval width ({credible_interval_width:.4f}) > 0.2 threshold" if is_underpowered else None,
        'samples': posterior_samples,
        'tune': tune,
        'convergence': {
            'r_hat': posterior_stats['r_hat'],
            'effective_n': posterior_stats['n_eff']
        }
    }
    
    # Save trace for future reference
    if model_path:
        Path(model_path).parent.mkdir(parents=True, exist_ok=True)
        az.to_netcdf(trace, model_path)
        logger.info(f"Saved model trace to {model_path}")
    
    return model_info

