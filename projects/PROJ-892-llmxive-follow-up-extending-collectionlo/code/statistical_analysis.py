def main(
    results_path: str = "data/results.csv",
    ranks_path: str = "data/subspace_ranks.json",
    output_path: str = "data/analysis_results.json",
    model_path: str = "state/bayesian_model.nc"
) -> Dict[str, Any]:
    """
    Main function to run the full statistical analysis pipeline.
    
    1. Load results and subspace ranks
    2. Run Bayesian Hierarchical Model
    3. Check posterior width (FR-014) and flag if underpowered
    4. Compute correlation between subspace rank and concept bleeding
    5. Save results to analysis_results.json
    """
    logger.info("Starting statistical analysis pipeline...")
    
    # Load data
    results_df = load_results_data(results_path)
    ranks_data = load_subspace_ranks(ranks_path)
    
    # Prepare correlation data
    correlation_data = prepare_correlation_data(results_df, ranks_data)
    
    # Run Bayesian model
    model_results = run_bayesian_hierarchical_model(correlation_data, model_path=model_path)
    
    # Compute correlation stats
    correlation_results = compute_correlation_stats(correlation_data)
    
    # Compile final results
    analysis_results = {
        'model_results': model_results,
        'correlation_results': correlation_results,
        'fr14_status': {
            'is_underpowered': model_results['underpowered'],
            'reason': model_results.get('underpowered_reason'),
            'threshold': 0.2,
            'metric_value': model_results['posterior_stats']['credible_interval_width']
        },
        'data_summary': {
            'total_samples': len(results_df),
            'quantized_samples': len(results_df[results_df['quantization_level'].isin(['INT8', 'INT4'])]),
            'fp16_samples': len(results_df[results_df['quantization_level'] == 'FP16']),
            'unique_effects': results_df['effect'].nunique(),
            'unique_prompts': results_df['prompt'].nunique()
        }
    }
    
    # Save results
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(analysis_results, f, indent=2)
    
    logger.info(f"Analysis results saved to {output_path}")
    
    # Log FR-014 status
    if analysis_results['fr14_status']['is_underpowered']:
        logger.warning(f"FR-014: Result is UNDERPOWERED. {analysis_results['fr14_status']['reason']}")
    else:
        logger.info("FR-014: Result is adequately powered.")
    
    return analysis_results

