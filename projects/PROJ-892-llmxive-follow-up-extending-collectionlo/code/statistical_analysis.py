def prepare_correlation_data(df: pd.DataFrame, subspace_ranks: Dict[str, int]) -> pd.DataFrame:
    """
    Prepare data for correlation analysis between subspace rank and concept bleeding.
    
    Args:
        df: The results DataFrame.
        subspace_ranks: Dictionary of effect subspace ranks.
        
    Returns:
        DataFrame with effect_id, subspace_rank, and mean_bleeding columns.
    """
    # Calculate mean concept bleeding (similarity drop) per effect
    # Assuming lower similarity_score indicates more bleeding/drop
    effect_stats = df.groupby('prompt')['similarity_score'].agg(['mean', 'std']).reset_index()
    effect_stats.columns = ['effect_id', 'mean_similarity', 'std_similarity']
    
    # Merge with subspace ranks
    # Note: The prompt names in results.csv should match the effect names in subspace_ranks
    correlation_data = effect_stats.merge(
        pd.DataFrame(list(subspace_ranks.items()), columns=['effect_id', 'subspace_rank']),
        on='effect_id',
        how='inner'
    )
    
    if correlation_data.empty:
        logger.warning("No matching effects found between results and subspace ranks.")
        
    return correlation_data

def run_bayesian_hierarchical_model(df: pd.DataFrame) -> Dict[str, Any]:
    """
    Run the Bayesian Hierarchical Model to analyze quantization effects.
    
    Model Formula: similarity_score ~ quantization_level + (1 | effect_id)
    
    Args:
        df: The results DataFrame structured for Bambi.
            Must contain: 'effect_id', 'similarity_score', 'quantization_level', 'seed'.
            
    Returns:
        Dictionary containing model results, posterior distributions, and diagnostics.
    """
    logger.info("Running Bayesian Hierarchical Model...")
    
    # Ensure quantization_level is treated as a categorical variable
    df['quantization_level'] = pd.Categorical(df['quantization_level'])
    
    try:
        # Define the model using Bambi
        # Formula: similarity_score ~ quantization_level + (1 | effect_id)
        model = bmb.Model(
            "similarity_score ~ quantization_level + (1 | effect_id)",
            data=df,
            family="gaussian"
        )
        
        # Fit the model
        logger.info("Fitting model...")
        idata = model.fit(draws=1000, tune=1000, chains=2, progressbar=True)
        
        # Extract posterior width for the quantization effect
        # We look at the coefficient for the quantization levels (excluding intercept)
        summary = idata.summary()
        
        # Identify quantization effect coefficients
        quant_cols = [col for col in summary.index if 'quantization_level' in str(col)]
        
        posterior_widths = {}
        for col in quant_cols:
            row = summary.loc[col]
            # Assuming the summary has 'mean' and 'hdi_94' (or similar) columns
            # Bambi summary typically includes mean, sd, hdi_3, hdi_97
            mean_val = row.get('mean', 0)
            hdi_low = row.get('hdi_3', row.get('hdi_low', 0)) # Adjust column name based on actual output
            hdi_high = row.get('hdi_97', row.get('hdi_high', 0))
            
            width = hdi_high - hdi_low
            posterior_widths[col] = width
            
        # Calculate overall width for the quantization effect (max width among levels)
        max_width = max(posterior_widths.values()) if posterior_widths else 0.0
        
        # Check for significance (HDI excludes zero)
        significant_effects = {}
        for col in quant_cols:
            row = summary.loc[col]
            hdi_low = row.get('hdi_3', row.get('hdi_low', 0))
            hdi_high = row.get('hdi_97', row.get('hdi_high', 0))
            significant_effects[col] = (hdi_low > 0) or (hdi_high < 0)
            
        return {
            "model_summary": summary.to_dict(),
            "posterior_widths": posterior_widths,
            "max_posterior_width": max_width,
            "significant_effects": significant_effects,
            "idata": idata, # Keep the full idata for further analysis if needed
            "underpowered": max_width > 0.2
        }
        
    except Exception as e:
        logger.error(f"Failed to run Bayesian Hierarchical Model: {e}")
        raise

def compute_correlation_stats(correlation_data: pd.DataFrame) -> Dict[str, Any]:
    """
    Compute correlation statistics between subspace rank and concept bleeding.
    
    Args:
        correlation_data: DataFrame with effect_id, subspace_rank, and mean_bleeding.
        
    Returns:
        Dictionary with correlation coefficient, p-value, and description.
    """
    if correlation_data.empty:
        return {
            "correlation_coefficient": None,
            "p_value": None,
            "n_samples": 0,
            "description": "Insufficient data for correlation analysis."
        }
        
    x = correlation_data['subspace_rank'].values
    y = correlation_data['mean_similarity'].values # Using mean_similarity as proxy for bleeding
    
    # Compute Pearson correlation
    corr_matrix = np.corrcoef(x, y)
    corr_coef = corr_matrix[0, 1]
    
    # Compute p-value (simple approximation)
    n = len(x)
    if n > 2:
        t_stat = corr_coef * np.sqrt((n - 2) / (1 - corr_coef**2))
        from scipy import stats
        p_value = 2 * (1 - stats.t.cdf(abs(t_stat), n - 2))
    else:
        p_value = None
        
    return {
        "correlation_coefficient": float(corr_coef),
        "p_value": float(p_value) if p_value is not None else None,
        "n_samples": n,
        "description": f"Correlation between subspace rank and mean similarity: {corr_coef:.3f}"
    }

def main():
    """
    Main entry point for statistical analysis.
    Loads data, runs Bayesian Hierarchical Model, computes correlations,
    and saves results to data/analysis_results.json.
    """
    logger.info("Starting Statistical Analysis (T023)...")
    
    project_root = get_project_root()
    results_path = os.path.join(project_root, "data", "results.csv")
    ranks_path = os.path.join(project_root, "data", "subspace_ranks.json")
    output_path = os.path.join(project_root, "data", "analysis_results.json")
    
    # 1. Load Results Data
    try:
        df = load_results_data(results_path)
        logger.info(f"Loaded {len(df)} rows from results.csv")
    except Exception as e:
        logger.error(f"Failed to load results data: {e}")
        raise
        
    # 2. Structure Data for Bayesian Model
    # The task requires columns: effect_id, similarity_score, quantization_level, seed
    # We need to map 'prompt' to 'effect_id' if they are the same, or create a mapping
    # Assuming 'prompt' column contains the effect names (e.g., "oil painting")
    structured_df = df.rename(columns={'prompt': 'effect_id'})
    
    # Ensure required columns exist
    required_cols = ['effect_id', 'similarity_score', 'quantization_level', 'seed']
    missing = [c for c in required_cols if c not in structured_df.columns]
    if missing:
        raise ValueError(f"Structured data missing columns: {missing}")
        
    # 3. Load Subspace Ranks
    try:
        subspace_ranks = load_subspace_ranks(ranks_path)
        logger.info(f"Loaded subspace ranks for {len(subspace_ranks)} effects")
    except Exception as e:
        logger.error(f"Failed to load subspace ranks: {e}")
        raise
        
    # 4. Run Bayesian Hierarchical Model
    try:
        bh_results = run_bayesian_hierarchical_model(structured_df)
        logger.info("Bayesian Hierarchical Model completed.")
    except Exception as e:
        logger.error(f"Bayesian Hierarchical Model failed: {e}")
        raise
        
    # 5. Compute Correlation Stats
    try:
        corr_data = prepare_correlation_data(structured_df, subspace_ranks)
        corr_stats = compute_correlation_stats(corr_data)
        logger.info("Correlation analysis completed.")
    except Exception as e:
        logger.error(f"Correlation analysis failed: {e}")
        # We might want to continue even if correlation fails, but log it
        corr_stats = {"error": str(e)}
        
    # 6. Compile Final Results
    final_results = {
        "bh_model": {
            "max_posterior_width": bh_results.get("max_posterior_width"),
            "underpowered": bh_results.get("underpowered"),
            "significant_effects": bh_results.get("significant_effects"),
            # We exclude the full idata object from JSON serialization to avoid issues
            # Instead, we save summary stats
            "summary_stats": {
                col: {k: v for k, v in row.items() if k != 'idata'} 
                for col, row in bh_results.get("model_summary", {}).items()
            }
        },
        "correlation_analysis": corr_stats,
        "data_summary": {
            "total_rows": len(structured_df),
            "unique_effects": structured_df['effect_id'].nunique(),
            "quantization_levels": structured_df['quantization_level'].unique().tolist()
        }
    }
    
    # 7. Save Results
    try:
        with open(output_path, 'w') as f:
            json.dump(final_results, f, indent=2, default=str)
        logger.info(f"Analysis results saved to {output_path}")
        
        # Register artifact in state
        artifacts_state = load_artifacts_state()
        from data_loader import compute_sha256_file, register_downloaded_artifact
        hash_val = compute_sha256_file(output_path)
        register_downloaded_artifact(artifacts_state, "analysis_results.json", hash_val, output_path)
        save_artifacts_state(artifacts_state)
        
    except Exception as e:
        logger.error(f"Failed to save analysis results: {e}")
        raise
        
    logger.info("Statistical Analysis (T023) completed successfully.")

if __name__ == "__main__":
    main()