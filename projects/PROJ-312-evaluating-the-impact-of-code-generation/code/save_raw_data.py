import json
import logging
import os
import sys
from pathlib import Path
from typing import List, Dict, Any

# Import from existing API surface
from utils import validate_json_schema

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s",
    handlers=[
        logging.FileHandler("logs/pipeline.log"),
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)

def load_raw_pr_data(input_path: Path) -> List[Dict[str, Any]]:
    """
    Load the raw PR data fetched from the GitHub API.
    Expected input: data/raw/pr_data_raw.json (or similar intermediate file)
    """
    if not input_path.exists():
        # Fallback: Check if data was saved in a different location or format
        # In a real pipeline, this would be a critical error
        raise FileNotFoundError(f"Raw PR data not found at {input_path}")
    
    with open(input_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    return data

def save_raw_data(data: List[Dict[str, Any]], output_path: Path) -> None:
    """
    Save the raw PR data to the specified output path after validation.
    """
    # Schema validation
    schema_path = Path("contracts/pull_request.schema.yaml")
    if not validate_json_schema(data, schema_path):
        logger.error("Raw data failed schema validation. Aborting save.")
        raise ValueError("Schema validation failed for raw PR data")
    
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=2, default=str)
    
    logger.info(f"Raw PR data saved to {output_path} with {len(data)} records.")

def main():
    """
    Main entry point for saving raw PR data.
    Reads from a temporary intermediate file (generated by fetch_data.py)
    and saves to the final raw data location with validation.
    """
    # In a real pipeline, fetch_data.py would save to a temp file first
    # or we would read from the memory object if this was a monolithic script.
    # Given the modular structure, we assume the raw data is available
    # in a standard location or passed as an argument.
    # For this implementation, we will read from a standard intermediate path
    # that fetch_data.py would have populated, or fail loudly if missing.
    
    raw_input_path = Path("data/raw/pr_data_raw_temp.json")
    final_output_path = Path("data/raw/pr_data.json")
    
    # If the intermediate file doesn't exist, we assume the pipeline
    # failed earlier or the data needs to be fetched again.
    # We do NOT generate synthetic data.
    if not raw_input_path.exists():
        logger.critical(f"Intermediate raw data file not found at {raw_input_path}. "
                        "Please ensure T012b (fetch data) has completed successfully.")
        sys.exit(1)

    try:
        raw_data = load_raw_pr_data(raw_input_path)
        save_raw_data(raw_data, final_output_path)
        logger.info("Task T018a completed successfully.")
    except Exception as e:
        logger.error(f"Failed to save raw data: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
