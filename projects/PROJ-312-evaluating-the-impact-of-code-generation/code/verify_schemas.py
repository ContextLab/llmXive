"""
Schema Verification Utility for PROJ-312.

This module verifies that all CSV and JSON outputs generated by the pipeline
match the schema contracts defined in the `contracts/` directory.

It validates:
1. data/raw/repos.json against repo_metadata.schema.yaml
2. data/raw/pr_data.json against pull_request.schema.yaml
3. data/processed/pr_turnaround.csv against pull_request.schema.yaml (adapted)
4. data/processed/statistical_results.json against statistical_result.schema.yaml
"""
import json
import csv
import logging
import sys
from pathlib import Path
from typing import Dict, Any, List, Optional

# Add project root to path for imports if running as script
if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).parent.parent))

from utils import validate_json_schema

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

PROJECT_ROOT = Path(__file__).parent.parent
CONTRACTS_DIR = PROJECT_ROOT / "contracts"
DATA_DIR = PROJECT_ROOT / "data"

# Mapping of file paths to their corresponding schema files
VERIFICATION_MAP = [
    {
        "file": DATA_DIR / "raw" / "repos.json",
        "schema": CONTRACTS_DIR / "repo_metadata.schema.yaml",
        "type": "json_list"
    },
    {
        "file": DATA_DIR / "raw" / "pr_data.json",
        "schema": CONTRACTS_DIR / "pull_request.schema.yaml",
        "type": "json_list"
    },
    {
        "file": DATA_DIR / "processed" / "pr_turnaround.csv",
        "schema": CONTRACTS_DIR / "pull_request.schema.yaml",
        "type": "csv"
    },
    {
        "file": DATA_DIR / "processed" / "statistical_results.json",
        "schema": CONTRACTS_DIR / "statistical_result.schema.yaml",
        "type": "json_object"
    },
    {
        "file": DATA_DIR / "processed" / "repo_metadata.json",
        "schema": CONTRACTS_DIR / "repo_metadata.schema.yaml",
        "type": "json_object" # Assuming this file exists as per T017
    }
]

def load_yaml_schema(schema_path: Path) -> Dict[str, Any]:
    """
    Loads a YAML schema file. Since PyYAML is a dependency, we use it directly.
    """
    try:
        import yaml
        with open(schema_path, 'r') as f:
            return yaml.safe_load(f)
    except ImportError:
        logger.error("PyYAML not installed. Cannot load schema: {}".format(schema_path))
        raise
    except Exception as e:
        logger.error("Failed to load schema {}: {}".format(schema_path, e))
        raise

def validate_json_list(data: List[Dict], schema: Dict, file_path: Path) -> bool:
    """Validates a list of JSON objects against a schema."""
    all_valid = True
    for i, item in enumerate(data):
        if not validate_json_schema(item, schema):
            logger.error(f"Validation failed for item {i} in {file_path}")
            all_valid = False
    return all_valid

def validate_json_object(data: Dict, schema: Dict, file_path: Path) -> bool:
    """Validates a single JSON object against a schema."""
    if not validate_json_schema(data, schema):
        logger.error(f"Validation failed for object in {file_path}")
        return False
    return True

def validate_csv(csv_path: Path, schema_path: Path) -> bool:
    """
    Validates a CSV file against a JSON schema.
    Since CSVs are row-based, we validate each row against the schema's properties.
    We check for required columns and basic type compliance where possible.
    """
    if not csv_path.exists():
        logger.error(f"CSV file not found: {csv_path}")
        return False
    
    schema = load_yaml_schema(schema_path)
    required_fields = schema.get('required', [])
    properties = schema.get('properties', {})
    
    if not required_fields:
        logger.warning(f"No required fields defined in schema for {csv_path}. Skipping row validation.")
        return True

    try:
        with open(csv_path, 'r', newline='', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            
            # Check if all required columns exist in header
            if reader.fieldnames is None:
                logger.error(f"CSV file {csv_path} is empty or has no header.")
                return False
            
            header_fields = set(reader.fieldnames)
            missing_required = set(required_fields) - header_fields
            
            if missing_required:
                logger.error(f"Missing required columns in {csv_path}: {missing_required}")
                return False
            
            # Validate rows
            valid_rows = 0
            total_rows = 0
            for i, row in enumerate(reader):
                total_rows += 1
                # Basic type check for numeric fields if defined
                row_valid = True
                for field, spec in properties.items():
                    if field in row and row[field]:
                        val_type = spec.get('type')
                        if val_type == 'number':
                            try:
                                float(row[field])
                            except ValueError:
                                logger.error(f"Type mismatch in {csv_path}, row {i}, field {field}: expected number, got {row[field]}")
                                row_valid = False
                                break
                
                if row_valid:
                    valid_rows += 1
            
            logger.info(f"Validated {valid_rows}/{total_rows} rows in {csv_path}")
            return valid_rows == total_rows

    except Exception as e:
        logger.error(f"Error reading CSV {csv_path}: {e}")
        return False

def verify_all_schemas() -> bool:
    """
    Iterates through the verification map and validates each file against its schema.
    Returns True if all validations pass, False otherwise.
    """
    all_passed = True
    
    if not CONTRACTS_DIR.exists():
        logger.error(f"Contracts directory not found: {CONTRACTS_DIR}")
        return False

    for entry in VERIFICATION_MAP:
        file_path = entry["file"]
        schema_path = entry["schema"]
        data_type = entry["type"]
        
        logger.info(f"Verifying {file_path} against {schema_path}...")
        
        if not file_path.exists():
            logger.error(f"File not found: {file_path}")
            all_passed = False
            continue
        
        if not schema_path.exists():
            logger.error(f"Schema not found: {schema_path}")
            all_passed = False
            continue
        
        try:
            schema = load_yaml_schema(schema_path)
            
            if data_type == "json_list":
                with open(file_path, 'r', encoding='utf-8') as f:
                    data = json.load(f)
                if not isinstance(data, list):
                    logger.error(f"Expected JSON list in {file_path}, got {type(data)}")
                    all_passed = False
                    continue
                if not validate_json_list(data, schema, file_path):
                    all_passed = False
                    
            elif data_type == "json_object":
                with open(file_path, 'r', encoding='utf-8') as f:
                    data = json.load(f)
                if not isinstance(data, dict):
                    logger.error(f"Expected JSON object in {file_path}, got {type(data)}")
                    all_passed = False
                    continue
                if not validate_json_object(data, schema, file_path):
                    all_passed = False
                    
            elif data_type == "csv":
                if not validate_csv(file_path, schema_path):
                    all_passed = False
                    
        except Exception as e:
            logger.error(f"Error processing {file_path}: {e}")
            all_passed = False
    
    return all_passed

def main():
    logger.info("Starting schema verification for PROJ-312...")
    success = verify_all_schemas()
    
    if success:
        logger.info("SUCCESS: All outputs match their schema contracts.")
        sys.exit(0)
    else:
        logger.error("FAILURE: One or more outputs failed schema validation.")
        sys.exit(1)

if __name__ == "__main__":
    main()
