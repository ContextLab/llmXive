"""
Task T020: Save spot-check results to data/spot_check/validation_report.csv

This script reads the validation results generated by validate_spot_check.py
(which simulates the manual review and calculates the false negative rate)
and persists them to the designated CSV file in the data/spot_check directory.

It relies on the functions defined in code/validate_spot_check.py to perform
the actual data loading, stratification, sampling, and calculation.
"""
import logging
import os
from pathlib import Path

from validate_spot_check import main as run_validation_pipeline

def main():
    """
    Executes the spot-check validation pipeline and saves the report.
    """
    # Configure logging
    log_dir = Path("logs")
    log_dir.mkdir(exist_ok=True)
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(levelname)s - %(message)s",
        handlers=[
            logging.FileHandler(log_dir / "pipeline.log"),
            logging.StreamHandler()
        ]
    )
    logger = logging.getLogger(__name__)

    logger.info("Starting T020: Saving spot-check results...")

    # The validate_spot_check.py module's main function is designed to:
    # 1. Load processed data
    # 2. Stratify and sample
    # 3. Simulate manual review
    # 4. Calculate false negative rate
    # 5. Save the validation_report.csv
    # We call it directly to ensure the artifact is created.
    try:
        run_validation_pipeline()
        logger.info("Spot-check validation report saved successfully to data/spot_check/validation_report.csv")
    except Exception as e:
        logger.error(f"Failed to generate spot-check results: {e}")
        raise

if __name__ == "__main__":
    main()
