"""
fetch_data.py

Module responsible for fetching PR data from GitHub, classifying AI contributions,
and calculating turnaround times.
"""

import json
import logging
import os
import time
from datetime import datetime
from pathlib import Path
from typing import List, Dict, Any, Optional

import requests

from utils import validate_json_schema, log_api_headers, api_request_with_backoff, MIN_PR_THRESHOLD

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Constants
GITHUB_API_BASE = "https://api.github.com"
REPOS_FILE = "data/raw/repos.json"
PR_DATA_FILE = "data/raw/pr_data.json"
PROCESSED_PR_FILE = "data/processed/pr_turnaround.csv"
EXCLUDED_REPOS_FILE = "data/processed/excluded_repos.txt"
TRUNCATED_REPOS_FILE = "data/processed/truncated_repos.txt"
LOG_FILE = "logs/pipeline.log"

# AI Classification Keywords and Labels
AI_KEYWORDS = ["copilot", "ai-generated", "llm-code", "generated by copilot"]
AI_LABELS = ["ai-generated", "copilot-assisted", "llm-code"]

def parse_iso_datetime(iso_string: str) -> Optional[datetime]:
    """Parse ISO 8601 datetime string."""
    if not iso_string:
        return None
    try:
        # Handle 'Z' suffix and timezone offsets
        iso_string = iso_string.replace('Z', '+00:00')
        return datetime.fromisoformat(iso_string)
    except ValueError:
        logger.warning(f"Failed to parse datetime: {iso_string}")
        return None

def extract_commit_keywords(commits: List[Dict]) -> List[str]:
    """Extract commit messages and search for AI keywords."""
    messages = []
    for commit in commits:
        msg = commit.get('commit', {}).get('message', '')
        if msg:
            messages.append(msg.lower())
    return messages

def check_labels(labels: List[Dict]) -> bool:
    """Check if any PR label matches AI labels."""
    for label in labels:
        label_name = label.get('name', '').lower()
        if label_name in AI_LABELS:
            return True
    return False

def classify_pr(commit_messages: List[str], labels: List[Dict]) -> str:
    """Classify PR as AI-assisted or non-AI based on keywords and labels."""
    # Check labels first
    if check_labels(labels):
        return "AI"

    # Check commit messages
    for msg in commit_messages:
        for keyword in AI_KEYWORDS:
            if keyword in msg:
                return "AI"

    return "Non-AI"

def calculate_turnaround_hours(created_at: str, merged_at: str) -> Optional[float]:
    """Calculate turnaround time in hours between creation and merge."""
    created_dt = parse_iso_datetime(created_at)
    merged_dt = parse_iso_datetime(merged_at)

    if not created_dt or not merged_dt:
        return None

    delta = merged_dt - created_dt
    return delta.total_seconds() / 3600

def fetch_repos_from_github() -> List[Dict]:
    """Fetch top Python and JavaScript repositories from GitHub API."""
    repos = []
    languages = ["Python", "JavaScript"]

    for lang in languages:
        query = f"language:{lang}+stars:>10000"
        url = f"{GITHUB_API_BASE}/search/repositories"
        params = {
            "q": query,
            "sort": "stars",
            "order": "desc",
            "per_page": 20
        }
        headers = {"Accept": "application/vnd.github.v3+json"}

        response = api_request_with_backoff(url, headers, params=params)
        if response.status_code != 200:
            logger.error(f"Failed to fetch {lang} repos: {response.status_code}")
            continue

        # Log API headers
        log_api_headers(response)

        data = response.json()
        items = data.get('items', [])
        repos.extend(items)

    return repos

def fetch_prs_for_repo(repo_name: str, max_pages: int = 50) -> List[Dict]:
    """Fetch PRs for a given repository with pagination."""
    all_prs = []
    page = 1
    url = f"{GITHUB_API_BASE}/repos/{repo_name}/pulls"
    headers = {"Accept": "application/vnd.github.v3+json"}
    params = {"state": "all", "per_page": 100}

    truncated = False

    while page <= max_pages:
        params["page"] = page
        response = api_request_with_backoff(url, headers, params=params)

        if response.status_code != 200:
            logger.error(f"Failed to fetch PRs for {repo_name} (page {page}): {response.status_code}")
            break

        # Log API headers
        log_api_headers(response)

        prs = response.json()
        if not prs:
            break

        all_prs.extend(prs)

        # Check Link header for next page
        link_header = response.headers.get('Link', '')
        if 'rel="next"' not in link_header:
            break

        page += 1

        # Safety stop condition
        if page > max_pages:
            logger.warning(f"Reached max pages ({max_pages}) for {repo_name}")
            truncated = True
            break

        # Small delay to be polite to the API
        time.sleep(1)

    if truncated:
        # Log truncated repos
        truncated_path = Path(TRUNCATED_REPOS_FILE)
        truncated_path.parent.mkdir(parents=True, exist_ok=True)
        with open(truncated_path, 'a') as f:
            f.write(f"{repo_name}\n")

    return all_prs

def fetch_commits_for_pr(repo_name: str, pr_number: int) -> List[Dict]:
    """Fetch commits for a specific PR."""
    url = f"{GITHUB_API_BASE}/repos/{repo_name}/pulls/{pr_number}/commits"
    headers = {"Accept": "application/vnd.github.v3+json"}

    response = api_request_with_backoff(url, headers)
    if response.status_code != 200:
        logger.error(f"Failed to fetch commits for PR #{pr_number}: {response.status_code}")
        return []

    # Log API headers
    log_api_headers(response)

    return response.json()

def process_pr_data(repo_name: str, pr: Dict) -> Optional[Dict]:
    """Process a single PR to extract turnaround time and classification."""
    pr_id = str(pr.get('number', ''))
    created_at = pr.get('created_at')
    merged_at = pr.get('merged_at')
    labels = pr.get('labels', [])

    # Skip unmerged PRs
    if not merged_at:
        return None

    turnaround = calculate_turnaround_hours(created_at, merged_at)
    if turnaround is None:
        return None

    # Fetch commits for classification
    commits = fetch_commits_for_pr(repo_name, pr.get('number'))
    commit_messages = extract_commit_keywords(commits)

    classification = classify_pr(commit_messages, labels)

    return {
        "pr_id": pr_id,
        "repo_name": repo_name,
        "created_at": created_at,
        "merged_at": merged_at,
        "turnaround_hours": turnaround,
        "classification": classification,
        "labels": [l.get('name') for l in labels]
    }

def fetch_prs_and_commits_for_repos(repos: List[Dict]) -> List[Dict]:
    """Fetch PRs and commits for all repositories."""
    all_pr_data = []
    excluded_repos = []

    for repo in repos:
        repo_name = repo.get('full_name', '')
        logger.info(f"Processing repository: {repo_name}")

        prs = fetch_prs_for_repo(repo_name)

        if len(prs) < MIN_PR_THRESHOLD:
            logger.warning(f"Skipping {repo_name}: only {len(prs)} PRs (threshold: {MIN_PR_THRESHOLD})")
            excluded_repos.append(repo_name)
            continue

        repo_pr_data = []
        for pr in prs:
            processed = process_pr_data(repo_name, pr)
            if processed:
                repo_pr_data.append(processed)

        all_pr_data.extend(repo_pr_data)

    # Save excluded repos
    if excluded_repos:
        save_excluded_repos(excluded_repos)

    return all_pr_data

def save_excluded_repos(repo_names: List[str]):
    """Save list of excluded repos to file."""
    path = Path(EXCLUDED_REPOS_FILE)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'w') as f:
        for name in repo_names:
            f.write(f"{name}\n")
    logger.info(f"Saved {len(repo_names)} excluded repos to {path}")

def save_raw_pr_data(data: List[Dict]):
    """Save raw PR data to JSON file."""
    path = Path(PR_DATA_FILE)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'w') as f:
        json.dump(data, f, indent=2)
    logger.info(f"Saved raw PR data to {path}")

def save_processed_data(data: List[Dict]):
    """Save processed PR data to CSV file."""
    import csv
    path = Path(PROCESSED_PR_FILE)
    path.parent.mkdir(parents=True, exist_ok=True)

    fieldnames = ['pr_id', 'repo_name', 'created_at', 'merged_at', 'turnaround_hours', 'classification', 'labels']

    with open(path, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in data:
            writer.writerow(row)

    logger.info(f"Saved processed PR data to {path}")

def main():
    """Main entry point for data fetching."""
    logger.info("Starting data fetch pipeline...")

    # Fetch repositories
    repos = fetch_repos_from_github()
    logger.info(f"Fetched {len(repos)} repositories")

    # Save raw repo data
    repo_data_path = Path(REPOS_FILE)
    repo_data_path.parent.mkdir(parents=True, exist_ok=True)
    with open(repo_data_path, 'w') as f:
        json.dump(repos, f, indent=2)

    # Fetch PRs and commits
    pr_data = fetch_prs_and_commits_for_repos(repos)
    logger.info(f"Processed {len(pr_data)} PRs")

    # Save raw and processed data
    save_raw_pr_data(pr_data)
    save_processed_data(pr_data)

    logger.info("Data fetch pipeline completed.")

if __name__ == "__main__":
    main()