class TestParseIsoDatetime(unittest.TestCase):
    """Tests for ISO datetime parsing."""

    def test_valid_iso_format(self):
        """Test with valid ISO 8601 format."""
        timestamp = "2023-10-15T14:30:00Z"
        result = parse_iso_datetime(timestamp)
        self.assertIsNotNone(result)
        self.assertEqual(result.year, 2023)
        self.assertEqual(result.month, 10)
        self.assertEqual(result.day, 15)

    def test_iso_format_with_offset(self):
        """Test with ISO format including timezone offset."""
        timestamp = "2023-10-15T14:30:00+00:00"
        result = parse_iso_datetime(timestamp)
        self.assertIsNotNone(result)

    def test_invalid_format(self):
        """Test with invalid datetime format."""
        with self.assertRaises(ValueError):
            parse_iso_datetime("not-a-date")

    def test_empty_string(self):
        """Test with empty string."""
        with self.assertRaises(ValueError):
            parse_iso_datetime("")

    def test_none_value(self):
        """Test with None value."""
        with self.assertRaises((ValueError, TypeError)):
            parse_iso_datetime(None)


class TestCalculateTurnaroundHours(unittest.TestCase):
    """Tests for turnaround time calculation."""

    def test_basic_calculation(self):
        """Test basic turnaround time calculation."""
        created = datetime(2023, 10, 15, 10, 0, 0)
        merged = datetime(2023, 10, 15, 14, 0, 0)
        result = calculate_turnaround_hours(created, merged)
        self.assertEqual(result, 4.0)

    def test_multi_day_calculation(self):
        """Test calculation spanning multiple days."""
        created = datetime(2023, 10, 15, 10, 0, 0)
        merged = datetime(2023, 10, 17, 10, 0, 0)
        result = calculate_turnaround_hours(created, merged)
        self.assertEqual(result, 48.0)

    def test_fractional_hours(self):
        """Test calculation with fractional hours."""
        created = datetime(2023, 10, 15, 10, 0, 0)
        merged = datetime(2023, 10, 15, 10, 30, 0)
        result = calculate_turnaround_hours(created, merged)
        self.assertEqual(result, 0.5)

    def test_negative_turnaround(self):
        """Test with merged before created (should return 0 or handle gracefully)."""
        created = datetime(2023, 10, 15, 14, 0, 0)
        merged = datetime(2023, 10, 15, 10, 0, 0)
        result = calculate_turnaround_hours(created, merged)
        # Should handle negative case (either return 0 or raise error)
        self.assertGreaterEqual(result, 0)

    def test_same_timestamp(self):
        """Test with same created and merged time."""
        created = datetime(2023, 10, 15, 10, 0, 0)
        merged = datetime(2023, 10, 15, 10, 0, 0)
        result = calculate_turnaround_hours(created, merged)
        self.assertEqual(result, 0.0)


class TestApiRequestWithBackoff(unittest.TestCase):
    """Tests for API request with backoff edge cases."""

    @patch('fetch_data.requests.get')
    def test_rate_limit_403(self, mock_get):
        """Test handling of 403 rate limit response."""
        mock_response = MagicMock()
        mock_response.status_code = 403
        mock_response.headers = {
            'X-RateLimit-Remaining': '0',
            'X-RateLimit-Reset': '1697380800'
        }
        mock_response.raise_for_status.side_effect = Exception("403 Client Error")
        mock_get.return_value = mock_response

        with self.assertRaises(Exception):
            api_request_with_backoff(
                "https://api.github.com/repos/test/test",
                {"Authorization": "token fake"}
            )

    @patch('fetch_data.requests.get')
    def test_empty_response(self, mock_get):
        """Test handling of empty response body."""
        mock_response = MagicMock()
        mock_response.status_code = 200
        mock_response.json.return_value = {}
        mock_response.headers = {
            'X-RateLimit-Remaining': '100',
            'X-RateLimit-Reset': '1697380800'
        }
        mock_get.return_value = mock_response

        # Should not raise, just return empty dict
        result = api_request_with_backoff(
            "https://api.github.com/repos/test/test",
            {"Authorization": "token fake"}
        )
        self.assertEqual(result, {})

    @patch('fetch_data.requests.get')
    def test_invalid_json_response(self, mock_get):
        """Test handling of invalid JSON in response."""
        mock_response = MagicMock()
        mock_response.status_code = 200
        mock_response.json.side_effect = json.JSONDecodeError("Expecting value", "doc", 0)
        mock_response.headers = {
            'X-RateLimit-Remaining': '100',
            'X-RateLimit-Reset': '1697380800'
        }
        mock_get.return_value = mock_response

        with self.assertRaises(json.JSONDecodeError):
            api_request_with_backoff(
                "https://api.github.com/repos/test/test",
                {"Authorization": "token fake"}
            )

    @patch('fetch_data.requests.get')
    def test_network_timeout(self, mock_get):
        """Test handling of network timeout."""
        import requests
        mock_get.side_effect = requests.exceptions.Timeout("Request timed out")

        with self.assertRaises(requests.exceptions.Timeout):
            api_request_with_backoff(
                "https://api.github.com/repos/test/test",
                {"Authorization": "token fake"}
            )

    @patch('fetch_data.requests.get')
    def test_connection_error(self, mock_get):
        """Test handling of connection error."""
        import requests
        mock_get.side_effect = requests.exceptions.ConnectionError("Connection refused")

        with self.assertRaises(requests.exceptions.ConnectionError):
            api_request_with_backoff(
                "https://api.github.com/repos/test/test",
                {"Authorization": "token fake"}
            )

    @patch('fetch_data.requests.get')
    def test_successful_response(self, mock_get):
        """Test successful API response."""
        mock_response = MagicMock()
        mock_response.status_code = 200
        mock_response.json.return_value = {"data": "test"}
        mock_response.headers = {
            'X-RateLimit-Remaining': '100',
            'X-RateLimit-Reset': '1697380800'
        }
        mock_get.return_value = mock_response

        result = api_request_with_backoff(
            "https://api.github.com/repos/test/test",
            {"Authorization": "token fake"}
        )
        self.assertEqual(result, {"data": "test"})


class TestMissingFieldsInPrData(unittest.TestCase):
    """Tests for handling missing fields in PR data."""

    def test_missing_created_at(self):
        """Test PR data missing created_at field."""
        pr_data = {
            "pr_id": "123",
            "repo_name": "test/repo",
            "merged_at": "2023-10-15T14:00:00Z"
        }
        # This should be handled by the calling code
        # We test that the function doesn't crash with missing field
        with self.assertRaises(KeyError):
            parse_iso_datetime(pr_data.get("created_at"))

    def test_missing_merged_at(self):
        """Test PR data missing merged_at field."""
        pr_data = {
            "pr_id": "123",
            "repo_name": "test/repo",
            "created_at": "2023-10-15T10:00:00Z"
        }
        # This should be handled by the calling code
        with self.assertRaises(KeyError):
            parse_iso_datetime(pr_data.get("merged_at"))

    def test_missing_labels_field(self):
        """Test PR data missing labels field."""
        pr_data = {
            "pr_id": "123",
            "repo_name": "test/repo",
            "created_at": "2023-10-15T10:00:00Z",
            "merged_at": "2023-10-15T14:00:00Z"
        }
        # check_labels should handle missing labels gracefully
        labels = pr_data.get("labels", [])
        result = check_labels(labels)
        self.assertFalse(result)

    def test_missing_commit_messages(self):
        """Test PR data missing commit_messages field."""
        pr_data = {
            "pr_id": "123",
            "repo_name": "test/repo",
            "created_at": "2023-10-15T10:00:00Z",
            "merged_at": "2023-10-15T14:00:00Z",
            "labels": []
        }
        commit_messages = pr_data.get("commit_messages", [])
        result = extract_commit_keywords(str(commit_messages))
        # Empty list should return empty result
        self.assertEqual(result, [])


