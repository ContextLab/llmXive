class TestExtractCommitKeywords(unittest.TestCase):
    """Tests for commit message keyword extraction."""

    def test_empty_message(self):
        """Test with empty commit message."""
        result = extract_commit_keywords("")
        self.assertEqual(result, [])

    def test_no_keywords(self):
        """Test with message containing no AI keywords."""
        message = "Fix bug in user authentication"
        result = extract_commit_keywords(message)
        self.assertEqual(result, [])

    def test_single_keyword(self):
        """Test with single AI keyword."""
        message = "Generated by Copilot"
        result = extract_commit_keywords(message)
        self.assertIn("copilot", result)

    def test_multiple_keywords(self):
        """Test with multiple AI keywords."""
        message = "AI-generated code using copilot assistance"
        result = extract_commit_keywords(message)
        self.assertIn("copilot", result)
        self.assertIn("ai-generated", result)

    def test_case_insensitive(self):
        """Test that keyword matching is case-insensitive."""
        message = "COPILOT generated this code"
        result = extract_commit_keywords(message)
        self.assertIn("copilot", result)

    def test_partial_word_not_matched(self):
        """Test that partial words are not matched."""
        message = "This is a copilotry of code"
        result = extract_commit_keywords(message)
        self.assertNotIn("copilot", result)


