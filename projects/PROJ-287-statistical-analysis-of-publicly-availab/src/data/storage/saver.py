import os
import logging
import hashlib
import json
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple
import pandas as pd
from src.utils.logging import get_logger

# Define the specific 5-year windows as per project requirements
WINDOWS = [
    ("2000-2004", 2000, 2004),
    ("2005-2009", 2005, 2009),
    ("2010-2014", 2010, 2014),
    ("2015-2019", 2015, 2019),
    ("2020-2024", 2020, 2024),
]

logger = get_logger(__name__)


def partition_by_window(
    data: List[Dict[str, Any]], year_field: str = "year"
) -> Dict[str, List[Dict[str, Any]]]:
    """
    Partition a list of abstract records into the specific 5-year windows.

    Args:
        data: List of dictionaries containing abstract records with a 'year' field.
        year_field: The key in the dictionary representing the publication year.

    Returns:
        A dictionary mapping window labels (e.g., "2000-2004") to lists of records.
    """
    partitions: Dict[str, List[Dict[str, Any]]] = {w[0]: [] for w in WINDOWS}
    missing_year_records = []

    for record in data:
        if year_field not in record:
            missing_year_records.append(record)
            continue

        try:
            year = int(record[year_field])
        except (ValueError, TypeError):
            missing_year_records.append(record)
            continue

        assigned = False
        for label, start, end in WINDOWS:
            if start <= year <= end:
                partitions[label].append(record)
                assigned = True
                break

        if not assigned:
            # Record is outside the 2000-2024 range
            logger.debug(f"Record with year {year} outside defined windows, skipping.")

    if missing_year_records:
        logger.warning(
            f"Found {len(missing_year_records)} records missing valid year data."
        )

    return partitions


def compute_checksum(file_path: Path) -> str:
    """
    Compute the SHA256 checksum of a file.

    Args:
        file_path: Path to the file.

    Returns:
        Hexadecimal string of the SHA256 checksum.
    """
    sha256_hash = hashlib.sha256()
    with open(file_path, "rb") as f:
        for byte_block in iter(lambda: f.read(4096), b""):
            sha256_hash.update(byte_block)
    return sha256_hash.hexdigest()


def save_partitioned_csvs(
    data: List[Dict[str, Any]],
    output_dir: Path,
    year_field: str = "year",
    source_field: str = "source",
) -> Dict[str, str]:
    """
    Save processed data partitioned by the specific 5-year windows to CSV files.

    Args:
        data: List of processed abstract records.
        output_dir: Directory where CSV files will be saved.
        year_field: Key in record dict for publication year.
        source_field: Key in record dict for data source (arXiv/PubMed).

    Returns:
        A dictionary mapping window labels to their file paths (relative to output_dir).
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    partitions = partition_by_window(data, year_field)
    checksums = {}

    for label, records in partitions.items():
        if not records:
            logger.info(f"No records found for window {label}. Skipping file creation.")
            continue

        # Create filename: processed_{window_label}.csv
        filename = f"processed_{label.replace('-', '_')}.csv"
        file_path = output_dir / filename

        df = pd.DataFrame(records)

        # Ensure the dataframe has the expected columns for downstream tasks
        # Common columns based on fetchers/tokenizers
        expected_cols = {"id", "title", "abstract", "year", "source", "tokens"}
        existing_cols = set(df.columns)
        missing_cols = expected_cols - existing_cols
        if missing_cols:
            logger.warning(
                f"DataFrame for {label} missing expected columns: {missing_cols}"
            )

        df.to_csv(file_path, index=False)
        checksum = compute_checksum(file_path)
        checksums[label] = checksum
        logger.info(
            f"Saved {len(records)} records to {file_path} (SHA256: {checksum[:16]}...)"
        )

    return checksums


def main() -> None:
    """
    Main entry point for the saver module.
    Loads preprocessed data (assumed to be in data/processed/stage1.json or similar),
    partitions it, and saves CSVs.

    Note: This implementation assumes the preprocessed data is available as a JSONL
    file generated by the previous filter step (T015).
    """
    logger.info("Starting data storage and partitioning (T016).")

    # Configuration
    input_file = Path("data/processed/stage1_filtered.jsonl")
    output_dir = Path("data/processed")

    if not input_file.exists():
        logger.error(f"Input file not found: {input_file}. Cannot proceed.")
        raise FileNotFoundError(
            f"Input file {input_file} not found. "
            "Ensure T015 (filter) has completed and generated the input file."
        )

    # Load data
    logger.info(f"Loading data from {input_file}...")
    data = []
    with open(input_file, "r", encoding="utf-8") as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                record = json.loads(line)
                data.append(record)
            except json.JSONDecodeError as e:
                logger.error(f"JSON decode error at line {line_num}: {e}")
                raise

    logger.info(f"Loaded {len(data)} records.")

    # Save partitioned CSVs
    checksums = save_partitioned_csvs(data, output_dir)

    logger.info("Partitioning complete. Checksums:")
    for window, cksum in checksums.items():
        logger.info(f"  {window}: {cksum}")

    # Optional: Save a manifest of the partitioning step
    manifest_path = output_dir / "partitioning_manifest.json"
    manifest_data = {
        "step": "T016_partition",
        "input_file": str(input_file),
        "output_dir": str(output_dir),
        "windows": list(checksums.keys()),
        "file_checksums": checksums,
        "total_records": len(data),
    }
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest_data, f, indent=2)
    logger.info(f"Partitioning manifest saved to {manifest_path}")


if __name__ == "__main__":
    main()