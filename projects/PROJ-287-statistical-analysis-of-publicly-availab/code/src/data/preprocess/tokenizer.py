"""
Tokenizer module for applying window-specific stopwords and lemmatization.

This module implements FR-014: Application of window-specific stopwords to
abstract text for topic drift analysis. It loads versioned stopword lists
generated by T014a/T014b and applies them during tokenization.
"""

import os
import re
import json
import logging
from pathlib import Path
from typing import List, Dict, Optional, Set, Tuple, Generator

import spacy
from dataclasses import dataclass
from src.utils.logging import get_logger

# Configuration
STOPWORDS_DIR = Path("data/stopwords")
MANIFEST_PATH = STOPWORDS_DIR / "manifest.json"

@dataclass
class TokenizationResult:
    """Result of tokenizing an abstract."""
    original_id: str
    window: str
    tokens: List[str]
    token_count: int
    filtered_tokens: List[str]
    filtered_count: int
    success: bool
    error_message: Optional[str] = None


class WindowStopwordLoader:
    """
    Loads versioned window-specific stopword lists from the manifest.
    
    This class ensures that the correct stopword list is loaded for each
    time window, preventing language drift across periods.
    """
    
    def __init__(self, manifest_path: Optional[Path] = None):
        self.logger = get_logger(__name__)
        self.manifest_path = manifest_path or MANIFEST_PATH
        self.stopword_cache: Dict[str, Set[str]] = {}
        self._load_manifest()
    
    def _load_manifest(self) -> None:
        """Load the stopword manifest and validate its structure."""
        if not self.manifest_path.exists():
            raise FileNotFoundError(
                f"Stopword manifest not found at {self.manifest_path}. "
                "Run T014a to generate stopwords first."
            )
        
        with open(self.manifest_path, 'r', encoding='utf-8') as f:
            self.manifest = json.load(f)
        
        # Validate manifest structure
        if 'windows' not in self.manifest:
            raise ValueError("Manifest missing 'windows' key")
        
        self.logger.info(f"Loaded stopword manifest with {len(self.manifest['windows'])} windows")
    
    def get_stopwords(self, window: str) -> Set[str]:
        """
        Get the stopword set for a specific window.
        
        Args:
            window: Window identifier (e.g., "2000-2004", "2005-2009")
        
        Returns:
            Set of stopwords for the specified window
        
        Raises:
            KeyError: If window not found in manifest
        """
        if window in self.stopword_cache:
            return self.stopword_cache[window]
        
        # Check if window exists in manifest
        window_found = False
        for w_info in self.manifest['windows']:
            if w_info['window_id'] == window:
                window_found = True
                break
        
        if not window_found:
            raise KeyError(
                f"Window '{window}' not found in stopword manifest. "
                f"Available windows: {[w['window_id'] for w in self.manifest['windows']]}"
            )
        
        # Load stopwords from file
        stopwords_file = self.manifest_path.parent / f"{window}_stopwords.json"
        if not stopwords_file.exists():
            raise FileNotFoundError(
                f"Stopword file not found for window {window}: {stopwords_file}"
            )
        
        with open(stopwords_file, 'r', encoding='utf-8') as f:
            stopwords_data = json.load(f)
        
        stopwords_set = set(stopwords_data['stopwords'])
        self.stopword_cache[window] = stopwords_set
        
        self.logger.debug(f"Loaded {len(stopwords_set)} stopwords for window {window}")
        return stopwords_set


class AbstractTokenizer:
    """
    Tokenizer that applies window-specific stopwords and lemmatization.
    
    Implements FR-014 by loading and applying versioned stopword lists
    specific to each time window.
    """
    
    def __init__(self, nlp_model: str = "en_core_web_sm"):
        self.logger = get_logger(__name__)
        self.nlp_model = nlp_model
        self.stopword_loader = WindowStopwordLoader()
        self._nlp = None
    
    @property
    def nlp(self):
        """Lazy load spaCy model."""
        if self._nlp is None:
            self.logger.info(f"Loading spaCy model: {self.nlp_model}")
            try:
                self._nlp = spacy.load(self.nlp_model)
            except OSError:
                raise RuntimeError(
                    f"spaCy model '{self.nlp_model}' not found. "
                    "Run: python -m spacy download {self.nlp_model}"
                )
        return self._nlp
    
    def _clean_text(self, text: str) -> str:
        """Clean and normalize text before tokenization."""
        # Remove URLs
        text = re.sub(r'http\S+|www\S+|https\S+', '', text, flags=re.MULTILINE)
        # Remove email addresses
        text = re.sub(r'\S+@\S+', '', text)
        # Remove special characters but keep spaces
        text = re.sub(r'[^a-zA-Z0-9\s]', ' ', text)
        # Normalize whitespace
        text = re.sub(r'\s+', ' ', text).strip()
        return text
    
    def tokenize(self, abstract: Dict, window: str) -> TokenizationResult:
        """
        Tokenize an abstract with window-specific stopwords.
        
        Args:
            abstract: Dictionary containing 'id' and 'text' fields
            window: Time window identifier (e.g., "2000-2004")
        
        Returns:
            TokenizationResult with tokens and metadata
        """
        try:
            abstract_id = abstract.get('id', 'unknown')
            text = abstract.get('text', '')
            
            if not text:
                return TokenizationResult(
                    original_id=abstract_id,
                    window=window,
                    tokens=[],
                    token_count=0,
                    filtered_tokens=[],
                    filtered_count=0,
                    success=False,
                    error_message="Empty text"
                )
            
            # Clean text
            cleaned_text = self._clean_text(text)
            
            # Tokenize with spaCy
            doc = self.nlp(cleaned_text)
            
            # Extract tokens with lemmatization
            tokens = []
            for token in doc:
                # Skip whitespace, punctuation, and very short tokens
                if not token.is_space and not token.is_punct and len(token.text) > 1:
                    # Use lemma if available, otherwise use text
                    lemma = token.lemma_.lower()
                    # Skip if lemma is same as special characters
                    if lemma not in ('-PRON-', '-NONE-', '``', "''", '.'):
                        tokens.append(lemma)
            
            # Get window-specific stopwords
            try:
                stopwords = self.stopword_loader.get_stopwords(window)
            except (KeyError, FileNotFoundError) as e:
                return TokenizationResult(
                    original_id=abstract_id,
                    window=window,
                    tokens=tokens,
                    token_count=len(tokens),
                    filtered_tokens=[],
                    filtered_count=0,
                    success=False,
                    error_message=f"Failed to load stopwords: {str(e)}"
                )
            
            # Apply stopwords
            filtered_tokens = [t for t in tokens if t not in stopwords]
            
            self.logger.debug(
                f"Tokenized abstract {abstract_id}: "
                f"{len(tokens)} -> {len(filtered_tokens)} tokens"
            )
            
            return TokenizationResult(
                original_id=abstract_id,
                window=window,
                tokens=tokens,
                token_count=len(tokens),
                filtered_tokens=filtered_tokens,
                filtered_count=len(filtered_tokens),
                success=True
            )
            
        except Exception as e:
            self.logger.error(f"Tokenization failed for abstract {abstract.get('id', 'unknown')}: {e}")
            return TokenizationResult(
                original_id=abstract.get('id', 'unknown'),
                window=window,
                tokens=[],
                token_count=0,
                filtered_tokens=[],
                filtered_count=0,
                success=False,
                error_message=str(e)
            )
    
    def tokenize_batch(self, abstracts: List[Dict], window: str) -> Generator[TokenizationResult, None, None]:
        """
        Tokenize a batch of abstracts.
        
        Args:
            abstracts: List of abstract dictionaries
            window: Time window identifier
        
        Yields:
            TokenizationResult for each abstract
        """
        for abstract in abstracts:
            yield self.tokenize(abstract, window)

def load_preprocessed_data(data_path: Path) -> List[Dict]:
    """
    Load preprocessed abstracts from a JSONL file.
    
    Args:
        data_path: Path to the JSONL file
    
    Returns:
        List of abstract dictionaries
    """
    if not data_path.exists():
        raise FileNotFoundError(f"Data file not found: {data_path}")
    
    abstracts = []
    with open(data_path, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                abstract = json.loads(line)
                abstracts.append(abstract)
            except json.JSONDecodeError as e:
                logging.warning(f"Invalid JSON at line {line_num}: {e}")
    
    return abstracts

def save_tokenized_results(results: List[TokenizationResult], output_path: Path) -> None:
    """
    Save tokenization results to a JSONL file.
    
    Args:
        results: List of TokenizationResult objects
        output_path: Path to output file
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        for result in results:
            record = {
                'id': result.original_id,
                'window': result.window,
                'tokens': result.tokens,
                'token_count': result.token_count,
                'filtered_tokens': result.filtered_tokens,
                'filtered_count': result.filtered_count,
                'success': result.success
            }
            if result.error_message:
                record['error'] = result.error_message
            f.write(json.dumps(record) + '\n')

def main():
    """
    Main entry point for tokenization pipeline.
    
    This function processes all preprocessed abstracts, applying
    window-specific stopwords and lemmatization.
    """
    logger = get_logger(__name__)
    logger.info("Starting tokenization pipeline")
    
    # Define windows
    windows = [
        "2000-2004",
        "2005-2009",
        "2010-2014",
        "2015-2019",
        "2020-2024"
    ]
    
    # Initialize tokenizer
    tokenizer = AbstractTokenizer()
    
    # Process each window
    for window in windows:
        input_path = Path(f"data/processed/abstracts_{window}.jsonl")
        output_path = Path(f"data/processed/tokenized_{window}.jsonl")
        
        if not input_path.exists():
            logger.warning(f"Input file not found: {input_path}, skipping window {window}")
            continue
        
        logger.info(f"Processing window {window} from {input_path}")
        
        # Load data
        abstracts = load_preprocessed_data(input_path)
        logger.info(f"Loaded {len(abstracts)} abstracts for window {window}")
        
        # Tokenize
        results = list(tokenizer.tokenize_batch(abstracts, window))
        
        # Save results
        save_tokenized_results(results, output_path)
        
        # Log summary
        success_count = sum(1 for r in results if r.success)
        avg_tokens = sum(r.filtered_count for r in results) / len(results) if results else 0
        
        logger.info(
            f"Window {window}: {success_count}/{len(results)} successful, "
            f"avg filtered tokens: {avg_tokens:.1f}"
        )
    
    logger.info("Tokenization pipeline completed")

if __name__ == "__main__":
    main()
