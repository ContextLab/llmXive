import os
import sys
import yaml
import json
import logging
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any, List

from src.data.archive_utils import generate_checksum_manifest
from src.config import setup_logging

logger = setup_logging(__name__)


def load_checksums_from_archive(archive_dir: Path) -> Dict[str, str]:
    """
    Load checksums from the archive manifest generated by T005d.
    
    Args:
        archive_dir: Path to the data/raw/archive directory.
        
    Returns:
        Dictionary mapping file paths (relative to archive) to SHA-256 hashes.
        
    Raises:
        FileNotFoundError: If the manifest file does not exist.
        ValueError: If the manifest is invalid.
    """
    manifest_path = archive_dir / "checksums.json"
    
    if not manifest_path.exists():
        raise FileNotFoundError(f"Checksum manifest not found at {manifest_path}. "
                              "Ensure T005d (Archive and Checksum) has been completed.")
    
    try:
        with open(manifest_path, 'r', encoding='utf-8') as f:
            manifest = json.load(f)
    except json.JSONDecodeError as e:
        raise ValueError(f"Invalid JSON in checksum manifest: {e}") from e
    
    if "files" not in manifest:
        raise ValueError("Checksum manifest missing 'files' key.")
    
    return {item["path"]: item["sha256"] for item in manifest["files"]}


def update_state_file(
    project_id: str,
    checksums: Dict[str, str],
    state_dir: Path
) -> None:
    """
    Update the project state file with artifact checksums and timestamp.
    
    This implements T005e: Update State File.
    
    Args:
        project_id: The project identifier (e.g., PROJ-132-...).
        checksums: Dictionary of artifact paths to their SHA-256 hashes.
        state_dir: Path to the state/projects directory.
        
    Raises:
        FileNotFoundError: If the state directory does not exist.
        OSError: If the state file cannot be written.
    """
    state_dir.mkdir(parents=True, exist_ok=True)
    state_file_path = state_dir / f"{project_id}.yaml"
    
    timestamp = datetime.now(timezone.utc).isoformat()
    
    state_data = {
        "project_id": project_id,
        "artifact_hashes": checksums,
        "updated_at": timestamp,
        "source": "T005e_update_state_pipeline"
    }
    
    try:
        with open(state_file_path, 'w', encoding='utf-8') as f:
            yaml.dump(state_data, f, default_flow_style=False, sort_keys=False)
        logger.info(f"State file updated successfully: {state_file_path}")
        logger.info(f"Recorded {len(checksums)} artifact checksums.")
    except OSError as e:
        logger.error(f"Failed to write state file {state_file_path}: {e}")
        raise


def run_state_update_pipeline(
    project_id: str,
    archive_dir: Path,
    state_dir: Path
) -> None:
    """
    Orchestrate the state update pipeline: load checksums from archive and write state file.
    
    Args:
        project_id: The project identifier.
        archive_dir: Path to the data/raw/archive directory.
        state_dir: Path to the state/projects directory.
    """
    logger.info(f"Starting state update pipeline for project {project_id}")
    
    if not archive_dir.exists():
        raise FileNotFoundError(f"Archive directory not found: {archive_dir}. "
                              "Ensure T005d (Archive and Checksum) has been completed.")
    
    logger.info(f"Loading checksums from archive: {archive_dir}")
    checksums = load_checksums_from_archive(archive_dir)
    
    logger.info(f"Updating state file in: {state_dir}")
    update_state_file(project_id, checksums, state_dir)
    
    logger.info("State update pipeline completed successfully.")


def main() -> None:
    """Entry point for the state update script."""
    root_dir = Path(__file__).resolve().parent.parent.parent.parent
    project_id = "PROJ-132-statistical-analysis-of-publicly-availab"
    
    archive_dir = root_dir / "data" / "raw" / "archive"
    state_dir = root_dir / "state" / "projects"
    
    try:
        run_state_update_pipeline(project_id, archive_dir, state_dir)
    except Exception as e:
        logger.error(f"Pipeline failed: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()
