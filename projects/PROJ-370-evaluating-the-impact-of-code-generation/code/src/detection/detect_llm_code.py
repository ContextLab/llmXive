"""
T018 Implementation: Detect LLM-generated code in PR diffs using heuristics.

Heuristics implemented (FR-016):
1. Presence of LLM-specific comments (e.g., "Generated by", "AI assistance").
2. Code structure patterns typical of LLMs (highly repetitive, specific formatting).
3. Statistical analysis of code complexity (optional, simplified for now).
4. Detection of specific tokens often found in LLM outputs.

Output: Writes results to data/derived/llm_detections.json
"""
import json
import re
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple

from config.settings import get_paths, ensure_directories
from src.detection.schema import LLMCodeDetectionResult, ConfidenceLevel

# Configure logging
logger = logging.getLogger(__name__)

# Heuristic patterns
LLM_COMMENT_PATTERNS = [
    r'#\s*Generated\s+by\s+\w+',
    r'#\s*AI\s+generated',
    r'#\s*LLM\s+output',
    r'#\s*Model\s+generated',
    r'#\s*Assistant:',
    r'#\s*Copilot:',
    r'#\s*Code\s+generated\s+by\s+AI',
    r'#\s*This\s+code\s+was\s+generated\s+by',
]

# Patterns indicating potential LLM-generated code blocks
LLM_STRUCTURE_PATTERNS = [
    # Highly repetitive variable names often generated by LLMs
    r'var\s+item\d+',
    r'var\s+obj\d+',
    r'var\s+temp\d+',
    # Generic function names
    r'def\s+process_data\(.*\):',
    r'def\s+handle_request\(.*\):',
    r'def\s+calculate_result\(.*\):',
]

# Specific tokens often found in LLM outputs
LLM_TOKEN_PATTERNS = [
    r'Here\s+is\s+the\s+code',
    r'Sure,\s+I\s+can\s+help',
    r'Certainly,\s+here\s+is',
    r'As\s+an\s+AI\s+language\s+model',
    r'Below\s+is\s+the\s+code',
]

def calculate_confidence(matches: Dict[str, List[str]]) -> ConfidenceLevel:
    """
    Calculate confidence level based on heuristic matches.

    Args:
        matches: Dictionary of pattern types to list of matches found

    Returns:
        ConfidenceLevel enum value
    """
    total_matches = sum(len(v) for v in matches.values())

    if total_matches == 0:
        return ConfidenceLevel.LOW
    elif total_matches == 1:
        return ConfidenceLevel.LOW
    elif total_matches == 2:
        return ConfidenceLevel.MEDIUM
    elif total_matches >= 3:
        return ConfidenceLevel.HIGH
    else:
        return ConfidenceLevel.LOW

def detect_llm_generated_code(diff_content: str, pr_id: str, file_path: str, line_start: int, line_end: int) -> LLMCodeDetectionResult:
    """
    Detect if code in a diff segment is likely LLM-generated.

    Args:
        diff_content: The actual code diff content
        pr_id: Pull request identifier
        file_path: Path to the file in the repository
        line_start: Starting line number
        line_end: Ending line number

    Returns:
        LLMCodeDetectionResult object
    """
    matches = {
        'comment_patterns': [],
        'structure_patterns': [],
        'token_patterns': []
    }

    # Check for LLM comment patterns
    for pattern in LLM_COMMENT_PATTERNS:
        found = re.findall(pattern, diff_content, re.IGNORECASE)
        if found:
            matches['comment_patterns'].extend(found)

    # Check for LLM structure patterns
    for pattern in LLM_STRUCTURE_PATTERNS:
        found = re.findall(pattern, diff_content, re.IGNORECASE)
        if found:
            matches['structure_patterns'].extend(found)

    # Check for LLM token patterns
    for pattern in LLM_TOKEN_PATTERNS:
        found = re.findall(pattern, diff_content, re.IGNORECASE)
        if found:
            matches['token_patterns'].extend(found)

    confidence = calculate_confidence(matches)
    is_llm_generated = confidence in [ConfidenceLevel.MEDIUM, ConfidenceLevel.HIGH]

    return LLMCodeDetectionResult(
        pr_id=pr_id,
        file_path=file_path,
        line_start=line_start,
        line_end=line_end,
        is_llm_generated=is_llm_generated,
        confidence=confidence,
        matches=matches
    )

def process_pr_diffs(pr_data_path: Path) -> List[LLMCodeDetectionResult]:
    """
    Process all PR diffs from a JSON file and detect LLM-generated code.

    Args:
        pr_data_path: Path to the JSON file containing PR data

    Returns:
        List of LLMCodeDetectionResult objects
    """
    if not pr_data_path.exists():
        logger.error(f"PR data file not found: {pr_data_path}")
        return []

    with open(pr_data_path, 'r', encoding='utf-8') as f:
        pr_data = json.load(f)

    results = []

    for pr in pr_data:
        pr_id = pr.get('pr_id', 'unknown')
        diffs = pr.get('diffs', [])

        for diff in diffs:
            file_path = diff.get('file_path', 'unknown')
            line_start = diff.get('line_start', 0)
            line_end = diff.get('line_end', 0)
            diff_content = diff.get('diff_content', '')

            if not diff_content:
                continue

            result = detect_llm_generated_code(
                diff_content=diff_content,
                pr_id=pr_id,
                file_path=file_path,
                line_start=line_start,
                line_end=line_end
            )
            results.append(result)
            logger.debug(f"Processed {pr_id}/{file_path}: confidence={result.confidence}")

    return results

def main():
    """Main entry point for T018."""
    logger.info("Starting T018: LLM Code Detection")

    paths = get_paths()
    ensure_directories()

    # Find the most recent raw PR data file
    raw_dir = paths['raw_data']
    pr_files = list(Path(raw_dir).glob('*.json'))

    if not pr_files:
        logger.error("No PR data files found in data/raw/. Please run T012 first.")
        return

    # Sort by modification time and take the most recent
    pr_files.sort(key=lambda x: x.stat().st_mtime, reverse=True)
    latest_pr_file = pr_files[0]

    logger.info(f"Processing PR data from: {latest_pr_file}")

    results = process_pr_diffs(latest_pr_file)

    if not results:
        logger.warning("No results generated from PR data.")
        # Still create an empty output file for downstream tasks
        output_path = paths['derived_data'] / 'llm_detections.json'
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump([], f, indent=2)
        logger.info(f"Wrote empty results to: {output_path}")
        return

    # Convert results to JSON-serializable format
    output_data = [result.to_dict() for result in results]

    # Write output
    output_path = paths['derived_data'] / 'llm_detections.json'
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(output_data, f, indent=2)

    logger.info(f"Wrote {len(results)} detection results to: {output_path}")

    # Summary statistics
    high_confidence = sum(1 for r in results if r.confidence == ConfidenceLevel.HIGH)
    medium_confidence = sum(1 for r in results if r.confidence == ConfidenceLevel.MEDIUM)
    low_confidence = sum(1 for r in results if r.confidence == ConfidenceLevel.LOW)

    logger.info(f"Detection Summary: High={high_confidence}, Medium={medium_confidence}, Low={low_confidence}")

if __name__ == '__main__':
    main()
