"""
Split dataset analysis module.

Splits analysis data into "Human-Written" and "LLM-Generated" subsets
based on the llm_code_flag from T018 (detect_llm_code).
"""
import json
import logging
import sys
from pathlib import Path
from typing import Dict, List, Any, Tuple

from code.config.settings import get_paths, ensure_directories

# Configure logging
logger = logging.getLogger(__name__)

def load_llm_detections(input_path: Path) -> List[Dict[str, Any]]:
    """
    Load the LLM detections JSON file generated by T018.
    
    Args:
        input_path: Path to the llm_detections.json file.
        
    Returns:
        List of detection records.
        
    Raises:
        FileNotFoundError: If the input file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    with open(input_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
        
    if not isinstance(data, list):
        raise ValueError(f"Expected list of detections, got {type(data)}")
        
    return data

def split_by_llm_flag(detections: List[Dict[str, Any]]) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """
    Split detections into Human-Written and LLM-Generated subsets.
    
    Args:
        detections: List of detection records containing 'llm_code_flag'.
        
    Returns:
        Tuple of (human_written, llm_generated) lists.
        
    Raises:
        KeyError: If 'llm_code_flag' is missing from a record.
    """
    human_written = []
    llm_generated = []
    
    for record in detections:
        if 'llm_code_flag' not in record:
            raise KeyError(f"Record missing 'llm_code_flag': {record.get('pr_id', 'unknown')}")
        
        # llm_code_flag is boolean: True if LLM-generated, False if Human-written
        if record['llm_code_flag']:
            llm_generated.append(record)
        else:
            human_written.append(record)
            
    return human_written, llm_generated

def save_split_datasets(
    human_written: List[Dict[str, Any]],
    llm_generated: List[Dict[str, Any]],
    output_dir: Path
) -> Tuple[Path, Path]:
    """
    Save the split datasets to JSON files.
    
    Args:
        human_written: List of human-written PR detections.
        llm_generated: List of LLM-generated PR detections.
        output_dir: Directory to save the output files.
        
    Returns:
        Tuple of (human_path, llm_path) for the saved files.
    """
    ensure_directories([output_dir])
    
    human_path = output_dir / "human_written_prs.json"
    llm_path = output_dir / "llm_generated_prs.json"
    
    with open(human_path, 'w', encoding='utf-8') as f:
        json.dump(human_written, f, indent=2, ensure_ascii=False)
        
    with open(llm_path, 'w', encoding='utf-8') as f:
        json.dump(llm_generated, f, indent=2, ensure_ascii=False)
        
    logger.info(f"Saved {len(human_written)} human-written PRs to {human_path}")
    logger.info(f"Saved {len(llm_generated)} LLM-generated PRs to {llm_path}")
    
    return human_path, llm_path

def run_split_analysis(
    input_path: Path,
    output_dir: Path
) -> Dict[str, Any]:
    """
    Main analysis function: load, split, and save datasets.
    
    Args:
        input_path: Path to the input llm_detections.json.
        output_dir: Directory to save the split outputs.
        
    Returns:
        Dictionary containing split statistics and output paths.
    """
    logger.info(f"Loading detections from {input_path}")
    detections = load_llm_detections(input_path)
    logger.info(f"Loaded {len(detections)} total detections")
    
    logger.info("Splitting by llm_code_flag...")
    human_written, llm_generated = split_by_llm_flag(detections)
    
    logger.info(f"Split complete: {len(human_written)} human-written, {len(llm_generated)} LLM-generated")
    
    human_path, llm_path = save_split_datasets(human_written, llm_generated, output_dir)
    
    return {
        "total": len(detections),
        "human_written_count": len(human_written),
        "llm_generated_count": len(llm_generated),
        "human_written_path": str(human_path),
        "llm_generated_path": str(llm_path)
    }

def main():
    """
    Entry point for the split dataset script.
    
    Reads configuration from settings.py and processes the llm_detections.json
    file created by T018.
    """
    # Setup logging
    from code.src.utils.logger import get_logger
    logger = get_logger(__name__)
    
    try:
        paths = get_paths()
        input_file = paths["derived"] / "llm_detections.json"
        output_dir = paths["derived"]
        
        logger.info(f"Starting dataset split analysis")
        logger.info(f"Input: {input_file}")
        logger.info(f"Output directory: {output_dir}")
        
        result = run_split_analysis(input_file, output_dir)
        
        logger.info("Split analysis completed successfully")
        logger.info(f"Statistics: {json.dumps(result, indent=2)}")
        
        # Save summary stats
        stats_path = output_dir / "split_stats.json"
        with open(stats_path, 'w', encoding='utf-8') as f:
            json.dump(result, f, indent=2)
            
        logger.info(f"Statistics saved to {stats_path}")
        
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"Input file not found: {e}")
        logger.error("Ensure T018 has been run and data/derived/llm_detections.json exists.")
        return 1
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in input file: {e}")
        return 1
    except KeyError as e:
        logger.error(f"Missing required field in detection record: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during split analysis: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())
