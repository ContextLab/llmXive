"""
Split analysis data into "Human-Written" and "LLM-Generated" subsets.

This module implements T021: Split the analysis data based on the
`llm_code_flag` generated by T018 (detect_llm_code.py).

Dependencies:
    - T018: Must run before this task to generate `data/derived/llm_detections.json`.
"""

import json
import logging
import sys
from pathlib import Path
from typing import Dict, List, Any, Tuple

# Import project config and schema utilities
from code.config.settings import get_paths, ensure_directories
from code.src.detection.schema import LLMCodeDetectionResult

logger = logging.getLogger(__name__)


def load_llm_detections(input_path: Path) -> List[Dict[str, Any]]:
    """
    Load the LLM code detection results from the derived data file.

    Args:
        input_path: Path to `data/derived/llm_detections.json`.

    Returns:
        List of detection result dictionaries.

    Raises:
        FileNotFoundError: If the input file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    if not input_path.exists():
        raise FileNotFoundError(
            f"Input file not found: {input_path}. "
            "Ensure T018 (detect_llm_code.py) has been run successfully."
        )

    with open(input_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    if not isinstance(data, list):
        raise ValueError(
            f"Expected a list of detection results in {input_path}, "
            f"but got {type(data).__name__}."
        )

    return data


def split_by_llm_flag(
    detections: List[Dict[str, Any]]
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """
    Split the list of detections into two subsets based on `llm_code_flag`.

    Args:
        detections: List of detection result dictionaries.

    Returns:
        A tuple (human_written_subset, llm_generated_subset).
    """
    human_written = []
    llm_generated = []

    for item in detections:
        # The flag should be a boolean. If missing or None, treat as Human-Written
        # to be conservative, but log a warning.
        flag = item.get("llm_code_flag")

        if flag is None:
            logger.warning(
                f"Missing 'llm_code_flag' in detection for PR {item.get('pr_id', 'unknown')}. "
                "Assigning to 'Human-Written' subset by default."
            )
            human_written.append(item)
        elif flag is True:
            llm_generated.append(item)
        else:
            human_written.append(item)

    return human_written, llm_generated


def save_split_datasets(
    human_written: List[Dict[str, Any]],
    llm_generated: List[Dict[str, Any]],
    output_dir: Path
) -> Tuple[Path, Path]:
    """
    Save the split datasets to JSON files.

    Args:
        human_written: List of human-written PR detections.
        llm_generated: List of LLM-generated PR detections.
        output_dir: Directory to save the output files.

    Returns:
        Tuple of paths to the saved files.
    """
    ensure_directories(output_dir)

    human_path = output_dir / "human_written_subset.json"
    llm_path = output_dir / "llm_generated_subset.json"

    with open(human_path, 'w', encoding='utf-8') as f:
        json.dump(human_written, f, indent=2, ensure_ascii=False)

    with open(llm_path, 'w', encoding='utf-8') as f:
        json.dump(llm_generated, f, indent=2, ensure_ascii=False)

    logger.info(f"Saved human-written subset to: {human_path}")
    logger.info(f"Saved LLM-generated subset to: {llm_path}")

    return human_path, llm_path


def run_split_analysis(input_path: Path, output_dir: Path) -> Dict[str, Any]:
    """
    Main execution logic for splitting the dataset.

    Args:
        input_path: Path to the input `llm_detections.json`.
        output_dir: Directory for output files.

    Returns:
        Dictionary containing summary statistics and output paths.
    """
    logger.info(f"Loading LLM detections from: {input_path}")
    detections = load_llm_detections(input_path)
    total_count = len(detections)
    logger.info(f"Loaded {total_count} detection records.")

    if total_count == 0:
        logger.warning("No detection records found. Output files will be empty lists.")

    logger.info("Splitting dataset based on 'llm_code_flag'...")
    human_subset, llm_subset = split_by_llm_flag(detections)

    logger.info(f"Split complete: {len(human_subset)} Human-Written, {len(llm_subset)} LLM-Generated.")

    logger.info("Saving split datasets...")
    human_path, llm_path = save_split_datasets(human_subset, llm_subset, output_dir)

    return {
        "total_input_records": total_count,
        "human_written_count": len(human_subset),
        "llm_generated_count": len(llm_subset),
        "human_written_output_path": str(human_path),
        "llm_generated_output_path": str(llm_path)
    }


def main():
    """
    Entry point for the script.
    """
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )

    paths = get_paths()
    input_file = paths["derived"] / "llm_detections.json"
    output_dir = paths["derived"]

    try:
        result = run_split_analysis(input_file, output_dir)
        logger.info("Split dataset analysis completed successfully.")
        logger.info(f"Summary: {result}")
        return 0
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        return 1
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in input file: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during split analysis: {e}", exc_info=True)
        return 1


if __name__ == "__main__":
    sys.exit(main())
