class TestDetectLlmCode:
    """Test suite for LLM code detection functions."""

    def test_calculate_confidence_zero_matches(self):
        """Test confidence calculation with no matches."""
        matches = {'comment_patterns': [], 'structure_patterns': [], 'token_patterns': []}
        result = calculate_confidence(matches)
        assert result == ConfidenceLevel.LOW

    def test_calculate_confidence_single_match(self):
        """Test confidence calculation with one match."""
        matches = {'comment_patterns': ['Generated by'], 'structure_patterns': [], 'token_patterns': []}
        result = calculate_confidence(matches)
        assert result == ConfidenceLevel.LOW

    def test_calculate_confidence_two_matches(self):
        """Test confidence calculation with two matches."""
        matches = {
            'comment_patterns': ['Generated by'],
            'structure_patterns': ['def process_data'],
            'token_patterns': []
        }
        result = calculate_confidence(matches)
        assert result == ConfidenceLevel.MEDIUM

    def test_calculate_confidence_three_matches(self):
        """Test confidence calculation with three matches."""
        matches = {
            'comment_patterns': ['Generated by'],
            'structure_patterns': ['def process_data'],
            'token_patterns': ['Here is the code']
        }
        result = calculate_confidence(matches)
        assert result == ConfidenceLevel.HIGH

    def test_detect_llm_generated_code_with_ai_comment(self):
        """Test detection of code with AI-generated comment."""
        diff_content = "# Generated by Copilot\nprint('hello')\n"
        result = detect_llm_generated_code(diff_content, 'PR-123', 'test.py', 1, 2)

        assert result.pr_id == 'PR-123'
        assert result.file_path == 'test.py'
        assert result.line_start == 1
        assert result.line_end == 2
        assert result.is_llm_generated == True
        assert result.confidence == ConfidenceLevel.MEDIUM
        assert len(result.matches['comment_patterns']) > 0

    def test_detect_llm_generated_code_without_ai_indicators(self):
        """Test detection of normal human-written code."""
        diff_content = "def calculate_sum(a, b):\n    return a + b\n"
        result = detect_llm_generated_code(diff_content, 'PR-456', 'utils.py', 1, 2)

        assert result.is_llm_generated == False
        assert result.confidence == ConfidenceLevel.LOW

    def test_detect_llm_generated_code_with_multiple_indicators(self):
        """Test detection with multiple LLM indicators."""
        diff_content = """
        # Generated by AI
        # Here is the code you requested
        def process_data(data):
            return data
        """
        result = detect_llm_generated_code(diff_content, 'PR-789', 'processor.py', 1, 5)

        assert result.is_llm_generated == True
        assert result.confidence == ConfidenceLevel.HIGH

    def test_detect_llm_generated_code_with_copilot_comment(self):
        """Test detection of Copilot-generated comment."""
        diff_content = "# Copilot: Here's a function to add numbers\n"
        result = detect_llm_generated_code(diff_content, 'PR-101', 'math.py', 1, 1)

        assert result.is_llm_generated == True
        assert len(result.matches['comment_patterns']) > 0

class TestProcessPrDiffs:
    """Test suite for PR diff processing."""

    def test_process_pr_diffs_empty_file(self):
        """Test processing an empty PR data file."""
        with tempfile.NamedTemporaryFile(mode='w', suffix='.json', delete=False) as f:
            json.dump([], f)
            temp_path = Path(f.name)

        try:
            results = process_pr_diffs(temp_path)
            assert results == []
        finally:
            temp_path.unlink()

    def test_process_pr_diffs_with_valid_data(self):
        """Test processing PR data with valid diffs."""
        pr_data = [
            {
                'pr_id': 'PR-123',
                'diffs': [
                    {
                        'file_path': 'test.py',
                        'line_start': 1,
                        'line_end': 5,
                        'diff_content': "# Generated by AI\nprint('hello')"
                    }
                ]
            }
        ]

        with tempfile.NamedTemporaryFile(mode='w', suffix='.json', delete=False) as f:
            json.dump(pr_data, f)
            temp_path = Path(f.name)

        try:
            results = process_pr_diffs(temp_path)
            assert len(results) == 1
            assert results[0].pr_id == 'PR-123'
            assert results[0].is_llm_generated == True
        finally:
            temp_path.unlink()

    def test_process_pr_diffs_missing_file(self):
        """Test processing when file doesn't exist."""
        results = process_pr_diffs(Path('/nonexistent/file.json'))
        assert results == []

class TestLLMCodeDetectionResult:
    """Test suite for LLMCodeDetectionResult schema."""

    def test_llm_detection_result_creation(self):
        """Test creating an LLMCodeDetectionResult."""
        result = LLMCodeDetectionResult(
            pr_id='PR-123',
            file_path='test.py',
            line_start=1,
            line_end=5,
            is_llm_generated=True,
            confidence=ConfidenceLevel.HIGH,
            matches={'comment_patterns': ['Generated by AI']}
        )

        assert result.pr_id == 'PR-123'
        assert result.is_llm_generated == True
        assert result.confidence == ConfidenceLevel.HIGH

    def test_llm_detection_result_json_roundtrip(self):
        """Test JSON serialization and deserialization."""
        original = LLMCodeDetectionResult(
            pr_id='PR-123',
            file_path='test.py',
            line_start=1,
            line_end=5,
            is_llm_generated=True,
            confidence=ConfidenceLevel.MEDIUM,
            matches={'comment_patterns': ['Generated by AI']}
        )

        json_str = original.to_json()
        reconstructed = LLMCodeDetectionResult.from_json(json_str)

        assert reconstructed.pr_id == original.pr_id
        assert reconstructed.file_path == original.file_path
        assert reconstructed.is_llm_generated == original.is_llm_generated
        assert reconstructed.confidence == original.confidence
        assert reconstructed.matches == original.matches

