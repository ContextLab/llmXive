def validate_result_structure(results: Dict[str, Any], schema_path: Optional[str] = None) -> bool:
    """
    Validates that the results dictionary contains all required keys
    as defined in contracts/analysis_output.schema.yaml.

    Required keys:
    - correlation_coefficient
    - p_value
    - adjusted_p_value
    - confidence_interval
    - r_squared
    - delta_r_squared
    """
    required_keys = [
        'correlation_coefficient',
        'p_value',
        'adjusted_p_value',
        'confidence_interval',
        'r_squared',
        'delta_r_squared'
    ]

    missing_keys = [key for key in required_keys if key not in results]
    if missing_keys:
        logger.error(f"Missing required keys in results: {missing_keys}")
        return False

    # Validate types
    numeric_keys = ['correlation_coefficient', 'p_value', 'adjusted_p_value', 'r_squared', 'delta_r_squared']
    for key in numeric_keys:
        val = results.get(key)
        if val is None or (isinstance(val, float) and np.isnan(val)):
            logger.warning(f"Key '{key}' is None or NaN in results. This may indicate a failed calculation.")
        elif not isinstance(val, (int, float)):
            logger.error(f"Key '{key}' has invalid type: {type(val).__name__}. Expected numeric.")
            return False

    ci = results.get('confidence_interval')
    if not isinstance(ci, (list, tuple)) or len(ci) != 2:
        logger.error(f"confidence_interval must be a list/tuple of 2 floats. Got: {type(ci).__name__}")
        return False

    return True

def save_correlation_results(
    results: Dict[str, Any],
    output_filename: str = "correlation_results.json",
    schema_path: Optional[str] = None
) -> Path:
    """
    Saves the correlation results dictionary to a JSON file in the results directory.
    Validates the structure against the schema before saving.

    Args:
        results: Dictionary containing correlation analysis results.
        output_filename: Name of the output file.
        schema_path: Optional path to the schema file for validation.

    Returns:
        Path to the saved file.

    Raises:
        ValueError: If the results structure is invalid.
    """
    results_dir = get_results_dir()
    output_path = results_dir / output_filename

    if not validate_result_structure(results, schema_path):
        raise ValueError("Results structure validation failed. Check logs for details.")

    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)

    logger.info(f"Saved correlation results to {output_path}")
    return output_path

