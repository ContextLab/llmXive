import os
import pandas as pd
from pathlib import Path
import logging
import sys
from code.src.utils.config import SEED, DATA_DIR, RAW_DATA_DIR, LOGS_DIR, ensure_directories, set_global_seed
from code.src.utils.validation import load_schema, validate_dataframe_against_schema

# Configure logger
logger = logging.getLogger(__name__)

def load_microbiome_data(file_path: Path) -> pd.DataFrame:
    """
    Load 16S rRNA sequencing data (or derived metrics) from a CSV file.
    
    In this synthetic pipeline, the 'microbiome' data is pre-aggregated 
    (Shannon, Simpson, Chao1) in the single source CSV generated by T008.
    This function loads that data.
    """
    logger.info(f"Loading microbiome data from {file_path}")
    if not file_path.exists():
        raise FileNotFoundError(f"Microbiome data file not found: {file_path}")
    
    df = pd.read_csv(file_path)
    logger.info(f"Loaded {len(df)} rows of microbiome data")
    return df

def load_cognitive_data(file_path: Path) -> pd.DataFrame:
    """
    Load linked cognitive assessment data from a CSV file.
    
    In this synthetic pipeline, cognitive scores are in the same CSV 
    generated by T008. This function loads that data.
    """
    logger.info(f"Loading cognitive data from {file_path}")
    if not file_path.exists():
        raise FileNotFoundError(f"Cognitive data file not found: {file_path}")
    
    df = pd.read_csv(file_path)
    logger.info(f"Loaded {len(df)} rows of cognitive data")
    return df

def merge_datasets(microbiome_df: pd.DataFrame, cognitive_df: pd.DataFrame, key: str = "participant_id") -> pd.DataFrame:
    """
    Merge microbiome and cognitive datasets on the participant ID.
    
    Args:
        microbiome_df: DataFrame containing microbiome metrics.
        cognitive_df: DataFrame containing cognitive scores and demographics.
        key: The column name to merge on (default: 'participant_id').
    
    Returns:
        Merged DataFrame.
    
    Raises:
        ValueError: If the merge results in fewer rows than expected or key is missing.
    """
    if key not in microbiome_df.columns:
        raise ValueError(f"Key '{key}' not found in microbiome data")
    if key not in cognitive_df.columns:
        raise ValueError(f"Key '{key}' not found in cognitive data")
    
    # Since our synthetic generator produces a single CSV, we expect an inner join
    # to result in the same number of rows, but we handle general cases.
    merged_df = pd.merge(microbiome_df, cognitive_df, on=key, how='inner')
    
    if len(merged_df) == 0:
        raise ValueError("Merge resulted in an empty dataset. Check for mismatched IDs.")
    
    logger.info(f"Merged datasets: {len(merged_df)} rows (key: {key})")
    return merged_df

def ingest_synthetic_cohort(raw_data_path: Path = None) -> pd.DataFrame:
    """
    Ingest the synthetic cohort from the raw data directory.
    
    This function orchestrates loading the synthetic data generated by T008,
    which contains both microbiome and cognitive data in a single file.
    
    Args:
        raw_data_path: Path to the raw data file. Defaults to DATA_DIR/raw/synthetic_data.csv.
    
    Returns:
        DataFrame containing the merged cohort.
    """
    if raw_data_path is None:
        raw_data_path = RAW_DATA_DIR / "synthetic_data.csv"
    
    logger.info(f"Starting ingestion of synthetic cohort from {raw_data_path}")
    
    # Load the single source of truth for synthetic data
    # T008 generates this file with all required columns
    df = pd.read_csv(raw_data_path)
    
    logger.info(f"Ingested {len(df)} participants")
    return df

def save_merged_cohort(df: pd.DataFrame, output_path: Path) -> None:
    """
    Save the merged cohort to a CSV file.
    
    Args:
        df: The merged DataFrame.
        output_path: Path to save the CSV.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    logger.info(f"Saved merged cohort to {output_path}")

def main():
    """
    Main entry point for the ingestion task.
    Loads synthetic data, validates it against the schema, and saves the processed cohort.
    """
    set_global_seed(SEED)
    ensure_directories()
    
    # Setup logging for this module if not already done
    if not logger.handlers:
        handler = logging.StreamHandler(sys.stdout)
        handler.setLevel(logging.INFO)
        formatter = logging.Formatter('%(asctime)s - %(name)s - %(levelname)s - %(message)s')
        handler.setFormatter(formatter)
        logger.addHandler(handler)
    
    try:
        # 1. Ingest data
        # T008 produces data/raw/synthetic_data.csv
        raw_path = RAW_DATA_DIR / "synthetic_data.csv"
        
        if not raw_path.exists():
            logger.error(f"Raw data file not found at {raw_path}. Please run T008 first.")
            sys.exit(1)
        
        logger.info(f"Loading data from {raw_path}")
        cohort_df = ingest_synthetic_cohort(raw_path)
        
        # 2. Validate against schema
        schema_path = Path("contracts/dataset.schema.yaml")
        if schema_path.exists():
            logger.info(f"Validating against schema: {schema_path}")
            schema = load_schema(schema_path)
            validate_dataframe_against_schema(cohort_df, schema)
            logger.info("Schema validation passed.")
        else:
            logger.warning(f"Schema file not found at {schema_path}. Skipping validation.")
        
        # 3. Save the merged cohort to the processed directory
        # T011 will read from here, but T010 establishes the ingestion artifact
        processed_path = Path("data/processed/ingested_cohort.csv")
        save_merged_cohort(cohort_df, processed_path)
        
        logger.info("Ingestion task completed successfully.")
        return cohort_df
        
    except Exception as e:
        logger.error(f"Ingestion failed: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()
