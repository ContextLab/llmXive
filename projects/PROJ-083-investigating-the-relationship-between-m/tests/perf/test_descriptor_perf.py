"""
Performance test for topological descriptor calculation.

Task: T018 [US2] Performance test ensuring full filtered EAS set calculation < 15 mins
on 2-core runner.

This test loads the filtered EAS dataset (generated by T015) and measures the time
required to calculate Wiener, Balaban, and Zagreb indices for all records.
The test fails if the total time exceeds 15 minutes (900 seconds).
"""
import os
import sys
import time
import logging
import unittest
from pathlib import Path

# Add project root to path to allow imports
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from code.config import get_config
from code.utils.logger import setup_logger
from code.export_descriptors import load_eas_reactions
from code.descriptors import (
    is_connected,
    calculate_wiener_index,
    calculate_balaban_index,
    calculate_zagreb_index
)

# Setup logging for the test
logger = setup_logger("perf_test", level=logging.INFO)

# Configuration
MAX_TIME_SECONDS = 15 * 60  # 15 minutes
EAS_DATA_PATH = Path("data/processed/eas_reactions.csv")


class TestDescriptorPerformance(unittest.TestCase):
    """Performance test class for descriptor calculation."""

    def setUp(self):
        """Load the dataset before the test."""
        if not EAS_DATA_PATH.exists():
            self.skipTest(
                f"Dataset {EAS_DATA_PATH} not found. "
                "Please ensure T015 (Write filtered dataset) has been completed."
            )
        
        logger.info(f"Loading dataset from {EAS_DATA_PATH}...")
        self.df = load_eas_reactions(EAS_DATA_PATH)
        logger.info(f"Loaded {len(self.df)} records.")

    def test_descriptor_calculation_time(self):
        """
        Test that calculating descriptors for the full EAS set takes less than 15 minutes.
        
        This ensures the pipeline is efficient enough for the research scope.
        """
        logger.info("Starting descriptor calculation performance test...")
        start_time = time.time()
        
        processed_count = 0
        disconnected_count = 0

        for _, row in self.df.iterrows():
            smiles = row['smiles']
            
            # Parse and check connectivity
            from rdkit import Chem
            mol = Chem.MolFromSmiles(smiles)
            
            if mol is None:
                # Skip malformed SMILES (should be rare if T012 worked)
                continue
            
            if not is_connected(mol):
                disconnected_count += 1
                continue

            # Calculate indices
            # These functions are optimized and should be fast per molecule
            try:
                _ = calculate_wiener_index(mol)
                _ = calculate_balaban_index(mol)
                _ = calculate_zagreb_index(mol)
                processed_count += 1
            except Exception as e:
                logger.warning(f"Error calculating descriptors for {smiles}: {e}")
                continue

        end_time = time.time()
        elapsed_time = end_time - start_time

        logger.info(f"Processed {processed_count} valid molecules.")
        logger.info(f"Skipped {disconnected_count} disconnected graphs.")
        logger.info(f"Total time: {elapsed_time:.2f} seconds ({elapsed_time/60:.2f} minutes)")

        # Assertion
        self.assertLess(
            elapsed_time, 
            MAX_TIME_SECONDS, 
            f"Descriptor calculation took {elapsed_time:.2f}s, exceeding the limit of {MAX_TIME_SECONDS}s."
        )

        logger.info("Performance test PASSED.")


if __name__ == "__main__":
    unittest.main(verbosity=2)