"""
T024b: Document Override of FR-005 by Constitution Principle VII.

This script reads the existing training report (generated by T023/T024),
explicitly documents the statistical test override, and writes the updated
report to data/artifacts/training_report.json.

Override Details:
- Original Spec FR-005: Wilcoxon signed-rank test.
- Constitution Principle VII: Paired t-test (overrides FR-005).
"""

import json
import os
import sys
from pathlib import Path

# Add parent directory to path to allow imports if needed, though this script is standalone
# relative to code/
code_dir = Path(__file__).parent
project_root = code_dir.parent
artifacts_dir = project_root / "data" / "artifacts"
report_path = artifacts_dir / "training_report.json"

def main():
    if not artifacts_dir.exists():
        artifacts_dir.mkdir(parents=True, exist_ok=True)

    if not report_path.exists():
        print(f"ERROR: {report_path} not found. Run T023/T024 first.", file=sys.stderr)
        sys.exit(1)

    try:
        with open(report_path, "r", encoding="utf-8") as f:
            report = json.load(f)
    except json.JSONDecodeError as e:
        print(f"ERROR: Invalid JSON in {report_path}: {e}", file=sys.stderr)
        sys.exit(1)

    # Document the override explicitly
    override_doc = {
        "statistical_test_override": {
            "original_spec": "FR-005",
            "original_method": "Wilcoxon signed-rank test",
            "overriding_principle": "Constitution Principle VII",
            "new_method": "Paired t-test",
            "reason": "Constitution Principle VII takes precedence over Spec FR-005 as per project governance.",
            "applied": True
        }
    }

    # Merge into report, ensuring we don't overwrite existing valid data
    # but explicitly set the override section.
    report.update(override_doc)

    # Write back
    with open(report_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)

    print(f"Successfully updated {report_path} with statistical test override documentation.")

if __name__ == "__main__":
    main()