"""
Finalize processed dataset: write solubility_features.csv and generate checksum.
"""
import os
import sys
import json
import hashlib
from pathlib import Path

# Add project root to path to allow relative imports if run as script
project_root = Path(__file__).resolve().parent
sys.path.insert(0, str(project_root))

from utils.constants import DATA_DIR
from utils.checksums import generate_checksums

# Define paths
INPUT_FILE = DATA_DIR / "processed" / "solubility_features.csv"
OUTPUT_FILE = DATA_DIR / "processed" / "solubility_features.csv"
CHECKSUM_FILE = DATA_DIR / ".checksums.json"

def write_final_dataset():
    """
    Reads the processed features, ensures the directory exists,
    writes the final CSV, and generates a checksum.
    """
    if not INPUT_FILE.exists():
        raise FileNotFoundError(f"Input file not found: {INPUT_FILE}. "
                                "Ensure T014-T016 have completed successfully.")
    
    import pandas as pd
    
    # Load the features generated by previous steps
    df = pd.read_csv(INPUT_FILE)
    
    # Ensure output directory exists
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    
    # Write the final dataset
    df.to_csv(OUTPUT_FILE, index=False)
    print(f"Successfully wrote {len(df)} rows to {OUTPUT_FILE}")
    
    return OUTPUT_FILE

def main():
    try:
        output_path = write_final_dataset()
        
        # Generate checksum for the new file
        checksums = generate_checksums([output_path])
        
        # Update or create the checksums file
        if CHECKSUM_FILE.exists():
            with open(CHECKSUM_FILE, 'r') as f:
                existing_checksums = json.load(f)
        else:
            existing_checksums = {}
        
        existing_checksums.update(checksums)
        
        with open(CHECKSUM_FILE, 'w') as f:
            json.dump(existing_checksums, f, indent=2)
        
        print(f"Checksum updated: {CHECKSUM_FILE}")
        
    except Exception as e:
        print(f"Error finalizing dataset: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()