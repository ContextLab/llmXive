def apply_fdr_correction(p_values: List[float], alpha: float = 0.05) -> Tuple[List[bool], List[float]]:
    """Apply Benjamini-Hochberg FDR correction."""
    n = len(p_values)
    if n == 0:
        return [], []
    sorted_indices = np.argsort(p_values)
    sorted_p = np.array(p_values)[sorted_indices]
    ranks = np.arange(1, n + 1)
    thresholds = (ranks / n) * alpha
    # Find the largest k where p_k <= threshold_k
    # BH step-up procedure
    reject = np.zeros(n, dtype=bool)
    for i in range(n - 1, -1, -1):
        if sorted_p[i] <= thresholds[i]:
            reject[:i+1] = True
            break
    # Map back to original order
    original_order_reject = np.zeros(n, dtype=bool)
    original_order_reject[sorted_indices] = reject
    return original_order_reject.tolist(), sorted_p.tolist()

