def run_paired_ttest_fold_differences(entropy_model_type: str = "entropy_only",
                                      connectivity_model_type: str = "connectivity_baseline",
                                      input_dir: str = "data/derived",
                                      output_path: str = "data/derived/paired_ttest_results.json") -> Dict[str, Any]:
    """
    Perform paired t-test on fold differences between Entropy and Connectivity models.
    
    This function loads per-fold Pearson r values for both models, aligns them by fold,
    computes the difference (Entropy - Connectivity), and performs a paired t-test.
    
    Args:
        entropy_model_type: Key for entropy model fold metrics file.
        connectivity_model_type: Key for connectivity model fold metrics file.
        input_dir: Directory containing fold metrics CSVs.
        output_path: Path to save the results JSON.
        
    Returns:
        Dictionary containing t-statistic, p-value, mean difference, and confidence interval.
    """
    logger = setup_logger("paired_ttest")
    logger.info(f"Loading fold metrics for {entropy_model_type} and {connectivity_model_type}")
    
    try:
        entropy_metrics = load_fold_metrics(entropy_model_type, input_dir)
        connectivity_metrics = load_fold_metrics(connectivity_model_type, input_dir)
    except FileNotFoundError as e:
        logger.error(str(e))
        raise
    
    # Ensure both have the 'fold' column to align
    if 'fold' not in entropy_metrics.columns or 'fold' not in connectivity_metrics.columns:
        raise ValueError("Fold metrics must contain a 'fold' column for alignment.")
    
    if 'pearson_r' not in entropy_metrics.columns or 'pearson_r' not in connectivity_metrics.columns:
        raise ValueError("Fold metrics must contain a 'pearson_r' column.")
    
    # Merge on fold to align the pairs
    merged = pd.merge(
        entropy_metrics[['fold', 'pearson_r']],
        connectivity_metrics[['fold', 'pearson_r']],
        on='fold',
        suffixes=('_entropy', '_connectivity')
    )
    
    if len(merged) == 0:
        raise ValueError("No matching folds found between the two model metric files.")
    
    r_entropy = merged['pearson_r_entropy'].values
    r_connectivity = merged['pearson_r_connectivity'].values
    
    # Calculate differences
    differences = r_entropy - r_connectivity
    mean_diff = np.mean(differences)
    
    # Perform paired t-test
    t_stat, p_value = stats.ttest_rel(r_entropy, r_connectivity)
    
    # Calculate 95% confidence interval for the mean difference
    # Using t-distribution for small samples
    n = len(differences)
    if n < 2:
        logger.warning("Less than 2 folds available for CI calculation.")
        ci_lower, ci_upper = None, None
    else:
        se = stats.sem(differences)
        t_crit = stats.t.ppf(0.975, df=n-1)
        ci_lower = mean_diff - t_crit * se
        ci_upper = mean_diff + t_crit * se
    
    result = {
        "t_statistic": float(t_stat),
        "p_value": float(p_value),
        "mean_difference": float(mean_diff),
        "n_folds": int(n),
        "ci_95_lower": float(ci_lower) if ci_lower is not None else None,
        "ci_95_upper": float(ci_upper) if ci_upper is not None else None,
        "significant_at_0.05": bool(p_value < 0.05)
    }
    
    # Save to JSON
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(result, f, indent=2)
    
    logger.info(f"Paired t-test completed. p-value: {p_value:.4f}, mean diff: {mean_diff:.4f}")
    logger.info(f"Results saved to {output_path}")
    
    return result

