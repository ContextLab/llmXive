from pathlib import Path
from typing import Any, Dict, List

import yaml

# Add project root to path to allow imports if needed, though this test is mostly file-based
PROJECT_ROOT = Path(__file__).parent.parent.parent
SCHEMA_PATH = PROJECT_ROOT / "data" / "schemas" / "sensitivity_schema.yaml"
REPORT_PATH = PROJECT_ROOT / "results" / "reports" / "sensitivity_analysis.json"

# Fallback path if the task generated a JSON report instead of Markdown (common in data contracts)
# The schema defines the data structure, which is typically JSON.
# If the report is Markdown, we might need to parse it or check for an accompanying JSON.
# For this contract test, we assume the existence of a JSON representation or a JSON file
# generated by the sensitivity analysis logic (often `sensitivity_results.json` or similar).
# However, T030 generates `sensitivity_analysis.md`.
# Let's check if there is a corresponding JSON file or if we need to adapt.
# Based on standard practice, the "report" data structure is JSON, the "presentation" is Markdown.
# We will look for a JSON file that matches the schema.
# If T030 only produced MD, we might need to check the MD content or assume a JSON exists.
# Let's assume the sensitivity analysis script (T028/T029) produces a JSON data file
# or the report generation step produces a JSON intermediate.
# We will check for `results/reports/sensitivity_analysis.json` first.
# If not found, we check if the task description implies a JSON output.
# T028 outputs `data/processed/sensitivity_absolute.csv`.
# T030 outputs `results/reports/sensitivity_analysis.md`.
# The schema `sensitivity_schema.yaml` describes the *data* structure.
# We will check for a JSON file that represents this data.
# If no JSON file exists, we will attempt to load the schema and validate that the schema itself is valid.
# But the task is to validate the *report* against the schema.
# Let's assume the pipeline generates a JSON version of the report or we validate the schema file itself.
# Actually, T029/T030 logic likely produces the data structure.
# Let's check for `results/reports/sensitivity_analysis.json` as the canonical data artifact.
# If it doesn't exist, we might need to run the code or check if the schema is the target.
# Given the constraints, I will write a test that validates the *schema file* itself is valid YAML,
# and then attempts to validate a JSON report if it exists.
# If the report doesn't exist, the test should fail with a clear message.

def load_schema(schema_path: Path) -> Dict[str, Any]:
    """Load the YAML schema."""
    if not schema_path.exists():
        raise FileNotFoundError(f"Schema file not found: {schema_path}")
    with open(schema_path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)

def validate_structure(data: Dict[str, Any], schema: Dict[str, Any]) -> List[str]:
    """
    Simple validation of data against the schema structure.
    This is a basic contract test, not a full JSON Schema validator.
    """
    errors = []

    # Check required top-level keys
    required_keys = schema.get("required", [])
    for key in required_keys:
        if key not in data:
            errors.append(f"Missing required top-level key: {key}")

    if errors:
        return errors

    # Check 'metadata' structure
    if "metadata" in data:
        meta = data["metadata"]
        meta_required = schema["properties"]["metadata"].get("required", [])
        for key in meta_required:
            if key not in meta:
                errors.append(f"Missing required key in metadata: {key}")

    # Check 'thresholds' (array of numbers)
    if "thresholds" in data:
        if not isinstance(data["thresholds"], list):
            errors.append("'thresholds' must be a list")
        else:
            for i, t in enumerate(data["thresholds"]):
                if not isinstance(t, (int, float)):
                    errors.append(f"Threshold at index {i} is not a number: {t}")

    # Check 'success_rates' (array of objects)
    if "success_rates" in data:
        if not isinstance(data["success_rates"], list):
            errors.append("'success_rates' must be a list")
        else:
            sr_required = schema["properties"]["success_rates"]["items"].get("required", [])
            for i, item in enumerate(data["success_rates"]):
                if not isinstance(item, dict):
                    errors.append(f"Item at index {i} in success_rates is not an object")
                else:
                    for key in sr_required:
                        if key not in item:
                            errors.append(f"Missing key '{key}' in success_rates[{i}]")

    # Check 'corrected_p_values' (array of objects)
    if "corrected_p_values" in data:
        if not isinstance(data["corrected_p_values"], list):
            errors.append("'corrected_p_values' must be a list")
        else:
            cp_required = schema["properties"]["corrected_p_values"]["items"].get("required", [])
            for i, item in enumerate(data["corrected_p_values"]):
                if not isinstance(item, dict):
                    errors.append(f"Item at index {i} in corrected_p_values is not an object")
                else:
                    for key in cp_required:
                        if key not in item:
                            errors.append(f"Missing key '{key}' in corrected_p_values[{i}]")

    return errors

class TestSensitivityReportSchema(unittest.TestCase):
    """Contract test for sensitivity report schema."""

    def test_schema_file_exists(self):
        """Ensure the schema file exists."""
        self.assertTrue(SCHEMA_PATH.exists(), f"Schema file not found: {SCHEMA_PATH}")

    def test_schema_is_valid_yaml(self):
        """Ensure the schema file is valid YAML."""
        try:
            schema = load_schema(SCHEMA_PATH)
            self.assertIsInstance(schema, dict)
        except Exception as e:
            self.fail(f"Schema file is not valid YAML: {e}")

    def test_report_data_exists_and_matches_schema(self):
        """
        Validate the sensitivity report data against the schema.
        We look for a JSON report. If the pipeline only produced MD,
        we might need to check for a JSON intermediate or the MD content.
        For this test, we expect a JSON file at results/reports/sensitivity_analysis.json
        or a similar canonical location if the report generation step outputs JSON.
        If T030 only outputs MD, we assume the data structure is embedded or
        we check for a generated JSON file from the analysis step.
        Let's check for `results/reports/sensitivity_analysis.json`.
        If it doesn't exist, we check if the task requires a JSON output.
        T028 outputs CSV. T029 outputs corrected values. T030 outputs MD.
        The schema is for the *report*. The report is likely the JSON data structure
        that T030 consumes to generate the MD.
        If no JSON file exists, we cannot validate the data.
        We will check for `results/reports/sensitivity_analysis.json`.
        If it doesn't exist, we will try to find a JSON file in the results/reports directory.
        """
        # Try to find the JSON report
        report_file = REPORT_PATH
        if not report_file.exists():
            # Fallback: look for any JSON in results/reports that might be the report
            report_dir = PROJECT_ROOT / "results" / "reports"
            json_files = list(report_dir.glob("*.json"))
            # Filter for likely candidates
            candidates = [f for f in json_files if "sensitivity" in f.name.lower()]
            if candidates:
                report_file = candidates[0]
            else:
                self.fail(
                    f"Report file not found at {REPORT_PATH} and no sensitivity JSON found in {report_dir}. "
                    "The sensitivity analysis pipeline must generate a JSON report to validate against the schema."
                )

        # Load the report data
        with open(report_file, "r", encoding="utf-8") as f:
            try:
                report_data = json.load(f)
            except json.JSONDecodeError as e:
                self.fail(f"Report file {report_file} is not valid JSON: {e}")

        # Load the schema
        schema = load_schema(SCHEMA_PATH)

        # Validate
        errors = validate_structure(report_data, schema)
        self.assertEqual(len(errors), 0, f"Report data does not match schema:\n" + "\n".join(errors))

if __name__ == "__main__":
    unittest.main()