    def test_missing_required_field_fails(self):
        """
        Verify that missing a required field causes validation to fail.
        """
        invalid_output = {
            "model_type": "GCN",
            # Missing 'metrics' which is required
            "hyperparameters": {},
            "timestamp": "2023-10-27T10:00:00Z",
            "dataset_checksum": "abc123"
        }

        errors = self._validate_object_schema(invalid_output, self.schema)
        self.assertTrue(
            any("missing required field 'metrics'" in e for e in errors),
            "Expected error for missing 'metrics' field"
        )

