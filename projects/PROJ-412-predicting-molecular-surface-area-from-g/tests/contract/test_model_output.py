import yaml

# Add project root to path to allow imports if needed, though this test
# primarily relies on file I/O and schema validation.
PROJECT_ROOT = Path(__file__).parent.parent.parent
SCHEMA_PATH = PROJECT_ROOT / "data" / "schemas" / "model_schema.yaml"

class TestModelOutputSchema(unittest.TestCase):
    """
    Contract tests verifying model output artifacts against the schema.
    """

    @classmethod
    def setUpClass(cls):
        """Load the schema once for all tests."""
        if not SCHEMA_PATH.exists():
            raise FileNotFoundError(
                f"Schema file not found at {SCHEMA_PATH}. "
                "Ensure T005 has been completed."
            )
        with open(SCHEMA_PATH, "r", encoding="utf-8") as f:
            cls.schema = yaml.safe_load(f)

    def _validate_type(self, value: Any, expected_type: str, path: str) -> List[str]:
        """Helper to validate a value against a simple type string."""
        errors = []
        if expected_type == "string":
            if not isinstance(value, str):
                errors.append(f"{path}: expected string, got {type(value).__name__}")
        elif expected_type == "number":
            if not isinstance(value, (int, float)):
                errors.append(f"{path}: expected number, got {type(value).__name__}")
        elif expected_type == "integer":
            if not isinstance(value, int):
                errors.append(f"{path}: expected integer, got {type(value).__name__}")
        elif expected_type == "boolean":
            if not isinstance(value, bool):
                errors.append(f"{path}: expected boolean, got {type(value).__name__}")
        elif expected_type == "object":
            if not isinstance(value, dict):
                errors.append(f"{path}: expected object, got {type(value).__name__}")
        elif expected_type == "array":
            if not isinstance(value, list):
                errors.append(f"{path}: expected array, got {type(value).__name__}")
        return errors

    def _validate_enum(self, value: Any, allowed_values: List[str], path: str) -> List[str]:
        """Helper to validate enum values."""
        errors = []
        if value not in allowed_values:
            errors.append(
                f"{path}: value '{value}' not in allowed enum values: {allowed_values}"
            )
        return errors

    def _validate_object_schema(
        self, data: Dict[str, Any], schema: Dict[str, Any], path: str = ""
    ) -> List[str]:
        """
        Recursively validate a dictionary against a JSON Schema-like definition.
        """
        errors = []

        # Check required fields
        if "required" in schema:
            for field in schema["required"]:
                if field not in data:
                    errors.append(f"{path or 'root'}: missing required field '{field}'")

        # Check properties
        if "properties" in schema:
            for prop, prop_schema in schema["properties"].items():
                if prop in data:
                    value = data[prop]
                    current_path = f"{path}.{prop}" if path else prop

                    # Type check
                    if "type" in prop_schema:
                        errors.extend(
                            self._validate_type(value, prop_schema["type"], current_path)
                        )

                    # Enum check
                    if "enum" in prop_schema:
                        errors.extend(
                            self._validate_enum(
                                value, prop_schema["enum"], current_path
                            )
                        )

                    # Nested object check
                    if prop_schema.get("type") == "object" and isinstance(value, dict):
                        # If nested schema is defined, recurse
                        if "properties" in prop_schema or "required" in prop_schema:
                            errors.extend(
                                self._validate_object_schema(
                                    value, prop_schema, current_path
                                )
                            )
                        # Check nested required fields if present
                        if "required" in prop_schema:
                            for field in prop_schema["required"]:
                                if field not in value:
                                    errors.append(
                                        f"{current_path}: missing required field '{field}'"
                                    )

        # Check additionalProperties restriction if defined
        if schema.get("additionalProperties") is False:
            allowed_keys = set(schema.get("properties", {}).keys())
            for key in data.keys():
                if key not in allowed_keys:
                    errors.append(
                        f"{path or 'root'}: additional property '{key}' not allowed"
                    )

        return errors

    def test_schema_structure_valid(self):
        """
        Verify the loaded schema itself has the expected structure.
        """
        self.assertIn("type", self.schema)
        self.assertEqual(self.schema["type"], "object")
        self.assertIn("required", self.schema)
        self.assertIn("properties", self.schema)

