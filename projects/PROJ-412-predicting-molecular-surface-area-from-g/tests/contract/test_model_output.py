"""
Contract test for model output schema (T019).

Validates that model output artifacts conform to the schema defined in
`data/schemas/model_schema.yaml` (generated by T005).

This test ensures that any model output (GCN, Baseline, Oracle) produced
by the pipeline strictly adheres to the required structure, types, and
allowed enum values.
"""
import json
