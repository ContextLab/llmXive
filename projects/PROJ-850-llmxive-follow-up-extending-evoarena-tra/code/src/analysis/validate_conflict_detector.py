"""
Validation script for the Conflict Detector (US1).

Runs the conflict detector on the synthetic dataset generated by T005.
Calculates Precision, Recall, and F1-score against ground truth.
Confirms the >= 80% baseline requirement.
"""
import json
import os
import sys
import csv
from pathlib import Path
from typing import List, Dict, Any, Tuple

# Add project root to path if running as script
if "code" in sys.path[0]:
    sys.path.insert(0, str(Path(sys.path[0]).parent))
elif "src" in sys.path[0]:
    sys.path.insert(0, str(Path(sys.path[0]).parent.parent))

from src.heuristics.conflict_detector import ConflictDetector
from src.utils.logging import get_logger
from src.utils.seeding import set_deterministic_seed

logger = get_logger(__name__)

def load_synthetic_pairs(filepath: str) -> List[Dict[str, Any]]:
    """Load the synthetic pairs generated by T005."""
    path = Path(filepath)
    if not path.exists():
        raise FileNotFoundError(f"Synthetic pairs file not found: {filepath}")
    
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    if not isinstance(data, list):
        raise ValueError("Expected JSON list of pairs")
    
    return data

def calculate_metrics(predictions: List[bool], ground_truth: List[bool]) -> Dict[str, float]:
    """Calculate Precision, Recall, F1, and Accuracy."""
    if len(predictions) != len(ground_truth):
        raise ValueError("Predictions and ground truth must be same length")
    
    tp = 0
    fp = 0
    tn = 0
    fn = 0

    for pred, truth in zip(predictions, ground_truth):
        if truth and pred:
            tp += 1
        elif truth and not pred:
            fn += 1
        elif not truth and pred:
            fp += 1
        else:
            tn += 1

    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0.0
    accuracy = (tp + tn) / len(predictions) if len(predictions) > 0 else 0.0

    return {
        "precision": precision,
        "recall": recall,
        "f1_score": f1,
        "accuracy": accuracy,
        "true_positives": tp,
        "false_positives": fp,
        "true_negatives": tn,
        "false_negatives": fn,
        "total_samples": len(predictions)
    }

def run_validation(
    data_path: str,
    output_path: str,
    threshold: float = 0.90,
    model_name: str = "distilbert-base-uncased"
) -> Dict[str, Any]:
    """
    Run the conflict detector on synthetic data and validate metrics.
    
    Args:
        data_path: Path to synthetic_pairs.json
        output_path: Path to write validation results CSV
        threshold: Confidence threshold for conflict classification
        model_name: HuggingFace model name to use
    
    Returns:
        Dictionary containing metrics and status
    """
    set_deterministic_seed(42)
    logger.info(f"Loading synthetic data from {data_path}")
    pairs = load_synthetic_pairs(data_path)
    logger.info(f"Loaded {len(pairs)} pairs")

    logger.info(f"Initializing ConflictDetector with {model_name}, threshold={threshold}")
    detector = ConflictDetector(model_name=model_name, threshold=threshold)

    predictions = []
    ground_truth = []
    details = []

    logger.info("Running inference on pairs...")
    for i, pair in enumerate(pairs):
        patch_a = pair.get("patch_a", "")
        patch_b = pair.get("patch_b", "")
        is_contradiction = pair.get("is_contradiction", False)

        # Run detector
        result = detector.detect_conflict(patch_a, patch_b)
        pred_label = result["is_conflict"]
        
        predictions.append(pred_label)
        ground_truth.append(is_contradiction)
        
        details.append({
            "index": i,
            "is_contradiction_gt": is_contradiction,
            "predicted_conflict": pred_label,
            "confidence": result.get("confidence", 0.0)
        })

        if (i + 1) % 50 == 0:
            logger.info(f"Processed {i + 1}/{len(pairs)} pairs")

    metrics = calculate_metrics(predictions, ground_truth)
    
    # Determine pass/fail status
    # Requirement: Precision AND Recall >= 80%
    passed = metrics["precision"] >= 0.80 and metrics["recall"] >= 0.80
    metrics["baseline_met"] = passed
    metrics["threshold_used"] = threshold
    metrics["model_used"] = model_name

    # Write detailed results to CSV
    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_file, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=details[0].keys() if details else [])
        writer.writeheader()
        writer.writerows(details)

    logger.info(f"Validation results written to {output_path}")
    logger.info(f"Precision: {metrics['precision']:.4f}, Recall: {metrics['recall']:.4f}, F1: {metrics['f1_score']:.4f}")
    
    if passed:
        logger.info("SUCCESS: Baseline requirement (>=80% Precision & Recall) MET.")
    else:
        logger.warning(f"FAILURE: Baseline requirement NOT MET. Precision={metrics['precision']:.2f}, Recall={metrics['recall']:.2f}")

    return metrics

def save_results(metrics: Dict[str, Any], report_path: str):
    """Save a summary report."""
    report_file = Path(report_path)
    report_file.parent.mkdir(parents=True, exist_ok=True)
    
    with open(report_file, 'w', encoding='utf-8') as f:
        f.write("# Conflict Detector Validation Report\n\n")
        f.write(f"## Summary\n")
        f.write(f"- **Baseline Met**: {'YES' if metrics.get('baseline_met') else 'NO'}\n")
        f.write(f"- **Threshold**: {metrics.get('threshold_used', 'N/A')}\n")
        f.write(f"- **Model**: {metrics.get('model_used', 'N/A')}\n\n")
        f.write("## Metrics\n")
        f.write(f"- Precision: {metrics['precision']:.4f}\n")
        f.write(f"- Recall: {metrics['recall']:.4f}\n")
        f.write(f"- F1 Score: {metrics['f1_score']:.4f}\n")
        f.write(f"- Accuracy: {metrics['accuracy']:.4f}\n")
        f.write(f"- Total Samples: {metrics['total_samples']}\n\n")
        f.write("## Confusion Matrix\n")
        f.write(f"- True Positives: {metrics['true_positives']}\n")
        f.write(f"- False Positives: {metrics['false_positives']}\n")
        f.write(f"- True Negatives: {metrics['true_negatives']}\n")
        f.write(f"- False Negatives: {metrics['false_negatives']}\n")

def main():
    """Entry point for the validation script."""
    # Default paths relative to project root
    project_root = Path(__file__).resolve().parent.parent.parent.parent
    data_path = project_root / "data" / "raw" / "synthetic_pairs.json"
    output_csv = project_root / "data" / "processed" / "validation_results.csv"
    report_md = project_root / "data" / "processed" / "validation_report.md"

    # Allow override via environment or args if needed, but keep defaults for CI
    if len(sys.argv) > 1:
        data_path = Path(sys.argv[1])
    if len(sys.argv) > 2:
        output_csv = Path(sys.argv[2])
    if len(sys.argv) > 3:
        report_md = Path(sys.argv[3])

    logger.info(f"Starting validation. Data: {data_path}, Output: {output_csv}")

    try:
        metrics = run_validation(
            data_path=str(data_path),
            output_path=str(output_csv),
            threshold=0.90,
            model_name="distilbert-base-uncased"
        )
        
        save_results(metrics, str(report_md))
        
        # Exit with error code if baseline not met to fail CI
        if not metrics["baseline_met"]:
            logger.error("Validation failed: Baseline metrics not met.")
            sys.exit(1)
        
        logger.info("Validation completed successfully.")
        sys.exit(0)

    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Validation failed with error: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)

if __name__ == "__main__":
    main()
