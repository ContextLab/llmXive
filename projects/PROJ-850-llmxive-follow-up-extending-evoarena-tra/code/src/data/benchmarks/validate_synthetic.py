"""
Synthetic Validation Gate for T006b.

This script validates the synthetic dataset (generated by T006-SYNTH) against
the real dataset (if available from T006) to ensure distribution similarity.

It calculates:
1. Task type distribution (e.g., file edit vs. command run)
2. Length distribution (token/char count of instructions)
3. Vocabulary overlap (Jaccard similarity of unique tokens)

Gate Logic:
- If real data exists: Compare distributions. Fail if KL-divergence or 
  statistical distance exceeds thresholds (defined in constants).
- If real data missing: Pass (synthetic is the only source).

Output:
- Prints validation report to stdout.
- Writes detailed metrics to `data/processed/synthetic_validation_report.json`.
- Exits with code 0 on PASS, 1 on FAIL.
"""

import json
import os
import sys
import math
from pathlib import Path
from typing import Dict, List, Any, Optional
from collections import Counter
import random

# Add project root to path for imports if running as script
PROJECT_ROOT = Path(__file__).parent.parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.utils.seeding import set_deterministic_seed

# Constants
RANDOM_SEED = 42
REAL_DATA_PATH = PROJECT_ROOT / "data" / "raw" / "terminal_bench_evo.jsonl"
SYNTHETIC_DATA_PATH = PROJECT_ROOT / "data" / "raw" / "terminal_bench_evo_synthetic.jsonl"
OUTPUT_REPORT_PATH = PROJECT_ROOT / "data" / "processed" / "synthetic_validation_report.json"

# Thresholds for similarity
MAX_KL_DIVergence = 0.5  # Max allowed KL divergence for task type distribution
MIN_VOCAB_OVERLAP = 0.6  # Minimum Jaccard similarity for vocabulary

def set_seed():
    set_deterministic_seed(RANDOM_SEED)

def load_jsonl(path: Path) -> List[Dict[str, Any]]:
    """Load a JSONL file into a list of dictionaries."""
    if not path.exists():
        return []
    
    data = []
    with open(path, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f):
            line = line.strip()
            if not line:
                continue
            try:
                data.append(json.loads(line))
            except json.JSONDecodeError as e:
                print(f"Warning: Skipping malformed JSON at line {line_num} in {path}: {e}")
    return data

def extract_features(task: Dict[str, Any]) -> Dict[str, Any]:
    """Extract simple features from a task for distribution comparison."""
    instruction = task.get("instruction", "")
    commands = task.get("commands", [])
    
    # Feature 1: Instruction Length (character count)
    length = len(instruction)
    
    # Feature 2: Task Type (heuristic: if 'file' in instruction, else 'command')
    # This is a simplified heuristic for distribution checking
    task_type = "command"
    if isinstance(commands, list) and len(commands) > 0:
        # Heuristic: check if commands look like file operations
        first_cmd = str(commands[0]).lower()
        if any(op in first_cmd for op in ["edit", "write", "read", "cat", "vim", "nano"]):
            task_type = "file_edit"
        elif any(op in first_cmd for op in ["run", "execute", "bash", "sh", "python"]):
            task_type = "script_run"
        else:
            task_type = "other"
    else:
        task_type = "unknown"
        
    return {
        "length": length,
        "task_type": task_type,
        "tokens": set(instruction.lower().split())
    }

def calculate_kl_divergence(p_counts: Dict[str, int], q_counts: Dict[str, int]) -> float:
    """
    Calculate KL Divergence between two distributions.
    P is real (or reference), Q is synthetic.
    """
    total_p = sum(p_counts.values())
    total_q = sum(q_counts.values())
    
    if total_p == 0 or total_q == 0:
        return float('inf')
    
    p_dist = {k: v / total_p for k, v in p_counts.items()}
    q_dist = {k: v / total_q for k, v in q_counts.items()}
    
    kl = 0.0
    all_keys = set(p_dist.keys()) | set(q_dist.keys())
    
    for k in all_keys:
        p_val = p_dist.get(k, 0.0)
        q_val = q_dist.get(k, 0.0)
        
        # Add small epsilon to avoid log(0)
        if p_val > 0 and q_val > 0:
            kl += p_val * math.log(p_val / q_val)
        elif p_val > 0 and q_val == 0:
            # This contributes to divergence
            kl += p_val * math.log(p_val / 1e-9)
            
    return kl

def calculate_jaccard_similarity(set1: set, set2: set) -> float:
    """Calculate Jaccard similarity between two sets."""
    if not set1 or not set2:
        return 0.0
    intersection = len(set1.intersection(set2))
    union = len(set1.union(set2))
    if union == 0:
        return 0.0
    return intersection / union

def aggregate_vocabulary(data: List[Dict[str, Any]]) -> set:
    """Aggregate all unique tokens from a dataset."""
    vocab = set()
    for task in data:
        instruction = task.get("instruction", "")
        vocab.update(instruction.lower().split())
    return vocab

def run_validation() -> bool:
    """
    Main validation logic.
    Returns True if validation passes, False otherwise.
    """
    set_seed()
    
    print(f"--- Synthetic Validation Gate (T006b) ---")
    print(f"Real Data Path: {REAL_DATA_PATH}")
    print(f"Synthetic Data Path: {SYNTHETIC_DATA_PATH}")
    
    # Load data
    real_data = load_jsonl(REAL_DATA_PATH)
    synth_data = load_jsonl(SYNTHETIC_DATA_PATH)
    
    report = {
        "status": "PASS",
        "reason": "",
        "metrics": {}
    }
    
    # Case 1: No real data available
    if not real_data:
        print("WARNING: Real dataset not found. Skipping distribution comparison.")
        print("Assuming synthetic data is the ground truth for this run.")
        report["reason"] = "Real data unavailable; synthetic data accepted as default."
        report["metrics"]["real_data_count"] = 0
        report["metrics"]["synthetic_data_count"] = len(synth_data)
        
        if not synth_data:
            print("ERROR: Neither real nor synthetic data found. Validation FAIL.")
            report["status"] = "FAIL"
            report["reason"] = "No data available for validation."
        else:
            print(f"Found {len(synth_data)} synthetic tasks. Validation PASS.")
        
        # Ensure output directory exists
        OUTPUT_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
        with open(OUTPUT_REPORT_PATH, 'w', encoding='utf-8') as f:
            json.dump(report, f, indent=2)
        
        return report["status"] == "PASS"
    
    # Case 2: Real data exists, compare distributions
    print(f"Loaded {len(real_data)} real tasks.")
    print(f"Loaded {len(synth_data)} synthetic tasks.")
    
    if len(synth_data) == 0:
        print("ERROR: Synthetic data is empty. Validation FAIL.")
        report["status"] = "FAIL"
        report["reason"] = "Synthetic dataset is empty."
        report["metrics"]["real_data_count"] = len(real_data)
        report["metrics"]["synthetic_data_count"] = 0
        OUTPUT_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
        with open(OUTPUT_REPORT_PATH, 'w', encoding='utf-8') as f:
            json.dump(report, f, indent=2)
        return False
    
    # Extract features
    real_features = [extract_features(t) for t in real_data]
    synth_features = [extract_features(t) for t in synth_data]
    
    # 1. Task Type Distribution
    real_types = [f["task_type"] for f in real_features]
    synth_types = [f["task_type"] for f in synth_features]
    
    real_type_counts = Counter(real_types)
    synth_type_counts = Counter(synth_types)
    
    kl_div = calculate_kl_divergence(real_type_counts, synth_type_counts)
    
    print(f"Task Type KL Divergence: {kl_div:.4f} (Threshold: {MAX_KL_DIVergence})")
    report["metrics"]["task_type_kl_divergence"] = kl_div
    report["metrics"]["real_type_distribution"] = dict(real_type_counts)
    report["metrics"]["synth_type_distribution"] = dict(synth_type_counts)
    
    type_pass = kl_div <= MAX_KL_DIVergence
    
    # 2. Vocabulary Overlap
    real_vocab = aggregate_vocabulary(real_data)
    synth_vocab = aggregate_vocabulary(synth_data)
    
    vocab_sim = calculate_jaccard_similarity(real_vocab, synth_vocab)
    
    print(f"Vocabulary Jaccard Similarity: {vocab_sim:.4f} (Threshold: {MIN_VOCAB_OVERLAP})")
    report["metrics"]["vocab_jaccard_similarity"] = vocab_sim
    report["metrics"]["real_vocab_size"] = len(real_vocab)
    report["metrics"]["synth_vocab_size"] = len(synth_vocab)
    
    vocab_pass = vocab_sim >= MIN_VOCAB_OVERLAP
    
    # Determine final status
    if type_pass and vocab_pass:
        print("Validation PASSED: Distributions are sufficiently similar.")
        report["status"] = "PASS"
        report["reason"] = "Synthetic data distribution matches real data within thresholds."
    else:
        reasons = []
        if not type_pass:
            reasons.append(f"Task type distribution too divergent (KL={kl_div:.4f})")
        if not vocab_pass:
            reasons.append(f"Vocabulary similarity too low (Jaccard={vocab_sim:.4f})")
        
        print(f"Validation FAILED: {'; '.join(reasons)}")
        report["status"] = "FAIL"
        report["reason"] = "; ".join(reasons)
    
    # Save report
    OUTPUT_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_REPORT_PATH, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)
    
    print(f"Report saved to: {OUTPUT_REPORT_PATH}")
    
    return report["status"] == "PASS"

def main():
    """Entry point for the validation script."""
    success = run_validation()
    sys.exit(0 if success else 1)

if __name__ == "__main__":
    main()