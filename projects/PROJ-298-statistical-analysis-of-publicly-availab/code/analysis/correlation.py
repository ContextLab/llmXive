def load_json_safe(file_path: Path) -> Optional[Dict[str, Any]]:
    """Load a JSON file safely, returning None if it doesn't exist or is invalid."""
    if not file_path.exists():
        return None
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            return json.load(f)
    except (json.JSONDecodeError, IOError) as e:
        print(f"Error loading {file_path}: {e}")
        return None

def load_external_metrics(file_path: Path) -> Dict[str, Any]:
    """
    Load external metrics from the JSON file generated by T039.
    Expects a structure like:
    {
      "metrics": {
        "tag_name": {
          "github": { "repo": "owner/repo", "stars": 123, "found": true },
          "npm": { "package": "pkg-name", "downloads": 456, "found": true }
        },
        ...
      }
    }
    """
    data = load_json_safe(file_path)
    if data is None:
        raise FileNotFoundError(f"External metrics file not found: {file_path}")
    
    if "metrics" not in data:
        raise ValueError(f"Expected 'metrics' key in {file_path}")
    
    return data["metrics"]

def map_tag_to_repos(tag: str, external_metrics: Dict[str, Any]) -> Dict[str, Any]:
    """
    Map a single tag to its associated GitHub repo and NPM package based on external_metrics.
    Returns a mapping entry.
    """
    mapping = {
        "tag": tag,
        "github": None,
        "npm": None,
        "mapped": False
    }

    if tag not in external_metrics:
        return mapping

    tag_data = external_metrics[tag]
    
    # Check GitHub
    if tag_data.get("github", {}).get("found", False):
        mapping["github"] = tag_data["github"].get("repo")
        mapping["mapped"] = True
    
    # Check NPM
    if tag_data.get("npm", {}).get("found", False):
        mapping["npm"] = tag_data["npm"].get("package")
        mapping["mapped"] = True

    return mapping

def build_tag_mappings(external_metrics: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    Build a list of tag-to-repo mappings for all tags present in external_metrics.
    Returns a list of dictionaries, each representing a mapping for a tag.
    """
    mappings = []
    for tag in external_metrics.keys():
        mapping = map_tag_to_repos(tag, external_metrics)
        mappings.append(mapping)
    return mappings

def run_correlation_mapping(external_metrics_path: Path, output_path: Path) -> Dict[str, Any]:
    """
    Main function to run the tag-to-repo mapping logic.
    Reads external_metrics.json, builds mappings, and writes to tag_mappings.json.
    Also generates unmapped_tags.log if unmapped tags are identified.
    """
    print(f"Loading external metrics from {external_metrics_path}...")
    external_metrics = load_external_metrics(external_metrics_path)
    
    print(f"Building tag mappings for {len(external_metrics)} tags...")
    mappings = build_tag_mappings(external_metrics)
    
    # Filter for successfully mapped tags for summary
    mapped_count = sum(1 for m in mappings if m["mapped"])
    unmapped_count = len(mappings) - mapped_count
    
    result = {
        "total_tags": len(mappings),
        "mapped_tags": mapped_count,
        "unmapped_tags": unmapped_count,
        "mappings": mappings
    }
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Generate unmapped_tags.log if there are unmapped tags
    unmapped_log_path = output_path.parent / "unmapped_tags.log"
    unmapped_tags = [m["tag"] for m in mappings if not m["mapped"]]
    
    if unmapped_tags:
        print(f"Writing {len(unmapped_tags)} unmapped tags to {unmapped_log_path}...")
        with open(unmapped_log_path, 'w', encoding='utf-8') as f:
            for tag in unmapped_tags:
                f.write(json.dumps({"tag": tag, "reason": "no_match_found"}) + "\n")
    else:
        print("No unmapped tags found.")
        # Ensure the log file exists even if empty, or remove if strictly not needed
        # Per FR-007: "log unmapped tags ... if no match found". If none, we can create empty or skip.
        # We'll create an empty file to ensure consistency if expected by downstream.
        with open(unmapped_log_path, 'w', encoding='utf-8') as f:
            pass

    print(f"Writing tag mappings to {output_path}...")
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(result, f, indent=2)
    
    print(f"Successfully mapped {mapped_count} out of {len(mappings)} tags.")
    return result

def main():
    """Entry point for the correlation mapping task."""
    # Define paths relative to project root
    project_root = Path(__file__).resolve().parent.parent.parent
    external_metrics_path = project_root / "data" / "processed" / "external_metrics.json"
    output_path = project_root / "data" / "processed" / "tag_mappings.json"
    
    if not external_metrics_path.exists():
        raise FileNotFoundError(
            f"Required input file not found: {external_metrics_path}. "
            "Please ensure T039 has completed successfully."
        )
    
    run_correlation_mapping(external_metrics_path, output_path)

if __name__ == "__main__":
    main()