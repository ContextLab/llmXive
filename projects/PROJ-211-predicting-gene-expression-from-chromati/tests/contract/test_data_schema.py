"""
Contract tests for synthetic data schema validation.

This module validates that the synthetic data generated by `code/generate_data.py`
adheres to the schema definitions specified in `specs/001-gene-regulation/contracts/`.

It verifies:
1. CSV structure for counts (headers, types, required columns).
2. BED structure for peaks (chrom, start, end, name, score, strand).
3. Data integrity constraints (non-negative counts, valid coordinates).
"""
import os
import csv
import pytest
import json
from pathlib import Path

# Project root relative to this file
PROJECT_ROOT = Path(__file__).parent.parent.parent
SCHEMA_DIR = PROJECT_ROOT / "specs" / "001-gene-regulation" / "contracts"
DATA_DIR = PROJECT_ROOT / "data" / "raw"

# Expected files based on T005 and T011
SYNTHETIC_COUNTS_PATH = DATA_DIR / "synthetic_counts.csv"
SYNTHETIC_PEAKS_PATH = DATA_DIR / "synthetic_peaks.bed"

# Schema definitions (loaded from contract files if they exist, otherwise hardcoded for robustness)
def load_schema(schema_name: str) -> dict:
    schema_path = SCHEMA_DIR / f"{schema_name}.schema.yaml"
    if schema_path.exists():
        import yaml
        with open(schema_path, "r") as f:
            return yaml.safe_load(f)
    # Fallback to hardcoded schema if file missing (defensive)
    if schema_name == "dataset_schema":
        return {
            "counts": {
                "required_columns": ["gene_id", "gene_name", "cell_line", "count"],
                "types": {
                    "gene_id": str,
                    "gene_name": str,
                    "cell_line": str,
                    "count": int
                },
                "constraints": {
                    "count": lambda x: x >= 0
                }
            },
            "peaks": {
                "required_columns": ["chrom", "start", "end", "name", "score", "strand"],
                "types": {
                    "chrom": str,
                    "start": int,
                    "end": int,
                    "name": str,
                    "score": float,
                    "strand": str
                },
                "constraints": {
                    "start": lambda x: x >= 0,
                    "end": lambda x: x > 0,
                    "strand": lambda x: x in ["+", "-", "."]
                }
            }
        }
    return {}

class TestSyntheticCountsSchema:
    """Tests for synthetic_counts.csv schema compliance."""
    
    @pytest.fixture(scope="class")
    def counts_data(self):
        """Load the synthetic counts data once for the class."""
        if not SYNTHETIC_COUNTS_PATH.exists():
            pytest.skip(f"Synthetic counts file not found: {SYNTHETIC_COUNTS_PATH}. Run T011 first.")
        
        with open(SYNTHETIC_COUNTS_PATH, "r", newline="") as f:
            reader = csv.DictReader(f)
            return list(reader)
    
    def test_file_exists(self):
        """Assert that the synthetic counts file exists."""
        assert SYNTHETIC_COUNTS_PATH.exists(), f"File {SYNTHETIC_COUNTS_PATH} does not exist."
    
    def test_required_columns_present(self, counts_data, counts_schema):
        """Assert that all required columns are present in the CSV header."""
        if not counts_data:
            pytest.skip("No data rows found.")
        
        headers = counts_data[0].keys()
        required = counts_schema["required_columns"]
        missing = set(required) - set(headers)
        assert not missing, f"Missing required columns: {missing}"
    
    def test_data_types(self, counts_data, counts_schema):
        """Assert that values match expected data types."""
        type_map = counts_schema["types"]
        
        for row_idx, row in enumerate(counts_data):
            for col, expected_type in type_map.items():
                val = row.get(col)
                if val is None:
                    pytest.fail(f"Row {row_idx}: Missing value for column '{col}'")
                
                # Special handling for int/float conversion checks
                if expected_type == int:
                    try:
                        int(val)
                    except ValueError:
                        pytest.fail(f"Row {row_idx}, Col '{col}': '{val}' is not an integer")
                elif expected_type == float:
                    try:
                        float(val)
                    except ValueError:
                        pytest.fail(f"Row {row_idx}, Col '{col}': '{val}' is not a float")
                
                # Type check (strict)
                if not isinstance(val, str): # CSV reads as string
                    # We already validated conversion above, so this is a pass for string-represented types
                    pass
    
    def test_value_constraints(self, counts_data, counts_schema):
        """Assert that values satisfy logical constraints (e.g., non-negative counts)."""
        constraints = counts_schema.get("constraints", {})
        
        for row_idx, row in enumerate(counts_data):
            for col, validator in constraints.items():
                val = row.get(col)
                if val is None:
                    continue
                
                try:
                    if col == "count":
                        # Ensure count is non-negative integer
                        count_val = int(val)
                        assert validator(count_val), f"Row {row_idx}: Count {count_val} violates constraint"
                    elif col == "start":
                        assert validator(int(val)), f"Row {row_idx}: Start {val} violates constraint"
                    elif col == "end":
                        assert validator(int(val)), f"Row {row_idx}: End {val} violates constraint"
                    elif col == "strand":
                        assert validator(val), f"Row {row_idx}: Strand {val} violates constraint"
                except (ValueError, TypeError) as e:
                    pytest.fail(f"Row {row_idx}, Col '{col}': Validation error: {e}")

class TestSyntheticPeaksSchema:
    """Tests for synthetic_peaks.bed schema compliance."""
    
    @pytest.fixture(scope="class")
    def peaks_data(self):
        """Load the synthetic peaks data once for the class."""
        if not SYNTHETIC_PEAKS_PATH.exists():
            pytest.skip(f"Synthetic peaks file not found: {SYNTHETIC_PEAKS_PATH}. Run T011 first.")
        
        with open(SYNTHETIC_PEAKS_PATH, "r", newline="") as f:
            reader = csv.DictReader(f, delimiter="\t", fieldnames=["chrom", "start", "end", "name", "score", "strand"])
            return list(reader)
    
    def test_file_exists(self):
        """Assert that the synthetic peaks file exists."""
        assert SYNTHETIC_PEAKS_PATH.exists(), f"File {SYNTHETIC_PEAKS_PATH} does not exist."
    
    def test_required_columns_present(self, peaks_data, peaks_schema):
        """Assert that all required columns are present in the BED file."""
        if not peaks_data:
            pytest.skip("No data rows found.")
        
        # BED is tab-separated, headers might not be explicit, but we check the field count
        # The schema defines the expected fields for a standard 6-column BED
        required = peaks_schema["required_columns"]
        if len(peaks_data[0]) != len(required):
            pytest.fail(f"Expected {len(required)} columns, found {len(peaks_data[0])}")
    
    def test_data_types(self, peaks_data, peaks_schema):
        """Assert that values match expected data types."""
        type_map = peaks_schema["types"]
        
        for row_idx, row in enumerate(peaks_data):
            for col, expected_type in type_map.items():
                val = row.get(col)
                if val is None:
                    pytest.fail(f"Row {row_idx}: Missing value for column '{col}'")
                
                if expected_type == int:
                    try:
                        int(val)
                    except ValueError:
                        pytest.fail(f"Row {row_idx}, Col '{col}': '{val}' is not an integer")
                elif expected_type == float:
                    try:
                        float(val)
                    except ValueError:
                        pytest.fail(f"Row {row_idx}, Col '{col}': '{val}' is not a float")
    
    def test_value_constraints(self, peaks_data, peaks_schema):
        """Assert that values satisfy logical constraints."""
        constraints = peaks_schema.get("constraints", {})
        
        for row_idx, row in enumerate(peaks_data):
            for col, validator in constraints.items():
                val = row.get(col)
                if val is None:
                    continue
                
                try:
                    if col in ["start", "end"]:
                        assert validator(int(val)), f"Row {row_idx}: {col} {val} violates constraint"
                    elif col == "strand":
                        assert validator(val), f"Row {row_idx}: Strand {val} violates constraint"
                except (ValueError, TypeError) as e:
                    pytest.fail(f"Row {row_idx}, Col '{col}': Validation error: {e}")

