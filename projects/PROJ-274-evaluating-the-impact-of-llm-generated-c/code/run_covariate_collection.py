"""
Task T021g: Aggregate LOC, CC, and Doc Quality scores into a single covariate dataset.

This script loads the intermediate artifacts generated by previous tasks:
- data/raw/repo_loc_raw.json
- data/raw/repo_cc_raw.json
- data/raw/doc_quality_scores.json

It merges them by repository identifier, calculates normalized/centered covariates,
and writes the result to data/raw/repo_covariates.json.

This artifact is required for the ANCOVA statistical adjustment in Phase 6.
"""
import json
import os
import sys
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger("run_covariate_collection")

# Define paths relative to project root
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_RAW_DIR = PROJECT_ROOT / "data" / "raw"

# Input files
LOC_INPUT_PATH = DATA_RAW_DIR / "repo_loc_raw.json"
CC_INPUT_PATH = DATA_RAW_DIR / "repo_cc_raw.json"
DOC_QUALITY_INPUT_PATH = DATA_RAW_DIR / "doc_quality_scores.json"

# Output file
COVARIATES_OUTPUT_PATH = DATA_RAW_DIR / "repo_covariates.json"

def load_json_file(path: Path) -> Dict[str, Any]:
    """Load a JSON file and return its contents."""
    if not path.exists():
        raise FileNotFoundError(f"Required input file not found: {path}")
    
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)

def save_json_file(path: Path, data: Dict[str, Any]) -> None:
    """Save data to a JSON file with indentation."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=4, sort_keys=True)

def calculate_mean(values: List[float]) -> float:
    """Calculate the arithmetic mean of a list of numbers."""
    if not values:
        return 0.0
    return sum(values) / len(values)

def calculate_std_dev(values: List[float], mean: float) -> float:
    """Calculate the population standard deviation."""
    if len(values) < 2:
        return 0.0
    variance = sum((x - mean) ** 2 for x in values) / len(values)
    return variance ** 0.5

def main():
    """
    Main execution function for T021g.
    
    1. Loads LOC, CC, and Doc Quality data.
    2. Aggregates them into a single record per repository.
    3. Calculates global mean and std dev for each metric.
    4. Computes centered (z-score normalized) covariates.
    5. Writes the final covariate dataset to repo_covariates.json.
    """
    logger.info("Starting T021g: Covariate Aggregation")
    
    # 1. Load Input Data
    logger.info(f"Loading LOC data from {LOC_INPUT_PATH}")
    loc_data = load_json_file(LOC_INPUT_PATH)
    
    logger.info(f"Loading CC data from {CC_INPUT_PATH}")
    cc_data = load_json_file(CC_INPUT_PATH)
    
    logger.info(f"Loading Doc Quality data from {DOC_QUALITY_INPUT_PATH}")
    doc_quality_data = load_json_file(DOC_QUALITY_INPUT_PATH)

    # 2. Validate and Normalize Input Structures
    # We expect these files to be dictionaries keyed by repo name (or ID)
    # If they are lists, we need to normalize. Assuming dict structure based on previous tasks.
    
    # Ensure consistent key usage (repo_name)
    # loc_data format: { "repo_name": { "loc": int, ... } }
    # cc_data format: { "repo_name": { "cc": float, ... } }
    # doc_quality_data format: { "repo_name": { "score": int, ... } }
    
    covariates_records: List[Dict[str, Any]] = []
    
    # Collect all unique repo names
    all_repos = set(loc_data.keys()) | set(cc_data.keys()) | set(doc_quality_data.keys())
    
    if not all_repos:
        logger.error("No repositories found in input files. Cannot proceed.")
        sys.exit(1)

    logger.info(f"Found {len(all_repos)} unique repositories to process.")

    # 3. Aggregate Raw Values and Collect for Statistics
    raw_values: Dict[str, List[float]] = {
        "loc": [],
        "cc": [],
        "doc_quality": []
    }
    
    aggregated_raw: Dict[str, Dict[str, Any]] = {}

    for repo in all_repos:
        raw_loc = loc_data.get(repo, {}).get("loc", 0)
        raw_cc = cc_data.get(repo, {}).get("cc", 0)
        raw_score = doc_quality_data.get(repo, {}).get("score", 0)
        
        # Store raw values for statistical calculation
        aggregated_raw[repo] = {
            "loc": raw_loc,
            "cc": raw_cc,
            "doc_quality": raw_score
        }
        
        raw_values["loc"].append(float(raw_loc))
        raw_values["cc"].append(float(raw_cc))
        raw_values["doc_quality"].append(float(raw_score))

    # 4. Calculate Global Statistics (Mean and Std Dev)
    stats = {}
    for metric in ["loc", "cc", "doc_quality"]:
        vals = raw_values[metric]
        mean_val = calculate_mean(vals)
        std_val = calculate_std_dev(vals, mean_val)
        stats[metric] = {
            "mean": mean_val,
            "std_dev": std_val
        }
        logger.info(f"Metric '{metric}': Mean={mean_val:.4f}, StdDev={std_val:.4f}")

    # 5. Compute Centered (Normalized) Covariates
    # Formula: (value - mean) / std_dev
    # If std_dev is 0, centered value is 0.
    
    final_covariates = {
        "metadata": {
            "description": "Normalized covariates for ANCOVA adjustment",
            "source_files": [
                str(LOC_INPUT_PATH.relative_to(PROJECT_ROOT)),
                str(CC_INPUT_PATH.relative_to(PROJECT_ROOT)),
                str(DOC_QUALITY_INPUT_PATH.relative_to(PROJECT_ROOT))
            ],
            "statistics": stats
        },
        "covariates": []
    }

    for repo in sorted(all_repos):
        raw = aggregated_raw[repo]
        
        def normalize(val: float, mean: float, std: float) -> float:
            if std == 0:
                return 0.0
            return (val - mean) / std

        norm_loc = normalize(raw["loc"], stats["loc"]["mean"], stats["loc"]["std_dev"])
        norm_cc = normalize(raw["cc"], stats["cc"]["mean"], stats["cc"]["std_dev"])
        norm_doc = normalize(raw["doc_quality"], stats["doc_quality"]["mean"], stats["doc_quality"]["std_dev"])

        record = {
            "repo": repo,
            "raw": {
                "loc": raw["loc"],
                "cc": raw["cc"],
                "doc_quality": raw["doc_quality"]
            },
            "normalized": {
                "loc": round(norm_loc, 6),
                "cc": round(norm_cc, 6),
                "doc_quality": round(norm_doc, 6)
            }
        }
        final_covariates["covariates"].append(record)

    # 6. Write Output
    logger.info(f"Writing covariate dataset to {COVARIATES_OUTPUT_PATH}")
    save_json_file(COVARIATES_OUTPUT_PATH, final_covariates)

    logger.info("T021g completed successfully.")
    return 0

if __name__ == "__main__":
    sys.exit(main())