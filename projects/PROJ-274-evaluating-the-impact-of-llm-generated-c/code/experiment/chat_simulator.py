"""
Chat Simulator for User Story 1 (T016a).
Generates simulated chat interactions for assigned participants.
"""
import json
import os
import random
import sys
from datetime import datetime, timedelta
from pathlib import Path
from typing import List, Dict, Any

# Add parent directory to path for imports if running as script
sys.path.insert(0, str(Path(__file__).parent.parent))

from utils.seed import set_global_seed
from utils.setup_paths import ensure_project_dirs

# Configuration
PROJECT_ROOT = Path(__file__).parent.parent
ASSIGNMENT_LOG_PATH = PROJECT_ROOT / "data" / "processed" / "assignment_log.json"
OUTPUT_PATH = PROJECT_ROOT / "data" / "raw" / "chat_transcripts.json"

# Seed for reproducibility
set_global_seed(42)

# Templates for simulated messages based on condition
TEMPLATES = {
    "LLM": [
        {"role": "assistant", "content": "Here is the documentation snippet you requested. It covers the setup and API usage."},
        {"role": "assistant", "content": "I've generated the architecture diagram based on the code structure."},
        {"role": "assistant", "content": "You can find the installation instructions in the README section I just provided."},
        {"role": "assistant", "content": "Based on the code, the main entry point is the `main()` function in `app.py`."},
        {"role": "assistant", "content": "I've summarized the dependencies required for this module."}
    ],
    "Human": [
        {"role": "assistant", "content": "I've attached the PDF documentation. Let me know if you need clarification on the setup."},
        {"role": "assistant", "content": "The API reference is in the `docs/api.md` file. Check section 3 for examples."},
        {"role": "assistant", "content": "I wrote the architecture guide yesterday. It explains the data flow."},
        {"role": "assistant", "content": "Here is the link to the internal wiki for installation steps."},
        {"role": "assistant", "content": "I can walk you through the setup if you have specific errors."}
    ],
    "None": [
        # No assistant messages, only user attempts to find info
        {"role": "assistant", "content": ""} # Placeholder, effectively no chat
    ]
}

USER_QUESTIONS = [
    "How do I install this?",
    "What is the main entry point?",
    "Can you explain the architecture?",
    "Where are the API docs?",
    "How do I run the tests?",
    "What dependencies are needed?",
    "How do I configure the database?",
    "Explain the data flow."
]

def load_assignment_log() -> List[Dict[str, Any]]:
    """Load the assignment log generated by T014b."""
    if not ASSIGNMENT_LOG_PATH.exists():
        raise FileNotFoundError(f"Assignment log not found at {ASSIGNMENT_LOG_PATH}. "
                                "Please run T014b first.")
    
    with open(ASSIGNMENT_LOG_PATH, 'r') as f:
        data = json.load(f)
    
    # Handle both list of dicts and dict of mappings
    if isinstance(data, dict):
        # Convert dict mapping participant_id -> condition to list
        return [{"participant_id": pid, "condition": cond} for pid, cond in data.items()]
    return data

def generate_chat_transcript(participant_id: str, condition: str) -> Dict[str, Any]:
    """Generate a simulated chat transcript for a participant."""
    transcript = []
    start_time = datetime.now()
    
    # Simulate 1-3 interaction turns
    num_turns = random.randint(1, 3) if condition != "None" else 0
    
    for i in range(num_turns):
        # User asks a question
        user_msg = {
            "role": "user",
            "content": random.choice(USER_QUESTIONS),
            "timestamp": (start_time + timedelta(seconds=i*30)).isoformat()
        }
        transcript.append(user_msg)
        
        # Assistant responds
        if condition == "None":
            # No response in None condition
            continue
            
        templates = TEMPLATES[condition]
        response_content = random.choice(templates)["content"]
        
        assistant_msg = {
            "role": "assistant",
            "content": response_content,
            "timestamp": (start_time + timedelta(seconds=i*30 + 5)).isoformat()
        }
        transcript.append(assistant_msg)
    
    return {
        "participant_id": participant_id,
        "condition": condition,
        "transcript": transcript,
        "generated_at": datetime.now().isoformat()
    }

def main():
    """Main entry point for T016a."""
    print("Starting T016a: Generating chat transcripts...")
    
    # Ensure output directory exists
    ensure_project_dirs([str(OUTPUT_PATH.parent)])
    
    # Load assignments
    assignments = load_assignment_log()
    print(f"Loaded {len(assignments)} participant assignments.")
    
    if len(assignments) == 0:
        print("No participants found. Generating empty output.")
        output_data = []
    else:
        # Generate transcripts
        transcripts = []
        for assignment in assignments:
            pid = assignment.get("participant_id")
            cond = assignment.get("condition")
            
            if not pid or not cond:
                print(f"Skipping invalid assignment: {assignment}")
                continue
                
            try:
                transcript = generate_chat_transcript(pid, cond)
                transcripts.append(transcript)
            except Exception as e:
                print(f"Error generating transcript for {pid}: {e}")
                # Continue with other participants
                continue
        
        output_data = transcripts
    
    # Write output
    with open(OUTPUT_PATH, 'w') as f:
        json.dump(output_data, f, indent=2)
    
    print(f"Successfully generated {len(output_data)} chat transcripts.")
    print(f"Output written to: {OUTPUT_PATH}")
    
    # Verification
    if not OUTPUT_PATH.exists():
        raise RuntimeError(f"Failed to write output to {OUTPUT_PATH}")
    
    with open(OUTPUT_PATH, 'r') as f:
        result = json.load(f)
    
    if len(result) != len(assignments):
        print(f"Warning: Generated {len(result)} transcripts for {len(assignments)} assignments.")
    
    return 0

if __name__ == "__main__":
    sys.exit(main())
