def load_species_list(species_list_path: Path) -> Set[str]:
    """
    Load the target species list from data/raw/species_list.txt.
    Returns a set of scientific names (the third column).
    """
    if not species_list_path.exists():
        raise FileNotFoundError(f"Species list not found at {species_list_path}")
    
    species = set()
    with open(species_list_path, 'r', encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            parts = line.split('\t')
            if len(parts) >= 3:
                # Format: NCBI_ID\tKEGG_CODE\tScientificName
                species.add(parts[2])
    return species

def load_processed_log(log_path: Path) -> Set[str]:
    """
    Load the list of species that successfully passed through the pipeline.
    We look for the 'validation_log.txt' or 'analysis_summary.txt' which
    should contain the list of retained species or a summary of retention.
    
    For this audit, we assume the main pipeline logs the retained species
    in a structured way or we can infer from the processed data files.
    
    Strategy:
    1. Check for data/processed/mantel_results.json to see if it ran.
    2. Check for data/processed/phylo_dist_matrix.csv or similar to count rows.
    3. Ideally, we read the 'validation_log.txt' generated by T020b.
    """
    # We will look for the validation log generated by T020b
    # If it doesn't exist, we might need to parse the main pipeline logs
    # or infer from the distance matrix size.
    
    # Primary source: validation_log.txt (from T020b)
    if log_path.exists():
        retained = set()
        with open(log_path, 'r', encoding='utf-8') as f:
            for line in f:
                # Look for lines that list species or a summary count
                # If the log format is "Retention X% (PASS/FAIL)", we can't get the list directly.
                # However, T020a usually logs the excluded species.
                # Let's assume the log contains a section "Retained Species:" or similar.
                # If not, we fall back to counting the distance matrix rows.
                pass
        
        # Fallback: If the log doesn't list species, we check the distance matrix
        # The distance matrix is symmetric, so the number of species = rows
        matrix_path = project_root / "data" / "processed" / "phylo_dist_matrix.csv"
        if matrix_path.exists():
            with open(matrix_path, 'r', encoding='utf-8') as f:
                # Skip header
                lines = f.readlines()[1:]
                # Count unique species names from the first column (or row count)
                # Assuming the CSV has headers: species, ...
                # We count the number of data rows
                count = len(lines)
                # We can't get the names without parsing the matrix carefully,
                # but we can get the count.
                # For a full audit, we need the names.
                # Let's assume the matrix has species names in the first column.
                names = set()
                for line in lines:
                    parts = line.strip().split(',')
                    if parts:
                        names.add(parts[0])
                return names
    else:
        # Try to infer from the distance matrix if log is missing
        matrix_path = project_root / "data" / "processed" / "phylo_dist_matrix.csv"
        if matrix_path.exists():
            names = set()
            with open(matrix_path, 'r', encoding='utf-8') as f:
                lines = f.readlines()[1:] # Skip header
                for line in lines:
                    parts = line.strip().split(',')
                    if parts:
                        names.add(parts[0])
            return names
    
    return set()

def calculate_retention(target: Set[str], retained: Set[str]) -> Tuple[float, Set[str], Set[str]]:
    """
    Calculate retention percentage and identify missing species.
    """
    if not target:
        return 0.0, set(), set()
    
    missing = target - retained
    # Species that are in target but not in retained
    # Note: retained might have extra species if the matrix includes something else,
    # but we only care about the intersection with target for retention.
    
    retention_pct = (len(retained & target) / len(target)) * 100
    return retention_pct, missing, retained & target

def main():
    logger = setup_logging()
    logger.info("Starting Data Retention Audit (T042)")
    
    config = load_config()
    species_list_path = project_root / "data" / "raw" / "species_list.txt"
    validation_log_path = project_root / "output" / "reports" / "validation_log.txt"
    output_path = project_root / "output" / "reports" / "retention_audit.txt"
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    try:
        # 1. Load Target Species
        logger.info(f"Loading target species from {species_list_path}")
        target_species = load_species_list(species_list_path)
        logger.info(f"Found {len(target_species)} target species.")
        
        # 2. Load Retained Species
        logger.info(f"Loading retained species from {validation_log_path} or matrix")
        retained_species = load_processed_log(validation_log_path)
        logger.info(f"Found {len(retained_species)} retained species.")
        
        # 3. Calculate Metrics
        retention_pct, missing_species, kept_species = calculate_retention(target_species, retained_species)
        
        # 4. Determine Status
        threshold = 80.0 # From T004 config or spec
        status = "PASS" if retention_pct >= threshold else "FAIL"
        
        # 5. Write Report
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write("=" * 60 + "\n")
            f.write("DATA RETENTION AUDIT REPORT\n")
            f.write(f"Generated: {datetime.now().isoformat()}\n")
            f.write("=" * 60 + "\n\n")
            
            f.write(f"Target Species Count: {len(target_species)}\n")
            f.write(f"Retained Species Count: {len(retained_species)}\n")
            f.write(f"Retention Percentage: {retention_pct:.2f}%\n")
            f.write(f"Threshold: {threshold}%\n")
            f.write(f"Status: {status}\n\n")
            
            if missing_species:
                f.write("MISSING SPECIES (Target but not in processed data):\n")
                for species in sorted(missing_species):
                    f.write(f"  - {species}\n")
                f.write("\n")
            
            f.write("RETAINED SPECIES:\n")
            for species in sorted(kept_species):
                f.write(f"  - {species}\n")
            f.write("\n")
            
            f.write("=" * 60 + "\n")
            f.write(f"AUDIT RESULT: {status}\n")
            f.write("=" * 60 + "\n")
        
        logger.info(f"Audit report written to {output_path}")
        logger.info(f"Retention: {retention_pct:.2f}% -> {status}")
        
        return 0 if status == "PASS" else 1
        
    except FileNotFoundError as e:
        logger.error(f"Critical file missing: {e}")
        # Write a failure report
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write("AUDIT FAILED: Critical file missing.\n")
            f.write(f"Error: {str(e)}\n")
        return 1
    except Exception as e:
        logger.error(f"Audit failed with unexpected error: {e}")
        raise

if __name__ == "__main__":
    sys.exit(main())
