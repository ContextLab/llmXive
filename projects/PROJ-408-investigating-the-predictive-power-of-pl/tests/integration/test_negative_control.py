"""
T012: Negative control test for User Story 1.

Verifies that shuffled metabolite profiles yield negligible phylogenetic signal.
Threshold: |r| < 0.05.

Inputs:
  - data/processed/phylo_dist_matrix.csv (generated by T017)
  - data/processed/metabolite_matrix.csv (generated by T018)

Outputs:
  - data/processed/negative_control_results.json (contains r, p-value, and status)
"""
import os
import json
import logging
import random
from pathlib import Path
from typing import Tuple, List

import numpy as np
import pandas as pd

# Import from project modules (matching API surface)
from stats_engine import calculate_jaccard_dissimilarity_matrix, run_mantel_test, save_mantel_results
from config import get_config, load_config
from logging_config import get_logger, init_pipeline_logging

# Initialize logging for the test
init_pipeline_logging()
logger = get_logger("test_negative_control")

def load_distance_matrix(path: Path) -> np.ndarray:
    """Load a CSV distance matrix and return as numpy array."""
    df = pd.read_csv(path, index_col=0)
    return df.values

def load_metabolite_matrix(path: Path) -> pd.DataFrame:
    """Load the metabolite presence/absence matrix."""
    return pd.read_csv(path, index_col=0)

def shuffle_metabolite_matrix(df: pd.DataFrame, seed: int = 42) -> pd.DataFrame:
    """
    Shuffle the metabolite matrix column-wise (metabolites) relative to rows (species).
    This breaks the biological link between phylogeny and metabolite profile while
    preserving the marginal distribution of metabolites.
    """
    random.seed(seed)
    np.random.seed(seed)
    
    # Create a copy to avoid modifying original
    shuffled_df = df.copy()
    
    # Shuffle each column independently to break row-column correlation
    # while maintaining column sums (metabolite prevalence)
    for col in shuffled_df.columns:
        shuffled_df[col] = np.random.permutation(shuffled_df[col].values)
        
    return shuffled_df

def run_negative_control_test(
    phylo_dist_path: Path,
    metab_matrix_path: Path,
    output_path: Path,
    n_permutations: int = 999
) -> dict:
    """
    Run the negative control test.
    
    1. Load real phylogenetic distance matrix.
    2. Load real metabolite matrix.
    3. Shuffle metabolite matrix.
    4. Compute Jaccard dissimilarity on shuffled data.
    5. Run Mantel test against real phylogenetic distances.
    6. Verify |r| < 0.05.
    """
    logger.info(f"Starting negative control test")
    logger.info(f"Phylo dist path: {phylo_dist_path}")
    logger.info(f"Metab matrix path: {metab_matrix_path}")
    
    # Load data
    if not phylo_dist_path.exists():
        raise FileNotFoundError(f"Phylogenetic distance matrix not found: {phylo_dist_path}")
    if not metab_matrix_path.exists():
        raise FileNotFoundError(f"Metabolite matrix not found: {metab_matrix_path}")
    
    phylo_dist_matrix = load_distance_matrix(phylo_dist_path)
    metab_df = load_metabolite_matrix(metab_matrix_path)
    
    logger.info(f"Loaded phylo matrix shape: {phylo_dist_matrix.shape}")
    logger.info(f"Loaded metab matrix shape: {metab_df.shape}")
    
    # Shuffle metabolite matrix
    logger.info("Shuffling metabolite matrix...")
    shuffled_metab_df = shuffle_metabolite_matrix(metab_df)
    
    # Calculate Jaccard dissimilarity on shuffled data
    logger.info("Calculating Jaccard dissimilarity on shuffled data...")
    shuffled_dist_matrix = calculate_jaccard_dissimilarity_matrix(shuffled_metab_df)
    
    # Run Mantel test
    logger.info("Running Mantel test on shuffled data...")
    r_stat, p_value, null_dist = run_mantel_test(
        phylo_dist_matrix,
        shuffled_dist_matrix,
        n_permutations=n_permutations
    )
    
    logger.info(f"Negative control Mantel r: {r_stat:.4f}, p-value: {p_value:.4f}")
    
    # Verify threshold
    threshold = 0.05
    is_pass = abs(r_stat) < threshold
    
    results = {
        "test_name": "Negative Control (Shuffled Metabolites)",
        "n_permutations": n_permutations,
        "mantel_r": float(r_stat),
        "p_value": float(p_value),
        "threshold": threshold,
        "abs_r": float(abs(r_stat)),
        "status": "PASS" if is_pass else "FAIL",
        "message": f"Observed |r|={abs(r_stat):.4f} < {threshold} (PASS)" if is_pass else f"Observed |r|={abs(r_stat):.4f} >= {threshold} (FAIL)"
    }
    
    # Save results
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    
    logger.info(f"Results saved to {output_path}")
    logger.info(results["message"])
    
    return results

def main():
    """Entry point for the negative control test."""
    config = load_config()
    data_dir = Path(config.get("data_dir", "data"))
    
    phylo_dist_path = data_dir / "processed" / "phylo_dist_matrix.csv"
    metab_matrix_path = data_dir / "processed" / "metabolite_matrix.csv"
    output_path = data_dir / "processed" / "negative_control_results.json"
    
    try:
        results = run_negative_control_test(
            phylo_dist_path,
            metab_matrix_path,
            output_path,
            n_permutations=999
        )
        
        if results["status"] == "FAIL":
            logger.error("Negative control test FAILED. Phylogenetic signal detected in shuffled data.")
            raise AssertionError(results["message"])
        
        logger.info("Negative control test PASSED.")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"Missing required input file: {e}")
        raise
    except Exception as e:
        logger.error(f"Test execution failed: {e}")
        raise

if __name__ == "__main__":
    main()