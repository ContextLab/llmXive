def validate_dict_schema(data: Dict, schema: Dict, path: str = "") -> List[str]:
    """
    Validate a dictionary against a schema definition.
    Returns a list of validation errors.
    """
    errors = []

    if schema.get("type") == "dict":
        if not isinstance(data, dict):
            errors.append(f"{path}: Expected dict, got {type(data).__name__}")
            return errors

        required_keys = schema.get("required_keys", [])
        for key in required_keys:
            if key not in data:
                errors.append(f"{path}: Missing required key '{key}'")
            else:
                # Recursively validate nested schemas if defined
                nested_schema = schema.get("nested_schemas", {}).get(key)
                if nested_schema:
                    errors.extend(
                        validate_dict_schema(data[key], nested_schema, f"{path}.{key}")
                    )

    return errors


