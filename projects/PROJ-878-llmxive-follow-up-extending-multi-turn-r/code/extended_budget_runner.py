"""
Extended Budget Validation Run (FR-008).

Filters the primary execution log for instances where convergence_status='failure',
re-runs them with an extended turn limit (1000 turns), and writes results to
data/processed/extended_budget_log.csv.
"""
import os
import sys
import csv
import logging
import time
from pathlib import Path
from typing import Dict, List, Any, Optional

# Project root setup
PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "code"))

from utils.logging_utils import configure_logging
from rm_executor import ReflectiveMaskingExecutor
from batch_processor import BatchConfig, stream_puzzles, process_batch, write_results

# Constants
PRIMARY_LOG_PATH = PROJECT_ROOT / "data" / "processed" / "execution_log.csv"
EXTENDED_LOG_PATH = PROJECT_ROOT / "data" / "processed" / "extended_budget_log.csv"
PUZZLES_PATH = PROJECT_ROOT / "data" / "raw" / "logical_puzzles.jsonl"

# Configuration
EXTENDED_TURN_LIMIT = 1000
BATCH_SIZE = 10
FAILURE_STATUS = "failure"

def load_failure_instances() -> List[Dict[str, Any]]:
    """Load instances from the primary log that failed to converge."""
    if not PRIMARY_LOG_PATH.exists():
        raise FileNotFoundError(f"Primary execution log not found: {PRIMARY_LOG_PATH}")

    failures = []
    with open(PRIMARY_LOG_PATH, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if row.get("convergence_status") == FAILURE_STATUS:
                failures.append(row)
    
    logging.info(f"Found {len(failures)} failure instances to re-run.")
    return failures

def load_puzzle_metadata(instance_id: str) -> Optional[Dict[str, Any]]:
    """Retrieve puzzle metadata (graph structure, ground truth) for a specific instance."""
    if not PUZZLES_PATH.exists():
        raise FileNotFoundError(f"Puzzle metadata not found: {PUZZLES_PATH}")
    
    with open(PUZZLES_PATH, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            data = eval(line)  # Safe for JSONL generated by controlled script
            if data.get("instance_id") == instance_id:
                return data
    return None

def re_run_extended_budget(failures: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Re-run failed instances with extended turn limit."""
    if not failures:
        logging.warning("No failure instances to process.")
        return []

    results = []
    executor = ReflectiveMaskingExecutor()
    
    # Prepare batch config for extended run
    # Note: We construct a temporary list of puzzle IDs to re-run
    puzzle_ids = [f["instance_id"] for f in failures]
    
    # We need to map back to full puzzle data because the executor needs the graph structure
    # and the primary log only has IDs and basic metrics.
    # We will stream the original puzzles, filter by ID, and process.
    
    def filter_puzzle_stream(target_ids: set):
        if not PUZZLES_PATH.exists():
            raise FileNotFoundError(f"Puzzle file missing: {PUZZLES_PATH}")
        with open(PUZZLES_PATH, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                data = eval(line)
                if data.get("instance_id") in target_ids:
                    yield data

    # Process failures in batches
    for i in range(0, len(puzzle_ids), BATCH_SIZE):
        batch_ids = puzzle_ids[i : i + BATCH_SIZE]
        batch_data = list(filter_puzzle_stream(set(batch_ids)))
        
        if not batch_data:
            continue

        logging.info(f"Processing batch {i//BATCH_SIZE + 1}: {len(batch_data)} instances")
        
        batch_results = process_batch(
            puzzles=batch_data,
            executor=executor,
            turn_limit=EXTENDED_TURN_LIMIT,
            batch_id=f"extended_{i//BATCH_SIZE}"
        )
        
        results.extend(batch_results)

    return results

def write_extended_log(results: List[Dict[str, Any]]):
    """Write the extended budget results to CSV."""
    if not results:
        logging.warning("No results to write.")
        # Write empty file with headers to indicate completion
        headers = [
            "instance_id", "turns_to_converge", "convergence_status", 
            "path_coverage", "divergence_from_ground_truth", "extended_run", "extended_limit"
        ]
        with open(EXTENDED_LOG_PATH, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=headers)
            writer.writeheader()
        return

    # Ensure all required fields exist, adding extended metadata
    enriched_results = []
    for r in results:
        enriched = {
            "instance_id": r.get("instance_id"),
            "turns_to_converge": r.get("turns_to_converge"),
            "convergence_status": r.get("convergence_status"),
            "path_coverage": r.get("path_coverage"),
            "divergence_from_ground_truth": r.get("divergence_from_ground_truth"),
            "extended_run": True,
            "extended_limit": EXTENDED_TURN_LIMIT
        }
        enriched_results.append(enriched)

    with open(EXTENDED_LOG_PATH, "w", newline="", encoding="utf-8") as f:
        fieldnames = list(enriched_results[0].keys())
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(enriched_results)

    logging.info(f"Wrote {len(enriched_results)} results to {EXTENDED_LOG_PATH}")

def main():
    """Entry point for the extended budget validation run."""
    configure_logging(level=logging.INFO)
    logging.info("Starting Extended Budget Validation Run (T028)")

    try:
        # 1. Identify failures
        failures = load_failure_instances()
        
        if not failures:
            logging.info("No failures found. Creating empty extended log.")
            write_extended_log([])
            return

        # 2. Re-run with extended limit
        extended_results = re_run_extended_budget(failures)

        # 3. Write results
        write_extended_log(extended_results)

        logging.info("Extended Budget Validation Run completed successfully.")

    except Exception as e:
        logging.error(f"Extended Budget Validation Run failed: {e}")
        raise

if __name__ == "__main__":
    main()
