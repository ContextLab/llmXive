"""
T027: Write execution results to data/processed/execution_log.csv.

This script reads the raw execution data generated by the RM executor and batch processor,
calculates divergence metrics against the ground truth (as perturbed by T015/T024),
and writes the final structured CSV to data/processed/execution_log.csv.

It relies on:
  - data/processed/raw_execution_results.jsonl (output of T026)
  - data/raw/logical_puzzles.jsonl (input from T016, containing ground_truth_path)

It uses:
  - code/execution_metrics.py (for divergence calculation)
  - code/utils/graph_utils.py (for path parsing if needed)
"""
import os
import json
import csv
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional

# Import from project modules as defined in API surface
from execution_metrics import (
    load_execution_log,
    load_puzzles_metadata,
    calculate_divergence_metrics,
    write_execution_log_with_metrics
)
from utils.logging_utils import configure_logging

# Configure logging
logger = logging.getLogger(__name__)
configure_logging(level=logging.INFO)

def main():
    """
    Main entry point for T027.
    Reads raw execution results, merges with puzzle metadata, calculates metrics,
    and writes the final CSV.
    """
    # Define paths relative to project root
    # Note: The script is expected to be run from the project root or code/ directory
    # We use Path(__file__).resolve().parent to find the code directory, then traverse up
    project_root = Path(__file__).resolve().parent.parent
    data_dir = project_root / "data"
    raw_results_path = data_dir / "processed" / "raw_execution_results.jsonl"
    puzzles_path = data_dir / "raw" / "logical_puzzles.jsonl"
    output_path = data_dir / "processed" / "execution_log.csv"

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    if not raw_results_path.exists():
        logger.error(f"Raw execution results not found at: {raw_results_path}")
        logger.error("Ensure T026 (batch_processor) has run successfully.")
        raise FileNotFoundError(f"Missing raw execution results: {raw_results_path}")

    if not puzzles_path.exists():
        logger.error(f"Puzzle metadata not found at: {puzzles_path}")
        logger.error("Ensure T016 (graph_generator) has run successfully.")
        raise FileNotFoundError(f"Missing puzzle metadata: {puzzles_path}")

    logger.info(f"Loading raw execution results from: {raw_results_path}")
    raw_results = load_execution_log(raw_results_path)
    logger.info(f"Loaded {len(raw_results)} execution records.")

    logger.info(f"Loading puzzle metadata from: {puzzles_path}")
    puzzles_metadata = load_puzzles_metadata(puzzles_path)
    logger.info(f"Loaded metadata for {len(puzzles_metadata)} puzzles.")

    # Create a lookup dictionary for puzzles by instance_id for O(1) access
    puzzle_lookup = {p['instance_id']: p for p in puzzles_metadata}

    logger.info("Calculating divergence metrics and formatting output...")
    
    # Prepare the final rows for CSV
    final_rows = []
    
    for record in raw_results:
        instance_id = record.get('instance_id')
        if not instance_id or instance_id not in puzzle_lookup:
            logger.warning(f"Skipping record with missing or unknown instance_id: {instance_id}")
            continue

        puzzle_data = puzzle_lookup[instance_id]
        
        # Extract fields required by T027
        # The raw record should have: turns_to_converge, convergence_status, path_coverage
        # We need to calculate divergence_from_ground_truth
        
        turns_to_converge = record.get('turns_to_converge')
        convergence_status = record.get('convergence_status')
        path_coverage = record.get('path_coverage')
        
        # Calculate divergence
        # The record should contain the model's predicted path (or graph structure)
        # The puzzle_data contains the 'ground_truth_path' (perturbed)
        model_path = record.get('predicted_path') # Assumed to be in raw results
        ground_truth_path = puzzle_data.get('ground_truth_path')
        
        divergence = 0.0
        if model_path and ground_truth_path:
            try:
                divergence = calculate_divergence_metrics(model_path, ground_truth_path)
            except Exception as e:
                logger.warning(f"Failed to calculate divergence for {instance_id}: {e}")
                divergence = float('nan') # Or some error code
        elif not model_path and convergence_status == 'failure':
            # If it failed, we might not have a path, or we have a partial one.
            # If no path was generated, divergence is undefined or max.
            # For now, we set it to NaN or a specific indicator if the column allows.
            # The task asks for a value. Let's assume 1.0 (max divergence) if no path found on failure.
            divergence = 1.0
        else:
            logger.warning(f"No path data for {instance_id}, setting divergence to NaN.")
            divergence = float('nan')

        row = {
            'instance_id': instance_id,
            'turns_to_converge': turns_to_converge,
            'convergence_status': convergence_status,
            'path_coverage': path_coverage,
            'divergence_from_ground_truth': divergence
        }
        final_rows.append(row)

    logger.info(f"Writing {len(final_rows)} rows to: {output_path}")
    write_execution_log_with_metrics(final_rows, output_path)
    
    logger.info("T027 completed successfully.")

if __name__ == "__main__":
    main()
