"""
quickstart_validation.py

This script validates that the steps described in ``quickstart.md`` have been
successfully executed.  It checks for the existence and basic integrity of
the key artefacts produced by the pipeline (raw data, processed data,
model artefacts, evaluation results, and visualisations).

The validation logic re‑uses the helper functions defined in
``code/validation/validate_quickstart.py`` which provide low‑level checks
for file existence, non‑emptiness, JSON structure and CSV column headers.

The script produces a JSON report at ``data/logs/quickstart_validation_report.json``.
The report contains a per‑file status (``passed``/``failed``) together with an
optional error message.
"""

import os
import json
import logging
from pathlib import Path
from typing import Dict, List, Tuple

# Import the low‑level validators from the existing module.
from validation.validate_quickstart import (
    validate_file_exists,
    validate_file_not_empty,
    validate_json_structure,
    validate_csv_structure,
    run_quickstart_validation,
    main as validate_quickstart_main,
)

# Configure a simple logger that writes to the same log directory used by the
# rest of the project.
LOG_DIR = Path("data/logs")
LOG_DIR.mkdir(parents=True, exist_ok=True)
LOG_FILE = LOG_DIR / "quickstart_validation.log"

logging.basicConfig(
    filename=LOG_FILE,
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(message)s",
)
logger = logging.getLogger(__name__)

# -------------------------------------------------------------------------
# Definition of the artefacts that quickstart.md is expected to produce.
# -------------------------------------------------------------------------
# The keys are the relative paths (from the repository root) to the files.
# The values indicate the type of validation that should be performed.
#
# Types:
#   - "csv": check existence, non‑emptiness and that required columns are present.
#   - "json": check existence, non‑emptiness and that the file can be parsed as JSON.
#   - "png": check existence and that the file is not empty (size > 0 bytes).
#   - "dir": check that the directory exists (no further content checks).
REQUIRED_ARTIFACTS: Dict[str, Tuple[str, List[str]]] = {
    # Raw dataset
    "data/raw/esol.csv": ("csv", ["smiles", "logS"]),
    # Processed graphs (stored as a generic binary – we only check existence)
    "data/processed/cleaned_graphs.pt": ("dir", []),
    # Train/validation/test split indices
    "data/processed/split_indices.json": ("json", []),
    # Baseline Random Forest model & metrics
    "models/baseline_rf.pkl": ("dir", []),
    "results/baseline_metrics.json": ("json", ["rmse", "r2"]),
    # GNN model & predictions
    "models/gnn_mpnn.pt": ("dir", []),
    "results/gnn_predictions.csv": ("csv", ["smiles", "prediction"]),
    "results/gnn_metrics.json": ("json", ["rmse", "r2"]),
    # Model comparison & final report
    "results/model_comparison.json": ("json", ["rmse_delta"]),
    "results/final_report.json": ("json", ["rmse_baseline", "rmse_gnn", "p_value", "power"]),
    # Visualisations (at least five PNG files are required)
    # We will validate any file matching the pattern below exists and is non‑empty.
    # The concrete filenames are generated by the pipeline; we simply check the
    # directory contains the expected count.
    "results/feature_importance": ("png_dir", []),
}

def validate_png_directory(png_dir: Path) -> Tuple[bool, str]:
    """
    Validate that ``png_dir`` contains at least five non‑empty ``.png`` files.
    """
    if not png_dir.is_dir():
        return False, f"Directory {png_dir} does not exist."
    png_files = list(png_dir.glob("*.png"))
    if len(png_files) < 5:
        return (
            False,
            f"Expected at least 5 PNG files in {png_dir}, found {len(png_files)}.",
        )
    for f in png_files:
        if f.stat().st_size == 0:
            return False, f"PNG file {f} is empty."
    return True, ""

def run_validation() -> Dict[str, Dict[str, str]]:
    """
    Execute validation for all required artefacts.

    Returns
    -------
    dict
        Mapping from artefact path to a dict with ``status`` (passed/failed)
        and an optional ``message`` describing the failure.
    """
    report: Dict[str, Dict[str, str]] = {}

    for rel_path, (art_type, required_fields) in REQUIRED_ARTIFACTS.items():
        path = Path(rel_path)

        try:
            if art_type == "csv":
                # Existence + non‑emptiness
                validate_file_exists(str(path))
                validate_file_not_empty(str(path))
                # Validate required columns
                validate_csv_structure(str(path), required_fields)
            elif art_type == "json":
                validate_file_exists(str(path))
                validate_file_not_empty(str(path))
                validate_json_structure(str(path), required_fields)
            elif art_type == "png":
                validate_file_exists(str(path))
                validate_file_not_empty(str(path))
            elif art_type == "dir":
                # For binary artefacts we only need to ensure the file exists.
                validate_file_exists(str(path))
            elif art_type == "png_dir":
                passed, msg = validate_png_directory(path)
                if not passed:
                    raise AssertionError(msg)
            else:
                raise ValueError(f"Unsupported artefact type: {art_type}")

            report[rel_path] = {"status": "passed", "message": ""}
            logger.info("Validation passed for %s", rel_path)

        except Exception as exc:  # pylint: disable=broad-except
            # Capture any validation error and continue with the rest.
            report[rel_path] = {"status": "failed", "message": str(exc)}
            logger.error("Validation failed for %s: %s", rel_path, exc)

    return report

def write_report(report: Dict[str, Dict[str, str]]) -> None:
    """
    Write the validation report as JSON.
    """
    output_path = LOG_DIR / "quickstart_validation_report.json"
    with output_path.open("w", encoding="utf-8") as fp:
        json.dump(report, fp, indent=2)
    logger.info("Quickstart validation report written to %s", output_path)

def main() -> None:
    """
    Entry point for the quickstart validation script.

    The function first runs any high‑level validation logic already provided
    by ``validation.validate_quickstart.run_quickstart_validation`` (if that
    function is implemented).  It then performs the detailed artefact checks
    defined in this module and writes a JSON report.
    """
    logger.info("Starting quickstart validation...")

    # Run any generic validation that may be defined in the existing module.
    try:
        run_quickstart_validation()
        logger.info("Generic quickstart validation completed successfully.")
    except Exception as exc:  # pylint: disable=broad-except
        logger.warning(
            "Generic quickstart validation raised an exception but will be ignored: %s",
            exc,
        )

    # Perform the artefact‑specific validation.
    report = run_validation()
    write_report(report)

    # Summarise the outcome on stdout for human operators.
    passed = sum(1 for r in report.values() if r["status"] == "passed")
    total = len(report)
    logger.info("Quickstart validation finished: %d/%d artefacts passed.", passed, total)
    print(f"Quickstart validation finished: {passed}/{total} artefacts passed.")
    if passed != total:
        print("Some artefacts failed validation – see the log for details.")

if __name__ == "__main__":
    main()