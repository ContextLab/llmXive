"""
Statistical Power Review Implementation for Task T049.

This module analyzes the output of T028 (statistical_test.py) to confirm
statistical power > 0.8 or documents the limitation and its impact.
"""
import os
import sys
import json
import logging
import argparse
from pathlib import Path
from typing import Dict, Any, Optional

# Setup project paths
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
RESULTS_DIR = PROJECT_ROOT / "results"
REPORTS_DIR = PROJECT_ROOT / "docs" / "reports"
LOGS_DIR = PROJECT_ROOT / "data" / "logs"

def setup_review_logger() -> logging.Logger:
    """Setup a dedicated logger for the power review process."""
    logger = logging.getLogger("statistical_power_review")
    logger.setLevel(logging.INFO)

    if not logger.handlers:
        # File handler
        log_file = LOGS_DIR / "power_review.log"
        log_file.parent.mkdir(parents=True, exist_ok=True)
        fh = logging.FileHandler(log_file)
        fh.setLevel(logging.INFO)

        # Console handler
        ch = logging.StreamHandler()
        ch.setLevel(logging.INFO)

        formatter = logging.Formatter(
            '%(asctime)s - %(name)s - %(levelname)s - %(message)s'
        )
        fh.setFormatter(formatter)
        ch.setFormatter(formatter)

        logger.addHandler(fh)
        logger.addHandler(ch)

    return logger

def load_statistical_results(logger: logging.Logger) -> Dict[str, Any]:
    """
    Load the statistical test results generated by T028.

    Expected file: results/statistical_test_results.json
    """
    input_path = RESULTS_DIR / "statistical_test_results.json"

    if not input_path.exists():
        logger.error(f"Statistical results file not found: {input_path}")
        raise FileNotFoundError(
            f"Required input file missing: {input_path}. "
            "Ensure T028 (statistical_test.py) has been executed successfully."
        )

    try:
        with open(input_path, 'r') as f:
            data = json.load(f)
        logger.info(f"Successfully loaded statistical results from {input_path}")
        return data
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse JSON from {input_path}: {e}")
        raise

def interpret_statistical_power(power_value: float, logger: logging.Logger) -> Dict[str, Any]:
    """
    Interpret the statistical power value.

    Standard threshold is 0.80.
    Returns a dictionary with interpretation details.
    """
    threshold = 0.80
    is_sufficient = power_value >= threshold

    if is_sufficient:
        status = "SUFFICIENT"
        interpretation = (
            f"The calculated statistical power ({power_value:.4f}) exceeds the "
            f"standard threshold of {threshold}. This indicates a low probability "
            f"(1 - {power_value:.4f}) of Type II error (failing to detect a true "
            f"effect). The sample size is adequate for the observed effect size."
        )
    else:
        status = "INSUFFICIENT"
        interpretation = (
            f"The calculated statistical power ({power_value:.4f}) is below the "
            f"standard threshold of {threshold}. This indicates a high probability "
            f"({1 - power_value:.4f}) of Type II error. The study may lack "
            f"sensitivity to detect the observed effect size, and results should "
            f"be interpreted with caution."
        )

    return {
        "power_value": power_value,
        "threshold": threshold,
        "status": status,
        "interpretation": interpretation,
        "is_sufficient": is_sufficient
    }

def analyze_effect_size(cohens_d: float, logger: logging.Logger) -> Dict[str, Any]:
    """
    Analyze the effect size (Cohen's d) to provide context for the power analysis.

    Cohen's d conventions:
    - 0.2: Small effect
    - 0.5: Medium effect
    - 0.8: Large effect
    """
    abs_d = abs(cohens_d)

    if abs_d < 0.2:
        magnitude = "Negligible"
    elif abs_d < 0.5:
        magnitude = "Small"
    elif abs_d < 0.8:
        magnitude = "Medium"
    else:
        magnitude = "Large"

    return {
        "cohens_d": cohens_d,
        "magnitude": magnitude,
        "interpretation": (
            f"The effect size (Cohen's d = {cohens_d:.4f}) is considered {magnitude}. "
            f"This magnitude influences the required sample size to achieve sufficient power."
        )
    }

def generate_power_review_report(
    stat_results: Dict[str, Any],
    logger: logging.Logger
) -> Dict[str, Any]:
    """
    Generate the comprehensive power review report.

    Combines power interpretation, effect size analysis, and limitations.
    """
    # Extract values from statistical results
    power = stat_results.get("post_hoc_power")
    cohens_d = stat_results.get("effect_size_cohens_d")
    p_value = stat_results.get("p_value")
    n_samples = stat_results.get("n_samples", "N/A")

    if power is None:
        logger.error("Statistical results missing 'post_hoc_power' key.")
        raise ValueError("Invalid statistical results format: missing 'post_hoc_power'.")

    if cohens_d is None:
        logger.error("Statistical results missing 'effect_size_cohens_d' key.")
        raise ValueError("Invalid statistical results format: missing 'effect_size_cohens_d'.")

    # Perform analyses
    power_interpretation = interpret_statistical_power(power, logger)
    effect_analysis = analyze_effect_size(cohens_d, logger)

    # Determine limitations and impact
    limitations = []
    impact_statement = ""

    if not power_interpretation["is_sufficient"]:
        limitations.append(
            "Statistical power is below the recommended 0.80 threshold."
        )
        impact_statement = (
            "Due to insufficient power, there is an increased risk of Type II error. "
            "While the observed difference may be statistically significant (p < 0.05), "
            "the robustness of this finding is limited. Future studies with larger "
            "sample sizes are recommended to confirm the effect."
        )
    else:
        impact_statement = (
            "The study has sufficient statistical power to detect the observed effect. "
            "The findings regarding the difference between the Random Forest baseline "
            "and the GNN model are robust with respect to sample size."
        )

    report = {
        "task_id": "T049",
        "analysis_date": "2023-10-27", # Placeholder, actual date handled by logger
        "input_source": "results/statistical_test_results.json",
        "statistical_power": power_interpretation,
        "effect_size_analysis": effect_analysis,
        "statistical_significance": {
            "p_value": p_value,
            "is_significant": p_value < 0.05 if p_value is not None else False
        },
        "sample_size": n_samples,
        "limitations": limitations,
        "impact_on_interpretation": impact_statement,
        "conclusion": (
            f"Power Review Complete. Power: {power:.4f} ({power_interpretation['status']}). "
            f"Effect Size: {cohens_d:.4f} ({effect_analysis['magnitude']}). "
            f"Conclusion: {impact_statement}"
        )
    }

    return report

def save_review_report(report: Dict[str, Any], logger: logging.Logger) -> Path:
    """
    Save the review report to docs/reports/statistical_power_review.json.
    """
    output_dir = REPORTS_DIR
    output_dir.mkdir(parents=True, exist_ok=True)

    output_path = output_dir / "statistical_power_review.json"

    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)

    logger.info(f"Power review report saved to {output_path}")
    return output_path

def main():
    """Main entry point for the Statistical Power Review task."""
    parser = argparse.ArgumentParser(
        description="Analyze statistical power from T028 results."
    )
    parser.add_argument(
        "--input",
        type=str,
        default=str(RESULTS_DIR / "statistical_test_results.json"),
        help="Path to the statistical test results JSON file."
    )
    parser.add_argument(
        "--output",
        type=str,
        default=str(REPORTS_DIR / "statistical_power_review.json"),
        help="Path to save the power review report."
    )
    args = parser.parse_args()

    logger = setup_review_logger()
    logger.info("Starting Statistical Power Review (T049)...")

    try:
        # 1. Load results from T028
        stat_results = load_statistical_results(logger)

        # 2. Generate report
        review_report = generate_power_review_report(stat_results, logger)

        # 3. Save report
        output_path = Path(args.output)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, 'w') as f:
            json.dump(review_report, f, indent=2)

        logger.info(f"Review complete. Report saved to {output_path}")
        print(f"\n--- Power Review Summary ---")
        print(f"Power: {review_report['statistical_power']['power_value']:.4f}")
        print(f"Status: {review_report['statistical_power']['status']}")
        print(f"Conclusion: {review_report['conclusion']}")

    except FileNotFoundError as e:
        logger.critical(str(e))
        sys.exit(1)
    except ValueError as e:
        logger.critical(str(e))
        sys.exit(1)
    except Exception as e:
        logger.critical(f"Unexpected error during power review: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()