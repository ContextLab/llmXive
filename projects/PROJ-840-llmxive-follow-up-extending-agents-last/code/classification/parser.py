from typing import Dict, Any, Optional, List
import json
import re
from pathlib import Path
import hashlib

def parse_ale_trace(input_path: Path) -> Dict[str, Any]:
    """
    Parses an ALE trace file and extracts environment state and agent actions.
    
    This implementation specifically handles the golden subset generated by T015/T015b.
    It detects compound actions (e.g., "read file A and write to file B") and splits them
    into distinct step entries with single actions to enable atomic state comparison.
    
    The output JSON preserves the original order while enabling step-level state comparison.
    """
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    with open(input_path, 'r') as f:
        data = json.load(f)
    
    # Ensure data is a list of traces
    if not isinstance(data, list):
        data = [data]
    
    processed_traces = []
    
    for trace in data:
        if not isinstance(trace, dict):
            continue
        
        # Extract basic trace metadata
        trace_id = trace.get('trace_id', 'unknown')
        ground_truth = trace.get('ground_truth_label', 'unknown')
        task_description = trace.get('task_description', '')
        
        # Get step state information
        step_state = trace.get('step_state', {})
        
        # Process files and variables into atomic steps
        files = step_state.get('files', [])
        variables = step_state.get('variables', [])
        
        # Detect and split compound actions
        atomic_steps = []
        
        # Analyze task description for compound actions
        # Pattern: "action1 and action2" or "action1, action2"
        compound_pattern = r'(\w+(?:\s+\w+)*)\s+(?:and|,)\s+(\w+(?:\s+\w+)*)'
        matches = re.findall(compound_pattern, task_description)
        
        # If we find compound actions, split them
        if matches:
            step_id_counter = 0
            for match in matches:
                action1, action2 = match
                # Create two atomic steps
                step_id_counter += 1
                atomic_steps.append({
                    "step_id": f"{trace_id}_step_{step_id_counter:03d}",
                    "action": action1.strip(),
                    "action_sequence": [action1.strip()],
                    "state_snapshot": {
                        "files": files,
                        "variables": variables
                    }
                })
                
                step_id_counter += 1
                atomic_steps.append({
                    "step_id": f"{trace_id}_step_{step_id_counter:03d}",
                    "action": action2.strip(),
                    "action_sequence": [action1.strip(), action2.strip()],
                    "state_snapshot": {
                        "files": files,
                        "variables": variables
                    }
                })
        else:
            # No compound actions detected, create a single step
            # Extract action from task description or use a default
            action = task_description.split('.')[0] if task_description else "unknown_action"
            atomic_steps.append({
                "step_id": f"{trace_id}_step_001",
                "action": action.strip(),
                "action_sequence": [action.strip()],
                "state_snapshot": {
                    "files": files,
                    "variables": variables
                }
            })
        
        # Build the processed trace
        processed_trace = {
            "trace_id": trace_id,
            "ground_truth_label": ground_truth,
            "task_description": task_description,
            "atomic_steps": atomic_steps,
            "original_step_state": step_state,
            "total_steps": len(atomic_steps)
        }
        
        processed_traces.append(processed_trace)
    
    return processed_traces

def main():
    import argparse
    
    parser = argparse.ArgumentParser(description="Parse ALE execution traces with atomic step splitting")
    parser.add_argument("--input", type=str, default="data/raw/golden_subset.json", help="Input JSON file")
    parser.add_argument("--output", type=str, default="data/processed/classified_traces.json", help="Output JSON file")
    
    args = parser.parse_args()
    input_path = Path(args.input)
    output_path = Path(args.output)
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    try:
        parsed_data = parse_ale_trace(input_path)
        
        with open(output_path, 'w') as f:
            json.dump(parsed_data, f, indent=2)
        
        total_steps = sum(trace.get('total_steps', 0) for trace in parsed_data)
        print(f"Parsed {len(parsed_data)} traces into {total_steps} atomic steps to {output_path}")
    except Exception as e:
        print(f"Error parsing traces: {e}")
        raise

if __name__ == "__main__":
    main()