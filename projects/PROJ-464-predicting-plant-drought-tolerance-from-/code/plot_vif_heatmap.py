"""
Task T045: Generate VIF Heatmap Visualization.

Reads the VIF report generated by T043 (state/vif_report.yaml) and the
model results (data/derived/model_results.csv) to create a heatmap
visualizing collinearity among predictors.

Output: results/figures/vif_heatmap.png
"""
import os
import sys
import logging
from pathlib import Path
from typing import Dict, Any, Optional
import pandas as pd
import numpy as np
import yaml
import matplotlib.pyplot as plt
import seaborn as sns

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from config import ensure_directories
from analysis import generate_vif_report

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler(project_root / 'state' / 'pipeline.log')
    ]
)
logger = logging.getLogger(__name__)

def load_vif_report(report_path: Path) -> Dict[str, Any]:
    """Load the VIF report from YAML."""
    if not report_path.exists():
        raise FileNotFoundError(f"VIF report not found at {report_path}. "
                                "Run T043 (generate_vif_report) first.")
    
    with open(report_path, 'r') as f:
        return yaml.safe_load(f)

def load_model_results(results_path: Path) -> pd.DataFrame:
    """Load model results to correlate with VIF data."""
    if not results_path.exists():
        raise FileNotFoundError(f"Model results not found at {results_path}. "
                                "Run T026 (generate model results) first.")
    return pd.read_csv(results_path)

def extract_vif_matrix(vif_data: Dict[str, Any]) -> pd.DataFrame:
    """
    Extract VIF scores into a matrix format suitable for heatmap.
    
    Expected structure in vif_report.yaml:
    {
      "vif_scores": [
        {"predictor": "depth", "vif": 1.2},
        {"predictor": "surface_area", "vif": 3.4},
        ...
      ],
      "correlation_matrix": {
        "depth": {"depth": 1.0, "surface_area": 0.85, ...},
        ...
      }
    }
    """
    # Prefer correlation matrix if available, otherwise just list VIFs
    if "correlation_matrix" in vif_data:
        corr_data = vif_data["correlation_matrix"]
        df = pd.DataFrame(corr_data)
        # Ensure diagonal is 1.0 and symmetric if needed
        return df
    elif "vif_scores" in vif_data:
        # If we only have VIFs (not correlations), we can't make a true
        # correlation heatmap, but we can visualize VIF magnitude per predictor
        # against a dummy axis or just list them. 
        # However, the task asks for a heatmap of VIF scores for *all* predictors.
        # A common pattern is to show the VIF of each predictor as a bar or
        # a 1xN heatmap. Let's try to construct a "VIF vs Predictor" heatmap.
        scores = vif_data["vif_scores"]
        if not scores:
            raise ValueError("No VIF scores found in report.")
        
        df_vif = pd.DataFrame(scores)
        # Pivot to 1xN matrix for heatmap
        df_vif = df_vif.set_index('predictor')['vif'].to_frame().T
        return df_vif
    else:
        raise ValueError("VIF report lacks 'vif_scores' or 'correlation_matrix'.")

def generate_vif_heatmap(vif_df: pd.DataFrame, output_path: Path):
    """Generate and save the VIF heatmap."""
    plt.figure(figsize=(10, 6))
    
    # Check if it's a correlation matrix (NxN) or VIF list (1xN)
    if vif_df.shape[0] == 1 and vif_df.shape[1] > 1:
        # Single row of VIF scores
        ax = sns.heatmap(vif_df, annot=True, cmap='YlOrRd', 
                         fmt='.2f', cbar_kws={'label': 'VIF Score'})
        plt.title('Variance Inflation Factor (VIF) per Predictor')
        plt.xlabel('Predictor')
        plt.ylabel('')
        plt.xticks(rotation=45)
    else:
        # Correlation matrix or NxN VIF matrix (unlikely but possible)
        ax = sns.heatmap(vif_df, annot=True, cmap='coolwarm', 
                         fmt='.2f', cbar_kws={'label': 'Value'})
        plt.title('VIF / Correlation Matrix Heatmap')
        plt.xticks(rotation=45)
        plt.yticks(rotation=0)
    
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()
    logger.info(f"VIF heatmap saved to {output_path}")

def main():
    """Main entry point for T045."""
    logger.info("Starting VIF Heatmap Generation (T045)...")
    
    # Ensure output directories exist
    ensure_directories()
    
    # Define paths
    vif_report_path = Path("state/vif_report.yaml")
    model_results_path = Path("data/derived/model_results.csv")
    output_path = Path("results/figures/vif_heatmap.png")
    
    # Load data
    try:
        vif_data = load_vif_report(vif_report_path)
        logger.info("VIF report loaded successfully.")
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
        
    try:
        # We load this to ensure the pipeline state is consistent, 
        # though the heatmap logic primarily uses vif_data.
        model_results = load_model_results(model_results_path)
        logger.info("Model results loaded successfully.")
    except FileNotFoundError as e:
        logger.warning(str(e))
        logger.info("Proceeding with VIF heatmap generation without model results.")

    # Process and Generate
    try:
        vif_matrix = extract_vif_matrix(vif_data)
        generate_vif_heatmap(vif_matrix, output_path)
        logger.info("Task T045 completed successfully.")
    except Exception as e:
        logger.error(f"Failed to generate VIF heatmap: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
