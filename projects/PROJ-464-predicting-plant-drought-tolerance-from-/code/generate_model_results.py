def load_precomputed_results() -> Dict[str, pd.DataFrame]:
    """
    Loads pre-computed model results from the intermediate artifacts generated by T023a, T023c, T024b.
    Expected files:
      - data/derived/ols_results.csv (or similar from T023a)
      - data/derived/rf_results.csv (from T023c)
      - data/derived/pgls_results.csv (from T024b)
    
    Since T023a, T023c, T024b are marked as completed in the task list but their specific output files
    might vary slightly in naming convention in a real run, we check for standard names or the specific
    outputs described in the task logic.
    
    If files are missing, we assume the previous tasks generated them in a standard location or we
    need to look for them. For this implementation, we assume the previous tasks wrote to:
    - data/derived/ols_results.csv
    - data/derived/rf_results.csv
    - data/derived/pgls_results.csv
    
    If these specific files don't exist, we might need to infer from the 'models.py' execution or
    the 'analysis.py' execution. However, the task T026 explicitly says "Aggregate results from T023a, T023c, T024b".
    
    We will attempt to load these. If they are missing, we raise an error as per "Fail loudly" constraint.
    """
    results = {}
    base_path = Path(CONFIG.data_derived_dir)
    
    # Define expected files based on standard naming for these tasks
    expected_files = {
        'ols': base_path / 'ols_results.csv',
        'rf': base_path / 'rf_results.csv',
        'pgls': base_path / 'pgls_results.csv'
    }
    
    missing = []
    for key, path in expected_files.items():
        if not path.exists():
            missing.append(str(path))
        else:
            try:
                df = pd.read_csv(path)
                results[key] = df
                logger.info(f"Loaded {key} results from {path}")
            except Exception as e:
                logger.error(f"Failed to load {key} results from {path}: {e}")
                raise e
    
    if missing:
        error_msg = f"Missing pre-computed result files required for aggregation: {', '.join(missing)}. Ensure T023a, T023c, and T024b have successfully generated their outputs."
        logger.error(error_msg)
        raise FileNotFoundError(error_msg)
        
    return results

def aggregate_ols_results(ols_df: pd.DataFrame, alpha: float = 0.05) -> pd.DataFrame:
    """
    Aggregates OLS/Ridge/Lasso results from T023a.
    Expected columns in ols_df: model_type, predictor, coefficient, p_value, r2, (maybe adj_r2)
    Returns a DataFrame formatted for the final model_results.csv.
    """
    if ols_df.empty:
        return pd.DataFrame()
    
    # Ensure column types
    required_cols = ['model_type', 'predictor', 'coefficient', 'p_value', 'r2']
    # Adjust column names if they differ slightly in the source
    if 'adj_p_value' not in ols_df.columns:
        # We will calculate adjusted p-values later in the main function or here if needed
        # For now, assume we just pass through and adjust later
        pass
    
    # Calculate adjusted p-values (Bonferroni) if not present
    # Assuming multiple predictors per model type, we adjust across all tests or per model type?
    # Usually per family of tests. Let's assume we adjust across all rows for this aggregation step 
    # or we rely on the multiple_comparison_correction from analysis.py. 
    # The task T025 handles correction. We assume the input df might already have it or we calculate it here.
    # Let's calculate it here to be safe if not present.
    if 'adj_p_value' not in ols_df.columns:
        n_tests = len(ols_df)
        ols_df['adj_p_value'] = ols_df['p_value'].apply(lambda p: min(p * n_tests, 1.0))
    
    # Ensure all required columns exist
    for col in required_cols:
        if col not in ols_df.columns:
            raise ValueError(f"Missing required column '{col}' in OLS results.")
    
    return ols_df[['model_type', 'predictor', 'coefficient', 'p_value', 'r2', 'adj_p_value']]

def aggregate_rf_results(rf_df: pd.DataFrame, alpha: float = 0.05) -> pd.DataFrame:
    """
    Aggregates Random Forest results from T023c.
    RF typically provides feature importances, not coefficients.
    However, the schema requires 'coefficient'. We will map 'importance' to 'coefficient' 
    or use a placeholder if the schema strictly requires a regression coefficient.
    Given the schema: `coefficient` (float). For RF, we might use the mean decrease in impurity 
    or permutation importance as the 'effect size' proxy.
    Let's assume the input rf_df has 'feature', 'importance', 'r2'.
    We will map 'feature' -> 'predictor', 'importance' -> 'coefficient'.
    """
    if rf_df.empty:
        return pd.DataFrame()
    
    required_cols = ['model_type', 'predictor', 'coefficient', 'p_value', 'r2']
    
    # Standardize column names if needed
    if 'predictor' not in rf_df.columns and 'feature' in rf_df.columns:
        rf_df['predictor'] = rf_df['feature']
    
    if 'coefficient' not in rf_df.columns and 'importance' in rf_df.columns:
        rf_df['coefficient'] = rf_df['importance']
    
    # RF doesn't have p-values naturally. We might have computed them via permutation tests in T023c.
    # If not present, we set to NaN or 1.0. Let's assume T023c computed them.
    if 'p_value' not in rf_df.columns:
        logger.warning("p_value not found in RF results. Setting to 1.0 (non-significant).")
        rf_df['p_value'] = 1.0
    
    if 'adj_p_value' not in rf_df.columns:
        n_tests = len(rf_df)
        rf_df['adj_p_value'] = rf_df['p_value'].apply(lambda p: min(p * n_tests, 1.0))
    
    # Ensure required columns
    for col in required_cols:
        if col not in rf_df.columns:
            raise ValueError(f"Missing required column '{col}' in RF results.")
    
    return rf_df[['model_type', 'predictor', 'coefficient', 'p_value', 'r2', 'adj_p_value']]

def aggregate_pgl_results(pgls_df: pd.DataFrame, alpha: float = 0.05) -> pd.DataFrame:
    """
    Aggregates PGLS results from T024b.
    Expected columns: model_type, predictor, coefficient, p_value, r2 (or pseudo-r2), lambda, kappa, etc.
    """
    if pgls_df.empty:
        return pd.DataFrame()
    
    required_cols = ['model_type', 'predictor', 'coefficient', 'p_value', 'r2']
    
    # Standardize if needed
    if 'predictor' not in pgls_df.columns and 'variable' in pgls_df.columns:
        pgls_df['predictor'] = pgls_df['variable']
    
    if 'adj_p_value' not in pgls_df.columns:
        n_tests = len(pgls_df)
        pgls_df['adj_p_value'] = pgls_df['p_value'].apply(lambda p: min(p * n_tests, 1.0))
    
    for col in required_cols:
        if col not in pgls_df.columns:
            raise ValueError(f"Missing required column '{col}' in PGLS results.")
    
    return pgls_df[['model_type', 'predictor', 'coefficient', 'p_value', 'r2', 'adj_p_value']]

def main():
    """
    Main entry point for T026.
    1. Loads results from T023a (OLS), T023c (RF), T024b (PGLS).
    2. Aggregates them into a single DataFrame.
    3. Validates against the schema.
    4. Saves to data/derived/model_results.csv.
    """
    ensure_directories()
    
    logger.info("Starting T026: Generate model_results.csv")
    
    try:
        # Load pre-computed results
        raw_results = load_precomputed_results()
        
        # Aggregate
        dfs = []
        if 'ols' in raw_results:
            dfs.append(aggregate_ols_results(raw_results['ols']))
        if 'rf' in raw_results:
            dfs.append(aggregate_rf_results(raw_results['rf']))
        if 'pgls' in raw_results:
            dfs.append(aggregate_pgl_results(raw_results['pgls']))
        
        if not dfs:
            raise ValueError("No results found to aggregate. Check if T023a, T023c, T024b produced valid outputs.")
        
        combined_df = pd.concat(dfs, ignore_index=True)
        
        # Ensure column order matches schema
        final_columns = ['model_type', 'predictor', 'coefficient', 'p_value', 'r2', 'adj_p_value']
        # Reindex to ensure order, filling missing with NaN if any (though we checked above)
        combined_df = combined_df.reindex(columns=final_columns)
        
        # Validate against schema
        logger.info("Validating aggregated results against schema...")
        # Assuming validate_model_results checks the file content or structure
        # We pass the dataframe or the path. Let's save first then validate, or validate in memory.
        # The function signature in validate_schemas says: validate_model_results
        # Let's assume it takes a DataFrame or path.
        
        # Save to file
        output_path = Path(CONFIG.data_derived_dir) / 'model_results.csv'
        combined_df.to_csv(output_path, index=False)
        logger.info(f"Saved model results to {output_path}")
        
        # Validate
        if not validate_model_results(output_path):
            logger.error("Validation failed. Model results do not meet schema requirements.")
            raise ValueError("Schema validation failed for model_results.csv")
        
        logger.info("T026 completed successfully.")
        
    except Exception as e:
        logger.error(f"T026 failed: {e}")
        raise e

if __name__ == "__main__":
    main()
