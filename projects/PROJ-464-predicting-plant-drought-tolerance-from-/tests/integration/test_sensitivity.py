"""
Integration tests for the sensitivity analysis pipeline (T038).

This test verifies that the sensitivity report generated by the pipeline
contains the expected metrics (threshold variation data or N/A justification)
as required by the specification.
"""
import os
import sys
import pytest
from pathlib import Path
import pandas as pd
import yaml
import logging

# Add project root to path to allow imports from code/
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from code.config import ensure_directories
from code.generate_sensitivity_report import main as generate_report_main

# Configure logging to capture output during tests
logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

@pytest.fixture(scope="module")
def setup_test_environment():
    """Ensure necessary directories exist for the test."""
    ensure_directories()
    return {
        "sensitivity_csv": PROJECT_ROOT / "data" / "derived" / "sensitivity_sweep_results.csv",
        "report_md": PROJECT_ROOT / "data" / "derived" / "sensitivity_report.md",
        "proxy_yaml": PROJECT_ROOT / "state" / "proxy_detection.yaml"
    }

def test_sensitivity_report_contains_expected_metrics(setup_test_environment):
    """
    Integration test: test_sensitivity_report_contains_expected_metrics.
    
    Asserts that the generated sensitivity report contains either:
    1. Threshold variation data (if a proxy was found and classification was built), OR
    2. An explicit N/A justification stating that classification was skipped 
       due to the lack of an independent tolerance proxy (Plan: No Circular Classification).
    
    This test runs the report generation logic and validates the output file content.
    """
    paths = setup_test_environment
    csv_path = paths["sensitivity_csv"]
    report_path = paths["report_md"]
    proxy_path = paths["proxy_yaml"]

    # Ensure the CSV exists first (generated by T028)
    if not csv_path.exists():
        pytest.fail(f"Required input file missing: {csv_path}. "
                    "Ensure T028 (run_sensitivity_analysis) has been executed successfully.")

    # Ensure the proxy status file exists
    if not proxy_path.exists():
        pytest.fail(f"Required proxy status file missing: {proxy_path}. "
                    "Ensure T027 (detect_tolerance_proxies) has been executed.")

    # Load proxy status to determine expected report content
    with open(proxy_path, 'r') as f:
        proxy_status = yaml.safe_load(f)
    
    has_proxy = proxy_status.get('has_proxy', False)
    logger.info(f"Proxy status detected: has_proxy={has_proxy}")

    # Run the report generation logic
    try:
        generate_report_main()
    except Exception as e:
        pytest.fail(f"Report generation failed with exception: {e}")

    # Verify the report file was created
    assert report_path.exists(), f"Sensitivity report not generated at {report_path}"

    # Read the report content
    with open(report_path, 'r') as f:
        report_content = f.read()

    # Validate content based on proxy status
    if has_proxy:
        # Case 1: Proxy exists -> Report should contain threshold variation data
        # Expected metrics: accuracy, precision, recall, F1, False Positive Rate, False Negative Rate
        expected_keywords = [
            "threshold",
            "accuracy",
            "precision",
            "recall",
            "F1",
            "False Positive Rate",
            "False Negative Rate"
        ]
        
        missing_keywords = []
        for keyword in expected_keywords:
            if keyword.lower() not in report_content.lower():
                missing_keywords.append(keyword)
        
        if missing_keywords:
            pytest.fail(
                f"Report for proxy-enabled run is missing expected metrics: {missing_keywords}. "
                f"Report content:\n{report_content}"
            )
        
        # Verify that a table or structured data regarding thresholds is present
        # (Checking for a common markdown table header or a list of threshold values)
        if "|" not in report_content and "threshold" not in report_content.lower():
            pytest.fail("Report does not appear to contain threshold variation data (no table or threshold values found).")
            
        logger.info("✓ Report correctly contains threshold variation data for proxy-enabled run.")

    else:
        # Case 2: No proxy -> Report should contain N/A justification
        # Expected text: "Classification skipped" or "N/A" or "not applicable"
        # Specific justification from T027b/T028: "Classification model not built due to lack of independent tolerance proxy"
        expected_phrases = [
            "Classification skipped",
            "N/A",
            "not applicable",
            "lack of independent tolerance proxy",
            "No Circular Classification"
        ]
        
        found_phrase = False
        for phrase in expected_phrases:
            if phrase.lower() in report_content.lower():
                found_phrase = True
                break
        
        if not found_phrase:
            pytest.fail(
                f"Report for non-proxy run does not contain the required N/A justification. "
                f"Expected phrases: {expected_phrases}. "
                f"Report content:\n{report_content}"
            )

        # Verify the CSV also reflects the N/A status
        df = pd.read_csv(csv_path)
        # Check if the CSV has a row indicating N/A or if it's empty/single row with N/A justification
        if len(df) > 0:
            # Check for a column indicating status or a row with N/A
            has_na_status = df.applymap(lambda x: isinstance(x, str) and "N/A" in str(x)).any().any()
            if not has_na_status:
                # Check if the first row contains the justification string
                first_row_str = " ".join(df.iloc[0].astype(str))
                if "N/A" not in first_row_str and "skipped" not in first_row_str.lower():
                    pytest.fail(
                        f"Sensitivity CSV does not reflect N/A status correctly. "
                        f"First row content: {first_row_str}"
                    )
        
        logger.info("✓ Report correctly contains N/A justification for non-proxy run.")

    logger.info("✓ Integration test passed: Sensitivity report contains expected metrics.")