"""
Install and verify SRA Toolkit via conda.

This script:
1. Installs 'sratoolkit' via conda (channel: bioconda).
2. Configures ~/.ncbi/settings with default user settings if missing.
3. Verifies installation by running 'prefetch --help'.
4. Exits with code 1 if any step fails (fail loudly).
"""

import os
import subprocess
import sys
from pathlib import Path


def run_command(cmd: list[str], description: str) -> None:
    """Run a shell command, raising an error if it fails."""
    print(f"--> {description}")
    print(f"    Command: {' '.join(cmd)}")
    try:
        result = subprocess.run(
            cmd,
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
        if result.stdout:
            # Print first few lines of output for verification
            lines = result.stdout.splitlines()
            for line in lines[:10]:
                print(f"    {line}")
            if len(lines) > 10:
                print(f"    ... ({len(lines) - 10} more lines)")
    except subprocess.CalledProcessError as e:
        print(f"ERROR: {description} failed.")
        print(f"    stderr: {e.stderr}")
        sys.exit(1)


def ensure_ncbi_settings() -> None:
    """Ensure ~/.ncbi/settings exists with default user settings."""
    ncbi_dir = Path.home() / ".ncbi"
    settings_file = ncbi_dir / "settings"

    if not ncbi_dir.exists():
        ncbi_dir.mkdir(parents=True, exist_ok=True)
        print(f"Created directory: {ncbi_dir}")

    if not settings_file.exists():
        # Create a minimal default settings file
        default_content = """
        [config]
        ; Default user settings for SRA Toolkit
        ; This file is generated by the pipeline setup script.

        [repository]
        ; Default repository location (optional, usually defaults to public)
        ; public = https://sra-download.ncbi.nlm.nih.gov/traces/sra/

        [user]
        ; User name for SRA Toolkit (optional, defaults to current user)
        ; name = pipeline_user

        [cache]
        ; Cache directory (optional, defaults to ~/.ncbi/cache)
        ; dir = ~/.ncbi/cache
        """
        settings_file.write_text(default_content)
        print(f"Created default settings file: {settings_file}")
    else:
        print(f"Settings file already exists: {settings_file}")


def verify_sra_toolkit() -> None:
    """Verify SRA Toolkit installation by running 'prefetch --help'."""
    print("\n--> Verifying SRA Toolkit installation...")
    run_command(
        ["prefetch", "--help"],
        "Running 'prefetch --help' to verify installation",
    )
    print("SUCCESS: SRA Toolkit is installed and accessible.")


def install_sra_toolkit() -> None:
    """Install SRA Toolkit via conda."""
    print("--> Checking for conda...")
    try:
        subprocess.run(
            ["conda", "--version"],
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
    except (subprocess.CalledProcessError, FileNotFoundError):
        print("ERROR: 'conda' is not found in PATH. Please install Miniconda/Anaconda.")
        sys.exit(1)

    print("--> Installing sratoolkit via conda (channel: bioconda)...")
    # Install sratoolkit from bioconda
    run_command(
        ["conda", "install", "-y", "-c", "bioconda", "sratoolkit"],
        "Installing sratoolkit via conda",
    )


def main() -> None:
    """Main entry point for SRA Toolkit installation and verification."""
    print("=" * 60)
    print("Installing and Verifying SRA Toolkit")
    print("=" * 60)

    install_sra_toolkit()
    ensure_ncbi_settings()
    verify_sra_toolkit()

    print("\n" + "=" * 60)
    print("SRA Toolkit installation and verification complete.")
    print("=" * 60)


if __name__ == "__main__":
    main()
