"""
Task T019b: TRACEABILITY
Associate the checksum generated in T019 with the SimulationRun metadata record.

This script reads the checksum manifest produced by T019 (state/checksums_raw.json),
loads the single run results produced by T015 (data/processed/single_run_results.json),
and updates the metadata record to include the checksum hash, satisfying the Data Model
requirement for linking raw data to logical runs.

It also ensures the raw matrix file exists and is valid before linking.
"""
import argparse
import json
import logging
import os
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any, Optional

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(project_root))

from utils.config import get_project_paths, load_config
from data_models import SimulationRun

def setup_logging():
    """Configure logging for the traceability task."""
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
        handlers=[
            logging.StreamHandler(sys.stdout),
            logging.FileHandler(
                project_root / 'data' / 'logs' / 'task019b_traceability.log',
                mode='a'
            )
        ]
    )
    return logging.getLogger(__name__)

def load_checksum_manifest(checksum_path: Path) -> Dict[str, Any]:
    """Load the checksum manifest generated by T019."""
    if not checksum_path.exists():
        raise FileNotFoundError(f"Checksum manifest not found: {checksum_path}")
    
    with open(checksum_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def load_single_run_results(results_path: Path) -> Dict[str, Any]:
    """Load the single run results generated by T015."""
    if not results_path.exists():
        raise FileNotFoundError(f"Single run results not found: {results_path}")
    
    with open(results_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def find_checksum_for_run(checksums: Dict[str, Any], run_id: str, seed: int, N: int) -> Optional[str]:
    """Find the checksum hash for a specific run configuration."""
    # The checksum manifest structure depends on T019 implementation
    # Assuming it stores entries keyed by filename or with a list of entries
    # We need to match on seed and N to find the correct matrix file
    
    if 'entries' in checksums:
        entries = checksums['entries']
    elif 'checksums' in checksums:
        entries = checksums['checksums']
    else:
        # Try to treat the whole dict as entries if it's a simple mapping
        entries = [checksums] if isinstance(checksums, dict) else []
    
    # Look for a file matching the pattern matrix_N{N}_seed{seed}.npy
    target_pattern = f"matrix_N{N}_seed{seed}.npy"
    
    for entry in entries:
        if isinstance(entry, dict):
            # Check if filename matches
            filename = entry.get('filename', '') or entry.get('file', '')
            if target_pattern in filename:
                return entry.get('sha256', entry.get('hash'))
        
        # Also check if the entry itself is a dict with file info
        if isinstance(entry, dict) and 'sha256' in entry:
            filename = entry.get('filename', '') or entry.get('file', '')
            if target_pattern in filename:
                return entry.get('sha256')
    
    return None

def update_run_metadata(run_results: Dict[str, Any], checksum_hash: str, logger: logging.Logger) -> Dict[str, Any]:
    """Update the run metadata with the checksum hash."""
    if 'metadata' not in run_results:
        run_results['metadata'] = {}
    
    run_results['metadata']['raw_data_checksum'] = checksum_hash
    run_results['metadata']['checksum_timestamp'] = datetime.now(timezone.utc).isoformat()
    run_results['metadata']['traceability_verified'] = True
    
    logger.info(f"Updated metadata with checksum: {checksum_hash[:16]}...")
    
    return run_results

def save_updated_results(updated_results: Dict[str, Any], output_path: Path):
    """Save the updated results to disk."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(updated_results, f, indent=2, default=str)
    
    logging.info(f"Saved updated results to: {output_path}")

def main():
    """Main entry point for T019b traceability task."""
    logger = setup_logging()
    logger.info("Starting T019b: Traceability task")
    
    try:
        # Load configuration
        config = load_config()
        paths = get_project_paths()
        
        # Define paths
        checksum_path = paths['state'] / 'checksums_raw.json'
        results_path = paths['processed'] / 'single_run_results.json'
        output_path = paths['processed'] / 'single_run_results.json'  # Update in place
        
        # Validate input files exist
        if not checksum_path.exists():
            raise FileNotFoundError(
                f"Checksum manifest not found at {checksum_path}. "
                "Ensure T019 has completed successfully."
            )
        
        if not results_path.exists():
            raise FileNotFoundError(
                f"Single run results not found at {results_path}. "
                "Ensure T015 has completed successfully."
            )
        
        # Load data
        logger.info(f"Loading checksum manifest from: {checksum_path}")
        checksums = load_checksum_manifest(checksum_path)
        
        logger.info(f"Loading single run results from: {results_path}")
        run_results = load_single_run_results(results_path)
        
        # Extract run parameters
        run_id = run_results.get('run_id')
        seed = run_results.get('seed')
        N = run_results.get('N')
        
        if not all([run_id, seed, N]):
            raise ValueError("Missing required run parameters (run_id, seed, N) in results file")
        
        logger.info(f"Processing run: {run_id} (N={N}, seed={seed})")
        
        # Find checksum for this run
        checksum_hash = find_checksum_for_run(checksums, run_id, seed, N)
        
        if not checksum_hash:
            raise ValueError(
                f"Could not find checksum for run N={N}, seed={seed} in manifest. "
                "Verify T019 generated the correct checksum entries."
            )
        
        logger.info(f"Found checksum: {checksum_hash[:32]}...")
        
        # Update metadata
        updated_results = update_run_metadata(run_results, checksum_hash, logger)
        
        # Save updated results
        save_updated_results(updated_results, output_path)
        
        # Log success
        logger.info("T019b traceability task completed successfully")
        logger.info(f"Run {run_id} is now linked to raw data via checksum: {checksum_hash[:16]}...")
        
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        return 1
    except ValueError as e:
        logger.error(f"Value error: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error: {e}", exc_info=True)
        return 1

if __name__ == '__main__':
    sys.exit(main())