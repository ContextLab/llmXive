"""
Task T019b: Traceability - Link checksums to SimulationRun metadata.

This module implements the traceability requirement for US1. It reads the
checksum manifest generated by T019 (state/checksums_raw.json), loads the
single run results (data/processed/single_run_results.json), finds the
matching checksum for the run's matrix, and updates the metadata record
with the checksum hash.

This satisfies the Data Model requirement for linking raw data to logical runs.
"""

import argparse
import json
import logging
import os
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any, Optional

# Ensure code directory is in path for imports
code_dir = Path(__file__).resolve().parent.parent
if str(code_dir) not in sys.path:
    sys.path.insert(0, str(code_dir))

from utils.config import get_project_paths, ensure_directories
from utils.checksum import load_checksum_manifest

def setup_logging(log_path: Optional[Path] = None) -> logging.Logger:
    """Configure logging for the traceability task."""
    logger = logging.getLogger("task019b_traceability")
    logger.setLevel(logging.INFO)

    if not logger.handlers:
        handler = logging.StreamHandler(sys.stdout)
        formatter = logging.Formatter(
            '%(asctime)s - %(name)s - %(levelname)s - %(message)s'
        )
        handler.setFormatter(formatter)
        logger.addHandler(handler)

        if log_path:
            file_handler = logging.FileHandler(log_path)
            file_handler.setFormatter(formatter)
            logger.addHandler(file_handler)

    return logger

def load_checksum_manifest(checksum_file: Path) -> Dict[str, Any]:
    """
    Load the checksum manifest generated by T019.

    Args:
        checksum_file: Path to state/checksums_raw.json

    Returns:
        Dictionary containing checksum entries keyed by matrix filename.
    """
    if not checksum_file.exists():
        raise FileNotFoundError(
            f"Checksum manifest not found: {checksum_file}. "
            "Ensure T019 has completed and generated state/checksums_raw.json."
        )

    with open(checksum_file, 'r', encoding='utf-8') as f:
        return json.load(f)

def load_single_run_results(results_file: Path) -> Dict[str, Any]:
    """
    Load the single run results from T015.

    Args:
        results_file: Path to data/processed/single_run_results.json

    Returns:
        Dictionary containing simulation run results.
    """
    if not results_file.exists():
        raise FileNotFoundError(
            f"Single run results not found: {results_file}. "
            "Ensure T015 has completed and generated data/processed/single_run_results.json."
        )

    with open(results_file, 'r', encoding='utf-8') as f:
        return json.load(f)

def find_checksum_for_run(
    checksum_manifest: Dict[str, Any],
    run_metadata: Dict[str, Any],
    logger: logging.Logger
) -> Optional[str]:
    """
    Find the checksum hash corresponding to the run's matrix file.

    Args:
        checksum_manifest: The loaded checksum manifest.
        run_metadata: The simulation run metadata (N, seed, theta).
        logger: Logger for messages.

    Returns:
        The SHA-256 checksum hash if found, None otherwise.
    """
    n = run_metadata.get("N")
    seed = run_metadata.get("seed")

    if n is None or seed is None:
        logger.warning(
            f"Run metadata missing N or seed: {run_metadata}. "
            "Cannot find corresponding checksum."
        )
        return None

    # Construct expected filename pattern from T019
    expected_filename = f"matrix_N{n}_seed{seed}.npy"

    # Check if the file exists in the manifest
    if expected_filename in checksum_manifest:
        checksum_entry = checksum_manifest[expected_filename]
        if isinstance(checksum_entry, dict):
            return checksum_entry.get("sha256")
        elif isinstance(checksum_entry, str):
            return checksum_entry

    # If not found with exact name, try to find by scanning entries
    # This handles cases where the manifest structure might vary slightly
    for filename, entry in checksum_manifest.items():
        if f"matrix_N{n}_seed{seed}" in filename:
            if isinstance(entry, dict):
                logger.info(f"Found matching checksum for {filename}")
                return entry.get("sha256")
            elif isinstance(entry, str):
                logger.info(f"Found matching checksum for {filename}")
                return entry

    logger.warning(
        f"Could not find checksum for matrix_N{n}_seed{seed}.npy in manifest. "
        "Available keys: {list(checksum_manifest.keys())}"
    )
    return None

def update_run_metadata(
    run_results: Dict[str, Any],
    checksum_hash: str,
    logger: logging.Logger
) -> Dict[str, Any]:
    """
    Update the run metadata with the checksum hash.

    Args:
        run_results: The simulation run results dictionary.
        checksum_hash: The SHA-256 checksum hash.
        logger: Logger for messages.

    Returns:
        Updated dictionary with checksum information.
    """
    # Ensure the metadata structure exists
    if "metadata" not in run_results:
        run_results["metadata"] = {}

    # Update with checksum
    run_results["metadata"]["checksum_sha256"] = checksum_hash
    run_results["metadata"]["checksum_verified_at"] = datetime.now(timezone.utc).isoformat()
    run_results["metadata"]["traceability_status"] = "linked"

    logger.info(f"Updated run metadata with checksum: {checksum_hash[:16]}...")
    return run_results

def save_updated_results(
    updated_results: Dict[str, Any],
    output_file: Path,
    logger: logging.Logger
) -> None:
    """
    Save the updated results to the output file.

    Args:
        updated_results: The updated dictionary to save.
        output_file: Path to the output JSON file.
        logger: Logger for messages.
    """
    # Ensure parent directory exists
    output_file.parent.mkdir(parents=True, exist_ok=True)

    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(updated_results, f, indent=2, default=str)

    logger.info(f"Saved updated results to {output_file}")

def main() -> int:
    """
    Main entry point for T019b traceability task.

    Returns:
        Exit code (0 for success, 1 for failure).
    """
    logger = setup_logging()
    logger.info("Starting T019b: Traceability - Link checksums to SimulationRun metadata")

    try:
        # Get project paths
        paths = get_project_paths()
        state_dir = paths["state"]
        data_processed_dir = paths["data_processed"]

        # Define file paths
        checksum_manifest_path = Path(state_dir) / "checksums_raw.json"
        results_file_path = Path(data_processed_dir) / "single_run_results.json"
        output_file_path = results_file_path  # Overwrite the existing file

        logger.info(f"Loading checksum manifest from: {checksum_manifest_path}")
        checksum_manifest = load_checksum_manifest(checksum_manifest_path)

        logger.info(f"Loading single run results from: {results_file_path}")
        run_results = load_single_run_results(results_file_path)

        # Find the checksum for this run
        logger.info("Searching for matching checksum in manifest...")
        checksum_hash = find_checksum_for_run(checksum_manifest, run_results, logger)

        if checksum_hash is None:
            logger.error(
                "Failed to find checksum for the current run. "
                "Traceability cannot be established."
            )
            return 1

        # Update the run metadata
        updated_results = update_run_metadata(run_results, checksum_hash, logger)

        # Save the updated results
        save_updated_results(updated_results, output_file_path, logger)

        logger.info("T019b completed successfully. Traceability established.")
        return 0

    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        return 1
    except json.JSONDecodeError as e:
        logger.error(f"JSON parsing error: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
