"""
Task T019b: Traceability - Register checksum with SimulationRun metadata.

This task reads the checksum manifest generated by T019 (or the unified registry
if already updated) and the single run results, then updates the metadata registry
to link the raw data checksum to the logical SimulationRun record.
"""
import argparse
import json
import logging
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

# Import project utilities and models
from utils.config import get_project_paths
from data_models import SimulationRun

def setup_logging(log_file: Path) -> logging.Logger:
    """Configure logging to file and console."""
    logger = logging.getLogger("T019b_traceability")
    logger.setLevel(logging.INFO)
    
    # Ensure directory exists
    log_file.parent.mkdir(parents=True, exist_ok=True)
    
    # File handler
    fh = logging.FileHandler(log_file)
    fh.setLevel(logging.INFO)
    formatter = logging.Formatter('%(asctime)s - %(name)s - %(levelname)s - %(message)s')
    fh.setFormatter(formatter)
    
    # Console handler
    ch = logging.StreamHandler()
    ch.setLevel(logging.INFO)
    ch.setFormatter(formatter)
    
    logger.addHandler(fh)
    logger.addHandler(ch)
    return logger

def load_checksum_manifest(manifest_path: Path) -> dict:
    """Load the checksum manifest generated by T019."""
    if not manifest_path.exists():
        raise FileNotFoundError(f"Checksum manifest not found: {manifest_path}")
    
    with open(manifest_path, 'r') as f:
        return json.load(f)

def load_single_run_results(results_path: Path) -> dict:
    """Load the single run results from T014/T015."""
    if not results_path.exists():
        raise FileNotFoundError(f"Single run results not found: {results_path}")
    
    with open(results_path, 'r') as f:
        return json.load(f)

def find_checksum_for_run(manifest: dict, run_id: str) -> str:
    """Find the checksum hash for a specific run_id in the manifest."""
    if "checksums" not in manifest:
        raise ValueError("Invalid manifest format: missing 'checksums' key")
    
    for entry in manifest["checksums"]:
        if entry.get("run_id") == run_id:
            return entry.get("hash")
    
    raise ValueError(f"No checksum found for run_id: {run_id}")

def update_run_metadata(
    results: dict, 
    checksum_hash: str, 
    logger: logging.Logger
) -> SimulationRun:
    """Update the run metadata with the checksum hash and create SimulationRun record."""
    # Extract parameters from results
    run_id = results.get("run_id")
    N = results.get("N")
    seed = results.get("seed")
    theta = results.get("theta")
    
    if run_id is None or N is None or seed is None:
        raise ValueError("Missing required fields in results: run_id, N, seed")
    
    # Create SimulationRun model instance
    simulation_run = SimulationRun(
        run_id=run_id,
        N=N,
        seed=seed,
        theta=theta,
        checksum=checksum_hash,
        timestamp=datetime.now(timezone.utc).isoformat(),
        source_file=f"data/raw/matrix_N{N}_seed{seed}.npy",
        status="registered"
    )
    
    logger.info(f"Created SimulationRun record for {run_id}")
    logger.info(f"  N: {N}, Seed: {seed}, Theta: {theta}")
    logger.info(f"  Checksum: {checksum_hash}")
    
    return simulation_run

def save_updated_results(
    registry_path: Path, 
    simulation_run: SimulationRun, 
    logger: logging.Logger
) -> None:
    """Save the updated metadata to the unified registry."""
    # Load existing registry or create new one
    if registry_path.exists():
        with open(registry_path, 'r') as f:
            registry = json.load(f)
    else:
        registry = {"runs": [], "metadata": {"created": datetime.now(timezone.utc).isoformat()}}
    
    # Convert SimulationRun to dict and add to registry
    run_dict = simulation_run.model_dump(mode="json")
    
    # Check if run already exists (update if so)
    existing_idx = None
    for i, existing_run in enumerate(registry.get("runs", [])):
        if existing_run.get("run_id") == simulation_run.run_id:
            existing_idx = i
            break
    
    if existing_idx is not None:
        registry["runs"][existing_idx] = run_dict
        logger.info(f"Updated existing run record: {simulation_run.run_id}")
    else:
        registry["runs"].append(run_dict)
        logger.info(f"Added new run record: {simulation_run.run_id}")
    
    # Ensure directory exists
    registry_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Write updated registry
    with open(registry_path, 'w') as f:
        json.dump(registry, f, indent=2)
    
    logger.info(f"Metadata registry saved to: {registry_path}")

def main():
    """Main entry point for T019b."""
    parser = argparse.ArgumentParser(description="Task T019b: Register checksum with metadata")
    parser.add_argument("--manifest", type=str, default="state/checksums_manifest.json",
                      help="Path to checksum manifest from T019")
    parser.add_argument("--results", type=str, default="data/processed/single_run_results.json",
                      help="Path to single run results from T014/T015")
    parser.add_argument("--registry", type=str, default="state/metadata_registry.json",
                      help="Path to unified metadata registry")
    parser.add_argument("--log", type=str, default="data/logs/task019b_traceability.log",
                      help="Path to log file")
    
    args = parser.parse_args()
    
    # Setup logging
    log_path = Path(args.log)
    logger = setup_logging(log_path)
    
    try:
        logger.info("Starting T019b: Traceability registration")
        
        # Load inputs
        manifest = load_checksum_manifest(Path(args.manifest))
        results = load_single_run_results(Path(args.results))
        
        # Find checksum for this run
        run_id = results.get("run_id")
        checksum_hash = find_checksum_for_run(manifest, run_id)
        
        # Create updated metadata record
        simulation_run = update_run_metadata(results, checksum_hash, logger)
        
        # Save to unified registry
        save_updated_results(Path(args.registry), simulation_run, logger)
        
        logger.info("T019b completed successfully")
        return 0
        
    except Exception as e:
        logger.error(f"T019b failed: {str(e)}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
