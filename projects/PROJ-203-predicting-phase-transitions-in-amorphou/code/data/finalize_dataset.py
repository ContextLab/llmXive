"""
finalize_dataset.py

Implements T014: Save final processed dataset to `data/processed/final_dataset.parquet`
with metadata flags for "truncated" simulations, "failed" runs, and the applied cooling rate.

Prerequisite: T013.1 (labeled_dataset_temp.parquet exists)
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional

import pandas as pd
import numpy as np

# Import project configuration
from config import get_config, get_data_config
from utils.logging_config import setup_pipeline_logging, get_missing_data_logger

# Configure logging
setup_pipeline_logging()
logger = logging.getLogger(__name__)
missing_data_logger = get_missing_data_logger()

def load_temp_dataset() -> pd.DataFrame:
    """
    Load the temporary labeled dataset from T013.1.
    """
    config = get_data_config()
    temp_path = config.processed_dir / "labeled_dataset_temp.parquet"
    
    if not temp_path.exists():
        raise FileNotFoundError(
            f"FATAL: Temporary dataset missing at {temp_path}. "
            "Prerequisite T013.1 has not been completed."
        )
    
    logger.info(f"Loading temporary dataset from {temp_path}")
    df = pd.read_parquet(temp_path)
    logger.info(f"Loaded {len(df)} rows with columns: {list(df.columns)}")
    return df

def load_simulation_metadata() -> Dict[str, Any]:
    """
    Load simulation metadata (truncation flags, cooling rates) generated during T010/T012.
    Expects a JSON file containing a list of dicts or a keyed dict.
    """
    config = get_data_config()
    # The metadata is typically generated by descriptor_utils or simulate and saved
    # Let's assume it's saved as metadata.json in processed or raw based on T012.2
    # T012.2 says: "Output the scaling factor and aligned parameters to data/processed/metadata.json"
    # However, simulation specific flags (truncated/failed) are often in a run-specific log or JSON.
    # We will look for a specific metadata file generated by the simulation/descriptor phase.
    # Based on T010/T011 flow, we expect a file like simulation_metadata.json or similar.
    # If T012.2 output is the only source, we might need to infer flags or check a log.
    # Let's check for a specific file that tracks run status.
    
    # Attempt to load from a standard location defined in config or a specific file
    # If T012.2 wrote to metadata.json, we need to merge that with run status.
    # Let's look for a file that contains the "truncated" and "failed" flags.
    # Usually, simulate.py or descriptor_utils.py would dump a run_status.json.
    
    # Fallback: Check if a specific metadata file exists
    metadata_paths = [
        config.processed_dir / "simulation_metadata.json",
        config.processed_dir / "metadata.json", # From T012.2
        config.raw_dir / "simulation_status.json"
    ]
    
    metadata = {}
    found = False
    
    for p in metadata_paths:
        if p.exists():
            logger.info(f"Loading metadata from {p}")
            with open(p, 'r') as f:
                raw = json.load(f)
                # Normalize: if it's a list of records, convert to dict by composition_id
                if isinstance(raw, list):
                    metadata = {row.get('composition_id'): row for row in raw if 'composition_id' in row}
                else:
                    metadata = raw
            found = True
            break
    
    if not found:
        # If no specific metadata file exists, we assume all runs are successful for now
        # but log a warning. In a real pipeline, this should fail loudly if flags are required.
        logger.warning("No simulation metadata file found. Assuming all runs successful.")
        return {}
        
    return metadata

def enrich_with_metadata(df: pd.DataFrame, metadata: Dict[str, Any]) -> pd.DataFrame:
    """
    Enrich the dataset with metadata flags:
    - 'simulation_status': 'truncated', 'failed', or 'success'
    - 'cooling_rate': applied cooling rate
    - 'scaling_factor': from T012.2 if available
    """
    logger.info("Enriching dataset with simulation metadata")
    
    # Initialize default values
    df['simulation_status'] = 'success'
    df['cooling_rate'] = np.nan
    df['scaling_factor'] = np.nan
    
    # Map metadata to dataframe
    # Assume 'composition_id' or similar column exists in df to join on
    join_col = 'composition_id'
    if join_col not in df.columns:
        # Try to find a similar column
        possible_cols = [c for c in df.columns if 'id' in c.lower() or 'comp' in c.lower()]
        if possible_cols:
            join_col = possible_cols[0]
            logger.warning(f"Using '{join_col}' as join key for metadata enrichment.")
        else:
            raise ValueError("Could not find a composition identifier column to join metadata.")
    
    for idx, row in df.iterrows():
        comp_id = row[join_col]
        if comp_id in metadata:
          meta = metadata[comp_id]
          if 'status' in meta:
              df.at[idx, 'simulation_status'] = meta['status']
          elif 'simulation_status' in meta:
              df.at[idx, 'simulation_status'] = meta['simulation_status']
          
          if 'cooling_rate' in meta:
              df.at[idx, 'cooling_rate'] = meta['cooling_rate']
          elif 'cooling_rate_K_s' in meta:
              df.at[idx, 'cooling_rate'] = meta['cooling_rate_K_s']
          
          if 'scaling_factor' in meta:
              df.at[idx, 'scaling_factor'] = meta['scaling_factor']
          elif 'SRO_Invariance_Assumed' in meta:
              # If SRO_Invariance_Assumed is False, it implies scaling was applied
              pass 
    
    # Log any missing metadata
    missing_count = df['simulation_status'].isna().sum()
    if missing_count > 0:
        logger.warning(f"{missing_count} rows missing metadata. Defaulting to 'success'.")
    
    return df

def validate_final_dataset(df: pd.DataFrame) -> bool:
    """
    Validate the final dataset before saving.
    Checks for required columns and non-null critical values.
    """
    required_cols = ['composition_id', 'simulation_status', 'cooling_rate']
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"Final dataset missing required columns: {missing_cols}")
    
    # Check for NaN in critical columns if we expect them to be filled
    # Note: T013.1 might have filtered rows with null Tg/Tx, but cooling_rate should be present
    if df['simulation_status'].isna().any():
        logger.warning("Dataset contains rows with missing simulation_status.")
    
    return True

def save_final_dataset(df: pd.DataFrame, output_path: Path) -> None:
    """
    Save the final dataset to Parquet.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    logger.info(f"Saving final dataset to {output_path}")
    df.to_parquet(output_path, index=False)
    logger.info(f"Saved {len(df)} rows to {output_path}")

def main():
    """
    Main entry point for T014.
    """
    logger.info("Starting T014: Finalize Dataset")
    
    config = get_data_config()
    output_path = config.processed_dir / "final_dataset.parquet"
    
    try:
        # 1. Load temporary dataset
        df = load_temp_dataset()
        
        # 2. Load metadata
        metadata = load_simulation_metadata()
        
        # 3. Enrich with metadata
        df = enrich_with_metadata(df, metadata)
        
        # 4. Validate
        validate_final_dataset(df)
        
        # 5. Save
        save_final_dataset(df, output_path)
        
        logger.info("T014 completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during T014: {e}")
        raise

if __name__ == "__main__":
    main()
