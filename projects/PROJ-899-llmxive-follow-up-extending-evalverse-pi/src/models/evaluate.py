logger = get_logger(__name__)

def _load_predictions_and_targets() -> Tuple[pd.DataFrame, pd.Series]:
    """
    Loads the processed features and target scores.
    Expects the training data to be available in the processed data directory
    as generated by T015 (train.py).
    """
    data_root = get_data_root()
    processed_dir = Path(data_root) / "processed"
    
    # Expected output file from T015 (train.py)
    # If T015 hasn't run, this will fail loudly as per constraints.
    feature_file = processed_dir / "features.csv"
    target_file = processed_dir / "targets.csv"

    if not feature_file.exists():
        raise FileNotFoundError(f"Required feature file not found: {feature_file}. "
                                "Ensure T015 (train.py) has been executed successfully.")
    if not target_file.exists():
        raise FileNotFoundError(f"Required target file not found: {target_file}. "
                                "Ensure T015 (train.py) has been executed successfully.")

    X = pd.read_csv(feature_file)
    y = pd.read_csv(target_file)
    
    # Assuming the first column of X is the dimension name or index, 
    # but typically features are numeric columns. 
    # We need to align with how T016 expects the data. 
    # Let's assume X contains feature columns and 'dimension' column if applicable,
    # and y contains 'score' or similar.
    # For baseline evaluation, we usually need the full dataset used in T016.
    
    # If the file structure is different, we adapt. 
    # Based on T015 'save_results', it likely saved 'features.csv' and 'targets.csv'.
    # Let's assume numeric features are all columns except a potential ID column.
    
    return X, y

def _create_mean_predictor(y_true: pd.Series) -> pd.Series:
    """
    Creates a baseline prediction where every sample is predicted 
    to have the mean value of the training targets.
    """
    mean_val = y_true.mean()
    return pd.Series([mean_val] * len(y_true), index=y_true.index)

def _create_shuffled_predictor(y_true: pd.Series, random_state: int = 42) -> pd.Series:
    """
    Creates a baseline prediction by shuffling the true target values.
    This simulates a model with no predictive power (random permutation).
    """
    rng = np.random.default_rng(random_state)
    shuffled_values = rng.permutation(y_true.values)
    return pd.Series(shuffled_values, index=y_true.index)

def calculate_metrics(y_true: pd.Series, y_pred: pd.Series) -> Dict[str, float]:
    """
    Calculates standard regression metrics: MSE, MAE, and R^2.
    """
    y_true_arr = y_true.values
    y_pred_arr = y_pred.values

    mse = np.mean((y_true_arr - y_pred_arr) ** 2)
    mae = np.mean(np.abs(y_true_arr - y_pred_arr))
    
    ss_res = np.sum((y_true_arr - y_pred_arr) ** 2)
    ss_tot = np.sum((y_true_arr - np.mean(y_true_arr)) ** 2)
    
    r2 = 1 - (ss_res / ss_tot) if ss_tot != 0 else 0.0

    return {
        "mse": float(mse),
        "mae": float(mae),
        "r2": float(r2)
    }

def evaluate_baselines(output_path: Optional[str] = None) -> pd.DataFrame:
    """
    Implements baseline comparisons (Mean Predictor, Shuffled Features) 
    against the target scores.
    
    This function:
    1. Loads processed features and targets.
    2. Computes predictions for:
       - Mean Predictor (predicts mean of y)
       - Shuffled Features (random permutation of y)
    3. Calculates MSE, MAE, and R^2 for each baseline.
    4. Saves results to `data/baseline_results.csv`.
    
    Args:
        output_path: Optional path to save the CSV. Defaults to data/baseline_results.csv.
    
    Returns:
        DataFrame containing the baseline results.
    """
    logger.info("Loading data for baseline evaluation...")
    X, y = _load_predictions_and_targets()
    
    # Ensure y is a Series
    if isinstance(y, pd.DataFrame):
        # If it's a dataframe, assume the first column is the target
        if len(y.columns) > 0:
            y = y.iloc[:, 0]
        else:
            raise ValueError("Target DataFrame is empty.")
    
    logger.info(f"Loaded {len(y)} samples for baseline evaluation.")
    
    results = []
    
    # 1. Mean Predictor
    logger.info("Evaluating Mean Predictor...")
    y_pred_mean = _create_mean_predictor(y)
    metrics_mean = calculate_metrics(y, y_pred_mean)
    metrics_mean["model_type"] = "Mean Predictor"
    results.append(metrics_mean)
    
    # 2. Shuffled Features (Random Permutation of Targets)
    logger.info("Evaluating Shuffled Features Baseline...")
    y_pred_shuffled = _create_shuffled_predictor(y, random_state=42)
    metrics_shuffled = calculate_metrics(y, y_pred_shuffled)
    metrics_shuffled["model_type"] = "Shuffled Features"
    results.append(metrics_shuffled)
    
    # Create DataFrame
    df_results = pd.DataFrame(results)
    
    # Ensure output directory exists
    if output_path is None:
        data_root = get_data_root()
        output_path = os.path.join(data_root, "baseline_results.csv")
    
    output_dir = os.path.dirname(output_path)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)
    
    logger.info(f"Saving baseline results to {output_path}")
    df_results.to_csv(output_path, index=False)
    
    return df_results

def main():
    """
    Entry point for the baseline evaluation task.
    """
    logger.info("Starting T019: Baseline Comparisons")
    try:
        results = evaluate_baselines()
        logger.info("Baseline evaluation completed successfully.")
        logger.info(f"Results:\n{results}")
        return 0
    except Exception as e:
        logger.error(f"Baseline evaluation failed: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    exit(main())
