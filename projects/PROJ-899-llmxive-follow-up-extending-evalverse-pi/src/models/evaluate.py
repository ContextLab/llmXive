def calculate_baseline_mean(y_true: np.ndarray) -> float:
    """Calculate MSE of predicting the mean."""
    if len(y_true) == 0:
        return 0.0
    mean_pred = np.mean(y_true)
    return float(np.mean((y_true - mean_pred) ** 2))

def calculate_baseline_shuffled(y_true: np.ndarray, n_iter: int = 1000) -> float:
    """Calculate average MSE of shuffled predictions."""
    if len(y_true) == 0:
        return 0.0
    mse_scores = []
    for _ in range(n_iter):
        shuffled = np.random.permutation(y_true)
        mse_scores.append(np.mean((y_true - shuffled) ** 2))
    return float(np.mean(mse_scores))

def calculate_metrics(y_true: np.ndarray, y_pred: np.ndarray) -> Dict[str, float]:
    """Calculate regression metrics."""
    if len(y_true) == 0 or len(y_pred) == 0:
        return {"mse": 0.0, "rmse": 0.0, "mae": 0.0}
    mse = mean_squared_error(y_true, y_pred)
    return {
        "mse": float(mse),
        "rmse": float(np.sqrt(mse)),
        "mae": float(np.mean(np.abs(y_true - y_pred)))
    }

def run_baseline_comparisons(y_true: np.ndarray) -> Dict[str, float]:
    """Run baseline comparisons."""
    return {
        "mean_predictor_mse": calculate_baseline_mean(y_true),
        "shuffled_predictor_mse": calculate_baseline_shuffled(y_true)
    }

