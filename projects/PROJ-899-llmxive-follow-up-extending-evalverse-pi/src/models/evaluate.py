def load_scaling_profile() -> Optional[pd.DataFrame]:
    """
    Load the scaling profile from the data directory.
    Expects data/scaling_profile.csv generated by T022 (batch processing).
    """
    data_root = get_data_root()
    scaling_file = os.path.join(data_root, "scaling_profile.csv")
    
    if not os.path.exists(scaling_file):
        logger.warning(f"Scaling profile not found at {scaling_file}. "
                       "Ensure T022 has been run successfully.")
        return None
    
    try:
        df = pd.read_csv(scaling_file)
        required_cols = ["batch_size", "total_time_seconds", "avg_time_per_clip"]
        if not all(col in df.columns for col in required_cols):
            logger.error(f"Scaling profile missing required columns: {required_cols}")
            return None
        return df
    except Exception as e:
        logger.error(f"Failed to load scaling profile: {e}")
        return None

def calculate_inference_time_projection(
    scaling_df: pd.DataFrame, 
    target_n: int = 10000
) -> Dict[str, float]:
    """
    Calculate projected inference time for N clips based on linear scaling.
    
    Args:
        scaling_df: DataFrame with batch processing stats (from T022).
        target_n: Target number of clips (default 10,000).
    
    Returns:
        Dict with projected_total_seconds, projected_total_hours, 
        avg_time_per_clip, and validation status.
    """
    if scaling_df is None or scaling_df.empty:
        raise ValueError("Scaling profile is empty or None. Cannot project time.")
    
    # Use the most recent/largest batch for projection (most stable estimate)
    # Or perform a linear regression if multiple points exist
    if len(scaling_df) > 1:
        # Linear regression to ensure linearity assumption holds
        x = scaling_df["batch_size"].values
        y = scaling_df["total_time_seconds"].values
        
        # Simple linear fit: time = slope * n + intercept
        # Force intercept through 0 for physical realism (0 clips = 0 time)
        # slope = sum(x*y) / sum(x^2)
        slope = np.sum(x * y) / np.sum(x ** 2)
        
        projected_seconds = slope * target_n
        avg_time_per_clip = slope
    else:
        # Single data point: use the average time per clip directly
        avg_time_per_clip = scaling_df["avg_time_per_clip"].iloc[0]
        projected_seconds = avg_time_per_clip * target_n
    
    projected_hours = projected_seconds / 3600.0
    
    return {
        "target_n": target_n,
        "avg_time_per_clip_seconds": float(avg_time_per_clip),
        "projected_total_seconds": float(projected_seconds),
        "projected_total_hours": float(projected_hours),
        "method": "linear_scaling"
    }

def generate_timing_profile(
    scaling_df: Optional[pd.DataFrame] = None, 
    target_n: int = 10000
) -> pd.DataFrame:
    """
    Generate the timing profile CSV.
    
    This function calculates per-clip inference time and projects total time
    for N=10,000 clips based on T022 results (validated by T021b).
    
    Args:
        scaling_df: Optional DataFrame with scaling data. If None, loads from disk.
        target_n: Target number of clips for projection.
    
    Returns:
        DataFrame containing the timing profile.
    """
    if scaling_df is None:
        scaling_df = load_scaling_profile()
    
    if scaling_df is None:
        raise RuntimeError(
            "Could not load scaling profile. "
            "Ensure T022 (batch processing) and T021b (scaling validation) have run."
        )
    
    # Calculate projection
    projection = calculate_inference_time_projection(scaling_df, target_n)
    
    # Create output DataFrame
    # Columns: batch_size, avg_time_per_clip, projected_total_seconds, projected_total_hours
    output_data = {
        "batch_size": [target_n],
        "avg_time_per_clip_seconds": [projection["avg_time_per_clip_seconds"]],
        "projected_total_seconds": [projection["projected_total_seconds"]],
        "projected_total_hours": [projection["projected_total_hours"]],
        "method": [projection["method"]]
    }
    
    df_output = pd.DataFrame(output_data)
    
    # Save to data/timing_profile.csv
    data_root = get_data_root()
    output_path = os.path.join(data_root, "timing_profile.csv")
    write_csv(df_output, output_path)
    
    logger.info(f"Timing profile generated and saved to {output_path}")
    logger.info(f"Projected total time for {target_n} clips: {projection['projected_total_hours']:.2f} hours")
    
    return df_output

