"""
Serialization module for simulation results.
Handles loading, saving, and formatting simulation output to data/analysis/simulation_results.json.
"""
import json
import logging
import os
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from code.src.utils.config import load_config
from code.src.utils.logging import init_logging, log_metric

logger = logging.getLogger(__name__)

def setup_logging() -> logging.Logger:
    """Initialize logging for the serialization module."""
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
        handlers=[
            logging.StreamHandler(sys.stdout),
            logging.FileHandler('data/run_log.txt', mode='a')
        ]
    )
    return logging.getLogger(__name__)

def load_simulation_results(config_path: str) -> List[Dict[str, Any]]:
    """
    Load simulation results from the raw data directory.
    This function reads JSON files generated by the simulation phase.
    
    Args:
        config_path: Path to the config.yaml file.
        
    Returns:
        List of simulation result dictionaries.
        
    Raises:
        FileNotFoundError: If no simulation results are found.
    """
    config = load_config(config_path)
    data_dir = Path(config.get('data_dir', 'data'))
    simulation_dir = data_dir / 'raw' / 'simulation_results'
    
    if not simulation_dir.exists():
        # If the directory doesn't exist, we assume no results yet.
        # This is expected if the simulation phase hasn't run.
        logger.warning(f"Simulation results directory not found: {simulation_dir}")
        return []
    
    results = []
    for file_path in simulation_dir.glob('*.json'):
        try:
            with open(file_path, 'r') as f:
                result = json.load(f)
                results.append(result)
        except json.JSONDecodeError as e:
            logger.error(f"Failed to decode JSON in {file_path}: {e}")
            continue
        
    return results

def save_simulation_results(results: List[Dict[str, Any]], output_path: str) -> None:
    """
    Save simulation results to the specified output path.
    
    Args:
        results: List of simulation result dictionaries.
        output_path: Path where the results will be saved.
    """
    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_file, 'w') as f:
        json.dump(results, f, indent=2, default=str)
    
    logger.info(f"Saved {len(results)} simulation results to {output_path}")

def serialize_single_result(result: Dict[str, Any]) -> Dict[str, Any]:
    """
    Serialize a single simulation result, ensuring all values are JSON-serializable.
    
    Args:
        result: A dictionary containing simulation result data.
        
    Returns:
        A sanitized dictionary ready for JSON serialization.
    """
    sanitized = {}
    for key, value in result.items():
        if isinstance(value, (str, int, float, bool, type(None))):
            sanitized[key] = value
        elif isinstance(value, (list, tuple)):
            sanitized[key] = [serialize_single_result(item) if isinstance(item, dict) else item for item in value]
        elif isinstance(value, dict):
            sanitized[key] = serialize_single_result(value)
        else:
            # Convert non-serializable types to string
            sanitized[key] = str(value)
    return sanitized

def run_and_serialize_simulation(config_path: str) -> None:
    """
    Main function to run the serialization process.
    Loads simulation results, serializes them, and saves to the declared output file.
    
    Args:
        config_path: Path to the config.yaml file.
    """
    logger.info("Starting simulation result serialization...")
    
    # Initialize logging infrastructure to ensure data/run_log.json exists
    init_logging()
    
    # Load simulation results
    results = load_simulation_results(config_path)
    
    if not results:
        logger.warning("No simulation results found to serialize.")
        # Create an empty results file to indicate the phase completed but found no data
        output_path = Path(config_path).parent.parent / 'data' / 'analysis' / 'simulation_results.json'
        save_simulation_results([], str(output_path))
        return
    
    # Serialize each result
    serialized_results = [serialize_single_result(result) for result in results]
    
    # Determine output path from config or default
    config = load_config(config_path)
    output_path = Path(config.get('data_dir', 'data')) / 'analysis' / 'simulation_results.json'
    
    # Save results
    save_simulation_results(serialized_results, str(output_path))
    
    # Log the event
    log_metric({
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "event_type": "simulation_end",
        "run_id": "serialization_run",
        "seed": config.get('global_seed', 42),
        "status": "success",
        "duration_seconds": 0.0  # Placeholder, actual duration could be tracked
    })
    
    logger.info("Simulation result serialization completed successfully.")

def main() -> None:
    """Entry point for the serialization script."""
    parser = argparse.ArgumentParser(description="Serialize simulation results to JSON.")
    parser.add_argument(
        "--config",
        type=str,
        default="code/config.yaml",
        help="Path to the configuration file."
    )
    args = parser.parse_args()
    
    setup_logging()
    run_and_serialize_simulation(args.config)

if __name__ == "__main__":
    import argparse
    main()
