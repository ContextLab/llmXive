"""
Contract test for User Story 1: Ground Truth Generation via Exhaustive Sweep.

Validates that the output of the sweep process adheres to the strict schema
defined in the project contracts. Specifically, it verifies that for every
input sample processed, the output record contains:
1. A valid sample_id.
2. A mapping of all tested block sizes to their latency results.
3. A clearly identified optimal block size (B*) based on minimum latency.
4. Proper handling of OOM or failure states (marked as null or specific error code).

This test is designed to run against the generated `data/processed/ground_truth.jsonl`
file produced by `code/sweep.py`.
"""
import json
import pytest
from pathlib import Path
from typing import Dict, Any, List, Optional

# Import contract schemas defined in T007
# Note: The API surface lists contracts as a directory. We assume Pydantic models
# or dataclasses are defined in `contracts/__init__.py` or specific files.
# Based on T007 requirements, we expect FeatureVector, GroundTruth, Prediction, ModelArtifact.
# We will import the GroundTruth schema specifically.
try:
    from contracts import GroundTruth
except ImportError:
    # Fallback if contracts are not yet importable as a package in this context,
    # though T007 should have created them. We define a minimal validator here
    # to ensure the test logic is self-contained for the contract check.
    from dataclasses import dataclass, field
    from typing import Dict, Any, List, Optional
    
    @dataclass
    class GroundTruth:
        """
        Contract Schema for Sweep Output.
        Represents the ground truth optimal block size for a single sample.
        """
        sample_id: str
        block_size_results: Dict[int, Optional[float]]  # Map block_size -> latency (ms) or None if OOM
        optimal_block_size: Optional[int]               # The B* (winner)
        status: str                                     # 'success', 'partial_oom', 'failed'
        metadata: Dict[str, Any] = field(default_factory=dict)
        
        def validate(self) -> bool:
            """Validate the record against the contract rules."""
            if not self.sample_id:
                return False
            if not self.block_size_results:
                return False
            
            # Rule 1: Must have results for all tested block sizes
            expected_sizes = {1, 2, 4, 8, 16, 32}
            if set(self.block_size_results.keys()) != expected_sizes:
                return False
            
            # Rule 2: If status is 'success', optimal_block_size must be present
            if self.status == 'success' and self.optimal_block_size is None:
                return False
            
            # Rule 3: If status is 'success', the optimal_block_size must exist in results
            # and correspond to the minimum non-null latency
            if self.status == 'success':
                valid_latencies = {k: v for k, v in self.block_size_results.items() if v is not None}
                if not valid_latencies:
                    return False
                
                min_latency = min(valid_latencies.values())
                candidates = [k for k, v in valid_latencies.items() if v == min_latency]
                
                # Deterministic tie-breaking: smallest block size
                expected_b_star = min(candidates)
                if self.optimal_block_size != expected_b_star:
                    return False
            
            return True

class TestSweepOutputContract:
    """
    Contract tests for the sweep output schema.
    """
    
    @pytest.fixture
    def ground_truth_file(self) -> Path:
        """Locate the ground truth file generated by T012."""
        project_root = Path(__file__).parent.parent.parent
        file_path = project_root / "data" / "processed" / "ground_truth.jsonl"
        if not file_path.exists():
            pytest.skip(f"Ground truth file not found at {file_path}. "
                        "Run code/sweep.py first to generate data.")
        return file_path
    
    def test_file_is_valid_jsonl(self, ground_truth_file: Path):
        """Ensure the file is a valid JSON Lines format."""
        count = 0
        with open(ground_truth_file, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    json.loads(line)
                    count += 1
                except json.JSONDecodeError as e:
                    pytest.fail(f"Invalid JSON on line {count + 1}: {e}")
        assert count > 0, "Ground truth file is empty."
    
    def test_schema_compliance(self, ground_truth_file: Path):
        """
        Verify every record in the file strictly adheres to the GroundTruth schema.
        """
        errors = []
        with open(ground_truth_file, 'r', encoding='utf-8') as f:
            for line_num, line in enumerate(f, 1):
                line = line.strip()
                if not line:
                    continue
                
                try:
                    record = json.loads(line)
                    # Instantiate the schema object to trigger validation logic
                    gt = GroundTruth(
                        sample_id=record.get("sample_id"),
                        block_size_results=record.get("block_size_results", {}),
                        optimal_block_size=record.get("optimal_block_size"),
                        status=record.get("status"),
                        metadata=record.get("metadata", {})
                    )
                    
                    if not gt.validate():
                        errors.append(f"Line {line_num}: Record failed validation rules.")
                        errors.append(f"  Data: {record}")
                        
                except (KeyError, TypeError, ValueError) as e:
                    errors.append(f"Line {line_num}: Failed to parse record: {e}")
        
        if errors:
            pytest.fail("Schema validation failed for the following records:\n" + "\n".join(errors))
    
    def test_all_block_sizes_present(self, ground_truth_file: Path):
        """
        Verify that every record contains results for the full set of block sizes:
        {1, 2, 4, 8, 16, 32}.
        """
        expected_sizes = {1, 2, 4, 8, 16, 32}
        missing_in_records = []
        
        with open(ground_truth_file, 'r', encoding='utf-8') as f:
            for line_num, line in enumerate(f, 1):
                line = line.strip()
                if not line:
                    continue
                record = json.loads(line)
                keys = set(record.get("block_size_results", {}).keys())
                if keys != expected_sizes:
                    missing_in_records.append({
                        "line": line_num,
                        "sample_id": record.get("sample_id"),
                        "expected": sorted(expected_sizes),
                        "found": sorted(keys)
                    })
        
        assert not missing_in_records, (
            f"Found {len(missing_in_records)} records with missing or extra block sizes. "
            f"Details: {missing_in_records}"
        )
    
    def test_optimal_block_size_logic(self, ground_truth_file: Path):
        """
        Verify that the optimal_block_size (B*) is correctly calculated:
        1. It must be the block size with the minimum latency.
        2. If there's a tie, the smallest block size must be chosen.
        """
        violations = []
        
        with open(ground_truth_file, 'r', encoding='utf-8') as f:
            for line_num, line in enumerate(f, 1):
                line = line.strip()
                if not line:
                    continue
                record = json.loads(line)
                
                if record.get("status") != "success":
                    continue
                
                results = record.get("block_size_results", {})
                b_star = record.get("optimal_block_size")
                
                # Filter out OOMs (None values)
                valid_results = {k: v for k, v in results.items() if v is not None}
                
                if not valid_results:
                    # If success but no valid results, that's a logic error
                    violations.append(f"Line {line_num}: Status 'success' but no valid latencies found.")
                    continue
                
                min_latency = min(valid_results.values())
                candidates = [k for k, v in valid_results.items() if v == min_latency]
                expected_b_star = min(candidates)  # Tie-breaking rule
                
                if b_star != expected_b_star:
                    violations.append(
                        f"Line {line_num}: Incorrect B*. "
                        f"Expected {expected_b_star} (min of {candidates}), got {b_star}. "
                        f"Latencies: {valid_results}"
                    )
        
        assert not violations, (
            f"Optimal block size calculation violations found:\n" + "\n".join(violations)
        )