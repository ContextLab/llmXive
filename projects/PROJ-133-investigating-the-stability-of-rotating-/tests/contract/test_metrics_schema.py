"""
Contract test for the StabilityMetric output schema.

This test verifies that the metrics generated by the analysis pipeline
strictly adhere to the schema defined in `models.entities.StabilityMetric`.
It ensures data types, required fields, and structural integrity are maintained
across the US2 implementation.
"""
import pytest
import numpy as np
from datetime import datetime
from typing import Dict, Any

# Imports from project API surface
from models.entities import StabilityMetric, SimulationRun
from utils.io_helpers import save_dataframe, load_dataframe
from utils.logger import get_logger
from utils.seed_manager import derive_seed

logger = get_logger(__name__)


def _generate_valid_metric_data() -> Dict[str, Any]:
    """
    Generates a dictionary of values that satisfy the StabilityMetric schema.
    This is used to construct valid instances for the contract test.
    """
    run_id = derive_seed("test_metrics_contract", 42)
    return {
        "run_id": f"sim_{run_id}",
        "timestamp": datetime.now(),
        "omega": 0.5,
        "epsilon_dd": 0.5,
        "N": 10000,
        "vortex_density": 0.0012,  # vortices per unit area (FR-004)
        "radial_variance": 0.05,
        "structure_factor_sharpness": 0.85,
        "is_stable": True,
        "metastable_drop_percent": 0.0,
        "simulation_status": "SUCCESS",
        "grid_size": 64,
        "run_time_seconds": 12.5
    }


def test_metrics_schema_structure():
    """
    Contract Test: test_metrics_schema
    
    Verifies that the StabilityMetric dataclass enforces the correct structure,
    types, and required fields as defined in the specification (US2).
    
    Specifically checks:
    1. Instantiation with valid data succeeds.
    2. All required fields defined in spec FR-004 (vortex_density, etc.) exist.
    3. Type checking works as expected (e.g., numeric fields are float/int).
    """
    data = _generate_valid_metric_data()
    
    # 1. Verify instantiation
    try:
        metric = StabilityMetric(**data)
    except Exception as e:
        pytest.fail(f"StabilityMetric failed to instantiate with valid schema data: {e}")

    # 2. Verify specific fields required by FR-004 (vortex_density) and US2
    assert hasattr(metric, 'vortex_density'), "Missing required field 'vortex_density' per FR-004"
    assert hasattr(metric, 'radial_variance'), "Missing required field 'radial_variance'"
    assert hasattr(metric, 'structure_factor_sharpness'), "Missing required field 'structure_factor_sharpness'"
    
    # 3. Verify types
    assert isinstance(metric.vortex_density, float), "vortex_density must be float"
    assert isinstance(metric.radial_variance, float), "radial_variance must be float"
    assert isinstance(metric.structure_factor_sharpness, float), "structure_factor_sharpness must be float"
    assert isinstance(metric.is_stable, bool), "is_stable must be bool"
    assert isinstance(metric.run_id, str), "run_id must be str"

    logger.info("Contract test passed: StabilityMetric schema is valid and complete.")


def test_metrics_schema_serialization():
    """
    Contract Test: Verify that StabilityMetric can be serialized to a DataFrame
    and back without losing schema integrity.
    """
    data = _generate_valid_metric_data()
    metric = StabilityMetric(**data)
    
    # Convert to dict for DataFrame (standard practice in pipeline)
    metric_dict = metric.__dict__
    
    # Save to temporary location (simulating pipeline output)
    # We use a unique path to avoid collisions in parallel runs
    import tempfile
    import os
    from pathlib import Path
    
    temp_dir = Path(tempfile.mkdtemp())
    output_path = temp_dir / "test_metrics_output.csv"
    
    try:
        save_dataframe([metric_dict], str(output_path))
        
        # Load back
        loaded_df = load_dataframe(str(output_path))
        
        # Verify schema presence in loaded data
        required_cols = ['vortex_density', 'radial_variance', 'structure_factor_sharpness', 'is_stable']
        for col in required_cols:
            assert col in loaded_df.columns, f"Schema violation: Column '{col}' missing after serialization round-trip"
        
        # Verify types in loaded data (pandas may infer dtypes)
        assert isinstance(loaded_df['vortex_density'].iloc[0], (float, np.floating)), \
            "vortex_density type corrupted during serialization"
            
    finally:
        # Cleanup
        if output_path.exists():
            output_path.unlink()
        if temp_dir.exists():
            temp_dir.rmdir()

    logger.info("Contract test passed: Metrics serialization schema is valid.")


