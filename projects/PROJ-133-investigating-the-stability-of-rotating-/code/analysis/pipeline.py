"""
Analysis Pipeline for Rotating Bose-Einstein Condensates.

This module integrates vortex detection and stability metric calculation
into a unified processing pipeline. It processes simulation snapshot files
generated by the GPE solver, detects vortices, calculates stability metrics,
and outputs aggregated results.

Dependencies:
    - analysis.vortex_detector: detect_vortices_phase_winding
    - analysis.metrics: calculate_all_metrics, process_snapshot_file
    - models.entities: StabilityMetric
    - utils.io_helpers: load_simulation_snapshot, save_simulation_snapshot
    - utils.logger: get_logger
    - config.grid_config: get_grid_resolution
"""

