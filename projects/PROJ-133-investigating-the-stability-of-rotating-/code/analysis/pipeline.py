logger = get_logger(__name__)


def process_single_snapshot(
    snapshot_path: str,
    output_dir: Optional[str] = None,
    overwrite: bool = False
) -> Optional[Dict[str, Any]]:
    """
    Process a single simulation snapshot file.

    This function:
    1. Loads the simulation snapshot (density and phase data).
    2. Detects vortices using phase winding analysis.
    3. Calculates stability metrics (vortex density, radial variance, structure factor).
    4. Saves the results if an output directory is specified.

    Args:
        snapshot_path: Path to the input snapshot file (.npy or .csv).
        output_dir: Directory to save the results. If None, results are returned in memory.
        overwrite: If True, overwrite existing output files.

    Returns:
        A dictionary containing the stability metrics and vortex data, or None if processing fails.
    """
    logger.info(f"Processing snapshot: {snapshot_path}")

    if not os.path.exists(snapshot_path):
        logger.error(f"Snapshot file not found: {snapshot_path}")
        return None

    try:
        # Load snapshot
        density, phase, metadata = load_simulation_snapshot(snapshot_path)
        logger.debug(f"Loaded snapshot with shape: {density.shape}, metadata keys: {list(metadata.keys())}")

        # Detect vortices
        vortices = detect_vortices_phase_winding(density, phase)
        logger.info(f"Detected {len(vortices)} vortices in {snapshot_path}")

        # Calculate metrics
        metrics = calculate_all_metrics(density, phase, vortices, metadata)
        logger.info(f"Calculated metrics: {metrics}")

        # Prepare result dictionary
        result = {
            'snapshot_path': snapshot_path,
            'vortices': vortices,
            'metrics': metrics,
            'metadata': metadata
        }

        # Save results if output directory specified
        if output_dir:
            os.makedirs(output_dir, exist_ok=True)
            base_name = os.path.splitext(os.path.basename(snapshot_path))[0]
            output_file = os.path.join(output_dir, f"{base_name}_metrics.json")

            if os.path.exists(output_file) and not overwrite:
                logger.warning(f"Output file exists, skipping: {output_file}")
            else:
                # Convert vortices to JSON-serializable format
                serializable_vortices = [
                    {'x': v[0], 'y': v[1], 'charge': v[2]} for v in vortices
                ]
                result_to_save = {
                    'snapshot_path': snapshot_path,
                    'vortices': serializable_vortices,
                    'metrics': metrics,
                    'metadata': metadata
                }
                save_simulation_snapshot(result_to_save, output_file)
                logger.info(f"Saved results to: {output_file}")

        return result

    except Exception as e:
        logger.error(f"Error processing snapshot {snapshot_path}: {str(e)}", exc_info=True)
        return None


def process_batch_snapshots(
    input_dir: str,
    output_dir: str,
    pattern: str = "*.npy",
    overwrite: bool = False
) -> List[Dict[str, Any]]:
    """
    Process multiple snapshot files from a directory.

    Args:
        input_dir: Directory containing input snapshot files.
        output_dir: Directory to save processed results.
        pattern: Glob pattern for input files (default: "*.npy").
        overwrite: If True, overwrite existing output files.

    Returns:
        List of result dictionaries for successfully processed snapshots.
    """
    logger.info(f"Processing batch from {input_dir} with pattern {pattern}")

    if not os.path.isdir(input_dir):
        logger.error(f"Input directory does not exist: {input_dir}")
        return []

    # Find all matching files
    input_files = list(Path(input_dir).glob(pattern))
    logger.info(f"Found {len(input_files)} files to process")

    if not input_files:
        logger.warning(f"No files found matching pattern {pattern} in {input_dir}")
        return []

    results = []
    successful = 0
    failed = 0

    for snapshot_path in input_files:
        result = process_single_snapshot(
            str(snapshot_path),
            output_dir=output_dir,
            overwrite=overwrite
        )

        if result is not None:
            results.append(result)
            successful += 1
        else:
            failed += 1

    logger.info(f"Batch processing complete: {successful} successful, {failed} failed")
    return results


def aggregate_results(results: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Aggregate results from multiple snapshot processing runs.

    Args:
        results: List of result dictionaries from process_single_snapshot.

    Returns:
        Aggregated statistics and summary.
    """
    if not results:
        logger.warning("No results to aggregate")
        return {'error': 'No results provided'}

    total_vortices = sum(len(r['vortices']) for r in results)
    total_snapshots = len(results)

    # Calculate average metrics
    avg_vortex_density = 0.0
    avg_radial_variance = 0.0
    avg_structure_factor_sharpness = 0.0

    count = 0
    for r in results:
        if 'metrics' in r:
            avg_vortex_density += r['metrics'].get('vortex_density', 0.0)
            avg_radial_variance += r['metrics'].get('radial_variance', 0.0)
            avg_structure_factor_sharpness += r['metrics'].get('structure_factor_sharpness', 0.0)
            count += 1

    if count > 0:
        avg_vortex_density /= count
        avg_radial_variance /= count
        avg_structure_factor_sharpness /= count

    return {
        'total_snapshots': total_snapshots,
        'total_vortices': total_vortices,
        'average_vortex_density': avg_vortex_density,
        'average_radial_variance': avg_radial_variance,
        'average_structure_factor_sharpness': avg_structure_factor_sharpness,
        'results': results
    }


def main():
    """
    Main entry point for the analysis pipeline.

    Usage:
        python code/analysis/pipeline.py --input /path/to/snapshots --output /path/to/results
        python code/analysis/pipeline.py --batch --input /path/to/snapshots --output /path/to/results
    """
    parser = argparse.ArgumentParser(
        description="Analysis Pipeline for Rotating BEC Snapshots"
    )
    parser.add_argument(
        '--input', '-i',
        required=True,
        help='Input snapshot file or directory'
    )
    parser.add_argument(
        '--output', '-o',
        required=True,
        help='Output directory for results'
    )
    parser.add_argument(
        '--batch', '-b',
        action='store_true',
        help='Process all .npy files in input directory'
    )
    parser.add_argument(
        '--overwrite',
        action='store_true',
        help='Overwrite existing output files'
    )
    parser.add_argument(
        '--pattern', '-p',
        default="*.npy",
        help='Glob pattern for batch processing (default: *.npy)'
    )

    args = parser.parse_args()

    # Ensure output directory exists
    os.makedirs(args.output, exist_ok=True)

    if args.batch:
        # Batch processing mode
        results = process_batch_snapshots(
            args.input,
            args.output,
            pattern=args.pattern,
            overwrite=args.overwrite
        )

        if results:
            aggregated = aggregate_results(results)
            # Save aggregated results
            agg_file = os.path.join(args.output, "aggregated_results.json")
            save_simulation_snapshot(aggregated, agg_file)
            logger.info(f"Saved aggregated results to: {agg_file}")
    else:
        # Single file processing mode
        result = process_single_snapshot(
            args.input,
            output_dir=args.output,
            overwrite=args.overwrite
        )

        if result:
            logger.info(f"Successfully processed: {args.input}")
        else:
            logger.error(f"Failed to process: {args.input}")
            sys.exit(1)

    logger.info("Pipeline execution complete")


if __name__ == "__main__":
    main()