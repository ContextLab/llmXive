"""
T031: Sensitivity Analysis Sweep for P-Value Validity in High-Dimensional Data.

Reads KS statistics from data/results/ks_stats.json, groups by rho,
identifies the worst-case scenario (max KS) for each rho with tie-breaking,
and outputs data/results/sensitivity.csv.
"""
import json
import logging
import os
import sys
from pathlib import Path
from typing import Dict, List, Any, Optional, Tuple

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

KS_STATS_PATH = Path("data/results/ks_stats.json")
OUTPUT_PATH = Path("data/results/sensitivity.csv")

def load_ks_stats() -> Dict[str, Any]:
    """Load KS statistics from the JSON file generated by T029."""
    if not KS_STATS_PATH.exists():
        raise FileNotFoundError(f"Required input file not found: {KS_STATS_PATH}. "
                                "Ensure T029 has completed successfully.")
    
    with open(KS_STATS_PATH, 'r') as f:
        data = json.load(f)
    
    if not isinstance(data, dict):
        raise ValueError(f"Expected ks_stats.json to be a dictionary, got {type(data)}")
    
    return data

def calculate_ks_statistic_for_rho(
    ks_data: Dict[str, Any], 
    rho: float
) -> List[Dict[str, Any]]:
    """
    Filter KS statistics for a specific rho value.
    
    Args:
        ks_data: The full dictionary of KS statistics.
        rho: The correlation coefficient to filter by.
        
    Returns:
        List of dictionaries containing ks_stat, n, p, seed, and rho for the given rho.
    """
    results = []
    for key, entry in ks_data.items():
        # Entry structure expected: {"seed": int, "n": int, "p": int, "rho": float, "ks_stat": float}
        if isinstance(entry, dict) and 'rho' in entry:
            # Use a small tolerance for float comparison if necessary, but exact match preferred for generated data
            if abs(entry['rho'] - rho) < 1e-6:
                results.append({
                    'seed': entry.get('seed'),
                    'n': entry.get('n'),
                    'p': entry.get('p'),
                    'rho': entry['rho'],
                    'ks_stat': entry.get('ks_stat')
                })
    return results

def select_worst_case(
    candidates: List[Dict[str, Any]], 
    rho: float
) -> Optional[Dict[str, Any]]:
    """
    Select the worst-case scenario for a given rho.
    
    Tie-breaking rules:
    1. Max KS statistic.
    2. If tie, highest p/n ratio.
    3. If still tie, highest rho (though rho is constant here, this handles edge cases).
    
    Args:
        candidates: List of candidate entries for the specific rho.
        rho: The rho value for context.
        
    Returns:
        The selected candidate dictionary with 'worst_case_flag' set to True, or None if empty.
    """
    if not candidates:
        return None
    
    def sort_key(entry):
        ks = entry['ks_stat']
        n = entry['n']
        p = entry['p']
        # Avoid division by zero
        pn_ratio = p / n if n > 0 else 0
        # Sort by KS (desc), then p/n ratio (desc), then rho (desc)
        # We use negative for descending order in Python's sort
        return (ks, pn_ratio, rho)
    
    # Sort candidates: highest KS first, then highest p/n, then highest rho
    sorted_candidates = sorted(candidates, key=sort_key, reverse=True)
    
    winner = sorted_candidates[0]
    winner['worst_case_flag'] = True
    return winner

def run_sensitivity_analysis() -> None:
    """
    Main logic to run the sensitivity analysis sweep.
    """
    logger.info(f"Loading KS statistics from {KS_STATS_PATH}")
    ks_data = load_ks_stats()
    
    # Define the rho sweep as per task specification
    rhos = [0.0, 0.1, 0.3, 0.5, 0.7, 0.9]
    
    sensitivity_results = []
    
    for rho in rhos:
        logger.info(f"Processing rho = {rho}")
        candidates = calculate_ks_statistic_for_rho(ks_data, rho)
        
        if not candidates:
            logger.warning(f"No data found for rho = {rho}. Skipping.")
            continue
        
        worst_case = select_worst_case(candidates, rho)
        if worst_case:
            sensitivity_results.append(worst_case)
            logger.info(f"  Worst case for rho={rho}: KS={worst_case['ks_stat']:.4f} "
                        f"(n={worst_case['n']}, p={worst_case['p']}, seed={worst_case['seed']})")
    
    if not sensitivity_results:
        logger.error("No results generated. Check input data.")
        return

    # Write to CSV
    logger.info(f"Writing sensitivity analysis to {OUTPUT_PATH}")
    
    # Ensure output directory exists
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    
    fieldnames = ['rho', 'n', 'p', 'ks_stat', 'worst_case_flag']
    
    with open(OUTPUT_PATH, 'w', newline='') as f:
        writer = logging.NullHandler() # Just to get a reference, we use csv writer below
        import csv
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        
        for row in sensitivity_results:
            # Ensure types are correct for CSV
            out_row = {
                'rho': row['rho'],
                'n': row['n'],
                'p': row['p'],
                'ks_stat': row['ks_stat'],
                'worst_case_flag': row['worst_case_flag']
            }
            writer.writerow(out_row)
    
    logger.info("Sensitivity analysis completed successfully.")

def main():
    """Entry point for the script."""
    try:
        run_sensitivity_analysis()
    except FileNotFoundError as e:
        logger.error(f"Input file error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during sensitivity analysis: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()
