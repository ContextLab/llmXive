import json
import logging
import os
import sys
from pathlib import Path
from typing import Dict, List, Any, Optional

# Ensure project root is in path for imports if running as script
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from utils.exceptions import HighDimensionalInstabilityError

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def load_master_seed(master_seed_path: Path) -> int:
    """
    Load the master seed from the specified file.
    If the file does not exist, create it with the default seed 42.
    """
    if not master_seed_path.exists():
        logger.info(f"Master seed file {master_seed_path} not found. Creating with default value 42.")
        master_seed_path.parent.mkdir(parents=True, exist_ok=True)
        with open(master_seed_path, 'w') as f:
            f.write("42")
        return 42

    try:
        with open(master_seed_path, 'r') as f:
            seed_str = f.read().strip()
            return int(seed_str)
    except ValueError:
        logger.error(f"Invalid master seed value in {master_seed_path}. Expected integer.")
        raise ValueError(f"Invalid master seed value: {seed_str}")

def load_params(params_csv_path: Path) -> List[Dict[str, Any]]:
    """
    Load parameter rows from the CSV file generated by T017.
    Returns a list of dictionaries.
    """
    if not params_csv_path.exists():
        logger.error(f"Parameter CSV file {params_csv_path} not found. T017 must be completed first.")
        raise FileNotFoundError(f"Parameter CSV file not found: {params_csv_path}")

    import csv
    params = []
    with open(params_csv_path, 'r', newline='') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Convert numeric strings to appropriate types
            processed_row = {}
            for key, value in row.items():
                if key == 'seed':
                    processed_row[key] = int(value)
                elif key in ['n', 'p']:
                    processed_row[key] = int(value)
                elif key == 'rho':
                    processed_row[key] = float(value)
                else:
                    processed_row[key] = value
            params.append(processed_row)

    logger.info(f"Loaded {len(params)} parameter combinations from {params_csv_path}")
    return params

def build_seed_map(params: List[Dict[str, Any]], master_seed: int) -> Dict[str, List[int]]:
    """
    Build the seed map: maps (n, p, rho, distribution_type) to a list of seeds.
    Seeds are assigned sequentially starting from master_seed.
    """
    seed_map: Dict[str, List[int]] = {}
    current_seed = master_seed

    for param in params:
        n = param['n']
        p = param['p']
        rho = param['rho']
        dist_type = param['distribution_type']

        # Create a unique key for the parameter combination
        key = f"n={n}_p={p}_rho={rho}_dist={dist_type}"

        if key not in seed_map:
            seed_map[key] = []

        # Assign the current seed and increment
        seed_map[key].append(current_seed)
        current_seed += 1

    logger.info(f"Built seed map with {len(seed_map)} unique parameter combinations.")
    logger.info(f"Total seeds assigned: {current_seed - master_seed}")
    return seed_map

def write_seed_map(seed_map: Dict[str, List[int]], output_path: Path) -> None:
    """
    Write the seed map to a JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(seed_map, f, indent=2, sort_keys=True)
    logger.info(f"Seed map written to {output_path}")

def main():
    """
    Main entry point for T019b: Generate seed map.
    """
    # Define paths relative to project root
    project_root = Path(__file__).resolve().parent.parent
    sweep_dir = project_root / 'data' / 'sweep'
    master_seed_path = sweep_dir / 'master_seed.txt'
    params_csv_path = sweep_dir / 'params.csv'
    seed_map_output_path = sweep_dir / 'seed_map.json'

    logger.info("Starting T019b: Generate seed map")

    try:
        # 1. Load master seed
        master_seed = load_master_seed(master_seed_path)
        logger.info(f"Master seed loaded: {master_seed}")

        # 2. Load parameters from T017 output
        params = load_params(params_csv_path)

        # 3. Build seed map
        seed_map = build_seed_map(params, master_seed)

        # 4. Write seed map to JSON
        write_seed_map(seed_map, seed_map_output_path)

        logger.info("T019b completed successfully.")

    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Value error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during seed map generation: {e}")
        sys.exit(1)

if __name__ == '__main__':
    main()
