"""
Contract test for results/coverage.csv schema.

This test verifies that the output file generated by the pipeline
strictly adheres to the schema defined in contracts/output.schema.yaml.
It checks for required columns, data types, and value constraints.
"""

import os
import yaml
import pandas as pd
import pytest
from pathlib import Path

# Project root relative to test execution
PROJECT_ROOT = Path(__file__).parent.parent.parent
SCHEMA_PATH = PROJECT_ROOT / "contracts" / "output.schema.yaml"
OUTPUT_PATH = PROJECT_ROOT / "results" / "coverage.csv"


def load_schema():
    """Load the schema definition from the YAML file."""
    if not SCHEMA_PATH.exists():
        raise FileNotFoundError(f"Schema file not found: {SCHEMA_PATH}")
    with open(SCHEMA_PATH, "r") as f:
        return yaml.safe_load(f)


def get_dataframe():
    """Load the coverage results dataframe."""
    if not OUTPUT_PATH.exists():
        raise FileNotFoundError(
            f"Output file not found: {OUTPUT_PATH}. "
            "Run the pipeline (T014-T019) before running this contract test."
        )
    return pd.read_csv(OUTPUT_PATH)


class TestCoverageSchema:
    """Contract tests for results/coverage.csv."""

    @pytest.fixture(scope="class")
    def schema(self):
        return load_schema()

    @pytest.fixture(scope="class")
    def df(self):
        return get_dataframe()

    def test_required_columns_exist(self, df, schema):
        """Verify all columns defined in the schema are present."""
        required_columns = set(schema["required_columns"])
        actual_columns = set(df.columns)
        missing = required_columns - actual_columns
        assert not missing, f"Missing required columns: {missing}"

    def test_column_order_matches_schema(self, df, schema):
        """Verify the order of columns matches the schema definition."""
        expected_order = schema["column_order"]
        actual_order = list(df.columns)
        assert actual_order == expected_order, (
            f"Column order mismatch.\nExpected: {expected_order}\nActual: {actual_order}"
        )

    def test_data_types(self, df, schema):
        """Verify data types match the schema specifications."""
        type_map = {
            "int64": "int64",
            "float64": "float64",
            "object": "str",
            "str": "object"
        }

        for col_def in schema["columns"]:
            col_name = col_def["name"]
            expected_type_str = col_def["type"]
            expected_type = type_map.get(expected_type_str, expected_type_str)

            if col_name in df.columns:
                actual_type = str(df[col_name].dtype)
                # Normalize string types
                if expected_type_str == "str" and actual_type == "object":
                    continue
                assert actual_type == expected_type, (
                    f"Column '{col_name}' has type {actual_type}, expected {expected_type}"
                )

    def test_nominal_coverage_values(self, df, schema):
        """Verify nominal_coverage values match allowed set from config/schema."""
        allowed_values = set(schema["constraints"]["nominal_coverage"])
        actual_values = set(df["nominal_coverage"].unique())
        invalid = actual_values - allowed_values
        assert not invalid, f"Invalid nominal_coverage values found: {invalid}"

    def test_coverage_range_constraints(self, df, schema):
        """Verify coverage values are within [0, 1]."""
        coverage_cols = ["nominal_coverage", "empirical_coverage"]
        for col in coverage_cols:
            if col in df.columns:
                assert (df[col] >= 0).all() and (df[col] <= 1).all(), (
                    f"Column '{col}' contains values outside [0, 1] range."
                )

    def test_p_value_range_constraints(self, df, schema):
        """Verify p-values are within [0, 1]."""
        p_cols = ["p_raw", "p_value"]
        for col in p_cols:
            if col in df.columns:
                assert (df[col] >= 0).all() and (df[col] <= 1).all(), (
                    f"Column '{col}' contains values outside [0, 1] range."
                )

    def test_no_missing_values(self, df, schema):
        """Verify no null values in required columns."""
        required_columns = schema["required_columns"]
        for col in required_columns:
            assert df[col].isnull().sum() == 0, (
                f"Column '{col}' contains missing values."
            )

    def test_series_id_uniqueness_per_model_horizon(self, df):
        """Verify that (series_id, model, horizon) combinations are unique."""
        # Depending on aggregation logic, this might be unique or not.
        # Assuming T019 aggregates per (series, model, horizon) -> should be unique.
        unique_count = df.groupby(["series_id", "model", "horizon"]).size()
        assert (unique_count == 1).all(), (
            "Duplicate (series_id, model, horizon) combinations found."
        )
