"""
Select a high-volume subset of 1000 series from the stratified sample generated in T013a.

This script reads the sampling report generated by T013a (data/processed/sampling_report.json),
validates the distribution, and selects exactly 1000 series indices.
The selection is deterministic based on the seed used in T013a (seed=42) to ensure reproducibility.

Deliverable: data/processed/sample_indices_1000.csv
"""
import json
import logging
import os
import pandas as pd

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Constants
SAMPLING_REPORT_PATH = "data/processed/sampling_report.json"
OUTPUT_PATH = "data/processed/sample_indices_1000.csv"
TARGET_SIZE = 1000
SEED = 42

def load_sampling_report(path: str) -> dict:
    """Load the sampling report JSON file."""
    if not os.path.exists(path):
        raise FileNotFoundError(f"Sampling report not found at {path}. "
                                "Please ensure T013a has been executed successfully.")
    
    with open(path, 'r') as f:
        return json.load(f)

def select_1000_series(report: dict) -> pd.DataFrame:
    """
    Select exactly 1000 series indices from the stratified sample.
    
    The report from T013a should contain a list of selected indices.
    We verify the sample size is sufficient and then select the first 1000
    (or a deterministic subset if the sample is larger).
    """
    if "sample_indices" not in report:
        raise ValueError("Sampling report does not contain 'sample_indices' key.")
    
    all_indices = report["sample_indices"]
    total_available = len(all_indices)
    
    logger.info(f"Total available series in stratified sample: {total_available}")
    
    if total_available < TARGET_SIZE:
        raise ValueError(
            f"Insufficient series in stratified sample. "
            f"Available: {total_available}, Required: {TARGET_SIZE}. "
            f"Please re-run T013a with a larger initial sample size."
        )
    
    # Deterministic selection: sort indices to ensure reproducibility, then take first 1000
    # This assumes the original sampling was already stratified and representative
    sorted_indices = sorted(all_indices)
    selected_indices = sorted_indices[:TARGET_SIZE]
    
    logger.info(f"Selected {len(selected_indices)} series for full pipeline.")
    
    # Create DataFrame for output
    df = pd.DataFrame({
        "series_id": selected_indices
    })
    
    return df

def verify_distribution(report: dict, selected_count: int) -> bool:
    """
    Verify that the selection maintains representativeness.
    This is a simplified check assuming the stratified sample was already representative.
    """
    # In a real implementation, we might re-check frequency distribution
    # For now, we log the distribution stats from the report
    if "distribution_stats" in report:
        logger.info("Distribution stats from sampling report:")
        for key, value in report["distribution_stats"].items():
            logger.info(f"  {key}: {value}")
    
    return True

def main():
    """Main execution function."""
    logger.info("Starting T013b: Selecting 1000-series subset")
    
    # Load the sampling report
    report = load_sampling_report(SAMPLING_REPORT_PATH)
    
    # Verify we have enough data
    if "sample_indices" not in report or len(report["sample_indices"]) < TARGET_SIZE:
        logger.error("Sampling report does not contain enough indices.")
        raise ValueError("Insufficient data in sampling report.")
    
    # Select the 1000 series
    df_selected = select_1000_series(report)
    
    # Verify distribution (log only)
    verify_distribution(report, len(df_selected))
    
    # Ensure output directory exists
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    
    # Save to CSV
    df_selected.to_csv(OUTPUT_PATH, index=False)
    
    logger.info(f"Successfully saved {len(df_selected)} series indices to {OUTPUT_PATH}")
    
    # Verification: load and confirm
    df_verify = pd.read_csv(OUTPUT_PATH)
    assert len(df_verify) == TARGET_SIZE, f"Expected {TARGET_SIZE} rows, got {len(df_verify)}"
    assert "series_id" in df_verify.columns, "Missing 'series_id' column"
    
    logger.info("Verification passed: Output file contains exactly 1000 series indices.")
    
    return df_selected

if __name__ == "__main__":
    main()
