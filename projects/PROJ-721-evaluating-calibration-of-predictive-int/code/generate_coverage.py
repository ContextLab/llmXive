def load_interval_outputs(
    intervals_dir: str,
    sample_indices_file: str
) -> pd.DataFrame:
    """
    Load interval outputs from the generated files.

    Assumes the pipeline generated files like:
    data/processed/intervals_<series_id>.json or a consolidated file.
    For this task, we assume a consolidated intermediate file exists from T015:
    data/processed/interval_forecasts.csv

    If that file doesn't exist, we try to load from individual series files.
    """
    consolidated_path = os.path.join(intervals_dir, "interval_forecasts.csv")
    
    if os.path.exists(consolidated_path):
        logger.info(f"Loading consolidated interval forecasts from {consolidated_path}")
        df = pd.read_csv(consolidated_path)
        # Ensure required columns exist
        required = ['series_id', 'model', 'horizon', 'lower', 'upper']
        if not all(col in df.columns for col in required):
            # Try to explode if stored as string representation of lists
            for col in ['lower', 'upper']:
                if col in df.columns and df[col].dtype == 'object':
                    # Attempt to parse stringified lists
                    try:
                        df[col] = df[col].apply(lambda x: np.fromstring(x.strip('[]'), sep=',') if isinstance(x, str) else x)
                    except:
                        pass
        return df
    
    # Fallback: Load from individual files if consolidated doesn't exist
    # This is a placeholder logic assuming the T015 task produced individual files
    # In a real run, T015 should produce the consolidated file or this script should
    # aggregate them. For T016 implementation, we assume T015 output format.
    logger.warning(f"Consolidated file {consolidated_path} not found. Attempting to load individual series.")
    
    # Load sample indices to know which series to process
    sample_indices = pd.read_csv(sample_indices_file)
    series_ids = sample_indices['series_id'].tolist()
    
    all_intervals = []
    for sid in series_ids:
        # Assume format: data/processed/intervals_<sid>.csv
        fpath = os.path.join(intervals_dir, f"intervals_{sid}.csv")
        if os.path.exists(fpath):
            df = pd.read_csv(fpath)
            df['series_id'] = sid
            all_intervals.append(df)
    
    if not all_intervals:
        raise FileNotFoundError(f"No interval files found in {intervals_dir} for the specified series.")
    
    return pd.concat(all_intervals, ignore_index=True)


