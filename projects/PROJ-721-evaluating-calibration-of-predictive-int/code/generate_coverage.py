def main():
    parser = argparse.ArgumentParser(description="Calculate empirical coverage from interval forecasts.")
    parser.add_argument("--intervals-dir", type=str, default="data/processed",
                        help="Directory containing interval forecast outputs.")
    parser.add_argument("--sample-indices", type=str, default="data/processed/sample_indices_1000.csv",
                        help="Path to the CSV file with selected series indices.")
    parser.add_argument("--output", type=str, default="results/coverage_intermediate.csv",
                        help="Path to the output coverage CSV file.")
    
    args = parser.parse_args()
    
    # Ensure output directory exists
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    
    logger.info("Loading interval forecasts...")
    try:
        intervals_df = load_interval_outputs(args.intervals_dir, args.sample_indices)
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    
    logger.info(f"Loaded {len(intervals_df)} interval records.")
    
    logger.info("Loading actual test values...")
    try:
        actuals_df = load_actuals(args.intervals_dir, args.sample_indices)
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    
    logger.info(f"Loaded {len(actuals_df)} actual records.")
    
    logger.info("Calculating empirical coverage...")
    coverage_df = calculate_coverage_batch(intervals_df, actuals_df)
    
    logger.info(f"Calculated coverage for {len(coverage_df)} series-model-horizon combinations.")
    
    logger.info(f"Saving results to {args.output}...")
    save_coverage_results(coverage_df, args.output)
    
    logger.info("Done.")


if __name__ == "__main__":
    main()
