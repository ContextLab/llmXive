from dataclasses import dataclass, field
from typing import List, Dict, Optional, Any
import json


@dataclass
class RelevanceProfile:
    """
    Data structure representing the aggregated relevance profile for a specific chunk.
    
    Attributes:
        chunk_id: Unique identifier for the chunk (e.g., "doc_123_chunk_5").
        scores: List of retrieval scores (floats) representing relevance to other contexts.
        document_id: The ID of the source document this chunk belongs to.
    """
    chunk_id: str
    scores: List[float]
    document_id: str

    def to_dict(self) -> Dict[str, Any]:
        """Convert the RelevanceProfile to a dictionary for JSON serialization."""
        return {
            "chunk_id": self.chunk_id,
            "scores": self.scores,
            "document_id": self.document_id
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "RelevanceProfile":
        """Create a RelevanceProfile instance from a dictionary."""
        return cls(
            chunk_id=data["chunk_id"],
            scores=data["scores"],
            document_id=data["document_id"]
        )


@dataclass
class StaticIndex:
    """
    Data structure representing the static lookup table generated by K-Means clustering.
    
    Attributes:
        centroids: Numpy array of cluster centroids (shape: K x reduced_dim).
        chunk_to_cluster: Mapping from chunk_id to cluster index (int).
        k: Number of clusters used.
    """
    centroids: Any  # np.ndarray
    chunk_to_cluster: Dict[str, int]
    k: int

    def to_dict(self) -> Dict[str, Any]:
        """Convert StaticIndex to a serializable dictionary (excluding numpy arrays directly)."""
        # Note: centroids should be converted to list before final JSON dump in the service layer
        return {
            "centroids": self.centroids.tolist() if hasattr(self.centroids, 'tolist') else self.centroids,
            "chunk_to_cluster": self.chunk_to_cluster,
            "k": self.k
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "StaticIndex":
        """Create a StaticIndex instance from a dictionary."""
        import numpy as np
        centroids = np.array(data["centroids"])
        return cls(
            centroids=centroids,
            chunk_to_cluster=data["chunk_to_cluster"],
            k=data["k"]
        )


@dataclass
class EvaluationReport:
    """
    Data structure for the final evaluation report containing metrics.
    
    Attributes:
        perplexity: Perplexity score of the model.
        qa_accuracy: Accuracy on the QA benchmark.
        p_value: P-value from statistical significance testing.
        latency: Average latency in milliseconds.
        memory_footprint: Memory usage in MB.
    """
    perplexity: float
    qa_accuracy: float
    p_value: float
    latency: float
    memory_footprint: float

    def to_dict(self) -> Dict[str, float]:
        """Convert the report to a dictionary."""
        return {
            "perplexity": self.perplexity,
            "qa_accuracy": self.qa_accuracy,
            "p_value": self.p_value,
            "latency": self.latency,
            "memory_footprint": self.memory_footprint
        }