"""
Data models for the llmXive hierarchical sparse attention pipeline.

This module defines the core data structures used for representing
relevance profiles, static indices, and evaluation reports.
"""

from dataclasses import dataclass, field
from typing import List, Dict, Optional, Any
import json


@dataclass
class RelevanceProfile:
    """
    Represents the aggregated retrieval relevance profile for a specific chunk.

    Attributes:
        chunk_id: Unique identifier for the chunk (e.g., 'doc_id:chunk_idx').
        scores: List of retrieval scores corresponding to this chunk's relevance
                against the query or context window.
        document_id: The ID of the parent document this chunk belongs to.
    """
    chunk_id: str
    scores: List[float]
    document_id: str

    def to_dict(self) -> Dict[str, Any]:
        """Convert the profile to a dictionary for JSON serialization."""
        return {
            "chunk_id": self.chunk_id,
            "scores": self.scores,
            "document_id": self.document_id
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "RelevanceProfile":
        """Reconstruct a RelevanceProfile from a dictionary."""
        return cls(
            chunk_id=data["chunk_id"],
            scores=data["scores"],
            document_id=data["document_id"]
        )

    def validate(self) -> bool:
        """
        Validate the integrity of the profile.

        Returns:
            True if the profile is valid, False otherwise.
        """
        if not self.chunk_id or not isinstance(self.chunk_id, str):
            return False
        if not self.document_id or not isinstance(self.document_id, str):
            return False
        if not isinstance(self.scores, list):
            return False
        if not all(isinstance(s, (int, float)) for s in self.scores):
            return False
        return True


@dataclass
class StaticIndex:
    """
    Represents the static index generated by clustering relevance profiles.

    Attributes:
        centroids: Numpy array of cluster centroids.
        chunk_to_cluster: Mapping from chunk_id to cluster index.
        k: Number of clusters (K).
    """
    centroids: Any  # np.ndarray
    chunk_to_cluster: Dict[str, int]
    k: int

    def to_dict(self) -> Dict[str, Any]:
        """
        Convert the index to a dictionary for serialization.
        Note: centroids are serialized as lists.
        """
        import numpy as np
        return {
            "centroids": self.centroids.tolist() if isinstance(self.centroids, np.ndarray) else self.centroids,
            "chunk_to_cluster": self.chunk_to_cluster,
            "k": self.k
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "StaticIndex":
        """Reconstruct a StaticIndex from a dictionary."""
        import numpy as np
        centroids = data["centroids"]
        if isinstance(centroids, list):
            centroids = np.array(centroids)
        return cls(
            centroids=centroids,
            chunk_to_cluster=data["chunk_to_cluster"],
            k=data["k"]
        )


@dataclass
class EvaluationReport:
    """
    Structured report for comparative evaluation results.

    Attributes:
        perplexity: Perplexity metric value.
        qa_accuracy: QA accuracy metric value.
        p_value: P-value from statistical significance testing.
        latency: Latency measurement in milliseconds.
        memory_footprint: Memory usage report.
    """
    perplexity: float
    qa_accuracy: float
    p_value: float
    latency: float
    memory_footprint: Dict[str, Any]

    def to_dict(self) -> Dict[str, Any]:
        """Convert the report to a dictionary for JSON serialization."""
        return {
            "perplexity": self.perplexity,
            "qa_accuracy": self.qa_accuracy,
            "p_value": self.p_value,
            "latency": self.latency,
            "memory_footprint": self.memory_footprint
        }