"""
Contract test for ingestion output schema.
Validates the schema of `data/processed/deduplicated.csv` generated by code/ingestion.py.

This test ensures that the ingestion pipeline produces a CSV with the exact
required columns and data types as specified in the project requirements.

Expected Schema:
- smiles: string (non-empty)
- target_mean: float (numeric)
- count: integer (>= 1)
- source_id: string (non-empty)

The test loads the file produced by the ingestion pipeline and asserts
that it exists, is not empty, and matches the schema.
"""

import os
import sys
import pandas as pd
import pytest
from pathlib import Path

# Add the project root to the path to allow imports if needed,
# though this test primarily validates file contents.
PROJECT_ROOT = Path(__file__).parent.parent.parent
DATA_PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
DEDUPLICATED_CSV_PATH = DATA_PROCESSED_DIR / "deduplicated.csv"

REQUIRED_COLUMNS = ["smiles", "target_mean", "count", "source_id"]

@pytest.fixture
def deduplicated_df():
    """Load the deduplicated CSV file if it exists."""
    if not DEDUPLICATED_CSV_PATH.exists():
        pytest.fail(
            f"File not found: {DEDUPLICATED_CSV_PATH}. "
            "Please run `python code/ingestion.py` first to generate the data."
        )
    try:
        df = pd.read_csv(DEDUPLICATED_CSV_PATH)
    except Exception as e:
        pytest.fail(f"Failed to read CSV: {e}")
    return df

class TestIngestionOutputSchema:
    """Contract tests for the ingestion output schema."""

    def test_file_exists(self):
        """Assert that the deduplicated CSV file exists."""
        assert DEDUPLICATED_CSV_PATH.exists(), f"Output file missing: {DEDUPLICATED_CSV_PATH}"

    def test_file_not_empty(self, deduplicated_df):
        """Assert that the file contains at least one row."""
        assert len(deduplicated_df) > 0, "Deduplicated CSV is empty."

    def test_required_columns_present(self, deduplicated_df):
        """Assert that all required columns are present in the DataFrame."""
        missing_columns = set(REQUIRED_COLUMNS) - set(deduplicated_df.columns)
        assert not missing_columns, f"Missing required columns: {missing_columns}"

    def test_column_order(self, deduplicated_df):
        """Assert that the columns appear in the expected order."""
        # Check if the first 4 columns match the required order exactly
        actual_columns = deduplicated_df.columns.tolist()
        assert actual_columns[:4] == REQUIRED_COLUMNS, (
            f"Column order mismatch. Expected {REQUIRED_COLUMNS}, "
            f"got {actual_columns[:4]}"
        )

    def test_smiles_column_type_and_content(self, deduplicated_df):
        """Assert that 'smiles' column is string and non-empty."""
        assert deduplicated_df["smiles"].dtype == "object", "smiles column must be string/object."
        assert deduplicated_df["smiles"].notna().all(), "smiles column contains null values."
        assert (deduplicated_df["smiles"].str.strip() != "").all(), "smiles column contains empty strings."

    def test_target_mean_column_type(self, deduplicated_df):
        """Assert that 'target_mean' column is numeric."""
        assert pd.api.types.is_float_dtype(deduplicated_df["target_mean"]), (
            "target_mean column must be numeric (float)."
        )
        assert deduplicated_df["target_mean"].notna().all(), "target_mean column contains null values."

    def test_count_column_type_and_validity(self, deduplicated_df):
        """Assert that 'count' column is integer and >= 1."""
        assert pd.api.types.is_integer_dtype(deduplicated_df["count"]), (
            "count column must be integer."
        )
        assert (deduplicated_df["count"] >= 1).all(), "count column contains values < 1."
        assert deduplicated_df["count"].notna().all(), "count column contains null values."

    def test_source_id_column_type_and_content(self, deduplicated_df):
        """Assert that 'source_id' column is string and non-empty."""
        assert deduplicated_df["source_id"].dtype == "object", "source_id column must be string/object."
        assert deduplicated_df["source_id"].notna().all(), "source_id column contains null values."
        assert (deduplicated_df["source_id"].str.strip() != "").all(), "source_id column contains empty strings."

    def test_no_extra_columns(self, deduplicated_df):
        """Assert that no unexpected columns are present (strict schema)."""
        actual_columns = set(deduplicated_df.columns)
        expected_columns = set(REQUIRED_COLUMNS)
        extra_columns = actual_columns - expected_columns
        assert not extra_columns, f"Unexpected columns found: {extra_columns}"