def save_results(results: Dict[str, Any], limitations: str) -> Path:
    """
    Save ANOVA results to JSON file.
    """
    output_dir = get_data_dir() / "analysis"
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "anova_results.json"
    
    # Append limitations to results
    results["limitations"] = limitations
    results["analysis_type"] = "Between-Subjects One-Way ANOVA"
    
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    
    logger.info(f"Results saved to {output_path}")
    return output_path

