def load_false_memory_data() -> pd.DataFrame:
    """
    Load the processed false memory rate data.
    Expected input format: Long-format dataframe with columns:
    - participant_id
    - condition (Baseline, Enhanced, Reduced)
    - false_memory_rate
    """
    # Path to the processed data file (generated by T035.1 or session simulation)
    # Since T035.1 generates per-condition rates, we assume a file exists with aggregated data
    # or we generate a minimal mock dataset for the ANOVA if real data is missing.
    # However, per strict constraints, we must NOT fabricate results.
    # We will attempt to load from a standard location where T035.1 would write results.
    # If that fails, we raise an error to avoid silent fallback.
    
    data_path = get_data_dir() / "analysis" / "false_memory_rates.csv"
    
    if not data_path.exists():
        # Check for alternative location or generated by session simulation
        # If the file is missing, we cannot proceed with real data.
        # We raise an error to force the user to run the data generation steps first.
        raise FileNotFoundError(
            f"Required data file not found: {data_path}. "
            "Please ensure T035.1 (Calculate False Memory Rate) or session simulation has run."
        )

    try:
        df = pd.read_csv(data_path)
        required_cols = {'participant_id', 'condition', 'false_memory_rate'}
        if not required_cols.issubset(df.columns):
            raise ValueError(f"Data missing required columns. Found: {df.columns}, Expected: {required_cols}")
        
        logger.info(f"Loaded {len(df)} records from {data_path}")
        return df
    except Exception as e:
        logger.error(f"Failed to load data from {data_path}: {e}")
        raise

def run_anova(df: pd.DataFrame) -> Dict[str, Any]:
    """
    Perform Between-Subjects One-Way ANOVA using OLS + anova_lm.
    
    Args:
        df: Long-format dataframe with 'participant_id', 'condition', 'false_memory_rate'
        
    Returns:
        Dictionary containing ANOVA results
    """
    logger.info("Running Between-Subjects One-Way ANOVA...")
    
    # Ensure condition is treated as a categorical variable
    df['condition'] = df['condition'].astype('category')
    
    # Fit OLS model: false_memory_rate ~ C(condition)
    model = ols('false_memory_rate ~ C(condition)', data=df).fit()
    
    # Compute ANOVA table
    anova_table = anova_lm(model)
    
    # Extract metrics
    f_statistic = anova_table['F'][0]  # First row is usually the condition effect
    p_value = anova_table['PR(>F)'][0]
    
    # Degrees of freedom
    # anova_table has columns: df, sum_sq, mean_sq, F, PR(>F)
    # The row for C(condition) contains the effect df
    df_effect = anova_table['df'][0]
    df_residual = anova_table['df'][1]
    
    # Effect size (Eta-squared)
    # Eta^2 = SS_effect / SS_total
    ss_effect = anova_table['sum_sq'][0]
    ss_total = ss_effect + anova_table['sum_sq'][1]
    effect_size = ss_effect / ss_total if ss_total > 0 else 0.0
    
    results = {
        "f_statistic": float(f_statistic),
        "p_value": float(p_value),
        "effect_size": float(effect_size),
        "degrees_of_freedom": {
            "effect": int(df_effect),
            "residual": int(df_residual)
        },
        "anova_table": anova_table.to_dict()
    }
    
    logger.info(f"ANOVA Results: F={f_statistic:.4f}, p={p_value:.4f}, Eta^2={effect_size:.4f}")
    return results

