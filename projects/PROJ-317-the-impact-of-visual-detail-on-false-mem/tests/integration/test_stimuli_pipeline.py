import os
import sys
import tempfile
import yaml
from pathlib import Path

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "code"))

import pytest
from data.loader import generate_mock_visual_genome
from stimuli.manipulator import process_directory
from stimuli.metadata import load_metadata_from_yaml
from config import get_stimuli_dir, get_stimuli_metadata_dir, get_project_root


def test_full_pipeline():
    """
    Integration test for full pipeline: generate mock images -> manipulate -> metadata.
    
    Asserts that:
    1. Mock images are generated.
    2. Manipulated images (enhanced and reduced) are created for each input.
    3. A valid metadata YAML file is created for each input.
    """
    # Ensure we are working in the project's data directories
    project_root = get_project_root()
    stimuli_dir = get_stimuli_dir()
    metadata_dir = get_stimuli_metadata_dir()
    
    # Create a specific output dir for manipulated images to keep things clean and verifiable
    # The task requires asserting that manipulated images are created.
    # We define a unique subdirectory to avoid conflicts if tests run in parallel or on dirty state.
    # However, the task implies checking the standard pipeline output.
    # We will use a temporary directory for the manipulated output to ensure isolation,
    # but the input images will be generated in the standard stimuli_dir.
    # To strictly follow the "real data" constraint for the *test* (which uses mock generator as input source),
    # we rely on generate_mock_visual_genome which creates real PNG bytes.
    
    # Step 1: Generate Mock Visual Genome
    # The loader expects a count and an output directory. 
    # We'll generate 2 images to ensure "multiple" are processed.
    num_images = 2
    
    # Clean up previous test artifacts in the stimuli dir to ensure a fresh start
    # We only remove files generated by this test pattern if they exist, or clear the dir if safe.
    # For safety, we create a unique subfolder for this test run's input to avoid polluting main data.
    # But the task says "generate mock images... output to data/stimuli/raw/". 
    # The existing T006.1 logic suggests raw/ subfolder.
    # Let's adapt: we will generate into a temp subfolder within stimuli_dir to simulate the "raw" input.
    test_input_dir = stimuli_dir / "test_run_input"
    test_input_dir.mkdir(parents=True, exist_ok=True)
    
    generate_mock_visual_genome(num_images, str(test_input_dir))
    
    # Verify input images exist
    input_images = list(test_input_dir.glob("*.png"))
    assert len(input_images) == num_images, f"Expected {num_images} input images, found {len(input_images)}"
    
    # Step 2: Run Manipulation Pipeline
    # We define an output directory for manipulated images
    test_manipulated_dir = stimuli_dir / "test_run_manipulated"
    test_manipulated_dir.mkdir(parents=True, exist_ok=True)
    
    # We define a test-specific metadata directory to avoid clobbering main metadata
    test_metadata_dir = metadata_dir / "test_run"
    test_metadata_dir.mkdir(parents=True, exist_ok=True)
    
    # Execute the pipeline
    process_directory(
        input_dir=str(test_input_dir),
        output_dir=str(test_manipulated_dir),
        metadata_dir=str(test_metadata_dir)
    )
    
    # Step 3: Verify Artifacts
    
    # 3a: Check that manipulated images exist
    # The manipulator should create 'enhanced' and 'reduced' versions.
    # Based on typical naming in such pipelines, they might be named <id>_enhanced.png, <id>_reduced.png
    enhanced_images = list(test_manipulated_dir.glob("*_enhanced.png"))
    reduced_images = list(test_manipulated_dir.glob("*_reduced.png"))
    
    # We expect 2 enhanced and 2 reduced images (one for each input)
    assert len(enhanced_images) == num_images, f"Expected {num_images} enhanced images, found {len(enhanced_images)}"
    assert len(reduced_images) == num_images, f"Expected {num_images} reduced images, found {len(reduced_images)}"
    
    # 3b: Check that metadata files exist
    # The metadata should be in metadata_dir with .yaml extension
    metadata_files = list(test_metadata_dir.glob("*.yaml"))
    
    # We expect one metadata file per input image
    assert len(metadata_files) >= num_images, f"Expected at least {num_images} metadata files, found {len(metadata_files)}"
    
    # 3c: Verify metadata content is valid YAML and contains expected keys
    for meta_file in metadata_files:
        with open(meta_file, 'r') as f:
            try:
                data = yaml.safe_load(f)
                assert data is not None, f"Metadata file {meta_file} is empty or invalid YAML"
                # Check for key fields defined in StimulusMetadata dataclass
                # The metadata generator creates 'image_id' or 'id'
                assert 'image_id' in data or 'id' in data, f"Metadata file {meta_file} missing image_id"
                assert 'manipulations' in data, f"Metadata file {meta_file} missing manipulations list"
                # Verify manipulations list has entries
                assert isinstance(data['manipulations'], list), "Manipulations should be a list"
                # We expect at least 2 manipulations (enhanced and reduced) per image
                assert len(data['manipulations']) >= 2, "Should have at least enhanced and reduced manipulations"
                
                # Verify specific manipulation types exist
                types = [m.get('type') for m in data['manipulations']]
                assert 'enhanced' in types, "Missing 'enhanced' manipulation in metadata"
                assert 'reduced' in types, "Missing 'reduced' manipulation in metadata"
                
            except yaml.YAMLError as e:
                pytest.fail(f"Invalid YAML in {meta_file}: {e}")