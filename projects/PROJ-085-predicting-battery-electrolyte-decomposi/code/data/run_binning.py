"""
Simple binning script required by the quickstart pipeline.

It reads the processed feature matrix (generated by the descriptor pipeline),
assigns a ``bin`` column based on the electrochemical potential, and writes the
result to ``data/processed/bins.csv``.
"""

import sys
from pathlib import Path

import pandas as pd

# Project‑relative helpers
from config import get_data_dir, get_processed_dir
from utils.constants import get_potential_bin

def main() -> None:
    # Locate the features file produced by the descriptor step
    data_dir = Path(get_data_dir())
    processed_dir = Path(get_processed_dir())

    features_path = data_dir / "raw" / "electrolytes_raw.csv"
    if not features_path.exists():
        # Fallback to the processed feature matrix if the raw file was moved
        features_path = processed_dir / "electrolyte_features.csv"

    if not features_path.exists():
        raise FileNotFoundError(f"Feature matrix not found at {features_path}")

    df = pd.read_csv(features_path)

    if "potential_v" not in df.columns:
        raise KeyError("Column 'potential_v' is required for binning but was not found.")

    # Assign bin label
    df["bin"] = df["potential_v"].apply(get_potential_bin)

    # Write output
    output_path = processed_dir / "bins.csv"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    print(f"Binning completed. Output written to {output_path}")


if __name__ == "__main__":
    main()
