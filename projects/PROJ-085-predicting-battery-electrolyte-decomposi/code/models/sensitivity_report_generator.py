import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional
import pandas as pd

from config import get_project_root, get_validation_dir, get_processed_dir
from utils.logging_config import get_logger

logger = get_logger(__name__)

def load_sensitivity_results() -> Optional[Dict[str, Any]]:
    """
    Load the sensitivity analysis results from the JSON artifact generated by T031/T032.
    Expected path: data/processed/sensitivity_analysis_results.json
    """
    root = get_project_root()
    results_path = root / "data" / "processed" / "sensitivity_analysis_results.json"
    
    if not results_path.exists():
        logger.error(f"Sensitivity results file not found at {results_path}. "
                     "Ensure T031 and T032 have been run successfully.")
        return None
    
    try:
        with open(results_path, 'r') as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse sensitivity results JSON: {e}")
        return None

def load_model_info() -> Optional[Dict[str, Any]]:
    """
    Load model artifacts and metadata from T026.
    Expected path: data/processed/model_run.json
    """
    root = get_project_root()
    model_path = root / "data" / "processed" / "model_run.json"
    
    if not model_path.exists():
        logger.error(f"Model run file not found at {model_path}. "
                     "Ensure T026 has been run successfully.")
        return None
    
    try:
        with open(model_path, 'r') as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse model run JSON: {e}")
        return None

def generate_report_content(
    sensitivity_results: Dict[str, Any], 
    model_info: Dict[str, Any]
) -> str:
    """
    Generate the Markdown content for the sensitivity analysis report.
    Includes:
    1. Executive Summary
    2. Methodology (Threshold Sweep)
    3. Rank Stability Results
    4. Feature Importance Shifts
    5. Warnings/Deviations (FR-006/SC-003)
    """
    thresholds = sensitivity_results.get("thresholds_swept", [])
    rank_stability = sensitivity_results.get("rank_stability", {})
    feature_shifts = sensitivity_results.get("feature_shifts", {})
    internal_metrics = sensitivity_results.get("internal_metrics", {})
    
    model_r2 = model_info.get("r2_score", "N/A")
    model_mae = model_info.get("mae", "N/A")
    
    report_lines = [
        "# Sensitivity Analysis Report: Decomposition Energy Stability",
        "",
        "## 1. Executive Summary",
        "",
        "This report details the sensitivity of the Random Forest model's feature importance rankings",
        "to variations in the decomposition energy stability cutoff threshold.",
        f"- **Model R² Score**: {model_r2}",
        f"- **Internal Consistency MAE**: {model_mae}",
        "",
        "## 2. Methodology",
        "",
        "A threshold sweep was performed on the 'decomposition energy stability cutoff' parameter.",
        "The following thresholds were evaluated:",
        "",
    ]
    
    for t in thresholds:
        report_lines.append(f"- {t:.2f} eV")
        
    report_lines.extend([
        "",
        "## 3. Rank Stability Analysis",
        "",
        "The stability of the top 3 descriptors was verified across the swept thresholds.",
        f"- **Max Rank Shift Observed**: {rank_stability.get('max_rank_shift', 'N/A')} positions",
        f"- **Stability Threshold**: ≤ 1 position",
        f"- **Verdict**: {'PASS' if rank_stability.get('is_stable', False) else 'FAIL'}",
        "",
        "### Top 3 Descriptors by Threshold",
        "",
        "| Threshold (eV) | Rank 1 | Rank 2 | Rank 3 |",
        "|----------------|--------|--------|--------|",
    ])
    
    for t in thresholds:
        key = f"{t:.2f}"
        top_features = feature_shifts.get(key, {}).get("top_3", [])
        if len(top_features) >= 3:
            r1, r2, r3 = top_features[0], top_features[1], top_features[2]
        elif len(top_features) == 2:
            r1, r2, r3 = top_features[0], top_features[1], "N/A"
        elif len(top_features) == 1:
            r1, r2, r3 = top_features[0], "N/A", "N/A"
        else:
            r1, r2, r3 = "N/A", "N/A", "N/A"
        
        report_lines.append(f"| {t:.2f} | {r1} | {r2} | {r3} |")
        
    report_lines.extend([
        "",
        "## 4. Feature Importance Shifts",
        "",
        "Analysis of descriptors entering the top 3 at high-potential (4V) but absent in low-potential (0-2V).",
        "(Note: High-potential range 3-5V approximated by 4V data point due to data constraints.)",
        "",
    ])
    
    shifted = feature_shifts.get("shifted_high_potential", [])
    if shifted:
        for feature in shifted:
            report_lines.append(f"- **{feature}**")
    else:
        report_lines.append("- No significant shifts identified in top 3 across bins.")
        
    report_lines.extend([
        "",
        "## 5. Warnings and Deviations",
        "",
        "> **WARNING**: FR-006 and SC-003 (External Validation) could not be fulfilled due to unavailability of experimental onset potential datasets. Internal DFT validation was used as a fallback.",
        "",
        "This report relies on internal consistency metrics (MAE, R² against held-out DFT data) rather than experimental ground truth.",
        "Consequently, the model predicts thermodynamic stability ($E_{decomp}$) rather than kinetic onset potentials.",
        "",
        "---",
        "*Generated by llmXive Pipeline*",
    ])
    
    return "\n".join(report_lines)

def run_report_generation() -> bool:
    """
    Main entry point to generate the sensitivity report.
    Reads T031/T032 results and T026 model info, writes to data/validation/sensitivity_report.md.
    """
    logger.info("Starting sensitivity report generation...")
    
    sensitivity_results = load_sensitivity_results()
    if not sensitivity_results:
        logger.error("Aborting report generation: Could not load sensitivity results.")
        return False
        
    model_info = load_model_info()
    if not model_info:
        logger.error("Aborting report generation: Could not load model info.")
        return False
    
    report_content = generate_report_content(sensitivity_results, model_info)
    
    output_dir = get_validation_dir()
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "sensitivity_report.md"
    
    try:
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(report_content)
        logger.info(f"Successfully generated sensitivity report at {output_path}")
        return True
    except IOError as e:
        logger.error(f"Failed to write report to {output_path}: {e}")
        return False

if __name__ == "__main__":
    success = run_report_generation()
    sys.exit(0 if success else 1)
