import os
import json
from pathlib import Path
from typing import Optional, Dict, Any

# Project Root
_PROJECT_ROOT = Path(__file__).parent.parent.resolve()

# Configuration Dictionary
_CONFIG: Dict[str, Any] = {
    # Seeds
    "random_seed": 42,
    
    # Dataset URLs
    "dataset_url": "https://huggingface.co/datasets/materialsproject/mp-dft-electrolytes",
    
    # Paths (relative to project root)
    "data_dir": "data",
    "raw_dir": "data/raw",
    "processed_dir": "data/processed",
    "validation_dir": "data/validation",
    "output_dir": "data/outputs",
    "models_dir": "code/models",
    
    # Model Run Artifact (generated by T026/T031)
    "model_run_path": "data/processed/model_run.json",
    
    # Fallback paths
    "fallback_electrolytes_path": "data/raw/mock_electrolytes.csv",
    
    # Debug
    "debug_mode": False,
    "log_level": "INFO"
}

def get_project_root() -> Path:
    """Returns the absolute path to the project root."""
    return _PROJECT_ROOT

def get_config() -> Dict[str, Any]:
    """Returns the current configuration dictionary."""
    return _CONFIG.copy()

def get_seed() -> int:
    """Returns the configured random seed."""
    return _CONFIG["random_seed"]

def set_seed(seed: int) -> None:
    """Sets the random seed in configuration."""
    _CONFIG["random_seed"] = seed

def get_dataset_url() -> str:
    """Returns the configured dataset URL."""
    return _CONFIG["dataset_url"]

def set_dataset_url(url: str) -> None:
    """Sets the dataset URL in configuration."""
    _CONFIG["dataset_url"] = url

def get_data_dir() -> Path:
    """Returns the path to the data directory."""
    return _PROJECT_ROOT / _CONFIG["data_dir"]

def get_raw_dir() -> Path:
    """Returns the path to the raw data directory."""
    return _PROJECT_ROOT / _CONFIG["raw_dir"]

def get_processed_dir() -> Path:
    """Returns the path to the processed data directory."""
    return _PROJECT_ROOT / _CONFIG["processed_dir"]

def get_validation_dir() -> Path:
    """Returns the path to the validation data directory."""
    return _PROJECT_ROOT / _CONFIG["validation_dir"]

def get_output_dir() -> Path:
    """Returns the path to the output directory."""
    return _PROJECT_ROOT / _CONFIG["output_dir"]

def get_fallback_path() -> Path:
    """Returns the path to the fallback mock data file."""
    return _PROJECT_ROOT / _CONFIG["fallback_electrolytes_path"]

def is_debug_mode() -> bool:
    """Returns whether debug mode is enabled."""
    return _CONFIG["debug_mode"]

def set_debug_mode(mode: bool) -> None:
    """Sets the debug mode."""
    _CONFIG["debug_mode"] = mode

def get_log_level() -> str:
    """Returns the configured log level."""
    return _CONFIG["log_level"]

def save_config_to_env(config: Optional[Dict[str, Any]] = None) -> None:
    """Saves current config to environment variables (stringified)."""
    if config is None:
        config = _CONFIG
    for key, value in config.items():
        os.environ[f"LLMXIVE_{key.upper()}"] = str(value)

def load_config_from_env() -> None:
    """Loads configuration from environment variables if present."""
    for key in _CONFIG.keys():
        env_key = f"LLMXIVE_{key.upper()}"
        if env_key in os.environ:
            try:
                _CONFIG[key] = json.loads(os.environ[env_key])
            except json.JSONDecodeError:
                _CONFIG[key] = os.environ[env_key]

def get_config_summary() -> Dict[str, Any]:
    """Returns a summary of the current configuration."""
    return {
        "seed": _CONFIG["random_seed"],
        "dataset_url": _CONFIG["dataset_url"],
        "debug": _CONFIG["debug_mode"],
        "log_level": _CONFIG["log_level"]
    }
