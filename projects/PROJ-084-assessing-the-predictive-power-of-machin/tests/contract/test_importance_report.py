# Project root relative to this test file
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
REPORT_PATH = PROJECT_ROOT / "data" / "results" / "feature_importance_report.json"
SCHEMA_PATH = (
    PROJECT_ROOT
    / "specs"
    / "001-assess-ml-predictive-power"
    / "contracts"
    / "importance_report.schema.yaml"
)

def load_schema() -> Dict[str, Any]:
    """Load the importance report schema from YAML."""
    if not SCHEMA_PATH.exists():
        raise FileNotFoundError(
            f"Schema file not found: {SCHEMA_PATH}. "
            "Ensure T008 (output schema contracts) and T029 setup are complete."
        )
    with open(SCHEMA_PATH, "r") as f:
        return yaml.safe_load(f)

def load_report() -> Dict[str, Any]:
    """Load the feature importance report from JSON."""
    if not REPORT_PATH.exists():
        # If the report doesn't exist, the test cannot run.
        # This indicates that the modeling pipeline (T032/T033) hasn't run yet.
        pytest.fail(
            f"Feature importance report not found at {REPORT_PATH}. "
            "Run the modeling pipeline (T032/T033) before running this contract test."
        )
    with open(REPORT_PATH, "r") as f:
        return json.load(f)

def validate_type(value: Any, expected_type: str, field_path: str) -> None:
    """Validate that a value matches the expected type string."""
    type_map = {
        "string": str,
        "integer": int,
        "number": (int, float),
        "boolean": bool,
        "array": list,
        "object": dict,
    }

    expected_python_type = type_map.get(expected_type)
    if expected_python_type is None:
        raise ValueError(f"Unknown type in schema: {expected_type}")

    if not isinstance(value, expected_python_type):
        raise TypeError(
            f"Field '{field_path}' has type {type(value).__name__}, "
            f"expected {expected_type}"
        )

def validate_schema(report: Dict[str, Any], schema: Dict[str, Any]) -> None:
    """Recursively validate the report against the schema."""
    required_fields = schema.get("required", [])
    properties = schema.get("properties", {})

    # Check required fields
    for field in required_fields:
        if field not in report:
            raise KeyError(f"Missing required field in report: '{field}'")

    # Validate each field in the report
    for key, value in report.items():
        if key not in properties:
            # Extra fields are allowed unless the schema explicitly forbids them
            # (not implemented here for flexibility)
            continue

        field_schema = properties[key]
        field_type = field_schema.get("type")

        if field_type:
            validate_type(value, field_type, key)

        # Nested object validation
        if field_type == "object" and "properties" in field_schema:
            if isinstance(value, dict):
                validate_schema(value, field_schema)
            else:
                raise TypeError(
                    f"Field '{key}' is not an object as expected by schema"
                )

        # Array validation
        if field_type == "array" and "items" in field_schema:
            if isinstance(value, list):
                item_schema = field_schema["items"]
                item_type = item_schema.get("type")
                for i, item in enumerate(value):
                    if item_type:
                        validate_type(item, item_type, f"{key}[{i}]")
                    # If item is an object, we could recurse here if needed
                    if item_type == "object" and "properties" in item_schema:
                        if isinstance(item, dict):
                            validate_schema(item, item_schema)
            else:
                raise TypeError(
                    f"Field '{key}' is not an array as expected by schema"
                )

@pytest.fixture
def schema(self) -> Dict[str, Any]:
    """Load the schema once for all tests in this module."""
    return load_schema()

@pytest.fixture
def report(self) -> Dict[str, Any]:
    """Load the report once for all tests in this module."""
    return load_report()

def test_schema_file_exists(self) -> None:
    """Ensure the schema definition file exists."""
    assert SCHEMA_PATH.exists(), f"Schema file missing: {SCHEMA_PATH}"

def test_report_file_exists(self) -> None:
    """Ensure the feature importance report file exists."""
    assert REPORT_PATH.exists(), f"Report file missing: {REPORT_PATH}"

def test_schema_is_valid_yaml(self, schema: Dict[str, Any]) -> None:
    """Ensure the schema file is valid YAML and parseable."""
    assert isinstance(schema, dict), "Schema must be a dictionary"
    assert "properties" in schema, "Schema must define 'properties'"

def test_report_conforms_to_schema(self, report: Dict[str, Any], schema: Dict[str, Any]) -> None:
    """Main contract test: validate the report structure against the schema."""
    try:
        validate_schema(report, schema)
    except (KeyError, TypeError, ValueError) as e:
        pytest.fail(f"Report does not conform to schema: {e}")

def test_top_level_keys_present(self, report: Dict[str, Any]) -> None:
    """Verify that all top-level keys defined in the schema are present."""
    schema = load_schema()
    required = schema.get("required", [])
    missing = [k for k in required if k not in report]
    assert not missing, f"Missing top-level keys: {missing}"

