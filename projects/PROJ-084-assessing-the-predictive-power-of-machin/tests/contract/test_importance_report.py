    assert isinstance(perf["rf_rmse"], (int, float)), "rf_rmse must be a number"
    assert isinstance(perf["svm_r2"], (int, float)), "svm_r2 must be a number"
    assert isinstance(perf["svm_rmse"], (int, float)), "svm_rmse must be a number"

