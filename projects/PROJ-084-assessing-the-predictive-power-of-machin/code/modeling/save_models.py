"""
Save best model artifacts and hyperparameters to data/results/best_models/.

This script loads the best models and their metadata generated by `code/modeling/train.py`,
and persists them to disk in the `data/results/best_models/` directory.

Artifacts produced:
- data/results/best_models/random_forest_model.pkl
- data/results/best_models/random_forest_hyperparameters.json
- data/results/best_models/svm_model.pkl
- data/results/best_models/svm_hyperparameters.json
- data/results/best_models/model_registry.json (summary of all saved models)
"""
import json
import logging
import pickle
import os
from pathlib import Path
from typing import Any, Dict

import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.svm import SVR

# Project imports
import config
from modeling.train import train_random_forest_grid_search, train_svm_grid_search
