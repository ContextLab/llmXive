def get_scaffold_group_keys(df: pd.DataFrame) -> pd.Series:
    """
    Retrieve scaffold group keys from the dataframe.
    Expects 'scaffold_group_id' column to be present (generated by T010).
    """
    if 'scaffold_group_id' not in df.columns:
        raise ValueError("DataFrame must contain 'scaffold_group_id' column for grouping.")
    return df['scaffold_group_id']


def stratified_scaffold_split(
    df: pd.DataFrame,
    group_col: str = 'scaffold_group_id',
    target_col: str = 'yield',
    train_ratio: float = 0.7,
    val_ratio: float = 0.15,
    test_ratio: float = 0.15,
    random_state: int = 42
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Perform a stratified split based on reaction class and scaffold groups.
    
    Strategy:
    1. Group by reaction_class.
    2. Within each class, stratify by scaffold_group_id to ensure scaffold diversity
       is maintained across splits.
    3. Split groups into train/val/test.
    
    Args:
        df: Input dataframe with 'reaction_class' and 'scaffold_group_id'.
        group_col: Column name for scaffold groups.
        target_col: Column name for target variable (yield).
        train_ratio: Proportion of data for training.
        val_ratio: Proportion of data for validation.
        test_ratio: Proportion of data for testing.
        random_state: Random seed for reproducibility.
        
    Returns:
        Tuple of (train_df, val_df, test_df).
    """
    if 'reaction_class' not in df.columns:
        raise ValueError("DataFrame must contain 'reaction_class' column for stratification.")
    
    # Ensure ratios sum to 1.0
    total_ratio = train_ratio + val_ratio + test_ratio
    if abs(total_ratio - 1.0) > 0.001:
        raise ValueError(f"Ratios must sum to 1.0, got {total_ratio}")
    
    # Normalize ratios
    train_ratio /= total_ratio
    val_ratio /= total_ratio
    test_ratio /= total_ratio

    logger.info(f"Performing stratified scaffold split: Train={train_ratio:.2f}, Val={val_ratio:.2f}, Test={test_ratio:.2f}")

    # We need to split groups, not individual rows, to ensure intra-scaffold consistency.
    # However, standard GroupShuffleSplit doesn't support stratification by a secondary label easily.
    # Strategy: Iterate unique reaction classes, split groups within each class.
    
    train_indices = []
    val_indices = []
    test_indices = []

    unique_classes = df['reaction_class'].unique()
    
    for cls in unique_classes:
        cls_df = df[df['reaction_class'] == cls]
        groups = cls_df[group_col].unique()
        
        # Filter out classes with only 1 scaffold (assign all to train)
        if len(groups) == 1:
            indices = cls_df.index.tolist()
            train_indices.extend(indices)
            logger.warning(f"Class '{cls}' has only 1 scaffold. Assigning all to train.")
            continue
        
        # Split groups into train/val/test
        # Use GroupShuffleSplit for the first split (Train vs Rest)
        gss_train = GroupShuffleSplit(n_splits=1, train_size=train_ratio / (train_ratio + val_ratio + test_ratio), random_state=random_state)
        
        # Actually, we need a 3-way split. 
        # Approach: Split Train vs (Val+Test) first, then split (Val+Test) into Val vs Test.
        
        # 1. Train vs Rest
        for train_group_idx, rest_group_idx in gss_train.split(groups, groups):
            train_groups = groups[train_group_idx]
            rest_groups = groups[rest_group_idx]
            
        # 2. Val vs Test from Rest
        # Calculate relative ratio for Val within (Val+Test)
        val_ratio_relative = val_ratio / (val_ratio + test_ratio)
        gss_val = GroupShuffleSplit(n_splits=1, train_size=val_ratio_relative, random_state=random_state)
        
        for val_group_idx, test_group_idx in gss_val.split(rest_groups, rest_groups):
            val_groups = rest_groups[val_group_idx]
            test_groups = rest_groups[test_group_idx]
            
        # Map group IDs back to row indices
        train_indices.extend(cls_df[cls_df[group_col].isin(train_groups)].index.tolist())
        val_indices.extend(cls_df[cls_df[group_col].isin(val_groups)].index.tolist())
        test_indices.extend(cls_df[cls_df[group_col].isin(test_groups)].index.tolist())
    
    # Create dataframes
    train_df = df.loc[train_indices].copy()
    val_df = df.loc[val_indices].copy()
    test_df = df.loc[test_indices].copy()
    
    logger.info(f"Split complete. Train: {len(train_df)}, Val: {len(val_df)}, Test: {len(test_df)}")
    
    return train_df, val_df, test_df


def create_train_val_test_split(
    input_path: str,
    output_dir: str,
    split_ratios: Dict[str, float] = None,
    random_state: int = 42
) -> Dict[str, str]:
    """
    Orchestrates the splitting process and saves indices.
    
    Args:
        input_path: Path to cleaned_reactions.parquet.
        output_dir: Directory to save split outputs.
        split_ratios: Dict with keys 'train', 'val', 'test'.
        random_state: Random seed.
        
    Returns:
        Dict mapping split name to output file path.
    """
    if split_ratios is None:
        split_ratios = {'train': 0.7, 'val': 0.15, 'test': 0.15}
    
    Path(output_dir).mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Loading data from {input_path}")
    df = load_parquet(input_path)
    
    if df.empty:
        raise ValueError("Input dataframe is empty.")
    
    # Perform split
    train_df, val_df, test_df = stratified_scaffold_split(
        df,
        group_col='scaffold_group_id',
        train_ratio=split_ratios['train'],
        val_ratio=split_ratios['val'],
        test_ratio=split_ratios['test'],
        random_state=random_state
    )
    
    # Save split indices (just the indices and class info for reproducibility)
    # We save the full dataframes for convenience in downstream tasks, but the task specifically asks for indices.
    # To be safe and efficient, we save the indices and the split assignment.
    
    split_indices = pd.DataFrame({
        'index': df.index,
        'split': ['train' if i in train_df.index else ('val' if i in val_df.index else 'test') for i in df.index]
    })
    
    output_paths = {}
    
    # Save split indices
    indices_path = Path(output_dir) / 'split_indices.parquet'
    save_parquet(split_indices, str(indices_path))
    output_paths['indices'] = str(indices_path)
    
    # Save individual splits (optional but useful for training scripts)
    # The task specifically asks for validation set extraction, so we ensure that exists.
    train_path = Path(output_dir) / 'train_set.parquet'
    val_path = Path(output_dir) / 'validation_set.parquet'
    test_path = Path(output_dir) / 'test_set.parquet'
    
    save_parquet(train_df, str(train_path))
    save_parquet(val_df, str(val_path))
    save_parquet(test_df, str(test_path))
    
    output_paths['train'] = str(train_path)
    output_paths['val'] = str(val_path)
    output_paths['test'] = str(test_path)
    
    # Log split ratios
    log_path = Path(output_dir) / 'split_log.json'
    log_data = {
        'timestamp': datetime.now().isoformat(),
        'ratios': split_ratios,
        'counts': {
            'train': len(train_df),
            'val': len(val_df),
            'test': len(test_df),
            'total': len(df)
        },
        'files': output_paths
    }
    with open(log_path, 'w') as f:
        json.dump(log_data, f, indent=2)
    
    logger.info(f"Split complete. Logs saved to {log_path}")
    return output_paths


def extract_validation_set(
    split_indices_path: str,
    data_path: str,
    output_path: str
) -> str:
    """
    Extract the held-out validation set from split_indices and source data.
    This is specifically for SC-003 substructure frequency checks.
    
    Args:
        split_indices_path: Path to split_indices.parquet.
        data_path: Path to source data (cleaned_reactions.parquet).
        output_path: Path to save validation_set.parquet.
        
    Returns:
        Path to the created validation set.
    """
    logger.info(f"Loading split indices from {split_indices_path}")
    split_indices = load_parquet(split_indices_path)
    
    if 'split' not in split_indices.columns:
        raise ValueError(f"Split indices file must contain 'split' column. Columns found: {split_indices.columns.tolist()}")
    
    logger.info(f"Loading source data from {data_path}")
    # We assume the source data has the same index as the split_indices
    # If not, we need to join on a unique ID. Assuming index alignment for now based on T022b logic.
    # To be robust, we check if 'index' column exists in split_indices.
    if 'index' in split_indices.columns:
        # Join on index column
        validation_indices = split_indices[split_indices['split'] == 'val']['index'].tolist()
    else:
        # Fallback: assume split_indices is aligned with data_path index
        # This is risky if data was reloaded differently.
        # Better to assume the split_indices file contains the original index.
        # Let's assume the split_indices file has an 'index' column representing the original row index.
        # If not present, we might need to re-read the split logic. 
        # Based on T022b implementation, we created a DataFrame with 'index' and 'split'.
        # So we rely on 'index' column.
        raise ValueError("split_indices.parquet must contain an 'index' column to map back to source data.")

    logger.info(f"Extracting {len(validation_indices)} rows for validation set.")
    
    source_data = load_parquet(data_path)
    
    if len(source_data) != len(split_indices):
        logger.warning(f"Source data length ({len(source_data)}) does not match split indices length ({len(split_indices)}). "
                       "Attempting to join on index values if possible.")
        # If lengths differ, we might have lost the index during save/load.
        # We will try to reset index on source and join.
        source_data = source_data.reset_index(drop=True)
        # Re-index split_indices if it was saved as 0..N-1
        if 'index' in split_indices.columns:
             # We assume the 'index' column in split_indices refers to the 0-based index of the original data
             pass
        else:
            raise ValueError("Index alignment mismatch and no 'index' column found in split_indices.")
    
    validation_set = source_data.loc[validation_indices].reset_index(drop=True)
    
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    save_parquet(validation_set, output_path)
    
    logger.info(f"Validation set saved to {output_path}")
    return output_path


def main():
    """
    Main entry point for the split and validation extraction script.
    """
    # Configuration
    CONFIG = {
        'input_data': 'data/processed/cleaned_reactions.parquet',
        'split_indices_input': 'data/processed/split_indices.parquet',
        'output_dir': 'data/processed',
        'validation_output': 'data/processed/validation_set.parquet',
        'split_ratios': {'train': 0.7, 'val': 0.15, 'test': 0.15},
        'random_state': 42
    }
    
    # Check prerequisites
    if not Path(CONFIG['input_data']).exists():
        logger.error(f"Input data not found: {CONFIG['input_data']}")
        sys.exit(1)
    
    # Step 1: Create splits if split_indices doesn't exist (T022b logic)
    # Note: T022d (logging) is assumed to be part of this or previous step.
    # If T022b is already done, we skip this.
    if not Path(CONFIG['split_indices_input']).exists():
        logger.info("Split indices not found. Running split generation (T022b).")
        create_train_val_test_split(
            input_path=CONFIG['input_data'],
            output_dir=CONFIG['output_dir'],
            split_ratios=CONFIG['split_ratios'],
            random_state=CONFIG['random_state']
        )
    else:
        logger.info(f"Split indices found at {CONFIG['split_indices_input']}. Skipping generation.")
    
    # Step 2: Extract Validation Set (T023)
    logger.info("Extracting validation set for SC-003 checks.")
    try:
        extract_validation_set(
            split_indices_path=CONFIG['split_indices_input'],
            data_path=CONFIG['input_data'],
            output_path=CONFIG['validation_output']
        )
        logger.info("T023 completed successfully.")
    except Exception as e:
        logger.error(f"Failed to extract validation set: {e}")
        sys.exit(1)


if __name__ == '__main__':
    main()