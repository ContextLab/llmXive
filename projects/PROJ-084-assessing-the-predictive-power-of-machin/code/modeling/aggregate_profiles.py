"""
T027b: Aggregate Memory and Runtime Profiles

This script aggregates the individual memory profile logs generated by the
@profile_memory decorator (from code/utils/memory_profiler.py) during the
execution of T024 (Random Forest) and T025 (SVM).

It produces:
1. data/results/memory_profile.log: A consolidated text log of peak RAM usage.
2. data/results/runtime_profile.json: A structured JSON report of peak RAM and runtime.

It validates that total system RAM < 7GB as per SC-004.
"""

import json
import logging
import os
import sys
import glob
from pathlib import Path
from datetime import datetime
from typing import Dict, Any, List, Optional

# Add project root to path for imports if running as script
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from utils.memory_profiler import get_total_system_memory_gb

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler(PROJECT_ROOT / 'data' / 'results' / 'aggregate_profiles.log')
    ]
)
logger = logging.getLogger(__name__)

# Constants
MEMORY_LIMIT_GB = 7.0
RESULTS_DIR = PROJECT_ROOT / 'data' / 'results'
PROFILE_GLOB_PATTERN = str(RESULTS_DIR / 'memory_profile_*.log')
OUTPUT_LOG = RESULTS_DIR / 'memory_profile.log'
OUTPUT_JSON = RESULTS_DIR / 'runtime_profile.json'

def load_individual_profiles(pattern: str) -> List[Dict[str, Any]]:
    """
    Loads all individual memory profile logs matching the pattern.
    Expects JSON content per file (as generated by save_memory_profile_log).
    """
    profiles = []
    files = glob.glob(pattern)
    logger.info(f"Found {len(files)} profile files matching '{pattern}'.")

    if not files:
        logger.warning("No profile files found. Creating empty report.")
        return profiles

    for file_path in sorted(files):
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                content = f.read().strip()
                if not content:
                    logger.warning(f"Skipping empty file: {file_path}")
                    continue
                data = json.loads(content)
                data['source_file'] = os.path.basename(file_path)
                profiles.append(data)
        except json.JSONDecodeError as e:
            logger.error(f"Failed to parse JSON from {file_path}: {e}")
        except Exception as e:
            logger.error(f"Error reading {file_path}: {e}")

    return profiles

def aggregate_profiles(profiles: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Aggregates individual profiles into a single summary structure.
    """
    if not profiles:
        return {
            "status": "no_data",
            "message": "No profile data found to aggregate.",
            "entries": []
        }

    total_peak_mb = 0.0
    max_peak_mb = 0.0
    max_peak_task = ""
    entries = []

    for p in profiles:
        peak_mb = p.get("peak_memory_mb", 0.0)
        task_name = p.get("task_name", "unknown")
        total_peak_mb += peak_mb
        if peak_mb > max_peak_mb:
            max_peak_mb = peak_mb
            max_peak_task = task_name

        entries.append({
            "task": task_name,
            "peak_memory_mb": peak_mb,
            "timestamp": p.get("timestamp", "N/A"),
            "source_file": p.get("source_file", "N/A")
        })

    return {
        "status": "success",
        "generated_at": datetime.now().isoformat(),
        "total_entries": len(entries),
        "summary": {
            "total_peak_memory_mb": round(total_peak_mb, 2),
            "max_peak_memory_mb": round(max_peak_mb, 2),
            "max_peak_task": max_peak_task
        },
        "entries": entries
    }

def validate_memory_limit(agg_report: Dict[str, Any]) -> bool:
    """
    Validates that the maximum observed peak memory is within the 7GB limit.
    """
    system_ram_gb = get_total_system_memory_gb()
    logger.info(f"Detected total system RAM: {system_ram_gb:.2f} GB")

    if system_ram_gb >= MEMORY_LIMIT_GB:
        logger.warning(f"System RAM ({system_ram_gb:.2f} GB) is >= {MEMORY_LIMIT_GB} GB limit. "
                       f"Validation based on observed peak might be misleading if system is over-provisioned.")

    max_peak_mb = agg_report.get("summary", {}).get("max_peak_memory_mb", 0.0)
    max_peak_gb = max_peak_mb / 1024.0

    if max_peak_gb > MEMORY_LIMIT_GB:
        logger.error(f"CRITICAL: Max peak memory ({max_peak_gb:.2f} GB) exceeds limit ({MEMORY_LIMIT_GB} GB).")
        return False
    
    logger.info(f"Validation passed: Max peak memory ({max_peak_gb:.2f} GB) is within limit ({MEMORY_LIMIT_GB} GB).")
    return True

def write_text_log(agg_report: Dict[str, Any], output_path: Path):
    """
    Writes a human-readable text log of the aggregated profiles.
    """
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write("=== Memory Profile Aggregation Report ===\n")
        f.write(f"Generated: {agg_report.get('generated_at', 'N/A')}\n")
        f.write(f"Status: {agg_report.get('status', 'N/A')}\n")
        f.write("-" * 40 + "\n")
        
        if agg_report.get('status') == 'success':
            summary = agg_report.get('summary', {})
            f.write(f"Total Entries: {agg_report.get('total_entries', 0)}\n")
            f.write(f"Total Peak Memory (sum): {summary.get('total_peak_memory_mb', 0):.2f} MB\n")
            f.write(f"Max Peak Memory: {summary.get('max_peak_memory_mb', 0):.2f} MB\n")
            f.write(f"Max Peak Task: {summary.get('max_peak_task', 'N/A')}\n")
            f.write("-" * 40 + "\n")
            f.write("Detailed Entries:\n")
            for entry in agg_report.get('entries', []):
                f.write(f"  Task: {entry['task']}\n")
                f.write(f"    Peak: {entry['peak_memory_mb']:.2f} MB\n")
                f.write(f"    Source: {entry['source_file']}\n")
                f.write(f"    Time: {entry['timestamp']}\n")
                f.write("\n")
        else:
            f.write(f"Message: {agg_report.get('message', 'N/A')}\n")
    
    logger.info(f"Written text log to: {output_path}")

def write_json_report(agg_report: Dict[str, Any], output_path: Path):
    """
    Writes the structured JSON report.
    """
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(agg_report, f, indent=2)
    logger.info(f"Written JSON report to: {output_path}")

def main():
    logger.info("Starting T027b: Aggregate Profiles")
    
    # Ensure results directory exists
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    # Load profiles
    profiles = load_individual_profiles(PROFILE_GLOB_PATTERN)

    # Aggregate
    agg_report = aggregate_profiles(profiles)

    # Validate
    is_valid = validate_memory_limit(agg_report)
    agg_report["validation_passed"] = is_valid

    # Write outputs
    write_text_log(agg_report, OUTPUT_LOG)
    write_json_report(agg_report, OUTPUT_JSON)

    if not is_valid:
        logger.error("Aggregation completed but memory limit validation FAILED.")
        sys.exit(1)
    
    logger.info("T027b completed successfully.")

if __name__ == "__main__":
    main()