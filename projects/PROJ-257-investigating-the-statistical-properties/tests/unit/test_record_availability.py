"""
tests/unit/test_record_availability.py

Verify that the data‑availability JSON report is correctly produced
after the GWTC download step.
"""

import json
from pathlib import Path

import pytest
from llmxive_toolkit import paths

@pytest.fixture(scope="module")
def availability_report():
    # Ensure the download has been performed.
    from src.data.download import download_all
    download_all()
    # Run the availability check.
    from src.data.record_availability import record_availability
    return record_availability()

def test_report_file_exists():
    out_path = paths.results("data_availability.json")
    assert out_path.is_file(), "data_availability.json was not created"

def test_report_structure(availability_report):
    # The report must be a dict mapping filenames to metadata.
    assert isinstance(availability_report, dict)
    for filename, meta in availability_report.items():
        assert "checksum" in meta
        assert "status" in meta
        assert meta["status"] == "verified"

def test_checksums_match():
    # Load the manifest generated by the download step.
    manifest_path = paths.data("raw", "checksums.json")
    with open(manifest_path, "r", encoding="utf-8") as f:
        checksums = json.load(f)

    report_path = paths.results("data_availability.json")
    with open(report_path, "r", encoding="utf-8") as f:
        report = json.load(f)

    for filename, expected_hash in checksums.items():
        assert filename in report, f"{filename} missing from availability report"
        assert report[filename]["checksum"] == expected_hash
        assert report[filename]["status"] == "verified"