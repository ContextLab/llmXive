"""Record data‑availability metadata for downloaded GWTC files (T002).

This script reads the checksum manifest generated by the GWTC download
step (``data/raw/checksums.json``), verifies that each listed file exists
and matches its recorded SHA‑256 hash, and writes a JSON report
``data/results/data_availability.json`` that conforms to the contract
``specs/001-investigating-the-statistical-properties/contracts/result.schema.yaml``.

If the checksum manifest is missing (e.g., because the download
step has not been run yet), the script will invoke the GWTC download
routine to fetch the required files and generate the manifest before
proceeding.
"""

import json
import sys
from pathlib import Path

from llmxive_toolkit import paths, get_logger
from src.utils.checksum import verify_file
from src.data.download import download_all  # Import the GWTC download helper

log = get_logger(__name__)

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------


def _load_checksums(manifest_path: Path) -> dict:
    """Load the checksum manifest produced by ``download_all``.

    If the manifest does not exist, trigger a download of the GWTC
    archives, which will also create ``checksums.json``.

    Parameters
    ----------
    manifest_path:
        Path to ``checksums.json``.

    Returns
    -------
    dict
        Mapping ``filename -> checksum`` (hex string).
    """
    if not manifest_path.is_file():
        log.info(
            "Checksum manifest %s not found – attempting to download GWTC data.",
            manifest_path,
        )
        # ``download_all`` downloads the GWTC archives and writes the
        # ``checksums.json`` file under ``data/raw``.
        download_all()
        if not manifest_path.is_file():
            raise FileNotFoundError(
                f"Checksum manifest still missing after download attempt: {manifest_path}"
            )
    with manifest_path.open("r", encoding="utf-8") as fh:
        return json.load(fh)


def _verify_file(file_path: Path, expected_hash: str) -> bool:
    """Verify that *file_path* exists and matches *expected_hash*.

    Returns ``True`` if the file is present and the hash matches,
    otherwise ``False``.
    """
    if not file_path.is_file():
        log.error("Expected file missing: %s", file_path)
        return False
    try:
        return verify_file(str(file_path), expected_hash)
    except Exception as exc:  # pragma: no cover – defensive
        log.error("Checksum verification failed for %s: %s", file_path, exc)
        return False


# ----------------------------------------------------------------------
# Main orchestration
# ----------------------------------------------------------------------


def record_availability() -> dict:
    """Perform the availability check and write the JSON report.

    Returns
    -------
    dict
        The JSON object written to ``data/results/data_availability.json``.
    """
    # Paths
    manifest_path = paths.data("raw", "checksums.json")
    raw_dir = paths.data("raw")
    out_path = paths.results("data_availability.json")

    log.info("Loading checksum manifest from %s", manifest_path)
    checksums = _load_checksums(manifest_path)

    report = {}
    all_ok = True

    for filename, expected_hash in checksums.items():
        file_path = raw_dir / filename
        ok = _verify_file(file_path, expected_hash)
        status = "verified" if ok else "unavailable"
        report[filename] = {"checksum": expected_hash, "status": status}
        if not ok:
            all_ok = False

    # Write the report
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=2, sort_keys=True)

    if not all_ok:
        raise RuntimeError(
            f"Data‑availability check failed; see {out_path} for details."
        )

    log.info("Data‑availability report written to %s", out_path)
    return report


def main() -> None:
    """CLI entry point used by the test suite."""
    try:
        record_availability()
    except Exception as exc:
        log.error("record_availability failed: %s", exc)
        sys.exit(1)


if __name__ == "__main__":
    main()
