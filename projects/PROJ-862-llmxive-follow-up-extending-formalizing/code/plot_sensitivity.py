"""
Plot sensitivity analysis results and generate the sensitivity report document.
"""
import os
import json
import logging
import matplotlib.pyplot as plt
import seaborn as sns
import pandas as pd
import numpy as np
from typing import Dict, Any, List, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Ensure output directories exist
DOCS_DIR = "docs"
PROCESSED_DIR = "data/processed"
FIGURES_DIR = "figures"

os.makedirs(DOCS_DIR, exist_ok=True)
os.makedirs(FIGURES_DIR, exist_ok=True)

def load_sensitivity_report() -> Dict[str, Any]:
    """Load the sensitivity report JSON generated by T037."""
    path = os.path.join(PROCESSED_DIR, "sensitivity_report.json")
    if not os.path.exists(path):
        raise FileNotFoundError(f"Sensitivity report not found at {path}")
    
    with open(path, 'r') as f:
        return json.load(f)

def plot_trade_off_curves(
    trade_off_data: List[Dict[str, Any]],
    collapse_points: List[Dict[str, Any]],
    output_path: str
) -> None:
    """
    Plot trade-off curves for each task type with validity collapse points marked.
    """
    df = pd.DataFrame(trade_off_data)
    
    if df.empty:
        logger.warning("No trade-off data to plot")
        return

    plt.figure(figsize=(12, 8))
    sns.set_style("whitegrid")
    
    # Plot each task type
    for task_type in df['task_type'].unique():
        task_df = df[df['task_type'] == task_type]
        sns.lineplot(
            data=task_df,
            x='sigma',
            y='validity_pass_rate',
            label=f'{task_type}',
            marker='o'
        )
    
    # Mark collapse points
    if collapse_points:
        collapse_df = pd.DataFrame(collapse_points)
        for idx, row in collapse_df.iterrows():
            plt.axvline(
                x=row['sigma'],
                color='red',
                linestyle='--',
                alpha=0.5,
                label='Collapse Point' if idx == 0 else None
            )
            plt.scatter(
                row['sigma'],
                row['pass_rate'],
                color='red',
                s=100,
                zorder=5,
                edgecolors='black',
                linewidth=1.5
            )
    
    plt.xlabel('Noise Level (Sigma)', fontsize=12)
    plt.ylabel('Semantic Validity Pass Rate', fontsize=12)
    plt.title('Trade-off Curves: Noise vs. Semantic Validity', fontsize=14)
    plt.legend(loc='best')
    plt.ylim(0, 1.05)
    plt.grid(True, alpha=0.3)
    
    plt.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close()
    logger.info(f"Saved trade-off curves plot to {output_path}")

def plot_global_sensitivity(
    global_data: List[Dict[str, Any]],
    output_path: str
) -> None:
    """
    Plot global sensitivity curve across all task types.
    """
    if not global_data:
        logger.warning("No global data to plot")
        return
    
    df = pd.DataFrame(global_data)
    
    plt.figure(figsize=(10, 6))
    sns.set_style("whitegrid")
    
    sns.lineplot(
        data=df,
        x='sigma',
        y='global_validity_pass_rate',
        marker='o',
        linewidth=2,
        color='blue'
    )
    
    plt.xlabel('Noise Level (Sigma)', fontsize=12)
    plt.ylabel('Global Validity Pass Rate', fontsize=12)
    plt.title('Global Sensitivity: Average Validity Across Task Types', fontsize=14)
    plt.ylim(0, 1.05)
    plt.grid(True, alpha=0.3)
    
    plt.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close()
    logger.info(f"Saved global sensitivity plot to {output_path}")

def plot_collapse_distribution(
    collapse_points: List[Dict[str, Any]],
    output_path: str
) -> None:
    """
    Plot the distribution of validity collapse points across task types.
    """
    if not collapse_points:
        logger.warning("No collapse points to plot")
        return
    
    collapse_df = pd.DataFrame(collapse_points)
    sigmas = collapse_df['sigma'].values
    
    plt.figure(figsize=(10, 6))
    sns.set_style("whitegrid")
    
    # Histogram
    plt.hist(
        sigmas,
        bins=10,
        color='steelblue',
        edgecolor='black',
        alpha=0.7,
        density=False
    )
    
    # Mean line
    mean_sigma = np.mean(sigmas)
    plt.axvline(
        x=mean_sigma,
        color='red',
        linestyle='--',
        linewidth=2,
        label=f'Mean: {mean_sigma:.3f}'
    )
    
    plt.xlabel('Validity Collapse Sigma', fontsize=12)
    plt.ylabel('Frequency', fontsize=12)
    plt.title('Distribution of Validity Collapse Points', fontsize=14)
    plt.legend()
    plt.grid(True, alpha=0.3)
    
    plt.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close()
    logger.info(f"Saved collapse distribution plot to {output_path}")

def generate_report_markdown(
    report_data: Dict[str, Any],
    output_path: str
) -> None:
    """
    Generate the sensitivity report markdown document.
    """
    inconclusive = report_data.get('inconclusive', False)
    collapse_stats = report_data.get('collapse_statistics', {})
    trade_off_summary = report_data.get('trade_off_summary', {})
    
    md_content = f"""# Sensitivity Analysis Report

## Executive Summary

This report summarizes the sensitivity analysis of latent separability under input noise injection.
The analysis evaluates the trade-off between perturbation magnitude (noise level $\sigma$) and
semantic validity preservation across multiple task types.

**Status**: {"⚠️ Inconclusive - No Valid Sigma Found" if inconclusive else "✅ Analysis Complete"}

---

## Key Findings

### Validity Collapse Distribution

The validity collapse point is the noise level at which semantic validity drops below 90% for a given task type.

- **Mean Collapse Sigma**: {collapse_stats.get('mean', 'N/A'):.4f}
- **Standard Deviation**: {collapse_stats.get('std', 'N/A'):.4f}
- **Number of Task Types Analyzed**: {collapse_stats.get('n_tasks', 'N/A')}

### Trade-off Summary

{trade_off_summary.get('description', 'No trade-off summary available.')}

"""
    
    if inconclusive:
        md_content += """
### ⚠️ Inconclusive Results

No noise level passed the 90% semantic validity threshold across all task types.
This suggests that even minimal noise injection significantly impacts semantic validity
for the evaluated model and dataset configuration.

"""
    else:
        md_content += """
### Validity Collapse Points by Task Type

| Task Type | Collapse Sigma | Pass Rate at Collapse |
|-----------|----------------|----------------------|
"""
        for point in report_data.get('raw_collapse_points', []):
            md_content += f"| {point['task_type']} | {point['sigma']:.4f} | {point['pass_rate']:.2%} |\n"
    
    md_content += """
---

## Visualizations

### Trade-off Curves

The following plot shows the semantic validity pass rate as a function of noise level
for each task type. Red dashed lines indicate the validity collapse point.

![Trade-off Curves](../figures/sensitivity_trade_offs.png)

### Global Sensitivity Curve

This plot shows the average validity pass rate across all task types at each noise level.

![Global Sensitivity](../figures/global_sensitivity.png)

### Collapse Point Distribution

The histogram shows the distribution of validity collapse points across task types.
The red dashed line indicates the mean collapse sigma.

![Collapse Distribution](../figures/collapse_distribution.png)

---

## Methodology

1. **Data Source**: BigBench Lite reasoning dataset
2. **Model**: Frozen transformer model (Llama/distilled variant)
3. **Validity Metric**: Semantic similarity using `sentence-transformers/all-MiniLM-L6-v2`
4. **Collapse Threshold**: 90% semantic validity pass rate
5. **Statistical Analysis**: Paired t-test / Wilcoxon signed-rank test with Holm-Bonferroni correction

---

## Recommendations

1. **For Robustness Testing**: Use noise levels below the minimum observed collapse sigma.
2. **For Separability Analysis**: Focus on noise levels where validity remains above 90%.
3. **Future Work**: Investigate model architectures or training strategies that improve noise robustness.

---

*Report generated automatically by the llmXive pipeline.*
"""
    
    with open(output_path, 'w') as f:
        f.write(md_content)
    
    logger.info(f"Generated sensitivity report at {output_path}")

def main():
    """
    Main entry point: load sensitivity report, generate plots, create markdown report.
    """
    logger.info("Starting sensitivity report generation...")
    
    try:
        # Load data
        report_data = load_sensitivity_report()
        logger.info("Loaded sensitivity report data")
        
        # Extract data for plotting
        trade_off_data = report_data.get('trade_off_curve', [])
        global_data = report_data.get('global_trade_off_curve', [])
        collapse_points = report_data.get('raw_collapse_points', [])
        
        # Generate plots
        trade_off_path = os.path.join(FIGURES_DIR, "sensitivity_trade_offs.png")
        plot_trade_off_curves(trade_off_data, collapse_points, trade_off_path)
        
        global_path = os.path.join(FIGURES_DIR, "global_sensitivity.png")
        plot_global_sensitivity(global_data, global_path)
        
        collapse_path = os.path.join(FIGURES_DIR, "collapse_distribution.png")
        plot_collapse_distribution(collapse_points, collapse_path)
        
        # Generate markdown report
        report_path = os.path.join(DOCS_DIR, "sensitivity_report.md")
        generate_report_markdown(report_data, report_path)
        
        logger.info("Sensitivity report generation completed successfully")
        
    except FileNotFoundError as e:
        logger.error(f"Data file not found: {e}")
        raise
    except Exception as e:
        logger.error(f"Error generating report: {e}")
        raise

if __name__ == "__main__":
    main()