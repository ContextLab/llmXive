"""
Module T030: Save perturbed vectors and metadata to data/processed/perturbed_vectors.csv.

This script is invoked by the main pipeline (or run independently) to persist the
perturbed latent vectors generated during the noise injection sweep. It reads the
perturbation results (typically generated during the T029 sweep loop), validates them,
encodes them as base64, and writes them to the specified CSV output.

Output:
    data/processed/perturbed_vectors.csv
"""
