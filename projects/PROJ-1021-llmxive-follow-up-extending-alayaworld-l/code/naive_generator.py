def load_verification_status() -> Dict[str, Any]:
    """
    Reads the model verification status generated by T011a.
    Returns the JSON content or raises FileNotFoundError if missing.
    """
    if not VERIFICATION_FILE.exists():
        raise FileNotFoundError(
            f"Verification file not found: {VERIFICATION_FILE}. "
            "Please run T011a (model_verifier.py) first."
        )
    
    with open(VERIFICATION_FILE, 'r', encoding='utf-8') as f:
        return json.load(f)


def load_ground_truth_subset() -> Optional[Dict[str, Any]]:
    """
    Loads the ground truth subset for reference/validation context.
    Returns None if file is missing (though T008a should have created it).
    """
    if not GT_FILE.exists():
        return None
    
    with open(GT_FILE, 'r', encoding='utf-8') as f:
        return json.load(f)


def generate_synthetic_frames(num_frames: int = 30, width: int = 640, height: int = 480) -> List[np.ndarray]:
    """
    Generates a sequence of synthetic frames (random noise + moving shapes)
    to validate pipeline logic when the model is unavailable.
    
    Args:
        num_frames: Number of frames to generate.
        width: Frame width.
        height: Frame height.
        
    Returns:
        List of numpy arrays representing frames.
    """
    frames = []
    for i in range(num_frames):
        # Create a base frame with random noise
        frame = np.random.randint(0, 256, (height, width, 3), dtype=np.uint8)
        
        # Add a moving "object" (a simple rectangle) to simulate motion
        # This allows the CV pipeline (T013) to have something to detect
        x = int((i / num_frames) * (width - 100))
        y = height // 2
        cv2.rectangle(frame, (x, y), (x + 50, y + 50), (255, 0, 0), -1)
        
        frames.append(frame)
    return frames


def save_synthetic_frames_to_video(frames: List[np.ndarray], output_path: Path) -> None:
    """
    Saves a list of synthetic frames to a video file using OpenCV.
    """
    if cv2 is None:
        raise RuntimeError("OpenCV (cv2) is required to save synthetic video but is not installed.")
    
    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    out = cv2.VideoWriter(str(output_path), fourcc, 10.0, (frames[0].shape[1], frames[0].shape[0]))
    
    for frame in frames:
        out.write(frame)
    
    out.release()


def generate_methodological_validation_report() -> Dict[str, Any]:
    """
    Generates the Methodological Validation Report when the model is missing.
    This report confirms that the pipeline logic (generation -> storage) works,
    even without the heavy AI model.
    """
    print("Model status: MISSING. Generating Methodological Validation Report...")
    
    # 1. Generate synthetic frames
    frames = generate_synthetic_frames(num_frames=30)
    
    # 2. Save to a temporary video file
    video_path = DATA_DIR / "videos" / "methodological_validation.mp4"
    save_synthetic_frames_to_video(frames, video_path)
    
    # 3. Construct the report
    report = {
        "status": "DATA_UNAVAILABLE",
        "reason": "Model verification failed (T011a). Generated synthetic data for pipeline validation.",
        "pipeline_test": {
            "frames_generated": len(frames),
            "video_saved": str(video_path),
            "video_exists": video_path.exists(),
            "video_size_bytes": video_path.stat().st_size if video_path.exists() else 0
        },
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "note": "This is a placeholder run. Real video generation requires the AlayaWorld model."
    }
    
    # 4. Write report to disk
    report_path = RESULTS_DIR / "methodological_validation_report.json"
    with open(report_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)
    
    print(f"Methodological validation report written to: {report_path}")
    return report


