def load_analysis_results() -> Optional[Dict[str, Any]]:
    """
    Loads the statistical analysis results from the processed data directory.
    Expects a file like data/processed/analysis_results.json generated by T024/T029.
    """
    config = get_config()
    results_path = config['paths']['processed'] / 'analysis_results.json'
    
    if not results_path.exists():
        logger.error(f"Analysis results file not found: {results_path}")
        return None
    
    try:
        with open(results_path, 'r') as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse analysis results: {e}")
        return None

def load_visualization_paths() -> Dict[str, str]:
    """
    Constructs or loads the paths to the visualization files generated by T031.
    """
    config = get_config()
    figures_dir = config['paths']['figures']
    
    # Define expected filenames based on T031 implementation
    paths = {
        'box_plot': str(figures_dir / 'review_time_boxplot.png'),
        'cdf_plot': str(figures_dir / 'review_time_cdf.png'),
        'sensitivity_plot': str(figures_dir / 'sensitivity_analysis.png')
    }
    
    # Verify existence and log warnings if missing
    for key, path in paths.items():
        if not os.path.exists(path):
            logger.warning(f"Visualization file missing for report: {path}")
    
    return paths

