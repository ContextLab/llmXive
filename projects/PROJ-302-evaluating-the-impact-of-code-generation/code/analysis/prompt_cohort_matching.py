    def calculate_smd(treated: pd.Series, control: pd.Series) -> float:
        """Calculate Standardized Mean Difference."""
        mean_t = treated.mean()
        mean_c = control.mean()
        std_t = treated.std()
        std_c = control.std()
        pooled_std = np.sqrt((std_t**2 + std_c**2) / 2)
        if pooled_std == 0:
            return 0.0
        return (mean_t - mean_c) / pooled_std

    def estimate_propensity_scores(df: pd.DataFrame, covariates: List[str], treatment_col: str) -> pd.Series:
        """Estimate propensity scores using logistic regression."""
        X = df[covariates].fillna(0)
        y = df[treatment_col].astype(int)
        model = LogisticRegression()
        model.fit(X, y)
        return pd.Series(model.predict_proba(X)[:, 1], index=df.index)

    def perform_matching(df: pd.DataFrame, propensity_col: str, treatment_col: str, ratio: int = 1) -> pd.DataFrame:
        """Perform 1:1 or 1:k nearest neighbor matching."""
        treated = df[df[treatment_col] == 1].sort_values(by=propensity_col)
        control = df[df[treatment_col] == 0].sort_values(by=propensity_col)
        
        matched_indices = []
        control_used = set()
        
        for _, t_row in treated.iterrows():
            t_prop = t_row[propensity_col]
            # Find closest control not yet used (for 1:1) or available (for 1:k)
            candidates = control[~control.index.isin(control_used)]
            if candidates.empty:
                continue
            
            diffs = (candidates[propensity_col] - t_prop).abs()
            best_match_idx = diffs.idxmin()
            matched_indices.append((t_row.name, best_match_idx))
            
            if ratio == 1:
                control_used.add(best_match_idx)
        
        matched_df = pd.DataFrame(matched_indices, columns=['treated_idx', 'control_idx'])
        return matched_df

    def check_balance(df: pd.DataFrame, matched_indices: pd.DataFrame, covariates: List[str], treatment_col: str) -> Dict[str, float]:
        """Check balance of covariates after matching."""
        smd_results = {}
        for col in covariates:
            treated_vals = df.loc[matched_indices['treated_idx'], col]
            control_vals = df.loc[matched_indices['control_idx'], col]
            smd_results[col] = calculate_smd(treated_vals, control_vals)
        return smd_results

