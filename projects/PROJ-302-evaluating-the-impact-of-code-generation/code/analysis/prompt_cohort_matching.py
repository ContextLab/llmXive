def load_prompt_cohort_data(input_path: Optional[str] = None) -> pd.DataFrame:
    """
    Load the cohort segments generated by T033a.
    Expects a parquet file with columns: snippet_id, author_type, file_size, complexity_score, review_duration, ...
    """
    if input_path is None:
        input_path = str(CONFIG['paths']['data_processed'] / 'cohort_segments.parquet')
    
    path = Path(input_path)
    if not path.exists():
        logger.error(f"Cohort segments file not found: {path}")
        raise FileNotFoundError(f"Cohort segments file not found: {path}")
    
    logger.info(f"Loading cohort data from {path}")
    df = pd.read_parquet(path)
    
    required_cols = ['snippet_id', 'author_type', 'file_size', 'complexity_score', 'review_duration']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Cohort data missing required columns: {missing}")
    
    return df

def prepare_cohort_for_matching(df: pd.DataFrame) -> Tuple[pd.DataFrame, List[str]]:
    """
    Prepare the dataframe for matching.
    1. Encode author_type: 'llm-like' -> 1, 'human' -> 0.
    2. Define covariates (EXCLUDING semantic similarity per Plan/US2 logic).
    3. Handle missing values.
    """
    logger.info("Preparing cohort for matching...")
    
    # Encode treatment variable
    df = df.copy()
    df['treatment'] = (df['author_type'] == 'llm-like').astype(int)
    
    # Define covariates based on US2 matching logic (file_size, complexity, activity)
    # We use review_duration as a proxy for activity if available, otherwise just size/complexity
    covariates = []
    if 'file_size' in df.columns:
        covariates.append('file_size')
    if 'complexity_score' in df.columns:
        covariates.append('complexity_score')
    if 'review_duration' in df.columns:
        covariates.append('review_duration')
    
    if not covariates:
        raise ValueError("No covariates found for matching.")
    
    # Fill missing values with median
    for col in covariates:
        median_val = df[col].median()
        if pd.isna(median_val):
            median_val = 0.0
        df[col] = df[col].fillna(median_val)
    
    logger.info(f"Using covariates for matching: {covariates}")
    return df, covariates

def run_prompt_cohort_matching(df: pd.DataFrame, covariates: List[str], max_smd: float = 0.1, max_retries: int = 3) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """
    Run propensity score matching for the prompt-based cohort.
    
    Logic:
    1. Estimate propensity scores.
    2. Perform matching.
    3. Check balance (SMD).
    4. If SMD > threshold, retry with interaction terms (up to max_retries).
    5. If still failing, generate failure report and halt.
    """
    logger.info("Starting prompt cohort matching...")
    
    # Step 1: Estimate Propensity Scores
    propensity_scores = estimate_propensity_scores(df, covariates, 'treatment')
    df['propensity_score'] = propensity_scores
    
    # Step 2: Perform Matching
    matched_indices = perform_matching(df, 'propensity_score', 'treatment', ratio=1)
    
    if matched_indices.empty:
        logger.warning("Matching produced no pairs.")
        return matched_indices, {'status': 'no_matches'}
    
    # Step 3: Check Balance
    smd_results = check_balance(df, matched_indices, covariates, 'treatment')
    max_smd_val = max(abs(v) for v in smd_results.values())
    
    logger.info(f"Initial SMD values: {smd_results}, Max SMD: {max_smd_val}")
    
    retry_count = 0
    final_smd_results = smd_results
    
    # Step 4: Retry Logic if SMD > threshold
    while max_smd_val > max_smd and retry_count < max_retries:
        retry_count += 1
        logger.info(f"SMD ({max_smd_val:.4f}) > {max_smd}. Retry {retry_count}/{max_retries}. Adding interaction terms.")
        
        # Add interaction terms to covariates
        # Retry 1: file_size * complexity
        # Retry 2: complexity * review_duration (if exists)
        # Retry 3: file_size * review_duration (if exists)
        
        new_covariates = covariates.copy()
        if retry_count == 1 and 'file_size' in covariates and 'complexity_score' in covariates:
            new_covariates.append('file_size_complexity')
            df['file_size_complexity'] = df['file_size'] * df['complexity_score']
        elif retry_count == 2 and 'complexity_score' in covariates and 'review_duration' in covariates:
            new_covariates.append('complexity_review')
            df['complexity_review'] = df['complexity_score'] * df['review_duration']
        elif retry_count == 3 and 'file_size' in covariates and 'review_duration' in covariates:
            new_covariates.append('size_review')
            df['size_review'] = df['file_size'] * df['review_duration']
        else:
            # No more interaction terms to add
            logger.warning("No more interaction terms available for retry.")
            break
        
        # Re-estimate and re-match
        propensity_scores = estimate_propensity_scores(df, new_covariates, 'treatment')
        df['propensity_score'] = propensity_scores
        matched_indices = perform_matching(df, 'propensity_score', 'treatment', ratio=1)
        
        if matched_indices.empty:
            logger.warning("Retry matching produced no pairs.")
            break
            
        final_smd_results = check_balance(df, matched_indices, new_covariates, 'treatment')
        max_smd_val = max(abs(v) for v in final_smd_results.values())
        logger.info(f"Retry {retry_count} SMD: {max_smd_val:.4f}")
    
    status = 'success' if max_smd_val <= max_smd else 'failed'
    
    return matched_indices, {
        'status': status,
        'max_smd': max_smd_val,
        'covariates_used': covariates if status == 'success' else new_covariates if 'new_covariates' in locals() else covariates,
        'retry_count': retry_count,
        'smd_details': final_smd_results
    }

def generate_matching_failure_report(results: Dict[str, Any], output_path: Path) -> None:
    """
    Generate a JSON report if matching fails (SMD > 0.1 after retries).
    """
    report = {
        'status': 'matching_failed',
        'reason': 'SMD threshold exceeded after maximum retries',
        'max_smd': results.get('max_smd'),
        'retry_count': results.get('retry_count'),
        'smd_details': results.get('smd_details', {}),
        'timestamp': str(pd.Timestamp.now())
    }
    
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)
    logger.info(f"Generated matching failure report: {output_path}")

def main():
    """
    Main entry point for T034: LLM-Like Cohort Matching.
    """
    logger.info("Starting T034: LLM-Like Cohort Matching")
    
    # Ensure directories exist
    ensure_directories()
    
    try:
        # 1. Load Data
        df = load_prompt_cohort_data()
        
        # 2. Prepare Data
        df, covariates = prepare_cohort_for_matching(df)
        
        # 3. Run Matching
        matched_indices, results = run_prompt_cohort_matching(df, covariates)
        
        # 4. Handle Results
        if results['status'] == 'failed':
            failure_report_path = CONFIG['paths']['data_processed'] / 'matching_failure_report.json'
            generate_matching_failure_report(results, failure_report_path)
            logger.error("Matching failed. Halting pipeline.")
            sys.exit(1)
        
        # 5. Save Matched Indices
        output_path = CONFIG['paths']['data_processed'] / 'prompt_cohort_matched.parquet'
        # Create a dataframe from the indices for saving
        matched_df = matched_indices.copy()
        matched_df.to_parquet(output_path)
        logger.info(f"Successfully saved matched pairs to {output_path}")
        
        # 6. Save Matching Summary
        summary_path = CONFIG['paths']['data_processed'] / 'prompt_cohort_matching_summary.json'
        with open(summary_path, 'w') as f:
            json.dump(results, f, indent=2)
        logger.info(f"Saved matching summary to {summary_path}")
        
        logger.info("T034 completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(f"Data file not found: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during matching: {e}", exc_info=True)
        sys.exit(1)

