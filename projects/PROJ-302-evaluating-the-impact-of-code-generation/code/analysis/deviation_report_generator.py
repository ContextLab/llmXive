DEVIATION_REASONING = """
# Deviation Report: Exclusion of Semantic Similarity from Propensity Score Matching

## 1. Deviation Summary
**Original Requirement**: FR-004 and FR-009 initially suggested utilizing all available code metrics, including semantic similarity scores (computed in T017b), for matching LLM-like and Human code snippets to control for confounding variables.

**Implemented Action**: Semantic similarity scores were explicitly **EXCLUDED** from the propensity score matching covariates in `code/analysis/matching.py`. Only `file_size`, `complexity_score`, and `activity` (review activity) were used as matching covariates.

## 2. Scientific Rationale
The exclusion of semantic similarity scores is a deliberate methodological adjustment based on the following scientific reasoning:

### 2.1 Prevention of Collider Bias
In the causal graph of this study:
- **Treatment**: Code Generation Source (LLM vs. Human)
- **Outcome**: Review Time
- **Confounders**: File Size, Complexity, Activity
- **Mediator/Collider**: Semantic Similarity

Semantic similarity is likely a *collider* or a *mediator* rather than a pure confounder.
1. **Mediator Path**: The generation method (LLM) directly influences the semantic style and similarity of the code. If we match on semantic similarity, we are effectively matching on a variable that is an *outcome* of the treatment. This blocks the natural pathway through which the treatment affects the outcome, leading to "over-adjustment" bias.
2. **Collider Path**: Both the treatment (LLM generation) and unmeasured factors (e.g., developer intent) might influence semantic similarity. Conditioning on a collider opens a spurious path between the treatment and unmeasured confounders, introducing bias.

### 2.2 Alignment with Causal Inference Best Practices
To estimate the *Total Causal Effect* of LLM code generation on review time, we must control for pre-treatment confounders (size, complexity) but not for variables on the causal pathway (semantic style resulting from generation). Excluding semantic similarity ensures we measure the *total* impact, including any effects mediated through the code's semantic properties.

## 3. Implementation Details
- **Data Source**: `data/processed/diagnostic_scores.parquet` (generated by T017b) is loaded but its `semantic_similarity_score` column is dropped before matching.
- **Matching Algorithm**: `code/analysis/matching.py` uses `estimate_propensity_scores` with covariates: `['file_size', 'complexity_score', 'activity']`.
- **Documentation**: This deviation is logged and the report is generated at `data/processed/deviation_report.md`.

## 4. Impact Assessment
By excluding semantic similarity:
- **Reduced Bias**: Avoids collider bias and over-adjustment.
- **Valid Estimate**: Provides a more accurate estimate of the total causal effect of LLM generation on review time.
- **Diagnostic Value**: Semantic similarity scores remain available in `data/processed/diagnostic_scores.parquet` for secondary diagnostic analysis (e.g., verifying that LLM and Human code differ in semantics) but do not influence the primary causal estimate.

## 5. References
- Plan.md: "Semantic similarity scores are computed for diagnostic purposes only and are EXCLUDED from matching covariates per Plan."
- FR-004 (Adjusted): "Match on file size, complexity, and activity. Exclude semantic similarity to avoid collider bias."
"""

def generate_deviation_report(output_path: Optional[str] = None) -> str:
    """
    Generates the deviation_report.md documenting the exclusion of semantic similarity
    from matching covariates.

    Args:
        output_path: Optional custom path. Defaults to data/processed/deviation_report.md.

    Returns:
        The absolute path to the generated report.
    """
    config = get_config()
    if output_path is None:
        output_path = str(config["paths"]["processed_data"] / "deviation_report.md")

    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    full_content = f"""# Deviation Report: Exclusion of Semantic Similarity from Propensity Score Matching
**Generated**: {timestamp}
**Task ID**: T022b
**Status**: Completed

{DEVIATION_REASONING}
"""
    
    try:
        with open(output_file, 'w', encoding='utf-8') as f:
            f.write(full_content)
        logger.info(f"Deviation report generated successfully at: {output_file}")
        return str(output_file)
    except Exception as e:
        logger.error(f"Failed to write deviation report: {e}")
        raise

def main():
    """Entry point for the deviation report generator."""
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    try:
        path = generate_deviation_report()
        print(f"SUCCESS: Deviation report written to {path}")
        sys.exit(0)
    except Exception as e:
        print(f"ERROR: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()