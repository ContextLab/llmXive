def sigmoid(x: float) -> float:
    """Compute the sigmoid function."""
    if x >= 0:
        return 1 / (1 + math.exp(-x))
    else:
        exp_x = math.exp(x)
        return exp_x / (1 + exp_x)

def heuristic_solver_success(density: float, alpha: float, threshold: float) -> bool:
    """
    Determine success probabilistically using the logistic function:
    P(retrieval) = sigmoid(alpha * (density - threshold))
    """
    prob = sigmoid(alpha * (density - threshold))
    return random.random() < prob

def check_evidence_visibility(critical_turn: int, current_turn: int, retention_horizon: int) -> bool:
    """
    Check if the critical evidence is within the retention horizon.
    Logic: 1 if (critical_evidence_turn_index >= current_turn - retention_horizon + 1)
    Handles edge case where critical evidence is at the very last turn.
    """
    # The evidence is visible if it occurred within the last `retention_horizon` turns
    # inclusive of the current turn.
    # Window: [current_turn - retention_horizon + 1, current_turn]
    lower_bound = current_turn - retention_horizon + 1
    return critical_turn >= lower_bound

def load_trajectories_streaming(input_path: Path, batch_size: int = 50):
    """
    Generator to load trajectories in batches to manage RAM.
    Yields lists of trajectory dictionaries.
    """
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    with open(input_path, 'r', encoding='utf-8') as f:
        # Assuming JSONL format for streaming efficiency, or a list of dicts
        # If it's a single large JSON list, we need to parse it carefully.
        # Given the task T011 output is JSON, it might be a list.
        # To stream a large JSON list without loading all into memory, we can use ijson or manual parsing.
        # However, standard json.load loads the whole file. 
        # If the file is JSONL (one JSON object per line), we can stream line by line.
        # Let's assume JSONL for true streaming, or if it's a list, we process chunks.
        # For robustness, let's try to read line by line first.
        
        buffer = []
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                traj = json.loads(line)
                buffer.append(traj)
                if len(buffer) >= batch_size:
                    yield buffer
                    buffer = []
            except json.JSONDecodeError:
                # If it's not JSONL, it might be a single JSON array.
                # We fallback to reading the whole file if JSONL fails? 
                # No, that defeats streaming. 
                # Let's assume the generator produces JSONL as per best practices for T015.
                # If the file is a single JSON array, we must handle it differently.
                # For this implementation, we assume JSONL or handle the array case by reading chunks.
                # If it's a standard JSON array, we can't stream easily without a library.
                # Let's assume the input is JSONL for the streaming requirement.
                raise ValueError(f"Invalid JSON line in streaming input: {line[:50]}...")

        if buffer:
            yield buffer

def run_simulation_batch(batch: List[Dict[str, Any]], alpha: float, threshold: float, max_horizon: int) -> List[Dict[str, Any]]:
    """
    Run simulation for a batch of trajectories across all horizons.
    """
    results = []
    for traj in batch:
        traj_id = traj.get('id', 'unknown')
        density = traj.get('density', 0.0)
        critical_turn = traj.get('critical_evidence_turn_index', -1)
        total_turns = traj.get('total_turns', 0)
        
        if critical_turn == -1 or total_turns == 0:
            continue

        # Simulate for each horizon from 1 to max_horizon (or total_turns)
        effective_max = min(max_horizon, total_turns)
        for horizon in range(1, effective_max + 1):
            success_count = 0
            total_attempts = 0
            
            # We simulate the agent's performance over the trajectory turns
            # For simplicity, we check visibility at the critical turn and apply heuristic
            # The success logic: 1 if (visible AND heuristic_success)
            
            # Check visibility at the critical turn
            is_visible = check_evidence_visibility(critical_turn, critical_turn, horizon)
            
            if is_visible:
                # If visible, check if the heuristic solver succeeds
                if heuristic_solver_success(density, alpha, threshold):
                    success_count = 1
                else:
                    success_count = 0
            else:
                success_count = 0

            results.append({
                "trajectory_id": traj_id,
                "horizon": horizon,
                "density": density,
                "success": success_count,
                "critical_turn": critical_turn,
                "is_visible": is_visible
            })
    
    return results

def write_batch_to_file(batch_results: List[Dict[str, Any]], output_path: Path):
    """
    Write a batch of results to the output file in JSONL format.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'a', encoding='utf-8') as f:
        for item in batch_results:
            f.write(json.dumps(item) + '\n')

def get_memory_usage_gb() -> float:
    """
    Get current memory usage in GB.
    Returns 0.0 if psutil is not available.
    """
    if not HAS_PSUTIL:
        return 0.0
    process = psutil.Process(os.pid)
    mem_info = process.memory_info()
    return mem_info.rss / (1024 ** 3)

