    parser = argparse.ArgumentParser(description="Simulate agent with variable retention horizons.")
    parser.add_argument("--input", type=str, required=True, help="Path to input trajectories file (JSONL)")
    parser.add_argument("--output", type=str, required=True, help="Path to output results file (JSONL)")
    parser.add_argument("--alpha", type=float, default=1.0, help="Scaling factor for logistic function")
    parser.add_argument("--threshold", type=float, default=0.5, help="Critical density threshold")
    parser.add_argument("--max-horizon", type=int, default=20, help="Maximum retention horizon to test")
    parser.add_argument("--batch-size", type=int, default=50, help="Number of trajectories per batch")
    
    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)

    # Clear output file if it exists to avoid appending to old runs
    if output_path.exists():
        output_path.unlink()

    print(f"Starting simulation with alpha={args.alpha}, threshold={args.threshold}")
    
    batch_count = 0
    total_results = 0

    try:
        for batch in load_trajectories_streaming(input_path, args.batch_size):
            batch_results = run_simulation_batch(batch, args.alpha, args.threshold, args.max_horizon)
            write_batch_to_file(batch_results, output_path)
            total_results += len(batch_results)
            batch_count += 1
            
            if HAS_PSUTIL:
                mem_gb = get_memory_usage_gb()
                print(f"Batch {batch_count} processed. Total results: {total_results}. Memory: {mem_gb:.2f} GB")
            else:
                print(f"Batch {batch_count} processed. Total results: {total_results}.")
                
        print(f"Simulation complete. Wrote {total_results} results to {output_path}")
    except FileNotFoundError as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f"Error during simulation: {e}", file=sys.stderr)
        sys.exit(1)

