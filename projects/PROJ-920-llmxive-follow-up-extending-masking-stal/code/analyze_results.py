import argparse
import json
import sys
import os
from pathlib import Path
from typing import Any, Dict, List, Optional
import time

import numpy as np
import pandas as pd
import statsmodels.api as sm
from patsy import dmatrix

def load_simulation_data(filepath: Path) -> pd.DataFrame:
    """
    Load simulation results from a JSON-lines file into a DataFrame.
    Optimized for speed using pandas read_json with lines=True.
    """
    if not filepath.exists():
        raise FileNotFoundError(f"Simulation results not found: {filepath}")
    
    # Use lines=True for JSONL format to stream load efficiently
    df = pd.read_json(filepath, lines=True)
    return df

def validate_sample_size(df: pd.DataFrame, min_size: int = 30) -> bool:
    """
    Validate that the sample size is sufficient for statistical power.
    """
    n = len(df)
    if n < min_size:
        print(f"WARNING: Sample size {n} is below minimum {min_size}. Results may be unreliable.")
        return False
    return True

def build_formula_with_splines(df: pd.DataFrame, df_splines: int = 3) -> str:
    """
    Build the regression formula with natural splines for 'horizon'.
    Uses patsy to generate the spline basis.
    """
    # We construct the formula string. The splines will be generated by patsy.
    # Formula: success ~ density * ns(horizon, df)
    # Note: patsy's 'ns' (natural spline) requires the 'splines' package or similar,
    # but statsmodels/patsy often uses 'bs' (B-splines) or we can use 'ns' if available.
    # Standard patsy uses 'bs' for B-splines which can approximate natural splines with constraints,
    # or we can use 'cr' (cubic regression).
    # To be safe and standard with statsmodels, we use 'bs' with constraints or just 'ns' if installed.
    # However, patsy doesn't have 'ns' by default. It has 'bs'.
    # Let's use 'bs' (B-splines) which is standard in patsy.
    # If strict natural splines are required, we might need to install 'splines' or use a custom function.
    # For this task, we use 'bs' as it's the standard patsy spline term.
    # Alternatively, we can use 'cr' (Cubic Regression Splines) from the 'splines' package if available.
    # Given the requirement for "natural splines", and patsy's limitations, we will use 'bs' 
    # and note that it's a spline basis.
    # Actually, patsy supports 'ns' if the 'splines' module is installed? No, patsy has 'bs'.
    # Let's use 'bs' (B-splines) which is robust.
    formula = f"success ~ density * bs(horizon, df={df_splines})"
    return formula

def run_logistic_regression(df: pd.DataFrame, formula: str) -> Any:
    """
    Run logistic regression with the given formula.
    """
    # Ensure binary outcome
    y = df['success']
    # Build design matrix
    try:
        # patsy handles the formula parsing
        X = dmatrix(formula, data=df, return_type='dataframe')
    except Exception as e:
        # Fallback if 'bs' is not recognized or formula error
        # Try a simpler interaction if splines fail
        print(f"Error building design matrix: {e}. Falling back to linear interaction.")
        formula = "success ~ density * horizon"
        X = dmatrix(formula, data=df, return_type='dataframe')

    # Add intercept if not present (dmatrix usually adds it)
    # Run logistic regression
    model = sm.Logit(y, X)
    result = model.fit(disp=False) # disp=False suppresses convergence output
    return result

def write_summary(result: sm.LogitResults, output_path: Path):
    """
    Write regression coefficients and p-values to JSON.
    """
    summary_dict = {
        'coefficients': result.params.to_dict(),
        'pvalues': result.pvalues.to_dict(),
        'log_likelihood': result.llf,
        'nobs': result.nobs,
        'converged': result.converged
    }
    
    # Check interaction term significance
    # The interaction term name depends on the formula.
    # If using bs, it might be 'density:bs(horizon, df=3)[T.1]', etc.
    # We look for any term containing 'density' and 'horizon' or the interaction.
    interaction_p = None
    for term, pval in result.pvalues.items():
        if 'density' in term and ('horizon' in term or 'bs' in term):
            interaction_p = pval
            break
    
    # If specific interaction term not found, assume the first interaction-like term
    if interaction_p is None:
        # Fallback: check if any term with 'density' and 'horizon' exists in pvalues
        # This is a heuristic.
        pass

    summary_dict['interaction_p_value'] = interaction_p
    summary_dict['hypothesis_supported'] = interaction_p is not None and interaction_p < 0.05

    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(summary_dict, f, indent=2)

def write_hypothesis_summary(summary_path: Path, summary_dict: Dict[str, Any]):
    """
    Write a markdown summary of the hypothesis test.
    """
    hypothesis_supported = summary_dict.get('hypothesis_supported', False)
    interaction_p = summary_dict.get('interaction_p_value', 'N/A')
    
    content = f"""# Hypothesis Summary

**Hypothesis**: Masking stale observations helps search agents up to a certain horizon, after which performance degrades (interaction effect).

**Interaction Term P-Value**: {interaction_p}

**Hypothesis Supported**: {hypothesis_supported}

**Conclusion**:
{'The interaction between semantic density and retention horizon is statistically significant (p < 0.05), supporting the hypothesis that masking staleness has a non-linear effect dependent on horizon.' if hypothesis_supported else 'The interaction term is not statistically significant (p >= 0.05). The hypothesis that masking staleness has a non-linear effect dependent on horizon is not supported by this data.'}
"""
    with open(summary_path, 'w', encoding='utf-8') as f:
        f.write(content)

def main():
    parser = argparse.ArgumentParser(description="Analyze simulation results with logistic regression")
    parser.add_argument('--input', type=str, default='data/processed/simulation_results.csv', help='Input simulation results file (JSONL)')
    parser.add_argument('--output-dir', type=str, default='output', help='Output directory for results')
    parser.add_argument('--splines-df', type=int, default=3, help='Degrees of freedom for splines')
    args = parser.parse_args()

    input_path = Path(args.input)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    summary_json_path = output_dir / 'regression_summary.json'
    summary_md_path = output_dir / 'hypothesis_summary.md'

    print(f"Loading data from {input_path}...")
    start_time = time.time()
    
    try:
        df = load_simulation_data(input_path)
    except Exception as e:
        print(f"Error loading data: {e}", file=sys.stderr)
        sys.exit(1)

    if not validate_sample_size(df):
        # Continue but warn
        pass

    print(f"Building formula with splines (df={args.splines_df})...")
    formula = build_formula_with_splines(df, args.splines_df)
    
    print("Running logistic regression...")
    result = run_logistic_regression(df, formula)
    
    print("Writing summary...")
    write_summary(result, summary_json_path)
    
    # Read back to write MD
    with open(summary_json_path, 'r') as f:
        summary_dict = json.load(f)
    write_hypothesis_summary(summary_md_path, summary_dict)

    end_time = time.time()
    print(f"Analysis complete in {end_time - start_time:.2f} seconds.")
    print(f"Results written to {summary_json_path} and {summary_md_path}")

if __name__ == '__main__':
    main()