"""
Validation script for synthetic trajectories generated by `generate_trajectories.py`.

This version reads a JSON‑Lines file (one trajectory per line) and validates:
  1. Presence of all required top‑level fields.
  2. Entropy tolerance (±0.01 bits/token).
  3. Correct `is_last_turn` flag.

Exits with status 0 on success; non‑zero on any validation failure.
"""

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

# Ensure project root is on sys.path for imports
import os
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from code.utils.entropy import entropy_per_token

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s",
)
logger = logging.getLogger(__name__)

TOLERANCE = 0.01
REQUIRED_TOP_FIELDS = {
    "trajectory_id",
    "turns",
    "critical_evidence_turn",
    "density_level",
    "target_entropy",
    "actual_entropy",
    "technical_token_ratio",
    "final_density",
    "is_last_turn",
}


def load_trajectories(filepath: Path) -> List[Dict[str, Any]]:
    """Load trajectories from a JSON‑Lines file."""
    if not filepath.exists():
        logger.error(f"Trajectory file not found: {filepath}")
        sys.exit(1)
    trajectories = []
    try:
        with open(filepath, "r", encoding="utf-8") as f:
            for line_number, line in enumerate(f, start=1):
                line = line.strip()
                if not line:
                    continue
                try:
                    obj = json.loads(line)
                    trajectories.append(obj)
                except json.JSONDecodeError as e:
                    logger.error(f"Invalid JSON at line {line_number}: {e}")
                    sys.exit(1)
    except IOError as e:
        logger.error(f"Error reading trajectory file: {e}")
        sys.exit(1)
    return trajectories


def validate_required_fields(traj: Dict[str, Any]) -> Tuple[bool, str]:
    missing = REQUIRED_TOP_FIELDS.difference(traj.keys())
    if missing:
        return False, f"Missing required fields: {sorted(missing)}"
    return True, ""


def validate_entropy(traj: Dict[str, Any]) -> Tuple[bool, str]:
    target = traj.get("target_entropy")
    actual = traj.get("actual_entropy")
    if target is None or actual is None:
        return False, "Missing target_entropy or actual_entropy"
    diff = abs(float(actual) - float(target))
    if diff > TOLERANCE:
        return (
            False,
            f"Entropy mismatch (target={target:.4f}, actual={actual:.4f}, diff={diff:.4f})",
        )
    return True, ""


def validate_last_turn_flag(traj: Dict[str, Any]) -> Tuple[bool, str]:
    is_last = traj.get("is_last_turn")
    turns = traj.get("turns")
    crit_idx = traj.get("critical_evidence_turn")
    if is_last is None or turns is None or crit_idx is None:
        return False, "Missing is_last_turn, turns, or critical_evidence_turn"
    expected = (crit_idx == len(turns) - 1)
    if is_last != expected:
        return False, f"is_last_turn flag mismatch (expected {expected}, got {is_last})"
    return True, ""


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input",
        type=str,
        default="data/raw/trajectories.jsonl",
        help="Path to the trajectories JSON‑Lines file.",
    )
    args = parser.parse_args()

    traj_path = Path(args.input)
    trajectories = load_trajectories(traj_path)

    total = len(trajectories)
    valid_count = 0
    errors = []

    for i, traj in enumerate(trajectories):
        ok, msg = validate_required_fields(traj)
        if not ok:
            errors.append(f"Trajectory {i}: {msg}")
            continue
        ok, msg = validate_entropy(traj)
        if not ok:
            errors.append(f"Trajectory {i}: {msg}")
            continue
        ok, msg = validate_last_turn_flag(traj)
        if not ok:
            errors.append(f"Trajectory {i}: {msg}")
            continue
        valid_count += 1

    if errors:
        logger.error(
            f"Validation failed: {valid_count}/{total} passed, {len(errors)} failed."
        )
        for err in errors[:10]:
            logger.error(f"  - {err}")
        sys.exit(1)
    else:
        logger.info(f"All {total} trajectories passed validation.")
        sys.exit(0)


if __name__ == "__main__":
    main()
