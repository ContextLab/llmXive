def load_trajectories(filepath: Path) -> List[Dict[str, Any]]:
    """Load trajectories from JSON file."""
    if not filepath.exists():
        logger.error(f"Trajectory file not found: {filepath}")
        sys.exit(1)
    
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            data = json.load(f)
        if not isinstance(data, list):
            logger.error("Trajectory file must contain a JSON list of objects.")
            sys.exit(1)
        return data
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in trajectory file: {e}")
        sys.exit(1)

def calculate_evidence_block_entropy(trajectory: Dict[str, Any]) -> float:
    """
    Calculate the entropy per token for the injected evidence block.
    
    The trajectory object is expected to have:
    - 'text': The full text of the trajectory (or we need to reconstruct it)
    - 'evidence_turn_index': The index where evidence was injected.
    - 'evidence_text': The actual text of the evidence block (if stored separately).
    
    Based on T011 description, the trajectory object includes metadata.
    If 'evidence_text' is not present, we assume the 'text' field contains the full trajectory
    and we need to identify the evidence block. However, T011 says "injected evidence blocks".
    A robust assumption: The trajectory JSON generated by T011 should include the 'evidence_text'
    or a way to slice it. If not, we might need to parse the 'text' based on turn structure.
    
    Let's assume the trajectory object has a field 'evidence_text' if it's critical,
    or we reconstruct it. If the generator T011 didn't save 'evidence_text', we must
    infer it.
    
    Re-reading T011: "Each object MUST include metadata fields: evidence_turn_index, density_value, is_critical".
    It does NOT explicitly say 'evidence_text' is saved.
    However, to calculate entropy of the *evidence block*, we need the text of that block.
    If T011 only saves the full trajectory text, we need to know how to slice it.
    
    Assumption: The 'text' field in the trajectory is a list of turns or a structured string.
    If it's a single string, we can't easily slice without a delimiter.
    Let's assume the generator T011 saved 'evidence_text' for verification purposes,
    or the 'text' is a list of turns.
    
    If the trajectory structure is:
    {
      "turns": [...],
      "evidence_turn_index": 3,
      ...
    }
    Then the evidence block is turns[3].
    
    If the trajectory structure is:
    {
      "text": "Turn 1... Turn 2...",
      "evidence_turn_index": 3,
      ...
    }
    This is ambiguous.
    
    Given the requirement "calculated entropy per token for injected evidence blocks",
    and the fact that T011 is the source, we must assume the data structure allows this.
    If T011 generated a 'text' that is a concatenation of turns, we need a delimiter.
    However, T011 description says "generate_text_block" in utils.
    
    Let's assume the trajectory object has a 'text' field that is the full text,
    and 'evidence_start' and 'evidence_end' indices, OR 'evidence_text' is provided.
    If neither, we cannot verify.
    
    Wait, T011 description: "Each object MUST include metadata fields: evidence_turn_index...".
    It does not mention evidence text.
    However, the validation task T048 *requires* calculating entropy of the evidence block.
    Therefore, T011 *must* have stored the evidence text or the turns are accessible.
    
    Let's assume the trajectory has a 'turns' list.
    If 'turns' is not present, we check for 'evidence_text'.
    If neither, we fail with a clear error.
    """
    turns = trajectory.get("turns")
    evidence_text = trajectory.get("evidence_text")
    evidence_idx = trajectory.get("evidence_turn_index")
    
    if evidence_text:
        block_text = evidence_text
    elif turns and isinstance(turns, list) and evidence_idx is not None:
        if 0 <= evidence_idx < len(turns):
            block_text = turns[evidence_idx]
        else:
            logger.warning(f"Invalid evidence_turn_index {evidence_idx} for trajectory length {len(turns)}")
            return 0.0
    else:
        logger.error(f"Cannot locate evidence block in trajectory. Missing 'turns' or 'evidence_text'.")
        sys.exit(1)
    
    if not block_text:
        logger.warning("Evidence block is empty.")
        return 0.0
        
    return entropy_per_token(block_text)

def validate_single_trajectory(trajectory: Dict[str, Any]) -> Tuple[bool, str]:
    """
    Validate a single trajectory's density match.
    Returns (is_valid, error_message).
    """
    requested_density = trajectory.get("density_value")
    if requested_density is None:
        return False, "Missing 'density_value' in trajectory metadata."
    
    try:
        calculated_entropy = calculate_evidence_block_entropy(trajectory)
    except Exception as e:
        return False, f"Failed to calculate entropy: {e}"
    
    # The task says "matches the requested density levels within ±0.01 bits/token".
    # Density is defined as 0.6 * Entropy + 0.4 * Ratio.
    # However, the validation requirement specifically says "calculated entropy per token ... matches the requested density".
    # This phrasing is slightly ambiguous.
    # Interpretation A: The 'density_value' stored in the trajectory IS the entropy (if technical ratio is 0 or ignored for this check).
    # Interpretation B: The 'density_value' is the composite density, and we must compare calculated composite density.
    # But the requirement says "calculated entropy per token ... matches ... density levels".
    # Given T011 generates "synthetic trajectories with controlled density", and the check is for "entropy per token",
    # it implies the target 'density_value' was the entropy target (or the entropy component is the primary driver).
    # However, the formula in T008 is Density = 0.6 * Entropy + 0.4 * Ratio.
    # If we calculate Entropy, we cannot directly compare to Density unless Ratio is known or 0.
    # BUT, T048 requirement: "assert that the calculated entropy per token for injected evidence blocks matches the requested density levels".
    # This implies the 'density_value' in the trajectory IS the entropy value we should compare against.
    # Why? Because the generator likely set the text to achieve a target ENTROPY, which then results in a density.
    # Or the 'density_value' field is actually the entropy.
    # Let's assume 'density_value' is the target entropy for the evidence block.
    # If the generator used the composite density to control the text, then 'density_value' is the composite.
    # But the check is on "entropy per token".
    # If 'density_value' is composite, and we check entropy, they won't match (0.6*E vs E).
    # The only way this check makes sense is if 'density_value' = Entropy, OR we calculate composite density.
    # Re-reading T011: "generated ... with controlled density ... verify ... entropy per token ... matches requested density".
    # This is a contradiction if density != entropy.
    # However, in many such synthetic generators, the "density" parameter often refers to the entropy of the text.
    # Let's assume the 'density_value' stored is the target entropy for the evidence block.
    # If the generator stored the composite density, the check "entropy matches density" would fail by definition (0.6 factor).
    # Given the strict wording "entropy per token ... matches ... density", I will assume 'density_value' is the target entropy.
    
    diff = abs(calculated_entropy - requested_density)
    if diff > TOLERANCE:
        return False, f"Entropy mismatch: requested={requested_density:.4f}, calculated={calculated_entropy:.4f}, diff={diff:.4f}"
    
    return True, ""

def main():
    logger.info("Starting trajectory validation...")
    
    if not TRAJECTORIES_PATH.exists():
        logger.error(f"Data file not found: {TRAJECTORIES_PATH}")
        logger.error("Run generate_trajectories.py (T011) first.")
        sys.exit(1)
    
    trajectories = load_trajectories(TRAJECTORIES_PATH)
    logger.info(f"Loaded {len(trajectories)} trajectories.")
    
    if len(trajectories) == 0:
        logger.error("No trajectories found to validate.")
        sys.exit(1)
    
    errors = []
    valid_count = 0
    
    for i, traj in enumerate(trajectories):
        is_valid, msg = validate_single_trajectory(traj)
        if is_valid:
            valid_count += 1
        else:
            errors.append(f"Trajectory {i}: {msg}")
    
    logger.info(f"Validation complete. Valid: {valid_count}, Invalid: {len(errors)}")
    
    if errors:
        logger.error(f"Found {len(errors)} invalid trajectories:")
        for err in errors[:10]: # Log first 10 errors
            logger.error(f"  - {err}")
        if len(errors) > 10:
            logger.error(f"  ... and {len(errors) - 10} more.")
        
        logger.error("Exiting with non-zero code due to validation failures.")
        sys.exit(1)
    else:
        logger.info("All trajectories passed validation.")
        sys.exit(0)

if __name__ == "__main__":
    main()