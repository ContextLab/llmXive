"""
Validation script for synthetic trajectories generated by `generate_trajectories.py`.

Checks performed:
  1. All required top‑level fields are present.
  2. The recorded `actual_entropy` of the injected evidence block matches the
     requested `target_entropy` within ±0.01 bits/token.  If `actual_entropy`
     is missing, it is recomputed from the evidence text.
  3. If the trajectory includes an `is_last_turn` flag, it must be consistent
     with whether the critical evidence occurs on the final turn.
  4. Reports a concise summary and exits with status 0 on success,
     non‑zero on any validation failure.
"""

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

# Ensure project root is on PYTHONPATH for sibling imports
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from code.utils.entropy import entropy_per_token
# Imported for completeness – not used directly in validation logic
from code.utils.heuristics import calculate_composite_density  # noqa: F401

# ----------------------------------------------------------------------
# Logging configuration
# ----------------------------------------------------------------------
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s",
)
logger = logging.getLogger(__name__)

# ----------------------------------------------------------------------
# Constants
# ----------------------------------------------------------------------
TOLERANCE = 0.01  # bits/token tolerance for entropy match
DEFAULT_TRAJ_PATH = PROJECT_ROOT / "data" / "raw" / "trajectories.json"
REQUIRED_TOP_FIELDS = {
    "trajectory_id",
    "turns",
    "critical_evidence_turn",
    "density_level",
    "target_entropy",
    "actual_entropy",
    "technical_token_ratio",
    "final_density",
}

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def load_trajectories(filepath: Path) -> List[Dict[str, Any]]:
    """Load a list of trajectory dictionaries from a JSON file."""
    if not filepath.exists():
        logger.error(f"Trajectory file not found: {filepath}")
        sys.exit(1)
    try:
        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)
        if not isinstance(data, list):
            logger.error("Trajectory file must contain a JSON list of objects.")
            sys.exit(1)
        return data
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in trajectory file: {e}")
        sys.exit(1)

def extract_evidence_text(traj: Dict[str, Any]) -> str:
    """
    Return the raw text of the injected evidence block.

    The generator stores each turn as a dict with a ``text`` field and marks the
    critical turn via ``critical_evidence_turn``.  We therefore fetch the turn
    at that index.
    """
    turns = traj.get("turns")
    idx = traj.get("critical_evidence_turn")
    if not isinstance(turns, list) or idx is None:
        raise ValueError("Missing 'turns' list or 'critical_evidence_turn' index.")
    if not (0 <= idx < len(turns)):
        raise IndexError(
            f"critical_evidence_turn {idx} out of bounds for {len(turns)} turns."
        )
    turn = turns[idx]
    text = turn.get("text")
    if text is None:
        raise ValueError("Critical turn missing 'text' field.")
    return text

def validate_required_fields(traj: Dict[str, Any]) -> Tuple[bool, str]:
    """Verify that all top‑level required keys are present."""
    missing = REQUIRED_TOP_FIELDS.difference(traj.keys())
    if missing:
        return False, f"Missing required fields: {sorted(missing)}"
    return True, ""

def validate_entropy(traj: Dict[str, Any]) -> Tuple[bool, str]:
    """
    Verify that the entropy recorded for the evidence block matches the
    target entropy within the allowed tolerance.

    Preference is given to the stored ``actual_entropy`` field (generated by
    `generate_trajectories.py`).  If that field is missing or not a number,
    the function falls back to recomputing entropy from the evidence text.
    """
    target = traj.get("target_entropy")
    if target is None:
        return False, "Field 'target_entropy' is missing."

    # Prefer the pre‑computed value that the generator already stored.
    actual = traj.get("actual_entropy")
    if isinstance(actual, (int, float)):
        measured = float(actual)
    else:
        # Fallback: compute from the evidence text.
        try:
            evidence_text = extract_evidence_text(traj)
            measured = entropy_per_token(evidence_text)
        except Exception as e:
            return False, f"Failed to compute evidence entropy: {e}"

    diff = abs(measured - target)
    if diff > TOLERANCE:
        return (
            False,
            f"Entropy mismatch (target={target:.4f}, measured={measured:.4f}, diff={diff:.4f})",
        )
    return True, ""

def validate_last_turn_flag(traj: Dict[str, Any]) -> Tuple[bool, str]:
    """
    If the trajectory provides an ``is_last_turn`` flag, ensure it matches the
    logical condition ``critical_evidence_turn == len(turns) - 1``.
    The flag is optional; if absent the check is skipped.
    """
    if "is_last_turn" not in traj:
        # Flag not supplied – nothing to validate.
        return True, ""
    is_last = traj["is_last_turn"]
    turns = traj["turns"]
    expected = traj["critical_evidence_turn"] == (len(turns) - 1)
    if is_last != expected:
        return (
            False,
            f"is_last_turn flag mismatch (expected {expected}, got {is_last})",
        )
    return True, ""

# ----------------------------------------------------------------------
# Main validation routine
# ----------------------------------------------------------------------
def main() -> None:
    parser = argparse.ArgumentParser(
        description="Validate synthetic trajectories against specification T012."
    )
    parser.add_argument(
        "--input",
        type=str,
        default=str(DEFAULT_TRAJ_PATH),
        help="Path to the trajectories JSON file (default: data/raw/trajectories.json)",
    )
    args = parser.parse_args()

    traj_path = Path(args.input)
    logger.info(f"Loading trajectories from {traj_path}")
    trajectories = load_trajectories(traj_path)

    if not trajectories:
        logger.error("No trajectories found in the file.")
        sys.exit(1)

    total = len(trajectories)
    valid_count = 0
    errors: List[str] = []

    for i, traj in enumerate(trajectories):
        # 1. Required fields
        ok, msg = validate_required_fields(traj)
        if not ok:
            errors.append(f"Trajectory {i}: {msg}")
            continue

        # 2. Entropy consistency (using stored actual_entropy when possible)
        ok, msg = validate_entropy(traj)
        if not ok:
            errors.append(f"Trajectory {i}: {msg}")
            continue

        # 3. is_last_turn flag (optional)
        ok, msg = validate_last_turn_flag(traj)
        if not ok:
            errors.append(f"Trajectory {i}: {msg}")
            continue

        # If we reach here, this trajectory passed all checks
        valid_count += 1

    logger.info(
        f"Validation complete: {valid_count}/{total} trajectories passed, {len(errors)} failed."
    )

    if errors:
        logger.error("Details of failed trajectories (first 10 shown):")
        for err in errors[:10]:
            logger.error(f"  - {err}")
        if len(errors) > 10:
            logger.error(f"  ... and {len(errors) - 10} more.")
        sys.exit(1)
    else:
        logger.info(f"All {total} trajectories passed validation.")
        sys.exit(0)


if __name__ == "__main__":
    main()
