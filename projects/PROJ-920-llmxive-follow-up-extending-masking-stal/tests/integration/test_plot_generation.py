"""
Integration test for plot generation (T024).

This test verifies that the visualization pipeline (analyze_results -> visualize_results)
produces a valid 3D surface plot file at the expected output location.

It simulates the end-to-end flow:
1. Loads real simulation data from data/processed/ (generated by T014/T015).
2. Runs the analysis pipeline (T018-T022) to generate regression_summary.json.
3. Runs the visualization pipeline (T021) to generate the 3D surface plot.
4. Verifies the plot file exists, is non-empty, and is under the 5MB size limit.
"""

import json
import os
import sys
import tempfile
import unittest
from pathlib import Path

# Ensure code directory is in path
project_root = Path(__file__).parent.parent.parent
code_dir = project_root / "code"
if str(code_dir) not in sys.path:
    sys.path.insert(0, str(code_dir))

# Import the modules we are testing
# These imports must match the API surface provided in the prompt
from analyze_results import (
    load_simulation_data,
    validate_sample_size,
    build_formula_with_splines,
    run_logistic_regression,
    write_summary,
    write_hypothesis_summary,
)
from visualize_results import (
    load_regression_summary,
    generate_surface_grid,
    plot_3d_surface,
)


class TestPlotGenerationIntegration(unittest.TestCase):
    """Integration test for the full plot generation pipeline."""

    def setUp(self):
        """Set up test fixtures and paths."""
        self.project_root = Path(__file__).parent.parent.parent
        self.data_processed_dir = self.project_root / "data" / "processed"
        self.output_dir = self.project_root / "output"
        self.plots_dir = self.output_dir / "plots"
        self.summary_file = self.output_dir / "regression_summary.json"
        self.hypothesis_file = self.output_dir / "hypothesis_summary.md"
        self.plot_file = self.plots_dir / "surface_plot.png"

        # Ensure directories exist (mimicking T001 setup)
        self.data_processed_dir.mkdir(parents=True, exist_ok=True)
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.plots_dir.mkdir(parents=True, exist_ok=True)

        # Check if input data exists (generated by T014/T015)
        # We look for a typical output file from the simulation
        simulation_files = list(self.data_processed_dir.glob("simulation_results_*.json"))
        if not simulation_files:
            # If no real data exists, we cannot run the full integration test
            # We skip the test rather than fabricate data
            self.skipTest(
                "No simulation results found in data/processed/. "
                "Please run T014/T015 to generate real data first."
            )
        
        self.simulation_file = simulation_files[0]

    def test_full_pipeline_produces_valid_plot(self):
        """
        Test that the full pipeline (Analysis -> Visualization) produces a valid plot file.
        
        Steps:
        1. Load real simulation data.
        2. Run logistic regression analysis.
        3. Write summary files.
        4. Generate the 3D surface plot.
        5. Verify the plot file exists and meets size constraints.
        """
        # --- Step 1: Load Data ---
        # Verify we can load the data (T018 requirement)
        try:
            data = load_simulation_data(self.simulation_file)
            self.assertIsInstance(data, list, "Data should be a list of records")
            self.assertGreater(len(data), 0, "Data should not be empty")
        except Exception as e:
            self.fail(f"Failed to load simulation data: {e}")

        # --- Step 2: Validate Sample Size (T019) ---
        try:
            is_valid, msg = validate_sample_size(data, min_samples=50)
            self.assertTrue(is_valid, f"Sample size validation failed: {msg}")
        except Exception as e:
            self.fail(f"Failed to validate sample size: {e}")

        # --- Step 3: Build Formula & Run Regression (T018) ---
        try:
            # Build formula with natural splines for 'horizon'
            formula = build_formula_with_splines("success", "density", "horizon", df=3)
            self.assertIn("density", formula)
            self.assertIn("horizon", formula)
            # Note: We assume 'ns' is available in statsmodels or we handle the import inside the function
            # The actual run_logistic_regression handles the statsmodels logic
            
            results = run_logistic_regression(data, formula)
            self.assertIsNotNone(results, "Regression results should not be None")
        except Exception as e:
            self.fail(f"Failed to run logistic regression: {e}")

        # --- Step 4: Write Summary Files (T020, T022) ---
        try:
            summary_data = write_summary(results, self.summary_file)
            self.assertTrue(self.summary_file.exists(), "Summary JSON file should exist")
            
            hypothesis_data = write_hypothesis_summary(results, self.hypothesis_file)
            self.assertTrue(self.hypothesis_file.exists(), "Hypothesis summary file should exist")
            
            # Verify content structure
            with open(self.summary_file, 'r') as f:
                summary_json = json.load(f)
                self.assertIn("coefficients", summary_json)
                self.assertIn("p_values", summary_json)
        except Exception as e:
            self.fail(f"Failed to write summary files: {e}")

        # --- Step 5: Generate Plot (T021) ---
        try:
            # Load the summary we just wrote
            summary = load_regression_summary(self.summary_file)
            
            # Generate the grid and plot
            # This calls the actual plotting logic which writes to disk
            plot_path = plot_3d_surface(summary, self.plots_dir, "surface_plot.png")
            
            self.assertIsNotNone(plot_path, "Plot path should not be None")
            self.assertTrue(Path(plot_path).exists(), f"Plot file should exist at {plot_path}")
            
            # Verify file size constraint (FR-004: PNG <= 5 MB)
            file_size = Path(plot_path).stat().st_size
            max_size_bytes = 5 * 1024 * 1024  # 5 MB
            self.assertLess(
                file_size, 
                max_size_bytes, 
                f"Plot file size ({file_size} bytes) exceeds limit of {max_size_bytes} bytes"
            )
            
            # Verify it's a non-empty file
            self.assertGreater(file_size, 0, "Plot file should not be empty")
            
            # Optional: Verify it looks like a PNG (magic bytes)
            with open(plot_path, 'rb') as f:
                header = f.read(8)
                # PNG signature: 89 50 4E 47 0D 0A 1A 0A
                if header[:4] != b'\x89PNG':
                    self.fail(f"File at {plot_path} does not appear to be a valid PNG.")

        except Exception as e:
            self.fail(f"Failed to generate or validate plot: {e}")


if __name__ == "__main__":
    unittest.main()