"""
T038: Post-split stratification validation.

Loads the train/val/test splits generated by T021A and performs a
Chi-Square test to assert that the distribution of 'quantization_level'
is statistically similar across splits.

Logs the p-value to logs/pipeline.log.
"""
import json
import logging
import argparse
from pathlib import Path
from typing import Dict, Any

import pandas as pd
from scipy import stats

from src.config.logging_config import setup_logger, ensure_log_dir

# Constants
SPLIT_FILES = {
    "train": "data/processed/split_train.parquet",
    "val": "data/processed/split_val.parquet",
    "test": "data/processed/split_test.parquet",
}
OUTPUT_DIR = "logs"
LOG_FILE = "pipeline.log"
COLUMN_NAME = "quantization_level"

def load_splits() -> Dict[str, pd.DataFrame]:
    """Load all three split files."""
    splits = {}
    for name, path_str in SPLIT_FILES.items():
        path = Path(path_str)
        if not path.exists():
            raise FileNotFoundError(f"Split file not found: {path_str}")
        splits[name] = pd.read_parquet(path)
    return splits

def validate_stratification(splits: Dict[str, pd.DataFrame]) -> Dict[str, Any]:
    """
    Perform Chi-Square test for independence on the quantization_level distribution
    across the splits.

    Returns:
        Dict containing test statistic, p-value, and observed counts.
    """
    # Extract counts per level per split
    observed_counts = []
    all_levels = set()

    for name, df in splits.items():
        if COLUMN_NAME not in df.columns:
            raise ValueError(f"Column '{COLUMN_NAME}' not found in {name} split.")
        
        counts = df[COLUMN_NAME].value_counts().to_dict()
        all_levels.update(counts.keys())
        observed_counts.append(counts)

    # Ensure all splits have entries for all levels (fill 0 if missing)
    sorted_levels = sorted(list(all_levels))
    matrix = []
    for counts in observed_counts:
        row = [counts.get(level, 0) for level in sorted_levels]
        matrix.append(row)

    # Perform Chi-Square Test
    # We are testing if the distribution of levels is independent of the split
    chi2, p_value, dof, expected = stats.chi2_contingency(matrix)

    return {
        "chi2_statistic": float(chi2),
        "p_value": float(p_value),
        "degrees_of_freedom": int(dof),
        "observed_counts": {k: v for k, v in zip(splits.keys(), matrix)},
        "expected_counts": expected.tolist(),
        "levels": sorted_levels,
        "is_statistically_similar": p_value > 0.05  # Standard alpha
    }

def main():
    """Entry point for T038."""
    # Setup logging
    ensure_log_dir(OUTPUT_DIR)
    logger = setup_logger("validate_stratification", Path(OUTPUT_DIR) / LOG_FILE)
    
    logger.info("Starting stratification validation (T038).")
    
    try:
        splits = load_splits()
        logger.info(f"Loaded splits: {list(splits.keys())}")

        # Check for empty splits
        for name, df in splits.items():
            if df.empty:
                logger.warning(f"Split '{name}' is empty.")

        result = validate_stratification(splits)
        
        logger.info(f"Chi-Square Statistic: {result['chi2_statistic']:.4f}")
        logger.info(f"P-Value: {result['p_value']:.4f}")
        logger.info(f"Statistically Similar (p > 0.05): {result['is_statistically_similar']}")
        
        # Log detailed counts
        logger.info(f"Observed Counts: {json.dumps(result['observed_counts'])}")

        # If p-value is very low, log a warning that stratification might be skewed
        if not result['is_statistically_similar']:
            logger.warning(
                f"Stratification check FAILED (p={result['p_value']:.4f}). "
                "The distribution of quantization levels differs significantly across splits."
            )
        else:
            logger.info("Stratification check PASSED.")

    except FileNotFoundError as e:
        logger.error(f"Missing required split file: {e}")
        raise
    except Exception as e:
        logger.error(f"Validation failed with error: {e}", exc_info=True)
        raise

    logger.info("T038 completed.")

if __name__ == "__main__":
    main()