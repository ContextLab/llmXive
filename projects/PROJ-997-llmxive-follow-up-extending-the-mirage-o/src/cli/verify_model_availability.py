"""
T036: Verify Model Availability for T015

Checks for the existence of the full-precision Llama-3-8B model
and the required quantized .gguf files (INT4, INT8, FP8) in data/raw/
before the main generation pipeline (T015) begins.

FAILS LOUDLY if any required resource is missing, providing clear
instructions on how to obtain them.
"""

import os
import sys
import logging
from pathlib import Path
from typing import List, Tuple, Dict, Any

# Import existing config utilities
from src.config.env_config import load_config, get_model_path, get_dataset_id
from src.config.logging_config import setup_logger, ensure_log_dir

# Constants for quantization levels and expected filenames
QUANTIZATION_LEVELS = {
    "INT4": "model-Q4_K_M.gguf",
    "INT8": "model-Q8_0.gguf",
    "FP8": "model-FP8.gguf"
}

# HuggingFace repo ID for the base model (Llama-3-8B)
# Note: Users must have access to this model on HF.
HF_BASE_MODEL_ID = "meta-llama/Meta-Llama-3-8B"
HF_CONVERSION_SCRIPT_URL = "https://github.com/ggerganov/llama.cpp/tree/master"

logger = logging.getLogger(__name__)


def check_huggingface_model_availability(model_id: str) -> Tuple[bool, str]:
    """
    Checks if the HuggingFace model exists and is accessible.
    Note: This does not download the model, only verifies existence via metadata.
    """
    try:
        from huggingface_hub import model_info
        # Attempt to get model info. If the model doesn't exist or is private/missing,
        # this will raise an exception.
        info = model_info(model_id)
        if info:
            return True, f"Model '{model_id}' found on HuggingFace Hub."
        return False, f"Model '{model_id}' not found on HuggingFace Hub."
    except Exception as e:
        # Check if it's a specific "model not found" error or general network issue
        error_msg = str(e)
        if "401" in error_msg or "404" in error_msg or "Repo id not found" in error_msg:
            return False, f"Model '{model_id}' not found or not accessible (requires login/acceptance). Error: {error_msg}"
        # For network issues or other errors, we assume it might be available but can't verify
        # However, for a strict check, we fail loudly if we can't confirm.
        return False, f"Could not verify model '{model_id}' on HuggingFace Hub. Error: {error_msg}"


def check_local_quantized_models(data_raw_dir: Path) -> Dict[str, Tuple[bool, str]]:
    """
    Checks for the existence of quantized .gguf files in the data/raw directory.
    Returns a dictionary mapping quantization level to (exists, message).
    """
    results = {}
    for level, filename in QUANTIZATION_LEVELS.items():
        file_path = data_raw_dir / filename
        if file_path.exists() and file_path.is_file():
            file_size_mb = file_path.stat().st_size / (1024 * 1024)
            results[level] = (True, f"Found {filename} ({file_size_mb:.2f} MB)")
        else:
            results[level] = (False, f"Missing {filename} in {data_raw_dir}")
    return results


def generate_instructions(missing_models: List[str], missing_ggufs: List[str]) -> str:
    """
    Generates a clear error message with instructions on how to obtain missing resources.
    """
    instructions = []
    instructions.append("\n" + "="*60)
    instructions.append("HOW TO OBTAIN MISSING RESOURCES:")
    instructions.append("="*60)

    if missing_models:
        instructions.append("\n1. HuggingFace Model Missing:")
        for model in missing_models:
            instructions.append(f"   - Model ID: {model}")
            instructions.append(f"     Action: Visit https://huggingface.co/{model}")
            instructions.append(f"     Note: You must be logged in and accept the user agreement for Llama 3.")
            instructions.append(f"     Command: huggingface-cli login")

    if missing_ggufs:
        instructions.append("\n2. Quantized .gguf Files Missing:")
        instructions.append("   - These files are typically generated by converting the base model using llama.cpp.")
        instructions.append("   - OR download pre-converted models from trusted sources (e.g., TheBloke on HuggingFace).")
        instructions.append("   - Example download command (if pre-converted models exist):")
        instructions.append("     huggingface-cli download <repo-id> <filename>")
        instructions.append("   - Or convert manually using:")
        instructions.append(f"     git clone {HF_CONVERSION_SCRIPT_URL}")
        instructions.append("     cd llama.cpp && make")
        instructions.append(f"     ./quantize <path-to-f16-model> {data_raw_dir}/model-Q4_K_M.gguf Q4_K_M")
        # Add specific commands for other levels if needed, or general instruction

    instructions.append("\n" + "="*60)
    return "\n".join(instructions)


def main():
    """
    Main entry point for T036 verification.
    """
    # Setup logging
    log_dir = Path("logs")
    ensure_log_dir(log_dir)
    logger = setup_logger("verify_model_availability", log_dir / "pipeline.log")

    logger.info("Starting T036: Model Availability Verification")

    # Load configuration
    try:
        config = load_config()
        # Get the base model path (though we mostly care about the HF ID for verification)
        # The task description specifically mentions 'meta-llama/Llama-3-8B'
        # We will use the constant HF_BASE_MODEL_ID for the HF check
        base_model_id = HF_BASE_MODEL_ID
    except Exception as e:
        logger.error(f"Failed to load configuration: {e}")
        print(f"CRITICAL: Failed to load configuration. Error: {e}")
        sys.exit(1)

    # Determine data/raw directory
    project_root = Path(__file__).resolve().parent.parent.parent
    data_raw_dir = project_root / "data" / "raw"

    if not data_raw_dir.exists():
        logger.warning(f"Directory {data_raw_dir} does not exist. Creating it.")
        data_raw_dir.mkdir(parents=True, exist_ok=True)

    missing_hf_models = []
    missing_ggufs = []

    # 1. Check HuggingFace Model
    logger.info(f"Checking availability of HuggingFace model: {base_model_id}")
    hf_available, hf_msg = check_huggingface_model_availability(base_model_id)
    if hf_available:
        logger.info(hf_msg)
        print(f"✓ {hf_msg}")
    else:
        logger.warning(hf_msg)
        missing_hf_models.append(base_model_id)
        print(f"✗ {hf_msg}")

    # 2. Check Local Quantized Models
    logger.info(f"Checking local quantized models in {data_raw_dir}")
    gguf_results = check_local_quantized_models(data_raw_dir)

    for level, (exists, msg) in gguf_results.items():
        if exists:
            logger.info(f"[{level}] {msg}")
            print(f"✓ [{level}] {msg}")
        else:
            logger.warning(f"[{level}] {msg}")
            missing_ggufs.append(level)
            print(f"✗ [{level}] {msg}")

    # 3. Final Decision
    all_missing = missing_hf_models + missing_ggufs
    if all_missing:
        logger.error("CRITICAL: One or more required model resources are missing.")
        print("\n" + "!"*60)
        print("CRITICAL ERROR: Required model resources are missing.")
        print("!"*60)

        if missing_hf_models:
            print(f"\nMissing HuggingFace Model(s): {', '.join(missing_hf_models)}")
        if missing_ggufs:
            print(f"\nMissing Quantized Files: {', '.join([QUANTIZATION_LEVELS[lvl] for lvl in missing_ggufs])}")

        # Print instructions
        print(generate_instructions(missing_hf_models, missing_ggufs))

        logger.error("Pipeline aborted due to missing resources.")
        sys.exit(1)
    else:
        logger.info("All required model resources are present and verified.")
        print("\n" + "="*60)
        print("SUCCESS: All required model resources are available.")
        print("Pipeline can proceed to T015.")
        print("="*60)
        sys.exit(0)


if __name__ == "__main__":
    main()
