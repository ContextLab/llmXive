def load_synchronized_inputs(path: Path) -> List[Dict[str, Any]]:
    """Load the synchronized inputs generated by T026A."""
    if not path.exists():
        raise FileNotFoundError(f"Synchronized inputs file not found: {path}")
    
    with open(path, 'r') as f:
        data = json.load(f)
    
    return data


def calculate_reasoning_score(
    log_probs: List[float], 
    generated_tokens: List[int],
    correct_answer_tokens: List[int],
    tokenizer: Any
) -> float:
    """
    Calculate continuous reasoning score derived from log-probabilities.
    
    Formula: score = log_prob(correct_answer_token_sequence) * (1 - entropy_of_sequence)
    
    Args:
        log_probs: List of log probabilities for generated tokens
        generated_tokens: List of generated token IDs
        correct_answer_tokens: List of token IDs for the correct answer
        tokenizer: The tokenizer used for the model
        
    Returns:
        float: Calculated reasoning score
    """
    if not log_probs or not generated_tokens:
        return 0.0
    
    # Calculate log probability of the correct answer sequence
    # We need to find where the correct answer starts in the generated sequence
    # For simplicity, we assume the model generates the answer directly
    # In a real implementation, we'd need to align generated tokens with correct tokens
    
    # Calculate sum of log probs for the generated sequence (proxy for log_prob of correct sequence)
    total_log_prob = sum(log_probs)
    
    # Calculate entropy of the sequence
    # Entropy = -sum(p * log(p)) where p = exp(log_prob)
    probs = [np.exp(lp) for lp in log_probs]
    # Normalize to ensure they sum to 1 (for entropy calculation)
    prob_sum = sum(probs)
    if prob_sum > 0:
        probs = [p / prob_sum for p in probs]
    
    # Calculate entropy
    entropy = 0.0
    for p in probs:
        if p > 0:
            entropy -= p * np.log(p + 1e-10)
    
    # Normalize entropy (max entropy for sequence of length n is log(n))
    max_entropy = np.log(len(log_probs) + 1e-10) if len(log_probs) > 0 else 1.0
    normalized_entropy = entropy / max_entropy if max_entropy > 0 else 0.0
    
    # Calculate final score
    score = total_log_prob * (1 - normalized_entropy)
    
    return float(score)


def get_correct_answer_tokens(
    prompt: str, 
    ground_truth: str, 
    tokenizer: Any
) -> List[int]:
    """
    Get token IDs for the correct answer from GSM8K ground truth.
    
    Args:
        prompt: The input prompt
        ground_truth: The ground truth answer from GSM8K
        tokenizer: The tokenizer used for the model
        
    Returns:
        List[int]: Token IDs for the correct answer
    """
    # Extract just the answer part (GSM8K format: "#### <answer>")
    if "####" in ground_truth:
        answer_part = ground_truth.split("####")[1].strip()
    else:
        answer_part = ground_truth.strip()
    
    # Tokenize the answer
    tokens = tokenizer.encode(answer_part, add_special_tokens=False)
    return tokens


def run_baseline_sync(
    test_data_path: Path,
    synchronized_inputs_path: Path,
    output_path: Path,
    quantization_levels: List[str] = ["INT4", "INT8", "FP8"],
    acceptance_threshold: float = -10.0
) -> Dict[str, Any]:
    """
    Execute the full-hardware-sync baseline.
    
    Args:
        test_data_path: Path to the test dataset (parquet)
        synchronized_inputs_path: Path to synchronized inputs JSON
        output_path: Path to write the output metrics JSON
        quantization_levels: List of quantization levels to evaluate
        acceptance_threshold: Threshold for acceptance rate calculation
        
    Returns:
        Dict containing baseline metrics
    """
    ensure_log_dir()
    logger.info(f"Starting baseline sync execution for {len(quantization_levels)} quantization levels")
    
    # Load test data
    test_data = load_test_data(test_data_path)
    logger.info(f"Loaded {len(test_data)} test samples")
    
    # Load synchronized inputs
    synchronized_inputs = load_synchronized_inputs(synchronized_inputs_path)
    logger.info(f"Loaded {len(synchronized_inputs)} synchronized inputs")
    
    # Load configuration
    config = load_config()
    model_path = get_model_path()
    
    if not model_path:
        raise ValueError("MODEL_PATH not configured in .env")
    
    # Load tokenizer
    from transformers import AutoTokenizer
    tokenizer = AutoTokenizer.from_pretrained(model_path)
    
    # Initialize metrics storage
    all_scores = []
    all_acceptances = []
    total_time_start = time.time()
    
    # Process each quantization level
    level_metrics = {}
    
    for level in quantization_levels:
        logger.info(f"Processing quantization level: {level}")
        
        # Load quantized model for this level
        inference_time_start = time.time()
        
        try:
            quantized_model = load_quantized_model(model_path, level)
            if quantized_model is None:
                logger.error(f"Failed to load model for level {level}, skipping")
                continue
            
            inference_time_end = time.time()
            inference_only_time = inference_time_end - inference_time_start
            
            level_scores = []
            level_acceptances = []
            
            # Process each sample
            for idx, sample in enumerate(test_data):
                if idx % 50 == 0:
                    logger.info(f"Processing sample {idx}/{len(test_data)} for level {level}")
                
                # Get prompt and ground truth
                prompt = sample.get('prompt', '')
                ground_truth = sample.get('ground_truth', '')
                
                if not prompt or not ground_truth:
                    logger.warning(f"Skipping sample {idx} due to missing prompt or ground truth")
                    continue
                
                # Get correct answer tokens
                correct_answer_tokens = get_correct_answer_tokens(prompt, ground_truth, tokenizer)
                
                # Run quantized inference
                try:
                    result = run_quantized_inference(
                        model=quantized_model,
                        prompt=prompt,
                        max_new_tokens=100
                    )
                    
                    if result is None or not result.success:
                        logger.warning(f"Inference failed for sample {idx} at level {level}")
                        continue
                    
                    # Extract log probs and generated tokens
                    log_probs = result.log_probs if hasattr(result, 'log_probs') else []
                    generated_tokens = result.generated_tokens if hasattr(result, 'generated_tokens') else []
                    
                    # Calculate reasoning score
                    score = calculate_reasoning_score(
                        log_probs=log_probs,
                        generated_tokens=generated_tokens,
                        correct_answer_tokens=correct_answer_tokens,
                        tokenizer=tokenizer
                    )
                    
                    level_scores.append(score)
                    
                    # Determine acceptance
                    acceptance = 1.0 if score > acceptance_threshold else 0.0
                    level_acceptances.append(acceptance)
                    
                except Exception as e:
                    logger.error(f"Error processing sample {idx} at level {level}: {str(e)}")
                    continue
            
            # Calculate level metrics
            if level_scores:
                avg_score = float(np.mean(level_scores))
                acceptance_rate = float(np.mean(level_acceptances))
            else:
                avg_score = 0.0
                acceptance_rate = 0.0
            
            level_metrics[level] = {
                'average_reasoning_score': avg_score,
                'acceptance_rate': acceptance_rate,
                'sample_count': len(level_scores),
                'inference_only_time': inference_only_time
            }
            
            all_scores.extend(level_scores)
            all_acceptances.extend(level_acceptances)
            
        except Exception as e:
            logger.error(f"Failed to process level {level}: {str(e)}")
            continue
    
    total_time_end = time.time()
    total_time = total_time_end - total_time_start
    
    # Calculate overall metrics
    if all_scores:
        overall_reasoning_score = float(np.mean(all_scores))
        overall_acceptance_rate = float(np.mean(all_acceptances))
    else:
        overall_reasoning_score = 0.0
        overall_acceptance_rate = 0.0
    
    # Prepare output
    baseline_metrics = {
        'acceptance_rate': overall_acceptance_rate,
        'reasoning_score': overall_reasoning_score,
        'timing_metadata': {
            'total_time': float(total_time),
            'inference_only_time': sum(
                level_metrics[l].get('inference_only_time', 0) 
                for l in quantization_levels if l in level_metrics
            ),
            'policy_evaluation_time': 0.0  # For baseline, this is the inference overhead
        },
        'per_level_metrics': level_metrics,
        'config': {
            'quantization_levels': quantization_levels,
            'acceptance_threshold': acceptance_threshold,
            'total_samples_processed': len(all_scores)
        }
    }
    
    # Write output
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(baseline_metrics, f, indent=2)
    
    logger.info(f"Baseline sync complete. Output written to {output_path}")
    logger.info(f"Overall acceptance rate: {overall_acceptance_rate:.4f}")
    logger.info(f"Overall reasoning score: {overall_reasoning_score:.4f}")
    
    return baseline_metrics


