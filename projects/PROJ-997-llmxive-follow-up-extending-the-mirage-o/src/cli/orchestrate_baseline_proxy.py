"""
Orchestrate Baseline and Proxy execution for US3.

This script synchronizes inputs from T026A, loads the test set,
and triggers the Baseline (T027) and Proxy (T028) loops with
shared inputs to ensure a valid paired comparison.
"""
import os
import sys
import json
import logging
import random
from pathlib import Path
from typing import List, Dict, Any, Optional

# Ensure src is in path for execution
if "src" not in sys.path:
    sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from src.config.logging_config import setup_logger
from src.config.env_config import load_config
from src.models.entities import TrainingSample

# Import the specific task scripts to trigger them
# Note: These imports assume the scripts have a main() or run() function
# that can be called programmatically. If they are strictly CLI,
# we simulate the execution flow by importing their logic or calling subprocess.
# For this implementation, we assume we can import the logic functions
# or call the scripts via subprocess to ensure isolation if needed.
# However, to keep it as a pure Python module as requested:
try:
    from src.cli.run_baseline_sync import run_baseline_execution
except ImportError:
    # Fallback if the function is not directly importable as a library
    run_baseline_execution = None

try:
    from src.cli.run_proxy_loop import run_proxy_execution
except ImportError:
    run_proxy_execution = None

LOGGER = setup_logger(__name__)

FIXED_SEED = 42
INPUTS_FILE = Path("data/processed/synchronized_inputs.json")
TEST_SET_FILE = Path("data/processed/split_test.parquet")
BASELINE_OUTPUT = Path("data/processed/baseline_metrics.json")
PROXY_OUTPUT = Path("data/processed/proxy_metrics.json")

def load_synchronized_inputs() -> List[Dict[str, Any]]:
    """Load the fixed set of prompts generated by T026A."""
    if not INPUTS_FILE.exists():
        raise FileNotFoundError(
            f"Synchronized inputs file not found: {INPUTS_FILE}. "
            "Please ensure T026A (synchronize_inputs.py) has been run."
        )
    
    with open(INPUTS_FILE, "r", encoding="utf-8") as f:
        data = json.load(f)
    
    if "prompts" not in data:
        raise ValueError("Invalid format in synchronized_inputs.json: missing 'prompts' key.")
    
    return data["prompts"]

def load_test_set() -> List[Dict[str, Any]]:
    """Load the test split prepared by T021A."""
    if not TEST_SET_FILE.exists():
        raise FileNotFoundError(
            f"Test set not found: {TEST_SET_FILE}. "
            "Please ensure T021A (prepare_data_split.py) has been run."
        )
    
    import pandas as pd
    df = pd.read_parquet(TEST_SET_FILE)
    return df.to_dict(orient="records")

def synchronize_and_filter(test_set: List[Dict], prompts: List[Dict]) -> List[Dict]:
    """
    Filter the test set to only include samples that match the synchronized inputs.
    This ensures the Baseline and Proxy run on the exact same data points.
    """
    # Assuming 'input_id' or 'prompt' is the unique identifier.
    # Based on T015, we have 'input_id'.
    prompt_ids = {p.get("input_id") or p.get("id") for p in prompts}
    
    filtered = []
    for sample in test_set:
        sample_id = sample.get("input_id") or sample.get("id")
        if sample_id in prompt_ids:
            filtered.append(sample)
    
    LOGGER.info(f"Synchronized test set: {len(filtered)} samples matched {len(prompts)} inputs.")
    if len(filtered) != len(prompts):
        LOGGER.warning(
            f"Mismatch in synchronization: {len(prompts)} inputs provided, "
            f"but only {len(filtered)} found in test set. "
            "This may indicate data drift or missing samples."
        )
    return filtered

def run_baseline_loop(synchronized_samples: List[Dict]) -> Dict[str, Any]:
    """
    Execute the full-hardware-sync baseline (T027).
    If the script is not importable as a library, we attempt to run it via subprocess.
    """
    LOGGER.info("Starting Baseline Execution (T027)...")
    
    if run_baseline_execution:
        try:
            return run_baseline_execution(synchronized_samples)
        except Exception as e:
            LOGGER.error(f"Baseline execution failed: {e}")
            raise
    else:
        # Fallback: Execute the script directly
        import subprocess
        result = subprocess.run(
            [sys.executable, str(Path(__file__).parent / "run_baseline_sync.py")],
            capture_output=True,
            text=True,
            check=False
        )
        if result.returncode != 0:
            LOGGER.error(f"Baseline script failed: {result.stderr}")
            raise RuntimeError(f"Baseline execution failed: {result.stderr}")
        
        if not BASELINE_OUTPUT.exists():
            raise RuntimeError("Baseline script did not produce output file.")
        
        with open(BASELINE_OUTPUT, "r") as f:
            return json.load(f)

def run_proxy_loop(synchronized_samples: List[Dict]) -> Dict[str, Any]:
    """
    Execute the Proxy MIPU loop (T028) using the synchronized inputs.
    """
    LOGGER.info("Starting Proxy Execution (T028)...")
    
    if run_proxy_execution:
        try:
            return run_proxy_execution(synchronized_samples)
        except Exception as e:
            LOGGER.error(f"Proxy execution failed: {e}")
            raise
    else:
        # Fallback: Execute the script directly
        import subprocess
        result = subprocess.run(
            [sys.executable, str(Path(__file__).parent / "run_proxy_loop.py")],
            capture_output=True,
            text=True,
            check=False
        )
        if result.returncode != 0:
            LOGGER.error(f"Proxy script failed: {result.stderr}")
            raise RuntimeError(f"Proxy execution failed: {result.stderr}")
        
        if not PROXY_OUTPUT.exists():
            raise RuntimeError("Proxy script did not produce output file.")
        
        with open(PROXY_OUTPUT, "r") as f:
            return json.load(f)

def main():
    """Main entry point for orchestration."""
    setup_logger()
    config = load_config()
    
    # 1. Set Fixed Seed
    random.seed(FIXED_SEED)
    if "numpy" in sys.modules:
        import numpy as np
        np.random.seed(FIXED_SEED)
    LOGGER.info(f"Random seed set to {FIXED_SEED}")

    # 2. Load Synchronized Inputs (T026A output)
    try:
        prompts = load_synchronized_inputs()
    except FileNotFoundError as e:
        LOGGER.critical(str(e))
        sys.exit(1)

    # 3. Load Test Set
    try:
        test_set = load_test_set()
    except FileNotFoundError as e:
        LOGGER.critical(str(e))
        sys.exit(1)

    # 4. Synchronize
    synchronized_samples = synchronize_and_filter(test_set, prompts)
    if not synchronized_samples:
        LOGGER.error("No samples found after synchronization. Aborting.")
        sys.exit(1)

    # 5. Run Baseline (T027)
    try:
        baseline_results = run_baseline_loop(synchronized_samples)
    except Exception as e:
        LOGGER.critical(f"Baseline execution aborted: {e}")
        sys.exit(1)

    # 6. Run Proxy (T028)
    try:
        proxy_results = run_proxy_loop(synchronized_samples)
    except Exception as e:
        LOGGER.critical(f"Proxy execution aborted: {e}")
        sys.exit(1)

    # 7. Log Summary
    LOGGER.info("Orchestration Complete.")
    LOGGER.info(f"Baseline Metrics: {json.dumps(baseline_results, indent=2)}")
    LOGGER.info(f"Proxy Metrics: {json.dumps(proxy_results, indent=2)}")
    
    return {
        "baseline": baseline_results,
        "proxy": proxy_results,
        "synchronized_count": len(synchronized_samples)
    }

if __name__ == "__main__":
    main()