"""
T032: Aggregate bound verification results from T027B.

This script loads the consistency report generated by T027B (verify_bound_consistency.py),
calculates a global pass/fail verdict based on a threshold, and writes the final
aggregated report to data/processed/aggregated_consistency_report.json.
"""

import json
import logging
import sys
from pathlib import Path
from typing import Dict, Any, Optional

# Add project root to path if running as script
if __name__ == "__main__" and "code" not in sys.path[0]:
    sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from src.config.logging_config import setup_logger, ensure_log_dir

# Constants
INPUT_FILE = Path("data/processed/consistency_report.json")
OUTPUT_FILE = Path("data/processed/aggregated_consistency_report.json")
GLOBAL_THRESHOLD = 0.90  # 90% of samples must satisfy the bound
PER_LEVEL_THRESHOLD = 0.85  # 85% per level
logger = setup_logger("T032_aggregate_bound_results", Path("logs/pipeline.log"))

def load_consistency_data(input_path: Path) -> Dict[str, Any]:
    """Load the consistency report from T027B."""
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    with open(input_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # Validate schema
    required_keys = ["per_level_correlations", "global_consistency_metric", "bound_satisfaction_pct"]
    for key in required_keys:
        if key not in data:
            raise ValueError(f"Missing required key '{key}' in {input_path}")
    
    return data

def calculate_aggregated_verdict(
    global_metric: float,
    per_level_metrics: Dict[str, float],
    global_threshold: float = GLOBAL_THRESHOLD,
    per_level_threshold: float = PER_LEVEL_THRESHOLD
) -> Dict[str, Any]:
    """
    Determine pass/fail verdict based on thresholds.
    
    Returns:
        dict with 'verdict' (PASS/FAIL), 'global_score', 'per_level_scores', 'details'
    """
    global_pass = global_metric >= global_threshold
    
    per_level_pass = {}
    all_levels_pass = True
    for level, score in per_level_metrics.items():
        passed = score >= per_level_threshold
        per_level_pass[level] = {
            "score": score,
            "threshold": per_level_threshold,
            "passed": passed
        }
        if not passed:
            all_levels_pass = False

    final_verdict = "PASS" if (global_pass and all_levels_pass) else "FAIL"
    
    return {
        "verdict": final_verdict,
        "global_score": global_metric,
        "global_threshold": global_threshold,
        "global_passed": global_pass,
        "per_level_scores": per_level_pass,
        "per_level_threshold": per_level_threshold,
        "all_levels_passed": all_levels_pass
    }

def aggregate_results(
    input_path: Path = INPUT_FILE,
    global_threshold: float = GLOBAL_THRESHOLD,
    per_level_threshold: float = PER_LEVEL_THRESHOLD
) -> Dict[str, Any]:
    """
    Main aggregation logic.
    
    1. Load consistency report from T027B.
    2. Calculate aggregated verdict.
    3. Return the full report structure.
    """
    logger.info(f"Loading consistency data from {input_path}")
    data = load_consistency_data(input_path)
    
    logger.info(f"Calculating aggregated verdict with global_threshold={global_threshold}")
    verdict_data = calculate_aggregated_verdict(
        data["global_consistency_metric"],
        data["per_level_correlations"],
        global_threshold,
        per_level_threshold
    )
    
    # Construct final report
    report = {
        "source": str(input_path),
        "aggregated_at": "runtime",  # Will be replaced by actual timestamp if needed
        "global_consistency_metric": data["global_consistency_metric"],
        "bound_satisfaction_pct": data["bound_satisfaction_pct"],
        "per_level_correlations": data["per_level_correlations"],
        "verdict_details": verdict_data,
        "summary": f"Global Metric: {data['global_consistency_metric']:.4f} (Threshold: {global_threshold}), "
                   f"Verdict: {verdict_data['verdict']}"
    }
    
    return report

def write_report(report: Dict[str, Any], output_path: Path = OUTPUT_FILE) -> None:
    """Write the aggregated report to JSON file."""
    ensure_log_dir(output_path.parent)
    
    logger.info(f"Writing aggregated report to {output_path}")
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Report written successfully. Verdict: {report['verdict_details']['verdict']}")

def main() -> int:
    """Entry point for the script."""
    try:
        ensure_log_dir(Path("logs"))
        logger.info("Starting T032: Aggregate Bound Results")
        
        report = aggregate_results()
        write_report(report)
        
        logger.info("T032 completed successfully")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"Input file missing: {e}")
        return 1
    except ValueError as e:
        logger.error(f"Invalid data format: {e}")
        return 2
    except Exception as e:
        logger.exception(f"Unexpected error during aggregation: {e}")
        return 3

if __name__ == "__main__":
    sys.exit(main())
