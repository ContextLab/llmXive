"""
T021: Train the Kernel Ridge Regression (KRR) predictor for the policy gap.

This script loads the stratified training data generated by T021A,
trains a KRR model to predict the calculated KL divergence (policy gap)
based on training-side features (gradient norms, local curvature),
and saves the model artifact to data/models/gap_predictor.pkl.

Dependencies:
    - src/services/evaluator.py (for evaluation logic if needed during training)
    - src/config/logging_config.py
    - src/config/env_config.py
"""
import os
import sys
import json
import logging
import pickle
from pathlib import Path
from typing import Optional, Dict, Any

import pandas as pd
import numpy as np
from sklearn.kernel_ridge import KernelRidge
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_absolute_error, r2_score
from scipy.stats import pearsonr

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(project_root))

from src.config.logging_config import setup_logger, ensure_log_dir
from src.config.env_config import load_config

# Constants
TRAIN_DATA_PATH = "data/processed/split_train.parquet"
VAL_DATA_PATH = "data/processed/split_val.parquet"
MODEL_OUTPUT_PATH = "data/models/gap_predictor.pkl"
TRAIN_METRICS_OUTPUT = "data/processed/train_metrics.json"
LOG_FILE = "logs/pipeline.log"

# Feature columns defined in T012/T015
FEATURE_COLS = ["gradient_norms", "local_curvature"]
TARGET_COL = "calculated_kl_divergence"

def load_and_prepare_data(train_path: str, val_path: str) -> tuple:
    """
    Load training and validation data, prepare features and targets.
    
    Args:
        train_path: Path to split_train.parquet
        val_path: Path to split_val.parquet
        
    Returns:
        Tuple of (X_train, y_train, X_val, y_val) as numpy arrays
    """
    logger = logging.getLogger(__name__)
    
    if not os.path.exists(train_path):
        raise FileNotFoundError(f"Training data not found at {train_path}. "
                              "Please run T021A (prepare_data_split.py) first.")
    if not os.path.exists(val_path):
        logger.warning(f"Validation data not found at {val_path}. "
                     "Training will proceed without validation set.")
        
    # Load training data
    df_train = pd.read_parquet(train_path)
    logger.info(f"Loaded {len(df_train)} training samples")
    
    # Validate required columns
    missing_cols = [col for col in FEATURE_COLS + [TARGET_COL] if col not in df_train.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in training data: {missing_cols}")
        
    # Extract features and target
    X_train = df_train[FEATURE_COLS].values
    y_train = df_train[TARGET_COL].values
    
    # Handle potential NaNs
    if np.any(np.isnan(X_train)) or np.any(np.isnan(y_train)):
        logger.warning("NaN values detected in data. Dropping rows with NaN.")
        valid_mask = ~(np.isnan(X_train).any(axis=1) | np.isnan(y_train))
        X_train = X_train[valid_mask]
        y_train = y_train[valid_mask]
        logger.info(f"Remaining samples after NaN removal: {len(X_train)}")
        
    # Load validation data if available
    X_val, y_val = None, None
    if os.path.exists(val_path):
        df_val = pd.read_parquet(val_path)
        if all(col in df_val.columns for col in FEATURE_COLS + [TARGET_COL]):
            X_val = df_val[FEATURE_COLS].values
            y_val = df_val[TARGET_COL].values
            # Handle NaNs in validation
            if np.any(np.isnan(X_val)) or np.any(np.isnan(y_val)):
                valid_mask = ~(np.isnan(X_val).any(axis=1) | np.isnan(y_val))
                X_val = X_val[valid_mask]
                y_val = y_val[valid_mask]
            logger.info(f"Loaded {len(X_val)} validation samples")
            
    return X_train, y_train, X_val, y_val

def train_krr_model(X_train: np.ndarray, y_train: np.ndarray, 
                   X_val: Optional[np.ndarray] = None,
                   y_val: Optional[np.ndarray] = None) -> tuple:
    """
    Train a Kernel Ridge Regression model with hyperparameter tuning.
    
    Args:
        X_train: Training features
        y_train: Training targets
        X_val: Validation features (optional)
        y_val: Validation targets (optional)
        
    Returns:
        Tuple of (trained_model, best_params, metrics_dict)
    """
    logger = logging.getLogger(__name__)
    
    # Hyperparameter grid for KRR
    alphas = [0.01, 0.1, 1.0, 10.0, 100.0]
    kernels = ['rbf', 'polynomial']
    kernel_params = [
        {'gamma': [0.01, 0.1, 1.0]},
        {'degree': [2, 3], 'coef0': [1.0, 2.5]}
    ]
    
    best_model = None
    best_score = -np.inf
    best_params = {}
    
    logger.info("Starting hyperparameter search...")
    
    for kernel, k_params in zip(kernels, kernel_params):
        for alpha in alphas:
            for param_val in k_params.values():
                if len(k_params) == 1:
                    k_param = k_params[list(k_params.keys())[0]]
                    if isinstance(k_param, list):
                        for val in k_param:
                            kwargs = {list(k_params.keys())[0]: val}
                            try:
                                model = KernelRidge(alpha=alpha, kernel=kernel, **kwargs)
                                model.fit(X_train, y_train)
                                
                                # Evaluate
                                if X_val is not None and y_val is not None:
                                    score = model.score(X_val, y_val)
                                else:
                                    # Fallback to training score if no validation
                                    score = model.score(X_train, y_train)
                                
                                if score > best_score:
                                    best_score = score
                                    best_model = model
                                    best_params = {
                                        'alpha': alpha,
                                        'kernel': kernel,
                                        **kwargs
                                    }
                                    logger.debug(f"New best: {best_params} with score {score:.4f}")
                            except Exception as e:
                                logger.debug(f"Failed with params {alpha}, {kernel}, {kwargs}: {e}")
                                continue
    
    if best_model is None:
        # Fallback to default params if nothing worked
        logger.warning("Hyperparameter search failed. Using default KRR parameters.")
        best_model = KernelRidge(alpha=1.0, kernel='rbf', gamma=0.1)
        best_model.fit(X_train, y_train)
        best_params = {'alpha': 1.0, 'kernel': 'rbf', 'gamma': 0.1}
        
    # Final evaluation on validation set if available
    metrics = {}
    if X_val is not None and y_val is not None:
        y_pred = best_model.predict(X_val)
        metrics['val_mae'] = float(mean_absolute_error(y_val, y_pred))
        metrics['val_r2'] = float(r2_score(y_val, y_pred))
        if len(y_val) > 1:
            corr, _ = pearsonr(y_val, y_pred)
            metrics['val_pearson_r'] = float(corr)
        logger.info(f"Validation MAE: {metrics['val_mae']:.4f}, R2: {metrics['val_r2']:.4f}")
    else:
        # Evaluate on training set if no validation
        y_pred = best_model.predict(X_train)
        metrics['train_mae'] = float(mean_absolute_error(y_train, y_pred))
        metrics['train_r2'] = float(r2_score(y_train, y_pred))
        if len(y_train) > 1:
            corr, _ = pearsonr(y_train, y_pred)
            metrics['train_pearson_r'] = float(corr)
        logger.info(f"Training MAE: {metrics['train_mae']:.4f}, R2: {metrics['train_r2']:.4f}")
        
    return best_model, best_params, metrics

def save_model(model: KernelRidge, params: Dict[str, Any], metrics: Dict[str, float], 
              output_path: str, metrics_path: str):
    """
    Save the trained model and its metadata.
    
    Args:
        model: Trained KRR model
        params: Hyperparameters used
        metrics: Evaluation metrics
        output_path: Path to save model pickle
        metrics_path: Path to save metrics JSON
    """
    logger = logging.getLogger(__name__)
    
    # Ensure output directory exists
    model_dir = Path(output_path).parent
    model_dir.mkdir(parents=True, exist_ok=True)
    
    # Save model
    with open(output_path, 'wb') as f:
        pickle.dump({
            'model': model,
            'params': params,
            'feature_cols': FEATURE_COLS,
            'target_col': TARGET_COL,
            'metrics': metrics
        }, f)
    logger.info(f"Model saved to {output_path}")
    
    # Save metrics
    with open(metrics_path, 'w') as f:
        json.dump(metrics, f, indent=2)
    logger.info(f"Metrics saved to {metrics_path}")

def main():
    """Main entry point for training the gap predictor."""
    # Setup logging
    ensure_log_dir(LOG_FILE)
    logger = setup_logger("train_predictor", LOG_FILE)
    
    logger.info("=" * 60)
    logger.info("Starting T021: Training Gap Predictor (KRR)")
    logger.info("=" * 60)
    
    try:
        # Load configuration
        config = load_config()
        logger.info(f"Configuration loaded: model_path={config.get('MODEL_PATH', 'N/A')}")
        
        # Prepare data paths
        train_path = str(project_root / TRAIN_DATA_PATH)
        val_path = str(project_root / VAL_DATA_PATH)
        model_output = str(project_root / MODEL_OUTPUT_PATH)
        metrics_output = str(project_root / TRAIN_METRICS_OUTPUT)
        
        # Load and prepare data
        logger.info(f"Loading data from {train_path}...")
        X_train, y_train, X_val, y_val = load_and_prepare_data(train_path, val_path)
        
        if len(X_train) == 0:
            raise ValueError("No training data available after cleaning.")
            
        logger.info(f"Training on {len(X_train)} samples")
        if X_val is not None:
            logger.info(f"Validating on {len(X_val)} samples")
        
        # Train model
        logger.info("Training Kernel Ridge Regression model...")
        model, params, metrics = train_krr_model(X_train, y_train, X_val, y_val)
        
        # Save results
        logger.info("Saving model and metrics...")
        save_model(model, params, metrics, model_output, metrics_output)
        
        logger.info("=" * 60)
        logger.info("T021 COMPLETED SUCCESSFULLY")
        logger.info(f"Model: {model_output}")
        logger.info(f"Metrics: {metrics_output}")
        logger.info("=" * 60)
        
    except FileNotFoundError as e:
        logger.error(f"Data file not found: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Training failed with error: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()