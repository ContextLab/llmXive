"""
Simple integration test for the statistics‑validation script.

It re‑uses the dataset generated by ``test_generate_ground_truth_wrapper`` to
confirm that the validator returns a zero exit code when the JSON file
contains a statistically significant KL divergence (which is very likely
for real GSM8K prompts).
"""

import json
from pathlib import Path

import pytest

@pytest.mark.timeout(120)
def test_validate_dataset_stats(tmp_path, subprocess):
    # First generate a tiny dataset using the wrapper (same as above)
    parquet_file = tmp_path / "training_sample.parquet"
    stats_file = tmp_path / "dataset_stats.json"

    gen_cmd = [
        "python",
        "code/data/generate_ground_truth.py",
        "--model",
        "distilgpt2",
        "--levels",
        "INT8",
        "--output",
        str(parquet_file),
        "--sample-size",
        "15",
    ]
    gen_res = subprocess.run(gen_cmd, capture_output=True, text=True)
    assert gen_res.returncode == 0, f"Generation failed: {gen_res.stderr}"
    assert stats_file.is_file(), "Stats JSON not created by generation step"

    # Now run the validator on the produced stats file
    val_cmd = [
        "python",
        "code/cli/validate_dataset_stats.py",
        "--stats",
        str(stats_file),
    ]
    val_res = subprocess.run(val_cmd, capture_output=True, text=True)

    # The validator should exit with code 0 (success)
    assert val_res.returncode == 0, f"Validator failed: {val_res.stderr}"
    # Optional: check printed message contains "passed"
    assert "passed" in val_res.stdout.lower()