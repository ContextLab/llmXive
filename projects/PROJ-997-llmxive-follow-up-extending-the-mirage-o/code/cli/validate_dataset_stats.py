"""
validate_dataset_stats.py

This script implements task **T016** – Validate Dataset Statistics.

It reads the JSON statistics file generated by ``generate_ground_truth.py`` and
checks that at least one quantization level reports a statistically significant
non‑zero KL divergence (p < 0.05).  If the condition is satisfied the script exits
with status 0; otherwise it prints a clear error message and exits with status
1.

The script is deliberately minimal – it does not perform any synthetic
calculations and relies solely on the real statistics produced by the ground‑
truth generation step.
"""

import argparse
import json
import sys
from pathlib import Path

def load_stats(stats_path: Path) -> dict:
    """Load the JSON statistics file."""
    if not stats_path.is_file():
        raise FileNotFoundError(f"Statistics file not found: {stats_path}")
    with open(stats_path, "r", encoding="utf-8") as f:
        return json.load(f)

def validate(stats: dict, alpha: float = 0.05) -> bool:
    """
    Return True if any quantization level has p_value < alpha.
    """
    per_level = stats.get("per_level_statistics", {})
    for level, metrics in per_level.items():
        p = metrics.get("p_value")
        if p is not None and p < alpha:
            return True
    return False

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Validate that the generated dataset exhibits a statistically "
                    "significant non‑zero KL divergence."
    )
    parser.add_argument(
        "--stats",
        type=str,
        required=True,
        help="Path to the dataset statistics JSON file produced by "
             "generate_ground_truth.py.",
    )
    parser.add_argument(
        "--alpha",
        type=float,
        default=0.05,
        help="Significance threshold (default 0.05).",
    )
    args = parser.parse_args()

    stats_path = Path(args.stats).expanduser().resolve()
    try:
        stats = load_stats(stats_path)
    except Exception as exc:
        print(f"Error loading statistics: {exc}", file=sys.stderr)
        sys.exit(1)

    if validate(stats, alpha=args.alpha):
        print("Validation passed: at least one quantization level shows "
              f"p < {args.alpha}.")
        sys.exit(0)
    else:
        print("Validation failed: no quantization level achieved "
              f"statistical significance (p < {args.alpha}).", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()
