"""
T032: Aggregate bound verification results into a final summary report.

This script loads the consistency report generated by T027B (verify_bound_consistency.py),
calculates a global consistency metric, determines a pass/fail verdict based on a threshold,
and writes the final aggregated report to data/processed/aggregated_consistency_report.json.
"""

import json
import logging
import sys
from pathlib import Path
from typing import Dict, Any, Optional

# Add project root to path for imports
project_root = Path(__file__).parent.parent.parent
sys.path.insert(0, str(project_root))

from src.config.logging_config import setup_logger, ensure_log_dir
from src.cli.aggregate_consistency import load_consistency_data, calculate_summary_consistency_metric

# Constants
BOUND_THRESHOLD = 0.90  # Threshold for global consistency metric to pass
INPUT_FILE_PATH = "data/processed/consistency_report.json"
OUTPUT_FILE_PATH = "data/processed/aggregated_consistency_report.json"
LOG_FILE_PATH = "logs/pipeline.log"

def aggregate_results(consistency_data: Dict[str, Any], threshold: float = BOUND_THRESHOLD) -> Dict[str, Any]:
    """
    Aggregate consistency results and determine pass/fail verdict.

    Args:
        consistency_data: The dictionary loaded from consistency_report.json.
        threshold: The minimum global consistency metric required to pass.

    Returns:
        A dictionary containing the aggregated results and verdict.
    """
    # Extract per-level correlations if available, otherwise use the global metric directly
    per_level = consistency_data.get("per_level_correlations", {})
    global_metric = consistency_data.get("global_consistency_metric")
    bound_satisfaction_pct = consistency_data.get("bound_satisfaction_pct")

    # If global metric is missing, calculate it from per-level data
    if global_metric is None and per_level:
        global_metric = calculate_summary_consistency_metric(per_level)

    # Determine verdict
    verdict = "PASS" if global_metric >= threshold else "FAIL"

    aggregated_report = {
        "global_consistency_metric": global_metric,
        "bound_satisfaction_pct": bound_satisfaction_pct,
        "threshold": threshold,
        "verdict": verdict,
        "per_level_correlations": per_level,
        "methodology": "Aggregation of T027B bound verification results across INT4, INT8, FP8 levels.",
        "timestamp": None  # Will be set by caller if needed, or rely on file modification time
    }

    return aggregated_report

def write_report(report: Dict[str, Any], output_path: Path) -> None:
    """Write the aggregated report to a JSON file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)
    logging.info(f"Aggregated report written to {output_path}")

def main() -> int:
    """Main entry point for T032."""
    # Setup logging
    ensure_log_dir(Path(LOG_FILE_PATH).parent)
    logger = setup_logger("aggregate_bound_results", log_file=LOG_FILE_PATH)
    
    input_path = project_root / INPUT_FILE_PATH
    output_path = project_root / OUTPUT_FILE_PATH

    if not input_path.exists():
        logger.error(f"Input file not found: {input_path}. Please run T027B first.")
        return 1

    try:
        logger.info(f"Loading consistency data from {input_path}")
        consistency_data = load_consistency_data(input_path)

        logger.info("Aggregating bound results")
        aggregated_report = aggregate_results(consistency_data, BOUND_THRESHOLD)

        logger.info(f"Global Consistency Metric: {aggregated_report['global_consistency_metric']:.4f}")
        logger.info(f"Verdict: {aggregated_report['verdict']}")

        write_report(aggregated_report, output_path)

        return 0

    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse input JSON: {e}")
        return 1
    except Exception as e:
        logger.exception(f"Unexpected error during aggregation: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
