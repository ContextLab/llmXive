"""
Aggregate consistency results from T031 (bound_verifier) across INT4, INT8, and FP8 levels.

This script loads the consistency data generated by T031 (bound_verifier),
calculates correlation coefficients per quantization level, computes a summary
consistency metric (SC-004), and writes the final report to:
data/processed/consistency_report.json

SC-004: Summary Consistency Metric
- Defined as the mean of the correlation coefficients across all three levels
- Represents the overall consistency of the gap prediction model across quantization levels
"""

import json
import logging
import sys
from pathlib import Path
from typing import Dict, Any, List, Optional

import numpy as np
import pandas as pd

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(project_root))

from src.config.logging_config import setup_logger
from src.config.env_config import load_config

# Configure logging
logger = setup_logger("aggregate_consistency")

# Constants
INPUT_FILE = "data/processed/consistency_report.json"  # Output from T031
OUTPUT_FILE = "data/processed/consistency_report.json"  # Final aggregated report
QUANTIZATION_LEVELS = ["INT4", "INT8", "FP8"]
CORRELATION_THRESHOLD = 0.8  # Expected minimum correlation for consistency


def load_consistency_data(input_path: Path) -> Dict[str, Any]:
    """
    Load the consistency report from T031.
    
    Args:
        input_path: Path to the input JSON file from T031
        
    Returns:
        Dictionary containing consistency data per quantization level
        
    Raises:
        FileNotFoundError: If input file doesn't exist
        json.JSONDecodeError: If file is not valid JSON
    """
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    with open(input_path, 'r') as f:
        data = json.load(f)
    
    logger.info(f"Loaded consistency data from {input_path}")
    return data


def calculate_correlation_per_level(data: Dict[str, Any]) -> Dict[str, float]:
    """
    Calculate correlation coefficient for each quantization level.
    
    Args:
        data: Consistency data dictionary with per-level results
        
    Returns:
        Dictionary mapping quantization level to correlation coefficient
    """
    correlations = {}
    
    for level in QUANTIZATION_LEVELS:
        level_data = data.get(level, {})
        
        # Extract predicted and actual gap values
        predicted_gaps = level_data.get("predicted_gaps", [])
        actual_gaps = level_data.get("actual_gaps", [])
        
        if not predicted_gaps or not actual_gaps:
            logger.warning(f"No data found for {level}, correlation will be NaN")
            correlations[level] = np.nan
            continue
        
        if len(predicted_gaps) != len(actual_gaps):
            logger.warning(f"Length mismatch for {level}: predicted={len(predicted_gaps)}, actual={len(actual_gaps)}")
            correlations[level] = np.nan
            continue
        
        # Calculate Pearson correlation coefficient
        correlation = np.corrcoef(predicted_gaps, actual_gaps)[0, 1]
        correlations[level] = float(correlation)
        
        logger.info(f"Correlation for {level}: {correlation:.4f}")
    
    return correlations


def calculate_summary_consistency_metric(correlations: Dict[str, float]) -> float:
    """
    Calculate the Summary Consistency Metric (SC-004).
    
    SC-004 is defined as the mean of correlation coefficients across all levels.
    Only considers levels with valid (non-NaN) correlations.
    
    Args:
        correlations: Dictionary of correlations per level
        
    Returns:
        Summary consistency metric (mean correlation)
    """
    valid_correlations = [v for v in correlations.values() if not np.isnan(v)]
    
    if not valid_correlations:
        logger.warning("No valid correlations found, returning NaN")
        return float('nan')
    
    summary_metric = np.mean(valid_correlations)
    logger.info(f"Summary Consistency Metric (SC-004): {summary_metric:.4f}")
    
    return float(summary_metric)


def verify_consistency(correlations: Dict[str, float], threshold: float = CORRELATION_THRESHOLD) -> Dict[str, bool]:
    """
    Verify if consistency meets threshold for each level.
    
    Args:
        correlations: Dictionary of correlations per level
        threshold: Minimum acceptable correlation coefficient
        
    Returns:
        Dictionary mapping level to boolean (True if consistent)
    """
    verification = {}
    
    for level, corr in correlations.items():
        if np.isnan(corr):
            verification[level] = False
            logger.warning(f"{level}: Cannot verify - no valid correlation")
        elif corr >= threshold:
            verification[level] = True
            logger.info(f"{level}: Consistent (corr={corr:.4f} >= {threshold})")
        else:
            verification[level] = False
            logger.warning(f"{level}: Inconsistent (corr={corr:.4f} < {threshold})")
    
    return verification


def aggregate_results() -> Dict[str, Any]:
    """
    Main aggregation function.
    
    Returns:
        Complete consistency report with all metrics
    """
    input_path = project_root / INPUT_FILE
    
    # Load data from T031
    try:
        raw_data = load_consistency_data(input_path)
    except (FileNotFoundError, json.JSONDecodeError) as e:
        logger.error(f"Failed to load input data: {e}")
        raise
    
    # Calculate correlations per level
    correlations = calculate_correlation_per_level(raw_data)
    
    # Calculate summary metric (SC-004)
    summary_metric = calculate_summary_consistency_metric(correlations)
    
    # Verify consistency against threshold
    verification = verify_consistency(correlations)
    
    # Build final report
    report = {
        "script": "aggregate_consistency.py",
        "task_id": "T032",
        "description": "Aggregate consistency results across quantization levels",
        "quantization_levels": QUANTIZATION_LEVELS,
        "correlations_per_level": correlations,
        "summary_consistency_metric": summary_metric,
        "consistency_verification": verification,
        "threshold_used": CORRELATION_THRESHOLD,
        "all_levels_consistent": all(verification.values()),
        "metadata": {
            "total_levels": len(QUANTIZATION_LEVELS),
            "levels_with_valid_data": sum(1 for v in correlations.values() if not np.isnan(v)),
            "timestamp": pd.Timestamp.now().isoformat()
        }
    }
    
    # Add per-level detailed stats if available
    for level in QUANTIZATION_LEVELS:
        if level in raw_data:
            report[level] = raw_data[level]
    
    return report


def write_report(report: Dict[str, Any], output_path: Path) -> None:
    """
    Write the aggregated report to JSON file.
    
    Args:
        report: Complete consistency report dictionary
        output_path: Path to write the report
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2, default=str)
    
    logger.info(f"Wrote consistency report to {output_path}")

def main() -> int:
    """
    Main entry point.
    
    Returns:
        Exit code (0 for success, 1 for failure)
    """
    try:
        logger.info("Starting consistency aggregation (T032)...")
        
        # Load config for any environment-specific settings
        config = load_config()
        logger.info(f"Loaded configuration: {list(config.keys())}")
        
        # Run aggregation
        report = aggregate_results()
        
        # Write report
        output_path = project_root / OUTPUT_FILE
        write_report(report, output_path)
        
        # Log summary
        logger.info("=" * 60)
        logger.info("CONSISTENCY AGGREGATION SUMMARY")
        logger.info("=" * 60)
        logger.info(f"Correlations: {report['correlations_per_level']}")
        logger.info(f"Summary Metric (SC-004): {report['summary_consistency_metric']:.4f}")
        logger.info(f"All levels consistent: {report['all_levels_consistent']}")
        logger.info("=" * 60)
        
        # Check if summary metric meets threshold
        if report['summary_consistency_metric'] < CORRELATION_THRESHOLD:
            logger.warning(f"Summary consistency metric ({report['summary_consistency_metric']:.4f}) "
                         f"is below threshold ({CORRELATION_THRESHOLD})")
        
        logger.info("Consistency aggregation completed successfully")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"Required input file not found: {e}")
        logger.error("Ensure T031 (bound_verifier) has been run successfully first")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during aggregation: {e}", exc_info=True)
        return 1


if __name__ == "__main__":
    sys.exit(main())