"""
Data entities for the llmXive follow-up pipeline.

Defines core data structures for training samples and gap prediction results.
"""

from dataclasses import dataclass, field
from typing import List, Optional, Dict, Any
import json


@dataclass
class TrainingSample:
    """
    Represents a single data point for training the gap predictor.

    Attributes:
        input_id: Unique identifier for the input prompt/sample.
        gradient_norms: L2 norm of the gradient vector for the sample.
        local_curvature: Hutchinson's estimator result for local curvature.
        quantization_level: The quantization precision used (e.g., 'INT4', 'INT8', 'FP8').
        quantized_logits: Logits generated by the quantized model.
        full_precision_logits: Logits generated by the full-precision model (ground truth).
        calculated_kl_divergence: The KL divergence between full-precision and quantized logits.
    """
    input_id: str
    gradient_norms: float
    local_curvature: float
    quantization_level: str
    quantized_logits: List[float]
    full_precision_logits: List[float]
    calculated_kl_divergence: float

    def to_dict(self) -> Dict[str, Any]:
        """Convert the sample to a dictionary for serialization."""
        return {
            "input_id": self.input_id,
            "gradient_norms": self.gradient_norms,
            "local_curvature": self.local_curvature,
            "quantization_level": self.quantization_level,
            "quantized_logits": self.quantized_logits,
            "full_precision_logits": self.full_precision_logits,
            "calculated_kl_divergence": self.calculated_kl_divergence
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "TrainingSample":
        """Create a TrainingSample instance from a dictionary."""
        return cls(
            input_id=data["input_id"],
            gradient_norms=data["gradient_norms"],
            local_curvature=data["local_curvature"],
            quantization_level=data["quantization_level"],
            quantized_logits=data["quantized_logits"],
            full_precision_logits=data["full_precision_logits"],
            calculated_kl_divergence=data["calculated_kl_divergence"]
        )


@dataclass
class GapPredictionResult:
    """
    Represents the output of the gap prediction model for a given sample.

    Attributes:
        input_id: The ID of the input sample being predicted.
        predicted_gap: The model's predicted KL divergence (policy gap).
        actual_gap: The ground-truth KL divergence (if available).
        features_used: Dictionary of features used for the prediction.
        is_within_bound: Boolean indicating if |predicted - actual| < threshold.
    """
    input_id: str
    predicted_gap: float
    features_used: Dict[str, float]
    actual_gap: Optional[float] = None
    threshold: float = 0.1

    def __post_init__(self):
        """Calculate bound verification after initialization."""
        if self.actual_gap is not None:
            self.is_within_bound = abs(self.predicted_gap - self.actual_gap) < self.threshold
        else:
            self.is_within_bound = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert the result to a dictionary for serialization."""
        return {
            "input_id": self.input_id,
            "predicted_gap": self.predicted_gap,
            "actual_gap": self.actual_gap,
            "features_used": self.features_used,
            "threshold": self.threshold,
            "is_within_bound": self.is_within_bound
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "GapPredictionResult":
        """Create a GapPredictionResult instance from a dictionary."""
        return cls(
            input_id=data["input_id"],
            predicted_gap=data["predicted_gap"],
            actual_gap=data.get("actual_gap"),
            features_used=data["features_used"],
            threshold=data.get("threshold", 0.1)
        )