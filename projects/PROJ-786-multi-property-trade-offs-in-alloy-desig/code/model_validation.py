import os
import sys
import logging
import argparse
import json
from pathlib import Path
from typing import Dict, Any, List, Optional
import numpy as np
import pandas as pd

from config import get_config
from utils.logging_config import log_info_with_context, log_warning_with_context, log_error_with_context, get_logger

def load_loso_results(metrics_path: str) -> pd.DataFrame:
    """
    Load the LOSO-CV results from the metrics JSON file generated by model_training.py.
    Expects a structure like:
    {
      "loso_results": [
        {"system": "Al-Fe", "r2_bulk": 0.85, "r2_shear": 0.82, "variance_bulk": 0.02, "variance_shear": 0.03},
        ...
      ]
    }
    """
    logger = get_logger(__name__)
    if not os.path.exists(metrics_path):
        log_error_with_context(logger, f"LOSO metrics file not found: {metrics_path}", "load_loso_results")
        raise FileNotFoundError(f"LOSO metrics file not found: {metrics_path}")

    try:
        with open(metrics_path, 'r') as f:
            data = json.load(f)
        
        if 'loso_results' not in data:
            log_error_with_context(logger, "LOSO results key missing in metrics file", "load_loso_results")
            raise KeyError("LOSO results key missing in metrics file")
        
        df = pd.DataFrame(data['loso_results'])
        log_info_with_context(logger, f"Loaded {len(df)} LOSO-CV results", "load_loso_results")
        return df
    except Exception as e:
        log_error_with_context(logger, f"Failed to load LOSO results: {str(e)}", "load_loso_results")
        raise

def calculate_system_coverage(loso_df: pd.DataFrame, total_systems: int) -> Dict[str, Any]:
    """
    Calculate coverage statistics: how many systems were tested, average coverage, etc.
    """
    logger = get_logger(__name__)
    tested_systems = loso_df['system'].nunique()
    coverage_pct = (tested_systems / total_systems * 100) if total_systems > 0 else 0.0
    
    log_info_with_context(logger, f"Coverage: {tested_systems}/{total_systems} systems ({coverage_pct:.1f}%)", "calculate_system_coverage")
    
    return {
        "tested_systems": int(tested_systems),
        "total_systems": int(total_systems),
        "coverage_percentage": float(coverage_pct),
        "untested_systems": int(total_systems - tested_systems)
    }

def identify_unreliable_regions(loso_df: pd.DataFrame, variance_threshold_bulk: float = 0.1, 
                                variance_threshold_shear: float = 0.1) -> Dict[str, Any]:
    """
    Identify regions (systems) where uncertainty (variance) exceeds thresholds.
    Returns a list of unreliable systems and a summary flag.
    """
    logger = get_logger(__name__)
    
    unreliable_bulk = loso_df[loso_df['variance_bulk'] > variance_threshold_bulk]
    unreliable_shear = loso_df[loso_df['variance_shear'] > variance_threshold_shear]
    
    unreliable_systems = set(unreliable_bulk['system'].tolist()) | set(unreliable_shear['system'].tolist())
    
    summary = {
        "unreliable_systems": sorted(list(unreliable_systems)),
        "count": len(unreliable_systems),
        "threshold_bulk": variance_threshold_bulk,
        "threshold_shear": variance_threshold_shear,
        "flag_unreliable": len(unreliable_systems) > 0
    }
    
    if summary['flag_unreliable']:
        log_warning_with_context(logger, f"Found {len(unreliable_systems)} unreliable systems based on variance thresholds", "identify_unreliable_regions")
    else:
        log_info_with_context(logger, "All systems within acceptable uncertainty thresholds", "identify_unreliable_regions")
    
    return summary

def generate_validation_report(loso_df: pd.DataFrame, total_systems: int, 
                               variance_threshold_bulk: float = 0.1, 
                               variance_threshold_shear: float = 0.1) -> Dict[str, Any]:
    """
    Generate the full model validation report linking LOSO-CV results to uncertainty metrics.
    """
    logger = get_logger(__name__)
    log_info_with_context(logger, "Generating model validation report", "generate_validation_report")
    
    # System-level variance statistics
    bulk_stats = {
        "mean": float(loso_df['variance_bulk'].mean()),
        "std": float(loso_df['variance_bulk'].std()),
        "max": float(loso_df['variance_bulk'].max()),
        "min": float(loso_df['variance_bulk'].min())
    }
    
    shear_stats = {
        "mean": float(loso_df['variance_shear'].mean()),
        "std": float(loso_df['variance_shear'].std()),
        "max": float(loso_df['variance_shear'].max()),
        "min": float(loso_df['variance_shear'].min())
    }
    
    # Coverage stats
    coverage_stats = calculate_system_coverage(loso_df, total_systems)
    
    # Unreliable regions
    unreliable_regions = identify_unreliable_regions(loso_df, variance_threshold_bulk, variance_threshold_shear)
    
    # Aggregate performance
    performance_summary = {
        "mean_r2_bulk": float(loso_df['r2_bulk'].mean()),
        "mean_r2_shear": float(loso_df['r2_shear'].mean()),
        "std_r2_bulk": float(loso_df['r2_bulk'].std()),
        "std_r2_shear": float(loso_df['r2_shear'].std())
    }
    
    report = {
        "report_type": "LOSO-CV Model Validation Report",
        "generated_at": pd.Timestamp.now().isoformat(),
        "system_level_variance": {
            "bulk_modulus": bulk_stats,
            "shear_modulus": shear_stats
        },
        "coverage_statistics": coverage_stats,
        "performance_summary": performance_summary,
        "unreliable_regions": unreliable_regions,
        "recommendations": []
    }
    
    # Add recommendations based on findings
    if coverage_stats['coverage_percentage'] < 80:
        report['recommendations'].append("Coverage is below 80%. Consider expanding training data to include more systems.")
    
    if unreliable_regions['flag_unreliable']:
        report['recommendations'].append(
            f"Found {unreliable_regions['count']} systems with high variance. "
            "These regions should be flagged as unreliable in predictions."
        )
    
    if performance_summary['mean_r2_bulk'] < 0.7 or performance_summary['mean_r2_shear'] < 0.7:
        report['recommendations'].append("Mean R² scores are below 0.7. Model performance may need improvement.")
    
    log_info_with_context(logger, f"Validation report generated with {len(report['recommendations'])} recommendations", "generate_validation_report")
    return report

def save_validation_report(report: Dict[str, Any], output_path: str) -> None:
    """
    Save the validation report to a JSON file.
    """
    logger = get_logger(__name__)
    output_dir = os.path.dirname(output_path)
    
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)
    
    try:
        with open(output_path, 'w') as f:
            json.dump(report, f, indent=2)
        log_info_with_context(logger, f"Validation report saved to {output_path}", "save_validation_report")
    except Exception as e:
        log_error_with_context(logger, f"Failed to save validation report: {str(e)}", "save_validation_report")
        raise

def main():
    """
    Main entry point for generating the model validation report.
    """
    logger = get_logger(__name__)
    log_info_with_context(logger, "Starting model validation report generation", "main")
    
    config = get_config()
    
    parser = argparse.ArgumentParser(description="Generate LOSO-CV validation report")
    parser.add_argument("--metrics-path", type=str, default="data/processed/model_metrics.json",
                      help="Path to the model metrics JSON file from model_training.py")
    parser.add_argument("--output-path", type=str, default="data/processed/model_validation_report.json",
                      help="Path to save the validation report")
    parser.add_argument("--variance-threshold-bulk", type=float, default=0.1,
                      help="Variance threshold for Bulk Modulus to flag unreliable regions")
    parser.add_argument("--variance-threshold-shear", type=float, default=0.1,
                      help="Variance threshold for Shear Modulus to flag unreliable regions")
    parser.add_argument("--total-systems", type=int, default=10,
                      help="Total number of binary systems in the dataset (for coverage calculation)")
    
    args = parser.parse_args()
    
    try:
        # Load LOSO results
        loso_df = load_loso_results(args.metrics_path)
        
        # Generate report
        report = generate_validation_report(
            loso_df, 
            args.total_systems,
            args.variance_threshold_bulk,
            args.variance_threshold_shear
        )
        
        # Save report
        save_validation_report(report, args.output_path)
        
        log_info_with_context(logger, "Model validation report generation completed successfully", "main")
        print(f"Validation report saved to: {args.output_path}")
        
    except Exception as e:
        log_error_with_context(logger, f"Failed to generate validation report: {str(e)}", "main")
        sys.exit(1)

if __name__ == "__main__":
    main()