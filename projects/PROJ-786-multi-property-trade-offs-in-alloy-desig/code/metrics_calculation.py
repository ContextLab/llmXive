def load_models_and_frontier(config: Dict) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Load the trained models metadata and the Pareto frontier points.
    Assumes models are saved in config['model_output_path'] and frontier in config['pareto_output_path'].
    """
    model_path = Path(config['model_output_path'])
    frontier_path = Path(config['pareto_output_path'])
    empirical_path = Path(config['processed_data_path'])

    if not model_path.exists():
        raise FileNotFoundError(f"Model output path not found: {model_path}")
    if not frontier_path.exists():
        raise FileNotFoundError(f"Pareto frontier output path not found: {frontier_path}")
    if not empirical_path.exists():
        raise FileNotFoundError(f"Empirical data path not found: {empirical_path}")

    # Load Pareto frontier (generated by T023)
    frontier_df = pd.read_parquet(frontier_path)
    
    # Load empirical data (generated by T015)
    empirical_df = pd.read_csv(empirical_path)

    # Ensure we have the predicted values for the empirical set if they exist
    # If not, we might need to re-predict, but for this metric task we assume
    # the empirical set has the ground truth Bulk/Shear or we use the model predictions
    # on the empirical set as the "observed" performance for comparison.
    # Based on T023, we likely have a 'predicted_bulk' and 'predicted_shear' or similar.
    # Let's standardise column names for the metric calculation.
    
    bulk_col = 'predicted_bulk_modulus'
    shear_col = 'predicted_shear_modulus'
    
    if bulk_col not in frontier_df.columns:
        # Fallback if column names differ, try to find similar
        cols = [c for c in frontier_df.columns if 'bulk' in c.lower()]
        if cols: bulk_col = cols[0]
    
    if shear_col not in frontier_df.columns:
        cols = [c for c in frontier_df.columns if 'shear' in c.lower()]
        if cols: shear_col = cols[0]

    return frontier_df, empirical_df, bulk_col, shear_col


def calculate_rule_of_mixtures(compositions: pd.DataFrame, bulk_vals: Dict, shear_vals: Dict) -> Tuple[np.ndarray, np.ndarray]:
    """
    Calculate the Rule of Mixtures (ROM) baseline for Bulk and Shear moduli.
    
    ROM = sum(element_fraction * element_property)
    
    Args:
        compositions: DataFrame with columns like 'Fe_fraction', 'Ni_fraction', etc.
        bulk_vals: Dict mapping element symbol to its Bulk Modulus (GPa).
        shear_vals: Dict mapping element symbol to its Shear Modulus (GPa).
    
    Returns:
        Tuple of (rom_bulk, rom_shear) numpy arrays.
    """
    rom_bulk = np.zeros(len(compositions))
    rom_shear = np.zeros(len(compositions))
    
    # Identify element fraction columns
    element_cols = [c for c in compositions.columns if c.endswith('_fraction')]
    
    for elem_col in element_cols:
        # Extract element symbol (e.g., 'Fe_fraction' -> 'Fe')
        elem_sym = elem_col.replace('_fraction', '').upper()
        
        if elem_sym in bulk_vals and elem_sym in shear_vals:
            frac = compositions[elem_col].values
            rom_bulk += frac * bulk_vals[elem_sym]
            rom_shear += frac * shear_vals[elem_sym]
    
    return rom_bulk, rom_shear


