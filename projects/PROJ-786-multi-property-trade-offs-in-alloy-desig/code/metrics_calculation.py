def is_dominated(point_a: Tuple[float, float], point_b: Tuple[float, float]) -> bool:
    """
    Check if point_a is dominated by point_b.
    Dominance: b is better or equal in all objectives and strictly better in at least one.
    Assuming maximization for Bulk and Shear (higher is better).
    """
    return (point_b[0] >= point_a[0] and point_b[1] >= point_a[1]) and \
           (point_b[0] > point_a[0] or point_b[1] > point_a[1])


def calculate_dominance_metrics(frontier_df: pd.DataFrame, empirical_df: pd.DataFrame, 
                                bulk_col: str, shear_col: str,
                                rom_bulk: np.ndarray, rom_shear: np.ndarray) -> Dict[str, float]:
    """
    Calculate:
    1. % of test points (empirical) dominated by the frontier.
    2. % of frontier points dominating the empirical set.
    3. Comparison against Rule of Mixtures (ROM).
    """
    metrics = {}
    
    # Convert to numpy arrays for speed
    frontier_points = frontier_df[[bulk_col, shear_col]].values
    empirical_points = empirical_df[[bulk_col, shear_col]].values
    
    # 1. % of empirical points dominated by frontier
    dominated_count = 0
    for emp_pt in empirical_points:
        for fr_pt in frontier_points:
            if is_dominated(emp_pt, fr_pt):
                dominated_count += 1
                break # Found a dominator, move to next empirical point
    
    pct_emp_dominated = (dominated_count / len(empirical_points)) * 100 if len(empirical_points) > 0 else 0.0
    metrics['pct_empirical_dominated_by_frontier'] = pct_emp_dominated
    logger.info(f"Percentage of empirical points dominated by frontier: {pct_emp_dominated:.2f}%")

    # 2. % of frontier points dominating at least one empirical point
    frontier_dominating_count = 0
    for fr_pt in frontier_points:
        dominates_any = False
        for emp_pt in empirical_points:
            if is_dominated(emp_pt, fr_pt):
                dominates_any = True
                break
        if dominates_any:
            frontier_dominating_count += 1
    
    pct_frontier_dominating = (frontier_dominating_count / len(frontier_points)) * 100 if len(frontier_points) > 0 else 0.0
    metrics['pct_frontier_dominating_empirical'] = pct_frontier_dominating
    logger.info(f"Percentage of frontier points dominating empirical set: {pct_frontier_dominating:.2f}%")

    # 3. Rule of Mixtures Comparison
    # Count how many empirical points are better than ROM
    rom_dominated_by_empirical = 0
    rom_dominated_by_frontier = 0
    
    # ROM points for empirical set
    for i in range(len(empirical_points)):
        rom_pt = (rom_bulk[i], rom_shear[i])
        emp_pt = empirical_points[i]
        
        # Is empirical better than ROM? (Empirical dominates ROM)
        if is_dominated(rom_pt, emp_pt):
            rom_dominated_by_empirical += 1
        
        # Check if any frontier point dominates ROM
        for fr_pt in frontier_points:
            if is_dominated(rom_pt, fr_pt):
                rom_dominated_by_frontier += 1
                break # ROM is dominated by at least one frontier point
    
    metrics['pct_empirical_beating_rom'] = (rom_dominated_by_empirical / len(empirical_points)) * 100 if len(empirical_points) > 0 else 0.0
    metrics['pct_rom_dominated_by_frontier'] = (rom_dominated_by_frontier / len(empirical_points)) * 100 if len(empirical_points) > 0 else 0.0
    
    logger.info(f"Percentage of empirical points beating ROM: {metrics['pct_empirical_beating_rom']:.2f}%")
    logger.info(f"Percentage of ROM points dominated by frontier: {metrics['pct_rom_dominated_by_frontier']:.2f}%")

    return metrics


def main():
    """
    Main entry point for metric calculation.
    """
    load_environment()
    args = parse_cli_args(description="Calculate Pareto and Rule of Mixtures metrics")
    config = get_config()
    verify_config(config)

    logger.info("Starting Metric Calculation (T026)")

    try:
        # Load data
        frontier_df, empirical_df, bulk_col, shear_col = load_models_and_frontier(config)
        logger.info(f"Loaded {len(frontier_df)} frontier points and {len(empirical_df)} empirical points.")

        # Prepare ROM
        bulk_props, shear_props = get_element_properties()
        rom_bulk, rom_shear = calculate_rule_of_mixtures(empirical_df, bulk_props, shear_props)

        # Calculate metrics
        metrics = calculate_dominance_metrics(frontier_df, empirical_df, bulk_col, shear_col, rom_bulk, rom_shear)

        # Save metrics
        output_path = Path(config['metrics_output_path'])
        output_path.parent.mkdir(parents=True, exist_ok=True)
        
        with open(output_path, 'w') as f:
            json.dump(metrics, f, indent=2)
        
        logger.info(f"Metrics saved to {output_path}")
        print(json.dumps(metrics, indent=2))

    except Exception as e:
        logger.error(f"Error during metric calculation: {e}", exc_info=True)
        sys.exit(1)


if __name__ == "__main__":
    main()
