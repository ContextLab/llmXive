logger = get_logger(__name__)

@dataclass
class ReconstructionConfig:
    """Configuration for 3D reconstruction parameters."""
    focal_length_x: float = 525.0
    focal_length_y: float = 525.0
    principal_point_x: float = 320.0
    principal_point_y: float = 240.0
    depth_threshold_min: float = 0.1
    depth_threshold_max: float = 20.0
    velocity_smoothing_window: int = 3
    confidence_dropout: float = 0.1

def load_depth_maps(depth_dir: str) -> Tuple[np.ndarray, List[str]]:
    """
    Load depth maps from the processed directory.
    Expects .npy files or a directory of images (if generated as images).
    Returns a stack of depth maps and their corresponding frame IDs.
    """
    depth_path = Path(depth_dir)
    if not depth_path.exists():
        fail_loudly(f"Depth map directory not found: {depth_dir}", "DataLoadError")
    
    # Try loading as a single .npy file first (common output from monodepth2 batch)
    npy_file = depth_path / "depth_maps.npy"
    if npy_file.exists():
        try:
            data = np.load(str(npy_file))
            logger.info(f"Loaded depth maps from {npy_file}: shape {data.shape}")
            return data, [f"frame_{i}" for i in range(data.shape[0])]
        except Exception as e:
            logger.warning(f"Failed to load {npy_file} as single array: {e}")
    
    # Fallback: scan for individual .npy or .png files
    files = sorted(depth_path.glob("*.npy")) + sorted(depth_path.glob("*.png"))
    if not files:
        fail_loudly(f"No depth map files found in {depth_dir}", "DataLoadError")
    
    depth_frames = []
    frame_ids = []
    for f in files:
        if f.suffix == '.npy':
            arr = np.load(str(f))
            depth_frames.append(arr)
        elif f.suffix == '.png':
            # Assuming 16-bit PNG depth encoding
            import cv2
            arr = cv2.imread(str(f), cv2.IMREAD_UNCHANGED).astype(np.float32) / 1000.0
            depth_frames.append(arr)
        frame_ids.append(f.stem)
    
    if len(depth_frames) == 0:
        fail_loudly("No valid depth frames loaded", "DataLoadError")
    
    # Stack into (N, H, W)
    return np.stack(depth_frames, axis=0), frame_ids

def load_camera_poses(pose_dir: str) -> np.ndarray:
    """
    Load camera poses (extrinsics) and intrinsics.
    Expected format: pose_dir/poses.npy (N, 4, 4) or poses.json
    """
    pose_path = Path(pose_dir)
    npy_file = pose_path / "camera_poses.npy"
    if npy_file.exists():
        return np.load(str(npy_file))
    
    json_file = pose_path / "camera_poses.json"
    if json_file.exists():
        with open(json_file, 'r') as f:
            poses = json.load(f)
        return np.array(poses)
    
    fail_loudly(f"Camera poses not found in {pose_dir}", "DataLoadError")

def depth_to_3d_point(depth_val: float, u: int, v: int, config: ReconstructionConfig) -> Optional[np.ndarray]:
    """
    Convert a single depth pixel (u, v, depth) to 3D camera coordinates (X, Y, Z).
    Returns None if depth is out of valid range.
    """
    if depth_val < config.depth_threshold_min or depth_val > config.depth_threshold_max:
        return None
    
    # Pinhole camera model
    X = (u - config.principal_point_x) * depth_val / config.focal_length_x
    Y = (v - config.principal_point_y) * depth_val / config.focal_length_y
    Z = depth_val
    
    return np.array([X, Y, Z])

def estimate_object_centroids(depth_map: np.ndarray, mask: Optional[np.ndarray] = None) -> Tuple[np.ndarray, float]:
    """
    Estimate the 3D centroid of the primary object in the depth map.
    Uses a simple threshold-based segmentation if no mask is provided.
    Returns (centroid_3d, confidence_score).
    """
    H, W = depth_map.shape
    
    # Simple heuristic: find the largest connected component of valid depth
    # or just the median of valid depths if no clear object segmentation exists.
    valid_mask = (depth_map > 0.1) & (depth_map < 20.0)
    
    if mask is not None:
        valid_mask = valid_mask & (mask > 0)
    
    if np.sum(valid_mask) < 10:
        return np.zeros(3), 0.0
    
    # Get coordinates
    ys, xs = np.where(valid_mask)
    depths = depth_map[ys, xs]
    
    # Convert to 3D points
    points_3d = []
    for u, v, d in zip(xs, ys, depths):
        pt = depth_to_3d_point(d, u, v, ReconstructionConfig())
        if pt is not None:
            points_3d.append(pt)
    
    if not points_3d:
        return np.zeros(3), 0.0
    
    points_3d = np.array(points_3d)
    centroid = np.mean(points_3d, axis=0)
    
    # Confidence based on number of points and depth variance
    confidence = min(1.0, len(points_3d) / 1000.0)
    if np.std(depths) > 5.0:
        confidence *= 0.5 # Lower confidence if depth is noisy
    
    return centroid, confidence

def compute_velocities(positions: List[np.ndarray], time_step: float = 1.0/30.0) -> List[np.ndarray]:
    """
    Compute velocities from a list of 3D positions using central differences.
    """
    velocities = []
    n = len(positions)
    for i in range(n):
        if n < 2:
            velocities.append(np.zeros(3))
            continue
        
        if i == 0:
            vel = (positions[1] - positions[0]) / time_step
        elif i == n - 1:
            vel = (positions[i] - positions[i-1]) / time_step
        else:
            vel = (positions[i+1] - positions[i-1]) / (2 * time_step)
        
        velocities.append(vel)
    
    return velocities

def reconstruct_states(
    depth_dir: str,
    pose_dir: Optional[str] = None,
    config: Optional[ReconstructionConfig] = None
) -> List[EstimatedState3D]:
    """
    Main entry point for 3D state reconstruction.
    
    Args:
        depth_dir: Path to directory containing depth maps.
        pose_dir: Path to camera poses (optional, defaults to static camera).
        config: Reconstruction configuration.
    
    Returns:
        List of EstimatedState3D objects.
    """
    if config is None:
        config = ReconstructionConfig()
    
    logger.info(f"Starting 3D reconstruction from {depth_dir}")
    start_time = time.time()
    
    # Load data
    depth_maps, frame_ids = load_depth_maps(depth_dir)
    logger.info(f"Loaded {len(frame_ids)} depth frames")
    
    # If no poses provided, assume static camera at origin
    if pose_dir:
        poses = load_camera_poses(pose_dir)
    else:
        logger.warning("No camera poses provided. Assuming static camera at origin.")
        poses = np.tile(np.eye(4), (len(frame_ids), 1, 1))
    
    # Process frames
    states = []
    positions = []
    
    for i, frame_id in enumerate(frame_ids):
        depth_map = depth_maps[i]
        
        # Estimate object centroid in camera coordinates
        centroid_cam, conf = estimate_object_centroids(depth_map)
        
        # Transform to world coordinates if poses are available
        if np.linalg.norm(poses[i] - np.eye(4)) > 1e-6:
            # Apply extrinsic: P_world = R * P_cam + T
            R = poses[i][:3, :3]
            T = poses[i][:3, 3]
            centroid_world = R @ centroid_cam + T
        else:
            centroid_world = centroid_cam
        
        positions.append(centroid_world)
        
        state = EstimatedState3D(
            id=f"{frame_id}_state",
            position=centroid_world.tolist(),
            confidence_score=conf
        )
        states.append(state)
    
    # Compute velocities
    time_step = 1.0 / 30.0 # Assuming 30 FPS
    velocities = compute_velocities(positions, time_step)
    
    # Update states with velocities
    for i, state in enumerate(states):
        state.velocity = velocities[i].tolist()
        # Update orientation if we had multiple points (simplified here to identity or velocity direction)
        state.orientation = [0.0, 0.0, 0.0] # Placeholder for roll/pitch/yaw if needed
        
        # Re-normalize confidence if velocity is extreme (physics implausible)
        vel_mag = np.linalg.norm(velocities[i])
        if vel_mag > 10.0: # > 10 m/s is likely error
            state.confidence_score *= 0.1
    
    elapsed = time.time() - start_time
    logger.info(f"Reconstruction complete. Processed {len(states)} states in {elapsed:.2f}s")
    
    return states

def save_reconstructed_states(states: List[EstimatedState3D], output_path: str):
    """
    Save reconstructed states to a JSON file.
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    data = [asdict(s) for s in states]
    with open(output_path, 'w') as f:
        json.dump(data, f, indent=2)
    
    logger.info(f"Saved {len(states)} states to {output_path}")

def main():
    """
    CLI entry point for T021.
    """
    # Default paths relative to project root
    depth_dir = "data/processed/depth_maps"
    pose_dir = "data/processed/camera_poses" # Optional
    output_file = "data/processed/reconstructed_states.json"
    
