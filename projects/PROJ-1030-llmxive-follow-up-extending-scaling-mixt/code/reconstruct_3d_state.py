"""
T021: Implement 3D state reconstruction logic to extract positions/velocities from depth maps.

This module consumes depth maps generated by `generate_labels.py` (monodepth2) 
and camera poses to reconstruct 3D trajectories of objects in the scene.
It outputs EstimatedState3D data structures containing positions, velocities, and confidence scores.

Inputs:
    - data/processed/depth_maps.npy: Depth maps (N, H, W) or list of paths
    - data/processed/camera_poses.npy: Camera intrinsics/extrinsics per frame
    - data/processed/manifest.json: Video clip metadata

Outputs:
    - data/processed/reconstructed_states.json: List of EstimatedState3D records
"""
