"""
Separate low-confidence / failed samples from the labeling pipeline.

This module processes the raw labels generated from the 3D reconstruction and
physics simulation pipeline. It separates samples with reconstruction confidence
< 0.9 or simulation failures into a null_labels.csv file, and merges the remaining
valid rows into the final labels.csv. It also creates an excluded_samples.log
file to ensure reproducibility and hashing.

Artifact Outputs:
- data/processed/null_labels.csv: Rows with confidence < 0.9 or simulation failures
- data/processed/labels.csv: Final valid labels (non-null rows)
- data/processed/excluded_samples.log: Log of excluded samples (or empty if none)
"""
import os
import sys
import json
import csv
import logging
from pathlib import Path
from typing import List, Dict, Any, Tuple, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
    handlers=[
        logging.FileHandler('data/processed/separate_null_samples.log'),
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)

# Constants
CONFIDENCE_THRESHOLD = 0.9
RAW_LABELS_PATH = Path('data/processed/raw_labels.csv')
NULL_LABELS_PATH = Path('data/processed/null_labels.csv')
FINAL_LABELS_PATH = Path('data/processed/labels.csv')
EXCLUDED_LOG_PATH = Path('data/processed/excluded_samples.log')


def load_raw_labels() -> List[Dict[str, Any]]:
    """
    Load the raw labels from the CSV file generated by the labeling pipeline.
    
    Returns:
        List of dictionaries containing label data.
        
    Raises:
        FileNotFoundError: If raw_labels.csv does not exist.
        ValueError: If the CSV format is invalid.
    """
    if not RAW_LABELS_PATH.exists():
        raise FileNotFoundError(f"Raw labels file not found: {RAW_LABELS_PATH}")
    
    labels = []
    with open(RAW_LABELS_PATH, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        # Verify required columns exist
        if not {'clip_id', 'label', 'confidence_score'}.issubset(set(reader.fieldnames or [])):
            raise ValueError(f"Invalid CSV format. Expected columns: clip_id, label, confidence_score. Found: {reader.fieldnames}")
        
        for row in reader:
            try:
                labels.append({
                    'clip_id': row['clip_id'],
                    'label': row['label'],
                    'confidence_score': float(row['confidence_score']),
                    'reason': row.get('reason', None)  # Optional simulation failure reason
                })
            except (ValueError, KeyError) as e:
                logger.warning(f"Skipping malformed row: {row}. Error: {e}")
                continue
    
    logger.info(f"Loaded {len(labels)} raw labels from {RAW_LABELS_PATH}")
    return labels


def process_labels_and_exclusions(
    labels: List[Dict[str, Any]]
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """
    Separate labels into valid and null (excluded) based on confidence threshold.
    
    Args:
        labels: List of raw label dictionaries.
        
    Returns:
        Tuple of (valid_labels, null_labels).
    """
    valid_labels = []
    null_labels = []
    
    for label in labels:
        confidence = label.get('confidence_score', 0.0)
        reason = label.get('reason')
        
        # Determine if sample should be excluded
        is_null = False
        exclusion_reason = None
        
        if confidence < CONFIDENCE_THRESHOLD:
            is_null = True
            exclusion_reason = f"Low confidence: {confidence:.4f} < {CONFIDENCE_THRESHOLD}"
        elif reason is not None:
            # Simulation failure
            is_null = True
            exclusion_reason = f"Simulation failure: {reason}"
        
        if is_null:
            null_labels.append({
                'clip_id': label['clip_id'],
                'reason': exclusion_reason,
                'confidence_score': confidence
            })
            logger.debug(f"Excluding clip {label['clip_id']}: {exclusion_reason}")
        else:
            valid_labels.append(label)
    
    logger.info(f"Processed {len(labels)} labels: {len(valid_labels)} valid, {len(null_labels)} excluded")
    return valid_labels, null_labels


def save_null_labels(null_labels: List[Dict[str, Any]]) -> None:
    """
    Save null labels to the null_labels.csv file.
    
    Args:
        null_labels: List of null label dictionaries.
    """
    with open(NULL_LABELS_PATH, 'w', newline='', encoding='utf-8') as f:
        fieldnames = ['clip_id', 'reason', 'confidence_score']
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(null_labels)
    
    logger.info(f"Saved {len(null_labels)} null labels to {NULL_LABELS_PATH}")


def save_final_labels(valid_labels: List[Dict[str, Any]]) -> None:
    """
    Save valid labels to the final labels.csv file.
    
    Args:
        valid_labels: List of valid label dictionaries.
    """
    with open(FINAL_LABELS_PATH, 'w', newline='', encoding='utf-8') as f:
        fieldnames = ['clip_id', 'label', 'confidence_score']
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(valid_labels)
    
    logger.info(f"Saved {len(valid_labels)} valid labels to {FINAL_LABELS_PATH}")


def save_excluded_log(null_labels: List[Dict[str, Any]]) -> None:
    """
    Save the excluded samples log to ensure reproducibility.
    If no samples are excluded, creates an empty file.
    
    Args:
        null_labels: List of excluded label dictionaries.
    """
    with open(EXCLUDED_LOG_PATH, 'w', encoding='utf-8') as f:
        if not null_labels:
            # Create empty file as per spec
            f.write("")
        else:
            for entry in null_labels:
                f.write(f"{entry['clip_id']}|{entry['reason']}|{entry['confidence_score']}\n")
    
    logger.info(f"Saved excluded samples log to {EXCLUDED_LOG_PATH}")


def main() -> None:
    """
    Main entry point for the separate_null_samples script.
    
    This function orchestrates the loading of raw labels, separation of null samples,
    and saving of all output artifacts.
    """
    logger.info("Starting separate_null_samples process")
    
    try:
        # 1. Load raw labels
        raw_labels = load_raw_labels()
        
        if not raw_labels:
            logger.warning("No raw labels found. Creating empty output files.")
            save_null_labels([])
            save_final_labels([])
            save_excluded_log([])
            return
        
        # 2. Process and separate labels
        valid_labels, null_labels = process_labels_and_exclusions(raw_labels)
        
        # 3. Save artifacts
        save_null_labels(null_labels)
        save_final_labels(valid_labels)
        save_excluded_log(null_labels)
        
        logger.info("separate_null_samples process completed successfully")
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during processing: {e}", exc_info=True)
        raise


if __name__ == "__main__":
    main()