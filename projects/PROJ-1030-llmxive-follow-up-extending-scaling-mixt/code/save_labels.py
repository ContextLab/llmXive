logger = get_logger(__name__)

def load_simulation_results(results_path: str) -> List[Dict[str, Any]]:
    """
    Load simulation results from the JSON file generated by simulate_physics.py.
    Expected structure: list of dicts with keys like 'clip_id', 'gravity_valid', 
    'collision_valid', 'energy_valid', 'confidence_score', etc.
    """
    if not os.path.exists(results_path):
        fail_loudly(f"Simulation results file not found: {results_path}")
    
    logger.info(f"Loading simulation results from {results_path}")
    with open(results_path, 'r') as f:
        data = json.load(f)
    
    if not isinstance(data, list):
        fail_loudly(f"Expected simulation results to be a list, got {type(data)}")
    
    logger.info(f"Loaded {len(data)} simulation results")
    return data

def load_labels_temporary(labels_path: str) -> pd.DataFrame:
    """
    Load the temporary labels CSV generated by the labeling pipeline (T024).
    This CSV contains 'valid', 'invalid', or 'null' labels.
    """
    if not os.path.exists(labels_path):
        fail_loudly(f"Temporary labels file not found: {labels_path}")
    
    logger.info(f"Loading temporary labels from {labels_path}")
    df = pd.read_csv(labels_path)
    
    required_cols = ['clip_id', 'label']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        fail_loudly(f"Missing required columns in labels file: {missing_cols}")
    
    logger.info(f"Loaded {len(df)} labels with columns: {list(df.columns)}")
    return df

def load_metadata_temporary(metadata_path: str) -> Dict[str, Any]:
    """
    Load temporary metadata if it exists, otherwise start with an empty dict.
    """
    if os.path.exists(metadata_path):
        logger.info(f"Loading existing metadata from {metadata_path}")
        with open(metadata_path, 'r') as f:
            return json.load(f)
    return {}

def save_labels_and_metadata(
    labels_df: pd.DataFrame,
    metadata: Dict[str, Any],
    output_labels_path: str,
    output_metadata_path: str
) -> None:
    """
    Save the final labels DataFrame to CSV and metadata to JSON.
    
    Args:
        labels_df: DataFrame with 'clip_id', 'label', and optional 'confidence_score'
        metadata: Dictionary of metadata to save
        output_labels_path: Path for the final labels CSV
        output_metadata_path: Path for the final metadata JSON
    """
    # Ensure output directory exists
    os.makedirs(os.path.dirname(output_labels_path), exist_ok=True)
    os.makedirs(os.path.dirname(output_metadata_path), exist_ok=True)

    # Save labels
    logger.info(f"Saving {len(labels_df)} labels to {output_labels_path}")
    labels_df.to_csv(output_labels_path, index=False)
    
    # Save metadata
    logger.info(f"Saving metadata to {output_metadata_path}")
    with open(output_metadata_path, 'w') as f:
        json.dump(metadata, f, indent=2)

    logger.info("Successfully saved labels and metadata")

def main():
    """
    Main entry point for T025: Save valid labels to data/processed/labels.csv 
    and metadata to data/processed/metadata.json.
    
    This task assumes that T024 has already run and produced:
    - data/processed/labels_temp.csv (or similar) containing labels including 'null'
    - data/processed/simulation_results.json containing simulation details
    """
    start_time = time.time()
    logger.info("Starting T025: Save labels and metadata")
    
    config = get_config()
    
    # Define paths
    temp_labels_path = os.path.join(config.get('data_dir', 'data'), 'processed', 'labels_temp.csv')
    sim_results_path = os.path.join(config.get('data_dir', 'data'), 'processed', 'simulation_results.json')
    output_labels_path = os.path.join(config.get('data_dir', 'data'), 'processed', 'labels.csv')
    output_metadata_path = os.path.join(config.get('data_dir', 'data'), 'processed', 'metadata.json')
    
    # Load data
    labels_df = load_labels_temporary(temp_labels_path)
    sim_results = load_simulation_results(sim_results_path)
    
    # Create a mapping from clip_id to simulation details for merging
    sim_map = {item['clip_id']: item for item in sim_results}
    
    # Merge simulation details (confidence scores) into labels DataFrame
    # We assume sim_results has 'clip_id' and 'confidence_score'
    if 'confidence_score' in sim_results[0] if sim_results else False:
        logger.info("Merging confidence scores from simulation results")
        labels_df = labels_df.merge(
            pd.DataFrame(sim_results)[['clip_id', 'confidence_score']],
            on='clip_id',
            how='left'
        )
    else:
        # If confidence_score is not in sim_results, add a default column
        logger.warning("confidence_score not found in simulation results, adding default")
        labels_df['confidence_score'] = 0.0
    
    # Prepare metadata
    metadata = {
        'generated_at': time.strftime('%Y-%m-%d %H:%M:%S'),
        'total_samples': len(labels_df),
        'label_distribution': labels_df['label'].value_counts().to_dict(),
        'average_confidence': float(labels_df['confidence_score'].mean()) if 'confidence_score' in labels_df.columns else None,
        'null_count': int((labels_df['label'] == 'null').sum()),
        'valid_count': int((labels_df['label'] == 'valid').sum()),
        'invalid_count': int((labels_df['label'] == 'invalid').sum()),
    }
    
    logger.info(f"Label distribution: {metadata['label_distribution']}")
    logger.info(f"Average confidence score: {metadata['average_confidence']}")
    
    # Save outputs
    save_labels_and_metadata(
        labels_df,
        metadata,
        output_labels_path,
        output_metadata_path
    )
    
    elapsed = time.time() - start_time
    logger.info(f"T025 completed in {elapsed:.2f} seconds")
    print(f"Successfully saved labels to {output_labels_path}")
    print(f"Successfully saved metadata to {output_metadata_path}")

if __name__ == '__main__':
    main()