"""
save_labels.py

Implements T025: Save valid labels (including "null" rows) to data/processed/labels.csv
and metadata (confidence scores) to data/processed/metadata.json.

This script expects the temporary outputs from the labeling pipeline (T024) to exist:
- data/processed/labels_temporary.csv: The raw labels with confidence scores and perturbation types.
- data/processed/simulation_results.json: The raw simulation results (optional, for metadata enrichment).
- data/processed/excluded_samples.csv: The log of excluded samples (generated by T024).

It merges these into the final artifacts:
- data/processed/labels.csv: Final CSV with columns [clip_id, label, reason, confidence_score, perturbation_type].
- data/processed/metadata.json: JSON containing global statistics and confidence score distributions.
- data/processed/excluded_samples.log: The final excluded samples log (renamed from .csv if needed, or kept as .csv).
"""

import os
import sys
import json
import logging
import time
import pandas as pd
from pathlib import Path

# Add project root to path to allow relative imports if run as script
PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from utils.logging_config import get_logger

logger = get_logger(__name__)

# Constants
DATA_PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
TEMP_LABELS_PATH = DATA_PROCESSED_DIR / "labels_temporary.csv"
TEMP_SIM_RESULTS_PATH = DATA_PROCESSED_DIR / "simulation_results.json"
TEMP_EXCLUDED_PATH = DATA_PROCESSED_DIR / "excluded_samples.csv"

OUTPUT_LABELS_PATH = DATA_PROCESSED_DIR / "labels.csv"
OUTPUT_METADATA_PATH = DATA_PROCESSED_DIR / "metadata.json"
OUTPUT_EXCLUDED_LOG_PATH = DATA_PROCESSED_DIR / "excluded_samples.log"


def load_simulation_results() -> dict:
    """Load simulation results if available."""
    if not TEMP_SIM_RESULTS_PATH.exists():
        logger.warning(f"Simulation results not found at {TEMP_SIM_RESULTS_PATH}. Skipping metadata enrichment from sim results.")
        return {}
    
    try:
        with open(TEMP_SIM_RESULTS_PATH, 'r') as f:
            return json.load(f)
    except Exception as e:
        logger.error(f"Failed to load simulation results: {e}")
        return {}


def load_labels_temporary() -> pd.DataFrame:
    """Load the temporary labels dataframe."""
    if not TEMP_LABELS_PATH.exists():
        raise FileNotFoundError(f"Temporary labels file not found at {TEMP_LABELS_PATH}. "
                                "Please ensure T024 (labeling step) has run successfully.")
    
    try:
        df = pd.read_csv(TEMP_LABELS_PATH)
        # Ensure required columns exist
        required_cols = ['clip_id', 'label', 'reason', 'confidence_score', 'perturbation_type']
        missing_cols = [c for c in required_cols if c not in df.columns]
        if missing_cols:
            raise ValueError(f"Temporary labels file missing required columns: {missing_cols}")
        return df
    except Exception as e:
        logger.error(f"Failed to load temporary labels: {e}")
        raise


def load_metadata_temporary() -> dict:
    """Load any temporary metadata if it exists."""
    # This is a placeholder if T024 produces a separate metadata file.
    # For now, we generate metadata from the labels themselves.
    return {}


def save_labels_and_metadata(labels_df: pd.DataFrame, sim_results: dict):
    """
    Save the final labels.csv and metadata.json.
    
    Args:
        labels_df: The dataframe containing all labels (including 'null').
        sim_results: Dictionary of simulation results for metadata enrichment.
    """
    # 1. Save labels.csv
    # Ensure columns are in the correct order
    column_order = ['clip_id', 'label', 'reason', 'confidence_score', 'perturbation_type']
    # Reindex to ensure order, filling missing with NaN if any (though we validated earlier)
    final_df = labels_df[column_order]
    
    logger.info(f"Saving {len(final_df)} labels to {OUTPUT_LABELS_PATH}")
    final_df.to_csv(OUTPUT_LABELS_PATH, index=False)
    logger.info(f"Successfully saved {OUTPUT_LABELS_PATH}")

    # 2. Generate Metadata
    # Calculate statistics on confidence scores and label distribution
    total_samples = len(final_df)
    valid_count = len(final_df[final_df['label'] == 'valid'])
    invalid_count = len(final_df[final_df['label'] == 'invalid'])
    null_count = len(final_df[final_df['label'] == 'null'])
    
    conf_scores = final_df['confidence_score'].dropna()
    conf_stats = {}
    if len(conf_scores) > 0:
        conf_stats = {
            "mean": float(conf_scores.mean()),
            "std": float(conf_scores.std()),
            "min": float(conf_scores.min()),
            "max": float(conf_scores.max())
        }
    else:
        conf_stats = {"mean": None, "std": None, "min": None, "max": None}

    label_distribution = {
        "valid": int(valid_count),
        "invalid": int(invalid_count),
        "null": int(null_count)
    }

    perturbation_distribution = final_df['perturbation_type'].value_counts().to_dict()
    # Ensure integer keys are converted to strings for JSON safety if needed, 
    # but pandas usually handles this well. We'll convert explicitly.
    perturbation_distribution = {str(k): int(v) for k, v in perturbation_distribution.items()}

    metadata = {
        "generated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "total_samples": total_samples,
        "label_distribution": label_distribution,
        "confidence_score_stats": conf_stats,
        "perturbation_type_distribution": perturbation_distribution,
        "excluded_samples_path": str(OUTPUT_EXCLUDED_LOG_PATH.relative_to(PROJECT_ROOT))
    }

    # Enrich with simulation results if available (e.g., total simulation time)
    if sim_results and "total_simulation_time" in sim_results:
        metadata["total_simulation_time_seconds"] = sim_results["total_simulation_time"]

    logger.info(f"Saving metadata to {OUTPUT_METADATA_PATH}")
    with open(OUTPUT_METADATA_PATH, 'w') as f:
        json.dump(metadata, f, indent=2)
    logger.info(f"Successfully saved {OUTPUT_METADATA_PATH}")

    # 3. Handle Excluded Samples Log
    # T024 should have created excluded_samples.csv. We rename/copy it to .log 
    # or ensure it exists as an empty file if T024 didn't create it but we need it.
    if TEMP_EXCLUDED_PATH.exists():
        # Move or copy to .log extension as per requirement
        logger.info(f"Moving {TEMP_EXCLUDED_PATH} to {OUTPUT_EXCLUDED_LOG_PATH}")
        TEMP_EXCLUDED_PATH.rename(OUTPUT_EXCLUDED_LOG_PATH)
    else:
        # Create an empty log file if T024 failed to create it (should not happen if T024 ran)
        logger.warning(f"Excluded samples file not found at {TEMP_EXCLUDED_PATH}. Creating empty log.")
        with open(OUTPUT_EXCLUDED_LOG_PATH, 'w') as f:
            f.write("clip_id,reason,confidence_score\n") # Header only

    logger.info(f"Successfully finalized {OUTPUT_EXCLUDED_LOG_PATH}")


def main():
    """Main entry point for T025."""
    logger.info("Starting T025: Save labels and metadata")
    
    if not DATA_PROCESSED_DIR.exists():
        DATA_PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
        logger.info(f"Created directory {DATA_PROCESSED_DIR}")

    try:
        # Load inputs
        sim_results = load_simulation_results()
        labels_df = load_labels_temporary()
        # metadata_temp = load_metadata_temporary() # Not strictly needed if we generate from DF

        # Validate data integrity
        if labels_df.empty:
            logger.warning("Labels dataframe is empty. Proceeding to save empty file.")

        # Save outputs
        save_labels_and_metadata(labels_df, sim_results)

        logger.info("T025 completed successfully.")
        return 0

    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        logger.error("T025 failed. Ensure T024 has completed and generated temporary artifacts.")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during T025: {e}", exc_info=True)
        return 1


if __name__ == "__main__":
    sys.exit(main())
