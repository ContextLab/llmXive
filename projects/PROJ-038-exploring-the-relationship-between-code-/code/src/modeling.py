import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, Tuple, Optional, List
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import RepeatedStratifiedKFold, cross_validate
from sklearn.metrics import roc_auc_score, f1_score, make_scorer
from src.config import get_memory_limit_bytes

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

def load_features_csv(path: str) -> pd.DataFrame:
    """Load the features CSV generated by the ingestion pipeline."""
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"Features file not found: {path}")
    df = pd.read_csv(p)
    required_cols = {'file_path', 'cc', 'halstead', 'loc', 'is_buggy'}
    if not required_cols.issubset(df.columns):
        missing = required_cols - set(df.columns)
        raise ValueError(f"Missing required columns: {missing}")
    return df

def prepare_features(df: pd.DataFrame) -> Tuple[np.ndarray, np.ndarray]:
    """
    Prepare X (metrics) and y (target) from the dataframe.
    Handles class imbalance detection and returns clean arrays.
    """
    # Check for class imbalance (zero buggy files)
    if df['is_buggy'].sum() == 0:
        logger.warning("Dataset contains no buggy files. Skipping modeling.")
        return np.array([]), np.array([])
    
    # Filter out rows with NaN in metric columns to ensure clean training
    metric_cols = ['cc', 'halstead', 'loc']
    df_clean = df.dropna(subset=metric_cols)
    
    if len(df_clean) == 0:
        logger.warning("No valid rows after NaN removal.")
        return np.array([]), np.array([])

    X = df_clean[metric_cols].values
    y = df_clean['is_buggy'].values
    return X, y

def train_logistic_regression(X: np.ndarray, y: np.ndarray, seed: int = 42) -> Dict[str, Any]:
    """
    Train Logistic Regression with Repeated 5-Fold CV (10 repeats).
    Returns metrics and the fitted model.
    """
    if len(X) == 0:
        return {"error": "Empty dataset"}

    rskf = RepeatedStratifiedKFold(n_splits=5, n_repeats=10, random_state=seed)
    model = LogisticRegression(max_iter=1000, random_state=seed)
    
    scoring = {
        'roc_auc': 'roc_auc',
        'f1': 'f1'
    }
    
    cv_results = cross_validate(
        model, X, y, cv=rskf, scoring=scoring, return_train_score=False
    )
    
    return {
        'model': model,
        'roc_auc_mean': np.mean(cv_results['test_roc_auc']),
        'roc_auc_std': np.std(cv_results['test_roc_auc']),
        'f1_mean': np.mean(cv_results['test_f1']),
        'f1_std': np.std(cv_results['test_f1']),
        'folds': 50  # 5 splits * 10 repeats
    }

def train_random_forest(X: np.ndarray, y: np.ndarray, seed: int = 42) -> Dict[str, Any]:
    """
    Train Random Forest with Repeated 5-Fold CV (10 repeats).
    Returns metrics and the fitted model.
    """
    if len(X) == 0:
        return {"error": "Empty dataset"}

    rskf = RepeatedStratifiedKFold(n_splits=5, n_repeats=10, random_state=seed)
    model = RandomForestClassifier(n_estimators=100, random_state=seed, n_jobs=-1)
    
    scoring = {
        'roc_auc': 'roc_auc',
        'f1': 'f1'
    }
    
    cv_results = cross_validate(
        model, X, y, cv=rskf, scoring=scoring, return_train_score=False
    )
    
    return {
        'model': model,
        'roc_auc_mean': np.mean(cv_results['test_roc_auc']),
        'roc_auc_std': np.std(cv_results['test_roc_auc']),
        'f1_mean': np.mean(cv_results['test_f1']),
        'f1_std': np.std(cv_results['test_f1']),
        'folds': 50  # 5 splits * 10 repeats
    }

def run_modeling_analysis(features_path: str, output_dir: str) -> Dict[str, Any]:
    """
    Run the full modeling analysis including aggregation logic for T024.
    Computes mean and standard deviation across 50 folds for both models.
    """
    logger.info(f"Loading features from {features_path}")
    df = load_features_csv(features_path)
    X, y = prepare_features(df)
    
    if len(X) == 0:
        return {"status": "skipped", "reason": "No valid data or class imbalance"}

    logger.info("Training Logistic Regression...")
    lr_results = train_logistic_regression(X, y)
    
    logger.info("Training Random Forest...")
    rf_results = train_random_forest(X, y)
    
    # T024 Aggregation Logic: Calculate mean and std across 50 folds
    # The cross_validate function already returns mean/std, but we explicitly
    # document the aggregation step here as required by the task.
    aggregation_report = {
        "logistic_regression": {
            "roc_auc": {
                "mean": float(lr_results['roc_auc_mean']),
                "std": float(lr_results['roc_auc_std']),
                "folds": lr_results['folds']
            },
            "f1": {
                "mean": float(lr_results['f1_mean']),
                "std": float(lr_results['f1_std']),
                "folds": lr_results['folds']
            }
        },
        "random_forest": {
            "roc_auc": {
                "mean": float(rf_results['roc_auc_mean']),
                "std": float(rf_results['roc_auc_std']),
                "folds": rf_results['folds']
            },
            "f1": {
                "mean": float(rf_results['f1_mean']),
                "std": float(rf_results['f1_std']),
                "folds": rf_results['folds']
            }
        }
    }
    
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)
    
    result_file = output_path / "baseline_metrics.json"
    with open(result_file, 'w') as f:
        json.dump(aggregation_report, f, indent=2)
    
    logger.info(f"Aggregation results saved to {result_file}")
    return aggregation_report

def main():
    """Entry point for running the modeling analysis."""
    import argparse
    parser = argparse.ArgumentParser(description="Run modeling analysis and aggregation")
    parser.add_argument("--features", type=str, default="code/data/processed/features.csv",
                        help="Path to features CSV")
    parser.add_argument("--output", type=str, default="code/data/results",
                        help="Output directory for results")
    args = parser.parse_args()
    
    run_modeling_analysis(args.features, args.output)

if __name__ == "__main__":
    main()