"""
Script to generate the final features.csv artifact for User Story 1.

This script orchestrates the aggregation of metrics (LOC, CC, Halstead)
and bug labels (is_buggy) into a single CSV file.

It relies on the following pre-computed artifacts (generated by previous tasks):
1. code/data/processed/loc_metrics.csv (from T014)
2. code/data/processed/cc_metrics.csv (from T014b)
3. code/data/processed/halstead_metrics.csv (from T014c)
4. code/data/processed/bug_labels.csv (from T015)

It also performs validation to ensure no NaN values exist in numeric columns
as per T018 requirements.
"""
import os
import sys
import logging
import pandas as pd
from pathlib import Path
from typing import List, Optional

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.config import get_memory_limit_bytes
from src.validate_metrics import validate_no_nan_in_metrics

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Define paths relative to project root
PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
OUTPUT_FILE = PROCESSED_DIR / "features.csv"

# Input files (expected to exist from previous tasks)
LOC_FILE = PROCESSED_DIR / "loc_metrics.csv"
CC_FILE = PROCESSED_DIR / "cc_metrics.csv"
HALSTEAD_FILE = PROCESSED_DIR / "halstead_metrics.csv"
LABELS_FILE = PROCESSED_DIR / "bug_labels.csv"

def load_csv_safely(filepath: Path, required_columns: List[str]) -> Optional[pd.DataFrame]:
    """Load a CSV file and validate it has required columns."""
    if not filepath.exists():
        logger.error(f"Required input file missing: {filepath}")
        return None
    
    try:
        df = pd.read_csv(filepath)
        missing_cols = set(required_columns) - set(df.columns)
        if missing_cols:
            logger.error(f"File {filepath} missing columns: {missing_cols}")
            return None
        logger.info(f"Loaded {filepath}: {len(df)} rows")
        return df
    except Exception as e:
        logger.error(f"Failed to load {filepath}: {e}")
        return None

def merge_metrics(
    loc_df: pd.DataFrame,
    cc_df: pd.DataFrame,
    halstead_df: pd.DataFrame,
    labels_df: pd.DataFrame
) -> pd.DataFrame:
    """Merge all metric dataframes on file_path."""
    # Standardize column names if necessary (assuming consistent 'file_path' key)
    # Ensure 'file_path' is the key
    for df in [loc_df, cc_df, halstead_df, labels_df]:
        if 'file_path' not in df.columns:
            raise ValueError("One of the input DataFrames is missing 'file_path' column")

    # Start with LOC
    merged = loc_df[['file_path', 'loc']].copy()
    
    # Merge CC
    merged = merged.merge(
        cc_df[['file_path', 'cc']], 
        on='file_path', 
        how='inner'
    )
    
    # Merge Halstead
    merged = merged.merge(
        halstead_df[['file_path', 'halstead']], 
        on='file_path', 
        how='inner'
    )
    
    # Merge Labels
    merged = merged.merge(
        labels_df[['file_path', 'is_buggy']], 
        on='file_path', 
        how='inner'
    )
    
    return merged

def main():
    logger.info("Starting feature generation pipeline (T017)...")
    
    # Ensure output directory exists
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)

    # Load inputs
    loc_df = load_csv_safely(LOC_FILE, ['file_path', 'loc'])
    if loc_df is None:
        raise RuntimeError(f"Cannot proceed: {LOC_FILE} missing or invalid")

    cc_df = load_csv_safely(CC_FILE, ['file_path', 'cc'])
    if cc_df is None:
        raise RuntimeError(f"Cannot proceed: {CC_FILE} missing or invalid")

    halstead_df = load_csv_safely(HALSTEAD_FILE, ['file_path', 'halstead'])
    if halstead_df is None:
        raise RuntimeError(f"Cannot proceed: {HALSTEAD_FILE} missing or invalid")

    labels_df = load_csv_safely(LABELS_FILE, ['file_path', 'is_buggy'])
    if labels_df is None:
        raise RuntimeError(f"Cannot proceed: {LABELS_FILE} missing or invalid")

    # Merge
    try:
        final_df = merge_metrics(loc_df, cc_df, halstead_df, labels_df)
    except ValueError as e:
        raise RuntimeError(f"Merge failed: {e}")

    logger.info(f"Merged dataset shape: {final_df.shape}")

    # Validate no NaN in numeric columns (T018 requirement)
    numeric_cols = ['loc', 'cc', 'halstead', 'is_buggy']
    nan_count = final_df[numeric_cols].isna().sum().sum()
    if nan_count > 0:
        logger.error(f"Validation failed: Found {nan_count} NaN values in numeric columns.")
        raise ValueError("NaN values detected in metrics. T018 validation failed.")
    
    # Ensure correct column order
    final_df = final_df[['file_path', 'cc', 'halstead', 'loc', 'is_buggy']]
    
    # Save to CSV
    final_df.to_csv(OUTPUT_FILE, index=False)
    logger.info(f"Successfully generated {OUTPUT_FILE}")
    logger.info(f"Final row count: {len(final_df)}")

    return 0

if __name__ == "__main__":
    sys.exit(main())
