def load_sensitivity_analysis(path: str = "data/processed/sensitivity_analysis.json") -> List[Dict[str, Any]]:
    """
    Load the sensitivity analysis results from the JSON file generated by T032.
    """
    if not os.path.exists(path):
        raise FileNotFoundError(f"Sensitivity analysis file not found: {path}. "
                                "Ensure T032 has been run successfully.")
    
    with open(path, 'r') as f:
        data = json.load(f)
    
    # The structure from T032 is expected to be a list of dicts or a dict with a key
    # Assuming the file contains a list of results as per T032 spec:
    # [{threshold, r2, kruskal_stat, kruskal_pval}, ...]
    if isinstance(data, list):
        return data
    elif isinstance(data, dict) and 'results' in data:
        return data['results']
    else:
        # Fallback if structure is slightly different, try to extract list
        logging.warning("Sensitivity analysis file format unexpected. Attempting to parse.")
        return []

def prepare_data_and_split(data_path: str) -> Tuple[pd.DataFrame, List[int], List[int]]:
    """
    Load processed descriptor data and perform the scaffold split.
    Returns the full dataframe and the train/test indices.
    """
    if not os.path.exists(data_path):
        raise FileNotFoundError(f"Input data file not found: {data_path}")
    
    df = pd.read_csv(data_path)
    
    # Validate required columns exist
    required_cols = ['smiles', 'degree_mean', 'degree_std', 'degree_max', 'degree_min',
                     'path_length_mean', 'path_length_std', 'path_length_max', 'path_length_min',
                     'aromaticity_index', 'conjugation_length', 'ring_count']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required descriptor columns: {missing}")
    
    # Assume target is 'conductivity' or 'HOMO_LUMO_gap' based on T026 logic
    target_col = None
    if 'conductivity' in df.columns:
        target_col = 'conductivity'
    elif 'HOMO_LUMO_gap' in df.columns:
        target_col = 'HOMO_LUMO_gap'
    
    if not target_col:
        raise ValueError("No valid target variable found (conductivity or HOMO_LUMO_gap).")
    
    # Perform scaffold split
    # We need the indices to ensure reproducibility with T027
    train_idx, test_idx = scaffold_split(df, target_col, random_state=SEED)
    
    return df, train_idx, test_idx

def train_models_and_get_r2(df: pd.DataFrame, train_idx: List[int], test_idx: List[int]) -> Dict[str, float]:
    """
    Train RF and GB models on the split data and return R2 scores.
    """
    # Log transformation of target
    target_col = 'conductivity' if 'conductivity' in df.columns else 'HOMO_LUMO_gap'
    df_log = apply_log_transformation(df, target_col)
    
    # Prepare features (exclude non-feature columns)
    feature_cols = [c for c in df_log.columns if c not in ['smiles', target_col, f'log_{target_col}', 'status']]
    
    X = df_log[feature_cols].values
    y = df_log[f'log_{target_col}'].values
    
    X_train, X_test = X[train_idx], X[test_idx]
    y_train, y_test = y[train_idx], y[test_idx]
    
    # Train models
    rf_r2, gb_r2 = train_models(X_train, y_train, X_test, y_test, seed=SEED)
    
    return {
        'rf_r2': float(rf_r2),
        'gb_r2': float(gb_r2)
    }

def main():
    parser = argparse.ArgumentParser(description="Save model results and sensitivity analysis.")
    parser.add_argument("--data", type=str, default="data/processed/descriptors.csv",
                        help="Path to the processed descriptors CSV.")
    parser.add_argument("--output", type=str, default="data/processed/model_results.json",
                        help="Path to save the final model results JSON.")
    parser.add_argument("--sensitivity", type=str, default="data/processed/sensitivity_analysis.json",
                        help="Path to the sensitivity analysis JSON input.")
    
    args = parser.parse_args()
    
    # Setup logging
    setup_logging()
    logger = logging.getLogger(__name__)
    
    try:
        # 1. Load Sensitivity Analysis (from T032)
        logger.info(f"Loading sensitivity analysis from {args.sensitivity}")
        sensitivity_data = load_sensitivity_analysis(args.sensitivity)
        
        # 2. Prepare Data and Split
        logger.info(f"Loading and splitting data from {args.data}")
        df, train_idx, test_idx = prepare_data_and_split(args.data)
        
        # 3. Train Models and get R2
        logger.info("Training models and calculating R2 scores.")
        model_metrics = train_models_and_get_r2(df, train_idx, test_idx)
        
        # 4. Construct final result
        result = {
            'rf_r2': model_metrics['rf_r2'],
            'gb_r2': model_metrics['gb_r2'],
            'sensitivity_analysis': sensitivity_data
        }
        
        # 5. Save to disk
        output_dir = os.path.dirname(args.output)
        if output_dir and not os.path.exists(output_dir):
            os.makedirs(output_dir)
        
        with open(args.output, 'w') as f:
            json.dump(result, f, indent=2)
        
        logger.info(f"Model results saved to {args.output}")
        logger.info(f"RF R2: {model_metrics['rf_r2']:.4f}, GB R2: {model_metrics['gb_r2']:.4f}")
        
    except Exception as e:
        logger.error(f"Failed to save model results: {e}")
        raise

if __name__ == "__main__":
    main()