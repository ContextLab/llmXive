"""
T016b: Aggregate task-fMRI BOLD time series to calculate mean ventral striatum
activation magnitude per subject.

Reads VS ROI time series generated by T016c (preprocessing.py) from
data/processed/subject_*/vs_timeseries.npy, calculates the mean activation
magnitude per subject, and writes the results to
data/processed/ventral_striatum_activation.csv.

FR-002: Explicitly extract VS ROI time series and calculate activation magnitude.
"""
import os
import sys
import csv
import logging
import numpy as np
from pathlib import Path
from typing import List, Dict, Any

from config import ensure_directories
from state_manager import update_state_artifact, load_state, save_state

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler('data/processed/activation_aggregation.log')
    ]
)
logger = logging.getLogger(__name__)

def load_subject_vs_timeseries(subject_dir: Path) -> np.ndarray:
    """
    Load the VS ROI time series for a single subject.

    Expected file: <subject_dir>/vs_timeseries.npy
    Returns a 1D numpy array of shape (n_timepoints,).
    """
    timeseries_path = subject_dir / "vs_timeseries.npy"
    if not timeseries_path.exists():
        raise FileNotFoundError(f"VS timeseries not found for {subject_dir.name}: {timeseries_path}")
    
    try:
        data = np.load(timeseries_path)
        if data.ndim != 1:
            logger.warning(f"Unexpected shape for {subject_dir.name}: {data.shape}. Flattening.")
            data = data.flatten()
        return data
    except Exception as e:
        logger.error(f"Failed to load timeseries for {subject_dir.name}: {e}")
        raise

def calculate_mean_activation(timeseries: np.ndarray) -> float:
    """
    Calculate the mean activation magnitude for a time series.
    
    Note: In fMRI analysis, 'activation magnitude' often refers to the mean
    signal intensity or mean z-score if preprocessed. We assume the input
    timeseries is already preprocessed (e.g., normalized or raw BOLD) and
    calculate the arithmetic mean as the aggregate metric.
    """
    if timeseries.size == 0:
        raise ValueError("Empty timeseries provided.")
    return float(np.mean(timeseries))

def find_valid_subject_dirs(processed_dir: Path) -> List[Path]:
    """
    Scan data/processed for subject directories containing vs_timeseries.npy.
    """
    if not processed_dir.exists():
        logger.error(f"Processed directory does not exist: {processed_dir}")
        return []
    
    valid_dirs = []
    for item in processed_dir.iterdir():
        if item.is_dir() and item.name.startswith("subject_"):
            if (item / "vs_timeseries.npy").exists():
                valid_dirs.append(item)
            else:
                logger.warning(f"Skipping {item.name}: missing vs_timeseries.npy")
    
    logger.info(f"Found {len(valid_dirs)} valid subject directories with VS timeseries.")
    return sorted(valid_dirs)

def write_activation_csv(results: List[Dict[str, Any]], output_path: Path):
    """
    Write the aggregation results to a CSV file.
    """
    ensure_directories()
    with open(output_path, 'w', newline='') as csvfile:
        fieldnames = ['subject_id', 'mean_activation']
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        
        writer.writeheader()
        for row in results:
            writer.writerow(row)
    
    logger.info(f"Successfully wrote activation metrics to {output_path}")

def main():
    """
    Main entry point for T016b.
    """
    ensure_directories()
    processed_dir = Path("data/processed")
    output_path = processed_dir / "ventral_striatum_activation.csv"
    
    logger.info("Starting VS activation aggregation (T016b)...")
    
    subject_dirs = find_valid_subject_dirs(processed_dir)
    if not subject_dirs:
        logger.error("No valid subject directories found. Cannot proceed.")
        sys.exit(1)
    
    results = []
    failed_subjects = []
    
    for subj_dir in subject_dirs:
        subject_id = subj_dir.name
        try:
            ts = load_subject_vs_timeseries(subj_dir)
            mean_act = calculate_mean_activation(ts)
            results.append({
                "subject_id": subject_id,
                "mean_activation": mean_act
            })
            logger.info(f"Processed {subject_id}: mean_activation = {mean_act:.4f}")
        except Exception as e:
            logger.error(f"Failed to process {subject_id}: {e}")
            failed_subjects.append(subject_id)
    
    if failed_subjects:
        logger.warning(f"Failed to process {len(failed_subjects)} subjects: {failed_subjects}")
    
    if not results:
        logger.error("No subjects were successfully processed. Aborting.")
        sys.exit(1)
    
    write_activation_csv(results, output_path)
    
    # Update state management
    try:
        update_state_artifact(str(output_path))
        logger.info("State updated successfully.")
    except Exception as e:
        logger.error(f"Failed to update state: {e}")
    
    logger.info("T016b completed successfully.")

if __name__ == "__main__":
    main()
