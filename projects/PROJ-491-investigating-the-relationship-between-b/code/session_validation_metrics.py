def calculate_pass_rate(valid_subjects: list, total_subjects: int) -> float:
    """
    Calculate the pass-rate percentage.
    
    Args:
        valid_subjects: List of subject IDs that passed distinct session validation.
        total_subjects: Total number of subjects attempted.
        
    Returns:
        Pass rate as a float (0.0 to 1.0).
    """
    if total_subjects == 0:
        return 0.0
    return len(valid_subjects) / total_subjects

def write_metrics(metrics: Dict[str, Any], output_path: Path) -> None:
    """
    Write the metrics dictionary to a JSON file.
    
    Args:
        metrics: Dictionary containing pass_rate, total_subjects, valid_subjects.
        output_path: Path to the output JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(metrics, f, indent=2)
    logger.info(f"Metrics written to {output_path}")

