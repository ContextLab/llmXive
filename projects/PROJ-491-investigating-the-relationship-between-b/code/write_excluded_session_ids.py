import os
import sys
import csv
import json
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional

from config import ensure_directories

# Setup logging for this module
logger = logging.getLogger(__name__)
logger.setLevel(logging.INFO)
if not logger.handlers:
    handler = logging.StreamHandler(sys.stdout)
    handler.setFormatter(logging.Formatter('%(asctime)s - %(name)s - %(levelname)s - %(message)s'))
    logger.addHandler(handler)

def load_validation_state() -> Dict[str, Any]:
    """
    Loads the session validation metrics state from the previous step (T013b).
    Expects data/processed/session_validation_metrics.json.
    """
    metrics_path = Path("data/processed/session_validation_metrics.json")
    if not metrics_path.exists():
        raise FileNotFoundError(
            f"Validation state file not found at {metrics_path}. "
            "Please ensure T013b (session_validation_metrics.py) has been run successfully."
        )
    
    with open(metrics_path, 'r') as f:
        return json.load(f)

def save_validation_state(state: Dict[str, Any]) -> None:
    """
    Saves the updated validation state back to disk.
    """
    metrics_path = Path("data/processed/session_validation_metrics.json")
    ensure_directories()
    with open(metrics_path, 'w') as f:
        json.dump(state, f, indent=2)

def write_excluded_subjects_csv(excluded_ids: List[str]) -> str:
    """
    Writes the list of excluded subject IDs to a CSV file.
    Output: data/processed/excluded_session_ids.csv
    
    Args:
        excluded_ids: List of subject IDs that failed the session distinctness check.
        
    Returns:
        Path to the written CSV file.
    """
    output_path = Path("data/processed/excluded_session_ids.csv")
    ensure_directories()
    
    logger.info(f"Writing {len(excluded_ids)} excluded subject IDs to {output_path}")
    
    with open(output_path, 'w', newline='') as csvfile:
        writer = csv.writer(csvfile)
        writer.writerow(['subject_id', 'reason'])
        for sid in excluded_ids:
            writer.writerow([sid, 'session_id_mismatch'])
    
    logger.info(f"Successfully wrote excluded subjects to {output_path}")
    return str(output_path)

def run_validation_if_needed() -> bool:
    """
    Checks if the excluded list needs to be generated based on the current state.
    Returns True if the file was generated or already exists, False otherwise.
    """
    output_path = Path("data/processed/excluded_session_ids.csv")
    if output_path.exists():
        logger.info(f"Excluded subjects file already exists at {output_path}. Skipping generation.")
        return True
    return False

def main() -> int:
    """
    Main entry point for T013c.
    Reads session validation metrics, extracts excluded subjects, and writes CSV.
    """
    try:
        # Check if we already have the output
        if run_validation_if_needed():
            return 0

        # Load the metrics generated by T013b
        state = load_validation_state()
        
        # Extract the list of excluded subjects from the state
        # The state structure from T013b is expected to be:
        # {
        #   "total_subjects": int,
        #   "valid_subjects": int,
        #   "excluded_subjects": ["sub-001", ...],
        #   "pass_rate": float
        # }
        if "excluded_subjects" not in state:
            logger.error("Validation state does not contain 'excluded_subjects' key.")
            logger.error(f"State content: {state}")
            return 1
        
        excluded_ids = state["excluded_subjects"]
        
        if not excluded_ids:
            logger.info("No subjects were excluded. Creating empty CSV with headers.")
            write_excluded_subjects_csv([])
            return 0

        # Write the CSV
        write_excluded_subjects_csv(excluded_ids)
        
        return 0

    except FileNotFoundError as e:
        logger.error(f"Missing required input file: {e}")
        return 1
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse validation metrics JSON: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during excluded session ID generation: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
