"""
Task T016d: Post-Augmentation Save
Saves the final augmented dataset (result of T025) to data/processed/final_augmented_dataset.csv
with checksums. This artifact is the input for the training phase.
"""
import os
import sys
import json
import logging
import hashlib
import pandas as pd
from pathlib import Path

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root / "code"))

from utils import get_logger, get_project_paths
from augment import load_pre_augmented_dataset, check_augmentation_trigger, augment_dataset

logger = get_logger("T016d_save_augmented")
paths = get_project_paths()

def compute_file_checksum(file_path: Path) -> str:
    """Compute SHA256 checksum of a file."""
    sha256_hash = hashlib.sha256()
    with open(file_path, "rb") as f:
        for byte_block in iter(lambda: f.read(4096), b""):
            sha256_hash.update(byte_block)
    return sha256_hash.hexdigest()

def main():
    """
    Main entry point for T016d.
    Loads the augmented dataset (if augmentation was performed), validates it,
    saves it to data/processed/final_augmented_dataset.csv, and records checksums.
    """
    logger.info("Starting T016d: Post-Augmentation Save")

    # Check augmentation trigger state
    trigger_path = paths["state"] / "augmentation_trigger.json"
    augmentation_performed = False

    if trigger_path.exists():
        try:
            with open(trigger_path, "r") as f:
                trigger_data = json.load(f)
            if trigger_data.get("action") == "augment":
                augmentation_performed = True
                logger.info("Augmentation was triggered (50 <= n <= 150). Loading augmented dataset.")
            else:
                logger.info(f"Augmentation trigger found but action was '{trigger_data.get('action')}'. Skipping augmentation load.")
        except (json.JSONDecodeError, KeyError) as e:
            logger.warning(f"Could not parse augmentation trigger: {e}. Assuming no augmentation.")
    else:
        logger.info("No augmentation trigger found. Assuming no augmentation.")

    if augmentation_performed:
        # Load the augmented dataset generated by T025
        # T025 saves to data/processed/augmented_graph_dataset.csv
        augmented_path = paths["processed"] / "augmented_graph_dataset.csv"
        
        if not augmented_path.exists():
            logger.error(f"Augmented dataset not found at {augmented_path}. "
                         "T025 must complete successfully before T016d.")
            sys.exit(1)
        
        try:
            df_augmented = pd.read_csv(augmented_path)
            logger.info(f"Loaded augmented dataset with {len(df_augmented)} records from {augmented_path}")
        except Exception as e:
            logger.error(f"Failed to load augmented dataset: {e}")
            sys.exit(1)
        
        # Validate dataset integrity
        if len(df_augmented) == 0:
            logger.error("Augmented dataset is empty. Cannot save.")
            sys.exit(1)
        
        # Save the final augmented dataset
        output_path = paths["processed"] / "final_augmented_dataset.csv"
        df_augmented.to_csv(output_path, index=False)
        checksum = compute_file_checksum(output_path)
        
        logger.info(f"Saved final augmented dataset to {output_path} ({len(df_augmented)} records)")
        logger.info(f"Checksum (SHA256): {checksum}")
        
        # Save checksum manifest
        manifest_path = paths["processed"] / "final_augmented_dataset_manifest.json"
        manifest = {
            "file": "final_augmented_dataset.csv",
            "checksum_algorithm": "SHA256",
            "checksum": checksum,
            "record_count": len(df_augmented),
            "source": "augmented_graph_dataset.csv",
            "timestamp": pd.Timestamp.now().isoformat()
        }
        with open(manifest_path, "w") as f:
            json.dump(manifest, f, indent=2)
        logger.info(f"Saved manifest to {manifest_path}")
    else:
        # If no augmentation was performed, the pre-augmented dataset is the final one
        # However, T016d specifically asks for the result of T025. 
        # If T025 was skipped (n > 150), the "result" is effectively the pre-augmented set.
        # But strictly, if no augmentation happened, we should check if we need to copy the pre-augmented set.
        # According to T025 logic: "If trigger file is absent (n > 150), log status='skipped'".
        # In that case, the training data is the pre-augmented set.
        # We will copy the pre-augmented dataset to the final_augmented_dataset.csv path
        # to ensure the training phase (T028) has a consistent input path.
        
        pre_aug_path = paths["processed"] / "pre_augmented_graph_dataset.csv"
        if pre_aug_path.exists():
            df_pre = pd.read_csv(pre_aug_path)
            output_path = paths["processed"] / "final_augmented_dataset.csv"
            df_pre.to_csv(output_path, index=False)
            checksum = compute_file_checksum(output_path)
            
            logger.info(f"No augmentation triggered. Copied pre-augmented dataset to {output_path}")
            logger.info(f"Checksum (SHA256): {checksum}")
            
            # Save manifest indicating no augmentation
            manifest_path = paths["processed"] / "final_augmented_dataset_manifest.json"
            manifest = {
                "file": "final_augmented_dataset.csv",
                "checksum_algorithm": "SHA256",
                "checksum": checksum,
                "record_count": len(df_pre),
                "source": "pre_augmented_graph_dataset.csv",
                "augmentation_performed": False,
                "timestamp": pd.Timestamp.now().isoformat()
            }
            with open(manifest_path, "w") as f:
                json.dump(manifest, f, indent=2)
            logger.info(f"Saved manifest to {manifest_path}")
        else:
            logger.error(f"Neither augmented nor pre-augmented dataset found. "
                         "Cannot produce final_augmented_dataset.csv.")
            sys.exit(1)

    logger.info("T016d completed successfully.")

if __name__ == "__main__":
    main()
