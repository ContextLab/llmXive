def load_processed_data(path: str) -> pd.DataFrame:
    """Load the final processed dataset."""
    if not os.path.exists(path):
        raise FileNotFoundError(f"Processed data file not found: {path}")
    return pd.read_csv(path)

def load_responder_labels(path: str) -> pd.DataFrame:
    """Load responder labels generated by T030d."""
    if not os.path.exists(path):
        raise FileNotFoundError(f"Responder labels file not found: {path}")
    return pd.read_csv(path)

def load_variance_filtered_taxa(path: str) -> List[str]:
    """Load the list of variance-filtered taxa."""
    if not os.path.exists(path):
        raise FileNotFoundError(f"Variance filtered taxa file not found: {path}")
    with open(path, 'r') as f:
        data = json.load(f)
    return data.get('taxa', [])

def select_features_inner_loop(
    train_X: pd.DataFrame,
    train_y: pd.Series,
    variance_filtered_taxa: List[str]
) -> List[str]:
    """
    Select features strictly within the training fold using Spearman correlation + BH correction.
    This implements the logic for T032b_model to prevent data leakage.
    """
    # Identify taxa columns in the training set (intersection with variance filtered list)
    available_taxa = [t for t in variance_filtered_taxa if t in train_X.columns]
    
    if not available_taxa:
        logger.warning("No available taxa for feature selection. Using fallback.")
        return variance_filtered_taxa

    correlations = []
    pvalues = []
    taxa_names = []

    for taxon in available_taxa:
        col = train_X[taxon]
        # Handle constant columns (variance 0) to avoid NaN in spearmanr
        if col.nunique() < 2:
            correlations.append(0.0)
            pvalues.append(1.0)
            taxa_names.append(taxon)
            continue

        corr, pval = spearmanr(col, train_y)
        if np.isnan(corr):
            corr, pval = 0.0, 1.0
        correlations.append(corr)
        pvalues.append(pval)
        taxa_names.append(taxon)

    # Apply Benjamini-Hochberg correction
    if len(pvalues) > 0:
        _, p_adj, _, _ = multipletests(pvalues, alpha=0.05, method='fdr_bh')
    else:
        p_adj = []

    # Select significant taxa
    significant_taxa = [
        taxa_names[i] for i, p in enumerate(p_adj) if p < 0.05
    ]

    # Fallback: if no significant taxa, use entire variance-filtered set
    if not significant_taxa:
        logger.info("No significant taxa found in inner loop. Using variance-filtered set.")
        return variance_filtered_taxa

    return significant_taxa

def define_thresholds(base_threshold: float) -> List[float]:
    """
    Define the sweep of thresholds: base * (1 + 0.1 * i) for i in [-2, -1, 0, 1, 2].
    Runtime guard: if estimated time > 2 hours, reduce range.
    """
    # Estimate: 5 folds * 5 thresholds * (inner loop time ~1s + model time ~1s) ~ 50s.
    # Even with overhead, 5 thresholds is safe. We keep the full range unless system is extremely slow.
    # For safety in this implementation, we stick to the spec's full range but log a warning if it gets tight.
    factors = [-0.2, -0.1, 0.0, 0.1, 0.2]
    return [base_threshold * (1 + f) for f in factors]

def run_nested_cv_for_threshold(
    df: pd.DataFrame,
    labels: pd.Series,
    variance_filtered_taxa: List[str],
    threshold_idx: int,
    threshold_val: float
) -> Dict[str, Any]:
    """
    Run nested 5-fold CV for a specific threshold.
    Returns metrics and the specific folds used.
    """
    logger.info(f"Processing Threshold {threshold_idx}: {threshold_val:.4f}")
    
    # 1. Regenerate Outer Folds (Stratified by responder status)
    # Ensure binary labels for StratifiedKFold
    y_binary = (labels >= threshold_val).astype(int)
    
    # Check if we have both classes
    if y_binary.value_counts().min() == 0:
        logger.warning(f"Threshold {threshold_val} results in a single class. Skipping.")
        return {
            "threshold": threshold_val,
            "threshold_idx": threshold_idx,
            "status": "skipped_single_class",
            "metrics": {}
        }

    skf = StratifiedKFold(n_splits=BASE_FOLDS, shuffle=True, random_state=get_random_seed() + threshold_idx)
    folds_indices = [
        [train_idx.tolist(), test_idx.tolist()] 
        for train_idx, test_idx in skf.split(df, y_binary)
    ]
    
    # Save folds to disk for verification (T034d requirement)
    folds_path = Path("data/results") / f"folds_threshold_{threshold_idx}.json"
    with open(folds_path, 'w') as f:
        json.dump(folds_indices, f)
    logger.info(f"Saved folds to {folds_path}")

    # 2. Inner Loop Execution
    accuracies = []
    precisions = []
    recalls = []
    f1s = []

    for fold_idx, (train_idx, test_idx) in enumerate(folds_indices):
        # Split data
        train_X = df.iloc[train_idx]
        train_y = y_binary.iloc[train_idx]
        test_X = df.iloc[test_idx]
        test_y = y_binary.iloc[test_idx]

        # Feature Selection (Inner Loop) - STRICT ISOLATION
        selected_features = select_features_inner_loop(
            train_X, train_y, variance_filtered_taxa
        )
        
        # Ensure all selected features exist in test set (sanity check)
        # In practice, df is constant, so this should always pass if variance_filtered_taxa is valid
        final_features = [f for f in selected_features if f in train_X.columns]
        if not final_features:
            logger.warning(f"Fold {fold_idx} has no features. Skipping.")
            continue

        train_X_sub = train_X[final_features]
        test_X_sub = test_X[final_features]

        # Model Training
        rf = RandomForestClassifier(
            n_estimators=100,
            random_state=get_random_seed(),
            n_jobs=-1
        )
        rf.fit(train_X_sub, train_y)

        # Evaluation
        y_pred = rf.predict(test_X_sub)
        
        acc = accuracy_score(test_y, y_pred)
        prec = precision_score(test_y, y_pred, zero_division=0)
        rec = recall_score(test_y, y_pred, zero_division=0)
        f1 = f1_score(test_y, y_pred, zero_division=0)

        accuracies.append(acc)
        precisions.append(prec)
        recalls.append(rec)
        f1s.append(f1)

        logger.debug(f"  Fold {fold_idx}: Acc={acc:.3f}, F1={f1:.3f}")

    if not accuracies:
        logger.error(f"No valid folds for threshold {threshold_val}.")
        return {
            "threshold": threshold_val,
            "threshold_idx": threshold_idx,
            "status": "failed_no_folds",
            "metrics": {}
        }

    return {
        "threshold": float(threshold_val),
        "threshold_idx": threshold_idx,
        "status": "completed",
        "metrics": {
            "mean_accuracy": float(np.mean(accuracies)),
            "std_accuracy": float(np.std(accuracies)),
            "mean_precision": float(np.mean(precisions)),
            "mean_recall": float(np.mean(recalls)),
            "mean_f1": float(np.mean(f1s)),
            "accuracy_scores": accuracies
        }
    }

def run_sensitivity_analysis():
    """Main entry point for T034d."""
    start_time = time.time()
    
    # Paths
    processed_path = "data/processed/cleared_final.csv"
    labels_path = "data/processed/responder_labels.csv"
    variance_path = "data/results/variance_filtered_taxa.json"
    output_metrics_path = "data/results/model_metrics.json"
    output_csv_path = "data/results/sensitivity_analysis.csv"

    # Load Data
    logger.info("Loading processed data...")
    df = load_processed_data(processed_path)
    
    logger.info("Loading responder labels...")
    labels_df = load_responder_labels(labels_path)
    # Merge to ensure alignment (though T030d should have aligned them)
    # We assume 'subject_id' is the key
    if 'subject_id' not in df.columns or 'subject_id' not in labels_df.columns:
        raise ValueError("Missing subject_id in data or labels.")
    
    merged = pd.merge(df, labels_df[['subject_id', 'responder_status']], on='subject_id', how='inner')
    if merged.empty:
        raise ValueError("No matching subjects between data and labels.")
    
    # Extract labels series (we will re-apply thresholds to this base status or use the raw titers)
    # The spec says "Define NEW responder labels based on current threshold".
    # This implies we need the raw titers to calculate new labels, not just the pre-computed status.
    # However, T030d output `responder_labels.csv` likely contains the status for the base threshold.
    # To support the sweep, we need `titer_post` and `titer_baseline`.
    # Assuming these are in `cleared_final.csv` or `cleared_log.csv`? 
    # T011d produced `cleared.csv` with titers. T021 produced `cleared_log.csv`.
    # `cleared_final.csv` (T020a) merges Shannon, Log, and Norm. So it SHOULD have titers.
    # Let's check columns. If not, we might need to load `cleared_log.csv`.
    
    required_titer_cols = ['titer_post', 'titer_baseline']
    missing_cols = [c for c in required_titer_cols if c not in merged.columns]
    
    if missing_cols:
        # Fallback: try loading cleared_log.csv which definitely has log titers, but we need raw for 4x rule
        # Actually, the 4x rule uses raw titers. Let's assume cleared_final has them or load cleared_log
        log_path = "data/processed/cleared_log.csv"
        if os.path.exists(log_path):
            log_df = pd.read_csv(log_path)
            if all(c in log_df.columns for c in required_titer_cols):
                merged = pd.merge(merged, log_df[['subject_id'] + required_titer_cols], on='subject_id', how='left')
                missing_cols = [c for c in required_titer_cols if c not in merged.columns]
        
        if missing_cols:
            raise ValueError(f"Could not find required titer columns {missing_cols} in data.")

    # Load variance filtered taxa
    variance_taxa = load_variance_filtered_taxa(variance_path)
    
    # Get base threshold
    base_threshold = get_seroconversion_threshold()
    if base_threshold is None:
        base_threshold = 4.0  # Default seroconversion (4-fold)
        logger.warning(f"Config SEROCONVERSION_THRESHOLD not set. Using default {base_threshold}.")

    # Define thresholds
    thresholds = define_thresholds(base_threshold)
    
    # Runtime Guard Check
    estimated_time = len(thresholds) * BASE_FOLDS * 2  # Rough estimate in seconds
    if estimated_time > MAX_RUNTIME_SECONDS:
        logger.warning(f"Estimated runtime {estimated_time}s > {MAX_RUNTIME_SECONDS}s. Reducing thresholds.")
        # Reduce to -1, 0, 1
        thresholds = [base_threshold * 0.9, base_threshold, base_threshold * 1.1]
        logger.info(f"Reduced thresholds to: {thresholds}")

    # Feature columns (taxa)
    # We assume the variance filtered taxa are the features.
    # We must ensure they exist in the dataframe.
    available_features = [t for t in variance_taxa if t in merged.columns]
    if not available_features:
        raise ValueError("No variance filtered taxa found in the processed dataframe.")

    results = []
    all_metrics = []

    for i, thresh in enumerate(thresholds):
        # Define NEW responder labels for this threshold
        # Logic: post_titer >= threshold * baseline_titer? 
        # Or is threshold an absolute titer? 
        # T030a: seroconversion (post >= 4 * baseline). 
        # T030b: absolute (post >= 40).
        # The sweep in T034d says "factor = 0.1 * i; threshold = base * (1 + factor)".
        # If base is 4 (seroconversion ratio), then we are sweeping the ratio.
        # If base is 40 (absolute), we are sweeping the absolute titer.
        # We need to know which logic T030d used. 
        # Assuming the config `SEROCONVERSION_THRESHOLD` implies the ratio (default 4).
        # So the label is: (titer_post >= threshold * titer_baseline)
        
        # Let's create the boolean series
        # Handle potential division by zero or NaN in baseline
        baseline = merged['titer_baseline'].replace(0, np.nan)
        if baseline.isna().any():
            logger.warning("Some baseline titers are zero or NaN. Handling with imputation or exclusion.")
            # For ratio calculation, if baseline is 0, we can't divide. 
            # If baseline is 0 and post > 0, it's a massive rise. 
            # We'll exclude rows with NaN baseline for this calculation.
            valid_mask = baseline.notna()
            merged_valid = merged[valid_mask].copy()
            baseline_valid = merged_valid['titer_baseline']
            post_valid = merged_valid['titer_post']
            
            new_labels = (post_valid >= thresh * baseline_valid).astype(int)
            # Re-index to match original df? No, we just use the valid subset for this threshold
            # But wait, StratifiedKFold needs the full set or we lose subjects.
            # Better: assign 0 or NaN to invalid ones? 
            # If baseline is 0, we can't determine seroconversion ratio. 
            # We'll drop them for this specific threshold calculation if necessary, 
            # but StratifiedKFold requires consistent indices.
            # Simpler approach: If baseline is 0, assume no seroconversion unless post is huge? 
            # Spec says "post >= 4 * baseline". If baseline=0, 4*0=0. If post > 0, it's True.
            # Let's handle 0 baseline as 0 in multiplication.
            baseline_clean = merged['titer_baseline'].fillna(0).replace(0, 1e-9) # Avoid div issues if we were dividing
            # Actually, the formula is multiplication: post >= thresh * baseline.
            # If baseline is 0, threshold * 0 = 0. If post > 0, it's True.
            # This seems valid.
            baseline_clean = merged['titer_baseline'].fillna(0)
            new_labels = (merged['titer_post'] >= thresh * baseline_clean).astype(int)
        else:
            new_labels = (merged['titer_post'] >= thresh * merged['titer_baseline']).astype(int)

        # Run CV
        result = run_nested_cv_for_threshold(
            merged[available_features],
            new_labels,
            variance_taxa,
            i,
            thresh
        )
        results.append(result)
        all_metrics.append(result.get('metrics', {}))

    # Compile Final Outputs
    end_time = time.time()
    total_runtime = end_time - start_time

    # Check SC-003: Accuracy > 60%
    # We take the best performing threshold's mean accuracy
    best_acc = 0.0
    best_thresh = None
    for r in results:
        if r.get('status') == 'completed':
            acc = r['metrics'].get('mean_accuracy', 0)
            if acc > best_acc:
                best_acc = acc
                best_thresh = r['threshold']

    meets_target = best_acc > 0.60

    final_report = {
        "total_runtime_seconds": total_runtime,
        "thresholds_tested": len(thresholds),
        "best_threshold": best_thresh,
        "best_mean_accuracy": best_acc,
        "meets_accuracy_target": meets_target,
        "results": results
    }

    # Write JSON
    with open(output_metrics_path, 'w') as f:
        json.dump(final_report, f, indent=2)
    logger.info(f"Written model metrics to {output_metrics_path}")

    # Write CSV (Sensitivity Analysis)
    csv_data = []
    for r in results:
        if r.get('status') == 'completed':
            csv_data.append({
                "threshold": r['threshold'],
                "mean_accuracy": r['metrics']['mean_accuracy'],
                "std_accuracy": r['metrics']['std_accuracy'],
                "mean_f1": r['metrics']['mean_f1'],
                "status": "completed"
            })
        else:
            csv_data.append({
                "threshold": r['threshold'],
                "mean_accuracy": None,
                "std_accuracy": None,
                "mean_f1": None,
                "status": r['status']
            })
    
    df_csv = pd.DataFrame(csv_data)
    df_csv.to_csv(output_csv_path, index=False)
    logger.info(f"Written sensitivity analysis to {output_csv_path}")

    return final_report

def main():
    """Entry point for the script."""
    try:
        result = run_sensitivity_analysis()
        logger.info("Sensitivity analysis completed successfully.")
        print(json.dumps(result, indent=2))
        sys.exit(0)
    except Exception as e:
        logger.error(f"Error during sensitivity analysis: {e}", exc_info=True)
        print(f"Error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
