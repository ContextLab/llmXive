logger = get_logger(__name__)

def load_correlation_results(input_path: str) -> List[Dict[str, Any]]:
    """
    Load correlation results from the JSON file generated by the correlation pipeline.
    
    Args:
        input_path: Path to the correlation_results.json file.
        
    Returns:
        List of dictionaries containing correlation data.
        
    Raises:
        FileNotFoundError: If the input file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    path = Path(input_path)
    if not path.exists():
        raise FileNotFoundError(f"Correlation results file not found: {path}")
        
    with open(path, 'r') as f:
        data = json.load(f)
        
    # The JSON structure from T032 is expected to be a list of results
    # or a dict with a 'results' key. We handle both.
    if isinstance(data, list):
        return data
    elif isinstance(data, dict) and 'results' in data:
        return data['results']
    else:
        # If it's a dict with taxon keys, convert to list
        if 'taxa' in data:
            return data['taxa']
        # Fallback: try to treat the whole dict as a single result or list items
        logger.warning(f"Unexpected JSON structure in {path}, attempting to parse as list of dicts")
        return [data] if isinstance(data, dict) else []

def write_correlation_csv(results: List[Dict[str, Any]], output_path: str) -> None:
    """
    Write correlation results to a CSV file with the required schema.
    
    Schema: [taxon, coefficient, raw_pvalue, adj_pvalue]
    
    Args:
        results: List of dictionaries containing correlation data.
        output_path: Path to the output CSV file.
        
    Raises:
        ValueError: If required fields are missing from results.
    """
    if not results:
        logger.warning("No correlation results to write. Creating empty CSV with headers.")
        df = pd.DataFrame(columns=['taxon', 'coefficient', 'raw_pvalue', 'adj_pvalue'])
    else:
        # Ensure required fields exist
        required_fields = ['taxon', 'coefficient', 'raw_pvalue', 'adj_pvalue']
        for i, result in enumerate(results):
            for field in required_fields:
                if field not in result:
                    logger.error(f"Missing field '{field}' in result at index {i}")
                    raise ValueError(f"Missing required field '{field}' in correlation results")
        
        df = pd.DataFrame(results)
        
        # Ensure correct column order and types
        df = df[['taxon', 'coefficient', 'raw_pvalue', 'adj_pvalue']]
        df['coefficient'] = pd.to_numeric(df['coefficient'], errors='coerce')
        df['raw_pvalue'] = pd.to_numeric(df['raw_pvalue'], errors='coerce')
        df['adj_pvalue'] = pd.to_numeric(df['adj_pvalue'], errors='coerce')
    
    # Create output directory if it doesn't exist
    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    # Write to CSV
    df.to_csv(output_path, index=False)
    logger.info(f"Successfully wrote {len(df)} rows to {output_path}")

def validate_output(output_path: str) -> bool:
    """
    Validate the output CSV file against the expected schema.
    
    Args:
        output_path: Path to the output CSV file.
        
    Returns:
        True if validation passes, False otherwise.
    """
    path = Path(output_path)
    if not path.exists():
        logger.error(f"Output file does not exist: {path}")
        return False
        
    try:
        df = pd.read_csv(path)
        
        # Check columns
        expected_columns = {'taxon', 'coefficient', 'raw_pvalue', 'adj_pvalue'}
        if set(df.columns) != expected_columns:
            logger.error(f"Column mismatch. Expected {expected_columns}, got {set(df.columns)}")
            return False
            
        # Check for non-empty data (unless intentionally empty)
        if len(df) == 0:
            logger.warning("Output CSV is empty. This might be valid if no significant taxa were found.")
            
        # Check for nulls in critical columns
        if df['taxon'].isnull().any():
            logger.error("Found null values in 'taxon' column")
            return False
            
        if df['coefficient'].isnull().any():
            logger.error("Found null values in 'coefficient' column")
            return False
            
        if df['raw_pvalue'].isnull().any():
            logger.error("Found null values in 'raw_pvalue' column")
            return False
            
        if df['adj_pvalue'].isnull().any():
            logger.error("Found null values in 'adj_pvalue' column")
            return False
            
        logger.info("Validation passed")
        return True
        
    except Exception as e:
        logger.error(f"Validation failed with error: {e}")
        return False

def main() -> int:
    """
    Main entry point for the correlation CSV writer.
    
    Returns:
        0 on success, 1 on failure.
    """
    try:
        # Define paths
        # T032 outputs to data/results/correlation_results.json
        input_path = get_output_path("results/correlation_results.json")
        output_path = get_output_path("results/correlation_results.csv")
        
        logger.info(f"Loading correlation results from {input_path}")
        results = load_correlation_results(input_path)
        
        logger.info(f"Writing {len(results)} correlation results to {output_path}")
        write_correlation_csv(results, output_path)
        
        logger.info("Validating output file")
        if not validate_output(output_path):
            logger.error("Output validation failed")
            return 1
            
        logger.info("Task completed successfully")
        return 0
        
    except Exception as e:
        logger.error(f"Task failed with exception: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())