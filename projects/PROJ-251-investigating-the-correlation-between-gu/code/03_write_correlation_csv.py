import os
import sys
import logging
import json
from pathlib import Path
from typing import List, Dict, Any

import pandas as pd

# Import from utils
from utils.logging_config import get_logger
from utils.validators import validate_correlation_results_schema

logger = get_logger(__name__)

def load_correlation_results(filepath: Path) -> List[Dict[str, Any]]:
    """
    Load correlation results from the JSON file generated by T032.
    Expected structure: a list of dicts with keys: taxon, coefficient, raw_pvalue, adj_pvalue
    """
    logger.info(f"Loading correlation results from {filepath}")
    
    if not filepath.exists():
        raise FileNotFoundError(f"Correlation results file not found: {filepath}")
    
    with open(filepath, 'r') as f:
        data = json.load(f)
    
    if not isinstance(data, list):
        raise ValueError(f"Expected a list in {filepath}, got {type(data)}")
    
    return data

def write_correlation_csv(data: List[Dict[str, Any]], output_path: Path) -> None:
    """
    Write correlation results to a CSV file with columns:
    [taxon, coefficient, raw_pvalue, adj_pvalue]
    """
    logger.info(f"Writing correlation results to {output_path}")
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Create DataFrame
    df = pd.DataFrame(data)
    
    # Ensure correct column order and types
    required_cols = ['taxon', 'coefficient', 'raw_pvalue', 'adj_pvalue']
    
    # Check if all required columns exist
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in input data: {missing_cols}")
    
    # Select and order columns
    df = df[required_cols]
    
    # Ensure numeric types
    df['coefficient'] = pd.to_numeric(df['coefficient'], errors='raise')
    df['raw_pvalue'] = pd.to_numeric(df['raw_pvalue'], errors='raise')
    df['adj_pvalue'] = pd.to_numeric(df['adj_pvalue'], errors='raise')
    
    # Write to CSV
    df.to_csv(output_path, index=False)
    logger.info(f"Successfully wrote {len(df)} rows to {output_path}")

def validate_output(output_path: Path) -> bool:
    """
    Validate the output CSV file exists and has the correct schema.
    """
    logger.info(f"Validating output file: {output_path}")
    
    if not output_path.exists():
        logger.error(f"Output file does not exist: {output_path}")
        return False
    
    try:
        df = pd.read_csv(output_path)
        
        # Check required columns
        required_cols = ['taxon', 'coefficient', 'raw_pvalue', 'adj_pvalue']
        if not all(col in df.columns for col in required_cols):
            logger.error(f"Missing required columns. Found: {list(df.columns)}")
            return False
        
        # Check for non-null values in required columns
        for col in required_cols:
            if df[col].isnull().any():
                logger.error(f"Null values found in column: {col}")
                return False
        
        logger.info(f"Validation passed: {len(df)} rows, columns: {list(df.columns)}")
        return True
        
    except Exception as e:
        logger.error(f"Validation failed: {e}")
        return False

def main():
    """
    Main entry point for T024: Write correlation results to CSV.
    """
    # Setup paths
    project_root = Path(__file__).resolve().parent.parent
    results_dir = project_root / "data" / "results"
    
    input_file = results_dir / "correlation_results.json"
    output_file = results_dir / "correlation_results.csv"
    
    # Ensure results directory exists
    results_dir.mkdir(parents=True, exist_ok=True)
    
    try:
        # Load correlation results
        data = load_correlation_results(input_file)
        
        if not data:
            logger.warning("No correlation results found. Writing empty CSV.")
            # Write empty CSV with headers
            pd.DataFrame(columns=['taxon', 'coefficient', 'raw_pvalue', 'adj_pvalue']).to_csv(output_file, index=False)
        else:
            # Write to CSV
            write_correlation_csv(data, output_file)
        
        # Validate output
        if validate_output(output_file):
            logger.info("T024 completed successfully.")
            return 0
        else:
            logger.error("T024 validation failed.")
            return 1
            
    except FileNotFoundError as e:
        logger.error(f"Input file not found: {e}")
        return 1
    except Exception as e:
        logger.error(f"Error during T024 execution: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
