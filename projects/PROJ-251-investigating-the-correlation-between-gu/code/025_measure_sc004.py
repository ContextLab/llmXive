"""
T025: Measure & Log SC-004 Outcome (Logging Only).

This task reads the correlation results generated by T032, counts the number
of significant taxa (adjusted p-value < 0.05), and logs the outcome to
data/results/sc004_report.json.

It does NOT halt execution. It is a logging task only.
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, List

# Import from existing project modules
from utils.config import get_use_synthetic_data, get_significant_taxa_range
from utils.logging_config import get_logger, log_error_context

# Configure logger
logger = get_logger(__name__)

INPUT_PATH = Path("data/results/correlation_results.json")
OUTPUT_PATH = Path("data/results/sc004_report.json")
EXPECTED_RANGE = (1, 9)  # Expected range for real data per SC-004


def load_correlation_results(path: Path) -> List[Dict[str, Any]]:
    """Load correlation results from JSON file."""
    if not path.exists():
        raise FileNotFoundError(f"Correlation results not found at {path}")
    
    with open(path, 'r') as f:
        data = json.load(f)
    
    # Ensure it's a list of dicts
    if isinstance(data, dict) and 'results' in data:
        return data['results']
    elif isinstance(data, list):
        return data
    else:
        raise ValueError(f"Unexpected format in {path}: {type(data)}")


def count_significant_taxa(results: List[Dict[str, Any]], threshold: float = 0.05) -> int:
    """Count taxa with adjusted p-value below threshold."""
    count = 0
    for row in results:
        adj_p = row.get('adj_pvalue')
        if adj_p is not None and adj_p < threshold:
            count += 1
    return count


def generate_report(
    count: int,
    is_synthetic: bool,
    expected_range: tuple = EXPECTED_RANGE
) -> Dict[str, Any]:
    """Generate the SC-004 report dictionary."""
    report = {
        "count": count,
        "expected_range": list(expected_range) if not is_synthetic else "N/A (Synthetic)",
        "is_synthetic": is_synthetic
    }

    if is_synthetic:
        report["status"] = "reported"
        report["message"] = "Synthetic data used; SC-004 range check skipped."
    else:
        in_range = expected_range[0] <= count <= expected_range[1]
        report["within_range"] = in_range
        
        if in_range:
            report["status"] = "reported"
            report["message"] = "Significant taxa count within expected range."
        else:
            report["status"] = "warning"
            report["message"] = "Significant taxa count out of expected range for real data. Logged for review."
            
    return report


def write_report(report: Dict[str, Any], path: Path) -> None:
    """Write report to JSON file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'w') as f:
        json.dump(report, f, indent=2)
    logger.info(f"SC-004 report written to {path}")


def run_sc004_measurement() -> Dict[str, Any]:
    """Main execution logic for T025."""
    logger.info("Starting SC-004 outcome measurement (T025)...")
    
    # Load inputs
    try:
        results = load_correlation_results(INPUT_PATH)
    except FileNotFoundError as e:
        logger.error(str(e))
        raise
    
    # Determine if synthetic
    is_synthetic = get_use_synthetic_data()
    
    # Count significant taxa
    count = count_significant_taxa(results)
    logger.info(f"Found {count} significant taxa (adj_p < 0.05).")
    
    # Generate report
    report = generate_report(count, is_synthetic)
    
    # Write output
    write_report(report, OUTPUT_PATH)
    
    return report


def main() -> int:
    """Entry point."""
    try:
        run_sc004_measurement()
        return 0
    except Exception as e:
        log_error_context(logger, e)
        return 1


if __name__ == "__main__":
    sys.exit(main())
