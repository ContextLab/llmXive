"""
Task T025: Measure & Log SC-004 Outcome (Reporting Only).

This task reads the correlation results generated by T032, counts the number
of significant taxa, and logs the outcome to a JSON report.

It does NOT halt the pipeline regardless of the count; it is a reporting step.
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from utils.config import get_use_synthetic_data, get_results_path, get_research_path
from utils.logging_config import get_logger

logger = get_logger(__name__)

CORRELATION_RESULTS_PATH = "data/results/correlation_results.json"
SC004_REPORT_PATH = "data/results/sc004_report.json"
SIGNIFICANCE_THRESHOLD = 0.05

def load_correlation_results() -> list:
    """Load correlation results from JSON file."""
    results_path = project_root / CORRELATION_RESULTS_PATH
    if not results_path.exists():
        raise FileNotFoundError(
            f"Correlation results file not found at {results_path}. "
            "Ensure T032 has completed successfully."
        )
    
    with open(results_path, 'r') as f:
        data = json.load(f)
    
    return data

def count_significant_taxa(results: list, threshold: float = SIGNIFICANCE_THRESHOLD) -> int:
    """Count taxa with adjusted p-value below the significance threshold."""
    count = 0
    for item in results:
        adj_p = item.get('adj_pvalue')
        if adj_p is not None and adj_p < threshold:
            count += 1
    return count

def generate_report(count: int, is_synthetic: bool) -> Dict[str, Any]:
    """Generate the SC-004 report dictionary."""
    report = {
        "status": "reported",
        "count": count,
    }

    if is_synthetic:
        report["expected_range"] = "N/A (Synthetic)"
        report["within_range"] = None
        report["message"] = "Result reported (Synthetic Data)."
        logger.info(f"SC-004 Report (Synthetic): {count} significant taxa found.")
    else:
        # Expected range per Spec SC-004: "low single-digit to higher single-digit"
        # Interpreted as roughly 1 to 9.
        expected_min = 1
        expected_max = 9
        within_range = expected_min <= count <= expected_max
        
        report["expected_range"] = f"{expected_min} to {expected_max}"
        report["within_range"] = within_range
        
        if within_range:
            message = (
                f"Result reported as finding: {count} significant taxa found. "
                "This falls within the expected range (low single-digit to higher single-digit)."
            )
            logger.info(f"SC-004 Report (Real Data): {message}")
        else:
            message = (
                f"Result reported as finding: {count} significant taxa found. "
                f"This is outside the expected range ({expected_min}-{expected_max})."
            )
            logger.warning(f"SC-004 Report (Real Data): {message}")
        
        report["message"] = message

    return report

def write_report(report: Dict[str, Any]) -> None:
    """Write the report to the output JSON file."""
    output_path = project_root / SC004_REPORT_PATH
    
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"SC-004 report written to {output_path}")

def run_sc004_measurement() -> None:
    """Main entry point for T025."""
    logger.info("Starting T025: Measure & Log SC-004 Outcome")
    
    try:
        # 1. Load correlation results
        results = load_correlation_results()
        logger.debug(f"Loaded {len(results)} correlation records.")
        
        # 2. Count significant taxa
        significant_count = count_significant_taxa(results)
        logger.info(f"Found {significant_count} significant taxa (adj_p < {SIGNIFICANCE_THRESHOLD}).")
        
        # 3. Determine if synthetic
        is_synthetic = get_use_synthetic_data()
        
        # 4. Generate report
        report = generate_report(significant_count, is_synthetic)
        
        # 5. Write report
        write_report(report)
        
        logger.info("T025 completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(f"Missing required input file: {e}")
        sys.exit(1)
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in correlation results: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during T025 execution: {e}", exc_info=True)
        sys.exit(1)

def main():
    """CLI entry point."""
    run_sc004_measurement()

if __name__ == "__main__":
    main()
