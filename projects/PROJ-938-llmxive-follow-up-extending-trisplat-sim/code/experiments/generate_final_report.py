logger = logging.getLogger(__name__)

def load_batch_results(base_dir: str = "data/processed") -> List[Dict[str, Any]]:
    """
    Loads all JSON log files generated by run_batch.py.
    Expects files like scene_*.json in the base directory.
    """
    results = []
    base_path = Path(base_dir)
    if not base_path.exists():
        logger.warning(f"Directory {base_dir} does not exist. No batch results to load.")
        return results

    for file_path in base_path.glob("scene_*.json"):
        try:
            with open(file_path, 'r') as f:
                data = json.load(f)
                results.append(data)
        except json.JSONDecodeError:
            logger.error(f"Failed to decode JSON in {file_path}")
        except Exception as e:
            logger.error(f"Error reading {file_path}: {e}")
    
    # Also try to load the summary report if it exists
    summary_path = base_path / "batch_summary.json"
    if summary_path.exists():
        try:
            with open(summary_path, 'r') as f:
                summary = json.load(f)
                # If summary contains a list of results, extend
                if isinstance(summary, list):
                    results.extend(summary)
                elif isinstance(summary, dict) and 'results' in summary:
                    results.extend(summary['results'])
        except Exception as e:
            logger.error(f"Error reading batch summary: {e}")

    return results

def aggregate_threshold_data(threshold_results_path: str) -> Dict[str, Any]:
    """
    Loads the threshold identification result from data/processed/threshold_result.json.
    """
    path = Path(threshold_results_path)
    if not path.exists():
        logger.warning(f"Threshold result file not found at {threshold_results_path}.")
        return {}
    
    try:
        with open(path, 'r') as f:
            return json.load(f)
    except Exception as e:
        logger.error(f"Error loading threshold results: {e}")
        return {}

def generate_final_batch_report(
    batch_results: List[Dict[str, Any]],
    threshold_data: Dict[str, Any],
    output_path: str = "data/processed/final_batch_report.json"
) -> Dict[str, Any]:
    """
    Integrates statistical results (thresholds) into the final batch report JSON.
    """
    report = {
        "meta": {
            "total_scenes_processed": len(batch_results),
            "threshold_analysis_included": bool(threshold_data)
        },
        "threshold_analysis": threshold_data,
        "scene_results": batch_results,
        "summary_stats": {}
    }

    # Compute basic summary stats from batch results if available
    if batch_results:
        view_counts = {}
        for res in batch_results:
            vc = res.get("view_count", "unknown")
            if vc not in view_counts:
                view_counts[vc] = {"count": 0, "psnr_sum": 0.0, "chamfer_sum": 0.0}
            view_counts[vc]["count"] += 1
            # Safely sum metrics if they exist
            if "psnr" in res and res["psnr"] is not None:
                view_counts[vc]["psnr_sum"] += float(res["psnr"])
            if "chamfer_distance" in res and res["chamfer_distance"] is not None:
                view_counts[vc]["chamfer_sum"] += float(res["chamfer_distance"])
        
        for vc, data in view_counts.items():
            count = data["count"]
            report["summary_stats"][str(vc)] = {
                "scenes": count,
                "avg_psnr": round(data["psnr_sum"] / count, 4) if count > 0 else None,
                "avg_chamfer": round(data["chamfer_sum"] / count, 4) if count > 0 else None
            }

    # Write to disk
    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    with open(output_file, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Final batch report written to {output_path}")
    return report

def main():
    """
    Entry point to generate the final batch report.
    1. Loads raw batch results.
    2. Loads statistical threshold analysis.
    3. Merges them into a single JSON report.
    """
    logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
    
    base_dir = "data/processed"
    threshold_file = os.path.join(base_dir, "threshold_result.json")
    output_file = os.path.join(base_dir, "final_batch_report.json")

    logger.info("Loading batch results...")
    batch_results = load_batch_results(base_dir)
    
    if not batch_results:
        logger.warning("No batch results found. Generating empty report structure.")
    
    logger.info("Loading threshold analysis...")
    threshold_data = aggregate_threshold_data(threshold_file)

    logger.info("Generating final integrated report...")
    report = generate_final_batch_report(batch_results, threshold_data, output_file)

    print(f"Report generated: {output_file}")
    print(f"Total scenes: {report['meta']['total_scenes_processed']}")
    if threshold_data:
        print(f"Identified Threshold View Count: {threshold_data.get('optimal_view_count', 'N/A')}")

if __name__ == "__main__":
    main()