def test_plot_script_execution():
    """Test that the script runs successfully."""
    # Ensure output is clean
    if OUTPUT_PATH.exists():
        OUTPUT_PATH.unlink()
    
    result = subprocess.run(
        [sys.executable, str(SCRIPT_PATH)],
        capture_output=True,
        text=True
    )
    
    assert result.returncode == 0, f"Script failed with: {result.stderr}"
    
def test_output_file_created():
    """Test that the output PNG file is created."""
    # Run the script first to ensure state
    subprocess.run([sys.executable, str(SCRIPT_PATH)], check=True)
    
    assert OUTPUT_PATH.exists(), f"Output file {OUTPUT_PATH} was not created."
    assert OUTPUT_PATH.stat().st_size > 0, "Output file is empty."
    
    # Verify it's a valid PNG (basic magic number check)
    with open(OUTPUT_PATH, 'rb') as f:
        header = f.read(8)
        assert header[:8] == b'\x89PNG\r\n\x1a\n', "File is not a valid PNG."

def test_plot_contains_expected_labels():
    """
    Test that the plot contains the expected labels by reopening the saved figure.
    This ensures the plot isn't just a blank canvas.
    """
    subprocess.run([sys.executable, str(SCRIPT_PATH)], check=True)
    
    # We can't easily read text from a PNG without OCR, but we can verify
    # the file size is reasonable for a plot with data points.
    # A blank 10x6 inch plot is usually > 10KB.
    size = OUTPUT_PATH.stat().st_size
    assert size > 5000, f"Plot file size ({size} bytes) seems too small for a populated plot."