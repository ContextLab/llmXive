def load_processed_corpus(corpus_path: Path) -> List[Dict[str, Any]]:
    """Load the tokenized JSONL corpus."""
    if not corpus_path.exists():
        raise FileNotFoundError(f"Processed corpus not found at {corpus_path}")
    
    corpus = []
    with open(corpus_path, 'r', encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if line:
                corpus.append(json.loads(line))
    return corpus

def verify_token_bounds(corpus: List[Dict[str, Any]], min_tokens: int = 1000000, max_tokens: int = 1010000) -> Dict[str, Any]:
    """
    Verify the total token count is within bounds.
    Returns a dict with check results.
    """
    total_tokens = sum(entry.get('token_count', 0) for entry in corpus)
    entry_count = len(corpus)
    
    # Calculate stats
    tokens_list = [entry.get('token_count', 0) for entry in corpus]
    avg_tokens = sum(tokens_list) / len(tokens_list) if tokens_list else 0
    min_entry_tokens = min(tokens_list) if tokens_list else 0
    max_entry_tokens = max(tokens_list) if tokens_list else 0

    passed = min_tokens <= total_tokens <= max_tokens

    return {
        "target_tokens": min_tokens + (max_tokens - min_tokens) // 2, # Approximate target
        "actual_tokens": total_tokens,
        "tolerance": (max_tokens - min_tokens) // 2,
        "min_bound": min_tokens,
        "max_bound": max_tokens,
        "passed": passed,
        "entry_count": entry_count,
        "avg_tokens_per_entry": round(avg_tokens, 2),
        "min_tokens_in_entry": min_entry_tokens,
        "max_tokens_in_entry": max_entry_tokens
    }

def compute_text_fingerprint(text: str) -> str:
    """Compute a SHA-256 fingerprint of a text string."""
    if not text:
        return ""
    return hashlib.sha256(text.encode('utf-8')).hexdigest()

def load_human_eval_samples() -> List[Dict[str, Any]]:
    """
    Load HumanEval samples.
    In a real execution, this would fetch from the 'evalplus/humaneval' dataset or a local file.
    We use the 'datasets' library to fetch the real source.
    """
    try:
        from datasets import load_dataset
        # Load the standard HumanEval dataset
        ds = load_dataset("openai_humaneval", split="test")
        return list(ds)
    except Exception as e:
        error(f"Failed to load HumanEval dataset: {e}")
        # If we cannot load it, we cannot verify exclusion. 
        # We must fail loudly as per constraints.
        raise RuntimeError("HumanEval dataset could not be loaded. Cannot verify exclusion.")

def load_corpus_samples(corpus: List[Dict[str, Any]], limit: int = 1000) -> List[str]:
    """
    Extract text content from corpus for fingerprinting.
    We check a sample of the corpus to ensure no overlap.
    """
    texts = []
    # Check first N entries and a random sample if corpus is large
    # For 1M tokens, the corpus might be manageable, but we sample to be safe on RAM.
    # The task requires verifying exclusion. We check all entries if feasible, or a robust sample.
    # Given the constraint of "fail loudly" and real data, we check all entries.
    # However, if the corpus is huge, checking all might be slow. 
    # The task says "ensure HumanEval data is excluded".
    # We will iterate through all entries to compute fingerprints.
    for entry in corpus:
        text = entry.get('text', '')
        if text:
            texts.append(text)
    return texts

def check_exclusion(corpus_texts: List[str], human_eval_samples: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Check for overlaps between corpus texts and HumanEval samples.
    Returns a dict with check results.
    """
    # Compute fingerprints for HumanEval samples
    human_eval_fps = set()
    for sample in human_eval_samples:
        # HumanEval samples have 'prompt' and 'canonical_solution'
        # We check the prompt primarily as it's the input
        prompt = sample.get('prompt', '')
        if prompt:
            human_eval_fps.add(compute_text_fingerprint(prompt))
        # Also check the full problem description if available
        # Some datasets have 'text' field
        full_text = sample.get('text', '')
        if full_text:
            human_eval_fps.add(compute_text_fingerprint(full_text))

    overlaps = []
    corpus_count = len(corpus_texts)
    checked_count = 0
    
    # Check every corpus entry
    for i, text in enumerate(corpus_texts):
        fp = compute_text_fingerprint(text)
        if fp in human_eval_fps:
            overlaps.append({
                "index": i,
                "fingerprint": fp
            })
        checked_count += 1
        if checked_count % 10000 == 0:
            info(f"Checked {checked_count} / {corpus_count} corpus entries...")

    passed = len(overlaps) == 0

    return {
        "passed": passed,
        "human_eval_count": len(human_eval_samples),
        "corpus_count": corpus_count,
        "corpus_samples_checked": checked_count,
        "overlaps_found": len(overlaps),
        "overlap_details": overlaps[:10]  # Log first 10 overlaps for debugging
    }

def verify_human_eval_exclusion(corpus: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Main function to verify HumanEval exclusion.
    """
    info("Loading HumanEval samples...")
    human_eval_samples = load_human_eval_samples()
    
    info("Extracting corpus texts...")
    corpus_texts = load_corpus_samples(corpus)
    
    info("Checking for overlaps...")
    return check_exclusion(corpus_texts, human_eval_samples)

def generate_validation_report(corpus: List[Dict[str, Any]], 
                               token_bounds_result: Dict[str, Any], 
                               human_eval_result: Dict[str, Any]) -> Dict[str, Any]:
    """Generate the full validation report."""
    overall_passed = token_bounds_result["passed"] and human_eval_result["passed"]
    overall_status = "PASSED" if overall_passed else "FAILED"
    
    report = {
        "validation_timestamp": time.strftime("%Y-%m-%dT%H:%M:%S.%f", time.gmtime()),
        "project_root": "projects/PROJ-864-llmxive-follow-up-extending-improved-lar",
        "overall_status": overall_status,
        "overall_passed": overall_passed,
        "checks": {
            "token_bounds": token_bounds_result,
            "human_eval_exclusion": human_eval_result
        },
        "summary": {
            "total_entries": token_bounds_result["entry_count"],
            "total_tokens": token_bounds_result["actual_tokens"],
            "human_eval_overlaps": human_eval_result["overlaps_found"],
            "ram_usage_gb": round(get_ram_usage_gb(), 2)
        }
    }
    return report

def save_validation_report(report: Dict[str, Any], output_path: Path):
    """Save the validation report to JSON."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)
    info(f"Validation report saved to {output_path}")

def main():
    """Main entry point for corpus validation."""
    setup_logging()
    info("Starting corpus validation...")
    
    # Paths
    project_root = Path("projects/PROJ-864-llmxive-follow-up-extending-improved-lar")
    corpus_path = project_root / "data" / "processed" / "micro_corpus_full.jsonl"
    output_path = project_root / "data" / "artifacts" / "corpus_validation.json"
    
    # 1. Load Corpus
    try:
        info(f"Loading processed corpus from {corpus_path}...")
        corpus = load_processed_corpus(corpus_path)
        info(f"Loaded {len(corpus)} entries.")
    except FileNotFoundError as e:
        error(f"Corpus file not found: {e}")
        sys.exit(1)
    except Exception as e:
        error(f"Error loading corpus: {e}")
        sys.exit(1)

    # 2. Verify Token Bounds
    info("Verifying token bounds...")
    token_bounds_result = verify_token_bounds(corpus)
    if token_bounds_result["passed"]:
        info(f"Token bounds check PASSED: {token_bounds_result['actual_tokens']} tokens.")
    else:
        error(f"Token bounds check FAILED: {token_bounds_result['actual_tokens']} tokens (Expected: {token_bounds_result['min_bound']} - {token_bounds_result['max_bound']}).")

    # 3. Verify HumanEval Exclusion
    info("Verifying HumanEval exclusion...")
    try:
        human_eval_result = verify_human_eval_exclusion(corpus)
        if human_eval_result["passed"]:
            info("HumanEval exclusion check PASSED.")
        else:
            error(f"HumanEval exclusion check FAILED: {human_eval_result['overlaps_found']} overlaps found.")
    except Exception as e:
        error(f"Error during HumanEval exclusion check: {e}")
        sys.exit(1)

    # 4. Generate and Save Report
    report = generate_validation_report(corpus, token_bounds_result, human_eval_result)
    save_validation_report(report, output_path)

    if report["overall_passed"]:
        info("Corpus validation completed successfully.")
        sys.exit(0)
    else:
        error("Corpus validation failed. Check the report for details.")
        sys.exit(1)

if __name__ == "__main__":
    main()