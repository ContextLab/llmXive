import os
import sys
import pytest
from pathlib import Path

# Add the code directory to the path for imports
sys.path.insert(0, str(Path(__file__).parent.parent / 'code'))

from setup_directories import create_directories, verify_directories, main

class TestSetupDirectories:
    """Test suite for directory initialization functionality."""

    def test_create_directories_creates_all_required(self):
        """Test that all required directories are created."""
        required_dirs = [
            'code',
            'code/utils',
            'data',
            'data/processed',
            'data/raw',
            'tests',
            'state',
            'state/projects'
        ]
        
        created = create_directories()
        
        for dir_path in required_dirs:
            assert Path(dir_path).exists(), f"Directory {dir_path} was not created"
            assert Path(dir_path).is_dir(), f"{dir_path} exists but is not a directory"

    def test_create_directories_idempotent(self):
        """Test that running create_directories twice doesn't cause errors."""
        # First run
        created1 = create_directories()
        # Second run
        created2 = create_directories()
        
        # Both should succeed and create the same set of directories
        assert len(created1) == len(created2)

    def test_verify_directories_raises_on_missing(self, tmp_path, monkeypatch):
        """Test that verify_directories raises FileNotFoundError when directories are missing."""
        # Change to temp directory
        monkeypatch.chdir(tmp_path)
        
        # Don't create any directories
        with pytest.raises(FileNotFoundError):
            verify_directories()

    def test_verify_directories_succeeds_when_present(self):
        """Test that verify_directories succeeds when all directories exist."""
        # Ensure directories exist
        create_directories()
        
        # Should not raise
        output = verify_directories()
        
        # Output should contain directory names
        assert 'data' in output
        assert 'code' in output
        assert 'tests' in output
        assert 'state' in output

    def test_main_creates_checksums_file(self):
        """Test that main() creates data/checksums.txt."""
        # Remove existing file if present
        checksums_path = Path('data/checksums.txt')
        if checksums_path.exists():
            checksums_path.unlink()
        
        # Run main
        main()
        
        # Check file exists
        assert checksums_path.exists(), "data/checksums.txt was not created"
        
        # Check file has content
        with open(checksums_path, 'r') as f:
            content = f.read()
        
        assert len(content) > 0, "data/checksums.txt is empty"
        assert 'Directory Structure Verification' in content
        assert 'data' in content
        assert 'code' in content
        assert 'tests' in content
        assert 'state' in content

    def test_checksums_file_format(self):
        """Test that checksums.txt has the expected format."""
        # Ensure file exists
        main()
        
        with open('data/checksums.txt', 'r') as f:
            content = f.read()
        
        # Check for expected headers
        assert '# Directory Structure Verification' in content
        assert '# Generated by: T001' in content
        assert '# Command: ls -R' in content

    def test_directory_structure_in_checksums(self):
        """Test that the directory listing is actually captured in checksums.txt."""
        # Ensure file exists
        main()
        
        with open('data/checksums.txt', 'r') as f:
            content = f.read()
        
        # Check that subdirectories are listed
        assert 'data/processed' in content or 'data/processed:' in content
        assert 'data/raw' in content or 'data/raw:' in content
        assert 'code/utils' in content or 'code/utils:' in content
        assert 'state/projects' in content or 'state/projects:' in content
