"""Contract test ensuring that each intent JSON file conforms to the expected schema.

The schema lives in ``specs/001-evaluating-the-use-of-llms-for-automated/contracts/intententity.schema.yaml``.
"""
from __future__ import annotations

import json
import pathlib

import jsonschema
import yaml

from llmxive_toolkit import paths

SCHEMA_PATH = pathlib.Path(
    "specs/001-evaluating-the-use-of-llms-for-automated/contracts/intententity.schema.yaml"
)

def load_schema() -> dict:
    with SCHEMA_PATH.open("r", encoding="utf-8") as f:
        return yaml.safe_load(f)

def test_intent_json_schema(tmp_path):
    # Locate a sample intent JSON file (generated by the pipeline).
    intent_dir = paths.data("intermediate", "intent_entities")
    json_files = list(intent_dir.glob("*.json"))
    assert json_files, "No intent JSON files found – run the extraction first."

    schema = load_schema()
    for jf in json_files:
        with jf.open("r", encoding="utf-8") as f:
            instance = json.load(f)
        # Basic structural checks via jsonschema.
        try:
            jsonschema.validate(instance=instance, schema=schema)
        except jsonschema.ValidationError as e:
            raise AssertionError(f"{jf} fails schema validation: {e}") from e