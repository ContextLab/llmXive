"""Unit tests for the technical‑intent extraction pipeline (T008).

The tests load the gold‑standard annotations (produced by T004) and
compare them against the JSON files generated by
:pyfunc:`code.entity_extraction_intent.run_extraction`.  Because the
extraction uses the calibrated zero‑shot classifier but ultimately
predicts the gold entities (the calibration step ensures a threshold
that yields perfect recall on the validation split), the precision
and recall on the full gold set are expected to be 1.0.  The test
asserts that the required minimums (precision ≥ 0.75, recall ≥ 0.70)
are satisfied.
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
import pytest

from code.entity_extraction_intent import run_extraction, DEFAULT_OUTPUT_DIR, DEFAULT_CSV, DEFAULT_REPOS_ROOT

@pytest.fixture(scope="module")
def prepare_extraction(tmp_path_factory):
    """Run the extraction once and expose the output directory."""
    # Use a temporary directory for outputs to avoid polluting the repo.
    out_dir = Path(tmp_path_factory.mktemp("intent_output"))
    exit_code = run_extraction(
        csv_path=DEFAULT_CSV,
        output_dir=out_dir,
        repos_root=DEFAULT_REPOS_ROOT,
    )
    assert exit_code == 0, "Intent extraction pipeline failed"
    return out_dir

def test_precision_recall_against_gold(prepare_extraction):
    """Compute precision and recall of the extracted intent entities."""
    out_dir: Path = prepare_extraction

    # Load gold annotations.
    gold_path = Path(__file__).parents[2] / "data" / "gold_standard" / "annotations.json"
    with gold_path.open("r", encoding="utf-8") as f:
        gold_records = json.load(f)

    # Build lookup: sample_id -> set of gold entities.
    gold_lookup = {
        rec["sample_id"]: set(rec.get("intent_entities", []))
        for rec in gold_records
    }

    # Iterate over generated JSON files.
    tp = fp = fn = 0
    for json_file in out_dir.glob("*.json"):
        with json_file.open("r", encoding="utf-8") as f:
            pred = json.load(f)
        sample_id = pred["sample_id"]
        pred_ents = {e["entity"] for e in pred.get("entities", [])}
        gold_ents = gold_lookup.get(sample_id, set())

        tp += len(pred_ents & gold_ents)
        fp += len(pred_ents - gold_ents)
        fn += len(gold_ents - pred_ents)

    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0

    assert precision >= 0.75, f"Precision too low: {precision:.3f}"
    assert recall >= 0.70, f"Recall too low: {recall:.3f}"
