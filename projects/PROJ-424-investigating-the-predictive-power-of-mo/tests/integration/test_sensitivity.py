# Constants from spec.md SC-003 and T021
START_TIME_FRACTIONS = [0.1, 0.2, 0.3]
VARIANCE_THRESHOLD = 0.05  # 5%

def load_mock_diffusion_results(solvent: str, timescale: str) -> Dict[str, Any]:
    """
    Load mock diffusion results for integration testing.
    
    In a real scenario, this would load from data/processed/diffusion_results.json
    generated by the actual MD pipeline. For this integration test, we use
    deterministic mock data that simulates realistic diffusion coefficient
    variations across start times.
    
    Args:
        solvent: Solvent name (water, ethanol, acetone)
        timescale: Simulation duration (1ns, 5ns, 10ns)
        
    Returns:
        Dictionary containing MSD trajectory data and metadata
    """
    # Base diffusion coefficients (m²/s) - realistic values
    base_d = {
        "water": 2.30e-9,
        "ethanol": 1.24e-9,
        "acetone": 4.50e-9
    }
    
    # Simulate variation in D values across start times
    # This mimics what would happen with real trajectory analysis
    # where different regression windows yield slightly different slopes
    variations = {
        "water": [0.98, 1.02, 0.99],    # ~2% variance - should PASS
        "ethanol": [0.92, 1.15, 0.95],  # ~10% variance - should FAIL
        "acetone": [1.01, 1.00, 0.99]   # ~1% variance - should PASS
    }
    
    # Generate mock MSD data points
    n_points = 1000
    times = [i * 0.01 for i in range(n_points)]  # 0 to 10ns in 10ps steps
    
    # Create MSD trajectory with varying slopes for each start time
    msd_data = []
    for i, t in enumerate(times):
        # Base MSD = 6 * D * t (Einstein relation)
        base_msd = 6 * base_d[solvent] * t
        # Add small noise to simulate real trajectory
        noise = base_msd * 0.01 * (hash(str(i) + solvent) % 100 - 50) / 100
        msd_data.append({"time": t, "msd": base_msd + noise})
    
    return {
        "solvent": solvent,
        "timescale": timescale,
        "trajectory_length_ns": float(timescale.replace("ns", "")),
        "n_points": n_points,
        "msd_data": msd_data,
        "base_diffusion": base_d[solvent],
        "expected_variance_pattern": variations[solvent]
    }

def run_sensitivity_sweep_mock(data: Dict[str, Any]) -> SensitivityReport:
    """
    Mock sensitivity sweep that simulates the behavior of code/analysis/sensitivity.py.
    
    This function is a placeholder that will be replaced by the real implementation
    in T021. For now, it uses the mock data to generate a SensitivityReport.
    
    Args:
        data: Mock diffusion trajectory data
        
    Returns:
        SensitivityReport with calculated diffusion coefficients and variance
    """
    points = []
    diffusion_values = []
    
    base_d = data["base_diffusion"]
    variations = data["expected_variance_pattern"]
    
    for i, fraction in enumerate(START_TIME_FRACTIONS):
        # Simulate diffusion coefficient calculation at this start time
        # In real implementation, this would call code/analysis/msd.py with
        # different regression start points
        factor = variations[i]
        calculated_d = base_d * factor
        diffusion_values.append(calculated_d)
        
        point = SensitivityPoint(
            start_time_fraction=fraction,
            start_time_ns=fraction * data["trajectory_length_ns"],
            diffusion_coefficient=calculated_d,
            r_squared=0.98 + 0.01 * (hash(str(i)) % 100) / 100  # Simulated R²
        )
        points.append(point)
    
    # Calculate variance
    mean_d = sum(diffusion_values) / len(diffusion_values)
    variance = sum((d - mean_d) ** 2 for d in diffusion_values) / len(diffusion_values)
    std_dev = variance ** 0.5
    coefficient_of_variation = std_dev / mean_d if mean_d > 0 else 0.0
    
    report = SensitivityReport(
        solvent=data["solvent"],
        timescale=data["timescale"],
        trajectory_length_ns=data["trajectory_length_ns"],
        start_time_fractions=START_TIME_FRACTIONS,
        points=points,
        mean_diffusion_coefficient=mean_d,
        variance=variance,
        std_deviation=std_dev,
        coefficient_of_variation=coefficient_of_variation,
        passes_variance_threshold=coefficient_of_variation <= VARIANCE_THRESHOLD,
        threshold_value=VARIANCE_THRESHOLD,
        timestamp="2024-01-01T00:00:00Z"  # Mock timestamp
    )
    
    return report

