class TestVarianceThresholdCheck:
    """
    Integration tests for variance threshold check in sensitivity analysis.
    
    These tests verify that the sensitivity analysis correctly identifies
    when the variance in diffusion coefficients exceeds the 5% threshold.
    """
    
    def test_water_passes_variance_threshold(self, mock_water_data):
        """
        Test that water data (low variance) passes the threshold check.
        
        Expected: coefficient_of_variation < 0.05, passes_variance_threshold = True
        """
        logger.info("Testing water variance threshold check...")
        
        report = run_sensitivity_sweep_mock(mock_water_data)
        
        # Verify report structure
        assert report.solvent == "water"
        assert report.timescale == "10ns"
        assert len(report.points) == len(START_TIME_FRACTIONS)
        
        # Verify variance check
        assert report.coefficient_of_variation < VARIANCE_THRESHOLD, \
            f"Water CV {report.coefficient_of_variation:.4f} should be < {VARIANCE_THRESHOLD}"
        assert report.passes_variance_threshold is True, \
            "Water should pass variance threshold"
        
        logger.info(f"Water variance check PASSED: CV={report.coefficient_of_variation:.4f}")

    def test_ethanol_fails_variance_threshold(self, mock_ethanol_data):
        """
        Test that ethanol data (high variance) fails the threshold check.
        
        Expected: coefficient_of_variation > 0.05, passes_variance_threshold = False
        """
        logger.info("Testing ethanol variance threshold check...")
        
        report = run_sensitivity_sweep_mock(mock_ethanol_data)
        
        # Verify report structure
        assert report.solvent == "ethanol"
        assert report.timescale == "10ns"
        assert len(report.points) == len(START_TIME_FRACTIONS)
        
        # Verify variance check - this should FAIL before T021 implementation
        assert report.coefficient_of_variation >= VARIANCE_THRESHOLD, \
            f"Ethanol CV {report.coefficient_of_variation:.4f} should be >= {VARIANCE_THRESHOLD}"
        assert report.passes_variance_threshold is False, \
            "Ethanol should fail variance threshold"
        
        logger.info(f"Ethanol variance check FAILED (as expected): CV={report.coefficient_of_variation:.4f}")

    def test_acetone_passes_variance_threshold(self, mock_acetone_data):
        """
        Test that acetone data (low variance) passes the threshold check.
        
        Expected: coefficient_of_variation < 0.05, passes_variance_threshold = True
        """
