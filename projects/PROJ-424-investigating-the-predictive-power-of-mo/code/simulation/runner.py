@dataclass
class SimulationResult:
    """Result of a simulation run."""
    solvent: str
    duration_ns: float
    success: bool
    timeout: bool
    equilibrated: bool
    final_density_g_cm3: Optional[float] = None
    density_variance: Optional[float] = None
    output_files: List[str] = None
    error_message: Optional[str] = None
    checksums: Dict[str, str] = None
    timestamp: str = None

    def __post_init__(self):
        if self.output_files is None:
            self.output_files = []
        if self.checksums is None:
            self.checksums = {}
        if self.timestamp is None:
            self.timestamp = datetime.now().isoformat()

def _generate_mdp_file(config: SimulationConfig, output_dir: Path) -> Path:
    """
    Generate the .mdp (molecular dynamics parameters) file for GROMACS.
    Creates NPT production parameters.
    """
    mdp_path = output_dir / "production.mdp"
    
    # Map config to GROMACS parameters
    dt = 0.02  # 20 fs in ps
    nsteps = int(config.duration_ns * 1000 / dt)  # duration in ns -> steps
    
    mdp_content = f"""
    ; Molecular Dynamics Parameters
    ; Generated by runner.py
    ; Date: {datetime.now().isoformat()}
    
    integrator          = md
    dt                  = {dt}
    nsteps              = {nsteps}
    comm-mode           = Linear
    nstcomm             = 1
    
    ; Output Control
    nstxout             = 1000
    nstvout             = 1000
    nstenergy           = 100
    nstlog              = 100
    
    ; Neighbor Searching
    ns_type             = grid
    nstlist             = 10
    rlist               = 1.2
    
    ; Electrostatics
    coulombtype         = PME
    rcoulomb            = 1.2
    rvdw                = 1.2
    
    ; Temperature Coupling
    tcoupl              = V-rescale
    tc-grps             = System
    tau_t               = 0.1
    ref_t               = {config.temperature_k}
    
    ; Pressure Coupling (NPT)
    pcoupl              = Parrinello-Rahman
    pcoupltype          = isotropic
    tau_p               = 2.0
    ref_p               = 1.0
    compressibility     = 4.5e-5
    
    ; Constraints
    constraints         = h-bonds
    constraint_algorithm = lincs
    lincs_iter          = 1
    lincs_order         = 4
    
    ; Dispersion Correction
    DispCorr            = EnerPres
    """
    
    with open(mdp_path, 'w') as f:
        f.write(mdp_content)
    
    logger.info(f"Generated mdp file: {mdp_path}")
    return mdp_path

def _generate_index_file(output_dir: Path) -> Path:
    """
    Generate a simple index file for GROMACS.
    """
    index_path = output_dir / "index.ndx"
    # Minimal index file with a "System" group
    content = """[ System ]
    1
    """
    with open(index_path, 'w') as f:
        f.write(content)
    return index_path

def _run_gromacs_command(cmd: List[str], timeout_sec: int, cwd: Path) -> Tuple[int, str, str]:
    """
    Execute a GROMACS command with timeout and capture output.
    Returns (returncode, stdout, stderr).
    """
    try:
        process = subprocess.run(
            cmd,
            cwd=cwd,
            capture_output=True,
            text=True,
            timeout=timeout_sec,
            start_new_session=True
        )
        return process.returncode, process.stdout, process.stderr
    except subprocess.TimeoutExpired as e:
        # Kill the process group
        try:
            os.killpg(os.getpgid(e.pid), signal.SIGKILL)
        except (ProcessLookupError, PermissionError):
            pass
        logger.error(f"Simulation timed out after {timeout_sec}s")
        return -1, "", "Timeout expired"
    except Exception as e:
        logger.error(f"Error running GROMACS command: {e}")
        return -2, "", str(e)

