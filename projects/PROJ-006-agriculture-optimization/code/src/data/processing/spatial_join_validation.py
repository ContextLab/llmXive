from src.utils.io_helpers import setup_logging, load_json_strict, read_csv_strict

# Configure logger
logger = setup_logging("spatial_join_validation")


def load_linkage_validation(log_path: Path) -> Dict[str, Any]:
    """
    Loads the linkage validation JSON file generated by T017 (spatial_join.py).

    Args:
        log_path: Path to data/logs/linkage_validation.json

    Returns:
        Dictionary containing linkage metrics.

    Raises:
        FileNotFoundError: If the log file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    if not log_path.exists():
        raise FileNotFoundError(f"Linkage validation log not found at {log_path}")
    
    logger.info(f"Loading linkage validation log from {log_path}")
    return load_json_strict(log_path)


def count_valid_households_in_raw_survey(survey_path: Path) -> int:
    """
    Counts the number of rows in the raw survey data that have non-null latitude and longitude.
    
    Definition: total_valid_households = count of records with non-null coordinates 
    in data/raw/survey_raw.csv.

    Args:
        survey_path: Path to data/raw/survey_raw.csv

    Returns:
        Integer count of valid households.
    
    Raises:
        FileNotFoundError: If the survey file does not exist.
        ValueError: If required columns are missing.
    """
    if not survey_path.exists():
        raise FileNotFoundError(f"Raw survey data not found at {survey_path}")

    logger.info(f"Reading raw survey data from {survey_path} to count valid households")
    df = read_csv_strict(survey_path)

    required_cols = ['latitude', 'longitude']
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in raw survey: {missing_cols}")

    # Count rows where both latitude and longitude are not null
    valid_mask = df['latitude'].notna() & df['longitude'].notna()
    count = valid_mask.sum()
    
    logger.info(f"Found {count} valid households with non-null coordinates in raw survey")
    return int(count)


def count_matched_households(joined_path: Path, survey_path: Path) -> int:
    """
    Counts the number of households in the spatial_joined_data.csv that exist in the raw survey.
    
    Logic Detail: matched households = count of rows in spatial_joined_data.csv 
    where household_id exists in survey_raw.csv.

    Args:
        joined_path: Path to data/processed/spatial_joined_data.csv
        survey_path: Path to data/raw/survey_raw.csv

    Returns:
        Integer count of matched households.
    """
    if not joined_path.exists():
        raise FileNotFoundError(f"Spatial joined data not found at {joined_path}")
    if not survey_path.exists():
        raise FileNotFoundError(f"Raw survey data not found at {survey_path}")

    logger.info(f"Calculating matched households between {joined_path} and {survey_path}")
    
    df_joined = read_csv_strict(joined_path)
    df_survey = read_csv_strict(survey_path)

    if 'household_id' not in df_joined.columns:
        raise ValueError("spatial_joined_data.csv missing 'household_id' column")
    if 'household_id' not in df_survey.columns:
        raise ValueError("survey_raw.csv missing 'household_id' column")

    survey_ids = set(df_survey['household_id'].dropna().astype(str))
    matched_count = 0

    for _, row in df_joined.iterrows():
        if pd.notna(row['household_id']):
            if str(row['household_id']) in survey_ids:
                matched_count += 1

    logger.info(f"Found {matched_count} matched households")
    return matched_count


