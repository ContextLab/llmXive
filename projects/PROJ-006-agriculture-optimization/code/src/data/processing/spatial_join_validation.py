def run_validation(config: Dict[str, Any]) -> Dict[str, Any]:
    """
    Main validation logic for T017c.
    
    Reads data/logs/linkage_validation.json (output of T017).
    Calculates linkage percentage = (matched households / total_valid_households).
    
    Error Handling:
    - If total_valid_households is 0: Log FATAL_NO_HOUSEHOLDS and exit immediately.
    - If triggered_aggregation is true in the log: Trigger aggregation routine (T021).
    - If triggered_aggregation is false: Log success.
    
    Args:
        config: Dictionary containing paths and thresholds.
               Expected keys: 'survey_path', 'joined_path', 'log_path', 'linkage_threshold'
    
    Returns:
        Dictionary with validation results.
    """
    survey_path = Path(config['survey_path'])
    joined_path = Path(config['joined_path'])
    log_path = Path(config['log_path'])
    linkage_threshold = config.get('linkage_threshold', 0.95)

    logger.info("Starting Spatial Join Validation (T017c)...")

    # 1. Load linkage validation log from T017
    try:
        linkage_log = load_linkage_validation(log_path)
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)

    # 2. Count total valid households in raw survey
    try:
        total_valid_households = count_valid_households_in_raw_survey(survey_path)
    except (FileNotFoundError, ValueError) as e:
        logger.error(str(e))
        sys.exit(1)

    # 3. FATAL_ERROR: No households
    if total_valid_households == 0:
        logger.critical("FATAL_NO_HOUSEHOLDS: No households with valid coordinates found in raw survey.")
        sys.exit(1)

    # 4. Count matched households
    try:
        matched_households = count_matched_households(joined_path, survey_path)
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)

    # 5. Calculate linkage percentage
    linkage_percentage = (matched_households / total_valid_households) * 100
    logger.info(f"Linkage Percentage: {linkage_percentage:.2f}% ({matched_households}/{total_valid_households})")

    # 6. Check existing triggered_aggregation flag from T017 log
    # The task description says: "If triggered_aggregation is true in the log, trigger the aggregation routine"
    # It also implies we calculate linkage to verify if the trigger was correct or if we need to trigger it now.
    # However, T017 is supposed to write the log. T017c reads it.
    # If T017 failed to write the log correctly, we might need to recalculate the trigger condition.
    # But per spec: "Read data/logs/linkage_validation.json... If triggered_aggregation is true... trigger..."
    
    triggered_aggregation = linkage_log.get('triggered_aggregation', False)
    
    # We also check our calculated linkage percentage against the threshold to ensure consistency
    # If the log says false but our calc says < 95%, we should probably trigger it (or at least log a warning).
    # But the strict instruction is: "If triggered_aggregation is true in the log, trigger..."
    # Let's follow the log's instruction primarily, but log our own calc.
    
    if linkage_percentage < (linkage_threshold * 100):
        logger.warning(f"Calculated linkage ({linkage_percentage:.2f}%) is below threshold ({linkage_threshold*100}%).")
        if not triggered_aggregation:
            logger.warning("Discrepancy: Log does not indicate aggregation, but linkage is low. Triggering aggregation.")
            triggered_aggregation = True

    if triggered_aggregation:
        logger.info("Aggregation Trigger Condition Met.")
        trigger_aggregation_routine()
        # Return status indicating aggregation was triggered
        return {
            "status": "aggregation_triggered",
            "linkage_percentage": linkage_percentage,
            "total_valid_households": total_valid_households,
            "matched_households": matched_households
        }
    else:
        logger.info("Linkage validation successful. No aggregation required.")
        return {
            "status": "success",
            "linkage_percentage": linkage_percentage,
            "total_valid_households": total_valid_households,
            "matched_households": matched_households
        }


def main():
    """CLI entry point for T017c."""
    parser = argparse.ArgumentParser(description="T017c: Perform Spatial Join Validation and Aggregation Trigger")
    parser.add_argument(
        "--survey-path", 
        type=str, 
        default="data/raw/survey_raw.csv",
        help="Path to raw survey CSV"
    )
    parser.add_argument(
        "--joined-path", 
        type=str, 
        default="data/processed/spatial_joined_data.csv",
        help="Path to spatial joined CSV"
    )
    parser.add_argument(
        "--log-path", 
        type=str, 
        default="data/logs/linkage_validation.json",
        help="Path to linkage validation JSON"
    )
    parser.add_argument(
        "--linkage-threshold", 
        type=float, 
        default=0.95,
        help="Minimum linkage percentage (0.0-1.0)"
    )
    parser.add_argument(
        "--log-level", 
        type=str, 
        default="INFO",
        choices=["DEBUG", "INFO", "WARNING", "ERROR", "CRITICAL"],
        help="Logging level"
    )

    args = parser.parse_args()

    # Re-configure logger with the specified level
    global logger
    logger = setup_logging("spatial_join_validation", level=args.log_level)

    config = {
        "survey_path": args.survey_path,
        "joined_path": args.joined_path,
        "log_path": args.log_path,
        "linkage_threshold": args.linkage_threshold
    }

    try:
        result = run_validation(config)
        logger.info(f"Validation completed with status: {result['status']}")
        sys.exit(0)
    except Exception as e:
        logger.error(f"Validation failed with error: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()