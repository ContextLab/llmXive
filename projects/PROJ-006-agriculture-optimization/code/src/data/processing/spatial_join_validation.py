"""
Spatial Join Validation Module (T017c).

This module implements the logic to validate spatial linkage results,
calculate linkage percentages, and trigger aggregation routines if necessary.
It acts as the gatekeeper between spatial joining (T017) and feature engineering (T018b/T021).
"""
import argparse
