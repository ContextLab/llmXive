import os
import sys
import logging
import json
from pathlib import Path
from typing import List, Dict, Any, Optional

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from data.graph_build import run_topology_audit
from utils.exceptions import DataError

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def load_graph_stats(graphs_path: Path) -> Dict[str, Any]:
    """
    Load graph statistics from the topology audit run by graph_build.py.
    Expects a JSON file generated by run_topology_audit or similar process.
    """
    audit_json_path = graphs_path.parent / "topology_audit_stats.json"
    
    if not audit_json_path.exists():
        # If the JSON doesn't exist, we try to run the audit again or raise error
        # Based on T022, graph_build.py should have generated this or the graphs.pt
        # We assume graph_build.py (T022) generated this file during its execution
        raise DataError(f"Topology audit stats file not found at {audit_json_path}. "
                        f"Ensure code/data/graph_build.py has been executed successfully.")
    
    with open(audit_json_path, 'r') as f:
        return json.load(f)

def generate_markdown_report(stats: Dict[str, Any], output_path: Path) -> None:
    """
    Generate a markdown report from the topology statistics.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    report_lines = [
        "# Topology Audit Report",
        "",
        "This report summarizes the topological properties of the molecular graphs",
        "constructed for the polymer-filler interface prediction task (US2).",
        "",
        "## Summary Statistics",
        "",
        f"- **Total Graphs Processed**: {stats.get('total_graphs', 0)}",
        f"- **Total Nodes**: {stats.get('total_nodes', 0)}",
        f"- **Total Edges**: {stats.get('total_edges', 0)}",
        f"- **Average Nodes per Graph**: {stats.get('avg_nodes_per_graph', 0):.2f}",
        f"- **Average Edges per Graph**: {stats.get('avg_edges_per_graph', 0):.2f}",
        "",
        "## Pruning Statistics",
        "",
        "Pruning operations performed during graph construction:",
        "",
    ]
    
    pruning_stats = stats.get('pruning_stats', {})
    if pruning_stats:
        report_lines.append(f"- **Nodes Removed**: {pruning_stats.get('nodes_removed', 0)}")
        report_lines.append(f"- **Edges Removed**: {pruning_stats.get('edges_removed', 0)}")
        report_lines.append(f"- **Graphs Pruned**: {pruning_stats.get('graphs_pruned', 0)}")
    else:
        report_lines.append("- No pruning operations recorded.")
        
    report_lines.append("")
    report_lines.append("## Per-Graph Breakdown")
    report_lines.append("")
    report_lines.append("| Graph ID | Nodes | Edges | Is Valid |")
    report_lines.append("| :--- | :--- | :--- | :--- |")
    
    graph_details = stats.get('graph_details', [])
    for g in graph_details:
        report_lines.append(
            f"| {g.get('graph_id', 'N/A')} | {g.get('nodes', 0)} | "
            f"{g.get('edges', 0)} | {g.get('is_valid', 'N/A')} |"
        )
        
    report_lines.append("")
    report_lines.append("## Notes")
    report_lines.append("")
    report_lines.append("- Graphs were constructed from SMILES strings using RDKit.")
    report_lines.append("- Interface pairs were modeled as heterogeneous graphs.")
    report_lines.append("- Pruning rules: Remove isolated nodes and disconnected components if any.")
    report_lines.append("")
    report_lines.append(f"*Report generated on: {stats.get('generated_at', 'N/A')}*")
    
    with open(output_path, 'w') as f:
        f.write('\n'.join(report_lines))
    
    logger.info(f"Topology audit report generated at {output_path}")

def main():
    """
    Main entry point for generating the topology audit report.
    Reads stats from the graph_build output and writes analysis/topology_audit.md.
    """
    # Define paths
    curated_path = PROJECT_ROOT / "data" / "curated" / "curated_dataset.csv"
    graphs_path = PROJECT_ROOT / "data" / "processed" / "graphs.pt"
    output_path = PROJECT_ROOT / "analysis" / "topology_audit.md"
    
    if not curated_path.exists():
        raise DataError(f"Input curated dataset not found at {curated_path}. "
                        f"Please run code/data/clean.py and code/data/generate_curated.py first.")
    
    if not graphs_path.exists():
        # Attempt to run the graph build process first if graphs are missing
        logger.warning(f"Graphs not found at {graphs_path}. Attempting to run graph_build.py...")
        try:
            # Import and run the main function from graph_build
            from data.graph_build import main as graph_build_main
            graph_build_main()
        except Exception as e:
            raise DataError(f"Failed to generate graphs automatically: {e}")
    
    # Load stats
    try:
        stats = load_graph_stats(graphs_path)
    except DataError as e:
        # If stats file is missing, try to regenerate it by running graph_build again
        logger.warning("Stats file missing. Re-running graph_build to generate stats...")
        from data.graph_build import main as graph_build_main
        graph_build_main()
        stats = load_graph_stats(graphs_path)
    
    # Generate report
    generate_markdown_report(stats, output_path)
    
    logger.info("Topology audit task completed successfully.")

if __name__ == "__main__":
    main()
