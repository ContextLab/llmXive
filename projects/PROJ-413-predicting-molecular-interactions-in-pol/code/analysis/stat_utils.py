"""
Statistical utilities for permutation test analysis.

Implements:
- Calculation of the 0.95 quantile of permuted baseline MSEs
- Computation of p-value for the observed model MSE
"""
import os
import sys
import csv
import logging
from pathlib import Path
from typing import List, Optional, Tuple
import numpy as np

# Project root relative to this file
PROJECT_ROOT = Path(__file__).parent.parent.parent
RESULTS_DIR = PROJECT_ROOT / "results"
PERMUTED_MSES_FILE = RESULTS_DIR / "permuted_mses.csv"

logger = logging.getLogger(__name__)


def load_permuted_mses(file_path: Optional[Path] = None) -> List[float]:
    """
    Load permuted MSE values from the CSV file generated by T033.
    
    Args:
        file_path: Path to permuted_mses.csv. Defaults to RESULTS_DIR/permuted_mses.csv.
        
    Returns:
        List of float MSE values.
        
    Raises:
        FileNotFoundError: If the file does not exist.
        ValueError: If the file is empty or contains invalid data.
    """
    if file_path is None:
        file_path = PERMUTED_MSES_FILE
        
    if not file_path.exists():
        raise FileNotFoundError(
            f"Permutation results file not found: {file_path}. "
            "Ensure T033 (perm_test.py) has been executed successfully."
        )
    
    mses = []
    with open(file_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        # Expect a column named 'mse' or 'permuted_mse' based on T033 output
        # We handle both common naming conventions
        if reader.fieldnames is None:
            raise ValueError(f"CSV file {file_path} is empty or has no headers.")
        
        # Find the column containing the MSE values
        mse_col = None
        for col in reader.fieldnames:
            if 'mse' in col.lower():
                mse_col = col
                break
        
        if mse_col is None:
            raise ValueError(
                f"Could not find an 'mse' column in {file_path}. "
                f"Available columns: {reader.fieldnames}"
            )
        
        for row in reader:
            try:
                val = float(row[mse_col])
                mses.append(val)
            except (ValueError, TypeError) as e:
                raise ValueError(f"Invalid MSE value '{row[mse_col]}' in row: {row}") from e
    
    if not mses:
        raise ValueError(f"No valid MSE values found in {file_path}.")
        
    return mses


def calculate_quantile_95(mses: List[float]) -> float:
    """
    Calculate the 0.95 (95th) quantile of the permuted MSE distribution.
    
    This value serves as the critical threshold for significance testing.
    If the observed model MSE is lower than this quantile, the model
    performs significantly better than random chance at the 0.05 level.
    
    Args:
        mses: List of permuted MSE values.
        
    Returns:
        The 0.95 quantile value.
    """
    if not mses:
        raise ValueError("Cannot calculate quantile of empty list.")
    
    return float(np.quantile(mses, 0.95))


def calculate_p_value(observed_mse: float, permuted_mses: List[float]) -> float:
    """
    Calculate the one-sided p-value for the observed MSE against the permuted distribution.
    
    The null hypothesis (H0) is that the model's performance is no better than random.
    The alternative hypothesis (H1) is that the model performs better (lower MSE).
    
    p-value = (count of permuted MSEs <= observed MSE + 1) / (N + 1)
    
    Note: We use the (k+1)/(N+1) estimator to avoid a p-value of exactly 0.
    
    Args:
        observed_mse: The MSE of the trained model on the real data.
        permuted_mses: List of MSEs from the permutation test.
        
    Returns:
        The calculated p-value.
    """
    if not permuted_mses:
        raise ValueError("Cannot calculate p-value with empty permutation list.")
    
    n = len(permuted_mses)
    # Count how many permuted results are as good or better (lower MSE) than observed
    # Note: Lower MSE is better.
    count_better_or_equal = sum(1 for m in permuted_mses if m <= observed_mse)
    
    # P-value calculation with correction to avoid 0
    p_val = (count_better_or_equal + 1) / (n + 1)
    
    return float(p_val)


def analyze_permutation_results(observed_mse: float, output_file: Optional[Path] = None) -> Tuple[float, float]:
    """
    Main analysis function: loads permuted MSEs, calculates 0.95 quantile and p-value.
    
    Args:
        observed_mse: The MSE of the trained model (from T028).
        output_file: Optional path to save a summary JSON. Defaults to None.
        
    Returns:
        Tuple of (quantile_95, p_value).
    """
    logger.info(f"Loading permuted MSEs from {PERMUTED_MSES_FILE}...")
    permuted_mses = load_permuted_mses()
    logger.info(f"Loaded {len(permuted_mses)} permuted MSE values.")
    
    logger.info("Calculating 0.95 quantile...")
    quantile_95 = calculate_quantile_95(permuted_mses)
    logger.info(f"95th Quantile: {quantile_95:.6f}")
    
    logger.info("Calculating p-value...")
    p_value = calculate_p_value(observed_mse, permuted_mses)
    logger.info(f"Observed MSE: {observed_mse:.6f}")
    logger.info(f"P-value: {p_value:.6f}")
    
    if output_file:
        import json
        output_file.parent.mkdir(parents=True, exist_ok=True)
        summary = {
            "observed_mse": observed_mse,
            "quantile_95": quantile_95,
            "p_value": p_value,
            "n_permutations": len(permuted_mses),
            "significant_at_0.05": p_value < 0.05,
            "observed_better_than_95pct": observed_mse < quantile_95
        }
        with open(output_file, 'w', encoding='utf-8') as f:
            json.dump(summary, f, indent=2)
        logger.info(f"Analysis summary saved to {output_file}")
        
    return quantile_95, p_value


def main():
    """
    CLI entry point for statistical analysis of permutation test.
    
    Usage:
        python code/analysis/stat_utils.py --observed-mse <float> [--output <path>]
        
    If --observed-mse is not provided, it attempts to load it from a known location
    or prompts the user. For automation, it is best to pass the value explicitly.
    """
    import argparse
    
    parser = argparse.ArgumentParser(description="Analyze permutation test results.")
    parser.add_argument(
        "--observed-mse", 
        type=float, 
        required=True,
        help="The observed MSE from the trained model (T028)."
    )
    parser.add_argument(
        "--output",
        type=str,
        default=str(RESULTS_DIR / "perm_test_summary.json"),
        help="Path to save the analysis summary JSON."
    )
    
    args = parser.parse_args()
    
    # Configure logging
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    try:
        quantile_95, p_value = analyze_permutation_results(
            observed_mse=args.observed_mse,
            output_file=Path(args.output)
        )
        
        print(f"\n--- Analysis Complete ---")
        print(f"95th Percentile Threshold: {quantile_95:.6f}")
        print(f"Observed MSE:            {args.observed_mse:.6f}")
        print(f"P-value:                 {p_value:.6f}")
        print(f"Significant (p < 0.05)?  {'YES' if p_value < 0.05 else 'NO'}")
        
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Data error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()