def load_existing_stats(stats_path: str) -> pd.DataFrame:
    """
    Load the existing stats.csv file if it exists.
    Returns an empty DataFrame if the file is missing.
    """
    path = Path(stats_path)
    if not path.exists():
        logger.warning(f"Stats file not found at {stats_path}. Starting fresh.")
        return pd.DataFrame()
    
    try:
        df = pd.read_csv(path)
        logger.info(f"Loaded existing stats from {stats_path} with {len(df)} rows.")
        return df
    except Exception as e:
        logger.error(f"Failed to load stats from {stats_path}: {e}")
        return pd.DataFrame()

def aggregate_attribution_results(attribution_path: str, stats_df: pd.DataFrame) -> Tuple[pd.DataFrame, List[Dict[str, Any]]]:
    """
    Aggregate attribution results from attribution.json.
    
    1. Loads attribution.json generated by T035.
    2. Calculates standard deviation of attributions for each feature across samples.
    3. Identifies features with std > 0.1.
    4. Updates or creates a 'topological_features' entry in stats_df.
    
    Returns:
        Tuple of (updated stats_df, list of identified features with std > 0.1)
    """
    attr_path = Path(attribution_path)
    if not attr_path.exists():
        raise DataError(f"Attribution results file not found at {attribution_path}. "
                        "Ensure T035 (attribution analysis) has been run successfully.")
    
    with open(attr_path, 'r') as f:
        attr_data = json.load(f)
    
    if not attr_data or 'attributions' not in attr_data:
        raise DataError("Attribution results file is empty or missing 'attributions' key.")
    
    attributions = attr_data['attributions']
    if not attributions:
        logger.warning("No attribution samples found in the file.")
        return stats_df, []
    
    # Convert to DataFrame for easier calculation
    # Expected structure: list of dicts where keys are feature names and values are attribution scores
    df_attr = pd.DataFrame(attributions)
    
    if df_attr.empty:
        logger.warning("Attribution DataFrame is empty.")
        return stats_df, []

    # Calculate standard deviation for each feature (column)
    # We only care about numerical columns
    numeric_cols = df_attr.select_dtypes(include=[np.number]).columns.tolist()
    
    std_scores = df_attr[numeric_cols].std()
    
    # Identify features with std > 0.1
    high_var_features = []
    for feature, std_val in std_scores.items():
        if std_val > 0.1:
            high_var_features.append({
                "feature": feature,
                "std_dev": float(std_val),
                "threshold": 0.1
            })
    
    logger.info(f"Found {len(high_var_features)} features with std_dev > 0.1: {[f['feature'] for f in high_var_features]}")
    
    # Prepare the row for stats_df
    # We need to aggregate these into a single metric for the stats CSV
    # Per T041, we need a row for 'topological_features_significant' or similar
    # We will create a JSON string of the list for the 'observed_value' column
    # or we can add a row for each feature if the format allows. 
    # Given the schema in T041 (metric, observed_value, p_value...), 
    # let's create a row for the count or a summary.
    # However, T037 specifically asks to "identify" them.
    # Let's add a row for the count of significant features and a JSON string of the list.
    
    new_rows = []
    
    # Row 1: Count of significant features
    new_rows.append({
        "metric": "topological_features_significant_count",
        "observed_value": len(high_var_features),
        "p_value": None, # Not applicable for this specific metric directly
        "corrected_p_value": None,
        "vif_score": None,
        "fwer": None,
        "details": json.dumps(high_var_features, indent=2)
    })
    
    # If stats_df is empty, create columns
    if stats_df.empty:
        # Define expected columns based on T041 requirements
        stats_df = pd.DataFrame(columns=["metric", "observed_value", "p_value", "corrected_p_value", "vif_score", "fwer", "details"])
    
    # Append new rows
    stats_df = pd.concat([stats_df, pd.DataFrame(new_rows)], ignore_index=True)
    
    return stats_df, high_var_features

def update_stats_csv(stats_df: pd.DataFrame, output_path: str) -> None:
    """
    Save the updated stats DataFrame to CSV.
    """
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    stats_df.to_csv(path, index=False)
    logger.info(f"Updated stats saved to {output_path}")

def save_results(high_var_features: List[Dict[str, Any]], output_path: str) -> None:
    """
    Save the detailed list of high-variance features to a JSON file for inspection.
    """
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    
    results = {
        "description": "Topological features with standard deviation > 0.1",
        "threshold": 0.1,
        "count": len(high_var_features),
        "features": high_var_features
    }
    
    with open(path, 'w') as f:
        json.dump(results, f, indent=2)
    logger.info(f"Significant features details saved to {output_path}")

def main():
    """
    Main entry point for T037: Aggregate attribution results.
    """
    # Paths relative to project root
    project_root = Path(__file__).resolve().parent.parent.parent
    stats_path = project_root / "results" / "stats.csv"
    attribution_path = project_root / "results" / "attribution.json"
    output_stats_path = project_root / "results" / "stats.csv"
    output_details_path = project_root / "results" / "topological_features.json"
    
    try:
        logger.info("Starting T037: Aggregate attribution results.")
        
        # Load existing stats (might be empty or partially filled by T034/T036)
        stats_df = load_existing_stats(stats_path)
        
        # Aggregate attribution results
        updated_stats_df, significant_features = aggregate_attribution_results(
            str(attribution_path), 
            stats_df
        )
        
        # Save updated stats
        update_stats_csv(updated_stats_df, str(output_stats_path))
        
        # Save detailed results
        save_results(significant_features, str(output_details_path))
        
        logger.info("T037 completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except DataError as e:
        logger.error(f"Data error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
