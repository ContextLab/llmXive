"""
Contract test for the cleaned study data extraction schema.

This test validates that the CSV output generated by the data extraction pipeline
(T014-T018) strictly adheres to the schema defined in `contracts/cleaned_study.schema.yaml`.
It ensures data types, required fields, and value constraints (e.g., age ranges,
enum values) are met before the data proceeds to effect size calculation.

Per Constitution Principle V (Fail Fast), this test must run automatically
against the artifact `data/processed/cleaned_studies.csv`.
"""

import os
import csv
import yaml
import pytest
from pathlib import Path
from typing import Any, Dict, List, Optional

# Import project utilities
from code.utils.config import get_data_path, get_config

# Path constants
CONTRACT_PATH = Path("contracts/cleaned_study.schema.yaml")
DATA_PATH = get_data_path() / "processed" / "cleaned_studies.csv"


def load_schema() -> Dict[str, Any]:
    """Load the JSON/YAML schema contract."""
    if not CONTRACT_PATH.exists():
        raise FileNotFoundError(
            f"Schema contract missing at {CONTRACT_PATH}. "
            "Ensure T007 (Create schema contracts) is complete."
        )
    with open(CONTRACT_PATH, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def load_csv_records() -> List[Dict[str, Any]]:
    """Load the CSV artifact generated by the data pipeline."""
    if not DATA_PATH.exists():
        pytest.fail(
            f"Data artifact missing at {DATA_PATH}. "
            "Ensure T014-T018 (Data Collection Pipeline) have run successfully."
        )
    records = []
    with open(DATA_PATH, "r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            records.append(row)
    return records


def get_field_spec(schema: Dict[str, Any], field_name: str) -> Optional[Dict[str, Any]]:
    """Retrieve the definition for a specific field in the schema."""
    properties = schema.get("properties", {})
    return properties.get(field_name)


def validate_field_type(value: Any, type_spec: str) -> bool:
    """Validate that a value matches the expected JSON schema type."""
    if value is None:
        return type_spec == "null"

    if type_spec == "string":
        return isinstance(value, str)
    elif type_spec == "integer":
        # CSV reads as string, so we check if it can be an int
        try:
            int(value)
            return True
        except ValueError:
            return False
    elif type_spec == "number":
        try:
            float(value)
            return True
        except ValueError:
            return False
    elif type_spec == "boolean":
        return value.lower() in ("true", "false", "1", "0", "yes", "no")
    return False


def validate_enum(value: Any, allowed_values: List[str]) -> bool:
    """Validate that a value is in the allowed enumeration."""
    if value is None:
        return True
    return str(value).lower() in [str(v).lower() for v in allowed_values]


def validate_constraints(value: Any, field_spec: Dict[str, Any]) -> List[str]:
    """Validate specific constraints (min, max, pattern) defined in the schema."""
    errors = []
    if value is None:
        return errors

    # Numeric constraints
    if "minimum" in field_spec:
        try:
            if float(value) < field_spec["minimum"]:
                errors.append(f"Value {value} is below minimum {field_spec['minimum']}")
        except (ValueError, TypeError):
            pass

    if "maximum" in field_spec:
        try:
            if float(value) > field_spec["maximum"]:
                errors.append(f"Value {value} is above maximum {field_spec['maximum']}")
        except (ValueError, TypeError):
            pass

    # String pattern constraints
    if "pattern" in field_spec:
        import re
        if not re.match(field_spec["pattern"], str(value)):
            errors.append(f"Value '{value}' does not match pattern '{field_spec['pattern']}'")

    return errors


@pytest.fixture(scope="module")
def schema() -> Dict[str, Any]:
    """Fixture to load the schema once."""
    return load_schema()


@pytest.fixture(scope="module")
def records() -> List[Dict[str, Any]]:
    """Fixture to load the CSV records once."""
    return load_csv_records()


class TestCleanedStudySchema:
    """
    Contract tests for the cleaned study data schema.
    """

    def test_schema_exists(self):
        """Verify the schema contract file is present."""
        assert CONTRACT_PATH.exists(), "Schema contract file is missing."

    def test_data_exists(self):
        """Verify the data artifact is present."""
        assert DATA_PATH.exists(), "Data artifact file is missing."

    def test_all_required_fields_present(self, schema, records):
        """Ensure every record contains all required fields defined in the schema."""
        required_fields = schema.get("required", [])
        properties = schema.get("properties", {})

        for i, record in enumerate(records):
            for field in required_fields:
                assert field in record, (
                    f"Record {i} is missing required field: '{field}'. "
                    f"Schema requires: {required_fields}"
                )

            # Check for unexpected extra fields if 'additionalProperties' is false
            if schema.get("additionalProperties") is False:
                allowed_fields = set(properties.keys())
                extra_fields = set(record.keys()) - allowed_fields
                if extra_fields:
                    pytest.fail(
                        f"Record {i} contains unexpected fields: {extra_fields}. "
                        f"Allowed: {allowed_fields}"
                    )

    def test_field_types(self, schema, records):
        """Validate that each field matches its defined type."""
        properties = schema.get("properties", {})

        for i, record in enumerate(records):
            for field, value in record.items():
                field_spec = properties.get(field)
                if not field_spec:
                    continue

                type_spec = field_spec.get("type")
                if type_spec and not validate_field_type(value, type_spec):
                    pytest.fail(
                        f"Record {i}, field '{field}': expected type '{type_spec}', "
                        f"got '{type(value).__name__}' with value '{value}'."
                    )

    def test_enum_values(self, schema, records):
        """Validate that enumerated fields only contain allowed values."""
        properties = schema.get("properties", {})

        for i, record in enumerate(records):
            for field, value in record.items():
                field_spec = properties.get(field)
                if not field_spec:
                    continue

                enum_values = field_spec.get("enum")
                if enum_values:
                    if not validate_enum(value, enum_values):
                        pytest.fail(
                            f"Record {i}, field '{field}': value '{value}' is not in "
                            f"allowed enum: {enum_values}"
                        )

    def test_numeric_constraints(self, schema, records):
        """Validate min/max constraints on numeric fields."""
        properties = schema.get("properties", {})

        for i, record in enumerate(records):
            for field, value in record.items():
                field_spec = properties.get(field)
                if not field_spec:
                    continue

                errors = validate_constraints(value, field_spec)
                if errors:
                    for error in errors:
                        pytest.fail(
                            f"Record {i}, field '{field}': {error}"
                        )

    def test_age_range_constraint(self, records):
        """
        Specific contract test for the age inclusion criteria (6-12 years).
        This enforces FR-007: Validate age (6-12).
        """
        # This test assumes 'age_mean' or 'age_min' is the field representing the sample age.
        # If the schema defines 'age' as the primary field, we check that.
        # Based on typical cleaned study schemas, we look for 'age_mean' or similar.
        
        # We will check any field that might represent age if 'age' or 'age_mean' is present.
        # For strictness, we assume the schema defines 'age' or 'age_mean' with min=6, max=12.
        # If the schema is correct, the generic type/constraint tests above will catch it.
        # This specific test adds a narrative assertion for the business rule.

        age_fields = [f for f in records[0].keys() if "age" in f.lower()]
        assert len(age_fields) > 0, "No age-related fields found in data."

        for field in age_fields:
            for i, record in enumerate(records):
                val_str = record.get(field)
                if val_str is None or val_str == "":
                    continue
                
                try:
                    val = float(val_str)
                    if val < 6 or val > 12:
                        pytest.fail(
                            f"Business Rule Violation (FR-007): Record {i} has {field}={val}, "
                            f"which is outside the inclusion range [6, 12]."
                        )
                except ValueError:
                    # If it's a range string like "8-10", we might need custom parsing,
                    # but for this contract test, we assume the cleaner normalized it.
                    pass

    def test_data_integrity(self, records):
        """
        Verify that the dataset is not empty and contains at least one record.
        This ensures the pipeline actually produced output.
        """
        assert len(records) > 0, "The cleaned_studies.csv file is empty. " \
                                 "The data collection pipeline (T014-T018) produced no results."