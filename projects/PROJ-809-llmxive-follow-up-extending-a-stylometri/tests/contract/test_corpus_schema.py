"""
Contract test for the data/processed/ schema.

This module validates that the processed corpus generated by User Story 1
adheres to the strict schema defined in the project specifications.

Schema Requirements (derived from FR-001, FR-002, FR-009):
1. Directory Structure: data/processed/ must contain exactly 20 subdirectories,
   one for each unique author.
2. Author Directory: Each author directory must be named {author_id} (e.g., 'author_00').
3. File Content: Each author directory must contain >= 10 .txt files.
4. File Format: Each .txt file must contain preprocessed text:
   - Lowercase only
   - No punctuation
   - Space-separated tokens
5. Metadata: A summary file 'corpus_manifest.json' must exist in data/processed/
   containing the list of authors and file counts.
"""

import os
import json
import re
import pytest
from pathlib import Path
from typing import List, Dict, Any

# Constants derived from project specs
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
REQUIRED_AUTHORS = 20
MIN_FILES_PER_AUTHOR = 10
MANIFEST_FILE = PROCESSED_DIR / "corpus_manifest.json"


class TestCorpusSchema:
    """Contract tests for the processed corpus schema."""

    @pytest.fixture(scope="module")
    def corpus_path(self) -> Path:
        """Ensure the processed directory exists."""
        if not PROCESSED_DIR.exists():
            pytest.fail(
                f"Processed directory does not exist: {PROCESSED_DIR}. "
                "Run data ingestion pipeline first."
            )
        return PROCESSED_DIR

    def test_manifest_exists(self, corpus_path: Path):
        """Verify that the corpus manifest file exists."""
        assert MANIFEST_FILE.exists(), "corpus_manifest.json is missing from data/processed/"

    def test_manifest_structure(self, corpus_path: Path):
        """Verify the structure of the corpus manifest."""
        with open(MANIFEST_FILE, 'r', encoding='utf-8') as f:
            manifest = json.load(f)

        assert isinstance(manifest, dict), "Manifest must be a JSON object."
        assert "authors" in manifest, "Manifest must contain 'authors' key."
        assert "total_files" in manifest, "Manifest must contain 'total_files' key."
        assert "generated_at" in manifest, "Manifest must contain 'generated_at' key."

        authors = manifest["authors"]
        assert isinstance(authors, list), "Manifest 'authors' must be a list."
        assert len(authors) == REQUIRED_AUTHORS, (
            f"Expected exactly {REQUIRED_AUTHORS} authors, found {len(authors)}. "
            "This violates FR-001 (Balanced Cohort)."
        )

        for author_entry in authors:
            assert "author_id" in author_entry, "Author entry must have 'author_id'."
            assert "file_count" in author_entry, "Author entry must have 'file_count'."
            assert "text_files" in author_entry, "Author entry must have 'text_files'."

    def test_author_directory_count(self, corpus_path: Path):
        """Verify exactly 20 author directories exist."""
        author_dirs = [d for d in corpus_path.iterdir() if d.is_dir() and not d.name.startswith('.')]
        assert len(author_dirs) == REQUIRED_AUTHORS, (
            f"Expected {REQUIRED_AUTHORS} author directories, found {len(author_dirs)}. "
            f"Found: {[d.name for d in author_dirs]}"
        )

    def test_author_directory_naming(self, corpus_path: Path):
        """Verify author directories follow naming convention author_XX."""
        author_dirs = [d for d in corpus_path.iterdir() if d.is_dir()]
        pattern = re.compile(r"^author_\d{2}$")

        for d in author_dirs:
            assert pattern.match(d.name), (
                f"Directory '{d.name}' does not match expected pattern 'author_XX'. "
                "All author directories must be named author_00 through author_19."
            )

    def test_minimum_files_per_author(self, corpus_path: Path):
        """Verify each author directory contains at least 10 text files."""
        author_dirs = [d for d in corpus_path.iterdir() if d.is_dir()]

        for author_dir in author_dirs:
            txt_files = list(author_dir.glob("*.txt"))
            assert len(txt_files) >= MIN_FILES_PER_AUTHOR, (
                f"Author directory '{author_dir.name}' has only {len(txt_files)} files. "
                f"Minimum required is {MIN_FILES_PER_AUTHOR} (FR-001)."
            )

    def test_file_content_format(self, corpus_path: Path):
        """Verify that all text files contain valid preprocessed content."""
        author_dirs = [d for d in corpus_path.iterdir() if d.is_dir()]
        invalid_files = []

        # Regex to ensure only lowercase letters, numbers, and spaces
        # No punctuation, no uppercase
        valid_pattern = re.compile(r"^[a-z0-9\s]*$")

        for author_dir in author_dirs:
            txt_files = list(author_dir.glob("*.txt"))
            for file_path in txt_files:
                try:
                    with open(file_path, 'r', encoding='utf-8') as f:
                        content = f.read().strip()
                    
                    if not content:
                        invalid_files.append(f"{file_path}: Empty file")
                        continue
                    
                    # Check for forbidden characters (uppercase, punctuation)
                    if not valid_pattern.match(content):
                        invalid_files.append(
                            f"{file_path}: Contains invalid characters (uppercase or punctuation)."
                        )
                    
                    # Check for double spaces (should be single tokenized)
                    if "  " in content:
                        invalid_files.append(
                            f"{file_path}: Contains double spaces (improper tokenization)."
                        )

                except Exception as e:
                    invalid_files.append(f"{file_path}: Error reading file - {e}")

        if invalid_files:
            pytest.fail(
                f"Found {len(invalid_files)} files with invalid content:\n" +
                "\n".join(invalid_files[:10]) + 
                (f"\n... and {len(invalid_files) - 10} more." if len(invalid_files) > 10 else "")
            )

    def test_manifest_consistency(self, corpus_path: Path):
        """Verify that the manifest counts match the actual file counts on disk."""
        with open(MANIFEST_FILE, 'r', encoding='utf-8') as f:
            manifest = json.load(f)

        actual_total = 0
        for author_entry in manifest["authors"]:
            author_id = author_entry["author_id"]
            expected_count = author_entry["file_count"]
            
            author_dir = corpus_path / author_id
            if not author_dir.exists():
                pytest.fail(f"Author directory {author_id} missing but listed in manifest.")
            
            actual_count = len(list(author_dir.glob("*.txt")))
            actual_total += actual_count

            assert actual_count == expected_count, (
                f"Author '{author_id}': Manifest says {expected_count} files, "
                f"but found {actual_count} on disk."
            )

        assert actual_total == manifest["total_files"], (
            f"Manifest total_files ({manifest['total_files']}) does not match "
            f"sum of actual files ({actual_total})."
        )

    def test_no_unexpected_files(self, corpus_path: Path):
        """Ensure no unexpected file types exist in author directories."""
        author_dirs = [d for d in corpus_path.iterdir() if d.is_dir()]
        unexpected = []

        for author_dir in author_dirs:
            for file_path in author_dir.iterdir():
                if file_path.is_file() and not file_path.suffix == ".txt":
                    unexpected.append(f"{file_path}: Unexpected file type ({file_path.suffix})")

        if unexpected:
            pytest.fail(
                "Found unexpected files in author directories:\n" + "\n".join(unexpected)
            )

if __name__ == "__main__":
    pytest.main([__file__, "-v"])