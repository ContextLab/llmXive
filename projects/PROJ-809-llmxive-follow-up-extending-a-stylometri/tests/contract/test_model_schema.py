"""
Contract test for artifacts/models/ schema (US2).

Validates that model artifacts generated by code/model_training.py
conform to the expected schema:
  - Filename pattern: author_{id}_n{n}.pkl or author_{id}_n{n}_fallback.pkl
  - File must be a valid pickle containing a dictionary with keys:
    'vectorizer' (sklearn CountVectorizer), 'counts' (np.ndarray or sparse),
    'author_id' (str), 'n' (int), 'smoothing_type' (str).
"""

import os
import pickle
import re
import pytest
from pathlib import Path

# Import project utilities if needed for path resolution
from utils import load_json

PROJECT_ROOT = Path(__file__).resolve().parents[2]
MODELS_DIR = PROJECT_ROOT / "artifacts" / "models"

# Expected schema constraints
FILENAME_PATTERN = re.compile(r"^author_(.+)_n(\d+)(?:_fallback)?\.pkl$")
REQUIRED_KEYS = {"vectorizer", "counts", "author_id", "n", "smoothing_type"}
VALID_N_VALUES = {4, 5, 6}
VALID_SMOOTHING_TYPES = {"kneser-ney", "laplace", None}  # None allowed if not smoothed yet, but spec requires KN

def get_model_files():
    """Retrieve all .pkl files in the models directory."""
    if not MODELS_DIR.exists():
        return []
    return list(MODELS_DIR.glob("*.pkl"))

@pytest.fixture
def model_files():
    return get_model_files()

def test_model_directory_exists():
    """Contract: The models directory must exist."""
    assert MODELS_DIR.exists(), f"Models directory {MODELS_DIR} does not exist."

def test_model_filename_convention(model_files):
    """Contract: All model files must match the naming convention."""
    if not model_files:
        pytest.skip("No model files found to test.")

    for file_path in model_files:
        match = FILENAME_PATTERN.match(file_path.name)
        assert match, f"Filename {file_path.name} does not match pattern: {FILENAME_PATTERN.pattern}"

def test_model_pickle_structure(model_files):
    """Contract: Each pickle must contain the required schema keys."""
    if not model_files:
        pytest.skip("No model files found to test.")

    for file_path in model_files:
        try:
            with open(file_path, "rb") as f:
                data = pickle.load(f)
        except Exception as e:
            pytest.fail(f"Failed to unpickle {file_path.name}: {e}")

        assert isinstance(data, dict), f"Model data in {file_path.name} is not a dictionary."
        missing_keys = REQUIRED_KEYS - set(data.keys())
        assert not missing_keys, f"Model {file_path.name} missing required keys: {missing_keys}"

def test_model_n_value_valid(model_files):
    """Contract: The 'n' value in models must be 4, 5, or 6."""
    if not model_files:
        pytest.skip("No model files found to test.")

    for file_path in model_files:
        match = FILENAME_PATTERN.match(file_path.name)
        n_val = int(match.group(2))
        assert n_val in VALID_N_VALUES, f"Invalid n={n_val} in {file_path.name}"

        # Cross-check with file content
        with open(file_path, "rb") as f:
            data = pickle.load(f)
        assert data["n"] == n_val, f"Content 'n' mismatch for {file_path.name}: file says {n_val}, content says {data['n']}"

def test_model_smoothing_type(model_files):
    """Contract: Models must specify a smoothing type (spec requires Kneser-Ney)."""
    if not model_files:
        pytest.skip("No model files found to test.")

    for file_path in model_files:
        with open(file_path, "rb") as f:
            data = pickle.load(f)
        
        smooth_type = data.get("smoothing_type")
        assert smooth_type in VALID_SMOOTHING_TYPES, f"Invalid smoothing_type '{smooth_type}' in {file_path.name}"
        
        # Enforce spec requirement: Kneser-Ney must be used
        # If the project allows other smoothing for fallbacks, this might be relaxed,
        # but FR-011 requires Kneser-Ney.
        if smooth_type is None:
            pytest.fail(f"Model {file_path.name} has no smoothing_type defined, but spec requires Kneser-Ney.")

def test_model_vectorizer_present(model_files):
    """Contract: Models must contain a vectorizer object."""
    if not model_files:
        pytest.skip("No model files found to test.")

    for file_path in model_files:
        with open(file_path, "rb") as f:
            data = pickle.load(f)
        
        assert data["vectorizer"] is not None, f"Vectorizer is None in {file_path.name}"
        # Basic check that it looks like a sklearn vectorizer (has transform method)
        assert hasattr(data["vectorizer"], "transform"), f"Vectorizer in {file_path.name} lacks 'transform' method."

def test_model_author_id_consistency(model_files):
    """Contract: The author_id in content must match the filename."""
    if not model_files:
        pytest.skip("No model files found to test.")

    for file_path in model_files:
        match = FILENAME_PATTERN.match(file_path.name)
        filename_author = match.group(1)
        
        with open(file_path, "rb") as f:
            data = pickle.load(f)
        
        content_author = data["author_id"]
        assert filename_author == content_author, (
            f"Author ID mismatch in {file_path.name}: "
            f"filename={filename_author}, content={content_author}"
        )