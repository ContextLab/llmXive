"""
Project directory initialization script.

This script creates the required directory hierarchy for the
PROJ-809-llmxive-follow-up-extending-a-stylometri project under the
repository root.

Expected structure:

projects/
  PROJ-809-llmxive-follow-up-extending-a-stylometri/
    code/
    data/
      raw/
      processed/
      hybrid/
    artifacts/
      models/
      metrics/
    contracts/
    tests/
      unit/
      contract/
      integration/
    state/
"""
import os
from pathlib import Path

# Import utility to ensure a directory exists
try:
    from utils import ensure_dir
except ImportError:
    # Fallback if utils is not importable (should not happen in the repo)
    def ensure_dir(p: Path) -> Path:
        p.mkdir(parents=True, exist_ok=True)
        return p

def main() -> None:
    """
    Create the full directory tree for the project.

    The function is idempotent – running it multiple times will not raise
    errors and will leave the directory structure intact.
    """
    # Base path for the project inside the repository
    base_path = Path.cwd() / "projects" / "PROJ-809-llmxive-follow-up-extending-a-stylometri"

    # Define the required sub‑directories relative to the base path
    subdirs = [
        "code",
        "data/raw",
        "data/processed",
        "data/hybrid",
        "artifacts/models",
        "artifacts/metrics",
        "contracts",
        "tests/unit",
        "tests/contract",
        "tests/integration",
        "state",
    ]

    # Create each directory, ensuring parents are also created
    for sub in subdirs:
        dir_path = base_path / sub
        ensure_dir(dir_path)

    # Optional: create a placeholder README in the project root for visibility
    readme_path = base_path / "README.md"
    if not readme_path.exists():
        readme_path.write_text(
            "# PROJ-809 llmxive follow‑up\n"
            "\n"
            "Project scaffolding generated by `code/setup_project.py`.\n"
        )

    print(f"Project directory structure created at: {base_path}")

if __name__ == "__main__":
    main()
