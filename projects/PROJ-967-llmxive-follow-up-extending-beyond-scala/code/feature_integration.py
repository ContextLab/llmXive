def load_raw_dataset(logger, data_path):
    """
    Load the raw dataset from the parquet file generated by T037/T038.
    """
    logger.info(f"Loading raw dataset from {data_path}")
    if not data_path.exists():
        raise FileNotFoundError(f"Raw dataset not found at {data_path}. "
                                "Please run T037 (Download) and T012 (Ingest) first.")
    
    # Try to load as parquet first, fallback to csv if needed
    try:
        df = pd.read_parquet(data_path)
    except Exception as e:
        logger.warning(f"Failed to load as parquet ({e}), trying CSV...")
        df = pd.read_csv(data_path)
    
    logger.info(f"Loaded dataset with shape: {df.shape}")
    return df


def extract_teacher_scores_matrix(df, logger):
    """
    Extract the 4-dimensional teacher score matrix from the dataframe.
    Expected keys in 'teacher_scores' column: Alignment, Realism, Aesthetics, Plausibility.
    """
    if 'teacher_scores' not in df.columns:
        raise KeyError("Column 'teacher_scores' not found in dataset.")

    # Normalize the column to ensure it's a dict-like structure
    # If it's already a dict, good. If it's a string representation, parse it.
    def parse_scores(cell):
        if isinstance(cell, dict):
            return cell
        elif isinstance(cell, str):
            try:
                import ast
                return ast.literal_eval(cell)
            except:
                return {}
        return {}

    parsed_scores = df['teacher_scores'].apply(parse_scores)
    
    # Extract specific dimensions
    dimensions = ['Alignment', 'Realism', 'Aesthetics', 'Plausibility']
    missing_dims = [d for d in dimensions if d not in parsed_scores.iloc[0]]
    
    if missing_dims:
        logger.warning(f"Missing dimensions in teacher_scores: {missing_dims}. "
                       f"Attempting to fill with NaN or dropping rows.")
        # For robustness, we'll try to extract what we have
        score_df = pd.DataFrame(parsed_scores.tolist())
        # Ensure all 4 columns exist
        for d in dimensions:
            if d not in score_df.columns:
                score_df[d] = np.nan
    else:
        score_df = pd.DataFrame(parsed_scores.tolist())[dimensions]

    # Drop rows where any teacher score is NaN (required for covariance)
    initial_count = len(score_df)
    score_df = score_df.dropna()
    dropped_count = initial_count - len(score_df)
    if dropped_count > 0:
        logger.info(f"Dropped {dropped_count} rows due to missing teacher scores.")

    return score_df.values, score_df.index


def calculate_global_covariance_and_eigenvalue(scores_matrix, logger):
    """
    Calculate the global covariance matrix and its dominant eigenvalue.
    This satisfies T022b.
    """
    if scores_matrix.shape[0] < 4:
        raise ValueError("Not enough samples to compute a 4x4 covariance matrix.")

    # Compute Covariance Matrix (N samples x 4 dimensions) -> 4x4
    # rowvar=False indicates that columns are variables (dimensions)
    cov_matrix = np.cov(scores_matrix, rowvar=False)
    
    # Calculate Eigenvalues
    eigenvalues, eigenvectors = np.linalg.eigh(cov_matrix)
    
    # Dominant Eigenvalue is the largest one
    dominant_eigenvalue = np.max(eigenvalues)
    
    logger.info(f"Global Covariance Matrix computed. Shape: {cov_matrix.shape}")
    logger.info(f"Dominant Eigenvalue: {dominant_eigenvalue:.4f}")
    
    return cov_matrix, dominant_eigenvalue


def compute_per_sample_frobenius_norm(df, logger):
    """
    Compute per-sample variance, entropy, skewness, and kurtosis.
    This satisfies T022a.
    """
    if 'teacher_scores' not in df.columns:
        raise KeyError("Column 'teacher_scores' not found.")

    dimensions = ['Alignment', 'Realism', 'Aesthetics', 'Plausibility']
    
    # Helper to safely extract scores
    def get_scores(row):
        cell = row['teacher_scores']
        if isinstance(cell, dict):
            return [cell.get(d, np.nan) for d in dimensions]
        elif isinstance(cell, str):
            try:
                import ast
                d = ast.literal_eval(cell)
                return [d.get(dim, np.nan) for dim in dimensions]
            except:
                return [np.nan] * 4
        return [np.nan] * 4

    # Extract scores into a temporary DataFrame for vectorization
    temp_scores = df.apply(get_scores, axis=1, result_type='expand')
    temp_scores.columns = dimensions
    
    # Calculate Variance (across dimensions for each sample)
    # Axis 1 means across columns (dimensions)
    df['variance'] = temp_scores.var(axis=1, ddof=0)
    
    # Calculate Entropy (Shannon)
    def calc_entropy(row):
        # Normalize to probability distribution
        p = np.array(row)
        # Filter out NaNs and zeros
        p = p[~np.isnan(p)]
        if len(p) == 0:
            return 0.0
        # Normalize
        p_sum = np.sum(p)
        if p_sum == 0:
            return 0.0
        p_norm = p / p_sum
        # Avoid log(0)
        p_norm = p_norm[p_norm > 0]
        if len(p_norm) == 0:
            return 0.0
        return -np.sum(p_norm * np.log(p_norm))
    
    df['entropy'] = temp_scores.apply(calc_entropy, axis=1)
    
    # Calculate Skewness and Kurtosis
    # scipy.stats.skew and kurtosis handle 1D arrays
    df['skewness'] = temp_scores.apply(lambda x: stats.skew(x, nan_policy='omit'), axis=1)
    df['kurtosis'] = temp_scores.apply(lambda x: stats.kurtosis(x, nan_policy='omit'), axis=1)
    
    # Fill NaNs in stats with 0 (for constant distributions or single values)
    df['skewness'] = df['skewness'].fillna(0.0)
    df['kurtosis'] = df['kurtosis'].fillna(0.0)
    
    logger.info("Per-sample statistics (Variance, Entropy, Skewness, Kurtosis) computed.")
    return df


def integrate_features(df, cov_matrix, mean_vector, logger):
    """
    Calculate Mahalanobis Distance for each sample using the global covariance.
    This satisfies T022c.
    """
    dimensions = ['Alignment', 'Realism', 'Aesthetics', 'Plausibility']
    
    # Extract scores again for Mahalanobis calculation
    def get_scores(row):
        cell = row['teacher_scores']
        if isinstance(cell, dict):
            return np.array([cell.get(d, np.nan) for d in dimensions])
        elif isinstance(cell, str):
            try:
                import ast
                d = ast.literal_eval(cell)
                return np.array([d.get(dim, np.nan) for dim in dimensions])
            except:
                return np.array([np.nan] * 4)
        return np.array([np.nan] * 4)

    temp_scores = df.apply(get_scores, axis=1, result_type='expand')
    temp_scores.columns = dimensions
    
    # We need to handle NaNs carefully. 
    # For Mahalanobis, we can't compute it if any dimension is missing.
    # We will mark those as NaN in the result.
    
    valid_indices = temp_scores.dropna().index
    invalid_indices = temp_scores[temp_scores.isna().any(axis=1)].index
    
    mahalanobis_distances = np.full(len(df), np.nan)
    
    if len(valid_indices) > 0:
        valid_scores = temp_scores.loc[valid_indices].values
        
        # Compute inverse covariance (using pseudo-inverse for stability)
        try:
            cov_inv = np.linalg.pinv(cov_matrix)
        except np.linalg.LinAlgError:
            logger.warning("Covariance matrix is singular. Using pseudo-inverse.")
            cov_inv = np.linalg.pinv(cov_matrix)
        
        # Calculate distances
        diff = valid_scores - mean_vector
        # D^2 = (x - mu).T @ inv(Sigma) @ (x - mu)
        mahal_sq = np.einsum('ij,ji->i', diff @ cov_inv, diff.T)
        mahal_sq = np.clip(mahal_sq, 0, None) # Ensure non-negative due to float errors
        distances = np.sqrt(mahal_sq)
        
        mahalanobis_distances[valid_indices] = distances
        
        logger.info(f"Mahalanobis Distance computed for {len(valid_indices)} samples.")
    
    df['mahalanobis_distance'] = mahalanobis_distances
    
    if len(invalid_indices) > 0:
        logger.warning(f"Skipped {len(invalid_indices)} samples with missing scores for Mahalanobis calculation.")
        
    return df


def parse_args():
    parser = argparse.ArgumentParser(description="Integrate per-sample and global features.")
    parser.add_argument('--input', type=str, 
                        default='projects/PROJ-967-llmxive-follow-up-extending-beyond-scala/data/processed/raw_data.parquet',
                        help='Path to the raw data parquet file.')
    parser.add_argument('--output', type=str,
                        default='projects/PROJ-967-llmxive-follow-up-extending-beyond-scala/data/processed/features.json',
                        help='Path to output features JSON.')
    parser.add_argument('--global-stats', type=str,
                        default='projects/PROJ-967-llmxive-follow-up-extending-beyond-scala/data/processed/global_stats.json',
                        help='Path to save global stats (covariance, eigenvalue).')
    return parser.parse_args()


def main():
    logger = setup_logging()
    data_path, results_path = setup_directories(logger)
    args = parse_args()
    
    input_path = Path(args.input)
    output_path = Path(args.output)
    global_stats_path = Path(args.global_stats)
    
    logger.info("Starting Feature Integration Pipeline (T041 Replacement)")
    
    # 1. Load Raw Data
    df = load_raw_dataset(logger, input_path)
    
    # 2. Extract Teacher Scores Matrix for Global Stats
    scores_matrix, valid_indices = extract_teacher_scores_matrix(df, logger)
    
    # 3. Compute Global Covariance and Eigenvalue (T022b)
    cov_matrix, dominant_eigenvalue = calculate_global_covariance_and_eigenvalue(scores_matrix, logger)
    mean_vector = np.mean(scores_matrix, axis=0)
    
    # Save Global Stats
    global_stats = {
        "dominant_eigenvalue": float(dominant_eigenvalue),
        "covariance_matrix": cov_matrix.tolist(),
        "mean_vector": mean_vector.tolist(),
        "sample_count": int(len(scores_matrix))
    }
    with open(global_stats_path, 'w') as f:
        json.dump(global_stats, f, indent=2)
    logger.info(f"Global stats saved to {global_stats_path}")
    
    # 4. Compute Per-Sample Stats (T022a)
    df = compute_per_sample_frobenius_norm(df, logger)
    
    # 5. Integrate Mahalanobis Distance (T022c)
    df = integrate_features(df, cov_matrix, mean_vector, logger)
    
    # 6. Prepare Output
    # Select relevant columns for the output schema
    output_cols = [
        'sample_id', 'variance', 'entropy', 'skewness', 'kurtosis', 
        'mahalanobis_distance', 'dominant_eigenvalue' # dominant_eigenvalue is global, repeated
    ]
    
    # Ensure sample_id exists or create one
    if 'sample_id' not in df.columns:
        df['sample_id'] = range(len(df))
    
    # Add global eigenvalue to every row
    df['dominant_eigenvalue'] = dominant_eigenvalue
    
    # Filter to required columns
    # Handle missing columns gracefully if they don't exist yet
    existing_cols = [c for c in output_cols if c in df.columns]
    result_df = df[existing_cols].copy()
    
    # Convert to list of dicts
    features = result_df.to_dict(orient='records')
    
    # 7. Save Output
    with open(output_path, 'w') as f:
        json.dump(features, f, indent=2)
    
    logger.info(f"Feature integration complete. Output saved to {output_path}")
    logger.info(f"Total features generated: {len(features)}")
    
    return 0


if __name__ == "__main__":
    sys.exit(main())