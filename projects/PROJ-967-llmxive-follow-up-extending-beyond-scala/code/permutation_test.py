"""
Permutation Test Implementation for User Story 3.

This module implements the permutation test logic to validate the correlation strength
between entanglement features and fidelity loss.

SC-001: Validates correlation strength by comparing observed R² against a null distribution
generated by permuting the feature matrix X against the target y.
"""

import argparse
import json
import logging
import os
import sys
import pickle
import numpy as np
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import r2_score
from sklearn.model_selection import train_test_split
from pathlib import Path

# Add parent directory to path to import project modules if run as script
sys.path.insert(0, str(Path(__file__).parent.parent))

def setup_logging():
    """Configure logging for the permutation test module."""
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(levelname)s - %(message)s'
    )
    return logging.getLogger(__name__)

def load_features(logger):
    """
    Load cleaned features from data/processed/cleaned_data.parquet.
    
    Returns:
        tuple: (features_df, target_column_name)
    """
    try:
        import pandas as pd
        # Determine the project root relative to this script
        project_root = Path(__file__).parent.parent
        features_path = project_root / 'data' / 'processed' / 'cleaned_data.parquet'
        
        if not features_path.exists():
            raise FileNotFoundError(f"Features file not found: {features_path}")
        
        df = pd.read_parquet(features_path)
        logger.info(f"Loaded {len(df)} samples from {features_path}")
        
        # Verify required columns exist
        required_cols = ['sample_id', 'fidelity_loss', 'variance', 'entropy', 
                       'skewness', 'kurtosis', 'mahalanobis_distance', 
                       'dominant_eigenvalue']
        
        missing_cols = [col for col in required_cols if col not in df.columns]
        if missing_cols:
            raise ValueError(f"Missing required columns: {missing_cols}")
        
        return df, 'fidelity_loss'
        
    except Exception as e:
        logger.error(f"Failed to load features: {e}")
        raise

def load_split_config(logger):
    """
    Load the train/test split configuration from data/processed/split_config.json.
    
    Returns:
        dict: Split configuration containing train_indices and test_indices
    """
    project_root = Path(__file__).parent.parent
    config_path = project_root / 'data' / 'processed' / 'split_config.json'
    
    if not config_path.exists():
        raise FileNotFoundError(f"Split config not found: {config_path}")
    
    with open(config_path, 'r') as f:
        config = json.load(f)
    
    logger.info(f"Loaded split config with {config['train_size']} train, {config['test_size']} test samples")
    return config

def load_model(logger):
    """
    Load the trained Random Forest model from results/model.pkl.
    
    Returns:
        RandomForestRegressor: The trained model
    """
    project_root = Path(__file__).parent.parent
    model_path = project_root / 'results' / 'model.pkl'
    
    if not model_path.exists():
        raise FileNotFoundError(f"Model file not found: {model_path}")
    
    with open(model_path, 'rb') as f:
        model = pickle.load(f)
    
    logger.info("Loaded trained Random Forest model")
    return model

def calculate_permutation_pvalue(
    X_train, 
    y_train, 
    X_test, 
    y_test, 
    model, 
    n_permutations=1000, 
    random_state=42, 
    logger=None
):
    """
    Calculate the permutation test p-value.
    
    This function permutes the feature matrix X against the target y n_permutations times,
    calculates R² for each permutation, and computes the p-value as the fraction of 
    permuted R² values >= observed R².
    
    Args:
        X_train (np.ndarray): Training features
        y_train (np.ndarray): Training target
        X_test (np.ndarray): Test features
        y_test (np.ndarray): Test target
        model: Trained model to evaluate (should have .predict() method)
        n_permutations (int): Number of permutations to run
        random_state (int): Random seed for reproducibility
        logger: Logger instance
    
    Returns:
        dict: Contains observed_r2, p_value, and permuted_r2_scores
    """
    if logger is None:
        logger = setup_logging()
    
    logger.info(f"Starting permutation test with {n_permutations} permutations")
    
    # Calculate observed R² on test set
    y_pred_observed = model.predict(X_test)
    observed_r2 = r2_score(y_test, y_pred_observed)
    logger.info(f"Observed R²: {observed_r2:.4f}")
    
    # Store permuted R² scores
    permuted_r2_scores = []
    
    # Create a copy of X_train to permute
    rng = np.random.RandomState(random_state)
    
    for i in range(n_permutations):
        if (i + 1) % 100 == 0:
            logger.info(f"Permutation {i + 1}/{n_permutations}")
        
        # Permute X_train (shuffle rows)
        X_train_permuted = X_train.copy()
        perm_indices = rng.permutation(len(X_train))
        X_train_permuted = X_train_permuted[perm_indices]
        
        # Train a new model on permuted data
        # We use the same model type and parameters
        perm_model = RandomForestRegressor(
            n_estimators=100,
            max_depth=None,
            random_state=random_state,
            n_jobs=1  # Use single thread for speed in loop
        )
        perm_model.fit(X_train_permuted, y_train)
        
        # Evaluate on original test set
        y_pred_perm = perm_model.predict(X_test)
        r2_perm = r2_score(y_test, y_pred_perm)
        permuted_r2_scores.append(r2_perm)
    
    # Calculate p-value: fraction of permuted R² >= observed R²
    permuted_r2_scores = np.array(permuted_r2_scores)
    p_value = np.sum(permuted_r2_scores >= observed_r2) / n_permutations
    
    logger.info(f"Permutation test complete. P-value: {p_value:.4f}")
    logger.info(f"Permuted R² stats - Mean: {np.mean(permuted_r2_scores):.4f}, "
               f"Std: {np.std(permuted_r2_scores):.4f}, "
               f"Max: {np.max(permuted_r2_scores):.4f}")
    
    return {
        'observed_r2': float(observed_r2),
        'p_value': float(p_value),
        'permuted_r2_scores': permuted_r2_scores.tolist(),
        'n_permutations': n_permutations,
        'random_state': random_state
    }

def run_permutation_test(
    n_permutations=1000, 
    random_state=42, 
    output_path=None, 
    logger=None
):
    """
    Run the full permutation test pipeline.
    
    Args:
        n_permutations (int): Number of permutations
        random_state (int): Random seed
        output_path (str): Path to save results JSON
        logger: Logger instance
    
    Returns:
        dict: Permutation test results
    """
    if logger is None:
        logger = setup_logging()
    
    # Load data
    features_df, target_col = load_features(logger)
    split_config = load_split_config(logger)
    model = load_model(logger)
    
    # Prepare features and target
    feature_cols = ['variance', 'entropy', 'skewness', 'kurtosis', 
                   'mahalanobis_distance', 'dominant_eigenvalue']
    
    X = features_df[feature_cols].values
    y = features_df[target_col].values
    
    # Split data according to config
    train_indices = split_config['train_indices']
    test_indices = split_config['test_indices']
    
    X_train = X[train_indices]
    y_train = y[train_indices]
    X_test = X[test_indices]
    y_test = y[test_indices]
    
    logger.info(f"Training set: {len(X_train)}, Test set: {len(X_test)}")
    
    # Run permutation test
    results = calculate_permutation_pvalue(
        X_train, y_train, X_test, y_test, 
        model, n_permutations, random_state, logger
    )
    
    # Save results if output path provided
    if output_path:
        with open(output_path, 'w') as f:
            json.dump(results, f, indent=2)
        logger.info(f"Results saved to {output_path}")
    
    return results

def parse_args():
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(
        description='Run permutation test for feature-target correlation validation'
    )
    parser.add_argument(
        '--n-permutations', 
        type=int, 
        default=1000,
        help='Number of permutations (default: 1000)'
    )
    parser.add_argument(
        '--random-state', 
        type=int, 
        default=42,
        help='Random seed (default: 42)'
    )
    parser.add_argument(
        '--output', 
        type=str, 
        default=None,
        help='Output path for results JSON'
    )
    return parser.parse_args()

def main():
    """Main entry point for the permutation test script."""
    args = parse_args()
    logger = setup_logging()
    
    try:
        results = run_permutation_test(
            n_permutations=args.n_permutations,
            random_state=args.random_state,
            output_path=args.output,
            logger=logger
        )
        
        logger.info("Permutation test completed successfully")
        logger.info(f"P-value: {results['p_value']:.4f}")
        logger.info(f"Observed R²: {results['observed_r2']:.4f}")
        
        # Exit with code 0 if p-value < 0.05 (significant)
        if results['p_value'] < 0.05:
            logger.info("Result is statistically significant (p < 0.05)")
        else:
            logger.warning("Result is NOT statistically significant (p >= 0.05)")
        
        return 0
        
    except Exception as e:
        logger.error(f"Permutation test failed: {e}")
        return 1

if __name__ == '__main__':
    sys.exit(main())