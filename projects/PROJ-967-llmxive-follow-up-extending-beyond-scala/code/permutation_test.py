"""
Permutation Test Implementation for llmXive Follow-up.

This script performs a permutation test to evaluate the statistical significance
of the trained model's R² score against a null distribution generated by
permuting the target variable.

Dependencies:
- Uses the model and split configuration produced by T027a and T027b.
- Uses the features dataset produced by T025b-mahalanobis.
"""
import argparse
import json
import logging
import os
import sys
import pickle
import numpy as np
from sklearn.metrics import r2_score
from sklearn.ensemble import RandomForestRegressor
from sklearn.linear_model import Ridge

# Import shared logging setup if available, otherwise define locally
def setup_logging(log_file=None):
    """Configure logging for the script."""
    log_format = "%(asctime)s - %(levelname)s - %(message)s"
    handlers = [logging.StreamHandler(sys.stdout)]
    if log_file:
        handlers.append(logging.FileHandler(log_file))
    
    logging.basicConfig(level=logging.INFO, format=log_format, handlers=handlers)
    return logging.getLogger(__name__)

def load_features(features_path):
    """Load the features JSON file."""
    if not os.path.exists(features_path):
        raise FileNotFoundError(f"Features file not found: {features_path}")
    with open(features_path, 'r') as f:
        return json.load(f)

def load_split_config(split_config_path):
    """Load the split configuration JSON file."""
    if not os.path.exists(split_config_path):
        raise FileNotFoundError(f"Split config file not found: {split_config_path}")
    with open(split_config_path, 'r') as f:
        return json.load(f)

def load_model(model_path):
    """Load the trained model from pickle file."""
    if not os.path.exists(model_path):
        raise FileNotFoundError(f"Model file not found: {model_path}")
    with open(model_path, 'rb') as f:
        return pickle.load(f)

def calculate_permutation_pvalue(model, X_train, y_train, n_permutations=1000, random_state=42):
    """
    Calculate the p-value for the permutation test.

    Args:
        model: The trained scikit-learn model.
        X_train: The training feature matrix.
        y_train: The training target vector.
        n_permutations: Number of permutations to perform.
        random_state: Random seed for reproducibility.

    Returns:
        p_value: Fraction of permuted R² scores >= observed R².
        observed_r2: The R² score of the original model.
        permuted_r2s: List of R² scores from permuted targets.
    """
    logger = logging.getLogger(__name__)
    
    # Calculate observed R²
    y_pred = model.predict(X_train)
    observed_r2 = r2_score(y_train, y_pred)
    logger.info(f"Observed R²: {observed_r2:.4f}")

    # Prepare for permutation test
    np.random.seed(random_state)
    n_samples = len(y_train)
    permuted_r2s = []

    logger.info(f"Starting permutation test with {n_permutations} iterations...")

    for i in range(n_permutations):
        # Permute the target variable
        y_permuted = y_train.copy()
        np.random.shuffle(y_permuted)

        # Train a new model on the permuted data
        # We clone the model type to ensure fairness, but since we only need
        # the R² score, we can re-fit the same instance if we are careful.
        # However, to be safe and avoid state leakage, we create a new instance.
        if isinstance(model, RandomForestRegressor):
            perm_model = RandomForestRegressor(
                n_estimators=model.n_estimators,
                random_state=random_state,
                n_jobs=2
            )
        elif isinstance(model, Ridge):
            perm_model = Ridge(alpha=model.alpha, random_state=random_state)
        else:
            # Fallback for other models (though spec limits to RF/Ridge)
            perm_model = type(model)(**model.get_params())

        perm_model.fit(X_train, y_permuted)
        y_perm_pred = perm_model.predict(X_train)
        r2_perm = r2_score(y_permuted, y_perm_pred)
        permuted_r2s.append(r2_perm)

        if (i + 1) % 100 == 0:
            logger.info(f"Completed {i + 1}/{n_permutations} permutations")

    # Calculate p-value: fraction of permuted R² >= observed R²
    permuted_r2s = np.array(permuted_r2s)
    p_value = np.mean(permuted_r2s >= observed_r2)

    logger.info(f"Permutation test complete. P-value: {p_value:.4f}")
    logger.info(f"Max permuted R²: {np.max(permuted_r2s):.4f}")
    logger.info(f"Min permuted R²: {np.min(permuted_r2s):.4f}")
    logger.info(f"Mean permuted R²: {np.mean(permuted_r2s):.4f}")

    return p_value, observed_r2, permuted_r2s

def run_permutation_test(features_path, split_config_path, model_path, output_path, n_permutations=1000, random_state=42):
    """
    Run the full permutation test pipeline.
    """
    logger = setup_logging()
    logger.info("Loading data and model...")

    # Load features
    features_data = load_features(features_path)
    
    # Convert features to numpy array
    # Assuming features_data is a list of dicts with 'features' key or flat keys
    # Based on T025b, it's a list of records. We need to identify feature columns.
    if not features_data:
        raise ValueError("Features dataset is empty.")
    
    # Identify feature columns (exclude target and metadata)
    # We assume 'fidelity_loss' is the target.
    sample = features_data[0]
    feature_cols = [k for k in sample.keys() if k not in ['sample_id', 'fidelity_loss', 'primary_dimension']]
    
    X = np.array([[row.get(col, 0.0) for col in feature_cols] for row in features_data])
    y = np.array([row['fidelity_loss'] for row in features_data])

    # Load split config to get training indices
    split_config = load_split_config(split_config_path)
    train_indices = split_config['train_indices']
    
    X_train = X[train_indices]
    y_train = y[train_indices]

    logger.info(f"Training set size: {len(X_train)}")

    # Load model
    model = load_model(model_path)

    # Run permutation test
    p_value, observed_r2, permuted_r2s = calculate_permutation_pvalue(
        model, X_train, y_train, n_permutations, random_state
    )

    # Save results
    results = {
        "p_value_permutation": p_value,
        "observed_r2": observed_r2,
        "n_permutations": n_permutations,
        "random_state": random_state,
        "permuted_r2_stats": {
            "mean": float(np.mean(permuted_r2s)),
            "std": float(np.std(permuted_r2s)),
            "min": float(np.min(permuted_r2s)),
            "max": float(np.max(permuted_r2s))
        }
    }

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    
    logger.info(f"Results saved to {output_path}")
    return results

def parse_args():
    parser = argparse.ArgumentParser(description="Run permutation test for model significance.")
    parser.add_argument("--features", type=str, default="data/processed/features.json",
                        help="Path to features JSON file.")
    parser.add_argument("--split-config", type=str, default="data/processed/split_config.json",
                        help="Path to split configuration JSON file.")
    parser.add_argument("--model", type=str, default="results/model.pkl",
                        help="Path to trained model pickle file.")
    parser.add_argument("--output", type=str, default="results/permutation_test.json",
                        help="Path to output results JSON file.")
    parser.add_argument("--n-permutations", type=int, default=1000,
                        help="Number of permutations for the test.")
    parser.add_argument("--random-state", type=int, default=42,
                        help="Random seed for reproducibility.")
    return parser.parse_args()

def main():
    args = parse_args()
    run_permutation_test(
        features_path=args.features,
        split_config_path=args.split_config,
        model_path=args.model,
        output_path=args.output,
        n_permutations=args.n_permutations,
        random_state=args.random_state
    )

if __name__ == "__main__":
    main()
