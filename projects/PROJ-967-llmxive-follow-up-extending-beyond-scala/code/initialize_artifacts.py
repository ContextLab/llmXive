import argparse
import json
import logging
import os
import sys
from pathlib import Path

def setup_logging(log_level=logging.INFO):
    """Configure logging for the artifact initialization process."""
    logging.basicConfig(
        level=log_level,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    return logging.getLogger(__name__)

def initialize_empty_artifacts(logger):
    """
    Initialize empty output artifacts to prevent file-not-found errors in downstream tasks.
    
    Creates:
    - data/processed/features.json (initialized to empty list [])
    - results/results.json (initialized to empty object {})
    
    These files serve as placeholders until actual data is generated by the pipeline.
    """
    # Define project root relative to the script location
    # Assuming script is in code/ directory
    script_dir = Path(__file__).parent
    project_root = script_dir.parent
    
    # Define paths for artifacts
    features_path = project_root / "data" / "processed" / "features.json"
    results_path = project_root / "results" / "results.json"
    
    # Ensure directories exist
    features_path.parent.mkdir(parents=True, exist_ok=True)
    results_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Initialize features.json with empty list
    logger.info(f"Initializing {features_path} with empty list []")
    with open(features_path, 'w') as f:
        json.dump([], f, indent=2)
    
    # Initialize results.json with empty object
    logger.info(f"Initializing {results_path} with empty object {{}}")
    with open(results_path, 'w') as f:
        json.dump({}, f, indent=2)
    
    logger.info("Artifact initialization completed successfully")
    return True

def parse_args():
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(
        description='Initialize empty output artifacts for the llmXive pipeline.'
    )
    parser.add_argument(
        '--log-level',
        type=str,
        default='INFO',
        choices=['DEBUG', 'INFO', 'WARNING', 'ERROR', 'CRITICAL'],
        help='Set the logging level'
    )
    return parser.parse_args()

def main():
    """Main entry point for artifact initialization."""
    args = parse_args()
    logger = setup_logging(getattr(logging, args.log_level))
    
    try:
        success = initialize_empty_artifacts(logger)
        if success:
            logger.info("All artifacts initialized successfully")
            return 0
        else:
            logger.error("Failed to initialize some artifacts")
            return 1
    except Exception as e:
        logger.exception(f"Unexpected error during artifact initialization: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
