import argparse
import json
import logging
import os
import sys
from pathlib import Path

import pandas as pd
import numpy as np
from scipy import stats

def setup_logging():
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(levelname)s - %(message)s',
        handlers=[logging.StreamHandler(sys.stdout)]
    )

def parse_args():
    parser = argparse.ArgumentParser(description='Verify data provenance for human_annotations.')
    parser.add_argument('--input', type=str, default='data/raw/oxford_pets_simulated.parquet',
                        help='Path to the simulated dataset.')
    parser.add_argument('--output', type=str, default='data/processed/provenance_report.json',
                        help='Path to write the provenance verification report.')
    return parser.parse_args()

def verify_provenance_independence(df):
    """
    Verifies that 'human_annotations' is generated by a deterministic function 
    of 'species_id' and 'prompt_text' ONLY, with NO dependency on 'teacher_scores' 
    or 'student_scalar'.
    
    Strategy:
    1. Check if 'human_annotations' is perfectly correlated with 'teacher_scores' 
       or 'student_scalar' (Pearson/Spearman). If correlation is ~1.0 or -1.0, 
       it suggests direct dependency.
    2. Perform a partial correlation test: Correlate 'human_annotations' with 
       'teacher_scores' controlling for 'species_id' and 'prompt_text' (encoded).
       If the partial correlation is near zero, it supports independence.
    3. Since 'species_id' and 'prompt_text' are the intended drivers, we check 
       if variance in 'human_annotations' is explained by them.
    """
    logger = logging.getLogger(__name__)
    
    # Ensure required columns exist
    required_cols = ['human_annotations', 'teacher_scores', 'student_scalar', 'species_id', 'prompt_text']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns for provenance check: {missing}")

    # Flatten teacher_scores if it's a list/array column to check correlation per dimension
    # Assuming teacher_scores is a list of 4 floats per row
    if isinstance(df['teacher_scores'].iloc[0], (list, np.ndarray)):
        teacher_df = pd.DataFrame(df['teacher_scores'].tolist(), 
                                  columns=[f'teacher_dim_{i}' for i in range(4)])
        teacher_df['index'] = df.index
        df_expanded = pd.concat([df.drop('teacher_scores', axis=1), teacher_df], axis=1)
    else:
        df_expanded = df.copy()

    results = {
        "status": "passed",
        "checks": [],
        "details": {}
    }

    # Check 1: Correlation with student_scalar
    # If human_annotations depends on student_scalar, correlation should be high.
    # We expect low correlation if they are independent (simulated independently).
    try:
        corr_student, p_val_student = stats.spearmanr(df['human_annotations'], df['student_scalar'])
        results['checks'].append({
            "check": "correlation_with_student_scalar",
            "correlation": float(corr_student),
            "p_value": float(p_val_student),
            "passed": abs(corr_student) < 0.9, # Threshold for independence
            "reason": "High correlation suggests dependency." if abs(corr_student) >= 0.9 else "Low correlation suggests independence."
        })
        if abs(corr_student) >= 0.9:
            results['status'] = "failed"
            results['details']['student_scalar_issue'] = "Human annotations appear dependent on student scalar."
    except Exception as e:
        results['checks'].append({
            "check": "correlation_with_student_scalar",
            "error": str(e),
            "passed": False
        })

    # Check 2: Correlation with teacher_scores (any dimension)
    if 'teacher_dim_0' in df_expanded.columns:
        teacher_correlations = {}
        all_high = True
        for col in [c for c in df_expanded.columns if c.startswith('teacher_dim_')]:
            try:
                corr, p_val = stats.spearmanr(df_expanded['human_annotations'], df_expanded[col])
                teacher_correlations[col] = {"correlation": float(corr), "p_value": float(p_val)}
                if abs(corr) < 0.9:
                    all_high = False
            except Exception as e:
                teacher_correlations[col] = {"error": str(e)}
        
        results['checks'].append({
            "check": "correlation_with_teacher_scores",
            "details": teacher_correlations,
            "passed": not all_high,
            "reason": "High correlation across all dimensions suggests dependency." if all_high else "Low correlation in at least one dimension suggests independence."
        })
        if all_high:
            results['status'] = "failed"
            results['details']['teacher_scores_issue'] = "Human annotations appear dependent on teacher scores."
    else:
        results['checks'].append({
            "check": "correlation_with_teacher_scores",
            "skipped": "teacher_scores not expanded or missing",
            "passed": True
        })

    # Check 3: Determinism check (Optional but good for "deterministic function" requirement)
    # Group by species_id and prompt_text, check if human_annotations is constant.
    # Note: The task says "deterministic function of species_id and prompt_text ONLY".
    # If there is noise added based on other factors, this might fail. 
    # However, if the simulation is truly deterministic on these two, variance within groups should be 0.
    try:
        # Encode prompt_text to hash for grouping if it's long
        # Using a simple groupby
        grouped = df_expanded.groupby(['species_id', 'prompt_text'])['human_annotations'].agg(['nunique', 'var'])
        unique_counts = grouped['nunique'].unique()
        
        # If nunique > 1 for any group, it's not a deterministic function of ONLY these two.
        is_deterministic = len(unique_counts) == 1 and unique_counts[0] == 1
        
        results['checks'].append({
            "check": "determinism_on_species_and_prompt",
            "passed": is_deterministic,
            "unique_counts_per_group": unique_counts.tolist(),
            "reason": "Human annotations are not unique per (species, prompt) group." if not is_deterministic else "Human annotations are deterministic per (species, prompt) group."
        })
        if not is_deterministic:
            results['status'] = "failed"
            results['details']['determinism_issue'] = "Human annotations vary within (species_id, prompt_text) groups."
    except Exception as e:
        results['checks'].append({
            "check": "determinism_on_species_and_prompt",
            "error": str(e),
            "passed": False
        })

    return results

def main():
    args = parse_args()
    setup_logging()
    logger = logging.getLogger(__name__)

    input_path = Path(args.input)
    output_path = Path(args.output)

    if not input_path.exists():
        logger.error(f"Input file not found: {input_path}")
        sys.exit(1)

    logger.info(f"Loading dataset from {input_path}")
    try:
        df = pd.read_parquet(input_path)
    except Exception as e:
        logger.error(f"Failed to load dataset: {e}")
        sys.exit(1)

    logger.info(f"Dataset loaded with {len(df)} rows.")
    logger.info("Verifying data provenance...")

    results = verify_provenance_independence(df)

    logger.info(f"Verification Status: {results['status']}")
    for check in results['checks']:
        logger.info(f"  - {check['check']}: {'PASS' if check.get('passed', False) else 'FAIL'}")
        if 'reason' in check:
            logger.info(f"    Reason: {check['reason']}")

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)

    logger.info(f"Report saved to {output_path}")

    if results['status'] == "failed":
        sys.exit(1)

if __name__ == '__main__':
    main()
