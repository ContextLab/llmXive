import re
import hashlib
from typing import Optional, List
import os

def scan_for_pii(text: str) -> List[str]:
    """
    Scan text for personally identifiable information (PII).
    
    Args:
        text: Input text to scan
        
    Returns:
        List of detected PII patterns
    """
    pii_patterns = {
        'email': r'\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Z|a-z]{2,}\b',
        'phone': r'\b\d{3}[-.]?\d{3}[-.]?\d{4}\b',
        'ssn': r'\b\d{3}-\d{2}-\d{4}\b',
        'credit_card': r'\b\d{4}[- ]?\d{4}[- ]?\d{4}[- ]?\d{4}\b',
    }
    
    detected = []
    for pii_type, pattern in pii_patterns.items():
        matches = re.findall(pattern, text)
        if matches:
            detected.extend([f"{pii_type}:{m}" for m in matches])
    
    return detected

def compute_artifact_hash(file_path: str) -> str:
    """
    Compute SHA-256 hash of a file for versioning.
    
    Args:
        file_path: Path to the file to hash
        
    Returns:
        Hex digest of the file's SHA-256 hash
    """
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"File not found: {file_path}")
    
    sha256_hash = hashlib.sha256()
    with open(file_path, "rb") as f:
        # Read file in chunks to handle large files
        for byte_block in iter(lambda: f.read(4096), b""):
            sha256_hash.update(byte_block)
    
    return sha256_hash.hexdigest()

def normalize_story_id(text: str) -> str:
    """
    Generate a consistent story_id (SHA-256 hash of the first 50 chars of the text).
    
    This ensures that story_id generated by T016 (Extraction) and T030 (Data Loader)
    are identical for joining in T032.
    
    Args:
        text: Input text to hash
        
    Returns:
        SHA-256 hash of the first 50 characters of the text
    """
    # Take first 50 characters or full text if shorter
    text_slice = text[:50] if len(text) >= 50 else text
    return hashlib.sha256(text_slice.encode()).hexdigest()
