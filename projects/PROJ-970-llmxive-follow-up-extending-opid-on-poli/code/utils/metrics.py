import math
from typing import List, Dict, Any, Optional

def calculate_success_rate(results: List[Dict[str, Any]]) -> float:
    """Calculate the success rate from a list of episode results."""
    if not results:
        return 0.0
    successes = sum(1 for r in results if r.get("success", False))
    return successes / len(results)

def calculate_raw_entropy(probs: List[float]) -> float:
    """Calculate raw Shannon entropy from a probability distribution."""
    if not probs:
        return 0.0
    entropy = 0.0
    for p in probs:
        if p > 0:
            entropy -= p * math.log2(p)
    return entropy

def calculate_mean_entropy(entropies: List[float]) -> float:
    """Calculate mean entropy from a list of entropy values."""
    if not entropies:
        return 0.0
    return sum(entropies) / len(entropies)

def calculate_variance(values: List[float]) -> float:
    """Calculate variance of a list of values."""
    if len(values) < 2:
        return 0.0
    mean = sum(values) / len(values)
    return sum((x - mean) ** 2 for x in values) / len(values)

def calculate_mean_log_prob_shift(logs: List[Dict[str, Any]], 
                                  tier: Optional[str] = None, 
                                  threshold: Optional[float] = None) -> float:
    """
    Calculate the mean log-probability shift per (Tier, Threshold) setting.
    
    This function aggregates logs generated by T021 (OPIDRouter logging) to compute
    the average absolute log-probability shift caused by skill injection.
    
    Args:
        logs: List of episode log dictionaries. Each dict is expected to contain:
              - 'tier': The complexity tier string (e.g., "Tier1", "Tier2", "Tier3")
              - 'threshold': The routing threshold float used for the episode
              - 'log_prob_shift': The float value of the log-probability shift
        tier: Optional filter for specific tier. If None, all tiers are included.
        threshold: Optional filter for specific threshold. If None, all thresholds are included.
    
    Returns:
        float: The mean log-probability shift for the filtered subset. 
               Returns 0.0 if no matching logs are found.
    
    Raises:
        ValueError: If required keys are missing from log entries.
    """
    if not logs:
        return 0.0
    
    filtered_shifts = []
    
    for log in logs:
        # Filter by tier if specified
        if tier is not None and log.get("tier") != tier:
            continue
        
        # Filter by threshold if specified
        if threshold is not None:
            log_threshold = log.get("threshold")
            if log_threshold is None:
                continue
            # Use a small epsilon for float comparison if needed, 
            # but exact match is preferred if thresholds are discrete
            if abs(log_threshold - threshold) > 1e-9:
                continue
        
        shift = log.get("log_prob_shift")
        if shift is None:
            raise ValueError("Log entry missing 'log_prob_shift' key")
        
        filtered_shifts.append(shift)
    
    if not filtered_shifts:
        return 0.0
    
    return sum(filtered_shifts) / len(filtered_shifts)

def calculate_distillation_cost_benefit_ratio(mean_shift: float, 
                                              success_rate_improvement: float) -> float:
    """
    Calculate the distillation cost-benefit ratio.
    
    Ratio = mean_log_prob_shift / success_rate_improvement
    
    Args:
        mean_shift: The mean log-probability shift (from calculate_mean_log_prob_shift).
        success_rate_improvement: The improvement in success rate (delta).
    
    Returns:
        float: The calculated ratio. Returns 0.0 if improvement is zero to avoid division by zero.
    """
    if success_rate_improvement == 0.0:
        return 0.0
    return mean_shift / success_rate_improvement
