"""
Motion exclusion filter for fMRI preprocessing pipeline.

This module implements the logic to exclude subjects based on motion parameters
extracted from fMRIPrep output. Subjects are excluded if their maximum
translation exceeds 3mm or maximum rotation exceeds 3 degrees.

Thresholds are configurable via the settings module.
"""

import os
import csv
import json
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple

import pandas as pd

from src.config.settings import get_config

logger = logging.getLogger(__name__)


class MotionFilterError(Exception):
    """Custom exception for motion filtering errors."""
    pass


def load_motion_data(motion_csv_path: Path) -> pd.DataFrame:
    """
    Load motion parameters from a CSV file generated by extract_motion.py.

    Args:
        motion_csv_path: Path to the motion parameters CSV file.

    Returns:
        DataFrame containing motion parameters with columns:
        subject_id, translation_x/y/z, rotation_x/y/z

    Raises:
        MotionFilterError: If the file does not exist or cannot be read.
    """
    if not motion_csv_path.exists():
        raise MotionFilterError(f"Motion CSV file not found: {motion_csv_path}")

    try:
        df = pd.read_csv(motion_csv_path)
    except Exception as e:
        raise MotionFilterError(f"Failed to read motion CSV: {e}")

    required_cols = [
        'subject_id', 'translation_x', 'translation_y', 'translation_z',
        'rotation_x', 'rotation_y', 'rotation_z'
    ]

    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise MotionFilterError(f"Missing required columns in motion CSV: {missing_cols}")

    return df


def calculate_max_displacement(row: pd.Series, translation_cols: List[str], rotation_cols: List[str]) -> Tuple[float, float]:
    """
    Calculate maximum translation (mm) and maximum rotation (degrees) for a subject.

    Args:
        row: A single row from the motion DataFrame.
        translation_cols: List of column names for translation parameters.
        rotation_cols: List of column names for rotation parameters.

    Returns:
        Tuple of (max_translation_mm, max_rotation_deg)
    """
    trans_values = [abs(float(row[col])) for col in translation_cols if not pd.isna(row[col])]
    rot_values = [abs(float(row[col])) for col in rotation_cols if not pd.isna(row[col])]

    max_trans = max(trans_values) if trans_values else 0.0
    max_rot = max(rot_values) if rot_values else 0.0

    return max_trans, max_rot


def filter_subjects(
    df: pd.DataFrame,
    translation_threshold_mm: float = 3.0,
    rotation_threshold_deg: float = 3.0
) -> Tuple[List[str], List[str], pd.DataFrame]:
    """
    Filter subjects based on motion thresholds.

    Subjects are excluded if their maximum translation > threshold_mm
    or maximum rotation > threshold_deg.

    Args:
        df: DataFrame with motion parameters.
        translation_threshold_mm: Maximum allowed translation in mm (default 3.0).
        rotation_threshold_deg: Maximum allowed rotation in degrees (default 3.0).

    Returns:
        Tuple of (included_subject_ids, excluded_subject_ids, filtered_df)
    """
    translation_cols = ['translation_x', 'translation_y', 'translation_z']
    rotation_cols = ['rotation_x', 'rotation_y', 'rotation_z']

    included_ids = []
    excluded_ids = []
    filtered_rows = []

    for _, row in df.iterrows():
        max_trans, max_rot = calculate_max_displacement(row, translation_cols, rotation_cols)

        if max_trans > translation_threshold_mm or max_rot > rotation_threshold_deg:
            excluded_ids.append(row['subject_id'])
            logger.debug(
                f"Excluding subject {row['subject_id']}: max_trans={max_trans:.3f}mm, "
                f"max_rot={max_rot:.3f}deg"
            )
        else:
            included_ids.append(row['subject_id'])
            filtered_rows.append(row)

    filtered_df = pd.DataFrame(filtered_rows) if filtered_rows else pd.DataFrame(columns=df.columns)

    return included_ids, excluded_ids, filtered_df


def write_exclusion_report(
    excluded_ids: List[str],
    report_path: Path,
  metadata: Optional[Dict[str, Any]] = None
) -> None:
    """
    Write a JSON report of excluded subjects.

    Args:
        excluded_ids: List of subject IDs that were excluded.
        report_path: Path to write the JSON report.
        metadata: Optional metadata to include in the report (e.g., thresholds used).
    """
    report = {
        "exclusion_criteria": {
            "max_translation_mm": metadata.get("translation_threshold_mm", 3.0) if metadata else 3.0,
            "max_rotation_deg": metadata.get("rotation_threshold_deg", 3.0) if metadata else 3.0
        },
        "total_excluded": len(excluded_ids),
        "excluded_subject_ids": excluded_ids
    }

    report_path.parent.mkdir(parents=True, exist_ok=True)

    with open(report_path, 'w') as f:
        json.dump(report, f, indent=2)

    logger.info(f"Wrote exclusion report to {report_path}")


def run_motion_filter(
    input_motion_csv: Path,
    output_filtered_csv: Path,
    output_report_json: Path,
    translation_threshold_mm: Optional[float] = None,
    rotation_threshold_deg: Optional[float] = None
) -> Dict[str, Any]:
    """
    Run the full motion filtering pipeline.

    1. Load motion data from CSV.
    2. Filter subjects based on thresholds.
    3. Write filtered data to new CSV.
    4. Write exclusion report to JSON.

    Args:
        input_motion_csv: Path to input motion parameters CSV.
        output_filtered_csv: Path to write filtered motion CSV.
        output_report_json: Path to write exclusion report JSON.
        translation_threshold_mm: Override threshold for translation (mm).
        rotation_threshold_deg: Override threshold for rotation (degrees).

    Returns:
        Dictionary with filtering results summary.
    """
    # Load config if thresholds not provided
    if translation_threshold_mm is None or rotation_threshold_deg is None:
        try:
            config = get_config()
            if translation_threshold_mm is None:
                translation_threshold_mm = float(config.get('motion_thresholds', {}).get('translation_mm', 3.0))
            if rotation_threshold_deg is None:
                rotation_threshold_deg = float(config.get('motion_thresholds', {}).get('rotation_deg', 3.0))
        except Exception as e:
            logger.warning(f"Could not load config for thresholds: {e}. Using defaults.")
            if translation_threshold_mm is None:
                translation_threshold_mm = 3.0
            if rotation_threshold_deg is None:
                rotation_threshold_deg = 3.0

    logger.info(f"Running motion filter with thresholds: trans={translation_threshold_mm}mm, rot={rotation_threshold_deg}deg")

    df = load_motion_data(input_motion_csv)

    included_ids, excluded_ids, filtered_df = filter_subjects(
        df,
        translation_threshold_mm=translation_threshold_mm,
        rotation_threshold_deg=rotation_threshold_deg
    )

    if not filtered_df.empty:
        filtered_df.to_csv(output_filtered_csv, index=False)
        logger.info(f"Wrote filtered data for {len(included_ids)} subjects to {output_filtered_csv}")
    else:
        # Create empty CSV with headers if no subjects pass
        df.head(0).to_csv(output_filtered_csv, index=False)
        logger.warning("No subjects passed the motion filter. Created empty output CSV.")

    metadata = {
        "translation_threshold_mm": translation_threshold_mm,
        "rotation_threshold_deg": rotation_threshold_deg
    }
    write_exclusion_report(excluded_ids, output_report_json, metadata)

    return {
        "total_subjects": len(df),
        "included_count": len(included_ids),
        "excluded_count": len(excluded_ids),
        "excluded_ids": excluded_ids,
        "translation_threshold_mm": translation_threshold_mm,
        "rotation_threshold_deg": rotation_threshold_deg
    }


def main() -> None:
    """Main entry point for motion filtering script."""
    import argparse

    parser = argparse.ArgumentParser(description="Filter subjects based on motion parameters.")
    parser.add_argument(
        "--input", "-i",
        type=Path,
        required=True,
        help="Path to input motion parameters CSV (from extract_motion.py)"
    )
    parser.add_argument(
        "--output-csv", "-o",
        type=Path,
        required=True,
        help="Path to write filtered motion CSV"
    )
    parser.add_argument(
        "--output-report", "-r",
        type=Path,
        required=True,
        help="Path to write exclusion report JSON"
    )
    parser.add_argument(
        "--trans-threshold",
        type=float,
        default=None,
        help="Maximum translation threshold in mm (default from config or 3.0)"
    )
    parser.add_argument(
        "--rot-threshold",
        type=float,
        default=None,
        help="Maximum rotation threshold in degrees (default from config or 3.0)"
    )

    args = parser.parse_args()

    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )

    try:
        result = run_motion_filter(
            input_motion_csv=args.input,
            output_filtered_csv=args.output_csv,
            output_report_json=args.output_report,
            translation_threshold_mm=args.trans_threshold,
            rotation_threshold_deg=args.rot_threshold
        )

        print(f"Motion filtering complete.")
        print(f"  Total subjects: {result['total_subjects']}")
        print(f"  Included: {result['included_count']}")
        print(f"  Excluded: {result['excluded_count']}")
        if result['excluded_ids']:
            print(f"  Excluded IDs: {', '.join(result['excluded_ids'])}")

    except MotionFilterError as e:
        logger.error(f"Motion filtering failed: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during motion filtering: {e}")
        raise


if __name__ == "__main__":
    main()
