import json
import logging
import sys
from pathlib import Path
from typing import Dict, Any, List, Tuple
from datetime import datetime

import pandas as pd
import numpy as np

from config import get_data_dir, get_config

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s",
    stream=sys.stdout,
)
logger = logging.getLogger(__name__)


def load_standardized_data() -> pd.DataFrame:
    """
    Load the standardized CSV generated by T017.
    Expects: data/processed/standardized.csv
    """
    data_dir = get_data_dir()
    input_path = data_dir / "processed" / "standardized.csv"

    if not input_path.exists():
        raise FileNotFoundError(
            f"Standardized data file not found at {input_path}. "
            "Please ensure T017 has been run successfully."
        )

    logger.info(f"Loading standardized data from {input_path}")
    df = pd.read_csv(input_path)

    # Verify required columns for Markov calculation
    required_cols = ["stimulus_sequence", "participant_id", "surprisal"]
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(
            f"Standardized data missing required columns: {missing}. "
            "T016 (Markov surprisal) must have been run correctly."
        )

    logger.info(f"Loaded {len(df)} rows. Columns: {list(df.columns)}")
    return df


def compute_transition_matrices(df: pd.DataFrame) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    """
    Compute first-order Markov transition probability tables and model state.

    Returns:
        transition_probs: Dict mapping participant_id -> transition matrix (dict of dicts)
        markov_state: Dict containing metadata about the model (order, alphabet, etc.)
    """
    logger.info("Computing first-order Markov transition matrices...")

    # Determine unique stimulus values (alphabet)
    # Assuming stimulus_sequence is numeric or can be treated as categorical
    # We handle both numeric and string sequences
    if df["stimulus_sequence"].dtype == object:
        alphabet = sorted(df["stimulus_sequence"].dropna().unique().tolist())
    else:
        # For numeric, we might have many unique values.
        # If it's a continuous variable, we might need to bin it, but T016 implies
        # a discrete sequence was used for the Markov model.
        # We'll assume discrete or binned values exist in the sequence.
        unique_vals = df["stimulus_sequence"].dropna().unique()
        # Sort numerically if possible
        try:
            alphabet = sorted([float(v) for v in unique_vals])
        except (ValueError, TypeError):
            alphabet = sorted([str(v) for v in unique_vals])

    logger.info(f"Alphabet size: {len(alphabet)}")

    transition_probs = {}
    participant_ids = df["participant_id"].unique()

    for pid in participant_ids:
        sub_df = df[df["participant_id"] == pid].copy()
        sub_df = sub_df.dropna(subset=["stimulus_sequence"])
        seq = sub_df["stimulus_sequence"].tolist()

        if len(seq) < 2:
            logger.warning(f"Participant {pid} has insufficient sequence length (<2). Skipping.")
            continue

        # Count transitions: P(next | current)
        # Key: current state, Value: dict of next_state -> count
        counts = {}
        for i in range(len(seq) - 1):
            curr = seq[i]
            nxt = seq[i + 1]

            if curr not in counts:
                counts[curr] = {}
            if nxt not in counts[curr]:
                counts[curr][nxt] = 0
            counts[curr][nxt] += 1

        # Convert counts to probabilities
        probs = {}
        for curr, next_counts in counts.items():
            total = sum(next_counts.values())
            probs[curr] = {}
            for nxt, count in next_counts.items():
                probs[curr][nxt] = count / total

        transition_probs[str(pid)] = probs

    logger.info(f"Computed transition matrices for {len(transition_probs)} participants.")

    markov_state = {
        "model_type": "First-Order Markov",
        "order": 1,
        "alphabet": alphabet,
        "alphabet_size": len(alphabet),
        "computation_timestamp": datetime.utcnow().isoformat(),
        "total_participants_processed": len(transition_probs),
        "source_file": "data/processed/standardized.csv",
        "description": "Transition probabilities P(S_t | S_{t-1}) computed from standardized stimulus sequences."
    }

    return transition_probs, markov_state


def save_markov_artifacts(
    transition_probs: Dict[str, Any],
    markov_state: Dict[str, Any],
    output_dir: Path
) -> None:
    """
    Save the transition probability tables and Markov model state to JSON files.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    # Save transition probabilities
    tp_path = output_dir / "transition_probs.json"
    with open(tp_path, "w", encoding="utf-8") as f:
        json.dump(transition_probs, f, indent=2, sort_keys=True)
    logger.info(f"Saved transition probabilities to {tp_path}")

    # Save Markov model state
    ms_path = output_dir / "markov_state.json"
    with open(ms_path, "w", encoding="utf-8") as f:
        json.dump(markov_state, f, indent=2, sort_keys=True)
    logger.info(f"Saved Markov model state to {ms_path}")


def run_t017b() -> None:
    """
    Main entry point for Task T017b.
    Loads standardized data, computes Markov artifacts, and saves them.
    """
    config = get_config()
    set_seed(config.get("random_seed", 42))

    data_dir = get_data_dir()
    processed_dir = data_dir / "processed"

    # 1. Load standardized data
    df = load_standardized_data()

    # 2. Compute transition matrices and state
    transition_probs, markov_state = compute_transition_matrices(df)

    # 3. Save artifacts
    save_markov_artifacts(transition_probs, markov_state, processed_dir)

    logger.info("T017b completed successfully.")


def main() -> None:
    try:
        run_t017b()
    except Exception as e:
        logger.error(f"T017b failed: {e}", exc_info=True)
        sys.exit(1)


if __name__ == "__main__":
    main()
