def load_standardized_data() -> pd.DataFrame:
    """Load the standardized CSV generated by T017."""
    processed_dir = get_processed_dir()
    input_path = processed_dir / "standardized.csv"
    
    if not input_path.exists():
        raise FileNotFoundError(f"Standardized data not found at {input_path}. "
                                "Ensure T017 has been executed successfully.")
    
    logger.info(f"Loading standardized data from {input_path}")
    df = pd.read_csv(input_path)
    logger.info(f"Loaded {len(df)} rows with columns: {list(df.columns)}")
    return df

def compute_transition_matrices(df: pd.DataFrame, stimulus_col: str = 'stimulus_sequence') -> Tuple[Dict[str, Dict[str, float]], List[str]]:
    """
    Compute the transition probability matrix and alphabet from the sequence data.
    
    Args:
        df: DataFrame containing the standardized data.
        stimulus_col: Name of the column containing the stimulus sequence.
        
    Returns:
        Tuple of (transition_matrix, alphabet)
    """
    if stimulus_col not in df.columns:
        raise ValueError(f"Column '{stimulus_col}' not found in dataframe. "
                         f"Available columns: {list(df.columns)}")
    
    # Flatten the sequence if it's stored as a list/string representation
    # Assuming the column contains lists or comma-separated strings
    sequences = []
    for seq in df[stimulus_col]:
        if isinstance(seq, str):
            # Handle string representation of lists or comma-separated values
            if seq.startswith('[') and seq.endswith(']'):
                # Remove brackets and split
                items = [x.strip().strip("'\"") for x in seq[1:-1].split(',')]
            else:
                items = [x.strip() for x in seq.split(',')]
            sequences.extend(items)
        elif isinstance(seq, list):
            sequences.extend(seq)
        else:
            sequences.append(str(seq))
    
    if not sequences:
        raise ValueError("No valid sequence data found to compute transitions.")
    
    # Compute transition counts
    transition_counts: Dict[str, Dict[str, int]] = {}
    alphabet = set()
    
    for i in range(len(sequences) - 1):
        current = str(sequences[i])
        next_item = str(sequences[i + 1])
        alphabet.add(current)
        alphabet.add(next_item)
        
        if current not in transition_counts:
            transition_counts[current] = {}
        
        if next_item not in transition_counts[current]:
            transition_counts[current][next_item] = 0
        
        transition_counts[current][next_item] += 1
    
    # Convert counts to probabilities (Laplace smoothing with alpha=1.0)
    alpha = 1.0
    alphabet_list = sorted(list(alphabet))
    alphabet_size = len(alphabet_list)
    
    transition_matrix: Dict[str, Dict[str, float]] = {}
    
    for current_state in transition_counts:
        transition_matrix[current_state] = {}
        total_transitions = sum(transition_counts[current_state].values())
        
        for next_state in alphabet_list:
            count = transition_counts[current_state].get(next_state, 0)
            # Laplace smoothing: P(next|current) = (count + alpha) / (total + alpha * |V|)
            prob = (count + alpha) / (total_transitions + alpha * alphabet_size)
            transition_matrix[current_state][next_state] = prob
    
    # Ensure all alphabet states are present in the matrix (even if they have no outgoing transitions)
    for state in alphabet_list:
        if state not in transition_matrix:
            transition_matrix[state] = {next_state: 1.0 / alphabet_size for next_state in alphabet_list}
    
    return transition_matrix, alphabet_list

def save_markov_artifacts(transition_matrix: Dict[str, Dict[str, float]], 
                          alphabet: List[str], 
                          order: int = 1) -> None:
    """
    Save the Markov model state and transition probability tables to JSON files.
    
    Args:
        transition_matrix: The computed transition probability matrix.
        alphabet: The list of unique states in the sequence.
        order: The order of the Markov model (must be 1 for this task).
    """
    processed_dir = get_processed_dir()
    processed_dir.mkdir(parents=True, exist_ok=True)
    
    # Validate order constraint
    if order != 1:
        raise ValueError(f"Markov model order must be 1 for this task. "
                         f"Received order: {order}")
    
    # Prepare state dictionary
    markov_state = {
        "transition_matrix": transition_matrix,
        "alphabet": alphabet,
        "order": order,
        "metadata": {
            "generated_at": datetime.utcnow().isoformat(),
            "source": "T017b - Markov Artifacts",
            "smoothing": "Laplace (alpha=1.0)"
        }
    }
    
    # Save markov_state.json
    state_path = processed_dir / "markov_state.json"
    with open(state_path, 'w', encoding='utf-8') as f:
        json.dump(markov_state, f, indent=2)
    logger.info(f"Saved Markov state to {state_path}")
    
    # Save transition-probability table separately for easy access
    probs_path = processed_dir / "transition_probs.json"
    with open(probs_path, 'w', encoding='utf-8') as f:
        json.dump(transition_matrix, f, indent=2)
    logger.info(f"Saved transition probabilities to {probs_path}")
    
    # Verify files exist and are not empty
    assert state_path.exists(), "markov_state.json was not created"
    assert state_path.stat().st_size > 0, "markov_state.json is empty"
    assert probs_path.exists(), "transition_probs.json was not created"
    assert probs_path.stat().st_size > 0, "transition_probs.json is empty"

def run_t017b() -> None:
    """
    Execute the T017b pipeline: load standardized data, compute transition matrices,
    and save artifacts.
    """
    try:
        # 1. Load standardized data
        df = load_standardized_data()
        
        # 2. Compute transition matrices
        transition_matrix, alphabet = compute_transition_matrices(df)
        logger.info(f"Computed transition matrix for {len(alphabet)} states")
        
        # 3. Save artifacts with order=1
        save_markov_artifacts(transition_matrix, alphabet, order=1)
        
        logger.info("T017b completed successfully. Artifacts saved.")
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Value error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during T017b execution: {e}", exc_info=True)
        sys.exit(1)

def main() -> None:
    """Entry point for the script."""
    run_t017b()

if __name__ == "__main__":
    main()
