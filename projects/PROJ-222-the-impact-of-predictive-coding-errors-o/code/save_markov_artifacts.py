"""
Task T017b: Save 'transition-probability tables' and 'Markov model state' as versioned artifacts.

This script reads the standardized processed data (generated by T017),
extracts the Markov model parameters (transition probabilities) derived
during the surprisal calculation, and saves them as versioned JSON artifacts
in data/processed/.

It depends on the Markov model state computed in `code/preprocess.py` (specifically
the transition matrices stored in the metadata or re-computed from the sequence data
if not explicitly stored yet). To ensure robustness, this script recomputes the
transition probabilities from the `stimulus_sequence` column in the standardized data
using the same logic as `compute_markov_surprisal`.
"""
import json
import logging
import sys
from pathlib import Path
from typing import Dict, Any, List, Tuple
from datetime import datetime

import pandas as pd
import numpy as np

# Import project utilities
from config import get_data_dir, get_config
from preprocess import compute_markov_surprisal

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def load_standardized_data() -> pd.DataFrame:
    """Load the standardized CSV generated by T017."""
    data_dir = get_data_dir()
    input_path = data_dir / "processed" / "standardized.csv"
    
    if not input_path.exists():
        raise FileNotFoundError(
            f"Standardized data not found at {input_path}. "
            "Please run T017 (generate_standardized_output.py) first."
        )
    
    logger.info(f"Loading standardized data from {input_path}")
    df = pd.read_csv(input_path)
    return df

def compute_transition_matrices(df: pd.DataFrame) -> Dict[str, Any]:
    """
    Compute transition probability tables from the stimulus sequence.
    
    This function reconstructs the Markov model state by counting
    transitions between consecutive stimuli in the sequence and
    normalizing them to probabilities.
    
    Returns:
        A dictionary containing:
        - 'transition_counts': The raw count matrix.
        - 'transition_probabilities': The normalized probability matrix.
        - 'unique_states': List of unique stimulus states found.
        - 'sequence_length': Total length of sequences analyzed.
    """
    if 'stimulus_sequence' not in df.columns:
        raise ValueError("Column 'stimulus_sequence' not found in standardized data.")
    
    # Flatten sequences if they are stored as lists/strings, or iterate if already flat
    # Assuming 'stimulus_sequence' is a string representation or a list of states
    # We handle both cases.
    
    all_transitions = []
    unique_states = set()
    total_sequence_length = 0
    
    # Process each row's sequence
    for seq in df['stimulus_sequence']:
        # Normalize input: if it's a string like "[A, B, C]", parse it
        if isinstance(seq, str):
            # Handle string representations of lists
            try:
                # Simple parsing for "[A, B, C]" or "A,B,C"
                if seq.startswith('[') and seq.endswith(']'):
                    seq = seq.strip('[]').replace(' ', '').split(',')
                elif ',' in seq:
                    seq = seq.split(',')
                else:
                    seq = list(seq) # Treat as char sequence
            except Exception:
                logger.warning(f"Could not parse sequence string: {seq}, skipping.")
                continue
        
        if not isinstance(seq, (list, tuple, np.ndarray)):
            seq = list(seq)
        
        if len(seq) < 2:
            continue
        
        # Convert to a consistent type (string) for hashing
        seq_str = [str(s) for s in seq]
        unique_states.update(seq_str)
        total_sequence_length += len(seq_str)
        
        # Count transitions
        for i in range(len(seq_str) - 1):
            all_transitions.append((seq_str[i], seq_str[i+1]))
    
    if not all_transitions:
        logger.warning("No valid transitions found in the dataset.")
        return {
            "transition_counts": {},
            "transition_probabilities": {},
            "unique_states": [],
            "sequence_length": 0,
            "error": "No transitions found"
        }
    
    # Aggregate counts
    from collections import defaultdict
    counts = defaultdict(lambda: defaultdict(int))
    
    for src, dst in all_transitions:
        counts[src][dst] += 1
    
    # Convert to regular dicts and compute probabilities
    prob_matrix = {}
    count_matrix = {}
    sorted_states = sorted(list(unique_states))
    
    for src in sorted_states:
        count_matrix[src] = {}
        prob_matrix[src] = {}
        total_out = sum(counts[src].values())
        
        for dst in sorted_states:
            c = counts[src][dst]
            count_matrix[src][dst] = c
            if total_out > 0:
                prob_matrix[src][dst] = c / total_out
            else:
                prob_matrix[src][dst] = 0.0
    
    return {
        "transition_counts": count_matrix,
        "transition_probabilities": prob_matrix,
        "unique_states": sorted_states,
        "sequence_length": total_sequence_length,
        "total_transitions": len(all_transitions)
    }

def save_markov_artifacts(transition_data: Dict[str, Any], output_dir: Path) -> None:
    """
    Save the transition probability tables and model state to JSON files.
    
    Artifacts created:
    - transition_probabilities.json: The core Markov model state.
    - model_metadata.json: Versioning, dataset info, and generation timestamp.
    """
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    version = get_config().get("version", "0.1.0")
    
    # 1. Save Transition Probabilities
    prob_file = output_dir / f"transition_probabilities_{timestamp}.json"
    with open(prob_file, 'w') as f:
        json.dump(transition_data["transition_probabilities"], f, indent=2)
    logger.info(f"Saved transition probabilities to {prob_file}")
    
    # 2. Save Counts (for debugging/verification)
    counts_file = output_dir / f"transition_counts_{timestamp}.json"
    with open(counts_file, 'w') as f:
        json.dump(transition_data["transition_counts"], f, indent=2)
    logger.info(f"Saved transition counts to {counts_file}")
    
    # 3. Save Model State Metadata (Constitution VI: Versioning)
    metadata = {
        "artifact_type": "markov_model_state",
        "version": version,
        "generated_at": timestamp,
        "unique_states": transition_data["unique_states"],
        "total_sequence_length": transition_data["sequence_length"],
        "total_transitions": transition_data["total_transitions"],
        "input_file": "data/processed/standardized.csv",
        "source_code": "code/save_markov_artifacts.py"
    }
    
    meta_file = output_dir / f"markov_model_state_{timestamp}.json"
    with open(meta_file, 'w') as f:
        json.dump(metadata, f, indent=2)
    logger.info(f"Saved model state metadata to {meta_file}")
    
    # Create a symlink or copy for the latest version for easy access
    latest_prob = output_dir / "transition_probabilities_latest.json"
    latest_counts = output_dir / "transition_counts_latest.json"
    latest_meta = output_dir / "markov_model_state_latest.json"
    
    # Using shutil.copy2 to preserve metadata or just write again? 
    # Since we are in a script, let's just copy the file content if possible, 
    # but simpler is to just note the latest timestamp in a manifest or 
    # just rely on the timestamped files. 
    # For robustness, we'll create a 'latest' pointer file.
    
    latest_manifest = output_dir / "latest_markov_artifacts.json"
    with open(latest_manifest, 'w') as f:
        json.dump({
            "probabilities": prob_file.name,
            "counts": counts_file.name,
            "metadata": meta_file.name
        }, f, indent=2)
    
    logger.info(f"Created latest manifest at {latest_manifest}")

def run_t017b() -> None:
    """Main entry point for Task T017b."""
    logger.info("Starting Task T017b: Saving Markov Artifacts")
    
    try:
        # 1. Load Data
        df = load_standardized_data()
        
        # 2. Compute Transition Matrices
        # This effectively reconstructs the Markov Model State from the data
        transition_data = compute_transition_matrices(df)
        
        if "error" in transition_data:
            logger.error(f"Failed to compute transition data: {transition_data['error']}")
            sys.exit(1)
        
        # 3. Save Artifacts
        data_dir = get_data_dir()
        output_dir = data_dir / "processed"
        
        if not output_dir.exists():
            output_dir.mkdir(parents=True)
        
        save_markov_artifacts(transition_data, output_dir)
        
        logger.info("Task T017b completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(f"Missing required input: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during T017b: {e}")
        raise

if __name__ == "__main__":
    run_t017b()
