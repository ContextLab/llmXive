"""
Update README with dataset exclusion status and reasons.

This script reads the exclusion log generated by T012b (download.py)
and updates data/README.md with a comprehensive status table.
"""
import json
import logging
import os
import sys
from pathlib import Path
from typing import Dict, Any, List, Optional
from datetime import datetime

# Import from local config
from config import get_data_dir

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)


def load_exclusion_log(exclusion_log_path: Path) -> List[Dict[str, Any]]:
    """
    Load the exclusion log from JSON file.
    
    Args:
        exclusion_log_path: Path to the exclusion log file
        
    Returns:
        List of exclusion records
        
    Raises:
        FileNotFoundError: If the exclusion log file doesn't exist
        json.JSONDecodeError: If the file is not valid JSON
    """
    if not exclusion_log_path.exists():
        raise FileNotFoundError(f"Exclusion log not found at {exclusion_log_path}")
        
    with open(exclusion_log_path, 'r', encoding='utf-8') as f:
        return json.load(f)


def parse_verified_datasets(dataset_ids_path: Path) -> List[str]:
    """
    Parse the list of dataset IDs from the source file.
    
    Args:
        dataset_ids_path: Path to dataset_ids.txt
        
    Returns:
        List of dataset ID strings
    """
    if not dataset_ids_path.exists():
        logger.warning(f"Dataset IDs file not found at {dataset_ids_path}")
        return []
        
    with open(dataset_ids_path, 'r', encoding='utf-8') as f:
        # Filter out empty lines and comments
        ids = [line.strip() for line in f if line.strip() and not line.startswith('#')]
    return ids


def generate_dataset_status_section(
    all_ids: List[str],
    exclusion_log: List[Dict[str, Any]]
) -> str:
    """
    Generate a markdown table showing the status of all datasets.
    
    Args:
        all_ids: List of all dataset IDs that were attempted
        exclusion_log: List of exclusion records
        
    Returns:
        Markdown formatted status section
    """
    # Build a lookup for exclusions
    exclusion_map = {
        record.get('dataset_id', record.get('id', '')): record
        for record in exclusion_log
    }
    
    lines = []
    lines.append("## Dataset Status Summary")
    lines.append("")
    lines.append("| Dataset ID | Status | Reason | Checksum |")
    lines.append("|------------|--------|--------|----------|")
    
    valid_count = 0
    excluded_count = 0
    
    for dataset_id in all_ids:
        if dataset_id in exclusion_map:
            record = exclusion_map[dataset_id]
            status = "Excluded"
            reason = record.get('reason', 'Unknown')
            checksum = record.get('checksum', 'N/A')
            excluded_count += 1
        else:
            status = "Valid"
            reason = "N/A"
            checksum = "Verified"
            valid_count += 1
        
        lines.append(f"| {dataset_id} | {status} | {reason} | {checksum} |")
    
    lines.append("")
    lines.append(f"**Summary**: {valid_count} valid, {excluded_count} excluded.")
    lines.append("")
    
    return "\n".join(lines)


def generate_exclusion_details_section(exclusion_log: List[Dict[str, Any]]) -> str:
    """
    Generate detailed exclusion reasons section.
    
    Args:
        exclusion_log: List of exclusion records
        
    Returns:
        Markdown formatted exclusion details
    """
    if not exclusion_log:
        return "## Dataset Exclusions\n\nNo datasets were excluded.\n"
        
    lines = []
    lines.append("## Dataset Exclusions")
    lines.append("")
    
    for record in exclusion_log:
        dataset_id = record.get('dataset_id', record.get('id', 'Unknown'))
        reason = record.get('reason', 'Unknown reason')
        step = record.get('step', 'Unknown step')
        
        lines.append(f"### {dataset_id}")
        lines.append(f"- **Status**: Excluded")
        lines.append(f"- **Reason**: {reason}")
        lines.append(f"- **Failure Stage**: {step}")
        lines.append("")
    
    return "\n".join(lines)


def update_readme(
    readme_path: Path,
    dataset_ids_path: Path,
    exclusion_log: List[Dict[str, Any]]
) -> None:
    """
    Update the README.md file with current dataset status.
    
    Args:
        readme_path: Path to the README.md file
        dataset_ids_path: Path to dataset_ids.txt
        exclusion_log: List of exclusion records
    """
    if not readme_path.exists():
        logger.error(f"README.md not found at {readme_path}")
        raise FileNotFoundError(f"README.md not found at {readme_path}")
        
    # Read existing content
    with open(readme_path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Generate new sections
    all_ids = parse_verified_datasets(dataset_ids_path)
    status_section = generate_dataset_status_section(all_ids, exclusion_log)
    exclusion_section = generate_exclusion_details_section(exclusion_log)
    
    # Insert or replace sections
    # Find the "## Dataset Status Summary" section
    if "## Dataset Status Summary" in content:
        # Replace the status section
        start_idx = content.find("## Dataset Status Summary")
        # Find the next section header or end of file
        next_header = content.find("##", start_idx + 1)
        if next_header == -1:
            next_header = len(content)
        
        # Replace everything from status start to next header
        new_content = (
            content[:start_idx] + 
            status_section + "\n" + 
            exclusion_section + "\n" +
            content[next_header:]
        )
    else:
        # Append new sections before "## Checksums" or at end
        if "## Checksums" in content:
            checksum_idx = content.find("## Checksums")
            new_content = (
                content[:checksum_idx] + 
                status_section + "\n" + 
                exclusion_section + "\n" +
                content[checksum_idx:]
            )
        else:
            # Append to end
            new_content = content + "\n" + status_section + "\n" + exclusion_section
    
    # Write updated content
    with open(readme_path, 'w', encoding='utf-8') as f:
        f.write(new_content)
    
    logger.info(f"Updated README at {readme_path}")


def run_t013(exclusion_log_path: Path, dataset_ids_path: Path, readme_path: Path) -> None:
    """
    Execute the full T012c workflow.
    
    Args:
        exclusion_log_path: Path to exclusion log JSON
        dataset_ids_path: Path to dataset IDs file
        readme_path: Path to README.md
    """
    logger.info(f"Loading exclusion log from {exclusion_log_path}")
    exclusion_log = load_exclusion_log(exclusion_log_path)
    
    logger.info(f"Updating README at {readme_path}")
    update_readme(readme_path, dataset_ids_path, exclusion_log)


def main() -> int:
    """
    Main entry point for the update_readme script.
    
    Returns:
        Exit code (0 for success, 1 for failure)
    """
    try:
        data_dir = get_data_dir()
        exclusion_log_path = data_dir / "processed" / "exclusion_log.json"
        dataset_ids_path = data_dir / "dataset_ids.txt"
        readme_path = data_dir / "README.md"
        
        logger.info(f"Data directory: {data_dir}")
        logger.info(f"Exclusion log path: {exclusion_log_path}")
        
        # Check if exclusion log exists
        if not exclusion_log_path.exists():
            logger.warning(f"Exclusion log not found at {exclusion_log_path}.")
            logger.warning("This may be expected if all datasets were valid.")
            # Still update README to reflect no exclusions
            exclusion_log = []
        else:
            exclusion_log = load_exclusion_log(exclusion_log_path)
            logger.info(f"Loaded {len(exclusion_log)} exclusion records.")
        
        # Update README
        update_readme(readme_path, dataset_ids_path, exclusion_log)
        
        logger.info("README update completed successfully.")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        return 1
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in exclusion log: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())