"""
Update README with exclusion log data.

This script reads the exclusion log generated by T012b and updates
the data/README.md file with the status of each dataset (valid/excluded)
and the reasons for exclusion.
"""

import json
import logging
import os
import sys
from pathlib import Path
from typing import Dict, Any, List, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def get_data_dir() -> Path:
    """Get the data directory path."""
    return Path(__file__).parent.parent / 'data'

def get_processed_dir() -> Path:
    """Get the processed data directory path."""
    return get_data_dir() / 'processed'

def load_exclusion_log(log_path: Optional[Path] = None) -> List[Dict[str, Any]]:
    """
    Load the exclusion log from JSON file.

    Args:
        log_path: Path to the exclusion log file. If None, uses default path.

    Returns:
        List of exclusion records.

    Raises:
        FileNotFoundError: If the exclusion log file doesn't exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    if log_path is None:
        log_path = get_processed_dir() / 'exclusion_log.json'

    if not log_path.exists():
        raise FileNotFoundError(f"Exclusion log not found at {log_path}")

    with open(log_path, 'r') as f:
        data = json.load(f)

    # Ensure we return a list
    if isinstance(data, dict) and 'exclusions' in data:
        return data['exclusions']
    elif isinstance(data, list):
        return data
    else:
        logger.warning(f"Unexpected exclusion log format at {log_path}")
        return []

def parse_verified_datasets(readme_path: Path) -> Dict[str, Any]:
    """
    Parse the verified datasets section from README if it exists.

    Args:
        readme_path: Path to the README file.

    Returns:
        Dictionary of verified datasets.
    """
    if not readme_path.exists():
        return {}

    verified_datasets = {}

    with open(readme_path, 'r') as f:
        content = f.read()

    # Simple parsing to extract existing verified datasets
    # This is a placeholder for more sophisticated parsing if needed
    # For now, we'll just return an empty dict and rebuild the section
    return verified_datasets

def generate_dataset_status_section(exclusion_log: List[Dict[str, Any]],
                                   verified_datasets: Dict[str, Any]) -> str:
    """
    Generate the dataset status section for the README.

    Args:
        exclusion_log: List of exclusion records.
        verified_datasets: Dictionary of verified datasets.

    Returns:
        Markdown string for the dataset status section.
    """
    lines = [
        "## Dataset Status",
        "",
        "| Dataset ID | Status | Reason | Checksum |",
        "|------------|--------|--------|----------|"
    ]

    # Collect all dataset IDs from exclusion log
    all_datasets = {}

    # Add excluded datasets
    for entry in exclusion_log:
        dataset_id = entry.get('dataset_id', 'Unknown')
        reason = entry.get('reason', 'Unknown reason')
        checksum = entry.get('checksum', 'N/A')
        all_datasets[dataset_id] = {
            'status': 'Excluded',
            'reason': reason,
            'checksum': checksum
        }

    # Add verified datasets (if any)
    for dataset_id, info in verified_datasets.items():
        if dataset_id not in all_datasets:
            all_datasets[dataset_id] = {
                'status': 'Valid',
                'reason': 'Passed all validation checks',
                'checksum': info.get('checksum', 'N/A')
            }

    # Sort by dataset ID for consistent output
    for dataset_id in sorted(all_datasets.keys()):
        info = all_datasets[dataset_id]
        lines.append(
            f"| {dataset_id} | {info['status']} | {info['reason']} | {info['checksum']} |"
        )

    if len(all_datasets) == 0:
        lines.append("| No datasets processed yet | - | - | - |")

    lines.append("")
    return "\n".join(lines)

def generate_exclusion_details_section(exclusion_log: List[Dict[str, Any]]) -> str:
    """
    Generate the exclusion details section for the README.

    Args:
        exclusion_log: List of exclusion records.

    Returns:
        Markdown string for the exclusion details section.
    """
    lines = [
        "## Dataset Exclusions",
        ""
    ]

    if not exclusion_log:
        lines.append("No datasets were excluded during validation.")
        lines.append("")
        return "\n".join(lines)

    # Group exclusions by reason
    exclusions_by_reason = {}
    for entry in exclusion_log:
        reason = entry.get('reason', 'Unknown reason')
        if reason not in exclusions_by_reason:
            exclusions_by_reason[reason] = []
        exclusions_by_reason[reason].append(entry)

    for reason, entries in exclusions_by_reason.items():
        lines.append(f"### {reason}")
        lines.append("")
        for entry in entries:
            dataset_id = entry.get('dataset_id', 'Unknown')
            details = entry.get('details', 'No additional details')
            lines.append(f"- **{dataset_id}**: {details}")
        lines.append("")

    return "\n".join(lines)

def update_readme(readme_path: Path,
                 exclusion_log: List[Dict[str, Any]],
                 verified_datasets: Dict[str, Any]) -> None:
    """
    Update the README.md file with exclusion log data.

    Args:
        readme_path: Path to the README file.
        exclusion_log: List of exclusion records.
        verified_datasets: Dictionary of verified datasets.
    """
    if not readme_path.exists():
        logger.error(f"README not found at {readme_path}")
        return

    # Read existing content
    with open(readme_path, 'r') as f:
        content = f.read()

    # Generate new sections
    status_section = generate_dataset_status_section(exclusion_log, verified_datasets)
    exclusion_section = generate_exclusion_details_section(exclusion_log)

    # Replace or add sections
    # Find the "## Dataset Status" section
    status_marker = "## Dataset Status"
    exclusion_marker = "## Dataset Exclusions"

    lines = content.split('\n')
    new_lines = []
    in_status_section = False
    in_exclusion_section = False
    skip_until_next_header = False

    i = 0
    while i < len(lines):
        line = lines[i]

        # Check for section markers
        if line.strip().startswith(status_marker):
            in_status_section = True
            new_lines.append(line)
            # Add the new status section content
            for status_line in status_section.split('\n'):
                new_lines.append(status_line)
            # Skip old content until next header
            skip_until_next_header = True
            i += 1
            continue

        if line.strip().startswith(exclusion_marker):
            in_exclusion_section = True
            new_lines.append(line)
            # Add the new exclusion section content
            for exclusion_line in exclusion_section.split('\n'):
                new_lines.append(exclusion_line)
            # Skip old content until next header
            skip_until_next_header = True
            i += 1
            continue

        # Handle skipping old content
        if skip_until_next_header:
            if line.strip().startswith('## ') and not line.strip().startswith(status_marker) and not line.strip().startswith(exclusion_marker):
                skip_until_next_header = False
                new_lines.append(line)
            i += 1
            continue

        new_lines.append(line)
        i += 1

    # If sections weren't found, append them at the end
    if not in_status_section:
        new_lines.append("\n" + status_section)
    if not in_exclusion_section:
        new_lines.append("\n" + exclusion_section)

    # Write updated content
    with open(readme_path, 'w') as f:
        f.write('\n'.join(new_lines))

    logger.info(f"README updated successfully at {readme_path}")

def run_t013() -> None:
    """
    Main entry point for T012c task.

    This function orchestrates the README update process:
    1. Load the exclusion log from data/processed/exclusion_log.json
    2. Parse any existing verified datasets
    3. Generate updated sections
    4. Write the updated README
    """
    data_dir = get_data_dir()
    processed_dir = get_processed_dir()
    readme_path = data_dir / 'README.md'
    exclusion_log_path = processed_dir / 'exclusion_log.json'

    logger.info(f"Starting README update process")
    logger.info(f"Exclusion log path: {exclusion_log_path}")
    logger.info(f"README path: {readme_path}")

    # Check if exclusion log exists
    if not exclusion_log_path.exists():
        logger.warning(f"Exclusion log not found at {exclusion_log_path}")
        logger.warning("Creating empty exclusion log and updating README accordingly")

        # Create empty exclusion log
        processed_dir.mkdir(parents=True, exist_ok=True)
        with open(exclusion_log_path, 'w') as f:
            json.dump({'exclusions': []}, f, indent=2)

        exclusion_log = []
    else:
        try:
            exclusion_log = load_exclusion_log(exclusion_log_path)
            logger.info(f"Loaded {len(exclusion_log)} exclusion records")
        except Exception as e:
            logger.error(f"Failed to load exclusion log: {e}")
            sys.exit(1)

    # Parse verified datasets (currently empty as we don't have a separate verified list)
    verified_datasets = parse_verified_datasets(readme_path)
    logger.info(f"Parsed {len(verified_datasets)} verified datasets")

    # Update README
    try:
        update_readme(readme_path, exclusion_log, verified_datasets)
        logger.info("README update completed successfully")
    except Exception as e:
        logger.error(f"Failed to update README: {e}")
        sys.exit(1)

def main() -> None:
    """Main entry point."""
    run_t013()

if __name__ == '__main__':
    main()
