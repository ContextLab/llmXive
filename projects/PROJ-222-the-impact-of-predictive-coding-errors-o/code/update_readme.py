"""
T013: Update README with dataset exclusion logs and statuses.

This script reads the exclusion log generated by T012 (data/processed/exclusion_log.json)
and updates data/README.md to reflect the status (valid/excluded) and reasons for each dataset.

It does NOT modify the README during the download phase; it is the sole updater based on
the final exclusion log.
"""

import json
import logging
import os
import sys
from pathlib import Path
from typing import Dict, Any, List, Optional

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from config import get_data_dir, get_processed_dir

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)


def load_exclusion_log(exclusion_log_path: Path) -> List[Dict[str, Any]]:
    """
    Load the exclusion log from the specified path.
    Returns an empty list if the file does not exist or is empty.
    """
    if not exclusion_log_path.exists():
        logger.warning(f"Exclusion log not found at {exclusion_log_path}. Returning empty list.")
        return []

    try:
        with open(exclusion_log_path, 'r', encoding='utf-8') as f:
            content = f.read().strip()
            if not content:
                return []
            return json.loads(content)
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse exclusion log JSON: {e}")
        return []
    except Exception as e:
        logger.error(f"Error reading exclusion log: {e}")
        return []


def parse_verified_datasets(readme_path: Path) -> Dict[str, Dict[str, Any]]:
    """
    Parse the 'Verified datasets' section from the README to get the initial list of datasets.
    Returns a dict mapping dataset_id (e.g., 'openml_42277') to their metadata.
    """
    if not readme_path.exists():
        logger.warning(f"README not found at {readme_path}. Returning empty dict.")
        return {}

    datasets = {}
    current_dataset = None
    in_verified_section = False

    try:
        with open(readme_path, 'r', encoding='utf-8') as f:
            for line in f:
                line_stripped = line.strip()

                if line_stripped.startswith("### Verified datasets"):
                    in_verified_section = True
                    continue

                if in_verified_section:
                    if line_stripped.startswith("### ") and not line_stripped.startswith("### Verified"):
                        # End of verified section
                        if current_dataset:
                            datasets[current_dataset['id']] = current_dataset
                        in_verified_section = False
                        break

                    if line_stripped.startswith("- id:"):
                        if current_dataset:
                            datasets[current_dataset['id']] = current_dataset
                        dataset_id = line_stripped.split(":", 1)[1].strip()
                        current_dataset = {'id': dataset_id, 'source': '', 'type': ''}
                    elif line_stripped.startswith("- source:") and current_dataset:
                        current_dataset['source'] = line_stripped.split(":", 1)[1].strip()
                    elif line_stripped.startswith("- type:") and current_dataset:
                        current_dataset['type'] = line_stripped.split(":", 1)[1].strip()

        if current_dataset:
            datasets[current_dataset['id']] = current_dataset

    except Exception as e:
        logger.error(f"Error parsing README: {e}")

    return datasets


def generate_dataset_status_section(
    verified_datasets: Dict[str, Dict[str, Any]],
    exclusion_log: List[Dict[str, Any]]
) -> str:
    """
    Generate the 'Dataset Status' section for the README.
    Combines verified datasets with their status (valid/excluded) and reasons.
    """
    exclusion_dict = {item.get('dataset_id'): item for item in exclusion_log}

    lines = ["### Dataset Status"]

    # Sort by dataset_id for consistent output
    sorted_ids = sorted(verified_datasets.keys())

    for ds_id in sorted_ids:
        ds_info = verified_datasets[ds_id]
        source = ds_info.get('source', 'unknown')
        # Format ID as 'source_id' (e.g., 'openml_42277')
        formatted_id = f"{source}_{ds_id}"

        if formatted_id in exclusion_dict:
            entry = exclusion_dict[formatted_id]
            reason = entry.get('reason', 'Unknown reason')
            lines.append(f"- {formatted_id}: excluded ({reason})")
        else:
            # If not in exclusion log, it's valid
            lines.append(f"- {formatted_id}: valid")

    return "\n".join(lines)


def update_readme(readme_path: Path, status_section: str) -> None:
    """
    Update the README.md file by replacing the '### Dataset Status' section
    with the newly generated status section.
    If the section doesn't exist, append it under '## Exclusion Logs'.
    """
    if not readme_path.exists():
        logger.error(f"README not found at {readme_path}. Cannot update.")
        raise FileNotFoundError(f"README not found at {readme_path}")

    try:
        with open(readme_path, 'r', encoding='utf-8') as f:
            content = f.read()

        # Check if '### Dataset Status' section exists
        if "### Dataset Status" in content:
            # Replace the existing section
            # Find start and end of the section
            start_marker = "### Dataset Status"
            start_idx = content.find(start_marker)

            # Find the next section header (### ) after the start
            end_idx = content.find("\n### ", start_idx + len(start_marker))
            if end_idx == -1:
                # If no next section, go to end of file
                end_idx = len(content)

            # Extract parts
            before = content[:start_idx]
            after = content[end_idx:]

            # Construct new content
            new_content = f"{before}{start_marker}\n{status_section}{after}"
        else:
            # Append the section if it doesn't exist
            # Look for '## Exclusion Logs' to append after
            exclusion_logs_header = "## Exclusion Logs"
            if exclusion_logs_header in content:
                insertion_idx = content.find(exclusion_logs_header) + len(exclusion_logs_header)
                # Find the end of that section (next ## or end)
                next_header = content.find("\n## ", insertion_idx)
                if next_header == -1:
                    next_header = len(content)
                
                # Insert status section before the next header or at end
                # We'll insert it right after the '## Exclusion Logs' header text
                # But we need to handle the newlines correctly.
                # Let's just append it at the end of the file for safety if structure is complex
                # Actually, the spec says "under ## Exclusion Logs".
                # Let's insert it after the '## Exclusion Logs' line and any existing content under it.
                # For simplicity, if '### Dataset Status' is missing, we append it at the very end.
                new_content = f"{content}\n\n{status_section}"
            else:
                new_content = f"{content}\n\n## Exclusion Logs\n\n{status_section}"

        with open(readme_path, 'w', encoding='utf-8') as f:
            f.write(new_content)

        logger.info(f"Successfully updated {readme_path} with dataset status.")

    except Exception as e:
        logger.error(f"Error updating README: {e}")
        raise


def run_t013() -> None:
    """
    Main entry point for T013.
    1. Load exclusion log from data/processed/exclusion_log.json
    2. Parse verified datasets from data/README.md
    3. Generate status section
    4. Update data/README.md
    """
    data_dir = get_data_dir()
    processed_dir = get_processed_dir()

    exclusion_log_path = processed_dir / "exclusion_log.json"
    readme_path = data_dir / "README.md"

    logger.info(f"Loading exclusion log from {exclusion_log_path}")
    exclusion_log = load_exclusion_log(exclusion_log_path)
    logger.info(f"Found {len(exclusion_log)} excluded datasets.")

    logger.info(f"Parsing verified datasets from {readme_path}")
    verified_datasets = parse_verified_datasets(readme_path)
    logger.info(f"Found {len(verified_datasets)} verified datasets.")

    logger.info("Generating dataset status section")
    status_section = generate_dataset_status_section(verified_datasets, exclusion_log)

    logger.info("Updating README")
    update_readme(readme_path, status_section)

    logger.info("T013 completed successfully.")


def main() -> None:
    """CLI entry point."""
    try:
        run_t013()
    except Exception as e:
        logger.error(f"T013 failed: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()
