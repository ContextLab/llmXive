class TestConstantSeries:
    """Tests for handling constant (zero-variance) series."""

    def test_constant_series_no_crash(self):
        """
        Test that the pipeline handles constant series without crashing.
        A constant series should have zero variance and may cause issues
        in standardization or kernel computation.
        """
        # Generate synthetic data with a constant segment
        np.random.seed(42)
        data = generate_synthetic_ili_series(
            n_weeks=50,
            constant_start=20,
            constant_end=30,
            constant_value=2.5,
            missing_start=0,
            missing_end=0,
            outlier_start=0,
            outlier_end=0
        )

        # Remove missing weeks (none in this case)
        clean_data = remove_missing_weeks(data)

        # Apply log transform
        # Note: constant positive values will remain constant after log
        log_data = log_transform(clean_data)

        # Apply standardization
        # This is where constant series might cause division by zero
        try:
            std_data = standardize(log_data)
            # If we reach here, standardization handled the constant series
            # The result should be all NaNs or all zeros for the constant segment
            constant_segment = std_data.iloc[20:30]
            assert constant_segment.isna().all() or (constant_segment == 0).all()
        except Exception as e:
            # If it raises, it should be a meaningful error, not a crash
            pytest.fail(f"Standardization crashed on constant series: {e}")

    def test_mmd_on_constant_series(self):
        """
        Test that MMD computation handles constant series gracefully.
        Two constant series with the same value should have MMD ≈ 0.
        """
        np.random.seed(42)
        
        # Create two constant windows
        window1 = np.array([2.5] * 10)
        window2 = np.array([2.5] * 10)
        
        # Compute kernel matrix
        kernel_matrix = compute_gaussian_kernel(window1, window2, bandwidth=1.0)
        
        # Compute MMD statistic
        mmd_stat = compute_mmd_statistic(kernel_matrix)
        
        # MMD should be very close to 0 for identical constant series
        assert mmd_stat < 1e-6, f"MMD for identical constant series should be ~0, got {mmd_stat}"

    def test_mmd_constant_vs_different_constant(self):
        """
        Test MMD between two different constant series.
        Should be non-zero but stable.
        """
        np.random.seed(42)
        
        # Create two different constant windows
        window1 = np.array([2.0] * 10)
        window2 = np.array([3.0] * 10)
        
        # Compute kernel matrix
        kernel_matrix = compute_gaussian_kernel(window1, window2, bandwidth=1.0)
        
        # Compute MMD statistic
        mmd_stat = compute_mmd_statistic(kernel_matrix)
        
        # MMD should be non-zero for different constant series
        assert mmd_stat > 0.01, f"MMD for different constant series should be > 0, got {mmd_stat}"


class TestOutlierHandling:
    """Tests for handling outliers in the data."""

    def test_outlier_series_no_crash(self):
        """
        Test that the pipeline handles series with outliers without crashing.
        """
        # Generate synthetic data with outliers
        np.random.seed(42)
        data = generate_synthetic_ili_series(
            n_weeks=50,
            constant_start=0,
            constant_end=0,
            constant_value=0,
            missing_start=0,
            missing_end=0,
            outlier_start=20,
            outlier_end=21
        )

        # Remove missing weeks (none in this case)
        clean_data = remove_missing_weeks(data)

        # Apply log transform
        log_data = log_transform(clean_data)

        # Apply standardization
        try:
            std_data = standardize(log_data)
            # Should not crash
            assert len(std_data) == len(log_data)
        except Exception as e:
            pytest.fail(f"Standardization crashed on outlier series: {e}")

    def test_mmd_with_outlier(self):
        """
        Test that MMD can detect a shift caused by an outlier.
        """
        np.random.seed(42)
        
        # Create a window with an outlier
        window1 = np.random.normal(2.0, 0.5, 10)
        window2 = np.array([2.0] * 9 + [10.0])  # One large outlier
        
        # Compute kernel matrix
        kernel_matrix = compute_gaussian_kernel(window1, window2, bandwidth=1.0)
        
        # Compute MMD statistic
        mmd_stat = compute_mmd_statistic(kernel_matrix)
        
        # MMD should be higher when there's an outlier
        assert mmd_stat > 0, "MMD should be positive when comparing normal vs outlier series"

    def test_detect_shifts_with_outliers(self):
        """
        Test the full shift detection pipeline with outlier data.
        Should not crash and should produce valid output.
        """
        np.random.seed(42)
        
        # Generate synthetic data with outliers
        data = generate_synthetic_ili_series(
            n_weeks=100,
            constant_start=0,
            constant_end=0,
            constant_value=0,
            missing_start=0,
            missing_end=0,
            outlier_start=40,
            outlier_end=41
        )
        
        # Preprocess
        clean_data = remove_missing_weeks(data)
        log_data = log_transform(clean_data)
        std_data = standardize(log_data)
        
        # Run shift detection
        try:
            flags = detect_shifts(
                std_data,
                window_size=12,
                stride=1,
                permutations=100,
                alpha=0.01,
                bandwidth='median'
            )
            # Should produce a DataFrame
            assert isinstance(flags, pd.DataFrame)
            assert 'week' in flags.columns
            assert 'p_value' in flags.columns
            assert 'flagged' in flags.columns
        except Exception as e:
            pytest.fail(f"Shift detection crashed on outlier data: {e}")

    def test_outlier_influence_on_p_value(self):
        """
        Test that outliers affect the p-value as expected.
        """
        np.random.seed(42)
        
        # Create two windows: one normal, one with outlier
        window1 = np.random.normal(2.0, 0.5, 20)
        window2_normal = np.random.normal(2.0, 0.5, 20)
        window2_outlier = np.array(list(window2_normal[:19]) + [20.0])
        
        # Compute MMD with normal window
        kernel_normal = compute_gaussian_kernel(window1, window2_normal, bandwidth=1.0)
        mmd_normal = compute_mmd_statistic(kernel_normal)
        
        # Compute MMD with outlier window
        kernel_outlier = compute_gaussian_kernel(window1, window2_outlier, bandwidth=1.0)
        mmd_outlier = compute_mmd_statistic(kernel_outlier)
        
        # MMD should be higher with the outlier
        assert mmd_outlier > mmd_normal, \
            f"MMD with outlier ({mmd_outlier}) should be higher than without ({mmd_normal})"