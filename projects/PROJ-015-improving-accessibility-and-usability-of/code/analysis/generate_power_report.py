"""
Generate Power Analysis Report (T036b).

Logic:
1. Load `power_flags.json` (output of T036).
2. Generate a dedicated markdown report `data/processed/power_report.md`.
3. Update `report_summary.txt` to include a link/summary of the power analysis.
4. CRITICAL CONSTRAINT: If ANY subgroup is flagged as 'UNDERPOWERED', the pipeline
   MUST exit with a non-zero code and log a warning. This enforces the scientific
   rigor that results from underpowered studies cannot be claimed as significant
   without qualification.
"""
import os
import sys
import json
import pandas as pd
from pathlib import Path
from typing import Dict, Any, List
from utils.logger import get_logger

logger = get_logger(__name__)

def load_power_flags(power_flags_path: Path) -> List[Dict[str, Any]]:
    """Load the power flags JSON generated by T036."""
    if not power_flags_path.exists():
        raise FileNotFoundError(f"Power flags file not found: {power_flags_path}")
    
    with open(power_flags_path, 'r') as f:
        data = json.load(f)
    
    # Handle both list format and single dict format
    if isinstance(data, list):
        return data
    elif isinstance(data, dict) and 'subgroups' in data:
        return data['subgroups']
    else:
        # Assume it's a single record in a dict
        return [data]

def load_metrics_summary(metrics_summary_path: Path) -> pd.DataFrame:
    """Load the metrics summary to cross-reference effect sizes."""
    if not metrics_summary_path.exists():
        logger.warning(f"Metrics summary not found at {metrics_summary_path}. "
                     "Power report will be generated without effect size context.")
        return pd.DataFrame()
    return pd.read_csv(metrics_summary_path)

def generate_power_report_md(power_flags: List[Dict[str, Any]], output_path: Path) -> bool:
    """
    Generate the dedicated power analysis report in Markdown.
    
    Returns True if successful, False otherwise.
    """
    if not output_path.parent.exists():
        output_path.parent.mkdir(parents=True, exist_ok=True)
    
    lines = [
        "# Power Analysis Report",
        "",
        "This report details the statistical power calculations for the usability study.",
        "Power was calculated based on the observed effect sizes (eta-squared) from the",
        "Repeated Measures ANOVA, with a target alpha of 0.05.",
        "",
        "## Methodology",
        "- **Test**: F-test for Repeated Measures ANOVA",
        "- **Alpha**: 0.05",
        "- **Metric**: Eta-squared (effect size)",
        "- **Tool**: `statsmodels.stats.power.FTestAnovaPower`",
        "",
        "## Results"
    ]
    
    underpowered_found = False
    
    for flag in power_flags:
        subgroup = flag.get('subgroup', 'Unknown')
        n = flag.get('N', 0)
        power = flag.get('power', 0.0)
        required_n = flag.get('required_N', 0)
        status = flag.get('flag', 'UNKNOWN')
        
        if status == 'UNDERPOWERED':
            underpowered_found = True
            status_markdown = "**UNDERPOWERED** ⚠️"
        else:
            status_markdown = "OK ✅"
        
        lines.extend([
            f"### {subgroup}",
            "",
            f"- **Participants (N)**: {n}",
            f"- **Observed Power**: {power:.4f}",
            f"- **Required N (for 80% power)**: {required_n}",
            f"- **Status**: {status_markdown}",
            ""
        ])
        
        if underpowered_found:
            lines.append(f"> **Warning**: This subgroup is underpowered. "
                       f"Results for {subgroup} should be interpreted with caution.")
            lines.append("")
    
    lines.extend([
        "## Conclusion",
        ""
    ])
    
    if underpowered_found:
        lines.append("**CRITICAL**: One or more subgroups are underpowered. "
                   "The pipeline has flagged these results. "
                   "Final claims regarding statistical significance for these subgroups "
                   "cannot be made without increasing the sample size.")
    else:
        lines.append("All subgroups have sufficient statistical power (>= 0.80) "
                   "to detect the observed effects.")
    
    with open(output_path, 'w') as f:
        f.write('\n'.join(lines))
    
    return underpowered_found

def update_main_report(report_summary_path: Path, power_report_path: Path):
    """Append a summary section to the main report_summary.txt."""
    if not report_summary_path.exists():
        logger.warning(f"Main report not found at {report_summary_path}. "
                     "Skipping update.")
        return
    
    summary_text = f"\n\n## Power Analysis\n\n" \
                  f"See detailed power analysis in: {power_report_path.name}\n"
    
    with open(report_summary_path, 'a') as f:
        f.write(summary_text)

def main():
    """Main entry point for T036b."""
    # Define paths relative to project root
    project_root = Path(__file__).resolve().parents[2]
    data_processed = project_root / "data" / "processed"
    
    power_flags_path = data_processed / "power_flags.json"
    metrics_summary_path = data_processed / "metrics_summary.csv"
    output_report_path = data_processed / "power_report.md"
    main_report_path = data_processed / "report_summary.txt"
    
    logger.info(f"Starting Power Analysis Report generation (T036b)...")
    
    try:
        # 1. Load data
        power_flags = load_power_flags(power_flags_path)
        logger.info(f"Loaded {len(power_flags)} power flag records.")
        
        # 2. Generate report
        underpowered = generate_power_report_md(power_flags, output_report_path)
        logger.info(f"Generated power report at: {output_report_path}")
        
        # 3. Update main report
        if main_report_path.exists():
            update_main_report(main_report_path, output_report_path)
            logger.info("Updated main report summary.")
        
        # 4. CRITICAL CONSTRAINT: Fail loudly if underpowered
        if underpowered:
            logger.error("CRITICAL: Power analysis detected underpowered subgroups. "
                       "Pipeline exiting with error code 1 as per specification.")
            sys.exit(1)
        
        logger.info("Power Analysis Report generated successfully.")
        sys.exit(0)
        
    except FileNotFoundError as e:
        logger.error(f"Required input file missing: {e}")
        sys.exit(1)
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in power flags file: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during power report generation: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)

if __name__ == "__main__":
    main()