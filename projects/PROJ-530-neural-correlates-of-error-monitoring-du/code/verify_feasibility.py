"""
Verify feasibility report for RAM usage constraint.

Task: T037
Description: Verify `results/diagnostics/feasibility_report.json` shows < 7GB RAM usage.

This script reads the feasibility report generated by the pipeline (typically by
run_validation_subset.py or analysis.py) and validates that the peak memory usage
is strictly less than 7GB (7168 MB).

If the file is missing, it attempts to run the validation subset pipeline to generate it.
If the report exists but shows > 7GB, it exits with a clear error code and message.
"""
import os
import sys
import json
import logging
from pathlib import Path

# Add project root to path for imports if running from subdirectory
project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from run_validation_subset import run_pipeline_subset
from logging_config import get_logger, initialize_logging

# Constants
RAM_THRESHOLD_MB = 7168  # 7 GB in MB
REPORT_PATH = project_root / "results" / "diagnostics" / "feasibility_report.json"

def verify_feasibility_report(report_path: Path) -> bool:
    """
    Verify that the feasibility report exists and shows RAM usage < 7GB.
    
    Args:
        report_path: Path to the feasibility_report.json file.
        
    Returns:
        True if the report exists and RAM usage is within limits, False otherwise.
    """
    if not report_path.exists():
        logging.error(f"Feasibility report not found at: {report_path}")
        logging.error("Please run the validation subset pipeline first to generate the report.")
        return False

    try:
        with open(report_path, 'r') as f:
            report = json.load(f)
    except json.JSONDecodeError as e:
        logging.error(f"Invalid JSON in feasibility report: {e}")
        return False
    except Exception as e:
        logging.error(f"Error reading feasibility report: {e}")
        return False

    # Extract memory usage
    peak_memory_mb = report.get("peak_memory_mb")
    
    if peak_memory_mb is None:
        logging.error("Peak memory usage not found in report.")
        logging.error(f"Report keys: {list(report.keys())}")
        return False

    logging.info(f"Peak memory usage reported: {peak_memory_mb:.2f} MB")
    logging.info(f"Threshold limit: {RAM_THRESHOLD_MB} MB")

    if peak_memory_mb < RAM_THRESHOLD_MB:
        logging.info("SUCCESS: Memory usage is within the 7GB limit.")
        return True
    else:
        logging.error(f"FAILURE: Memory usage ({peak_memory_mb:.2f} MB) exceeds limit ({RAM_THRESHOLD_MB} MB).")
        logging.error("The pipeline requires optimization to meet the feasibility constraint.")
        return False

def main():
    """Main entry point for feasibility verification."""
    # Initialize logging
    initialize_logging(log_file=project_root / "data" / "feasibility_verification.log")
    logger = get_logger("feasibility_verification")
    
    logger.info("Starting feasibility verification for Task T037.")
    
    # Check if report exists; if not, try to generate it
    if not REPORT_PATH.exists():
        logger.warning(f"Report not found at {REPORT_PATH}. Attempting to run validation subset pipeline...")
        try:
            # Run the subset pipeline to generate the report
            run_pipeline_subset(subset_size=5, output_dir=project_root / "results" / "diagnostics")
            logger.info("Validation subset pipeline completed. Re-checking report.")
        except Exception as e:
            logger.error(f"Failed to run validation subset pipeline: {e}")
            logger.error("Cannot verify feasibility without the report. Please run the pipeline manually.")
            return 1

    # Verify the report
    is_feasible = verify_feasibility_report(REPORT_PATH)
    
    if is_feasible:
        logger.info("Feasibility check PASSED.")
        return 0
    else:
        logger.error("Feasibility check FAILED.")
        return 1

if __name__ == "__main__":
    sys.exit(main())
