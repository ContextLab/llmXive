def load_classification_predictions(input_file: str) -> pd.DataFrame:
    """
    Load classification predictions from the metrics CSV generated by T030.
    Expects columns: ['true_label', 'predicted_prob', ...]
    """
    path = Path(input_file)
    if not path.exists():
        raise FileNotFoundError(f"Classification metrics file not found: {input_file}")
    df = pd.read_csv(path)
    required_cols = ['true_label', 'predicted_prob']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in {input_file}: {missing}")
    return df

def compute_metrics_at_threshold(df: pd.DataFrame, threshold: float) -> Dict[str, float]:
    """
    Compute classification metrics (Accuracy, Precision, Recall, F1, ROC-AUC)
    at a specific decision threshold.
    """
    # Binarize predictions
    y_pred = (df['predicted_prob'] >= threshold).astype(int)
    y_true = df['true_label']

    # Calculate metrics
    tp = ((y_pred == 1) & (y_true == 1)).sum()
    tn = ((y_pred == 0) & (y_true == 0)).sum()
    fp = ((y_pred == 1) & (y_true == 0)).sum()
    fn = ((y_pred == 0) & (y_true == 1)).sum()

    accuracy = (tp + tn) / len(df) if len(df) > 0 else 0.0
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0.0

    # ROC-AUC approximation (AUC of the single point at this threshold is not standard,
    # but we can calculate the specific TPR/FPR point. For a full AUC, we'd need the curve.
    # However, the task asks for metrics *at* the threshold.
    # We will report Accuracy, Precision, Recall, F1 explicitly.
    # If a full ROC curve is needed, we'd need to sweep all unique probs.
    # For this task, we focus on the specific threshold metrics.
    
    return {
        'threshold': threshold,
        'accuracy': accuracy,
        'precision': precision,
        'recall': recall,
        'f1_score': f1,
        'tp': tp,
        'tn': tn,
        'fp': fp,
        'fn': fn
    }

def calculate_stability_metrics(metrics_at_thresholds: List[Dict[str, float]]) -> List[Dict[str, Any]]:
    """
    Calculate relative decrease or stability metrics between thresholds.
    Compares each threshold to the baseline (0.50) or previous threshold.
    """
    results = []
    baseline_threshold = 0.50
    baseline_metrics = next((m for m in metrics_at_thresholds if m['threshold'] == baseline_threshold), None)

    if not baseline_metrics:
        logging.warning(f"Baseline threshold {baseline_threshold} not found in metrics. Skipping stability analysis.")
        return results

    for m in metrics_at_thresholds:
        if m['threshold'] == baseline_threshold:
            results.append({
                'threshold': m['threshold'],
                'accuracy': m['accuracy'],
                'precision': m['precision'],
                'recall': m['recall'],
                'f1_score': m['f1_score'],
                'rel_acc_change': 0.0,
                'rel_prec_change': 0.0,
                'rel_rec_change': 0.0,
                'rel_f1_change': 0.0,
                'stability_status': 'BASELINE'
            })
            continue

        # Calculate relative change: (current - baseline) / baseline
        def safe_rel_change(curr, base):
            if base == 0:
                return float('nan') if curr == 0 else float('inf')
            return (curr - base) / base

        rel_acc = safe_rel_change(m['accuracy'], baseline_metrics['accuracy'])
        rel_prec = safe_rel_change(m['precision'], baseline_metrics['precision'])
        rel_rec = safe_rel_change(m['recall'], baseline_metrics['recall'])
        rel_f1 = safe_rel_change(m['f1_score'], baseline_metrics['f1_score'])

        # Determine stability status
        # "Stable" if change is within +/- 5%, otherwise "Decrease" or "Increase"
        def status(change):
            if np.isnan(change) or np.isinf(change):
                return "UNDEFINED"
            if abs(change) <= 0.05:
                return "STABLE"
            elif change < 0:
                return "DECREASE"
            else:
                return "INCREASE"

        results.append({
            'threshold': m['threshold'],
            'accuracy': m['accuracy'],
            'precision': m['precision'],
            'recall': m['recall'],
            'f1_score': m['f1_score'],
            'rel_acc_change': rel_acc,
            'rel_prec_change': rel_prec,
            'rel_rec_change': rel_rec,
            'rel_f1_change': rel_f1,
            'stability_status': status(rel_f1)
        })

    return results

def run_sensitivity_analysis(
    input_file: str,
    output_file: str,
    thresholds: List[float] = [0.40, 0.50, 0.60]
) -> None:
    """
    Run the full sensitivity analysis pipeline:
    1. Load predictions
    2. Compute metrics at each threshold
    3. Calculate stability metrics
    4. Save to CSV
    """
    logging.info(f"Starting sensitivity analysis with thresholds: {thresholds}")
    
    # Load data
    df = load_classification_predictions(input_file)
    logging.info(f"Loaded {len(df)} predictions from {input_file}")

    # Compute metrics for each threshold
    all_metrics = []
    for thresh in thresholds:
        metrics = compute_metrics_at_threshold(df, thresh)
        all_metrics.append(metrics)
        logging.info(f"Computed metrics for threshold {thresh}: Acc={metrics['accuracy']:.4f}")

    # Calculate stability metrics
    stability_results = calculate_stability_metrics(all_metrics)
    
    # Prepare DataFrame
    df_out = pd.DataFrame(stability_results)
    
    # Ensure output directory exists
    output_path = Path(output_file)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Save to CSV
    df_out.to_csv(output_file, index=False)
    logging.info(f"Sensitivity analysis results saved to {output_file}")
    
    # Log caveat if ground truth is derived
    # We check the input file path or config to see if we should add a note
    # Since T029 set status to UNVALIDATED, we assume this caveat applies.
    logging.info("Caveat: Ground truth derived from search-time median split; predictive validity is limited.")

def main():
    parser = argparse.ArgumentParser(description="Sensitivity Analysis for Classifier Thresholds")
    parser.add_argument("--input", type=str, default="results/classification_metrics.csv",
                        help="Input CSV file with classification predictions (from T030)")
    parser.add_argument("--output", type=str, default="results/sensitivity_analysis.csv",
                        help="Output CSV file for sensitivity analysis results")
    parser.add_argument("--thresholds", type=float, nargs='+', default=[0.40, 0.50, 0.60],
                        help="Thresholds to sweep (default: 0.40, 0.50, 0.60)")
    
    args = parser.parse_args()
    
    # Setup logging
    logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
    
    try:
        run_sensitivity_analysis(
            input_file=args.input,
            output_file=args.output,
            thresholds=args.thresholds
        )
    except Exception as e:
        logging.error(f"Sensitivity analysis failed: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
