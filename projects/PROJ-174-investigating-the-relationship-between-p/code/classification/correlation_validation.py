"""
Correlation Validation Module for User Story 3 (T032).

Implements continuous correlation between predicted probability and search time
as auxiliary validation for the real-time load classification prototype.
"""
import os
import sys
import logging
import argparse
from pathlib import Path
from typing import Tuple, Optional, List, Dict, Any

import numpy as np
import pandas as pd
from scipy.stats import pearsonr, spearmanr
import matplotlib
matplotlib.use('Agg')  # Non-interactive backend for headless execution
import matplotlib.pyplot as plt

# Ensure code root is in path
CODE_ROOT = Path(__file__).resolve().parent.parent
if str(CODE_ROOT) not in sys.path:
    sys.path.insert(0, str(CODE_ROOT))

from config import load_config
from logging_config import get_logger

# Output paths relative to project root
PROJECT_ROOT = CODE_ROOT.parent
RESULTS_DIR = PROJECT_ROOT / "results"
FIGURES_DIR = PROJECT_ROOT / "figures"

# Ensure directories exist
RESULTS_DIR.mkdir(parents=True, exist_ok=True)
FIGURES_DIR.mkdir(parents=True, exist_ok=True)

CORRELATION_CSV = RESULTS_DIR / "correlation_validation.csv"
CORRELATION_PLOT = FIGURES_DIR / "prob_vs_search_time.png"

def load_classification_results() -> pd.DataFrame:
    """
    Load classification results from the metrics CSV generated by T030/T031.
    Expects columns: predicted_probability, search_time (or similar).
    """
    # The classification metrics file is expected to be generated by T030/T031
    metrics_file = RESULTS_DIR / "classification_metrics.csv"
    
    if not metrics_file.exists():
        raise FileNotFoundError(
            f"Classification metrics file not found: {metrics_file}. "
            "Ensure T030/T031 have run successfully."
        )
    
    df = pd.read_csv(metrics_file)
    
    # Verify required columns exist
    required_cols = ['predicted_probability', 'search_time']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(
            f"Missing required columns in {metrics_file}: {missing}. "
            "Ensure T030/T031 output includes 'predicted_probability' and 'search_time'."
        )
    
    # Drop rows with missing values in key columns
    df = df.dropna(subset=required_cols)
    
    logging.info(f"Loaded {len(df)} valid rows from {metrics_file}")
    return df

def compute_continuous_correlation(
    df: pd.DataFrame,
    prob_col: str = 'predicted_probability',
    time_col: str = 'search_time'
) -> Tuple[float, float, float, float]:
    """
    Compute Pearson and Spearman correlations between predicted probability and search time.
    
    Returns:
        Tuple of (pearson_r, pearson_p, spearman_r, spearman_p)
    """
    if len(df) < 2:
        raise ValueError("Insufficient data points for correlation analysis (need >= 2).")
    
    y_pred = df[prob_col].values
    search_time = df[time_col].values
    
    # Pearson correlation
    pearson_r, pearson_p = pearsonr(y_pred, search_time)
    
    # Spearman rank correlation (robust to non-linear monotonic relationships)
    spearman_r, spearman_p = spearmanr(y_pred, search_time)
    
    logging.info(f"Pearson r={pearson_r:.4f} (p={pearson_p:.4e})")
    logging.info(f"Spearman rho={spearman_r:.4f} (p={spearman_p:.4e})")
    
    return pearson_r, pearson_p, spearman_r, spearman_p

def save_correlation_report(
    pearson_r: float,
    pearson_p: float,
    spearman_r: float,
    spearman_p: float,
    n_samples: int,
    output_path: Path = CORRELATION_CSV
) -> None:
    """
    Save correlation statistics to a CSV file.
    """
    report = pd.DataFrame([{
        'metric': 'pearson_r',
        'value': pearson_r,
        'p_value': pearson_p,
        'n_samples': n_samples
    }, {
        'metric': 'spearman_rho',
        'value': spearman_r,
        'p_value': spearman_p,
        'n_samples': n_samples
    }])
    
    report.to_csv(output_path, index=False)
    logging.info(f"Saved correlation report to {output_path}")

def plot_correlation(
    df: pd.DataFrame,
    pearson_r: float,
    pearson_p: float,
    prob_col: str = 'predicted_probability',
    time_col: str = 'search_time',
    output_path: Path = CORRELATION_PLOT
) -> None:
    """
    Generate a scatter plot of predicted probability vs. search time with regression line.
    """
    plt.figure(figsize=(10, 8))
    
    x = df[prob_col]
    y = df[time_col]
    
    plt.scatter(x, y, alpha=0.6, edgecolors='w', linewidth=0.5, s=50)
    
    # Add regression line
    z = np.polyfit(x, y, 1)
    p = np.poly1d(z)
    x_line = np.linspace(x.min(), x.max(), 100)
    plt.plot(x_line, p(x_line), "r-", linewidth=2, label=f'Linear Fit (r={pearson_r:.3f})')
    
    plt.xlabel('Predicted Probability (Cognitive Load)')
    plt.ylabel('Search Time (s)')
    plt.title(f'Continuous Correlation: Predicted Probability vs. Search Time\n'
              f'Pearson r = {pearson_r:.4f}, p = {pearson_p:.4e}')
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    
    plt.savefig(output_path, dpi=150)
    plt.close()
    
    logging.info(f"Saved correlation plot to {output_path}")

def run_validation_pipeline() -> Dict[str, Any]:
    """
    Main pipeline for T032: Load results, compute correlations, save report and plot.
    """
    logger = get_logger(__name__)
    
    try:
        # 1. Load data
        df = load_classification_results()
        
        # 2. Compute correlations
        pearson_r, pearson_p, spearman_r, spearman_p = compute_continuous_correlation(df)
        
        # 3. Save report
        save_correlation_report(pearson_r, pearson_p, spearman_r, spearman_p, len(df))
        
        # 4. Generate plot
        plot_correlation(df, pearson_r, pearson_p)
        
        return {
            'status': 'success',
            'pearson_r': pearson_r,
            'pearson_p': pearson_p,
            'spearman_r': spearman_r,
            'spearman_p': spearman_p,
            'n_samples': len(df),
            'output_csv': str(CORRELATION_CSV),
            'output_plot': str(CORRELATION_PLOT)
        }
        
    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        raise
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        raise
    except Exception as e:
        logger.error(f"Pipeline failed: {e}")
        raise

def main():
    """CLI entry point for T032."""
    parser = argparse.ArgumentParser(
        description="T032: Compute continuous correlation between predicted probability and search time."
    )
    parser.add_argument(
        "--config",
        type=str,
        default="code/config.yaml",
        help="Path to config file (optional)."
    )
    args = parser.parse_args()
    
    # Load config if provided
    if os.path.exists(args.config):
        load_config(args.config)
    
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    result = run_validation_pipeline()
    print(f"\nValidation Complete:")
    print(f"  Pearson r: {result['pearson_r']:.4f} (p={result['pearson_p']:.4e})")
    print(f"  Spearman rho: {result['spearman_r']:.4f} (p={result['spearman_p']:.4e})")
    print(f"  Samples: {result['n_samples']}")
    print(f"  Report: {result['output_csv']}")
    print(f"  Plot: {result['output_plot']}")
    
    return 0

if __name__ == "__main__":
    sys.exit(main())