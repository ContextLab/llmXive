"""
Project Structure Initialization Script.
Creates the required directory tree and __init__.py files for the llmXive pipeline.
"""
import os
import sys
from pathlib import Path

def create_project_structure():
    """
    Creates the standard project directories and initializes them with __init__.py files.
    Directories created:
    - code/
    - data/raw/
    - data/processed/
    - results/
    - specs/
    - tests/
    - tests/unit/
    - tests/integration/
    """
    # Define the root directory (current working directory or project root)
    # We assume this script runs from the project root
    root = Path.cwd()

    # Define relative paths based on task requirements
    directories = [
        "code",
        "data/raw",
        "data/processed",
        "results",
        "specs",
        "tests",
        "tests/unit",
        "tests/integration",
        # Additional standard directories often needed for this pipeline
        "code/pipeline",
        "code/utils",
        "code/schemas",
        "code/results",
        "code/templates",
        "code/tests/unit",
        "code/tests/integration",
        "data/raw/openwebtext",
        "data/raw/gsm8k",
        "data/raw/arc_challenge",
        "data/raw/wikitext2",
        "results/logs",
        "results/checkpoints",
        "figures",
    ]

    created_count = 0
    skipped_count = 0

    print(f"Initializing project structure at: {root}")

    for rel_path in directories:
        target_path = root / rel_path
        
        if target_path.exists():
            skipped_count += 1
            continue

        try:
            target_path.mkdir(parents=True, exist_ok=True)
            created_count += 1
            
            # Create __init__.py in every directory to make them Python packages
            init_file = target_path / "__init__.py"
            if not init_file.exists():
                # Write a standard header to the init file
                init_content = f"""# {rel_path} package
# Auto-generated by setup_project.py
"""
                init_file.write_text(init_content)
                
            print(f"  Created: {rel_path}")
        except OSError as e:
            print(f"  ERROR creating {rel_path}: {e}")
            return False

    print(f"\nProject structure initialization complete.")
    print(f"  Directories created: {created_count}")
    print(f"  Directories skipped (already exist): {skipped_count}")
    
    # Verification step
    print("\nVerifying required directories and __init__.py files:")
    required = [
        "code/__init__.py",
        "data/raw/__init__.py",
        "data/processed/__init__.py",
        "results/__init__.py",
        "specs/__init__.py",
        "tests/__init__.py",
        "tests/unit/__init__.py",
        "tests/integration/__init__.py",
    ]
    
    all_present = True
    for req in required:
        full_path = root / req
        if full_path.exists():
            print(f"  [OK] {req}")
        else:
            print(f"  [MISSING] {req}")
            all_present = False
    
    return all_present

if __name__ == "__main__":
    success = create_project_structure()
    sys.exit(0 if success else 1)