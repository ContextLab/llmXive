"""
Schema for architectural modification proposals.

This module defines the Pydantic model used to validate and structure
architectural modification proposals generated by the self-improving LLM.
"""
from pydantic import BaseModel, Field, field_validator
from typing import Literal, Optional
import json

ModificationType = Literal[
    "layer_count",
    "head_count",
    "hidden_size",
    "intermediate_size",
    "dropout_rate",
    "vocab_size"
]

class ModificationProposal(BaseModel):
    """
    Represents a proposed architectural modification to the LLM.

    Attributes:
        modification_type: The specific architectural parameter to modify.
        magnitude: The scalar multiplier or absolute change value.
        rationale: Natural language explanation for the proposed change.
        estimated_param_count: Estimated total parameter count after modification.
    """
    modification_type: ModificationType = Field(
        ...,
        description="The type of architectural modification to apply."
    )
    magnitude: float = Field(
        ...,
        ge=0.0,
        description="The magnitude of change. For scaling factors, >1.0 increases, <1.0 decreases. For absolute changes, this is the new value."
    )
    rationale: str = Field(
        ...,
        min_length=1,
        description="Natural language explanation for the proposed change."
    )
    estimated_param_count: int = Field(
        ...,
        gt=0,
        description="Estimated total parameter count after applying this modification."
    )

    @field_validator('magnitude')
    @classmethod
    def validate_magnitude_range(cls, v, info):
        """Ensure magnitude is within reasonable bounds to prevent extreme changes."""
        if v > 10.0 or v < 0.1:
            raise ValueError("Magnitude must be between 0.1 and 10.0 to prevent extreme architectural changes.")
        return v

    @field_validator('estimated_param_count')
    @classmethod
    def validate_param_count_reasonable(cls, v):
        """Ensure estimated param count is a reasonable positive integer."""
        if v <= 0:
            raise ValueError("Estimated parameter count must be positive.")
        if v > 10_000_000_000:  # 10B limit as a sanity check
            raise ValueError("Estimated parameter count exceeds reasonable limits.")
        return v

    def to_dict(self) -> dict:
        """Convert the proposal to a dictionary for JSON serialization."""
        return self.model_dump()

    def to_json(self, indent: int = 2) -> str:
        """Convert the proposal to a JSON string."""
        return json.dumps(self.to_dict(), indent=indent)

    @classmethod
    def from_json(cls, json_str: str) -> 'ModificationProposal':
        """Create a ModificationProposal from a JSON string."""
        data = json.loads(json_str)
        return cls(**data)
