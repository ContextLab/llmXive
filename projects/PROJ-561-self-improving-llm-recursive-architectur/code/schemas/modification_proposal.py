from pydantic import BaseModel, Field, field_validator, ValidationError
from typing import Literal, Optional, List
import json


class ModificationProposal(BaseModel):
    """
    Schema for an architecture modification proposal generated by the LLM.
    
    This schema strictly defines the allowable structural changes to the model
    to ensure the modification is valid before attempting application.
    
    Fields:
        proposal_id: Unique identifier for this proposal.
        description: Natural language description of the change.
        modification_type: The specific type of architectural change.
        layer_index: Target layer index (0-based) for the modification.
        hidden_size_change: Delta to apply to hidden size (optional).
        num_heads_change: Delta to apply to number of attention heads (optional).
        new_activation: Name of a new activation function (optional).
        add_layer: Boolean flag to indicate adding a new layer.
        remove_layer: Boolean flag to indicate removing a layer.
    """
    proposal_id: str = Field(..., description="Unique identifier for the proposal")
    description: str = Field(..., description="Human-readable description of the proposed change")
    
    modification_type: Literal[
        "layer_add", 
        "layer_remove", 
        "head_count_change", 
        "hidden_size_change", 
        "activation_change",
        "layer_reorder"
    ] = Field(..., description="Type of modification being proposed")
    
    layer_index: Optional[int] = Field(None, description="Target layer index for the modification (0-based)")
    hidden_size_change: Optional[int] = Field(None, description="Delta to add to current hidden size (e.g., +64, -32)")
    num_heads_change: Optional[int] = Field(None, description="Delta to add to current number of heads (e.g., +1, -1)")
    new_activation: Optional[Literal["relu", "gelu", "swish", "mish", "tanh"]] = Field(None, description="Name of the new activation function")
    
    # Flags for structural changes that don't necessarily need deltas
    add_layer: bool = Field(False, description="True if this proposal adds a new layer")
    remove_layer: bool = Field(False, description="True if this proposal removes an existing layer")

    @field_validator('layer_index')
    @classmethod
    def validate_layer_index(cls, v, info):
        if v is not None and v < 0:
            raise ValueError("layer_index must be non-negative")
        return v

    @field_validator('hidden_size_change')
    @classmethod
    def validate_hidden_size_change(cls, v, info):
        if v is not None and v == 0:
            raise ValueError("hidden_size_change cannot be zero")
        return v

    @field_validator('num_heads_change')
    @classmethod
    def validate_num_heads_change(cls, v, info):
        if v is not None and v == 0:
            raise ValueError("num_heads_change cannot be zero")
        return v

    @field_validator('new_activation')
    @classmethod
    def validate_new_activation(cls, v, info):
        # If new_activation is provided, ensure it's not empty string
        if v is not None and len(v.strip()) == 0:
            raise ValueError("new_activation cannot be an empty string")
        return v

    @field_validator('add_layer', 'remove_layer')
    @classmethod
    def validate_mutual_exclusion(cls, v, info):
        # This validator is called per field, but we can check the whole object in a model_validator
        # However, for simplicity in Pydantic v1/v2 mixed usage or just field level:
        # We will rely on the model_validator below for cross-field logic.
        return v

    @field_validator('modification_type')
    @classmethod
    def validate_modification_type_consistency(cls, v, info):
        if v == "layer_add" and not info.data.get('add_layer'):
            # If type is layer_add, add_layer flag should ideally be true, 
            # but we allow the type to drive the logic.
            pass
        return v


def validate_modification_json(json_str: str) -> ModificationProposal:
    """
    Validates a JSON string against the ModificationProposal schema.
    
    Args:
        json_str: A JSON string representing the modification proposal.
        
    Returns:
        A validated ModificationProposal instance.
        
    Raises:
        ValidationError: If the JSON is invalid or does not match the schema.
    """
    try:
        data = json.loads(json_str)
        return ModificationProposal(**data)
    except json.JSONDecodeError as e:
        raise ValidationError(f"Invalid JSON format: {e}")
    except Exception as e:
        raise ValidationError(f"Validation failed: {e}")
