"""
Schema definitions for architectural modification proposals.
"""
from pydantic import BaseModel, Field, field_validator, ValidationError
from typing import Literal, Optional, List
import json


ModificationType = Literal[
    "layer_add",
    "layer_remove",
    "head_count_change",
    "hidden_dim_change",
    "dropout_change",
    "activation_change"
]


class ModificationProposal(BaseModel):
    """
    Pydantic model representing a proposed architectural modification.
    Used to validate JSON payloads generated by the model's self-prompting.
    """
    modification_type: ModificationType = Field(
        ...,
        description="Type of architectural change to apply"
    )
    magnitude: float = Field(
        ...,
        gt=0.0,
        description="Magnitude of the change (e.g., number of layers to add, % change in heads)"
    )
    rationale: str = Field(
        ...,
        min_length=1,
        max_length=1000,
        description="Explanation for why this modification is proposed"
    )
    estimated_param_count: int = Field(
        ...,
        gt=0,
        description="Estimated total parameter count after modification"
    )

    @field_validator('rationale')
    @classmethod
    def rationale_must_not_be_empty(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("Rationale cannot be empty or whitespace only")
        return v

    @field_validator('estimated_param_count')
    @classmethod
    def param_count_must_be_reasonable(cls, v: int) -> int:
        if v < 1000:
            raise ValueError("Estimated parameter count must be at least 1000")
        return v


def validate_modification_json(json_str: str) -> ModificationProposal:
    """
    Validates a JSON string against the ModificationProposal schema.
    
    Args:
        json_str: JSON string to validate
        
    Returns:
        Validated ModificationProposal instance
        
    Raises:
        ValidationError: If the JSON is invalid or missing required fields
        json.JSONDecodeError: If the input is not valid JSON
    """
    data = json.loads(json_str)
    return ModificationProposal(**data)
