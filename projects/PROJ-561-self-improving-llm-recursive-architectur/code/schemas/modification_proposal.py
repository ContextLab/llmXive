"""
Schema for architectural modification proposals.

Defines the structure for proposals generated by the self-improving LLM
to modify its own architecture.
"""
from pydantic import BaseModel, Field, field_validator
from typing import Literal, Optional, List
import json

# Allowed modification types as per spec
MODIFICATION_TYPES = [
    "layer_add",
    "head_count_change"
]

class ModificationProposal(BaseModel):
    """
    Represents a proposed architectural modification for the GPT-2 model.

    Attributes:
        modification_type: Type of modification (e.g., 'layer_add', 'head_count_change')
        magnitude: Integer magnitude of the change (e.g., number of layers to add)
        rationale: String explaining why this modification is proposed
        estimated_param_count: Estimated total parameter count after modification
    """
    modification_type: Literal["layer_add", "head_count_change"] = Field(
        ...,
        description="Type of architectural modification"
    )
    magnitude: int = Field(
        ...,
        ge=1,
        description="Magnitude of the modification (e.g., number of layers to add)"
    )
    rationale: str = Field(
        ...,
        min_length=1,
        max_length=1000,
        description="Rationale for proposing this modification"
    )
    estimated_param_count: int = Field(
        ...,
        gt=0,
        description="Estimated total parameter count after applying this modification"
    )

    @field_validator('modification_type')
    @classmethod
    def validate_modification_type(cls, v):
        if v not in MODIFICATION_TYPES:
            raise ValueError(f"modification_type must be one of {MODIFICATION_TYPES}, got {v}")
        return v

    @field_validator('magnitude')
    @classmethod
    def validate_magnitude(cls, v):
        if v < 1:
            raise ValueError("magnitude must be at least 1")
        return v

    @field_validator('estimated_param_count')
    @classmethod
    def validate_param_count(cls, v):
        if v <= 0:
            raise ValueError("estimated_param_count must be positive")
        return v

    def to_json(self) -> str:
        """Convert proposal to JSON string."""
        return self.model_dump_json()

    @classmethod
    def from_json(cls, json_str: str) -> 'ModificationProposal':
        """Parse proposal from JSON string."""
        return cls.model_validate_json(json_str)

    def to_dict(self) -> dict:
        """Convert proposal to dictionary."""
        return self.model_dump()

    @classmethod
    def from_dict(cls, data: dict) -> 'ModificationProposal':
        """Create proposal from dictionary."""
        return cls(**data)

