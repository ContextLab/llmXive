"""
Modification Proposal Schema for Self-Improving LLM.

Defines the Pydantic model for architectural modification proposals
generated by the model during the recursive refinement cycle.
"""
from pydantic import BaseModel, Field, field_validator
from typing import Literal, Optional, List
import json


class ModificationProposal(BaseModel):
    """
    Schema for a single architectural modification proposal.

    Attributes:
        modification_type: The type of change to the architecture.
                           Allowed: 'layer_add', 'head_count_change'.
        magnitude: The integer magnitude of the change (e.g., number of layers to add).
        rationale: A string explaining why this modification is proposed.
        estimated_param_count: The estimated total parameter count after modification.
    """
    modification_type: Literal["layer_add", "head_count_change"] = Field(
        ...,
        description="Type of architectural modification. Allowed: 'layer_add', 'head_count_change'."
    )
    magnitude: int = Field(
        ...,
        ge=1,
        description="Magnitude of the change (e.g., number of layers to add or head count delta)."
    )
    rationale: str = Field(
        ...,
        min_length=1,
        description="Human-readable rationale for the proposed modification."
    )
    estimated_param_count: int = Field(
        ...,
        gt=0,
        description="Estimated total parameter count of the model after applying this modification."
    )

    @field_validator('modification_type')
    @classmethod
    def validate_type(cls, v):
        if v not in ["layer_add", "head_count_change"]:
            raise ValueError(f"modification_type must be 'layer_add' or 'head_count_change', got {v}")
        return v

    @field_validator('magnitude')
    @classmethod
    def validate_magnitude(cls, v):
        if v < 1:
            raise ValueError(f"magnitude must be at least 1, got {v}")
        return v

    @field_validator('estimated_param_count')
    @classmethod
    def validate_param_count(cls, v):
        if v <= 0:
            raise ValueError(f"estimated_param_count must be positive, got {v}")
        return v

    def to_json(self) -> str:
        """Returns the model as a JSON string."""
        return self.model_dump_json()

    @classmethod
    def from_json(cls, json_str: str) -> "ModificationProposal":
        """Parses a JSON string into a ModificationProposal instance."""
        return cls.model_validate_json(json_str)