def load_raw_data() -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Load raw GSN and TSI data from data/raw/ directory.
    Expects files generated by T013a (fetch_silso_gsn) and T013b (fetch_sorce_tsi).
    
    Returns:
        Tuple of (gsn_df, tsi_df)
    """
    data_path = get_data_path()
    raw_dir = Path(data_path) / "raw"
    
    gsn_file = raw_dir / "silso_gsn.csv"
    tsi_file = raw_dir / "sorce_tsi.csv"
    
    if not gsn_file.exists():
        raise FileNotFoundError(f"GSN data not found at {gsn_file}. Run T013a first.")
    if not tsi_file.exists():
        raise FileNotFoundError(f"TSI data not found at {tsi_file}. Run T013b first.")
        
    logger.info(f"Loading GSN data from {gsn_file}")
    gsn_df = pd.read_csv(gsn_file)
    
    logger.info(f"Loading TSI data from {tsi_file}")
    tsi_df = pd.read_csv(tsi_file)
    
    # Ensure date columns are datetime
    if 'date' in gsn_df.columns:
        gsn_df['date'] = pd.to_datetime(gsn_df['date'], errors='coerce')
    if 'date' in tsi_df.columns:
        tsi_df['date'] = pd.to_datetime(tsi_df['date'], errors='coerce')
        
    return gsn_df, tsi_df

def detect_cycle_boundaries(df: pd.DataFrame) -> pd.DataFrame:
    """
    Assign Cycle ID to each row based on SILSO historical cycle definitions.
    
    Args:
        df: DataFrame with 'date' column (datetime)
        
    Returns:
        DataFrame with added 'cycle_id' column
    """
    def get_cycle(row):
        year, month = row['date'].year, row['date'].month
        current_cycle = None
        
        # Iterate through cycles to find the active one
        # Cycles are defined by start date. We assume cycle continues until next starts.
        for i, cycle_def in enumerate(SILSO_CYCLES):
            start_y, start_m = cycle_def["start"]
            if (year, month) >= (start_y, start_m):
                current_cycle = cycle_def["cycle_id"]
            else:
                break
        return current_cycle

    df = df.copy()
    df['cycle_id'] = df.apply(get_cycle, axis=1)
    
    # Handle pre-1755 data (before Cycle 1)
    df.loc[df['cycle_id'].isna(), 'cycle_id'] = 0  # Unknown/Pre-cycle
    
    return df

def fill_gaps(df: pd.DataFrame, gap_threshold_years: float = GAP_THRESHOLD_YEARS) -> pd.DataFrame:
    """
    Fill gaps in GSN data.
    - Gaps < 1 year: Linear interpolation
    - Gaps >= 1 year: Set GSN=0 (as per FR-002, we do NOT use GSN=0 for proxy, 
      but the data itself might have missing values. The task says "Do NOT use GSN=0" 
      for the proxy value, but for the actual GSN series, if it's missing for a long time, 
      we represent it as 0 or NaN. However, the task specifically says:
      "Apply TSI proxy value 1360.5 W/m² (per FR-002) for gaps ≥ 1 year. Do NOT use GSN=0."
      
      This implies:
      1. If GSN data is missing for >= 1 year, we cannot infer GSN.
      2. For TSI reconstruction, we use the TSI proxy (1360.5) for those periods.
      3. For the GSN column itself in the output, we might leave as NaN or 0.
      
      Let's interpret the task: "Apply TSI proxy value 1360.5 W/m² ... for gaps >= 1 year."
      This likely means: In the final merged dataset, if a time period has no GSN data for >= 1 year,
      we assign the TSI proxy value to the TSI column (if we are reconstructing TSI) or handle the gap.
      
      However, this function is on GSN data. The logic is:
      - Interpolate small gaps in GSN.
      - For large gaps in GSN, we cannot interpolate. We mark them.
      - The TSI proxy logic is applied later or during the merge if TSI is missing.
      
      Re-reading T014b: "Apply TSI proxy value 1360.5 W/m² ... for gaps >= 1 year. Do NOT use GSN=0."
      This suggests that if we are missing GSN data for a long time, we don't assume GSN=0 (which would imply TSI minimum).
      Instead, for the purpose of TSI reconstruction, we might use the proxy.
      
      But this function is `fill_gaps` on GSN. Let's stick to GSN handling:
      - Small gaps: Interpolate.
      - Large gaps: Leave as NaN (or 0 if required by downstream, but task says don't use GSN=0 as proxy).
      - We will leave large gaps as NaN in GSN. The TSI proxy logic will be handled in the merge/prediction step
        or by explicitly creating a TSI column if needed.
        
      Wait, the task T014c says: "Ingest and preprocess both satellite-era and pre-satellite GSN data."
      And T014b says: "Apply TSI proxy value 1360.5 W/m² ... for gaps >= 1 year."
      This implies the output dataset might need a TSI column filled with the proxy for large GSN gaps.
      
      Let's assume the input GSN data has NaNs for missing periods.
      1. Interpolate gaps < 1 year.
      2. Identify gaps >= 1 year.
      3. For those periods, we cannot fill GSN. We will mark them.
      4. If we are producing a TSI column (as part of the merged output), we fill those with 1360.5.
      
      Since this function takes a GSN df, we will:
      - Fill small gaps in GSN.
      - Identify large gaps.
      - Return the GSN df with small gaps filled and large gaps marked (NaN).
      
      The TSI proxy application will be done in `merge_datasets` if we are creating a unified TSI column.
      
    """
    df = df.copy()
    
    if 'date' not in df.columns or 'gsn' not in df.columns:
        raise ValueError("DataFrame must have 'date' and 'gsn' columns")
        
    df = df.sort_values('date').reset_index(drop=True)
    
    # Identify gaps
    df['date_diff'] = df['date'].diff()
    df['gap_years'] = df['date_diff'].dt.days / 365.25
    
    # Fill small gaps (< 1 year)
    mask_small = df['gap_years'] < gap_threshold_years
    # We need to interpolate the GSN values
    # Create a mask for NaNs in GSN
    gsn_na = df['gsn'].isna()
    
    # Identify contiguous NaN blocks
    gnan = gsn_na.astype(int)
    gnan_group = (gnan != gnan.shift()).cumsum()
    
    for group_id in gnan_group[gnan].unique():
        indices = gnan[gnan_group == group_id].index
        start_idx = indices[0]
        end_idx = indices[-1]
        
        # Check if this block is preceded and followed by valid data
        if start_idx > 0 and end_idx < len(df) - 1:
            prev_val = df.loc[start_idx - 1, 'gsn']
            next_val = df.loc[end_idx + 1, 'gsn']
            
            # Calculate gap duration
            gap_duration = (df.loc[end_idx + 1, 'date'] - df.loc[start_idx - 1, 'date']).days / 365.25
            
            if gap_duration < gap_threshold_years:
                # Linear interpolation
                df.loc[start_idx:end_idx, 'gsn'] = np.linspace(prev_val, next_val, len(indices) + 2)[1:-1]
            else:
                # Large gap: Do not interpolate. Leave as NaN.
                # But we mark it for TSI proxy logic later
                df.loc[start_idx:end_idx, 'gsn'] = np.nan
                df.loc[start_idx:end_idx, 'is_large_gap'] = True
        else:
            # Edge cases: leave as NaN
            df.loc[start_idx:end_idx, 'gsn'] = np.nan
    
    # Clean up temp columns
    df.drop(columns=['date_diff', 'gap_years'], inplace=True)
    
    # Ensure NaN for large gaps
    if 'is_large_gap' not in df.columns:
        df['is_large_gap'] = df['gsn'].isna()
        
    return df

def merge_datasets(gsn_df: pd.DataFrame, tsi_df: pd.DataFrame) -> pd.DataFrame:
    """
    Merge GSN and TSI datasets.
    - Align on date.
    - For satellite era (2003+), use actual TSI where available.
    - For pre-satellite or gaps in TSI, use GSN-based reconstruction or proxy.
    
    Output:
        DataFrame with columns: date, gsn, tsi, cycle_id, is_large_gap
    """
    data_path = get_data_path()
    processed_dir = Path(data_path) / "processed"
    processed_dir.mkdir(parents=True, exist_ok=True)
    
    # Ensure both have date index
    gsn_df = gsn_df.set_index('date').sort_index()
    tsi_df = tsi_df.set_index('date').sort_index()
    
    # Create a unified date range
    # We want to cover 1610 to present
    # Start from min date in GSN (pre-satellite) to max date in TSI (satellite)
    start_date = min(gsn_df.index.min(), tsi_df.index.min())
    end_date = max(gsn_df.index.max(), tsi_df.index.max())
    
    # Create a complete date index (daily)
    # This might be too large for 400 years? 400 * 365 = 146,000 rows. Manageable.
    # However, GSN data is often monthly. Let's resample to monthly for consistency.
    # Or keep daily if available. Let's assume monthly for GSN and daily for TSI?
    # T013a says SILSO GSN is monthly. T013b says SORCE TSI is daily.
    # Let's resample everything to monthly for the final output to reduce size and align with GSN.
    
    gsn_monthly = gsn_df.resample('MS').mean()
    tsi_monthly = tsi_df.resample('MS').mean()
    
    # Merge
    merged = pd.merge(
        gsn_monthly.reset_index(),
        tsi_monthly.reset_index(),
        on='date',
        how='outer'
    )
    
    merged = merged.sort_values('date').reset_index(drop=True)
    
    # Apply Cycle ID
    merged = detect_cycle_boundaries(merged)
    
    # Apply Gap Filling logic
    merged = fill_gaps(merged)
    
    # Handle TSI Proxy for large GSN gaps
    # If GSN is NaN (large gap) and TSI is also NaN (pre-satellite or gap in TSI), use proxy
    # Note: T014b says "Apply TSI proxy value 1360.5 W/m² for gaps >= 1 year"
    # This implies if we have a gap in GSN >= 1 year, we assign TSI = 1360.5.
    # But we must be careful: if TSI data exists (satellite era), we use that.
    
    proxy_value = get_tsi_proxy_value()
    if pd.isna(proxy_value):
        proxy_value = 1360.5
        
    # Condition: GSN is NaN (indicating large gap or missing) AND TSI is NaN
    # OR specifically if the gap in GSN is >= 1 year (is_large_gap)
    # Let's use the is_large_gap flag we created.
    
    mask_proxy = merged['is_large_gap'] & merged['tsi'].isna()
    merged.loc[mask_proxy, 'tsi'] = proxy_value
    
    # For satellite era where GSN is missing but TSI exists, we keep TSI.
    # For pre-satellite where GSN exists, we keep GSN, TSI is NaN (to be reconstructed later).
    
    # Clean up
    if 'is_large_gap' in merged.columns:
        merged.drop(columns=['is_large_gap'], inplace=True)
        
    # Ensure dtypes
    merged['gsn'] = merged['gsn'].astype(float)
    merged['tsi'] = merged['tsi'].astype(float)
    merged['cycle_id'] = merged['cycle_id'].astype(int)
    
    return merged

def run_preprocessing() -> str:
    """
    Main entry point for preprocessing.
    1. Load raw GSN and TSI.
    2. Merge and preprocess.
    3. Write to data/processed/preprocessed_data.parquet (atomic write).
    
    Returns:
        Path to the output file.
    """
    logger.info("Starting preprocessing pipeline (T014c)")
    
    # Load
    gsn_df, tsi_df = load_raw_data()
    
    # Merge and Process
    merged_df = merge_datasets(gsn_df, tsi_df)
    
    # Output path
    data_path = get_data_path()
    processed_dir = Path(data_path) / "processed"
    processed_dir.mkdir(parents=True, exist_ok=True)
    output_file = processed_dir / "preprocessed_data.parquet"
    temp_file = processed_dir / "preprocessed_data.parquet.tmp"
    
    # Atomic write
    logger.info(f"Writing preprocessed data to {output_file}")
    merged_df.to_parquet(temp_file, index=False)
    os.replace(temp_file, output_file)
    
    logger.info(f"Preprocessing complete. Output: {output_file}")
    logger.info(f"Dataset shape: {merged_df.shape}")
    logger.info(f"Date range: {merged_df['date'].min()} to {merged_df['date'].max()}")
    logger.info(f"Cycle IDs present: {sorted(merged_df['cycle_id'].unique())}")
    
    return str(output_file)

def main():
    """Script entry point."""
    output_path = run_preprocessing()
    print(f"Preprocessing completed. Output saved to: {output_path}")

if __name__ == "__main__":
    main()