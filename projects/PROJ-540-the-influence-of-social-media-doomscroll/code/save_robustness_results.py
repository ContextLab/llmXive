"""
Module to save robustness check results to JSON.

This module implements task T027: Save robustness results to outputs/robustness_results.json.
It loads the results generated by the robustness check (run_robustness_check) and saves
them to the specified output file with proper formatting and logging.
"""
import json
import logging
import sys
from pathlib import Path
from typing import Dict, Any, Optional
from config import load_config, ensure_directories

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
    handlers=[
        logging.FileHandler('outputs/analysis.log'),
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)


def save_robustness_results(results: Dict[str, Any], output_path: Optional[Path] = None) -> Path:
    """
    Save robustness check results to a JSON file.

    Args:
        results: Dictionary containing robustness check results including:
            - correlation between engagement and news exposure
            - subset selection criteria
            - regression results for full and subset models
            - comparison metrics
        output_path: Optional custom output path. Defaults to 'outputs/robustness_results.json'.

    Returns:
        Path to the saved file.

    Raises:
        ValueError: If results dictionary is empty or missing required fields.
        IOError: If file cannot be written.
    """
    if not results:
        raise ValueError("Results dictionary cannot be empty")

    # Required fields for robustness results
    required_fields = [
        'engagement_correlation',
        'subset_selected',
        'full_model_results',
        'subset_model_results'
    ]

    for field in required_fields:
        if field not in results:
            logger.warning(f"Missing required field in results: {field}")

    # Use config for default output path if not provided
    if output_path is None:
        config = load_config()
        output_path = Path(config.get('output_path', 'outputs')) / 'robustness_results.json'

    # Ensure output directory exists
    ensure_directories([output_path.parent])

    # Write results to JSON
    try:
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(results, f, indent=2, default=str)
        
        logger.info(f"Robustness results saved to {output_path}")
        return output_path
    except IOError as e:
        logger.error(f"Failed to write robustness results to {output_path}: {e}")
        raise


def main():
    """
    Main function to demonstrate saving robustness results.
    
    This function loads the robustness check results from the model module
    (if available) and saves them to the output file.
    """
    logger.info("Starting robustness results save process")
    
    try:
        # Import the robustness check function to get results
        from robustness import run_robustness_check
        from pathlib import Path
        
        # Load processed data path from config
        config = load_config()
        data_path = Path(config.get('processed_data_path', 'data/processed/analysis_data.csv'))
        
        if not data_path.exists():
            logger.error(f"Processed data file not found: {data_path}")
            logger.error("Please run the data ingestion and cleaning pipeline first (T010-T013)")
            sys.exit(1)
        
        # Run robustness check to get results
        logger.info("Running robustness check...")
        results = run_robustness_check(data_path)
        
        # Save results
        output_path = save_robustness_results(results)
        
        logger.info(f"Successfully saved robustness results to {output_path}")
        logger.info(f"Results summary:")
        logger.info(f"  - Engagement correlation: {results.get('engagement_correlation', 'N/A')}")
        logger.info(f"  - Subset selected: {results.get('subset_selected', False)}")
        if results.get('subset_selected'):
            logger.info(f"  - Full model news_exposure coefficient: {results['full_model_results']['coefficients'].get('news_exposure_freq', 'N/A')}")
            logger.info(f"  - Subset model news_exposure coefficient: {results['subset_model_results']['coefficients'].get('news_exposure_freq', 'N/A')}")
        
        return results
        
    except Exception as e:
        logger.error(f"Error in main robustness save process: {e}", exc_info=True)
        sys.exit(1)


if __name__ == "__main__":
    main()