import json
import logging
import sys
from pathlib import Path
from typing import Dict, Any, Optional
from config import load_config, ensure_directories

logger = logging.getLogger(__name__)

def save_robustness_results(results: Dict[str, Any], output_path: Optional[Path] = None) -> Path:
    """
    Save robustness check results to a JSON file.

    Args:
        results: Dictionary containing robustness check results (full model vs high-engagement subset)
        output_path: Optional specific path to save results. If None, uses config default.

    Returns:
        Path to the saved JSON file.

    Raises:
        IOError: If unable to write the file.
        ValueError: If results structure is invalid.
    """
    if output_path is None:
        config = load_config()
        output_dir = Path(config.get('output_dir', 'outputs'))
        ensure_directories([output_dir])
        output_path = output_dir / 'robustness_results.json'
    else:
        ensure_directories([output_path.parent])

    if not isinstance(results, dict):
        raise ValueError("Results must be a dictionary.")

    try:
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(results, f, indent=2, default=str)
        logger.info(f"Robustness results saved to {output_path}")
        return output_path
    except IOError as e:
        logger.error(f"Failed to save robustness results: {e}")
        raise

def main():
    """
    Main entry point for saving robustness results.
    Expects results to be passed via command line args or loaded from a previous step.
    For this implementation, we assume the results are generated by run_robustness_check
    and passed here, or we load the raw data to re-run the check if needed.
    However, per task T026, the results should ideally be generated there.
    To ensure T027 is runnable independently for the output artifact,
    we will re-run the robustness check logic here if no results file exists,
    or load the results from the previous step if T026 produced them in memory.
    
    Since this is a script to save, and T026 (run_robustness_check) likely returns the dict,
    we will implement a flow that:
    1. Loads processed data.
    2. Runs the robustness check (importing from robustness.py).
    3. Saves the result.
    """
    logging.basicConfig(level=logging.INFO)
    config = load_config()
    
    try:
        from robustness import run_robustness_check
        from config import get_dataset_url
        
        # Load processed data (T013 output)
        processed_data_path = Path(config.get('processed_data_path', 'data/processed/analysis_data.csv'))
        if not processed_data_path.exists():
            logger.error(f"Processed data not found at {processed_data_path}. Run T013 first.")
            sys.exit(1)
        
        import pandas as pd
        df = pd.read_csv(processed_data_path)
        
        logger.info("Running robustness check to generate results...")
        results = run_robustness_check(df, config)
        
        logger.info("Saving robustness results...")
        output_path = save_robustness_results(results)
        
        print(f"Robustness results successfully saved to: {output_path}")
        
    except Exception as e:
        logger.exception("Error during robustness results generation and saving:")
        sys.exit(1)

if __name__ == "__main__":
    main()
