"""
Stability analysis script for T008.

Reads the primary estimation results (produced by the main pipeline)
and the sensitivity sweep results generated by
``run_sensitivity_sweep.py`` and writes a JSON report containing the
maximum absolute difference in coverage rates across the overlapping
τ² levels.
"""

from pathlib import Path

from analysis.stats import compute_stability_analysis

def main() -> int:
    # Paths are fixed by the project convention.
    primary_csv = Path("data/results/estimation_results.csv")
    sensitivity_csv = Path("data/results/estimation_results_sensitivity.csv")
    output_json = Path("data/results/stability_analysis.json")

    # Perform the comparison.
    compute_stability_analysis(primary_csv, sensitivity_csv, output_json)

    print(f"Stability analysis written to {output_json}")
    return 0

if __name__ == "__main__":
    import sys

    sys.exit(main())