"""
Multiple-comparison correction (FDR) for narrative categories and ROIs.

This module implements the Benjamini-Hochberg FDR correction across
multiple hypothesis tests generated by the decoder analysis (US3).
It processes accuracy p-values across narrative categories (plot, character, theme)
and ROIs (hippocampus, mPFC, PCC, lateral temporal cortex).

Inputs:
  - results/decoder_metrics.json (or similar aggregated results)
Outputs:
  - results/fdr_corrected_metrics.json
"""

import numpy as np
import json
import logging
from pathlib import Path
from statsmodels.stats.multitest import fdrcorrection
import code.config as config

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


def apply_fdr_to_results(p_values: list, alpha: float = 0.05) -> dict:
    """
    Apply Benjamini-Hochberg FDR correction to a list of p-values.

    Args:
        p_values: List of p-values from hypothesis tests.
        alpha: Significance threshold (default 0.05).

    Returns:
        Dictionary with corrected p-values and significance flags.
    """
    if not p_values:
        logger.warning("No p-values provided for FDR correction.")
        return {"corrected_pvalues": [], "is_significant": [], "q_thresholds": []}

    p_values = np.array(p_values)
    rejected, corrected_pvalues, _, _ = fdrcorrection(p_values, alpha=alpha, method="indep")

    # Calculate q-thresholds (BH procedure thresholds)
    n = len(p_values)
    q_thresholds = [(i + 1) / n * alpha for i in range(n)]

    return {
        "corrected_pvalues": corrected_pvalues.tolist(),
        "is_significant": rejected.tolist(),
        "q_thresholds": q_thresholds,
        "original_pvalues": p_values.tolist(),
        "alpha": alpha
    }


def run_fdr_correction_pipeline(
    input_path: str = None,
    output_path: str = None,
    alpha: float = 0.05
) -> dict:
    """
    Main pipeline to apply FDR correction to decoder results.

    Expects an input JSON file containing p-values for each (category, ROI) pair.
    Structure expected:
    {
      "results": [
        {"category": "plot", "roi": "hippocampus", "p_value": 0.03, ...},
        ...
      ]
    }

    Args:
        input_path: Path to input JSON file.
        output_path: Path to output JSON file.
        alpha: FDR significance threshold.

    Returns:
        Dictionary containing corrected results.
    """
    if input_path is None:
        input_path = config.get_output_path("results/decoder_metrics.json")
    if output_path is None:
        output_path = config.get_output_path("results/fdr_corrected_metrics.json")

    input_path = Path(input_path)
    output_path = Path(output_path)

    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")

    logger.info(f"Loading results from {input_path}")
    with open(input_path, 'r') as f:
        data = json.load(f)

    # Handle both list of results and single metrics object
    results_list = data.get("results", [])
    if not results_list and "p_value" in data:
        # Single result case (wrap for uniformity)
        results_list = [data]

    if not results_list:
        raise ValueError("No results found in input file.")

    # Extract p-values and metadata
    p_values = []
    metadata = []

    for item in results_list:
        p_val = item.get("p_value")
        if p_val is None:
            # Try to compute p-value from accuracy if not present (fallback logic)
            # For now, we assume p_value is provided or computed in T030/T031
            logger.warning(f"Missing p_value in item: {item}, skipping.")
            continue
        p_values.append(float(p_val))
        metadata.append({
            "category": item.get("category", "unknown"),
            "roi": item.get("roi", "unknown"),
            "accuracy": item.get("accuracy", None),
            "chance_level": item.get("chance_level", None)
        })

    if not p_values:
        raise ValueError("No valid p-values found in input.")

    logger.info(f"Applying FDR correction to {len(p_values)} tests.")
    fdr_results = apply_fdr_to_results(p_values, alpha=alpha)

    # Merge metadata with FDR results
    corrected_results = []
    for i, meta in enumerate(metadata):
        if i < len(fdr_results["corrected_pvalues"]):
            corrected_results.append({
                "category": meta["category"],
                "roi": meta["roi"],
                "accuracy": meta["accuracy"],
                "chance_level": meta["chance_level"],
                "original_pvalue": fdr_results["original_pvalues"][i],
                "corrected_pvalue": fdr_results["corrected_pvalues"][i],
                "is_significant_after_fdr": fdr_results["is_significant"][i],
                "q_threshold": fdr_results["q_thresholds"][i]
            })

    output_data = {
        "alpha": alpha,
        "num_tests": len(p_values),
        "num_significant": sum(fdr_results["is_significant"]),
        "results": corrected_results
    }

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    logger.info(f"Writing FDR-corrected results to {output_path}")
    with open(output_path, 'w') as f:
        json.dump(output_data, f, indent=2)

    return output_data


def main():
    """Entry point for running FDR correction pipeline."""
    logger.info("Starting FDR correction pipeline for narrative categories and ROIs.")

    try:
        # Default paths based on config
        input_path = config.get_output_path("results/decoder_metrics.json")
        output_path = config.get_output_path("results/fdr_corrected_metrics.json")

        # Check if input exists
        if not Path(input_path).exists():
            logger.error(f"Input file {input_path} not found. "
                         "Please ensure decoder analysis (T030/T031) has been run.")
            return 1

        results = run_fdr_correction_pipeline(
            input_path=input_path,
            output_path=output_path,
            alpha=0.05
        )

        logger.info(f"FDR correction complete. {results['num_significant']} of "
                    f"{results['num_tests']} tests are significant at q < {results['alpha']}.")
        logger.info(f"Results saved to {output_path}")

        return 0

    except Exception as e:
        logger.error(f"FDR correction pipeline failed: {e}", exc_info=True)
        return 1


if __name__ == "__main__":
    exit(main())
