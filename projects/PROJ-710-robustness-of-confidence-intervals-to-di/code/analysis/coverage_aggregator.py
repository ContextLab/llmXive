"""
Coverage Aggregator: Reads intermediate simulation results and computes final coverage statistics.

This module implements Task T015: Result Aggregation.
It reads `artifacts/coverage_intermediate.csv` and produces `artifacts/coverage_results.csv`
with the explicit calculation of `deviation_from_nominal`.
"""
import pandas as pd
import numpy as np
import json
import os
from pathlib import Path
from typing import Optional, List, Dict, Any

# Import config to get the nominal target
import sys
# Ensure the code directory is in the path for imports
if str(Path(__file__).parent.parent) not in sys.path:
    sys.path.insert(0, str(Path(__file__).parent.parent))

import config

def load_coverage_intermediate(input_path: Optional[Path] = None) -> pd.DataFrame:
    """
    Loads the intermediate coverage CSV generated by the main simulation loop.

    Args:
        input_path: Path to the intermediate CSV. Defaults to config.COVERAGE_INTERMEDIATE_PATH.

    Returns:
        DataFrame containing the intermediate results.

    Raises:
        FileNotFoundError: If the intermediate file does not exist.
        ValueError: If required columns are missing.
    """
    if input_path is None:
        input_path = config.COVERAGE_INTERMEDIATE_PATH

    if not os.path.exists(input_path):
        raise FileNotFoundError(f"Intermediate coverage file not found at {input_path}. "
                                "Run the main simulation (T013) first.")

    df = pd.read_csv(input_path)

    required_columns = ['dataset', 'epsilon', 'noise_type', 'statistic',
                        'covered', 'ci_lower', 'ci_upper', 'point_estimate']
    missing = set(required_columns) - set(df.columns)
    if missing:
        raise ValueError(f"Missing required columns in {input_path}: {missing}")

    # Ensure numeric types for calculation
    numeric_cols = ['epsilon', 'ci_lower', 'ci_upper', 'point_estimate']
    for col in numeric_cols:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors='coerce')

    return df

def calculate_adjusted_coverage(df: pd.DataFrame) -> pd.DataFrame:
    """
    Calculates the deviation from the nominal coverage target for each row.

    This function satisfies the specific requirement of T015 to explicitly
    calculate and store `deviation_from_nominal` using the target from config.py.

    Args:
        df: DataFrame with coverage results.

    Returns:
        DataFrame with the new 'deviation_from_nominal' column added.
    """
    # Get nominal target from config, defaulting to 0.95 if not found
    nominal_target = getattr(config, 'NOMINAL_COVERAGE_TARGET', 0.95)

    # Calculate deviation
    # 'covered' is expected to be 0 or 1 (boolean or int) indicating if the true parameter was in the CI
    # We calculate the deviation of the *observed* coverage (which is 0 or 1 for a single trial)
    # from the nominal target.
    # Note: The aggregation of this column across rows will yield the empirical coverage rate.
    df['deviation_from_nominal'] = df['covered'] - nominal_target

    return df

def save_extended_results(df: pd.DataFrame, output_path: Optional[Path] = None) -> Path:
    """
    Saves the final coverage results to the specified output path.

    Args:
        df: DataFrame containing the extended results.
        output_path: Path to save the CSV. Defaults to config.COVERAGE_RESULTS_PATH.

    Returns:
        The path where the file was saved.
    """
    if output_path is None:
        output_path = config.COVERAGE_RESULTS_PATH

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Save to CSV
    df.to_csv(output_path, index=False)

    return output_path

def main():
    """
    Main entry point for the coverage aggregation pipeline.
    Reads intermediate data, calculates deviation, and saves final results.
    """
    print("Starting coverage aggregation (T015)...")

    try:
        # Load intermediate data
        print(f"Loading intermediate data from {config.COVERAGE_INTERMEDIATE_PATH}...")
        df = load_coverage_intermediate()
        print(f"Loaded {len(df)} rows.")

        # Calculate deviation from nominal
        print("Calculating deviation from nominal coverage...")
        df = calculate_adjusted_coverage(df)

        # Save final results
        print(f"Saving results to {config.COVERAGE_RESULTS_PATH}...")
        output_path = save_extended_results(df)

        print(f"Aggregation complete. Output saved to {output_path}")

        # Print a sample of the new column to verify
        print("Sample of 'deviation_from_nominal' values:")
        print(df['deviation_from_nominal'].head())

    except FileNotFoundError as e:
        print(f"Error: {e}")
        print("Please ensure the main simulation (T013) has been run and produced artifacts/coverage_intermediate.csv")
        sys.exit(1)
    except Exception as e:
        print(f"Unexpected error during aggregation: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()