"""
Execute the filter logic for User Story 2.

Reads the validation report generated by T007-exec, applies the filter_and_fallback
logic defined in T024a (from descriptors.py), and outputs:
1. data/processed/filtered_config_ids.json: List of IDs to process.
2. Internal flags for VDOS status (logged and used for subsequent steps).

This script does not calculate descriptors; it only determines which configs
proceed to the descriptor calculation stage and how they should be handled
regarding missing VDOS.
"""
import json
import logging
import sys
from pathlib import Path
from typing import Dict, List, Any, Optional

# Import the logic defined in T024a
from descriptors import filter_and_fallback
from config.env_config import get_processed_dir
from logging_config import setup_logging, get_logger

def load_validation_report(report_path: Path) -> Dict[str, Any]:
    """Load the validation report JSON."""
    if not report_path.exists():
        raise FileNotFoundError(f"Validation report not found at {report_path}")
    
    with open(report_path, 'r') as f:
        return json.load(f)

def save_filtered_config_ids(ids: List[str], output_path: Path) -> None:
    """Save the list of filtered config IDs to JSON."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(ids, f, indent=2)
    logging.info(f"Saved {len(ids)} filtered config IDs to {output_path}")

def run_filter(
    validation_report_path: Path,
    output_ids_path: Path,
    logger: logging.Logger
) -> Dict[str, Any]:
    """
    Execute the filter logic on validated configs.
    
    Args:
        validation_report_path: Path to data/processed/validation_report.json
        output_ids_path: Path to write data/processed/filtered_config_ids.json
        logger: Logger instance
    
    Returns:
        A summary dict of the filtering operation.
    """
    logger.info(f"Loading validation report from {validation_report_path}")
    report = load_validation_report(validation_report_path)
    
    validated_configs = report.get('validated_configs', [])
    logger.info(f"Found {len(validated_configs)} validated configs.")
    
    if not validated_configs:
        logger.warning("No validated configs found. Filtering will result in empty list.")
        save_filtered_config_ids([], output_ids_path)
        return {"total": 0, "filtered": 0, "vdos_missing": 0}
    
    # Prepare input for filter_and_fallback
    # The function expects a list of config identifiers or objects.
    # Based on T024a logic, we pass the IDs and let the function determine VDOS status.
    # We assume the function can check for VDOS existence internally or via metadata.
    # For this execution, we pass the list of IDs.
    
    filtered_ids, vdos_status_map = filter_and_fallback(validated_configs, logger)
    
    logger.info(f"Filtering complete. {len(filtered_ids)} configs retained for processing.")
    
    vdos_missing_count = sum(1 for status in vdos_status_map.values() if status == "VDOS-MISSING")
    logger.info(f"VDOS Missing count: {vdos_missing_count}")
    
    # Save the filtered IDs
    save_filtered_config_ids(filtered_ids, output_ids_path)
    
    # Log the VDOS status for retained configs (internal flags)
    for cid, status in vdos_status_map.items():
        if status == "VDOS-MISSING":
            logger.warning(f"Config {cid} retained for topological-only analysis (VDOS missing).")
        else:
            logger.debug(f"Config {cid} has full data (VDOS present).")
    
    return {
        "total_validated": len(validated_configs),
        "total_filtered": len(filtered_ids),
        "vdos_missing_count": vdos_missing_count,
        "vdos_status_map": vdos_status_map
    }

def main() -> int:
    """Main entry point for the filter execution."""
    setup_logging()
    logger = get_logger(__name__)
    
    processed_dir = get_processed_dir()
    validation_report_path = processed_dir / "validation_report.json"
    output_ids_path = processed_dir / "filtered_config_ids.json"
    
    try:
        summary = run_filter(validation_report_path, output_ids_path, logger)
        logger.info("Filter execution completed successfully.")
        logger.info(f"Summary: {json.dumps(summary, indent=2)}")
        return 0
    except FileNotFoundError as e:
        logger.error(f"Required file not found: {e}")
        return 1
    except Exception as e:
        logger.exception(f"Unexpected error during filtering: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
