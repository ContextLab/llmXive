import csv
import json
import logging
from pathlib import Path
from typing import List, Dict, Any

from config.env_config import get_processed_dir

logger = logging.getLogger(__name__)

def load_processed_configs() -> List[Dict[str, Any]]:
    """
    Load the aggregated descriptor data from the JSON file generated by T025.
    This file contains the mapping of Config ID to their full descriptor vectors.
    """
    processed_dir = get_processed_dir()
    input_path = processed_dir / "aggregated_descriptors.json"
    
    if not input_path.exists():
        logger.error(f"Aggregated descriptors file not found at {input_path}. "
                     "Please ensure T025 (Aggregate all descriptors) has been run.")
        raise FileNotFoundError(f"Missing aggregated descriptors file: {input_path}")

    with open(input_path, 'r') as f:
        data = json.load(f)
    
    # Expected structure: {"configs": [{"config_id": "...", "descriptors": {...}}, ...]}
    # or a flat list of dicts. We handle the nested structure typically produced by aggregation.
    if isinstance(data, dict) and "configs" in data:
        return data["configs"]
    elif isinstance(data, list):
        return data
    else:
        logger.error(f"Unexpected data format in {input_path}. Expected list or dict with 'configs' key.")
        raise ValueError("Invalid data format in aggregated descriptors file.")

def save_descriptors_to_csv(configs: List[Dict[str, Any]], output_filename: str = "descriptors.csv") -> Path:
    """
    Save the processed descriptors to a CSV file.
    
    The CSV will have a header row where the first column is 'config_id'
    and subsequent columns are the descriptor keys (flattened if nested).
    
    Args:
        configs: List of dictionaries containing config_id and descriptor data.
        output_filename: Name of the output CSV file.
        
    Returns:
        Path to the saved CSV file.
    """
    if not configs:
        logger.warning("No configurations to save. Creating empty CSV with headers.")
        # Create empty file with headers if possible, or just an empty file
        output_path = get_processed_dir() / output_filename
        with open(output_path, 'w', newline='') as f:
            f.write("config_id\n") # Minimal header if no data
        return output_path

    # Flatten keys to determine columns
    all_keys = {"config_id"}
    for config in configs:
        if "descriptors" in config and isinstance(config["descriptors"], dict):
            all_keys.update(config["descriptors"].keys())
        elif isinstance(config, dict):
            # Fallback if structure is flat
            all_keys.update(k for k in config.keys() if k != "config_id")
    
    sorted_keys = sorted(list(all_keys))
    
    output_path = get_processed_dir() / output_filename
    
    try:
        with open(output_path, 'w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=sorted_keys)
            writer.writeheader()
            
            for config in configs:
                row = {}
                config_id = config.get("config_id", "")
                row["config_id"] = config_id
                
                descriptors = config.get("descriptors", {})
                if not isinstance(descriptors, dict):
                    # If descriptors is not a dict, try to parse or skip
                    logger.warning(f"Config {config_id} has non-dict descriptors. Skipping descriptor values.")
                    descriptors = {}
                
                for key in sorted_keys:
                    if key == "config_id":
                        continue
                    # Handle nested values if any, though we expect flat dicts here
                    val = descriptors.get(key, "")
                    row[key] = val
                
                writer.writerow(row)
        
        logger.info(f"Successfully saved {len(configs)} configurations to {output_path}")
        return output_path
    
    except Exception as e:
        logger.error(f"Failed to save descriptors to CSV: {e}")
        raise

def main():
    """
    Main entry point for T027: Save processed descriptors to data/processed/descriptors.csv
    """
    setup_logging = False # Assuming logging is already configured by main.py or logging_config
    # If this script is run standalone:
    # from logging_config import setup_logging
    # setup_logging()
    
    try:
        logger.info("Starting T027: Save processed descriptors to CSV")
        
        # 1. Load the aggregated data (produced by T025)
        configs = load_processed_configs()
        logger.info(f"Loaded {len(configs)} configurations from aggregated data.")
        
        # 2. Save to CSV
        output_path = save_descriptors_to_csv(configs, "descriptors.csv")
        
        logger.info(f"T027 completed. Output written to: {output_path}")
        
    except FileNotFoundError as e:
        logger.error(f"Data not found. Ensure T025 has completed successfully: {e}")
        raise
    except Exception as e:
        logger.error(f"Error during T027 execution: {e}")
        raise

if __name__ == "__main__":
    main()
