import csv
import logging
import json
from pathlib import Path
from typing import List, Dict, Any

from config.env_config import get_processed_dir
from logging_config import get_logger

logger = get_logger(__name__)

def load_processed_configs() -> List[Dict[str, Any]]:
    """
    Load the aggregated descriptors from the intermediate JSON file.
    This file is expected to be generated by `aggregate_descriptors.py`.
    """
    processed_dir = get_processed_dir()
    input_path = processed_dir / "aggregated_descriptors.json"

    if not input_path.exists():
        logger.error(f"Input file not found: {input_path}. "
                     "Please run `aggregate_descriptors.py` first.")
        raise FileNotFoundError(f"Missing aggregated descriptors: {input_path}")

    with open(input_path, 'r') as f:
        data = json.load(f)

    return data

def save_descriptors_to_csv(configs: List[Dict[str, Any]], output_filename: str = "descriptors.csv") -> None:
    """
    Save the list of configuration descriptor dictionaries to a CSV file.
    
    Args:
        configs: List of dictionaries where each dict represents a configuration
                 with 'config_id' and various descriptor keys.
        output_filename: Name of the output file in the processed directory.
    """
    if not configs:
        logger.warning("No configurations to save.")
        return

    processed_dir = get_processed_dir()
    output_path = processed_dir / output_filename

    # Flatten nested dictionaries if any (e.g., if ring_stats is a dict)
    # We expect the aggregation step to have flattened these into top-level keys
    # like 'ring_3', 'ring_4', etc., or we handle them here.
    # Assuming the input is already a flat dict per config for CSV compatibility.
    
    fieldnames = list(configs[0].keys())
    
    logger.info(f"Saving {len(configs)} configurations to {output_path}")
    
    with open(output_path, 'w', newline='', encoding='utf-8') as csvfile:
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        writer.writeheader()
        for config in configs:
            writer.writerow(config)

    logger.info(f"Successfully saved descriptors to {output_path}")

    # Register the artifact in the state manager for reproducibility
    try:
        from state_manager import register_artifact
        register_artifact(str(output_path))
    except ImportError:
        logger.debug("State manager not available, skipping registration.")

def main():
    """
    Main entry point for the save_descriptors task.
    Loads aggregated data and saves it as a CSV.
    """
    setup_logger = get_logger(__name__)
    setup_logger.info("Starting descriptor saving process...")
    
    try:
        configs = load_processed_configs()
        save_descriptors_to_csv(configs)
        logger.info("Task T027 completed successfully.")
    except FileNotFoundError as e:
        logger.critical(str(e))
        raise
    except Exception as e:
        logger.critical(f"Failed to save descriptors: {e}")
        raise

if __name__ == "__main__":
    main()