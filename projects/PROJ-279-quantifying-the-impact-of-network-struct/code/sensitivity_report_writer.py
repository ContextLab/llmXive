"""
Sensitivity Report Writer for T015c.

Reads the sensitivity analysis results generated by T015b (run_sensitivity_analysis)
and writes the final `data/processed/sensitivity_report.json` with the required schema.

Schema:
{
  "cutoff_radii": [2.8, 3.0, 3.2],
  "results": [
    {
      "cutoff_radius": 2.8,
      "average_degree": <float>,
      "component_count": <int>,
      "num_configs_processed": <int>
    },
    ...
  ]
}
"""
import json
import logging
from pathlib import Path
from typing import Dict, List, Any, Optional
import numpy as np

from config.env_config import get_processed_dir
from logging_config import get_logger

logger = get_logger(__name__)

def load_sensitivity_data(processed_dir: Path) -> Optional[Dict[str, Any]]:
    """
    Loads the raw sensitivity analysis data generated by T015b.
    Expected file: data/processed/sensitivity_analysis_raw.json
    """
    raw_data_path = processed_dir / "sensitivity_analysis_raw.json"
    if not raw_data_path.exists():
        logger.error(f"Sensitivity raw data not found at {raw_data_path}. "
                     "Please ensure T015b (Execute Sensitivity Loop) has been run.")
        return None
    
    with open(raw_data_path, 'r') as f:
        return json.load(f)

def format_report(data: Dict[str, Any]) -> Dict[str, Any]:
    """
    Formats the raw sensitivity data into the required report schema.
    """
    # The raw data from T015b is expected to be a list of results,
    # keyed by cutoff radius or a flat list. We normalize it here.
    
    results_list = []
    
    # Expected keys in raw data: "2.8", "3.0", "3.2" or a list of dicts
    cutoff_radii = [2.8, 3.0, 3.2]
    
    for radius in cutoff_radii:
        radius_str = str(radius)
        entry = data.get(radius_str, None)
        
        if entry is None:
            logger.warning(f"No data found for cutoff radius {radius}. "
                           "Report will include this entry with null metrics.")
            result_entry = {
                "cutoff_radius": radius,
                "average_degree": None,
                "component_count": None,
                "num_configs_processed": 0,
                "status": "MISSING_DATA"
            }
        else:
            # Extract metrics, handling potential nested structures
            avg_deg = entry.get("average_degree")
            comp_cnt = entry.get("component_count")
            num_cfg = entry.get("num_configs_processed", 0)
            
            result_entry = {
                "cutoff_radius": radius,
                "average_degree": float(avg_deg) if avg_deg is not None else None,
                "component_count": int(comp_cnt) if comp_cnt is not None else None,
                "num_configs_processed": int(num_cfg),
                "status": "OK"
            }
        
        results_list.append(result_entry)

    return {
        "cutoff_radii": cutoff_radii,
        "results": results_list,
        "generated_from": "sensitivity_analysis_raw.json",
        "task_id": "T015c"
    }

def save_report(report: Dict[str, Any], output_path: Path) -> None:
    """
    Saves the formatted report to the specified JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)
    logger.info(f"Sensitivity report successfully written to {output_path}")

def main() -> None:
    """
    Main entry point for T015c.
    Reads T015b output and writes the final sensitivity_report.json.
    """
    processed_dir = get_processed_dir()
    output_path = processed_dir / "sensitivity_report.json"
    
    logger.info("Starting Sensitivity Report Writer (T015c)...")
    
    raw_data = load_sensitivity_data(processed_dir)
    if raw_data is None:
        logger.error("Aborting: Cannot generate report without raw sensitivity data.")
        raise FileNotFoundError("Sensitivity raw data missing. Run T015b first.")
    
    report = format_report(raw_data)
    save_report(report, output_path)
    
    logger.info("T015c completed successfully.")

if __name__ == "__main__":
    main()