"""
Execute the sensitivity analysis loop on validated configurations.

This script reads the validation report generated by T007-exec,
loads the corresponding atomic configurations, and runs the
sensitivity loop (cutoff radii: 2.8, 3.0, 3.2 Å) defined in T015a.

Output: data/processed/sensitivity_report.json
"""
import json
import logging
import sys
from pathlib import Path
from typing import Dict, List, Any, Optional
import numpy as np

# Import from project modules using the provided API surface
from config.env_config import get_processed_dir, get_config
from logging_config import setup_logging, get_logger
from validation import load_validation_report
from graph_builder import run_sensitivity_analysis
from state_manager import register_artifact, compute_file_checksum

# Setup logging
logger = setup_logging()

def load_configurations_from_validation_report(report_path: Path) -> List[Dict[str, Any]]:
    """
    Load the atomic configuration data for the validated configs.
    
    Note: This function assumes the raw data files (e.g., .xyz or .json)
    corresponding to the config IDs in the validation report exist in data/raw/.
    It reconstructs the list of AtomicConfiguration-like dicts needed for graph building.
    """
    report_data = load_validation_report(report_path)
    validated_ids = report_data.get("validated_configs", [])
    
    if not validated_ids:
        logger.warning("No validated configurations found in validation report.")
        return []

    # The actual loading logic depends on the specific file format in data/raw/
    # Since T014 (Download) is marked completed, we assume files exist.
    # We will attempt to load them using the project's standard loader if available,
    # or reconstruct based on the metadata if the raw loader is in download.py.
    # For this executor, we assume the 'download.py' module has a function to load configs by ID.
    # If not explicitly exported, we will try to import load_configurations_from_raw.
    
    try:
        from download import load_configurations_from_raw
        # Assuming this function loads all or specific configs.
        # We need to filter for validated_ids.
        # If load_configurations_from_raw takes a list of IDs, use it.
        # If it loads all, we filter.
        configs = load_configurations_from_raw(validated_ids)
        return configs
    except ImportError:
        logger.error("Could not import load_configurations_from_raw from download.py. "
                     "Ensure the download module exports this function.")
        raise

def run_sensitivity_executor():
    """
    Main entry point for T015b.
    """
    logger.info("Starting Sensitivity Analysis Execution (T015b)...")
    
    processed_dir = get_processed_dir()
    validation_report_path = Path(processed_dir) / "validation_report.json"
    output_report_path = Path(processed_dir) / "sensitivity_report.json"
    
    if not validation_report_path.exists():
        logger.error(f"Validation report not found at {validation_report_path}. "
                     "Please run T007-exec first.")
        sys.exit(1)
    
    # 1. Load validated configs
    logger.info(f"Loading configurations from validation report: {validation_report_path}")
    try:
        configs = load_configurations_from_validation_report(validation_report_path)
    except Exception as e:
        logger.error(f"Failed to load configurations: {e}")
        sys.exit(1)
    
    if not configs:
        logger.warning("No configurations to process. Stopping.")
        sys.exit(0)
    
    logger.info(f"Loaded {len(configs)} validated configurations.")
    
    # 2. Run Sensitivity Analysis
    # The graph_builder module exposes run_sensitivity_analysis which handles the loop
    # over {2.8, 3.0, 3.2} as defined in T015a.
    logger.info("Running sensitivity analysis loop...")
    try:
        sensitivity_results = run_sensitivity_analysis(configs)
    except Exception as e:
        logger.error(f"Sensitivity analysis failed: {e}")
        sys.exit(1)
    
    # 3. Save Report
    logger.info(f"Saving sensitivity report to {output_report_path}")
    with open(output_report_path, 'w') as f:
        json.dump(sensitivity_results, f, indent=2)
    
    # 4. Register artifact
    checksum = compute_file_checksum(output_report_path)
    register_artifact(
        path=str(output_report_path),
        checksum=checksum,
        task_id="T015b",
        description="Sensitivity analysis report for cutoff radii 2.8, 3.0, 3.2"
    )
    
    logger.info("Sensitivity Analysis Execution completed successfully.")
    return sensitivity_results

if __name__ == "__main__":
    run_sensitivity_executor()
