"""
Task T025: Save processed feature matrix to data/processed/features.csv with metadata.

This script loads the feature matrix (generated by T024/T024b/T029) and the
corresponding participant metadata (from the cleaned dataset), merges them,
and saves the final result to data/processed/features.csv.

It also generates a derivation log and updates metadata with completion status.
"""
import logging
import json
from pathlib import Path
from typing import Dict, Any, Optional

import pandas as pd
import numpy as np

from config import get_path, ensure_dirs
from features import extract_all_features
from derivation import generate_derivation_log

# Configure logging
logger = logging.getLogger(__name__)
if not logger.handlers:
    handler = logging.StreamHandler()
    handler.setFormatter(logging.Formatter('%(asctime)s - %(name)s - %(levelname)s - %(message)s'))
    logger.addHandler(handler)
    logger.setLevel(logging.INFO)

def load_feature_matrix() -> pd.DataFrame:
    """
    Load the intermediate feature matrix.
    Expected to be produced by previous steps (T024b, T029) in data/interim/
    or data/processed/ depending on the pipeline stage.
    For T025, we assume the features are in a temporary state or need to be
    re-extracted if the intermediate file is missing, but primarily we load
    from the expected interim location if T029 wrote it there, or we reconstruct
    from the cleaned dataset if the intermediate file is missing (fallback for robustness).
    
    However, per strict pipeline flow: T029 writes to data/interim/exclusions.log
    and the feature matrix should be ready in memory or a temp file.
    
    To ensure T025 is runnable standalone as per "whole-file contents", 
    we will attempt to load from data/interim/features_temp.csv (if T029 saved it there)
    OR re-run extraction from data/interim/cleaned_adress.csv if the temp file is missing.
    """
    interim_path = get_path("interim", "features_temp.csv")
    cleaned_path = get_path("interim", "cleaned_adress.csv")
    
    if interim_path.exists():
        logger.info(f"Loading feature matrix from {interim_path}")
        df = pd.read_csv(interim_path)
        return df
    
    if cleaned_path.exists():
        logger.warning(f"Intermediate feature file missing. Re-extracting features from {cleaned_path} (T024 dependency).")
        # Re-extract features to ensure we have data to save
        # This effectively runs the feature extraction logic again
        df_clean = pd.read_csv(cleaned_path)
        if 'text' not in df_clean.columns or 'label' not in df_clean.columns:
            raise ValueError("Cleaned dataset missing required columns 'text' or 'label'.")
        
        # Extract features using the existing pipeline
        # We assume the columns are: participant_id, label, text, TTR, MTLD, Noun_Verb_Ratio, 
        # Mean_Clause_Length, T_Unit_Count, Sentence_Embedding_Cosine_Similarity
        # If they don't exist, we need to compute them.
        
        # Check if features already exist
        required_cols = ['TTR', 'MTLD', 'Noun_Verb_Ratio', 'Mean_Clause_Length', 'T_Unit_Count', 'Sentence_Embedding_Cosine_Similarity']
        missing_cols = [c for c in required_cols if c not in df_clean.columns]
        
        if missing_cols:
            logger.info(f"Features missing: {missing_cols}. Re-extracting...")
            # We need to call the extraction logic. 
            # Since T024b/T029 are completed, we assume the functions exist in features.py
            # We will re-run the extraction logic here for robustness.
            # Note: This might be slow if embeddings are re-computed, but necessary for standalone run.
            
            # To avoid full re-computation if not needed, we check if the cleaned data has embeddings
            # For now, we assume we need to re-extract.
            # We will use the extract_all_features logic if available, or replicate it minimally.
            # Since we cannot import internal logic easily without circular deps, 
            # we assume the user has run T024b successfully and the data is in a state where
            # we just need to assemble. 
            
            # Fallback: If we are here, it means the intermediate file is missing.
            # We will raise an error if we cannot find the data, as T025 depends on T029.
            # However, to make it runnable, we will try to load the cleaned data and 
            # assume the features were computed in memory by the previous step in a real pipeline.
            # Since this is a file-based artifact, we must have the data.
            # We will raise a clear error if the data is not in the expected format.
            raise FileNotFoundError(
                f"Feature matrix not found at {interim_path} and cleaned data at {cleaned_path} "
                f"lacks required feature columns {missing_cols}. "
                f"Please ensure T024/T029 has been run successfully to generate the feature matrix."
            )
        
        return df_clean
    
    raise FileNotFoundError(
        f"Neither feature matrix ({interim_path}) nor cleaned dataset ({cleaned_path}) found. "
        f"Ensure T016 and T024/T029 have been executed."
    )

def load_cleaned_metadata() -> pd.DataFrame:
    """
    Load the cleaned dataset to ensure we have participant_id and label for the final output.
    """
    path = get_path("interim", "cleaned_adress.csv")
    if not path.exists():
        raise FileNotFoundError(f"Cleaned dataset not found at {path}. Run T016 first.")
    return pd.read_csv(path)

def merge_features_with_metadata(features_df: pd.DataFrame, metadata_df: pd.DataFrame) -> pd.DataFrame:
    """
    Merge the feature matrix with the original metadata (participant_id, label).
    Ensure participant_id is the join key.
    """
    # Standardize column names if necessary
    if 'participant_id' not in features_df.columns and 'participant_id' in metadata_df.columns:
        # If features_df was derived from metadata, it should have the ID.
        # If not, we assume the order is preserved or we need to join by index.
        # Ideally, the feature extraction step preserves the ID.
        if 'participant_id' not in features_df.columns:
            # Fallback: assume same order
            logger.warning("participant_id not found in features_df. Assuming row order matches metadata.")
            features_df['participant_id'] = metadata_df['participant_id'].values
            features_df['label'] = metadata_df['label'].values
            return features_df

    # If both have participant_id, merge
    if 'participant_id' in features_df.columns and 'participant_id' in metadata_df.columns:
        # Drop duplicate columns from metadata that are already in features (like text if present)
        cols_to_drop = [c for c in metadata_df.columns if c in features_df.columns and c != 'participant_id']
        metadata_df = metadata_df.drop(columns=cols_to_drop)
        return pd.merge(features_df, metadata_df, on='participant_id', how='left')
    
    # Fallback: just return features_df if it already has everything
    return features_df

def save_feature_matrix(df: pd.DataFrame, output_path: Path) -> None:
    """
    Save the final feature matrix to CSV.
    """
    ensure_dirs(output_path.parent)
    df.to_csv(output_path, index=False)
    logger.info(f"Saved feature matrix to {output_path} with shape {df.shape}")

def update_metadata(status: str = "completed") -> None:
    """
    Update data/results/metadata.json to reflect T025 completion.
    """
    metadata_path = get_path("results", "metadata.json")
    metadata = {}
    if metadata_path.exists():
        with open(metadata_path, 'r') as f:
            metadata = json.load(f)
    
    metadata['t025_status'] = status
    metadata['t025_timestamp'] = pd.Timestamp.now().isoformat()
    metadata['t025_output_file'] = str(get_path("processed", "features.csv"))
    
    ensure_dirs(metadata_path.parent)
    with open(metadata_path, 'w') as f:
        json.dump(metadata, f, indent=2)
    logger.info(f"Updated metadata at {metadata_path}")

def main():
    logger.info("Starting T025: Save processed feature matrix")
    
    try:
        # 1. Load features (from intermediate or re-extract if necessary)
        features_df = load_feature_matrix()
        
        # 2. Load metadata (to ensure participant_id and label are present and correct)
        metadata_df = load_cleaned_metadata()
        
        # 3. Merge
        final_df = merge_features_with_metadata(features_df, metadata_df)
        
        # 4. Validate required columns exist
        required_cols = [
            'participant_id', 'label', 
            'TTR', 'MTLD', 'Noun_Verb_Ratio', 
            'Mean_Clause_Length', 'T_Unit_Count', 
            'Sentence_Embedding_Cosine_Similarity'
        ]
        missing = [c for c in required_cols if c not in final_df.columns]
        if missing:
            logger.error(f"Missing required columns in final output: {missing}")
            raise ValueError(f"Feature matrix missing required columns: {missing}")
        
        # 5. Save to data/processed/features.csv
        output_path = get_path("processed", "features.csv")
        save_feature_matrix(final_df, output_path)
        
        # 6. Generate derivation log
        log_path = get_path("processed", "features.derivation.log")
        generate_derivation_log(
            source_files=["data/interim/cleaned_adress.csv"],
            output_file=str(output_path),
            transformation="Feature extraction and merging",
            log_path=log_path
        )
        
        # 7. Update metadata
        update_metadata(status="completed")
        
        logger.info("T025 completed successfully.")
        
    except Exception as e:
        logger.error(f"T025 failed: {e}")
        update_metadata(status="failed")
        raise

if __name__ == "__main__":
    main()