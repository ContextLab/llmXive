def load_interim_data() -> pd.DataFrame:
    """
    Load the raw transcripts that have been cleaned and filtered by T013-T015.
    Expects the output of the ingestion pipeline to be in data/interim/stage_filtered.csv
    (or similar intermediate file if T015 output is distinct).
    
    Based on the task flow:
    T012 -> T013 (clean) -> T014 (filter) -> T015 (metadata) -> T016 (finalize)
    
    We assume T015 produces a consolidated CSV in data/interim/ with all necessary columns.
    If T015 hasn't been run yet, this function will fail loudly as expected.
    """
    # Determine the input file. Based on the flow, T015 likely outputs to a temp or 
    # intermediate location, or overwrites the previous stage. 
    # We will look for the most recent processed file or a specific name.
    # Let's assume T015 outputs to 'data/interim/stage_metadata.csv' or similar.
    # To be robust, we check for the existence of the expected input.
    
    # Since T015 is marked completed, we assume it produced a file.
    # We will define the input path as the output of the previous step.
    # If T015 output is not standardized, we might need to infer.
    # Let's assume the ingestion pipeline (main) writes to 'data/interim/processed_adress.csv'
    # or similar. Let's look for a file that contains 'metadata' or 'cleaned' in the name.
    
    # For this task, we assume the input is 'data/interim/stage_filtered_metadata.csv'
    # or the ingestion main function outputs to a specific file.
    # Let's check the ingestion.py main to see what it outputs. 
    # Since we can't see the content of ingestion.py's main output path, 
    # we will assume a standard naming convention: 'data/interim/ingestion_output.csv'
    # or we will look for the file generated by T015.
    
    # Given the dependency T015 (metadata extraction), let's assume T015 writes to:
    input_path = get_path("data/interim/stage_metadata.csv")
    
    if not os.path.exists(input_path):
        # Fallback: check if ingestion main wrote to a different location
        # Common pattern: data/interim/cleaned_adress_raw.csv
        alt_path = get_path("data/interim/cleaned_adress_raw.csv")
        if os.path.exists(alt_path):
            input_path = alt_path
        else:
            raise FileNotFoundError(
                f"Input file for derivation not found. Expected {get_path('data/interim/stage_metadata.csv')} "
                f"or {get_path('data/interim/cleaned_adress_raw.csv')}. "
                f"Ensure T015 (metadata extraction) has been run successfully."
            )
    
    logger.info(f"Loading intermediate data from {input_path}")
    df = pd.read_csv(input_path)
    
    # Basic validation
    required_cols = ['participant_id', 'label', 'text']
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in input data: {missing_cols}")
    
    return df


def generate_derivation_log(df: pd.DataFrame, output_path: Path) -> Dict[str, Any]:
    """
    Generate a derivation log documenting the transformation steps.
    """
    log_entry = {
        "source_file": str(output_path.parent / "stage_metadata.csv"), # Assumed source
        "target_file": str(output_path),
        "timestamp": pd.Timestamp.now().isoformat(),
        "record_counts": {
            "input": len(df),
            "output": len(df)
        },
        "columns": list(df.columns),
        "label_distribution": df['label'].value_counts().to_dict(),
        "steps_applied": [
            "T012: ADReSS Download & Verification",
            "T013: Text Cleaning (non-verbal removal, UTF-8)",
            "T014: Filtering (<50 words, missing labels)",
            "T015: Metadata Extraction (status parsing, reason codes)",
            "T016: Finalization (Schema validation, CSV export)"
        ],
        "data_quality_checks": {
            "null_labels": int(df['label'].isna().sum()),
            "null_text": int(df['text'].isna().sum()),
            "empty_text": int((df['text'].str.strip() == "").sum()),
            "short_text": int((df['text'].str.len() < 50).sum()) # Should be 0 due to T014
        }
    }
    
    # Write log
    log_path = output_path.parent / "derivation_log.json"
    # Use simple json for now, or yaml if preferred. tasks.md says "derivation log", usually JSON/YAML.
    import json
    with open(log_path, 'w', encoding='utf-8') as f:
        json.dump(log_entry, f, indent=2, default=str)
    
    logger.info(f"Derivation log written to {log_path}")
    return log_entry


def finalize_dataset(df: pd.DataFrame) -> pd.DataFrame:
    """
    Perform final validation and formatting before saving.
    """
    # Ensure strict types
    df['participant_id'] = df['participant_id'].astype(str)
    df['label'] = df['label'].astype(str)
    df['text'] = df['text'].astype(str)
    
    # Drop duplicates based on participant_id if any
    initial_count = len(df)
    df = df.drop_duplicates(subset=['participant_id'], keep='first')
    dropped = initial_count - len(df)
    if dropped > 0:
        logger.warning(f"Dropped {dropped} duplicate participant records.")
    
    # Sort by participant_id for consistency
    df = df.sort_values('participant_id').reset_index(drop=True)
    
    return df


def main():
    """
    Main entry point for T016: Create intermediate cleaned dataset.
    """
    logger.info("Starting T016: Creating intermediate cleaned dataset (data/interim/cleaned_adress.csv)")
    
    # 1. Load data from previous stage
    try:
        df = load_interim_data()
    except FileNotFoundError as e:
        logger.error(str(e))
        raise
    
    # 2. Finalize
    df_clean = finalize_dataset(df)
    
    # 3. Generate derivation log
    output_dir = get_path("data/interim")
    ensure_dirs([output_dir])
    output_path = Path(output_dir) / "cleaned_adress.csv"
    
    log = generate_derivation_log(df_clean, output_path)
    
    # 4. Save CSV
    df_clean.to_csv(output_path, index=False, encoding='utf-8')
    
    logger.info(f"T016 Complete. Saved {len(df_clean)} records to {output_path}")
    logger.info(f"Label distribution: {log['label_distribution']}")
    
    return output_path


if __name__ == "__main__":
    # Setup logging if not already done (in case run standalone)
    from utils import setup_logging
    setup_logging()
    main()
