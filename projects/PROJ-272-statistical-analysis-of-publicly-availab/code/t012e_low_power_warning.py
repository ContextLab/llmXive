"""
Task T012e: Low Power Warning

Validates dataset size by counting participants per group.
Logs a WARNING if any group has < 15 participants.
Saves partial metadata to data/results/metadata_partial_e.json.
Does NOT block execution.
"""
import json
import logging
from pathlib import Path
import pandas as pd
from config import get_path

# Configure logging to ensure warnings are visible
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def validate_dataset_size(input_csv_path: Path) -> dict:
    """
    Counts participants per group from the cleaned dataset.
    Logs warnings for low sample sizes and returns group counts.
    
    Args:
        input_csv_path: Path to the cleaned transcripts CSV.
        
    Returns:
        Dictionary with 'low_power' boolean and 'group_counts'.
    """
    if not input_csv_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_csv_path}")

    df = pd.read_csv(input_csv_path)
    
    # Ensure label column exists and is not null for counting
    if 'label' not in df.columns:
        raise ValueError("Input CSV must contain a 'label' column.")
    
    # Count non-null labels per group
    # Assuming 'label' contains the group names: Control, MCI, AD
    group_counts = df['label'].value_counts().to_dict()
    
    # Ensure all expected groups are present in the dict (default to 0 if missing)
    expected_groups = ['Control', 'MCI', 'AD']
    for group in expected_groups:
        if group not in group_counts:
            group_counts[group] = 0

    low_power = False
    warnings_logged = []

    for group, count in group_counts.items():
        if count < 15:
            warning_msg = f"Low sample size in group {group}: {count}"
            logger.warning(warning_msg)
            warnings_logged.append(warning_msg)
            low_power = True

    result = {
        "low_power": low_power,
        "group_counts": group_counts
    }
    
    return result

def save_metadata(result: dict, output_path: Path) -> None:
    """
    Saves the validation result to the specified JSON file.
    
    Args:
        result: The dictionary containing low_power and group_counts.
        output_path: Path to the output JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(result, f, indent=2)
    logger.info(f"Metadata saved to {output_path}")

def main():
    """
    Main entry point for Task T012e.
    Reads the cleaned dataset, validates group sizes, logs warnings, and saves metadata.
    """
    # Define paths based on project structure
    # The input is expected to be the cleaned transcripts CSV generated by T016/T013
    input_file = get_path("data/interim/cleaned_transcripts.csv")
    output_file = get_path("data/results/metadata_partial_e.json")

    logger.info(f"Starting T012e: Validating dataset size from {input_file}")
    
    try:
        result = validate_dataset_size(input_file)
        save_metadata(result, output_file)
        logger.info("T012e completed successfully.")
    except FileNotFoundError as e:
        logger.error(f"Input file missing: {e}")
        # Re-raise to fail loudly if dependencies are not met
        raise
    except Exception as e:
        logger.error(f"Error during validation: {e}")
        raise

if __name__ == "__main__":
    main()