import os
import sys
import logging
import csv
from pathlib import Path
from typing import List, Dict, Any, Optional

from utils.config import get_paths
from utils.logging_config import get_logger

logger = get_logger(__name__)

def load_processed_data(filepath: str) -> List[Dict[str, Any]]:
    """
    Load processed data from a CSV file.
    
    Args:
        filepath: Path to the CSV file.
        
    Returns:
        List of dictionaries representing rows in the CSV.
    """
    data = []
    try:
        with open(filepath, 'r', newline='', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            for row in reader:
                data.append(row)
        logger.info(f"Loaded {len(data)} rows from {filepath}")
    except FileNotFoundError:
        logger.error(f"File not found: {filepath}")
        raise
    except Exception as e:
        logger.error(f"Error reading file {filepath}: {e}")
        raise
    return data

def validate_target_no_missing(data: List[Dict[str, Any]], target_column: str = "shear_modulus_GPa") -> Dict[str, Any]:
    """
    Validate that the target variable contains no missing values.
    
    Args:
        data: List of dictionaries representing rows in the processed data.
        target_column: Name of the target column to validate.
        
    Returns:
        Dictionary containing validation results:
            - valid: bool, True if no missing values found.
            - missing_count: int, number of missing values found.
            - missing_indices: List[int], indices of rows with missing values.
            - message: str, descriptive message.
    """
    missing_indices = []
    missing_count = 0
    
    for i, row in enumerate(data):
        value = row.get(target_column)
        if value is None or value == '' or (isinstance(value, float) and str(value) == 'nan'):
            missing_count += 1
            missing_indices.append(i)
    
    valid = missing_count == 0
    message = (
        f"Validation passed: No missing values in '{target_column}'."
        if valid else
        f"Validation failed: Found {missing_count} missing values in '{target_column}' at indices {missing_indices}."
    )
    
    logger.info(message)
    
    return {
        "valid": valid,
        "missing_count": missing_count,
        "missing_indices": missing_indices,
        "message": message
    }

def save_validation_report(validation_result: Dict[str, Any], output_path: str) -> None:
    """
    Save the validation result to a JSON file.
    
    Args:
        validation_result: Dictionary containing validation results.
        output_path: Path to save the JSON report.
    """
    import json
    try:
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(validation_result, f, indent=2)
        logger.info(f"Validation report saved to {output_path}")
    except Exception as e:
        logger.error(f"Error saving validation report to {output_path}: {e}")
        raise

def main():
    """
    Main function to run the target validation.
    Expects the processed data file path as an argument or uses default.
    """
    paths = get_paths()
    # Default to the processed data file generated by the pipeline
    input_file = paths["data_processed"] / "bmg_processed.csv"
    output_file = paths["data_artifacts"] / "target_validation_report.json"
    
    # Allow override via command line argument
    if len(sys.argv) > 1:
        input_file = Path(sys.argv[1])
    if len(sys.argv) > 2:
        output_file = Path(sys.argv[2])
        
    logger.info(f"Validating target variable in {input_file}")
    
    if not input_file.exists():
        logger.error(f"Input file does not exist: {input_file}")
        sys.exit(1)
        
    data = load_processed_data(str(input_file))
    
    if not data:
        logger.warning("No data found in input file.")
        sys.exit(0)
        
    result = validate_target_no_missing(data)
    
    save_validation_report(result, str(output_file))
    
    if not result["valid"]:
        logger.error("Target variable contains missing values. Pipeline cannot proceed.")
        sys.exit(1)
    else:
        logger.info("Target validation successful. Pipeline can proceed.")
        sys.exit(0)

if __name__ == "__main__":
    main()
