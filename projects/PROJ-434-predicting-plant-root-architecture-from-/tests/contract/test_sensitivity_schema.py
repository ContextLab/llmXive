"""
Contract tests for the sensitivity analysis report schema (T026).

This module validates the structure and content of the sensitivity report
generated by `code/modeling/sensitivity.py` (Task T029).

It ensures compliance with the specification:
- Presence of required sections: '## Threshold Stability' and '## Justification'.
- Correct table schema for the stability table.
- Citation of a verified community standard in the justification.
- Associational framing of findings (FR-006).
"""

import json
import os
import re
import pytest
from pathlib import Path

# Paths relative to project root
REPORT_PATH = Path("artifacts/sensitivity_report.md")
FEATURE_IMPORTANCE_PATH = Path("artifacts/feature_importance.csv")
SC002_STATUS_PATH = Path("artifacts/sc002_status.json")

# Required sections
REQUIRED_SECTIONS = ["## Threshold Stability", "## Justification"]

# Required table columns
REQUIRED_TABLE_COLUMNS = ["threshold", "top_feature", "rank_2", "rank_3", "stable"]


@pytest.mark.contract
class TestSensitivityReportSchema:
    """Contract tests for the sensitivity analysis report."""

    @pytest.fixture(scope="class")
    def report_content(self):
        """Load the sensitivity report content."""
        if not REPORT_PATH.exists():
            pytest.skip(f"Report not found at {REPORT_PATH}. Run T029 first.")
        with open(REPORT_PATH, "r", encoding="utf-8") as f:
            return f.read()

    @pytest.fixture(scope="class")
    def feature_importance_data(self):
        """Load feature importance data to validate against the report."""
        if not FEATURE_IMPORTANCE_PATH.exists():
            pytest.skip(f"Feature importance data not found at {FEATURE_IMPORTANCE_PATH}. Run T025/T027 first.")
        import pandas as pd
        return pd.read_csv(FEATURE_IMPORTANCE_PATH)

    def test_report_file_exists(self, report_content):
        """Verify the report file exists and is not empty."""
        assert report_content is not None
        assert len(report_content) > 0

    def test_required_sections_present(self, report_content):
        """Verify all required sections are present in the report."""
        for section in REQUIRED_SECTIONS:
            assert section in report_content, f"Missing required section: {section}"

    def test_threshold_stability_table_schema(self, report_content):
        """
        Verify the 'Threshold Stability' section contains a table with the correct columns.
        The table is expected to be a Markdown table.
        """
        # Extract the section content
        section_match = re.search(
            r"## Threshold Stability\s*(.*?)(?=## |$)",
            report_content,
            re.DOTALL
        )
        assert section_match is not None, "Could not extract 'Threshold Stability' section"
        section_content = section_match.group(1)

        # Check for Markdown table header
        # We expect a header row containing the required columns
        header_pattern = r"\|\s*" + r"\s*\|\s*".join(REQUIRED_TABLE_COLUMNS) + r"\s*\|"
        assert re.search(header_pattern, section_content, re.IGNORECASE), (
            f"Table header in 'Threshold Stability' section does not match required columns: {REQUIRED_TABLE_COLUMNS}"
        )

        # Verify the separator row exists (---)
        separator_pattern = r"\|\s*---+\s*\|"
        assert re.search(separator_pattern, section_content), (
            "Markdown table separator row not found in 'Threshold Stability' section"
        )

        # Verify at least one data row exists
        data_row_pattern = r"\|\s*[^|]+\s*\|\s*[^|]+\s*\|\s*[^|]+\s*\|\s*[^|]+\s*\|\s*[^|]+\s*\|"
        assert re.search(data_row_pattern, section_content), (
            "No data rows found in 'Threshold Stability' table"
        )

    def test_justification_cites_standard(self, report_content):
        """
        Verify the 'Justification' section cites a verified community standard.
        We look for keywords like 'standard', 'literature', 'community', 'threshold',
        or specific citations (e.g., 'Benjamini-Hochberg', 'p < 0.05', 'FDR').
        """
        section_match = re.search(
            r"## Justification\s*(.*?)(?=## |$)",
            report_content,
            re.DOTALL
        )
        assert section_match is not None, "Could not extract 'Justification' section"
        section_content = section_match.group(1).lower()

        # Check for keywords indicating a standard is cited
        citation_keywords = [
            "standard", "literature", "community", "threshold",
            "benjamini-hochberg", "fdr", "false discovery",
            "bonferroni", "significance level", "p < 0.05", "p < 0.01"
        ]

        found_citation = any(keyword in section_content for keyword in citation_keywords)
        assert found_citation, (
            "The 'Justification' section must cite a verified community standard or literature reference "
            "for the significance level used (e.g., Benjamini-Hochberg, FDR, or standard p < 0.05)."
        )

    def test_associational_framing(self, report_content):
        """
        Verify findings are framed as associational (FR-006) and not causal.
        We check for the absence of causal language like 'causes', 'causation',
        'determines', 'effect of', 'impact on' (in a causal sense).
        """
        # Causal language to avoid
        causal_terms = [
            r"\bcauses?\b", r"\bcausation\b", r"\bdetermines?\b",
            r"\beffect of\b", r"\bimpact on\b", r"\bleads to\b",
            r"\bresults in\b", r"\binfluences\b" # 'influences' can be ambiguous but often implies causality
        ]

        # We allow 'associated with', 'correlated with', 'predicts' (in a statistical sense)
        # But we flag strong causal verbs.
        for term in causal_terms:
            if re.search(term, report_content, re.IGNORECASE):
                # Allow some exceptions if it's in a quote or specific context, but generally fail
                # For strictness, we fail if these appear in the main body of findings.
                # A simple heuristic: if found, assume it violates FR-006 unless in a specific context.
                # Given the strictness of FR-006, we fail if these appear.
                pytest.fail(
                    f"Found causal language '{term}' in the report. "
                    "Findings must be framed as associational (FR-006), not causal."
                )

    def test_feature_importance_data_consistency(self, report_content, feature_importance_data):
        """
        Verify that the top features mentioned in the report match the data in feature_importance.csv.
        This is a cross-validation between the report and the source data.
        """
        # Extract top features from the table in the report
        # We look for the 'top_feature' column values
        table_section = re.search(
            r"## Threshold Stability\s*(.*?)(?=## |$)",
            report_content,
            re.DOTALL
        )
        if not table_section:
            pytest.skip("Could not extract table section for consistency check")

        table_text = table_section.group(1)
        # Parse the table rows (skip header and separator)
        rows = [
            line.strip().split("|")
            for line in table_text.strip().split("\n")
            if line.strip() and not line.strip().startswith("|---") and not line.strip().startswith("| ")
        ]

        if not rows:
            pytest.skip("No data rows found in the table for consistency check")

        report_features = set()
        for row in rows:
            if len(row) >= 2:
                # The second column (index 1) is 'top_feature' after stripping pipes
                # The split might leave empty strings at start/end
                clean_row = [x.strip() for x in row if x.strip()]
                if len(clean_row) >= 2:
                    report_features.add(clean_row[1])

        # Check if these features exist in the CSV
        csv_features = set(feature_importance_data['feature_name'].astype(str).str.strip())

        # All features in the report must exist in the CSV
        missing_features = report_features - csv_features
        assert not missing_features, (
            f"Features found in the report but missing in feature_importance.csv: {missing_features}"
        )

    def test_sc002_status_consistency(self, report_content):
        """
        Verify that the report mentions the SC-002 status if it is relevant.
        If SC-002 failed, the report should ideally reflect that or be consistent.
        This is a soft check for consistency.
        """
        if not SC002_STATUS_PATH.exists():
            pytest.skip("SC-002 status file not found")

        with open(SC002_STATUS_PATH, "r", encoding="utf-8") as f:
            sc002_data = json.load(f)

        # If SC-002 failed, the report should not claim success without qualification
        if not sc002_data.get("pass", True):
            # The report should mention the failure or the condition
            # We check if the report mentions 'SC-002' or 'success criterion'
            # This is a soft check, as the report might focus on sensitivity regardless.
            # However, if the model failed the primary criterion, the sensitivity analysis
            # on that model's importance might be moot.
            # We just ensure the report doesn't claim 'success' in a way that contradicts the status.
            if "success" in report_content.lower() and "sc-002" in report_content.lower():
                # If it mentions both, it should be nuanced
                pass # For now, we just ensure it exists. A more complex check would be needed.

if __name__ == "__main__":
    pytest.main([__file__, "-v"])