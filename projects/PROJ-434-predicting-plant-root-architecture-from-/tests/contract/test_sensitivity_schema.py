"""
Contract test for sensitivity report schema.

This test validates that the sensitivity analysis report generated by
code/modeling/sensitivity.py adheres to the expected schema structure.

It checks:
1. The presence of required sections (Threshold Stability, Justification).
2. The structure of the stability table (columns: threshold, top_3_features, stability_score).
3. The presence of the required citation in the Justification section.
4. The framing of findings as associational (FR-006).
"""
import os
import json
import re
import pytest
from pathlib import Path

# Expected schema definition
SENSITIVITY_REPORT_SCHEMA = {
    "required_sections": [
        "## Threshold Stability",
        "## Justification"
    ],
    "stability_table_columns": [
        "threshold",
        "top_3_features",
        "stability_score"
    ],
    "required_citation": "0.05 chosen based on typical significance levels in ecological regression",
    "associational_keywords": [
        "association",
        "correlation",
        "predictive",
        "does not imply causation",
        "observational"
    ]
}


def get_report_path():
    """Get the path to the sensitivity report."""
    return Path("artifacts/sensitivity_report.md")


def test_report_file_exists():
    """Test that the sensitivity report file exists."""
    report_path = get_report_path()
    assert report_path.exists(), f"Sensitivity report not found at {report_path}"


def test_report_has_required_sections():
    """Test that the report contains all required sections."""
    report_path = get_report_path()
    with open(report_path, 'r', encoding='utf-8') as f:
        content = f.read()

    for section in SENSITIVITY_REPORT_SCHEMA["required_sections"]:
        assert section in content, f"Missing required section: {section}"


def test_stability_table_structure():
    """Test that the stability table has the correct structure."""
    report_path = get_report_path()
    with open(report_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Extract the table under "## Threshold Stability"
    threshold_section_match = re.search(
        r'## Threshold Stability\s*\n(.*?)(?=\n## |\Z)',
        content,
        re.DOTALL
    )
    assert threshold_section_match, "Could not find Threshold Stability section"

    table_content = threshold_section_match.group(1)

    # Check for table headers
    headers = SENSITIVITY_REPORT_SCHEMA["stability_table_columns"]
    header_row = "| " + " | ".join(headers) + " |"
    assert header_row in table_content, f"Table headers not found. Expected: {header_row}"

    # Check for separator row (markdown table syntax)
    separator_row = "| " + " | ".join(["---"] * len(headers)) + " |"
    assert separator_row in table_content, "Table separator row not found"

    # Check for at least one data row
    data_rows = [
        line for line in table_content.split('\n')
        if line.strip().startswith('|') and '---' not in line and '|' in line
    ]
    assert len(data_rows) > 0, "No data rows found in stability table"


def test_citation_present():
    """Test that the required citation is present in the Justification section."""
    report_path = get_report_path()
    with open(report_path, 'r', encoding='utf-8') as f:
        content = f.read()

    justification_match = re.search(
        r'## Justification\s*\n(.*?)(?=\n## |\Z)',
        content,
        re.DOTALL
    )
    assert justification_match, "Could not find Justification section"

    justification_content = justification_match.group(1)
    citation = SENSITIVITY_REPORT_SCHEMA["required_citation"]
    assert citation in justification_content, f"Required citation not found: {citation}"


def test_findings_framed_as_associational():
    """Test that findings are framed as associational (FR-006)."""
    report_path = get_report_path()
    with open(report_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Check for at least one associational keyword
    found_keywords = []
    for keyword in SENSITIVITY_REPORT_SCHEMA["associational_keywords"]:
        if keyword.lower() in content.lower():
            found_keywords.append(keyword)

    assert len(found_keywords) > 0, (
        f"No associational language found. "
        f"Expected at least one of: {SENSITIVITY_REPORT_SCHEMA['associational_keywords']}"
    )

    # Specifically check for "does not imply causation" or similar cautionary language
    cautionary_patterns = [
        r"does not imply causation",
        r"associational only",
        r"not causal",
        r"correlation does not imply causation"
    ]
    found_caution = any(re.search(pattern, content, re.IGNORECASE) for pattern in cautionary_patterns)
    assert found_caution, (
        "Report should explicitly state that findings are associational and not causal. "
        "Add a cautionary statement like 'does not imply causation'."
    )


def test_threshold_values_are_valid():
    """Test that threshold values in the stability table are valid p-values."""
    report_path = get_report_path()
    with open(report_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Extract the table content
    threshold_section_match = re.search(
        r'## Threshold Stability\s*\n(.*?)(?=\n## |\Z)',
        content,
        re.DOTALL
    )
    assert threshold_section_match, "Could not find Threshold Stability section"

    table_content = threshold_section_match.group(1)
    lines = table_content.split('\n')

    # Find the header row to get the index of the threshold column
    header_line = None
    for line in lines:
        if 'threshold' in line.lower():
            header_line = line
            break

    assert header_line, "Could not identify threshold column in table header"

    # Parse the header to get column index
    headers = [h.strip() for h in header_line.split('|') if h.strip()]
    try:
        threshold_idx = headers.index('threshold')
    except ValueError:
        pytest.fail("Could not find 'threshold' column in table header")

    # Validate each data row
    for line in lines:
        if not line.strip().startswith('|') or '---' in line:
            continue

        cells = [c.strip() for c in line.split('|') if c.strip()]
        if len(cells) <= threshold_idx:
            continue  # Skip malformed rows

        threshold_str = cells[threshold_idx]
        try:
            threshold_val = float(threshold_str)
            assert 0.0 <= threshold_val <= 1.0, (
                f"Invalid threshold value: {threshold_val}. "
                f"Must be between 0.0 and 1.0."
            )
        except ValueError:
            pytest.fail(f"Threshold value is not a valid number: {threshold_str}")


def test_feature_names_are_consistent():
    """Test that feature names in the stability table match expected soil predictors."""
    report_path = get_report_path()
    with open(report_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Expected soil predictors based on the project
    expected_features = [
        "N", "P", "K", "pH",
        "N_mg_kg", "P_mg_kg", "K_mg_kg", "pH_value"
    ]

    # Extract all feature names from the table
    # Look for patterns like "N, P, K" or "N_mg_kg, P_mg_kg, K_mg_kg"
    feature_pattern = r'([A-Z]+(?:_[a-z]+)?)'
    found_features = set(re.findall(feature_pattern, content))

    # Check if at least some expected features are present
    matching_features = found_features.intersection(set(expected_features))
    assert len(matching_features) > 0, (
        f"Expected to find at least one of {expected_features} in the stability table. "
        f"Found: {found_features}"
    )


if __name__ == "__main__":
    pytest.main([__file__, "-v"])