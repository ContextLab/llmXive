"""
Contract test for model output schema (T018).

This test verifies that the model metrics output generated by code/modeling/train.py
adheres to the schema defined in specs/001-predict-root-architecture/contracts/model_output.schema.yaml.

It checks:
1. File existence at artifacts/model_metrics.json
2. Presence of required top-level keys
3. Correct data types for numeric fields
4. Structure of nested dictionaries (per_target_metrics)
"""
import os
import json
import pytest
from pathlib import Path
from typing import Any, Dict

# Project root is assumed to be the parent of 'tests'
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
METRICS_PATH = PROJECT_ROOT / "artifacts" / "model_metrics.json"
SCHEMA_PATH = PROJECT_ROOT / "specs" / "001-predict-root-architecture" / "contracts" / "model_output.schema.yaml"

REQUIRED_TOP_LEVEL_KEYS = {
    "mean_r2",
    "mean_rmse",
    "loso_r2_sd",
    "spatial_cv_r2_sd",
    "per_target_metrics"
}

REQUIRED_SCALAR_TYPES = {
    "mean_r2": (int, float),
    "mean_rmse": (int, float),
    "loso_r2_sd": (int, float),
    "spatial_cv_r2_sd": (int, float),
}

REQUIRED_PER_TARGET_KEYS = {
    "mean_r2",
    "mean_rmse",
    "permutation_p_value",
    "baseline_r2",
    "delta_r2",
    "significance_pass"
}

def load_schema() -> Dict[str, Any]:
    """Load the schema definition from the YAML file."""
    import yaml
    if not SCHEMA_PATH.exists():
        pytest.fail(f"Schema file not found: {SCHEMA_PATH}")
    with open(SCHEMA_PATH, "r") as f:
        return yaml.safe_load(f)

def load_metrics() -> Dict[str, Any]:
    """Load the generated model metrics JSON."""
    if not METRICS_PATH.exists():
        pytest.fail(f"Model metrics file not found: {METRICS_PATH}. "
                    "Ensure code/modeling/train.py has been executed to generate artifacts/model_metrics.json.")
    with open(METRICS_PATH, "r") as f:
        return json.load(f)

@pytest.fixture
def schema_definition():
    return load_schema()

@pytest.fixture
def metrics_data():
    return load_metrics()

class TestModelOutputSchema:
    """Contract tests for model_output.json schema compliance."""

    def test_file_exists(self, metrics_data):
        """Verify the metrics file was generated."""
        assert metrics_data is not None, "Metrics file is empty or invalid JSON"

    def test_required_top_level_keys_present(self, metrics_data):
        """Verify all required top-level keys exist."""
        missing_keys = REQUIRED_TOP_LEVEL_KEYS - set(metrics_data.keys())
        assert not missing_keys, f"Missing required top-level keys: {missing_keys}"

    def test_scalar_types_correct(self, metrics_data):
        """Verify numeric fields are numbers."""
        for key, expected_type in REQUIRED_SCALAR_TYPES.items():
            value = metrics_data.get(key)
            assert isinstance(value, expected_type), (
                f"Field '{key}' has type {type(value).__name__}, "
                f"expected {expected_type.__name__}"
            )

    def test_per_target_metrics_structure(self, metrics_data):
        """Verify the structure of per_target_metrics."""
        per_target = metrics_data.get("per_target_metrics")
        assert isinstance(per_target, dict), "per_target_metrics must be a dictionary"
        
        # Check that we have at least one target (e.g., 'max_depth' or 'root_length')
        # The schema implies specific target names, but we check for generic structure first.
        # We expect keys to be target variable names (e.g., 'max_depth', 'root_length')
        assert len(per_target) > 0, "per_target_metrics should contain at least one target"

        for target_name, target_metrics in per_target.items():
            assert isinstance(target_metrics, dict), (
                f"Metrics for target '{target_name}' must be a dictionary"
            )
            
            missing_target_keys = REQUIRED_PER_TARGET_KEYS - set(target_metrics.keys())
            assert not missing_target_keys, (
                f"Target '{target_name}' missing keys: {missing_target_keys}"
            )

    def test_per_target_scalar_types(self, metrics_data):
        """Verify numeric fields within per_target_metrics are numbers."""
        per_target = metrics_data.get("per_target_metrics", {})
        
        numeric_fields = ["mean_r2", "mean_rmse", "permutation_p_value", "baseline_r2", "delta_r2"]
        
        for target_name, target_metrics in per_target.items():
            for field in numeric_fields:
                if field in target_metrics:
                    value = target_metrics[field]
                    assert isinstance(value, (int, float)), (
                        f"Target '{target_name}', field '{field}' has type {type(value).__name__}, "
                        f"expected number"
                    )

    def test_significance_pass_boolean(self, metrics_data):
        """Verify significance_pass is a boolean."""
        per_target = metrics_data.get("per_target_metrics", {})
        
        for target_name, target_metrics in per_target.items():
            if "significance_pass" in target_metrics:
                val = target_metrics["significance_pass"]
                assert isinstance(val, bool), (
                    f"Target '{target_name}', field 'significance_pass' must be boolean, "
                    f"got {type(val).__name__}"
                )

    def test_schema_compliance(self, schema_definition, metrics_data):
        """
        Verify the metrics structure matches the declared schema definition.
        This ensures the code output aligns with the contract specification.
        """
        # Basic structural check against schema description if available
        if "properties" in schema_definition:
            schema_props = schema_definition["properties"]
            for key in REQUIRED_TOP_LEVEL_KEYS:
                if key in schema_props:
                    # If schema defines type, check it (basic check)
                    schema_type = schema_props[key].get("type")
                    if schema_type == "number":
                        assert isinstance(metrics_data.get(key), (int, float)), (
                            f"Schema violation: {key} should be number"
                        )
                    elif schema_type == "object":
                        assert isinstance(metrics_data.get(key), dict), (
                            f"Schema violation: {key} should be object"
                        )