def load_json_file(filepath: Path) -> Dict[str, Any]:
    """Load and parse a JSON file."""
    if not filepath.exists():
        raise FileNotFoundError(f"Required file not found: {filepath}")
    
    with open(filepath, 'r') as f:
        return json.load(f)

def test_required_artifacts_exist():
    """Test that all required model output files exist."""
    missing_files = []
    for filename in REQUIRED_FILES:
        filepath = ARTIFACTS_DIR / filename
        if not filepath.exists():
            missing_files.append(filename)
    
    assert len(missing_files) == 0, f"Missing required artifacts: {missing_files}"

def test_model_metrics_schema():
    """
    Validate model_metrics.json schema.
    
    Expected schema (from T024):
    {
      "mean_r2": float,
      "mean_rmse": float,
      "loso_r2_sd": float,
      "per_target_metrics": {
        "target_name": {
          "r2": float,
          "rmse": float,
          ...
        }
      }
    }
    """
    filepath = ARTIFACTS_DIR / "model_metrics.json"
    if not filepath.exists():
        pytest.skip("model_metrics.json not yet generated (T024)")
    
    data = load_json_file(filepath)
    
    # Check top-level required fields
    required_fields = ["mean_r2", "mean_rmse", "loso_r2_sd", "per_target_metrics"]
    for field in required_fields:
        assert field in data, f"Missing required field in model_metrics.json: {field}"
    
    # Validate types
    assert isinstance(data["mean_r2"], (int, float)), "mean_r2 must be numeric"
    assert isinstance(data["mean_rmse"], (int, float)), "mean_rmse must be numeric"
    assert isinstance(data["loso_r2_sd"], (int, float)), "loso_r2_sd must be numeric"
    assert isinstance(data["per_target_metrics"], dict), "per_target_metrics must be a dictionary"
    
    # Validate per_target_metrics structure
    for target, metrics in data["per_target_metrics"].items():
        assert "r2" in metrics, f"Missing 'r2' for target {target}"
        assert "rmse" in metrics, f"Missing 'rmse' for target {target}"
        assert isinstance(metrics["r2"], (int, float)), f"r2 for {target} must be numeric"
        assert isinstance(metrics["rmse"], (int, float)), f"rmse for {target} must be numeric"

