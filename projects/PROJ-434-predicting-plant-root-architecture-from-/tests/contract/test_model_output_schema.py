def test_permutation_distributions_schema():
    """
    Validate permutation_distributions.json schema.
    
    Expected structure (from T022):
    {
      "model_a": [r2_scores...],
      "model_b": [r2_scores...]
    }
    Must contain 1000 iterations.
    """
    filepath = ARTIFACTS_DIR / "permutation_distributions.json"
    if not filepath.exists():
        pytest.skip("permutation_distributions.json not yet generated (T022)")
    
    data = load_json_file(filepath)
    
    # Check required keys
    assert "model_a" in data, "Missing 'model_a' in permutation_distributions.json"
    assert "model_b" in data, "Missing 'model_b' in permutation_distributions.json"
    
    # Validate types and length
    assert isinstance(data["model_a"], list), "model_a must be a list"
    assert isinstance(data["model_b"], list), "model_b must be a list"
    assert len(data["model_a"]) == 1000, f"model_a must have 1000 iterations, got {len(data['model_a'])}"
    assert len(data["model_b"]) == 1000, f"model_b must have 1000 iterations, got {len(data['model_b'])}"
    
    # Validate that all values are numeric
    for i, val in enumerate(data["model_a"]):
        assert isinstance(val, (int, float)), f"model_a[{i}] must be numeric"
    for i, val in enumerate(data["model_b"]):
        assert isinstance(val, (int, float)), f"model_b[{i}] must be numeric"

def test_feature_importance_csv_schema():
    """
    Validate feature_importance.csv schema.
    
    Expected columns (from T025, T027):
    - feature_name: string
    - importance_score: float
    - p_value: float (added by T027)
    """
    filepath = ARTIFACTS_DIR / "feature_importance.csv"
    if not filepath.exists():
        pytest.skip("feature_importance.csv not yet generated (T025)")
    
    import pandas as pd
    df = pd.read_csv(filepath)
    
    # Check required columns
    required_columns = ["feature_name", "importance_score"]
    for col in required_columns:
        assert col in df.columns, f"Missing required column in feature_importance.csv: {col}"
    
    # Check data types
    assert df["feature_name"].dtype == object or str(df["feature_name"].dtype) == "string", \
        "feature_name must be string type"
    assert pd.api.types.is_numeric_dtype(df["importance_score"]), \
        "importance_score must be numeric"
    
    # p_value is added by T027, so it might not exist yet
    if "p_value" in df.columns:
        assert pd.api.types.is_numeric_dtype(df["p_value"]), \
            "p_value must be numeric"

