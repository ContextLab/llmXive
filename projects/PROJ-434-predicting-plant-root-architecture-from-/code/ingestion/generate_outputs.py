import os
import sys
import logging
from pathlib import Path
from typing import Tuple, List, Dict, Any, Optional
import pandas as pd
from ingestion.logging_utils import log_species_exclusion_summary

# Ensure we can import from the project root if run as script
if 'code' not in sys.path:
    code_root = Path(__file__).resolve().parent.parent
    sys.path.insert(0, str(code_root))

def count_valid_observations(species_counts_path: Path) -> pd.DataFrame:
    """
    Reads the species_counts.csv generated by T015 and returns the DataFrame.
    """
    if not species_counts_path.exists():
        raise FileNotFoundError(f"Species counts file not found: {species_counts_path}")
    
    df = pd.read_csv(species_counts_path)
    return df

def generate_exclusion_summary(
    species_counts_path: Path,
    output_summary_path: Path,
    output_log_path: Path,
    min_observations: int = 10
) -> Tuple[pd.DataFrame, List[Dict[str, Any]]]:
    """
    Generates the excluded species summary CSV and the exclusion log.
    
    Logic:
    1. Read species_counts.csv (produced by T015).
    2. Filter for species with valid_count < min_observations.
    3. Create excluded_species_summary.csv with columns: species_name, observation_count, reason.
    4. Create species_exclusions.log with columns: species_name, reason, observation_count.
    5. Ensure output directories exist.
    """
    df = count_valid_observations(species_counts_path)
    
    # Ensure required columns exist
    required_cols = {'species_name', 'valid_count'}
    if not required_cols.issubset(df.columns):
        raise ValueError(f"Species counts file missing required columns. Found: {df.columns}, Expected: {required_cols}")
    
    # Filter for excluded species
    excluded_df = df[df['valid_count'] < min_observations].copy()
    
    # Prepare the summary DataFrame
    summary_df = excluded_df.rename(columns={'valid_count': 'observation_count'})
    summary_df['reason'] = f'observation_count < {min_observations}'
    
    # Select and order columns for summary
    summary_df = summary_df[['species_name', 'observation_count', 'reason']]
    
    # Prepare the log data (list of dicts for logging utility)
    log_data = []
    for _, row in summary_df.iterrows():
        log_data.append({
            'species_name': row['species_name'],
            'reason': row['reason'],
            'observation_count': row['observation_count']
        })
    
    # Ensure output directories exist
    output_summary_path.parent.mkdir(parents=True, exist_ok=True)
    output_log_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Write the summary CSV
    summary_df.to_csv(output_summary_path, index=False)
    logging.info(f"Written excluded species summary to {output_summary_path}")
    
    # Write the exclusion log using the utility
    log_species_exclusion_summary(output_log_path, log_data)
    logging.info(f"Written species exclusions log to {output_log_path}")
    
    return summary_df, log_data

def main():
    """
    Main entry point for T017.
    Reads species_counts.csv, filters species < 10 obs, writes summary CSV and log.
    """
    # Setup logging
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    # Define paths relative to project root (assuming code/ingestion is where this script lives)
    project_root = Path(__file__).resolve().parent.parent.parent
    species_counts_path = project_root / 'data' / 'processed' / 'species_counts.csv'
    output_summary_path = project_root / 'data' / 'processed' / 'excluded_species_summary.csv'
    output_log_path = project_root / 'data' / 'logs' / 'species_exclusions.log'
    
    try:
        logging.info(f"Starting T017: Generating exclusion summaries from {species_counts_path}")
        summary_df, log_data = generate_exclusion_summary(
            species_counts_path,
            output_summary_path,
            output_log_path,
            min_observations=10
        )
        
        if len(summary_df) > 0:
            logging.info(f"Excluded {len(summary_df)} species with < 10 observations.")
            logging.info(f"Summary columns: {list(summary_df.columns)}")
        else:
            logging.info("No species excluded based on observation count threshold.")
            
    except FileNotFoundError as e:
        logging.error(f"Required input file missing: {e}")
        sys.exit(1)
    except Exception as e:
        logging.error(f"Error during T017 execution: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
