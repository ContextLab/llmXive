# Configure logging for this module
logger = None

def _ensure_logger():
    global logger
    if logger is None:
        setup_logging()
        logger = get_logger("merge")
    return logger

def load_soil_data(coords_path: str) -> pd.DataFrame:
    """
    Load soil data from the processed CSV generated by soil_data.py.
    Validates that required columns exist.
    """
    _ensure_logger()
    path = Path(coords_path)
    if not path.exists():
        raise FileNotFoundError(f"Soil data file not found at {coords_path}")
    
    df = pd.read_csv(coords_path)
    required_cols = ['latitude', 'longitude', 'species_name', 'N', 'P', 'K', 'pH']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise DataQualityError(f"Soil data missing required columns: {missing}")
    
    logger.info(f"Loaded {len(df)} rows from soil data at {coords_path}")
    return df

def load_trait_data(trait_path: str) -> pd.DataFrame:
    """
    Load trait data from the processed CSV generated by trait_data.py.
    """
    _ensure_logger()
    path = Path(trait_path)
    if not path.exists():
        raise FileNotFoundError(f"Trait data file not found at {trait_path}")
    
    df = pd.read_csv(trait_path)
    required_cols = ['latitude', 'longitude', 'species_name', 'root_depth', 'root_mass']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise DataQualityError(f"Trait data missing required columns: {missing}")
    
    logger.info(f"Loaded {len(df)} rows from trait data at {trait_path}")
    return df

def merge_datasets(
    soil_df: pd.DataFrame, 
    trait_df: pd.DataFrame, 
    on: List[str] = ["latitude", "longitude", "species_name"]
) -> pd.DataFrame:
    """
    Merge soil and trait dataframes on coordinates and species.
    Uses inner join to ensure only paired observations are kept.
    """
    _ensure_logger()
    logger.info(f"Attempting merge on columns: {on}")
    merged = pd.merge(trait_df, soil_df, on=on, how="inner")
    logger.info(f"Merge result: {len(merged)} rows (from {len(trait_df)} trait and {len(soil_df)} soil)")
    return merged

def apply_species_filter(df: pd.DataFrame, min_obs: int = 10) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Filter for species with at least `min_obs` valid observations.
    A valid observation has non-null values in all key predictor and outcome columns.
    
    Returns:
        Tuple[filtered_df, excluded_summary_df]
        excluded_summary_df contains: species_name, observation_count, reason
    """
    _ensure_logger()
    key_cols = ["N", "P", "K", "pH", "root_depth", "root_mass"]
    
    # Identify rows with complete data for key variables
    valid_mask = df[key_cols].notna().all(axis=1)
    valid_df = df[valid_mask]
    
    if len(valid_df) == 0:
        raise DataQualityError("No valid observations found after merging. Cannot apply species filter.")
    
    counts = valid_df["species_name"].value_counts()
    valid_species = counts[counts >= min_obs].index
    
    filtered = df[df["species_name"].isin(valid_species)]
    
    # Prepare excluded summary
    excluded_species = counts[counts < min_obs]
    excluded_summary = pd.DataFrame({
        "species_name": excluded_species.index,
        "observation_count": excluded_species.values,
        "reason": "observation_count < 10"
    })
    
    logger.info(f"Species filter applied: {len(valid_species)} species kept, {len(excluded_species)} excluded.")
    return filtered, excluded_summary

def main():
    """
    Main entry point for T014 (Merge).
    
    Workflow:
    1. Load soil data from data/processed/soil_extracted.csv
    2. Load trait data from data/processed/trait_filtered.csv
    3. Merge on latitude, longitude, species_name
    4. Apply species filter (>= 10 obs)
    5. Save merged dataset to data/processed/merged_raw.csv
    6. Save excluded species summary to data/processed/excluded_species_summary.csv
    7. Log species exclusions to data/logs/species_exclusions.log
    """
    _ensure_logger()
    
    # Paths
    project_root = Path(__file__).resolve().parent.parent.parent
    soil_path = project_root / "data" / "processed" / "soil_extracted.csv"
    trait_path = project_root / "data" / "processed" / "trait_filtered.csv"
    output_path = project_root / "data" / "processed" / "merged_raw.csv"
    excluded_summary_path = project_root / "data" / "processed" / "excluded_species_summary.csv"
    exclusion_log_path = project_root / "data" / "logs" / "species_exclusions.log"
    
    logger.info(f"Starting merge process. Project root: {project_root}")
    
    # 1. Load Data
    try:
        soil_df = load_soil_data(str(soil_path))
        trait_df = load_trait_data(str(trait_path))
    except (FileNotFoundError, DataQualityError) as e:
        logger.error(f"Failed to load data: {e}")
        raise
    
    # 2. Merge
    merged_df = merge_datasets(soil_df, trait_df)
    
    if merged_df.empty:
        logger.warning("Merged dataset is empty. No overlapping coordinates/species found.")
        # Still create empty outputs to maintain pipeline structure
        merged_df.to_csv(output_path, index=False)
        excluded_summary_path.parent.mkdir(parents=True, exist_ok=True)
        pd.DataFrame(columns=["species_name", "observation_count", "reason"]).to_csv(excluded_summary_path, index=False)
        return
    
    # 3. Apply Species Filter
    filtered_df, excluded_summary = apply_species_filter(merged_df, min_obs=10)
    
    # 4. Save Outputs
    output_path.parent.mkdir(parents=True, exist_ok=True)
    filtered_df.to_csv(output_path, index=False)
    logger.info(f"Saved filtered merged dataset to {output_path}")
    
    excluded_summary_path.parent.mkdir(parents=True, exist_ok=True)
    excluded_summary.to_csv(excluded_summary_path, index=False)
    logger.info(f"Saved excluded species summary to {excluded_summary_path}")
    
    # 5. Log Exclusions
    exclusion_log_path.parent.mkdir(parents=True, exist_ok=True)
    log_species_exclusion_summary(excluded_summary, str(exclusion_log_path))
    logger.info(f"Logged species exclusions to {exclusion_log_path}")
    
    logger.info("T014 Merge completed successfully.")

if __name__ == "__main__":
    main()