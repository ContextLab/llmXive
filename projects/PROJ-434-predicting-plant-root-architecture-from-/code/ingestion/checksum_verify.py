"""
T012b: Verify checksum of data/processed/soil_extracted.csv.

Reads the checksum file `data/processed/soil_extracted.csv.sha256` generated by T012
and verifies it matches the current hash of `data/processed/soil_extracted.csv`.

Logs verification status to `data/logs/checksum_verification.log`.
"""
import os
import sys
import hashlib
import logging
from pathlib import Path
from datetime import datetime

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from utils.logging_utils import setup_logging, get_logger

# Paths relative to project root
DATA_PROCESSED_DIR = project_root / "data" / "processed"
DATA_LOGS_DIR = project_root / "data" / "logs"
FILE_NAME = "soil_extracted.csv"
CHECKSUM_FILE_NAME = f"{FILE_NAME}.sha256"
LOG_FILE_NAME = "checksum_verification.log"

FILE_PATH = DATA_PROCESSED_DIR / FILE_NAME
CHECKSUM_PATH = DATA_PROCESSED_DIR / CHECKSUM_FILE_NAME
LOG_PATH = DATA_LOGS_DIR / LOG_FILE_NAME

def compute_sha256(file_path: Path) -> str:
    """Compute SHA256 hash of a file."""
    sha256_hash = hashlib.sha256()
    with open(file_path, "rb") as f:
        for chunk in iter(lambda: f.read(4096), b""):
            sha256_hash.update(chunk)
    return sha256_hash.hexdigest()

def verify_checksum() -> bool:
    """
    Verify the checksum of the soil extracted CSV file.

    Returns:
        bool: True if verification passes, False otherwise.
    """
    logger = get_logger(__name__)

    # Ensure directories exist
    DATA_PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    DATA_LOGS_DIR.mkdir(parents=True, exist_ok=True)

    # Setup logging for this specific file
    setup_logging(log_file=str(LOG_PATH), logger_name="checksum_verification")
    logger = logging.getLogger("checksum_verification")

    logger.info(f"Starting checksum verification for {FILE_PATH}")

    # Check if the main file exists
    if not FILE_PATH.exists():
        error_msg = f"ERROR: Data file not found: {FILE_PATH}"
        logger.error(error_msg)
        print(error_msg)
        return False

    # Check if the checksum file exists
    if not CHECKSUM_PATH.exists():
        error_msg = f"ERROR: Checksum file not found: {CHECKSUM_PATH}"
        logger.error(error_msg)
        print(error_msg)
        return False

    try:
        # Read stored checksum (should be just the hex string, possibly with whitespace)
        with open(CHECKSUM_PATH, "r") as f:
            stored_checksum = f.read().strip()

        # Compute current checksum
        current_checksum = compute_sha256(FILE_PATH)

        logger.info(f"Stored checksum:   {stored_checksum}")
        logger.info(f"Computed checksum: {current_checksum}")

        if stored_checksum == current_checksum:
            status_msg = "VERIFICATION PASSED: Checksums match."
            logger.info(status_msg)
            print(status_msg)
            return True
        else:
            status_msg = "VERIFICATION FAILED: Checksums do not match!"
            logger.error(status_msg)
            print(status_msg)
            return False

    except Exception as e:
        error_msg = f"ERROR during verification: {str(e)}"
        logger.exception(error_msg)
        print(error_msg)
        return False

def main():
    """Entry point for the script."""
    success = verify_checksum()
    sys.exit(0 if success else 1)

if __name__ == "__main__":
    main()