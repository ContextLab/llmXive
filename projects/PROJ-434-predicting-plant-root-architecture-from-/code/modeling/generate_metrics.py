import pickle
from pathlib import Path
from typing import Dict, Any, Optional

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent))

from utils.exceptions import DataQualityError
from utils.logging_utils import get_logger

logger = get_logger(__name__)

def load_model_metrics_from_training_log(
    training_log_path: Path
) -> Dict[str, Any]:
    """
    Load model metrics from the training log generated by train.py.
    
    Expects a JSON file containing metrics from LOSO and Stratified CV runs
    for both Model A (Soil-Only) and Model B (Soil+Species).
    
    Args:
        training_log_path: Path to the training log JSON file.
        
    Returns:
        Dictionary containing raw metrics from training.
        
    Raises:
        FileNotFoundError: If the training log file does not exist.
        DataQualityError: If the log file is empty or malformed.
    """
    if not training_log_path.exists():
        raise FileNotFoundError(
            f"Training log not found at {training_log_path}. "
            "Ensure train.py (T020) and subsequent validation tasks have run."
        )
    
    try:
        with open(training_log_path, 'r') as f:
            content = f.read().strip()
            if not content:
                raise DataQualityError("Training log file is empty.")
            metrics = json.loads(content)
    except json.JSONDecodeError as e:
        raise DataQualityError(f"Training log file is malformed JSON: {e}")
    
    return metrics

def generate_model_metrics_json(
    raw_metrics: Dict[str, Any],
    output_path: Path
) -> Dict[str, Any]:
    """
    Process raw training metrics into the standardized model_metrics.json format.
    
    Computes:
    - mean_r2: Average R² across all targets and validation folds (primary focus on LOSO).
    - mean_rmse: Average RMSE across all targets and validation folds.
    - loso_r2_sd: Standard deviation of R² scores across LOSO folds for the primary model.
    - per_target_metrics: Detailed breakdown per target variable.
    
    Args:
        raw_metrics: Raw metrics dictionary from training log.
        output_path: Path where the final JSON will be written.
        
    Returns:
        The processed metrics dictionary.
    """
    # Ensure SC-002 passed before generating final metrics
    sc002_path = output_path.parent / "sc002_status.json"
    if sc002_path.exists():
        with open(sc002_path, 'r') as f:
            sc002_status = json.load(f)
            if not sc002_status.get('pass', False):
                logger.warning(
                    "SC-002 validation failed. Generating metrics anyway, "
                    "but model performance may not meet scientific standards."
                )
    else:
        logger.warning(
            "sc002_status.json not found. Ensure T023 has run before T024."
        )

    # Extract LOSO metrics for Model B (Soil+Species) as the primary model
    # Assuming raw_metrics structure: {'model_b_loso': {'r2': [...], 'rmse': [...], ...}}
    # Adjust keys based on actual train.py output structure if different
    model_b_loso = raw_metrics.get('model_b_loso', {})
    model_a_loso = raw_metrics.get('model_a_loso', {})
    
    # Calculate aggregate statistics
    r2_scores = model_b_loso.get('r2', [])
    rmse_scores = model_b_loso.get('rmse', [])
    
    if not r2_scores:
        raise DataQualityError(
            "No R² scores found in training log. Ensure LOSO CV was executed."
        )
    
    mean_r2 = float(sum(r2_scores) / len(r2_scores))
    mean_rmse = float(sum(rmse_scores) / len(rmse_scores)) if rmse_scores else 0.0
    
    # Calculate standard deviation of R² for LOSO
    if len(r2_scores) > 1:
        variance = sum((x - mean_r2) ** 2 for x in r2_scores) / (len(r2_scores) - 1)
        loso_r2_sd = float(variance ** 0.5)
    else:
        loso_r2_sd = 0.0
    
    # Structure per_target_metrics
    # Assuming targets are 'root_depth' and 'root_density' based on domain
    per_target_metrics = {}
    
    # Helper to extract per-target stats if available in raw_metrics
    # If raw_metrics has nested structure like {'root_depth': {'r2': [...]}, ...}
    if 'per_target' in raw_metrics:
        per_target_metrics = raw_metrics['per_target']
    else:
        # Fallback: create generic structure if not explicitly broken down
        # This assumes the raw_metrics might have 'root_depth' and 'root_density' keys
        for target in ['root_depth', 'root_density']:
            if target in raw_metrics:
                target_r2 = raw_metrics[target].get('r2', [])
                target_rmse = raw_metrics[target].get('rmse', [])
                per_target_metrics[target] = {
                    'mean_r2': float(sum(target_r2)/len(target_r2)) if target_r2 else 0.0,
                    'mean_rmse': float(sum(target_rmse)/len(target_rmse)) if target_rmse else 0.0,
                    'loso_r2_sd': 0.0 # Calculated separately if needed
                }
    
    # Final output structure
    final_metrics = {
        "mean_r2": mean_r2,
        "mean_rmse": mean_rmse,
        "loso_r2_sd": loso_r2_sd,
        "per_target_metrics": per_target_metrics,
        "model_a_loso_r2": float(sum(model_a_loso.get('r2', []))/len(model_a_loso.get('r2', []))) if model_a_loso.get('r2') else None,
        "model_b_loso_r2": mean_r2,
        "validation_method": "LOSO"
    }
    
    # Write to file
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(final_metrics, f, indent=2)
    
    logger.info(f"Model metrics written to {output_path}")
    return final_metrics

def main():
    """Main entry point for generating model metrics JSON."""
    # Define paths relative to project root
    project_root = Path(__file__).parent.parent.parent
    training_log_path = project_root / "artifacts" / "training_log.json"
    output_path = project_root / "artifacts" / "model_metrics.json"
    
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    try:
        logger.info("Loading training metrics...")
        raw_metrics = load_model_metrics_from_training_log(training_log_path)
        
        logger.info("Generating model_metrics.json...")
        generate_model_metrics_json(raw_metrics, output_path)
        
        logger.info("Task T024 completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except DataQualityError as e:
        logger.error(f"Data quality error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
