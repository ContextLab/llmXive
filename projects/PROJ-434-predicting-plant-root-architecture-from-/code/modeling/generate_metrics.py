import os
import sys
import json
import logging
import pickle
from pathlib import Path
from typing import Dict, Any, Optional

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from utils.exceptions import DataQualityError

logger = logging.getLogger(__name__)

def load_model_metrics_from_training_log(log_path: Path) -> Dict[str, Any]:
    """
    Load metrics generated by the training script (T020-T023).
    Expects a JSON file containing stratified CV and LOSO results.
    """
    if not log_path.exists():
        raise FileNotFoundError(f"Training log not found at {log_path}")

    with open(log_path, 'r') as f:
        data = json.load(f)
    
    # Validate expected structure
    required_keys = ['stratified_cv_results', 'loso_cv_results', 'per_target_metrics']
    for key in required_keys:
        if key not in data:
            raise ValueError(f"Training log missing required key: {key}")
    
    return data

def generate_model_metrics_json(
    training_data: Dict[str, Any], 
    output_path: Path
) -> Dict[str, Any]:
    """
    Generate the model_metrics.json artifact for T024.
    
    Schema:
    {
      "mean_r2": float,
      "mean_rmse": float,
      "loso_r2_sd": float,
      "per_target_metrics": {
          "target_name": {
              "mean_r2": float,
              "mean_rmse": float,
              "loso_r2_sd": float
          },
          ...
      }
    }
    """
    stratified_results = training_data['stratified_cv_results']
    loso_results = training_data['loso_cv_results']
    per_target = training_data['per_target_metrics']
    
    # Aggregate metrics across all targets for the summary
    all_r2 = []
    all_rmse = []
    for target, metrics in per_target.items():
        if 'mean_r2' in metrics:
            all_r2.append(metrics['mean_r2'])
        if 'mean_rmse' in metrics:
            all_rmse.append(metrics['mean_rmse'])
    
    # Calculate overall mean R2 and RMSE
    mean_r2 = sum(all_r2) / len(all_r2) if all_r2 else 0.0
    mean_rmse = sum(all_rmse) / len(all_rmse) if all_rmse else 0.0
    
    # Calculate LOSO R2 SD across targets
    loso_sd_values = []
    for target, metrics in per_target.items():
        if 'loso_r2_sd' in metrics:
            loso_sd_values.append(metrics['loso_r2_sd'])
    
    loso_r2_sd = sum(loso_sd_values) / len(loso_sd_values) if loso_sd_values else 0.0
    
    output_metrics = {
        "mean_r2": round(mean_r2, 6),
        "mean_rmse": round(mean_rmse, 6),
        "loso_r2_sd": round(loso_r2_sd, 6),
        "per_target_metrics": {}
    }
    
    # Format per-target metrics
    for target, metrics in per_target.items():
        output_metrics["per_target_metrics"][target] = {
            "mean_r2": round(metrics.get('mean_r2', 0.0), 6),
            "mean_rmse": round(metrics.get('mean_rmse', 0.0), 6),
            "loso_r2_sd": round(metrics.get('loso_r2_sd', 0.0), 6)
        }
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(output_metrics, f, indent=2)
    
    logger.info(f"Model metrics written to {output_path}")
    return output_metrics

def main():
    """
    Entry point for generating model_metrics.json.
    Reads from artifacts/training_results.json and writes to artifacts/model_metrics.json.
    """
    # Define paths
    artifacts_dir = project_root / 'artifacts'
    input_log = artifacts_dir / 'training_results.json'
    output_file = artifacts_dir / 'model_metrics.json'
    
    # Setup logging
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    try:
        logger.info(f"Loading training results from {input_log}")
        training_data = load_model_metrics_from_training_log(input_log)
        
        logger.info("Generating model metrics JSON")
        metrics = generate_model_metrics_json(training_data, output_file)
        
        logger.info(f"Successfully generated {output_file}")
        logger.info(f"Summary: Mean R2 = {metrics['mean_r2']:.4f}, Mean RMSE = {metrics['mean_rmse']:.4f}")
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        raise
    except ValueError as e:
        logger.error(f"Invalid training log format: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error generating metrics: {e}")
        raise

if __name__ == "__main__":
    main()