def main():
    """Main entry point for T056."""
    config = get_config()
    data_raw_dir = Path(config["data"]["raw"])
    data_metadata_dir = Path(config["data"]["metadata"])
    state_dir = Path(get_project_root()) / "state" / "projects"
    
    # Setup logging
    log_file = data_metadata_dir / "data_loader.log"
    logger = setup_logger("data_loader", str(log_file))
    
    logger.info("Starting T056: Data Loader")
    
    # Load registry
    try:
        registry = load_verified_dataset_ids()
        logger.info(f"Loaded registry: {registry}")
    except Exception as e:
        logger.critical(f"FATAL: Could not load dataset registry: {e}")
        sys.exit(1)
    
    # Check for required sizes
    missing_sizes = [size for size in REQUIRED_SIZES if size not in registry]
    if missing_sizes:
        write_missing_log(missing_sizes, data_metadata_dir / "missing_datasets.log")
    
    # Fetch datasets
    trajectory_ids = []
    downloaded_files = []
    
    for size in REQUIRED_SIZES:
        dataset_id = registry[size]
        output_path = data_raw_dir / f"amorphous_si_N{size}.tar.gz"
        
        try:
            # Fetch
            file_path = fetch_dataset(dataset_id, size, data_raw_dir, logger)
            if not file_path:
                logger.critical(f"FATAL: Failed to fetch dataset for N={size}")
                sys.exit(1)
            
            downloaded_files.append(file_path)
            
            # Extract trajectory ID
            traj_info = extract_trajectory_id(file_path, size, logger)
            trajectory_ids.append(traj_info)
            
            # Validate realizations (assuming we can count them from metadata or file)
            # For now, we assume at least 1 realization per file
            validate_realizations(1, size, logger)
            
        except RuntimeError as e:
            logger.critical(str(e))
            sys.exit(1)
    
    # Write trajectory IDs
    traj_output = data_metadata_dir / "trajectory_ids.json"
    write_trajectory_ids(trajectory_ids, traj_output, logger)
    
    # Update state checksums
    state_file = state_dir / "PROJ-260-investigating-the-influence-of-network-s.yaml"
    update_state_checksums(state_file, logger)
    
    logger.info("T056 completed successfully.")

