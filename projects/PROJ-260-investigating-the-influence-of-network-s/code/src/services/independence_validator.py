"""
Independence Validator Service for T039.

Verifies that the source trajectory ID used for thermal conductivity (kappa)
values is distinct from the trajectory used for topology extraction.
"""
import json
import logging
from pathlib import Path
from typing import Set, Dict, Any

from src.lib.config import get_config

# Custom exception for fatal validation errors
class FatalError(Exception):
    """Raised when a critical validation check fails, halting the pipeline."""
    pass

def setup_logger(name: str = "independence_validator") -> logging.Logger:
    """Configure and return a logger for the independence validator."""
    logger = logging.getLogger(name)
    if not logger.handlers:
        logger.setLevel(logging.INFO)
        handler = logging.StreamHandler()
        formatter = logging.Formatter(
            "%(asctime)s - %(levelname)s - %(module)s - %(message)s"
        )
        handler.setFormatter(formatter)
        logger.addHandler(handler)
    return logger

def load_trajectory_ids(trajectory_ids_path: Path) -> Set[str]:
    """
    Load the set of trajectory IDs from the metadata file generated by T056.

    Args:
        trajectory_ids_path: Path to trajectory_ids.json

    Returns:
        Set of unique trajectory IDs.

    Raises:
        FileNotFoundError: If the file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    logger = setup_logger()
    logger.info(f"Loading trajectory IDs from {trajectory_ids_path}")
    
    if not trajectory_ids_path.exists():
        raise FileNotFoundError(
            f"Trajectory IDs file not found: {trajectory_ids_path}. "
            "Ensure T056 has completed successfully."
        )

    with open(trajectory_ids_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    # Extract IDs from the structure: {"trajectories": [{"id": "..."}, ...]}
    # or simply a list of IDs depending on T056 output format.
    # Assuming standard structure based on T056 description:
    ids = set()
    if isinstance(data, list):
        ids = set(str(item) for item in data)
    elif isinstance(data, dict) and "trajectories" in data:
        ids = set(item.get("id") for item in data["trajectories"] if "id" in item)
    elif isinstance(data, dict):
        # Fallback: assume keys are IDs or a specific "ids" key
        if "ids" in data:
            ids = set(str(item) for item in data["ids"])
        else:
            ids = set(data.keys())
    
    if not ids:
        raise ValueError("No trajectory IDs found in the metadata file.")
    
    logger.info(f"Loaded {len(ids)} unique trajectory IDs.")
    return ids

def load_kappa_trajectory_ids(kappa_file_path: Path) -> Set[str]:
    """
    Load the set of trajectory IDs referenced in the validated kappa values CSV.

    Args:
        kappa_file_path: Path to kappa_values.csv

    Returns:
        Set of trajectory IDs found in the 'trajectory_id' column.

    Raises:
        FileNotFoundError: If the file does not exist.
        KeyError: If 'trajectory_id' column is missing.
    """
    logger = setup_logger()
    logger.info(f"Loading trajectory IDs from kappa file: {kappa_file_path}")

    if not kappa_file_path.exists():
        raise FileNotFoundError(
            f"Kappa values file not found: {kappa_file_path}. "
            "Ensure T057 has completed successfully."
        )

    import csv
    ids = set()
    with open(kappa_file_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if "trajectory_id" not in reader.fieldnames:
            raise KeyError(
                f"Missing 'trajectory_id' column in {kappa_file_path}. "
                "The kappa file must contain this column."
            )
        
        for row in reader:
            tid = row.get("trajectory_id", "").strip()
            if tid:
                ids.add(tid)

    if not ids:
        raise ValueError("No trajectory IDs found in the kappa file.")

    logger.info(f"Found {len(ids)} unique trajectory IDs in kappa file.")
    return ids

def validate_independence(
    metadata_trajectory_ids: Set[str],
    kappa_trajectory_ids: Set[str],
    logger: logging.Logger
) -> bool:
    """
    Verify that the sets of trajectory IDs are disjoint.

    Args:
        metadata_trajectory_ids: IDs from the topology extraction source (T056).
        kappa_trajectory_ids: IDs from the kappa values source (T057).
        logger: Logger instance.

    Returns:
        True if independent.

    Raises:
        FatalError: If there is any overlap (not independent).
    """
    logger.info("Checking for independence between trajectory sources...")
    
    intersection = metadata_trajectory_ids.intersection(kappa_trajectory_ids)
    
    if intersection:
        error_msg = (
            f"CRITICAL: Trajectory source is NOT independent. "
            f"Found {len(intersection)} overlapping trajectory IDs: {intersection}. "
            f"FR-008 violation: Thermal conductivity data must come from a source "
            f"independent of the topology extraction data."
        )
        logger.error(error_msg)
        raise FatalError(error_msg)
    
    logger.info("Independence check PASSED: No overlapping trajectory IDs found.")
    return True

def main() -> None:
    """
    Main entry point for the Independence Validator.
    Reads config, loads IDs, and performs the check.
    """
    logger = setup_logger()
    config = get_config()
    
    # Paths
    metadata_path = config.data_metadata_dir / "trajectory_ids.json"
    kappa_path = config.data_derived_ref_dir / "kappa_values.csv"
    
    try:
        # Load IDs
        meta_ids = load_trajectory_ids(metadata_path)
        kappa_ids = load_kappa_trajectory_ids(kappa_path)
        
        # Validate
        validate_independence(meta_ids, kappa_ids, logger)
        
        logger.info("Reference generation validation complete. Proceeding to output generation.")
        
    except (FileNotFoundError, KeyError, ValueError, FatalError) as e:
        logger.critical(f"Validation failed: {e}")
        # Re-raise to ensure the pipeline halts
        raise
    except Exception as e:
        logger.critical(f"Unexpected error during validation: {e}")
        raise

if __name__ == "__main__":
    main()
