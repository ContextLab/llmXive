"""
Preprocess raw perovskite data: clean, handle missing values, validate schema,
and save the final features dataset.

This module implements Task T016 for US1. It expects raw data generated by
code/data/download.py and code/data/descriptors.py to be present in data/raw/.
It outputs the cleaned feature set to data/processed/features.csv.

Pipeline Flow:
1. Load raw CSV (output of descriptors.py).
2. Validate schema against contracts/data-schema.yaml.
3. Clean data: remove duplicates, handle missing values (drop rows with nulls in critical columns).
4. Save to data/processed/features.csv.
"""

import os
import sys
import logging
from pathlib import Path
from typing import List, Optional, Dict, Any, Tuple

import pandas as pd
import yaml

# Ensure project root is in path for imports
PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT))

from utils.logging_config import get_logger, log_exclusion_reason, log_pipeline_event
from utils.config import get_config_summary

logger = get_logger(__name__)

# Constants
RAW_DATA_PATH = PROJECT_ROOT / "data" / "raw" / "perovskites_with_descriptors.csv"
PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
OUTPUT_PATH = PROCESSED_DIR / "features.csv"
SCHEMA_PATH = PROJECT_ROOT / "contracts" / "data-schema.yaml"

REQUIRED_COLUMNS = [
    "material_id",
    "formula",
    "structure_type",
    "space_group_number",
    "tolerance_factor",
    "octahedral_factor",
    "ionic_radius_mismatch",
    "electronegativity_difference",
    "decomposition_energy"
]

CRITICAL_COLUMNS = [
    "tolerance_factor",
    "octahedral_factor",
    "decomposition_energy"
]

def load_raw_data() -> pd.DataFrame:
    """Load the raw CSV generated by the descriptors pipeline."""
    if not RAW_DATA_PATH.exists():
        raise FileNotFoundError(
            f"Raw data file not found at {RAW_DATA_PATH}. "
            "Please run code/data/download.py and code/data/descriptors.py first."
        )

    logger.info(f"Loading raw data from {RAW_DATA_PATH}")
    df = pd.read_csv(RAW_DATA_PATH)
    log_pipeline_event(f"Loaded {len(df)} rows from raw data")
    return df

def validate_schema(df: pd.DataFrame) -> Tuple[bool, List[str]]:
    """
    Validate the dataframe against the expected schema.
    Returns (is_valid, list_of_errors).
    """
    errors = []

    # Check for required columns
    missing_cols = set(REQUIRED_COLUMNS) - set(df.columns)
    if missing_cols:
        errors.append(f"Missing required columns: {missing_cols}")
        return False, errors

    # Check for nulls in critical columns
    for col in CRITICAL_COLUMNS:
        null_count = df[col].isnull().sum()
        if null_count > 0:
            errors.append(f"Column '{col}' has {null_count} null values.")

    if errors:
        logger.warning("Schema validation failed with errors: %s", errors)
        return False, errors

    logger.info("Schema validation passed.")
    return True, []

def clean_data(df: pd.DataFrame) -> pd.DataFrame:
    """
    Clean the data:
    1. Remove duplicates based on material_id.
    2. Drop rows where critical columns (target or key descriptors) are null.
    3. Log exclusion reasons.
    """
    initial_count = len(df)
    logger.info(f"Starting data cleaning on {initial_count} rows.")

    # 1. Remove duplicates
    before_dedup = len(df)
    df = df.drop_duplicates(subset=['material_id'], keep='first')
    dedup_removed = before_dedup - len(df)
    if dedup_removed > 0:
        log_exclusion_reason(f"Removed {dedup_removed} duplicate material_ids")
        logger.info(f"Removed {dedup_removed} duplicate material_ids.")

    # 2. Handle missing values in critical columns
    # We drop rows where decomposition_energy or key descriptors are null.
    # The descriptors.py should have already handled most, but we enforce it here.
    before_drop = len(df)
    df = df.dropna(subset=CRITICAL_COLUMNS)
    dropped_count = before_drop - len(df)

    if dropped_count > 0:
        log_exclusion_reason(f"Removed {dropped_count} rows with missing critical values (tolerance_factor, octahedral_factor, or decomposition_energy)")
        logger.warning(f"Dropped {dropped_count} rows due to missing critical values.")

    # 3. Ensure numeric types for critical columns
    for col in CRITICAL_COLUMNS:
        df[col] = pd.to_numeric(df[col], errors='coerce')

    # Final null check just in case coercion created NaNs
    final_na = df[df[CRITICAL_COLUMNS].isnull().any(axis=1)]
    if not final_na.empty:
        count = len(final_na)
        log_exclusion_reason(f"Removed {count} rows with NaN after type coercion")
        df = df.dropna(subset=CRITICAL_COLUMNS)

    final_count = len(df)
    log_pipeline_event(f"Cleaning complete: {initial_count} -> {final_count} rows")
    logger.info(f"Data cleaning complete: {initial_count} -> {final_count} rows.")

    return df

def split_data(df: pd.DataFrame) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Split data into train and test sets.
    Note: For US1, the main goal is producing features.csv.
    The actual split logic is often handled in train.py to allow for stratification
    by target variable. However, we ensure the data is ready for split here.
    Returns the full cleaned dataframe for now, as the split happens in train.py.
    """
    logger.info("Data prepared for splitting. Actual split will occur in train.py.")
    return df, df # Placeholder return, logic moved to train.py for stratification

def save_processed_data(df: pd.DataFrame) -> str:
    """Save the processed dataframe to the specified output path."""
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)

    # Ensure we don't have any remaining NaN in critical columns before saving
    if df[CRITICAL_COLUMNS].isnull().any().any():
        raise ValueError("Cannot save data with NaN in critical columns.")

    df.to_csv(OUTPUT_PATH, index=False)
    log_pipeline_event(f"Saved processed features to {OUTPUT_PATH}")
    logger.info(f"Saved processed features to {OUTPUT_PATH}")
    return str(OUTPUT_PATH)

def main():
    """Main entry point for the preprocessing pipeline."""
    log_pipeline_event("Starting Preprocessing Pipeline (T016)")
    logger.info("Preprocessing pipeline started.")

    try:
        # 1. Load
        df_raw = load_raw_data()

        # 2. Validate Schema
        is_valid, errors = validate_schema(df_raw)
        if not is_valid:
            logger.error("Schema validation failed. Aborting.")
            for err in errors:
                logger.error(f"  - {err}")
            sys.exit(1)

        # 3. Clean
        df_clean = clean_data(df_raw)

        # 4. Save
        output_path = save_processed_data(df_clean)

        logger.info(f"Preprocessing complete. Output: {output_path}")
        log_pipeline_event("Preprocessing Pipeline (T016) completed successfully")

    except FileNotFoundError as e:
        logger.critical(str(e))
        sys.exit(1)
    except Exception as e:
        logger.critical(f"Unexpected error during preprocessing: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()
