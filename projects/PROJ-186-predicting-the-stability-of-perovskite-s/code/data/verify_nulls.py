import os
import sys
import logging
import pandas as pd
from pathlib import Path

# Add project root to path to allow imports from utils
project_root = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(project_root))

from utils.logging_config import get_logger, log_pipeline_event

logger = get_logger(__name__)

def main():
    """
    Task T018: Verify `data/processed/features.csv` has zero nulls in `decomposition_energy` column.
    
    This script loads the processed features file generated by T017 (preprocess.py),
    asserts that the target column 'decomposition_energy' contains no null values,
    and logs the result. If the assertion fails, it raises an AssertionError to halt execution.
    """
    input_path = Path(project_root) / "data" / "processed" / "features.csv"
    
    if not input_path.exists():
        logger.error(f"Input file not found: {input_path}")
        log_pipeline_event("T018_FAILURE", f"Input file missing: {input_path}")
        raise FileNotFoundError(f"Required artifact {input_path} does not exist. Run T017 (preprocess.py) first.")

    logger.info(f"Loading {input_path}...")
    try:
        df = pd.read_csv(input_path)
    except Exception as e:
        logger.error(f"Failed to read CSV: {e}")
        raise

    if df.empty:
        logger.error("Dataset is empty. Cannot verify nulls.")
        log_pipeline_event("T018_FAILURE", "Dataset is empty.")
        raise ValueError("Dataset is empty.")

    target_column = "decomposition_energy"
    
    if target_column not in df.columns:
        logger.error(f"Target column '{target_column}' not found in {df.columns.tolist()}")
        log_pipeline_event("T018_FAILURE", f"Column '{target_column}' missing.")
        raise KeyError(f"Column '{target_column}' not found in dataframe.")

    null_count = df[target_column].isnull().sum()
    total_count = len(df)
    
    logger.info(f"Column '{target_column}': {null_count} nulls out of {total_count} rows.")

    # The core assertion for Task T018
    if null_count > 0:
        error_msg = f"Verification FAILED: Found {null_count} null values in '{target_column}' column."
        logger.error(error_msg)
        log_pipeline_event("T018_FAILURE", error_msg)
        raise AssertionError(error_msg)

    logger.info(f"Verification PASSED: '{target_column}' column has zero nulls.")
    log_pipeline_event("T018_SUCCESS", f"Verified zero nulls in '{target_column}' for {total_count} rows.")
    return True

if __name__ == "__main__":
    main()