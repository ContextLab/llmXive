import os
import sys
import logging
import pandas as pd
from pathlib import Path
from typing import List, Dict, Any, Optional

from utils.logging_config import get_logger, log_pipeline_event

logger = get_logger(__name__)

# Constants matching project config
INPUT_FILE = "results/screening_full.csv"
OUTPUT_FILE = "results/screening_candidates.md"
TOP_N = 20
STABILITY_THRESHOLD = -0.1  # eV/atom

def load_ranked_candidates(filepath: str) -> pd.DataFrame:
    """Load the full ranked list of candidates."""
    path = Path(filepath)
    if not path.exists():
        raise FileNotFoundError(f"Ranked candidates file not found: {filepath}")
    
    df = pd.read_csv(path)
    
    # Ensure sorting is correct (ascending by predicted energy)
    if 'predicted_decomposition_energy' in df.columns:
        df = df.sort_values(by='predicted_decomposition_energy', ascending=True)
    
    return df

def select_top_candidates(df: pd.DataFrame, n: int = TOP_N) -> pd.DataFrame:
    """Select the top N most stable candidates."""
    if len(df) == 0:
        logger.warning("Input dataframe is empty. Returning empty dataframe.")
        return pd.DataFrame()
    
    return df.head(n)

def generate_markdown_report(df: pd.DataFrame, output_path: str) -> None:
    """
    Generate a curated Markdown report of the top candidates.
    
    The report includes:
    - A summary header
    - A table of the top candidates with key descriptors
    - A note on stability thresholds
    """
    if df.empty:
        logger.error("Cannot generate report from empty dataframe.")
        return

    lines = []
    lines.append("# Top Virtual Screening Candidates for Perovskite Stability")
    lines.append("")
    lines.append(f"**Generated from:** `{INPUT_FILE}`")
    lines.append(f"**Total candidates considered:** {len(df)}")
    lines.append(f"**Top candidates displayed:** {len(df)}")
    lines.append(f"**Stability threshold:** < {STABILITY_THRESHOLD} eV/atom")
    lines.append("")
    
    # Determine columns to display based on expected schema from predict.py/screening_full.py
    # Expected columns: formula, A, B, X, tolerance_factor, octahedral_factor, 
    #                   ionic_radius_mismatch, electronegativity_diff, 
    #                   predicted_decomposition_energy, is_ood
    display_cols = [
        'formula', 'A', 'B', 'X', 
        'tolerance_factor', 'octahedral_factor', 'ionic_radius_mismatch', 
        'electronegativity_diff', 'predicted_decomposition_energy', 'is_ood'
    ]
    
    # Filter to only columns that actually exist in the dataframe
    available_cols = [col for col in display_cols if col in df.columns]
    
    # Build table header
    header = "| " + " | ".join(available_cols) + " |"
    separator = "|" + "---|" * len(available_cols)
    
    lines.append(header)
    lines.append(separator)
    
    # Build table rows
    for _, row in df.iterrows():
        row_data = []
        for col in available_cols:
            val = row[col]
            # Format floats to 4 decimal places for readability
            if isinstance(val, float):
                row_data.append(f"{val:.4f}")
            elif pd.isna(val):
                row_data.append("N/A")
            else:
                row_data.append(str(val))
        
        # Highlight stable candidates in the energy column if possible (markdown doesn't support color, so we use bold)
        # We need to reconstruct the row string to apply bolding to the energy value if it meets criteria
        # Since we can't easily inject markdown into the pipe-delimited row without re-parsing, 
        # we will just format the text.
        # However, to strictly follow the "highlight" requirement, we will bold the energy value if stable.
        
        # Re-iterate to apply bolding to the energy column specifically
        formatted_row = []
        for i, col in enumerate(available_cols):
            val = row[col]
            if isinstance(val, float):
                text = f"{val:.4f}"
            elif pd.isna(val):
                text = "N/A"
            else:
                text = str(val)
            
            if col == 'predicted_decomposition_energy' and isinstance(row[col], (int, float)) and row[col] < STABILITY_THRESHOLD:
                text = f"**{text}**" # Highlight stable candidates
            
            formatted_row.append(text)
        
        lines.append("| " + " | ".join(formatted_row) + " |")

    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append(f"Out of {len(df)} candidates analyzed, the top {len(df)} are listed above.")
    lines.append(f"Candidates with predicted decomposition energy **below** {STABILITY_THRESHOLD} eV/atom are highlighted in bold.")
    lines.append("These candidates represent the most thermodynamically stable hypothetical perovskites in the screened library.")
    lines.append("")
    lines.append("---")
    lines.append("*Report generated by `code/models/generate_candidates_report.py`*")

    # Write to file
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    
    logger.info(f"Markdown report generated successfully: {output_path}")

def save_report(df: pd.DataFrame, output_path: str) -> None:
    """Wrapper to generate and save the report."""
    generate_markdown_report(df, output_path)

def main():
    """Main entry point for generating the screening candidates report."""
    log_pipeline_event("Starting T041: Generate screening candidates report")
    
    input_path = Path(INPUT_FILE)
    output_path = Path(OUTPUT_FILE)
    
    # Ensure input exists
    if not input_path.exists():
        logger.error(f"Input file {input_path} not found. T040 (screening_full.csv) must be completed first.")
        sys.exit(1)
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    try:
        # Load data
        logger.info(f"Loading ranked candidates from {input_path}...")
        df = load_ranked_candidates(str(input_path))
        
        if df.empty:
            logger.warning("No candidates found in input file. Generating empty report.")
            # Still generate a report indicating no data
            save_report(pd.DataFrame(), str(output_path))
            return

        # Select top candidates
        logger.info(f"Selecting top {TOP_N} candidates...")
        top_candidates = select_top_candidates(df, n=TOP_N)
        
        # Generate report
        logger.info(f"Generating Markdown report to {output_path}...")
        save_report(top_candidates, str(output_path))
        
        logger.info("T041 completed successfully.")
        
    except Exception as e:
        logger.error(f"Failed to generate report: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()