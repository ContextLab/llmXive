import os
import sys
import logging
import pandas as pd
from pathlib import Path
from typing import List, Dict, Any, Optional

# Import logging utilities from the project's existing utils
from utils.logging_config import get_logger, log_pipeline_event

# Configure logger for this module
logger = get_logger(__name__)

def load_ranked_candidates(filepath: str) -> pd.DataFrame:
    """
    Load the full ranked candidate list from the CSV generated by T040.
    
    Args:
        filepath: Path to results/screening_full.csv
        
    Returns:
        DataFrame containing all candidates sorted by predicted energy.
    """
    path = Path(filepath)
    if not path.exists():
        raise FileNotFoundError(f"Ranked candidates file not found at {filepath}. "
                                "Ensure T040 (screening_full.py) has been executed successfully.")
    
    logger.info(f"Loading ranked candidates from {filepath}")
    df = pd.read_csv(filepath)
    
    # Basic validation
    required_cols = ['formula', 'predicted_decomposition_energy', 'tolerance_factor', 'octahedral_factor']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in {filepath}: {missing}")
        
    return df

def select_top_candidates(df: pd.DataFrame, n_top: int = 20) -> pd.DataFrame:
    """
    Select the top N candidates based on predicted decomposition energy (lowest first).
    
    Args:
        df: DataFrame with ranked candidates.
        n_top: Number of top candidates to select.
        
    Returns:
        Subset DataFrame with the top candidates.
    """
    if df.empty:
        logger.warning("Input DataFrame is empty.")
        return pd.DataFrame()
        
    # Ensure sorting by energy (ascending) just in case
    df_sorted = df.sort_values(by='predicted_decomposition_energy', ascending=True)
    
    logger.info(f"Selecting top {n_top} candidates from {len(df_sorted)} total.")
    return df_sorted.head(n_top)

def generate_markdown_report(df: pd.DataFrame, output_path: str) -> None:
    """
    Generate a Markdown report summarizing the top candidates.
    
    The report includes:
    - A header with project context.
    - A table of top candidates with formula, predicted energy, and key descriptors.
    - A summary section with statistics (min energy, count, etc.).
    
    Args:
        df: DataFrame of top candidates.
        output_path: Path where the .md file will be written.
    """
    if df.empty:
        raise ValueError("Cannot generate report from an empty DataFrame.")
        
    lines = []
    lines.append("# Top Perovskite Candidates for Stability")
    lines.append("")
    lines.append("This report lists the top candidates identified by the virtual screening pipeline "
                 "(Task T041) based on predicted decomposition energy. Lower values indicate higher stability.")
    lines.append("")
    
    # Statistics Summary
    lines.append("## Summary Statistics")
    lines.append("")
    min_energy = df['predicted_decomposition_energy'].min()
    avg_energy = df['predicted_decomposition_energy'].mean()
    stable_count = (df['predicted_decomposition_energy'] < -0.1).sum()
    
    lines.append(f"- **Total Candidates Analyzed**: {len(df)}")
    lines.append(f"- **Minimum Predicted Decomposition Energy**: {min_energy:.4f} eV/atom")
    lines.append(f"- **Average Predicted Decomposition Energy**: {avg_energy:.4f} eV/atom")
    lines.append(f"- **Candidates with Energy < -0.1 eV/atom**: {stable_count}")
    lines.append("")
    
    # Candidates Table
    lines.append("## Top Candidates")
    lines.append("")
    lines.append("| Rank | Formula | Predicted Energy (eV/atom) | Tolerance Factor (t) | Octahedral Factor (μ) | Stability Flag |")
    lines.append("| :--- | :--- | :--- | :--- | :--- | :--- |")
    
    # Format the table rows
    for idx, row in df.iterrows():
        rank = idx + 1
        formula = row['formula']
        energy = row['predicted_decomposition_energy']
        t_factor = row['tolerance_factor']
        mu_factor = row['octahedral_factor']
        
        # Determine stability flag based on threshold
        is_stable = "Stable (< -0.1 eV/atom)" if energy < -0.1 else "Metastable"
        
        # Format floats to 4 decimal places
        lines.append(f"| {rank} | {formula} | {energy:.4f} | {t_factor:.4f} | {mu_factor:.4f} | {is_stable} |")
        
    lines.append("")
    lines.append("---")
    lines.append("*Generated by llmXive automated science pipeline (Task T041)*")
    
    # Write to file
    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_file, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
        
    logger.info(f"Markdown report successfully written to {output_path}")

def save_report(report_content: str, filepath: str) -> None:
    """
    Save the raw report content to a file.
    (Wrapper for direct file writing if needed, though generate_markdown_report handles this).
    """
    Path(filepath).parent.mkdir(parents=True, exist_ok=True)
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(report_content)
    logger.info(f"Report saved to {filepath}")

def main():
    """
    Main entry point for Task T041.
    1. Loads the full ranked list from results/screening_full.csv.
    2. Selects the top 20 candidates.
    3. Generates and saves results/screening_candidates.md.
    """
    # Define paths relative to project root
    project_root = Path(__file__).resolve().parent.parent.parent
    input_path = project_root / "results" / "screening_full.csv"
    output_path = project_root / "results" / "screening_candidates.md"
    
    log_pipeline_event("Starting T041: Generate Candidates Report")
    
    try:
        # Step 1: Load data
        df_full = load_ranked_candidates(str(input_path))
        
        # Step 2: Select top candidates
        # The spec asks for a "curated set of the top candidates". 20 is a standard number for such reports.
        df_top = select_top_candidates(df_full, n_top=20)
        
        if df_top.empty:
            raise RuntimeError("No candidates found to report. Ensure screening_full.csv is populated.")
        
        # Step 3: Generate and save report
        generate_markdown_report(df_top, str(output_path))
        
        log_pipeline_event("T041 completed successfully. Report saved.")
        
    except FileNotFoundError as e:
        logger.error(f"Input file missing: {e}")
        raise
    except Exception as e:
        logger.error(f"Error during report generation: {e}")
        raise

if __name__ == "__main__":
    main()