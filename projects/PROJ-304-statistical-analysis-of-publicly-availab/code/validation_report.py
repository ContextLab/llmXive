"""
T034: Generate final comparison report in data/processed/validation_report.json.

This script aggregates results from model selection, success criteria validation,
and spatial cross-validation to produce the final validation report.
"""
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional
from logger import get_logger, get_project_root
from model_selection import load_model_results, select_best_model
from validation import check_success_criteria
from hygiene import compute_and_record_checksums

logger = get_logger(__name__)

def load_sc_report() -> Optional[Dict[str, Any]]:
    """Load the success criteria validation report generated by T033."""
    sc_path = get_project_root() / "data" / "processed" / "sc_validation_report.json"
    if not sc_path.exists():
        logger.warning(f"Success criteria report not found at {sc_path}. "
                       "Ensure T033 has been completed.")
        return None
    with open(sc_path, 'r') as f:
        return json.load(f)

def load_cv_metrics() -> Optional[Dict[str, Any]]:
    """
    Load cross-validation metrics.
    Note: T030 (performance metrics) is marked as incomplete in the task list,
    but T029 (CV implementation) and T031 (permutation test) are complete.
    We attempt to load a metrics file if it exists, otherwise return a placeholder
    structure indicating metrics are pending or derived from model results.
    """
    # Attempt to load from a potential aggregated metrics file if it exists
    cv_path = get_project_root() / "data" / "processed" / "cv_metrics_aggregated.json"
    if cv_path.exists():
        with open(cv_path, 'r') as f:
            return json.load(f)
    
    # Fallback: derive from model results if available, as T030 might not have
    # generated a separate file yet but T026 (model_results.json) exists.
    model_results = load_model_results()
    if model_results:
        # Extract key metrics from model results for the report
        return {
            "status": "derived_from_model_results",
            "note": "T030 not yet fully implemented as separate artifact; metrics derived from T026.",
            "models": {
                name: {
                    "rmse": results.get("rmse", "N/A"),
                    "r2": results.get("r_squared", "N/A"),
                    "aic": results.get("aic", "N/A")
                }
                for name, results in model_results.get("models", {}).items()
            }
        }
    
    logger.warning("No cross-validation metrics found. Report will be incomplete.")
    return None

def generate_final_report() -> Dict[str, Any]:
    """
    Assemble the final validation report by combining:
    1. Best model selection (T032)
    2. Success criteria validation (T033)
    3. Cross-validation metrics (T030/T029)
    4. Permutation test results (T031)
    """
    logger.info("Generating final comparison report (T034)...")
    
    report = {
        "report_metadata": {
            "task_id": "T034",
            "user_story": "US3",
            "description": "Final comparison report for spatial noise pollution models",
            "generated_at": None  # Will be set by hygiene or script
        },
        "best_model": {},
        "success_criteria": {},
        "cross_validation": {},
        "permutation_test": {},
        "recommendations": []
    }

    # 1. Load Best Model (T032)
    model_results = load_model_results()
    if model_results:
        best_model_name, best_model_data = select_best_model(model_results)
        report["best_model"] = {
            "model_name": best_model_name,
            "details": best_model_data,
            "selection_criteria": "Lowest AIC with significant RMSE reduction"
        }
        logger.info(f"Best model selected: {best_model_name}")
    else:
        report["best_model"] = {"error": "Model results not found. Ensure T026 is complete."}
        logger.error("Model results not found.")

    # 2. Load Success Criteria (T033)
    sc_report = load_sc_report()
    if sc_report:
        report["success_criteria"] = sc_report
        # Add recommendations based on SC status
        if sc_report.get("all_criteria_met", False):
            report["recommendations"].append("All success criteria met. Pipeline is ready for deployment.")
        else:
            report["recommendations"].append("Some success criteria not met. Review sc_validation_report.json for details.")
    else:
        report["success_criteria"] = {"error": "Success criteria report not found. Ensure T033 is complete."}

    # 3. Load Cross-Validation Metrics (T030/T029)
    cv_metrics = load_cv_metrics()
    if cv_metrics:
        report["cross_validation"] = cv_metrics
    else:
        report["cross_validation"] = {"error": "Cross-validation metrics not found."}

    # 4. Permutation Test (T031)
    # Assuming permutation test results are part of the CV metrics or model selection
    # If T031 generated a separate file, load it here. For now, we assume it's integrated.
    if cv_metrics and "permutation_test" in cv_metrics:
        report["permutation_test"] = cv_metrics["permutation_test"]
    elif model_results and "permutation_test" in model_results:
        report["permutation_test"] = model_results["permutation_test"]
    else:
        report["permutation_test"] = {"status": "not_found", "note": "Check T031 output."}

    # 5. Final Recommendations
    if report["best_model"] and "error" not in report["best_model"]:
        if report["success_criteria"].get("all_criteria_met", False):
            report["recommendations"].append(
                f"Deploy the {report['best_model']['model_name']} model for production use."
            )
        else:
            report["recommendations"].append(
                f"Model {report['best_model']['model_name']} is the best available, but success criteria are not fully met."
            )

    return report

def save_report(report: Dict[str, Any]) -> Path:
    """Save the final report to data/processed/validation_report.json."""
    output_path = get_project_root() / "data" / "processed" / "validation_report.json"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2, default=str)
    
    logger.info(f"Final report saved to {output_path}")
    return output_path

def main():
    """Main entry point for T034."""
    logger.info("Starting T034: Generate final comparison report")
    
    try:
        report = generate_final_report()
        output_path = save_report(report)
        
        # Update checksums
        compute_and_record_checksums()
        
        logger.info("T034 completed successfully.")
        return 0
    except Exception as e:
        logger.error(f"T034 failed with error: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    exit(main())
