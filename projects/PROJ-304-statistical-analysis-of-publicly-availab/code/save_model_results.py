"""
Save model outputs to JSON.

This script loads the model results dictionary generated by `code/models.py`,
applies FDR correction if not already applied (or assumes T023 has done it),
and writes the final coefficients, p-values, AIC, R², and Moran's I to
`data/processed/model_results.json`.

It relies on the output of T022 (robust SEs) and T023 (FDR correction) being
present in the model results structure or passed via the models module.
"""
