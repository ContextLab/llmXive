logger = get_logger(__name__)

def save_model_results(results: Dict[str, Any], output_path: Path) -> None:
    """
    Save the model results dictionary to a JSON file.

    Args:
        results: Dictionary containing model outputs (coefficients, p-values, AIC, R², Moran's I).
        output_path: Path to the output JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Ensure data types are JSON serializable (numpy types -> python types)
    def make_serializable(obj):
        if isinstance(obj, dict):
            return {k: make_serializable(v) for k, v in obj.items()}
        elif isinstance(obj, (list, tuple)):
            return [make_serializable(item) for item in obj]
        elif hasattr(obj, 'item'):  # numpy scalar
            return obj.item()
        elif hasattr(obj, 'tolist'):  # numpy array
            return obj.tolist()
        else:
            return obj

    serializable_results = make_serializable(results)

    with open(output_path, 'w') as f:
        json.dump(serializable_results, f, indent=2)
    
    logger.info(f"Model results saved to {output_path}")

