"""
Model Selection Logic for Urban Noise Pollution Analysis.

Implements logic to identify the best model based on lowest AIC
and significant RMSE reduction compared to the baseline OLS model.
"""

import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple

import numpy as np
import pandas as pd

from logger import get_logger, get_project_root

logger = get_logger(__name__)

# Configuration
RMSE_IMPROVEMENT_THRESHOLD = 0.05  # 5% reduction required to be considered significant
AIC_WEIGHT = 1.0  # Primary metric for selection, RMSE is the tie-breaker/significance check

def load_model_results(results_path: Path) -> List[Dict[str, Any]]:
    """
    Load model results from the JSON file generated by save_model_results.py.

    Args:
        results_path: Path to the model_results.json file.

    Returns:
        List of dictionaries containing model results.

    Raises:
        FileNotFoundError: If the results file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    if not results_path.exists():
        raise FileNotFoundError(f"Model results file not found: {results_path}")

    with open(results_path, 'r') as f:
        data = json.load(f)

    # Ensure data is a list of results
    if isinstance(data, dict) and 'results' in data:
        return data['results']
    elif isinstance(data, list):
        return data
    else:
        raise ValueError("Unexpected format in model_results.json")

def calculate_rmse_reduction(baseline_rmse: float, candidate_rmse: float) -> float:
    """
    Calculate the percentage reduction in RMSE.

    Args:
        baseline_rmse: RMSE of the baseline model (usually OLS).
        candidate_rmse: RMSE of the candidate model.

    Returns:
        Percentage reduction (positive if improvement, negative if worse).
    """
    if baseline_rmse == 0:
        return 0.0
    return ((baseline_rmse - candidate_rmse) / baseline_rmse) * 100.0

def is_rmse_significant(baseline_rmse: float, candidate_rmse: float, threshold: float = RMSE_IMPROVEMENT_THRESHOLD) -> bool:
    """
    Check if the RMSE reduction is significant.

    Args:
        baseline_rmse: RMSE of the baseline model.
        candidate_rmse: RMSE of the candidate model.
        threshold: Minimum percentage reduction required.

    Returns:
        True if the reduction is significant.
    """
    reduction = calculate_rmse_rmse_reduction(baseline_rmse, candidate_rmse)
    return reduction >= threshold

def select_best_model(
    model_results: List[Dict[str, Any]],
    baseline_model_name: str = "OLS",
    rmse_threshold: float = RMSE_IMPROVEMENT_THRESHOLD
) -> Tuple[Optional[Dict[str, Any]], Dict[str, Any]]:
    """
    Identify the best model based on lowest AIC and significant RMSE reduction.

    Selection Logic:
    1. Filter models that have converged and have valid metrics.
    2. Identify the baseline model (e.g., OLS) to compare against.
    3. Sort candidates by AIC (ascending).
    4. Select the model with the lowest AIC that also shows a significant
       RMSE reduction compared to the baseline.
    5. If no model meets the RMSE threshold, fall back to the lowest AIC model
       but flag it as not meeting the RMSE significance criteria.

    Args:
        model_results: List of model result dictionaries.
        baseline_model_name: Name of the baseline model to compare against.
        rmse_threshold: Minimum percentage RMSE reduction required.

    Returns:
        Tuple of (best_model_dict, selection_summary_dict).
    """
    if not model_results:
        logger.warning("No model results provided for selection.")
        return None, {"status": "no_data", "reason": "Empty model results"}

    # Filter valid results
    valid_results = [
        r for r in model_results
        if r.get('converged', False) and r.get('metrics', {}).get('rmse') is not None and r.get('metrics', {}).get('aic') is not None
    ]

    if not valid_results:
        logger.warning("No valid converged models found.")
        return None, {"status": "no_valid_models", "reason": "No converged models with metrics"}

    # Identify baseline
    baseline = None
    for r in valid_results:
        if r.get('model_type', '').upper() == baseline_model_name.upper():
            baseline = r
            break

    if not baseline:
        logger.warning(f"Baseline model '{baseline_model_name}' not found. Using first model as reference.")
        baseline = valid_results[0]

    baseline_rmse = baseline['metrics']['rmse']
    baseline_aic = baseline['metrics']['aic']

    # Sort by AIC (ascending)
    sorted_candidates = sorted(valid_results, key=lambda x: x['metrics']['aic'])

    best_model = None
    selection_reason = ""

    # Strategy: Find the lowest AIC model that also improves RMSE significantly
    # If none do, pick the lowest AIC but mark as not significant
    
    significant_candidates = []
    for candidate in sorted_candidates:
        candidate_rmse = candidate['metrics']['rmse']
        reduction = calculate_rmse_reduction(baseline_rmse, candidate_rmse)
        candidate['metrics']['rmse_reduction_pct'] = reduction
        
        if reduction >= rmse_threshold:
            significant_candidates.append(candidate)

    if significant_candidates:
        # Pick the one with lowest AIC among significant ones
        best_model = significant_candidates[0]
        selection_reason = f"Lowest AIC ({best_model['metrics']['aic']:.2f}) with significant RMSE reduction ({best_model['metrics']['rmse_reduction_pct']:.2f}%)"
    else:
        # Fallback: Lowest AIC overall, but RMSE reduction not significant
        best_model = sorted_candidates[0]
        selection_reason = f"Lowest AIC ({best_model['metrics']['aic']:.2f}), but RMSE reduction ({best_model['metrics'].get('rmse_reduction_pct', 0):.2f}%) below threshold ({rmse_threshold}%)"

    summary = {
        "status": "success",
        "baseline_model": baseline_model_name,
        "baseline_rmse": baseline_rmse,
        "baseline_aic": baseline_aic,
        "best_model_type": best_model.get('model_type'),
        "best_model_aic": best_model['metrics']['aic'],
        "best_model_rmse": best_model['metrics']['rmse'],
        "rmse_reduction_pct": best_model['metrics'].get('rmse_reduction_pct', 0),
        "selection_reason": selection_reason,
        "threshold_applied": rmse_threshold
    }

    return best_model, summary

def main():
    """
    Main entry point for model selection.
    Loads results, selects best model, and writes the selection report.
    """
    project_root = get_project_root()
    results_path = project_root / "data" / "processed" / "model_results.json"
    output_path = project_root / "data" / "processed" / "model_selection_report.json"

    logger.info(f"Starting model selection. Loading results from: {results_path}")

    try:
        results = load_model_results(results_path)
    except FileNotFoundError as e:
        logger.error(f"Failed to load model results: {e}")
        return
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse model results: {e}")
        return

    best_model, summary = select_best_model(results)

    if best_model:
        logger.info(f"Best model selected: {summary['best_model_type']}")
        logger.info(f"Reason: {summary['selection_reason']}")
        
        # Prepare output
        output_data = {
            "selection_summary": summary,
            "best_model_details": best_model
        }

        # Write report
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, 'w') as f:
            json.dump(output_data, f, indent=2)

        logger.info(f"Model selection report written to: {output_path}")
    else:
        logger.error("Could not select a best model.")
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, 'w') as f:
            json.dump({"status": "failed", "reason": summary.get("reason", "Unknown")}, f, indent=2)

if __name__ == "__main__":
    main()
