"""
src/experiment/verify_clips.py
--------------------------------
This module implements the verification step for the main‑study video clips.
It computes SHA‑256 checksums for each clip stored in the local archive,
combines them with dataset provenance information (URL and version ID) from
the dataset manifest generated by ``src.experiment.fetch_clips`` and writes
a consolidated manifest to ``data/metadata/clip_manifest.json``.

The implementation is deliberately defensive:
* If the expected stimuli directory does not exist, a ``FileNotFoundError``
  is raised.
* If the dataset manifest is missing, a ``FileNotFoundError`` is raised.
* If a file cannot be read (e.g., permission error), the error is logged
  and processing continues for the remaining files.
* An empty clip directory results in a manifest with an empty ``clips``
  mapping – this satisfies the test expectations for the “no video files”
  scenario.
"""

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import Dict, Any

# Re‑use the checksum helper from the fetch script – it is part of the public API.
from src.experiment.fetch_clips import compute_sha256
from src.config import get_relative_path

logger = logging.getLogger(__name__)
logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")


def _load_dataset_manifest() -> Dict[str, Any]:
    """
    Load the dataset manifest generated by ``fetch_clips``.
    Expected keys: ``dataset_url`` and ``version_id``.
    """
    manifest_path = get_relative_path("data/metadata/dataset_manifest.json")
    if not manifest_path.is_file():
        raise FileNotFoundError(
            f"Dataset manifest not found at '{manifest_path}'. "
            "Run `src.experiment.fetch_clips` first."
        )
    with manifest_path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    # Basic validation – the tests rely on these fields being present.
    if "dataset_url" not in data or "version_id" not in data:
        raise ValueError(
            f"Dataset manifest at '{manifest_path}' is missing required keys."
        )
    return data


def verify_clips(
    stimuli_dir: Path | None = None,
    output_manifest_path: Path | None = None,
) -> Dict[str, Any]:
    """
    Compute SHA‑256 checksums for every file in ``stimuli_dir`` and write a
    manifest that records the dataset provenance and per‑clip checksums.

    Parameters
    ----------
    stimuli_dir: Path | None
        Directory containing the downloaded clips. If ``None`` the default
        ``data/stimuli/raw`` (relative to the project root) is used.
    output_manifest_path: Path | None
        Destination for the generated manifest. If ``None`` the default
        ``data/metadata/clip_manifest.json`` is used.

    Returns
    -------
    dict
        The manifest dictionary that was written to disk.
    """
    # Resolve defaults using the project's path helper.
    if stimuli_dir is None:
        stimuli_dir = get_relative_path("data/stimuli/raw")
    if output_manifest_path is None:
        output_manifest_path = get_relative_path("data/metadata/clip_manifest.json")

    # Ensure the stimuli directory exists.
    if not stimuli_dir.is_dir():
        raise FileNotFoundError(
            f"Stimuli directory '{stimuli_dir}' does not exist."
        )

    # Load provenance information from the dataset manifest.
    dataset_info = _load_dataset_manifest()
    dataset_url = dataset_info["dataset_url"]
    version_id = dataset_info["version_id"]

    # Gather all files (non‑recursive – the fetch script stores clips directly).
    clip_files = [p for p in stimuli_dir.iterdir() if p.is_file()]

    # Compute checksums, handling individual file errors gracefully.
    checksums: Dict[str, str] = {}
    for clip_path in clip_files:
        try:
            checksum = compute_sha256(clip_path)
            # Store the path relative to the stimuli directory for readability.
            rel_path = clip_path.relative_to(stimuli_dir).as_posix()
            checksums[rel_path] = checksum
            logger.info("Checksum computed for %s", clip_path.name)
        except Exception as exc:  # pragma: no cover – exercised via test partial failure
            logger.error(
                "Failed to compute checksum for %s: %s", clip_path, exc
            )
            # Continue processing remaining files.

    # Assemble the final manifest.
    manifest: Dict[str, Any] = {
        "dataset_url": dataset_url,
        "version_id": version_id,
        "clips": checksums,
    }

    # Ensure the parent directory exists before writing.
    output_manifest_path.parent.mkdir(parents=True, exist_ok=True)
    with output_manifest_path.open("w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)

    logger.info(
        "Clip manifest written to %s (total clips: %d)",
        output_manifest_path,
        len(checksums),
    )
    return manifest


def parse_arguments() -> argparse.Namespace:
    """
    CLI argument parser.
    """
    parser = argparse.ArgumentParser(
        description="Verify downloaded meeting clips and record their checksums."
    )
    parser.add_argument(
        "--stimuli-dir",
        type=Path,
        default=get_relative_path("data/stimuli/raw"),
        help="Directory containing the downloaded clips (default: data/stimuli/raw).",
    )
    parser.add_argument(
        "--output-manifest",
        type=Path,
        default=get_relative_path("data/metadata/clip_manifest.json"),
        help=(
            "Path to write the clip manifest JSON file "
            "(default: data/metadata/clip_manifest.json)."
        ),
    )
    return parser.parse_args()


def main() -> None:
    """
    Entry‑point for the module when executed as a script.
    """
    args = parse_arguments()
    try:
        verify_clips(stimuli_dir=args.stimuli_dir, output_manifest_path=args.output_manifest)
    except Exception as exc:
        logger.error("Verification failed: %s", exc)
        sys.exit(1)


if __name__ == "__main__":
    main()
