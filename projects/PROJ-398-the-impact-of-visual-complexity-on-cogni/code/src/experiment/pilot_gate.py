"""
src/experiment/pilot_gate.py
----------------------------

This module provides utilities for the pilot study gate step.  It loads the
human‑ratings CSV, loads the automatically extracted metrics CSV, aggregates
them per stimulus, and computes the Pearson correlation between the human
complexity scores and each automated metric.

The functions are deliberately lightweight and have no side‑effects beyond
reading files and returning pandas DataFrames or scalar correlation results.
They are used by the downstream pilot‑gate test suite and by later analysis
steps.

The implementation follows the project's configuration conventions:
- Paths are resolved via ``src.config.get_relative_path`` which returns a
  ``pathlib.Path`` anchored at the repository root.
- The global random seed is defined elsewhere; this module does not rely on
  randomness.
- All I/O failures raise informative exceptions – no silent fall‑backs or
  synthetic data generation.
"""

import pandas as pd
from pathlib import Path
from typing import Tuple

from scipy.stats import pearsonr

from src.config import get_relative_path

# ----------------------------------------------------------------------
# Public API (as declared in the project’s API surface)
# ----------------------------------------------------------------------
__all__ = [
    "load_human_ratings",
    "load_metrics",
    "aggregate_metrics",
    "compute_correlation",
    "main",
]

# ----------------------------------------------------------------------
# Helper constants
# ----------------------------------------------------------------------
# Expected column names for the human‑ratings CSV.  The test suite checks
# that these columns exist; additional columns are ignored.
_HUMAN_RATINGS_REQUIRED_COLUMNS = {
    "image_id",
    "participant_id",
    "complexity_score",
}

# Expected column names for the metrics CSV generated by ``src.metrics.extract``.
_METRICS_REQUIRED_COLUMNS = {
    "image_id",
    "entropy",
    "color_variance",
    "object_count",
}

# ----------------------------------------------------------------------
# Function implementations
# ----------------------------------------------------------------------
def load_human_ratings(csv_path: Path | None = None) -> pd.DataFrame:
    """
    Load the human ratings CSV into a pandas DataFrame.

    Parameters
    ----------
    csv_path: pathlib.Path | None
        Optional explicit path to the CSV file.  If omitted, the default
        location ``data/measurements/human_ratings.csv`` (relative to the
        repository root) is used.

    Returns
    -------
    pandas.DataFrame
        DataFrame containing the human ratings.

    Raises
    ------
    FileNotFoundError
        If the CSV file does not exist.
    ValueError
        If any of the required columns are missing.
    """
    if csv_path is None:
        csv_path = get_relative_path("data/measurements/human_ratings.csv")
    # Ensure the file exists – let the exception propagate for a clear error.
    if not csv_path.is_file():
        raise FileNotFoundError(f"Human ratings CSV not found at {csv_path}")

    df = pd.read_csv(csv_path)

    missing = _HUMAN_RATINGS_REQUIRED_COLUMNS - set(df.columns)
    if missing:
        raise ValueError(
            f"Human ratings CSV is missing required columns: {sorted(missing)}"
        )
    return df


def load_metrics(csv_path: Path | None = None) -> pd.DataFrame:
    """
    Load the automated metrics CSV into a pandas DataFrame.

    Parameters
    ----------
    csv_path: pathlib.Path | None
        Optional explicit path to the metrics CSV.  Defaults to
        ``data/processed/metrics.csv``.

    Returns
    -------
    pandas.DataFrame
        DataFrame containing the extracted visual‑complexity metrics.

    Raises
    ------
    FileNotFoundError
        If the CSV file does not exist.
    ValueError
        If required metric columns are missing.
    """
    if csv_path is None:
        csv_path = get_relative_path("data/processed/metrics.csv")
    if not csv_path.is_file():
        raise FileNotFoundError(f"Metrics CSV not found at {csv_path}")

    df = pd.read_csv(csv_path)

    missing = _METRICS_REQUIRED_COLUMNS - set(df.columns)
    if missing:
        raise ValueError(
            f"Metrics CSV is missing required columns: {sorted(missing)}"
        )
    return df


def aggregate_metrics(
    human_df: pd.DataFrame, metrics_df: pd.DataFrame
) -> pd.DataFrame:
    """
    Merge human ratings with automated metrics on ``image_id``.

    The merge is an inner join – only images present in **both** tables are
    retained.  This mirrors the intended analysis where each stimulus must
    have a human rating and a set of computed metrics.

    Parameters
    ----------
    human_df : pandas.DataFrame
        DataFrame returned by ``load_human_ratings``.
    metrics_df : pandas.DataFrame
        DataFrame returned by ``load_metrics``.

    Returns
    -------
    pandas.DataFrame
        A combined DataFrame containing the columns:
        ``image_id, participant_id, complexity_score,
        entropy, color_variance, object_count``.
    """
    merged = pd.merge(
        human_df,
        metrics_df,
        on="image_id",
        how="inner",
        suffixes=("_human", "_metric"),
    )
    # The test suite cares only that the required columns are present;
    # ordering is not strict.
    return merged


def compute_correlation(
    merged_df: pd.DataFrame,
) -> Tuple[float, float]:
    """
    Compute Pearson correlation between human complexity scores and each
    automated metric.  Returns the correlation coefficient and the associated
    p‑value for the **average** of the three metrics, which is a common
    summarisation used in the pilot gate.

    Parameters
    ----------
    merged_df : pandas.DataFrame
        Output of ``aggregate_metrics`` containing both human scores and
        metric columns.

    Returns
    -------
    tuple[float, float]
        ``(r, p)`` where ``r`` is Pearson's correlation coefficient and ``p``
        is the two‑tailed p‑value.
    """
    # Compute a simple average metric per stimulus for the correlation.
    metric_cols = ["entropy", "color_variance", "object_count"]
    if not all(col in merged_df.columns for col in metric_cols):
        raise ValueError(
            f"merged_df must contain metric columns {metric_cols}"
        )
    merged_df["metric_average"] = merged_df[metric_cols].mean(axis=1)
    r, p = pearsonr(merged_df["complexity_score"], merged_df["metric_average"])
    return r, p


def main() -> None:
    """
    Entry‑point for the ``pilot_gate`` script.  It loads the required CSV
    files, merges them, computes the correlation, and prints a concise
    summary to stdout.  The function is deliberately side‑effect free
    besides the console output, making it safe to invoke from CI or other
    automation.
    """
    human_df = load_human_ratings()
    metrics_df = load_metrics()
    merged_df = aggregate_metrics(human_df, metrics_df)
    r, p = compute_correlation(merged_df)

    print(f"Pilot gate correlation: r = {r:.4f}, p = {p:.4e}")

# ----------------------------------------------------------------------
# When executed as a script ``python -m src.experiment.pilot_gate``
# ----------------------------------------------------------------------
if __name__ == "__main__":
    main()