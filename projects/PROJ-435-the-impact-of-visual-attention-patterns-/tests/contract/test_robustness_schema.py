"""
Contract test for robustness report schema (Task T029).

This test verifies that the robustness analysis report generated by
`code/robustness_analysis.py` adheres to the required schema defined in the
project specifications (SC-003). It ensures that the output file
`data/derived/robustness_report.csv` contains the correct columns and data types
necessary for downstream validation of threshold stability.

The schema requirements are:
- fixation_threshold_ms: The duration cutoff used for this iteration (float/int).
- mean_belief_rating: The average belief rating for the filtered dataset (float).
- interaction_coefficient: The estimated coefficient for the three-way interaction
  (fixation_duration * valence * crt) from the mixed-effects model (float).
- interaction_p_value: The p-value associated with the interaction term (float).
- interaction_significant: Boolean indicating if p < 0.05 (bool).
- n_observations: Number of observations used in the regression (int).
"""

import os
import pytest
import pandas as pd
from pathlib import Path

# Path to the expected output artifact
ROBUSTNESS_REPORT_PATH = Path("data/derived/robustness_report.csv")

REQUIRED_COLUMNS = {
    "fixation_threshold_ms",
    "mean_belief_rating",
    "interaction_coefficient",
    "interaction_p_value",
    "interaction_significant",
    "n_observations",
}

REQUIRED_DTYPES = {
    "fixation_threshold_ms": "number",
    "mean_belief_rating": "number",
    "interaction_coefficient": "number",
    "interaction_p_value": "number",
    "interaction_significant": "bool",
    "n_observations": "integer",
}


@pytest.fixture(scope="module")
def robustness_report():
    """
    Load the robustness report if it exists.
    Skips the test if the file is missing (indicating the pipeline hasn't run yet).
    """
    if not ROBUSTNESS_REPORT_PATH.exists():
        pytest.skip(f"Robustness report not found at {ROBUSTNESS_REPORT_PATH}. "
                    "Run code/robustness_analysis.py first.")
    return pd.read_csv(ROBUSTNESS_REPORT_PATH)


def test_file_exists():
    """Verify the robustness report file exists."""
    assert ROBUSTNESS_REPORT_PATH.exists(), (
        f"Robustness report file {ROBUSTNESS_REPORT_PATH} does not exist. "
        "Ensure code/robustness_analysis.py has been executed."
    )


def test_has_required_columns(robustness_report):
    """Verify the report contains all required columns."""
    missing_columns = REQUIRED_COLUMNS - set(robustness_report.columns)
    assert not missing_columns, (
        f"Robustness report is missing required columns: {missing_columns}. "
        f"Found columns: {list(robustness_report.columns)}"
    )


def test_column_data_types(robustness_report):
    """Verify that columns have the expected data types."""
    errors = []
    for col, expected_type in REQUIRED_DTYPES.items():
        if col not in robustness_report.columns:
            continue  # Handled by test_has_required_columns

        series = robustness_report[col]
        actual_type = series.dtype

        if expected_type == "number":
            if not pd.api.types.is_numeric_dtype(actual_type):
                errors.append(f"Column '{col}' is numeric but has dtype {actual_type}")
        elif expected_type == "integer":
            if not pd.api.types.is_integer_dtype(actual_type):
                # Allow float if it contains only integers, but strict check preferred
                if not (pd.api.types.is_float_dtype(actual_type) and series.equals(series.astype(int))):
                     errors.append(f"Column '{col}' should be integer but has dtype {actual_type}")
        elif expected_type == "bool":
            if not pd.api.types.is_bool_dtype(actual_type):
                errors.append(f"Column '{col}' is boolean but has dtype {actual_type}")

    if errors:
        pytest.fail("Data type errors found:\n" + "\n".join(errors))


def test_no_null_values(robustness_report):
    """Verify that no required columns contain null values."""
    null_counts = robustness_report[list(REQUIRED_COLUMNS)].isnull().sum()
    if null_counts.any():
        null_details = null_counts[null_counts > 0].to_dict()
        pytest.fail(f"Null values found in required columns: {null_details}")


def test_threshold_sweep_logic(robustness_report):
    """
    Verify that the report actually represents a sweep of different thresholds.
    There must be at least 2 unique threshold values.
    """
    unique_thresholds = robustness_report["fixation_threshold_ms"].nunique()
    assert unique_thresholds >= 2, (
        f"Robustness report must contain at least 2 unique fixation thresholds. "
        f"Found {unique_thresholds}."
    )


def test_interaction_significant_is_boolean(robustness_report):
    """
    Specifically ensure the significant flag is strictly boolean (0/1 or True/False).
    """
    if robustness_report["interaction_significant"].dtype != bool:
        # Check if it's 0/1 integers which are effectively boolean
        unique_vals = set(robustness_report["interaction_significant"].unique())
        if unique_vals not in [{0, 1}, {0}, {1}]:
            pytest.fail(
                f"Column 'interaction_significant' should be boolean or 0/1 integers. "
                f"Found unique values: {unique_vals}"
            )