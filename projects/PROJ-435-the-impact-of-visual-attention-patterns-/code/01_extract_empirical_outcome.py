"""
Task T004b: Extract Empirical Outcomes from Raw Eye-Tracking Data.

This script loads the raw dataset fetched in T005 (from Hugging Face or verified URL),
verifies the presence of required columns ('belief_rating', 'headline_text'),
and extracts them into a derived CSV file.

Constraint: MUST NOT generate synthetic values for 'belief_rating'.
Constraint: MUST fail loudly if real data is missing or schema is invalid.
"""
import os
import sys
import logging
import hashlib
import json
from pathlib import Path
from typing import List, Dict, Any

import pandas as pd
import numpy as np

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from utils.environment_manager import get_paths, load_config, setup_logging
from utils.logging_config import get_pipeline_logger

def compute_sha256(file_path: Path) -> str:
    """Compute SHA-256 checksum of a file."""
    sha256_hash = hashlib.sha256()
    with open(file_path, "rb") as f:
        for byte_block in iter(lambda: f.read(4096), b""):
            sha256_hash.update(byte_block)
    return sha256_hash.hexdigest()

def load_raw_data(config: Dict[str, Any]) -> pd.DataFrame:
    """
    Load the raw dataset.
    Expects T005 to have placed the file in data/raw/ or fetched it.
    We look for the specific file generated by T005.
    """
    paths = get_paths()
    raw_dir = paths["data_raw"]
    
    # T005 should have downloaded the file. We look for the most recent parquet or csv.
    # Based on T005 description, it likely saves as 'raw_data.parquet' or similar.
    # We scan for available files to be robust.
    possible_files = list(raw_dir.glob("*.parquet")) + list(raw_dir.glob("*.csv"))
    
    if not possible_files:
        # Fallback: Try to trigger fetch if T005 failed or wasn't run, 
        # but per constraints, we must fail loudly if real source is missing.
        # We do NOT implement a fetch here; we assume T005 handled it.
        raise FileNotFoundError(
            f"No raw data files found in {raw_dir}. "
            "Ensure T005 (fetch_eye_tracking_data) has been completed successfully."
        )

    # Prefer parquet for speed, otherwise csv
    if possible_files:
        data_file = max(possible_files, key=lambda p: p.stat().st_mtime)
        logger = get_pipeline_logger()
        logger.info(f"Loading raw data from: {data_file}")
        
        if data_file.suffix == ".parquet":
            df = pd.read_parquet(data_file)
        else:
            df = pd.read_csv(data_file)
        
        return df
    else:
        raise FileNotFoundError(f"Could not locate raw data file in {raw_dir}")

def verify_schema(df: pd.DataFrame) -> None:
    """
    Verify that the dataset contains the required columns.
    Raises an error if 'belief_rating' or 'headline_text' are missing.
    """
    required_cols = ['belief_rating', 'headline_text']
    missing_cols = [col for col in required_cols if col not in df.columns]
    
    if missing_cols:
        raise ValueError(
            f"Schema validation failed. Missing required columns: {missing_cols}. "
            f"Available columns: {list(df.columns)}. "
            "This script cannot proceed without real empirical data containing these fields."
        )

def extract_outcomes(df: pd.DataFrame) -> pd.DataFrame:
    """
    Extract the specific columns required for the empirical outcomes.
    Output columns: participant_id, headline_id, belief_rating, headline_text.
    """
    # Ensure ID columns exist; if not, try to infer or raise error
    id_cols = ['participant_id', 'headline_id']
    missing_ids = [col for col in id_cols if col not in df.columns]
    
    if missing_ids:
        # Try common variations if exact names are missing, but strict failure is preferred
        # for data integrity unless we know the dataset schema well.
        # For this task, we assume the T005 dataset has standard names.
        raise ValueError(
            f"Missing ID columns required for output: {missing_ids}. "
            f"Available: {list(df.columns)}"
        )

    output_df = df[id_cols + ['belief_rating', 'headline_text']].copy()
    
    # Clean data types
    output_df['belief_rating'] = pd.to_numeric(output_df['belief_rating'], errors='raise')
    
    # Drop rows where belief_rating is NaN (invalid data)
    initial_count = len(output_df)
    output_df = output_df.dropna(subset=['belief_rating'])
    dropped_count = initial_count - len(output_df)
    
    if dropped_count > 0:
        logger = get_pipeline_logger()
        logger.warning(f"Dropped {dropped_count} rows with missing belief_rating.")
        
    return output_df

def main():
    """Main execution entry point."""
    # Setup logging
    config = load_config()
    setup_logging(config)
    logger = get_pipeline_logger()
    
    logger.info("Starting T004b: Extract Empirical Outcomes")
    
    try:
        # 1. Load raw data
        logger.info("Loading raw dataset...")
        raw_df = load_raw_data(config)
        logger.info(f"Loaded {len(raw_df)} rows.")
        
        # 2. Verify schema
        logger.info("Verifying schema...")
        verify_schema(raw_df)
        
        # 3. Extract outcomes
        logger.info("Extracting belief_rating and headline_text...")
        outcomes_df = extract_outcomes(raw_df)
        
        # 4. Save to derived directory
        paths = get_paths()
        output_path = paths["data_derived"] / "empirical_outcomes.csv"
        
        outcomes_df.to_csv(output_path, index=False)
        logger.info(f"Successfully wrote empirical outcomes to {output_path}")
        
        # 5. Compute and store checksum for the output
        output_checksum = compute_sha256(output_path)
        hash_file = paths["state"] / "data_hashes.json"
        
        current_hashes = {}
        if hash_file.exists():
            with open(hash_file, 'r') as f:
                current_hashes = json.load(f)
        
        current_hashes["empirical_outcomes.csv"] = output_checksum
        
        with open(hash_file, 'w') as f:
            json.dump(current_hashes, f, indent=2)
        
        logger.info(f"Updated state/data_hashes.json with checksum for empirical_outcomes.csv")
        
    except FileNotFoundError as fnf_err:
        logger.error(f"File not found: {fnf_err}")
        raise
    except ValueError as val_err:
        logger.error(f"Data validation error: {val_err}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during T004b execution: {e}")
        raise

if __name__ == "__main__":
    main()