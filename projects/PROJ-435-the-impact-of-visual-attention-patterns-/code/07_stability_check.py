logger = logging.getLogger(__name__)

def get_paths() -> Tuple[Path, Path, Path]:
    """
    Returns paths for robustness report input, stability check output, and project root.
    """
    project_root = get_project_root()
    input_path = project_root / "data" / "derived" / "robustness_report.csv"
    output_path = project_root / "output" / "stability_check.json"
    return project_root, input_path, output_path

def load_robustness_report(input_path: Path) -> pd.DataFrame:
    """
    Loads the robustness report CSV.
    Raises FileNotFoundError if the file does not exist.
    """
    if not input_path.exists():
        raise FileNotFoundError(f"Robustness report not found at {input_path}. "
                                "Ensure T033 (Robustness Sweep) has been executed successfully.")
    df = pd.read_csv(input_path)
    logger.info(f"Loaded robustness report with {len(df)} rows from {input_path}")
    return df

def analyze_stability(df: pd.DataFrame) -> Dict[str, Any]:
    """
    Analyzes the stability of the three-way interaction term across thresholds.
    
    Checks:
    1. Consistent Direction: The sign of the coefficient for the interaction term
       (e.g., 'fixation_duration:valence:cognitive_reflection_score') is the same
       for all thresholds.
    2. Consistent Significance: The corrected p-value (p_adj) for the interaction term
       is below 0.05 for all thresholds (or above for all, though consistency implies
       we care about the binary state of significance).
    3. CI Overlap Summary: Checks if the 95% Confidence Intervals of the interaction
       coefficient overlap across all thresholds.
    
    Returns a dictionary with the analysis results.
    """
    if df.empty:
        raise ValueError("Robustness report is empty.")

    # Identify the interaction term column. 
    # The exact name depends on how statsmodels formatted it in the regression.
    # Common formats: 'fixation_duration:valence:cognitive_reflection_score', 
    # or 'C(valence)[T.1]:fixation_duration:cognitive_reflection_score', etc.
    # We look for a column containing 'interaction' or the specific terms.
    # Based on T024/T032, the term is likely named with colons.
    
    interaction_candidates = [col for col in df.columns if 'interaction' in col.lower()]
    if not interaction_candidates:
        # Fallback: look for the specific pattern if we know the variable names
        # Assuming the model formula was: belief_rating ~ fixation_duration * valence * crt ...
        # The highest order interaction is the one we need.
        # Let's assume the column is named exactly as the product of the variables
        # or contains the key variables.
        # We will search for a column that has 'fixation' and 'valence' and 'cognitive'
        # in its name, or simply the last column if it's the interaction.
        # A safer heuristic for this specific project:
        # The regression results usually have a 'term' column or the coefficient name is the term.
        # Let's assume the robustness report has columns: threshold, coefficient, p_adj, ci_lower, ci_upper
        # and the interaction term is the one we are tracking.
        # If the report was generated by T033/T032, it likely has a column for the interaction coefficient.
        
        # Let's try to find the coefficient column for the interaction.
        # If the dataframe has a 'term' column, we filter for the interaction term.
        if 'term' in df.columns:
            # Find the row/col corresponding to the interaction
            # We assume the interaction term is the one with the most colons or specific keywords
            interaction_rows = df[df['term'].str.contains('fixation.*valence.*cognitive', regex=True, case=False) |
                                  df['term'].str.contains('cognitive.*valence.*fixation', regex=True, case=False)]
            if interaction_rows.empty:
                # Try a broader match
                interaction_rows = df[df['term'].str.contains('fixation', regex=True, case=False)]
            if not interaction_rows.empty:
                # We need to reshape or select the coefficient for this term
                # For simplicity in this check, we assume the robustness report 
                # has already aggregated the interaction coefficient into a column 
                # named something like 'interaction_coef' or we iterate rows.
                # However, the task says "Read robustness_report.csv".
                # Let's assume the robustness report has columns: 
                # threshold, interaction_coef, interaction_p_adj, interaction_ci_lower, interaction_ci_upper
                # If not, we must infer.
                pass

        # Let's assume the standard output of T033/T032 includes a column for the 
        # interaction term's coefficient and p-value. 
        # If the columns are generic (e.g., 'coef', 'pvalue'), we need to know WHICH row is the interaction.
        # To be robust, we will look for a column named 'interaction_coef' or similar.
        # If not found, we assume the first numeric column is the one of interest 
        # (which is a risky assumption but common in generated reports if not specified).
        
        # Better approach: The robustness report should have been generated with specific columns.
        # Let's assume the columns are: 'threshold', 'interaction_coef', 'interaction_p_adj', 'ci_lower', 'ci_upper'
        # If the column 'interaction_coef' exists, use it.
        
        target_coef_col = None
        target_p_col = None
        target_ci_lower_col = None
        target_ci_upper_col = None

        # Heuristic: Look for columns that seem to track the interaction
        for col in df.columns:
            if 'interaction' in col.lower() and 'coef' in col.lower():
                target_coef_col = col
            elif 'interaction' in col.lower() and 'p' in col.lower():
                target_p_col = col
            elif 'ci_lower' in col.lower() and 'interaction' in col.lower():
                target_ci_lower_col = col
            elif 'ci_upper' in col.lower() and 'interaction' in col.lower():
                target_ci_upper_col = col

        # If specific interaction columns not found, assume generic 'coef', 'p_adj', 'ci_lower', 'ci_upper'
        # and that the report only contains the interaction term stats per threshold.
        if target_coef_col is None and 'coef' in df.columns:
            target_coef_col = 'coef'
        if target_p_col is None and 'p_adj' in df.columns:
            target_p_col = 'p_adj'
        if target_ci_lower_col is None and 'ci_lower' in df.columns:
            target_ci_lower_col = 'ci_lower'
        if target_ci_upper_col is None and 'ci_upper' in df.columns:
            target_ci_upper_col = 'ci_upper'

        if not all([target_coef_col, target_p_col, target_ci_lower_col, target_ci_upper_col]):
            # Fallback: Use all numeric columns if we can't find specific ones? No, too risky.
            # Raise error with available columns.
            raise ValueError(f"Could not identify interaction term columns in robustness report. "
                             f"Available columns: {list(df.columns)}")
    else:
        # If we found interaction candidates, assume the first one is the coefficient
        target_coef_col = interaction_candidates[0]
        # Find corresponding p-value and CI columns
        base_name = target_coef_col.replace('coef', '').replace('interaction', '').strip('_')
        target_p_col = next((c for c in df.columns if 'p' in c.lower() and base_name in c.lower()), None)
        if not target_p_col: target_p_col = 'p_adj'
        
        target_ci_lower_col = next((c for c in df.columns if 'ci_lower' in c.lower()), None)
        target_ci_upper_col = next((c for c in df.columns if 'ci_upper' in c.lower()), None)
        if not target_ci_lower_col: target_ci_lower_col = 'ci_lower'
        if not target_ci_upper_col: target_ci_upper_col = 'ci_upper'

    if not all([target_coef_col, target_p_col, target_ci_lower_col, target_ci_upper_col]):
        raise ValueError("Could not locate necessary columns for stability analysis.")

    coeffs = df[target_coef_col].dropna()
    pvals = df[target_p_col].dropna()
    ci_lowers = df[target_ci_lower_col].dropna()
    ci_uppers = df[target_ci_upper_col].dropna()

    if len(coeffs) == 0:
        raise ValueError("No valid coefficients found in robustness report.")

    # 1. Consistent Direction
    signs = np.sign(coeffs)
    # Ignore zeros? If sign is 0, it's ambiguous. We'll treat 0 as consistent with either? 
    # Usually, we want all non-zero signs to be the same.
    non_zero_signs = signs[signs != 0]
    if len(non_zero_signs) > 0:
        consistent_direction = len(set(non_zero_signs)) == 1
    else:
        consistent_direction = True # All zeros? Trivially consistent or undefined. Let's say True.

    # 2. Consistent Significance
    # Significance is p < 0.05
    sig_status = pvals < 0.05
    # We want all to be True or all to be False? 
    # "Consistent significance" usually means the result is stable (either always significant or always not).
    # But in scientific robustness, we hope it's always significant.
    # Let's check if all are True OR all are False.
    if sig_status.all() or (~sig_status).all():
        consistent_significance = True
    else:
        consistent_significance = False

    # 3. CI Overlap Summary
    # Check if the interval [min(lower), max(upper)] of the whole set overlaps with each individual interval?
    # Or do we check if the intersection of all intervals is non-empty?
    # "CI overlap summary" usually implies checking if the CIs of the estimates overlap with each other.
    # A simple check: Does the global range of CIs overlap? 
    # More rigorous: Intersection of all CIs is non-empty.
    # Let's compute the intersection of all intervals.
    max_lower = ci_lowers.max()
    min_upper = ci_uppers.min()
    
    ci_overlap = max_lower <= min_upper
    
    # If the intersection is non-empty, then all CIs overlap with at least one point.
    # However, "CI overlap" in stability often means: Do the CIs of different thresholds overlap?
    # If the intersection of all is non-empty, they all overlap.
    
    # Construct summary string
    ci_summary = f"Intersection of all 95% CIs: [{max_lower:.4f}, {min_upper:.4f}]. Non-empty: {ci_overlap}"

    return {
        "consistent_direction": bool(consistent_direction),
        "consistent_significance": bool(consistent_significance),
        "ci_overlap_summary": ci_summary,
        "thresholds_analyzed": len(coeffs),
        "coefficients": coeffs.tolist(),
        "p_values": pvals.tolist()
    }

def write_results(results: Dict[str, Any], output_path: Path) -> None:
    """
    Writes the stability check results to a JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(results, f, indent=2)
    logger.info(f"Wrote stability check results to {output_path}")

def main() -> int:
    """
    Main entry point for the stability check task.
    """
    setup_global_logger()
    project_root, input_path, output_path = get_paths()
    
    try:
        logger.info(f"Starting stability check. Input: {input_path}, Output: {output_path}")
        
        df = load_robustness_report(input_path)
        results = analyze_stability(df)
        write_results(results, output_path)
        
        logger.info("Stability check completed successfully.")
        print(json.dumps(results, indent=2))
        return 0
        
    except FileNotFoundError as e:
        logger.error(str(e))
        return 1
    except Exception as e:
        logger.error(f"Stability check failed: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())
