"""
T007: Generate a summary of excluded participants.

This script reads the exclusion log generated by T018 and the preprocessed gaze data
to produce a comprehensive data quality report. It satisfies SC-001 by documenting
data loss and exclusion reasons.

Input:
    - output/exclusion_log.txt (from T018)
    - data/derived/preprocessed_gaze.csv (from T018)

Output:
    - output/data_quality_report.csv
"""

import os
import sys
import logging
import json
from pathlib import Path
from typing import Dict, List, Any, Optional
import pandas as pd

# Configure logging for this module
logger = logging.getLogger(__name__)

def get_project_root() -> Path:
    """Determine the project root directory (parent of the 'code' directory)."""
    current_file = Path(__file__).resolve()
    # Assuming this file is at code/02_data_quality_report.py
    return current_file.parent.parent

def setup_logger() -> logging.Logger:
    """Initialize the logger for this script."""
    # Try to load global logging config if available, otherwise use basic config
    try:
        from utils.logging_init import setup_global_logger
        setup_global_logger()
        return logging.getLogger(__name__)
    except ImportError:
        logging.basicConfig(
            level=logging.INFO,
            format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
        )
        return logging.getLogger(__name__)

def load_exclusion_log(log_path: Path) -> List[Dict[str, Any]]:
    """
    Load and parse the exclusion log file.

    The log file is expected to contain JSON objects, one per line (JSONL),
    or a list of JSON objects. We handle both formats.

    Args:
        log_path: Path to the exclusion log file.

    Returns:
        List of dictionaries containing exclusion details.
    """
    if not log_path.exists():
        raise FileNotFoundError(f"Exclusion log not found at {log_path}")

    exclusions = []
    with open(log_path, 'r', encoding='utf-8') as f:
        content = f.read().strip()
        if not content:
            return exclusions

        # Try to parse as JSONL (one JSON object per line)
        lines = content.split('\n')
        for line in lines:
            line = line.strip()
            if not line:
                continue
            try:
                record = json.loads(line)
                exclusions.append(record)
            except json.JSONDecodeError:
                # If JSONL fails, try parsing the whole content as a single JSON list
                try:
                    all_records = json.loads(content)
                    if isinstance(all_records, list):
                        return all_records
                    else:
                        logger.warning("Exclusion log is not a list or JSONL format.")
                        return []
                except json.JSONDecodeError:
                    logger.warning(f"Skipping malformed log line: {line}")
                    continue

    return exclusions

def load_preprocessed_gaze(gaze_path: Path) -> pd.DataFrame:
    """
    Load the preprocessed gaze data.

    Args:
        gaze_path: Path to the preprocessed gaze CSV.

    Returns:
        DataFrame containing preprocessed gaze data.
    """
    if not gaze_path.exists():
        raise FileNotFoundError(f"Preprocessed gaze data not found at {gaze_path}")

    return pd.read_csv(gaze_path)

def generate_quality_report(
    exclusions: List[Dict[str, Any]],
    preprocessed_df: pd.DataFrame
) -> pd.DataFrame:
    """
    Generate the data quality report.

    Args:
        exclusions: List of exclusion records from the log.
        preprocessed_df: DataFrame of preprocessed gaze data.

    Returns:
        DataFrame containing the quality report.
    """
    if not exclusions:
        logger.info("No exclusions found in the log.")
        # Return an empty report with the correct schema
        return pd.DataFrame(columns=[
            'participant_id',
            'exclusion_reason',
            'data_loss_percent',
            'total_fixations',
            'total_trials'
        ])

    # Aggregate exclusions by participant
    report_data = []

    # Group exclusions by participant_id
    participant_exclusions = {}
    for exc in exclusions:
        pid = exc.get('participant_id')
        if pid:
            if pid not in participant_exclusions:
                participant_exclusions[pid] = []
            participant_exclusions[pid].append(exc)

    for pid, exc_list in participant_exclusions.items():
        # Aggregate reasons
        reasons = []
        data_loss = 0.0
        for exc in exc_list:
            reason = exc.get('reason', 'Unknown')
            if reason not in reasons:
                reasons.append(reason)
            loss = exc.get('data_loss_percent', 0.0)
            if loss > data_loss:
                data_loss = loss

        # Get total fixations and trials from preprocessed data for context
        # Note: If a participant was excluded, they might not be in the preprocessed data.
        # We try to get stats if available, otherwise mark as excluded before processing.
        participant_stats = preprocessed_df[preprocessed_df['participant_id'] == pid]
        total_fixations = len(participant_stats) if not participant_stats.empty else 0
        total_trials = participant_stats['headline_id'].nunique() if not participant_stats.empty else 0

        report_data.append({
            'participant_id': pid,
            'exclusion_reason': '; '.join(reasons),
            'data_loss_percent': round(data_loss, 2),
            'total_fixations': total_fixations,
            'total_trials': total_trials
        })

    return pd.DataFrame(report_data)

def write_report(report_df: pd.DataFrame, output_path: Path) -> None:
    """
    Write the quality report to a CSV file.

    Args:
        report_df: The report DataFrame.
        output_path: Path to the output CSV file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    report_df.to_csv(output_path, index=False)
    logger.info(f"Data quality report written to {output_path}")

def main() -> None:
    """Main execution function."""
    logger = setup_logger()
    logger.info("Starting Data Quality Report generation (T007).")

    project_root = get_project_root()
    exclusion_log_path = project_root / 'output' / 'exclusion_log.txt'
    preprocessed_gaze_path = project_root / 'data' / 'derived' / 'preprocessed_gaze.csv'
    output_report_path = project_root / 'output' / 'data_quality_report.csv'

    try:
        # Load inputs
        logger.info(f"Loading exclusion log from {exclusion_log_path}")
        exclusions = load_exclusion_log(exclusion_log_path)

        logger.info(f"Loading preprocessed gaze data from {preprocessed_gaze_path}")
        preprocessed_df = load_preprocessed_gaze(preprocessed_gaze_path)

        # Generate report
        logger.info("Generating quality report...")
        report_df = generate_quality_report(exclusions, preprocessed_df)

        # Write output
        write_report(report_df, output_report_path)

        logger.info("Data Quality Report generation completed successfully.")

    except FileNotFoundError as e:
        logger.error(f"Required input file missing: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Error generating data quality report: {e}")
        sys.exit(1)

if __name__ == '__main__':
    main()