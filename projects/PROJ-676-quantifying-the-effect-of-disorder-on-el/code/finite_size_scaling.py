"""
Finite-Size Scaling Fit Logic for Participation Ratio.

Implements the fitting model PR(L) = PR_inf * (1 - exp(-L/xi))
using non-linear least squares. Handles convergence failures and
non-physical results by logging warnings and skipping realizations.
"""
import json
import os
import logging
import warnings
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple

import numpy as np
from scipy.optimize import curve_fit
from scipy.stats import r2_score

# Ensure logging is configured
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Output paths
WarningsPath = Path("data/metadata/warnings.json")
ScalingRawPath = Path("data/processed/pr_scaling_raw.json")
InputPath = Path("data/processed/pr_raw_multiL.json")


def saturation_model(L: np.ndarray, PR_inf: float, xi: float) -> np.ndarray:
    """
    Saturation model for finite-size scaling of Participation Ratio.
    
    PR(L) = PR_inf * (1 - exp(-L/xi))
    
    Args:
        L: System sizes (array of integers)
        PR_inf: Asymptotic participation ratio at infinite size
        xi: Localization length (characteristic scale)
        
    Returns:
        Predicted PR values
    """
    return PR_inf * (1 - np.exp(-L / xi))


def load_raw_pr_data() -> List[Dict[str, Any]]:
    """
    Load the multi-L PR dataset generated by T013b.
    
    Returns:
        List of dictionaries containing PR data.
    """
    if not InputPath.exists():
        raise FileNotFoundError(f"Input file not found: {InputPath}")
    
    with open(InputPath, 'r') as f:
        data = json.load(f)
    
    logger.info(f"Loaded {len(data)} entries from {InputPath}")
    return data


def fit_scaling_curve(
    L_values: np.ndarray, 
    PR_values: np.ndarray
) -> Optional[Tuple[float, float, float]]:
    """
    Fit the saturation model to PR vs L data.
    
    Args:
        L_values: System sizes
        PR_values: Participation ratios
        
    Returns:
        Tuple (PR_inf, xi, R_squared) if fit is successful and physical,
        None otherwise.
    """
    if len(L_values) < 2:
        logger.warning("Insufficient data points for fitting")
        return None

    # Initial guesses based on data range
    PR_max = np.max(PR_values)
    # Avoid zero division if PR is very small
    if PR_max < 1e-6:
        PR_max = 1.0
    
    p0 = [PR_max, np.mean(L_values)]  # [PR_inf, xi]
    bounds = ([0, 1e-6], [np.inf, np.inf])  # PR_inf >= 0, xi > 0

    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", RuntimeWarning)
            popt, pcov = curve_fit(
                saturation_model, 
                L_values, 
                PR_values, 
                p0=p0, 
                bounds=bounds,
                maxfev=5000
            )
        
        PR_inf, xi = popt
        
        # Check for physical validity
        if xi <= 0:
            logger.warning(f"Non-physical xi (<=0): {xi}")
            return None
        
        # Calculate R-squared
        PR_pred = saturation_model(L_values, PR_inf, xi)
        ss_res = np.sum((PR_values - PR_pred) ** 2)
        ss_tot = np.sum((PR_values - np.mean(PR_values)) ** 2)
        
        if ss_tot == 0:
            r2 = 1.0
        else:
            r2 = 1 - (ss_res / ss_tot)
        
        # Check R^2 threshold
        if r2 < 0.95:
            logger.warning(f"Fit R^2 too low: {r2:.4f} < 0.95")
            return None
        
        # Estimate uncertainty from covariance matrix
        try:
            perr = np.sqrt(np.diag(pcov))
            xi_uncertainty = perr[1]
        except Exception:
            xi_uncertainty = np.nan
        
        return float(PR_inf), float(xi), float(xi_uncertainty), float(r2)
        
    except (RuntimeError, ValueError) as e:
        logger.warning(f"Fit failed to converge: {e}")
        return None
    except Exception as e:
        logger.warning(f"Unexpected error during fitting: {e}")
        return None


def run_scaling_analysis() -> List[Dict[str, Any]]:
    """
    Run finite-size scaling analysis on all disorder widths.
    
    Returns:
        List of fit results for each disorder width.
    """
    data = load_raw_pr_data()
    
    # Group data by disorder width W
    data_by_W: Dict[float, Dict[int, List[float]]] = {}
    
    for entry in data:
        W = entry['W']
        L = entry['L']
        pr = entry['pr']
        
        if W not in data_by_W:
            data_by_W[W] = {}
        
        if L not in data_by_W[W]:
            data_by_W[W][L] = []
        
        data_by_W[W][L].append(pr)
    
    results = []
    warnings_list = []
    
    for W in sorted(data_by_W.keys()):
        logger.info(f"Processing disorder width W={W}")
        
        # Average PR over realizations for each L
        L_values = []
        PR_avg = []
        
        for L in sorted(data_by_W[W].keys()):
            pr_values = data_by_W[W][L]
            L_values.append(L)
            PR_avg.append(np.mean(pr_values))
        
        L_arr = np.array(L_values)
        PR_arr = np.array(PR_avg)
        
        fit_result = fit_scaling_curve(L_arr, PR_arr)
        
        if fit_result is None:
            warning_entry = {
                "W": W,
                "reason": "Fit failed or non-physical parameters",
                "L_values": L_values,
                "PR_avg": PR_avg.tolist()
            }
            warnings_list.append(warning_entry)
            continue
        
        PR_inf, xi, xi_uncertainty, r2 = fit_result
        
        result_entry = {
            "disorder_width": W,
            "xi": xi,
            "uncertainty": xi_uncertainty,
            "r_squared": r2,
            "PR_inf": PR_inf,
            "L_range": [min(L_values), max(L_values)]
        }
        results.append(result_entry)
        
        logger.info(f"W={W}: xi={xi:.4f}, uncertainty={xi_uncertainty:.4f}, R²={r2:.4f}")
    
    # Write warnings to metadata
    if warnings_list:
        WarningsPath.parent.mkdir(parents=True, exist_ok=True)
        with open(WarningsPath, 'w') as f:
            json.dump(warnings_list, f, indent=2)
        logger.info(f"Written {len(warnings_list)} warnings to {WarningsPath}")
    
    return results


def main():
    """Main entry point for the scaling analysis."""
    logger.info("Starting finite-size scaling analysis")
    
    results = run_scaling_analysis()
    
    # Write results to output file
    ScalingRawPath.parent.mkdir(parents=True, exist_ok=True)
    with open(ScalingRawPath, 'w') as f:
        json.dump(results, f, indent=2)
    
    logger.info(f"Written {len(results)} fit results to {ScalingRawPath}")
    logger.info("Scaling analysis completed successfully")


if __name__ == "__main__":
    main()
