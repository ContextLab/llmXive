"""
T017 Implementation: Calculate age_in_days and handle missing release metadata.

This script processes the raw dependency data collected by T016.
It calculates 'age_in_days' based on the last release date relative to today.
Crucially, it handles missing release dates by setting age_in_days to null (None)
while ensuring the dependency row (and its vulnerability count) is preserved.

Output:
    Writes a processed CSV to data/processed/dependencies_processed.csv
    containing the calculated age_in_days.
"""
import os
import sys
import json
import csv
from pathlib import Path
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.models.data_models import Dependency

# Constants
INPUT_PATH = PROJECT_ROOT / "data" / "raw" / "dependencies_raw.json"
OUTPUT_PATH = PROJECT_ROOT / "data" / "processed" / "dependencies_processed.csv"
TODAY = datetime.now(timezone.utc)

def parse_date(date_str: Optional[str]) -> Optional[datetime]:
    """Parse ISO format date string to datetime object."""
    if not date_str:
        return None
    try:
        # Handle various ISO formats
        if date_str.endswith('Z'):
            date_str = date_str[:-1] + '+00:00'
        return datetime.fromisoformat(date_str)
    except (ValueError, TypeError):
        return None

def calculate_age_in_days(last_release_date: Optional[str]) -> Optional[int]:
    """
    Calculate age in days from last_release_date to today.
    Returns None if last_release_date is missing or invalid.
    """
    dt = parse_date(last_release_date)
    if dt is None:
        return None
    
    # Ensure dt is timezone aware
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    
    delta = TODAY - dt
    return delta.days

def load_dependencies_from_json(file_path: Path) -> List[Dict[str, Any]]:
    """Load dependencies from the JSON file generated by T016."""
    if not file_path.exists():
        raise FileNotFoundError(f"Input file not found: {file_path}")
    
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # Expecting a list of dependency dictionaries
    if isinstance(data, dict) and 'dependencies' in data:
        return data['dependencies']
    elif isinstance(data, list):
        return data
    else:
        raise ValueError(f"Unexpected JSON structure in {file_path}")

def process_dependencies(dependencies: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Process dependencies: calculate age_in_days.
    
    Logic:
    1. If last_release_date exists, calculate age_in_days.
    2. If last_release_date is missing/null, set age_in_days to None.
    3. Keep vulnerability_count as is (even if age is null).
    """
    processed = []
    
    for dep in dependencies:
        processed_dep = dict(dep)  # Copy to avoid mutation issues
        
        # Extract raw values
        last_release = dep.get('last_release_date')
        vulnerability_count = dep.get('vulnerability_count', 0)
        
        # Calculate age
        age_days = calculate_age_in_days(last_release)
        
        # Update the record
        processed_dep['age_in_days'] = age_days
        
        # Ensure vulnerability_count is present (default 0 if missing)
        if 'vulnerability_count' not in processed_dep:
            processed_dep['vulnerability_count'] = 0
        
        processed.append(processed_dep)
    
    return processed

def write_csv(dependencies: List[Dict[str, Any]], output_path: Path) -> None:
    """Write processed dependencies to CSV."""
    if not dependencies:
        raise ValueError("No data to write")
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Determine fields
    # Prioritize specific fields, then include others
    base_fields = [
        'package_name', 'version', 'last_release_date', 
        'last_commit_date', 'age_in_days', 'vulnerability_count'
    ]
    
    # Collect all unique keys
    all_keys = set()
    for dep in dependencies:
        all_keys.update(dep.keys())
    
    # Order: base fields first, then others alphabetically
    other_keys = sorted([k for k in all_keys if k not in base_fields])
    fieldnames = base_fields + other_keys
    
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction='ignore')
        writer.writeheader()
        
        for dep in dependencies:
            # Convert None to empty string for CSV or keep as null? 
            # CSV standard: empty string is safer for numeric columns that might be null
            # but we want to distinguish "null" from "0". 
            # We'll write Python's None as empty string which pandas/readers can interpret.
            row = {k: (v if v is not None else '') for k, v in dep.items()}
            writer.writerow(row)

def main():
    """Main entry point for T017."""
    print(f"Starting T017: Age Calculation and Metadata Handling")
    print(f"Input: {INPUT_PATH}")
    print(f"Output: {OUTPUT_PATH}")
    
    try:
        # Load
        dependencies = load_dependencies_from_json(INPUT_PATH)
        print(f"Loaded {len(dependencies)} dependencies.")
        
        # Process
        processed = process_dependencies(dependencies)
        print(f"Calculated age_in_days for {len(processed)} dependencies.")
        
        # Verify constraints
        null_age_count = sum(1 for d in processed if d['age_in_days'] is None)
        non_null_vuln_count = sum(1 for d in processed if d['vulnerability_count'] is not None)
        
        print(f"Rows with null age_in_days: {null_age_count}")
        print(f"Rows with non-null vulnerability_count: {non_null_vuln_count}")
        
        # Write
        write_csv(processed, OUTPUT_PATH)
        print(f"Successfully wrote processed data to {OUTPUT_PATH}")
        
        # Summary stats for verification
        if null_age_count > 0:
            sample_null = [d for d in processed if d['age_in_days'] is None][0]
            print(f"Verification Sample (Null Age): {sample_null['package_name']} -> age={sample_null['age_in_days']}, vulns={sample_null['vulnerability_count']}")
        
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        print("T017 cannot run without the output from T016 (dependencies_raw.json).")
        sys.exit(1)
    except Exception as e:
        print(f"ERROR during processing: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)

if __name__ == "__main__":
    main()