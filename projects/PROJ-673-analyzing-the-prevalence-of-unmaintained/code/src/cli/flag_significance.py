"""
Task T025: Flag statistical significance (p < 0.05) in the output report.

This script loads the correlation results generated by T024, evaluates the
p-value against the significance threshold (alpha=0.05), and writes an
updated report containing the significance flag.

Acceptance Criteria (US-2 Acceptance 3):
- The output report must include a 'is_significant' boolean field.
- 'is_significant' is True if p_value < 0.05, False otherwise.
"""
import json
import logging
import sys
from pathlib import Path
from typing import Any, Dict

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Constants
ALPHA_THRESHOLD = 0.05
INPUT_FILE = Path("data/processed/results_correlation.json")
OUTPUT_FILE = Path("data/processed/results_correlation_with_significance.json")

def load_results(input_path: Path) -> Dict[str, Any]:
    """Load the correlation results from the JSON file."""
    if not input_path.exists():
        raise FileNotFoundError(
            f"Input file not found: {input_path}. "
            "Ensure T024 (run_analysis.py) has been executed successfully."
        )
    
    with open(input_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def flag_significance(results: Dict[str, Any], alpha: float = ALPHA_THRESHOLD) -> Dict[str, Any]:
    """
    Analyze the results and add significance flags.
    
    Updates the 'results' dictionary in-place and returns it.
    Handles nested structures if the correlation result is embedded.
    """
    logger.info(f"Evaluating statistical significance with alpha={alpha}")
    
    # Normalize: ensure we are looking at the top-level 'results' key or the root
    # depending on how T024 formatted the output.
    data_to_process = results.get('results', results)
    
    # Case 1: Direct correlation result (e.g., from T024)
    if isinstance(data_to_process, dict):
        p_value = data_to_process.get('p_value')
        
        if p_value is not None:
            is_significant = float(p_value) < alpha
            data_to_process['is_significant'] = is_significant
            data_to_process['significance_alpha'] = alpha
            logger.info(f"P-value: {p_value:.4f} -> Significant: {is_significant}")
        else:
            logger.warning("No 'p_value' found in the top-level result structure.")
            data_to_process['is_significant'] = None
            data_to_process['significance_alpha'] = alpha
    
    # Case 2: List of results (e.g., stratified analysis)
    elif isinstance(data_to_process, list):
        for i, item in enumerate(data_to_process):
            if isinstance(item, dict) and 'p_value' in item:
                p_val = item['p_value']
                item['is_significant'] = float(p_val) < alpha
                item['significance_alpha'] = alpha
                logger.info(f"Item {i} (p={p_val:.4f}) -> Significant: {item['is_significant']}")
            else:
                logger.warning(f"Item {i} missing 'p_value'. Skipping significance flag.")
    
    # Case 3: Unknown structure
    else:
        logger.warning("Results structure is not a dict or list. Cannot flag significance.")
        results['significance_flagged'] = False
        return results

    results['significance_flagged'] = True
    return results

def save_results(results: Dict[str, Any], output_path: Path) -> None:
    """Save the updated results to the output JSON file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(results, f, indent=2)
    
    logger.info(f"Significance-flagged results saved to: {output_path}")

def main() -> int:
    """Main entry point for the significance flagging script."""
    try:
        logger.info(f"Loading results from {INPUT_FILE}")
        results = load_results(INPUT_FILE)
        
        logger.info("Calculating significance flags...")
        updated_results = flag_significance(results)
        
        logger.info(f"Saving updated results to {OUTPUT_FILE}")
        save_results(updated_results, OUTPUT_FILE)
        
        logger.info("Task T025 completed successfully.")
        return 0
    
    except FileNotFoundError as e:
        logger.error(str(e))
        return 1
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in input file: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during execution: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())