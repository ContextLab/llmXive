def test_stratification_excludes_small_categories(categorized_data):
    """
    Test that categories with N < 30 are excluded from the stratified analysis.
    
    This is the core requirement of T032.
    """
    # Group by category and count
    category_counts = categorized_data.groupby('category').size()
    
    # Identify categories that should be included (N >= 30)
    valid_categories = category_counts[category_counts >= MIN_CATEGORY_SIZE].index.tolist()
    excluded_categories = category_counts[category_counts < MIN_CATEGORY_SIZE].index.tolist()
    
    # If no categories meet the threshold, the result should be empty or handle gracefully
    if not valid_categories:
        # This is a valid state if the dataset is very small or skewed
        # The function should return an empty result or a specific indicator
        result = compute_stratified_correlations(categorized_data, min_samples=MIN_CATEGORY_SIZE)
        
        # Verify the result structure handles the empty case
        assert isinstance(result, dict), "Result should be a dictionary."
        # Depending on implementation, it might be empty or have a 'skipped' key
        # We assert that no correlations were calculated for the small groups
        # (since there are no valid groups)
        return
    
    # Run the stratified analysis with the minimum sample size
    result = compute_stratified_correlations(categorized_data, min_samples=MIN_CATEGORY_SIZE)
    
    # Verify the result contains only valid categories
    result_categories = list(result.keys())
    
    # Assert that no excluded categories are in the result
    for excluded in excluded_categories:
        assert excluded not in result_categories, (
            f"Category '{excluded}' with N={category_counts[excluded]} "
            f"should have been excluded but was found in results."
        )
    
    # Assert that all valid categories are present (if the implementation is correct)
    for valid in valid_categories:
        assert valid in result_categories, (
            f"Category '{valid}' with N={category_counts[valid]} "
            f"should have been included but was missing from results."
        )
    
    # Verify the structure of the result for included categories
    for category, stats in result.items():
        assert 'correlation' in stats, f"Missing 'correlation' in stats for {category}"
        assert 'p_value' in stats, f"Missing 'p_value' in stats for {category}"
        assert 'sample_size' in stats, f"Missing 'sample_size' in stats for {category}"
        assert stats['sample_size'] >= MIN_CATEGORY_SIZE, (
            f"Sample size for {category} ({stats['sample_size']}) "
            f"should be >= {MIN_CATEGORY_SIZE}"
        )

def test_filter_valid_samples_handles_nulls(categorized_data):
    """
    Test that the filtering logic correctly handles null age_in_days or vulnerability_count.
    
    The stratified analysis should only compute correlations on rows where both
    variables are non-null.
    """
    # Count nulls
    null_age = categorized_data['age_in_days'].isna().sum()
    null_vuln = categorized_data['vulnerability_count'].isna().sum()
    
    # Run the filter
    filtered_df = filter_valid_samples(categorized_data)
    
    # Verify that no nulls remain in the target columns
    assert filtered_df['age_in_days'].isna().sum() == 0, "Filtered data still contains null age_in_days"
    assert filtered_df['vulnerability_count'].isna().sum() == 0, "Filtered data still contains null vulnerability_count"
    
    # Verify that the count matches expectation
    expected_len = len(categorized_data) - null_age - null_vuln # Approximation if same rows
    # More precise:
    valid_mask = categorized_data['age_in_days'].notna() & categorized_data['vulnerability_count'].notna()
    expected_count = valid_mask.sum()
    
    assert len(filtered_df) == expected_count, (
        f"Filter length mismatch. Expected {expected_count}, got {len(filtered_df)}"
    )

def test_stratified_analysis_integration_flow(categorized_data):
    """
    End-to-end integration test for the stratified analysis flow.
    
    This ensures the pipeline runs without errors and produces the expected
    output structure, respecting the N < 30 exclusion rule.
    """
    # Run the full stratified analysis
    # This function typically wraps loading, filtering, and computing
    results = run_stratified_analysis(categorized_data, min_samples=MIN_CATEGORY_SIZE)
    
    # Verify output type
    assert isinstance(results, dict), "run_stratified_analysis should return a dict"
    
    # Check for summary keys if present
    if 'summary' in results:
        assert 'total_categories' in results['summary']
        assert 'valid_categories' in results['summary']
        assert 'excluded_categories' in results['summary']
        
        # Verify the exclusion logic in the summary
        excluded_count = len(results['summary']['excluded_categories'])
        actual_excluded = [cat for cat, count in categorized_data.groupby('category').size().items() 
                           if count < MIN_CATEGORY_SIZE]
        
        assert excluded_count == len(actual_excluded), (
            f"Summary exclusion count mismatch: {excluded_count} vs {len(actual_excluded)}"
        )
    
    # Verify per-category results
    if 'results' in results:
        for cat, stats in results['results'].items():
            assert stats['sample_size'] >= MIN_CATEGORY_SIZE, (
                f"Result for {cat} violates minimum sample size rule."
            )

def test_real_data_correlation_bounds(categorized_data):
    """
    Verify that calculated correlations for valid categories are within [-1, 1].
    
    This is a sanity check on the real data processing.
    """
    result = compute_stratified_correlations(categorized_data, min_samples=MIN_CATEGORY_SIZE)
    
    for category, stats in result.items():
        rho = stats['correlation']
        p = stats['p_value']
        
        assert -1.0 <= rho <= 1.0, (
            f"Correlation for {category} ({rho}) is out of bounds [-1, 1]"
        )
        assert 0.0 <= p <= 1.0, (
            f"P-value for {category} ({p}) is out of bounds [0, 1]"
        )