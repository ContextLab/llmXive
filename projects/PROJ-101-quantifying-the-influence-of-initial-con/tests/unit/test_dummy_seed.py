"""
Dummy test to verify that the `seed` fixture from `tests/conftest.py` provides a
deterministic random seed and that NumPy's RandomState reproduces the same
first random value for that seed. This satisfies the verification requirement
for Task T003.
"""

import numpy as np


def test_seed_reproducibility(seed):
    """
    Given the fixed seed (42) from the `seed` fixture, the first random number
    generated by `np.random.RandomState` must be the known constant.
    """
    rng = np.random.RandomState(seed)
    first_val = rng.rand()
    # The first value for seed 42 is a well‑known constant.
    assert np.isclose(first_val, 0.3745401188473625)  # noqa: PLR2004