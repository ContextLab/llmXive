"""
Boundedness/Escape Time Check Module.

This module implements a post-generation validation step to verify that
generated trajectories remain within the expected attractor bounds.
It calculates escape times for trajectories that diverge, serving as
a diagnostic tool for stochastic regimes without blocking the main FTLE pipeline.

Dependency: T018 (Generation) - Operates on files in data/raw/
"""
import json
import logging
import sys
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple

import numpy as np

# Import the core stability check from T007
from utils.stability import check_boundedness, StabilityReport

# Project root relative to this file
PROJECT_ROOT = Path(__file__).parent.parent.parent

# Logger setup
logger = logging.getLogger(__name__)
if not logger.handlers:
    handler = logging.StreamHandler(sys.stdout)
    handler.setFormatter(logging.Formatter(
        '%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    ))
    logger.addHandler(handler)
    logger.setLevel(logging.INFO)


class BoundednessCheckResult:
    """
    Data class to store the result of a boundedness check for a single trajectory.
    """
    def __init__(
        self,
        trajectory_id: str,
        is_bounded: bool,
        escape_time: Optional[float] = None,
        max_norm: float = 0.0,
        threshold: float = 100.0
    ):
        self.trajectory_id = trajectory_id
        self.is_bounded = is_bounded
        self.escape_time = escape_time
        self.max_norm = max_norm
        self.threshold = threshold

    def to_dict(self) -> Dict[str, Any]:
        return {
            "trajectory_id": self.trajectory_id,
            "is_bounded": self.is_bounded,
            "escape_time": self.escape_time,
            "max_norm": self.max_norm,
            "threshold": self.threshold,
            "status": "BOUND" if self.is_bounded else "ESCAPED"
        }


def load_trajectory_for_check(trajectory_path: Path) -> Tuple[np.ndarray, List[float]]:
    """
    Loads a trajectory from a CSV file.
    Expects the file to be a CSV with columns matching the state vector dimensions.
    Returns (state_array, time_array).

    Note: This assumes the CSV format generated by T017 (data/loader.py).
    """
    try:
        # Load data using numpy, assuming comma-separated, no header or simple header
        # We need to be robust to the exact format. T017 saves CSVs.
        # Let's assume the first row might be a header or data.
        # For safety, we try to load as float, ignoring non-numeric rows if any.
        
        # Attempt to load as CSV. 
        # T017 typically saves: time, x1, y1, z1, x2, y2, z2...
        data = np.genfromtxt(trajectory_path, delimiter=',', skip_header=1)
        
        if data.ndim == 1:
            data = data.reshape(1, -1)
        
        if data.shape[0] == 0:
            raise ValueError(f"Trajectory file {trajectory_path} is empty or invalid.")
        
        # Assuming first column is time, rest are state
        time_col = data[:, 0]
        state_data = data[:, 1:]
        
        return state_data, time_col.tolist()
        
    except Exception as e:
        logger.error(f"Failed to load trajectory {trajectory_path}: {e}")
        raise


def check_trajectory_boundedness(
    trajectory_path: Path,
    threshold: float = 100.0
) -> BoundednessCheckResult:
    """
    Performs the boundedness check on a single trajectory file.
    
    Logic:
    1. Load the trajectory state vector.
    2. Iterate through time steps.
    3. Use check_boundedness (from T007) on the state vector at each step.
    4. If boundedness fails, record the escape time (current time step).
    5. If the whole trajectory is bounded, report max norm.
    
    Args:
        trajectory_path: Path to the CSV file.
        threshold: The attractor bound threshold (default 100.0).
        
    Returns:
        BoundednessCheckResult object.
    """
    state_array, time_array = load_trajectory_for_check(trajectory_path)
    trajectory_id = trajectory_path.stem
    
    max_norm = 0.0
    escape_time = None
    is_bounded = True
    
    # Iterate through each time step
    for i, state in enumerate(state_array):
        # Check boundedness for the current state vector
        # check_boundedness returns True if bounded (norm <= threshold), False otherwise
        if not check_boundedness(state, threshold=threshold):
            is_bounded = False
            escape_time = time_array[i]
            # Calculate the norm at escape
            current_norm = np.linalg.norm(state)
            if current_norm > max_norm:
                max_norm = current_norm
            break
        
        # Track max norm even if bounded so far
        current_norm = np.linalg.norm(state)
        if current_norm > max_norm:
            max_norm = current_norm
    
    return BoundednessCheckResult(
        trajectory_id=trajectory_id,
        is_bounded=is_bounded,
        escape_time=escape_time,
        max_norm=max_norm,
        threshold=threshold
    )


def run_boundedness_validation_batch(
    data_dir: Optional[Path] = None,
    pattern: str = "trajectory_*.csv",
    threshold: float = 100.0
) -> List[BoundednessCheckResult]:
    """
    Runs the boundedness check on all trajectories in a directory.
    
    Args:
        data_dir: Directory containing trajectory files. Defaults to data/raw/.
        pattern: Glob pattern to match trajectory files.
        threshold: Boundedness threshold.
        
    Returns:
        List of BoundednessCheckResult objects.
    """
    if data_dir is None:
        data_dir = PROJECT_ROOT / "data" / "raw"
        
    if not data_dir.exists():
        logger.warning(f"Data directory {data_dir} does not exist. Skipping validation.")
        return []
        
    results = []
    files = list(data_dir.glob(pattern))
    
    if not files:
        logger.warning(f"No files matching {pattern} found in {data_dir}.")
        return results
        
    logger.info(f"Checking boundedness for {len(files)} trajectories in {data_dir}...")
    
    for file_path in files:
        try:
            result = check_trajectory_boundedness(file_path, threshold)
            results.append(result)
            
            # Log status
            status = "BOUND" if result.is_bounded else f"ESCAPED at t={result.escape_time:.2f}"
            logger.debug(f"  {result.trajectory_id}: {status} (max_norm={result.max_norm:.4f})")
            
        except Exception as e:
            logger.error(f"Error processing {file_path}: {e}")
            # Create a failure result
            results.append(BoundednessCheckResult(
                trajectory_id=file_path.stem,
                is_bounded=False,
                escape_time=None,
                max_norm=-1.0,
                threshold=threshold
            ))
    
    return results


def save_validation_report(
    results: List[BoundednessCheckResult],
    output_path: Optional[Path] = None
) -> Path:
    """
    Saves the validation results to a JSON file.
    
    Args:
        results: List of results to save.
        output_path: Path to save the report. Defaults to data/processed/boundedness_report.json.
        
    Returns:
        Path to the saved report.
    """
    if output_path is None:
        output_path = PROJECT_ROOT / "data" / "processed" / "boundedness_report.json"
        
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    report_data = {
        "total_trajectories": len(results),
        "bounded_count": sum(1 for r in results if r.is_bounded),
        "escaped_count": sum(1 for r in results if not r.is_bounded),
        "threshold": results[0].threshold if results else 100.0,
        "details": [r.to_dict() for r in results]
    }
    
    with open(output_path, 'w') as f:
        json.dump(report_data, f, indent=2)
        
    logger.info(f"Validation report saved to {output_path}")
    return output_path


def main():
    """
    Main entry point to run the boundedness check on all generated trajectories.
    This is a post-generation validation step as per T043.
    """
    logger.info("Starting Boundedness/Escape Time Check (T043)...")
    
    # Run check on all trajectories in data/raw/
    results = run_boundedness_validation_batch(
        data_dir=PROJECT_ROOT / "data" / "raw",
        pattern="trajectory_*.csv",
        threshold=100.0
    )
    
    if not results:
        logger.warning("No results to report.")
        return
        
    # Save report
    report_path = save_validation_report(results)
    
    # Summary
    bounded = sum(1 for r in results if r.is_bounded)
    escaped = len(results) - bounded
    
    logger.info(f"--- Summary ---")
    logger.info(f"Total checked: {len(results)}")
    logger.info(f"Bounded: {bounded}")
    logger.info(f"Escaped: {escaped}")
    logger.info(f"Report saved to: {report_path}")
    
    # Log specific escapes
    escaped_results = [r for r in results if not r.is_bounded]
    if escaped_results:
        logger.warning(f"Found {len(escaped_results)} trajectories that escaped the attractor bounds.")
        for r in escaped_results:
            logger.warning(f"  - {r.trajectory_id}: Escaped at t={r.escape_time:.2f}, Max Norm={r.max_norm:.2f}")


if __name__ == "__main__":
    main()
