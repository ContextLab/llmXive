def actual_schema():
    """Load the actual schema file generated by T007."""
    if not SCHEMA_PATH.exists():
        pytest.fail(f"Schema file not found at {SCHEMA_PATH}. Ensure T007 has been executed.")
    
    with open(SCHEMA_PATH, "r") as f:
        return yaml.safe_load(f)


def test_schema_is_valid_yaml(sample_decision, tmp_path):
    """Test that the generated schema function produces valid YAML."""
    schema = generate_schema(sample_decision)
    
    # Convert to YAML string and parse back
    yaml_str = yaml.dump(schema, default_flow_style=False)
    parsed = yaml.safe_load(yaml_str)
    
    assert parsed == schema


def test_schema_contains_target_variable(sample_decision):
    """Test that the generated schema correctly sets the target variable."""
    schema = generate_schema(sample_decision)
    
    target_in_schema = schema["properties"]["metadata"]["properties"]["target_variable"]["const"]
    assert target_in_schema == sample_decision["target"]


def test_schema_structure(sample_decision):
    """Test that the generated schema has the required structure."""
    schema = generate_schema(sample_decision)
    
    # Check top-level keys
    assert "$schema" in schema
    assert "title" in schema
    assert "description" in schema
    assert "type" in schema
    assert "properties" in schema
    
    # Check properties
    assert "metadata" in schema["properties"]
    assert "data" in schema["properties"]
    
    # Check metadata structure
    metadata_props = schema["properties"]["metadata"]["properties"]
    assert "target_variable" in metadata_props
    assert "correlation_coefficient" in metadata_props
    assert "p_value" in metadata_props
    assert "threshold" in metadata_props
    assert "decision_reason" in metadata_props
    
    # Check data structure
    data_props = schema["properties"]["data"]["properties"]
    assert "items" in schema["properties"]["data"]


