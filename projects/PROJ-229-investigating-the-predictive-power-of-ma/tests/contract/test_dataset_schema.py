def test_actual_schema_loads_and_validates(actual_schema):
    """Test that the actual schema file is valid JSON Schema and can validate data."""
    # Verify it's a valid JSON Schema structure
    assert actual_schema.get("$schema") is not None
    assert actual_schema.get("type") == "object"
    assert "properties" in actual_schema
    
    # Verify it can validate a dummy record
    dummy_data = {
        "metadata": {
            "target_variable": "melting_point",
            "correlation_coefficient": 0.85,
            "p_value": 0.001,
            "threshold": 0.7,
            "decision_reason": "Test"
        },
        "data": {
            "items": [
                {
                    "material_id": "mp-123",
                    "composition": "NaCl",
                    "elements": ["Na", "Cl"],
                    "n_elements": 2
                }
            ]
        }
    }
    
    # This should not raise an exception if the schema is valid
    try:
        validate(instance=dummy_data, schema=actual_schema)
    except ValidationError as e:
        pytest.fail(f"Schema failed to validate valid data: {e.message}")


def test_actual_schema_matches_target_decision():
    """Test that the actual schema matches the target decision file."""
    if not TARGET_DECISION_PATH.exists():
        pytest.skip("Target decision file not found. Skipping cross-check.")
    
    decision = load_target_decision()
    
    with open(SCHEMA_PATH, "r") as f:
        schema = yaml.safe_load(f)
    
    schema_target = schema["properties"]["metadata"]["properties"]["target_variable"]["const"]
    assert schema_target == decision["target"], \
        f"Schema target ({schema_target}) does not match decision target ({decision['target']})"