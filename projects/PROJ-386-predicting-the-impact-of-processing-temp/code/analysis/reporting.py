def detect_proxy_variables(df):
    """Detect potential proxy variables in the dataset."""
    proxy_keywords = ['strain', 'cooling', 'rate', 'time', 'duration']
    cols = df.columns.tolist()
    proxies = [c for c in cols if any(k in c.lower() for k in proxy_keywords)]
    return proxies

