def aggregate_final_metrics():
    """
    Aggregate final metrics from all previous tasks (T035).
    Consumes:
      - R2/MAE from T024 (Baseline) and T030 (RF)
      - p-value from T034 (Permutation Test)
      - Stability scores from T032 (Sensitivity Analysis)
      - Confounder report from T046
      - Collinearity framing from T047
    Output:
      - data/artifacts/final_report.json
    """
    config = get_config()
    paths = config['paths']
    
    # 1. Load Collinearity Report (T023 -> T047)
    collinearity_report = load_collinearity_report()
    collinearity_notes = format_collinearity_message(collinearity_report)
    
    # 2. Load Sensitivity Report (T032)
    sensitivity_path = paths.get('sensitivity_report', 'data/artifacts/sensitivity_report.json')
    stability_score = 0.0
    if os.path.exists(sensitivity_path):
        with open(sensitivity_path, 'r') as f:
            sens_data = json.load(f)
            stability_score = sens_data.get('stability_pct', 0.0)
    else:
        logger.warning(f"Sensitivity report not found at {sensitivity_path}. Stability score set to 0.0.")
    
    # 3. Load Confounder Report (T046)
    confounder_path = paths.get('confounder_report', 'data/artifacts/confounder_report.json')
    confounder_status = "N/A"
    if os.path.exists(confounder_path):
        with open(confounder_path, 'r') as f:
            conf_data = json.load(f)
            confounder_status = conf_data.get('status', 'N/A')
    else:
        logger.warning(f"Confounder report not found at {confounder_path}. Status set to N/A.")
    
    # 4. Load Baseline Metrics (T024)
    baseline_metrics = {"r2": 0.0, "mae": 0.0}
    baseline_path = paths.get('baseline_metrics', 'data/artifacts/baseline_metrics.json')
    if os.path.exists(baseline_path):
        with open(baseline_path, 'r') as f:
            baseline_metrics = json.load(f)
    else:
        logger.warning(f"Baseline metrics not found at {baseline_path}.")
    
    # 5. Load RF Metrics (T030)
    rf_metrics = {"r2": 0.0, "mae": 0.0}
    rf_path = paths.get('rf_metrics', 'data/artifacts/rf_metrics.json')
    if os.path.exists(rf_path):
        with open(rf_path, 'r') as f:
            rf_metrics = json.load(f)
    else:
        logger.warning(f"RF metrics not found at {rf_path}.")
    
    # 6. Load Permutation Test Results (T034)
    p_value = 1.0
    perm_path = paths.get('permutation_test_results', 'data/artifacts/permutation_test_results.json')
    if os.path.exists(perm_path):
        with open(perm_path, 'r') as f:
            perm_data = json.load(f)
            p_value = perm_data.get('p_value', 1.0)
    else:
        logger.warning(f"Permutation test results not found at {perm_path}. P-value set to 1.0.")
    
    # 7. Assemble Final Report
    final_report = {
        "r2_baseline": float(baseline_metrics.get('r2', 0.0)),
        "r2_rf": float(rf_metrics.get('r2', 0.0)),
        "p_value": float(p_value),
        "stability_score": float(stability_score),
        "collinearity_notes": collinearity_notes,
        "confounder_status": confounder_status,
        "mae_baseline": float(baseline_metrics.get('mae', 0.0)),
        "mae_rf": float(rf_metrics.get('mae', 0.0))
    }
    
    # 8. Write Output
    output_path = paths.get('final_report', 'data/artifacts/final_report.json')
    os.makedirs(os.dirname(output_path), exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(final_report, f, indent=2)
    
    logger.info(f"Final metrics aggregated and saved to {output_path}")
    return final_report

def run_reporting_pipeline():
    """Run the full reporting pipeline including final metrics aggregation."""
    try:
        # Ensure data exists
        df = load_processed_data()
        
        # Run T046 (Confounder) if not already done
        confounder_path = get_config()['paths'].get('confounder_report', 'data/artifacts/confounder_report.json')
        if not os.path.exists(confounder_path):
            logger.info("Generating confounder report...")
            conf_report = generate_confounder_report(df, None) # Model not strictly needed for proxy detection
            with open(confounder_path, 'w') as f:
                json.dump(conf_report, f, indent=2)
        
        # Run T035 (Final Metrics)
        logger.info("Aggregating final metrics...")
        result = aggregate_final_metrics()
        return result
        
    except Exception as e:
        logger.error(f"Reporting pipeline failed: {e}", exc_info=True)
        raise

def main():
    parser = argparse.ArgumentParser(description="Run reporting pipeline and aggregate final metrics")
    parser.add_argument('--pipeline', action='store_true', help='Run full pipeline')
    args = parser.parse_args()
    
    if args.pipeline:
        run_reporting_pipeline()
    else:
        aggregate_final_metrics()

if __name__ == "__main__":
    main()