def format_collinearity_message(report):
    """Format collinearity notes for the final report."""
    if not report or "flagged_pairs" not in report:
        return "No collinearity issues detected."
    
    pairs = report["flagged_pairs"]
    if not pairs:
        return "No collinearity issues detected."
    
    notes = []
    for pair in pairs:
        if len(pair) >= 2:
            notes.append(
                f"Features '{pair[0]}' and '{pair[1]}' are highly correlated (r > 0.8). "
                "Their effects are reported as a joint contribution, not independent coefficients."
            )
    
    return " ".join(notes)

