#!/bin/bash
# Run Baseline Training Pipeline
# This script orchestrates data generation and baseline model training.
# It explicitly calls data generation functions for training and testing
# to ensure independent distributions as per FR-006 and US-001.

set -e

# Project root detection
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
PROJECT_ROOT="$( dirname "$SCRIPT_DIR" )"
cd "$PROJECT_ROOT"

echo "=== Project Root: $PROJECT_ROOT ==="

# Ensure required directories exist
echo "Ensuring directory structure..."
python -c "from scripts.setup_directories import ensure_directory_structure; ensure_directory_structure()"

# 1. Generate Training Data (Lorenz Attractor)
# This corresponds to T008a logic, generating the training distribution.
echo "=== Generating Training Data (Lorenz Attractor) ==="
python -c "
import sys
from pathlib import Path
sys.path.insert(0, str(Path.cwd()))
from src.data.benchmarks import generate_training_data, save_generated_data

# Generate and save training data
train_data = generate_training_data()
save_generated_data(train_data, 'data/results/train_data_lorenz.npy')
print('Training data saved to data/results/train_data_lorenz.npy')
"

# 2. Generate Test Data (Polynomial Surfaces)
# This corresponds to T008c logic, generating an independent test distribution.
echo "=== Generating Test Data (Polynomial Surfaces) ==="
python -c "
import sys
from pathlib import Path
sys.path.insert(0, str(Path.cwd()))
from src.data.benchmarks import generate_test_data, save_generated_data

# Generate and save test data
test_data = generate_test_data()
save_generated_data(test_data, 'data/results/test_data_polynomial.npy')
print('Test data saved to data/results/test_data_polynomial.npy')
"

# 3. Verify Independence of Distributions
# This corresponds to T008b logic.
echo "=== Verifying Data Independence ==="
python -c "
import sys
import numpy as np
from pathlib import Path
sys.path.insert(0, str(Path.cwd()))
from src.data.benchmarks import verify_independence

train_path = Path('data/results/train_data_lorenz.npy')
test_path = Path('data/results/test_data_polynomial.npy')

if not train_path.exists() or not test_path.exists():
    raise FileNotFoundError('Generated data files not found. Run data generation steps first.')

train_data = np.load(train_path)
test_data = np.load(test_path)

is_independent = verify_independence(train_data, test_data)
if not is_independent:
    raise RuntimeError('Data independence verification failed. Train and Test distributions are not distinct by design.')
print('Independence verified: Train (Lorenz) and Test (Polynomial) are distinct.')
"

# 4. Run Baseline Training
echo "=== Running Baseline Training ==="
python scripts/run_baseline_training.py

echo "=== Baseline Pipeline Complete ==="
echo "Outputs:"
echo "  - Training Data: data/results/train_data_lorenz.npy"
echo "  - Test Data: data/results/test_data_polynomial.npy"
echo "  - Training Log: data/logs/training_log.json"
echo "  - Gradient Norms: data/logs/gradient_norms.json"
echo "  - Generalization Report: data/results/generalization_report.md (generated by baseline_runner)"