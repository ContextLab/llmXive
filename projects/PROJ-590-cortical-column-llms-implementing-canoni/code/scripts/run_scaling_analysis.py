"""
Script to run the scaling law analysis (Task T050).

This script orchestrates the analysis of scaling data generated by the scaling study
and produces the scaling law report.
"""
import os
import sys
import logging
from pathlib import Path

# Add project root to path
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from src.utils.scaling_analyzer import main as scaling_analyzer_main

def main():
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    input_path = "data/results/scaling_law.csv"
    output_path = "data/results/scaling_law_report.md"
    
    # Check if input file exists
    if not os.path.exists(input_path):
        logging.error(f"Input file not found: {input_path}")
        logging.error("Please ensure the scaling study (T049) has been run successfully.")
        sys.exit(1)
        
    logging.info(f"Starting scaling analysis on {input_path}")
    logging.info(f"Output will be written to {output_path}")
    
    try:
        scaling_analyzer_main()
        logging.info("Scaling analysis completed successfully.")
    except Exception as e:
        logging.error(f"Scaling analysis failed: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
