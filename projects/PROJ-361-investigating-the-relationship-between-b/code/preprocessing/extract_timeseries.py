"""
Extract BOLD time series from preprocessed fMRI data using Schaefer parcellations.

This script maps Schaefer atlas ROIs to preprocessed BOLD data (generated by fMRIPrep)
to produce subject-specific time series matrices (T x N).

Dependencies:
    - nibabel (NIfTI handling)
    - nilearn (atlas loading, masking)
    - numpy
    - pandas
    - utils.logging_utils
    - utils.config
"""

import os
import sys
import argparse
from pathlib import Path
from typing import List, Dict, Any, Optional

import numpy as np
import nibabel as nib
import pandas as pd
from nilearn import datasets, masking, image
from nilearn.masking import apply_mask

# Project imports
from utils.config import get_project_root, get_raw_data_dir, get_processed_data_dir
from utils.logging_utils import get_logger, log_preprocessing_step, handle_pipeline_exception, PreprocessingError

logger = get_logger(__name__)

# Supported Schaefer parcellations (number of parcels)
SCHAEFER_PARCELATIONS = [
    100, 200, 300, 400, 500, 600, 700, 800, 900, 1000
]

def get_subject_fmriprep_paths(subject_id: str) -> Optional[Path]:
    """
    Locate the preprocessed BOLD file for a given subject.

    Assumes fMRIPrep output structure:
    data/processed/sub-<subject_id>/func/sub-<subject_id>_task-rest_space-MNI152NLin2009cAsym_desc-preproc_bold.nii.gz

    Returns:
        Path to the preprocessed NIfTI file, or None if not found.
    """
    processed_dir = get_processed_data_dir()
    sub_dir = processed_dir / f"sub-{subject_id}" / "func"

    if not sub_dir.exists():
        logger.warning(f"Preprocessed directory not found for subject {subject_id}: {sub_dir}")
        return None

    # Look for the standard fMRIPrep preproc file
    # Pattern: sub-<id>_task-rest_space-<space>_desc-preproc_bold.nii.gz
    candidates = list(sub_dir.glob("sub-*_task-rest*_desc-preproc_bold.nii.gz"))

    if not candidates:
        logger.warning(f"No preprocessed BOLD file found for subject {subject_id} in {sub_dir}")
        return None

    # Prefer the MNI space version if multiple exist
    for candidate in candidates:
        if "space-MNI" in str(candidate):
            return candidate

    return candidates[0]

def load_schaefer_atlas(n_parcels: int) -> Dict[str, Any]:
    """
    Load a Schaefer parcellation atlas from nilearn.

    Args:
        n_parcels: Number of parcels (e.g., 200, 400).

    Returns:
        Dictionary containing 'maps' (NIfTI image) and 'labels' (list of region names).
    """
    logger.info(f"Loading Schaefer atlas with {n_parcels} parcels...")
    try:
        atlas = datasets.fetch_atlas_schaefer_2018(
            n_rois=n_parcels,
            yeo_networks=7,  # Default 7-network Yeo template
            resolution_mm=2,  # Match typical fMRIPrep MNI resolution
            data_dir=str(get_project_root() / "data" / "external")
        )
        return {
            'maps': atlas['maps'],
            'labels': atlas['labels']
        }
    except Exception as e:
        logger.error(f"Failed to load Schaefer atlas ({n_parcels} parcels): {e}")
        raise PreprocessingError(f"Atlas fetch failed: {e}")

def extract_timeseries_for_parcellation(
    bold_path: Path,
    atlas_maps_path: Path,
    n_parcels: int
) -> np.ndarray:
    """
    Extract time series from BOLD data using a specific parcellation.

    Args:
        bold_path: Path to preprocessed BOLD NIfTI file.
        atlas_maps_path: Path to Schaefer atlas NIfTI file.
        n_parcels: Number of parcels (for logging).

    Returns:
        2D numpy array of shape (T, N) where T = time points, N = parcels.
    """
    logger.info(f"Extracting time series for {n_parcels} parcels...")

    # Load images
    try:
        bold_img = image.load_img(bold_path)
        atlas_img = image.load_img(atlas_maps_path)
    except Exception as e:
        logger.error(f"Failed to load images for {n_parcels} parcels: {e}")
        raise PreprocessingError(f"Image loading failed: {e}")

    # Ensure spatial alignment (atlas is typically in MNI space, BOLD should be too)
    # nilearn's apply_mask handles resampling if necessary, but we warn if resolutions differ
    if not np.allclose(bold_img.affine, atlas_img.affine):
        logger.warning(f"Affine mismatch between BOLD and atlas for {n_parcels} parcels. Resampling may occur.")

    try:
        # Extract mean time series per ROI
        time_series = apply_mask(bold_img, atlas_img)
    except Exception as e:
        logger.error(f"Masking failed for {n_parcels} parcels: {e}")
        raise PreprocessingError(f"Time series extraction failed: {e}")

    # Validate output
    if time_series.shape[1] != n_parcels:
        logger.error(f"Expected {n_parcels} columns, got {time_series.shape[1]}")
        raise PreprocessingError(f"Parcellation mismatch: expected {n_parcels}, got {time_series.shape[1]}")

    # Check for NaNs
    if np.any(np.isnan(time_series)):
        nan_count = np.isnan(time_series).sum()
        logger.warning(f"Found {nan_count} NaN values in time series for {n_parcels} parcels. Imputing with 0.")
        time_series = np.nan_to_num(time_series, nan=0.0)

    logger.info(f"Extracted time series shape: {time_series.shape}")
    return time_series

def save_timeseries(subject_id: str, n_parcels: int, timeseries: np.ndarray, output_dir: Path):
    """
    Save extracted time series to CSV.

    Args:
        subject_id: Subject identifier.
        n_parcels: Number of parcels.
        timeseries: 2D numpy array (T x N).
        output_dir: Directory to save the CSV.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    filename = f"sub-{subject_id}_schaefer{n_parcels}_timeseries.csv"
    filepath = output_dir / filename

    # Create DataFrame with column names
    col_names = [f"ROI_{i+1}" for i in range(timeseries.shape[1])]
    df = pd.DataFrame(timeseries, columns=col_names)
    df.to_csv(filepath, index=False)

    logger.info(f"Saved timeseries to {filepath}")
    return filepath

def process_subject(subject_id: str, n_parcels_list: Optional[List[int]] = None) -> Dict[str, str]:
    """
    Process a single subject: extract time series for specified parcellations.

    Args:
        subject_id: Subject ID (e.g., '001').
        n_parcels_list: List of parcellation sizes to process. Defaults to all supported.

    Returns:
        Dictionary mapping parcellation size to output file path.
    """
    if n_parcels_list is None:
        n_parcels_list = SCHAEFER_PARCELATIONS

    results = {}

    # Get BOLD path
    bold_path = get_subject_fmriprep_paths(subject_id)
    if not bold_path:
        raise PreprocessingError(f"No preprocessed BOLD found for subject {subject_id}")

    for n_parcels in n_parcels_list:
        try:
            # Load atlas
            atlas_data = load_schaefer_atlas(n_parcels)
            atlas_maps_path = Path(atlas_data['maps'])

            # Extract
            ts = extract_timeseries_for_parcellation(bold_path, atlas_maps_path, n_parcels)

            # Save
            out_dir = get_processed_data_dir() / "timeseries"
            out_path = save_timeseries(subject_id, n_parcels, ts, out_dir)
            results[n_parcels] = str(out_path)

        except Exception as e:
            logger.error(f"Failed processing subject {subject_id} with {n_parcels} parcels: {e}")
            # Continue with other parcellations instead of failing the whole subject
            continue

    return results

def main():
    parser = argparse.ArgumentParser(description="Extract BOLD time series using Schaefer parcellations.")
    parser.add_argument(
        "--subject",
        type=str,
        help="Specific subject ID to process (e.g., '001'). If omitted, processes all subjects in data/raw."
    )
    parser.add_argument(
        "--parcels",
        type=int,
        nargs="+",
        default=None,
        help="Specific parcellation sizes to process (e.g., 200 400). Defaults to all supported."
    )
    parser.add_argument(
        "--force-atlas-download",
        action="store_true",
        help="Force re-download of atlas files."
    )

    args = parser.parse_args()

    log_preprocessing_step("extract_timeseries", "START", args)

    try:
        # Determine subjects to process
        raw_dir = get_raw_data_dir()
        if args.subject:
            subjects = [args.subject]
        else:
            # Scan data/raw for subject directories (sub-*)
            subjects = [
                d.name.replace("sub-", "")
                for d in raw_dir.iterdir()
                if d.is_dir() and d.name.startswith("sub-")
            ]
            if not subjects:
                raise PreprocessingError("No subject directories found in data/raw/")
            logger.info(f"Processing {len(subjects)} subjects: {subjects[:5]}...")

        # Process each subject
        for sub_id in subjects:
            logger.info(f"Processing subject: {sub_id}")
            try:
                results = process_subject(sub_id, args.parcels)
                if results:
                    logger.info(f"Subject {sub_id} completed. Files: {list(results.keys())}")
                else:
                    logger.warning(f"Subject {sub_id} produced no output files.")
            except Exception as e:
                logger.error(f"Subject {sub_id} failed: {e}")
                handle_pipeline_exception(e, f"Subject {sub_id}")

        log_preprocessing_step("extract_timeseries", "COMPLETE", {"subjects_processed": len(subjects)})

    except Exception as e:
        handle_pipeline_exception(e, "extract_timeseries")
        sys.exit(1)

if __name__ == "__main__":
    main()