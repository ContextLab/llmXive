import os
import sys
from pathlib import Path
import logging

# Add project root to path if running as script
project_root = Path(__file__).resolve().parent
sys.path.insert(0, str(project_root))

from config import ensure_directories
from ingestion import generate_cleaned_data
from utils import get_logger

logger = get_logger(__name__)

def main():
    """
    Entry point for generating cleaned_data.csv (T016).
    Expects raw data to be present in data/raw/ as generated by T009-T015.
    """
    # Ensure directories exist
    ensure_directories()
    
    raw_dir = project_root / "data" / "raw"
    output_file = project_root / "data" / "processed" / "cleaned_data.csv"
    
    logger.info(f"Running ingestion pipeline. Raw: {raw_dir}, Output: {output_file}")
    
    try:
        generate_cleaned_data(raw_dir, output_file)
        logger.info("Ingestion pipeline completed successfully.")
    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Pipeline failed: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
