def load_hcp_fmri_data(raw_dir: Union[str, Path]) -> pd.DataFrame:
    """
    Load HCP fMRI data from raw directory.
    Expected to read pre-processed data files generated by T009-T012.
    """
    raw_dir = Path(raw_dir)
    # Assuming T009-T012 have generated intermediate CSVs or parquet files
    # In a real scenario, we would load the specific files produced by previous tasks
    # For this implementation, we assume data is available in a specific format
    fMRI_data_path = raw_dir / "hcp_fmri_metrics.csv"
    if not file_exists(fMRI_data_path):
        raise FileNotFoundError(f"Expected fMRI metrics file not found: {fMRI_data_path}")
    
    df = read_csv(fMRI_data_path)
    required_cols = ['Subject_ID', 'Global_Signal_SD', 'Mean_FD', 'Mean_DVARS']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in fMRI data: {missing}")
    return df

def load_mwq_data(raw_dir: Union[str, Path]) -> pd.DataFrame:
    """
    Load MWQ (Mind-Wandering Questionnaire) data from raw directory.
    """
    raw_dir = Path(raw_dir)
    mwq_data_path = raw_dir / "mwq_scores.csv"
    if not file_exists(mwq_data_path):
        raise FileNotFoundError(f"Expected MWQ scores file not found: {mwq_data_path}")
    
    df = read_csv(mwq_data_path)
    required_cols = ['Subject_ID', 'MWQ_Score', 'Age', 'Sex']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in MWQ data: {missing}")
    return df

def join_fmri_mwq_data(fmri_df: pd.DataFrame, mwq_df: pd.DataFrame) -> pd.DataFrame:
    """
    Join fMRI and MWQ data on Subject_ID.
    """
    merged = pd.merge(fmri_df, mwq_df, on='Subject_ID', how='inner')
    logger.info(f"Joined {len(fmri_df)} fMRI subjects with {len(mwq_df)} MWQ subjects. Result: {len(merged)}")
    return merged

def validate_subject_data(df: pd.DataFrame) -> pd.DataFrame:
    """
    Validate that all required fields are present and non-null.
    """
    required = ['Subject_ID', 'Global_Signal_SD', 'MWQ_Score', 'Age', 'Sex', 'Mean_FD', 'Mean_DVARS']
    for col in required:
        if col not in df.columns:
            raise ValueError(f"Missing column: {col}")
        if df[col].isnull().any():
            logger.warning(f"Found {df[col].isnull().sum()} null values in {col}. Dropping rows.")
            df = df.dropna(subset=[col])
    return df

def apply_motion_exclusion(df: pd.DataFrame, threshold: float = 0.5) -> pd.DataFrame:
    """
    Exclude subjects where mean FD > threshold.
    """
    before = len(df)
    df = df[df['Mean_FD'] <= threshold]
    after = len(df)
    logger.info(f"Motion exclusion (FD > {threshold}): Removed {before - after} subjects. Remaining: {after}")
    return df

def check_zero_variance_subjects(df: pd.DataFrame) -> pd.DataFrame:
    """
    Exclude subjects with global_signal_sd == 0.
    """
    before = len(df)
    df = df[df['Global_Signal_SD'] != 0]
    after = len(df)
    if before != after:
        logger.warning(f"Zero-variance exclusion: Removed {before - after} subjects with Global_Signal_SD == 0.")
    return df

def generate_cleaned_data(raw_dir: Union[str, Path], output_path: Union[str, Path]) -> None:
    """
    Main pipeline to generate cleaned_data.csv.
    1. Load fMRI and MWQ data.
    2. Join on Subject_ID.
    3. Validate data.
    4. Apply motion exclusion (FD > 0.5).
    5. Apply zero-variance exclusion (SD == 0).
    6. Save to output_path.
    """
    raw_dir = Path(raw_dir)
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    logger.info(f"Starting data cleaning pipeline. Raw dir: {raw_dir}, Output: {output_path}")
    
    # Load data
    fmri_df = load_hcp_fmri_data(raw_dir)
    mwq_df = load_mwq_data(raw_dir)
    
    # Join
    merged_df = join_fmri_mwq_data(fmri_df, mwq_df)
    
    # Validate
    merged_df = validate_subject_data(merged_df)
    
    # Motion exclusion
    merged_df = apply_motion_exclusion(merged_df, threshold=0.5)
    
    # Zero variance exclusion
    merged_df = check_zero_variance_subjects(merged_df)
    
    # Ensure correct column order
    cols = ['Subject_ID', 'Global_Signal_SD', 'MWQ_Score', 'Age', 'Sex', 'Mean_FD', 'Mean_DVARS']
    merged_df = merged_df[cols]
    
    # Save
    write_csv(merged_df, output_path)
    logger.info(f"Successfully wrote cleaned data to {output_path}")

