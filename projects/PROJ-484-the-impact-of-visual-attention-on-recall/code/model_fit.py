def _load_power_analysis():
    """
    Load the Monte Carlo power analysis results generated by T024.
    Expected location: artifacts/logs/power_analysis.json
    Returns a dict with at least an 'achieved_power' key if present.
    """
    power_path = Path("artifacts/logs/power_analysis.json")
    if power_path.is_file():
        try:
            with open(power_path, "r") as f:
                data = json.load(f)
            # The structure may vary; try common keys
            if isinstance(data, dict):
                if "achieved_power" in data:
                    return {"achieved_power": float(data["achieved_power"])}
                # Nested structure example: {"power": {"achieved": 0.73}}
                for key in ("power", "results", "analysis"):
                    sub = data.get(key)
                    if isinstance(sub, dict) and "achieved_power" in sub:
                        return {"achieved_power": float(sub["achieved_power"])}
            logger.warning("Power analysis file found but could not extract achieved power.")
        except Exception as e:
            logger.warning(f"Failed to read power analysis file: {e}")
    else:
        logger.info("Power analysis file not found; will use fallback estimation.")
    return None

def _estimate_power_fallback(df):
    """
    Estimate power when a proper Monte Carlo result is unavailable.
    Uses a very simple heuristic based on sample size.
    """
    n = len(df)
    # Heuristic: small samples (<200) are likely underpowered for a three‑way interaction.
    if n < 200:
        return 0.60
    else:
        return 0.85

def run_monte_carlo_power_analysis(df):
    """
    Run Monte Carlo power analysis (or load existing results) and emit a warning
    if the achieved power for the three‑way interaction is below 0.80.
    The warning is logged and a JSON file `power_warning.json` is written.
    """
    # Try to load the concrete Monte Carlo result first
    power_info = _load_power_analysis()
    if power_info and "achieved_power" in power_info:
        estimated_power = power_info["achieved_power"]
        logger.info(f"Loaded achieved power from Monte Carlo results: {estimated_power:.2f}")
    else:
        # Fall back to a quick heuristic estimation
        estimated_power = _estimate_power_fallback(df)
        logger.info(f"Estimated power via fallback heuristic: {estimated_power:.2f}")

    output_dir = Path("artifacts/logs")
    output_dir.mkdir(parents=True, exist_ok=True)

    warning_path = output_dir / "power_warning.json"

    if estimated_power < 0.80:
        warning_msg = "WARNING: Low statistical power detected"
        logger.warning(warning_msg)

        warning_data = {
            "status": "low_power",
            "achieved_power": estimated_power,
            "threshold": 0.80,
            "sample_size": len(df),
            "message": "The Monte Carlo simulation indicates achieved power < 0.80 for the three-way interaction.",
            "constraints": {
                "sample_size_limitation": True,
                "effect_size_assumption": "conservative"
            }
        }

        with open(warning_path, "w") as f:
            json.dump(warning_data, f, indent=2)

        logger.info(f"Power warning written to {warning_path}")
        return warning_data
    else:
        logger.info("Power is sufficient (>= 0.80). No warning generated.")
        # Ensure no stale warning file remains
        if warning_path.is_file():
            try:
                warning_path.unlink()
                logger.info(f"Removed existing stale warning file {warning_path}")
            except Exception:
                pass
        return None

