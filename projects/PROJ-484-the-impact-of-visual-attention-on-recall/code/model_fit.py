def export_power_results(power_results, output_path):
    """Export power analysis results to JSON."""
    with open(output_path, 'w') as f:
        json.dump(power_results, f, indent=2)
    logging.info(f"Power analysis results exported to {output_path}")

def export_bootstrap_results(convergence_rate, output_path):
    """Export bootstrap convergence results to JSON."""
    results = {
        "convergence_rate": convergence_rate,
        "status": "success" if convergence_rate > 0.9 else "warning"
    }
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    logging.info(f"Bootstrap results exported to {output_path}")

def main():
    """Main entry point for model fitting and power analysis."""
    # Setup logging
    logger = setup_logging("model_fit")
    logger.info("Starting model fitting and power analysis.")
    
    try:
        # Load data
        data = load_analysis_data()
        logger.info(f"Loaded {len(data)} rows.")
        
        # Prepare data
        data = prepare_model_data(data)
        
        # Fit full model
        logger.info("Fitting full mixed-effects model...")
        full_result, full_converged = fit_mixed_effects_model(data)
        
        if not full_converged:
            logger.warning("Full model did not converge. Attempting simplified model.")
            # Try simplified model (random effects only)
            full_result, full_converged = fit_mixed_effects_model(data, formula="recall ~ fixation_duration * valence * trait_anxiety + (1|participant)")
            
        if not full_converged:
            logger.error("Model failed to converge even with simplification.")
            # Export failure status
            export_power_results({"status": "failed_convergence"}, "artifacts/logs/model_results.json")
            return
        
        logger.info("Full model converged.")
        
        # Fit reduced model
        logger.info("Fitting reduced model...")
        reduced_result, reduced_converged = fit_reduced_model(data)
        
        # Likelihood-ratio test
        if full_converged and reduced_converged:
            chi2, p_val, significant = run_likelihood_ratio_test(full_result, reduced_result)
            logger.info(f"LRT: Chi2={chi2}, p={p_val}, significant={significant}")
        else:
            logger.warning("Could not perform LRT due to convergence issues.")
            chi2, p_val, significant = None, None, False
        
        # Residual diagnostics
        diagnostics = run_residual_diagnostics(full_result)
        
        # Bootstrap convergence
        conv_rate = run_bootstrap_convergence_verification(data)
        logger.info(f"Bootstrap convergence rate: {conv_rate}")
        
        # Monte Carlo power analysis
        power_results = run_monte_carlo_power_analysis(data)
        logger.info(f"Power estimate: {power_results['power_estimate']}")
        
        # --- T072: Sparse Data Power Warning ---
        if power_results['power_estimate'] < 0.80:
            warning_msg = "WARNING: Low statistical power detected"
            logger.warning(warning_msg)
            
            warning_data = {
                "warning": warning_msg,
                "power_estimate": power_results['power_estimate'],
                "sample_size": power_results.get('n_subjects', len(data)),
                "effect_size_constraint": "Three-way interaction requires large sample size",
                "threshold": 0.80,
                "status": "low_power"
            }
            
            warning_path = "artifacts/logs/power_warning.json"
            with open(warning_path, 'w') as f:
                json.dump(warning_data, f, indent=2)
            logger.info(f"Power warning exported to {warning_path}")
        else:
            logger.info("Statistical power is sufficient.")
        
        # Export results
        model_results = {
            "convergence": full_converged,
            "chi_squared_stat": chi2,
            "p_value": p_val,
            "power_estimate": power_results['power_estimate'],
            "diagnostics": diagnostics,
            "bootstrap_convergence_rate": conv_rate
        }
        
        export_path = "artifacts/logs/model_results.json"
        with open(export_path, 'w') as f:
            json.dump(model_results, f, indent=2)
        logger.info(f"Model results exported to {export_path}")
        
        export_power_results(power_results, "artifacts/logs/power_analysis.json")
        
    except Exception as e:
        logger.error(f"Fatal error during model fitting: {e}")
        raise

if __name__ == "__main__":
    main()
