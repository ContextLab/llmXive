def load_analysis_data():
    """Load the analysis-ready CSV generated by preprocess.py."""
    data_path = get_data_path()
    csv_path = os.path.join(data_path, "processed", "analysis.csv")
    
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Analysis data not found at {csv_path}. Run preprocess.py first.")
    
    df = pd.read_csv(csv_path)
    return df

def prepare_model_data(df):
    """
    Prepare data for mixed-effects model.
    Ensure categorical variables are treated correctly.
    """
    # Create a copy to avoid modifying original
    data = df.copy()
    
    # Ensure target variable is binary (0/1)
    if 'recall' not in data.columns:
        raise ValueError("Column 'recall' not found in data.")
    
    # Ensure fixed effects are present
    required_cols = ['recall', 'fixation_duration', 'valence', 'trait_anxiety']
    for col in required_cols:
        if col not in data.columns:
            raise ValueError(f"Required column '{col}' not found in data.")
    
    # Convert categorical columns
    data['valence'] = data['valence'].astype('category')
    data['participant'] = data['participant'].astype('category')
    if 'stimulus_id' in data.columns:
        data['stimulus_id'] = data['stimulus_id'].astype('category')
    
    return data

def fit_mixed_effects_model(data, formula=None):
    """
    Fit the full mixed-effects logistic regression model.
    Formula: recall ~ fixation_duration * valence * trait_anxiety + (1|participant) + (1|stimulus_id)
    """
    if formula is None:
        formula = "recall ~ fixation_duration * valence * trait_anxiety + (1|participant) + (1|stimulus_id)"
    
    # Handle potential missing stimulus_id if not in data
    if "(1|stimulus_id)" in formula and "stimulus_id" not in data.columns:
        warnings.warn("stimulus_id not in data, simplifying random effects.")
        formula = formula.replace(" + (1|stimulus_id)", "")
    
    try:
        model = smf.mixedlm(
            formula,
            data,
            groups=data["participant"],
            re_formula="1"
        )
        # Use bobyqa optimizer as per requirements
        result = model.fit(method="bobyqa", maxiter=10000, tol=1e-6)
        return result, True
    except Exception as e:
        logging.warning(f"Full model failed to converge: {e}. Attempting simplified model.")
        return None, False

def fit_reduced_model(data, formula=None):
    """
    Fit the reduced model (without the three-way interaction) for LRT.
    Formula: recall ~ fixation_duration * valence + trait_anxiety + (1|participant)
    """
    if formula is None:
        # Simplified to remove the three-way interaction
        formula = "recall ~ fixation_duration * valence + trait_anxiety + (1|participant)"
    
    if "(1|stimulus_id)" in formula and "stimulus_id" not in data.columns:
        formula = formula.replace(" + (1|stimulus_id)", "")

    try:
        model = smf.mixedlm(
            formula,
            data,
            groups=data["participant"],
            re_formula="1"
        )
        result = model.fit(method="bobyqa", maxiter=10000, tol=1e-6)
        return result, True
    except Exception as e:
        logging.warning(f"Reduced model failed: {e}")
        return None, False

def run_likelihood_ratio_test(full_result, reduced_result):
    """
    Perform likelihood-ratio test comparing full and reduced models.
    """
    if full_result is None or reduced_result is None:
        return None, 1.0, False # Cannot perform test if models didn't converge

    ll_full = full_result.llf
    ll_reduced = reduced_result.llf
    
    # Chi-squared statistic: 2 * (LL_full - LL_reduced)
    # Degrees of freedom: difference in number of parameters
    # For a three-way interaction term, df is usually the number of parameters added.
    # In a factorial design with 2 levels for valence and continuous others, 
    # the interaction adds 1 parameter if binary, or more if categorical.
    # We'll estimate df based on the difference in params if available, or assume 1 for the specific interaction term.
    # A safer approach for LRT in mixed models with categorical variables:
    # We assume the interaction term adds 1 degree of freedom for the specific slope interaction if valence is binary.
    # If valence is categorical with >2 levels, df increases.
    # Let's assume valence is binary (e.g., positive/negative) for this specific hypothesis test.
    # If not, we might need to count parameters.
    
    # Heuristic: assume 1 df for the specific interaction coefficient if valence is binary.
    # If valence has k levels, the interaction adds (k-1) parameters.
    if 'valence' in full_result.model.data.col_names:
        # Check unique values in data if possible, but here we rely on model structure
        # Assuming binary for simplicity in this specific task context unless specified otherwise
        # A robust way: df = full_result.df_model - reduced_result.df_model
        df_diff = full_result.df_model - reduced_result.df_model
        if df_diff <= 0: df_diff = 1 # Fallback
    else:
        df_diff = 1

    chi2_stat = 2 * (ll_full - ll_reduced)
    p_value = 1 - stats.chi2.cdf(chi2_stat, df_diff)
    
    significant = p_value < 0.05
    return chi2_stat, p_value, significant

def run_residual_diagnostics(result):
    """Calculate residuals and report basic diagnostics."""
    if result is None:
        return {}
    
    residuals = result.resid
    # Basic stats
    return {
        "mean_residual": float(np.mean(residuals)),
        "std_residual": float(np.std(residuals)),
        "convergence_status": result.converged
    }

