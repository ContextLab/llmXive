"""
Task T045: Verify all artifacts are hashed and state.yaml is updated.

This script scans the project for key artifacts generated by the pipeline,
computes their SHA-256 hashes, and updates (or creates) `state.yaml`
with the manifest of artifacts and their checksums.

It ensures data integrity and reproducibility by tracking the exact state
of all processed files.
"""
import os
import hashlib
import yaml
from pathlib import Path
from datetime import datetime
import logging

from config_loader import get_project_root, ensure_directory

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Define the key artifacts to track based on the pipeline output
# These paths are relative to the project root
ARTIFACT_PATTERNS = [
    # Preprocessed data
    "data/processed/epo_raw.fif",
    "data/processed/epo_clean.fif",
    "data/processed/diff_wave.fif",
    # Logs
    "data/processed/rejected_participants.log",
    # Results
    "results/metrics.csv",
    "results/statistics.json",
    "results/latency_validation.json",
    # Plots
    "results/plots/erp_plot.png",
    "results/plots/topomap.png",
    # Raw data (optional, if downloaded)
    "data/raw/ds003645/.ds_id", # Placeholder for raw data marker
]

def calculate_sha256(file_path: Path) -> str:
    """Calculate SHA-256 hash of a file."""
    sha256_hash = hashlib.sha256()
    try:
        with open(file_path, "rb") as f:
            for byte_block in iter(lambda: f.read(4096), b""):
                sha256_hash.update(byte_block)
        return sha256_hash.hexdigest()
    except FileNotFoundError:
        logger.warning(f"File not found for hashing: {file_path}")
        return None
    except Exception as e:
        logger.error(f"Error hashing {file_path}: {e}")
        return None

def find_artifacts(project_root: Path) -> dict:
    """
    Scan the project root for defined artifacts and compute their hashes.
    Returns a dictionary of relative_path -> {hash, size, status}.
    """
    artifacts = {}
    for pattern in ARTIFACT_PATTERNS:
        full_path = project_root / pattern
        if full_path.exists():
            file_hash = calculate_sha256(full_path)
            file_size = full_path.stat().st_size
            artifacts[pattern] = {
                "hash": file_hash,
                "size_bytes": file_size,
                "status": "verified"
            }
            logger.info(f"Verified: {pattern} ({file_size} bytes, {file_hash[:16]}...)")
        else:
            artifacts[pattern] = {
                "hash": None,
                "size_bytes": 0,
                "status": "missing"
            }
            logger.warning(f"Missing artifact: {pattern}")
    return artifacts

def update_state_yaml(project_root: Path, artifacts: dict):
    """
    Update or create `state.yaml` with the artifact manifest.
    """
    state_path = project_root / "state.yaml"
    state_data = {
        "last_updated": datetime.utcnow().isoformat() + "Z",
        "pipeline_version": "1.0.0", # Should ideally be read from a version file
        "artifacts": artifacts,
        "summary": {
            "total_artifacts": len(artifacts),
            "verified_count": sum(1 for a in artifacts.values() if a["status"] == "verified"),
            "missing_count": sum(1 for a in artifacts.values() if a["status"] == "missing")
        }
    }

    ensure_directory(state_path.parent)
    with open(state_path, "w") as f:
        yaml.dump(state_data, f, default_flow_style=False, sort_keys=False)
    
    logger.info(f"State manifest written to: {state_path}")
    return state_data

def run_verification():
    """Main entry point for artifact verification."""
    project_root = get_project_root()
    logger.info(f"Starting artifact verification for project at: {project_root}")

    artifacts = find_artifacts(project_root)
    state_data = update_state_yaml(project_root, artifacts)

    # Final report
    summary = state_data["summary"]
    logger.info(f"Verification Complete: {summary['verified_count']}/{summary['total_artifacts']} artifacts found.")
    
    if summary['missing_count'] > 0:
        logger.warning(f"{summary['missing_count']} artifacts are missing. Check previous pipeline steps.")
        # Do not fail loudly here as T045 is a verification step, 
        # but log the status clearly for the user.
    
    return state_data

if __name__ == "__main__":
    run_verification()
