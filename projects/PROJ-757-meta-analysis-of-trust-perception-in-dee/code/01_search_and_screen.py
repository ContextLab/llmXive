def load_raw_studies() -> List[Dict[str, Any]]:
    """Load raw studies from the CSV generated by the search step."""
    if not RAW_STUDIES_PATH.exists():
        logger.error(f"Raw studies file not found: {RAW_STUDIES_PATH}")
        raise FileNotFoundError(f"Raw studies file not found: {RAW_STUDIES_PATH}")
    
    studies = []
    with open(RAW_STUDIES_PATH, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            studies.append(row)
    
    logger.info(f"Loaded {len(studies)} raw studies.")
    return studies

def evaluate_study_against_criteria(study: Dict[str, Any], criteria: Dict[str, Any]) -> Tuple[bool, List[str]]:
    """
    Evaluate a single study against the inclusion criteria.
    Returns (is_included, list_of_exclusion_reasons).
    Note: This is a placeholder for actual logic. In a real system, 
    this would parse the abstract/full text using NLP or regex.
    For this implementation, we simulate the evaluation based on 
    keywords found in the abstract/title to demonstrate the logic flow.
    """
    exclusion_reasons = []
    text_to_check = f"{study.get('title', '')} {study.get('abstract', '')}".lower()
    
    # Check for Trust Metric (NO_TRUST_METRIC)
    # Real logic would look for specific scales (e.g., "trust scale", "Morrow", "Jiang")
    if not any(kw in text_to_check for kw in ["trust", "trustworthiness", "confidence", "credibility"]):
        exclusion_reasons.append("NO_TRUST_METRIC")
    
    # Check for Control Condition (NO_CONTROL_CONDITION)
    # Real logic would look for "control", "baseline", "real face", "human face"
    if not any(kw in text_to_check for kw in ["control", "baseline", "real face", "human face", "comparison"]):
        exclusion_reasons.append("NO_CONTROL_CONDITION")
    
    # Check for Moderator Data (NO_MODERATOR_DATA)
    # Real logic would look for specific moderator variables if required
    # For this simulation, we assume if it passes the first two, it might lack moderator data
    # to demonstrate the flag. We'll randomly decide or check for keywords.
    # Let's be strict: if no mention of "moderator", "age", "literacy", "realism" in context
    # of analysis, flag it.
    if not any(kw in text_to_check for kw in ["moderator", "interaction", "age", "literacy", "realism"]):
        exclusion_reasons.append("NO_MODERATOR_DATA")

    # Check for Peer Review (NOT_PEER_REVIEWED)
    # Simple heuristic: if source is arXiv and not marked as "published" or similar
    source = study.get('source', '').lower()
    if source == 'arxiv' and 'published' not in text_to_check:
        exclusion_reasons.append("NOT_PEER_REVIEWED")

    is_included = len(exclusion_reasons) == 0
    return is_included, exclusion_reasons

def simulate_reviewer_decision(study: Dict[str, Any], criteria: Dict[str, Any], reviewer_id: str) -> Tuple[bool, List[str]]:
    """
    Simulates a single reviewer's decision.
    Introduces realistic noise to simulate human error.
    """
    # Get the "true" decision based on strict criteria
    is_true_included, true_exclusions = evaluate_study_against_criteria(study, criteria)
    
    # Simulate error: with small probability, flip the decision or add/remove a reason
    if random.random() < REVIEWER_ERROR_RATE:
        # Flip the decision
        is_final_included = not is_true_included
        if is_final_included:
            return True, []
        else:
            # If flipping to excluded, pick a random reason
            possible_reasons = ["NO_TRUST_METRIC", "NO_CONTROL_CONDITION", "NO_MODERATOR_DATA", "NOT_PEER_REVIEWED"]
            return False, [random.choice(possible_reasons)]
    else:
        # Correct decision
        return is_true_included, true_exclusions

def run_dual_reviewer_simulation(studies: List[Dict[str, Any]], criteria: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    Runs the dual-reviewer simulation on all studies.
    Returns a list of screening results.
    """
    logger.info("Starting dual-reviewer simulation...")
    screening_results = []

    for study in studies:
        # Reviewer 1
        r1_included, r1_reasons = simulate_reviewer_decision(study, criteria, "Reviewer_1")
        
        # Reviewer 2
        r2_included, r2_reasons = simulate_reviewer_decision(study, criteria, "Reviewer_2")
        
        # Determine final status
        # If both agree, that's the result. If they disagree, flag for adjudication.
        # Note: In this simulation, we assume the "truth" is the strict evaluation,
        # but the system only sees the two reviewers.
        
        if r1_included == r2_included:
            final_included = r1_included
            final_reasons = r1_reasons if not r1_included else []
            adjudication_needed = False
            agreement = True
        else:
            # Disagreement: flag for adjudication
            final_included = False # Default to exclude until resolved
            final_reasons = list(set(r1_reasons + r2_reasons))
            adjudication_needed = True
            agreement = False

        result = {
            "doi": study.get('doi', 'unknown'),
            "title": study.get('title', ''),
            "reviewer_1_included": r1_included,
            "reviewer_1_reasons": "; ".join(r1_reasons),
            "reviewer_2_included": r2_included,
            "reviewer_2_reasons": "; ".join(r2_reasons),
            "final_included": final_included,
            "final_reasons": "; ".join(final_reasons),
            "adjudication_needed": adjudication_needed,
            "agreement": agreement
        }
        screening_results.append(result)

    logger.info(f"Completed simulation for {len(screening_results)} studies.")
    return screening_results

def write_screening_log(screening_results: List[Dict[str, Any]]) -> None:
    """Writes the screening log to CSV."""
    if not screening_results:
        logger.warning("No screening results to write.")
        return

    fieldnames = [
        "doi", "title", "reviewer_1_included", "reviewer_1_reasons",
        "reviewer_2_included", "reviewer_2_reasons", "final_included",
        "final_reasons", "adjudication_needed", "agreement"
    ]

    with open(SCREENING_LOG_PATH, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(screening_results)
    
    logger.info(f"Screening log written to {SCREENING_LOG_PATH}")

def calculate_cohen_kappa(results: List[Dict[str, Any]]) -> float:
    """
    Calculates Cohen's Kappa coefficient for the dual-reviewer agreement.
    Returns -1.0 if calculation is not possible (e.g., no data).
    """
    if not results:
        return -1.0

    # Count agreements and totals
    n = len(results)
    agreements = sum(1 for r in results if r['agreement'])
    
    # Calculate observed agreement (Po)
    po = agreements / n

    # Calculate expected agreement (Pe)
    # Count how many times R1 said Yes/No and R2 said Yes/No
    r1_yes = sum(1 for r in results if r['reviewer_1_included'])
    r1_no = n - r1_yes
    r2_yes = sum(1 for r in results if r['reviewer_2_included'])
    r2_no = n - r2_yes

    # Probability both say Yes by chance
    pe_yes = (r1_yes / n) * (r2_yes / n)
    # Probability both say No by chance
    pe_no = (r1_no / n) * (r2_no / n)
    
    pe = pe_yes + pe_no

    if pe == 1.0:
        return 1.0 # Perfect chance agreement (all same decision)
    if pe == 0.0:
        return 0.0 # Avoid division by zero, though unlikely

    kappa = (po - pe) / (1 - pe)
    return kappa

def generate_adjudication_request(results: List[Dict[str, Any]]) -> None:
    """
    Generates the adjudication request CSV for disputed studies.
    """
    disputed = [r for r in results if r['adjudication_needed']]
    
    if not disputed:
        logger.info("No disputed studies found. No adjudication request generated.")
        if ADJUDICATION_REQUEST_PATH.exists():
            ADJUDICATION_REQUEST_PATH.unlink()
        return

    fieldnames = ["doi", "title", "reviewer_1_decision", "reviewer_2_decision", "reasons_r1", "reasons_r2"]
    
    with open(ADJUDICATION_REQUEST_PATH, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for r in disputed:
            writer.writerow({
                "doi": r['doi'],
                "title": r['title'],
                "reviewer_1_decision": "Included" if r['reviewer_1_included'] else "Excluded",
                "reviewer_2_decision": "Included" if r['reviewer_2_included'] else "Excluded",
                "reasons_r1": r['reviewer_1_reasons'],
                "reasons_r2": r['reviewer_2_reasons']
            })
    
    logger.warning(f"Adjudication request generated: {ADJUDICATION_REQUEST_PATH} ({len(disputed)} studies)")

def main():
    """Main entry point for the screening and dual-reviewer simulation."""
    logger.info("Starting Screening and Dual-Reviewer Simulation (T015).")

    # 1. Load Inclusion Criteria
    if not INCLUSION_CRITERIA_PATH.exists():
        logger.error(f"Criteria file not found: {INCLUSION_CRITERIA_PATH}")
        logger.error("Please ensure T017 has generated data/screening/inclusion_criteria.yaml")
        sys.exit(1)
    
    try:
        criteria = parse_inclusion_criteria(INCLUSION_CRITERIA_PATH)
        logger.info("Inclusion criteria loaded successfully.")
    except Exception as e:
        logger.error(f"Failed to parse inclusion criteria: {e}")
        sys.exit(1)

    # 2. Load Raw Studies
    try:
        studies = load_raw_studies()
    except FileNotFoundError:
        sys.exit(1)

    # 3. Run Dual-Reviewer Simulation
    screening_results = run_dual_reviewer_simulation(studies, criteria)

    # 4. Write Screening Log
    write_screening_log(screening_results)

    # 5. Calculate Kappa
    kappa = calculate_cohen_kappa(screening_results)
    logger.info(f"Cohen's Kappa calculated: {kappa:.4f}")

    # 6. Check Kappa Threshold and Handle Adjudication
    if kappa < 0.6:
        logger.warning(f"Low agreement detected (Kappa = {kappa:.4f} < 0.6).")
        logger.warning("Human Adjudication Required (Kappa < 0.6)")
        generate_adjudication_request(screening_results)
        logger.warning("System HALTED. Please resolve disputes in adjudication_request.csv and screening_log.csv.")
        sys.exit(1)
    else:
        logger.info("Agreement sufficient (Kappa >= 0.6). Proceeding.")
        # Clear any old adjudication file if it exists (though logic above handles generation)
        if ADJUDICATION_REQUEST_PATH.exists():
            ADJUDICATION_REQUEST_PATH.unlink()
        logger.info("Screening phase completed successfully.")

    logger.info("T015 Execution Complete.")

if __name__ == "__main__":
    main()