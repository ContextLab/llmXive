def test_cohen_d_math_verification():
    """
    Verify the mathematical correctness of Cohen's d calculation.
    
    This test manually calculates expected values and compares them
    to the logic defined in the helper functions.
    """
    # Test case 1: Standard
    m_t, m_c = 55.0, 50.0
    s_t, s_c = 10.0, 10.0
    n_t, n_c = 30, 30
    
    expected_d = calculate_expected_cohen_d(m_t, m_c, s_t, s_c, n_t, n_c)
    
    # Manual calculation:
    # s_pooled = sqrt(((29*100) + (29*100)) / 58) = sqrt(5800/58) = sqrt(100) = 10
    # d = (55 - 50) / 10 = 0.5
    assert abs(expected_d - 0.5) < 1e-6, f"Expected 0.5, got {expected_d}"
    
    # Test case 2: Negative effect
    m_t, m_c = 45.0, 50.0
    expected_d_neg = calculate_expected_cohen_d(m_t, m_c, s_t, s_c, n_t, n_c)
    assert abs(expected_d_neg - (-0.5)) < 1e-6, f"Expected -0.5, got {expected_d_neg}"
    
    # Test case 3: Unequal variances
    s_t, s_c = 20.0, 5.0
    # s_pooled = sqrt(((29*400) + (29*25)) / 58) = sqrt((11600 + 1450) / 58) = sqrt(13050/58) = sqrt(225) = 15
    # d = (55 - 50) / 15 = 0.3333...
    expected_d_unequal = calculate_expected_cohen_d(m_t, m_c, s_t, s_c, n_t, n_c)
    assert abs(expected_d_unequal - 0.333333) < 1e-4, f"Expected ~0.333, got {expected_d_unequal}"


def test_variance_calculation():
    """Verify the variance of Cohen's d calculation."""
    n_t, n_c = 30, 30
    d = 0.5
    
    var = calculate_expected_variance_d(n_t, n_c, d)
    
    # Manual: (60 / 900) + (0.25 / 120) = 0.0666... + 0.002083... = 0.06875
    expected_var = (60 / 900) + (0.25 / 120)
    assert abs(var - expected_var) < 1e-6, f"Expected {expected_var}, got {var}"


