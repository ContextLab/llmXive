def validate_field_type(value, expected_type, field_name):
    """Validate that a value matches the expected type."""
    if expected_type == "float":
        if not isinstance(value, (int, float)) or np.isnan(value):
            raise AssertionError(f"Field '{field_name}' must be a valid float, got {type(value)} with value {value}")
    elif expected_type == "int":
        if not isinstance(value, int):
            raise AssertionError(f"Field '{field_name}' must be an int, got {type(value)}")
    elif expected_type == "boolean":
        if not isinstance(value, bool):
            raise AssertionError(f"Field '{field_name}' must be a boolean, got {type(value)}")
    elif expected_type == "string":
        if not isinstance(value, str):
            raise AssertionError(f"Field '{field_name}' must be a string, got {type(value)}")
    elif expected_type == "object":
        if not isinstance(value, dict):
            raise AssertionError(f"Field '{field_name}' must be an object (dict), got {type(value)}")
    return True

def validate_constraints(value, constraints, field_name):
    """Validate that a value meets specific constraints."""
    if "min" in constraints:
        if value < constraints["min"]:
            raise AssertionError(f"Field '{field_name}' value {value} is below minimum {constraints['min']}")
    if "max" in constraints:
        if value > constraints["max"]:
            raise AssertionError(f"Field '{field_name}' value {value} is above maximum {constraints['max']}")
    return True

def validate_nested_schema(data, schema, parent_key=""):
    """Recursively validate a dictionary against a schema."""
    for field_name, field_def in schema.items():
        full_name = f"{parent_key}.{field_name}" if parent_key else field_name
        
        if field_name not in data:
            raise AssertionError(f"Missing required field: {full_name}")

        value = data[field_name]
        expected_type = field_def.get("type")
        
        # Type validation
        validate_field_type(value, expected_type, full_name)

        # Constraint validation
        if "constraints" in field_def:
            validate_constraints(value, field_def["constraints"], full_name)

        # Nested object validation
        if expected_type == "object" and "fields" in field_def:
            validate_nested_schema(value, field_def["fields"], full_name)

def validate_regression_coefficients(coeffs):
    """Validate the structure of regression coefficients."""
    # Check for required keys
    required_keys = ["intercept", "temperature", "mass", "metallicity"]
    for key in required_keys:
        if key not in coeffs:
            # Some models might not include all if dropped, but schema expects them
            # We allow missing if the model type is different, but for standard Tobit:
            # We'll just check that if present, they are floats.
            pass 
        else:
            if not isinstance(coeffs[key], (int, float)):
                raise AssertionError(f"Regression coefficient '{key}' must be a number")

