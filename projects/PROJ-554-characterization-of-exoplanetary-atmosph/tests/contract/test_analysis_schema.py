def test_analysis_output_schema_exists(analysis_results_path):
    """Test that the analysis results file exists."""
    assert analysis_results_path.exists(), f"Analysis results file not found at {analysis_results_path}"

def test_analysis_output_schema_structure(analysis_results_path):
    """Test that the analysis results file matches the expected schema."""
    with open(analysis_results_path, 'r') as f:
        data = json.load(f)

    validate_nested_schema(data, EXPECTED_ANALYSIS_RESULTS_SCHEMA)
    
    # Additional specific validation for regression coefficients if present
    if "regression" in data and "coefficients" in data["regression"]:
        validate_regression_coefficients(data["regression"]["coefficients"])

def test_analysis_output_semantic_validity(analysis_results_path):
    """Test that values are semantically valid (e.g., p-values between 0 and 1)."""
    with open(analysis_results_path, 'r') as f:
        data = json.load(f)

    # Check Kendall's tau range
    tau = data.get("kendall_tau")
    if tau is not None:
        assert -1.0 <= tau <= 1.0, f"Kendall's tau {tau} out of range [-1, 1]"

    # Check p-value range
    p_val = data.get("kendall_tau_p_value")
    if p_val is not None:
        assert 0.0 <= p_val <= 1.0, f"P-value {p_val} out of range [0, 1]"

    # Check CI width is non-negative
    ci_width = data.get("robustness", {}).get("ci_width")
    if ci_width is not None:
        assert ci_width >= 0.0, f"CI width {ci_width} must be non-negative"

    # Check power estimate range
    power = data.get("power_analysis", {}).get("power_estimate")
    if power is not None:
        assert 0.0 <= power <= 1.0, f"Power estimate {power} out of range [0, 1]"

    # Check sample counts
    n = data.get("sample_size", 0)
    censored = data.get("censored_count", 0)
    assert censored <= n, f"Censored count {censored} cannot exceed sample size {n}"