"""
Module T030a: Output MDC Stats
Implements save_mdc_stats to aggregate Minimum Detectable Concentration statistics.
Depends on T020 (retrieval_results.csv).
"""
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional, List

import pandas as pd
import numpy as np

# Configure logging to use project standard if available, otherwise basic config
logger = logging.getLogger(__name__)
if not logger.handlers:
    handler = logging.StreamHandler()
    formatter = logging.Formatter('%(asctime)s - %(name)s - %(levelname)s - %(message)s')
    handler.setFormatter(formatter)
    logger.addHandler(handler)
    logger.setLevel(logging.INFO)

def load_retrieval_results(input_path: Optional[Path] = None) -> pd.DataFrame:
    """
    Load the retrieval results CSV generated by T020.
    
    Args:
        input_path: Path to retrieval_results.csv. Defaults to data/processed/retrieval_results.csv.
        
    Returns:
        DataFrame containing retrieval results including min_detectable_concentration.
        
    Raises:
        FileNotFoundError: If the file does not exist.
        ValueError: If required columns are missing.
    """
    if input_path is None:
        input_path = Path("data/processed/retrieval_results.csv")
    
    if not input_path.exists():
        raise FileNotFoundError(f"Retrieval results not found at {input_path}. "
                              "Ensure T020 (retrieval.py) has run successfully.")
    
    df = pd.read_csv(input_path)
    
    required_cols = ['planet_name', 'min_detectable_concentration', 'is_upper_limit']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in retrieval results: {missing}")
    
    logger.info(f"Loaded {len(df)} retrieval results from {input_path}")
    return df

def compute_mdc_statistics(df: pd.DataFrame) -> Dict[str, Any]:
    """
    Compute aggregate statistics for the Minimum Detectable Concentration (MDC).
    
    This addresses Marie Curie's concern regarding the "minimum quantity of 
    atmospheric material" detectable by the pipeline.
    
    Args:
        df: DataFrame with 'min_detectable_concentration' and 'is_upper_limit' columns.
        
    Returns:
        Dictionary containing MDC statistics.
    """
    if df.empty:
        logger.warning("Empty DataFrame provided. Returning zero statistics.")
        return {
            "count": 0,
            "median_mdc": None,
            "mean_mdc": None,
            "std_mdc": None,
            "min_mdc": None,
            "max_mdc": None,
            "percentile_95_mdc": None,
            "upper_limit_count": 0,
            "detection_count": 0
        }

    mdc_series = df['min_detectable_concentration'].dropna()
    
    if mdc_series.empty:
        logger.warning("No valid MDC values found in DataFrame.")
        return {
            "count": 0,
            "median_mdc": None,
            "mean_mdc": None,
            "std_mdc": None,
            "min_mdc": None,
            "max_mdc": None,
            "percentile_95_mdc": None,
            "upper_limit_count": 0,
            "detection_count": 0
        }

    # Calculate statistics
    median_val = float(mdc_series.median())
    mean_val = float(mdc_series.mean())
    std_val = float(mdc_series.std())
    min_val = float(mdc_series.min())
    max_val = float(mdc_series.max())
    p95_val = float(mdc_series.quantile(0.95))

    # Count limits
    upper_limit_count = int(df['is_upper_limit'].sum())
    detection_count = int(len(df) - upper_limit_count)

    stats = {
        "count": int(len(df)),
        "median_mdc": median_val,
        "mean_mdc": mean_val,
        "std_mdc": std_val,
        "min_mdc": min_val,
        "max_mdc": max_val,
        "percentile_95_mdc": p95_val,
        "upper_limit_count": upper_limit_count,
        "detection_count": detection_count,
        "notes": "MDC statistics derived from real retrieval results. "
                 "95th percentile represents the effective detection floor for 95% of the sample."
    }
    
    logger.info(f"MDC Statistics computed: Median={median_val:.4e}, 95th Percentile={p95_val:.4e}")
    return stats

def save_mdc_stats(stats: Dict[str, Any], output_path: Optional[Path] = None) -> Path:
    """
    Save the MDC statistics to a JSON file.
    
    Args:
        stats: Dictionary of statistics to save.
        output_path: Path for the output JSON. Defaults to data/processed/mdc_stats.json.
        
    Returns:
        Path to the saved file.
    """
    if output_path is None:
        output_path = Path("data/processed/mdc_stats.json")
    
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(stats, f, indent=2)
    
    logger.info(f"MDC statistics saved to {output_path}")
    return output_path

def main():
    """
    Main entry point for T030a.
    Loads retrieval results, computes MDC stats, and saves them.
    """
    try:
        # 1. Load Data
        logger.info("Starting T030a: Output MDC Stats")
        df = load_retrieval_results()
        
        # 2. Compute Statistics
        stats = compute_mdc_statistics(df)
        
        # 3. Save Results
        output_file = save_mdc_stats(stats)
        
        logger.info(f"T030a completed successfully. Output: {output_file}")
        
    except FileNotFoundError as e:
        logger.error(f"Data not found: {e}")
        raise
    except Exception as e:
        logger.error(f"Error during T030a execution: {e}")
        raise

if __name__ == "__main__":
    main()