logger = logging.getLogger(__name__)


def process_retrieval_results(
    retrieval_results: List[RetrievalResult],
    output_path: Optional[Path] = None
) -> pd.DataFrame:
    """
    Convert a list of RetrievalResult objects into a pandas DataFrame and save
    to CSV.

    Handles censored data (upper limits) by marking them explicitly in the
    output columns as per reviewer requirements for evidentiary standards.

    Args:
        retrieval_results: List of RetrievalResult objects from the retrieval stage.
        output_path: Optional path to write the CSV. If None, uses config default.

    Returns:
        DataFrame containing the structured retrieval results.
    """
    if not retrieval_results:
        logger.warning("No retrieval results provided. Returning empty DataFrame.")
        return pd.DataFrame()

    records = []
    for res in retrieval_results:
        record = {
            'planet_name': res.planet_name,
            'equilibrium_temperature_K': res.equilibrium_temperature_K,
            'host_metallicity_fe_h': res.host_metallicity_fe_h,
            'spectral_resolution_R': res.spectral_resolution_R,
            'snr': res.snr,
            'log10_water_mixing_ratio': res.log10_water_mixing_ratio,
            'water_mixing_ratio_std': res.water_mixing_ratio_std,
            'is_censored': res.censorship_status == CensorshipStatus.UPPER_LIMIT,
            'censorship_status': res.censorship_status.value,
            'convergence_status': res.convergence_status,
            'retrieval_log_likelihood': res.log_likelihood,
        }
        records.append(record)

    df = pd.DataFrame(records)

    if output_path is None:
        config = get_config()
        output_path = Path(config['output_paths']['retrieval_results_csv'])

    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Write to CSV
    df.to_csv(output_path, index=False)
    logger.info(f"Saved {len(df)} retrieval results to {output_path}")

    return df


def main():
    """
    Entry point for the retrieval output generation script.
    This script expects retrieval results to have been generated by `retrieval.py`
    and stored in memory or a temporary structure. In a real pipeline, this would
    be called after the retrieval loop completes.

    For this implementation, we simulate loading results from a pickle or
    reconstructing them if the retrieval step has already run.
    However, per task requirements, we assume `retrieval.py` has populated
    a list of `RetrievalResult` objects which we then serialize.

    Since this task is about *output generation*, we will:
    1. Attempt to load existing results if available (e.g., from a pickle).
    2. If not available, we assume the pipeline flow calls this function
       directly with the list of results.
    3. For demonstration/execution purposes, we check if data/processed/retrieval_results.csv
       needs to be generated from existing raw data if the retrieval step was simulated.

    NOTE: In the actual pipeline execution, `retrieval.py` would call this function
    or pass the list to it. Here we provide the standalone script that can be
    invoked if results are available in a standard location.
    """
    setup_logging()
    config = get_config()

    # Path to raw spectrum metadata (from US1)
    metadata_path = Path(config['data_paths']['processed_metadata_csv'])
    
    # If metadata exists, we assume retrieval was run and results should be
    # available. However, since T018b/T019 might not have been fully executed
    # in isolation, we check for a pickle of results or run a mock retrieval
    # ONLY if the file is missing to satisfy the "real output" constraint.
    # BUT, per strict "real data only", we must not fake retrieval results.
    # Instead, we look for a `retrieval_results.pkl` that `retrieval.py` should have created.
    
    results_pickle_path = Path(config['output_paths'].get('retrieval_results_pickle', 'data/processed/retrieval_results.pkl'))
    
    if results_pickle_path.exists():
        import pickle
        try:
            with open(results_pickle_path, 'rb') as f:
                results = pickle.load(f)
            if not isinstance(results, list) or not all(isinstance(r, RetrievalResult) for r in results):
                raise TypeError("Invalid retrieval results format in pickle.")
            logger.info(f"Loaded {len(results)} results from {results_pickle_path}")
        except Exception as e:
            logger.error(f"Failed to load results from pickle: {e}")
            raise
    else:
        # If no pickle exists, we cannot fabricate data.
        # We check if we can re-run retrieval (T018b) or if we are in a state
        # where the pipeline expects this script to be called *after* retrieval.
        # Since T020 is "Implement output generation", we assume the caller
        # (the pipeline runner) will pass the list.
        # To make this script runnable as a standalone task for verification,
        # we attempt to import and run the retrieval logic if it hasn't been run.
        # However, to avoid circular dependencies or re-running heavy code,
        # we raise an error if the source data is missing.
        raise FileNotFoundError(
            f"Retrieval results not found at {results_pickle_path}. "
            "Please ensure T018b (retrieval) has completed and saved results."
        )

    # Generate the CSV output
    df = process_retrieval_results(results)
    
    # Log summary stats for verification
    logger.info(f"Total planets: {len(df)}")
    logger.info(f"Censored (Upper Limits): {df['is_censored'].sum()}")
    logger.info(f"Uncensored: {(~df['is_censored']).sum()}")
    logger.info(f"Water mixing ratio mean (uncensored): {df[~df['is_censored']]['log10_water_mixing_ratio'].mean():.4f}")

if __name__ == "__main__":
    main()