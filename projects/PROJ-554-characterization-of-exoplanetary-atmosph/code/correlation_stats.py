"""
Module to compute and save correlation statistics (Kendall's tau, p-values, CI width).
This implements task T030a.
"""
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional

import pandas as pd
import numpy as np

from config import get_config
from utils import setup_logging

logger = logging.getLogger(__name__)


def load_correlation_results(input_path: Optional[str] = None) -> Dict[str, Any]:
    """
    Load correlation results from the bootstrap CI JSON file generated by analysis.py.
    
    Args:
        input_path: Path to the bootstrap_ci.json file. Defaults to config value.
        
    Returns:
        Dictionary containing Kendall's tau, p-value, and bootstrap CI data.
    """
    config = get_config()
    if input_path is None:
        input_path = config.get('paths', {}).get('bootstrap_ci_file', 'data/processed/bootstrap_ci.json')
    
    path = Path(input_path)
    if not path.exists():
        raise FileNotFoundError(f"Bootstrap results file not found: {path}")
    
    with open(path, 'r') as f:
        data = json.load(f)
    
    logger.info(f"Loaded correlation results from {path}")
    return data


def compute_ci_width(tau_lower: float, tau_upper: float) -> float:
    """
    Compute the width of the confidence interval.
    
    Args:
        tau_lower: Lower bound of the CI.
        tau_upper: Upper bound of the CI.
        
    Returns:
        Width of the confidence interval.
    """
    return tau_upper - tau_lower


def save_correlation_stats(
    results: Dict[str, Any],
    output_path: Optional[str] = None
) -> None:
    """
    Save correlation statistics to a JSON file.
    
    Args:
        results: Dictionary containing correlation statistics.
        output_path: Path to save the output JSON. Defaults to config value.
    """
    config = get_config()
    if output_path is None:
        output_path = config.get('paths', {}).get('correlation_stats_file', 'data/processed/correlation_stats.json')
    
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(path, 'w') as f:
        json.dump(results, f, indent=2)
    
    logger.info(f"Saved correlation statistics to {path}")


def main() -> None:
    """Main entry point for generating correlation statistics."""
    setup_logging()
    logger.info("Starting correlation statistics generation (T030a)")
    
    try:
        # Load bootstrap results containing Kendall's tau and CI
        bootstrap_data = load_correlation_results()
        
        # Extract key statistics
        tau = bootstrap_data.get('kendall_tau')
        p_value = bootstrap_data.get('p_value')
        ci_lower = bootstrap_data.get('ci_lower')
        ci_upper = bootstrap_data.get('ci_upper')
        iterations = bootstrap_data.get('iterations', 1000)
        
        if tau is None or ci_lower is None or ci_upper is None:
            raise ValueError("Missing required fields in bootstrap results")
        
        # Compute CI width
        ci_width = compute_ci_width(ci_lower, ci_upper)
        
        # Prepare output dictionary
        correlation_stats = {
            'kendall_tau': tau,
            'p_value': p_value,
            'ci_lower': ci_lower,
            'ci_upper': ci_upper,
            'ci_width': ci_width,
            'bootstrap_iterations': iterations,
            'status': 'success'
        }
        
        # Save results
        save_correlation_stats(correlation_stats)
        
        logger.info(f"Correlation statistics computed successfully. CI width: {ci_width:.4f}")
        
    except Exception as e:
        logger.error(f"Failed to compute correlation statistics: {e}")
        raise


if __name__ == "__main__":
    main()