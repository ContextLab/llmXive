logger = logging.getLogger(__name__)

def load_retrieval_results(config: Dict[str, Any]) -> pd.DataFrame:
    """
    Load the retrieval results CSV generated by T020.
    Handles censored data (upper limits) by parsing the 'is_upper_limit' flag.
    """
    results_path = Path(config['paths']['processed']) / 'retrieval_results.csv'
    if not results_path.exists():
        raise FileNotFoundError(f"Retrieval results file not found at {results_path}. "
                                "Ensure T020 has completed successfully.")
    
    df = pd.read_csv(results_path)
    
    required_cols = ['planet_name', 'water_mixing_ratio', 'is_upper_limit']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in retrieval results: {missing_cols}")
    
    # Ensure types
    df['water_mixing_ratio'] = pd.to_numeric(df['water_mixing_ratio'], errors='coerce')
    df['is_upper_limit'] = df['is_upper_limit'].astype(bool)
    
    logger.info(f"Loaded {len(df)} retrieval results from {results_path}")
    return df

def compute_ci_width(df: pd.DataFrame) -> float:
    """
    Compute the 95% Confidence Interval width of the water mixing ratio distribution
    using the Kaplan-Meier estimator to account for censored values (upper limits).
    
    The Kaplan-Meier estimator is appropriate here because:
    1. We have censored data (upper limits for non-detections).
    2. We need a robust estimate of the distribution's spread (CI width) that
       respects the censoring mechanism, rather than treating upper limits as
       exact values or dropping them.
    
    We use the 'lifelines' library which implements Kaplan-Meier for survival data.
    In this context, 'survival' is treated as the cumulative distribution function (CDF)
    of the water mixing ratio.
    
    Returns:
        float: The width of the 95% CI (log10 units/dex).
    """
    try:
        from lifelines import KaplanMeierFitter
    except ImportError:
        logger.error("lifelines library is required for Kaplan-Meier estimation. "
                     "Please install it via requirements.txt.")
        raise

    # Prepare data for lifelines
    # In lifelines, 'T' is the time (value) and 'E' is the event indicator.
    # For an upper limit (censored), the event (detection) did NOT happen.
    # So, if is_upper_limit is True, event = 0 (censored).
    # If is_upper_limit is False, event = 1 (detected).
    
    df_clean = df.dropna(subset=['water_mixing_ratio'])
    
    if len(df_clean) == 0:
        logger.warning("No valid water mixing ratio data found after dropping NaNs.")
        return 0.0

    kmf = KaplanMeierFitter()
    
    # T = water_mixing_ratio, E = 1 if detected, 0 if censored (upper limit)
    T = df_clean['water_mixing_ratio'].values
    E = (~df_clean['is_upper_limit']).astype(int).values
    
    kmf.fit(T, event_observed=E)
    
    # Calculate 95% CI for the median or the distribution range?
    # The task asks for the "CI width of the water mixing ratio distribution".
    # In survival analysis, the CI of the survival function is standard.
    # However, for a distribution summary, the CI of the *median* is a common robust metric.
    # Alternatively, we can look at the 2.5th and 97.5th percentiles of the estimated CDF.
    
    # Let's compute the 2.5th and 97.5th percentiles of the KM estimator.
    # The KM estimator gives S(t) = P(T > t).
    # We want the range [t_low, t_high] such that the cumulative probability covers 95%.
    # This corresponds to finding t where S(t) = 0.975 and S(t) = 0.025.
    
    # lifelines has a method `median` but we need the full percentile range.
    # We can use `percentiles` method if available, or interpolate from the survival curve.
    
    # Check if we can get the survival curve at specific points or percentiles.
    # lifelines.KaplanMeierFitter has `summary` and `plot`.
    # A robust way: Get the time points corresponding to survival probabilities 0.975 and 0.025.
    
    # The survival function S(t) is a step function.
    # We want t such that S(t) >= 0.975 (lower bound of the 95% interval)
    # and t such that S(t) <= 0.025 (upper bound).
    
    # Using the `survival_function_` attribute which is a DataFrame with 'km_fit' and 'upper'/'lower' bounds?
    # No, we want the quantile function (inverse CDF).
    
    # Let's use the `percentiles` method which returns the time at which the survival function
    # crosses the given probability.
    # Note: percentiles in lifelines are for the *event* time distribution.
    # S(t) = 1 - F(t). So F(t) = 1 - S(t).
    # We want the 2.5th percentile (F(t)=0.025 => S(t)=0.975)
    # and 97.5th percentile (F(t)=0.975 => S(t)=0.025).
    
    try:
        # lifelines >= 0.25.0 has `percentiles`
        percentiles = kmf.percentiles([2.5, 97.5])
        # percentiles is a Series: index is the percentile, value is the time (water mixing ratio)
        p25 = percentiles[2.5]
        p975 = percentiles[97.5]
        
        if pd.isna(p25) or pd.isna(p975):
            # If the curve doesn't reach these percentiles (e.g. all censored or small N),
            # we might need to handle it. But for a robust report, we return the width if possible.
            logger.warning("Could not compute 2.5th or 97.5th percentile from KM estimator. "
                           "Data might be too censored or small.")
            return 0.0
        
        ci_width = p975 - p25
        logger.info(f"Computed 95% CI width using KM estimator: {ci_width:.4f} dex")
        return float(ci_width)
        
    except AttributeError:
        # Fallback for older lifelines versions: manual interpolation
        logger.warning("lifelines version might be too old for `percentiles`. Attempting manual calculation.")
        # Get the survival function values
        s = kmf.survival_function_
        # We need to find t where S(t) crosses 0.975 and 0.025
        # s is a DataFrame with index as time
        times = s.index.values
        surv_vals = s[kmf.name].values # assuming name is 'km_fit' or similar, check actual column
        
        # Find indices where survival drops below thresholds
        # 97.5th percentile: S(t) = 0.025 (since 97.5% of data is below this, so 2.5% survival)
        # 2.5th percentile: S(t) = 0.975
        
        # Find index where surv_vals <= 0.975 for the first time (2.5th percentile of distribution)
        idx_low = np.where(surv_vals <= 0.975)[0]
        # Find index where surv_vals <= 0.025 for the first time (97.5th percentile of distribution)
        idx_high = np.where(surv_vals <= 0.025)[0]
        
        if len(idx_low) == 0 or len(idx_high) == 0:
            logger.warning("Survival curve does not reach required thresholds for CI calculation.")
            return 0.0
        
        t_low = times[idx_low[0]]
        t_high = times[idx_high[0]]
        
        return float(t_high - t_low)

def determine_threshold_met(ci_width: float, threshold: float = 0.2) -> bool:
    """
    Explicitly verify if the CI width is <= 0.2 dex.
    """
    return ci_width <= threshold

def save_robustness_report(ci_width: float, threshold_met: bool, output_path: Path) -> None:
    """
    Save the robustness report to a JSON file.
    """
    report = {
        "ci_width": round(ci_width, 4),
        "threshold_met": threshold_met,
        "threshold_value": 0.2,
        "description": "95% CI width of water mixing ratio distribution (Kaplan-Meier estimator)"
    }
    
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Saved robustness report to {output_path}")

def main():
    """
    Main entry point for T026: Compute and report the CI width of the water mixing ratio distribution.
    """
    setup_logging()
    config = get_config()
    
    try:
        logger.info("Starting T026: Robustness Analysis (CI Width)")
        
        # Load data
        df = load_retrieval_results(config)
        
        # Compute CI width using Kaplan-Meier
        ci_width = compute_ci_width(df)
        
        # Determine if threshold is met
        threshold_met = determine_threshold_met(ci_width)
        
        # Save report
        results_dir = Path(config['paths']['results'])
        output_path = results_dir / 'robustness_report.json'
        save_robustness_report(ci_width, threshold_met, output_path)
        
        logger.info(f"T026 Complete. CI Width: {ci_width:.4f}, Threshold Met: {threshold_met}")
        
    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        raise
    except Exception as e:
        logger.error(f"Error during T026 execution: {e}", exc_info=True)
        raise

if __name__ == "__main__":
    main()
