def load_processed_data() -> pd.DataFrame:
    """
    Load the merged data from the processed directory.
    Expects: data/processed/merged_data.csv
    """
    config = get_config()
    data_path = config.get('paths', {}).get('processed_data', 'data/processed/merged_data.csv')
    
    if not os.path.exists(data_path):
        raise FileNotFoundError(f"Processed data file not found at {data_path}. "
                              "Please ensure T017 (clean_merge) has been completed successfully.")
    
    df = pd.read_csv(data_path)
    
    # Validate expected columns exist
    required_cols = ['species', 'telomere_length_kb', 'lifespan', 'migration_status', 'body_mass_g']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Processed data missing required columns: {missing}")
    
    return df

def load_moderator_results() -> Optional[pd.DataFrame]:
    """
    Load the moderator analysis results (interaction stats).
    Expects: results/moderator_analysis.csv (generated by T034/T06)
    """
    config = get_config()
    results_dir = config.get('paths', {}).get('results', 'results')
    result_path = os.path.join(results_dir, 'moderator_analysis.csv')
    
    if not os.path.exists(result_path):
        logging.warning(f"Moderator results not found at {result_path}. "
                      "Plot will be generated without regression line coefficients from model, "
                      "but will still show data grouping.")
        return None
    
    return pd.read_csv(result_path)

def plot_moderator_scatter(df: pd.DataFrame, output_path: str) -> Tuple[str, Dict[str, Any]]:
    """
    Generate a grouped scatter plot with separate regression lines for 
    'Migratory' and 'Resident' species.
    
    Args:
        df: DataFrame with columns species, telomere_length_kb, lifespan, migration_status
        output_path: Path to save the plot (e.g., 'results/moderator_plot.png')
        
    Returns:
        Tuple of (output_path, stats_dict)
    """
    # Validate migration_status values
    if 'migration_status' not in df.columns:
        raise ValueError("Input DataFrame must contain 'migration_status' column")
    
    # Filter for valid groups
    valid_groups = df['migration_status'].dropna().unique()
    if len(valid_groups) < 2:
        logging.warning(f"Only {len(valid_groups)} unique migration groups found. "
                      "Plotting may not show interaction effect clearly.")
    
    # Setup plot
    plt.figure(figsize=(10, 8))
    sns.set_style("whitegrid")
    
    # Create scatter plot with regression lines per group
    # Use hue for migration status, fit_reg=True for regression lines
    # Since seaborn regplot/hue handles multiple groups, we use lmplot or scatterplot+regplot
    
    # Ensure we have numeric data for regression
    numeric_df = df.dropna(subset=['telomere_length_kb', 'lifespan', 'migration_status'])
    
    if len(numeric_df) == 0:
        raise ValueError("No valid numeric data points for regression plotting.")
    
    # Use lmplot for grouped regression
    g = sns.lmplot(
        data=numeric_df,
        x='telomere_length_kb',
        y='lifespan',
        hue='migration_status',
        palette='Set1',
        markers=['o', 's'],
        height=8,
        aspect=1.25,
        scatter_kws={'s': 60, 'alpha': 0.7, 'edgecolor': 'w'},
        line_kws={'lw': 2}
    )
    
    g.set_axis_labels("Telomere Length (kb)", "Lifespan (years)")
    g.fig.suptitle("Telomere Length vs Lifespan by Migration Status", y=1.02, fontsize=14)
    g.add_legend(title="Migration Status")
    
    # Calculate and annotate statistics per group
    stats_dict = {}
    for group in numeric_df['migration_status'].unique():
        group_data = numeric_df[numeric_df['migration_status'] == group]
        if len(group_data) > 1:
            # Simple linear regression stats
            x = group_data['telomere_length_kb'].values
            y = group_data['lifespan'].values
            
            # Calculate slope and intercept manually for annotation
            slope = np.cov(x, y, bias=False)[0, 1] / np.var(x)
            intercept = np.mean(y) - slope * np.mean(x)
            r_squared = np.corrcoef(x, y)[0, 1]**2
            
            stats_dict[group] = {
                'slope': slope,
                'intercept': intercept,
                'r_squared': r_squared,
                'n': len(group_data)
            }
    
    # Save plot
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()
    
    logging.info(f"Moderator scatter plot saved to {output_path}")
    
    return output_path, stats_dict

def main():
    """
    Main entry point for T035: Generate moderator scatter plot.
    
    Dependencies:
        - data/processed/merged_data.csv (from T017)
        - results/moderator_analysis.csv (optional, from T034)
        
    Outputs:
        - results/moderator_plot.png
    """
    # Initialize logging
    init_project_logging()
    logger = logging.getLogger(__name__)
    
    try:
        # Check memory pressure
        log_memory_status()
        
        # Load data
        logger.info("Loading processed data...")
        df = load_processed_data()
        logger.info(f"Loaded {len(df)} records from processed data.")
        
        # Check for required columns
        required = ['species', 'telomere_length_kb', 'lifespan', 'migration_status']
        missing = [c for c in required if c not in df.columns]
        if missing:
            raise ValueError(f"Missing required columns: {missing}")
        
        # Optional: Load moderator results for annotation (not strictly required for plot)
        moderator_results = load_moderator_results()
        if moderator_results is not None:
            logger.info(f"Loaded moderator results with {len(moderator_results)} entries.")
        
        # Define output path
        config = get_config()
        results_dir = config.get('paths', {}).get('results', 'results')
        output_path = os.path.join(results_dir, 'moderator_plot.png')
        
        # Ensure results directory exists
        os.makedirs(results_dir, exist_ok=True)
        
        # Generate plot
        logger.info("Generating moderator scatter plot...")
        saved_path, stats = plot_moderator_scatter(df, output_path)
        
        # Log summary stats
        logger.info("Plot generation statistics:")
        for group, stat in stats.items():
            logger.info(f"  {group}: slope={stat['slope']:.4f}, r2={stat['r_squared']:.4f}, n={stat['n']}")
        
        logger.info(f"Task T035 completed successfully. Output: {saved_path}")
        
    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during plot generation: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()