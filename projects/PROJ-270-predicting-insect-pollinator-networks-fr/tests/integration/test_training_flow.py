def test_training_flow_integration(test_environment):
    """
    Integration test: Run the full training loop on the available data.
    
    Steps:
    1. Load the feature matrix from data/processed/feature_matrix.csv
    2. Run the training loop (CV + Permutation Importance)
    3. Verify that model.pkl is saved to data/processed/
    4. Verify that metrics.json is saved to results/
    5. Verify the structure of the metrics file
    """
    # 1. Load Data
    logger.info("Loading feature matrix...")
    X, y, feature_names = load_feature_matrix()
    
    assert X is not None, "Feature matrix X is None"
    assert y is not None, "Target vector y is None"
    assert len(X) == len(y), "X and y length mismatch"
    assert X.shape[1] == len(feature_names), "Feature names count mismatch"
    
    logger.info(f"Loaded data: X shape {X.shape}, y shape {y.shape}")
    
    # 2. Run Training
    # We mock the model saving to a temporary directory to avoid cluttering the real results 
    # if this test is run in isolation, but the actual code saves to the configured paths.
    # However, per requirements, the script must write to the real paths.
    # We will run the training directly.
    
    logger.info("Starting Random Forest training with Cross-Validation...")
    
    try:
        model, metrics = train_random_forest(X, y, feature_names, cv_folds=3, seed=TEST_SEED)
    except Exception as e:
        logger.error(f"Training failed: {e}")
        raise e
    
    # 3. Verify Model Serialization
    results_root = get_results_root()
    model_path = results_root / EXPECTED_MODEL_FILENAME
    metrics_path = results_root / EXPECTED_METRICS_FILENAME
    
    # Check if files exist
    assert model_path.exists(), f"Model file not found at {model_path}"
    assert metrics_path.exists(), f"Metrics file not found at {metrics_path}"
    
    logger.info(f"Model saved to {model_path}")
    logger.info(f"Metrics saved to {metrics_path}")
    
    # 4. Verify Metrics Content
    with open(metrics_path, 'r') as f:
        saved_metrics = json.load(f)
    
    assert isinstance(saved_metrics, dict), "Metrics should be a dictionary"
    
    for key in EXPECTED_METRICS_KEYS:
        assert key in saved_metrics, f"Missing expected key '{key}' in metrics"
        assert saved_metrics[key] is not None, f"Key '{key}' is None"
    
    # Verify specific metric types
    assert isinstance(saved_metrics["auc_roc_mean"], (int, float)), "AUC mean should be numeric"
    assert isinstance(saved_metrics["auc_roc_std"], (int, float)), "AUC std should be numeric"
    assert isinstance(saved_metrics["permutation_importance"], list), "Permutation importance should be a list"
    
    # Verify AUC is in valid range
    assert 0.0 <= saved_metrics["auc_roc_mean"] <= 1.0, "AUC mean out of range [0, 1]"
    
    logger.info(f"Metrics validation passed: AUC Mean={saved_metrics['auc_roc_mean']:.4f}, Std={saved_metrics['auc_roc_std']:.4f}")
    
    # 5. Verify Model Loadability
    import joblib
    loaded_model = joblib.load(model_path)
    assert loaded_model is not None, "Loaded model is None"
    assert hasattr(loaded_model, 'predict'), "Loaded model missing 'predict' method"
    
    # Run a quick prediction to ensure it works
    sample_pred = loaded_model.predict(X[:5])
    assert len(sample_pred) == 5, "Prediction length mismatch"
    
    logger.info("Integration test PASSED: Training loop executed successfully.")

