"""
Reporting module for generating the final research report.
Implements T045a (Template) and T045b (Content Compilation).
"""
import os
import json
from pathlib import Path
from typing import Dict, Any, List, Optional
import logging

try:
    from jinja2 import Template, Environment, FileSystemLoader
    JINJA_AVAILABLE = True
except ImportError:
    JINJA_AVAILABLE = False
    logging.warning("Jinja2 not installed. Report generation will fall back to string formatting.")

from config import get_results_root, ensure_directories_exist
from utils.logger import get_logger

logger = get_logger(__name__)

REPORT_TEMPLATE_STR = """
# Predicting Insect Pollinator Networks: Research Report

## Executive Summary
This report summarizes the results of the Leave-One-Ecosystem-Out (LOEO) cross-validation
and the analysis of trait importance in predicting pollinator networks.

## Model Performance
- **Mean AUC-ROC**: {{ auc_mean }}
- **Standard Deviation**: {{ auc_std }}

## Trait Importance
The following traits were identified as the most predictive of interaction links:
{% for trait in trait_importance_ranking %}
- {{ loop.index }}. {{ trait }}
{% endfor %}

## Generalization Analysis
- **Trait Gap**: {{ trait_gap }}
(Difference between Trait-Only Baseline AUC and Trait-Shuffled Null AUC)

## Conclusion
The model demonstrates {{ "significant" if trait_gap > 0.05 else "limited" }} ability to generalize
based on floral traits alone, with a trait gap of {{ trait_gap }}.

---
Generated by llmXive Pipeline
"""

def generate_report_template(template_str: Optional[str] = None) -> str:
    """
    T045a: Implement report template.
    Returns the raw template string.
    """
    return template_str or REPORT_TEMPLATE_STR

def compile_report_content(results: Dict[str, Any]) -> str:
    """
    T045b: Implement content compilation.
    Uses Jinja2 to insert metrics into the template and writes to results/report.md.
    
    Args:
        results: Dictionary containing:
            - auc_mean (float)
            - auc_std (float)
            - trait_importance_ranking (list of str)
            - trait_gap (float)
    
    Returns:
        The generated markdown content.
    
    Raises:
        FileNotFoundError: If required result files are missing.
        ValueError: If required keys are missing from results.
    """
    ensure_directories_exist()
    results_root = get_results_root()
    report_path = Path(results_root) / "report.md"
    metrics_path = Path(results_root) / "metrics.json"
    
    # Load metrics if not provided in the results dict
    if not results:
        if not metrics_path.exists():
            raise FileNotFoundError(f"Results metrics file not found at {metrics_path}")
        with open(metrics_path, 'r') as f:
            results = json.load(f)
    
    # Validate required keys
    required_keys = ['auc_mean', 'auc_std', 'trait_importance_ranking', 'trait_gap']
    for key in required_keys:
        if key not in results:
            raise ValueError(f"Missing required key '{key}' in results/metrics.json")
    
    auc_mean = results['auc_mean']
    auc_std = results['auc_std']
    trait_importance_ranking = results['trait_importance_ranking']
    trait_gap = results['trait_gap']
    
    # Format trait gap to 4 decimal places for readability
    trait_gap_formatted = f"{trait_gap:.4f}"
    
    template_content = generate_report_template()
    
    if JINJA_AVAILABLE:
        try:
            env = Environment()
            template = env.from_string(template_content)
            rendered_content = template.render(
                auc_mean=auc_mean,
                auc_std=auc_std,
                trait_importance_ranking=trait_importance_ranking,
                trait_gap=trait_gap_formatted
            )
        except Exception as e:
            logger.error(f"Jinja2 rendering failed: {e}. Falling back to manual formatting.")
            # Fallback to simple string replacement if Jinja fails
            rendered_content = template_content.replace("{{ auc_mean }}", str(auc_mean))
            rendered_content = rendered_content.replace("{{ auc_std }}", str(auc_std))
            rendered_content = rendered_content.replace("{{ trait_gap }}", trait_gap_formatted)
            
            # Handle list formatting manually for fallback
            traits_list = "\n".join([f"- {i+1}. {t}" for i, t in enumerate(trait_importance_ranking)])
            rendered_content = rendered_content.replace(
                "{% for trait in trait_importance_ranking %}\n- {{ loop.index }}. {{ trait }}\n{% endfor %}",
                traits_list
            )
    else:
        # Manual fallback without Jinja
        rendered_content = template_content
        rendered_content = rendered_content.replace("{{ auc_mean }}", str(auc_mean))
        rendered_content = rendered_content.replace("{{ auc_std }}", str(auc_std))
        rendered_content = rendered_content.replace("{{ trait_gap }}", trait_gap_formatted)
        
        # Replace the loop block manually
        traits_list = "\n".join([f"- {i+1}. {t}" for i, t in enumerate(trait_importance_ranking)])
        rendered_content = rendered_content.replace(
            "{% for trait in trait_importance_ranking %}\n- {{ loop.index }}. {{ trait }}\n{% endfor %}",
            traits_list
        )
    
    # Write to file
    with open(report_path, 'w', encoding='utf-8') as f:
        f.write(rendered_content)
    
    logger.info(f"Report generated successfully at {report_path}")
    logger.info(f"Trait Gap verified in report: {trait_gap_formatted}")
    
    return rendered_content

def main():
    """
    Entry point for report generation.
    Reads metrics from results/metrics.json and generates results/report.md.
    """
    try:
        results_root = get_results_root()
        metrics_path = Path(results_root) / "metrics.json"
        
        if not metrics_path.exists():
            logger.error(f"Metrics file not found at {metrics_path}. Run model_training.py first.")
            return 1
        
        with open(metrics_path, 'r') as f:
            metrics = json.load(f)
        
        compile_report_content(metrics)
        return 0
        
    except Exception as e:
        logger.error(f"Report generation failed: {e}")
        return 1

if __name__ == "__main__":
    exit(main())
