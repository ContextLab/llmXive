import os
import sys
import argparse
import logging
from pathlib import Path
import pandas as pd

# Ensure project root is in path for imports if running as script
if 'code' not in sys.path:
    project_root = Path(__file__).resolve().parent.parent
    sys.path.insert(0, str(project_root))

from utils.logger import get_logger
from utils.config import get_config_dict

CONFIG = get_config_dict()

def load_split_metadata(split_metadata_path: Path) -> pd.DataFrame:
    """
    Load the split metadata CSV generated by the preprocessing step.
    Expects columns: ['split', 'alloy_family', ...]
    """
    if not split_metadata_path.exists():
        raise FileNotFoundError(f"Split metadata file not found: {split_metadata_path}")
    
    df = pd.read_csv(split_metadata_path)
    
    required_cols = ['split', 'alloy_family']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Split metadata missing required columns: {missing_cols}")
    
    return df

def aggregate_split_distribution(df: pd.DataFrame) -> pd.DataFrame:
    """
    Aggregate the split metadata to count samples per split and alloy family.
    Returns a DataFrame with columns: ['split', 'alloy_family', 'count']
    """
    if df.empty:
        logging.warning("Input dataframe is empty. Returning empty result.")
        return pd.DataFrame(columns=['split', 'alloy_family', 'count'])

    # Group by split and alloy_family and count
    counts = df.groupby(['split', 'alloy_family']).size().reset_index(name='count')
    
    # Ensure consistent column order
    counts = counts[['split', 'alloy_family', 'count']]
    
    return counts

def save_split_metadata(counts_df: pd.DataFrame, output_path: Path) -> None:
    """
    Save the aggregated split metadata to a CSV file.
    """
    counts_df.to_csv(output_path, index=False)
    logging.info(f"Saved split metadata to {output_path}")

def main():
    """
    Main entry point to generate split_metadata.csv from the processed split data.
    """
    # Setup logging
    logger = get_logger("generate_split_metadata")
    
    parser = argparse.ArgumentParser(description="Generate split metadata CSV")
    parser.add_argument(
        "--input", 
        type=str, 
        default="data/processed/split_metadata.csv",
        help="Path to the input split metadata CSV (from preprocessing)"
    )
    parser.add_argument(
        "--output", 
        type=str, 
        default="data/processed/split_metadata.csv",
        help="Path to the output split metadata CSV (aggregated counts)"
    )
    
    args = parser.parse_args()
    
    input_path = Path(args.input)
    output_path = Path(args.output)
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    try:
        logger.info(f"Loading split metadata from {input_path}")
        df = load_split_metadata(input_path)
        
        logger.info(f"Aggregating distribution for {len(df)} records")
        counts_df = aggregate_split_distribution(df)
        
        logger.info(f"Saving aggregated counts to {output_path}")
        save_split_metadata(counts_df, output_path)
        
        logger.info("Split metadata generation completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
