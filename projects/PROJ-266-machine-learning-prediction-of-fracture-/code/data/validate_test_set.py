"""
Validation script for T016: Ensure test set contains at least one sample per alloy family.

This script loads the split metadata generated by the preprocessing pipeline (T014/T015)
and verifies that the 'test' split contains at least one sample for each expected alloy family
('steel', 'Al', 'Ti'). If any family is missing, it exits with code 1 and prints an error.
"""

import os
import sys
import argparse
import logging
import pandas as pd
from pathlib import Path

# Add project root to path if running as script
if __name__ == "__main__":
    project_root = Path(__file__).resolve().parent.parent.parent
    sys.path.insert(0, str(project_root))

from code.utils.logger import get_logger
from code.utils.config import get_config_dict

CONFIG = get_config_dict()
EXPECTED_FAMILIES = {'steel', 'Al', 'Ti'}

def validate_test_set_families(split_metadata_path: Path) -> bool:
    """
    Validates that the test split in the metadata contains all expected alloy families.

    Args:
        split_metadata_path: Path to the split_metadata.csv file.

    Returns:
        True if validation passes, False otherwise.
    """
    logger = get_logger("validate_test_set")
    
    if not split_metadata_path.exists():
        logger.error(f"Split metadata file not found: {split_metadata_path}")
        print(f"ERROR: Split metadata file not found: {split_metadata_path}")
        return False

    try:
        df = pd.read_csv(split_metadata_path)
    except Exception as e:
        logger.error(f"Failed to read split metadata: {e}")
        print(f"ERROR: Failed to read split metadata: {e}")
        return False

    # Check required columns
    required_cols = ['split', 'alloy_family']
    if not all(col in df.columns for col in required_cols):
        missing = set(required_cols) - set(df.columns)
        logger.error(f"Missing required columns in split metadata: {missing}")
        print(f"ERROR: Missing required columns in split metadata: {missing}")
        return False

    # Filter for test set
    test_df = df[df['split'] == 'test']
    
    if test_df.empty:
        logger.error("Test set is empty in split metadata.")
        print("ERROR: Test set is empty in split metadata.")
        return False

    # Get unique alloy families in test set
    # Handle case where alloy_family might be aggregated (count > 1) or individual rows
    # The schema in T015 suggests: ['split', 'alloy_family', 'count']
    # If 'count' exists, we just check presence. If not, we check unique values.
    if 'count' in df.columns:
        # Aggregated format: check if any row exists for each family in test split
        test_families = set(test_df['alloy_family'].unique())
    else:
        # Individual row format
        test_families = set(test_df['alloy_family'].unique())

    missing_families = EXPECTED_FAMILIES - test_families

    if missing_families:
        error_msg = f"ERROR: Test set missing alloy family: {', '.join(sorted(missing_families))}"
        logger.error(error_msg)
        print(error_msg)
        return False

    logger.info(f"Test set validation passed. Found families: {sorted(test_families)}")
    print(f"SUCCESS: Test set contains all expected alloy families: {sorted(EXPECTED_FAMILIES)}")
    return True

def main():
    parser = argparse.ArgumentParser(
        description="Validate that the test set contains at least one sample per alloy family."
    )
    parser.add_argument(
        "--input", 
        type=str, 
        default="data/processed/split_metadata.csv",
        help="Path to the split_metadata.csv file generated by preprocessing."
    )
    args = parser.parse_args()

    split_path = Path(args.input)
    
    # Setup logging
    logger = get_logger("validate_test_set")
    logger.info(f"Validating test set families using: {split_path}")

    success = validate_test_set_families(split_path)
    
    # Exit with appropriate code
    sys.exit(0 if success else 1)

if __name__ == "__main__":
    main()