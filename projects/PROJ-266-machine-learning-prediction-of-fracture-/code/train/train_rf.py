"""
Random Forest Baseline Training Loop

This module implements the training loop for a Random Forest Regressor baseline model.
It consumes features extracted by code/data/features.py and saves the trained model
and evaluation metrics to the models/baselines/rf directory.
"""

import os
import json
import argparse
import logging
from pathlib import Path
from typing import Dict, Any, List, Tuple, Optional
import numpy as np
from sklearn.ensemble import RandomForestRegressor
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_error, r2_score, mean_absolute_error

# Import logger from project utils
from code.utils.logger import get_logger
from code.utils.config import get_config_dict, set_seed

# Ensure the models/baselines directory exists
MODEL_DIR = Path("models/baselines/rf")
RESULTS_DIR = Path("results")

def load_features(features_path: str) -> Tuple[np.ndarray, np.ndarray, List[str]]:
    """
    Load features and target values from the JSON file generated by features.py.

    Args:
        features_path: Path to the features.json file.

    Returns:
        X: Feature matrix (numpy array)
        y: Target vector (K_IC values, numpy array)
        image_ids: List of image identifiers
    """
    with open(features_path, 'r') as f:
        data = json.load(f)

    # Extract feature vectors and targets
    # The features.json structure is expected to be a list of dicts with 'features' and 'k_ic'
    # or a dict with 'data' key. We handle the list format primarily.
    feature_list = []
    target_list = []
    image_ids = []

    for item in data:
        if isinstance(item, dict):
            if 'features' in item and 'k_ic' in item:
                feature_list.append(item['features'])
                target_list.append(item['k_ic'])
                image_ids.append(item.get('image_id', 'unknown'))
            elif 'band_pass_spectrum' in item:
                # Fallback for flat feature extraction structure if needed
                # Assuming the whole item is the feature vector if it contains numeric keys
                # But based on T022, we expect a structured list of features.
                # We'll construct a vector from all numeric keys except 'k_ic' and 'image_id'
                keys = [k for k in item.keys() if k not in ['k_ic', 'image_id']]
                feat_vec = [item[k] for k in keys]
                feature_list.append(feat_vec)
                target_list.append(item['k_ic'])
                image_ids.append(item.get('image_id', 'unknown'))

    if not feature_list:
        raise ValueError("No valid feature entries found in the input file.")

    return np.array(feature_list), np.array(target_list), image_ids

def train_random_forest(
    X: np.ndarray,
    y: np.ndarray,
    test_size: float = 0.2,
    random_state: Optional[int] = None
) -> Tuple[RandomForestRegressor, Dict[str, Any]]:
    """
    Train a Random Forest Regressor and evaluate it on a hold-out test set.

    Args:
        X: Feature matrix
        y: Target vector
        test_size: Fraction of data to use for testing
        random_state: Random seed for reproducibility

    Returns:
        model: Trained RandomForestRegressor instance
        metrics: Dictionary containing R2, MAE, RMSE
    """
    if random_state is None:
        config = get_config_dict()
        random_state = config.get('train_seed', 42)

    # Split data
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, random_state=random_state
    )

    # Initialize and train model
    model = RandomForestRegressor(
        n_estimators=100,
        max_depth=None,
        random_state=random_state,
        n_jobs=-1
    )
    model.fit(X_train, y_train)

    # Predict and evaluate
    y_pred = model.predict(X_test)

    mse = mean_squared_error(y_test, y_pred)
    rmse = np.sqrt(mse)
    mae = mean_absolute_error(y_test, y_pred)
    r2 = r2_score(y_test, y_pred)

    metrics = {
        'r2': float(r2),
        'mae': float(mae),
        'rmse': float(rmse),
        'test_size': len(y_test),
        'train_size': len(y_train)
    }

    return model, metrics

def save_model(model: RandomForestRegressor, metrics: Dict[str, Any], model_dir: Path) -> None:
    """
    Save the trained model and metrics to disk.

    Args:
        model: Trained RandomForestRegressor instance
        metrics: Evaluation metrics dictionary
        model_dir: Directory to save the artifacts
    """
    model_dir.mkdir(parents=True, exist_ok=True)

    # Save model using joblib (standard for sklearn)
    import joblib
    joblib.dump(model, model_dir / 'rf_model.joblib')

    # Save metrics
    metrics_path = model_dir / 'metrics.json'
    with open(metrics_path, 'w') as f:
        json.dump(metrics, f, indent=2)

    logging.info(f"Model and metrics saved to {model_dir}")

def main() -> None:
    """
    Main entry point for the Random Forest training script.
    """
    parser = argparse.ArgumentParser(description="Train Random Forest baseline model.")
    parser.add_argument(
        '--features',
        type=str,
        default='data/features.json',
        help='Path to the features.json file generated by code/data/features.py'
    )
    parser.add_argument(
        '--test-size',
        type=float,
        default=0.2,
        help='Fraction of data to use for testing (default: 0.2)'
    )
    parser.add_argument(
        '--seed',
        type=int,
        default=None,
        help='Random seed for reproducibility (default: uses config)'
    )
    args = parser.parse_args()

    # Setup logging
    logger = get_logger('TRAIN_RF')
    logger.info("Starting Random Forest training pipeline.")

    # Load features
    logger.info(f"Loading features from {args.features}")
    try:
        X, y, image_ids = load_features(args.features)
        logger.info(f"Loaded {X.shape[0]} samples with {X.shape[1]} features.")
    except FileNotFoundError:
        logger.error(f"Features file not found: {args.features}")
        raise
    except Exception as e:
        logger.error(f"Failed to load features: {e}")
        raise

    # Train model
    logger.info("Training Random Forest model...")
    model, metrics = train_random_forest(
        X, y, test_size=args.test_size, random_state=args.seed
    )

    # Log results
    logger.info(f"Training complete. R2: {metrics['r2']:.4f}, MAE: {metrics['mae']:.4f}, RMSE: {metrics['rmse']:.4f}")

    # Save artifacts
    save_model(model, metrics, MODEL_DIR)

    logger.info("Random Forest training pipeline finished successfully.")

if __name__ == '__main__':
    main()