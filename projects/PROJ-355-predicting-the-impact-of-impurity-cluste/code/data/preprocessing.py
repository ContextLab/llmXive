from config import get_project_root, get_data_paths

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

def filter_zero_impurity_configs(input_path: Path, output_path: Path) -> int:
    """
    Filters bulk configurations that have zero impurity atoms.
    
    Logic:
    1. Load the input CSV (expected to contain a column indicating impurity count or species).
    2. Identify rows where the impurity count is 0 or the impurity species is empty/null.
    3. Drop these rows.
    4. Save the filtered DataFrame to the output path.
    5. Return the count of excluded configurations.
    
    Args:
        input_path: Path to the input CSV (e.g., descriptors.csv or a combined dataset).
        output_path: Path to save the filtered CSV.
        
    Returns:
        int: Number of configurations excluded due to zero impurities.
    """
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")

    logger.info(f"Loading data from {input_path}")
    df = pd.read_csv(input_path)

    # Determine the column to check. 
    # Based on T016 output (alloy_systems.json) and T015 (descriptors.csv),
    # we expect 'impurity_species' or a derived count. 
    # If 'impurity_species' exists, we check for empty strings or NaN.
    # If a count column exists (e.g., 'impurity_count'), we check for 0.
    
    excluded_count = 0
    
    if 'impurity_species' in df.columns:
        # Filter out rows where impurity_species is NaN or empty string
        mask = df['impurity_species'].notna() & (df['impurity_species'].str.strip() != '')
        excluded_count = (~mask).sum()
        filtered_df = df[mask]
        logger.info(f"Filtered based on 'impurity_species': {excluded_count} rows excluded.")
        
    elif 'impurity_count' in df.columns:
        # Filter out rows where impurity_count is 0
        mask = df['impurity_count'] > 0
        excluded_count = (~mask).sum()
        filtered_df = df[mask]
        logger.info(f"Filtered based on 'impurity_count': {excluded_count} rows excluded.")
        
    else:
        # Fallback: If neither column exists, we cannot filter based on the specific rule.
        # We log a warning but proceed with the full dataset to avoid breaking the pipeline.
        logger.warning("No 'impurity_species' or 'impurity_count' column found. Skipping zero-impurity filter.")
        filtered_df = df
        excluded_count = 0

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Saving filtered data to {output_path}")
    filtered_df.to_csv(output_path, index=False)
    
    return excluded_count

def generate_preprocessing_report(excluded_count: int, output_path: Path) -> None:
    """
    Generates a JSON report logging the exclusion count.
    
    Args:
        excluded_count: Number of configurations excluded.
        output_path: Path to save the JSON report.
    """
    report = {
        "task": "filter_zero_impurity_configs",
        "excluded_count": excluded_count,
        "reason": "Configurations with zero impurity atoms (empty species or count=0) are not valid for segregation analysis.",
        "status": "completed"
    }
    
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Preprocessing report saved to {output_path}")

def run_preprocessing_filter(input_path: Optional[Path] = None, output_path: Optional[Path] = None) -> int:
    """
    Orchestrates the filtering process using default paths if none are provided.
    
    Returns:
        int: Number of excluded configurations.
    """
    project_root = get_project_root()
    data_paths = get_data_paths()
    
    # Default paths
    if input_path is None:
        # Try to find the descriptors file generated by T015
        input_path = data_paths['processed'] / 'descriptors.csv'
        if not input_path.exists():
            # Fallback to a generic processed file if descriptors.csv doesn't exist yet
            # In a real pipeline, this would be the output of the previous step
            input_path = data_paths['processed'] / 'combined_data.csv'
            
    if output_path is None:
        output_path = data_paths['processed'] / 'descriptors_filtered.csv'
        
    report_path = data_paths['processed'] / 'preprocessing_report.json'

    if not input_path.exists():
        logger.error(f"Input file {input_path} does not exist. Cannot run preprocessing filter.")
        # Create an empty report indicating failure or missing input
        report = {
            "task": "filter_zero_impurity_configs",
            "status": "failed",
            "error": f"Input file not found: {input_path}",
            "excluded_count": 0
        }
        with open(report_path, 'w') as f:
            json.dump(report, f, indent=2)
        return 0

    excluded_count = filter_zero_impurity_configs(input_path, output_path)
    generate_preprocessing_report(excluded_count, report_path)
    
    return excluded_count

def main():
    """Entry point for the script."""
    logger.info("Starting preprocessing filter (T019)...")
    try:
        count = run_preprocessing_filter()
        logger.info(f"Preprocessing complete. Excluded {count} configurations.")
    except Exception as e:
        logger.error(f"Preprocessing failed: {e}", exc_info=True)
        raise

if __name__ == "__main__":
    main()