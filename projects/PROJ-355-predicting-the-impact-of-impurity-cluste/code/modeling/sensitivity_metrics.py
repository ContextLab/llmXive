import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple
import pandas as pd
import numpy as np

from config import get_project_root, get_data_paths

logger = logging.getLogger(__name__)

def calculate_rmse_variance(rmse_values: List[float]) -> float:
    """
    Calculate the variance of RMSE values across a threshold sweep.
    
    Args:
        rmse_values: List of RMSE values obtained from different thresholds.
        
    Returns:
        Variance of the RMSE values.
    """
    if not rmse_values:
        logger.warning("Empty RMSE values list provided. Returning 0.0 variance.")
        return 0.0
    
    return float(np.var(rmse_values))

def calculate_r2_stability(r2_values: List[float]) -> float:
    """
    Calculate the stability of R² values across a threshold sweep.
    Stability is defined as the inverse of the coefficient of variation (CV).
    CV = std / mean. Stability = 1 / CV (if mean != 0), else 0.
    
    Higher stability indicates less variation relative to the mean.
    
    Args:
        r2_values: List of R² values obtained from different thresholds.
        
    Returns:
        Stability score (higher is more stable).
    """
    if not r2_values:
        logger.warning("Empty R² values list provided. Returning 0.0 stability.")
        return 0.0
    
    r2_array = np.array(r2_values)
    mean_r2 = np.mean(r2_array)
    std_r2 = np.std(r2_array)
    
    if abs(mean_r2) < 1e-10:
        # Avoid division by zero if mean is effectively zero
        logger.warning("Mean R² is near zero. Returning 0.0 stability.")
        return 0.0
    
    cv = std_r2 / abs(mean_r2)
    if cv == 0:
        return float('inf')
    
    stability = 1.0 / cv
    return float(stability)

def compute_sensitivity_metrics(
    rmse_values: List[float],
    r2_values: List[float]
) -> Dict[str, float]:
    """
    Compute both RMSE variance and R² stability from sweep results.
    
    Args:
        rmse_values: List of RMSE values across thresholds.
        r2_values: List of R² values across thresholds.
        
    Returns:
        Dictionary with keys 'rmse_variance' and 'r2_stability'.
    """
    if len(rmse_values) != len(r2_values):
        raise ValueError(
            f"RMSE and R² lists must have the same length. "
            f"Got {len(rmse_values)} and {len(r2_values)}."
        )
    
    rmse_var = calculate_rmse_variance(rmse_values)
    r2_stab = calculate_r2_stability(r2_values)
    
    return {
        "rmse_variance": rmse_var,
        "r2_stability": r2_stab
    }

def run_sensitivity_metrics_analysis(
    sensitivity_data_path: Optional[Path] = None
) -> Dict[str, Any]:
    """
    Main entry point to compute sensitivity metrics from existing sweep data.
    
    This function loads the sensitivity sweep results (generated by T032),
    calculates RMSE variance and R² stability, and returns the metrics.
    
    Args:
        sensitivity_data_path: Path to the sensitivity report JSON. 
                               Defaults to results/sensitivity_report.json.
                                
    Returns:
        Dictionary containing the computed metrics.
    """
    project_root = get_project_root()
    if sensitivity_data_path is None:
        sensitivity_data_path = project_root / "results" / "sensitivity_report.json"
    
    if not sensitivity_data_path.exists():
        raise FileNotFoundError(
            f"Sensitivity report not found at {sensitivity_data_path}. "
            f"Ensure T032 has been run successfully."
        )
    
    logger.info(f"Loading sensitivity data from {sensitivity_data_path}")
    
    with open(sensitivity_data_path, 'r') as f:
        data = json.load(f)
    
    # Extract RMSE and R² values from the sweep results
    # Expected format: {"sweep_results": [{"threshold": ..., "rmse": ..., "r2": ...}, ...]}
    sweep_results = data.get("sweep_results", [])
    
    if not sweep_results:
        raise ValueError("No sweep results found in the sensitivity report.")
    
    rmse_values = [entry.get("rmse") for entry in sweep_results if "rmse" in entry]
    r2_values = [entry.get("r2") for entry in sweep_results if "r2" in entry]
    
    if not rmse_values or not r2_values:
        raise ValueError("Could not extract RMSE and R² values from sweep results.")
    
    metrics = compute_sensitivity_metrics(rmse_values, r2_values)
    
    logger.info(
        f"Computed RMSE Variance: {metrics['rmse_variance']:.6f}, "
        f"R² Stability: {metrics['r2_stability']:.6f}"
    )
    
    return metrics

def save_sensitivity_metrics(
    metrics: Dict[str, float],
    output_path: Optional[Path] = None
) -> Path:
    """
    Save computed sensitivity metrics to a JSON file.
    
    Args:
        metrics: Dictionary containing 'rmse_variance' and 'r2_stability'.
        output_path: Path to save the metrics. 
                     Defaults to results/sensitivity_metrics.json.
                     
    Returns:
        Path to the saved file.
    """
    project_root = get_project_root()
    if output_path is None:
        output_path = project_root / "results" / "sensitivity_metrics.json"
    
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(metrics, f, indent=2)
    
    logger.info(f"Sensitivity metrics saved to {output_path}")
    return output_path

def main():
    """
    CLI entry point to run sensitivity metrics analysis.
    """
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    try:
        metrics = run_sensitivity_metrics_analysis()
        output_path = save_sensitivity_metrics(metrics)
        print(f"Analysis complete. Metrics saved to: {output_path}")
        print(f"RMSE Variance: {metrics['rmse_variance']}")
        print(f"R² Stability: {metrics['r2_stability']}")
    except FileNotFoundError as e:
        logger.error(str(e))
        exit(1)
    except ValueError as e:
        logger.error(str(e))
        exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        exit(1)

if __name__ == "__main__":
    main()