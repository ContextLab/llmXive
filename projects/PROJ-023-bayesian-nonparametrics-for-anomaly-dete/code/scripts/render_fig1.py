import os
import sys
import logging
import argparse
from pathlib import Path
from typing import Optional, Dict, Any, Tuple, List

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Importing from local lib modules
try:
    from lib.utils import set_seed
except ImportError:
    print("Error: Required modules in code/lib/ not found.")
    sys.exit(1)

logger = logging.getLogger(__name__)
logger.setLevel(logging.INFO)
handler = logging.StreamBuffer(sys.stdout)
handler.setFormatter(logging.Formatter('%(asctime)s - %(levelname)s - %(message)s'))
logger.addHandler(handler)

def load_and_align_data(
    timeseries_path: str,
    predictions_path: str
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Load and align time series and prediction data.

    Args:
        timeseries_path (str): Path to time series CSV.
        predictions_path (str): Path to predictions CSV.

    Returns:
        Tuple[pd.DataFrame, pd.DataFrame]: Aligned DataFrames.
    """
    df_ts = pd.read_csv(timeseries_path)
    df_pred = pd.read_csv(predictions_path)

    # Ensure common timestamp column
    if 'timestamp' in df_ts.columns and 'timestamp' in df_pred.columns:
        merged = pd.merge(df_ts, df_pred, on='timestamp', how='outer')
        return df_ts, df_pred
    else:
        raise ValueError("Both files must have 'timestamp' column for alignment.")

def plot_timeseries_with_anomalies(
    df_ts: pd.DataFrame,
    df_pred: pd.DataFrame,
    output_path: str
) -> None:
    """
    Plot time series with anomalies and scores.

    Args:
        df_ts (pd.DataFrame): Time series data.
        df_pred (pd.DataFrame): Prediction data.
        output_path (str): Output image path.
    """
    plt.figure(figsize=(12, 6))
    plt.style.use('seaborn-v0_8-whitegrid')

    # Plot time series
    plt.plot(df_ts['timestamp'], df_ts['value'], label='Original Signal', color='blue', alpha=0.7)

    # Plot anomaly scores
    if 'anomaly_score' in df_pred.columns:
        plt.plot(df_pred['timestamp'], df_pred['anomaly_score'], label='Anomaly Score', color='red', linestyle='--')

    # Highlight anomalies if available
    if 'anomaly_flag' in df_pred.columns:
        anomaly_indices = df_pred[df_pred['anomaly_flag'] == 1].index
        if len(anomaly_indices) > 0:
            # Plot vertical lines for anomalies
            for idx in anomaly_indices:
                ts = df_pred.loc[idx, 'timestamp']
                plt.axvline(x=ts, color='orange', linestyle=':', alpha=0.5)

    plt.title('Time Series with Anomaly Detection Scores')
    plt.xlabel('Timestamp')
    plt.ylabel('Value / Score')
    plt.legend()
    plt.tight_layout()

    # Save figure
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=300)
    plt.close()
    logger.info(f"Figure saved to {output_path}")

def main() -> None:
    """Main entry point."""
    parser = argparse.ArgumentParser(description="Render Figure 1")
    parser.add_argument('--data', type=str, required=True, help='Path to time series CSV')
    parser.add_argument('--predictions', type=str, required=True, help='Path to predictions CSV')
    parser.add_argument('--output', type=str, default='paper/figures/fig1_timeseries.png', help='Output image')
    args = parser.parse_args()

    set_seed(42)

    df_ts, df_pred = load_and_align_data(args.data, args.predictions)
    plot_timeseries_with_anomalies(df_ts, df_pred, args.output)
    logger.info("Figure 1 generation completed.")

if __name__ == '__main__':
    main()
