# --- Helper Functions ---

def validate_field_type(value: Any, expected_type: str, field_path: str) -> None:
    """
    Validate that a value matches the expected JSON Schema type.
    
    Args:
        value: The value to check.
        expected_type: The expected type string (e.g., 'number', 'string', 'boolean', 'array', 'object').
        field_path: Human-readable path for error messages.
        
    Raises:
        AssertionError: If the type does not match.
    """
    if expected_type == "number":
        if not isinstance(value, (int, float)):
            raise AssertionError(f"Field '{field_path}' must be a number, got {type(value).__name__}")
    elif expected_type == "string":
        if not isinstance(value, str):
            raise AssertionError(f"Field '{field_path}' must be a string, got {type(value).__name__}")
    elif expected_type == "boolean":
        if not isinstance(value, bool):
            raise AssertionError(f"Field '{field_path}' must be a boolean, got {type(value).__name__}")
    elif expected_type == "array":
        if not isinstance(value, list):
            raise AssertionError(f"Field '{field_path}' must be an array, got {type(value).__name__}")
    elif expected_type == "object":
        if not isinstance(value, dict):
            raise AssertionError(f"Field '{field_path}' must be an object, got {type(value).__name__}")
    elif expected_type == "null":
        if value is not None:
            raise AssertionError(f"Field '{field_path}' must be null, got {type(value).__name__}")


def validate_constraints(value: Any, constraints: Dict[str, Any], field_path: str) -> None:
    """
    Validate value against specific constraints (minimum, maximum, minItems, etc.).
    """
    if "minimum" in constraints:
        if value < constraints["minimum"]:
            raise AssertionError(f"Field '{field_path}' value {value} is less than minimum {constraints['minimum']}")
    
    if "maximum" in constraints:
        if value > constraints["maximum"]:
            raise AssertionError(f"Field '{field_path}' value {value} is greater than maximum {constraints['maximum']}")
    
    if "minItems" in constraints and isinstance(value, list):
        if len(value) < constraints["minItems"]:
            raise AssertionError(f"Field '{field_path}' has {len(value)} items, minimum is {constraints['minItems']}")
    
    if "enum" in constraints:
        if value not in constraints["enum"]:
            raise AssertionError(f"Field '{field_path}' value '{value}' not in allowed enum {constraints['enum']}")


def validate_schema_recursive(
    data: Any, 
    schema_def: Dict[str, Any], 
    path: str = "root",
    required_fields: List[str] = []
) -> None:
    """
    Recursively validate a data structure against a schema definition.
    """
    schema_type = schema_def.get("type")
    
    # Check required fields if this is an object
    if schema_type == "object":
        if required_fields:
            missing = [f for f in required_fields if f not in data]
            if missing:
                raise AssertionError(f"Missing required fields at {path}: {missing}")
        
        properties = schema_def.get("properties", {})
        for key, value in data.items():
            if key in properties:
                validate_schema_recursive(value, properties[key], f"{path}.{key}")
            else:
                # Optional: strict mode could fail here if extra properties are forbidden
                pass
    
    elif schema_type:
        validate_field_type(data, schema_type, path)
        validate_constraints(data, schema_def, path)
    
    elif "items" in schema_def and isinstance(data, list):
        item_schema = schema_def["items"]
        for idx, item in enumerate(data):
            validate_schema_recursive(item, item_schema, f"{path}[{idx}]")


# --- Test Class ---

class TestEvaluationSchema:
    """
    Contract tests for the evaluation output schema.
    
    These tests ensure that `code/scripts/evaluate.py` produces output
    that matches the structure defined in `contracts/evaluation.schema.yaml`.
    """

    def test_schema_file_exists(self, schema_path: Path) -> None:
        """Verify that the schema definition file exists."""
        assert schema_path.exists(), f"Schema file missing: {schema_path}"

    def test_schema_is_valid_yaml(self, schema: Dict[str, Any]) -> None:
        """Verify that the schema file is valid YAML and has a root type."""
        assert isinstance(schema, dict), "Schema root must be a dictionary"
        assert "type" in schema, "Schema root must define a 'type'"
        assert schema["type"] == "object", "Root schema type must be 'object'"

    @pytest.mark.skipif(
        not Path("data/results/evaluation.json").exists(),
        reason="Evaluation results file not yet generated. Run code/scripts/evaluate.py first."
    )
    def test_evaluation_results_file_exists(self, evaluation_results_path: Path) -> None:
        """Verify that the evaluation results file exists."""
        assert evaluation_results_path.exists(), f"Evaluation results file missing: {evaluation_results_path}"

    @pytest.mark.skipif(
        not Path("data/results/evaluation.json").exists(),
        reason="Evaluation results file not yet generated. Run code/scripts/evaluate.py first."
    )
    def test_evaluation_results_is_valid_json(self, evaluation_results: Dict[str, Any]) -> None:
        """Verify that the evaluation results file is valid JSON."""
        assert isinstance(evaluation_results, dict), "Evaluation results must be a JSON object"

    @pytest.mark.skipif(
        not Path("data/results/evaluation.json").exists(),
        reason="Evaluation results file not yet generated. Run code/scripts/evaluate.py first."
    )
    def test_evaluation_results_matches_schema(self, evaluation_results: Dict[str, Any], schema: Dict[str, Any]) -> None:
        """
        Verify that the evaluation results conform to the schema definition.
        This is the core contract test.
        """
        required_fields = schema.get("required", [])
        try:
            validate_schema_recursive(evaluation_results, schema, "root", required_fields)
        except AssertionError as e:
            pytest.fail(f"Schema validation failed: {e}")

    @pytest.mark.skipif(
        not Path("data/results/evaluation.json").exists(),
        reason="Evaluation results file not yet generated. Run code/scripts/evaluate.py first."
    )
    def test_required_top_level_keys_present(self, evaluation_results: Dict[str, Any]) -> None:
        """
        Verify that all top-level required keys defined in the schema are present.
        """
        # Load schema to get required keys
        schema_path = Path("contracts/evaluation.schema.yaml")
        with open(schema_path, "r", encoding="utf-8") as f:
            schema = yaml.safe_load(f)
        
        required_keys = schema.get("required", [])
        missing_keys = [key for key in required_keys if key not in evaluation_results]
        
        assert not missing_keys, f"Missing required top-level keys in evaluation.json: {missing_keys}"

    @pytest.mark.skipif(
        not Path("data/results/evaluation.json").exists(),
        reason="Evaluation results file not yet generated. Run code/scripts/evaluate.py first."
    )
    def test_method_comparison_structure(self, evaluation_results: Dict[str, Any]) -> None:
        """
        Verify the structure of the 'method_comparison' section if present.
        Ensures it contains the expected comparison metrics.
        """
        if "method_comparison" in evaluation_results:
            comparison = evaluation_results["method_comparison"]
            assert isinstance(comparison, dict), "method_comparison must be an object"
            
            # Check for common comparison keys
            expected_keys = ["bayesian", "shewhart", "cusum", "vae"]
            for key in expected_keys:
                if key in comparison:
                    assert isinstance(comparison[key], dict), f"method_comparison.{key} must be an object"

    @pytest.mark.skipif(
        not Path("data/results/evaluation.json").exists(),
        reason="Evaluation results file not yet generated. Run code/scripts/evaluate.py first."
    )
    def test_statistical_tests_structure(self, evaluation_results: Dict[str, Any]) -> None:
        """
        Verify the structure of the 'statistical_tests' section if present.
        Ensures it contains p-values and confidence intervals as required by FR-006.
        """
        if "statistical_tests" in evaluation_results:
            tests = evaluation_results["statistical_tests"]
            assert isinstance(tests, dict), "statistical_tests must be an object"
            
            # Check for Wilcoxon test results
            if "wilcoxon" in tests:
                wilcoxon = tests["wilcoxon"]
                assert isinstance(wilcoxon, dict), "statistical_tests.wilcoxon must be an object"
                assert "p_value" in wilcoxon, "Wilcoxon test must include p_value"
                assert isinstance(wilcoxon["p_value"], (int, float)), "p_value must be a number"
            
            # Check for Bootstrap CI results
            if "bootstrap_ci" in tests:
                bootstrap = tests["bootstrap_ci"]
                assert isinstance(bootstrap, dict), "statistical_tests.bootstrap_ci must be an object"
                # CI usually has lower and upper bounds
                assert "lower_bound" in bootstrap or "ci_lower" in bootstrap, "Bootstrap CI must include lower bound"
                assert "upper_bound" in bootstrap or "ci_upper" in bootstrap, "Bootstrap CI must include upper bound"

    @pytest.mark.skipif(
        not Path("data/results/evaluation.json").exists(),
        reason="Evaluation results file not yet generated. Run code/scripts/evaluate.py first."
    )
    def test_no_null_critical_fields(self, evaluation_results: Dict[str, Any]) -> None:
        """
        Verify that critical numeric fields are not null.
        """
        # Check top level metrics if they exist
        if "aggregate_metrics" in evaluation_results:
            metrics = evaluation_results["aggregate_metrics"]
            for key in ["f1_score", "precision", "recall"]:
                if key in metrics:
                    assert metrics[key] is not None, f"Critical metric '{key}' cannot be null"
                    assert isinstance(metrics[key], (int, float)), f"Critical metric '{key}' must be a number"