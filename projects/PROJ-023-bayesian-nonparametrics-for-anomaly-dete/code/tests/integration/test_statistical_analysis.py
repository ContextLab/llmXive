def test_threshold_sensitivity(aligned_datasets: Dict[str, pd.DataFrame]) -> None:
    """
    Test T024: Verify threshold sensitivity logic.

    Sweeps thresholds and calculates metrics (Precision, Recall, F1).
    This ensures the evaluation pipeline can handle dynamic thresholding.
    """
    gt = aligned_datasets["ground_truth"]
    bayes = aligned_datasets["bayesian"]

    scores = bayes["score"].values
    true_labels = gt["anomaly"].values.astype(int)

    thresholds = np.linspace(scores.min(), scores.max(), 10)

    results = []
    for thresh in thresholds:
        preds = (scores >= thresh).astype(int)

        # Calculate simple metrics
        tp = np.sum((preds == 1) & (true_labels == 1))
        fp = np.sum((preds == 1) & (true_labels == 0))
        fn = np.sum((preds == 0) & (true_labels == 1))

        precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
        recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
        f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0.0

        results.append({
            "threshold": thresh,
            "precision": precision,
            "recall": recall,
            "f1": f1
        })

    df_results = pd.DataFrame(results)

    # Verify structure
    assert "f1" in df_results.columns, "F1 score must be calculated"
    assert "threshold" in df_results.columns, "Threshold must be recorded"

    # Verify that F1 varies with threshold (unless data is trivial)
    # If all thresholds yield same F1, data might be degenerate
    if df_results["f1"].std() == 0:
        logger.warning("F1 score is constant across all thresholds. Data may be degenerate.")

    # Check that max F1 is reasonable (>= 0)
    assert df_results["f1"].max() >= 0.0

