def pair_correlation_distribution(x: float) -> float:
    """
    The pair correlation function for GUE zeros: 1 - (sin(pi*x)/(pi*x))^2.
    This describes the local spacing between zeros.
    """
    if abs(x) < 1e-10:
        return 0.0
    return 1.0 - (np.sin(np.pi * x) / (np.pi * x))**2

def gue_extreme_value_cdf(x: float, beta: int = 2) -> float:
    """
    Compute the theoretical GUE-derived extreme value CDF for maximal gaps.
    
    According to the methodology (FR-004), the distribution of maximal gaps,
    when normalized, converges to the Tracy-Widom distribution for beta=2 (GUE).
    
    Formula: F(x) = F_TW(x; beta=2)
    
    Note: The normalization factor log^2(p) is applied to the gap size before
    comparison, as handled in the data loading/normalization steps (T018b).
    This function takes the normalized value x and returns the CDF probability.
    
    Args:
        x: The normalized gap value (gap / log(p)^2) adjusted for the extreme value scaling.
           In the context of the Tracy-Widom limit for the largest eigenvalue,
           x is typically scaled as (lambda_max - 2) * N^(2/3).
           For prime gaps, the specific scaling factor derived from the Cramer model
           and RH hypothesis is applied to x before calling this function.
           Here we assume x is already in the correct domain for the TW distribution.
        beta: The Dyson index (2 for GUE).
    
    Returns:
        float: The cumulative probability P(X <= x).
    """
    # scipy.stats.tracy_widom is not a standard direct function in all scipy versions.
    # However, scipy.stats has the distribution.
    # We use the 'tracy_widom' distribution if available, or approximate.
    # Standard scipy.stats.tracy_widom was added in scipy 1.7.0.
    
    try:
        # Use the built-in distribution if available
        tw_dist = stats.tracy_widom(beta)
        return tw_dist.cdf(x)
    except AttributeError:
        # Fallback to numerical approximation if scipy version is old
        # Tracy-Widom F2 (beta=2) approximation
        # Using the approximation from Bornemann (2010) or similar
        # For x < -10, it's effectively 0. For x > 10, it's effectively 1.
        if x < -10:
            return 0.0
        if x > 10:
            return 1.0
        
        # Simple numerical integration of the Painleve II equation solution is complex.
        # We will use a known approximation for F2(x) for the sake of this implementation
        # if the specific scipy function is missing.
        # However, for a research pipeline, we assume a reasonably modern scipy.
        # If the environment is strict, we might need to implement the numerical solver.
        # Given the constraints, we assume scipy >= 1.7.0.
        # If not, we raise an error to force environment update rather than fake it.
        raise ImportError("scipy>=1.7.0 is required for scipy.stats.tracy_widom. "
                          "Please update scipy or implement a numerical approximation for F2.")

def compute_empirical_cdf(data: List[float]) -> Tuple[List[float], List[float]]:
    """Compute the empirical CDF from a list of data points."""
    if not data:
        return [], []
    
    sorted_data = sorted(data)
    n = len(sorted_data)
    # Empirical CDF: P(X <= x) = k/n
    cdf_values = [(i + 1) / n for i in range(n)]
    return sorted_data, cdf_values

def run_ks_test(empirical_data: List[float], theoretical_cdf_func, params: Dict[str, Any]) -> Dict[str, Any]:
    """Perform Kolmogorov-Smirnov test between empirical data and theoretical CDF."""
    if not empirical_data:
        return {"ks_statistic": None, "p_value": None, "error": "No empirical data"}
    
    # scipy.stats.kstest takes a cdf function.
    # We need to wrap our gue_extreme_value_cdf to match the signature expected by kstest.
    # kstest expects cdf(x, *args)
    
    def theoretical_cdf(x, *args):
        return theoretical_cdf_func(x, **params)
    
    try:
        result = stats.kstest(empirical_data, theoretical_cdf)
        return {
            "ks_statistic": float(result.statistic),
            "p_value": float(result.pvalue),
            "method": "scipy.stats.kstest"
        }
    except Exception as e:
        logger.error(f"KS test failed: {e}")
        return {"ks_statistic": None, "p_value": None, "error": str(e)}

def plot_cdf_comparison(empirical_data: List[float], theoretical_cdf_func, params: Dict[str, Any], output_path: Path):
    """Generate a plot overlaying empirical and theoretical CDFs."""
    import matplotlib.pyplot as plt
    
    if not empirical_data:
        logger.warning("No data to plot.")
        return
    
    sorted_data, emp_cdf = compute_empirical_cdf(empirical_data)
    
    # Generate theoretical CDF points
    x_min = min(sorted_data) - 1
    x_max = max(sorted_data) + 1
    x_theory = np.linspace(x_min, x_max, 100)
    y_theory = [theoretical_cdf_func(x, **params) for x in x_theory]
    
    plt.figure(figsize=(10, 6))
    plt.plot(sorted_data, emp_cdf, label='Empirical CDF (Maximal Gaps)', linestyle='-', linewidth=2)
    plt.plot(x_theory, y_theory, label='Theoretical GUE Extreme Value CDF', linestyle='--', linewidth=2)
    plt.xlabel('Normalized Gap Value')
    plt.ylabel('Cumulative Probability')
    plt.title('Comparison of Empirical Maximal Gaps vs GUE Extreme Value Distribution')
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()
    logger.info(f"Plot saved to {output_path}")

