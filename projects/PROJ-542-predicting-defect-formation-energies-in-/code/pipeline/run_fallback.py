"""
code/pipeline/run_fallback.py
--------------------------------
Driver script that re‑runs the modelling pipeline using the
augmented feature set produced by ``src.data.augment_structural``.

Procedure (as defined in the spec for T016):

1. Load ``data/processed/performance.json`` and inspect the
   ``fallback_needed`` flag.
2. If the flag is ``True``:
   * Replace ``features.csv`` with ``features_augmented.csv``.
   * Re‑compute the SHA‑256 checksum for the (new) ``features.csv``.
   * Re‑execute the modelling steps:
     - Train‑test split (``src.models.split``)
     - Cross‑validation training (``src.models.train``)
     - Held‑out evaluation (``src.models.evaluate``)
     - Feature‑importance generation (``src.models.feature_importance``)
3. The evaluation step will write an updated ``performance.json``
   where the ``fallback_needed`` flag should now be ``False``.

The script is intended to be invoked via:

    python -m code.pipeline.run_fallback

and will raise an exception on any failure, causing the CI to
surface the error.
"""

import json
import shutil
import subprocess
import sys
from pathlib import Path

from llmxive_toolkit import get_logger, paths

log = get_logger(__name__)


def _load_performance(perf_path: Path) -> dict:
    """Load the JSON performance file."""
    if not perf_path.is_file():
        raise FileNotFoundError(f"Performance file not found at {perf_path}")
    with perf_path.open("r", encoding="utf-8") as f:
        return json.load(f)


def _fallback_needed(performance: dict) -> bool:
    """Return True if the fallback flag is set."""
    return bool(performance.get("fallback_needed", False))


def _replace_features_with_augmented():
    """
    Overwrite the baseline ``features.csv`` with the augmented version.
    The augmented file is generated by ``src.data.augment_structural`` and
    lives at ``data/processed/features_augmented.csv``.
    """
    src_path = paths.data("processed", "features_augmented.csv")
    dst_path = paths.data("processed", "features.csv")

    if not src_path.is_file():
        raise FileNotFoundError(
            f"Augmented feature file not found at {src_path}"
        )

    log.info("Replacing %s with %s", dst_path, src_path)
    shutil.copyfile(src_path, dst_path)

    # Re‑compute checksum for the new features file.
    checksum_path = paths.checksums("features.sha256")
    log.info("Computing checksum for %s -> %s", dst_path, checksum_path)
    subprocess.run(
        [sys.executable, "-m", "src.utils.checksum_all"],
        check=True,
    )


def _run_cli_module(module: str, args: list[str]) -> None:
    """
    Execute a module as ``python -m <module> <args>``.

    Parameters
    ----------
    module: str
        The dotted module name (e.g. ``src.models.split``).
    args: list[str]
        Arguments to pass to the module.
    """
    cmd = [sys.executable, "-m", module] + args
    log.info("Running command: %s", " ".join(cmd))
    subprocess.run(cmd, check=True)


def main() -> None:
    """Entry point for ``python -m code.pipeline.run_fallback``."""
    # 1. Load performance JSON and decide whether to fallback.
    perf_path = paths.data("processed", "performance.json")
    performance = _load_performance(perf_path)

    if not _fallback_needed(performance):
        log.info("Fallback not required – exiting.")
        return

    log.info("Fallback required – re‑running pipeline with augmented features.")

    # 2. Replace the baseline feature matrix.
    _replace_features_with_augmented()

    # 3. Re‑run the modelling steps.
    #    The CLI modules expect positional arguments matching the quickstart guide.
    #    a) Split
    _run_cli_module(
        "src.models.split",
        [
            str(paths.data("processed", "features.csv")),
            str(paths.data("processed", "train.csv")),
            str(paths.data("processed", "test.csv")),
        ],
    )

    #    b) Train (cross‑validation)
    _run_cli_module(
        "src.models.train",
        [
            str(paths.data("processed", "train.csv")),
            str(paths.data("processed", "cv_metrics.json")),
        ],
    )

    #    c) Evaluate on held‑out test set
    _run_cli_module(
        "src.models.evaluate",
        [
            str(paths.data("processed", "train.csv")),
            str(paths.data("processed", "test.csv")),
            str(paths.data("processed", "performance.json")),
        ],
    )

    #    d) Feature importance (produces updated JSON & figure)
    _run_cli_module("src.models.feature_importance", [])

    log.info("Fallback pipeline completed successfully.")


if __name__ == "__main__":
    main()
