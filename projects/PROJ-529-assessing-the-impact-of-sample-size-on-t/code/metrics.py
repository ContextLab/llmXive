def calculate_stability_metrics(
    subsample_results_path: str,
    full_sample_results_path: str,
    output_path: str
) -> pd.DataFrame:
    """
    T025 & T026 & T028: Calculate stability (SD) and coverage metrics.

    Reads subsample results generated by models.py (run_modeling_pipeline),
    groups by meta_id and k, calculates:
    - sd_effects: Standard deviation of pooled effect sizes across subsamples.
    - coverage_rate: Proportion of subsample CIs containing the full-sample estimate.

    Args:
        subsample_results_path: Path to the CSV/Parquet with subsample modeling results.
        full_sample_results_path: Path to the CSV/Parquet with full-sample estimates.
        output_path: Path to write the aggregated stability_metrics.csv.

    Returns:
        DataFrame with columns: meta_id, k, model_type, sd_effects, coverage_rate, n_subsamples.
    """
    logger.info(f"Loading subsample results from {subsample_results_path}")
    if not os.path.exists(subsample_results_path):
        raise FileNotFoundError(f"Subsample results file not found: {subsample_results_path}")

    # Load data
    if subsample_results_path.endswith('.parquet'):
        df_sub = pd.read_parquet(subsample_results_path)
    else:
        df_sub = pd.read_csv(subsample_results_path)

    if full_sample_results_path.endswith('.parquet'):
        df_full = pd.read_parquet(full_sample_results_path)
    else:
        df_full = pd.read_csv(full_sample_results_path)

    # Ensure required columns exist
    required_cols = ['meta_id', 'k', 'model_type', 'pooled_effect', 'se_pooled', 'ci_lower', 'ci_upper']
    for col in required_cols:
        if col not in df_sub.columns:
            raise DataValidationError(f"Missing required column '{col}' in subsample results.")
    
    full_required = ['meta_id', 'model_type', 'pooled_effect']
    for col in full_required:
        if col not in df_full.columns:
            raise DataValidationError(f"Missing required column '{col}' in full sample results.")

    # Merge full sample estimate into subsample dataframe for coverage calculation
    # We assume full sample results are unique per meta_id and model_type
    df_merged = df_sub.merge(
        df_full[['meta_id', 'model_type', 'pooled_effect']],
        on=['meta_id', 'model_type'],
        suffixes=('', '_full')
    )

    # Calculate Coverage Rate (T026)
    # Check if full-sample pooled effect is within [ci_lower, ci_upper] of the subsample
    df_merged['covers_full'] = (
        (df_merged['ci_lower'] <= df_merged['pooled_effect_full']) &
        (df_merged['pooled_effect_full'] <= df_merged['ci_upper'])
    ).astype(int)

    # Group by meta_id, k, model_type to calculate metrics
    metrics = df_merged.groupby(['meta_id', 'k', 'model_type']).agg(
        n_subsamples=('pooled_effect', 'count'),
        sd_effects=('pooled_effect', 'std'),
        coverage_rate=('covers_full', 'mean')
    ).reset_index()

    # Handle edge case where std is NaN (e.g., only 1 subsample)
    metrics['sd_effects'] = metrics['sd_effects'].fillna(0.0)

    # Save to output
    output_dir = Path(output_path).parent
    output_dir.mkdir(parents=True, exist_ok=True)
    metrics.to_csv(output_path, index=False)
    logger.info(f"Stability metrics saved to {output_path}")

    return metrics


def calculate_sensitivity_analysis(
    metrics_path: str,
    subsample_results_path: str,
    output_path: str,
    perturbation_factor: float = 1.0
) -> pd.DataFrame:
    """
    T027: Sensitivity analysis by perturbing the reference value (full-sample estimate).
    
    Perturbs the full-sample estimate by +/- (perturbation_factor * SE) and recalculates coverage.
    Compares variation against primary coverage rate.

    Args:
        metrics_path: Path to the primary stability_metrics.csv (for reference).
        subsample_results_path: Path to subsample results (to access full-sample SE).
        output_path: Path to write sensitivity_analysis_results.csv.
        perturbation_factor: Multiplier for SE (default 1.0).
    """
    logger.info(f"Performing sensitivity analysis with perturbation factor: {perturbation_factor}")
    
    if not os.path.exists(subsample_results_path):
        raise FileNotFoundError(f"Subsample results file not found: {subsample_results_path}")

    if subsample_results_path.endswith('.parquet'):
        df_sub = pd.read_parquet(subsample_results_path)
    else:
        df_sub = pd.read_csv(subsample_results_path)

    # We need the full sample SE. Assuming it was stored in a separate file or we need to infer.
    # For this implementation, we assume the full sample results file has 'se_pooled' as well.
    # If not, we might need to load it from a specific full-sample output.
    # Let's assume we load full sample stats from a specific path or derive from the merge logic.
    # To be robust, we'll expect a full_sample_stats file or merge it.
    # For T027, let's assume we have a file with full sample stats including SE.
    # If not provided in args, we might need to look for a standard location.
    # Let's add a parameter for full_sample_stats_path if needed, but for now, 
    # let's assume the subsample_results_path contains the full sample info if we loaded it earlier?
    # No, the subsample file is subsamples.
    
    # Let's assume a standard path for full sample stats if not passed, or require it.
    # To keep it simple and compliant with T027 requirements:
    # We need the full sample estimate and its SE.
    # Let's assume the user provides the full_sample_stats_path or we derive it.
    # Since the function signature doesn't have it, let's look for a standard file or raise.
    # Actually, let's assume the full sample results were saved to a specific file by models.py.
    # We'll search for it or require it. For now, let's assume it's in data/processed/full_sample_stats.csv
    full_sample_path = Path(subsample_results_path).parent / 'full_sample_stats.csv'
    if not full_sample_path.exists():
        full_sample_path = Path(subsample_results_path).parent.parent / 'output' / 'full_sample_stats.csv'
    
    if not full_sample_path.exists():
        # Fallback: try to find any full_sample file in the directory
        parent = Path(subsample_results_path).parent
        candidates = list(parent.glob('*full_sample*.csv')) + list(parent.glob('*full_sample*.parquet'))
        if candidates:
            full_sample_path = candidates[0]
        else:
            raise FileNotFoundError("Could not locate full sample statistics file for sensitivity analysis.")

    if full_sample_path.suffix == '.parquet':
        df_full = pd.read_parquet(full_sample_path)
    else:
        df_full = pd.read_csv(full_sample_path)

    # Ensure we have SE for full sample
    if 'se_pooled' not in df_full.columns:
        raise DataValidationError("Full sample stats file missing 'se_pooled' column required for sensitivity analysis.")

    # Merge full sample stats with subsamples
    df_merged = df_sub.merge(
        df_full[['meta_id', 'model_type', 'pooled_effect', 'se_pooled']],
        on=['meta_id', 'model_type'],
        suffixes=('', '_full')
    )

    # Perturb full sample estimate
    # Upper perturbation
    df_merged['ref_upper'] = df_merged['pooled_effect_full'] + (perturbation_factor * df_merged['se_pooled_full'])
    df_merged['covers_upper'] = (
        (df_merged['ci_lower'] <= df_merged['ref_upper']) &
        (df_merged['ref_upper'] <= df_merged['ci_upper'])
    ).astype(int)

    # Lower perturbation
    df_merged['ref_lower'] = df_merged['pooled_effect_full'] - (perturbation_factor * df_merged['se_pooled_full'])
    df_merged['covers_lower'] = (
        (df_merged['ci_lower'] <= df_merged['ref_lower']) &
        (df_merged['ref_lower'] <= df_merged['ci_upper'])
    ).astype(int)

    # Aggregate
    sensitivity_metrics = df_merged.groupby(['meta_id', 'k', 'model_type']).agg(
        coverage_original=('covers_full', 'mean'),
        coverage_upper=('covers_upper', 'mean'),
        coverage_lower=('covers_lower', 'mean'),
        variation_upper=('covers_upper', lambda x: abs(x.mean() - df_merged[df_merged['meta_id']==x.name[0]]['covers_full'].mean())), # Simplified logic
        variation_lower=('covers_lower', lambda x: abs(x.mean() - df_merged[df_merged['meta_id']==x.name[0]]['covers_full'].mean()))
    ).reset_index()
    
    # Correct aggregation for variation
    # We need to calculate variation relative to the original coverage for that group
    # The groupby above loses the original mean for the group if we don't calculate it first.
    # Let's re-calculate properly.
    
    # Re-group for original coverage
    orig_cov = df_merged.groupby(['meta_id', 'model_type', 'k'])['covers_full'].mean().reset_index()
    orig_cov.columns = ['meta_id', 'model_type', 'k', 'coverage_original']
    
    sens_agg = df_merged.groupby(['meta_id', 'model_type', 'k']).agg(
        coverage_upper=('covers_upper', 'mean'),
        coverage_lower=('covers_lower', 'mean')
    ).reset_index()
    
    result = orig_cov.merge(sens_agg, on=['meta_id', 'model_type', 'k'])
    result['variation_upper'] = (result['coverage_upper'] - result['coverage_original']).abs()
    result['variation_lower'] = (result['coverage_lower'] - result['coverage_original']).abs()
    result['max_variation'] = result[['variation_upper', 'variation_lower']].max(axis=1)

    output_dir = Path(output_path).parent
    output_dir.mkdir(parents=True, exist_ok=True)
    result.to_csv(output_path, index=False)
    logger.info(f"Sensitivity analysis results saved to {output_path}")

    return result


