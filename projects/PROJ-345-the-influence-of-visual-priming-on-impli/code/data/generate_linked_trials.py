"""
Module to generate the final linked_trials.csv artifact.

This script consumes the preprocessed trial data (after ingestion,
integrity checks, and linkage derivation) and writes the final
`data/processed/linked_trials.csv` file with the required schema.

Schema:
- trial_id
- response_time
- stimulus_id
- prime_condition
- participant_id

It also performs verification to ensure the linked metadata percentage
meets the SC-001 target (default 0.95).
"""

import os
import csv
import logging
import sys
from pathlib import Path
from typing import List, Dict, Any, Optional

# Import local project utilities
# Note: These imports assume the script is run from the project root
