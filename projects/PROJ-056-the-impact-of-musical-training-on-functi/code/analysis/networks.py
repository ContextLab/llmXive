import os
import logging
import numpy as np
import pandas as pd
from pathlib import Path
from typing import List, Dict, Any

logger = logging.getLogger(__name__)

def load_connectivity_matrices(filepath: str) -> np.ndarray:
    """
    Load connectivity matrices from a .npy file.
    Expected shape: [n_subjects, n_rois, n_rois]
    """
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Connectivity matrices file not found: {filepath}")
    return np.load(filepath)

def load_atlas_annotations(atlas_path: str) -> pd.DataFrame:
    """
    Load the atlas annotations (ROI labels and network assignments).
    Supports both CSV and Parquet formats.
    Returns a DataFrame with at least the columns:
        - roi_index (int)
        - network (str)
    """
    path = Path(atlas_path)
    if not path.is_file():
        raise FileNotFoundError(f"Atlas file not found: {atlas_path}")

    if path.suffix.lower() == ".csv":
        df = pd.read_csv(path)
    elif path.suffix.lower() == ".parquet":
        df = pd.read_parquet(path)
    else:
        raise ValueError(f"Unsupported atlas file format: {path.suffix}")

    # Standardise column names
    if "roi_id" in df.columns:
        df = df.rename(columns={"roi_id": "roi_index"})
    elif "roi_index" not in df.columns:
        raise ValueError("Atlas must contain a 'roi_index' column (or 'roi_id').")

    if "network" not in df.columns:
        raise ValueError("Atlas must contain a 'network' column.")

    return df

def get_roi_indices_for_networks(atlas_df: pd.DataFrame, target_networks: List[str]) -> List[int]:
    """
    Extract ROI indices belonging to the specified networks.
    """
    mask = atlas_df["network"].isin(target_networks)
    return atlas_df.loc[mask, "roi_index"].tolist()

def extract_network_metrics(
    matrices: np.ndarray,
    atlas_df: pd.DataFrame,
    target_networks: List[str],
    output_path: str
) -> pd.DataFrame:
    """
    Extract and compute mean connectivity metrics for each target network
    and each subject.

    The output CSV contains columns:
        subject_id, network, mean_connectivity
    """
    n_subjects = matrices.shape[0]
    results = []

    for subj_idx in range(n_subjects):
        mat = matrices[subj_idx]
        for net in target_networks:
            roi_inds = get_roi_indices_for_networks(atlas_df, [net])
            if not roi_inds:
                continue
            submat = mat[np.ix_(roi_inds, roi_inds)]
            # Upper‑triangle (excluding diagonal) mean
            triu = np.triu_indices_from(submat, k=1)
            if triu[0].size == 0:
                mean_conn = np.nan
            else:
                mean_conn = submat[triu].mean()
            results.append({
                "subject_id": f"subj_{subj_idx}",
                "network": net,
                "mean_connectivity": mean_conn
            })

    df = pd.DataFrame(results)
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    logger.info(f"Network metrics saved to {output_path}")
    return df

def process_network_extraction(config: Dict[str, Any]) -> pd.DataFrame:
    """
    Orchestrates loading of data, extraction of metrics, and CSV writing.

    Expected keys in ``config``:
        - matrices_path: path to ``connectivity_matrices.npy``
        - atlas_path: path to the atlas CSV (generated by download_atlas)
        - output_path: where to write ``network_metrics.csv``
        - target_networks: list of network names to extract
    """
    matrices = load_connectivity_matrices(config["matrices_path"])
    atlas_df = load_atlas_annotations(config["atlas_path"])
    df = extract_network_metrics(
        matrices,
        atlas_df,
        config["target_networks"],
        config["output_path"]
    )
    return df

def main():
    """
    CLI entry point for network‑level metric extraction.
    """
    import argparse

    parser = argparse.ArgumentParser(description="Extract network metrics from connectivity matrices")
    parser.add_argument("--matrices", required=True, help="Path to connectivity_matrices.npy")
    parser.add_argument("--atlas", required=True, help="Path to atlas CSV (generated by download_atlas)")
    parser.add_argument("--output", default="data/processed/network_metrics.csv", help="CSV output path")
    parser.add_argument(
        "--networks",
        nargs="+",
        default=["auditory", "motor", "executive_control"],
        help="Target network names (must match labels in the atlas)"
    )
    args = parser.parse_args()

    config = {
        "matrices_path": args.matrices,
        "atlas_path": args.atlas,
        "output_path": args.output,
        "target_networks": args.networks
    }

    process_network_extraction(config)

if __name__ == "__main__":
    main()
