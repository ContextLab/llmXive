import os
import logging
import numpy as np
import pandas as pd
from typing import List, Dict, Any, Optional, Tuple
from pathlib import Path

from utils.logging import get_logger

logger = get_logger(__name__)

# Thresholds to sweep as defined in T038 logic
THRESHOLDS_TO_SWEEP = [0.01, 0.05, 0.10]

def load_correlation_results(input_path: str) -> pd.DataFrame:
    """
    Load the correlation results generated by T039.
    Expected columns: connection_id, r_value, p_value, effect_size, ci_95, stability_flag
    """
    path = Path(input_path)
    if not path.exists():
        raise FileNotFoundError(f"Correlation results file not found: {input_path}")
    
    df = pd.read_csv(path)
    required_cols = ['connection_id', 'p_value', 'stability_flag']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in {input_path}: {missing}")
    
    return df

def sweep_thresholds(df: pd.DataFrame, thresholds: Optional[List[float]] = None) -> pd.DataFrame:
    """
    Sweep across significance thresholds and count significant connections.
    
    Args:
        df: DataFrame with 'p_value' column.
        thresholds: List of alpha thresholds to test. Defaults to [0.01, 0.05, 0.10].
        
    Returns:
        DataFrame with columns: threshold, significant_count, stability_flag
    """
    if thresholds is None:
        thresholds = THRESHOLDS_TO_SWEEP
        
    results = []
    
    for threshold in sorted(thresholdes):
        # Count connections where p_value < threshold
        sig_count = (df['p_value'] < threshold).sum()
        
        # Determine stability flag for this threshold level
        # If ANY connection is unstable (stability_flag == 'low') at this threshold, mark the row
        # However, the task T038 defines stability per connection. 
        # T040 output aggregates: "stability_flag" in the output likely refers to the aggregate state
        # or the stability of the findings at that threshold.
        # Interpretation: If the number of significant findings drops drastically or if 
        # the underlying connections are unstable, we flag.
        # Strict interpretation of T038: "Flag low stability ... if 95% CI includes zero".
        # T040 output: "stability_flag" column. 
        # Let's define aggregate stability: 'high' if all significant connections at this threshold are stable, 'low' otherwise.
        
        # Get subset of significant connections
        sig_df = df[df['p_value'] < threshold]
        
        if len(sig_df) == 0:
            # No significant findings
            agg_stability = 'high' # No unstable findings if no findings
        else:
            # Check if any of the significant connections are marked 'low'
            if (sig_df['stability_flag'] == 'low').any():
                agg_stability = 'low'
            else:
                agg_stability = 'high'
        
        results.append({
            'threshold': threshold,
            'significant_count': int(sig_count),
            'stability_flag': agg_stability
        })
        
    return pd.DataFrame(results)

def check_connection_stability(df: pd.DataFrame) -> pd.DataFrame:
    """
    Re-verify stability flags based on the raw data if needed, or just pass through.
    For T040, we rely on the pre-computed stability_flag from T039.
    This function serves as a hook for potential re-calculation if the input lacks the flag.
    """
    if 'stability_flag' not in df.columns:
        logger.warning("stability_flag column missing. Assuming all high stability.")
        df['stability_flag'] = 'high'
    return df

def process_sensitivity_analysis(input_path: str, output_path: str) -> None:
    """
    Main entry point to run the sensitivity analysis.
    1. Load correlation results.
    2. Sweep thresholds.
    3. Write results to CSV.
    """
    logger.info(f"Loading correlation results from {input_path}")
    df = load_correlation_results(input_path)
    
    logger.info("Performing threshold sweep...")
    df = check_connection_stability(df)
    results_df = sweep_thresholds(df)
    
    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Writing sensitivity analysis results to {output_path}")
    results_df.to_csv(output_file, index=False)
    
    logger.info(f"Completed. Found {len(results_df)} threshold levels.")
    logger.debug(f"Results:\n{results_df}")

def main() -> None:
    """CLI entry point."""
    import argparse
    
    parser = argparse.ArgumentParser(description="Run sensitivity analysis on correlation results.")
    parser.add_argument("--input", type=str, default="data/processed/correlation_results.csv",
                        help="Path to correlation results CSV (output of T039)")
    parser.add_argument("--output", type=str, default="data/processed/sensitivity_analysis.csv",
                        help="Path to output sensitivity analysis CSV")
    args = parser.parse_args()
    
    configure_logger()
    process_sensitivity_analysis(args.input, args.output)

if __name__ == "__main__":
    main()
