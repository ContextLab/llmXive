from utils.logging import get_logger

logger = get_logger(__name__)

def load_nbs_results(input_path: str) -> pd.DataFrame:
    """
    Loads the NBS results from a CSV file generated by the NBS analysis.
    
    Args:
        input_path (str): Path to the input CSV file containing NBS results.
        
    Returns:
        pd.DataFrame: DataFrame containing the NBS results.
        
    Raises:
        FileNotFoundError: If the input file does not exist.
        ValueError: If the file is empty or missing required columns.
    """
    if not os.path.exists(input_path):
        raise FileNotFoundError(f"NBS results file not found: {input_path}")
    
    df = pd.read_csv(input_path)
    
    required_columns = ['component_id', 'size_edges', 'p_value_fwer']
    missing_cols = [col for col in required_columns if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in NBS results: {missing_cols}")
    
    if df.empty:
        logger.warning("NBS results file is empty.")
        
    logger.info(f"Loaded {len(df)} NBS results from {input_path}")
    return df

def write_nbs_results(df: pd.DataFrame, output_path: str) -> None:
    """
    Writes the NBS results to a CSV file.
    
    Args:
        df (pd.DataFrame): DataFrame containing the NBS results.
        output_path (str): Path to the output CSV file.
        
    Raises:
        IOError: If the file cannot be written.
    """
    output_dir = os.path.dirname(output_path)
    if output_dir and not os.path.exists(output_dir):
        os.makedirs(output_dir, exist_ok=True)
        
    try:
        df.to_csv(output_path, index=False)
        logger.info(f"Wrote {len(df)} NBS results to {output_path}")
    except Exception as e:
        logger.error(f"Failed to write NBS results to {output_path}: {e}")
        raise IOError(f"Failed to write NBS results: {e}")

def main():
    """
    Main entry point for writing NBS results.
    
    Reads NBS results from a default or specified input path and writes them
    to the standard output location: data/processed/nbs_results.csv.
    """
    # Default paths relative to project root
    input_path = os.environ.get('NBS_INPUT_PATH', 'data/processed/nbs_temp_results.csv')
    output_path = os.environ.get('NBS_OUTPUT_PATH', 'data/processed/nbs_results.csv')
    
    # If the default input doesn't exist, check if we are in a context where 
    # run_nbs.py was just executed and might have left data in memory or a temp file.
    # For this specific task T031, we assume the data exists at the input path 
    # (produced by T029a logic) or we simulate the loading if the file is missing 
    # ONLY for the purpose of verifying the write logic in verification mode,
    # but the task requires REAL output. 
    # 
    # CRITICAL: This script is the OUTPUT writer. It expects the data to exist.
    # If the file doesn't exist, it means the previous step (T029a) didn't run or failed.
    # We raise an error rather than fabricating data.
    
    if not os.path.exists(input_path):
        # Check if we can find a generated file from the run_nbs analysis
        # In a real pipeline, run_nbs.py would write to this temp file or memory.
        # Since we are implementing T031 (Output), we assume the pipeline flow:
        # run_nbs -> writes temp -> write_nbs_results -> writes final.
        # If the temp file is missing, we cannot proceed without data.
        raise FileNotFoundError(
            f"Input NBS data file not found at {input_path}. "
            f"Please ensure the NBS analysis (T029a) has completed successfully."
        )

    try:
        df = load_nbs_results(input_path)
        write_nbs_results(df, output_path)
        logger.info("NBS results successfully written.")
    except Exception as e:
        logger.error(f"Error processing NBS results: {e}")
        sys.exit(1)

