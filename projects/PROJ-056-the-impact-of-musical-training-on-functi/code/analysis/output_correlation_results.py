"""
Output module for correlation analysis results (Task T039).

This script loads the processed correlation analysis data (generated by
code/analysis/correlation.py and refined by sensitivity.py) and writes
the final results to `data/processed/correlation_results.csv`.

The output file contains:
- connection_id
- r_value
- p_value
- effect_size
- ci_95
- stability_flag

This satisfies Task T039 requirements.
"""
import os
import sys
import logging
import pandas as pd
from pathlib import Path
from typing import Optional, Dict, Any

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent
sys.path.append(str(project_root))

from utils.logging import get_logger

logger = get_logger(__name__)

# Constants
OUTPUT_FILE = Path("data/processed/correlation_results.csv")
INPUT_FILE = Path("data/processed/correlation_analysis_intermediate.csv")
STABILITY_FILE = Path("data/processed/sensitivity_analysis.csv")

# Required columns in the intermediate input file
REQUIRED_INPUT_COLUMNS = [
    "connection_id",
    "r_value",
    "p_value",
    "effect_size",
    "ci_lower",
    "ci_upper"
]

# Required columns in the stability input file
REQUIRED_STABILITY_COLUMNS = [
    "connection_id",
    "stability_flag"
]

def load_correlation_data(input_path: Optional[Path] = None) -> pd.DataFrame:
    """
    Load the intermediate correlation analysis results.
    
    Args:
        input_path: Path to the intermediate CSV file. Defaults to INPUT_FILE.
        
    Returns:
        DataFrame with correlation results.
        
    Raises:
        FileNotFoundError: If the input file does not exist.
        ValueError: If required columns are missing.
    """
    path = input_path if input_path else INPUT_FILE
    
    if not path.exists():
        logger.error(f"Input file not found: {path}")
        raise FileNotFoundError(f"Correlation input file not found: {path}")
    
    logger.info(f"Loading correlation data from {path}")
    df = pd.read_csv(path)
    
    # Validate required columns
    missing_cols = [col for col in REQUIRED_INPUT_COLUMNS if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in {path}: {missing_cols}")
    
    logger.info(f"Loaded {len(df)} correlation records")
    return df

def load_stability_data(stability_path: Optional[Path] = None) -> pd.DataFrame:
    """
    Load the sensitivity analysis results containing stability flags.
    
    Args:
        stability_path: Path to the sensitivity analysis CSV. Defaults to STABILITY_FILE.
        
    Returns:
        DataFrame with connection_id and stability_flag.
        
    Raises:
        FileNotFoundError: If the input file does not exist.
        ValueError: If required columns are missing.
    """
    path = stability_path if stability_path else STABILITY_FILE
    
    if not path.exists():
        logger.error(f"Stability input file not found: {path}")
        raise FileNotFoundError(f"Sensitivity input file not found: {path}")
    
    logger.info(f"Loading stability data from {path}")
    df = pd.read_csv(path)
    
    # Validate required columns
    missing_cols = [col for col in REQUIRED_STABILITY_COLUMNS if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in {path}: {missing_cols}")
    
    logger.info(f"Loaded {len(df)} stability records")
    return df

def merge_and_format_results(
    correlation_df: pd.DataFrame,
    stability_df: pd.DataFrame
) -> pd.DataFrame:
    """
    Merge correlation data with stability flags and format for output.
    
    Args:
        correlation_df: DataFrame with correlation statistics.
        stability_df: DataFrame with stability flags.
        
    Returns:
        Formatted DataFrame ready for writing.
    """
    # Merge on connection_id
    merged = pd.merge(
        correlation_df,
        stability_df[["connection_id", "stability_flag"]],
        on="connection_id",
        how="left"
    )
    
    # Format CI_95 as a string representation of the interval
    merged["ci_95"] = merged.apply(
        lambda row: f"[{row['ci_lower']:.6f}, {row['ci_upper']:.6f}]",
        axis=1
    )
    
    # Select and order final columns
    output_columns = [
        "connection_id",
        "r_value",
        "p_value",
        "effect_size",
        "ci_95",
        "stability_flag"
    ]
    
    # Ensure all columns exist (fill missing stability flags with 'unknown' if any)
    if "stability_flag" not in merged.columns:
        merged["stability_flag"] = "unknown"
    
    final_df = merged[output_columns].copy()
    
    # Round numeric columns for cleaner output
    final_df["r_value"] = final_df["r_value"].round(6)
    final_df["p_value"] = final_df["p_value"].round(6)
    final_df["effect_size"] = final_df["effect_size"].round(6)
    
    return final_df

def write_results(df: pd.DataFrame, output_path: Optional[Path] = None) -> Path:
    """
    Write the formatted results to CSV.
    
    Args:
        df: Formatted DataFrame to write.
        output_path: Path to output file. Defaults to OUTPUT_FILE.
        
    Returns:
        Path to the written file.
        
    Raises:
        RuntimeError: If writing fails.
    """
    path = output_path if output_path else OUTPUT_FILE
    
    # Ensure directory exists
    path.parent.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Writing results to {path}")
    
    try:
        df.to_csv(path, index=False)
        logger.info(f"Successfully wrote {len(df)} records to {path}")
    except Exception as e:
        logger.error(f"Failed to write results: {e}")
        raise RuntimeError(f"Failed to write correlation results: {e}")
    
    return path

def process_correlation_output(
    correlation_input: Optional[Path] = None,
    stability_input: Optional[Path] = None,
    output: Optional[Path] = None
) -> Path:
    """
    Main pipeline function to process and output correlation results.
    
    Args:
        correlation_input: Path to intermediate correlation CSV.
        stability_input: Path to sensitivity analysis CSV.
        output: Path to output CSV.
        
    Returns:
        Path to the generated output file.
    """
    logger.info("Starting correlation results output pipeline")
    
    # Load data
    correlation_df = load_correlation_data(correlation_input)
    stability_df = load_stability_data(stability_input)
    
    # Merge and format
    final_df = merge_and_format_results(correlation_df, stability_df)
    
    # Write output
    output_path = write_results(final_df, output)
    
    logger.info("Correlation results output pipeline completed successfully")
    return output_path

def main():
    """Entry point for running the output script."""
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    try:
        output_path = process_correlation_output()
        print(f"Output written to: {output_path}")
        return 0
    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        print(f"ERROR: {e}")
        print("Please ensure that code/analysis/correlation.py and code/analysis/sensitivity.py have been run first.")
        return 1
    except Exception as e:
        logger.error(f"Pipeline failed: {e}")
        print(f"ERROR: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
