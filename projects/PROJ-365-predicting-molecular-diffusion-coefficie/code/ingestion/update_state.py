"""Update project versioning metadata for raw data artifacts.

This script reads the checksum file generated by ``code/ingestion/checksums.py``,
builds a mapping of artifact relative paths to their SHA‑256 hashes, and writes
a state YAML file under the ``data/state`` directory (project‑owned).

The resulting YAML has the following structure:

.. code-block:: yaml

    artifact_hashes:
      data/raw/dataset.csv: <sha256>
      data/checksums.txt: <sha256>
    updated_at: 2026-10-15T12:34:56.789012+00:00

The ``updated_at`` field is an ISO‑8601 UTC timestamp indicating when the
state was refreshed.
"""

import datetime
import sys
from pathlib import Path
from typing import Dict

import yaml
from llmxive_toolkit import paths, get_logger

log = get_logger(__name__)

# Write the state file inside the project‑owned ``data/state`` directory
STATE_FILE = paths.data("state", "ingestion_state.yaml")
CHECKSUMS_FILE = paths.data("checksums.txt")

def _load_checksums(checksum_path: Path) -> Dict[str, str]:
    """Parse ``checksums.txt`` and return a mapping of relative paths → hash.

    The file is expected to contain lines of the form:

        <hash>  <relative_path>

    Whitespace between the two fields may be one or more spaces/tabs.
    """
    if not checksum_path.is_file():
        log.error(f"Checksum file not found: {checksum_path}")
        raise FileNotFoundError(f"Checksum file missing: {checksum_path}")

    artifact_hashes: Dict[str, str] = {}
    with checksum_path.open("r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                hash_val, rel_path = line.split(maxsplit=1)
            except ValueError:
                log.error(f"Malformed checksum line: {line!r}")
                raise ValueError(f"Malformed checksum line: {line!r}")
            artifact_hashes[rel_path] = hash_val
    return artifact_hashes

def _write_state(state_path: Path, artifact_hashes: Dict[str, str]) -> None:
    """Write the state YAML file with the given hashes and a fresh timestamp."""
    state_path.parent.mkdir(parents=True, exist_ok=True)

    state_content = {
        "artifact_hashes": artifact_hashes,
        "updated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
    }

    with state_path.open("w", encoding="utf-8") as fh:
        yaml.safe_dump(state_content, fh, sort_keys=False)

    log.info(f"State file written to {state_path}")

def main() -> None:
    """Entry point for the script.

    1. Load the checksum file.
    2. Add the checksum file itself to the map (so the state records its own hash).
    3. Write the state YAML under ``data/state``.
    """
    try:
        artifact_hashes = _load_checksums(CHECKSUMS_FILE)
    except Exception as exc:
        log.error(f"Failed to load checksums: {exc}")
        sys.exit(1)

    # Include the checksum file's own hash in the state.
    # Compute it on‑the‑fly to avoid a circular dependency on the file's
    # entry (which may or may not already be present).
    import hashlib

    def _hash_file(p: Path) -> str:
        h = hashlib.sha256()
        with p.open("rb") as f:
            for chunk in iter(lambda: f.read(8192), b""):
                h.update(chunk)
        return h.hexdigest()

    checksum_file_hash = _hash_file(CHECKSUMS_FILE)
    artifact_hashes[str(CHECKSUMS_FILE.relative_to(paths.root))] = checksum_file_hash

    _write_state(STATE_FILE, artifact_hashes)

if __name__ == "__main__":
    main()
