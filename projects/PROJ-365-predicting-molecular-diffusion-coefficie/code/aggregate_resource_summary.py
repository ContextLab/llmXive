"""
Aggregate runtime and memory usage into a unified resource summary.

This script reads the `runtime_memory.json` file generated by the
`utils.monitor` module (Task T006c/e) and copies the relevant fields
into `resource_summary.json`.  It is intended to be run after the full
pipeline has completed so that a single consolidated report is available
for downstream analysis and contract tests (Task T036).
"""

import json
from pathlib import Path
from utils.config import get_project_root

def main() -> None:
    """
    Entry point for the aggregation script.

    Reads ``artifacts/reports/runtime_memory.json`` and writes
    ``artifacts/reports/resource_summary.json`` containing the keys
    ``total_seconds`` and ``peak_memory_mb`` with numeric values.
    """
    # Resolve the root of the project and the expected input/output locations
    project_root = get_project_root()
    reports_dir = project_root / "artifacts" / "reports"
    runtime_path = reports_dir / "runtime_memory.json"
    summary_path = reports_dir / "resource_summary.json"

    # Load the source JSON; let any IOError or JSONDecodeError propagate
    # so that failures are loud and clear.
    with runtime_path.open("r", encoding="utf-8") as f:
        runtime_data = json.load(f)

    # Extract the required fields; raise a clear error if they are missing.
    try:
        total_seconds = runtime_data["total_seconds"]
        peak_memory_mb = runtime_data["peak_memory_mb"]
    except KeyError as exc:
        raise KeyError(
            f"Missing expected key {exc.args[0]} in {runtime_path}"
        ) from exc

    # Prepare the summary payload.
    summary_data = {
        "total_seconds": total_seconds,
        "peak_memory_mb": peak_memory_mb,
    }

    # Ensure the reports directory exists (it should, but be defensive).
    reports_dir.mkdir(parents=True, exist_ok=True)

    # Write the aggregated summary.
    with summary_path.open("w", encoding="utf-8") as f:
        json.dump(summary_data, f, indent=2)

    print(f"Resource summary written to {summary_path}")

if __name__ == "__main__":
    main()