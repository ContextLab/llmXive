"""
T065: Verify Heavy-Tailed Independence

This script validates Constitution Principle VI (Validation Independence) by:
1. Ensuring the heavy-tailed validation (T034d) can run independently.
2. Verifying it does NOT read from `data/processed/full_sweep_results.json`.
3. Generating `data/processed/heavy_tailed_results.json` using only the held-out set
   generated by T034c/T034h.

Verification Procedure:
1. Delete `data/processed/full_sweep_results.json` if it exists.
2. Run this script.
3. Verify `data/processed/heavy_tailed_results.json` is created successfully.
4. Verify no errors related to missing full_sweep_results.json occur.
"""
import os
import sys
import json
import argparse
import logging
from pathlib import Path

# Project root setup
PROJECT_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "code"))

from src.environment.synthetic_mdp import generate_heavy_tailed_mdp
from src.analysis.stats import validate_heavy_tailed_pareto
from src.environment.pareto_oracle import calculate_pareto_distance

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler(PROJECT_ROOT / "logs" / "heavy_tailed_independence_test.log")
    ]
)
logger = logging.getLogger(__name__)

DATA_PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
HEAVY_TAILED_INPUT_PATH = DATA_PROCESSED_DIR / "heavy_tailed_mdp.json"
HEAVY_TAILED_OUTPUT_PATH = DATA_PROCESSED_DIR / "heavy_tailed_results.json"
FULL_SWEEP_PATH = DATA_PROCESSED_DIR / "full_sweep_results.json"

def check_file_exists(path: Path, description: str):
    """Helper to check file existence."""
    if not path.exists():
        raise FileNotFoundError(f"{description} not found: {path}")
    logger.info(f"Verified {description} exists: {path}")

def check_file_missing(path: Path, description: str):
    """Helper to ensure a file is missing (for independence test)."""
    if path.exists():
        logger.warning(f"Removing {description} to test independence: {path}")
        path.unlink()
        logger.info(f"Removed {description}")

def load_heavy_tailed_mdp_from_disk() -> dict:
    """Loads the heavy-tailed MDP instance from the persistent file generated by T034h."""
    if not HEAVY_TAILED_INPUT_PATH.exists():
        logger.error(f"Input file {HEAVY_TAILED_INPUT_PATH} not found. "
                     "Please ensure T034h (Generate persistent heavy-tailed dataset) has run.")
        raise FileNotFoundError(f"Missing required input: {HEAVY_TAILED_INPUT_PATH}")
    
    with open(HEAVY_TAILED_INPUT_PATH, 'r') as f:
        return json.load(f)

def run_independence_validation():
    """
    Core validation logic:
    1. Ensure full_sweep_results.json is absent.
    2. Load heavy-tailed MDP from disk (T034h output).
    3. Run validation (T034d logic) using only that MDP.
    4. Save results to heavy_tailed_results.json.
    """
    logger.info("=== Starting Heavy-Tailed Independence Validation (T065) ===")
    
    # Step 1: Ensure independence by removing the dependency file if it exists
    logger.info("Step 1: Ensuring independence by removing full_sweep_results.json...")
    check_file_missing(FULL_SWEEP_PATH, "full_sweep_results.json")
    
    # Step 2: Load the heavy-tailed MDP from the persistent file
    logger.info("Step 2: Loading heavy-tailed MDP from disk...")
    try:
        mdp_data = load_heavy_tailed_mdp_from_disk()
        logger.info(f"Loaded MDP with {len(mdp_data.get('rewards', []))} objectives.")
    except FileNotFoundError as e:
        logger.critical(f"Failed to load MDP: {e}")
        raise

    # Step 3: Run the heavy-tailed validation logic
    # This function (from T034d) calculates distance to theoretical Pareto frontier
    # and compares it against the threshold (0.10).
    logger.info("Step 3: Running heavy-tailed Pareto validation (T034d)...")
    try:
        # The validate_heavy_tailed_pareto function expects an MDP instance or data dict
        # and an oracle function. We pass the loaded data and the oracle function.
        # Note: The function signature in src/analysis/stats.py is:
        # validate_heavy_tailed_pareto(mdp_instance, oracle_function)
        
        # We need to reconstruct the MDP object or pass the dict if the function handles it.
        # Assuming the function can handle the dict representation or we reconstruct.
        # For robustness, we pass the dict and let the function handle reconstruction if needed.
        # If the function strictly requires an object, we might need to reconstruct it here.
        # Based on T034d description, it takes 'mdp_instance'. 
        # Let's assume we can pass the dict or a reconstructed object.
        # To be safe, we'll pass the dict and the oracle function.
        
        result = validate_heavy_tailed_pareto(mdp_data, calculate_pareto_distance)
        
        if not isinstance(result, dict):
            raise TypeError(f"Expected dict result from validate_heavy_tailed_pareto, got {type(result)}")
            
        logger.info(f"Validation result: {result}")
        
    except Exception as e:
        logger.critical(f"Validation failed: {e}")
        raise

    # Step 4: Save results
    logger.info("Step 4: Saving results to heavy_tailed_results.json...")
    DATA_PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    with open(HEAVY_TAILED_OUTPUT_PATH, 'w') as f:
        json.dump(result, f, indent=2)
    
    logger.info(f"Successfully wrote results to {HEAVY_TAILED_OUTPUT_PATH}")
    
    # Final Verification
    logger.info("Step 5: Final Verification...")
    if not HEAVY_TAILED_OUTPUT_PATH.exists():
        raise RuntimeError("Output file was not created.")
    
    with open(HEAVY_TAILED_OUTPUT_PATH, 'r') as f:
        saved_data = json.load(f)
    
    required_keys = ['threshold_passed', 'deviation_metric', 'construct_validity_failure']
    missing_keys = [k for k in required_keys if k not in saved_data]
    if missing_keys:
        raise RuntimeError(f"Output missing required keys: {missing_keys}")
    
    logger.info("=== Independence Validation PASSED ===")
    logger.info(f"Result: threshold_passed={saved_data['threshold_passed']}, "
                f"deviation_metric={saved_data['deviation_metric']:.4f}")
    
    return True

def main():
    parser = argparse.ArgumentParser(description="T065: Verify Heavy-Tailed Independence")
    parser.add_argument('--force-clean', action='store_true', 
                        help="Force removal of full_sweep_results.json if present")
    args = parser.parse_args()

    try:
        # If --force-clean is set, explicitly remove the dependency
        if args.force_clean and FULL_SWEEP_PATH.exists():
            logger.info("Forcing removal of full_sweep_results.json...")
            FULL_SWEEP_PATH.unlink()
        
        run_independence_validation()
        logger.info("T065 Verification: SUCCESS")
        sys.exit(0)
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        logger.error("Ensure T034h (Generate persistent heavy-tailed dataset) has been run first.")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Validation failed with error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()