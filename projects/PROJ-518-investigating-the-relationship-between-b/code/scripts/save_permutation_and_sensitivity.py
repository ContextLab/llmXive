def main():
    """
    Main entry point for saving permutation and sensitivity results.
    """
    logger.info("Starting T030: Saving permutation and sensitivity results.")
    
    try:
        # Load real data state (or re-run analysis if state is missing but raw data exists)
        # For this implementation, we assume the state file exists from T027/T046
        state = load_real_analysis_data()
        
        # Extract data
        flexibility = state.get('flexibility')
        creativity = state.get('creativity')
        window_lengths = state.get('window_lengths', [20, 30, 40])
        permutation_results = state.get('permutation_results') # List of (shuffle_id, correlation)
        sensitivity_data = state.get('sensitivity_data') # Dict from T046
        
        if flexibility is None or creativity is None:
            raise DataMissingCreativityError("Missing flexibility or creativity vectors in state.")
        
        # 1. Save Permutation Results
        # Schema: shuffle_id, correlation
        if permutation_results is None:
            # If not in state, we might need to re-run T027 if raw data is available
            # But we assume it's in state from T027
            logger.warning("Permutation results not found in state. Re-running T027?")
            # We cannot re-run T027 without raw data here. Fail.
            raise DataMissingCreativityError("Permutation results missing from state.")
        
        perm_df = pd.DataFrame(permutation_results, columns=['shuffle_id', 'correlation'])
        save_permutation_results(perm_df, output_path="data/interim/permutation_results.csv")
        logger.info("Saved permutation_results.csv")
        
        # 2. Save Sensitivity Summary
        # Schema: window_length, correlation, empirical_p_value
        if sensitivity_data is None:
            # Re-run T046 if possible, or fail
            logger.warning("Sensitivity data not found in state. Re-running T046?")
            raise DataMissingCreativityError("Sensitivity data missing from state.")
        
        # T046 returns a dict: {'p_values': [...], 'correlations': [...], 'window_lengths': [...]}
        # We need to construct the DataFrame
        sens_df = construct_sensitivity_df(sensitivity_data)
        
        if 'empirical_p_value' not in sens_df.columns:
            # Ensure the column exists as per T046.1 requirement
            # If p_values are present, rename them
            if 'p_value' in sens_df.columns:
                sens_df = sens_df.rename(columns={'p_value': 'empirical_p_value'})
            else:
                raise DataMissingCreativityError("Sensitivity DataFrame missing empirical_p_value column.")
        
        save_sensitivity_summary(sens_df, output_path="data/interim/sensitivity_summary.csv")
        logger.info("Saved sensitivity_summary.csv")
        
        logger.info("T030 completed successfully.")
        
    except DataMissingCreativityError as e:
        logger.error(f"Data missing error: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during T030: {e}")
        raise

if __name__ == "__main__":
    main()
