"""
Convergence Monitor for GLM fitting iterations.

This module parses the convergence log generated by the GLM fitter,
identifies iterations with convergence issues (excessive iterations
or insufficient tolerance), and generates a summary report.
"""

import argparse
import json
import logging
import sys
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)


class ConvergenceMonitor:
    """
    Monitors and reports on GLM convergence statistics.

    Reads convergence logs from the GLM fitter, flags problematic
    iterations, and generates a human-readable report.
    """

    def __init__(
        self,
        input_path: Path,
        output_path: Path,
        max_iterations_threshold: int = 100,
        min_tolerance_threshold: float = 1e-4
    ):
        """
        Initialize the convergence monitor.

        Args:
            input_path: Path to the convergence_log.json file.
            output_path: Path where the report will be written.
            max_iterations_threshold: Iterations above this are flagged.
            min_tolerance_threshold: Tolerance below this is flagged (too loose).
        """
        self.input_path = input_path
        self.output_path = output_path
        self.max_iterations_threshold = max_iterations_threshold
        self.min_tolerance_threshold = min_tolerance_threshold
        self.issues: List[Dict[str, Any]] = []

    def load_log(self) -> List[Dict[str, Any]]:
        """Load the convergence log from disk."""
        if not self.input_path.exists():
            raise FileNotFoundError(
                f"Convergence log not found at {self.input_path}. "
                "Ensure GLM fitting (T016) has completed successfully."
            )

        with open(self.input_path, 'r', encoding='utf-8') as f:
            return json.load(f)

    def analyze(self, log_data: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """
        Analyze log data and flag iterations with convergence issues.

        Flags:
            - max_iterations > threshold
            - tolerance < threshold (meaning the solver stopped too early/loosely)

        Args:
            log_data: List of convergence records.

        Returns:
            List of flagged issues.
        """
        issues = []
        for record in log_data:
            iteration_id = record.get("iteration_id")
            converged = record.get("converged", False)
            max_iters = record.get("max_iterations", 0)
            tolerance = record.get("tolerance", 0.0)

            reasons = []

            # Check iteration count
            if max_iters > self.max_iterations_threshold:
                reasons.append(
                    f"Exceeded max iterations ({max_iters} > {self.max_iterations_threshold})"
                )

            # Check tolerance (lower tolerance is stricter, but if it's very low
            # and we stopped, it might mean we hit a loose tolerance too early
            # or the solver struggled. The task specifically flags tolerance < 1e-4.
            # Note: Usually we want tolerance to be SMALL (e.g. 1e-6).
            # However, the task spec says: "flag iterations where ... tolerance < 1e-4".
            # This implies we are looking for cases where the achieved tolerance
            # was too loose (i.e., the error was still large relative to 1e-4?
            # Or perhaps the task implies the *target* tolerance was too loose?
            # Re-reading T049: "flag iterations where ... tolerance < 1e-4".
            # In statsmodels, 'tolerance' often refers to the convergence criterion.
            # If the achieved tolerance is < 1e-4, that usually means it converged well.
            # BUT, if the task says flag < 1e-4, it might mean "flag if the
            # *reported* tolerance is suspiciously low" or it's a specific
            # heuristic for this project.
            # Let's follow the task literally: Flag if tolerance < 1e-4.
            # Wait, typically we flag if tolerance is *too high* (bad convergence).
            # If tolerance < 1e-4, that is usually GOOD (tight convergence).
            # However, the prompt says: "flag iterations where max_iterations > 100 or tolerance < 1e-4".
            # This is counter-intuitive for "tolerance" as error.
            # Perhaps it means "tolerance" as the *step size* or *delta*?
            # Let's assume the prompt is literal: if the value is < 1e-4, flag it.
            # Maybe it implies the solver stopped because the step was too small,
            # but maybe it's a false convergence?
            # I will implement exactly as requested: flag if tolerance < 1e-4.
            if tolerance < self.min_tolerance_threshold:
                reasons.append(
                    f"Tolerance too tight/low ({tolerance} < {self.min_tolerance_threshold})"
                )

            if reasons:
                issues.append({
                    "iteration_id": iteration_id,
                    "reason": "; ".join(reasons)
                })

        return issues

    def generate_report(self, issues: List[Dict[str, Any]]) -> None:
        """
        Generate the markdown report.

        Args:
            issues: List of flagged issues.
        """
        self.output_path.parent.mkdir(parents=True, exist_ok=True)

        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        report_lines = [
            "# Convergence Monitor Report",
            f"**Generated:** {timestamp}",
            f"**Input Log:** {self.input_path.name}",
            "",
            "## Summary",
            f"- Total Issues Detected: {len(issues)}",
            "",
            "## Flagged Iterations",
            ""
        ]

        if not issues:
            report_lines.append("No convergence issues detected. All iterations met criteria.")
        else:
            report_lines.append("| Iteration ID | Reason |")
            report_lines.append("| :--- | :--- |")
            for issue in issues:
                report_lines.append(
                    f"| {issue['iteration_id']} | {issue['reason']} |"
                )

        # Write report
        report_content = "\n".join(report_lines)
        with open(self.output_path, 'w', encoding='utf-8') as f:
            f.write(report_content)

        logger.info(f"Convergence report written to {self.output_path}")

    def run(self) -> None:
        """Execute the full monitoring pipeline."""
        logger.info(f"Loading convergence log from {self.input_path}")
        log_data = self.load_log()
        logger.info(f"Loaded {len(log_data)} records.")

        logger.info("Analyzing convergence criteria...")
        self.issues = self.analyze(log_data)
        logger.info(f"Found {len(self.issues)} issues.")

        logger.info(f"Generating report at {self.output_path}")
        self.generate_report(self.issues)


def main() -> None:
    """Entry point for the convergence monitor script."""
    parser = argparse.ArgumentParser(
        description="Monitor GLM convergence and generate a report."
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("data/aggregated/convergence_log.json"),
        help="Path to the convergence log JSON file."
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("results/paper/convergence_report.md"),
        help="Path for the output markdown report."
    )
    parser.add_argument(
        "--max-iterations",
        type=int,
        default=100,
        help="Threshold for maximum iterations."
    )
    parser.add_argument(
        "--min-tolerance",
        type=float,
        default=1e-4,
        help="Threshold for minimum tolerance."
    )

    args = parser.parse_args()

    try:
        monitor = ConvergenceMonitor(
            input_path=args.input,
            output_path=args.output,
            max_iterations_threshold=args.max_iterations,
            min_tolerance_threshold=args.min_tolerance
        )
        monitor.run()
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in convergence log: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during convergence monitoring: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()
