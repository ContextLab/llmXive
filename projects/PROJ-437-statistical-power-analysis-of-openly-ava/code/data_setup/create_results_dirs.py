"""
Module to create the results directory structure for the llmXive project.

This module implements task T001d by creating the 'results/' and 'results/paper/'
directories if they do not already exist.
"""
import os
import sys
from pathlib import Path


def create_results_directories(root_dir: str = ".") -> None:
    """
    Create the required results directory structure.
    
    Creates:
        - results/
        - results/paper/
    
    Args:
        root_dir: The root directory of the project (default: current directory).
    
    Raises:
        OSError: If the directories cannot be created due to permissions or other OS errors.
    """
    root_path = Path(root_dir).resolve()
    results_dir = root_path / "results"
    paper_dir = results_dir / "paper"
    
    # Create the directories, ensuring parents exist and not failing if they already do
    results_dir.mkdir(parents=True, exist_ok=True)
    paper_dir.mkdir(parents=True, exist_ok=True)
    
    # Create a .gitkeep file in the paper directory to ensure it is tracked by git
    # even if it is empty.
    gitkeep_path = paper_dir / ".gitkeep"
    if not gitkeep_path.exists():
        gitkeep_path.write_text("# Results and paper artifacts generated by the pipeline.\n")
    
    print(f"Created directory: {results_dir}")
    print(f"Created directory: {paper_dir}")


def main() -> int:
    """
    Main entry point for the script.
    
    Returns:
        int: Exit code (0 for success, 1 for failure).
    """
    try:
        create_results_directories()
        return 0
    except OSError as e:
        print(f"Error creating directories: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
