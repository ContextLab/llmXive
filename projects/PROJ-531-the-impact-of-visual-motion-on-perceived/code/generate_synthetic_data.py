"""
Synthetic Data Generation Module for Visual Motion Agency Study.

This module generates synthetic human‑avatar interaction data strictly for
pipeline stress‑testing when real data is unavailable. It enforces strict
independence between the 'user_response_trigger' and 'agency_score' to
prevent tautological coupling (FR‑012) and updates the download status
file to reflect that synthetic data is being used.
"""
import json
import sys
from pathlib import Path
from datetime import datetime

import numpy as np
import pandas as pd

# Ensure project root is in path if running as script
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from utils.logging_config import get_logger

logger = get_logger(__name__)

# ----------------------------------------------------------------------
# Configuration constants
# ----------------------------------------------------------------------
TARGET_N = 150                     # Target sample size (≥ 150 rows)
CORRELATION_THRESHOLD = 0.05      # Max allowed |r| between trigger & agency
SEED = 42                          # Fixed seed for reproducibility

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def _load_status(status_path: Path) -> dict:
    """Load the download_status.json file."""
    if not status_path.exists():
        logger.error(f"Status file missing: {status_path}")
        raise FileNotFoundError(status_path)

    with open(status_path, "r", encoding="utf-8") as f:
        return json.load(f)

def _update_status(status_path: Path, updates: dict) -> None:
    """Merge ``updates`` into the existing status JSON and write back."""
    data = _load_status(status_path)
    data.update(updates)
    # Keep a timestamp of the modification
    data["timestamp"] = datetime.utcnow().isoformat() + "Z"
    with open(status_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, sort_keys=True)
    logger.info(f"Updated download_status.json with {updates}")

def check_download_status(status_path: Path) -> str:
    """
    Reads the download status file generated by T012.

    Returns:
        str: The status string (\"unavailable\", \"success\", \"invalid\")
    Raises:
        SystemExit: If status is \"invalid\" (FR‑009 compliance)
    """
    data = _load_status(status_path)
    status = data.get("status", "").lower()

    if status == "invalid":
        logger.critical("Dataset excluded: Unvalidated instrument (FR‑009)")
        raise SystemExit(1)

    return status

def generate_synthetic_data(
    n_samples: int = TARGET_N,
    seed: int = SEED,
) -> pd.DataFrame:
    """
    Generates synthetic human‑avatar interaction data with a known linear
    relationship between motion features and agency, and with an
    independent ``user_response_trigger``.

    The linear model follows the specification:

        agency_score = 0.4*latency - 0.3*smoothness + 0.2*lead_time + ε

    where ε ~ N(0, 5). The resulting ``agency_score`` is clipped to the
    0‑100 range.

    Args:
        n_samples: Number of rows to generate (≥ 150).
        seed: Random seed for reproducibility.

    Returns:
        pd.DataFrame with the required columns.
    """
    rng = np.random.default_rng(seed)
    logger.info(f"Generating {n_samples} synthetic samples (seed={seed})")

    # ------------------------------------------------------------------
    # 1. Motion feature generation (realistic bounds)
    # ------------------------------------------------------------------
    latency = rng.normal(loc=150, scale=40, size=n_samples)
    latency = np.clip(latency, 50, 300)  # ms

    smoothness = rng.uniform(0.0, 1.0, size=n_samples)  # dimensionless jerk (0‑1)

    lead_time = rng.normal(loc=20, scale=30, size=n_samples)
    lead_time = np.clip(lead_time, -50, 100)  # ms (negative = lag, positive = lead)

    # ------------------------------------------------------------------
    # 2. Agency score (linear relationship + noise)
    # ------------------------------------------------------------------
    noise = rng.normal(loc=0.0, scale=5.0, size=n_samples)
    agency_raw = (
        0.4 * latency
        - 0.3 * smoothness * 100  # scale smoothness to comparable magnitude
        + 0.2 * lead_time
        + noise
    )
    agency_score = np.clip(agency_raw, 0.0, 100.0)

    # ------------------------------------------------------------------
    # 3. Independent user response trigger
    # ------------------------------------------------------------------
    # Generate from a distribution unrelated to the motion features.
    trigger = rng.exponential(scale=1.0, size=n_samples)
    # Scale to a comparable range (0‑100) for easier inspection.
    trigger = 100 * (trigger - trigger.min()) / (trigger.max() - trigger.min())

    # Verify independence; regenerate if needed (rare).
    corr = np.corrcoef(trigger, agency_score)[0, 1]
    logger.info(f"Initial trigger‑agency correlation: {corr:.4f}")

    attempts = 0
    while abs(corr) >= CORRELATION_THRESHOLD and attempts < 100:
        trigger = rng.exponential(scale=1.0, size=n_samples)
        trigger = 100 * (trigger - trigger.min()) / (trigger.max() - trigger.min())
        corr = np.corrcoef(trigger, agency_score)[0, 1]
        attempts += 1
        logger.debug(f"Regeneration attempt {attempts}, corr={corr:.4f}")

    if abs(corr) >= CORRELATION_THRESHOLD:
        raise RuntimeError(
            f"Failed to achieve independence after {attempts} attempts "
            f"(final |corr|={abs(corr):.4f})"
        )

    logger.info(
        f"Independence verified: |corr|={abs(corr):.4f} < {CORRELATION_THRESHOLD}"
    )

    # ------------------------------------------------------------------
    # 4. Assemble DataFrame
    # ------------------------------------------------------------------
    participant_ids = [f"P{str(i).zfill(4)}" for i in range(n_samples)]

    df = pd.DataFrame({
        "participant_id": participant_ids,
        "latency": np.round(latency, 2),
        "smoothness": np.round(smoothness, 4),
        "lead_time": np.round(lead_time, 2),
        "agency_score": np.round(agency_score, 2),
        "user_response_trigger": np.round(trigger, 2),
    })

    return df

def main():
    """
    Main entry point for T003.

    Steps:
    1. Load ``download_status.json``.
    2. If status == \"invalid\", abort (SystemExit 1).
    3. If status == \"unavailable\", generate synthetic data,
       write ``data/raw/synthetic_data.csv`` and update the status file
       with ``use_synthetic: true`` (and optionally ``status: synthetic``).
    4. If status == \"success\", do nothing.
    """
    status_path = PROJECT_ROOT / "data" / "raw" / "download_status.json"
    output_path = PROJECT_ROOT / "data" / "raw" / "synthetic_data.csv"

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    try:
        status = check_download_status(status_path)
    except SystemExit:
        # Propagate the exit code (invalid instrument)
        raise
    except FileNotFoundError:
        logger.warning(
            "download_status.json missing – assuming 'unavailable' for fallback."
        )
        status = "unavailable"

    if status == "success":
        logger.info("Real data present – synthetic generation skipped.")
        return

    if status == "unavailable":
        logger.info("Real data unavailable – generating synthetic dataset.")
        df = generate_synthetic_data()

        # Write CSV
        df.to_csv(output_path, index=False)
        logger.info(f"Synthetic data written to {output_path}")

        # Update status JSON
        _update_status(
            status_path,
            {
                "use_synthetic": True,
                "status": "synthetic",
            },
        )
        return

    logger.error(f"Unexpected status value: {status}")
    sys.exit(1)

if __name__ == "__main__":
    main()
