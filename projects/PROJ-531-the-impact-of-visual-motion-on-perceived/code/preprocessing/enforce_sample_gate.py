"""
Task T016b: Enforce N>=80 Gate

Reads the modeling configuration generated by T016.
If the abort_flag is set (indicating N < 80), the script exits with code 1
and a specific error message, preventing downstream modeling tasks from running.
"""
import json
import sys
from pathlib import Path

# Constants for paths
CONFIG_PATH = Path("data/processed/modeling_config.json")
GATE_ERROR_MSG = "Analysis aborted: Insufficient sample size (N < 80)"


def enforce_sample_gate(config_path: Path = CONFIG_PATH) -> bool:
    """
    Reads the modeling config and enforces the sample size gate.

    Args:
        config_path: Path to the modeling_config.json file.

    Returns:
        True if the gate passes (N >= 80).
        Raises SystemExit if the gate fails.
    """
    if not config_path.exists():
        raise FileNotFoundError(
            f"Config file not found: {config_path}. "
            "Task T016 (Power Analysis) must run before this task."
        )

    try:
        with open(config_path, 'r', encoding='utf-8') as f:
            config = json.load(f)
    except json.JSONDecodeError as e:
        raise ValueError(f"Invalid JSON in config file {config_path}: {e}")

    abort_flag = config.get('abort_flag', False)
    n_samples = config.get('n_samples', 0)

    if abort_flag:
        print(f"ERROR: {GATE_ERROR_MSG}", file=sys.stderr)
        print(f"Current sample size detected: N={n_samples}", file=sys.stderr)
        sys.exit(1)

    print(f"Sample size gate passed. N={n_samples} >= 80.")
    return True


def main():
    """Entry point for the script."""
    try:
        enforce_sample_gate()
    except FileNotFoundError as e:
        print(f"CRITICAL ERROR: {e}", file=sys.stderr)
        sys.exit(1)
    except ValueError as e:
        print(f"CRITICAL ERROR: {e}", file=sys.stderr)
        sys.exit(1)
    except SystemExit:
        # Re-raise SystemExit to ensure the process terminates with the correct code
        raise
    except Exception as e:
        print(f"UNEXPECTED ERROR: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()