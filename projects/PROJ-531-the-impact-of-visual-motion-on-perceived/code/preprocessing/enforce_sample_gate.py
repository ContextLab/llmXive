import json
import sys
from pathlib import Path

def enforce_sample_gate():
    """
    Reads the modeling config generated by T016.
    If abort_flag is true, raises SystemExit(1) with the specific error message.
    Otherwise, prints success and exits 0.
    """
    config_path = Path("data/processed/modeling_config.json")
    
    if not config_path.exists():
        print("ERROR: Modeling config file not found at data/processed/modeling_config.json", file=sys.stderr)
        print("Run T016 (power analysis) before T016b.", file=sys.stderr)
        sys.exit(1)

    try:
        with open(config_path, 'r') as f:
            config = json.load(f)
    except json.JSONDecodeError as e:
        print(f"ERROR: Failed to parse modeling config: {e}", file=sys.stderr)
        sys.exit(1)

    abort_flag = config.get('abort_flag', False)
    n_samples = config.get('n_samples', 0)

    if abort_flag:
        print(f"Analysis aborted: Insufficient sample size (N < 80). Current N: {n_samples}", file=sys.stderr)
        sys.exit(1)
    
    print(f"Sample size gate passed. N = {n_samples} (>= 80). Proceeding to modeling.")
    return True

def main():
    enforce_sample_gate()

if __name__ == "__main__":
    main()
