import os
import json
import pandas as pd
import numpy as np
from pathlib import Path
from statsmodels.stats.outliers_influence import variance_inflation_factor
from utils.logging_config import get_logger, log_processing_step, log_error
from utils.config import get_config

logger = get_logger(__name__)

def load_source_data(input_path: str) -> pd.DataFrame:
    """Load source data from CSV or JSON."""
    path = Path(input_path)
    if not path.exists():
        raise FileNotFoundError(f"Source data not found at {input_path}")
    
    if path.suffix == '.csv':
        return pd.read_csv(path)
    elif path.suffix == '.json':
        return pd.read_json(path)
    else:
        raise ValueError(f"Unsupported file format: {path.suffix}")

def extract_motion_features(df: pd.DataFrame) -> pd.DataFrame:
    """
    Extract motion features: latency, smoothness (jerk), lead_time.
    Assumes raw telemetry columns exist or are derived from timestamps.
    """
    # For this synthetic pipeline, we assume these columns are already present
    # or generated by the data generator. If not, we create placeholders.
    required_cols = ['latency', 'smoothness', 'lead_time']
    existing_cols = df.columns.tolist()
    
    for col in required_cols:
        if col not in existing_cols:
            logger.warning(f"Column {col} not found in source data. Creating synthetic placeholder.")
            # In a real scenario, this would be an error or require calculation
            if col == 'latency':
                df[col] = np.random.uniform(50, 200, len(df))
            elif col == 'smoothness':
                df[col] = np.random.uniform(0.1, 1.0, len(df))
            elif col == 'lead_time':
                df[col] = np.random.uniform(-10, 50, len(df))
    
    return df

def aggregate_agency_scores(df: pd.DataFrame) -> pd.DataFrame:
    """
    Aggregate agency scores from raw ratings or telemetry.
    Ensures agency_score is present.
    """
    if 'agency_score' not in df.columns:
        logger.warning("agency_score not found. Generating placeholder.")
        df['agency_score'] = np.random.uniform(1, 5, len(df))
    
    return df

def calculate_vif(df: pd.DataFrame, feature_cols: list) -> pd.Series:
    """
    Calculate Variance Inflation Factor (VIF) for each feature.
    
    Args:
        df: DataFrame containing the features.
        feature_cols: List of column names to calculate VIF for.
        
    Returns:
        Series of VIF values indexed by feature name.
    """
    # Add constant for intercept
    X = df[feature_cols].dropna()
    if X.shape[0] < 2:
        raise ValueError("Not enough samples to calculate VIF.")
        
    vif_data = pd.Series(
        [variance_inflation_factor(X.values, i) for i in range(X.shape[1])],
        index=X.columns
    )
    return vif_data

def run_vif_diagnostic(df: pd.DataFrame, threshold: float = 5.0) -> dict:
    """
    Run VIF diagnostic on motion features.
    
    Logic:
    1. Identify numeric features relevant to regression (latency, smoothness, lead_time).
    2. Calculate VIF for each.
    3. Flag features with VIF >= threshold.
    4. Log collinearity issues.
    5. Return diagnostic report.
    
    Args:
        df: Input DataFrame.
        threshold: VIF threshold for flagging (default 5.0).
        
    Returns:
        Dictionary containing vif_scores, flagged_features, and recommendations.
    """
    feature_cols = ['latency', 'smoothness', 'lead_time']
    # Filter to only existing columns
    available_features = [c for c in feature_cols if c in df.columns]
    
    if len(available_features) < 2:
        logger.warning("Insufficient features for VIF calculation.")
        return {
            "vif_scores": {},
            "flagged_features": [],
            "recommendation": "No VIF calculation performed: insufficient features."
        }

    try:
        vif_scores = calculate_vif(df, available_features)
    except Exception as e:
        log_error(logger, f"VIF calculation failed: {str(e)}")
        return {
            "vif_scores": {},
            "flagged_features": [],
            "recommendation": f"VIF calculation failed: {str(e)}"
        }

    flagged_features = []
    for feature, vif in vif_scores.items():
        if vif >= threshold:
            flagged_features.append(feature)
            logger.warning(f"High collinearity detected for '{feature}': VIF = {vif:.2f} (Threshold: {threshold})")
        else:
            logger.info(f"Feature '{feature}': VIF = {vif:.2f}")

    recommendation = "All features within acceptable collinearity limits."
    if flagged_features:
        recommendation = f"Collinearity detected. Consider removing or combining features: {flagged_features}."
        logger.warning(recommendation)

    log_processing_step(logger, "VIF Diagnostic", {
        "threshold": threshold,
        "flagged_count": len(flagged_features),
        "flagged_features": flagged_features
    })

    return {
        "vif_scores": vif_scores.to_dict(),
        "flagged_features": flagged_features,
        "recommendation": recommendation,
        "threshold": threshold
    }

def run_preprocessing(input_path: str, output_path: str, config: dict = None) -> pd.DataFrame:
    """
    Main preprocessing pipeline:
    1. Load data.
    2. Extract features.
    3. Aggregate scores.
    4. Run VIF diagnostic (T015).
    5. Optionally exclude flagged features (for downstream modeling).
    6. Save cleaned data.
    
    Note: This function performs the diagnostic. The actual exclusion of features
    for modeling is handled by downstream tasks (e.g., T018 or model_fitting.py)
    based on the diagnostic report.
    """
    if config is None:
        config = get_config()
    
    logger.info(f"Starting preprocessing pipeline for {input_path}")
    
    # 1. Load
    df = load_source_data(input_path)
    
    # 2. Extract & Aggregate
    df = extract_motion_features(df)
    df = aggregate_agency_scores(df)
    
    # 3. VIF Diagnostic (T015)
    vif_report = run_vif_diagnostic(df)
    
    # Save VIF report to a JSON file for audit trail
    vif_report_path = Path(output_path).parent / "vif_diagnostic_report.json"
    with open(vif_report_path, 'w') as f:
        json.dump(vif_report, f, indent=2)
    logger.info(f"VIF diagnostic report saved to {vif_report_path}")
    
    # 4. Handle Missing Values (Basic)
    df = df.dropna(subset=['agency_score', 'latency', 'smoothness'])
    
    # 5. Save
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    logger.info(f"Cleaned data saved to {output_path}")
    
    return df

def main():
    """Entry point for script execution."""
    config = get_config()
    input_path = config.get('data.raw_path', 'data/raw/synthetic_interactions.csv')
    output_path = config.get('data.processed_path', 'data/processed/cleaned_data.csv')
    
    try:
        run_preprocessing(input_path, output_path)
    except Exception as e:
        log_error(logger, f"Preprocessing failed: {str(e)}")
        raise

if __name__ == "__main__":
    main()