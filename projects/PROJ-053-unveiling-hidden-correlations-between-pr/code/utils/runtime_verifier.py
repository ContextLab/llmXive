import os
import json
import logging
from config import get_results_dir, get_time_limit_seconds, get_logs_dir, ensure_directories

def setup_verifier_logger():
    """Setup a dedicated logger for runtime verification tasks."""
    logger = logging.getLogger('runtime_verifier')
    logger.setLevel(logging.INFO)
    
    # Avoid adding duplicate handlers if called multiple times
    if not logger.handlers:
        handler = logging.StreamHandler()
        formatter = logging.Formatter(
            '%(asctime)s - %(name)s - %(levelname)s - %(message)s'
        )
        handler.setFormatter(formatter)
        logger.addHandler(handler)
        
        # Also log to a file for persistent record
        log_dir = get_logs_dir()
        ensure_directories()
        log_file = os.path.join(log_dir, 'runtime_verification.log')
        file_handler = logging.FileHandler(log_file)
        file_handler.setFormatter(formatter)
        logger.addHandler(file_handler)
    
    return logger

def verify_runtime_limit():
    """
    Read total_runtime_seconds from results/metrics.json and compare
    against the configured TIME_LIMIT_SECONDS (6 hours).
    
    Logs:
      - "PASS: Runtime within 6-hour limit" if within limit.
      - "FAIL: Runtime exceeds limit" if over limit.
    
    This implements the explicit logging requirement for SC-005 / T041.
    """
    logger = setup_verifier_logger()
    
    # Get paths
    results_dir = get_results_dir()
    metrics_path = os.path.join(results_dir, 'metrics.json')
    
    # Read the metrics file generated by T040
    if not os.path.exists(metrics_path):
        logger.error("metrics.json not found at %s. T040 must run first.", metrics_path)
        return False
    
    try:
        with open(metrics_path, 'r') as f:
            metrics = json.load(f)
    except json.JSONDecodeError as e:
        logger.error("Failed to parse metrics.json: %s", e)
        return False
    
    # Extract runtime
    total_runtime = metrics.get('total_runtime_seconds')
    if total_runtime is None:
        logger.error("total_runtime_seconds not found in metrics.json. T040 must populate this.")
        return False
    
    # Get limit from config
    time_limit = get_time_limit_seconds()
    
    # Compare and log result
    if total_runtime < time_limit:
        logger.info("PASS: Runtime within 6-hour limit (%.2f s < %.2f s)", total_runtime, time_limit)
        return True
    else:
        logger.warning("FAIL: Runtime exceeds limit (%.2f s >= %.2f s)", total_runtime, time_limit)
        return False

def main():
    """Entry point for runtime verification script."""
    logger = setup_verifier_logger()
    logger.info("Starting runtime limit verification (Task T041)...")
    
    success = verify_runtime_limit()
    
    if success:
        logger.info("Verification complete: Runtime check passed.")
    else:
        logger.warning("Verification complete: Runtime check failed or metrics missing.")
    
    return 0 if success else 1

if __name__ == '__main__':
    import sys
    sys.exit(main())
