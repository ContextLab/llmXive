"""
Permutation Importance and Baseline Correlation Script
----------------------------------------------------
This script computes permutation importance scores for the trained
Gaussian Process Regression (GPR) model on the test set, saves the
importance ranking to ``results/permutation_importance.json`` and
calculates the Spearman rank correlation with a literature baseline
ranking located at ``data/literature_baseline_importance.json``.
The correlation coefficient is stored in ``results/metrics.json`` under
the key ``importance_correlation``.
The script is intended to be run as part of the analysis step:
    python code/analysis/importance.py
"""
import json
import logging
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr
from sklearn.inspection import permutation_importance

from config import (
    get_processed_data_dir,
    get_results_dir,
    get_logger,
)
from joblib import load as joblib_load

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def load_test_data() -> pd.DataFrame:
    """
    Load the processed test CSV generated by the preprocessing step.
    Returns a DataFrame containing both features and target columns.
    """
    processed_dir = Path(get_processed_data_dir())
    test_path = processed_dir / "test.csv"
    if not test_path.exists():
        raise FileNotFoundError(f"Test CSV not found at {test_path}")
    return pd.read_csv(test_path)

def identify_target_and_features(df: pd.DataFrame):
    """
    Determine the target column (the first of the known target list that
    exists) and the feature columns (all others).
    """
    target_candidates = ["yield_strength", "ductility"]
    target_cols = [c for c in target_candidates if c in df.columns]
    if not target_cols:
        raise ValueError("No target column found in test data.")
    target = target_cols[0]
    feature_cols = [c for c in df.columns if c != target]
    return target, feature_cols

def load_gpr_model():
    """
    Load the trained GPR model. The training step saves the model as a
    joblib file under ``results/model/gpr_model.joblib``.
    """
    model_path = Path(get_results_dir()) / "model" / "gpr_model.joblib"
    if not model_path.exists():
        raise FileNotFoundError(f"GPR model not found at {model_path}")
    return joblib_load(model_path)

def compute_permutation_importance(model, X: np.ndarray, y: np.ndarray, feature_names):
    """
    Compute permutation importance using scikit‑learn's utility.
    Returns a dictionary mapping feature name -> mean importance.
    """
    result = permutation_importance(
        model,
        X,
        y,
        n_repeats=10,
        random_state=42,
        scoring="neg_mean_squared_error",
    )
    importance_dict = {
        name: float(mean_imp)
        for name, mean_imp in zip(feature_names, result.importances_mean)
    }
    return importance_dict

def save_importance_json(importance_dict: dict):
    """
    Write the importance dictionary to ``results/permutation_importance.json``.
    """
    results_dir = Path(get_results_dir())
    results_dir.mkdir(parents=True, exist_ok=True)
    out_path = results_dir / "permutation_importance.json"
    with open(out_path, "w") as f:
        json.dump(importance_dict, f, indent=2)
    return out_path

def load_baseline_ranking():
    """
    Load the literature baseline importance ranking.
    Expected format (data/literature_baseline_importance.json):
    {
        "citation": "...",
        "ranking": [0.45, 0.30, 0.25],
        "features": ["laser_power", "scan_speed", "layer_thickness"]
    }
    Returns a dict mapping feature name -> score.
    """
    baseline_path = Path("data") / "literature_baseline_importance.json"
    if not baseline_path.exists():
        raise FileNotFoundError(f"Baseline importance file not found at {baseline_path}")
    with open(baseline_path, "r") as f:
        baseline = json.load(f)
    if "features" not in baseline or "ranking" not in baseline:
        raise ValueError("Baseline JSON must contain 'features' and 'ranking' keys.")
    return dict(zip(baseline["features"], baseline["ranking"]))

def compute_spearman_correlation(importance_dict: dict, baseline_dict: dict):
    """
    Compute Spearman rank correlation between the model's importance
    ranking and the baseline ranking. Both dictionaries must contain the
    same set of features.
    Returns the correlation coefficient (float). If the feature sets
    differ, the intersection is used.
    """
    common_features = set(importance_dict.keys()) & set(baseline_dict.keys())
    if not common_features:
        raise ValueError("No overlapping features between model importance and baseline.")
    model_scores = [importance_dict[f] for f in common_features]
    baseline_scores = [baseline_dict[f] for f in common_features]
    corr, _ = spearmanr(model_scores, baseline_scores)
    return float(corr)

def update_metrics_file(correlation: float):
    """
    Insert the ``importance_correlation`` field into
    ``results/metrics.json``. Existing fields are preserved.
    """
    metrics_path = Path(get_results_dir()) / "metrics.json"
    if not metrics_path.exists():
        raise FileNotFoundError(f"Metrics file not found at {metrics_path}")
    with open(metrics_path, "r") as f:
        metrics = json.load(f)

    metrics["importance_correlation"] = correlation

    with open(metrics_path, "w") as f:
        json.dump(metrics, f, indent=2)

# ----------------------------------------------------------------------
# Main orchestration
# ----------------------------------------------------------------------
def main():
    logger = get_logger("importance")
    logger.info("Starting permutation importance analysis...")

    # 1. Load data
    test_df = load_test_data()
    target_col, feature_cols = identify_target_and_features(test_df)
    X_test = test_df[feature_cols].values
    y_test = test_df[target_col].values
    logger.info(f"Test set loaded: {X_test.shape[0]} samples, {len(feature_cols)} features.")

    # 2. Load model
    model = load_gpr_model()
    logger.info("GPR model loaded successfully.")

    # 3. Compute permutation importance
    importance = compute_permutation_importance(model, X_test, y_test, feature_cols)
    logger.info("Permutation importance computed.")

    # 4. Save importance JSON
    importance_path = save_importance_json(importance)
    logger.info(f"Permutation importance saved to {importance_path}")

    # 5. Load baseline ranking and compute correlation
    baseline = load_baseline_ranking()
    corr = compute_spearman_correlation(importance, baseline)
    logger.info(f"Spearman correlation with baseline: {corr:.4f}")

    # 6. Update metrics.json
    update_metrics_file(corr)
    logger.info("Metrics file updated with importance correlation.")

    logger.info("Permutation importance analysis completed successfully.")

if __name__ == "__main__":
    main()
