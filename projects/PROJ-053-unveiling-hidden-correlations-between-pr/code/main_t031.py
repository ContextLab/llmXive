"""
Orchestration script for Task T031: Permutation Importance Correlation Analysis.
This script runs the analysis after the model (T026) and preprocessing (T016/T018) are complete.
"""
import os
import sys
import json
import logging
import pickle
from pathlib import Path

from config import (
    get_project_root,
    get_results_dir,
    get_models_dir,
    get_processed_data_dir,
    ensure_directories
)
from utils.importance_analyzer import run_correlation_analysis

def main():
    ensure_directories()
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(levelname)s - %(message)s',
        handlers=[
            logging.FileHandler(os.path.join(get_project_root(), "data", "processed", "t031_run.log")),
            logging.StreamHandler()
        ]
    )

    try:
        # 1. Load Model
        model_path = os.path.join(get_models_dir(), "gpr_model.pkl")
        if not os.path.exists(model_path):
            raise FileNotFoundError(f"Model file not found: {model_path}. Please run T026 first.")
        
        with open(model_path, 'rb') as f:
            model = pickle.load(f)
        logging.info(f"Loaded model from {model_path}")

        # 2. Load Test Data
        # These files should be generated by preprocess.py (T018)
        X_test_path = os.path.join(get_processed_data_dir(), "test_data_X.pkl")
        y_test_path = os.path.join(get_processed_data_dir(), "test_data_y.pkl")
        feature_names_path = os.path.join(get_processed_data_dir(), "feature_names.json")

        if not os.path.exists(X_test_path) or not os.path.exists(y_test_path) or not os.path.exists(feature_names_path):
            raise FileNotFoundError(
                f"Test data files not found. Expected:\n"
                f"  {X_test_path}\n"
                f"  {y_test_path}\n"
                f"  {feature_names_path}\n"
                f"Please run T018 (preprocess) first."
            )

        with open(X_test_path, 'rb') as f:
            X_test = pickle.load(f)
        with open(y_test_path, 'rb') as f:
            y_test = pickle.load(f)
        with open(feature_names_path, 'r') as f:
            feature_names = json.load(f)
        
        logging.info(f"Loaded test data: X shape {X_test.shape}, {len(feature_names)} features")

        # 3. Run Correlation Analysis
        logging.info("Running permutation importance correlation analysis...")
        analysis_results = run_correlation_analysis(model, X_test, y_test, feature_names)

        # 4. Save Results to metrics.json
        metrics_path = os.path.join(get_results_dir(), "metrics.json")
        existing_metrics = {}
        
        if os.path.exists(metrics_path):
            with open(metrics_path, 'r') as f:
                existing_metrics = json.load(f)
        
        existing_metrics["permutation_importance_analysis"] = analysis_results

        with open(metrics_path, 'w') as f:
            json.dump(existing_metrics, f, indent=2)
        
        logging.info(f"Analysis results saved to {metrics_path}")
        logging.info(f"Correlation Coefficient: {analysis_results.get('correlation_coefficient', 'N/A')}")

    except Exception as e:
        logging.error(f"Task T031 failed: {e}", exc_info=True)
        raise

if __name__ == "__main__":
    main()