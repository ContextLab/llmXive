"""
SchNet (Continuous-filter Convolutional Neural Network) implementation for
predicting molecular surface charge distribution.

This module implements the architecture described in:
"SchNet: A continuous-filter convolutional neural network for modeling quantum
interactions" (Schütt et al., 2017).

It inherits from torch.nn.Module and is designed to work with the MoleculeData
schema defined in code/data/dataset.py.
"""
from typing import Optional, Tuple

import torch
import torch.nn as nn
import torch.nn.functional as F
from torch_geometric.nn import MessagePassing
from torch_geometric.nn import global_mean_pool
from torch_geometric.utils import radius_graph

from utils import get_logger

logger = get_logger(__name__)


class GaussianSmearing(nn.Module):
    """
    Gaussian smearing (expansion) of inter-atomic distances.

    Converts scalar distances into a vector of features using a set of
    Gaussian basis functions. This allows the network to learn smooth
    functions of distance.
    """

    def __init__(
        self,
        start: float = 0.0,
        stop: float = 10.0,
        num_gaussians: int = 50
    ):
        """
        Initialize the Gaussian smearing layer.

        Args:
            start: Start of the distance range.
            stop: End of the distance range.
            num_gaussians: Number of Gaussian functions.
        """
        super().__init__()
        self.start = start
        self.stop = stop
        self.num_gaussians = num_gaussians

        # Create Gaussian centers and widths
        offset = torch.linspace(start, stop, num_gaussians)
        self.coeffs = 1.0 / (stop - start)  # Standard width factor
        self.register_buffer('offset', offset)

    def forward(self, dist: torch.Tensor) -> torch.Tensor:
        """
        Apply Gaussian smearing to input distances.

        Args:
            dist: Tensor of shape (E,) containing inter-atomic distances.

        Returns:
            Tensor of shape (E, num_gaussians).
        """
        # dist: (E,) -> (E, 1)
        dist = dist.unsqueeze(-1)
        # Calculate exp(-gamma * (d - offset)^2)
        # We use a fixed width for simplicity, matching standard SchNet implementations
        # where gamma is often set to 1.0 or derived from the spacing.
        # Here we implement a standard RBF: exp(-0.5 * ((x - center) / width)^2)
        # With width = (stop - start) / (num_gaussians - 1)
        width = (self.stop - self.start) / (self.num_gaussians - 1)
        diff = dist - self.offset
        return torch.exp(-0.5 * (diff / width) ** 2)


class ContinuousFilterConv(MessagePassing):
    """
    Continuous-filter convolutional layer.

    This layer updates node features based on messages from neighbors.
    The message is a product of the source node feature and a distance-dependent
    filter generated by the Gaussian smearing and a small MLP.
    """

    def __init__(
        self,
        num_filters: int,
        num_gaussians: int,
        num_interaction_blocks: int = 3
    ):
        """
        Initialize the convolution layer.

        Args:
            num_filters: Dimensionality of hidden node features.
            num_gaussians: Number of Gaussian basis functions (from distance).
        """
        super().__init__(aggr='add')  # Sum aggregation

        self.num_filters = num_filters
        self.num_gaussians = num_gaussians

        # Filter network: Maps distance features to interaction filters
        # Input: num_gaussians, Output: num_filters * num_filters
        self.filter_net = nn.Sequential(
            nn.Linear(num_gaussians, num_filters),
            nn.SiLU(),  # Swish activation
            nn.Linear(num_filters, num_filters * num_filters),
            nn.SiLU()
        )

        # Initialize weights
        self._init_weights()

    def _init_weights(self):
        """Initialize weights using Xavier uniform."""
        for m in self.filter_net:
            if isinstance(m, nn.Linear):
                nn.init.xavier_uniform_(m.weight)
                nn.init.zeros_(m.bias)

    def forward(
        self,
        x: torch.Tensor,
        edge_index: torch.Tensor,
        edge_attr: torch.Tensor
    ) -> torch.Tensor:
        """
        Forward pass of the continuous filter convolution.

        Args:
            x: Node features of shape (N, num_filters).
            edge_index: Edge index of shape (2, E).
            edge_attr: Distance features (Gaussian smeared) of shape (E, num_gaussians).

        Returns:
            Updated node features of shape (N, num_filters).
        """
        # Generate filters: (E, num_filters * num_filters)
        filters = self.filter_net(edge_attr)
        # Reshape to (E, num_filters, num_filters)
        filters = filters.view(-1, self.num_filters, self.num_filters)

        # Propagate: m_ij = x_j * filter_ij
        # x: (N, num_filters) -> (E, num_filters) for source nodes
        # We use the 'out' mapping for source features in the message function
        return self.propagate(edge_index, x=x, filters=filters)

    def message(self, x_j: torch.Tensor, filters: torch.Tensor) -> torch.Tensor:
        """
        Compute messages.

        Args:
            x_j: Source node features (E, num_filters).
            filters: Interaction filters (E, num_filters, num_filters).

        Returns:
            Messages of shape (E, num_filters).
        """
        # (E, num_filters) @ (E, num_filters, num_filters).transpose(-2, -1)
        # Result: (E, num_filters)
        # Note: torch.bmm expects (B, N, K) @ (B, K, M) -> (B, N, M)
        # Here we have (E, 1, num_filters) @ (E, num_filters, num_filters)
        x_j = x_j.unsqueeze(1)  # (E, 1, num_filters)
        messages = torch.bmm(x_j, filters).squeeze(1)
        return messages


class SchNetInteractionBlock(nn.Module):
    """
    A single interaction block consisting of two continuous filter convolutions.
    """

    def __init__(
        self,
        num_filters: int,
        num_gaussians: int
    ):
        super().__init__()
        self.conv1 = ContinuousFilterConv(num_filters, num_gaussians)
        self.conv2 = ContinuousFilterConv(num_filters, num_gaussians)

        # Activation and normalization
        self.act = nn.SiLU()
        self.norm1 = nn.LayerNorm(num_filters)
        self.norm2 = nn.LayerNorm(num_filters)

    def forward(
        self,
        x: torch.Tensor,
        edge_index: torch.Tensor,
        edge_attr: torch.Tensor
    ) -> torch.Tensor:
        """
        Forward pass of the interaction block.

        Args:
            x: Node features.
            edge_index: Edge index.
            edge_attr: Distance features.

        Returns:
            Updated node features.
        """
        # First convolution
        x1 = self.conv1(x, edge_index, edge_attr)
        x1 = self.norm1(x1)
        x1 = self.act(x1)

        # Second convolution
        x2 = self.conv2(x1, edge_index, edge_attr)
        x2 = self.norm2(x2)
        x2 = self.act(x2)

        return x + x2  # Residual connection


class SchNet(nn.Module):
    """
    SchNet architecture for predicting molecular properties (surface charges).

    This model takes atomic numbers and 3D coordinates as input and predicts
    a scalar charge for each atom.

    Attributes:
        num_atom_types: Number of unique atomic types (e.g., 9 for QM9).
        num_filters: Dimensionality of hidden layers.
        num_gaussians: Number of Gaussian basis functions.
        num_interaction_blocks: Number of interaction blocks.
    """

    def __init__(
        self,
        num_atom_types: int = 9,
        num_filters: int = 128,
        num_gaussians: int = 50,
        num_interaction_blocks: int = 3,
        max_radius: float = 10.0
    ):
        """
        Initialize the SchNet model.

        Args:
            num_atom_types: Number of unique atomic numbers in the dataset.
            num_filters: Dimensionality of hidden node features.
            num_gaussians: Number of Gaussian basis functions.
            num_interaction_blocks: Number of interaction blocks.
            max_radius: Maximum cutoff radius for graph construction (Angstroms).
        """
        super().__init__()
        self.num_atom_types = num_atom_types
        self.num_filters = num_filters
        self.num_gaussians = num_gaussians
        self.num_interaction_blocks = num_interaction_blocks
        self.max_radius = max_radius

        # Embedding layer for atomic numbers
        self.embedding = nn.Embedding(num_atom_types, num_filters)

        # Gaussian smearing for distances
        self.distance_expansion = GaussianSmearing(
            start=0.0,
            stop=max_radius,
            num_gaussians=num_gaussians
        )

        # Interaction blocks
        self.interaction_blocks = nn.ModuleList([
            SchNetInteractionBlock(num_filters, num_gaussians)
            for _ in range(num_interaction_blocks)
        ])

        # Output layer: Maps hidden features to 1D charge prediction per atom
        self.output_net = nn.Sequential(
            nn.Linear(num_filters, num_filters),
            nn.SiLU(),
            nn.Linear(num_filters, 1)
        )

        logger.info(f"Initialized SchNet with {num_interaction_blocks} interaction blocks")

    def forward(
        self,
        x: torch.Tensor,
        pos: torch.Tensor,
        edge_index: Optional[torch.Tensor] = None,
        batch: Optional[torch.Tensor] = None
    ) -> torch.Tensor:
        """
        Forward pass of the SchNet model.

        Args:
            x: Atomic numbers (LongTensor) of shape (N,).
            pos: 3D coordinates (FloatTensor) of shape (N, 3).
            edge_index: Optional pre-computed edge index. If None, computed from pos.
            batch: Optional batch vector for graph pooling (not used for atom-wise output).

        Returns:
            Predicted charges of shape (N, 1).
        """
        # 1. Embed atomic numbers
        h = self.embedding(x)  # (N, num_filters)

        # 2. Compute edge attributes (distances)
        if edge_index is None:
            # Construct graph based on distance cutoff
            # radius_graph returns edge_index of shape (2, E)
            edge_index = radius_graph(pos, r=self.max_radius, batch=batch)

        # Calculate distances
        row, col = edge_index
        dist = torch.norm(pos[row] - pos[col], dim=1)

        # Gaussian smearing of distances
        edge_attr = self.distance_expansion(dist)  # (E, num_gaussians)

        # 3. Interaction blocks
        for block in self.interaction_blocks:
            h = block(h, edge_index, edge_attr)

        # 4. Output layer (atom-wise prediction)
        charges = self.output_net(h)  # (N, 1)

        return charges

    def predict_batch(
        self,
        data: 'MoleculeData'
    ) -> torch.Tensor:
        """
        Convenience method to run forward pass on a MoleculeData object.

        Args:
            data: MoleculeData object containing x, pos, and optionally batch.

        Returns:
            Predicted charges of shape (num_atoms, 1).
        """
        # Ensure x is LongTensor for embedding
        if data.x.dtype != torch.long:
            data.x = data.x.long()

        return self.forward(data.x, data.pos, batch=data.batch)


def create_schnet_model(
    num_atom_types: int = 9,
    num_filters: int = 128,
    num_gaussians: int = 50,
    num_interaction_blocks: int = 3
) -> SchNet:
    """
    Factory function to create a SchNet model with specified hyperparameters.

    Args:
        num_atom_types: Number of unique atomic types.
        num_filters: Dimensionality of hidden layers.
        num_gaussians: Number of Gaussian basis functions.
        num_interaction_blocks: Number of interaction blocks.

    Returns:
        Initialized SchNet model.
    """
    return SchNet(
        num_atom_types=num_atom_types,
        num_filters=num_filters,
        num_gaussians=num_gaussians,
        num_interaction_blocks=num_interaction_blocks
    )