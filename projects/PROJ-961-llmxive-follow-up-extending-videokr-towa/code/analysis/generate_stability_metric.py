"""
Module to calculate and log the stability metric for the sensitivity analysis.

This script reads the sensitivity analysis results (thresholds, p-values, effect sizes),
counts the number of thresholds where the p-value is less than 0.05, and determines
if the "reasoning cliff" is robust (count >= 2).

It outputs a JSON file `data/processed/stability_metric.json` with the robustness status.
"""
import json
import logging
import sys
from pathlib import Path
from typing import List, Dict, Any

# Import from local utils for path handling
try:
    from utils.config import get_project_root, get_path, ensure_dir
except ImportError:
    # Fallback for direct execution or different import context
    import os
    def get_project_root():
        return Path(__file__).parent.parent.parent
    def get_path(base, sub):
        return Path(base) / sub
    def ensure_dir(p):
        p.mkdir(parents=True, exist_ok=True)

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def load_sensitivity_results(file_path: Path) -> List[Dict[str, Any]]:
    """
    Load the sensitivity results from the CSV file generated by T026a.
    
    Expected columns: threshold_hop, p_value, effect_size, is_significant
    """
    if not file_path.exists():
        raise FileNotFoundError(f"Sensitivity results file not found: {file_path}")
    
    results = []
    with open(file_path, 'r', encoding='utf-8') as f:
        import csv
        reader = csv.DictReader(f)
        for row in reader:
            results.append({
                'threshold_hop': int(row['threshold_hop']),
                'p_value': float(row['p_value']),
                'effect_size': float(row['effect_size']),
                'is_significant': row['is_significant'].lower() == 'true'
            })
    return results

def calculate_robustness(sensitivity_results: List[Dict[str, Any]], alpha: float = 0.05) -> Dict[str, Any]:
    """
    Calculate the robustness metric based on sensitivity results.
    
    Logic:
    1. Count thresholds where p_value < alpha.
    2. If count >= 2, status is 'PASS', else 'FAIL'.
    
    Args:
        sensitivity_results: List of dicts containing threshold analysis results.
        alpha: Significance threshold (default 0.05).
        
    Returns:
        Dict containing count, status, and details.
    """
    significant_count = 0
    significant_thresholds = []
    
    for result in sensitivity_results:
        if result['p_value'] < alpha:
            significant_count += 1
            significant_thresholds.append(result['threshold_hop'])
    
    # Robustness condition: >= 2 significant thresholds
    robustness_status = 'PASS' if significant_count >= 2 else 'FAIL'
    
    return {
        'significant_count': significant_count,
        'total_thresholds': len(sensitivity_results),
        'thresholds_tested': [r['threshold_hop'] for r in sensitivity_results],
        'significant_thresholds': significant_thresholds,
        'robustness_status': robustness_status,
        'alpha': alpha
    }

def save_stability_metric(metric_data: Dict[str, Any], output_path: Path) -> None:
    """
    Save the stability metric to a JSON file.
    
    Args:
        metric_data: Dictionary containing the calculated metrics.
        output_path: Path to the output JSON file.
    """
    ensure_dir(output_path.parent)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(metric_data, f, indent=2)
    logger.info(f"Stability metric saved to: {output_path}")

def main() -> None:
    """Main entry point for the stability metric generation."""
    project_root = get_project_root()
    
    # Define paths
    sensitivity_csv_path = get_path(project_root, 'data/processed/sensitivity_thresholds.csv')
    output_json_path = get_path(project_root, 'data/processed/stability_metric.json')
    
    logger.info(f"Loading sensitivity results from: {sensitivity_csv_path}")
    
    try:
        results = load_sensitivity_results(sensitivity_csv_path)
    except FileNotFoundError as e:
        logger.error(str(e))
        logger.error("Cannot proceed with stability calculation. Ensure T026a (sensitivity_thresholds.csv) has been run.")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Error loading sensitivity results: {e}")
        sys.exit(1)
    
    if not results:
        logger.error("Sensitivity results file is empty. Cannot calculate robustness.")
        sys.exit(1)
    
    logger.info(f"Loaded {len(results)} threshold results.")
    
    # Calculate robustness
    metric_data = calculate_robustness(results)
    
    # Log summary
    logger.info(f"Significant thresholds found: {metric_data['significant_count']}")
    logger.info(f"Thresholds tested: {metric_data['thresholds_tested']}")
    logger.info(f"Significant thresholds: {metric_data['significant_thresholds']}")
    logger.info(f"Robustness Status: {metric_data['robustness_status']}")
    
    # Save output
    save_stability_metric(metric_data, output_json_path)
    
    logger.info("Stability metric calculation complete.")

if __name__ == '__main__':
    main()