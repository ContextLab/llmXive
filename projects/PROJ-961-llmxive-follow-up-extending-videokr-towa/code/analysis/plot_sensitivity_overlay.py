def load_sensitivity_results() -> list:
    """
    Load the sensitivity results from the CSV generated by T026a.
    Expected columns: threshold_hop, p_value, effect_size, is_significant
    """
    csv_path = get_path("data/processed/sensitivity_thresholds.csv")
    if not csv_path.exists():
        raise FileNotFoundError(
            f"Sensitivity results file not found: {csv_path}. "
            "Please run T026a first."
        )

    results = []
    with open(csv_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            results.append({
                'threshold_hop': int(row['threshold_hop']),
                'p_value': float(row['p_value']),
                'effect_size': float(row['effect_size']),
                'is_significant': row['is_significant'].lower() == 'true'
            })
    return results

def load_annotated_data() -> list:
    """
    Load the annotated dataset to calculate accuracy by hop count.
    Returns a list of dicts with 'chain_length' and 'correctness'.
    """
    csv_path = get_path("data/processed/annotated_videokr.csv")
    if not csv_path.exists():
        raise FileNotFoundError(
            f"Annotated dataset not found: {csv_path}. "
            "Please run T013 first."
        )

    data = []
    with open(csv_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Skip unmapped/unresolvable if marked
            if row.get('chain_length') in ['unmapped', 'unresolvable', '']:
                continue
            try:
                data.append({
                    'chain_length': int(row['chain_length']),
                    'correctness': int(row['correctness']) if row.get('correctness') else 0
                })
            except ValueError:
                continue
    return data

def calculate_accuracy_by_hop(data: list, threshold_hop: int) -> dict:
    """
    Calculate accuracy for each hop count, grouped by the threshold definition.
    
    Logic:
    - For a given threshold_hop (e.g., 2), we treat hops >= threshold_hop as a single bin "high".
    - However, the task asks for an "overlay plot" of accuracy curves for different threshold definitions.
    - This implies plotting the accuracy of the "critical" region (hops >= threshold) vs the hop count itself?
    - No, standard interpretation: Plot Accuracy (Y) vs Hop Count (X).
    - Then, for each threshold definition (2, 3, 4), we highlight or annotate the "cliff" point.
    - Alternatively, the "curve" might represent the cumulative accuracy drop or the accuracy of the bin defined by the threshold.
    
    Re-reading T027a: "overlaying accuracy curves for different threshold definitions (2, 3, 4 hops)".
    This likely means:
    1. Calculate the accuracy for each specific hop count (1, 2, 3, 4, 5...).
    2. Plot these points as a line/scatter.
    3. Overlay multiple lines? No, the data is the same.
    4. Perhaps it means plotting the "Accuracy of the High-Bin" vs "Threshold"? No, that's a single point per threshold.
    
    Correct Interpretation for "Overlay Plot" in Sensitivity Analysis:
    The "curve" is the accuracy trend. The "threshold definition" changes where we draw the line for the "cliff".
    We will plot the Accuracy vs Hop Count (the raw trend).
    Then, for each threshold (2, 3, 4), we will draw a vertical line or a shaded region indicating the "cliff" start,
    and perhaps plot the "High Bin Accuracy" as a horizontal line segment starting from that threshold.
    
    Let's refine: The task asks for "accuracy curves for different threshold definitions".
    This might imply re-binning the data for each threshold and plotting the resulting "step function" or "piecewise" accuracy.
    - Threshold 2: Accuracy is X for hops < 2, Y for hops >= 2. (Step function)
    - Threshold 3: Accuracy is X for hops < 3, Y for hops >= 3.
    - Threshold 4: Accuracy is X for hops < 4, Y for hops >= 4.
    
    This creates a set of step functions overlayed on the same plot. This visualizes how the "cliff" location shifts the low-accuracy region.
    
    Implementation:
    1. Calculate mean accuracy for each raw hop count (1, 2, 3, 4, 5).
    2. For each threshold T in [2, 3, 4]:
       - Define two bins: "Low" (hops < T) and "High" (hops >= T).
       - Calculate mean accuracy for "Low" and "High".
       - Create a step function: Y = mean_acc_low for x < T, Y = mean_acc_high for x >= T.
       - Plot this step function.
    3. Also plot the raw data points (mean accuracy per hop) as a reference.
    """
    if not data:
        return {}
    
    # Group by raw hop count
    hop_accuracies = defaultdict(list)
    for row in data:
        hop = row['chain_length']
        hop_accuracies[hop].append(row['correctness'])
    
    # Calculate mean accuracy per raw hop
    mean_acc_per_hop = {}
    for hop, accs in hop_accuracies.items():
        mean_acc_per_hop[hop] = sum(accs) / len(accs)
    
    # Calculate accuracy for the specific threshold definition
    # Bin 1: hops < threshold
    # Bin 2: hops >= threshold
    low_accs = []
    high_accs = []
    
    for row in data:
        hop = row['chain_length']
        if hop < threshold_hop:
            low_accs.append(row['correctness'])
        else:
            high_accs.append(row['correctness'])
    
    acc_low = sum(low_accs) / len(low_accs) if low_accs else 0.0
    acc_high = sum(high_accs) / len(high_accs) if high_accs else 0.0
    
    return {
        'threshold': threshold_hop,
        'acc_low': acc_low,
        'acc_high': acc_high,
        'raw_means': mean_acc_per_hop
    }

def plot_sensitivity_overlay(output_path: Path, results: list, data: list):
    """
    Generate the overlay plot.
    """
    plt.style.use('seaborn-v0_8-whitegrid')
    fig, ax = plt.subplots(figsize=(10, 6))
    
    # Define thresholds to plot (2, 3, 4)
    thresholds = [2, 3, 4]
    colors = ['#1f77b4', '#ff7f0e', '#2ca02c']  # Blue, Orange, Green
    labels = [f"Threshold = {t} hops" for t in thresholds]
    
    # Plot raw data points (mean accuracy per hop) as a reference
    # Collect all unique hops
    all_hops = sorted(set(row['chain_length'] for row in data))
    raw_means = {}
    for row in data:
        h = row['chain_length']
        if h not in raw_means:
            raw_means[h] = []
        raw_means[h].append(row['correctness'])
    
    raw_x = []
    raw_y = []
    for h in all_hops:
        raw_x.append(h)
        raw_y.append(sum(raw_means[h]) / len(raw_means[h]))
    
    ax.scatter(raw_x, raw_y, color='gray', alpha=0.5, label='Raw Mean Accuracy', zorder=1)
    ax.plot(raw_x, raw_y, color='gray', linestyle='--', alpha=0.3, zorder=0)
    
    # Plot step functions for each threshold
    for t, color, label in zip(thresholds, colors, labels):
        # Calculate step values
        # We need to cover the range of hops
        min_hop = min(all_hops)
        max_hop = max(all_hops)
        
        # Calculate accuracy for this threshold
        step_data = calculate_accuracy_by_hop(data, t)
        acc_low = step_data['acc_low']
        acc_high = step_data['acc_high']
        
        # Create x and y for step plot
        # Step starts at t. 
        # x: [min_hop, t, t, max_hop] -> y: [acc_low, acc_low, acc_high, acc_high]
        # Actually, matplotlib's step function 'where=mid' or 'pre' works well.
        # Let's construct points manually for clarity
        x_step = [min_hop, t, t, max_hop]
        y_step = [acc_low, acc_low, acc_high, acc_high]
        
        ax.step(x_step, y_step, where='pre', color=color, linewidth=2, label=label, zorder=2)
        
        # Annotate the cliff
        ax.axvline(x=t, color=color, linestyle=':', alpha=0.5, zorder=1)
        ax.text(t + 0.1, acc_high, f'Cliff @ {t}', color=color, fontsize=9, fontweight='bold')

    ax.set_xlabel('Chain Length (Hops)', fontsize=12)
    ax.set_ylabel('Accuracy', fontsize=12)
    ax.set_title('Sensitivity Analysis: Accuracy Curves for Different Threshold Definitions', fontsize=14)
    ax.legend(loc='lower left')
    ax.set_ylim(0, 1.05)
    ax.set_xticks(all_hops)
    
    plt.tight_layout()
    plt.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close()
    logger.info(f"Plot saved to {output_path}")

