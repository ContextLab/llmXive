"""
T014c: Validate Exclusions
Verifies artifacts/exclusion_report.json exists and exclusion count < 0.1%.
Verifies artifacts/memory_adjustment.log if applicable.
Depends on T014a.
"""
import os
import sys
import json
import logging
from typing import Dict, Any, Optional

# Import config for paths
from config import get_config, ensure_directories

# Import logging utilities
from utils.logging_utils import setup_logging, log_metric, flush_metrics, log_execution_summary

def setup_script_logging() -> logging.Logger:
    """Initialize logging for the script."""
    logger = setup_logging("validate_exclusions")
    return logger

def load_exclusion_report(logger: logging.Logger) -> Optional[Dict[str, Any]]:
    """
    Load the exclusion report generated by T014a.
    Returns None if file does not exist or is invalid.
    """
    config = get_config()
    report_path = os.path.join(config["artifacts_dir"], "exclusion_report.json")
    
    if not os.path.exists(report_path):
        logger.error(f"Exclusion report not found at {report_path}. "
                     f"Has T014a (preprocess_graphs) run successfully?")
        return None

    try:
        with open(report_path, 'r') as f:
            data = json.load(f)
        logger.info(f"Successfully loaded exclusion report from {report_path}")
        return data
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse exclusion report JSON: {e}")
        return None
    except Exception as e:
        logger.error(f"Unexpected error loading exclusion report: {e}")
        return None

def load_memory_log(logger: logging.Logger) -> Optional[str]:
    """
    Load the memory adjustment log if it exists.
    """
    config = get_config()
    log_path = os.path.join(config["artifacts_dir"], "memory_adjustment.log")
    
    if not os.path.exists(log_path):
        logger.warning(f"Memory adjustment log not found at {log_path}. "
                       f"This is optional; T014a might not have needed adjustments.")
        return None

    try:
        with open(log_path, 'r') as f:
            content = f.read()
        logger.info(f"Successfully loaded memory adjustment log from {log_path}")
        return content
    except Exception as e:
        logger.error(f"Failed to read memory adjustment log: {e}")
        return None

def validate_exclusion_threshold(report: Dict[str, Any], logger: logging.Logger) -> bool:
    """
    Validate that the exclusion count is < 0.1%.
    """
    if "exclusion_count" not in report:
        logger.error("Exclusion report missing 'exclusion_count' key.")
        return False
    
    if "total_molecules" not in report:
        logger.error("Exclusion report missing 'total_molecules' key.")
        return False

    excluded = report["exclusion_count"]
    total = report["total_molecules"]

    if total == 0:
        logger.error("Total molecules is 0; cannot calculate exclusion percentage.")
        return False

    percentage = (excluded / total) * 100
    threshold = 0.1

    logger.info(f"Exclusion Stats: {excluded} excluded out of {total} total "
                f"({percentage:.4f}%)")

    if percentage >= threshold:
        logger.error(f"CRITICAL: Exclusion rate ({percentage:.4f}%) exceeds threshold ({threshold}%).")
        logger.error("Data quality issue detected. Failing validation.")
        return False
    
    logger.info(f"SUCCESS: Exclusion rate ({percentage:.4f}%) is within acceptable limits (< {threshold}%).")
    return True

def validate_memory_log(log_content: Optional[str], logger: logging.Logger) -> bool:
    """
    Validate the memory log if it exists.
    Currently just checks that if it exists, it is not empty.
    """
    if log_content is None:
        return True  # Optional file
    
    if not log_content.strip():
        logger.warning("Memory adjustment log exists but is empty.")
        return False
    
    logger.info("Memory adjustment log is present and non-empty.")
    return True

def main():
    """Main entry point for T014c."""
    logger = setup_script_logging()
    logger.info("Starting T014c: Validate Exclusions")

    # Ensure directories exist (though we are reading, not writing)
    config = get_config()
    ensure_directories([config["artifacts_dir"]])

    # 1. Load Exclusion Report
    report = load_exclusion_report(logger)
    if report is None:
        logger.error("Validation FAILED: Could not load exclusion report.")
        log_execution_summary(logger, "T014c", "FAILED", "Missing exclusion report")
        sys.exit(1)

    # 2. Validate Exclusion Threshold
    threshold_ok = validate_exclusion_threshold(report, logger)
    if not threshold_ok:
        log_execution_summary(logger, "T014c", "FAILED", "Exclusion rate too high")
        sys.exit(1)

    # 3. Load and Validate Memory Log (Optional)
    memory_log = load_memory_log(logger)
    memory_ok = validate_memory_log(memory_log, logger)
    if not memory_ok:
        # This is a warning level failure, but strictly speaking the task 
        # says "Verify ... if applicable". If applicable (exists), it must be valid.
        # We will treat an empty log as a failure of the log generation step, 
        # but not necessarily the whole pipeline if the exclusion check passed.
        # However, to be strict: if the file exists, it should have content.
        logger.warning("Memory log validation failed (empty file).")
    
    # 4. Final Summary
    log_execution_summary(logger, "T014c", "PASSED", "Exclusion rate valid")
    logger.info("T014c completed successfully.")
    return 0

if __name__ == "__main__":
    sys.exit(main())