import os
import json
import hashlib
import logging
from typing import Dict, Any, Optional
from config import get_config

def calculate_sha256(file_path: str) -> str:
    """Calculate the SHA-256 hash of a file."""
    sha256_hash = hashlib.sha256()
    with open(file_path, "rb") as f:
        for byte_block in iter(lambda: f.read(4096), b""):
            sha256_hash.update(byte_block)
    return sha256_hash.hexdigest()

def load_checksums(checksums_path: str) -> Dict[str, Any]:
    """Load the checksums manifest from a JSON file."""
    if not os.path.exists(checksums_path):
        raise FileNotFoundError(f"Checksums file not found: {checksums_path}")
    with open(checksums_path, "r") as f:
        return json.load(f)

def save_checksums(checksums_path: str, data: Dict[str, Any]) -> None:
    """Save the checksums manifest to a JSON file."""
    os.makedirs(os.path.dirname(checksums_path), exist_ok=True)
    with open(checksums_path, "w") as f:
        json.dump(data, f, indent=2)

def update_checksum_for_file(
    checksums_path: str,
    key: str,
    file_path: str,
    source_url: Optional[str] = None,
    version: Optional[str] = None
) -> None:
    """
    Calculate the SHA-256 hash of a file and update the checksums manifest.
    
    Args:
        checksums_path: Path to the checksums.json file.
        key: The key in the manifest to update (e.g., 'kinetic_dataset').
        file_path: Path to the file to hash.
        source_url: Optional source URL for the data.
        version: Optional version string for the data.
    """
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"File not found for hashing: {file_path}")
    
    checksums = load_checksums(checksums_path) if os.path.exists(checksums_path) else {}
    
    file_hash = calculate_sha256(file_path)
    
    checksums[key] = {
        "hash": file_hash,
        "source_url": source_url,
        "version": version,
        "file_path": file_path
    }
    
    save_checksums(checksums_path, checksums)
    logging.info(f"Updated checksum for {key}: {file_hash}")

def verify_checksum_against_manifest(
    checksums_path: str,
    key: str,
    file_path: str
) -> bool:
    """
    Verify the SHA-256 hash of a file against the manifest.
    
    Returns:
        True if the hash matches, False otherwise.
    """
    if not os.path.exists(file_path):
        logging.error(f"File not found for verification: {file_path}")
        return False
    
    if not os.path.exists(checksums_path):
        logging.error(f"Checksums manifest not found: {checksums_path}")
        return False
    
    checksums = load_checksums(checksums_path)
    if key not in checksums:
        logging.error(f"Key '{key}' not found in checksums manifest.")
        return False
    
    expected_hash = checksums[key].get("hash")
    if not expected_hash:
        logging.error(f"No hash found for key '{key}' in manifest.")
        return False
    
    actual_hash = calculate_sha256(file_path)
    
    if actual_hash == expected_hash:
        logging.info(f"Checksum verification passed for {key}: {actual_hash}")
        return True
    else:
        logging.error(f"Checksum verification FAILED for {key}.")
        logging.error(f"  Expected: {expected_hash}")
        logging.error(f"  Actual:   {actual_hash}")
        return False

def initialize_checksums_template(checksums_path: str) -> None:
    """
    Create an initial template for the checksums.json file if it doesn't exist.
    This is used by T009g to define the expected structure.
    """
    if os.path.exists(checksums_path):
        logging.info(f"Checksums file already exists: {checksums_path}")
        return
    
    template = {
        "reference_substructures": {
            "hash": "",
            "source_url": "local:generated",
            "version": "1.0",
            "file_path": "data/raw/reference_substructures_raw.csv",
            "description": "Curated static file of reference substructures (generated by T009a)."
        },
        "kinetic_dataset": {
            "hash": "",
            "source_url": "https://huggingface.co/datasets/kinetic-rates", 
            "version": "1.0",
            "file_path": "data/raw/kinetic_dataset_raw.csv",
            "description": "Real external kinetic dataset (fetched by T009d)."
        }
    }
    
    save_checksums(checksums_path, template)
    logging.info(f"Initialized checksums template at {checksums_path}")

def main():
    """
    Entry point for T009g: Initialize the checksums.json file with the expected structure.
    """
    config = get_config()
    checksums_path = os.path.join(config["data_dir"], "raw", "checksums.json")
    
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(levelname)s - %(message)s'
    )
    
    initialize_checksums_template(checksums_path)
    logging.info("Task T009g completed: Checksums manifest initialized.")

if __name__ == "__main__":
    main()
