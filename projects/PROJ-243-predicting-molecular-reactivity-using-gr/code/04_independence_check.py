"""
Independence Check for Model Prediction Errors.

Calculates pairwise Tanimoto similarity of prediction errors between models.
If errors are correlated (p < 0.05), logs a warning and recommends Wilcoxon
signed-rank test for sensitivity analysis.

Input:
    artifacts/predictions.json (generated by T023a)
Output:
    artifacts/independence_check_results.json
"""
import os
import sys
import json
import logging
from typing import Dict, List, Any, Optional, Tuple
import numpy as np
from scipy import stats

# Add project root to path for imports
project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
if project_root not in sys.path:
    sys.path.insert(0, project_root)

from config import get_config, ensure_directories
from utils.logging_utils import setup_logging, get_logger

def setup_script_logging() -> logging.Logger:
    """Initialize logging for this script."""
    ensure_directories()
    return setup_logging("04_independence_check")

def load_predictions(file_path: str) -> Dict[str, Any]:
    """Load predictions from JSON file."""
    logger = logging.getLogger(__name__)
    if not os.path.exists(file_path):
        logger.error(f"Predictions file not found: {file_path}")
        raise FileNotFoundError(f"Predictions file not found: {file_path}")
    
    with open(file_path, 'r') as f:
        return json.load(f)

def extract_errors(predictions: Dict[str, Any]) -> Dict[str, np.ndarray]:
    """
    Extract error vectors for each model.
    Error = predicted - true
    """
    logger = logging.getLogger(__name__)
    errors = {}
    
    # The predictions JSON structure is expected to be:
    # {
    #   "predictions": {
    #     "model_name": {
    #       "predicted": [...],
    #       "true": [...]
    #     },
    #     ...
    #   }
    # }
    
    if "predictions" not in predictions:
        logger.error("Invalid predictions format: missing 'predictions' key")
        raise ValueError("Invalid predictions format")
    
    pred_data = predictions["predictions"]
    
    for model_name, model_data in pred_data.items():
        if "predicted" not in model_data or "true" not in model_data:
            logger.error(f"Missing 'predicted' or 'true' for model {model_name}")
            continue
        
        predicted = np.array(model_data["predicted"])
        true = np.array(model_data["true"])
        
        if len(predicted) != len(true):
            logger.error(f"Mismatched lengths for model {model_name}")
            continue
        
        errors[model_name] = predicted - true
        
    if not errors:
        logger.error("No valid error vectors extracted")
        raise ValueError("No valid error vectors extracted")
        
    return errors

def tanimoto_similarity(vec1: np.ndarray, vec2: np.ndarray) -> float:
    """
    Calculate Tanimoto similarity between two error vectors.
    
    For continuous vectors, Tanimoto is defined as:
    T = (A . B) / (|A|^2 + |B|^2 - (A . B))
    
    Where A and B are the vectors.
    """
    dot_product = np.dot(vec1, vec2)
    norm_sq_a = np.dot(vec1, vec1)
    norm_sq_b = np.dot(vec2, vec2)
    
    denominator = norm_sq_a + norm_sq_b - dot_product
    
    if denominator == 0:
        return 0.0
        
    return float(dot_product / denominator)

def pearson_correlation(vec1: np.ndarray, vec2: np.ndarray) -> Tuple[float, float]:
    """
    Calculate Pearson correlation coefficient and p-value between two vectors.
    
    Returns:
        Tuple of (correlation_coefficient, p_value)
    """
    if len(vec1) < 3 or len(vec2) < 3:
        return 0.0, 1.0
        
    corr, p_value = stats.pearsonr(vec1, vec2)
    return float(corr), float(p_value)

def check_independence(errors: Dict[str, np.ndarray]) -> Dict[str, Any]:
    """
    Check pairwise independence of errors between models.
    
    Returns:
        Dictionary with correlation results and recommendations.
    """
    logger = logging.getLogger(__name__)
    model_names = list(errors.keys())
    n_models = len(model_names)
    
    if n_models < 2:
        logger.warning("Less than 2 models to compare")
        return {
            "correlation_coefficient": 0.0,
            "p_value": 1.0,
            "recommended_test": "t-test",
            "is_correlated": False,
            "pairwise_results": []
        }
    
    pairwise_results = []
    max_corr = 0.0
    max_p = 1.0
    correlated_pair = None
    
    # Compare all pairs
    for i in range(n_models):
        for j in range(i + 1, n_models):
            model_a = model_names[i]
            model_b = model_names[j]
            
            vec_a = errors[model_a]
            vec_b = errors[model_b]
            
            # Ensure same length
            min_len = min(len(vec_a), len(vec_b))
            vec_a = vec_a[:min_len]
            vec_b = vec_b[:min_len]
            
            corr, p_val = pearson_correlation(vec_a, vec_b)
            tanimoto = tanimoto_similarity(vec_a, vec_b)
            
            pairwise_results.append({
                "model_a": model_a,
                "model_b": model_b,
                "pearson_correlation": corr,
                "p_value": p_val,
                "tanimoto_similarity": tanimoto
            })
            
            logger.info(f"Correlation between {model_a} and {model_b}: r={corr:.4f}, p={p_val:.4f}, Tanimoto={tanimoto:.4f}")
            
            # Track maximum correlation for overall decision
            if abs(corr) > abs(max_corr):
                max_corr = corr
                max_p = p_val
                correlated_pair = (model_a, model_b)
    
    # Determine if errors are correlated (p < 0.05)
    is_correlated = max_p < 0.05
    
    recommendation = "wilcoxon" if is_correlated else "t-test"
    
    logger.warning(f"Max correlation: {max_corr:.4f} (p={max_p:.4f}) between {correlated_pair}")
    if is_correlated:
        logger.warning("Errors are correlated (p < 0.05). Recommended test: Wilcoxon signed-rank test.")
    else:
        logger.info("Errors appear independent (p >= 0.05). Recommended test: Paired t-test.")
    
    return {
        "correlation_coefficient": max_corr,
        "p_value": max_p,
        "recommended_test": recommendation,
        "is_correlated": is_correlated,
        "correlated_pair": correlated_pair,
        "pairwise_results": pairwise_results
    }

def save_results(results: Dict[str, Any], output_path: str) -> None:
    """Save results to JSON file."""
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    logging.getLogger(__name__).info(f"Results saved to {output_path}")

def main() -> None:
    """Main entry point for independence check."""
    logger = setup_script_logging()
    logger.info("Starting independence check for model prediction errors")
    
    config = get_config()
    predictions_path = os.path.join(config["paths"]["artifacts"], "predictions.json")
    output_path = os.path.join(config["paths"]["artifacts"], "independence_check_results.json")
    
    try:
        # Load predictions
        predictions = load_predictions(predictions_path)
        logger.info(f"Loaded predictions from {predictions_path}")
        
        # Extract errors
        errors = extract_errors(predictions)
        logger.info(f"Extracted errors for {len(errors)} models")
        
        # Check independence
        results = check_independence(errors)
        
        # Save results
        save_results(results, output_path)
        
        logger.info("Independence check completed successfully")
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Invalid data: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
