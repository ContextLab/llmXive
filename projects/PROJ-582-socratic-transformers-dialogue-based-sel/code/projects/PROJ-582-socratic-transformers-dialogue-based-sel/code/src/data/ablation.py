"""
Ablation Data Generator for Socratic Transformers Project.

This module implements the ablation data generation process as per FR-007.
It takes dialogue tuples generated by T014 (generate_dialogue.py) and replaces
the critique text with a neutral placeholder of equivalent token length.
This allows for isolation of the critique signal's effect on model performance.
"""

import json
import os
import sys
from pathlib import Path
from typing import List, Dict, Any, Optional
import tiktoken
from src.utils.config import get_config

# Default placeholder template for neutral text
NEUTRAL_PLACEHOLDER_TEMPLATE = "[NEUTRAL_CRITIQUE_PLACEHOLDER]"

def count_tokens(text: str, model_name: str = "cl100k_base") -> int:
    """
    Count the number of tokens in a given text string.

    Args:
        text: The input text to tokenize.
        model_name: The tokenizer model to use (default: cl100k_base for GPT-3.5/4).

    Returns:
        int: The number of tokens in the text.
    """
    if not text:
        return 0
    try:
        encoding = tiktoken.get_encoding(model_name)
        return len(encoding.encode(text))
    except Exception as e:
        # Fallback to a simple approximation if tiktoken fails
        # This should not happen in a properly configured environment
        print(f"Warning: tiktoken failed, using character-length approximation: {e}", file=sys.stderr)
        return len(text) // 4  # Rough approximation: 4 chars per token

def generate_neutral_placeholder(token_count: int, model_name: str = "cl100k_base") -> str:
    """
    Generate a neutral placeholder string that matches the token count of the original text.

    The placeholder consists of repeated neutral phrases designed to have no semantic
    content related to the specific critique, ensuring the ablation condition only
    removes the specific instructional signal while preserving sequence length.

    Args:
        token_count: The target number of tokens.
        model_name: The tokenizer model to use for generation.

    Returns:
        str: A neutral placeholder string with approximately `token_count` tokens.
    """
    if token_count <= 0:
        return ""

    # We will build the placeholder by repeating a neutral phrase
    # and adjusting to match the target token count as closely as possible.
    base_phrase = "The analysis provided no specific guidance."
    encoding = tiktoken.get_encoding(model_name)
    
    base_tokens = encoding.encode(base_phrase)
    base_token_count = len(base_tokens)
    
    if base_token_count == 0:
        return ""

    # Calculate how many full repetitions we need
    full_repeats = token_count // base_token_count
    remainder_tokens = token_count % base_token_count

    placeholder_parts = []
    
    # Add full repetitions
    for _ in range(full_repeats):
        placeholder_parts.append(base_phrase)
    
    # Add partial phrase if remainder exists
    if remainder_tokens > 0:
        # Find the shortest prefix of base_phrase that has at least remainder_tokens
        # or the longest prefix with exactly remainder_tokens.
        # Since we want equivalent length, we try to match as close as possible.
        for i in range(1, len(base_tokens) + 1):
            if len(base_tokens[:i]) >= remainder_tokens:
                partial_text = encoding.decode(base_tokens[:i])
                placeholder_parts.append(partial_text)
                break

    return " ".join(placeholder_parts)

def create_ablation_tuple(dialogue_tuple: Dict[str, Any], tokenizer_name: str = "cl100k_base") -> Dict[str, Any]:
    """
    Create an ablation tuple from a dialogue tuple by replacing the critique.

    The original critique is replaced with a neutral placeholder that has the
    same number of tokens. This preserves the sequence length for the model
    while removing the specific instructional content of the critique.

    Args:
        dialogue_tuple: A dictionary containing 'question', 'initial_answer',
                        'critique', and 'revised_answer'.
        tokenizer_name: The name of the tokenizer to use for token counting.

    Returns:
        Dict[str, Any]: A new dictionary with the same keys, but 'critique'
                        replaced by a neutral placeholder.
    """
    # Validate input
    required_keys = {'question', 'initial_answer', 'critique', 'revised_answer'}
    if not required_keys.issubset(dialogue_tuple.keys()):
        missing = required_keys - dialogue_tuple.keys()
        raise ValueError(f"Dialogue tuple missing required keys: {missing}")

    original_critique = dialogue_tuple['critique']
    
    # Count tokens in the original critique
    token_count = count_tokens(original_critique, tokenizer_name)
    
    # Generate neutral placeholder
    neutral_placeholder = generate_neutral_placeholder(token_count, tokenizer_name)
    
    # Create the ablation tuple
    ablation_tuple = {
        'question': dialogue_tuple['question'],
        'initial_answer': dialogue_tuple['initial_answer'],
        'critique': neutral_placeholder,
        'revised_answer': dialogue_tuple['revised_answer'],
        'ablation_metadata': {
            'original_critique_length': token_count,
            'placeholder_generated': True,
            'ablation_type': 'neutral_placeholder'
        }
    }
    
    return ablation_tuple

def generate_ablation_dataset(
    input_path: str,
    output_path: str,
    tokenizer_name: str = "cl100k_base",
    max_samples: Optional[int] = None
) -> int:
    """
    Generate an ablation dataset from a dialogue dataset.

    Reads dialogue tuples from the input JSONL file, creates ablation tuples
    by replacing critiques with neutral placeholders, and writes the results
    to the output JSONL file.

    Args:
        input_path: Path to the input JSONL file containing dialogue tuples.
        output_path: Path to the output JSONL file for ablation tuples.
        tokenizer_name: The name of the tokenizer to use for token counting.
        max_samples: Maximum number of samples to process (None for all).

    Returns:
        int: The number of samples processed.
    """
    input_file = Path(input_path)
    output_file = Path(output_path)
    
    if not input_file.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    # Ensure output directory exists
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    processed_count = 0
    
    with open(input_file, 'r', encoding='utf-8') as infile, \
         open(output_file, 'w', encoding='utf-8') as outfile:
         
         for line in infile:
             if max_samples is not None and processed_count >= max_samples:
                 break
             
             line = line.strip()
             if not line:
                 continue
             
             try:
                 dialogue_tuple = json.loads(line)
                 ablation_tuple = create_ablation_tuple(dialogue_tuple, tokenizer_name)
                 
                 outfile.write(json.dumps(ablation_tuple) + '\n')
                 processed_count += 1
                 
             except json.JSONDecodeError as e:
                 print(f"Warning: Skipping invalid JSON line: {e}", file=sys.stderr)
                 continue
             except ValueError as e:
                 print(f"Warning: Skipping invalid dialogue tuple: {e}", file=sys.stderr)
                 continue
    
    print(f"Ablation dataset generated: {processed_count} samples written to {output_path}")
    return processed_count

def main():
    """
    Main entry point for the ablation data generator script.
    
    Reads configuration from environment variables or uses defaults:
    - INPUT_PATH: Path to the dialogue dataset JSONL file
    - OUTPUT_PATH: Path for the ablation dataset JSONL file
    - TOKENIZER_NAME: Tokenizer model name (default: cl100k_base)
    - MAX_SAMPLES: Maximum samples to process (optional)
    """
    config = get_config()
    
    # Get paths from config or environment
    input_path = os.environ.get('ABLATION_INPUT_PATH', config.get('ablation_input_path', 'data/processed/dialogue_dataset.jsonl'))
    output_path = os.environ.get('ABLATION_OUTPUT_PATH', config.get('ablation_output_path', 'data/processed/ablation_dataset.jsonl'))
    tokenizer_name = os.environ.get('TOKENIZER_NAME', 'cl100k_base')
    
    max_samples = None
    if 'MAX_SAMPLES' in os.environ:
        try:
            max_samples = int(os.environ['MAX_SAMPLES'])
        except ValueError:
            print(f"Warning: Invalid MAX_SAMPLES value, ignoring.", file=sys.stderr)
    
    print(f"Starting ablation dataset generation...")
    print(f"Input: {input_path}")
    print(f"Output: {output_path}")
    print(f"Tokenizer: {tokenizer_name}")
    if max_samples:
        print(f"Max samples: {max_samples}")
    
    try:
        count = generate_ablation_dataset(
            input_path=input_path,
            output_path=output_path,
            tokenizer_name=tokenizer_name,
            max_samples=max_samples
        )
        print(f"Successfully processed {count} samples.")
    except Exception as e:
        print(f"Error during ablation generation: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == '__main__':
    main()
