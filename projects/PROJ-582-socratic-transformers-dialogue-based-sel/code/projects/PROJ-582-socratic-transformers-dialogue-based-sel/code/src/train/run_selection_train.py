# Local imports matching the project API surface
from src.utils.config import get_config, set_seed
from src.train.lora_config import get_4bit_quantization_config, create_lora_config_from_env
from src.train.train_loop import run_training_loop, setup_timeout, cancel_timeout, TimeoutError
from src.utils.logging import get_logger, log_event

# Configure logging
logger = get_logger("run_selection_train")
log_event("start", {"task": "T047a", "condition": "Selection"})

def load_dialogue_data(data_path: str):
    """
    Loads the dialogue tuples from the JSONL file generated by T014.
    Expects a JSONL file with keys: question, initial_answer, critique, revised_answer.
    """
    logger.info(f"Loading dialogue data from {data_path}")
    if not os.path.exists(data_path):
        raise FileNotFoundError(f"Dialogue data file not found: {data_path}")

    # Load as a custom dataset from JSONL
    dataset = load_dataset("json", data_files={"train": data_path}, split="train")
    logger.info(f"Loaded {len(dataset)} dialogue tuples")
    return dataset

def prepare_dataset(dataset, tokenizer, max_length: int = 512):
    """
    Formats the dialogue tuples for training.
    Constructs a prompt: "Question: {question}\nInitial Answer: {initial_answer}\nCritique: {critique}\nRevised Answer: {revised_answer}"
    """
    def format_example(examples):
        texts = []
        for q, ia, c, ra in zip(
            examples["question"],
            examples["initial_answer"],
            examples["critique"],
            examples["revised_answer"],
        ):
            text = f"Question: {q}\nInitial Answer: {ia}\nCritique: {c}\nRevised Answer: {ra}"
            texts.append(text)
        return {"text": texts}

    formatted = dataset.map(
        format_example,
        batched=True,
        remove_columns=dataset.column_names,
    )
    tokenized = formatted.map(
        lambda x: tokenizer(x["text"], truncation=True, max_length=max_length, padding="max_length"),
        batched=True,
    )
    tokenized.rename_column("input_ids", "labels")  # Standard format for causal LM
    tokenized.rename_column("attention_mask", "attention_mask")
    return tokenized

def main():
    config = get_config()
    set_seed(config.RANDOM_SEED)

    # Paths
    project_root = Path(__file__).resolve().parent.parent.parent.parent
    data_path = project_root / "data" / "processed" / "dialogue_tuples.jsonl"
    output_dir = project_root / "data" / "results"
    output_dir.mkdir(parents=True, exist_ok=True)
    checkpoint_path = output_dir / "checkpoint_selection.pt"

    logger.info(f"Output checkpoint will be saved to: {checkpoint_path}")

    # Load Model and Tokenizer
    logger.info(f"Loading base model: {config.BASE_MODEL_ID}")
    bnb_config = get_4bit_quantization_config()
    model = AutoModelForCausalLM.from_pretrained(
        config.BASE_MODEL_ID,
        quantization_config=bnb_config,
        device_map="auto",
        trust_remote_code=True,
    )
    tokenizer = AutoTokenizer.from_pretrained(config.BASE_MODEL_ID)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    # Load LoRA Config
    lora_config = create_lora_config_from_env()
    model = get_peft_model(model, lora_config)
    model.print_trainable_parameters()

    # Load and Prepare Data
    dataset = load_dialogue_data(str(data_path))
    tokenized_dataset = prepare_dataset(dataset, tokenizer)

    # Training Arguments
    training_args = TrainingArguments(
        output_dir=str(output_dir),
        per_device_train_batch_size=1,  # Small batch for CPU safety
        gradient_accumulation_steps=4,
        learning_rate=2e-4,
        num_train_epochs=1,
        fp16=False,
        bf16=False,
        logging_steps=10,
        save_strategy="no",
        report_to="none",
        disable_tqdm=False,
    )

    # Setup Timeout
    setup_timeout(300)  # 5 minute timeout for CPU safety

    try:
        logger.info("Starting training loop...")
        run_training_loop(
            model=model,
            tokenizer=tokenizer,
            train_dataset=tokenized_dataset,
            args=training_args,
            lora_config=lora_config,
        )
        logger.info("Training completed successfully.")

    except TimeoutError:
        logger.warning("Training timed out. Saving partial checkpoint.")
        model.save_pretrained(str(output_dir / "checkpoint_timeout_selection"))
        sys.exit(1)
    except Exception as e:
        logger.error(f"Training failed with error: {e}")
        sys.exit(1)
    finally:
        cancel_timeout()

    # Save Final Checkpoint
    logger.info(f"Saving final selection checkpoint to {checkpoint_path}")
    # Save the adapter weights (PEFT)
    model.save_pretrained(str(checkpoint_path))
    tokenizer.save_pretrained(str(checkpoint_path))

    # Log completion
    log_event("complete", {"task": "T047a", "output": str(checkpoint_path)})
    logger.info("Task T047a completed.")

if __name__ == "__main__":
    main()