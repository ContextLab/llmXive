def test_schema_against_valid_data():
    """Verify a valid CeramicEntry dict passes validation."""
    schema_path = CONTRACTS_DIR / "ceramic_entry.schema.yaml"
    with open(schema_path, 'r') as f:
        schema = yaml.safe_load(f)
    
    valid_entry = {
        "composition": "Al2O3",
        "weibull_modulus": 10.5,
        "sample_count": 50,
        "sintering_temp": 1600.0,
        "primary_anion_cation_group": "Oxide-Al",
        "is_range_flag": False,
        "is_imputed": False,
        "source_url": "https://example.com/paper"
    }
    
    jsonschema.validate(instance=valid_entry, schema=schema)

def test_schema_rejects_invalid_data():
    """Verify an invalid CeramicEntry dict fails validation."""
    schema_path = CONTRACTS_DIR / "ceramic_entry.schema.yaml"
    with open(schema_path, 'r') as f:
        schema = yaml.safe_load(f)
    
    invalid_entry = {
        "composition": 123,  # Should be string
        "weibull_modulus": -5.0  # Should be positive
    }
    
    with pytest.raises(jsonschema.ValidationError):
        jsonschema.validate(instance=invalid_entry, schema=schema)

