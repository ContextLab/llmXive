"""
Unit tests for contract schema validation.
Verifies that the generated YAML schemas are valid and can be loaded.
"""
import pytest
import yaml
import json
import jsonschema
from pathlib import Path
from code.contracts.generate_schemas import load_schema, validate_schemas

BASE_DIR = Path(__file__).parent.parent
CONTRACTS_DIR = BASE_DIR / "code" / "contracts"

def test_ceramic_entry_schema_exists():
    """Verify ceramic_entry.schema.yaml exists and is valid YAML."""
    schema_path = CONTRACTS_DIR / "ceramic_entry.schema.yaml"
    assert schema_path.exists(), "Schema file ceramic_entry.schema.yaml not found"
    
    with open(schema_path, 'r') as f:
        schema = yaml.safe_load(f)
    
    assert isinstance(schema, dict), "Schema must be a dictionary"
    assert schema.get("title") == "CeramicEntry", "Schema title must be 'CeramicEntry'"
    assert "properties" in schema, "Schema must define properties"
    assert "composition" in schema["properties"], "Schema must define 'composition'"
    assert "weibull_modulus" in schema["properties"], "Schema must define 'weibull_modulus'"

def test_ceramic_entry_schema_valid_json_schema():
    """Verify the schema is valid according to JSON Schema draft-07."""
    schema_path = CONTRACTS_DIR / "ceramic_entry.schema.yaml"
    with open(schema_path, 'r') as f:
        schema = yaml.safe_load(f)
    
    # Basic validation that the structure looks like a JSON Schema
    assert "$schema" in schema, "Schema must declare $schema"
    assert "type" in schema, "Schema must declare type"
    assert schema["type"] == "object", "Top level type must be object"

