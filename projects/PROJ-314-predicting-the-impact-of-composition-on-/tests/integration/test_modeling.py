def test_5fold_cv_stratified_split(test_data_path, output_dir):
    """
    Integration test for T025: Verify the 5-fold CV workflow and generate
    `data/results/cv_split_report.json` containing stratification distribution metrics.
    
    Schema: {"fold_sizes": [int], "class_distribution": {"class_name": {"train": int, "test": int}}, "total_samples": int}
    
    Dependencies: T026 (prepare_splits), T027b (train_models - logic only), T028 (evaluate_models).
    """
    # 1. Load Data
    if not test_data_path.exists():
        pytest.skip(f"Test data not found at {test_data_path}. Run ingestion pipeline first.")
    
    df = load_processed_data(str(test_data_path))
    
    # Filter for rare classes as per T060 if necessary (though T060 is a separate task, 
    # prepare_splits handles the logic based on the data provided).
    # We assume the data is already filtered or T060 logic is integrated in prepare_splits.
    
    # 2. Prepare Splits (T026)
    # This function returns the split indices and the stratification logic.
    # We need to ensure it runs successfully and returns the split objects.
    try:
        splits = prepare_splits(df, n_splits=5)
    except Exception as e:
        pytest.fail(f"prepare_splits failed: {e}")
    
    # 3. Verify Split Structure
    # Check if splits is a list of (train_idx, test_idx) tuples
    assert isinstance(splits, list), "Splits must be a list of tuples"
    assert len(splits) == 5, "Must be 5-fold CV"
    
    for i, (train_idx, test_idx) in enumerate(splits):
        assert len(train_idx) > 0, f"Fold {i} train set is empty"
        assert len(test_idx) > 0, f"Fold {i} test set is empty"
        # Check for overlap
        assert len(set(train_idx) & set(test_idx)) == 0, f"Fold {i} has overlapping train/test indices"
    
    # 4. Generate Stratification Report (T025 Requirement)
    # The task requires generating `data/results/cv_split_report.json`.
    # We will generate this report based on the splits.
    
    class_distribution = {}
    fold_sizes = []
    total_samples = len(df)
    
    # Assuming the target column for stratification is 'primary_anion_cation_group'
    # This must match the logic in prepare_splits
    strat_col = 'primary_anion_cation_group'
    if strat_col not in df.columns:
        # Fallback if the column name is different or missing
        # But per spec, it should exist.
        pytest.fail(f"Stratification column '{strat_col}' not found in data.")
    
    for i, (train_idx, test_idx) in enumerate(splits):
        fold_sizes.append(len(train_idx) + len(test_idx))
        
        train_df = df.iloc[train_idx]
        test_df = df.iloc[test_idx]
        
        # Count distribution per class in train and test
        train_counts = train_df[strat_col].value_counts().to_dict()
        test_counts = test_df[strat_col].value_counts().to_dict()
        
        # Union of all classes seen in this fold
        all_classes = set(train_counts.keys()) | set(test_counts.keys())
        
        for cls in all_classes:
            if cls not in class_distribution:
                class_distribution[cls] = {"train": 0, "test": 0}
            class_distribution[cls]["train"] += train_counts.get(cls, 0)
            class_distribution[cls]["test"] += test_counts.get(cls, 0)
    
    report = {
        "fold_sizes": fold_sizes,
        "class_distribution": class_distribution,
        "total_samples": total_samples
    }
    
    # 5. Write Report to Disk
    # The task specifies the output path: data/results/cv_split_report.json
    results_dir = PROJECT_ROOT / "data" / "results"
    results_dir.mkdir(parents=True, exist_ok=True)
    report_path = results_dir / "cv_split_report.json"
    
    with open(report_path, 'w') as f:
        json.dump(report, f, indent=2)
    
    # 6. Verify Artifact Existence
    assert report_path.exists(), f"Report file {report_path} was not created"
    
    # 7. Verify Content Validity
    with open(report_path, 'r') as f:
        loaded_report = json.load(f)
    
    assert "fold_sizes" in loaded_report
    assert "class_distribution" in loaded_report
    assert "total_samples" in loaded_report
    assert len(loaded_report["fold_sizes"]) == 5
    assert loaded_report["total_samples"] == total_samples
    
    # Optional: Verify stratification quality (simple check: classes present in train should be in test if N is large enough)
    # This is a basic sanity check, not a strict statistical test.
    for cls, counts in loaded_report["class_distribution"].items():
        if counts["train"] > 0 and counts["test"] == 0:
            # Warning only, as small classes might not appear in every fold
            print(f"Warning: Class {cls} not present in test sets of all folds.")
    
    print(f"Successfully generated {report_path}")
    print(f"Report content: {json.dumps(report, indent=2)}")

    # 8. Run a minimal training step to ensure T027b/T028 integration works (optional but good for integration)
    # We won't save the full model here to avoid side effects, just verify the split works for training
    feature_cols = [c for c in df.columns if c not in ['weibull_modulus', 'primary_anion_cation_group', 'composition']]
    if not feature_cols:
        pytest.fail("No feature columns found for modeling.")
    
    X = df[feature_cols]
    y = df['weibull_modulus']
    
    # Verify we can create a simple model with these splits
    # This ensures the splits are valid for the modeling step
    from sklearn.ensemble import RandomForestRegressor
    from sklearn.model_selection import cross_val_score
    
    model = RandomForestRegressor(n_estimators=5, random_state=42)
    # Just a quick check that cross_val_score works with our data
    # Note: We are not using the custom splits object here, but verifying data compatibility
    try:
        scores = cross_val_score(model, X, y, cv=5, scoring='neg_mean_absolute_error')
        print(f"Cross-validation scores (neg MAE): {scores}")
    except Exception as e:
        pytest.fail(f"Model training with splits failed: {e}")

    # Final assertion: The report must exist and be valid JSON
    assert report_path.stat().st_size > 0, "Report file is empty"
    
    return True
