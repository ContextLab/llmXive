def load_processed_data() -> pd.DataFrame:
    """
    Load the processed dataset from data/processed/cleaned_data.csv.
    This file is expected to be generated by the ingestion pipeline (T018a/T019).
    """
    input_path = PROCESSED_DIR / "cleaned_data.csv"
    if not input_path.exists():
        raise FileNotFoundError(f"Processed data not found at {input_path}. "
                                "Run the ingestion pipeline first.")
    logger.info(f"Loading processed data from {input_path}")
    return pd.read_csv(input_path)

def load_or_train_model(X: pd.DataFrame, y: pd.Series) -> Any:
    """
    Load the best model from disk if it exists, otherwise train a new one.
    The model is expected to be saved by the modeling pipeline (T027/T028).
    """
    model_path = MODELS_DIR / "best_model.pkl"
    
    if model_path.exists():
        logger.info(f"Loading best model from {model_path}")
        import joblib
        return joblib.load(model_path)
    
    logger.warning("No saved model found. Training a new Random Forest model.")
    model = RandomForestRegressor(n_estimators=100, random_state=42, n_jobs=-1)
    model.fit(X, y)
    return model

def generate_shap_analysis(model: Any, X: pd.DataFrame) -> shap.Explainer:
    """
    Generate SHAP values for the given model and data.
    """
    logger.info("Generating SHAP values...")
    # Use TreeExplainer for tree-based models (RF, GBM)
    explainer = shap.TreeExplainer(model)
    shap_values = explainer.shap_values(X)
    return shap_values

def plot_shap_summary(shap_values: Any, X: pd.DataFrame, output_path: Path):
    """
    Generate and save the SHAP summary plot.
    """
    logger.info(f"Generating SHAP summary plot at {output_path}")
    plt.figure(figsize=(10, 8))
    shap.summary_plot(shap_values, X, plot_type="dot", show=False)
    plt.tight_layout()
    plt.savefig(output_path, dpi=300)
    plt.close()
    logger.info(f"SHAP summary plot saved to {output_path}")

def save_feature_ranking(shap_values: Any, feature_names: List[str], output_path: Path):
    """
    Calculate mean absolute SHAP values, rank features, and save to CSV.
    """
    logger.info(f"Calculating feature ranking and saving to {output_path}")
    
    # Handle case where shap_values might be a list (for multi-output or specific models)
    if isinstance(shap_values, list):
        # For regression, usually a single array, but safe-guard
        if len(shap_values) == 1:
            abs_shap = np.abs(shap_values[0])
        else:
            # If multiple, average them (rare for single target regression)
            abs_shap = np.abs(np.mean(shap_values, axis=0))
    else:
        abs_shap = np.abs(shap_values)

    # Calculate mean absolute SHAP value for each feature
    mean_abs_shap = np.mean(abs_shap, axis=0)
    
    # Create a DataFrame for ranking
    ranking_df = pd.DataFrame({
        'feature': feature_names,
        'mean_abs_shap_value': mean_abs_shap
    })
    
    # Sort by importance descending
    ranking_df = ranking_df.sort_values(by='mean_abs_shap_value', ascending=False)
    
    # Save to CSV
    ranking_df.to_csv(output_path, index=False)
    logger.info(f"Feature ranking table saved to {output_path}")
    return ranking_df

def calculate_cv_stability(X: pd.DataFrame, y: pd.Series, model_class, n_splits: int = 5) -> pd.DataFrame:
    """
    Calculate Coefficient of Variation (CV) for feature importances across folds.
    This satisfies SC-002 evidence requirements.
    """
    logger.info("Calculating CV stability scores across CV folds...")
    
    model = model_class(n_estimators=100, random_state=42, n_jobs=-1)
    cv = shap.utils.sample(X, min(1000, X.shape[0])) # Sample for speed if large
    
    # We need to get feature importances (or SHAP values) for each fold
    # Using SHAP values per fold is more robust than raw feature_importance_
    shap_values_list = []
    
    kf = shap.utils.sample(X, min(1000, X.shape[0])) # Just for shape check
    
    # Using cross_val_predict to get predictions is standard, but we need SHAP per fold
    # To do this efficiently without retraining the whole model 5 times in a loop manually:
    # We will use a custom cross-validation loop to capture SHAP values for the training set of each fold
    
    feature_names = X.columns.tolist()
    n_features = len(feature_names)
    n_samples = X.shape[0]
    
    # Store SHAP values for each sample across folds where it was in the training set
    # This is computationally expensive. We will approximate by training on full data
    # and checking stability of global importance if CV is too slow, 
    # OR perform a reduced CV if data is small.
    # Given the constraint of "real data" and potential size, we will do a 5-fold CV
    # but only compute SHAP on the training fold data.
    
    from sklearn.model_selection import KFold
    
    kf = KFold(n_splits=n_splits, shuffle=True, random_state=42)
    feature_importance_matrix = np.zeros((n_splits, n_features))
    
    for i, (train_idx, _) in enumerate(kf.split(X)):
        X_train_fold = X.iloc[train_idx]
        y_train_fold = y.iloc[train_idx]
        
        model_fold = model_class(n_estimators=100, random_state=42, n_jobs=-1)
        model_fold.fit(X_train_fold, y_train_fold)
        
        # Calculate SHAP for this fold's training data
        explainer = shap.TreeExplainer(model_fold)
        # Sample training data for SHAP calculation if too large to keep memory low
        sample_size = min(500, X_train_fold.shape[0])
        X_sample = X_train_fold.sample(n=sample_size, random_state=42)
        
        shap_vals = explainer.shap_values(X_sample)
        if isinstance(shap_vals, list):
            shap_vals = shap_vals[0]
        
        mean_abs = np.mean(np.abs(shap_vals), axis=0)
        feature_importance_matrix[i] = mean_abs

    # Calculate Mean and Std across folds
    mean_importance = np.mean(feature_importance_matrix, axis=0)
    std_importance = np.std(feature_importance_matrix, axis=0)
    
    # Calculate CV = Std / Mean
    # Avoid division by zero
    cv_scores = np.divide(std_importance, mean_importance, out=np.zeros_like(std_importance), where=mean_importance!=0)
    
    stability_df = pd.DataFrame({
        'feature': feature_names,
        'mean_importance': mean_importance,
        'std_importance': std_importance,
        'cv_stability_score': cv_scores
    })
    
    stability_df = stability_df.sort_values(by='mean_importance', ascending=False)
    return stability_df

def main():
    """
    Main execution flow for T041:
    1. Load processed data.
    2. Load or train model.
    3. Generate SHAP values.
    4. Plot SHAP summary -> data/results/shap_summary.png
    5. Save feature ranking -> data/results/feature_ranking_table.csv
    6. Calculate and save CV stability -> data/results/stability_metrics.json
    """
    try:
        # 1. Load Data
        df = load_processed_data()
        
        # Identify target and features
        # Assuming 'weibull_modulus' is the target as per project specs
        target_col = 'weibull_modulus'
        if target_col not in df.columns:
            raise ValueError(f"Target column '{target_col}' not found in dataset.")
        
        # Exclude non-feature columns
        exclude_cols = [target_col, 'composition', 'primary_anion_cation_group', 'is_range_flag', 'range_original', 'is_imputed']
        feature_cols = [c for c in df.columns if c not in exclude_cols]
        
        # Fallback if specific columns are missing
        if not feature_cols:
            # Try to select numeric columns excluding target
            feature_cols = df.select_dtypes(include=[np.number]).columns.drop(target_col).tolist()
        
        X = df[feature_cols]
        y = df[target_col]
        
        logger.info(f"Dataset loaded: {X.shape[0]} samples, {X.shape[1]} features")
        
        # 2. Load or Train Model
        model = load_or_train_model(X, y)
        
        # 3. Generate SHAP Analysis
        shap_values = generate_shap_analysis(model, X)
        
        # 4. Plot SHAP Summary
        shap_summary_path = RESULTS_DIR / "shap_summary.png"
        plot_shap_summary(shap_values, X, shap_summary_path)
        
        # 5. Save Feature Ranking Table
        ranking_path = RESULTS_DIR / "feature_ranking_table.csv"
        save_feature_ranking(shap_values, feature_cols, ranking_path)
        
        # 6. Calculate and Save CV Stability
        # Determine model class based on loaded model
        if isinstance(model, RandomForestRegressor):
            model_class = RandomForestRegressor
        elif isinstance(model, GradientBoostingRegressor):
            model_class = GradientBoostingRegressor
        else:
            # Default to RF if unknown
            model_class = RandomForestRegressor
            logger.warning(f"Unknown model type {type(model)}, defaulting to RandomForest for stability calc.")

        stability_df = calculate_cv_stability(X, y, model_class)
        
        stability_path = RESULTS_DIR / "stability_metrics.json"
        stability_df.to_json(stability_path, orient='records', indent=2)
        logger.info(f"Stability metrics saved to {stability_path}")
        
        logger.info("T041 Execution Complete.")
        
    except Exception as e:
        logger.error(f"Execution failed: {e}", exc_info=True)
        raise

if __name__ == "__main__":
    main()
