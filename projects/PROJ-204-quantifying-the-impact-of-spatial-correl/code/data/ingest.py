"""
code/data/ingest.py
-------------------

Implements the ingestion pipeline required by **Task T101**.  The script
orchestrates the following steps:

1. Load the project configuration (``code/utils/config.py``).
2. Download raw EDS maps and performance metrics using
   ``code/data/download.py``.  The download routine always works with real
   data – either a verified source (future extension) or a small public
   fallback dataset.
3. Align the three elemental maps to a common pixel grid using
   ``code/data/align.create_aligned_dataset``.
4. Apply defect masking via ``code/preprocess/calibrate``.
5. Assemble a unified CSV (``data/processed/unified_dataset.csv``) that
   contains the required columns and excludes any sample with missing
   performance metrics.
6. Write ingestion statistics (success rate and per‑sample exclusion reasons)
   to ``data/results/ingestion_stats.json``.
7. Log the process to ``data/results/ingestion_log.txt``.

The public function ``ingest_and_filter_dataset`` matches the signature
expected by ``code/main_pipeline.py`` (``ingest_and_filter_dataset(config)``).
Running this module directly (``python -m code.data.ingest``) executes the
full pipeline using the default configuration file ``code/config.yaml``
(created later by task T106a).
"""

import json
import logging
from pathlib import Path
from typing import Dict, List

import numpy as np
import pandas as pd

from llmxive_toolkit import paths, get_logger

from utils.config import get_config
from data.download import download_from_verified_source
from data.align import create_aligned_dataset
from preprocess.calibrate import calibrate_and_log

# Initialise a module‑level logger
log = get_logger(__name__)

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def _load_feasibility_report() -> Dict:
    """
    Load the JSON report generated by ``code/data.feasibility``.
    If the file does not exist, an empty dict is returned – the download
    routine will then fall back to the public dataset.
    """
    report_path = paths.results("data_feasibility_report.json")
    if not report_path.is_file():
        log.warning(
            f"Feasibility report not found at {report_path}; using empty report."
        )
        return {}
    with open(report_path, "r") as f:
        return json.load(f)

def _write_ingestion_log(messages: List[str]) -> None:
    """Write a plain‑text log file summarising the ingestion run."""
    log_path = paths.results("ingestion_log.txt")
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with open(log_path, "w") as f:
        for line in messages:
            f.write(line + "\n")

def _write_ingestion_stats(
    n_requested: int, n_processed: int, exclusions: List[Dict]
) -> None:
    """
    Write ``data/results/ingestion_stats.json`` with the overall success
    rate and per‑sample exclusion reasons.
    """
    stats = {
        "ingestion_success_rate": n_processed / n_requested if n_requested else 0.0,
        "total_requested": n_requested,
        "total_processed": n_processed,
        "exclusions": exclusions,
    }
    stats_path = paths.results("ingestion_stats.json")
    stats_path.parent.mkdir(parents=True, exist_ok=True)
    with open(stats_path, "w") as f:
        json.dump(stats, f, indent=2)

# ----------------------------------------------------------------------
# Core pipeline
# ----------------------------------------------------------------------
def ingest_and_filter_dataset(config_path: str | None = None) -> pd.DataFrame:
    """
    Main entry point used by ``code/main_pipeline.py``.
    The function performs the complete ingestion workflow and returns the
    final pandas DataFrame (the unified dataset).

    Parameters
    ----------
    config_path: str | None
        Optional path to a YAML configuration file.  If ``None`` the default
        configuration ``code/config.yaml`` is used.

    Returns
    -------
    pd.DataFrame
        The unified dataset written to ``data/processed/unified_dataset.csv``.
    """
    # ------------------------------------------------------------------
    # 1. Load configuration
    # ------------------------------------------------------------------
    config = get_config(config_path)
    base_dir = Path(config.get("base_dir", ".")).resolve()
    raw_dir = base_dir / "data" / "raw"
    processed_dir = base_dir / "data" / "processed"

    # Ensure directories exist
    raw_dir.mkdir(parents=True, exist_ok=True)
    processed_dir.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # 2. Download raw data
    # ------------------------------------------------------------------
    feasibility = _load_feasibility_report()
    try:
        samples = download_from_verified_source(feasibility)
    except Exception as e:
        log.error(f"Data download failed: {e}")
        raise

    n_requested = len(samples)
    log.info(f"Requested {n_requested} sample(s) for ingestion.")

    # ------------------------------------------------------------------
    # 3. Align elemental maps
    # ------------------------------------------------------------------
    aligned_samples: List[Dict] = []
    for sample in samples:
        try:
            # Build the list of element filenames expected in ``raw_dir``
            element_files = [
                sample["pb_map_filename"],
                sample["i_map_filename"],
                sample["ma_map_filename"],
            ]
            # ``create_aligned_dataset`` loads the .npy files and returns a
            # dict mapping element name → aligned ndarray.
            aligned_maps = create_aligned_dataset(
                raw_dir=raw_dir,
                element_files=element_files,
                reference_key="Pb",
            )
            # Store the aligned arrays as new keys in the sample dict.
            sample["aligned_maps"] = aligned_maps
            aligned_samples.append(sample)
        except Exception as e:
            log.warning(f"Alignment failed for sample {sample['sample_id']}: {e}")

    # ------------------------------------------------------------------
    # 4. Defect masking
    # ------------------------------------------------------------------
    masked_samples: List[Dict] = []
    mask_exclusions: List[Dict] = []
    for sample in aligned_samples:
        try:
            aligned_maps = sample["aligned_maps"]
            # Apply a simple mask (dead pixels ≤0 and bright artifacts >3σ)
            masked_maps = {}
            mask_stats = {}
            for element, arr in aligned_maps.items():
                masked_arr, stats = calibrate_and_log(
                    image=arr,
                    dead_threshold=0.0,
                    artifact_sigma=3.0,
                    log_path=None,
                )
                masked_maps[element] = masked_arr
                mask_stats[element] = stats

            # Save the masked arrays to ``processed_dir`` as .npy files.
            # Filenames follow the pattern ``<sample_id>_<element>_masked.npy``.
            for element, arr in masked_maps.items():
                out_path = (
                    processed_dir
                    / f"{sample['sample_id']}_{element}_masked.npy"
                )
                np.save(out_path, arr)
                # Record the path for later CSV creation
                sample[f"masked_{element.lower()}_map_path"] = str(out_path)

            # Record mask statistics (percentage of masked pixels) – we
            # compute the mean of the dead+artifact masks from the last call.
            # ``dead_pixel_fraction`` and ``artifact_fraction`` are stored
            # in ``mask_stats`` for each element; we average them.
            mask_percentages = [
                (stats["dead_pixel_fraction"] + stats["artifact_fraction"])
                / 2.0
                for stats in mask_stats.values()
            ]
            sample["mask_percentage"] = float(np.mean(mask_percentages))
            masked_samples.append(sample)
        except Exception as e:
            log.warning(f"Masking failed for sample {sample['sample_id']}: {e}")
            mask_exclusions.append(
                {
                    "sample_id": sample["sample_id"],
                    "reason": f"Masking error: {str(e)}",
                }
            )

    # ------------------------------------------------------------------
    # 5. Build the unified CSV
    # ------------------------------------------------------------------
    records = []
    exclusions = []
    for s in masked_samples:
        # Verify that performance metrics are present and numeric
        try:
            pce = float(s["pce"])
            j_sc = float(s["j_sc"])
            v_oc = float(s["v_oc"])
        except (KeyError, ValueError, TypeError):
            exclusions.append(
                {
                    "sample_id": s["sample_id"],
                    "reason": "Missing or non‑numeric performance metric",
                }
            )
            continue

        # Ensure that all three masked map paths exist
        required_paths = [
            s.get("masked_pb_map_path"),
            s.get("masked_i_map_path"),
            s.get("masked_ma_map_path"),
        ]
        if not all(p and Path(p).exists() for p in required_paths):
            exclusions.append(
                {
                    "sample_id": s["sample_id"],
                    "reason": "Missing masked map file(s)",
                }
            )
            continue

        record = {
            "sample_id": s["sample_id"],
            "Pb_map_path": s["masked_pb_map_path"],
            "I_map_path": s["masked_i_map_path"],
            "MA_map_path": s["masked_ma_map_path"],
            "pce": pce,
            "j_sc": j_sc,
            "v_oc": v_oc,
            "mask_percentage": s["mask_percentage"],
            # The following columns are required by the specification;
            # they are filled with deterministic placeholders because the
            # current fallback dataset does not provide depth or co‑location
            # validation information.
            "co_location_status": "unknown",
            "depth_validation_status": "unknown",
            "eds_status": "complete",  # we successfully downloaded maps
        }
        records.append(record)

    df = pd.DataFrame(records)
    # Write the unified dataset
    unified_path = processed_dir / "unified_dataset.csv"
    unified_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(unified_path, index=False)
    log.info(
        f"Unified dataset written to {unified_path} with {len(df)} rows."
    )

    # ------------------------------------------------------------------
    # 6. Write logs and statistics
    # ------------------------------------------------------------------
    # Combine exclusions from masking and missing metrics
    all_exclusions = exclusions + mask_exclusions
    _write_ingestion_log(
        [f"{ex['sample_id']}: {ex['reason']}" for ex in all_exclusions]
    )
    _write_ingestion_stats(
        n_requested=n_requested,
        n_processed=len(df),
        exclusions=all_exclusions,
    )

    return df

# ----------------------------------------------------------------------
# Command‑line entry point
# ----------------------------------------------------------------------
def main() -> None:
    """
    CLI entry point – mirrors the behaviour expected by the quickstart
    documentation:

    ``python -m code.data.ingest``
    """
    ingest_and_filter_dataset()

if __name__ == "__main__":
    main()
