import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, List, Any, Tuple

# Import logging setup from existing utility
from utils.logging import setup_logger

# Constants
SIGNIFICANCE_THRESHOLD = 0.01
CORRELATION_RESULTS_JSON = "data/processed/correlation_results.json"
VALIDATION_REPORT_PATH = "data/processed/pvalue_validation_report.json"

def load_correlation_results(file_path: str) -> Dict[str, Any]:
    """
    Load the correlation results from the JSON file generated by T020.
    Raises FileNotFoundError if the file does not exist.
    """
    path = Path(file_path)
    if not path.exists():
        raise FileNotFoundError(f"Correlation results file not found: {path}")
    
    with open(path, 'r') as f:
        return json.load(f)

def validate_pvalues_exist(data: Dict[str, Any]) -> Tuple[bool, List[str]]:
    """
    Validate that p-values are present for all correlation entries.
    Returns (True, []) if all are present, or (False, [list of missing keys]).
    """
    missing = []
    
    # The data structure is expected to be a dict with keys like "He/p", "Fe/p", "Control"
    # containing lists of results per rigidity bin.
    if not isinstance(data, dict):
        missing.append("Root data is not a dictionary")
        return False, missing

    for species, bins in data.items():
        if not isinstance(bins, list):
            missing.append(f"Species '{species}' data is not a list of bins")
            continue
        
        for i, bin_data in enumerate(bins):
            if not isinstance(bin_data, dict):
                missing.append(f"Species '{species}', bin {i} is not a dictionary")
                continue
            
            # Check for p-value keys. T020 saves both 'p_value' and potentially 'pvalues'
            # We expect a specific key based on the correlation logic.
            # Assuming the structure: { "lag": ..., "correlation": ..., "p_value": ... }
            if "p_value" not in bin_data and "pvalues" not in bin_data:
                missing.append(f"Species '{species}', bin {i}: Missing 'p_value' field")
    
    if missing:
        return False, missing
    return True, []

def flag_non_significant_results(data: Dict[str, Any], threshold: float = SIGNIFICANCE_THRESHOLD) -> Dict[str, Any]:
    """
    Iterate through all correlation results and flag those where p > threshold.
    Returns a summary dictionary of non-significant counts and details.
    """
    report = {
        "threshold": threshold,
        "total_correlations": 0,
        "non_significant_count": 0,
        "non_significant_details": []
    }

    if not isinstance(data, dict):
        return report

    for species, bins in data.items():
        if not isinstance(bins, list):
            continue
        
        for i, bin_data in enumerate(bins):
            if not isinstance(bin_data, dict):
                continue
            
            # Determine the p-value key
            p_val = bin_data.get("p_value") or bin_data.get("pvalues")
            if p_val is None:
                continue

            report["total_correlations"] += 1

            if p_val > threshold:
                report["non_significant_count"] += 1
                report["non_significant_details"].append({
                    "species": species,
                    "bin_index": i,
                    "rigidity": bin_data.get("rigidity", "unknown"),
                    "lag_months": bin_data.get("lag", "unknown"),
                    "p_value": p_val,
                    "correlation": bin_data.get("correlation", "unknown")
                })
    
    return report

def generate_validation_report(data: Dict[str, Any], output_path: str) -> Dict[str, Any]:
    """
    Perform full validation: check existence of p-values and flag non-significant ones.
    Saves the report to the specified JSON path.
    """
    # 1. Validate existence
    exists_ok, missing_keys = validate_pvalues_exist(data)
    
    # 2. Flag non-significant
    flag_report = flag_non_significant_results(data)
    
    # 3. Assemble final report
    final_report = {
        "validation_status": "PASSED" if exists_ok else "FAILED",
        "missing_pvalue_fields": missing_keys,
        "significance_analysis": flag_report
    }

    # Save to file
    out_path = Path(output_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, 'w') as f:
        json.dump(final_report, f, indent=2)
    
    # Log summary
    logger = logging.getLogger(__name__)
    logger.info(f"Validation complete. Status: {final_report['validation_status']}")
    logger.info(f"Total correlations analyzed: {flag_report['total_correlations']}")
    logger.info(f"Non-significant results (p > {SIGNIFICANCE_THRESHOLD}): {flag_report['non_significant_count']}")
    
    if not exists_ok:
        logger.warning(f"Missing p-value fields found: {missing_keys}")
    
    return final_report

def main():
    """
    Entry point for T024: Validate p-values and flag non-significant results.
    """
    # Setup logger
    logger = setup_logger("validate_pvalues")
    logger.info("Starting p-value validation (T024)...")

    try:
        # Load data
        logger.info(f"Loading correlation results from {CORRELATION_RESULTS_JSON}...")
        data = load_correlation_results(CORRELATION_RESULTS_JSON)
        
        # Validate and flag
        report = generate_validation_report(data, VALIDATION_REPORT_PATH)
        
        # Exit with error code if validation failed (missing p-values)
        if report["validation_status"] == "FAILED":
            logger.error("Validation failed: Missing p-values detected.")
            sys.exit(1)
        
        logger.info("T024 completed successfully.")
        sys.exit(0)

    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        logger.error("Ensure T020 has been run successfully to generate correlation_results.json.")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during validation: {e}")
        raise

if __name__ == "__main__":
    main()