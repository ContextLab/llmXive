"""
Task T024: Validate that p-values are calculated for all correlations and flag non-significant results.

This module consumes the correlation results generated by T020/T023 and:
1. Verifies that every correlation entry has a valid p-value.
2. Flags any results where p > 0.01 as non-significant.
3. Generates a summary report of significant vs. non-significant findings.
4. Writes the validation report to data/processed/validation_pvalues.md.
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, List, Any, Tuple

# Add project root to path for imports
project_root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(project_root))

from code.utils.logging import setup_logger

# Constants
PVALUE_THRESHOLD = 0.01
CORRELATION_RESULTS_JSON = "data/processed/correlation_results.json"
CORRELATION_RESULTS_CSV = "data/processed/correlation_summary.csv"
VALIDATION_REPORT_PATH = "data/processed/validation_pvalues.md"

def load_correlation_results() -> Dict[str, Any]:
    """Load correlation results from JSON file."""
    json_path = project_root / CORRELATION_RESULTS_JSON
    if not json_path.exists():
        raise FileNotFoundError(f"Correlation results file not found: {json_path}")
    
    with open(json_path, 'r') as f:
        return json.load(f)

def validate_pvalues_exist(data: Dict[str, Any]) -> Tuple[int, int, List[str]]:
    """
    Validate that p-values exist for all correlations.
    
    Returns:
        Tuple of (total_count, valid_count, list of missing p-value entries)
    """
    total_count = 0
    valid_count = 0
    missing_entries = []

    if "results" not in data:
        logging.error("Correlation results JSON missing 'results' key")
        return 0, 0, ["Missing 'results' key in JSON"]

    results = data["results"]
    
    # Iterate through rigidity bins
    for rigidity_bin, species_data in results.items():
        for species_pair, correlation_data in species_data.items():
            if "correlations" not in correlation_data:
                missing_entries.append(f"Missing 'correlations' for {rigidity_bin}/{species_pair}")
                continue

            for corr_entry in correlation_data["correlations"]:
                total_count += 1
                if "p_value" in corr_entry and corr_entry["p_value"] is not None:
                    valid_count += 1
                else:
                    missing_entries.append(
                        f"Missing p_value for {rigidity_bin}/{species_pair} at lag={corr_entry.get('lag_months', 'unknown')}"
                    )

    return total_count, valid_count, missing_entries

def flag_non_significant_results(data: Dict[str, Any]) -> Dict[str, List[Dict[str, Any]]]:
    """
    Flag all correlations where p-value > threshold.
    
    Returns:
        Dictionary mapping species/rigidity to list of non-significant results
    """
    non_significant = {
        "He/p": [],
        "Fe/p": [],
        "He_flux": [],
        "Fe_flux": []
    }

    if "results" not in data:
        return non_significant

    results = data["results"]
    
    for rigidity_bin, species_data in results.items():
        for species_pair, correlation_data in species_data.items():
            if "correlations" not in correlation_data:
                continue

            for corr_entry in correlation_data["correlations"]:
                p_value = corr_entry.get("p_value")
                if p_value is not None and p_value > PVALUE_THRESHOLD:
                    non_significant[species_pair].append({
                        "rigidity_bin": rigidity_bin,
                        "lag_months": corr_entry.get("lag_months"),
                        "correlation_coefficient": corr_entry.get("coefficient"),
                        "p_value": p_value
                    })

    return non_significant

def generate_validation_report(
    total_count: int,
    valid_count: int,
    missing_entries: List[str],
    non_significant_results: Dict[str, List[Dict[str, Any]]]
) -> str:
    """Generate a markdown validation report."""
    lines = [
        "# P-Value Validation Report",
        "",
        f"**Threshold**: p > {PVALUE_THRESHOLD} considered non-significant",
        "",
        "## Summary Statistics",
        "",
        f"- **Total Correlation Tests**: {total_count}",
        f"- **Valid P-Values**: {valid_count}",
        f"- **Missing P-Values**: {total_count - valid_count}",
        "",
    ]

    if missing_entries:
        lines.append("## Missing P-Values")
        lines.append("")
        lines.append("The following entries are missing p-values:")
        lines.append("")
        for entry in missing_entries:
            lines.append(f"- {entry}")
        lines.append("")
    else:
        lines.append("## P-Value Completeness")
        lines.append("")
        lines.append("✅ All correlation entries have valid p-values.")
        lines.append("")

    lines.append("## Non-Significant Results (p > 0.01)")
    lines.append("")
    
    total_non_significant = 0
    for species_pair, results in non_significant_results.items():
        count = len(results)
        total_non_significant += count
        lines.append(f"### {species_pair}")
        lines.append("")
        lines.append(f"**Count**: {count} non-significant results")
        lines.append("")
        
        if count > 0:
            lines.append("| Rigidity Bin | Lag (months) | Coefficient | P-Value |")
            lines.append("|--------------|--------------|-------------|---------|")
            for result in results:
                lines.append(
                    f"| {result['rigidity_bin']} | {result['lag_months']} | "
                    f"{result['correlation_coefficient']:.4f} | {result['p_value']:.6f} |"
                )
            lines.append("")

    lines.append("## Overall Statistics")
    lines.append("")
    if total_count > 0:
        significant_count = valid_count - total_non_significant
        significance_rate = (significant_count / valid_count * 100) if valid_count > 0 else 0
        lines.append(f"- **Total Non-Significant**: {total_non_significant}")
        lines.append(f"- **Significant Results**: {significant_count}")
        lines.append(f"- **Significance Rate**: {significance_rate:.2f}%")
    else:
        lines.append("- No correlations found to analyze.")

    lines.append("")
    lines.append("---")
    lines.append(f"*Generated on: {pd.Timestamp.now().strftime('%Y-%m-%d %H:%M:%S')}*")
    
    return "\n".join(lines)

def main():
    """Main entry point for p-value validation."""
    logger = setup_logger(__name__)
    logger.info("Starting p-value validation for correlation results")

    try:
        # Load results
        logger.info(f"Loading correlation results from {CORRELATION_RESULTS_JSON}")
        data = load_correlation_results()

        # Validate p-values exist
        logger.info("Validating p-value completeness...")
        total_count, valid_count, missing_entries = validate_pvalues_exist(data)
        
        if total_count == 0:
            logger.warning("No correlation entries found in results")
        else:
            logger.info(f"Found {total_count} total correlation tests, {valid_count} with valid p-values")

        # Flag non-significant results
        logger.info("Flagging non-significant results...")
        non_significant_results = flag_non_significant_results(data)
        
        total_non_sig = sum(len(v) for v in non_significant_results.values())
        logger.info(f"Found {total_non_sig} non-significant results (p > {PVALUE_THRESHOLD})")

        # Generate report
        logger.info(f"Generating validation report to {VALIDATION_REPORT_PATH}")
        report = generate_validation_report(
            total_count, valid_count, missing_entries, non_significant_results
        )

        # Ensure output directory exists
        output_path = project_root / VALIDATION_REPORT_PATH
        output_path.parent.mkdir(parents=True, exist_ok=True)
        
        with open(output_path, 'w') as f:
            f.write(report)

        logger.info(f"Validation report written to {output_path}")
        
        # Exit with error if missing p-values found
        if missing_entries:
            logger.error(f"Validation failed: {len(missing_entries)} missing p-values detected")
            sys.exit(1)
        
        logger.info("P-value validation completed successfully")

    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Validation failed with error: {e}")
        import traceback
        logger.error(traceback.format_exc())
        sys.exit(1)

if __name__ == "__main__":
    main()
