"""
Task T023: Save and validate correlation results.

This module serves as the checkpoint for T020's output. It ensures that
the correlation results (coefficients, p-values) generated by T020 are
correctly saved to disk and validates their structure.

It implements the specific requirement to verify the existence and
validity of:
- data/processed/correlation_results.json
- data/processed/correlation_summary.csv
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, List, Any, Tuple
import pandas as pd
from datetime import datetime

# Add project root to path for imports
project_root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(project_root))

from code.utils.logging import setup_logger

# Configure paths
PROCESSED_DIR = project_root / "data" / "processed"
RESULTS_JSON_PATH = PROCESSED_DIR / "correlation_results.json"
SUMMARY_CSV_PATH = PROCESSED_DIR / "correlation_summary.csv"

logger = setup_logger("save_correlation_results")


def verify_file_exists(file_path: Path) -> bool:
    """
    Check if the specified file exists on disk.
    
    Args:
        file_path: Path to the file to check.
        
    Returns:
        True if file exists, False otherwise.
    """
    exists = file_path.exists()
    if exists:
        logger.info(f"File exists: {file_path} ({file_path.stat().st_size} bytes)")
    else:
        logger.error(f"File missing: {file_path}")
    return exists


def validate_json_structure(file_path: Path) -> Tuple[bool, str]:
    """
    Validate the structure of the correlation results JSON file.
    
    Expected structure:
    {
        "metadata": { "generated_at": "...", "version": "..." },
        "results": [
            {
                "rigidity_bin": float,
                "species_pair": str,  // e.g., "He/p", "Fe/p"
                "lag_months": int,
                "method": str,  // "pearson" or "spearman"
                "coefficient": float,
                "p_value": float
            },
            ...
        ]
    }
    
    Args:
        file_path: Path to the JSON file.
        
    Returns:
        Tuple of (is_valid, message).
    """
    if not verify_file_exists(file_path):
        return False, "File does not exist"

    try:
        with open(file_path, 'r') as f:
            data = json.load(f)
    except json.JSONDecodeError as e:
        return False, f"Invalid JSON format: {e}"
    except Exception as e:
        return False, f"Error reading file: {e}"

    # Validate top-level keys
    if "results" not in data:
        return False, "Missing 'results' key in JSON"
    
    if not isinstance(data["results"], list):
        return False, "'results' must be a list"

    if len(data["results"]) == 0:
        return False, "'results' list is empty"

    # Validate structure of first result item
    required_keys = {"rigidity_bin", "species_pair", "lag_months", "method", "coefficient", "p_value"}
    sample = data["results"][0]
    
    missing_keys = required_keys - set(sample.keys())
    if missing_keys:
        return False, f"Missing keys in result items: {missing_keys}"

    # Validate data types
    try:
        float(sample["rigidity_bin"])
        float(sample["coefficient"])
        float(sample["p_value"])
        int(sample["lag_months"])
    except (ValueError, TypeError) as e:
        return False, f"Invalid data types in result items: {e}"

    logger.info(f"JSON structure valid. Found {len(data['results'])} records.")
    return True, "JSON structure is valid"


def validate_csv_structure(file_path: Path) -> Tuple[bool, str]:
    """
    Validate the structure of the correlation summary CSV file.
    
    Expected columns:
    rigidity_bin, species_pair, lag_months, method, coefficient, p_value
    
    Args:
        file_path: Path to the CSV file.
        
    Returns:
        Tuple of (is_valid, message).
    """
    if not verify_file_exists(file_path):
        return False, "File does not exist"

    try:
        df = pd.read_csv(file_path)
    except Exception as e:
        return False, f"Error reading CSV: {e}"

    required_columns = {"rigidity_bin", "species_pair", "lag_months", "method", "coefficient", "p_value"}
    missing_cols = required_columns - set(df.columns)
    
    if missing_cols:
        return False, f"Missing columns in CSV: {missing_cols}"

    if len(df) == 0:
        return False, "CSV file is empty"

    # Check for NaN values in critical columns
    critical_cols = ["coefficient", "p_value"]
    nan_counts = df[critical_cols].isna().sum()
    if nan_counts.any():
        logger.warning(f"Found NaN values in critical columns: {nan_counts[nan_counts > 0].to_dict()}")

    logger.info(f"CSV structure valid. Found {len(df)} records.")
    return True, "CSV structure is valid"


def main():
    """
    Main entry point for T023.
    
    Verifies that T020 has successfully produced the required output files
    and validates their structure.
    """
    logger.info("Starting T023: Correlation Results Checkpoint")
    
    # Ensure output directory exists (though files should be written by T020)
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Verify JSON file
    json_valid, json_msg = validate_json_structure(RESULTS_JSON_PATH)
    logger.info(f"JSON Validation: {json_msg}")

    # 2. Verify CSV file
    csv_valid, csv_msg = validate_csv_structure(SUMMARY_CSV_PATH)
    logger.info(f"CSV Validation: {csv_msg}")

    # 3. Final verdict
    if json_valid and csv_valid:
        logger.info("T023 PASSED: All correlation result files exist and are valid.")
        return 0
    else:
        logger.error("T023 FAILED: One or more validation checks failed.")
        logger.error(f"  JSON: {json_msg}")
        logger.error(f"  CSV: {csv_msg}")
        # Note: We do not exit with error code 1 here if the files are missing,
        # because T020 might not have run yet in a clean environment.
        # However, for this task to be 'completed', the files MUST exist.
        # If they don't exist, this task effectively cannot be marked as done
        # in the context of a full pipeline run.
        # We return 1 to indicate the checkpoint failed.
        return 1


if __name__ == "__main__":
    sys.exit(main())
