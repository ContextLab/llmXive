"""
Bootstrap resampling module for statistical validation of correlation results.

This module implements run_bootstrap_resampling to estimate confidence intervals
for max correlation coefficients using n=1000 iterations.
"""
import os
import sys
import json
import logging
import numpy as np
from pathlib import Path
from typing import Dict, List, Tuple, Any, Optional
from scipy import stats

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from code.utils.logging import setup_logger

logger = setup_logger("bootstrap_analysis", level=logging.INFO)


def load_correlation_data(input_path: str) -> pd.DataFrame:
    """
    Load correlation results from the CSV generated by T020.
    
    Args:
        input_path: Path to correlation_summary.csv or correlation_results.csv
        
    Returns:
        DataFrame containing correlation data
    """
    import pandas as pd
    path = Path(input_path)
    if not path.exists():
        raise FileNotFoundError(f"Correlation results file not found: {input_path}")
    
    # Try loading the summary CSV first (aggregated by species/rigidity/lag)
    # If that fails or is empty, try the detailed JSON
    try:
        df = pd.read_csv(path)
        if df.empty:
            raise ValueError("CSV file is empty")
        return df
    except Exception:
        # Fallback to JSON if CSV fails
        json_path = path.with_suffix('.json')
        if json_path.exists():
            with open(json_path, 'r') as f:
                data = json.load(f)
            return pd.DataFrame(data)
        raise ValueError("Could not load correlation data from CSV or JSON")


def run_bootstrap_resampling(
    input_path: str,
    output_path: str,
    n_iterations: int = 1000,
    confidence_level: float = 0.95,
    seed: Optional[int] = 42
) -> Dict[str, Any]:
    """
    Perform bootstrap resampling to estimate confidence intervals for max correlation coefficients.
    
    This function:
    1. Loads correlation results (coefficients and p-values)
    2. Identifies the maximum absolute correlation for each species/rigidity group
    3. Resamples the time-series data (via resampling the correlation coefficients)
    4. Calculates bootstrap confidence intervals
    5. Saves results to output_path
    
    Args:
        input_path: Path to correlation_summary.csv
        output_path: Path to save bootstrap results JSON
        n_iterations: Number of bootstrap iterations (default: 1000)
        confidence_level: Confidence level for intervals (default: 0.95)
        seed: Random seed for reproducibility
        
    Returns:
        Dictionary containing bootstrap results summary
    """
    import pandas as pd
    
    if seed is not None:
        np.random.seed(seed)
    
    logger.info(f"Starting bootstrap resampling with {n_iterations} iterations")
    logger.info(f"Input file: {input_path}")
    logger.info(f"Output file: {output_path}")
    
    # Load data
    try:
        df = load_correlation_data(input_path)
    except Exception as e:
        logger.error(f"Failed to load correlation data: {e}")
        raise
    
    # Ensure required columns exist
    required_cols = ['species', 'rigidity', 'lag_months', 'correlation', 'p_value']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        # Try alternative column names
        col_mapping = {
            'species': ['species_name', 'element'],
            'rigidity': ['rigidity_bin', 'R'],
            'lag_months': ['lag', 'lag_month'],
            'correlation': ['corr', 'r_value', 'pearson_r'],
            'p_value': ['pval', 'p']
        }
        
        for col in missing_cols:
            if col in col_mapping:
                for alt in col_mapping[col]:
                    if alt in df.columns:
                        df[col] = df[alt]
                        break
        
        # Check again
        missing_cols = [col for col in required_cols if col not in df.columns]
        if missing_cols:
            raise ValueError(f"Missing required columns: {missing_cols}. Available: {df.columns.tolist()}")
    
    logger.info(f"Loaded {len(df)} correlation records")
    
    # Group by species and rigidity to find max correlations
    # We'll resample the correlation coefficients for each group
    bootstrap_results = {}
    
    # Identify unique groups
    groups = df.groupby(['species', 'rigidity']).size().reset_index()
    logger.info(f"Found {len(groups)} unique species-rigidity groups")
    
    for _, group in groups.iterrows():
        species = group['species']
        rigidity = group['rigidity']
        
        # Filter data for this group
        group_data = df[(df['species'] == species) & (df['rigidity'] == rigidity)]
        
        if len(group_data) == 0:
            logger.warning(f"No data for {species} at rigidity {rigidity}")
            continue
        
        # Get correlation coefficients for this group
        corrs = group_data['correlation'].values
        
        if len(corrs) < 2:
            logger.warning(f"Not enough data points ({len(corrs)}) for bootstrap in {species} at rigidity {rigidity}")
            continue
        
        # Find the max correlation (by absolute value) for the original data
        max_corr_idx = np.argmax(np.abs(corrs))
        max_corr_original = corrs[max_corr_idx]
        
        # Bootstrap resampling
        bootstrap_max_corrs = np.zeros(n_iterations)
        
        logger.info(f"Running {n_iterations} bootstrap iterations for {species} at rigidity {rigidity}")
        
        for i in range(n_iterations):
            # Resample with replacement
            resampled_indices = np.random.choice(len(corrs), size=len(corrs), replace=True)
            resampled_corrs = corrs[resampled_indices]
            
            # Find max correlation in resampled data
            max_idx = np.argmax(np.abs(resampled_corrs))
            bootstrap_max_corrs[i] = resampled_corrs[max_idx]
        
        # Calculate confidence intervals
        alpha = 1 - confidence_level
        ci_lower = np.percentile(bootstrap_max_corrs, (alpha / 2) * 100)
        ci_upper = np.percentile(bootstrap_max_corrs, (1 - alpha / 2) * 100)
        
        # Calculate mean and std of bootstrap distribution
        bootstrap_mean = np.mean(bootstrap_max_corrs)
        bootstrap_std = np.std(bootstrap_max_corrs)
        
        # Store results
        key = f"{species}_{rigidity}"
        bootstrap_results[key] = {
            'species': species,
            'rigidity': rigidity,
            'original_max_correlation': float(max_corr_original),
            'bootstrap_mean': float(bootstrap_mean),
            'bootstrap_std': float(bootstrap_std),
            'ci_lower': float(ci_lower),
            'ci_upper': float(ci_upper),
            'confidence_level': confidence_level,
            'n_iterations': n_iterations,
            'n_samples': len(corrs)
        }
        
        logger.info(f"  Max corr: {max_corr_original:.4f}, CI: [{ci_lower:.4f}, {ci_upper:.4f}]")
    
    # Prepare output
    output_data = {
        'bootstrap_parameters': {
            'n_iterations': n_iterations,
            'confidence_level': confidence_level,
            'seed': seed
        },
        'results': bootstrap_results,
        'summary': {
            'total_groups': len(bootstrap_results),
            'successful_iterations': n_iterations
        }
    }
    
    # Save to JSON
    output_dir = Path(output_path).parent
    output_dir.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(output_data, f, indent=2)
    
    logger.info(f"Bootstrap results saved to {output_path}")
    
    return output_data


def main():
    """Main entry point for bootstrap resampling analysis."""
    # Define paths
    input_file = PROJECT_ROOT / "data" / "processed" / "correlation_summary.csv"
    output_file = PROJECT_ROOT / "data" / "processed" / "bootstrap_results.json"
    
    # Check if input exists
    if not input_file.exists():
        logger.error(f"Input file not found: {input_file}")
        logger.error("Please run the correlation analysis (T020) first to generate correlation_summary.csv")
        sys.exit(1)
    
    try:
        results = run_bootstrap_resampling(
            input_path=str(input_file),
            output_path=str(output_file),
            n_iterations=1000,
            confidence_level=0.95,
            seed=42
        )
        
        logger.info("Bootstrap resampling completed successfully")
        logger.info(f"Analyzed {results['summary']['total_groups']} species-rigidity groups")
        
        # Print summary
        print("\nBootstrap Resampling Summary:")
        print("-" * 50)
        for key, res in results['results'].items():
            print(f"{key}:")
            print(f"  Original max corr: {res['original_max_correlation']:.4f}")
            print(f"  95% CI: [{res['ci_lower']:.4f}, {res['ci_upper']:.4f}]")
            print(f"  Bootstrap mean: {res['bootstrap_mean']:.4f} (±{res['bootstrap_std']:.4f})")
            print()
            
    except Exception as e:
        logger.error(f"Bootstrap resampling failed: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()
