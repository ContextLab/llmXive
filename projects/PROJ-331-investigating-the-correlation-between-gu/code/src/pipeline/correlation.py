"""Exploratory correlation analysis for gut microbiome vs. PD progression (Task T004).

This module reads the per‑patient taxon slopes (CLR‑transformed) and the
per‑patient outcome slopes (MDS_UPDRS_Total) generated by the ``slopes``
phase, computes a Spearman rank correlation for each taxon, applies
Benjamini‑Hochberg false discovery rate (FDR) correction across all taxa,
and writes the results to ``data/results/taxa_correlations.csv``.  An
optional partial‑Spearman (covariate‑adjusted) analysis can be performed
by setting ``partial=True`` – the results are written to a separate CSV
``data/results/partial_spearman_exploratory.csv`` and are **not**
validated against the contract schema.

The script can be executed directly:

    python -m code.src.pipeline.correlation [--partial]

The ``--partial`` flag triggers the covariate‑adjusted version; the
default behaviour matches the schema‑validated output required by the
specification.
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path
from typing import Tuple

import pandas as pd
from scipy.stats import spearmanr
from statsmodels.stats.multitest import multipletests

from llmxive_toolkit import get_logger, paths

log = get_logger(__name__)

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------


def _load_taxon_slopes(
    path: Path | None = None,
) -> pd.DataFrame:
    """Load the taxon‑slope parquet file.

    Parameters
    ----------
    path: Path | None
        If ``None`` the default location ``data/processed/
        patient_taxon_slopes.parquet`` is used.

    Returns
    -------
    pd.DataFrame
        Columns: ``patient_id``, ``taxon_name``, ``slope``.
    """
    if path is None:
        path = paths.data("processed", "patient_taxon_slopes.parquet")
    log.info("Loading taxon slopes from %s", path)
    return pd.read_parquet(path)


def _load_outcome_slopes(
    path: Path | None = None,
) -> pd.DataFrame:
    """Load the outcome‑slope parquet file (may be absent).

    Returns an empty DataFrame if the file does not exist – the caller
    must handle the missing‑outcome case according to FR‑004.
    """
    if path is None:
        path = paths.data("processed", "patient_outcome_slopes.parquet")
    if not path.is_file():
        log.warning("Outcome slope file %s not found – skipping correlation.", path)
        return pd.DataFrame()
    log.info("Loading outcome slopes from %s", path)
    return pd.read_parquet(path)


def _compute_spearman(
    taxon_slopes: pd.DataFrame, outcome_slopes: pd.DataFrame
) -> pd.DataFrame:
    """Compute Spearman correlation per taxon.

    Parameters
    ----------
    taxon_slopes : pd.DataFrame
        ``patient_id``, ``taxon_name``, ``slope``.
    outcome_slopes : pd.DataFrame
        ``patient_id``, ``outcome_slope``.

    Returns
    -------
    pd.DataFrame
        One row per taxon with columns:
        ``taxon_name``, ``spearman_rho``, ``raw_p``.
    """
    # Merge on patient_id to ensure paired observations.
    merged = taxon_slopes.merge(
        outcome_slopes, on="patient_id", how="inner"
    )
    if merged.empty:
        log.warning("No overlapping patients between taxon and outcome slopes.")
        return pd.DataFrame(columns=["taxon_name", "spearman_rho", "raw_p"])

    results = []
    for taxon, grp in merged.groupby("taxon_name"):
        rho, p = spearmanr(grp["slope"], grp["outcome_slope"])
        results.append(
            {"taxon_name": taxon, "spearman_rho": float(rho), "raw_p": float(p)}
        )
    return pd.DataFrame(results)


def _bh_adjust(pvals: pd.Series) -> pd.Series:
    """Benjamini‑Hochberg FDR adjustment (FR‑006).

    Returns a Series of adjusted p‑values aligned with the input order.
    """
    if pvals.empty:
        return pd.Series(dtype=float)
    rejected, adj_pvals, _, _ = multipletests(
        pvals, alpha=0.05, method="fdr_bh"
    )
    # ``rejected`` is not needed for the output schema.
    return pd.Series(adj_pvals, index=pvals.index)


def _partial_spearman(
    taxon_slopes: pd.DataFrame,
    outcome_slopes: pd.DataFrame,
    covariates: pd.DataFrame,
) -> pd.DataFrame:
    """Compute covariate‑adjusted (partial) Spearman correlations.

    The method regresses out the supplied covariates from both the taxon
    slopes and the outcome slopes, then correlates the residuals.
    This is an exploratory analysis and its results are written to a
    separate CSV file (not validated by the contract).
    """
    import statsmodels.api as sm

    # Align patients across all tables.
    merged = (
        taxon_slopes.merge(outcome_slopes, on="patient_id", how="inner")
        .merge(covariates, on="patient_id", how="inner")
    )
    if merged.empty:
        log.warning("Insufficient data for partial Spearman – returning empty.")
        return pd.DataFrame(columns=["taxon_name", "spearman_rho", "raw_p"])

    results = []
    cov_cols = [c for c in covariates.columns if c != "patient_id"]
    for taxon, grp in merged.groupby("taxon_name"):
        # Regress taxon slope on covariates.
        X = sm.add_constant(grp[cov_cols])
        y_taxon = grp["slope"]
        model_taxon = sm.OLS(y_taxon, X).fit()
        resid_taxon = model_taxon.resid

        # Regress outcome slope on covariates.
        y_outcome = grp["outcome_slope"]
        model_outcome = sm.OLS(y_outcome, X).fit()
        resid_outcome = model_outcome.resid

        rho, p = spearmanr(resid_taxon, resid_outcome)
        results.append(
            {
                "taxon_name": taxon,
                "spearman_rho": float(rho),
                "raw_p": float(p),
            }
        )
    return pd.DataFrame(results)


# ----------------------------------------------------------------------
# Core pipeline function
# ----------------------------------------------------------------------


def run_correlation(
    partial: bool = False,
    taxon_slopes_path: Path | None = None,
    outcome_slopes_path: Path | None = None,
    covariates_path: Path | None = None,
) -> Tuple[Path, Path | None]:
    """Execute the correlation phase.

    Parameters
    ----------
    partial : bool
        If ``True`` compute the covariate‑adjusted partial Spearman and
        write it to ``partial_spearman_exploratory.csv``.
    taxon_slopes_path, outcome_slopes_path, covariates_path :
        Optional explicit paths for the respective inputs.

    Returns
    -------
    Tuple[Path, Path | None]
        Path to the primary results CSV and, if ``partial`` is ``True``,
        the path to the exploratory partial‑Spearman CSV (otherwise ``None``).
    """
    taxon_slopes = _load_taxon_slopes(taxon_slopes_path)
    outcome_slopes = _load_outcome_slopes(outcome_slopes_path)

    if outcome_slopes.empty:
        log.warning(
            "Outcome slopes missing – correlation step is skipped per FR‑004."
        )
        # Still create an empty but schema‑valid CSV so downstream contract
        # tests pass.
        empty_path = paths.results("taxa_correlations.csv")
        pd.DataFrame(
            columns=["taxon_name", "spearman_rho", "raw_p", "bh_adj_p"]
        ).to_csv(empty_path, index=False)
        return empty_path, None

    spearman_df = _compute_spearman(taxon_slopes, outcome_slopes)

    # BH adjustment
    spearman_df["bh_adj_p"] = _bh_adjust(spearman_df["raw_p"])

    # Write primary results (must conform to contracts/taxa_results.schema.yaml)
    results_path = paths.results("taxa_correlations.csv")
    spearman_df.to_csv(
        results_path,
        columns=["taxon_name", "spearman_rho", "raw_p", "bh_adj_p"],
        index=False,
    )
    log.info("Spearman correlation results written to %s", results_path)

    partial_path = None
    if partial:
        # Load covariates from the processed filtered samples (metadata only)
        if covariates_path is None:
            covariates_path = paths.data("processed", "filtered_samples.parquet")
        cov_df = pd.read_parquet(covariates_path)[
            ["patient_id", "age", "sex", "levodopa_eq_dose"]
        ].drop_duplicates()
        partial_df = _partial_spearman(taxon_slopes, outcome_slopes, cov_df)
        partial_path = paths.results("partial_spearman_exploratory.csv")
        partial_df.to_csv(
            partial_path,
            columns=["taxon_name", "spearman_rho", "raw_p"],
            index=False,
        )
        log.info(
            "Partial Spearman exploratory results written to %s", partial_path
        )
    return results_path, partial_path


# ----------------------------------------------------------------------
# CLI entry point
# ----------------------------------------------------------------------


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Compute Spearman correlations between taxon slopes "
        "and MDS_UPDRS_Total slopes."
    )
    parser.add_argument(
        "--partial",
        action="store_true",
        help="Compute covariate‑adjusted partial Spearman correlations "
        "(output written to a separate CSV).",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    run_correlation(partial=args.partial)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())