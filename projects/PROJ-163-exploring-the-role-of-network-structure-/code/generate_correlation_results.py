def load_correlation_data() -> pd.DataFrame:
    """
    Load the correlation results computed by stats_engine.
    
    Since stats_engine computes correlations in memory, we re-run the pipeline
    up to the point of saving results to ensure we have the data.
    Alternatively, if stats_engine had a cache, we would load from there.
    For this implementation, we execute the pipeline steps.
    """
    logger.info("Loading and merging metrics from processed data...")
    
    # Load processed data files
    # Assuming T017 produced raw_calibration.csv and T025 produced graph_metrics.csv
    raw_cal_path = Path("data/processed/raw_calibration.csv")
    graph_metrics_path = Path("data/processed/graph_metrics.csv")
    
    if not raw_cal_path.exists():
        raise FileNotFoundError(f"Required file not found: {raw_cal_path}")
    if not graph_metrics_path.exists():
        raise FileNotFoundError(f"Required file not found: {graph_metrics_path}")
    
    df_perf = pd.read_csv(raw_cal_path)
    df_graph = pd.read_csv(graph_metrics_path)
    
    # Merge metrics
    # The stats_engine function handles the join logic
    # We call the internal logic or re-implement the merge here to get the base DF
    # Based on T028/T029, we join on device_id.
    
    # Ensure device_id is string for consistent merging
    df_perf['device_id'] = df_perf['device_id'].astype(str)
    df_graph['device_id'] = df_graph['device_id'].astype(str)
    
    # Pivot graph metrics to wide format for merging
    # Expected columns in graph_metrics: device_id, metric_name, value
    graph_wide = df_graph.pivot(index='device_id', columns='metric_name', values='value').reset_index()
    
    # Pivot performance metrics to wide format
    # Expected columns in raw_calibration: device_id, metric_name, value (or specific columns)
    # T017 output structure: device_id, metric_name, value (based on standard pattern)
    perf_wide = df_perf.pivot(index='device_id', columns='metric_name', values='value').reset_index()
    
    # Merge
    merged_df = pd.merge(graph_wide, perf_wide, on='device_id', how='inner')
    
    if merged_df.empty:
        raise ValueError("No devices found with both graph and performance metrics.")
    
    logger.info(f"Merged dataset shape: {merged_df.shape}")
    return merged_df

