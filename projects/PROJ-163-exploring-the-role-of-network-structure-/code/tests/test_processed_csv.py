"""
Test suite for the performance metrics CSV generated by
`code/generate_calibration_csv.py`.

The test verifies:
1. The CSV file exists.
2. It contains at least one data row (excluding the header).
3. No numeric column contains NaN or infinite values.
4. Each row conforms to the JSON schema defined in
   `specs/001-exploring-the-role-of-network-structure/contracts/performance_metrics.schema.yaml`.
"""

import os
from pathlib import Path

import pandas as pd
import pytest
from jsonschema import validate, ValidationError

# Path to the generated CSV
CSV_PATH = Path("data/processed/performance_metrics.csv")

# Path to the JSON schema
SCHEMA_PATH = Path(
    "specs/001-exploring-the-role-of-network-structure/contracts/performance_metrics.schema.yaml"
)


@pytest.fixture(scope="module")
def csv_df():
    """Load the CSV into a DataFrame; skip test if file is missing."""
    if not CSV_PATH.is_file():
        pytest.skip(f"Performance metrics CSV not found at {CSV_PATH}")
    df = pd.read_csv(CSV_PATH)
    return df


@pytest.fixture(scope="module")
def schema():
    """Load the JSON schema."""
    if not SCHEMA_PATH.is_file():
        pytest.fail(f"Schema file not found at {SCHEMA_PATH}")
    import yaml

    with open(SCHEMA_PATH, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def test_csv_exists():
    """The CSV file must exist."""
    assert CSV_PATH.is_file(), f"Expected CSV at {CSV_PATH}"


def test_csv_non_empty(csv_df):
    """CSV must contain at least one data row."""
    # pandas includes header as column names; ensure there is at least one row
    assert len(csv_df) > 0, "Performance metrics CSV is empty (no data rows)."


def test_numeric_columns_finite(csv_df):
    """Numeric columns must not contain NaN or infinite values."""
    numeric_cols = [
        "t1_mean",
        "t2_mean",
        "cx_error_mean",
        "readout_error_mean",
    ]
    for col in numeric_cols:
        assert col in csv_df.columns, f"Missing expected column: {col}"
        series = pd.to_numeric(csv_df[col], errors="coerce")
        assert not series.isnull().any(), f"Column {col} contains NaN values."
        assert not series.isin([float("inf"), float("-inf")]).any(), (
            f"Column {col} contains infinite values."
        )


def test_rows_conform_to_schema(csv_df, schema):
    """Each row must validate against the JSON schema."""
    for idx, row in csv_df.iterrows():
        # Convert pandas Series to dict with native Python types
        instance = {
            "device_id": str(row["device_id"]),
            "timestamp": str(row["timestamp"]),
            "t1_mean": float(row["t1_mean"]),
            "t2_mean": float(row["t2_mean"]),
            "cx_error_mean": float(row["cx_error_mean"]),
            "readout_error_mean": float(row["readout_error_mean"]),
            "chip_family": str(row["chip_family"]),
        }
        try:
            validate(instance=instance, schema=schema)
        except ValidationError as e:
            pytest.fail(
                f"Row {idx} failed schema validation: {e.message}\n"
                f"Instance: {instance}"
            )

# Optional: ensure timestamps are recent (≤30 days) as per FR‑001
def test_timestamps_fresh(csv_df):
    """All timestamps must be within 30 days of now."""
    from datetime import datetime, timezone

    now = datetime.now(timezone.utc)
    max_age_days = 30
    for idx, ts in enumerate(csv_df["timestamp"]):
        try:
            ts_dt = pd.to_datetime(ts, utc=True)
        except Exception:
            pytest.fail(f"Invalid timestamp format at row {idx}: {ts}")
        age_days = (now - ts_dt).total_seconds() / 86400.0
        assert age_days <= max_age_days, (
            f"Row {idx} has stale data ({age_days:.1f} days old)."
        )