"""
Generate graph metrics CSV from processed calibration data.

This script reads the raw calibration CSV generated by T017, constructs
connectivity graphs for each device using the graph_builder module,
computes topological metrics, and saves the results to data/processed/graph_metrics.csv.
"""
import os
import csv
import logging
from pathlib import Path
from typing import List, Dict, Any, Tuple, Optional
import pandas as pd

from graph_builder import (
    build_coupling_graph,
    compute_shortest_path_metrics,
    compute_clustering_and_assortativity,
    compute_edge_betweenness_and_spectral_gap,
    process_device_coupling_map
)
from logger import setup_logger

# Setup logging
logger = setup_logger(__name__)

def load_processed_calibration(csv_path: str) -> pd.DataFrame:
    """
    Load the processed calibration CSV containing coupling maps.

    Args:
        csv_path: Path to the raw_calibration.csv file.

    Returns:
        DataFrame with device metrics including coupling_map.
    """
    path = Path(csv_path)
    if not path.exists():
        raise FileNotFoundError(f"Processed calibration file not found: {csv_path}")

    df = pd.read_csv(csv_path)

    required_columns = ['device_id', 'timestamp', 'coupling_map']
    missing = [col for col in required_columns if col not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in {csv_path}: {missing}")

    # Ensure coupling_map is a list of tuples/lists, not a string representation
    def parse_coupling_map(cm_str):
        if isinstance(cm_str, list):
            return cm_str
        # Try to parse string representation if loaded as string
        try:
            import ast
            parsed = ast.literal_eval(cm_str)
            return parsed
        except (ValueError, SyntaxError):
            logger.warning(f"Could not parse coupling map for device, treating as empty: {cm_str}")
            return []

    df['coupling_map_parsed'] = df['coupling_map'].apply(parse_coupling_map)
    return df

def compute_device_metrics(device_id: str, coupling_map: List[Tuple[int, int]]) -> List[Dict[str, Any]]:
    """
    Compute all graph metrics for a single device.

    Args:
        device_id: The device identifier.
        coupling_map: List of (u, v) edges.

    Returns:
        List of dictionaries containing metric_name, value, and is_finite.
    """
    metrics = []

    if not coupling_map:
        logger.warning(f"No coupling map for {device_id}, skipping metrics.")
        return metrics

    try:
        graph = build_coupling_graph(coupling_map)
    except Exception as e:
        logger.error(f"Failed to build graph for {device_id}: {e}")
        return metrics

    # 1. Shortest Path Metrics
    path_metrics = compute_shortest_path_metrics(graph)
    for name, val in path_metrics.items():
        is_finite = pd.notna(val) and not (isinstance(val, float) and (val != val)) # Check NaN
        if isinstance(val, float):
            is_finite = is_finite and (val != float('inf'))
        metrics.append({
            'device_id': device_id,
            'metric_name': f'shortest_path_{name}',
            'value': val if is_finite else None,
            'is_finite': is_finite
        })

    # 2. Clustering and Assortativity
    cluster_metrics = compute_clustering_and_assortativity(graph)
    for name, val in cluster_metrics.items():
        is_finite = pd.notna(val) and (val != float('inf'))
        metrics.append({
            'device_id': device_id,
            'metric_name': f'clustering_{name}',
            'value': val if is_finite else None,
            'is_finite': is_finite
        })

    # 3. Edge Betweenness and Spectral Gap
    spectral_metrics = compute_edge_betweenness_and_spectral_gap(graph)
    for name, val in spectral_metrics.items():
        is_finite = pd.notna(val) and (val != float('inf'))
        metrics.append({
            'device_id': device_id,
            'metric_name': f'spectral_{name}',
            'value': val if is_finite else None,
            'is_finite': is_finite
        })

    return metrics

def main():
    """Main entry point to generate graph metrics CSV."""
    logger.info("Starting graph metrics generation...")

    # Paths
    input_path = "data/processed/raw_calibration.csv"
    output_path = "data/processed/graph_metrics.csv"

    # Ensure output directory exists
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)

    try:
        df = load_processed_calibration(input_path)
    except FileNotFoundError as e:
        logger.error(str(e))
        return 1
    except ValueError as e:
        logger.error(str(e))
        return 1

    all_metrics = []

    logger.info(f"Processing {len(df)} devices...")
    for _, row in df.iterrows():
        device_id = row['device_id']
        coupling_map = row['coupling_map_parsed']
        device_metrics = compute_device_metrics(device_id, coupling_map)
        all_metrics.extend(device_metrics)

    if not all_metrics:
        logger.warning("No metrics computed. Check if coupling maps are empty.")
        # Create empty file with headers to satisfy verification
        with open(output_path, 'w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=['device_id', 'metric_name', 'value', 'is_finite'])
            writer.writeheader()
        return 0

    # Write to CSV
    try:
        with open(output_path, 'w', newline='') as f:
            fieldnames = ['device_id', 'metric_name', 'value', 'is_finite']
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(all_metrics)

        logger.info(f"Successfully wrote {len(all_metrics)} metrics to {output_path}")

        # Verification: Read back and count
        verify_df = pd.read_csv(output_path)
        assert 'device_id' in verify_df.columns, "Missing device_id column"
        assert 'metric_name' in verify_df.columns, "Missing metric_name column"
        assert 'value' in verify_df.columns, "Missing value column"
        assert 'is_finite' in verify_df.columns, "Missing is_finite column"
        assert len(verify_df) > 0, "Output file is empty"

        logger.info("Verification passed: Columns and row count are correct.")
        return 0

    except Exception as e:
        logger.error(f"Failed to write output file: {e}")
        return 1

if __name__ == "__main__":
    exit(main())
