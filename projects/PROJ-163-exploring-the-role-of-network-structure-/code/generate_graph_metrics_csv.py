import os
import csv
import logging
from pathlib import Path
from typing import List, Dict, Any, Tuple, Optional
import pandas as pd

from graph_builder import process_device_coupling_map
from fetcher import extract_topology_data, extract_performance_metrics
from logger import setup_logger

logger = setup_logger(__name__)

def load_processed_calibration(csv_path: str) -> pd.DataFrame:
    """
    Load the processed calibration CSV generated by T017.
    Expects columns: device_id, coupling_map (list repr), t1, t2, cx_error, readout_error, timestamp.
    """
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Processed calibration file not found: {csv_path}")

    df = pd.read_csv(csv_path)
    # Parse the coupling_map string back into a list of lists if necessary
    # The CSV likely stores it as a string representation like "[[0, 1], [1, 2]]"
    # or as a JSON string. We'll use ast.literal_eval or json.loads.
    import ast
    import json

    def parse_coupling_map(val):
        if isinstance(val, list):
            return val
        if pd.isna(val):
            return []
        try:
            # Try JSON first
            return json.loads(val)
        except (json.JSONDecodeError, TypeError):
            try:
                # Fallback to ast.literal_eval
                return ast.literal_eval(val)
            except (ValueError, SyntaxError):
                logger.warning(f"Could not parse coupling map: {val}")
                return []

    df['coupling_map_parsed'] = df['coupling_map'].apply(parse_coupling_map)
    return df

def compute_device_metrics(df: pd.DataFrame) -> List[Dict[str, Any]]:
    """
    Compute graph metrics for each device in the dataframe.
    """
    results = []
    for _, row in df.iterrows():
        device_id = row['device_id']
        coupling_map = row['coupling_map_parsed']

        if not coupling_map:
            logger.warning(f"No coupling map for {device_id}, skipping graph metrics.")
            continue

        try:
            metrics = process_device_coupling_map(device_id, coupling_map)
            results.append(metrics)
        except Exception as e:
            logger.error(f"Error computing metrics for {device_id}: {e}")
            # Add a placeholder entry with NaNs to maintain row count if needed
            results.append({
                'device_id': device_id,
                'num_nodes': 0,
                'num_edges': 0,
                'avg_shortest_path': float('nan'),
                'diameter': float('nan'),
                'clustering_coefficient': float('nan'),
                'assortativity': float('nan'),
                'edge_betweenness_mean': float('nan'),
                'edge_betweenness_std': float('nan'),
                'spectral_gap': float('nan'),
                'is_finite': False
            })
    return results

def main():
    """
    Main execution function.
    Reads data/processed/raw_calibration.csv, computes graph metrics,
    and writes data/processed/graph_metrics.csv.
    """
    base_dir = Path(__name__).parent if '__name__' in globals() else Path.cwd()
    # Adjust path relative to project root (assuming script is run from project root)
    input_path = Path("data/processed/raw_calibration.csv")
    output_path = Path("data/processed/graph_metrics.csv")

    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}. "
                                "Please run T017 (generate_calibration_csv.py) first.")

    logger.info(f"Loading data from {input_path}")
    df = load_processed_calibration(str(input_path))

    logger.info(f"Computing graph metrics for {len(df)} devices...")
    results = compute_device_metrics(df)

    if not results:
        logger.warning("No results computed. Check input data.")
        return

    logger.info(f"Writing results to {output_path}")
    # Define columns explicitly to ensure order
    columns = [
        'device_id', 'num_nodes', 'num_edges',
        'avg_shortest_path', 'diameter',
        'clustering_coefficient', 'assortativity',
        'edge_betweenness_mean', 'edge_betweenness_std',
        'spectral_gap', 'is_finite'
    ]

    # Prepare dataframe
    result_df = pd.DataFrame(results)
    
    # Ensure all columns exist
    for col in columns:
        if col not in result_df.columns:
            result_df[col] = float('nan')

    result_df.to_csv(output_path, index=False)
    logger.info(f"Successfully wrote {len(result_df)} rows to {output_path}")

if __name__ == "__main__":
    main()
