# Configure logging
LOG = logger.setup_logger(__name__)

def load_processed_calibration(csv_path: str) -> pd.DataFrame:
    """
    Load the processed calibration CSV generated by T017.
    
    Expected columns include 'device_id', 'coupling_map' (as string/list),
    and performance metrics.
    """
    if not os.path.exists(csv_path):
        raise FileNotFoundError(
            f"Processed calibration file not found at {csv_path}. "
            "Please ensure T017 (generate_calibration_csv) has been run first."
        )
    
    LOG.info(f"Loading processed calibration data from {csv_path}")
    df = pd.read_csv(csv_path)
    
    # Ensure coupling_map is parsed if stored as string
    if 'coupling_map' in df.columns:
        # If it's a string representation of a list, parse it
        # Otherwise assume it's already a list or JSON
        def parse_coupling_map(val):
            if isinstance(val, list):
                return val
            if isinstance(val, str):
                # Simple eval for list of lists, or json.loads
                import json
