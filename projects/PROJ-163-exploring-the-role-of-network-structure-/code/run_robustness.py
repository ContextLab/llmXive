"""
Run robustness checks for the analysis pipeline.

This script performs the Leave‑One‑Device‑Out (LODO) robustness analysis
and verifies the bootstrap stability score generated by T005.  It is
intended to be invoked as part of the test suite (see
`code/tests/test_stats_engine.py`) and can also be run manually.

Expected outputs:
  - data/processed/robustness_results.csv
  - data/processed/stability_score.txt  (generated by T005 if not already present)
"""
import logging
from pathlib import Path

# The project treats the ``code`` directory as a package root; imports are
# performed directly from the module name (e.g. ``stats_engine``) as done in
# other scripts such as ``generate_correlation_results.py``.
from stats_engine import (
    load_and_merge_metrics,
    leave_one_device_out,
    robustness_check_bootstrap,
)
from fetcher import compare_current_vs_historical

logger = logging.getLogger(__name__)

def _ensure_stability_score() -> None:
    """
    Ensure that the bootstrap stability score file exists.

    T005 is responsible for creating ``stability_score.txt`` via
    ``fetcher.compare_current_vs_historical``.  In case it has not been
    produced yet (e.g. when this script is run in isolation), we invoke
    the function here.  The function writes the required file and returns
    its path.
    """
    stability_path = Path("data/processed/stability_score.txt")
    if not stability_path.is_file():
        logger.info(
            "Stability score not found – generating it via fetcher.compare_current_vs_historical()"
        )
        compare_current_vs_historical()
    else:
        logger.info(f"Stability score already present at {stability_path}")

def main() -> None:
    """
    Execute the full robustness workflow:

    1. Load and merge performance and graph metrics.
    2. Run the LODO analysis and write ``robustness_results.csv``.
    3. Ensure a bootstrap stability score exists.
    4. Verify that the stability score meets the required threshold.
    """
    logging.basicConfig(level=logging.INFO)

    # ------------------------------------------------------------------
    # 1. Load merged dataset
    # ------------------------------------------------------------------
    logger.info("Loading and merging performance and graph metrics")
    merged_df = load_and_merge_metrics()

    # Determine numeric columns for the LODO analysis
    numeric_cols = merged_df.select_dtypes(include=[float, int]).columns.tolist()

    # ------------------------------------------------------------------
    # 2. LODO robustness check – writes the CSV
    # ------------------------------------------------------------------
    logger.info("Running Leave‑One‑Device‑Out robustness analysis")
    leave_one_device_out(merged_df, numeric_cols=numeric_cols)

    # ------------------------------------------------------------------
    # 3. Ensure stability score exists (generated by T005)
    # ------------------------------------------------------------------
    _ensure_stability_score()

    # ------------------------------------------------------------------
    # 4. Verify bootstrap stability score meets the ≥ 0.7 threshold
    # ------------------------------------------------------------------
    logger.info("Verifying bootstrap stability score")
    robustness_check_bootstrap()

    logger.info("Robustness checks completed successfully")

if __name__ == "__main__":
    main()
