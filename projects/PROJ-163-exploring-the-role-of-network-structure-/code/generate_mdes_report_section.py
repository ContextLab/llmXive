"""
Module to generate the MDES Sensitivity Report section for the final report.

This module loads the MDES report generated by T041 and formats it into a
tabular and narrative summary suitable for inclusion in docs/report.md.
"""
import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional

logger = logging.getLogger(__name__)

def load_mdes_report(report_path: str = "data/processed/MDES_report.json") -> Optional[Dict[str, Any]]:
    """
    Load the MDES report JSON file.
    
    Args:
        report_path: Path to the MDES report JSON file.
        
    Returns:
        Dictionary containing MDES data, or None if file not found/invalid.
    """
    path = Path(report_path)
    if not path.exists():
        logger.warning(f"MDES report not found at {report_path}. Skipping MDES section.")
        return None
    
    try:
        with open(path, 'r') as f:
            data = json.load(f)
        return data
    except (json.JSONDecodeError, IOError) as e:
        logger.error(f"Failed to load MDES report: {e}")
        return None

def generate_mdes_section(mdes_data: Dict[str, Any]) -> str:
    """
    Generate the Markdown section for the MDES Sensitivity Report.
    
    Args:
        mdes_data: Dictionary containing MDES analysis results.
        
    Returns:
        Markdown formatted string for the report.
    """
    lines = []
    lines.append("### Minimum Detectable Effect Size (MDES) Sensitivity Analysis")
    lines.append("")
    lines.append("This section presents the statistical power analysis for the observed correlations.")
    lines.append("The Minimum Detectable Effect Size (MDES) indicates the smallest correlation coefficient")
    lines.append("that can be reliably detected given the current sample size and statistical constraints.")
    lines.append("")
    
    # Extract values with defaults
    sample_size = mdes_data.get('sample_size', 0)
    mdes_val = mdes_data.get('mdes', 0.0)
    power = mdes_data.get('power', 0.8)
    alpha = mdes_data.get('alpha', 0.05)
    low_power_flag = mdes_data.get('low_power_flag', 'Unknown')
    confidence_interval = mdes_data.get('confidence_interval', [])
    
    # Summary Table
    lines.append("#### MDES Parameters")
    lines.append("")
    lines.append("| Parameter | Value |")
    lines.append("| :--- | :--- |")
    lines.append(f"| Sample Size (N) | {sample_size} |")
    lines.append(f"| Target Power | {power} |")
    lines.append(f"| Significance Level (α) | {alpha} |")
    lines.append(f"| **Minimum Detectable Effect (MDES)** | **{mdes_val:.4f}** |")
    lines.append(f"| 95% CI Width (Approx) | {confidence_interval[1] - confidence_interval[0]:.4f} |")
    lines.append("")
    
    # Interpretation
    lines.append("#### Interpretation and Implications")
    lines.append("")
    if "Low Power" in low_power_flag:
        lines.append(f"> **⚠️ Low Power Warning:** {low_power_flag}")
        lines.append("")
        lines.append("Due to the limited sample size (N < 30), the analysis has reduced sensitivity to")
        lines.append("detect small or moderate effect sizes. Correlations observed with p < 0.05 in this")
        lines.append("regime should be treated as **Exploratory Only** and require validation with a larger")
        lines.append("dataset before definitive conclusions can be drawn.")
        lines.append("")
        lines.append(f"Specifically, effects smaller than |ρ| ≈ {mdes_val:.2f} are unlikely to be detected")
        lines.append("with the current configuration. Non-significant results (p > 0.05) do not necessarily")
        lines.append("imply the absence of an effect; they may simply reflect insufficient statistical power.")
    else:
        lines.append(f"> **✅ Adequate Power:** {low_power_flag}")
        lines.append("")
        lines.append(f"The current sample size provides sufficient power to detect effects of magnitude")
        lines.append(f"ρ ≥ {mdes_val:.2f} with 80% probability at α = 0.05. Significant correlations (p < 0.05)")
        lines.append("are robust to the sample size limitations.")
    
    lines.append("")
    
    # Sensitivity Context
    lines.append("#### Sensitivity Context")
    lines.append("")
    lines.append("The MDES is calculated based on the Spearman rank-correlation test assumptions.")
    lines.append("Given the observed correlation coefficients in the `correlation_results.csv`:")
    lines.append("")
    lines.append("- Any observed |ρ| < MDES should be interpreted with caution as potentially spurious or")
    lines.append("  underpowered findings.")
    lines.append("- Any observed |ρ| > MDES that is statistically significant represents a robust finding")
    lines.append("  given the current data volume.")
    lines.append("")
    lines.append("For future iterations, increasing the sample size (N) would proportionally decrease the")
    lines.append("MDES, allowing for the detection of subtler network-structure effects on qubit performance.")
    
    return "\n".join(lines)

def main():
    """Main entry point for generating the MDES section."""
    logging.basicConfig(level=logging.INFO)
    
    mdes_data = load_mdes_report()
    
    if mdes_data is None:
        # If no MDES data, return a placeholder indicating missing data
        section = (
            "### Minimum Detectable Effect Size (MDES) Sensitivity Analysis\n\n"
            "> **Note:** The MDES report (`data/processed/MDES_report.json`) was not found or could not be loaded. "
            "This section is omitted pending the completion of the power analysis task (T041).\n"
        )
    else:
        section = generate_mdes_section(mdes_data)
        
    print(section)
    return section

if __name__ == "__main__":
    main()
