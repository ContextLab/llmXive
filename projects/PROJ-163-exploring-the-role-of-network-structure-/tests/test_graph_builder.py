logger = logging.getLogger(__name__)

# Path to the processed CSV generated by T017
PROCESSED_CSV_PATH = Path("data/processed/raw_calibration.csv")

def test_load_real_device_data():
    """
    Verify that real device data exists and can be loaded.
    This acts as a prerequisite check for the integration test.
    """
    assert PROCESSED_CSV_PATH.exists(), f"Processed data file not found: {PROCESSED_CSV_PATH}. Run T017 first."
    df = pd.read_csv(PROCESSED_CSV_PATH)
    assert len(df) > 0, "Processed data file is empty."
    # Check for expected columns
    required_cols = ["device_id", "coupling_map"]
    for col in required_cols:
        assert col in df.columns, f"Missing column {col} in {PROCESSED_CSV_PATH}"
    logger.info(f"Loaded {len(df)} devices from {PROCESSED_CSV_PATH}")

def test_build_graphs_from_real_devices():
    """
    Integration test: Build graphs for all real devices and verify basic properties.
    """
    df = pd.read_csv(PROCESSED_CSV_PATH)
    failed_devices = []
    successful_devices = []

    for _, row in df.iterrows():
        device_id = row["device_id"]
        coupling_map_str = row["coupling_map"]

        try:
            # Parse coupling map from string representation (list of lists)
            # The CSV likely stores it as a string like "[[0, 1], [1, 2]]"
            import ast
            coupling_map = ast.literal_eval(coupling_map_str)

            G = build_coupling_graph(coupling_map)
            assert isinstance(G, nx.Graph), "build_coupling_graph must return a NetworkX Graph"
            assert G.number_of_nodes() > 0, f"Graph for {device_id} has no nodes"
            successful_devices.append(device_id)
        except Exception as e:
            logger.warning(f"Failed to build graph for {device_id}: {e}")
            failed_devices.append((device_id, str(e)))

    # Assert that at least some devices succeeded
    assert len(successful_devices) > 0, "No devices were successfully processed."
    logger.info(f"Successfully built graphs for {len(successful_devices)} devices.")
    if failed_devices:
        logger.warning(f"Failed to build graphs for {len(failed_devices)} devices: {failed_devices}")

def test_compute_metrics_on_real_devices():
    """
    Integration test: Compute metrics for real devices and verify they are finite.
    """
    df = pd.read_csv(PROCESSED_CSV_PATH)
    metrics_found = {
        "shortest_path_length": False,
        "diameter": False,
        "clustering_coefficient": False,
        "assortativity": False,
        "spectral_gap": False
    }

    for _, row in df.iterrows():
        device_id = row["device_id"]
        coupling_map_str = row["coupling_map"]
        import ast
        coupling_map = ast.literal_eval(coupling_map_str)

        G = build_coupling_graph(coupling_map)

        # Test shortest path metrics
        try:
            avg_path, diameter = compute_shortest_path_metrics(G)
            if avg_path is not None:
                assert isinstance(avg_path, (int, float))
                if not nx.is_connected(G) and avg_path == float('inf'):
                    # Expected for disconnected graphs if not handled by component logic
                    pass
                else:
                    metrics_found["shortest_path_length"] = True
            if diameter is not None:
                metrics_found["diameter"] = True
        except Exception as e:
            logger.warning(f"Error computing path metrics for {device_id}: {e}")

        # Test clustering and assortativity
        try:
            clustering, assortativity = compute_clustering_and_assortativity(G)
            if clustering is not None:
                metrics_found["clustering_coefficient"] = True
            if assortativity is not None:
                metrics_found["assortativity"] = True
        except Exception as e:
            logger.warning(f"Error computing clustering/assortativity for {device_id}: {e}")

        # Test spectral gap
        try:
            edge_betweenness, spectral_gap = compute_edge_betweenness_and_spectral_gap(G)
            if spectral_gap is not None:
                metrics_found["spectral_gap"] = True
        except Exception as e:
            logger.warning(f"Error computing spectral gap for {device_id}: {e}")

    # Assert that we found at least some metrics
    found_count = sum(1 for v in metrics_found.values() if v)
    assert found_count > 0, "No metrics were successfully computed for any device."
    logger.info(f"Metrics found: {metrics_found}")

def test_process_device_coupling_map_integration():
    """
    Integration test: Run the full pipeline function for a subset of devices.
    """
    df = pd.read_csv(PROCESSED_CSV_PATH)
    # Test on first 5 devices to avoid timeout on large datasets
    test_devices = df.head(5)

    results = []
    for _, row in test_devices.iterrows():
        device_id = row["device_id"]
        coupling_map_str = row["coupling_map"]
        import ast
        coupling_map = ast.literal_eval(coupling_map_str)

        try:
            result = process_device_coupling_map(device_id, coupling_map)
            assert result is not None
            assert "device_id" in result
            assert result["device_id"] == device_id
            assert "is_connected" in result
            assert "avg_shortest_path" in result
            assert "clustering_coeff" in result
            results.append(result)
        except Exception as e:
            logger.error(f"Full pipeline failed for {device_id}: {e}")
            raise

    assert len(results) == len(test_devices), "Not all test devices produced results."
    logger.info(f"Successfully processed {len(results)} devices with full pipeline.")

