"""Unit tests for the T003 GitHub fetcher (no network required)."""
import sys
from pathlib import Path

CODE_DIR = Path(__file__).resolve().parents[2] / "code"
if str(CODE_DIR) not in sys.path:
    sys.path.insert(0, str(CODE_DIR))

from data.fetch_github import classify_pr_source_type, _safe_repo_name


def test_copilot_bot_is_llm():
    pr = {"user": {"login": "github-copilot"}, "title": "", "body": ""}
    assert classify_pr_source_type(pr) == "llm"


def test_dependabot_is_human():
    pr = {"user": {"login": "dependabot[bot]"}, "title": "", "body": ""}
    assert classify_pr_source_type(pr) == "human"


def test_copilot_marker_in_body_is_llm():
    pr = {"user": {"login": "alice"}, "title": "Fix", "body": "Generated by GitHub Copilot"}
    assert classify_pr_source_type(pr) == "llm"


def test_regular_user_is_human():
    pr = {"user": {"login": "alice"}, "title": "Fix bug", "body": "Some change"}
    assert classify_pr_source_type(pr) == "human"


def test_safe_repo_name():
    assert _safe_repo_name("psf/requests") == "psf_requests"