"""
Unit tests for the primary classification logic in classify_prs.py
"""
import pytest
import sys
from pathlib import Path

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from code.data.classify_prs import (
    is_llm_bot,
    is_human_bot,
    has_llm_signature,
    calculate_confidence_score,
    classify_prs
)

class TestBotDetection:
    def test_copilot_bot_detection(self):
        """Test that Copilot bots are detected as LLM bots."""
        assert is_llm_bot("copilot") is True
        assert is_llm_bot("CopilotBot") is True
        assert is_llm_bot("ai-bot") is True
        assert is_llm_bot("LLM-Generator") is True

    def test_human_bot_detection(self):
        """Test that human infrastructure bots are detected correctly."""
        assert is_human_bot("dependabot") is True
        assert is_human_bot("RenovateBot") is True
        assert is_human_bot("stale-bot") is True

    def test_regular_user_detection(self):
        """Test that regular users are not detected as bots."""
        assert is_llm_bot("john-doe") is False
        assert is_human_bot("jane-smith") is False

class TestSignatureDetection:
    def test_llm_signature_detection(self):
        """Test detection of LLM signatures in commit messages."""
        assert has_llm_signature("Generated by Copilot") is True
        assert has_llm_signature("Automated by Copilot") is True
        assert has_llm_signature("AI-generated code") is True
        assert has_llm_signature("LLM-assisted refactor") is True

    def test_no_signature(self):
        """Test that messages without signatures return False."""
        assert has_llm_signature("Regular commit message") is False
        assert has_llm_signature("") is False
        assert has_llm_signature(None) is False

class TestConfidenceScoring:
    def test_llm_bot_high_confidence(self):
        """Test that LLM bots get high confidence scores."""
        score = calculate_confidence_score("copilot", "Regular message")
        assert score >= 0.9

    def test_human_bot_low_confidence(self):
        """Test that human bots get low confidence scores."""
        score = calculate_confidence_score("dependabot", "Update dependency")
        assert score <= 0.1

    def test_llm_signature_boost(self):
        """Test that LLM signatures boost confidence."""
        score_no_sig = calculate_confidence_score("regular-user", "Regular message")
        score_with_sig = calculate_confidence_score("regular-user", "Generated by Copilot")
        assert score_with_sig > score_no_sig

    def test_ambiguous_case(self):
        """Test that ambiguous cases get scores around the threshold."""
        score = calculate_confidence_score("unknown-user", "Some message")
        assert 0.4 <= score <= 0.6

class TestClassification:
    def test_classification_output_structure(self):
        """Test that classification produces correct output structure."""
        test_prs = [
            {
                'id': 1,
                'user': {'login': 'copilot'},
                'title': 'Fix bug',
                'body': 'Fixed a bug'
            },
            {
                'id': 2,
                'user': {'login': 'dependabot'},
                'title': 'Update deps',
                'body': 'Updated dependencies'
            },
            {
                'id': 3,
                'user': {'login': 'regular-user'},
                'title': 'Regular PR',
                'body': 'Regular message'
            }
        ]

        classified = classify_prs(test_prs)

        assert len(classified) == 3

        # Check structure
        for pr in classified:
            assert 'pr_id' in pr
            assert 'source_type' in pr
            assert 'confidence_score' in pr
            assert 'flagged' in pr
            assert isinstance(pr['confidence_score'], float)
            assert 0.0 <= pr['confidence_score'] <= 1.0
            assert isinstance(pr['flagged'], bool)

    def test_llm_classification(self):
        """Test that LLM bots are classified as 'llm'."""
        test_prs = [
            {
                'id': 1,
                'user': {'login': 'copilot'},
                'title': 'Fix bug',
                'body': 'Generated by Copilot'
            }
        ]

        classified = classify_prs(test_prs)
        assert classified[0]['source_type'] == 'llm'
        assert classified[0]['flagged'] is False

    def test_human_classification(self):
        """Test that human bots are classified as 'human'."""
        test_prs = [
            {
                'id': 1,
                'user': {'login': 'dependabot'},
                'title': 'Update deps',
                'body': 'Updated dependencies'
            }
        ]

        classified = classify_prs(test_prs)
        assert classified[0]['source_type'] == 'human'
        assert classified[0]['flagged'] is True

    def test_flagged_ambiguous_cases(self):
        """Test that ambiguous cases are flagged."""
        test_prs = [
            {
                'id': 1,
                'user': {'login': 'unknown-user'},
                'title': 'Some PR',
                'body': 'Some message'
            }
        ]

        classified = classify_prs(test_prs)
        # Unknown users should be flagged if confidence is below threshold
        # The exact behavior depends on the scoring logic
        assert 'flagged' in classified[0]

class TestEdgeCases:
    def test_empty_message(self):
        """Test handling of empty commit messages."""
        score = calculate_confidence_score("regular-user", "")
        assert isinstance(score, float)
        assert 0.0 <= score <= 1.0

    def test_none_message(self):
        """Test handling of None commit messages."""
        score = calculate_confidence_score("regular-user", None)
        assert isinstance(score, float)
        assert 0.0 <= score <= 1.0

    def test_special_characters_in_username(self):
        """Test handling of usernames with special characters."""
        assert is_llm_bot("copilot-bot_123") is True
        assert is_human_bot("dependabot[bot]") is True

    def test_confidence_score_bounds(self):
        """Test that confidence scores are always within bounds."""
        test_cases = [
            ("copilot", "Message"),
            ("dependabot", "Message"),
            ("unknown", "Message"),
            ("unknown", "Generated by Copilot"),
        ]

        for username, message in test_cases:
            score = calculate_confidence_score(username, message)
            assert 0.0 <= score <= 1.0, f"Score {score} out of bounds for {username}"
