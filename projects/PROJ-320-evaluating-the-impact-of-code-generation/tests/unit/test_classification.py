class TestAmbiguousMessageConfidence:
    """Tests for T010c: Ambiguous message confidence scoring."""

    def test_ambiguous_message_confidence(self):
        """
        Asserts that a message with no signature yields confidence < 0.6.
        This tests the fallback behavior when no clear LLM or human signature is detected.
        """
        # Test cases with ambiguous/no signatures
        test_messages = [
            "Fix bug in login",
            "Update README",
            "Refactor code",
            "Add new feature",
            "Small changes",
            "WIP",
            "Draft PR",
            "Update dependencies",
            "Merge branch 'main'",
            "Revert previous commit"
        ]

        # Get the threshold for ambiguous cases from config
        thresholds = get_classification_thresholds()
        ambiguous_threshold = thresholds.get('ambiguous_confidence_threshold', 0.6)

        for message in test_messages:
            # Calculate confidence score for ambiguous message
            confidence = calculate_confidence_score(message)

            # Assert that confidence is below the ambiguous threshold
            assert confidence < ambiguous_threshold, (
                f"Expected confidence < {ambiguous_threshold} for ambiguous message: '{message}', "
                f"got {confidence}"
            )

            # Additional check: ensure confidence is not negative
            assert confidence >= 0.0, f"Confidence should be non-negative, got {confidence} for message: '{message}'"

            # Additional check: ensure confidence is not above 1.0
            assert confidence <= 1.0, f"Confidence should not exceed 1.0, got {confidence} for message: '{message}'"

    def test_empty_message_confidence(self):
        """
        Asserts that an empty message yields very low confidence.
        """
        confidence = calculate_confidence_score("")
        thresholds = get_classification_thresholds()
        ambiguous_threshold = thresholds.get('ambiguous_confidence_threshold', 0.6)

        assert confidence < ambiguous_threshold, (
            f"Expected confidence < {ambiguous_threshold} for empty message, got {confidence}"
        )

    def test_whitespace_only_message_confidence(self):
        """
        Asserts that a whitespace-only message yields very low confidence.
        """
        confidence = calculate_confidence_score("   \n\t  ")
        thresholds = get_classification_thresholds()
        ambiguous_threshold = thresholds.get('ambiguous_confidence_threshold', 0.6)

        assert confidence < ambiguous_threshold, (
            f"Expected confidence < {ambiguous_threshold} for whitespace message, got {confidence}"
        )