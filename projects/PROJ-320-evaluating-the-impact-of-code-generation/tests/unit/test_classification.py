def test_confidence_scores():
    # Exact bot match → 1.0
    assert calculate_confidence_score("copilot-bot", "any message") == 1.0
    # Bot username only → 0.9
    assert calculate_confidence_score("copilot-bot", "") == 0.9
    # Commit marker only → 0.7
    assert calculate_confidence_score("alice", "Generated by Copilot") == 0.7
    # No evidence → 0.0 (infra bot)
    assert calculate_confidence_score("dependabot", "update deps") == 0.0

def test_classify_prs(sample_prs: Path, tmp_path: Path):
    prs = load_prs_from_raw(str(sample_prs))
    results = classify_prs(prs)

    # Verify number of results and required columns
    assert len(results) == 3
    required_fields = {
        "pr_id",
        "repo",
        "source_type",
        "confidence_score",
        "flagged_for_audit",
        "comment_count",
        "time_to_merge_minutes",
        "review_cycles",
        "complexity_score",
        "loc",
        "entropy_score",
        "hour_of_day",
        "day_of_week",
    }
    for row in results:
        assert required_fields.issubset(row.keys())

    # First PR is from known bot → llm, confidence 1.0
    assert results[0]["source_type"] == "llm"
    assert results[0]["confidence_score"] == 1.0
    assert results[0]["flagged_for_audit"] is False

    # Second PR has commit marker only → confidence 0.7 → llm (>=0.6)
    assert results[1]["source_type"] == "llm"
    assert results[1]["confidence_score"] == 0.7
    assert results[1]["flagged_for_audit"] is False

    # Third PR is infra bot → confidence 0.0 → human, flagged for audit
    assert results[2]["source_type"] == "human"
    assert results[2]["confidence_score"] == 0.0
    assert results[2]["flagged_for_audit"] is True

    # Write out CSV and verify it can be read back
    out_csv = tmp_path / "out.csv"
    from code.data.classify_prs import save_classified_prs
    save_classified_prs(results, str(out_csv))

    with open(out_csv, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
        assert len(rows) == 3
        assert rows[0]["source_type"] == "llm"
        assert rows[2]["source_type"] == "human"