class TestCopilotSignature:
    """Tests for T010a: Copilot signature matching."""

    def test_copilot_signature_match(self):
        """
        Asserts that messages with explicit Copilot signatures are labeled as 'llm'
        with high confidence.
        """
        # Test cases with known Copilot signatures
        test_messages = [
            "Generated by Copilot",
            "Co-authored-by: Copilot <copilot@github.com>",
            "This code was generated by GitHub Copilot",
            "Review by Copilot"
        ]

        for message in test_messages:
            # has_llm_signature should return True for Copilot signatures
            assert has_llm_signature(message) is True, f"Expected True for signature: {message}"

            # calculate_confidence_score should return high value for clear signatures
            confidence = calculate_confidence_score(message)
            assert confidence >= 0.9, f"Expected high confidence for signature: {message}, got {confidence}"


