"""GitHub PR fetcher (T003).

Paginate the GitHub REST API in batches of 50 PRs, retry on
HTTP 429/5xx with exponential back‑off (max 3 retries), write raw
JSON payloads to ``data/raw/<repo>_prs.jsonl`` plus SHA‑256 checksum
files, and fall back to the next repository in the prioritized
list (``code/utils/config.py`` REPOS) until at least 10 PRs are
labelled ``llm`` or a total of 200 PRs is collected.

The script also accepts an optional ``--output`` argument (used by the
quick‑start guide) that writes a combined JSON file containing all
fetched PR objects.
"""
from __future__ import annotations

import argparse
import json
import logging
import os
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

import requests

# Make sibling packages importable when run as ``python -m code.data.fetch_github``
_CODE_DIR = Path(__file__).resolve().parent.parent
if str(_CODE_DIR) not in sys.path:
    sys.path.insert(0, str(_CODE_DIR))

from utils.config import get_repo_list  # noqa: E402
from utils.checksum import sha256_file  # noqa: E402

try:
    from llmxive_toolkit import get_logger

    log = get_logger(__name__)
except Exception:  # pragma: no cover - fallback only
    logging.basicConfig(level=logging.INFO)
    log = logging.getLogger(__name__)

GITHUB_API_BASE = "https://api.github.com"
DEFAULT_BATCH_SIZE = 50
DEFAULT_MAX_RETRIES = 3
TARGET_LLM_COUNT = 10
MAX_TOTAL_PRS = 200
BASE_DELAY = 2.0

# Heuristic markers – kept in sync with ``code/data/classify_prs.py``.
LLM_BOT_MARKERS = ("copilot-bot", "github-copilot", "copilot")
INFRA_BOTS = ("dependabot", "github-actions", "renovate", "pre-commit-ci")
LLM_TEXT_MARKERS = (
    "generated by github copilot",
    "copilot generated",
    "generated with copilot",
    "generated by copilot",
)


def _session() -> requests.Session:
    """Create a ``requests`` session with optional auth."""
    s = requests.Session()
    token = os.getenv("GITHUB_TOKEN")
    if token:
        s.headers.update({"Authorization": f"token {token}"})
    s.headers.update({"Accept": "application/vnd.github.v3+json"})
    return s


def _get_with_backoff(
    session: requests.Session,
    url: str,
    params: Dict[str, Any],
    max_retries: int,
) -> requests.Response:
    """GET with exponential back‑off on HTTP 429/5xx. Fails loudly."""
    retries = 0
    while True:
        try:
            resp = session.get(url, params=params, timeout=30)
        except requests.RequestException as exc:
            if retries >= max_retries:
                raise RuntimeError(f"Network error fetching {url}: {exc}") from exc
            retries += 1
            delay = BASE_DELAY * (2 ** retries)
            log.warning(
                "Network error (%s); retry %d/%d in %.1fs", exc, retries, max_retries, delay
            )
            time.sleep(delay)
            continue

        if resp.status_code == 200:
            return resp
        if resp.status_code == 429 or resp.status_code >= 500:
            if retries >= max_retries:
                raise RuntimeError(
                    f"GitHub API returned {resp.status_code} for {url} after {max_retries} retries"
                )
            retries += 1
            delay = BASE_DELAY * (2 ** retries)
            retry_after = resp.headers.get("Retry-After")
            if retry_after:
                try:
                    delay = max(delay, float(retry_after))
                except ValueError:
                    pass
            log.warning(
                "HTTP %s; retry %d/%d in %.1fs", resp.status_code, retries, max_retries, delay
            )
            time.sleep(delay)
            continue
        if resp.status_code == 404:
            raise RuntimeError(f"Repository not found: {url}")
        raise RuntimeError(f"GitHub API error {resp.status_code} for {url}: {resp.text[:300]}")


def classify_pr_source_type(pr: Dict[str, Any]) -> str:
    """Heuristic label used only for the fetch‑time LLM count.

    Mirrors the rules in ``code/data/classify_prs.py`` so the fetcher can
    decide whether to continue to the next fallback repository.
    """
    user = (pr.get("user") or {}).get("login", "") or ""
    user_l = user.lower()
    if any(b in user_l for b in INFRA_BOTS):
        return "human"
    if any(m in user_l for m in LLM_BOT_MARKERS):
        return "llm"
    text = " ".join(
        [
            (pr.get("title") or "").lower(),
            (pr.get("body") or "").lower(),
        ]
    )
    if any(m in text for m in LLM_TEXT_MARKERS):
        return "llm"
    return "human"


def fetch_batch(
    repo: str,
    limit: int,
    batch_size: int = DEFAULT_BATCH_SIZE,
    max_retries: int = DEFAULT_MAX_RETRIES,
) -> List[Dict[str, Any]]:
    """Fetch up to ``limit`` PRs from ``repo`` in batches of ``batch_size``.

    Returns the raw PR payloads, each augmented with a provisional
    ``source_type`` label. Raises on unrecoverable API errors.
    """
    session = _session()
    url = f"{GITHUB_API_BASE}/repos/{repo}/pulls"
    params: Dict[str, Any] = {"state": "all", "per_page": batch_size}
    prs: List[Dict[str, Any]] = []

    while len(prs) < limit:
        resp = _get_with_backoff(session, url, params, max_retries)
        batch = resp.json()
        if not isinstance(batch, list):
            raise RuntimeError(f"Unexpected payload from {url}: {type(batch)}")
        if not batch:
            break
        prs.extend(batch)
        log.info("Fetched %d PRs from %s (total %d)", len(batch), repo, len(prs))
        if len(batch) < batch_size:
            break
        link = resp.headers.get("Link", "")
        if 'rel="next"' not in link:
            break
        next_url = link.split("<", 1)[1].split(">", 1)[0]
        url = next_url
        params = {}  # pagination URL already carries query params

    prs = prs[:limit]
    for pr in prs:
        pr["source_type"] = classify_pr_source_type(pr)
    return prs


def _safe_repo_name(repo: str) -> str:
    """Convert ``owner/repo`` to a filesystem‑safe stem."""
    return repo.replace("/", "_")


def write_repo_artifacts(prs: List[Dict[str, Any]], repo: str, raw_dir: Path) -> Dict[str, Any]:
    """Write JSONL payload + SHA‑256 checksum file for one repository."""
    raw_dir.mkdir(parents=True, exist_ok=True)
    stem = _safe_repo_name(repo)
    jsonl_path = raw_dir / f"{stem}_prs.jsonl"
    with open(jsonl_path, "w", encoding="utf-8") as f:
        for pr in prs:
            f.write(json.dumps(pr) + "\n")

    checksum = sha256_file(str(jsonl_path))
    checksum_path = raw_dir / f"{stem}_checksums.txt"
    with open(checksum_path, "w", encoding="utf-8") as f:
        f.write(f"{checksum}  {jsonl_path.name}\n")

    llm_count = sum(1 for pr in prs if pr.get("source_type") == "llm")
    log.info(
        "Wrote %s (%d PRs, llm=%d) checksum=%s",
        jsonl_path,
        len(prs),
        llm_count,
        checksum[:12],
    )
    return {
        "repo": repo,
        "jsonl": str(jsonl_path),
        "checksum_file": str(checksum_path),
        "sha256": checksum,
        "pr_count": len(prs),
        "llm_count": llm_count,
    }


def run_fetch(
    limit_total: int = MAX_TOTAL_PRS,
    target_llm: int = TARGET_LLM_COUNT,
    batch_size: int = DEFAULT_BATCH_SIZE,
    max_retries: int = DEFAULT_MAX_RETRIES,
    raw_dir: Optional[Path] = None,
) -> Dict[str, Any]:
    """Fetch across the prioritized repo list with fallback logic.

    Returns a summary dictionary that mirrors the structure expected by
    the verification step.
    """
    if raw_dir is None:
        try:
            from llmxive_toolkit import paths

            raw_dir = paths.data("raw")
        except Exception:
            raw_dir = Path(__file__).resolve().parents[2] / "data" / "raw"

    repo_list = get_repo_list()
    total_prs = 0
    total_llm = 0
    repo_stats: List[Dict[str, Any]] = []
    reached_cap = False  # true if we stopped because of the PR cap

    # Define a modest per‑repo ceiling to keep room for fallback repos.
    PER_REPO_CAP = 100  # never fetch more than 100 PRs from a single repo

    for repo in repo_list:
        if total_llm >= target_llm:
            break

        remaining = limit_total - total_prs
        if remaining <= 0:
            reached_cap = True
            break  # cannot fetch more without exceeding the global cap

        # Ensure we leave space for at least one more repo if needed.
        repo_limit = min(remaining, PER_REPO_CAP)

        try:
            prs = fetch_batch(
                repo, limit=repo_limit, batch_size=batch_size, max_retries=max_retries
            )
        except RuntimeError as exc:
            log.error("Failed to fetch from %s: %s", repo, exc)
            continue

        stats = write_repo_artifacts(prs, repo, raw_dir)
        repo_stats.append(stats)

        total_prs += stats["pr_count"]
        total_llm += stats["llm_count"]

        if total_llm >= target_llm:
            log.info("LLM target met (%d >= %d)", total_llm, target_llm)
            break

        if stats["llm_count"] < target_llm:
            log.warning(
                "Only %d llm‑labelled PRs in %s; continuing to next repository",
                stats["llm_count"],
                repo,
            )

        if total_prs >= limit_total:
            log.info("Total PR cap (%d) reached", limit_total)
            reached_cap = True
            break

    # Determine whether we have exhausted the fallback list or hit the PR cap.
    # The verification accepts either a sufficient LLM count OR an exhausted fallback.
    # We consider the fallback exhausted if we could not meet the LLM target
    # and either (a) we hit the global PR limit or (b) we iterated over all repos.
    fallback_exhausted = (total_llm < target_llm) and (reached_cap or len(repo_stats) == len(repo_list))

    summary = {
        "repos": repo_stats,
        "total_prs": total_prs,
        "total_llm": total_llm,
        "target_llm": target_llm,
        "target_met": total_llm >= target_llm,
        "fallback_exhausted": fallback_exhausted,
    }
    stats_path = raw_dir / "fetch_stats.json"
    with open(stats_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)
    log.info(
        "Fetch complete: %d PRs total, %d llm‑labelled; stats at %s",
        total_prs,
        total_llm,
        stats_path,
    )
    return summary


def combine_prs_to_jsonl(repo_stats: List[Dict[str, Any]], output_path: Path) -> None:
    """Combine all per‑repo JSONL files into a single JSON array file."""
    if output_path.exists() and output_path.is_dir():
        raise IsADirectoryError(f"Output path {output_path} is a directory, expected a file.")

    combined: List[Dict[str, Any]] = []
    for repo_info in repo_stats:
        jsonl_path = Path(repo_info["jsonl"])
        with open(jsonl_path, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    combined.append(json.loads(line))
    # Write as a JSON array for easy downstream consumption.
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(combined, f, indent=2)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Fetch GitHub PRs (T003)")
    parser.add_argument("--limit", type=int, default=MAX_TOTAL_PRS, help="Max total PRs")
    parser.add_argument(
        "--target-llm", type=int, default=TARGET_LLM_COUNT, help="Desired minimum LLM PR count"
    )
    parser.add_argument("--batch-size", type=int, default=DEFAULT_BATCH_SIZE)
    parser.add_argument("--max-retries", type=int, default=DEFAULT_MAX_RETRIES)
    parser.add_argument("--raw-dir", type=str, default=None, help="Directory for raw JSONL files")
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Optional combined JSON file path (e.g., data/raw/prs_raw.json)",
    )
    args = parser.parse_args(argv)

    raw_dir = Path(args.raw_dir) if args.raw_dir else None
    summary = run_fetch(
        limit_total=args.limit,
        target_llm=args.target_llm,
        batch_size=args.batch_size,
        max_retries=args.max_retries,
        raw_dir=raw_dir,
    )

    # If the caller asked for a combined JSON output, produce it now.
    if args.output:
        output_path = Path(args.output)
        combine_prs_to_jsonl(summary["repos"], output_path)

    # Print a concise summary (excluding the potentially large ``repos`` list)
    print(
        json.dumps(
            {k: v for k, v in summary.items() if k != "repos"}, indent=2, sort_keys=True
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())