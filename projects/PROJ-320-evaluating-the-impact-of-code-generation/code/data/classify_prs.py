"""
Primary PR Classification Script (T006)

This script reads raw PR data (JSONL) from the `data/raw/` directory (or a single
combined JSON file), classifies each PR as generated by an LLM bot or by a human,
computes auxiliary scores (confidence, entropy, secondary detector), and writes a
CSV that conforms to `specs/001-evaluating-the-impact-of-code-generation/contracts/pr_schema.schema.yaml`.

The script:
  * Loads all PR objects from every `*.jsonl` file in the provided input directory
    (or from a single JSON file if a file path is given).
  * Detects known LLM‑bot usernames and commit‑message markers.
  * Calls the entropy detector on each diff.
  * Assigns `source_type` (`llm` or `human`).
  * Computes a confidence score:
      - 1.0 for exact LLM‑bot username match,
      - 0.9 for LLM‑bot username without commit‑message marker,
      - 0.7 for commit‑message marker without bot username,
      - 0.5 for weak evidence,
      - 0.0 for known infrastructure bots.
    If the confidence is < 0.6 the PR is labelled `human` and flagged for audit.
  * Writes `data/processed/prs_labeled.csv` with **exactly** the columns defined in the schema.
"""

import argparse
import csv
import json
import os
import sys
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

# Project imports
from utils.logging import get_logger, setup_logging
from utils.seeds import set_global_seed
# The entropy detector lives in the same package (`code/data`), so we import it
# via the package name `data` (the `code/data` directory is now a package thanks
# to the added `__init__.py` file).
from data.entropy_detector import compute_entropy

# ----------------------------------------------------------------------
# Configuration & Constants
# ----------------------------------------------------------------------
LLM_BOT_USERNAMES = {
    "copilot-bot",
    "github-copilot",
    "codex-bot",
    "gpt-bot",
    "llama-bot",
    "claude-bot",
    "gemini-bot",
    "deepseek-bot",
}

INFRA_BOT_USERNAMES = {
    "dependabot",
    "renovate",
    "snyk",
    "codecov",
    "coveralls",
    "travis-ci",
    "circleci",
    "jenkins",
    "github-actions",
}

LLM_COMMIT_INDICATORS = [
    "copilot",
    "generated by",
    "generated with",
    "auto-generated",
    "ai-generated",
    "llm",
    "copilot suggested",
]

# ----------------------------------------------------------------------
# Helper Functions
# ----------------------------------------------------------------------
logger = get_logger(__name__)

def set_reproducibility_seed(seed: int = 42) -> None:
    """Set the global random seed for any stochastic components."""
    set_global_seed(seed)

def is_llm_bot(user: str) -> bool:
    """Return True if the username matches a known LLM bot."""
    return any(bot in user.lower() for bot in LLM_BOT_USERNAMES)

def is_infra_bot(user: str) -> bool:
    """Return True if the username matches a known infrastructure bot."""
    return any(bot in user.lower() for bot in INFRA_BOT_USERNAMES)

def has_llm_signature(message: str) -> bool:
    """Return True if the PR title/body contains any LLM indicator."""
    if not message:
        return False
    lowered = message.lower()
    return any(indicator in lowered for indicator in LLM_COMMIT_INDICATORS)

def calculate_confidence_score(user: str, message: str) -> float:
    """
    Compute a confidence score (0‑1) based on bot username and commit markers.

    Scoring logic:
      * Exact LLM‑bot username → 1.0
      * LLM‑bot username *without* a commit‑message marker → 0.9
      * Commit‑message marker *without* bot username → 0.7
      * Both present but not an exact bot match → 0.8 (treated as strong evidence)
      * No evidence → 0.0 (treated as human)
    """
    if is_infra_bot(user):
        return 0.0

    bot_match = is_llm_bot(user)
    msg_match = has_llm_signature(message)

    if bot_match and msg_match:
        return 1.0
    if bot_match and not msg_match:
        return 0.9
    if not bot_match and msg_match:
        return 0.7
    # Weak or no evidence – give a low non‑zero score to keep the range
    return 0.5 if (bot_match or msg_match) else 0.0

def parse_timestamp(ts: str) -> Optional[datetime]:
    """Parse ISO‑8601 timestamps used by the GitHub API."""
    if not ts:
        return None
    formats = [
        "%Y-%m-%dT%H:%M:%SZ",
        "%Y-%m-%dT%H:%M:%S.%fZ",
        "%Y-%m-%d %H:%M:%S",
        "%Y-%m-%dT%H:%M:%S",
    ]
    for fmt in formats:
        try:
            return datetime.strptime(ts, fmt)
        except ValueError:
            continue
    logger.warning(f"Unparseable timestamp: {ts}")
    return None

def calculate_time_to_merge(created: str, merged: str) -> float:
    """
    Return minutes between creation and merge.
    If merge timestamp missing or earlier than creation, return -1.0.
    """
    created_dt = parse_timestamp(created)
    merged_dt = parse_timestamp(merged)
    if created_dt and merged_dt and merged_dt > created_dt:
        delta = merged_dt - created_dt
        return delta.total_seconds() / 60.0
    return -1.0

def extract_comment_count(pr: Dict[str, Any]) -> int:
    """Sum of top‑level comment fields."""
    comments = int(pr.get("comments", 0))
    review_comments = int(pr.get("review_comments", 0))
    return comments + review_comments

def calculate_review_cycles(pr: Dict[str, Any]) -> int:
    """
    Very simple heuristic: count distinct review states in the
    `review_events` list if present, otherwise default to 1.
    """
    events = pr.get("review_events", [])
    if not events:
        return 1
    states = {e.get("state", "").upper() for e in events if e.get("state")}
    return max(1, len(states))

def extract_diff_text(pr: Dict[str, Any]) -> str:
    """Extract raw diff text from common keys; fallback to empty string."""
    for key in ("diff", "patch", "body", "description", "text"):
        if key in pr and isinstance(pr[key], str):
            return pr[key]
    return ""

def load_prs_from_raw(input_path: str) -> List[Dict[str, Any]]:
    """
    Load PR objects from a directory of JSONL files or a single JSON file.

    * If `input_path` is a directory, all `*.jsonl` files are read line‑by‑line.
    * If it is a file ending with `.json`, the file is expected to contain either
      a list of PR objects or a dict with a top‑level `prs` key.
    """
    path = Path(input_path)

    prs: List[Dict[str, Any]] = []

    if path.is_dir():
        jsonl_files = sorted(p for p in path.iterdir() if p.is_file() and p.suffix.lower() == ".jsonl")
        if not jsonl_files:
            raise FileNotFoundError(f"No JSONL files found in directory {input_path}")
        logger.info(f"Loading PRs from {len(jsonl_files)} JSONL files in {input_path}")
        for jsonl in jsonl_files:
            with open(jsonl, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line:
                        try:
                            prs.append(json.loads(line))
                        except json.JSONDecodeError as exc:
                            logger.warning(f"Skipping malformed line in {jsonl.name}: {exc}")
        return prs

    # Single file handling
    if not path.is_file():
        raise FileNotFoundError(f"Input path {input_path} does not exist")

    if path.suffix.lower() == ".jsonl":
        # Treat as a single JSONL file
        with open(path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    prs.append(json.loads(line))
        return prs

    # Assume a regular JSON file
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)

    if isinstance(data, dict):
        if "prs" in data:
            return data["prs"]
        # Single PR dict
        return [data]
    elif isinstance(data, list):
        return data
    else:
        raise ValueError("Unexpected JSON structure for raw PR data")

# ----------------------------------------------------------------------
# Main Classification Logic
# ----------------------------------------------------------------------
def classify_prs(prs: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Produce a list of dictionaries conforming to the PR schema.

    Required columns (per schema):
      pr_id, repo, source_type, confidence_score, flagged_for_audit,
      comment_count, time_to_merge_minutes, review_cycles,
      complexity_score, loc, entropy_score, hour_of_day, day_of_week
    """
    results: List[Dict[str, Any]] = []

    for pr in prs:
        # Basic identifiers
        pr_id = int(pr.get("id") or pr.get("number") or 0)
        repo = (
            pr.get("base", {})
            .get("repo", {})
            .get("full_name")
            or pr.get("repository", {})
            .get("full_name")
            or ""
        )

        # User / message for primary signature
        user = (
            pr.get("user", {})
            .get("login")
            or pr.get("author", "")
            or ""
        )
        message = pr.get("title") or pr.get("commit_message") or pr.get("body") or ""

        # Primary classification
        confidence = calculate_confidence_score(user, message)
        source_type = "llm" if confidence >= 0.6 else "human"
        flagged_for_audit = confidence < 0.6

        # Secondary detector (entropy)
        diff_text = extract_diff_text(pr)
        entropy_score = compute_entropy(diff_text)  # returns 0‑1

        # Additional metrics needed for the schema
        comment_count = extract_comment_count(pr)
        time_to_merge = calculate_time_to_merge(
            pr.get("created_at", ""), pr.get("merged_at", "")
        )
        review_cycles = calculate_review_cycles(pr)

        # Temporal covariates
        created_dt = parse_timestamp(pr.get("created_at", ""))
        if created_dt:
            hour_of_day = created_dt.hour
            day_of_week = created_dt.weekday()
        else:
            hour_of_day = -1
            day_of_week = -1

        # Place‑holders for fields that are computed later
        complexity_score = 0.0
        loc = 0

        results.append(
            {
                "pr_id": pr_id,
                "repo": repo,
                "source_type": source_type,
                "confidence_score": round(confidence, 4),
                "flagged_for_audit": flagged_for_audit,
                "comment_count": comment_count,
                "time_to_merge_minutes": round(time_to_merge, 4) if time_to_merge >= 0 else -1.0,
                "review_cycles": review_cycles,
                "complexity_score": complexity_score,
                "loc": loc,
                "entropy_score": round(entropy_score, 4),
                "hour_of_day": hour_of_day,
                "day_of_week": day_of_week,
            }
        )
    return results

def save_classified_prs(results: List[Dict[str, Any]], output_path: str) -> None:
    """Write the classification results to CSV, creating parent directories."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    fieldnames = [
        "pr_id",
        "repo",
        "source_type",
        "confidence_score",
        "flagged_for_audit",
        "comment_count",
        "time_to_merge_minutes",
        "review_cycles",
        "complexity_score",
        "loc",
        "entropy_score",
        "hour_of_day",
        "day_of_week",
    ]
    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(results)

def run_classification(input_path: str, output_path: str) -> Dict[str, Any]:
    """Execute the end‑to‑end classification pipeline."""
    logger.log("classification_started", input=input_path, output=output_path)

    prs = load_prs_from_raw(input_path)
    logger.log("raw_prs_loaded", count=len(prs))

    results = classify_prs(prs)
    llm_cnt = sum(1 for r in results if r["source_type"] == "llm")
    logger.log("classification_completed", llm=llm_cnt)

    save_classified_prs(results, output_path)
    logger.log("results_saved", path=output_path)

    summary = {
        "total_prs": len(results),
        "llm_count": llm_cnt,
        "human_count": len(results) - llm_cnt,
        "output_file": output_path,
    }
    return summary

# ----------------------------------------------------------------------
# CLI Entry Point
# ----------------------------------------------------------------------
def main() -> None:
    parser = argparse.ArgumentParser(description="Classify PRs as LLM‑generated or Human‑authored")
    parser.add_argument("--input", required=True, help="Path to raw PR data (directory of JSONL files or a JSON file)")
    parser.add_argument("--output", required=True, help="Path to output CSV")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for reproducibility")
    args = parser.parse_args()

    # Initialise logging and reproducibility
    setup_logging(script_name="classify_prs")
    set_reproducibility_seed(args.seed)

    try:
        summary = run_classification(args.input, args.output)
        print(json.dumps(summary, indent=2))
    except Exception as exc:
        logger.log("classification_failed", error=str(exc))
        print(f"Error: {exc}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()