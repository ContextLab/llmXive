# Constants for signature matching
LLM_BOT_NAMES = [
    "copilot-bot", "github-copilot", "copilot", "codey", 
    "code-generator", "ai-coder", "llm-assistant"
]

HUMAN_BOT_NAMES = [
    "dependabot", "dependabot[bot]", "renovate", "renovate-bot",
    "travis-ci", "circleci", "jenkins", "codecov", "coveralls",
    "stale", "welcome", "cla-bot", "all-contributors"
]

# LLM-indicative keywords in commit messages
LLM_KEYWORDS = [
    "copilot", "generated by", "ai generated", "code generation",
    "automatically generated", "llm suggestion", "ai assistance",
    "copilot suggestion", "generated code"
]

# Human-indicative keywords
HUMAN_KEYWORDS = [
    "fix typo", "update docs", "refactor", "optimize",
    "manual fix", "hotfix", "bugfix", "feature", "chore"
]

def set_reproducibility_seed(seed_value: Optional[int] = None) -> int:
    """Set global seed for reproducibility."""
    if seed_value is None:
        seed_value = 42
    set_global_seed(seed_value)
    return seed_value

def is_llm_bot(user: str) -> bool:
    """Check if user is a known LLM bot."""
    if not user:
        return False
    user_lower = user.lower()
    return any(llm_bot in user_lower for llm_bot in LLM_BOT_NAMES)

def is_human_bot(user: str) -> bool:
    """Check if user is a known infrastructure/human bot."""
    if not user:
        return False
    user_lower = user.lower()
    return any(human_bot in user_lower for human_bot in HUMAN_BOT_NAMES)

def has_llm_signature(message: str) -> bool:
    """Check if commit message contains LLM signatures."""
    if not message:
        return False
    message_lower = message.lower()
    return any(keyword in message_lower for keyword in LLM_KEYWORDS)

def calculate_signature_strength(user: str, message: str) -> Tuple[float, str]:
    """
    Calculate the strength of the signature match.
    Returns (strength_score, label_hint).
    Strength is between 0.0 and 1.0.
    """
    strength = 0.0
    label_hint = "unknown"

    # Check user signature
    if is_llm_bot(user):
        strength = 0.95
        label_hint = "llm"
    elif is_human_bot(user):
        strength = 0.85
        label_hint = "human"
    else:
        # Check message content
        if has_llm_signature(message):
            strength = 0.75
            label_hint = "llm"
        else:
            # Check for human keywords (lower confidence)
            if message:
                message_lower = message.lower()
                human_count = sum(1 for kw in HUMAN_KEYWORDS if kw in message_lower)
                if human_count > 0:
                    strength = 0.4 + (human_count * 0.05)
                    strength = min(strength, 0.6)
                    label_hint = "human"
                else:
                    # Default to human if no indicators
                    strength = 0.5
                    label_hint = "human"

    return strength, label_hint

def calculate_confidence_score(user: str, message: str, secondary_score: float = 0.0) -> float:
    """
    Calculate a normalized confidence score (0.0 to 1.0) for the classification.
    
    Logic:
    1. Start with signature strength (0.0-1.0).
    2. If secondary detector score is available, blend it (30% weight) to refine.
    3. Ensure score is bounded [0.0, 1.0].
    
    Args:
        user: GitHub username
        message: Commit message
        secondary_score: Score from secondary detector (0.0-1.0), defaults to 0.0
    
    Returns:
        float: Confidence score
    """
    sig_strength, label_hint = calculate_signature_strength(user, message)
    
    # Blend with secondary score if provided and significant
    if secondary_score > 0:
        # Weighted average: 70% signature, 30% secondary
        blended = (sig_strength * 0.7) + (secondary_score * 0.3)
        final_score = blended
    else:
        final_score = sig_strength

    # Clamp to [0.0, 1.0]
    return max(0.0, min(1.0, final_score))

def calculate_code_entropy(code: str) -> float:
    """Calculate Shannon entropy of the code string."""
    if not code:
        return 0.0
    
    # Count character frequencies
    freq = {}
    for char in code:
        freq[char] = freq.get(char, 0) + 1
    
    # Calculate entropy
    length = len(code)
    entropy = 0.0
    for count in freq.values():
        p = count / length
        if p > 0:
            entropy -= p * math.log2(p)
    
    return entropy

def calculate_ngram_anomaly_score(code: str, n: int = 3) -> float:
    """
    Calculate n-gram anomaly score.
    Returns a score between 0.0 and 1.0 where higher means more anomalous.
    """
    if not code or len(code) < n:
        return 0.0
    
    # Simple n-gram frequency check
    ngrams = []
    for i in range(len(code) - n + 1):
        ngram = code[i:i+n]
        ngrams.append(ngram)
    
    if not ngrams:
        return 0.0
    
    # Count frequencies
    freq = {}
    for ng in ngrams:
        freq[ng] = freq.get(ng, 0) + 1
    
    # Calculate anomaly score based on unique n-grams ratio
    unique_ratio = len(freq) / len(ngrams)
    
    # Normalize to [0, 1] (higher unique ratio = more anomalous)
    # Heuristic: if > 50% are unique, it's likely generated/anomalous
    score = min(unique_ratio * 2, 1.0)
    
    return score

def compute_secondary_detector_score(code_diff: str) -> float:
    """
    Compute secondary detector score using local heuristics.
    Combines entropy and n-gram anomaly.
    """
    if not code_diff:
        return 0.0
    
    entropy = calculate_code_entropy(code_diff)
    ngram_score = calculate_ngram_anomaly_score(code_diff)
    
    # Normalize entropy (typical code entropy ~ 3.5-4.5 bits for ASCII)
    # Assume max entropy ~ 6.0 for highly random/gibberish
    normalized_entropy = min(entropy / 6.0, 1.0)
    
    # Weighted combination: 60% entropy, 40% n-gram
    score = (normalized_entropy * 0.6) + (ngram_score * 0.4)
    
    return min(1.0, max(0.0, score))

def extract_diff_text(pr_data: Dict[str, Any]) -> str:
    """Extract diff text from PR data structure."""
    # Handle various possible structures
    if "diff" in pr_data:
        return pr_data["diff"]
    if "patch" in pr_data:
        return pr_data["patch"]
    if "files" in pr_data:
        # Concatenate patches from all files
        patches = [f.get("patch", "") for f in pr_data["files"] if f.get("patch")]
        return "\n".join(patches)
    return ""

def load_prs_from_raw(input_path: str) -> List[Dict[str, Any]]:
    """Load PRs from raw JSON file."""
    logger.info(f"Loading PRs from {input_path}")
    
    if not os.path.exists(input_path):
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    with open(input_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # Handle both list and dict with 'prs' key
    if isinstance(data, list):
        return data
    elif isinstance(data, dict) and "prs" in data:
        return data["prs"]
    else:
        raise ValueError(f"Unexpected JSON structure in {input_path}")

def classify_prs(pr_data: Dict[str, Any]) -> Dict[str, Any]:
    """
    Classify a single PR.
    
    Returns a dictionary with:
    - pr_id: int
    - source_type: str ('llm' or 'human')
    - confidence_score: float (0.0-1.0)
    - flagged: bool (True if confidence < 0.6)
    - detector_score: float (from secondary detector)
    - metadata: dict with original data
    """
    pr_id = pr_data.get("pr_id", pr_data.get("id", 0))
    user = pr_data.get("user", {}).get("login", "") or pr_data.get("user", "")
    message = pr_data.get("title", "") or pr_data.get("commit_message", "")
    
    # Extract diff for secondary detector
    diff_text = extract_diff_text(pr_data)
    detector_score = compute_secondary_detector_score(diff_text)
    
    # Calculate confidence score
    confidence = calculate_confidence_score(user, message, detector_score)
    
    # Determine label
    if confidence >= 0.6:
        # Use the stronger signal
        sig_strength, label_hint = calculate_signature_strength(user, message)
        if label_hint == "llm" and sig_strength > 0.5:
            source_type = "llm"
        elif label_hint == "human":
            source_type = "human"
        else:
            # Fallback: if confidence is high but hint is unknown, assume human
            source_type = "human"
    else:
        # Low confidence: default to human but flag
        source_type = "human"
    
    flagged = confidence < 0.6
    
    return {
        "pr_id": int(pr_id),
        "source_type": source_type,
        "confidence_score": round(confidence, 4),
        "flagged": flagged,
        "detector_score": round(detector_score, 4),
        "user": user,
        "message": message,
        "metadata": {
            "original_data": pr_data
        }
    }

def save_classified_prs(classified_prs: List[Dict[str, Any]], output_path: str) -> None:
    """Save classified PRs to CSV."""
    logger.info(f"Saving classified PRs to {output_path}")
    
    # Ensure output directory exists
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    fieldnames = [
        "pr_id", "source_type", "confidence_score", "flagged", 
        "detector_score", "user", "message"
    ]
    
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        
        for pr in classified_prs:
            row = {k: pr[k] for k in fieldnames}
            writer.writerow(row)
    
    logger.info(f"Saved {len(classified_prs)} PRs to {output_path}")

def run_classification(input_path: str, output_path: str, seed: Optional[int] = None) -> List[Dict[str, Any]]:
    """Run the full classification pipeline."""
    if seed is not None:
        set_reproducibility_seed(seed)
    
    # Load raw PRs
    prs = load_prs_from_raw(input_path)
    logger.info(f"Loaded {len(prs)} PRs")
    
    # Classify each PR
    classified_prs = []
    for i, pr in enumerate(prs):
        try:
            classified = classify_prs(pr)
            classified_prs.append(classified)
            
            # Log progress
            if (i + 1) % 50 == 0:
                logger.info(f"Classified {i + 1}/{len(prs)} PRs")
        except Exception as e:
            logger.error(f"Error classifying PR {pr.get('id', i)}: {e}")
            # Still add a placeholder to avoid losing data
            classified_prs.append({
                "pr_id": pr.get("id", i),
                "source_type": "human",
                "confidence_score": 0.5,
                "flagged": True,
                "detector_score": 0.0,
                "user": "unknown",
                "message": "error",
                "metadata": {"error": str(e)}
            })
    
    # Save results
    save_classified_prs(classified_prs, output_path)
    
    return classified_prs

def main():
    """Main entry point for CLI."""
    import argparse
    
    parser = argparse.ArgumentParser(description="Classify PRs as LLM or Human")
    parser.add_argument("--input", required=True, help="Path to raw PRs JSON")
    parser.add_argument("--output", required=True, help="Path to output CSV")
    parser.add_argument("--seed", type=int, default=42, help="Random seed")
    
    args = parser.parse_args()
    
    # Setup logging
    setup_logging(log_file="data/logs/classify_prs.log")
    
    logger.info("Starting PR classification pipeline (T014)")
    logger.info(f"Input: {args.input}")
    logger.info(f"Output: {args.output}")
    
    try:
        classified_prs = run_classification(args.input, args.output, seed=args.seed)
        
        # Summary stats
        llm_count = sum(1 for p in classified_prs if p["source_type"] == "llm")
        human_count = sum(1 for p in classified_prs if p["source_type"] == "human")
        flagged_count = sum(1 for p in classified_prs if p["flagged"])
        
        logger.info(f"Classification complete: {llm_count} LLM, {human_count} Human, {flagged_count} flagged")
        
    except Exception as e:
        logger.error(f"Pipeline failed: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()