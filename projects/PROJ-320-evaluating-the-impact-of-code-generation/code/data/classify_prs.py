# --- Primary Classification Logic (Preserved from existing implementation) ---
def is_llm_bot(author: str) -> bool:
    """Checks if the author is a known LLM bot (e.g., Copilot)."""
    llm_patterns = [
        r"copilot", r"code-climate", r"dependabot" # Dependabot is handled separately in is_human_bot
    ]
    author_lower = author.lower()
    return any(re.search(p, author_lower) for p in llm_patterns)

def is_human_bot(author: str) -> bool:
    """Checks if the author is an infrastructure bot (e.g., dependabot) that counts as human."""
    # Per T010b: dependabot is labeled human
    human_bot_patterns = [r"dependabot"]
    author_lower = author.lower()
    return any(re.search(p, author_lower) for p in human_bot_patterns)

def has_llm_signature(message: str) -> bool:
    """Checks for explicit LLM signatures in commit message."""
    if not message:
        return False
    message_lower = message.lower()
    signatures = [
        "copilot", "generated by", "llm generated", "ai generated",
        "written by copilot", "copilot suggested"
    ]
    return any(sig in message_lower for sig in signatures)

def calculate_confidence_score(author: str, message: str) -> float:
    """
    Calculates primary confidence score based on signature and bot detection.
    Returns a float between 0.0 and 1.0.
    """
    score = 0.5 # Base uncertainty
    
    # High confidence LLM
    if is_llm_bot(author):
        score = 0.95
        if has_llm_signature(message):
            score = 0.99
    elif is_human_bot(author):
        score = 0.10 # Very likely human
    else:
        # Check message for hints if not a known bot
        if has_llm_signature(message):
            score = 0.85
        elif not message or len(message.strip()) < 10:
            score = 0.50 # Ambiguous
        else:
            score = 0.45 # Default to likely human if no signals

    return min(1.0, max(0.0, score))

# --- Secondary Detector Implementation (T015 Requirement) ---

def calculate_code_entropy(diff_text: str) -> float:
    """
    Calculates Shannon entropy of the code diff characters.
    Higher entropy often indicates synthetic/random generation patterns,
    though valid code also has structure. We look for anomalies in distribution.
    """
    if not diff_text or len(diff_text) < 10:
        return 0.0
    
    # Normalize to lowercase for entropy calc to focus on structure
    text = diff_text.lower()
    freq = {}
    for char in text:
        freq[char] = freq.get(char, 0) + 1
    
    length = len(text)
    entropy = 0.0
    for count in freq.values():
        p = count / length
        if p > 0:
            entropy -= p * math.log2(p)
    
    return entropy

def calculate_ngram_anomaly_score(diff_text: str, n: int = 3) -> float:
    """
    Calculates an anomaly score based on n-gram frequency.
    Synthetic code often has unusual n-gram distributions compared to human code.
    Returns a score normalized 0.0 (normal) to 1.0 (highly anomalous).
    """
    if not diff_text or len(diff_text) < n:
        return 0.0
    
    # Simple heuristic: compare observed n-gram frequency to expected uniform-ish distribution
    # or check for repetitive patterns common in LLM outputs (e.g., excessive boilerplate)
    # For a robust implementation without a pre-trained model, we use a heuristic based on
    # repetition and character diversity.
    
    text = diff_text.lower()
    ngrams = [text[i:i+n] for i in range(len(text) - n + 1)]
    
    if not ngrams:
        return 0.0
    
    total = len(ngrams)
    freq = {}
    for ng in ngrams:
        freq[ng] = freq.get(ng, 0) + 1
    
    # Calculate Gini coefficient or similar measure of concentration
    # High concentration (few n-grams dominate) -> Anomalous for code?
    # Actually, LLMs can be repetitive. Let's measure the "peakiness".
    max_freq = max(freq.values())
    max_ratio = max_freq / total
    
    # Heuristic: If one n-gram dominates significantly (> 20% of all n-grams), it's suspicious
    # Human code usually has more varied n-gram distribution
    if max_ratio > 0.20:
        return min(1.0, (max_ratio - 0.20) * 5) # Scale up
    
    return 0.0

def compute_secondary_detector_score(diff_text: str) -> float:
    """
    Computes the final detector_score based on entropy and n-gram anomaly.
    Returns a float between 0.0 (human-like) and 1.0 (LLM-like).
    """
    if not diff_text or len(diff_text) < 50:
        return 0.0 # Insufficient data to score
    
    entropy = calculate_code_entropy(diff_text)
    ngram_score = calculate_ngram_anomaly_score(diff_text)
    
    # Heuristic weighting:
    # Normal code entropy is typically in a specific range.
    # Very high entropy might be minified/random, very low might be boilerplate.
    # We rely more heavily on the n-gram anomaly for "synthetic" feel.
    
    # Normalize entropy contribution (approximate range 3.0 - 6.0 for code)
    # If entropy is extremely high (> 6.5) or low (< 2.5), it might be suspicious
    entropy_suspicion = 0.0
    if entropy > 6.5:
        entropy_suspicion = (entropy - 6.5) * 0.2
    elif entropy < 2.5:
        entropy_suspicion = (2.5 - entropy) * 0.2
    
    # Combine scores
    # Weight n-gram anomaly higher as it's more specific to generation patterns
    detector_score = (0.3 * min(1.0, entropy_suspicion)) + (0.7 * ngram_score)
    
    return min(1.0, max(0.0, detector_score))

# --- Data Loading & Processing (Preserved and Extended) ---

def load_prs_from_raw(raw_dir: str) -> List[Dict[str, Any]]:
    """Loads PR data from raw JSON files in the specified directory."""
    raw_path = Path(raw_dir)
    prs = []
    
    if not raw_path.exists():
        raise FileNotFoundError(f"Raw directory not found: {raw_path}")
    
    for json_file in raw_path.glob("*.json"):
        try:
            with open(json_file, 'r', encoding='utf-8') as f:
                data = json.load(f)
                # Handle both single object and list of objects
                if isinstance(data, list):
                    prs.extend(data)
                else:
                    prs.append(data)
        except json.JSONDecodeError:
            continue
    
    return prs

def extract_diff_text(pr_data: Dict[str, Any]) -> str:
    """Extracts the diff text from PR data structure."""
    # Common GitHub API structure variations
    if 'diff' in pr_data:
        return pr_data['diff']
    if 'patch' in pr_data:
        return pr_data['patch']
    if 'files' in pr_data and isinstance(pr_data['files'], list):
        parts = []
        for f in pr_data['files']:
            if 'patch' in f:
                parts.append(f['patch'])
        return "\n".join(parts)
    return ""

def classify_prs(prs: List[Dict[str, Any]], logger) -> List[Dict[str, Any]]:
    """
    Classifies PRs as 'llm' or 'human' and computes secondary detector scores.
    
    Updates each PR dict with:
      - source_type: 'llm' or 'human'
      - confidence_score: float (0-1)
      - flagged: bool (True if confidence < 0.6)
      - detector_score: float (0-1) from secondary detector
    """
    classified = []
    
    for pr in prs:
        # Extract basic info
        pr_id = pr.get('id') or pr.get('number')
        author = pr.get('user', {}).get('login', 'unknown')
        message = pr.get('title', '') + " " + pr.get('body', '')
        diff_text = extract_diff_text(pr)
        
        # Primary classification
        confidence = calculate_confidence_score(author, message)
        source_type = 'llm' if confidence >= 0.6 else 'human'
        flagged = confidence < 0.6
        
        # Secondary detector (T015)
        detector_score = compute_secondary_detector_score(diff_text)
        
        # Update PR dict
        pr['source_type'] = source_type
        pr['confidence_score'] = round(confidence, 4)
        pr['flagged'] = flagged
        pr['detector_score'] = round(detector_score, 4)
        
        # Log if flagged
        if flagged:
            logger.debug(f"PR {pr_id} flagged: confidence={confidence:.2f}, detector={detector_score:.2f}")
        
        classified.append(pr)
    
    return classified

def save_classified_prs(prs: List[Dict[str, Any]], output_path: str, logger):
    """Saves classified PRs to a CSV file."""
    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)
    
    fieldnames = [
        'id', 'number', 'title', 'author', 'source_type', 
        'confidence_score', 'flagged', 'detector_score', 'created_at'
    ]
    
    with open(output, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        
        for pr in prs:
            row = {
                'id': pr.get('id') or pr.get('number'),
                'number': pr.get('number'),
                'title': pr.get('title', ''),
                'author': pr.get('user', {}).get('login', ''),
                'source_type': pr.get('source_type'),
                'confidence_score': pr.get('confidence_score'),
                'flagged': pr.get('flagged'),
                'detector_score': pr.get('detector_score'),
                'created_at': pr.get('created_at', '')
            }
            writer.writerow(row)
    
    logger.info(f"Saved {len(prs)} classified PRs to {output}")

def run_classification(raw_dir: str, output_csv: str):
    """Main entry point for the classification pipeline."""
    logger = setup_logging_and_config()
    logger.info("Starting PR classification pipeline...")
    
    # Load raw data
    prs = load_prs_from_raw(raw_dir)
    if not prs:
        raise ValueError("No PRs found in raw directory. Did T013 run successfully?")
    
    logger.info(f"Loaded {len(prs)} PRs from {raw_dir}")
    
    # Classify
    classified = classify_prs(prs, logger)
    
    # Save
    save_classified_prs(classified, output_csv, logger)
    
    logger.info("Classification pipeline complete.")

def main():
    """CLI entry point."""
    from utils.config import get_path
    
    raw_dir = get_path("data_raw")
    output_csv = get_path("data_processed") / "prs_classified.csv"
    
    run_classification(str(raw_dir), str(output_csv))

if __name__ == "__main__":
    main()