# --- Classification Logic (Primary) ---

def is_llm_bot(author: str) -> bool:
    """Check if author is a known LLM bot (e.g., Copilot)."""
    llm_patterns = [
        r'copilot', r'github-copilot', r'copilot-bot',
        r'codex', r'code-whisperer', r'genie'
    ]
    author_lower = author.lower()
    return any(re.search(p, author_lower) for p in llm_patterns)

def is_human_bot(author: str) -> bool:
    """Check if author is an infrastructure bot (e.g., dependabot)."""
    infra_patterns = [
        r'dependabot', r'stale-bot', r'renovate', r'codecov',
        r'travis', r'circleci', r'jenkins', r'github-actions'
    ]
    author_lower = author.lower()
    return any(re.search(p, author_lower) for p in infra_patterns)

def has_llm_signature(message: str) -> bool:
    """Check for LLM signatures in commit message."""
    if not message:
        return False
    message_lower = message.lower()
    signatures = [
        'generated by copilot', 'copilot generated', 'copilot:',
        'generated by codeium', 'generated by tabnine',
        'this code was generated by'
    ]
    return any(sig in message_lower for sig in signatures)

def calculate_confidence_score(author: str, message: str) -> float:
    """
    Calculate primary confidence score based on author and message.
    Returns float in [0.0, 1.0].
    """
    score = 0.5  # Base uncertainty
    
    if is_llm_bot(author):
        score = 0.95
        if has_llm_signature(message):
            score = 0.99
    elif is_human_bot(author):
        score = 0.10
    else:
        if has_llm_signature(message):
            score = 0.85
        elif 'generated' in message.lower() and 'by' in message.lower():
            score = 0.65
        
    # Normalize
    return max(0.0, min(1.0, score))

# --- Secondary Detector Logic (T015 Implementation) ---

def calculate_code_entropy(code_block: str) -> float:
    """
    Calculate Shannon entropy of a code block based on character frequencies.
    Higher entropy suggests more randomness (potentially synthetic).
    """
    if not code_block:
        return 0.0
    
    char_counts = Counter(code_block)
    total_chars = len(code_block)
    entropy = 0.0
    
    for count in char_counts.values():
        if count > 0:
            p = count / total_chars
            entropy -= p * math.log2(p)
    
    return entropy

def calculate_ngram_anomaly_score(code_block: str, n: int = 4) -> float:
    """
    Calculate n-gram anomaly score.
    Compares n-gram frequency against a baseline of typical code.
    Returns a score where higher values indicate more anomalous (potentially synthetic) patterns.
    """
    if not code_block or len(code_block) < n:
        return 0.0
    
    # Extract n-grams
    ngrams = [code_block[i:i+n] for i in range(len(code_block) - n + 1)]
    if not ngrams:
        return 0.0
    
    counts = Counter(ngrams)
    total = len(ngrams)
    
    # Calculate entropy of n-gram distribution
    entropy = 0.0
    for count in counts.values():
        p = count / total
        if p > 0:
            entropy -= p * math.log2(p)
    
    # Normalize entropy to [0, 1] (approximate, assuming max entropy for random string)
    # Max entropy for n-grams is log2(total_possible_ngrams), but we normalize by max possible entropy for this length
    max_entropy = math.log2(len(code_block) - n + 1) if len(code_block) > n else 1.0
    if max_entropy == 0:
        max_entropy = 1.0
        
    normalized_entropy = entropy / max_entropy
    
    # Synthetic code often has lower entropy (repetitive) or specific high-entropy patterns
    # We use normalized entropy as a proxy; if it's too high or too low, it might be anomalous
    # For simplicity, we return normalized entropy as the score
    # In a real scenario, we'd compare against a baseline distribution
    return normalized_entropy

def compute_secondary_detector_score(diff_text: str) -> float:
    """
    Compute the secondary detector score based on code entropy and n-gram anomaly.
    Returns a float in [0.0, 1.0].
    """
    if not diff_text:
        return 0.0
    
    # Calculate metrics
    entropy = calculate_code_entropy(diff_text)
    ngram_score = calculate_ngram_anomaly_score(diff_text)
    
    # Normalize entropy (typical code entropy is around 3-5 bits for ASCII)
    # We'll normalize to [0, 1] assuming max entropy around 6.0 for random ASCII
    normalized_entropy = min(1.0, entropy / 6.0)
    
    # Combine scores
    # Heuristic: synthetic code might have higher entropy (randomness) or lower (repetition)
    # We'll take the average as a simple fusion
    # A more sophisticated approach would use a trained model
    combined_score = (normalized_entropy + ngram_score) / 2.0
    
    return combined_score

# --- Data Loading & Saving ---

def load_prs_from_raw(raw_dir: Path) -> List[Dict[str, Any]]:
    """Load PRs from raw JSON files."""
    prs = []
    if not raw_dir.exists():
        logger.error(f"Raw directory {raw_dir} does not exist.")
        return prs
    
    for file_path in raw_dir.glob("*.json"):
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
                if isinstance(data, list):
                    prs.extend(data)
                else:
                    prs.append(data)
        except json.JSONDecodeError as e:
            logger.warning(f"Failed to parse {file_path}: {e}")
    
    logger.info(f"Loaded {len(prs)} PRs from {raw_dir}")
    return prs

def classify_prs(prs: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Classify PRs with primary and secondary detectors.
    Adds 'source_type', 'confidence_score', 'flagged', 'detector_score'.
    """
    classified = []
    
    for pr in prs:
        author = pr.get('user', {}).get('login', '')
        message = pr.get('title', '') + ' ' + pr.get('body', '')
        diff_text = pr.get('diff', '')  # Assuming diff is stored in 'diff' field
        
        # Primary classification
        is_llm = is_llm_bot(author) or has_llm_signature(message)
        source_type = 'llm' if is_llm else 'human'
        confidence = calculate_confidence_score(author, message)
        flagged = confidence < 0.6
        
        # Secondary detector (T015)
        detector_score = compute_secondary_detector_score(diff_text)
        
        pr['source_type'] = source_type
        pr['confidence_score'] = confidence
        pr['flagged'] = flagged
        pr['detector_score'] = detector_score
        
        classified.append(pr)
    
    return classified

def save_classified_prs(classified_prs: List[Dict[str, Any]], output_path: Path):
    """Save classified PRs to CSV."""
    if not classified_prs:
        logger.warning("No PRs to save.")
        return
    
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    fieldnames = [
        'pr_id', 'source_type', 'confidence_score', 'flagged', 
        'detector_score', 'author', 'title', 'created_at'
    ]
    
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        
        for pr in classified_prs:
            row = {k: pr.get(k, '') for k in fieldnames}
            # Ensure numeric fields are floats
            if 'confidence_score' in row:
                row['confidence_score'] = float(row['confidence_score'])
            if 'detector_score' in row:
                row['detector_score'] = float(row['detector_score'])
            if 'flagged' in row:
                row['flagged'] = str(row['flagged']).lower() == 'true'
            writer.writerow(row)
    
    logger.info(f"Saved {len(classified_prs)} classified PRs to {output_path}")

def run_classification(raw_dir: Path, output_path: Path):
    """Main pipeline for classification."""
    logger.info("Starting classification pipeline...")
    prs = load_prs_from_raw(raw_dir)
    if not prs:
        logger.error("No PRs loaded. Exiting.")
        return
    
    classified = classify_prs(prs)
    save_classified_prs(classified, output_path)
    logger.info("Classification pipeline completed.")

def main():
    """Entry point for the script."""
    config = setup_logging_and_config()
    
    # Paths
    raw_dir = Path(config.get('raw_data_dir', 'data/raw'))
    output_path = Path(config.get('classified_output', 'data/processed/prs_classified.csv'))
    
    run_classification(raw_dir, output_path)

if __name__ == '__main__':
    main()