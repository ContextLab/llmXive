# Entropy thresholds (bits per token)
# Typical human code tends to be more structured (lower entropy) or highly variable (high entropy).
# LLM code often falls in a specific "sweet spot" of moderate entropy.
ENTROPY_THRESHOLD_LOW = 2.5
ENTROPY_THRESHOLD_HIGH = 5.5

# N-gram parameters
NGRAM_SIZE = 3
NGRAM_ANOMALY_THRESHOLD = 0.3  # Jaccard similarity threshold

# Scoring weights
WEIGHT_ENTROPY = 0.6
WEIGHT_NGRAM = 0.4

