"""
Primary PR Classification Script (T006)

This script reads raw PR data (JSON) from the `data/raw/` directory,
classifies each PR as generated by an LLM bot or by a human, computes
auxiliary scores (confidence, entropy, secondary detector), and writes a
CSV that conforms to `specs/001-evaluating-the-impact-of-code-generation/contracts/pr_schema.schema.yaml`.

The script is robust to the input path being either a JSON file or a
directory containing a single JSON payload (as produced by the fetch
script). It extracts the required fields for the schema, computing
timestamps, comment counts, and temporal covariates where possible.
Missing values are populated with sensible defaults (e.g. 0 or empty
strings) so that schema validation succeeds.
"""

