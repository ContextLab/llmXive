from data.entropy_detector import compute_entropy  # secondary entropy detector

# ----------------------------------------------------------------------
# Configuration & Constants
# ----------------------------------------------------------------------
LLM_BOT_USERNAMES = {
    "copilot-bot",
    "github-copilot",
    "codex-bot",
    "gpt-bot",
    "llama-bot",
    "claude-bot",
    "gemini-bot",
    "deepseek-bot",
}

INFRA_BOT_USERNAMES = {
    "dependabot",
    "renovate",
    "snyk",
    "codecov",
    "coveralls",
    "travis-ci",
    "circleci",
    "jenkins",
    "github-actions",
}

LLM_COMMIT_INDICATORS = [
    "copilot",
    "generated by",
    "generated with",
    "auto-generated",
    "ai-generated",
    "llm",
    "copilot suggested",
]

# ----------------------------------------------------------------------
# Helper Functions
# ----------------------------------------------------------------------
logger = get_logger(__name__)

def set_reproducibility_seed(seed: int = 42) -> None:
    """Set the global random seed for any stochastic components."""
    set_global_seed(seed)

def is_llm_bot(user: str) -> bool:
    """Return True if the username matches a known LLM bot."""
    return any(bot in user.lower() for bot in LLM_BOT_USERNAMES)

def is_infra_bot(user: str) -> bool:
    """Return True if the username matches a known infrastructure bot."""
    return any(bot in user.lower() for bot in INFRA_BOT_USERNAMES)

def has_llm_signature(message: str) -> bool:
    """Return True if the commit / PR title/message contains LLM markers."""
    if not message:
        return False
    lowered = message.lower()
    return any(indicator in lowered for indicator in LLM_COMMIT_INDICATORS)

def calculate_signature_strength(user: str, message: str) -> float:
    """
    Compute a simple strength score (0‑1) based on presence of bot username
    and LLM commit markers.
    """
    score = 0.0
    if is_llm_bot(user):
        score += 0.5
    if has_llm_signature(message):
        score += 0.5
    return min(score, 1.0)

def calculate_confidence_score(user: str, message: str) -> float:
    """
    Primary confidence score:
    - 1.0 for exact LLM‑bot username match
    - 0.0 for known infra‑bot (human) match
    - otherwise the signature strength (0‑1)
    """
    if is_infra_bot(user):
        return 0.0
    if is_llm_bot(user):
        return 1.0
    return calculate_signature_strength(user, message)

def parse_timestamp(ts: str) -> Optional[datetime]:
    """Parse ISO‑8601 timestamps used by the GitHub API."""
    if not ts:
        return None
    formats = [
        "%Y-%m-%dT%H:%M:%SZ",
        "%Y-%m-%dT%H:%M:%S.%fZ",
        "%Y-%m-%d %H:%M:%S",
        "%Y-%m-%dT%H:%M:%S",
    ]
    for fmt in formats:
        try:
            return datetime.strptime(ts, fmt)
        except ValueError:
            continue
    logger.warning(f"Unparseable timestamp: {ts}")
    return None

def calculate_time_to_merge(created: str, merged: str) -> float:
    """
    Return minutes between creation and merge.
    If merge timestamp missing or earlier than creation, return -1.0.
    """
    created_dt = parse_timestamp(created)
    merged_dt = parse_timestamp(merged)
    if created_dt and merged_dt and merged_dt > created_dt:
        delta = merged_dt - created_dt
        return delta.total_seconds() / 60.0
    return -1.0

def extract_comment_count(pr: Dict[str, Any]) -> int:
    """Sum of top‑level comment fields."""
    comments = int(pr.get("comments", 0))
    review_comments = int(pr.get("review_comments", 0))
    return comments + review_comments

def calculate_review_cycles(pr: Dict[str, Any]) -> int:
    """
    Very simple heuristic: count distinct review states in the
    `review_events` list if present, otherwise default to 1.
    """
    events = pr.get("review_events", [])
    if not events:
        return 1
    states = {e.get("state", "").upper() for e in events if e.get("state")}
    return max(1, len(states))

def extract_diff_text(pr: Dict[str, Any]) -> str:
    """Extract raw diff text from common keys; fallback to empty string."""
    for key in ("diff", "patch", "body", "description", "text"):
        if key in pr and isinstance(pr[key], str):
            return pr[key]
    return ""

def load_prs_from_raw(input_path: str) -> List[Dict[str, Any]]:
    """
    Load PR objects from a JSON file or a directory containing a single
    JSON payload (ignoring auxiliary files such as `fetch_stats.json`).
    """
    path = Path(input_path)
    if path.is_dir():
        # Find the first JSON file that is not a known meta‑file
        json_files = [
            p for p in path.iterdir()
            if p.is_file() and p.suffix.lower() == ".json"
            and p.name != "fetch_stats.json"
        ]
        if not json_files:
            raise FileNotFoundError(f"No JSON payload found in directory {input_path}")
        json_path = json_files[0]
    else:
        json_path = path

    logger.info(f"Loading raw PR data from {json_path}")
    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    # The fetch script may wrap the list under a key; handle common patterns
    if isinstance(data, dict):
        if "prs" in data:
            return data["prs"]
        # If the file contains a single large dict per PR (unlikely), wrap it
        return [data]
    elif isinstance(data, list):
        return data
    else:
        raise ValueError("Unexpected JSON structure for raw PR data")

# ----------------------------------------------------------------------
# Main Classification Logic
# ----------------------------------------------------------------------
def classify_prs(prs: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Produce a list of dictionaries conforming to the PR schema.

    Required columns (per schema):
      pr_id, repo, source_type, confidence_score, flagged_for_audit,
      comment_count, time_to_merge_minutes, review_cycles,
      complexity_score, loc, entropy_score, hour_of_day, day_of_week
    """
    results: List[Dict[str, Any]] = []

    for pr in prs:
        # Basic identifiers
        pr_id = int(pr.get("id") or pr.get("number") or 0)
        repo = (
            pr.get("base", {})
            .get("repo", {})
            .get("full_name")
            or pr.get("repository", {})
            .get("full_name")
            or ""
        )

        # User / message for primary signature
        user = (
            pr.get("user", {})
            .get("login")
            or pr.get("author", "")
            or ""
        )
        message = pr.get("title") or pr.get("commit_message") or pr.get("body") or ""

        # Primary classification
        confidence = calculate_confidence_score(user, message)
        source_type = "llm" if confidence >= 0.6 else "human"
        flagged_for_audit = confidence < 0.6

        # Secondary detector (entropy)
        diff_text = extract_diff_text(pr)
        entropy_score = compute_entropy(diff_text)  # returns 0‑1

        # Additional metrics needed for the schema
        comment_count = extract_comment_count(pr)
        time_to_merge = calculate_time_to_merge(
            pr.get("created_at", ""), pr.get("merged_at", "")
        )
        review_cycles = calculate_review_cycles(pr)

        # Temporal covariates
        created_dt = parse_timestamp(pr.get("created_at", ""))
        if created_dt:
            hour_of_day = created_dt.hour
            day_of_week = created_dt.weekday()
        else:
            hour_of_day = -1
            day_of_week = -1

        # Place‑holders for fields that are computed later
        complexity_score = 0.0
        loc = 0

        results.append(
            {
                "pr_id": pr_id,
                "repo": repo,
                "source_type": source_type,
                "confidence_score": round(confidence, 4),
                "flagged_for_audit": flagged_for_audit,
                "comment_count": comment_count,
                "time_to_merge_minutes": round(time_to_merge, 4) if time_to_merge >= 0 else -1.0,
                "review_cycles": review_cycles,
                "complexity_score": complexity_score,
                "loc": loc,
                "entropy_score": round(entropy_score, 4),
                "hour_of_day": hour_of_day,
                "day_of_week": day_of_week,
            }
        )
    return results

def save_classified_prs(results: List[Dict[str, Any]], output_path: str) -> None:
    """Write the classification results to CSV, creating parent directories."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    fieldnames = [
        "pr_id",
        "repo",
        "source_type",
        "confidence_score",
        "flagged_for_audit",
        "comment_count",
        "time_to_merge_minutes",
        "review_cycles",
        "complexity_score",
        "loc",
        "entropy_score",
        "hour_of_day",
        "day_of_week",
    ]
    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(results)

def run_classification(input_path: str, output_path: str) -> Dict[str, Any]:
    """Execute the end‑to‑end classification pipeline."""
    logger.log("classification_started", input=input_path, output=output_path)

    prs = load_prs_from_raw(input_path)
    logger.log("raw_prs_loaded", count=len(prs))

    results = classify_prs(prs)
    logger.log("classification_completed", llm=sum(1 for r in results if r["source_type"] == "llm"))

    save_classified_prs(results, output_path)
    logger.log("results_saved", path=output_path)

    summary = {
        "total_prs": len(results),
        "llm_count": sum(1 for r in results if r["source_type"] == "llm"),
        "human_count": sum(1 for r in results if r["source_type"] == "human"),
        "output_file": output_path,
    }
    return summary

# ----------------------------------------------------------------------
# CLI Entry Point
# ----------------------------------------------------------------------
def main() -> None:
    parser = argparse.ArgumentParser(description="Classify PRs as LLM‑generated or Human‑authored")
    parser.add_argument("--input", required=True, help="Path to raw PR JSON (file or directory)")
    parser.add_argument("--output", required=True, help="Path to output CSV")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for reproducibility")
    args = parser.parse_args()

    # Initialise logging and reproducibility
    setup_logging(script_name="classify_prs")
    set_reproducibility_seed(args.seed)

    try:
        summary = run_classification(args.input, args.output)
        print(json.dumps(summary, indent=2))
    except Exception as exc:
        logger.log("classification_failed", error=str(exc))
        print(f"Error: {exc}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()