import os
import csv
import json
from pathlib import Path
from typing import List, Dict, Any
from utils.logging import get_logger, setup_logging
from utils.config import get_path

logger = get_logger(__name__)

def setup_logging_and_config():
    """Initialize logging and configuration for the metrics saving process."""
    setup_logging()
    logger.info("Starting metrics saving process")
    return get_path("processed", "prs_metrics.csv")

def load_metrics_from_json(metrics_dir: Path) -> List[Dict[str, Any]]:
    """
    Load metrics from the processed JSON files generated by extract_metrics.py.
    Expects a directory structure where metrics are stored in JSON format.
    """
    metrics_file = metrics_dir / "extracted_metrics.json"
    if not metrics_file.exists():
        logger.error(f"Metrics file not found: {metrics_file}")
        raise FileNotFoundError(f"Metrics file not found: {metrics_file}")
    
    with open(metrics_file, 'r') as f:
        return json.load(f)

def save_metrics_to_csv(metrics: List[Dict[str, Any]], output_path: Path):
    """
    Save the processed metrics to a CSV file with the required schema:
    pr_id (int), comment_count (int), time_to_merge_minutes (float), 
    review_cycles (int), complexity_score (float).
    
    This implements T023: Save processed metrics to data/processed/prs_metrics.csv
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    fieldnames = ['pr_id', 'comment_count', 'time_to_merge_minutes', 
                 'review_cycles', 'complexity_score']
    
    with open(output_path, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        
        for metric in metrics:
            row = {
                'pr_id': int(metric['pr_id']),
                'comment_count': int(metric['comment_count']),
                'time_to_merge_minutes': float(metric['time_to_merge_minutes']),
                'review_cycles': int(metric['review_cycles']),
                'complexity_score': float(metric['complexity_score'])
            }
            writer.writerow(row)
        
        logger.info(f"Saved {len(metrics)} metrics to {output_path}")

def run_save_metrics():
    """Main entry point for saving metrics to CSV."""
    output_path = setup_logging_and_config()
    metrics_dir = get_path("processed")
    
    try:
        metrics = load_metrics_from_json(metrics_dir)
        save_metrics_to_csv(metrics, output_path)
        logger.info("Metrics saving completed successfully")
        return True
    except Exception as e:
        logger.error(f"Failed to save metrics: {e}")
        raise

def main():
    """Script entry point."""
    run_save_metrics()

if __name__ == "__main__":
    main()
