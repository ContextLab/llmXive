"""
T017: Save the labeled dataset to data/processed/prs_labeled.csv.

This script aggregates the classification results (source_type, confidence_score, flagged)
and secondary detector scores (detector_score) into a final processed CSV file.
It also includes relevant metadata (repo, pr_number, merged_at, author) for downstream analysis.

Dependencies:
  - code/data/classify_prs.py (load_prs_from_raw)
  - code/utils/logging.py
  - code/utils/config.py
"""
import os
import csv
import json
from pathlib import Path
from typing import List, Dict, Any, Optional

# Import from project utilities
from utils.logging import get_logger, setup_logging
from utils.config import get_config_summary

# Import classification functions to load raw data
from data.classify_prs import load_prs_from_raw

def setup_logging_and_config():
    """Initialize logging and return config summary."""
    setup_logging()
    logger = get_logger("save_labeled_dataset")
    config_summary = get_config_summary()
    return logger, config_summary

def load_classified_prs(raw_data_dir: Path) -> List[Dict[str, Any]]:
    """
    Load classified PRs from the raw JSON files generated by fetch_github.py
    and processed by classify_prs.py.
    
    Returns a list of dictionaries containing classification results.
    """
    logger = get_logger("save_labeled_dataset")
    prs = load_prs_from_raw(raw_data_dir)
    
    if not prs:
        logger.warning("No PRs found in raw data directory. Ensure T013 and T014/015 have run.")
        return []
    
    logger.info(f"Loaded {len(prs)} classified PRs from raw data.")
    return prs

def save_labeled_dataset(prs: List[Dict[str, Any]], output_path: Path):
    """
    Save the labeled dataset to a CSV file.
    
    Output columns:
      - pr_id: Unique identifier (repo + pr_number)
      - source_type: 'llm' or 'human'
      - confidence_score: Float (0.0 to 1.0)
      - flagged: Boolean (True if confidence < 0.6)
      - detector_score: Float (secondary detector score)
      - repo: Repository name
      - pr_number: Pull request number
      - author: Author username
      - merged_at: Timestamp of merge (if applicable)
      - created_at: Timestamp of creation
    """
    logger = get_logger("save_labeled_dataset")
    
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Define CSV fieldnames based on requirements
    fieldnames = [
        "pr_id", "source_type", "confidence_score", "flagged", "detector_score",
        "repo", "pr_number", "author", "merged_at", "created_at"
    ]
    
    rows_written = 0
    with open(output_path, 'w', newline='', encoding='utf-8') as csvfile:
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        writer.writeheader()
        
        for pr in prs:
            # Ensure all required fields exist, use defaults if missing
            row = {
                "pr_id": pr.get("pr_id", f"{pr.get('repo', 'unknown')}_{pr.get('pr_number', 'unknown')}"),
                "source_type": pr.get("source_type", "unknown"),
                "confidence_score": pr.get("confidence_score", 0.0),
                "flagged": pr.get("flagged", False),
                "detector_score": pr.get("detector_score", 0.0),
                "repo": pr.get("repo", ""),
                "pr_number": pr.get("pr_number", ""),
                "author": pr.get("author", ""),
                "merged_at": pr.get("merged_at", ""),
                "created_at": pr.get("created_at", "")
            }
            
            # Convert boolean to string for CSV
            row["flagged"] = str(row["flagged"]).lower()
            
            writer.writerow(row)
            rows_written += 1
    
    logger.info(f"Successfully saved {rows_written} labeled PRs to {output_path}")

def run_save_labeled_dataset(raw_data_dir: Optional[Path] = None, output_dir: Optional[Path] = None):
    """
    Main execution function for T017.
    
    Args:
        raw_data_dir: Path to directory containing raw JSON files (default: data/raw/)
        output_dir: Path to directory for output CSV (default: data/processed/)
    """
    logger, config = setup_logging_and_config()
    
    if raw_data_dir is None:
        raw_data_dir = Path("data/raw")
    if output_dir is None:
        output_dir = Path("data/processed")
    
    logger.info("Starting save_labeled_dataset process.")
    logger.info(f"Raw data directory: {raw_data_dir}")
    logger.info(f"Output directory: {output_dir}")
    
    # Load classified PRs
    prs = load_classified_prs(raw_data_dir)
    
    if not prs:
        logger.error("No PRs to save. Exiting.")
        return False
    
    # Define output path
    output_path = output_dir / "prs_labeled.csv"
    
    # Save dataset
    save_labeled_dataset(prs, output_path)
    
    logger.info("save_labeled_dataset completed successfully.")
    return True

def main():
    """Entry point for the script."""
    success = run_save_labeled_dataset()
    if not success:
        exit(1)

if __name__ == "__main__":
    main()
