"""
Validate output logs against the output schema contracts.

This script reads generated output logs (e.g., from T029c-gen) and verifies
that they conform to the schema defined in `contracts/output.schema.yaml`
(generated by T000b-gen).

It performs strict schema validation and reports any discrepancies.
"""

import json
import os
import sys
import argparse
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional

# Attempt to import yaml for schema loading
try:
    import yaml
except ImportError:
    print("Error: PyYAML is required. Install with: pip install pyyaml")
    sys.exit(1)


class SchemaValidationError(Exception):
    """Raised when a log file fails schema validation."""
    pass


def load_schema(schema_path: Path) -> Dict[str, Any]:
    """Load and parse the YAML schema file."""
    if not schema_path.exists():
        raise FileNotFoundError(f"Schema file not found: {schema_path}")

    with open(schema_path, 'r', encoding='utf-8') as f:
        schema = yaml.safe_load(f)

    if schema is None:
        raise ValueError(f"Schema file is empty or invalid: {schema_path}")

    return schema


def load_log_file(log_path: Path) -> List[Dict[str, Any]]:
    """Load a JSON log file (or JSONL) into a list of records."""
    if not log_path.exists():
        raise FileNotFoundError(f"Log file not found: {log_path}")

    records = []

    with open(log_path, 'r', encoding='utf-8') as f:
        content = f.read().strip()

    if not content:
        logging.warning(f"Log file is empty: {log_path}")
        return records

    # Try parsing as a single JSON object (array) first
    try:
        data = json.loads(content)
        if isinstance(data, list):
            records = data
        elif isinstance(data, dict):
            # If it's a single object, wrap it in a list
            records = [data]
        else:
            raise ValueError(f"Unexpected JSON structure in {log_path}: expected list or object")
    except json.JSONDecodeError:
        # If that fails, try parsing as JSONL (one JSON object per line)
        logging.info(f"Attempting JSONL parsing for {log_path}")
        for line_num, line in enumerate(content.splitlines(), 1):
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError as e:
                raise ValueError(f"Invalid JSON on line {line_num} in {log_path}: {e}")

    return records


def validate_record_against_schema(record: Dict[str, Any], schema: Dict[str, Any]) -> List[str]:
    """
    Validate a single record against the schema.
    This is a basic structural validation based on 'properties' and 'required' fields.
    """
    errors = []
    properties = schema.get('properties', {})
    required_fields = schema.get('required', [])

    # Check required fields
    for field in required_fields:
        if field not in record:
            errors.append(f"Missing required field: '{field}'")

    # Check types for present fields
    for key, value in record.items():
        if key in properties:
            expected_type = properties[key].get('type')
            if expected_type:
                actual_type = type(value).__name__
                # Simple type mapping
                type_map = {
                    'string': str,
                    'integer': int,
                    'number': (int, float),
                    'boolean': bool,
                    'array': list,
                    'object': dict
                }
                expected_python_type = type_map.get(expected_type)
                if expected_python_type and not isinstance(value, expected_python_type):
                    errors.append(f"Field '{key}' has wrong type: expected {expected_type}, got {actual_type}")
        else:
            # Optional: warn about unknown fields if strict mode is desired
            logging.debug(f"Field '{key}' not defined in schema (allowed if not strict)")

    return errors


def validate_against_schema(logs: List[Dict[str, Any]], schema: Dict[str, Any], log_path: Path) -> Dict[str, Any]:
    """
    Validate all records in the log list against the schema.
    Returns a validation report.
    """
    report = {
        "log_file": str(log_path),
        "schema_file": str(Path(schema.get("id", "unknown"))), # Fallback if id not present
        "total_records": len(logs),
        "valid_records": 0,
        "invalid_records": 0,
        "errors": []
    }

    for i, record in enumerate(logs):
        record_errors = validate_record_against_schema(record, schema)
        if record_errors:
            report["invalid_records"] += 1
            report["errors"].append({
                "record_index": i,
                "errors": record_errors
            })
        else:
            report["valid_records"] += 1

    report["is_valid"] = report["invalid_records"] == 0
    return report


def main():
    parser = argparse.ArgumentParser(
        description="Validate output logs against the output schema contracts."
    )
    parser.add_argument(
        "--logs",
        type=str,
        required=True,
        help="Path to the output log file (JSON or JSONL) to validate."
    )
    parser.add_argument(
        "--schema",
        type=str,
        required=True,
        help="Path to the output schema YAML file (contracts/output.schema.yaml)."
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Path to write the validation report JSON. If not provided, prints to stdout."
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Fail immediately on first error."
    )

    args = parser.parse_args()

    # Setup logging
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(levelname)s - %(message)s'
    )

    try:
        schema_path = Path(args.schema)
        log_path = Path(args.logs)

        logging.info(f"Loading schema from: {schema_path}")
        schema = load_schema(schema_path)

        logging.info(f"Loading logs from: {log_path}")
        logs = load_log_file(log_path)

        if not logs:
            logging.warning("No records found in log file. Validation skipped.")
            report = {
                "log_file": str(log_path),
                "schema_file": str(schema_path),
                "total_records": 0,
                "valid_records": 0,
                "invalid_records": 0,
                "errors": [],
                "is_valid": True # Empty is technically valid
            }
        else:
            logging.info(f"Validating {len(logs)} records against schema...")
            report = validate_against_schema(logs, schema, log_path)

        # Output results
        report_json = json.dumps(report, indent=2)

        if args.output:
            output_path = Path(args.output)
            output_path.parent.mkdir(parents=True, exist_ok=True)
            with open(output_path, 'w', encoding='utf-8') as f:
                f.write(report_json)
            logging.info(f"Validation report written to: {output_path}")
        else:
            print(report_json)

        # Exit with error code if validation failed and not in non-strict mode
        if not report["is_valid"]:
            logging.error("Validation FAILED. Invalid records found.")
            if args.strict:
                sys.exit(1)
        else:
            logging.info("Validation PASSED.")
            sys.exit(0)

    except FileNotFoundError as e:
        logging.error(f"File not found: {e}")
        sys.exit(1)
    except ValueError as e:
        logging.error(f"Validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logging.error(f"Unexpected error: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()