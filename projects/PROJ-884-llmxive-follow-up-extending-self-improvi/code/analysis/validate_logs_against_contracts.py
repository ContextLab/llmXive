"""
Task T016b: Validate output logs against the output schema contract.

This script reads output logs generated by the BES loop (specifically
data/processed/statistical_report.json as the primary output of T029c-gen)
and validates them against the schema defined in contracts/output.schema.yaml.

It ensures that the generated report contains all required fields, correct
data types, and adheres to the structural constraints defined in the contract.
"""

import json
import os
import sys
import argparse
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional

# Add parent directory to path for imports if running as script
if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).parent.parent))

try:
    import yaml
except ImportError:
    logging.critical("PyYAML is required. Install with: pip install pyyaml")
    sys.exit(1)

from exceptions import BaseResearchException, VERIFIER_ERROR

logger = logging.getLogger(__name__)


class SchemaValidationError(BaseResearchException):
    """Custom exception for schema validation failures."""
    pass


def load_schema(schema_path: Path) -> Dict[str, Any]:
    """
    Load and parse the YAML schema file.

    Args:
        schema_path: Path to the output.schema.yaml file.

    Returns:
        Dictionary representing the schema.

    Raises:
        FileNotFoundError: If the schema file does not exist.
        SchemaValidationError: If the schema file is invalid YAML.
    """
    if not schema_path.exists():
        raise FileNotFoundError(f"Schema file not found: {schema_path}")

    try:
        with open(schema_path, 'r', encoding='utf-8') as f:
            schema = yaml.safe_load(f)
        if not isinstance(schema, dict):
            raise SchemaValidationError("Schema file must contain a YAML mapping.")
        return schema
    except yaml.YAMLError as e:
        raise SchemaValidationError(f"Invalid YAML in schema file: {e}")


def load_log_file(log_path: Path) -> Dict[str, Any]:
    """
    Load the JSON log file to be validated.

    Args:
        log_path: Path to the JSON log file.

    Returns:
        Dictionary representing the log data.

    Raises:
        FileNotFoundError: If the log file does not exist.
        SchemaValidationError: If the log file is invalid JSON.
    """
    if not log_path.exists():
        raise FileNotFoundError(f"Log file not found: {log_path}")

    try:
        with open(log_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        if not isinstance(data, dict):
            raise SchemaValidationError("Log file must contain a JSON object.")
        return data
    except json.JSONDecodeError as e:
        raise SchemaValidationError(f"Invalid JSON in log file: {e}")


def validate_against_schema(data: Dict[str, Any], schema: Dict[str, Any]) -> List[str]:
    """
    Perform basic validation of data against a JSON-schema-like YAML structure.

    This implementation supports a subset of JSON Schema features sufficient
    for the project's output contracts:
    - 'required': list of required keys
    - 'properties': dictionary of property definitions
    - 'type': expected type (string, number, boolean, object, array)
    - 'items': schema for array items (if type is array)

    Args:
        data: The data to validate.
        schema: The schema to validate against.

    Returns:
        A list of error messages. Empty if validation passes.
    """
    errors = []

    # Check required fields
    if 'required' in schema:
        for field in schema['required']:
            if field not in data:
                errors.append(f"Missing required field: '{field}'")

    # Check properties
    if 'properties' in schema:
        for prop_name, prop_schema in schema['properties'].items():
            if prop_name in data:
                value = data[prop_name]
                expected_type = prop_schema.get('type')

                if expected_type:
                    type_valid = False
                    if expected_type == 'string':
                        type_valid = isinstance(value, str)
                    elif expected_type == 'number':
                        type_valid = isinstance(value, (int, float))
                    elif expected_type == 'boolean':
                        type_valid = isinstance(value, bool)
                    elif expected_type == 'object':
                        type_valid = isinstance(value, dict)
                    elif expected_type == 'array':
                        type_valid = isinstance(value, list)

                    if not type_valid:
                        errors.append(f"Field '{prop_name}' has invalid type. Expected {expected_type}, got {type(value).__name__}")
                    
                    # Recursively validate nested objects
                    if expected_type == 'object' and 'properties' in prop_schema:
                        nested_errors = validate_against_schema(value, prop_schema)
                        for err in nested_errors:
                            errors.append(f"Field '{prop_name}.{err}'")
                    
                    # Validate array items
                    if expected_type == 'array' and 'items' in prop_schema:
                        for i, item in enumerate(value):
                            if not isinstance(item, dict):
                                errors.append(f"Field '{prop_name}[{i}]' is not an object")
                            else:
                                item_errors = validate_against_schema(item, prop_schema['items'])
                                for err in item_errors:
                                    errors.append(f"Field '{prop_name}[{i}].{err}'")

    return errors


def main():
    """
    Main entry point for the validation script.

    Usage:
        python code/analysis/validate_logs_against_contracts.py --log <path> --schema <path>
    """
    parser = argparse.ArgumentParser(
        description="Validate output logs against the output schema contract."
    )
    parser.add_argument(
        "--log",
        type=str,
        required=True,
        help="Path to the JSON log file to validate (e.g., data/processed/statistical_report.json)."
    )
    parser.add_argument(
        "--schema",
        type=str,
        required=True,
        help="Path to the output.schema.yaml file."
    )
    parser.add_argument(
        "--output",
        type=str,
        default="data/processed/log_validation_report.json",
        help="Path to write the validation report."
    )

    args = parser.parse_args()

    # Setup logging
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(levelname)s - %(message)s'
    )

    log_path = Path(args.log)
    schema_path = Path(args.schema)
    output_path = Path(args.output)

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    try:
        logger.info(f"Loading schema from {schema_path}")
        schema = load_schema(schema_path)

        logger.info(f"Loading log file from {log_path}")
        log_data = load_log_file(log_path)

        logger.info("Validating log data against schema")
        validation_errors = validate_against_schema(log_data, schema)

        is_valid = len(validation_errors) == 0

        report = {
            "status": "PASS" if is_valid else "FAIL",
            "log_file": str(log_path),
            "schema_file": str(schema_path),
            "validation_errors": validation_errors,
            "error_count": len(validation_errors)
        }

        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(report, f, indent=2)

        if is_valid:
            logger.info("Validation PASSED. Report written to %s", output_path)
            sys.exit(0)
        else:
            logger.error("Validation FAILED. Found %d errors. Report written to %s", len(validation_errors), output_path)
            for err in validation_errors:
                logger.error("  - %s", err)
            sys.exit(1)

    except FileNotFoundError as e:
        logger.critical("File not found: %s", e)
        sys.exit(1)
    except SchemaValidationError as e:
        logger.critical("Schema validation error: %s", e)
        sys.exit(1)
    except Exception as e:
        logger.critical("Unexpected error during validation: %s", e)
        raise VERIFIER_ERROR(f"Unexpected error: {e}")


if __name__ == "__main__":
    main()