"""
Scalability Analysis Runner for T029b.
Executes the scalability analysis on the raw logs generated by T029a.
"""
import sys
import logging
from pathlib import Path

# Add project root to path if running as script
if str(Path(__file__).parent.parent) not in sys.path:
    sys.path.insert(0, str(Path(__file__).parent.parent))

from code.analysis.scalability_analyzer import main as analyze_main

def main():
    """
    Entry point for T029b: Implement Scalability Analysis.
    Reads data/processed/scaling_raw_logs.json, performs log-log regression,
    and writes data/processed/scaling_analysis.csv.
    """
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(levelname)s - %(message)s'
    )
    logger = logging.getLogger(__name__)
    logger.info("Starting Scalability Analysis (T029b)...")
    
    try:
        # Delegate to the analyzer which contains the core logic
        analyze_main()
        logger.info("Scalability analysis completed successfully.")
    except Exception as e:
        logger.error(f"Scalability analysis failed: {e}")
        raise

if __name__ == "__main__":
    main()
