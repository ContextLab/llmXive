"""
Configuration module for the Bidirectional Evolutionary Search (BES) framework.

Provides a simple dataclass ``BESConfig`` that holds all configuration parameters
required by the forward step, backward step, population manager and other
components.  The configuration can be loaded from a YAML file (generated by
``code/config.py`` or edited by the user) or instantiated with default values.
"""

from __future__ import annotations

import yaml
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict

@dataclass
class BESConfig:
    """Configuration parameters for the BES pipeline.

    The fields cover model loading, evolutionary hyper‑parameters and runtime
    settings.  All fields have sensible defaults that make the pilot run
    functional on a CPU‑only environment.
    """
    # -------------------------------------------------
    # Model / forward‑step configuration
    # -------------------------------------------------
    model_id: str = "distilbert-base-uncased"
    revision: str | None = None               # HuggingFace revision/commit SHA
    device: str = "cpu"
    use_bitsandbytes: bool = False
    use_ipex: bool = False
    ipex_precision: str = "bf16"
    max_length: int = 512
    temperature: float = 0.7
    top_k: int = 50
    top_p: float = 0.95

    # -------------------------------------------------
    # Evolutionary hyper‑parameters
    # -------------------------------------------------
    population_size: int = 30
    elite_rate: float = 0.1                 # proportion of elites kept each generation
    tournament_size: int = 3
    mutation_rate: float = 0.2
    crossover_rate: float = 0.7
    selection_method: str = "roulette"     # matches ``Population.SelectionMethod`` enum

    # -------------------------------------------------
    # Runtime settings
    # -------------------------------------------------
    seed: int = 42
    max_attempts: int = 100
    timeout_seconds: int = 300
    generations: int = 10

    @classmethod
    def load(cls, path: Path) -> "BESConfig":
        """Load a configuration from a YAML file.

        Parameters
        ----------
        path: Path
            Path to the YAML configuration file.

        Returns
        -------
        BESConfig
            An instance populated with the values from the file. Missing keys
            fall back to the dataclass defaults.
        """
        if not path.exists():
            raise FileNotFoundError(f"BES configuration file not found: {path}")

        with path.open("r", encoding="utf-8") as f:
            data = yaml.safe_load(f) or {}

        # ``data`` may contain keys that are not part of the dataclass – ignore them.
        field_names = {f.name for f in cls.__dataclass_fields__.values()}
        filtered: Dict[str, Any] = {k: v for k, v in data.items() if k in field_names}
        return cls(**filtered)

    def to_dict(self) -> Dict[str, Any]:
        """Return a plain‑dictionary representation (useful for logging)."""
        return {f: getattr(self, f) for f in self.__dataclass_fields__}

    def dump(self, path: Path) -> None:
        """Write the current configuration back to a YAML file."""
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8") as f:
            yaml.safe_dump(self.to_dict(), f)
