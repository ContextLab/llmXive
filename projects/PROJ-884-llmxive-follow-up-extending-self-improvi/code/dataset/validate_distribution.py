"""
Validate dataset distribution using the distribution report and schema.

This script reads `data/processed/distribution_report.json` (generated by T014c-exec)
and `contracts/dataset.schema.yaml` (generated by T000a-gen) to verify statistical
representativeness. It outputs `data/processed/distribution_validation.json` with
fields: `is_valid`, `power_estimate`, `notes`.

Constraint: Must strictly enforce "Fail Loudly" (no synthetic fallback).
"""
import json
import os
import sys
import math
from pathlib import Path
from typing import Dict, Any, List, Optional

# Add project root to path to allow imports from sibling modules
# In the actual project structure, this file is at code/dataset/validate_distribution.py
# We need to ensure we can import from the code directory
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

# Import the schema loader from the contract generation task
# Since we don't have a direct import path for the schema, we'll load it directly
from yaml import safe_load


def load_json(file_path: Path) -> Dict[str, Any]:
    """Load JSON file with error handling."""
    if not file_path.exists():
        raise FileNotFoundError(f"Required file not found: {file_path}")
    
    with open(file_path, 'r', encoding='utf-8') as f:
        return json.load(f)


def load_schema(file_path: Path) -> Dict[str, Any]:
    """Load YAML schema file."""
    if not file_path.exists():
        raise FileNotFoundError(f"Required schema file not found: {file_path}")
    
    with open(file_path, 'r', encoding='utf-8') as f:
        return safe_load(f)


def calculate_chi_square(
    observed: Dict[str, int], 
    expected_ratio: Dict[str, float], 
    total_count: int
) -> float:
    """
    Calculate chi-square statistic for type distribution.
    
    Args:
        observed: Dictionary of type -> count
        expected_ratio: Dictionary of type -> expected ratio (should sum to 1.0)
        total_count: Total number of samples
        
    Returns:
        Chi-square statistic value
    """
    chi_square = 0.0
    
    for puzzle_type, obs_count in observed.items():
        if puzzle_type not in expected_ratio:
            continue
        
        exp_count = expected_ratio[puzzle_type] * total_count
        if exp_count == 0:
            continue
        
        chi_square += ((obs_count - exp_count) ** 2) / exp_count
    
    return chi_square


def validate_complexity_scaling(
    distribution_data: Dict[str, Any]
) -> tuple[bool, List[str]]:
    """
    Validate that complexity scaling is continuous.
    
    Args:
        distribution_data: The distribution report data
        
    Returns:
        Tuple of (is_valid, list of notes/warnings)
    """
    notes = []
    is_valid = True
    
    # Check if complexity data exists
    if 'complexity_distribution' not in distribution_data:
        notes.append("No complexity distribution data found in report")
        return False, notes
    
    complexity_data = distribution_data['complexity_distribution']
    
    if 'n_values' not in complexity_data or 'counts' not in complexity_data:
        notes.append("Missing n_values or counts in complexity distribution")
        return False, notes
    
    n_values = complexity_data['n_values']
    counts = complexity_data['counts']
    
    if len(n_values) != len(counts):
        notes.append("Mismatch between n_values and counts lengths")
        return False, notes
    
    if len(n_values) < 2:
        notes.append("Insufficient data points for continuity check")
        return False, notes
    
    # Check for gaps in complexity scaling
    sorted_n = sorted(n_values)
    gaps = []
    for i in range(1, len(sorted_n)):
        gap = sorted_n[i] - sorted_n[i-1]
        if gap > 1:  # Allow some flexibility, but flag large gaps
            gaps.append((sorted_n[i-1], sorted_n[i], gap))
    
    if gaps:
        notes.append(f"Found {len(gaps)} gaps in complexity scaling: {gaps}")
        # Consider it valid if gaps are small, but flag it
        if any(g[2] > 10 for g in gaps):
            is_valid = False
    else:
        notes.append("Complexity scaling is continuous (no significant gaps)")
    
    return is_valid, notes


def calculate_power_estimate(
    chi_square: float, 
    degrees_of_freedom: int,
    significance_level: float = 0.05
) -> float:
    """
    Estimate statistical power based on chi-square statistic.
    
    This is a simplified estimation. In practice, power analysis would require
    effect size and sample size calculations.
    
    Args:
        chi_square: Chi-square statistic value
        degrees_of_freedom: Degrees of freedom for the test
        significance_level: Significance level (alpha)
        
    Returns:
        Estimated power (0.0 to 1.0)
    """
    if degrees_of_freedom <= 0:
        return 0.0
    
    # Critical value for chi-square distribution
    # Approximation using Wilson-Hilferty transformation
    critical_value = degrees_of_freedom * (1 - 2/(9*degrees_of_freedom) + 
                                          1.96 * math.sqrt(2/(9*degrees_of_freedom)))**3
    
    if chi_square <= critical_value:
        # Not significant, power is low
        return 0.5  # Neutral estimate
    
    # Rough power estimation based on effect size
    effect_size = chi_square / degrees_of_freedom
    power = min(1.0, effect_size / 3.0)  # Simplified scaling
    
    return power


def main():
    """Main function to validate dataset distribution."""
    # Define paths
    project_root = Path(__file__).resolve().parent.parent.parent
    distribution_report_path = project_root / "data" / "processed" / "distribution_report.json"
    schema_path = project_root / "contracts" / "dataset.schema.yaml"
    output_path = project_root / "data" / "processed" / "distribution_validation.json"
    
    # Load required files (fail loudly if missing)
    try:
        distribution_data = load_json(distribution_report_path)
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        print("Cannot proceed without distribution_report.json. Run T014c-exec first.")
        sys.exit(1)
    
    try:
        schema_data = load_schema(schema_path)
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        print("Cannot proceed without dataset schema. Run T000a-gen first.")
        sys.exit(1)
    
    # Extract expected ratios from schema or use defaults
    # The schema should define the expected distribution
    expected_ratio = {}
    if 'properties' in schema_data and 'type_distribution' in schema_data['properties']:
        type_dist = schema_data['properties']['type_distribution']
        if 'expected_ratio' in type_dist:
            expected_ratio = type_dist['expected_ratio']
        else:
            # Default to equal distribution if not specified
            types = list(type_dist.get('enum', ['sudoku', 'pathfinding']))
            expected_ratio = {t: 1.0/len(types) for t in types}
    else:
        # Default assumption: equal distribution
        types = distribution_data.get('type_distribution', {}).keys()
        if types:
            expected_ratio = {t: 1.0/len(types) for t in types}
        else:
            expected_ratio = {'sudoku': 0.5, 'pathfinding': 0.5}
    
    # Validate type distribution
    type_distribution = distribution_data.get('type_distribution', {})
    total_count = sum(type_distribution.values())
    
    if total_count == 0:
        print("ERROR: No puzzles found in distribution report")
        validation_result = {
            'is_valid': False,
            'power_estimate': 0.0,
            'notes': ['No puzzles found in distribution report'],
            'chi_square': None,
            'sample_size': 0
        }
    else:
        # Calculate chi-square statistic
        chi_square = calculate_chi_square(type_distribution, expected_ratio, total_count)
        
        # Degrees of freedom = number of categories - 1
        degrees_of_freedom = len(type_distribution) - 1
        
        # Calculate power estimate
        power_estimate = calculate_power_estimate(chi_square, degrees_of_freedom)
        
        # Validate complexity scaling
        complexity_valid, complexity_notes = validate_complexity_scaling(distribution_data)
        
        # Compile notes
        notes = [f"Chi-square statistic: {chi_square:.4f}"]
        notes.append(f"Expected ratio: {expected_ratio}")
        notes.append(f"Observed distribution: {type_distribution}")
        notes.extend(complexity_notes)
        
        # Determine overall validity
        is_valid = complexity_valid and (chi_square < 7.815)  # Critical value for df=2, alpha=0.05
        
        validation_result = {
            'is_valid': is_valid,
            'power_estimate': round(power_estimate, 4),
            'notes': notes,
            'chi_square': round(chi_square, 4),
            'sample_size': total_count,
            'type_distribution': type_distribution,
            'complexity_valid': complexity_valid
        }
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Write validation result
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(validation_result, f, indent=2)
    
    print(f"Validation complete. Results written to {output_path}")
    print(f"Is valid: {validation_result['is_valid']}")
    print(f"Power estimate: {validation_result['power_estimate']}")
    
    # Return exit code based on validity
    sys.exit(0 if validation_result['is_valid'] else 1)


if __name__ == "__main__":
    main()