"""Generate a data scarcity report if the cleaned dataset contains fewer than 30 samples.

This script reads the processed dataset and the split configuration generated by
`code/02_preprocess.py`. If the number of samples is less than 30, it writes a
markdown report to `docs/data_scarcity_report.md` describing the sample size,
the fallback LOOCV strategy, and the limitation on statistical power.

If the dataset contains 30 or more samples, the script performs a no‑op (the
report file is removed if it exists) to keep the repository clean.
"""

import json
import pandas as pd
from pathlib import Path
from llmxive_toolkit import paths, get_logger

# Local imports (project API)
from config import load_config, get_path
from exceptions import DataInsufficientError

log = get_logger(__name__)


def _load_cleaned_dataset() -> pd.DataFrame:
    """Load `data/processed/dataset_cleaned.csv`."""
    config = load_config()
    dataset_path = get_path(config, "processed", "dataset_cleaned.csv")
    if not dataset_path.exists():
        raise DataInsufficientError(
            f"Cleaned dataset not found at {dataset_path}. Run 02_preprocess.py first."
        )
    try:
        df = pd.read_csv(dataset_path)
        log.info(f"Loaded cleaned dataset with {len(df)} rows from {dataset_path}")
        return df
    except Exception as e:
        raise DataInsufficientError(f"Failed to read cleaned dataset: {e}")


def _load_split_config() -> dict:
    """Load `data/processed/split_config.json`."""
    config = load_config()
    split_path = get_path(config, "processed", "split_config.json")
    if not split_path.exists():
        raise DataInsufficientError(
            f"Split config not found at {split_path}. Run 02_preprocess.py first."
        )
    try:
        with open(split_path, "r") as f:
            split_cfg = json.load(f)
        log.info(f"Loaded split config: {split_cfg}")
        return split_cfg
    except Exception as e:
        raise DataInsufficientError(f"Failed to read split config: {e}")


def _write_report(sample_count: int, strategy: str) -> None:
    """Write the markdown report to `docs/data_scarcity_report.md`."""
    report_path = paths.docs("data_scarcity_report.md")
    report_path.parent.mkdir(parents=True, exist_ok=True)

    content = f"""# Data Scarcity Report

The preprocessing step resulted in **N = {sample_count}** samples, which is fewer than the recommended minimum of 30 samples for reliable statistical analysis.

**Split strategy:** {strategy} was used as a fallback.

**Implications:** With such a small dataset, statistical power is limited. Results should be interpreted with caution, and conclusions about model performance may be unreliable.
"""
    report_path.write_text(content, encoding="utf-8")
    log.info(f"Data scarcity report written to {report_path}")


def _remove_report_if_exists() -> None:
    """Remove the report file if it exists (used when N >= 30)."""
    report_path = paths.docs("data_scarcity_report.md")
    if report_path.exists():
        report_path.unlink()
        log.info(f"Removed existing data scarcity report at {report_path}")


def main() -> None:
    """Entry point for the data scarcity reporting task (T028)."""
    try:
        df = _load_cleaned_dataset()
        split_cfg = _load_split_config()

        n_samples = len(df)
        strategy = split_cfg.get("strategy", "unknown")

        if n_samples < 30:
            log.warning(
                f"Sample size {n_samples} < 30 – generating data scarcity report."
            )
            _write_report(sample_count=n_samples, strategy=strategy)
        else:
            log.info(
                f"Sample size {n_samples} >= 30 – no data scarcity report needed."
            )
            _remove_report_if_exists()
    except DataInsufficientError as e:
        log.error(f"Data insufficient for reporting: {e}")
        raise
    except Exception as e:
        log.exception(f"Unexpected error in data scarcity reporting: {e}")
        raise


if __name__ == "__main__":
    main()