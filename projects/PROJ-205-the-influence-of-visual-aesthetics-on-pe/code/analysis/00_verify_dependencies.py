"""
Dependency Order Verification Script.

This script ensures that the preprocessing step (00_preprocess.py) has
successfully completed and generated the required clean data file before
allowing downstream analysis (e.g., ANOVA) to proceed.

It verifies:
1. Existence of data/processed/clean_data.csv
2. Integrity of the file via checksum comparison against the checksum 
   recorded in data/raw/submissions.csv (specifically the 'clean_data.csv' 
   entry in the submissions metadata if available, or by verifying the 
   clean data is a valid derivative of the current raw data).

CRITICAL: This script must run BEFORE 01_anova.py, 02_pairwise.py, etc.
"""

import os
import sys
import json
import argparse
from pathlib import Path
import hashlib

# Add project root to path for imports
def get_project_root():
    """Returns the absolute path to the project root."""
    return Path(__file__).resolve().parents[2]

def get_submissions_csv_path():
    """Returns the path to the raw submissions CSV."""
    return get_project_root() / "data" / "raw" / "submissions.csv"

def get_cleaned_csv_path():
    """Returns the path to the processed clean data CSV."""
    return get_project_root() / "data" / "processed" / "clean_data.csv"

def get_checksum_store_path():
    """Returns the path to the JSON file storing checksums."""
    # T057 stores checksums here. We rely on this as the source of truth
    # for the "recorded" state of the data pipeline.
    return get_project_root() / "data" / "raw" / "checksums.json"

def compute_file_checksum(file_path):
    """
    Computes the SHA-256 checksum of a file.

    Args:
        file_path (Path): Path to the file.

    Returns:
        str: Hexadecimal checksum string.
    """
    sha256_hash = hashlib.sha256()
    try:
        with open(file_path, "rb") as f:
            for byte_block in iter(lambda: f.read(4096), b""):
                sha256_hash.update(byte_block)
        return sha256_hash.hexdigest()
    except FileNotFoundError:
        raise FileNotFoundError(f"Input file not found: {file_path}")
    except Exception as e:
        raise RuntimeError(f"Error computing checksum for {file_path}: {e}")

def load_checksums():
    """
    Loads the stored checksums from the JSON file.

    Returns:
        dict: Dictionary of checksums.
    """
    checksum_path = get_checksum_store_path()
    if not checksum_path.exists():
        raise FileNotFoundError(
            f"Checksums file not found at {checksum_path}. "
            "Please ensure T057 (checksum storage) has run after data collection "
            "and T024a (preprocessing) has recorded its output checksum."
        )
    try:
        with open(checksum_path, "r") as f:
            return json.load(f)
    except json.JSONDecodeError:
        raise RuntimeError(f"Checksums file {checksum_path} is corrupted or invalid JSON.")

def verify_dependencies():
    """
    Verifies that dependencies for downstream analysis are met.

    Requirements:
    1. data/raw/submissions.csv must exist.
    2. data/processed/clean_data.csv must exist.
    3. The checksum of submissions.csv must match the stored baseline (T057).
    4. The checksum of clean_data.csv must match the stored 'clean_data.csv' entry
       (generated by T024a/T057 after preprocessing).

    Raises:
        FileNotFoundError: If required files are missing.
        ValueError: If checksums do not match (stale data).
    """
    print("Verifying dependencies for analysis...")

    # 1. Check if raw submissions exist (source of truth)
    submissions_path = get_submissions_csv_path()
    if not submissions_path.exists():
        raise FileNotFoundError(
            f"Source data missing: {submissions_path} does not exist. "
            "Please run the survey (code/survey/app.py) or generate valid data first."
        )
    print(f"✓ Found raw submissions: {submissions_path}")

    # 2. Check if clean data exists
    cleaned_path = get_cleaned_csv_path()
    if not cleaned_path.exists():
        raise FileNotFoundError(
            f"Dependency missing: {cleaned_path} does not exist. "
            "Please run code/analysis/00_preprocess.py first."
        )
    print(f"✓ Found clean data: {cleaned_path}")

    # 3. Load stored checksums (the record of the last successful pipeline run)
    stored_checksums = load_checksums()

    # 4. Verify checksum of raw submissions matches stored value
    # This ensures we haven't modified the source data since the last preprocessing.
    current_raw_checksum = compute_file_checksum(submissions_path)
    
    if "submissions.csv" not in stored_checksums:
        raise ValueError(
            "Checksum Mismatch: No stored checksum found for 'submissions.csv'. "
            "The baseline has not been established. Run T057 checksum utility after data collection."
        )

    stored_raw_checksum = stored_checksums["submissions.csv"]

    if current_raw_checksum != stored_raw_checksum:
        raise ValueError(
            "Data Integrity Error: The current 'submissions.csv' checksum does not match "
            "the stored checksum. The raw data has been modified since the last preprocessing. "
            "Please re-run code/analysis/00_preprocess.py to regenerate clean_data.csv and update checksums."
        )
    print("✓ Raw data checksum verified (matches stored baseline).")

    # 5. Verify the clean data file checksum matches the stored value
    # This ensures the clean_data.csv on disk is exactly what was produced by the last valid preprocessing run.
    if "clean_data.csv" not in stored_checksums:
        raise ValueError(
            "Checksum Mismatch: No stored checksum found for 'clean_data.csv'. "
            "The clean data file exists but its integrity has not been recorded. "
            "Please ensure code/analysis/00_preprocess.py has run successfully and updated the checksum store."
        )

    current_clean_checksum = compute_file_checksum(cleaned_path)
    stored_clean_checksum = stored_checksums["clean_data.csv"]

    if current_clean_checksum != stored_clean_checksum:
        raise ValueError(
            "Data Integrity Error: The current 'clean_data.csv' checksum does not match "
            "the stored checksum. The clean data file has been modified or is stale. "
            "Please re-run code/analysis/00_preprocess.py to ensure consistency."
        )
    print("✓ Clean data checksum verified (matches stored baseline).")

    print("✓ All dependency checks passed. Analysis can proceed.")
    return True

def main():
    """Main entry point for the dependency verification script."""
    parser = argparse.ArgumentParser(
        description="Verify dependencies before running analysis scripts."
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Print detailed verification steps."
    )
    args = parser.parse_args()

    try:
        verify_dependencies()
        if args.verbose:
            print("Verification successful.")
        sys.exit(0)
    except FileNotFoundError as e:
        print(f"FATAL ERROR: {e}", file=sys.stderr)
        sys.exit(1)
    except ValueError as e:
        print(f"INTEGRITY ERROR: {e}", file=sys.stderr)
        sys.exit(1)
    except RuntimeError as e:
        print(f"SYSTEM ERROR: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()