"""
Duplicate detection and audit script.

This script scans the raw submissions for duplicate IP addresses
and generates an audit report.

It relies on real data generated by the survey (code/survey/app.py)
or the authorized mock data generator (code/utils/generate_mock_data.py).
It does NOT generate synthetic data itself.
"""
import os
import sys
import csv
import argparse
from pathlib import Path
from datetime import datetime

def get_project_root():
    """Get the project root directory."""
    return Path(__file__).parent.parent.parent

def get_submissions_csv_path():
    """Get the path to the raw submissions CSV."""
    return get_project_root() / 'data' / 'raw' / 'submissions.csv'

def get_duplicate_audit_path():
    """Get the path to the duplicate audit CSV."""
    return get_project_root() / 'data' / 'raw' / 'duplicate_audit.csv'

def load_submissions_data():
    """Load raw survey data from CSV."""
    csv_path = get_submissions_csv_path()
    if not csv_path.exists():
        raise FileNotFoundError(
            f"Raw data not found: {csv_path}. "
            "Please run the survey or generate mock data first using "
            "`python code/utils/generate_mock_data.py`."
        )
    
    with open(csv_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        data = list(reader)
    return data

def detect_duplicates(data):
    """
    Detect duplicate entries based on hashed_ip.
    
    Returns a list of rows flagged as duplicates and a summary.
    """
    if not data:
        return [], {}

    ip_counts = {}
    for row in data:
        ip = row.get('hashed_ip', '')
        if ip:
            ip_counts[ip] = ip_counts.get(ip, 0) + 1
    
    duplicate_ips = {ip: count for ip, count in ip_counts.items() if count > 1}
    
    flagged_rows = []
    for row in data:
        ip = row.get('hashed_ip', '')
        if ip in duplicate_ips:
            row_copy = row.copy()
            row_copy['duplicate_flag'] = 'True'
            row_copy['duplicate_count'] = str(duplicate_ips[ip])
        else:
            row_copy = row.copy()
            row_copy['duplicate_flag'] = 'False'
            row_copy['duplicate_count'] = '1'
        flagged_rows.append(row_copy)
    
    return flagged_rows, duplicate_ips

def write_audit_log(flagged_rows, duplicate_ips):
    """Write the duplicate audit report."""
    output_path = get_duplicate_audit_path()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    if not flagged_rows:
        # Handle empty data case
        fieldnames = ['participant_id', 'stimulus_id', 'credibility', 'professionalism', 
                      'timestamp', 'hashed_ip', 'age', 'education', 'duplicate_flag', 
                      'duplicate_count']
        with open(output_path, 'w', newline='', encoding='utf-8') as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
    else:
        fieldnames = list(flagged_rows[0].keys())
        with open(output_path, 'w', newline='', encoding='utf-8') as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(flagged_rows)
    
    # Also write a summary JSON
    summary = {
        'generated_at': datetime.now().isoformat(),
        'total_rows': len(flagged_rows),
        'duplicate_ips_found': len(duplicate_ips),
        'duplicate_ip_details': {ip: count for ip, count in duplicate_ips.items()}
    }
    
    summary_path = output_path.with_suffix('.json')
    with open(summary_path, 'w', encoding='utf-8') as f:
        import json
        json.dump(summary, f, indent=2)

def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(description="Audit submissions for duplicate IPs.")
    parser.add_argument('--input', type=str, help='Path to input CSV (overrides default)')
    parser.add_argument('--output', type=str, help='Path to output audit CSV (overrides default)')
    args = parser.parse_args()

    if args.input:
        # If input is provided, we temporarily override the path logic
        # but for this task we stick to the standard paths defined above
        # unless explicitly needed for testing.
        pass

    print("Loading submissions data...")
    try:
        data = load_submissions_data()
        print(f"Loaded {len(data)} rows.")
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        return 1
    
    if not data:
        print("Warning: No data found in submissions CSV.")
        print("Writing empty audit log...")
        write_audit_log([], {})
        return 0

    print("Detecting duplicates...")
    flagged_rows, duplicate_ips = detect_duplicates(data)
    print(f"Found {len(duplicate_ips)} duplicate IPs.")
    
    print("Writing audit log...")
    write_audit_log(flagged_rows, duplicate_ips)
    
    print(f"Audit saved to: {get_duplicate_audit_path()}")
    
    return 0

if __name__ == "__main__":
    sys.exit(main())