"""
Task T033: Calculate Coefficient of Variation (CV) of credible upper limits.

This module calculates the coefficient of variation (CV) of the 95th percentile
credible upper limits for the Yukawa coupling parameter (alpha) across all
robustness iterations (leave-one-out or bootstrap).

CV = (standard deviation / mean) * 100

If CV > 15%, a warning is logged and the result is flagged, but no error is raised.
"""
import os
import sys
import json
import logging
import numpy as np
from pathlib import Path
from typing import Dict, Any, List, Optional

# Add project root to path if running as script
if __name__ == "__main__":
    project_root = Path(__file__).resolve().parent.parent.parent
    if str(project_root) not in sys.path:
        sys.path.insert(0, str(project_root))

from config import get_logger, setup_logging
from data.state_manager import read_state

# Configure logging
logger = get_logger(__name__)

def load_cv_results() -> List[float]:
    """
    Load the credible upper limits (95th percentile) from robustness iterations.
    
    Returns:
        List of upper limit values from each iteration.
    
    Raises:
        FileNotFoundError: If the results file does not exist.
        ValueError: If the file is empty or contains no valid data.
    """
    # Look for the cross-validation results file
    # This is typically generated by T030 (cross_val.py) or T032 (parallel_runner.py)
    results_path = Path("data/results/cross_val_results.json")
    
    if not results_path.exists():
        # Try alternative path
        results_path = Path("data/results/robustness_iterations.json")
        if not results_path.exists():
            raise FileNotFoundError(
                f"Cannot find cross-validation results file at {results_path}. "
                "Ensure T030 (cross_val.py) has been executed successfully."
            )
    
    with open(results_path, 'r') as f:
        data = json.load(f)
    
    # Extract upper limits (95th percentile of alpha posterior)
    upper_limits = []
    
    if isinstance(data, dict):
        # Check if it's a structured result with 'iterations' key
        if 'iterations' in data:
            for iter_data in data['iterations']:
                if 'alpha_upper_95' in iter_data:
                    upper_limits.append(iter_data['alpha_upper_95'])
                elif 'alpha_95_upper' in iter_data:
                    upper_limits.append(iter_data['alpha_95_upper'])
                elif 'upper_limit' in iter_data:
                    upper_limits.append(iter_data['upper_limit'])
        # Check if it's a list of iterations
        elif isinstance(data, list):
            for iter_data in data:
                if 'alpha_upper_95' in iter_data:
                    upper_limits.append(iter_data['alpha_upper_95'])
                elif 'alpha_95_upper' in iter_data:
                    upper_limits.append(iter_data['alpha_95_upper'])
                elif 'upper_limit' in iter_data:
                    upper_limits.append(iter_data['upper_limit'])
    elif isinstance(data, list):
        for iter_data in data:
            if 'alpha_upper_95' in iter_data:
                upper_limits.append(iter_data['alpha_upper_95'])
            elif 'alpha_95_upper' in iter_data:
                upper_limits.append(iter_data['alpha_95_upper'])
            elif 'upper_limit' in iter_data:
                upper_limits.append(iter_data['upper_limit'])
    
    if not upper_limits:
        raise ValueError(
            "No credible upper limits found in the results file. "
            "Ensure the file contains 'alpha_upper_95', 'alpha_95_upper', or 'upper_limit' fields."
        )
    
    return upper_limits

def calculate_cv(upper_limits: List[float]) -> Dict[str, Any]:
    """
    Calculate the coefficient of variation (CV) of the upper limits.
    
    CV = (standard deviation / mean) * 100
    
    Args:
        upper_limits: List of 95th percentile credible upper limits from each iteration.
    
    Returns:
        Dictionary containing:
            - mean: Mean of upper limits
            - std: Standard deviation of upper limits
            - cv: Coefficient of variation (percentage)
            - is_stable: Boolean indicating if CV <= 15%
            - warning: Warning message if CV > 15%, else None
    """
    if len(upper_limits) < 2:
        logger.warning("Less than 2 iterations found. Cannot calculate meaningful CV.")
        return {
            'mean': upper_limits[0] if upper_limits else 0.0,
            'std': 0.0,
            'cv': 0.0,
            'is_stable': True,
            'warning': None,
            'count': len(upper_limits)
        }
    
    upper_limits_array = np.array(upper_limits)
    mean_val = np.mean(upper_limits_array)
    std_val = np.std(upper_limits_array)
    
    # Avoid division by zero
    if mean_val == 0:
        cv = 0.0 if std_val == 0 else float('inf')
    else:
        cv = (std_val / mean_val) * 100
    
    # Check stability threshold (15%)
    is_stable = cv <= 15.0
    
    warning = None
    if not is_stable:
        warning = (
            f"Stability warning: CV = {cv:.2f}% exceeds threshold of 15%. "
            f"Results may be unstable across robustness iterations."
        )
        logger.warning(warning)
    else:
        logger.info(f"Stability check passed: CV = {cv:.2f}% (threshold: 15%)")
    
    return {
        'mean': float(mean_val),
        'std': float(std_val),
        'cv': float(cv),
        'is_stable': is_stable,
        'warning': warning,
        'count': len(upper_limits),
        'upper_limits': [float(x) for x in upper_limits]
    }

def save_cv_report(cv_results: Dict[str, Any], output_path: Optional[Path] = None) -> Path:
    """
    Save the CV calculation results to a JSON file.
    
    Args:
        cv_results: Dictionary containing CV calculation results.
        output_path: Optional path for the output file. Defaults to data/results/cv_analysis.json.
    
    Returns:
        Path to the saved file.
    """
    if output_path is None:
        output_path = Path("data/results/cv_analysis.json")
    
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Add timestamp and metadata
    final_report = {
        'task_id': 'T033',
        'description': 'Coefficient of Variation analysis of credible upper limits',
        'threshold_percent': 15.0,
        'results': cv_results,
        'status': 'STABLE' if cv_results['is_stable'] else 'UNSTABLE'
    }
    
    with open(output_path, 'w') as f:
        json.dump(final_report, f, indent=2)
    
    logger.info(f"CV analysis report saved to {output_path}")
    return output_path

def main():
    """
    Main entry point for T033: Calculate CV of credible upper limits.
    
    This function:
    1. Loads the upper limits from robustness iterations (T030/T032 output)
    2. Calculates the coefficient of variation (CV)
    3. Logs the result and flags if CV > 15%
    4. Saves the analysis report to data/results/cv_analysis.json
    """
    logger.info("Starting T033: Coefficient of Variation calculation")
    
    try:
        # Load upper limits from robustness iterations
        upper_limits = load_cv_results()
        logger.info(f"Loaded {len(upper_limits)} upper limit values from robustness iterations")
        
        # Calculate CV
        cv_results = calculate_cv(upper_limits)
        
        # Log the results
        logger.info(f"CV Analysis Results:")
        logger.info(f"  - Mean upper limit: {cv_results['mean']:.6e}")
        logger.info(f"  - Std deviation: {cv_results['std']:.6e}")
        logger.info(f"  - CV: {cv_results['cv']:.2f}%")
        logger.info(f"  - Stability: {'PASS' if cv_results['is_stable'] else 'WARNING'}")
        
        if cv_results['warning']:
            logger.warning(cv_results['warning'])
        
        # Save the report
        report_path = save_cv_report(cv_results)
        
        # Update state if needed (flag the result)
        if not cv_results['is_stable']:
            logger.warning("Result flagged: CV exceeds 15% threshold. Review robustness iterations.")
            # Note: We do NOT raise an error, just log the warning as per spec
        
        logger.info("T033 completed successfully")
        return cv_results
        
    except FileNotFoundError as e:
        logger.error(f"Data file not found: {e}")
        logger.error("Ensure T030 (cross_val.py) has been executed and produced results.")
        raise
    except ValueError as e:
        logger.error(f"Invalid data format: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during CV calculation: {e}", exc_info=True)
        raise

if __name__ == "__main__":
    setup_logging()
    main()
