def load_prompts(csv_path: str) -> list:
    """Load prompts from the diverse prompts CSV generated by T006d."""
    path = Path(csv_path)
    if not path.exists():
        raise FileNotFoundError(f"Required prompts file not found: {path}. "
                                "Run T006d (download_diverse_prompts.py) first.")
    prompts = []
    with open(path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Expect 'prompt' or 'caption' column; adapt based on T006d output
            text = row.get('prompt') or row.get('caption') or row.get('text')
            if text and isinstance(text, str) and text.strip():
                prompts.append(text.strip())
    if not prompts:
        raise ValueError("No valid prompts found in the CSV file.")
    logger.info(f"Loaded {len(prompts)} prompts from {csv_path}")
    return prompts

def compute_entropy_scores(prompts: list, proxy: EntropyProxy) -> dict:
    """Compute semantic entropy for each prompt using the EntropyProxy."""
    logger.info("Computing semantic entropy scores...")
    scores = {}
    for i, prompt in enumerate(prompts):
        try:
            entropy = proxy.compute_entropy(prompt)
            scores[prompt] = float(entropy)
            if (i + 1) % 10 == 0:
                logger.info(f"Entropy computed for {i+1}/{len(prompts)} prompts")
        except Exception as e:
            logger.error(f"Entropy computation failed for prompt '{prompt[:50]}...': {e}")
            raise
    logger.info(f"Computed entropy for {len(scores)} prompts")
    return scores

