def aggregate_variances(variance_results: dict) -> list:
    """
    Aggregate variance results per prompt.
    Returns a list of (prompt, avg_variance) tuples.
    """
    logger.info("Aggregating variance results...")
    aggregated = []
    for prompt, layers in variance_results.items():
        if "error" in layers:
            logger.warning(f"Skipping prompt with generation error: {prompt[:40]}...")
            continue
        if not layers:
            logger.warning(f"No variance data for prompt: {prompt[:40]}...")
            continue
        
        # Compute mean variance across layers for this prompt
        var_values = list(layers.values())
        avg_var = float(np.mean(var_values))
        aggregated.append((prompt, avg_var))
    
    logger.info(f"Aggregated variances for {len(aggregated)} prompts")
    return aggregated

def compute_correlation(entropy_scores: dict, aggregated_variances: list) -> dict:
    """Compute Pearson correlation between entropy and activation variance."""
    logger.info("Computing correlation...")
    
    # Align data
    prompts_with_entropy = set(entropy_scores.keys())
    prompts_with_var = set(v[0] for v in aggregated_variances)
    common_prompts = prompts_with_entropy & prompts_with_var
    
    if len(common_prompts) < 3:
        raise ValueError(f"Not enough common prompts for correlation (found {len(common_prompts)}). "
                         "Need at least 3.")
    
    entropy_vals = [entropy_scores[p] for p in common_prompts]
    variance_vals = [v[1] for v in aggregated_variances if v[0] in common_prompts]
    
    # Compute Pearson correlation
    corr_coef, p_value = stats.pearsonr(entropy_vals, variance_vals)
    
    logger.info(f"Pearson correlation: {corr_coef:.4f}, p-value: {p_value:.4e}")
    
    return {
        "correlation_coefficient": float(corr_coef),
        "p_value": float(p_value),
        "n_samples": len(common_prompts),
        "method": "pearson"
    }

def save_results(correlation_data: dict, entropy_scores: dict, variance_results: dict, output_path: str):
    """Save all results to the output JSON file."""
    output = {
        "metadata": {
            "task_id": "T017",
            "description": "Correlation between Prompt Entropy and Activation Variance",
            "input_prompts": "data/processed/diverse_prompts.csv",
            "output_file": output_path
        },
        "correlation": correlation_data,
        "entropy_scores": entropy_scores,
        "variance_results": variance_results
    }
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(output, f, indent=2, default=str)
    
    logger.info(f"Results saved to {output_path}")

def main():
    """Main orchestration function."""
    logger.info("Starting T017: Correlation Analysis Pipeline")
    
    # 1. Load Prompts
    prompts_path = str(Path(config.data_dir) / 'processed' / 'diverse_prompts.csv')
    prompts = load_prompts(prompts_path)
    
    # 2. Compute Entropy
    proxy = EntropyProxy(config)
    entropy_scores = compute_entropy_scores(prompts, proxy)
    
    # 3. Setup Model and Hooks
    model_loader = ModelLoader(config)
    dit_wrapper = create_dit_wrapper(config)
    activation_capture = ActivationCapture()
    
    # 4. Run Generation and Capture Variances
    variance_results = run_dit_generation_and_capture_variance(
        prompts, entropy_scores, model_loader, dit_wrapper, activation_capture
    )
    
    # 5. Aggregate Variances
    aggregated = aggregate_variances(variance_results)
    
    # 6. Compute Correlation
    correlation_data = compute_correlation(entropy_scores, aggregated)
    
    # 7. Save Results
    output_path = str(Path(config.data_dir) / 'processed' / 'correlation_results.json')
    save_results(correlation_data, entropy_scores, variance_results, output_path)
    
    logger.info("T017 completed successfully")
    return correlation_data

if __name__ == "__main__":
    main()