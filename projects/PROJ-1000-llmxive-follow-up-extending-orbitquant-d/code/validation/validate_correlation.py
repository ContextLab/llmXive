"""
Validation script for Task T023b: Verify correlation results and p-value < 0.05.

This script validates the existence and content of `data/processed/correlation_results.json`.
It checks that the file exists, is valid JSON, contains the required 'p_value' key,
and verifies that the p-value is strictly less than 0.05 (statistically significant).

Exit codes:
  0: Validation passed (p-value < 0.05)
  1: Validation failed (file missing, invalid JSON, missing key, or p-value >= 0.05)
"""

import os
import sys
import json
import logging
from pathlib import Path

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Constants
CORRELATION_RESULTS_PATH = Path("data/processed/correlation_results.json")
SIGNIFICANCE_THRESHOLD = 0.05

def validate_correlation_results(file_path: Path) -> bool:
    """
    Validates the correlation results file.

    Args:
        file_path: Path to the correlation_results.json file.

    Returns:
        bool: True if validation passes, False otherwise.
    """
    # 1. Check file existence
    if not file_path.exists():
        logger.error(f"File not found: {file_path}")
        logger.error("CRITICAL: correlation_results.json must be generated by T017 before running this validation.")
        return False

    # 2. Load and parse JSON
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON format in {file_path}: {e}")
        return False
    except Exception as e:
        logger.error(f"Error reading file {file_path}: {e}")
        return False

    # 3. Check for required keys
    required_keys = ['p_value', 'correlation_coefficient', 'num_samples']
    missing_keys = [key for key in required_keys if key not in data]
    if missing_keys:
        logger.error(f"Missing required keys in correlation results: {missing_keys}")
        logger.error(f"Found keys: {list(data.keys())}")
        return False

    p_value = data['p_value']
    correlation_coefficient = data['correlation_coefficient']

    # 4. Validate p-value type and range
    if not isinstance(p_value, (int, float)):
        logger.error(f"p-value must be a number, got {type(p_value)}")
        return False

    if not (0.0 <= p_value <= 1.0):
        logger.error(f"p-value must be between 0.0 and 1.0, got {p_value}")
        return False

    # 5. Validate statistical significance
    logger.info(f"Loaded results: p-value={p_value:.6f}, r={correlation_coefficient:.6f}, n={data['num_samples']}")

    if p_value < SIGNIFICANCE_THRESHOLD:
        logger.info(f"SUCCESS: p-value ({p_value:.6f}) is less than threshold ({SIGNIFICANCE_THRESHOLD}).")
        logger.info("Correlation is statistically significant. Proceeding to Phase 4 (US2).")
        return True
    else:
        logger.error(f"FAILURE: p-value ({p_value:.6f}) is NOT less than threshold ({SIGNIFICANCE_THRESHOLD}).")
        logger.error("Correlation is NOT statistically significant. The hypothesis is not supported.")
        logger.error("Execution halted. Do not proceed to User Story 2 (Dynamic Router).")
        return False

def main():
    """Main entry point for validation."""
    logger.info("Starting correlation validation (Task T023b)...")

    success = validate_correlation_results(CORRELATION_RESULTS_PATH)

    if success:
        logger.info("Validation completed successfully.")
        sys.exit(0)
    else:
        logger.error("Validation failed. Halting pipeline.")
        sys.exit(1)

if __name__ == "__main__":
    main()
