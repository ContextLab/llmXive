import os
import sys
import json
import logging
import csv
from pathlib import Path
from typing import List, Dict, Any, Tuple

# Add project root to path for imports if running as script
project_root = Path(__file__).parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from config import Config
from analysis.correlation import compute_pearson_correlation

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def load_raw_data_points(config: Config) -> List[Dict[str, Any]]:
    """
    Loads the raw data points from the intermediate files generated by run_correlation.py.
    Expects:
      - data/processed/entropy_scores.csv (columns: prompt_id, entropy_score)
      - data/processed/activation_variances.csv (columns: prompt_id, variance_value)
    
    Returns a list of dicts: [{'prompt_id': ..., 'entropy': ..., 'variance': ...}, ...]
    """
    entropy_path = config.data_dir / "processed" / "entropy_scores.csv"
    variance_path = config.data_dir / "processed" / "activation_variances.csv"

    if not entropy_path.exists():
        raise FileNotFoundError(f"Entropy scores file not found at {entropy_path}. "
                                "Ensure T017 (run_correlation.py) has completed successfully.")
    if not variance_path.exists():
        raise FileNotFoundError(f"Activation variances file not found at {variance_path}. "
                                "Ensure T017 (run_correlation.py) has completed successfully.")

    entropies = {}
    with open(entropy_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            prompt_id = row['prompt_id']
            try:
                entropies[prompt_id] = float(row['entropy_score'])
            except (ValueError, KeyError) as e:
                logger.warning(f"Skipping invalid entropy row for {prompt_id}: {e}")

    variances = {}
    with open(variance_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            prompt_id = row['prompt_id']
            try:
                variances[prompt_id] = float(row['variance_value'])
            except (ValueError, KeyError) as e:
                logger.warning(f"Skipping invalid variance row for {prompt_id}: {e}")

    # Merge on prompt_id
    data_points = []
    common_ids = set(entropies.keys()) & set(variances.keys())
    
    if not common_ids:
        raise ValueError("No common prompt IDs found between entropy and variance files. "
                         "Check T017 output integrity.")

    logger.info(f"Merged {len(common_ids)} data points from entropy and variance files.")

    for pid in common_ids:
        data_points.append({
            "prompt_id": pid,
            "entropy": entropies[pid],
            "variance": variances[pid]
        })

    return data_points

def main():
    """
    Orchestrates the generation of correlation_results.json.
    1. Loads raw data points.
    2. Computes Pearson correlation coefficient and p-value.
    3. Saves the full results dictionary to data/processed/correlation_results.json.
    """
    config = Config()
    output_path = config.data_dir / "processed" / "correlation_results.json"
    
    logger.info(f"Starting correlation results generation. Output: {output_path}")

    try:
        data_points = load_raw_data_points(config)
    except (FileNotFoundError, ValueError) as e:
        logger.error(f"Failed to load data: {e}")
        sys.exit(1)

    if len(data_points) < 2:
        logger.error("Insufficient data points (need >= 2) to compute correlation.")
        sys.exit(1)

    entropies = [dp["entropy"] for dp in data_points]
    variances = [dp["variance"] for dp in data_points]

    logger.info(f"Computing Pearson correlation on {len(entropies)} points.")
    
    try:
        r, p_value = compute_pearson_correlation(entropies, variances)
    except Exception as e:
        logger.error(f"Correlation computation failed: {e}")
        sys.exit(1)

    results = {
        "metadata": {
            "task_id": "T018",
            "description": "Correlation between prompt entropy and activation variance",
            "n_samples": len(data_points),
            "source_entropy_file": "data/processed/entropy_scores.csv",
            "source_variance_file": "data/processed/activation_variances.csv"
        },
        "statistics": {
            "pearson_r": float(r),
            "p_value": float(p_value),
            "significance_level": 0.05,
            "is_significant": p_value < 0.05
        },
        "raw_data_points": data_points
    }

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(results, f, indent=2)

    logger.info(f"Successfully wrote correlation results to {output_path}")
    logger.info(f"Result: r={r:.4f}, p={p_value:.4e}, significant={p_value < 0.05}")

if __name__ == "__main__":
    main()
