"""
Statistical testing module for User Story 3.

Performs paired t-tests on metric distributions (FID, CLIP, MSE) between
static baseline and dynamic router methods.

Conditionally applies Bonferroni correction if the number of comparisons
exceeds a defined threshold (default: >3), as configured in config.py.
"""
import os
import json
import logging
import numpy as np
from scipy import stats
from pathlib import Path
from typing import Dict, List, Tuple, Any, Optional
from config import Config

logger = logging.getLogger(__name__)


def load_metrics_from_json(filepath: Path) -> Dict[str, List[float]]:
    """
    Load metrics from a JSON file generated by evaluation/metrics.py.
    
    Args:
        filepath: Path to the JSON file containing metrics.
        
    Returns:
        Dictionary with metric names as keys and lists of values as values.
    """
    if not filepath.exists():
        raise FileNotFoundError(f"Metrics file not found: {filepath}")
    
    with open(filepath, 'r') as f:
        data = json.load(f)
    
    # Expected structure: { "metrics": { "fid": [...], "clip": [...], "mse": [...] } }
    # or flat: { "fid": [...], "clip": [...], "mse": [...] }
    if "metrics" in data:
        return data["metrics"]
    return data


def perform_paired_ttest(
    group_a: List[float], 
    group_b: List[float], 
    metric_name: str
) -> Dict[str, Any]:
    """
    Perform a paired t-test between two groups of metric values.
    
    Args:
        group_a: List of values from the static baseline method.
        group_b: List of values from the dynamic router method.
        metric_name: Name of the metric being tested (for logging).
        
    Returns:
        Dictionary containing t-statistic, p-value, and significance flag.
    """
    if len(group_a) != len(group_b):
        raise ValueError(
            f"Group sizes mismatch for {metric_name}: "
            f"len(A)={len(group_a)}, len(B)={len(group_b)}"
        )
    
    if len(group_a) < 2:
        raise ValueError(
            f"Insufficient data points for {metric_name}: "
            f"need at least 2, got {len(group_a)}"
        )
    
    # Convert to numpy arrays for scipy
    arr_a = np.array(group_a)
    arr_b = np.array(group_b)
    
    # Perform paired t-test
    t_stat, p_value = stats.ttest_rel(arr_a, arr_b)
    
    return {
        "metric": metric_name,
        "t_statistic": float(t_stat),
        "p_value": float(p_value),
        "n_samples": len(arr_a),
        "mean_diff": float(np.mean(arr_a - arr_b)),
        "mean_a": float(np.mean(arr_a)),
        "mean_b": float(np.mean(arr_b))
    }


def apply_bonferroni_correction(
    test_results: List[Dict[str, Any]], 
    threshold: int
) -> List[Dict[str, Any]]:
    """
    Apply Bonferroni correction to p-values if the number of comparisons
    exceeds the defined threshold.
    
    Args:
        test_results: List of test result dictionaries containing p-values.
        threshold: Maximum number of comparisons before correction is applied.
        
    Returns:
        Updated list of test results with corrected p-values and flags.
    """
    n_comparisons = len(test_results)
    correction_applied = n_comparisons > threshold
    
    logger.info(
        f"Bonferroni check: {n_comparisons} comparisons vs threshold {threshold}. "
        f"Correction {'APPLIED' if correction_applied else 'NOT APPLIED'}."
    )
    
    corrected_results = []
    for result in test_results:
        new_result = result.copy()
        new_result["bonferroni_applied"] = correction_applied
        new_result["n_comparisons"] = n_comparisons
        
        if correction_applied:
            # Bonferroni correction: p_corrected = p * n
            p_raw = result["p_value"]
            p_corrected = min(p_raw * n_comparisons, 1.0)
            new_result["p_value_corrected"] = p_corrected
            new_result["is_significant"] = p_corrected < 0.05
        else:
            new_result["p_value_corrected"] = result["p_value"]
            new_result["is_significant"] = result["p_value"] < 0.05
            
        corrected_results.append(new_result)
        
    return corrected_results


def run_statistical_tests(
    static_metrics_path: Path,
    dynamic_metrics_path: Path,
    metrics_of_interest: Optional[List[str]] = None,
    bonferroni_threshold: Optional[int] = None
) -> Dict[str, Any]:
    """
    Run paired t-tests on metric distributions from static and dynamic methods.
    
    Args:
        static_metrics_path: Path to JSON file with static baseline metrics.
        dynamic_metrics_path: Path to JSON file with dynamic router metrics.
        metrics_of_interest: List of metric names to test (default: all found).
        bonferroni_threshold: Threshold for Bonferroni correction (default from Config).
        
    Returns:
        Dictionary containing all test results and summary statistics.
    """
    config = Config()
    threshold = (
        bonferroni_threshold 
        if bonferroni_threshold is not None 
        else config.statistical_test_bonferroni_threshold
    )
    
    # Load metrics
    logger.info(f"Loading static metrics from: {static_metrics_path}")
    static_metrics = load_metrics_from_json(static_metrics_path)
    
    logger.info(f"Loading dynamic metrics from: {dynamic_metrics_path}")
    dynamic_metrics = load_metrics_from_json(dynamic_metrics_path)
    
    # Determine which metrics to test
    if metrics_of_interest is None:
        # Use intersection of keys from both files
        metrics_of_interest = list(
            set(static_metrics.keys()) & set(dynamic_metrics.keys())
        )
    
    if not metrics_of_interest:
        raise ValueError(
            "No common metrics found between static and dynamic result files."
        )
    
    logger.info(f"Testing metrics: {metrics_of_interest}")
    
    # Run tests
    test_results = []
    for metric in metrics_of_interest:
        if metric not in static_metrics or metric not in dynamic_metrics:
            logger.warning(f"Skipping {metric}: missing in one of the files.")
            continue
        
        try:
            result = perform_paired_ttest(
                static_metrics[metric],
                dynamic_metrics[metric],
                metric
            )
            test_results.append(result)
        except ValueError as e:
            logger.error(f"Test failed for {metric}: {e}")
            test_results.append({
                "metric": metric,
                "error": str(e)
            })
    
    # Apply Bonferroni correction if needed
    corrected_results = apply_bonferroni_correction(test_results, threshold)
    
    # Build summary
    significant_count = sum(
        1 for r in corrected_results 
        if r.get("is_significant", False)
    )
    
    summary = {
        "total_comparisons": len(corrected_results),
        "bonferroni_threshold": threshold,
        "bonferroni_applied": threshold < len(corrected_results),
        "significant_results": significant_count,
        "metrics_tested": metrics_of_interest
    }
    
    return {
        "summary": summary,
        "test_results": corrected_results
    }


def save_results(results: Dict[str, Any], output_path: Path) -> None:
    """
    Save statistical test results to a JSON file.
    
    Args:
        results: Dictionary containing test results and summary.
        output_path: Path to save the JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    logger.info(f"Results saved to: {output_path}")


def main() -> None:
    """
    Main entry point for running statistical tests on evaluation metrics.
    
    Loads metrics from data/processed/static_metrics.json and 
    data/processed/dynamic_metrics.json, performs paired t-tests,
    applies Bonferroni correction if necessary, and saves results
    to data/processed/statistical_test_results.json.
    """
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    config = Config()
    project_root = Path(config.project_root)
    
    # Define paths
    static_metrics_path = project_root / "data" / "processed" / "static_metrics.json"
    dynamic_metrics_path = project_root / "data" / "processed" / "dynamic_metrics.json"
    output_path = project_root / "data" / "processed" / "statistical_test_results.json"
    
    # Verify inputs exist
    if not static_metrics_path.exists():
        raise FileNotFoundError(
            f"Static metrics file not found: {static_metrics_path}. "
            "Run the evaluation pipeline first."
        )
    if not dynamic_metrics_path.exists():
        raise FileNotFoundError(
            f"Dynamic metrics file not found: {dynamic_metrics_path}. "
            "Run the evaluation pipeline first."
        )
    
    logger.info("Starting statistical test analysis...")
    
    try:
        results = run_statistical_tests(
            static_metrics_path=static_metrics_path,
            dynamic_metrics_path=dynamic_metrics_path
        )
        
        save_results(results, output_path)
        
        # Log summary
        summary = results["summary"]
        logger.info(f"Test completed. Significant results: {summary['significant_results']}/{summary['total_comparisons']}")
        
    except Exception as e:
        logger.error(f"Statistical test failed: {e}")
        raise


if __name__ == "__main__":
    main()