import os
import json
import logging
import numpy as np
from scipy import stats
from pathlib import Path
from typing import Dict, List, Tuple, Any, Optional
from config import Config

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

def load_metrics_from_json(file_path: str) -> Dict[str, List[float]]:
    """
    Load metrics from a JSON file generated by the evaluation pipeline.
    Expected structure:
    {
        "static": {"fid": [...], "clip": [...], "mse": [...]},
        "dynamic": {"fid": [...], "clip": [...], "mse": [...]}
    }
    """
    path = Path(file_path)
    if not path.exists():
        raise FileNotFoundError(f"Metrics file not found: {file_path}")
    
    with open(path, 'r') as f:
        data = json.load(f)
    
    if "static" not in data or "dynamic" not in data:
        raise ValueError("Metrics file must contain 'static' and 'dynamic' keys")
    
    metrics = {}
    for method in ["static", "dynamic"]:
        metrics[method] = {}
        for metric_name in ["fid", "clip", "mse"]:
            if metric_name in data[method]:
                metrics[method][metric_name] = data[method][metric_name]
            else:
                logger.warning(f"Metric {metric_name} not found in {method} results")
                metrics[method][metric_name] = []
    
    return metrics

def perform_paired_ttest(
    static_values: List[float], 
    dynamic_values: List[float], 
    metric_name: str
) -> Tuple[float, float]:
    """
    Perform a paired t-test between static and dynamic method results.
    Returns (t_statistic, p_value).
    """
    if len(static_values) == 0 or len(dynamic_values) == 0:
        logger.warning(f"Empty data for {metric_name}, skipping t-test")
        return 0.0, 1.0
    
    if len(static_values) != len(dynamic_values):
        raise ValueError(
            f"Length mismatch for {metric_name}: "
            f"static={len(static_values)}, dynamic={len(dynamic_values)}"
        )
    
    if len(static_values) < 2:
        logger.warning(f"Insufficient samples for {metric_name} (n < 2), skipping t-test")
        return 0.0, 1.0
    
    t_stat, p_val = stats.ttest_rel(static_values, dynamic_values)
    logger.info(f"{metric_name}: t={t_stat:.4f}, p={p_val:.6f}")
    return float(t_stat), float(p_val)

def apply_bonferroni_correction(p_values: List[float], threshold: float = 0.05) -> Dict[str, bool]:
    """
    Apply Bonferroni correction if the number of comparisons exceeds the threshold.
    Returns a dict mapping metric names to whether the result is significant after correction.
    
    Args:
        p_values: List of p-values from the t-tests.
        threshold: The threshold for the number of comparisons to trigger correction.
    """
    n_comparisons = len(p_values)
    corrected_results = {}
    
    if n_comparisons > threshold:
        logger.info(f"Applying Bonferroni correction for {n_comparisons} comparisons (threshold: {threshold})")
        adjusted_alpha = threshold / n_comparisons
        for i, p_val in enumerate(p_values):
          # The key is just a placeholder index since we don't have names here, 
          # but in the full context we map back.
          corrected_results[f"comparison_{i}"] = p_val < adjusted_alpha
    else:
        logger.info(f"No Bonferroni correction needed ({n_comparisons} <= {threshold})")
        for i, p_val in enumerate(p_values):
            corrected_results[f"comparison_{i}"] = p_val < threshold
    
    return corrected_results

def run_statistical_tests(
    metrics_data: Dict[str, Dict[str, List[float]]],
    bonferroni_threshold: int = 3
) -> Dict[str, Any]:
    """
    Run paired t-tests on all available metrics and apply Bonferroni correction if needed.
    
    Args:
        metrics_data: Dict with 'static' and 'dynamic' keys, each containing metric lists.
        bonferroni_threshold: Threshold for number of comparisons to trigger correction.
    
    Returns:
        Dictionary containing test results and significance flags.
    """
    results = {
        "tests": [],
        "summary": {},
        "bonferroni_applied": False
    }
    
    metric_names = ["fid", "clip", "mse"]
    p_values = []
    
    for metric in metric_names:
        if not metrics_data["static"].get(metric) or not metrics_data["dynamic"].get(metric):
            logger.warning(f"Skipping {metric} due to missing data")
            continue
        
        t_stat, p_val = perform_paired_ttest(
            metrics_data["static"][metric],
            metrics_data["dynamic"][metric],
            metric
        )
        
        results["tests"].append({
            "metric": metric,
            "t_statistic": t_stat,
            "p_value": p_val,
            "n_samples": len(metrics_data["static"][metric])
        })
        p_values.append(p_val)
    
    if len(p_values) > 0:
        corrected_significance = apply_bonferroni_correction(p_values, bonferroni_threshold)
        results["bonferroni_applied"] = (len(p_values) > bonferroni_threshold)
        
        # Map back significance to specific metrics
        for i, metric in enumerate(metric_names):
            if i < len(p_values) and f"comparison_{i}" in corrected_significance:
                results["summary"][metric] = {
                    "significant_before_correction": p_values[i] < 0.05,
                    "significant_after_correction": corrected_significance[f"comparison_{i}"],
                    "bonferroni_adjusted_alpha": 0.05 / len(p_values) if results["bonferroni_applied"] else 0.05
                }
    
    return results

def save_results(results: Dict[str, Any], output_path: str) -> None:
    """
    Save statistical test results to a JSON file.
    """
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(path, 'w') as f:
        json.dump(results, f, indent=2)
    
    logger.info(f"Results saved to {output_path}")

def main():
    """
    Main entry point for running statistical tests on evaluation metrics.
    Reads metrics from data/processed/final_evaluation_report.json (or similar)
    and outputs results to data/processed/statistical_test_results.json.
    """
    config = Config()
    
    # Default paths
    input_path = config.data_dir / "processed" / "final_evaluation_report.json"
    output_path = config.data_dir / "processed" / "statistical_test_results.json"
    
    # Allow override via environment or args if needed (simplified here)
    if not input_path.exists():
        # Fallback to common alternative if exact name differs
        alt_path = config.data_dir / "processed" / "evaluation_metrics.json"
        if alt_path.exists():
            input_path = alt_path
        else:
            raise FileNotFoundError(
                f"Could not find evaluation metrics file. "
                f"Searched: {input_path}, {alt_path}"
            )
    
    logger.info(f"Loading metrics from {input_path}")
    metrics_data = load_metrics_from_json(str(input_path))
    
    logger.info("Running statistical tests...")
    results = run_statistical_tests(metrics_data, bonferroni_threshold=3)
    
    logger.info(f"Saving results to {output_path}")
    save_results(results, str(output_path))
    
    # Print summary
    print("\n--- Statistical Test Summary ---")
    for metric, summary in results.get("summary", {}).items():
        sig_status = "Significant" if summary["significant_after_correction"] else "Not Significant"
        print(f"{metric.upper()}: {sig_status} (p < {summary['significant_after_correction']})")
    print("--------------------------------\n")
    
    return results

if __name__ == "__main__":
    main()