import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Tuple, Optional
import numpy as np

from config import Config

logger = logging.getLogger(__name__)

class MatrixLoader:
    """
    Loads and verifies pre-computed rotation matrices from the clustering report.
    This module is critical for the Dynamic Rotation Router (US2).
    """

    def __init__(self, config: Config):
        self.config = config
        self.report_path = Path(config.CLUSTERING_REPORT_PATH)
        self._matrices_cache: Optional[Dict[str, Any]] = None

    def load(self) -> Dict[str, Any]:
        """
        Loads the clustering report JSON and extracts rotation matrices.
        Returns the full report structure or raises an error if missing/invalid.
        """
        if not self.report_path.exists():
            raise FileNotFoundError(
                f"Clustering report not found at {self.report_path}. "
                "Ensure T022b has been executed successfully."
            )

        logger.info(f"Loading clustering report from {self.report_path}")

        with open(self.report_path, 'r', encoding='utf-8') as f:
            data = json.load(f)

        # Verify structure
        required_keys = ['layers', 'matrices', 'boundaries']
        for key in required_keys:
            if key not in data:
                raise ValueError(
                    f"Clustering report missing required key: '{key}'. "
                    "This file is likely corrupted or generated by an incomplete run."
                )

        # Validate matrices exist and are numpy-compatible
        matrices = data.get('matrices', {})
        if not matrices:
            raise ValueError("Clustering report contains no rotation matrices.")

        # Optional: Verify matrix dimensions if 'layer_dims' is present
        if 'layer_dims' in data:
            for layer_name, dims in data['layer_dims'].items():
                if layer_name in matrices:
                    mat = np.array(matrices[layer_name])
                    expected_rows = dims[0] if isinstance(dims, (list, tuple)) else dims
                    if mat.shape[0] != expected_rows:
                        logger.warning(
                            f"Matrix for layer '{layer_name}' has {mat.shape[0]} rows, "
                            f"expected {expected_rows}. Proceeding with caution."
                        )

        self._matrices_cache = data
        logger.info(f"Successfully loaded {len(matrices)} rotation matrices.")
        return data

    def get_matrices(self) -> Dict[str, np.ndarray]:
        """
        Returns a dictionary of layer names -> numpy rotation matrices.
        Matrices are loaded on first call and cached.
        """
        if self._matrices_cache is None:
            self.load()

        raw_matrices = self._matrices_cache['matrices']
        return {k: np.array(v, dtype=np.float32) for k, v in raw_matrices.items()}

    def get_boundaries(self) -> List[float]:
        """
        Returns the entropy boundaries used for clustering.
        """
        if self._matrices_cache is None:
            self.load()
        return self._matrices_cache['boundaries']

    def get_layer_mapping(self) -> Dict[str, int]:
        """
        Returns a mapping of layer names to their matrix indices (0..K-1).
        This is useful if the router needs to know which matrix index corresponds to which layer.
        """
        if self._matrices_cache is None:
            self.load()
        
        # The report structure typically has 'layers' as a list of layer names
        # and 'matrices' as a dict of layer_name -> matrix_data.
        # We assume the index in the 'layers' list corresponds to the matrix index.
        layers = self._matrices_cache.get('layers', [])
        return {layer: idx for idx, layer in enumerate(layers)}

def load_matrices_from_path(path: str) -> Dict[str, np.ndarray]:
    """
    Convenience function to load matrices from a specific path without a Config object.
    Used primarily for testing or one-off scripts.
    """
    config = Config()
    config.CLUSTERING_REPORT_PATH = path
    loader = MatrixLoader(config)
    return loader.get_matrices()

def verify_matrices(matrices: Dict[str, np.ndarray]) -> bool:
    """
    Performs basic sanity checks on the loaded matrices.
    Returns True if all checks pass, False otherwise.
    """
    if not matrices:
        return False

    for name, mat in matrices.items():
        if not isinstance(mat, np.ndarray):
            logger.error(f"Matrix '{name}' is not a numpy array.")
            return False
        if mat.ndim != 2:
            logger.error(f"Matrix '{name}' is not 2D (shape: {mat.shape}).")
            return False
        if np.any(np.isnan(mat)) or np.any(np.isinf(mat)):
            logger.error(f"Matrix '{name}' contains NaN or Inf values.")
            return False
    return True

def main():
    """
    Entry point for standalone verification of the clustering report.
    Loads the report, extracts matrices, and prints a summary.
    """
    config = Config()
    loader = MatrixLoader(config)

    try:
        report = loader.load()
        matrices = loader.get_matrices()
        boundaries = loader.get_boundaries()

        print(f"--- Clustering Report Summary ---")
        print(f"Report Path: {config.CLUSTERING_REPORT_PATH}")
        print(f"Total Layers: {len(report.get('layers', []))}")
        print(f"Total Matrices: {len(matrices)}")
        print(f"Entropy Boundaries (K={len(boundaries)-1}):")
        print(f"  {boundaries}")

        if verify_matrices(matrices):
            print("\n[OK] All matrix integrity checks passed.")
        else:
            print("\n[FAIL] Matrix integrity checks failed.")
            return 1

        return 0

    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        return 1
    except ValueError as e:
        logger.error(f"Validation error: {e}")
        return 1
    except Exception as e:
        logger.exception(f"Unexpected error: {e}")
        return 1

if __name__ == "__main__":
    import sys
    sys.exit(main())
