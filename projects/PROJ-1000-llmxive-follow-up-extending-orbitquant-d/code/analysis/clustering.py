def compute_activation_histograms(variances_file: str, bins: int = 100) -> np.ndarray:
    """
    Load activation variances from CSV and compute histograms for clustering.
    Input: data/processed/activation_variances_train.csv (generated by T017/T008 pipeline)
    Output: numpy array of shape (n_samples, n_features) where features are binned variance counts.
    """
    if not os.path.exists(variances_file):
        raise FileNotFoundError(f"Activation variances file not found: {variances_file}. "
                                "Run T017 (correlation) to generate this file first.")
    
    logger.info(f"Loading activation variances from {variances_file}")
    data = []
    with open(variances_file, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Assume columns are named like 'layer_0_variance', 'layer_1_variance', etc.
            # or a generic 'variance' if flattened. We expect a structured variance per layer.
            # We will collect all numeric columns.
            row_data = []
            for k, v in row.items():
                if k != 'prompt_id' and k != 'entropy_score' and k != 'image_id':
                    try:
                        row_data.append(float(v))
                    except ValueError:
                        pass
            if row_data:
                data.append(row_data)
    
    if not data:
        raise ValueError("No numeric variance data found in CSV.")
    
    X = np.array(data)
    logger.info(f"Loaded {X.shape[0]} samples with {X.shape[1]} variance features.")
    
    # Compute histograms per feature (layer)
    # We will use the raw variance values for clustering, but optionally bin them if needed.
    # For K-Means on variance distributions, raw values are often better.
    # However, the task mentions "activation histograms". We will interpret this as:
    # The input is already variance per layer. We will cluster these variance vectors.
    # If the user wants histograms of the *distribution* of variances across samples,
    # that is a different step. Here we assume the "histogram" refers to the distribution
    # of variances across the dataset which we are clustering to find "subsets" of similar behavior.
    # We proceed with the raw variance vectors X.
    return X

def compute_rotation_matrix_from_activations(activations: np.ndarray, k: int = 16) -> np.ndarray:
    """
    Compute a rotation matrix based on the PCA of the activation variance distribution.
    This implements the OrbitQuant logic: derive rotation matrices that align with
    the principal components of the activation variance to minimize quantization error.
    
    Args:
        activations: numpy array of shape (n_samples, n_features) representing variances.
        k: number of clusters (K=16) to derive distinct matrices.
    
    Returns:
        A list of k rotation matrices (numpy arrays).
    """
    logger.info(f"Computing {k} rotation matrices from activation variance distribution.")
    
    # Standardize the data for PCA
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(activations)
    
    # Perform PCA to find principal directions
    # We use numpy's SVD for PCA
    U, S, Vt = np.svd(X_scaled, full_matrices=False)
    
    # The principal components are in Vt (rows are components)
    # We want to cluster the samples based on their variance profile to find "subsets"
    # Then for each subset, we compute a specific rotation matrix.
    # However, the task asks for K=16 pre-optimized matrices.
    # Strategy: Cluster the samples into K groups. For each group, compute the mean variance vector.
    # Then compute a rotation matrix that aligns with the covariance structure of that group.
    # Or, simpler: Use K-Means on the variance vectors to find K clusters.
    # For each cluster, compute the PCA rotation matrix of that cluster's data.
    
    from sklearn.cluster import KMeans
    
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    labels = kmeans.fit_predict(X_scaled)
    
    rotation_matrices = []
    
    for i in range(k):
        mask = labels == i
        cluster_data = X_scaled[mask]
        
        if len(cluster_data) == 0:
            # Fallback to identity if cluster is empty
            rotation_matrices.append(np.eye(activations.shape[1]))
            continue
        
        # Compute PCA on the cluster data to get the rotation matrix
        # The rotation matrix is the matrix of eigenvectors of the covariance matrix
        # which are the rows of Vt from SVD of the cluster data.
        U_c, S_c, Vt_c = np.svd(cluster_data, full_matrices=False)
        
        # The rotation matrix is Vt_c (the principal components)
        # We take the top d components where d is the number of features
        # (which is all components in this case)
        R = Vt_c
        
        rotation_matrices.append(R)
        logger.info(f"Cluster {i}: size={len(cluster_data)}, matrix shape={R.shape}")
    
    return rotation_matrices

def run_clustering_pipeline(train_variances_file: str, output_file: str, k: int = 16):
    """
    Main pipeline to:
    1. Load activation variances from the train split.
    2. Cluster them into K subsets.
    3. Compute a rotation matrix for each subset.
    4. Save the results to a JSON report.
    """
    logger.info("Starting clustering pipeline for rotation matrix derivation.")
    
    # 1. Load data
    activations = compute_activation_histograms(train_variances_file)
    
    # 2. Compute rotation matrices
    rotation_matrices = compute_rotation_matrix_from_activations(activations, k=k)
    
    # 3. Prepare the report
    # We need to save: layers, subsets, boundaries, and matrices.
    # Since we don't have explicit layer names in the variance file (just columns),
    # we will infer them as "layer_0", "layer_1", etc.
    n_layers = activations.shape[1]
    layers = [f"layer_{i}" for i in range(n_layers)]
    
    # We need to describe the subsets (clusters)
    # We'll save the cluster centers and the rotation matrix for each.
    # Also, we need to save the boundaries (the range of variance values that define the cluster?)
    # Since K-Means doesn't give explicit boundaries in feature space, we can save the min/max
    # of the cluster members in the original variance space.
    
    # Re-load original data to get boundaries
    data = []
    with open(train_variances_file, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            row_data = []
            for k, v in row.items():
                if k != 'prompt_id' and k != 'entropy_score' and k != 'image_id':
                    try:
                        row_data.append(float(v))
                    except ValueError:
                        pass
            if row_data:
                data.append(row_data)
    original_X = np.array(data)
    
    # Re-run clustering to get labels
    from sklearn.cluster import KMeans
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(original_X)
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    labels = kmeans.fit_predict(X_scaled)
    
    subsets = []
    for i in range(k):
        mask = labels == i
        cluster_original = original_X[mask]
        
        if len(cluster_original) == 0:
            continue
        
        subset_info = {
            "cluster_id": i,
            "size": int(len(cluster_original)),
            "boundaries": {
                "min": cluster_original.min(axis=0).tolist(),
                "max": cluster_original.max(axis=0).tolist()
            },
            "rotation_matrix": rotation_matrices[i].tolist()
        }
        subsets.append(subset_info)
    
    report = {
        "k": k,
        "n_layers": n_layers,
        "layers": layers,
        "subsets": subsets,
        "description": "Pre-optimized rotation matrices derived from K-Means clustering of activation variances."
    }
    
    # 4. Save report
    os.makedirs(os.path.dirname(output_file), exist_ok=True)
    with open(output_file, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Clustering report saved to {output_file}")
    return report

def main():
    """
    Entry point for T022b.
    Reads: data/processed/activation_variances_train.csv (generated by T017)
    Writes: data/processed/clustering_report.json
    """
    config = {
        "train_variances_file": "data/processed/activation_variances_train.csv",
        "output_file": "data/processed/clustering_report.json",
        "k": 16
    }
    
    # Check if input file exists
    if not os.path.exists(config["train_variances_file"]):
        logger.error(f"Input file {config['train_variances_file']} not found. "
                     "T017 (correlation) must be run first to generate activation variances.")
        # In a real pipeline, we might raise an error here.
        # For this task, we assume the file exists as per the dependency.
        # If it doesn't, the task fails.
        raise FileNotFoundError(f"Required input file {config['train_variances_file']} not found.")
    
    run_clustering_pipeline(
        train_variances_file=config["train_variances_file"],
        output_file=config["output_file"],
        k=config["k"]
    )

if __name__ == "__main__":
    main()
