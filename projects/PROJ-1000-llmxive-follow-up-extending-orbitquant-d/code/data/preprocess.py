"""
Preprocess MS-COCO dataset to extract captions and split into train/test sets.

This script reads the MS-COCO dataset downloaded by T005 (download_coco.py),
extracts the text captions, saves them to data/processed/prompts.csv, and
splits the data into train and test sets.

Output:
  - data/processed/prompts.csv: Combined CSV with all prompts
  - data/processed/prompts_train.csv: Training split (80%)
  - data/processed/prompts_test.csv: Test split (20%)
"""

import os
import sys
import csv
import random
from pathlib import Path
from typing import List, Dict, Any

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(project_root))

from config import Config


def load_coco_captions(config: Config) -> List[Dict[str, Any]]:
    """
    Load captions from the downloaded MS-COCO dataset.

    The dataset is expected to be cached at config.data_path / "coco"
    as generated by T005 (download_coco.py).

    Returns:
        List of dictionaries with 'image_id' and 'caption' keys.
    """
    # Expected path based on T005 implementation
    coco_data_path = config.data_path / "coco"
    
    if not coco_data_path.exists():
        raise FileNotFoundError(
            f"MS-COCO dataset not found at {coco_data_path}. "
            "Please run code/data/download_coco.py first."
        )

    # The datasets library caches data in a specific structure.
    # We need to load the validation split which contains image/caption pairs.
    # Since download_coco.py uses streaming=False, the data is cached locally.
    
    try:
        from datasets import load_dataset
    except ImportError:
        raise ImportError(
            "The 'datasets' package is required. Install it with: pip install datasets"
        )

    # Load the cached dataset
    # The download_coco.py script downloads "mscoco" dataset with validation split
    # Using the correct config name for mscoco 2014
    dataset = load_dataset(
        "mscoco", 
        "2014",
        split="validation",
        cache_dir=str(config.data_path),
        trust_remote_code=True
    )

    captions = []
    for item in dataset:
        # Each item has 'image_id' and 'caption' (or similar structure)
        # The mscoco dataset typically has 'caption' field for the single caption
        if 'caption' in item and item['caption']:
            captions.append({
                'image_id': item.get('image_id', ''),
                'caption': item['caption']
            })

    if not captions:
        raise ValueError(
            f"No captions found in the dataset at {coco_data_path}. "
            "Verify that download_coco.py completed successfully."
        )

    return captions


def split_data(
    data: List[Dict[str, Any]], 
    test_ratio: float = 0.2, 
    seed: int = 42
) -> tuple:
    """
    Split data into train and test sets.

    Args:
        data: List of data dictionaries
        test_ratio: Proportion of data to use for testing
        seed: Random seed for reproducibility

    Returns:
        Tuple of (train_data, test_data)
    """
    random.seed(seed)
    shuffled_data = data.copy()
    random.shuffle(shuffled_data)
    
    split_idx = int(len(shuffled_data) * (1 - test_ratio))
    train_data = shuffled_data[:split_idx]
    test_data = shuffled_data[split_idx:]
    
    return train_data, test_data


def write_csv(data: List[Dict[str, Any]], output_path: Path) -> None:
    """
    Write data to a CSV file.

    Args:
        data: List of dictionaries to write
        output_path: Path to the output CSV file
    """
    if not data:
        raise ValueError("Cannot write empty data to CSV")

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    fieldnames = data[0].keys()
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(data)


def main():
    """
    Main function to preprocess COCO captions.
    """
    config = Config()
    
    print(f"Starting preprocessing for MS-COCO captions...")
    print(f"Data path: {config.data_path}")
    print(f"Output path: {config.processed_data_path}")

    # Load captions
    print("Loading captions from MS-COCO dataset...")
    try:
        captions = load_coco_captions(config)
        print(f"Loaded {len(captions)} captions.")
    except Exception as e:
        print(f"ERROR: Failed to load captions: {e}")
        sys.exit(1)

    # Split into train/test
    print("Splitting data into train/test sets...")
    train_data, test_data = split_data(captions, test_ratio=0.2, seed=config.seed)
    print(f"Train set: {len(train_data)} samples")
    print(f"Test set: {len(test_data)} samples")

    # Write combined CSV
    combined_path = config.processed_data_path / "prompts.csv"
    print(f"Writing combined prompts to {combined_path}...")
    try:
        write_csv(captions, combined_path)
        print(f"Successfully wrote {len(captions)} rows to {combined_path}")
    except Exception as e:
        print(f"ERROR: Failed to write combined CSV: {e}")
        sys.exit(1)

    # Write train split
    train_path = config.processed_data_path / "prompts_train.csv"
    print(f"Writing train split to {train_path}...")
    try:
        write_csv(train_data, train_path)
        print(f"Successfully wrote {len(train_data)} rows to {train_path}")
    except Exception as e:
        print(f"ERROR: Failed to write train CSV: {e}")
        sys.exit(1)

    # Write test split
    test_path = config.processed_data_path / "prompts_test.csv"
    print(f"Writing test split to {test_path}...")
    try:
        write_csv(test_data, test_path)
        print(f"Successfully wrote {len(test_data)} rows to {test_path}")
    except Exception as e:
        print(f"ERROR: Failed to write test CSV: {e}")
        sys.exit(1)

    print("Preprocessing complete!")


if __name__ == "__main__":
    main()