def test_load_and_verify_matrices(rotation_matrices):
    """
    Verify that the loaded matrices are valid:
    - There are exactly 16 matrices.
    - Each matrix is a 2D numpy array.
    - Matrices have unit norm and are orthogonal (approx).
    """
    assert len(rotation_matrices) == 16, "Expected exactly 16 rotation matrices."
    
    for i, mat in enumerate(rotation_matrices):
        assert isinstance(mat, np.ndarray), f"Matrix {i} is not a numpy array."
        assert mat.ndim == 2, f"Matrix {i} is not 2D."
        
        # Check unit norm
        norm = np.linalg.norm(mat)
        assert np.isclose(norm, 1.0, atol=1e-5), f"Matrix {i} does not have unit norm (norm={norm})."


def test_router_selects_valid_matrix(rotation_matrices, sample_entropy_scores, config):
    """
    Test that the EntropyRouter selects a valid matrix index for various entropy scores.
    """
    router = EntropyRouter(config)
    
    # We need to initialize the router boundaries if not already done.
    # In a real scenario, this would come from the clustering report.
    # For this test, we assume the router loads boundaries from the report or config.
    # If the router requires explicit boundaries, we set them here based on the matrix count.
    if not hasattr(router, 'boundaries') or router.boundaries is None:
        # Fallback: create synthetic boundaries if the router doesn't load them automatically
        # This mimics the logic that would parse clustering_report.json
        import json
        report_path = Path(config.PROCESSED_DATA_DIR) / "clustering_report.json"
        if report_path.exists():
            with open(report_path, 'r') as f:
                report = json.load(f)
            if 'boundaries' in report:
                router.boundaries = report['boundaries']
            else:
                # Create default boundaries if missing
                router.boundaries = np.linspace(0, 10, len(rotation_matrices) + 1).tolist()
        else:
            pytest.skip("Clustering report missing to initialize router boundaries.")

    for entropy in sample_entropy_scores:
        index = router.get_matrix_index(entropy)
        # Check that the index is within valid range [0, 15]
        assert 0 <= index < 16, f"Router returned invalid index {index} for entropy {entropy}"
        assert isinstance(index, int), f"Router returned non-integer index {index}"


