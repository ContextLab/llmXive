def test_out_of_range_entropy_handling(rotation_matrices, config):
    """
    Test that the router handles entropy scores outside the expected range
    by clamping to the nearest boundary (0 or 15).
    """
    router = EntropyRouter(config)
    
    # Initialize boundaries if missing
    if not hasattr(router, 'boundaries') or router.boundaries is None:
        report_path = Path(config.PROCESSED_DATA_DIR) / "clustering_report.json"
        if report_path.exists():
            with open(report_path, 'r') as f:
                report = json.load(f)
            if 'boundaries' in report:
                router.boundaries = report['boundaries']
            else:
                router.boundaries = np.linspace(0, 10, len(rotation_matrices) + 1).tolist()
        else:
            pytest.skip("Clustering report missing.")

    # Very low entropy -> should clamp to 0
    low_entropy = -100.0
    idx_low = router.get_matrix_index(low_entropy)
    assert idx_low == 0, f"Low entropy {low_entropy} should clamp to index 0, got {idx_low}"

    # Very high entropy -> should clamp to 15
    high_entropy = 1000.0
    idx_high = router.get_matrix_index(high_entropy)
    assert idx_high == 15, f"High entropy {high_entropy} should clamp to index 15, got {idx_high}"


