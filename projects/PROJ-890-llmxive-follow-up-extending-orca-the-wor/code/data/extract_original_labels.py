"""
Extract Original Physical Outcomes (N=450)

Parses video metadata from the N=450 curated clips (previously filtered by optical flow)
to extract the 'original_outcome' as ground truth for Descriptive Analysis.

Output: data/processed/original_labels.csv
Columns: scenario_id, original_outcome
"""

import os
import sys
import csv
import json
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional

# Project root imports
sys.path.insert(0, str(Path(__file__).parent.parent))
from config import get_config, ensure_directories
from utils.audit_logger import log_skipped_file, log_audit_event

logger = logging.getLogger(__name__)

# Constants
INPUT_FILE_NAME = "filtered_orca_metadata.json"
OUTPUT_FILE_NAME = "original_labels.csv"
BATCH_SIZE = 100  # Processing batch size for logging

def load_filtered_metadata(config: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    Loads the JSON file containing the filtered Orca dataset metadata.
    This file is expected to be generated by T011/T012 (download_orca.py).

    Args:
        config: Project configuration dictionary.

    Returns:
        List of metadata dictionaries.

    Raises:
        FileNotFoundError: If the input metadata file does not exist.
        ValueError: If the file is not valid JSON.
    """
    input_path = Path(config["data_dir"]) / "processed" / INPUT_FILE_NAME

    if not input_path.exists():
        raise FileNotFoundError(
            f"Required input file not found: {input_path}. "
            "Please ensure T011/T012 (download_orca.py) has been executed successfully."
        )

    logger.info(f"Loading filtered metadata from {input_path}")
    with open(input_path, "r", encoding="utf-8") as f:
        try:
            data = json.load(f)
        except json.JSONDecodeError as e:
            raise ValueError(f"Invalid JSON in {input_path}: {e}")

    if not isinstance(data, list):
        # Handle case where data might be wrapped in a key, though spec implies list
        if isinstance(data, dict) and "data" in data:
            data = data["data"]
        else:
            raise ValueError(f"Expected JSON list in {input_path}, got {type(data)}")

    logger.info(f"Loaded {len(data)} metadata records.")
    return data

def extract_outcome(record: Dict[str, Any]) -> Optional[str]:
    """
    Extracts the original outcome string from a metadata record.

    The outcome is typically found in:
    - metadata['outcome']
    - metadata['label']
    - metadata['description'] (fallback if outcome is missing)

    Args:
        record: A single metadata dictionary.

    Returns:
        The outcome string, or None if not found.
    """
    # Try standard keys based on typical dataset structures
    outcome = None
    possible_keys = ["outcome", "label", "original_outcome", "description"]

    for key in possible_keys:
        if key in record:
            val = record[key]
            if isinstance(val, str) and val.strip():
                outcome = val.strip()
                break
            elif isinstance(val, dict):
                # Sometimes outcome is nested, e.g., {"text": "object fell"}
                if "text" in val:
                    outcome = val["text"].strip()
                    break

    # Fallback: If no explicit outcome, try to construct from prompt if it implies an outcome
    if not outcome and "prompt" in record:
        prompt = record["prompt"]
        # Simple heuristic: if prompt contains "fell", "moved", "hit", etc.
        # This is a weak fallback, but better than None for some edge cases
        if any(kw in prompt.lower() for kw in ["fell", "dropped", "moved", "pushed", "hit", "broke"]):
            outcome = prompt

    return outcome

def run_extraction_pipeline(metadata: List[Dict[str, Any]], output_path: Path) -> int:
    """
    Processes the metadata list and writes the original_labels.csv file.

    Args:
        metadata: List of metadata dictionaries.
        output_path: Path to the output CSV file.

    Returns:
        Number of successfully extracted records.
    """
    extracted_count = 0
    skipped_count = 0

    with open(output_path, "w", newline="", encoding="utf-8") as csvfile:
        writer = csv.writer(csvfile)
        writer.writerow(["scenario_id", "original_outcome"])

        for i, record in enumerate(metadata):
            scenario_id = record.get("id") or record.get("video_id") or record.get("scenario_id")

            if not scenario_id:
                logger.warning(f"Record at index {i} missing ID. Skipping.")
                skipped_count += 1
                continue

            outcome = extract_outcome(record)

            if not outcome:
                logger.warning(f"Could not extract outcome for scenario_id: {scenario_id}. Skipping.")
                log_skipped_file(f"extract_original_labels", str(scenario_id), "Missing outcome field")
                skipped_count += 1
                continue

            writer.writerow([scenario_id, outcome])
            extracted_count += 1

            # Log progress every BATCH_SIZE
            if (i + 1) % BATCH_SIZE == 0:
                logger.info(f"Processed {i + 1}/{len(metadata)} records. Extracted: {extracted_count}, Skipped: {skipped_count}")

    log_audit_event(
        "extract_original_labels",
        "extraction_complete",
        {
            "total_processed": len(metadata),
            "extracted": extracted_count,
            "skipped": skipped_count,
            "output_file": str(output_path)
        }
    )

    logger.info(f"Extraction complete. Wrote {extracted_count} records to {output_path}. Skipped {skipped_count}.")
    return extracted_count

def main():
    """Main entry point for the script."""
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(name)s - %(levelname)s - %(message)s"
    )

    config = get_config()
    ensure_directories(config)

    output_path = Path(config["data_dir"]) / "processed" / OUTPUT_FILE_NAME

    try:
        metadata = load_filtered_metadata(config)
        if not metadata:
            logger.warning("No metadata found in input file. Creating empty output.")
            with open(output_path, "w", newline="", encoding="utf-8") as f:
                writer = csv.writer(f)
                writer.writerow(["scenario_id", "original_outcome"])
            return

        count = run_extraction_pipeline(metadata, output_path)

        if count == 0:
            logger.error("No records were extracted. Check input data and extraction logic.")
            sys.exit(1)

        logger.info(f"Successfully generated {output_path} with {count} entries.")

    except FileNotFoundError as e:
        logger.error(f"Input data missing: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Data processing error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.exception(f"Unexpected error during extraction: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()