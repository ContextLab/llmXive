"""
Unit tests for verifying the output shape and validity of latent vectors.

This module validates that the latent vectors extracted by extract_latents.py
meet the following criteria:
1. Correct shape (expected dimensionality)
2. Valid data types (float32/float64)
3. No NaN or Inf values
4. Reasonable value ranges (not exploding gradients)
5. Consistency across batches
"""

import os
import sys
import csv
import json
import numpy as np
import pytest
from pathlib import Path

# Add project root to path for imports
project_root = Path(__file__).parent.parent.parent
sys.path.insert(0, str(project_root / "code"))

from config import get_config, ensure_directories
from data.models import LatentVector


class TestLatentVectorValidation:
    """Test suite for validating latent vector outputs."""

    @pytest.fixture
    def config(self):
        """Load project configuration."""
        return get_config()

    @pytest.fixture
    def latents_csv_path(self, config):
        """Return the path to the processed latents CSV file."""
        return config["DATA_PROCESSED_DIR"] / "latents.csv"

    def _load_latents_from_csv(self, path: Path) -> list:
        """
        Load latent vectors from the CSV file generated by extract_latents.py.
        
        Returns a list of dictionaries with 'video_id', 'prompt', and 'latent_vector' (numpy array).
        """
        if not path.exists():
            pytest.skip(f"Latents CSV not found at {path}. Run extract_latents.py first.")
        
        latents_data = []
        with open(path, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                try:
                    # Parse the latent vector string back to numpy array
                    # Format is expected to be: "[val1, val2, ...]"
                    vector_str = row["latent_vector"].strip("[]")
                    vector_values = [float(x.strip()) for x in vector_str.split(",") if x.strip()]
                    latent_array = np.array(vector_values, dtype=np.float32)
                    
                    latents_data.append({
                        "video_id": row["video_id"],
                        "prompt": row["prompt"],
                        "latent_vector": latent_array
                    })
                except (ValueError, KeyError) as e:
                    pytest.fail(f"Failed to parse row in {path}: {e}")
        
        return latents_data

    def test_file_exists(self, latents_csv_path):
        """Test that the latents CSV file was created."""
        assert latents_csv_path.exists(), "Latents CSV file does not exist. Run extract_latents.py first."

    def test_non_empty_output(self, latents_csv_path):
        """Test that the output file is not empty."""
        with open(latents_csv_path, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            rows = list(reader)
            assert len(rows) > 0, "Latents CSV file is empty. No latents were extracted."

    def test_expected_shape(self, latents_csv_path, config):
        """
        Test that all latent vectors have the expected dimensionality.
        
        The expected shape comes from the frozen Orca model's output layer.
        """
        expected_dim = config.get("EXPECTED_LATENT_DIM", 768)  # Default to 768 if not specified
        latents_data = self._load_latents_from_csv(latents_csv_path)
        
        for item in latents_data:
            assert item["latent_vector"].shape == (expected_dim,), \
                f"Latent vector for {item['video_id']} has shape {item['latent_vector'].shape}, expected ({expected_dim},)"

    def test_valid_dtype(self, latents_csv_path):
        """Test that latent vectors are of valid floating point dtype."""
        latents_data = self._load_latents_from_csv(latents_csv_path)
        
        for item in latents_data:
            assert np.issubdtype(item["latent_vector"].dtype, np.floating), \
                f"Latent vector for {item['video_id']} is not a floating point type: {item['latent_vector'].dtype}"

    def test_no_nan_values(self, latents_csv_path):
        """Test that latent vectors do not contain NaN values."""
        latents_data = self._load_latents_from_csv(latents_csv_path)
        
        for item in latents_data:
            assert not np.isnan(item["latent_vector"]).any(), \
                f"Latent vector for {item['video_id']} contains NaN values"

    def test_no_inf_values(self, latents_csv_path):
        """Test that latent vectors do not contain Inf values."""
        latents_data = self._load_latents_from_csv(latents_csv_path)
        
        for item in latents_data:
            assert not np.isinf(item["latent_vector"]).any(), \
                f"Latent vector for {item['video_id']} contains Inf values"

    def test_reasonable_value_range(self, latents_csv_path):
        """
        Test that latent vectors are within a reasonable numerical range.
        
        Typically, normalized embeddings should be within [-10, 10] or similar.
        This prevents exploding gradients or numerical instability.
        """
        latents_data = self._load_latents_from_csv(latents_csv_path)
        
        # Allowable range: typically [-10, 10] for normalized embeddings
        # Adjust if the model uses different normalization
        min_val = -10.0
        max_val = 10.0
        
        for item in latents_data:
            vector = item["latent_vector"]
            assert vector.min() >= min_val and vector.max() <= max_val, \
                f"Latent vector for {item['video_id']} has values outside [{min_val}, {max_val}]: " \
                f"min={vector.min():.4f}, max={vector.max():.4f}"

    def test_consistent_dimensions(self, latents_csv_path):
        """Test that all latent vectors have the same dimensionality."""
        latents_data = self._load_latents_from_csv(latents_csv_path)
        
        if not latents_data:
            pytest.skip("No latents to check")
        
        first_dim = latents_data[0]["latent_vector"].shape[0]
        
        for item in latents_data[1:]:
            assert item["latent_vector"].shape[0] == first_dim, \
                f"Inconsistent dimensions: {item['video_id']} has {item['latent_vector'].shape[0]}, " \
                f"expected {first_dim}"

    def test_latent_vector_model_compatibility(self, latents_csv_path):
        """
        Test that the extracted latents can be validated by the LatentVector Pydantic model.
        """
        latents_data = self._load_latents_from_csv(latents_csv_path)
        
        for item in latents_data:
            try:
                # Create a LatentVector instance to validate structure
                latent_obj = LatentVector(
                    video_id=item["video_id"],
                    prompt=item["prompt"],
                    vector=item["latent_vector"].tolist()  # Convert to list for Pydantic
                )
                assert latent_obj is not None
            except Exception as e:
                pytest.fail(f"LatentVector validation failed for {item['video_id']}: {e}")

    def test_csv_headers(self, latents_csv_path):
        """Test that the CSV file has the required headers."""
        required_headers = {"video_id", "prompt", "latent_vector"}
        
        with open(latents_csv_path, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            actual_headers = set(reader.fieldnames) if reader.fieldnames else set()
            
            missing = required_headers - actual_headers
            assert not missing, f"Missing required CSV headers: {missing}"

    def test_sample_size_validation(self, latents_csv_path, config):
        """
        Test that the number of extracted latents meets the minimum expected count.
        
        This ensures the pipeline processed a significant portion of the dataset.
        """
        min_expected = config.get("MIN_EXTRACTED_LATENTS", 10)  # Minimum threshold
        
        with open(latents_csv_path, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            count = sum(1 for _ in reader)
        
        assert count >= min_expected, \
            f"Only {count} latents extracted, expected at least {min_expected}. " \
            "Check if the dataset download and filtering worked correctly."

if __name__ == "__main__":
    pytest.main([__file__, "-v"])
