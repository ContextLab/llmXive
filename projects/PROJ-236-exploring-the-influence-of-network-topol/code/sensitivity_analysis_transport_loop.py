"""
Sensitivity Analysis Transport Loop

This script iterates over the cutoff values defined in the simulation
configuration, invokes the transport calculation for each cutoff, and
aggregates the resulting transport metrics into a single CSV file
``data/analysis/sensitivity_results.csv``.
"""

from __future__ import annotations

import csv
import subprocess
import sys
from pathlib import Path
from typing import List, Dict, Any

from utils.io import load_simulation_config, get_config_value


def _run_transport_for_cutoff(cutoff: float) -> Path:
    """
    Execute the transport calculation script for a specific cutoff.

    The transport script is expected to be ``code/compute_transport.py`` and
    must accept a ``--cutoff`` command‑line argument.  After successful
    execution it should produce (or append to) ``data/transport/transport_results.csv``.

    Parameters
    ----------
    cutoff: float
        The cutoff value to pass to the transport solver.

    Returns
    -------
    Path
        Path to the transport results CSV file generated by the solver.
    """
    cmd = [
        sys.executable,
        "code/compute_transport.py",
        "--cutoff",
        str(cutoff),
    ]
    # ``check=True`` propagates any failure as a CalledProcessError.
    subprocess.run(cmd, check=True)

    transport_path = Path("data/transport/transport_results.csv")
    if not transport_path.is_file():
        raise FileNotFoundError(
            f"Transport results not found at expected location: {transport_path}"
        )
    return transport_path


def _extract_latest_transport_row(transport_csv: Path) -> Dict[str, Any]:
    """
    Read the transport results CSV and return the most recent row.
    The transport script is assumed to append a single row per invocation.
    """
    with transport_csv.open(newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
        if not rows:
            raise ValueError(f"No rows found in transport results file {transport_csv}")
        return rows[-1]  # last row corresponds to the most recent run


def main() -> None:
    """
    Main entry point for the sensitivity analysis transport loop.

    The function:
    1. Loads ``simulation_config.yaml`` and extracts the ``cutoff_values`` list.
    2. For each cutoff, runs the transport calculation.
    3. Collects the resulting transport metrics and writes them together with the
       cutoff value to ``data/analysis/sensitivity_results.csv``.
    """
    # ------------------------------------------------------------------
    # 1. Load configuration
    # ------------------------------------------------------------------
    config = load_simulation_config()
    cutoffs: List[float] = get_config_value(config, "cutoff_values")
    if not isinstance(cutoffs, list) or not cutoffs:
        raise ValueError(
            "simulation_config.yaml must contain a non‑empty list under the key "
            "'cutoff_values'."
        )

    # ------------------------------------------------------------------
    # 2. Prepare output CSV
    # ------------------------------------------------------------------
    output_path = Path("data/analysis/sensitivity_results.csv")
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Define the column order.  TransportResult fields are taken from the
    # contract schema (see contracts/transport_schema.schema.yaml) and
    # we prepend the cutoff that drove the calculation.
    fieldnames = [
        "cutoff",
        "network_id",
        "kappa",
        "error_estimate",
        "convergence_status",
        "runtime",
        "regime_flag",
    ]

    with output_path.open("w", newline="") as out_file:
        writer = csv.DictWriter(out_file, fieldnames=fieldnames)
        writer.writeheader()

        # ------------------------------------------------------------------
        # 3. Loop over cutoffs, run transport, and aggregate results
        # ------------------------------------------------------------------
        for cutoff in cutoffs:
            transport_csv = _run_transport_for_cutoff(cutoff)
            latest_row = _extract_latest_transport_row(transport_csv)

            # Assemble the combined row; ensure all expected keys exist.
            combined_row: Dict[str, Any] = {"cutoff": cutoff}
            for key in fieldnames[1:]:
                combined_row[key] = latest_row.get(key, "")

            writer.writerow(combined_row)

    print(f"Sensitivity analysis completed. Results written to {output_path}")


if __name__ == "__main__":
    main()
