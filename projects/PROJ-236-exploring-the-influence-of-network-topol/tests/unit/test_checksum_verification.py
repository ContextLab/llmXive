"""
Automated verification for the checksumming utility (Task T020).

The test reads the manifest ``data/checksums.txt`` generated by
``code/generate_checksums.py`` and recomputes the SHA‑256 checksum for each listed
artifact. Any mismatch (or missing file) causes the test to fail, ensuring that the
stored checksums stay in sync with the actual data on disk.
"""

import pathlib

import pytest

from utils.io import compute_file_checksum


@pytest.fixture(scope="module")
def checksum_manifest():
    """
    Load the checksum manifest once per test session.

    Returns
    -------
    dict
        Mapping of relative POSIX paths (as stored in the manifest) to the recorded
        checksum strings.
    """
    manifest_path = pathlib.Path("data") / "checksums.txt"
    assert manifest_path.is_file(), "Checksum manifest 'data/checksums.txt' is missing."

    manifest = {}
    with manifest_path.open("r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            # Expected format: "<relative_path> <checksum>"
            try:
                rel_path, checksum = line.split()
            except ValueError:
                raise AssertionError(
                    f"Malformed line in checksum manifest: '{line}'. Expected two whitespace‑separated columns."
                )
            manifest[rel_path] = checksum
    return manifest


def test_all_artifact_checksums_match(checksum_manifest):
    """
    Re‑compute the checksum for every file listed in the manifest and assert that it
    matches the recorded value.

    The test deliberately skips the manifest file itself to avoid a circular check.
    """
    data_root = pathlib.Path("data")
    for rel_path, recorded_checksum in checksum_manifest.items():
        artifact_path = data_root / pathlib.Path(rel_path)
        assert artifact_path.is_file(), f"Artifact listed in manifest not found: {rel_path}"

        actual_checksum = compute_file_checksum(artifact_path)
        assert (
            actual_checksum == recorded_checksum
        ), f"Checksum mismatch for '{rel_path}': expected {recorded_checksum}, got {actual_checksum}"

    # If the manifest is empty, the test passes vacuously – this is acceptable when no
    # data artifacts have been generated yet.
