from data.fetch_prs import check_keywords, load_repo_list, RepoStats

class TestCheckKeywords:
    def test_keywords_in_title(self):
        title = "Implement copilot feature"
        body = "This adds new functionality"
        keywords = ["copilot", "llm"]
        assert check_keywords(title, body, keywords) is True

    def test_keywords_in_body(self):
        title = "New feature"
        body = "Generated by LLM"
        keywords = ["copilot", "llm"]
        assert check_keywords(title, body, keywords) is True

    def test_no_keywords(self):
        title = "Fix bug"
        body = "Update documentation"
        keywords = ["copilot", "llm"]
        assert check_keywords(title, body, keywords) is False

    def test_case_insensitive(self):
        title = "COPILOT integration"
        body = "llm support added"
        keywords = ["copilot", "llm"]
        assert check_keywords(title, body, keywords) is True

class TestLoadRepoList:
    def test_valid_repo_list(self, tmp_path):
        repo_file = tmp_path / "repos.txt"
        repo_file.write_text("microsoft/vscode\nfacebook/react\n")
        repos = load_repo_list(str(repo_file))
        assert repos == ["microsoft/vscode", "facebook/react"]

    def test_rejects_invalid_format(self, tmp_path):
        repo_file = tmp_path / "repos.txt"
        repo_file.write_text("invalid-format\nmicrosoft/vscode\n")
        repos = load_repo_list(str(repo_file))
        assert repos == ["microsoft/vscode"]

    def test_handles_comments(self, tmp_path):
        repo_file = tmp_path / "repos.txt"
        repo_file.write_text("# Comment\nmicrosoft/vscode\n# Another comment\n")
        repos = load_repo_list(str(repo_file))
        assert repos == ["microsoft/vscode"]

    def test_file_not_found(self):
        with pytest.raises(FileNotFoundError):
            load_repo_list("nonexistent.txt")

class TestRepoStats:
    def test_init(self):
        stats = RepoStats("test/repo", 1000)
        assert stats.repo_id == "test/repo"
        assert stats.star_count == 1000
        assert stats.pr_count == 0
        assert stats.keyword_matches == 0

    def test_increment(self):
        stats = RepoStats("test/repo", 1000)
        stats.pr_count += 1
        stats.keyword_matches += 1
        assert stats.pr_count == 1
        assert stats.keyword_matches == 1
