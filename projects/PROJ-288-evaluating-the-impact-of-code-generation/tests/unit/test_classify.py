class TestCheckDisclosureKeywords:
    """Tests for the check_disclosure_keywords function."""

    def test_detect_copilot_keyword(self):
        """Test detection of 'copilot' keyword in title."""
        title = "Fix bug with GitHub Copilot integration"
        body = "This PR addresses issues with Copilot."
        result = check_disclosure_keywords(title, body)
        assert result is True

    def test_detect_llm_keyword(self):
        """Test detection of 'llm' keyword in body."""
        title = "Refactor data processing module"
        body = "We used an LLM to generate the initial draft."
        result = check_disclosure_keywords(title, body)
        assert result is True

    def test_detect_generated_keyword(self):
        """Test detection of 'generated' keyword."""
        title = "Update documentation"
        body = "The following code was AI-generated and needs review."
        result = check_disclosure_keywords(title, body)
        assert result is True

    def test_case_insensitive_detection(self):
        """Test that keyword detection is case-insensitive."""
        title = "Fix BUG with GITHUB COPILOT integration"
        body = "This PR addresses issues with LLM."
        result = check_disclosure_keywords(title, body)
        assert result is True

    def test_no_keywords_found(self):
        """Test that no keywords returns False."""
        title = "Fix typo in README"
        body = "Corrected a spelling mistake."
        result = check_disclosure_keywords(title, body)
        assert result is False

    def test_empty_title_and_body(self):
        """Test handling of empty strings."""
        result = check_disclosure_keywords("", "")
        assert result is False

    def test_partial_keyword_not_detected(self):
        """Test that partial matches are not detected."""
        title = "CopilotX is a new tool"
        body = "No relevant keywords here."
        # "CopilotX" should not match "copilot" as a whole word
        result = check_disclosure_keywords(title, body)
        assert result is False

    def test_keyword_in_code_block(self):
        """Test that keywords in code blocks are still detected."""
        title = "Update code"
        body = "```python\n# Generated by copilot\nprint('hello')\n```"
        result = check_disclosure_keywords(title, body)
        assert result is True


class TestCalculateHeuristicScores:
    """Tests for the calculate_heuristic_scores function."""

    def test_high_comment_ratio(self):
        """Test scoring for high comment ratio."""
        pr_data = {
            "title": "Add comments",
            "body": "Added extensive comments.",
            "lines_changed": 100,
            "comment_lines": 40  # 40% comment ratio
        }
        scores = calculate_heuristic_scores(pr_data)
        # Expect high comment score
        assert scores["comment_ratio_score"] > 0.5

    def test_low_comment_ratio(self):
        """Test scoring for low comment ratio."""
        pr_data = {
            "title": "Refactor",
            "body": "Refactored code.",
            "lines_changed": 100,
            "comment_lines": 5  # 5% comment ratio
        }
        scores = calculate_heuristic_scores(pr_data)
        # Expect low comment score
        assert scores["comment_ratio_score"] < 0.3

    def test_formatting_pattern_score(self):
        """Test formatting pattern scoring."""
        pr_data = {
            "title": "Format code",
            "body": "Applied auto-formatter.",
            "lines_changed": 500,
            "formatting_changes": 450  # 90% formatting changes
        }
        scores = calculate_heuristic_scores(pr_data)
        # Expect high formatting score
        assert scores["formatting_pattern_score"] > 0.8

    def test_small_change_size(self):
        """Test scoring for small changes."""
        pr_data = {
            "title": "Fix",
            "body": "Small fix.",
            "lines_changed": 5,
            "comment_lines": 1,
            "formatting_changes": 0
        }
        scores = calculate_heuristic_scores(pr_data)
        # Small changes might have different scoring
        assert scores["change_size_score"] is not None

    def test_combined_scores(self):
        """Test that all scores are calculated."""
        pr_data = {
            "title": "PR",
            "body": "Body.",
            "lines_changed": 100,
            "comment_lines": 20,
            "formatting_changes": 10
        }
        scores = calculate_heuristic_scores(pr_data)
        assert "comment_ratio_score" in scores
        assert "formatting_pattern_score" in scores
        assert "change_size_score" in scores
        assert "overall_heuristic_score" in scores


