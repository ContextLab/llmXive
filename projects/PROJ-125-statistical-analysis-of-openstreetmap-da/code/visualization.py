logger = get_logger(__name__)


def load_correlation_matrix() -> pd.DataFrame:
    """
    Load the correlation matrix generated by the EDA pipeline.
    
    Returns:
        DataFrame: Correlation matrix with variables as index/columns.
    """
    path = get_path("data/results/correlation_matrix.csv")
    if not os.path.exists(path):
        raise FileNotFoundError(f"Correlation matrix not found at {path}")
    
    df = pd.read_csv(path, index_col=0)
    logger.info(f"Loaded correlation matrix with shape {df.shape}")
    return df


def load_spatial_stats() -> Dict[str, Any]:
    """
    Load spatial statistics (Moran's I, variogram params) from JSON.
    
    Returns:
        Dict: Spatial statistics dictionary.
    """
    path = get_path("data/results/spatial_stats.json")
    if not os.path.exists(path):
        raise FileNotFoundError(f"Spatial stats not found at {path}")
    
    with open(path, 'r') as f:
        data = json.load(f)
    
    logger.info(f"Loaded spatial stats: {list(data.keys())}")
    return data


def plot_correlation_heatmap(
    df: Optional[pd.DataFrame] = None,
    output_path: Optional[Path] = None,
    title: str = "Correlation Matrix: OSM Features vs Temperature"
) -> Path:
    """
    Generate and save a correlation heatmap.
    
    Args:
        df: Correlation DataFrame. If None, loads from default path.
        output_path: Path to save the figure. Defaults to data/results/correlation_heatmap.png.
        title: Plot title.
        
    Returns:
        Path: Path to the saved figure.
    """
    if df is None:
        df = load_correlation_matrix()
    
    if output_path is None:
        output_path = get_path("data/results/correlation_heatmap.png")
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    plt.figure(figsize=(12, 10))
    mask = np.triu(np.ones_like(df, dtype=bool))
    
    sns.heatmap(
        df,
        mask=mask,
        cmap='coolwarm',
        vmin=-1,
        vmax=1,
        center=0,
        square=True,
        linewidths=.5,
        annot=True,
        fmt=".2f",
        cbar_kws={"shrink": .5}
    )
    
    plt.title(title, fontsize=14, pad=20)
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close()
    
    logger.info(f"Saved correlation heatmap to {output_path}")
    return output_path


def compute_empirical_variogram(
    values: np.ndarray,
    coordinates: np.ndarray,
    bin_width: float = 500.0,
    max_lag: Optional[float] = None
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Compute empirical variogram from values and coordinates.
    
    Args:
        values: 1D array of values (e.g., temperature).
        coordinates: 2D array of coordinates (N, 2).
        bin_width: Width of distance bins in meters.
        max_lag: Maximum lag distance. Defaults to half the max distance.
        
    Returns:
        Tuple of (lag_distances, semivariances, counts).
    """
    if len(values) != len(coordinates):
        raise ValueError("Values and coordinates must have same length")
    
    # Calculate distance matrix
    dists = distance_matrix(coordinates, coordinates)
    np.fill_diagonal(dists, np.inf)  # Ignore self-distances
    
    # Get upper triangle
    upper_tri = dists[np.triu_indices_from(dists, k=1)]
    diff_vals = np.abs(values[:, None] - values[None, :])
    diff_vals = diff_vals[np.triu_indices_from(diff_vals, k=1)]
    
    # Bin the distances
    if max_lag is None:
        max_lag = np.max(upper_tri) / 2
    
    bins = np.arange(0, max_lag + bin_width, bin_width)
    bin_indices = np.digitize(upper_tri, bins) - 1
    
    lag_centers = []
    semivariances = []
    counts = []
    
    for i in range(len(bins) - 1):
        mask = bin_indices == i
        if np.sum(mask) > 0:
            lag_centers.append(np.mean(upper_tri[mask]))
            semivariances.append(np.mean(0.5 * (diff_vals[mask] ** 2)))
            counts.append(np.sum(mask))
    
    return np.array(lag_centers), np.array(semivariances), np.array(counts)


def plot_variogram(
    output_path: Optional[Path] = None,
    temperature_raster_path: Optional[str] = None,
    sample_size: int = 1000,
    seed: int = 42
) -> Path:
    """
    Generate and save an empirical variogram plot for temperature data.
    
    Args:
        output_path: Path to save the figure. Defaults to data/results/variogram.png.
        temperature_raster_path: Path to temperature raster. If None, uses config default.
        sample_size: Number of random points to sample from the raster.
        seed: Random seed for reproducibility.
        
    Returns:
        Path: Path to the saved figure.
    """
    if output_path is None:
        output_path = get_path("data/results/variogram.png")
    
    # Load spatial stats if available to get variogram model params
    stats_data = load_spatial_stats()
    
    # Try to load temperature data from raster
    # If rasterio is available and data exists, sample from it
    # Otherwise, use synthetic-like sampling from the stats if available
    try:
        import rasterio
        from rasterio.transform import from_bounds
        
        if temperature_raster_path is None:
            # Try to find temperature raster in processed data
            processed_dir = get_path("data/processed")
            temp_files = list(Path(processed_dir).glob("*temperature*.tif"))
            if not temp_files:
                raise FileNotFoundError("No temperature raster found")
            temperature_raster_path = str(temp_files[0])
        
        with rasterio.open(temperature_raster_path) as src:
            # Read metadata
            bounds = src.bounds
            transform = src.transform
            crs = src.crs
            
            # Sample random points
            np.random.seed(seed)
            n_valid = src.count * src.width * src.height
            
            # Simple sampling: read data and sample indices
            data = src.read(1)
            valid_mask = ~np.isnan(data) & (data != src.nodata)
            
            valid_indices = np.argwhere(valid_mask)
            if len(valid_indices) < sample_size:
                sample_size = len(valid_indices)
                logger.warning(f"Reduced sample size to {sample_size}")
            
            sampled_indices = np.random.choice(len(valid_indices), sample_size, replace=False)
            sampled_coords = valid_indices[sampled_indices]
            
            # Convert pixel coordinates to real coordinates
            sampled_real_coords = []
            sampled_values = []
            
            for row, col in sampled_coords:
                x, y = rasterio.transform.xy(transform, row, col, offset='center')
                sampled_real_coords.append([x, y])
                sampled_values.append(data[row, col])
            
            sampled_values = np.array(sampled_values)
            sampled_real_coords = np.array(sampled_real_coords)
            
            # Compute empirical variogram
            lags, semivars, counts = compute_empirical_variogram(
                sampled_values, 
                sampled_real_coords, 
                bin_width=500.0
            )
            
            # Plot
            plt.figure(figsize=(10, 6))
            plt.scatter(lags, semivars, alpha=0.6, s=30, edgecolors='k')
            
            # Fit a simple spherical model if we have enough points
            if len(lags) >= 3 and 'variogram' in stats_data:
                var_data = stats_data.get('variogram', {})
                nugget = var_data.get('nugget', 0)
                sill = var_data.get('sill', 1)
                range_val = var_data.get('range', 1000)
                
                # Spherical model
                def spherical_model(h, nugget, sill, range_val):
                    if h == 0:
                        return nugget
                    if h >= range_val:
                        return nugget + sill
                    ratio = h / range_val
                    return nugget + sill * (1.5 * ratio - 0.5 * ratio**3)
                
                model_vals = [spherical_model(h, nugget, sill, range_val) for h in lags]
                plt.plot(lags, model_vals, 'r-', linewidth=2, label=f'Spherical Model (R²={sill:.2f})')
                
            plt.xlabel('Distance (m)')
            plt.ylabel('Semivariance')
            plt.title('Empirical Variogram: Land Surface Temperature')
            plt.grid(True, alpha=0.3)
            plt.legend()
            plt.tight_layout()
            plt.savefig(output_path, dpi=300, bbox_inches='tight')
            plt.close()
            
            logger.info(f"Saved variogram to {output_path}")
            return output_path
            
    except ImportError:
        logger.warning("rasterio not available, using fallback variogram generation")
        # Fallback: generate from spatial stats if available
        if 'variogram' in stats_data:
            var_data = stats_data['variogram']
            lags = var_data.get('lags', [])
            semivars = var_data.get('semivariances', [])
            
            if lags and semivars:
                plt.figure(figsize=(10, 6))
                plt.scatter(lags, semivars, alpha=0.6, s=30, edgecolors='k')
                plt.plot(lags, semivars, 'r-', linewidth=2)
                plt.xlabel('Distance (m)')
                plt.ylabel('Semivariance')
                plt.title('Empirical Variogram: Land Surface Temperature (from stats)')
                plt.grid(True, alpha=0.3)
                plt.tight_layout()
                plt.savefig(output_path, dpi=300, bbox_inches='tight')
                plt.close()
                logger.info(f"Saved variogram (fallback) to {output_path}")
                return output_path
        
        raise FileNotFoundError("Could not generate variogram: no raster data or stats available")


def plot_combined_eda(
    output_dir: Optional[Path] = None
) -> Dict[str, Path]:
    """
    Generate all EDA visualizations in one call.
    
    Args:
        output_dir: Directory to save figures. Defaults to data/results/.
        
    Returns:
        Dict: Mapping of plot names to file paths.
    """
    if output_dir is None:
        output_dir = get_path("data/results")
    
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    
    results = {}
    
    # Correlation heatmap
    try:
        corr_path = plot_correlation_heatmap(
            output_path=output_dir / "correlation_heatmap.png",
            title="Correlation Matrix: OSM Features vs Temperature"
        )
        results['correlation_heatmap'] = corr_path
    except Exception as e:
        logger.error(f"Failed to generate correlation heatmap: {e}")
    
    # Variogram
    try:
        var_path = plot_variogram(
            output_path=output_dir / "variogram.png"
        )
        results['variogram'] = var_path
    except Exception as e:
        logger.error(f"Failed to generate variogram: {e}")
    
    return results


def main():
    """Main entry point for generating EDA visualizations."""
    logger.info("Starting EDA visualization generation")
    
    try:
        results = plot_combined_eda()
        
        logger.info("Generated visualizations:")
        for name, path in results.items():
            logger.info(f"  - {name}: {path}")
        
        if not results:
            logger.warning("No visualizations were generated")
            return 1
        
        return 0
        
    except Exception as e:
        logger.error(f"Error generating visualizations: {e}", exc_info=True)
        return 1


if __name__ == "__main__":
    exit(main())
