"""
Size gate utilities for the ball milling dataset pipeline.

This module implements the pre-processing size gate (T015c) which
reads the row count from the merged dataset and logs a critical warning
if the count is below the minimum viable threshold (150 rows), without
halting the pipeline.
"""

import json
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional

from src.utils.logger import get_module_logger
from src.exceptions import InsufficientDataError

# Minimum viable dataset size as per spec SC-004
MIN_MV_ROWS = 150

def read_row_count(count_file_path: Optional[str] = None) -> int:
    """
    Read the row count from the JSON file generated by T015b.

    Args:
        count_file_path: Path to the row_count.json file. Defaults to
                         'data/processed/row_count.json' relative to project root.

    Returns:
        The integer row count.

    Raises:
        FileNotFoundError: If the count file does not exist.
        json.JSONDecodeError: If the file contains invalid JSON.
        KeyError: If the 'count' key is missing from the JSON.
    """
    if count_file_path is None:
        # Default path relative to project root
        count_file_path = str(Path("data/processed/row_count.json"))

    path = Path(count_file_path)
    if not path.exists():
        raise FileNotFoundError(f"Row count file not found at {count_file_path}")

    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    if 'count' not in data:
        raise KeyError("JSON file must contain a 'count' key")

    return int(data['count'])

def load_flagged_entries(flagged_file_path: Optional[str] = None) -> List[Dict[str, Any]]:
    """
    Load flagged PSD entries from the JSON file generated by T014b.

    Args:
        flagged_file_path: Path to the flagged_psd.json file. Defaults to
                           'data/flagged_psd.json'.

    Returns:
        List of flagged entry dictionaries. Returns empty list if file not found.
    """
    if flagged_file_path is None:
        flagged_file_path = str(Path("data/flagged_psd.json"))

    path = Path(flagged_file_path)
    if not path.exists():
        # No flagged entries if file doesn't exist
        return []

    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)

def trigger_ocr_fallback(flagged_entries: List[Dict[str, Any]], config: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    Trigger OCR extraction for flagged entries if enabled in config.

    Args:
        flagged_entries: List of flagged entry dictionaries.
        config: Configuration dictionary containing 'ocr_enabled' key.

    Returns:
        List of entries that were successfully processed or re-flagged.
        Returns empty list if OCR is disabled or no entries exist.
    """
    if not config.get('ocr_enabled', False):
        return []

    if not flagged_entries:
        return []

    # Import here to avoid circular dependencies and ensure OCR is only attempted if needed
    from src.ingest.ocr_fallback import extract_psd_from_image
    from src.utils.logger import get_module_logger

    logger = get_module_logger(__name__)
    processed_entries = []

    for entry in flagged_entries:
        try:
            # Attempt extraction (this function handles its own logging/errors)
            result = extract_psd_from_image(
                image_path=entry.get('image_path'),
                flagged_entry_id=entry.get('experiment_id'),
                config=config
            )
            if result:
                processed_entries.append(result)
                logger.info(f"OCR extraction successful for entry {entry.get('experiment_id')}")
        except Exception as e:
            logger.warning(f"OCR extraction failed for entry {entry.get('experiment_id')}: {e}")
            # Re-flag for manual review if extraction fails
            entry['status'] = 'ocr_failed'
            processed_entries.append(entry)

    return processed_entries

def check_size_gate(count: int, threshold: int = MIN_MV_ROWS) -> bool:
    """
    Check if the dataset meets the minimum viable size threshold.

    This function implements the T015c requirement:
    - If count < 150, log a CRITICAL warning but DO NOT halt.
    - Returns True if the gate passes (count >= threshold), False otherwise.

    Args:
        count: The number of rows in the dataset.
        threshold: The minimum viable threshold (default 150).

    Returns:
        True if count >= threshold, False otherwise.
    """
    logger = get_module_logger(__name__)

    if count < threshold:
        logger.critical(
            f"Dataset size gate warning: {count} rows found, "
            f"which is below the minimum viable threshold of {threshold} rows. "
            f"Pipeline will continue but results may lack statistical power. "
            f"Consider augmenting data sources."
        )
        return False
    else:
        logger.info(f"Dataset size gate passed: {count} rows >= {threshold} rows.")
        return True