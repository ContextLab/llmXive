import os
import sys
import logging
import glob
from pathlib import Path
from typing import List

from src.utils.logger import get_module_logger
from src.interpret.partial_dependence import generate_partial_dependence_plots
from src.interpret.feature_importance import export_feature_importance

logger = get_module_logger(__name__)

PLOT_SIZE_LIMIT_BYTES = 10 * 1024 * 1024  # 10MB

def validate_plot_size(results_dir: str = "results") -> None:
    """
    Calculate the total file size of all generated plots in the results directory.
    If the total size exceeds 10MB, raise a SystemExit with a clear error message.
    
    Args:
        results_dir: Path to the directory containing generated plots.
        
    Raises:
        SystemExit: If total plot size exceeds 10MB.
    """
    results_path = Path(results_dir)
    if not results_path.exists():
        logger.warning(f"Results directory '{results_dir}' does not exist. Skipping size validation.")
        return

    # Find all PNG plots generated by the interpret pipeline
    # Assuming plots are named with 'partial_dependence' or similar pattern
    plot_patterns = [
        str(results_path / "partial_dependence_*.png"),
        str(results_path / "feature_importance_*.png"),
        str(results_path / "*.png")  # Catch-all for any other plots
    ]
    
    plot_files: List[Path] = []
    for pattern in plot_patterns:
        plot_files.extend(results_path.glob(os.path.basename(pattern).replace("*", "*")))
    
    # Remove duplicates and filter only existing files
    unique_plots = list(set([p for p in plot_files if p.exists()]))
    
    if not unique_plots:
        logger.info("No plot files found in results directory. Skipping size validation.")
        return

    total_size = 0
    oversized_files: List[str] = []
    
    for plot_file in unique_plots:
        file_size = plot_file.stat().st_size
        total_size += file_size
        if file_size > PLOT_SIZE_LIMIT_BYTES:
            oversized_files.append(f"{plot_file.name} ({file_size / (1024*1024):.2f}MB)")

    total_size_mb = total_size / (1024 * 1024)
    logger.info(f"Total plot size: {total_size_mb:.2f}MB ({len(unique_plots)} files)")

    if total_size > PLOT_SIZE_LIMIT_BYTES:
        error_msg = (
            f"Total plot size ({total_size_mb:.2f}MB) exceeds 10MB limit.\n"
            f"Offending files:\n"
        )
        for f in unique_plots:
            size_mb = f.stat().st_size / (1024 * 1024)
            error_msg += f"  - {f.name}: {size_mb:.2f}MB\n"
        
        logger.error(error_msg)
        raise SystemExit(1)
    
    logger.info("Plot size validation passed.")

def main():
    """
    Main entry point for the interpret CLI.
    Orchestrates plot generation, feature importance export, and size validation.
    """
    logger.info("Starting interpret pipeline...")
    
    try:
        # Step 1: Generate partial dependence plots
        logger.info("Generating partial dependence plots...")
        generate_partial_dependence_plots()
        
        # Step 2: Export feature importance
        logger.info("Exporting feature importance...")
        export_feature_importance()
        
        # Step 3: Validate total plot size
        logger.info("Validating plot sizes...")
        validate_plot_size(results_dir="results")
        
        logger.info("Interpret pipeline completed successfully.")
        
    except SystemExit:
        raise
    except Exception as e:
        logger.error(f"Interpret pipeline failed: {e}", exc_info=True)
        raise

if __name__ == "__main__":
    main()
