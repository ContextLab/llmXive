"""
Pipeline Orchestrator for Statistical Power Drift Detection (T030).

Sequences the entire research pipeline:
1. Setup & Directory Initialization
2. Data Download & Validation
3. Preprocessing (Cleaning & Grouping Validation)
4. LMM Fitting (Trend Analysis)
5. Robustness Checks (Permutation & Sensitivity)
6. Visualization
7. Final Reporting & State Update
"""

import os
import sys
import json
import logging
import pickle
from pathlib import Path

# Local imports matching the provided API surface
from setup_dirs import main as setup_dirs_main
from download import main as download_main
from validate_source import main as validate_source_main
from preprocess import main as preprocess_main
from compute_trends import main as compute_trends_main
from robustness import main as robustness_main
from visualize import main as visualize_main
from update_state import main as update_state_main
from logging_config import setup_logging, get_module_logger, log_operation_start, log_operation_complete

# Project root path (relative to where this script is run from)
PROJECT_ROOT = Path(__file__).parent.parent
DATA_RAW_DIR = PROJECT_ROOT / "data" / "raw"
DATA_DERIVED_DIR = PROJECT_ROOT / "data" / "derived"
RESULTS_DIR = PROJECT_ROOT / "results"
STATE_DIR = PROJECT_ROOT / "state"

def run_pipeline():
    """Execute the full research pipeline in sequence."""
    logger = get_module_logger("main_pipeline")
    logger.info("Starting Statistical Power Drift Detection Pipeline (T030)")

    try:
        # 1. Setup Directories
        log_operation_start(logger, "Setting up project directories")
        setup_dirs_main()
        log_operation_complete(logger, "Directories ready")

        # 2. Download Data
        log_operation_start(logger, "Downloading raw data")
        download_main()
        log_operation_complete(logger, "Data downloaded")

        # 3. Validate Source
        log_operation_start(logger, "Validating data source integrity")
        validate_source_main()
        log_operation_complete(logger, "Source validation passed")

        # 4. Preprocess Data
        log_operation_start(logger, "Preprocessing and cleaning data")
        preprocess_main()
        log_operation_complete(logger, "Data preprocessing complete")

        # 5. Compute Trends (LMM)
        log_operation_start(logger, "Fitting Linear Mixed-Effects Model")
        compute_trends_main()
        log_operation_complete(logger, "LMM fitting complete")

        # 6. Robustness Checks
        log_operation_start(logger, "Running robustness checks (Permutation & Sensitivity)")
        robustness_main()
        log_operation_complete(logger, "Robustness checks complete")

        # 7. Visualization
        log_operation_start(logger, "Generating visualizations")
        visualize_main()
        log_operation_complete(logger, "Visualizations generated")

        # 8. Update State (Hashes)
        log_operation_start(logger, "Updating project state with artifact hashes")
        update_state_main()
        log_operation_complete(logger, "State updated")

        logger.info("Pipeline completed successfully.")
        return 0

    except Exception as e:
        logger.error(f"Pipeline execution failed: {e}", exc_info=True)
        return 1

def generate_final_report():
    """
    Aggregates key results from intermediate JSON files into a single final report.
    This is called after the pipeline runs to summarize findings.
    """
    logger = get_module_logger("main_pipeline")
    logger.info("Generating final aggregated report")

    report = {
        "project_id": "PROJ-150-detecting-statistical-power-drift-in-rep",
        "status": "completed",
        "artifacts": {}
    }

    # Collect LMM Summary
    lmm_path = RESULTS_DIR / "lmm_final_summary.json"
    if lmm_path.exists():
        with open(lmm_path, 'r') as f:
            report["artifacts"]["lmm_summary"] = json.load(f)
    else:
        logger.warning(f"Missing file: {lmm_path}")

    # Collect Permutation P-value
    perm_path = RESULTS_DIR / "permutation_pvalue.json"
    if perm_path.exists():
        with open(perm_path, 'r') as f:
            report["artifacts"]["permutation_test"] = json.load(f)
    else:
        logger.warning(f"Missing file: {perm_path}")

    # Collect Sensitivity Report (if generated by robustness)
    sens_path = RESULTS_DIR / "sensitivity_report.json"
    if sens_path.exists():
        with open(sens_path, 'r') as f:
            report["artifacts"]["sensitivity_analysis"] = json.load(f)

    # Save Final Report
    final_report_path = RESULTS_DIR / "final_report.json"
    with open(final_report_path, 'w') as f:
        json.dump(report, f, indent=2)

    logger.info(f"Final report saved to {final_report_path}")
    return report

def main():
    """Entry point for the orchestrator."""
    setup_logging()
    exit_code = run_pipeline()
    
    if exit_code == 0:
        generate_final_report()
    
    sys.exit(exit_code)

if __name__ == "__main__":
    main()