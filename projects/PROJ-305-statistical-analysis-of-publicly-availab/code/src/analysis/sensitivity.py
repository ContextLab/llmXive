def load_signals(filepath: str) -> pd.DataFrame:
    """
    Load the signals CSV generated by T026.
    
    Args:
        filepath: Path to output/signals.csv
        
    Returns:
        DataFrame with signal metrics
        
    Raises:
        FileNotFoundError: If the file does not exist
        ValueError: If the file is empty or has invalid schema
    """
    path = Path(filepath)
    if not path.exists():
        raise FileNotFoundError(f"Signals file not found: {filepath}")
    
    df = pd.read_csv(filepath)
    
    # Validate required columns for sensitivity analysis
    required_cols = {'soc', 'ror', 'ror_ci_lower', 'ror_ci_upper', 
                    'prr', 'prr_ci_lower', 'prr_ci_upper', 
                    'ic', 'ic_ci_lower', 'ic_ci_upper', 'signal_flag'}
    
    if not required_cols.issubset(set(df.columns)):
        missing = required_cols - set(df.columns)
        raise ValueError(f"Signals file missing required columns: {missing}")
    
    # Filter only signals (signal_flag == True)
    signals_df = df[df['signal_flag'] == True].copy()
    
    if signals_df.empty:
        logger.warning("No signals found in the input file. Sensitivity analysis cannot proceed.")
        return pd.DataFrame(columns=['soc', 'ror', 'ror_ci_lower', 'ror_ci_upper',
                                    'prr', 'prr_ci_lower', 'prr_ci_upper',
                                    'ic', 'ic_ci_lower', 'ic_ci_upper', 'signal_flag'])
    
    return signals_df

def load_cleaned_data(filepath: str) -> pd.DataFrame:
    """
    Load the cleaned VAERS data from T015.
    
    Args:
        filepath: Path to data/processed/cleaned_vaers.parquet or .csv
        
    Returns:
        DataFrame with cleaned data including baseline group columns
        
    Raises:
        FileNotFoundError: If the file does not exist
    """
    path = Path(filepath)
    if not path.exists():
        raise FileNotFoundError(f"Cleaned data file not found: {filepath}")
    
    if path.suffix == '.parquet':
        df = pd.read_parquet(filepath)
    else:
        df = pd.read_csv(filepath)
    
    # Verify required columns exist
    required_cols = ['SOC', 'baseline_type', 'VAX_TYPE']
    if not all(col in df.columns for col in required_cols):
        missing = [col for col in required_cols if col not in df.columns]
        raise ValueError(f"Cleaned data missing required columns: {missing}")
    
    return df

def filter_data_for_baseline(df: pd.DataFrame, baseline_type: str) -> pd.DataFrame:
    """
    Filter the cleaned data for a specific baseline group.
    
    Args:
        df: Full cleaned DataFrame
        baseline_type: Either 'Non-COVID (All)' or 'Flu-only'
        
    Returns:
        Filtered DataFrame for the specified baseline
    """
    if baseline_type == 'Non-COVID (All)':
        # Primary Baseline: All non-COVID vaccines
        filtered = df[df['baseline_type'] == 'Non-COVID']
    elif baseline_type == 'Flu-only':
        # Flu-only subset of Primary Baseline
        filtered = df[df['baseline_type'] == 'Flu-only']
    else:
        raise ValueError(f"Unknown baseline type: {baseline_type}")
    
    return filtered

def calculate_metrics_for_soc(data: pd.DataFrame, soc: str) -> Dict[str, float]:
    """
    Calculate ROR, PRR, and IC for a specific SOC using the provided data.
    
    This function builds a 2x2 contingency table for the SOC:
    - Event (SOC = target) vs No Event (SOC != target)
    - Case (COVID-19) vs Control (Baseline group)
    
    Args:
        data: Filtered DataFrame containing both COVID-19 and baseline groups
        soc: The System Organ Class code to analyze
        
    Returns:
        Dictionary with ROR, PRR, IC and their 95% CIs
    """
    # Ensure we have both case and control groups in the data
    case_count = len(data[data['VAX_TYPE'].str.contains('COVID-19', na=False)])
    control_count = len(data[data['baseline_type'].isin(['Non-COVID', 'Flu-only'])])
    
    if case_count < 5 or control_count < 5:
        logger.warning(f"Insufficient data for SOC {soc}: {case_count} cases, {control_count} controls")
        return {
            'ror': float('nan'),
            'ror_ci_lower': float('nan'),
            'ror_ci_upper': float('nan'),
            'prr': float('nan'),
            'prr_ci_lower': float('nan'),
            'prr_ci_upper': float('nan'),
            'ic': float('nan'),
            'ic_ci_lower': float('nan'),
            'ic_ci_upper': float('nan')
        }
    
    # Build contingency table
    # a = Events in Case group (COVID-19 + SOC)
    # b = Events in Control group (Baseline + SOC)
    # c = Non-events in Case group (COVID-19 + Not SOC)
    # d = Non-events in Control group (Baseline + Not SOC)
    
    # Filter for the specific SOC
    soc_data = data[data['SOC'] == soc]
    non_soc_data = data[data['SOC'] != soc]
    
    # Case group (COVID-19)
    case_soc = len(soc_data[soc_data['VAX_TYPE'].str.contains('COVID-19', na=False)])
    case_total = len(data[data['VAX_TYPE'].str.contains('COVID-19', na=False)])
    case_non_soc = case_total - case_soc
    
    # Control group (Baseline)
    control_soc = len(soc_data[soc_data['baseline_type'].isin(['Non-COVID', 'Flu-only'])])
    control_total = len(data[data['baseline_type'].isin(['Non-COVID', 'Flu-only'])])
    control_non_soc = control_total - control_soc
    
    # Apply continuity correction
    a, b, c, d = apply_continuity_correction(case_soc, control_soc, case_non_soc, control_non_soc)
    
    # Calculate metrics
    ror = calculate_ror(a, b, c, d)
    ror_ci_lower, ror_ci_upper = calculate_ci_ror(a, b, c, d)
    
    prr = calculate_prr(a, b, c, d)
    prr_ci_lower, prr_ci_upper = calculate_ci_prr(a, b, c, d)
    
    ic = calculate_ic(a, b, c, d)
    ic_ci_lower, ic_ci_upper = calculate_ci_ic(a, b, c, d)
    
    return {
        'ror': ror,
        'ror_ci_lower': ror_ci_lower,
        'ror_ci_upper': ror_ci_upper,
        'prr': prr,
        'prr_ci_lower': prr_ci_lower,
        'prr_ci_upper': prr_ci_upper,
        'ic': ic,
        'ic_ci_lower': ic_ci_lower,
        'ic_ci_upper': ic_ci_upper
    }

def run_sensitivity_analysis(cleaned_data_path: str, signals_path: str, output_path: str) -> pd.DataFrame:
    """
    Run the full sensitivity analysis comparing Non-COVID vs Flu-only baselines.
    
    Args:
        cleaned_data_path: Path to cleaned VAERS data (T015 output)
        signals_path: Path to signals CSV (T026 output)
        output_path: Path where sensitivity_analysis.csv will be written
        
    Returns:
        DataFrame with sensitivity analysis results
    """
    logger.info(f"Loading signals from {signals_path}")
    signals_df = load_signals(signals_path)
    
    if signals_df.empty:
        logger.warning("No signals to analyze. Creating empty output.")
        # Create empty DataFrame with expected schema
        result_df = pd.DataFrame(columns=['soc', 'ror_delta', 'prr_delta', 'ic_delta', 'baseline_type'])
        result_df.to_csv(output_path, index=False)
        return result_df
    
    # Get top 5 signals (or fewer if less than 5)
    top_n = 5
    top_signals = signals_df.head(top_n)
    logger.info(f"Analyzing top {len(top_signals)} signals")
    
    logger.info(f"Loading cleaned data from {cleaned_data_path}")
    cleaned_data = load_cleaned_data(cleaned_data_path)
    
    results = []
    
    for _, signal_row in top_signals.iterrows():
        soc = signal_row['soc']
        logger.info(f"Processing SOC: {soc}")
        
        # Get baseline metrics from the main analysis (Non-COVID, Non-Flu)
        # We need to recalculate for Non-COVID (All) and Flu-only baselines
        
        # For Non-COVID (All) baseline
        data_non_covid = cleaned_data[cleaned_data['baseline_type'] == 'Non-COVID']
        # Ensure we have COVID-19 data merged in
        covid_data = cleaned_data[cleaned_data['VAX_TYPE'].str.contains('COVID-19', na=False)]
        combined_non_covid = pd.concat([covid_data, data_non_covid], ignore_index=True)
        
        metrics_non_covid = calculate_metrics_for_soc(combined_non_covid, soc)
        
        # For Flu-only baseline
        data_flu = cleaned_data[cleaned_data['baseline_type'] == 'Flu-only']
        combined_flu = pd.concat([covid_data, data_flu], ignore_index=True)
        
        metrics_flu = calculate_metrics_for_soc(combined_flu, soc)
        
        # Calculate deltas (Flu-only - Non-COVID)
        ror_delta = metrics_flu['ror'] - metrics_non_covid['ror']
        prr_delta = metrics_flu['prr'] - metrics_non_covid['prr']
        ic_delta = metrics_flu['ic'] - metrics_non_covid['ic']
        
        results.append({
            'soc': soc,
            'ror_delta': ror_delta,
            'prr_delta': prr_delta,
            'ic_delta': ic_delta,
            'baseline_type': 'Flu-only vs Non-COVID'
        })
    
    result_df = pd.DataFrame(results)
    
    # Ensure output directory exists
    ensure_dirs([output_path])
    
    # Write to CSV
    result_df.to_csv(output_path, index=False)
    logger.info(f"Sensitivity analysis results written to {output_path}")
    
    return result_df

