"""
Sensitivity analysis module for User Story 2.

Compares disproportionality metrics (ROR, PRR, IC) across different baseline groups:
- Full Non-COVID (Primary Baseline)
- Flu-only (Sensitivity Baseline 1)
- Non-COVID, Non-Flu (Sensitivity Baseline 2)

Calculates delta metrics between baselines for top signals.
"""
import os
import sys
import logging
import math
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple

import pandas as pd
import numpy as np

# Import from existing API surface
from src.utils.config import THRESHOLDS
from src.analysis.disproportionality import (
    apply_continuity_correction,
    build_contingency_table,
    calculate_ror,
    calculate_prr,
    calculate_ic,
    calculate_ci_ror,
    calculate_ci_prr,
    calculate_ci_ic
)

logger = logging.getLogger(__name__)

# Constants
MIN_REPORTS_FOR_ANALYSIS = 5
CONTINUITY_CORRECTION = 0.5

def load_signals(signals_path: str) -> pd.DataFrame:
    """
    Load the signals CSV generated by T025b.
    
    Args:
        signals_path: Path to output/signals.csv
        
    Returns:
        DataFrame with signal metrics
        
    Raises:
        FileNotFoundError: If signals file doesn't exist
        ValueError: If required columns are missing
    """
    if not os.path.exists(signals_path):
        raise FileNotFoundError(f"Signals file not found: {signals_path}")
    
    df = pd.read_csv(signals_path)
    
    required_cols = ['soc', 'ror', 'prr', 'ic', 'signal_flag']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in signals file: {missing_cols}")
    
    return df

def load_cleaned_data(data_path: str) -> pd.DataFrame:
    """
    Load the cleaned VAERS dataset.
    
    Args:
        data_path: Path to data/processed/cleaned_vaers.parquet
        
    Returns:
        DataFrame with cleaned VAERS data
    """
    if not os.path.exists(data_path):
        raise FileNotFoundError(f"Cleaned data file not found: {data_path}")
    
    df = pd.read_parquet(data_path)
    return df

def filter_data_for_baseline(df: pd.DataFrame, baseline_type: str) -> pd.DataFrame:
    """
    Filter data to create specific baseline groups for comparison.
    
    Args:
        df: Full cleaned dataset with 'VAX_TYPE' and 'SOC' columns
        baseline_type: One of 'full_non_covid', 'flu_only', 'non_covid_non_flu'
        
    Returns:
        Filtered DataFrame for the specified baseline
    """
    if baseline_type == 'full_non_covid':
        # Full Non-COVID Group: VAX_TYPE does NOT contain "COVID-19"
        # This includes Flu and Non-COVID-Non-Flu
        mask = ~df['VAX_TYPE'].str.contains('COVID-19', na=False)
    elif baseline_type == 'flu_only':
        # Flu-only Group: VAX_TYPE contains "Influenza" (and not COVID-19)
        mask = df['VAX_TYPE'].str.contains('Influenza', na=False) & ~df['VAX_TYPE'].str.contains('COVID-19', na=False)
    elif baseline_type == 'non_covid_non_flu':
        # Non-COVID, Non-Flu Group: VAX_TYPE does NOT contain "COVID-19" AND does NOT contain "Influenza"
        mask = ~df['VAX_TYPE'].str.contains('COVID-19', na=False) & ~df['VAX_TYPE'].str.contains('Influenza', na=False)
    else:
        raise ValueError(f"Unknown baseline_type: {baseline_type}")
    
    return df[mask].copy()

def calculate_metrics_for_soc(
    soc: str,
    covid_data: pd.DataFrame,
    baseline_data: pd.DataFrame,
    min_reports: int = MIN_REPORTS_FOR_ANALYSIS
) -> Optional[Dict[str, Any]]:
    """
    Calculate ROR, PRR, IC and CIs for a specific SOC comparing COVID-19 vs a baseline.
    
    Args:
        soc: System Organ Class code
        covid_data: DataFrame with COVID-19 reports
        baseline_data: DataFrame with baseline reports
        min_reports: Minimum total reports required for analysis
        
    Returns:
        Dictionary with metrics or None if insufficient data
    """
    # Filter for specific SOC
    covid_soc = covid_data[covid_data['SOC'] == soc]
    baseline_soc = baseline_data[baseline_data['SOC'] == soc]
    
    total_covid = len(covid_data)
    total_baseline = len(baseline_data)
    
    if total_covid == 0 or total_baseline == 0:
        return None
    
    # Build 2x2 contingency table
    # Event (SOC) vs No Event (Not SOC) for each group
    a = len(covid_soc)  # COVID with event
    b = total_covid - a  # COVID without event
    c = len(baseline_soc)  # Baseline with event
    d = total_baseline - c  # Baseline without event
    
    total_reports = a + b + c + d
    if total_reports < min_reports:
        return None
    
    # Apply continuity correction
    a, b, c, d = apply_continuity_correction(a, b, c, d)
    
    # Calculate metrics
    ror = calculate_ror(a, b, c, d)
    prr = calculate_prr(a, b, c, d)
    ic = calculate_ic(a, b, c, d)
    
    # Calculate confidence intervals
    ror_ci_lower, ror_ci_upper = calculate_ci_ror(a, b, c, d)
    prr_ci_lower, prr_ci_upper = calculate_ci_prr(a, b, c, d)
    ic_ci_lower, ic_ci_upper = calculate_ci_ic(a, b, c, d)
    
    return {
        'soc': soc,
        'ror': ror,
        'ror_ci_lower': ror_ci_lower,
        'ror_ci_upper': ror_ci_upper,
        'prr': prr,
        'prr_ci_lower': prr_ci_lower,
        'prr_ci_upper': prr_ci_upper,
        'ic': ic,
        'ic_ci_lower': ic_ci_lower,
        'ic_ci_upper': ic_ci_upper,
        'total_reports': total_reports,
        'baseline_type': 'full_non_covid' if total_baseline == len(baseline_data) else baseline_type
    }

def run_sensitivity_analysis(
    signals_df: pd.DataFrame,
    covid_data: pd.DataFrame,
    baseline_full: pd.DataFrame,
    baseline_flu: pd.DataFrame,
    baseline_non_flu: pd.DataFrame,
    top_n: int = 5
) -> pd.DataFrame:
    """
    Run sensitivity analysis comparing different baselines for top signals.
    
    Args:
        signals_df: DataFrame with signals from T025b
        covid_data: COVID-19 group data
        baseline_full: Full Non-COVID baseline data
        baseline_flu: Flu-only baseline data
        baseline_non_flu: Non-COVID, Non-Flu baseline data
        top_n: Number of top signals to analyze
        
    Returns:
        DataFrame with sensitivity analysis results
    """
    # Get top N signals (by signal_flag or ROR)
    signal_socs = signals_df[signals_df['signal_flag'] == True]['soc'].head(top_n).tolist()
    
    if not signal_socs:
        logger.warning("No signals found for sensitivity analysis")
        return pd.DataFrame(columns=['soc', 'ror_delta', 'prr_delta', 'ic_delta', 'baseline_type'])
    
    results = []
    
    for soc in signal_socs:
        # Get primary baseline metrics (Full Non-COVID)
        primary_metrics = calculate_metrics_for_soc(soc, covid_data, baseline_full)
        
        if primary_metrics is None:
            logger.warning(f"Skipping {soc}: insufficient data for primary baseline")
            continue
        
        # Calculate metrics for Flu-only baseline
        flu_metrics = calculate_metrics_for_soc(soc, covid_data, baseline_flu)
        
        # Calculate metrics for Non-COVID, Non-Flu baseline
        non_flu_metrics = calculate_metrics_for_soc(soc, covid_data, baseline_non_flu)
        
        # Calculate deltas
        if flu_metrics:
            ror_delta_flu = flu_metrics['ror'] - primary_metrics['ror']
            prr_delta_flu = flu_metrics['prr'] - primary_metrics['prr']
            ic_delta_flu = flu_metrics['ic'] - primary_metrics['ic']
            
            results.append({
                'soc': soc,
                'ror_delta': ror_delta_flu,
                'prr_delta': prr_delta_flu,
                'ic_delta': ic_delta_flu,
                'baseline_type': 'flu_only'
            })
        
        if non_flu_metrics:
            ror_delta_nfl = non_flu_metrics['ror'] - primary_metrics['ror']
            prr_delta_nfl = non_flu_metrics['prr'] - primary_metrics['prr']
            ic_delta_nfl = non_flu_metrics['ic'] - primary_metrics['ic']
            
            results.append({
                'soc': soc,
                'ror_delta': ror_delta_nfl,
                'prr_delta': prr_delta_nfl,
                'ic_delta': ic_delta_nfl,
                'baseline_type': 'non_covid_non_flu'
            })
    
    if not results:
        return pd.DataFrame(columns=['soc', 'ror_delta', 'prr_delta', 'ic_delta', 'baseline_type'])
    
    return pd.DataFrame(results)

def main():
    """
    Main entry point for sensitivity analysis.
    
    Reads signals from output/signals.csv, loads cleaned data,
    runs sensitivity analysis, and writes results to output/sensitivity_analysis.csv.
    """
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(levelname)s - %(message)s'
    )
    
    # Define paths
    project_root = Path(__file__).parent.parent.parent.parent
    signals_path = project_root / 'output' / 'signals.csv'
    cleaned_data_path = project_root / 'data' / 'processed' / 'cleaned_vaers.parquet'
    output_path = project_root / 'output' / 'sensitivity_analysis.csv'
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    try:
        # Load signals
        logger.info(f"Loading signals from {signals_path}")
        signals_df = load_signals(str(signals_path))
        logger.info(f"Loaded {len(signals_df)} signals")
        
        # Load cleaned data
        logger.info(f"Loading cleaned data from {cleaned_data_path}")
        cleaned_data = load_cleaned_data(str(cleaned_data_path))
        logger.info(f"Loaded {len(cleaned_data)} records")
        
        # Separate COVID-19 and baseline groups
        covid_data = cleaned_data[cleaned_data['VAX_TYPE'].str.contains('COVID-19', na=False)].copy()
        logger.info(f"COVID-19 group: {len(covid_data)} records")
        
        # Create baseline groups
        baseline_full = filter_data_for_baseline(cleaned_data, 'full_non_covid')
        logger.info(f"Full Non-COVID baseline: {len(baseline_full)} records")
        
        baseline_flu = filter_data_for_baseline(cleaned_data, 'flu_only')
        logger.info(f"Flu-only baseline: {len(baseline_flu)} records")
        
        baseline_non_flu = filter_data_for_baseline(cleaned_data, 'non_covid_non_flu')
        logger.info(f"Non-COVID, Non-Flu baseline: {len(baseline_non_flu)} records")
        
        # Run sensitivity analysis
        logger.info("Running sensitivity analysis")
        sensitivity_results = run_sensitivity_analysis(
            signals_df=signals_df,
            covid_data=covid_data,
            baseline_full=baseline_full,
            baseline_flu=baseline_flu,
            baseline_non_flu=baseline_non_flu,
            top_n=5
        )
        
        # Save results
        if not sensitivity_results.empty:
            sensitivity_results.to_csv(output_path, index=False)
            logger.info(f"Sensitivity analysis results saved to {output_path}")
            logger.info(f"Generated {len(sensitivity_results)} delta records")
        else:
            logger.warning("No sensitivity analysis results to save")
            # Create empty file with headers
            sensitivity_results.to_csv(output_path, index=False)
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == '__main__':
    main()
