"""
Generate manifest.json for reproducibility tracking.

This script collects software versions, random seeds, and data checksums
to create a comprehensive manifest file for the Bayesian hierarchical
modeling pipeline.

Inputs:
  - data/checksums.txt (generated by T061)
  - requirements.txt (project dependencies)
Outputs:
  - data/manifest.json (reproducibility manifest)
"""
import json
import logging
import platform
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from pipeline.utils import set_global_seed, setup_logger

# Set global seed for reproducibility
set_global_seed(12345)

def get_python_version():
    """Get Python version string."""
    return f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}"

def get_package_versions():
    """Extract versions of key packages from requirements.txt or installed packages."""
    requirements_path = project_root / "requirements.txt"
    versions = {}

    if requirements_path.exists():
        with open(requirements_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith("#") and "==" in line:
                    package, version = line.split("==", 1)
                    versions[package.strip()] = version.strip()
    else:
        # Fallback: try to get installed versions
        key_packages = [
            "numpy",
            "pandas",
            "numpyro",
            "cmdstanpy",
            "networkx",
            "pyyaml",
            "jsonschema",
        ]
        for pkg in key_packages:
            try:
                import importlib.metadata
                versions[pkg] = importlib.metadata.version(pkg)
            except importlib.metadata.PackageNotFoundError:
                versions[pkg] = "not installed"

    return versions

def get_data_checksums():
    """Read checksums from data/checksums.txt."""
    checksums_path = project_root / "data" / "checksums.txt"
    checksums = {}

    if checksums_path.exists():
        with open(checksums_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line and "  " in line:
                    # Format: <hash>  <path>
                    parts = line.split("  ", 1)
                    if len(parts) == 2:
                        hash_val, file_path = parts
                        checksums[file_path.strip()] = hash_val.strip()
    else:
        logging.warning(f"Checksums file not found at {checksums_path}. "
                      "Manifest will be generated without data hashes.")

    return checksums

def get_system_info():
    """Get basic system information."""
    return {
        "platform": platform.system(),
        "platform_release": platform.release(),
        "platform_version": platform.version(),
        "architecture": platform.machine(),
        "processor": platform.processor(),
    }

def generate_manifest(output_path=None):
    """Generate the manifest.json file."""
    if output_path is None:
        output_path = project_root / "data" / "manifest.json"

    manifest = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "random_seed": 12345,
        "python_version": get_python_version(),
        "system_info": get_system_info(),
        "package_versions": get_package_versions(),
        "data_checksums": get_data_checksums(),
        "pipeline_version": "1.0.0",
        "task_id": "T083",
    }

    # Write manifest to file
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)

    logging.info(f"Manifest generated successfully at {output_path}")
    return manifest

def main():
    """Main entry point for manifest generation."""
    logger = setup_logger("generate_manifest")
    logger.info("Starting manifest generation...")

    try:
        manifest = generate_manifest()
        logger.info(f"Manifest created with {len(manifest['data_checksums'])} data checksums")
        logger.info(f"Package versions tracked: {len(manifest['package_versions'])}")
        return 0
    except Exception as e:
        logger.error(f"Failed to generate manifest: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
