"""
T039: Generate Final Report
Reads data/analysis_results.json and generates data/report.md.
Explicitly links the conclusion to the 'is_significant' boolean.
"""
import json
import os
import sys
from pathlib import Path

def load_analysis_results(path: str) -> dict:
    if not os.path.exists(path):
        raise FileNotFoundError(f"Analysis results not found at {path}. "
                                "Run T038 (generate_analysis_results) first.")
    with open(path, 'r') as f:
        return json.load(f)

def generate_report(results: dict, output_path: str) -> None:
    """
    Generates a markdown report summarizing the findings.
    Traceability: The conclusion is strictly derived from results['is_significant'].
    """
    is_significant = results.get('is_significant', False)
    p_tobit = results.get('p_tobit_corrected', None)
    p_cox = results.get('p_cox_corrected', None)
    coef_tobit = results.get('interaction_coef_tobit', None)
    coef_cox = results.get('interaction_coef_cox', None)

    # Determine conclusion based on the boolean flag
    if is_significant:
        conclusion = (
            "The analysis provides statistically significant evidence that the "
            "effect of the rewiring probability (beta) on convergence speed depends "
            "on the loss function used. Specifically, the contrastive loss (InfoNCE) "
            "demonstrates a different convergence trajectory relative to Cross-Entropy "
            "as the graph topology shifts from lattice to random."
        )
    else:
        conclusion = (
            "The analysis did not find statistically significant evidence of an "
            "interaction effect between the loss function and the rewiring probability "
            "(beta). Based on the current data, we cannot conclude that contrastive "
            "loss converges faster as beta increases compared to Cross-Entropy."
        )

    report_content = f"""# Final Research Report: Loss Functions on Small-World Graphs

## Executive Summary

This report summarizes the statistical analysis investigating the effectiveness of Contrastive Loss (InfoNCE) versus Cross-Entropy (CE) on Watts-Strogatz small-world graphs with varying rewiring probabilities (beta).

## Methodology

- **Data Source**: 110 synthetic graphs generated across beta levels [0.0, 1.0].
- **Models**: 2-layer GCN trained with CE and InfoNCE losses.
- **Statistical Approach**:
  - Tobit Regression (handling censored convergence steps).
  - Cox Proportional Hazards (survival analysis of convergence time).
- **Interaction Term**: Loss Type × Beta.
- **Correction**: Bonferroni correction applied for multiple comparisons (n=2).

## Statistical Results

### Tobit Regression
- **Interaction Coefficient**: {coef_tobit if coef_tobit is not None else 'N/A'}
- **Corrected p-value**: {p_tobit if p_tobit is not None else 'N/A'}

### Cox Proportional Hazards
- **Interaction Coefficient**: {coef_cox if coef_cox is not None else 'N/A'}
- **Corrected p-value**: {p_cox if p_cox is not None else 'N/A'}

## Conclusion

{conclusion}

This conclusion is directly derived from the `is_significant` flag in `data/analysis_results.json`, which aggregates the corrected p-values from both the Tobit and Cox models.

## Traceability

- **Hypothesis**: InfoNCE vs CE on small-world graphs.
- **Statistical Test**: Interaction term significance in Tobit and Cox models.
- **Decision Rule**: Significant if min(p_tobit_corr, p_cox_corr) < 0.05.
- **Result**: `is_significant` = {is_significant}.

---
*Generated by code/generate_report.py (Task T039)*
"""

    # Ensure output directory exists
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, 'w') as f:
        f.write(report_content)

def main():
    project_root = Path(__file__).parent.parent
    results_path = project_root / "data" / "analysis_results.json"
    report_path = project_root / "data" / "report.md"

    if not results_path.exists():
        print(f"Error: {results_path} not found. Please run T038 first.", file=sys.stderr)
        sys.exit(1)

    try:
        results = load_analysis_results(str(results_path))
        generate_report(results, str(report_path))
        print(f"Report successfully generated at {report_path}")
    except Exception as e:
        print(f"Error generating report: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()