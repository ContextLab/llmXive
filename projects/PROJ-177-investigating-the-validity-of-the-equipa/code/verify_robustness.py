def load_statistical_results_local(results_path: Path) -> Dict[str, Any]:
    """Load statistical results from JSON file."""
    if not results_path.exists():
        raise FileNotFoundError(f"Statistical results not found at {results_path}. "
                                "Run US2 (generate_statistical_results.py) first.")
    with open(results_path, 'r') as f:
        return json.load(f)

def verify_robustness_local(results: Dict[str, Any], 
                            thresholds: List[float] = [0.01, 0.05, 0.10]) -> Dict[str, Any]:
    """
    Verify that the primary rejection decision remains identical across thresholds.
    
    The "primary rejection decision" is defined as the overall conclusion of the study:
    "Does the system reject the null hypothesis (Equipartition Theorem validity)?"
    
    We check if the rejection status (True/False) for the main hypothesis test
    (e.g., the KS test or Chi-squared test on the aggregate data) is consistent
    across all specified alpha thresholds.
    
    Args:
        results: Dictionary containing statistical test results.
        thresholds: List of alpha thresholds to check.
        
    Returns:
        Dictionary with verification results.
    """
    # Extract test results. The structure depends on US2 output.
    # Expected structure based on T025: 
    # {
    #   "bins": {
    #     "bin_id": {
    #       "tests": {
    #         "ks_test": { "statistic": ..., "p_value": ..., "rejection": ... },
    #         "chisquared_test": { ... }
    #       }
    #     }
    #   },
    #   "summary": { ... }
    # }
    
    # We need to identify the "primary" test. 
    # According to the spec, the main test is against Maxwell-Boltzmann.
    # We will check the KS test results across bins or the aggregate summary.
    # If there is a summary rejection flag, use that. Otherwise, aggregate bin results.
    
    primary_decisions = {}
    
    # Strategy: For each threshold, determine the global rejection decision.
    # Global decision: Reject if ANY bin rejects (conservative) OR if the majority rejects?
    # SC-003 says "primary rejection decision". Let's assume it means the conclusion for the 
    # overall experiment. If the summary has a 'global_rejection' field, use it.
    # Otherwise, we derive it from the bins.
    
    # Let's look for a 'summary' section first
    summary = results.get('summary', {})
    if 'global_rejection' in summary:
        # If the summary already has a rejection decision for a specific alpha,
        # we need to re-calculate for all alphas.
        # But usually summary is for a single alpha. We need to re-evaluate p-values.
        pass

    # Better approach: Re-evaluate rejection for each threshold based on p-values
    # collected in the results.
    
    # Collect all p-values for the primary test (KS test against MB)
    # We assume the structure allows iterating through bins.
    bins = results.get('bins', {})
    if not bins:
        # Maybe the results are flat?
        # Fallback: check top level keys
        pass
    
    # We need to find the p-values. Let's assume a standard structure from T025.
    # If the structure is different, we might need to adapt.
    # Let's assume: results['bins'][bin_name]['tests']['ks_test']['p_value']
    
    p_values = []
    bin_ids = []
    
    for bin_id, bin_data in bins.items():
        tests = bin_data.get('tests', {})
        if 'ks_test' in tests:
            ks_result = tests['ks_test']
            if 'p_value' in ks_result:
                p_values.append(ks_result['p_value'])
                bin_ids.append(bin_id)
        # Also check chi-squared if KS is missing?
        if 'chisquared_test' in tests:
            cs_result = tests['chisquared_test']
            if 'p_value' in cs_result:
                # If KS is missing, maybe use Chi-squared?
                # But the spec emphasizes KS for MB. Let's stick to KS if available.
                if not p_values: # Only if KS not found
                     p_values.append(cs_result['p_value'])
                     bin_ids.append(bin_id)

    if not p_values:
        # No p-values found? Maybe the structure is different.
        # Try to find any p_value in the entire dict
        def find_p_values(d, path=""):
            vals = []
            if isinstance(d, dict):
                for k, v in d.items():
                    if k == 'p_value':
                        vals.append(v)
                    else:
                        vals.extend(find_p_values(v, f"{path}.{k}"))
            elif isinstance(d, list):
                for i, v in enumerate(d):
                    vals.extend(find_p_values(v, f"{path}[{i}]"))
            return vals
        
        found_p = find_p_values(results)
        if found_p:
            p_values = found_p
        else:
            raise ValueError("No p-values found in statistical results. Cannot verify robustness.")

    # Now evaluate rejection for each threshold
    decisions = {}
    for alpha in thresholds:
        # Rejection rule: p_value < alpha
        # Primary decision: Reject if at least one bin rejects? 
        # Or Reject if the majority? 
        # The spec says "primary rejection decision". In scientific context, 
        # if the null is rejected in any significant condition, the theorem is considered invalid for that condition.
        # But "primary" might mean the overall conclusion. Let's assume "Reject if ANY bin rejects".
        # This is a strict interpretation. Alternatively, "Reject if the global test rejects".
        # Since we are aggregating bins, let's assume the "primary decision" is the rejection status 
        # of the aggregate or the consistency across the most critical bin.
        # Let's define "Primary Decision" as: Reject if the minimum p-value < alpha.
        min_p = min(p_values)
        reject = min_p < alpha
        decisions[alpha] = reject

    # Check if all decisions are identical
    decision_values = list(decisions.values())
    all_identical = len(set(decision_values)) == 1
    primary_decision = decision_values[0] if decision_values else None

    return {
        "thresholds_checked": thresholds,
        "decisions": decisions,
        "all_identical": all_identical,
        "primary_decision": primary_decision,
        "min_p_value": min(p_values) if p_values else None,
        "num_bins_analyzed": len(p_values),
        "verification_status": "PASSED" if all_identical else "FAILED"
    }

