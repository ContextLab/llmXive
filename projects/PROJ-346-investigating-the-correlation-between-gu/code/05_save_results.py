"""
Task T026: Save correlation matrix and regression results to data/processed/ with metadata.
This script loads the outputs from T021 (correlation) and T023 (regression),
bundles them with execution metadata, and writes them to the project's
data/processed directory as JSON files.
"""
import os
import sys
import json
import logging
from pathlib import Path
from datetime import datetime

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from utils import get_data_processed_path, get_logger, ensure_directory

# Setup logger
logger = get_logger("save_results")

def load_correlation_results():
    """
    Load correlation results from the file generated by code/03_correlation.py.
    Handles the case where the file might not exist (data gap scenario).
    """
    processed_dir = get_data_processed_path()
    correlation_file = processed_dir / "correlation_results.json"

    if not correlation_file.exists():
        logger.warning(f"Correlation results file not found: {correlation_file}")
        return None

    try:
        with open(correlation_file, 'r') as f:
            data = json.load(f)
        logger.info(f"Loaded correlation results from {correlation_file}")
        return data
    except json.JSONDecodeError as e:
        logger.error(f"Failed to decode correlation results JSON: {e}")
        return None

def load_regression_results():
    """
    Load regression results from the file generated by code/04_regression.py.
    Handles the case where the file might not exist (data gap scenario).
    """
    processed_dir = get_data_processed_path()
    regression_file = processed_dir / "regression_results.json"

    if not regression_file.exists():
        logger.warning(f"Regression results file not found: {regression_file}")
        return None

    try:
        with open(regression_file, 'r') as f:
            data = json.load(f)
        logger.info(f"Loaded regression results from {regression_file}")
        return data
    except json.JSONDecodeError as e:
        logger.error(f"Failed to decode regression results JSON: {e}")
        return None

def create_metadata():
    """
    Create a metadata dictionary for the final results.
    """
    return {
        "generated_at": datetime.utcnow().isoformat() + "Z",
        "project_id": "PROJ-346-investigating-the-correlation-between-gu",
        "task_id": "T026",
        "description": "Aggregated correlation and regression results with metadata",
        "labels": ["associational"],
        "note": "These results are associational only and do not imply causation."
    }

def save_with_metadata():
    """
    Main logic for T026: Load results, add metadata, and save to disk.
    """
    processed_dir = get_data_processed_path()
    ensure_directory(processed_dir)

    # Load component results
    corr_data = load_correlation_results()
    reg_data = load_regression_results()

    # If both are missing, we might be in a data gap scenario.
    # We still create a report indicating this state to satisfy T026's requirement
    # to "save results" (even if the result is "no data").
    if corr_data is None and reg_data is None:
        logger.info("No correlation or regression data found. Creating N/A report.")
        final_report = {
            "metadata": create_metadata(),
            "status": "N/A",
            "reason": "No data available for correlation or regression analysis (Data Linkage Failed or upstream steps skipped).",
            "correlation_results": None,
            "regression_results": None
        }
    else:
        # Combine results
        final_report = {
            "metadata": create_metadata(),
            "status": "success",
            "correlation_results": corr_data,
            "regression_results": reg_data
        }

    # Define output paths
    # We save to data/processed/ as per T026 description, but ensure the filename is specific
    output_path = processed_dir / "final_analysis_results.json"

    try:
        with open(output_path, 'w') as f:
            json.dump(final_report, f, indent=2)
        logger.info(f"Successfully saved final analysis results to {output_path}")
        return True
    except IOError as e:
        logger.error(f"Failed to write final analysis results: {e}")
        return False

def main():
    """
    Entry point for the script.
    """
    logger.info("Starting T026: Save results with metadata.")
    success = save_with_metadata()
    if success:
        logger.info("T026 completed successfully.")
        sys.exit(0)
    else:
        logger.error("T026 failed to write output.")
        sys.exit(1)

if __name__ == "__main__":
    main()