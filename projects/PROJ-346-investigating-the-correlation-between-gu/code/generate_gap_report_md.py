import os
import json
import logging
from pathlib import Path
from datetime import datetime
import sys

# Add project root to path if running directly
if 'code' not in sys.path:
    project_root = Path(__file__).resolve().parent.parent
    sys.path.insert(0, str(project_root))

from code.utils import get_project_root_path, get_data_processed_path, ensure_directory, setup_logger

# Configure logger
logger = setup_logger("generate_gap_report_md")

def load_gap_report_json():
    """
    Loads the data gap report JSON generated by T017a.
    """
    project_root = get_project_root_path()
    json_path = project_root / "data" / "processed" / "data_gap_report.json"
    
    if not json_path.exists():
        raise FileNotFoundError(
            f"Required input file missing: {json_path}. "
            "Ensure T017a (code/07_gap_report.py) has been executed successfully."
        )
    
    with open(json_path, 'r') as f:
        return json.load(f)

def generate_markdown_report(data):
    """
    Generates the Markdown content for the data gap report based on the JSON input.
    """
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    md_content = f"""# Data Gap Report: Gut Microbiome and Cognitive Flexibility

**Generated:** {timestamp}
**Pipeline Version:** 1.0.0

## 1. Executive Summary

**Status:** Individual-level data linkage failed.

This report documents the inability to link individual-level data between the gut microbiome cohort (Qiita Study 10313) and the cognitive flexibility cohort (UK Biobank / NHANES). Due to the absence of common participant identifiers across these datasets, direct correlational analysis (SC-001) and downstream regression models (SC-004) could not be performed.

## 2. Fallback Execution

Per the project specification, **FR-008 (Data Gap Fallback)** was triggered immediately upon detection of the linkage failure during the preprocessing stage (Task T014).

- **Action Taken:** The pipeline halted further analysis (correlation, regression, sensitivity) to prevent invalid inference.
- **Output:** This report and the structured JSON summary (`data/processed/data_gap_report.json`) were generated as the final deliverable for this execution path.

## 3. Impact on Success Criteria

The following Success Criteria are marked as **"Not Measurable"** due to the data gap:

| Criterion ID | Description | Status | Reason |
| :--- | :--- | :--- | :--- |
| **SC-001** | Compute Spearman correlation between taxa abundance and cognitive flexibility scores. | **Not Measurable** | No common participant IDs exist to compute pairwise associations. |
| **SC-004** | Fit regularized regression models (LASSO/Elastic Net) to predict cognitive scores from microbiome features. | **Not Measurable** | Dependent on SC-001; requires a merged dataset which could not be formed. |

## 4. Methodological Constraints

- **Associational Only:** No causal claims can be made. In fact, no association could be measured at all due to the data fragmentation.
- **Data Sources:** The analysis attempted to utilize Qiita Study 10313 (microbiome) and UK Biobank Field 20002 / NHANES Cognitive Battery (cognition). These cohorts operate in silos with no public cross-cohort identifier mapping available for this specific study configuration.

## 5. Conclusion

The pipeline successfully executed the FR-008 fallback protocol. While the primary research question regarding the correlation between gut microbiome composition and cognitive flexibility remains unanswered in this iteration, the system has correctly identified and reported the data infrastructure limitation. Future iterations would require a unified cohort or a verified method for individual-level data linkage.

---
*End of Report*
"""
    return md_content

def main():
    """
    Main entry point to generate the Markdown report from the JSON gap report.
    """
    try:
        # Load the JSON report generated by T017a
        gap_data = load_gap_report_json()
        logger.info(f"Loaded gap report from data/processed/data_gap_report.json")

        # Generate Markdown content
        md_content = generate_markdown_report(gap_data)

        # Define output path
        project_root = get_project_root_path()
        reports_dir = project_root / "reports"
        ensure_directory(reports_dir)
        
        output_path = reports_dir / "data_gap_report.md"

        # Write the file
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(md_content)
        
        logger.info(f"Successfully generated report: {output_path}")
        print(f"Report generated at: {output_path}")

    except FileNotFoundError as e:
        logger.error(str(e))
        raise
    except Exception as e:
        logger.error(f"An unexpected error occurred: {e}")
        raise

if __name__ == "__main__":
    main()