def load_literature_metadata(path: str) -> List[Dict[str, Any]]:
    """
    Loads the synthetic literature metadata generated by T039a.
    """
    full_path = Path(project_root) / path
    if not full_path.exists():
        raise FileNotFoundError(f"Literature metadata not found at {full_path}. "
                                "Run T039a to generate data/raw/literature_metadata.json.")
    
    with open(full_path, 'r') as f:
        data = json.load(f)
    
    if isinstance(data, dict) and "studies" in data:
        return data["studies"]
    elif isinstance(data, list):
        return data
    else:
        logger.warning("Unexpected literature metadata format. Attempting to parse as list.")
        return [data] if isinstance(data, dict) else []

def extract_entities_from_abstract(study: Dict[str, Any]) -> Dict[str, List[str]]:
    """
    Extracts key entities (Taxa, Metabolites, Markers) from a study record.
    Uses the pre-defined mappings and simple keyword matching if data is missing.
    """
    entities = {
        "taxa": [],
        "metabolites": [],
        "neural_markers": [],
        "mechanisms": []
    }

    # 1. Extract Taxa
    if "taxon_name" in study:
        entities["taxa"].append(study["taxon_name"])
    
    # 2. Map Taxa to Metabolites
    for taxon in list(entities["taxa"]):
        if taxon in TAXA_TO_METABOLITE:
            meta = TAXA_TO_METABOLITE[taxon]
            if meta not in entities["metabolites"]:
                entities["metabolites"].append(meta)

    # 3. Map Metabolites to Mechanisms
    for meta in list(entities["metabolites"]):
        if meta in METABOLITE_TO_MECHANISM:
            mech = METABOLITE_TO_MECHANISM[meta]["target"]
            if mech not in entities["mechanisms"]:
                entities["mechanisms"].append(mech)

    # 4. Map Mechanisms to Neural Markers
    for mech in list(entities["mechanisms"]):
        if "HDAC" in mech:
            markers = MECHANISM_TO_NEURAL.get("Increased histone acetylation", {}).get("target_genes", [])
            for m in markers:
                if m not in entities["neural_markers"]:
                    entities["neural_markers"].append(m)
        
        # Add general markers based on cognitive flexibility context
        if "BDNF" not in entities["neural_markers"]:
            entities["neural_markers"].append("BDNF")
        if "CREB" not in entities["neural_markers"]:
            entities["neural_markers"].append("CREB")

    return entities

def build_mechanistic_graph(studies: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Constructs a directed graph of the proposed pathway:
    Microbe -> Metabolite -> HDAC Inhibition -> Histone Acetylation -> BDNF/CREB -> Plasticity
    """
    graph = {
        "nodes": [],
        "edges": [],
        "metadata": {
            "source": "Literature Synthesis (T040)",
            "description": "Proposed cellular alphabet linking gut microbiome to cognitive flexibility",
            "limitation": "Derived from literature, not measured in current cohort (US1-US3)"
        }
    }

    node_ids = {}
    edge_list = []

    # Define static nodes for the core pathway
    core_pathway = [
        ("Butyrate", "Metabolite"),
        ("HDAC Inhibition", "Mechanism"),
        ("H3K27ac Accumulation", "Epigenetic Marker"),
        ("BDNF Expression", "Neural Marker"),
        ("Synaptic Plasticity", "Outcome")
    ]

    for name, type_ in core_pathway:
        node_id = f"{type_}_{name.replace(' ', '_')}"
        node_ids[name] = node_id
        graph["nodes"].append({
            "id": node_id,
            "label": name,
            "type": type_,
            "source": "Literature Consensus"
        })

    # Connect core pathway
    for i in range(len(core_pathway) - 1):
        src = node_ids[core_pathway[i][0]]
        dst = node_ids[core_pathway[i+1][0]]
        edge_list.append({"source": src, "target": dst, "relation": "induces"})

    # Integrate specific taxa from studies
    for study in studies:
        entities = extract_entities_from_abstract(study)
        
        for taxon in entities["taxa"]:
            taxon_id = f"Taxon_{taxon.replace(' ', '_')}"
            if taxon_id not in [n["id"] for n in graph["nodes"]]:
                graph["nodes"].append({
                    "id": taxon_id,
                    "label": taxon,
                    "type": "Microbe",
                    "source": study.get("study_id", "Unknown")
                })
            
            # Connect Taxon to Metabolite
            if taxon in TAXA_TO_METABOLITE:
                meta = TAXA_TO_METABOLITE[taxon]
                meta_id = node_ids.get(meta)
                if meta_id:
                    edge_list.append({"source": taxon_id, "target": meta_id, "relation": "produces"})

    graph["edges"] = edge_list
    return graph

