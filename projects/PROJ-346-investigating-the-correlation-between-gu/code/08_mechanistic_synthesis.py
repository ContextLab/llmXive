def main():
    """
    Main entry point for T040 and T041.
    1. Load literature metadata (T039a output).
    2. Extract entities and build graph (T040).
    3. Generate the hypothesis report (T041).
    """
    logger.info("Starting Mechanistic Synthesis (T040/T041)...")
    
    try:
        # 1. Load Data
        logger.info(f"Loading literature metadata from {LITERATURE_INPUT_PATH}...")
        studies = load_literature_metadata(LITERATURE_INPUT_PATH)
        logger.info(f"Loaded {len(studies)} studies.")

        if not studies:
            logger.error("No studies found in literature metadata. Cannot proceed.")
            sys.exit(1)

        # 2. Build Graph (T040)
        logger.info("Building mechanistic graph...")
        graph = build_mechanistic_graph(studies)
        
        # Save graph to JSON (intermediate artifact)
        graph_path = Path(project_root) / OUTPUT_GRAPH_PATH
        ensure_directory(graph_path.parent)
        with open(graph_path, 'w') as f:
            json.dump(graph, f, indent=2)
        logger.info(f"Mechanistic graph saved to {graph_path}")

        # 3. Generate Report (T041)
        logger.info("Generating Mechanistic Hypothesis Report...")
        generate_mechanistic_hypothesis_report(graph, OUTPUT_REPORT_PATH)
        
        logger.info("Mechanistic Synthesis completed successfully.")

    except FileNotFoundError as e:
        logger.error(f"Missing required input file: {e}")
        logger.error("Ensure T039a has been run to generate data/raw/literature_metadata.json.")
        sys.exit(1)
    except Exception as e:
        logger.error(f"An error occurred during synthesis: {e}")
        import traceback
        logger.error(traceback.format_exc())
        sys.exit(1)

if __name__ == "__main__":
    main()
