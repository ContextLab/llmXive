"""
Contract test for the TimeSeries schema.
Ensures the TimeSeries model validates data correctly.
"""
import pytest
import pandas as pd
from pathlib import Path
from contracts.timeseries import TimeSeries

# Project root detection for test execution
PROJECT_ROOT = Path(__file__).parent.parent.parent

def _load_aligned_monthly_data():
    """
    Loads the real aligned_monthly.csv generated by the preprocessing pipeline.
    Raises FileNotFoundError or ValueError if the file is missing or malformed.
    """
    data_path = PROJECT_ROOT / "data" / "processed" / "aligned_monthly.csv"
    if not data_path.exists():
        raise FileNotFoundError(f"Contract test failed: Required data file not found at {data_path}. "
                                "Ensure T018 (preprocessing) has been executed successfully.")
    
    df = pd.read_csv(data_path)
    
    # Validate basic structure expected by the contract
    required_columns = ['date', 'gdelt_sentiment_mean', 'fred_gdp', 'fred_unrate']
    missing_cols = [col for col in required_columns if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Contract test failed: Missing required columns in {data_path}: {missing_cols}")
    
    # Ensure date column is parsed correctly
    if not pd.api.types.is_datetime64_any_dtype(df['date']):
        try:
            df['date'] = pd.to_datetime(df['date'])
        except Exception as e:
            raise ValueError(f"Contract test failed: Could not parse 'date' column as datetime: {e}")
    
    return df

def test_timeseries_valid_data():
    """Test that the TimeSeries model validates synthetic data correctly (baseline)."""
    ts = TimeSeries(
        variable_name="GDP",
        source="FRED",
        frequency="monthly",
        unit="billions",
        data=[
            {"date": "2020-01-01", "value": 100.5},
            {"date": "2020-02-01", "value": 101.2}
        ]
    )
    assert ts.variable_name == "GDP"
    assert len(ts.get_dates()) == 2
    assert ts.get_values() == [100.5, 101.2]

def test_timeseries_missing_keys():
    """Test that data missing 'date' or 'value' fails."""
    with pytest.raises((ValueError, TypeError)):
        TimeSeries(
            variable_name="Test",
            source="TestSource",
            frequency="monthly",
            unit="units",
            data=[{"date": "2020-01-01"}]  # Missing 'value'
        )

def test_timeseries_empty_list():
    """Test that empty data list fails."""
    with pytest.raises((ValueError, TypeError)):
        TimeSeries(
            variable_name="Test",
            source="TestSource",
            frequency="monthly",
            unit="units",
            data=[]
        )

def test_contract_aligned_monthly_gdp():
    """
    Contract test: Verify the 'GDP' time series in aligned_monthly.csv matches the TimeSeries schema.
    """
    df = _load_aligned_monthly_data()
    
    # Construct TimeSeries object from real data
    data_points = [
        {"date": row['date'].strftime('%Y-%m-%d'), "value": row['fred_gdp']}
        for _, row in df.iterrows()
        if pd.notna(row['fred_gdp'])
    ]
    
    if not data_points:
        pytest.fail("Contract test failed: No valid GDP data points found in aligned_monthly.csv")

    ts = TimeSeries(
        variable_name="GDP",
        source="FRED",
        frequency="monthly",
        unit="billions_chained_2017",
        data=data_points
    )
    
    assert ts.variable_name == "GDP"
    assert len(ts.get_dates()) == len(data_points)
    assert all(isinstance(v, (int, float)) for v in ts.get_values())

