def load_raw_data() -> Dict[str, pd.DataFrame]:
    """
    Load raw data files generated by data_ingestion.py.
    
    Returns:
        Dictionary with keys 'sentiment', 'gdp', 'unrate' containing DataFrames.
    """
    data = {}
    
    # Load GDELT sentiment
    sentiment_path = RAW_DATA_DIR / "gdelt_sentiment.csv"
    if not sentiment_path.exists():
        raise FileNotFoundError(f"Raw sentiment data not found: {sentiment_path}")
    data['sentiment'] = pd.read_csv(sentiment_path, parse_dates=['date'])
    logger.info(f"Loaded sentiment data: {len(data['sentiment'])} rows")
    
    # Load FRED GDP
    gdp_path = RAW_DATA_DIR / "fred_gdp.csv"
    if not gdp_path.exists():
        raise FileNotFoundError(f"Raw GDP data not found: {gdp_path}")
    data['gdp'] = pd.read_csv(gdp_path, parse_dates=['date'])
    logger.info(f"Loaded GDP data: {len(data['gdp'])} rows")
    
    # Load FRED Unemployment Rate
    unrate_path = RAW_DATA_DIR / "fred_unrate.csv"
    if not unrate_path.exists():
        raise FileNotFoundError(f"Raw unemployment data not found: {unrate_path}")
    data['unrate'] = pd.read_csv(unrate_path, parse_dates=['date'])
    logger.info(f"Loaded unemployment data: {len(data['unrate'])} rows")
    
    return data


def resample_sentiment_to_monthly(df: pd.DataFrame) -> pd.DataFrame:
    """
    Resample daily sentiment data to monthly averages.
    
    Args:
        df: DataFrame with 'date' column and sentiment score columns.
        
    Returns:
        Monthly aggregated DataFrame.
    """
    df = df.copy()
    df.set_index('date', inplace=True)
    
    # Resample to monthly, taking mean of daily values
    monthly_df = df.resample('ME').mean()
    
    # Reset index to make 'date' a column again
    monthly_df.reset_index(inplace=True)
    monthly_df.rename(columns={'index': 'date'}, inplace=True)
    
    logger.info(f"Resampled sentiment to monthly: {len(monthly_df)} rows")
    return monthly_df


def resample_macro_to_monthly(df: pd.DataFrame, column: str) -> pd.DataFrame:
    """
    Resample macroeconomic data to monthly frequency.
    
    Args:
        df: DataFrame with 'date' column.
        column: Name of the value column to resample.
        
    Returns:
        Monthly DataFrame with the specified column.
    """
    df = df.copy()
    df.set_index('date', inplace=True)
    
    # Resample to monthly, taking mean (for GDP growth) or last (for rate)
    # Assuming GDP is quarterly growth rate -> monthly mean
    # Assuming Unrate is monthly rate -> monthly last (no change needed usually)
    # We'll use mean for consistency unless specified otherwise
    monthly_df = df.resample('ME')[column].mean()
    
    # Forward fill any NaNs that might result from irregular reporting
    monthly_df = monthly_df.ffill()
    
    monthly_df.reset_index(inplace=True)
    monthly_df.rename(columns={'index': 'date'}, inplace=True)
    
    logger.info(f"Resampled {column} to monthly: {len(monthly_df)} rows")
    return monthly_df


def interpolate_missing(df: pd.DataFrame, method: str = 'linear') -> pd.DataFrame:
    """
    Interpolate missing values in the DataFrame.
    
    Args:
        df: DataFrame with potential NaN values.
        method: Interpolation method ('linear', 'forward_fill', 'back_fill').
        
    Returns:
        DataFrame with interpolated values.
    """
    df = df.copy()
    
    # Identify numeric columns for interpolation
    numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
    
    if method == 'linear':
        df[numeric_cols] = df[numeric_cols].interpolate(method='linear')
    elif method == 'forward_fill':
        df[numeric_cols] = df[numeric_cols].ffill()
    elif method == 'back_fill':
        df[numeric_cols] = df[numeric_cols].bfill()
    else:
        raise ValueError(f"Unknown interpolation method: {method}")
    
    # Log interpolation stats
    nan_counts_before = df[numeric_cols].isna().sum()
    nan_counts_after = df[numeric_cols].isna().sum()
    logger.info(f"Interpolation ({method}): filled {nan_counts_before.sum() - nan_counts_after.sum()} values")
    
    return df


def calculate_missing_rate(df: pd.DataFrame) -> Dict[str, float]:
    """
    Calculate the missing data rate for each column.
    
    Args:
        df: DataFrame to analyze.
        
    Returns:
        Dictionary mapping column names to missing rates (0.0 to 1.0).
    """
    total_rows = len(df)
    if total_rows == 0:
        return {}
    
    missing_rates = {}
    for col in df.columns:
        if col == 'date':
            continue
        if df[col].dtype in ['object', 'datetime64[ns]']:
            continue
        
        missing_count = df[col].isna().sum()
        missing_rates[col] = missing_count / total_rows
    
    return missing_rates


def flag_low_confidence(df: pd.DataFrame, 
                        confidence_col: str = 'confidence',
                        sample_col: str = 'sample_size') -> pd.DataFrame:
    """
    Flag rows with low confidence or insufficient sample size.
    
    Args:
        df: DataFrame with confidence and sample size columns.
        confidence_col: Name of the confidence column.
        sample_col: Name of the sample size column.
        
    Returns:
        DataFrame with a 'low_confidence_flag' boolean column.
    """
    df = df.copy()
    
    # Ensure columns exist, create dummy if not
    if confidence_col not in df.columns:
        logger.warning(f"Confidence column '{confidence_col}' not found. Creating dummy column.")
        df[confidence_col] = 1.0
    
    if sample_col not in df.columns:
        logger.warning(f"Sample size column '{sample_col}' not found. Creating dummy column.")
        df[sample_col] = 1000
    
    # Apply flagging logic
    df['low_confidence_flag'] = (
        (df[confidence_col] < CONFIDENCE_THRESHOLD) | 
        (df[sample_col] < MIN_SAMPLE_SIZE)
    )
    
    flagged_count = df['low_confidence_flag'].sum()
    logger.info(f"Flagged {flagged_count} rows as low confidence")
    
    return df


def apply_rolling_average(df: pd.DataFrame, column: str, window: int = 3) -> pd.DataFrame:
    """
    Apply a rolling average to smooth sentiment noise.
    
    Args:
        df: DataFrame with the target column.
        column: Name of the column to smooth.
        window: Rolling window size (in months).
        
    Returns:
        DataFrame with an additional '_smoothed' column.
    """
    df = df.copy()
    
    if column not in df.columns:
        raise KeyError(f"Column '{column}' not found in DataFrame")
    
    smooth_col = f"{column}_smoothed"
    df[smooth_col] = df[column].rolling(window=window, min_periods=1).mean()
    
    logger.info(f"Applied rolling average (window={window}) to '{column}'")
    return df


def run_adf_test(series: pd.Series, max_lag: int = None) -> Dict[str, Any]:
    """
    Run the Augmented Dickey-Fuller stationarity test.
    
    Args:
        series: Time series data to test.
        max_lag: Maximum lag order to consider (None for auto).
        
    Returns:
        Dictionary with test results (statistic, p-value, critical values).
    """
    # Drop NaNs
    clean_series = series.dropna()
    
    if len(clean_series) < 10:
        logger.warning(f"Series too short for ADF test (len={len(clean_series)})")
        return {
            'statistic': np.nan,
            'pvalue': np.nan,
            'critical_values': {},
            'is_stationary': False,
            'note': 'Series too short'
        }
    
    try:
        result = adfuller(clean_series, maxlag=max_lag, autolag='AIC')
        
        return {
            'statistic': float(result[0]),
            'pvalue': float(result[1]),
            'critical_values': {
                '1%': float(result[4]['1%']),
                '5%': float(result[4]['5%']),
                '10%': float(result[4]['10%'])
            },
            'is_stationary': result[1] < 0.05,  # Reject null hypothesis if p < 0.05
            'note': 'Test completed successfully'
        }
    except Exception as e:
        logger.error(f"ADF test failed: {e}")
        return {
            'statistic': np.nan,
            'pvalue': np.nan,
            'critical_values': {},
            'is_stationary': False,
            'note': f'Error: {str(e)}'
        }


def align_and_preprocess() -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """
    Main preprocessing pipeline:
    1. Load raw data
    2. Resample to monthly frequency
    3. Merge on date
    4. Interpolate missing values
    5. Calculate missing rates
    6. Flag low confidence
    7. Apply rolling average
    8. Run stationarity checks
    
    Returns:
        Tuple of (processed DataFrame, quality log dictionary)
    """
    logger.info("Starting preprocessing pipeline...")
    
    # 1. Load raw data
    raw_data = load_raw_data()
    
    # 2. Resample to monthly
    sentiment_monthly = resample_sentiment_to_monthly(raw_data['sentiment'])
    gdp_monthly = resample_macro_to_monthly(raw_data['gdp'], 'value')
    unrate_monthly = resample_macro_to_monthly(raw_data['unrate'], 'value')
    
    # 3. Merge on date
    merged_df = sentiment_monthly.merge(gdp_monthly, on='date', how='outer')
    merged_df = merged_df.merge(unrate_monthly, on='date', how='outer')
    
    # Rename columns for clarity
    merged_df.rename(columns={
        'value_x': 'gdp_growth',
        'value_y': 'unemployment_rate'
    }, inplace=True)
    
    # 4. Interpolate missing values
    # Macro data: linear interpolation
    merged_df['gdp_growth'] = merged_df['gdp_growth'].interpolate(method='linear')
    merged_df['unemployment_rate'] = merged_df['unemployment_rate'].interpolate(method='linear')
    
    # Sentiment: forward fill (conservative approach)
    if 'sentiment_score' in merged_df.columns:
        merged_df['sentiment_score'] = merged_df['sentiment_score'].ffill()
    
    # 5. Calculate missing rates
    missing_rates = calculate_missing_rate(merged_df)
    
    # Flag if any rate > 5%
    quality_flags = {}
    for col, rate in missing_rates.items():
        if rate > MISSING_RATE_THRESHOLD:
            quality_flags[col] = f"High missing rate: {rate:.2%}"
            logger.warning(f"Column '{col}' has high missing rate: {rate:.2%}")
    
    # 6. Flag low confidence (if confidence data exists)
    if 'confidence' in merged_df.columns or 'sample_size' in merged_df.columns:
        merged_df = flag_low_confidence(merged_df)
    
    # 7. Apply rolling average to sentiment
    if 'sentiment_score' in merged_df.columns:
        merged_df = apply_rolling_average(merged_df, 'sentiment_score', window=3)
    
    # 8. Run stationarity checks
    stationarity_results = {}
    for col in ['sentiment_score', 'gdp_growth', 'unemployment_rate']:
        if col in merged_df.columns:
            stationarity_results[col] = run_adf_test(merged_df[col])
    
    # Prepare quality log
    quality_log = {
        'generated_at': datetime.now().isoformat(),
        'total_rows': len(merged_df),
        'missing_rates': missing_rates,
        'quality_flags': quality_flags,
        'stationarity_tests': stationarity_results,
        'interpolation_methods': {
            'gdp_growth': 'linear',
            'unemployment_rate': 'linear',
            'sentiment_score': 'forward_fill'
        }
    }
    
    logger.info(f"Preprocessing complete. Output rows: {len(merged_df)}")
    return merged_df, quality_log


def save_outputs(df: pd.DataFrame, quality_log: Dict[str, Any]) -> None:
    """
    Save the processed DataFrame and quality log to disk.
    
    Args:
        df: Processed DataFrame.
        quality_log: Quality log dictionary.
    """
    # Save aligned monthly data
    output_path = PROCESSED_DATA_DIR / "aligned_monthly.csv"
    df.to_csv(output_path, index=False)
    logger.info(f"Saved processed data to {output_path}")
    
    # Save quality log
    log_path = PROCESSED_DATA_DIR / "data_quality_log.json"
    with open(log_path, 'w') as f:
        json.dump(quality_log, f, indent=2, default=str)
    logger.info(f"Saved quality log to {log_path}")


def main():
    """Main entry point for preprocessing."""
    logger.info("Preprocessing module started")
    
    try:
        # Run pipeline
        df, quality_log = align_and_preprocess()
        
        # Save outputs
        save_outputs(df, quality_log)
        
        logger.info("Preprocessing completed successfully")
        
    except FileNotFoundError as e:
        logger.error(f"Missing raw data: {e}")
        raise
    except Exception as e:
        logger.error(f"Preprocessing failed: {e}")
        raise


if __name__ == "__main__":
    main()