import json
import os
import re
from pathlib import Path
from typing import Any, Dict, List, Optional

# Project utilities
from utils.config import get_path, ensure_dirs_exist

# Optional JSON schema validation (requires jsonschema, which is in the base environment)
try:
    from jsonschema import validate, ValidationError
except ImportError:  # pragma: no cover
    # jsonschema is part of the default environment; this is a safeguard.
    validate = None
    ValidationError = Exception

# ---------------------------------------------------------------------------
# Helper functions
# ---------------------------------------------------------------------------

def load_injected_data(input_path: Optional[Path] = None) -> List[Dict[str, Any]]:
    """
    Load the injected failure subset generated by the ``injector`` step.

    Parameters
    ----------
    input_path: Optional[Path]
        Path to the JSON‑Lines file. If ``None`` the default location
        ``data/derived/implicit_failure_subset.jsonl`` is used.

    Returns
    -------
    List[Dict[str, Any]]
        List of task dictionaries.
    """
    if input_path is None:
        input_path = get_path('data/derived/implicit_failure_subset.jsonl')

    if not input_path.exists():
        raise FileNotFoundError(f"Injected data not found at {input_path}")

    data = []
    with input_path.open('r', encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if line:
                data.append(json.loads(line))
    return data


def extract_failure_signatures(data: List[Dict[str, Any]]) -> List[Dict[str, str]]:
    """
    Extract failure patterns from the injected data and map them to deterministic
    tool identifiers.

    The expected input rows contain the keys ``injected_error_pattern`` and
    ``injected_error_type`` (populated by ``dataset.injector``).  For each unique
    error type we create a deterministic ``tool_id`` and store the pattern string.

    Returns
    -------
    List[Dict[str, str]]
        Each entry conforms to the JSON schema required by downstream agents:
        {
            "tool_id": "<deterministic_id>",
            "pattern_string": "<error_pattern>",
            "recovery_strategy": "replan"
        }
    """
    signatures: Dict[str, Dict[str, str]] = {}

    for item in data:
        # Only consider records where we injected an error pattern.
        if item.get('injected_error_pattern'):
            error_type = item.get('injected_error_type', 'unknown_error')
            # Deterministic tool identifier – stable across runs.
            tool_id = f"tool_{hash(error_type) % 1000}"

            if tool_id not in signatures:
                signatures[tool_id] = {
                    'tool_id': tool_id,
                    'pattern_string': error_type,
                    'recovery_strategy': 'replan'
                }

    # Return a list sorted by tool_id for deterministic ordering.
    return [signatures[k] for k in sorted(signatures.keys())]


def build_failure_index(signatures: List[Dict[str, str]]) -> Dict[str, str]:
    """
    Build a simple lookup dictionary from ``tool_id`` to the associated pattern
    string.  This structure is convenient for the augmented agent which performs
    an exact‑match (or ``fnmatch``) against the stored pattern.

    Returns
    -------
    Dict[str, str]
        Mapping ``tool_id`` → ``pattern_string``.
    """
    return {sig['tool_id']: sig['pattern_string'] for sig in signatures}


def _validate_schema(index_data: List[Dict[str, str]]) -> None:
    """
    Validate the generated index against the required JSON schema.
    Raises ``jsonschema.ValidationError`` if the data do not conform.
    """
    if validate is None:
        # If jsonschema is unexpectedly unavailable, skip validation – the
        # downstream code will still function, but we log a warning.
        print("Warning: jsonschema not installed – skipping schema validation.")
        return

    schema = {
        "type": "array",
        "items": {
            "type": "object",
            "properties": {
                "tool_id": {"type": "string"},
                "pattern_string": {"type": "string"},
                "recovery_strategy": {
                    "type": "string",
                    "enum": ["replan"]
                }
            },
            "required": ["tool_id", "pattern_string", "recovery_strategy"],
            "additionalProperties": False
        }
    }

    try:
        validate(instance=index_data, schema=schema)
    except ValidationError as exc:  # pragma: no cover
        raise ValueError(f"Failure‑signature index does not match schema: {exc}") from exc


def save_index(index_data: List[Dict[str, str]], output_path: Optional[Path] = None) -> Path:
    """
    Persist the failure‑signature index to ``data/derived/failure_signatures.json``.

    Parameters
    ----------
    index_data: List[Dict[str, str]]
        The list of signature dictionaries produced by ``extract_failure_signatures``.
    output_path: Optional[Path]
        Destination path; defaults to the canonical location.

    Returns
    -------
    Path
        Path to the written JSON file.
    """
    if output_path is None:
        output_path = get_path('data/derived/failure_signatures.json')

    # Ensure the target directory exists.
    ensure_dirs_exist(output_path.parent)

    # Validate before writing.
    _validate_schema(index_data)

    with output_path.open('w', encoding='utf-8') as f:
        json.dump(index_data, f, indent=2, ensure_ascii=False)

    return output_path


def main() -> None:
    """
    CLI entry point: load the injected subset, extract signatures, validate,
    and write the JSON index.
    """
    injected_data = load_injected_data()
    signatures = extract_failure_signatures(injected_data)
    output_file = save_index(signatures)
    print(f"Failure signatures index saved to: {output_file}")


if __name__ == "__main__":
    main()
