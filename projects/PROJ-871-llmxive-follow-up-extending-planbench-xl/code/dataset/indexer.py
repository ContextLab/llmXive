"""
Failure Signature Indexer.
Parses injected data and builds a signature index.

This module reads the `implicit_failure_subset.jsonl` generated by the injector,
extracts the specific error patterns injected into tool outputs, maps them to
the tool identifiers that produced them, and saves a JSON index for the
AugmentedAgent to consult during execution.
"""
import json
import os
from pathlib import Path
from typing import Any, Dict, List, Optional
from utils.config import get_path

def load_injected_data(input_path: Optional[str] = None) -> List[Dict[str, Any]]:
    """
    Loads the injected failure subset from JSONL.
    
    Args:
        input_path: Optional path override. Defaults to config "implicit_failure_subset".
        
    Returns:
        List of task dictionaries.
        
    Raises:
        FileNotFoundError: If the input file does not exist.
        json.JSONDecodeError: If the file contains invalid JSON lines.
    """
    if input_path is None:
        input_path = str(get_path("implicit_failure_subset"))
    
    if not os.path.exists(input_path):
        raise FileNotFoundError(
            f"Input file not found: {input_path}. "
            "Ensure T009a (injector) has run successfully."
        )
    
    tasks = []
    with open(input_path, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                tasks.append(json.loads(line))
            except json.JSONDecodeError as e:
                raise json.JSONDecodeError(
                    f"Invalid JSON at line {line_num} in {input_path}", e.doc, e.pos
                )
    return tasks

def extract_failure_signatures(tasks: List[Dict[str, Any]]) -> Dict[str, Dict[str, str]]:
    """
    Extracts failure patterns and maps them to tool identifiers.
    
    Iterates through tasks that have the `injected_error` flag set to True.
    It inspects the `tool_outputs` list for strings containing "ERROR".
    
    The output schema is a dictionary where keys are the error pattern strings
    and values are objects containing `tool_id` and `recovery_strategy`.
    
    Schema:
    {
        "ERROR: silent_tool_failure": {
            "tool_id": "tool_name_from_task",
            "recovery_strategy": "replan"
        },
        ...
    }
    
    Args:
        tasks: List of task dictionaries from the injected subset.
        
    Returns:
        Dictionary mapping error patterns to metadata.
    """
    signatures: Dict[str, Dict[str, str]] = {}
    
    for task in tasks:
        # Only process tasks where we explicitly injected an error
        if not task.get("injected_error", False):
            continue
        
        tool_outputs = task.get("tool_outputs", [])
        # We assume the task structure includes a 'tool_id' or 'tool_name' 
        # that identifies the tool used for this specific task instance,
        # or we infer it from the context if available.
        # Based on PlanBench-XL typical structure, the tool might be identified 
        # in the task definition or the output itself.
        # We will use the task's 'tool_id' if present, otherwise default to a generic
        # identifier derived from the error context or a placeholder if strictly necessary,
        # but the requirement says "map them to tool identifiers".
        # Assuming the task object has a 'tool_id' field or similar.
        # If not, we look at the output string to see if it contains the tool name.
        
        task_tool_id = task.get("tool_id", task.get("tool_name", "unknown_tool"))
        
        for output in tool_outputs:
            if isinstance(output, str) and "ERROR" in output:
                pattern = output.strip()
                
                # If we already have this pattern, we can verify consistency
                # or just overwrite (assuming deterministic injection).
                if pattern not in signatures:
                    signatures[pattern] = {
                        "tool_id": task_tool_id,
                        "recovery_strategy": "replan"
                    }
                else:
                    # Optional: Verify that the tool_id matches if we see the same error again
                    # If mismatches occur, we might need a list of tools, but for this spec:
                    # "JSON Schema: {"tool_id": "pattern", "recovery_strategy": "replan"}"
                    # implies a single mapping. We trust the deterministic injection.
                    pass
                    
    return signatures

def build_failure_index(signatures: Dict[str, Dict[str, str]]) -> Dict[str, Dict[str, str]]:
    """
    Builds the final failure index structure.
    
    Currently, this is a pass-through as the signature extraction already
    produces the desired structure.
    
    Args:
        signatures: Dictionary of patterns to metadata.
        
    Returns:
        The same dictionary, ready for serialization.
    """
    return signatures

def save_index(index: Dict[str, Dict[str, str]], output_path: Optional[str] = None) -> str:
    """
    Saves the failure index to a JSON file.
    
    Args:
        index: The failure index dictionary.
        output_path: Optional path override. Defaults to config "failure_signatures".
        
    Returns:
        The absolute path to the saved file.
        
    Raises:
        IOError: If the file cannot be written.
    """
    if output_path is None:
        output_path = str(get_path("failure_signatures"))
    
    # Ensure directory exists
    output_dir = os.path.dirname(output_path)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(index, f, indent=2)
    
    return output_path

def main():
    """
    Main entry point for building the index.
    
    Orchestrates loading, extraction, building, and saving.
    """
    print("Loading injected failure subset...")
    try:
        tasks = load_injected_data()
    except FileNotFoundError as e:
        print(f"Error: {e}")
        print("Please ensure T009a (injector) has run and generated data/derived/implicit_failure_subset.jsonl")
        raise
    
    print(f"Loaded {len(tasks)} tasks.")
    
    print("Extracting failure signatures...")
    signatures = extract_failure_signatures(tasks)
    
    print(f"Found {len(signatures)} unique failure patterns.")
    
    print("Building failure index...")
    index = build_failure_index(signatures)
    
    print("Saving index...")
    path = save_index(index)
    print(f"Failure index saved to {path}")
    
    # Verification
    if not index:
        print("Warning: The index is empty. No error patterns were found in the injected subset.")
        print("This might indicate the injector did not successfully inject errors or the subset is empty.")
    else:
        print("Index construction complete.")

if __name__ == "__main__":
    main()
