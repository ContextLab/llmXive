"""
Contract test for data loader (US1).
Verifies PlanBench-XL subset loading from data/derived/implicit_failure_subset.jsonl.
"""
import json
import os
import sys
import tempfile
import shutil
from pathlib import Path
from typing import List, Dict, Any

import pytest

# Add project root to path for imports
# The test is run from the project root or via pytest discovery
project_root = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(project_root))

from code.dataset.loader import load_injected_data
from code.utils.config import get_path


class TestLoaderContract:
    """Contract tests for the data loader functionality."""

    @pytest.fixture(autouse=True)
    def setup(self):
        """Ensure required data files exist before running tests."""
        # The test relies on the existence of the implicit_failure_subset.jsonl
        # which should be generated by T009a. If it doesn't exist, the test
        # will fail, indicating the prerequisite task is not complete.
        self.data_path = get_path("derived", "implicit_failure_subset.jsonl")
        assert os.path.exists(self.data_path), (
            f"Prerequisite data file missing: {self.data_path}. "
            "Ensure T009a (injector) has been executed successfully."
        )

    def test_load_injected_data_returns_list(self):
        """Contract: load_injected_data must return a list of dictionaries."""
        data = load_injected_data()
        
        assert isinstance(data, list), (
            f"Expected load_injected_data to return a list, got {type(data)}"
        )
        assert len(data) > 0, "Expected non-empty dataset"

    def test_load_injected_data_schema(self):
        """Contract: Each record must contain required fields including injected_error flag."""
        data = load_injected_data()
        
        required_fields = [
            "task_id", 
            "ground_truth", 
            "injected_error"
        ]
        
        for i, record in enumerate(data):
            assert isinstance(record, dict), f"Record {i} is not a dictionary"
            
            for field in required_fields:
                assert field in record, (
                    f"Record {i} missing required field: '{field}'. "
                    f"Available keys: {list(record.keys())}"
                )
            
            # Verify injected_error is a boolean
            assert isinstance(record["injected_error"], bool), (
                f"Record {i}: 'injected_error' must be boolean, got {type(record['injected_error'])}"
            )

    def test_load_injected_data_contains_injected_failures(self):
        """Contract: The subset must contain records with injected_error=True."""
        data = load_injected_data()
        
        injected_records = [r for r in data if r.get("injected_error", False)]
        
        assert len(injected_records) > 0, (
            "No records with 'injected_error=True' found. "
            "This suggests T009a (injector) did not run or failed to inject errors."
        )

    def test_load_injected_data_preserves_original_fields(self):
        """Contract: Original PlanBench-XL fields must be preserved."""
        data = load_injected_data()
        
        # PlanBench-XL typically has these core fields
        expected_original_fields = ["task_id", "ground_truth", "goal", "tools"]
        
        for record in data:
            for field in expected_original_fields:
                assert field in record, (
                    f"Original field '{field}' missing from record. "
                    f"Available keys: {list(record.keys())}"
                )

    def test_load_injected_data_file_format(self):
        """Contract: Verify the underlying file is valid JSONL."""
        file_path = get_path("derived", "implicit_failure_subset.jsonl")
        
        with open(file_path, "r", encoding="utf-8") as f:
            line_count = 0
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    json.loads(line)
                    line_count += 1
                except json.JSONDecodeError as e:
                    pytest.fail(f"Invalid JSON on line {line_count + 1}: {e}")
            
            assert line_count > 0, "File appears to be empty or contains only whitespace"