# Requirement Threshold for FR-009
# Based on typical social science validation, we require a significant positive correlation
# and a minimum effect size.
FR_009_MIN_CORRELATION = 0.3
FR_009_P_VALUE_THRESHOLD = 0.05

def load_correlation_data(correlation_file_path: str) -> Optional[Dict[str, Any]]:
    """
    Load the raw correlation data generated by T017d.
    """
    path = Path(correlation_file_path)
    if not path.exists():
        logger.error(f"Correlation data file not found: {path}")
        return None

    try:
        with open(path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        logger.info(f"Successfully loaded correlation data from {path}")
        return data
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse JSON in {path}: {e}")
        return None
    except Exception as e:
        logger.error(f"Unexpected error loading {path}: {e}")
        return None

def validate_correlation_against_threshold(correlation_data: Dict[str, Any]) -> Dict[str, Any]:
    """
    Validate the correlation results against FR-009 requirements.
    Returns a dictionary with validation status and details.
    """
    # Extract correlation value (assuming the key is 'authority_density_correlation' or similar)
    # The structure depends on T017d output. We assume a structure like:
    # {'pearson_r': 0.XX, 'p_value': 0.XX, 'n': XX, ...}
    
    pearson_r = correlation_data.get('pearson_r')
    p_value = correlation_data.get('p_value')
    sample_size = correlation_data.get('n')

    if pearson_r is None or p_value is None:
        logger.error("Correlation data missing required fields (pearson_r or p_value).")
        return {
            'passed': False,
            'reason': 'Missing required correlation metrics in input data.',
            'pearson_r': pearson_r,
            'p_value': p_value
        }

    # Check against thresholds
    correlation_threshold_met = pearson_r >= FR_009_MIN_CORRELATION
    significance_met = p_value <= FR_009_P_VALUE_THRESHOLD

    passed = correlation_threshold_met and significance_met

    result = {
        'passed': passed,
        'pearson_r': pearson_r,
        'p_value': p_value,
        'sample_size': sample_size,
        'correlation_threshold': FR_009_MIN_CORRELATION,
        'significance_threshold': FR_009_P_VALUE_THRESHOLD,
        'correlation_threshold_met': correlation_threshold_met,
        'significance_met': significance_met,
        'reason': 'Validation passed' if passed else (
            'Failed: Correlation too low' if not correlation_threshold_met else
            'Failed: Not statistically significant'
        )
    }
    
    logger.info(f"Validation Result: {'PASS' if passed else 'FAIL'}")
    logger.info(f"  Pearson r: {pearson_r:.4f} (Threshold: {FR_009_MIN_CORRELATION})")
    logger.info(f"  P-value: {p_value:.4f} (Threshold: {FR_009_P_VALUE_THRESHOLD})")
    
    return result

def compute_p_value_and_ci(correlation_data: Dict[str, Any]) -> Dict[str, Any]:
    """
    Compute confidence intervals for the correlation if not present in input.
    Uses Fisher's z-transformation.
    """
    r = correlation_data.get('pearson_r')
    n = correlation_data.get('n')

    if r is None or n is None or n < 3:
        logger.warning("Cannot compute CI: missing r or insufficient sample size.")
        return {}

    # Fisher's z-transformation
    z = 0.5 * np.log((1 + r) / (1 - r))
    se = 1 / np.sqrt(n - 3)
    
    # 95% CI for z
    z_lower = z - 1.96 * se
    z_upper = z + 1.96 * se
    
    # Transform back to r
    r_lower = (np.exp(2 * z_lower) - 1) / (np.exp(2 * z_lower) + 1)
    r_upper = (np.exp(2 * z_upper) - 1) / (np.exp(2 * z_upper) + 1)

    return {
        'r_95_ci_lower': r_lower,
        'r_95_ci_upper': r_upper,
        'method': "Fisher's z-transformation"
    }

def generate_validation_report(validation_result: Dict[str, Any], output_path: str):
    """
    Generate the markdown report for the validation gate.
    """
    report_lines = [
        "# Annotation Correlation Validation Report",
        "",
        f"**Generated**: {pd.Timestamp.now().isoformat()}",
        "",
        "## Requirement: FR-009",
        "This report validates the correlation between automated linguistic features and human-perceived authority density.",
        "",
        "## Thresholds",
        f"- Minimum Correlation (r): {FR_009_MIN_CORRELATION}",
        f"- Significance Level (p): {FR_009_P_VALUE_THRESHOLD}",
        "",
        "## Results",
        f"- **Status**: {'✅ PASS' if validation_result['passed'] else '❌ FAIL'}",
        f"- **Pearson Correlation (r)**: {validation_result['pearson_r']:.4f}",
        f"- **P-value**: {validation_result['p_value']:.4f}",
        f"- **Sample Size (n)**: {validation_result['sample_size']}",
        "",
        "## Detailed Analysis",
        f"- Correlation Threshold Met: {'Yes' if validation_result['correlation_threshold_met'] else 'No'}",
        f"- Significance Threshold Met: {'Yes' if validation_result['significance_met'] else 'No'}",
        "",
        "## Conclusion",
        f"The pipeline {'successfully meets' if validation_result['passed'] else 'fails to meet'} the requirements for FR-009.",
        f"Reason: {validation_result['reason']}",
        ""
    ]

    # Add CI if computed
    if 'r_95_ci_lower' in validation_result:
        report_lines.extend([
            "## Confidence Intervals",
            f"- 95% CI for r: [{validation_result['r_95_ci_lower']:.4f}, {validation_result['r_95_ci_upper']:.4f}]",
            f"- Method: {validation_result.get('method', 'N/A')}",
            ""
        ])

    report_content = "\n".join(report_lines)

    # Ensure directory exists
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(report_content)

    logger.info(f"Validation report written to {output_path}")

def run_validation_gate_pipeline(correlation_input_path: str, output_report_path: str):
    """
    Main pipeline function for T017e.
    """
    logger.info("Starting Validation Gate Pipeline (T017e)...")
    
    # 1. Load Data
    correlation_data = load_correlation_data(correlation_input_path)
    if not correlation_data:
        logger.critical("Failed to load correlation data. Aborting validation.")
        # Create a failure report
        fail_result = {
            'passed': False,
            'reason': 'Could not load input data',
            'pearson_r': None,
            'p_value': None,
            'sample_size': 0
        }
        generate_validation_report(fail_result, output_report_path)
        return False

    # 2. Compute Confidence Intervals
    ci_data = compute_p_value_and_ci(correlation_data)
    if ci_data:
        correlation_data.update(ci_data)

    # 3. Validate
    validation_result = validate_correlation_against_threshold(correlation_data)
    
    # 4. Generate Report
    generate_validation_report(validation_result, output_report_path)

    logger.info("Validation Gate Pipeline completed.")
    return validation_result['passed']

def main():
    """
    Entry point for the script.
    """
    config = get_config()
    # Define paths based on project structure
    input_file = config.get('paths', {}).get('annotation_correlation_raw', 'data/interim/annotation_correlation_raw.json')
    output_file = config.get('paths', {}).get('annotation_correlation_report', 'data/results/annotation_correlation_report.md')

    # Allow overrides via command line args if running directly
    if len(sys.argv) >= 3:
        input_file = sys.argv[1]
        output_file = sys.argv[2]

    success = run_validation_gate_pipeline(input_file, output_file)
    
    if not success:
        logger.warning("Validation Gate FAILED. Pipeline should not proceed to US2.")
        sys.exit(1)
    else:
        logger.info("Validation Gate PASSED. Proceeding to US2.")
        sys.exit(0)

if __name__ == "__main__":
    main()
