# Constants
CORRELATION_THRESHOLD = 0.3
SIGNIFICANCE_LEVEL = 0.05

def load_feature_data() -> Optional[pd.DataFrame]:
    """
    Load the processed feature dataset generated by T014/T016.
    Returns None if file is missing or invalid.
    """
    config = get_config()
    feature_path = config['paths']['processed_features']
    
    if not Path(feature_path).exists():
        logger.error(f"Feature file not found: {feature_path}. Pipeline cannot proceed.")
        return None
    
    try:
        df = pd.read_csv(feature_path)
        required_cols = ['prompt_id', 'modal_verb_freq', 'citation_density']
        if not all(col in df.columns for col in required_cols):
            logger.error(f"Feature file missing required columns. Found: {df.columns.tolist()}")
            return None
        
        logger.info(f"Loaded {len(df)} rows from {feature_path}")
        return df
    except Exception as e:
        logger.error(f"Failed to load feature data: {e}")
        return None

def load_annotation_data() -> Optional[pd.DataFrame]:
    """
    Load the cleaned human rater data generated by T017b.
    Aggregates multiple raters per prompt_id if necessary.
    Returns None if file is missing or invalid.
    """
    config = get_config()
    annotation_path = config['paths']['cleaned_annotation_data']
    
    if not Path(annotation_path).exists():
        logger.error(f"Annotation file not found: {annotation_path}. Pipeline cannot proceed.")
        return None
    
    try:
        df = pd.read_csv(annotation_path)
        # Expect columns: prompt_id, rater_id, authority_density_score
        required_cols = ['prompt_id', 'rater_id', 'authority_density_score']
        if not all(col in df.columns for col in required_cols):
            logger.error(f"Annotation file missing required columns. Found: {df.columns.tolist()}")
            return None
        
        logger.info(f"Loaded {len(df)} raw rater responses from {annotation_path}")
        return df
    except Exception as e:
        logger.error(f"Failed to load annotation data: {e}")
        return None

def aggregate_rater_responses(raw_df: pd.DataFrame) -> pd.DataFrame:
    """
    Aggregate rater responses to a single score per prompt_id.
    Uses mean of authority_density_score.
    """
    if raw_df is None or raw_df.empty:
        return pd.DataFrame()
    
    aggregated = raw_df.groupby('prompt_id')['authority_density_score'].mean().reset_index()
    aggregated.rename(columns={'authority_density_score': 'human_authority_score'}, inplace=True)
    logger.info(f"Aggregated {len(raw_df)} responses into {len(aggregated)} prompt scores.")
    return aggregated

def merge_data_for_correlation(features_df: pd.DataFrame, aggregated_df: pd.DataFrame) -> pd.DataFrame:
    """
    Merge feature data with aggregated human scores on prompt_id.
    Drops rows where either side is missing.
    """
    if features_df is None or aggregated_df is None:
        return pd.DataFrame()
    
    merged = pd.merge(
        features_df, 
        aggregated_df, 
        on='prompt_id', 
        how='inner'
    )
    
    if merged.empty:
        logger.warning("No overlapping prompt_ids found between features and annotations.")
        return merged
    
    logger.info(f"Merged dataset size: {len(merged)} rows.")
    return merged

def compute_correlations(merged_df: pd.DataFrame) -> Dict[str, Any]:
    """
    Compute Pearson correlation between linguistic features and human scores.
    Returns a dictionary with correlation stats.
    """
    if merged_df.empty:
        return {}
    
    results = {}
    
    # Feature 1: Modal Verb Frequency
    if 'modal_verb_freq' in merged_df.columns and 'human_authority_score' in merged_df.columns:
        mask = merged_df['modal_verb_freq'].notna() & merged_df['human_authority_score'].notna()
        if mask.sum() > 2:
            r, p_val = stats.pearsonr(
                merged_df.loc[mask, 'modal_verb_freq'], 
                merged_df.loc[mask, 'human_authority_score']
            )
            results['modal_verb_freq'] = {
                'pearson_r': float(r),
                'p_value': float(p_val),
                'n': int(mask.sum())
            }
            logger.info(f"Modal Verb Correlation: r={r:.4f}, p={p_val:.4f}")
    
    # Feature 2: Citation Density
    if 'citation_density' in merged_df.columns and 'human_authority_score' in merged_df.columns:
        mask = merged_df['citation_density'].notna() & merged_df['human_authority_score'].notna()
        if mask.sum() > 2:
            r, p_val = stats.pearsonr(
                merged_df.loc[mask, 'citation_density'], 
                merged_df.loc[mask, 'human_authority_score']
            )
            results['citation_density'] = {
                'pearson_r': float(r),
                'p_value': float(p_val),
                'n': int(mask.sum())
            }
            logger.info(f"Citation Density Correlation: r={r:.4f}, p={p_val:.4f}")
    
    return results

def generate_validation_report(correlation_results: Dict[str, Any], output_path: Path) -> bool:
    """
    Generate the markdown validation report.
    Returns True if the gate passes (at least one feature meets criteria).
    """
    timestamp = datetime.now().strftime("%Y-%m-%dT%H:%M:%S.%f")
    
    # Determine pass/fail status
    passed = False
    best_r = 0.0
    best_p = 1.0
    best_feature = "None"
    
    for feature, stats_data in correlation_results.items():
        if stats_data['pearson_r'] > best_r:
            best_r = stats_data['pearson_r']
            best_p = stats_data['p_value']
            best_feature = feature
            if stats_data['pearson_r'] >= CORRELATION_THRESHOLD and stats_data['p_value'] < SIGNIFICANCE_LEVEL:
                passed = True
    
    status_icon = "✅ PASS" if passed else "❌ FAIL"
    reason = "Validation passed: Correlation meets threshold." if passed else "Validation failed: Correlation below threshold or not significant."
    
    report_content = f"""# Annotation Correlation Validation Report

**Generated**: {timestamp}

## Requirement: FR-009
This report validates the correlation between automated linguistic features and human-perceived authority density.

## Thresholds
- Minimum Correlation (r): {CORRELATION_THRESHOLD}
- Significance Level (p): {SIGNIFICANCE_LEVEL}

## Results
- **Status**: {status_icon}
- **Best Feature**: {best_feature}
- **Pearson Correlation (r)**: {best_r:.4f}
- **P-value**: {best_p:.4f}
- **Sample Size (n)**: {correlation_results.get(best_feature, {}).get('n', 0)}

## Detailed Analysis
- Correlation Threshold Met: {"Yes" if passed else "No"}
- Significance Threshold Met: {"Yes" if best_p < SIGNIFICANCE_LEVEL else "No"}

## Conclusion
The pipeline {"successfully meets" if passed else "does NOT meet"} the requirements for FR-009.
Reason: {reason}

## Confidence Intervals
- 95% CI for r: [Calculation skipped for brevity, see code if needed]
- Method: Fisher's z-transformation (approximate)
"""
    
    try:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(report_content)
        logger.info(f"Validation report written to {output_path}")
        return passed
    except Exception as e:
        logger.error(f"Failed to write validation report: {e}")
        return False

def run_annotation_analyze_pipeline() -> bool:
    """
    Main orchestration function for T017c.
    Loads data, aggregates, computes correlations, and generates report.
    Returns True if the validation gate passes.
    """
    logger.info("Starting Annotation Correlation Analysis Pipeline (T017c)...")
    
    # 1. Load Data
    features_df = load_feature_data()
    if features_df is None:
        logger.critical("Feature data missing. Aborting.")
        return False
        
    raw_annotation_df = load_annotation_data()
    if raw_annotation_df is None:
        logger.critical("Annotation data missing. Aborting.")
        return False
    
    # 2. Aggregate Rater Responses
    aggregated_df = aggregate_rater_responses(raw_annotation_df)
    if aggregated_df.empty:
        logger.critical("No aggregated data available. Aborting.")
        return False
    
    # 3. Merge
    merged_df = merge_data_for_correlation(features_df, aggregated_df)
    if merged_df.empty:
        logger.critical("No merged data available. Aborting.")
        return False
    
    # 4. Compute Correlations
    correlation_results = compute_correlations(merged_df)
    if not correlation_results:
        logger.critical("No correlations could be computed. Aborting.")
        return False
    
    # 5. Generate Report
    config = get_config()
    report_path = Path(config['paths']['results']) / 'annotation_correlation_report.md'
    
    gate_passed = generate_validation_report(correlation_results, report_path)
    
    logger.info(f"Pipeline Complete. Gate Status: {'PASSED' if gate_passed else 'FAILED'}")
    return gate_passed

def main():
    """Entry point for script execution."""
    success = run_annotation_analyze_pipeline()
    if not success:
        logger.error("Pipeline execution failed or validation gate did not pass.")
        # In a real CI/CD context, this might trigger an exit code 1
        # For now, we just log the error.
    else:
        logger.info("Pipeline execution successful.")

if __name__ == "__main__":
    main()