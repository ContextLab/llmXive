def run_semantic_scoring_pipeline():
    """Orchestrates T022-T025."""
    logger.info("Running Semantic Scoring Pipeline (T022-T025)...")
    config = get_config()
    
    # Load features and responses (assuming ingestion and feature extraction ran)
    # We need to merge features with responses.
    # For this pipeline, we assume a response generation step happened or we are simulating it.
    # Since T025 requires merging features, responses, and labels, we need a source of responses.
    # In a real run, this would come from an inference step.
    # We will assume the dataset from ingestion has 'response_text' or we load it from a generated file.
    # If not present, we might need to generate dummy responses for testing, but T013 requires real data.
    # Let's assume there is a 'response_text' column in the merged data or we load it.
    
    # For this implementation, we load the features dataset and merge with a hypothetical response dataset.
    # If 'response_text' is missing, we cannot compute similarities.
    # We will check for 'response_text' column.
    
    features_path = config['paths']['features']
    if not os.path.exists(features_path):
        raise FileNotFoundError(f"Features not found at {features_path}. Run T015.")
    
    df = pd.read_csv(features_path)
    
    # Check for response_text
    if 'response_text' not in df.columns:
        # If responses are missing, we cannot proceed with labeling.
        # In a real scenario, we would run an inference script here.
        # For this task, we assume the data flow includes responses.
        # We will raise an error if missing.
        raise FileNotFoundError("No 'response_text' column found. Inference step missing.")
    
    # T024: Detect safety refusal
    logger.info("Detecting safety refusals...")
    df['safety_refusal'] = df['response_text'].apply(detect_safety_refusal)
    
    # T022: Compute similarities
    df = compute_semantic_similarities(df)
    
    # T023: Apply label logic
    logger.info("Applying label logic...")
    df['adherence_label'] = df.apply(apply_label_logic, axis=1)
    
    # T025: Save merged dataset
    output_path = config['paths']['labeled_responses']
    save_labeled_dataset(df, output_path)
    
    return output_path

