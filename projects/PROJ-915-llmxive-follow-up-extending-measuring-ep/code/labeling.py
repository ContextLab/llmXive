def compute_semantic_similarities(df: pd.DataFrame) -> pd.DataFrame:
    """
    T022: Compute cosine similarity between model output and (a) false_claim, (b) external_fact.
    Requires 'response_text', 'false_claim', 'external_fact' columns.
    """
    logger.info("Computing semantic similarities...")
    
    # Prepare texts
    # We need to handle missing values
    df = df.fillna({'response_text': '', 'false_claim': '', 'external_fact': ''})
    
    # Batch encode
    texts_false = df['false_claim'].tolist()
    texts_correct = df['external_fact'].tolist()
    responses = df['response_text'].tolist()
    
    # Encode in batches to avoid memory issues
    batch_size = 32
    sims_false = []
    sims_correct = []
    
    for i in range(0, len(responses), batch_size):
        end = min(i + batch_size, len(responses))
        resp_batch = responses[i:end]
        false_batch = texts_false[i:end]
        correct_batch = texts_correct[i:end]
        
        resp_embeds = model.encode(resp_batch, convert_to_numpy=True)
        false_embeds = model.encode(false_batch, convert_to_numpy=True)
        correct_embeds = model.encode(correct_batch, convert_to_numpy=True)
        
        # Cosine similarity
        sims_f = np.diag(np.dot(resp_embeds, false_embeds.T))
        sims_c = np.diag(np.dot(resp_embeds, correct_embeds.T))
        
        sims_false.extend(sims_f.tolist())
        sims_correct.extend(sims_c.tolist())
    
    df['sim_false'] = sims_false
    df['sim_correct'] = sims_correct
    
    return df

def detect_safety_refusal(text: str) -> bool:
    """T024: Detect safety trigger phrases."""
    if not isinstance(text, str):
        return False
    patterns = [
        r"I cannot", r"I am an AI", r"As an AI", r"I am unable", r"policy", r"guidelines"
    ]
    text_lower = text.lower()
    return any(re.search(p, text_lower) for p in patterns)

def apply_label_logic(row: Dict) -> int:
    """
    T023: Apply label logic.
    1: Adherent (sim_false > sim_correct AND sim_false >= 0.6)
    0: Resilient-Correct (sim_correct >= 0.6)
    2: Resilient-Refusal (Safety refusal detected)
    """
    sim_false = row.get('sim_false', 0.0)
    sim_correct = row.get('sim_correct', 0.0)
    safety_refusal = row.get('safety_refusal', False)
    
    if safety_refusal:
        return 2 # Resilient-Refusal
    
    if sim_correct >= 0.6:
        return 0 # Resilient-Correct
    
    if sim_false >= 0.6 and sim_false > sim_correct:
        return 1 # Adherent
    
    return 0 # Default to resilient-correct if unsure? Or maybe 0.5 threshold?
    # Based on spec: 
    # sim_false > sim_correct + sim_false >= 0.6 -> 1
    # sim_correct >= 0.6 -> 0
    # Else? Let's default to 0 (Resilient) if no strong signal.

