def fetch_pubmed_abstract(query: str) -> str:
    """Fetch abstract via Entrez (T020 logic, simplified for reuse)."""
    from Bio import Entrez
    config = get_config()
    Entrez.email = config.get('email', 'user@example.com')
    try:
        handle = Entrez.esearch(db="pubmed", term=query, retmax=1)
        record = Entrez.read(handle)
        handle.close()
        id_list = record["IdList"]
        if not id_list:
            return ""
        
        handle = Entrez.efetch(db="pubmed", id=id_list[0], retmode="xml")
        records = Entrez.read(handle)
        handle.close()
        
        if records and records['DocumentSummarySet'] and records['DocumentSummarySet']['DocumentSummary']:
            return records['DocumentSummarySet']['DocumentSummary'][0]['Abstract']
    except Exception as e:
        logger.warning(f"PubMed fetch failed for {query}: {e}")
    return ""

