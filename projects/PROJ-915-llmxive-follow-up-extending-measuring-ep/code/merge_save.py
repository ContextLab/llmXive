"""
Merge and Save Task (T025)

Merges features, responses, and labels into a single dataset.
Performs inner join on prompt_id.
Aborts with clear error if any required column is missing.
"""
import os
import sys
import logging
import pandas as pd
from pathlib import Path

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)

def load_features():
    """Load features from data/processed/features.csv"""
    path = Path("data/processed/features.csv")
    if not path.exists():
        raise FileNotFoundError(f"Required file not found: {path}")
    
    df = pd.read_csv(path)
    required_cols = ['prompt_id', 'modal_freq', 'imperative_ratio', 'citation_density', 
                    'is_ratio_undefined', 'ratio_safe_value', 'raw_text']
    
    missing = [col for col in required_cols if col not in df.columns]
    if missing:
        raise ValueError(f"Features file missing required columns: {missing}")
    
    logger.info(f"Loaded features with {len(df)} rows")
    return df

def load_responses():
    """Load responses from data/interim/responses.csv (generated by inference)"""
    path = Path("data/interim/responses.csv")
    if not path.exists():
        raise FileNotFoundError(f"Required file not found: {path}")
    
    df = pd.read_csv(path)
    required_cols = ['prompt_id', 'response_text']
    
    missing = [col for col in required_cols if col not in df.columns]
    if missing:
        raise ValueError(f"Responses file missing required columns: {missing}")
    
    logger.info(f"Loaded responses with {len(df)} rows")
    return df

def load_labels():
    """Load labels from data/interim/labels.csv (generated by labeling)"""
    path = Path("data/interim/labels.csv")
    if not path.exists():
        raise FileNotFoundError(f"Required file not found: {path}")
    
    df = pd.read_csv(path)
    required_cols = ['prompt_id', 'adherence_label', 'safety_refusal']
    
    missing = [col for col in required_cols if col not in df.columns]
    if missing:
        raise ValueError(f"Labels file missing required columns: {missing}")
    
    logger.info(f"Loaded labels with {len(df)} rows")
    return df

def merge_datasets(features_df, responses_df, labels_df):
    """Merge all datasets on prompt_id using inner join"""
    # Start with features
    merged = features_df.copy()
    
    # Merge responses
    merged = merged.merge(responses_df, on='prompt_id', how='inner')
    logger.info(f"After merging responses: {len(merged)} rows")
    
    # Merge labels
    merged = merged.merge(labels_df, on='prompt_id', how='inner')
    logger.info(f"After merging labels: {len(merged)} rows")
    
    return merged

def save_merged_dataset(df, output_path):
    """Save merged dataset to CSV"""
    # Ensure output directory exists
    output_dir = Path(output_path).parent
    output_dir.mkdir(parents=True, exist_ok=True)
    
    df.to_csv(output_path, index=False)
    logger.info(f"Saved merged dataset to {output_path} with {len(df)} rows")

def run_merge_save_pipeline():
    """Execute the full merge and save pipeline"""
    logger.info("Starting merge and save pipeline (T025)")
    
    try:
        # Load all components
        features_df = load_features()
        responses_df = load_responses()
        labels_df = load_labels()
        
        # Merge
        merged_df = merge_datasets(features_df, responses_df, labels_df)
        
        # Validate schema
        expected_schema = [
            'prompt_id', 'raw_text', 'modal_freq', 'imperative_ratio', 
            'citation_density', 'is_ratio_undefined', 'ratio_safe_value',
            'response_text', 'adherence_label', 'safety_refusal'
        ]
        
        missing_from_schema = [col for col in expected_schema if col not in merged_df.columns]
        if missing_from_schema:
            raise ValueError(f"Merged dataset missing schema columns: {missing_from_schema}")
        
        # Save
        output_path = "data/interim/labeled_responses.csv"
        save_merged_dataset(merged_df, output_path)
        
        logger.info("Merge and save pipeline completed successfully")
        return True
        
    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        raise
    except ValueError as e:
        logger.error(f"Validation error: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during merge: {e}")
        raise

def main():
    """Main entry point"""
    success = run_merge_save_pipeline()
    return 0 if success else 1

if __name__ == "__main__":
    sys.exit(main())