# Constants
SENTINEL = -999.0
WINDOW_SIZE = 5
MIN_INTERACTIONS = 2

# Setup logging
logger = setup_logger("metrics_calculation")

def load_valence_sequence() -> pd.DataFrame:
    """Load the valence sequence CSV generated by 01_ingest.py."""
    input_path = DATA_PROCESSED_DIR / "valence_sequence.csv"
    if not input_path.exists():
        raise FileNotFoundError(
            f"Required input file not found: {input_path}. "
            "Please run code/01_ingest.py first."
        )
    
    logger.info(f"Loading valence sequence from {input_path}")
    df = pd.read_csv(input_path)
    
    required_cols = ['user_id', 'timestamp', 'post_text', 'reply_text', 'calculated_valence']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Input CSV missing required columns: {missing_cols}")
    
    logger.info(f"Loaded {len(df)} rows. Unique users: {df['user_id'].nunique()}")
    return df

def calculate_rolling_std(valence_sequence: List[float], window_size: int = WINDOW_SIZE) -> float:
    """
    Calculate the standard deviation of a rolling window.
    If sequence length < 2, return SENTINEL.
    If 2 <= length < window_size, use all available data.
    """
    if len(valence_sequence) < MIN_INTERACTIONS:
        return SENTINEL
    
    # Filter out sentinels for calculation if any exist (though spec says exclude sentinels)
    # The spec says "excluding sentinels" for mean, but for volatility we look at the sequence.
    # If a sequence has sentinels, they represent missing feedback. 
    # We will treat SENTINEL as missing and exclude it from the rolling calculation if present,
    # but if the resulting list is < 2, we return SENTINEL.
    
    valid_sequence = [v for v in valence_sequence if v != SENTINEL]
    
    if len(valid_sequence) < MIN_INTERACTIONS:
        return SENTINEL
    
    # Use the full valid sequence if smaller than window, otherwise rolling
    # The task asks for "Standard Deviation of a rolling window (size=5)".
    # Usually, this implies the mean of the rolling stds or the std of the windowed data.
    # Given the context of "volatility", calculating the rolling std and taking the mean
    # of those rolling stds is a common interpretation for a single user metric.
    # However, if the instruction implies a single rolling window over the whole series,
    # we take the max or mean of the rolling stds. Let's calculate the mean of rolling stds.
    
    series = pd.Series(valid_sequence)
    
    if len(series) < window_size:
        # Use all data
        return float(series.std())
    else:
        rolling_std = series.rolling(window=window_size).std()
        # Return the mean of the rolling standard deviations
        return float(rolling_std.mean())

def calculate_sign_changes(valence_sequence: List[float]) -> float:
    """
    Calculate the frequency of sign changes in the valence sequence.
    Returns the count of transitions from positive to negative or vice versa.
    If sequence length < 2, return SENTINEL.
    """
    if len(valence_sequence) < MIN_INTERACTIONS:
        return SENTINEL
    
    valid_sequence = [v for v in valence_sequence if v != SENTINEL]
    
    if len(valid_sequence) < MIN_INTERACTIONS:
        return SENTINEL
    
    count = 0
    for i in range(1, len(valid_sequence)):
        prev_sign = np.sign(valid_sequence[i-1])
        curr_sign = np.sign(valid_sequence[i])
        
        # Skip if either is zero (neutral), or if signs are the same
        if prev_sign == 0 or curr_sign == 0:
            continue
        if prev_sign != curr_sign:
            count += 1
    
    return float(count)

def calculate_self_esteem_indicator(post_texts: List[str], lexicon: Dict[str, float]) -> float:
    """
    Calculate the Self-Esteem Indicator (Rosenberg lexicon score) for a list of post texts.
    Score is the average count of Rosenberg words found across the user's posts.
    """
    if not post_texts:
        return SENTINEL
    
    total_score = 0.0
    valid_posts = 0
    
    for text in post_texts:
        if not isinstance(text, str) or not text.strip():
            continue
        
        # Normalize text
        clean_text = text.lower()
        words = clean_text.split()
        
        # Count matches
        matches = sum(1 for word in words if word in lexicon)
        total_score += matches
        valid_posts += 1
    
    if valid_posts == 0:
        return SENTINEL
    
    return total_score / valid_posts

def calculate_mean_reply_valence(valence_sequence: List[float]) -> float:
    """Calculate mean of calculated_valence excluding sentinels."""
    valid_vals = [v for v in valence_sequence if v != SENTINEL]
    if not valid_vals:
        return SENTINEL
    return float(np.mean(valid_vals))

def calculate_post_valence(post_texts: List[str], pipeline) -> float:
    """Calculate mean sentiment of the user's own post_text."""
    valid_texts = [t for t in post_texts if isinstance(t, str) and t.strip()]
    if not valid_texts:
        return SENTINEL
    
    scores = []
    for text in valid_texts:
        # Truncate if too long for model (typical limit ~512 tokens)
        if len(text) > 512:
            text = text[:512]
        
        result = pipeline(text, return_all_scores=False)
        # Assuming binary classification or regression output. 
        # If it's classification (positive/negative), we need to map to -1..1.
        # The spec says "normalizing scores to [-1.0, 1.0]".
        # RoBERTa sentiment often returns [{'label': 'POSITIVE', 'score': 0.99}].
        # We map Positive -> 1.0, Negative -> -1.0, weighted by confidence?
        # Or if it's a regression model, it's direct.
        # The task T016 says "normalizing scores to [-1.0, 1.0]".
        # Let's assume the pipeline returns a score in 0-1 where 0.5 is neutral.
        # Map: score -> 2*score - 1.
        
        if isinstance(result, list) and len(result) > 0:
            item = result[0]
            score = item['score']
            # If it's a binary classifier (POSITIVE/NEGATIVE)
            if item.get('label', '').upper() == 'POSITIVE':
                normalized = 2 * score - 1
            elif item.get('label', '').upper() == 'NEGATIVE':
                normalized = 1 - 2 * score
            else:
                # Fallback: treat as probability of positive
                normalized = 2 * score - 1
            scores.append(normalized)
        else:
            scores.append(0.0)
    
    if not scores:
        return SENTINEL
    return float(np.mean(scores))

def calculate_post_length(post_texts: List[str]) -> float:
    """Calculate mean character length of post_text."""
    valid_lengths = [len(t) for t in post_texts if isinstance(t, str)]
    if not valid_lengths:
        return SENTINEL
    return float(np.mean(valid_lengths))

def calculate_user_activity(interaction_count: int) -> int:
    """Total number of interactions per user."""
    return interaction_count

def process_user_group(user_id: Any, group_df: pd.DataFrame, pipeline, lexicon: Dict[str, float]) -> Dict[str, Any]:
    """Process a single user's group and return metrics dictionary."""
    # Sort by timestamp just in case
    group_df = group_df.sort_values('timestamp')
    
    valence_sequence = group_df['calculated_valence'].tolist()
    post_texts = group_df['post_text'].tolist()
    
    # Calculate metrics
    metrics = {
        'user_id': user_id,
        'user_activity_level': calculate_user_activity(len(group_df)),
        'mean_reply_valence': calculate_mean_reply_valence(valence_sequence),
        'self_esteem_indicator': calculate_self_esteem_indicator(post_texts, lexicon),
        'post_valence': calculate_post_valence(post_texts, pipeline),
        'post_length': calculate_post_length(post_texts),
    }
    
    # Volatility metrics
    metrics['volatility_std'] = calculate_rolling_std(valence_sequence)
    metrics['volatility_sign_changes'] = calculate_sign_changes(valence_sequence)
    
    # Log exclusion if < 2 interactions
    if len(group_df) < MIN_INTERACTIONS:
        logger.warning(f"User {user_id} has {len(group_df)} interactions (< {MIN_INTERACTIONS}). "
                     f"Metrics set to sentinel.")
    
    return metrics

def main():
    """Main entry point for metric calculation."""
    logger.info("Starting User Story 2: Volatility Metric Calculation")
    
    # Load dependencies
    try:
        pipeline = get_sentiment_pipeline()
        lexicon = get_rosenberg_lexicon()
    except Exception as e:
        logger.error(f"Failed to load models/lexicon: {e}")
        raise
    
    # Load data
    try:
        df = load_valence_sequence()
    except FileNotFoundError as e:
        logger.error(str(e))
        raise
    
    # Group by user
    grouped = df.groupby('user_id')
    total_users = len(grouped)
    excluded_users = 0
    
    results = []
    
    logger.info(f"Processing {total_users} unique users...")
    
    for user_id, group_df in grouped:
        user_metrics = process_user_group(user_id, group_df, pipeline, lexicon)
        results.append(user_metrics)
        
        if user_metrics['user_activity_level'] < MIN_INTERACTIONS:
            excluded_users += 1
    
    # Create output DataFrame
    output_df = pd.DataFrame(results)
    
    # Ensure correct column order as per spec
    columns = [
        'user_id', 
        'self_esteem_indicator', 
        'volatility_std', 
        'volatility_sign_changes', 
        'mean_reply_valence', 
        'post_valence', 
        'post_length', 
        'user_activity_level'
    ]
    
    # Reorder and fill missing columns if any
    for col in columns:
        if col not in output_df.columns:
            output_df[col] = SENTINEL
    
    output_df = output_df[columns]
    
    # Save output
    output_path = DATA_PROCESSED_DIR / "user_metrics.csv"
    output_df.to_csv(output_path, index=False)
    
    logger.info(f"Successfully saved metrics to {output_path}")
    logger.info(f"Total users processed: {total_users}")
    logger.info(f"Users excluded (< {MIN_INTERACTIONS} interactions): {excluded_users}")
    logger.info(f"Exclusion percentage: {(excluded_users/total_users)*100:.2f}%")
    
    return output_df

if __name__ == "__main__":
    main()