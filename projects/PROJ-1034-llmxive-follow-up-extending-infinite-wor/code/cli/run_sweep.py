"""
Simulation Runner Wrapper for Parameter Sweeps.

This script executes a sweep over parameter configurations generated by generate_grid.py.
It runs the simulation for each configuration, handles memory/time constraints,
and logs results to data/raw/ for subsequent aggregation.

Usage:
    python code/cli/run_sweep.py --grid data/processed/param_grid.csv --output data/raw/sweep_results.csv
"""

