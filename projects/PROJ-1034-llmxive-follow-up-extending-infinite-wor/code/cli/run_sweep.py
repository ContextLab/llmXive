# Constants
MAX_MEMORY_MB = 6000  # 6GB limit as per T014
DEFAULT_TIMEOUT_STEPS = 10000  # Default steps if not specified in config
SWEEP_LOG_FILE = "data/raw/sweep_execution_log.jsonl"


def load_grid_from_csv(grid_path: str) -> List[Dict[str, Any]]:
    """Load parameter configurations from a CSV grid file."""
    if not os.path.exists(grid_path):
        raise FileNotFoundError(f"Grid file not found: {grid_path}")
    
    configurations = []
    with open(grid_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Convert numeric strings to appropriate types
            config = {}
            for k, v in row.items():
                if v == '' or v is None:
                    config[k] = None
                    continue
                try:
                    if '.' in v:
                        config[k] = float(v)
                    else:
                        config[k] = int(v)
                except ValueError:
                    config[k] = v
            configurations.append(config)
    
    return configurations


def run_single_configuration(
    config_id: int,
    params: Dict[str, Any],
    output_dir: str,
    base_seed: int,
    timeout_steps: int = DEFAULT_TIMEOUT_STEPS
) -> Dict[str, Any]:
    """
    Run a single simulation configuration.
    
    Returns a result dictionary with status, metrics, and error info.
    """
    result = {
        "config_id": config_id,
        "params": params,
        "status": "pending",
        "start_time": None,
        "end_time": None,
        "memory_peak_mb": 0,
        "metrics": {},
        "error": None,
        "error_traceback": None
    }
    
    result["start_time"] = time.time()
    set_seed(base_seed + config_id)
    initialize_reproducibility(base_seed + config_id)
    
    # Setup logging for this run
    run_id = f"sweep_{config_id}_{int(time.time())}"
    logger = create_logger(run_id, output_dir)
    monitor = HealthMonitor(max_memory_mb=MAX_MEMORY_MB)
    
    try:
        # Check memory before starting
        initial_mem = get_memory_usage_mb()
        if initial_mem > MAX_MEMORY_MB * 0.9:
            raise MemoryError(f"Initial memory usage {initial_mem}MB exceeds 90% of limit")
        
        # Merge params with base config
        # We assume params contains the override values for the simulation
        # The actual simulation logic will handle merging with defaults
        sim_params = params.copy()
        sim_params['seed'] = base_seed + config_id
        sim_params['steps'] = timeout_steps
        
        # Run the simulation with fallback logic
        # This wraps the core simulation with memory/time monitoring
        sim_result = run_simulation_with_fallback(
            config_params=sim_params,
            logger=logger,
            monitor=monitor
        )
        
        result["status"] = "completed"
        result["metrics"] = sim_result.get("metrics", {})
        result["memory_peak_mb"] = sim_result.get("memory_peak_mb", 0)
        
        # Log completion
        log_status(
            status="completed",
            memory_mb=result["memory_peak_mb"],
            config_id=config_id,
            timestamp=result["end_time"]
        )
        
    except MemoryError as e:
        result["status"] = "memory_exceeded"
        result["error"] = str(e)
        result["memory_peak_mb"] = get_memory_usage_mb()
        log_status(
            status="memory_exceeded",
            memory_mb=result["memory_peak_mb"],
            config_id=config_id,
            timestamp=time.time()
        )
        
    except TimeoutError as e:
        result["status"] = "timeout"
        result["error"] = str(e)
        log_status(
            status="timeout",
            memory_mb=get_memory_usage_mb(),
            config_id=config_id,
            timestamp=time.time()
        )
        
    except Exception as e:
        result["status"] = "failed"
        result["error"] = str(e)
        result["error_traceback"] = traceback.format_exc()
        log_status(
            status="failed",
            memory_mb=get_memory_usage_mb(),
            config_id=config_id,
            timestamp=time.time()
        )
        
    finally:
        result["end_time"] = time.time()
        # Clean up logger resources if needed
        if logger:
            logger.flush()
    
    return result


def run_sweep(
    grid_path: str,
    output_dir: str,
    steps: int = DEFAULT_TIMEOUT_STEPS,
    seed: Optional[int] = None
) -> List[Dict[str, Any]]:
    """
    Execute a full parameter sweep.
    
    Args:
        grid_path: Path to the parameter grid CSV
        output_dir: Directory to save results
        steps: Number of simulation steps per configuration
        seed: Base seed for reproducibility
        
    Returns:
        List of result dictionaries for each configuration
    """
    # Ensure output directory exists
    os.makedirs(output_dir, exist_ok=True)
    
    # Load configurations
    print(f"Loading parameter grid from {grid_path}...")
    configurations = load_grid_from_csv(grid_path)
    print(f"Loaded {len(configurations)} configurations.")
    
    if seed is None:
        seed = int(time.time()) % (2**31)
        
    results = []
    sweep_log_path = os.path.join(output_dir, os.path.basename(SWEEP_LOG_FILE))
    
    # Ensure sweep log directory exists
    os.makedirs(os.path.dirname(sweep_log_path), exist_ok=True)
    
    with open(sweep_log_path, 'w', encoding='utf-8') as log_file:
        for i, params in enumerate(configurations):
            print(f"Running configuration {i+1}/{len(configurations)}: {params}")
            
            result = run_single_configuration(
                config_id=i,
                params=params,
                output_dir=output_dir,
                base_seed=seed,
                timeout_steps=steps
            )
            
            results.append(result)
            
            # Write to log file immediately for crash recovery
            log_line = json.dumps(result)
            log_file.write(log_line + '\n')
            log_file.flush()
            
            # Small delay to allow I/O to settle
            time.sleep(0.1)
            
            # Check overall system health periodically
            if (i + 1) % 10 == 0:
                current_mem = get_memory_usage_mb()
                print(f"System memory after {i+1} configs: {current_mem:.1f}MB")
    
    return results


def write_results_csv(results: List[Dict[str, Any]], output_path: str):
    """Write sweep results to a CSV file for aggregation."""
    if not results:
        print("No results to write.")
        return
        
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        # Flatten the result structure for CSV
        # We'll create columns for common fields and JSON for complex ones
        fieldnames = [
            'config_id', 'status', 'start_time', 'end_time', 
            'memory_peak_mb', 'error'
        ]
        
        # Add metric fields dynamically
        first_result = results[0]
        if 'metrics' in first_result and first_result['metrics']:
            metric_keys = list(first_result['metrics'].keys())
            fieldnames.extend([f"metric_{k}" for k in metric_keys])
        
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction='ignore')
        writer.writeheader()
        
        for result in results:
            row = {
                'config_id': result['config_id'],
                'status': result['status'],
                'start_time': result['start_time'],
                'end_time': result['end_time'],
                'memory_peak_mb': result['memory_peak_mb'],
                'error': result['error']
            }
            
            # Flatten metrics
            if 'metrics' in result and result['metrics']:
                for k, v in result['metrics'].items():
                    row[f"metric_{k}"] = v
            
            writer.writerow(row)
    
    print(f"Results written to {output_path}")


def main():
    """Main entry point for the sweep runner."""
    parser = argparse.ArgumentParser(
        description="Run a parameter sweep over simulation configurations."
    )
    parser.add_argument(
        "--grid", 
        type=str, 
        required=True,
        help="Path to the parameter grid CSV file (output of generate_grid.py)"
    )
    parser.add_argument(
        "--output",
        type=str,
        required=True,
        help="Output directory for results"
    )
    parser.add_argument(
        "--steps",
        type=int,
        default=DEFAULT_TIMEOUT_STEPS,
        help=f"Number of simulation steps per configuration (default: {DEFAULT_TIMEOUT_STEPS})"
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="Base random seed for reproducibility (default: current time)"
    )
    parser.add_argument(
        "--results-csv",
        type=str,
        default=None,
        help="Path to write aggregated results CSV (default: <output_dir>/results.csv)"
    )
    
    args = parser.parse_args()
    
    # Validate grid file
    if not os.path.exists(args.grid):
        print(f"Error: Grid file not found: {args.grid}", file=sys.stderr)
        sys.exit(1)
        
    # Determine output CSV path
    results_csv = args.results_csv
    if not results_csv:
        results_csv = os.path.join(args.output, "results.csv")
        
    print(f"Starting sweep with {len(load_grid_from_csv(args.grid))} configurations...")
    print(f"Output directory: {args.output}")
    print(f"Steps per config: {args.steps}")
    print(f"Base seed: {args.seed if args.seed else 'dynamic'}")
    
    try:
        results = run_sweep(
            grid_path=args.grid,
            output_dir=args.output,
            steps=args.steps,
            seed=args.seed
        )
        
        write_results_csv(results, results_csv)
        
        success_count = sum(1 for r in results if r['status'] == 'completed')
        fail_count = sum(1 for r in results if r['status'] in ['failed', 'memory_exceeded', 'timeout'])
        
        print(f"\nSweep completed: {success_count} succeeded, {fail_count} failed.")
        
        if fail_count > 0:
            print("Check data/raw/sweep_execution_log.jsonl for error details.")
            
    except Exception as e:
        print(f"Sweep execution failed: {e}", file=sys.stderr)
        traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()