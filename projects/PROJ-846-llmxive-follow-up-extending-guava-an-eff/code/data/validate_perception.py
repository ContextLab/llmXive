"""
Validation module for the Symbolic-Guava perception pipeline.

This module validates:
1. YOLO object detection precision and recall against ground truth annotations.
2. The total transformation time constraint (must complete within 4 hours for the full dataset).

It reads the processed symbolic JSONs generated by `transform_symbolic.py` and compares them
against the ground truth annotations found in `data/raw/guava/ground_truth_annotations.json`.
"""
import json
import os
import sys
import time
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Tuple, Any, Optional

# Project root path resolution
PROJECT_ROOT = Path(__file__).resolve().parents[2]
DATA_RAW_DIR = PROJECT_ROOT / "data" / "raw" / "guava"
DATA_PROCESSED_DIR = PROJECT_ROOT / "data" / "processed" / "symbolic_guava"
DATA_ARTIFACTS_DIR = PROJECT_ROOT / "data" / "artifacts"

# Thresholds
IOU_THRESHOLD = 0.5
CONFIDENCE_THRESHOLD = 0.3
MAX_TRANSFORMATION_TIME_HOURS = 4.0


def calculate_iou(bbox1: List[int], bbox2: List[int]) -> float:
    """
    Calculate Intersection over Union (IoU) between two bounding boxes.
    bbox format: [x_min, y_min, x_max, y_max]
    """
    x1 = max(bbox1[0], bbox2[0])
    y1 = max(bbox1[1], bbox2[1])
    x2 = min(bbox1[2], bbox2[2])
    y2 = min(bbox1[3], bbox2[3])

    intersection_area = max(0, x2 - x1) * max(0, y2 - y1)
    bbox1_area = (bbox1[2] - bbox1[0]) * (bbox1[3] - bbox1[1])
    bbox2_area = (bbox2[2] - bbox2[0]) * (bbox2[3] - bbox2[1])

    union_area = bbox1_area + bbox2_area - intersection_area
    if union_area == 0:
        return 0.0

    return intersection_area / union_area


def calculate_metrics_from_ground_truth(
    processed_dir: Path,
    ground_truth_path: Path
) -> Dict[str, Any]:
    """
    Calculate precision and recall metrics by comparing processed symbolic observations
    against ground truth annotations.

    Args:
        processed_dir: Path to the directory containing processed symbolic JSONs.
        ground_truth_path: Path to the ground truth annotations JSON file.

    Returns:
        A dictionary containing precision, recall, F1 score, and detailed counts.
    """
    if not processed_dir.exists():
        raise FileNotFoundError(f"Processed directory not found: {processed_dir}")
    if not ground_truth_path.exists():
        raise FileNotFoundError(f"Ground truth file not found: {ground_truth_path}")

    # Load ground truth
    with open(ground_truth_path, 'r', encoding='utf-8') as f:
        ground_truth_data = json.load(f)

    # Index ground truth by trajectory_id and frame_id for quick lookup
    # Expected structure: { "trajectories": [ { "id": "...", "frames": [ { "frame_id": ..., "objects": [...] } ] } ] }
    gt_index = {}
    if "trajectories" in ground_truth_data:
        for traj in ground_truth_data["trajectories"]:
            traj_id = traj.get("id")
            if traj_id:
                gt_index[traj_id] = {}
                for frame in traj.get("frames", []):
                    frame_id = frame.get("frame_id")
                    if frame_id is not None:
                        gt_index[traj_id][frame_id] = frame.get("objects", [])
    elif isinstance(ground_truth_data, list):
        # Handle flat list structure if necessary, though spec implies nested
        pass

    total_tp = 0
    total_fp = 0
    total_fn = 0
    total_frames_processed = 0
    total_gt_objects = 0

    processed_files = list(processed_dir.glob("*.json"))

    for p_file in processed_files:
        traj_id = p_file.stem
        with open(p_file, 'r', encoding='utf-8') as f:
            processed_data = json.load(f)

        # Handle both list of frames or single object structure depending on transform_symbolic output
        frames = processed_data if isinstance(processed_data, list) else processed_data.get("frames", [])

        for frame in frames:
            total_frames_processed += 1
            frame_id = frame.get("frame_id")
            detected_objects = frame.get("detected_objects", [])

            # Get ground truth for this frame
            gt_objects = []
            if traj_id in gt_index and frame_id in gt_index[traj_id]:
                gt_objects = gt_index[traj_id][frame_id]

            total_gt_objects += len(gt_objects)

            # Match detections to ground truth
            matched_gt_indices = set()

            for det in detected_objects:
                det_bbox = det.get("bbox", [])
                det_class = det.get("class", "")
                det_conf = det.get("confidence", 0.0)

                if det_conf < CONFIDENCE_THRESHOLD:
                    total_fp += 1
                    continue

                best_iou = 0.0
                best_gt_idx = -1

                for i, gt_obj in enumerate(gt_objects):
                    if i in matched_gt_indices:
                        continue
                    if gt_obj.get("class", "") != det_class:
                        continue

                    gt_bbox = gt_obj.get("bbox", [])
                    iou = calculate_iou(det_bbox, gt_bbox)
                    if iou > best_iou:
                        best_iou = iou
                        best_gt_idx = i

                if best_iou >= IOU_THRESHOLD and best_gt_idx != -1:
                    total_tp += 1
                    matched_gt_indices.add(best_gt_idx)
                else:
                    total_fp += 1

            # Count missed ground truth objects as FN
            total_fn += (len(gt_objects) - len(matched_gt_indices))

    precision = total_tp / (total_tp + total_fp) if (total_tp + total_fp) > 0 else 0.0
    recall = total_tp / (total_tp + total_fn) if (total_tp + total_fn) > 0 else 0.0
    f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0

    return {
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1_score": round(f1, 4),
        "true_positives": total_tp,
        "false_positives": total_fp,
        "false_negatives": total_fn,
        "total_gt_objects": total_gt_objects,
        "total_frames_processed": total_frames_processed,
        "iou_threshold": IOU_THRESHOLD,
        "confidence_threshold": CONFIDENCE_THRESHOLD
    }


def validate_transformation_time(
    start_time: float,
    end_time: Optional[float] = None
) -> Tuple[bool, float, Dict[str, Any]]:
    """
    Validate that the transformation process completed within the specified time constraint.

    Args:
        start_time: Unix timestamp of when the transformation started.
        end_time: Unix timestamp of when the transformation ended. If None, uses current time.

    Returns:
        Tuple of (is_valid, duration_seconds, details_dict)
    """
    if end_time is None:
        end_time = time.time()

    duration_seconds = end_time - start_time
    duration_hours = duration_seconds / 3600.0
    is_valid = duration_hours <= MAX_TRANSFORMATION_TIME_HOURS

    details = {
        "start_timestamp": datetime.fromtimestamp(start_time).isoformat(),
        "end_timestamp": datetime.fromtimestamp(end_time).isoformat() if end_time else "ongoing",
        "duration_seconds": round(duration_seconds, 2),
        "duration_hours": round(duration_hours, 4),
        "max_allowed_hours": MAX_TRANSFORMATION_TIME_HOURS,
        "constraint_met": is_valid
    }

    return is_valid, duration_seconds, details


def main():
    """
    Main entry point for the validation script.
    Performs precision/recall calculation and time constraint validation.
    """
    print(f"Starting perception validation at {datetime.now().isoformat()}")

    # Paths
    gt_path = DATA_RAW_DIR / "ground_truth_annotations.json"
    processed_dir = DATA_PROCESSED_DIR
    output_path = DATA_ARTIFACTS_DIR / "validation_results.json"

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # 1. Calculate Metrics
    print("Calculating precision/recall metrics...")
    try:
        metrics = calculate_metrics_from_ground_truth(processed_dir, gt_path)
        print(f"  Precision: {metrics['precision']}")
        print(f"  Recall: {metrics['recall']}")
        print(f"  F1 Score: {metrics['f1_score']}")
    except FileNotFoundError as e:
        print(f"ERROR: Could not load data for metrics: {e}")
        sys.exit(1)

    # 2. Validate Time Constraint
    # We attempt to read a start timestamp from a log file if it exists, otherwise assume current time (fail if running long)
    # In a real pipeline, the transform script would write a start_time to a log.
    # For this validation step, we assume the transform has just finished or we are checking historical data.
    # If we are re-running validation on existing data, we cannot measure the *past* runtime unless it was logged.
    # We will simulate a check by assuming the "process" is the time taken to read and process files now,
    # OR we read a log file if T018/T014 wrote one.
    # Since T014/T018 write logs, let's try to find a 'transform_start_time' in a log or just report current status.
    # For the purpose of this task, we will assume the validation is run immediately after transformation or
    # we check the file modification times to infer duration if a specific log isn't available.
    # However, the task asks to "verify the completion time constraint".
    # We will assume a log file `data/artifacts/transform_timestamps.json` might exist from the transformer.
    timestamp_log = DATA_ARTIFACTS_DIR / "transform_timestamps.json"
    time_valid = False
    time_details = {"message": "No start time found in logs"}

    if timestamp_log.exists():
        with open(timestamp_log, 'r', encoding='utf-8') as f:
            ts_data = json.load(f)
        start_ts = ts_data.get("start_time")
        end_ts = ts_data.get("end_time")
        if start_ts and end_ts:
            time_valid, _, time_details = validate_transformation_time(start_ts, end_ts)
    else:
        # Fallback: If no log, we cannot verify historical time.
        # We will log a warning and set valid to False to force manual check or re-run with logging.
        print("WARNING: transform_timestamps.json not found. Cannot verify historical time constraint.")
        time_valid = False
        time_details = {"message": "Start/End timestamps not found in artifacts"}

    # Compile Results
    results = {
        "timestamp": datetime.now().isoformat(),
        "metrics": metrics,
        "time_validation": {
            "valid": time_valid,
            "details": time_details
        },
        "constraints": {
            "min_precision": 0.5, # Example threshold, adjust based on spec
            "min_recall": 0.5,
            "max_time_hours": MAX_TRANSFORMATION_TIME_HOURS
        },
        "overall_pass": (
            metrics["precision"] >= 0.5 and
            metrics["recall"] >= 0.5 and
            time_valid
        )
    }

    # Write Output
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(results, f, indent=2)

    print(f"Validation results written to {output_path}")
    print(f"Overall Status: {'PASS' if results['overall_pass'] else 'FAIL'}")

    if not results['overall_pass']:
        sys.exit(1)

    return results


if __name__ == "__main__":
    main()