"""
Task T013b: Verify data/raw/guava/ integrity using checksums.json.

This script loads the checksum manifest generated by T013a (download_guava.py)
and verifies the SHA-256 hashes of all files in the raw Guava dataset directory.

It logs the result to the console and exits with code 0 on success, 
or code 1 if any file is missing or has a mismatched hash.

Dependencies:
- data/raw/guava/ directory must exist (created by T013a)
- data/raw/guava/checksums.json must exist (created by T013a)
"""
import json
import hashlib
import os
import sys
from pathlib import Path
from datetime import datetime

# Project root relative to this script's location
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
RAW_DATA_DIR = PROJECT_ROOT / "data" / "raw" / "guava"
CHECKSUM_FILE = RAW_DATA_DIR / "checksums.json"
LOG_FILE = PROJECT_ROOT / "data" / "artifacts" / "integrity_verification_log.json"

# Ensure artifact directory exists
LOG_FILE.parent.mkdir(parents=True, exist_ok=True)

def calculate_sha256(file_path: Path) -> str:
    """Calculate SHA-256 hash of a file."""
    sha256_hash = hashlib.sha256()
    try:
        with open(file_path, "rb") as f:
            for chunk in iter(lambda: f.read(4096), b""):
                sha256_hash.update(chunk)
        return sha256_hash.hexdigest()
    except (IOError, OSError) as e:
        raise RuntimeError(f"Failed to read file {file_path}: {e}")

def verify_integrity() -> dict:
    """
    Verify the integrity of all files in data/raw/guava/ against checksums.json.
    
    Returns:
        dict: Verification results summary.
    """
    if not RAW_DATA_DIR.exists():
        return {
            "status": "failed",
            "error": f"Raw data directory not found: {RAW_DATA_DIR}",
            "timestamp": datetime.now().isoformat(),
            "verified_count": 0,
            "failed_count": 0,
            "missing_count": 0
        }

    if not CHECKSUM_FILE.exists():
        return {
            "status": "failed",
            "error": f"Checksum file not found: {CHECKSUM_FILE}",
            "timestamp": datetime.now().isoformat(),
            "verified_count": 0,
            "failed_count": 0,
            "missing_count": 0
        }

    # Load checksums
    try:
        with open(CHECKSUM_FILE, "r", encoding="utf-8") as f:
            checksums = json.load(f)
    except json.JSONDecodeError as e:
        return {
            "status": "failed",
            "error": f"Invalid JSON in checksum file: {e}",
            "timestamp": datetime.now().isoformat(),
            "verified_count": 0,
            "failed_count": 0,
            "missing_count": 0
        }

    verified_files = []
    failed_files = []
    missing_files = []
    
    total_files = len(checksums)
    start_time = datetime.now()

    print(f"Verifying integrity of {total_files} files in {RAW_DATA_DIR}...")

    for file_rel_path, expected_hash in checksums.items():
        file_path = RAW_DATA_DIR / file_rel_path
        
        if not file_path.exists():
            missing_files.append(file_rel_path)
            print(f"  [MISSING] {file_rel_path}")
            continue

        try:
            actual_hash = calculate_sha256(file_path)
            if actual_hash == expected_hash:
                verified_files.append(file_rel_path)
            else:
                failed_files.append({
                    "file": file_rel_path,
                    "expected": expected_hash,
                    "actual": actual_hash
                })
                print(f"  [MISMATCH] {file_rel_path}")
        except Exception as e:
            failed_files.append({
                "file": file_rel_path,
                "error": str(e)
            })
            print(f"  [ERROR] {file_rel_path}: {e}")

    end_time = datetime.now()
    duration = (end_time - start_time).total_seconds()

    result = {
        "status": "passed" if (len(missing_files) == 0 and len(failed_files) == 0) else "failed",
        "timestamp": start_time.isoformat(),
        "duration_seconds": duration,
        "total_files": total_files,
        "verified_count": len(verified_files),
        "failed_count": len(failed_files),
        "missing_count": len(missing_files),
        "verified_files": verified_files,
        "failed_files": failed_files,
        "missing_files": missing_files
    }

    return result

def main():
    """Main entry point for integrity verification."""
    print("=" * 60)
    print("T013b: Guava Dataset Integrity Verification")
    print("=" * 60)
    
    result = verify_integrity()
    
    # Log result to artifact file
    with open(LOG_FILE, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2)
    
    print(f"\nVerification completed in {result['duration_seconds']:.2f}s")
    print(f"Status: {result['status'].upper()}")
    print(f"Verified: {result['verified_count']}/{result['total_files']}")
    
    if result['missing_count'] > 0:
        print(f"Missing: {result['missing_count']} files")
    if result['failed_count'] > 0:
        print(f"Failed: {result['failed_count']} files")
    
    print(f"\nDetailed log written to: {LOG_FILE}")
    
    # Exit with appropriate code
    if result['status'] == 'passed':
        print("\n✓ All files verified successfully.")
        sys.exit(0)
    else:
        print("\n✗ Integrity verification failed.")
        sys.exit(1)

if __name__ == "__main__":
    main()