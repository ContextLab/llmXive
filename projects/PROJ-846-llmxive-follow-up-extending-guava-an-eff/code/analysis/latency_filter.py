import json
import os
import sys
from pathlib import Path
from typing import List, Dict, Any, Optional
from utils.config import get_path, get_hyperparameter

def load_categorized_outcomes() -> List[Dict[str, Any]]:
    """
    Load the categorized task outcomes from the data/processed directory.
    This file is expected to be generated by the failure categorizer (T033).
    """
    input_path = get_path("processed", "evaluation_outcomes_categorized.json")
    if not os.path.exists(input_path):
        raise FileNotFoundError(
            f"Categorized outcomes file not found at {input_path}. "
            "Please run the failure categorization task (T033) first."
        )
    
    with open(input_path, 'r') as f:
        return json.load(f)

def is_latency_failure(outcome: Dict[str, Any]) -> bool:
    """
    Determine if a specific task outcome is a latency-induced failure.
    
    Logic:
    1. Check if the outcome is marked as a failure (success == False).
    2. Check if the failure_category is explicitly 'latency'.
    
    Args:
        outcome: A dictionary representing a TaskOutcome.
    
    Returns:
        True if the failure is due to latency, False otherwise.
    """
    if outcome.get("success", True):
        return False
    
    failure_category = outcome.get("failure_category", "")
    # Check for exact match or list containment if the category is stored differently
    if failure_category == "latency":
        return True
    
    # Handle cases where failure_category might be a list or contain multiple tags
    if isinstance(failure_category, list):
        return "latency" in failure_category
    
    return False

def filter_latency_failures(outcomes: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Filter out latency-induced failures from the list of outcomes.
    
    This implements the logic for FR-008:
    "Filter out latency-induced failures from the primary success rate calculation."
    
    Args:
        outcomes: List of all task outcomes (categorized).
    
    Returns:
        A new list containing only non-latency outcomes (successes + non-latency failures).
    """
    filtered = []
    for outcome in outcomes:
        if not is_latency_failure(outcome):
            filtered.append(outcome)
    return filtered

def write_filtered_outcomes(filtered_outcomes: List[Dict[str, Any]], stats: Dict[str, Any]) -> None:
    """
    Write the filtered outcomes and exclusion statistics to the processed data directory.
    
    Output:
        data/processed/evaluation_outcomes.json (filtered list)
        data/processed/evaluation_outcomes_stats.json (metadata about the filtering)
    
    Args:
        filtered_outcomes: The list of outcomes with latency failures removed.
        stats: Dictionary containing counts of total, excluded, and remaining outcomes.
    """
    output_path = get_path("processed", "evaluation_outcomes.json")
    stats_path = get_path("processed", "evaluation_outcomes_stats.json")
    
    # Ensure directory exists
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    # Write filtered outcomes
    with open(output_path, 'w') as f:
        json.dump(filtered_outcomes, f, indent=2)
    
    # Write statistics
    with open(stats_path, 'w') as f:
        json.dump(stats, f, indent=2)

def main():
    """
    Main entry point for T035: Filter latency-induced failures.
    
    1. Load categorized outcomes (from T033).
    2. Identify and remove latency-induced failures.
    3. Write the updated outcomes to data/processed/evaluation_outcomes.json.
    4. Log the exclusion statistics.
    """
    print("Starting T035: Filtering latency-induced failures...")
    
    try:
        # Load input
        outcomes = load_categorized_outcomes()
        total_count = len(outcomes)
        print(f"Loaded {total_count} categorized outcomes.")
        
        # Filter
        filtered_outcomes = filter_latency_failures(outcomes)
        filtered_count = len(filtered_outcomes)
        
        # Calculate stats
        latency_failure_count = total_count - filtered_count
        
        stats = {
            "total_outcomes": total_count,
            "latency_failures_excluded": latency_failure_count,
            "remaining_outcomes": filtered_count,
            "exclusion_reason": "Latency > 150ms threshold (FR-008)",
            "timestamp": __import__('datetime').datetime.now().isoformat()
        }
        
        # Write output
        write_filtered_outcomes(filtered_outcomes, stats)
        
        print(f"Filtering complete.")
        print(f"  Total: {total_count}")
        print(f"  Excluded (Latency): {latency_failure_count}")
        print(f"  Remaining: {filtered_count}")
        print(f"Output written to: {get_path('processed', 'evaluation_outcomes.json')}")
        
    except FileNotFoundError as e:
        print(f"Error: {e}")
        sys.exit(1)
    except Exception as e:
        print(f"Unexpected error during filtering: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
