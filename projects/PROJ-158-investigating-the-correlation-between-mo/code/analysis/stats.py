"""
Statistical analysis module for User Story 2.
Computes fold-wise metrics and performs statistical comparison between GCN and RF models.

This module implements the primary statistical tests required by FR-006 and SC-003:
- Paired t-test on fold-wise MAE
- Cohen's d effect size calculation
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, List, Any, Optional, Tuple

import numpy as np
from scipy import stats

# Add project root to path for imports if running as script
if __name__ == "__main__":
    project_root = Path(__file__).resolve().parent.parent.parent
    sys.path.insert(0, str(project_root))

from utils.config import get_config
from utils.logger import setup_logger

# Initialize logger
logger = setup_logger("stats")
config = get_config()
RESULTS_DIR = config["results_dir"]
FOLD_METRICS_PATH = Path(RESULTS_DIR) / "fold_metrics.json"
STATS_SUMMARY_PATH = Path(RESULTS_DIR) / "stats_summary.json"


def load_fold_metrics() -> Dict[str, Any]:
    """
    Load fold-wise metrics from the file generated by T019.
    
    Returns:
        Dictionary containing metrics for each fold and model.
        
    Raises:
        FileNotFoundError: If the metrics file does not exist.
        json.JSONDecodeError: If the file content is not valid JSON.
    """
    if not FOLD_METRICS_PATH.exists():
        logger.error(f"Fold metrics file not found: {FOLD_METRICS_PATH}")
        raise FileNotFoundError(f"Fold metrics file not found: {FOLD_METRICS_PATH}")
    
    with open(FOLD_METRICS_PATH, 'r') as f:
        return json.load(f)


def compute_fold_metrics(metrics_data: Dict[str, Any]) -> Dict[str, List[float]]:
    """
    Extract fold-wise MAE, RMSE, and R² for both GCN and RF models.
    
    Args:
        metrics_data: The raw metrics dictionary loaded from fold_metrics.json.
        
    Returns:
        Dictionary with keys 'gcn' and 'rf', each mapping to a list of metric dictionaries
        containing 'mae', 'rmse', and 'r2' for each fold.
    """
    results = {
        'gcn': [],
        'rf': []
    }
    
    # Expected structure: { "folds": [ { "fold_id": 0, "gcn": {...}, "rf": {...} }, ... ] }
    # or potentially just a flat list of fold results.
    folds = metrics_data.get("folds", [])
    
    if not folds:
        # Fallback: check if the root is the list
        if isinstance(metrics_data, list):
            folds = metrics_data
        else:
            logger.warning("No 'folds' key found in metrics data. Attempting to parse structure...")
            # Try to find a key that looks like folds
            for key in metrics_data:
                if isinstance(metrics_data[key], list) and len(metrics_data[key]) > 0:
                    folds = metrics_data[key]
                    break
    
    for fold in folds:
        fold_id = fold.get("fold_id", len(results['gcn']))
        
        gcn_metrics = fold.get("gcn", fold.get("GCN", {}))
        rf_metrics = fold.get("rf", fold.get("RF", {}))
        
        # Extract specific metrics, handling potential key variations
        gcn_entry = {
            "fold_id": fold_id,
            "mae": float(gcn_metrics.get("mae", gcn_metrics.get("MAE", 0.0))),
            "rmse": float(gcn_metrics.get("rmse", gcn_metrics.get("RMSE", 0.0))),
            "r2": float(gcn_metrics.get("r2", gcn_metrics.get("R2", 0.0)))
        }
        
        rf_entry = {
            "fold_id": fold_id,
            "mae": float(rf_metrics.get("mae", rf_metrics.get("MAE", 0.0))),
            "rmse": float(rf_metrics.get("rmse", rf_metrics.get("RMSE", 0.0))),
            "r2": float(rf_metrics.get("r2", rf_metrics.get("R2", 0.0)))
        }
        
        results['gcn'].append(gcn_entry)
        results['rf'].append(rf_entry)
        
        logger.debug(f"Processed fold {fold_id}: GCN MAE={gcn_entry['mae']:.4f}, RF MAE={rf_entry['mae']:.4f}")

    return results


def compute_cohen_d(group1: List[float], group2: List[float]) -> float:
    """
    Calculate Cohen's d effect size for two groups.
    
    Cohen's d = (mean1 - mean2) / pooled_std
    where pooled_std = sqrt(((n1-1)*std1^2 + (n2-1)*std2^2) / (n1 + n2 - 2))
    
    Args:
        group1: List of values for the first group (GCN MAEs).
        group2: List of values for the second group (RF MAEs).
        
    Returns:
        Cohen's d value.
    """
    if len(group1) != len(group2):
        raise ValueError("Group sizes must be equal for paired test effect size.")
    
    n = len(group1)
    if n < 2:
        logger.warning("Less than 2 samples; returning 0.0 for Cohen's d.")
        return 0.0
    
    mean1 = np.mean(group1)
    mean2 = np.mean(group2)
    
    std1 = np.std(group1, ddof=1)
    std2 = np.std(group2, ddof=1)
    
    # Pooled standard deviation
    pooled_std = np.sqrt(((n - 1) * std1**2 + (n - 1) * std2**2) / (2 * n - 2))
    
    if pooled_std == 0:
        logger.warning("Pooled standard deviation is zero; returning 0.0 for Cohen's d.")
        return 0.0
    
    return (mean1 - mean2) / pooled_std


def perform_statistical_tests(gcn_maes: List[float], rf_maes: List[float]) -> Dict[str, Any]:
    """
    Perform paired t-test and calculate Cohen's d for GCN vs RF MAEs.
    
    Args:
        gcn_maes: List of MAE values for GCN model across folds.
        rf_maes: List of MAE values for RF model across folds.
        
    Returns:
        Dictionary containing:
            - 't_statistic': t-statistic from paired t-test
            - 'p_value': p-value from paired t-test
            - 'cohen_d': Cohen's d effect size
            - 'significant': Boolean indicating if p < 0.05
            - 'test_type': Description of the test performed
    """
    if len(gcn_maes) != len(rf_maes):
        raise ValueError("Number of folds must be equal for paired t-test.")
    
    if len(gcn_maes) < 2:
        logger.warning("Insufficient folds (< 2) for statistical testing.")
        return {
            "t_statistic": None,
            "p_value": None,
            "cohen_d": None,
            "significant": False,
            "test_type": "skipped_insufficient_samples",
            "message": "Insufficient folds for statistical testing."
        }
    
    # Perform paired t-test
    t_stat, p_value = stats.ttest_rel(gcn_maes, rf_maes)
    
    # Calculate Cohen's d
    d = compute_cohen_d(gcn_maes, rf_maes)
    
    significance_level = 0.05
    significant = p_value < significance_level if p_value is not None else False
    
    return {
        "t_statistic": float(t_stat) if t_stat is not None else None,
        "p_value": float(p_value) if p_value is not None else None,
        "cohen_d": float(d) if d is not None else None,
        "significant": significant,
        "test_type": "paired_t_test",
        "significance_level": significance_level,
        "num_folds": len(gcn_maes)
    }


def main():
    """
    Main entry point for T022.
    Loads fold metrics, performs paired t-test and Cohen's d calculation,
    and saves the statistical summary to results/stats_summary.json.
    """
    logger.info("Starting T022: Performing statistical comparison between GCN and RF models.")
    
    try:
        # 1. Load raw fold metrics (from T019)
        raw_metrics = load_fold_metrics()
        logger.info(f"Loaded metrics from {FOLD_METRICS_PATH}")
        
        # 2. Compute structured fold metrics (from T021 logic)
        processed_metrics = compute_fold_metrics(raw_metrics)
        
        if not processed_metrics['gcn'] or not processed_metrics['rf']:
            logger.error("Failed to extract valid metrics for one or both models.")
            raise ValueError("No valid metrics found for GCN or RF models.")
        
        # 3. Extract MAE lists for statistical testing
        gcn_maes = [entry['mae'] for entry in processed_metrics['gcn']]
        rf_maes = [entry['mae'] for entry in processed_metrics['rf']]
        
        logger.info(f"Extracted {len(gcn_maes)} fold-wise MAE values for each model.")
        logger.info(f"GCN MAE mean: {np.mean(gcn_maes):.4f}, std: {np.std(gcn_maes):.4f}")
        logger.info(f"RF MAE mean: {np.mean(rf_maes):.4f}, std: {np.std(rf_maes):.4f}")
        
        # 4. Perform statistical tests (Primary: Paired T-Test + Cohen's D)
        test_results = perform_statistical_tests(gcn_maes, rf_maes)
        
        # 5. Prepare summary structure
        summary = {
            "gcn_fold_metrics": processed_metrics['gcn'],
            "rf_fold_metrics": processed_metrics['rf'],
            "num_folds": len(processed_metrics['gcn']),
            "status": "statistical_analysis_complete",
            "statistical_tests": {
                "paired_t_test": test_results
            },
            "interpretation": {
                "model_with_lower_mae": "GCN" if np.mean(gcn_maes) < np.mean(rf_maes) else "RF",
                "difference_in_mean_mae": float(abs(np.mean(gcn_maes) - np.mean(rf_maes))),
                "effect_size_category": interpret_cohen_d(test_results.get('cohen_d'))
            }
        }
        
        # 6. Ensure directory exists and save results
        STATS_SUMMARY_PATH.parent.mkdir(parents=True, exist_ok=True)
        
        with open(STATS_SUMMARY_PATH, 'w') as f:
            json.dump(summary, f, indent=2)
        
        logger.info(f"Successfully saved statistical summary to {STATS_SUMMARY_PATH}")
        logger.info(f"T-statistic: {test_results['t_statistic']:.4f}, p-value: {test_results['p_value']:.4f}")
        logger.info(f"Cohen's d: {test_results['cohen_d']:.4f} ({summary['interpretation']['effect_size_category']})")
        logger.info(f"Statistically significant (p < {test_results['significance_level']}): {test_results['significant']}")
        
        return 0

    except FileNotFoundError as e:
        logger.critical(f"Input file missing: {e}")
        return 1
    except json.JSONDecodeError as e:
        logger.critical(f"Invalid JSON in metrics file: {e}")
        return 2
    except ValueError as e:
        logger.critical(f"Data error: {e}")
        return 3
    except Exception as e:
        logger.critical(f"Unexpected error during statistical analysis: {e}", exc_info=True)
        return 1


def interpret_cohen_d(d: Optional[float]) -> str:
    """
    Interpret the magnitude of Cohen's d effect size.
    
    Args:
        d: Cohen's d value.
        
    Returns:
        String description of the effect size magnitude.
    """
    if d is None:
        return "undefined"
    
    abs_d = abs(d)
    if abs_d < 0.2:
        return "negligible"
    elif abs_d < 0.5:
        return "small"
    elif abs_d < 0.8:
        return "medium"
    else:
        return "large"


if __name__ == "__main__":
    sys.exit(main())
