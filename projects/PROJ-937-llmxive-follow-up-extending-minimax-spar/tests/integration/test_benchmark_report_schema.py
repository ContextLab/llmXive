"""
Integration test for T036: Verify results/benchmark_report.json schema.

This test ensures the benchmark report generated by the pipeline contains
all required keys for metrics and statistical tests as specified in T036.

Required keys:
- f1_score
- p_value
- false_positive_rate
- sensitivity_table
- ttest_stat
- wilcoxon_stat
"""
import json
import os
import pytest
from pathlib import Path

# Expected schema keys defined in T036
REQUIRED_KEYS = {
    "f1_score",
    "p_value",
    "false_positive_rate",
    "sensitivity_table",
    "ttest_stat",
    "wilcoxon_stat"
}

REPORT_PATH = Path("results/benchmark_report.json")

@pytest.fixture(scope="module")
def report_data():
    """Load the benchmark report if it exists."""
    if not REPORT_PATH.exists():
        pytest.skip(f"Report file {REPORT_PATH} not found. Run pipeline to generate report.")
    
    with open(REPORT_PATH, "r", encoding="utf-8") as f:
        return json.load(f)

def test_report_file_exists():
    """Verify the report file exists at the expected path."""
    assert REPORT_PATH.exists(), f"Report file {REPORT_PATH} does not exist."

def test_report_is_valid_json(report_data):
    """Verify the report is valid JSON (already handled by fixture, but explicit check)."""
    assert isinstance(report_data, (dict, list)), "Report data must be a JSON object or array."

def test_required_keys_present(report_data):
    """
    Verify all required keys are present in the report.
    
    Checks for:
    - f1_score
    - p_value
    - false_positive_rate
    - sensitivity_table
    - ttest_stat
    - wilcoxon_stat
    """
    if isinstance(report_data, dict):
        # Direct keys at root level
        present_keys = set(report_data.keys())
    elif isinstance(report_data, list) and len(report_data) > 0:
        # If it's a list of experiments, check the first one or aggregate
        # Assuming the structure might be nested, we flatten check
        all_keys = set()
        for item in report_data:
            if isinstance(item, dict):
                all_keys.update(item.keys())
        present_keys = all_keys
    else:
        raise AssertionError("Report structure is neither a dict nor a non-empty list.")

    missing_keys = REQUIRED_KEYS - present_keys
    assert not missing_keys, f"Missing required keys in benchmark report: {missing_keys}"

