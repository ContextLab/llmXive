def test_report_has_heuristic_comparison(report_data):
    """
    Verify the report contains evidence of heuristic comparison (e.g., baseline vs heuristic).
    This ensures the report is not just a static template.
    """
    # Check for common keys that indicate comparison logic ran
    comparison_indicators = {"baseline", "heuristic", "delta", "accuracy", "f1"}
    
    if isinstance(report_data, dict):
        keys = set(report_data.keys())
    else:
        keys = set()
        for item in report_data:
            if isinstance(item, dict):
                keys.update(item.keys())
    
    # We expect at least some overlap with comparison indicators
    # This is a soft check to ensure the report isn't empty of content
    assert len(keys.intersection(comparison_indicators)) > 0, "Report lacks evidence of heuristic comparison."