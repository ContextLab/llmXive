def _load_or_generate_data():
    """
    Loads preprocessed data if it exists, otherwise generates mock data 
    and runs the preprocessing pipeline to create the splits needed for training.
    
    This ensures the integration test has valid input data without relying 
    on external network fetches during the test run, while still testing 
    the full pipeline logic.
    """
    train_path = PROCESSED_DIR / "train.parquet"
    
    if train_path.exists():
        logger.info(f"Found existing train data at {train_path}")
        return True

    logger.info("No existing split data found. Generating mock data and preprocessing...")
    
    # Verify if we can generate mock data (fallback if real data not reachable)
    # Note: In a strict CI environment, we might want to fail if real data isn't present.
    # However, for this integration test to run independently, we ensure valid input exists.
    # The task T026 is about the training loop, not the data fetch.
    
    # Generate mock data to ensure the pipeline has something to train on
    try:
        generate_mock_dataset(RAW_DIR)
        logger.info("Mock data generated successfully.")
    except Exception as e:
        logger.error(f"Failed to generate mock data: {e}")
        # If we can't generate mock data, we can't proceed with integration test
        # This is a critical failure for the test environment
        raise RuntimeError("Cannot generate mock data for integration test setup.")

    # Run preprocessing to create splits
    # We need to simulate the steps from T018-T023
    from preprocess import match_accessions, filter_missingness, encode_genotypes, save_unified_dataset, stratified_split
    
    # Load raw mock data
    accession_file = RAW_DIR / "accessions.csv"
    phenotype_file = RAW_DIR / "phenotypes.csv"
    genotype_file = RAW_DIR / "genotypes.csv"
    
    if not all(f.exists() for f in [accession_file, phenotype_file, genotype_file]):
        raise FileNotFoundError("Mock data files not found after generation.")
    
    accessions = pd.read_csv(accession_file)
    phenotypes = pd.read_csv(phenotype_file)
    genotypes = pd.read_csv(genotype_file)
    
    # Match accessions
    logger.info("Matching accessions...")
    matched = match_accessions(accessions, phenotypes, genotypes)
    
    if matched is None or matched.empty:
        raise ValueError("No matched data found. Preprocessing failed.")
    
    # Filter missingness
    logger.info("Filtering missingness...")
    filtered = filter_missingness(matched, threshold=0.05)
    
    if filtered is None or filtered.empty:
        raise ValueError("Data filtered out completely. Missingness threshold too high or data empty.")
    
    # Encode genotypes
    logger.info("Encoding genotypes...")
    encoded = encode_genotypes(filtered)
    
    if encoded is None or encoded.empty:
        raise ValueError("Genotype encoding failed.")
    
    # Save unified dataset
    logger.info("Saving unified dataset...")
    unified_path = PROCESSED_DIR / "unified_dataset.parquet"
    save_unified_dataset(encoded, unified_path, is_mock=True)
    
    # Stratified split
    logger.info("Performing stratified split...")
    splits = stratified_split(encoded, target_col="phenotype_value", group_col="nutrient_condition", test_size=0.1, val_size=0.1, random_state=42)
    
    if not splits:
        raise ValueError("Stratified split returned empty results.")
    
    # Save splits
    for split_name, split_data in splits.items():
        split_path = PROCESSED_DIR / f"{split_name}.parquet"
        split_data.to_parquet(split_path, index=False)
        logger.info(f"Saved {split_name} data to {split_path}")
    
    return True

