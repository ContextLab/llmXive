"""
Contract test for final JSON output schema.

Validates that all result JSON files generated by the pipeline conform to the
expected schema structure defined in contracts/simulation_schema.json.

This test ensures:
1. All required top-level keys are present
2. Metadata structure is correct (including disclaimer)
3. Error rate calculations are present and numeric
4. P-value distributions are arrays of floats
5. All required fields match the schema definition
"""

import json
import os
import pytest
from pathlib import Path
from typing import Dict, Any, List

import jsonschema


@pytest.fixture
def schema_path() -> Path:
    """Load the simulation schema from contracts directory."""
    return Path("contracts/simulation_schema.json")


@pytest.fixture
def schema(schema_path: Path) -> Dict[str, Any]:
    """Load and parse the JSON schema."""
    with open(schema_path, 'r') as f:
        return json.load(f)


@pytest.fixture
def results_dir() -> Path:
    """Get the results directory path."""
    return Path("results")


@pytest.fixture
def result_files(results_dir: Path) -> List[Path]:
    """Find all JSON files in the results directory."""
    if not results_dir.exists():
        return []
    return list(results_dir.glob("*.json"))


def test_schema_exists(schema_path: Path):
    """Verify the schema file exists."""
    assert schema_path.exists(), f"Schema file not found at {schema_path}"

def test_schema_is_valid_json(schema):
    """Verify the schema is valid JSON and has required structure."""
    assert isinstance(schema, dict), "Schema must be a dictionary"
    assert "type" in schema, "Schema must have a 'type' field"
    assert schema["type"] == "object", "Root schema type must be 'object'"

def test_all_result_files_conform_to_schema(result_files: List[Path], schema: Dict[str, Any]):
    """
    Test that all result JSON files in the results directory conform to the schema.
    
    This is the main contract test that validates the output format.
    """
    if not result_files:
        pytest.skip("No result files found in results directory")
    
    for file_path in result_files:
        with open(file_path, 'r') as f:
            try:
                data = json.load(f)
            except json.JSONDecodeError as e:
                pytest.fail(f"File {file_path} is not valid JSON: {e}")
        
        try:
            jsonschema.validate(instance=data, schema=schema)
        except jsonschema.ValidationError as e:
            pytest.fail(
                f"File {file_path} does not conform to schema.\n"
                f"Error: {e.message}\n"
                f"Path: {list(e.path)}\n"
                f"Instance: {e.instance}"
            )

def test_metadata_disclaimer_present(result_files: List[Path]):
    """
    Verify that all result files contain the required disclaimer in metadata.
    
    Per FR-007, every result JSON file must include:
    metadata.disclaimer = "DISCLAIMER: Findings are associational..."
    """
    required_disclaimer_prefix = "DISCLAIMER: Findings are associational"
    
    if not result_files:
        pytest.skip("No result files found in results directory")
    
    for file_path in result_files:
        with open(file_path, 'r') as f:
            data = json.load(f)
        
        assert "metadata" in data, f"File {file_path} missing 'metadata' key"
        assert "disclaimer" in data["metadata"], f"File {file_path} missing 'metadata.disclaimer'"
        
        disclaimer = data["metadata"]["disclaimer"]
        assert isinstance(disclaimer, str), f"File {file_path} disclaimer must be a string"
        assert disclaimer.startswith(required_disclaimer_prefix), (
            f"File {file_path} disclaimer does not start with required prefix. "
            f"Got: {disclaimer[:50]}..."
        )

def test_error_rates_are_numeric(result_files: List[Path]):
    """Verify that error rate fields contain numeric values."""
    if not result_files:
        pytest.skip("No result files found in results directory")
    
    for file_path in result_files:
        with open(file_path, 'r') as f:
            data = json.load(f)
        
        # Check Type I error rate
        if "type_i_error_rate" in data:
            assert isinstance(data["type_i_error_rate"], (int, float)), (
                f"File {file_path}: type_i_error_rate must be numeric"
            )
        
        # Check Type II error rate
        if "type_ii_error_rate" in data:
            assert isinstance(data["type_ii_error_rate"], (int, float)), (
                f"File {file_path}: type_ii_error_rate must be numeric"
            )
        
        # Check confidence intervals
        if "type_i_error_ci" in data:
            ci = data["type_i_error_ci"]
            assert isinstance(ci, list) and len(ci) == 2, (
                f"File {file_path}: type_i_error_ci must be a list of 2 numbers"
            )
            assert all(isinstance(x, (int, float)) for x in ci), (
                f"File {file_path}: type_i_error_ci values must be numeric"
            )

def test_pvalue_distributions_are_arrays(result_files: List[Path]):
    """Verify that p-value distribution fields are arrays of numbers."""
    if not result_files:
        pytest.skip("No result files found in results directory")
    
    for file_path in result_files:
        with open(file_path, 'r') as f:
            data = json.load(f)
        
        # Check p-value distributions if present
        for key in ["p_values_null", "p_values_alt"]:
            if key in data:
                p_values = data[key]
                assert isinstance(p_values, list), (
                    f"File {file_path}: {key} must be a list"
                )
                assert all(isinstance(p, (int, float)) for p in p_values), (
                    f"File {file_path}: {key} must contain only numeric values"
                )

def test_required_top_level_keys(result_files: List[Path], schema: Dict[str, Any]):
    """
    Verify that all required top-level keys from the schema are present.
    """
    if not result_files:
        pytest.skip("No result files found in results directory")
    
    required_keys = schema.get("required", [])
    
    for file_path in result_files:
        with open(file_path, 'r') as f:
            data = json.load(f)
        
        for key in required_keys:
            assert key in data, (
                f"File {file_path} missing required key: {key}"
            )

def test_fixed_design_threshold_present(result_files: List[Path]):
    """
    Verify that the fixed design threshold (0.10) is present in the output.
    
    Per SC-001, the fixed design threshold value must be included in JSON output.
    """
    if not result_files:
        pytest.skip("No result files found in results directory")
    
    for file_path in result_files:
        with open(file_path, 'r') as f:
            data = json.load(f)
        
        # Check in metadata
        if "metadata" in data and "fixed_design_threshold" in data["metadata"]:
            threshold = data["metadata"]["fixed_design_threshold"]
            assert threshold == 0.10, (
                f"File {file_path}: fixed_design_threshold must be 0.10, got {threshold}"
            )
            return  # Found it, move to next file
        
        # Check at root level
        if "fixed_design_threshold" in data:
            threshold = data["fixed_design_threshold"]
            assert threshold == 0.10, (
                f"File {file_path}: fixed_design_threshold must be 0.10, got {threshold}"
            )
            return  # Found it, move to next file
        
        # If we get here, the threshold is missing
        pytest.fail(f"File {file_path} missing fixed_design_threshold (must be 0.10)")