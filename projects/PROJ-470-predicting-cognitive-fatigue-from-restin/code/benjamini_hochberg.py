"""
Benjamini-Hochberg Correction for Multiple Comparisons (T022)

Implements the Benjamini-Hochberg procedure to control the False Discovery Rate (FDR)
across multiple hypothesis tests (one per electrode/channel) as required by FR-005.

Input: data/analysis/correlation_results.csv (generated by T020)
Output: data/analysis/bh_corrected_pvalues.csv
"""
import os
import sys
import json
import logging
import pandas as pd
import numpy as np
from pathlib import Path

# Import shared utilities from existing API surface
# Note: Assuming setup_logger and load_config exist in analysis.py or utils
# Since we cannot import from analysis.py directly without circular risks if not careful,
# we will implement minimal config loading here or reuse if available.
# The API surface shows `from analysis import load_config, setup_logger`.
# We will import them to maintain consistency.
from analysis import load_config, setup_logger


def run_benjamini_hochberg(p_values: pd.Series, alpha: float = 0.05) -> pd.DataFrame:
    """
    Apply the Benjamini-Hochberg FDR correction to a series of p-values.

    Parameters
    ----------
    p_values : pd.Series
        Series of raw p-values. Index should be the electrode/channel name.
    alpha : float
        Desired FDR level (default 0.05).

    Returns
    -------
    pd.DataFrame
        DataFrame with columns: ['electrode', 'raw_p', 'bh_p', 'is_significant']
    """
    if p_values.empty:
        raise ValueError("Input p-values series is empty. Cannot run BH correction.")

    # Create a working copy to avoid modifying the original
    df = pd.DataFrame({'raw_p': p_values})
    df = df.reset_index().rename(columns={'index': 'electrode'})

    # Sort by p-value
    df = df.sort_values('raw_p').reset_index(drop=True)

    n = len(df)
    if n == 0:
        return pd.DataFrame(columns=['electrode', 'raw_p', 'bh_p', 'is_significant'])

    # Calculate BH critical values: p_i * (n / i)
    # i is the rank (1-based)
    df['rank'] = range(1, n + 1)
    df['bh_p'] = df['raw_p'] * (n / df['rank'])

    # Ensure BH p-values do not exceed 1.0
    df['bh_p'] = df['bh_p'].clip(upper=1.0)

    # Monotonicity adjustment: ensure p-values are non-decreasing from smallest to largest
    # We iterate from the largest rank downwards to ensure monotonicity
    for i in range(n - 2, -1, -1):
        if df.loc[i, 'bh_p'] > df.loc[i + 1, 'bh_p']:
            df.loc[i, 'bh_p'] = df.loc[i + 1, 'bh_p']

    # Determine significance
    df['is_significant'] = df['bh_p'] <= alpha

    # Re-sort by raw p-value for readability (optional, but good practice)
    df = df.sort_values('raw_p').reset_index(drop=True)

    return df


def main():
    logger = setup_logger("benjamini_hochberg")
    config = load_config()

    input_path = Path("data/analysis/correlation_results.csv")
    output_path = Path("data/analysis/bh_corrected_pvalues.csv")

    logger.info(f"Starting Benjamini-Hochberg correction pipeline.")

    if not input_path.exists():
        logger.error(f"Input file not found: {input_path}")
        logger.error("Please run code/analysis.py first to generate correlation_results.csv.")
        sys.exit(1)

    try:
        # Load correlation results
        # Expected columns based on T020: electrode, pearson_r, pearson_p, spearman_r, spearman_p
        df = pd.read_csv(input_path)
        logger.info(f"Loaded {len(df)} correlation results from {input_path}")

        # We need to decide which p-values to correct.
        # Typically, we correct for the primary metric. Let's assume Pearson p-values are primary
        # or we correct both. The task says "across electrodes", implying we treat each electrode's
        # test as a hypothesis.
        # If the file has multiple p-value columns, we should process the one relevant to the hypothesis.
        # Let's look for a column named 'pearson_p' or similar.
        p_col = None
        if 'pearson_p' in df.columns:
            p_col = 'pearson_p'
        elif 'p_value' in df.columns:
            p_col = 'p_value'
        else:
            # Fallback to any column ending in _p
            candidates = [c for c in df.columns if c.endswith('_p')]
            if candidates:
                p_col = candidates[0]
            else:
                logger.error("No p-value column found in correlation_results.csv")
                logger.error(f"Available columns: {df.columns.tolist()}")
                sys.exit(1)

        logger.info(f"Using '{p_col}' for FDR correction.")

        # Extract p-values, indexed by electrode
        # Ensure 'electrode' column exists
        if 'electrode' not in df.columns:
            logger.error("Column 'electrode' not found in correlation_results.csv")
            sys.exit(1)

        p_series = df.set_index('electrode')[p_col]

        # Run correction
        corrected_df = run_benjamini_hochberg(p_series, alpha=config.get('fdr_alpha', 0.05))

        # Save results
        corrected_df.to_csv(output_path, index=False)
        logger.info(f"Saved corrected p-values to {output_path}")

        # Log summary
        sig_count = corrected_df['is_significant'].sum()
        logger.info(f"Significant electrodes at FDR {config.get('fdr_alpha', 0.05)}: {sig_count} / {len(corrected_df)}")

    except Exception as e:
        logger.error(f"Error during Benjamini-Hochberg correction: {e}")
        raise


if __name__ == "__main__":
    main()
