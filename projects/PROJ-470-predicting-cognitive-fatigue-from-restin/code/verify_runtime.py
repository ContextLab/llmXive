"""
Verify total pipeline runtime <= 6 hours (SC-002).

This script reads the resource usage metrics generated by the pipeline
(specifically from code/utils/monitor.py) and asserts that the total
runtime does not exceed the 6-hour limit.
"""
import os
import sys
import json
import logging
import argparse
from pathlib import Path

# Add project root to path for imports if running as script
project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from code.utils.logging import get_logger, log_operation

# Configuration
RESOURCE_USAGE_FILE = "data/analysis/resource_usage.json"
MAX_RUNTIME_HOURS = 6.0

def load_resource_usage(filepath: str) -> dict:
    """Load the resource usage JSON file."""
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Resource usage file not found: {filepath}")
    
    with open(filepath, 'r') as f:
        return json.load(f)

def verify_runtime(resource_data: dict, max_hours: float, logger: logging.Logger) -> bool:
    """
    Verify that total_runtime_hours <= max_hours.
    
    Returns True if verification passes, False otherwise.
    """
    if "total_runtime_hours" not in resource_data:
        logger.error("Missing 'total_runtime_hours' in resource usage data.")
        return False
    
    total_hours = resource_data["total_runtime_hours"]
    logger.info(f"Total pipeline runtime: {total_hours:.4f} hours")
    
    if total_hours > max_hours:
        logger.error(f"Runtime limit exceeded: {total_hours:.4f}h > {max_hours}h")
        return False
    
    logger.info(f"Runtime verification PASSED: {total_hours:.4f}h <= {max_hours}h")
    return True

def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(description="Verify pipeline runtime constraints.")
    parser.add_argument("--file", type=str, default=RESOURCE_USAGE_FILE,
                        help="Path to resource usage JSON file.")
    parser.add_argument("--limit", type=float, default=MAX_RUNTIME_HOURS,
                        help="Maximum allowed runtime in hours.")
    args = parser.parse_args()

    # Setup logging
    logger = get_logger("verify_runtime")
    log_operation("verify_runtime_start", file=args.file, limit=args.limit)

    try:
        resource_data = load_resource_usage(args.file)
        success = verify_runtime(resource_data, args.limit, logger)
        
        if success:
            log_operation("verify_runtime_end", status="PASS", runtime=resource_data["total_runtime_hours"])
            print("Runtime verification successful.")
            sys.exit(0)
        else:
            log_operation("verify_runtime_end", status="FAIL", runtime=resource_data.get("total_runtime_hours", "N/A"))
            print("Runtime verification FAILED.")
            sys.exit(1)
    
    except FileNotFoundError as e:
        logger.error(str(e))
        log_operation("verify_runtime_end", status="ERROR", error=str(e))
        print(f"Error: {e}")
        sys.exit(1)
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON format in {args.file}: {e}")
        log_operation("verify_runtime_end", status="ERROR", error=str(e))
        print(f"Error: Invalid JSON format.")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        log_operation("verify_runtime_end", status="ERROR", error=str(e))
        print(f"Error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
