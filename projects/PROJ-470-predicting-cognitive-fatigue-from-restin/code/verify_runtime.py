"""Verify pipeline runtime against the 6-hour constraint (SC-002).

This script loads the resource usage metrics generated by the monitoring
infrastructure (T026) and verifies that the total runtime does not exceed
the specified limit.
"""
from __future__ import annotations

import argparse
import json
import logging
import os
import sys
from pathlib import Path

# Import from the project's logging utility (T006)
# We use the tolerant logger defined in utils/logging.py
from utils.logging import get_logger

# Import monitor to ensure we have the correct path constants if needed,
# though we mostly rely on the file path from config or default.
from utils.monitor import main as monitor_main

# Configuration constants
DEFAULT_RESOURCE_USAGE_PATH = "data/analysis/resource_usage.json"
DEFAULT_MAX_RUNTIME_HOURS = 6.0

def load_resource_usage(file_path: str) -> dict:
    """Load resource usage metrics from JSON file.

    Args:
        file_path: Path to the resource_usage.json file.

    Returns:
        Dictionary containing resource usage metrics.

    Raises:
        FileNotFoundError: If the file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
        KeyError: If required keys are missing.
    """
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Resource usage file not found: {file_path}")

    with open(file_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    # Validate required keys
    required_keys = ["total_runtime_hours", "peak_rss_gb"]
    for key in required_keys:
        if key not in data:
            raise KeyError(f"Missing required key in resource usage file: {key}")

    return data

def verify_runtime(
    resource_data: dict, max_runtime_hours: float, logger: logging.Logger | None = None
) -> tuple[bool, str]:
    """Verify that the pipeline runtime meets the constraint.

    Args:
        resource_data: Dictionary containing resource usage metrics.
        max_runtime_hours: Maximum allowed runtime in hours.
        logger: Optional logger for status messages.

    Returns:
        Tuple of (success: bool, message: str).
    """
    total_runtime = resource_data["total_runtime_hours"]
    status = "PASS" if total_runtime <= max_runtime_hours else "FAIL"

    if logger:
        logger.info(f"Runtime verification: {status}")
        logger.info(f"  Total runtime: {total_runtime:.4f} hours")
        logger.info(f"  Max allowed: {max_runtime_hours:.4f} hours")

    if total_runtime <= max_runtime_hours:
        message = (
            f"SUCCESS: Pipeline runtime ({total_runtime:.4f}h) is within "
            f"the limit ({max_runtime_hours:.4f}h)."
        )
        return True, message
    else:
        message = (
            f"FAILURE: Pipeline runtime ({total_runtime:.4f}h) exceeds "
            f"the limit ({max_runtime_hours:.4f}h)."
        )
        return False, message

def main() -> int:
    """Main entry point for runtime verification."""
    parser = argparse.ArgumentParser(
        description="Verify pipeline runtime against SC-002 constraint."
    )
    parser.add_argument(
        "--resource-file",
        type=str,
        default=DEFAULT_RESOURCE_USAGE_PATH,
        help=f"Path to resource_usage.json (default: {DEFAULT_RESOURCE_USAGE_PATH})",
    )
    parser.add_argument(
        "--max-runtime",
        type=float,
        default=DEFAULT_MAX_RUNTIME_HOURS,
        help=f"Maximum allowed runtime in hours (default: {DEFAULT_MAX_RUNTIME_HOURS})",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Enable verbose logging output.",
    )

    args = parser.parse_args()

    # Setup logging
    logger = get_logger("verify_runtime")
    if args.verbose:
        logging.basicConfig(
            level=logging.INFO,
            format="%(asctime)s - %(name)s - %(levelname)s - %(message)s",
        )
    else:
        logging.basicConfig(
            level=logging.WARNING,
            format="%(asctime)s - %(name)s - %(levelname)s - %(message)s",
        )

    try:
        # Load resource usage data
        logger.info(f"Loading resource usage from: {args.resource_file}")
        resource_data = load_resource_usage(args.resource_file)

        # Verify runtime constraint
        success, message = verify_runtime(
            resource_data, args.max_runtime, logger if args.verbose else None
        )

        # Print result
        print(message)

        # Exit with appropriate code
        return 0 if success else 1

    except FileNotFoundError as e:
        logger.error(str(e))
        print(f"ERROR: {e}")
        print("The pipeline must be run first to generate data/analysis/resource_usage.json")
        return 1
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in resource usage file: {e}")
        print(f"ERROR: Invalid JSON in resource usage file: {e}")
        return 1
    except KeyError as e:
        logger.error(f"Missing required data: {e}")
        print(f"ERROR: Missing required data in resource usage file: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during verification: {e}")
        print(f"ERROR: Unexpected error: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())