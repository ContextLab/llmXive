import os
import sys
import yaml
from pathlib import Path
import pandas as pd
import numpy as np
import logging

def load_config():
    config_path = Path(__file__).parent / "config.yaml"
    with open(config_path, 'r') as f:
        return yaml.safe_load(f)

def setup_logger(name, log_file):
    """Setup logging infrastructure."""
    logs_dir = Path(__file__).parent.parent / "logs"
    logs_dir.mkdir(exist_ok=True)
    
    log_path = logs_dir / log_file
    log_path.parent.mkdir(parents=True, exist_ok=True)
    
    logger = logging.getLogger(name)
    logger.setLevel(logging.INFO)
    
    if logger.hasHandlers():
        logger.handlers.clear()
    
    fh = logging.FileHandler(log_path, mode='a')
    fh.setLevel(logging.INFO)
    formatter = logging.Formatter('%(asctime)s - %(levelname)s - %(message)s')
    fh.setFormatter(formatter)
    logger.addHandler(fh)
    
    return logger

def load_analysis_results():
    """
    Load the main analysis results containing correlation coefficients and p-values.
    Expects: data/analysis/correlation_results.csv
    """
    results_path = Path(__file__).parent.parent / "data" / "analysis" / "correlation_results.csv"
    if not results_path.exists():
        return None
    return pd.read_csv(results_path)

def load_sensitivity_table():
    """
    Load the sensitivity analysis table generated by T021.
    Expects: data/analysis/sensitivity_table.csv
    """
    table_path = Path(__file__).parent.parent / "data" / "analysis" / "sensitivity_table.csv"
    if not table_path.exists():
        return None
    return pd.read_csv(table_path)

