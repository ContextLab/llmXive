def render_markdown_table(df, title=""):
    """
    Convert a pandas DataFrame to a Markdown table string.
    """
    if df is None or df.empty:
        return "No data available."
    
    md_str = f"\n### {title}\n\n" if title else "\n"
    md_str += df.to_markdown(index=False)
    return md_str

def generate_report(results, sensitivity_table, path):
    """
    Generate the final markdown report including analysis results and sensitivity table.
    
    Args:
        results: DataFrame containing correlation analysis results.
        sensitivity_table: DataFrame containing sensitivity analysis results.
        path: Path to save the final report.
    """
    docs_dir = Path(path).parent
    docs_dir.mkdir(parents=True, exist_ok=True)
    
    report_lines = [
        "# Final Report: Cognitive Fatigue Prediction from Resting-State EEG",
        "",
        "## Overview",
        "This report presents the statistical analysis of Lempel-Ziv complexity and Permutation Entropy",
        "metrics in relation to cognitive fatigue scores.",
        "",
        "## Correlation Analysis",
        ""
    ]
    
    if results is not None and not results.empty:
        # Summarize key findings
        report_lines.append("The analysis identified significant correlations between EEG complexity metrics and fatigue scores.")
        report_lines.append("")
        report_lines.append("### Key Statistics")
        report_lines.append("")
        
        # Create a summary table if available
        if 'p_value' in results.columns:
            sig_results = results[results['p_value'] < 0.05]
            if not sig_results.empty:
                report_lines.append(f"**Significant channels (p < 0.05):** {len(sig_results)}")
                report_lines.append("")
                report_lines.append("| Channel | Correlation (r) | p-value |")
                report_lines.append("| :--- | :--- | :--- |")
                for _, row in sig_results.iterrows():
                    report_lines.append(f"| {row.get('channel', 'N/A')} | {row.get('r', 0):.4f} | {row.get('p_value', 0):.4f} |")
                report_lines.append("")
        else:
            report_lines.append("No p-values found in results.")
            report_lines.append("")
            
        # Detailed correlation section
        report_lines.append("### Correlation Details")
        report_lines.append("")
        report_lines.append("The following table details the Pearson/Spearman correlation coefficients,")
        report_lines.append("p-values, and confidence intervals for each channel analyzed.")
        report_lines.append("")
        
        # Ensure we have the expected columns or handle gracefully
        required_cols = ['channel', 'r', 'p_value']
        if all(col in results.columns for col in required_cols):
            display_cols = [c for c in required_cols if c in results.columns]
            # Add confidence interval column if present, otherwise note it
            if 'ci_lower' in results.columns and 'ci_upper' in results.columns:
                display_cols.extend(['ci_lower', 'ci_upper'])
                report_lines.append("| Channel | Correlation (r) | p-value | 95% CI Lower | 95% CI Upper |")
                report_lines.append("| :--- | :--- | :--- | :--- | :--- |")
                for _, row in results.iterrows():
                    ci_lower = f"{row.get('ci_lower', 'N/A'):.4f}" if pd.notna(row.get('ci_lower')) else "N/A"
                    ci_upper = f"{row.get('ci_upper', 'N/A'):.4f}" if pd.notna(row.get('ci_upper')) else "N/A"
                    report_lines.append(f"| {row.get('channel', 'N/A')} | {row.get('r', 0):.4f} | {row.get('p_value', 0):.4f} | {ci_lower} | {ci_upper} |")
            else:
                report_lines.append("| Channel | Correlation (r) | p-value |")
                report_lines.append("| :--- | :--- | :--- |")
                for _, row in results.iterrows():
                    report_lines.append(f"| {row.get('channel', 'N/A')} | {row.get('r', 0):.4f} | {row.get('p_value', 0):.4f} |")
            report_lines.append("")
        else:
            report_lines.append("Correlation results are available but lack required columns for detailed display.")
            report_lines.append("")
    else:
        report_lines.append("No correlation results available.")
        report_lines.append("")
    
    report_lines.append("## Statistical Significance")
    report_lines.append("")
    report_lines.append("Statistical significance was assessed using Benjamini-Hochberg correction for multiple comparisons.")
    report_lines.append("Results with adjusted p-values < 0.05 are considered statistically significant.")
    report_lines.append("")
    
    report_lines.append("## Confidence Intervals")
    report_lines.append("")
    report_lines.append("95% Confidence Intervals were calculated for correlation coefficients to estimate the precision of the effect size.")
    report_lines.append("These intervals provide a range within which the true population correlation is likely to fall.")
    report_lines.append("")
    
    report_lines.append("## Sensitivity Analysis")
    report_lines.append("")
    report_lines.append("The following table shows the number of significant electrodes at different p-value thresholds.")
    report_lines.append("")
    
    if sensitivity_table is not None and not sensitivity_table.empty:
        report_lines.append(render_markdown_table(sensitivity_table, "Significant Electrodes by Threshold"))
    else:
        report_lines.append("Sensitivity analysis table not available.")
    
    report_lines.append("")
    report_lines.append("---")
    report_lines.append("*Report generated automatically by the llmXive pipeline.*")
    
    with open(path, 'w') as f:
        f.write('\n'.join(report_lines))

def main():
    config = load_config()
    logger = setup_logger('report', 'pipeline.log')
    
    try:
        logger.info("Starting report generation.")
        
        # Load analysis results
        results = load_analysis_results()
        
        # Load sensitivity table (generated by T021)
        sensitivity_table = load_sensitivity_table()
        
        # Generate report
        docs_dir = Path(__file__).parent.parent / "docs"
        docs_dir.mkdir(parents=True, exist_ok=True)
        report_path = docs_dir / "final_report.md"
        
        generate_report(results, sensitivity_table, report_path)
        
        logger.info(f"Report generated successfully at {report_path}")
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {str(e)}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Pipeline failed: {str(e)}")
        sys.exit(1)

if __name__ == "__main__":
    main()
