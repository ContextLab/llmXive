"""
Evaluation script for the Metallic Glass CTE models.

It loads the test split generated by ``code/modeling/train.py``,
loads the serialized Linear Regression and Random Forest models,
computes R², MAE and RMSE on the test set, runs a ≥ 1000‑iteration
permutation test, and writes the results to ``results/model_performance.json``.
"""
import sys
import json
import logging
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import r2_score, mean_absolute_error, mean_squared_error
from sklearn.utils import resample
from joblib import load

from utils.io import setup_logging

logger = setup_logging()

# -------------------------------------------------------------------------
# Constants (must match training script)
# -------------------------------------------------------------------------

REQUIRED_FEATURES = [
    "weighted_mean_atomic_radius",
    "electronegativity_variance",
    "vec",
    "atomic_size_coefficient_of_variation",
]
TARGET_COLUMN = "cte"

# -------------------------------------------------------------------------
# Helper functions
# -------------------------------------------------------------------------

def load_test_split() -> pd.DataFrame:
    test_path = Path("data/processed/test.parquet")
    if not test_path.exists():
        raise FileNotFoundError(f"Test split not found at {test_path}")
    df = pd.read_parquet(test_path)
    missing = [c for c in REQUIRED_FEATURES + [TARGET_COLUMN] if c not in df.columns]
    if missing:
        raise ValueError(f"Missing columns in test split: {missing}")
    return df

def load_models():
    models_dir = Path("models")
    lr_path = models_dir / "linear_regression.pkl"
    rf_path = models_dir / "random_forest.pkl"
    if not lr_path.exists() or not rf_path.exists():
        raise FileNotFoundError("Serialized model files not found.")
    lr = load(lr_path)
    rf = load(rf_path)
    return lr, rf

def calculate_metrics(y_true, y_pred):
    return {
        "r2": r2_score(y_true, y_pred),
        "mae": mean_absolute_error(y_true, y_pred),
        "rmse": np.sqrt(mean_squared_error(y_true, y_pred)),
    }

def run_permutation_test(model, X, y, n_iterations=1000, random_state=42):
    """Permutation test as required by FR‑005."""
    logger.info(f"Running permutation test ({n_iterations} iterations)")
    rng = np.random.default_rng(random_state)
    actual = r2_score(y, model.predict(X))
    perm_scores = []
    for i in range(n_iterations):
        y_perm = rng.permutation(y)
        score = r2_score(y_perm, model.predict(X))
        perm_scores.append(score)
    perm_scores = np.array(perm_scores)
    p_value = np.mean(perm_scores >= actual)
    logger.info(f"Permutation test completed. p-value = {p_value:.4f}")
    return p_value, actual

def main() -> int:
    start = time.time()
    test_df = load_test_split()
    X_test = test_df[REQUIRED_FEATURES].values
    y_test = test_df[TARGET_COLUMN].values

    lr, rf = load_models()

    # Linear Regression evaluation
    lr_metrics = calculate_metrics(y_test, lr.predict(X_test))
    # Random Forest evaluation
    rf_metrics = calculate_metrics(y_test, rf.predict(X_test))

    # Permutation test on the best model (choose higher R2)
    best_model = rf if rf_metrics["r2"] >= lr_metrics["r2"] else lr
    p_value, actual_r2 = run_permutation_test(best_model, X_test, y_test)

    # Assemble final results
    results = {
        "linear_regression": lr_metrics,
        "random_forest": rf_metrics,
        "best_model": "random_forest" if best_model is rf else "linear_regression",
        "permutation_test": {
            "p_value": float(p_value),
            "observed_r2": float(actual_r2),
        },
    }

    # Flag null result if R2 <= 0.3
    if results["best_model"] == "random_forest" and rf_metrics["r2"] <= 0.3:
        results["null_result_flag"] = True
    elif results["best_model"] == "linear_regression" and lr_metrics["r2"] <= 0.3:
        results["null_result_flag"] = True
    else:
        results["null_result_flag"] = False

    # Write out
    out_path = Path("results/model_performance.json")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(results, f, indent=2)
    logger.info(f"Model performance written to {out_path}")

    logger.info(f"Evaluation completed in {time.time() - start:.2f}s")
    return 0

if __name__ == "__main__":
    sys.exit(main())
