"""
Save cleaned metallic glass dataset to parquet format with checksum manifest.

This script:
1. Loads the raw/processed data generated by previous ingestion steps (T013-T017).
   Since T013-T017 are completed, we assume a temporary intermediate CSV or
   in-memory state exists. In this pipeline, we assume the ingestion process
   writes a temporary 'data/raw/ingested_mg_data.csv' which we then clean
   (filtering handled in fetch_data.py, but we ensure final schema here)
   and save as the final parquet artifact.
2. Computes SHA256 checksum using utils.io.compute_sha256.
3. Writes the manifest to data/processed/checksum_manifest.json.
4. Writes the final dataset to data/processed/clean_mg_data.parquet.

Prerequisites:
- T001 (Structure), T005a (compute_sha256), T013-T017 (Data Ingestion & Features)
"""
import os
import sys
import logging
import json
from pathlib import Path
import pandas as pd
from utils.io import setup_logging, compute_sha256
from utils.config import get_env_var

# Configure logging
logger = setup_logging("save_clean_data")

def load_intermediate_data() -> pd.DataFrame:
    """
    Load the intermediate data generated by T013-T017.
    In a real pipeline, this might be a direct continuation or a file read.
    We look for the expected intermediate file.
    """
    # Expected intermediate file from ingestion steps
    intermediate_path = Path("data/raw/ingested_mg_data.csv")
    
    if not intermediate_path.exists():
        logger.error(f"Intermediate file not found: {intermediate_path}")
        logger.error("Please ensure T013-T017 have been executed and produced data/raw/ingested_mg_data.csv")
        raise FileNotFoundError(f"Intermediate data file missing: {intermediate_path}")

    logger.info(f"Loading intermediate data from {intermediate_path}")
    try:
        df = pd.read_csv(intermediate_path)
        logger.info(f"Loaded {len(df)} rows. Columns: {list(df.columns)}")
        return df
    except Exception as e:
        logger.error(f"Failed to load intermediate data: {e}")
        raise

def clean_and_validate(df: pd.DataFrame) -> pd.DataFrame:
    """
    Perform final cleaning and schema validation before saving.
    Ensures no missing values in critical columns and enforces types.
    """
    logger.info("Performing final cleaning and validation...")
    
    # Define required columns based on T016/T017 output schema
    required_cols = [
        'composition', 'cte', 
        'mean_atomic_radius', 'electronegativity_variance', 
        'vec', 'size_mismatch', 'alloy_family'
    ]
    
    # Check for required columns
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        logger.error(f"Missing required columns: {missing_cols}")
        raise ValueError(f"Schema validation failed: missing columns {missing_cols}")
    
    # Drop rows with missing critical values
    initial_count = len(df)
    df = df.dropna(subset=required_cols)
    dropped_count = initial_count - len(df)
    if dropped_count > 0:
        logger.warning(f"Dropped {dropped_count} rows due to missing values in required columns.")
    
    # Ensure specific types
    df['cte'] = pd.to_numeric(df['cte'], errors='raise')
    df['mean_atomic_radius'] = pd.to_numeric(df['mean_atomic_radius'], errors='raise')
    df['vec'] = pd.to_numeric(df['vec'], errors='raise')
    df['size_mismatch'] = pd.to_numeric(df['size_mismatch'], errors='raise')
    
    # Filter for amorphous state if a flag exists (T015 requirement)
    if 'is_amorphous' in df.columns:
        initial = len(df)
        df = df[df['is_amorphous'] == True]
        logger.info(f"Filtered for amorphous entries: {initial} -> {len(df)}")
    
    logger.info(f"Final dataset size: {len(df)} rows.")
    return df

def save_parquet_and_manifest(df: pd.DataFrame, output_path: Path) -> str:
    """
    Save dataframe to parquet and compute checksum.
    Returns the checksum hex digest.
    """
    logger.info(f"Saving to {output_path}...")
    
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Write parquet
    df.to_parquet(output_path, index=False)
    logger.info("Parquet file written.")
    
    # Compute checksum
    checksum = compute_sha256(str(output_path))
    logger.info(f"Checksum computed: {checksum}")
    
    return checksum

def write_manifest(checksum: str, output_path: Path, manifest_path: Path):
    """
    Write the checksum manifest JSON.
    """
    manifest = {
        "file": output_path.name,
        "path": str(output_path),
        "sha256": checksum,
        "row_count": len(pd.read_parquet(output_path)),
        "generated_by": "T022-save_clean_data",
        "timestamp": "runtime" # In a real run, use datetime.utcnow().isoformat()
    }
    
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    with open(manifest_path, 'w') as f:
        json.dump(manifest, f, indent=2)
    
    logger.info(f"Manifest written to {manifest_path}")

def main():
    """
    Main entry point for T022.
    """
    try:
        # 1. Load intermediate data
        df = load_intermediate_data()
        
        # 2. Clean and validate
        df_clean = clean_and_validate(df)
        
        if len(df_clean) == 0:
            logger.error("No data remaining after cleaning. Aborting.")
            sys.exit(1)

        # 3. Define output paths
        output_path = Path("data/processed/clean_mg_data.parquet")
        manifest_path = Path("data/processed/checksum_manifest.json")
        
        # 4. Save and checksum
        checksum = save_parquet_and_manifest(df_clean, output_path)
        
        # 5. Write manifest
        write_manifest(checksum, output_path, manifest_path)
        
        logger.info("Task T022 completed successfully.")
        print(f"SUCCESS: Dataset saved to {output_path} (SHA256: {checksum})")
        
    except FileNotFoundError as e:
        logger.critical(f"Data not found: {e}")
        sys.exit(1)
    except Exception as e:
        logger.critical(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()