def aggregate_to_genus_level(df: pd.DataFrame) -> pd.DataFrame:
    """
    Aggregate species-level counts to genus level.
    Assumes columns are in format 'Genus_species' or similar, or a separate taxonomy column exists.
    If the input is already genus-level, this acts as a pass-through or simple check.
    
    Strategy:
    1. Identify taxonomic columns.
    2. Parse genus name from column header if possible, or use a taxonomy mapping if provided.
    3. Group by participant_id and sum counts at the genus level.
    
    For this implementation, we assume the input dataframe from T014 has columns 
    representing taxa (species or OTUs) and the first part of the column name (before '_') 
    or a specific pattern indicates the Genus.
    If the data is already genus-level (e.g., 'Bacteroides', 'Prevotella'), no parsing needed.
    
    Heuristic: If column names contain underscores, split on first underscore to get Genus.
    If not, assume they are already genera.
    """
    logger.info("Aggregating to genus level...")
    participant_col = 'participant_id'
    if participant_col not in df.columns:
        raise PreprocessingError(f"Missing participant column '{participant_col}'")
    
    taxon_cols = [c for c in df.columns if c != participant_col]
    
    genus_map = {}
    for col in taxon_cols:
        if '_' in col:
            genus = col.split('_')[0]
        else:
            genus = col
        genus_map[col] = genus
    
    # Group by participant and sum
    # We need to reset index if it was set, but standard read_parquet returns index 0..N
    df_grouped = df.groupby(participant_col).agg({col: 'sum' for col in taxon_cols})
    
    # Rename columns to genus
    df_grouped = df_grouped.rename(columns=genus_map)
    
    # Sum duplicates (if multiple species mapped to same genus)
    df_grouped = df_grouped.groupby(df_grouped.columns, axis=1).sum()
    
    # Reset index to make participant_id a column
    df_grouped = df_grouped.reset_index()
    
    logger.info(f"Aggregated to {len(df_grouped.columns) - 1} genera")
    return df_grouped

def centered_log_ratio_transform(df: pd.DataFrame) -> pd.DataFrame:
    """
    Apply Centered Log-Ratio (CLR) transformation.
    CLR(x) = log(x / g(x)) where g(x) is the geometric mean of the composition.
    Requires strictly positive data (handled by T014 Bayesian replacement).
    """
    logger.info("Applying CLR transformation...")
    participant_col = 'participant_id'
    taxon_cols = [c for c in df.columns if c != participant_col]
    
    if len(taxon_cols) == 0:
        raise PreprocessingError("No taxon columns found for CLR transformation")
    
    # Calculate geometric mean for each row
    # geometric mean = exp(mean(log(x)))
    log_data = np.log(df[taxon_cols])
    geo_mean = np.exp(log_data.mean(axis=1))
    
    # Avoid division by zero (should not happen if data > 0)
    geo_mean = geo_mean.replace(0, np.finfo(float).eps)
    
    clr_data = log_data - np.log(geo_mean.values.reshape(-1, 1))
    clr_df = df[[participant_col]].copy()
    clr_df[taxon_cols] = clr_data
    
    logger.info("CLR transformation complete")
    return clr_df

def ilr_transform(df: pd.DataFrame) -> pd.DataFrame:
    """
    Apply Isometric Log-Ratio (ILR) transformation.
    ILR transforms compositional data into orthonormal coordinates in real space.
    Uses sequential binary partition (SBP) or a standard basis (e.g., pivot coordinates).
    
    Implementation:
    We use the standard pivot coordinate basis (also known as the 'sequential' or 'balance' basis).
    For D taxa, we get D-1 ILR coordinates.
    Coordinate k is proportional to log(geometric_mean(first k taxa) / geometric_mean(rest)).
    
    Reference: Egozcue et al. (2003) "Isometric logratio transformations for compositional data analysis"
    """
    logger.info("Applying ILR transformation...")
    participant_col = 'participant_id'
    taxon_cols = [c for c in df.columns if c != participant_col]
    
    if len(taxon_cols) < 2:
        raise PreprocessingError("ILR requires at least 2 taxa. Cannot transform.")
    
    D = len(taxon_cols)
    n = len(df)
    
    # Sort taxa to ensure deterministic order (optional but good practice)
    # Using alphabetical order for reproducibility
    taxon_cols_sorted = sorted(taxon_cols)
    
    # Construct the ILR matrix (V)
    # For pivot coordinates:
    # v_k = sqrt(k / (k+1)) * [1, 1, ..., 1 (k times), -k, 0, ..., 0] / k ? 
    # Actually, the standard pivot basis vector for the k-th coordinate (1-based index k from 1 to D-1)
    # compares the k-th taxon against the geometric mean of the first k-1 taxa? 
    # No, standard pivot: coordinate k compares the k-th taxon to the geometric mean of the first k-1?
    # Let's use the definition: 
    # z_k = sqrt( (D-k) / (D-k+1) ) * [ log(x_k) - 1/(D-k) * sum(log(x_{k+1}...x_D)) ]
    # Or the simpler "sequential binary partition" where we split the set.
    # Let's use the standard 'balance' approach where we partition the set of D taxa into two groups.
    # A common choice is the 'pivot' basis:
    # Coordinate 1: log(x1 / g(x2...xD)) * sqrt((D-1)/D)
    # Coordinate 2: log(x2 / g(x3...xD)) * sqrt((D-2)/(D-1))
    # ...
    # Coordinate D-1: log(x_{D-1} / x_D) * sqrt(1/2)
    
    ilr_cols = [f"ilr_{i+1}" for i in range(D-1)]
    ilr_data = np.zeros((n, D-1))
    
    log_data = np.log(df[taxon_cols_sorted].values)
    
    for k in range(D - 1):
        # k is 0-based index for the loop, corresponding to the (k+1)-th taxon in the sorted list
        # The pivot coordinate compares the (k+1)-th taxon to the geometric mean of the remaining (D - (k+1)) taxa.
        # Remaining taxa count: rem = D - (k+1)
        # Weight: w = sqrt( rem / (rem + 1) ) = sqrt( (D - k - 1) / (D - k) )
        
        rem = D - (k + 1)
        if rem == 0:
            # This shouldn't happen in the loop range 0 to D-2
            continue
        
        weight = np.sqrt(rem / (rem + 1))
        
        # log(x_{k+1})
        term1 = log_data[:, k]
        
        # log(g(x_{k+2}...x_D)) = mean(log(x_{k+2}...x_D))
        if rem > 0:
            term2 = np.mean(log_data[:, k+1:], axis=1)
        else:
            term2 = 0.0 # Should not be reached
        
        ilr_data[:, k] = weight * (term1 - term2)
    
    ilr_df = df[[participant_col]].copy()
    ilr_df[ilr_cols] = ilr_data
    
    logger.info(f"ILR transformation complete. Generated {D-1} coordinates.")
    return ilr_df

def run_ilr_pipeline() -> pd.DataFrame:
    """
    Main pipeline for T015:
    1. Load zero-replaced counts (T014 output)
    2. Aggregate to genus level
    3. Apply CLR
    4. Apply ILR
    5. Save to data/processed/ilr_coordinates.parquet
    """
    # 1. Load
    df_micro = load_raw_microbiome_data()
    df_cog = load_raw_cognitive_data()
    
    # 2. Merge on participant_id (if not already merged)
    # T013 should have filtered both, so we assume they share the same IDs.
    # We perform an inner join to ensure only matched participants are processed.
    if 'participant_id' not in df_cog.columns:
        # Try to find the cognitive score column
        cog_col = [c for c in df_cog.columns if 'score' in c.lower() or 'cognitive' in c.lower()]
        if cog_col:
            df_cog = df_cog.rename(columns={cog_col[0]: 'cognitive_score'})
        else:
            # If no score column, maybe it's a composite or we need to compute it?
            # Assuming T012/T013 produced a 'cognitive_score' column.
            raise PreprocessingError("Cognitive dataframe missing score column.")
    
    df_merged = pd.merge(df_micro, df_cog[['participant_id', 'cognitive_score']], 
                         on='participant_id', how='inner')
    
    logger.info(f"Merged dataset size: {len(df_merged)} participants")
    
    # 3. Aggregate to Genus
    df_genus = aggregate_to_genus_level(df_merged)
    
    # 4. CLR
    df_clr = centered_log_ratio_transform(df_genus)
    
    # 5. ILR
    df_ilr = ilr_transform(df_clr)
    
    # 6. Save
    output_path = get_path("data/processed/ilr_coordinates.parquet")
    ensure_directories([output_path])
    
    df_ilr.to_parquet(output_path, index=False)
    logger.info(f"ILR coordinates saved to {output_path}")
    
    return df_ilr

def run_preprocessing_pipeline() -> pd.DataFrame:
    """
    Full preprocessing pipeline including T015 steps.
    """
    return run_ilr_pipeline()

