"""
Validation script for LLM-generated explanations (Task T016).

Verifies:
1. No null values in critical fields (snippet_id, code, complexity, explanation).
2. All complexity labels are valid ('low', 'medium', 'high').
3. Token counts are strictly less than 200.
4. Total number of records N >= 20.

Input: data/intermediate/explanations.json (generated by T014)
Output: data/intermediate/validation_report.json, exit code 0 on success, 1 on failure.
"""
import json
import logging
import sys
from pathlib import Path
from typing import List, Dict, Any, Tuple

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler('data/intermediate/validation.log')
    ]
)
logger = logging.getLogger(__name__)

INPUT_PATH = Path("data/intermediate/explanations.json")
OUTPUT_REPORT_PATH = Path("data/intermediate/validation_report.json")
VALID_COMPLEXITY_LABELS = {'low', 'medium', 'high'}
MAX_TOKEN_COUNT = 200
MIN_RECORD_COUNT = 20

def load_data(file_path: Path) -> List[Dict[str, Any]]:
    """Load the explanations JSON file."""
    if not file_path.exists():
        raise FileNotFoundError(f"Input file not found: {file_path}")
    
    logger.info(f"Loading data from {file_path}")
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    if not isinstance(data, list):
        raise ValueError(f"Expected a list of records, got {type(data)}")
    
    logger.info(f"Loaded {len(data)} records")
    return data

def validate_record(record: Dict[str, Any]) -> Tuple[bool, List[str]]:
    """
    Validate a single record against T016 requirements.
    Returns (is_valid, list_of_error_messages).
    """
    errors = []
    required_fields = ['snippet_id', 'code', 'complexity', 'explanation', 'token_count']
    
    # Check for nulls in required fields
    for field in required_fields:
        if field not in record or record[field] is None:
            errors.append(f"Missing or null value in required field: {field}")
        elif field == 'explanation' and record[field] == "":
            errors.append("Empty explanation string")
        elif field == 'code' and record[field] == "":
            errors.append("Empty code string")
    
    # Check validity of complexity label
    if 'complexity' in record and record['complexity'] is not None:
        if record['complexity'] not in VALID_COMPLEXITY_LABELS:
            errors.append(f"Invalid complexity label: {record['complexity']}. Must be one of {VALID_COMPLEXITY_LABELS}")
    
    # Check token count limit
    if 'token_count' in record and record['token_count'] is not None:
        try:
            token_val = int(record['token_count'])
            if token_val >= MAX_TOKEN_COUNT:
                errors.append(f"Token count {token_val} exceeds limit of {MAX_TOKEN_COUNT}")
        except (ValueError, TypeError):
            errors.append(f"Invalid token_count format: {record['token_count']}")
    
    return len(errors) == 0, errors

def run_validation(data: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Run validation on the entire dataset.
    Returns a summary report.
    """
    total_records = len(data)
    valid_count = 0
    invalid_records = []
    
    logger.info(f"Starting validation of {total_records} records")
    
    for idx, record in enumerate(data):
        is_valid, errors = validate_record(record)
        if is_valid:
            valid_count += 1
        else:
            invalid_records.append({
                "index": idx,
                "snippet_id": record.get('snippet_id', 'UNKNOWN'),
                "errors": errors
            })
            logger.warning(f"Record {idx} ({record.get('snippet_id')}) failed validation: {errors}")
    
    # Check N >= 20
    n_check_passed = total_records >= MIN_RECORD_COUNT
    
    # Summary
    report = {
        "total_records": total_records,
        "valid_records": valid_count,
        "invalid_records_count": len(invalid_records),
        "n_check_passed": n_check_passed,
        "n_check_min_required": MIN_RECORD_COUNT,
        "validation_passed": n_check_passed and len(invalid_records) == 0,
        "invalid_details": invalid_records[:10]  # Limit to first 10 for brevity in report
    }
    
    logger.info(f"Validation complete. Passed: {report['validation_passed']}")
    return report

def save_report(report: Dict[str, Any], output_path: Path) -> None:
    """Save the validation report to JSON."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)
    logger.info(f"Report saved to {output_path}")

def main() -> int:
    """Main entry point."""
    try:
        # Load data
        data = load_data(INPUT_PATH)
        
        # Run validation
        report = run_validation(data)
        
        # Save report
        save_report(report, OUTPUT_REPORT_PATH)
        
        # Exit with appropriate code
        if report['validation_passed']:
            logger.info("SUCCESS: All validation checks passed.")
            return 0
        else:
            logger.error("FAILURE: Validation checks failed.")
            if not report['n_check_passed']:
                logger.error(f"  - Record count {report['total_records']} < required {MIN_RECORD_COUNT}")
            if report['invalid_records_count'] > 0:
                logger.error(f"  - {report['invalid_records_count']} records failed validation.")
            return 1
            
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        return 2
    except json.JSONDecodeError as e:
        logger.error(f"JSON decode error: {e}")
        return 3
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        return 4

if __name__ == "__main__":
    sys.exit(main())
