"""
Module to generate the final results table for the gut microbiome and circadian rhythm study.

This module loads correlation results computed by the analysis pipeline, ensures
all required columns (effect sizes, p-values, FDR-corrected p-values) are present,
and saves the final table to data/outputs/correlation_results.csv.

It relies on the analysis.py module for the core correlation computations and FDR correction.
"""

import os
import logging
import argparse
from pathlib import Path
from typing import Optional, List, Dict, Any
import pandas as pd

# Import from sibling modules based on provided API surface
from analysis import load_processed_cohort, load_biom_table, load_metadata, calculate_alpha_diversity, calculate_beta_diversity, calculate_correlations, apply_fdr_correction, run_all_correlations, save_results
from utils.logging_utils import setup_logging, get_logger
from utils.seeding import set_seed
from config import get_config

# Setup logging
logger = get_logger(__name__)

def load_correlation_results(results_path: Optional[str] = None) -> pd.DataFrame:
    """
    Load correlation results from a CSV file if it exists, otherwise compute them.
    
    Args:
        results_path: Path to the results CSV file. Defaults to data/outputs/correlation_results.csv.
        
    Returns:
        A pandas DataFrame containing the correlation results.
    """
    if results_path is None:
        config = get_config()
        results_path = str(config.data_output_dir / "correlation_results.csv")
        
    results_path = Path(results_path)
    
    if results_path.exists():
        logger.info(f"Loading existing correlation results from {results_path}")
        df = pd.read_csv(results_path)
        return df
    else:
        logger.info(f"Results file not found at {results_path}. Running analysis to generate results.")
        # If results don't exist, we run the full analysis pipeline
        # This is a fallback, but ideally results are generated by code/analysis.py first
        df = run_all_correlations()
        save_results(df, str(results_path))
        return df

def generate_results_table(df: pd.DataFrame, output_path: str) -> pd.DataFrame:
    """
    Ensure the results DataFrame has all required columns and format, then save it.
    
    Required columns:
    - variable1: First variable in the correlation pair
    - variable2: Second variable in the correlation pair
    - correlation_type: 'alpha' or 'beta' or 'taxa'
    - method: 'spearman' or 'pearson'
    - effect_size: The correlation coefficient (rho or r)
    - p_value: Raw p-value
    - p_value_fdr: FDR-corrected p-value
    - n: Sample size
    - ci_lower: Lower bound of 95% CI (if available, else NaN)
    - ci_upper: Upper bound of 95% CI (if available, else NaN)
    
    Args:
        df: DataFrame with correlation results.
        output_path: Path to save the final CSV file.
        
    Returns:
        The formatted DataFrame.
    """
    logger.info(f"Generating final results table for {len(df)} correlations")
    
    # Ensure we have the necessary columns
    required_cols = ['variable1', 'variable2', 'correlation_type', 'method', 'effect_size', 'p_value', 'p_value_fdr', 'n']
    
    # Check for missing columns and add them with appropriate defaults if needed
    for col in required_cols:
        if col not in df.columns:
            if col == 'n':
                # If n is missing, we might need to infer it or set a default
                # For now, we'll set it to a placeholder if not present
                logger.warning(f"Column 'n' not found in results. Setting to -1 as placeholder.")
                df[col] = -1
            else:
                raise ValueError(f"Required column '{col}' is missing from the results DataFrame and cannot be inferred.")
    
    # Ensure effect_size, p_value, and p_value_fdr are numeric
    for col in ['effect_size', 'p_value', 'p_value_fdr']:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors='coerce')
    
    # Ensure p_value_fdr exists; if not, compute it from p_value
    if 'p_value_fdr' not in df.columns and 'p_value' in df.columns:
        logger.info("Computing FDR correction for p_values as p_value_fdr column is missing.")
        # Extract p-values, apply FDR, and assign back
        p_values = df['p_value'].values
        if len(p_values) > 0:
            # Re-implement simple BH procedure here to ensure independence from analysis.py state
            # Sort p-values
            sorted_indices = np.argsort(p_values)
            sorted_p = p_values[sorted_indices]
            n_tests = len(sorted_p)
            ranked = np.arange(1, n_tests + 1)
            # BH correction
            fdr_p = np.minimum(1, (sorted_p * n_tests) / ranked)
            # Ensure monotonicity (cumulative min from the end)
            for i in range(n_tests - 2, -1, -1):
                fdr_p[i] = min(fdr_p[i], fdr_p[i+1])
            # Map back to original order
            fdr_p_original = np.empty(n_tests)
            fdr_p_original[sorted_indices] = fdr_p
            df['p_value_fdr'] = fdr_p_original
            logger.info("FDR correction completed.")
        else:
            df['p_value_fdr'] = np.nan
    elif 'p_value_fdr' not in df.columns:
        df['p_value_fdr'] = np.nan
    
    # Add CI columns if not present (will be NaN until bootstrap results are merged)
    if 'ci_lower' not in df.columns:
        df['ci_lower'] = np.nan
    if 'ci_upper' not in df.columns:
        df['ci_upper'] = np.nan
        
    # Sort by FDR-corrected p-value for readability
    df = df.sort_values(by='p_value_fdr', ascending=True).reset_index(drop=True)
    
    # Ensure output directory exists
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Save to CSV
    df.to_csv(output_path, index=False)
    logger.info(f"Final results table saved to {output_path}")
    
    return df

def main():
    """
    Main entry point for generating the final results table.
    """
    parser = argparse.ArgumentParser(description="Generate final correlation results table.")
    parser.add_argument('--input', type=str, default=None, help="Path to input correlation results CSV. If None, attempts to load from default or compute.")
    parser.add_argument('--output', type=str, default=None, help="Path to output CSV file. Defaults to data/outputs/correlation_results.csv.")
    parser.add_argument('--seed', type=int, default=42, help="Random seed for reproducibility.")
    
    args = parser.parse_args()
    
    # Setup logging
    setup_logging()
    
    # Set seed
    set_seed(args.seed)
    
    logger.info("Starting final results table generation.")
    
    # Load or compute results
    df = load_correlation_results(args.input)
    
    # Determine output path
    if args.output is None:
        config = get_config()
        output_path = str(config.data_output_dir / "correlation_results.csv")
    else:
        output_path = args.output
        
    # Generate and save the table
    final_df = generate_results_table(df, output_path)
    
    logger.info(f"Successfully generated results table with {len(final_df)} rows.")
    logger.info(f"Sample of results:\n{final_df.head()}")
    
    return final_df

if __name__ == "__main__":
    main()
