"""
Narrative Synthesis Engine (T015b)

Implements the core 'pivot' mechanism and text assembly logic.
Reads narrative themes and study count to generate structured narrative content
when the quantitative meta-analysis is skipped (N < 10).
"""
import json
import sys
import logging
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

# Import project utilities to ensure consistent path handling and logging
# The API surface shows utils.config has get_project_root
try:
    from utils.config import get_project_root, ensure_directory
except ImportError:
    # Fallback for direct execution if utils.config structure varies slightly
    # but standard surface says it exists.
    def get_project_root() -> Path:
        return Path(__file__).resolve().parent.parent.parent
    
    def ensure_directory(path: Path) -> None:
        path.mkdir(parents=True, exist_ok=True)

from utils.logger import get_logger

logger = get_logger(__name__)

# Constants for file paths relative to project root
NARRATIVE_THEMES_FILE = "data/derived/narrative_themes.json"
STUDY_COUNT_FILE = "data/processed/study_count.json"
NARRATIVE_CONTENT_OUTPUT = "data/derived/narrative_content.md"

def load_study_count_json() -> Dict[str, Any]:
    """
    Loads the study count JSON generated by T014a.
    
    Returns:
        Dict containing 'N' (study count) and other metadata.
        
    Raises:
        FileNotFoundError: If study_count.json is missing.
        ValueError: If 'N' key is missing.
    """
    root = get_project_root()
    file_path = root / STUDY_COUNT_FILE
    
    if not file_path.exists():
        raise FileNotFoundError(
            f"Required input file missing: {file_path}. "
            "Ensure T014a (study_counter) has been executed successfully."
        )
    
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    if 'N' not in data:
        raise ValueError(f"Missing 'N' key in {file_path}")
    
    logger.info(f"Loaded study count: N={data['N']}")
    return data

def load_narrative_themes_json() -> Dict[str, Any]:
    """
    Loads the narrative themes JSON generated by T015a.
    
    Returns:
        Dict containing aggregated themes and counts.
        
    Raises:
        FileNotFoundError: If narrative_themes.json is missing.
    """
    root = get_project_root()
    file_path = root / NARRATIVE_THEMES_FILE
    
    if not file_path.exists():
        raise FileNotFoundError(
            f"Required input file missing: {file_path}. "
            "Ensure T015a (narrative_logic) has been executed successfully."
        )
    
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    logger.info(f"Loaded narrative themes: {len(data.get('themes', []))} themes found")
    return data

def generate_narrative_content(study_count_data: Dict[str, Any], themes_data: Dict[str, Any]) -> str:
    """
    Generates the structured text content for the narrative review.
    
    This function implements the pivot logic: it constructs a Markdown document
    summarizing the qualitative findings when N < 10.
    
    Args:
        study_count_data: Data from study_count.json (contains N).
        themes_data: Data from narrative_themes.json (contains theme aggregations).
        
    Returns:
        A formatted Markdown string representing the narrative content.
    """
    n = study_count_data.get('N', 0)
    timestamp = datetime.now().isoformat()
    themes = themes_data.get('themes', [])
    methodology = themes_data.get('methodology_summary', 'Thematic analysis based on tract lexicon and directional verbs.')
    
    # Start building the Markdown content
    lines = []
    
    # Header
    lines.append("# Narrative Synthesis: Structural Connectivity and Music Preferences")
    lines.append("")
    
    # Metadata Block (JSON style as per common scientific markdown practices in this pipeline)
    lines.append("```json")
    meta_block = {
        "study_count": n,
        "synthesis_mode": "narrative",
        "timestamp": timestamp,
        "trigger_reason": f"Quantitative meta-analysis skipped (N={n} < 10)"
    }
    lines.append(json.dumps(meta_block, indent=2))
    lines.append("```")
    lines.append("")
    
    # Section 1: Overview
    lines.append("## Study Overview")
    lines.append("")
    lines.append(f"This review synthesizes findings from **{n} study(ies)** where quantitative meta-analysis was not feasible due to insufficient sample size (N < 10).")
    lines.append("")
    lines.append("**Methodology:**")
    lines.append(methodology)
    lines.append("")
    
    # Section 2: Qualitative Themes
    lines.append("## Qualitative Themes")
    lines.append("")
    
    if not themes:
        lines.append("*No distinct qualitative themes were identified in the extracted studies.*")
        lines.append("")
    else:
        # Sort themes by frequency (descending)
        sorted_themes = sorted(themes, key=lambda x: x.get('count', 0), reverse=True)
        
        for i, theme in enumerate(sorted_themes, 1):
            theme_name = theme.get('name', 'Unknown Theme')
            count = theme.get('count', 0)
            description = theme.get('description', 'No description available.')
            supporting_studies = theme.get('supporting_studies', [])
            
            lines.append(f"### {i}. {theme_name}")
            lines.append("")
            lines.append(f"**Frequency:** Mentioned in {count} study(ies).")
            lines.append("")
            lines.append(f"**Description:** {description}")
            lines.append("")
            
            if supporting_studies:
                lines.append("**Supporting Evidence:**")
                lines.append("")
                for study in supporting_studies:
                    # Format: Author (Year): Description
                    author = study.get('author', 'Unknown')
                    year = study.get('year', 'n.d.')
                    desc = study.get('desc', '')
                    lines.append(f"- {author} ({year}): {desc}")
                lines.append("")
            else:
                lines.append("*No specific study references available for this theme.*")
                lines.append("")

    # Section 3: Limitations
    lines.append("## Limitations")
    lines.append("")
    lines.append(f"### Data Insufficiency (N < 10)")
    lines.append("")
    lines.append(f"The primary limitation of this synthesis is the small number of available studies (**N = {n}**).")
    lines.append("")
    lines.append("Consequently:")
    lines.append("- Statistical power is insufficient for a robust random-effects meta-analysis.")
    lines.append("- Heterogeneity metrics (I²) and publication bias tests (Egger's regression) cannot be reliably calculated.")
    lines.append("- The results presented here are qualitative in nature and should be interpreted as preliminary hypotheses rather than definitive effect sizes.")
    lines.append("")
    lines.append("### Systematic Review Fallback")
    lines.append("")
    lines.append("This report represents the 'Systematic Review Fallback' mechanism mandated by the project protocol when quantitative thresholds are not met.")
    lines.append("")
    
    return "\n".join(lines)

def run_narrative_engine() -> bool:
    """
    Main entry point for the Narrative Synthesis Engine.
    
    1. Loads study count and narrative themes.
    2. Checks the pivot condition (N < 10).
    3. Generates and saves the narrative content.
    
    Returns:
        True if successful, False otherwise (with error logging).
    """
    try:
        # Load inputs
        logger.info("Starting Narrative Synthesis Engine (T015b)...")
        study_count_data = load_study_count_json()
        themes_data = load_narrative_themes_json()
        
        n = study_count_data.get('N', 0)
        
        # Pivot Logic: Only generate content if N < 10
        # (Although T016 should only call this when N < 10, we enforce the logic here)
        if n >= 10:
            logger.warning(f"Pivot condition not met: N={n} >= 10. Skipping narrative generation.")
            logger.info("Quantitative meta-analysis is preferred when N >= 10.")
            return True  # Not an error, just a skip
        
        logger.info(f"Pivot condition met: N={n} < 10. Generating narrative content.")
        
        # Generate content
        content_md = generate_narrative_content(study_count_data, themes_data)
        
        # Write output
        root = get_project_root()
        output_path = root / NARRATIVE_CONTENT_OUTPUT
        ensure_directory(output_path)
        
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(content_md)
        
        logger.info(f"Successfully wrote narrative content to {output_path}")
        return True
        
    except FileNotFoundError as e:
        logger.error(f"Input file missing: {e}")
        return False
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        return False
    except Exception as e:
        logger.exception(f"Unexpected error during narrative generation: {e}")
        return False

def main():
    """Command-line entry point."""
    success = run_narrative_engine()
    sys.exit(0 if success else 1)

if __name__ == "__main__":
    main()