"""
Stratified Subset Selection for DeepFashion2 Benchmarking.

This module implements logic to select a benchmark subset from the filtered dataset
ensuring class balance across garment feature classes (color, pattern, texture).
"""

import json
import sys
import argparse
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple
from collections import defaultdict

# Import existing components
from src.data.loader import load_config, load_deepfashion2_streaming, iterate_dataset
from src.data.feasibility_filter import GarmentFeatureClass

def load_filtered_manifest(manifest_path: Path) -> List[Dict[str, Any]]:
    """
    Load the filtered subset manifest generated by feasibility_filter.py.
    
    Args:
        manifest_path: Path to the filtered_subset_manifest.json file.
        
    Returns:
        List of sample dictionaries that passed the feasibility filter.
        
    Raises:
        FileNotFoundError: If the manifest file does not exist.
        json.JSONDecodeError: If the manifest file is not valid JSON.
    """
    if not manifest_path.exists():
        raise FileNotFoundError(f"Filtered manifest not found at {manifest_path}")
    
    with open(manifest_path, 'r') as f:
        data = json.load(f)
        
    # Handle different possible structures
    if isinstance(data, list):
        return data
    elif isinstance(data, dict) and 'samples' in data:
        return data['samples']
    else:
        # Assume the whole file is a list of samples
        return data

def stratify_samples(
    samples: List[Dict[str, Any]], 
    target_size_per_class: int = 100
) -> Tuple[List[Dict[str, Any]], Dict[str, int]]:
    """
    Select a stratified subset ensuring class balance.
    
    This function groups samples by their GarmentFeatureClass and selects
    a balanced number of samples from each class to ensure fair comparison.
    
    Args:
        samples: List of sample dictionaries with 'garment_feature_class' field.
        target_size_per_class: Target number of samples per class.
        
    Returns:
        Tuple of (stratified_samples, class_counts) where:
            - stratified_samples: List of selected samples
            - class_counts: Dictionary mapping class names to actual selected counts
    """
    # Group samples by class
    class_groups: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    
    for sample in samples:
        feature_class = sample.get('garment_feature_class')
        if feature_class and feature_class in [c.value for c in GarmentFeatureClass]:
            class_groups[feature_class].append(sample)
        else:
            # Samples without valid feature class go to 'unknown' bucket
            class_groups['unknown'].append(sample)
    
    # Select samples from each class
    stratified_samples = []
    class_counts = {}
    
    for class_name, class_samples in class_groups.items():
        # Cap at target size per class
        actual_count = min(len(class_samples), target_size_per_class)
        
        # Select samples (first N for simplicity, could be random)
        selected = class_samples[:actual_count]
        stratified_samples.extend(selected)
        class_counts[class_name] = actual_count
    
    return stratified_samples, class_counts

def validate_subset_balance(
    samples: List[Dict[str, Any]], 
    tolerance_percent: float = 10.0
) -> Tuple[bool, Dict[str, Any]]:
    """
    Validate that the subset has reasonable class balance.
    
    Args:
        samples: List of sample dictionaries.
        tolerance_percent: Maximum allowed deviation from perfect balance (percent).
        
    Returns:
        Tuple of (is_balanced, details) where:
            - is_balanced: True if subset meets balance criteria
            - details: Dictionary with balance statistics
    """
    # Count samples per class
    class_counts = defaultdict(int)
    for sample in samples:
        feature_class = sample.get('garment_feature_class', 'unknown')
        class_counts[feature_class] += 1
    
    if not class_counts:
        return False, {"error": "No samples in subset"}
    
    total_samples = sum(class_counts.values())
    expected_per_class = total_samples / len(class_counts)
    
    # Check balance
    balance_issues = []
    for class_name, count in class_counts.items():
        deviation = abs(count - expected_per_class) / expected_per_class * 100
        if deviation > tolerance_percent:
            balance_issues.append({
                "class": class_name,
                "count": count,
                "expected": expected_per_class,
                "deviation_percent": deviation
            })
    
    is_balanced = len(balance_issues) == 0
    
    details = {
        "total_samples": total_samples,
        "num_classes": len(class_counts),
        "class_counts": dict(class_counts),
        "is_balanced": is_balanced,
        "issues": balance_issues
    }
    
    return is_balanced, details

def save_stratified_subset(
    samples: List[Dict[str, Any]], 
    class_counts: Dict[str, int], 
    output_path: Path,
    validation_report: Optional[Dict[str, Any]] = None
) -> None:
    """
    Save the stratified subset to a JSON file.
    
    Args:
        samples: List of selected sample dictionaries.
        class_counts: Dictionary of class counts.
        output_path: Path to output JSON file.
        validation_report: Optional validation report to include.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    output_data = {
        "subset_info": {
            "total_samples": len(samples),
            "class_counts": class_counts,
            "validation": validation_report
        },
        "samples": samples
    }
    
    with open(output_path, 'w') as f:
        json.dump(output_data, f, indent=2)

def run_pipeline(
    filtered_manifest_path: Path,
    output_subset_path: Path,
    target_size_per_class: int = 100,
    validate: bool = True
) -> Dict[str, Any]:
    """
    Run the full stratified subset selection pipeline.
    
    Args:
        filtered_manifest_path: Path to filtered_subset_manifest.json.
        output_subset_path: Path for output stratified subset.
        target_size_per_class: Target samples per class.
        validate: Whether to validate balance.
        
    Returns:
        Dictionary with pipeline results and statistics.
    """
    # Load filtered samples
    print(f"Loading filtered manifest from {filtered_manifest_path}...")
    filtered_samples = load_filtered_manifest(filtered_manifest_path)
    print(f"Loaded {len(filtered_samples)} filtered samples.")
    
    # Stratify
    print(f"Stratifying samples with target {target_size_per_class} per class...")
    stratified_samples, class_counts = stratify_samples(
        filtered_samples, 
        target_size_per_class
    )
    print(f"Selected {len(stratified_samples)} stratified samples.")
    
    # Validate if requested
    validation_report = None
    if validate:
        is_balanced, validation_report = validate_subset_balance(stratified_samples)
        print(f"Balance validation: {'PASSED' if is_balanced else 'FAILED'}")
        if validation_report.get('issues'):
            for issue in validation_report['issues']:
                print(f"  - {issue['class']}: {issue['deviation_percent']:.1f}% deviation")
    
    # Save output
    print(f"Saving stratified subset to {output_subset_path}...")
    save_stratified_subset(
        stratified_samples, 
        class_counts, 
        output_subset_path,
        validation_report
    )
    
    return {
        "total_input_samples": len(filtered_samples),
        "total_output_samples": len(stratified_samples),
        "class_counts": class_counts,
        "validation_passed": validation_report.get('is_balanced') if validation_report else None,
        "output_path": str(output_subset_path)
    }

def main():
    """Main entry point for command-line execution."""
    parser = argparse.ArgumentParser(
        description="Create a stratified subset from filtered DeepFashion2 samples."
    )
    parser.add_argument(
        "--input-manifest",
        type=str,
        default="data/processed/filtered_subset_manifest.json",
        help="Path to filtered subset manifest (default: data/processed/filtered_subset_manifest.json)"
    )
    parser.add_argument(
        "--output-subset",
        type=str,
        default="data/processed/stratified_benchmark_subset.json",
        help="Path for output stratified subset (default: data/processed/stratified_benchmark_subset.json)"
    )
    parser.add_argument(
        "--target-per-class",
        type=int,
        default=100,
        help="Target number of samples per class (default: 100)"
    )
    parser.add_argument(
        "--no-validate",
        action="store_true",
        help="Skip balance validation"
    )
    
    args = parser.parse_args()
    
    try:
        results = run_pipeline(
            filtered_manifest_path=Path(args.input_manifest),
            output_subset_path=Path(args.output_subset),
            target_size_per_class=args.target_per_class,
            validate=not args.no_validate
        )
        
        print("\nPipeline Results:")
        print(json.dumps(results, indent=2))
        
    except FileNotFoundError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f"ERROR: Pipeline failed with {type(e).__name__}: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()
