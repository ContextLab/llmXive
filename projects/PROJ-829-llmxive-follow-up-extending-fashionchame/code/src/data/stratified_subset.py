import json
import sys
import argparse
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple
from collections import defaultdict

def load_filtered_manifest(manifest_path: str) -> List[Dict[str, Any]]:
    """Loads the filtered subset manifest.
    
    Reads the JSON file generated by T021-redo (filtered_subset_manifest.json).
    """
    path = Path(manifest_path)
    if not path.exists():
        raise FileNotFoundError(f"Manifest not found: {manifest_path}")
    
    with open(path, 'r') as f:
        data = json.load(f)
    
    # Handle both list format and dict with 'samples' key
    if isinstance(data, list):
        return data
    elif isinstance(data, dict) and 'samples' in data:
        return data['samples']
    else:
        # Fallback: try to treat the whole dict as a single sample or list of values
        if isinstance(data, dict):
            return [data]
        return []

def stratify_samples(samples: List[Dict[str, Any]], class_key: str = 'GarmentFeatureClass') -> Dict[str, List[Dict[str, Any]]]:
    """Stratifies samples by class.
    
    Groups samples into buckets based on their GarmentFeatureClass attribute
    (Color, Pattern, Texture).
    """
    stratified = defaultdict(list)
    for sample in samples:
        # Try the spec-defined key first, then common variants
        cls = (
            sample.get('GarmentFeatureClass') or 
            sample.get('garment_class') or 
            sample.get('feature_class') or 
            'Unknown'
        )
        stratified[cls].append(sample)
    return stratified

def validate_subset_balance(stratified: Dict[str, List[Dict[str, Any]]], min_count: int = 10) -> bool:
    """Validates that each class has enough samples.
    
    Checks if every class bucket meets the minimum sample count threshold.
    Returns True if balanced, False otherwise (with warnings).
    """
    valid = True
    for cls, samples in stratified.items():
        count = len(samples)
        if count < min_count:
            print(f"Warning: Class '{cls}' has only {count} samples (min: {min_count}).")
            valid = False
        else:
            print(f"Class '{cls}': {count} samples (OK)")
    return valid

def save_stratified_subset(stratified: Dict[str, List[Dict[str, Any]]], output_path: str) -> None:
    """Saves the stratified subset to a manifest.
    
    This artifact MUST list samples grouped by GarmentFeatureClass to satisfy 
    Constitution Principle VI.
    
    The manifest structure:
    {
      "stratified_by": "GarmentFeatureClass",
      "total_samples": <int>,
      "classes": {
        "<class_name>": {
          "count": <int>,
          "sample_ids": [<str>, ...],
          "samples": [<full_sample_dict>, ...]
        }
      }
    }
    """
    manifest = {
        "stratified_by": "GarmentFeatureClass",
        "total_samples": sum(len(v) for v in stratified.values()),
        "classes": {}
    }
    
    for cls, samples in stratified.items():
        # Extract sample IDs and key metadata for the manifest
        sample_ids = []
        for s in samples:
            sample_id = s.get('id') or s.get('sample_id') or s.get('video_id')
            if sample_id is None:
                # Generate a fallback ID if none exists
                sample_id = f"sample_{len(sample_ids)}"
            sample_ids.append(sample_id)
        
        manifest["classes"][cls] = {
            "count": len(samples),
            "sample_ids": sample_ids,
            "samples": samples  # Store full sample objects for downstream use
        }

    # Ensure output directory exists
    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_file, 'w') as f:
        json.dump(manifest, f, indent=2)
    
    print(f"Stratified subset saved to {output_path}")
    print(f"Total samples: {manifest['total_samples']}")
    print(f"Classes: {list(manifest['classes'].keys())}")
    for cls, data in manifest["classes"].items():
        print(f"  {cls}: {data['count']} samples")

def run_pipeline(input_manifest_path: str, output_manifest_path: str) -> None:
    """Runs the stratified subset pipeline.
    
    1. Loads the filtered subset manifest (from T021-redo).
    2. Stratifies samples by GarmentFeatureClass.
    3. Validates balance (warns if < 10 per class).
    4. Saves the stratified manifest to disk.
    
    Args:
        input_manifest_path: Path to filtered_subset_manifest.json
        output_manifest_path: Path to write stratified_subset_manifest.json
    """
    print(f"Loading filtered manifest from {input_manifest_path}...")
    try:
        samples = load_filtered_manifest(input_manifest_path)
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        print("The filtered_subset_manifest.json must be generated by T021-redo first.")
        sys.exit(1)
    
    print(f"Loaded {len(samples)} samples.")
    
    if len(samples) == 0:
        print("Warning: No samples found in input manifest. Creating empty stratified manifest.")
        stratified = {}
    else:
        print("Stratifying by GarmentFeatureClass...")
        stratified = stratify_samples(samples)
    
    if len(stratified) == 0:
        print("Warning: No classes found. Creating empty stratified manifest.")
    
    print("Validating subset balance...")
    is_balanced = validate_subset_balance(stratified)
    
    if not is_balanced:
        print("Warning: Subset is imbalanced. Proceeding anyway.")
    
    print(f"Saving stratified manifest to {output_manifest_path}...")
    save_stratified_subset(stratified, output_manifest_path)
    print("Pipeline complete.")

def main():
    parser = argparse.ArgumentParser(description="Stratify Subset for Benchmark (T016b)")
    parser.add_argument('--input', type=str, 
                        default='data/processed/filtered_subset_manifest.json',
                        help='Path to filtered subset manifest (T021-redo output)')
    parser.add_argument('--output', type=str, 
                        default='data/processed/stratified_subset_manifest.json',
                        help='Path to output stratified manifest')
    args = parser.parse_args()

    run_pipeline(args.input, args.output)

if __name__ == '__main__':
    main()