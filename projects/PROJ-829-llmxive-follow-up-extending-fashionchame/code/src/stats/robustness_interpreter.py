import json
import csv
import sys
import argparse
from pathlib import Path
from typing import Dict, Any, List, Optional
from collections import defaultdict

def load_sensitivity_analysis(input_path: str) -> List[Dict[str, Any]]:
    """
    Load the sensitivity analysis CSV file generated by T035.
    
    Args:
        input_path: Path to data/processed/sensitivity_analysis.csv
        
    Returns:
        List of dictionaries containing threshold and robustness_metric.
    """
    results = []
    path = Path(input_path)
    if not path.exists():
        raise FileNotFoundError(f"Sensitivity analysis file not found: {input_path}")
        
    with open(path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                results.append({
                    'threshold': float(row['threshold']),
                    'robustness_metric': float(row['robustness_metric'])
                })
            except (ValueError, KeyError) as e:
                raise ValueError(f"Invalid data in row {row}: {e}")
    
    if not results:
        raise ValueError("Sensitivity analysis file is empty or has no valid data rows.")
        
    return results

def calculate_final_robustness_index(data: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Calculate the final Robustness Index and analyze stability.
    
    The Robustness Index is the mean of the robustness_metric column.
    Stability is determined by checking if the metric remains > 90% for the majority
    of the threshold range (0.0 to 1.0).
    
    Args:
        data: List of analysis results from load_sensitivity_analysis.
        
    Returns:
        Dictionary with final index, stability status, and detailed stats.
    """
    if not data:
        raise ValueError("Cannot calculate index from empty data.")
        
    metrics = [d['robustness_metric'] for d in data]
    thresholds = [d['threshold'] for d in data]
    
    mean_index = sum(metrics) / len(metrics)
    min_index = min(metrics)
    max_index = max(metrics)
    std_dev = (sum((x - mean_index) ** 2 for x in metrics) / len(metrics)) ** 0.5
    
    # Stability check: Is the mean robustness > 90%?
    # This indicates the motion labels are stable across threshold variations.
    is_stable = mean_index >= 90.0
    
    # Check for significant drops (instability)
    # If any point drops below 50%, it indicates high sensitivity at that threshold.
    has_instability = any(m < 50.0 for m in metrics)
    
    return {
        "final_robustness_index": mean_index,
        "min_index": min_index,
        "max_index": max_index,
        "std_dev": std_dev,
        "is_stable": is_stable,
        "has_instability": has_instability,
        "sample_count": len(data),
        "threshold_range": f"{min(thresholds)} to {max(thresholds)}"
    }

def generate_robustness_report(input_path: str, output_path: str) -> Dict[str, Any]:
    """
    Generate the final robustness report JSON.
    
    Args:
        input_path: Path to sensitivity_analysis.csv.
        output_path: Path to write robustness_report.json.
        
    Returns:
        The generated report dictionary.
    """
    # Load data
    data = load_sensitivity_analysis(input_path)
    
    # Calculate metrics
    analysis = calculate_final_robustness_index(data)
    
    # Determine conclusion
    if analysis['is_stable']:
        conclusion = "The motion labeling pipeline demonstrates high robustness. " \
                     "Optical flow magnitude thresholds between 0.0 and 1.0 yield consistent " \
                     "motion labels (High/Low) across the majority of samples."
    elif analysis['has_instability']:
        conclusion = "WARNING: The pipeline shows instability at specific thresholds. " \
                     "Some threshold values cause significant fluctuations in motion labels. " \
                     "Review the sensitivity_analysis.csv for specific drop-off points."
    else:
        conclusion = "The pipeline shows moderate robustness. While not strictly stable " \
                     "(>=90%), it does not exhibit catastrophic failure (>=50%). " \
                     "Further tuning of the optical flow threshold may be beneficial."
                     
    report = {
        "summary": {
            "input_file": input_path,
            "generated_at": "runtime",
            "status": "STABLE" if analysis['is_stable'] else "UNSTABLE" if analysis['has_instability'] else "MODERATE"
        },
        "metrics": analysis,
        "interpretation": {
            "conclusion": conclusion,
            "recommendation": "Proceed with benchmark if stable. Re-tune threshold if unstable."
        },
        "raw_data_summary": {
            "thresholds_tested": len(data),
            "avg_robustness": analysis['final_robustness_index'],
            "variance": analysis['std_dev'] ** 2
        }
    }
    
    # Write to disk
    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)
        
    return report

def main():
    parser = argparse.ArgumentParser(
        description="Interpret sensitivity analysis results and generate robustness report."
    )
    parser.add_argument(
        "--input",
        type=str,
        default="data/processed/sensitivity_analysis.csv",
        help="Path to the sensitivity analysis CSV file."
    )
    parser.add_argument(
        "--output",
        type=str,
        default="data/processed/robustness_report.json",
        help="Path to write the robustness report JSON."
    )
    
    args = parser.parse_args()
    
    try:
        print(f"Loading sensitivity analysis from: {args.input}")
        report = generate_robustness_report(args.input, args.output)
        
        print(f"Robustness Report generated: {args.output}")
        print(f"Final Robustness Index: {report['metrics']['final_robustness_index']:.2f}%")
        print(f"Status: {report['summary']['status']}")
        print(f"Conclusion: {report['interpretation']['conclusion'][:100]}...")
        
        return 0
    except FileNotFoundError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1
    except ValueError as e:
        print(f"DATA ERROR: {e}", file=sys.stderr)
        return 1
    except Exception as e:
        print(f"UNEXPECTED ERROR: {e}", file=sys.stderr)
        return 1

if __name__ == "__main__":
    sys.exit(main())
