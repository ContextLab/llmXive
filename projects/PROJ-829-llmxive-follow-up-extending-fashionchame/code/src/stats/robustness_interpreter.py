import json
import csv
import sys
import argparse
from pathlib import Path
from typing import Dict, Any, List, Optional
from collections import defaultdict

def load_sensitivity_analysis(csv_path: Path) -> List[Dict[str, Any]]:
    """
    Load the sensitivity analysis CSV generated by T035.
    Expected columns: threshold, robustness_metric
    """
    if not csv_path.exists():
        raise FileNotFoundError(f"Sensitivity analysis file not found: {csv_path}")
    
    data = []
    with open(csv_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            data.append({
                'threshold': float(row['threshold']),
                'robustness_metric': float(row['robustness_metric'])
            })
    return data

def calculate_final_robustness_index(data: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Calculate the final Robustness Index and analyze stability.
    
    The Robustness Index is defined as the average robustness_metric across all thresholds,
    representing the overall stability of motion labeling against threshold variations.
    
    Returns a dictionary with:
    - final_robustness_index: float (average of robustness_metric)
    - stability_status: "STABLE" if index > 0.8, "MODERATE" if > 0.5, "UNSTABLE" otherwise
    - min_metric: minimum robustness_metric observed
    - max_metric: maximum robustness_metric observed
    - threshold_range: (min_threshold, max_threshold)
    - sample_count: number of thresholds analyzed
    """
    if not data:
        raise ValueError("Sensitivity analysis data is empty")
    
    metrics = [d['robustness_metric'] for d in data]
    thresholds = [d['threshold'] for d in data]
    
    final_index = sum(metrics) / len(metrics)
    
    if final_index > 0.8:
        stability_status = "STABLE"
    elif final_index > 0.5:
        stability_status = "MODERATE"
    else:
        stability_status = "UNSTABLE"
    
    return {
        'final_robustness_index': final_index,
        'stability_status': stability_status,
        'min_metric': min(metrics),
        'max_metric': max(metrics),
        'threshold_range': (min(thresholds), max(thresholds)),
        'sample_count': len(data)
    }

def generate_robustness_report(data: List[Dict[str, Any]], output_path: Path) -> None:
    """
    Generate the robustness report JSON file.
    
    The report confirms robustness against a defined threshold or flags instability.
    """
    analysis = calculate_final_robustness_index(data)
    
    # Determine if the system is robust enough for production use
    # A system is considered robust if the stability status is STABLE or MODERATE
    # and the minimum metric is above 0.3 (no catastrophic failure points)
    is_production_ready = (
        analysis['stability_status'] in ['STABLE', 'MODERATE'] and 
        analysis['min_metric'] > 0.3
    )
    
    report = {
        'summary': {
            'final_robustness_index': analysis['final_robustness_index'],
            'stability_status': analysis['stability_status'],
            'production_ready': is_production_ready,
            'thresholds_analyzed': analysis['sample_count'],
            'threshold_range': {
                'min': analysis['threshold_range'][0],
                'max': analysis['threshold_range'][1]
            }
        },
        'metrics': {
            'mean_robustness': analysis['final_robustness_index'],
            'min_robustness': analysis['min_metric'],
            'max_robustness': analysis['max_metric'],
            'range': analysis['max_metric'] - analysis['min_metric']
        },
        'interpretation': {
            'status': analysis['stability_status'],
            'message': (
                f"The motion labeling pipeline shows {analysis['stability_status'].lower()} "
                f"robustness to optical flow threshold variations. "
                f"Average Robustness Index: {analysis['final_robustness_index']:.4f}. "
                f"{'System is ready for production.' if is_production_ready else 'System requires threshold optimization or further analysis.'}"
            )
        },
        'raw_data_summary': {
            'sample_count': analysis['sample_count'],
            'thresholds': [d['threshold'] for d in data],
            'metrics': [d['robustness_metric'] for d in data]
        }
    }
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)

def main():
    parser = argparse.ArgumentParser(
        description='Interpret sensitivity analysis results and generate robustness report.'
    )
    parser.add_argument(
        '--input-csv',
        type=str,
        default='data/processed/sensitivity_analysis.csv',
        help='Path to the sensitivity analysis CSV file.'
    )
    parser.add_argument(
        '--output-json',
        type=str,
        default='data/processed/robustness_report.json',
        help='Path to write the robustness report JSON.'
    )
    
    args = parser.parse_args()
    
    input_path = Path(args.input_csv)
    output_path = Path(args.output_json)
    
    try:
        print(f"Loading sensitivity analysis from: {input_path}")
        data = load_sensitivity_analysis(input_path)
        print(f"Loaded {len(data)} data points.")
        
        print(f"Generating robustness report: {output_path}")
        generate_robustness_report(data, output_path)
        
        print("Robustness report generated successfully.")
        
        # Print summary to stdout
        analysis = calculate_final_robustness_index(data)
        print(f"\nSummary:")
        print(f"  Final Robustness Index: {analysis['final_robustness_index']:.4f}")
        print(f"  Stability Status: {analysis['stability_status']}")
        print(f"  Production Ready: {analysis['stability_status'] in ['STABLE', 'MODERATE'] and analysis['min_metric'] > 0.3}")
        
    except FileNotFoundError as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
    except ValueError as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f"Unexpected error: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == '__main__':
    main()
