import csv
import json
import sys
import argparse
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple
from collections import defaultdict

# Import from sibling modules as per API surface
# We assume T034-extended produced data/processed/motion_labels.json
# We assume T033 logic (which might be in this file or imported) provides the ground truth vs prediction logic.
# Since T033 is marked completed, we assume the logic to derive motion labels exists.
# However, for T035 specifically, we need to read the motion labels and compare them against
# a threshold derived from optical flow magnitude to calculate FP/FN rates.

# The task requires:
# 1. Read motion labels (ground truth) from data/processed/motion_labels.json (produced by T034-extended)
# 2. Iterate through thresholds {0.01, 0.05, 0.1} (or range)
# 3. For each threshold, classify samples as High/Low motion based on optical_flow_magnitude
# 4. Compare with ground truth motion_label
# 5. Calculate False Positive Rate (FP) and False Negative Rate (FN)
# 6. Output to data/processed/sensitivity_analysis.csv

def load_motion_labels(path: Path) -> List[Dict[str, Any]]:
    """Load motion labels generated by T034-extended."""
    if not path.exists():
        raise FileNotFoundError(f"Motion labels file not found: {path}. "
                                "Ensure T034-extended has been run to generate data/processed/motion_labels.json.")
    with open(path, 'r') as f:
        return json.load(f)

def calculate_fp_fn_rates(samples: List[Dict[str, Any]], threshold: float) -> Tuple[float, float]:
    """
    Calculate False Positive and False Negative rates for a given threshold.
    
    Ground Truth (from T034-extended):
      - 'High' motion: Optical flow magnitude is high.
      - 'Low' motion: Optical flow magnitude is low.
    
    Prediction (Derived from threshold):
      - If optical_flow_magnitude >= threshold: Predicted 'High'
      - If optical_flow_magnitude < threshold: Predicted 'Low'
    
    Confusion Matrix definitions:
      - True Positive (TP): Predicted High, Actual High
      - False Positive (FP): Predicted High, Actual Low (Type I error)
      - True Negative (TN): Predicted Low, Actual Low
      - False Negative (FN): Predicted Low, Actual High (Type II error)
    
    Rates:
      - FP Rate = FP / (FP + TN)  [Proportion of actual negatives incorrectly identified as positive]
      - FN Rate = FN / (FN + TP)  [Proportion of actual positives incorrectly identified as negative]
    """
    tp, fp, tn, fn = 0, 0, 0, 0

    for sample in samples:
        magnitude = sample.get('optical_flow_magnitude', 0.0)
        actual_label = sample.get('motion_label', '').strip().lower()
        
        # Determine prediction based on threshold
        predicted_label = 'high' if magnitude >= threshold else 'low'

        if actual_label == 'high' and predicted_label == 'high':
            tp += 1
        elif actual_label == 'low' and predicted_label == 'high':
            fp += 1
        elif actual_label == 'low' and predicted_label == 'low':
            tn += 1
        elif actual_label == 'high' and predicted_label == 'low':
            fn += 1
        else:
            # Handle unexpected labels if any, or ignore
            continue

    # Calculate rates, handling division by zero
    fp_rate = fp / (fp + tn) if (fp + tn) > 0 else 0.0
    fn_rate = fn / (fn + tp) if (fn + tp) > 0 else 0.0

    return fp_rate, fn_rate

def run_sensitivity_analysis(input_path: Path, output_path: Path, thresholds: Optional[List[float]] = None):
    """
    Run the sensitivity analysis by sweeping thresholds.
    
    Args:
        input_path: Path to motion_labels.json
        output_path: Path for sensitivity_analysis.csv
        thresholds: List of thresholds to test. Defaults to [0.01, 0.05, 0.1]
    """
    if thresholds is None:
        thresholds = [0.01, 0.05, 0.1]

    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")

    samples = load_motion_labels(input_path)
    
    if not samples:
        raise ValueError("No samples found in motion labels file.")

    results = []
    for t in thresholds:
        fp, fn = calculate_fp_fn_rates(samples, t)
        results.append({
            'threshold': t,
            'fp_rate': fp,
            'fn_rate': fn
        })
        print(f"Threshold: {t:.4f} -> FP Rate: {fp:.4f}, FN Rate: {fn:.4f}")

    # Write to CSV
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', newline='') as csvfile:
        fieldnames = ['threshold', 'fp_rate', 'fn_rate']
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        writer.writeheader()
        for row in results:
            writer.writerow(row)

    print(f"Sensitivity analysis complete. Results written to {output_path}")

def main():
    parser = argparse.ArgumentParser(description="Generate threshold variation table for motion detection sensitivity.")
    parser.add_argument('--input', type=str, default='data/processed/motion_labels.json',
                        help='Path to the motion labels JSON file.')
    parser.add_argument('--output', type=str, default='data/processed/sensitivity_analysis.csv',
                        help='Path for the output CSV file.')
    parser.add_argument('--thresholds', type=str, default='0.01,0.05,0.1',
                        help='Comma-separated list of thresholds to test.')
    
    args = parser.parse_args()

    try:
        thresholds = [float(t.strip()) for t in args.thresholds.split(',')]
        run_sensitivity_analysis(
            input_path=Path(args.input),
            output_path=Path(args.output),
            thresholds=thresholds
        )
    except FileNotFoundError as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f"Error during sensitivity analysis: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()