@dataclass
class MergeResult:
    processed_count: int
    missing_count: int
    total_input_genomic: int
    total_input_phenotypic: int
    linkage_ratio: float
    output_path: str
    report_path: str
    is_aggregated: bool = False

def load_genomic_features(features_dir: Path) -> List[Dict[str, Any]]:
    """
    Loads genomic features from CSV files generated by extract.py.
    Expected format: strain_id, feature_id, type, presence_binary, pwm_count, source
    """
    features = []
    if not features_dir.exists():
        logger.warning(f"Features directory {features_dir} does not exist.")
        return features

    for csv_file in features_dir.glob("*.csv"):
        logger.info(f"Loading genomic features from {csv_file}")
        with open(csv_file, 'r', newline='', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            for row in reader:
                # Ensure types are correct
                row['presence_binary'] = int(row['presence_binary'])
                row['pwm_count'] = int(row['pwm_count'])
                features.append(row)
    return features

def load_phenotypic_scores(phenotype_dir: Path) -> List[Dict[str, Any]]:
    """
    Loads phenotypic scores from CSV files generated by download.py.
    Expected format: strain_id, species, phenotype_score, metadata
    """
    scores = []
    if not phenotype_dir.exists():
        logger.warning(f"Phenotype directory {phenotype_dir} does not exist.")
        return scores

    for csv_file in phenotype_dir.glob("*.csv"):
        logger.info(f"Loading phenotypic scores from {csv_file}")
        with open(csv_file, 'r', newline='', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            for row in reader:
                row['phenotype_score'] = float(row['phenotype_score'])
                scores.append(row)
    return scores

def aggregate_by_species(phenotypic_scores: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Aggregates phenotypic scores by species if isolate-level linkage is low.
    Returns a list of species aggregates with avg_phenotype and isolate_count.
    """
    species_data: Dict[str, List[float]] = {}
    species_counts: Dict[str, int] = {}

    for score in phenotypic_scores:
        species = score['species']
        if species not in species_data:
            species_data[species] = []
            species_counts[species] = 0
        
        species_data[species].append(score['phenotype_score'])
        species_counts[species] += 1

    aggregates = []
    for species, scores in species_data.items():
        avg_score = sum(scores) / len(scores)
        variance = sum((x - avg_score) ** 2 for x in scores) / len(scores) if len(scores) > 1 else 0.0
        aggregates.append({
            'species_name': species,
            'avg_phenotype': avg_score,
            'isolate_count': species_counts[species],
            'variance': variance
        })
    return aggregates

def align_and_merge(genomic_features: List[Dict[str, Any]], 
                    phenotypic_scores: List[Dict[str, Any]], 
                    fallback_threshold: float = 0.5) -> Tuple[pd.DataFrame, bool]:
    """
    Aligns genomic features with phenotypic scores.
    If <50% of genomic features have matching phenotypes, aggregates by species.
    
    Returns:
        DataFrame: Merged dataset
        bool: True if aggregated by species, False if isolate-level merge
    """
    if not genomic_features:
        logger.warning("No genomic features found to merge.")
        return pd.DataFrame(), False
    
    if not phenotypic_scores:
        logger.warning("No phenotypic scores found to merge.")
        return pd.DataFrame(), False

    # Create lookup for phenotypes by strain_id
    phenotype_lookup = {p['strain_id']: p for p in phenotypic_scores}
    
    # Create a pivot table for genomic features
    # Rows: strain_id, Columns: feature_id, Values: presence_binary or pwm_count
    # We'll create two separate wide tables or one combined? 
    # Let's assume we want presence_binary primarily, but maybe we include counts too.
    # For simplicity in this task, we'll create a wide table of presence_binary.
    
    df_genomic = pd.DataFrame(genomic_features)
    if df_genomic.empty:
        return pd.DataFrame(), False

    # Pivot to wide format: index=strain_id, columns=feature_id, values=presence_binary
    df_pivot = df_genomic.pivot_table(
        index='strain_id', 
        columns='feature_id', 
        values='presence_binary', 
        aggfunc='first', 
        fill_value=0
    ).reset_index()
    
    # Calculate linkage ratio
    matched_strains = df_pivot['strain_id'].isin(phenotype_lookup.keys())
    matched_count = matched_strains.sum()
    total_genomic_strains = len(df_pivot)
    linkage_ratio = matched_count / total_genomic_strains if total_genomic_strains > 0 else 0.0

    logger.info(f"Linkage ratio: {linkage_ratio:.2f} ({matched_count}/{total_genomic_strains})")

    is_aggregated = False
    
    if linkage_ratio < fallback_threshold:
        logger.warning(f"Linkage ratio {linkage_ratio:.2f} < {fallback_threshold}. Aggregating by species.")
        is_aggregated = True
        
        # Aggregate phenotypes by species
        species_agg = aggregate_by_species(phenotypic_scores)
        df_species = pd.DataFrame(species_agg)
        
        # We need to map genomic features to species. 
        # This requires a mapping from strain_id to species.
        # We can get this from the original phenotypic scores or genomic features if they have species info.
        # Let's assume genomic features have 'species' or we derive from phenotypic_scores.
        # Since phenotypic_scores has 'species', we can map strain_id -> species.
        
        strain_to_species = {p['strain_id']: p['species'] for p in phenotypic_scores}
        df_pivot['species'] = df_pivot['strain_id'].map(strain_to_species)
        
        # Group genomic features by species (mean presence)
        feature_cols = [col for col in df_pivot.columns if col != 'strain_id' and col != 'species']
        df_genomic_agg = df_pivot.groupby('species')[feature_cols].mean().reset_index()
        
        # Merge with species aggregates
        df_merged = df_genomic_agg.merge(df_species, on='species', how='inner')
        df_merged = df_merged.rename(columns={'species': 'species_name'})
        
    else:
        # Isolate level merge
        df_pivot = df_pivot.rename(columns={'strain_id': 'strain_id'})
        phenotypes = []
        for strain_id in df_pivot['strain_id']:
            if strain_id in phenotype_lookup:
                p = phenotype_lookup[strain_id]
                phenotypes.append({
                    'strain_id': strain_id,
                    'species': p['species'],
                    'phenotype_score': p['phenotype_score']
                })
        
        df_pheno = pd.DataFrame(phenotypes)
        df_merged = df_pivot.merge(df_pheno, on='strain_id', how='inner')

    return df_merged, is_aggregated

def write_merged_dataset(df: pd.DataFrame, output_path: Path, is_aggregated: bool) -> str:
    """
    Writes the merged dataset to a Parquet file and a CSV summary report.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Write Parquet
    df.to_parquet(output_path, index=False)
    logger.info(f"Wrote merged dataset to {output_path}")
    
    # Generate summary report
    report_data = {
        "output_file": str(output_path),
        "total_rows": len(df),
        "is_aggregated": is_aggregated,
        "columns": list(df.columns),
        "column_types": {col: str(df[col].dtype) for col in df.columns},
        "missing_counts": df.isnull().sum().to_dict(),
        "phenotype_stats": {
            "mean": float(df['phenotype_score'].mean()) if 'phenotype_score' in df.columns else None,
            "std": float(df['phenotype_score'].std()) if 'phenotype_score' in df.columns else None,
            "min": float(df['phenotype_score'].min()) if 'phenotype_score' in df.columns else None,
            "max": float(df['phenotype_score'].max()) if 'phenotype_score' in df.columns else None
        }
    }
    
    report_path = output_path.parent / "merge_summary.json"
    with open(report_path, 'w', encoding='utf-8') as f:
        json.dump(report_data, f, indent=2)
    
    logger.info(f"Wrote summary report to {report_path}")
    return str(report_path)

def main():
    """
    Main entry point for the merge task.
    Reads from data/raw (or data/processed intermediates) and writes to data/processed/merged_dataset.parquet.
    """
    # Define paths based on project structure
    # Assuming genomic features and phenotypic scores are in data/processed as intermediate CSVs
    # or data/raw if they are raw downloads. 
    # Based on T015-T020, they likely write to data/processed as intermediate CSVs.
    # Let's assume:
    #   data/processed/genomic_features.csv (from T017/18)
    #   data/processed/phenotypic_scores.csv (from T016)
    
    base_dir = Path("data/processed")
    genomic_dir = base_dir  # Assuming CSVs are here
    phenotype_dir = base_dir
    
    output_dir = Path("data/processed")
    output_file = output_dir / "merged_dataset.parquet"
    
    logger.info("Starting merge process...")
    
    # Load data
    genomic_features = load_genomic_features(genomic_dir)
    phenotypic_scores = load_phenotypic_scores(phenotype_dir)
    
    if not genomic_features:
        raise RuntimeError("No genomic features found. Ensure T017/T018 have run.")
    if not phenotypic_scores:
        raise RuntimeError("No phenotypic scores found. Ensure T016 has run.")
    
    logger.info(f"Loaded {len(genomic_features)} genomic features and {len(phenotypic_scores)} phenotypic scores.")
    
    # Align and merge
    df_merged, is_aggregated = align_and_merge(genomic_features, phenotypic_scores)
    
    if df_merged.empty:
        raise RuntimeError("Merge resulted in an empty dataset. Check linkage logic.")
    
    # Calculate counts for report
    processed_count = len(df_merged)
    missing_count = df_merged.isnull().sum().sum()
    linkage_ratio = processed_count / len(genomic_features) if len(genomic_features) > 0 else 0.0
    
    # Write output
    report_path = write_merged_dataset(df_merged, output_file, is_aggregated)
    
    # Create MergeResult for logging
    result = MergeResult(
        processed_count=processed_count,
        missing_count=missing_count,
        total_input_genomic=len(genomic_features),
        total_input_phenotypic=len(phenotypic_scores),
        linkage_ratio=linkage_ratio,
        output_path=str(output_file),
        report_path=report_path,
        is_aggregated=is_aggregated
    )
    
    logger.info(f"Merge completed. Processed: {result.processed_count}, Missing: {result.missing_count}, Aggregated: {result.is_aggregated}")
    return result

if __name__ == "__main__":
    main()
