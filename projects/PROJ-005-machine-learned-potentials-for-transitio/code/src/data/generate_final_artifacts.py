def load_processed_graphs_for_splitting(graphs_path: Path) -> pd.DataFrame:
    """
    Load the processed graphs parquet file to retrieve metadata and sample IDs.
    This is used to enrich the predictions with context if necessary.
    """
    if not graphs_path.exists():
        raise FileNotFoundError(f"Graphs file not found at {graphs_path}")
    
    # Load as DataFrame; assumes it has 'sample_id' and potentially 'ligand_class'
    df = pd.read_parquet(graphs_path)
    return df

def aggregate_predictions(residuals_path: Path, graphs_path: Path, output_path: Path) -> None:
    """
    Aggregates raw predictions from residuals.parquet into the final predictions.parquet.
    
    Logic:
    1. Load residuals.parquet (generated by T025).
    2. Load graphs.parquet (generated by T017) to retrieve additional metadata 
       (e.g., ligand_class, metal_center) if not present in residuals.
    3. Merge on 'sample_id' to ensure a complete record.
    4. Calculate final predicted barrier height: predicted = dft_barrier + error_ml_dft.
       (Assuming residuals contains 'error_ml_dft' and 'dft_barrier' or 'energy_dft').
    5. Save to code/data/processed/predictions.parquet.
    
    Args:
        residuals_path: Path to residuals.parquet
        graphs_path: Path to graphs.parquet
        output_path: Path to write predictions.parquet
    """
    logger = get_logger(__name__)
    
    logger.info(f"Loading residuals from {residuals_path}")
    if not residuals_path.exists():
        raise FileNotFoundError(f"Residuals file not found at {residuals_path}. "
                                "Ensure T025 has completed successfully.")
    
    residuals_df = pd.read_parquet(residuals_path)
    
    # Ensure required columns exist in residuals
    required_cols = ['sample_id', 'error_ml_dft']
    for col in required_cols:
        if col not in residuals_df.columns:
            raise ValueError(f"Missing required column '{col}' in residuals file.")
    
    logger.info(f"Loading graphs metadata from {graphs_path}")
    if not graphs_path.exists():
        logger.warning(f"Graphs file not found at {graphs_path}. Proceeding with residuals only.")
        graphs_df = None
    else:
        graphs_df = pd.read_parquet(graphs_path)
    
    final_df = residuals_df.copy()
    
    if graphs_df is not None and 'sample_id' in graphs_df.columns:
        # Merge to get ligand_class, metal_center, etc. if they are in graphs but not residuals
        # We only keep columns from graphs that are not already in residuals to avoid conflicts
        cols_to_add = [c for c in graphs_df.columns if c not in final_df.columns and c != 'sample_id']
        if cols_to_add:
            logger.info(f"Adding columns from graphs: {cols_to_add}")
            final_df = final_df.merge(graphs_df[['sample_id'] + cols_to_add], on='sample_id', how='left')
    
    # Calculate predicted barrier height
    # We need the DFT barrier height. It might be in residuals (if T025 output it) or graphs.
    dft_barrier_col = None
    for candidate in ['dft_barrier', 'energy_dft', 'barrier_height']:
        if candidate in final_df.columns:
            dft_barrier_col = candidate
            break
    
    if dft_barrier_col is None:
        # If not found, we cannot calculate the absolute prediction, only the error.
        # However, the task asks for "final predictions". 
        # We will assume 'error_ml_dft' is ML - DFT, so ML = DFT + error.
        # If DFT is missing, we might just output the error or raise an error.
        # Given T025 output 'residuals.parquet', let's check if we can derive DFT from context.
        # If strictly missing, we will log a warning and set predicted to NaN or just the error.
        # But typically, residuals files include the ground truth.
        # Let's assume 'dft_barrier' is the standard name if not present, we check 'barrier_height'.
        # If still missing, we cannot compute 'predicted_barrier'.
        logger.warning("DFT barrier height column not found in residuals or graphs. "
                       "Cannot compute absolute predicted barrier. Setting to NaN.")
        final_df['predicted_barrier'] = float('nan')
    else:
        final_df['predicted_barrier'] = final_df[dft_barrier_col] + final_df['error_ml_dft']
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Writing final predictions to {output_path}")
    final_df.to_parquet(output_path, index=False)
    
    logger.info(f"Successfully generated {output_path} with {len(final_df)} rows.")

def run_aggregation(residuals_path: Optional[Path] = None, graphs_path: Optional[Path] = None, output_path: Optional[Path] = None) -> None:
    project_root = get_project_root()
    
    if residuals_path is None:
        residuals_path = project_root / "data" / "processed" / "residuals.parquet"
    if graphs_path is None:
        graphs_path = project_root / "data" / "processed" / "graphs.parquet"
    if output_path is None:
        output_path = project_root / "data" / "processed" / "predictions.parquet"
    
    aggregate_predictions(residuals_path, graphs_path, output_path)

def main():
    setup_logger(level=logging.INFO)
    logger = get_logger(__name__)
    logger.info("Starting final artifact generation (T027a)")
    
    try:
        run_aggregation()
        logger.info("Task T027a completed successfully.")
    except Exception as e:
        logger.error(f"Task T027a failed: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
