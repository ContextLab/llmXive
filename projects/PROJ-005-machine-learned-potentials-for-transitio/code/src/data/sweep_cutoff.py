def analyze_cutoff(df: pd.DataFrame, cutoff: float) -> Dict[str, Any]:
    """
    Analyzes a specific cutoff value on the loaded graphs.
    
    Args:
        df: DataFrame containing processed graphs.
        cutoff: Cutoff distance in Angstroms.
        
    Returns:
        Dictionary containing analysis metrics for this cutoff.
    """
    logger.info(f"Analyzing cutoff: {cutoff} Angstroms")
    
    total_edges = 0
    total_nodes = 0
    coordination_numbers = []
    density_values = []
    feature_stability_scores = [] # Placeholder for a stability metric if needed
    
    # We need to reconstruct the graph structure for each sample to count edges
    # The DataFrame likely has a column 'adjacency_matrix' or 'edges' or similar.
    # Based on T016, we expect 'atomic_numbers' and 'coordinates'.
    
    # If the data is stored as a list of graphs in a single row, we need to explode.
    # Assuming standard format: each row is one reaction/graph.
    
    # Check if 'coordinates' column exists and is a list of lists
    if 'coordinates' not in df.columns or 'atomic_numbers' not in df.columns:
        raise ValueError("DataFrame must contain 'coordinates' and 'atomic_numbers' columns.")

    for idx, row in df.iterrows():
        coords = row['coordinates']
        atoms = row['atomic_numbers']
        
        if not coords or not atoms:
            continue
            
        coords_np = np.array(coords)
        atoms_np = np.array(atoms)
        
        num_nodes = len(atoms_np)
        total_nodes += num_nodes
        
        # Calculate distances
        # coords_np shape: (N, 3)
        diff = coords_np[:, np.newaxis, :] - coords_np[np.newaxis, :, :]
        dist_matrix = np.sqrt(np.sum(diff**2, axis=2))
        
        # Build adjacency based on cutoff (excluding self-loops)
        mask = (dist_matrix > 0) & (dist_matrix <= cutoff)
        num_edges = np.sum(mask) // 2  # Undirected graph
        
        total_edges += num_edges
        
        # Calculate density: 2 * E / (N * (N-1))
        if num_nodes > 1:
            density = (2 * num_edges) / (num_nodes * (num_nodes - 1))
        else:
            density = 0.0
        density_values.append(density)
        
        # Coordination numbers (degree)
        degrees = np.sum(mask, axis=1)
        coordination_numbers.extend(degrees.tolist())
        
        # Feature stability: Check if any node has coordination > 6 (outlier flag logic from T018 context)
        # Or simply measure variance in coordination distribution
        if len(degrees) > 0:
            feature_stability_scores.append(np.var(degrees))

    avg_density = np.mean(density_values) if density_values else 0.0
    avg_coord = np.mean(coordination_numbers) if coordination_numbers else 0.0
    std_coord = np.std(coordination_numbers) if coordination_numbers else 0.0
    avg_feature_stability = np.mean(feature_stability_scores) if feature_stability_scores else 0.0
    
    # Count outliers (coordination > 6)
    outlier_count = sum(1 for c in coordination_numbers if c > 6)
    
    return {
        "cutoff": cutoff,
        "total_nodes": total_nodes,
        "total_edges": total_edges,
        "avg_density": float(avg_density),
        "avg_coordination_number": float(avg_coord),
        "std_coordination_number": float(std_coord),
        "outlier_count": outlier_count,
        "avg_feature_stability_variance": float(avg_feature_stability),
        "num_graphs_analyzed": len(df)
    }

def run_sensitivity_analysis(df: pd.DataFrame, cutoffs: Optional[List[float]] = None) -> List[Dict[str, Any]]:
    """
    Runs the sensitivity analysis across specified cutoff values.
    
    Args:
        df: DataFrame with processed graphs.
        cutoffs: List of cutoff values to test. Defaults to CUTOFF_VALUES.
        
    Returns:
        List of dictionaries, one per cutoff value, containing analysis results.
    """
    if cutoffs is None:
        cutoffs = CUTOFF_VALUES
        
    results = []
    total = len(cutoffs)
    
    for i, cutoff in enumerate(cutoffs):
        log_progress(i, total, f"Analyzing cutoff {cutoff}A")
        result = analyze_cutoff(df, cutoff)
        results.append(result)
        logger.info(f"Completed cutoff {cutoff}A: Density={result['avg_density']:.4f}, AvgCoord={result['avg_coordination_number']:.2f}")
        
    return results

def save_results(results: List[Dict[str, Any]], output_path: Optional[Path] = None) -> Path:
    """
    Saves the sensitivity analysis results to a JSON file.
    
    Args:
        results: List of result dictionaries.
        output_path: Path to save the JSON file. Defaults to data/results/cutoff_sensitivity.json.
        
    Returns:
        Path to the saved file.
    """
    project_root = get_project_root()
    if output_path is None:
        output_path = project_root / "data" / "results" / "cutoff_sensitivity.json"
        
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Saving results to {output_path}")
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
        
    return output_path

def main():
    """Main entry point for the sensitivity analysis."""
    logger.info("Starting T017: Cutoff Sensitivity Analysis")
    
    try:
        # 1. Load data
        df = load_processed_graphs()
        
        # 2. Run analysis
        results = run_sensitivity_analysis(df)
        
        # 3. Save results
        output_file = save_results(results)
        
        logger.info(f"T017 Completed. Results saved to {output_file}")
        log_metric("t017_status", "completed")
        
    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        log_metric("t017_status", "failed", reason="Missing input data")
        raise
    except Exception as e:
        logger.error(f"Error during analysis: {e}")
        log_metric("t017_status", "failed", reason=str(e))
        raise

if __name__ == "__main__":
    main()
