def load_processed_graphs() -> pd.DataFrame:
    """
    Loads the processed graphs from the parquet file generated by T016.
    
    Returns:
        pd.DataFrame: DataFrame containing graph data with atomic features and coordinates.
        
    Raises:
        FileNotFoundError: If the processed graphs file does not exist.
    """
    project_root = get_project_root()
    graphs_path = project_root / "data" / "processed" / "graphs.parquet"
    
    if not graphs_path.exists():
        raise FileNotFoundError(
            f"Processed graphs file not found at {graphs_path}. "
            "Please run T016 (graph_construction.py) first to generate this file."
        )
    
    logger.info(f"Loading processed graphs from {graphs_path}")
    df = pd.read_parquet(graphs_path)
    logger.info(f"Loaded {len(df)} graphs")
    return df

