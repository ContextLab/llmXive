def load_processed_graphs_intermediate() -> pd.DataFrame:
    """
    Load the intermediate processed geometries from T015.
    Expects 'code/data/processed/intermediate_geometries.parquet' or similar.
    Since T015/T016/T016b/T016c were marked as completed but rejected for missing artifacts,
    we must ensure this loader points to the correct source file generated by ingestion.
    Based on T015, the raw data is fetched. T016 filters it.
    We assume the filtered data is stored as 'code/data/processed/filtered_geometries.parquet'.
    """
    project_root = get_project_root()
    # Attempt to load the filtered geometries from the ingestion step
    input_path = project_root / "data" / "processed" / "filtered_geometries.parquet"
    
    if not input_path.exists():
        # Fallback to raw if intermediate doesn't exist, but log a warning
        raw_path = project_root / "data" / "raw" / "qm9_ts_filtered.parquet"
        if raw_path.exists():
            logger.warning(f"Intermediate file not found, using raw: {raw_path}")
            input_path = raw_path
        else:
            raise FileNotFoundError(
                f"Could not find input geometries. Expected {input_path} or {raw_path}. "
                "Ensure T015/T016 ingestion steps have successfully written data."
            )
    
    logger.info(f"Loading geometries from {input_path}")
    df = pd.read_parquet(input_path)
    return df

def parse_atomic_features(df: pd.DataFrame) -> Tuple[np.ndarray, np.ndarray]:
    """
    Extract atomic numbers and coordinates from the dataframe.
    Expects columns: 'atomic_numbers' (list of ints) and 'coordinates' (list of lists or array).
    """
    atomic_numbers = []
    coordinates = []
    
    for _, row in df.iterrows():
        # Handle potential variations in storage format
        if isinstance(row['atomic_numbers'], list):
            atomic_numbers.append(np.array(row['atomic_numbers']))
        else:
            atomic_numbers.append(np.array(row['atomic_numbers']))
        
        if isinstance(row['coordinates'], list):
            coordinates.append(np.array(row['coordinates']))
        else:
            coordinates.append(np.array(row['coordinates']))
            
    return atomic_numbers, coordinates

def calculate_distance_matrix(coords: np.ndarray) -> np.ndarray:
    """
    Calculate the pairwise Euclidean distance matrix for a set of coordinates.
    coords: (N, 3) array
    Returns: (N, N) distance matrix
    """
    # Use broadcasting for efficient distance calculation
    diff = coords[:, np.newaxis, :] - coords[np.newaxis, :, :]
    dists = np.sqrt(np.sum(diff ** 2, axis=-1))
    return dists

def build_adjacency_matrix(distances: np.ndarray, cutoff: float) -> np.ndarray:
    """
    Build an adjacency matrix based on a distance cutoff.
    Returns a binary adjacency matrix (1 if connected, 0 otherwise).
    """
    adj = (distances <= cutoff).astype(int)
    # Remove self-loops
    np.fill_diagonal(adj, 0)
    return adj

def calculate_coordination_number(adj: np.ndarray) -> List[int]:
    """
    Calculate the coordination number (degree) for each node.
    """
    return np.sum(adj, axis=1).tolist()

def extract_edge_attributes(distances: np.ndarray, adj: np.ndarray) -> List[Dict[str, Any]]:
    """
    Extract edge attributes (distance) for connected nodes.
    """
    edges = []
    N = adj.shape[0]
    for i in range(N):
        for j in range(i + 1, N):
            if adj[i, j] == 1:
                edges.append({
                    'source': i,
                    'target': j,
                    'distance': float(distances[i, j])
                })
    return edges

def calculate_graph_metrics(adj: np.ndarray, distances: np.ndarray) -> Dict[str, float]:
    """
    Calculate key graph metrics:
    - avg_degree: Average number of connections per node
    - edge_count: Total number of edges
    - density: Ratio of existing edges to possible edges
    """
    N = adj.shape[0]
    degree = np.sum(adj, axis=1)
    avg_degree = float(np.mean(degree))
    edge_count = int(np.sum(adj) / 2) # Undirected graph
    max_edges = N * (N - 1) / 2
    density = float(edge_count / max_edges) if max_edges > 0 else 0.0
    
    return {
        'avg_degree': avg_degree,
        'edge_count': edge_count,
        'density': density
    }

def analyze_cutoff(df: pd.DataFrame, cutoff: float) -> Dict[str, Any]:
    """
    Analyze a specific cutoff value on the dataset.
    """
    atomic_numbers_list, coords_list = parse_atomic_features(df)
    metrics_list = []
    
    total_atoms = 0
    total_edges = 0
    total_nodes = 0
    
    for i, coords in enumerate(coords_list):
        if coords.size == 0:
            continue
        
        dists = calculate_distance_matrix(coords)
        adj = build_adjacency_matrix(dists, cutoff)
        
        graph_metrics = calculate_graph_metrics(adj, dists)
        metrics_list.append(graph_metrics)
        
        total_atoms += coords.shape[0]
        total_edges += graph_metrics['edge_count']
        total_nodes += 1

    if not metrics_list:
        return {
            'cutoff': cutoff,
            'samples_processed': 0,
            'avg_degree': 0.0,
            'total_edge_count': 0,
            'avg_density': 0.0
        }

    # Aggregate metrics across the dataset
    avg_degrees = [m['avg_degree'] for m in metrics_list]
    densities = [m['density'] for m in metrics_list]
    
    result = {
        'cutoff': cutoff,
        'samples_processed': len(metrics_list),
        'avg_degree': float(np.mean(avg_degrees)),
        'total_edge_count': total_edges,
        'avg_density': float(np.mean(densities))
    }
    
    logger.info(f"Cutoff {cutoff}A: Processed {result['samples_processed']} samples, "
                f"Avg Degree: {result['avg_degree']:.2f}, Avg Density: {result['avg_density']:.4f}")
    return result

def run_sensitivity_analysis(df: pd.DataFrame, cutoffs: List[float] = [3.0, 3.5, 4.0]) -> List[Dict[str, Any]]:
    """
    Run the sensitivity analysis sweep over specified cutoff values.
    """
    results = []
    for cutoff in cutoffs:
        logger.info(f"Analyzing cutoff: {cutoff} Angstroms")
        metric = analyze_cutoff(df, cutoff)
        results.append(metric)
    return results

def save_results(results: List[Dict[str, Any]], output_path: Path):
    """
    Save the sensitivity analysis results to a JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    logger.info(f"Results saved to {output_path}")

