def test_dataset_schema_validates_jsonl(temp_jsonl_file):
    """
    Contract test: Verify that a valid JSONL file generated by the pipeline
    conforms to dataset.schema.yaml.
    """
    schema = load_schema()
    
    with open(temp_jsonl_file, 'r', encoding='utf-8') as f:
        lines = f.readlines()
    
    assert len(lines) > 0, "JSONL file is empty"
    
    for line_num, line in enumerate(lines, 1):
        try:
            record = json.loads(line.strip())
        except json.JSONDecodeError as e:
            raise AssertionError(f"Line {line_num} is not valid JSON: {e}")
        
        try:
            validate_record_against_schema(record, schema)
        except AssertionError as e:
            raise AssertionError(f"Record on line {line_num} failed schema validation: {e}")

def test_invalid_record_fails_validation(invalid_jsonl_file):
    """
    Ensure that a JSONL file with missing required fields fails validation.
    """
    schema = load_schema()
    
    with open(invalid_jsonl_file, 'r', encoding='utf-8') as f:
        line = f.readline()
    
    record = json.loads(line)
    
    with pytest.raises(AssertionError) as exc_info:
        validate_record_against_schema(record, schema)
    
    assert "Missing required field" in str(exc_info.value)

