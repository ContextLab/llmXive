def load_schema():
    """Load the dataset schema from the YAML file."""
    if not SCHEMA_PATH.exists():
        raise FileNotFoundError(f"Schema file not found at {SCHEMA_PATH}")
    return load_schema_from_file(SCHEMA_PATH)

def validate_record_against_schema(record, schema):
    """
    Validate a single JSONL record against the schema.
    Returns True if valid, raises AssertionError otherwise.
    """
    # Basic type checks based on schema definition
    if not isinstance(record, dict):
        raise AssertionError("Record must be a dictionary")

    required_fields = schema.get("required", [])
    for field in required_fields:
        if field not in record:
            raise AssertionError(f"Missing required field: {field}")

    # Type validation for 'id'
    if not isinstance(record.get("id"), str):
        raise AssertionError("Field 'id' must be a string")

    # Type validation for 'steps' (array of objects)
    steps = record.get("steps")
    if not isinstance(steps, list):
        raise AssertionError("Field 'steps' must be a list")
    for step in steps:
        if not isinstance(step, dict):
            raise AssertionError("Each step in 'steps' must be an object")
        step_required = schema["properties"]["steps"]["items"].get("required", [])
        for req in step_required:
            if req not in step:
                raise AssertionError(f"Step missing required field: {req}")

    # Type validation for 'dependency_graph' (object)
    graph = record.get("dependency_graph")
    if not isinstance(graph, dict):
        raise AssertionError("Field 'dependency_graph' must be an object")

    # Type validation for 'pseudo_code', 'original_question', 'original_answer' (strings)
    for field in ["pseudo_code", "original_question", "original_answer"]:
        if not isinstance(record.get(field), str):
            raise AssertionError(f"Field '{field}' must be a string")

    return True

