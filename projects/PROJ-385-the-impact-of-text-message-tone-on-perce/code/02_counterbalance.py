"""
Counterbalancing script for the "Impact of Text Message Tone" study.

This script reads the generated stimuli, creates a set of participants,
and produces a counterbalanced trial list where each participant sees each
stimulus in both relationship contexts: "friend" and "acquaintance".

The output is written to ``data/processed/counterbalanced_trials.csv``.
"""
import csv
import logging
import os
import random
from datetime import datetime
from pathlib import Path
from typing import List, Dict

from config import (
    get_raw_data_dir,
    get_processed_data_dir,
    get_project_root,
)
from logging_config import setup_logging, get_logger

# ----------------------------------------------------------------------
# Configuration
# ----------------------------------------------------------------------
NUM_PARTICIPANTS = 30  # default number of participants; can be overridden via env var
PARTICIPANT_ID_PREFIX = "P"

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------


def load_stimuli() -> List[Dict[str, str]]:
    """
    Load the stimulus CSV generated by ``code/01_generate_stimuli.py``.

    Returns
    -------
    List[Dict[str, str]]
        List of stimulus rows as dictionaries. Expected at least the column
        ``id`` (stimulus identifier).
    """
    stimuli_path = get_raw_data_dir() / "stimuli.csv"
    if not stimuli_path.is_file():
        raise FileNotFoundError(
            f"Stimuli file not found at {stimuli_path}. "
            "Run `code/01_generate_stimuli.py` first."
        )
    with stimuli_path.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        stimuli = [row for row in reader]
    if not stimuli:
        raise ValueError(f"No stimuli found in {stimuli_path}")
    return stimuli


def generate_participant_ids(num: int = NUM_PARTICIPANTS) -> List[str]:
    """
    Generate deterministic participant IDs.

    Parameters
    ----------
    num : int
        Number of participants to generate.

    Returns
    -------
    List[str]
        List like ["P001", "P002", ...].
    """
    random.seed(42)  # deterministic for reproducibility
    return [
        f"{PARTICIPANT_ID_PREFIX}{i:03d}"
        for i in range(1, num + 1)
    ]


def create_counterbalanced_trials(
    stimuli: List[Dict[str, str]],
    participant_ids: List[str],
) -> List[Dict[str, str]]:
    """
    For each participant, create two rows per stimulus: one for each
    relationship context.

    Parameters
    ----------
    stimuli : List[Dict[str, str]]
        Stimulus definitions.
    participant_ids : List[str]
        Participant identifiers.

    Returns
    -------
    List[Dict[str, str]]
        Trial rows ready to be written to CSV.
    """
    trials = []
    contexts = ["friend", "acquaintance"]
    for pid in participant_ids:
        for stim in stimuli:
            for ctx in contexts:
                trial = {
                    "participant_id": pid,
                    "stimulus_id": stim["id"],
                    "context": ctx,
                    # Preserve original stimulus columns for downstream convenience
                    **stim,
                }
                trials.append(trial)
    return trials


def save_counterbalanced_trials(trials: List[Dict[str, str]]) -> Path:
    """
    Write the counterbalanced trial list to ``data/processed/counterbalanced_trials.csv``.

    Parameters
    ----------
    trials : List[Dict[str, str]]
        The rows to write.

    Returns
    -------
    pathlib.Path
        Path to the written CSV file.
    """
    output_dir = get_processed_data_dir()
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "counterbalanced_trials.csv"

    # Determine fieldnames – ensure a stable column order
    if not trials:
        raise ValueError("No trials to save.")
    fieldnames = list(trials[0].keys())

    with output_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(trials)

    get_logger().info(f"Counterbalanced trials saved to {output_path}")
    return output_path


def verify_counterbalancing(
    trials_path: Path,
    stimuli: List[Dict[str, str]],
    participant_ids: List[str],
) -> None:
    """
    Verify that each participant appears with each stimulus exactly twice
    (once per context).

    Raises
    ------
    AssertionError
        If any verification rule fails.
    """
    with trials_path.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    # Build lookup: (participant_id, stimulus_id) -> set(contexts)
    lookup: Dict[tuple, set] = {}
    for row in rows:
        key = (row["participant_id"], row["stimulus_id"])
        lookup.setdefault(key, set()).add(row["context"])

    # Verify each participant‑stimulus pair has exactly the two contexts
    expected_contexts = {"friend", "acquaintance"}
    for pid in participant_ids:
        for stim in stimuli:
            key = (pid, stim["id"])
            contexts = lookup.get(key)
            assert (
                contexts == expected_contexts
            ), f"Participant {pid} / stimulus {stim['id']} missing contexts: {contexts}"

    get_logger().info("Counterbalancing verification passed.")


def main() -> None:
    """
    Entry point for the counterbalancing step.
    """
    # Setup logging (writes to data/pipeline.log via logging_config)
    setup_logging()
    logger = get_logger()
    logger.info("Starting counterbalancing step...")

    # Load stimuli
    stimuli = load_stimuli()
    logger.debug(f"Loaded {len(stimuli)} stimuli.")

    # Generate participants
    participant_ids = generate_participant_ids()
    logger.debug(f"Generated {len(participant_ids)} participant IDs.")

    # Create trials
    trials = create_counterbalanced_trials(stimuli, participant_ids)
    logger.debug(f"Created {len(trials)} counterbalanced trial rows.")

    # Save to CSV
    output_path = save_counterbalanced_trials(trials)

    # Verify
    verify_counterbalancing(output_path, stimuli, participant_ids)

    logger.info("Counterbalancing step completed successfully.")


if __name__ == "__main__":
    main()