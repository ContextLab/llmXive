"""
Counterbalancing module for the Text Message Tone study.

This module assigns every stimulus to both relationship contexts (friend & acquaintance)
for a defined set of participants, ensuring a balanced experimental design.
"""
import csv
import logging
import os
import random
from datetime import datetime
from pathlib import Path
from typing import List, Dict, Any, Tuple

from config import get_processed_data_dir, get_raw_data_dir
from logging_config import setup_logging, get_logger

# Initialize logger
logger = get_logger(__name__)

def load_stimuli(stimuli_path: Path) -> List[Dict[str, Any]]:
    """
    Load stimuli from the CSV file generated by T013.
    
    Args:
        stimuli_path: Path to data/raw/stimuli.csv
        
    Returns:
        List of dictionaries containing stimulus data.
    """
    if not stimuli_path.exists():
        raise FileNotFoundError(f"Stimuli file not found: {stimuli_path}")
    
    stimuli = []
    with open(stimuli_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            stimuli.append(row)
    
    if not stimuli:
        raise ValueError("Stimuli file is empty or has no valid rows.")
    
    logger.info(f"Loaded {len(stimuli)} stimuli from {stimuli_path}")
    return stimuli

def generate_participant_ids(num_participants: int, seed: int) -> List[str]:
    """
    Generate a list of unique participant IDs based on a seed.
    
    Args:
        num_participants: Number of participants to generate IDs for.
        seed: Random seed for reproducibility.
        
    Returns:
        List of participant ID strings.
    """
    random.seed(seed)
    # Generate IDs in format: P0001, P0002, etc.
    ids = [f"P{i:04d}" for i in range(1, num_participants + 1)]
    # Shuffle to simulate random assignment if needed, though IDs remain unique
    random.shuffle(ids)
    return ids

def create_counterbalanced_trials(
    stimuli: List[Dict[str, Any]], 
    participant_ids: List[str],
    relationship_contexts: List[str] = None
) -> List[Dict[str, Any]]:
    """
    Create a counterbalanced trial list where every stimulus is assigned 
    to every relationship context for every participant.
    
    Args:
        stimuli: List of stimulus dictionaries.
        participant_ids: List of participant ID strings.
        relationship_contexts: List of relationship context strings (default: ['friend', 'acquaintance']).
        
    Returns:
        List of dictionaries representing counterbalanced trials.
    """
    if relationship_contexts is None:
        relationship_contexts = ['friend', 'acquaintance']
    
    trials = []
    
    for participant_id in participant_ids:
        for stimulus in stimuli:
            for context in relationship_contexts:
                trial = {
                    'participant_id': participant_id,
                    'stimulus_id': stimulus.get('id'),
                    'relationship_type': context,
                    'text': stimulus.get('text'),
                    'emoji_count': stimulus.get('emoji_count'),
                    'punctuation_type': stimulus.get('punctuation_type'),
                    'length_category': stimulus.get('length_category'),
                    'scenario_id': stimulus.get('scenario_id'),
                    'cue_intensity': stimulus.get('cue_intensity'),
                    'created_at': datetime.now().isoformat()
                }
                trials.append(trial)
    
    logger.info(f"Created {len(trials)} counterbalanced trials for {len(participant_ids)} participants "
                f"and {len(stimuli)} stimuli across {len(relationship_contexts)} contexts.")
    return trials

def save_counterbalanced_trials(trials: List[Dict[str, Any]], output_path: Path) -> None:
    """
    Save the counterbalanced trials to a CSV file.
    
    Args:
        trials: List of trial dictionaries.
        output_path: Path to the output CSV file.
    """
    if not trials:
        raise ValueError("No trials to save.")
    
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    fieldnames = [
        'participant_id', 'stimulus_id', 'relationship_type', 
        'text', 'emoji_count', 'punctuation_type', 'length_category', 
        'scenario_id', 'cue_intensity', 'created_at'
    ]
    
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(trials)
    
    logger.info(f"Saved {len(trials)} trials to {output_path}")

def verify_counterbalancing(trials: List[Dict[str, Any]], expected_participants: int, expected_stimuli: int, expected_contexts: int) -> bool:
    """
    Verify that the counterbalancing is correct.
    
    Args:
        trials: List of trial dictionaries.
        expected_participants: Expected number of unique participants.
        expected_stimuli: Expected number of unique stimuli.
        expected_contexts: Expected number of relationship contexts.
        
    Returns:
        True if verification passes, False otherwise.
    """
    participants = set(t['participant_id'] for t in trials)
    stimuli = set(t['stimulus_id'] for t in trials)
    contexts = set(t['relationship_type'] for t in trials)
    
    if len(participants) != expected_participants:
        logger.error(f"Participant count mismatch: expected {expected_participants}, got {len(participants)}")
        return False
        
    if len(stimuli) != expected_stimuli:
        logger.error(f"Stimuli count mismatch: expected {expected_stimuli}, got {len(stimuli)}")
        return False
        
    if len(contexts) != expected_contexts:
        logger.error(f"Context count mismatch: expected {expected_contexts}, got {len(contexts)}")
        return False
    
    # Check that every participant has every stimulus in every context
    expected_total = expected_participants * expected_stimuli * expected_contexts
    if len(trials) != expected_total:
        logger.error(f"Total trial count mismatch: expected {expected_total}, got {len(trials)}")
        return False
    
    logger.info("Counterbalancing verification passed.")
    return True

def main():
    """
    Main entry point for the counterbalancing script.
    """
    setup_logging()
    
    # Configuration
    # We assume a fixed number of participants for the study design, e.g., 60
    # In a real scenario, this might be read from a config or power analysis result
    NUM_PARTICIPANTS = 60
    RANDOM_SEED = 42  # Should ideally come from config.py
    
    # Paths
    raw_data_dir = get_raw_data_dir()
    processed_data_dir = get_processed_data_dir()
    
    stimuli_path = raw_data_dir / "stimuli.csv"
    output_path = processed_data_dir / "counterbalanced_trials.csv"
    
    try:
        # 1. Load Stimuli
        logger.info("Starting counterbalancing process...")
        stimuli = load_stimuli(stimuli_path)
        
        # 2. Generate Participant IDs
        participant_ids = generate_participant_ids(NUM_PARTICIPANTS, RANDOM_SEED)
        
        # 3. Create Counterbalanced Trials
        trials = create_counterbalanced_trials(stimuli, participant_ids)
        
        # 4. Verify
        contexts = ['friend', 'acquaintance']
        if not verify_counterbalancing(trials, NUM_PARTICIPANTS, len(stimuli), len(contexts)):
            logger.error("Counterbalancing verification failed. Exiting.")
            return 1
        
        # 5. Save
        save_counterbalanced_trials(trials, output_path)
        
        logger.info("Counterbalancing completed successfully.")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        return 1
    except ValueError as e:
        logger.error(f"Value error: {e}")
        return 1
    except Exception as e:
        logger.exception(f"Unexpected error during counterbalancing: {e}")
        return 1

if __name__ == "__main__":
    exit(main())
