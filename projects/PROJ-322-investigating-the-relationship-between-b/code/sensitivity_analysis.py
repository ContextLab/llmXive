def load_data_for_sensitivity() -> pd.DataFrame:
    """
    Loads preprocessed data (connectivity metrics and cognitive scores) required for sensitivity analysis.
    In Methodology Validation Mode, it falls back to the synthetic generator if real data is unavailable,
    but strictly raises an error if real data is required and missing (per constraints).
    """
    config = get_config()
    data_path = Path(config.get('data_paths', {}).get('processed', 'data/processed'))
    results_path = Path(config.get('data_paths', {}).get('results', 'data/results'))
    
    # Try to load the manifest or preprocessed data generated by previous steps
    # We expect a file like 'data/processed/merged_metrics.csv' or similar from T019/T021
    potential_files = [
        data_path / "merged_metrics.csv",
        data_path / "graph_metrics.csv",
        results_path / "model_results.json" # Fallback if we need to reconstruct
    ]
    
    df = None
    for p in potential_files:
        if p.exists():
            try:
                df = pd.read_csv(p)
                logger.info(f"Loaded sensitivity data from {p}")
                break
            except Exception as e:
                logger.warning(f"Failed to load {p}: {e}")
    
    if df is None:
        # Check if we are in synthetic mode to generate data for validation
        if is_methodology_validation_mode():
            logger.info("Real data not found. In Methodology Validation Mode, generating synthetic data for sensitivity analysis.")
            from synthetic_data import generate_dataset
            # Generate a consistent synthetic dataset
            synthetic_data = generate_dataset(n_subjects=50, seed=42)
            df = synthetic_data
            # Save for consistency if needed
            data_path.mkdir(parents=True, exist_ok=True)
            synthetic_path = data_path / "merged_metrics.csv"
            df.to_csv(synthetic_path, index=False)
            logger.info(f"Generated synthetic sensitivity data at {synthetic_path}")
        else:
            raise FileNotFoundError(
                "Real preprocessed data not found and not in Methodology Validation Mode. "
                "Cannot perform sensitivity analysis without data. "
                "Please ensure T011 and T019 have completed successfully."
            )
    
    # Ensure necessary columns exist
    required_cols = ['efficiency', 'modularity', 'cognitive_score']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        # Attempt to map from standard entity names if possible
        # Assuming T019/T021 produced 'global_efficiency' or similar
        if 'global_efficiency' in df.columns:
            df['efficiency'] = df['global_efficiency']
            missing.remove('efficiency')
        if 'modularity' not in df.columns and 'Q' in df.columns:
            df['modularity'] = df['Q']
            if 'modularity' in missing: missing.remove('modularity')
        
        if missing:
            raise ValueError(f"Missing required columns for sensitivity analysis: {missing}")

    return df

def generate_synthetic_sensitivity_data(n_samples: int = 100, seed: int = 42) -> pd.DataFrame:
    """
    Generates synthetic data specifically for testing sensitivity analysis logic.
    Used only when real data is unavailable and in validation mode.
    """
    np.random.seed(seed)
    # Create a dataset with known correlation structure
    efficiency = np.random.normal(0.4, 0.1, n_samples)
    modularity = np.random.normal(0.3, 0.1, n_samples)
    # Cognitive score correlated with efficiency
    cognitive_score = 50 + 30 * efficiency + np.random.normal(0, 5, n_samples)
    
    return pd.DataFrame({
        'efficiency': efficiency,
        'modularity': modularity,
        'cognitive_score': cognitive_score
    })

