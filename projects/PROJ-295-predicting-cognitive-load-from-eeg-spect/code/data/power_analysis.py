"""
Power Analysis for EEG Cognitive Load Prediction Study.

This module calculates the minimum sample size (N) required to detect
a specific effect size (R² = 0.2) given the number of predictors derived
from the EEG channel count. It enforces a strict halt if the actual
dataset size is insufficient.

Dependencies:
    - code/data/verify_dataset.py (for loading verification report)
    - code/data/manifest.py (for state updates)
"""

import os
import sys
import json
import math
import hashlib
import datetime
import yaml
from typing import Dict, Any, Optional

# Add project root to path for imports if running as script
PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from data.manifest import update_state

# Constants
TARGET_R2 = 0.2
ALPHA = 0.05
POWER = 0.80
EPSILON = 1e-9

# Approximate F-test power calculation constants
# Using the rule of thumb for multiple regression:
# N >= (L * (1 - R2) / R2) + k + 1
# Where L is the non-centrality parameter derived from alpha and power.
# For alpha=0.05, power=0.80, L is approximately 7.85 for large df.
# A more robust approximation often used is:
# N = ( (Z_alpha + Z_beta)^2 * (1 - R2) ) / R2 + k
# But for F-test specifically, we use the approximation:
# N >= k + ( (L / R2) * (1 - R2) )
# Where L ~ 7.85 for standard alpha/power.
NON_CENTRAL_PARAM = 7.85


def calculate_file_checksum(filepath: str) -> str:
    """Calculate SHA-256 checksum of a file."""
    sha256_hash = hashlib.sha256()
    try:
        with open(filepath, "rb") as f:
            for byte_block in iter(lambda: f.read(4096), b""):
                sha256_hash.update(byte_block)
        return sha256_hash.hexdigest()
    except FileNotFoundError:
        return "MISSING"


def calculate_minimum_n(n_predictors: int, r2_target: float = TARGET_R2) -> int:
    """
    Calculate the minimum sample size (N) required for a multiple regression
    to achieve the target R² with the given number of predictors.

    Formula approximation for F-test power (alpha=0.05, power=0.80):
    N >= k + (L * (1 - R²)) / R²
    Where L is the non-centrality parameter (~7.85 for standard settings).

    Args:
        n_predictors (int): Number of independent variables (k).
        r2_target (float): Target R-squared value.

    Returns:
        int: Minimum required sample size N.
    """
    if r2_target <= 0 or r2_target >= 1:
        raise ValueError("R² target must be between 0 and 1.")

    # Calculate required N
    # N = k + (L * (1 - R2)) / R2
    term = (NON_CENTRAL_PARAM * (1 - r2_target)) / r2_target
    min_n = n_predictors + term

    return math.ceil(min_n)


def load_verification_report(report_path: str) -> Dict[str, Any]:
    """
    Load the verification report generated by T000.

    Args:
        report_path (str): Path to results/verification_report.json.

    Returns:
        dict: Parsed JSON content.

    Raises:
        FileNotFoundError: If the report does not exist.
        ValueError: If the report is missing required fields.
    """
    if not os.path.exists(report_path):
        raise FileNotFoundError(
            f"Verification report not found at {report_path}. "
            "Run T000 (verify_dataset.py) first."
        )

    with open(report_path, 'r') as f:
        data = json.load(f)

    required_fields = ['status', 'n_channels']
    for field in required_fields:
        if field not in data:
            raise ValueError(f"Verification report missing required field: {field}")

    if data['status'] != 'success':
        raise ValueError(
            f"Verification report status is '{data['status']}'. "
            "Cannot proceed with power analysis if dataset verification failed."
        )

    return data


def update_state_checksums(report_data: Dict[str, Any], output_path: str) -> None:
    """
    Update the state YAML file with the checksum of the new report and timestamp.
    """
    checksum = calculate_file_checksum(output_path)
    state_update = {
        'power_analysis': {
            'checksum': checksum,
            'updated_at': datetime.datetime.now(datetime.timezone.utc).isoformat(),
            'min_n_required': report_data.get('calculated_min_n'),
            'actual_n': report_data.get('actual_n'),
            'is_powered': report_data.get('is_powered')
        }
    }
    update_state(state_update)


def main():
    """
    Main entry point for T001: Power Analysis.

    1. Loads verification report from T000.
    2. Calculates predictors: n_channels * 2.
    3. Calculates minimum N for R²=0.2.
    4. Compares with actual N (if available, or defaults to a safe upper bound check).
    5. HALTS if underpowered.
    6. Writes results to results/power_analysis_report.json.
    7. Updates state.yaml.
    """
    # Paths
    verification_report_path = os.path.join(PROJECT_ROOT, 'results', 'verification_report.json')
    output_report_path = os.path.join(PROJECT_ROOT, 'results', 'power_analysis_report.json')

    print(f"[T001] Starting Power Analysis...")
    print(f"[T001] Loading verification report from: {verification_report_path}")

    try:
        verification_data = load_verification_report(verification_report_path)
    except (FileNotFoundError, ValueError) as e:
        print(f"[T001] CRITICAL ERROR: {e}")
        sys.exit(1)

    n_channels = verification_data['n_channels']
    n_predictors = n_channels * 2

    print(f"[T001] Detected {n_channels} channels.")
    print(f"[T001] Calculating for {n_predictors} predictors (n_channels * 2).")

    min_n = calculate_minimum_n(n_predictors, TARGET_R2)

    # Determine actual N.
    # Since T000 only verifies existence and channel count, it doesn't necessarily
    # provide the total number of subjects/epochs in the dataset.
    # However, the task requires a HALT if actual_n < calculated_min_n.
    # We will assume the dataset size is the number of subjects available.
    # If the verification report doesn't have 'n_subjects', we cannot definitively
    # halt based on actual count unless we load the dataset.
    # Given the constraints, we will check if the report has 'n_subjects'.
    # If not, we will assume a conservative estimate or halt if we can't verify.
    # To be safe and strictly follow "HALT if actual_n < calculated_min_n",
    # we need the actual count. We will attempt to infer it from the manifest
    # or assume a standard large dataset size if not present, but the strict
    # requirement implies we must know.
    # Let's check if T000 output included subject count. If not, we must
    # try to get it from the dataset structure or fail loudly if we can't verify.
    # For this implementation, we assume the verification report might have been
    # extended to include 'n_subjects' or we read it from the dataset metadata.
    # Since T000 is defined as just verifying gaze and channels, we might need
    # to count subjects here. But to keep T001 focused, we will assume the
    # verification report *should* have contained it or we derive it from the
    # raw data directory structure if possible.
    # However, the prompt says "derived from results/verification_report.json".
    # If that JSON lacks 'n_subjects', we cannot calculate actual_n.
    # We will assume for this task that the verification report *should* have
    # been updated to include 'n_subjects' or we treat the dataset as having
    # a known size from the manifest.
    # Let's check the manifest for subject count.
    manifest_path = os.path.join(PROJECT_ROOT, 'data', 'manifest.yaml')
    actual_n = None
    if os.path.exists(manifest_path):
        with open(manifest_path, 'r') as f:
            manifest = yaml.safe_load(f)
            if 'metadata' in manifest and 'n_subjects' in manifest['metadata']:
                actual_n = manifest['metadata']['n_subjects']
            elif 'subjects' in manifest:
                actual_n = len(manifest['subjects'])

    if actual_n is None:
        # Fallback: If we can't find actual N, we cannot verify power.
        # We must HALT to be safe, as we cannot prove we have enough data.
        print(f"[T001] WARNING: Could not determine actual number of subjects.")
        print(f"[T001] HALTING: Cannot verify power without actual N.")
        report = {
            'status': 'failed',
            'message': 'Unable to determine actual N from manifest or verification report.',
            'calculated_min_n': min_n,
            'actual_n': None,
            'is_powered': False,
            'timestamp': datetime.datetime.now(datetime.timezone.utc).isoformat()
        }
        with open(output_report_path, 'w') as f:
            json.dump(report, f, indent=2)
        sys.exit(1)

    is_powered = actual_n >= min_n

    report = {
        'status': 'success' if is_powered else 'underpowered',
        'message': 'Study is adequately powered.' if is_powered else f'Study is underpowered. Need {min_n} subjects, have {actual_n}.',
        'calculated_min_n': min_n,
        'actual_n': actual_n,
        'n_channels': n_channels,
        'n_predictors': n_predictors,
        'target_r2': TARGET_R2,
        'is_powered': is_powered,
        'timestamp': datetime.datetime.now(datetime.timezone.utc).isoformat()
    }

    print(f"[T001] Calculated Minimum N: {min_n}")
    print(f"[T001] Actual N: {actual_n}")
    print(f"[T001] Result: {'PASS' if is_powered else 'FAIL (Underpowered)'}")

    # Write output
    with open(output_report_path, 'w') as f:
        json.dump(report, f, indent=2)

    print(f"[T001] Report written to: {output_report_path}")

    if not is_powered:
        print(f"[T001] HALTING EXECUTION: Study is underpowered.")
        # Update state before exiting to reflect failure
        update_state_checksums(report, output_report_path)
        sys.exit(1)

    # Update state
    update_state_checksums(report, output_report_path)
    print(f"[T001] State updated successfully.")


if __name__ == '__main__':
    main()
