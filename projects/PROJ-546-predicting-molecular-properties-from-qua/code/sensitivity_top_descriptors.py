"""
Task T030: Identify top-ranked descriptors and calculate cumulative importance.

This module reads the feature importance results generated by T029 (sensitivity_analysis.py),
sorts them by descending importance, and appends a ranked table to `reports/sensitivity.csv`.
"""
import argparse
import csv
import logging
import os
import sys
from pathlib import Path
from typing import List, Dict, Any

# Import the setup_logger from the existing sensitivity_analysis module to ensure
# consistent logging configuration across the US3 pipeline.
from sensitivity_analysis import setup_logger

def load_feature_importance(csv_path: str) -> List[Dict[str, Any]]:
    """
    Load feature importance data from a CSV file.
    
    Expected columns: 'descriptor', 'importance' (or similar).
    Returns a list of dictionaries.
    """
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Feature importance file not found: {csv_path}")
    
    data = []
    with open(csv_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Handle potential key variations if the source file naming differs slightly
            descriptor = row.get('descriptor') or row.get('feature')
            importance_str = row.get('importance') or row.get('importance_score')
            
            if descriptor is not None and importance_str is not None:
                try:
                    data.append({
                        'descriptor': str(descriptor),
                        'importance': float(importance_str)
                    })
                except ValueError:
                    logging.warning(f"Skipping row with invalid importance value: {row}")
    return data

def calculate_cumulative_importance(data: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Sort data by descending importance and calculate cumulative sum.
    """
    # Sort by importance descending
    sorted_data = sorted(data, key=lambda x: x['importance'], reverse=True)
    
    cumulative_sum = 0.0
    cumulative_results = []
    
    for rank, item in enumerate(sorted_data, start=1):
        cumulative_sum += item['importance']
        cumulative_results.append({
            'rank': rank,
            'descriptor': item['descriptor'],
            'importance': item['importance'],
            'cumulative_importance': cumulative_sum
        })
    
    return cumulative_results

def append_to_sensitivity_report(results: List[Dict[str, Any]], output_path: str) -> None:
    """
    Append the ranked descriptors to the existing sensitivity.csv file.
    If the file does not exist or is empty, write the header first.
    """
    file_exists = os.path.exists(output_path)
    
    # Determine if file has content
    has_content = False
    if file_exists and os.path.getsize(output_path) > 0:
        with open(output_path, 'r', encoding='utf-8') as f:
            # Check if there's a second line (header + at least one row)
            # or if the file is just a header
            lines = f.readlines()
            if len(lines) > 1:
                has_content = True
            elif len(lines) == 1 and lines[0].strip() == '':
                has_content = False
            else:
                # Check if the single line is a header
                reader = csv.reader([lines[0]])
                header = next(reader)
                # If the file is only a header, we don't need to add header again
                # but we need to know if we are appending to a header-only file or existing data
                # For T030, we assume we are appending the top descriptors section.
                # The task says "append to reports/sensitivity.csv".
                # We will write a section header or just the data. 
                # To be safe and consistent with CSV standards, if the file exists and has headers,
                # we append rows. If it's empty, we write headers.
                if len(header) > 0 and header[0] == 'rank':
                    # File has headers, no data yet
                    has_content = False 
                else:
                    has_content = False # Empty file effectively
        
        # Re-open to check if headers exist
        with open(output_path, 'r', encoding='utf-8') as f_check:
            first_line = f_check.readline().strip()
            if first_line == 'rank,descriptor,importance':
                # Headers exist, we can append data directly
                write_header = False
            elif first_line == '':
                # Empty file
                write_header = True
            else:
                # Assume no headers or different format, write headers
                write_header = True
    else:
        write_header = True

    with open(output_path, 'a', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=['rank', 'descriptor', 'importance'])
        
        if write_header:
            writer.writeheader()
        
        for item in results:
            writer.writerow({
                'rank': item['rank'],
                'descriptor': item['descriptor'],
                'importance': item['importance']
            })

def main():
    parser = argparse.ArgumentParser(description="Identify top descriptors and calculate cumulative importance (T030).")
    parser.add_argument('--input', type=str, default='data/feature_importance_semi.csv',
                        help='Path to the feature importance CSV generated by T029.')
    parser.add_argument('--output', type=str, default='reports/sensitivity.csv',
                        help='Path to the sensitivity report CSV to append to.')
    args = parser.parse_args()

    # Setup logging
    logger = setup_logger('t030_top_descriptors', 'logs/t030_top_descriptors.log')
    logger.info("Starting T030: Top Descriptor Identification")

    try:
        # Ensure output directory exists
        output_dir = os.path.dirname(args.output)
        if output_dir:
            os.makedirs(output_dir, exist_ok=True)

        # Load data
        logger.info(f"Loading feature importance from {args.input}")
        data = load_feature_importance(args.input)
        
        if not data:
            logger.warning("No feature importance data found. Exiting.")
            sys.exit(0)

        logger.info(f"Loaded {len(data)} descriptors.")

        # Calculate cumulative importance
        results = calculate_cumulative_importance(data)
        
        # Append to report
        logger.info(f"Appending {len(results)} ranked descriptors to {args.output}")
        append_to_sensitivity_report(results, args.output)

        logger.info("T030 completed successfully.")

    except FileNotFoundError as e:
        logger.error(f"Required input file missing: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"An error occurred: {e}", exc_info=True)
        sys.exit(1)

if __name__ == '__main__':
    main()