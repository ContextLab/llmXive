"""
Generate SHA256 checksums for all raw and processed artifacts in the project.

This script implements Constitution Check #3 by computing cryptographic hashes
for all data artifacts to ensure integrity and reproducibility.

Outputs:
    data/checksums.txt: A text file containing SHA256 checksums for all artifacts.
"""
import hashlib
import os
import sys
from pathlib import Path
from typing import List, Dict, Tuple

# Define the root directory for the project
PROJECT_ROOT = Path(__file__).parent.parent
DATA_DIR = PROJECT_ROOT / "data"
REPORTS_DIR = PROJECT_ROOT / "reports"
FIGURES_DIR = PROJECT_ROOT / "figures"

# Define relative paths to scan for artifacts
# These cover raw data, processed data, and generated reports
# Note: We explicitly include the paths expected by the pipeline (T004b, T011, T013c, T020b)
ARTIFACT_PATTERNS = [
    "data/raw/*.csv",
    "data/raw/*.tar.gz",
    "data/raw/*.txt",
    "data/optimized_geometries/*.xyz",
    "data/confounds.csv",
    "data/descriptors_semi.csv",
    "data/descriptors_dft.csv",
    "data/checksums.txt", # Will be filtered out
    "reports/*.json",
    "reports/*.csv",
    "reports/*.md",
    "figures/*.png",
    "figures/*.pdf",
]

def compute_sha256(file_path: Path) -> str:
    """
    Compute the SHA256 hash of a file.
    
    Args:
        file_path: Path to the file to hash.
        
    Returns:
        Hexadecimal string of the SHA256 hash.
        
    Raises:
        FileNotFoundError: If the file does not exist.
        IOError: If the file cannot be read.
    """
    sha256_hash = hashlib.sha256()
    try:
        with open(file_path, "rb") as f:
            # Read in chunks to handle large files efficiently
            for chunk in iter(lambda: f.read(4096), b""):
                sha256_hash.update(chunk)
        return sha256_hash.hexdigest()
    except FileNotFoundError:
        raise FileNotFoundError(f"File not found: {file_path}")
    except IOError as e:
        raise IOError(f"Error reading file {file_path}: {e}")

def find_artifacts(patterns: List[str], base_dir: Path) -> List[Path]:
    """
    Find all files matching the given glob patterns relative to the base directory.
    
    Args:
        patterns: List of glob patterns (e.g., "data/raw/*.csv").
        base_dir: Base directory to start searching from.
        
    Returns:
        List of Path objects for matching files.
    """
    artifacts = []
    for pattern in patterns:
        full_pattern = base_dir / pattern
        # Handle the case where the directory might not exist yet for a specific pattern
        if not full_pattern.parent.exists():
            continue
        
        matches = list(full_pattern.parent.glob(full_pattern.name))
        artifacts.extend(matches)
    
    # Filter out the checksums file itself if it exists to avoid self-referencing
    checksums_path = base_dir / "checksums.txt"
    artifacts = [p for p in artifacts if p != checksums_path]
    
    return sorted(artifacts)

def generate_checksums(output_path: Path, artifacts: List[Path]) -> None:
    """
    Generate a checksums file for the given artifacts.
    
    Args:
        output_path: Path where the checksums file will be written.
        artifacts: List of artifact paths to include.
        
    Raises:
        RuntimeError: If no artifacts are found.
    """
    if not artifacts:
        raise RuntimeError("No artifacts found to checksum. Check the data directory.")
    
    lines = []
    lines.append(f"# SHA256 Checksums generated on {output_path.parent.name}")
    lines.append(f"# Generated by: generate_checksums.py")
    lines.append("# Format: <sha256_hash>  <relative_path>")
    lines.append("#" + "=" * 70)
    
    for artifact in artifacts:
        try:
            checksum = compute_sha256(artifact)
            # Use relative path from project root for portability
            relative_path = artifact.relative_to(PROJECT_ROOT)
            lines.append(f"{checksum}  {relative_path}")
            print(f"  Checked: {relative_path} -> {checksum[:16]}...")
        except Exception as e:
            print(f"  Warning: Could not checksum {artifact}: {e}", file=sys.stderr)
    
    # Write to file
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    
    print(f"\nChecksums written to: {output_path}")
    print(f"Total artifacts processed: {len(artifacts)}")

def main():
    """Main entry point for the checksum generation script."""
    print("Starting artifact checksum generation...")
    print(f"Project root: {PROJECT_ROOT}")
    print(f"Data directory: {DATA_DIR}")
    
    # Ensure data directory exists (it should, but safety check)
    if not DATA_DIR.exists():
        print(f"Warning: Data directory {DATA_DIR} does not exist.")
        print("Creating a minimal checksums file noting no data found.")
        DATA_DIR.mkdir(parents=True, exist_ok=True)
    
    # Find all artifacts
    artifacts = find_artifacts(ARTIFACT_PATTERNS, PROJECT_ROOT)
    
    if not artifacts:
        print("No artifacts found. Creating an empty checksums file with a note.")
        output_path = DATA_DIR / "checksums.txt"
        with open(output_path, "w", encoding="utf-8") as f:
            f.write("# No artifacts found to checksum.\n")
            f.write("# This file was generated because the data directory was empty.\n")
            f.write("# Please ensure data has been downloaded and processed before running this script again.\n")
        return
    
    # Generate checksums
    output_path = DATA_DIR / "checksums.txt"
    generate_checksums(output_path, artifacts)
    
    print("Checksum generation completed successfully.")

if __name__ == "__main__":
    main()