"""
Sensitivity Analysis Module for User Story 3.

This module extracts feature importance from the trained semi-empirical Random Forest model,
identifies top-ranked descriptors, and performs sensitivity sweeps on noise-injected datasets.

Outputs:
- reports/feature_importance.json: Raw importance scores per feature.
- reports/sensitivity.csv: Summary of top descriptors and stability metrics (generated by subsequent tasks).
"""

import argparse
import csv
import json
import logging
import os
import sys
from pathlib import Path
from typing import List, Dict, Any, Tuple

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.model_selection import StratifiedKFold
from scipy.stats import spearmanr

# Project root resolution
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = PROJECT_ROOT / "data"
REPORTS_DIR = PROJECT_ROOT / "reports"
LOGS_DIR = PROJECT_ROOT / "logs"

# Ensure output directories exist
REPORTS_DIR.mkdir(parents=True, exist_ok=True)
LOGS_DIR.mkdir(parents=True, exist_ok=True)

def setup_logger(name: str) -> logging.Logger:
    """Configure a standard logger for the module."""
    logger = logging.getLogger(name)
    logger.setLevel(logging.INFO)
    if not logger.handlers:
        handler = logging.StreamHandler(sys.stdout)
        handler.setFormatter(logging.Formatter(
            '%(asctime)s - %(name)s - %(levelname)s - %(message)s'
        ))
        logger.addHandler(handler)
    return logger

logger = setup_logger("sensitivity_analysis")

def load_model(model_path: str) -> RandomForestRegressor:
    """
    Load a trained Random Forest model from a pickle file.
    Note: The model is expected to be saved by train_models.py.
    """
    import pickle
    path = Path(model_path)
    if not path.exists():
        raise FileNotFoundError(f"Model file not found: {path}")
    
    with open(path, 'rb') as f:
        model = pickle.load(f)
    logger.info(f"Loaded model from {path}")
    return model

def load_data(csv_path: str) -> Tuple[pd.DataFrame, pd.Series]:
    """
    Load descriptor data and target from CSV.
    Expected columns: all descriptor columns + 'experimental_barrier'.
    """
    path = Path(csv_path)
    if not path.exists():
        raise FileNotFoundError(f"Data file not found: {path}")
    
    df = pd.read_csv(path)
    
    # Identify target column
    if 'experimental_barrier' in df.columns:
        target_col = 'experimental_barrier'
    elif 'target' in df.columns:
        target_col = 'target'
    else:
        raise ValueError("Data file must contain 'experimental_barrier' or 'target' column")
    
    features = [col for col in df.columns if col != target_col]
    
    logger.info(f"Loaded {len(df)} samples with {len(features)} features from {path}")
    return df[features], df[target_col]

def prepare_features_target(X: pd.DataFrame, y: pd.Series) -> Tuple[np.ndarray, np.ndarray]:
    """Convert pandas objects to numpy arrays for sklearn."""
    return X.values.astype(np.float64), y.values.astype(np.float64)

def extract_feature_importance(model: RandomForestRegressor, feature_names: List[str]) -> Dict[str, float]:
    """
    Extract feature importance from a trained Random Forest model.
    Returns a dictionary mapping feature names to their importance scores.
    """
    importances = model.feature_importances_
    importance_dict = dict(zip(feature_names, importances))
    
    # Sort by importance descending
    sorted_importance = dict(sorted(importance_dict.items(), key=lambda x: x[1], reverse=True))
    
    logger.info(f"Extracted importance for {len(sorted_importance)} features")
    return sorted_importance

def identify_top_descriptors(importance_dict: Dict[str, float], top_n: int = 10) -> List[Dict[str, Any]]:
    """
    Identify the top N descriptors by importance.
    Returns a list of dictionaries with rank, descriptor name, and importance.
    """
    sorted_items = sorted(importance_dict.items(), key=lambda x: x[1], reverse=True)
    top_descriptors = []
    
    for rank, (name, importance) in enumerate(sorted_items[:top_n], 1):
        top_descriptors.append({
            'rank': rank,
            'descriptor': name,
            'importance': float(importance)
        })
    
    logger.info(f"Identified top {top_n} descriptors")
    return top_descriptors

def run_sensitivity_sweep(
    base_model: RandomForestRegressor,
    X_train: np.ndarray,
    y_train: np.ndarray,
    noise_levels: List[float] = [0.01, 0.05]
) -> Dict[str, Any]:
    """
    Run a sensitivity sweep by injecting Gaussian noise into the training data
    and re-evaluating feature importance stability.
    
    Returns a dictionary containing results for each noise level.
    """
    results = {}
    base_importance = extract_feature_importance(base_model, list(range(X_train.shape[1])))
    
    for sigma in noise_levels:
        logger.info(f"Injecting noise with sigma={sigma}")
        
        # Inject Gaussian noise
        noise = np.random.normal(0, sigma, X_train.shape)
        X_noisy = X_train + noise
        
        # Retrain model on noisy data (using same random_state for consistency)
        noisy_model = RandomForestRegressor(
            n_estimators=base_model.n_estimators,
            max_depth=base_model.max_depth,
            random_state=42,
            n_jobs=-1
        )
        noisy_model.fit(X_noisy, y_train)
        
        noisy_importance = extract_feature_importance(noisy_model, list(range(X_train.shape[1])))
        
        # Calculate correlation with base importance
        base_vals = np.array([base_importance[i] for i in range(len(base_importance))])
        noisy_vals = np.array([noisy_importance[i] for i in range(len(noisy_importance))])
        
        rho, p_value = spearmanr(base_vals, noisy_vals)
        
        results[f"sigma_{sigma}"] = {
            'rho': float(rho),
            'p_value': float(p_value),
            'top_3_indices': sorted(noisy_importance, key=noisy_importance.get, reverse=True)[:3]
        }
    
    return results

def calculate_mae_degradation(
    base_model: RandomForestRegressor,
    X_test: np.ndarray,
    y_test: np.ndarray,
    noise_levels: List[float] = [0.01, 0.05]
) -> Dict[str, float]:
    """
    Calculate MAE degradation for models trained on noisy data.
    """
    from sklearn.metrics import mean_absolute_error
    
    base_mae = mean_absolute_error(y_test, base_model.predict(X_test))
    degradations = {}
    
    for sigma in noise_levels:
        noise = np.random.normal(0, sigma, X_test.shape)
        X_noisy = X_test + noise
        
        # Use base model to predict on noisy data (simulating input noise)
        noisy_mae = mean_absolute_error(y_test, base_model.predict(X_noisy))
        degradations[f"sigma_{sigma}"] = float(noisy_mae - base_mae)
    
    return degradations

def verify_stability(sweep_results: Dict[str, Any], threshold: float = 0.9) -> bool:
    """
    Verify if the top descriptors are stable across noise levels.
    Stability is defined as Spearman's rho >= threshold.
    """
    if not sweep_results:
        return False
    
    rhos = [res['rho'] for res in sweep_results.values()]
    min_rho = min(rhos)
    
    stable = min_rho >= threshold
    logger.info(f"Stability check: min_rho={min_rho:.4f}, threshold={threshold}, stable={stable}")
    return stable

def generate_summary_report(
    importance_dict: Dict[str, float],
    top_descriptors: List[Dict[str, Any]],
    sweep_results: Dict[str, Any],
    stability: bool,
    output_path: str
):
    """
    Generate a comprehensive JSON report of the sensitivity analysis.
    """
    report = {
        'feature_importance': importance_dict,
        'top_descriptors': top_descriptors,
        'sensitivity_sweep_results': sweep_results,
        'stability_verified': stability,
        'analysis_timestamp': pd.Timestamp.now().isoformat()
    }
    
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Summary report written to {output_path}")

def main():
    """Main entry point for sensitivity analysis."""
    parser = argparse.ArgumentParser(description="Extract feature importance and run sensitivity analysis")
    parser.add_argument(
        "--model-path",
        type=str,
        default=str(PROJECT_ROOT / "code" / "models" / "rf_semi.pkl"),
        help="Path to the trained Random Forest model"
    )
    parser.add_argument(
        "--data-path",
        type=str,
        default=str(DATA_DIR / "descriptors_semi.csv"),
        help="Path to the descriptor dataset"
    )
    parser.add_argument(
        "--output-report",
        type=str,
        default=str(REPORTS_DIR / "feature_importance.json"),
        help="Path to the output JSON report"
    )
    parser.add_argument(
        "--noise-levels",
        type=float,
        nargs='+',
        default=[0.01, 0.05],
        help="Noise levels for sensitivity sweep"
    )
    parser.add_argument(
        "--top-n",
        type=int,
        default=10,
        help="Number of top descriptors to identify"
    )
    
    args = parser.parse_args()
    
    try:
        # Load model and data
        logger.info("Loading model and data...")
        model = load_model(args.model_path)
        X, y = load_data(args.data_path)
        X_train, y_train = prepare_features_target(X, y)
        
        # Extract feature importance
        logger.info("Extracting feature importance...")
        importance_dict = extract_feature_importance(model, list(X.columns))
        
        # Identify top descriptors
        logger.info("Identifying top descriptors...")
        top_descriptors = identify_top_descriptors(importance_dict, args.top_n)
        
        # Run sensitivity sweep
        logger.info("Running sensitivity sweep...")
        sweep_results = run_sensitivity_sweep(model, X_train, y_train, args.noise_levels)
        
        # Verify stability
        stability = verify_stability(sweep_results)
        
        # Generate summary report
        logger.info("Generating summary report...")
        generate_summary_report(
            importance_dict,
            top_descriptors,
            sweep_results,
            stability,
            args.output_report
        )
        
        # Write top descriptors to CSV for downstream tasks
        csv_path = str(REPORTS_DIR / "sensitivity.csv")
        with open(csv_path, 'w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=['rank', 'descriptor', 'importance'])
            writer.writeheader()
            writer.writerows(top_descriptors)
        
        logger.info(f"Top descriptors written to {csv_path}")
        logger.info("Sensitivity analysis completed successfully.")
        
    except Exception as e:
        logger.error(f"Error during sensitivity analysis: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()