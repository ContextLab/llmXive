import hashlib
import json
import os
import logging
from pathlib import Path
from typing import Dict, List, Any, Optional

from config import PROJECT_ROOT

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def calculate_file_hash(file_path: str) -> str:
    """Calculate SHA-256 hash of a file."""
    sha256_hash = hashlib.sha256()
    with open(file_path, "rb") as f:
        for byte_block in iter(lambda: f.read(4096), b""):
            sha256_hash.update(byte_block)
    return sha256_hash.hexdigest()

def calculate_content_hash(content: str) -> str:
    """Calculate SHA-256 hash of a string content."""
    return hashlib.sha256(content.encode('utf-8')).hexdigest()

def load_json_file(file_path: str) -> Any:
    """Load and parse a JSON file."""
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"File not found: {file_path}")
    with open(file_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def load_raw_manifest() -> List[Dict[str, Any]]:
    """Load the raw manifest generated by T005."""
    raw_path = PROJECT_ROOT / "data" / "prompts" / "raw_manifest.json"
    if not raw_path.exists():
        raise FileNotFoundError(f"Raw manifest not found at {raw_path}. "
                                "Please ensure T005 (download.py) has been executed.")
    return load_json_file(str(raw_path))

def load_handcrafted_prompts() -> List[Dict[str, Any]]:
    """Load the handcrafted prompts generated by T006."""
    handcrafted_path = PROJECT_ROOT / "data" / "prompts" / "handcrafted.json"
    if not handcrafted_path.exists():
        raise FileNotFoundError(f"Handcrafted prompts not found at {handcrafted_path}. "
                                "Please ensure T006 has been executed.")
    return load_json_file(str(handcrafted_path))

def generate_prompt_id(source: str, index: int, content_hash: str) -> str:
    """Generate a unique, deterministic prompt ID."""
    # Format: {source}_{index}_{short_hash}
    short_hash = content_hash[:8]
    return f"{source}_{index}_{short_hash}"

def build_unified_manifest(raw_prompts: List[Dict[str, Any]], 
                           handcrafted_prompts: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Combine raw and handcrafted prompts into a unified manifest.
    
    Returns a manifest structure with:
    - metadata: generation timestamp, total count, source breakdown
    - prompts: list of prompt objects with source attribution and checksums
    """
    unified_prompts = []
    
    # Process raw CodeXGLUE prompts
    for i, prompt in enumerate(raw_prompts):
        content = prompt.get('prompt_text', '')
        content_hash = calculate_content_hash(content)
        
        unified_entry = {
            "prompt_id": generate_prompt_id("codexglue", i, content_hash),
            "source": "codexglue",
            "original_id": prompt.get('id', f"raw_{i}"),
            "prompt_text": content,
            "content_hash": content_hash,
            "category": prompt.get('category', 'security'),
            "relevance_score": prompt.get('relevance_score', 0.0),
            "checksum": prompt.get('checksum', calculate_file_hash(PROJECT_ROOT / "data" / "prompts" / "raw_manifest.json"))
        }
        unified_prompts.append(unified_entry)
    
    # Process handcrafted prompts
    for i, prompt in enumerate(handcrafted_prompts):
        content = prompt.get('prompt_text', '')
        content_hash = calculate_content_hash(content)
        
        unified_entry = {
            "prompt_id": generate_prompt_id("handcrafted", i, content_hash),
            "source": "handcrafted",
            "original_id": prompt.get('id', f"handcrafted_{i}"),
            "prompt_text": content,
            "content_hash": content_hash,
            "category": prompt.get('category', 'web-security'),
            "subcategory": prompt.get('subcategory', 'general'),
            "checksum": calculate_content_hash(json.dumps(prompt))
        }
        unified_prompts.append(unified_entry)
    
    # Sort by source then ID for consistency
    unified_prompts.sort(key=lambda x: (x['source'], x['prompt_id']))
    
    manifest = {
        "metadata": {
            "version": "1.0",
            "generated_at": "T010_EXECUTION", # Will be replaced by actual time in main if needed, or kept static for reproducibility
            "total_prompts": len(unified_prompts),
            "source_breakdown": {
                "codexglue": len(raw_prompts),
                "handcrafted": len(handcrafted_prompts)
            },
            "description": "Unified manifest combining CodeXGLUE security prompts and handcrafted web security prompts."
        },
        "prompts": unified_prompts
    }
    
    return manifest

def save_manifest(manifest: Dict[str, Any], output_path: Path) -> None:
    """Save the unified manifest to a JSON file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)
    logger.info(f"Saved unified manifest to {output_path} ({len(manifest['prompts'])} prompts)")

def main():
    """Main entry point for T010."""
    logger.info("Starting T010: Combine prompts into unified manifest")
    
    try:
        # Load source data
        raw_prompts = load_raw_manifest()
        logger.info(f"Loaded {len(raw_prompts)} raw prompts from raw_manifest.json")
        
        handcrafted_prompts = load_handcrafted_prompts()
        logger.info(f"Loaded {len(handcrafted_prompts)} handcrafted prompts from handcrafted.json")
        
        # Build unified manifest
        manifest = build_unified_manifest(raw_prompts, handcrafted_prompts)
        
        # Save output
        output_path = PROJECT_ROOT / "data" / "prompts" / "manifest.json"
        save_manifest(manifest, output_path)
        
        logger.info("T010 completed successfully.")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"Missing required input file: {e}")
        return 1
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in input file: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during T010 execution: {e}")
        return 1

if __name__ == "__main__":
    import sys
    sys.exit(main())
