"""
Task T018: Generate segregation profiles for ternary systems.

This script orchestrates the computation of equilibrium segregation profiles
for Fe-Cr-Mo, Fe-Cr-V, Fe-Mo-V, Fe-Cr-W, and Fe-Mo-W systems.

It relies on:
1. Equilibrium bulk compositions from data/processed/equilibrium_compositions.csv (T048).
2. Segregation energies from the SurrogateService (T013).
3. McLean isotherm calculations from code/models/mclean.py (T014).

Output: data/processed/segregation_profiles.json
"""
import json
import logging
import sys
from pathlib import Path
from typing import Dict, List, Any, Optional

import pandas as pd

# Adjust path for execution context
ROOT_PATH = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT_PATH))

from code.config import get_logger, PROCESSED_PATH, DATA_RAW_PATH
from code.models.mclean import calculate_mclean_profile, McLeanResult
from code.services.surrogate_service import SurrogateService
from code.errors import DataLoadError, ConfigurationError

# Initialize logger
logger = get_logger(__name__)

# Define ternary systems to process
TERNARY_SYSTEMS = [
    "Fe-Cr-Mo",
    "Fe-Cr-V",
    "Fe-Mo-V",
    "Fe-Cr-W",
    "Fe-Mo-W"
]

def load_equilibrium_compositions() -> pd.DataFrame:
    """Load equilibrium compositions generated by T048."""
    input_path = PROCESSED_PATH / "equilibrium_compositions.csv"
    if not input_path.exists():
        logger.error(f"Equilibrium compositions file not found: {input_path}")
        raise FileNotFoundError(f"Required input file missing: {input_path}")
    
    logger.info(f"Loading equilibrium compositions from {input_path}")
    df = pd.read_csv(input_path)
    
    # Validate required columns
    required_cols = ['system', 'temperature_K', 'bulk_concentration']
    if not all(col in df.columns for col in required_cols):
        raise ConfigurationError(f"Missing required columns in {input_path}. Expected: {required_cols}")
    
    return df

def get_system_base_elements(system_name: str) -> List[str]:
    """Extract base binary elements from a ternary system name (e.g., 'Fe-Cr-Mo' -> ['Fe', 'Cr'])."""
    # Assuming format is 'Base-Solute1-Solute2' or similar. 
    # For this pipeline, we treat the first two as the primary binary for DFT lookup if needed,
    # or we map the specific ternary combination to the surrogate service.
    parts = system_name.split('-')
    if len(parts) < 2:
        raise ConfigurationError(f"Invalid system name format: {system_name}")
    return parts

def compute_segregation_profile(
    system: str, 
    temperature: float, 
    bulk_conc: float,
    surrogate_service: SurrogateService
) -> Optional[Dict[str, Any]]:
    """
    Compute the segregation profile for a specific system, temperature, and concentration.
    
    Returns a dictionary representing the McLeanResult or None if calculation fails.
    """
    try:
        # 1. Get Segregation Energy from Surrogate Service
        # The surrogate service is expected to handle the logic of mapping 
        # the ternary system to the appropriate energy value (or interpolated value).
        segregation_energy = surrogate_service.get_segregation_energy(
            system=system, 
            temperature=temperature
        )
        
        if segregation_energy is None:
            logger.warning(f"No segregation energy found for {system} at {temperature}K. Skipping.")
            return None

        logger.debug(f"System: {system}, Temp: {temperature}K, Bulk Conc: {bulk_conc}, Energy: {segregation_energy} eV")

        # 2. Calculate McLean Profile
        # bulk_concentration is expected to be a fraction (0.0 - 1.0)
        result: McLeanResult = calculate_mclean_profile(
            segregation_energy_eV=segregation_energy,
            bulk_concentration=bulk_conc,
            temperature_K=temperature
        )

        return {
            "system": system,
            "temperature_K": temperature,
            "bulk_concentration": bulk_conc,
            "segregation_energy_eV": segregation_energy,
            "equilibrium_concentration": result.equilibrium_concentration,
            "saturation_flag": result.saturation_flag,
            "profile": result.profile  # List of concentrations at different distances
        }

    except (DataLoadError, ConfigurationError, ValueError) as e:
        logger.error(f"Failed to compute profile for {system} at {temperature}K: {e}")
        return None
    except Exception as e:
        logger.exception(f"Unexpected error computing profile for {system}: {e}")
        return None

def main():
    """Main entry point for T018."""
    logger.info("Starting T018: Segregation Profile Generation")
    
    # 1. Load Inputs
    try:
        df_compositions = load_equilibrium_compositions()
    except Exception as e:
        logger.critical(f"Failed to load equilibrium compositions: {e}")
        return 1

    # 2. Initialize Surrogate Service
    # This service loads the DFT energies (real or placeholder per T018a)
    try:
        surrogate_service = SurrogateService()
    except Exception as e:
        logger.critical(f"Failed to initialize SurrogateService: {e}")
        return 1

    # 3. Process Ternary Systems
    # Filter the dataframe for the specific ternary systems defined in T018
    # Note: The CSV from T048 might contain many systems. We filter for our target list.
    target_rows = df_compositions[df_compositions['system'].isin(TERNARY_SYSTEMS)]
    
    if target_rows.empty:
        logger.warning(f"No data found in equilibrium_compositions.csv for systems: {TERNARY_SYSTEMS}")
        # Still create an empty output file to indicate completion
        results = []
    else:
        results = []
        for _, row in target_rows.iterrows():
            system = row['system']
            temp = row['temperature_K']
            conc = row['bulk_concentration']
            
            profile_data = compute_segregation_profile(system, temp, conc, surrogate_service)
            if profile_data:
                results.append(profile_data)

    # 4. Write Output
    output_path = PROCESSED_PATH / "segregation_profiles.json"
    PROCESSED_PATH.mkdir(parents=True, exist_ok=True)
    
    try:
        with open(output_path, 'w') as f:
            json.dump(results, f, indent=2)
        logger.info(f"Successfully wrote {len(results)} profiles to {output_path}")
    except IOError as e:
        logger.error(f"Failed to write output file: {e}")
        return 1

    logger.info("T018: Segregation Profile Generation completed.")
    return 0

if __name__ == "__main__":
    sys.exit(main())
