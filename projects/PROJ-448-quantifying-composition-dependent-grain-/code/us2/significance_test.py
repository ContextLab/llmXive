"""
T023: Implement significance testing (p-value < 0.05) for interaction coefficients.

This script loads the regression results (coefficients and standard errors)
generated by T021b (fit_linear_model_with_interactions) and computes p-values
using the t-distribution. It flags coefficients with p < 0.05 as statistically
significant.

Output: data/processed/significance_test_results.json
"""
import json
import logging
import sys
from pathlib import Path
from typing import Dict, List, Any, Optional, Tuple
import numpy as np
import pandas as pd
from scipy import stats

# Import from existing API surface
from code.config import PROCESSED_PATH, get_logger
from code.errors import ValidationError

# Ensure logger is available
logger = get_logger(__name__)

def load_regression_results() -> Dict[str, Any]:
    """
    Load regression results from the interaction model.
    Expects data/processed/regression_results.json (output of T021b).
    """
    input_path = PROCESSED_PATH / "regression_results.json"
    
    if not input_path.exists():
        logger.error(f"Regression results file not found: {input_path}")
        raise FileNotFoundError(f"Regression results file not found: {input_path}")
    
    with open(input_path, 'r') as f:
        data = json.load(f)
    
    return data

def calculate_pvalues(coefficients: np.ndarray, 
                     standard_errors: np.ndarray, 
                     degrees_of_freedom: int) -> np.ndarray:
    """
    Calculate two-tailed p-values for regression coefficients.
    
    Parameters
    ----------
    coefficients : np.ndarray
        Array of regression coefficients
    standard_errors : np.ndarray
        Array of standard errors for each coefficient
    degrees_of_freedom : int
        Degrees of freedom (n_samples - n_features - 1)
        
    Returns
    -------
    np.ndarray
        Array of p-values
    """
    # Calculate t-statistics
    t_stats = coefficients / standard_errors
    
    # Calculate two-tailed p-values using t-distribution
    p_values = 2 * (1 - stats.t.cdf(np.abs(t_stats), degrees_of_freedom))
    
    return p_values

def perform_significance_test(
    coefficients: np.ndarray,
    standard_errors: np.ndarray,
    feature_names: List[str],
    degrees_of_freedom: int,
    alpha: float = 0.05
) -> Tuple[Dict[str, Any], List[str]]:
    """
    Perform significance testing for interaction coefficients.
    
    Parameters
    ----------
    coefficients : np.ndarray
        Array of regression coefficients
    standard_errors : np.ndarray
        Array of standard errors
    feature_names : List[str]
        Names of features (including interaction terms)
    degrees_of_freedom : int
        Degrees of freedom
    alpha : float
        Significance level (default: 0.05)
        
    Returns
    -------
    Tuple[Dict[str, Any], List[str]]
        - Dictionary with test results (coefficients, p-values, significance flags)
        - List of significant interaction term names
    """
    # Calculate p-values
    p_values = calculate_pvalues(coefficients, standard_errors, degrees_of_freedom)
    
    # Determine significance
    significant = p_values < alpha
    
    # Build results dictionary
    results = {
        "alpha": alpha,
        "degrees_of_freedom": degrees_of_freedom,
        "results": []
    }
    
    significant_terms = []
    
    for i, (name, coef, se, p_val, sig) in enumerate(zip(
        feature_names, coefficients, standard_errors, p_values, significant
    )):
        result_entry = {
            "feature": name,
            "coefficient": float(coef),
            "standard_error": float(se),
            "p_value": float(p_val),
            "significant": bool(sig),
            "t_statistic": float(coef / se) if se > 0 else 0.0
        }
        results["results"].append(result_entry)
        
        # Track significant interaction terms (those with underscore in name)
        if sig and "_" in name:
            significant_terms.append(name)
    
    results["significant_interaction_terms"] = significant_terms
    results["total_significant"] = len(significant_terms)
    
    return results, significant_terms

def main():
    """Main entry point for significance testing."""
    logger.info("Starting significance testing for interaction coefficients (T023)")
    
    try:
        # Load regression results
        logger.info("Loading regression results...")
        regression_data = load_regression_results()
        
        # Extract necessary data
        coefficients = np.array(regression_data["coefficients"])
        standard_errors = np.array(regression_data["standard_errors"])
        feature_names = regression_data["feature_names"]
        n_samples = regression_data["n_samples"]
        n_features = regression_data["n_features"]
        
        # Calculate degrees of freedom
        degrees_of_freedom = n_samples - n_features - 1
        
        if degrees_of_freedom <= 0:
            raise ValidationError(
                f"Invalid degrees of freedom: {degrees_of_freedom}. "
                f"Need more samples than features."
            )
        
        logger.info(f"Degrees of freedom: {degrees_of_freedom}")
        logger.info(f"Number of features: {n_features}")
        logger.info(f"Number of samples: {n_samples}")
        
        # Perform significance testing
        logger.info("Performing significance testing...")
        results, significant_terms = perform_significance_test(
            coefficients, 
            standard_errors, 
            feature_names, 
            degrees_of_freedom
        )
        
        # Log results
        logger.info(f"Found {len(significant_terms)} significant interaction terms")
        if significant_terms:
            logger.info(f"Significant terms: {', '.join(significant_terms)}")
        else:
            logger.warning("No significant interaction terms found at alpha=0.05")
        
        # Save results
        output_path = PROCESSED_PATH / "significance_test_results.json"
        with open(output_path, 'w') as f:
            json.dump(results, f, indent=2)
        
        logger.info(f"Significance test results saved to: {output_path}")
        
        # Return success
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        return 1
    except ValidationError as e:
        logger.error(f"Validation error: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during significance testing: {e}")
        raise

if __name__ == "__main__":
    sys.exit(main())