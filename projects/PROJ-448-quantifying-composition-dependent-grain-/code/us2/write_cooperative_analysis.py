def compile_cooperative_analysis(
    regression_results: Dict[str, Any],
    validation_report: Dict[str, Any],
    mse_results: Dict[str, Any]
) -> Dict[str, Any]:
    """
    Compile the final cooperative effects analysis report.
    
    Aggregates regression coefficients, p-values, significance flags,
    and MSE reduction statistics into a single analysis artifact.
    """
    analysis = {
        "status": "complete",
        "summary": {
            "cooperative_effects_detected": validation_report.get("status", "unknown"),
            "total_systems_analyzed": len(regression_results.get("systems", [])),
            "significant_interaction_terms": 0,
            "systems_with_cooperative_effects": []
        },
        "systems": []
    }

    systems_data = regression_results.get("systems", [])
    
    for system_data in systems_data:
        system_name = system_data.get("system_name")
        
        # Extract coefficients and p-values
        coefficients = system_data.get("coefficients", {})
        p_values = system_data.get("p_values", {})
        
        # Count significant interaction terms for this system
        significant_terms = []
        interaction_keys = [k for k in coefficients.keys() if '_' in k]
        
        for key in interaction_keys:
            coef = coefficients.get(key, 0.0)
            p_val = p_values.get(key, 1.0)
            
            # Check significance: p < 0.05 and |coef| > 0.01 eV
            if p_val < 0.05 and abs(coef) > 0.01:
                significant_terms.append({
                    "term": key,
                    "coefficient_eV": float(coef),
                    "p_value": float(p_val),
                    "significance": "significant"
                })
            else:
                significant_terms.append({
                    "term": key,
                    "coefficient_eV": float(coef),
                    "p_value": float(p_val),
                    "significance": "not_significant"
                })

        # Get MSE reduction for this system if available
        system_mse = None
        if "systems" in mse_results:
            for mse_sys in mse_results["systems"]:
                if mse_sys.get("system_name") == system_name:
                    system_mse = mse_sys
                    break

        system_analysis = {
            "system_name": system_name,
            "cooperative_effects_detected": False,
            "interaction_terms": significant_terms,
            "mse_reduction": system_mse.get("mse_reduction_percent", None) if system_mse else None,
            "mse_reduction_threshold_met": system_mse.get("threshold_met", False) if system_mse else False
        }

        # Determine if cooperative effects are detected for this system
        if len(significant_terms) > 0 and system_mse and system_mse.get("threshold_met", False):
            system_analysis["cooperative_effects_detected"] = True
            analysis["summary"]["systems_with_cooperative_effects"].append(system_name)

        # Update count of significant interaction terms across all systems
        analysis["summary"]["significant_interaction_terms"] += len([
            t for t in significant_terms if t["significance"] == "significant"
        ])

        analysis["systems"].append(system_analysis)

    # Finalize summary
    analysis["summary"]["systems_with_cooperative_effects_count"] = len(
        analysis["summary"]["systems_with_cooperative_effects"]
    )

    logger.info(f"Cooperative effects analysis complete. Detected in {analysis['summary']['systems_with_cooperative_effects_count']} systems.")
    return analysis

def main():
    """Main entry point for T025: Write cooperative effects analysis results."""
    logger.info("Starting T025: Writing cooperative effects analysis results.")
    
    try:
        # Load all required inputs
        regression_results = load_regression_results()
        validation_report = load_statistical_validation_report()
        mse_results = load_mse_reduction_results()
        
        logger.info("Loaded regression results, validation report, and MSE reduction results.")
        
        # Compile the analysis
        analysis_report = compile_cooperative_analysis(
            regression_results, 
            validation_report, 
            mse_results
        )
        
        # Write output
        output_path = PROCESSED_PATH / "cooperative_effects_analysis.json"
        with open(output_path, 'w') as f:
            json.dump(analysis_report, f, indent=2)
        
        logger.info(f"Successfully wrote cooperative effects analysis to {output_path}")
        print(f"T025 Completed: {output_path}")
        
    except FileNotFoundError as e:
        logger.error(f"Missing required input file: {e}")
        raise
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in input file: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during analysis compilation: {e}")
        raise

if __name__ == "__main__":
    main()
