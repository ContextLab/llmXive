"""
Generate interaction terms for regression analysis (T021a).

This script loads the computed segregation profiles from T018,
extracts bulk compositions, and generates polynomial interaction terms
(degree=2, no bias) using sklearn.preprocessing.PolynomialFeatures.

Output: data/processed/interaction_terms.csv
"""
import logging
import sys
from pathlib import Path
from typing import List, Dict, Any, Tuple

import numpy as np
import pandas as pd
from sklearn.preprocessing import PolynomialFeatures

# Add project root to path for imports if running as script
if Path.cwd() != Path(__file__).parent.parent:
    sys.path.insert(0, str(Path(__file__).parent.parent))

from code.config import PROCESSED_PATH, get_logger
from code.errors import DataLoadError

# Ensure logger is configured
logger = get_logger(__name__)

INPUT_FILE = "segregation_profiles.json"
OUTPUT_FILE = "interaction_terms.csv"
INTERACTION_COLUMNS = ["Cr_Mo", "Cr_V", "Mo_V", "Cr_W", "Mo_W", "V_W"]

def load_segregation_profiles() -> pd.DataFrame:
    """
    Load segregation profiles generated by T018.
    Expects a JSON file with a list of profile records.
    """
    input_path = PROCESSED_PATH / INPUT_FILE
    if not input_path.exists():
        raise DataLoadError(f"Input file not found: {input_path}")

    logger.info(f"Loading segregation profiles from {input_path}")
    
    try:
        df = pd.read_json(input_path)
    except Exception as e:
        raise DataLoadError(f"Failed to parse JSON: {e}")

    if df.empty:
        raise DataLoadError("Segregation profiles file is empty.")

    # Ensure required columns exist
    required_cols = ["system", "cr_conc", "mo_conc", "v_conc", "w_conc", "segregation_energy"]
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise DataLoadError(f"Missing required columns in input: {missing}")

    return df

def generate_interaction_terms(df: pd.DataFrame) -> pd.DataFrame:
    """
    Generate interaction terms using sklearn PolynomialFeatures.
    
    Input features: Cr, Mo, V, W concentrations.
    Output: Original features + 2-way interactions.
    """
    feature_cols = ["cr_conc", "mo_conc", "v_conc", "w_conc"]
    X = df[feature_cols].values

    logger.info(f"Generating interaction terms for {len(X)} samples using PolynomialFeatures(degree=2)")
    
    poly = PolynomialFeatures(degree=2, include_bias=False)
    X_poly = poly.fit_transform(X)

    # Get feature names from sklearn
    feature_names = poly.get_feature_names_out(feature_cols)
    
    # Filter for interaction terms only (those containing '_')
    interaction_mask = ["_" in name for name in feature_names]
    interaction_features = X_poly[:, interaction_mask]
    interaction_names = [name.replace(" ", "_") for name in np.array(feature_names)[interaction_mask]]
    
    # Rename to match the required convention: Cr_Mo, Cr_V, etc.
    # sklearn outputs: "cr_conc mo_conc" -> we want "Cr_Mo"
    # Map sklearn output names to required convention
    name_map = {}
    for i, name in enumerate(interaction_names):
        # Parse "cr_conc mo_conc" -> "Cr_Mo"
        parts = name.split()
        if len(parts) == 2:
            el1 = parts[0].replace("_conc", "").upper()
            el2 = parts[1].replace("_conc", "").upper()
            new_name = f"{el1}_{el2}"
            name_map[name] = new_name

    # Create a dataframe for interaction terms
    interaction_df = pd.DataFrame(interaction_features, columns=[name_map.get(n, n) for n in interaction_names])
    
    # Ensure column order matches requirement
    # Requirement: [Cr, Mo, Cr_Mo, ...] -> Actually requirement says:
    # "Generate data/processed/interaction_terms.csv with columns [Cr, Mo, Cr_Mo,...]"
    # Wait, re-reading: "columns [Cr, Mo, Cr_Mo,...]" implies main effects first?
    # But the constraint says: "Use exact column naming convention: Cr_Mo, Cr_V..."
    # And the requirement says: "Generate interaction terms... columns [Cr, Mo, Cr_Mo,...]"
    # Let's include main effects AND interactions, ordered as: Main Effects -> Interactions
    # But the specific list [Cr, Mo, Cr_Mo...] suggests a specific order.
    # Let's follow the standard: Main effects first, then interactions.
    # However, the requirement text "columns [Cr, Mo, Cr_Mo,...]" might imply the full set.
    # Let's output: Main effects (Cr, Mo, V, W) + Interactions (Cr_Mo, Cr_V, ...)
    # But the constraint says "exact column naming convention: Cr_Mo..." for interactions.
    
    # Let's construct the final dataframe with Main Effects + Interactions
    main_effects_df = df[["cr_conc", "mo_conc", "v_conc", "w_conc"]].copy()
    main_effects_df.columns = ["Cr", "Mo", "V", "W"]
    
    # Filter interaction_df to only include the specific required interaction columns
    # The requirement lists: Cr_Mo, Cr_V, Mo_V, Cr_W, Mo_W, V_W
    # We need to ensure these exist in our generated interaction_df
    available_interactions = [c for c in INTERACTION_COLUMNS if c in interaction_df.columns]
    if len(available_interactions) != len(INTERACTION_COLUMNS):
        missing = set(INTERACTION_COLUMNS) - set(available_interactions)
        logger.warning(f"Missing interaction columns: {missing}. Generating from available: {available_interactions}")
    
    interaction_subset = interaction_df[available_interactions].copy()
    
    # Combine: Main effects first, then interactions
    result_df = pd.concat([main_effects_df, interaction_subset], axis=1)
    
    # Add metadata columns for traceability
    result_df["system"] = df["system"]
    
    return result_df

def save_interaction_terms(df: pd.DataFrame, output_path: Path):
    """Save the interaction terms to CSV."""
    df.to_csv(output_path, index=False)
    logger.info(f"Saved interaction terms to {output_path}")

def main():
    """Main entry point."""
    logger.info("Starting T021a: Generate interaction terms for regression")
    
    try:
        # 1. Load data
        df = load_segregation_profiles()
        
        # 2. Generate terms
        result_df = generate_interaction_terms(df)
        
        # 3. Save output
        output_path = PROCESSED_PATH / OUTPUT_FILE
        save_interaction_terms(result_df, output_path)
        
        logger.info("T021a completed successfully")
        return 0
        
    except DataLoadError as e:
        logger.error(f"Data loading error: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())
