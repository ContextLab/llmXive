"""
T026 [US2] Add logic to flag systems where no significant cooperative effects are detected within statistical power.

This module reads the regression analysis results and statistical validation report
generated by previous tasks (T021b, T023, T025) to determine if any alloy system
exhibits statistically significant cooperative segregation effects.

A system is flagged as 'NO_COOPERATIVE_EFFECTS' if:
1. No interaction term has a p-value < 0.05 AND |coefficient| > 0.01 eV.
2. OR the MSE reduction compared to the additive null model is <= 10%.
3. OR the k-fold cross-validation R² standard deviation > 0.05 (indicating instability).

The results are written to a JSON file for downstream reporting.
"""

import json
import logging
import sys
from pathlib import Path
from typing import Dict, List, Any, Optional

# Import from project API surface
from code.config import PROCESSED_PATH, get_logger
from code.errors import ValidationError

# Ensure paths are initialized if not done by config
PROCESSED_PATH.mkdir(parents=True, exist_ok=True)

# Configure logger
logger = get_logger(__name__)

INPUT_REGRESSION_PATH = PROCESSED_PATH / "cooperative_effects_analysis.json"
INPUT_VALIDATION_PATH = PROCESSED_PATH / "statistical_validation_report.json"
OUTPUT_FLAG_PATH = PROCESSED_PATH / "no_cooperative_effects_flag.json"

# Thresholds defined in task requirements
P_VALUE_THRESHOLD = 0.05
COEFFICIENT_MAGNITUDE_THRESHOLD = 0.01  # eV
MSE_REDUCTION_THRESHOLD = 0.10  # 10%
CV_R2_STD_THRESHOLD = 0.05


def load_json_file(path: Path) -> Dict[str, Any]:
    """Load and return JSON content from a file."""
    if not path.exists():
        raise FileNotFoundError(f"Required input file not found: {path}")
    with open(path, 'r') as f:
        return json.load(f)


def check_interaction_significance(regression_data: Dict[str, Any]) -> bool:
    """
    Check if ANY interaction term meets the significance criteria:
    p-value < 0.05 AND |coefficient| > 0.01 eV.

    Returns True if significant cooperative effects are detected.
    Returns False otherwise.
    """
    interaction_terms = regression_data.get("interaction_coefficients", {})
    p_values = regression_data.get("interaction_p_values", {})

    significant_found = False
    for term, coeff in interaction_terms.items():
        p_val = p_values.get(term, 1.0)
        if p_val < P_VALUE_THRESHOLD and abs(coeff) > COEFFICIENT_MAGNITUDE_THRESHOLD:
            logger.info(f"Significant interaction detected: {term} (coeff={coeff:.4f}, p={p_val:.4f})")
            significant_found = True
            break

    if not significant_found:
        logger.warning("No interaction terms met significance criteria (p < 0.05 AND |coeff| > 0.01).")

    return significant_found


def check_mse_reduction(regression_data: Dict[str, Any]) -> bool:
    """
    Check if MSE reduction compared to additive null model is > 10%.

    Returns True if reduction is significant.
    Returns False otherwise.
    """
    mse_reduction = regression_data.get("mse_reduction_percent", 0.0)
    if mse_reduction > (MSE_REDUCTION_THRESHOLD * 100):
        logger.info(f"MSE reduction {mse_reduction:.2f}% exceeds threshold {MSE_REDUCTION_THRESHOLD*100:.1f}%.")
        return True
    else:
        logger.warning(f"MSE reduction {mse_reduction:.2f}% does not exceed threshold {MSE_REDUCTION_THRESHOLD*100:.1f}%.")
        return False


def check_cv_stability(validation_data: Dict[str, Any]) -> bool:
    """
    Check if k-fold cross-validation R² standard deviation <= 0.05.

    Returns True if stable.
    Returns False if unstable.
    """
    # The validation report might contain CV stats directly or we might need to look deeper
    # Assuming the structure from T021c/T030
    cv_results = validation_data.get("cross_validation_results", {})
    r2_std = cv_results.get("r2_std_dev", 1.0)

    if r2_std <= CV_R2_STD_THRESHOLD:
        logger.info(f"CV stability OK: R² std dev {r2_std:.4f} <= {CV_R2_STD_THRESHOLD}.")
        return True
    else:
        logger.warning(f"CV instability detected: R² std dev {r2_std:.4f} > {CV_R2_STD_THRESHOLD}.")
        return False


def flag_systems(
    regression_data: Dict[str, Any],
    validation_data: Dict[str, Any]
) -> List[Dict[str, Any]]:
    """
    Determine which systems (or the overall model) should be flagged for lack of
    significant cooperative effects.

    Returns a list of flag entries.
    """
    flags = []

    # Check conditions
    has_significant_interaction = check_interaction_significance(regression_data)
    has_mse_reduction = check_mse_reduction(regression_data)
    is_cv_stable = check_cv_stability(validation_data)

    # Logic: If NO significant interaction OR NO MSE reduction OR unstable CV, flag it.
    # Specifically, the task asks to flag systems where "no significant cooperative effects
    # are detected within statistical power".
    # This implies: if (not significant_interaction) OR (not mse_reduction) OR (not stable_cv) -> Flag.
    # However, typically "cooperative effects" are confirmed if interaction is significant AND stable.
    # If interaction is not significant, we definitely flag "No Cooperative Effects".

    if not has_significant_interaction:
        reason = "No interaction terms met statistical significance criteria (p < 0.05 AND |coeff| > 0.01)."
        flags.append({
            "flag": "NO_COOPERATIVE_EFFECTS_DETECTED",
            "reason": reason,
            "criteria_met": {
                "significant_interaction": False,
                "mse_reduction": has_mse_reduction,
                "cv_stability": is_cv_stable
            }
        })
        logger.warning(f"Flagging system: {reason}")
    elif not has_mse_reduction:
        reason = "MSE reduction did not exceed 10% threshold despite significant interactions."
        flags.append({
            "flag": "MARGINAL_COOPERATIVE_EFFECTS",
            "reason": reason,
            "criteria_met": {
                "significant_interaction": True,
                "mse_reduction": False,
                "cv_stability": is_cv_stable
            }
        })
        logger.warning(f"Flagging system: {reason}")
    elif not is_cv_stable:
        reason = "Model instability (CV R² std dev > 0.05) prevents reliable detection of cooperative effects."
        flags.append({
            "flag": "UNSTABLE_MODEL",
            "reason": reason,
            "criteria_met": {
                "significant_interaction": True,
                "mse_reduction": True,
                "cv_stability": False
            }
        })
        logger.warning(f"Flagging system: {reason}")
    else:
        logger.info("All criteria met: Significant cooperative effects detected with stable model.")

    return flags


def main():
    """Main entry point for T026."""
    logger.info("Starting T026: Flagging systems with no significant cooperative effects.")

    try:
        # Load inputs
        regression_data = load_json_file(INPUT_REGRESSION_PATH)
        validation_data = load_json_file(INPUT_VALIDATION_PATH)

        # Perform flagging logic
        flags = flag_systems(regression_data, validation_data)

        # Prepare output
        output = {
            "task_id": "T026",
            "input_files": {
                "regression": str(INPUT_REGRESSION_PATH),
                "validation": str(INPUT_VALIDATION_PATH)
            },
            "flags": flags,
            "summary": {
                "total_flags": len(flags),
                "status": "FLAGGED" if flags else "NO_FLAGS"
            }
        }

        # Write output
        with open(OUTPUT_FLAG_PATH, 'w') as f:
            json.dump(output, f, indent=2)

        logger.info(f"Successfully wrote flags to {OUTPUT_FLAG_PATH}")
        return 0

    except FileNotFoundError as e:
        logger.error(f"Missing required input file: {e}")
        raise
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in input file: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during T026 execution: {e}")
        raise


if __name__ == "__main__":
    sys.exit(main())