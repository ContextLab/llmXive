"""
Surrogate Service for computing literature-calibrated segregation energies.

Implements the algorithm: E_seg_ternary = sum(w_i * E_seg_binary_i) + Delta_E_interaction
with validation to ensure inputs align with supercell geometry.
"""
import logging
import numpy as np
from typing import Dict, List, Optional, Tuple, Any
from pathlib import Path
import json
from models.alloy_system import AlloySystem
from models.segregation_profile import SegregationProfile, BoundaryType
from errors import SurrogateModelError, ValidationError
