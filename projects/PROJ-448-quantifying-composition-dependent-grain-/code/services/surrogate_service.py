logger = logging.getLogger(__name__)

class SurrogateService:
    """
    Service for computing segregation energies using a surrogate model.
    
    Validates that surrogate inputs (alloy composition, site environment)
    align with the supercell geometry generated by gb_service.py before
    performing energy calculations.
    """

    def __init__(self, temperature_range: Tuple[float, float] = (300.0, 900.0)):
        """
        Initialize the surrogate service.
        
        Args:
            temperature_range: Tuple of (min_temp, max_temp) in Kelvin.
        """
        self.temperature_range = temperature_range
        self.validation_flags: List[str] = []

    def validate_geometry_alignment(
        self,
        alloy_system: AlloySystem,
        gb_structure: Any,
        target_sites: List[int]
    ) -> bool:
        """
        Validate that surrogate inputs align with the supercell geometry.
        
        This ensures:
        1. The alloy system composition matches the bulk composition in the supercell.
        2. The target sites for segregation are within the supercell bounds.
        3. The site environments are physically plausible (e.g., not vacuum).
        
        Args:
            alloy_system: The alloy system definition.
            gb_structure: The supercell structure from gb_service.
            target_sites: List of site indices to validate.
            
        Returns:
            True if validation passes, False otherwise.
            
        Raises:
            ValidationError: If validation fails and cannot be recovered.
        """
        logger.info(f"Validating geometry alignment for alloy {alloy_system.name}")
        
        # Check 1: Verify target sites are within bounds
        num_sites = len(gb_structure.sites)
        for site_idx in target_sites:
            if site_idx < 0 or site_idx >= num_sites:
                error_msg = f"Target site {site_idx} out of bounds [0, {num_sites})"
                logger.error(error_msg)
                raise ValidationError(error_msg)
        
        # Check 2: Verify bulk composition consistency
        # Extract bulk composition from the supercell (excluding GB core if needed)
        # For simplicity, we assume the supercell represents the bulk + GB
        # In a more advanced implementation, we would filter out GB core sites
        bulk_composition = {}
        for site in gb_structure.sites:
            species = site.species
            for element, occ in species.items():
                elem_str = str(element)
                bulk_composition[elem_str] = bulk_composition.get(elem_str, 0.0) + occ
        
        # Normalize to atomic fractions
        total = sum(bulk_composition.values())
        if total > 0:
            bulk_composition = {k: v / total for k, v in bulk_composition.items()}
        
        # Compare with alloy system composition
        alloy_composition = alloy_system.composition
        for element, expected_frac in alloy_composition.items():
            actual_frac = bulk_composition.get(element, 0.0)
            # Allow a small tolerance for numerical precision
            if abs(actual_frac - expected_frac) > 0.01:
                warning_msg = (
                    f"Composition mismatch for {element}: "
                    f"alloy={expected_frac:.4f}, supercell={actual_frac:.4f}"
                )
                logger.warning(warning_msg)
                self.validation_flags.append(warning_msg)
        
        # Check 3: Verify site environments are not vacuum
        for site_idx in target_sites:
            site = gb_structure.sites[site_idx]
            species = site.species
            if not species or sum(species.values()) < 0.1:
                error_msg = f"Site {site_idx} appears to be vacuum (empty or near-empty)"
                logger.error(error_msg)
                raise ValidationError(error_msg)
        
        logger.info("Geometry validation passed")
        return True

    def compute_segregation_energy(
        self,
        alloy_system: AlloySystem,
        gb_structure: Any,
        target_sites: List[int],
        temperature: float
    ) -> Dict[str, Any]:
        """
        Compute segregation energy for the given alloy system and geometry.
        
        Args:
            alloy_system: The alloy system definition.
            gb_structure: The supercell structure.
            target_sites: List of site indices to compute segregation for.
            temperature: Temperature in Kelvin.
            
        Returns:
            Dictionary containing segregation energies and metadata.
        """
        # Validate geometry alignment first
        self.validate_geometry_alignment(alloy_system, gb_structure, target_sites)
        
        # Check temperature range
        if not (self.temperature_range[0] <= temperature <= self.temperature_range[1]):
            raise ValidationError(
                f"Temperature {temperature}K outside valid range "
                f"[{self.temperature_range[0]}K, {self.temperature_range[1]}K]"
            )
        
        # Compute segregation energies
        # Algorithm: E_seg_ternary = sum(w_i * E_seg_binary_i) + Delta_E_interaction
        # For now, we use a placeholder calculation - this would be replaced
        # with actual surrogate model calls in a full implementation
        
        results = {
            "alloy_system": alloy_system.name,
            "temperature": temperature,
            "segregation_energies": {},
            "flags": self.validation_flags.copy()
        }
        
        # Clear flags for next run
        self.validation_flags = []
        
        # Placeholder: In a real implementation, this would call the surrogate model
        # For demonstration, we compute a simple weighted average based on composition
        composition = alloy_system.composition
        elements = list(composition.keys())
        fractions = [composition[e] for e in elements]
        
        for site_idx in target_sites:
            site = gb_structure.sites[site_idx]
            # Simple heuristic: segregation energy proportional to local composition
            # In reality, this would use DFT-calibrated surrogate models
            e_seg = 0.0
            for elem, frac in zip(elements, fractions):
                # Placeholder: binary segregation energy (would come from literature)
                binary_e_seg = 0.1 * (np.random.rand() - 0.5)  # Random for demo
                e_seg += frac * binary_e_seg
            
            # No ternary interaction data -> Delta_E_interaction = 0
            results["segregation_energies"][site_idx] = e_seg
        
        return results

    def generate_profile(
        self,
        alloy_system: AlloySystem,
        gb_type: BoundaryType,
        temperatures: Optional[List[float]] = None
    ) -> SegregationProfile:
        """
        Generate a full segregation profile for the given alloy and boundary type.
        
        Args:
            alloy_system: The alloy system definition.
            gb_type: Type of grain boundary.
            temperatures: List of temperatures to compute (defaults to range).
            
        Returns:
            SegregationProfile object with computed energies and concentrations.
        """
        if temperatures is None:
            temperatures = [self.temperature_range[0], self.temperature_range[1]]
        
        # Generate supercell
        gb_structure = generate_symmetric_tilt_grain_boundary_supercell(
            alloy_system, gb_type
        )
        
        # Identify target sites (near GB plane)
        # For simplicity, we select sites within a certain distance from the GB plane
        # In a real implementation, this would be more sophisticated
        target_sites = list(range(min(10, len(gb_structure.sites))))
        
        profile_data = {
            "alloy_system": alloy_system.name,
            "boundary_type": gb_type.value,
            "temperatures": {},
            "geometry_validated": True
        }
        
        for temp in temperatures:
            result = self.compute_segregation_energy(
                alloy_system, gb_structure, target_sites, temp
            )
            profile_data["temperatures"][str(temp)] = result
        
        return SegregationProfile(
            alloy_system=alloy_system,
            boundary_type=gb_type,
            data=profile_data
        )

