"""
DFT Service for Quantum ESPRESSO Interface Simulation.

This module provides the interface for Quantum ESPRESSO DFT calculations.
Per spec-amendment T017b and the CI constraints, this task is HPC-ONLY.
It MUST be skipped in the CI environment to avoid attempting real DFT runs.
"""
import os
import logging
from pathlib import Path
from code.config import DATA_RAW_PATH, RESEARCH_TEMPLATES_PATH

# Initialize logger
logger = logging.getLogger(__name__)

def is_ci_environment() -> bool:
    """Check if running in a CI environment."""
    return os.getenv("CI", "false").lower() in ("true", "1", "yes")

def generate_supercell_template(system: str = "fe_cr", boundary_type: str = "symmetric_tilt") -> Path:
    """
    Generate a template PWscf input file for a specific supercell geometry.

    Args:
        system: The alloy system identifier (e.g., 'fe_cr', 'fe_mo').
        boundary_type: The type of grain boundary (e.g., 'symmetric_tilt').

    Returns:
        Path to the generated template file.
    """
    logger.info(f"Generating DFT supercell template for {system} ({boundary_type})")

    # Ensure output directories exist
    RESEARCH_TEMPLATES_PATH.mkdir(parents=True, exist_ok=True)
    DATA_RAW_PATH.mkdir(parents=True, exist_ok=True)

    template_path = RESEARCH_TEMPLATES_PATH / f"{system}_{boundary_type}.pwscf"
    output_path = DATA_RAW_PATH / "supercell_template.pwscf"

    # Define a minimal but valid PWscf input template structure
    # This is a template, not a full calculation, intended for HPC submission later
    pwscf_content = f"""&CONTROL
    calculation = 'scf'
    restart_mode = 'from_scratch'
    prefix = '{system}_gb'
    pseudo_dir = './pseudo'
    outdir = './tmp'
    verbosity = 'high'
/
&SYSTEM
    ibrav = 0
    nat = 100  ! Placeholder: actual number depends on supercell size
    ntyp = 2   ! Placeholder: Fe and Cr
    ecutwfc = 40.0
    ecutrho = 400.0
    occupations = 'smearing'
    smearing = 'marzari-vanderbilt'
    degauss = 0.01
/
&ELECTRONS
    conv_thr = 1.0d-8
    mixing_beta = 0.7
/
ATOMIC_SPECIES
    Fe  55.845  Fe.pbe-n-kjpaw_psl.1.0.0.UPF
    Cr  51.996  Cr.pbe-n-kjpaw_psl.1.0.0.UPF
ATOMIC_POSITIONS crystal
    ! Lattice vectors and atomic positions will be generated by gb_service
    ! This is a template placeholder
    Fe  0.0  0.0  0.0
    Cr  0.5  0.5  0.5
    ! ... additional atoms ...
K_POINTS automatic
    4 4 1 0 0 0
CELL_PARAMETERS bohr
    ! Lattice vectors will be defined by the specific supercell geometry
    10.0 0.0 0.0
    0.0 10.0 0.0
    0.0 0.0 20.0
"""
    try:
        # Write to research templates
        template_path.write_text(pwscf_content)
        logger.info(f"Template written to {template_path}")

        # Copy to data/raw as the output artifact
        output_path.write_text(pwscf_content)
        logger.info(f"Output template written to {output_path}")

        return output_path
    except Exception as e:
        logger.error(f"Failed to generate template: {e}")
        raise

def main():
    """
    Main entry point for the DFT service.
    Implements the HPC-ONLY constraint: skips execution in CI.
    """
    if is_ci_environment():
        logger.warning("SKIPPED: HPC-ONLY task in CI environment.")
        logger.warning("Per spec-amendment T017b, real DFT calculations are deferred to HPC resources.")
        # Still generate the template artifact to satisfy the deliverable requirement
        # but do not attempt to run any calculation or fetch real data.
        try:
            generate_supercell_template()
            logger.info("Template artifact created successfully despite CI skip.")
        except Exception as e:
            logger.error(f"Failed to create template artifact: {e}")
            raise
        return

    logger.info("Starting DFT Service (Non-CI Environment)")
    try:
        generate_supercell_template()
        logger.info("DFT Service completed successfully.")
    except Exception as e:
        logger.error(f"DFT Service failed: {e}")
        raise

if __name__ == "__main__":
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(name)s - %(levelname)s - %(message)s"
    )
    main()
