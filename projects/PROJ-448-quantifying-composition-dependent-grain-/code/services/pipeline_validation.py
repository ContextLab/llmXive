import json
import logging
import sys
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple

from code.config import PROCESSED_PATH, RESEARCH_PATH, get_logger
from code.errors import DataLoadError, ConfigurationError

logger = get_logger(__name__)

def load_regression_results() -> Dict[str, Any]:
    """
    Load regression results from T025 (cooperative_effects_analysis.json).
    """
    path = PROCESSED_PATH / "cooperative_effects_analysis.json"
    if not path.exists():
        raise DataLoadError(f"Regression results file not found: {path}")
    
    with open(path, 'r') as f:
        data = json.load(f)
    
    logger.info(f"Loaded regression results from {path}")
    return data

def load_ground_truth() -> Dict[str, Any]:
    """
    Load injected ground truth from T091 (generated_ground_truth.csv or corresponding metadata).
    Since T091 generates a CSV, we assume the ground truth coefficients are stored
    in a companion JSON metadata file or embedded in the CSV structure.
    For this implementation, we look for a specific metadata file generated by T091.
    """
    # The task T091 mentions generating 'data/raw/generated_ground_truth.csv'.
    # We need a way to retrieve the 'injected' coefficients. 
    # Typically, the generator (T090-Script) would log these or save a config.
    # We assume a companion file 'data/raw/generated_ground_truth_meta.json' exists
    # or we read the 'interaction_coefficients' from the config used (research/synthetic_ground_truth.yaml).
    
    # Let's try to load from the research config directly as that is the source of truth for injection.
    config_path = RESEARCH_PATH / "synthetic_ground_truth.yaml"
    
    if not config_path.exists():
        # Fallback: try to find a metadata file in raw data
        meta_path = PROCESSED_PATH.parent / "raw" / "generated_ground_truth_meta.json"
        if meta_path.exists():
            with open(meta_path, 'r') as f:
                return json.load(f)
        else:
            raise DataLoadError(
                f"Ground truth configuration not found: {config_path} "
                f"or metadata at {meta_path}. "
                f"Ensure T090-Config and T091-Exec have run successfully."
            )
    
    # Load YAML manually to avoid extra dependencies if possible, 
    # but pyyaml is in requirements.
    import yaml
    with open(config_path, 'r') as f:
        config = yaml.safe_load(f)
    
    return config

def compare_coefficients(
    regression_results: Dict[str, Any], 
    ground_truth: Dict[str, Any]
) -> Dict[str, Any]:
    """
    Compare regression coefficients against injected ground truth.
    Returns a validation report.
    """
    interaction_coefficients = ground_truth.get("interaction_coefficients", {})
    random_seed = ground_truth.get("random_seed", 42)
    
    # Extract regression coefficients from the results
    # Structure of cooperative_effects_analysis.json depends on T025 implementation.
    # We assume it contains a 'coefficients' dict or list of models.
    regression_coeffs = regression_results.get("coefficients", {})
    
    # If the structure is nested (e.g., per system), we flatten or iterate.
    # For simplicity, assuming a flat dict of { "Cr_Mo": 0.05, ... }
    # If it's a list of models, we might need to aggregate or check the best one.
    # Let's assume the top-level 'coefficients' is the dictionary of interest.
    
    if not regression_coeffs:
        logger.warning("No regression coefficients found in results.")
        # If no coefficients, we cannot compare.
        return {
            "status": "incomplete",
            "message": "No regression coefficients found in T025 results.",
            "comparison": []
        }

    comparison_results = []
    total_error = 0.0
    count = 0

    for key, true_val in interaction_coefficients.items():
        if key in regression_coeffs:
            pred_val = regression_coeffs[key]
            error = abs(pred_val - true_val)
            total_error += error
            count += 1
            comparison_results.append({
                "term": key,
                "injected_value": true_val,
                "recovered_value": pred_val,
                "absolute_error": error,
                "recovered_sign": "positive" if pred_val > 0 else "negative",
                "true_sign": "positive" if true_val > 0 else "negative",
                "sign_match": (pred_val > 0) == (true_val > 0)
            })
        else:
            comparison_results.append({
                "term": key,
                "injected_value": true_val,
                "recovered_value": None,
                "absolute_error": None,
                "status": "missing_in_regression"
            })

    mean_error = total_error / count if count > 0 else float('inf')
    
    # Determine pass/fail based on a heuristic threshold (e.g., 50% error or sign mismatch)
    # Since this is pipeline validation, we check if the model recovered the *sign* and *order of magnitude*.
    sign_matches = sum(1 for r in comparison_results if r.get("sign_match") is True)
    total_compared = sum(1 for r in comparison_results if r.get("recovered_value") is not None)
    
    sign_accuracy = sign_matches / total_compared if total_compared > 0 else 0.0
    
    status = "passed" if (sign_accuracy >= 0.5 and mean_error < 0.1) else "failed"
    
    report = {
        "validation_type": "pipeline_logic_check",
        "random_seed_used": random_seed,
        "status": status,
        "mean_absolute_error": mean_error,
        "sign_accuracy": sign_accuracy,
        "details": comparison_results,
        "note": "This validation checks if the regression pipeline can recover injected synthetic parameters. It does not validate against experimental reality (SC-003)."
    }
    
    return report

def save_validation_report(report: Dict[str, Any]) -> Path:
    """
    Save the validation report to data/processed/pipeline_validation_report.json.
    """
    output_path = PROCESSED_PATH / "pipeline_validation_report.json"
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)
    logger.info(f"Saved pipeline validation report to {output_path}")
    return output_path

def main():
    """
    Main entry point for T095b.
    """
    try:
        logger.info("Starting Pipeline Validation (T095b)...")
        
        # 1. Load Regression Results (T025)
        regression_data = load_regression_results()
        
        # 2. Load Ground Truth (T091 config)
        ground_truth_data = load_ground_truth()
        
        # 3. Compare
        report = compare_coefficients(regression_data, ground_truth_data)
        
        # 4. Save Report
        output_path = save_validation_report(report)
        
        # 5. Log Summary
        logger.info(f"Validation Status: {report['status']}")
        logger.info(f"Mean Absolute Error: {report['mean_absolute_error']:.4f}")
        logger.info(f"Sign Accuracy: {report['sign_accuracy']:.2%}")
        
        if report['status'] == 'passed':
            logger.info("Pipeline logic verification PASSED: Regression model recovered injected parameters.")
        else:
            logger.warning("Pipeline logic verification FAILED: Regression model did not recover injected parameters accurately.")
        
        return 0

    except (DataLoadError, ConfigurationError, FileNotFoundError, json.JSONDecodeError) as e:
        logger.error(f"Pipeline Validation failed: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())