"""
Final Integration Test for PROJ-810-llmxive-follow-up-extending-qwen-image-v.

This script validates the entire pipeline by checking the existence of all
critical artifacts generated by previous tasks. It does not re-run the
heavy computation but verifies the outputs of the completed workflow.

Deliverable: data/results/final_report.md
"""
import os
import json
from pathlib import Path
from datetime import datetime
from typing import List, Dict, Any

# Project root relative to this file (code/integration/)
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
DATA_DIR = PROJECT_ROOT / "data"
RESULTS_DIR = DATA_DIR / "results"
MANUAL_DIR = DATA_DIR / "manual"
INTERIM_DIR = DATA_DIR / "interim"
RAW_DIR = DATA_DIR / "raw"

def check_file_exists(path: Path, description: str) -> Dict[str, Any]:
    """Check if a file exists and is not empty."""
    exists = path.exists()
    size = path.stat().st_size if exists else 0
    return {
        "path": str(path.relative_to(PROJECT_ROOT)),
        "description": description,
        "exists": exists,
        "size_bytes": size,
        "status": "PASS" if exists and size > 0 else "FAIL"
    }

def run_integration_checks() -> Dict[str, Any]:
    """Run checks for all critical artifacts."""
    checks = []
    
    # Phase 1: Setup Artifacts
    checks.append(check_file_exists(PROJECT_ROOT / "requirements.txt", "Dependencies"))
    checks.append(check_file_exists(PROJECT_ROOT / ".gitignore", "Git Ignore"))
    checks.append(check_file_exists(PROJECT_ROOT / "pyproject.toml", "Linting Config"))
    
    # Phase 2: Foundational Artifacts (Simulated/Expected)
    # Note: We check for the existence of the output files that *should* exist
    # if the previous tasks (T008-run, T009-run, etc.) were successful.
    checks.append(check_file_exists(RESULTS_DIR / "power_analysis.json", "Power Analysis Result"))
    checks.append(check_file_exists(INTERIM_DIR / "ground_truth_labels.parquet", "Ground Truth Labels"))
    checks.append(check_file_exists(INTERIM_DIR / "heuristic_labels.csv", "Heuristic Labels"))
    checks.append(check_file_exists(INTERIM_DIR / "latent_vectors_unlabeled.parquet", "Latent Vectors"))
    
    # Phase 2.5: Data Ingestion
    checks.append(check_file_exists(RAW_DIR / "omnidoc_tokenbench.parquet", "Raw Dataset"))
    checks.append(check_file_exists(INTERIM_DIR / "sample_omnidoc.parquet", "Sampled Dataset"))
    
    # Phase 3: US1 Results
    checks.append(check_file_exists(RESULTS_DIR / "permutation_test_results.json", "Permutation Test"))
    checks.append(check_file_exists(RESULTS_DIR / "pca_plot.png", "PCA Visualization"))
    
    # Phase 4: US2 Results
    checks.append(check_file_exists(RESULTS_DIR / "ssim_scores.json", "SSIM Scores"))
    checks.append(check_file_exists(RESULTS_DIR / "keypoint_scores.json", "Keypoint Scores"))
    checks.append(check_file_exists(RESULTS_DIR / "ocr_accuracy.json", "OCR Accuracy"))
    checks.append(check_file_exists(MANUAL_DIR / "verification_queue.csv", "Verification Queue (T032)"))
    
    # Phase 5: US3 Results
    checks.append(check_file_exists(RESULTS_DIR / "sensitivity_analysis.json", "Sensitivity Analysis"))
    checks.append(check_file_exists(RESULTS_DIR / "corrected_p_values.json", "Corrected P-Values"))
    
    # Phase 2: Checksums & Runtime
    checks.append(check_file_exists(RESULTS_DIR / "checksums_all.json", "Artifact Checksums"))
    checks.append(check_file_exists(RESULTS_DIR / "runtime_monitor.log", "Runtime Log"))
    
    return checks

def generate_report(checks: List[Dict[str, Any]]) -> str:
    """Generate a markdown report."""
    passed = [c for c in checks if c["status"] == "PASS"]
    failed = [c for c in checks if c["status"] == "FAIL"]
    
    report_lines = [
        "# Final Integration Test Report",
        f"**Generated**: {datetime.now().isoformat()}",
        f"**Project**: PROJ-810-llmxive-follow-up-extending-qwen-image-v",
        "",
        "## Summary",
        f"- **Total Checks**: {len(checks)}",
        f"- **Passed**: {len(passed)}",
        f"- **Failed**: {len(failed)}",
        "",
    ]
    
    if failed:
        report_lines.append("## ❌ Failed Artifacts")
        report_lines.append("| Path | Description | Size (bytes) |")
        report_lines.append("|------|-------------|--------------|")
        for f in failed:
            report_lines.append(f"| `{f['path']}` | {f['description']} | {f['size_bytes']} |")
        report_lines.append("")
    else:
        report_lines.append("## ✅ All Checks Passed")
        report_lines.append("All critical artifacts are present and non-empty.")
        report_lines.append("")
    
    report_lines.append("## Detailed Results")
    report_lines.append("| Status | Path | Description | Size (bytes) |")
    report_lines.append("|--------|------|-------------|--------------|")
    for c in checks:
        icon = "✅" if c["status"] == "PASS" else "❌"
        report_lines.append(f"| {icon} | `{c['path']}` | {c['description']} | {c['size_bytes']} |")
    
    return "\n".join(report_lines)

def main():
    """Main entry point."""
    print("Running Final Integration Test...")
    
    # Ensure results directory exists
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    
    # Run checks
    checks = run_integration_checks()
    
    # Generate report
    report_content = generate_report(checks)
    
    # Write report to disk
    report_path = RESULTS_DIR / "final_report.md"
    with open(report_path, "w", encoding="utf-8") as f:
        f.write(report_content)
    
    print(f"Report written to: {report_path}")
    
    # Exit with error code if any checks failed
    failed_count = sum(1 for c in checks if c["status"] == "FAIL")
    if failed_count > 0:
        print(f"Integration Test FAILED: {failed_count} artifacts missing.")
        return 1
    else:
        print("Integration Test PASSED.")
        return 0

if __name__ == "__main__":
    exit(main())
