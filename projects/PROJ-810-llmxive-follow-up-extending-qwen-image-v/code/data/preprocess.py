# Constants for heuristic thresholds
OCR_DENSITY_THRESHOLD = 0.005  # Minimum characters per pixel to be considered text
ASPECT_RATIO_THRESHOLD = 2.0   # Width/height ratio > 2.0 suggests horizontal text line

