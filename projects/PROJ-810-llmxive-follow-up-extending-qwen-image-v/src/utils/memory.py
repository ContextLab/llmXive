import os
import json
import torch
import numpy as np
from pathlib import Path
from typing import Dict, Any, Optional

# Constants
MAX_RUNTIME_SECONDS = 6 * 3600  # 6 hours
MAX_RAM_GB = 7.0
MAX_RAM_BYTES = MAX_RAM_GB * 1024**3

def estimate_peak_ram_usage(n_samples: int, batch_size: int = 16) -> float:
    """
    Estimate peak RAM usage for VAE encoding + OCR + Classifier.
    
    Assumes:
    - VAE model size: ~500MB (CPU-only quantized/fallback)
    - Per-sample overhead (image + latent + OCR): ~50MB
    - Classifier overhead: ~100MB
    
    Returns:
        float: Estimated peak RAM in GB.
    """
    model_overhead_gb = 0.5
    per_sample_gb = 0.05
    classifier_overhead_gb = 0.1
    
    total_gb = model_overhead_gb + (n_samples * per_sample_gb) + classifier_overhead_gb
    return total_gb

def calculate_max_samples(max_ram_gb: float = MAX_RAM_GB) -> int:
    """
    Calculate maximum number of samples that fit within RAM budget.
    
    Args:
        max_ram_gb: Maximum allowed RAM in GB.
        
    Returns:
        int: Maximum number of samples.
    """
    model_overhead_gb = 0.5
    classifier_overhead_gb = 0.1
    per_sample_gb = 0.05
    
    available_gb = max_ram_gb - model_overhead_gb - classifier_overhead_gb
    if available_gb <= 0:
        return 0
        
    return int(available_gb / per_sample_gb)

def determine_chunk_size(n_samples: int, max_ram_gb: float = MAX_RAM_GB) -> int:
    """
    Determine optimal chunk size to stay within RAM budget.
    
    Args:
        n_samples: Total number of samples to process.
        max_ram_gb: Maximum allowed RAM in GB.
        
    Returns:
        int: Chunk size.
    """
    max_samples = calculate_max_samples(max_ram_gb)
    if max_samples <= 0:
        return 1
    return min(max_samples, n_samples)

def estimate_runtime(n_samples: int, batch_size: int = 16) -> float:
    """
    Estimate runtime for processing n_samples on CPU.
    
    Assumptions (based on typical CPU performance for VAE + OCR):
    - ~2 seconds per sample (conservative CPU estimate)
    
    Args:
        n_samples: Number of samples.
        batch_size: Batch size (not used in simple linear estimate but kept for API).
        
    Returns:
        float: Estimated runtime in seconds.
    """
    seconds_per_sample = 2.0
    return n_samples * seconds_per_sample

def run_runtime_fallback_logic(
    n_required: int,
    max_runtime_seconds: int = MAX_RUNTIME_SECONDS,
    output_path: Optional[str] = None
) -> Dict[str, Any]:
    """
    Implement runtime fallback logic.
    
    If n_required exceeds estimated 6h runtime, reduce N to N_fallback
    and flag runtime_inconclusive status.
    
    Args:
        n_required: Required sample size from power analysis (T000).
        max_runtime_seconds: Maximum allowed runtime in seconds (default 6h).
        output_path: Path to write results JSON.
        
    Returns:
        Dict with N_final, estimated_runtime, status, reason.
    """
    estimated_runtime = estimate_runtime(n_required)
    
    results = {
        "N_required": n_required,
        "N_final": n_required,
        "estimated_runtime_seconds": estimated_runtime,
        "status": "PASS",
        "reason": f"N_required ({n_required}) fits within {max_runtime_seconds}s runtime budget."
    }
    
    if estimated_runtime > max_runtime_seconds:
        # Calculate fallback N that fits within budget
        seconds_per_sample = 2.0
        n_fallback = int(max_runtime_seconds / seconds_per_sample)
        
        # Ensure fallback is reasonable (at least 100 samples)
        n_fallback = max(n_fallback, 100)
        
        estimated_runtime_fallback = estimate_runtime(n_fallback)
        
        results["N_final"] = n_fallback
        results["estimated_runtime_seconds"] = estimated_runtime_fallback
        results["status"] = "INCONCLUSIVE"
        results["reason"] = (
            f"N_required ({n_required}) exceeds {max_runtime_seconds}s runtime budget. "
            f"Reduced to N_fallback ({n_fallback}) with estimated runtime "
            f"{estimated_runtime_fallback:.1f}s. Results may be inconclusive due to reduced power."
        )
    
    # Write to output file if path provided
    if output_path:
        output_file = Path(output_path)
        output_file.parent.mkdir(parents=True, exist_ok=True)
        with open(output_file, 'w') as f:
            json.dump(results, f, indent=2)
    
    return results

def main():
    """
    Main entry point for runtime fallback logic.
    
    Reads N_required from data/results/power_analysis.json (generated by T000).
    Writes results to data/results/runtime_fallback.json.
    """
    project_root = Path(__file__).resolve().parents[2]
    power_analysis_path = project_root / "data" / "results" / "power_analysis.json"
    output_path = project_root / "data" / "results" / "runtime_fallback.json"
    
    if not power_analysis_path.exists():
        raise FileNotFoundError(
            f"Required input file not found: {power_analysis_path}. "
            "Please run T000 (Power Analysis) first."
        )
    
    with open(power_analysis_path, 'r') as f:
        power_data = json.load(f)
    
    n_required = power_data.get("N_required")
    if n_required is None:
        raise ValueError(
            f"N_required not found in {power_analysis_path}. "
            "Ensure T000 output includes 'N_required'."
        )
    
    print(f"Running runtime fallback logic for N_required={n_required}...")
    results = run_runtime_fallback_logic(n_required, output_path=str(output_path))
    
    print(f"Runtime fallback status: {results['status']}")
    print(f"N_final: {results['N_final']}")
    print(f"Estimated runtime: {results['estimated_runtime_seconds']:.1f}s")
    print(f"Reason: {results['reason']}")
    
    return results

if __name__ == "__main__":
    main()
