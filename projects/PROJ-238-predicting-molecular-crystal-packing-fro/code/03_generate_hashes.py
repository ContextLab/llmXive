"""
T037 Implementation: Update artifact_hashes with final result checksums.

This script computes SHA-256 checksums for all critical output artifacts
generated by the pipeline (data/processed, results, state) and writes
them to the project state file.
"""
import hashlib
import os
import json
import logging
from pathlib import Path
from typing import List, Dict, Any, Iterable
from datetime import datetime

# Project root relative to this script (assuming script is in code/)
PROJECT_ROOT = Path(__file__).resolve().parent.parent

# Target directories to hash
TARGET_DIRS = [
    PROJECT_ROOT / "data" / "processed",
    PROJECT_ROOT / "results",
    PROJECT_ROOT / "state" / "projects" / "PROJ-238-predicting-molecular-crystal-packing-fro",
]

# Output path for the hash file
HASH_OUTPUT_PATH = PROJECT_ROOT / "state" / "projects" / "PROJ-238-predicting-molecular-crystal-packing-fro" / "artifact_hashes"

# Setup logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)


def iter_target_files() -> Iterable[Path]:
    """Iterate over all relevant files in target directories."""
    extensions_to_include = {'.csv', '.json', '.log', '.txt', '.png', '.md'}
    
    for directory in TARGET_DIRS:
        if not directory.exists():
            logger.warning(f"Directory does not exist: {directory}")
            continue
        
        for file_path in directory.rglob('*'):
            if file_path.is_file():
                # Include specific extensions or if no extension (like artifact_hashes itself, though we exclude it usually)
                if file_path.suffix in extensions_to_include or file_path.suffix == '':
                    yield file_path


def compute_sha256(file_path: Path) -> str:
    """Compute SHA-256 hash of a file."""
    sha256_hash = hashlib.sha256()
    try:
        with open(file_path, "rb") as f:
            for byte_block in iter(lambda: f.read(4096), b""):
                sha256_hash.update(byte_block)
        return sha256_hash.hexdigest()
    except Exception as e:
        logger.error(f"Error computing hash for {file_path}: {e}")
        raise


def collect_hashes() -> List[Dict[str, Any]]:
    """Collect hashes for all target files."""
    hashes = []
    for file_path in iter_target_files():
        # Skip the output file itself to avoid self-referential issues if it changes
        if file_path == HASH_OUTPUT_PATH:
            continue
        
        try:
            rel_path = file_path.relative_to(PROJECT_ROOT)
            file_hash = compute_sha256(file_path)
            hashes.append({
                "path": str(rel_path),
                "sha256": file_hash,
                "size_bytes": file_path.stat().st_size,
                "timestamp": datetime.fromtimestamp(file_path.stat().st_mtime).isoformat()
            })
            logger.info(f"Hashed: {rel_path}")
        except Exception as e:
            logger.error(f"Failed to process {file_path}: {e}")
    
    return hashes


def write_hash_file(hashes: List[Dict[str, Any]], output_path: Path) -> None:
    """Write the collected hashes to the output JSON file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    output_data = {
        "project_id": "PROJ-238-predicting-molecular-crystal-packing-fro",
        "generated_at": datetime.now().isoformat(),
        "artifact_count": len(hashes),
        "artifacts": hashes
    }
    
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(output_data, f, indent=2)
    
    logger.info(f"Hash manifest written to: {output_path}")


def main() -> None:
    """Main entry point for T037."""
    logger.info("Starting T037: Generating artifact checksums...")
    
    if not any(dir.exists() for dir in TARGET_DIRS):
        logger.error("No target directories found. Pipeline artifacts may not exist yet.")
        # We do not fail hard here if the directories don't exist, 
        # as this might be run before all steps, but we log a warning.
        # However, the task requires updating the file, so we create an empty manifest if needed.
    
    hashes = collect_hashes()
    write_hash_file(hashes, HASH_OUTPUT_PATH)
    
    logger.info("T037 completed successfully.")


if __name__ == "__main__":
    main()