import os
import pandas as pd
import logging
from pathlib import Path
from datetime import datetime
import json
from code.config import get_config, setup_logging, log_event

def setup_logger():
    """Setup logging infrastructure for the imputation and filtering task."""
    return setup_logging("02_impute_and_filter")

def load_raw_descriptors(logger: logging.Logger) -> pd.DataFrame:
    """
    Load the raw descriptors CSV generated by 01_ingest_and_descriptors.py.
    """
    config = get_config()
    input_path = Path(config.DATA_PATH) / "descriptors" / "raw_descriptors.csv"
    
    if not input_path.exists():
        logger.error(f"Input file not found: {input_path}")
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    logger.info(f"Loading raw descriptors from {input_path}")
    df = pd.read_csv(input_path)
    return df

def impute_missing_auxiliary(df: pd.DataFrame, logger: logging.Logger) -> pd.DataFrame:
    """
    Impute missing auxiliary descriptors (specifically 'Dipole') with the training-set median.
    Since we are processing the raw dataset before the split, we use the global median 
    of non-null values in the current dataset as a proxy for the training set median 
    (or we assume this runs after a split if the input was already split, but the task 
    description implies running on the raw descriptors file to flag rows).
    
    Per task: "impute auxiliary descriptors (e.g., Dipole) with the training‑set median"
    and "flag the row ... with a boolean column `dipole_imputed`".
    
    We will calculate the median of non-null 'Dipole' values in the provided dataframe 
    (assuming this represents the available data for imputation) and impute.
    """
    df = df.copy()
    aux_columns = ['Dipole'] # As per task example
    
    for col in aux_columns:
        if col not in df.columns:
            logger.warning(f"Column {col} not found in dataframe, skipping imputation.")
            continue
        
        non_null_vals = df[col].dropna()
        if len(non_null_vals) == 0:
            logger.error(f"No non-null values found for {col} to compute median.")
            raise ValueError(f"Cannot impute {col}: no non-null values available.")
        
        median_val = non_null_vals.median()
        logger.info(f"Median for {col}: {median_val}")
        
        # Identify rows that are missing
        missing_mask = df[col].isna()
        count_missing = missing_mask.sum()
        
        if count_missing > 0:
            logger.info(f"Imputing {count_missing} missing values in {col} with median {median_val}")
            df.loc[missing_mask, col] = median_val
            # Add flag column if not exists, default False
            flag_col = f"{col.lower()}_imputed"
            if flag_col not in df.columns:
                df[flag_col] = False
            df.loc[missing_mask, flag_col] = True
        else:
            # Ensure flag column exists even if no imputation happened
            flag_col = f"{col.lower()}_imputed"
            if flag_col not in df.columns:
                df[flag_col] = False
                
    return df

def filter_missing_target(df: pd.DataFrame, logger: logging.Logger) -> pd.DataFrame:
    """
    Exclude rows with missing target ('packing_coefficient') and log the count.
    """
    target_col = 'packing_coefficient'
    
    if target_col not in df.columns:
        logger.error(f"Target column '{target_col}' not found in dataframe.")
        raise ValueError(f"Target column '{target_col}' not found.")
    
    missing_target_mask = df[target_col].isna()
    count_missing = missing_target_mask.sum()
    
    if count_missing > 0:
        logger.warning(f"Found {count_missing} rows with missing target '{target_col}'. Excluding them.")
        df_clean = df[~missing_target_mask].copy()
    else:
        logger.info("No rows with missing target found.")
        df_clean = df.copy()
        
    return df_clean, count_missing

def save_outputs(df: pd.DataFrame, missing_target_count: int, logger: logging.Logger):
    """
    Save the processed dataframe and the log file for missing target count.
    """
    config = get_config()
    data_path = Path(config.DATA_PATH)
    
    # Save updated raw_descriptors.csv with imputation flags
    output_path_descriptors = data_path / "descriptors" / "raw_descriptors.csv"
    df.to_csv(output_path_descriptors, index=False)
    logger.info(f"Saved updated descriptors to {output_path_descriptors}")
    
    # Log missing target count
    log_path = data_path / "processed" / "missing_target.log"
    log_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(log_path, 'w') as f:
        f.write(f"Rows excluded due to missing target (packing_coefficient): {missing_target_count}\n")
        f.write(f"Timestamp: {datetime.now().isoformat()}\n")
    
    logger.info(f"Logged missing target count to {log_path}")

def main():
    logger = setup_logger()
    log_event("02_impute_and_filter", "start")
    
    try:
        # 1. Load data
        df = load_raw_descriptors(logger)
        original_count = len(df)
        
        # 2. Impute missing auxiliary descriptors (Dipole)
        df_imputed = impute_missing_auxiliary(df, logger)
        
        # 3. Filter out rows with missing target
        df_clean, missing_count = filter_missing_target(df_imputed, logger)
        
        # 4. Save outputs
        save_outputs(df_clean, missing_count, logger)
        
        log_event("02_impute_and_filter", "success", {
            "original_rows": original_count,
            "final_rows": len(df_clean),
            "missing_target_excluded": missing_count
        })
        
        print(f"Processing complete. Rows: {original_count} -> {len(df_clean)}. "
              f"Excluded {missing_count} due to missing target.")
              
    except Exception as e:
        log_event("02_impute_and_filter", "error", {"error": str(e)})
        logger.exception("An error occurred during processing")
        raise

if __name__ == "__main__":
    main()