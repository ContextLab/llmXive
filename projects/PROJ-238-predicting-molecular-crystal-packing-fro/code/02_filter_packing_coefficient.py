def setup_logger(name: str) -> logging.Logger:
    """Configure and return a logger for the script."""
    logger = logging.getLogger(name)
    if not logger.handlers:
        logger.setLevel(logging.INFO)
        handler = logging.StreamHandler(sys.stdout)
        formatter = logging.Formatter(
            '%(asctime)s - %(name)s - %(levelname)s - %(message)s'
        )
        handler.setFormatter(formatter)
        logger.addHandler(handler)
    return logger

def load_raw_descriptors(input_path: Path) -> pd.DataFrame:
    """
    Load the raw descriptors CSV generated by T014.
    Expected columns: ID, Volume, SurfaceArea, Dipole, HBD, HBA, PSA, packing_coefficient (optional initially)
    """
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    df = pd.read_csv(input_path)
    
    required_cols = ['ID', 'Volume', 'SurfaceArea', 'Dipole', 'HBD', 'HBA', 'PSA']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in {input_path}: {missing_cols}")
    
    return df

def derive_and_filter_packing_coefficient(df: pd.DataFrame, logger: logging.Logger) -> pd.DataFrame:
    """
    Derive packing_coefficient = V_mol / V_cell if not present, 
    then filter out physically impossible values (< 0 or > 1).
    
    Note: The task description implies V_mol is derived from descriptors (e.g., Volume)
    and V_cell is the unit cell volume. 
    However, looking at T012/T014 output expectations:
    T012 generates `data/descriptors/raw_descriptors.csv` with columns: 
    [ID, Volume, SurfaceArea, Dipole, HBD, HBA, PSA, packing_coefficient]
    
    If 'packing_coefficient' is already in the input (from T012/T014), we filter it.
    If not, we must derive it. The formula is packing_coefficient = V_mol / V_cell.
    In this pipeline context, 'Volume' from RDKit is V_mol (molecular volume).
    We need V_cell. 
    
    Re-reading T012: "calculate V_cell". 
    T014: "Implement descriptor computation for Volume...".
    
    If the input file `raw_descriptors.csv` only contains molecular descriptors (V_mol)
    and not V_cell, we cannot calculate the ratio without V_cell.
    
    However, the task T015 says: "Derive packing_coefficient = V_mol / V_cell".
    This implies V_cell must be available. 
    Looking at T012 deliverable: "Generate ... with columns [ID, Volume, ..., packing_coefficient]".
    This suggests T012 might have already calculated it or V_cell is present.
    
    Let's assume the input CSV from T014 (which T012 feeds into) contains the necessary data.
    If 'packing_coefficient' is missing, we look for 'V_cell' or similar.
    If neither exists, we cannot proceed without modifying the upstream T012/T014 logic.
    But T015 is a distinct task.
    
    Correction: The task T015 is to "Derive... and filter". 
    If the upstream script (T012/T014) didn't derive it, this script must.
    If the upstream script provided 'packing_coefficient' (as per T012 description), 
    this script filters it.
    
    Scenario A: Input has 'packing_coefficient'. -> Filter.
    Scenario B: Input has 'Volume' (V_mol) and 'V_cell'. -> Derive then Filter.
    Scenario C: Input has 'Volume' (V_mol) but no 'V_cell'. -> Cannot derive.
    
    Given T012 description says it generates 'packing_coefficient', it's likely T014 
    (which T015 follows) outputs a file with that column.
    However, T014 is marked as FAILED in the "REJECTED" list. 
    The "REJECTED" list says T014 has no code. 
    Therefore, we must assume the file `data/descriptors/raw_descriptors.csv` 
    might be missing the 'packing_coefficient' column or V_cell column if we are 
    implementing T015 now.
    
    Wait, the prompt says "Implement task T015". 
    The existing API surface shows `code/02_filter_packing_coefficient.py` exists 
    (from the "Existing project API surface" list). 
    This implies the file structure is there, but maybe the logic is incomplete or 
    the upstream data is incomplete.
    
    Let's look at the T012 description again: "Generate ... with columns ... packing_coefficient".
    If T012 is marked completed (it is in the completed list), then the file should have it.
    BUT T014 is marked FAILED/REJECTED. T014 is "Implement descriptor computation...".
    If T014 failed, maybe the 'Volume' column is missing or the file is empty?
    
    Let's assume the standard flow: 
    1. T012 downloads CIFs and calculates V_cell.
    2. T014 computes descriptors (Volume = V_mol).
    3. T015 derives ratio and filters.
    
    If T014 failed to run, we might not have 'Volume'. 
    However, the task T015 requires us to "Derive packing_coefficient".
    This implies we must have V_mol and V_cell.
    
    Assumption: The input file `data/descriptors/raw_descriptors.csv` contains:
    - ID
    - Volume (V_mol) - computed by T014 (even if marked failed, maybe partial data exists? Or we assume T014 logic is now in place via T015 implementation context?)
    - V_cell (computed by T012)
    
    If 'V_cell' is not in the CSV, we cannot do the math. 
    Let's check the T012 description: "calculate V_cell". 
    It does NOT explicitly say it saves V_cell to the CSV, only "packing_coefficient".
    If T012 saved packing_coefficient, then T015 just filters.
    
    However, the prompt says T014 is REJECTED. T014 computes Volume.
    If T014 didn't run, we don't have Volume.
    
    Let's look at the T015 requirement again: "Derive packing_coefficient = V_mol / V_cell".
    This phrasing strongly suggests the derivation happens HERE, not in T012.
    So T012 likely saved V_cell, and T014 saved Volume.
    We need to ensure both are in the input or the input has the components.
    
    Strategy:
    1. Load CSV.
    2. Check for 'packing_coefficient'. If present, use it.
    3. If not, check for 'Volume' (V_mol) and 'V_cell'.
       - If both present, calculate ratio.
       - If 'V_cell' missing, we cannot derive. Raise error.
    4. Filter rows where packing_coefficient < 0 or > 1.
    5. Log the count of excluded rows.
    
    Given the constraints and the "REJECTED" status of T014, I will assume the 
    input file might be missing 'packing_coefficient' and we need to calculate it 
    from 'Volume' and 'V_cell'. I will also assume T012 saved 'V_cell' to the CSV.
    
    If 'V_cell' is missing, I will raise a clear error rather than faking data.
    """
    
    logger.info("Starting derivation and filtering of packing_coefficient")
    
    # Check if packing_coefficient exists
    if 'packing_coefficient' not in df.columns:
        logger.info("Column 'packing_coefficient' not found. Checking for components (Volume, V_cell)...")
        if 'Volume' not in df.columns or 'V_cell' not in df.columns:
            raise ValueError(
                "Cannot derive packing_coefficient. Missing 'packing_coefficient' column "
                "and/or required components ('Volume', 'V_cell')."
            )
        
        # Handle potential division by zero or missing values
        df = df.dropna(subset=['Volume', 'V_cell'])
        df['packing_coefficient'] = df['Volume'] / df['V_cell']
        logger.info(f"Derived packing_coefficient for {len(df)} rows.")
    else:
        logger.info("Found existing 'packing_coefficient' column.")
        # Ensure it's numeric
        df['packing_coefficient'] = pd.to_numeric(df['packing_coefficient'], errors='coerce')
        # Drop rows where derivation failed (NaN)
        initial_count = len(df)
        df = df.dropna(subset=['packing_coefficient'])
        if initial_count != len(df):
            logger.warning(f"Dropped {initial_count - len(df)} rows with NaN packing_coefficient.")

    # Filter physically impossible values
    initial_count = len(df)
    mask = (df['packing_coefficient'] >= 0) & (df['packing_coefficient'] <= 1)
    filtered_df = df[mask]
    excluded_count = initial_count - len(filtered_df)
    
    logger.info(f"Filtered out {excluded_count} rows with packing_coefficient < 0 or > 1.")
    
    return filtered_df, excluded_count

def save_filter_log(output_path: Path, excluded_count: int, total_input: int):
    """Write the filter log to the specified path."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    with open(output_path, 'w') as f:
        f.write(f"Packing Coefficient Filter Log\n")
        f.write(f"Generated: {timestamp}\n")
        f.write(f"Total input rows: {total_input}\n")
        f.write(f"Excluded rows (physically impossible): {excluded_count}\n")
        f.write(f"Remaining rows: {total_input - excluded_count}\n")
        f.write(f"Criteria: 0 <= packing_coefficient <= 1\n")
    
    logging.info(f"Filter log saved to {output_path}")

def save_outputs(df: pd.DataFrame, output_path: Path, log_path: Path, excluded_count: int, total_input: int):
    """Save the filtered dataframe and the log."""
    # Save the filtered CSV
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    logging.info(f"Filtered data saved to {output_path}")
    
    # Save the log
    save_filter_log(log_path, excluded_count, total_input)

def main():
    config = get_config()
    logger = setup_logger("T015_Filter")
    
    # Define paths
    input_path = Path(config.get('DATA_PATH', 'data')) / 'descriptors' / 'raw_descriptors.csv'
    output_path = Path(config.get('DATA_PATH', 'data')) / 'descriptors' / 'raw_descriptors_filtered.csv'
    log_path = Path(config.get('DATA_PATH', 'data')) / 'processed' / 'filter_log.txt'
    
    try:
        logger.info(f"Loading data from {input_path}")
        df = load_raw_descriptors(input_path)
        
        logger.info(f"Loaded {len(df)} rows.")
        total_input = len(df)
        
        filtered_df, excluded_count = derive_and_filter_packing_coefficient(df, logger)
        
        save_outputs(filtered_df, output_path, log_path, excluded_count, total_input)
        
        logger.info("Task T015 completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()