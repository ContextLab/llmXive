"""
T015: Derive packing_coefficient and filter physically impossible values.

This script reads the raw descriptors CSV generated by the ingestion pipeline,
calculates the packing_coefficient (V_mol / V_cell), and filters out rows where
the coefficient is physically impossible (< 0 or > 1).

It also logs the number of excluded rows to data/processed/filter_log.txt.
"""
import os
import sys
import logging
import pandas as pd
from pathlib import Path
from datetime import datetime
from typing import Tuple

# Add project root to path to allow imports
PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from code.config import setup_logging, get_config

def setup_logger() -> logging.Logger:
    """Configure and return a logger for this module."""
    return setup_logging("filter_packing_coefficient")

def load_raw_descriptors(logger: logging.Logger, input_path: Path) -> pd.DataFrame:
    """Load the raw descriptors CSV."""
    if not input_path.exists():
        logger.error(f"Input file not found: {input_path}")
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    logger.info(f"Loading raw descriptors from {input_path}")
    df = pd.read_csv(input_path)
    
    required_cols = ['Volume', 'packing_coefficient']
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        logger.error(f"Missing required columns: {missing_cols}")
        raise ValueError(f"Missing required columns: {missing_cols}")
    
    return df

def derive_and_filter_packing_coefficient(
    df: pd.DataFrame, 
    logger: logging.Logger
) -> Tuple[pd.DataFrame, int]:
    """
    Derive packing_coefficient if not present (though T014 should have done it),
    and filter out values < 0 or > 1.
    
    Returns the filtered dataframe and the count of excluded rows.
    """
    # Ensure packing_coefficient exists (re-calculate if needed for safety)
    # T014 should have produced this, but we verify/calculate here if missing
    if 'packing_coefficient' not in df.columns:
        if 'Volume' in df.columns and 'V_cell' in df.columns:
            logger.warning("Re-calculating packing_coefficient from Volume and V_cell")
            df['packing_coefficient'] = df['Volume'] / df['V_cell']
        else:
            logger.error("Cannot derive packing_coefficient: missing Volume or V_cell")
            raise ValueError("Cannot derive packing_coefficient: missing required columns")

    # Convert to numeric, coercing errors to NaN
    df['packing_coefficient'] = pd.to_numeric(df['packing_coefficient'], errors='coerce')

    # Count rows before filtering
    total_rows = len(df)
    logger.info(f"Total rows before filtering: {total_rows}")

    # Filter: keep only 0 <= packing_coefficient <= 1
    # Note: We also drop NaNs implicitly by the condition
    valid_mask = (df['packing_coefficient'] >= 0) & (df['packing_coefficient'] <= 1)
    
    filtered_df = df[valid_mask].copy()
    excluded_count = total_rows - len(filtered_df)

    logger.info(f"Excluded {excluded_count} rows with physically impossible packing_coefficient (< 0 or > 1)")
    
    return filtered_df, excluded_count

def save_filter_log(excluded_count: int, log_path: Path, logger: logging.Logger):
    """Write the exclusion count to the filter log file."""
    log_path.parent.mkdir(parents=True, exist_ok=True)
    
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    log_content = f"[{timestamp}] Excluded {excluded_count} rows due to invalid packing_coefficient.\n"
    
    with open(log_path, 'w') as f:
        f.write(log_content)
    
    logger.info(f"Filter log written to {log_path}")

def save_outputs(filtered_df: pd.DataFrame, output_path: Path, logger: logging.Logger):
    """Save the filtered dataframe to CSV."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    filtered_df.to_csv(output_path, index=False)
    logger.info(f"Filtered data saved to {output_path}")

def main():
    logger = setup_logger()
    config = get_config()

    # Define paths
    # Input: generated by T012/T014
    input_file = Path("data/descriptors/raw_descriptors.csv")
    output_file = Path("data/processed/filtered_descriptors.csv")
    log_file = Path("data/processed/filter_log.txt")

    try:
        # Load data
        df = load_raw_descriptors(logger, input_file)

        # Filter
        filtered_df, excluded_count = derive_and_filter_packing_coefficient(df, logger)

        # Save outputs
        save_outputs(filtered_df, output_file, logger)
        save_filter_log(excluded_count, log_file, logger)

        logger.info("T015: Filter task completed successfully.")
        return 0

    except FileNotFoundError as e:
        logger.error(f"File error: {e}")
        return 1
    except ValueError as e:
        logger.error(f"Data error: {e}")
        return 1
    except Exception as e:
        logger.exception(f"Unexpected error: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())