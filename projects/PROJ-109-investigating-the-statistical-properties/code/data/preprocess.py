# ----------------------------------------------------------------------
# Compatibility wrapper for the integration test
# ----------------------------------------------------------------------
def run_preprocessing_pipeline(
    input_path: str = None,
    output_dir: str = None,
    schema_path: str = None,
) -> str:
    """
    Run the preprocessing pipeline with sensible defaults for the test suite.

    If ``input_path`` is not supplied, the function searches ``DATA_RAW_DIR``
    for the first ``*.h5`` file (the synthetic halo catalogue produced by the
    integration test). ``output_dir`` defaults to ``DATA_PROCESSED_DIR`` and
    ``schema_path`` defaults to ``HALO_SCHEMA_PATH``. The function loads the
    raw HDF5 file, filters halos with ``particle_count`` >= ``MIN_PARTICLES``,
    and writes the result to a timestamped Parquet file.

    Returns
    -------
    str
        The absolute path to the written Parquet file.
    """
    # Resolve defaults
    if input_path is None:
        raw_dir = Path(DATA_RAW_DIR)
        h5_files = sorted(raw_dir.glob("*.h5"))
        if not h5_files:
            raise FileNotFoundError(f"No HDF5 files found in {DATA_RAW_DIR}")
        input_path = str(h5_files[0])

    if output_dir is None:
        output_dir = DATA_PROCESSED_DIR

    if schema_path is None:
        schema_path = HALO_SCHEMA_PATH

    logger.info(f"Preprocessing raw data from {input_path}")

    # ------------------------------------------------------------------
    # Load raw data
    # ------------------------------------------------------------------
    with h5py.File(input_path, "r") as f:
        # Load every dataset into a dict; h5py returns numpy arrays.
        raw_dict: Dict[str, Any] = {key: f[key][...] for key in f.keys()}

    # Convert to pandas DataFrame
    df = pd.DataFrame(raw_dict)

    # ------------------------------------------------------------------
    # Optional schema validation (kept minimal for speed)
    # ------------------------------------------------------------------
    # The original implementation validates against a JSON/YAML schema.
    # For the integration test we only ensure required columns exist.
    required_cols = {"mass", "particle_count"}
    missing = required_cols - set(df.columns)
    if missing:
        raise ValueError(f"Missing required columns in raw data: {missing}")

    # ------------------------------------------------------------------
    # Filter halos by particle count
    # ------------------------------------------------------------------
    filtered_df = df[df["particle_count"] >= MIN_PARTICLES].copy()
    logger.info(
        f"Filtered halos: {len(df)} -> {len(filtered_df)} (min particles = {MIN_PARTICLES})"
    )

    # ------------------------------------------------------------------
    # Write Parquet output (timestamped filename)
    # ------------------------------------------------------------------
    os.makedirs(output_dir, exist_ok=True)
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    output_path = Path(output_dir) / f"filtered_halos_{timestamp}.parquet"
    filtered_df.to_parquet(output_path, index=False)
    logger.info(f"Filtered data written to {output_path}")

    return str(output_path)
