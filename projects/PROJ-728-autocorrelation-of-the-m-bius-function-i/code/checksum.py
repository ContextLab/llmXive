"""
checksum.py

Compute SHA-256 checksums for all raw data files generated by the pipeline
and write a manifest file. This script is intended to be run after
``code.generate_mobius`` has produced its outputs.

The manifest is written to ``data/checksums/manifest.sha256`` with one line
per file in the form::

    <sha256>  <relative_path>

where ``relative_path`` is the path relative to the project root (e.g.
``data/raw/mobius_array.npy``).

The script can be executed as a module::

    python -m code.checksum

or directly::

    python code/checksum.py
"""

from __future__ import annotations

import hashlib
from pathlib import Path
import sys

# ----------------------------------------------------------------------
# Configuration
# ----------------------------------------------------------------------
RAW_DATA_DIR: Path = Path("data/raw")
MANIFEST_PATH: Path = Path("data/checksums/manifest.sha256")


def _ensure_parent_dir(p: Path) -> None:
    """Create the parent directory of ``p`` if it does not exist."""
    p.parent.mkdir(parents=True, exist_ok=True)


def _sha256_of_file(file_path: Path) -> str:
    """Return the hex SHA‑256 digest of the given file."""
    h = hashlib.sha256()
    # Read in binary mode in chunks to avoid excessive memory use.
    with file_path.open("rb") as f:
        for chunk in iter(lambda: f.read(8192), b""):
            h.update(chunk)
    return h.hexdigest()


def compute_checksums() -> None:
    """
    Compute SHA‑256 checksums for every file in ``RAW_DATA_DIR`` and write
    the manifest file.
    """
    if not RAW_DATA_DIR.is_dir():
        sys.stderr.write(f"Error: raw data directory '{RAW_DATA_DIR}' does not exist.\n")
        sys.exit(1)

    # Gather all files (non‑recursive, as the current layout places raw files
    # directly under ``data/raw``). If sub‑directories appear in the future,
    # they will also be included.
    raw_files = sorted(p for p in RAW_DATA_DIR.rglob("*") if p.is_file())

    if not raw_files:
        sys.stderr.write(f"Warning: no raw data files found in '{RAW_DATA_DIR}'.\n")
        # Still create an empty manifest for completeness.
        _ensure_parent_dir(MANIFEST_PATH)
        MANIFEST_PATH.write_text("", encoding="utf-8")
        return

    lines = []
    for file_path in raw_files:
        # Compute checksum and format the line.
        checksum = _sha256_of_file(file_path)
        # Store path relative to the project root.
        rel_path = file_path.as_posix()
        lines.append(f"{checksum}  {rel_path}")

    # Write manifest.
    _ensure_parent_dir(MANIFEST_PATH)
    MANIFEST_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"SHA‑256 manifest written to {MANIFEST_PATH}")


def main() -> None:
    """Entry‑point for ``python -m code.checksum``."""
    compute_checksums()


if __name__ == "__main__":
    main()
