"""
pack.py
-------

Utility module that provides 2‑bit packing and unpacking of the Möbius
sequence. The core packing logic is implemented here to avoid any
circular dependencies on the sieve implementation. The functions
follow the encoding used in ``code.sieve``:

    -1 → 2  (binary ``10``)
     0 → 0  (binary ``00``)
     1 → 1  (binary ``01``)

Four ternary values are stored per byte:

    byte = b0 | (b1 << 2) | (b2 << 4) | (b3 << 6)

where ``b0 … b3`` are the 2‑bit codes of consecutive entries.

The module also provides a small command‑line entry point that packs the
full Möbius array (generated by ``code.sieve``) and writes the packed
``.npy`` file to ``data/raw/mobius_2bit.npy`` – this matches the artifact
expected by task **T003**.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Tuple

import numpy as np

__all__ = ["pack_mu", "unpack_mu", "main"]


# ----------------------------------------------------------------------
# Packing / unpacking helpers
# ----------------------------------------------------------------------
_ENCODE_MAP = {
    -1: 2,  # 0b10
     0: 0,  # 0b00
     1: 1,  # 0b01
}

_DECODE_MAP = {
    0: 0,
    1: 1,
    2: -1,
}


def _encode_mu(values: np.ndarray) -> np.ndarray:
    """
    Vectorised encoding of a ``int8`` Möbius array to the 2‑bit codes.

    Parameters
    ----------
    values : np.ndarray
        1‑D array of ``int8`` values in ``{-1, 0, 1}``.

    Returns
    -------
    np.ndarray
        1‑D ``uint8`` array of the same shape containing the 2‑bit codes.
    """
    # Use fancy indexing with a list‑like map for speed.
    # ``np.vectorize`` would be slower; we take advantage of the small
    # integer domain.
    # Create an array of possible inputs [-1,0,1] and map to codes.
    lookup = np.array([_ENCODE_MAP[-1], _ENCODE_MAP[0], _ENCODE_MAP[1]], dtype=np.uint8)
    # Shift values by +1 to obtain indices 0,1,2.
    indices = values.astype(np.int8) + 1
    return lookup[indices]


def pack_mu(mobius: np.ndarray) -> np.ndarray:
    """
    Pack a Möbius ``int8`` array into a compact ``uint8`` representation
    using 2‑bits per entry.

    The input may contain a dummy ``0`` at index 0 (as produced by the
    sieve). The function packs the *entire* array, padding the final
    byte with zeros if the length is not a multiple of four.

    Parameters
    ----------
    mobius : np.ndarray
        1‑D ``int8`` array containing values ``{-1, 0, 1}``.

    Returns
    -------
    np.ndarray
        1‑D ``uint8`` array where each byte stores four packed values.
    """
    if mobius.ndim != 1:
        raise ValueError("Input Möbius array must be one‑dimensional")

    # Encode to 2‑bit codes.
    codes = _encode_mu(mobius.astype(np.int8))

    # Pad to a multiple of 4.
    pad_len = (-len(codes)) % 4
    if pad_len:
        codes = np.concatenate([codes, np.zeros(pad_len, dtype=np.uint8)])

    # Reshape to (n_bytes, 4) and pack.
    reshaped = codes.reshape(-1, 4)
    packed = (
        reshaped[:, 0]
        | (reshaped[:, 1] << 2)
        | (reshaped[:, 2] << 4)
        | (reshaped[:, 3] << 6)
    ).astype(np.uint8)
    return packed


def _decode_mu(packed: np.ndarray) -> np.ndarray:
    """
    Vectorised decoding of a packed ``uint8`` array back to the 2‑bit
    codes (still in the range {0,1,2}).
    """
    # Extract the four 2‑bit fields.
    b0 = packed & 0b11
    b1 = (packed >> 2) & 0b11
    b2 = (packed >> 4) & 0b11
    b3 = (packed >> 6) & 0b11
    return np.stack([b0, b1, b2, b3], axis=1).reshape(-1)


def unpack_mu(packed: np.ndarray, original_length: int) -> np.ndarray:
    """
    Unpack a 2‑bit packed Möbius array back to the original ``int8``
    representation.

    Parameters
    ----------
    packed : np.ndarray
        1‑D ``uint8`` array produced by :func:`pack_mu`.
    original_length : int
        The length of the original Möbius array before packing.

    Returns
    -------
    np.ndarray
        1‑D ``int8`` array of length ``original_length`` containing
        ``{-1, 0, 1}``.
    """
    if packed.ndim != 1:
        raise ValueError("Packed array must be one‑dimensional")
    if original_length < 0:
        raise ValueError("original_length must be non‑negative")

    # Decode to 2‑bit codes.
    codes = _decode_mu(packed)
    # Trim to the requested length (discard padding).
    codes = codes[:original_length]

    # Map back to {-1,0,1}.
    # We can use a vectorised lookup similar to the encoding step.
    lookup = np.array([_DECODE_MAP[0], _DECODE_MAP[1], _DECODE_MAP[2]], dtype=np.int8)
    # Codes are 0,1,2 → use directly as indices.
    decoded = lookup[codes]
    return decoded


# ----------------------------------------------------------------------
# Command‑line driver
# ----------------------------------------------------------------------
def main() -> None:
    """
    Command‑line driver for the packing utility.

    It loads the raw Möbius array (``data/raw/mobius_array.npy``),
    packs it using :func:`pack_mu`, and writes the packed array to
    ``data/raw/mobius_2bit.npy``.
    """
    parser = argparse.ArgumentParser(
        description="Pack the int8 Möbius array into a 2‑bit per entry NumPy file."
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("data/raw/mobius_array.npy"),
        help="Path to the raw Möbius ``int8`` array (default: data/raw/mobius_array.npy).",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("data/raw/mobius_2bit.npy"),
        help="Destination path for the packed ``uint8`` array (default: data/raw/mobius_2bit.npy).",
    )
    args = parser.parse_args()

    if not args.input.is_file():
        raise FileNotFoundError(f"Möbius array not found at {args.input}")

    mobius = np.load(args.input, allow_pickle=False)
    packed = pack_mu(mobius)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    np.save(args.output, packed)

    print(f"Packed Möbius array written to {args.output}")


if __name__ == "__main__":
    main()
