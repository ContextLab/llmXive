"""
pack.py
-------

Utility module that provides 2‑bit packing and unpacking of the Möbius
sequence.  The core packing logic already exists in ``code.sieve``; this
module simply re‑exports those functions so that downstream code can
import them without creating a circular dependency on the sieve
implementation.

The packed representation stores four ternary values (‑1, 0, 1) per
byte using the encoding defined in ``sieve._encode_mu``:

    -1 → 2  (binary ``10``)
     0 → 0  (binary ``00``)
     1 → 1  (binary ``01``)

The layout of a packed byte is::

    byte = b0 | (b1 << 2) | (b2 << 4) | (b3 << 6)

where ``b0`` … ``b3`` are the 2‑bit codes of consecutive entries.

The module also provides a small command‑line entry point that packs the
full Möbius array (generated by ``code.sieve``) and writes the packed
``.npy`` file to ``data/raw/mobius_2bit.npy`` – this matches the
artifact expected by task **T003**.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

# The packing helpers are defined in ``code.sieve``.  Importing them
# directly avoids code duplication and guarantees that the two‑bit
# encoding stays in sync with the sieve implementation.
from sieve import pack_mu, unpack_mu  # noqa: F401  (re‑export)

__all__ = ["pack_mu", "unpack_mu", "main"]

def main() -> None:
    """
    Command‑line driver for the packing utility.

    It loads the raw Möbius array (``data/raw/mobius_array.npy``),
    packs it using :func:`pack_mu`, and writes the packed array to
    ``data/raw/mobius_2bit.npy``.  The script is deliberately tiny – it
    performs no validation beyond the existence of the input file,
    because the sieve stage already guarantees correctness.
    """
    raw_path = Path("data/raw/mobius_array.npy")
    packed_path = Path("data/raw/mobius_2bit.npy")

    if not raw_path.is_file():
        raise FileNotFoundError(f"Möbius array not found at {raw_path}")

    mobius = np.load(raw_path, allow_pickle=False)
    packed = pack_mu(mobius)

    # Ensure the output directory exists.
    packed_path.parent.mkdir(parents=True, exist_ok=True)
    np.save(packed_path, packed)

    print(f"Packed Möbius array written to {packed_path}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Pack the int8 Möbius array into a 2‑bit per entry NumPy file."
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("data/raw/mobius_array.npy"),
        help="Path to the raw Möbius ``int8`` array (default: data/raw/mobius_array.npy).",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("data/raw/mobius_2bit.npy"),
        help="Destination path for the packed ``uint8`` array (default: data/raw/mobius_2bit.npy).",
    )
    args = parser.parse_args()

    if not args.input.is_file():
        raise FileNotFoundError(f"Möbius array not found at {args.input}")

    mobius = np.load(args.input, allow_pickle=False)
    packed = pack_mu(mobius)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    np.save(args.output, packed)

    print(f"Packed Möbius array written to {args.output}")
