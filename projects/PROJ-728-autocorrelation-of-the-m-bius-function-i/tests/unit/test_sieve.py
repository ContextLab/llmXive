"""
Unit tests for the Möbius sieve implementation.

These tests verify that the linear-time sieve correctly computes the
Möbius function values for a few well‑known arguments:
    μ(1) =  1
    μ(2) = -1
    μ(4) =  0
    μ(30) = -1
    μ(3025) = 0
The test also checks that the returned NumPy array has the expected
``int8`` dtype and that the dummy element at index 0 is zero.
Finally, it asserts that every entry of the array lies in the set
{‑1, 0, 1} and that the 2‑bit packing round‑trips exactly.

Additional checks verify that the SHA‑256 checksum for the packed
Möbius file is recorded in ``data/checksums/manifest.sha256``.
"""

import pathlib
import hashlib
import numpy as np
import pytest

# The sieve implementation lives in ``code/sieve.py`` and exposes
# ``compute_mobius``, ``pack_mu`` and ``unpack_mu`` as public functions.
from code.sieve import compute_mobius, pack_mu, unpack_mu

@pytest.fixture(scope="module")
def mobius_array():
    """
    Compute the Möbius array for a small N (≥ 3025) once per test session.
    Using N=5000 ensures that the values μ(30) and μ(3025) are covered
    while keeping execution fast.
    """
    N = 5000
    return compute_mobius(N)

def test_array_shape_and_dtype(mobius_array):
    """The array should have length N+1 and dtype int8."""
    assert isinstance(mobius_array, np.ndarray)
    # Length should be N+1 (including dummy index 0)
    assert mobius_array.shape == (5001,)
    assert mobius_array.dtype == np.int8

def test_dummy_zero_at_index_zero(mobius_array):
    """Index 0 is unused in the mathematical definition and must be 0."""
    assert mobius_array[0] == 0

@pytest.mark.parametrize(
    "n,expected",
    [
        (1, 1),      # μ(1) = 1
        (2, -1),     # μ(2) = -1 (prime)
        (4, 0),      # μ(4) = 0 (square factor)
        (30, -1),    # μ(30) = -1 (product of three distinct primes)
        (3025, 0),   # μ(3025) = 0 (contains square factor 5^2)
    ],
)
def test_known_mobius_values(mobius_array, n, expected):
    """Check that known values of the Möbius function are correct."""
    assert int(mobius_array[n]) == expected

def test_all_entries_within_ternary_set(mobius_array):
    """Every entry must be -1, 0, or 1."""
    unique_vals = set(np.unique(mobius_array))
    assert unique_vals.issubset({-1, 0, 1}), f"Unexpected values: {unique_vals}"

# ----------------------------------------------------------------------
# Packing round‑trip tests
# ----------------------------------------------------------------------
@pytest.fixture(scope="module")
def raw_mobius_path():
    """Path to the full‑size raw Möbius array generated by the pipeline."""
    return pathlib.Path("data/raw/mobius_array.npy")

@pytest.fixture(scope="module")
def packed_mobius_path():
    """Path to the 2‑bit packed Möbius array."""
    return pathlib.Path("data/raw/mobius_2bit.npy")

def test_pack_unpack_full_array(raw_mobius_path, packed_mobius_path):
    """Packing then unpacking the full array must reproduce the original."""
    raw = np.load(raw_mobius_path, allow_pickle=False)
    packed = np.load(packed_mobius_path, allow_pickle=False)

    # Verify that the packing size is as expected (≈ ceil(N/4) bytes)
    expected_len = (raw.size + 3) // 4
    assert packed.size == expected_len

    # Round‑trip
    unpacked = unpack_mu(packed, original_length=raw.size)
    np.testing.assert_array_equal(unpacked, raw)

def test_pack_unpack_random_slices(raw_mobius_path, packed_mobius_path):
    """Random slices of the packed representation must also round‑trip."""
    raw = np.load(raw_mobius_path, allow_pickle=False)
    packed = np.load(packed_mobius_path, allow_pickle=False)

    rng = np.random.default_rng(20231017)
    for _ in range(10):
        start = rng.integers(0, raw.size - 1)
        length = rng.integers(1, min(1000, raw.size - start))
        slice_raw = raw[start : start + length]

        # Pack the slice by extracting the relevant bits from the full packed array
        # Re‑pack the slice directly using the public API for simplicity.
        packed_slice = pack_mu(slice_raw)
        unpacked_slice = unpack_mu(packed_slice, original_length=length)

        np.testing.assert_array_equal(unpacked_slice, slice_raw)

# ----------------------------------------------------------------------
# Checksum verification
# ----------------------------------------------------------------------
def test_checksum_manifest_contains_packed_file(packed_mobius_path):
    """
    The SHA‑256 checksum of the packed file must be recorded in
    ``data/checksums/manifest.sha256``.
    """
    manifest_path = pathlib.Path("data/checksums/manifest.sha256")
    assert manifest_path.is_file(), "Checksum manifest does not exist."

    # Compute the SHA‑256 of the packed file
    sha256 = hashlib.sha256()
    with packed_mobius_path.open("rb") as f:
        for chunk in iter(lambda: f.read(8192), b""):
            sha256.update(chunk)
    computed_digest = sha256.hexdigest()

    # Look for a line ending with the relative path of the packed file
    expected_suffix = f" {packed_mobius_path.as_posix()}"
    matching_lines = [
        line for line in manifest_path.read_text().splitlines()
        if line.endswith(expected_suffix)
    ]
    assert matching_lines, f"No checksum entry for {packed_mobius_path}"
    # Verify that the recorded digest matches the computed one
    recorded_digest = matching_lines[0].split()[0]
    assert recorded_digest == computed_digest, (
        f"Checksum mismatch for {packed_mobius_path}: "
        f"recorded {recorded_digest}, computed {computed_digest}"
    )
