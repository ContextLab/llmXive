"""
Unit tests for the 2‑bit packing utilities (code.pack).

The tests verify that a round‑trip through ``pack_mu`` and
``unpack_mu`` reproduces the original Möbius array, both for the full
dataset and for a collection of random slices.
"""

import json
from pathlib import Path

import numpy as np
import pytest

from code.pack import pack_mu, unpack_mu

# Path helpers.
MOBIUS_RAW_PATH = Path("data/raw/mobius_array.npy")
PACKED_PATH = Path("data/raw/mobius_2bit.npy")
CHECKSUM_MANIFEST = Path("data/checksums/manifest.sha256")


@pytest.fixture(scope="module")
def mobius_array() -> np.ndarray:
    """Load the full Möbius array generated by the sieve."""
    if not MOBIUS_RAW_PATH.is_file():
        raise FileNotFoundError(f"Missing Möbius array at {MOBIUS_RAW_PATH}")
    return np.load(MOBIUS_RAW_PATH, allow_pickle=False)


def test_round_trip_full(mobius_array: np.ndarray) -> None:
    """Packing and then unpacking the entire array must be lossless."""
    packed = pack_mu(mobius_array)
    # Write the packed file so that the checksum test can see it.
    PACKED_PATH.parent.mkdir(parents=True, exist_ok=True)
    np.save(PACKED_PATH, packed)

    unpacked = unpack_mu(packed, original_length=len(mobius_array))
    assert np.array_equal(unpacked, mobius_array), "Full round‑trip failed"


def test_random_slices(mobius_array: np.ndarray) -> None:
    """Check 100 random sub‑slices of the packed representation."""
    rng = np.random.default_rng(20231017)
    for _ in range(100):
        start = rng.integers(0, len(mobius_array) - 10)
        length = rng.integers(5, 100)  # reasonable slice length
        slice_original = mobius_array[start : start + length]

        # Pack the *entire* array, then unpack only the slice we care about.
        packed = pack_mu(mobius_array)
        slice_unpacked = unpack_mu(packed, original_length=len(mobius_array))[start : start + length]

        assert np.array_equal(slice_original, slice_unpacked), (
            f"Slice round‑trip failed for start={start}, length={length}"
        )


def test_manifest_contains_hashes() -> None:
    """Both the raw and packed files must be listed in ``manifest.sha256``."""
    if not CHECKSUM_MANIFEST.is_file():
        raise FileNotFoundError("Checksum manifest missing")
    with CHECKSUM_MANIFEST.open("r", encoding="utf-8") as f:
        manifest = f.read()
    assert "data/raw/mobius_array.npy" in manifest, "Raw Möbius file missing from manifest"
    assert "data/raw/mobius_2bit.npy" in manifest, "Packed Möbius file missing from manifest"