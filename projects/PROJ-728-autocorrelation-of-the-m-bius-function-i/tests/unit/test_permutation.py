"""
Unit tests for the block‑permutation generator.

These tests verify two essential properties required by the specification:

1. **Count preservation** – each generated permutation must contain the same
   number of ``-1``, ``0`` and ``+1`` values as the original window.
2. **Block shuffling only** – the permutation must be a re‑ordering of the
   *blocks* of the original window; the internal order of each block must
   remain unchanged.

The tests load the real Möbius array generated by the pipeline
(``data/raw/mobius_array.npy``) and use a modest window (``L = 1000``) to
keep execution fast while still exercising the block logic.
"""

import pathlib

import numpy as np
import pytest

# Import the public API from the project's permutation module.
from permutation import generate_permutations, _load_mobius_array

# Helper to split a window into blocks of a given size (mirrors the
# implementation in ``code/permutation.py``).
def _split_into_blocks(arr: np.ndarray, block_size: int) -> list[np.ndarray]:
    """Return a list of contiguous blocks from ``arr`` of size ``block_size``."""
    blocks = []
    for i in range(0, len(arr), block_size):
        blocks.append(arr[i : i + block_size])
    return blocks

@pytest.fixture(scope="module")
def mobius_array():
    """Load the real Möbius array from disk."""
    path = pathlib.Path("data/raw/mobius_array.npy")
    return _load_mobius_array(path)

@pytest.fixture(scope="module")
def sample_window(mobius_array):
    """
    Choose a deterministic window for testing.

    The ``window_starts.json`` file already contains a start index for
    ``L = 1000``; we use the first entry to keep the test reproducible.
    """
    starts_path = pathlib.Path("data/raw/window_starts.json")
    with starts_path.open() as f:
        import json

        starts = json.load(f)
    L = 1000
    start = starts[str(L)][0]  # first start for L=1000
    # Validate the window fits inside the Möbius array.
    assert start >= 1
    assert start + L <= mobius_array.shape[0] - 1
    return start, L

def test_permutations_preserve_counts(mobius_array, sample_window):
    """Each permutation must have the same counts of -1, 0, +1 as the original."""
    start, L = sample_window
    block_size = 100
    n_permutations = 10
    seed = 12345

    perms = generate_permutations(
        mobius=mobius_array,
        start=start,
        L=L,
        block_size=block_size,
        n_permutations=n_permutations,
        seed=seed,
    )
    assert perms.shape == (n_permutations, L)

    # Original window counts.
    original_window = mobius_array[start : start + L]
    original_counts = {
        -1: int(np.sum(original_window == -1)),
        0: int(np.sum(original_window == 0)),
        1: int(np.sum(original_window == 1)),
    }

    for idx in range(n_permutations):
        perm = perms[idx]
        perm_counts = {
            -1: int(np.sum(perm == -1)),
            0: int(np.sum(perm == 0)),
            1: int(np.sum(perm == 1)),
        }
        assert perm_counts == original_counts, f"Counts differ in permutation {idx}"

def test_permutations_shuffle_blocks_only(mobius_array, sample_window):
    """
    Permutations must be a re‑ordering of the original blocks; each block's
    internal ordering must stay exactly the same.
    """
    start, L = sample_window
    block_size = 100
    n_permutations = 10
    seed = 98765

    perms = generate_permutations(
        mobius=mobius_array,
        start=start,
        L=L,
        block_size=block_size,
        n_permutations=n_permutations,
        seed=seed,
    )

    original_window = mobius_array[start : start + L]
    original_blocks = _split_into_blocks(original_window, block_size)
    # Represent each block as a bytes object for easy comparison.
    original_block_keys = [blk.tobytes() for blk in original_blocks]

    for idx in range(n_permutations):
        perm = perms[idx]
        perm_blocks = _split_into_blocks(perm, block_size)
        perm_block_keys = [blk.tobytes() for blk in perm_blocks]

        # The multiset of block keys must be identical.
        assert sorted(perm_block_keys) == sorted(original_block_keys), (
            f"Permutation {idx} does not contain the same set of blocks as the original"
        )

        # Additionally, ensure that within each block the order is unchanged.
        # Since the multiset check already guarantees each block appears exactly
        # once, we only need to verify that any block in the permutation matches
        # an original block *as‑is*.
        for p_key, p_block in zip(perm_block_keys, perm_blocks):
            # Find the corresponding original block.
            assert p_key in original_block_keys, (
                f"Block in permutation {idx} was altered internally"
            )
            # No further check needed – the bytes equality guarantees unchanged order.