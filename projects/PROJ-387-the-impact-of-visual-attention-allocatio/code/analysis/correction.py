import os
import sys
import json
import argparse
from pathlib import Path
from typing import List, Dict, Any, Optional

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from utils.logger import get_logger
from utils.config import get_output_path

logger = get_logger(__name__)

def load_lmm_results(input_path: Optional[str] = None) -> List[Dict[str, Any]]:
    """
    Loads LMM summary results from the CSV generated by lmm_model.py.
    Expects columns: metric, valence, coef, p_raw.
    """
    if input_path is None:
        input_path = str(get_output_path() / "results" / "lmm_summary.csv")
    
    path = Path(input_path)
    if not path.exists():
        logger.error(f"LMM summary file not found: {path}")
        raise FileNotFoundError(f"LMM summary file not found: {path}")
    
    try:
        import pandas as pd
        df = pd.read_csv(path)
        required_cols = ['metric', 'valence', 'coef', 'p_raw']
        missing = [c for c in required_cols if c not in df.columns]
        if missing:
            raise ValueError(f"LMM summary missing required columns: {missing}")
        
        results = df.to_dict(orient='records')
        logger.info(f"Loaded {len(results)} LMM results from {path}")
        return results
    except Exception as e:
        logger.error(f"Failed to load LMM results: {e}")
        raise

def apply_bonferroni_correction(results: List[Dict[str, Any]], alpha: float = 0.05) -> List[Dict[str, Any]]:
    """
    Applies Bonferroni correction to the p-values in the results.
    The task specifies 9 metric-category combinations.
    Returns a new list of dictionaries with 'p_corrected' and 'is_significant' added.
    """
    if not results:
        logger.warning("No results to correct.")
        return []

    n_tests = len(results)
    if n_tests == 0:
        logger.warning("No tests found to apply correction.")
        return results

    corrected_results = []
    for item in results:
        new_item = item.copy()
        p_raw = item.get('p_raw')
        if p_raw is None:
            logger.warning(f"Missing p_raw in result: {item}")
            new_item['p_corrected'] = 1.0
            new_item['is_significant'] = False
        else:
            p_corrected = min(p_raw * n_tests, 1.0)
            new_item['p_corrected'] = p_corrected
            new_item['is_significant'] = p_corrected < alpha
            # Ensure associational labeling is present as per FR-005
            new_item['association_label'] = 'associational'
        
        corrected_results.append(new_item)
        logger.debug(f"Corrected p-value for {item.get('metric')}-{item.get('valence')}: "
                     f"{p_raw:.4f} -> {p_corrected:.4f} (Sig: {new_item['is_significant']})")

    logger.info(f"Applied Bonferroni correction for {n_tests} tests (alpha={alpha}).")
    return corrected_results

def save_results(results: List[Dict[str, Any]], output_path: Optional[str] = None) -> str:
    """
    Saves the corrected results to a JSON file.
    """
    if output_path is None:
        output_path = str(get_output_path() / "results" / "correction_results.json")
    
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    
    try:
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(results, f, indent=2)
        logger.info(f"Saved corrected results to {path}")
        return str(path)
    except Exception as e:
        logger.error(f"Failed to save results: {e}")
        raise

def main():
    """
    Main entry point for the correction task.
    Loads LMM results, applies Bonferroni correction, and saves the output.
    """
    parser = argparse.ArgumentParser(description="Apply Bonferroni correction to LMM results.")
    parser.add_argument("--input", type=str, default=None, help="Path to lmm_summary.csv")
    parser.add_argument("--output", type=str, default=None, help="Path to output JSON")
    parser.add_argument("--alpha", type=float, default=0.05, help="Significance threshold")
    args = parser.parse_args()

    try:
        # 1. Load LMM results
        logger.info("Starting Bonferroni correction process.")
        lmm_data = load_lmm_results(args.input)
        
        if not lmm_data:
            logger.error("No data loaded from LMM summary. Cannot proceed.")
            sys.exit(1)

        # 2. Apply Correction
        corrected_data = apply_bonferroni_correction(lmm_data, alpha=args.alpha)

        # 3. Save Results
        output_file = save_results(corrected_data, args.output)

        logger.info("Correction process completed successfully.")
        sys.exit(0)

    except FileNotFoundError as e:
        logger.error(f"Data file error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during correction: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()