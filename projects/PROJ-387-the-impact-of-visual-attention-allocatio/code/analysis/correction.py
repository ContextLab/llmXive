import os
import sys
import json
import argparse
from pathlib import Path
from typing import List, Dict, Any, Optional

# Add project root to path for imports
project_root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(project_root))

from utils.logger import get_logger
from utils.config import get_output_path

logger = get_logger(__name__)

def load_lmm_results() -> List[Dict[str, Any]]:
    """
    Loads the LMM summary results from the CSV generated by T020/T021.
    Expects 'output/results/lmm_summary.csv'.
    """
    output_path = get_output_path()
    csv_path = output_path / "results" / "lmm_summary.csv"
    
    if not csv_path.exists():
        logger.error(f"LMM results file not found at {csv_path}. "
                     "Please ensure T020/T021 have been run successfully.")
        raise FileNotFoundError(f"Missing LMM results: {csv_path}")

    import pandas as pd
    df = pd.read_csv(csv_path)
    
    # Convert to list of dicts for processing
    results = df.to_dict(orient='records')
    logger.info(f"Loaded {len(results)} LMM results for correction.")
    return results

def apply_bonferroni_correction(results: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Applies Bonferroni correction to the p-values in the LMM results.
    
    The task specifies 9 metric-category combinations.
    Correction factor = 9.
    
    Args:
        results: List of dicts containing 'p_raw' and other metadata.
        
    Returns:
        List of dicts with added 'p_corrected' and 'association_label'.
    """
    if not results:
        logger.warning("No results to correct.")
        return []

    # FR-004: Bonferroni correction across all 9 metric-category combinations
    n_comparisons = 9
    alpha = 0.05
    
    corrected_results = []
    
    for row in results:
        p_raw = float(row.get('p_raw', 1.0))
        
        # Bonferroni: p_corrected = p_raw * n
        p_corrected = min(p_raw * n_comparisons, 1.0)
        
        corrected_row = row.copy()
        corrected_row['p_corrected'] = p_corrected
        corrected_row['n_comparisons'] = n_comparisons
        corrected_row['alpha_threshold'] = alpha
        
        # FR-005: Explicit associational labeling
        corrected_row['association_label'] = "associational"
        
        corrected_results.append(corrected_row)
        logger.debug(f"Corrected p-value for {row.get('metric')}:{row.get('valence')} "
                     f"from {p_raw:.4f} to {p_corrected:.4f}")
    
    return corrected_results

def save_results(corrected_results: List[Dict[str, Any]]) -> str:
    """
    Saves the corrected results to a JSON file.
    
    Deliverable: output/results/correction_results.json
    """
    output_path = get_output_path()
    results_dir = output_path / "results"
    results_dir.mkdir(parents=True, exist_ok=True)
    
    output_file = results_dir / "correction_results.json"
    
    with open(output_file, 'w') as f:
        json.dump(corrected_results, f, indent=2)
    
    logger.info(f"Saved corrected results to {output_file}")
    return str(output_file)

def main():
    """
    Main entry point for the correction task (T022).
    """
    parser = argparse.ArgumentParser(description="Apply Bonferroni correction to LMM results.")
    parser.add_argument('--input', type=str, help="Path to LMM results CSV (optional, defaults to output/results/lmm_summary.csv)")
    args = parser.parse_args()

    try:
        # 1. Load LMM results
        logger.info("Starting Bonferroni correction process...")
        lmm_results = load_lmm_results()
        
        # 2. Apply correction
        corrected_results = apply_bonferroni_correction(lmm_results)
        
        # 3. Save results
        output_file = save_results(corrected_results)
        
        logger.info(f"Correction complete. Output written to {output_file}")
        return 0
        
    except FileNotFoundError as e:
        logger.error(str(e))
        return 1
    except Exception as e:
        logger.error(f"An error occurred during correction: {str(e)}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())
