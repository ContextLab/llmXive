def load_lmm_summary_csv(csv_path: Path) -> List[Dict[str, Any]]:
    """
    Load the LMM summary CSV generated by T020.
    Returns a list of dictionaries representing the rows.
    """
    results = []
    if not csv_path.exists():
        logger.error(f"LMM Summary CSV not found at {csv_path}")
        return results

    with open(csv_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Convert numeric strings to floats where appropriate
            cleaned_row = {}
            for k, v in row.items():
                if k in ['coef', 'p_raw']:
                    try:
                        cleaned_row[k] = float(v)
                    except ValueError:
                        cleaned_row[k] = v
                else:
                    cleaned_row[k] = v
            results.append(cleaned_row)
    
    logger.info(f"Loaded {len(results)} rows from LMM summary CSV.")
    return results

def load_correction_results_json(json_path: Path) -> List[Dict[str, Any]]:
    """
    Load the Bonferroni correction results JSON generated by T022.
    """
    if not json_path.exists():
        logger.error(f"Correction results JSON not found at {json_path}")
        return []
    
    with open(json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # The structure is expected to be a list of results or a dict containing a list
    if isinstance(data, list):
        return data
    elif isinstance(data, dict) and 'results' in data:
        return data['results']
    else:
        logger.warning(f"Unexpected structure in correction results: {type(data)}")
        return []

def generate_report_content(
    lmm_results: List[Dict[str, Any]],
    correction_results: List[Dict[str, Any]],
    output_path: Path
) -> str:
    """
    Compiles the LMM coefficients, corrected p-values, and associational disclaimer
    into a Markdown report string.
    
    FR-005: Explicit "associational" labeling to prohibit causal language.
    """
    report_lines = []
    
    # Header
    report_lines.append("# Final Analysis Report: Visual Attention & Recall")
    report_lines.append("")
    report_lines.append("## Disclaimer: Associational Findings Only")
    report_lines.append("")
    report_lines.append("> **IMPORTANT**: The results presented in this report are **associational** in nature.")
    report_lines.append("> This analysis identifies statistical relationships between visual attention metrics")
    report_lines.append("> and recall accuracy. **No causal claims** can be inferred from these results.")
    report_lines.append("> Per project constitution, all interpretations must remain within the bounds of")
    report_lines.append("> observed associations.")
    report_lines.append("")
    
    # Methodology Summary
    report_lines.append("## Methodology")
    report_lines.append("- **Model**: Linear Mixed-Effects Models (LMM)")
    report_lines.append("- **Correction**: Bonferroni correction applied across all metric-category combinations.")
    report_lines.append("- **Data Source**: Validated eye-tracking and recall datasets.")
    report_lines.append("")
    
    # Results Table
    report_lines.append("## Statistical Results")
    report_lines.append("")
    report_lines.append("The table below summarizes the fixed effects coefficients and p-values.")
    report_lines.append("")
    report_lines("| Metric | Valence | Coefficient (β) | Raw P-value | Corrected P-value | Significant? |")
    report_lines.append("| :--- | :--- | :--- | :--- | :--- | :--- |")
    
    # Merge LMM results with correction results for the table
    # We expect correction_results to have matching keys (metric, valence) or an index alignment
    # Assuming correction_results is a list of dicts with 'metric', 'valence', 'p_corrected'
    
    # Create a lookup for correction results
    correction_lookup = {}
    for corr in correction_results:
        key = (corr.get('metric'), corr.get('valence'))
        correction_lookup[key] = corr.get('p_corrected', 'N/A')
    
    significant_count = 0
    total_count = 0
    
    for row in lmm_results:
        metric = row.get('metric', 'Unknown')
        valence = row.get('valence', 'Unknown')
        coef = row.get('coef', 0.0)
        p_raw = row.get('p_raw', 1.0)
        
        p_corrected = correction_lookup.get((metric, valence), 'N/A')
        
        # Determine significance (alpha = 0.05)
        is_sig = "No"
        if p_corrected != 'N/A':
            try:
                if float(p_corrected) < 0.05:
                    is_sig = "Yes"
                    significant_count += 1
            except (ValueError, TypeError):
                pass
        
        if p_corrected != 'N/A':
            total_count += 1
        
        # Format numbers
        coef_str = f"{coef:.4f}"
        p_raw_str = f"{p_raw:.4f}" if isinstance(p_raw, float) else str(p_raw)
        p_corr_str = f"{float(p_corrected):.4f}" if isinstance(p_corrected, float) else str(p_corrected)
        
        report_lines.append(f"| {metric} | {valence} | {coef_str} | {p_raw_str} | {p_corr_str} | {is_sig} |")
    
    report_lines.append("")
    
    # Summary Statistics
    report_lines.append("## Summary")
    report_lines.append(f"- **Total Combinations Tested**: {total_count}")
    report_lines.append(f"- **Significant Associations Found**: {significant_count}")
    report_lines.append("")
    
    # Footer
    report_lines.append("---")
    report_lines.append("*Report generated automatically by the llmXive pipeline.*")
    
    return "\n".join(report_lines)

def main():
    """
    Main entry point for T043.
    Generates output/results/final_report.md
    """
    parser = argparse.ArgumentParser(description="Generate final analysis report.")
    parser.add_argument("--output-dir", type=str, default=None, help="Override output directory")
    args = parser.parse_args()

    project_root = get_project_root()
    output_base = Path(args.output_dir) if args.output_dir else get_output_path(project_root)
    results_dir = output_base / "results"
    
    # Ensure output directory exists
    ensure_directory(results_dir)
    
    # Define input paths based on previous tasks (T020, T022)
    lmm_csv_path = results_dir / "lmm_summary.csv"
    correction_json_path = results_dir / "correction_results.json"
    final_report_path = results_dir / "final_report.md"
    
    logger.info(f"Starting report generation. Output: {final_report_path}")
    
    # Load data
    lmm_results = load_lmm_summary_csv(lmm_csv_path)
    correction_results = load_correction_results_json(correction_json_path)
    
    if not lmm_results:
        logger.error("No LMM results found. Cannot generate report.")
        sys.exit(1)
    
    if not correction_results:
        logger.error("No correction results found. Cannot generate report.")
        sys.exit(1)
    
    # Generate content
    report_content = generate_report_content(lmm_results, correction_results, final_report_path)
    
    # Write to file
    with open(final_report_path, 'w', encoding='utf-8') as f:
        f.write(report_content)
    
    logger.info(f"Report successfully generated at {final_report_path}")
    return 0

if __name__ == "__main__":
    sys.exit(main())