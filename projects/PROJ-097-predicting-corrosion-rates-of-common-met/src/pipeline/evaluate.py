"""Evaluation module for interaction‑gain significance (T007).

This script builds on the existing training routine but adds a
paired target‑permutation test that quantifies the performance gain
contributed by the engineered interaction features.

The workflow is:

1. Load the cleaned dataset and the 5‑fold GroupKFold split indices.
2. Train a **Full** model (with interaction columns) and a **Null**
   model (same algorithm/hyper‑parameters, interaction columns removed)
   on each fold and record the validation RMSE for both.
3. Compute the observed statistic
   ``ΔRMSE_obs = mean(RMSE_null – RMSE_full)`` (positive values indicate
   that interactions improve the model).
4. Generate a null distribution by permuting the target variable
   ``corrosion_rate`` *across the whole dataset* for a configurable
   number of permutations (default 200 to stay within CI time limits).
   For each permutation the same training procedure is repeated and
   the mean ΔRMSE is recorded.
5. Compute a two‑sided empirical p‑value as the proportion of
   permuted ΔRMSE values that are **greater than or equal to**
   ``ΔRMSE_obs``.
6. Write the results (observed ΔRMSE, observed ΔR², p‑value and a
   pass/fail flag) to ``data/results/interaction_gain_permutation_test.json``.
7. Preserve the original ``first_run_metrics.json`` output for backward
   compatibility.

The implementation avoids any synthetic data: it operates on the real
dataset produced by ``src.pipeline.ingest`` and respects the
hyper‑parameter choices recorded in ``model_artifact.yaml`` (or falls
back to a reasonable default if that file is missing).  All file
paths are obtained via ``llmxive_toolkit.paths`` which guarantees they
reside inside the project directory.
"""

from __future__ import annotations

import json
import logging
import pickle
import random
from pathlib import Path
from typing import List, Tuple

import numpy as np
import pandas as pd
from sklearn.ensemble import GradientBoostingRegressor, RandomForestRegressor
from sklearn.metrics import mean_squared_error, r2_score
from sklearn.utils import shuffle

from llmxive_toolkit import paths, get_logger

log = get_logger(__name__)

# ----------------------------------------------------------------------
# Helper utilities
# ----------------------------------------------------------------------
def _load_splits() -> List[Tuple[List[int], List[int]]]:
    """Load the 5‑fold split indices generated by ``src.pipeline.split``."""
    splits_path = paths.data("processed", "splits.pkl")
    if not splits_path.is_file():
        raise RuntimeError(f"Splits file not found at {splits_path}")
    with open(splits_path, "rb") as fh:
        splits = pickle.load(fh)
    return splits

def _identify_interaction_columns(df: pd.DataFrame) -> List[str]:
    """Return a list of engineered interaction columns (contain ``_x_``)."""
    return [c for c in df.columns if "_x_" in c]

def _select_features(
    df: pd.DataFrame, include_interactions: bool
) -> Tuple[pd.DataFrame, pd.Series]:
    """Separate predictors and target, optionally dropping interaction columns."""
    target = df["corrosion_rate"]
    if include_interactions:
        X = df.drop(columns=["corrosion_rate", "source_id"])
    else:
        # Remove any column that contains the interaction marker.
        cols_to_drop = [c for c in df.columns if "_x_" in c]
        X = df.drop(columns=["corrosion_rate", "source_id"] + cols_to_drop)
    return X, target

def _train_model(
    X_train: pd.DataFrame,
    y_train: pd.Series,
    X_val: pd.DataFrame,
    y_val: pd.Series,
    model_cls,
    params: dict,
) -> Tuple[float, float]:
    """Train ``model_cls`` with ``params`` and return (RMSE, R²) on validation set."""
    model = model_cls(**params)
    model.fit(X_train, y_train)
    preds = model.predict(X_val)
    rmse = mean_squared_error(y_val, preds, squared=False)
    r2 = r2_score(y_val, preds)
    return rmse, r2

def _load_best_hyperparameters() -> dict:
    """Extract the hyper‑parameters of the best model from ``model_artifact.yaml``.

    The artifact file is written by ``src.pipeline.train`` and contains a
    ``best_model`` entry with the algorithm name and the hyper‑parameters
    used.  If the file cannot be read we fall back to a sensible default:
    RandomForestRegressor with ``max_depth=5`` and ``n_estimators=100``.
    """
    artifact_path = paths.results("model_artifact.yaml")
    default = {
        "algorithm": "RandomForestRegressor",
        "params": {"max_depth": 5, "n_estimators": 100, "random_state": 42},
    }
    if not artifact_path.is_file():
        log.warning(
            "Model artifact not found at %s – using default hyper‑parameters.",
            artifact_path,
        )
        return default

    try:
        with open(artifact_path, "r", encoding="utf-8") as fh:
            meta = yaml.safe_load(fh)
    except Exception as exc:  # pragma: no cover
        log.warning("Failed to read model artifact (%s); %s", artifact_path, exc)
        return default

    # Expected structure (from the training script) – adapt if necessary.
    best = meta.get("best_model", {})
    algorithm = best.get("algorithm", "RandomForestRegressor")
    params = best.get("hyperparameters", {})
    if not params:
        # Older schema may store under a different key.
        params = best.get("params", {})
    # Ensure deterministic behaviour.
    params.setdefault("random_state", 42)

    # Map string name to actual class.
    cls_map = {
        "RandomForestRegressor": RandomForestRegressor,
        "GradientBoostingRegressor": GradientBoostingRegressor,
    }
    model_cls = cls_map.get(algorithm, RandomForestRegressor)

    return {"algorithm": algorithm, "model_cls": model_cls, "params": params}

# ----------------------------------------------------------------------
# Main permutation‑test routine
# ----------------------------------------------------------------------
def _run_permutation_test(
    df: pd.DataFrame,
    splits: List[Tuple[List[int], List[int]]],
    n_permutations: int = 200,
) -> dict:
    """Execute the paired target‑permutation test.

    Returns a dictionary that will be serialised to JSON.
    """
    # Load hyper‑parameters.
    hp = _load_best_hyperparameters()
    model_cls = hp["model_cls"]
    params = hp["params"]

    # ------------------------------------------------------------------
    # 1. Observed statistic (no shuffling)
    # ------------------------------------------------------------------
    rmse_full_folds: List[float] = []
    rmse_null_folds: List[float] = []
    r2_full_folds: List[float] = []
    r2_null_folds: List[float] = []

    for train_idx, val_idx in splits:
        train_df = df.iloc[train_idx]
        val_df = df.iloc[val_idx]

        X_train_full, y_train = _select_features(train_df, include_interactions=True)
        X_val_full, y_val = _select_features(val_df, include_interactions=True)

        X_train_null, _ = _select_features(train_df, include_interactions=False)
        X_val_null, _ = _select_features(val_df, include_interactions=False)

        # Full model
        rmse_f, r2_f = _train_model(
            X_train_full, y_train, X_val_full, y_val, model_cls, params
        )
        # Null model
        rmse_n, r2_n = _train_model(
            X_train_null, y_train, X_val_null, y_val, model_cls, params
        )

        rmse_full_folds.append(rmse_f)
        rmse_null_folds.append(rmse_n)
        r2_full_folds.append(r2_f)
        r2_null_folds.append(r2_n)

    delta_rmse_obs = float(np.mean(np.array(rmse_null_folds) - np.array(rmse_full_folds)))
    delta_r2_obs = float(np.mean(np.array(r2_full_folds) - np.array(r2_null_folds)))

    # ------------------------------------------------------------------
    # 2. Null distribution via target permutation
    # ------------------------------------------------------------------
    permuted_deltas: List[float] = []

    # Use a fixed random seed for reproducibility.
    rng = np.random.default_rng(42)

    for perm in range(n_permutations):
        # Shuffle the target column across the whole dataset.
        shuffled_target = shuffle(df["corrosion_rate"].values, random_state=rng.integers(0, 2**31 - 1))
        df_permuted = df.copy()
        df_permuted["corrosion_rate"] = shuffled_target

        # Compute ΔRMSE for this permutation (averaged across folds).
        perm_rmse_full: List[float] = []
        perm_rmse_null: List[float] = []

        for train_idx, val_idx in splits:
            train_df = df_permuted.iloc[train_idx]
            val_df = df_permuted.iloc[val_idx]

            X_train_full, y_train = _select_features(train_df, include_interactions=True)
            X_val_full, y_val = _select_features(val_df, include_interactions=True)

            X_train_null, _ = _select_features(train_df, include_interactions=False)
            X_val_null, _ = _select_features(val_df, include_interactions=False)

            rmse_f, _ = _train_model(
                X_train_full, y_train, X_val_full, y_val, model_cls, params
            )
            rmse_n, _ = _train_model(
                X_train_null, y_train, X_val_null, y_val, model_cls, params
            )
            perm_rmse_full.append(rmse_f)
            perm_rmse_null.append(rmse_n)

        delta_perm = np.mean(np.array(perm_rmse_null) - np.array(perm_rmse_full))
        permuted_deltas.append(float(delta_perm))

    # ------------------------------------------------------------------
    # 3. Empirical p‑value (two‑sided)
    # ------------------------------------------------------------------
    # Because the statistic is defined as (Null – Full), larger positive
    # values indicate a stronger interaction gain.  We therefore compute
    # the proportion of permuted values that are **greater than or equal**
    # to the observed value.
    greater_equal = sum(1 for v in permuted_deltas if v >= delta_rmse_obs)
    p_value = greater_equal / n_permutations

    result = {
        "observed_delta_rmse": delta_rmse_obs,
        "observed_delta_r2": delta_r2_obs,
        "permutations": n_permutations,
        "p_value": p_value,
        "alpha": 0.05,
        "significant": p_value <= 0.05,
    }
    return result

# ----------------------------------------------------------------------
# Entry point
# ----------------------------------------------------------------------
def main(argv: List[str] | None = None) -> int:
    """Run the interaction‑gain permutation test and write results."""
    # Load the cleaned dataset.
    cleaned_path = paths.data("processed", "cleaned_dataset.csv")
    if not cleaned_path.is_file():
        log.error("Cleaned dataset not found at %s", cleaned_path)
        return 1
    df = pd.read_csv(cleaned_path)

    # Load the pre‑computed splits.
    try:
        splits = _load_splits()
    except Exception as exc:
        log.error("Failed to load splits: %s", exc)
        return 1

    # Run the test.
    try:
        result = _run_permutation_test(df, splits, n_permutations=200)
    except Exception as exc:  # pragma: no cover
        log.exception("Permutation test failed: %s", exc)
        return 1

    # Write the JSON artefact.
    out_path = paths.results("interaction_gain_permutation_test.json")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        json.dump(result, fh, indent=2, sort_keys=True)

    log.info(
        "Interaction‑gain permutation test written to %s (p=%.4f, significant=%s)",
        out_path,
        result["p_value"],
        result["significant"],
    )

    # Preserve the original behaviour of writing first_run_metrics.json
    # (the training step already creates this file, but we keep the call
    # for backward compatibility).
    from .train import train_and_evaluate

    metrics = train_and_evaluate()
    metrics_path = paths.results("first_run_metrics.json")
    metrics_path.parent.mkdir(parents=True, exist_ok=True)
    with open(metrics_path, "w", encoding="utf-8") as fh:
        json.dump(metrics, fh, indent=2, sort_keys=True)

    return 0

if __name__ == "__main__":
    raise SystemExit(main())