"""
T027b: Halt Check Implementation

Reads data/results/power_analysis.json generated by T027.
Logic:
1. If is_sufficient is False AND the cause is missing cognitive data (N < 85),
   log a warning and exit with code 0 (proceed with EEG-only).
2. If is_sufficient is False due to other reasons (e.g., total N < 15),
   log an error and exit with code 1 (halt pipeline).
3. If is_sufficient is True, exit with code 0.
"""
import json
import logging
import sys
from pathlib import Path
from config import ensure_dirs

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def load_power_analysis(path: Path) -> dict:
    """Load the power analysis JSON file."""
    if not path.exists():
        raise FileNotFoundError(f"Power analysis file not found: {path}")
    
    with open(path, 'r') as f:
        return json.load(f)

def check_halt_conditions(power_data: dict) -> int:
    """
    Evaluate power analysis results and determine exit code.
    
    Returns:
        0: Success (proceed) or Warning (proceed with EEG-only)
        1: Failure (halt pipeline)
    """
    is_sufficient = power_data.get('is_sufficient', False)
    mdes = power_data.get('mdes', 0.0)
    power_for_r03 = power_data.get('power_for_r03', 0.0)
    
    # Check if the study is underpowered
    if not is_sufficient:
        # Determine the cause based on available metadata
        # We assume the power analysis script populates a 'reason' or similar field
        # If not explicitly present, we infer from the MDES and sample size context
        
        # The task description specifies:
        # "If is_sufficient == false AND the cause is missing cognitive data (N < 85)"
        # We check for a 'reason' field or infer from the context of the power analysis.
        # Since T027 generates this file, we expect it to contain context about N.
        
        # Let's assume the power_analysis.json contains a 'sample_size' or 'n_total' 
        # and 'n_cognitive' to distinguish the cause.
        n_total = power_data.get('n_total', 0)
        n_cognitive = power_data.get('n_cognitive', 0)
        reason = power_data.get('reason', '')
        
        # Heuristic for "Missing Cognitive Data" cause:
        # If n_cognitive is significantly lower than n_total, or explicitly stated.
        # Or if the reason string contains "cognitive".
        is_missing_cognitive = (
            'cognitive' in reason.lower() or 
            (n_cognitive < 85 and n_total >= 15) # Assuming total N is okay but cognitive is low
        )
        
        # Heuristic for "Other Reasons" (e.g., N < 15 total):
        is_low_total_n = n_total < 15

        if is_missing_cognitive:
            logger.warning(
                "Study underpowered for cognitive analysis; proceeding with EEG-only analysis. "
                f"(Power for r=0.3: {power_for_r03:.2f}, MDES: {mdes:.2f}, N_cognitive: {n_cognitive})"
            )
            return 0 # Proceed with EEG-only
        
        elif is_low_total_n:
            logger.error(
                f"Study underpowered due to insufficient total sample size (N={n_total} < 15). "
                "Halting pipeline."
            )
            return 1 # Halt pipeline
        
        else:
            # Generic underpowered case (e.g., effect size too small, N between 15 and 85 but cognitive missing logic failed)
            # The task says: "If underpowered due to other reasons (e.g., N < 15 total), exit with code 1"
            # We treat any other underpowered case as a halt to be safe, unless we have a specific "proceed" flag.
            logger.error(
                f"Study underpowered (Power: {power_for_r03:.2f}, MDES: {mdes:.2f}). "
                "Reason: {reason}. Halting pipeline."
            )
            return 1

    else:
        logger.info(
            f"Power analysis sufficient. "
            f"Power for r=0.3: {power_for_r03:.2f}, MDES: {mdes:.2f}"
        )
        return 0

def main():
    """Main entry point for T027b."""
    config_root = Path(__file__).resolve().parent.parent.parent
    power_analysis_path = config_root / "data" / "results" / "power_analysis.json"
    
    try:
        power_data = load_power_analysis(power_analysis_path)
        exit_code = check_halt_conditions(power_data)
        sys.exit(exit_code)
    
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in power analysis file: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during halt check: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()