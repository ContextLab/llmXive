"""
T032: Create regression_summary.json with power warnings for age groups.

Reads the regression results generated by code/stats/regression.py,
counts participants in the 'Older' age group (Age >= 65), and generates
a summary JSON file. If the count of older participants is less than 15,
it appends 'Low Power for Older Group' to the warnings array.
"""
import json
import logging
import sys
from pathlib import Path
from typing import List, Dict, Any

# Add project root to path if running as script
if __name__ == "__main__":
    project_root = Path(__file__).resolve().parent.parent.parent
    if str(project_root) not in sys.path:
        sys.path.insert(0, str(project_root))

from config import ensure_dirs, get_config_summary
from stats.regression import load_metrics_and_demographics

logger = logging.getLogger(__name__)
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')

# Constants
OLD_AGE_THRESHOLD = 65
MIN_OLD_AGE_COUNT = 15
OUTPUT_FILE = Path("data/results/regression_summary.json")
INPUT_FILE = Path("data/results/regression_results.csv")

def load_regression_results(input_path: Path) -> List[Dict[str, Any]]:
    """Load regression results from CSV."""
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    import pandas as pd
    df = pd.read_csv(input_path)
    return df.to_dict(orient='records')

def analyze_age_groups(records: List[Dict[str, Any]]) -> Dict[str, int]:
    """Count participants in Young (<65) and Older (>=65) groups."""
    young_count = 0
    older_count = 0
    
    for record in records:
        age = record.get('age')
        if age is None:
            continue
        
        try:
            age_val = float(age)
            if age_val >= OLD_AGE_THRESHOLD:
                older_count += 1
            else:
                young_count += 1
        except (ValueError, TypeError):
            logger.warning(f"Invalid age value found: {age}, skipping record.")
            continue
    
    return {
        "young_count": young_count,
        "older_count": older_count,
        "total_count": len(records)
    }

def generate_summary(age_counts: Dict[str, int]) -> Dict[str, Any]:
    """Generate the summary JSON structure with warnings."""
    warnings: List[str] = []
    
    older_count = age_counts.get("older_count", 0)
    
    if older_count < MIN_OLD_AGE_COUNT:
        warnings.append("Low Power for Older Group")
        logger.warning(f"Older group count ({older_count}) is below threshold ({MIN_OLD_AGE_COUNT}). Warning added.")
    
    summary = {
        "warnings": warnings,
        "age_group_counts": age_counts,
        "threshold_old_age": OLD_AGE_THRESHOLD,
        "min_required_old_count": MIN_OLD_AGE_COUNT
    }
    
    return summary

def main():
    """Main entry point for T032."""
    logger.info("Starting regression summary generation (T032)...")
    
    # Ensure output directory exists
    ensure_dirs()
    
    try:
        # Load results
        logger.info(f"Loading regression results from {INPUT_FILE}...")
        records = load_regression_results(INPUT_FILE)
        
        if not records:
            logger.warning("No records found in regression results. Generating empty summary.")
            summary = generate_summary({"young_count": 0, "older_count": 0, "total_count": 0})
        else:
            # Analyze age distribution
            age_counts = analyze_age_groups(records)
            logger.info(f"Age distribution: Young={age_counts['young_count']}, Older={age_counts['older_count']}")
            
            # Generate summary
            summary = generate_summary(age_counts)
    
        # Write output
        OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
        with open(OUTPUT_FILE, 'w', encoding='utf-8') as f:
            json.dump(summary, f, indent=2)
        
        logger.info(f"Successfully wrote summary to {OUTPUT_FILE}")
        print(f"Summary generated: {OUTPUT_FILE}")
        
    except FileNotFoundError as e:
        logger.error(f"Input file missing: {e}")
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()
