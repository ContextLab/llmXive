def load_f1_scores_from_config(config_path: Optional[str] = None) -> Dict[str, Any]:
    """
    Loads F1 scores and p-values from the evaluation pipeline outputs.
    These are expected to be generated by code/evaluation.py (T034a, T035).
    We assume the evaluation pipeline writes intermediate results or we
    re-run the necessary logic if not present. For this task, we assume
    the evaluation.py main() has been run and produced results in memory
    or we need to aggregate them.
    
    Since T034a and T035 are completed, we expect the evaluation pipeline
    to have produced the necessary metrics. We will re-run the sensitivity
    analysis and combine results.
    """
    root = get_project_root()
    processed_dir = root / "data" / "processed"
    
    # Check if evaluation results exist
    eval_results_path = processed_dir / "evaluation_results.json"
    
    if eval_results_path.exists():
        return read_json(str(eval_results_path))
    else:
        # If not present, we assume the evaluation pipeline needs to be run.
        # However, T034a and T035 are marked completed, so we assume the data
        # exists in the expected format or we can reconstruct it.
        # For this implementation, we will assume the evaluation.py main()
        # produced a file with the necessary data. If not, we raise an error.
        raise FileNotFoundError(
            f"Evaluation results not found at {eval_results_path}. "
            "Please ensure T034a and T035 have been executed successfully."
        )


def run_sensitivity_analysis_wrapper() -> pd.DataFrame:
    """
    Wrapper to run the sensitivity analysis and return the results as a DataFrame.
    This corresponds to T037.
    """
    root = get_project_root()
    processed_dir = root / "data" / "processed"
    
    # Run sensitivity analysis
    # The sensitivity_analysis.py module should handle the analysis and
    # write results to a file. We then read it back.
    # For this task, we assume the main() of sensitivity_analysis.py
    # has been run and produced a file.
    
    sensitivity_path = processed_dir / "sensitivity_analysis.csv"
    
    if sensitivity_path.exists():
        return read_csv(str(sensitivity_path))
    else:
        # Re-run the sensitivity analysis if not present
        from code.sensitivity_analysis import main as sensitivity_main
        sensitivity_main()
        return read_csv(str(sensitivity_path))


def generate_final_metrics_report(
    f1_scores: Dict[str, Any],
    sensitivity_results: pd.DataFrame
) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """
    Combines F1 scores, p-values, and sensitivity analysis results into a final
    report. Returns a DataFrame for metrics.csv and a dictionary for the report.
    """
    # Prepare metrics DataFrame
    metrics_data = []
    
    # Extract F1 scores and p-values
    # Assuming f1_scores has structure like:
    # {
    #     "detector_f1": [f1_seed1, f1_seed2, ...],
    #     "baseline_f1": [f1_seed1, f1_seed2, ...],
    #     "wilcoxon_p_value": p_val,
    #     "wilcoxon_statistic": stat,
    #     "f1_std_dev": std_dev,
    #     "sc_003_passed": True/False
    # }
    
    detector_f1 = f1_scores.get("detector_f1", [])
    baseline_f1 = f1_scores.get("baseline_f1", [])
    p_value = f1_scores.get("wilcoxon_p_value", None)
    statistic = f1_scores.get("wilcoxon_statistic", None)
    f1_std_dev = f1_scores.get("f1_std_dev", None)
    sc_003_passed = f1_scores.get("sc_003_passed", None)
    
    # Add aggregated metrics
    metrics_data.append({
        "metric_name": "detector_mean_f1",
        "value": np.mean(detector_f1) if detector_f1 else None,
        "std_dev": np.std(detector_f1) if detector_f1 else None,
        "description": "Mean F1 score of the detector across seeds"
    })
    
    metrics_data.append({
        "metric_name": "baseline_mean_f1",
        "value": np.mean(baseline_f1) if baseline_f1 else None,
        "std_dev": np.std(baseline_f1) if baseline_f1 else None,
        "description": "Mean F1 score of the stratified random baseline across seeds"
    })
    
    metrics_data.append({
        "metric_name": "wilcoxon_p_value",
        "value": p_value,
        "std_dev": None,
        "description": "P-value from Wilcoxon signed-rank test comparing detector vs baseline"
    })
    
    metrics_data.append({
        "metric_name": "wilcoxon_statistic",
        "value": statistic,
        "std_dev": None,
        "description": "Test statistic from Wilcoxon signed-rank test"
    })
    
    metrics_data.append({
        "metric_name": "f1_std_dev",
        "value": f1_std_dev,
        "std_dev": None,
        "description": "Standard deviation of F1 scores across rubric types"
    })
    
    metrics_data.append({
        "metric_name": "sc_003_passed",
        "value": 1 if sc_003_passed else 0,
        "std_dev": None,
        "description": "Boolean indicator if SC-003 (F1 std dev <= 0.15) passed"
    })
    
    # Add sensitivity analysis results
    for _, row in sensitivity_results.iterrows():
        metrics_data.append({
            "metric_name": f"sensitivity_threshold_{row['threshold']}",
            "value": row.get("f1_score", None),
            "std_dev": row.get("f1_std_dev", None),
            "description": f"F1 score at ground truth drop threshold {row['threshold']}"
        })
    
    metrics_df = pd.DataFrame(metrics_data)
    
    # Prepare report dictionary
    report = {
        "summary": {
            "detector_mean_f1": np.mean(detector_f1) if detector_f1 else None,
            "baseline_mean_f1": np.mean(baseline_f1) if baseline_f1 else None,
            "improvement": (np.mean(detector_f1) - np.mean(baseline_f1)) if (detector_f1 and baseline_f1) else None,
            "wilcoxon_p_value": p_value,
            "wilcoxon_statistic": statistic,
            "statistically_significant": p_value < 0.05 if p_value is not None else None,
            "f1_std_dev": f1_std_dev,
            "sc_003_passed": sc_003_passed
        },
        "sensitivity_analysis": sensitivity_results.to_dict(orient="records"),
        "notes": [
            "This report aggregates results from T034a (Wilcoxon test), T035 (SC-003 check), and T037 (Sensitivity analysis).",
            "Statistical significance is determined by p-value < 0.05.",
            "SC-003 is passed if F1 std dev <= 0.15."
        ]
    }
    
    return metrics_df, report


def main():
    """
    Main function for T038: Generate final metrics.csv and evaluation report.
    """
    root = get_project_root()
    processed_dir = root / "data" / "processed"
    
    # Ensure output directory exists
    processed_dir.mkdir(parents=True, exist_ok=True)
    
    # Load evaluation results (from T034a, T035)
    try:
        f1_scores = load_f1_scores_from_config()
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        sys.exit(1)
    
    # Run sensitivity analysis (T037) if not already done
    try:
        sensitivity_results = run_sensitivity_analysis_wrapper()
    except Exception as e:
        print(f"ERROR: Sensitivity analysis failed: {e}")
        sys.exit(1)
    
    # Generate final report
    metrics_df, report = generate_final_metrics_report(f1_scores, sensitivity_results)
    
    # Write metrics.csv
    metrics_path = processed_dir / "metrics.csv"
    write_csv(str(metrics_path), metrics_df)
    print(f"Written metrics to {metrics_path}")
    
    # Write evaluation report
    report_path = processed_dir / "evaluation_report.json"
    write_json(str(report_path), report)
    print(f"Written evaluation report to {report_path}")
    
    # Print summary
    print("\n=== Evaluation Report Summary ===")
    print(f"Detector Mean F1: {report['summary']['detector_mean_f1']:.4f}")
    print(f"Baseline Mean F1: {report['summary']['baseline_mean_f1']:.4f}")
    print(f"Improvement: {report['summary']['improvement']:.4f}")
    print(f"Wilcoxon P-Value: {report['summary']['wilcoxon_p_value']}")
    print(f"Statistically Significant: {report['summary']['statistically_significant']}")
    print(f"F1 Std Dev: {report['summary']['f1_std_dev']}")
    print(f"SC-003 Passed: {report['summary']['sc_003_passed']}")
    
    return 0


if __name__ == "__main__":
    sys.exit(main())