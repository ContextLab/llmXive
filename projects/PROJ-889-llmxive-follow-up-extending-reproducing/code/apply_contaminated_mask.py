"""
Apply the contaminated window mask to the divergence data.

This script reads the divergence data (from T016/T025b) which should already
contain the `is_contaminated` boolean column. It validates that the column
exists and is correctly populated, then prepares the DataFrame for the
baseline calculation in T022.

The preparation involves ensuring the data is sorted and the mask is ready
to be used by the detector to skip contaminated indices when calculating
the baseline noise floor.
"""
import os
import sys
from pathlib import Path
from typing import Optional
import pandas as pd
import numpy as np

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from code.config import get_project_root
from code.utils.io_utils import ensure_dir, write_csv, read_csv

def load_divergence_data() -> pd.DataFrame:
    """
    Load the divergence data generated by T016/T025b.
    
    Returns:
        pd.DataFrame: The trajectory data with G(t), dG(t), and is_contaminated columns.
        
    Raises:
        FileNotFoundError: If the input file does not exist.
        ValueError: If the required columns are missing.
    """
    root = get_project_root()
    input_path = root / "data" / "processed" / "trajectories_divergence.csv"
    
    if not input_path.exists():
        raise FileNotFoundError(
            f"Input file not found: {input_path}. "
            "Ensure T016 (aggregation) and T025b (mask generation) have completed successfully."
        )
    
    df = read_csv(input_path)
    
    required_cols = ['seed_id', 'bias_type', 'timestep', 'G_t', 'is_contaminated']
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(
            f"Input file missing required columns: {missing_cols}. "
            "T025b must run before T025c to generate the 'is_contaminated' column."
        )
        
    return df

def apply_contaminated_mask(df: pd.DataFrame) -> pd.DataFrame:
    """
    Apply the contaminated mask to prepare the DataFrame for baseline calculation.
    
    This function validates the mask integrity and ensures the data is sorted
    by seed and timestep, which is required for the sliding window calculations
    in T022. It effectively "applies" the mask by ensuring the `is_contaminated`
    column is ready to be used by the detector logic to exclude contaminated
    windows from the baseline noise floor calculation.
    
    Logic:
    1. Verify `is_contaminated` column is boolean.
    2. Sort data by seed_id and timestep to ensure chronological order.
    3. (Optional) Log statistics about contaminated vs clean timesteps.
    
    Args:
        df (pd.DataFrame): The input divergence data.
        
    Returns:
        pd.DataFrame: The prepared DataFrame ready for T022.
    """
    if df.empty:
        return df

    # Ensure boolean type
    if df['is_contaminated'].dtype != bool:
        df['is_contaminated'] = df['is_contaminated'].astype(bool)
    
    # Sort by seed_id and timestep to ensure correct order for sliding window
    # This is critical for T022's baseline calculation (preceding 100 timesteps)
    if 'seed_id' in df.columns and 'timestep' in df.columns:
        df = df.sort_values(by=['seed_id', 'timestep']).reset_index(drop=True)
    
    # Validate mask consistency: ensure no NaNs in the mask
    if df['is_contaminated'].isna().any():
        raise ValueError("NaN values found in 'is_contaminated' column. "
                         "T025b must ensure all values are True/False.")
    
    # Log statistics
    total_rows = len(df)
    contaminated_rows = df['is_contaminated'].sum()
    clean_rows = total_rows - contaminated_rows
    
    print(f"Mask Application Statistics:")
    print(f"  Total timesteps: {total_rows}")
    print(f"  Contaminated timesteps: {contaminated_rows} ({100*contaminated_rows/total_rows:.2f}%)")
    print(f"  Clean timesteps: {clean_rows} ({100*clean_rows/total_rows:.2f}%)")
    
    # The mask is now ready. The actual "skipping" of these indices happens in T022
    # when calculating the baseline standard deviation.
    return df

def main():
    """Main entry point for T025c."""
    try:
        print("Starting T025c: Apply Contaminated Mask to Baseline Calculation...")
        
        # Load data
        df = load_divergence_data()
        
        # Apply/Validate mask
        df_prepared = apply_contaminated_mask(df)
        
        # Save the prepared data back (overwriting to ensure it's ready for T022)
        # T022 will read this file.
        root = get_project_root()
        output_path = root / "data" / "processed" / "trajectories_divergence.csv"
        
        ensure_dir(output_path.parent)
        write_csv(df_prepared, output_path)
        
        print(f"Successfully applied mask. Data saved to: {output_path}")
        print("T025c Complete. Ready for T022 (Detector Baseline Calculation).")
        
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        sys.exit(2) # Data missing
    except ValueError as e:
        print(f"ERROR: Data validation failed - {e}")
        sys.exit(1)
    except Exception as e:
        print(f"ERROR: Unexpected failure - {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()