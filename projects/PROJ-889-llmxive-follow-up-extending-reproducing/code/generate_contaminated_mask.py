"""
Generate the `is_contaminated` boolean mask column.

This script reads the contaminated segments identified by T025a
(from `data/processed/contaminated_segments.csv`) and the main
divergence data (from `data/processed/trajectories_divergence.csv`).
It generates a boolean column `is_contaminated` in the divergence data
where True indicates the timestep belongs to a contaminated segment.
"""
import os
import sys
from pathlib import Path
from typing import List, Tuple, Optional

import pandas as pd
import numpy as np

# Import project root and config helpers
from code.config import get_project_root
from code.utils.io_utils import ensure_dir, read_csv, write_csv

def load_contaminated_segments(file_path: Path) -> List[Tuple[int, int, str, str]]:
    """
    Load contaminated segments from the CSV generated by T025a.

    Expected columns: seed_id, bias_type, start_timestep, end_timestep
    Returns a list of tuples: (seed_id, bias_type, start, end)
    """
    if not file_path.exists():
        raise FileNotFoundError(
            f"Contaminated segments file not found: {file_path}. "
            "Run T025a (identify_contaminated_windows) first."
        )

    df = pd.read_csv(file_path)
    required_cols = {'seed_id', 'bias_type', 'start_timestep', 'end_timestep'}
    if not required_cols.issubset(df.columns):
        raise ValueError(
            f"Missing required columns in {file_path}. "
            f"Expected: {required_cols}, Found: {df.columns.tolist()}"
        )

    segments = []
    for _, row in df.iterrows():
        segments.append((
            row['seed_id'],
            row['bias_type'],
            int(row['start_timestep']),
            int(row['end_timestep'])
        ))
    return segments

def generate_is_contaminated_mask(
    divergence_df: pd.DataFrame,
    segments: List[Tuple[int, int, int, int]]
) -> pd.DataFrame:
    """
    Generate the `is_contaminated` boolean mask.

    Args:
        divergence_df: The main trajectory divergence DataFrame.
                       Must contain columns: seed_id, bias_type, timestep.
        segments: List of (seed_id, bias_type, start_timestep, end_timestep).

    Returns:
        The input DataFrame with a new boolean column 'is_contaminated'.
    """
    # Initialize the mask column as False
    divergence_df['is_contaminated'] = False

    # Group segments by (seed_id, bias_type) for efficient lookup
    # We assume the divergence_df is also grouped similarly or we iterate
    # For large datasets, a merge/interval join would be more efficient,
    # but for this specific task, we iterate segments and filter the DF.

    # Convert to numpy arrays for faster boolean indexing if possible
    # But since we need to match seed_id and bias_type strings, we'll do group-wise logic.

    # Create a copy of the index to avoid SettingWithCopyWarning if we were modifying a slice
    # We are modifying the passed dataframe directly which is fine here.

    for seed_id, bias_type, start_ts, end_ts in segments:
        # Create a boolean mask for the specific seed and bias type
        mask = (
            (divergence_df['seed_id'] == seed_id) &
            (divergence_df['bias_type'] == bias_type) &
            (divergence_df['timestep'] >= start_ts) &
            (divergence_df['timestep'] <= end_ts)
        )
        # Set the contaminated flag to True for these rows
        divergence_df.loc[mask, 'is_contaminated'] = True

    return divergence_df

def main():
    """
    Main entry point for generating the contaminated mask.
    """
    project_root = get_project_root()
    input_divergence_path = project_root / "data" / "processed" / "trajectories_divergence.csv"
    input_segments_path = project_root / "data" / "processed" / "contaminated_segments.csv"
    output_path = project_root / "data" / "processed" / "trajectories_divergence_with_mask.csv"

    print(f"Loading divergence data from: {input_divergence_path}")
    if not input_divergence_path.exists():
        print(f"ERROR: Input file not found: {input_divergence_path}")
        print("Please ensure T016 (aggregate_trajectories.py) has run successfully.")
        sys.exit(1)

    print(f"Loading contaminated segments from: {input_segments_path}")
    if not input_segments_path.exists():
        print(f"ERROR: Segments file not found: {input_segments_path}")
        print("Please ensure T025a (identify_contaminated_windows.py) has run successfully.")
        sys.exit(1)

    try:
        # Load data
        divergence_df = pd.read_csv(input_divergence_path)
        segments = load_contaminated_segments(input_segments_path)

        if len(segments) == 0:
            print("WARNING: No contaminated segments found. All rows will be False.")
        
        # Generate mask
        print(f"Generating mask for {len(segments)} contaminated segments...")
        result_df = generate_is_contaminated_mask(divergence_df, segments)

        # Ensure output directory exists
        ensure_dir(output_path.parent)

        # Save result
        print(f"Saving result to: {output_path}")
        result_df.to_csv(output_path, index=False)

        # Verification
        contaminated_count = result_df['is_contaminated'].sum()
        total_count = len(result_df)
        print(f"Success. Mask generated.")
        print(f"  Total rows: {total_count}")
        print(f"  Contaminated rows: {contaminated_count}")
        print(f"  Contamination rate: {(contaminated_count/total_count)*100:.2f}%")

    except Exception as e:
        print(f"ERROR: Failed to generate mask: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)

if __name__ == "__main__":
    main()