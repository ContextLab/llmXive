# Core functionality
# ----------------------------------------------------------------------


def load_divergence_data(path: Optional[str] = None) -> pd.DataFrame:
    """
    Load the aggregated divergence data.

    The default location is::

        <project_root>/data/processed/trajectories_divergence.csv

    Parameters
    ----------
    path: Optional[str]
        Override path to the CSV file (mainly for testing).

    Returns
    -------
    pd.DataFrame
    """
    root = get_project_root()
    default_path = root / "data" / "processed" / "trajectories_divergence.csv"
    csv_path = Path(path) if path is not None else default_path

    if not csv_path.exists():
        raise FileNotFoundError(
            f"Required divergence file not found: {csv_path}. "
            "Ensure the ingestion pipeline (T015/T016) has completed."
        )

    df = load_csv(str(csv_path))

    # Basic validation – these columns are produced by the ingestion step.
    required = ["seed_id", "bias_type", "timestep", "G_t", "hacked_label"]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(
            f"Input divergence data is missing required columns: {missing}"
        )
    return df


def generate_is_contaminated_mask(df: pd.DataFrame) -> pd.DataFrame:
    """
    Generate the ``is_contaminated`` boolean column according to FR‑009.

    The algorithm works per ``seed_id``/``bias_type`` group to avoid
    cross‑seed leakage.

    Steps
    -----
    1. Compute the MAD of ``G_t`` for the group.
    2. Flag *event* timesteps where ``G_t > 3 * MAD``.
    3. Identify contiguous segments where the ground‑truth label
       ``hacked_label`` is True.
    4. For each such segment, if its length exceeds the sliding‑window
       size ``W`` (taken from :class:`DataConfig`), mark **all**
       timesteps in that segment as contaminated.
    5. All other timesteps receive ``False``.

    Parameters
    ----------
    df: pd.DataFrame
        DataFrame produced by the ingestion pipeline, containing at
        minimum the columns ``seed_id``, ``bias_type``, ``G_t`` and
        ``hacked_label``.

    Returns
    -------
    pd.DataFrame
        The original DataFrame with an added ``is_contaminated`` column.
    """
    # Ensure deterministic ordering.
    df = df.sort_values(["seed_id", "bias_type", "timestep"]).reset_index(drop=True)

    # Prepare output column.
    df["is_contaminated"] = False

    window_size = DataConfig.SLIDING_WINDOW_SIZE  # W = 20 per spec

    # Process each seed/bias combination independently.
    group_cols = ["seed_id", "bias_type"]
    for _, group in df.groupby(group_cols):
        idx = group.index

        # 1. MAD of G_t within the group.
        mad = _median_absolute_deviation(group["G_t"])

        # 2. Event detection (not directly used for contamination decision
        #    but kept for traceability and possible downstream use).
        group["event"] = _detect_hacking_events(group, mad)

        # 3. Find contiguous True segments of the ground‑truth label.
        hacked_mask = group["hacked_label"].astype(bool)
        segments = _contiguous_true_segments(hacked_mask)

        # 4. Apply contamination rule.
        for _, seg in segments.iterrows():
            if seg["length"] > window_size:
                # Mark all rows belonging to this segment as contaminated.
                segment_idx = idx[seg["start"] : seg["end"] + 1]
                df.loc[segment_idx, "is_contaminated"] = True

    # Drop the temporary helper column if it exists.
    if "event" in df.columns:
        df = df.drop(columns=["event"])

    return df


def main() -> int:
    """
    Entry point for the task.

    The function loads the divergence CSV, generates the contamination mask,
    writes the updated DataFrame back to disk (overwrites the original file),
    and returns an appropriate exit code.

    Returns
    -------
    int
        ``0`` on success, non‑zero on failure.
    """
    try:
        print("T025 – Generating contaminated‑window mask...")
        df = load_divergence_data()
        df_masked = generate_is_contaminated_mask(df)

        # Persist the result.
        root = get_project_root()
        out_path = root / "data" / "processed" / "trajectories_divergence.csv"
        ensure_dir(out_path)
        save_csv(df_masked, str(out_path))

        contaminated_count = df_masked["is_contaminated"].sum()
        total = len(df_masked)
        print(
            f"Mask generation complete: {contaminated_count}/{total} "
            f"timesteps marked as contaminated ({contaminated_count/total:.2%})."
        )
        return 0

    except Exception as exc:
        print(f"ERROR during contaminated‑mask generation: {exc}")
        import traceback

        traceback.print_exc()
        return 1


if __name__ == "__main__":
    sys.exit(main())