"""
generate_contaminated_mask.py
--------------------------------
Implements Task T025: Contaminated window exclusion logic (FR‑009).

This script reads the aggregated divergence data produced by the ingestion
pipeline (``data/processed/trajectories_divergence.csv``), uses the
ground‑truth hacking labels generated by ``code/ground_truth.py`` and
creates a boolean ``is_contaminated`` column.

Contamination definition (per spec):
  1. A timestep is considered a *hacking event* if the divergence gap
     ``G_t`` exceeds three times the Median Absolute Deviation (MAD) of
     ``G_t`` within the same seed/bias group.
  2. Contiguous segments where the ground‑truth label ``hacked_label`` is
     ``True`` and whose duration (number of consecutive timesteps) is
     larger than the sliding‑window size ``W=20`` are marked as contaminated.
  3. All timesteps belonging to those segments receive
     ``is_contaminated=True``; all others receive ``False``.
The resulting DataFrame is written back to the same location,
overwriting the input file (the column is added in‑place).

The implementation follows the public API surface already defined in the
repository:
  * ``code.utils.io_utils.load_csv`` / ``save_csv`` for I/O.
  * ``code.utils.io_utils.ensure_dir`` to guarantee the output directory.
  * ``code.config.DataConfig`` provides the sliding‑window size (``W``).

The script fails loudly if required columns are missing or if the input
file cannot be found, in accordance with the project's “fail loud”
policy.
"""

import os
import sys
from pathlib import Path
from typing import Optional

import numpy as np
import pandas as pd

# Project utilities
from code.utils.io_utils import load_csv, save_csv, ensure_dir
from code.config import DataConfig, get_project_root

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------


def _median_absolute_deviation(series: pd.Series) -> float:
    """
    Compute the Median Absolute Deviation (MAD) of a pandas Series.

    Parameters
    ----------
    series: pd.Series
        Numeric series for which to compute MAD.

    Returns
    -------
    float
        The MAD value.
    """
    median = series.median()
    mad = np.median(np.abs(series - median))
    return float(mad)


def _detect_hacking_events(df: pd.DataFrame, mad: float) -> pd.Series:
    """
    Flag timesteps as hacking *events* based on the MAD criterion.

    A timestep is an event if ``G_t > 3 * MAD(G)``.

    Parameters
    ----------
    df: pd.DataFrame
        DataFrame containing a ``G_t`` column.
    mad: float
        Median absolute deviation of ``G_t`` for the current group.

    Returns
    -------
    pd.Series
        Boolean series where True indicates a hacking event.
    """
    threshold = 3.0 * mad
    return df["G_t"] > threshold


def _contiguous_true_segments(mask: pd.Series) -> pd.DataFrame:
    """
    Identify contiguous True segments in a boolean mask.

    Returns a DataFrame with columns:
      * ``start`` – integer index of the first True in the segment
      * ``end``   – integer index of the last True in the segment
      * ``length`` – number of True entries in the segment

    Parameters
    ----------
    mask: pd.Series
        Boolean series (typically ``hacked_label``).

    Returns
    -------
    pd.DataFrame
    """
    # ``mask`` must be a pandas Series with a default integer index.
    # We use the classic run‑length encoding technique.
    is_true = mask.astype(bool)
    # Identify where the value changes.
    change = is_true != is_true.shift()
    # Cumulative sum gives a unique id for each run.
    run_id = change.cumsum()
    # Group by run_id and aggregate.
    groups = is_true.groupby(run_id)
    segments = []
    for _, grp in groups:
        if not grp.iloc[0]:
            continue  # skip False runs
        start = grp.index[0]
        end = grp.index[-1]
        length = len(grp)
        segments.append({"start": start, "end": end, "length": length})
    return pd.DataFrame(segments)


