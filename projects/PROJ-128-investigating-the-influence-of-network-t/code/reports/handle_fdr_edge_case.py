"""
T028: Handle edge case for zero significant findings after FDR correction.

This module ensures that if the Benjamini-Hochberg FDR correction yields
zero significant findings, the final report explicitly states this fact
rather than omitting the results or leaving the section blank.

It modifies the correlation results dataframe to add a flag for 'no_significant_findings'
and generates a summary text block that can be injected into the final report.
"""

import os
import sys
import pandas as pd
import numpy as np
from pathlib import Path
from typing import Dict, Any, Optional, Tuple

# Add project root to path if running as script
if "code" not in sys.path:
    sys.path.insert(0, str(Path(__file__).parent.parent))

from config import get_config_dict

def load_correlation_results(csv_path: str) -> pd.DataFrame:
    """
    Load the correlation results CSV generated by T027.

    Args:
        csv_path: Path to the correlation results CSV.

    Returns:
        DataFrame containing correlation results.
    """
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Correlation results file not found: {csv_path}")
    
    df = pd.read_csv(csv_path)
    
    # Ensure required columns exist
    required_cols = ['structural_metric', 'dynamic_metric', 'r_value', 'p_value_raw', 'p_value_fdr']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in correlation results: {missing_cols}")
    
    return df

def check_for_zero_significant_findings(df: pd.DataFrame, alpha: float = 0.05) -> Tuple[bool, int, int]:
    """
    Check if FDR correction resulted in zero significant findings.

    Args:
        df: DataFrame with 'p_value_fdr' column.
        alpha: Significance threshold (default 0.05).

    Returns:
        Tuple of (has_zero_significant, total_tests, significant_count)
    """
    if df.empty:
        return True, 0, 0
    
    total_tests = len(df)
    significant_count = (df['p_value_fdr'] <= alpha).sum()
    
    return (significant_count == 0, total_tests, significant_count)

def generate_edge_case_report(df: pd.DataFrame, alpha: float = 0.05) -> Dict[str, Any]:
    """
    Generate a report section explicitly stating if there are zero significant findings.

    Args:
        df: DataFrame with correlation results.
        alpha: Significance threshold.

    Returns:
        Dictionary containing the report text and metadata.
    """
    has_zero, total, significant = check_for_zero_significant_findings(df, alpha)
    
    report = {
        "has_zero_significant_findings": has_zero,
        "total_correlation_tests": total,
        "significant_findings_at_alpha_0.05": significant,
        "alpha_threshold": alpha,
        "message": ""
    }
    
    if has_zero:
        report["message"] = (
            "NOTE: The Benjamini-Hochberg FDR correction (q=0.05) yielded ZERO significant findings. "
            f"Out of {total} tested correlations between structural and dynamic metrics, "
            f"none survived FDR correction (adjusted p-values > {alpha}). "
            "This indicates that, at the current sample size and statistical power, "
            "there is insufficient evidence to claim a significant association between "
            "structural topology and dynamic functional patterns after correcting for multiple comparisons. "
            "This result is explicitly reported rather than omitted, in compliance with T028 requirements."
        )
    else:
        report["message"] = (
            f"FDR correction yielded {significant} significant findings out of {total} tests. "
            "See 'significant_findings' section below for details."
        )
    
    # Add list of top non-significant findings if zero significant
    if has_zero and total > 0:
        df_sorted = df.sort_values('p_value_fdr')
        top_n = df_sorted.head(5)
        report["top_non_significant_findings"] = [
            {
                "structural": row['structural_metric'],
                "dynamic": row['dynamic_metric'],
                "r": float(row['r_value']),
                "p_raw": float(row['p_value_raw']),
                "p_fdr": float(row['p_value_fdr'])
            }
            for _, row in top_n.iterrows()
        ]
    
    return report

def annotate_results_with_edge_case(df: pd.DataFrame, alpha: float = 0.05) -> pd.DataFrame:
    """
    Add a column to the results dataframe indicating if this is a zero-significant scenario.

    Args:
        df: DataFrame with correlation results.
        alpha: Significance threshold.

    Returns:
        DataFrame with added 'is_zero_significant_scenario' column.
    """
    has_zero, _, _ = check_for_zero_significant_findings(df, alpha)
    df = df.copy()
    df['is_zero_significant_scenario'] = has_zero
    return df

def main():
    """
    Main entry point to process correlation results and handle the zero-significant edge case.
    
    This function:
    1. Loads the correlation results from data/processed/correlation_results.csv
    2. Checks for zero significant findings after FDR correction
    3. Generates an edge case report text
    4. Saves the report to data/processed/fdr_edge_case_report.json
    5. Updates the correlation results CSV with the edge case flag
    """
    config = get_config_dict()
    data_dir = Path(config.get('data_dir', 'data'))
    processed_dir = data_dir / 'processed'
    
    correlation_results_path = processed_dir / 'correlation_results.csv'
    edge_case_report_path = processed_dir / 'fdr_edge_case_report.json'
    
    print(f"T028: Handling FDR edge case for zero significant findings...")
    
    if not correlation_results_path.exists():
        print(f"ERROR: Correlation results file not found at {correlation_results_path}")
        print("T028 cannot proceed without correlation_results.csv. Please ensure T027 is complete.")
        sys.exit(1)
    
    try:
        # Load data
        df = load_correlation_results(str(correlation_results_path))
        print(f"Loaded {len(df)} correlation results.")
        
        # Check for edge case
        has_zero, total, significant = check_for_zero_significant_findings(df)
        print(f"Significant findings: {significant}/{total}")
        
        # Generate report
        report = generate_edge_case_report(df)
        
        # Save report
        with open(edge_case_report_path, 'w') as f:
            import json
            json.dump(report, f, indent=2)
        print(f"Saved edge case report to {edge_case_report_path}")
        
        # Annotate and save updated CSV
        df_annotated = annotate_results_with_edge_case(df)
        df_annotated.to_csv(correlation_results_path, index=False)
        print(f"Updated {correlation_results_path} with edge case flag.")
        
        # Print summary
        print("\n--- T028 SUMMARY ---")
        print(report["message"])
        print("--------------------\n")
        
        return 0
        
    except Exception as e:
        print(f"ERROR: Failed to process FDR edge case: {e}")
        import traceback
        traceback.print_exc()
        return 1

if __name__ == "__main__":
    sys.exit(main())