def load_loo_centroids(centroids_path: Optional[str] = None) -> Dict[str, np.ndarray]:
    """
    Load the LOO centroids file generated by T016.

    Args:
        centroids_path: Path to the .npz file. If None, uses config default.

    Returns:
        Dictionary mapping subject_id to centroid array (k, n_features).
    """
    config = get_config_dict()
    if centroids_path is None:
        centroids_path = config.get('LOO_CENTROIDS_PATH', 'data/processed/loo_centroids_all_subjects.npz')
    
    path = Path(centroids_path)
    if not path.exists():
        raise FileNotFoundError(f"LOO Centroids file not found at {centroids_path}. "
                                f"Ensure T016 has been completed successfully.")
    
    try:
        data = np.load(path, allow_pickle=True)
        centroids_dict = {}
        for key in data.files:
            # Load the array
            arr = data[key]
            if isinstance(arr, np.ndarray) and arr.size > 0:
                centroids_dict[key] = arr
        return centroids_dict
    except Exception as e:
        raise RuntimeError(f"Failed to load LOO centroids from {centroids_path}: {e}")

def compute_sliding_window_correlation(fmri_data: np.ndarray, 
                                     window_length: int, 
                                     step: int = 1) -> List[np.ndarray]:
    """
    Compute sliding window correlation matrices for a single subject's fMRI time series.

    Args:
        fmri_data: Array of shape (time_points, regions).
        window_length: Length of the sliding window in TRs.
        step: Step size between windows in TRs.

    Returns:
        List of correlation matrices (each shape: regions x regions).
    """
    n_time, n_regions = fmri_data.shape
    windows = []
    
    # Simple sliding window implementation
    for start in range(0, n_time - window_length + 1, step):
        end = start + window_length
        window_data = fmri_data[start:end, :]
        
        # Compute correlation matrix
        # Handle potential NaNs or constant signals
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            corr_matrix = np.corrcoef(window_data.T)
            
        # Handle cases where correlation might be NaN (e.g., constant signal)
        if np.any(np.isnan(corr_matrix)):
            # Replace NaNs with 0 or a small value to avoid breaking downstream
            corr_matrix = np.nan_to_num(corr_matrix, nan=0.0)
        
        windows.append(corr_matrix)
    
    return windows

def assign_states_and_calculate_metrics(
    subject_id: str,
    centroids_dict: Dict[str, np.ndarray],
    fmri_data: np.ndarray,
    window_length: int,
    step: int = 1,
    state_key_prefix: str = "subject_"
) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """
    Assign states to windows using the specific LOO centroids for this subject
    and calculate dynamic metrics.

    Args:
        subject_id: The ID of the current subject.
        centroids_dict: Dictionary of all LOO centroids.
        fmri_data: The fMRI time series for the subject (T x R).
        window_length: Window length in TRs.
        step: Step size in TRs.
        state_key_prefix: Prefix used in the centroids file keys.

    Returns:
        Tuple of (state_assignments_df, metrics_dict).
    """
    # Construct the key for this subject's LOO centroids
    # T016 format: "subject_001_centroids"
    centroids_key = f"{state_key_prefix}{subject_id}_centroids"
    
    if centroids_key not in centroids_dict:
        raise KeyError(f"LOO Centroids not found for subject {subject_id} (key: {centroids_key}). "
                       f"Available keys: {list(centroids_dict.keys())}")
    
    subject_centroids = centroids_dict[centroids_key]
    k = subject_centroids.shape[0]
    
    # Compute sliding window correlations for this subject
    window_corrs = compute_sliding_window_correlation(fmri_data, window_length, step)
    
    if not window_corrs:
        raise ValueError(f"No windows generated for subject {subject_id}. "
                         f"Check data length vs window_length.")
    
    # Flatten correlation matrices to feature vectors for assignment
    # We use the upper triangle (excluding diagonal) to avoid redundancy and self-correlation
    n_regions = window_corrs[0].shape[0]
    indices = np.triu_indices(n_regions, k=1)
    n_features = len(indices[0])
    
    window_features = []
    for corr in window_corrs:
        vec = corr[indices]
        window_features.append(vec)
    
    window_features = np.array(window_features) # (n_windows, n_features)
    
    # Assign each window to the nearest centroid (Euclidean distance)
    # Centroids are (k, n_features)
    distances = np.linalg.norm(window_features[:, np.newaxis, :] - subject_centroids, axis=2)
    state_assignments = np.argmin(distances, axis=1) # (n_windows,)
    
    # Calculate Metrics
    state_ids = np.unique(state_assignments)
    dwell_times = []
    visited_counts = []
    
    # State Assignments DataFrame
    assignments_data = {
        'subject_id': [],
        'window_index': [],
        'state_id': []
    }
    
    for i, state in enumerate(state_assignments):
        assignments_data['subject_id'].append(subject_id)
        assignments_data['window_index'].append(i)
        assignments_data['state_id'].append(state)
    
    state_df = pd.DataFrame(assignments_data)
    
    # Calculate Dwell Times and Visits
    metrics = {
        'subject_id': subject_id,
        'state_id': [],
        'mean_dwell_time': [],
        'num_visits': []
    }
    
    for s in range(k): # Iterate through all possible states
        # Find indices where this state occurs
        state_indices = np.where(state_assignments == s)[0]
        
        if len(state_indices) == 0:
            # State never visited
            metrics['state_id'].append(s)
            metrics['mean_dwell_time'].append(0.0)
            metrics['num_visits'].append(0)
            continue
        
        # Calculate visit durations (consecutive sequences)
        # A "visit" is a contiguous block of the same state
        visits = []
        current_visit_start = state_indices[0]
        current_visit_len = 1
        
        for j in range(1, len(state_indices)):
            if state_indices[j] == state_indices[j-1] + 1:
                current_visit_len += 1
            else:
                visits.append(current_visit_len)
                current_visit_start = state_indices[j]
                current_visit_len = 1
        visits.append(current_visit_len)
        
        mean_dwell = np.mean(visits)
        num_visits = len(visits)
        
        metrics['state_id'].append(s)
        metrics['mean_dwell_time'].append(mean_dwell)
        metrics['num_visits'].append(num_visits)
    
    return state_df, metrics

