import csv
import hashlib
import json
import logging
import os
from pathlib import Path
from typing import Dict, Any, Optional, List

# Configure logging for this module
logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

def load_csv(file_path: Path) -> List[Dict[str, Any]]:
    """Load a CSV file and return a list of dictionaries."""
    if not file_path.exists():
        raise FileNotFoundError(f"CSV file not found: {file_path}")
    
    data = []
    with open(file_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            data.append(row)
    return data

def load_parquet(file_path: Path) -> List[Dict[str, Any]]:
    """Load a Parquet file and return a list of dictionaries."""
    try:
        import pandas as pd
    except ImportError:
        raise ImportError("pandas is required to load Parquet files. Install with: pip install pandas pyarrow")
    
    if not file_path.exists():
        raise FileNotFoundError(f"Parquet file not found: {file_path}")
    
    df = pd.read_parquet(file_path)
    return df.to_dict(orient='records')

def compute_sha256(file_path: Path) -> str:
    """
    Compute the SHA-256 hash of a file.
    
    Args:
        file_path: Path to the file to hash.
        
    Returns:
        Hexadecimal string of the SHA-256 hash.
    """
    if not file_path.exists():
        raise FileNotFoundError(f"File not found: {file_path}")
    
    sha256_hash = hashlib.sha256()
    with open(file_path, "rb") as f:
        # Read in chunks to handle large files
        for chunk in iter(lambda: f.read(4096), b""):
            sha256_hash.update(chunk)
    return sha256_hash.hexdigest()

def verify_checksum(file_path: Path, expected_checksum: str) -> bool:
    """
    Verify the SHA-256 checksum of a file against an expected value.
    
    Args:
        file_path: Path to the file to verify.
        expected_checksum: Expected SHA-256 hash string.
        
    Returns:
        True if checksum matches, False otherwise.
    """
    if not file_path.exists():
        logger.error(f"File not found for checksum verification: {file_path}")
        return False
    
    actual_checksum = compute_sha256(file_path)
    
    if actual_checksum == expected_checksum:
        logger.info(f"Checksum verified for {file_path.name}")
        return True
    else:
        logger.error(f"Checksum mismatch for {file_path.name}: Expected {expected_checksum}, Got {actual_checksum}")
        return False

def write_checksum_to_state(project_id: str, checksums: Dict[str, str]) -> Optional[Path]:
    """
    Write successful checksums to the project state file.
    
    Args:
        project_id: Unique identifier for the project.
        checksums: Dictionary mapping filenames to their SHA-256 checksums.
        
    Returns:
        Path to the state file if successful, None otherwise.
    """
    if not checksums:
        logger.warning("No checksums provided to write to state.")
        return None
    
    state_dir = Path("state") / "projects"
    state_dir.mkdir(parents=True, exist_ok=True)
    
    state_file = state_dir / f"{project_id}.yaml"
    
    # Prepare content in YAML-like format (simple key-value structure)
    # Since we are writing to a .yaml file but using basic text, we format it manually
    lines = [
        f"# Checksum verification state for {project_id}",
        f"# Generated by code/utils/io_helpers.py",
        "checksums:",
    ]
    
    for filename, checksum in checksums.items():
        lines.append(f"  - file: {filename}")
        lines.append(f"    sha256: {checksum}")
    
    content = "\n".join(lines) + "\n"
    
    try:
        with open(state_file, 'w', encoding='utf-8') as f:
            f.write(content)
        logger.info(f"Checksums written to state file: {state_file}")
        return state_file
    except IOError as e:
        logger.error(f"Failed to write checksums to state file {state_file}: {e}")
        return None
