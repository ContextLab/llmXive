"""T009: Power Analysis Gate.

Performs a prospective power analysis to calculate the minimum sample
size required to detect an expected R^2 = 0.1 with 80% power at
alpha = 0.05, reads N_actual from verified_source_manifest.json
(generated by T011), compares N_actual against N_min, and writes
data/processed/power_analysis_report.json.

If N_actual < N_min (and a dataset was found), the mode flag is set to
'Underpowered' and downstream statistical inference is skipped.
The pre-registration.json artifact is updated with the actual predictor
count when T011 succeeded (status 'found').
"""
import json
import logging
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Optional

from scipy import stats

PROJECT_ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = PROJECT_ROOT / "data" / "verified_source_manifest.json"
PREREG_PATH = PROJECT_ROOT / "data" / "processed" / "pre-registration.json"
REPORT_PATH = PROJECT_ROOT / "data" / "processed" / "power_analysis_report.json"

# Plan.md Phase 1: 21 predictors (15 spectral power features from
# motor-cortex channels x 5 bands + 6 connectivity metrics from
# C3-C4, C3-Cz, C4-Cz pairs x PLV/wPLI).
DEFAULT_K_PREDICTORS = 21

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
    stream=sys.stdout,
)
log = logging.getLogger("power_analysis_gate")


def calculate_minimum_sample_size(
    r2_target: float = 0.1,
    power: float = 0.8,
    alpha: float = 0.05,
    k_predictors: int = DEFAULT_K_PREDICTORS,
) -> int:
    """Minimum N to detect R^2 = r2_target with given power via the
    non-central F distribution for a multiple regression with
    k_predictors predictors.

    Solves for the smallest integer N such that
    P(F(k, N-k-1, lambda) > F_crit) >= power, where
    lambda = f^2 * N and f^2 = R^2 / (1 - R^2).
    """
    if not 0.0 < r2_target < 1.0:
        raise ValueError("r2_target must be in (0, 1)")
    if not 0.0 < power < 1.0:
        raise ValueError("power must be in (0, 1)")
    if not 0.0 < alpha < 1.0:
        raise ValueError("alpha must be in (0, 1)")
    if k_predictors < 1:
        raise ValueError("k_predictors must be >= 1")

    f2 = r2_target / (1.0 - r2_target)
    n = k_predictors + 2
    while n < 100000:
        df2 = n - k_predictors - 1
        if df2 < 1:
            n += 1
            continue
        lam = f2 * n
        f_crit = stats.f.ppf(1.0 - alpha, k_predictors, df2)
        achieved_power = 1.0 - stats.ncf.cdf(
            f_crit, k_predictors, df2, lam
        )
        if achieved_power >= power:
            return n
        n += 1
    raise RuntimeError("Failed to converge on a minimum sample size")


def achieved_power_at_n(
    n: int,
    r2_target: float = 0.1,
    alpha: float = 0.05,
    k_predictors: int = DEFAULT_K_PREDICTORS,
) -> float:
    """Statistical power achieved at sample size n (for the report)."""
    f2 = r2_target / (1.0 - r2_target)
    df2 = n - k_predictors - 1
    lam = f2 * n
    f_crit = stats.f.ppf(1.0 - alpha, k_predictors, df2)
    return float(1.0 - stats.ncf.cdf(f_crit, k_predictors, df2, lam))


def load_manifest(path: Path = MANIFEST_PATH) -> Dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(
            f"verified_source_manifest.json not found at {path}. "
            "T011 (Source Verification) must run before the power "
            "analysis gate."
        )
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def load_preregistration(path: Path = PREREG_PATH) -> Optional[Dict[str, Any]]:
    if not path.exists():
        return None
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def run_gate(
    manifest: Dict[str, Any],
    prereg: Optional[Dict[str, Any]],
    r2_target: float = 0.1,
    power: float = 0.8,
    alpha: float = 0.05,
) -> Dict[str, Any]:
    """Run the power analysis gate and return the report dict."""
    t011_succeeded = (
        manifest.get("status") == "found"
        or manifest.get("paired_found") is True
    )

    # Predictor count: use the actual count when T011 succeeded;
    # otherwise fall back to the plan's 21-predictor design.
    if t011_succeeded:
        dataset = manifest.get("dataset") or {}
        k_predictors = int(
            dataset.get("predictor_count", DEFAULT_K_PREDICTORS)
        )
        k_source = "actual (from verified dataset, T011)"
    else:
        k_predictors = DEFAULT_K_PREDICTORS
        k_source = (
            "assumed from plan.md Phase 1 (T011 did not verify a "
            "paired dataset; pre-registration placeholder retained)"
        )

    n_min = calculate_minimum_sample_size(
        r2_target=r2_target,
        power=power,
        alpha=alpha,
        k_predictors=k_predictors,
    )

    # N_actual from the manifest (T011). Missing/absent -> 0.
    n_actual = manifest.get("N_actual", 0)
    try:
        n_actual = int(n_actual)
    except (TypeError, ValueError):
        n_actual = 0

    manifest_mode = manifest.get("mode_flag", "Data Insufficient")

    if not t011_succeeded or n_actual <= 0:
        mode_flag = manifest_mode if manifest_mode else "Data Insufficient"
        status = (
            "Data Insufficient: no verified paired dataset, "
            "statistical inference skipped"
        )
        inference_allowed = False
        comparison = "N/A (no verified dataset)"
    elif n_actual >= n_min:
        mode_flag = "Primary"
        status = "Sufficient Power"
        inference_allowed = True
        comparison = f"N_actual ({n_actual}) >= N_min ({n_min})"
    else:
        mode_flag = "Underpowered"
        status = "Underpowered"
        inference_allowed = False
        comparison = f"N_actual ({n_actual}) < N_min ({n_min})"

    report = {
        "artifact": "power_analysis_report",
        "task_id": "T009",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "parameters": {
            "r2_target": r2_target,
            "power": power,
            "alpha": alpha,
            "k_predictors": k_predictors,
            "k_predictors_source": k_source,
            "effect_size_f2": r2_target / (1.0 - r2_target),
        },
        "N_min": n_min,
        "N_actual": n_actual,
        "comparison": comparison,
        "status": status,
        "mode_flag": mode_flag,
        "inference_allowed": inference_allowed,
        "achieved_power_at_N_min": round(
            achieved_power_at_n(n_min, r2_target, alpha, k_predictors), 6
        ),
        "source_manifest": str(MANIFEST_PATH),
    }
    if inference_allowed is False and t011_succeeded and n_actual > 0:
        report["fr005_flag"] = {
            "status": "underpowered",
            "reason": "N < required",
        }
    return report


def update_preregistration(
    prereg: Optional[Dict[str, Any]],
    report: Dict[str, Any],
) -> Dict[str, Any]:
    """Update pre-registration.json with the actual predictor count
    when T011 succeeded; otherwise annotate the placeholder."""
    if prereg is None:
        prereg = {
            "artifact": "pre-registration",
            "task_id": "T009a",
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "analysis_plan_hash": "",
            "parameters": {},
        }
    t011_succeeded = report["parameters"]["k_predictors_source"].startswith(
        "actual"
    )
    params = prereg.setdefault("parameters", {})
    params["r2_target"] = report["parameters"]["r2_target"]
    params["power"] = report["parameters"]["power"]
    params["alpha"] = report["parameters"]["alpha"]
    if t011_succeeded:
        params["k_predictors"] = report["parameters"]["k_predictors"]
        prereg["k_predictors_status"] = "actual"
        prereg["notes"] = (
            "Predictor count updated by the power analysis gate "
            "(T009) from the verified dataset (T011)."
        )
    else:
        params.setdefault("k_predictors", None)
        prereg.setdefault("k_predictors_status", "placeholder")
        prereg["notes"] = (
            "T011 did not verify a paired dataset; the predictor "
            "count remains a placeholder. The power analysis gate "
            "(T009) used the plan.md 21-predictor design for the "
            "minimum sample size calculation."
        )
    prereg["power_analysis"] = {
        "task_id": "T009",
        "N_min": report["N_min"],
        "N_actual": report["N_actual"],
        "mode_flag": report["mode_flag"],
        "report_path": str(REPORT_PATH),
    }
    return prereg


def main() -> int:
    log.info("T009: Power Analysis Gate starting.")
    manifest = load_manifest()
    log.info(
        "Loaded manifest: status=%r, mode_flag=%r, N_actual=%r",
        manifest.get("status"),
        manifest.get("mode_flag"),
        manifest.get("N_actual", 0),
    )
    prereg = load_preregistration()

    report = run_gate(manifest, prereg)
    log.info(
        "Power analysis: N_min=%d (R^2=%.2f, power=%.2f, alpha=%.2f, "
        "k=%d)",
        report["N_min"],
        report["parameters"]["r2_target"],
        report["parameters"]["power"],
        report["parameters"]["alpha"],
        report["parameters"]["k_predictors"],
    )
    log.info("Comparison: %s", report["comparison"])
    log.info("Status: %s", report["status"])
    log.info("Mode flag: %s", report["mode_flag"])

    if report["mode_flag"] == "Underpowered":
        log.warning(
            "Underpowered: Minimum N required = %d, actual N = %d. "
            "Downstream statistical inference will be skipped.",
            report["N_min"],
            report["N_actual"],
        )
    if report["mode_flag"] == "Data Insufficient":
        log.warning(
            "Data Insufficient: no verified paired dataset; "
            "downstream statistical inference is skipped."
        )

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(REPORT_PATH, "w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=2)
    log.info("Wrote %s", REPORT_PATH)

    updated = update_preregistration(prereg, report)
    PREREG_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(PREREG_PATH, "w", encoding="utf-8") as fh:
        json.dump(updated, fh, indent=2)
    log.info("Updated %s", PREREG_PATH)

    log.info("T009 complete.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
