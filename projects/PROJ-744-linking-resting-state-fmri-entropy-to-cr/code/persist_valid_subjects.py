def parse_excluded_subjects_from_log(log_path: Path, pattern: str = r"Subject\s+(\S+)\s+excluded") -> Set[str]:
    """
    Parse a log file to find excluded subjects based on a regex pattern.
    
    Args:
        log_path: Path to the log file.
        pattern: Regex pattern to match exclusion lines.
    
    Returns:
        A set of subject IDs found in exclusion lines.
    """
    excluded = set()
    if not log_path.exists():
        logger.warning(f"Log file not found: {log_path}. No exclusions parsed from this file.")
        return excluded

    try:
        with open(log_path, 'r', encoding='utf-8') as f:
            for line in f:
                match = re.search(pattern, line, re.IGNORECASE)
                if match:
                    subject_id = match.group(1)
                    excluded.add(subject_id)
                    logger.debug(f"Parsed excluded subject from {log_path.name}: {subject_id}")
    except Exception as e:
        logger.error(f"Error reading log file {log_path}: {e}")
    
    return excluded

def get_all_subjects_from_phenotype(phenotype_path: Path) -> Set[str]:
    """
    Extract all subject IDs from the phenotype CSV.
    
    Args:
        phenotype_path: Path to Creative_Problem_Solving.csv.
    
    Returns:
        A set of subject IDs.
    """
    if not phenotype_path.exists():
        raise FileNotFoundError(f"Phenotype file not found at {phenotype_path}. Cannot determine subject list.")
    
    df = safe_read_csv(phenotype_path)
    if df is None:
        raise ValueError(f"Failed to read phenotype file: {phenotype_path}")
    
    # Assume the column is named 'subject_id' or similar. 
    # Based on T040/T006 context, we look for a subject identifier column.
    # Common HCP phenotype columns: Subject_ID, subj, subject_id
    subject_col = None
    possible_cols = ['subject_id', 'Subject_ID', 'subj', 'Subject', 'ID']
    for col in possible_cols:
        if col in df.columns:
            subject_col = col
            break
    
    if subject_col is None:
        # Fallback: try to find any column that looks like an ID if we haven't found one
        # This is a heuristic; strict implementation requires known schema.
        logger.warning("Subject ID column not explicitly found. Attempting to infer or failing.")
        # If we can't find it, we might need to rely on file names or other sources.
        # For now, raise error to be safe.
        raise ValueError(f"Could not identify subject ID column in {phenotype_path}. Columns found: {df.columns.tolist()}")
    
    # Clean and collect
    subjects = set(df[subject_col].astype(str).str.strip().tolist())
    logger.info(f"Found {len(subjects)} total subjects from phenotype file.")
    return subjects

def get_all_subjects_from_logs(log_dir: Path) -> Set[str]:
    """
    Attempt to infer subjects from log files if phenotype is missing (fallback).
    This is less reliable but prevents total failure if phenotype is missing.
    """
    subjects = set()
    if not log_dir.exists():
        return subjects
    
    # Look for log files that might contain subject IDs
    log_files = list(log_dir.glob("*.log"))
    pattern = r"Subject\s+(\S+)"
    
    for log_file in log_files:
        try:
            with open(log_file, 'r', encoding='utf-8') as f:
                for line in f:
                    matches = re.findall(pattern, line)
                    for m in matches:
                        subjects.add(m)
        except Exception:
            continue
    
    return subjects

