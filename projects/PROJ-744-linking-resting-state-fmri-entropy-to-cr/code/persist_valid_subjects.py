"""
Module to persist the list of valid subject IDs after motion scrubbing and validation.

This task (T007b) implements the logic to:
1. Identify all subjects from the phenotype file.
2. Parse exclusion logs generated by T007 (motion scrubbing, missing data, parcel quality).
3. Compute the set difference to find valid subjects.
4. Persist the valid subject IDs to data/processed/valid_subjects.csv.

This file is consumed by downstream tasks T013 (entropy computation) and T022 (modeling).
"""

import os
import sys
import logging
import re
from pathlib import Path
from typing import Set, List, Dict, Any

# Ensure we can import sibling modules
sys.path.insert(0, str(Path(__file__).parent.parent))

from config import Config
from utils import ensure_dir, safe_read_csv

# Configure logging for this module
logger = logging.getLogger(__name__)

def get_all_subjects_from_phenotype() -> Set[str]:
    """
    Reads the phenotype CSV and returns a set of all subject IDs found in it.
    
    Returns:
        Set[str]: A set of subject ID strings.
    """
    phenotype_path = Path(Config.PHENOTYPE_PATH)
    if not phenotype_path.exists():
        raise FileNotFoundError(f"Phenotype file not found at {phenotype_path}")
    
    try:
        df = safe_read_csv(phenotype_path)
        # Assuming the subject ID column is named 'SubjectID' or similar based on HCP standards
        # We need to be flexible. Common HCP columns: 'Subject', 'SubjectID', 'sub_id'
        col_candidates = ['SubjectID', 'Subject', 'sub_id', 'SubID']
        id_col = None
        
        for col in col_candidates:
            if col in df.columns:
                id_col = col
                break
        
        if id_col is None:
            # Fallback: assume first column is ID if only one exists or specific pattern
            # For HCP Creative Problem Solving, it's usually 'SubjectID'
            if len(df.columns) > 0:
                id_col = df.columns[0]
                logger.warning(f"Could not find standard ID column. Using '{id_col}' as ID column.")
            else:
                raise ValueError("Phenotype CSV has no columns.")
        
        # Convert to set of strings, stripping whitespace
        subjects = set(df[id_col].astype(str).str.strip().tolist())
        return subjects
        
    except Exception as e:
        logger.error(f"Failed to read phenotype file: {e}")
        raise

def parse_excluded_subjects_from_log(log_path: Path) -> Set[str]:
    """
    Parses a log file to extract subject IDs that were excluded.
    
    This function handles the specific log formats generated by T007:
    - motion_exclusions.log: Contains lines like "Excluding subject {id} due to..."
    - missing_data.log: Contains lines like "Subject {id} excluded due to missing data..."
    - parcel_quality.log: Contains lines like "Subject {id} flagged for high NaN count..."
    
    Args:
        log_path: Path to the log file.
        
    Returns:
        Set[str]: A set of excluded subject IDs.
    """
    excluded = set()
    if not log_path.exists():
        logger.debug(f"Log file not found: {log_path}. No exclusions parsed from this file.")
        return excluded
    
    try:
        with open(log_path, 'r') as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                
                # Pattern 1: "Excluding subject {id}"
                match = re.search(r'Excluding subject\s+(\S+)', line, re.IGNORECASE)
                if match:
                    excluded.add(match.group(1))
                    continue
                
                # Pattern 2: "Subject {id} excluded"
                match = re.search(r'Subject\s+(\S+)\s+excluded', line, re.IGNORECASE)
                if match:
                    excluded.add(match.group(1))
                    continue
                
                # Pattern 3: "Subject {id} flagged" (for parcel quality)
                match = re.search(r'Subject\s+(\S+)\s+flagged', line, re.IGNORECASE)
                if match:
                    excluded.add(match.group(1))
                    continue
                
                # Pattern 4: Generic "Skipping subject {id}"
                match = re.search(r'Skipping subject\s+(\S+)', line, re.IGNORECASE)
                if match:
                    excluded.add(match.group(1))
                    continue
                    
    except Exception as e:
        logger.error(f"Failed to parse exclusion log {log_path}: {e}")
        # We don't raise here to be resilient; if we can't parse, we assume no exclusions from this specific log
        # but the main process might still fail if critical logs are missing entirely.
    
    return excluded

def get_all_subjects_from_logs() -> Set[str]:
    """
    Aggregates excluded subjects from all relevant log files generated in T007.
    
    Returns:
        Set[str]: Union of all excluded subject IDs.
    """
    excluded = set()
    
    log_dir = Path(Config.LOG_DIR)
    ensure_dir(log_dir)
    
    # Define log files to check
    log_files = [
        log_dir / "motion_exclusions.log",
        log_dir / "missing_data.log",
        log_dir / "parcel_quality.log"
    ]
    
    for log_file in log_files:
        if log_file.exists():
            logger.info(f"Parsing exclusions from {log_file.name}")
            excluded.update(parse_excluded_subjects_from_log(log_file))
        else:
            logger.warning(f"Exclusion log not found: {log_file.name}. Assuming no exclusions from this source.")
    
    return excluded

def main():
    """
    Main entry point for T007b.
    
    1. Loads all subjects from the phenotype file.
    2. Loads all excluded subjects from the motion/quality logs.
    3. Computes valid subjects = All - Excluded.
    4. Writes valid subjects to data/processed/valid_subjects.csv.
    """
    logger.info("Starting T007b: Persist Valid Subjects")
    
    try:
        # 1. Get all subjects
        all_subjects = get_all_subjects_from_phenotype()
        logger.info(f"Total subjects found in phenotype: {len(all_subjects)}")
        
        if not all_subjects:
            raise ValueError("No subjects found in phenotype file. Cannot proceed.")
        
        # 2. Get excluded subjects
        excluded_subjects = get_all_subjects_from_logs()
        logger.info(f"Total subjects excluded via logs: {len(excluded_subjects)}")
        if excluded_subjects:
            logger.debug(f"Excluded IDs: {sorted(excluded_subjects)}")
        
        # 3. Compute valid subjects
        valid_subjects = all_subjects - excluded_subjects
        logger.info(f"Valid subjects remaining: {len(valid_subjects)}")
        
        if len(valid_subjects) == 0:
            logger.critical("No valid subjects remain after filtering. Check exclusion logs.")
            # We still write the empty file to be explicit, but warn heavily
        
        # 4. Persist to CSV
        output_path = Path(Config.PROCESSED_DATA_DIR) / "valid_subjects.csv"
        ensure_dir(output_path.parent)
        
        # Create a DataFrame for consistent output format
        import pandas as pd
        df_output = pd.DataFrame({'subject_id': sorted(list(valid_subjects))})
        
        df_output.to_csv(output_path, index=False)
        logger.info(f"Successfully wrote {len(valid_subjects)} valid subjects to {output_path}")
        
        return valid_subjects
        
    except Exception as e:
        logger.error(f"Failed to persist valid subjects: {e}")
        raise

if __name__ == "__main__":
    # Setup basic logging if not already configured
    if not logging.getLogger().handlers:
        logging.basicConfig(level=logging.INFO)
    
    main()
