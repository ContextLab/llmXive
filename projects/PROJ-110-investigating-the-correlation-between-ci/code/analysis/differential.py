def stratify_by_tissue(
    expression_path: Path = Path("data/processed/core_genes_log2_matrix.csv"),
    phenotype_path: Path = Path("data/processed/filtered_phenotype.csv"),
) -> Dict[str, pd.DataFrame]:
    """
    Group samples by tissue type, returning a dictionary where each key is a
    tissue name and each value is a DataFrame containing the expression data
    for that tissue together with the MetS label.

    Returns
    -------
    dict
        Mapping ``tissue -> DataFrame``. Each DataFrame includes the columns
        ``sample_id``, ``label`` and one column per gene.
    """
    expr = _load_expression_matrix(expression_path)
    pheno = _load_phenotype(phenotype_path)

    # Merge on sample_id
    merged = pd.merge(expr, pheno[["sample_id", "tissue", "label"]], on="sample_id")
    logger.info(f"Merged expression with phenotype: {merged.shape[0]} samples")

    tissues = {}
    for tissue, group in merged.groupby("tissue"):
        tissues[tissue] = group.drop(columns=["tissue"]).reset_index(drop=True)
        logger.debug(f"Tissue '{tissue}' contains {group.shape[0]} samples")
    return tissues

def filter_underpowered_tissues(
    tissue_groups: Dict[str, pd.DataFrame],
    min_per_group: int = 20,
) -> List[str]:
    """
    Identify tissues that have at least ``min_per_group`` samples in **both**
    MetS and Control groups.

    Parameters
    ----------
    tissue_groups : dict
        Output of :func:`stratify_by_tissue`.
    min_per_group : int, optional
        Minimum required number of samples per phenotype group.

    Returns
    -------
    list
        Tissue names that satisfy the power requirement.
    """
    logger.info("Filtering under‑powered tissues")
    sufficient = []
    for tissue, df in tissue_groups.items():
        counts = df["label"].value_counts()
        met_counts = counts.get("MetS", 0)
        ctrl_counts = counts.get("Control", 0)
        logger.debug(
            f"Tissue '{tissue}': MetS={met_counts}, Control={ctrl_counts}"
        )
        if met_counts >= min_per_group and ctrl_counts >= min_per_group:
            sufficient.append(tissue)
        else:
            logger.warning(
                f"Excluding tissue '{tissue}' due to insufficient sample size"
            )
    # Write excluded tissues report
    excluded = [t for t in tissue_groups if t not in sufficient]
    report_path = Path("data/processed/excluded_tissues.json")
    report_path.parent.mkdir(parents=True, exist_ok=True)
    with report_path.open("w") as f:
        json.dump(
            {"excluded_tissues": excluded, "reason": " < 20 samples per group"},
            f,
            indent=2,
        )
    logger.info(
        f"{len(sufficient)} tissues retained, {len(excluded)} tissues excluded"
    )
    return sufficient

def run_wilcoxon_tests(
    tissue_groups: Dict[str, pd.DataFrame],
    valid_tissues: List[str],
    output_path: Path = Path("data/processed/wilcoxon_results.csv"),
) -> None:
    """
    Perform a Wilcoxon rank‑sum test for each gene within each tissue,
    comparing MetS vs. Control donors.

    The result CSV contains columns:
    ``tissue, gene, statistic, p_value``

    Parameters
    ----------
    tissue_groups : dict
        Mapping of tissue -> DataFrame (as returned by
        :func:`stratify_by_tissue`).
    valid_tissues : list
        List of tissue names that passed the power filter.
    output_path : Path, optional
        Destination for the results CSV.
    """
    from scipy.stats import ranksums

    logger.info("Running Wilcoxon rank‑sum tests")
    records = []
    for tissue in valid_tissues:
        df = tissue_groups[tissue]
        # Identify gene columns (numeric columns excluding sample_id and label)
        gene_cols = df.select_dtypes(include=[np.number]).columns.tolist()
        gene_cols = [c for c in gene_cols if c not in {"sample_id"}]

        for gene in gene_cols:
            group1 = df.loc[df["label"] == "MetS", gene]
            group2 = df.loc[df["label"] == "Control", gene]

            # Skip if any group is empty
            if group1.empty or group2.empty:
                logger.debug(
                    f"Skipping gene {gene} in tissue {tissue} due to empty group"
                )
                continue

            stat, p = ranksums(group1, group2)
            records.append(
                {"tissue": tissue, "gene": gene, "statistic": stat, "p_value": p}
            )
    results_df = pd.DataFrame.from_records(records)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    results_df.to_csv(output_path, index=False)
    logger.info(f"Wilcoxon results written to {output_path}")

def compute_effect_sizes(
    wilcoxon_path: Path = Path("data/processed/wilcoxon_results.csv"),
    expression_path: Path = Path("data/processed/core_genes_log2_matrix.csv"),
    phenotype_path: Path = Path("data/processed/filtered_phenotype.csv"),
    output_path: Path = Path("data/processed/effect_sizes.csv"),
) -> None:
    """
    Compute Cohen's d effect size for each gene‑tissue pair using the
    log2‑transformed expression values.

    Parameters
    ----------
    wilcoxon_path : Path
        CSV produced by :func:`run_wilcoxon_tests`.
    expression_path : Path
        Log2‑transformed expression matrix.
    phenotype_path : Path
        Filtered phenotype with MetS labels.
    output_path : Path
        Destination CSV containing ``tissue, gene, cohen_d``.
    """
    logger.info("Computing effect sizes (Cohen's d)")
    wilcoxon_df = pd.read_csv(wilcoxon_path)
    expr = _load_expression_matrix(expression_path)
    pheno = _load_phenotype(phenotype_path)

    merged = pd.merge(expr, pheno[["sample_id", "label"]], on="sample_id")
    records = []

    for _, row in wilcoxon_df.iterrows():
        tissue = row["tissue"]
        gene = row["gene"]
        # Subset to the tissue of interest
        tissue_samples = pheno[pheno["tissue"] == tissue]["sample_id"]
        sub = merged[merged["sample_id"].isin(tissue_samples)]

        mets = sub.loc[sub["label"] == "MetS", gene]
        ctrl = sub.loc[sub["label"] == "Control", gene]

        if mets.empty or ctrl.empty:
            continue

        # Cohen's d
        mean_diff = mets.mean() - ctrl.mean()
        pooled_sd = np.sqrt(
            ((mets.std() ** 2) + (ctrl.std() ** 2)) / 2
        )
        d = mean_diff / pooled_sd if pooled_sd != 0 else np.nan
        records.append(
            {"tissue": tissue, "gene": gene, "cohen_d": d}
        )

    effect_df = pd.DataFrame.from_records(records)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    effect_df.to_csv(output_path, index=False)
    logger.info(f"Effect sizes written to {output_path}")

def apply_fdr_correction(
    wilcoxon_path: Path = Path("data/processed/wilcoxon_results.csv"),
    output_path: Path = Path("data/processed/wilcoxon_fdr_corrected.csv"),
) -> None:
    """
    Apply the Benjamini‑Hochberg FDR correction to the raw p‑values
    generated by the Wilcoxon tests.

    The correction is **global**: all p‑values across **all tissues** and
    **all genes** are pooled before adjustment, satisfying FR‑004.

    Parameters
    ----------
    wilcoxon_path : Path, optional
        Path to the CSV file containing raw Wilcoxon results with a
        ``p_value`` column.
    output_path : Path, optional
        Destination CSV that mirrors the input but adds a ``p_adj`` column
        with the FDR‑adjusted p‑values.
    """
    logger.info("Applying Benjamini‑Hochberg FDR correction to DE p‑values")
    if not wilcoxon_path.is_file():
        raise FileNotFoundError(f"Wilcoxon results not found: {wilcoxon_path}")

    df = pd.read_csv(wilcoxon_path)
    if "p_value" not in df.columns:
        raise ValueError("Input Wilcoxon file must contain a 'p_value' column")

    pvals = df["p_value"].values
    n = len(pvals)
    if n == 0:
        raise ValueError("No p‑values to correct")

    # Benjamini‑Hochberg procedure
    order = np.argsort(pvals)
    sorted_p = pvals[order]
    bh_adjusted = np.empty(n, dtype=float)

    # Compute the adjusted values
    cumulative_min = 1.0
    for i in range(n - 1, -1, -1):
        rank = i + 1  # ranks are 1‑based
        adj = sorted_p[i] * n / rank
        cumulative_min = min(cumulative_min, adj)
        bh_adjusted[i] = cumulative_min

    # Re‑order to original order
    p_adj = np.empty(n, dtype=float)
    p_adj[order] = bh_adjusted

    # Clip to [0,1]
    p_adj = np.clip(p_adj, 0, 1)

    df["p_adj"] = p_adj
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    logger.info(f"FDR‑adjusted results written to {output_path}")

