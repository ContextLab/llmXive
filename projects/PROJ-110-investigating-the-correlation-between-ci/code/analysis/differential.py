# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def _load_expression_matrix(
    path: Path = Path("data/processed/core_genes_log2_matrix.csv"),
) -> pd.DataFrame:
    """
    Load the log2‑transformed expression matrix for core circadian genes.

    Returns
    -------
    pd.DataFrame
        DataFrame with ``sample_id`` as the first column and one column per
        gene containing log2(TPM+1) values.
    """
    logger.debug(f"Loading expression matrix from {path}")
    if not path.is_file():
        raise FileNotFoundError(f"Expression matrix not found: {path}")
    df = pd.read_csv(path)
    if df.empty:
        raise ValueError("Expression matrix is empty")
    return df

def _load_phenotype(
    path: Path = Path("data/processed/filtered_phenotype.csv"),
) -> pd.DataFrame:
    """
    Load the phenotype file that contains at least ``sample_id`` and
    ``tissue`` columns as well as the metabolic syndrome label
    (``MetS`` / ``Control``) generated by ``classify_metabolic_status``.
    """
    logger.debug(f"Loading phenotype data from {path}")
    if not path.is_file():
        raise FileNotFoundError(f"Phenotype file not found: {path}")
    df = pd.read_csv(path)
    if df.empty:
        raise ValueError("Phenotype file is empty")
    required = {"sample_id", "tissue", "label"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Phenotype file missing required columns: {missing}")
    return df

