"""
Module to save the cleaned and processed dataset.

This module implements Task T015: Save cleaned dataset.
It takes the processed DataFrame from the data ingestion pipeline
and writes it to data/processed/cleaned_data.csv with a header
containing column definitions.
"""
import os
import sys
import pandas as pd
from pathlib import Path
from typing import Optional, List, Dict, Any

# Ensure project root is in path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from config import ensure_directories, INPUT_PATHS, SAMPLE_LIMIT
from logging_config import get_logger, log_provenance, log_warning
from data_ingestion import run_ingestion_pipeline

logger = get_logger(__name__)

def save_cleaned_dataset(df: pd.DataFrame, output_path: Optional[str] = None) -> str:
    """
    Save the cleaned dataset to CSV with column definitions in the header.
    
    Args:
        df: The processed DataFrame containing cleaned data.
        output_path: Optional path to save the CSV. Defaults to config setting.
        
    Returns:
        str: The path where the file was saved.
        
    Raises:
        ValueError: If the DataFrame is empty or None.
        IOError: If the file cannot be written.
    """
    if df is None or df.empty:
        error_msg = "Cannot save empty or None DataFrame. Data ingestion may have failed."
        logger.error(error_msg)
        raise ValueError(error_msg)
    
    # Determine output path
    if output_path is None:
        output_path = str(INPUT_PATHS.get('PROCESSED_OUTPUT', 'data/processed/cleaned_data.csv'))
    
    # Ensure output directory exists
    output_dir = Path(output_path).parent
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Create column definitions header
    column_definitions = []
    for col in df.columns:
        dtype = str(df[col].dtype)
        null_count = df[col].isnull().sum()
        null_pct = (null_count / len(df)) * 100
        desc = f"{col}: dtype={dtype}, nulls={null_count} ({null_pct:.2f}%)"
        column_definitions.append(desc)
    
    # Write to CSV with definitions as comments at the top
    try:
        with open(output_path, 'w') as f:
            # Write column definitions as comments
            f.write("# Cleaned Data Output - Generated by data_ingestion pipeline\n")
            f.write(f"# Total records: {len(df)}\n")
            f.write(f"# Columns: {', '.join(df.columns)}\n")
            f.write("# Column Definitions:\n")
            for definition in column_definitions:
                f.write(f"#   {definition}\n")
            f.write("#\n")
            # Write the actual CSV data
            df.to_csv(f, index=False)
        
        log_provenance(f"Saved cleaned dataset to {output_path} with {len(df)} records.")
        logger.info(f"Successfully saved cleaned dataset to {output_path}")
        return output_path
        
    except IOError as e:
        logger.error(f"Failed to write cleaned dataset to {output_path}: {str(e)}")
        raise IOError(f"Failed to write cleaned dataset: {str(e)}") from e

def main() -> int:
    """
    Main entry point for saving cleaned data.
    
    This function runs the data ingestion pipeline to get the cleaned data,
    then saves it to the specified output path.
    
    Returns:
        int: Exit code (0 for success, 1 for failure)
    """
    try:
        logger.info("Starting cleaned data save process (Task T015)")
        
        # Ensure directories exist
        ensure_directories()
        
        # Run the ingestion pipeline to get cleaned data
        # This assumes T011-T014 have been executed or are part of the pipeline
        cleaned_df = run_ingestion_pipeline()
        
        if cleaned_df is None or cleaned_df.empty:
            logger.warning("Ingestion pipeline returned empty dataset. Nothing to save.")
            # Still create an empty file with headers to indicate the step ran
            output_path = str(INPUT_PATHS.get('PROCESSED_OUTPUT', 'data/processed/cleaned_data.csv'))
            with open(output_path, 'w') as f:
                f.write("# Cleaned Data Output - Generated by data_ingestion pipeline\n")
                f.write("# WARNING: No data available to save.\n")
                f.write("# Columns: N/A\n")
            logger.info(f"Created empty output file at {output_path}")
            return 0
        
        # Save the dataset
        saved_path = save_cleaned_dataset(cleaned_df)
        
        logger.info(f"Task T015 completed successfully. Output: {saved_path}")
        return 0
        
    except Exception as e:
        logger.error(f"Task T015 failed: {str(e)}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())
