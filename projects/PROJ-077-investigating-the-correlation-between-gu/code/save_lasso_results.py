"""
Module to save Lasso regression results to CSV.
Implements T029b: Save Lasso coefficients, non-zero feature count, and performance metrics.
"""
import os
import sys
import pandas as pd
import numpy as np
from pathlib import Path
from typing import Dict, Any, Optional, List, Tuple

from config import ensure_directories
from logging_config import get_logger, log_provenance, log_warning

logger = get_logger(__name__)

def load_lasso_results_from_analysis() -> Tuple[pd.DataFrame, int, Dict[str, float]]:
    """
    Loads Lasso results computed by the analysis pipeline.
    
    Expects the results to be available in the analysis module's global scope
    or to be re-computed if not present. For this implementation, we assume
    the analysis module has already run and stored the necessary data.
    
    Returns:
        Tuple containing:
        - DataFrame with coefficients (features as index)
        - Number of non-zero features
        - Dictionary of performance metrics (R2, MSE)
    """
    # This function is a placeholder for retrieving results from the analysis pipeline.
    # In a real scenario, this would import from analysis.py or load from a temporary file.
    # Since T029a (run_lasso) is completed, we assume the data exists in memory or a temp file.
    # For the purpose of this task (saving), we will simulate the retrieval from the
    # expected location if the analysis script ran, or raise an error if not found.
    
    # Attempt to load from a temporary file generated by analysis.py if it exists
    temp_results_path = Path("data/processed/.lasso_temp_results.pkl")
    
    if temp_results_path.exists():
        import pickle
        with open(temp_results_path, 'rb') as f:
            data = pickle.load(f)
        coefficients = data['coefficients']
        non_zero_count = data['non_zero_count']
        metrics = data['metrics']
        logger.info("Loaded Lasso results from temporary file.")
    else:
        # If the analysis script hasn't run or saved the temp file, we cannot proceed.
        # This ensures we are not fabricating data.
        raise FileNotFoundError(
            "Lasso results not found. Please run the analysis pipeline (T029a) first. "
            "Expected temp file: data/processed/.lasso_temp_results.pkl"
        )
        
    return coefficients, non_zero_count, metrics

def save_lasso_results(
    coefficients: pd.DataFrame,
    non_zero_count: int,
    metrics: Dict[str, float],
    output_path: str = "data/processed/lasso_results.csv"
) -> None:
    """
    Saves Lasso regression results to a CSV file.
    
    Args:
        coefficients: DataFrame with feature names as index and coefficient values.
        non_zero_count: Integer count of non-zero coefficients.
        metrics: Dictionary containing performance metrics (e.g., R2, MSE).
        output_path: Path to the output CSV file.
    """
    ensure_directories()
    
    # Prepare the results DataFrame
    results_data = []
    
    # Add coefficients
    for feature, coef in coefficients.items():
        results_data.append({
            "feature": feature,
            "type": "coefficient",
            "value": float(coef),
            "is_non_zero": int(coef != 0)
        })
    
    # Add summary metrics as rows
    results_data.append({
        "feature": "non_zero_features",
        "type": "metric",
        "value": float(non_zero_count),
        "is_non_zero": 1
    })
    
    for metric_name, metric_value in metrics.items():
        results_data.append({
            "feature": metric_name,
            "type": "metric",
            "value": float(metric_value),
            "is_non_zero": 1
        })
        
    df_results = pd.DataFrame(results_data)
    
    # Ensure output directory exists
    output_dir = Path(output_path).parent
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Save to CSV
    df_results.to_csv(output_path, index=False)
    logger.info(f"Lasso results saved to {output_path}")
    log_provenance(f"Lasso results saved: {output_path}, Non-zero features: {non_zero_count}")

def run_save_lasso_pipeline() -> None:
    """
    Orchestrates the loading and saving of Lasso results.
    """
    try:
        logger.info("Starting Lasso results save pipeline.")
        coefficients, non_zero_count, metrics = load_lasso_results_from_analysis()
        save_lasso_results(coefficients, non_zero_count, metrics)
        logger.info("Lasso results save pipeline completed successfully.")
    except FileNotFoundError as e:
        logger.error(f"Failed to save Lasso results: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during Lasso results save: {e}")
        raise

def main() -> None:
    """
    Entry point for the script.
    """
    run_save_lasso_pipeline()

if __name__ == "__main__":
    main()
