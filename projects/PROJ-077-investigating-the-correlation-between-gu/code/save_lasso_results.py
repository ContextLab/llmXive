"""
Save Lasso regression results to a CSV file.
"""
import os
import sys
import pandas as pd
import numpy as np
from pathlib import Path
from typing import Dict, Any, Optional, Tuple

from config import ensure_directories
from logging_config import get_logger, log_provenance, log_warning

logger = get_logger(__name__)

def load_lasso_results_from_analysis() -> Dict[str, Any]:
    """
    Load Lasso regression results that were generated by analysis.py.
    This function assumes the results are stored in a temporary JSON or CSV
    generated by the analysis module, or passed via environment/args.
    For this implementation, we assume the analysis module saves intermediate
    results to a specific path or we load them from the output of run_lasso_regression.
    
    Since we need to interface with the existing API surface where 'analysis.py'
    runs the model, we will simulate loading the results that would have been
    computed by 'run_lasso_regression' in analysis.py if it were run in the same
    process or via a shared state.
    
    In a real pipeline, analysis.py would save the coefficients and metrics to a
    temporary file, or this function would call the analysis module directly.
    Given the constraints, we assume the results are available in the 'data/processed'
    directory as an intermediate file 'lasso_temp_results.json' or similar,
    OR we re-run the logic here if the cleaned data is available.
    
    To strictly follow the 'save' task, we assume the analysis module has already
    computed the results and stored them in a temporary location or we fetch them
    from the 'data/processed' directory if the previous step (T029a) saved them.
    
    For this task, we will implement a function that expects the Lasso results
    to be passed via a JSON file generated by the analysis pipeline or re-compute
    if necessary. However, to avoid re-computation dependencies, we will assume
    the analysis.py module saves a temporary file 'data/processed/lasso_temp.json'
    containing the coefficients and metrics.
    
    If that file does not exist, we raise an error indicating the analysis step
    must be run first.
    """
    temp_path = Path("data/processed/lasso_temp_results.json")
    if not temp_path.exists():
        raise FileNotFoundError(
            "Lasso results not found. Please ensure T029a (run_lasso_regression) "
            "has been executed and saved intermediate results to 'data/processed/lasso_temp_results.json'."
        )
    
    import json
    with open(temp_path, 'r') as f:
        return json.load(f)

def save_lasso_results(
    coefficients: Dict[str, float],
    non_zero_count: int,
    metrics: Dict[str, float],
    output_path: str = "data/processed/lasso_results.csv"
) -> None:
    """
    Save Lasso regression results to a CSV file.
    
    Args:
        coefficients: Dictionary mapping feature names to their coefficients.
        non_zero_count: Number of non-zero coefficients (selected features).
        metrics: Dictionary containing performance metrics (e.g., 'MSE', 'R2').
        output_path: Path to save the results CSV.
    """
    ensure_directories()
    
    # Prepare the DataFrame
    rows = []
    
    # Add coefficients
    for feature, coef in coefficients.items():
        rows.append({
            'feature': feature,
            'type': 'coefficient',
            'value': coef,
            'is_selected': 1 if coef != 0 else 0
        })
    
    # Add metrics
    for metric_name, value in metrics.items():
        rows.append({
            'feature': metric_name,
            'type': 'metric',
            'value': value,
            'is_selected': 0
        })
    
    # Add summary stats
    rows.append({
        'feature': 'non_zero_features',
        'type': 'summary',
        'value': non_zero_count,
        'is_selected': 1
    })
    
    df = pd.DataFrame(rows)
    
    # Ensure output directory exists
    output_dir = Path(output_path).parent
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Save to CSV
    df.to_csv(output_path, index=False)
    log_provenance(f"Lasso results saved to {output_path}")
    logger.info(f"Saved {len(coefficients)} coefficients and {len(metrics)} metrics.")

def run_save_lasso_pipeline() -> None:
    """
    Orchestrates the loading and saving of Lasso results.
    """
    logger.info("Starting Lasso results save pipeline.")
    
    try:
        # Load results from the temporary file generated by analysis.py
        results = load_lasso_results_from_analysis()
        
        coefficients = results.get('coefficients', {})
        non_zero_count = results.get('non_zero_count', 0)
        metrics = results.get('metrics', {})
        
        if not coefficients:
            log_warning("No coefficients found in Lasso results. Saving empty file.")
        
        save_lasso_results(coefficients, non_zero_count, metrics)
        logger.info("Lasso results save pipeline completed successfully.")
    
    except FileNotFoundError as e:
        log_warning(f"Failed to load Lasso results: {e}")
        raise
    except Exception as e:
        log_warning(f"Error in Lasso results save pipeline: {e}")
        raise

def main():
    """
    Entry point for the script.
    """
    run_save_lasso_pipeline()

if __name__ == "__main__":
    main()
