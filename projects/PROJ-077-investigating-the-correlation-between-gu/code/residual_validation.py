def load_regression_data() -> pd.DataFrame:
    """
    Loads the cleaned dataset required for regression analysis.
    Expects 'data/processed/cleaned_data.csv' to exist.
    
    Returns:
        pd.DataFrame: The cleaned dataset.
        
    Raises:
        FileNotFoundError: If the cleaned data file does not exist.
    """
    path = "data/processed/cleaned_data.csv"
    if not os.path.exists(path):
        raise FileNotFoundError(f"Required input file missing: {path}")
    
    logger.info(f"Loading regression data from {path}")
    df = pd.read_csv(path)
    
    # Ensure necessary columns exist for Lasso (Secondary Path)
    required_cols = ['fluid_intelligence', 'age', 'bmi', 'sex']
    # Note: DQS is optional per T014b logic, handled in analysis.py
    
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns for regression: {missing}")
        
    return df

def run_lasso_regression(df: pd.DataFrame) -> Tuple[Lasso, np.ndarray, np.ndarray, List[str]]:
    """
    Runs Lasso regression on CLR-transformed taxa data (Secondary Path).
    
    This function assumes the input DataFrame has been prepared with CLR-transformed
    taxa columns (generated by code/transformation.py) and the target variable.
    
    Args:
        df (pd.DataFrame): The DataFrame containing features and target.
        
    Returns:
        Tuple[Lasso, np.ndarray, np.ndarray, List[str]]:
            - fitted_model: The trained Lasso model.
            - y_true: The actual target values.
            - y_pred: The predicted target values.
            - feature_names: List of feature names used.
    """
    # Identify taxa columns (assumed to be non-standard columns not in config list)
    # In a real scenario, these would be explicitly passed or identified by a prefix.
    # For this implementation, we assume columns starting with 'taxa_' or specific names.
    # However, based on T021/T029a context, we expect CLR transformed columns.
    # We will select columns that are numeric and not the standard covariates/target.
    
    target_col = 'fluid_intelligence'
    covariates = ['age', 'bmi', 'sex']
    
    # Filter numeric columns for features
    numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
    
    # Remove target and standard covariates from features if they are in numeric_cols
    # Note: 'sex' might be numeric (0/1) or object. We assume it's handled as a covariate.
    feature_cols = [c for c in numeric_cols if c not in [target_col] + covariates]
    
    if not feature_cols:
        # Fallback: If no taxa columns found, raise error as per Secondary Path requirement
        raise ValueError("No taxa columns found for Lasso regression. Ensure CLR transformation was applied.")
    
    logger.info(f"Using {len(feature_cols)} taxa features for Lasso regression.")
    
    X = df[feature_cols].values
    y = df[target_col].values
    
    # Handle missing values in X or y (should be cleaned already, but safety check)
    mask = ~np.isnan(X).any(axis=1) & ~np.isnan(y)
    X = X[mask]
    y = y[mask]
    
    if len(X) == 0:
        raise ValueError("No valid samples remaining after filtering NaNs for Lasso.")
    
    # Select alpha via cross-validation (5-fold as per T029a)
    # We use a range of alphas to find the best one
    lasso_cv = Lasso(random_state=RANDOM_SEED, max_iter=10000)
    
    # Fit model with CV to select alpha
    # Note: LassoCV is often better for alpha selection, but T029a specifies Lasso with CV logic
    # We will use LassoCV internally to find best alpha, then refit or use LassoCV directly
    from sklearn.linear_model import LassoCV
    
    lasso_model = LassoCV(cv=5, random_state=RANDOM_SEED, max_iter=10000)
    lasso_model.fit(X, y)
    
    # Get predictions
    y_pred = lasso_model.predict(X)
    
    return lasso_model, y, y_pred, feature_cols

def perform_shapiro_wilk_test(residuals: np.ndarray) -> Dict[str, float]:
    """
    Performs the Shapiro-Wilk test for normality on the residuals.
    
    Args:
        residuals (np.ndarray): Array of residuals (y_true - y_pred).
        
    Returns:
        Dict[str, float]: Dictionary containing 'statistic' and 'p_value'.
    """
    if len(residuals) < 3:
        # Shapiro-Wilk requires at least 3 samples
        log_warning("Residual sample size < 3; skipping Shapiro-Wilk test.")
        return {"statistic": np.nan, "p_value": np.nan}
    
    stat, p_value = stats.shapiro(residuals)
    return {"statistic": float(stat), "p_value": float(p_value)}

def check_normality_assumption(p_value: float, threshold: float = 0.05) -> bool:
    """
    Checks if the normality assumption holds based on the p-value.
    
    Null Hypothesis (H0): Residuals are normally distributed.
    If p > 0.05, we fail to reject H0 (assumption holds).
    If p <= 0.05, we reject H0 (assumption violated).
    
    Args:
        p_value (float): The p-value from the Shapiro-Wilk test.
        threshold (float): Significance level.
        
    Returns:
        bool: True if normality assumption holds (p > 0.05), False otherwise.
    """
    return p_value > threshold

def generate_diagnostics_report(
    model, 
    residuals: np.ndarray, 
    shapiro_result: Dict[str, float], 
    is_normal: bool,
    feature_names: List[str]
) -> Dict[str, Any]:
    """
    Generates a comprehensive diagnostics report for the Lasso model.
    
    Args:
        model: The fitted Lasso model.
        residuals (np.ndarray): The residuals array.
        shapiro_result (Dict[str, float]): Results from Shapiro-Wilk test.
        is_normal (bool): Whether normality assumption holds.
        feature_names (List[str]): Names of features used.
        
    Returns:
        Dict[str, Any]: The report dictionary.
    """
    report = {
        "model_type": "Lasso (Secondary Path)",
        "normality_assumption": "Holds" if is_normal else "Violated",
        "shapiro_wilk": shapiro_result,
        "residual_stats": {
            "mean": float(np.mean(residuals)),
            "std": float(np.std(residuals)),
            "min": float(np.min(residuals)),
            "max": float(np.max(residuals))
        },
        "model_params": {
            "alpha": float(model.alpha),
            "l1_ratio": 1.0, # Lasso is pure L1
            "n_features": len(feature_names),
            "n_nonzero_coefs": int((model.coef_ != 0).sum())
        },
        "timestamp": pd.Timestamp.now().isoformat()
    }
    
    return report

def save_report(report: Dict[str, Any], output_path: str = OUTPUT_PATH) -> None:
    """
    Saves the diagnostics report to a JSON file.
    
    Args:
        report (Dict[str, Any]): The report dictionary.
        output_path (str): Path to save the JSON file.
    """
    # Ensure directory exists
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Lasso diagnostics report saved to {output_path}")

def save_warning_log(p_value: float, threshold: float = 0.05) -> None:
    """
    Logs a warning to the analysis_warnings.log if normality assumption is violated.
    
    Args:
        p_value (float): The p-value from the Shapiro-Wilk test.
        threshold (float): Significance level.
    """
    if p_value <= threshold:
        warning_msg = f"Lasso Residual Normality Warning: Shapiro-Wilk p-value ({p_value:.4f}) <= {threshold}. Normality assumption violated."
        logger.warning(warning_msg)
        
        # Append to specific log file as per T025c style
        os.makedirs("data/processed", exist_ok=True)
        with open(LOG_PATH, 'a') as f:
            f.write(f"{pd.Timestamp.now()} - {warning_msg}\n")

def run_validation_pipeline() -> None:
    """
    Orchestrates the full residual validation pipeline for the Secondary Path (Lasso).
    
    1. Loads data.
    2. Runs Lasso regression.
    3. Calculates residuals.
    4. Performs Shapiro-Wilk test.
    5. Checks assumption.
    6. Generates and saves report.
    7. Logs warnings if necessary.
    """
    logger.info("Starting Lasso Residual Normality Validation (T029c)")
    
    try:
        # 1. Load Data
        df = load_regression_data()
        
        # 2. Run Lasso Regression
        model, y_true, y_pred, feature_names = run_lasso_regression(df)
        
        # 3. Calculate Residuals
        residuals = y_true - y_pred
        
        # 4. Perform Shapiro-Wilk Test
        shapiro_result = perform_shapiro_wilk_test(residuals)
        p_value = shapiro_result['p_value']
        
        # 5. Check Normality Assumption
        is_normal = check_normality_assumption(p_value)
        
        # 6. Generate Report
        report = generate_diagnostics_report(model, residuals, shapiro_result, is_normal, feature_names)
        
        # 7. Save Report
        save_report(report)
        
        # 8. Log Warnings
        if p_value is not None and not np.isnan(p_value):
            save_warning_log(p_value)
        else:
            logger.warning("Could not determine normality (invalid p-value).")
            
        logger.info("Lasso Residual Normality Validation completed.")
        
    except Exception as e:
        logger.error(f"Validation pipeline failed: {str(e)}")
        raise

def main() -> None:
    """Entry point for the script."""
    run_validation_pipeline()

if __name__ == "__main__":
    main()