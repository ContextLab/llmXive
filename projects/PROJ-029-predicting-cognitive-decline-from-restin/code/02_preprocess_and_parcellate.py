logger = get_logger("preprocess_and_parcellate")


def read_eligible_subjects(file_path: Path) -> List[Dict[str, Any]]:
    """Read eligible subjects from CSV generated by T017."""
    if not file_path.exists():
        raise FileNotFoundError(f"Eligible subjects file not found: {file_path}")
    
    subjects = []
    with open(file_path, 'r', newline='') as f:
        reader = csv.DictReader(f)
        for row in reader:
            subjects.append(row)
    return subjects


def find_subject_fmri(subject_dir: Path, session: Optional[str] = None) -> Optional[Path]:
    """Find the preprocessed or raw fMRI NIfTI file for a subject."""
    # Look for common BIDS patterns
    patterns = [
        f"*_space-MNI152NLin2009cAsym_desc-preproc_bold.nii.gz",
        f"*_space-MNI152NLin2009cAsym_bold.nii.gz",
        f"*_space-MNI_bold.nii.gz",
        f"*_bold.nii.gz",
        f"func/*_bold.nii.gz",
        f"func/*_bold.nii",
    ]
    
    for pattern in patterns:
        matches = list(subject_dir.glob(pattern))
        if matches:
            return matches[0]
    
    # Fallback: look for any nifti in func
    func_dir = subject_dir / "func"
    if func_dir.exists():
        niftis = list(func_dir.glob("*.nii*"))
        if niftis:
            return niftis[0]
    
    return None


@log_operation("motion_correction")
def motion_correction(nifti_path: Path) -> nib.Nifti1Image:
    """
    Perform motion correction: realign to mean image.
    Uses nilearn's realign function.
    """
    logger.log("motion_correction_start", file=str(nifti_path))
    
    try:
        # Load image
        img = image.load_img(nifti_path)
        
        # Realign to mean image
        # nilearn's resample_img can handle realignment if we specify target
        # For full realignment, we use image.realign
        realigned_img = preprocessing.realign(img)
        
        logger.log("motion_correction_end", status="success")
        return realigned_img
    except Exception as e:
        logger.log("motion_correction_error", error=str(e))
        raise


@log_operation("normalize_and_parcellate")
def normalize_and_parcellate(
    realigned_img: nib.Nifti1Image, 
    atlas_path: Path
) -> np.ndarray:
    """
    Resample to MNI152 space and apply AAL atlas to extract time series.
    Returns connectivity matrix (correlation matrix of time series).
    """
    logger.log("normalize_start")
    
    try:
        # Resample to MNI152 standard space (2mm)
        # Standard MNI152 2mm template
        target_affine = np.eye(3) * 2
        target_shape = (91, 109, 91)
        
        normalized_img = image.resample_img(
            realigned_img,
            target_affine=target_affine,
            target_shape=target_shape,
            interpolation='continuous'
        )
        
        logger.log("normalize_end", status="success")
        
        # Load AAL atlas
        logger.log("fetch_atlas_start")
        aal = fetch_atlas_aal()
        atlas_img = aal.maps
        labels = aal.labels
        
        logger.log("fetch_atlas_end", n_regions=len(labels))
        
        # Use NiftiLabelsMasker to extract time series
        masker = NiftiLabelsMasker(
            labels_img=atlas_img,
            standardize=True,
            detrend=True,
            low_pass=0.1,
            high_pass=0.01,
            t_r=2.0,  # Approximate TR, adjust if known
            mask_img=None,
            resampling_target="labels"
        )
        
        logger.log("extract_timeseries_start")
        time_series = masker.fit_transform(normalized_img)
        logger.log("extract_timeseries_end", shape=str(time_series.shape))
        
        # Compute connectivity matrix (Pearson correlation)
        logger.log("compute_connectivity_start")
        connectivity = np.corrcoef(time_series.T)
        
        # Handle NaNs (from constant regions)
        connectivity = np.nan_to_num(connectivity, nan=0.0)
        
        logger.log("compute_connectivity_end", shape=str(connectivity.shape))
        
        return connectivity
        
    except Exception as e:
        logger.log("normalize_error", error=str(e))
        raise


@log_operation("save_connectivity_matrix")
def save_connectivity_matrix(
    connectivity: np.ndarray, 
    subject_id: str, 
    session_id: str,
    output_dir: Path
) -> Path:
    """Save connectivity matrix to disk."""
    ensure_dir(output_dir)
    
    filename = f"sub-{subject_id}_ses-{session_id}_connectivity.npy"
    filepath = output_dir / filename
    
    np.save(filepath, connectivity)
    logger.log("save_success", file=str(filepath), shape=str(connectivity.shape))
    
    return filepath


@log_operation("save_time_series")
def save_time_series(
    time_series: np.ndarray,
    subject_id: str,
    session_id: str,
    output_dir: Path
) -> Path:
    """Save time series to disk for debugging/analysis."""
    ensure_dir(output_dir)
    
    filename = f"sub-{subject_id}_ses-{session_id}_timeseries.npy"
    filepath = output_dir / filename
    
    np.save(filepath, time_series)
    logger.log("save_ts_success", file=str(filepath), shape=str(time_series.shape))
    
    return filepath


@log_operation("preprocess_subject")
def preprocess_subject(
    subject_info: Dict[str, Any],
    data_root: Path,
    output_dir: Path
) -> Optional[Dict[str, Any]]:
    """
    Process a single subject: motion correction -> normalization -> parcellation.
    Returns metadata about the processed subject.
    """
    subject_id = subject_info.get('subject_id', '')
    session_id = subject_info.get('session_id', 'ses-01')
    
    logger.log("subject_start", subject_id=subject_id, session_id=session_id)
    
    try:
        # Find subject directory
        subject_dir = data_root / subject_id
        if not subject_dir.exists():
            # Try BIDS sub- prefix
            subject_dir = data_root / f"sub-{subject_id}"
            if not subject_dir.exists():
                raise FileNotFoundError(f"Subject directory not found: {subject_id}")
        
        # Find fMRI file
        fmri_path = find_subject_fmri(subject_dir, session_id)
        if fmri_path is None:
            logger.log("subject_skip", reason="no_fmri_found")
            return None
        
        logger.log("fmri_found", path=str(fmri_path))
        
        # Motion correction
        realigned = motion_correction(fmri_path)
        
        # Normalize and parcellate
        connectivity = normalize_and_parcellate(realigned, data_root)
        
        # Save results
        conn_path = save_connectivity_matrix(connectivity, subject_id, session_id, output_dir)
        
        # Also save time series for reference
        # Extract time series again for saving (could be optimized)
        atlas_img = fetch_atlas_aal().maps
        masker = NiftiLabelsMasker(
            labels_img=atlas_img,
            standardize=True,
            detrend=True,
            low_pass=0.1,
            high_pass=0.01,
            t_r=2.0,
            resampling_target="labels"
        )
        # Re-load normalized image for time series extraction
        # (In a real pipeline, we'd cache this)
        time_series = masker.fit_transform(realigned)
        ts_path = save_time_series(time_series, subject_id, session_id, output_dir)
        
        logger.log("subject_success", connectivity_file=str(conn_path))
        
        return {
            'subject_id': subject_id,
            'session_id': session_id,
            'connectivity_file': str(conn_path),
            'timeseries_file': str(ts_path),
            'status': 'success'
        }
        
    except Exception as e:
        logger.log("subject_error", error=str(e))
        return {
            'subject_id': subject_id,
            'session_id': session_id,
            'status': 'failed',
            'error': str(e)
        }


@log_operation("write_status")
def write_status(output_dir: Path, results: List[Dict[str, Any]]) -> Path:
    """Write processing status to JSON."""
    status_file = output_dir / "preprocessing_status.json"
    
    summary = {
        'total_processed': len(results),
        'success': sum(1 for r in results if r.get('status') == 'success'),
        'failed': sum(1 for r in results if r.get('status') == 'failed'),
        'results': results
    }
    
    with open(status_file, 'w') as f:
        json.dump(summary, f, indent=2)
    
    logger.log("status_written", file=str(status_file))
    return status_file


@log_operation("write_excluded_log")
def write_excluded_log(output_dir: Path, excluded: List[Dict[str, Any]]) -> Path:
    """Write log of excluded/failed subjects."""
    log_file = output_dir / "excluded_subjects.log"
    
    with open(log_file, 'w') as f:
        for item in excluded:
            f.write(f"Subject: {item.get('subject_id', 'unknown')}\n")
            f.write(f"  Session: {item.get('session_id', 'unknown')}\n")
            f.write(f"  Status: {item.get('status', 'unknown')}\n")
            if 'error' in item:
                f.write(f"  Error: {item['error']}\n")
            f.write("-" * 40 + "\n")
    
    logger.log("excluded_log_written", file=str(log_file), count=len(excluded))
    return log_file


@log_operation("preprocess_and_parcellate_main")
def main() -> int:
    """Main entry point for T018."""
    start_time = time.time()
    
    # Paths
    project_root = Path(__file__).parent.parent
    eligible_file = project_root / "data" / "processed" / "eligible_subjects.csv"
    output_dir = project_root / "data" / "processed" / "connectivity_matrices"
    data_root = project_root / "data" / "raw" / "ds000246"
    
    logger.log("main_start", eligible_file=str(eligible_file), output_dir=str(output_dir))
    
    # Check prerequisites
    if not eligible_file.exists():
        logger.log("error", message="Eligible subjects file not found. Run T017 first.")
        print(f"ERROR: {eligible_file} not found. Please run code/01_download_and_filter.py first.")
        return 3  # EXIT_CODE_NO_ELIGIBLE
    
    if not data_root.exists():
        logger.log("error", message="Raw data directory not found.")
        print(f"ERROR: {data_root} not found. Please ensure dataset is downloaded.")
        return 1
    
    ensure_dir(output_dir)
    
    # Read eligible subjects
    try:
        subjects = read_eligible_subjects(eligible_file)
        logger.log("subjects_loaded", count=len(subjects))
    except Exception as e:
        logger.log("error", message=f"Failed to read eligible subjects: {e}")
        return 1
    
    if len(subjects) == 0:
        logger.log("warning", message="No eligible subjects found.")
        print("WARNING: No eligible subjects found.")
        return 0
    
    # Process each subject
    results = []
    excluded = []
    
    for subj in subjects:
        result = preprocess_subject(subj, data_root, output_dir)
        if result:
            results.append(result)
            if result.get('status') == 'failed':
                excluded.append(result)
    
    # Write outputs
    write_status(output_dir, results)
    if excluded:
        write_excluded_log(output_dir, excluded)
    
    elapsed = time.time() - start_time
    logger.log("main_end", total=len(results), success=sum(1 for r in results if r.get('status') == 'success'), elapsed_seconds=elapsed)
    
    print(f"Preprocessing complete. Processed {len(results)} subjects in {elapsed:.2f}s.")
    print(f"Output directory: {output_dir}")
    
    return 0


if __name__ == "__main__":
    sys.exit(main())