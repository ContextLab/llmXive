import os
import sys
import logging
import json
from pathlib import Path
from typing import Dict, Any, List, Tuple, Optional
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Ensure output directories exist
ARTIFACTS_DIR = Path("data/artifacts")
LOGS_DIR = Path("data/logs")
ARTIFACTS_DIR.mkdir(parents=True, exist_ok=True)
LOGS_DIR.mkdir(parents=True, exist_ok=True)

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
    handlers=[
        logging.FileHandler(LOGS_DIR / 'evaluation.log'),
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)

def load_model_artifacts() -> Dict[str, Any]:
    """Load model comparison artifacts generated by T020."""
    model_path = ARTIFACTS_DIR / "model_comparison.csv"
    if not model_path.exists():
        raise FileNotFoundError(f"Model comparison artifact not found at {model_path}. "
                                "Ensure T020 has been executed successfully.")
    
    df = pd.read_csv(model_path)
    return df.to_dict('records')

def calculate_basin_r2_difference() -> Dict[str, Any]:
    """
    Calculate the raw difference between the highest and lowest basin R² scores.
    Loads data from T020 artifact (model_comparison.csv).
    """
    data = load_model_artifacts()
    
    # Find the row corresponding to the baseline (Random Forest) or the only available model
    # Assuming the CSV has columns: model, basin, r2, rmse, mae
    # We need to aggregate by model and basin if not already, or just pick the RF row if it has per-basin stats.
    # Based on T020 description: "includes basin-stratified R² scores"
    
    # We expect the model_comparison.csv to have rows for each basin and model.
    # Let's filter for the Random Forest model (baseline) as per SC-005 requirement.
    # If VLM failed, we might only have RF. If VLM succeeded, we might compare both, but SC-005 usually refers to the final model's variance.
    # The task T020b specifically asks for "difference between highest and lowest basin R² scores".
    
    # Filter for RF if available, otherwise take the first model (fallback)
    rf_rows = [r for r in data if 'random' in str(r.get('model', '')).lower() or 'rf' in str(r.get('model', '')).lower()]
    target_rows = rf_rows if rf_rows else data
    
    if not target_rows:
        logger.warning("No model data found to calculate basin variance.")
        return {"max_r2": None, "min_r2": None, "difference": None, "status": "No Data"}

    # Collect R2 values per basin
    basin_r2 = {}
    for row in target_rows:
        basin = row.get('basin')
        r2 = row.get('r2')
        if basin is not None and r2 is not None:
            basin_r2[basin] = float(r2)
    
    if not basin_r2:
        logger.warning("No basin R2 values found in model data.")
        return {"max_r2": None, "min_r2": None, "difference": None, "status": "No Basin Data"}

    r2_values = list(basin_r2.values())
    max_r2 = max(r2_values)
    min_r2 = min(r2_values)
    difference = max_r2 - min_r2

    result = {
        "max_r2": max_r2,
        "min_r2": min_r2,
        "difference": difference,
        "basin_r2_map": basin_r2,
        "status": "Calculated"
    }
    
    # Save to T020b artifact
    output_path = ARTIFACTS_DIR / "basin_r2_difference.json"
    with open(output_path, 'w') as f:
        json.dump(result, f, indent=2)
    
    logger.info(f"Basin R2 difference calculated: {difference:.4f} (Max: {max_r2:.4f}, Min: {min_r2:.4f})")
    return result

def generate_basin_variance_report() -> None:
    """
    Generate the basin variance report (T020a) and visualization.
    Reads from the T020b artifact (basin_r2_difference.json).
    Outputs:
      - data/artifacts/basin_variance_report.md
      - data/artifacts/basin_variance_viz.png
    """
    # Load the calculated metric from T020b
    metric_path = ARTIFACTS_DIR / "basin_r2_difference.json"
    if not metric_path.exists():
        logger.error(f"Metric file {metric_path} not found. Run T020b first.")
        raise FileNotFoundError(f"Required metric file {metric_path} not found.")
    
    with open(metric_path, 'r') as f:
        metrics = json.load(f)
    
    if metrics.get('status') == 'No Data' or metrics.get('difference') is None:
        logger.warning("No valid data to generate report.")
        # Still generate a report indicating failure
        report_content = """# Basin Variance Report

**Status**: No Data Available

The model performance data required to calculate basin variance was not found or was incomplete.
Please ensure the model training and evaluation pipeline (T020, T020b) has completed successfully.
"""
        with open(ARTIFACTS_DIR / "basin_variance_report.md", 'w') as f:
            f.write(report_content)
        
        # Create a placeholder figure
        fig, ax = plt.subplots(figsize=(10, 6))
        ax.text(0.5, 0.5, "No Data Available", ha='center', va='center', fontsize=20, color='red')
        ax.axis('off')
        plt.savefig(ARTIFACTS_DIR / "basin_variance_viz.png", dpi=150, bbox_inches='tight')
        plt.close()
        return

    basin_r2_map = metrics.get('basin_r2_map', {})
    max_r2 = metrics.get('max_r2')
    min_r2 = metrics.get('min_r2')
    difference = metrics.get('difference')

    # --- Generate Visualization ---
    fig, ax = plt.subplots(figsize=(10, 6))
    
    if basin_r2_map:
        basins = list(basin_r2_map.keys())
        r2_scores = list(basin_r2_map.values())
        
        # Sort by R2 for better visualization
        sorted_indices = np.argsort(r2_scores)
        sorted_basins = [basins[i] for i in sorted_indices]
        sorted_scores = [r2_scores[i] for i in sorted_indices]
        
        bars = ax.barh(sorted_basins, sorted_scores, color='skyblue', edgecolor='black')
        
        # Highlight max and min
        for i, (b, s) in enumerate(zip(sorted_basins, sorted_scores)):
            if s == max_r2:
                bars[i].set_color('green')
            elif s == min_r2:
                bars[i].set_color('red')
        
        ax.set_xlabel('R² Score')
        ax.set_title(f'Basin Variance in R² Scores (Diff: {difference:.4f})')
        ax.set_xlim(0, max(max_r2 + 0.1, 1.0)) # Ensure space for max
        ax.grid(axis='x', linestyle='--', alpha=0.7)
    else:
        ax.text(0.5, 0.5, "No Basin Data", ha='center', va='center', fontsize=20, color='gray')
        ax.axis('off')

    plt.tight_layout()
    viz_path = ARTIFACTS_DIR / "basin_variance_viz.png"
    plt.savefig(viz_path, dpi=150, bbox_inches='tight')
    plt.close()
    logger.info(f"Visualization saved to {viz_path}")

    # --- Generate Report ---
    report_lines = [
        "# Basin Variance Report",
        "",
        "## Overview",
        f"This report quantifies the variance in model performance (R²) across different ocean basins.",
        f"Variance is a critical metric for ensuring the model generalizes well across diverse oceanographic conditions (SC-005).",
        "",
        "## Key Metrics",
        f"- **Maximum R²**: {max_r2:.4f}",
        f"- **Minimum R²**: {min_r2:.4f}",
        f"- **Variance (Max - Min)**: {difference:.4f}",
        "",
        "## Basin-Specific Performance",
        "| Basin | R² Score |",
        "|-------|----------|",
    ]
    
    for basin, score in sorted(basin_r2_map.items(), key=lambda x: x[1], reverse=True):
        report_lines.append(f"| {basin} | {score:.4f} |")
    
    report_lines.extend([
        "",
        "## Analysis",
        f"The difference in R² scores across basins is **{difference:.4f}**.",
        "A lower difference indicates more consistent model performance across different ocean regions.",
        "A high difference suggests the model may be overfitting to specific basin characteristics or that the data distribution is highly imbalanced.",
        "",
        "## Visualization",
        f"See attached figure: `basin_variance_viz.png`.",
        "",
        f"*Generated by code/04_evaluation.py (T020a)*"
    ])
    
    report_content = "\n".join(report_lines)
    report_path = ARTIFACTS_DIR / "basin_variance_report.md"
    with open(report_path, 'w') as f:
        f.write(report_content)
    
    logger.info(f"Report saved to {report_path}")

def main():
    """Entry point for T020a execution."""
    logger.info("Starting Basin Variance Report Generation (T020a)...")
    try:
        # Ensure T020b has run by calling it (or checking the file)
        # We call it to ensure the metric is fresh, though it might just read the file.
        calculate_basin_r2_difference()
        
        generate_basin_variance_report()
        
        logger.info("T020a completed successfully.")
    except Exception as e:
        logger.error(f"T020a failed: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()