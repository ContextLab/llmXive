"""
Exclusion Log Processing (Task T015b).

Reads the exclusion log generated by feature extraction tasks (T014a, T015),
aggregates counts by reason, and writes a summary to data/processed/exclusion_summary.json.
"""
import os
import json
import logging
from pathlib import Path
from collections import defaultdict
from typing import Dict, Any

from code.config import get_paths, ProjectPaths
from code.utils.logging import get_logger

# Constants for log parsing
EXCLUSION_LOG_PATH = "data/logs/exclusions.log"
OUTPUT_FILE = "data/processed/exclusion_summary.json"

def parse_exclusion_log(log_path: Path) -> Dict[str, int]:
    """
    Reads the exclusion log and aggregates counts by reason.
    
    Expected log line formats (based on T014a/T015 implementation):
    - "EXCLUDED: <caption_id> | Reason: <REASON_CODE>"
    - "EXCLUDED: <caption_id> | REASON: <REASON_CODE>"
    - Or simply lines containing the reason code in a structured way.
    
    We look for common reason codes: TIMEOUT_EXCEEDED, BERT_FAILURE, SHORT_CAPTION, etc.
    """
    counts: Dict[str, int] = defaultdict(int)
    total_excluded = 0
    
    if not log_path.exists():
        logger = get_logger("exclusion_processor")
        logger.warning(f"Exclusion log not found at {log_path}. Returning empty summary.")
        return {
            "total_excluded": 0,
            "reasons": {},
            "status": "NO_LOG_FILE"
        }

    with open(log_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            
            # Heuristic to find reason codes. 
            # T014a/T015 log with specific patterns like "Reason: TIMEOUT_EXCEEDED"
            # or just the code itself if structured differently.
            # We check for common keywords defined in FR-001, FR-011, FR-012.
            
            reason = None
            if "Reason:" in line:
                parts = line.split("Reason:")
                if len(parts) > 1:
                    reason = parts[1].strip()
            elif "REASON:" in line:
                parts = line.split("REASON:")
                if len(parts) > 1:
                    reason = parts[1].strip()
            else:
                # Fallback: check if line contains known codes directly
                known_codes = ["TIMEOUT_EXCEEDED", "BERT_FAILURE", "SHORT_CAPTION", "MISSING_RATING"]
                for code in known_codes:
                    if code in line:
                        reason = code
                        break

            if reason:
                counts[reason] += 1
                total_excluded += 1

    return dict(counts), total_excluded

def write_summary(counts: Dict[str, int], total: int, output_path: Path) -> None:
    """
    Writes the aggregated summary to JSON.
    """
    summary = {
        "total_excluded": total,
        "reasons": counts,
        "status": "COMPLETE" if total > 0 else "NO_EXCLUSIONS"
    }
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)
    
    logger = get_logger("exclusion_processor")
    logger.info(f"Wrote exclusion summary to {output_path}")

def main() -> None:
    """
    Main entry point for T015b.
    """
    logger = get_logger("exclusion_processor")
    logger.info("Starting Exclusion Log Processing (T015b)")
    
    paths = get_paths()
    log_file = paths.data_raw.parent / "logs" / "exclusions.log" 
    # Note: The task specifies data/logs/exclusions.log relative to project root.
    # Based on T001b structure: data/raw, data/processed. 
    # We assume the log is created at data/logs/exclusions.log as per task spec.
    # Let's construct the path relative to project root.
    project_root = paths.project_root
    log_file = project_root / "data" / "logs" / "exclusions.log"
    output_file = project_root / "data" / "processed" / "exclusion_summary.json"

    try:
        counts, total = parse_exclusion_log(log_file)
        write_summary(counts, total, output_file)
        logger.info("T015b completed successfully.")
    except Exception as e:
        logger.error(f"T015b failed: {e}", exc_info=True)
        raise

if __name__ == "__main__":
    main()
