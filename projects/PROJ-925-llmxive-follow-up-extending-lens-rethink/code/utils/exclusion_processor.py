"""
Exclusion Log Processing (T015b)

Reads the exclusions log generated by feature extraction tasks (T014a, T015),
aggregates counts by exclusion reason, and writes a summary JSON to disk.
"""

import os
import json
import logging
from pathlib import Path
from collections import defaultdict
from typing import Dict, Any, List, Tuple

from config import get_paths, get_project_root
from utils.logging import get_logger

logger = get_logger(__name__)

# Constants
EXCLUSION_LOG_PATH = "data/logs/exclusions.log"
EXCLUSION_SUMMARY_PATH = "data/processed/exclusion_summary.json"


def parse_exclusion_log(log_path: Path) -> List[Dict[str, Any]]:
    """
    Parse the exclusions log file and extract structured exclusion records.

    Expected log line format (from T014a/T015):
    "INFO:caption_id=<id>;reason=<REASON>;message=<msg>"
    or similar structured format.

    Returns:
        List of dicts with keys: 'caption_id', 'reason', 'message'
    """
    records = []

    if not log_path.exists():
        logger.warning(f"Exclusion log not found at {log_path}. Returning empty list.")
        return records

    with open(log_path, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue

            # Expecting a structured log format like:
            # INFO:caption_id=123;reason=TIMEOUT_EXCEEDED;message=...
            # or similar. We'll parse key=value pairs separated by ';'
            parts = line.split(';')
            record = {}
            for part in parts:
                part = part.strip()
                if '=' in part:
                    key, value = part.split('=', 1)
                    key = key.strip().lower()
                    value = value.strip()
                    # Remove quotes if present
                    if value.startswith('"') and value.endswith('"'):
                        value = value[1:-1]
                    elif value.startswith("'") and value.endswith("'"):
                        value = value[1:-1]
                    record[key] = value

            # Only include if we have at least 'reason' and 'caption_id'
            if 'reason' in record and 'caption_id' in record:
                records.append(record)
            else:
                logger.debug(f"Skipping malformed log line at {line_num}: {line[:50]}...")

    logger.info(f"Parsed {len(records)} exclusion records from {log_path}")
    return records


def aggregate_exclusions(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Aggregate exclusion counts by reason.

    Args:
        records: List of exclusion records from parse_exclusion_log

    Returns:
        Dict with structure:
        {
            "total_excluded": int,
            "by_reason": {
                "REASON_1": count,
                "REASON_2": count,
                ...
            },
            "reasons_found": list of unique reasons
        }
    """
    by_reason = defaultdict(int)

    for record in records:
        reason = record.get('reason', 'UNKNOWN')
        by_reason[reason] += 1

    total_excluded = sum(by_reason.values())

    return {
        "total_excluded": total_excluded,
        "by_reason": dict(by_reason),
        "reasons_found": sorted(list(by_reason.keys())),
        "processed_at": None  # Will be set by caller
    }


def write_summary(summary: Dict[str, Any], output_path: Path) -> None:
    """
    Write the exclusion summary to a JSON file.

    Args:
        summary: Aggregated summary dict
        output_path: Path to write the JSON file
    """
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Add timestamp
    import datetime
    summary["processed_at"] = datetime.datetime.utcnow().isoformat() + "Z"

    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(summary, f, indent=2, ensure_ascii=False)

    logger.info(f"Wrote exclusion summary to {output_path}")


def main() -> Dict[str, Any]:
    """
    Main entry point for T015b: Exclusion Log Processing.

    1. Reads data/logs/exclusions.log
    2. Aggregates counts by exclusion reason
    3. Writes summary to data/processed/exclusion_summary.json

    Returns:
        The summary dict that was written to disk
    """
    paths = get_paths()
    project_root = get_project_root()

    log_path = project_root / EXCLUSION_LOG_PATH
    output_path = project_root / EXCLUSION_SUMMARY_PATH

    logger.info(f"Starting exclusion log processing. Log: {log_path}, Output: {output_path}")

    # Parse log
    records = parse_exclusion_log(log_path)

    if not records:
        logger.warning("No exclusion records found. Creating empty summary.")
        summary = {
            "total_excluded": 0,
            "by_reason": {},
            "reasons_found": [],
            "processed_at": None
        }
    else:
        # Aggregate
        summary = aggregate_exclusions(records)

    # Write summary
    write_summary(summary, output_path)

    logger.info(f"T015b complete. Total excluded: {summary['total_excluded']}")
    return summary


