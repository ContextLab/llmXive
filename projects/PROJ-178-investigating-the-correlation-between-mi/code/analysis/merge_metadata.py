import os
import sys
import logging
from pathlib import Path
import pandas as pd

from config.environment import get_local_paths, ensure_directories

logger = logging.getLogger(__name__)

def ensure_dirs():
    """Ensure all necessary directories exist."""
    ensure_directories()

def load_burden_data():
    """Load the heteroplasmy burden data calculated in preprocess.py."""
    paths = get_local_paths()
    burden_path = paths['burden_csv']
    
    if not os.path.exists(burden_path):
        raise FileNotFoundError(
            f"Burden data file not found at {burden_path}. "
            "Please run preprocessing tasks (T014-T016) first."
        )
    
    logger.info(f"Loading burden data from {burden_path}")
    df = pd.read_csv(burden_path)
    logger.info(f"Loaded {len(df)} burden records")
    return df

def load_haplogroup_data():
    """Load the haplogroup assignments generated by haplogrep2."""
    paths = get_local_paths()
    haplogroup_path = paths['haplogroup_csv']
    
    if not os.path.exists(haplogroup_path):
        raise FileNotFoundError(
            f"Haplogroup data file not found at {haplogroup_path}. "
            "Please run haplogroup assignment (T017) first."
        )
    
    logger.info(f"Loading haplogroup data from {haplogroup_path}")
    df = pd.read_csv(haplogroup_path)
    logger.info(f"Loaded {len(df)} haplogroup records")
    return df

def load_metadata_panel():
    """Load the 1000 Genomes metadata panel containing age, sex, population, and PCs."""
    paths = get_local_paths()
    metadata_path = paths['metadata_csv']
    
    if not os.path.exists(metadata_path):
        raise FileNotFoundError(
            f"Metadata panel file not found at {metadata_path}. "
            "Please ensure metadata download (T012) has completed."
        )
    
    logger.info(f"Loading metadata panel from {metadata_path}")
    df = pd.read_csv(metadata_path)
    logger.info(f"Loaded {len(df)} metadata records")
    
    # Normalize column names for consistency (lowercase, strip spaces)
    df.columns = df.columns.str.lower().str.strip()
    
    # Ensure expected columns exist
    required_cols = ['sample_id', 'age', 'sex', 'population']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(
            f"Metadata panel missing required columns: {missing}. "
            f"Available columns: {list(df.columns)}"
        )
    
    return df

def merge_datasets(burden_df, haplogroup_df, metadata_df):
    """
    Join burden, haplogroups, age, sex, population, and PCs into a single dataset.
    
    Performs inner joins on 'sample_id' to ensure only samples present in all
    datasets are retained.
    
    Args:
        burden_df: DataFrame with heteroplasmy burden metrics
        haplogroup_df: DataFrame with haplogroup assignments
        metadata_df: DataFrame with age, sex, population, and PCs
        
    Returns:
        Merged DataFrame with all attributes aligned by sample_id
    """
    logger.info("Starting metadata merge operation")
    
    # Normalize sample_id column names if necessary
    for df in [burden_df, haplogroup_df, metadata_df]:
        if 'sample_id' not in df.columns and 'sampleid' in df.columns:
            df.rename(columns={'sampleid': 'sample_id'}, inplace=True)
        if 'sample_id' not in df.columns:
            raise ValueError("Sample ID column not found in one of the input dataframes")
    
    # Normalize sample_id to string for consistent merging
    burden_df['sample_id'] = burden_df['sample_id'].astype(str)
    haplogroup_df['sample_id'] = haplogroup_df['sample_id'].astype(str)
    metadata_df['sample_id'] = metadata_df['sample_id'].astype(str)
    
    # Merge burden with haplogroups
    merged = pd.merge(
        burden_df, 
        haplogroup_df, 
        on='sample_id', 
        how='inner',
        suffixes=('_burden', '_haplogroup')
    )
    logger.info(f"After merging burden + haplogroups: {len(merged)} samples")
    
    # Merge with metadata (age, sex, population, PCs)
    merged = pd.merge(
        merged,
        metadata_df,
        on='sample_id',
        how='inner'
    )
    logger.info(f"After merging with metadata: {len(merged)} samples")
    
    # Select and order final columns
    # Prioritize: sample_id, burden metrics, haplogroup, age, sex, population, PCs
    burden_cols = [c for c in merged.columns if 'burden' in c.lower() or c in ['depth_low', 'depth_med', 'depth_high']]
    pc_cols = [c for c in merged.columns if c.startswith('pc') or c.startswith('PC')]
    
    final_columns = ['sample_id'] + burden_cols + ['haplogroup'] + ['age', 'sex', 'population'] + pc_cols
    
    # Filter to only existing columns
    final_columns = [c for c in final_columns if c in merged.columns]
    
    merged = merged[final_columns]
    
    logger.info(f"Final merged dataset shape: {merged.shape}")
    logger.info(f"Final columns: {list(merged.columns)}")
    
    return merged

def main():
    """Main entry point for metadata merge task."""
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    ensure_dirs()
    
    try:
        burden_df = load_burden_data()
        haplogroup_df = load_haplogroup_data()
        metadata_df = load_metadata_panel()
        
        merged_df = merge_datasets(burden_df, haplogroup_df, metadata_df)
        
        paths = get_local_paths()
        output_path = paths['merged_csv']
        
        merged_df.to_csv(output_path, index=False)
        logger.info(f"Successfully wrote merged dataset to {output_path}")
        logger.info(f"Total samples in merged dataset: {len(merged_df)}")
        
    except Exception as e:
        logger.error(f"Failed to merge metadata: {e}")
        raise

if __name__ == "__main__":
    main()