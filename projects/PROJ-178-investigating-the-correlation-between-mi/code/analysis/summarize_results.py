import os
import sys
import logging
import pandas as pd
from pathlib import Path
from config.environment import ensure_directories

logger = logging.getLogger(__name__)

def load_model_results(input_path: str) -> pd.DataFrame:
    """
    Load the model results CSV generated by T024/T025.
    Expects columns: model_type, variable, coefficient, p_value, adj_p_value
    """
    if not os.path.exists(input_path):
        raise FileNotFoundError(f"Model results file not found at {input_path}")
    
    logger.info(f"Loading model results from {input_path}")
    df = pd.read_csv(input_path)
    
    # Validate expected columns
    required_cols = ['model_type', 'variable', 'coefficient', 'p_value', 'adj_p_value']
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"Model results missing required columns: {missing_cols}")
    
    return df

def extract_summary_statistics(df: pd.DataFrame) -> pd.DataFrame:
    """
    Extract summary statistics for the primary analysis (Rank-OLS).
    Filters for the main 'rank_burden' variable and returns a clean summary table.
    """
    logger.info("Extracting summary statistics for primary analysis")
    
    # Filter for Rank-OLS model results
    rank_ols_results = df[df['model_type'] == 'rank_ols'].copy()
    
    if rank_ols_results.empty:
        logger.warning("No Rank-OLS results found in input data")
        return pd.DataFrame()
    
    # Focus on the primary variable of interest: rank_burden
    # Also include key confounders for completeness
    primary_vars = ['rank_burden', 'sex', 'PC1', 'PC2', 'rank_depth']
    summary_df = rank_ols_results[rank_ols_results['variable'].isin(primary_vars)].copy()
    
    # Ensure numeric types
    for col in ['coefficient', 'p_value', 'adj_p_value']:
        summary_df[col] = pd.to_numeric(summary_df[col], errors='coerce')
    
    # Sort by variable name for consistent output
    summary_df = summary_df.sort_values('variable')
    
    return summary_df

def write_summary_statistics(summary_df: pd.DataFrame, output_path: str) -> None:
    """
    Write the summary statistics to the specified CSV file.
    """
    if summary_df.empty:
        logger.warning("No summary data to write; creating empty file with headers")
        pd.DataFrame(columns=['model_type', 'variable', 'coefficient', 'p_value', 'adj_p_value']).to_csv(output_path, index=False)
        return

    logger.info(f"Writing summary statistics to {output_path}")
    summary_df.to_csv(output_path, index=False)
    logger.info(f"Successfully wrote {len(summary_df)} rows to {output_path}")

def main():
    """
    Main entry point for T028: Generate summary statistics for analysis_results.csv.
    """
    # Setup logging
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    # Ensure output directories exist
    ensure_directories()
    
    # Define paths based on project structure
    input_path = "code/data/processed/model_results.csv"
    output_path = "code/data/processed/analysis_results.csv"
    
    try:
        # Load results
        df = load_model_results(input_path)
        
        # Extract summary statistics
        summary_df = extract_summary_statistics(df)
        
        # Write output
        write_summary_statistics(summary_df, output_path)
        
        logger.info("T028 completed successfully: analysis_results.csv generated")
        return 0
        
    except Exception as e:
        logger.error(f"T028 failed: {str(e)}")
        raise

if __name__ == "__main__":
    sys.exit(main())
