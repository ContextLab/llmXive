import os
import sys
import logging
import pandas as pd
from pathlib import Path
from config.environment import ensure_directories

logger = logging.getLogger(__name__)

def load_model_results(input_path: Path) -> pd.DataFrame:
    """
    Load the model results CSV generated by T024.
    Expects columns: term, coefficient, p_value, adj_p_value, model_type
    """
    if not input_path.exists():
        raise FileNotFoundError(f"Model results file not found at {input_path}")
    
    logger.info(f"Loading model results from {input_path}")
    df = pd.read_csv(input_path)
    
    required_cols = {'term', 'coefficient', 'p_value', 'adj_p_value'}
    if not required_cols.issubset(df.columns):
        missing = required_cols - set(df.columns)
        raise ValueError(f"Model results missing required columns: {missing}")
    
    return df

def extract_summary_statistics(df: pd.DataFrame) -> pd.DataFrame:
    """
    Extract the primary summary statistics for the analysis.
    Focuses on the 'burden' term from the Rank-OLS model and the Spearman correlation.
    
    Returns a DataFrame with one row per key metric:
    - rank_ols_burden_coef
    - rank_ols_burden_p_value
    - rank_ols_burden_adj_p_value
    - spearman_correlation (if available in a specific format, otherwise null)
    """
    summary_data = []

    # 1. Rank-OLS Burden Statistics
    # Filter for the burden term in the Rank-OLS model
    # Assuming 'model_type' column distinguishes 'rank_ols' from others if mixed
    # If the file only contains Rank-OLS results as per T024, we filter by term
    
    rank_ols_df = df[df['term'] == 'rank(burden)']
    
    if rank_ols_df.empty:
        # Fallback if term name differs slightly, e.g., just 'burden'
        rank_ols_df = df[df['term'] == 'burden']
    
    if not rank_ols_df.empty:
        row = rank_ols_df.iloc[0]
        summary_data.append({
            'metric': 'rank_ols_burden_coefficient',
            'value': row['coefficient'],
            'p_value': row['p_value'],
            'adj_p_value': row['adj_p_value'],
            'model': 'Rank-OLS'
        })
    else:
        logger.warning("Could not find 'rank(burden)' term in model results for summary.")

    # 2. Spearman Correlation (if stored in the same file)
    # T023 calculates it, T024 saves Rank-OLS. T025 adjusts p-values.
    # If T024 output includes the Spearman result as a row, we extract it.
    # Otherwise, we look for a specific row marker or skip if not present.
    spearman_row = df[df['term'] == 'spearman_correlation']
    if not spearman_row.empty:
        row = spearman_row.iloc[0]
        summary_data.append({
            'metric': 'spearman_correlation',
            'value': row['coefficient'],
            'p_value': row['p_value'],
            'adj_p_value': row.get('adj_p_value', row['p_value']), # Spearman usually unadjusted or BH adjusted
            'model': 'Spearman'
        })

    return pd.DataFrame(summary_data)

def write_summary_statistics(summary_df: pd.DataFrame, output_path: Path) -> None:
    """
    Write the summary statistics to the final analysis_results.csv.
    """
    ensure_directories([output_path.parent])
    
    logger.info(f"Writing summary statistics to {output_path}")
    summary_df.to_csv(output_path, index=False)
    logger.info("Summary statistics written successfully.")

def main():
    """
    Main entry point for T028: Generate summary statistics.
    Reads code/data/processed/model_results.csv and writes code/data/processed/analysis_results.csv
    """
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )

    # Define paths relative to project root (assuming code/analysis is current dir or we handle paths)
    # The task specifies: code/data/processed/model_results.csv -> code/data/processed/analysis_results.csv
    project_root = Path(__file__).resolve().parents[2]
    input_path = project_root / "code" / "data" / "processed" / "model_results.csv"
    output_path = project_root / "code" / "data" / "processed" / "analysis_results.csv"

    try:
        # 1. Load
        model_df = load_model_results(input_path)
        
        # 2. Extract
        summary_df = extract_summary_statistics(model_df)
        
        if summary_df.empty:
            logger.error("No summary statistics could be extracted. The model results file may be malformed or missing expected terms.")
            sys.exit(1)

        # 3. Write
        write_summary_statistics(summary_df, output_path)
        
        logger.info("Task T028 completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(f"Input file missing: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during summary generation: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
