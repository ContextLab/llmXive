import os
import sys
import logging
import hashlib
import pandas as pd
from pathlib import Path
from config.environment import get_local_paths

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler('code/logs/write_dataset.log')
    ]
)
logger = logging.getLogger(__name__)

def calculate_file_checksum(file_path: Path, algorithm: str = 'md5') -> str:
    """
    Calculate the checksum of a file.

    Args:
        file_path: Path to the file to checksum.
        algorithm: Hash algorithm to use (default: 'md5').

    Returns:
        Hex digest string of the file checksum.
    """
    hash_func = hashlib.new(algorithm)
    with open(file_path, 'rb') as f:
        # Read in chunks to handle large files
        for chunk in iter(lambda: f.read(8192), b''):
            hash_func.update(chunk)
    return hash_func.hexdigest()

def write_processed_dataset(df: pd.DataFrame, output_path: Path) -> str:
    """
    Write the processed dataset to a CSV file and generate a checksum.

    Args:
        df: The processed pandas DataFrame.
        output_path: Path where the CSV file will be saved.

    Returns:
        The checksum of the written file.

    Raises:
        FileNotFoundError: If the input DataFrame is empty or None.
        IOError: If the file cannot be written.
    """
    if df is None or df.empty:
        error_msg = "Cannot write dataset: Input DataFrame is empty or None."
        logger.error(error_msg)
        raise ValueError(error_msg)

    # Ensure the directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    logger.info(f"Writing dataset to {output_path} with shape {df.shape}")
    
    # Write to CSV
    df.to_csv(output_path, index=False)
    
    # Verify file exists and is not empty
    if not output_path.exists():
        raise IOError(f"Failed to write file to {output_path}")
    
    if output_path.stat().st_size == 0:
        raise IOError(f"Written file {output_path} is empty.")

    # Calculate checksum
    checksum = calculate_file_checksum(output_path)
    logger.info(f"Dataset written successfully. Checksum (MD5): {checksum}")
    
    return checksum

def main():
    """
    Main entry point for the write_dataset script.
    Loads the processed data (assumed to be generated by previous steps),
    writes it to the final CSV, and logs the checksum.
    """
    try:
        paths = get_local_paths()
        processed_dir = paths['processed']
        output_file = processed_dir / 'mito_aging_dataset.csv'

        # Load the intermediate dataset produced by T018 (merge_metadata)
        # We assume the merge step produced a CSV at the same location or a temp location
        # For this pipeline, we assume the data is currently in memory or a temp file.
        # However, to be robust, we look for the file generated by T018.
        # Since T018 was marked as needing redo, we assume the file exists now or
        # we load from the path specified in T018's output.
        
        # Fallback: If the file doesn't exist yet, we check if there's a temp file
        # But per instructions, we must read real data. We assume T018 produced the file.
        if not output_file.exists():
            # Try to find if it was written to a different temp location or if we need to re-run merge
            # For this specific task, we assume the previous step (T018) wrote to this path
            # If it's missing, we raise an error to fail loudly rather than synthesize.
            raise FileNotFoundError(
                f"Processed dataset not found at {output_file}. "
                "Ensure T018 (merge_metadata) has completed successfully."
            )

        logger.info(f"Loading dataset from {output_file}")
        df = pd.read_csv(output_file)

        # Re-write to ensure final format and generate checksum
        # This ensures the file is finalized and checksummed as per T020
        final_checksum = write_processed_dataset(df, output_file)

        # Log the checksum to a dedicated file for verification
        checksum_log_path = paths['processed'] / 'dataset_checksum.txt'
        with open(checksum_log_path, 'w') as f:
            f.write(f"File: {output_file.name}\n")
            f.write(f"MD5: {final_checksum}\n")
            f.write(f"Rows: {len(df)}\n")
            f.write(f"Columns: {len(df.columns)}\n")
        
        logger.info(f"Checksum log written to {checksum_log_path}")
        print(f"Task T020 Complete: Dataset written to {output_file} with checksum {final_checksum}")

    except Exception as e:
        logger.error(f"Error in write_dataset: {e}")
        raise

if __name__ == '__main__':
    main()
