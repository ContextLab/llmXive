"""
Script to save the processed feature matrix to a Parquet file.

This task (T018) implements the saving of the 2D descriptor matrix
generated by preprocess_2d.py to data/processed/descriptors.parquet.
"""
import os
import sys
import logging
import gc
from pathlib import Path

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from utils.logging_config import get_logger, set_log_level
from data.preprocess_2d import preprocess_2d

# Configure logging
logger = get_logger(__name__)
set_log_level(logging.INFO)

def main():
    """
    Main entry point for saving processed descriptors.
    
    1. Runs the preprocessing pipeline (T014-T017 logic).
    2. Saves the resulting DataFrame to data/processed/descriptors.parquet.
    3. Logs the shape and schema of the saved file.
    """
    logger.info("Starting T018: Saving processed feature matrix to Parquet.")
    
    # Define paths
    raw_dir = project_root / "data" / "raw"
    processed_dir = project_root / "data" / "processed"
    output_file = processed_dir / "descriptors.parquet"
    
    # Ensure output directory exists
    processed_dir.mkdir(parents=True, exist_ok=True)
    
    if not raw_dir.exists():
        logger.error(f"Raw data directory not found: {raw_dir}")
        logger.error("Please run T013 (download_qm9.py) to populate data/raw/ first.")
        return 1

    # Check if raw data files exist
    raw_files = list(raw_dir.glob("*.csv")) + list(raw_dir.glob("*.txt")) + list(raw_dir.glob("*.sdf"))
    if not raw_files:
        logger.error(f"No data files found in {raw_dir}.")
        logger.error("Please ensure QM9 data is downloaded and placed in data/raw/.")
        return 1

    logger.info(f"Found {len(raw_files)} data files in {raw_dir}.")

    try:
        # Run the preprocessing pipeline
        # This function handles:
        # - Loading SMILES from raw files
        # - Computing 2D descriptors (T014)
        # - Filtering high correlation features (T015)
        # - Handling NaNs (T016)
        # - Batch processing for memory efficiency (T017)
        logger.info("Running preprocess_2d pipeline...")
        df_processed = preprocess_2d(str(raw_dir))
        
        if df_processed is None or df_processed.empty:
            logger.error("Preprocessing resulted in an empty dataframe. Aborting save.")
            return 1

        logger.info(f"Preprocessing complete. Shape: {df_processed.shape}")
        logger.info(f"Columns: {list(df_processed.columns)}")

        # Save to Parquet
        logger.info(f"Saving to {output_file}...")
        df_processed.to_parquet(output_file, index=False, engine='pyarrow')
        
        # Verify file exists and is non-empty
        if output_file.exists() and output_file.stat().st_size > 0:
            logger.info(f"Successfully saved descriptors to {output_file}")
            logger.info(f"File size: {output_file.stat().st_size / (1024*1024):.2f} MB")
            return 0
        else:
            logger.error("Failed to save file or file is empty.")
            return 1

    except Exception as e:
        logger.exception(f"Error during preprocessing or saving: {e}")
        return 1
    finally:
        gc.collect()

if __name__ == "__main__":
    sys.exit(main())