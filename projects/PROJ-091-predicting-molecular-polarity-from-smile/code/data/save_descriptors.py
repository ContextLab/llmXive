# Columns to explicitly exclude (TPSA, SMARTS derived)
EXCLUDED_COLUMNS = {'TPSA', 'TPSA_E', 'TPSA_E2', 'TPSA_E3', 'TPSA_E4', 'TPSA_E5'}
# SMARTS patterns are not computed as columns in this pipeline, but we check for common derived names
SMARTS_DERIVED_PREFIXES = ('smarts_', 'fg_', 'functional_')

def verify_schema(df: pd.DataFrame) -> bool:
    """
    Verify the dataframe schema meets T018 requirements:
    - Contains 'smiles' (string) and 'target' (float)
    - Contains 2D descriptor columns (float)
    - Does NOT contain TPSA or SMARTS-derived columns
    - Total columns match expected count (no filtering applied)
    """
    required_cols = {'smiles', 'target'}
    if not required_cols.issubset(df.columns):
        logger.error(f"Schema missing required columns: {required_cols - set(df.columns)}")
        return False

    # Check for excluded columns
    found_excluded = EXCLUDED_COLUMNS.intersection(df.columns)
    if found_excluded:
        logger.error(f"Found excluded columns in output: {found_excluded}")
        return False

    # Check for SMARTS-derived prefixes
    smart_cols = [c for c in df.columns if c.lower().startswith(SMARTS_DERIVED_PREFIXES)]
    if smart_cols:
        logger.error(f"Found SMARTS-derived columns in output: {smart_cols}")
        return False

    # Verify types
    if df['smiles'].dtype != 'object' and df['smiles'].dtype.name != 'string':
        logger.warning(f"SMILES column type is {df['smiles'].dtype}, expected string/object")

    if not pd.api.types.is_float_dtype(df['target']):
        logger.error(f"Target column is {df['target'].dtype}, expected float")
        return False

    # Check descriptor columns are numeric
    descriptor_cols = [c for c in df.columns if c not in required_cols]
    if not descriptor_cols:
        logger.error("No descriptor columns found in output")
        return False

    for col in descriptor_cols:
        if not pd.api.types.is_numeric_dtype(df[col]):
            logger.warning(f"Column {col} is {df[col].dtype}, expected numeric")

    logger.info(f"Schema verification passed. Columns: {len(df.columns)} (smiles, target + {len(descriptor_cols)} descriptors)")
    return True

