"""
Task T035: Generate stability report verifying Jaccard ≥ 0.7.

This script loads the bootstrap results generated by previous tasks (T033a, T033b, T034a, T034b),
computes the final stability metrics (Jaccard similarity for clusters and individual features),
and generates a formal report.

It verifies that:
- Jaccard similarity for top feature clusters >= 0.7
- Jaccard similarity for top individual features >= 0.7

If either metric is below 0.7, it logs a failure message as required by the spec.
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional

# Add project root to path for imports
project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from utils.logging_config import get_logger, set_log_level
from models.stability_analysis import calculate_jaccard_similarity
from models.stability_report import load_bootstrap_results, generate_stability_report, save_report

def main():
    """
    Main entry point for T035.
    Loads bootstrap results, calculates Jaccard metrics, and generates the stability report.
    """
    # Setup logging
    logger = get_logger("stability_report")
    set_log_level(logging.INFO)

    # Define paths
    data_dir = project_root / "data" / "processed"
    analysis_dir = data_dir / "analysis"
    bootstrap_results_path = analysis_dir / "bootstrap_results.json"
    report_output_path = analysis_dir / "stability_report.json"

    # Ensure output directory exists
    analysis_dir.mkdir(parents=True, exist_ok=True)

    logger.info(f"Loading bootstrap results from {bootstrap_results_path}")
    
    if not bootstrap_results_path.exists():
        logger.error(f"Bootstrap results file not found at {bootstrap_results_path}. "
                     "Please ensure T033a/T033b have been executed successfully.")
        return 1

    try:
        # Load the bootstrap results
        bootstrap_data = load_bootstrap_results(bootstrap_results_path)
        
        if not bootstrap_data:
            logger.error("Bootstrap results are empty. Cannot generate stability report.")
            return 1

        logger.info("Calculating stability metrics...")
        
        # Extract cluster and individual feature sets from bootstrap data
        cluster_sets = bootstrap_data.get("cluster_sets", [])
        individual_sets = bootstrap_data.get("individual_sets", [])
        
        if not cluster_sets or not individual_sets:
            logger.warning("No cluster or individual sets found in bootstrap data. "
                         "Skipping metric calculation.")
            # Create a minimal report indicating failure due to missing data
            report = {
                "status": "failed",
                "reason": "No bootstrap data found for clusters or individual features",
                "cluster_jaccard": None,
                "individual_jaccard": None,
                "threshold": 0.7
            }
            save_report(report, report_output_path)
            return 1

        # Calculate Jaccard similarity for clusters
        cluster_jaccard = calculate_jaccard_similarity(cluster_sets)
        
        # Calculate Jaccard similarity for individual features
        individual_jaccard = calculate_jaccard_similarity(individual_sets)

        logger.info(f"Cluster Jaccard Similarity: {cluster_jaccard:.4f}")
        logger.info(f"Individual Feature Jaccard Similarity: {individual_jaccard:.4f}")

        # Verify against threshold (0.7)
        threshold = 0.7
        cluster_pass = cluster_jaccard >= threshold
        individual_pass = individual_jaccard >= threshold

        status = "passed" if (cluster_pass and individual_pass) else "failed"
        
        if not cluster_pass:
            logger.error(f"CRITICAL: Cluster stability Jaccard ({cluster_jaccard:.4f}) is below threshold ({threshold}).")
        if not individual_pass:
            logger.error(f"CRITICAL: Individual feature stability Jaccard ({individual_jaccard:.4f}) is below threshold ({threshold}).")

        # Generate the report
        report = generate_stability_report(
            cluster_jaccard=cluster_jaccard,
            individual_jaccard=individual_jaccard,
            threshold=threshold,
            status=status,
            details={
                "cluster_pass": cluster_pass,
                "individual_pass": individual_pass,
                "num_cluster_resamples": len(cluster_sets),
                "num_individual_resamples": len(individual_sets)
            }
        )

        # Save the report
        save_report(report, report_output_path)
        logger.info(f"Stability report saved to {report_output_path}")

        # Return exit code based on status
        return 0 if status == "passed" else 1

    except Exception as e:
        logger.exception(f"Error generating stability report: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())