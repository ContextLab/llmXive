    parser.add_argument("--splits", type=str, default="data/processed/splits", help="Path to splits directory")
    parser.add_argument("--config", type=str, default="code/config.yaml", help="Path to config file")
    parser.add_argument("--output", type=str, default="data/processed/model.pkl", help="Path to save model")
    parser.add_argument("--no-tuning", action="store_true", help="Skip hyperparameter tuning")
    parser.add_argument("--log-level", type=str, default="INFO", help="Logging level")

    args = parser.parse_args()

    set_log_level(args.log_level)

    data_path = Path(args.data)
    splits_path = Path(args.splits)
    config_path = Path(args.config)
    output_path = Path(args.output)

    if not data_path.exists():
        logger.error(f"Data file not found: {data_path}")
        sys.exit(1)
    if not splits_path.exists():
        logger.error(f"Splits directory not found: {splits_path}")
        sys.exit(1)
    if not config_path.exists():
        logger.error(f"Config file not found: {config_path}")
        sys.exit(1)

    try:
        train_lightgbm(
            data_path=data_path,
            splits_path=splits_path,
            config_path=config_path,
            output_model_path=output_path,
            do_tuning=not args.no_tuning
        )
    except Exception as e:
        logger.error(f"Training failed: {e}", exc_info=True)
        sys.exit(1)


