def load_data_from_splits(splits_path: Path, data_path: Path) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Loads feature matrices and target vectors from pre-computed split files.

    This function reads the training, validation, and test sets from Parquet files
    generated by the data splitting module. It ensures that the feature columns
    match across all splits and aligns them appropriately.

    Args:
        splits_path (Path): Path to the directory containing split metadata (e.g., 'train_idx.npy').
        data_path (Path): Path to the main descriptors Parquet file.

    Returns:
        Tuple containing:
            - X_train (pd.DataFrame): Training feature matrix.
            - X_val (pd.DataFrame): Validation feature matrix.
            - X_test (pd.DataFrame): Test feature matrix.
            - y_train (pd.Series): Training target vector.

    Raises:
        FileNotFoundError: If split files or data file are missing.
        ValueError: If data alignment fails or columns are mismatched.
    """
    logger.info(f"Loading data from splits at {splits_path} and data at {data_path}")

    if not data_path.exists():
        raise FileNotFoundError(f"Data file not found: {data_path}")

    # Load full dataset
    df = pd.read_parquet(data_path)

    # Load split indices
    train_idx = np.load(splits_path / "train_idx.npy")
    val_idx = np.load(splits_path / "val_idx.npy")
    test_idx = np.load(splits_path / "test_idx.npy")

    # Separate features and target
    # Assuming 'dipole_moment' is the target column based on project context
    target_col = "dipole_moment"
    if target_col not in df.columns:
        # Fallback for generic naming if 'dipole_moment' is not present
        # In a real run, this should be explicit or passed as an argument
        logger.warning(f"Target column '{target_col}' not found. Looking for 'target' or similar.")
        if "target" in df.columns:
            target_col = "target"
        else:
            raise ValueError(f"Could not identify target column in {df.columns}")

    feature_cols = [c for c in df.columns if c != target_col]

    X = df[feature_cols]
    y = df[target_col]

    X_train = X.iloc[train_idx]
    y_train = y.iloc[train_idx]

    X_val = X.iloc[val_idx]
    y_val = y.iloc[val_idx]

    X_test = X.iloc[test_idx]
    y_test = y.iloc[test_idx]

    logger.info(f"Loaded splits: Train={len(X_train)}, Val={len(X_val)}, Test={len(X_test)}")
    return X_train, X_val, X_test, y_train


def train_base_model(X: pd.DataFrame, y: pd.Series, params: Dict[str, Any], verbose: bool = True) -> lgb.Booster:
    """
    Trains a base LightGBM model with the provided hyperparameters.

    Args:
        X (pd.DataFrame): Feature matrix.
        y (pd.Series): Target vector.
        params (Dict[str, Any]): Hyperparameters for LightGBM.
        verbose (bool): If True, prints training progress.

    Returns:
        lgb.Booster: The trained LightGBM booster object.
    """
    logger.info("Training base LightGBM model...")
    train_data = lgb.Dataset(X, label=y)

    # Default params if not provided
    default_params = {
        "objective": "regression",
        "metric": "rmse",
        "boosting_type": "gbdt",
        "verbosity": -1 if not verbose else 1,
        "seed": 42  # Hardcoded for reproducibility as per config constraints
    }
    default_params.update(params)

    model = lgb.train(
        default_params,
        train_data,
        num_boost_round=1000,
        verbose_eval=verbose,
        callbacks=[lgb.early_stopping(stopping_rounds=50, verbose=False)] if verbose else []
    )

    logger.info("Base model training completed.")
    return model


def cross_validate_model(
    X: pd.DataFrame,
    y: pd.Series,
    params: Dict[str, Any],
    n_splits: int = 5,
    seed: int = 42
) -> Dict[str, float]:
    """
    Performs k-fold cross-validation to estimate model generalization performance.

    This function splits the data into K folds, trains a model on K-1 folds,
    and evaluates on the held-out fold. It returns the mean and standard deviation
    of the R² score across all folds.

    Args:
        X (pd.DataFrame): Feature matrix.
        y (pd.Series): Target vector.
        params (Dict[str, Any]): Hyperparameters for LightGBM.
        n_splits (int): Number of CV folds.
        seed (int): Random seed for shuffling.

    Returns:
        Dict[str, float]: Dictionary containing 'mean_r2' and 'std_r2'.
    """
    logger.info(f"Starting {n_splits}-fold cross-validation...")

    kf = KFold(n_splits=n_splits, shuffle=True, random_state=seed)
    r2_scores = []

    for fold_idx, (train_idx, val_idx) in enumerate(kf.split(X)):
        X_tr, X_val = X.iloc[train_idx], X.iloc[val_idx]
        y_tr, y_val = y.iloc[train_idx], y.iloc[val_idx]

        train_data = lgb.Dataset(X_tr, label=y_tr)
        val_data = lgb.Dataset(X_val, label=y_val, reference=train_data)

        # Use minimal params for CV speed
        cv_params = params.copy()
        cv_params["verbose"] = -1
        cv_params["seed"] = seed

        model = lgb.train(
            cv_params,
            train_data,
            num_boost_round=1000,
            valid_sets=[val_data],
            verbose_eval=False,
            callbacks=[lgb.early_stopping(stopping_rounds=20, verbose=False)]
        )

        preds = model.predict(X_val)
        r2 = r2_score(y_val, preds)
        r2_scores.append(r2)

        logger.debug(f"Fold {fold_idx + 1} R²: {r2:.4f}")

    mean_r2 = np.mean(r2_scores)
    std_r2 = np.std(r2_scores)

    logger.info(f"Cross-validation complete. Mean R²: {mean_r2:.4f} (+/- {std_r2:.4f})")
    return {"mean_r2": mean_r2, "std_r2": std_r2}


def tune_hyperparameters(
    X: pd.DataFrame,
    y: pd.Series,
    base_params: Dict[str, Any],
    param_grid: Optional[Dict[str, List]] = None,
    n_splits: int = 5
) -> Tuple[Dict[str, Any], float]:
    """
    Performs hyperparameter tuning using cross-validation.

    Searches through a grid of hyperparameters (specifically 'num_leaves' and
    'learning_rate') to find the combination that maximizes the mean R² score
    from cross-validation.

    Args:
        X (pd.DataFrame): Feature matrix.
        y (pd.Series): Target vector.
        base_params (Dict[str, Any]): Base hyperparameters.
        param_grid (Dict[str, List], optional): Grid of parameters to search.
        n_splits (int): Number of CV folds.

    Returns:
        Tuple containing:
            - best_params (Dict[str, Any]): Optimal hyperparameters.
            - best_score (float): The best mean R² score found.
    """
    logger.info("Starting hyperparameter tuning...")

    if param_grid is None:
        # Default grid for LightGBM tuning
        param_grid = {
            "num_leaves": [31, 63, 127],
            "learning_rate": [0.01, 0.05, 0.1],
            "feature_fraction": [0.8, 0.9, 1.0]
        }

    best_score = -np.inf
    best_params = base_params.copy()

    # Generate combinations
    import itertools
    keys = param_grid.keys()
    values = param_grid.values()

    for combination in itertools.product(*values):
        current_params = base_params.copy()
        for i, key in enumerate(keys):
            current_params[key] = combination[i]

        # Run CV
        cv_results = cross_validate_model(X, y, current_params, n_splits=n_splits)
        mean_r2 = cv_results["mean_r2"]

        logger.info(f"Params: {current_params} -> Mean R²: {mean_r2:.4f}")

        if mean_r2 > best_score:
            best_score = mean_r2
            best_params = current_params

    logger.info(f"Tuning complete. Best params: {best_params}, Best R²: {best_score:.4f}")
    return best_params, best_score


def evaluate_model(model: lgb.Booster, X_test: pd.DataFrame, y_test: pd.Series) -> Dict[str, float]:
    """
    Evaluates the trained model on a test set.

    Computes R² and RMSE metrics to assess the model's predictive performance
    on unseen data.

    Args:
        model (lgb.Booster): Trained LightGBM model.
        X_test (pd.DataFrame): Test feature matrix.
        y_test (pd.Series): Test target vector.

    Returns:
        Dict[str, float]: Dictionary containing 'r2' and 'rmse'.
    """
    logger.info("Evaluating model on test set...")
    preds = model.predict(X_test)

    r2 = r2_score(y_test, preds)
    rmse = np.sqrt(mean_squared_error(y_test, preds))

    logger.info(f"Test Results - R²: {r2:.4f}, RMSE: {rmse:.4f}")
    return {"r2": r2, "rmse": rmse}


def save_model(model: lgb.Booster, params: Dict[str, Any], output_path: Path) -> None:
    """
    Saves the trained model and its metadata to disk.

    Serializes the LightGBM booster and a dictionary containing training
    metadata (parameters, timestamp, etc.) into a single pickle file.

    Args:
        model (lgb.Booster): The trained LightGBM model.
        params (Dict[str, Any]): Hyperparameters used for training.
        output_path (Path): Destination path for the model file.
    """
    logger.info(f"Saving model to {output_path}")
    output_path.parent.mkdir(parents=True, exist_ok=True)

    metadata = {
        "model": model,
        "params": params,
        "training_timestamp": str(pd.Timestamp.now()),
        "version": "1.0.0"
    }

    with open(output_path, "wb") as f:
        pickle.dump(metadata, f)

    logger.info("Model saved successfully.")


def update_config_with_params(config_path: Path, params: Dict[str, Any]) -> None:
    """
    Updates the project configuration file with optimal hyperparameters.

    Writes the tuned hyperparameters (num_leaves, learning_rate, etc.) to
    the YAML configuration file for downstream reproducibility.

    Args:
        config_path (Path): Path to the config.yaml file.
        params (Dict[str, Any]): Dictionary of hyperparameters to save.
    """
    logger.info(f"Updating config at {config_path} with optimal parameters...")
    import yaml

    if not config_path.exists():
        logger.warning(f"Config file {config_path} not found. Creating new one.")
        config_data = {"hyperparameters": {}}
    else:
        with open(config_path, "r") as f:
            config_data = yaml.safe_load(f) or {}

    if "hyperparameters" not in config_data:
        config_data["hyperparameters"] = {}

    # Update specific tuning parameters
    for key in ["num_leaves", "learning_rate", "feature_fraction"]:
        if key in params:
            config_data["hyperparameters"][key] = params[key]

    with open(config_path, "w") as f:
        yaml.dump(config_data, f, default_flow_style=False)

    logger.info("Configuration updated successfully.")


def train_lightgbm(
    data_path: Path,
    splits_path: Path,
    config_path: Path,
    output_model_path: Path,
    do_tuning: bool = True,
    tuning_params: Optional[Dict[str, List]] = None
) -> None:
    """
    Orchestrates the full LightGBM training pipeline.

    This function performs the following steps:
    1. Loads data from pre-computed splits.
    2. Loads base hyperparameters from config.
    3. Optionally tunes hyperparameters via cross-validation.
    4. Trains the final model on the full training set.
    5. Evaluates the model on the test set.
    6. Saves the model and updates the config.

    Args:
        data_path (Path): Path to the descriptors Parquet file.
        splits_path (Path): Path to the directory containing split indices.
        config_path (Path): Path to the YAML configuration file.
        output_model_path (Path): Path where the trained model will be saved.
        do_tuning (bool): Whether to perform hyperparameter tuning.
        tuning_params (Dict[str, List], optional): Grid for hyperparameter search.
    """
    logger.info("Starting LightGBM training pipeline...")

    # 1. Load Data
    X_train, X_val, X_test, y_train = load_data_from_splits(splits_path, data_path)

    # 2. Load Base Params
