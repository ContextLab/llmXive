"""
LightGBM Model Training Module for Molecular Polarity Prediction.

This module implements the training pipeline for predicting molecular dipole moments
(polarity) from 2D molecular descriptors generated from SMILES strings. It supports
base model training, cross-validation, hyperparameter tuning, and model evaluation
using the LightGBM gradient boosting framework.

The implementation strictly adheres to 2D-only constraints, ensuring no 3D conformer
generation or 3D-dependent descriptors are used during the training process.

Functions:
    load_data_from_splits: Loads training and validation data from pre-computed splits.
    train_base_model: Trains a LightGBM regressor with default or provided parameters.
    cross_validate_model: Performs k-fold cross-validation to estimate model performance.
    tune_hyperparameters: Searches for optimal hyperparameters using cross-validation.
    evaluate_model: Computes performance metrics (R², RMSE) on a test set.
    save_model: Serializes the trained model and metadata to disk.
    update_config_with_params: Writes optimal parameters back to the configuration file.
    train_lightgbm: Orchestrates the full training, tuning, and evaluation workflow.
"""

