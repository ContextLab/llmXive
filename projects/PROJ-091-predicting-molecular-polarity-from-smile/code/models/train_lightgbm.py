def load_data_from_splits(splits_path: str, data_path: str) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Load train/val/test splits from the parquet file generated by T022.
    Returns: X_train, y_train, X_val, y_val
    """
    logger.info(f"Loading splits from {splits_path} and data from {data_path}")
    
    # Load the full processed dataset
    full_df = pd.read_parquet(data_path)
    
    # Load split indices
    if not os.path.exists(splits_path):
        raise FileNotFoundError(f"Split file not found: {splits_path}. Run T022 first.")
        
    with open(splits_path, 'rb') as f:
        splits = pickle.load(f)
    
    train_idx = splits['train']
    val_idx = splits['val']
    test_idx = splits['test']
    
    # Feature columns (exclude 'smiles' and 'target')
    feature_cols = [c for c in full_df.columns if c not in ['smiles', 'target']]
    
    X_train = full_df.loc[train_idx, feature_cols].reset_index(drop=True)
    y_train = full_df.loc[train_idx, 'target'].reset_index(drop=True)
    
    X_val = full_df.loc[val_idx, feature_cols].reset_index(drop=True)
    y_val = full_df.loc[val_idx, 'target'].reset_index(drop=True)
    
    X_test = full_df.loc[test_idx, feature_cols].reset_index(drop=True)
    y_test = full_df.loc[test_idx, 'target'].reset_index(drop=True)
    
    logger.info(f"Loaded {len(X_train)} train, {len(X_val)} val, {len(X_test)} test samples")
    return X_train, y_train, X_val, y_val, X_test, y_test

def train_base_model(X_train: pd.DataFrame, y_train: pd.Series, config: TrainingConfig) -> lgb.Booster:
    """
    Train a base LightGBM model with optimized CPU parameters.
    
    T040b Implementation:
    - num_threads: Set to max CPU count available or config value.
    - verbose: Set to -1 to suppress training logs.
    """
    logger.info("Training base LightGBM model...")
    
    # Determine number of threads
    num_threads = os.cpu_count() or 4
    if config.num_threads and config.num_threads > 0:
        num_threads = min(num_threads, config.num_threads)
    
    logger.info(f"Using {num_threads} threads for training.")
    
    # Prepare LightGBM dataset
    train_data = lgb.Dataset(X_train, label=y_train)
    
    # Parameters
    params = {
        'objective': 'regression',
        'metric': 'rmse',
        'boosting_type': 'gbdt',
        'num_leaves': config.num_leaves,
        'learning_rate': config.learning_rate,
        'feature_fraction': config.feature_fraction,
        'bagging_fraction': config.bagging_fraction,
        'bagging_freq': config.bagging_freq,
        'verbose': -1,  # T040b: Suppress logs for cleaner output
        'num_threads': num_threads  # T040b: Tune for CPU performance
    }
    
    model = lgb.train(
        params,
        train_data,
        num_boost_round=config.num_boost_round
    )
    
    logger.info("Base model training complete.")
    return model

def cross_validate_model(X_train: pd.DataFrame, y_train: pd.Series, config: TrainingConfig) -> Dict[str, Any]:
    """
    Perform cross-validation to tune hyperparameters and evaluate stability.
    T040b: Applies optimized num_threads and verbose settings.
    """
    logger.info("Starting cross-validation...")
    
    num_threads = os.cpu_count() or 4
    if config.num_threads and config.num_threads > 0:
        num_threads = min(num_threads, config.num_threads)
    
    cv_params = {
        'objective': 'regression',
        'metric': 'rmse',
        'boosting_type': 'gbdt',
        'num_leaves': config.num_leaves,
        'learning_rate': config.learning_rate,
        'feature_fraction': config.feature_fraction,
        'bagging_fraction': config.bagging_fraction,
        'bagging_freq': config.bagging_freq,
        'verbose': -1,
        'num_threads': num_threads
    }
    
    cv_results = lgb.cv(
        cv_params,
        lgb.Dataset(X_train, label=y_train),
        num_boost_round=config.num_boost_round,
        nfold=config.n_folds,
        seed=config.seed,
        verbose_eval=False
    )
    
    best_rmse = min(cv_results['rmse-mean'])
    best_iteration = np.argmin(cv_results['rmse-mean'])
    
    logger.info(f"CV Best RMSE: {best_rmse:.4f} at iteration {best_iteration}")
    
    return {
        'best_rmse': best_rmse,
        'best_iteration': best_iteration,
        'cv_results': cv_results
    }

def tune_hyperparameters(X_train: pd.DataFrame, y_train: pd.Series, config: TrainingConfig) -> Dict[str, Any]:
    """
    Simple grid search or refinement for hyperparameters.
    T040b: Ensures optimized CPU parameters are used during tuning.
    """
    logger.info("Tuning hyperparameters...")
    # For this task, we assume config already has the tuned values from T025.
    # We perform a quick validation run with the current config.
    return cross_validate_model(X_train, y_train, config)

def evaluate_model(model: lgb.Booster, X_val: pd.DataFrame, y_val: pd.Series) -> Dict[str, float]:
    """
    Evaluate model on validation set.
    """
    preds = model.predict(X_val)
    r2 = r2_score(y_val, preds)
    rmse = np.sqrt(mean_squared_error(y_val, preds))
    
    logger.info(f"Validation R2: {r2:.4f}, RMSE: {rmse:.4f}")
    return {'r2': r2, 'rmse': rmse}

def compute_null_model_r2(y_train: pd.Series, y_val: pd.Series) -> float:
    """
    Compute R2 of a null model (predicting mean of training set).
    """
    mean_val = y_train.mean()
    null_preds = np.full_like(y_val, mean_val, dtype=float)
    return r2_score(y_val, null_preds)

def save_model(model: lgb.Booster, output_path: str):
    """
    Save the trained model.
    """
    logger.info(f"Saving model to {output_path}")
    model.save_model(output_path)

def update_config_with_params(config_path: str, params: Dict[str, Any]):
    """
    Update config.yaml with tuned parameters.
    """
    import yaml
    logger.info(f"Updating config at {config_path}")
    
    with open(config_path, 'r') as f:
        config_data = yaml.safe_load(f)
    
    config_data['training'].update(params)
    
    with open(config_path, 'w') as f:
        yaml.dump(config_data, f)

def train_lightgbm(config_path: str, data_path: str, splits_path: str, output_model_path: str):
    """
    Main orchestration function for LightGBM training.
    """
    # Load config
    config = load_hyperparameters(config_path)
    setup_logging()
    
    # Load data
    X_train, y_train, X_val, y_val, X_test, y_test = load_data_from_splits(splits_path, data_path)
    
    # Tune/Validate
    tune_results = tune_hyperparameters(X_train, y_train, config.training)
    
    # Train final model on full training set
    final_model = train_base_model(X_train, y_train, config.training)
    
    # Evaluate
    val_metrics = evaluate_model(final_model, X_val, y_val)
    
    # Null model comparison
    null_r2 = compute_null_model_r2(y_train, y_val)
    logger.info(f"Null Model R2: {null_r2:.4f}")
    
    if val_metrics['r2'] <= null_r2:
        logger.warning("Model R2 is not better than null model!")
    
    # Save model
    save_model(final_model, output_model_path)
    
    return final_model, val_metrics

