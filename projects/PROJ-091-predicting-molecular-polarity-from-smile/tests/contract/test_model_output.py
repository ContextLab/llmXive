"""
Contract test for the model evaluation output.

The test loads the JSON file generated by the evaluation step and
validates its contents against the ``ModelOutput`` Pydantic model.
"""

import json
import pathlib
import pytest

from llmxive_toolkit import paths
from .validators import ModelOutput

def _find_model_output_path() -> pathlib.Path:
    """
    Locate the model output JSON. The pipeline may write the file to one
    of two standard locations; this helper checks both.
    """
    possible_paths = [
        paths.results("model_metrics.json"),
        paths.data("processed", "analysis", "evaluation.json"),
    ]
    for p in possible_paths:
        if p.exists():
            return p
    raise FileNotFoundError(
        "Model output JSON not found in any of the expected locations."
    )

def test_model_output_schema():
    """
    Validate that the model evaluation JSON conforms to the expected schema.
    """
    output_path = _find_model_output_path()
    with open(output_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    # Pydantic validation – will raise ValidationError on failure.
    ModelOutput(**data)
