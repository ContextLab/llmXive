"""
Contract test for the VIF scores generated by T105.

It validates that the CSV file conforms to the expected schema
(columns: feature, vif, fallback_triggered) and that at least
150 descriptor columns remain after pruning (unless fallback was triggered).
"""

import csv
import pathlib

import pytest

from utils.logging_config import get_logger

logger = get_logger(__name__)

@pytest.fixture
def vif_csv_path():
    return pathlib.Path(__file__).parents[3] / "data" / "processed" / "vif_scores.csv"

def test_vif_schema(vif_csv_path):
    assert vif_csv_path.exists(), f"VIF scores file missing: {vif_csv_path}"
    with open(vif_csv_path, newline="") as f:
        reader = csv.DictReader(f)
        required_fields = {"feature", "vif", "fallback_triggered"}
        assert set(reader.fieldnames) >= required_fields, (
            f"VIF CSV must contain at least columns {required_fields}"
        )
        rows = list(reader)
        assert len(rows) > 0, "VIF CSV appears to be empty"

def test_descriptor_count_after_pruning():
    """
    Ensure that after feature selection at least 150 descriptor columns remain
    (unless fallback was triggered, in which case the original count is kept).
    """
    import pandas as pd

    descriptors_path = pathlib.Path(__file__).parents[3] / "data" / "processed" / "descriptors.parquet"
    vif_path = pathlib.Path(__file__).parents[3] / "data" / "processed" / "vif_scores.csv"

    df = pd.read_parquet(descriptors_path)
    with open(vif_path, newline="") as f:
        reader = csv.DictReader(f)
        fallback = any(row["fallback_triggered"].lower() == "true" for row in reader)

    # Identify descriptor columns (those not 'smiles' or target columns)
    non_feature = {"smiles", "dipole_moment", "target"}
    descriptor_cols = [c for c in df.columns if c not in non_feature]

    if fallback:
        # In fallback mode we retain the original set
        assert len(descriptor_cols) >= 150, (
            f"Fallback mode requires at least 150 descriptors, found {len(descriptor_cols)}"
        )
    else:
        assert len(descriptor_cols) >= 150, (
            f"After VIF pruning we expect ≥150 descriptors, found {len(descriptor_cols)}"
        )