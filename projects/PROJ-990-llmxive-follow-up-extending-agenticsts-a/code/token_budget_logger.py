"""
Task T056: Implement Robust Token Budget Logging.

Enhances the simulation process to log detailed token budget information for each trajectory.
Reads simulation logs (dynamic and static) generated by T017/T019, calculates savings,
and writes a detailed CSV report.

Output: data/processed/token_budget_detailed.csv
Columns: trajectory_id, initial_tokens, selected_layers, final_tokens, layers_pruned, pruning_reason
"""

import os
import json
import logging
import csv
from pathlib import Path
from typing import List, Dict, Any, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Constants
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
DYNAMIC_LOGS_PATH = DATA_PROCESSED_DIR / "simulation_logs_dynamic.json"
STATIC_LOGS_PATH = DATA_PROCESSED_DIR / "simulation_logs_static.json"
OUTPUT_PATH = DATA_PROCESSED_DIR / "token_budget_detailed.csv"

# Ensure output directory exists
DATA_PROCESSED_DIR.mkdir(parents=True, exist_ok=True)

def load_simulation_logs(file_path: Path) -> List[Dict[str, Any]]:
    """Load simulation logs from a JSON file."""
    if not file_path.exists():
        raise FileNotFoundError(f"Simulation log file not found: {file_path}")
    
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # Handle both list and dict with 'trajectories' key
    if isinstance(data, list):
        return data
    elif isinstance(data, dict) and 'trajectories' in data:
        return data['trajectories']
    else:
        raise ValueError(f"Unexpected format in {file_path}: expected list or dict with 'trajectories' key")

def get_trajectory_lookup(logs: List[Dict[str, Any]], key: str = 'trajectory_id') -> Dict[str, Dict[str, Any]]:
    """Create a lookup dictionary by trajectory ID."""
    lookup = {}
    for entry in logs:
        tid = entry.get(key)
        if tid:
            lookup[tid] = entry
    return lookup

def estimate_tokens_for_layers(layers: List[Dict[str, Any]]) -> int:
    """
    Estimate total tokens for a list of layer objects.
    Assumes each layer object has a 'token_count' or 'estimated_tokens' field.
    Falls back to len(content) if token count is missing (rough estimate).
    """
    total = 0
    for layer in layers:
        if 'token_count' in layer:
            total += layer['token_count']
        elif 'estimated_tokens' in layer:
            total += layer['estimated_tokens']
        elif 'content' in layer:
            # Rough estimate: 1 token ~= 4 characters
            total += len(str(layer['content'])) // 4
        else:
            total += 100  # Default placeholder if no info
    return total

def process_budget_data(dynamic_logs: List[Dict[str, Any]], static_logs: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Process dynamic and static logs to generate detailed token budget records.
    """
    dynamic_lookup = get_trajectory_lookup(dynamic_logs)
    static_lookup = get_trajectory_lookup(static_logs)

    results = []

    # Iterate over dynamic logs as the primary source (since it has pruning info)
    for dyn_entry in dynamic_logs:
        tid = dyn_entry.get('trajectory_id')
        if not tid:
            logger.warning(f"Skipping entry without trajectory_id in dynamic logs")
            continue

        static_entry = static_lookup.get(tid)
        if not static_entry:
            logger.warning(f"No matching static entry for trajectory {tid}; skipping")
            continue

        # Extract data
        dyn_layers = dyn_entry.get('selected_layers', [])
        static_layers = static_entry.get('all_layers', [])
        
        # Calculate token counts
        initial_tokens = estimate_tokens_for_layers(static_layers)
        final_tokens = estimate_tokens_for_layers(dyn_layers)
        
        # Identify selected layer names
        selected_layer_names = [l.get('name', l.get('layer_name', 'unknown')) for l in dyn_layers]
        
        # Determine pruning details
        layers_pruned_count = max(0, len(static_layers) - len(dyn_layers))
        pruning_reason = dyn_entry.get('pruning_reason', 'none')
        
        # If no pruning occurred but tokens were high, note it
        if layers_pruned_count == 0 and initial_tokens > 4096:
            pruning_reason = "budget_exceeded_no_prune_available"
        elif layers_pruned_count > 0 and not pruning_reason:
            pruning_reason = "budget_constraint"

        record = {
            'trajectory_id': tid,
            'initial_tokens': initial_tokens,
            'selected_layers': json.dumps(selected_layer_names), # Store as JSON string for CSV compatibility
            'final_tokens': final_tokens,
            'layers_pruned': layers_pruned_count,
            'pruning_reason': pruning_reason
        }
        results.append(record)

    return results

def write_csv_report(records: List[Dict[str, Any]], output_path: Path):
    """Write the detailed token budget report to CSV."""
    if not records:
        logger.warning("No records to write. Creating empty CSV with headers.")
    
    fieldnames = ['trajectory_id', 'initial_tokens', 'selected_layers', 'final_tokens', 'layers_pruned', 'pruning_reason']
    
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(records)
    
    logger.info(f"Wrote {len(records)} records to {output_path}")

def main():
    """Main entry point for T056."""
    logger.info("Starting T056: Token Budget Detailed Logging")

    try:
        # 1. Load logs
        logger.info(f"Loading dynamic logs from {DYNAMIC_LOGS_PATH}")
        dynamic_logs = load_simulation_logs(DYNAMIC_LOGS_PATH)
        logger.info(f"Loaded {len(dynamic_logs)} dynamic trajectory entries")

        logger.info(f"Loading static logs from {STATIC_LOGS_PATH}")
        static_logs = load_simulation_logs(STATIC_LOGS_PATH)
        logger.info(f"Loaded {len(static_logs)} static trajectory entries")

        # 2. Process data
        records = process_budget_data(dynamic_logs, static_logs)
        logger.info(f"Processed {len(records)} budget records")

        # 3. Write output
        write_csv_report(records, OUTPUT_PATH)

        logger.info("T056 completed successfully.")
        return 0

    except FileNotFoundError as e:
        logger.error(f"Missing required input file: {e}")
        logger.error("Ensure T017 (Dynamic Simulation) and T019 (Static Baseline) have run successfully.")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during T056 execution: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    exit(main())