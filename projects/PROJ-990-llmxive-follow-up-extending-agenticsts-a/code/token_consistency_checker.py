"""
T023: Token Consistency Checker

Calculates the standard deviation of token savings across the test set
for the Dynamic policy to address SC-004.

Input: data/processed/baseline_comparison.csv
Output: data/processed/token_consistency_report.json
"""
import os
import json
import logging
import pandas as pd
import numpy as np
from pathlib import Path
from typing import Dict, Any, Optional

# Configure logging to file as per project standards
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.FileHandler('data/processed/token_consistency_checker.log'),
        logging.StreamHandler()
    ]
)
logger = logging.getLogger(__name__)

INPUT_PATH = Path("data/processed/baseline_comparison.csv")
OUTPUT_PATH = Path("data/processed/token_consistency_report.json")

def load_baseline_comparison() -> pd.DataFrame:
    """
    Loads the baseline comparison CSV generated by T022.
    Expects columns: condition, win_rate, avg_tokens, std_dev_tokens.
    """
    if not INPUT_PATH.exists():
        raise FileNotFoundError(
            f"Input file not found: {INPUT_PATH}. "
            "Ensure T022 (generate_baseline_comparison) has run successfully."
        )
    
    df = pd.read_csv(INPUT_PATH)
    logger.info(f"Loaded baseline comparison with {len(df)} rows.")
    logger.info(f"Columns: {list(df.columns)}")
    
    required_cols = ['condition', 'avg_tokens']
    for col in required_cols:
        if col not in df.columns:
            raise ValueError(f"Missing required column '{col}' in {INPUT_PATH}")
    
    return df

def calculate_token_savings_consistency(df: pd.DataFrame) -> Dict[str, Any]:
    """
    Calculates the standard deviation of token savings.
    
    Logic:
    1. Identify 'Dynamic' and 'Static' rows.
    2. Calculate token savings = Static_avg_tokens - Dynamic_avg_tokens.
    3. Since the input is aggregated (mean/std per condition), we cannot
       calculate per-trajectory savings directly from this file.
       
    However, T022's schema includes 'std_dev_tokens' which represents
    the standard deviation of token usage *within* that condition.
    
    To satisfy SC-004 (token reduction consistency), we interpret the
    requirement as checking the stability of the Dynamic policy's token usage.
    Specifically, we look at the 'std_dev_tokens' of the Dynamic policy.
    A high std_dev implies inconsistent token usage (high variance in savings).
    
    If the task implies comparing the *variance* of savings, we would need
    the raw simulation logs (T017) to compute per-trajectory savings.
    Given the input is T022's aggregate CSV, we report the Dynamic policy's
    token usage standard deviation as the consistency metric.
    
    Returns:
        dict: {
            'std_dev_tokens': float,
            'passed': bool (True if std_dev < threshold, e.g., 500 tokens),
            'dynamic_avg_tokens': float,
            'static_avg_tokens': float,
            'savings_mean': float
        }
    """
    if df.empty:
        raise ValueError("Input DataFrame is empty.")

    dynamic_row = df[df['condition'] == 'dynamic']
    static_row = df[df['condition'] == 'static']

    if dynamic_row.empty:
        raise ValueError("No 'dynamic' condition found in input data.")
    if static_row.empty:
        logger.warning("No 'static' condition found. Cannot calculate savings mean.")
        static_avg = None
    else:
        static_avg = static_row['avg_tokens'].iloc[0]

    dynamic_avg = dynamic_row['avg_tokens'].iloc[0]
    dynamic_std = dynamic_row['std_dev_tokens'].iloc[0]

    savings_mean = None
    if static_avg is not None:
        savings_mean = static_avg - dynamic_avg

    # Threshold for consistency (SC-004): e.g., std_dev < 500 tokens
    # This is a heuristic threshold; in a real study, this would be statistically derived.
    THRESHOLD = 500.0 
    passed = dynamic_std < THRESHOLD

    return {
        'std_dev_tokens': float(dynamic_std),
        'dynamic_avg_tokens': float(dynamic_avg),
        'static_avg_tokens': float(static_avg) if static_avg else None,
        'savings_mean': float(savings_mean) if savings_mean else None,
        'threshold': THRESHOLD,
        'passed': passed
    }

def generate_consistency_report(metrics: Dict[str, Any]) -> None:
    """
    Writes the consistency report to the output JSON file.
    """
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    
    with open(OUTPUT_PATH, 'w', encoding='utf-8') as f:
        json.dump(metrics, f, indent=2)
    
    logger.info(f"Consistency report written to {OUTPUT_PATH}")
    logger.info(f"Consistency Check Result: {'PASSED' if metrics['passed'] else 'FAILED'}")
    logger.info(f"  - Dynamic Std Dev: {metrics['std_dev_tokens']:.2f} tokens")
    logger.info(f"  - Threshold: {metrics['threshold']} tokens")

def main():
    """
    Main entry point for T023.
    """
    try:
        logger.info("Starting T023: Token Consistency Check")
        
        # 1. Load Data
        df = load_baseline_comparison()
        
        # 2. Calculate Consistency
        metrics = calculate_token_savings_consistency(df)
        
        # 3. Write Output
        generate_consistency_report(metrics)
        
        logger.info("T023 completed successfully.")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"Data missing: {e}")
        return 1
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    exit(main())