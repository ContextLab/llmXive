"""
Stream & Save ERA5 Chunks (Task T002d)

Processes tiles from T002c, streams them to Parquet, and concatenates them.
Handles missing artifacts by re-executing the fetch with deterministic parameters.
"""
import os
import sys
import json
import logging
import time
from pathlib import Path
from typing import List, Dict, Any, Optional

import pandas as pd
import pyarrow as pa
import pyarrow.parquet as pq

# Project root relative to this file
PROJECT_ROOT = Path(__file__).resolve().parent.parent

# Paths
FETCH_STATUS_PATH = PROJECT_ROOT / "results" / "logs" / "fetch_status.json"
RAW_CHUNKS_DIR = PROJECT_ROOT / "data" / "raw" / "era5_raw_chunks"
OUTPUT_PARQUET_PATH = PROJECT_ROOT / "data" / "raw" / "era5_full.parquet"
LOG_FILE = PROJECT_ROOT / "results" / "logs" / "bbox_status.json"

# Ensure logging is configured
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s",
    handlers=[
        logging.FileHandler(LOG_FILE),
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)


def ensure_directories():
    """Ensure required directories exist."""
    RAW_CHUNKS_DIR.mkdir(parents=True, exist_ok=True)
    OUTPUT_PARQUET_PATH.parent.mkdir(parents=True, exist_ok=True)
    logger.info(f"Ensured directories: {RAW_CHUNKS_DIR}, {OUTPUT_PARQUET_PATH.parent}")


def load_fetch_status() -> List[Dict[str, Any]]:
    """Load the fetch status JSON generated by T002c."""
    if not FETCH_STATUS_PATH.exists():
        raise FileNotFoundError(
            f"Fetch status file not found at {FETCH_STATUS_PATH}. "
            "Run T002c (fetch_era_full.py) first."
        )
    
    with open(FETCH_STATUS_PATH, "r") as f:
        data = json.load(f)
    
    # Handle both list and dict structures
    if isinstance(data, list):
        return data
    elif isinstance(data, dict) and "tiles" in data:
        return data["tiles"]
    else:
        # Fallback if structure is unexpected
        logger.warning(f"Unexpected fetch status structure: {data.keys()}")
        return []


def stream_tile_to_parquet(tile_info: Dict[str, Any]) -> Optional[Path]:
    """
    Stream a single tile from NetCDF (or similar) to a Parquet chunk.
    
    Args:
        tile_info: Dictionary containing tile metadata (e.g., 'tile_id', 'file_path')
        
    Returns:
        Path to the generated Parquet chunk, or None if failed.
    """
    tile_id = tile_info.get("tile_id", "unknown")
    # Expecting the source file to be in RAW_CHUNKS_DIR
    # The fetch script should have saved NetCDF files here with a naming convention
    # e.g., era5_tile_{tile_id}.nc
    source_file = RAW_CHUNKS_DIR / f"era5_tile_{tile_id}.nc"
    
    if not source_file.exists():
        # Check for .h5 or other extensions if .nc is missing
        for ext in [".nc", ".h5", ".grib"]:
            alt_file = RAW_CHUNKS_DIR / f"era5_tile_{tile_id}{ext}"
            if alt_file.exists():
                source_file = alt_file
                break
        
        if not source_file.exists():
            logger.error(f"Source file for tile {tile_id} not found at {source_file}")
            return None

    try:
        # Attempt to read NetCDF using pandas (requires netcdf4 engine usually)
        # If this fails, we might need xarray, but we try pandas first for simplicity
        # based on existing project constraints.
        # Note: ERA5 data is often multi-dimensional. We flatten it for Parquet.
        
        # Try reading with pandas
        try:
            df = pd.read_csv(source_file) # Fallback if it's actually CSV-like
        except Exception:
            try:
                # Standard NetCDF reading
                # We assume xarray is available or pandas can handle it via engine
                # If xarray is not installed, we might need to install it or use netCDF4 directly.
                # Given the constraints, we assume standard scientific stack.
                import xarray as xr
                ds = xr.open_dataset(source_file)
                df = ds.to_dataframe().reset_index()
            except ImportError:
                logger.warning("xarray not found, attempting raw netCDF4 read or failing.")
                import netCDF4 as nc
                ds = nc.Dataset(source_file, 'r')
                # Convert to dict of arrays then DataFrame
                data_dict = {var: ds.variables[var][:] for var in ds.variables}
                # This is a simplified conversion; real ERA5 needs dimension handling
                # For now, we assume the fetch script normalized dimensions or we handle basic 2D
                # If dimensions are complex, we might need to iterate.
                # Let's assume a flat structure for this specific task context or that xarray is available.
                # Re-attempt with xarray as it's standard for ERA5
                try:
                    import xarray as xr
                    ds = xr.open_dataset(source_file)
                    df = ds.to_dataframe().reset_index()
                except Exception as e:
                    logger.error(f"Failed to read {source_file}: {e}")
                    return None

        # Clean column names for Parquet
        df.columns = [str(c).replace(" ", "_") for c in df.columns]
        
        output_chunk_path = RAW_CHUNKS_DIR / f"chunk_{tile_id}.parquet"
        df.to_parquet(output_chunk_path, index=False)
        
        logger.info(f"Streamed tile {tile_id} to {output_chunk_path}")
        return output_chunk_path

    except Exception as e:
        logger.error(f"Failed to stream tile {tile_id}: {e}")
        return None


def concatenate_parquet_chunks(chunk_paths: List[Path], output_path: Path):
    """
    Concatenate multiple Parquet chunks into a single file.
    
    Args:
        chunk_paths: List of paths to Parquet chunk files.
        output_path: Path for the final concatenated file.
    """
    if not chunk_paths:
        logger.warning("No chunks to concatenate.")
        return

    logger.info(f"Concatenating {len(chunk_paths)} chunks to {output_path}")
    
    # Read first chunk to get schema
    first_df = pd.read_parquet(chunk_paths[0])
    dfs = [first_df]
    
    for p in chunk_paths[1:]:
        dfs.append(pd.read_parquet(p))
    
    combined_df = pd.concat(dfs, ignore_index=True)
    combined_df.to_parquet(output_path, index=False)
    
    logger.info(f"Successfully wrote {output_path} with {len(combined_df)} rows.")


def re_execute_fetch():
    """
    Re-execute the fetch script (T002c) if the full parquet is missing.
    This is a deterministic re-run based on the fetch_status.json.
    """
    logger.warning("Full ERA5 file missing. Triggering re-fetch (T002c)...")
    # We call the fetch script directly
    fetch_script = PROJECT_ROOT / "code" / "fetch_era_full.py"
    if not fetch_script.exists():
        raise FileNotFoundError(f"Fetch script not found: {fetch_script}")
    
    # Run the fetch script
    import subprocess
    try:
        result = subprocess.run(
            [sys.executable, str(fetch_script)],
            check=True,
            capture_output=True,
            text=True
        )
        logger.info("Re-fetch completed successfully.")
        return True
    except subprocess.CalledProcessError as e:
        logger.error(f"Re-fetch failed: {e.stderr}")
        return False


def main():
    """Main entry point for T002d."""
    ensure_directories()
    
    # Check if output file exists
    if OUTPUT_PARQUET_PATH.exists():
        logger.info(f"Output file {OUTPUT_PARQUET_PATH} already exists. Skipping.")
        # Verify non-zero size
        if OUTPUT_PARQUET_PATH.stat().st_size == 0:
            logger.warning("Output file is empty. Re-processing.")
            OUTPUT_PARQUET_PATH.unlink()
        else:
            return 0

    # Load fetch status
    tiles = load_fetch_status()
    if not tiles:
        logger.error("No tiles found in fetch_status.json.")
        return 1

    successful_chunks: List[Path] = []

    for tile in tiles:
        tile_id = tile.get("tile_id", "unknown")
        status = tile.get("status", "unknown")
        
        if status != "completed":
            logger.warning(f"Tile {tile_id} status is '{status}'. Skipping.")
            continue
        
        chunk_path = stream_tile_to_parquet(tile)
        if chunk_path:
            successful_chunks.append(chunk_path)

    if not successful_chunks:
        logger.error("No chunks were successfully created.")
        # Try re-fetching if we have no chunks
        if re_execute_fetch():
            # Retry loading chunks after fetch
            tiles = load_fetch_status()
            for tile in tiles:
                if tile.get("status") == "completed":
                    chunk_path = stream_tile_to_parquet(tile)
                    if chunk_path:
                        successful_chunks.append(chunk_path)
        
        if not successful_chunks:
            logger.critical("Failed to generate any chunks after re-fetch.")
            return 1

    # Concatenate
    concatenate_parquet_chunks(successful_chunks, OUTPUT_PARQUET_PATH)

    # Final verification
    if not OUTPUT_PARQUET_PATH.exists() or OUTPUT_PARQUET_PATH.stat().st_size == 0:
        logger.critical("Final output file missing or empty.")
        return 1

    logger.info("Task T002d completed successfully.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
