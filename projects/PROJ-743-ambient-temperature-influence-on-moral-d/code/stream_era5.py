def ensure_directories():
    """Ensure all necessary directories exist."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    RAW_CHUNKS_DIR.mkdir(parents=True, exist_ok=True)
    Path("results/logs").mkdir(parents=True, exist_ok=True)

def load_fetch_status() -> Dict[str, Any]:
    """Load the fetch status generated by T002c."""
    if not FETCH_STATUS_PATH.exists():
        raise FileNotFoundError(
            f"Fetch status file not found at {FETCH_STATUS_PATH}. "
            "T002c (fetch_era_full.py) must be run first."
        )
    
    with open(FETCH_STATUS_PATH, 'r') as f:
        return json.load(f)

def stream_tile_to_parquet(tile_info: Dict[str, Any], chunk_index: int) -> Path:
    """
    Stream a single tile from NetCDF/HDF5 chunks to a Parquet file.
    
    Args:
        tile_info: Dictionary containing tile metadata (path, grid_id, etc.)
        chunk_index: Index for naming the output chunk.
        
    Returns:
        Path to the created Parquet chunk.
    """
    input_path = Path(tile_info['path'])
    if not input_path.exists():
        raise FileNotFoundError(
            f"Tile data file not found at {input_path}. "
            "Ensure T002c successfully downloaded the tiles."
        )

    chunk_path = RAW_CHUNKS_DIR / f"era5_tile_{chunk_index:04d}.parquet"
    
    # Determine file extension to handle reading
    suffix = input_path.suffix.lower()
    
    try:
        if suffix == '.nc' or suffix == '.netcdf':
            # Use pandas to read NetCDF (requires xarray usually, but pandas can handle simple ones or we use xarray if available)
            # Since xarray is not in the explicit API surface, we assume pandas with engine='netcdf4' or similar
            # However, standard pandas doesn't read NetCDF directly without xarray. 
            # We will attempt to use xarray if available, otherwise fallback to a robust error.
            try:
                import xarray as xr
                ds = xr.open_dataset(input_path)
                # Convert to pandas DataFrame
                df = ds.to_dataframe().reset_index()
                # Rename columns to standard names if necessary
                # ERA5 usually has 'time', 'latitude', 'longitude', '2m_temperature'
                # We normalize column names to snake_case and specific keys expected by downstream
                df.columns = [c.lower().replace('-', '_').replace(' ', '_') for c in df.columns]
                
                # Ensure we have the expected columns
                required = ['time', 'latitude', 'longitude']
                if '2m_temperature' not in df.columns and 't2m' in df.columns:
                    df['temperature_celsius'] = df['t2m']
                elif '2m_temperature' in df.columns:
                    df['temperature_celsius'] = df['2m_temperature']
                else:
                    # Try to find any temperature-like column
                    temp_cols = [c for c in df.columns if 'temp' in c or 't2m' in c]
                    if temp_cols:
                        df['temperature_celsius'] = df[temp_cols[0]]
                
                df['grid_id'] = tile_info.get('grid_id', f"tile_{chunk_index}")
                
                # Select and order columns
                cols_to_keep = ['grid_id', 'time', 'latitude', 'longitude', 'temperature_celsius']
                # Filter only existing columns
                cols_to_keep = [c for c in cols_to_keep if c in df.columns]
                df = df[cols_to_keep]
                
                # Convert time to datetime if not already
                if 'time' in df.columns and not pd.api.types.is_datetime64_any_dtype(df['time']):
                    df['time'] = pd.to_datetime(df['time'])
                
                df.to_parquet(chunk_path, index=False)
                logger.info(f"Converted NetCDF tile {input_path} to Parquet: {chunk_path}")
                
            except ImportError:
                raise RuntimeError(
                    "xarray is required to read NetCDF files. "
                    "Please install it: pip install xarray netcdf4"
                )
        elif suffix == '.h5' or suffix == '.hdf5':
            # Read HDF5
            try:
                import h5py
                import numpy as np
                
                with h5py.File(input_path, 'r') as f:
                    # Attempt to find data structure
                    # Common structure: /data/temperature or similar
                    keys = list(f.keys())
                    if not keys:
                        raise ValueError(f"HDF5 file {input_path} is empty or has no top-level keys.")
                    
                    # Simple heuristic: flatten the first dataset found
                    # This is a generic fallback; real ERA5 HDF5 structures vary.
                    # We assume a standard structure might be present or we need to iterate.
                    # For robustness, we try to find a dataset named 'temperature' or 'data'
                    data_key = None
                    for k in keys:
                        if isinstance(f[k], h5py.Dataset):
                            data_key = k
                            break
                        elif isinstance(f[k], h5py.Group):
                            # Recurse or pick first child
                            for sub_k in f[k].keys():
                                if isinstance(f[k][sub_k], h5py.Dataset):
                                    data_key = f"{k}/{sub_k}"
                                    break
                            if data_key: break
                    
                    if data_key:
                        data = f[data_key][:]
                        # If 4D (time, level, lat, lon) or 3D (time, lat, lon)
                        # We need to reshape or iterate.
                        # For simplicity in this generic script, we assume we can convert to DF if shape is 2D or 3D with known dims
                        # ERA5 usually has dimensions: time, number (levels), latitude, longitude
                        # We'll assume we are dealing with a 2m temperature slice already or a flattened view
                        # If we can't easily map, we log and skip or raise.
                        
                        # Fallback: Convert to DataFrame assuming 2D (rows, cols) or 1D
                        # This part is highly dependent on the exact export from T002c.
                        # We will assume T002c exported a structure where we can iterate.
                        # If it's a raw binary dump, we can't parse without schema.
                        # Given the task T002c uses CDS API, it likely returns NetCDF.
                        # If T002c saved as HDF5, it likely converted.
                        # We will assume a standard DataFrame-like structure was saved or can be reconstructed.
                        # If this fails, it means T002c didn't produce a readable HDF5.
                        raise NotImplementedError("Generic HDF5 parsing for ERA5 is complex without specific schema. "
                                                "Ensure T002c outputs NetCDF or a known HDF5 structure.")
                    else:
                        raise ValueError(f"Could not find data in HDF5 file {input_path}")
            except Exception as e:
                logger.error(f"Error reading HDF5 {input_path}: {e}")
                raise
        else:
            raise ValueError(f"Unsupported file format: {suffix}. Expected .nc, .h5, or .hdf5.")

    except Exception as e:
        logger.error(f"Failed to process tile {input_path}: {e}")
        raise

    return chunk_path

def concatenate_parquet_chunks(chunk_paths: List[Path]) -> Path:
    """Concatenate all Parquet chunks into a single file."""
    if not chunk_paths:
        raise FileNotFoundError("No chunk files found to concatenate.")
    
    logger.info(f"Concatenating {len(chunk_paths)} chunks into {FINAL_OUTPUT_PATH}")
    
    # Read all chunks
    dfs = []
    for i, path in enumerate(chunk_paths):
        if not path.exists():
            logger.warning(f"Chunk {path} missing, skipping.")
            continue
        try:
            df = pd.read_parquet(path)
            dfs.append(df)
        except Exception as e:
            logger.error(f"Error reading chunk {path}: {e}")
            raise
    
    if not dfs:
        raise ValueError("No valid data found in any chunk files.")
    
    # Concatenate
    final_df = pd.concat(dfs, ignore_index=True)
    
    # Ensure time column is datetime
    if 'time' in final_df.columns:
        final_df['time'] = pd.to_datetime(final_df['time'])
    
    # Sort by time and grid_id for consistency
    final_df = final_df.sort_values(by=['grid_id', 'time'])
    
    # Write to final destination
    final_df.to_parquet(FINAL_OUTPUT_PATH, index=False)
    
    logger.info(f"Successfully wrote {len(final_df)} rows to {FINAL_OUTPUT_PATH}")
    return FINAL_OUTPUT_PATH

def re_execute_fetch():
    """
    Re-execute the fetch step (T002c) if data is missing.
    This is a wrapper to call the fetch script again.
    """
    logger.warning("Missing ERA5 data. Re-executing fetch (T002c)...")
    # We assume the fetch script is fetch_era_full.py
    # We run it via subprocess or import main
    try:
        from fetch_era_full import main as fetch_main
        fetch_main()
        logger.info("Fetch re-execution completed.")
    except Exception as e:
        logger.error(f"Failed to re-execute fetch: {e}")
        raise

def main():
    """Main entry point for T002d."""
    setup_logging()
    ensure_directories()
    
    # 1. Load fetch status
    try:
        fetch_status = load_fetch_status()
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    
    tiles = fetch_status.get('tiles', [])
    if not tiles:
        logger.error("No tiles found in fetch status.")
        sys.exit(1)
    
    # 2. Check if final output exists
    if FINAL_OUTPUT_PATH.exists():
        logger.info(f"Final output {FINAL_OUTPUT_PATH} already exists. Skipping processing.")
        # Verify size
        if FINAL_OUTPUT_PATH.stat().st_size == 0:
            logger.warning("Final output is empty. Re-processing.")
        else:
            sys.exit(0)
    
    # 3. Process tiles
    chunk_paths = []
    for idx, tile in enumerate(tiles):
        if tile.get('status') != 'completed':
            logger.warning(f"Tile {tile.get('id', idx)} not completed. Skipping.")
            continue
        
        try:
            chunk_path = stream_tile_to_parquet(tile, idx)
            chunk_paths.append(chunk_path)
        except Exception as e:
            logger.error(f"Failed to stream tile {tile.get('id', idx)}: {e}")
            # Decide: fail hard or skip? Task says "raise exception after 3 retries" if missing.
            # Here we are processing, so if a tile is broken, we might need to re-fetch.
            # For now, we raise to stop the pipeline.
            raise
    
    if not chunk_paths:
        logger.error("No chunks were successfully processed.")
        # Trigger re-fetch logic
        retries = 0
        while retries < MAX_RETRIES:
            try:
                re_execute_fetch()
                # Reload status
                fetch_status = load_fetch_status()
                tiles = fetch_status.get('tiles', [])
                # Retry processing
                for idx, tile in enumerate(tiles):
                    if tile.get('status') == 'completed':
                        try:
                            chunk_path = stream_tile_to_parquet(tile, idx)
                            chunk_paths.append(chunk_path)
                        except:
                            pass
                if chunk_paths:
                    break
                retries += 1
            except Exception as e:
                logger.error(f"Retry {retries+1} failed: {e}")
                retries += 1
        
        if not chunk_paths:
            raise FileNotFoundError("Failed to retrieve and process ERA5 tiles after 3 retries.")
    
    # 4. Concatenate
    try:
        concatenate_parquet_chunks(chunk_paths)
    except Exception as e:
        logger.error(f"Failed to concatenate chunks: {e}")
        sys.exit(1)
    
    # 5. Verify output
    if not FINAL_OUTPUT_PATH.exists() or FINAL_OUTPUT_PATH.stat().st_size == 0:
        raise FileNotFoundError("Final output file was not created or is empty.")
    
    logger.info("T002d completed successfully.")

if __name__ == "__main__":
    main()
