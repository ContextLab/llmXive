def ensure_output_directories():
    """Ensure the output directory for processed data exists."""
    output_dir = PROJECT_ROOT / "data" / "processed"
    output_dir.mkdir(parents=True, exist_ok=True)
    return output_dir

def calculate_success_rate(df: pd.DataFrame, logger: logging.Logger) -> float:
    """
    Calculate the success rate of the merge process.
    Success is defined as a record having a valid temperature value and match_quality.
    SC-001: Log success rate.
    """
    if df is None or df.empty:
        logger.error("DataFrame is empty or None. Cannot calculate success rate.")
        return 0.0

    total_records = len(df)
    # Check for valid temperature and match_quality
    # Assuming 'temperature_celsius' and 'match_quality' are the columns populated by ingestion
    valid_mask = (
        df['temperature_celsius'].notna() & 
        (df['temperature_celsius'] != -999.0) & # Common missing value placeholder
        df['match_quality'].notna()
    )
    
    valid_count = valid_mask.sum()
    success_rate = (valid_count / total_records) * 100 if total_records > 0 else 0.0

    logger.info(f"Total records processed: {total_records}")
    logger.info(f"Valid records (with temp & match): {valid_count}")
    logger.info(f"Success Rate (SC-001): {success_rate:.2f}%")
    
    return success_rate

