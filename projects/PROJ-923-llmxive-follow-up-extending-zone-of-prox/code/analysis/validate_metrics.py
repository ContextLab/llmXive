"""
Validation module for aggregated metrics against schema contracts.

This module provides functionality to validate the aggregated metrics
generated by the comparative analysis pipeline against the defined
schema contracts to ensure data integrity and compliance.
"""

import os
import json
import yaml
from pathlib import Path
from typing import Dict, Any, Optional, List, Tuple

import jsonschema
from jsonschema import validate, ValidationError, SchemaError

from utils.logging import get_logger, info, warning, error, debug
from config import get_config

logger = get_logger(__name__)


def load_schema(schema_path: str) -> Dict[str, Any]:
    """
    Load a JSON/YAML schema from the given path.

    Args:
        schema_path: Path to the schema file (relative to project root)

    Returns:
        Dictionary containing the schema definition

    Raises:
        FileNotFoundError: If schema file doesn't exist
        ValueError: If schema file is invalid JSON/YAML
    """
    path = Path(schema_path)
    if not path.exists():
        error(f"Schema file not found: {schema_path}")
        raise FileNotFoundError(f"Schema file not found: {schema_path}")

    logger.debug(f"Loading schema from: {schema_path}")

    try:
        with open(path, 'r', encoding='utf-8') as f:
            if schema_path.endswith('.yaml') or schema_path.endswith('.yml'):
                schema = yaml.safe_load(f)
            else:
                schema = json.load(f)

        if schema is None:
            error(f"Schema file is empty or invalid: {schema_path}")
            raise ValueError(f"Schema file is empty or invalid: {schema_path}")

        debug(f"Successfully loaded schema: {schema_path}")
        return schema

    except yaml.YAMLError as e:
        error(f"Failed to parse YAML schema: {e}")
        raise ValueError(f"Invalid YAML in schema: {e}")
    except json.JSONDecodeError as e:
        error(f"Failed to parse JSON schema: {e}")
        raise ValueError(f"Invalid JSON in schema: {e}")


def load_metrics_data(metrics_path: str) -> Dict[str, Any]:
    """
    Load aggregated metrics data from a JSON file.

    Args:
        metrics_path: Path to the metrics JSON file

    Returns:
        Dictionary containing the metrics data

    Raises:
        FileNotFoundError: If metrics file doesn't exist
        ValueError: If metrics file is invalid JSON
    """
    path = Path(metrics_path)
    if not path.exists():
        error(f"Metrics file not found: {metrics_path}")
        raise FileNotFoundError(f"Metrics file not found: {metrics_path}")

    logger.debug(f"Loading metrics from: {metrics_path}")

    try:
        with open(path, 'r', encoding='utf-8') as f:
            metrics = json.load(f)

        if metrics is None:
            error(f"Metrics file is empty: {metrics_path}")
            raise ValueError(f"Metrics file is empty: {metrics_path}")

        debug(f"Successfully loaded metrics: {metrics_path}")
        return metrics

    except json.JSONDecodeError as e:
        error(f"Failed to parse JSON metrics: {e}")
        raise ValueError(f"Invalid JSON in metrics: {e}")


def validate_metrics_against_schema(
    metrics: Dict[str, Any],
    schema: Dict[str, Any]
) -> Tuple[bool, List[str]]:
    """
    Validate metrics data against a schema.

    Args:
        metrics: The metrics data to validate
        schema: The schema to validate against

    Returns:
        Tuple of (is_valid, list_of_errors)
    """
    errors = []

    try:
        validate(instance=metrics, schema=schema)
        debug("Metrics validation passed")
        return True, []

    except ValidationError as e:
        error(f"Schema validation error: {e.message}")
        errors.append(f"Schema validation error: {e.message}")

        # Collect all validation errors for detailed reporting
        for error in jsonschema.iter_errors(metrics, schema):
            errors.append(f"  - Path: {' -> '.join(map(str, error.path))}: {error.message}")

        return False, errors

    except SchemaError as e:
        error(f"Schema definition error: {e.message}")
        errors.append(f"Schema definition error: {e.message}")
        return False, errors


def validate_aggregated_metrics_file(
    metrics_path: str,
    schema_path: str
) -> Tuple[bool, Dict[str, Any]]:
    """
    Validate an aggregated metrics file against its schema.

    Args:
        metrics_path: Path to the metrics JSON file
        schema_path: Path to the schema YAML file

    Returns:
        Tuple of (is_valid, validation_report)
    """
    report = {
        "metrics_path": metrics_path,
        "schema_path": schema_path,
        "is_valid": False,
        "errors": [],
        "warnings": []
    }

    try:
        # Load schema
        schema = load_schema(schema_path)
        report["schema_loaded"] = True

        # Load metrics
        metrics = load_metrics_data(metrics_path)
        report["metrics_loaded"] = True

        # Validate
        is_valid, errors = validate_metrics_against_schema(metrics, schema)
        report["is_valid"] = is_valid
        report["errors"] = errors

        if is_valid:
            info(f"Validation successful for: {metrics_path}")
        else:
            error(f"Validation failed for: {metrics_path}")
            for err in errors:
                report["errors"].append(err)

    except FileNotFoundError as e:
        error(f"File not found during validation: {e}")
        report["errors"].append(f"File not found: {str(e)}")

    except ValueError as e:
        error(f"Value error during validation: {e}")
        report["errors"].append(f"Value error: {str(e)}")

    except Exception as e:
        error(f"Unexpected error during validation: {e}")
        report["errors"].append(f"Unexpected error: {str(e)}")

    return report["is_valid"], report


def main():
    """
    Main entry point for validating aggregated metrics.

    This function loads the aggregated metrics file and validates it
    against the schema contract defined in the contracts directory.
    """
    config = get_config()

    # Default paths
    schema_path = config.get("contracts.aggregated_metrics_path",
                             "contracts/aggregated_metrics.schema.yaml")
    metrics_path = config.get("analysis.aggregated_metrics_output_path",
                              "data/metrics/aggregated_metrics.json")

    # Allow command line override
    import sys
    if len(sys.argv) >= 2:
        metrics_path = sys.argv[1]
    if len(sys.argv) >= 3:
        schema_path = sys.argv[2]

    info(f"Validating metrics: {metrics_path}")
    info(f"Against schema: {schema_path}")

    is_valid, report = validate_aggregated_metrics_file(metrics_path, schema_path)

    # Print validation report
    print("\n" + "=" * 60)
    print("METRICS VALIDATION REPORT")
    print("=" * 60)
    print(f"Metrics File: {report['metrics_path']}")
    print(f"Schema File:  {report['schema_path']}")
    print(f"Status:       {'PASS' if is_valid else 'FAIL'}")
    print("-" * 60)

    if report.get("errors"):
        print("Errors:")
        for err in report["errors"]:
            print(f"  • {err}")
        print()

    if report.get("warnings"):
        print("Warnings:")
        for warn in report["warnings"]:
            print(f"  ⚠ {warn}")
        print()

    if is_valid:
        print("✓ All validations passed. Metrics are compliant with schema.")
    else:
        print("✗ Validation failed. Please review the errors above.")

    print("=" * 60)

    return 0 if is_valid else 1


if __name__ == "__main__":
    exit(main())
