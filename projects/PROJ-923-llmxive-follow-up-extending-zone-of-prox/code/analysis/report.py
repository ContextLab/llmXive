logger = get_logger(__name__)

def load_metrics_from_csv(file_path: str) -> pd.DataFrame:
    """
    Load metrics from a CSV file generated by the simulation loops.
    Expects columns: 'run_id', 'seed', 'aucc', 'final_accuracy', 'avg_prompt_length' (for CAP)
    """
    path = Path(file_path)
    if not path.exists():
        error(f"Metrics file not found: {file_path}")
        raise FileNotFoundError(f"Metrics file not found: {file_path}")
    
    df = pd.read_csv(path)
    debug(f"Loaded metrics from {file_path}: {len(df)} rows")
    return df

def calculate_summary_statistics(df: pd.DataFrame, metric: str = 'aucc') -> Dict[str, float]:
    """
    Calculate mean, std, min, max for a specific metric column.
    """
    if metric not in df.columns:
        error(f"Metric '{metric}' not found in dataframe columns: {df.columns.tolist()}")
        raise KeyError(f"Metric '{metric}' not found")
    
    values = df[metric].dropna()
    if len(values) == 0:
        raise ValueError(f"No valid values for metric '{metric}'")
    
    return {
        'mean': float(values.mean()),
        'std': float(values.std()),
        'min': float(values.min()),
        'max': float(values.max()),
        'count': int(len(values))
    }

def generate_comparative_report(
    baseline_results_path: str,
    cap_results_path: str,
    output_dir: str,
    report_name: str = "comparative_report.json"
) -> Dict[str, Any]:
    """
    Generate a comparative report between Baseline (Static ZPPO) and CAP-ZPPO.
    
    Produces:
    1. A JSON report with statistical metrics (p-value, effect size, AUCC diff, std dev).
    2. A PNG plot comparing the convergence curves and distribution of AUCC.
    3. A CSV summary of the statistical findings.
    
    Args:
        baseline_results_path: Path to baseline_results.csv
        cap_results_path: Path to cap_results.csv
        output_dir: Directory to save the report artifacts
        report_name: Base name for the report files
    """
    ensure_directory(output_dir)
    output_path = Path(output_dir)
    
    logger.info(f"Loading baseline metrics from {baseline_results_path}")
    df_baseline = load_metrics_from_csv(baseline_results_path)
    
    logger.info(f"Loading CAP metrics from {cap_results_path}")
    df_cap = load_metrics_from_csv(cap_results_path)
    
    # Ensure we have data
    if df_baseline.empty or df_cap.empty:
        raise ValueError("One or both result DataFrames are empty. Cannot generate report.")
    
    # 1. Statistical Analysis
    # Extract AUCC values
    aucc_baseline = df_baseline['aucc'].values
    aucc_cap = df_cap['aucc'].values
    
    # Calculate Standard Deviation of AUCC distribution (SC-002 requirement)
    std_baseline = calculate_summary_statistics(df_baseline, 'aucc')['std']
    std_cap = calculate_summary_statistics(df_cap, 'aucc')['std']
    
    # Paired T-Test (assuming runs are paired by task/seed if available, otherwise independent)
    # The batch runner (T031) ensures distinct seeds per run, but if we assume the same tasks/seeds
    # were run for both, we can pair them. If the CSVs are just lists of runs, we treat them as
    # independent samples for the t-test if lengths differ or pairing isn't explicit.
    # Given T031 runs 100 runs (10 tasks x 10 seeds) for EACH, we assume they are comparable sets.
    # We will perform an independent t-test if lengths differ, else paired if we can match seeds.
    # For simplicity and robustness in this report, we use independent t-test on the distributions.
    t_stat, p_value = scipy_stats.ttest_ind(aucc_baseline, aucc_cap)
    
    # Effect Size (Cohen's d)
    effect_size = calculate_effect_size(aucc_baseline, aucc_cap)
    
    # AUCC Difference
    mean_baseline = calculate_summary_statistics(df_baseline, 'aucc')['mean']
    mean_cap = calculate_summary_statistics(df_cap, 'aucc')['mean']
    aucc_diff = mean_cap - mean_baseline
    
    # Prompt Length Reduction (if available in CAP)
    prompt_reduction = None
    if 'avg_prompt_length' in df_cap.columns:
        # Baseline has fixed prompt length, so we compare CAP avg to a theoretical max or baseline length
        # Assuming baseline uses full set. We need to know the full set size or infer from data.
        # For now, we just report the CAP average and note the reduction relative to max possible if known.
        # If baseline has a 'prompt_length' column (fixed), we use that.
        if 'prompt_length' in df_baseline.columns:
            baseline_len = df_baseline['prompt_length'].mean()
            cap_len = df_cap['avg_prompt_length'].mean()
            prompt_reduction = baseline_len - cap_len
            logger.info(f"Prompt length reduction: {prompt_reduction:.2f} tokens")
        else:
            logger.warning("Baseline results missing 'prompt_length' column; cannot calculate reduction.")
    
    # Catastrophic Forgetting Check (Final Accuracy)
    if 'final_accuracy' in df_baseline.columns and 'final_accuracy' in df_cap.columns:
        forgetting_result = check_catastrophic_forgetting(
            df_baseline['final_accuracy'].values,
            df_cap['final_accuracy'].values
        )
    else:
        forgetting_result = {'significance': 'unknown', 'difference': None}
    
    # 2. Construct Report Dictionary
    report_data = {
        'metadata': {
            'baseline_file': baseline_results_path,
            'cap_file': cap_results_path,
            'n_baseline': len(df_baseline),
            'n_cap': len(df_cap)
        },
        'aucc_analysis': {
            'baseline': {
                'mean': mean_baseline,
                'std': std_baseline,
                'min': calculate_summary_statistics(df_baseline, 'aucc')['min'],
                'max': calculate_summary_statistics(df_baseline, 'aucc')['max']
            },
            'cap': {
                'mean': mean_cap,
                'std': std_cap,
                'min': calculate_summary_statistics(df_cap, 'aucc')['min'],
                'max': calculate_summary_statistics(df_cap, 'aucc')['max']
            },
            'difference': aucc_diff,
            'statistical_significance': {
                't_statistic': float(t_stat),
                'p_value': float(p_value),
                'is_significant': bool(p_value < 0.05),
                'effect_size_cohens_d': float(effect_size)
            }
        },
        'prompt_analysis': {
            'avg_cap_length': float(df_cap['avg_prompt_length'].mean()) if 'avg_prompt_length' in df_cap.columns else None,
            'reduction': float(prompt_reduction) if prompt_reduction is not None else None
        },
        'forgetting_analysis': forgetting_result
    }
    
    # Save JSON Report
    json_path = output_path / f"{report_name}.json"
    with open(json_path, 'w') as f:
        json.dump(report_data, f, indent=2)
    logger.info(f"Saved JSON report to {json_path}")
    
    # 3. Generate Plots
    plot_path = output_path / f"{report_name}_plot.png"
    fig, axes = plt.subplots(1, 2, figsize=(14, 6))
    
    # Plot A: Distribution of AUCC (Boxplot + Swarm)
    ax1 = axes[0]
    data_to_plot = [aucc_baseline, aucc_cap]
    labels = ['Baseline (Static)', 'CAP-ZPPO']
    bp = ax1.boxplot(data_to_plot, labels=labels, patch_artist=True)
    for patch, color in zip(bp['boxes'], ['#a6cee3', '#1f78b4']):
        patch.set_facecolor(color)
        patch.set_alpha(0.6)
    
    # Add swarm points (stripplot)
    x = [1, 2]
    for i, data in enumerate(data_to_plot):
        y = data
        ax1.scatter([x[i]] * len(y), y, alpha=0.5, color='black', s=20)
    
    ax1.set_ylabel('Area Under Convergence Curve (AUCC)')
    ax1.set_title('AUCC Distribution Comparison')
    ax1.grid(axis='y', linestyle='--', alpha=0.7)
    
    # Plot B: Convergence Curves (Mean Accuracy per Cycle)
    # We need to reconstruct the mean accuracy per cycle if available in the raw data.
    # Assuming the CSVs might not have cycle-by-cycle data, but if they do (e.g. in a separate log or aggregated),
    # we would plot it. Since the task asks for "plots" and the CSV is "metrics", we might only have final stats.
    # However, T031/T032 implies we have the logs. Let's assume we can load the cycle data if available.
    # If the CSV only has summary, we plot the summary stats.
    # To make this robust, we check if 'cycle_data' or similar exists, otherwise we just plot the boxplot again or a bar chart.
    # For this implementation, we will create a bar chart of the Mean AUCC with error bars (Std Dev) since cycle data isn't in the summary CSV.
    ax2 = axes[1]
    means = [mean_baseline, mean_cap]
    stds = [std_baseline, std_cap]
    x_pos = np.arange(len(labels))
    bars = ax2.bar(x_pos, means, yerr=stds, capsize=5, color=['#a6cee3', '#1f78b4'], alpha=0.7, edgecolor='black')
    ax2.set_xticks(x_pos)
    ax2.set_xticklabels(labels)
    ax2.set_ylabel('Mean AUCC')
    ax2.set_title('Mean AUCC with Standard Deviation')
    ax2.grid(axis='y', linestyle='--', alpha=0.7)
    
    # Annotate significance
    if p_value < 0.05:
        ax2.text(0.5, max(means) + stds[1] + 0.02, f'p = {p_value:.4f} (**)', ha='center', fontsize=12, fontweight='bold')
    else:
        ax2.text(0.5, max(means) + stds[1] + 0.02, f'p = {p_value:.4f} (ns)', ha='center', fontsize=12)
    
    plt.tight_layout()
    plt.savefig(plot_path, dpi=150)
    plt.close()
    logger.info(f"Saved plot to {plot_path}")
    
    # 4. Save CSV Summary
    csv_path = output_path / f"{report_name}_summary.csv"
    summary_df = pd.DataFrame([report_data['aucc_analysis']])
    # Flatten for CSV if needed, or keep nested. Let's flatten key metrics.
    flat_summary = {
        'metric': 'aucc',
        'baseline_mean': mean_baseline,
        'baseline_std': std_baseline,
        'cap_mean': mean_cap,
        'cap_std': std_cap,
        'difference': aucc_diff,
        'p_value': p_value,
        'effect_size': effect_size,
        'significant': p_value < 0.05
    }
    summary_df = pd.DataFrame([flat_summary])
    summary_df.to_csv(csv_path, index=False)
    logger.info(f"Saved CSV summary to {csv_path}")
    
    return report_data

def main():
    """
    Entry point to generate the comparative report.
    Reads paths from config or uses defaults if not specified.
    """
    config = get_config()
    
    # Default paths relative to project root
    baseline_path = config.get('paths', {}).get('baseline_results', 'data/metrics/baseline_results.csv')
    cap_path = config.get('paths', {}).get('cap_results', 'data/metrics/cap_results.csv')
    output_dir = config.get('paths', {}).get('reports', 'data/reports')
    
    # Allow override via command line args if needed (simplified here)
    # In a real scenario, we might parse sys.argv
    
    try:
        report = generate_comparative_report(
            baseline_results_path=baseline_path,
            cap_results_path=cap_path,
            output_dir=output_dir,
            report_name="zppo_comparison"
        )
        info("Comparative report generation completed successfully.")
        debug(json.dumps(report, indent=2))
    except FileNotFoundError as e:
        error(f"Missing required data file: {e}")
        raise
    except Exception as e:
        error(f"Failed to generate report: {e}")
        raise

if __name__ == '__main__':
    main()