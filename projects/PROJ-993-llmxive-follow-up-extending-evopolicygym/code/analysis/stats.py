logger = logging.getLogger(__name__)

def run_mixed_effects_model(
    input_path: str = "data/evolution_results.csv",
    output_path: str = "data/stats_results.json"
) -> Dict[str, Any]:
    """
    Run mixed-effects model analysis on evolution results.
    Formula: metric ~ condition + (1|seed)
    """
    if not os.path.exists(input_path):
        raise FileNotFoundError(f"Input file not found: {input_path}")

    df = pd.read_csv(input_path)
    
    required_cols = ['metric', 'condition', 'seed', 'run_id']
    for col in required_cols:
        if col not in df.columns:
            raise ValueError(f"Missing required column: {col}")

    formula = "metric ~ condition + (1|seed)"
    
    try:
        model = mixedlm(formula, df, groups=df["seed"])
        result = model.fit()
        
        p_value = result.pvalues["condition[T.counterfactual]"]
        effect_size = result.params["condition[T.counterfactual]"]
        
        results = {
            "p_value": float(p_value),
            "effect_size": float(effect_size),
            "model_formula": formula,
            "n_observations": len(df),
            "n_groups": df["seed"].nunique()
        }
        
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        with open(output_path, 'w') as f:
            json.dump(results, f, indent=2)
        
        logger.info(f"Mixed-effects model results written to {output_path}")
        return results
        
    except Exception as e:
        logger.error(f"Mixed-effects model failed: {e}")
        raise

def calculate_shift_validation(
    pre_shift_path: str = "data/pre_shift_metrics.csv",
    post_shift_path: str = "data/post_shift_metrics.csv",
    output_path: str = "data/shift_validation.json"
) -> Dict[str, float]:
    """
    Perform statistical test (t-test) to verify performance drop after shift.
    """
    if not os.path.exists(pre_shift_path) or not os.path.exists(post_shift_path):
        raise FileNotFoundError("Shift validation requires both pre and post shift metric files")

    pre_df = pd.read_csv(pre_shift_path)
    post_df = pd.read_csv(post_shift_path)

    pre_scores = pre_df['reward'].values
    post_scores = post_df['reward'].values

    if len(pre_scores) == 0 or len(post_scores) == 0:
        raise ValueError("Empty data arrays for shift validation")

    t_stat, p_value = stats.ttest_ind(pre_scores, post_scores, equal_var=False)
    
    results = {
        "t_statistic": float(t_stat),
        "p_value": float(p_value),
        "pre_mean": float(np.mean(pre_scores)),
        "post_mean": float(np.mean(post_scores)),
        "pre_std": float(np.std(pre_scores)),
        "post_std": float(np.std(post_scores))
    }

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)

    logger.info(f"Shift validation results written to {output_path}")
    return results

def calculate_success_rate(
    fallback_log_path: str = "data/fallbacks.log",
    total_attempts: int = None,
    output_path: str = "data/success_rate.json"
) -> Dict[str, Any]:
    """
    Calculate the rate of successful counterfactual explanation generation (SC-004).
    Aggregates success/failure counts from T021 (timeouts) and T023 (fallbacks).
    
    Args:
        fallback_log_path: Path to the fallback log file generated by T023
        total_attempts: Optional total number of generation attempts. If None, 
                      attempts are inferred from the log + successful runs 
                      (requires a separate metrics file or estimation).
                      For this implementation, we count failures from log 
                      and assume a total count passed or derived from context.
        output_path: Path to write the success rate report
    
    Returns:
        Dictionary with success_rate, total_attempts, fallback_count, timeout_count
    """
    fallback_count = 0
    timeout_count = 0
    
    if os.path.exists(fallback_log_path):
        with open(fallback_log_path, 'r') as f:
            for line in f:
                if 'timeout' in line.lower():
                    timeout_count += 1
                elif 'fallback' in line.lower():
                    fallback_count += 1
    
    # If total_attempts is not provided, we cannot accurately calculate rate
    # without a separate log of successful generations. 
    # We assume the caller provides total_attempts or we read from a companion file.
    # For robustness, if total_attempts is None, we look for a companion file
    # or raise an error if we can't infer it.
    if total_attempts is None:
        # Try to infer from a companion file if it exists, otherwise fail loudly
        companion_path = "data/explanation_attempts.json"
        if os.path.exists(companion_path):
            with open(companion_path, 'r') as f:
                data = json.load(f)
                total_attempts = data.get('total_attempts', 0)
        else:
            raise ValueError(
                "Cannot calculate success rate: total_attempts not provided "
                "and companion file 'data/explanation_attempts.json' not found. "
                "The generation pipeline must log total attempts."
            )

    if total_attempts == 0:
        raise ValueError("Total attempts is zero; cannot calculate rate.")

    failure_count = fallback_count + timeout_count
    success_count = total_attempts - failure_count

    if success_count < 0:
        logger.warning(f"Calculated success count ({success_count}) is negative. "
                       f"Check log integrity. Clamping to 0.")
        success_count = 0

    success_rate = success_count / total_attempts

    results = {
        "success_rate": float(success_rate),
        "total_attempts": total_attempts,
        "successful_generations": success_count,
        "fallback_count": fallback_count,
        "timeout_count": timeout_count,
        "failure_rate": float(failure_count / total_attempts)
    }

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)

    logger.info(f"Success rate report written to {output_path}: {success_rate:.4f}")
    return results