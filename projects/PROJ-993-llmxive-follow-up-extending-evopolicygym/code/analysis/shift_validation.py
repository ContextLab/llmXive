"""
T014: Shift Validation and P-Value Calculation Module.

This module calculates p-values for performance drops observed in dynamic-shift
environments. Environments with p >= 0.05 are logged as failures and excluded
from subsequent evolution runs to ensure statistical rigor.
"""

import os
import csv
import json
import logging
from typing import List, Dict, Any, Optional
from scipy import stats
import numpy as np

from utils.logging import get_logger

# Configure logger for this module
logger = get_logger(__name__)

def load_sensitivity_report(report_path: str) -> List[Dict[str, Any]]:
    """
    Load the sensitivity report generated by T013f.

    Args:
        report_path: Path to the sensitivity_report.csv file.

    Returns:
        List of dictionaries containing environment sensitivity data.
    """
    if not os.path.exists(report_path):
        raise FileNotFoundError(f"Sensitivity report not found at {report_path}")

    data = []
    with open(report_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Convert numeric fields
            row['shift_step'] = int(row['shift_step'])
            row['pre_shift_score'] = float(row['pre_shift_score'])
            row['post_shift_score'] = float(row['post_shift_score'])
            row['drop_rate'] = float(row['drop_rate'])
            data.append(row)
    return data

def calculate_p_value(pre_scores: List[float], post_scores: List[float]) -> float:
    """
    Calculate the p-value for the performance drop using a paired t-test.

    Args:
        pre_scores: List of scores before the shift.
        post_scores: List of scores after the shift.

    Returns:
        The p-value from the t-test.
    """
    if len(pre_scores) != len(post_scores) or len(pre_scores) < 2:
        logger.warning("Insufficient data for paired t-test. Returning p=1.0.")
        return 1.0

    # Paired t-test to check if post-shift scores are significantly lower
    t_stat, p_val = stats.ttest_rel(pre_scores, post_scores)

    # We are interested in the one-tailed test (post < pre)
    # ttest_rel returns two-tailed p-value, so we divide by 2
    # However, we must check the direction: if t_stat > 0, it means pre > post
    if t_stat > 0:
        return p_val / 2.0
    else:
        # If t_stat <= 0, the scores did not drop (or increased), so p is high
        return 1.0

def process_validation_report(input_report_path: str, output_log_path: str) -> List[Dict[str, Any]]:
    """
    Process the sensitivity report to calculate p-values and filter valid environments.

    Args:
        input_report_path: Path to the input sensitivity_report.csv.
        output_log_path: Path to write the shift_validation.log.

    Returns:
        List of valid environment rows (p < 0.05) to be used in evolution.
    """
    logger.info(f"Loading sensitivity report from {input_report_path}")
    try:
        report_data = load_sensitivity_report(input_report_path)
    except FileNotFoundError as e:
        logger.error(str(e))
        # Return empty list if file missing, allowing the pipeline to handle it upstream
        return []

    valid_environments = []
    failed_environments = []

    # Prepare log entries
    log_entries = []

    for row in report_data:
        env_id = row['env_id']
        pre_shift_score = row['pre_shift_score']
        post_shift_score = row['post_shift_score']
        drop_rate = row['drop_rate']

        # Check for zero drop rate first (optimization)
        if drop_rate == 0.0:
            logger.warning(f"Environment {env_id}: drop_rate is 0.0. Excluding from analysis.")
            log_entries.append({
                "env_id": env_id,
                "status": "skipped_zero_drop",
                "reason": "drop_rate is 0.0",
                "p_value": None
            })
            failed_environments.append(row)
            continue

        # Simulate multiple runs for p-value calculation if only single run exists
        # In a real scenario, T013f should have generated multiple seeds/runs.
        # If only single run, we cannot calculate a meaningful p-value.
        # We will treat single-run scenarios as having p=1.0 (fail) to be conservative,
        # or we assume the 'pre_shift_score' and 'post_shift_score' are aggregates.
        # Given the task description implies calculating p-value, we assume T013f
        # produced multiple data points or we need to simulate the distribution if not.
        # However, the schema in T015b suggests a single row per env_id.
        # To strictly follow "calculate p-value", we need variance.
        # If T013f only produced one run per env, we cannot calculate p-value.
        # Assumption: T013f might have produced multiple rows per env_id or we need to
        # aggregate. Let's assume the input CSV might have multiple rows per env_id
        # representing different seeds, OR we treat the single value as a point estimate
        # and fail validation if we can't compute variance.
        #
        # Correction based on T015b schema: "env_id (str), ... pre_shift_score (float)".
        # This implies one row per env. If one row, we cannot do a t-test.
        # We will assume the 'pre_shift_score' and 'post_shift_score' are means of N runs.
        # Without N, we cannot compute p-value.
        #
        # CRITICAL INTERPRETATION: If T013f only runs a static agent ONCE, we cannot
        # calculate a p-value. The task T014 asks to "calculate p-value".
        # This implies T013f MUST have collected multiple samples, OR the schema is
        # misleading, OR we must assume a default variance (which is bad science).
        #
        # Alternative: The 'pre_shift_score' and 'post_shift_score' in the CSV are
        # actually lists? No, schema says float.
        #
        # Resolution: We will assume that if the CSV has only one row per env,
        # we cannot calculate a p-value and we must SKIP it (log failure) to be safe,
        # OR we assume the 'drop_rate' is the metric and we treat it as a single sample.
        # However, the task explicitly says "calculate p-value".
        #
        # Let's look at T013f: "Run Static Agent... generate pre_shift_score and post_shift_score".
        # If it runs once, no p-value.
        #
        # Hypothesis: The 'sensitivity_report.csv' might contain multiple runs per env_id
        # if T013f was designed to run multiple seeds. If the current T013f only runs once,
        # then T014 cannot fulfill its requirement with real data unless we modify T013f
        # (which we can't in this task) or assume the single score is sufficient (which is wrong).
        #
        # Workaround for this specific task: We will assume that the 'pre_shift_score'
        # and 'post_shift_score' are the result of a single run, and we cannot calculate
        # a p-value. Therefore, we will log this as a validation failure (p >= 0.05)
        # effectively skipping it, OR we assume a synthetic variance if the task implies
        # we should have multiple runs.
        #
        # BETTER APPROACH: The task T014 depends on T013f. If T013f didn't produce
        # enough data for T014, T014 fails.
        #
        # Let's assume the 'sensitivity_report.csv' might have been generated with
        # multiple seeds for each env_id (even if the schema looks flat, maybe there are
        # multiple rows with same env_id?).
        #
        # We will group by env_id.
        pass

    # Group by env_id to handle multiple runs if they exist
    env_groups = {}
    for row in report_data:
        env_id = row['env_id']
        if env_id not in env_groups:
            env_groups[env_id] = []
        env_groups[env_id].append(row)

    for env_id, runs in env_groups.items():
        # Collect pre and post scores
        pre_scores = [r['pre_shift_score'] for r in runs]
        post_scores = [r['post_shift_score'] for r in runs]

        # If we have only one run, we cannot calculate a p-value.
        # We treat this as a failure to validate (p=1.0) and skip.
        if len(pre_scores) < 2:
            logger.warning(f"Environment {env_id}: Only {len(pre_scores)} run(s) found. Cannot calculate p-value. Skipping.")
            log_entries.append({
                "env_id": env_id,
                "status": "skipped_insufficient_runs",
                "reason": f"Only {len(pre_scores)} run(s) found, need >= 2",
                "p_value": None
            })
            failed_environments.append(runs[0]) # Add the first run to failed list
            continue

        # Calculate p-value
        p_val = calculate_p_value(pre_scores, post_scores)

        # Calculate average drop rate for this env
        avg_drop_rate = np.mean([r['drop_rate'] for r in runs])

        # Validation logic
        if p_val >= 0.05:
            logger.warning(f"Environment {env_id}: p-value {p_val:.4f} >= 0.05. Performance drop NOT statistically significant. Skipping.")
            log_entries.append({
                "env_id": env_id,
                "status": "failed_validation",
                "reason": f"p-value ({p_val:.4f}) >= 0.05",
                "p_value": p_val,
                "drop_rate": avg_drop_rate
            })
            failed_environments.append(runs[0])
        else:
            logger.info(f"Environment {env_id}: p-value {p_val:.4f} < 0.05. Valid for evolution.")
            # Update the row with the calculated p-value if needed, or just keep it valid
            # We take the first run's data and add p-value info if the schema allows,
            # but for the output list, we just return the valid rows.
            valid_env_row = runs[0].copy()
            valid_env_row['p_value'] = p_val
            valid_env_row['avg_drop_rate'] = avg_drop_rate
            valid_environments.append(valid_env_row)
            log_entries.append({
                "env_id": env_id,
                "status": "passed_validation",
                "reason": f"p-value ({p_val:.4f}) < 0.05",
                "p_value": p_val,
                "drop_rate": avg_drop_rate
            })

    # Write validation log
    os.makedirs(os.path.dirname(output_log_path) if os.path.dirname(output_log_path) else '.', exist_ok=True)
    with open(output_log_path, 'w', encoding='utf-8') as f:
        for entry in log_entries:
            f.write(json.dumps(entry) + '\n')

    logger.info(f"Validation complete. {len(valid_environments)} valid, {len(failed_environments)} skipped.")
    return valid_environments

def main():
    """Main entry point for T014."""
    # Paths
    base_dir = os.path.join(os.path.dirname(__file__), '..', '..')
    data_dir = os.path.join(base_dir, 'data')
    sensitivity_report_path = os.path.join(data_dir, 'sensitivity_report.csv')
    validation_log_path = os.path.join(data_dir, 'shift_validation.log')

    # Setup logging
    log_file = os.path.join(data_dir, 'shift_validation_task.log')
    logger = get_logger('shift_validation', log_file)
    logger.info("Starting T014: Shift Validation and P-Value Calculation")

    try:
        valid_envs = process_validation_report(sensitivity_report_path, validation_log_path)

        # Write valid environments to a JSON file for downstream tasks (T032a)
        valid_envs_path = os.path.join(data_dir, 'valid_evolution_envs.json')
        with open(valid_envs_path, 'w', encoding='utf-8') as f:
            json.dump(valid_envs, f, indent=2)

        logger.info(f"Valid environments written to {valid_envs_path}")

    except Exception as e:
        logger.error(f"Error during T014 execution: {e}")
        raise

if __name__ == '__main__':
    main()