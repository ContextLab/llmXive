class InferenceEngine:
    """
    Handles model loading and inference for the Teacher Distribution computation.
    Optimized for CPU/streaming to avoid OOM.
    """
    def __init__(self, model_name: str = "distilbert-base-uncased", device: str = "cpu"):
        self.model_name = model_name
        self.device = device
        self.tokenizer = None
        self.model = None
        self._load_model()

    def _load_model(self):
        """Load model and tokenizer."""
        try:
            self.tokenizer = AutoTokenizer.from_pretrained(self.model_name)
            if self.tokenizer.pad_token is None:
                self.tokenizer.pad_token = self.tokenizer.eos_token
            
            config = AutoConfig.from_pretrained(self.model_name)
            config.output_hidden_states = False # We only need logits
            config.return_dict = True

            self.model = AutoModelForCausalLM.from_pretrained(
                self.model_name,
                config=config,
                torch_dtype=torch.float32, # Force float32 for CPU stability
                low_cpu_mem_usage=True
            )
            self.model.to(self.device)
            self.model.eval()
            print(f"Loaded model {self.model_name} on {self.device}")
        except Exception as e:
            print(f"Error loading model: {e}", file=sys.stderr)
            raise

    def get_logits(self, text: str) -> np.ndarray:
        """
        Get the logit distribution for the last token of the input text.
        Returns a numpy array of shape (vocab_size,).
        """
        if self.model is None:
            raise RuntimeError("Model not loaded")

        inputs = self.tokenizer(
            text,
            return_tensors="pt",
            padding=True,
            truncation=True,
            max_length=512
        ).to(self.device)

        with torch.no_grad():
            outputs = self.model(**inputs)
            # outputs.logits shape: (batch_size, seq_len, vocab_size)
            # We want the logits for the last token
            last_token_logits = outputs.logits[:, -1, :] # (1, vocab_size)
            return last_token_logits.cpu().numpy().squeeze(0)

def load_context_splits(file_path: Path) -> List[Dict[str, Any]]:
    """
    Loads the context splits generated by T017.
    Expected format: list of dicts with 'prompt_text', 'privileged_context', 'target_rationales'.
    """
    if not file_path.exists():
        raise FileNotFoundError(f"Context splits file not found: {file_path}")
    
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    if not isinstance(data, list):
        raise ValueError("Context splits file must contain a JSON list")
    
    return data

def stream_aggregate_and_save(
    raw_logits_path: Path,
    output_path: Path,
    batch_size: int = 50
) -> Dict[str, Any]:
    """
    Reads raw logits from a JSONL file, computes the average distribution
    (Teacher Distribution) via streaming aggregation, and saves the result.
    
    This implements T048: Streaming aggregation to prevent OOM.
    """
    if not raw_logits_path.exists():
        raise FileNotFoundError(f"Raw logits file not found: {raw_logits_path}")
    
    # Accumulators
    total_sum = None
    count = 0
    vocab_size = None
    
    print(f"Starting streaming aggregation from {raw_logits_path}")
    
    with open(raw_logits_path, 'r', encoding='utf-8') as f_in:
        batch_buffer = []
        
        for line in f_in:
            line = line.strip()
            if not line:
                continue
            
            try:
                record = json.loads(line)
                # Expected format: {"prompt_id": "...", "logits": [...], ...}
                logits = record.get("logits")
                if logits is None:
                    print(f"Warning: Skipping record without 'logits' field")
                    continue
                
                logits_arr = np.array(logits, dtype=np.float32)
                
                if vocab_size is None:
                    vocab_size = len(logits_arr)
                elif len(logits_arr) != vocab_size:
                    print(f"Warning: Inconsistent vocab size {len(logits_arr)} vs {vocab_size}. Skipping.")
                    continue
                
                batch_buffer.append(logits_arr)
                
                if len(batch_buffer) >= batch_size:
                    # Process batch
                    batch_stack = np.stack(batch_buffer, axis=0) # (batch, vocab)
                    batch_sum = np.sum(batch_stack, axis=0)     # (vocab,)
                    
                    if total_sum is None:
                        total_sum = batch_sum
                    else:
                        total_sum += batch_sum
                    
                    count += len(batch_buffer)
                    batch_buffer = []
                    
                    if count % 1000 == 0:
                        print(f"Processed {count} records...")
                        
            except json.JSONDecodeError:
                print(f"Warning: Invalid JSON line, skipping.")
                continue
            except Exception as e:
                print(f"Error processing line: {e}")
                continue
        
        # Process remaining items in buffer
        if batch_buffer:
            batch_stack = np.stack(batch_buffer, axis=0)
            batch_sum = np.sum(batch_stack, axis=0)
            if total_sum is None:
                total_sum = batch_sum
            else:
                total_sum += batch_sum
            count += len(batch_buffer)
    
    if count == 0:
        raise ValueError("No valid logits found in the input file.")
    
    print(f"Aggregated {count} records. Computing average...")
    
    # Compute average
    teacher_dist = total_sum / count
    
    # Normalize to probabilities (softmax is already implicit if inputs were log probs, 
    # but task says "average of raw logits". We normalize to sum=1 for distribution representation)
    # To ensure numerical stability and valid probability distribution:
    # If inputs were log-probs, we should exp(avg(log_p)). 
    # If inputs were logits, we should softmax(avg(logits)).
    # Assuming "raw logits" means pre-softmax scores.
    # We apply softmax to the averaged logits to get the final distribution.
    max_val = np.max(teacher_dist)
    exp_logits = np.exp(teacher_dist - max_val)
    teacher_dist_probs = exp_logits / np.sum(exp_logits)
    
    # Save results
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    result = {
        "total_records": count,
        "vocab_size": int(vocab_size),
        "distribution": teacher_dist_probs.tolist(),
        "log_distribution": teacher_dist.tolist() # Save raw averaged logits too
    }
    
    with open(output_path, 'w', encoding='utf-8') as f_out:
        json.dump(result, f_out, indent=2)
    
    print(f"Teacher Distribution saved to {output_path}")
    return result

def main():
    """
    Main entry point for T048.
    1. Loads config for paths.
    2. Ensures context splits exist (dependency check).
    3. Checks for raw logits file (dependency on T021).
    4. Runs streaming aggregation.
    """
    print("=== T048: Teacher Distribution Averaging ===")
    
    # Load config
    try:
        config = load_config(CONFIG_PATH)
    except Exception as e:
        print(f"Error loading config: {e}")
        # Fallback to defaults if config missing
        config = {}
    
    raw_logits_path = DATA_DIR / "teacher_logits_raw.jsonl"
    output_path = DATA_DIR / "teacher_distribution.json"
    context_splits_path = DATA_DIR / "context_splits.json"
    
    # Dependency Checks
    if not context_splits_path.exists():
        print(f"ERROR: Missing dependency {context_splits_path}. Run T017 first.")
        sys.exit(1)
    
    if not raw_logits_path.exists():
        print(f"ERROR: Missing dependency {raw_logits_path}. Run T021 first.")
        sys.exit(1)
    
    try:
        result = stream_aggregate_and_save(raw_logits_path, output_path)
        print(f"Success. Processed {result['total_records']} records.")
    except FileNotFoundError as e:
        print(f"Critical Error: {e}")
        sys.exit(1)
    except Exception as e:
        print(f"Unexpected error during aggregation: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()