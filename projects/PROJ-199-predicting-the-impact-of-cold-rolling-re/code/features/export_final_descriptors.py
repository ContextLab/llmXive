"""
T020a: Output descriptors to data/processed/descriptors.csv linked to original sample IDs.

This script loads the calculated descriptors (from T018), applies the exclusion list
generated by T019 (mass balance verification), and writes the final clean dataset
to data/processed/descriptors.csv.

Dependency: T019 (Mass Balance Verification) must have run successfully to generate
the exclusion report.
"""
import os
import sys
import logging
import json
from pathlib import Path
from typing import List, Set, Optional
import pandas as pd

# Add project root to path if running as script
if "code" not in sys.path:
    project_root = Path(__file__).resolve().parent.parent
    sys.path.insert(0, str(project_root))

from utils.logging import get_logger
from config import get_data_path

logger = get_logger(__name__)

# File paths relative to project root
DESCRIPTORS_INPUT_PATH = "data/processed/descriptors.csv"
MASS_BALANCE_REPORT_PATH = "data/processed/mass_balance_report.json"
OUTPUT_PATH = "data/processed/descriptors.csv"

def load_descriptors(input_path: str) -> pd.DataFrame:
    """Load the raw descriptors calculated in T018."""
    path = Path(input_path)
    if not path.exists():
        raise FileNotFoundError(f"Input descriptors file not found: {path}")
    
    logger.info(f"Loading descriptors from {path}")
    df = pd.read_csv(path)
    
    # Validate required columns
    required_cols = ['sample_id', 'material', 'reduction', 'brass_fraction', 
                     'copper_fraction', 's_fraction', 'goss_fraction', 'random_fraction']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Descriptors file missing required columns: {missing}")
    
    return df

def load_exclusion_list(report_path: str) -> Set[str]:
    """Load the list of sample IDs to exclude from the T019 mass balance report."""
    path = Path(report_path)
    if not path.exists():
        logger.warning(f"Mass balance report not found at {path}. Proceeding with no exclusions.")
        return set()
    
    logger.info(f"Loading exclusion list from {path}")
    with open(path, 'r') as f:
        report = json.load(f)
    
    # The report structure typically contains a list of excluded samples
    excluded_samples = set()
    if 'excluded_samples' in report:
        for item in report['excluded_samples']:
            if isinstance(item, dict) and 'sample_id' in item:
                excluded_samples.add(item['sample_id'])
            elif isinstance(item, str):
                excluded_samples.add(item)
    
    logger.info(f"Found {len(excluded_samples)} samples to exclude based on mass balance failures.")
    return excluded_samples

def apply_exclusions(df: pd.DataFrame, excluded_ids: Set[str]) -> pd.DataFrame:
    """Filter the dataframe to remove excluded samples."""
    if not excluded_ids:
        return df
    
    initial_count = len(df)
    filtered_df = df[~df['sample_id'].isin(excluded_ids)]
    final_count = len(filtered_df)
    removed_count = initial_count - final_count
    
    logger.info(f"Filtered {removed_count} samples based on mass balance exclusions.")
    logger.info(f"Remaining valid samples: {final_count}")
    
    if final_count == 0:
        logger.error("All samples were excluded. The output file will be empty.")
    
    return filtered_df

def export_descriptors(df: pd.DataFrame, output_path: str):
    """Save the final clean descriptors to CSV."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Writing final descriptors to {path}")
    df.to_csv(path, index=False)
    logger.info("Export complete.")

def main():
    """Main entry point for T020a."""
    logger.info("Starting T020a: Export Final Descriptors (Mass Balance Filtered)")
    
    try:
        # 1. Load raw descriptors
        raw_df = load_descriptors(DESCRIPTORS_INPUT_PATH)
        
        # 2. Load exclusion list from T019
        excluded_ids = load_exclusion_list(MASS_BALANCE_REPORT_PATH)
        
        # 3. Apply exclusions
        clean_df = apply_exclusions(raw_df, excluded_ids)
        
        # 4. Export final CSV
        export_descriptors(clean_df, OUTPUT_PATH)
        
        logger.info("T020a completed successfully.")
        return 0
        
    except Exception as e:
        logger.error(f"T020a failed: {str(e)}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())