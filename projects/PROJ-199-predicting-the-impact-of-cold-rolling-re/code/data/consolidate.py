import os
import sys
import logging
from pathlib import Path
from typing import List, Optional, Dict, Any

import pandas as pd

from utils.logging import get_logger
from config import get_data_path

logger = get_logger(__name__)

# Ensure the output directory exists
DATA_PATH = Path(get_data_path())
PROCESSED_DIR = DATA_PATH / "processed"
PROCESSED_DIR.mkdir(parents=True, exist_ok=True)

def load_all_processed_datasets() -> pd.DataFrame:
    """
    Loads all processed EBSD data files from the 'processed' directory.
    
    Expects files generated by T014 (preprocess.py) which should be Parquet
    or CSV files containing columns: 
    'material', 'reduction', 'confidence', 'phi1', 'Phi', 'phi2', 'sample_id'.
    
    Returns:
        pd.DataFrame: Consolidated DataFrame of all valid processed data.
    """
    processed_files = list(PROCESSED_DIR.glob("*.parquet"))
    processed_files += list(PROCESSED_DIR.glob("*.csv"))
    
    if not processed_files:
        logger.warning(f"No processed data files found in {PROCESSED_DIR}")
        return pd.DataFrame()

    dataframes = []
    for file_path in processed_files:
        # Skip the target output file to avoid infinite loops if re-run
        if file_path.name == "cleaned_ebsd.parquet":
            continue

        try:
            logger.info(f"Loading {file_path}")
            if file_path.suffix == ".parquet":
                df = pd.read_parquet(file_path)
            else:
                df = pd.read_csv(file_path)
            
            # Basic validation of expected columns
            required_cols = ['material', 'reduction', 'confidence']
            if not all(col in df.columns for col in required_cols):
                logger.warning(f"Skipping {file_path}: Missing required columns {required_cols}")
                continue
            
            dataframes.append(df)
        except Exception as e:
            logger.error(f"Error loading {file_path}: {e}")
            continue

    if not dataframes:
        return pd.DataFrame()

    logger.info(f"Concatenating {len(dataframes)} files")
    return pd.concat(dataframes, ignore_index=True)

def write_consolidated_parquet(df: pd.DataFrame, output_path: Optional[Path] = None) -> Path:
    """
    Writes the consolidated DataFrame to a Parquet file.
    
    Args:
        df: The DataFrame to write.
        output_path: Optional path for the output file. Defaults to 
                     data/processed/cleaned_ebsd.parquet.
                     
    Returns:
        Path: The path to the written file.
    """
    if output_path is None:
        output_path = PROCESSED_DIR / "cleaned_ebsd.parquet"
    
    if df.empty:
        logger.warning("DataFrame is empty. Writing empty parquet file.")
        # Ensure the file is created even if empty to satisfy task artifact requirement
        # though typically this implies upstream failure
        df.to_parquet(output_path)
        return output_path

    logger.info(f"Writing consolidated data to {output_path}")
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    df.to_parquet(output_path, index=False)
    
    # Verify write
    if output_path.exists() and output_path.stat().st_size > 0:
        logger.info(f"Successfully wrote {len(df)} rows to {output_path}")
    else:
        raise IOError(f"Failed to write data to {output_path}")
        
    return output_path

def main():
    """
    Main entry point for T015: Generate consolidated Parquet output.
    """
    logger.info("Starting T015: Consolidating processed EBSD data")
    
    # Load all available processed data
    consolidated_df = load_all_processed_datasets()
    
    if consolidated_df.empty:
        logger.error("No data found to consolidate. Upstream tasks (T012-T014) may have failed.")
        # Create an empty file to satisfy artifact check, but log failure
        write_consolidated_parquet(consolidated_df)
        return 1
    
    # Write to the specified output path
    output_file = write_consolidated_parquet(consolidated_df)
    
    logger.info(f"T015 Complete. Output: {output_file}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
