"""
Module to generate the final research report for PROJ-421.
Aggregates results from power analysis, threshold detection, and sensitivity analysis.
"""
import os
import logging
import pandas as pd
from pathlib import Path
from typing import Optional, Dict, Any

from utils import get_logger
from visualization import find_threshold
from sensitivity_analysis import load_power_results, find_inflection_point, run_sensitivity_sweep
from type2_error_analysis import calculate_type2_error_delta

# Project root relative to this file
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_RESULTS_DIR = PROJECT_ROOT / "data" / "results"
POWER_RESULTS_PATH = DATA_RESULTS_DIR / "power_results.csv"
THRESHOLD_REPORT_PATH = DATA_RESULTS_DIR / "threshold_report.txt"
SENSITIVITY_REPORT_PATH = DATA_RESULTS_DIR / "sensitivity_report.txt"
TYPE2_ERROR_PATH = DATA_RESULTS_DIR / "type2_error_delta.csv"
FINAL_REPORT_PATH = DATA_RESULTS_DIR / "final_report.md"

def load_power_results() -> pd.DataFrame:
    """Load the power results CSV generated by analysis pipeline."""
    if not POWER_RESULTS_PATH.exists():
        raise FileNotFoundError(f"Power results not found at {POWER_RESULTS_PATH}. "
                                "Run the analysis pipeline first.")
    return pd.read_csv(POWER_RESULTS_PATH)

def generate_report_content(
    power_df: pd.DataFrame,
    threshold_info: Dict[str, Any],
    sensitivity_info: Dict[str, Any],
    type2_error_info: Dict[str, Any]
) -> str:
    """
    Construct the Markdown content for the final report.
    """
    report_lines = [
        "# Final Report: Assessing the Impact of Data Resolution on Statistical Power",
        "",
        "## Executive Summary",
        "",
        "This report presents the findings of the analysis on how spatial data resolution",
        "affects the statistical power to detect spatial autocorrelation (Moran's I).",
        "The study utilized NLCD land cover data for Colorado, aggregated from 30m to 480m",
        "resolutions, and evaluated power via Monte Carlo simulations.",
        "",
        f"**Key Finding**: The statistical power drops below the 0.80 threshold at **{threshold_info['threshold_resolution']}**.",
        "",
        "## Methodology",
        "",
        "- **Data Source**: NLCD 2019 Land Cover (30m) for Colorado.",
        "- **Resolutions Tested**: 30m, 60m, 120m, 240m, 480m (Factors: 1, 2, 4, 8, 16).",
        "- **Metric**: Moran's I for Binary Forest Indicator (Forest=1, Others=0).",
        "- **Null Hypothesis (H0)**: Random permutation (1,000 permutations).",
        "- **Alternative Hypothesis (H1)**: Gibbs Sampler simulation using calibrated lambda.",
        "- **Power Definition**: Proportion of H1 simulations where p-value < 0.05.",
        "",
        "## Results",
        "",
        "### Power vs. Resolution",
        "",
        "| Resolution | Aggregation Factor | Moran's I | P-Value | Statistical Power |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ]

    for _, row in power_df.iterrows():
        report_lines.append(
            f"| {row['resolution']} | {row['factor']} | {row['moran_i']:.4f} | "
            f"{row['p_value']:.4f} | {row['power']:.4f} |"
        )

    report_lines.extend([
        "",
        "### Threshold Identification",
        "",
        f"The analysis identified the resolution threshold where statistical power < 0.80:",
        f"- **Threshold Resolution**: {threshold_info['threshold_resolution']}",
        f"- **Power at Threshold**: {threshold_info['power_at_threshold']:.4f}",
        "",
        "### Type II Error Analysis",
        "",
        "Type II error (beta) is defined as 1 - Power. This represents the probability",
        "of failing to detect spatial autocorrelation when it exists.",
        "",
        "| Resolution | Type II Error (1 - Power) |",
        "| :--- | :--- |",
    ])

    for _, row in type2_error_info['deltas'].iterrows():
        report_lines.append(
            f"| {row['resolution']} | {row['type2_error']:.4f} |"
        )

    report_lines.extend([
        "",
        "### Sensitivity Analysis",
        "",
        "A sensitivity analysis was performed by sweeping the resolution aggregation factor",
        "by ±10% around the identified inflection point to assess threshold stability.",
        "",
        f"- **Inflection Point (Factor)**: {sensitivity_info['inflection_factor']}",
        f"- **Threshold Stability**: The threshold varies by **{sensitivity_info['max_variation_steps']}** resolution step(s).",
        "",
        "### Conclusion",
        "",
        f"The study concludes that for this dataset, spatial autocorrelation can be reliably",
        f"detected with >80% power at resolutions up to **{threshold_info['threshold_resolution']}**. ",
        f"Beyond this point, the Type II error rate increases significantly, indicating that",
        f"coarser data may mask underlying spatial patterns.",
        "",
        "---",
        f"*Report generated on: {pd.Timestamp.now().strftime('%Y-%m-%d %H:%M:%S')}*",
        f"*Based on analysis of {len(power_df)} resolution levels.*"
    ])

    return "\n".join(report_lines)

def main():
    """
    Main entry point to generate the final report.
    """
    logger = get_logger("generate_final_report")
    logger.info("Starting final report generation...")

    # Ensure output directory exists
    DATA_RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    try:
        # 1. Load Power Results
        logger.info(f"Loading power results from {POWER_RESULTS_PATH}")
        power_df = load_power_results()

        # 2. Determine Threshold
        logger.info("Calculating threshold...")
        # Re-calculate or load from existing file if preferred, 
        # but re-running ensures consistency with current data
        threshold_resolution, power_at_threshold = find_threshold(POWER_RESULTS_PATH)
        threshold_info = {
            "threshold_resolution": threshold_resolution,
            "power_at_threshold": power_at_threshold
        }
        logger.info(f"Threshold identified: {threshold_resolution} (Power: {power_at_threshold:.4f})")

        # 3. Calculate Type II Error
        logger.info("Calculating Type II error deltas...")
        type2_error_info = calculate_type2_error_delta(power_df)
        # Save the type2 error data for reference
        type2_error_info['deltas'].to_csv(TYPE2_ERROR_PATH, index=False)
        logger.info(f"Type II error data saved to {TYPE2_ERROR_PATH}")

        # 4. Sensitivity Analysis
        logger.info("Running sensitivity analysis...")
        inflection_factor = find_inflection_point(power_df)
        sensitivity_results = run_sensitivity_sweep(inflection_factor, power_df)
        
        # Determine max variation in steps
        # Assuming sensitivity_results contains a column 'variation_steps' or similar
        # If run_sensitivity_sweep returns a dict with 'max_variation_steps'
        max_variation = sensitivity_results.get('max_variation_steps', 0)
        
        sensitivity_info = {
            "inflection_factor": inflection_factor,
            "max_variation_steps": max_variation
        }
        logger.info(f"Sensitivity analysis complete. Max variation: {max_variation} steps")

        # 5. Generate Report Content
        logger.info("Generating Markdown content...")
        report_content = generate_report_content(
            power_df, threshold_info, sensitivity_info, type2_error_info
        )

        # 6. Write Report
        logger.info(f"Writing final report to {FINAL_REPORT_PATH}")
        with open(FINAL_REPORT_PATH, 'w', encoding='utf-8') as f:
            f.write(report_content)

        logger.info("Final report generation completed successfully.")
        return 0

    except FileNotFoundError as e:
        logger.error(f"Missing required data file: {e}")
        return 1
    except Exception as e:
        logger.error(f"Error generating report: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    exit(main())
