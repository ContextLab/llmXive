"""
Task T025: Save results (Moran's I, p-values, power estimates) to CSV.

This script reads the analysis results generated by the US2 pipeline
(specifically from `analysis.py` execution or intermediate logs) and
aggregates them into a single CSV file at `data/results/power_analysis.csv`.

It assumes that the `run_analysis_for_resolution` function (or the main
execution flow of `analysis.py`) has produced a summary dictionary or
list of dictionaries containing the metrics for each resolution.

If the intermediate results are not yet persisted in a standard format
(e.g., JSON logs), this script implements the logic to aggregate them
from the expected in-memory structure or a temporary JSON file if
generated by the previous step.
"""
import os
import json
import csv
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional

# Import from local project modules
from config import DATA_RESULTS_DIR, RESOLUTIONS, SEED
from utils import get_logger

# Ensure the results directory exists
os.makedirs(DATA_RESULTS_DIR, exist_ok=True)

logger = get_logger(__name__)

def load_analysis_results() -> List[Dict[str, Any]]:
    """
    Loads analysis results.
    
    This function attempts to load results from a temporary JSON file
    that would be written by `analysis.py` during the H0/H1 simulation loop.
    If that file does not exist (e.g., if the previous step didn't write it),
    it attempts to reconstruct the data structure if the previous step
    printed it, or raises a clear error if no data source is found.
    
    In a robust pipeline, `analysis.py` should write a `temp_results.json`
    or similar before exiting.
    """
    temp_file = Path(DATA_RESULTS_DIR) / "temp_analysis_results.json"
    
    if temp_file.exists():
        logger.info(f"Loading analysis results from {temp_file}")
        with open(temp_file, 'r') as f:
            return json.load(f)
    
    # Fallback: Check if we need to run the analysis again or if it's missing
    # For T025, we assume the data exists or is generated by the script itself
    # if the previous step failed to persist. However, per constraints, we
    # should not re-run heavy simulations here unless necessary.
    # If the file is missing, we raise an error to indicate the pipeline
    # is incomplete, rather than fabricating data.
    raise FileNotFoundError(
        f"Analysis results not found at {temp_file}. "
        "Please ensure `code/analysis.py` has been executed and saved results "
        "to `data/results/temp_analysis_results.json`."
    )

def save_results_to_csv(results: List[Dict[str, Any]], output_path: str) -> None:
    """
    Saves the list of result dictionaries to a CSV file.
    
    Expected columns:
    - resolution: The resolution string (e.g., '30m', '60m')
    - factor: The aggregation factor (1, 2, 4, 8, 16)
    - morn_i: Observed Moran's I
    - p_value: P-value from null distribution
    - power: Statistical power (rejection rate of H1)
    - h1_mean_moran: Mean Moran's I of H1 simulations
    - h0_mean_moran: Mean Moran's I of H0 null
    """
    if not results:
        logger.warning("No results to save.")
        return

    logger.info(f"Saving {len(results)} results to {output_path}")
    
    # Define standard fieldnames
    fieldnames = [
        "resolution", 
        "factor", 
        "moran_i", 
        "p_value", 
        "power", 
        "h1_mean_moran", 
        "h0_mean_moran",
        "n_permutations",
        "n_simulations"
    ]

    with open(output_path, 'w', newline='') as csvfile:
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        writer.writeheader()
        for row in results:
            # Ensure all fields are present, fill missing with None
            safe_row = {k: row.get(k, None) for k in fieldnames}
            writer.writerow(safe_row)

    logger.info(f"Successfully saved results to {output_path}")

def main():
    """Main entry point for T025."""
    try:
        # 1. Load results
        results = load_analysis_results()
        
        # 2. Define output path
        output_path = str(Path(DATA_RESULTS_DIR) / "power_analysis.csv")
        
        # 3. Save to CSV
        save_results_to_csv(results, output_path)
        
        logger.info("Task T025 completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(f"Data dependency missing: {e}")
        raise
    except Exception as e:
        logger.error(f"Error saving results: {e}")
        raise

if __name__ == "__main__":
    # Setup logging for this script
    setup_logger = get_logger("save_results", level=logging.INFO)
    main()
