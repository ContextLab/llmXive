"""
Type II Error Analysis Module (Task T030).

Calculates the Type II error delta (1 - power) relative to the 30m baseline
using the power results generated by previous analysis tasks.
"""
import os
import logging
import pandas as pd
from pathlib import Path
from utils import get_logger

# Ensure imports match the API surface provided in the prompt
# The prompt lists: from type2_error_analysis import calculate_type2_error_delta, main

def calculate_type2_error_delta(power_csv_path: str, baseline_resolution: str = "30m") -> pd.DataFrame:
    """
    Calculate Type II error delta (1 - power) for each resolution relative to the baseline.

    Args:
        power_csv_path: Path to the CSV file containing power results (from T025).
        baseline_resolution: The resolution string to use as the baseline (default: "30m").

    Returns:
        DataFrame with columns: resolution, power, type2_error_delta, is_baseline.
    """
    logger = get_logger(__name__)
    logger.info(f"Loading power results from {power_csv_path}")

    if not os.path.exists(power_csv_path):
        raise FileNotFoundError(f"Power results file not found: {power_csv_path}")

    df = pd.read_csv(power_csv_path)

    # Ensure required columns exist
    required_cols = ['resolution', 'power']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in power results: {missing_cols}")

    # Calculate Type II error delta: 1 - power
    df['type2_error_delta'] = 1.0 - df['power']

    # Identify baseline
    df['is_baseline'] = df['resolution'] == baseline_resolution

    # Sort by resolution (assuming numeric part or specific order)
    # We'll sort by the numeric factor if available, otherwise by string
    if 'factor' in df.columns:
        df = df.sort_values(by='factor')
    else:
        # Fallback: sort by resolution string, assuming format like "30m", "60m", etc.
        df['resolution_numeric'] = df['resolution'].str.replace('m', '').astype(int)
        df = df.sort_values(by='resolution_numeric')
        df = df.drop(columns=['resolution_numeric'])

    logger.info(f"Calculated Type II error delta for {len(df)} resolutions")
    logger.debug(f"Sample data:\n{df.head()}")

    return df

def main():
    """Main entry point for Type II Error Analysis."""
    logger = get_logger(__name__)
    
    # Define paths based on project structure
    base_dir = Path(__file__).parent.parent
    results_dir = base_dir / "data" / "results"
    power_csv_path = results_dir / "power_results.csv"
    output_csv_path = results_dir / "type2_error_analysis.csv"
    output_txt_path = results_dir / "type2_error_summary.txt"

    # Ensure results directory exists
    results_dir.mkdir(parents=True, exist_ok=True)

    try:
        # Calculate Type II error delta
        df_result = calculate_type2_error_delta(str(power_csv_path))

        # Save detailed results to CSV
        df_result.to_csv(output_csv_path, index=False)
        logger.info(f"Saved detailed Type II error analysis to {output_csv_path}")

        # Generate a summary text report
        baseline_row = df_result[df_result['is_baseline']]
        if not baseline_row.empty:
            baseline_power = baseline_row['power'].values[0]
            logger.info(f"Baseline (30m) Power: {baseline_power:.4f}")
        
            # Find the resolution with the highest Type II error (lowest power)
            max_error_row = df_result.loc[df_result['type2_error_delta'].idxmax()]
            logger.info(f"Max Type II Error Delta: {max_error_row['type2_error_delta']:.4f} at {max_error_row['resolution']}")

            # Write summary to text file
            with open(output_txt_path, 'w') as f:
                f.write("Type II Error Analysis Summary\n")
                f.write("=" * 40 + "\n")
                f.write(f"Baseline Resolution: 30m\n")
                f.write(f"Baseline Power: {baseline_power:.4f}\n")
                f.write(f"Baseline Type II Error Delta: {1.0 - baseline_power:.4f}\n")
                f.write("\n")
                f.write(f"Total Resolutions Analyzed: {len(df_result)}\n")
                f.write(f"Max Type II Error Delta: {max_error_row['type2_error_delta']:.4f}\n")
                f.write(f"Resolution with Max Error: {max_error_row['resolution']}\n")
                f.write("\n")
                f.write("Full details available in: type2_error_analysis.csv\n")

            logger.info(f"Saved summary report to {output_txt_path}")
        else:
            logger.warning("No baseline resolution (30m) found in results.")
            # Still save the CSV, but maybe not the summary
            df_result.to_csv(output_csv_path, index=False)

        print(f"Type II Error Analysis Complete. Results saved to {output_csv_path}")
        return 0

    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        return 1
    except Exception as e:
        logger.error(f"Error during analysis: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    exit(main())