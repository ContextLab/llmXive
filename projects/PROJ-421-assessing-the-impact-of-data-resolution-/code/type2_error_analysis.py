"""
Type II Error Delta Analysis Module.

This module calculates the increase in Type II error (1 - Power) relative to
the 30m baseline resolution for all derived resolutions.

It reads the existing `results.csv` generated by the power analysis pipeline,
identifies the baseline power at 30m, and appends a `type_ii_error_delta` column
representing the percentage point increase in error compared to that baseline.

Output:
    Updates `data/results/results.csv` in-place by appending the new column.
"""

import os
import logging
import pandas as pd
from pathlib import Path
from utils import get_logger

# Ensure project root is in path for imports if run as script
try:
    from utils import get_logger
except ImportError:
    # Fallback for direct execution if path isn't set
    import sys
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    from utils import get_logger

def calculate_type2_error_delta(results_path: str, output_path: str = None) -> pd.DataFrame:
    """
    Calculate the Type II error delta (1 - power) relative to the 30m baseline.

    The Type II error is defined as (1 - Power). The delta is the difference
    between the error at a given resolution and the error at the 30m baseline.
    Delta = Error(resolution) - Error(30m).

    Args:
        results_path: Path to the input results.csv file.
        output_path: Path to save the updated CSV. If None, overwrites input.

    Returns:
        The updated DataFrame containing the new column.
    """
    logger = get_logger(__name__)
    logger.info(f"Loading results from {results_path}")

    if not os.path.exists(results_path):
        raise FileNotFoundError(f"Results file not found at {results_path}. "
                                "Ensure T025/T025a has completed successfully.")

    df = pd.read_csv(results_path)

    if 'power' not in df.columns:
        raise ValueError(f"'power' column not found in {results_path}. "
                         "Cannot calculate Type II error without power estimates.")

    # Identify the 30m baseline.
    # Assuming the resolution column contains strings like "30m", "60m", etc.
    # or integers. We normalize to string comparison for robustness.
    df['resolution_str'] = df['resolution'].astype(str)
    
    # Filter for 30m baseline. Handle potential variations like '30', '30m', '30.0'
    baseline_mask = df['resolution_str'].str.contains('30', regex=False) & ~df['resolution_str'].str.contains('130', regex=False)
    
    if not baseline_mask.any():
        raise ValueError("Could not identify a 30m baseline resolution in the results. "
                         "Ensure the 30m analysis was included in the results file.")

    # If multiple rows for 30m (e.g., different classes), take the mean power for the baseline
    # or handle per-class if class_id exists. The task implies a general delta relative to baseline.
    # We will calculate delta per row based on the specific 30m row if class_id exists,
    # otherwise global mean.
    
    if 'class_id' in df.columns:
        # Calculate baseline per class_id
        baseline_powers = {}
        for cid in df['class_id'].unique():
            class_baseline = df[(df['resolution_str'].str.contains('30', regex=False)) & (df['class_id'] == cid)]['power'].mean()
            baseline_powers[cid] = class_baseline
        
        def get_delta(row):
            cid = row['class_id']
            if cid not in baseline_powers:
                # Fallback to global if specific class baseline missing (rare)
                global_mean = df[df['resolution_str'].str.contains('30', regex=False)]['power'].mean()
                error_baseline = 1.0 - global_mean
            else:
                error_baseline = 1.0 - baseline_powers[cid]
            
            current_error = 1.0 - row['power']
            return (current_error - error_baseline) * 100.0  # Percentage points

        df['type_ii_error_delta'] = df.apply(get_delta, axis=1)
    else:
        # Global baseline
        baseline_power = df[df['resolution_str'].str.contains('30', regex=False)]['power'].mean()
        error_baseline = 1.0 - baseline_power
        
        df['type_ii_error_delta'] = (1.0 - df['power']) - error_baseline
        df['type_ii_error_delta'] = df['type_ii_error_delta'] * 100.0  # Percentage points

    # Round to reasonable precision
    df['type_ii_error_delta'] = df['type_ii_error_delta'].round(4)

    logger.info(f"Calculated Type II error delta for {len(df)} rows.")
    logger.info(f"Sample deltas:\n{df[['resolution', 'power', 'type_ii_error_delta']].head()}")

    if output_path is None:
        output_path = results_path

    df.to_csv(output_path, index=False)
    logger.info(f"Updated results saved to {output_path}")

    return df

def main():
    """
    CLI entry point for Type II Error Delta calculation.
    
    Reads from data/results/results.csv and updates it in place.
    """
    logger = get_logger(__name__)
    project_root = Path(__file__).parent.parent
    results_path = project_root / "data" / "results" / "results.csv"
    
    if not results_path.exists():
        logger.error(f"Results file not found at {results_path}. "
                     "Run the full analysis pipeline (T025) first.")
        return

    try:
        calculate_type2_error_delta(str(results_path))
        logger.info("Task T030 completed successfully.")
    except Exception as e:
        logger.error(f"Failed to calculate Type II error delta: {e}")
        raise

if __name__ == "__main__":
    main()
