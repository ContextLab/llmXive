"""
Benjamini-Hochberg Correction for Multiple Testing.

This module implements the Benjamini-Hochberg (BH) procedure to control the
False Discovery Rate (FDR) when analyzing multiple land cover classes.
It reads the raw results from `results.csv` (generated by T035), applies the
correction, and writes the corrected p-values back to the same file.

Prerequisite: T035 (Multi-Class Sensitivity) must be completed to ensure
`results.csv` contains a `class_id` column.
"""

import os
import logging
import pandas as pd
from pathlib import Path
from typing import Optional, List, Dict, Any

# Import local utilities if available, otherwise fallback to standard logging
try:
    from utils import get_logger
except ImportError:
    def get_logger(name: str):
        logger = logging.getLogger(name)
        if not logger.handlers:
            handler = logging.StreamHandler()
            formatter = logging.Formatter('%(asctime)s - %(name)s - %(levelname)s - %(message)s')
            handler.setFormatter(formatter)
            logger.addHandler(handler)
            logger.setLevel(logging.INFO)
        return logger

logger = get_logger(__name__)

def load_results(csv_path: Path) -> pd.DataFrame:
    """
    Load the results CSV and validate the presence of the 'p_value' column.
    
    Args:
        csv_path: Path to the results CSV file.
        
    Returns:
        DataFrame containing the results.
        
    Raises:
        FileNotFoundError: If the CSV does not exist.
        ValueError: If required columns are missing.
    """
    if not csv_path.exists():
        raise FileNotFoundError(f"Results file not found: {csv_path}")
    
    df = pd.read_csv(csv_path)
    required_cols = ['p_value', 'class_id']
    missing = [col for col in required_cols if col not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in {csv_path}: {missing}")
    
    logger.info(f"Loaded {len(df)} rows from {csv_path}")
    return df

def apply_benjamini_hochberg(p_values: pd.Series, alpha: float = 0.05) -> pd.Series:
    """
    Apply the Benjamini-Hochberg procedure to a Series of p-values.
    
    The BH procedure controls the False Discovery Rate (FDR).
    Steps:
    1. Sort p-values in ascending order.
    2. Calculate critical values: (i / m) * alpha, where i is rank, m is count.
    3. Find the largest k such that p(k) <= (k / m) * alpha.
    4. Set all p-values with rank <= k to be significant (or adjust them).
    
    This implementation returns the adjusted p-values (q-values) for direct comparison.
    Adjusted p-value for rank i: min( (m/i) * p_i, ... ) ensuring monotonicity.
    
    Args:
        p_values: Series of raw p-values.
        alpha: Significance level (default 0.05).
        
    Returns:
        Series of adjusted p-values (same index as input).
    """
    m = len(p_values)
    if m == 0:
        return p_values
    
    # Create a DataFrame to track ranks and original indices
    df_p = pd.DataFrame({'p': p_values.values, 'orig_idx': p_values.index})
    
    # Sort by p-value
    df_p_sorted = df_p.sort_values('p').reset_index(drop=True)
    
    # Calculate ranks (1-based)
    ranks = np.arange(1, m + 1)
    
    # Calculate adjusted p-values (q-values)
    # Formula: q_i = min( (m / i) * p_i, 1 )
    # Enforce monotonicity from the bottom up (largest rank to smallest)
    q_values = (df_p_sorted['p'].values * m) / ranks
    q_values = np.minimum(q_values, 1.0)
    
    # Ensure monotonicity: q_i <= q_{i+1}
    # We iterate backwards to ensure that if a larger rank has a smaller q,
    # the smaller rank is capped at that value.
    for i in range(m - 2, -1, -1):
        if q_values[i] > q_values[i + 1]:
            q_values[i] = q_values[i + 1]
    
    df_p_sorted['p_adjusted'] = q_values
    
    # Sort back to original order
    df_p_final = df_p_sorted.sort_values('orig_idx')
    
    return pd.Series(df_p_final['p_adjusted'].values, index=df_p_final['orig_idx'])

def run_bh_correction(csv_path: Path, output_path: Optional[Path] = None, alpha: float = 0.05) -> Path:
    """
    Main entry point to apply BH correction to the results file.
    
    Reads `results.csv`, adds a `p_value_adj` column, and saves the result.
    If `output_path` is not provided, overwrites the input file.
    
    Args:
        csv_path: Path to the input results CSV.
        output_path: Optional path for the output CSV. Defaults to overwriting input.
        alpha: Significance level for FDR control.
        
    Returns:
        Path to the updated CSV file.
    """
    if output_path is None:
        output_path = csv_path
        
    logger.info(f"Starting Benjamini-Hochberg correction on {csv_path}")
    
    df = load_results(csv_path)
    
    # Apply correction globally across all classes and resolutions
    # The task implies correcting for the multiple tests performed across classes.
    # We treat the entire set of p-values as one family for FDR control.
    df['p_value_adj'] = apply_benjamini_hochberg(df['p_value'], alpha)
    
    # Add a boolean flag for significance based on adjusted p-value
    df['is_significant_adj'] = df['p_value_adj'] < alpha
    
    # Log summary statistics
    raw_sig = (df['p_value'] < alpha).sum()
    adj_sig = df['is_significant_adj'].sum()
    logger.info(f"Raw significant tests (< {alpha}): {raw_sig}")
    logger.info(f"Adjusted significant tests (< {alpha}): {adj_sig}")
    
    # Save to CSV
    df.to_csv(output_path, index=False)
    logger.info(f"Saved corrected results to {output_path}")
    
    return output_path

def main():
    """CLI entry point for Benjamini-Hochberg correction."""
    import argparse
    
    parser = argparse.ArgumentParser(description="Apply Benjamini-Hochberg correction to results.csv")
    parser.add_argument("--input", type=str, required=True, help="Path to results.csv")
    parser.add_argument("--output", type=str, default=None, help="Path to output CSV (default: overwrite input)")
    parser.add_argument("--alpha", type=float, default=0.05, help="FDR significance level")
    
    args = parser.parse_args()
    
    input_path = Path(args.input)
    output_path = Path(args.output) if args.output else None
    
    try:
        run_bh_correction(input_path, output_path, args.alpha)
        print("Correction completed successfully.")
    except Exception as e:
        logger.error(f"Correction failed: {e}")
        raise

if __name__ == "__main__":
    main()
