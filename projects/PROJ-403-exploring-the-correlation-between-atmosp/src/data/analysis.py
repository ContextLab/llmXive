"""
Wrapper module for the original analysis implementation.

This file re-exports all symbols from the original implementation located at
``code/src/data/analysis.py`` and adds the functionality required for task
**T035** – calculating percentage changes relative to the baseline AR‑detection
threshold and flagging bands/seasons that are “threshold‑sensitive”.

The original analysis code (functions for Pearson correlation, BH‑FDR
correction, sensitivity‑analysis orchestration, etc.) is kept untouched in
``code/src/data/analysis.py``.  By importing that module and updating the
current module’s ``globals()`` we preserve the full public API while only
extending it with the new helper.

The new helper ``calculate_percentage_change_and_flag`` expects a CSV file
produced by the earlier sensitivity‑aggregation step (task T034).  The CSV
must contain the columns:

* ``band``   – latitude‑band identifier (e.g. ``"30-40N"``)
* ``season`` – season identifier (e.g. ``"DJF"``)
* ``threshold`` – AR‑detection threshold value (kg m⁻¹ s⁻¹)
* ``significant_count`` – number of grid cells flagged as significant
  after BH‑FDR for that threshold

The function computes the percentage change of ``significant_count`` with
respect to the baseline threshold (the row where ``threshold`` equals the
baseline value passed via ``baseline_threshold``).  It adds two new columns:

* ``pct_change`` – percentage change relative to baseline (float)
* ``threshold_sensitive`` – boolean flag, ``True`` if ``abs(pct_change) >
  change_threshold`` (default 10 %).

The resulting table is written to ``output_path`` (CSV).  If the baseline
count for a given ``band``/``season`` pair is zero the function raises a
``ValueError`` to avoid division‑by‑zero ambiguities – this mirrors the
pipeline’s “fail loudly on invalid data” policy.

The wrapper is deliberately lightweight and does not interfere with the
existing pipeline logic.
"""

import importlib
import pathlib
import pandas as pd
from typing import Union

# ----------------------------------------------------------------------
# Re‑export original analysis implementation
# ----------------------------------------------------------------------
try:
    _original_analysis = importlib.import_module("code.src.data.analysis")
except ModuleNotFoundError as exc:
    raise ImportError(
        "Unable to locate the original analysis implementation at "
        "'code/src/data/analysis.py'. Ensure the original module exists "
        "and is importable."
    ) from exc

# Populate the current module's namespace with everything from the original.
globals().update(_original_analysis.__dict__)

# ----------------------------------------------------------------------
# New functionality for T035
# ----------------------------------------------------------------------
def calculate_percentage_change_and_flag(
    counts_csv_path: Union[str, pathlib.Path],
    output_csv_path: Union[str, pathlib.Path],
    baseline_threshold: float = 250.0,
    change_threshold: float = 10.0,
) -> None:
    """
    Calculate the percentage change in the number of significant correlation
    cells for each (band, season, threshold) relative to the baseline
    threshold, and flag entries where the change exceeds ``change_threshold``.

    Parameters
    ----------
    counts_csv_path : str or pathlib.Path
        Path to the CSV file generated by task T034.  Expected columns:
        ``band``, ``season``, ``threshold``, ``significant_count``.
    output_csv_path : str or pathlib.Path
        Destination path for the enriched CSV containing the additional
        columns ``pct_change`` and ``threshold_sensitive``.
    baseline_threshold : float, optional
        The AR‑detection threshold that defines the baseline (default 250.0
        kg m⁻¹ s⁻¹).  Rows with this exact threshold are used as the reference
        for percentage‑change calculations.
    change_threshold : float, optional
        Percentage‑change magnitude (absolute value) above which a band/season
        is considered “threshold‑sensitive”.  Default is 10 %.

    Raises
    ------
    FileNotFoundError
        If ``counts_csv_path`` does not exist.
    ValueError
        If the baseline count for a (band, season) pair is zero or missing.
    """
    # Resolve paths
    counts_path = pathlib.Path(counts_csv_path)
    out_path = pathlib.Path(output_csv_path)

    if not counts_path.is_file():
        raise FileNotFoundError(f"Counts CSV not found: {counts_path}")

    # Load the aggregation produced by T034
    df = pd.read_csv(counts_path)

    required_cols = {"band", "season", "threshold", "significant_count"}
    if not required_cols.issubset(df.columns):
        missing = required_cols - set(df.columns)
        raise ValueError(
            f"The counts CSV is missing required columns: {', '.join(missing)}"
        )

    # Identify baseline rows
    baseline_mask = df["threshold"] == baseline_threshold
    if not baseline_mask.any():
        raise ValueError(
            f"No baseline rows found for threshold={baseline_threshold}"
        )

    # Prepare a DataFrame with baseline counts indexed by (band, season)
    baseline_df = (
        df[baseline_mask]
        .set_index(["band", "season"])["significant_count"]
        .rename("baseline_count")
    )

    # Merge baseline counts back onto the full table
    df = df.set_index(["band", "season"])
    df = df.join(baseline_df, how="left")
    df.reset_index(inplace=True)

    # Verify that every row has a valid baseline count
    if df["baseline_count"].isnull().any():
        missing_idx = df[df["baseline_count"].isnull()][["band", "season"]]
        raise ValueError(
            "Missing baseline count for the following (band, season) pairs:\n"
            + missing_idx.to_string(index=False)
        )

    # Guard against division by zero
    if (df["baseline_count"] == 0).any():
        zero_baseline = df[df["baseline_count"] == 0][["band", "season"]]
        raise ValueError(
            "Baseline count is zero for the following (band, season) pairs, "
            "cannot compute percentage change:\n"
            + zero_baseline.to_string(index=False)
        )

    # Compute percentage change
    df["pct_change"] = (
        (df["significant_count"] - df["baseline_count"])
        / df["baseline_count"]
        * 100.0
    )

    # Flag threshold‑sensitive bands/seasons
    df["threshold_sensitive"] = df["pct_change"].abs() > change_threshold

    # Preserve original column order plus the new ones
    column_order = [
        "band",
        "season",
        "threshold",
        "significant_count",
        "pct_change",
        "threshold_sensitive",
    ]
    # Add any extra columns that might have been present (e.g., metadata)
    extra_cols = [c for c in df.columns if c not in column_order]
    final_columns = column_order + extra_cols

    # Write the enriched CSV
    out_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_path, index=False, columns=final_columns)

    # Log the operation (uses the logger from the original module if available)
    try:
        logger = get_logger(__name__)  # type: ignore[name-defined]
        logger.info(
            "Percentage‑change sensitivity file written to %s (rows: %d)",
            out_path,
            len(df),
        )
    except Exception:
        # If the original logger isn’t available, fall back to a simple print.
        print(f"Written sensitivity summary to {out_path}")

# Ensure the newly added name appears in the module’s ``__all__`` if it exists.
try:
    __all__.append("calculate_percentage_change_and_flag")  # type: ignore[name-defined]
except NameError:
    __all__ = ["calculate_percentage_change_and_flag"]  # type: ignore[assignment]