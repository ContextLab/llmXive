"""
Extract fixation metrics (first‑fixation probability, dwell time, fixation latency)
per region of interest (ROI) from raw eye‑tracking data.

The script expects the following directory layout (created by the project
bootstrap and verified by T002):

- data/raw/ds003123/eye_tracking/   – one or more CSV files containing raw
  gaze records.  Each file must contain at least the columns:
  ``trial_id``, ``participant_id``, ``stimulus_id``, ``timestamp_ms``,
  ``x``, ``y``, ``duration_ms``.
- data/interim/masks/                – binary PNG masks generated by
  ``code/eye_tracking/segment_roi.py``.  For every stimulus there must be
  ``<stimulus_id>_face.png`` and ``<stimulus_id>_weapon.png``.  The
  background ROI is defined as the complement of the two masks.

The script produces a single CSV file:

- data/interim/fixations.csv – columns
  ``trial_id,participant_id,stimulus_id,roi_type,dwell_time_ms,
  first_fixation_prob,fixation_latency_ms``

Trials with missing or malformed gaze data are excluded and a warning is
written to ``logs/fixation_warnings.log``.
"""

import csv
import json
import logging
from pathlib import Path
from typing import Dict, List, Tuple, Optional

import cv2
import numpy as np
import pandas as pd

from llmxive_toolkit import paths, get_logger

LOG = get_logger(__name__)

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def _load_mask(mask_path: Path) -> Optional[np.ndarray]:
    """
    Load a binary mask PNG as a boolean NumPy array.

    Returns ``None`` if the file does not exist or cannot be read.
    """
    if not mask_path.is_file():
        LOG.warning(f"Mask file not found: {mask_path}")
        return None
    img = cv2.imread(str(mask_path), cv2.IMREAD_GRAYSCALE)
    if img is None:
        LOG.warning(f"Unable to read mask image: {mask_path}")
        return None
    # Any non‑zero pixel is considered part of the ROI
    return img > 0

def _collect_masks(stimulus_id: str, masks_dir: Path) -> Dict[str, np.ndarray]:
    """
    Load face and weapon masks for a stimulus and build the background mask.

    Returns a dict mapping ROI type to a boolean mask array.
    Missing masks are treated as empty (all False) and a warning is logged.
    """
    face_path = masks_dir / f"{stimulus_id}_face.png"
    weapon_path = masks_dir / f"{stimulus_id}_weapon.png"

    face_mask = _load_mask(face_path) or np.zeros((1, 1), dtype=bool)
    weapon_mask = _load_mask(weapon_path) or np.zeros((1, 1), dtype=bool)

    # Ensure both masks have the same shape; if not, broadcast to the larger shape
    if face_mask.shape != weapon_mask.shape:
        max_h = max(face_mask.shape[0], weapon_mask.shape[0])
        max_w = max(face_mask.shape[1], weapon_mask.shape[1])
        LOG.warning(
            f"Mask shape mismatch for stimulus {stimulus_id}: "
            f"face {face_mask.shape}, weapon {weapon_mask.shape}. "
            f"Resizing to ({max_h}, {max_w})."
        )
        face_mask = cv2.resize(
            face_mask.astype(np.uint8), (max_w, max_h), interpolation=cv2.INTER_NEAREST
        ).astype(bool)
        weapon_mask = cv2.resize(
            weapon_mask.astype(np.uint8), (max_w, max_h), interpolation=cv2.INTER_NEAREST
        ).astype(bool)

    background_mask = np.logical_not(np.logical_or(face_mask, weapon_mask))

    return {
        "face": face_mask,
        "weapon": weapon_mask,
        "background": background_mask,
    }

def _assign_fixation_to_roi(
    x: float, y: float, masks: Dict[str, np.ndarray]
) -> str:
    """
    Determine which ROI a fixation falls into.

    ``x`` and ``y`` are pixel coordinates in the original image space.
    The function returns one of ``'face'``, ``'weapon'`` or ``'background'``.
    If the coordinate falls outside the mask dimensions, ``'background'`` is
    returned (the safest assumption).
    """
    # Round to nearest integer pixel index
    ix, iy = int(round(x)), int(round(y))

    # All masks share the same shape
    mask_shape = next(iter(masks.values())).shape
    h, w = mask_shape

    if not (0 <= iy < h and 0 <= ix < w):
        return "background"

    for roi, mask in masks.items():
        if mask[iy, ix]:
            return roi
    return "background"

# ----------------------------------------------------------------------
# Core extraction logic
# ----------------------------------------------------------------------
def _process_eye_tracking_file(
    file_path: Path,
    masks_dir: Path,
) -> Tuple[
    List[Dict[str, any]],
    Dict[str, int],
    int,
]:
    """
    Parse a single eye‑tracking CSV file.

    Returns
    -------
    - rows: list of dicts ready for CSV output (one per trial‑ROI)
    - first_fix_counts: dict counting how many trials had the first
      fixation in each ROI
    - total_trials: total number of trials processed from this file
    """
    required_cols = {
        "trial_id",
        "participant_id",
        "stimulus_id",
        "timestamp_ms",
        "x",
        "y",
        "duration_ms",
    }

    try:
        df = pd.read_csv(file_path)
    except Exception as exc:
        LOG.error(f"Failed to read eye‑tracking file {file_path}: {exc}")
        raise

    missing = required_cols - set(df.columns)
    if missing:
        LOG.error(
            f"Eye‑tracking file {file_path} missing required columns: {missing}"
        )
        raise RuntimeError(
            f"Eye‑tracking file {file_path} missing required columns: {missing}"
        )

    rows_out: List[Dict[str, any]] = []
    first_fix_counts: Dict[str, int] = {"face": 0, "weapon": 0, "background": 0}
    total_trials = 0

    # Group by trial
    for (trial_id, participant_id, stimulus_id), trial_df in df.groupby(
        ["trial_id", "participant_id", "stimulus_id"]
    ):
        total_trials += 1
        trial_df = trial_df.sort_values("timestamp_ms")
        masks = _collect_masks(stimulus_id, masks_dir)

        # Determine ROI of the *first* fixation (overall)
        first_fix = trial_df.iloc[0]
        first_roi = _assign_fixation_to_roi(
            first_fix["x"], first_fix["y"], masks
        )
        first_fix_counts[first_roi] += 1

        # Initialise per‑ROI aggregates
        dwell: Dict[str, float] = {"face": 0.0, "weapon": 0.0, "background": 0.0}
        latency: Dict[str, Optional[float]] = {
            "face": None,
            "weapon": None,
            "background": None,
        }

        # Iterate through fixations in temporal order
        for _, fix in trial_df.iterrows():
            roi = _assign_fixation_to_roi(fix["x"], fix["y"], masks)
            dwell[roi] += float(fix["duration_ms"])

            # Record latency only for the *first* fixation that lands in the ROI
            if latency[roi] is None:
                latency[roi] = float(fix["timestamp_ms"])

        # Build output rows (one per ROI)
        for roi_type in ("face", "weapon", "background"):
            rows_out.append(
                {
                    "trial_id": trial_id,
                    "participant_id": participant_id,
                    "stimulus_id": stimulus_id,
                    "roi_type": roi_type,
                    "dwell_time_ms": dwell[roi_type],
                    "first_fixation_prob": None,  # placeholder – filled later
                    "fixation_latency_ms": latency[roi_type],
                }
            )

    return rows_out, first_fix_counts, total_trials

def main() -> int:
    """
    Entry point for the fixation‑extraction task (T005).

    Returns
    -------
    int
        Exit code (0 = success, non‑zero = error).
    """
    try:
        eye_dir = paths.raw("ds003123", "eye_tracking")
        masks_dir = paths.interim("masks")
        output_path = paths.interim("fixations.csv")
        warning_log = paths.logs("fixation_warnings.log")

        # Ensure output directory exists
        output_path.parent.mkdir(parents=True, exist_ok=True)
        warning_log.parent.mkdir(parents=True, exist_ok=True)

        all_rows: List[Dict[str, any]] = []
        aggregate_first_fix: Dict[str, int] = {"face": 0, "weapon": 0, "background": 0}
        total_trials = 0

        eye_files = sorted(
            list(eye_dir.glob("*.csv"))
            + list(eye_dir.glob("*.tsv"))
            + list(eye_dir.glob("*.txt"))
        )
        if not eye_files:
            LOG.error(f"No eye‑tracking files found in {eye_dir}")
            raise RuntimeError(f"No eye‑tracking files found in {eye_dir}")

        for ef in eye_files:
            LOG.info(f"Processing eye‑tracking file {ef.name}")
            try:
                rows, first_counts, trials = _process_eye_tracking_file(
                    ef, masks_dir
                )
                all_rows.extend(rows)
                for roi in aggregate_first_fix:
                    aggregate_first_fix[roi] += first_counts.get(roi, 0)
                total_trials += trials
            except Exception as exc:
                LOG.error(f"Skipping file {ef.name} due to error: {exc}")
                with warning_log.open("a", encoding="utf-8") as wlog:
                    wlog.write(
                        f"{ef.name}: {exc}\n"
                    )
                continue

        if total_trials == 0:
            LOG.error("No valid trials processed – aborting.")
            return 1

        # Compute first‑fixation probability per ROI (global metric)
        first_fix_prob = {
            roi: aggregate_first_fix[roi] / total_trials
            for roi in aggregate_first_fix
        }

        # Fill the probability column
        for row in all_rows:
            row["first_fixation_prob"] = first_fix_prob[row["roi_type"]]

        # Write CSV
        df_out = pd.DataFrame(all_rows)
        df_out = df_out[
            [
                "trial_id",
                "participant_id",
                "stimulus_id",
                "roi_type",
                "dwell_time_ms",
                "first_fixation_prob",
                "fixation_latency_ms",
            ]
        ]
        df_out.to_csv(output_path, index=False)

        LOG.info(
            f"Fixation extraction completed. CSV written to {output_path}"
        )
        LOG.info(
            f"Processed {total_trials} trials across {len(eye_files)} files."
        )
        return 0

    except Exception as e:
        LOG.exception(f"Fatal error in fixation extraction: {e}")
        return 1

if __name__ == "__main__":
    import sys

    sys.exit(main())