"""
T024: Merge salience scores with eye-tracking metrics.

This module aligns the salience data (from US1) with the fixation metrics (from US2)
based on the TrialID.
"""
import os
import sys
import json
import logging
import numpy as np
import pandas as pd
from pathlib import Path
from typing import Optional, Dict, Any

from config import get_paths, load_config
from utils.logging import get_logger

logger = get_logger(__name__)

def load_salience_scores(salience_dir: Path) -> pd.DataFrame:
    """
    Load salience scores from the generated maps.
    
    Expects .npy files containing the mean salience score or a CSV index.
    For this implementation, we assume a CSV index exists or we compute the mean from .npy.
    """
    salience_data = []
    
    # Check for a pre-computed CSV index first
    csv_index = salience_dir.parent / "salience_index.csv"
    if csv_index.exists():
        logger.info(f"Loading salience index from {csv_index}")
        return pd.read_csv(csv_index)
    
    # Fallback: scan .npy files and compute mean
    files = list(salience_dir.glob("*.npy"))
    if not files:
        logger.warning(f"No salience maps found in {salience_dir}")
        return pd.DataFrame(columns=['trial_id', 'salience_score'])
    
    for f in files:
        try:
            data = np.load(f)
            mean_val = float(np.mean(data))
            salience_data.append({
                'trial_id': f.stem,
                'salience_score': mean_val
            })
        except Exception as e:
            logger.warning(f"Could not load salience map {f}: {e}")
    
    df = pd.DataFrame(salience_data)
    logger.info(f"Loaded {len(df)} salience scores from {salience_dir}")
    return df

def load_fixation_metrics(fixation_csv: Path) -> pd.DataFrame:
    """Load fixation metrics from the CSV generated by eye_tracking.py."""
    if not fixation_csv.exists():
        raise FileNotFoundError(f"Fixation metrics file not found: {fixation_csv}")
    
    df = pd.read_csv(fixation_csv)
    logger.info(f"Loaded {len(df)} fixation metrics from {fixation_csv}")
    return df

def merge_datasets(salience_df: pd.DataFrame, fixation_df: pd.DataFrame) -> pd.DataFrame:
    """
    Merge salience and fixation data on 'trial_id'.
    
    Uses an inner join to ensure only trials with both metrics are kept.
    """
    # Ensure column names match
    if 'trial_id' not in salience_df.columns:
        raise ValueError("Salience DataFrame missing 'trial_id' column")
    if 'trial_id' not in fixation_df.columns:
        raise ValueError("Fixation DataFrame missing 'trial_id' column")
    
    merged = pd.merge(
        fixation_df,
        salience_df[['trial_id', 'salience_score']],
        on='trial_id',
        how='inner'
    )
    
    logger.info(f"Merged dataset contains {len(merged)} rows (inner join)")
    dropped = len(fixation_df) + len(salience_df) - len(merged)
    if dropped > 0:
        logger.warning(f"Dropped {dropped} trials due to missing data in one of the sources.")
    
    return merged

def validate_alignment(df: pd.DataFrame) -> bool:
    """
    Basic validation that the merged dataframe has required columns.
    Returns True if valid.
    """
    required_cols = ['trial_id', 'salience_score']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        logger.error(f"Merged dataset missing required columns: {missing}")
        return False
    
    # Check for NaN in critical columns
    if df['salience_score'].isna().any():
        logger.warning("Merged dataset contains NaN values in 'salience_score'.")
        return False
    
    return True

def write_aligned_dataset(df: pd.DataFrame, output_path: Path, disclaimer: str = "") -> None:
    """Write the aligned dataset to CSV."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Add disclaimer if provided
    if disclaimer:
        logger.info(f"Appending disclaimer to {output_path}: {disclaimer}")
        # We append the disclaimer to the file content or a separate metadata file
        # For CSV, we can add a comment at the top or a specific column
        # Here we just write the CSV and assume the disclaimer is in the metadata
        # Or we can write a small JSON sidecar
        sidecar = output_path.with_suffix('.json')
        with open(sidecar, 'w') as f:
            json.dump({'disclaimer': disclaimer}, f)
    
    df.to_csv(output_path, index=False)
    logger.info(f"Wrote aligned dataset to {output_path}")

def main() -> None:
    """Main entry point for T024."""
    config = load_config()
    paths = get_paths()
    
    salience_dir = paths['processed_dir'] / 'salience_maps'
    fixation_csv = paths['interim_dir'] / 'fixation_metrics.csv'
    output_csv = paths['processed_dir'] / 'aligned_metrics.csv'
    
    disclaimer = "CORRELATIONAL ONLY - Do not infer causality."
    
    logger.info("Starting alignment (T024)...")
    
    try:
        salience_df = load_salience_scores(salience_dir)
        fixation_df = load_fixation_metrics(fixation_csv)
        
        merged_df = merge_datasets(salience_df, fixation_df)
        
        if not validate_alignment(merged_df):
            raise ValueError("Alignment validation failed.")
        
        write_aligned_dataset(merged_df, output_csv, disclaimer)
        
        logger.info("Alignment completed successfully.")
        
    except Exception as e:
        logger.error(f"Alignment failed: {e}")
        raise

if __name__ == "__main__":
    main()