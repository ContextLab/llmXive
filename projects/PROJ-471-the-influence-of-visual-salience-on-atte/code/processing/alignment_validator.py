"""
T025: Validate alignment of salience and fixation metrics.

This module performs the final validation step for User Story 2:
1. Ensures no trial ID mismatches between the merged dataset and source files.
2. Flags images with empty or invalid masks for manual review.
3. Generates a validation report in JSON format.
"""
import os
import sys
import json
import logging
import pandas as pd
from pathlib import Path
from typing import Dict, Any, List, Tuple, Optional

from config import get_paths, load_config
from utils.logging import get_logger

# Setup logger
logger = get_logger(__name__)

def load_aligned_dataset(path: Path) -> pd.DataFrame:
    """Load the aligned dataset generated by T024."""
    if not path.exists():
        raise FileNotFoundError(f"Aligned dataset not found at {path}")
    
    try:
        df = pd.read_csv(path)
        logger.info(f"Loaded aligned dataset with {len(df)} rows from {path}")
        return df
    except Exception as e:
        logger.error(f"Failed to load aligned dataset: {e}")
        raise

def load_salience_maps_index(salience_dir: Path) -> pd.DataFrame:
    """Create an index of available salience maps."""
    if not salience_dir.exists():
        logger.warning(f"Salience maps directory not found: {salience_dir}")
        return pd.DataFrame(columns=['trial_id', 'file_path', 'status'])
    
    files = list(salience_dir.glob("*.npy")) + list(salience_dir.glob("*.png"))
    records = []
    for f in files:
        # Assume filename format is {trial_id}.npy or similar
        trial_id = f.stem
        records.append({'trial_id': trial_id, 'file_path': str(f), 'status': 'exists'})
    
    df = pd.DataFrame(records)
    logger.info(f"Indexed {len(df)} salience maps from {salience_dir}")
    return df

def load_face_masks_index(masks_dir: Path) -> pd.DataFrame:
    """Create an index of face masks and detect empty/invalid ones."""
    if not masks_dir.exists():
        logger.warning(f"Face masks directory not found: {masks_dir}")
        return pd.DataFrame(columns=['trial_id', 'file_path', 'is_valid', 'mask_area'])
    
    # Look for mask files (assuming .npy or .png)
    files = list(masks_dir.glob("*.npy")) + list(masks_dir.glob("*.png"))
    records = []
    
    import numpy as np
    from PIL import Image
    
    for f in files:
        trial_id = f.stem
        is_valid = True
        mask_area = 0
        
        try:
            if f.suffix == '.npy':
                mask_data = np.load(f)
                mask_area = np.sum(mask_data > 0)
            elif f.suffix == '.png':
                img = Image.open(f)
                if img.mode != 'L':
                    img = img.convert('L')
                mask_data = np.array(img)
                mask_area = np.sum(mask_data > 0)
            else:
                is_valid = False
                mask_area = 0
            
            # Flag empty masks (area == 0)
            if mask_area == 0:
                is_valid = False
        except Exception as e:
            logger.warning(f"Could not read mask file {f}: {e}")
            is_valid = False
            mask_area = 0
        
        records.append({
            'trial_id': trial_id,
            'file_path': str(f),
            'is_valid': is_valid,
            'mask_area': mask_area
        })
    
    df = pd.DataFrame(records)
    logger.info(f"Indexed {len(df)} face masks from {masks_dir}")
    return df

def validate_alignment(df: pd.DataFrame, salience_index: pd.DataFrame, mask_index: pd.DataFrame) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """
    Validate the alignment of the merged dataset.
    
    Checks:
    1. All trial_ids in the aligned dataset have corresponding salience maps.
    2. All trial_ids in the aligned dataset have corresponding face masks.
    3. Flag trials where the face mask is empty/invalid.
    
    Returns:
      Tuple of (updated_df, validation_report)
    """
    report = {
        'total_trials': len(df),
        'missing_salience': [],
        'missing_masks': [],
        'empty_masks': [],
        'valid_trials': 0,
        'flagged_for_review': 0,
        'issues': []
    }
    
    # Check for missing salience maps
    salience_ids = set(salience_index['trial_id'].unique())
    aligned_ids = set(df['trial_id'].unique())
    
    missing_salience_ids = aligned_ids - salience_ids
    if missing_salience_ids:
        report['missing_salience'] = list(missing_salience_ids)
        report['issues'].append(f"Missing salience maps for {len(missing_salience_ids)} trials")
        logger.warning(f"Missing salience maps for {len(missing_salience_ids)} trials: {missing_salience_ids}")
    
    # Check for missing masks
    mask_ids = set(mask_index['trial_id'].unique())
    missing_mask_ids = aligned_ids - mask_ids
    if missing_mask_ids:
        report['missing_masks'] = list(missing_mask_ids)
        report['issues'].append(f"Missing face masks for {len(missing_mask_ids)} trials")
        logger.warning(f"Missing face masks for {len(missing_mask_ids)} trials: {missing_mask_ids}")
    
    # Check for empty/invalid masks
    if not mask_index.empty:
        invalid_mask_trials = mask_index[mask_index['is_valid'] == False]['trial_id'].tolist()
        if invalid_mask_trials:
            report['empty_masks'] = invalid_mask_trials
            report['issues'].append(f"Empty/invalid masks for {len(invalid_mask_trials)} trials")
            logger.warning(f"Empty/invalid masks for {len(invalid_mask_trials)} trials: {invalid_mask_trials}")
    
    # Mark trials for review
    review_ids = set(report['missing_salience']) | set(report['missing_masks']) | set(report['empty_masks'])
    
    # Add a column to the dataframe for review flag
    df['needs_manual_review'] = df['trial_id'].apply(lambda x: x in review_ids)
    
    report['valid_trials'] = len(df) - df['needs_manual_review'].sum()
    report['flagged_for_review'] = df['needs_manual_review'].sum()
    
    if report['issues']:
        logger.warning(f"Alignment validation found {len(report['issues'])} issues.")
    else:
        logger.info("Alignment validation passed: No mismatches or invalid masks found.")
    
    return df, report

def write_validation_report(report: Dict[str, Any], output_path: Path) -> None:
    """Write the validation report to a JSON file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2, default=str)
    
    logger.info(f"Validation report written to {output_path}")

def main() -> None:
    """Main entry point for T025 validation."""
    config = load_config()
    paths = get_paths()
    
    aligned_csv = paths['processed_dir'] / 'aligned_metrics.csv'
    salience_dir = paths['processed_dir'] / 'salience_maps'
    masks_dir = paths['interim_dir'] / 'face_masks'
    report_path = paths['interim_dir'] / 'alignment_validation_report.json'
    
    logger.info("Starting alignment validation (T025)...")
    
    try:
        # Load data
        df = load_aligned_dataset(aligned_csv)
        salience_index = load_salience_maps_index(salience_dir)
        mask_index = load_face_masks_index(masks_dir)
        
        # Validate
        validated_df, report = validate_alignment(df, salience_index, mask_index)
        
        # Write report
        write_validation_report(report, report_path)
        
        # Optionally, write the updated dataframe with the review flag back
        # This ensures the flag is persisted for downstream tasks
        validated_df.to_csv(aligned_csv, index=False)
        logger.info(f"Updated {aligned_csv} with 'needs_manual_review' flag.")
        
        # Exit with error if critical issues found (optional, depending on strictness)
        if report['missing_salience'] or report['missing_masks']:
            logger.error("Critical alignment failures detected. Manual review required.")
            # We do not exit with error code here to allow the pipeline to continue 
            # if the user wants to inspect the report, but we log the error loudly.
        
    except Exception as e:
        logger.error(f"Alignment validation failed: {e}")
        raise

if __name__ == "__main__":
    main()
