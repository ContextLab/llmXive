"""
Alignment script for the visual salience pipeline.

This script merges:
  1. Salience ROI mean scores (averaged over ROI masks)
  2. Low‑level visual features (luminance, contrast, edge density,
     scene complexity) generated by T006
  3. Fixation metrics extracted by T005
  4. Optional semantic covariates (currently none)

The result is written to `data/processed/aligned_data.csv` and
conforms to `contracts/dataset.schema.yaml`.  Rows that miss any
required component are flagged with ``excluded=True`` and a reason
is recorded in `data/processed/alignment_stats.json`.

The script is intended to be run as part of the pipeline
(`python -m code.analysis.align_data`).  It exits with status 0 on
success and raises ``RuntimeError`` on unrecoverable errors (e.g.
missing required input files).
"""

import json
import logging
from pathlib import Path
from collections import Counter

import cv2
import numpy as np
import pandas as pd

from llmxive_toolkit import paths, get_logger

log = get_logger(__name__)

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def _load_json(path: Path) -> dict:
    """Load a JSON file and return its contents."""
    if not path.is_file():
        raise RuntimeError(f"Required JSON file missing: {path}")
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)

def _load_csv(path: Path) -> pd.DataFrame:
    """Load a CSV file and return a DataFrame."""
    if not path.is_file():
        raise RuntimeError(f"Required CSV file missing: {path}")
    return pd.read_csv(path)

def _load_npy(path: Path) -> np.ndarray:
    """Load a .npy salience map."""
    if not path.is_file():
        raise RuntimeError(f"Salience map missing: {path}")
    return np.load(path)

def _load_mask(path: Path) -> np.ndarray:
    """Load a binary PNG mask as a boolean array."""
    if not path.is_file():
        raise RuntimeError(f"Mask file missing: {path}")
    mask = cv2.imread(str(path), cv2.IMREAD_GRAYSCALE)
    if mask is None:
        raise RuntimeError(f"Failed to read mask image: {path}")
    # Convert any non‑zero pixel to True
    return mask > 0

def _mean_salience_in_roi(salience: np.ndarray, mask: np.ndarray) -> float:
    """Return the mean salience value inside the ROI mask."""
    if mask.sum() == 0:
        # Empty mask – cannot compute a meaningful mean
        raise ValueError("Empty ROI mask")
    return float(salience[mask].mean())

# ----------------------------------------------------------------------
# Core alignment logic
# ----------------------------------------------------------------------
def align_data() -> None:
    """
    Perform the alignment and write the output files.

    Expected input locations (all under the project root):
      - Salience maps:      data/interim/salience_maps/<stimulus_id>.npy
      - ROI masks:          data/interim/masks/<stimulus_id>_<roi>.png
      - Low‑level features: data/interim/low_level_features.json
      - Fixation metrics:   data/interim/fixations.csv

    Outputs:
      - data/processed/aligned_data.csv
      - data/processed/alignment_stats.json
    """
    # Resolve paths
    salience_dir = paths.interim("salience_maps")
    masks_dir = paths.interim("masks")
    features_path = paths.interim("low_level_features.json")
    fixations_path = paths.interim("fixations.csv")
    aligned_csv_path = paths.processed("aligned_data.csv")
    stats_json_path = paths.processed("alignment_stats.json")

    # Load required inputs
    log.info("Loading low‑level visual features")
    low_level_features = _load_json(features_path)  # {stimulus_id: {...}}

    log.info("Loading fixation metrics")
    fixations_df = _load_csv(fixations_path)

    # Prepare caches for maps and masks to avoid repeated disk I/O
    salience_cache: dict[str, np.ndarray] = {}
    mask_cache: dict[tuple[str, str], np.ndarray] = {}

    rows = []
    exclusion_counter = Counter()

    log.info("Beginning row‑wise alignment")
    for idx, row in fixations_df.iterrows():
        trial_id = str(row["trial_id"])
        participant_id = str(row["participant_id"])
        stimulus_id = str(row["stimulus_id"])
        roi_type = str(row["roi_type"]).lower()  # expected: face, weapon, background

        # ------------------------------------------------------------------
        # Gather low‑level visual covariates
        # ------------------------------------------------------------------
        low_feat = low_level_features.get(stimulus_id)
        if low_feat is None:
            excluded = True
            reason = "missing_low_level_features"
            exclusion_counter[reason] += 1
            log.debug(f"Row {trial_id}: missing low‑level features for stimulus {stimulus_id}")
            # We still create a row with NaNs for the missing fields
            luminance = contrast = edge_density = scene_complexity = None
        else:
            luminance = low_feat.get("luminance")
            contrast = low_feat.get("contrast")
            edge_density = low_feat.get("edge_density")
            scene_complexity = low_feat.get("scene_complexity")

        # ------------------------------------------------------------------
        # Compute salience score for the ROI
        # ------------------------------------------------------------------
        salience_score = None
        try:
            # Load (or retrieve) the salience map for this stimulus
            if stimulus_id not in salience_cache:
                map_path = salience_dir / f"{stimulus_id}.npy"
                salience_cache[stimulus_id] = _load_npy(map_path)
            sal_map = salience_cache[stimulus_id]

            # Load (or retrieve) the mask for this ROI type
            mask_key = (stimulus_id, roi_type)
            if mask_key not in mask_cache:
                mask_path = masks_dir / f"{stimulus_id}_{roi_type}.png"
                mask_cache[mask_key] = _load_mask(mask_path)
            mask = mask_cache[mask_key]

            # Ensure dimensions match; if not, attempt a resize
            if sal_map.shape != mask.shape:
                log.debug(
                    f"Resizing mask for {stimulus_id}-{roi_type} "
                    f"from {mask.shape} to {sal_map.shape}"
                )
                mask = cv2.resize(
                    mask.astype(np.uint8),
                    (sal_map.shape[1], sal_map.shape[0]),
                    interpolation=cv2.INTER_NEAREST,
                ).astype(bool)

            salience_score = _mean_salience_in_roi(sal_map, mask)
        except Exception as e:
            # Any problem (missing files, empty mask, shape mismatch, etc.)
            excluded = True
            reason = "missing_salience_or_mask"
            exclusion_counter[reason] += 1
            log.debug(f"Row {trial_id}: salience computation failed – {e}")

        # ------------------------------------------------------------------
        # Determine overall exclusion status
        # ------------------------------------------------------------------
        # If any required component is missing, flag the row.
        if low_feat is None or salience_score is None:
            excluded = True
            # Already counted specific reasons above; add a generic one if not yet counted
            if low_feat is None:
                exclusion_counter["missing_low_level_features"] += 0  # ensure key exists
            if salience_score is None:
                exclusion_counter["missing_salience_or_mask"] += 0
        else:
            # If we got here without setting `excluded` earlier, the row is valid
            excluded = False

        # ------------------------------------------------------------------
        # Assemble the output row
        # ------------------------------------------------------------------
        output_row = {
            "trial_id": trial_id,
            "participant_id": participant_id,
            "stimulus_id": stimulus_id,
            "roi_type": roi_type,
            "dwell_time_ms": float(row["dwell_time_ms"]),
            "first_fixation_prob": float(row["first_fixation_prob"]),
            "fixation_latency_ms": float(row["fixation_latency_ms"]),
            "salience_score": float(salience_score) if salience_score is not None else None,
            "luminance": float(luminance) if luminance is not None else None,
            "contrast": float(contrast) if contrast is not None else None,
            "edge_density": float(edge_density) if edge_density is not None else None,
            "scene_complexity": int(scene_complexity) if scene_complexity is not None else None,
            "excluded": excluded,
        }
        rows.append(output_row)

    # ----------------------------------------------------------------------
    # Write the aligned CSV
    # ----------------------------------------------------------------------
    log.info(f"Writing aligned dataset with {len(rows)} rows to {aligned_csv_path}")
    aligned_df = pd.DataFrame(rows)

    # Ensure column order matches the schema
    column_order = [
        "trial_id",
        "participant_id",
        "stimulus_id",
        "roi_type",
        "dwell_time_ms",
        "first_fixation_prob",
        "fixation_latency_ms",
        "salience_score",
        "luminance",
        "contrast",
        "edge_density",
        "scene_complexity",
        "excluded",
    ]
    aligned_df = aligned_df[column_order]

    # Write CSV (NaNs are allowed; schema requires values, but excluded rows may have NaNs)
    aligned_df.to_csv(aligned_csv_path, index=False)

    # ----------------------------------------------------------------------
    # Write alignment statistics
    # ----------------------------------------------------------------------
    total_rows = len(rows)
    excluded_rows = sum(1 for r in rows if r["excluded"])
    stats = {
        "total_rows": total_rows,
        "excluded_rows": excluded_rows,
        "exclusion_rate": excluded_rows / total_rows if total_rows > 0 else 0.0,
        "reason_breakdown": dict(exclusion_counter),
    }
    log.info(f"Alignment stats: {stats}")
    with stats_json_path.open("w", encoding="utf-8") as f:
        json.dump(stats, f, indent=2)

    log.info("Alignment completed successfully.")

# ----------------------------------------------------------------------
# CLI entry point
# ----------------------------------------------------------------------
def main() -> int:
    """
    CLI entry point.

    Returns:
        int: Exit status (0 = success, non‑zero = failure)
    """
    try:
        align_data()
        return 0
    except Exception as exc:
        log.error(f"Alignment failed: {exc}", exc_info=True)
        raise

if __name__ == "__main__":
    raise SystemExit(main())