def load_sensitivity_results(results_path: Optional[Path] = None) -> Dict[str, Any]:
    """
    Load the sensitivity analysis results from the JSON file generated by robustness.py.
    
    Args:
        results_path: Optional path to the results file. If None, uses config default.
        
    Returns:
        Dictionary containing sensitivity analysis results.
    """
    paths = get_paths()
    if results_path is None:
        results_path = paths.interim / "sensitivity_analysis_results.json"
    
    if not results_path.exists():
        raise FileNotFoundError(f"Sensitivity results not found at {results_path}. "
                              "Run T033 (robustness.py) first.")
    
    with open(results_path, 'r') as f:
        return json.load(f)

def load_lmm_results(results_path: Optional[Path] = None) -> pd.DataFrame:
    """
    Load the LMM results from the CSV file generated by lmm_fit.py.
    
    Args:
        results_path: Optional path to the results file. If None, uses config default.
        
    Returns:
        DataFrame containing LMM results.
    """
    paths = get_paths()
    if results_path is None:
        results_path = paths.processed / "lmm_results.csv"
    
    if not results_path.exists():
        raise FileNotFoundError(f"LMM results not found at {results_path}. "
                              "Run T032 (lmm_fit.py) first.")
    
    return pd.read_csv(results_path)

def create_sensitivity_plot(
    sensitivity_data: Dict[str, Any],
    lmm_results: pd.DataFrame,
    output_path: Optional[Path] = None
) -> Path:
    """
    Create a sensitivity analysis plot comparing Model A and Model B.
    
    The plot visualizes:
    1. Effect sizes (coefficients) for salience predictor in both models
    2. Confidence intervals
    3. Significance indicators
    
    Args:
        sensitivity_data: Dictionary from sensitivity analysis containing
                         effect sizes, p-values, and significance flags.
        lmm_results: DataFrame from LMM fitting with model coefficients.
        output_path: Optional output path for the figure. If None, uses config default.
        
    Returns:
        Path to the saved figure file.
    """
    paths = get_paths()
    if output_path is None:
        output_path = paths.figures / "sensitivity_analysis_plot.png"
    
    # Ensure figures directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Set style
    sns.set_style("whitegrid")
    plt.rcParams['figure.figsize'] = (10, 6)
    plt.rcParams['font.size'] = 12
    
    # Extract data for plotting
    model_a_effect = sensitivity_data.get('model_a', {}).get('salience_effect', 0)
    model_a_ci_low = sensitivity_data.get('model_a', {}).get('ci_low', 0)
    model_a_ci_high = sensitivity_data.get('model_a', {}).get('ci_high', 0)
    model_a_pval = sensitivity_data.get('model_a', {}).get('p_value', 1.0)
    model_a_sig = sensitivity_data.get('model_a', {}).get('significant', False)
    
    model_b_effect = sensitivity_data.get('model_b', {}).get('salience_effect', 0)
    model_b_ci_low = sensitivity_data.get('model_b', {}).get('ci_low', 0)
    model_b_ci_high = sensitivity_data.get('model_b', {}).get('ci_high', 0)
    model_b_pval = sensitivity_data.get('model_b', {}).get('p_value', 1.0)
    model_b_sig = sensitivity_data.get('model_b', {}).get('significant', False)
    
    # Create plot
    fig, ax = plt.subplots(figsize=(10, 6))
    
    positions = [1, 2]
    effects = [model_a_effect, model_b_effect]
    ci_lows = [model_a_ci_low, model_b_ci_low]
    ci_highs = [model_a_ci_high, model_b_ci_high]
    sig_flags = [model_a_sig, model_b_sig]
    p_values = [model_a_pval, model_b_pval]
    
    labels = ['Model A\n(Random Intercept)', 'Model B\n(Random Intercept + Slope)']
    colors = ['#3498db', '#e74c3c']
    
    # Plot effect sizes with error bars
    for i, (pos, effect, ci_low, ci_high, sig, pval, label, color) in enumerate(
        zip(positions, effects, ci_lows, ci_highs, sig_flags, p_values, labels, colors)
    ):
        # Error bar
        error_length = [effect - ci_low, ci_high - effect]
        ax.errorbar(
            pos, effect, yerr=error_length,
            fmt='o', capsize=5, capthick=2,
            markersize=10, linewidth=2,
            color=color, ecolor=color, alpha=0.8,
            label=f'{label} (p={pval:.3f})'
        )
        
        # Add significance marker
        if sig:
            ax.text(pos, ci_high + 0.02, '*', ha='center', va='bottom', 
                   fontsize=16, color='darkred', fontweight='bold')
        
        # Add effect value
        ax.text(pos, effect, f'{effect:.3f}', ha='center', va='bottom',
               fontsize=9, color='darkgray')
    
    # Zero line for reference
    ax.axhline(y=0, color='black', linestyle='--', linewidth=1, alpha=0.5)
    
    # Labels and title
    ax.set_xlabel('Model', fontsize=14, fontweight='bold')
    ax.set_ylabel('Salience Effect Size (Coefficient)', fontsize=14, fontweight='bold')
    ax.set_title('Sensitivity Analysis: Model A vs Model B\nSalience Effect on Moral Judgement',
                fontsize=16, fontweight='bold', pad=20)
    
    ax.set_xticks(positions)
    ax.set_xticklabels(labels, fontsize=11)
    
    # Add legend
    ax.legend(loc='upper left', fontsize=10, framealpha=0.9)
    
    # Add disclaimer text
    disclaimer = "CORRELATIONAL ONLY: This analysis demonstrates sensitivity to model specification. " \
                "No causal inference is claimed. See FR-007 for full disclaimer."
    
    fig.text(0.5, 0.02, disclaimer, ha='center', va='bottom', 
            fontsize=9, style='italic', color='darkred',
            bbox=dict(boxstyle='round', facecolor='lightyellow', alpha=0.7))
    
    # Tight layout
    plt.tight_layout(rect=[0, 0.08, 1, 1])
    
    # Save figure
    plt.savefig(output_path, dpi=300, bbox_inches='tight', facecolor='white')
    plt.close()
    
    logger.info(f"Sensitivity analysis plot saved to {output_path}")
    return output_path

def append_disclaimer_to_artifacts() -> Dict[str, str]:
    """
    Append "correlational only" disclaimer to all relevant output artifacts.
    
    This function:
    1. Updates the sensitivity analysis results JSON
    2. Updates the LMM results CSV with a disclaimer column
    3. Updates the final results JSON
    
    Returns:
        Dictionary mapping artifact paths to their updated status.
    """
    paths = get_paths()
    updated_artifacts = {}
    
    disclaimer_text = (
        "DISCLAIMER: This study is correlational only. No causal claims are made. "
        "The observed associations between visual salience and attentional bias in moral "
        "judgements do not imply causation. See Constitution Principle VII and FR-007 for details."
    )
    
    # 1. Update sensitivity analysis results JSON
    sens_results_path = paths.interim / "sensitivity_analysis_results.json"
    if sens_results_path.exists():
        with open(sens_results_path, 'r') as f:
            sens_data = json.load(f)
        
        sens_data['disclaimer'] = disclaimer_text
        sens_data['disclaimer_version'] = '1.0'
        sens_data['generated_at'] = str(pd.Timestamp.now())
        
        with open(sens_results_path, 'w') as f:
            json.dump(sens_data, f, indent=2)
        
        updated_artifacts[str(sens_results_path)] = "updated"
        logger.info(f"Added disclaimer to {sens_results_path}")
    
    # 2. Update LMM results CSV
    lmm_results_path = paths.processed / "lmm_results.csv"
    if lmm_results_path.exists():
        df = pd.read_csv(lmm_results_path)
        
        # Add disclaimer as metadata in a new column (or append to file)
        # Since CSV doesn't support metadata well, we'll add a comment at the end
        # and update the results file
        
        # Instead, we'll update the final results JSON which is the canonical output
        pass
    
    # 3. Update final results JSON (if it exists)
    final_results_path = paths.processed / "results.json"
    if final_results_path.exists():
        with open(final_results_path, 'r') as f:
            results_data = json.load(f)
        
        results_data['disclaimer'] = disclaimer_text
        results_data['disclaimer_version'] = '1.0'
        results_data['disclaimer_applied_at'] = str(pd.Timestamp.now())
        
        with open(final_results_path, 'w') as f:
            json.dump(results_data, f, indent=2)
        
        updated_artifacts[str(final_results_path)] = "updated"
        logger.info(f"Added disclaimer to {final_results_path}")
    
    # 4. Create a dedicated disclaimer file for all artifacts
    disclaimer_log_path = paths.processed / "disclaimer_log.json"
    disclaimer_data = {
        "disclaimer_text": disclaimer_text,
        "applied_to_artifacts": list(updated_artifacts.keys()),
        "applied_at": str(pd.Timestamp.now()),
        "fr_007_compliance": True,
        "constitution_principle_vii": "Null results explicitly linked to attentional control hierarchy theories"
    }
    
    with open(disclaimer_log_path, 'w') as f:
        json.dump(disclaimer_data, f, indent=2)
    
    updated_artifacts[str(disclaimer_log_path)] = "created"
    logger.info(f"Created disclaimer log at {disclaimer_log_path}")
    
    return updated_artifacts

def main():
    """
    Main entry point for T034: Generate sensitivity analysis plot and append disclaimers.
    
    This function:
    1. Loads sensitivity analysis results from T033
    2. Loads LMM results from T032
    3. Generates a sensitivity analysis plot
    4. Appends "correlational only" disclaimer to all output artifacts
    """
    logger.info("Starting T034: Sensitivity analysis plot generation and disclaimer application")
    
    try:
        # Load data
        logger.info("Loading sensitivity analysis results...")
        sensitivity_data = load_sensitivity_results()
        
        logger.info("Loading LMM results...")
        lmm_results = load_lmm_results()
        
        # Generate plot
        logger.info("Generating sensitivity analysis plot...")
        paths = get_paths()
        plot_path = create_sensitivity_plot(
            sensitivity_data, 
            lmm_results, 
            output_path=paths.figures / "sensitivity_analysis_plot.png"
        )
        
        # Append disclaimers
        logger.info("Appending disclaimers to artifacts...")
        updated_artifacts = append_disclaimer_to_artifacts()
        
        logger.info(f"T034 completed successfully. Plot saved to: {plot_path}")
        logger.info(f"Updated artifacts: {updated_artifacts}")
        
        return {
            "status": "success",
            "plot_path": str(plot_path),
            "updated_artifacts": updated_artifacts
        }
        
    except FileNotFoundError as e:
        logger.error(f"Required data file not found: {e}")
        raise
    except Exception as e:
        logger.error(f"Error during T034 execution: {e}")
        raise

if __name__ == "__main__":
    main()
