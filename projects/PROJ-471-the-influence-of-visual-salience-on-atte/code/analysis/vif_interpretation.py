import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional

from config import get_paths, load_config
from utils.logging import get_logger

logger = get_logger(__name__)

def load_vif_verification_report(report_path: Path) -> Dict[str, Any]:
    """
    Load the VIF verification JSON report generated by vif_calc.py.
    """
    if not report_path.exists():
        raise FileNotFoundError(f"VIF verification report not found at {report_path}")
    
    with open(report_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def interpret_vif_results(vif_data: Dict[str, Any], threshold: float = 5.0) -> Dict[str, Any]:
    """
    Analyze VIF results to determine if multicollinearity is present.
    
    Args:
        vif_data: The loaded VIF verification report.
        threshold: The VIF threshold above which multicollinearity is considered high.
        
    Returns:
        A dictionary containing the interpretation results.
    """
    results = {
        "threshold": threshold,
        "max_vif": 0.0,
        "max_vif_feature": None,
        "high_vif_features": [],
        "recommendation": "PASS",
        "justification": ""
    }

    salience_vif = vif_data.get("salience_vif", 0.0)
    other_vifs = vif_data.get("other_features_vif", {})
    
    # Check Salience VIF specifically
    if salience_vif > threshold:
        results["high_vif_features"].append({
            "feature": "salience",
            "vif": salience_vif
        })
    
    # Check other features
    for feature, vif in other_vifs.items():
        if vif > threshold:
            results["high_vif_features"].append({
                "feature": feature,
                "vif": vif
            })

    # Determine max VIF
    all_vifs = [salience_vif] + list(other_vifs.values())
    if all_vifs:
        results["max_vif"] = max(all_vifs)
        results["max_vif_feature"] = "salience" if results["max_vif"] == salience_vif else max(
            other_vifs, key=other_vifs.get
        )

    # Generate Interpretation
    if results["high_vif_features"]:
        results["recommendation"] = "EXCLUDE_COVARIATES"
        feature_names = ", ".join([f["feature"] for f in results["high_vif_features"]])
        results["justification"] = (
            f"Multicollinearity detected: VIF > {threshold} for {feature_names}. "
            "As per SCR-002 (docs/scr_002_lowlevel_covariates_exclusion.md), "
            "low-level covariates (FR-009) are excluded from the final model to prevent "
            "statistical instability. The analysis will proceed with salience as the primary predictor."
        )
    else:
        results["recommendation"] = "SAFE_TO_INCLUDE"
        results["justification"] = (
            f"All VIF values are below the threshold of {threshold}. "
            "Low-level covariates could theoretically be included, but per SCR-002, "
            "they are excluded to maintain model parsimony and avoid potential multicollinearity."
        )

    return results

def write_vif_report(interpretation_results: Dict[str, Any], output_path: Path) -> None:
    """
    Write the VIF interpretation report to a text file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write("=" * 60 + "\n")
        f.write("VIF INTERPRETATION REPORT\n")
        f.write("=" * 60 + "\n\n")
        
        f.write(f"Threshold: {interpretation_results['threshold']}\n")
        f.write(f"Maximum VIF Observed: {interpretation_results['max_vif']:.4f}\n")
        f.write(f"Feature with Max VIF: {interpretation_results['max_vif_feature']}\n\n")
        
        f.write(f"Recommendation: {interpretation_results['recommendation']}\n\n")
        
        f.write("JUSTIFICATION / INTERPRETATION:\n")
        f.write("-" * 40 + "\n")
        f.write(f"{interpretation_results['justification']}\n\n")
        
        if interpretation_results["high_vif_features"]:
            f.write("High VIF Features Identified:\n")
            for item in interpretation_results["high_vif_features"]:
                f.write(f"  - {item['feature']}: VIF = {item['vif']:.4f}\n")
        
        f.write("\n" + "=" * 60 + "\n")
        f.write("END OF REPORT\n")
        f.write("=" * 60 + "\n")

def main() -> None:
    """
    Main entry point for VIF Interpretation task (T030a).
    """
    config = load_config()
    paths = get_paths()
    
    input_path = paths["interim"] / "vif_verification.json"
    output_path = paths["interim"] / "vif_report.txt"
    
    logger.info(f"Loading VIF verification report from {input_path}")
    
    try:
        vif_data = load_vif_verification_report(input_path)
    except FileNotFoundError as e:
        logger.error(f"Failed to load VIF report: {e}")
        logger.error("T030b (feature_gen) and T030 (vif_calc) must be completed first.")
        sys.exit(1)
    
    logger.info("Interpreting VIF results...")
    interpretation = interpret_vif_results(vif_data)
    
    logger.info(f"Writing VIF report to {output_path}")
    write_vif_report(interpretation, output_path)
    
    logger.info("VIF Interpretation (T030a) completed successfully.")
    logger.info(f"Recommendation: {interpretation['recommendation']}")

if __name__ == "__main__":
    main()
