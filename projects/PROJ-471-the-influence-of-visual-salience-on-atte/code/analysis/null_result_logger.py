"""
T035: Log null results explicitly linked to "theories of attentional control hierarchy".

This module implements Constitution Principle VII by analyzing the final LMM results
and explicitly logging null findings (non-significant effects of visual salience)
in the context of attentional control hierarchy theories (e.g., distinguishing
between stimulus-driven vs. goal-driven attention).
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional, List

# Import from existing project modules
from config import get_paths, load_config
from utils.logging import get_logger

def load_lmm_results(results_path: Path) -> Optional[Dict[str, Any]]:
    """Load the final LMM results from the JSON file generated by T032/T036."""
    if not results_path.exists():
        logger = get_logger(__name__)
        logger.warning(f"LMM results file not found at {results_path}. Skipping null result logging.")
        return None
    
    try:
        with open(results_path, 'r') as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        logger = get_logger(__name__)
        logger.error(f"Failed to parse LMM results JSON: {e}")
        return None

def analyze_null_results(results: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    Analyze LMM results to identify null findings (non-significant salience effects).
    
    Returns a list of dictionaries describing each null result, including:
    - model_name: Which model (A or B) produced the result
    - predictor: The predictor variable (e.g., 'salience_score')
    - estimate: The coefficient estimate
    - p_value: The p-value
    - interpretation: Contextual interpretation related to attentional control hierarchy
    """
    null_findings = []
    logger = get_logger(__name__)
    
    models = results.get('models', {})
    
    for model_name, model_data in models.items():
        fixed_effects = model_data.get('fixed_effects', [])
        
        for effect in fixed_effects:
            predictor = effect.get('term', '')
            p_value = effect.get('p_value')
            estimate = effect.get('estimate')
            
            if p_value is None:
                continue
            
            # Check for null result (p >= 0.05) for salience-related predictors
            # This is the core of T035: identifying when salience does NOT predict attention
            if 'salience' in predictor.lower() and p_value >= 0.05:
                finding = {
                    'model': model_name,
                    'predictor': predictor,
                    'estimate': estimate,
                    'p_value': p_value,
                    'is_null': True,
                    'theoretical_context': {
                        'theory': 'attentional_control_hierarchy',
                        'description': (
                            "Non-significant salience effect suggests that bottom-up, "
                            "stimulus-driven attention (as captured by DeepGaze II salience maps) "
                            "may not be the dominant factor in moral judgment trials. "
                            "This aligns with theories positing that top-down, goal-driven "
                            "attentional control (e.g., task relevance, moral salience of faces) "
                            "overrides low-level visual features in complex evaluative contexts."
                        ),
                        'implication': (
                            "The absence of a salience-attention link in this dataset supports "
                            "hierarchical models of attention where higher-order cognitive goals "
                            "modulate or suppress bottom-up capture, particularly in morally "
                            "charged visual scenes."
                        )
                    }
                }
                null_findings.append(finding)
                logger.info(
                    f"Null result identified in {model_name}: {predictor} "
                    f"(p={p_value:.4f}). Logged under attentional control hierarchy theory."
                )
    
    return null_findings

def write_null_result_report(null_findings: List[Dict[str, Any]], output_path: Path):
    """
    Write the null result analysis to a JSON report file.
    
    This report explicitly links null findings to theoretical interpretations
    as required by Constitution Principle VII.
    """
    logger = get_logger(__name__)
    
    report = {
        'task_id': 'T035',
        'constitutional_principle': 'VII',
        'description': (
            "Explicit logging of null results linked to theories of attentional control hierarchy. "
            "This report documents instances where visual salience (bottom-up attention) did not "
            "significantly predict eye-tracking metrics, supporting theoretical frameworks that "
            "prioritize top-down, goal-driven attention in moral judgment contexts."
        ),
        'null_findings': null_findings,
        'total_null_findings': len(null_findings),
        'theoretical_summary': (
            "Null results in this study suggest that in moral judgment tasks, "
            "attentional allocation is not primarily driven by low-level visual salience. "
            "This is consistent with hierarchical attentional control theories where "
            "higher-order goals (e.g., evaluating moral content) override stimulus-driven "
            "capture, especially when faces (social/moral cues) are the primary ROI."
        ),
        'generated_at': str(Path(output_path).parent.parent),  # Simple timestamp placeholder
        'disclaimer': "Correlational only - no causal claims inferred."
    }
    
    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Null result report written to {output_path}")

def main():
    """
    Main entry point for T035: Log null results linked to attentional control hierarchy.
    
    This function:
    1. Loads the final LMM results from data/processed/results.json
    2. Identifies non-significant salience effects
    3. Logs each null finding with theoretical context
    4. Writes a structured report to data/interim/null_result_analysis.json
    """
    logger = setup_logging_for_task()
    logger.info("Starting T035: Null result logging for attentional control hierarchy")
    
    # Load configuration
    config = load_config()
    paths = get_paths(config)
    
    # Define input and output paths
    lmm_results_path = paths['data_processed'] / 'results.json'
    null_report_path = paths['data_interim'] / 'null_result_analysis.json'
    
    # Ensure output directory exists
    null_report_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Load LMM results
    results = load_lmm_results(lmm_results_path)
    if results is None:
        logger.error("Cannot proceed with T035: LMM results not found. "
                     "Ensure T032/T036 has completed successfully.")
        return 1
    
    # Analyze for null results
    null_findings = analyze_null_results(results)
    
    if not null_findings:
        logger.info("No null results (non-significant salience effects) found in the LMM output. "
                    "This suggests salience may be a significant predictor in this dataset.")
        # Still write a report indicating no null findings
        write_null_result_report([], null_report_path)
    else:
        write_null_result_report(null_findings, null_report_path)
    
    logger.info("T035 completed successfully.")
    return 0

def setup_logging_for_task():
    """Setup logging for this specific task."""
    from utils.logging import setup_logging
    setup_logging()
    return get_logger(__name__)

if __name__ == '__main__':
    sys.exit(main())