"""
Performance optimization for salience generation using batched processing.

This module implements a memory-efficient batched inference pipeline for DeepGaze II
(and GBVS fallback) to optimize CPU resource usage and throughput. It processes
images in configurable batches to maintain RAM < 7GB while maximizing CPU utilization.

Features:
- Batched loading and inference to reduce memory fragmentation
- Multiprocessing pool for CPU-bound salience generation (optional)
- Progress tracking and logging
- Graceful handling of individual image failures (fallback or exclusion)
- Integration with existing salience_gen.py and fallback_heuristic.py logic
"""

