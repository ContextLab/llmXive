# Constants
DEFAULT_BATCH_SIZE = 4
DEFAULT_MAX_WORKERS = 4  # Match CPU cores usually available
MAX_MEMORY_GB = 6.5  # Safety margin below 7GB limit


def load_image_paths_from_metadata(metadata_path: Path) -> List[Dict[str, Any]]:
    """
    Load image paths from the metadata file generated by previous ingestion steps.
    Filters for images that need processing (e.g., missing salience map).

    Args:
        metadata_path: Path to metadata.json

    Returns:
        List of image metadata dictionaries needing processing
    """
    if not metadata_path.exists():
        logger.warning(f"Metadata file not found: {metadata_path}. Returning empty list.")
        return []

    with open(metadata_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    # Assuming data is a list of dicts with 'image_path' and 'map_path'
    # Filter for images where map_path is missing or invalid
    pending = []
    for item in data:
        if not item.get('map_path') or not Path(item['map_path']).exists():
            pending.append(item)
        else:
            logger.debug(f"Skipping {item.get('image_path')}: map already exists.")

    return pending


def process_single_image_batch(item: Dict[str, Any], deepgaze_model: Any) -> Tuple[str, Optional[SalienceResult], Optional[str]]:
    """
    Process a single image for salience, with fallback logic.
    This function is designed to be pickled for multiprocessing.

    Args:
        item: Dictionary containing 'image_path' and metadata
        deepgaze_model: Loaded DeepGaze model (Note: In real multiprocessing, model must be re-loaded per worker)

    Returns:
        Tuple of (image_id, result, error_message)
    """
    image_path = item.get('image_path')
    image_id = item.get('image_id', Path(image_path).stem)

    logger.info(f"Processing batch image: {image_id}")

    # Re-load model in worker if passed None (multiprocessing safety)
    # Note: DeepGaze model loading is heavy; in a real optimized pipeline,
    # we might use a shared memory model or reload per batch.
    # For CPU safety, we reload per worker to avoid serialization issues.
    model = deepgaze_model
    if model is None:
        try:
            model = load_deepgaze_model()
        except Exception as e:
            logger.error(f"Failed to load DeepGaze model in worker: {e}")
            return image_id, None, f"Model load error: {e}"

    try:
        # Check memory before processing
        mem_gb = get_memory_usage_gb()
        if mem_gb > MAX_MEMORY_GB:
            logger.warning(f"Memory usage high ({mem_gb:.2f}GB) before processing {image_id}. Skipping.")
            return image_id, None, "Memory limit exceeded pre-check"

        # Attempt DeepGaze generation
        result = process_image_with_monitoring(image_path, model)

        if result and result.success:
            return image_id, result, None
        else:
            # Fallback to GBVS
            logger.warning(f"DeepGaze failed for {image_id}, attempting GBVS fallback.")
            fallback_result = run_gvs(image_path)
            if fallback_result:
                # Construct a SalienceResult-like object or dict for consistency
                # Assuming run_gvs returns a numpy array or similar, we wrap it
                # The existing SalienceResult structure might need adaptation here
                # For now, we assume run_gvs returns a path or we construct a minimal result
                # Let's assume run_gvs returns (success, map_path, method) or similar
                # Based on fallback_heuristic signature: run_gvs(image_path)
                # We need to ensure it returns something compatible.
                # If run_gvs returns a path:
                if isinstance(fallback_result, str) and Path(fallback_result).exists():
                    return image_id, {
                        "success": True,
                        "map_path": fallback_result,
                        "method": "GBVS",
                        "image_path": image_path
                    }, None
                else:
                    # If it returns a tuple or object, adapt as needed
                    # Assuming standard return from fallback_heuristic
                    pass
            else:
                return image_id, None, "GBVS fallback failed"

    except Exception as e:
        logger.error(f"Error processing {image_id}: {e}")
        traceback.print_exc()
        return image_id, None, str(e)


def run_batched_salience_generation(
    metadata_path: Optional[Path] = None,
    output_dir: Optional[Path] = None,
    batch_size: int = DEFAULT_BATCH_SIZE,
    max_workers: int = DEFAULT_MAX_WORKERS,
    use_multiprocessing: bool = False
) -> Dict[str, Any]:
    """
    Main entry point for batched salience generation.

    Args:
        metadata_path: Path to metadata.json (defaults to project config)
        output_dir: Output directory for maps (defaults to project config)
        batch_size: Number of images to process in a batch
        max_workers: Max parallel workers (for multiprocessing)
        use_multiprocessing: Whether to use multiprocessing for CPU parallelism

    Returns:
        Summary statistics of the run
    """
    paths = get_paths()
    if metadata_path is None:
        metadata_path = paths.processed / "salience_maps" / "metadata.json"
    if output_dir is None:
        output_dir = paths.processed / "salience_maps"

    logger.info(f"Starting batched salience generation. Batch size: {batch_size}")
    logger.info(f"Input metadata: {metadata_path}")
    logger.info(f"Output dir: {output_dir}")

    # Load pending images
    pending_images = load_image_paths_from_metadata(metadata_path)
    total_images = len(pending_images)

    if total_images == 0:
        logger.info("No pending images found. Exiting.")
        return {"status": "success", "processed": 0, "failed": 0, "skipped": 0}

    logger.info(f"Found {total_images} images to process.")

    start_time = time.time()
    successful = 0
    failed = 0
    skipped = 0
    results = []

    # Pre-load model if not using multiprocessing (single process)
    deepgaze_model = None
    if not use_multiprocessing:
        try:
            deepgaze_model = load_deepgaze_model()
            logger.info("DeepGaze model loaded successfully for single-process mode.")
        except Exception as e:
            logger.error(f"Failed to load DeepGaze model: {e}")
            return {"status": "failed", "error": str(e)}

    # Process in batches
    for i in range(0, total_images, batch_size):
        batch = pending_images[i : i + batch_size]
        logger.info(f"Processing batch {i//batch_size + 1}: {len(batch)} images.")

        current_batch_results = []

        if use_multiprocessing:
            # Multiprocessing mode
            with ProcessPoolExecutor(max_workers=max_workers) as executor:
                # Note: Model cannot be passed directly to workers reliably if it's not picklable.
                # We pass None and let workers load it, or pass a path to a serialized model.
                # For safety, we pass None and workers load.
                futures = {
                    executor.submit(process_single_image_batch, item, None): item
                    for item in batch
                }
                for future in as_completed(futures):
                    image_id, result, error = future.result()
                    if result and (isinstance(result, dict) and result.get('success') or hasattr(result, 'success') and result.success):
                        successful += 1
                        current_batch_results.append({
                            "image_id": image_id,
                            "status": "success",
                            "map_path": result.get('map_path') if isinstance(result, dict) else getattr(result, 'map_path', None),
                            "method": result.get('method', 'DeepGaze')
                        })
                    else:
                        failed += 1
                        logger.error(f"Failed {image_id}: {error}")
                        current_batch_results.append({
                            "image_id": image_id,
                            "status": "failed",
                            "error": error
                        })
        else:
            # Single process mode (safer for complex models on some setups)
            for item in batch:
                image_id, result, error = process_single_image_batch(item, deepgaze_model)
                if result and (isinstance(result, dict) and result.get('success') or hasattr(result, 'success') and result.success):
                    successful += 1
                    current_batch_results.append({
                        "image_id": image_id,
                        "status": "success",
                        "map_path": result.get('map_path') if isinstance(result, dict) else getattr(result, 'map_path', None),
                        "method": result.get('method', 'DeepGaze')
                    })
                else:
                    failed += 1
                    logger.error(f"Failed {image_id}: {error}")
                    current_batch_results.append({
                        "image_id": image_id,
                        "status": "failed",
                        "error": error
                    })

        results.extend(current_batch_results)

        # Memory check between batches
        mem_gb = get_memory_usage_gb()
        if mem_gb > MAX_MEMORY_GB:
            logger.warning(f"High memory usage detected after batch: {mem_gb:.2f}GB. Pausing...")
            time.sleep(2)

    end_time = time.time()
    duration = end_time - start_time

    # Write summary report
    report = {
        "status": "completed",
        "total_images": total_images,
        "processed": successful,
        "failed": failed,
        "skipped": skipped,
        "duration_seconds": duration,
        "batch_size": batch_size,
        "use_multiprocessing": use_multiprocessing,
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "details": results
    }

    report_path = paths.interim / "salience_batch_report.json"
    with open(report_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)

    logger.info(f"Batched salience generation complete. Report saved to {report_path}")
    logger.info(f"Success: {successful}, Failed: {failed}, Duration: {duration:.2f}s")

    return report


def main():
    """
    Command-line entry point for batched salience generation.
    """
    import argparse

    parser = argparse.ArgumentParser(description="Batched Salience Generation")
    parser.add_argument("--metadata", type=str, help="Path to metadata.json")
    parser.add_argument("--batch-size", type=int, default=DEFAULT_BATCH_SIZE, help="Batch size")
    parser.add_argument("--workers", type=int, default=DEFAULT_MAX_WORKERS, help="Max workers for multiprocessing")
    parser.add_argument("--mp", action="store_true", help="Enable multiprocessing")
    args = parser.parse_args()

    setup_logging_for_task()

    metadata_path = Path(args.metadata) if args.metadata else None

    run_batched_salience_generation(
        metadata_path=metadata_path,
        batch_size=args.batch_size,
        max_workers=args.workers,
        use_multiprocessing=args.mp
    )


if __name__ == "__main__":
    main()
