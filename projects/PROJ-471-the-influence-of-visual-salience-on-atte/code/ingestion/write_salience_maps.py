"""
T016 Implementation: Write generated salience maps to disk.

Reads SalienceResult objects (generated by salience_gen.py) and writes
the salience maps to `data/processed/salience_maps/` with filenames
matching the StimulusImage IDs.
"""
import os
import sys
import json
import logging
import numpy as np
from pathlib import Path
from typing import List, Dict, Any, Optional

# Import from project API surface
from config import get_paths, load_config
from utils.logging import get_logger
from utils.versioning import register_artifact, compute_sha256
from data_models import StimulusImage

# Ensure the ingestion module is importable if run as a script
if __name__ == "__main__" and "code" not in sys.path:
    sys.path.insert(0, str(Path(__file__).parent.parent))

logger = get_logger(__name__)

class SalienceResult:
    """
    Data class representing the output of a salience generation run.
    Matches the public names expected by this module per the API surface.
    """
    def __init__(self, image_id: str, salience_map: np.ndarray, metadata: Optional[Dict[str, Any]] = None):
        self.image_id = image_id
        self.salience_map = salience_map
        self.metadata = metadata or {}

def load_salience_results(results_dir: Path) -> List[SalienceResult]:
    """
    Loads SalienceResult objects from a temporary staging directory or JSON/NPY files.
    
    In a real pipeline, salience_gen.py might output intermediate files (e.g., .npy)
    or a JSON manifest. This function assumes a manifest `salience_results_manifest.json`
    exists in the staging directory, pointing to the .npy map files.
    
    If the manifest doesn't exist, it scans the directory for .npy files matching
    the naming convention `{image_id}_map.npy`.
    """
    results = []
    
    manifest_path = results_dir / "salience_results_manifest.json"
    if manifest_path.exists():
        with open(manifest_path, 'r') as f:
            manifest = json.load(f)
        
        for entry in manifest.get("results", []):
            image_id = entry["image_id"]
            map_path = results_dir / entry["map_file"]
            
            if not map_path.exists():
                logger.warning(f"Map file missing for {image_id}: {map_path}")
                continue
            
            salience_map = np.load(map_path)
            results.append(SalienceResult(image_id, salience_map, entry.get("metadata", {})))
    else:
        # Fallback: scan for .npy files if manifest is missing
        # Expected naming: {image_id}_map.npy
        for npy_file in results_dir.glob("*_map.npy"):
            image_id = npy_file.stem.replace("_map", "")
            salience_map = np.load(npy_file)
            results.append(SalienceResult(image_id, salience_map))

    return results

def write_salience_maps(results: List[SalienceResult], output_dir: Path) -> List[str]:
    """
    Writes salience maps to the output directory.
    
    Files are saved as .npy to preserve the float32/float64 precision of the
    salience values. Filenames match the StimulusImage IDs as required.
    
    Args:
        results: List of SalienceResult objects.
        output_dir: Target directory path.
        
    Returns:
        List of paths to written files.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    written_paths = []

    for res in results:
        # Sanitize ID just in case, though StimulusImage IDs should be safe
        safe_id = res.image_id.replace("/", "_").replace("\\", "_")
        output_path = output_dir / f"{safe_id}.npy"
        
        # Validate map dimensions (DeepGaze II usually outputs 224x224 or matches input)
        if res.salience_map.ndim != 2:
            logger.error(f"Invalid map dimensions for {res.image_id}: {res.salience_map.shape}")
            continue

        np.save(output_path, res.salience_map)
        
        # Register artifact for versioning
        hash_val = compute_sha256(output_path)
        register_artifact(
            path=str(output_path.relative_to(Path.cwd())),
            hash=hash_val,
            artifact_type="salience_map"
        )
        
        written_paths.append(str(output_path))
        logger.info(f"Written salience map for {res.image_id} to {output_path}")

    return written_paths

def main():
    """
    Main entry point for T016.
    Reads intermediate salience results and writes final maps to data/processed/salience_maps/.
    """
    config = load_config()
    paths = get_paths()
    
    # Define paths
    # Assuming salience_gen.py outputs intermediate .npy files to data/interim/salience_stage/
    # or a manifest there.
    staging_dir = paths.get("data_interim", paths["data"] / "interim") / "salience_stage"
    output_dir = paths.get("data_processed", paths["data"] / "processed") / "salience_maps"
    
    if not staging_dir.exists():
        logger.error(f"Staging directory not found: {staging_dir}. Run salience_gen.py first.")
        sys.exit(1)

    logger.info(f"Loading salience results from {staging_dir}")
    results = load_salience_results(staging_dir)
    
    if not results:
        logger.warning("No salience results found to write.")
        sys.exit(0)

    logger.info(f"Writing {len(results)} salience maps to {output_dir}")
    written = write_salience_maps(results, output_dir)
    
    logger.info(f"Successfully wrote {len(written)} maps.")
    
    # Optional: Create a manifest of written files for downstream tasks (T018a)
    manifest = {
        "task": "T016",
        "written_files": written,
        "count": len(written)
    }
    manifest_path = output_dir / "written_manifest.json"
    with open(manifest_path, 'w') as f:
        json.dump(manifest, f, indent=2)
    register_artifact(str(manifest_path.relative_to(Path.cwd())), compute_sha256(manifest_path), "manifest")

if __name__ == "__main__":
    main()
