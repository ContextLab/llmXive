"""
Metadata Writer for Salience Maps (T016a)

This module generates `data/processed/salience_maps/metadata.json` containing a list
of processed image IDs and their corresponding map paths.

It relies on the output of `salience_gen.py` and `write_salience_maps.py` which
populate the `data/processed/salience_maps/` directory.
"""
import json
import logging
import os
from pathlib import Path
from typing import List, Dict, Any, Optional

from config import get_paths, load_config
from utils.logging import get_logger

# Initialize logger
logger = get_logger(__name__)


def scan_salience_maps_directory(output_dir: Path) -> List[Dict[str, Any]]:
    """
    Scans the output directory for generated salience map files (.npy).
    Extracts the StimulusID from the filename and constructs the metadata entry.

    Expected filename format: {StimulusID}.npy (e.g., "sub-001_img-01.npy")
    or any .npy file where the stem is treated as the ID.

    Args:
        output_dir: Path to the directory containing salience maps.

    Returns:
        A list of dictionaries with keys: 'stimulus_id', 'map_path', 'status'.
    """
    if not output_dir.exists():
        logger.warning(f"Output directory does not exist: {output_dir}")
        return []

    entries = []
    npy_files = list(output_dir.glob("*.npy"))

    if not npy_files:
        logger.warning(f"No .npy files found in {output_dir}")
        return []

    for file_path in npy_files:
        stimulus_id = file_path.stem  # Filename without extension
        # Construct relative path from the 'data' directory root to ensure portability
        # Assuming output_dir is data/processed/salience_maps
        # relative_path should be something like processed/salience_maps/{stimulus_id}.npy
        try:
            relative_path = str(file_path.relative_to(output_dir.parent.parent))
        except ValueError:
            # Fallback if parent structure is unexpected
            relative_path = str(file_path)

        entry = {
            "stimulus_id": stimulus_id,
            "map_path": relative_path,
            "status": "generated"
        }
        entries.append(entry)
        logger.debug(f"Indexed map: {stimulus_id} -> {relative_path}")

    return entries


def write_metadata_file(entries: List[Dict[str, Any]], output_path: Path) -> None:
    """
    Writes the metadata entries to a JSON file.

    Args:
        entries: List of metadata dictionaries.
        output_path: Full path to the output JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)

    metadata = {
        "version": "1.0",
        "description": "Metadata for processed salience maps. Generated by T016a.",
        "total_maps": len(entries),
        "maps": entries
    }

    try:
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(metadata, f, indent=2)
        logger.info(f"Successfully wrote metadata to {output_path}")
    except IOError as e:
        logger.error(f"Failed to write metadata file: {e}")
        raise


def main() -> None:
    """
    Main entry point for the metadata writer task.
    """
    config = load_config()
    paths = get_paths()

    # Define directories based on project structure
    salience_maps_dir = paths.processed / "salience_maps"
    metadata_output_path = salience_maps_dir / "metadata.json"

    logger.info(f"Scanning for salience maps in: {salience_maps_dir}")

    # Scan for generated maps
    entries = scan_salience_maps_directory(salience_maps_dir)

    if not entries:
        logger.warning("No salience maps found. Metadata file will be created with empty list.")
    
    # Write the metadata file
    write_metadata_file(entries, metadata_output_path)

    logger.info("Metadata writer task completed.")


if __name__ == "__main__":
    main()