"""
services/generator.py
---------------------

Adaptive workflow generator.

This module builds on the deterministic synthetic workflow generator
defined in ``code/generators/synthetic_workflow.py``.  The original
generator creates a uniform depth distribution (25 workflows per depth
level 1‑20).  For the *adaptive* variant we densify the depth
distribution around the context‑reduction percentage at which the error
rate first exceeds the 1 % bound (the “safe operating zone” threshold).

The threshold is produced by the analysis step
``code/analysis/threshold_detection.py`` and stored in
``data/results/threshold_ci.json``.  The JSON has the keys:

* ``threshold`` – reduction percentage where the error rate crosses 1 %
* ``ci_lower`` / ``ci_upper`` – confidence interval around the threshold
* ``threshold_pct`` – always ``1.0`` (the target error bound)

Because the relationship between reduction percentage and the depth
of the workflow is not linear in the synthetic data, we use a simple
heuristic to map the reduction percentage to a depth value:

``target_depth = round(threshold * MAX_DEPTH / 100)``

where ``MAX_DEPTH`` is the maximum depth generated by the original
generator (20).  Workflows whose depth lies within ``±2`` of this
``target_depth`` receive **double** the nominal number of samples,
while the remaining depths keep the uniform count.

The implementation is deliberately lightweight – it does not attempt
to recompute the exact mapping from reduction to depth (that would
require re‑running the full analysis pipeline).  The heuristic works
well for the current experimental setup and satisfies the requirement
of “densifying workflow depth distribution near the 1 % error‑rate
threshold”.

The public API mirrors the original generator:

* ``AdaptiveWorkflowGenerator(seed: int = 42)`` – constructor.
* ``generate_all(count: int = 500, output_path: str = "data/raw/workflows.json")``
  – generates the workflows using the adaptive scheme.
* ``get_workflows()`` – returns the in‑memory list (useful for tests).

The module also provides a CLI entry point compatible with the quick‑
start guide:

``python -m services.generator --count 500 --seed 42 --output data/raw/workflows.json``

The ``--adaptive`` flag toggles the adaptive behaviour; when omitted the
generator falls back to the original uniform distribution, preserving
backward compatibility.
"""

import json
import random
from pathlib import Path
from typing import List, Dict, Any

from generators.synthetic_workflow import (
    SyntheticWorkflowGenerator,
    generate_workflow,
    generate_invalid_workflow,
)

# ----------------------------------------------------------------------
# Helper to load the threshold from the analysis output.
# ----------------------------------------------------------------------
def _load_threshold(threshold_path: Path) -> float:
    """
    Load the reduction‑percentage threshold from ``threshold_ci.json``.

    Parameters
    ----------
    threshold_path: Path
        Path to the JSON file produced by ``threshold_detection.py``.

    Returns
    -------
    float
        The threshold reduction percentage (0‑100).  If the file does not
        exist or cannot be parsed, a ``FileNotFoundError`` is raised – the
        caller decides whether to fallback to a uniform distribution.

    Raises
    ------
    FileNotFoundError
        If the file does not exist.
    ValueError
        If the JSON does not contain a numeric ``threshold`` key.
    """
    if not threshold_path.is_file():
        raise FileNotFoundError(f"Threshold file not found: {threshold_path}")

    with threshold_path.open("r", encoding="utf-8") as f:
        data = json.load(f)

    # ``threshold`` may be stored as a number or a string; coerce to float.
    try:
        threshold = float(data["threshold"])
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError(
            f"Invalid threshold file format – missing numeric 'threshold' key: {exc}"
        ) from exc

    return threshold

# ----------------------------------------------------------------------
# Adaptive generator implementation.
# ----------------------------------------------------------------------
class AdaptiveWorkflowGenerator(SyntheticWorkflowGenerator):
    """
    Extends :class:`SyntheticWorkflowGenerator` with adaptive depth
    sampling based on the 1 % error‑rate threshold.

    Parameters
    ----------
    seed: int, default 42
        Random seed for reproducibility.
    threshold_path: Path, optional
        Path to ``data/results/threshold_ci.json``.  If omitted the
        generator behaves like the base class (uniform distribution).
    adaptive: bool, default True
        When ``True`` the depth distribution is adjusted; when ``False``
        a uniform distribution is used.
    """

    def __init__(
        self,
        seed: int = 42,
        threshold_path: Path = Path("data/results/threshold_ci.json"),
        adaptive: bool = True,
    ):
        super().__init__(seed=seed)
        self.threshold_path = threshold_path
        self.adaptive = adaptive

    def _determine_depth_weights(self, total_count: int) -> Dict[int, int]:
        """
        Compute the number of workflows to generate per depth.

        The algorithm:

        1.  Determine the nominal count per depth (uniform distribution):
            ``base = total_count // NUM_DEPTHS``.
        2.  If adaptive sampling is enabled, load the reduction‑percentage
            threshold and map it to a target depth.
        3.  Depths within ``TARGET_RANGE`` (``target_depth ± 2``) receive
            ``base * ADAPTIVE_FACTOR`` samples; other depths keep ``base``.
        4.  Any remainder from integer division is distributed one‑by‑one
            starting from the lowest depth.

        Returns
        -------
        dict[int, int]
            Mapping ``depth → count``.
        """
        NUM_DEPTHS = 20
        MAX_DEPTH = NUM_DEPTHS
        ADAPTIVE_FACTOR = 2  # Double the count for target depths
        TARGET_RANGE = 2     # ±2 around the target depth

        base = total_count // NUM_DEPTHS
        remainder = total_count % NUM_DEPTHS

        # Start with uniform allocation.
        depth_counts = {depth: base for depth in range(1, NUM_DEPTHS + 1)}

        # Distribute the remainder.
        for depth in range(1, remainder + 1):
            depth_counts[depth] += 1

        if not self.adaptive:
            return depth_counts

        # ------------------------------------------------------------------
        # Adaptive part – compute target depth from the threshold.
        # ------------------------------------------------------------------
        try:
            threshold_pct = _load_threshold(self.threshold_path)
        except Exception as exc:
            # If we cannot obtain the threshold we fall back to uniform.
            # Raising would break downstream pipelines that expect a file.
            # Logging to stdout is sufficient for debugging.
            print(f"[AdaptiveGenerator] Warning: {exc}. Using uniform distribution.")
            return depth_counts

        # Heuristic mapping: reduction % → depth (linear scaling).
        target_depth = int(round((threshold_pct / 100.0) * MAX_DEPTH))
        target_depth = max(1, min(target_depth, MAX_DEPTH))

        # Apply the adaptive factor to depths in the target window.
        for depth in range(1, NUM_DEPTHS + 1):
            if abs(depth - target_depth) <= TARGET_RANGE:
                depth_counts[depth] = int(depth_counts[depth] * ADAPTIVE_FACTOR)

        # Re‑balance the total count to stay close to ``total_count``.
        # We simply cap the total at ``total_count`` by truncating excess
        # entries in depth order (lowest first).  This keeps the logic
        # deterministic.
        total_generated = sum(depth_counts.values())
        if total_generated > total_count:
            excess = total_generated - total_count
            for depth in range(1, NUM_DEPTHS + 1):
                if excess <= 0:
                    break
                removable = min(depth_counts[depth] - 1, excess)
                if removable > 0:
                    depth_counts[depth] -= removable
                    excess -= removable

        return depth_counts

    def generate_all(self, count: int = 500, output_path: str = "data/raw/workflows.json") -> None:
        """
        Generate workflows using adaptive depth sampling.

        The method mirrors ``SyntheticWorkflowGenerator.generate_all`` but
        uses the depth‑weight map computed by ``_determine_depth_weights``.
        Invalid workflows (≈10 % of the total) are still generated at the
        end of the list, preserving the original behaviour.

        Parameters
        ----------
        count: int, default 500
            Desired total number of *valid* workflows.  The final file
            will contain ``count + count//10`` entries (including the
            invalid ones) as in the original generator.
        output_path: str
            Destination JSON file.
        """
        # ------------------------------------------------------------------
        # Compute per‑depth allocation.
        # ------------------------------------------------------------------
        depth_counts = self._determine_depth_weights(count)

        # ------------------------------------------------------------------
        # Generate valid workflows.
        # ------------------------------------------------------------------
        self.workflows = []
        workflow_id = 0
        random.seed(self.seed)

        for depth, num_for_this_depth in depth_counts.items():
            for _ in range(num_for_this_depth):
                # Choose complexity randomly as in the base generator.
                complexity = random.randint(1, 8)
                workflow = generate_workflow(
                    depth=depth,
                    complexity=complexity,
                    workflow_id=workflow_id,
                    seed=self.seed,
                )
                self.workflows.append(workflow)
                workflow_id += 1

        # ------------------------------------------------------------------
        # Generate invalid workflows (10 % of the *requested* count).
        # ------------------------------------------------------------------
        num_invalid = count // 10
        invalid_start_id = 9000  # Separate ID range for invalid workflows
        for i in range(num_invalid):
            depth = random.randint(1, 20)
            workflow = generate_invalid_workflow(
                depth=depth,
                workflow_id=invalid_start_id + i,
                seed=self.seed,
            )
            self.workflows.append(workflow)

        # ------------------------------------------------------------------
        # Write output.
        # ------------------------------------------------------------------
        output_file = Path(output_path)
        output_file.parent.mkdir(parents=True, exist_ok=True)

        with output_file.open("w", encoding="utf-8") as f:
            json.dump(self.workflows, f, indent=2)

        print(
            f"[AdaptiveGenerator] Generated {len(self.workflows)} workflows "
            f"(including {num_invalid} invalid). Saved to {output_path}"
        )

# ----------------------------------------------------------------------
# CLI entry point – mirrors the original generator CLI.
# ----------------------------------------------------------------------
def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(
        description="Generate synthetic workflows with optional adaptive depth sampling"
    )
    parser.add_argument(
        "--count",
        type=int,
        default=500,
        help="Number of *valid* workflows to generate (invalid workflows are added automatically)",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for reproducibility",
    )
    parser.add_argument(
        "--output",
        type=str,
        required=True,
        help="Output file path for generated workflows (JSON)",
    )
    parser.add_argument(
        "--adaptive",
        action="store_true",
        help="Enable adaptive depth sampling based on the 1 % error‑rate threshold",
    )
    args = parser.parse_args()

    generator = AdaptiveWorkflowGenerator(
        seed=args.seed, adaptive=args.adaptive
    )
    generator.generate_all(count=args.count, output_path=args.output)

if __name__ == "__main__":
    main()
