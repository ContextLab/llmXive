import json
import os
import sys
import csv
from pathlib import Path
from typing import List, Set, Dict, Any

def load_raw_workflows(raw_dir: Path) -> Dict[str, bool]:
    """
    Load all workflow files from data/raw/ and return a mapping of workflow_id -> is_valid.
    Handles both single JSON files and JSONL files.
    """
    workflow_map = {}
    if not raw_dir.exists():
        return workflow_map
    
    for file_path in raw_dir.iterdir():
        if file_path.suffix not in ['.json', '.jsonl']:
            continue
        
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                if file_path.suffix == '.jsonl':
                    for line in f:
                        if line.strip():
                            data = json.loads(line)
                            if 'id' in data:
                                workflow_map[data['id']] = data.get('is_valid', True)
                else:
                    data = json.load(f)
                    if isinstance(data, list):
                        for item in data:
                            if 'id' in item:
                                workflow_map[item['id']] = item.get('is_valid', True)
                    elif isinstance(data, dict) and 'id' in data:
                        workflow_map[data['id']] = data.get('is_valid', True)
        except Exception as e:
            print(f"Warning: Could not read {file_path}: {e}", file=sys.stderr)
    
    return workflow_map

def load_analysis_results(tradeoff_csv: Path, threshold_json: Path) -> Set[str]:
    """
    Load workflow IDs present in the analysis results (tradeoff_curve.csv).
    """
    analysis_ids = set()
    
    if tradeoff_csv.exists():
        with open(tradeoff_csv, 'r', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            for row in reader:
                if 'workflow_id' in row and row['workflow_id']:
                    analysis_ids.add(row['workflow_id'])
                # Some aggregations might not list individual IDs, check for depth/reduction columns
                # If the file is aggregated by reduction_pct, we rely on the presence of the file
                # to indicate that analysis occurred, but we specifically need to check if
                # any INVALID workflow IDs made it into the detailed logs if they were included.
    
    # Also check if threshold_json exists as a marker that analysis ran
    # The primary check is whether any invalid ID appears in the source data used for analysis.
    # Since tradeoff_curve.csv is aggregated, we check the processed logs if available.
    # However, per task description, we check if invalid IDs are EXCLUDED from the FINAL analysis.
    # If tradeoff_curve.csv exists and was generated by T032/T032b which filter invalid workflows,
    # we need to verify that the filtering logic actually worked.
    # We will cross-reference with the processed logs to be thorough.
    
    return analysis_ids

def load_processed_logs(processed_dir: Path) -> Dict[str, bool]:
    """
    Load workflow IDs from processed logs and their validity status.
    Returns mapping of workflow_id -> is_valid (from the log metadata).
    """
    log_map = {}
    if not processed_dir.exists():
        return log_map
    
    for file_path in processed_dir.iterdir():
        if file_path.suffix != '.json':
            continue
        
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
                # Handle single log or list of logs
                logs = data if isinstance(data, list) else [data]
                for log in logs:
                    wid = log.get('workflow_id')
                    if wid:
                        # Check if the log itself marks the workflow as invalid
                        # or if it contains the original metadata
                        is_valid = log.get('is_valid', True)
                        log_map[wid] = is_valid
        except Exception as e:
            print(f"Warning: Could not read {file_path}: {e}", file=sys.stderr)
    
    return log_map

def verify_exclusion(raw_workflows: Dict[str, bool], processed_logs: Dict[str, bool], tradeoff_csv: Path, threshold_json: Path) -> Dict[str, Any]:
    """
    Verify that workflows marked is_valid=false in raw data are NOT present in analysis results.
    """
    invalid_workflow_ids = {wid for wid, valid in raw_workflows.items() if not valid}
    processed_workflow_ids = set(processed_logs.keys())
    
    # Check if any invalid workflow ID appears in processed logs
    # Note: T017/T032 should have filtered these out.
    # We check the processed logs to see if any invalid ones slipped through.
    # The tradeoff_curve.csv is aggregated, so we check the underlying logs.
    
    found_invalid_in_processed = invalid_workflow_ids & processed_workflow_ids
    
    # Check if any invalid workflow ID appears in the tradeoff curve (if individual IDs are listed)
    # Since tradeoff_curve.csv is aggregated, we rely on the processed log check.
    # However, if the CSV has a 'workflow_id' column, we check that too.
    csv_invalid_ids = set()
    if tradeoff_csv.exists():
        with open(tradeoff_csv, 'r', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            for row in reader:
                if 'workflow_id' in row and row['workflow_id']:
                    csv_invalid_ids.add(row['workflow_id'])
    
    found_invalid_in_csv = invalid_workflow_ids & csv_invalid_ids
    
    # Verify threshold_json exists
    threshold_valid = threshold_json.exists() if threshold_json else False
    
    status = "PASS" if (len(found_invalid_in_processed) == 0 and len(found_invalid_in_csv) == 0) else "FAIL"
    
    return {
        "total_invalid_workflows": len(invalid_workflow_ids),
        "invalid_workflows_found_in_processed": list(found_invalid_in_processed),
        "invalid_workflows_found_in_csv": list(found_invalid_in_csv),
        "threshold_json_exists": threshold_valid,
        "status": status,
        "details": {
            "message": "All invalid workflows correctly excluded from analysis." if status == "PASS" else "Invalid workflows found in analysis results!"
        }
    }

def main():
    """
    Main entry point to verify invalid workflow exclusion.
    """
    base_dir = Path(__file__).resolve().parent.parent.parent
    raw_dir = base_dir / "data" / "raw"
    processed_dir = base_dir / "data" / "processed"
    tradeoff_csv = base_dir / "data" / "results" / "tradeoff_curve.csv"
    threshold_json = base_dir / "data" / "results" / "threshold_ci.json"
    output_file = base_dir / "data" / "results" / "invalid_workflow_exclusion_report.json"
    
    print("Loading raw workflows...")
    raw_workflows = load_raw_workflows(raw_dir)
    print(f"Loaded {len(raw_workflows)} raw workflows.")
    
    if not raw_workflows:
        print("Error: No raw workflows found. Ensure data/raw/ contains generated workflow files.")
        sys.exit(1)
    
    print("Loading processed logs...")
    processed_logs = load_processed_logs(processed_dir)
    print(f"Loaded {len(processed_logs)} processed logs.")
    
    print("Verifying exclusion...")
    result = verify_exclusion(raw_workflows, processed_logs, tradeoff_csv, threshold_json)
    
    # Save report
    output_file.parent.mkdir(parents=True, exist_ok=True)
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(result, f, indent=2)
    
    print(f"Report saved to {output_file}")
    print(f"Status: {result['status']}")
    
    if result['status'] == "FAIL":
        print("Invalid workflows found in analysis! Check the report for details.")
        sys.exit(1)
    else:
        print("Verification passed.")
        sys.exit(0)

if __name__ == "__main__":
    main()
