"""
tests/unit/test_pm4py_integration.py
------------------------------------

Unit‑tests for the pm4py integration added in ``services/executor.py``.
The tests verify two essential behaviours:

1. The ``Executor`` creates a pm4py ``EventLog`` with one event per workflow node.
2. The Oracle validation is correctly wired – for a workflow that contains no
   deliberately invalid constraints the executor should report zero policy
   violations.

The test uses the public ``SyntheticWorkflowGenerator`` to build a minimal
deterministic workflow, then runs the executor on that workflow and inspects
the returned dictionary.
"""

import json
import os
from pathlib import Path

import pytest

# Import the objects we need from the project.
from generators.synthetic_workflow import SyntheticWorkflowGenerator
from services.executor import Executor


@pytest.fixture
def simple_workflow(tmp_path: Path) -> dict:
    """
    Generate a deterministic, valid workflow with a small depth.
    The generator writes to ``tmp_path``; we read the JSON back and return
    the first workflow dict.
    """
    output_file = tmp_path / "workflows.json"
    generator = SyntheticWorkflowGenerator(seed=123)
    generator.generate_all(count=1, output_path=str(output_file))
    with open(output_file, "r", encoding="utf-8") as f:
        data = json.load(f)
    # ``generate_all`` always returns a list.
    assert isinstance(data, list) and len(data) == 1
    return data[0]


def test_executor_creates_eventlog(simple_workflow):
    """
    The executor should produce an ``event_log`` entry with the same number of
    events as there are nodes in the original workflow.
    """
    exec_service = Executor()
    result = exec_service.execute(simple_workflow)

    # The result must contain an ``event_log`` key that is a list.
    assert "event_log" in result
    assert isinstance(result["event_log"], list)

    # Number of events should match number of nodes.
    node_count = len(simple_workflow.get("nodes", []))
    assert len(result["event_log"]) == node_count


def test_executor_oracle_validation(simple_workflow):
    """
    For a workflow generated by ``SyntheticWorkflowGenerator`` the
    ``is_valid`` flag is ``True`` and there should be no policy violations.
    """
    exec_service = Executor()
    result = exec_service.execute(simple_workflow)

    # The workflow metadata marks it as valid.
    assert result["is_valid"] is True

    # No violations should be reported.
    assert result["policy_violations"] == []
    assert result["violation_details"] == []


def test_cli_writes_output(tmp_path: Path, simple_workflow):
    """
    End‑to‑end test of the command‑line interface: the script should read a
    workflow file, execute it, and write a JSON file containing the result.
    """
    # Write the workflow to a temporary file.
    workflow_path = tmp_path / "wf.json"
    with open(workflow_path, "w", encoding="utf-8") as f:
        json.dump([simple_workflow], f)

    output_path = tmp_path / "out.json"

    # Invoke the CLI entry point directly (no subprocess needed).
    executor = Executor()
    # Mimic the CLI arguments by calling ``run_cli`` via monkeypatching ``sys.argv``.
    import sys

    original_argv = sys.argv
    try:
        sys.argv = [
            "executor.py",
            "--workflow",
            str(workflow_path),
            "--output",
            str(output_path),
        ]
        executor.run_cli()
    finally:
        sys.argv = original_argv

    # Verify that the output file exists and contains a parsable JSON list.
    assert output_path.exists()
    with open(output_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    assert isinstance(data, list) and len(data) == 1
    assert data[0]["workflow_id"] == simple_workflow["id"]
