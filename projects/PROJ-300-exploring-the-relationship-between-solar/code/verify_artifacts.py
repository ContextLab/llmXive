"""
Verification script for T041b: Check that all expected artifacts exist in the results directory.
This script validates the presence of required output files generated by the pipeline.
"""
import os
import sys
import json
from pathlib import Path

# Project root relative to this script
PROJECT_ROOT = Path(__file__).parent.parent
RESULTS_DIR = PROJECT_ROOT / "results"
DATA_PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"

# Expected artifacts for T041b
EXPECTED_FILES = {
    "results": [
        "us1_correlation.json",
        "plot_scatter.png",
        "plot_timeseries.png",
    ],
    "data/processed": [
        "quality_log.json",
    ]
}

def check_file_exists(file_path: Path) -> bool:
    """Check if a file exists at the given path."""
    return file_path.exists()

def check_json_schema(file_path: Path, required_keys: list) -> bool:
    """Check if a JSON file contains the required keys."""
    try:
        with open(file_path, 'r') as f:
            data = json.load(f)
        return all(key in data for key in required_keys)
    except (json.JSONDecodeError, FileNotFoundError):
        return False

def main():
    """Main verification function for T041b."""
    print("Verifying artifacts for T041b...")
    all_passed = True

    # Check results directory
    print(f"\nChecking {RESULTS_DIR}...")
    for filename in EXPECTED_FILES["results"]:
        file_path = RESULTS_DIR / filename
        if check_file_exists(file_path):
            print(f"  [OK] {filename}")
            # Specific check for JSON schema if applicable
            if filename == "us1_correlation.json":
                required_keys = ["pearson", "spearman", "optimal_lag", "lag_correlation_value"]
                if not check_json_schema(file_path, required_keys):
                    print(f"    [WARN] Missing required keys in {filename}")
                    all_passed = False
        else:
            print(f"  [FAIL] {filename} NOT FOUND")
            all_passed = False

    # Check data/processed directory
    print(f"\nChecking {DATA_PROCESSED_DIR}...")
    for filename in EXPECTED_FILES["data/processed"]:
        file_path = DATA_PROCESSED_DIR / filename
        if check_file_exists(file_path):
            print(f"  [OK] {filename}")
        else:
            print(f"  [FAIL] {filename} NOT FOUND")
            all_passed = False

    if all_passed:
        print("\n✓ All expected artifacts verified successfully.")
        return 0
    else:
        print("\n✗ Some artifacts are missing or invalid.")
        return 1

if __name__ == "__main__":
    sys.exit(main())
