import json
import pytest
from pathlib import Path
import jsonschema
from jsonschema import ValidationError

@pytest.fixture
def schema_path():
    return Path(__file__).parent.parent.parent / 'contracts' / 'output-metrics.schema.yaml'

@pytest.fixture
def output_path():
    return Path(__file__).parent.parent.parent / 'data' / 'processed' / 'diversity_metrics.json'

def load_schema(schema_path):
    """Load YAML schema file."""
    import yaml
    with open(schema_path, 'r') as f:
        return yaml.safe_load(f)

def test_diversity_output_schema(output_path, schema_path):
    """
    Contract test: Verify diversity_metrics.json conforms to output-metrics.schema.yaml
    
    This test ensures that the diversity metrics report generated by code/03_diversity.py
    strictly follows the defined JSON schema.
    """
    # Check if output file exists
    assert output_path.exists(), f"Output file not found: {output_path}"
    
    # Load the output data
    with open(output_path, 'r') as f:
        data = json.load(f)
    
    # Load the schema
    schema = load_schema(schema_path)
    
    # Validate against schema
    try:
        jsonschema.validate(instance=data, schema=schema)
    except ValidationError as e:
        pytest.fail(f"Schema validation failed: {e.message}")
    
    # Additional contract checks
    assert 'alpha_diversity' in data, "Missing 'alpha_diversity' key"
    assert 'beta_diversity_summary' in data, "Missing 'beta_diversity_summary' key"
    assert 'permanova' in data, "Missing 'permanova' key"
    assert 'power_analysis' in data, "Missing 'power_analysis' key"
    assert 'metadata' in data, "Missing 'metadata' key"
    
    # Check alpha diversity structure
    for sample_id, metrics in data['alpha_diversity'].items():
        assert 'shannon' in metrics, f"Missing 'shannon' for sample {sample_id}"
        assert 'simpson' in metrics, f"Missing 'simpson' for sample {sample_id}"
        assert metrics['shannon'] >= 0, f"Invalid Shannon index for {sample_id}"
        assert 0 <= metrics['simpson'] <= 1, f"Invalid Simpson index for {sample_id}"
    
    # Check beta diversity summary
    beta_summary = data['beta_diversity_summary']
    assert beta_summary['distance_type'] in ['braycurtis', 'jaccard', 'unweighted_unifrac', 'weighted_unifrac']
    assert beta_summary['num_samples'] > 0
    assert beta_summary['mean_distance'] >= 0
    
    # Check PERMANOVA results
    perm = data['permanova']
    assert 'pseudo_f' in perm
    assert 'r_squared' in perm
    assert 'p_value' in perm
    assert 0 <= perm['r_squared'] <= 1
    assert 0 <= perm['p_value'] <= 1
    assert len(perm['groups']) >= 2
    
    # Check power analysis
    power = data['power_analysis']
    assert 'power' in power
    assert 'flag' in power
    assert 0 <= power['power'] <= 1
    assert power['flag'] in ['PASS', 'UNDERPOWERED']
    
    # Check metadata
    meta = data['metadata']
    assert 'generated_at' in meta
    assert 'sample_count' in meta
    assert meta['sample_count'] > 0

def test_diversity_output_values(output_path):
    """
    Contract test: Verify diversity metrics contain realistic values
    
    This test checks that the calculated diversity metrics are within
    biologically plausible ranges.
    """
    with open(output_path, 'r') as f:
        data = json.load(f)
    
    # Check alpha diversity ranges
    shannon_values = [m['shannon'] for m in data['alpha_diversity'].values()]
    simpson_values = [m['simpson'] for m in data['alpha_diversity'].values()]
    
    # Shannon index typically ranges from 0 to ~5-6 in microbial communities
    assert all(0 <= v <= 10 for v in shannon_values), "Shannon values outside plausible range"
    
    # Simpson index ranges from 0 to 1
    assert all(0 <= v <= 1 for v in simpson_values), "Simpson values outside plausible range"
    
    # Check PERMANOVA R² is reasonable
    r_squared = data['permanova']['r_squared']
    assert 0 <= r_squared <= 1, f"R² value {r_squared} is outside [0, 1]"
    
    # Check p-value is valid
    p_value = data['permanova']['p_value']
    assert 0 <= p_value <= 1, f"p-value {p_value} is outside [0, 1]"

def test_diversity_output_consistency(output_path):
    """
    Contract test: Verify internal consistency of diversity metrics
    
    This test checks that the number of samples in alpha diversity matches
    the sample count in metadata and beta diversity summary.
    """
    with open(output_path, 'r') as f:
        data = json.load(f)
    
    # Count samples in alpha diversity
    alpha_sample_count = len(data['alpha_diversity'])
    
    # Check consistency with metadata
    metadata_sample_count = data['metadata']['sample_count']
    assert alpha_sample_count == metadata_sample_count, \
        f"Sample count mismatch: alpha={alpha_sample_count}, metadata={metadata_sample_count}"
    
    # Check consistency with beta diversity summary
    beta_sample_count = data['beta_diversity_summary']['num_samples']
    assert alpha_sample_count == beta_sample_count, \
        f"Sample count mismatch: alpha={alpha_sample_count}, beta={beta_sample_count}"
    
    # Check that PERMANOVA groups are consistent with metadata
    perm_groups = data['permanova']['groups']
    assert len(perm_groups) >= 2, "PERMANOVA requires at least 2 groups"