import os
from pathlib import Path

def main():
    """
    Creates the root project directory structure for PROJ-280.
    This script implements task T001a and T001b by creating all required
    directories and the MANIFEST.txt file (T001c).
    """
    # Define the base project root relative to the script location or current working dir
    # The task specifies paths relative to the project root.
    # We assume the script is run from the project root or the root is the current directory.
    root = Path(".")

    # T001a: Root directories
    root_dirs = [
        "projects/PROJ-280-investigating-microbial-community-succes",
        "data",
        "code",
        "tests",
        "state",
        "contracts",
    ]

    # T001b: Subdirectories
    sub_dirs = [
        "data/raw",
        "data/processed",
        "data/config",
        "tests/unit",
        "tests/contract",
        "tests/integration",
        "state/projects",
    ]

    all_dirs = root_dirs + sub_dirs

    created_dirs = []
    for dir_path in all_dirs:
        full_path = root / dir_path
        full_path.mkdir(parents=True, exist_ok=True)
        created_dirs.append(str(full_path))
        print(f"Created directory: {full_path}")

    # T001c: Create MANIFEST.txt in the specific project folder
    project_root = root / "projects/PROJ-280-investigating-microbial-community-succes"
    manifest_path = project_root / "MANIFEST.txt"

    manifest_content = [
        "# MANIFEST.txt - Project Structure Verification",
        "# Generated by code/setup_project.py for Task T001a, T001b, T001c",
        "# This file lists all expected directories and files created during setup.",
        "",
        "## Root Directories (T001a)",
        "projects/PROJ-280-investigating-microbial-community-succes/",
        "data/",
        "code/",
        "tests/",
        "state/",
        "contracts/",
        "",
        "## Subdirectories (T001b)",
        "data/raw",
        "data/processed",
        "data/config",
        "tests/unit",
        "tests/contract",
        "tests/integration",
        "state/projects",
        "",
        "## Verification",
        "Run `python code/setup_project.py` to recreate this structure if missing.",
        "Verify existence with: ls -R projects/PROJ-280-investigating-microbial-community-succes/",
    ]

    with open(manifest_path, "w", encoding="utf-8") as f:
        f.write("\n".join(manifest_content))
    
    print(f"Created manifest: {manifest_path}")
    print("Project structure initialization complete.")

if __name__ == "__main__":
    main()