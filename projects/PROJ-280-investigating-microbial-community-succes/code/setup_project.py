import os
import sys
from pathlib import Path

def main():
    """
    T001: Initialize project structure and verify directories.
    Creates required directories and generates MANIFEST.txt.
    """
    base_path = Path(__file__).resolve().parent.parent
    project_root = base_path / "PROJ-280-investigating-microbial-community-succes"
    
    # Ensure we are operating in the correct project directory context
    # The task description implies absolute paths relative to the project root
    # We will construct paths relative to the project root found in the repo structure
    
    # Define the directories to create relative to the project root
    # Based on T001 description:
    # `data/`, `data/config/`, `data/raw/`, `data/processed/`, 
    # `code/`, `tests/`, `tests/unit/`, `tests/contract/`, `tests/integration/`, 
    # `state/`, `state/projects/`, `contracts/`
    
    dirs_to_create = [
        "data",
        "data/config",
        "data/raw",
        "data/processed",
        "code",
        "tests",
        "tests/unit",
        "tests/contract",
        "tests/integration",
        "state",
        "state/projects",
        "contracts"
    ]
    
    created_dirs = []
    errors = []
    
    print(f"Initializing project structure at: {project_root}")
    
    if not project_root.exists():
        print(f"ERROR: Project root {project_root} does not exist. Aborting.")
        sys.exit(1)
    
    for dir_name in dirs_to_create:
        full_path = project_root / dir_name
        try:
            full_path.mkdir(parents=True, exist_ok=True)
            # Verify writability
            test_file = full_path / ".write_test"
            test_file.touch()
            test_file.unlink()
            created_dirs.append(str(full_path.relative_to(project_root)))
            print(f"Created/Verified: {full_path}")
        except Exception as e:
            error_msg = f"Failed to create or verify {full_path}: {e}"
            errors.append(error_msg)
            print(f"ERROR: {error_msg}")
    
    if errors:
        print("\nCRITICAL: Directory initialization failed.")
        for err in errors:
            print(f"  - {err}")
        sys.exit(1)
    
    # Generate MANIFEST.txt
    manifest_path = project_root / "MANIFEST.txt"
    try:
        with open(manifest_path, 'w') as f:
            f.write("# Project Structure Manifest\n")
            f.write(f"# Generated by T001: Initialize project structure\n")
            f.write(f"# Date: {Path(__file__).parent.name}\n\n")
            f.write("Directories:\n")
            for d in sorted(created_dirs):
                f.write(f"  {d}/\n")
            f.write("\nExpected Files (to be generated by subsequent tasks):\n")
            f.write("  data/config/dataset_ids.json\n")
            f.write("  data/processed/metadata_with_rates.csv\n")
            f.write("  data/processed/filtered_feature_table.csv\n")
            f.write("  data/processed/power_analysis_report.json\n")
            f.write("  data/processed/sample_size_validation.json\n")
            f.write("  state/projects/PROJ-280-investigating-microbial-community-succes.yaml\n")
            f.write("  contracts/dataset-config.schema.yaml\n")
            f.write("  contracts/feature-table.schema.yaml\n")
            f.write("  code/requirements.txt\n")
        print(f"Generated manifest: {manifest_path}")
    except Exception as e:
        print(f"ERROR: Failed to write MANIFEST.txt: {e}")
        sys.exit(1)
    
    print("\nProject structure initialization complete.")
    return 0

if __name__ == "__main__":
    sys.exit(main())
