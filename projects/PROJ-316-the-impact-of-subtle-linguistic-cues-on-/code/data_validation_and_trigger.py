"""
T001g: Validate Data & Trigger Manual Annotation Protocol

This script checks `data/raw/conversations.jsonl` for the presence of
`authenticity_score`. If missing, it triggers the manual annotation protocol
by creating a flag file and a log report.
"""

import json
import os
import sys
from pathlib import Path
from datetime import datetime

# Project paths
PROJECT_ROOT = Path(__file__).resolve().parent.parent
RAW_DATA_PATH = PROJECT_ROOT / "data" / "raw" / "conversations.jsonl"
FLAG_FILE_PATH = PROJECT_ROOT / "data" / "processed" / "annotation_required.flag"
LOG_FILE_PATH = PROJECT_ROOT / "data" / "processed" / "annotation_trigger_log.md"
INSTRUCTIONS_PATH = PROJECT_ROOT / "data" / "raw" / "annotation_instructions.md"

def check_file_exists(path: Path) -> bool:
    if not path.exists():
        print(f"ERROR: Required file not found: {path}")
        return False
    return True

def load_and_check_authenticity_score(jsonl_path: Path) -> tuple[bool, int]:
    """
    Loads the JSONL file and checks if any record contains 'authenticity_score'.
    Returns (has_score, total_records_processed).
    """
    has_score = False
    count = 0
    try:
        with open(jsonl_path, 'r', encoding='utf-8') as f:
            for line in f:
                count += 1
                try:
                    record = json.loads(line)
                    if 'authenticity_score' in record and record['authenticity_score'] is not None:
                        has_score = True
                        break
                except json.JSONDecodeError:
                    continue
    except Exception as e:
        print(f"ERROR reading {jsonl_path}: {e}")
        sys.exit(1)

    return has_score, count

def create_flag_file(flag_path: Path) -> None:
    """Creates the flag file to signal downstream tasks."""
    flag_path.parent.mkdir(parents=True, exist_ok=True)
    with open(flag_path, 'w', encoding='utf-8') as f:
        f.write(f"TRIGGERED: {datetime.now().isoformat()}\n")
        f.write("REASON: authenticity_score missing from raw data.\n")
        f.write("ACTION: Proceed with T001b -> T001i -> T001j -> T001k protocol.\n")
    print(f"Flag file created: {flag_path}")

def write_trigger_log(log_path: Path, instructions_path: Path, total_records: int) -> None:
    """Writes the markdown log confirming protocol initiation."""
    log_path.parent.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    content = f"""# Annotation Protocol Trigger Log

**Timestamp**: {timestamp}
**Task ID**: T001g
**Status**: PROTOCOL INITIATED

## Input Validation Results
- **Source File**: {raw_data_path}
- **Total Records Scanned**: {total_records}
- **Authenticity Score Found**: No

## Decision Logic
The raw dataset (`conversations.jsonl`) does not contain the `authenticity_score` field.
Per the task specification (T001g), this triggers the manual annotation protocol.

## Protocol Execution Plan
The following sequence of tasks is now required to generate the Analysis Set:
1. **T001b**: Verify Annotation Instructions (`{instructions_path.name}`) are available.
2. **T001i**: Generate "Gold Standard" subset of 50 annotated turns for Lexicon Validation.
3. **T001j**: Generate Human Hedge Labels (Gold Standard) for the 50 validation turns.
4. **T001k**: Generate "Analysis Set" of N annotated turns for Regression (where N is from T000b).

## Next Steps
- Downstream tasks (T001d, T001e, T009, T012, etc.) must wait for the completion of T001k.
- The flag file `{FLAG_FILE_PATH.name}` has been created to signal this state to the pipeline.

---
*Generated by T001g Data Validation Script*
"""
    with open(log_path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"Trigger log created: {log_path}")

def main():
    print("Starting T001g: Data Validation & Annotation Trigger")
    
    # 1. Verify input file exists
    if not check_file_exists(RAW_DATA_PATH):
        print("FATAL: Raw data file missing. Cannot validate.")
        sys.exit(1)

    # 2. Verify instructions exist (prerequisite T001b)
    if not check_file_exists(INSTRUCTIONS_PATH):
        print("WARNING: Annotation instructions not found. Protocol cannot proceed cleanly.")
        # We still trigger the flag, but warn the user
    
    # 3. Check for authenticity_score
    has_score, total_records = load_and_check_authenticity_score(RAW_DATA_PATH)

    if has_score:
        print("SUCCESS: 'authenticity_score' found in dataset.")
        print("Action: No manual annotation protocol required. Proceed to T001k/T001j directly.")
        # If the flag exists from a previous run, we might want to remove it, 
        # but for now we just log success.
        if FLAG_FILE_PATH.exists():
            FLAG_FILE_PATH.unlink()
            print(f"Removed existing flag file: {FLAG_FILE_PATH}")
    else:
        print("RESULT: 'authenticity_score' is MISSING.")
        print("Action: Triggering Manual Annotation Protocol (T001b -> T001i -> T001j -> T001k).")
        
        # Create flag
        create_flag_file(FLAG_FILE_PATH)
        
        # Write log
        write_trigger_log(LOG_FILE_PATH, INSTRUCTIONS_PATH, total_records)
        
        print("Protocol trigger complete.")

if __name__ == "__main__":
    main()