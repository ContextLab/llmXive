"""
Module: code/analysis/log_hypothesis_rejections.py

Implements logging for null hypothesis rejection flags (p < 0.01)
as required by Task T027 in User Story 2.

This module scans statistical results files (generated by T023a/T023b/T025)
and logs all instances where the null hypothesis is rejected at the 0.01 significance level.
"""

import os
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional
import pandas as pd

from utils.config import get_project_root, get_data_processed_path, get_output_path

# Configure logging
logger = logging.getLogger(__name__)

# Threshold for null hypothesis rejection
REJECTION_THRESHOLD = 0.01


def log_hypothesis_rejection(
    test_name: str,
    predictor: str,
    p_value: float,
    result_row: Dict[str, Any],
    log_path: Optional[Path] = None
) -> None:
    """
    Log a single hypothesis rejection event.
    
    Args:
        test_name: Name of the statistical test (e.g., 'kruskal_wallis', 'linear_regression')
        predictor: The predictor variable being tested
        p_value: The p-value from the test
        result_row: Full row of result data for context
        log_path: Optional custom path for the log file. Defaults to project's rejection log.
    """
    if p_value < REJECTION_THRESHOLD:
        log_entry = {
            "test_name": test_name,
            "predictor": predictor,
            "p_value": p_value,
            "rejection_threshold": REJECTION_THRESHOLD,
            "status": "REJECTED",
            "full_result": result_row
        }
        
        if log_path is None:
            log_path = get_output_path() / "rejection_log.csv"
        
        # Ensure directory exists
        log_path.parent.mkdir(parents=True, exist_ok=True)
        
        # Append to log file
        log_df = pd.DataFrame([log_entry])
        file_exists = log_path.exists()
        log_df.to_csv(
            log_path,
            mode='a',
            header=not file_exists,
            index=False
        )
        
        logger.info(
            f"Null hypothesis REJECTED: {test_name} for '{predictor}' "
            f"(p={p_value:.6f} < {REJECTION_THRESHOLD})"
        )
    else:
        logger.debug(
            f"Null hypothesis NOT rejected: {test_name} for '{predictor}' "
            f"(p={p_value:.6f} >= {REJECTION_THRESHOLD})"
        )


def log_all_rejections_from_results(
    results_file: Optional[Path] = None,
    test_name: str = "statistical_analysis",
    p_value_column: str = "p_value",
    predictor_column: str = "predictor",
    log_path: Optional[Path] = None
) -> List[Dict[str, Any]]:
    """
    Scan a statistical results file and log all null hypothesis rejections.
    
    Args:
        results_file: Path to the results CSV file. Defaults to statistical_results.csv.
        test_name: Name to associate with all tests in this file.
        p_value_column: Column name containing p-values.
        predictor_column: Column name containing predictor variable names.
        log_path: Optional custom path for the log file.
        
    Returns:
        List of dictionaries containing all rejection entries.
    """
    if results_file is None:
        results_file = get_data_processed_path() / "statistical_results.csv"
    
    if not results_file.exists():
        logger.warning(f"Results file not found: {results_file}")
        return []
    
    if log_path is None:
        log_path = get_output_path() / "rejection_log.csv"
    
    # Load results
    try:
        df = pd.read_csv(results_file)
    except Exception as e:
        logger.error(f"Failed to read results file {results_file}: {e}")
        return []
    
    # Validate required columns
    if p_value_column not in df.columns:
        logger.error(f"Column '{p_value_column}' not found in {results_file}")
        return []
    
    if predictor_column not in df.columns:
        logger.warning(f"Column '{predictor_column}' not found in {results_file}. Using index.")
        df[predictor_column] = df.index.astype(str)
    
    # Collect rejections
    rejections = []
    for idx, row in df.iterrows():
        p_val = row[p_value_column]
        
        # Handle NaN or invalid p-values
        if pd.isna(p_val):
            continue
        
        try:
            p_val = float(p_val)
        except (ValueError, TypeError):
            continue
        
        # Log rejection if significant
        if p_val < REJECTION_THRESHOLD:
            result_entry = {
                "test_name": test_name,
                "predictor": str(row[predictor_column]),
                "p_value": p_val,
                "rejection_threshold": REJECTION_THRESHOLD,
                "status": "REJECTED",
                "full_result": row.to_dict()
            }
            rejections.append(result_entry)
            
            # Write to log file
            log_df = pd.DataFrame([result_entry])
            file_exists = log_path.exists()
            log_df.to_csv(
                log_path,
                mode='a',
                header=not file_exists,
                index=False
            )
            
            logger.info(
                f"Null hypothesis REJECTED: {test_name} for '{row[predictor_column]}' "
                f"(p={p_val:.6f} < {REJECTION_THRESHOLD})"
            )
    
    logger.info(f"Completed scanning {results_file}. Found {len(rejections)} rejections.")
    return rejections


def main() -> None:
    """
    Main entry point for T027: Log null hypothesis rejections from statistical results.
    
    This function:
    1. Loads the statistical results from data/processed/statistical_results.csv
    2. Identifies all rows where p_value < 0.01
    3. Logs these rejections to outputs/rejection_log.csv
    4. Prints a summary to the console
    """
    # Setup logging
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )
    
    logger.info("Starting T027: Log Hypothesis Rejections")
    
    # Define paths
    results_file = get_data_processed_path() / "statistical_results.csv"
    log_path = get_output_path() / "rejection_log.csv"
    
    # Ensure output directory exists
    log_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Process results
    rejections = log_all_rejections_from_results(
        results_file=results_file,
        test_name="user_story_2_analysis",
        p_value_column="p_value",
        predictor_column="predictor",
        log_path=log_path
    )
    
    # Print summary
    print(f"\n{'='*60}")
    print(f"T027 SUMMARY: Null Hypothesis Rejections (p < {REJECTION_THRESHOLD})")
    print(f"{'='*60}")
    print(f"Results file: {results_file}")
    print(f"Rejection log: {log_path}")
    print(f"Total rejections found: {len(rejections)}")
    
    if rejections:
        print("\nRejected hypotheses:")
        for i, rej in enumerate(rejections, 1):
            print(f"  {i}. {rej['test_name']} - {rej['predictor']}: p={rej['p_value']:.6f}")
    else:
        print("\nNo null hypotheses rejected at the 0.01 significance level.")
    
    print(f"{'='*60}\n")
    
    logger.info("T027 completed successfully")


if __name__ == "__main__":
    main()
