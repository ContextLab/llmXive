"""
T032: Generate sensitivity report comparing significance rates and p-value variance across thresholds.

This script reads the sensitivity analysis results generated by T030 (code/analysis/sensitivity.py),
aggregates the statistics, calculates the p-value variance across the swept thresholds,
and outputs a final report to data/processed/sensitivity_report.csv.

It verifies the SC-003 requirement: p-value variance <= 0.001.
"""
import os
import sys
import logging
import csv
from pathlib import Path
from typing import List, Dict, Any, Optional
import numpy as np

# Import project utilities
from utils.config import get_project_root, get_data_processed_path
from utils.logging import get_pipeline_logger, log_error, log_metric

# Ensure we can import from code/
PROJECT_ROOT = get_project_root()
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from analysis.sensitivity import run_sensitivity_analysis, load_statistical_results
from analysis.metadata_utils import load_metadata, save_metadata, add_associational_only_flag_to_csv

# Constants
SENSITIVITY_INPUT_FILE = "data/processed/sensitivity_analysis_results.csv"
SENSITIVITY_OUTPUT_FILE = "data/processed/sensitivity_report.csv"
THRESHOLD_VARIANCE_THRESHOLD = 0.001  # SC-003 requirement

def calculate_significance_rates(results: List[Dict[str, Any]]) -> Dict[str, float]:
    """
    Calculate the percentage of tests that rejected the null hypothesis (p < 0.01)
    for each threshold configuration.
    """
    if not results:
        return {}

    total_tests = len(results)
    rejections = sum(1 for r in results if float(r.get('p_value', 1.0)) < 0.01)
    
    rate = (rejections / total_tests) if total_tests > 0 else 0.0
    return {
        "total_tests": total_tests,
        "rejections": rejections,
        "significance_rate": rate
    }

def calculate_p_value_variance(results: List[Dict[str, Any]], metric: str = 'p_value') -> float:
    """
    Calculate the variance of p-values across all threshold configurations.
    """
    if not results:
        return 0.0
    
    p_values = []
    for r in results:
        try:
            val = float(r.get(metric, 0.0))
            p_values.append(val)
        except (ValueError, TypeError):
            continue
    
    if len(p_values) < 2:
        return 0.0
    
    return float(np.var(p_values))

def generate_report(
    sensitivity_results_path: Path,
    output_path: Path,
    metadata_path: Path
) -> None:
    """
    Generate the final sensitivity report CSV and update metadata.
    """
    logger = get_pipeline_logger("sensitivity_report")
    logger.info(f"Generating sensitivity report from {sensitivity_results_path}")

    if not sensitivity_results_path.exists():
        logger.error(f"Sensitivity analysis results not found at {sensitivity_results_path}. "
                     "Did you run code/analysis/sensitivity.py first?")
        # If the file doesn't exist, we cannot generate the report.
        # However, per T029/T030 logic, if the analysis failed due to missing data,
        # we might still need to create a report indicating that.
        # For this task, we assume T030 produced the file.
        raise FileNotFoundError(f"Required input file not found: {sensitivity_results_path}")

    # Load the raw sensitivity results
    results = []
    with open(sensitivity_results_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            results.append(row)

    if not results:
        logger.warning("Sensitivity analysis results file is empty.")
        # Create an empty report with headers
        with open(output_path, 'w', newline='', encoding='utf-8') as f:
            writer = csv.writer(f)
            writer.writerow(['metric', 'value', 'status', 'notes'])
            writer.writerow(['total_tests', 0, 'N/A', 'No results found'])
            writer.writerow(['significance_rate', 0.0, 'N/A', 'No results found'])
            writer.writerow(['p_value_variance', 0.0, 'FAILED_SC-003', 'No results found'])
            writer.writerow(['sc_003_status', 'FAILED_SC-003', 'N/A', 'No data to evaluate'])
        return

    # Calculate metrics
    sig_metrics = calculate_significance_rates(results)
    p_variance = calculate_p_value_variance(results)

    # Determine SC-003 status
    sc_003_status = "PASSED" if p_variance <= THRESHOLD_VARIANCE_THRESHOLD else "FAILED_SC-003"
    sc_003_notes = f"Variance {p_variance:.6f} {'<=' if p_variance <= THRESHOLD_VARIANCE_THRESHOLD else '>'} {THRESHOLD_VARIANCE_THRESHOLD}"

    # Prepare report rows
    report_rows = [
        {
            'metric': 'total_tests',
            'value': sig_metrics.get('total_tests', 0),
            'status': 'N/A',
            'notes': 'Total number of statistical tests performed across all thresholds'
        },
        {
            'metric': 'significance_rate',
            'value': sig_metrics.get('significance_rate', 0.0),
            'status': 'N/A',
            'notes': 'Proportion of tests rejecting null hypothesis (p < 0.01)'
        },
        {
            'metric': 'p_value_variance',
            'value': p_variance,
            'status': 'N/A',
            'notes': 'Variance of p-values across threshold configurations'
        },
        {
            'metric': 'sc_003_status',
            'value': sc_003_status,
            'status': sc_003_status,
            'notes': sc_003_notes
        }
    ]

    # Write report CSV
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=['metric', 'value', 'status', 'notes'])
        writer.writeheader()
        writer.writerows(report_rows)

    logger.info(f"Sensitivity report written to {output_path}")
    logger.info(f"SC-003 Status: {sc_003_status} (Variance: {p_variance:.6f})")

    # Update metadata
    if metadata_path.exists():
        metadata = load_metadata(metadata_path)
        metadata['sensitivity_analysis'] = {
            'sc_003_status': sc_003_status,
            'p_value_variance': p_variance,
            'threshold_variance_limit': THRESHOLD_VARIANCE_THRESHOLD,
            'significance_rate': sig_metrics.get('significance_rate', 0.0),
            'total_tests': sig_metrics.get('total_tests', 0)
        }
        save_metadata(metadata_path, metadata)
        logger.info("Metadata updated with sensitivity analysis results.")

    # Apply associational_only flag
    add_associational_only_flag_to_csv(output_path, metadata_path)
    logger.info("Applied 'associational_only=true' flag to report.")

def main():
    """Main entry point for T032."""
    root = get_project_root()
    processed_dir = get_data_processed_path()
    metadata_path = root / "data" / "metadata.yaml"

    input_path = processed_dir / SENSITIVITY_INPUT_FILE
    output_path = processed_dir / SENSITIVITY_OUTPUT_FILE

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    logger = get_pipeline_logger("sensitivity_report")
    log_metric("task_id", "T032")
    log_metric("input_file", str(input_path))
    log_metric("output_file", str(output_path))

    try:
        generate_report(input_path, output_path, metadata_path)
        log_metric("status", "completed")
        logger.info("T032 Sensitivity Report Generation: SUCCESS")
    except FileNotFoundError as e:
        log_error(str(e))
        logger.error("T032 Sensitivity Report Generation: FAILED - Input file missing")
        sys.exit(1)
    except Exception as e:
        log_error(str(e))
        logger.error(f"T032 Sensitivity Report Generation: FAILED - {str(e)}")
        sys.exit(1)

if __name__ == "__main__":
    main()