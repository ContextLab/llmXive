def test_reward_computation_contract():
    """
    Contract Test: Verify ImplicitRewardComputer produces valid outputs.
    
    Ensures that the reward computation module:
    - Accepts teacher and student logits.
    - Returns a tensor of the correct shape (batch, seq).
    - Handles epsilon smoothing correctly.
    """
    batch_size = 2
    seq_len = 10
    vocab_size = 100
    epsilon = 1e-6

    teacher_logits = torch.randn(batch_size, seq_len, vocab_size)
    student_logits = torch.randn(batch_size, seq_len, vocab_size)

    # Test with explicit epsilon
    rewards = compute_implicit_reward(
        teacher_logits, 
        student_logits, 
        epsilon=epsilon
    )

    assert rewards is not None, "Reward computation returned None"
    assert isinstance(rewards, torch.Tensor), "Rewards must be a torch.Tensor"
    assert rewards.shape == (batch_size, seq_len), \
        f"Expected shape ({batch_size}, {seq_len}), got {rewards.shape}"
    
    # Check for NaNs or Infs which indicate numerical instability
    assert not torch.isnan(rewards).any(), "Rewards contain NaN values"
    assert not torch.isinf(rewards).any(), "Rewards contain Inf values"

    # Test with default epsilon (should not raise)
    rewards_default = compute_implicit_reward(teacher_logits, student_logits)
    assert rewards_default.shape == rewards.shape

