def test_numerical_stability_edge_cases():
    """
    Contract Test: Verify robustness against edge cases (zero probabilities).
    """
    batch_size = 1
    seq_len = 3
    vocab_size = 10
    
    # Create logits that might result in very small probabilities
    teacher_logits = torch.full((batch_size, seq_len, vocab_size), -100.0)
    student_logits = torch.full((batch_size, seq_len, vocab_size), -100.0)
    
    # Add a tiny positive value to one logit to prevent total zero
    teacher_logits[0, 0, 0] = -1.0
    student_logits[0, 0, 0] = -2.0
    
    # This should not raise an exception due to division by zero or log(0)
    rewards = compute_implicit_reward(teacher_logits, student_logits, epsilon=1e-8)
    
    assert rewards.shape == (batch_size, seq_len)
    assert not torch.isnan(rewards).any()

