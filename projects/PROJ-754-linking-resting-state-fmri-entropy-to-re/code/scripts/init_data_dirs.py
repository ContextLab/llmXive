import os
import sys
from pathlib import Path
import hashlib
import argparse
from typing import List, Tuple, Optional

def get_project_root() -> Path:
    """Determine the project root directory."""
    # Assume the script is in code/scripts/, so root is two levels up
    current = Path(__file__).resolve()
    return current.parent.parent.parent

def ensure_directory(path: Path) -> None:
    """Create a directory if it doesn't exist."""
    path.mkdir(parents=True, exist_ok=True)

def compute_sha256(file_path: Path) -> str:
    """Compute SHA-256 checksum of a file."""
    sha256_hash = hashlib.sha256()
    with open(file_path, "rb") as f:
        # Read in chunks to handle large files
        for byte_block in iter(lambda: f.read(4096), b""):
            sha256_hash.update(byte_block)
    return sha256_hash.hexdigest()

def append_checksum(checksum_file: Path, relative_path: str, checksum: str) -> None:
    """Append a checksum entry to the checksums.txt file."""
    with open(checksum_file, "a") as f:
        f.write(f"{checksum}  {relative_path}\n")

def scan_and_log_checksums(data_root: Path, checksum_file: Path) -> List[Tuple[str, str]]:
    """
    Scan the data directory for files and log their checksums.
    Returns a list of (relative_path, checksum) tuples.
    """
    logged = []
    if not checksum_file.exists():
        # Initialize file with header if it doesn't exist
        with open(checksum_file, "w") as f:
            f.write("# SHA-256 checksums for data artifacts\n")
            f.write("# Format: <checksum>  <relative_path>\n")
            f.write(f"# Generated by init_data_dirs.py at {Path.cwd()}\n")

    # Walk through all files in the data directory
    for file_path in data_root.rglob("*"):
        if file_path.is_file():
            # Skip the checksums file itself
            if file_path.name == "checksums.txt":
                continue

            try:
                checksum = compute_sha256(file_path)
                relative_path = str(file_path.relative_to(data_root))
                append_checksum(checksum_file, relative_path, checksum)
                logged.append((relative_path, checksum))
            except Exception as e:
                print(f"Warning: Could not compute checksum for {file_path}: {e}", file=sys.stderr)

    return logged

def main():
    parser = argparse.ArgumentParser(description="Initialize data directory structure and log checksums.")
    parser.add_argument(
        "--scan",
        action="store_true",
        help="Scan existing data directory and log checksums for all files."
    )
    args = parser.parse_args()

    project_root = get_project_root()
    data_dir = project_root / "data"
    checksum_file = data_dir / "checksums.txt"

    # Ensure main data directories exist
    directories = [
        "raw",
        "raw/hcp",
        "cleaned",
        "derived",
        "results",
        "figures"
    ]

    for dir_name in directories:
        ensure_directory(data_dir / dir_name)
        print(f"Created/Verified directory: {data_dir / dir_name}")

    if args.scan:
        if not data_dir.exists():
            print(f"Error: Data directory {data_dir} does not exist.", file=sys.stderr)
            sys.exit(1)

        print(f"Scanning data directory: {data_dir}")
        logged = scan_and_log_checksums(data_dir, checksum_file)
        if logged:
            print(f"Logged checksums for {len(logged)} file(s):")
            for rel_path, checksum in logged:
                print(f"  {rel_path}: {checksum[:16]}...")
        else:
            print("No files found to checksum (excluding checksums.txt).")
    else:
        print("Data directory structure initialized. Use --scan to log checksums for existing files.")

if __name__ == "__main__":
    main()
