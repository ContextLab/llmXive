"""
Validate Pilot Study: Label "Constraint Mention" for N=10 traces.

This script loads the pilot traces generated by `pilot_study.py` and applies
a rule-based oracle to label whether a constraint was explicitly mentioned.

The oracle logic checks for the presence of the original task's `constraint`
string (case-insensitive) within the generated CoT trace.

Output:
    data/validation/pilot_labels.jsonl
"""
import json
import sys
import argparse
from pathlib import Path
from typing import List, Dict, Any, Optional
from datetime import datetime, timezone

# Add parent directory to path for imports if running as script
if __name__ == "__main__" and __package__ is None:
    sys.path.insert(0, str(Path(__file__).parent))

from utils.logging_config import get_logger

logger = get_logger(__name__)

def load_pilot_traces(input_path: Path) -> List[Dict[str, Any]]:
    """Load pilot traces from a JSONL file."""
    if not input_path.exists():
        raise FileNotFoundError(f"Pilot traces file not found: {input_path}")
    
    traces = []
    with open(input_path, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                trace = json.loads(line)
                traces.append(trace)
            except json.JSONDecodeError as e:
                logger.error(f"Failed to parse JSON at line {line_num}: {e}")
                raise
    
    if not traces:
        raise ValueError("Pilot traces file is empty.")
    
    logger.info(f"Loaded {len(traces)} pilot traces from {input_path}")
    return traces

def label_constraint_mention(trace: Dict[str, Any]) -> Dict[str, Any]:
    """
    Apply a rule-based oracle to label "Constraint Mention".
    
    Logic:
    1. Extract the 'constraint' field from the original task data within the trace.
    2. Extract the 'cot_trace' text.
    3. Perform a case-insensitive substring search.
    4. If found, label = "Yes", else "No".
    
    Returns a dictionary with the trace ID, label, and the method used.
    """
    task_data = trace.get("task_data", {})
    constraint = task_data.get("constraint")
    cot_trace = trace.get("cot_trace", "")
    
    if not constraint:
        logger.warning(f"Trace {trace.get('task_id', 'UNKNOWN')} missing 'constraint' field in task_data.")
        return {
            "task_id": trace.get("task_id", "UNKNOWN"),
            "constraint_mention": "Unknown",
            "reason": "Missing constraint field in source task",
            "oracle_method": "rule_based_substring"
        }
    
    if not cot_trace:
        logger.warning(f"Trace {trace.get('task_id', 'UNKNOWN')} has empty CoT trace.")
        return {
            "task_id": trace.get("task_id", "UNKNOWN"),
            "constraint_mention": "No",
            "reason": "Empty CoT trace",
            "oracle_method": "rule_based_substring"
        }

    # Case-insensitive check
    constraint_lower = constraint.lower()
    trace_lower = cot_trace.lower()
    
    is_mentioned = constraint_lower in trace_lower
    
    label = "Yes" if is_mentioned else "No"
    reason = "Constraint string found in trace" if is_mentioned else "Constraint string not found in trace"
    
    return {
        "task_id": trace.get("task_id", "UNKNOWN"),
        "constraint_mention": label,
        "reason": reason,
        "oracle_method": "rule_based_substring",
        "timestamp": datetime.now(timezone.utc).isoformat()
    }

def write_labels(labels: List[Dict[str, Any]], output_path: Path) -> None:
    """Write labeled results to a JSONL file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        for label_record in labels:
            f.write(json.dumps(label_record) + "\n")
    
    logger.info(f"Written {len(labels)} labels to {output_path}")

def main():
    parser = argparse.ArgumentParser(description="Validate pilot traces with rule-based oracle.")
    parser.add_argument(
        "--input", 
        type=str, 
        default="data/traces/pilot_traces.jsonl",
        help="Path to the pilot traces JSONL file."
    )
    parser.add_argument(
        "--output", 
        type=str, 
        default="data/validation/pilot_labels.jsonl",
        help="Path to write the labeled results."
    )
    parser.add_argument(
        "--limit", 
        type=int, 
        default=10,
        help="Maximum number of traces to process (N=10)."
    )
    
    args = parser.parse_args()
    
    input_path = Path(args.input)
    output_path = Path(args.output)
    
    try:
        traces = load_pilot_traces(input_path)
        
        # Enforce N=10 limit as per task description
        if len(traces) > args.limit:
            logger.info(f"Limiting processing to first {args.limit} traces (N={args.limit}).")
            traces = traces[:args.limit]
        elif len(traces) == 0:
            raise ValueError("No traces found to process.")
        
        logger.info(f"Processing {len(traces)} traces for constraint mention labeling.")
        
        labels = []
        for i, trace in enumerate(traces):
            label_record = label_constraint_mention(trace)
            labels.append(label_record)
            logger.debug(f"Processed trace {i+1}/{len(traces)}: {label_record['task_id']} -> {label_record['constraint_mention']}")
        
        write_labels(labels, output_path)
        
        # Summary
        yes_count = sum(1 for l in labels if l['constraint_mention'] == 'Yes')
        no_count = sum(1 for l in labels if l['constraint_mention'] == 'No')
        unknown_count = sum(1 for l in labels if l['constraint_mention'] == 'Unknown')
        
        logger.info(f"Validation Summary: Yes={yes_count}, No={no_count}, Unknown={unknown_count}")
        
    except FileNotFoundError as e:
        logger.error(f"File error: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Data error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()