"""
Generate a request file for human experts to label the N=10 pilot traces.

This script reads the pilot traces generated by `code/pilot_study.py` and formats
them into a structured JSONL request file for human annotation.

The request file asks experts to label:
1. "Constraint Mention": Does the trace explicitly mention the task constraint? (Yes/No)
2. "Task Outcome": Is the final answer in the trace correct? (Correct/Incorrect)

Output: data/pilot/annotation_request.jsonl
"""

import json
import sys
import logging
from pathlib import Path
from datetime import datetime, timezone
from typing import List, Dict, Any

# Import logging utilities from the project's utils
from utils.logging_config import get_logger

# Constants
PILOT_TRACES_PATH = Path("data/pilot/pilot_traces.jsonl")
ANNOTATION_REQUEST_PATH = Path("data/pilot/annotation_request.jsonl")
MAX_PILOT_SIZE = 10

def setup_logging() -> logging.Logger:
    """Configure logging for the annotation request generator."""
    logger = get_logger("generate_pilot_annotation_request")
    logger.setLevel(logging.INFO)
    if not logger.handlers:
        handler = logging.StreamHandler(sys.stdout)
        handler.setLevel(logging.INFO)
        formatter = logging.Formatter(
            "%(asctime)s - %(name)s - %(levelname)s - %(message)s"
        )
        handler.setFormatter(formatter)
        logger.addHandler(handler)
    return logger

def load_pilot_traces(logger: logging.Logger) -> List[Dict[str, Any]]:
    """
    Load pilot traces from the generated file.
    
    Returns:
        List of trace dictionaries.
    """
    if not PILOT_TRACES_PATH.exists():
        logger.error(f"Pilot traces file not found: {PILOT_TRACES_PATH}")
        raise FileNotFoundError(
            f"Pilot traces file not found: {PILOT_TRACES_PATH}. "
            "Please run code/pilot_study.py first to generate the pilot traces."
        )
    
    logger.info(f"Loading pilot traces from {PILOT_TRACES_PATH}")
    traces = []
    with open(PILOT_TRACES_PATH, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                traces.append(json.loads(line))
    
    logger.info(f"Loaded {len(traces)} pilot traces")
    return traces

def format_annotation_request(
    traces: List[Dict[str, Any]], logger: logging.Logger
) -> List[Dict[str, Any]]:
    """
    Format traces into annotation request items.
    
    Each item includes:
    - task_id: Unique identifier
    - task_category: Category of the task
    - constraint: The constraint to look for
    - trace: The generated CoT trace
    - annotation_id: A unique ID for the annotation request
    - created_at: Timestamp
    
    Args:
        traces: List of trace dictionaries
        logger: Logger instance
    
    Returns:
        List of formatted annotation request items
    """
    request_items = []
    
    for idx, trace in enumerate(traces[:MAX_PILOT_SIZE]):
        # Extract relevant fields
        task_id = trace.get("task_id", f"unknown_{idx}")
        task_category = trace.get("task_category", "Unknown")
        constraint = trace.get("constraint", "N/A")
        trace_text = trace.get("trace", "N/A")
        
        request_item = {
            "annotation_id": f"pilot_{idx}",
            "task_id": task_id,
            "task_category": task_category,
            "constraint": constraint,
            "trace": trace_text,
            "instructions": {
                "constraint_mention": {
                    "question": "Does the trace explicitly mention the task constraint?",
                    "options": ["Yes", "No"],
                    "description": "Check if the model's reasoning explicitly references the specific constraint given in the task (e.g., 'count the red objects', 'find the largest square')."
                },
                "task_outcome": {
                    "question": "Is the final answer in the trace correct?",
                    "options": ["Correct", "Incorrect"],
                    "description": "Determine if the final conclusion or answer provided in the trace matches the ground truth (if available) or is logically sound based on the reasoning."
                }
            },
            "created_at": datetime.now(timezone.utc).isoformat()
        }
        request_items.append(request_item)
    
    logger.info(f"Formatted {len(request_items)} annotation request items")
    return request_items

def write_annotation_request(
    request_items: List[Dict[str, Any]], logger: logging.Logger
) -> None:
    """
    Write annotation request items to a JSONL file.
    
    Args:
        request_items: List of formatted request items
        logger: Logger instance
    """
    output_path = ANNOTATION_REQUEST_PATH
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Writing annotation request to {output_path}")
    with open(output_path, "w", encoding="utf-8") as f:
        for item in request_items:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")
    
    logger.info(f"Successfully wrote {len(request_items)} items to {output_path}")
    logger.info(
        "Human experts should now label this file and save results to "
        "data/pilot/pilot_ground_truth_labels.jsonl"
    )

def main() -> int:
    """Main entry point for the script."""
    logger = setup_logging()
    logger.info("Starting pilot annotation request generation")
    
    try:
        # Load traces
        traces = load_pilot_traces(logger)
        
        if not traces:
            logger.error("No traces found in pilot file. Cannot generate request.")
            return 1
        
        # Format request
        request_items = format_annotation_request(traces, logger)
        
        # Write output
        write_annotation_request(request_items, logger)
        
        logger.info("Pilot annotation request generation completed successfully")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        return 1
    except json.JSONDecodeError as e:
        logger.error(f"JSON decode error: {e}")
        return 1
    except Exception as e:
        logger.exception(f"Unexpected error: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())