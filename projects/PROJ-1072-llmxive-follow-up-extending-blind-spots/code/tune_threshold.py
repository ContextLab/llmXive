import argparse
import json
import sys
from pathlib import Path
from typing import List, Dict, Tuple, Any
import numpy as np

from sentence_transformers import SentenceTransformer
from utils.logging_config import get_logger

# Configuration
THRESHOLD_MIN = -1.0
THRESHOLD_MAX = 1.0
THRESHOLD_STEPS = 21  # Step size 0.1
OUTPUT_PATH = Path("data/pilot/tuned_threshold.json")
TRACES_PATH = Path("data/pilot/pilot_traces.jsonl")
LABELS_PATH = Path("data/validation/pilot_labels.jsonl")

logger = get_logger(__name__)


def load_pilot_traces(path: Path) -> List[Dict[str, Any]]:
    """Load pilot traces generated by T040."""
    if not path.exists():
        logger.error(f"Traces file not found: {path}")
        raise FileNotFoundError(f"Traces file not found: {path}")
    
    traces = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                traces.append(json.loads(line))
    logger.info(f"Loaded {len(traces)} traces from {path}")
    return traces


def load_pilot_labels(path: Path) -> List[Dict[str, Any]]:
    """Load human/oracle labels generated by T041."""
    if not path.exists():
        logger.error(f"Labels file not found: {path}")
        raise FileNotFoundError(f"Labels file not found: {path}")
    
    labels = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                labels.append(json.loads(line))
    logger.info(f"Loaded {len(labels)} labels from {path}")
    return labels


def align_traces_and_labels(
    traces: List[Dict[str, Any]], labels: List[Dict[str, Any]]
) -> List[Tuple[Dict[str, Any], Dict[str, Any]]]:
    """Align traces with their corresponding labels by task_id."""
    trace_map = {t["task_id"]: t for t in traces}
    aligned = []
    
    for label in labels:
        task_id = label.get("task_id")
        if task_id not in trace_map:
            logger.warning(f"Trace not found for task_id: {task_id}")
            continue
        
        aligned.append((trace_map[task_id], label))
    
    logger.info(f"Aligned {len(aligned)} trace-label pairs")
    return aligned


def compute_agreement(
    aligned_pairs: List[Tuple[Dict[str, Any], Dict[str, Any]]],
    threshold: float,
    model: SentenceTransformer
) -> Tuple[float, int, int, int]:
    """
    Compute agreement between automated semantic match and human labels.
    
    Returns: (accuracy, true_positives, true_negatives, total)
    """
    correct = 0
    tp = 0
    tn = 0
    total = len(aligned_pairs)
    
    if total == 0:
        return 0.0, 0, 0, 0
    
    for trace, label in aligned_pairs:
        # Extract constraint from trace (from pilot study generation)
        # The trace should contain the generated CoT and the constraint mention
        trace_text = trace.get("cot_trace", "")
        constraint_text = trace.get("constraint", "")
        
        if not trace_text or not constraint_text:
            logger.warning("Missing trace or constraint text, skipping")
            continue
        
        # Compute semantic similarity
        embeddings = model.encode([trace_text, constraint_text], convert_to_numpy=True)
        similarity = np.dot(embeddings[0], embeddings[1]) / (
            np.linalg.norm(embeddings[0]) * np.linalg.norm(embeddings[1])
        )
        
        # Automated prediction: 1 if similarity >= threshold, else 0
        auto_pred = 1 if similarity >= threshold else 0
        
        # Human label: 1 if constraint mentioned, else 0
        human_label = label.get("constraint_mention", 0)
        
        if auto_pred == human_label:
            correct += 1
            if human_label == 1:
                tp += 1
            else:
                tn += 1
        
    accuracy = correct / total if total > 0 else 0.0
    return accuracy, tp, tn, total


def tune_threshold(
    aligned_pairs: List[Tuple[Dict[str, Any], Dict[str, Any]]],
    model: SentenceTransformer
) -> Dict[str, Any]:
    """
    Iterate over threshold range to find optimal threshold maximizing agreement.
    """
    thresholds = np.linspace(
        THRESHOLD_MIN, THRESHOLD_MAX, THRESHOLD_STEPS
    )
    
    best_threshold = None
    best_accuracy = -1.0
    best_stats = {}
    
    logger.info(f"Tuning threshold over {len(thresholds)} values...")
    
    for threshold in thresholds:
        accuracy, tp, tn, total = compute_agreement(
            aligned_pairs, threshold, model
        )
        
        logger.debug(
            f"Threshold {threshold:.2f}: Accuracy={accuracy:.4f} "
            f"(TP={tp}, TN={tn}, Total={total})"
        )
        
        if accuracy > best_accuracy:
            best_accuracy = accuracy
            best_threshold = threshold
            best_stats = {
                "accuracy": accuracy,
                "true_positives": tp,
                "true_negatives": tn,
                "total": total
            }
    
    return {
        "optimal_threshold": best_threshold,
        "optimal_accuracy": best_accuracy,
        "statistics": best_stats,
        "threshold_range": [THRESHOLD_MIN, THRESHOLD_MAX],
        "num_steps": THRESHOLD_STEPS
    }


def save_results(results: Dict[str, Any], output_path: Path) -> None:
    """Save tuning results to JSON file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)
    
    logger.info(f"Results saved to {output_path}")


def main() -> int:
    """Main entry point for threshold tuning."""
    parser = argparse.ArgumentParser(
        description="Tune semantic matching threshold for constraint detection"
    )
    parser.add_argument(
        "--traces",
        type=str,
        default=str(TRACES_PATH),
        help="Path to pilot traces JSONL file"
    )
    parser.add_argument(
        "--labels",
        type=str,
        default=str(LABELS_PATH),
        help="Path to human/oracle labels JSONL file"
    )
    parser.add_argument(
        "--output",
        type=str,
        default=str(OUTPUT_PATH),
        help="Path to output results JSON file"
    )
    parser.add_argument(
        "--model",
        type=str,
        default="all-MiniLM-L6-v2",
        help="SentenceTransformer model name"
    )
    
    args = parser.parse_args()
    
    traces_path = Path(args.traces)
    labels_path = Path(args.labels)
    output_path = Path(args.output)
    
    try:
        # Load data
        traces = load_pilot_traces(traces_path)
        labels = load_pilot_labels(labels_path)
        
        # Align traces and labels
        aligned_pairs = align_traces_and_labels(traces, labels)
        
        if len(aligned_pairs) == 0:
            logger.error("No aligned trace-label pairs found. Cannot tune threshold.")
            return 1
        
        # Load model
        logger.info(f"Loading model: {args.model}")
        model = SentenceTransformer(args.model)
        
        # Tune threshold
        results = tune_threshold(aligned_pairs, model)
        
        # Save results
        save_results(results, output_path)
        
        logger.info(
            f"Tuning complete. Optimal threshold: {results['optimal_threshold']:.2f}, "
            f"Accuracy: {results['optimal_accuracy']:.4f}"
        )
        
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during threshold tuning: {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
