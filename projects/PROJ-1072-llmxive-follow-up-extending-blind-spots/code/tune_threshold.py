def main():
    """Main entry point for threshold tuning."""
    setup_root_logger()
    
    parser = argparse.ArgumentParser(description="Tune semantic matching threshold on pilot data.")
    parser.add_argument(
        "--traces",
        type=str,
        default=str(PILOT_TRACES_PATH),
        help="Path to pilot traces JSONL"
    )
    parser.add_argument(
        "--labels",
        type=str,
        default=str(PILOT_LABELS_PATH),
        help="Path to pilot ground truth labels JSONL"
    )
    parser.add_argument(
        "--output",
        type=str,
        default=str(OUTPUT_PATH),
        help="Path to output JSON file"
    )
    parser.add_argument(
        "--model",
        type=str,
        default=MODEL_NAME,
        help="SentenceTransformer model name"
    )
    
    args = parser.parse_args()
    
    try:
        # Load data
        logger.info("Loading pilot traces...")
        traces = load_pilot_traces(Path(args.traces))
        
        logger.info("Loading pilot labels...")
        labels = load_pilot_labels(Path(args.labels))
        
        # Align data
        logger.info("Aligning traces and labels...")
        aligned_pairs = align_traces_and_labels(traces, labels)
        
        # Load model
        logger.info(f"Loading model: {args.model}")
        model = SentenceTransformer(args.model)
        
        # Tune threshold
        logger.info("Starting threshold tuning...")
        best_threshold, best_agreement, history = tune_threshold(aligned_pairs, model)
        
        # Save results
        logger.info("Saving results...")
        save_results(best_threshold, best_agreement, history, Path(args.output))
        
        logger.info("Threshold tuning completed successfully.")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        return 1
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        return 1
    except Exception as e:
        logger.exception(f"Unexpected error during tuning: {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
