"""
T041: Finalize data/results/output.json with all Success Criteria.

This script aggregates results from previous stages (Modeling, Interpretability)
and compiles the final `data/results/output.json` containing all required
Success Criteria (SC-001 through SC-008).
"""
import os
import sys
import json
import logging
from pathlib import Path
import numpy as np

# Add project root to path to allow imports
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from config import CONFIG
from utils.logging import get_logger, log_provenance_event

logger = get_logger(__name__)

def load_json_safe(path: Path, default: dict = None) -> dict:
    """Load JSON file safely, returning default if not found or invalid."""
    if not path.exists():
        logger.warning(f"File not found: {path}. Using default: {default}")
        return default if default else {}
    try:
        with open(path, 'r') as f:
            return json.load(f)
    except (json.JSONDecodeError, IOError) as e:
        logger.error(f"Error loading {path}: {e}")
        return default if default else {}

def load_pickle_safe(path: Path):
    """Load pickle file safely."""
    if not path.exists():
        logger.warning(f"Pickle file not found: {path}")
        return None
    try:
        import pickle
        with open(path, 'rb') as f:
            return pickle.load(f)
    except Exception as e:
        logger.error(f"Error loading pickle {path}: {e}")
        return None

def assemble_success_criteria() -> dict:
    """
    Assemble the final output dictionary with all Success Criteria.
    
    SC-001: Pearson correlation between Shear Modulus and Yield Strength
    SC-002: R2 and MAE for both models (Composition-only vs DFT-enhanced)
    SC-003: Paired t-test p-value comparing the two models
    SC-004: Std_dev from sample-size sweep (stability analysis)
    SC-005: Std_dev from fixed-sample bootstrap (stability analysis)
    SC-006: is_stable boolean (based on SC-005 threshold)
    SC-007: Top 5 features from SHAP analysis
    SC-008: Statistical power (1 - beta)
    """
    output = {}

    # 1. Load Modeling Results (T032 output)
    # Expected keys: r2_baseline, r2_dft, mae_baseline, mae_dft, p_value, power, pearson_correlation
    modeling_path = CONFIG.RESULTS_DIR / "output.json"
    modeling_results = load_json_safe(modeling_path, {})
    
    # SC-001: Pearson Correlation
    if 'pearson_correlation' in modeling_results:
        output['SC-001'] = {
            'pearson_correlation_coefficient': modeling_results['pearson_correlation'],
            'description': 'Pearson correlation between Shear Modulus and Yield Strength'
        }
    else:
        logger.warning("SC-001: pearson_correlation not found in modeling results")
        output['SC-001'] = {'status': 'missing_data', 'pearson_correlation_coefficient': None}

    # SC-002: Model Performance (R2, MAE)
    output['SC-002'] = {
        'composition_baseline': {
            'r2': modeling_results.get('r2_baseline'),
            'mae': modeling_results.get('mae_baseline')
        },
        'dft_enhanced': {
            'r2': modeling_results.get('r2_dft'),
            'mae': modeling_results.get('mae_dft')
        },
        'description': 'R2 and MAE for both models'
    }

    # SC-003: Paired t-test p-value
    if 'p_value' in modeling_results:
        output['SC-003'] = {
            'p_value': modeling_results['p_value'],
            'description': 'Paired t-test p-value comparing fold-wise errors'
        }
    else:
        logger.warning("SC-003: p_value not found in modeling results")
        output['SC-003'] = {'status': 'missing_data', 'p_value': None}

    # SC-008: Statistical Power
    if 'power' in modeling_results:
        output['SC-008'] = {
            'statistical_power': modeling_results['power'],
            'is_sufficient': modeling_results['power'] >= 0.8 if modeling_results.get('power') is not None else False,
            'description': 'Statistical power (1 - beta)'
        }
    else:
        logger.warning("SC-008: power not found in modeling results")
        output['SC-008'] = {'status': 'missing_data', 'statistical_power': None}

    # 2. Load Interpretability Results (Bootstrap Stability)
    # Expected path: data/intermediate/bootstrap_results.json (or similar from T037/T038)
    # We need to check the specific file generated by bootstrap_stability.py
    bootstrap_path = CONFIG.INTERMEDIATE_DIR / "bootstrap_results.json"
    bootstrap_results = load_json_safe(bootstrap_path, {})
    
    # If not in intermediate, try results
    if not bootstrap_results:
        bootstrap_path = CONFIG.RESULTS_DIR / "bootstrap_results.json"
        bootstrap_results = load_json_safe(bootstrap_path, {})

    # SC-004: Std_dev from sample-size sweep
    sweep_std = bootstrap_results.get('sample_size_sweep_std')
    output['SC-004'] = {
        'std_dev_sample_size_sweep': sweep_std,
        'description': 'Standard deviation of feature importance across sample-size sweep (n=10 to n=50)'
    }

    # SC-005: Std_dev from fixed-sample bootstrap
    bootstrap_std = bootstrap_results.get('fixed_sample_bootstrap_std')
    output['SC-005'] = {
        'std_dev_fixed_sample_bootstrap': bootstrap_std,
        'description': 'Standard deviation of feature importance across 10 bootstrapped samples'
    }

    # SC-006: is_stable boolean (based on SC-005 threshold < 0.05)
    # Logic from T039: check if std_dev of key DFT descriptors < 0.05
    is_stable = False
    if bootstrap_std is not None and isinstance(bootstrap_std, (int, float)):
        is_stable = bootstrap_std < 0.05
    
    output['SC-006'] = {
        'is_stable': is_stable,
        'threshold': 0.05,
        'observed_std_dev': bootstrap_std,
        'description': 'Boolean indicating if model stability is sufficient (std_dev < 0.05)'
    }

    # 3. Load SHAP Results for Top Features
    # Expected path: data/intermediate/shap_results.json (or similar from T035)
    shap_path = CONFIG.INTERMEDIATE_DIR / "shap_results.json"
    shap_results = load_json_safe(shap_path, {})
    
    if not shap_results:
        shap_path = CONFIG.RESULTS_DIR / "shap_results.json"
        shap_results = load_json_safe(shap_path, {})

    # SC-007: Top 5 features
    top_features = shap_results.get('top_5_features', [])
    if not top_features and 'feature_importance' in shap_results:
        # Fallback: sort the importance dict
        fi = shap_results.get('feature_importance', {})
        sorted_features = sorted(fi.items(), key=lambda x: x[1], reverse=True)[:5]
        top_features = [{"feature": k, "importance": v} for k, v in sorted_features]

    output['SC-007'] = {
        'top_5_features': top_features,
        'description': 'Top 5 most important features from SHAP analysis'
    }

    # Metadata
    output['metadata'] = {
        'project_id': CONFIG.PROJECT_ID,
        'success_criteria_count': 8,
        'all_criteria_met': (
            output['SC-001'].get('pearson_correlation_coefficient') is not None and
            output['SC-002']['composition_baseline']['r2'] is not None and
            output['SC-003'].get('p_value') is not None and
            output['SC-004'].get('std_dev_sample_size_sweep') is not None and
            output['SC-005'].get('std_dev_fixed_sample_bootstrap') is not None and
            output['SC-007'].get('top_5_features') is not None and
            output['SC-008'].get('statistical_power') is not None
        ),
        'timestamp': str(Path(__file__).stat().st_mtime) # Simple timestamp placeholder
    }

    return output

def main():
    logger.info("Starting T041: Finalizing output.json with all Success Criteria")
    
    try:
        final_output = assemble_success_criteria()
        
        output_path = CONFIG.RESULTS_DIR / "output.json"
        
        with open(output_path, 'w') as f:
            json.dump(final_output, f, indent=2)
        
        logger.info(f"Successfully wrote final output to {output_path}")
        log_provenance_event("T041", "output_finalized", str(output_path))
        
        # Print summary for verification
        print(f"SC-001 (Correlation): {final_output['SC-001']}")
        print(f"SC-002 (Performance): {final_output['SC-002']}")
        print(f"SC-003 (P-value): {final_output['SC-003']}")
        print(f"SC-004 (Sweep Std): {final_output['SC-004']}")
        print(f"SC-005 (Bootstrap Std): {final_output['SC-005']}")
        print(f"SC-006 (Is Stable): {final_output['SC-006']}")
        print(f"SC-007 (Top Features): {final_output['SC-007']}")
        print(f"SC-008 (Power): {final_output['SC-008']}")
        
    except Exception as e:
        logger.error(f"Failed to finalize output: {e}")
        raise

if __name__ == "__main__":
    main()