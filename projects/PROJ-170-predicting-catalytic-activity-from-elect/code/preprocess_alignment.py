"""
Alignment script for T003 – Align descriptors with experimental TOFs.

This script reads the descriptor table generated by `code/extract_descriptors.py`
(`data/processed/oc20_descriptors.parquet`) and the experimental TOF CSV
(`data/raw/experimental_tof.csv`).  It performs an exact string match on the
columns ``composition``, ``surface_facet`` and ``synthesis_condition`` (and,
when present, ``temperature`` and ``pressure``) between the two tables,
constructs a unified DataFrame, writes it to ``data/processed/unified_dataset.parquet``,
and records alignment metrics in ``outputs/alignment_metrics.json``.

The script follows the functional requirement FR‑002 and the success criteria
SC‑002: the alignment success rate (matched entries / total experimental entries)
must be ≥ 0.80 and the resulting unified dataset must contain at least 500 rows
(or ≥ 1500 when source data permit).  If the experimental TOF file is empty or
the alignment rate falls below the threshold, the script raises a
``RuntimeError`` – this makes the failure loud, as required by the project
policy.

The script is deliberately lightweight and does not perform any imputation or
scaling; those steps are handled later by ``code/preprocess.py`` (T004‑T005).
"""

import sys
import json
import logging
from pathlib import Path

import pandas as pd

# Project utilities
from config import get_data_path, get_output_path
from logging_config import get_logger

logger = get_logger(__name__)

# ----------------------------------------------------------------------
# Paths
# ----------------------------------------------------------------------
DESCRIPTORS_PATH = get_data_path() / "processed" / "oc20_descriptors.parquet"
EXPERIMENTAL_TOF_PATH = get_data_path() / "raw" / "experimental_tof.csv"
UNIFIED_OUTPUT_PATH = get_data_path() / "processed" / "unified_dataset.parquet"
METRICS_OUTPUT_PATH = get_output_path() / "alignment_metrics.json"

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def _load_descriptors() -> pd.DataFrame:
    """Load the descriptor parquet produced by ``extract_descriptors.py``."""
    if not DESCRIPTORS_PATH.exists():
        raise FileNotFoundError(f"Descriptor file not found at {DESCRIPTORS_PATH}")
    logger.info(f"Loading descriptors from {DESCRIPTORS_PATH}")
    df = pd.read_parquet(DESCRIPTORS_PATH)
    logger.info(f"Descriptors shape: {df.shape}")
    return df

def _load_experimental() -> pd.DataFrame:
    """Load the experimental TOF CSV (may be empty)."""
    if not EXPERIMENTAL_TOF_PATH.exists():
        raise FileNotFoundError(f"Experimental TOF file not found at {EXPERIMENTAL_TOF_PATH}")
    logger.info(f"Loading experimental TOF from {EXPERIMENTAL_TOF_PATH}")
    df = pd.read_csv(EXPERIMENTAL_TOF_PATH, dtype=str)  # keep everything as string initially
    logger.info(f"Experimental TOF shape: {df.shape}")
    return df

def _normalize_series(series: pd.Series) -> pd.Series:
    """Strip whitespace and lower‑case strings for robust matching."""
    return series.fillna("").astype(str).str.strip().str.lower()

def _prepare_for_merge(df: pd.DataFrame, suffix: str) -> pd.DataFrame:
    """
    Normalise the key columns and rename them with a suffix to avoid clashes
    during the merge.
    """
    for col in ["composition", "surface_facet", "synthesis_condition", "temperature", "pressure"]:
        if col in df.columns:
            df[col] = _normalize_series(df[col])
    # Ensure all required columns exist (create empty columns if missing)
    required = ["composition", "surface_facet", "synthesis_condition"]
    for col in required:
        if col not in df.columns:
            df[col] = ""
    # Temperature and pressure are optional – keep them if present
    return df

def align_datasets(descriptors: pd.DataFrame, experimental: pd.DataFrame) -> pd.DataFrame:
    """
    Perform an exact match on the required columns.
    Returns the merged DataFrame containing only rows that matched.
    """
    # Normalise both sides
    descriptors = _prepare_for_merge(descriptors.copy(), "desc")
    experimental = _prepare_for_merge(experimental.copy(), "exp")

    # Build a merge key
    merge_cols = ["composition", "surface_facet", "synthesis_condition"]
    # Include temperature/pressure only when both sides have them
    for optional in ["temperature", "pressure"]:
        if optional in descriptors.columns and optional in experimental.columns:
            merge_cols.append(optional)

    logger.info(f"Merging on columns: {merge_cols}")

    merged = pd.merge(
        descriptors,
        experimental,
        on=merge_cols,
        how="inner",
        suffixes=("_desc", "_exp")
    )
    logger.info(f"Merged dataset shape: {merged.shape}")
    return merged

def compute_alignment_metrics(total_experimental: int, matched: int) -> dict:
    """Calculate the alignment rate and package metrics."""
    alignment_rate = matched / total_experimental if total_experimental > 0 else 0.0
    metrics = {
        "total_experimental_entries": total_experimental,
        "aligned_entries": matched,
        "excluded_by_fr002": total_experimental - matched,
        "alignment_rate": alignment_rate
    }
    logger.info(f"Alignment metrics: {metrics}")
    return metrics

# ----------------------------------------------------------------------
# Main entry point
# ----------------------------------------------------------------------
def main() -> int:
    """
    Executes the alignment step.

    Returns:
        0 on success, non‑zero on failure.
    """
    try:
        descriptors = _load_descriptors()
        experimental = _load_experimental()

        total_experimental = len(experimental)
        if total_experimental == 0:
            raise RuntimeError(
                "Experimental TOF dataset is empty – cannot compute alignment. "
                "Provide a non‑empty CSV as required by FR‑001."
            )

        # Align datasets
        unified_df = align_datasets(descriptors, experimental)

        # Compute and store metrics
        metrics = compute_alignment_metrics(total_experimental, len(unified_df))
        METRICS_OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
        with open(METRICS_OUTPUT_PATH, "w") as f:
            json.dump(metrics, f, indent=2)
        logger.info(f"Wrote alignment metrics to {METRICS_OUTPUT_PATH}")

        # Verify success criteria
        if metrics["alignment_rate"] < 0.80:
            raise RuntimeError(
                f"Alignment success rate {metrics['alignment_rate']:.2%} is below the required 80 %."
            )
        if len(unified_df) < 500:
            raise RuntimeError(
                f"Unified dataset contains {len(unified_df)} rows, which is below the required 500."
            )

        # Write unified dataset
        UNIFIED_OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
        unified_df.to_parquet(UNIFIED_OUTPUT_PATH, index=False)
        logger.info(f"Wrote unified dataset to {UNIFIED_OUTPUT_PATH}")

        return 0

    except Exception as exc:
        logger.error(f"Alignment step failed: {exc}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())
