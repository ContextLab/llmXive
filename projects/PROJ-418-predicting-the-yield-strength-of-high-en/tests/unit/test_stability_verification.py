"""
Unit test for verifying that the stability rankings produced by the pipeline
satisfy the stability criterion: the rank difference for the top‑k features
across the three runs must be ≤ 1.

The expected JSON format (generated by ``scripts/run_stability.py``) is one
of the following:

1. A mapping from run identifiers to an ordered list of feature names,
   e.g.:
   {
       "run_1": ["feat_a", "feat_b", "feat_c", ...],
       "run_2": ["feat_a", "feat_c", "feat_b", ...],
       "run_3": ["feat_b", "feat_a", "feat_c", ...]
   }

2. A mapping from run identifiers to a mapping of feature name → rank
   (1‑based), e.g.:
   {
       "run_1": {"feat_a": 1, "feat_b": 2, "feat_c": 3, ...},
       "run_2": {"feat_a": 2, "feat_b": 1, "feat_c": 3, ...},
       "run_3": {"feat_a": 1, "feat_b": 2, "feat_c": 3, ...}
   }

The test normalises either representation to an ordered list per run and
then checks that, for the top‑k features (default k=5), the maximum
absolute rank difference across the three runs does not exceed 1.
"""

import json
import pathlib
from typing import Dict, List

import pytest

from utils.logging import get_logger

LOGGER = get_logger(__name__)

STABILITY_RANKINGS_PATH = pathlib.Path("output/stability_rankings.json")
TOP_K = 5  # Number of top features whose stability we enforce


def _load_rankings(path: pathlib.Path) -> Dict[str, List[str]]:
    """
    Load the stability rankings JSON and normalise it to a dict mapping
    run identifiers to an *ordered* list of feature names (rank 1 first).

    Parameters
    ----------
    path: pathlib.Path
        Path to ``stability_rankings.json``.

    Returns
    -------
    dict
        ``{run_id: [feature_1, feature_2, ...]}``
    """
    if not path.is_file():
        raise FileNotFoundError(f"Stability rankings file not found: {path}")

    with path.open("r", encoding="utf-8") as fh:
        raw = json.load(fh)

    normalised: Dict[str, List[str]] = {}
    for run_id, data in raw.items():
        if isinstance(data, list):
            # Already an ordered list of features
            normalised[run_id] = data
        elif isinstance(data, dict):
            # Mapping feature -> rank; sort by rank (ascending)
            try:
                sorted_features = [
                    feat for feat, _ in sorted(data.items(), key=lambda kv: kv[1])
                ]
            except Exception as exc:
                raise ValueError(
                    f"Invalid rank mapping for run '{run_id}': {exc}"
                ) from exc
            normalised[run_id] = sorted_features
        else:
            raise ValueError(
                f"Unexpected data type for run '{run_id}': {type(data)}"
            )
    return normalised


def _max_rank_difference(rankings: Dict[str, List[str]], top_k: int = TOP_K) -> int:
    """
    Compute the maximum absolute rank difference for the top‑k features
    across all runs.

    Parameters
    ----------
    rankings: dict
        Normalised rankings as returned by ``_load_rankings``.
    top_k: int
        Number of top features to consider.

    Returns
    -------
    int
        The largest absolute rank difference observed.
    """
    # Ensure we have exactly three runs (the specification)
    if len(rankings) != 3:
        raise AssertionError(
            f"Expected rankings from exactly three runs, got {len(rankings)}"
        )

    # Build a feature → list of ranks (one per run)
    feature_ranks: Dict[str, List[int]] = {}

    for run_idx, (run_id, ordered_features) in enumerate(rankings.items()):
        for rank, feature in enumerate(ordered_features, start=1):
            if feature not in feature_ranks:
                feature_ranks[feature] = [None, None, None]  # placeholder for three runs
            feature_ranks[feature][run_idx] = rank

    # Consider only features that appear within the top‑k of *any* run
    candidates = [
        feat
        for feat, ranks in feature_ranks.items()
        if any(r is not None and r <= top_k for r in ranks)
    ]

    max_diff = 0
    for feat in candidates:
        ranks = feature_ranks[feat]
        # Replace missing ranks with a large number (worse than top_k)
        # This will cause a diff > 1 and thus fail the test, which is
        # appropriate because a missing top‑k feature violates stability.
        filled_ranks = [r if r is not None else top_k + 10 for r in ranks]
        diff = max(filled_ranks) - min(filled_ranks)
        if diff > max_diff:
            max_diff = diff
    return max_diff


def test_stability_rankings_meet_criterion():
    """
    Verify that the rank difference for the top‑k features across the three
    runs does not exceed 1.
    """
    rankings = _load_rankings(STABILITY_RANKINGS_PATH)
    max_diff = _max_rank_difference(rankings, top_k=TOP_K)

    LOGGER.info(
        "Maximum rank difference among top-%d features: %d", TOP_K, max_diff
    )
    assert max_diff <= 1, (
        f"Stability criterion violated: maximum rank difference "
        f"{max_diff} > 1 for top-{TOP_K} features."
    )