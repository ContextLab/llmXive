"""
Unit test for T119 – Stability Rankings Verification

This test loads the JSON file generated by the stability script
(`output/stability_rankings.json`) and checks that, for the top‑k
features (default k=5), the rank difference across the three runs
does not exceed 1.  The JSON is expected to contain three top‑level
keys (e.g., "run1", "run2", "run3") each mapping to a list of
feature names ordered from most to least important.

If the file is missing or malformed, the test will raise an
informative exception, causing the verification to fail loudly.
"""

import json
import pathlib
import unittest
from typing import Dict, List


class TestStabilityRankings(unittest.TestCase):
    """Verify rank‑difference ≤ 1 for the top‑k features across runs."""

    #: Path to the generated stability rankings JSON
    STABILITY_JSON_PATH = pathlib.Path("output/stability_rankings.json")

    #: Number of top features to consider for the stability check
    TOP_K = 5

    def load_rankings(self) -> Dict[str, List[str]]:
        """Load the JSON file and return a mapping of run → ordered feature list.

        Expected JSON format:
        {
            "run1": ["featA", "featB", ...],
            "run2": ["featA", "featC", ...],
            "run3": ["featB", "featA", ...]
        }

        If the JSON does not match this simple schema, a ``ValueError`` is raised.
        """
        if not self.STABILITY_JSON_PATH.is_file():
            raise FileNotFoundError(
                f"Stability rankings file not found: {self.STABILITY_JSON_PATH}"
            )

        with self.STABILITY_JSON_PATH.open("r", encoding="utf-8") as f:
            data = json.load(f)

        if not isinstance(data, dict):
            raise ValueError("Stability rankings JSON must be a dictionary at top level.")

        # Ensure we have exactly three runs (allow any naming, but must be three keys)
        if len(data) != 3:
            raise ValueError(
                f"Expected 3 runs in stability rankings, found {len(data)} keys."
            )

        rankings: Dict[str, List[str]] = {}
        for run_name, feat_list in data.items():
            if not isinstance(feat_list, list) or not all(
                isinstance(feat, str) for feat in feat_list
            ):
                raise ValueError(
                    f"Run '{run_name}' must map to a list of feature name strings."
                )
            rankings[run_name] = feat_list
        return rankings

    def compute_rank_positions(
        self, rankings: Dict[str, List[str]]
    ) -> Dict[str, Dict[str, int]]:
        """
        Convert ordered feature lists into a mapping:
            run → {feature_name: rank_position}
        Rank positions are 0‑based (0 = most important).
        """
        rank_positions: Dict[str, Dict[str, int]] = {}
        for run, ordered_feats in rankings.items():
            rank_positions[run] = {feat: idx for idx, feat in enumerate(ordered_feats)}
        return rank_positions

    def test_rank_difference_within_threshold(self):
        """Core verification logic."""
        rankings = self.load_rankings()
        rank_positions = self.compute_rank_positions(rankings)

        # Gather all features that appear in the top‑k of any run
        top_k_features = set()
        for ordered in rankings.values():
            top_k_features.update(ordered[: self.TOP_K])

        # For each feature, collect its rank in each run (assign a large rank if missing)
        max_allowed_rank = self.TOP_K + 1  # sentinel for missing features
        for feature in top_k_features:
            ranks = []
            for run in sorted(rank_positions.keys()):  # deterministic order
                rank = rank_positions[run].get(feature, max_allowed_rank)
                ranks.append(rank)
            rank_range = max(ranks) - min(ranks)
            self.assertLessEqual(
                rank_range,
                1,
                msg=(
                    f"Feature '{feature}' rank range across runs is {rank_range} "
                    f"(ranks: {ranks}); exceeds allowed difference of 1."
                ),
            )


if __name__ == "__main__":
    # When run directly, invoke unittest main
    unittest.main()