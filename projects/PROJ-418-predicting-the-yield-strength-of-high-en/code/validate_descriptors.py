"""
Validate the descriptor table ``data/processed/hea_descriptors.csv`` against the
JSON‑Schema defined in ``contracts/descriptor.schema.yaml``.

This script is invoked by the quickstart after the pipeline has produced the
descriptor CSV.  It raises an exception (causing a non‑zero exit status) if
validation fails, otherwise it exits silently with status 0.
"""

import json
import pathlib
import sys

import pandas as pd
import yaml
from jsonschema import Draft7Validator, ValidationError


def load_schema(schema_path: pathlib.Path) -> dict:
    """Load a YAML schema file."""
    with schema_path.open("r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def validate_descriptor_table(csv_path: pathlib.Path, schema_path: pathlib.Path) -> None:
    """
    Validate ``csv_path`` against ``schema_path``.

    Parameters
    ----------
    csv_path: pathlib.Path
        Path to the descriptor CSV generated by the pipeline.
    schema_path: pathlib.Path
        Path to the JSON‑Schema (YAML format) describing the expected table.

    Raises
    ------
    FileNotFoundError
        If either the CSV or the schema file does not exist.
    ValidationError
        If the CSV content does not conform to the schema.
    """
    if not csv_path.is_file():
        raise FileNotFoundError(f"Descriptor CSV not found: {csv_path}")
    if not schema_path.is_file():
        raise FileNotFoundError(f"Schema file not found: {schema_path}")

    # Load CSV into a list of dicts (records)
    df = pd.read_csv(csv_path)
    records = df.to_dict(orient="records")

    # Load and compile the schema
    schema = load_schema(schema_path)
    validator = Draft7Validator(schema)

    # Validate each record; collect errors for a helpful message
    errors = []
    for idx, record in enumerate(records):
        for error in validator.iter_errors(record):
            errors.append(f"Row {idx + 2}: {error.message}")  # +2 for header + 0‑index

    if errors:
        error_msg = "\n".join(errors)
        raise ValidationError(f"Descriptor table validation failed:\n{error_msg}")

    # If we reach here, validation succeeded
    print(f"[validate_descriptors] Validation passed for {csv_path}")


def main(argv=None):
    """
    CLI entry point.

    Expected arguments:
        --descriptor-csv   Path to the descriptor CSV (default: data/processed/hea_descriptors.csv)
        --schema           Path to the descriptor schema (default: contracts/descriptor.schema.yaml)
    """
    import argparse

    parser = argparse.ArgumentParser(
        description="Validate the HEA descriptor CSV against its schema."
    )
    parser.add_argument(
        "--descriptor-csv",
        type=str,
        default="data/processed/hea_descriptors.csv",
        help="Path to the descriptor CSV file.",
    )
    parser.add_argument(
        "--schema",
        type=str,
        default="contracts/descriptor.schema.yaml",
        help="Path to the descriptor schema YAML file.",
    )
    args = parser.parse_args(argv if argv is not None else sys.argv[1:])

    csv_path = pathlib.Path(args.descriptor_csv)
    schema_path = pathlib.Path(args.schema)

    try:
        validate_descriptor_table(csv_path, schema_path)
    except (FileNotFoundError, ValidationError) as exc:
        print(f"[validate_descriptors] ERROR: {exc}", file=sys.stderr)
        sys.exit(1)
    sys.exit(0)


if __name__ == "__main__":
    main()
