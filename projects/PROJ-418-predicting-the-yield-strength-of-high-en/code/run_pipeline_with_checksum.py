"""
Run the full data pipeline with checksum verification.

This script ensures that the raw HEA dataset file
``data/raw/heas_raw.csv`` matches the checksum recorded in the
project state file. If the checksum does not match, the pipeline
aborts with a clear error (FR‑009).

The script performs three steps:
1. Download the raw dataset (if it does not already exist).
2. Verify the recorded SHA‑256 checksum against the actual file.
3. Execute the normal data pipeline which produces the processed
   descriptor file ``data/processed/hea_descriptors.csv`` and all
   downstream artifacts.

The script can be invoked directly from the command line; any
provided ``--seed`` or ``--output-dir`` arguments are passed through
to the underlying pipeline (if supported) but are otherwise ignored.
"""

import argparse
import sys
from pathlib import Path

# Project‑specific utilities
from data.download import download_dataset
from data.pipeline import run_pipeline
from T061_compute_checksum import compute_sha256, load_state
from utils.logging import get_logger, set_seeds

# Path to the global state file (generated by T060)
STATE_FILE = Path(
    "state/projects/PROJ-418-predicting-the-yield-strength-of-high-en.yaml"
)
RAW_DATA_PATH = Path("data/raw/heas_raw.csv")


def verify_checksum():
    """
    Verify that the checksum stored in the state file matches the
    actual SHA‑256 hash of ``data/raw/heas_raw.csv``.

    Raises
    ------
    FileNotFoundError
        If the raw data file does not exist.
    KeyError
        If the state file does not contain a recorded checksum.
    RuntimeError
        If the recorded checksum differs from the computed checksum.
    """
    logger = get_logger()

    if not RAW_DATA_PATH.is_file():
        raise FileNotFoundError(
            f"Raw dataset not found at expected location: {RAW_DATA_PATH}"
        )

    # Compute the actual checksum of the file on disk
    actual_checksum = compute_sha256(str(RAW_DATA_PATH))
    logger.debug(f"Computed checksum for {RAW_DATA_PATH}: {actual_checksum}")

    # Load the state file (YAML) and locate the recorded checksum
    if not STATE_FILE.is_file():
        raise FileNotFoundError(
            f"State file missing – expected at {STATE_FILE}. "
            "Run T060 to generate it before invoking the pipeline."
        )

    state = load_state(str(STATE_FILE))

    # The checksum key may have been named differently in earlier tasks.
    # We check a few common variants to stay robust.
    possible_keys = [
        "raw_dataset_checksum",
        "raw_dataset_sha256",
        "checksum_raw_dataset",
        "checksum",
    ]
    recorded_checksum = None
    for key in possible_keys:
        if key in state:
            recorded_checksum = state[key]
            break

    if recorded_checksum is None:
        raise KeyError(
            f"Checksum for the raw dataset not found in state file {STATE_FILE}. "
            f"Checked keys: {possible_keys}"
        )

    logger.debug(
        f"Recorded checksum from state file ({STATE_FILE}): {recorded_checksum}"
    )

    if actual_checksum.lower() != recorded_checksum.lower():
        raise RuntimeError(
            f"Checksum mismatch for raw dataset:\n"
            f"  Recorded: {recorded_checksum}\n"
            f"  Actual  : {actual_checksum}\n"
            "Aborting pipeline execution (FR‑009)."
        )
    logger.info("Checksum verification passed – proceeding with pipeline.")


def main(argv: list | None = None):
    """
    Entry point for the script.

    Parameters
    ----------
    argv : list | None
        Optional argument list; if ``None`` (default) ``sys.argv[1:]`` is used.
    """
    parser = argparse.ArgumentParser(
        description="Run full pipeline with checksum validation."
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="Random seed for reproducibility (passed to downstream pipeline).",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="output",
        help="Directory where pipeline outputs will be written.",
    )
    args = parser.parse_args(argv)

    logger = get_logger()
    logger.info("Starting pipeline with checksum validation.")

    # Ensure deterministic behavior if a seed is supplied
    if args.seed is not None:
        set_seeds(args.seed)

    # Step 1: download the raw dataset (no‑op if already present)
    logger.info("Downloading raw dataset (if needed)...")
    download_dataset()

    # Step 2: verify checksum against the recorded value in the state file
    verify_checksum()

    # Step 3: run the normal data pipeline
    logger.info("Running data pipeline...")
    try:
        # ``run_pipeline`` may accept configuration arguments; we forward the
        # output directory for consistency with the original quick‑start command.
        run_pipeline(output_dir=args.output_dir)
    except Exception as exc:
        logger.exception("Pipeline execution failed.")
        raise

    logger.info("Pipeline completed successfully.")


if __name__ == "__main__":
    # When executed as a script ``sys.argv[1:]`` is passed automatically.
    main()
