import os
import sys
import json
import logging
import argparse
import csv
from typing import List, Dict, Any, Optional
from pathlib import Path

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler('data/derived/aggregate_logs.log')
    ]
)
logger = logging.getLogger(__name__)

# Paths
PROJECT_ROOT = Path(__file__).parent.parent.parent
DATA_DIR = PROJECT_ROOT / 'data' / 'derived'
OUTPUT_FILE = DATA_DIR / 'simulation_logs.csv'
TEMP_DIR = PROJECT_ROOT / 'data' / 'temp'

# Required fields per FR-004 and FR-005
REQUIRED_FIELDS = [
    'student_id',
    'problem_id',
    'condition',  # neural, symbolic, neuro_symbolic
    'correct',
    'response_time_seconds',
    'comprehension_rating',
    'explanation_type',
    'bkt_state',
    'timestamp'
]

def load_simulation_logs(log_dir: Optional[Path] = None) -> List[Dict[str, Any]]:
    """
    Load simulation logs from individual JSON files generated by the BKT simulator.
    Expects files named 'simulation_log_<student_id>.json' in the log directory.
    """
    if log_dir is None:
        log_dir = DATA_DIR / 'temp' / 'simulation_logs'
    
    if not log_dir.exists():
        logger.error(f"Log directory does not exist: {log_dir}")
        return []

    logs = []
    log_files = list(log_dir.glob('simulation_log_*.json'))
    
    if not log_files:
        logger.warning(f"No simulation log files found in {log_dir}")
        return logs

    logger.info(f"Found {len(log_files)} simulation log files to aggregate")

    for log_file in log_files:
        try:
            with open(log_file, 'r', encoding='utf-8') as f:
                data = json.load(f)
                logs.append(data)
        except (json.JSONDecodeError, IOError) as e:
            logger.error(f"Failed to load log file {log_file}: {e}")
            continue

    return logs

def normalize_log_fields(log: Dict[str, Any]) -> Dict[str, Any]:
    """
    Normalize log fields to match the required schema (FR-004, FR-005).
    Handles potential variations in key names from the simulator.
    """
    normalized = {}
    
    # Map potential source keys to standard keys
    field_mapping = {
        'student_id': ['student_id', 'studentId', 'student'],
        'problem_id': ['problem_id', 'problemId', 'problem'],
        'condition': ['condition', 'experiment_condition', 'group'],
        'correct': ['correct', 'is_correct', 'response_correct', 'accuracy'],
        'response_time_seconds': ['response_time_seconds', 'response_time', 'rt_seconds', 'rt'],
        'comprehension_rating': ['comprehension_rating', 'comprehension', 'rating', 'understanding'],
        'explanation_type': ['explanation_type', 'explanation', 'type'],
        'bkt_state': ['bkt_state', 'state', 'knowledge_state'],
        'timestamp': ['timestamp', 'time', 'created_at', 'datetime']
    }

    for target_key, source_keys in field_mapping.items():
        value = None
        for source_key in source_keys:
            if source_key in log:
                value = log[source_key]
                break
        
        if value is None:
            # Provide sensible defaults or raise error for critical fields
            if target_key in ['student_id', 'problem_id', 'condition', 'correct']:
                logger.warning(f"Missing required field '{target_key}' in log, setting to None")
                value = None
            else:
                value = None
        
        normalized[target_key] = value

    return normalized

def validate_log(log: Dict[str, Any]) -> bool:
    """
    Validate that a normalized log entry has all required fields and valid types.
    """
    # Check required fields are present and not None
    for field in REQUIRED_FIELDS:
        if field not in log or log[field] is None:
            logger.debug(f"Validation failed: Missing or null field '{field}'")
            return False

    # Type validations
    if not isinstance(log['student_id'], str) or not log['student_id']:
        return False
    if not isinstance(log['problem_id'], str) or not log['problem_id']:
        return False
    if log['condition'] not in ['neural', 'symbolic', 'neuro_symbolic']:
        return False
    if not isinstance(log['correct'], bool):
        return False
    if not isinstance(log['response_time_seconds'], (int, float)) or log['response_time_seconds'] < 0:
        return False
    if not isinstance(log['comprehension_rating'], (int, float)) or not (1 <= log['comprehension_rating'] <= 5):
        return False
    if log['explanation_type'] not in ['neural', 'symbolic', 'neuro_symbolic']:
        return False
    if not isinstance(log['bkt_state'], str):
        return False
    if not isinstance(log['timestamp'], str):
        return False

    return True

def write_simulation_logs_csv(logs: List[Dict[str, Any]], output_path: Path) -> int:
    """
    Write validated and normalized logs to a CSV file.
    Returns the number of successfully written records.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    valid_logs = []
    for i, log in enumerate(logs):
        if validate_log(log):
            valid_logs.append(log)
        else:
            logger.warning(f"Skipping invalid log entry at index {i}")

    logger.info(f"Writing {len(valid_logs)} valid logs to {output_path}")

    with open(output_path, 'w', newline='', encoding='utf-8') as csvfile:
        writer = csv.DictWriter(csvfile, fieldnames=REQUIRED_FIELDS)
        writer.writeheader()
        for log in valid_logs:
            writer.writerow(log)

    return len(valid_logs)

def aggregate_logs(input_dir: Optional[Path] = None, output_path: Optional[Path] = None) -> Dict[str, Any]:
    """
    Main aggregation function: load, normalize, validate, and write logs.
    """
    if input_dir is None:
        input_dir = DATA_DIR / 'temp' / 'simulation_logs'
    
    if output_path is None:
        output_path = OUTPUT_FILE

    logger.info(f"Starting log aggregation from {input_dir} to {output_path}")

    # Step 1: Load logs
    raw_logs = load_simulation_logs(input_dir)
    if not raw_logs:
        logger.error("No logs loaded. Aborting aggregation.")
        return {'status': 'error', 'message': 'No logs loaded', 'count': 0}

    # Step 2: Normalize fields
    normalized_logs = [normalize_log_fields(log) for log in raw_logs]
    logger.info(f"Normalized {len(normalized_logs)} log entries")

    # Step 3: Write to CSV (validates internally)
    count = write_simulation_logs_csv(normalized_logs, output_path)

    result = {
        'status': 'success',
        'input_directory': str(input_dir),
        'output_file': str(output_path),
        'total_loaded': len(raw_logs),
        'valid_count': count,
        'invalid_count': len(raw_logs) - count
    }

    logger.info(f"Aggregation complete. Valid: {count}, Invalid: {len(raw_logs) - count}")
    return result

def main():
    parser = argparse.ArgumentParser(description='Aggregate simulation logs into a single CSV file.')
    parser.add_argument('--input-dir', type=str, help='Directory containing individual simulation log JSON files')
    parser.add_argument('--output-path', type=str, help='Path for the output CSV file')
    
    args = parser.parse_args()

    input_dir = Path(args.input_dir) if args.input_dir else None
    output_path = Path(args.output_path) if args.output_path else None

    result = aggregate_logs(input_dir, output_path)
    
    if result['status'] == 'error':
        logger.error(f"Aggregation failed: {result['message']}")
        sys.exit(1)
    else:
        logger.info(f"Successfully aggregated {result['valid_count']} records.")
        sys.exit(0)

if __name__ == '__main__':
    main()