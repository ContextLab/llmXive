import os
import sys
import json
import logging
import argparse
import yaml
from typing import Dict, Any

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA_PILOT_DIR = os.path.join(PROJECT_ROOT, 'data', 'pilot')
CODE_SIMULATE_DIR = os.path.join(PROJECT_ROOT, 'code', 'simulate')
METRICS_PATH = os.path.join(DATA_PILOT_DIR, 'calibration_metrics.json')
PARAMS_PATH = os.path.join(CODE_SIMULATE_DIR, 'bkt_params.yaml')
REPORT_PATH = os.path.join(DATA_PILOT_DIR, 'update_report.json')

def load_metrics(path: str = METRICS_PATH) -> Dict[str, Any]:
    """
    Load calibration metrics from the JSON file generated by T032.
    Raises FileNotFoundError if the file is missing.
    """
    if not os.path.exists(path):
        raise FileNotFoundError(f"Metrics file not found at {path}. Ensure T032 has run.")
    with open(path, 'r') as f:
        return json.load(f)

def load_params(path: str = PARAMS_PATH) -> Dict[str, float]:
    """
    Load current BKT parameters from the YAML file.
    If missing, returns a warning and defaults, but T033 expects this to exist
    after T031/T032 calibration.
    """
    if not os.path.exists(path):
        logger.warning(f"Params file {path} not found. Using defaults.")
        return {"P_G": 0.1, "P_L0": 0.5, "P_S": 0.2, "P_T": 0.1}
    with open(path, 'r') as f:
        return yaml.safe_load(f)

def calculate_adjustment(metrics: Dict[str, Any], current_params: Dict[str, float]) -> Dict[str, float]:
    """
    Calculate parameter adjustments based on calibration metrics from T032.
    
    Logic:
    - If metrics passed (RMSE diff <= 0.02 and absolute RMSE <= 0.15), return current params.
    - If failed, apply heuristic adjustments:
      - High RMSE (> 0.15): Increase initial learning probability (P_L0).
      - Moderate RMSE (> 0.10): Adjust slip rate (P_S).
      - If RMSE diff is high, adjust guess (P_G) or transfer (P_T).
    
    This ensures the BKT model better aligns with the pilot data distribution.
    """
    new_params = current_params.copy()
    rmse = metrics.get('rmse', 0.0)
    rmse_diff = metrics.get('rmse_diff', 0.0)
    passed = metrics.get('passed', True)
    
    if passed:
        logger.info("Calibration metrics passed thresholds. No adjustment needed.")
        return new_params
    
    logger.warning("Calibration metrics failed thresholds. Applying heuristic adjustments.")
    
    # Heuristic adjustment logic based on specific failure modes
    if rmse > 0.15:
        # High absolute error: Increase initial learning probability
        # This suggests students learn faster than the model predicts initially
        adjustment = 0.05
        new_params['P_L0'] = min(0.9, current_params['P_L0'] + adjustment)
        logger.info(f"Adjusting P_L0 from {current_params['P_L0']} to {new_params['P_L0']} due to high RMSE ({rmse:.4f}).")
        
    elif rmse > 0.10:
        # Moderate error: Adjust slip rate
        # This suggests students are making careless mistakes
        adjustment = -0.02
        new_params['P_S'] = max(0.0, current_params['P_S'] + adjustment)
        logger.info(f"Adjusting P_S from {current_params['P_S']} to {new_params['P_S']} due to moderate RMSE ({rmse:.4f}).")
    
    if abs(rmse_diff) > 0.02:
        # Significant deviation from expected performance
        # Adjust guess rate if the model predicts too many correct guesses
        if rmse_diff > 0:
            # Model predicts better than reality -> reduce guess rate
            new_params['P_G'] = max(0.0, current_params['P_G'] - 0.01)
            logger.info(f"Adjusting P_G from {current_params['P_G']} to {new_params['P_G']} due to high RMSE diff ({rmse_diff:.4f}).")
        else:
            # Model predicts worse than reality -> increase transfer rate
            new_params['P_T'] = min(0.9, current_params['P_T'] + 0.01)
            logger.info(f"Adjusting P_T from {current_params['P_T']} to {new_params['P_T']} due to low RMSE diff ({rmse_diff:.4f}).")
    
    return new_params

def validate_params(params: Dict[str, float]) -> bool:
    """
    Ensure all parameters are valid probabilities between 0 and 1.
    Returns False if any parameter is out of bounds.
    """
    for k, v in params.items():
        if not (0.0 <= v <= 1.0):
            logger.error(f"Parameter {k} = {v} is out of bounds [0, 1].")
            return False
    return True

def save_params(params: Dict[str, float], path: str = PARAMS_PATH) -> None:
    """
    Save the updated parameters to the YAML file.
    Creates parent directories if they do not exist.
    """
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        yaml.dump(params, f, default_flow_style=False)
    logger.info(f"Saved updated BKT parameters to {path}")

def save_report(report: Dict[str, Any], path: str = REPORT_PATH) -> None:
    """
    Save a JSON report detailing the update process.
    """
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        json.dump(report, f, indent=2)
    logger.info(f"Saved update report to {path}")

def run_update():
    """
    Main execution logic for T033.
    1. Load metrics from T032.
    2. Load current BKT params.
    3. Calculate adjustments if metrics failed.
    4. Validate new params.
    5. Save updated params and report.
    """
    logger.info("Running BKT Params Update (T033)...")
    
    try:
        metrics = load_metrics()
        current_params = load_params()
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    
    new_params = calculate_adjustment(metrics, current_params)
    
    if not validate_params(new_params):
        logger.error("Parameter validation failed. Aborting update.")
        sys.exit(1)
    
    save_params(new_params)
    
    report = {
        "original_params": current_params,
        "updated_params": new_params,
        "metrics": metrics,
        "status": "completed",
        "timestamp": os.popen('date -u +"%Y-%m-%dT%H:%M:%SZ"').read().strip()
    }
    save_report(report)
    
    logger.info("BKT Params Update completed successfully.")
    return 0

def main():
    """
    Entry point for the script.
    """
    return run_update()

if __name__ == "__main__":
    sys.exit(main())
