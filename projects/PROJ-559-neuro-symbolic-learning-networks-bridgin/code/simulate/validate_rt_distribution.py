"""
Validate the response time distribution from dry-run simulation logs.

This script checks the "no consecutive empty bins > 5s" constraint (SC-005)
using histogram binning (1s width) on the dry-run logs.

It reads from data/derived/dryrun_logs.csv (generated by T021a) and writes
the validation result to data/derived/rt_distribution_validation.json.

If validation fails (more than 2 consecutive empty bins found), the script
exits with code 1 to block T021 from proceeding.
"""

import os
import sys
import json
import logging
import argparse
import pandas as pd
import numpy as np
from pathlib import Path

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Constants
INPUT_FILE = "data/derived/dryrun_logs.csv"
OUTPUT_FILE = "data/derived/rt_distribution_validation.json"
BIN_WIDTH = 1.0  # seconds
MAX_CONSECUTIVE_EMPTY = 2  # SC-005 constraint: no >2 consecutive empty bins

def load_simulation_logs(file_path: str) -> pd.DataFrame:
    """
    Load simulation logs from CSV.

    Args:
        file_path: Path to the CSV file containing simulation logs.

    Returns:
        DataFrame with simulation log records.

    Raises:
        FileNotFoundError: If the input file does not exist.
        ValueError: If required columns are missing.
    """
    if not os.path.exists(file_path):
        logger.error(f"Input file not found: {file_path}")
        raise FileNotFoundError(f"Input file not found: {file_path}")

    logger.info(f"Loading simulation logs from: {file_path}")
    df = pd.read_csv(file_path)

    required_columns = ['rt_seconds']
    missing_cols = [col for col in required_columns if col not in df.columns]
    if missing_cols:
        logger.error(f"Missing required columns: {missing_cols}")
        raise ValueError(f"Missing required columns: {missing_cols}")

    logger.info(f"Loaded {len(df)} records")
    return df

def validate_rt_distribution(df: pd.DataFrame) -> dict:
    """
    Validate response time distribution for SC-005 constraint.

    Algorithm:
    1. Create histogram bins with 1s width.
    2. Count records in each bin.
    3. Check for consecutive empty bins (count == 0).
    4. Fail if >2 consecutive empty bins are found.

    Args:
        df: DataFrame with 'rt_seconds' column.

    Returns:
        Dictionary with validation results.
    """
    rt_values = df['rt_seconds'].dropna()

    if len(rt_values) == 0:
        logger.warning("No valid response time values found.")
        return {
            "status": "fail",
            "reason": "No valid response time values",
            "consecutive_empty_bins": 0,
            "max_consecutive_allowed": MAX_CONSECUTIVE_EMPTY,
            "bin_width": BIN_WIDTH,
            "total_bins": 0,
            "empty_bins": 0
        }

    # Determine bin edges
    min_rt = rt_values.min()
    max_rt = rt_values.max()

    # Ensure we cover at least a reasonable range
    # Start from 0 or min_rt, end at max_rt + buffer
    start_bin = max(0.0, min_rt - BIN_WIDTH)
    end_bin = max_rt + BIN_WIDTH * 2

    # Create bins
    bins = np.arange(start_bin, end_bin + BIN_WIDTH, BIN_WIDTH)
    bin_counts, bin_edges = np.histogram(rt_values, bins=bins)

    # Identify empty bins
    empty_bin_indices = np.where(bin_counts == 0)[0]
    total_bins = len(bin_counts)
    empty_bins_count = len(empty_bin_indices)

    # Check for consecutive empty bins
    max_consecutive_found = 0
    current_consecutive = 0

    for i in range(len(bin_counts)):
        if bin_counts[i] == 0:
            current_consecutive += 1
            max_consecutive_found = max(max_consecutive_found, current_consecutive)
        else:
            current_consecutive = 0

    logger.info(f"Total bins: {total_bins}, Empty bins: {empty_bins_count}")
    logger.info(f"Max consecutive empty bins found: {max_consecutive_found}")

    passed = max_consecutive_found <= MAX_CONSECUTIVE_EMPTY

    return {
        "status": "pass" if passed else "fail",
        "reason": "Distribution meets SC-005 constraint" if passed else f"Found {max_consecutive_found} consecutive empty bins (max allowed: {MAX_CONSECUTIVE_EMPTY})",
        "consecutive_empty_bins": max_consecutive_found,
        "max_consecutive_allowed": MAX_CONSECUTIVE_EMPTY,
        "bin_width": BIN_WIDTH,
        "total_bins": total_bins,
        "empty_bins": empty_bins_count,
        "min_rt": float(min_rt),
        "max_rt": float(max_rt)
    }

def save_validation_report(report: dict, output_path: str):
    """
    Save validation report to JSON file.

    Args:
        report: Validation report dictionary.
        output_path: Path to output JSON file.
    """
    # Ensure output directory exists
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)

    logger.info(f"Validation report saved to: {output_path}")

def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="Validate response time distribution from simulation logs."
    )
    parser.add_argument(
        "--input",
        type=str,
        default=INPUT_FILE,
        help=f"Path to input CSV file (default: {INPUT_FILE})"
    )
    parser.add_argument(
        "--output",
        type=str,
        default=OUTPUT_FILE,
        help=f"Path to output JSON file (default: {OUTPUT_FILE})"
    )

    args = parser.parse_args()

    try:
        # Load data
        df = load_simulation_logs(args.input)

        # Validate distribution
        report = validate_rt_distribution(df)

        # Save report
        save_validation_report(report, args.output)

        # Exit with appropriate code
        if report["status"] == "pass":
            logger.info("Validation PASSED. Pipeline can proceed.")
            sys.exit(0)
        else:
            logger.error(f"Validation FAILED: {report['reason']}")
            logger.error("Pipeline blocked. Fix data generation or distribution before proceeding.")
            sys.exit(1)

    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()