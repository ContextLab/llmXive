"""
Compute empirical standard deviation of regression coefficients across resampled subsets.

This script reads the subset indices generated by T047 (artifacts/stability/subsets_*.json),
loads the corresponding regression results (generated by T024/T027), and computes the
standard deviation of each coefficient for each dataset and sample size tier.

Output: artifacts/stability/coefficient_sd.json
"""

import json
import os
import sys
from pathlib import Path
from typing import Dict, List, Any, Optional
import numpy as np
import pandas as pd

# Ensure project root is in path for imports if running as script
PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.utils.config import load_config
from src.utils.logger import get_logger

logger = get_logger(__name__)

def load_subset_indices(base_path: Path) -> Dict[str, List[Dict[str, Any]]]:
    """
    Load all subset index files from the artifacts/stability directory.
    Returns a dictionary keyed by dataset name, containing lists of subset metadata.
    """
    subsets_dir = base_path / "artifacts" / "stability"
    if not subsets_dir.exists():
        raise FileNotFoundError(f"Subsets directory not found: {subsets_dir}")

    all_subsets: Dict[str, List[Dict[str, Any]]] = {}

    for file_path in sorted(subsets_dir.glob("subsets_*.json")):
        logger.info(f"Loading subset indices from {file_path}")
        with open(file_path, 'r') as f:
            data = json.load(f)

        # Expected structure: {"dataset_name": [{"tier": float, "subset_id": int, "indices": [...]}, ...]}
        if isinstance(data, dict):
            for dataset_name, subsets in data.items():
                if dataset_name not in all_subsets:
                    all_subsets[dataset_name] = []
                all_subsets[dataset_name].extend(subsets)
        else:
            logger.warning(f"Unexpected format in {file_path}, skipping.")

    return all_subsets

def load_regression_results(base_path: Path, dataset_name: str, subset_id: int) -> Optional[Dict[str, float]]:
    """
    Load regression coefficients for a specific dataset and subset.
    Assumes results are stored in a structured format or aggregated file.
    For this implementation, we assume a consolidated results file exists from T024/T027.
    """
    results_file = base_path / "artifacts" / "stability" / f"results_{dataset_name}.json"
    if not results_file.exists():
        # Fallback: check for a generic consolidated file if naming convention differs
        results_file = base_path / "artifacts" / "stability" / "all_regression_results.json"

    if not results_file.exists():
        logger.error(f"Regression results file not found for {dataset_name}: {results_file}")
        return None

    try:
        with open(results_file, 'r') as f:
            data = json.load(f)

        # Look for the specific subset result
        # Expected structure: {"dataset_name": {subset_id: {"coefficients": {...}, ...}}}
        if dataset_name in data and str(subset_id) in data[dataset_name]:
            return data[dataset_name][str(subset_id)]
        elif dataset_name in data:
            # Try integer key
            if subset_id in data[dataset_name]:
                return data[dataset_name][subset_id]
        
        logger.warning(f"Subset {subset_id} not found in results for {dataset_name}")
        return None
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse results file {results_file}: {e}")
        return None

def compute_std_dev(coefficients_list: List[Dict[str, float]]) -> Dict[str, float]:
    """
    Compute standard deviation for each coefficient name across a list of coefficient dicts.
    """
    if not coefficients_list:
        return {}

    # Collect all unique coefficient names
    all_names = set()
    for coeffs in coefficients_list:
        all_names.update(coeffs.keys())

    std_devs = {}
    for name in all_names:
        values = [c[name] for c in coefficients_list if name in c]
        if len(values) < 2:
            std_devs[name] = float('nan')
        else:
            std_devs[name] = float(np.std(values, ddof=1)) # Sample standard deviation

    return std_devs

def main():
    logger.info("Starting T048: Compute Empirical Coefficient Standard Deviations")

    config = load_config()
    base_path = Path(config.get("project_root", "."))
    
    # Load subset indices generated by T047
    try:
        all_subsets = load_subset_indices(base_path)
    except FileNotFoundError as e:
        logger.critical(str(e))
        sys.exit(1)

    if not all_subsets:
        logger.warning("No subset indices found. Ensure T047 has been run successfully.")
        sys.exit(1)

    results_output: Dict[str, Dict[str, Dict[str, float]]] = {}

    for dataset_name, subsets in all_subsets.items():
        logger.info(f"Processing dataset: {dataset_name} ({len(subsets)} subsets)")
        
        # Group subsets by tier to compute SD per tier
        tier_groups: Dict[float, List[Dict[str, float]]] = {}

        for subset_meta in subsets:
            tier = subset_meta.get("tier")
            subset_id = subset_meta.get("subset_id")
            
            if tier is None or subset_id is None:
                logger.warning(f"Skipping subset in {dataset_name} due to missing tier or id: {subset_meta}")
                continue

            if tier not in tier_groups:
                tier_groups[tier] = []

            # Load regression coefficients for this subset
            coeffs_data = load_regression_results(base_path, dataset_name, subset_id)
            
            if coeffs_data is None:
                logger.warning(f"Could not load coefficients for {dataset_name}, subset {subset_id}. Skipping.")
                continue

            # Extract coefficients (assuming key 'coefficients' in the result dict)
            coefficients = coeffs_data.get("coefficients")
            if not coefficients:
                logger.warning(f"No 'coefficients' key in result for {dataset_name}, subset {subset_id}. Skipping.")
                continue

            tier_groups[tier].append(coefficients)

        # Compute SD for each tier
        dataset_results = {}
        for tier, coeff_list in sorted(tier_groups.items()):
            if len(coeff_list) == 0:
                logger.warning(f"No valid subsets found for tier {tier} in {dataset_name}.")
                continue
            
            std_devs = compute_std_dev(coeff_list)
            dataset_results[str(tier)] = std_devs
            logger.info(f"  Tier {tier}: Computed SD for {len(std_devs)} coefficients.")

        if dataset_results:
            results_output[dataset_name] = dataset_results

    # Write output
    output_path = base_path / "artifacts" / "stability" / "coefficient_sd.json"
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, 'w') as f:
        json.dump(results_output, f, indent=2, default=str)

    logger.info(f"T048 Complete. Results saved to {output_path}")
    print(f"Output written to {output_path}")

if __name__ == "__main__":
    main()