def test_renv_lock_is_valid_json(temp_project):
    """Test that renv.lock is valid JSON."""
    lockfile = temp_project / "renv.lock"
    
    # Try to parse the file as JSON
    try:
        with open(lockfile, "r") as f:
            data = json.load(f)
        assert isinstance(data, dict), "renv.lock should be a JSON object"
        assert "Packages" in data, "renv.lock should contain a 'Packages' section"
    except json.JSONDecodeError as e:
        pytest.fail(f"renv.lock is not valid JSON: {e}")


def test_renv_lock_records_package_versions(temp_project):
    """Test that renv.lock records required package versions."""
    lockfile = temp_project / "renv.lock"
    
    with open(lockfile, "r") as f:
        data = json.load(f)
    
    required_packages = ["DESeq2", "org.At.tair.db", "biomaRt", "sva", "GEOquery"]
    
    packages_section = data.get("Packages", {})
    
    for pkg_name in required_packages:
        assert pkg_name in packages_section, f"Package {pkg_name} should be recorded in renv.lock"
        
        pkg_info = packages_section[pkg_name]
        assert "Version" in pkg_info, f"Package {pkg_name} should have a version"
        assert "Source" in pkg_info, f"Package {pkg_name} should have a source"
        
        # Verify version is a non-empty string
        version = pkg_info["Version"]
        assert isinstance(version, str) and len(version) > 0, f"Version for {pkg_name} should be a non-empty string"
        
        # Verify source is appropriate (Bioconductor or CRAN)
        source = pkg_info["Source"]
        assert source in ["Bioconductor", "CRAN"], f"Source for {pkg_name} should be Bioconductor or CRAN"
