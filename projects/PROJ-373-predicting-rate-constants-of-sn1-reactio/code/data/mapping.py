"""
T011c: Map columns and clean initial data from raw SN1 datasets.

Logic:
1. Load raw data from data/raw/sn1_raw.parquet (produced by T011b).
2. Map columns: 'smiles' -> 'SMILES', 'rate' -> 'rate_constant'.
3. Identify rows with missing 'SMILES' or 'rate_constant'.
4. Log excluded rows to data/processed/exclusion_raw.log.
5. Save clean data to data/processed/intermediate_sn1.csv.
"""
import os
import sys
import logging
import argparse
import pandas as pd
from pathlib import Path

# Import config for paths
from config import DataConfig, ensure_dirs
from utils.logger import get_logger

def setup_mapping_logger() -> logging.Logger:
    """Setup logger for mapping task."""
    return get_logger("mapping", "data/processed/mapping.log")

def load_raw_data(logger: logging.Logger) -> pd.DataFrame:
    """
    Load raw data from the parquet file generated by T011b.
    
    Raises:
        FileNotFoundError: If the raw parquet file does not exist.
        ValueError: If the file is empty or unreadable.
    """
    config = DataConfig()
    input_path = config.raw_data_path / "sn1_raw.parquet"
    
    if not input_path.exists():
        logger.error(f"Raw data file not found: {input_path}")
        raise FileNotFoundError(f"Raw data file not found: {input_path}")
    
    try:
        df = pd.read_parquet(input_path)
        if df.empty:
            logger.error("Raw data file is empty.")
            raise ValueError("Raw data file is empty.")
        logger.info(f"Loaded raw data with {len(df)} rows from {input_path}")
        return df
    except Exception as e:
        logger.error(f"Failed to read raw data: {e}")
        raise

def map_columns(df: pd.DataFrame, logger: logging.Logger) -> pd.DataFrame:
    """
    Map source columns to standard schema names.
    
    Mapping:
    - 'smiles' -> 'SMILES'
    - 'rate' -> 'rate_constant'
    
    Note: Case-insensitive matching is attempted for robustness.
    """
    df = df.copy()
    df.columns = df.columns.str.lower()
    
    # Define mapping
    mapping = {
        'smiles': 'SMILES',
        'rate': 'rate_constant'
    }
    
    # Apply mapping if columns exist
    for src, dest in mapping.items():
        if src in df.columns:
            # Check if destination already exists to avoid collision
            if dest not in df.columns:
                df.rename(columns={src: dest}, inplace=True)
                logger.info(f"Mapped column '{src}' -> '{dest}'")
            else:
                logger.warning(f"Destination column '{dest}' already exists, skipping mapping for '{src}'")
        else:
            logger.warning(f"Source column '{src}' not found in dataset")
    
    # Ensure we have the required columns for the next step
    required_cols = ['SMILES', 'rate_constant']
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        logger.error(f"Missing required columns after mapping: {missing_cols}")
        # We do not raise here immediately; we will filter them out in the next step
        # but log the error.
    
    return df

def clean_and_log_exclusions(df: pd.DataFrame, logger: logging.Logger) -> tuple[pd.DataFrame, int]:
    """
    Filter out rows with missing SMILES or rate_constant.
    Log excluded rows to data/processed/exclusion_raw.log.
    
    Returns:
        tuple: (Cleaned DataFrame, count of excluded rows)
    """
    config = DataConfig()
    exclusion_log_path = config.processed_data_path / "exclusion_raw.log"
    
    # Identify rows to exclude
    # We look for rows where SMILES is NaN/None or rate_constant is NaN/None
    mask_valid = df['SMILES'].notna() & df['rate_constant'].notna()
    
    df_excluded = df[~mask_valid]
    df_cleaned = df[mask_valid]
    
    excluded_count = len(df_excluded)
    
    if excluded_count > 0:
        logger.info(f"Excluding {excluded_count} rows due to missing SMILES or rate_constant")
        
        # Log exclusions
        # Format: row_index, reason, original_smiles
        exclusion_records = []
        for idx, row in df_excluded.iterrows():
            reason = []
            if pd.isna(row.get('SMILES')):
                reason.append("missing_smiles")
            if pd.isna(row.get('rate_constant')):
                reason.append("missing_rate_constant")
            
            exclusion_records.append({
                'row_index': idx,
                'reason': "; ".join(reason),
                'original_smiles': row.get('SMILES', '')
            })
        
        exclusion_df = pd.DataFrame(exclusion_records)
        
        # Ensure directory exists
        exclusion_log_path.parent.mkdir(parents=True, exist_ok=True)
        
        # Write log (overwrite if exists, as this is a fresh run)
        exclusion_df.to_csv(exclusion_log_path, index=False)
        logger.info(f"Exclusion log written to {exclusion_log_path}")
    else:
        logger.info("No rows excluded for missing SMILES or rate_constant")
        # Create empty log file to satisfy downstream tasks that expect it
        exclusion_log_path.parent.mkdir(parents=True, exist_ok=True)
        pd.DataFrame(columns=['row_index', 'reason', 'original_smiles']).to_csv(exclusion_log_path, index=False)
    
    return df_cleaned, excluded_count

def save_intermediate_dataset(df: pd.DataFrame, logger: logging.Logger) -> Path:
    """
    Save the cleaned and mapped dataset to data/processed/intermediate_sn1.csv.
    
    Returns:
        Path: Path to the saved CSV file.
    """
    config = DataConfig()
    output_path = config.processed_data_path / "intermediate_sn1.csv"
    
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    df.to_csv(output_path, index=False)
    logger.info(f"Saved intermediate dataset to {output_path} with {len(df)} rows")
    
    return output_path

def main():
    """Main entry point for T011c."""
    logger = setup_mapping_logger()
    logger.info("Starting T011c: Mapping and cleaning initial data")
    
    try:
        # 1. Load raw data
        df_raw = load_raw_data(logger)
        
        # 2. Map columns
        df_mapped = map_columns(df_raw, logger)
        
        # 3. Clean and log exclusions
        df_cleaned, excluded_count = clean_and_log_exclusions(df_mapped, logger)
        
        # 4. Save intermediate dataset
        output_path = save_intermediate_dataset(df_cleaned, logger)
        
        logger.info(f"T011c completed successfully. Output: {output_path}")
        return 0
    
    except Exception as e:
        logger.error(f"T011c failed with error: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
