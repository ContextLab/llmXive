"""
T011c: Map columns and clean initial data from raw SN1 datasets.

Logic:
1. Load raw data from `data/raw/sn1_raw.parquet` (produced by T011b).
2. Map columns: 'smiles' -> 'SMILES', 'rate' -> 'rate_constant'.
3. Log rows with missing 'SMILES' or 'rate_constant' to `data/processed/exclusion_raw.log`.
4. Output the cleaned dataframe to `data/processed/intermediate_sn1.csv`.
"""
import os
import sys
import logging
import argparse
import pandas as pd
from pathlib import Path

# Import config for paths
from config import DataConfig, ensure_dirs
from utils.logger import get_logger

def load_raw_data(input_path: Path) -> pd.DataFrame:
    """
    Load the raw parquet file generated by the download task.
    """
    if not input_path.exists():
        raise FileNotFoundError(
            f"Raw data file not found at {input_path}. "
            "Ensure T011b (download.py) has completed successfully."
        )
    
    logger = get_logger("mapping")
    logger.info(f"Loading raw data from {input_path}")
    
    try:
        df = pd.read_parquet(input_path)
        logger.info(f"Loaded {len(df)} rows from {input_path}")
        return df
    except Exception as e:
        logger.error(f"Failed to load parquet file: {e}")
        raise

def map_columns(df: pd.DataFrame, log_path: Path) -> pd.DataFrame:
    """
    Map source columns to standardized names and log exclusions.
    
    Mapping:
    - 'smiles' -> 'SMILES'
    - 'rate' -> 'rate_constant'
    
    Exclusion criteria:
    - Missing 'SMILES'
    - Missing 'rate_constant'
    """
    logger = get_logger("mapping")
    logger.info("Starting column mapping and cleaning")
    
    # Ensure output directory exists
    log_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Initialize exclusion log
    exclusion_data = []
    
    # Map columns if they exist
    # Note: We handle potential case variations or missing columns gracefully
    # but strictly follow the mapping rule: smiles->SMILES, rate->rate_constant
    
    df = df.copy()
    
    # Check for source columns
    if 'smiles' in df.columns:
        df = df.rename(columns={'smiles': 'SMILES'})
    else:
        # If 'smiles' is missing, we might have 'SMILES' already or a different name.
        # For this task, we assume the raw data has 'smiles' as per T011b spec.
        # If it doesn't exist, we proceed and filter later based on presence.
        logger.warning("Column 'smiles' not found in raw data. Checking for existing 'SMILES'.")
        if 'SMILES' not in df.columns:
            logger.error("Neither 'smiles' nor 'SMILES' found. Cannot proceed with mapping.")
            raise ValueError("Required column 'smiles' (or 'SMILES') missing in raw data.")

    if 'rate' in df.columns:
        df = df.rename(columns={'rate': 'rate_constant'})
    else:
        logger.warning("Column 'rate' not found in raw data. Checking for existing 'rate_constant'.")
        if 'rate_constant' not in df.columns:
            logger.error("Neither 'rate' nor 'rate_constant' found. Cannot proceed with mapping.")
            raise ValueError("Required column 'rate' (or 'rate_constant') missing in raw data.")

    # Identify rows with missing critical data
    initial_count = len(df)
    mask_missing_smiles = df['SMILES'].isna() | (df['SMILES'].astype(str).str.strip() == '')
    mask_missing_rate = df['rate_constant'].isna()
    
    # Combine masks for exclusion
    mask_exclude = mask_missing_smiles | mask_missing_rate
    
    excluded_count = mask_exclude.sum()
    
    if excluded_count > 0:
        logger.warning(f"Found {excluded_count} rows with missing SMILES or rate_constant.")
        
        # Log exclusions
        excluded_df = df[mask_exclude].copy()
        excluded_df['exclusion_reason'] = 'missing_smiles_or_rate'
        excluded_df['original_index'] = excluded_df.index
        
        # Prepare log entries
        for idx, row in excluded_df.iterrows():
            exclusion_data.append({
                'row_index': int(row['original_index']),
                'reason': 'missing_smiles_or_rate',
                'original_smiles': str(row['SMILES']) if pd.notna(row['SMILES']) else 'N/A'
            })
    else:
        logger.info("No rows excluded due to missing SMILES or rate_constant.")
    
    # Filter out invalid rows
    df_clean = df[~mask_exclude].reset_index(drop=True)
    
    # Write exclusion log
    if exclusion_data:
        exclusion_df = pd.DataFrame(exclusion_data)
        exclusion_df.to_csv(log_path, index=False)
        logger.info(f"Wrote {len(exclusion_data)} exclusion entries to {log_path}")
    else:
        # Write empty log with headers if no exclusions, to maintain schema consistency
        pd.DataFrame(columns=['row_index', 'reason', 'original_smiles']).to_csv(log_path, index=False)
        logger.info(f"Created empty exclusion log at {log_path}")
    
    logger.info(f"Mapping complete. Output shape: {df_clean.shape}")
    return df_clean

def main():
    """
    Main entry point for T011c.
    """
    parser = argparse.ArgumentParser(description="Map columns and clean initial SN1 data")
    parser.add_argument("--input", type=str, default=None, help="Path to raw parquet file")
    parser.add_argument("--output", type=str, default=None, help="Path to output CSV")
    parser.add_argument("--log", type=str, default=None, help="Path to exclusion log")
    args = parser.parse_args()
    
    config = DataConfig()
    ensure_dirs()
    
    # Determine paths
    input_path = Path(args.input) if args.input else config.raw_data_path
    output_path = Path(args.output) if args.output else config.intermediate_csv_path
    log_path = Path(args.log) if args.log else config.exclusion_raw_log_path
    
    logger = get_logger("mapping")
    logger.info(f"Starting mapping pipeline. Input: {input_path}, Output: {output_path}")
    
    try:
        # 1. Load raw data
        df = load_raw_data(input_path)
        
        # 2. Map columns and log exclusions
        df_clean = map_columns(df, log_path)
        
        # 3. Save intermediate dataset
        output_path.parent.mkdir(parents=True, exist_ok=True)
        df_clean.to_csv(output_path, index=False)
        
        logger.info(f"Successfully wrote intermediate dataset to {output_path}")
        logger.info("Mapping task completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during mapping: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()