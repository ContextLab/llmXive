def load_json_file(path, logger):
    try:
        with open(path, 'r') as f:
            return json.load(f)
    except FileNotFoundError:
        logger.error(f"File not found: {path}")
        return None
    except json.JSONDecodeError as e:
        logger.error(f"JSON decode error in {path}: {e}")
        return None

def load_csv_file(path, logger):
    try:
        with open(path, 'r') as f:
            reader = csv.DictReader(f)
            return list(reader)
    except FileNotFoundError:
        logger.error(f"File not found: {path}")
        return []
    except Exception as e:
        logger.error(f"Error reading CSV {path}: {e}")
        return []

def load_md_file(path, logger):
    try:
        with open(path, 'r') as f:
            return f.read()
    except FileNotFoundError:
        logger.error(f"File not found: {path}")
        return None
    except Exception as e:
        logger.error(f"Error reading MD {path}: {e}")
        return None

def evaluate_sc001(metrics_json, logger):
    """
    SC-001: MPNN R2 - Linear R2 > 0.05 AND p < 0.05
    Source: artifacts/sc-001_status.json (generated by T022)
    Fallback: If missing, try to derive from metrics.json if available.
    """
    sc001_path = "artifacts/sc-001_status.json"
    if os.path.exists(sc001_path):
        data = load_json_file(sc001_path, logger)
        if data and data.get('status') == 'PASS':
            return True, "PASS (from sc-001_status.json)"
        elif data:
            return False, f"FAIL (delta={data.get('delta_r2')}, p={data.get('p_value')})"
    
    # Fallback check in metrics.json if sc-001_status.json is missing
    if metrics_json:
        delta = metrics_json.get('mpnn_r2', 0) - metrics_json.get('linear_r2', 0)
        p_val = metrics_json.get('bootstrap_p_value', 1.0)
        if delta > 0.05 and p_val < 0.05:
            return True, "PASS (derived from metrics.json)"
        else:
            return False, f"FAIL (delta={delta:.3f}, p={p_val:.3f})"
    
    return False, "FAIL (missing data)"

