def evaluate_sc003(sensitivity_csv, logger):
    """
    SC-003: variance < 0.01 (in descriptor sensitivity)
    Source: artifacts/descriptor_sensitivity_report.csv (generated by T029A)
    """
    if not sensitivity_csv:
        return False, "FAIL (missing sensitivity report)"
    
    # Look for a row indicating overall variance or calculate from R2 values
    # Assuming the CSV has a row 'overall' or similar with variance
    variance = None
    for row in sensitivity_csv:
        if 'variance' in row:
            try:
                variance = float(row['variance'])
                break
            except ValueError:
                pass
        # Check for specific column name if 'variance' isn't key
        for k, v in row.items():
            if 'variance' in k.lower():
                try:
                    variance = float(v)
                    break
                except ValueError:
                    pass
        if variance is not None:
            break
    
    if variance is None:
        # Try to calculate variance from R2 column if present
        r2_values = []
        for row in sensitivity_csv:
            if 'r2' in row:
                try:
                    r2_values.append(float(row['r2']))
                except ValueError:
                    pass
        if len(r2_values) > 1:
            mean_r2 = sum(r2_values) / len(r2_values)
            variance = sum((x - mean_r2) ** 2 for x in r2_values) / len(r2_values)
        else:
            return False, "FAIL (insufficient data to calculate variance)"
    
    if variance < 0.01:
        return True, f"PASS (variance={variance:.4f})"
    return False, f"FAIL (variance={variance:.4f} >= 0.01)"

