def generate_limitations_section(logger):
    """
    Generate a limitations section based on potential issues found in the data or model.
    """
    limitations = []
    limitations.append("### Limitations")
    limitations.append("")
    limitations.append("1. **Data Scarcity**: The SN1 kinetic dataset size is limited compared to general organic reaction databases, which may affect the generalizability of the model to rare substrate classes.")
    limitations.append("2. **Descriptor Approximation**: Gasteiger charges are used as a CPU-tractable substitute for PM7 calculations. While efficient, they may not capture subtle electronic effects as accurately as DFT-based methods.")
    limitations.append("3. **Stereochemistry**: The pipeline standardizes SMILES but may lose specific stereochemical information if the input data contains ambiguous or non-standard representations.")
    limitations.append("4. **Solvent Effects**: The current model focuses on substrate structure. Explicit solvent effects are not fully parameterized, which could limit accuracy for reactions highly sensitive to solvent polarity.")
    limitations.append("5. **Computational Budget**: The hyperparameter search is bounded to ensure CPU-only feasibility, potentially missing optimal configurations available with more extensive search.")
    return "\n".join(limitations)

