import os
import sys
import json
import logging
import argparse
import csv
from pathlib import Path
from typing import List, Dict, Any, Optional

from utils.logger import setup_logging, get_logger
from config import TrainingConfig, DataConfig, AnalysisConfig, ensure_dirs

def setup_logging(output_path: str) -> logging.Logger:
    """Setup logging for the hyperparameter logging script."""
    log_dir = os.path.dirname(output_path)
    if log_dir:
        os.makedirs(log_dir, exist_ok=True)
    return setup_logging(log_level=logging.INFO, log_file=os.path.join(log_dir, "hyperparameter_search.log"))

def load_hyperparameter_log(json_path: str) -> List[Dict[str, Any]]:
    """
    Load the hyperparameter search results from the JSON file generated by T021/T020.
    Expected format: List of dicts with keys like 'config_id', 'learning_rate', 'hidden_dim', 'dropout', 'r2_val', 'mae_val'.
    """
    path = Path(json_path)
    if not path.exists():
        raise FileNotFoundError(f"Hyperparameter log file not found: {json_path}")
    
    with open(path, 'r') as f:
        data = json.load(f)
    
    if not isinstance(data, list):
        raise ValueError(f"Expected a list of results in {json_path}, got {type(data)}")
    
    return data

def format_hyperparameter_entry(entry: Dict[str, Any]) -> Dict[str, Any]:
    """
    Ensure the entry has the correct keys and types for the CSV output.
    Maps internal keys to the required CSV columns: config_id, learning_rate, hidden_dim, dropout, r2_val, mae_val.
    """
    # Map potential key variations to standard names
    config_id = entry.get('config_id', entry.get('id', 0))
    learning_rate = entry.get('learning_rate', entry.get('lr', 0.0))
    hidden_dim = entry.get('hidden_dim', entry.get('hidden_size', 128))
    dropout = entry.get('dropout', entry.get('drop', 0.0))
    r2_val = entry.get('r2_val', entry.get('val_r2', 0.0))
    mae_val = entry.get('mae_val', entry.get('val_mae', 0.0))

    return {
        "config_id": int(config_id),
        "learning_rate": float(learning_rate),
        "hidden_dim": int(hidden_dim),
        "dropout": float(dropout),
        "r2_val": float(r2_val),
        "mae_val": float(mae_val)
    }

def generate_hyperparameter_log(
    results: List[Dict[str, Any]], 
    output_path: str, 
    top_n: int = 10
) -> None:
    """
    Filter the top N configurations based on validation R² and save to CSV.
    
    Args:
        results: List of hyperparameter search results.
        output_path: Path to save the CSV file.
        top_n: Number of top configurations to keep.
    """
    if not results:
        logging.warning("No hyperparameter results found. Creating empty CSV.")
        # Create header only if no results
        with open(output_path, 'w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=["config_id", "learning_rate", "hidden_dim", "dropout", "r2_val", "mae_val"])
            writer.writeheader()
        return

    # Sort by validation R² descending
    sorted_results = sorted(results, key=lambda x: x.get('r2_val', x.get('val_r2', 0.0)), reverse=True)
    
    # Take top N
    top_results = sorted_results[:top_n]
    
    # Format entries
    formatted_results = [format_hyperparameter_entry(r) for r in top_results]
    
    # Write to CSV
    output_dir = os.path.dirname(output_path)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)
    
    fieldnames = ["config_id", "learning_rate", "hidden_dim", "dropout", "r2_val", "mae_val"]
    
    with open(output_path, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for entry in formatted_results:
            writer.writerow(entry)
    
    logging.info(f"Saved top {len(formatted_results)} hyperparameter configurations to {output_path}")

def run_hyperparameter_logging(
    input_json_path: str, 
    output_csv_path: str, 
    top_n: int = 10
) -> None:
    """
    Main orchestration function to load results and generate the CSV log.
    """
    logger = get_logger()
    logger.info(f"Loading hyperparameter results from {input_json_path}")
    
    try:
        results = load_hyperparameter_log(input_json_path)
    except (FileNotFoundError, json.JSONDecodeError, ValueError) as e:
        logger.error(f"Failed to load hyperparameter results: {e}")
        raise
    
    logger.info(f"Found {len(results)} configurations. Selecting top {top_n}.")
    
    generate_hyperparameter_log(results, output_csv_path, top_n)
    
    # Verify output
    if not os.path.exists(output_csv_path):
        raise RuntimeError(f"Output file {output_csv_path} was not created.")
    
    if os.path.getsize(output_csv_path) == 0:
        # It's okay if it's just headers, but we expect data if results existed
        if len(results) > 0:
            logger.warning(f"Output file {output_csv_path} is empty despite having input results.")
        else:
            logger.info("Output file is empty as expected (no input results).")

def main():
    parser = argparse.ArgumentParser(description="Log top hyperparameter configurations to CSV.")
    parser.add_argument(
        "--input-json", 
        type=str, 
        default="artifacts/hyperparameter_search_results.json",
        help="Path to the JSON file containing hyperparameter search results."
    )
    parser.add_argument(
        "--output-csv", 
        type=str, 
        default="artifacts/hyperparameter_search.csv",
        help="Path to save the top hyperparameter configurations CSV."
    )
    parser.add_argument(
        "--top-n", 
        type=int, 
        default=10,
        help="Number of top configurations to save."
    )
    
    args = parser.parse_args()
    
    # Setup logging
    logger = setup_logging(os.path.dirname(args.output_csv))
    
    try:
        run_hyperparameter_logging(args.input_json, args.output_csv, args.top_n)
        logger.info("Hyperparameter logging completed successfully.")
    except Exception as e:
        logger.error(f"Hyperparameter logging failed: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()