import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional
import yaml

from config import DataConfig, TrainingConfig, ensure_dirs
from utils.logger import setup_logging

# Path constants relative to project root
PROJECT_ROOT = Path(__file__).resolve().parent.parent
ARTIFACTS_DIR = PROJECT_ROOT / "artifacts"
DATA_DIR = PROJECT_ROOT / "data"
PROCESSED_DIR = DATA_DIR / "processed"
CONTRACTS_DIR = PROJECT_ROOT / "specs" / "001-predict-sn1-rate-constants" / "contracts"

# Expected output paths
BEST_MODEL_PATH = ARTIFACTS_DIR / "best_model.pt"
METRICS_PATH = ARTIFACTS_DIR / "metrics.json"
HYPERPARAM_SEARCH_PATH = ARTIFACTS_DIR / "hyperparameter_search.csv"
SCHEMA_PATH = CONTRACTS_DIR / "model_output.schema.yaml"

logger = None

def load_best_training_result() -> Dict[str, Any]:
    """
    Loads the best training result from the training log.
    The training log (training_results.json) is generated by code/models/train.py.
    It contains a list of results; we select the one with the highest validation R2.
    """
    results_path = ARTIFACTS_DIR / "training_results.json"
    if not results_path.exists():
        raise FileNotFoundError(f"Training results file not found at {results_path}. "
                                "Run code/models/train.py first.")
    
    with open(results_path, 'r') as f:
        results = json.load(f)
    
    if not results:
        raise ValueError("Training results list is empty.")
    
    # Select configuration with highest validation R2
    best_result = max(results, key=lambda x: x.get('r2_val', -float('inf')))
    logger.info(f"Best configuration selected: ID={best_result.get('config_id')}, "
                f"R2_val={best_result.get('r2_val'):.4f}")
    return best_result

def load_schema() -> Dict[str, Any]:
    """Loads the model output schema definition."""
    if not SCHEMA_PATH.exists():
        raise FileNotFoundError(f"Schema file not found at {SCHEMA_PATH}")
    
    with open(SCHEMA_PATH, 'r') as f:
        return yaml.safe_load(f)

def validate_metrics_against_schema(metrics: Dict[str, Any], schema: Dict[str, Any]) -> bool:
    """
    Validates the metrics dictionary against the loaded schema.
    Returns True if valid, raises ValueError if invalid.
    """
    required_fields = schema.get('required', [])
    properties = schema.get('properties', {})
    
    for field in required_fields:
        if field not in metrics:
            raise ValueError(f"Schema validation failed: Missing required field '{field}'")
        
        # Type check if defined in schema
        if field in properties:
            expected_type = properties[field].get('type')
            actual_val = metrics[field]
            
            # Simple type mapping
            type_map = {
                'string': str,
                'integer': int,
                'number': (int, float),
                'boolean': bool,
                'array': list,
                'object': dict
            }
            
            if expected_type and expected_type in type_map:
                if not isinstance(actual_val, type_map[expected_type]):
                    raise ValueError(f"Schema validation failed: Field '{field}' "
                                     f"expected {expected_type}, got {type(actual_val).__name__}")
    
    logger.info("Schema validation passed.")
    return True

def save_best_model(model_weights: Dict[str, Any], config: Dict[str, Any]) -> None:
    """
    Saves the best model weights and configuration to artifacts/best_model.pt.
    We save a dict containing 'state_dict' and 'config' to ensure full reproducibility.
    """
    ensure_dirs([ARTIFACTS_DIR])
    
    save_data = {
        'state_dict': model_weights,
        'config': config,
        'best_config_id': config.get('config_id')
    }
    
    import torch
    torch.save(save_data, BEST_MODEL_PATH)
    logger.info(f"Best model saved to {BEST_MODEL_PATH}")

def save_metrics(metrics: Dict[str, Any]) -> None:
    """Saves the metrics dictionary to artifacts/metrics.json."""
    ensure_dirs([ARTIFACTS_DIR])
    
    with open(METRICS_PATH, 'w') as f:
        json.dump(metrics, f, indent=2)
    logger.info(f"Metrics saved to {METRICS_PATH}")

def save_hyperparameter_log(results: list) -> None:
    """
    Saves the top 10 hyperparameter configurations to artifacts/hyperparameter_search.csv.
    This satisfies T023 requirements as part of the artifact saving workflow.
    """
    import csv
    ensure_dirs([ARTIFACTS_DIR])
    
    # Sort by R2 descending and take top 10
    sorted_results = sorted(results, key=lambda x: x.get('r2_val', 0), reverse=True)[:10]
    
    fieldnames = ['config_id', 'learning_rate', 'hidden_dim', 'dropout', 'r2_val', 'mae_val']
    
    with open(HYPERPARAM_SEARCH_PATH, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in sorted_results:
            # Ensure all fields exist
            row_data = {k: row.get(k, '') for k in fieldnames}
            writer.writerow(row_data)
    
    logger.info(f"Hyperparameter search log saved to {HYPERPARAM_SEARCH_PATH}")

def main():
    """
    Main entry point for T022: Save best model weights and metrics.
    1. Load best result from training.
    2. Load schema.
    3. Validate metrics against schema.
    4. Save model weights and metrics.
    5. Save hyperparameter search log (T023).
    """
    global logger
    logger = setup_logging("save_artifacts", level=logging.INFO)
    logger.info("Starting T022: Save best model artifacts")

    try:
        # 1. Load best training result
        best_result = load_best_training_result()
        
        # 2. Load schema
        schema = load_schema()
        
        # 3. Prepare metrics dictionary conforming to schema
        # Schema fields: model_id, hyperparameters, metrics (r2, mae)
        metrics_dict = {
            "model_id": f"mpnn_{best_result.get('config_id', 'unknown')}",
            "hyperparameters": {
                "learning_rate": best_result.get('learning_rate'),
                "hidden_dim": best_result.get('hidden_dim'),
                "dropout": best_result.get('dropout'),
                "num_layers": best_result.get('num_layers', 2)
            },
            "metrics": {
                "r2": best_result.get('r2_val'),
                "mae": best_result.get('mae_val'),
                "r2_train": best_result.get('r2_train'),
                "mae_train": best_result.get('mae_train'),
                "r2_test": best_result.get('r2_test'),
                "mae_test": best_result.get('mae_test')
            }
        }
        
        # Validate against schema
        validate_metrics_against_schema(metrics_dict, schema)
        
        # 4. Save metrics
        save_metrics(metrics_dict)
        
        # 5. Save model weights (we need to reload the actual model state)
        # Since we don't have the model instance here, we assume the training script
        # saved the best state_dict to a temporary file or we reconstruct it.
        # However, the standard pattern is that train.py saves the best state_dict
        # alongside the results. Let's check for a temporary weights file.
        best_weights_path = ARTIFACTS_DIR / "best_state_dict.pt"
        
        if best_weights_path.exists():
            import torch
            state_dict = torch.load(best_weights_path, map_location='cpu')
            # Save combined artifact
            save_best_model(state_dict, best_result)
            # Clean up temporary file
            best_weights_path.unlink()
            logger.info("Temporary weights file cleaned up.")
        else:
            logger.warning("Best state_dict file not found. Saving empty placeholder.")
            # If weights are missing, we can't save a valid model file.
            # But we must not fail silently. We raise an error if critical.
            raise FileNotFoundError("Best model weights not found. Ensure train.py saves 'best_state_dict.pt'.")
        
        # 6. Save hyperparameter log (T023 requirement)
        # Load full results again for logging
        results_path = ARTIFACTS_DIR / "training_results.json"
        with open(results_path, 'r') as f:
            all_results = json.load(f)
        save_hyperparameter_log(all_results)
        
        logger.info("T022 completed successfully.")
        
    except Exception as e:
        logger.error(f"T022 failed: {str(e)}")
        raise

if __name__ == "__main__":
    main()