"""
Verification script for the directory‑setup manifest generated by
``code.utils.setup_dirs`` (T001a).

The script loads ``data/processed/setup_dirs_verified.json`` and checks that
an entry exists for every directory listed in ``code.utils.setup_dirs.REQUIRED_DIRS``.
If any required directory is missing from the manifest, a ``RuntimeError`` is raised.
"""

import json
from pathlib import Path

from llmxive_toolkit import paths, get_logger

from code.utils.setup_dirs import REQUIRED_DIRS

log = get_logger(__name__)

def load_manifest() -> list[dict]:
    """
    Load the JSON manifest produced by ``setup_dirs``.
    """
    manifest_path = paths.data("processed", "setup_dirs_verified.json")
    if not manifest_path.is_file():
        raise RuntimeError(f"Manifest file not found: {manifest_path}")
    with manifest_path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    if not isinstance(data, list):
        raise RuntimeError("Manifest JSON is not a list")
    return data

def verify_manifest() -> None:
    """
    Verify that the manifest contains an entry for each required directory.
    """
    manifest = load_manifest()
    manifest_paths = {entry.get("path") for entry in manifest if isinstance(entry, dict)}
    missing = []
    for req_dir in REQUIRED_DIRS:
        abs_path = str(req_dir.resolve())
        if abs_path not in manifest_paths:
            missing.append(abs_path)
    if missing:
        raise RuntimeError(f"Missing directories in manifest: {missing}")
    log.info("All required directories verified in manifest.")

def main() -> None:
    """
    Entry point for the verification script.
    """
    log.info("Running setup verification...")
    verify_manifest()
    log.info("Verification completed successfully.")

if __name__ == "__main__":
    main()
