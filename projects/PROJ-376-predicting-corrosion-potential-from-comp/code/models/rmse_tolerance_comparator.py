"""
T023b: Implement RMSE calculation in millivolts (mV) and compare against ASTM G59 tolerance.

This module loads model results, converts RMSE to mV, and compares against the
tolerance defined in config/astm_g59_tolerance.yaml. It enforces SC-002:
if the standard does not define a specific value, the pipeline MUST halt.
"""

import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional, Tuple

# Import from project API surface
from utils.astm_g59_parser import load_astm_tolerance_config, get_tolerance_value
from utils.logging import get_logger
from utils.exceptions import DataInsufficientError

# Ensure the code/models directory is in the path for relative imports if run as script
# This is handled by the runner, but good practice for local execution
if 'code' not in sys.path:
    code_path = Path(__file__).resolve().parent.parent
    if code_path not in sys.path:
        sys.path.insert(0, str(code_path))

logger = get_logger(__name__)

def load_model_results(results_path: Path) -> Dict[str, Any]:
    """
    Load the model results JSON file generated by evaluate.py.

    Args:
        results_path: Path to the model_results.json file.

    Returns:
        Dictionary containing model metrics including RMSE.

    Raises:
        FileNotFoundError: If the results file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    if not results_path.exists():
        raise FileNotFoundError(f"Model results file not found at {results_path}")

    with open(results_path, 'r') as f:
        return json.load(f)

def convert_rmse_to_mv(rmse_volts: float) -> float:
    """
    Convert RMSE from Volts to millivolts (mV).

    Args:
        rmse_volts: RMSE value in Volts.

    Returns:
        RMSE value in millivolts.
    """
    return rmse_volts * 1000.0

def compare_rmse_against_tolerance(
    rmse_mv: float,
    tolerance_mv: float,
    model_name: str
) -> Dict[str, Any]:
    """
    Compare the RMSE against the ASTM G59 tolerance.

    Args:
        rmse_mv: The calculated RMSE in millivolts.
        tolerance_mv: The tolerance value from ASTM G59 in millivolts.
        model_name: Name of the model being evaluated.

    Returns:
        Dictionary containing the comparison result.
    """
    is_within_tolerance = rmse_mv <= tolerance_mv
    difference = rmse_mv - tolerance_mv

    return {
        "model_name": model_name,
        "rmse_mv": rmse_mv,
        "tolerance_mv": tolerance_mv,
        "is_within_tolerance": is_within_tolerance,
        "difference_mv": difference,
        "status": "PASS" if is_within_tolerance else "FAIL"
    }

def main():
    """
    Main entry point for the RMSE tolerance comparison task.

    1. Loads model results from data/processed/model_results.json.
    2. Loads ASTM G59 tolerance from config/astm_g59_tolerance.yaml.
    3. Converts RMSE to mV.
    4. Compares against tolerance.
    5. Prints the report.
    """
    # Define paths relative to project root
    project_root = Path(__file__).resolve().parent.parent.parent
    results_path = project_root / "data" / "processed" / "model_results.json"
    config_path = project_root / "config" / "astm_g59_tolerance.yaml"

    logger.info(f"Starting RMSE tolerance comparison. Results: {results_path}, Config: {config_path}")

    # 1. Load model results
    try:
        results = load_model_results(results_path)
        logger.info("Successfully loaded model results.")
    except FileNotFoundError as e:
        logger.error(f"Failed to load model results: {e}")
        raise
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in model results: {e}")
        raise

    # 2. Load tolerance configuration
    # This function will raise DataInsufficientError if the config is missing or invalid
    try:
        tolerance_config = load_astm_tolerance_config(config_path)
        tolerance_mv = get_tolerance_value(tolerance_config)
        logger.info(f"Loaded ASTM G59 tolerance: {tolerance_mv} mV")
    except DataInsufficientError as e:
        logger.error(f"Tolerance configuration error (SC-002): {e}")
        raise
    except FileNotFoundError as e:
        logger.error(f"Tolerance config file not found: {e}")
        raise

    # 3 & 4. Process each model result
    comparison_results = []

    if "models" not in results:
        raise KeyError("Model results JSON must contain a 'models' key.")

    for model_name, model_data in results["models"].items():
        if "rmse_volts" not in model_data:
            logger.warning(f"Skipping {model_name}: 'rmse_volts' not found in results.")
            continue

        rmse_volts = model_data["rmse_volts"]
        rmse_mv = convert_rmse_to_mv(rmse_volts)

        comparison = compare_rmse_against_tolerance(rmse_mv, tolerance_mv, model_name)
        comparison_results.append(comparison)

        logger.info(
            f"Model: {model_name} | RMSE: {rmse_mv:.2f} mV | "
            f"Tolerance: {tolerance_mv:.2f} mV | Status: {comparison['status']}"
        )

    # 5. Output final report
    report = {
        "tolerance_source": tolerance_config.get("source", "Unknown"),
        "tolerance_value_mv": tolerance_mv,
        "comparisons": comparison_results,
        "overall_status": "PASS" if all(c["is_within_tolerance"] for c in comparison_results) else "FAIL"
    }

    print(json.dumps(report, indent=2))
    logger.info("Comparison report generated.")

    return report

if __name__ == "__main__":
    main()
