def generate_run_id() -> str:
    """Generate a unique run ID based on timestamp and hash."""
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    random_hash = hashlib.sha256(os.urandom(32)).hexdigest()[:8]
    return f"{timestamp}_{random_hash}"

def load_projected_metrics(run_id: str) -> Dict[str, Any]:
    """
    Load projected embeddings/metrics from the conditioned pipeline output.
    This function expects the conditioned metrics to be stored in a specific location
    based on the run_id from the conditioned pipeline (T025).
    """
    # The conditioned pipeline (T025) should have produced metrics per dataset.
    # We assume they are stored in data/processed/conditioned_metrics_{run_id}.json
    # or a similar structure. We'll look for the aggregated metrics file first.
    
    # Path to the conditioned metrics file generated by T025
    metrics_file = Path("data/processed/conditioned_metrics") / f"metrics_{run_id}.json"
    
    if not metrics_file.exists():
        # Try alternative location
        alt_metrics_file = Path(f"data/processed/conditioned_metrics_{run_id}.json")
        if alt_metrics_file.exists():
            metrics_file = alt_metrics_file
        else:
            # Try to load from a directory of per-dataset files
            dir_path = Path("data/processed/conditioned_metrics")
            if dir_path.exists():
                # Aggregate all JSON files in the directory
                all_metrics = {}
                for file in dir_path.glob("*.json"):
                    try:
                        with open(file, 'r') as f:
                            data = json.load(f)
                            if isinstance(data, dict):
                                all_metrics.update(data)
                    except Exception as e:
                        log_warning(f"Failed to load {file}: {e}")
                if all_metrics:
                    return all_metrics
            
            raise FileNotFoundError(
                f"Could not find conditioned metrics for run_id={run_id}. "
                f"Expected at {metrics_file} or in {dir_path}"
            )
    
    with open(metrics_file, 'r') as f:
        return json.load(f)

def aggregate_conditioned_metrics(metrics: Dict[str, Any], run_id: str) -> Dict[str, Any]:
    """
    Aggregate conditioned metrics from all datasets into a single structure.
    Ensures run_id linkage is present in the output.
    """
    aggregated = {
        "run_id": run_id,
        "generated_at": datetime.now().isoformat(),
        "pipeline": "US2_Conditioned_Projection",
        "datasets": {},
        "summary": {}
    }
    
    total_datasets = 0
    successful_datasets = 0
    metrics_summaries = {}
    
    for dataset_id, dataset_metrics in metrics.items():
        total_datasets += 1
        if isinstance(dataset_metrics, dict):
            aggregated["datasets"][dataset_id] = dataset_metrics
            successful_datasets += 1
            
            # Aggregate specific metric types for summary
            for metric_name, metric_value in dataset_metrics.items():
                if isinstance(metric_value, (int, float)):
                    if metric_name not in metrics_summaries:
                        metrics_summaries[metric_name] = []
                    metrics_summaries[metric_name].append(metric_value)
    
    # Compute summary statistics
    for metric_name, values in metrics_summaries.items():
        if values:
            aggregated["summary"][metric_name] = {
                "mean": sum(values) / len(values),
                "min": min(values),
                "max": max(values),
                "count": len(values),
                "datasets_processed": successful_datasets
            }
    
    aggregated["summary"]["total_datasets"] = total_datasets
    aggregated["summary"]["successful_datasets"] = successful_datasets
    aggregated["summary"]["success_rate"] = successful_datasets / total_datasets if total_datasets > 0 else 0.0
    
    return aggregated

def save_aggregated_metrics(aggregated_metrics: Dict[str, Any], output_path: Path) -> None:
    """Save the aggregated metrics to a JSON file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(aggregated_metrics, f, indent=2)
    
    log_info(f"Saved aggregated conditioned metrics to {output_path}")

def main():
    """
    Main entry point for T028: Store results in data/artifacts/metrics_conditioned_{run_id}.json
    with run_id linkage.
    
    This script:
    1. Loads conditioned metrics from the US2 pipeline (T025)
    2. Aggregates them across all datasets
    3. Saves the aggregated results with run_id linkage to data/artifacts/
    """
    # Parse arguments
    import argparse
    parser = argparse.ArgumentParser(description="Save conditioned metrics with run_id linkage")
    parser.add_argument("--run_id", type=str, required=True, help="Run ID to process")
    parser.add_argument("--output_dir", type=str, default="data/artifacts", help="Output directory")
    args = parser.parse_args()
    
    # Setup logging
    log_dir = Path("logs")
    log_dir.mkdir(exist_ok=True)
    setup_logging(log_file=log_dir / "save_conditioned_metrics.log")
    
    log_info(f"Starting T028: Save conditioned metrics for run_id={args.run_id}")
    
    try:
        # Ensure output directories exist
        ensure_directories()
        output_dir = Path(args.output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)
        
        # Load conditioned metrics
        log_info(f"Loading conditioned metrics for run_id={args.run_id}")
        metrics = load_projected_metrics(args.run_id)
        log_info(f"Loaded metrics for {len(metrics)} datasets")
        
        # Aggregate metrics
        log_info("Aggregating conditioned metrics")
        aggregated = aggregate_conditioned_metrics(metrics, args.run_id)
        
        # Save to artifacts
        output_file = output_dir / f"metrics_conditioned_{args.run_id}.json"
        log_info(f"Saving aggregated metrics to {output_file}")
        save_aggregated_metrics(aggregated, output_file)
        
        log_info(f"T028 completed successfully. Output: {output_file}")
        return 0
        
    except FileNotFoundError as e:
        log_error(f"Required data not found: {e}")
        log_error("Ensure T025 (run_conditioned.py) has completed successfully and produced metrics.")
        return 1
    except Exception as e:
        log_error(f"Error during T028 execution: {e}")
        import traceback
        log_error(traceback.format_exc())
        return 1

if __name__ == "__main__":
    sys.exit(main())
