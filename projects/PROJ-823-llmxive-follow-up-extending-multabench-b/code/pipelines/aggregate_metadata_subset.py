"""
Task T024e: Metadata Aggregation & Subset Selection

Loads the metadata stats summary generated by T024, sorts datasets alphabetically,
and selects the initial subset. If the number of available datasets is limited,
it flags the shortfall in the report.

Output:
    Updates `data/processed/metadata_stats_summary.csv` with a 'selected' flag.
    Generates `data/artifacts/metadata_subset_report.json`.
"""
import os
import sys
import json
import csv
import argparse
from pathlib import Path
from datetime import datetime

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from config import ensure_directories
from utils.logging import get_logger, log_info, log_error, log_warning

logger = get_logger(__name__)

INPUT_PATH = "data/processed/metadata_stats_summary.csv"
OUTPUT_PATH = "data/processed/metadata_stats_summary.csv"
REPORT_PATH = "data/artifacts/metadata_subset_report.json"

def load_csv_data(input_path: str) -> list:
    """Load the metadata stats summary CSV."""
    path = Path(input_path)
    if not path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    
    data = []
    with open(path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            data.append(row)
    return data

def save_csv_data(data: list, output_path: str):
    """Save the updated metadata stats summary CSV."""
    if not data:
        log_warning("No data to save.")
        return

    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    fieldnames = list(data[0].keys())
    with open(path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(data)

def save_report_json(report: dict, output_path: str):
    """Save the subset selection report to JSON."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)

def aggregate_and_select_subset(input_path: str, output_path: str, report_path: str):
    """
    Main logic for T024e:
    1. Load data.
    2. Sort alphabetically by dataset_id.
    3. Select all available (subset selection logic: if limited, use all and flag).
    4. Add 'selected' flag.
    5. Save updated CSV and JSON report.
    """
    ensure_directories()
    log_info(f"Loading metadata stats from {input_path}")
    
    try:
        data = load_csv_data(input_path)
    except FileNotFoundError as e:
        log_error(str(e))
        raise

    if not data:
        log_warning("Input data is empty. Creating empty report.")
        report = {
            "timestamp": datetime.now().isoformat(),
            "input_file": input_path,
            "total_datasets": 0,
            "selected_datasets": 0,
            "selection_logic": "empty_input",
            "shortfall_flag": False,
            "datasets": []
        }
        save_report_json(report, report_path)
        # Create empty output file with headers if needed, or just return
        # We'll create a minimal valid CSV structure if data was empty but expected
        return

    # Sort alphabetically by dataset_id
    # Ensure dataset_id exists in keys
    if 'dataset_id' not in data[0]:
        raise KeyError("Expected 'dataset_id' column in input CSV.")

    data.sort(key=lambda x: x['dataset_id'])

    total_count = len(data)
    
    # Selection Logic:
    # "Sort datasets alphabetically by dataset_id and select the initial subset. 
    # If a limited number are available, use all and flag the shortfall in the report."
    # Since we don't have a fixed target count defined in the task description (other than "initial subset"),
    # and the constraint is to use all if limited, we select ALL available datasets
    # and flag if the total count is small (e.g., < 5) as a "shortfall" for statistical power,
    # or simply flag that we used all available.
    # The task implies we might have a target, but without a specific number, we select all.
    # We will flag "shortfall" if the count is less than a reasonable minimum for correlation (e.g., 10).
    MIN_RECOMMENDED_FOR_CORRELATION = 10
    shortfall = total_count < MIN_RECOMMENDED_FOR_CORRELATION

    # Mark all as selected
    for row in data:
        row['selected'] = 'true'

    # Prepare report
    selected_ids = [row['dataset_id'] for row in data]
    
    report = {
        "timestamp": datetime.now().isoformat(),
        "input_file": input_path,
        "output_file": output_path,
        "total_datasets": total_count,
        "selected_datasets": total_count,
        "selection_logic": "alphabetical_sort_all_available",
        "shortfall_flag": shortfall,
        "shortfall_reason": f"Total datasets ({total_count}) is below recommended minimum ({MIN_RECOMMENDED_FOR_CORRELATION}) for robust correlation analysis." if shortfall else "None",
        "datasets": selected_ids
    }

    log_info(f"Processing {total_count} datasets. Shortfall flag: {shortfall}")

    # Save updated CSV
    save_csv_data(data, output_path)
    log_info(f"Updated CSV saved to {output_path}")

    # Save report
    save_report_json(report, report_path)
    log_info(f"Subset report saved to {report_path}")

def main():
    parser = argparse.ArgumentParser(description="Aggregate metadata stats and select subset (T024e).")
    parser.add_argument("--input", type=str, default=INPUT_PATH, help="Input CSV path")
    parser.add_argument("--output", type=str, default=OUTPUT_PATH, help="Output CSV path")
    parser.add_argument("--report", type=str, default=REPORT_PATH, help="Output JSON report path")
    args = parser.parse_args()

    try:
        aggregate_and_select_subset(args.input, args.output, args.report)
        logger.info("Task T024e completed successfully.")
    except Exception as e:
        log_error(f"Task T024e failed: {str(e)}")
        sys.exit(1)

if __name__ == "__main__":
    main()
