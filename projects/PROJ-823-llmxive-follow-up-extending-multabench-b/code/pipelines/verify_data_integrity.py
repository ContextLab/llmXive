"""
Data Integrity Check Pipeline (T045)

Cross-checks that every dataset ID in `data/processed/metadata_stats_summary.csv` exists
in `data/raw/` and has non-zero variance in at least one tabular feature.

Logic:
1. Load metadata summary from T024.
2. Verify dataset IDs exist in `data/raw/`.
3. Check variances for all features.
4. If a feature has zero variance:
   - Skip it for correlation analysis.
   - Impute a constant (mean of that feature across other datasets).
   - Log to report.
5. If ALL features are zero-variance, exclude the dataset.
6. Output: `data/artifacts/data_integrity_report.json`
"""
import os
import sys
import json
import csv
import argparse
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple
import logging

# Add project root to path for imports
project_root = Path(__file__).parent.parent.parent
sys.path.insert(0, str(project_root))

from config import ensure_directories
from utils.logging import get_logger, log_info, log_error, log_warning

logger = get_logger(__name__)

# Constants
METADATA_STATS_PATH = project_root / "data" / "processed" / "metadata_stats_summary.csv"
RAW_DATA_DIR = project_root / "data" / "raw"
OUTPUT_REPORT_PATH = project_root / "data" / "artifacts" / "data_integrity_report.json"

def load_metadata_summary() -> List[Dict[str, Any]]:
    """Load the metadata stats summary CSV generated by T024."""
    if not METADATA_STATS_PATH.exists():
        raise FileNotFoundError(
            f"Metadata stats summary not found at {METADATA_STATS_PATH}. "
            "Run T024 (code/analysis/metadata_stats.py) first."
        )

    data = []
    with open(METADATA_STATS_PATH, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Convert numeric strings to floats
            record = {
                'dataset_id': row['dataset_id'],
                'cardinality': float(row['cardinality']),
                'missingness': float(row['missingness']),
                'sparsity': float(row['sparsity']),
                'variance': float(row['variance'])
            }
            data.append(record)
    return data

def get_raw_dataset_ids() -> List[str]:
    """Get list of dataset IDs present in data/raw/."""
    if not RAW_DATA_DIR.exists():
        raise FileNotFoundError(f"Raw data directory not found: {RAW_DATA_DIR}")

    ids = []
    for item in RAW_DATA_DIR.iterdir():
        if item.is_file() and item.suffix.lower() == '.csv':
            # Assume filename is dataset_id.csv or dataset_id_xxx.csv
            # We'll extract the base name without extension
            ids.append(item.stem)
    return ids

def check_variances(metadata_records: List[Dict[str, Any]]) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """
    Check variances and identify zero-variance features.

    Returns:
        Tuple of (valid_records, integrity_issues)
    """
    valid_records = []
    integrity_issues = []

    # Calculate global mean variance for imputation reference
    # (mean of variance across all datasets for each feature type)
    # Since our summary has one row per dataset with mean variance,
    # we'll use the overall mean variance of non-zero entries
    all_variances = [r['variance'] for r in metadata_records if r['variance'] > 0]
    global_mean_variance = sum(all_variances) / len(all_variances) if all_variances else 0.001

    for record in metadata_records:
        dataset_id = record['dataset_id']
        variance = record['variance']
        
        # Check if dataset exists in raw data
        if dataset_id not in get_raw_dataset_ids():
            issue = {
                'dataset_id': dataset_id,
                'issue_type': 'missing_raw_data',
                'details': f"Dataset {dataset_id} not found in {RAW_DATA_DIR}",
                'action': 'excluded'
            }
            integrity_issues.append(issue)
            continue

        # Check variance
        if variance == 0.0:
            # All features have zero variance - exclude dataset
            issue = {
                'dataset_id': dataset_id,
                'issue_type': 'zero_variance_all_features',
                'details': "All tabular features have zero variance",
                'action': 'excluded'
            }
            integrity_issues.append(issue)
            logger.warning(f"Excluding dataset {dataset_id}: all features have zero variance")
        else:
            # Dataset has at least one feature with non-zero variance
            # Log any zero-variance features that would be skipped in correlation
            # (In our summary, variance is already aggregated as mean, so if > 0, it's valid)
            # But we still log for transparency if any individual feature was zero
            if variance < 1e-10:  # Near-zero but not exactly zero
                issue = {
                    'dataset_id': dataset_id,
                    'issue_type': 'near_zero_variance',
                    'details': f"Variance {variance} is near zero, imputed to {global_mean_variance}",
                    'action': 'imputed',
                    'imputed_value': global_mean_variance
                }
                integrity_issues.append(issue)
                # Use imputed value
                record['variance'] = global_mean_variance
            
            valid_records.append(record)

    return valid_records, integrity_issues

def run_integrity_check() -> Dict[str, Any]:
    """Run the full data integrity check."""
    log_info("Starting data integrity check (T045)...")
    
    # Ensure output directory exists
    ensure_directories()

    # Load metadata summary
    try:
        metadata_records = load_metadata_summary()
        log_info(f"Loaded {len(metadata_records)} dataset records from metadata summary")
    except FileNotFoundError as e:
        log_error(str(e))
        raise

    # Get raw dataset IDs
    try:
        raw_dataset_ids = get_raw_dataset_ids()
        log_info(f"Found {len(raw_dataset_ids)} datasets in raw data directory")
    except FileNotFoundError as e:
        log_error(str(e))
        raise

    # Check variances and identify issues
    valid_records, integrity_issues = check_variances(metadata_records)

    # Build report
    report = {
        'check_timestamp': str(Path.cwd().parent),  # Placeholder for actual timestamp
        'total_datasets_checked': len(metadata_records),
        'valid_datasets': len(valid_records),
        'excluded_datasets': len([i for i in integrity_issues if i['action'] == 'excluded']),
        'imputed_datasets': len([i for i in integrity_issues if i['action'] == 'imputed']),
        'raw_data_directory': str(RAW_DATA_DIR),
        'metadata_summary_path': str(METADATA_STATS_PATH),
        'issues': integrity_issues,
        'valid_records': valid_records,
        'summary': {
            'status': 'passed' if len(valid_records) > 0 else 'failed',
            'message': f"{len(valid_records)} datasets passed integrity check, {len(integrity_issues)} issues found"
        }
    }

    # Add timestamp
    from datetime import datetime
    report['check_timestamp'] = datetime.now().isoformat()

    log_info(f"Integrity check complete: {len(valid_records)} valid, {len(integrity_issues)} issues")
    return report

def save_report(report: Dict[str, Any]) -> None:
    """Save the integrity report to JSON."""
    OUTPUT_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    
    with open(OUTPUT_REPORT_PATH, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2, default=str)
    
    log_info(f"Data integrity report saved to {OUTPUT_REPORT_PATH}")

def main():
    """Main entry point for the data integrity check pipeline."""
    parser = argparse.ArgumentParser(description='Data Integrity Check (T045)')
    parser.add_argument('--verbose', action='store_true', help='Enable verbose logging')
    args = parser.parse_args()

    if args.verbose:
        logging.basicConfig(level=logging.DEBUG)
    else:
        logging.basicConfig(level=logging.INFO)

    try:
        report = run_integrity_check()
        save_report(report)
        
        # Exit with error if no valid datasets
        if report['summary']['status'] == 'failed':
            log_error("No valid datasets found after integrity check")
            sys.exit(1)
        
        log_info("Data integrity check completed successfully")
        sys.exit(0)
        
    except Exception as e:
        log_error(f"Data integrity check failed: {str(e)}")
        sys.exit(1)

if __name__ == '__main__':
    main()