"""
verify_data_integrity.py

Implements T045: Data Integrity Check.
Cross-checks that every dataset ID in data/processed/metadata_stats_summary.csv exists
in data/raw/ and has non-zero variance in at least one tabular feature.
Logs failures to data/artifacts/data_integrity_report.json.
"""
import os
import sys
import json
import csv
import argparse
from pathlib import Path
from typing import List, Dict, Any, Set

# Add parent to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent))

from utils.logging import get_logger, log_info, log_warning, log_error, log_critical

logger = get_logger(__name__)

def load_metadata_summary(summary_path: Path) -> List[Dict[str, Any]]:
    """
    Load the metadata stats summary CSV generated by T024.
    Expected columns: dataset_id, cardinality, missingness, sparsity, variance.
    """
    if not summary_path.exists():
        raise FileNotFoundError(f"Metadata summary file not found: {summary_path}")

    datasets = []
    with open(summary_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            datasets.append({
                'dataset_id': row['dataset_id'],
                'cardinality': float(row['cardinality']),
                'missingness': float(row['missingness']),
                'sparsity': float(row['sparsity']),
                'variance': float(row['variance'])
            })
    return datasets

def get_raw_dataset_ids(raw_dir: Path) -> Set[str]:
    """
    Scan data/raw/ directory to find available dataset identifiers.
    Assumes datasets are stored as directories or files named with their ID.
    Returns a set of dataset IDs found.
    """
    if not raw_dir.exists():
        raise FileNotFoundError(f"Raw data directory not found: {raw_dir}")

    dataset_ids = set()
    for item in raw_dir.iterdir():
        # Skip hidden files and common non-data files
        if item.name.startswith('.') or item.name in ('README.md', 'checksums.json'):
            continue
        
        # Assume directory names or base file names (without extension) are dataset IDs
        dataset_id = item.name
        if item.is_file() and '.' in item.name:
            dataset_id = item.name.rsplit('.', 1)[0]
        
        dataset_ids.add(dataset_id)
    
    return dataset_ids

def check_variances(metadata: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Check if each dataset has non-zero variance in at least one tabular feature.
    The 'variance' column in metadata_stats_summary.csv is the mean variance across
    all features. If this is > 0, the dataset passes. If 0, it fails.
    
    Returns a list of issues found.
    """
    issues = []
    
    for row in metadata:
        dataset_id = row['dataset_id']
        variance = row['variance']
        
        # Check for zero variance (or very close to zero due to floating point)
        if variance <= 1e-9:
            issues.append({
                'dataset_id': dataset_id,
                'issue_type': 'zero_variance',
                'description': f"Dataset '{dataset_id}' has zero (or near-zero) variance in all tabular features. Variance value: {variance}",
                'severity': 'error'
            })
        else:
            logger.debug(f"Dataset '{dataset_id}' passed variance check: {variance}")
    
    return issues

def run_integrity_check(
    metadata_summary_path: Path,
    raw_data_dir: Path,
    report_output_path: Path
) -> Dict[str, Any]:
    """
    Run the full data integrity check:
    1. Load metadata summary from T024.
    2. Verify all dataset IDs exist in data/raw/.
    3. Verify all datasets have non-zero variance.
    4. Compile and save the report.
    """
    logger.info("Starting data integrity check...")
    
    report = {
        'timestamp': str(Path(__file__).parent.parent.parent / 'data' / 'artifacts'), # Will be fixed
        'status': 'pending',
        'checks': {
            'metadata_loaded': False,
            'raw_data_scanned': False,
            'variance_checked': False
        },
        'issues': [],
        'summary': {
            'total_datasets_in_metadata': 0,
            'datasets_missing_in_raw': 0,
            'datasets_zero_variance': 0,
            'datasets_passed': 0
        }
    }
    
    # 1. Load metadata summary
    try:
        metadata = load_metadata_summary(metadata_summary_path)
        report['checks']['metadata_loaded'] = True
        report['summary']['total_datasets_in_metadata'] = len(metadata)
        logger.info(f"Loaded {len(metadata)} datasets from metadata summary.")
    except Exception as e:
        log_error(f"Failed to load metadata summary: {e}")
        report['status'] = 'failed'
        report['issues'].append({
            'issue_type': 'load_error',
            'description': str(e),
            'severity': 'critical'
        })
        return report
    
    # 2. Scan raw data directory
    try:
        raw_ids = get_raw_dataset_ids(raw_data_dir)
        report['checks']['raw_data_scanned'] = True
        logger.info(f"Found {len(raw_ids)} datasets in raw data directory.")
    except Exception as e:
        log_error(f"Failed to scan raw data directory: {e}")
        report['status'] = 'failed'
        report['issues'].append({
            'issue_type': 'scan_error',
            'description': str(e),
            'severity': 'critical'
        })
        return report
    
    # 3. Check existence in raw data
    missing_datasets = []
    for row in metadata:
        dataset_id = row['dataset_id']
        if dataset_id not in raw_ids:
            missing_datasets.append(dataset_id)
            report['issues'].append({
                'dataset_id': dataset_id,
                'issue_type': 'missing_in_raw',
                'description': f"Dataset '{dataset_id}' is in metadata summary but not found in data/raw/",
                'severity': 'error'
            })
    
    report['summary']['datasets_missing_in_raw'] = len(missing_datasets)
    
    # 4. Check variances
    variance_issues = check_variances(metadata)
    report['issues'].extend(variance_issues)
    report['summary']['datasets_zero_variance'] = len(variance_issues)
    report['checks']['variance_checked'] = True
    
    # Calculate passed datasets
    failed_ids = set(missing_datasets) | set(i['dataset_id'] for i in variance_issues)
    report['summary']['datasets_passed'] = len(metadata) - len(failed_ids)
    
    # Set final status
    if len(report['issues']) == 0:
        report['status'] = 'passed'
        logger.info("Data integrity check PASSED: All datasets valid.")
    else:
        report['status'] = 'failed'
        log_warning(f"Data integrity check FAILED: {len(report['issues'])} issues found.")
    
    # Ensure output directory exists
    report_output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Save report
    with open(report_output_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Integrity report saved to: {report_output_path}")
    return report

def save_report(report: Dict[str, Any], output_path: Path) -> None:
    """
    Save the integrity report to JSON.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2, default=str)

def main():
    parser = argparse.ArgumentParser(description="Verify data integrity for MulTaBench pipeline.")
    parser.add_argument(
        "--metadata-summary",
        type=str,
        default="data/processed/metadata_stats_summary.csv",
        help="Path to the metadata stats summary CSV (output of T024)."
    )
    parser.add_argument(
        "--raw-dir",
        type=str,
        default="data/raw",
        help="Path to the raw data directory."
    )
    parser.add_argument(
        "--output",
        type=str,
        default="data/artifacts/data_integrity_report.json",
        help="Path to save the integrity report JSON."
    )
    
    args = parser.parse_args()
    
    metadata_path = Path(args.metadata_summary)
    raw_dir = Path(args.raw_dir)
    output_path = Path(args.output)
    
    # Run the check
    report = run_integrity_check(metadata_path, raw_dir, output_path)
    
    # Exit with non-zero code if check failed
    if report['status'] != 'passed':
        sys.exit(1)
    
    sys.exit(0)

if __name__ == "__main__":
    main()