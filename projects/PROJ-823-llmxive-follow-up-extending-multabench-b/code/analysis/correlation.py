"""
Correlation Analysis Module for T031.

Calculates the "Recovery Ratio" metric as defined in the project specification:
Recovery Ratio = (CPU-Conditioned - Frozen_Aggregated) / (GPU-Tuned - Frozen_Aggregated)

Inputs:
  - data/artifacts/gpu_tuned_baselines.csv (from T032a)
  - data/artifacts/frozen_baseline_aggregated_{run_id}.json (from T019c)
  - data/artifacts/metrics_conditioned_{run_id}.json (from T028)

Output:
  - data/processed/correlation_inputs.csv (Intermediate file for T033)
  - data/artifacts/correlation_report_{run_id}.json (Final report if run directly)
"""
import os
import sys
import json
import csv
import argparse
from pathlib import Path
from typing import Dict, List, Any, Optional, Tuple
import logging

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)

# Project root path
PROJECT_ROOT = Path(__file__).parent.parent.parent
DATA_DIR = PROJECT_ROOT / "data"
ARTIFACTS_DIR = DATA_DIR / "artifacts"
PROCESSED_DIR = DATA_DIR / "processed"

# Ensure output directories exist
ARTIFACTS_DIR.mkdir(parents=True, exist_ok=True)
PROCESSED_DIR.mkdir(parents=True, exist_ok=True)

def load_gpu_tuned_baselines(filepath: Optional[Path] = None) -> Dict[str, float]:
    """
    Loads GPU-Tuned baselines from the validated CSV file.
    
    Args:
        filepath: Path to the GPU-Tuned baselines CSV. Defaults to data/artifacts/gpu_tuned_baselines.csv.
        
    Returns:
        Dictionary mapping dataset_id to baseline_value (float).
        
    Raises:
        FileNotFoundError: If the file does not exist.
        ValueError: If the file is empty or malformed.
    """
    if filepath is None:
        filepath = ARTIFACTS_DIR / "gpu_tuned_baselines.csv"
    
    if not filepath.exists():
        raise FileNotFoundError(f"Required GPU-Tuned baselines file not found: {filepath}")
    
    baselines = {}
    try:
        with open(filepath, 'r', newline='', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            # Validate headers
            if reader.fieldnames is None or 'dataset_id' not in reader.fieldnames or 'value' not in reader.fieldnames:
                raise ValueError(f"Invalid CSV format in {filepath}. Expected headers: dataset_id, value")
            
            for row in reader:
                dataset_id = row['dataset_id'].strip()
                try:
                    value = float(row['value'])
                    baselines[dataset_id] = value
                except ValueError:
                    logger.warning(f"Skipping row with invalid value for dataset_id: {dataset_id}")
    except Exception as e:
        logger.error(f"Error reading GPU-Tuned baselines: {e}")
        raise
    
    if not baselines:
        raise ValueError(f"No valid baseline data found in {filepath}")
        
    logger.info(f"Loaded {len(baselines)} GPU-Tuned baselines.")
    return baselines

def load_frozen_aggregated_metrics(filepath: Optional[Path] = None) -> Dict[str, float]:
    """
    Loads Frozen Aggregated metrics from the JSON file generated by T019c.
    
    Args:
        filepath: Path to the frozen baseline aggregated JSON. Defaults to data/artifacts/frozen_baseline_aggregated_{run_id}.json.
        
    Returns:
        Dictionary mapping dataset_id to metric_value (float).
        
    Raises:
        FileNotFoundError: If the file does not exist.
        ValueError: If the file is empty or malformed.
    """
    if filepath is None:
        # Attempt to find the most recent aggregated file if exact name unknown
        # Pattern: frozen_baseline_aggregated_*.json
        pattern = "frozen_baseline_aggregated_*.json"
        matches = list(ARTIFACTS_DIR.glob(pattern))
        if not matches:
            raise FileNotFoundError(f"No frozen baseline aggregated metrics found in {ARTIFACTS_DIR}")
        # Sort by modification time and take the latest
        filepath = max(matches, key=os.path.getmtime)
    
    if not filepath.exists():
        raise FileNotFoundError(f"Required frozen aggregated metrics file not found: {filepath}")
    
    metrics = {}
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        # Handle potential list of records or direct dict structure
        if isinstance(data, list):
            for item in data:
                if 'dataset_id' in item and 'metric_value' in item:
                    metrics[item['dataset_id']] = float(item['metric_value'])
        elif isinstance(data, dict):
            # If the file is a direct mapping of dataset_id -> value
            if all(isinstance(v, (int, float)) for v in data.values()):
                metrics = {k: float(v) for k, v in data.items()}
            else:
                # Assume nested structure: {dataset_id: {'metric_value': ...}}
                for k, v in data.items():
                    if isinstance(v, dict) and 'metric_value' in v:
                        metrics[k] = float(v['metric_value'])
                    elif isinstance(v, (int, float)):
                        metrics[k] = float(v)
    except json.JSONDecodeError as e:
        logger.error(f"JSON decode error in {filepath}: {e}")
        raise
    except Exception as e:
        logger.error(f"Error reading frozen aggregated metrics: {e}")
        raise
    
    if not metrics:
        raise ValueError(f"No valid metric data found in {filepath}")
        
    logger.info(f"Loaded {len(metrics)} frozen aggregated metrics.")
    return metrics

def load_conditioned_metrics(filepath: Optional[Path] = None) -> Dict[str, float]:
    """
    Loads CPU-Conditioned metrics from the JSON file generated by T028.
    
    Args:
        filepath: Path to the conditioned metrics JSON. Defaults to data/artifacts/metrics_conditioned_{run_id}.json.
        
    Returns:
        Dictionary mapping dataset_id to metric_value (float).
        
    Raises:
        FileNotFoundError: If the file does not exist.
        ValueError: If the file is empty or malformed.
    """
    if filepath is None:
        # Attempt to find the most recent conditioned file
        pattern = "metrics_conditioned_*.json"
        matches = list(ARTIFACTS_DIR.glob(pattern))
        if not matches:
            raise FileNotFoundError(f"No conditioned metrics found in {ARTIFACTS_DIR}")
        filepath = max(matches, key=os.path.getmtime)
    
    if not filepath.exists():
        raise FileNotFoundError(f"Required conditioned metrics file not found: {filepath}")
    
    metrics = {}
    try:
        with open(filepath, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        if isinstance(data, list):
            for item in data:
                if 'dataset_id' in item and 'metric_value' in item:
                    metrics[item['dataset_id']] = float(item['metric_value'])
        elif isinstance(data, dict):
            if all(isinstance(v, (int, float)) for v in data.values()):
                metrics = {k: float(v) for k, v in data.items()}
            else:
                for k, v in data.items():
                    if isinstance(v, dict) and 'metric_value' in v:
                        metrics[k] = float(v['metric_value'])
                    elif isinstance(v, (int, float)):
                        metrics[k] = float(v)
    except json.JSONDecodeError as e:
        logger.error(f"JSON decode error in {filepath}: {e}")
