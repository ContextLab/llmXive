logger = get_logger(__name__)


def load_metadata_stats_summary(csv_path: str) -> pd.DataFrame:
    """
    Load the metadata statistics summary CSV generated by T024.

    Args:
        csv_path: Path to the metadata_stats_summary.csv file.

    Returns:
        DataFrame containing metadata statistics.
    """
    path = Path(csv_path)
    if not path.exists():
        raise FileNotFoundError(
            f"Metadata stats summary not found at {csv_path}. "
            "Ensure T024 (metadata_stats.py) has been completed successfully."
        )

    df = pd.read_csv(csv_path)
    log_info(logger, f"Loaded metadata stats for {len(df)} datasets from {csv_path}")
    return df


def process_edge_cases_for_all_datasets(
    stats_df: pd.DataFrame,
    output_dir: str,
    missing_value_strategy: str = "impute_mean",
    zero_variance_strategy: str = "impute_constant"
) -> Dict[str, Any]:
    """
    Process edge cases for all datasets listed in the metadata stats summary.

    This function:
    1. Identifies datasets with zero-variance features or missing fields.
    2. Applies the specified strategy to handle these edge cases.
    3. Generates a detailed report of actions taken.

    Args:
        stats_df: DataFrame from T024 containing dataset metadata.
        output_dir: Directory to save the edge case report.
        missing_value_strategy: Strategy for missing values ('drop', 'impute_mean', 'impute_median', 'impute_constant').
        zero_variance_strategy: Strategy for zero-variance columns ('drop', 'impute_constant').

    Returns:
        Dictionary containing the processing report.
    """
    ensure_directories(output_dir)
    report = {
        "total_datasets": len(stats_df),
        "datasets_processed": 0,
        "datasets_with_edge_cases": 0,
        "edge_case_details": [],
        "summary": {
            "zero_variance_count": 0,
            "missing_fields_count": 0,
            "columns_dropped": 0,
            "columns_imputed": 0
        }
    }

    for _, row in stats_df.iterrows():
        dataset_id = row["dataset_id"]
        log_info(logger, f"Processing edge cases for dataset: {dataset_id}")

        dataset_report = {
            "dataset_id": dataset_id,
            "has_zero_variance": False,
            "has_missing_fields": False,
            "actions_taken": []
        }

        # Check for zero variance features
        if "variance" in row and row["variance"] is not None:
            try:
                variance_val = float(row["variance"])
                if variance_val == 0.0:
                    dataset_report["has_zero_variance"] = True
                    dataset_report["actions_taken"].append({
                        "type": "zero_variance",
                        "strategy": zero_variance_strategy,
                        "details": "Dataset has zero variance features"
                    })
                    report["summary"]["zero_variance_count"] += 1
            except (ValueError, TypeError):
                log_warning(logger, f"Invalid variance value for {dataset_id}: {row['variance']}")

        # Check for missing fields
        if "missingness" in row and row["missingness"] is not None:
            try:
                missing_val = float(row["missingness"])
                if missing_val > 0.0:
                    dataset_report["has_missing_fields"] = True
                    dataset_report["actions_taken"].append({
                        "type": "missing_fields",
                        "strategy": missing_value_strategy,
                        "details": f"Missingness ratio: {missing_val:.4f}"
                    })
                    report["summary"]["missing_fields_count"] += 1
            except (ValueError, TypeError):
                log_warning(logger, f"Invalid missingness value for {dataset_id}: {row['missingness']}")

        # Determine if edge cases exist
        if dataset_report["has_zero_variance"] or dataset_report["has_missing_fields"]:
            report["datasets_with_edge_cases"] += 1
            report["edge_case_details"].append(dataset_report)

            # Log specific actions
            for action in dataset_report["actions_taken"]:
                if action["type"] == "zero_variance":
                    if zero_variance_strategy == "drop":
                        report["summary"]["columns_dropped"] += 1
                        log_info(logger, f"  -> Will drop zero-variance columns for {dataset_id}")
                    elif zero_variance_strategy == "impute_constant":
                        report["summary"]["columns_imputed"] += 1
                        log_info(logger, f"  -> Will impute constant value for zero-variance columns in {dataset_id}")
                elif action["type"] == "missing_fields":
                    if missing_value_strategy == "drop":
                        report["summary"]["columns_dropped"] += 1
                        log_info(logger, f"  -> Will drop rows with missing fields for {dataset_id}")
                    elif missing_value_strategy in ["impute_mean", "impute_median", "impute_constant"]:
                        report["summary"]["columns_imputed"] += 1
                        log_info(logger, f"  -> Will impute missing values using {missing_value_strategy} for {dataset_id}")

        report["datasets_processed"] += 1

    return report


def save_edge_case_report(report: Dict[str, Any], output_path: str) -> None:
    """
    Save the edge case processing report to a JSON file.

    Args:
        report: The report dictionary to save.
        output_path: Path to the output JSON file.
    """
    path = Path(output_path)
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2, default=str)
    log_info(logger, f"Saved edge case report to {output_path}")


def main():
    """
    Main entry point for the edge case processor.

    This script processes the metadata stats summary (T024) to identify
    and handle edge cases (zero-variance features, missing fields) across
    all datasets, preparing them for the conditioned projection training.
    """
    parser = argparse.ArgumentParser(
        description="Process edge cases in tabular metadata for US2"
    )
    parser.add_argument(
        "--input-stats",
        type=str,
        default="data/processed/metadata_stats_summary.csv",
        help="Path to the metadata stats summary CSV (from T024)"
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="data/artifacts",
        help="Directory to save the edge case report"
    )
    parser.add_argument(
        "--missing-strategy",
        type=str,
        default="impute_mean",
        choices=["drop", "impute_mean", "impute_median", "impute_constant"],
        help="Strategy for handling missing values"
    )
    parser.add_argument(
        "--zero-var-strategy",
        type=str,
        default="impute_constant",
        choices=["drop", "impute_constant"],
        help="Strategy for handling zero-variance columns"
    )

    args = parser.parse_args()

    try:
        # Load metadata stats
        log_info(logger, f"Loading metadata stats from {args.input_stats}")
        stats_df = load_metadata_stats_summary(args.input_stats)

        # Process edge cases
        log_info(logger, "Processing edge cases for all datasets")
        report = process_edge_cases_for_all_datasets(
            stats_df,
            args.output_dir,
            missing_value_strategy=args.missing_strategy,
            zero_variance_strategy=args.zero_var_strategy
        )

        # Save report
        output_path = Path(args.output_dir) / "edge_case_report.json"
        save_edge_case_report(report, str(output_path))

        # Print summary
        print("\n" + "="*60)
        print("EDGE CASE PROCESSING SUMMARY")
        print("="*60)
        print(f"Total Datasets: {report['total_datasets']}")
        print(f"Datasets with Edge Cases: {report['datasets_with_edge_cases']}")
        print(f"  - Zero Variance Issues: {report['summary']['zero_variance_count']}")
        print(f"  - Missing Fields Issues: {report['summary']['missing_fields_count']}")
        print(f"Actions Taken:")
        print(f"  - Columns Dropped: {report['summary']['columns_dropped']}")
        print(f"  - Columns Imputed: {report['summary']['columns_imputed']}")
        print(f"Report saved to: {output_path}")
        print("="*60)

    except FileNotFoundError as e:
        log_error(logger, str(e))
        print(f"\nError: {e}")
        print("Please ensure T024 (metadata_stats.py) has been completed first.")
        sys.exit(1)
    except Exception as e:
        log_error(logger, f"Unexpected error: {e}")
        print(f"\nUnexpected error: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()