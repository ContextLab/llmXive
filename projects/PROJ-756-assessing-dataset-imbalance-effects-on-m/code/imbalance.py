"""
Imbalance analysis module.
Calculates Target Imbalance Score (Gini) and Compositional Imbalance Score (Convex Hull Coverage).
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, List, Any, Optional, Tuple

import pandas as pd
import numpy as np
from scipy.stats import gini

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

# Project root is two levels up from code/
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = PROJECT_ROOT / "data"
PROCESSED_DIR = DATA_DIR / "processed"
RESULTS_DIR = PROJECT_ROOT / "results"

# Input: Descriptors generated by T007
INPUT_FILE = PROCESSED_DIR / "descriptors.parquet"

# Output files for T008
TARGET_IMBALANCE_FILE = RESULTS_DIR / "target_imbalance_scores.csv"
COMPOSITIONAL_IMBALANCE_FILE = RESULTS_DIR / "compositional_imbalance_score.csv"

MIN_SAMPLES = 100

def load_data() -> pd.DataFrame:
    """Loads the processed descriptors from Parquet."""
    if not INPUT_FILE.exists():
        raise FileNotFoundError(
            f"Descriptors file not found: {INPUT_FILE}. "
            "Run code/descriptors.py (T007) first to generate data/processed/descriptors.parquet."
        )
    return pd.read_parquet(INPUT_FILE)

def calculate_gini(values: np.ndarray) -> float:
    """
    Calculates the Gini coefficient for a 1D array of values.
    Handles negative values by shifting to positive range (absolute offset).
    """
    if len(values) == 0:
        return 0.0
    
    # Gini requires non-negative values. Shift if necessary.
    if np.any(values < 0):
        min_val = np.min(values)
        values = values - min_val + 1e-9  # Add small epsilon to avoid zero if min was exactly 0

    # If all values are zero after shift, Gini is 0
    if np.sum(values) == 0:
        return 0.0

    # Calculate Gini: 2 * sum(i * x_i) / (n * sum(x)) - (n+1)/n
    sorted_vals = np.sort(values)
    n = len(sorted_vals)
    index = np.arange(1, n + 1)
    return float((2 * np.sum(index * sorted_vals)) / (n * np.sum(sorted_vals)) - (n + 1) / n)

def calculate_compositional_imbalance_score(X: np.ndarray) -> float:
    """
    Calculates the Compositional Imbalance Score using Convex Hull Coverage Score.
    
    Logic:
    1. Compute the convex hull of the dataset in descriptor space.
    2. The "coverage" is the ratio of the volume of the convex hull to the volume 
       of the bounding box (or a reference volume). 
       However, in high dimensions, volume calculation is unstable.
       Alternative robust metric: Ratio of points on the hull boundary to total points.
       A higher ratio indicates a "hollow" or sparse distribution (high imbalance).
       A lower ratio indicates a dense, filled core (low imbalance).
       
    We will use the ratio of points on the convex hull as the score.
    """
    if X.shape[0] < 3:
        return 0.0
    
    try:
        from scipy.spatial import ConvexHull
        hull = ConvexHull(X)
        # Number of points on the hull (vertices)
        n_hull_points = len(hull.vertices)
        total_points = X.shape[0]
        
        # Score: Ratio of hull points to total points
        # 0.0 = perfectly dense (all internal), 1.0 = all on surface (highly imbalanced/sparse)
        score = n_hull_points / total_points
        return float(score)
    except Exception as e:
        logger.warning(f"Convex Hull calculation failed: {e}. Returning 0.0.")
        return 0.0

def calculate_target_imbalance_score(df: pd.DataFrame, property_name: str) -> Dict[str, Any]:
    """
    Calculates the Gini coefficient of the target property values.
    Skips properties with < MIN_SAMPLES.
    """
    if property_name not in df.columns:
        return {"property": property_name, "score": None, "samples": 0, "skipped": True, "reason": "column_not_found"}
    
    values = df[property_name].dropna().values
    n_samples = len(values)
    
    if n_samples < MIN_SAMPLES:
        return {"property": property_name, "score": None, "samples": n_samples, "skipped": True, "reason": "insufficient_samples"}
    
    score = calculate_gini(values)
    return {
        "property": property_name, 
        "score": score, 
        "samples": n_samples, 
        "skipped": False
    }

def identify_target_columns(df: pd.DataFrame) -> List[str]:
    """
    Identifies target property columns in the dataframe.
    Heuristic: Columns that are numeric and not part of the standard descriptor set.
    We assume descriptors are in 'data/processed/descriptors.parquet' and have specific prefixes,
    or we look for a 'target' column if it exists.
    Given the task description, we look for properties that are not standard Magpie descriptors.
    Magpie descriptors usually start with 'mean_', 'min_', 'max_', 'range_', 'var_', 'mode_', 'entropy_', etc.
    We will also accept any column that is clearly a property (e.g., 'formation_energy', 'band_gap').
    
    For robustness, if a 'target' column exists, use it. Otherwise, try to infer.
    """
    numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
    target_candidates = []
    
    # Standard descriptor prefixes to exclude
    descriptor_prefixes = ('mean_', 'min_', 'max_', 'range_', 'var_', 'std_', 'mode_', 'entropy_', 'count_', 'n_unique_')
    
    for col in numeric_cols:
        if col.startswith(descriptor_prefixes):
            continue
        if col in ['formula', 'element_counts', 'property_name']: # Common non-target identifiers
            continue
        target_candidates.append(col)
    
    # If no candidates found but 'target' exists, use it
    if not target_candidates and 'target' in df.columns:
        target_candidates = ['target']
        
    return target_candidates

def analyze_all_properties(df: pd.DataFrame) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Analyzes imbalance for all valid target properties.
    Returns two DataFrames: target_scores and compositional_scores.
    """
    target_candidates = identify_target_columns(df)
    logger.info(f"Identified target candidates: {target_candidates}")
    
    target_results = []
    comp_scores = []
    
    # Extract feature matrix for compositional score (all descriptor columns)
    # Assuming descriptors are the columns that look like descriptors
    all_cols = df.columns.tolist()
    feature_cols = [c for c in all_cols if c.startswith(('mean_', 'min_', 'max_', 'range_', 'var_', 'std_', 'mode_', 'entropy_', 'count_', 'n_unique_'))]
    
    if not feature_cols:
        logger.warning("No descriptor columns found for compositional imbalance calculation.")
    else:
        X = df[feature_cols].dropna().values
        # Calculate one global compositional score for the whole dataset
        # Or per property? The task says "Compositional Imbalance Score" (singular) for the dataset usually,
        # but could be per property subset. We calculate it once for the full dataset as a global metric.
        global_comp_score = calculate_compositional_imbalance_score(X)
        comp_scores.append({"dataset": "full", "score": global_comp_score, "feature_count": len(feature_cols)})

    for prop in target_candidates:
        res = calculate_target_imbalance_score(df, prop)
        target_results.append(res)
    
    return pd.DataFrame(target_results), pd.DataFrame(comp_scores)

def save_results(target_df: pd.DataFrame, comp_df: pd.DataFrame):
    """Saves results to CSV files in the results directory."""
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    
    target_df.to_csv(TARGET_IMBALANCE_FILE, index=False)
    logger.info(f"Target imbalance scores saved to {TARGET_IMBALANCE_FILE}")
    
    comp_df.to_csv(COMPOSITIONAL_IMBALANCE_FILE, index=False)
    logger.info(f"Compositional imbalance scores saved to {COMPOSITIONAL_IMBALANCE_FILE}")

def main():
    """Main entry point for imbalance analysis."""
    logger.info("Starting imbalance analysis (T008)...")
    try:
        df = load_data()
        logger.info(f"Loaded {len(df)} samples from {INPUT_FILE}")
        
        target_df, comp_df = analyze_all_properties(df)
        
        if target_df.empty:
            logger.warning("No target properties found to analyze.")
        
        save_results(target_df, comp_df)
        logger.info("Imbalance analysis completed successfully.")
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    except Exception as e:
        logger.exception(f"Error during imbalance analysis: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
