def load_feasibility_report() -> Dict[str, Any]:
    """
    Load the feasibility report generated by T011/T011c.
    Returns the report dictionary or exits if not found.
    """
    project_root = get_project_root()
    report_path = project_root / "data" / "results" / "feasibility_report.json"
    
    if not report_path.exists():
        logger.error(f"Feasibility report not found at {report_path}. Run T011 first.")
        sys.exit(1)
    
    with open(report_path, 'r') as f:
        return json.load(f)

def fetch_dataset_subset(capped_n: int, languages: List[str]) -> None:
    """
    Fetch the specified subset of codeparrot/github-code using streaming.
    
    Args:
        capped_n: Maximum number of chunks to download.
        languages: List of languages to fetch (e.g., ['python', 'java']).
    
    Raises:
        NetworkError: If the dataset fetch fails.
        PipelineError: If invalid parameters are provided.
    """
    if capped_n <= 0:
        raise PipelineError("capped_n must be positive")
    if not languages:
        raise PipelineError("At least one language must be specified")
    
    logger.info(f"Starting download of {capped_n} chunks for languages: {languages}")
    
    project_root = get_project_root()
    output_base = project_root / "data" / "processed"
    
    # Ensure output directories exist
    for lang in languages:
        lang_dir = output_base / f"train_{lang}"
        lang_dir.mkdir(parents=True, exist_ok=True)
    
    try:
        # Load dataset with streaming to avoid downloading full files to disk
        # We stream the entire dataset but only take the first capped_n examples
        # per language as requested by the task logic (simplified to total capped_n distributed)
        # The task says "take exactly capped_N examples". We will distribute this
        # proportionally or just take capped_N total if the dataset is filtered.
        # Given the constraint "streaming to stay within Disk storage", we stream.
        
        # Note: codeparrot/github-code is large. We stream.
        # We need to filter by language.
        
        # Strategy: Load dataset, filter by language, take N examples.
        # Since we need specific splits (train_python, val_java), we will handle logic below.
        
        # Determine split strategy based on task description:
        # "split into data/processed/train_python/ and data/processed/val_java/"
        # If only Python, just train_python.
        
        dataset_name = "codeparrot/github-code"
        
        # We will load the dataset in streaming mode.
        # We need to collect 'capped_n' examples.
        # If multiple languages are requested, we need to decide distribution.
        # The task says "take exactly capped_N examples".
        # Let's assume we want to fill the quota with the requested languages.
        # If 2 languages, we might split 50/50 or fill one then the other.
        # For simplicity and robustness, we will iterate and stop when we have N total.
        
        # However, the task implies specific directories: train_python, val_java.
        # Let's assume if Java is requested, we fill val_java, if Python, train_python.
        # We will try to get capped_N total.
        
        # Implementation:
        # 1. Create a generator for each language.
        # 2. Interleave or fill sequentially?
        # To ensure we get exactly capped_N and respect the "split" instruction:
        # If languages == ['python', 'java']:
        #   We want some in train_python, some in val_java.
        #   Let's split capped_N roughly equally if both present.
        
        count_per_lang = capped_n // len(languages)
        remainder = capped_n % len(languages)
        
        lang_counts = {}
        for i, lang in enumerate(languages):
            lang_counts[lang] = count_per_lang + (1 if i < remainder else 0)
        
        # Load dataset
        logger.info(f"Loading dataset {dataset_name} in streaming mode...")
        ds = load_dataset(dataset_name, streaming=True, split="train")
        
        # Filter and collect
        downloaded_counts = {lang: 0 for lang in languages}
        total_downloaded = 0
        
        # We need to iterate. Since we can't easily seek, we filter on the fly.
        # Note: Filtering a streaming dataset is efficient.
        
        # To handle multiple languages efficiently, we can create a filtered view for each.
        # But we need to stop when total reaches capped_N.
        
        # Simple approach: Iterate the stream, check language, write if needed.
        # Since the stream is random order from GitHub, we just take the first N that match.
        
        logger.info("Iterating dataset stream...")
        
        for idx, item in enumerate(ds):
            if total_downloaded >= capped_n:
                break
            
            # Determine language of the current item
            # The dataset usually has a 'lang' field.
            item_lang = item.get('lang', '').lower()
            
            if item_lang in languages:
                # Check if we still need more of this language
                if downloaded_counts[item_lang] < lang_counts[item_lang]:
                    # Write to disk
                    lang_dir = output_base / f"train_{item_lang}" if item_lang == 'python' else output_base / f"val_{item_lang}"
                    
                    # Ensure directory exists (redundant but safe)
                    lang_dir.mkdir(parents=True, exist_ok=True)
                    
                    # Create a unique filename
                    # Using index and lang to ensure uniqueness
                    filename = f"chunk_{idx:06d}_{item_lang}.py" if item_lang == 'python' else f"chunk_{idx:06d}_{item_lang}.java"
                    file_path = lang_dir / filename
                    
                    # Write content
                    # The 'content' field holds the code
                    content = item.get('content', '')
                    if not content:
                        logger.warning(f"Empty content at index {idx}, skipping.")
                        continue
                    
                    with open(file_path, 'w', encoding='utf-8') as f:
                        f.write(content)
                    
                    downloaded_counts[item_lang] += 1
                    total_downloaded += 1
                    logger.debug(f"Downloaded {total_downloaded}/{capped_n} ({item_lang})")
        
        logger.info(f"Download complete. Total: {total_downloaded}")
        for lang, count in downloaded_counts.items():
            logger.info(f"  {lang}: {count} files")
        
    except Exception as e:
        logger.error(f"Failed to fetch dataset: {e}")
        raise NetworkError(f"Dataset fetch failed: {e}") from e

