def main() -> None:
    """
    Main entry point for T015.
    Reads feasibility report, determines scope, and downloads data.
    """
    logger.info("Starting T015: Download Dataset")
    
    # 1. Read feasibility report
    report = load_feasibility_report()
    
    if not report.get('proceed_flag', False):
        logger.error("Feasibility report indicates we should not proceed. Aborting.")
        sys.exit(1)
    
    capped_n = report.get('capped_N')
    if not capped_n or capped_n <= 0:
        logger.error("Invalid capped_N in feasibility report.")
        sys.exit(1)
    
    # 2. Determine languages
    # Check scope_reduction or default to both
    scope_reduction = report.get('scope_reduction', '')
    
    if 'cross-language' in scope_reduction.lower() or 'java' in scope_reduction.lower():
        # If cross-language is disabled or Java specifically disabled
        # The task says: "If scope_reduction disables cross‑language, download only Python"
        languages = ['python']
        logger.info("Scope reduction detected: Downloading only Python.")
    else:
        # Default to both if feasible, or based on report hints
        # The task says "otherwise download both languages"
        languages = ['python', 'java']
        logger.info("No scope reduction: Downloading Python and Java.")
    
    # 3. Fetch dataset
    try:
        fetch_dataset_subset(capped_n, languages)
    except (NetworkError, PipelineError) as e:
        logger.error(f"Fatal error during download: {e}")
        sys.exit(1)
    
    logger.info("T015 completed successfully.")

if __name__ == "__main__":
    main()