"""
Task T018: Save preprocessed epochs to data/processed/ in HDF5/npz format.

This script loads the preprocessed epochs generated by code/01_download_preprocess.py
and saves them to the data/processed/ directory in both HDF5 (.h5) and NumPy (.npz)
formats for downstream analysis.
"""
import os
import sys
import json
import logging
import glob
from pathlib import Path

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent))

from utils.logging_config import setup_logging, get_logger
from utils.validation import validate_file_exists, exit_on_validation_failure

# Configure logger
logger = get_logger(__name__)


def load_config(config_path: str = "code/config.yaml") -> dict:
    """Load configuration from YAML file."""
    import yaml
    path = Path(config_path)
    if not path.exists():
        logger.error(f"Config file not found: {config_path}")
        return {}
    
    with open(path, 'r') as f:
        config = yaml.safe_load(f)
    
    logger.info(f"Loaded configuration from {config_path}")
    return config


def ensure_processed_directory(processed_dir: str) -> Path:
    """Ensure the processed directory exists."""
    path = Path(processed_dir)
    path.mkdir(parents=True, exist_ok=True)
    logger.info(f"Processed directory ensured: {path}")
    return path


def find_preprocessed_epochs(raw_dir: str, pattern: str = "*.fif") -> list:
    """Find preprocessed epoch files in the raw directory."""
    raw_path = Path(raw_dir)
    files = list(raw_path.glob(pattern))
    logger.info(f"Found {len(files)} epoch files in {raw_dir}")
    return files


def load_epochs_data(file_path: Path):
    """
    Load epochs data from MNE .fif file.
    Returns the epochs object and associated metadata.
    """
    try:
        import mne
        epochs = mne.read_epochs(file_path)
        logger.info(f"Loaded epochs from {file_path}: {len(epochs)} epochs, {len(epochs.ch_names)} channels")
        return epochs
    except Exception as e:
        logger.error(f"Failed to load epochs from {file_path}: {e}")
        return None


def save_epochs_to_hdf5(epochs, output_path: Path):
    """
    Save MNE epochs object to HDF5 format.
    MNE has native support for HDF5 via write_epochs.
    """
    try:
        import mne
        # MNE can write to HDF5 using the .fif extension with HDF5 backend
        # or we can use the to_data_frame approach for compatibility
        # Using the standard MNE HDF5 support
        epochs.save(output_path, overwrite=True)
        logger.info(f"Saved epochs to HDF5: {output_path}")
        return True
    except Exception as e:
        logger.error(f"Failed to save epochs to HDF5 {output_path}: {e}")
        return False


def save_epochs_to_npz(epochs, output_path: Path):
    """
    Save MNE epochs data to NumPy .npz format for broader compatibility.
    Extracts key arrays: data, times, event_id, event_times, info.
    """
    try:
        import numpy as np
        
        # Extract data arrays
        data = epochs.get_data()  # shape: (n_epochs, n_channels, n_times)
        times = epochs.times
        event_id = epochs.event_id
        
        # Convert event_id to serializable format if needed
        if isinstance(event_id, dict):
            event_id_serializable = {str(k): int(v) for k, v in event_id.items()}
        else:
            event_id_serializable = event_id
        
        # Save to npz
        np.savez_compressed(
            output_path,
            data=data,
            times=times,
            event_id=np.array([str(event_id_serializable)]),  # Store as string array
            info=str(epochs.info),  # Store info as string representation
            ch_names=np.array(epochs.ch_names),
            sfreq=epochs.info['sfreq']
        )
        logger.info(f"Saved epochs to NPZ: {output_path} (shape: {data.shape})")
        return True
    except Exception as e:
        logger.error(f"Failed to save epochs to NPZ {output_path}: {e}")
        return False


def main():
    """Main execution for saving preprocessed epochs."""
    # Load configuration
    config = load_config()
    if not config:
        logger.error("Failed to load configuration. Exiting.")
        sys.exit(1)
    
    # Get paths from config or defaults
    raw_dir = config.get('paths', {}).get('raw_data', 'data/raw')
    processed_dir = config.get('paths', {}).get('processed_data', 'data/processed')
    dataset_id = config.get('dataset', {}).get('id', 'ds000248')
    
    # Ensure processed directory exists
    processed_path = ensure_processed_directory(processed_dir)
    
    # Find preprocessed epoch files
    # Look for MNE epoch files (typically .fif or *epo.fif)
    epoch_files = find_preprocessed_epochs(raw_dir, pattern="*epo.fif")
    
    if not epoch_files:
        # Also try generic .fif files in case of different naming
        epoch_files = find_preprocessed_epochs(raw_dir, pattern="*.fif")
    
    if not epoch_files:
        logger.warning("No preprocessed epoch files found in raw directory.")
        logger.info("Expected files: data/raw/*/sub-*/**/*epo.fif or similar")
        sys.exit(0)  # Not an error, just no data yet
    
    saved_count = 0
    failed_count = 0
    
    for epoch_file in epoch_files:
        # Extract subject ID from filename or path
        # Expected pattern: .../sub-<subject_id>/...
        subject_id = "unknown"
        parts = epoch_file.parts
        for i, part in enumerate(parts):
            if part.startswith("sub-"):
                subject_id = part.replace("sub-", "")
                break
        
        # Create output filenames
        base_name = epoch_file.stem
        hdf5_output = processed_path / f"{base_name}.h5"
        npz_output = processed_path / f"{base_name}.npz"
        
        # Load epochs
        epochs = load_epochs_data(epoch_file)
        if epochs is None:
            failed_count += 1
            continue
        
        # Save to HDF5
        if save_epochs_to_hdf5(epochs, hdf5_output):
            saved_count += 1
        else:
            failed_count += 1
            continue
        
        # Save to NPZ
        if save_epochs_to_npz(epochs, npz_output):
            saved_count += 1
        else:
            failed_count += 1
    
    # Summary
    logger.info(f"Saving complete. Saved: {saved_count}, Failed: {failed_count}")
    logger.info(f"Output directory: {processed_path}")
    
    # Write manifest
    manifest = {
        "dataset_id": dataset_id,
        "saved_files": saved_count,
        "failed_files": failed_count,
        "output_directory": str(processed_path),
        "formats": ["hdf5", "npz"]
    }
    manifest_path = processed_path / "manifest.json"
    with open(manifest_path, 'w') as f:
        json.dump(manifest, f, indent=2)
    logger.info(f"Manifest written to {manifest_path}")
    
    if failed_count > 0:
        logger.warning(f"{failed_count} files failed to save.")
        sys.exit(1)
    
    sys.exit(0)


if __name__ == "__main__":
    main()
