"""
Threshold Analysis Module for US3.

Compares correlation coefficients and reliability metrics against defined thresholds
and outputs a JSON summary to data/results/threshold_results.json.

Dependencies:
- code/03_correlation_analysis.py (provides main analysis results)
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any

# Add parent directory to path for imports if running as script
if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).parent.parent))
    from code.utils.logging_config import setup_logging, get_logger
    from code.config import load_config
else:
    # Adjust for import when called as module
    try:
        from utils.logging_config import setup_logging, get_logger
        from config import load_config
    except ImportError:
        from code.utils.logging_config import setup_logging, get_logger
        from code.config import load_config

def load_analysis_results(results_path: Path) -> Dict[str, Any]:
    """
    Load the analysis results generated by 03_correlation_analysis.py.
    Expects a JSON file containing 'correlation' and 'reliability' sections.
    """
    if not results_path.exists():
        raise FileNotFoundError(f"Analysis results file not found: {results_path}")
    
    with open(results_path, 'r') as f:
        return json.load(f)

def evaluate_thresholds(results: Dict[str, Any], config: Dict[str, Any]) -> Dict[str, Any]:
    """
    Evaluate correlation and reliability metrics against thresholds.
    
    Args:
        results: Dictionary containing analysis results with keys:
                 - 'correlation': {'r_value': float, ...}
                 - 'reliability': {'coefficient': float, ...}
        config: Configuration dictionary containing threshold values.
    
    Returns:
        Dictionary with evaluation results:
        - threshold_status: 'PASS' if |r| >= threshold, else 'FAIL'
        - reliability_status: 'PASS' if coeff >= threshold, else 'LOW'
        - r_value: The observed correlation coefficient
        - reliability_coeff: The observed reliability coefficient
    """
    corr_threshold = config.get('analysis', {}).get('correlation_threshold', 0.3)
    reliability_threshold = config.get('analysis', {}).get('reliability_threshold', 0.7)
    
    # Extract values safely
    corr_data = results.get('correlation', {})
    reliability_data = results.get('reliability', {})
    
    r_value = corr_data.get('r_value', 0.0)
    reliability_coeff = reliability_data.get('coefficient', 0.0)
    
    # Evaluate thresholds
    threshold_status = 'PASS' if abs(r_value) >= corr_threshold else 'FAIL'
    reliability_status = 'PASS' if reliability_coeff >= reliability_threshold else 'LOW'
    
    return {
        'threshold_status': threshold_status,
        'reliability_status': reliability_status,
        'r_value': r_value,
        'reliability_coeff': reliability_coeff,
        'thresholds_used': {
            'correlation_threshold': corr_threshold,
            'reliability_threshold': reliability_threshold
        }
    }

def save_threshold_results(results: Dict[str, Any], output_path: Path) -> None:
    """
    Save threshold evaluation results to a JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    
    logging.info(f"Threshold results saved to {output_path}")

def main():
    """
    Main entry point for threshold analysis.
    """
    # Setup logging
    logger = setup_logging()
    logger.info("Starting threshold analysis (T034)")
    
    # Load configuration
    config = load_config()
    
    # Define paths
    base_dir = Path(__file__).parent.parent
    results_path = base_dir / 'data' / 'results' / 'analysis_results.json'
    output_path = base_dir / 'data' / 'results' / 'threshold_results.json'
    
    try:
        # Load analysis results from previous step
        logger.info(f"Loading analysis results from {results_path}")
        analysis_results = load_analysis_results(results_path)
        
        # Evaluate against thresholds
        logger.info("Evaluating thresholds")
        threshold_results = evaluate_thresholds(analysis_results, config)
        
        # Save results
        save_threshold_results(threshold_results, output_path)
        
        # Log summary
        logger.info(f"Correlation threshold status: {threshold_results['threshold_status']} (|r|={threshold_results['r_value']:.3f} >= {threshold_results['thresholds_used']['correlation_threshold']})")
        logger.info(f"Reliability status: {threshold_results['reliability_status']} (coeff={threshold_results['reliability_coeff']:.3f} >= {threshold_results['thresholds_used']['reliability_threshold']})")
        
        logger.info("Threshold analysis completed successfully")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"Required input file missing: {e}")
        return 1
    except Exception as e:
        logger.error(f"Error during threshold analysis: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())