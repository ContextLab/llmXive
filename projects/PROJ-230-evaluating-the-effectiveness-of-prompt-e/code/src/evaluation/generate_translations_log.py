"""
Aggregates all prompts, seeds, and raw outputs from the evaluation stage
into a version-controlled CSV log file.

This script scans the `data/evaluation/raw_translations/` directory,
reads the JSON files generated by the inference engine, and compiles
them into a single CSV artifact: `data/evaluation/raw_translations_log.csv`.

Columns:
  - prompt_condition: The specific prompt strategy used (e.g., 'zero_shot_basic')
  - seed: The random seed used for the request (if available)
  - raw_output: The raw text response from the LLM
  - timestamp: The ISO timestamp of when the translation was generated
"""
import os
import sys
import json
import csv
import logging
from pathlib import Path
from datetime import datetime

# Ensure parent directory is in path for imports if running as script
if 'code' not in sys.path:
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))

from src.utils.logging import get_logger

# Configure logging
logger = get_logger(__name__)

# Constants
TRANSLATIONS_DIR = Path("data/evaluation/raw_translations")
OUTPUT_LOG_PATH = Path("data/evaluation/raw_translations_log.csv")

def scan_translation_dirs(base_dir: Path) -> list:
    """
    Recursively scans the base directory for JSON files containing translation data.
    Expects directory structure: base_dir/<condition>/<id>.json

    Args:
        base_dir: The root directory containing condition subdirectories.

    Returns:
        A list of Path objects pointing to valid JSON files.
    """
    json_files = []
    if not base_dir.exists():
        logger.warning(f"Translations directory does not exist: {base_dir}")
        return json_files

    for condition_dir in base_dir.iterdir():
        if condition_dir.is_dir():
            for json_file in condition_dir.glob("*.json"):
                json_files.append(json_file)

    logger.info(f"Found {len(json_files)} translation JSON files.")
    return json_files

def extract_translation_data(json_path: Path) -> dict:
    """
    Reads a single JSON translation file and extracts the required fields.

    Expected JSON structure (based on run_inference.py output):
    {
        "prompt": "...",
        "input_code": "...",
        "output_code": "...",
        "seed": 42,
        "timestamp": "2023-10-27T10:00:00Z",
        "condition": "zero_shot_basic"
    }

    Args:
        json_path: Path to the JSON file.

    Returns:
        A dictionary with keys: prompt_condition, seed, raw_output, timestamp.
        Returns None if the file is corrupted or missing required fields.
    """
    try:
        with open(json_path, 'r', encoding='utf-8') as f:
            data = json.load(f)

        # Extract fields with fallbacks for missing keys
        condition = data.get("condition", json_path.parent.name)
        seed = data.get("seed", None)
        raw_output = data.get("output_code", "")
        timestamp = data.get("timestamp", datetime.now().isoformat())

        return {
            "prompt_condition": condition,
            "seed": seed,
            "raw_output": raw_output,
            "timestamp": timestamp
        }
    except json.JSONDecodeError as e:
        logger.error(f"Failed to decode JSON in {json_path}: {e}")
        return None
    except Exception as e:
        logger.error(f"Unexpected error processing {json_path}: {e}")
        return None

def aggregate_translations(base_dir: Path, output_path: Path):
    """
    Aggregates all translation data into a single CSV file.

    Args:
        base_dir: Directory containing condition subdirectories.
        output_path: Path where the CSV log will be written.
    """
    json_files = scan_translation_dirs(base_dir)

    if not json_files:
        logger.warning("No translation files found. Creating empty log.")
        # Ensure output directory exists even if empty
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, 'w', newline='', encoding='utf-8') as csvfile:
            writer = csv.DictWriter(csvfile, fieldnames=["prompt_condition", "seed", "raw_output", "timestamp"])
            writer.writeheader()
        return

    records = []
    skipped = 0

    for json_file in json_files:
        record = extract_translation_data(json_file)
        if record:
            records.append(record)
        else:
            skipped += 1

    if skipped > 0:
        logger.warning(f"Skipped {skipped} corrupted or invalid files.")

    logger.info(f"Aggregating {len(records)} valid records into {output_path}")

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Write to CSV
    # Note: raw_output may contain newlines, csv module handles quoting automatically
    with open(output_path, 'w', newline='', encoding='utf-8') as csvfile:
        fieldnames = ["prompt_condition", "seed", "raw_output", "timestamp"]
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)

        writer.writeheader()
        writer.writerows(records)

    logger.info(f"Successfully wrote {len(records)} rows to {output_path}")

def main():
    """
    Entry point for the script.
    """
    logger.info("Starting translation log generation (T025b).")
    aggregate_translations(TRANSLATIONS_DIR, OUTPUT_LOG_PATH)
    logger.info("Translation log generation complete.")

if __name__ == "__main__":
    main()
