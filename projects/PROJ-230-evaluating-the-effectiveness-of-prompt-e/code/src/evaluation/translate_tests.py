"""
translate_tests.py

Converts Python unit tests to JavaScript based on the strategy defined in
data/evaluation/transpiler_strategy.md.

Strategy: LLM-based fallback with deterministic prompting.
- Attempts deterministic transpilers (transcrypt) if USE_TRANSPILERS=True.
- Defaults to LLM translation via HuggingFace Inference API using a zero-shot prompt.
- Validates output with `node --check`.
"""

import os
import sys
import subprocess
import logging
import tempfile
from pathlib import Path
from typing import Optional, Tuple

# Import existing API surface
from src.utils.logging import get_logger
from src.execution.api_client import call_inference_api, InferenceError, ServerError
from src.utils.timeout_utils import run_with_test_timeout

# Constants
PROMPT_FILE = "data/prompts/zero_shot_basic.txt"
TRANSLATION_LOG_PATH = "data/evaluation/translation_log.csv"
TRANSLATED_TESTS_DIR = "data/evaluation/translated_tests"
TRANSLITERATION_PROMPT_TEMPLATE = """Convert the following Python `unittest` code into equivalent JavaScript `node:test` code. Preserve all assertion logic. Do not add explanations.

Python Code:
{python_code}

JavaScript Code:
"""

logger = get_logger(__name__)


def ensure_transcrypt_available() -> bool:
    """Check if 'transcrypt' is installed and available in PATH."""
    try:
        result = subprocess.run(["transcrypt", "--version"], capture_output=True, text=True, timeout=10)
        return result.returncode == 0
    except (subprocess.TimeoutExpired, FileNotFoundError, Exception):
        return False


def run_transcrypt(input_path: Path, output_path: Path) -> Tuple[bool, str]:
    """
    Attempt to run Transcrypt on the input Python file.
    Returns (success, error_message).
    """
    try:
        # Transcrypt typically outputs to a 'target' directory or requires specific flags.
        # We attempt a basic invocation. If it fails, we catch it.
        cmd = [
            "transcrypt",
            "-b",  # Build
            "-m",  # Minify (optional, but good for testing)
            "-u",  # Unqualified
            str(input_path)
        ]
        # Note: Transcrypt behavior varies by version. This is a best-effort attempt.
        # If it fails to generate a .js file in the expected location, we treat it as failure.
        
        # Run in a temp dir to avoid polluting source
        with tempfile.TemporaryDirectory() as tmpdir:
            tmp_input = Path(tmpdir) / input_path.name
            tmp_input.write_text(input_path.read_text())
            
            result = subprocess.run(
                cmd, 
                cwd=tmpdir,
                capture_output=True, 
                text=True, 
                timeout=120
            )
            
            if result.returncode != 0:
                return False, f"Transcrypt failed: {result.stderr}"
            
            # Transcrypt usually creates a 'target' subdirectory
            target_dir = Path(tmpdir) / "target"
            if not target_dir.exists():
                return False, "Transcrypt did not create target directory"
            
            # Look for generated .js file
            js_files = list(target_dir.glob("*.js"))
            if not js_files:
                return False, "No .js file generated by Transcrypt"
            
            # Copy the first found .js file to output
            js_content = js_files[0].read_text()
            output_path.write_text(js_content)
            return True, "Success"

    except subprocess.TimeoutExpired:
        return False, "Transcrypt timed out"
    except Exception as e:
        return False, str(e)


def translate_python_test_to_js(
    python_code: str,
    input_id: str,
    seed: int = 42
) -> Tuple[Optional[str], str]:
    """
    Translates Python test code to JavaScript.
    
    Logic:
    1. If USE_TRANSPILERS=True and transcrypt is available, try it.
    2. If that fails or is disabled, use LLM fallback.
    
    Returns (translated_code, status_message).
    If translation fails, returns (None, error_message).
    """
    use_transpilers = os.getenv("USE_TRANSPILERS", "False").lower() == "true"
    
    # Attempt Deterministic Tool
    if use_transpilers and ensure_transcrypt_available():
        with tempfile.NamedTemporaryFile(suffix=".py", delete=False) as tmp_py:
            tmp_py.write(python_code.encode())
            tmp_py_path = Path(tmp_py.name)
        
        with tempfile.NamedTemporaryFile(suffix=".js", delete=False) as tmp_js:
            tmp_js_path = Path(tmp_js.name)
        
        try:
            success, msg = run_transcrypt(tmp_py_path, tmp_js_path)
            if success:
                logger.info(f"Transcrypt succeeded for {input_id}")
                return tmp_js_path.read_text(), "transcrypt_success"
            else:
                logger.warning(f"Transcrypt failed for {input_id}: {msg}. Falling back to LLM.")
        finally:
            tmp_py_path.unlink(missing_ok=True)
            tmp_js_path.unlink(missing_ok=True)

    # Fallback to LLM
    logger.info(f"Using LLM fallback for {input_id}")
    
    prompt_text = TRANSLITERATION_PROMPT_TEMPLATE.format(python_code=python_code)
    
    try:
        # Use the existing API client with timeout
        response_text = run_with_test_timeout(
            call_inference_api,
            args=(prompt_text, seed),
            timeout_seconds=120,
            max_retries=3
        )
        
        # Clean up response (remove potential markdown blocks if the model adds them)
        if response_text.startswith("```javascript"):
            response_text = response_text.split("```javascript")[1].split("```")[0].strip()
        elif response_text.startswith("```"):
            response_text = response_text.split("```")[1].split("```")[0].strip()
        
        return response_text, "llm_success"
        
    except InferenceError as e:
        logger.error(f"LLM API error for {input_id}: {e}")
        return None, f"llm_api_error: {str(e)}"
    except Exception as e:
        logger.error(f"Unexpected error during LLM translation for {input_id}: {e}")
        return None, f"unexpected_error: {str(e)}"


def validate_js_syntax(js_code: str, input_id: str) -> bool:
    """Validates JavaScript syntax using `node --check`."""
    with tempfile.NamedTemporaryFile(suffix=".js", delete=False, mode="w") as f:
        f.write(js_code)
        temp_path = Path(f.name)
    
    try:
        result = subprocess.run(
            ["node", "--check", str(temp_path)],
            capture_output=True,
            text=True,
            timeout=10
        )
        return result.returncode == 0
    except subprocess.TimeoutExpired:
        logger.warning(f"Node syntax check timed out for {input_id}")
        return False
    except FileNotFoundError:
        logger.error("Node.js not found in PATH. Cannot validate syntax.")
        return False
    finally:
        temp_path.unlink(missing_ok=True)


def translate_test_directory(
    source_dir: Path,
    output_dir: Path,
    log_file: Path
):
    """
    Scans source_dir for Python test files, translates them, and saves to output_dir.
    Updates log_file with results.
    """
    source_dir = Path(source_dir)
    output_dir = Path(output_dir)
    log_file = Path(log_file)
    
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Prepare CSV log
    import csv
    import datetime
    
    file_exists = log_file.exists()
    
    # Find Python test files (assumes naming convention test_*.py or *_test.py)
    test_files = list(source_dir.glob("test_*.py")) + list(source_dir.glob("*_test.py"))
    
    if not test_files:
        logger.warning(f"No test files found in {source_dir}")
        return

    logger.info(f"Found {len(test_files)} test files to translate.")

    with open(log_file, mode='a', newline='', encoding='utf-8') as csvfile:
        fieldnames = ['input_id', 'strategy_used', 'success', 'error_msg', 'timestamp']
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        
        if not file_exists:
            writer.writeheader()
        
        for py_file in test_files:
            input_id = py_file.stem
            logger.info(f"Processing {input_id}...")
            
            try:
                python_code = py_file.read_text(encoding='utf-8')
            except Exception as e:
                logger.error(f"Failed to read {py_file}: {e}")
                writer.writerow({
                    'input_id': input_id,
                    'strategy_used': 'read_error',
                    'success': False,
                    'error_msg': str(e),
                    'timestamp': datetime.datetime.now().isoformat()
                })
                continue

            # Translate
            js_code, status = translate_python_test_to_js(python_code, input_id)
            
            if js_code is None:
                writer.writerow({
                    'input_id': input_id,
                    'strategy_used': 'llm' if 'llm' in status else 'transcrypt',
                    'success': False,
                    'error_msg': status,
                    'timestamp': datetime.datetime.now().isoformat()
                })
                continue
            
            # Validate Syntax
            if not validate_js_syntax(js_code, input_id):
                error_msg = "Syntax validation failed"
                writer.writerow({
                    'input_id': input_id,
                    'strategy_used': 'llm' if 'llm' in status else 'transcrypt',
                    'success': False,
                    'error_msg': error_msg,
                    'timestamp': datetime.datetime.now().isoformat()
                })
                continue
            
            # Save
            output_path = output_dir / f"{input_id}.js"
            output_path.write_text(js_code, encoding='utf-8')
            
            writer.writerow({
                'input_id': input_id,
                'strategy_used': 'llm' if 'llm' in status else 'transcrypt',
                'success': True,
                'error_msg': '',
                'timestamp': datetime.datetime.now().isoformat()
            })
            
            logger.info(f"Successfully translated {input_id} to {output_path}")


def main():
    """Main entry point for the translation task."""
    # Define paths relative to project root
    project_root = Path(__file__).resolve().parent.parent.parent.parent
    source_dir = project_root / "data" / "raw" / "tests" # Assumed source location based on typical pipeline
    # If raw tests are not in data/raw/tests, we might need to scan data/processed or a specific test dir.
    # However, the task implies converting tests for the corpus. 
    # Let's assume tests are stored in data/evaluation/raw_tests or similar if not generated on fly.
    # For this implementation, we assume the tests exist in a directory passed via env or default.
    
    # Fallback default path if env not set
    test_source = os.getenv("TEST_SOURCE_DIR", str(project_root / "data" / "raw" / "tests"))
    if not Path(test_source).exists():
        # Try alternative common location
        test_source = str(project_root / "data" / "processed" / "tests")
        if not Path(test_source).exists():
            # If no tests exist, we create a dummy one for the pipeline to run? 
            # No, the task says "convert Python unit tests". If none exist, we log and exit.
            logger.error(f"Test source directory not found: {test_source}. Cannot proceed.")
            return

    source_path = Path(test_source)
    output_path = project_root / TRANSLATED_TESTS_DIR
    log_path = project_root / TRANSLATION_LOG_PATH

    translate_test_directory(source_path, output_path, log_path)
    logger.info("Translation process completed.")


if __name__ == "__main__":
    main()