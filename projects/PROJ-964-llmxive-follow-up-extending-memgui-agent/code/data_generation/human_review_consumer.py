"""
Human Review Consumer Module

Consumes `needs_human_review.json` generated by the expert system validator.
Facilitates human review via a CLI interface and updates `review_results.json`.
Implements the 'human-in-the-loop' path of FR-007.
"""

import json
import sys
import os
from pathlib import Path
from typing import List, Dict, Any, Optional
from datetime import datetime

# Import shared utilities
from utils.config import get_project_root, get_data_dir


def get_file_paths() -> Dict[str, Path]:
    """
    Returns the absolute paths for the input and output files required for review.
    """
    root = get_project_root()
    data_dir = get_data_dir()
    return {
        "needs_review": root / "data" / "synthetic_benchmark" / "needs_human_review.json",
        "trajectories": root / "data" / "synthetic_benchmark" / "trajectories.jsonl",
        "results": data_dir / "synthetic_benchmark" / "review_results.json"
    }


def load_needs_review(path: Path) -> List[Dict[str, Any]]:
    """
    Loads the list of trajectories flagged for human review.
    Raises FileNotFoundError if the trigger file does not exist.
    """
    if not path.exists():
        raise FileNotFoundError(f"Trigger file not found: {path}")
    
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    if not isinstance(data, list):
        raise ValueError(f"Expected a list in {path}, got {type(data)}")
    
    return data


def load_trajectories(path: Path) -> Dict[str, Dict[str, Any]]:
    """
    Loads trajectories from the JSONL file into a dictionary keyed by trajectory_id.
    """
    trajectories = {}
    if not path.exists():
        # If trajectories don't exist, we can't review them, but we might still 
        # want to record the attempt.
        return trajectories

    with open(path, 'r', encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                traj = json.loads(line)
                traj_id = traj.get('trajectory_id')
                if traj_id:
                    trajectories[traj_id] = traj
            except json.JSONDecodeError:
                continue
    return trajectories


def load_existing_results(path: Path) -> Dict[str, Any]:
    """
    Loads existing review results if they exist, to preserve previous feedback.
    """
    if not path.exists():
        return {"reviews": [], "metadata": {"last_updated": None, "total_reviewed": 0}}
    
    try:
        with open(path, 'r', encoding='utf-8') as f:
            return json.load(f)
    except json.JSONDecodeError:
        return {"reviews": [], "metadata": {"last_updated": None, "total_reviewed": 0}}


def save_results(results: Dict[str, Any], path: Path) -> None:
    """
    Saves the review results to the JSON file.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(results, f, indent=2, ensure_ascii=False)


def get_human_feedback(
    traj_id: str, 
    trajectory_data: Dict[str, Any], 
    reason: str, 
    existing_review: Optional[Dict[str, Any]]
) -> Dict[str, Any]:
    """
    Presents the trajectory and reason to the user via CLI and collects feedback.
    
    Returns a feedback dictionary with:
    - trajectory_id
    - status: 'pass' | 'fail' | 'needs_modification'
    - comments
    - timestamp
    """
    print("\n" + "="*80)
    print(f"REVIEW ITEM: {traj_id}")
    print(f"REASON FLAGGED: {reason}")
    print("-"*80)
    
    # Display relevant parts of the trajectory
    if trajectory_data:
        print("TRAJECTORY SNIPPET:")
        # Show first few steps if available
        steps = trajectory_data.get('steps', [])
        for i, step in enumerate(steps[:5]):
            print(f"  Step {i}: {step}")
        if len(steps) > 5:
            print(f"  ... ({len(steps) - 5} more steps)")
    else:
        print("WARNING: Trajectory data not found for this ID.")
    
    print("-"*80)
    
    if existing_review:
        print(f"PREVIOUS STATUS: {existing_review.get('status')}")
        print(f"PREVIOUS COMMENTS: {existing_review.get('comments', 'None')}")
    
    print("\nPlease provide your review (or press Enter to keep previous):")
    print("Options: [p]ass, [f]ail, [m]odify, [s]kip (keep previous if exists)")
    
    choice = input("Decision > ").strip().lower()
    
    if choice == 's':
        if existing_review:
            return existing_review
        else:
            print("No previous review to skip to. Please make a decision.")
            return get_human_feedback(traj_id, trajectory_data, reason, None)
    
    status_map = {'p': 'pass', 'f': 'fail', 'm': 'needs_modification'}
    if choice not in status_map:
        print("Invalid choice. Please try again.")
        return get_human_feedback(traj_id, trajectory_data, reason, existing_review)
    
    status = status_map[choice]
    comments = input("Comments (optional) > ").strip()
    
    return {
        "trajectory_id": traj_id,
        "status": status,
        "comments": comments,
        "timestamp": datetime.now().isoformat(),
        "reviewer": "human_cli"
    }


def process_reviews() -> int:
    """
    Main orchestration function for the human review process.
    
    Returns:
        int: Exit code (0 for success, 1 for error, 2 for no items to review)
    """
    paths = get_file_paths()
    
    # 1. Load the trigger file
    try:
        needs_review_list = load_needs_review(paths["needs_review"])
    except FileNotFoundError:
        print("No 'needs_human_review.json' file found. Nothing to review.")
        return 2
    except Exception as e:
        print(f"Error loading needs_review file: {e}")
        return 1
    
    if not needs_review_list:
        print("The needs_review list is empty. Nothing to review.")
        return 2
    
    # 2. Load trajectories and existing results
    trajectories = load_trajectories(paths["trajectories"])
    existing_results = load_existing_results(paths["results"])
    
    # Convert existing reviews list to a dict for quick lookup
    existing_reviews_map = {r['trajectory_id']: r for r in existing_results.get('reviews', [])}
    
    reviews_to_add = []
    skipped_count = 0
    
    print(f"Found {len(needs_review_list)} items requiring review.")
    
    # 3. Iterate and collect feedback
    for item in needs_review_list:
        traj_id = item.get('trajectory_id')
        reason = item.get('reason', 'No reason provided')
        
        # Check if already reviewed
        if traj_id in existing_reviews_map:
            print(f"\n[{traj_id}] Already reviewed previously. Skipping.")
            skipped_count += 1
            continue
        
        traj_data = trajectories.get(traj_id, {})
        
        feedback = get_human_feedback(traj_id, traj_data, reason, existing_reviews_map.get(traj_id))
        reviews_to_add.append(feedback)
    
    # 4. Update results
    if reviews_to_add:
        existing_results['reviews'].extend(reviews_to_add)
        existing_results['metadata']['last_updated'] = datetime.now().isoformat()
        existing_results['metadata']['total_reviewed'] = len(existing_results['reviews'])
        
        save_results(existing_results, paths["results"])
        print(f"\nReview session complete. {len(reviews_to_add)} new reviews saved.")
    else:
        print("\nNo new reviews to save.")
    
    # 5. Cleanup: Remove the trigger file if all items are processed? 
    # Spec implies the workflow completes the OR clause. 
    # We do not delete the trigger file automatically to allow audit trails,
    # but we log completion.
    print(f"Results written to: {paths['results']}")
    
    return 0


def main():
    """
    Entry point for the human review consumer script.
    """
    try:
        exit_code = process_reviews()
        sys.exit(exit_code)
    except KeyboardInterrupt:
        print("\nReview process interrupted by user.")
        sys.exit(130)
    except Exception as e:
        print(f"Fatal error during review process: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()