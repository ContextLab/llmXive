"""
Evaluation Interfaces Module

Defines the protocol interfaces for execution runners to decouple
baseline and recall agent implementations from the evaluation logic.
"""

from abc import ABC, abstractmethod
from typing import List, Dict, Any, Optional
from utils.execution_log import TrajectoryExecutionLog


class RunnerProtocol(ABC):
    """
    Abstract base protocol for execution runners.

    This interface ensures that both baseline and recall runners
    provide a consistent API for trajectory execution and log retrieval,
    enabling unified statistical analysis and comparison.
    """

    @abstractmethod
    def run_trajectory(self, trajectory: Dict[str, Any]) -> TrajectoryExecutionLog:
        """
        Execute a single trajectory using the configured agent.

        Args:
            trajectory: A dictionary representing a single trajectory from the benchmark.
                        Expected to contain 'trajectory_id', 'steps', and 'dependency_links'.

        Returns:
            TrajectoryExecutionLog: A structured log containing step-level results,
                                    success metrics, latency, and any failure attribution.
        """
        pass

    @abstractmethod
    def get_logs(self) -> List[TrajectoryExecutionLog]:
        """
        Retrieve all execution logs accumulated during the run.

        Returns:
            List[TrajectoryExecutionLog]: A list of all trajectory execution logs
                                          generated by this runner instance.
        """
        pass