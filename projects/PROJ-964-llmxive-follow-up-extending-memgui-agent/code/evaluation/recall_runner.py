import json
import sys
import time
from pathlib import Path
from typing import List, Dict, Any, Optional, Generator

from evaluation.interfaces import RunnerProtocol
from utils.execution_log import ExecutionLog, TrajectoryExecutionLog
from utils.memory_profiler import profile_memory_latency, get_current_memory_usage
from agents.recall_agent import RecallAgent
from retrieval.index_builder import IndexBuilder
from retrieval.retriever import Retriever
from utils.config import get_project_root, get_data_dir, set_seed

class RecallRunner(RunnerProtocol):
    """
    Executes the recall-enhanced agent on the synthetic benchmark trajectories.
    
    This class implements the RunnerProtocol interface to decouple the recall
    agent execution from the baseline execution. It manages the retrieval index,
    instantiates the RecallAgent, and processes each trajectory while logging
    execution metrics.
    """

    def __init__(self, seed: int = 42, threshold: float = 0.6):
        """
        Initialize the RecallRunner.
        
        Args:
            seed: Random seed for reproducibility.
            threshold: Similarity threshold for retrieval injection.
        """
        set_seed(seed)
        self.seed = seed
        self.threshold = threshold
        self.project_root = get_project_root()
        self.data_dir = get_data_dir()
        self.agent = RecallAgent(threshold=threshold)
        self.index_builder = IndexBuilder()
        self.retriever = Retriever()
        self.logs: List[TrajectoryExecutionLog] = []
        
    def run_trajectory(self, trajectory: Dict[str, Any]) -> TrajectoryExecutionLog:
        """
        Execute a single trajectory with the recall-enhanced agent.
        
        Args:
            trajectory: A single trajectory dictionary from the benchmark.
        
        Returns:
            A TrajectoryExecutionLog containing the results.
        """
        trajectory_id = trajectory.get("trajectory_id", "unknown")
        steps = trajectory.get("steps", [])
        
        # Build index from trajectory history
        self.index_builder.reset()
        for step in steps:
            self.index_builder.add_entry(step)
        
        # Build the index
        self.index_builder.build()
        
        # Initialize the retriever with the built index
        self.retriever.set_index(self.index_builder.get_index())
        
        # Execute the trajectory with the recall agent
        start_time = time.time()
        profile_memory_latency("start")
        
        execution_log = self.agent.run_trajectory(trajectory, self.retriever)
        
        end_time = time.time()
        profile_memory_latency("end")
        
        # Create the execution log
        log = TrajectoryExecutionLog(
            trajectory_id=trajectory_id,
            agent_type="recall_enhanced",
            start_time=execution_log.start_time,
            end_time=execution_log.end_time,
            total_latency_ms=round((end_time - start_time) * 1000, 2),
            step_count=len(steps),
            success_rate=execution_log.success_rate,
            steps=execution_log.steps,
            memory_profile=execution_log.memory_profile,
            retrieval_stats=execution_log.retrieval_stats
        )
        
        self.logs.append(log)
        return log

    def get_logs(self) -> List[TrajectoryExecutionLog]:
        """
        Get all execution logs generated by this runner.
        
        Returns:
            List of TrajectoryExecutionLog objects.
        """
        return self.logs

    def run_benchmark(self, trajectories_path: Optional[str] = None) -> List[TrajectoryExecutionLog]:
        """
        Run the recall-enhanced agent on all trajectories in the benchmark.
        
        Args:
            trajectories_path: Path to the trajectories JSONL file. Defaults to
                             the standard benchmark location.
        
        Returns:
            List of TrajectoryExecutionLog objects for all trajectories.
        """
        if trajectories_path is None:
            trajectories_path = self.data_dir / "synthetic_benchmark" / "trajectories.jsonl"
        
        trajectories_path = Path(trajectories_path)
        
        if not trajectories_path.exists():
            raise FileNotFoundError(f"Trajectories file not found: {trajectories_path}")
        
        self.logs = []
        
        with open(trajectories_path, 'r', encoding='utf-8') as f:
            for line in f:
                if line.strip():
                    trajectory = json.loads(line)
                    log = self.run_trajectory(trajectory)
                    # Print progress
                    print(f"Processed trajectory: {log.trajectory_id} "
                          f"(Success: {log.success_rate:.2%}, "
                          f"Latency: {log.total_latency_ms}ms)")
        
        return self.logs

    def save_results(self, output_path: Optional[str] = None) -> None:
        """
        Save the execution logs to a JSONL file.
        
        Args:
            output_path: Path to save the results. Defaults to the standard
                        results location.
        """
        if output_path is None:
            output_path = self.data_dir / "results" / "recall_execution_logs.jsonl"
        
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        
        with open(output_path, 'w', encoding='utf-8') as f:
            for log in self.logs:
                f.write(json.dumps(log.to_dict()) + '\n')
        
        print(f"Results saved to: {output_path}")

def main():
    """Main entry point for the recall runner."""
    print("Starting Recall Runner...")
    
    # Initialize the runner
    runner = RecallRunner(seed=42, threshold=0.6)
    
    # Run the benchmark
    try:
        logs = runner.run_benchmark()
        
        # Save results
        runner.save_results()
        
        # Print summary
        print(f"\n=== Recall Runner Summary ===")
        print(f"Total trajectories processed: {len(logs)}")
        
        if logs:
            avg_success = sum(log.success_rate for log in logs) / len(logs)
            avg_latency = sum(log.total_latency_ms for log in logs) / len(logs)
            print(f"Average success rate: {avg_success:.2%}")
            print(f"Average latency: {avg_latency:.2f}ms")
            
    except Exception as e:
        print(f"Error during execution: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()