"""
Task T025: Apply Voxel-wise FDR correction (q < 0.05) and extract significant clusters.

This module implements the group-level statistical thresholding and cluster extraction
as defined in the project specification. It loads the group-level t-statistic map
generated by glm_group.py, applies Benjamini-Hochberg FDR correction, and extracts
significant clusters for further analysis.

Dependencies:
- numpy
- nibabel
- scipy
- statsmodels (for fdr_correction)
- nilearn (for image handling)
"""

import os
import sys
import logging
import json
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple

import numpy as np
import nibabel as nib
from scipy import ndimage
from nilearn.image import new_img_like
from statsmodels.stats.multitest import fdrcorrection

# Import local config
from stats_config import load_config, get_fdr_threshold, get_cluster_threshold

def setup_logging():
    """Configure logging for the FDR correction module."""
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
        handlers=[
            logging.StreamHandler(sys.stdout),
            logging.FileHandler('data/processed/fdr_correction.log')
        ]
    )
    return logging.getLogger(__name__)

def load_t_stat_map(t_stat_path: Path, logger: logging.Logger) -> nib.Nifti1Image:
    """
    Load the group-level t-statistic map.

    Args:
        t_stat_path: Path to the input t-statistic NIfTI file.
        logger: Logger instance.

    Returns:
        Loaded nibabel image object.

    Raises:
        FileNotFoundError: If the t-stat map does not exist.
        ValueError: If the file is not a valid NIfTI image.
    """
    if not t_stat_path.exists():
        raise FileNotFoundError(f"T-statistic map not found at: {t_stat_path}")

    try:
        img = nib.load(str(t_stat_path))
        logger.info(f"Successfully loaded t-stat map: {t_stat_path}")
        logger.info(f"Image shape: {img.shape}, Affine:\n{img.affine}")
        return img
    except Exception as e:
        logger.error(f"Failed to load image {t_stat_path}: {e}")
        raise

def apply_fdr_correction(t_stat_map: nib.Nifti1Image, q: float = 0.05, logger: logging.Logger = None) -> Tuple[np.ndarray, np.ndarray]:
    """
    Apply voxel-wise FDR correction to the t-statistic map.

    This uses the Benjamini-Hochberg procedure to control the False Discovery Rate.
    It returns a boolean mask of significant voxels and the corresponding
    uncorrected p-values for those voxels.

    Args:
        t_stat_map: The input t-statistic image.
        q: FDR threshold (default 0.05).
        logger: Logger instance.

    Returns:
        Tuple of (significant_mask, p_values_array) where significant_mask is
        a boolean array of the same shape as the input data.
    """
    if logger is None:
        logger = logging.getLogger(__name__)

    data = t_stat_map.get_fdata()
    mask = data != 0  # Only consider non-zero voxels (brain mask)
    t_values = data[mask]

    # Calculate uncorrected p-values from t-statistics
    # Assuming a two-tailed test. We need degrees of freedom, which depends on N subjects.
    # For a one-sample t-test, df = N - 1.
    # We estimate N from the data or use a safe default if unknown.
    # A robust way is to count non-NaN voxels if we had the design, but here we assume
    # the map is already computed. We'll estimate df based on typical small N for pilot,
    # or better: the stats_config might have N, or we infer from the t-distribution.
    # However, the most accurate way without the original design matrix is to assume
    # a large df approximation or use the exact N if available in metadata.
    # Since T024 (glm_group) generates this, let's assume we know N or infer it.
    # Let's assume N=20 for pilot (df=19) if not specified, but ideally we read it from config.
    # Actually, we can calculate p-values using the t-distribution.
    # We need df. Let's try to read from a sidecar or default to a conservative estimate.
    # For this implementation, we will assume df = 19 (N=20) as a placeholder if not found,
    # but the correct approach is to pass N or read from stats_config.
    # Let's check stats_config for N_subjects or similar.
    # If not present, we'll use a large df (100) as a conservative approximation for p-values,
    # or better: raise an error if df is critical.
    # Given the constraints, let's assume the user has set 'n_subjects' in stats_config.
    config = load_config()
    n_subjects = config.get('glm_params', {}).get('n_subjects', 20)
    df = n_subjects - 1

    if df <= 0:
        logger.warning(f"Invalid n_subjects ({n_subjects}) in config, using df=19")
        df = 19

    from scipy.stats import t as t_dist

    # Two-tailed p-values
    p_values = 2 * (1 - t_dist.cdf(np.abs(t_values), df))

    # Apply FDR correction
    # reject: boolean array indicating which hypotheses are rejected (significant)
    # pvals_corrected: adjusted p-values (optional, but we need the mask)
    reject, pvals_corrected, _, _ = fdrcorrection(p_values, alpha=q, method='indep')

    # Reconstruct the full mask
    significant_mask = np.zeros_like(data, dtype=bool)
    significant_mask[mask] = reject

    logger.info(f"Applied FDR correction (q={q}) with df={df}")
    logger.info(f"Number of significant voxels: {np.sum(significant_mask)}")

    return significant_mask, p_values

def extract_clusters(significant_mask: np.ndarray, affine: np.ndarray, 
                     cluster_threshold: int = 10, logger: logging.Logger = None) -> List[Dict[str, Any]]:
    """
    Extract connected clusters from the significant mask.

    Args:
        significant_mask: Boolean array of significant voxels.
        affine: Affine matrix of the image.
        cluster_threshold: Minimum number of voxels in a cluster (default 10).
        logger: Logger instance.

    Returns:
        List of dictionaries containing cluster metadata (label, size, center of mass, coordinates).
    """
    if logger is None:
        logger = logging.getLogger(__name__)

    if np.sum(significant_mask) == 0:
        logger.warning("No significant voxels found. Returning empty cluster list.")
        return []

    # Label connected components (6-connectivity for strictness, or 26 for looser)
    # Using 26-connectivity is common in neuroimaging for cluster formation.
    structure = ndimage.generate_binary_structure(3, 2) 
    labeled_array, num_features = ndimage.label(significant_mask, structure=structure)

    clusters = []
    for i in range(1, num_features + 1):
        cluster_indices = np.where(labeled_array == i)
        size = len(cluster_indices[0])

        if size < cluster_threshold:
            continue

        # Calculate center of mass in voxel coordinates
        com_vox = ndimage.center_of_mass(significant_mask, labeled_array, i)
        
        # Convert to MNI coordinates using affine
        com_mni = nib.affines.apply_affine(affine, com_vox)

        # Calculate mean t-value within the cluster (approximate, need original data)
        # We don't have original t-values here, so we skip or return size.
        # Ideally, we pass the t-data too. Let's assume we need to re-load or pass it.
        # For now, we just report size and coordinates.

        cluster_info = {
            "cluster_id": i,
            "size_voxels": size,
            "center_of_mass_voxel": [float(x) for x in com_vox],
            "center_of_mass_mni": [float(x) for x in com_mni],
            "x": float(com_mni[0]),
            "y": float(com_mni[1]),
            "z": float(com_mni[2])
        }
        clusters.append(cluster_info)

    # Sort by size descending
    clusters.sort(key=lambda x: x['size_voxels'], reverse=True)

    logger.info(f"Extracted {len(clusters)} clusters with size >= {cluster_threshold}")
    return clusters

def save_thresholded_map(significant_mask: np.ndarray, reference_img: nib.Nifti1Image, 
                         output_path: Path, logger: logging.Logger = None):
    """
    Save the FDR-corrected thresholded map as a NIfTI file.
    Values are 1 where significant, 0 otherwise.

    Args:
        significant_mask: Boolean mask of significant voxels.
        reference_img: Reference image for affine/header.
        output_path: Output path for the NIfTI file.
        logger: Logger instance.
    """
    if logger is None:
        logger = logging.getLogger(__name__)

    thresholded_data = significant_mask.astype(np.float32)
    thresholded_img = new_img_like(reference_img, thresholded_data)
    
    # Ensure parent directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    nib.save(thresholded_img, str(output_path))
    logger.info(f"Saved thresholded map to: {output_path}")

def save_cluster_metadata(clusters: List[Dict[str, Any]], output_path: Path, logger: logging.Logger = None):
    """
    Save cluster metadata to a JSON file.

    Args:
        clusters: List of cluster dictionaries.
        output_path: Output path for the JSON file.
        logger: Logger instance.
    """
    if logger is None:
        logger = logging.getLogger(__name__)

    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, 'w') as f:
        json.dump(clusters, f, indent=2)
    
    logger.info(f"Saved cluster metadata to: {output_path}")

def main():
    """
    Main entry point for T025.
    Reads the group t-stat map, applies FDR, extracts clusters, and saves results.
    """
    logger = setup_logging()
    
    # Configuration paths
    # Assuming the output of glm_group.py is at data/processed/group_t_stat.nii.gz
    input_t_stat_path = Path("data/processed/group_t_stat.nii.gz")
    output_thresholded_map = Path("data/processed/fdr_corrected_map.nii.gz")
    output_cluster_json = Path("data/processed/fdr_clusters.json")
    
    # Load config for parameters
    config = load_config()
    fdr_q = get_fdr_threshold(config)
    cluster_thresh = get_cluster_threshold(config)
    
    logger.info(f"Starting FDR Correction task (T025)")
    logger.info(f"Input: {input_t_stat_path}")
    logger.info(f"FDR Threshold (q): {fdr_q}")
    logger.info(f"Cluster Threshold (voxels): {cluster_thresh}")

    try:
        # 1. Load T-stat map
        t_stat_img = load_t_stat_map(input_t_stat_path, logger)
        
        # 2. Apply FDR
        significant_mask, p_vals = apply_fdr_correction(t_stat_img, q=fdr_q, logger=logger)
        
        # 3. Extract Clusters
        clusters = extract_clusters(
            significant_mask, 
            t_stat_img.affine, 
            cluster_threshold=cluster_thresh, 
            logger=logger
        )
        
        # 4. Save Thresholded Map
        save_thresholded_map(significant_mask, t_stat_img, output_thresholded_map, logger)
        
        # 5. Save Cluster Metadata
        save_cluster_metadata(clusters, output_cluster_json, logger)
        
        logger.info("T025 completed successfully.")
        
        # Summary
        if not clusters:
            logger.warning("No significant clusters found at q < 0.05.")
            # This triggers T027 logic in the pipeline (handled by the next step or T027 script)
        else:
            logger.info(f"Found {len(clusters)} significant clusters.")
            for c in clusters:
                logger.info(f"Cluster {c['cluster_id']}: Size={c['size_voxels']}, MNI=({c['x']:.1f}, {c['y']:.1f}, {c['z']:.1f})")
                
    except FileNotFoundError as e:
        logger.error(f"Input file missing: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Error during FDR correction: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()