"""
Task T015: Implement subject exclusion logic to generate valid_subjects.txt.

This script reads the motion QC log generated by preprocess.py (T014),
applies the exclusion criteria (>2mm displacement), and writes the list
of valid subjects to data/processed/valid_subjects.txt.
"""
import os
import sys
import logging
from pathlib import Path
from typing import List, Set

# Import existing utilities from utils.py
# The API surface confirms these exist in code/utils.py
from utils import check_motion_threshold, log_qc_metrics, get_motion_file

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
QC_LOG_PATH = PROJECT_ROOT / "data" / "processed" / "preprocessing.log"
VALID_SUBJECTS_OUTPUT = DATA_PROCESSED_DIR / "valid_subjects.txt"
MOTION_THRESHOLD_MM = 2.0

def load_qc_log(log_path: Path) -> dict:
    """
    Parse the preprocessing.log to extract motion metrics per subject.
    Expected format in log: "Subject {subject_id}: Max Displacement = {value}mm, Mean = {value}mm"
    or similar structured logging from process_qc_and_exclude.
    """
    if not log_path.exists():
        raise FileNotFoundError(f"QC Log not found at {log_path}. Run preprocess.py first.")

    qc_data = {}
    with open(log_path, 'r') as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            
            # Attempt to parse standard log format from utils.log_qc_metrics
            # Format: "Subject {sub_id} - Max Disp: {val}mm, Mean Disp: {val}mm, Excluded: {bool}"
            if "Subject" in line and "Max Disp" in line:
                try:
                    # Extract subject ID
                    sub_part = line.split("Subject")[1].split("-")[0].strip()
                    sub_id = sub_part
                    
                    # Extract max displacement
                    max_disp_part = line.split("Max Disp:")[1].split("mm")[0].strip()
                    max_disp = float(max_disp_part)
                    
                    # Extract exclusion status if logged, otherwise calculate
                    excluded = False
                    if "Excluded: True" in line:
                        excluded = True
                    elif "Excluded: False" in line:
                        excluded = False
                    
                    qc_data[sub_id] = {
                        "max_displacement": max_disp,
                        "excluded": excluded,
                        "reason": "Motion > 2.0mm" if max_disp > MOTION_THRESHOLD_MM else "OK"
                    }
                except (IndexError, ValueError) as e:
                    logger.warning(f"Could not parse log line: {line} ({e})")
                    continue
    
    return qc_data

def filter_valid_subjects(qc_data: dict, threshold: float = MOTION_THRESHOLD_MM) -> List[str]:
    """
    Return list of subjects that pass the motion threshold.
    """
    valid_subjects = []
    for sub_id, metrics in qc_data.items():
        if metrics["max_displacement"] <= threshold:
            valid_subjects.append(sub_id)
            logger.info(f"Subject {sub_id} included (Max Disp: {metrics['max_displacement']:.2f}mm)")
        else:
            logger.info(f"Subject {sub_id} excluded (Max Disp: {metrics['max_displacement']:.2f}mm > {threshold}mm)")
    
    return sorted(valid_subjects)

def write_valid_subjects(valid_subjects: List[str], output_path: Path):
    """
    Write the list of valid subjects to a text file, one per line.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        for sub_id in valid_subjects:
            f.write(f"{sub_id}\n")
    logger.info(f"Successfully wrote {len(valid_subjects)} valid subjects to {output_path}")

def main():
    """
    Main entry point for T015.
    1. Load QC log from data/processed/preprocessing.log
    2. Filter subjects based on motion threshold (>2mm excluded)
    3. Write valid subjects to data/processed/valid_subjects.txt
    """
    logger.info("Starting Subject Exclusion Logic (T015)...")
    
    if not QC_LOG_PATH.exists():
        logger.error(f"QC Log not found at {QC_LOG_PATH}. Please run code/preprocess.py first.")
        sys.exit(1)

    try:
        qc_data = load_qc_log(QC_LOG_PATH)
        if not qc_data:
            logger.error("No subject data found in QC log. Cannot proceed.")
            sys.exit(1)

        valid_subjects = filter_valid_subjects(qc_data)
        
        if not valid_subjects:
            logger.warning("No subjects passed the motion threshold. Output file will be empty.")
        
        write_valid_subjects(valid_subjects, VALID_SUBJECTS_OUTPUT)
        
        logger.info("T015 completed successfully.")
        
    except Exception as e:
        logger.error(f"Failed to process subject exclusion: {e}")
        raise

if __name__ == "__main__":
    main()
