class TestLoadQcLog:
    def test_parses_standard_format(self):
        """Test parsing of the standard log format generated by preprocess.py"""
        mock_log_content = """
        2023-10-27 10:00:00 - INFO - Subject sub-01 - Max Disp: 1.5mm, Mean Disp: 0.5mm, Excluded: False
        2023-10-27 10:00:01 - INFO - Subject sub-02 - Max Disp: 3.2mm, Mean Disp: 1.1mm, Excluded: True
        2023-10-27 10:00:02 - INFO - Subject sub-03 - Max Disp: 0.8mm, Mean Disp: 0.2mm, Excluded: False
        """
        
        with tempfile.NamedTemporaryFile(mode='w', delete=False, suffix='.log') as f:
            f.write(mock_log_content)
            temp_path = f.name

        try:
            result = load_qc_log(Path(temp_path))
            
            assert "sub-01" in result
            assert result["sub-01"]["max_displacement"] == 1.5
            assert result["sub-01"]["excluded"] == False
            
            assert "sub-02" in result
            assert result["sub-02"]["max_displacement"] == 3.2
            assert result["sub-02"]["excluded"] == True
            
            assert "sub-03" in result
            assert result["sub-03"]["max_displacement"] == 0.8
        finally:
            os.unlink(temp_path)

    def test_handles_missing_file(self):
        """Test that FileNotFoundError is raised for missing log"""
        with pytest.raises(FileNotFoundError):
            load_qc_log(Path("/nonexistent/path/preprocessing.log"))

    def test_skips_malformed_lines(self):
        """Test that malformed lines are skipped without crashing"""
        mock_log_content = """
        2023-10-27 10:00:00 - INFO - Subject sub-01 - Max Disp: 1.5mm, Mean Disp: 0.5mm, Excluded: False
        This is a random line without subject info
        2023-10-27 10:00:01 - INFO - Subject sub-02 - Max Disp: 3.2mm, Mean Disp: 1.1mm, Excluded: True
        """
        
        with tempfile.NamedTemporaryFile(mode='w', delete=False, suffix='.log') as f:
            f.write(mock_log_content)
            temp_path = f.name

        try:
            result = load_qc_log(Path(temp_path))
            assert len(result) == 2
            assert "sub-01" in result
            assert "sub-02" in result
        finally:
            os.unlink(temp_path)

class TestFilterValidSubjects:
    def test_filters_by_threshold(self):
        """Test that subjects > 2.0mm are excluded"""
        qc_data = {
            "sub-01": {"max_displacement": 1.0, "excluded": False},
            "sub-02": {"max_displacement": 2.0, "excluded": False}, # Exactly at threshold
            "sub-03": {"max_displacement": 2.1, "excluded": True}, # Over threshold
            "sub-04": {"max_displacement": 0.5, "excluded": False}
        }
        
        valid = filter_valid_subjects(qc_data, threshold=2.0)
        
        assert "sub-01" in valid
        assert "sub-02" in valid
        assert "sub-03" not in valid
        assert "sub-04" in valid
        assert len(valid) == 3

    def test_empty_input(self):
        """Test with empty qc_data"""
        valid = filter_valid_subjects({}, threshold=2.0)
        assert valid == []

class TestWriteValidSubjects:
    def test_writes_file_correctly(self):
        """Test that the output file is written with one subject per line"""
        valid_subjects = ["sub-01", "sub-02", "sub-03"]
        
        with tempfile.TemporaryDirectory() as tmpdir:
            output_path = Path(tmpdir) / "valid_subjects.txt"
            write_valid_subjects(valid_subjects, output_path)
            
            assert output_path.exists()
            with open(output_path, 'r') as f:
                content = f.read()
            
            assert "sub-01" in content
            assert "sub-02" in content
            assert "sub-03" in content
            # Verify newlines
            assert content.strip().split('\n') == valid_subjects