logger = get_logger(__name__)


def load_interim_lagged_mmns(data_dir: Optional[Path] = None) -> pd.DataFrame:
    """
    Load the interim lagged MMN data.
    """
    if data_dir is None:
        data_dir = get_data_dir()
    
    file_path = data_dir / "interim_lagged_mmns.csv"
    
    if not file_path.exists():
        raise FileNotFoundError(
            f"Required input file not found: {file_path}. "
            "Ensure T022 (Lagged Alignment) has been completed."
        )
    
    df = pd.read_csv(file_path)
    logger.info(f"Loaded {len(df)} rows from {file_path}")
    return df


