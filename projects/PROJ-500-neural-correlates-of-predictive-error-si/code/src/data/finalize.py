import os
import logging
from pathlib import Path
from typing import Optional, List, Tuple, Dict, Any
import pandas as pd
import numpy as np

from src.utils.logging import get_logger
from src.utils.config import get_data_dir

logger = get_logger(__name__)

def load_interim_lagged_mmns(data_dir: Optional[Path] = None) -> pd.DataFrame:
    """
    Load the intermediate lagged MMN data generated by T022.
    Expects: data/interim_lagged_mmns.csv
    """
    if data_dir is None:
        data_dir = get_data_dir()
    
    file_path = Path(data_dir) / "interim_lagged_mmns.csv"
    
    if not file_path.exists():
        raise FileNotFoundError(f"Required input file not found: {file_path}")
    
    logger.info(f"Loading interim lagged MMNs from {file_path}")
    df = pd.read_csv(file_path)
    
    required_cols = ['subject_id', 'block_id', 'mmn_amplitude', 'source_window_start_trial']
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in {file_path}: {missing_cols}")
    
    return df

