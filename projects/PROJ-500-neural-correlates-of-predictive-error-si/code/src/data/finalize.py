from typing import Optional, List, Tuple, Dict, Any
import pandas as pd
import numpy as np
import sys

# Add project root to path for imports if running as script
if __name__ == "__main__":
    project_root = Path(__file__).resolve().parent.parent.parent
    if str(project_root) not in sys.path:
        sys.path.insert(0, str(project_root))

from src.utils.logging import get_logger, log_event, log_error

logger = get_logger(__name__)

def load_interim_lagged_mmns(file_path: Path) -> pd.DataFrame:
    """
    Load the interim lagged MMN data generated by T024/T025.
    Expected columns: subject_id, block_id, mmn_amplitude, source_window_start_trial
    """
    if not file_path.exists():
        raise FileNotFoundError(f"Required file not found: {file_path}")
    
    df = pd.read_csv(file_path)
    logger.info(f"Loaded {len(df)} rows from {file_path}")
    return df

def load_accuracy_blocks(file_path: Path) -> pd.DataFrame:
    """
    Load the accuracy blocks data generated by T023/T025.
    Expected columns: subject_id, block_id, accuracy, trial_start, trial_end
    """
    if not file_path.exists():
        raise FileNotFoundError(f"Required file not found: {file_path}")
    
    df = pd.read_csv(file_path)
    logger.info(f"Loaded {len(df)} rows from {file_path}")
    return df

def load_excluded_subjects(file_path: Path) -> List[str]:
    """
    Load the list of excluded subject IDs from T016.
    Expected columns: subject_id, reason
    """
    if not file_path.exists():
        logger.warning(f"Excluded subjects file not found at {file_path}. Proceeding without exclusion filter.")
        return []
    
    df = pd.read_csv(file_path)
    excluded_ids = df['subject_id'].astype(str).tolist()
    logger.info(f"Loaded {len(excluded_ids)} excluded subject IDs from {file_path}")
    return excluded_ids

def filter_by_excluded_subjects(df: pd.DataFrame, excluded_ids: List[str], subject_col: str = 'subject_id') -> pd.DataFrame:
    """
    Filter a dataframe to remove rows where subject_id is in the excluded list.
    """
    if not excluded_ids:
        return df
    
    initial_count = len(df)
    # Ensure subject_col values are strings for comparison
    mask = ~df[subject_col].astype(str).isin(excluded_ids)
    filtered_df = df[mask]
    removed_count = initial_count - len(filtered_df)
    
    logger.info(f"Filtered out {removed_count} rows ({removed_count/initial_count*100:.2f}%) for excluded subjects.")
    return filtered_df

def validate_aligned_data(df: pd.DataFrame) -> bool:
    """
    Validate the final aligned dataset against schema requirements.
    Checks for:
    1. Presence of required columns: subject_id, block_id, mmn_amplitude, source_window_start_trial, accuracy
    2. Absence of NaN values in critical columns (mmn_amplitude, accuracy)
    """
    required_cols = ['subject_id', 'block_id', 'mmn_amplitude', 'source_window_start_trial', 'accuracy']
    missing_cols = [col for col in required_cols if col not in df.columns]
    
    if missing_cols:
        log_error(logger, f"Missing required columns in aligned data: {missing_cols}")
        return False
    
    critical_cols = ['mmn_amplitude', 'accuracy']
    for col in critical_cols:
        if df[col].isna().any():
            nan_count = df[col].isna().sum()
            log_error(logger, f"Found {nan_count} NaN values in critical column '{col}'")
            return False
    
    log_event(logger, "Aligned data validation passed.")
    return True

def run_finalization_pipeline(data_dir: Optional[Path] = None) -> Path:
    """
    Execute the T026 finalization pipeline:
    1. Load interim_lagged_mmns.csv (T025)
    2. Load accuracy_blocks.csv (T025)
    3. Load excluded_subjects.csv (T016)
    4. Merge MMN and Accuracy data on subject_id and block_id
    5. Filter out excluded subjects
    6. Validate final dataset
    7. Write aligned_data.csv
    """
    if data_dir is None:
        data_dir = Path(__file__).resolve().parent.parent.parent / "data"
    
    data_dir = Path(data_dir)
    data_dir.mkdir(parents=True, exist_ok=True)
    
    # Define paths
    interim_mmns_path = data_dir / "interim_lagged_mmns.csv"
    accuracy_blocks_path = data_dir / "accuracy_blocks.csv"
    excluded_subjects_path = data_dir / "excluded_subjects.csv"
    output_path = data_dir / "aligned_data.csv"
    
    log_event(logger, "Starting T026 Finalization Pipeline")
    
    # 1. Load inputs
    try:
        mmn_df = load_interim_lagged_mmns(interim_mmns_path)
        acc_df = load_accuracy_blocks(accuracy_blocks_path)
    except FileNotFoundError as e:
        log_error(logger, str(e))
        raise RuntimeError("Cannot proceed with T026: Missing input files from T023/T024/T025.")
    
    # 2. Load exclusions
    excluded_ids = load_excluded_subjects(excluded_subjects_path)
    
    # 3. Merge
    # Merge on subject_id and block_id
    merged_df = pd.merge(
        mmn_df, 
        acc_df, 
        on=['subject_id', 'block_id'], 
        how='inner'
    )
    
    if merged_df.empty:
        log_error(logger, "Merge resulted in empty dataframe. Check for mismatched keys.")
        raise ValueError("Merge failed: No matching records found between MMN and Accuracy data.")
    
    logger.info(f"Merged dataset shape: {merged_df.shape}")
    
    # 4. Filter excluded subjects
    if excluded_ids:
        merged_df = filter_by_excluded_subjects(merged_df, excluded_ids)
    
    # 5. Validate
    if not validate_aligned_data(merged_df):
        raise ValueError("Validation failed. Check logs for details.")
    
    # 6. Write output
    merged_df.to_csv(output_path, index=False)
    log_event(logger, f"Final aligned dataset written to {output_path}")
    logger.info(f"Final dataset shape: {merged_df.shape}")
    
    return output_path

def main():
    """
    Entry point for T026 execution.
    """
    try:
        output_file = run_finalization_pipeline()
        print(f"T026 Completed successfully. Output: {output_file}")
    except Exception as e:
        log_error(logger, f"T026 Failed: {str(e)}")
        raise

if __name__ == "__main__":
    main()
