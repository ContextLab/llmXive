def load_excluded_subjects(data_dir: Optional[Path] = None) -> List[str]:
    """
    Load the list of excluded subject IDs from the artifact generated by T016.
    """
    if data_dir is None:
        data_dir = get_data_dir()
    
    file_path = data_dir / "excluded_subjects.csv"
    
    if not file_path.exists():
        logger.warning(
            f"Excluded subjects file not found: {file_path}. "
            "Proceeding without subject filtering (no exclusions applied)."
        )
        return []
    
    df = pd.read_csv(file_path)
    if 'subject_id' not in df.columns:
        raise ValueError(
            f"Excluded subjects file {file_path} is missing 'subject_id' column."
        )
    
    excluded_ids = df['subject_id'].tolist()
    logger.info(f"Loaded {len(excluded_ids)} excluded subject IDs from {file_path}")
    return excluded_ids


def filter_by_excluded_subjects(
    mmn_df: pd.DataFrame, 
    acc_df: pd.DataFrame, 
    excluded_ids: List[str]
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Filter both DataFrames to remove rows belonging to excluded subjects.
    """
    if not excluded_ids:
        logger.info("No excluded subjects to filter.")
        return mmn_df, acc_df
    
    logger.info(f"Filtering out {len(excluded_ids)} excluded subjects.")
    
    filtered_mmn = mmn_df[~mmn_df['subject_id'].isin(excluded_ids)].copy()
    filtered_acc = acc_df[~acc_df['subject_id'].isin(excluded_ids)].copy()
    
    removed_mmn = len(mmn_df) - len(filtered_mmn)
    removed_acc = len(acc_df) - len(filtered_acc)
    
    logger.info(f"Filtered {removed_mmn} rows from MMN data and {removed_acc} rows from accuracy data.")
    
    return filtered_mmn, filtered_acc


def validate_aligned_data(df: pd.DataFrame, min_trials: int = 500) -> bool:
    """
    Perform final re-verification that the merged dataset contains no subjects/blocks
    violating the trial count threshold (<500 trials/condition).
    
    This function checks if a 'trial_count' column exists. If it does, it ensures
    no rows have values below the threshold. If the column is missing, it logs
    a warning but passes validation (assuming upstream logic handled it).
    """
    logger.info("Performing final validation of aligned data.")
    
    if 'trial_count' in df.columns:
        violations = df[df['trial_count'] < min_trials]
        if not violations.empty:
            logger.error(
                f"Validation FAILED: Found {len(violations)} rows with trial_count < {min_trials}. "
                "These should have been excluded by T016."
            )
            logger.error(violations.head())
            return False
        else:
            logger.info(f"Validation PASSED: All rows meet trial_count >= {min_trials}.")
    else:
        logger.warning(
            "Validation WARNING: 'trial_count' column not found in aligned_data. "
            "Skipping threshold check. Ensure upstream logic (T016) handled this."
        )
    
    # Check for NaN values in critical columns
    critical_cols = ['subject_id', 'block_id', 'mmn_amplitude', 'accuracy']
    missing_cols = [c for c in critical_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing critical columns in aligned data: {missing_cols}")
    
    nan_counts = df[critical_cols].isna().sum()
    if nan_counts.any():
        logger.error(f"Validation FAILED: Found NaN values in critical columns:\n{nan_counts[nan_counts > 0]}")
        return False
    
    logger.info("Validation PASSED: No NaN values in critical columns.")
    return True


def run_finalization_pipeline(
    data_dir: Optional[Path] = None,
    output_filename: str = "aligned_data.csv"
) -> str:
    """
    Orchestrates the T024 finalization steps:
    1. Load interim_lagged_mmns.csv and accuracy_blocks.csv.
    2. Load excluded_subjects.csv.
    3. Filter both datasets by excluded subjects.
    4. Merge the filtered datasets.
    5. Perform final re-verification (trial count, NaNs).
    6. Write data/aligned_data.csv.
    
    Returns the path to the output file.
    """
    if data_dir is None:
        data_dir = get_data_dir()
    
    output_path = data_dir / output_filename
    
    logger.info("Starting T024 Finalization Pipeline.")
    
    # 1. Load Inputs
    try:
        mmn_df = load_interim_lagged_mmns(data_dir)
        acc_df = load_accuracy_blocks(data_dir)
    except FileNotFoundError as e:
        logger.error(str(e))
        raise
    
    # 2. Load Exclusions
    excluded_ids = load_excluded_subjects(data_dir)
    
    # 3. Filter
    mmn_filtered, acc_filtered = filter_by_excluded_subjects(mmn_df, acc_df, excluded_ids)
    
    # 4. Merge
    # Assuming merge key is (subject_id, block_id) based on schema and task logic
    # We perform an inner join to ensure we only have blocks with both MMN and Accuracy data
    merged_df = pd.merge(
        mmn_filtered,
        acc_filtered,
        on=['subject_id', 'block_id'],
        how='inner',
        suffixes=('_mmn', '_acc')
    )
    
    # If there are duplicate column names that need to be kept (e.g. trial_count from both),
    # we might need to rename or select specific ones. Assuming standard schema:
    # mmn_df has: subject_id, block_id, mmn_amplitude, source_window_start_trial, learning_phase
    # acc_df has: subject_id, block_id, accuracy, trial_start, trial_end, trial_count
    
    # Check for required columns after merge
    required_cols = ['subject_id', 'block_id', 'mmn_amplitude', 'accuracy', 'learning_phase']
    missing = [c for c in required_cols if c not in merged_df.columns]
    if missing:
        # Try to find if they exist with suffixes
        for col in missing:
            for c in merged_df.columns:
                if col in c:
                    logger.warning(f"Column '{col}' found as '{c}'. Renaming or selecting.")
                    # If it's just a suffix issue, we might need to rename, but for now
                    # we assume the merge logic aligns correctly.
                    pass
        if missing:
            raise ValueError(f"Merged data missing required columns: {missing}")
    
    # Ensure learning_phase is present (from T022b)
    if 'learning_phase' not in merged_df.columns:
        # Fallback if T022b output wasn't merged correctly, though task says it should be.
        # We'll raise an error as this is a critical dependency.
        raise ValueError("Merged data missing 'learning_phase' column. Ensure T022b completed.")

    logger.info(f"Merged dataset shape: {merged_df.shape}")
    
    # 5. Final Re-verification
    # We assume 'trial_count' comes from the accuracy_blocks side.
    if 'trial_count' in merged_df.columns:
        if not validate_aligned_data(merged_df):
            raise RuntimeError("Final validation failed. Aborting T024.")
    else:
        logger.warning("trial_count column missing in merged data. Skipping numeric validation.")
    
    # 6. Write Output
    merged_df.to_csv(output_path, index=False)
    logger.info(f"T024 Complete. Wrote {len(merged_df)} rows to {output_path}")
    
    return str(output_path)


def main():
    """
    Entry point for running the finalization pipeline as a script.
    """
    try:
        output_file = run_finalization_pipeline()
        print(f"SUCCESS: Aligned data written to {output_file}")
        return 0
    except Exception as e:
        logger.exception("T024 Finalization Pipeline FAILED")
        print(f"FAILED: {e}")
        return 1


if __name__ == "__main__":
    import sys
    sys.exit(main())
