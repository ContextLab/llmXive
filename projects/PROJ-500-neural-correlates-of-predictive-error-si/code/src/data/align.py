# Constants for the sanity check
MIN_SOURCE_TRIALS = 10

def load_mmn_epochs() -> Optional[pd.DataFrame]:
    """
    Loads the pre-computed MMN epochs data.
    Expects data to be in data/interim_mmn_epochs.csv (generated by T020).
    Returns None if file is missing.
    """
    config = get_config()
    data_dir = Path(config.data_dir)
    input_path = data_dir / "interim_mmn_epochs.csv"

    if not input_path.exists():
        logger = get_logger(__name__)
        logger.warning(f"MMN epochs file not found at {input_path}. Skipping alignment.")
        return None

    df = pd.read_csv(input_path)
    # Ensure trial indices are integers
    if 'trial_index' in df.columns:
        df['trial_index'] = df['trial_index'].astype(int)
    return df

