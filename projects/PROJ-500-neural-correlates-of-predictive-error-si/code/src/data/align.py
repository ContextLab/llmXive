def calculate_block_accuracy(epochs_df: pd.DataFrame, block_size: int) -> pd.DataFrame:
    """
    Calculates accuracy over a configurable multi-trial block.
    This is a helper for T021, but included here for completeness if needed.
    """
    # Implementation depends on specific columns in epochs_df (e.g., 'is_correct')
    # Placeholder logic assuming 'is_correct' exists
    if 'is_correct' not in epochs_df.columns:
        raise ValueError("Column 'is_correct' not found in epochs data for accuracy calculation.")
    
    df = epochs_df.copy()
    df['trial_id'] = range(len(df))
    
    # Simple binning logic
    df['block_id'] = df['trial_id'] // block_size
    accuracy_df = df.groupby(['subject_id', 'block_id'])['is_correct'].mean().reset_index()
    accuracy_df.rename(columns={'is_correct': 'accuracy'}, inplace=True)
    
    return accuracy_df

def run_behavioral_binning_pipeline() -> bool:
    """
    Runs the behavioral binning logic (T021).
    Generates data/accuracy_blocks.csv.
    """
    logger = get_logger(__name__)
    config = get_config()
    data_dir = Path(config.data_dir)
    
    # Load raw epochs (assuming T017 produced this)
    epochs_path = data_dir / "epochs_raw.csv" # Placeholder path, adjust based on T017 output
    if not epochs_path.exists():
        logger.error(f"Raw epochs file not found at {epochs_path}. Cannot run binning.")
        return False
        
    epochs_df = pd.read_csv(epochs_path)
    block_size = get_accuracy_block_size()
    
    accuracy_df = calculate_block_accuracy(epochs_df, block_size)
    
    # Add trial range info
    accuracy_df['trial_start'] = accuracy_df['block_id'] * block_size
    accuracy_df['trial_end'] = accuracy_df['trial_start'] + block_size - 1
    
    output_path = data_dir / "accuracy_blocks.csv"
    accuracy_df.to_csv(output_path, index=False)
    logger.info(f"Behavioral binning complete. Output: {output_path}")
    return True

def run_lagged_alignment_pipeline() -> bool:
    """
    Implements T022: Lagged Alignment logic.
    Calculates MMN over a preceding fixed-length trial window (t-N to t-M)
    and aligns to the subsequent accuracy block (t to t+n).
    
    Performs T040: Lagged Window Sanity Check before writing output.
    
    Logic:
    1. Load MMN epochs (source) and Accuracy Blocks (target).
    2. For each subject and block in Accuracy Blocks:
       - Define target block window: [trial_start, trial_end]
       - Define source window: [trial_start - lag_end, trial_start - lag_start]
       - Sanity Check (T040):
         a. Ensure source window does not overlap with target window.
         b. Ensure source window contains at least MIN_SOURCE_TRIALS valid trials.
       - If checks pass, compute mean MMN amplitude in source window.
       - If checks fail, drop block and log warning.
    3. Write valid results to data/interim_lagged_mmns.csv.
    """
    logger = get_logger(__name__)
    config = get_config()
    data_dir = Path(config.data_dir)
    
    # 1. Load Data
    mmn_df = load_mmn_epochs()
    accuracy_df = load_accuracy_blocks()
    
    if mmn_df is None or accuracy_df is None:
        logger.error("Missing input data for lagged alignment. Aborting.")
        return False
    
    # 2. Get Config
    lag_start, lag_end = get_lag_window() # e.g., (10, 50) meaning 10-50 trials before target start
    # Default if not set: 10 to 50 trials back
    if lag_start is None or lag_end is None:
        lag_start, lag_end = 10, 50
    
    results = []
    skipped_count = 0
    
    # 3. Process Alignment
    # Assuming mmn_df has: subject_id, trial_index, mmn_amplitude (or similar)
    # Assuming accuracy_df has: subject_id, block_id, trial_start, trial_end
    
    for subject in accuracy_df['subject_id'].unique():
        subject_acc = accuracy_df[accuracy_df['subject_id'] == subject].copy()
        subject_mmn = mmn_df[mmn_df['subject_id'] == subject].copy()
        
        if subject_mmn.empty:
            logger.warning(f"No MMN data for subject {subject}. Skipping.")
            continue
        
        for _, block_row in subject_acc.iterrows():
            block_id = block_row['block_id']
            target_start = block_row['trial_start']
            target_end = block_row['trial_end']
            
            # Define Source Window (t-N to t-M) relative to target_start
            # e.g., if target starts at 100, and lag is 10-50, source is 50-90
            source_end = target_start - lag_start
            source_start = target_start - lag_end
            
            # --- T040: Lagged Window Sanity Check ---
            
            # Check 1: Overlap
            # Source window [source_start, source_end] vs Target [target_start, target_end]
            # Overlap exists if source_end >= target_start (which is handled by subtraction)
            # But we must ensure source_start < source_end and source_end < target_start
            if source_end >= target_start:
                logger.warning(f"Subject {subject}, Block {block_id}: Source window end ({source_end}) overlaps or touches target start ({target_start}). Dropping block.")
                skipped_count += 1
                continue
                
            if source_start >= source_end:
                logger.warning(f"Subject {subject}, Block {block_id}: Invalid source window ({source_start} to {source_end}). Dropping block.")
                skipped_count += 1
                continue
            
            # Check 2: Minimum Trials in Source Window
            source_trials = subject_mmn[
                (subject_mmn['trial_index'] >= source_start) & 
                (subject_mmn['trial_index'] <= source_end)
            ]
            
            trial_count = len(source_trials)
            if trial_count < MIN_SOURCE_TRIALS:
                logger.warning(f"Subject {subject}, Block {block_id}: Source window has only {trial_count} trials (min {MIN_SOURCE_TRIALS}). Dropping block.")
                skipped_count += 1
                continue
            
            # --- End T040 Check ---
            
            # Calculate MMN Amplitude for the source window
            # Assuming 'mmn_amplitude' column exists in mmn_df
            if 'mmn_amplitude' not in source_trials.columns:
                logger.error(f"Column 'mmn_amplitude' missing in MMN data for Subject {subject}.")
                continue
                
            mean_mmn = source_trials['mmn_amplitude'].mean()
            
            results.append({
                'subject_id': subject,
                'block_id': block_id,
                'mmn_amplitude': mean_mmn,
                'source_window_start_trial': source_start,
                'source_window_end_trial': source_end,
                'source_trial_count': trial_count
            })
    
    if not results:
        logger.warning("No valid blocks passed the sanity check. Output file will be empty.")
        output_path = data_dir / "interim_lagged_mmns.csv"
        # Create empty file with headers
        pd.DataFrame(columns=['subject_id', 'block_id', 'mmn_amplitude', 'source_window_start_trial', 'source_window_end_trial', 'source_trial_count']).to_csv(output_path, index=False)
        return True
        
    output_df = pd.DataFrame(results)
    output_path = data_dir / "interim_lagged_mmns.csv"
    output_df.to_csv(output_path, index=False)
    
    logger.info(f"Lagged alignment complete. Processed {len(results)} blocks. Skipped {skipped_count} blocks due to sanity checks.")
    logger.info(f"Output written to {output_path}")
    return True

def add_learning_phase(lagged_df: pd.DataFrame) -> pd.DataFrame:
    """
    Implements T022b: Adds 'learning_phase' column.
    Bins blocks into 'Early' or 'Late' based on block_id or cumulative trials.
    """
    df = lagged_df.copy()
    if 'block_id' not in df.columns:
        raise ValueError("block_id column required for learning phase assignment.")
    
    max_block = df['block_id'].max()
    mid_point = max_block / 2.0
    
    def classify(block_id):
        return "Early" if block_id < mid_point else "Late"
    
    df['learning_phase'] = df['block_id'].apply(classify)
    return df

def run_learning_phase_pipeline() -> bool:
    """
    Runs T022b pipeline: Loads interim_lagged_mmns, adds learning_phase, saves.
    """
    logger = get_logger(__name__)
    data_dir = Path(get_config().data_dir)
    input_path = data_dir / "interim_lagged_mmns.csv"
    
    if not input_path.exists():
        logger.error(f"Input file {input_path} not found. Cannot add learning phase.")
        return False
    
    df = pd.read_csv(input_path)
    if df.empty:
        logger.warning("Input file is empty. Saving empty output.")
        df['learning_phase'] = pd.Series(dtype=str)
    else:
        df = add_learning_phase(df)
    
    output_path = data_dir / "learning_phases.csv"
    df.to_csv(output_path, index=False)
    logger.info(f"Learning phases added. Output: {output_path}")
    return True

