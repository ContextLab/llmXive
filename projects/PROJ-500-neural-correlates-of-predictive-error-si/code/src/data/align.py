def calculate_lagged_mmns(
    mmn_epochs: pd.DataFrame,
    accuracy_blocks: pd.DataFrame,
    source_window_size: int = 50,
    target_window_size: int = 10
) -> pd.DataFrame:
    """
    Implement the Lagged Alignment logic for T024.

    Calculates MMN amplitude over a preceding 50-trial window (t-50 to t-10)
    and aligns it to the subsequent 10-trial accuracy block (t to t+10).

    Args:
        mmn_epochs: DataFrame with MMN data per trial.
        accuracy_blocks: DataFrame with 10-trial accuracy blocks.
        source_window_size: Number of trials to look back for MMN calculation (default 50).
        target_window_size: Size of the accuracy block (default 10).

    Returns:
        DataFrame with columns:
            subject_id, block_id, mmn_amplitude, source_window_start_trial
    """
    results = []

    # Sort MMN epochs by subject and trial_id to ensure correct ordering
    mmn_epochs = mmn_epochs.sort_values(['subject_id', 'trial_id'])

    for _, block in accuracy_blocks.iterrows():
        subject_id = block['subject_id']
        block_id = block['block_id']
        # The block starts at trial_start (t) and ends at trial_end (t+10)
        # We need MMN from (t - 50) to (t - 10)
        # Note: If trial_start is t, the block covers trials [t, t+10).
        # The source window should end just before the block starts.
        # The task says: "preceding 50-trial window (t-50 to t-10)".
        # If the block starts at trial `t`, the trials in the block are t, t+1, ..., t+9.
        # The window (t-50 to t-10) implies trials: t-50, t-49, ..., t-10.
        # This is a window of size 41? Or is it inclusive/exclusive?
        # "50-trial window" usually implies count=50.
        # If it ends at t-10, and has size 50, it starts at t-10-50 = t-60?
        # Let's re-read carefully: "preceding 50-trial window (t-50 to t-10)".
        # If t is the start of the accuracy block.
        # Window end = t - 10.
        # Window size = 50.
        # Window start = (t - 10) - 50 + 1 = t - 59?
        # OR does it mean the window ends at trial index `t-10` and starts at `t-50`?
        # (t-10) - (t-50) = 40 trials. That's not 50.
        # Let's assume the text "t-50 to t-10" is the exact range of trial indices relative to the block start `t`.
        # So we select trials where trial_id is in [t-50, t-10].
        # But we need a 50-trial window.
        # Maybe the block starts at `t`, and the window is the 50 trials immediately preceding the block?
        # i.e., [t-50, t-1].
        # The prompt says "(t-50 to t-10)". This is ambiguous.
        # However, the task says "Calculate MMN over a preceding 50-trial window (t-50 to t-10)".
        # If the window is 50 trials, and the range is defined as t-50 to t-10, there is a contradiction in count vs range.
        # Given "50-trial window" is the primary descriptor, I will interpret this as:
        # The window consists of the 50 trials immediately preceding the accuracy block start,
        # but shifted to ensure a gap?
        # Let's stick to the literal range provided in the prompt if possible, but ensure size 50.
        # If the block starts at `t`, the trials in the block are `t`...`t+9`.
        # The prompt says window is `t-50` to `t-10`.
        # Let's assume `trial_id` is the absolute trial number.
        # We will select trials where trial_id >= (block.trial_start - 50) AND trial_id <= (block.trial_start - 10).
        # If the count of such trials is not 50, we proceed with whatever is available (or fail if too few).
        # Actually, if the window is 50 trials, and the range is t-50 to t-10, the count is 41.
        # Perhaps the prompt meant "t-60 to t-10" for 50 trials? Or "t-50 to t-1"?
        # Let's assume the prompt's explicit range (t-50 to t-10) is the intended logic,
        # and the "50-trial window" text is a loose description of "a long window".
        # BUT, the prompt says "preceding 50-trial window".
        # Let's calculate the window start as: `block.trial_start - 50`.
        # And the window end as: `block.trial_start - 1`. (Immediately preceding).
        # Wait, the prompt explicitly says "(t-50 to t-10)".
        # If I follow the text strictly:
        # start_trial = block.trial_start - 50
        # end_trial = block.trial_start - 10
        # This is a gap of 40 trials.
        # Let's assume the prompt meant "a window of 50 trials ending at t-10".
        # Then start = t - 10 - 50 + 1 = t - 59.
        # Let's try to interpret "t-50 to t-10" as indices relative to the block start.
        # If the block starts at trial `t`, then the window is trials `t-50` through `t-10`.
        # This is a specific set of trials. I will use this range.
        # If the user meant "50 trials", they might have made a typo in the range.
        # I will implement the range `t-50` to `t-10` as written, but log a warning if the count isn't 50.
        # Actually, looking at standard lagged designs, often there is a gap.
        # Let's assume the range `t-50` to `t-10` is the intended window.

        start_trial = block['trial_start'] - 50
        end_trial = block['trial_start'] - 10

        subject_mmn = mmn_epochs[mmn_epochs['subject_id'] == subject_id]

        # Filter for the window
        # Assuming trial_id is an integer index
        window_data = subject_mmn[
            (subject_mmn['trial_id'] >= start_trial) &
            (subject_mmn['trial_id'] <= end_trial)
        ]

        if len(window_data) == 0:
            logger.warning(f"No MMN data found for subject {subject_id}, block {block_id} in window [{start_trial}, {end_trial}]")
            continue

        # Calculate mean MMN amplitude for this window
        mmn_amplitude = window_data['mmn_amplitude'].mean()

        results.append({
            'subject_id': subject_id,
            'block_id': block_id,
            'mmn_amplitude': mmn_amplitude,
            'source_window_start_trial': start_trial
        })

    result_df = pd.DataFrame(results)
    if not result_df.empty:
        # Ensure column order
        result_df = result_df[['subject_id', 'block_id', 'mmn_amplitude', 'source_window_start_trial']]
    
    return result_df

def run_lagged_alignment_pipeline(
    mmn_epochs_path: str,
    accuracy_blocks_path: str,
    output_path: str
) -> None:
    """
    Run the full lagged alignment pipeline for T024.

    1. Load MMN epochs.
    2. Load Accuracy blocks.
    3. Calculate lagged MMN.
    4. Write to data/interim_lagged_mmns.csv.

    Args:
        mmn_epochs_path: Path to MMN epochs file.
        accuracy_blocks_path: Path to accuracy blocks file.
        output_path: Path for the output CSV.
    """
    log_event("T024", "Starting Lagged Alignment Pipeline")

    try:
        # Load data
        mmn_epochs = load_mmn_epochs(mmn_epochs_path)
        accuracy_blocks = load_accuracy_blocks(accuracy_blocks_path)

        # Calculate
        lagged_data = calculate_lagged_mmns(mmn_epochs, accuracy_blocks)

        if lagged_data.empty:
            logger.warning("Lagged alignment produced no results.")
            # Still write an empty file with correct schema
            lagged_data = pd.DataFrame(columns=['subject_id', 'block_id', 'mmn_amplitude', 'source_window_start_trial'])

        # Ensure output directory exists
        Path(output_path).parent.mkdir(parents=True, exist_ok=True)

        # Write output
        lagged_data.to_csv(output_path, index=False)
        log_event("T024", f"Successfully wrote {len(lagged_data)} rows to {output_path}")

    except Exception as e:
        log_error("T024", f"Pipeline failed: {str(e)}")
        raise

