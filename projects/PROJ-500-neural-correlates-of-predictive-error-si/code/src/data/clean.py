import os
import logging
from pathlib import Path
from typing import Optional, Tuple
import pandas as pd
import numpy as np
import json

from src.utils.logging import get_logger, log_event, log_error

logger = get_logger(__name__)

# Constants for filtering
MIN_VALID_TRIALS = 10
NAN_THRESHOLD = 0.5  # If >50% of rows in a block are NaN, drop the block

def load_interim_lagged_mmns(data_dir: Path) -> Optional[pd.DataFrame]:
    """
    Load the interim lagged MMN data generated by T024.
    
    Args:
        data_dir: Path to the data directory.
        
    Returns:
        DataFrame with columns: subject_id, block_id, mmn_amplitude, source_window_start_trial
        or None if file not found.
    """
    file_path = data_dir / "interim_lagged_mmns.csv"
    if not file_path.exists():
        log_error(logger, f"File not found: {file_path}")
        return None
    
    try:
        df = pd.read_csv(file_path)
        log_event(logger, f"Loaded {len(df)} rows from interim_lagged_mmns.csv")
        return df
    except Exception as e:
        log_error(logger, f"Failed to load {file_path}: {e}")
        return None

def load_accuracy_blocks(data_dir: Path) -> Optional[pd.DataFrame]:
    """
    Load the accuracy blocks data generated by T023.
    
    Args:
        data_dir: Path to the data directory.
        
    Returns:
        DataFrame with columns: subject_id, block_id, accuracy, trial_start, trial_end
        or None if file not found.
    """
    file_path = data_dir / "accuracy_blocks.csv"
    if not file_path.exists():
        log_error(logger, f"File not found: {file_path}")
        return None
    
    try:
        df = pd.read_csv(file_path)
        log_event(logger, f"Loaded {len(df)} rows from accuracy_blocks.csv")
        return df
    except Exception as e:
        log_error(logger, f"Failed to load {file_path}: {e}")
        return None

def filter_blocks_by_trial_count(
    mmn_df: pd.DataFrame, 
    accuracy_df: pd.DataFrame,
    min_trials: int = MIN_VALID_TRIALS
) -> Tuple[pd.DataFrame, pd.DataFrame, int]:
    """
    Filter blocks that have fewer than min_trials valid trials.
    
    This function assumes that the 'block_id' in both DataFrames corresponds
    to a specific block of trials. In the context of T024/T023, the block_id
    usually represents the index of the block (e.g., 0, 1, 2...).
    
    However, the specific "valid trial count" per block is not explicitly
    stored in the standard schemas of T023/T024 as a column named 'valid_trial_count'.
    T023 calculates accuracy over 10-trial blocks. If a block was generated, 
    it implies it had trials. 
    
    To satisfy the requirement "exclusion logic for blocks with <10 valid trials",
    we must infer validity. 
    1. If accuracy is NaN, the block likely had no valid trials.
    2. If the MMN amplitude is NaN, the block likely had no valid trials for MMN.
    
    We will filter out rows where:
    - 'accuracy' is NaN (implies <10 valid trials or all rejected)
    - 'mmn_amplitude' is NaN (implies <10 valid trials for EEG)
    
    We also check if the 'trial_end' - 'trial_start' + 1 is less than min_trials
    if those columns exist and represent the actual count.
    
    Args:
        mmn_df: DataFrame from interim_lagged_mmns.csv
        accuracy_df: DataFrame from accuracy_blocks.csv
        min_trials: Minimum number of valid trials required (default 10)
        
    Returns:
        Tuple of (filtered_mmn_df, filtered_accuracy_df, count_removed)
    """
    initial_count = len(mmn_df)
    
    # Filter MMN DataFrame
    # Condition 1: Drop rows where mmn_amplitude is NaN
    mmn_valid = mmn_df['mmn_amplitude'].notna()
    
    # Condition 2: If trial_start and trial_end exist, check range
    if 'trial_start' in mmn_df.columns and 'trial_end' in mmn_df.columns:
        trial_counts = mmn_df['trial_end'] - mmn_df['trial_start'] + 1
        count_valid = trial_counts >= min_trials
        mmn_valid = mmn_valid & count_valid
    
    filtered_mmn = mmn_df[mmn_valid].copy()
    
    # Filter Accuracy DataFrame similarly
    acc_valid = accuracy_df['accuracy'].notna()
    
    if 'trial_start' in accuracy_df.columns and 'trial_end' in accuracy_df.columns:
        trial_counts = accuracy_df['trial_end'] - accuracy_df['trial_start'] + 1
        count_valid = trial_counts >= min_trials
        acc_valid = acc_valid & count_valid
    
    filtered_accuracy = accuracy_df[acc_valid].copy()
    
    # Ensure block_ids align (inner join logic essentially)
    # The task says "Filter ... to remove invalid blocks". 
    # We should ensure both dataframes only contain blocks that passed the filter.
    valid_block_ids = set(filtered_mmn['block_id'].unique())
    filtered_accuracy = filtered_accuracy[filtered_accuracy['block_id'].isin(valid_block_ids)]
    
    # Re-check MMN against updated accuracy just in case
    valid_acc_block_ids = set(filtered_accuracy['block_id'].unique())
    filtered_mmn = filtered_mmn[filtered_mmn['block_id'].isin(valid_acc_block_ids)]
    
    removed_count = initial_count - len(filtered_mmn)
    
    log_event(logger, f"Filtered {removed_count} blocks with <{min_trials} valid trials or NaN values.")
    
    return filtered_mmn, filtered_accuracy, removed_count

def handle_nan_values(
    mmn_df: pd.DataFrame, 
    accuracy_df: pd.DataFrame,
    threshold: float = NAN_THRESHOLD
) -> Tuple[pd.DataFrame, pd.DataFrame, int]:
    """
    Handle NaN values for excessive artifact rejection.
    
    If a block has excessive NaNs (e.g., if the data was split into finer
    granularities not shown here, or if we consider the block itself invalid
    if the core metric is missing), we drop it.
    
    In the context of the aggregated block data (T023/T024), a NaN in 
    'mmn_amplitude' or 'accuracy' already implies the block is invalid.
    This function specifically looks for rows where critical columns are NaN
    and removes them.
    
    Args:
        mmn_df: DataFrame from interim_lagged_mmns.csv (already filtered by count)
        accuracy_df: DataFrame from accuracy_blocks.csv (already filtered by count)
        threshold: Not used for aggregated blocks but kept for API consistency.
        
    Returns:
        Tuple of (cleaned_mmn_df, cleaned_accuracy_df, count_removed)
    """
    initial_mmn = len(mmn_df)
    initial_acc = len(accuracy_df)
    
    # Drop rows where critical columns are NaN
    # For MMN: mmn_amplitude
    mmn_clean = mmn_df.dropna(subset=['mmn_amplitude'])
    
    # For Accuracy: accuracy
    acc_clean = accuracy_df.dropna(subset=['accuracy'])
    
    # Ensure alignment again
    valid_mmn_ids = set(mmn_clean['block_id'].unique())
    acc_clean = acc_clean[acc_clean['block_id'].isin(valid_mmn_ids)]
    
    valid_acc_ids = set(acc_clean['block_id'].unique())
    mmn_clean = mmn_clean[mmn_clean['block_id'].isin(valid_acc_ids)]
    
    removed_mmn = initial_mmn - len(mmn_clean)
    removed_acc = initial_acc - len(acc_clean)
    
    log_event(logger, f"Handled NaNs: removed {removed_mmn} MMN rows and {removed_acc} Accuracy rows.")
    
    return mmn_clean, acc_clean, removed_mmn + removed_acc

def run_cleaning_pipeline(data_dir: Path, output_dir: Path) -> bool:
    """
    Run the full cleaning pipeline for T025.
    
    1. Load interim_lagged_mmns.csv and accuracy_blocks.csv.
    2. Filter blocks with <10 valid trials.
    3. Handle NaN values.
    4. Write filtered versions to data/filtered_lagged_mmns.csv and data/filtered_accuracy_blocks.csv.
    
    Args:
        data_dir: Input data directory.
        output_dir: Output directory (usually same as data_dir).
        
    Returns:
        True if successful, False otherwise.
    """
    log_event(logger, "Starting T025 Cleaning Pipeline")
    
    mmn_df = load_interim_lagged_mmns(data_dir)
    if mmn_df is None:
        log_error(logger, "Failed to load interim_lagged_mmns.csv. Cannot proceed.")
        return False
        
    acc_df = load_accuracy_blocks(data_dir)
    if acc_df is None:
        log_error(logger, "Failed to load accuracy_blocks.csv. Cannot proceed.")
        return False
    
    # Step 1: Filter by trial count
    filtered_mmn, filtered_acc, removed_count = filter_blocks_by_trial_count(mmn_df, acc_df)
    
    if filtered_mmn.empty:
        log_error(logger, "No valid blocks remaining after trial count filtering.")
        return False
    
    # Step 2: Handle NaNs
    cleaned_mmn, cleaned_acc, nan_removed = handle_nan_values(filtered_mmn, filtered_acc)
    
    if cleaned_mmn.empty:
        log_error(logger, "No valid blocks remaining after NaN handling.")
        return False
    
    # Step 3: Write outputs
    output_mmn_path = output_dir / "filtered_lagged_mmns.csv"
    output_acc_path = output_dir / "filtered_accuracy_blocks.csv"
    
    try:
        cleaned_mmn.to_csv(output_mmn_path, index=False)
        cleaned_acc.to_csv(output_acc_path, index=False)
        log_event(logger, f"Saved {output_mmn_path} ({len(cleaned_mmn)} rows)")
        log_event(logger, f"Saved {output_acc_path} ({len(cleaned_acc)} rows)")
        
        # Optional: Write a summary report
        report = {
            "task": "T025",
            "input_mmn_rows": len(mmn_df),
            "input_acc_rows": len(acc_df),
            "removed_by_trial_count": removed_count,
            "removed_by_nan": nan_removed,
            "output_mmn_rows": len(cleaned_mmn),
            "output_acc_rows": len(cleaned_acc)
        }
        report_path = output_dir / "cleaning_report.json"
        with open(report_path, 'w') as f:
            json.dump(report, f, indent=2)
        log_event(logger, f"Saved cleaning report to {report_path}")
        
        return True
    except Exception as e:
        log_error(logger, f"Failed to write output files: {e}")
        return False

def main():
    """Entry point for T025."""
    # Determine paths based on project structure
    # Assuming code/ is the root for execution, data/ is sibling
    project_root = Path(__file__).resolve().parent.parent.parent
    data_dir = project_root / "data"
    output_dir = data_dir
    
    if not data_dir.exists():
        log_error(logger, f"Data directory not found: {data_dir}")
        return 1
    
    success = run_cleaning_pipeline(data_dir, output_dir)
    return 0 if success else 1

if __name__ == "__main__":
    exit(main())
