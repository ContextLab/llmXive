def run_modeling_pipeline(
    data_path: Path,
    output_path: Path,
    formula: str = "mmn_amplitude ~ accuracy + learning_phase"
) -> Dict[str, Any]:
    """
    End-to-end pipeline: Load -> Fit LME -> FDR -> Permutation Test -> Save Results.
    
    Args:
        data_path: Path to data/aligned_data.csv
        output_path: Path to analysis/results/model_output.json
        formula: Model formula
        
    Returns:
        Results dictionary
    """
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Load Data
    logger.info(f"Loading aligned data from {data_path}")
    df = load_aligned_data(data_path)
    
    # Fit LME
    logger.info("Fitting LME model...")
    lme_result = fit_lme_model(df, formula)
    
    # Extract fixed effects
    fixed_effects = lme_result.params
    p_values = lme_result.pvalues
    
    # Apply FDR
    # We need to collect p-values for the predictors of interest (accuracy, learning_phase)
    # Not the random effects variance components
    pred_p_values = []
    pred_names = []
    
    for name, p_val in p_values.items():
        if 'accuracy' in name or 'learning_phase' in name:
            pred_p_values.append(p_val)
            pred_names.append(name)
    
    if pred_p_values:
        adj_p_values, significant = apply_fdr_correction(np.array(pred_p_values))
    else:
        adj_p_values = np.array([])
        significant = np.array([])
    
    # Permutation Test
    logger.info("Running Permutation Test...")
    perm_results = run_permutation_test(df, formula)
    
    # Compile Results
    results = {
        "model_type": "Gaussian LME",
        "formula": formula,
        "fixed_effects": {
            str(k): {
                "estimate": float(v) if not isinstance(v, (int, float)) else float(v),
                "p_value": float(p_values[k])
            }
            for k, v in fixed_effects.items()
        },
        "fdr_correction": {
            "method": "benjamini-hochberg",
            "adjusted_p_values": {k: float(v) for k, v in zip(pred_names, adj_p_values)},
            "significant": {k: bool(v) for k, v in zip(pred_names, significant)}
        },
        "permutation_test": perm_results,
        "n_observations": len(df),
        "n_subjects": df['subject_id'].nunique()
    }
    
    # Save Results
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    
    logger.info(f"Model results saved to {output_path}")
    return results

def main():
    """Main entry point for the modeling pipeline."""
    # Define paths relative to project root
    # Assuming script is run from project root or code/
    project_root = Path(__file__).parent.parent.parent
    data_path = project_root / "data" / "aligned_data.csv"
    output_path = project_root / "analysis" / "results" / "model_output.json"
    
    # Check if data exists
    if not data_path.exists():
        logger.error(f"Data file not found: {data_path}. Please run T026 first.")
        return
    
    try:
        results = run_modeling_pipeline(data_path, output_path)
        logger.info("Pipeline completed successfully.")
    except Exception as e:
        logger.error(f"Pipeline failed: {e}")
        raise

if __name__ == "__main__":
    main()
