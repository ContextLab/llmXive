"""
Utility module for filtering failed graphs from datasets based on log files.

This module provides functions to read failure logs generated by graph generation
or simulation tasks and filter out the corresponding graph IDs from datasets.
"""

import logging
from pathlib import Path
from typing import Set, List, Optional

logger = logging.getLogger(__name__)


def read_failed_graph_ids(log_path: Path) -> Set[str]:
    """
    Read graph IDs from a failure log file.

    The log file is expected to be in the format:
    GRAPH_ID|ISO8601_TIMESTAMP|ERROR_TYPE|MESSAGE

    Args:
        log_path: Path to the failure log file.

    Returns:
        A set of graph IDs that failed.
    """
    failed_ids = set()

    if not log_path.exists():
        logger.info(f"Log file {log_path} does not exist. No graphs to filter.")
        return failed_ids

    try:
        with open(log_path, 'r', encoding='utf-8') as f:
            for line_num, line in enumerate(f, 1):
                line = line.strip()
                if not line:
                    continue

                parts = line.split('|')
                if len(parts) < 4:
                    logger.warning(
                        f"Malformed log entry at line {line_num}: {line[:50]}..."
                    )
                    continue

                graph_id = parts[0].strip()
                if graph_id:
                    failed_ids.add(graph_id)

        logger.info(f"Read {len(failed_ids)} failed graph IDs from {log_path}")

    except Exception as e:
        logger.error(f"Error reading log file {log_path}: {e}")
        raise

    return failed_ids


def filter_dataframe_by_ids(df, id_column: str, failed_ids: Set[str]) -> List[dict]:
    """
    Filter a list of dictionaries (rows) by removing entries with IDs in failed_ids.

    Args:
        df: List of dictionaries representing rows of data.
        id_column: The key in each dictionary that contains the graph ID.
        failed_ids: Set of graph IDs to exclude.

    Returns:
        A new list of dictionaries with failed graphs removed.
    """
    if not failed_ids:
        return df

    filtered = [row for row in df if row.get(id_column) not in failed_ids]
    removed_count = len(df) - len(filtered)

    if removed_count > 0:
        logger.info(f"Filtered out {removed_count} graphs based on failure log.")
    else:
        logger.info("No graphs were filtered (none matched the failure log).")

    return filtered


def apply_filter_to_csv(
    input_path: Path,
    output_path: Path,
    id_column: str = 'id',
    log_path: Optional[Path] = None
) -> None:
    """
    Read a CSV, filter out rows whose ID is in the failure log, and write the result.

    Args:
        input_path: Path to the input CSV file.
        output_path: Path to write the filtered CSV file.
        id_column: Name of the column containing graph IDs.
        log_path: Path to the failure log. If None, no filtering is applied.
    """
    import csv

    if log_path is None or not log_path.exists():
        logger.info(f"No log file provided or found at {log_path}. Copying input to output.")
        # Just copy the file if no filtering is needed
        import shutil
        shutil.copy2(input_path, output_path)
        return

    failed_ids = read_failed_graph_ids(log_path)

    if not failed_ids:
        # No failures recorded, just copy
        import shutil
        shutil.copy2(input_path, output_path)
        return

    with open(input_path, 'r', encoding='utf-8') as infile, \
         open(output_path, 'w', newline='', encoding='utf-8') as outfile:

        reader = csv.DictReader(infile)
        fieldnames = reader.fieldnames

        if not fieldnames:
            raise ValueError(f"Input CSV {input_path} has no headers.")

        if id_column not in fieldnames:
            raise ValueError(f"Column '{id_column}' not found in {input_path}.")

        writer = csv.DictWriter(outfile, fieldnames=fieldnames)
        writer.writeheader()

        rows = list(reader)
        filtered_rows = filter_dataframe_by_ids(rows, id_column, failed_ids)

        writer.writerows(filtered_rows)

    logger.info(f"Filtered CSV written to {output_path}")


def main() -> None:
    """
    CLI entry point for filtering failed graphs.

    Usage:
        python -m code.utils.filter_failed_graphs --input data/raw/networks.csv \
            --output data/raw/networks_filtered.csv --log state/failedGraphs.log
    """
    import argparse

    parser = argparse.ArgumentParser(
        description="Filter failed graphs from a CSV based on a log file."
    )
    parser.add_argument(
        '--input', '-i',
        required=True,
        help='Path to the input CSV file.'
    )
    parser.add_argument(
        '--output', '-o',
        required=True,
        help='Path to write the filtered CSV file.'
    )
    parser.add_argument(
        '--log', '-l',
        required=True,
        help='Path to the failure log file.'
    )
    parser.add_argument(
        '--id-column', '-c',
        default='id',
        help='Column name containing graph IDs (default: id).'
    )

    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)
    log_path = Path(args.log)

    if not input_path.exists():
        logger.error(f"Input file not found: {input_path}")
        return 1

    try:
        apply_filter_to_csv(input_path, output_path, args.id_column, log_path)
        logger.info("Filtering completed successfully.")
    except Exception as e:
        logger.error(f"Failed to filter CSV: {e}")
        return 1

    return 0


if __name__ == '__main__':
    logging.basicConfig(level=logging.INFO)
    exit(main())