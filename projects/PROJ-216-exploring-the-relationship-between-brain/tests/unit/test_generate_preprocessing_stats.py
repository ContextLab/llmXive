import json
import os
import sys
import tempfile
from pathlib import Path
import pytest

# Add parent directory to path to import code modules
sys.path.insert(0, str(Path(__file__).parent.parent.parent / "code"))

from generate_preprocessing_stats import calculate_stats, load_subject_logs
from utils import ResourceMonitor

class TestGeneratePreprocessingStats:
    """
    Unit tests for generate_preprocessing_stats.py logic.
    Note: Full integration test requires the actual data files generated by T014a and T016a.
    These tests verify the calculation logic using mocks/patches.
    """

    def test_calculate_stats_with_valid_data(self):
        """Test calculation logic when total and successful are known."""
        logs = {
            "total_subjects": 10,
            "successful_subjects": 8
        }
        stats = calculate_stats(logs)
        
        assert stats["total_subjects"] == 10
        assert stats["successful_subjects"] == 8
        assert stats["success_rate_percentage"] == 80.0

    def test_calculate_stats_zero_total(self):
        """Test calculation logic when total is zero (edge case)."""
        logs = {
            "total_subjects": 0,
            "successful_subjects": 0
        }
        stats = calculate_stats(logs)
        
        assert stats["total_subjects"] == 0
        assert stats["successful_subjects"] == 0
        assert stats["success_rate_percentage"] == 0.0

    def test_calculate_stats_100_percent(self):
        """Test calculation logic for 100% success rate."""
        logs = {
            "total_subjects": 5,
            "successful_subjects": 5
        }
        stats = calculate_stats(logs)
        
        assert stats["success_rate_percentage"] == 100.0

    def test_calculate_stats_partial_success(self):
        """Test calculation logic for partial success."""
        logs = {
            "total_subjects": 10,
            "successful_subjects": 3
        }
        stats = calculate_stats(logs)
        
        # 3/10 = 0.3 -> 30.0%
        assert stats["success_rate_percentage"] == 30.0
        assert stats["total_subjects"] == 10
        assert stats["successful_subjects"] == 3

    def test_load_subject_logs_missing_file(self, tmp_path):
        """Test that load_subject_logs raises FileNotFoundError if file is missing."""
        # Temporarily patch the file paths
        import generate_preprocessing_stats as gps
        
        original_valid_file = gps.VALID_SUBJECTS_FILE
        original_motion_file = gps.MOTION_LOG_FILE
        
        # Create a temporary directory and set paths there
        temp_dir = tmp_path / "data" / "processed"
        temp_dir.mkdir(parents=True)
        
        gps.VALID_SUBJECTS_FILE = temp_dir / "valid_subjects.json"
        gps.MOTION_LOG_FILE = temp_dir / "motion_exclusion_log.csv"
        
        with pytest.raises(FileNotFoundError):
            load_subject_logs()
        
        # Restore original paths
        gps.VALID_SUBJECTS_FILE = original_valid_file
        gps.MOTION_LOG_FILE = original_motion_file

    def test_load_subject_logs_zero_valid_subjects(self, tmp_path):
        """Test behavior when valid_subjects.json exists but count is 0."""
        import generate_preprocessing_stats as gps
        
        original_valid_file = gps.VALID_SUBJECTS_FILE
        original_motion_file = gps.MOTION_LOG_FILE
        
        temp_dir = tmp_path / "data" / "processed"
        temp_dir.mkdir(parents=True)
        
        gps.VALID_SUBJECTS_FILE = temp_dir / "valid_subjects.json"
        gps.MOTION_LOG_FILE = temp_dir / "motion_exclusion_log.csv"
        
        # Create empty valid_subjects.json
        with open(gps.VALID_SUBJECTS_FILE, 'w') as f:
            json.dump({"subjects": [], "count": 0}, f)
        
        # Create empty motion log (header only)
        with open(gps.MOTION_LOG_FILE, 'w') as f:
            f.write("subject_id,translation_mm,rotation_mm,excluded\n")
        
        with pytest.raises(ValueError, match="No valid subjects found"):
            load_subject_logs()
        
        # Restore original paths
        gps.VALID_SUBJECTS_FILE = original_valid_file
        gps.MOTION_LOG_FILE = original_motion_file