def load_motion_exclusion_log(log_path: Path) -> Dict[str, List[str]]:
    """
    Load the motion exclusion log generated by T018a.
    Returns a dict: {"excluded": [list of subject_ids], "included": [list of subject_ids]}
    """
    if not log_path.exists():
        logger.warning(f"Motion exclusion log not found at {log_path}. Assuming no exclusions.")
        return {"excluded": [], "included": []}
    
    with open(log_path, 'r') as f:
        data = json.load(f)
    
    excluded = data.get("excluded_subjects", [])
    # We need to determine included subjects from the original list or the log
    # Assuming the log contains the full list of processed subjects and their status
    all_subjects = data.get("all_subjects", [])
    included = [s for s in all_subjects if s not in excluded]
    
    return {"excluded": excluded, "included": included}

def halt_on_zero_effective_subjects(included_subjects: List[str], output_stats_path: Path) -> None:
    """
    Halt the pipeline if no subjects remain after motion exclusion.
    Writes a stats file indicating failure.
    """
    if len(included_subjects) == 0:
        logger.critical("No subjects remain after motion exclusion. Halting pipeline.")
        stats = {
            "total_subjects_attempted": 0,
            "subjects_excluded": 0,
            "subjects_included": 0,
            "status": "failed_no_subjects",
            "message": "All subjects excluded due to motion artifacts."
        }
        with open(output_stats_path, 'w') as f:
            json.dump(stats, f, indent=2)
        sys.exit(1)

def main():
    """
    Main entry point for the preprocessing pipeline.
    1. Loads the motion exclusion log (from T018a).
    2. Identifies included subjects.
    3. Preprocesses included subjects.
    4. Logs excluded subjects but does NOT remove them from raw data.
    5. Writes preprocessing stats.
    """
    parser = argparse.ArgumentParser(description="Preprocess fMRI data for valid subjects.")
    parser.add_argument("--input", type=str, required=True, help="Path to raw data directory")
    parser.add_argument("--output", type=str, required=True, help="Path to output (interim) directory")
    parser.add_argument("--log", type=str, default="data/processed/motion_exclusion_log.json", help="Path to motion exclusion log")
    parser.add_argument("--stats", type=str, default="data/processed/preprocessing_stats.json", help="Path to output stats file")
    args = parser.parse_args()

    input_dir = Path(args.input)
    output_dir = Path(args.output)
    log_path = Path(args.log)
    stats_path = Path(args.stats)

    # Ensure output directories exist
    output_dir.mkdir(parents=True, exist_ok=True)

    # Check dependencies
    check_fsl_afni()

    # Load motion exclusion log
    exclusion_data = load_motion_exclusion_log(log_path)
    included_subjects = exclusion_data["included"]
    excluded_subjects = exclusion_data["excluded"]

    logger.info(f"Found {len(included_subjects)} subjects to include.")
    logger.info(f"Found {len(excluded_subjects)} subjects to exclude.")

    if len(included_subjects) == 0:
        # If the log exists but says 0 included, we might still proceed if the log is empty
        # but the task says "halt on zero".
        # However, if the log doesn't exist, we assume all are valid (T018a might not have run yet or failed).
        # Let's check if the log file existed.
        if log_path.exists():
            halt_on_zero_effective_subjects(included_subjects, stats_path)
        else:
            logger.warning("Motion exclusion log not found. Proceeding with all subjects in input directory.")
            # Fallback: scan input directory for subjects
            included_subjects = [d.name for d in input_dir.iterdir() if d.is_dir()]
            excluded_subjects = []

    # Write exclusion log summary to stats if not already done by T018a
    # T018b ensures excluded subjects are logged but not removed.
    # We log them here again for the preprocessing stats.
    
    processed_count = 0
    success_count = 0
    failed_count = 0

    # Process included subjects
    for subject_id in included_subjects:
        subject_path = input_dir / subject_id
        if not subject_path.exists():
            logger.warning(f"Subject {subject_id} not found in input directory. Skipping.")
            continue

        try:
            result = preprocess_subject(subject_id, input_dir, output_dir)
            if result["status"] == "success":
                success_count += 1
            processed_count += 1
        except Exception as e:
            logger.error(f"Failed to preprocess {subject_id}: {e}")
            failed_count += 1

    # Compile stats
    stats = {
        "total_subjects_attempted": len(included_subjects) + len(excluded_subjects),
        "subjects_excluded_by_motion": len(excluded_subjects),
        "subjects_included": len(included_subjects),
        "processed_successfully": success_count,
        "processed_failed": failed_count,
        "status": "success" if failed_count == 0 else "partial_success",
        "excluded_subjects_list": excluded_subjects,
        "included_subjects_list": included_subjects
    }

    # Write stats
    with open(stats_path, 'w') as f:
        json.dump(stats, f, indent=2)

    logger.info(f"Preprocessing complete. Stats written to {stats_path}")
    logger.info(f"Excluded subjects (logged, not removed): {excluded_subjects}")

if __name__ == "__main__":
    main()