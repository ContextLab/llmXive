def run_command(cmd: List[str], check: bool = True) -> subprocess.CompletedProcess:
    """Run a shell command and return the result."""
    try:
        result = subprocess.run(cmd, check=check, capture_output=True, text=True)
        return result
    except subprocess.CalledProcessError as e:
        logger.error(f"Command failed: {' '.join(cmd)}")
        logger.error(f"Error output: {e.stderr}")
        raise

def check_fsl_afni() -> bool:
    """Check if FSL and AFNI are available in the system."""
    tools = ['fsl', 'afni', 'fslmaths']
    missing = []
    for tool in tools:
        try:
            run_command(['which', tool], check=False)
        except FileNotFoundError:
            missing.append(tool)

    if missing:
        logger.warning(f"Missing tools: {missing}. Preprocessing may fail or be limited.")
        return False
    return True

