def load_motion_exclusion_log() -> List[Dict[str, Any]]:
    """
    Load the motion exclusion log generated by T018a.
    Returns a list of dictionaries with subject motion data.
    """
    if not MOTION_EXCLUSION_LOG.exists():
        logger.warning(f"Motion exclusion log not found: {MOTION_EXCLUSION_LOG}")
        return []

    records = []
    with open(MOTION_EXCLUSION_LOG, 'r') as f:
        # Assuming CSV format: subject_id, translation_mm, rotation_mm, excluded (bool)
        import csv
        reader = csv.DictReader(f)
        for row in reader:
            records.append({
                "subject_id": row["subject_id"],
                "translation_mm": float(row["translation_mm"]),
                "rotation_mm": float(row["rotation_mm"]),
                "excluded": row["excluded"].lower() == "true"
            })
    return records

def halt_on_zero_effective_subjects(effective_subjects: List[Dict[str, Any]]) -> None:
    """
    Check if the list of effective subjects is empty after motion exclusion.
    If empty, write an error log and raise a critical exception.
    """
    if not effective_subjects:
        error_msg = "No valid subjects remaining after motion exclusion"
        logger.critical(error_msg)

        # Ensure output directory exists
        DATA_PROCESSED.mkdir(parents=True, exist_ok=True)

        # Write error log with specific prefix as required
        with open(MOTION_EXCLUSION_ERROR_LOG, 'a') as f:
            f.write(f"[MOTION_EXCLUSION_ERROR] {error_msg}\n")

        raise RuntimeError(error_msg)

def main():
    """
    Main entry point for the preprocessing pipeline with motion exclusion logic.
    This function orchestrates the flow: load valid subjects -> preprocess -> check motion -> halt if 0.
    """
    # 1. Load subjects from download validation (T015)
    # Assuming a file exists from T015
    valid_subjects_file = DATA_PROCESSED / "valid_subjects.json"
    if not valid_subjects_file.exists():
        logger.error("Valid subjects file not found. Run T015 first.")
        sys.exit(1)

    with open(valid_subjects_file, 'r') as f:
        valid_data = json.load(f)
        subjects = valid_data.get("subjects", [])

    if not subjects:
        logger.error("No valid subjects found in download validation.")
        sys.exit(1)

    logger.info(f"Starting preprocessing for {len(subjects)} subjects.")

    # 2. Process subjects and collect motion data (Simulated for T018b context)
    # In a real run, T017a would have generated motion metrics.
    # T018a would have generated motion_exclusion_log.csv.
    # We load that log here to determine effective subjects.
    motion_log = load_motion_exclusion_log()
    excluded_ids = {r["subject_id"] for r in motion_log if r["excluded"]}
    
    effective_subjects = [s for s in subjects if s["id"] not in excluded_ids]

    logger.info(f"Effective subjects after motion exclusion: {len(effective_subjects)}")

    # 3. HALT LOGIC (T018b)
    halt_on_zero_effective_subjects(effective_subjects)

    logger.info("Preprocessing pipeline completed successfully with effective subjects.")
    return effective_subjects

if __name__ == "__main__":
    main()