"""
Generate preprocessing statistics artifact.
This script aggregates logs from the preprocessing run and writes
data/processed/preprocessing_stats.json.
"""
import json
import os
import sys
from pathlib import Path
from typing import Dict, Any, List

# Import ResourceMonitor from utils as per API surface
from utils import ResourceMonitor


def load_subject_logs(log_dir: Path) -> List[Dict[str, Any]]:
    """
    Scan log_dir for JSON log files generated by the preprocessing step.
    Returns a list of parsed log dicts.
    """
    logs = []
    if not log_dir.exists():
        return logs
    
    for file_path in log_dir.glob("*.json"):
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
                logs.append(data)
        except (json.JSONDecodeError, IOError):
            # Skip corrupted logs
            continue
    return logs


def calculate_stats(logs: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Calculate aggregate statistics from the list of subject logs.
    
    Expected log schema (from preprocess.py):
    {
        "subject_id": str,
        "status": "success" | "failed" | "excluded",
        "runtime_seconds": float,
        "ram_mb": float,
        "reason": str (optional)
    }
    """
    total_subjects = len(logs)
    successful = sum(1 for l in logs if l.get("status") == "success")
    failed = sum(1 for l in logs if l.get("status") == "failed")
    excluded = sum(1 for l in logs if l.get("status") == "excluded")
    
    total_runtime = sum(l.get("runtime_seconds", 0.0) for l in logs)
    total_ram_mb = sum(l.get("ram_mb", 0.0) for l in logs)
    
    peak_ram_mb = max((l.get("ram_mb", 0.0) for l in logs), default=0.0)
    
    stats = {
        "total_subjects": total_subjects,
        "successful_preprocessing": successful,
        "failed_preprocessing": failed,
        "excluded_by_motion": excluded,
        "total_runtime_seconds": total_runtime,
        "peak_ram_mb": peak_ram_mb,
        "success_rate": successful / total_subjects if total_subjects > 0 else 0.0
    }
    
    return stats


def main():
    """
    Main entry point to generate the preprocessing stats JSON.
    """
    # Paths relative to project root
    project_root = Path(__file__).resolve().parent.parent
    log_dir = project_root / "data" / "interim" / "logs"
    output_path = project_root / "data" / "processed" / "preprocessing_stats.json"
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Load logs
    logs = load_subject_logs(log_dir)
    
    if not logs:
        # If no logs found, create a minimal stats file indicating 0 subjects
        # This prevents the pipeline from crashing if no data was processed yet
        stats = {
            "total_subjects": 0,
            "successful_preprocessing": 0,
            "failed_preprocessing": 0,
            "excluded_by_motion": 0,
            "total_runtime_seconds": 0.0,
            "peak_ram_mb": 0.0,
            "success_rate": 0.0,
            "note": "No preprocessing logs found in data/interim/logs"
        }
    else:
        stats = calculate_stats(logs)
    
    # Write output
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(stats, f, indent=2)
    
    print(f"Preprocessing stats written to: {output_path}")
    print(f"Total subjects processed: {stats['total_subjects']}")
    print(f"Success rate: {stats['success_rate']:.2%}")


if __name__ == "__main__":
    main()