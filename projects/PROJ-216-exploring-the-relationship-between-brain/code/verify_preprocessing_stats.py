import os
import sys
import json
from pathlib import Path
from typing import Any, Dict

def verify_schema(file_path: str) -> bool:
    """
    Verify that the preprocessing stats file exists and contains the required schema:
    {
        "total_subjects": int,
        "successful_subjects": int,
        "success_rate_percentage": float
    }
    
    Args:
        file_path: Path to the preprocessing_stats.json file
        
    Returns:
        True if schema is valid, False otherwise
    """
    required_keys = ["total_subjects", "successful_subjects", "success_rate_percentage"]
    expected_types = {
        "total_subjects": int,
        "successful_subjects": int,
        "success_rate_percentage": float
    }
    
    if not os.path.exists(file_path):
        print(f"ERROR: File not found: {file_path}")
        return False
    
    try:
        with open(file_path, 'r') as f:
            data = json.load(f)
    except json.JSONDecodeError as e:
        print(f"ERROR: Invalid JSON in {file_path}: {e}")
        return False
    
    # Check for required keys
    missing_keys = [key for key in required_keys if key not in data]
    if missing_keys:
        print(f"ERROR: Missing required keys in {file_path}: {missing_keys}")
        return False
    
    # Check types
    type_errors = []
    for key, expected_type in expected_types.items():
        if not isinstance(data[key], expected_type):
            type_errors.append(f"{key}: expected {expected_type.__name__}, got {type(data[key]).__name__}")
    
    if type_errors:
        print(f"ERROR: Type mismatches in {file_path}: {type_errors}")
        return False
    
    # Validate values
    if data["total_subjects"] < 0:
        print(f"ERROR: total_subjects cannot be negative in {file_path}")
        return False
        
    if data["successful_subjects"] < 0:
        print(f"ERROR: successful_subjects cannot be negative in {file_path}")
        return False
        
    if data["successful_subjects"] > data["total_subjects"]:
        print(f"ERROR: successful_subjects cannot exceed total_subjects in {file_path}")
        return False
        
    if not (0.0 <= data["success_rate_percentage"] <= 100.0):
        print(f"ERROR: success_rate_percentage must be between 0 and 100 in {file_path}")
        return False
    
    print(f"SUCCESS: Schema validation passed for {file_path}")
    print(f"  total_subjects: {data['total_subjects']}")
    print(f"  successful_subjects: {data['successful_subjects']}")
    print(f"  success_rate_percentage: {data['success_rate_percentage']:.2f}%")
    return True

def main():
    """Main entry point for verification script."""
    stats_path = Path("data/processed/preprocessing_stats.json")
    
    if not stats_path.exists():
        print(f"CRITICAL: Preprocessing stats file not found at {stats_path}")
        print("This file should have been generated by T017b (Execute Preprocessing Pipeline).")
        sys.exit(1)
    
    success = verify_schema(str(stats_path))
    
    if not success:
        print("VERIFICATION FAILED: The preprocessing stats file does not meet requirements.")
        sys.exit(1)
    
    print("VERIFICATION PASSED: Preprocessing stats artifact is valid.")
    sys.exit(0)

if __name__ == "__main__":
    main()