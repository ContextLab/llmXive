"""
Task T019a: Verify Preprocessing Stats Artifact
Verifies the existence and schema of data/processed/preprocessing_stats.json
generated by T017d.
"""
import os
import sys
import json
from pathlib import Path
from typing import Any, Dict

# Constants
ARTIFACT_PATH = Path("data/processed/preprocessing_stats.json")
REQUIRED_KEYS = {"total_subjects", "processed_subjects", "excluded_subjects", "success_rate"}

def verify_schema(data: Dict[str, Any]) -> bool:
    """
    Verify the schema of the preprocessing stats artifact.
    
    Args:
        data: The loaded JSON data from preprocessing_stats.json
        
    Returns:
        bool: True if schema is valid, False otherwise
    """
    if not isinstance(data, dict):
        print(f"ERROR: Artifact is not a dictionary. Type: {type(data)}")
        return False

    missing_keys = REQUIRED_KEYS - set(data.keys())
    if missing_keys:
        print(f"ERROR: Missing required keys: {missing_keys}")
        return False

    # Validate types
    if not isinstance(data.get("total_subjects"), int):
        print(f"ERROR: 'total_subjects' must be an integer. Got: {type(data.get('total_subjects'))}")
        return False

    if not isinstance(data.get("processed_subjects"), int):
        print(f"ERROR: 'processed_subjects' must be an integer. Got: {type(data.get('processed_subjects'))}")
        return False

    if not isinstance(data.get("excluded_subjects"), int):
        print(f"ERROR: 'excluded_subjects' must be an integer. Got: {type(data.get('excluded_subjects'))}")
        return False

    if not isinstance(data.get("success_rate"), (int, float)):
        print(f"ERROR: 'success_rate' must be a number. Got: {type(data.get('success_rate'))}")
        return False

    # Validate logical consistency
    total = data["total_subjects"]
    processed = data["processed_subjects"]
    excluded = data["excluded_subjects"]

    if total != processed + excluded:
        print(f"ERROR: Inconsistent counts: total ({total}) != processed ({processed}) + excluded ({excluded})")
        return False

    if total > 0:
        expected_rate = processed / total
        if abs(data["success_rate"] - expected_rate) > 0.001:
            print(f"ERROR: Success rate mismatch. Expected {expected_rate:.4f}, got {data['success_rate']:.4f}")
            return False

    return True

def main() -> int:
    """
    Main entry point for verification.
    
    Returns:
        int: 0 if verification passes, 1 if it fails
    """
    print(f"Verifying artifact: {ARTIFACT_PATH}")

    if not ARTIFACT_PATH.exists():
        print(f"FAIL: Artifact does not exist at {ARTIFACT_PATH}")
        return 1

    try:
        with open(ARTIFACT_PATH, 'r') as f:
            data = json.load(f)
    except json.JSONDecodeError as e:
        print(f"FAIL: Invalid JSON in artifact: {e}")
        return 1
    except Exception as e:
        print(f"FAIL: Error reading artifact: {e}")
        return 1

    if verify_schema(data):
        print("SUCCESS: Artifact exists and schema is valid.")
        print(f"  Total Subjects: {data['total_subjects']}")
        print(f"  Processed: {data['processed_subjects']}")
        print(f"  Excluded: {data['excluded_subjects']}")
        print(f"  Success Rate: {data['success_rate']:.2%}")
        return 0
    else:
        print("FAIL: Artifact schema validation failed.")
        return 1

if __name__ == "__main__":
    sys.exit(main())