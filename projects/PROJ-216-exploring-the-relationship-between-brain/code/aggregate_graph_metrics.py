"""
Aggregate Graph Metrics Task (T026).

This module aggregates computed graph metrics from individual subject files
into a single CSV file: data/processed/graph_metrics.csv.

It reads JSON metric files generated by code/graph_metrics.py for each
preprocessed subject and consolidates them into the required format.
"""

import os
import sys
import csv
import json
from pathlib import Path
from typing import List, Dict, Any

# Constants
PROJECT_ROOT = Path(__file__).parent.parent
PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
INTERIM_DIR = PROJECT_ROOT / "data" / "interim"
OUTPUT_FILE = PROCESSED_DIR / "graph_metrics.csv"

# Metrics expected from graph_metrics.py
EXPECTED_METRICS = [
    "global_efficiency",
    "clustering_coefficient",
    "modularity_louvain_res1",
    "modularity_louvain_res2",
    "modularity_louvain_res3"
]

def load_preprocessed_subjects() -> List[Dict[str, Any]]:
    """
    Scan the interim directory for preprocessed subject data.
    Returns a list of subject dictionaries containing their IDs and paths.
    """
    if not INTERIM_DIR.exists():
        raise FileNotFoundError(f"Interim directory not found: {INTERIM_DIR}")

    subjects = []
    for item in INTERIM_DIR.iterdir():
        if item.is_dir() and item.name.startswith("sub_"):
            # Look for the metrics file generated by graph_metrics.py
            metrics_file = item / "metrics.json"
            if metrics_file.exists():
                subjects.append({
                    "id": item.name,
                    "metrics_path": metrics_file
                })
            else:
                # Check for legacy naming or different structure
                # graph_metrics.py might have saved directly to the subject dir
                pass

    if not subjects:
        # Fallback: scan for any JSON files that look like metrics
        for item in INTERIM_DIR.rglob("*.json"):
            if "metrics" in item.name.lower() or "graph" in item.name.lower():
                # Extract subject ID from parent or filename
                parent_name = item.parent.name
                if parent_name.startswith("sub_"):
                    subjects.append({
                        "id": parent_name,
                        "metrics_path": item
                    })

    # Deduplicate by subject ID
    seen_ids = set()
    unique_subjects = []
    for s in subjects:
        if s["id"] not in seen_ids:
            seen_ids.add(s["id"])
            unique_subjects.append(s)

    return unique_subjects

def aggregate_metrics_to_csv(subjects: List[Dict[str, Any]]) -> str:
    """
    Read metrics from each subject's JSON file and write them to a CSV.

    Args:
        subjects: List of subject dicts with 'id' and 'metrics_path'.

    Returns:
        Path to the generated CSV file.
    """
    if not PROCESSED_DIR.exists():
        PROCESSED_DIR.mkdir(parents=True, exist_ok=True)

    rows = []

    for subject in subjects:
        subject_id = subject["id"]
        metrics_path = subject["metrics_path"]

        try:
            with open(metrics_path, 'r') as f:
                metrics_data = json.load(f)

            # The metrics file might be a single dict or a list
            if isinstance(metrics_data, dict):
                # Assume keys are metric names
                for metric_name, value in metrics_data.items():
                    if metric_name in EXPECTED_METRICS or isinstance(value, (int, float)):
                        rows.append({
                            "subject_id": subject_id,
                            "metric_name": metric_name,
                            "value": float(value)
                        })
            elif isinstance(metrics_data, list):
                # Handle list of metrics
                for item in metrics_data:
                    if isinstance(item, dict):
                        metric_name = item.get("metric_name") or item.get("name")
                        value = item.get("value")
                        if metric_name and value is not None:
                            rows.append({
                                "subject_id": subject_id,
                                "metric_name": metric_name,
                                "value": float(value)
                            })
                    elif isinstance(item, (int, float)):
                        # Fallback for simple numeric lists
                        pass

        except (json.JSONDecodeError, IOError) as e:
            print(f"Warning: Could not read metrics for {subject_id}: {e}", file=sys.stderr)
            continue

    # Write to CSV
    output_path = str(OUTPUT_FILE)
    with open(output_path, 'w', newline='') as csvfile:
        fieldnames = ["subject_id", "metric_name", "value"]
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Aggregated {len(rows)} metrics for {len(subjects)} subjects to {output_path}")
    return output_path

def main():
    """Main entry point for the aggregation task."""
    print("Starting Graph Metrics Aggregation (T026)...")

    # Load preprocessed subjects
    subjects = load_preprocessed_subjects()
    if not subjects:
        print("Error: No preprocessed subjects found with metrics.", file=sys.stderr)
        print("Ensure code/graph_metrics.py has been run successfully.", file=sys.stderr)
        sys.exit(1)

    print(f"Found {len(subjects)} subjects with metrics.")

    # Aggregate to CSV
    output_path = aggregate_metrics_to_csv(subjects)

    # Verify output exists
    if not os.path.exists(output_path):
        print("Error: Output file was not created.", file=sys.stderr)
        sys.exit(1)

    print("Aggregation complete.")

if __name__ == "__main__":
    main()