import os
import sys
import json
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler('data/processed/validation_fluid_intelligence.log')
    ]
)
logger = logging.getLogger(__name__)

def load_aggregated_subjects(aggregated_path: str) -> List[Dict[str, Any]]:
    """
    Load the aggregated subjects data from the JSON file generated by T013a.
    
    Args:
        aggregated_path: Path to the aggregated subjects JSON file.
        
    Returns:
        List of subject dictionaries.
        
    Raises:
        FileNotFoundError: If the aggregated file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    path = Path(aggregated_path)
    if not path.exists():
        raise FileNotFoundError(f"Aggregated subjects file not found: {aggregated_path}")
    
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
        
    return data.get('subjects', [])

def extract_behavioral_scores(subjects: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Extract subjects that have Fluid Intelligence scores.
    
    Args:
        subjects: List of subject dictionaries.
        
    Returns:
        List of subjects with valid Fluid Intelligence scores.
    """
    valid_subjects = []
    for subject in subjects:
        # Check if behavioral_scores exists and contains Fluid Intelligence
        if 'behavioral_scores' in subject:
            scores = subject['behavioral_scores']
            if isinstance(scores, list):
                for score_entry in scores:
                    if score_entry.get('source_type') == 'Fluid Intelligence':
                        valid_subjects.append(subject)
                        break
            elif isinstance(scores, dict):
                # Handle case where scores might be a dict
                if scores.get('source_type') == 'Fluid Intelligence':
                    valid_subjects.append(subject)
        elif 'fluid_intelligence' in subject:
            # Alternative key name check
            if subject['fluid_intelligence'] is not None:
                valid_subjects.append(subject)
                
    return valid_subjects

def validate_fluid_intelligence(subjects: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Validate the presence of Fluid Intelligence scores in aggregated subjects.
    
    This function checks if the aggregated subject data contains valid Fluid 
    Intelligence scores. It returns a summary of the validation results.
    
    Args:
        subjects: List of subject dictionaries.
        
    Returns:
        Dictionary with validation results.
        
    Raises:
        ValueError: If no valid Fluid Intelligence scores are found.
    """
    if not subjects:
        raise ValueError("No subjects found in aggregated data.")
    
    valid_subjects = extract_behavioral_scores(subjects)
    total_subjects = len(subjects)
    valid_count = len(valid_subjects)
    
    validation_result = {
        'total_subjects': total_subjects,
        'subjects_with_fluid_intelligence': valid_count,
        'validation_passed': valid_count > 0,
        'subject_ids': [s.get('id', 'unknown') for s in valid_subjects]
    }
    
    logger.info(f"Validation Summary: {valid_count}/{total_subjects} subjects have Fluid Intelligence scores.")
    
    if valid_count == 0:
        logger.error("No valid Fluid Intelligence data found in specified datasets.")
        raise ValueError("No valid Fluid Intelligence data found in specified datasets.")
        
    return validation_result

def write_validation_log(validation_result: Dict[str, Any], output_path: str) -> None:
    """
    Write the validation results to a log file.
    
    Args:
        validation_result: Dictionary containing validation results.
        output_path: Path to the output log file.
    """
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(validation_result, f, indent=2)
        
    logger.info(f"Validation results written to {output_path}")

def main() -> None:
    """
    Main entry point for the Fluid Intelligence validation script.
    
    This script loads aggregated subjects from the data pipeline, validates
    the presence of Fluid Intelligence scores, and writes the results to a log file.
    """
    # Define paths
    config_path = Path('config.yaml')
    if not config_path.exists():
        logger.error("config.yaml not found. Please ensure the configuration file exists.")
        sys.exit(1)
        
    # Load config to get dataset info (optional, for logging)
    try:
        import yaml
        with open(config_path, 'r') as f:
            config = yaml.safe_load(f)
        primary_dataset = config.get('datasets', {}).get('primary', 'unknown')
    except Exception as e:
        logger.warning(f"Could not load config.yaml: {e}")
        primary_dataset = 'unknown'
    
    # Path to aggregated subjects (generated by T013a)
    aggregated_path = 'data/processed/aggregated_subjects.json'
    
    # Output path for validation log
    validation_log_path = 'data/processed/validation_fluid_intelligence.json'
    
    try:
        logger.info(f"Loading aggregated subjects from {aggregated_path}...")
        subjects = load_aggregated_subjects(aggregated_path)
        logger.info(f"Loaded {len(subjects)} subjects.")
        
        logger.info("Validating Fluid Intelligence scores...")
        validation_result = validate_fluid_intelligence(subjects)
        
        logger.info("Writing validation log...")
        write_validation_log(validation_result, validation_log_path)
        
        logger.info("Validation completed successfully.")
        print(f"Validation successful: {validation_result['subjects_with_fluid_intelligence']} subjects with Fluid Intelligence scores found.")
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Validation failed: {e}")
        # Re-raise to ensure the pipeline halts as required by T014c dependency
        raise
    except Exception as e:
        logger.error(f"An unexpected error occurred: {e}")
        sys.exit(1)

if __name__ == '__main__':
    main()
