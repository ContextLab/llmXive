"""
Contract test for statistical report schema (US3).

This test verifies that the final comparative report generated by the
symbolic vs. neural baseline experiment adheres to the strict schema
defined in the project specification.

It ensures:
1. All required top-level keys are present.
2. Statistical fields (p-value, test statistic) are valid floats.
3. Metrics are within expected ranges (0-1 for rates, >=0 for memory).
4. Error analysis sections are populated with valid counts.
"""

import json
import math
from pathlib import Path
from typing import Any, Dict

import pytest


# Path to the expected report generated by T032
REPORT_PATH = Path(__file__).parent.parent.parent / "data" / "results" / "final_report.md"
# Path to the JSON metrics source (if T032 writes a JSON intermediate)
METRICS_JSON_PATH = Path(__file__).parent.parent.parent / "data" / "results" / "sweep_metrics.csv"

# We assume the final report T032 produces is Markdown, but it MUST contain
# a JSON block or be parsable to validate the schema. 
# For this contract test, we validate against a hypothetical JSON export
# of the report data, or we parse the Markdown if it contains a JSON code block.
# However, to be robust against the specific T032 implementation, we define
# a strict schema that the *data* must satisfy.

# Since T032 generates a Markdown report, we will look for a companion JSON file
# that T032 should ideally generate for programmatic verification, OR we parse the MD.
# Given the strictness of "Contract Test", we will assert the existence of a JSON
# representation of the stats. If T032 only outputs MD, we will attempt to parse
# a JSON block within it.

EXPECTED_JSON_REPORT = Path(__file__).parent.parent.parent / "data" / "results" / "final_report_stats.json"

REQUIRED_TOP_LEVEL_KEYS = {
    "task_id",
    "experiment_name",
    "timestamp",
    "statistical_test",
    "metrics",
    "error_analysis",
    "conclusion"
}

REQUIRED_STATISTICAL_KEYS = {
    "test_name",
    "test_statistic",
    "p_value",
    "significance_level",
    "null_hypothesis"
}

REQUIRED_METRICS_KEYS = {
    "symbolic_success_rate",
    "neural_success_rate",
    "success_rate_delta",
    "symbolic_avg_latency_ms",
    "neural_avg_latency_ms",
    "latency_delta_ms",
    "symbolic_peak_memory_mb",
    "neural_peak_memory_mb",
    "memory_reduction_pct"
}

REQUIRED_ERROR_ANALYSIS_KEYS = {
    "total_failures_symbolic",
    "total_failures_neural",
    "categorized_failures_symbolic",
    "categorized_failures_neural",
    "coverage_pct",
    "categories"
}

REQUIRED_CATEGORIES_KEYS = {
    "discretization_ambiguity",
    "logical_inference_limitations"
}


def load_report_data() -> Dict[str, Any]:
    """
    Loads the statistical report data.
    Tries to load the JSON file first. If not found, attempts to parse
    a JSON block from the Markdown report generated by T032.
    """
    if EXPECTED_JSON_REPORT.exists():
        with open(EXPECTED_JSON_REPORT, "r", encoding="utf-8") as f:
            return json.load(f)
    
    if REPORT_PATH.exists():
        content = REPORT_PATH.read_text(encoding="utf-8")
        # Look for a JSON code block
        start_marker = "```json"
        end_marker = "```"
        start_idx = content.find(start_marker)
        if start_idx != -1:
            start_idx += len(start_marker)
            end_idx = content.find(end_marker, start_idx)
            if end_idx != -1:
                json_str = content[start_idx:end_idx].strip()
                return json.loads(json_str)
    
    # If neither exists, we cannot validate the schema, but we raise a clear error
    # indicating the report generation step (T032) has not produced the expected artifact.
    raise FileNotFoundError(
        f"Statistical report not found. Expected at {EXPECTED_JSON_REPORT} "
        f"or a JSON block in {REPORT_PATH}. Ensure T032 has been executed."
    )


def validate_schema(data: Dict[str, Any]) -> None:
    """Validates the structure and types of the statistical report."""
    
    # 1. Check Top Level Keys
    missing_keys = REQUIRED_TOP_LEVEL_KEYS - set(data.keys())
    assert not missing_keys, f"Missing top-level keys: {missing_keys}"

    # 2. Validate Statistical Test Section
    stats = data["statistical_test"]
    missing_stats = REQUIRED_STATISTICAL_KEYS - set(stats.keys())
    assert not missing_stats, f"Missing statistical keys: {missing_stats}"
    
    # Check numeric validity
    assert isinstance(stats["test_statistic"], (int, float)), "test_statistic must be numeric"
    assert isinstance(stats["p_value"], (int, float)), "p_value must be numeric"
    assert 0 <= stats["p_value"] <= 1, "p_value must be between 0 and 1"
    assert stats["test_name"] in ["McNemar", "T-test", "Wilcoxon"], "Invalid test name"

    # 3. Validate Metrics Section
    metrics = data["metrics"]
    missing_metrics = REQUIRED_METRICS_KEYS - set(metrics.keys())
    assert not missing_metrics, f"Missing metrics keys: {missing_metrics}"

    # Check rate ranges
    for key in ["symbolic_success_rate", "neural_success_rate"]:
        val = metrics[key]
        assert isinstance(val, (int, float)), f"{key} must be numeric"
        assert 0 <= val <= 1, f"{key} must be between 0 and 1"

    # Check deltas (success rate delta can be negative)
    assert isinstance(metrics["success_rate_delta"], (int, float)), "success_rate_delta must be numeric"
    
    # Check memory (must be non-negative)
    assert metrics["symbolic_peak_memory_mb"] >= 0, "Memory must be non-negative"
    assert metrics["neural_peak_memory_mb"] >= 0, "Memory must be non-negative"
    
    # Check memory reduction percentage (0-100)
    assert 0 <= metrics["memory_reduction_pct"] <= 100, "memory_reduction_pct must be 0-100"

    # 4. Validate Error Analysis Section
    errors = data["error_analysis"]
    missing_errors = REQUIRED_ERROR_ANALYSIS_KEYS - set(errors.keys())
    assert not missing_errors, f"Missing error analysis keys: {missing_errors}"

    # Check counts are integers
    for key in ["total_failures_symbolic", "total_failures_neural", 
                "categorized_failures_symbolic", "categorized_failures_neural"]:
        assert isinstance(errors[key], int), f"{key} must be an integer"

    # Check coverage percentage
    assert 0 <= errors["coverage_pct"] <= 100, "coverage_pct must be 0-100"

    # Check categories structure
    categories = errors.get("categories", {})
    missing_cats = REQUIRED_CATEGORIES_KEYS - set(categories.keys())
    assert not missing_cats, f"Missing category keys: {missing_cats}"
    
    for cat, count in categories.items():
        assert isinstance(count, int), f"Category count for {cat} must be integer"
        assert count >= 0, f"Category count for {cat} cannot be negative"

    # 5. Validate Conclusion is a string
    assert isinstance(data["conclusion"], str), "conclusion must be a string"
    assert len(data["conclusion"]) > 0, "conclusion cannot be empty"


@pytest.mark.contract
def test_statistical_report_schema():
    """
    Contract test: Ensures the final statistical report adheres to the
    schema required for US3 validation.
    """
    try:
        data = load_report_data()
    except FileNotFoundError as e:
        pytest.fail(str(e))
    
    validate_schema(data)


@pytest.mark.contract
def test_statistical_report_targets():
    """
    Contract test: Verifies that the reported metrics meet the success criteria
    defined in the project specification (e.g., p-value < 0.05, memory reduction > 0).
    This is a secondary validation of the *values* within the schema.
    """
    try:
        data = load_report_data()
    except FileNotFoundError as e:
        pytest.fail(str(e))

    metrics = data["metrics"]
    stats = data["statistical_test"]

    # Target 1: Statistical significance (p < 0.05)
    # Note: Depending on the hypothesis, we might expect symbolic to be better or worse.
    # The contract is that the p-value is calculated and present.
    assert stats["p_value"] < 0.05, (
        f"Statistical test did not reach significance (p={stats['p_value']}). "
        "The experiment may need more samples or the hypothesis may be invalid."
    )

    # Target 2: Memory reduction (Symbolic should use less memory)
    mem_reduction = metrics["memory_reduction_pct"]
    assert mem_reduction >= 0, "Memory reduction should be non-negative (Symbolic should be lighter)"
    
    # Target 3: Success rate delta (Symbolic should ideally be >= Neural, or within a small tolerance)
    # The spec mentions evaluating if targets (<=5% drop, >=80% success) are met.
    # We check that the delta is calculated correctly.
    expected_delta = metrics["symbolic_success_rate"] - metrics["neural_success_rate"]
    actual_delta = metrics["success_rate_delta"]
    assert math.isclose(expected_delta, actual_delta, rel_tol=1e-5), (
        f"Calculated success_rate_delta {actual_delta} does not match "
        f"symbolic ({metrics['symbolic_success_rate']}) - neural ({metrics['neural_success_rate']})"
    )

    # Target 4: Absolute success rates (should be > 0)
    assert metrics["symbolic_success_rate"] > 0, "Symbolic success rate must be > 0"
    assert metrics["neural_success_rate"] > 0, "Neural success rate must be > 0"