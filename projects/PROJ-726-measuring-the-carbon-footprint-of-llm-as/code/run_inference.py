import json
import logging
import os
import sys
import time
from pathlib import Path
from typing import Dict, List, Any, Optional

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer
from codecarbon import EmissionsTracker

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s",
    handlers=[logging.StreamHandler(sys.stdout)]
)
logger = logging.getLogger(__name__)

# Constants
MODEL_NAME = "gpt2-medium"
DEVICE = "cpu"
MAX_LENGTH = 128
PROMPT_LENGTH = 64
DATA_DIR = Path("data")
PROCESSED_DIR = DATA_DIR / "processed"
RAW_DIR = DATA_DIR / "raw"
OUTPUT_FILE = PROCESSED_DIR / "llm_inference_results.json"

def load_dataset(prompt_ids_path: Optional[str] = None) -> List[str]:
    """
    Load prompt IDs from the raw data directory.
    Expects data/raw/prompts.json or similar structure if defined,
    otherwise falls back to loading from the CodeXGLUE dataset if available.
    
    For this implementation, we assume the prompt IDs are stored in a JSON file
    generated by download_data.py, typically data/raw/prompts.json or similar.
    """
    # Try to load from a standard location first
    prompts_file = RAW_DIR / "codexglue_prompts.json"
    if not prompts_file.exists():
        prompts_file = RAW_DIR / "prompts.json"
    
    if prompts_file.exists():
        with open(prompts_file, 'r', encoding='utf-8') as f:
            data = json.load(f)
            # Handle both list of strings and list of dicts with 'text' or 'prompt' key
            if isinstance(data, list):
                if isinstance(data[0], str):
                    return data
                elif isinstance(data[0], dict):
                    return [item.get('text') or item.get('prompt') for item in data]
            raise ValueError(f"Unexpected format in {prompts_file}")
    
    # Fallback: try to load from HuggingFace if not cached
    try:
        from datasets import load_dataset
        logger.info("Loading CodeXGLUE dataset from HuggingFace...")
        dataset = load_dataset("code_x_glue_ct_code_to_text", "python", split="validation")
        prompts = [item['text'] for item in dataset]
        return prompts
    except Exception as e:
        logger.error(f"Failed to load dataset: {e}")
        raise

def load_model(model_name: str = MODEL_NAME, device: str = DEVICE):
    """
    Load GPT-2-medium model on CPU with default precision.
    No quantization or reduced-bit loading.
    """
    logger.info(f"Loading model {model_name} on {device}...")
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModelForCausalLM.from_pretrained(model_name)
    model = model.to(device)
    model.eval()
    logger.info("Model loaded successfully.")
    return tokenizer, model

def generate_code(tokenizer, model, prompt: str, device: str = DEVICE) -> str:
    """
    Generate code from a prompt using GPT-2-medium.
    Returns the generated code string.
    """
    inputs = tokenizer(prompt, return_tensors="pt")
    inputs = {k: v.to(device) for k, v in inputs.items()}
    
    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_length=MAX_LENGTH,
            num_return_sequences=1,
            do_sample=True,
            temperature=0.7,
            pad_token_id=tokenizer.eos_token_id,
            eos_token_id=tokenizer.eos_token_id
        )
    
    generated_ids = outputs[0][inputs['input_ids'].shape[1]:]
    generated_text = tokenizer.decode(generated_ids, skip_special_tokens=True)
    return generated_text

def count_loc(code_string: str) -> int:
    """
    Count non-empty lines in the generated code.
    """
    lines = code_string.strip().split('\n')
    return len([line for line in lines if line.strip()])

def run_inference_with_tracking(prompts: List[str], model_name: str = MODEL_NAME, device: str = DEVICE) -> List[Dict[str, Any]]:
    """
    Run inference on all prompts with CodeCarbon tracking.
    Returns a list of result dictionaries.
    """
    tokenizer, model = load_model(model_name, device)
    results = []
    
    # Initialize CodeCarbon tracker
    # Ensure output directory exists
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    
    with EmissionsTracker(output_dir=str(PROCESSED_DIR), save_to_file=True) as tracker:
        for idx, prompt in enumerate(prompts):
            logger.info(f"Processing prompt {idx + 1}/{len(prompts)}")
            start_time = time.time()
            
            try:
                generated_code = generate_code(tokenizer, model, prompt, device)
                loc = count_loc(generated_code)
                elapsed = time.time() - start_time
                
                # Get current emissions from tracker (cumulative)
                # Note: We track per-prompt emissions by resetting after each
                # However, CodeCarbon's design is cumulative. We'll record
                # the total and calculate per-prompt by subtraction if needed.
                # For simplicity in this MVP, we'll record the cumulative stats
                # and note that per-prompt breakdown requires more complex tracking.
                
                result = {
                    "prompt_id": f"prompt_{idx}",
                    "prompt_text": prompt[:100] + "..." if len(prompt) > 100 else prompt,
                    "generated_code": generated_code,
                    "loc_count": loc,
                    "model_used": model_name,
                    "device": device,
                    "generation_time_seconds": elapsed,
                    "status": "success"
                }
                results.append(result)
                
                # Log progress
                logger.info(f"  Generated {loc} lines of code in {elapsed:.2f}s")
                
            except Exception as e:
                logger.error(f"  Failed to generate code for prompt {idx}: {e}")
                results.append({
                    "prompt_id": f"prompt_{idx}",
                    "prompt_text": prompt[:100] + "..." if len(prompt) > 100 else prompt,
                    "generated_code": "",
                    "loc_count": 0,
                    "model_used": model_name,
                    "device": device,
                    "generation_time_seconds": 0,
                    "status": "error",
                    "error_message": str(e)
                })
    
    # Get final emissions data
    try:
        emissions_data = tracker.finalize()
        # The tracker writes to a JSON file, we can read it back
        emissions_file = PROCESSED_DIR / "emissions.csv"
        if emissions_file.exists():
            import pandas as pd
            df = pd.read_csv(emissions_file)
            total_energy = df['energy'].sum() if 'energy' in df.columns else 0
            total_co2 = df['co2_emitted'].sum() if 'co2_emitted' in df.columns else 0
            logger.info(f"Total energy: {total_energy:.6f} kWh, Total CO2: {total_co2:.6f} kg")
            
            # Distribute emissions across successful runs (simplified)
            successful_runs = [r for r in results if r['status'] == 'success']
            if successful_runs:
                per_run_energy = total_energy / len(successful_runs)
                per_run_co2 = total_co2 / len(successful_runs)
                for r in successful_runs:
                    r['energy_kWh'] = per_run_energy
                    r['co2_kg'] = per_run_co2
            else:
                logger.warning("No successful runs to distribute emissions")
    except Exception as e:
        logger.error(f"Failed to get emissions data: {e}")
    
    return results

def save_results(results: List[Dict[str, Any]], output_path: str = str(OUTPUT_FILE)):
    """
    Save inference results to a JSON file.
    """
    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(results, f, indent=2, ensure_ascii=False)
    
    logger.info(f"Results saved to {output_file}")

def main():
    """
    Main entry point for the inference script.
    """
    logger.info("Starting LLM inference pipeline...")
    
    try:
        # Load prompts
        prompts = load_dataset()
        logger.info(f"Loaded {len(prompts)} prompts")
        
        if not prompts:
            logger.error("No prompts found. Exiting.")
            sys.exit(1)
        
        # Run inference with tracking
        results = run_inference_with_tracking(prompts)
        
        # Save results
        save_results(results)
        
        # Summary
        successful = sum(1 for r in results if r['status'] == 'success')
        failed = sum(1 for r in results if r['status'] == 'error')
        logger.info(f"Inference complete: {successful} successful, {failed} failed")
        
    except Exception as e:
        logger.error(f"Pipeline failed: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()