import json
import logging
import os
import sys
from pathlib import Path
from typing import List, Dict, Any, Optional

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def count_loc(code_string: str) -> int:
    """
    Count the number of non-empty, non-comment lines in a code string.
    """
    if not code_string or not isinstance(code_string, str):
        return 0
    lines = code_string.splitlines()
    count = 0
    for line in lines:
        stripped = line.strip()
        if stripped and not stripped.startswith('#'):
            count += 1
    return count

def validate_schema(record: Dict[str, Any]) -> bool:
    """
    Validate that a result record contains the required fields and types.
    Required: prompt_id, model_used, energy_kWh, co2_kg, generated_code, loc_count
    """
    required_fields = ['prompt_id', 'model_used', 'energy_kWh', 'co2_kg', 'generated_code', 'loc_count']
    for field in required_fields:
        if field not in record:
            logger.warning(f"Missing required field: {field}")
            return False
    
    if not isinstance(record['prompt_id'], str):
        logger.warning(f"prompt_id must be a string")
        return False
    if not isinstance(record['model_used'], str):
        logger.warning(f"model_used must be a string")
        return False
    if not isinstance(record['energy_kWh'], (int, float)):
        logger.warning(f"energy_kWh must be a number")
        return False
    if not isinstance(record['co2_kg'], (int, float)):
        logger.warning(f"co2_kg must be a number")
        return False
    if not isinstance(record['generated_code'], str):
        logger.warning(f"generated_code must be a string")
        return False
    if not isinstance(record['loc_count'], int):
        logger.warning(f"loc_count must be an integer")
        return False
    
    return True

def load_accumulated_results(results_path: Path) -> List[Dict[str, Any]]:
    """
    Load the accumulated results from the in-memory list (simulated via JSON for this task).
    In a real pipeline, this might read from a temporary pickle or JSON file generated by T013.
    For this implementation, we assume the 'accumulated' state is passed as a JSON string or file.
    """
    if not results_path.exists():
        logger.error(f"Accumulated results file not found: {results_path}")
        return []
    
    try:
        with open(results_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        if not isinstance(data, list):
            logger.error("Accumulated results must be a list of records")
            return []
        return data
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse accumulated results JSON: {e}")
        return []

def process_results(accumulated_results: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Process the accumulated results:
    1. Exclude prompts that failed (generated_code is None, empty string, or missing).
    2. Calculate loc_count if not present (though T013 should have it, we ensure it).
    3. Validate schema.
    """
    valid_results = []
    excluded_count = 0

    for record in accumulated_results:
        code = record.get('generated_code')
        
        # Exclude if code is missing, None, or empty string
        if code is None or (isinstance(code, str) and code.strip() == ''):
            excluded_count += 1
            logger.info(f"Excluding prompt {record.get('prompt_id', 'UNKNOWN')}: empty or failed generation")
            continue

        # Ensure loc_count is calculated
        if 'loc_count' not in record or record['loc_count'] is None:
            record['loc_count'] = count_loc(code)
            logger.debug(f"Calculated LOC for {record.get('prompt_id')}: {record['loc_count']}")
        
        # Exclude if LOC is 0 (though T015 handles this, T014 requires exclusion of empty strings)
        if record['loc_count'] == 0:
            excluded_count += 1
            logger.info(f"Excluding prompt {record.get('prompt_id', 'UNKNOWN')}: LOC count is 0")
            continue

        if not validate_schema(record):
            excluded_count += 1
            logger.warning(f"Excluding prompt {record.get('prompt_id', 'UNKNOWN')}: schema validation failed")
            continue

        valid_results.append(record)

    logger.info(f"Processed {len(accumulated_results)} records. Excluded {excluded_count}. Valid: {len(valid_results)}")
    return valid_results

def save_results(valid_results: List[Dict[str, Any]], output_path: Path) -> None:
    """
    Save the valid results to the specified JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(valid_results, f, indent=2, ensure_ascii=False)
        logger.info(f"Successfully saved {len(valid_results)} results to {output_path}")
    except IOError as e:
        logger.error(f"Failed to write results to {output_path}: {e}")
        raise

def main():
    """
    Main entry point for T014: Write accumulated results to data/processed/llm_inference_results.json.
    Expects an intermediate file (e.g., data/raw/accumulated_inference.json) or uses a default path.
    For this task, we assume T013 wrote to a temp location or we read from a specific path.
    Since T013 says "Do NOT write to disk", this script must be run in a context where 
    the data is available. However, the constraint "Produce real outputs" implies we must 
    have a runnable script. 
    
    Strategy: This script assumes the 'accumulated' data is passed via a JSON file 
    generated by a previous step (or a simulated run for testing). 
    To satisfy the "runnable" constraint, we will look for a file named 
    'data/raw/accumulated_inference_results.json' (created by T013 if it were to write to disk 
    temporarily, or by a runner). 
    
    If the file doesn't exist, we cannot proceed with real data. 
    However, the task description says "Write the accumulated results from T013". 
    If T013 strictly does not write to disk, T014 would need to import the function 
    from run_inference.py or receive the data via stdin/args. 
    
    Given the constraint "Produce real outputs... when run as python code/<path>.py", 
    we assume a standard pipeline where T013 writes to a temporary intermediate file 
    (even if T013 description says "Do NOT write to disk" in the *memory* sense, 
    in a real CLI pipeline, data is passed via files). 
    
    Let's assume the intermediate file is `data/raw/accumulated_inference_results.json`.
    If that file does not exist, the script will fail loudly as per constraints.
    """
    input_path = Path("data/raw/accumulated_inference_results.json")
    output_path = Path("data/processed/llm_inference_results.json")

    if not input_path.exists():
        logger.error(f"Input file not found: {input_path}. T013 must generate this file or pass data.")
        sys.exit(1)

    logger.info(f"Loading accumulated results from {input_path}")
    accumulated = load_accumulated_results(input_path)
    
    if not accumulated:
        logger.warning("No accumulated results found. Exiting.")
        sys.exit(0)

    logger.info("Processing results (filtering empty codes, validating schema)...")
    valid_results = process_results(accumulated)

    logger.info(f"Saving {len(valid_results)} valid results to {output_path}")
    save_results(valid_results, output_path)

    return valid_results

if __name__ == "__main__":
    main()
