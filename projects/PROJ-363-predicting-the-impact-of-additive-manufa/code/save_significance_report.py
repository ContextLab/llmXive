"""
Task T035: Save statistical significance report to results/reports/significance_report.json.

This script loads the statistical analysis results (p-values, CIs, permutation importance)
generated by analyze_explainability.py and saves them to a JSON report file.
"""

import os
import sys
import json
import logging
from pathlib import Path

# Add project root to path to allow imports
project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from analyze_explainability import (
    load_model,
    load_data,
    find_best_model,
    calculate_shap_and_plot,
    perform_permutation_importance,
    calculate_bootstrap_shap_ci,
    calculate_p_values_and_significance,
)
from utils import setup_logging, compute_file_hash, load_state, update_state

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


def save_significance_report(
    feature_names,
    permutation_importance_results,
    bootstrap_ci_results,
    p_values_results,
    significant_features,
    output_path: Path,
):
    """
    Compile and save the statistical significance report.

    Args:
        feature_names: List of feature names used in the model.
        permutation_importance_results: Results from permutation importance.
        bootstrap_ci_results: Bootstrap confidence intervals for SHAP values.
        p_values_results: P-values from bootstrap distribution.
        significant_features: List of features with p < 0.05.
        output_path: Path to save the JSON report.
    """
    report = {
        "feature_names": feature_names,
        "permutation_importance": {
            "mean_importance": permutation_importance_results["mean_importance"],
            "std_importance": permutation_importance_results["std_importance"],
            "feature_ranking": permutation_importance_results["feature_ranking"],
        },
        "bootstrap_confidence_intervals": bootstrap_ci_results,
        "p_values": p_values_results,
        "statistically_significant_features": significant_features,
        "significance_threshold": 0.05,
        "summary": {
            "total_features": len(feature_names),
            "significant_count": len(significant_features),
            "significant_percentage": (len(significant_features) / len(feature_names)) * 100
            if feature_names
            else 0.0,
        },
    }

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Save report
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, default=str)

    logger.info(f"Significance report saved to: {output_path}")
    return report


def main():
    """Main entry point for T035."""
    logger.info("Starting T035: Save statistical significance report")

    # Paths
    models_dir = Path("models/artifacts")
    data_path = Path("data/processed/cleaned_316L.csv")
    output_path = Path("results/reports/significance_report.json")
    state_path = Path("state.yaml")

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Load data and model
    logger.info("Loading processed data...")
    df = load_data(data_path)

    logger.info("Finding best model...")
    best_model_name, best_model = find_best_model(models_dir)
    if best_model is None:
        logger.error("No trained models found in models/artifacts/")
        sys.exit(1)

    logger.info(f"Using best model: {best_model_name}")

    # Prepare features and target
    feature_cols = [
        "laser_power",
        "scan_speed",
        "hatch_spacing",
        "layer_thickness",
    ]
    # Check if energy_density is available and used instead
    if "energy_density" in df.columns:
        # Use energy_density instead of raw parameters to avoid multicollinearity
        # as per T034
        feature_cols = ["energy_density"]

    X = df[feature_cols]
    y = df["porosity"]

    # Calculate SHAP values
    logger.info("Calculating SHAP values...")
    shap_values, _ = calculate_shap_and_plot(best_model, X, plot=False)

    # Perform permutation importance
    logger.info("Performing permutation importance (1000 permutations)...")
    perm_results = perform_permutation_importance(best_model, X, y, n_permutations=1000)

    # Calculate bootstrap confidence intervals
    logger.info("Calculating bootstrap confidence intervals (1000 iterations)...")
    bootstrap_results = calculate_bootstrap_shap_ci(
        best_model, X, shap_values, n_iterations=1000
    )

    # Calculate p-values and significance
    logger.info("Calculating p-values and identifying significant features...")
    p_values_results, significant_features = calculate_p_values_and_significance(
        bootstrap_results, threshold=0.05
    )

    # Save report
    logger.info("Saving significance report...")
    report = save_significance_report(
        feature_names=feature_cols,
        permutation_importance_results=perm_results,
        bootstrap_ci_results=bootstrap_results,
        p_values_results=p_values_results,
        significant_features=significant_features,
        output_path=output_path,
    )

    # Update state
    if state_path.exists():
        state = load_state(state_path)
        file_hash = compute_file_hash(output_path)
        state = update_state(
            state,
            "significance_report",
            str(output_path),
            file_hash,
            "T035",
        )
        with open(state_path, "w", encoding="utf-8") as f:
            import yaml
            yaml.dump(state, f, default_flow_style=False)
        logger.info(f"Updated state.yaml with significance_report hash: {file_hash}")
    else:
        logger.warning(f"State file not found at {state_path}, skipping update")

    logger.info("T035 completed successfully")
    return report


if __name__ == "__main__":
    main()