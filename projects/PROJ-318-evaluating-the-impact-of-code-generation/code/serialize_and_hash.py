"""
Task T019: Serialize extracted data, compute SHA-256 checksums, and record in state YAML.

This script processes the JSON files generated by T018 (extract.py) located in
data/raw/repos/. It ensures the state directory exists, initializes or updates
the project-specific YAML state file with the SHA-256 hash of each processed file,
and verifies the presence of the 'ast_params' list in the data.
"""
import json
import hashlib
import os
import sys
import logging
from pathlib import Path
from typing import Dict, Any, List

# Ensure project root is in path for imports if run directly
PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from config import configure_logging
from utils.exceptions import SerializationException

# Configure logging
configure_logging()
logger = logging.getLogger(__name__)

# Constants
REPOS_DIR = PROJECT_ROOT / "data" / "raw" / "repos"
STATE_DIR = PROJECT_ROOT / "state" / "projects"
PROJECT_SLUG = "PROJ-318-evaluating-the-impact-of-code-generation"
STATE_FILE = STATE_DIR / f"{PROJECT_SLUG}.yaml"

def compute_sha256(file_path: Path) -> str:
    """Compute SHA-256 hash of a file."""
    sha256_hash = hashlib.sha256()
    try:
        with open(file_path, "rb") as f:
            for byte_block in iter(lambda: f.read(4096), b""):
                sha256_hash.update(byte_block)
        return sha256_hash.hexdigest()
    except Exception as e:
        raise SerializationException(f"Failed to compute hash for {file_path}: {e}")

def validate_ast_params(file_path: Path) -> bool:
    """Validate that the JSON file contains the 'ast_params' list."""
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
        
        if not isinstance(data, list):
            logger.warning(f"File {file_path} is not a list, skipping validation check or handling as single object.")
            return True # Skip strict list check for non-list structures if any

        for idx, record in enumerate(data):
            if not isinstance(record, dict):
                continue
            if 'ast_params' not in record:
                logger.error(f"Record {idx} in {file_path} missing 'ast_params' key.")
                return False
            if not isinstance(record['ast_params'], list):
                logger.error(f"Record {idx} in {file_path} has non-list 'ast_params'.")
                return False
        return True
    except json.JSONDecodeError as e:
        raise SerializationException(f"Invalid JSON in {file_path}: {e}")

def ensure_state_file():
    """Ensure the state directory and file exist with correct schema."""
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    
    if not STATE_FILE.exists():
        logger.info(f"Initializing state file: {STATE_FILE}")
        initial_content = {
            "artifact_hashes": {}
        }
        import yaml
        with open(STATE_FILE, 'w', encoding='utf-8') as f:
            yaml.dump(initial_content, f, default_flow_style=False)
    else:
        logger.info(f"State file exists: {STATE_FILE}")

def update_state_file(filename: str, file_hash: str):
    """Update the state YAML file with the new artifact hash."""
    import yaml
    
    try:
        with open(STATE_FILE, 'r', encoding='utf-8') as f:
            state_data = yaml.safe_load(f)
        
        if not isinstance(state_data, dict):
            state_data = {"artifact_hashes": {}}
        
        if "artifact_hashes" not in state_data:
            state_data["artifact_hashes"] = {}
        
        # Merge/Update the hash
        state_data["artifact_hashes"][filename] = file_hash
        
        with open(STATE_FILE, 'w', encoding='utf-8') as f:
            yaml.dump(state_data, f, default_flow_style=False)
        
        logger.info(f"Updated state file with hash for {filename}")
    except Exception as e:
        raise SerializationException(f"Failed to update state file {STATE_FILE}: {e}")

def process_repos():
    """Main logic to process all JSON files in data/raw/repos/."""
    if not REPOS_DIR.exists():
        logger.error(f"Repos directory not found: {REPOS_DIR}")
        sys.exit(1)

    # Find all .json files
    json_files = sorted(REPOS_DIR.glob("*.json"))
    
    if not json_files:
        logger.warning(f"No JSON files found in {REPOS_DIR}")
        return

    logger.info(f"Found {len(json_files)} JSON files to process.")
    
    processed_count = 0
    failed_count = 0

    for json_file in json_files:
        try:
            logger.info(f"Processing: {json_file.name}")
            
            # Validate content
            if not validate_ast_params(json_file):
                logger.error(f"Validation failed for {json_file.name}. Skipping hash recording.")
                failed_count += 1
                continue

            # Compute hash
            file_hash = compute_sha256(json_file)
            
            # Update state
            update_state_file(json_file.name, file_hash)
            
            processed_count += 1
            logger.info(f"Successfully processed {json_file.name} (Hash: {file_hash[:16]}...)")
            
        except SerializationException as e:
            logger.error(f"Serialization error for {json_file.name}: {e}")
            failed_count += 1
        except Exception as e:
            logger.error(f"Unexpected error for {json_file.name}: {e}")
            failed_count += 1

    logger.info(f"Processing complete. Success: {processed_count}, Failed: {failed_count}")
    if failed_count > 0:
        sys.exit(1)

def main():
    """Entry point."""
    logger.info("Starting T019: Serialize and Hash Extraction Data")
    ensure_state_file()
    process_repos()
    logger.info("T019 completed successfully.")

if __name__ == "__main__":
    main()
