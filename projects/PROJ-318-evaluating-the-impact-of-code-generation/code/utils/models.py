"""
Data models for code documentation completeness evaluation.

Defines core data structures (MethodSignature, DocstringPair) and
serialization logic for the research pipeline.
"""

import json
import hashlib
from dataclasses import dataclass, field, asdict
from typing import Optional, List, Dict, Any
from pathlib import Path


class SerializationException(Exception):
    """Raised when serialization or deserialization of model data fails."""
    pass


@dataclass
class MethodSignature:
    """
    Represents a parsed public method signature from a Python file.

    Attributes:
        file_path: Relative path to the source file within the repository.
        class_name: Name of the containing class, or None if module-level.
        method_name: Name of the method/function.
        parameters: List of parameter names extracted from the AST.
        return_annotation: String representation of the return type, or None.
        is_static: Boolean indicating if the method is static.
        is_classmethod: Boolean indicating if the method is a classmethod.
    """
    file_path: str
    method_name: str
    parameters: List[str] = field(default_factory=list)
    return_annotation: Optional[str] = None
    class_name: Optional[str] = None
    is_static: bool = False
    is_classmethod: bool = False

    def to_dict(self) -> Dict[str, Any]:
        """Converts the instance to a dictionary for JSON serialization."""
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'MethodSignature':
        """Creates an instance from a dictionary."""
        return cls(**data)


@dataclass
class DocstringPair:
    """
    Represents a pair of human-written and LLM-generated docstrings
    associated with a specific method signature.

    Attributes:
        signature: The MethodSignature this pair belongs to.
        human_docstring: The original docstring from the source code (parsed).
                        Can be None if no docstring existed.
        generated_docstring: The docstring generated by the LLM.
                             Can be None if generation failed or was skipped.
        parameter_coverage_score: Calculated coverage score (0.0 to 1.0).
        semantic_similarity: Calculated semantic similarity score (0.0 to 1.0).
        metadata: Additional context or flags (e.g., generation_time, memory_usage).
    """
    signature: MethodSignature
    human_docstring: Optional[str] = None
    generated_docstring: Optional[str] = None
    parameter_coverage_score: Optional[float] = None
    semantic_similarity: Optional[float] = None
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        """
        Converts the instance to a dictionary for JSON serialization.
        Handles nested serialization of MethodSignature.
        """
        return {
            "signature": self.signature.to_dict(),
            "human_docstring": self.human_docstring,
            "generated_docstring": self.generated_docstring,
            "parameter_coverage_score": self.parameter_coverage_score,
            "semantic_similarity": self.semantic_similarity,
            "metadata": self.metadata
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'DocstringPair':
        """
        Creates an instance from a dictionary.
        Handles nested deserialization of MethodSignature.
        """
        signature_data = data.get("signature", {})
        signature = MethodSignature.from_dict(signature_data)

        return cls(
            signature=signature,
            human_docstring=data.get("human_docstring"),
            generated_docstring=data.get("generated_docstring"),
            parameter_coverage_score=data.get("parameter_coverage_score"),
            semantic_similarity=data.get("semantic_similarity"),
            metadata=data.get("metadata", {})
        )


def serialize_pairs_to_json(pairs: List[DocstringPair], output_path: str) -> None:
    """
    Serializes a list of DocstringPair objects to a JSON file.

    Args:
        pairs: List of DocstringPair instances.
        output_path: Path to the output JSON file.

    Raises:
        SerializationException: If writing to the file fails.
    """
    try:
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        
        data = [pair.to_dict() for pair in pairs]
        
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
            
    except Exception as e:
        raise SerializationException(f"Failed to serialize pairs to {output_path}: {e}")


def deserialize_pairs_from_json(input_path: str) -> List[DocstringPair]:
    """
    Deserializes a list of DocstringPair objects from a JSON file.

    Args:
        input_path: Path to the input JSON file.

    Returns:
        List of DocstringPair instances.

    Raises:
        SerializationException: If reading or parsing the file fails.
    """
    try:
        path = Path(input_path)
        if not path.exists():
            raise SerializationException(f"File not found: {input_path}")

        with open(path, 'r', encoding='utf-8') as f:
            data = json.load(f)

        return [DocstringPair.from_dict(item) for item in data]
        
    except json.JSONDecodeError as e:
        raise SerializationException(f"Invalid JSON in {input_path}: {e}")
    except Exception as e:
        raise SerializationException(f"Failed to deserialize pairs from {input_path}: {e}")


def compute_checksum(file_path: str) -> str:
    """
    Computes the SHA-256 checksum of a file.

    Args:
        file_path: Path to the file.

    Returns:
        Hexadecimal string of the SHA-256 hash.

    Raises:
        SerializationException: If the file cannot be read.
    """
    try:
        sha256_hash = hashlib.sha256()
        with open(file_path, "rb") as f:
            for byte_block in iter(lambda: f.read(4096), b""):
                sha256_hash.update(byte_block)
        return sha256_hash.hexdigest()
    except Exception as e:
        raise SerializationException(f"Failed to compute checksum for {file_path}: {e}")