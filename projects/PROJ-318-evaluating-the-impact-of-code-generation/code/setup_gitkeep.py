"""
Task T001b: Create .gitkeep files in directories listed in logs/setup.log.

This script reads the directory paths from logs/setup.log (generated by T001a)
and ensures a .gitkeep file exists in each of them.
"""
import os
import sys
from pathlib import Path

def main():
    log_path = Path("logs/setup.log")
    
    if not log_path.exists():
        print(f"Error: {log_path} does not exist. Please run scripts/setup.sh (T001a) first.", file=sys.stderr)
        sys.exit(1)

    # Read directories from log file
    with open(log_path, "r") as f:
        lines = f.readlines()

    # Strip whitespace and filter empty lines
    dirs = [line.strip() for line in lines if line.strip()]

    if not dirs:
        print("Warning: No directories found in logs/setup.log", file=sys.stderr)
        sys.exit(0)

    created_count = 0
    existing_count = 0

    for dir_path in dirs:
        target_dir = Path(dir_path)
        gitkeep_file = target_dir / ".gitkeep"

        # Create directory if it doesn't exist (should exist from T001a, but safe to ensure)
        target_dir.mkdir(parents=True, exist_ok=True)

        if not gitkeep_file.exists():
            gitkeep_file.touch()
            created_count += 1
            print(f"Created: {gitkeep_file}")
        else:
            existing_count += 1
            # print(f"Exists: {gitkeep_file}")

    print(f"Done. Created {created_count} .gitkeep files, {existing_count} already existed.")

if __name__ == "__main__":
    main()