def generate_report():
    """
    Main entry point to generate the full analysis report.
    """
    logger.info("Starting report generation...")
    
    # Load data
    model_results = load_model_results()
    daily_aggregates = load_daily_aggregates()
    
    # Define output paths
    output_dir = get_path('data', 'processed')
    os.makedirs(output_dir, exist_ok=True)
    
    residual_plot_path = os.path.join(output_dir, 'residuals_vs_fitted.png')
    lopo_plot_path = os.path.join(output_dir, 'lopo_validation.png')
    sensitivity_plot_path = os.path.join(output_dir, 'sensitivity_analysis.png')
    report_path = os.path.join(output_dir, 'analysis_report.html')
    
    # Generate plots
    if 'validation' in model_results and 'lopo' in model_results['validation']:
        generate_lopo_plot(model_results['validation']['lopo'], lopo_plot_path)
    
    if 'sensitivity' in model_results:
        generate_sensitivity_plot(model_results['sensitivity'], sensitivity_plot_path)
        
    # Generate residual plot (requires model object, using placeholder logic here)
    generate_residual_plot(model_results, residual_plot_path)
    
    # Generate HTML Report
    generate_html_report(model_results, daily_aggregates, report_path)
    
    logger.info("Report generation complete.")
    return report_path

def main():
    """
    CLI entry point for report generation.
    """
    try:
        report_path = generate_report()
        print(f"Report successfully generated at: {report_path}")
        return 0
    except Exception as e:
        logger.error(f"Failed to generate report: {e}", exc_info=True)
        return 1

if __name__ == '__main__':
    sys.exit(main())