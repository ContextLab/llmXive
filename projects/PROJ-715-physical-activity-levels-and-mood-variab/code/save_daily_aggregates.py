import os
import sys
import logging
from pathlib import Path
import pandas as pd
from config import get_path
from output_validator import load_schema, validate_dataframe

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def save_and_validate():
    """
    Loads the daily aggregates from the preprocessing step (assumed to be
    available in the processed directory or generated by preprocess.py),
    validates it against the schema, and writes the final CSV.
    
    Note: In a strict pipeline, this might just read the intermediate
    result from preprocess.py if that script writes to a temp file,
    but typically preprocess.py writes the final artifact and this task
    ensures the validation happens before the pipeline proceeds or
    re-writes the final validated version.
    
    Based on the task description: "Write final output to data/processed/daily_aggregates.csv
    and validate against daily_aggregates.schema.yaml".
    """
    # Define paths
    input_path = get_path("data", "processed", "daily_aggregates.csv")
    schema_path = get_path("specs", "001-physical-activity-mood-variability", "contracts", "daily_aggregates.schema.yaml")
    
    # Check if input exists (preprocess.py should have created it)
    if not input_path.exists():
        logger.error(f"Input file not found: {input_path}")
        logger.error("Ensure T011-T015 have been executed successfully to generate the daily aggregates.")
        raise FileNotFoundError(f"Preprocessing output not found at {input_path}. Run preprocess.py first.")

    # Load the data generated by preprocess.py
    logger.info(f"Loading daily aggregates from {input_path}")
    df = pd.read_csv(input_path)
    
    # Load schema
    logger.info(f"Loading schema from {schema_path}")
    if not schema_path.exists():
        logger.error(f"Schema file not found: {schema_path}")
        raise FileNotFoundError(f"Schema file not found at {schema_path}")
    
    schema = load_schema(schema_path)
    
    # Validate
    logger.info("Validating daily aggregates against schema...")
    validation_result = validate_dataframe(df, schema)
    
    if not validation_result["valid"]:
        logger.error("Validation failed!")
        for error in validation_result["errors"]:
            logger.error(f"  - {error}")
        raise ValueError("Daily aggregates validation failed. Check logs for details.")
    
    logger.info("Validation successful.")
    
    # Ensure the directory exists
    input_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Save the final CSV (overwriting if exists, as it's the final validated version)
    logger.info(f"Saving validated daily aggregates to {input_path}")
    df.to_csv(input_path, index=False)
    
    logger.info(f"Task T016 completed successfully. Output: {input_path}")
    return input_path

def main():
    """Entry point for the script."""
    try:
        save_and_validate()
    except Exception as e:
        logger.error(f"Task T016 failed with error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
