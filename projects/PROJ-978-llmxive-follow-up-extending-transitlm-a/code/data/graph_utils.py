def load_ground_truth(path: str = "data/raw/transitlm_ground_truth.json") -> List[Dict[str, Any]]:
    """
    Load the ground truth dataset from the JSON file generated by T004.
    """
    if not os.path.exists(path):
        raise FileNotFoundError(f"Ground truth file not found at {path}. "
                                "Ensure T004 has been executed successfully.")
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    return data

def load_processed_routes(path: str = "data/processed/vocab_restricted_routes.jsonl") -> List[Dict[str, Any]]:
    """
    Load processed routes from the JSONL file generated by T006b.
    """
    if not os.path.exists(path):
        raise FileNotFoundError(f"Processed routes file not found at {path}. "
                                "Ensure T006b has been executed successfully.")
    routes = []
    with open(path, 'r', encoding='utf-8') as f:
        for line in f:
            if line.strip():
                routes.append(json.loads(line))
    return routes

def build_route_graph(routes: List[Dict[str, Any]]) -> Set[Tuple[str, str]]:
    """
    Build a set of directed edges from the list of routes.
    Each route is a sequence of stations.
    Returns a set of (station_a, station_b) tuples.
    """
    edges = set()
    for route in routes:
        # Assuming route has a key 'stops' or 'stations' containing a list of station names
        # Based on typical TransitLM structure, we look for 'stops'
        stops = route.get('stops') or route.get('stations') or route.get('stop_sequence')
        if not stops or len(stops) < 2:
            continue
        for i in range(len(stops) - 1):
            u, v = stops[i], stops[i+1]
            if u and v:
                edges.add((u, v))
    return edges

def compute_jaccard_index(set_a: Set[Any], set_b: Set[Any]) -> float:
    """
    Compute the Jaccard Index (Intersection over Union) between two sets.
    J(A, B) = |A ∩ B| / |A ∪ B|
    """
    if not set_a and not set_b:
        return 1.0 # Both empty, perfect match
    if not set_a or not set_b:
        return 0.0
    intersection = len(set_a & set_b)
    union = len(set_a | set_b)
    if union == 0:
        return 0.0
    return intersection / union

def validate_graph_against_ground_truth(
    routes_path: str = "data/processed/vocab_restricted_routes.jsonl",
    ground_truth_path: str = "data/raw/transitlm_ground_truth.json",
    output_path: str = "data/processed/graph_validation_report.json",
    threshold: float = 0.95
) -> Dict[str, Any]:
    """
    Build the local adjacency graph from processed routes and validate it against
    the ground truth using the Jaccard Index.

    Args:
        routes_path: Path to the processed routes (T006b output).
        ground_truth_path: Path to the ground truth (T004 output).
        output_path: Path to write the validation report.
        threshold: Minimum Jaccard Index required to pass.

    Returns:
        A dictionary containing the Jaccard index, status, and details.
    """
    print(f"Loading processed routes from {routes_path}...")
    routes = load_processed_routes(routes_path)
    print(f"Loaded {len(routes)} routes.")

    print(f"Loading ground truth from {ground_truth_path}...")
    ground_truth = load_ground_truth(ground_truth_path)
    print(f"Loaded {len(ground_truth)} ground truth entries.")

    # Build edge sets
    print("Building edge set from processed routes...")
    route_edges = build_route_graph(routes)

    print("Building edge set from ground truth...")
    gt_edges = build_route_graph(ground_truth)

    # Compute Jaccard Index
    jaccard = compute_jaccard_index(route_edges, gt_edges)
    status = "PASS" if jaccard >= threshold else "FAIL"

    report = {
        "jaccard_index": jaccard,
        "status": status,
        "threshold": threshold,
        "route_edges_count": len(route_edges),
        "ground_truth_edges_count": len(gt_edges),
        "intersection_count": len(route_edges & gt_edges),
        "union_count": len(route_edges | gt_edges),
        "message": f"Validation {'PASSED' if status == 'PASS' else 'FAILED'}. "
                   f"Jaccard Index: {jaccard:.4f} (Threshold: {threshold})"
    }

    # Write report to disk
    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)

    print(f"Validation report written to {output_path}")
    print(report["message"])

    if status == "FAIL":
        # CRITICAL: Fail loudly as per task requirements
        raise RuntimeError(f"Graph validation FAILED. Jaccard Index ({jaccard:.4f}) is below threshold ({threshold}). "
                           "Phase 3 cannot proceed.")

    return report

def main():
    """
    Entry point for T007: Graph Validation.
    """
    try:
        validate_graph_against_ground_truth()
        print("T007 completed successfully.")
        return 0
    except Exception as e:
        print(f"T007 failed with error: {e}", file=sys.stderr)
        return 1

if __name__ == "__main__":
    sys.exit(main())
