def test_compute_kaplan_meier(mock_inflection_data):
    """
    Test that compute_kaplan_meier correctly processes the input data
    and returns survival curve data for both models.
    """
    lightweight_survival, baseline_survival = compute_kaplan_meier(mock_inflection_data)

    # Assert structure
    assert isinstance(lightweight_survival, dict)
    assert isinstance(baseline_survival, dict)

    # Assert keys exist
    assert "survival_probabilities" in lightweight_survival
    assert "survival_probabilities" in baseline_survival
    assert "event_times" in lightweight_survival
    assert "event_times" in baseline_survival

    # Assert data types
    assert isinstance(lightweight_survival["survival_probabilities"], list)
    assert isinstance(baseline_survival["survival_probabilities"], list)

    # Assert monotonicity (survival probability should not increase)
    probs_light = lightweight_survival["survival_probabilities"]
    probs_base = baseline_survival["survival_probabilities"]

    for i in range(1, len(probs_light)):
        assert probs_light[i] <= probs_light[i-1], "Lightweight survival probability must be non-increasing"
    
    for i in range(1, len(probs_base)):
        assert probs_base[i] <= probs_base[i-1], "Baseline survival probability must be non-increasing"


