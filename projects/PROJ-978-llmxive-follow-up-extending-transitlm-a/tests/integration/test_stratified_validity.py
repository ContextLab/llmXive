"""
Integration test for stratified route validity scoring (T011).

This test verifies that the preprocessing pipeline correctly stratifies routes
and that the validity scoring logic produces expected results on the processed data.

It depends on T006 (preprocess.py) having generated the processed dataset.
"""
import json
import os
import sys
from pathlib import Path
from typing import List, Dict, Any

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT))

from data.preprocess import stratify_routes, compute_route_metrics
from data.contract_validator import validate_output_schema, load_schema


# Constants matching T006/T009 definitions
SHORT_THRESHOLD = 15
MEDIUM_THRESHOLD = 30
CITIES = ["Beijing", "Shanghai", "Guangzhou", "Shenzhen"]
PROCESSED_DATA_PATH = PROJECT_ROOT / "data" / "processed" / "transitlm_processed.json"
SCHEMA_PATH = PROJECT_ROOT / "data" / "contracts" / "output.schema.yaml"


def load_processed_dataset() -> List[Dict[str, Any]]:
    """Load the processed dataset generated by T006."""
    if not PROCESSED_DATA_PATH.exists():
        raise FileNotFoundError(
            f"Processed dataset not found at {PROCESSED_DATA_PATH}. "
            "Ensure T006 (preprocess.py) has been executed successfully."
        )
    
    with open(PROCESSED_DATA_PATH, 'r', encoding='utf-8') as f:
        return json.load(f)


def validate_schema(data: List[Dict[str, Any]]) -> bool:
    """Validate the processed data against the output schema."""
    if not SCHEMA_PATH.exists():
        raise FileNotFoundError(f"Schema file not found at {SCHEMA_PATH}")
    
    schema = load_schema(SCHEMA_PATH)
    is_valid, errors = validate_output_schema(data, schema)
    
    if not is_valid:
        raise AssertionError(f"Data schema validation failed: {errors}")
    
    return True


def test_stratification_logic():
    """
    Test that routes are correctly stratified into short, medium, and long categories.
    
    Expected behavior:
    - Short: < 15 stops
    - Medium: 15 <= stops <= 30
    - Long: > 30 stops
    """
    data = load_processed_dataset()
    validate_schema(data)
    
    if not data:
        raise AssertionError("Processed dataset is empty. T006 may have failed to filter data.")
    
    # Apply stratification logic locally to verify
    stratified = stratify_routes(data)
    
    # Verify all routes are assigned to exactly one category
    total_count = sum(len(stratified[cat]) for cat in stratified)
    assert total_count == len(data), "Stratification lost some routes."
    
    # Verify category definitions
    for route in stratified["short"]:
        stops = route.get("stop_count", len(route.get("stops", [])))
        assert stops < SHORT_THRESHOLD, f"Short route has {stops} stops, expected < {SHORT_THRESHOLD}"
    
    for route in stratified["medium"]:
        stops = route.get("stop_count", len(route.get("stops", [])))
        assert SHORT_THRESHOLD <= stops <= MEDIUM_THRESHOLD, (
            f"Medium route has {stops} stops, expected {SHORT_THRESHOLD}-{MEDIUM_THRESHOLD}"
        )
    
    for route in stratified["long"]:
        stops = route.get("stop_count", len(route.get("stops", [])))
        assert stops > MEDIUM_THRESHOLD, f"Long route has {stops} stops, expected > {MEDIUM_THRESHOLD}"
    
    # Verify at least one route exists in each category (unless data is naturally skewed)
    # Note: If a category is empty, it's a data characteristic, not a logic error, 
    # but we log it for awareness.
    for cat in ["short", "medium", "long"]:
        if not stratified[cat]:
            print(f"Warning: No routes found in '{cat}' category. Check data distribution.")
    
    print(f"Stratification test passed. Found {len(stratified['short'])} short, "
          f"{len(stratified['medium'])} medium, {len(stratified['long'])} long routes.")


def test_route_metrics_computation():
    """
    Test that route metrics (stop_count, city, etc.) are correctly computed.
    """
    data = load_processed_dataset()
    validate_schema(data)
    
    for route in data:
        metrics = compute_route_metrics(route)
        
        # Verify stop_count matches actual stops list length
        stops = route.get("stops", [])
        assert metrics["stop_count"] == len(stops), (
            f"Metrics stop_count ({metrics['stop_count']}) != actual stops ({len(stops)})"
        )
        
        # Verify city is one of the expected cities
        assert metrics["city"] in CITIES, (
            f"Route city '{metrics['city']}' not in expected cities {CITIES}"
        )
        
        # Verify route_id exists
        assert "route_id" in metrics, "Route metrics missing route_id"
    
    print(f"Route metrics computation test passed for {len(data)} routes.")


def test_validity_scoring_structure():
    """
    Test that validity scoring can be computed for stratified routes.
    This ensures the data structure supports the evaluation logic in T014.
    """
    data = load_processed_dataset()
    stratified = stratify_routes(data)
    
    # Simulate validity scoring logic (placeholder for T014 implementation)
    # We verify the structure is correct, not the actual scoring algorithm
    for category, routes in stratified.items():
        for route in routes:
            # Ensure route has required fields for validity scoring
            assert "stops" in route, f"Route in {category} missing 'stops' field"
            assert "city" in route, f"Route in {category} missing 'city' field"
            assert "route_id" in route, f"Route in {category} missing 'route_id' field"
            
            # Ensure metrics are present or computable
            if "stop_count" not in route:
                route["stop_count"] = len(route["stops"])
    
    print("Validity scoring structure test passed.")


def main():
    """Run all integration tests."""
    print("Running T011: Stratified Route Validity Scoring Integration Tests...")
    
    try:
        test_stratification_logic()
        test_route_metrics_computation()
        test_validity_scoring_structure()
        
        print("\n✅ All integration tests passed successfully.")
        return 0
        
    except (FileNotFoundError, AssertionError) as e:
        print(f"\n❌ Integration test failed: {e}")
        return 1
    except Exception as e:
        print(f"\n❌ Unexpected error: {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())