class TestStratifiedSchema:
    """Tests for data/processed/stratified_routes.parquet (T006c)"""

    @pytest.fixture
    def file_path(self):
        return PROCESSED_DIR / "stratified_routes.parquet"

    def test_file_exists(self, file_path):
        assert file_path.exists(), f"Output file {file_path} does not exist. Run T006c first."

    def test_schema_conformance(self, file_path):
        """Validate parquet structure and content using pandas."""
        try:
            import pandas as pd
        except ImportError:
            pytest.skip("pandas not installed for parquet validation")

        df = pd.read_parquet(file_path)
        
        # Check columns
        required_cols = SCHEMA_STRATIFIED["required_columns"]
        for col in required_cols:
            assert col in df.columns, f"Missing required column '{col}' in stratified routes"

        # Check categories
        valid_cats = SCHEMA_STRATIFIED["valid_categories"]
        assert df["length_category"].isin(valid_cats).all(), \
            "Invalid length_category values found"
        
        # Check category distribution (must have at least one of each)
        for cat in valid_cats:
            count = (df["length_category"] == cat).sum()
            assert count > 0, f"No routes found for category '{cat}'"

        # Validate stop_count consistency with category
        # short: <15, medium: 15-30, long: >30
        for idx, row in df.iterrows():
            count = row["stop_count"]
            cat = row["length_category"]
            
            if cat == "short":
                assert count < 15, f"Route {row['route_id']} marked 'short' but has {count} stops"
            elif cat == "medium":
                assert 15 <= count <= 30, f"Route {row['route_id']} marked 'medium' but has {count} stops"
            elif cat == "long":
                assert count > 30, f"Route {row['route_id']} marked 'long' but has {count} stops"

