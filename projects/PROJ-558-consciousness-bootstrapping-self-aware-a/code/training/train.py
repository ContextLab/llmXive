logger = get_logger(__name__)

class PileDataset(torch.utils.data.Dataset):
    """
    A lightweight dataset wrapper for the truncated Pile ArXiv subset.
    Reads the JSON file generated by data_loader.py.
    """
    def __init__(self, json_path: str, max_length: int = 512):
        self.json_path = json_path
        self.max_length = max_length
        self.data = []
        
        logger.info(f"Loading dataset from {json_path}")
        try:
            with open(json_path, 'r', encoding='utf-8') as f:
                for line in f:
                    self.data.append(json.loads(line))
        except FileNotFoundError:
            raise FileNotFoundError(f"Dataset file not found: {json_path}. "
                                    "Please run data_loader.py first to generate the data.")
        except json.JSONDecodeError as e:
            raise ValueError(f"Invalid JSON in dataset file {json_path}: {e}")
        
        logger.info(f"Loaded {len(self.data)} samples")

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        item = self.data[idx]
        # Assuming the JSON contains 'text' or 'input' field
        text = item.get('text', item.get('input', ''))
        # Simple tokenization placeholder - in real implementation, use tokenizer
        # For this specific task, we assume the data is already tokenized or we use a simple approach
        # Since we are focusing on the recursion validation logic, we simulate token IDs
        # In a full implementation, this would use a tokenizer from transformers
        tokens = list(range(len(text))) # Dummy tokenization for structure
        if len(tokens) > self.max_length:
            tokens = tokens[:self.max_length]
        
        # Return as tensors
        return {
            'input_ids': torch.tensor(tokens, dtype=torch.long),
            'labels': torch.tensor(tokens, dtype=torch.long)
        }

def train_epoch(model, dataloader, optimizer, device, config: Config, recursion_depth: int):
    """
    Trains the model for one epoch.
    Includes the hard-fail validation for recursion depth and OOM.
    """
    model.train()
    total_loss = 0.0
    num_batches = 0

    logger.info(f"Starting training epoch with recursion_depth={recursion_depth}")
    
    # VALIDATION: Hard-fail if recursion_depth > 2
    if recursion_depth > config.recursion_depth:
        error_msg = f"Recursion depth violation: requested {recursion_depth}, max allowed {config.recursion_depth}"
        logger.error(error_msg)
        raise RecursionDepthError(error_msg)

    for batch_idx, batch in enumerate(dataloader):
        input_ids = batch['input_ids'].to(device)
        labels = batch['labels'].to(device)

        try:
            # Check for OOM before forward pass
            torch.cuda.empty_cache() if torch.cuda.is_available() else None

            # Forward pass
            outputs = model(input_ids=input_ids, labels=labels)
            loss = outputs.loss if hasattr(outputs, 'loss') else outputs[0]

            # Backward pass
            optimizer.zero_grad()
            loss.backward()

            # Step
            optimizer.step()

            total_loss += loss.item()
            num_batches += 1

            if batch_idx % 10 == 0:
                logger.info(f"Batch {batch_idx}/{len(dataloader)}, Loss: {loss.item():.4f}")

        except RuntimeError as e:
            if "out of memory" in str(e).lower():
                error_msg = f"OOM detected at batch {batch_idx} with recursion_depth {recursion_depth}"
                logger.error(error_msg)
                raise RecursionDepthError(error_msg) from e
            else:
                raise

    avg_loss = total_loss / num_batches if num_batches > 0 else 0.0
    logger.info(f"Epoch complete. Average Loss: {avg_loss:.4f}")
    return avg_loss

def save_checkpoint(model, optimizer, epoch, loss, config: Config, output_path: str):
    """
    Saves the model checkpoint.
    """
    state = {
        'epoch': epoch,
        'model_state_dict': model.state_dict(),
        'optimizer_state_dict': optimizer.state_dict(),
        'loss': loss,
        'config': config.to_dict() if hasattr(config, 'to_dict') else vars(config)
    }
    
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    torch.save(state, output_path)
    logger.info(f"Checkpoint saved to {output_path}")

def run_training(config: Config):
    """
    Main training loop.
    Implements the hard-fail logic for recursion depth > 2.
    """
    device = torch.device("cpu") # Enforce CPU-only as per config
    if torch.cuda.is_available() and not config.cpu_only:
        logger.warning("CUDA available but CPU-only mode enforced by config.")
    
    logger.info("Initializing training...")
    
    # Load dataset
    dataset_path = os.path.join(config.data_dir, "raw", "pile_arxiv_truncated.json")
    dataset = PileDataset(dataset_path, max_length=config.token_limit)
    dataloader = DataLoader(dataset, batch_size=config.batch_size, shuffle=True)

    # Initialize Model
    # Note: For this task, we assume the model creation handles the recursion depth internally
    # but we enforce the check here as well before training starts.
    recursion_depth = config.recursion_depth
    
    # HARD-FAIL VALIDATION: Prevent recursion depth > 2
    if recursion_depth > 2:
        error_msg = f"Configuration Error: Recursion depth {recursion_depth} exceeds maximum allowed value of 2."
        logger.critical(error_msg)
        raise RecursionDepthError(error_msg)

    try:
        model = create_recursive_model(config)
        model.to(device)
    except Exception as e:
        logger.error(f"Failed to create model: {e}")
        raise ModelTrainingError("Model creation failed") from e

    optimizer = torch.optim.AdamW(model.parameters(), lr=config.learning_rate)

    # Training Loop
    for epoch in range(config.num_epochs):
        try:
            loss = train_epoch(model, dataloader, optimizer, device, config, recursion_depth)
            
            # Save checkpoint
            checkpoint_path = os.path.join(config.artifacts_dir, "checkpoints", f"model_epoch_{epoch}.pt")
            save_checkpoint(model, optimizer, epoch, loss, config, checkpoint_path)

        except RecursionDepthError as e:
            # Hard-fail on OOM or depth violation
            logger.critical(f"Training aborted due to critical error: {e}")
            sys.exit(1)
        except Exception as e:
            logger.error(f"Unexpected error during epoch {epoch}: {e}")
            raise

    logger.info("Training completed successfully.")
    return model

def main():
    """
    Entry point for the training script.
    """
    try:
        config = get_config()
        validate_config(config)
        
        log_training_start(config)
        
        run_training(config)
        
        log_training_end(config)
        
    except RecursionDepthError as e:
        logger.critical(f"CRITICAL FAILURE: {e}")
        sys.exit(1)
    except Exception as e:
        logger.critical("Training failed with unexpected error")
        log_exception(e)
        sys.exit(1)

if __name__ == "__main__":
    main()