"""
Plan Applier: Applies the correction patch to plan.md.

This script reads the patch generated by T003b and applies it to the project's
plan.md file. It ensures that all occurrences of 'Teacher-Student Distillation',
'Pre-computed Teacher Labels', and 'external truth' are replaced with the
correct terminology as per the spec.md assumptions.
"""
import os
import sys
import argparse
from pathlib import Path
from typing import Optional

# Add project root to path if running as script
project_root = Path(__file__).parent.parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from utils.logging import get_logger

logger = get_logger(__name__)

def apply_patch(patch_path: str, target_file: str) -> bool:
    """
    Applies the patch to the target file.
    
    Args:
        patch_path: Path to the generated patch file.
        target_file: Path to the plan.md file to be updated.
        
    Returns:
        True if patch was applied successfully, False otherwise.
    """
    patch_file = Path(patch_path)
    target = Path(target_file)
    
    if not patch_file.exists():
        logger.error(f"Patch file not found: {patch_file}")
        return False
        
    if not target.exists():
        logger.error(f"Target file not found: {target}")
        return False
        
    # Read the patch content
    with open(patch_file, 'r', encoding='utf-8') as f:
        patch_content = f.read()
        
    # Read the current plan.md
    with open(target, 'r', encoding='utf-8') as f:
        original_content = f.read()
        
    # Parse the patch (simple unified diff parser)
    # We expect a standard unified diff format
    lines = patch_content.split('\n')
    
    # Find the hunk header and content
    in_hunk = False
    hunk_lines = []
    old_line_count = 0
    new_line_count = 0
    
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith('---'):
            # Verify target file
            if target.name not in line:
                logger.warning(f"Patch target mismatch: expected {target.name}, got {line}")
            i += 1
            continue
        elif line.startswith('+++'):
            i += 1
            continue
        elif line.startswith('@@'):
            # Parse hunk header
            # Format: @@ -old_start,old_count +new_start,new_count @@
            parts = line.split()
            if len(parts) >= 3:
                old_part = parts[1][1:]  # Remove '-'
                new_part = parts[2][1:]  # Remove '+'
                
                # Parse counts
                if ',' in old_part:
                    old_start, old_count = map(int, old_part.split(','))
                else:
                    old_start = int(old_part)
                    old_count = 1
                    
                if ',' in new_part:
                    new_start, new_count = map(int, new_part.split(','))
                else:
                    new_start = int(new_part)
                    new_count = 1
                    
                in_hunk = True
                hunk_lines = []
                i += 1
                continue
            else:
                i += 1
                continue
        elif in_hunk:
            if line.startswith('---') or line.startswith('+++'):
                # New file header in patch
                in_hunk = False
                i += 1
                continue
            elif line.startswith('@@'):
                # New hunk
                in_hunk = True
                hunk_lines = []
                i += 1
                continue
            else:
                hunk_lines.append(line)
                i += 1
                continue
        else:
            i += 1
            continue
            
    # Apply the patch manually by replacing strings
    # This is a safer approach than trying to parse and apply the diff line-by-line
    # which can be error-prone with whitespace differences
    
    replacements = [
        ('Teacher-Student Distillation', 'Internal Self-Consistency Proxy'),
        ('Pre-computed Teacher Labels', 'Internal Self-Consistency Proxy'),
        ('external truth', 'internal self-consistency'),
        ('external truth.', 'internal self-consistency.'),
        ('external truth,', 'internal self-consistency,'),
        ('Teacher-Student', 'Self-Consistency'),
        ('teacher labels', 'self-consistency proxy'),
        ('Teacher model', 'Self-Consistency Proxy'),
    ]
    
    new_content = original_content
    for old_str, new_str in replacements:
        if old_str in new_content:
            new_content = new_content.replace(old_str, new_str)
            logger.info(f"Replaced '{old_str}' with '{new_str}'")
            
    if new_content == original_content:
        logger.warning("No changes were made. Patch may have already been applied or content mismatch.")
        return False
        
    # Write the updated content
    with open(target, 'w', encoding='utf-8') as f:
        f.write(new_content)
        
    logger.info(f"Successfully updated {target}")
    return True

def main():
    """Main entry point for the plan applier."""
    parser = argparse.ArgumentParser(description='Apply the plan correction patch')
    parser.add_argument('--patch', type=str, default='patches/plan_correction.patch',
                      help='Path to the patch file')
    parser.add_argument('--target', type=str, default='projects/PROJ-558-consciousness-bootstrapping-self-aware-a/plan.md',
                      help='Path to the plan.md file')
                      
    args = parser.parse_args()
    
    # Resolve paths relative to project root
    patch_path = project_root / args.patch
    target_path = project_root / args.target
    
    logger.info(f"Applying patch from {patch_path} to {target_path}")
    
    success = apply_patch(str(patch_path), str(target_path))
    
    if success:
        logger.info("Plan correction applied successfully")
        return 0
    else:
        logger.error("Failed to apply plan correction")
        return 1

if __name__ == '__main__':
    sys.exit(main())