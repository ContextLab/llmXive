def validate_config() -> List[str]:
    """Validate configuration values."""
    errors = []
    logger.info("Validating configuration...")

    config_path = PROJECT_ROOT / "code" / "utils" / "config.py"
    if not config_path.exists():
        errors.append("config.py not found")
        return errors

    try:
        # Import and validate
        from utils.config import validate_config, get_config
        config = get_config()
        if config is None:
            errors.append("Failed to load config")
        else:
            # Check token_limit specifically as per T002/T005 requirements
            if hasattr(config, 'token_limit'):
                if config.token_limit is None or config.token_limit == "deferred":
                    errors.append(f"Config token_limit is invalid: {config.token_limit}. Must be an integer (100000).")
                elif not isinstance(config.token_limit, int):
                    errors.append(f"Config token_limit must be an integer, got {type(config.token_limit)}")
            else:
                # Check if it's a dict or object with token_limit
                if isinstance(config, dict) and 'token_limit' in config:
                    val = config['token_limit']
                    if val is None or val == "deferred" or not isinstance(val, int):
                        errors.append(f"Config token_limit is invalid: {val}")
                elif not hasattr(config, 'token_limit'):
                    errors.append("Config missing token_limit attribute")
            logger.debug("Config validation passed")
    except Exception as e:
        errors.append(f"Error validating config: {str(e)}")
        logger.error(f"Error validating config: {str(e)}")

    return errors

def run_quickstart_validation() -> bool:
    """Run all validation checks and return True if all pass."""
    all_errors = []

    logger.info("Starting Quickstart Validation for PROJ-558")
    logger.info(f"Project Root: {PROJECT_ROOT}")

    # 1. Structure
    all_errors.extend(validate_project_structure())

    # 2. Config
    all_errors.extend(validate_config())

    # 3. Imports
    all_errors.extend(validate_python_imports())

    # 4. Data
    all_errors.extend(validate_data_artifacts())

    # 5. Results
    all_errors.extend(validate_result_artifacts())

    if all_errors:
        logger.critical(f"Validation FAILED with {len(all_errors)} errors:")
        for err in all_errors:
            logger.critical(f"  - {err}")
        return False
    else:
        logger.info("Validation PASSED. All required artifacts are present and valid.")
        return True

