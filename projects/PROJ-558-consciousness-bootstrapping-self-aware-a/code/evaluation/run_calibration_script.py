"""
Script to run error detection calibration analysis.

This script assumes that T019 (run_benchmarks.py) has already been executed
and that the evaluation results contain:
- error_flags: Binary flags indicating if the model predicted an error
- confidence_scores: Confidence scores from the model's classification head

The script aggregates these predictions, bins them by confidence score,
and computes observed error rates per bin.

Output: artifacts/results/error_detection_calibration.json
"""
import os
import sys
import json
import argparse
from typing import List, Dict, Any
from pathlib import Path

# Add project root to path
project_root = Path(__file__).parent.parent.parent
sys.path.insert(0, str(project_root))

from evaluation.metrics import calculate_error_detection_calibration, save_calibration_results
from utils.logging import get_logger

logger = get_logger(__name__)

def load_evaluation_results(benchmark_output_path: str) -> Dict[str, Any]:
    """
    Load evaluation results from a JSON file generated by run_benchmarks.py.
    
    Args:
        benchmark_output_path: Path to the benchmark output JSON file
    
    Returns:
        Dictionary containing evaluation results
    """
    if not os.path.exists(benchmark_output_path):
        raise FileNotFoundError(f"Benchmark output file not found: {benchmark_output_path}")
    
    with open(benchmark_output_path, 'r') as f:
        return json.load(f)

def extract_error_data(evaluation_results: Dict[str, Any]) -> tuple:
    """
    Extract error flags and confidence scores from evaluation results.
    
    Args:
        evaluation_results: Dictionary containing evaluation results
    
    Returns:
        Tuple of (error_flags, confidence_scores)
    """
    error_flags = []
    confidence_scores = []
    
    # Handle different possible structures of evaluation results
    if "results" in evaluation_results:
        results_list = evaluation_results["results"]
    elif "predictions" in evaluation_results:
        results_list = evaluation_results["predictions"]
    else:
        # Assume flat structure
        results_list = [evaluation_results]
    
    for item in results_list:
        if isinstance(item, dict):
            # Extract error flag (0 = correct, 1 = error)
            error_flag = item.get("error_flag", 0)
            confidence = item.get("confidence_score", 0.0)
            
            error_flags.append(error_flag)
            confidence_scores.append(confidence)
    
    if not error_flags:
        raise ValueError("No error data found in evaluation results")
    
    return error_flags, confidence_scores

def main():
    parser = argparse.ArgumentParser(description="Run error detection calibration analysis")
    parser.add_argument(
        "--benchmark-output",
        type=str,
        default="artifacts/results/benchmark_results.json",
        help="Path to benchmark output JSON file"
    )
    parser.add_argument(
        "--output-path",
        type=str,
        default="artifacts/results/error_detection_calibration.json",
        help="Path to save calibration results"
    )
    parser.add_argument(
        "--n-bins",
        type=int,
        default=10,
        help="Number of bins for calibration (default: 10)"
    )
    
    args = parser.parse_args()
    
    logger.info(f"Loading evaluation results from {args.benchmark_output}")
    
    try:
        # Load evaluation results
        evaluation_results = load_evaluation_results(args.benchmark_output)
        
        # Extract error data
        error_flags, confidence_scores = extract_error_data(evaluation_results)
        
        logger.info(f"Extracted {len(error_flags)} error samples")
        
        # Calculate error detection calibration
        calibration_results = calculate_error_detection_calibration(
            error_flags=error_flags,
            confidence_scores=confidence_scores,
            n_bins=args.n_bins
        )
        
        # Save results
        save_calibration_results(calibration_results, args.output_path)
        
        logger.info(f"Calibration analysis complete. Results saved to {args.output_path}")
        
        # Print summary
        logger.info("Calibration Summary:")
        logger.info(f"  Total samples: {len(error_flags)}")
        logger.info(f"  Bins: {args.n_bins}")
        logger.info(f"  Bin counts: {calibration_results['bin_counts']}")
        
    except Exception as e:
        logger.error(f"Error during calibration analysis: {str(e)}")
        raise

if __name__ == "__main__":
    main()