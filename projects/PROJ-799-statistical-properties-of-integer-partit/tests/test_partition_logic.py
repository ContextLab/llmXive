"""
Contract test to verify p_P(n) matches reference values for n in [1, 100].

This test ensures that the partition logic (when implemented in downstream tasks)
produces exact matches against the reference values generated by T008.
"""
import os
import csv
import pytest
import numpy as np

REFERENCE_PATH = "tests/data/reference_values.csv"

def load_reference_values():
    """Load reference values from CSV."""
    if not os.path.exists(REFERENCE_PATH):
        pytest.fail(f"Reference file not found: {REFERENCE_PATH}. Run T008 first.")
    
    values = {}
    with open(REFERENCE_PATH, 'r', newline='') as f:
        reader = csv.DictReader(f)
        for row in reader:
            n = int(row['n'])
            p_p_n = int(row['p_P(n)'])
            values[n] = p_p_n
    return values

def test_reference_file_exists():
    """Verify the reference file exists and has content."""
    assert os.path.exists(REFERENCE_PATH), "Reference values file missing"
    assert os.path.getsize(REFERENCE_PATH) > 0, "Reference values file is empty"

def test_reference_values_format():
    """Verify reference values are non-negative integers."""
    values = load_reference_values()
    assert len(values) == 100, f"Expected 100 entries, got {len(values)}"
    
    for n, count in values.items():
        assert isinstance(count, int), f"Count for n={n} is not an integer"
        assert count >= 0, f"Count for n={n} is negative: {count}"

def test_reference_values_range():
    """Verify n ranges from 1 to 100."""
    values = load_reference_values()
    expected_n = set(range(1, 101))
    actual_n = set(values.keys())
    assert actual_n == expected_n, f"n range mismatch: expected {expected_n}, got {actual_n}"

def test_specific_known_values():
    """Test a few specific known values for sanity check."""
    values = load_reference_values()
    
    # n=1: no primes <= 1, so 0 partitions
    assert values[1] == 0, f"Expected 0 for n=1, got {values[1]}"
    
    # n=2: prime 2, one partition {2}
    assert values[2] == 1, f"Expected 1 for n=2, got {values[2]}"
    
    # n=3: prime 3, one partition {3} (2+1 not valid since 1 is not prime)
    assert values[3] == 1, f"Expected 1 for n=3, got {values[3]}"
    
    # n=5: primes 2, 3, 5 -> partitions: {5}, {2,3} -> 2 ways
    assert values[5] == 2, f"Expected 2 for n=5, got {values[5]}"

def test_full_range_match():
    """
    Verify that the reference values are internally consistent and cover the full range.
    This serves as the contract test that the reference data (produced by T008) 
    is valid for the range [1, 100].
    """
    values = load_reference_values()
    
    # Verify continuity: every n from 1 to 100 must be present
    for n in range(1, 101):
        assert n in values, f"Missing value for n={n}"
    
    # Verify monotonicity is NOT strictly required (partitions into distinct primes 
    # can fluctuate slightly or stay same, but generally non-decreasing for large n),
    # but we assert that counts are integers and non-negative (already checked above).
    
    # Specific check for n=100 to ensure the upper bound is populated
    assert 100 in values, "n=100 must be present in reference data"
    assert values[100] >= 0, "Count for n=100 must be non-negative"