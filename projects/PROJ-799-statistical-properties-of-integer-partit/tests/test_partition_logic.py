"""
Contract test: Verify p_P(n) matches tests/data/reference_values.csv for all n in [1, 100].

This test validates the core distinct-prime partition logic against pre-computed
reference values generated by T008. It ensures the DP algorithm correctly
implements the generating function ∏_{p∈P} (1+q^p).
"""
import os
import csv
import pytest
import numpy as np
from pathlib import Path

# Path to reference file
REFERENCE_PATH = Path(__file__).parent / "data" / "reference_values.csv"

@pytest.fixture
def reference_data():
    """Load reference values from CSV."""
    if not REFERENCE_PATH.exists():
        pytest.fail(f"Reference file not found: {REFERENCE_PATH}. Run T008 first.")
    
    data = {}
    with open(REFERENCE_PATH, 'r', newline='') as f:
        reader = csv.DictReader(f)
        for row in reader:
            n = int(row['n'])
            count = int(row['p_P(n)'])
            data[n] = count
    return data

def test_reference_file_exists():
    """Verify reference file exists."""
    assert REFERENCE_PATH.exists(), f"Reference file {REFERENCE_PATH} does not exist."

def test_reference_file_format(reference_data):
    """Verify reference file has correct format and valid integers."""
    assert len(reference_data) == 100, f"Expected 100 entries, got {len(reference_data)}"
    
    for n, count in reference_data.items():
        assert n >= 1 and n <= 100, f"Invalid n value: {n}"
        assert isinstance(count, int), f"Count must be integer, got {type(count)}"
        assert count >= 0, f"Count must be non-negative, got {count}"

def test_partition_logic_matches_reference(reference_data):
    """
    Compute p_P(n) using the same DP algorithm and verify against reference.
    This is the core contract test.
    
    Algorithm:
    - Initialize dp array of size n_max + 1 with zeros, dp[0] = 1.
    - Iterate over primes p <= n_max.
    - For each prime, update dp[n] += dp[n - p] for n from n_max down to p.
    - This ensures each prime is used at most once (distinct summands).
    """
    from utils.prime_sieve import generate_primes
    
    n_max = 100
    primes = generate_primes(n_max)
    
    # Run DP algorithm
    # Use int64 to prevent overflow for larger n, though values are small for n<=100
    dp = np.zeros(n_max + 1, dtype=np.int64)
    dp[0] = 1
    
    for p in primes:
        for n in range(n_max, p - 1, -1):
            dp[n] += dp[n - p]
    
    # Verify against reference
    mismatches = []
    for n in range(1, n_max + 1):
        computed = int(dp[n])
        expected = reference_data[n]
        if computed != expected:
            mismatches.append((n, computed, expected))
    
    if mismatches:
        error_msg = "Partition logic mismatches reference values:\n"
        for n, computed, expected in mismatches:
            error_msg += f"  n={n}: computed={computed}, expected={expected}\n"
        pytest.fail(error_msg)
    
    # If we get here, all values match
    print("All partition values match reference data for n in [1, 100]")

def test_specific_values():
    """Test specific known values to ensure correctness."""
    from utils.prime_sieve import generate_primes
    
    # Known values (manually verified for small n):
    # n=1: no primes <= 1, so 0
    # n=2: prime 2. Partition: {2} -> 1 way
    # n=3: primes {2, 3}. Partition: {3} -> 1 way (2+? no)
    # n=5: primes {2, 3, 5}. Partitions: {5}, {2,3} -> 2 ways
    
    n_test = 5
    primes = generate_primes(n_test)
    
    dp = np.zeros(n_test + 1, dtype=np.int64)
    dp[0] = 1
    
    for p in primes:
        for n in range(n_test, p - 1, -1):
            dp[n] += dp[n - p]
    
    # n=5 should be 2: {5}, {2,3}
    assert int(dp[5]) == 2, f"Expected p_P(5)=2, got {dp[5]}"
    
    # n=10: primes {2,3,5,7}. 
    # Partitions: {7,3}, {5,3,2} -> 2 ways
    # Verification:
    # dp[0]=1
    # p=2: dp[2]=1
    # p=3: dp[5]+=dp[2]=1, dp[3]=1 -> dp[3]=1, dp[5]=1
    # p=5: dp[10]+=dp[5]=1, dp[8]+=dp[3]=1, dp[7]+=dp[2]=1, dp[5]+=1 -> dp[5]=2, dp[7]=1, dp[8]=1, dp[10]=1
    # p=7: dp[10]+=dp[3]=1 -> dp[10]=2
    assert int(dp[10]) == 2, f"Expected p_P(10)=2, got {dp[10]}"