"""
Contract test for T014: Feature Engineering Residual Calculation.

Verifies that the residual R(n) = log(p_P(n)) - log(Q_as(n)) is calculated correctly,
handles log(0) gracefully (by skipping invalid n), and matches expected values
for a sample of known n.

This test assumes the existence of `data/raw/partitions_raw.csv` generated by T012.
If the file is missing, the test will fail loudly as per the "fail loudly" constraint.
"""
import os
import sys
import math
import csv
import pytest

# Add project root to path to allow imports from code/
project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, project_root)

from utils.prime_sieve import generate_primes
from utils.asymptotic_baseline import compute_asymptotic_baseline


def load_partition_data():
    """Load the raw partition data generated by T012."""
    data_path = os.path.join(project_root, 'data', 'raw', 'partitions_raw.csv')
    if not os.path.exists(data_path):
        raise FileNotFoundError(
            f"Required data file not found: {data_path}. "
            "Ensure T012 (generate_partitions.py) has completed successfully."
        )

    data = []
    with open(data_path, 'r', newline='') as f:
        reader = csv.DictReader(f)
        for row in reader:
            data.append({
                'n': int(row['n']),
                'p_P_n': int(row['p_P(n)']),
                'Q_as_n': float(row['Q_as(n)'])
            })
    return data


def compute_residual(p_P_n, Q_as_n):
    """
    Compute the residual R(n) = log(p_P(n)) - log(Q_as(n)).
    Returns None if either value is <= 0 to avoid log(0).
    """
    if p_P_n <= 0 or Q_as_n <= 0:
        return None
    return math.log(p_P_n) - math.log(Q_as_n)


class TestResidualCalculation:
    """Contract tests for R(n) calculation logic."""

    def test_handles_log_zero_gracefully(self):
        """
        Verify that R(n) calculation handles log(0) gracefully.
        For n where p_P(n) = 0 or Q_as(n) <= 0, the function should return None
        rather than raising a ValueError or returning NaN.
        """
        # Case 1: p_P(n) = 0 (e.g., n < 2, though our data starts at 1)
        result = compute_residual(0, 1.5)
        assert result is None, "Should return None when p_P(n) is 0"

        # Case 2: Q_as(n) <= 0
        result = compute_residual(5, -0.1)
        assert result is None, "Should return None when Q_as(n) is negative"

        result = compute_residual(5, 0.0)
        assert result is None, "Should return None when Q_as(n) is 0"

    def test_matches_expected_values_for_sample_n(self):
        """
        Verify R(n) matches expected values for a sample of n.
        We use a small set of manually verified or known values.
        Since we rely on T012 data, we verify the calculation logic
        against the loaded data for specific n.
        """
        data = load_partition_data()
        if not data:
            pytest.fail("No data loaded from partitions_raw.csv")

        # Sample specific n values to check against the loaded data
        # We pick a few n values from the data and re-calculate R(n)
        # to ensure the formula is applied correctly.
        test_indices = [0, 10, 50, 100]  # Indices into the loaded data list

        for idx in test_indices:
            if idx >= len(data):
                continue

            record = data[idx]
            n = record['n']
            p_p_n = record['p_P_n']
            q_as_n = record['Q_as_n']

            # Calculate expected residual
            expected_residual = compute_residual(p_p_n, q_as_n)

            # If expected is None (due to log(0) protection), skip detailed comparison
            if expected_residual is None:
                # Just verify that the logic correctly identified it as invalid
                assert p_p_n <= 0 or q_as_n <= 0, \
                    f"Expected None for n={n} but p_P={p_p_n}, Q_as={q_as_n}"
                continue

            # Verify the calculation logic (simple re-implementation check)
            # We don't have a separate "ground truth" for R(n) other than the formula,
            # so we verify that the components are consistent.
            # We can check if the sign and magnitude are reasonable for a partition function.
            # p_P(n) and Q_as(n) should be positive for valid n.
            assert p_p_n > 0, f"p_P(n) should be positive for n={n}"
            assert q_as_n > 0, f"Q_as(n) should be positive for n={n}"

            # Re-calculate to ensure no floating point drift in the test logic itself
            manual_calc = math.log(p_p_n) - math.log(q_as_n)
            assert math.isclose(expected_residual, manual_calc, rel_tol=1e-9), \
                f"Residual calculation mismatch for n={n}"

    def test_residual_trend_for_small_n(self):
        """
        Verify that for small n where p_P(n) is known to be 0, the residual is handled.
        For n=1, 2, 3, 4, p_P(n) is typically 0 or very small.
        """
        data = load_partition_data()
        # Find records for small n
        small_n_records = [r for r in data if r['n'] <= 10]

        for record in small_n_records:
            n = record['n']
            p_p_n = record['p_P_n']
            q_as_n = record['Q_as_n']

            # If p_P(n) is 0, residual should be None
            if p_p_n == 0:
                assert compute_residual(p_p_n, q_as_n) is None, \
                    f"Residual for n={n} (p_P=0) should be None"

    def test_feature_engineering_input_compatibility(self):
        """
        Verify that the loaded data has the correct structure to be used
        as input for feature engineering (T016a).
        """
        data = load_partition_data()
        assert len(data) > 0, "Data must not be empty"

        first_record = data[0]
        required_keys = {'n', 'p_P_n', 'Q_as_n'}
        assert required_keys.issubset(first_record.keys()), \
            f"Missing required keys in data. Found: {first_record.keys()}"

        # Verify types
        assert isinstance(first_record['n'], int), "n must be int"
        assert isinstance(first_record['p_P_n'], int), "p_P_n must be int"
        assert isinstance(first_record['Q_as_n'], float), "Q_as_n must be float"