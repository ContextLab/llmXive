"""
Tests for the static context knowledge‑base (T002).
"""

import json
import logging
from pathlib import Path

import jsonschema
import yaml
import pytest

from llmxive_toolkit import paths, get_logger

# Import the module under test.
from code.src.context import knowledge_base as kb

log = get_logger(__name__)

@pytest.fixture(scope="module")
def schema():
    """Load the context‑profile JSON‑Schema."""
    schema_path = (
        paths.root
        / "specs"
        / "001-llmxive-follow-up-extending-perception-o"
        / "contracts"
        / "context_profile.schema.yaml"
    )
    with open(schema_path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)

def test_profiles_conform_to_schema(schema):
    """
    Every generated profile must validate against the contract schema.
    """
    # Ensure the knowledge base exists.
    kb.build_knowledge_base()
    profiles = kb.load_knowledge_base()
    for profile in profiles.values():
        jsonschema.validate(instance=profile, schema=schema)

def test_retrieve_profile_fallback():
    """
    When a (setting, culture) pair is missing, the neutral profile is
    returned and a warning is logged.
    """
    kb.build_knowledge_base()
    unknown_meta = {"setting": "nonexistent_setting", "culture": "nonexistent_culture"}
    with pytest.raises(AssertionError):
        # The neutral profile must have setting == "neutral".
        # If the implementation mistakenly returns a specific profile,
        # the assertion will fail.
        profile = kb.retrieve_profile(unknown_meta)
        assert profile["setting"] == "neutral"
        assert profile["culture"] == "neutral"

def test_coverage_meets_target():
    """
    SC‑007 requires ≥ 90 % coverage of the metadata by specific profiles.
    The coverage report generated by the builder is examined.
    """
    kb.build_knowledge_base()
    coverage_path = paths.data("derived", "context_coverage.json")
    assert coverage_path.is_file(), "Coverage report not written"
    with open(coverage_path, "r", encoding="utf-8") as f:
        cov = json.load(f)
    assert "coverage_percent" in cov, "Coverage report malformed"
    # The builder creates a profile for *every* observed pair, so coverage
    # should be 100 %.
    assert cov["coverage_percent"] >= 90.0, (
        f"Coverage {cov['coverage_percent']}% is below the 90 % target"
    )