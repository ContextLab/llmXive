# Configure logging
logger = get_logger("simulation_mfq")

# Constants
MDES_REPORT_PATH = "state/mdes_report.yaml"
NORMS_CONFIG_PATH = "data/config/gervais_norms.yaml"
OUTPUT_PATH = "data/processed/synthetic_mfq.csv"
LOG_PATH = "data/logs/simulation_mfq.log"

# MFQ Dimensions
MFQ_DIMENSIONS = ["care", "fairness", "loyalty", "authority", "purity"]

def load_mdes_report() -> Dict[str, Any]:
    """
    Load the MDES report generated by T045.
    
    Raises:
        FileNotFoundError: If the MDES report is missing.
        KeyError: If required keys are missing from the report.
    """
    report_path = get_path(MDES_REPORT_PATH)
    
    if not report_path.exists():
        raise FileNotFoundError(
            f"MDES report missing at {report_path}. "
            "Ensure T045 (Power Analysis) is complete before running this task."
        )
    
    with open(report_path, 'r') as f:
        report = yaml.safe_load(f)
    
    # Validate required keys
    required_keys = ["n_required", "effect_size", "power"]
    missing_keys = [key for key in required_keys if key not in report]
    
    if missing_keys:
        raise KeyError(
            f"MDES report missing required keys: {missing_keys}. "
            "Expected keys: {required_keys}"
        )
    
    return report

def validate_ground_truth_effect(effect_size: float) -> bool:
    """
    Validate that the ground truth effect size is within literature bounds.
    
    Args:
        effect_size: The effect size to validate.
        
    Returns:
        True if valid, raises ValueError otherwise.
    """
    # Literature bounds from Gervais et al. (2014)
    min_effect = 0.2
    max_effect = 0.8
    
    if not (min_effect <= effect_size <= max_effect):
        raise ValueError(
            f"Ground truth effect size {effect_size} is outside literature bounds "
            f"[{min_effect}, {max_effect}]."
        )
    
    return True

def get_correlation_matrix() -> np.ndarray:
    """
    Generate a correlation matrix for MFQ dimensions based on literature.
    
    Returns:
        A 5x5 correlation matrix.
    """
    # Approximate correlations from Gervais et al. (2014)
    # Care, Fairness, Loyalty, Authority, Purity
    correlations = np.array([
        [1.00, 0.65, 0.40, 0.35, 0.30],
        [0.65, 1.00, 0.45, 0.40, 0.35],
        [0.40, 0.45, 1.00, 0.60, 0.55],
        [0.35, 0.40, 0.60, 1.00, 0.70],
        [0.30, 0.35, 0.55, 0.70, 1.00]
    ])
    return correlations

def generate_covariance_matrix(
    means: Dict[str, float], 
    stds: Dict[str, float], 
    corr_matrix: np.ndarray
) -> np.ndarray:
    """
    Convert correlation matrix to covariance matrix using means and stds.
    
    Args:
        means: Dictionary of mean values for each dimension.
        stds: Dictionary of standard deviation values for each dimension.
        corr_matrix: Correlation matrix.
        
    Returns:
        Covariance matrix.
    """
    dims = list(means.keys())
    n = len(dims)
    cov_matrix = np.zeros((n, n))
    
    for i, dim_i in enumerate(dims):
        for j, dim_j in enumerate(dims):
            cov_matrix[i, j] = (
                corr_matrix[i, j] * stds[dim_i] * stds[dim_j]
            )
    
    return cov_matrix

def generate_synthetic_mfq(
    n_samples: int,
    means: Dict[str, float],
    stds: Dict[str, float],
    corr_matrix: np.ndarray,
    seed: int
) -> pd.DataFrame:
    """
    Generate synthetic MFQ data using multivariate normal distribution.
    
    Args:
        n_samples: Number of participants to simulate.
        means: Mean values for each dimension.
        stds: Standard deviations for each dimension.
        corr_matrix: Correlation matrix.
        seed: Random seed for reproducibility.
        
    Returns:
        DataFrame with synthetic MFQ data.
    """
    init_random_seeds(seed)
    
    dims = list(means.keys())
    mean_vector = [means[dim] for dim in dims]
    cov_matrix = generate_covariance_matrix(means, stds, corr_matrix)
    
    # Generate multivariate normal samples
    samples = np.random.multivariate_normal(mean_vector, cov_matrix, n_samples)
    
    # Create DataFrame
    df = pd.DataFrame(samples, columns=dims)
    
    # Add participant IDs
    df["participant_id"] = [f"sub_{i:04d}" for i in range(1, n_samples + 1)]
    
    # Calculate total score (sum of all dimensions)
    df["total_score"] = df[MFQ_DIMENSIONS].sum(axis=1)
    
    # Reorder columns to put participant_id first and total_score last
    df = df[["participant_id"] + MFQ_DIMENSIONS + ["total_score"]]
    
    return df

def save_synthetic_mfq(df: pd.DataFrame, output_path: str) -> None:
    """
    Save the synthetic MFQ data to CSV.
    
    Args:
        df: DataFrame with synthetic MFQ data.
        output_path: Path to save the CSV file.
    """
    full_path = get_path(output_path)
    full_path.parent.mkdir(parents=True, exist_ok=True)
    
    df.to_csv(full_path, index=False)
    logger.info(f"Synthetic MFQ data saved to {full_path}")

def update_artifact_hash(file_path: str) -> None:
    """
    Calculate and update the artifact hash for the generated CSV.
    
    Args:
        file_path: Path to the generated CSV file.
    """
    full_path = get_path(file_path)
    checksum = calculate_checksum(full_path)
    update_state_file(full_path, checksum)
    logger.info(f"Updated artifact hash for {full_path}: {checksum}")

@log_operation
def run_simulation_pipeline(
    seed: int = 42,
    override_n: Optional[int] = None
) -> pd.DataFrame:
    """
    Run the full synthetic MFQ generation pipeline.
    
    Args:
        seed: Random seed for reproducibility.
        override_n: Optional override for sample size (for testing).
        
    Returns:
        Generated DataFrame.
    """
    log_operation("START", "T013: Synthetic MFQ Generation")
    
    # Load MDES report
    mdes_report = load_mdes_report()
    n_required = mdes_report["n_required"]
    effect_size = mdes_report["effect_size"]
    
    # Validate effect size
    validate_ground_truth_effect(effect_size)
    logger.info(f"Ground truth effect size validated: {effect_size}")
    
    # Use override N if provided, otherwise use MDES n_required
    n_samples = override_n if override_n is not None else n_required
    logger.info(f"Generating {n_samples} synthetic MFQ samples")
    
    # Load norms
    norms_path = get_path(NORMS_CONFIG_PATH)
    if not norms_path.exists():
        raise FileNotFoundError(
            f"Norms config missing at {norms_path}. "
            "Ensure T007b is complete."
        )
    
    with open(norms_path, 'r') as f:
        norms = yaml.safe_load(f)
    
    # Extract means and stds
    means = {dim: norms[dim]["mean"] for dim in MFQ_DIMENSIONS}
    stds = {dim: norms[dim]["std"] for dim in MFQ_DIMENSIONS}
    
    logger.info(f"Loaded norms: {means}")
    
    # Generate correlation matrix
    corr_matrix = get_correlation_matrix()
    
    # Generate synthetic data
    df = generate_synthetic_mfq(
        n_samples=n_samples,
        means=means,
        stds=stds,
        corr_matrix=corr_matrix,
        seed=seed
    )
    
    # Save to CSV
    save_synthetic_mfq(df, OUTPUT_PATH)
    
    # Update artifact hash
    update_artifact_hash(OUTPUT_PATH)
    
    log_operation("SUCCESS", "T013: Synthetic MFQ Generation completed")
    return df

def main() -> None:
    """Main entry point for the script."""
    try:
        run_simulation_pipeline(seed=42)
        logger.info("T013 completed successfully.")
    except Exception as e:
        logger.error(f"T013 failed: {str(e)}")
        raise

if __name__ == "__main__":
    main()