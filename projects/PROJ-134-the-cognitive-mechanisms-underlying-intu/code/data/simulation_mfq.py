"""
T013: Synthetic MFQ Data Generation for Simulation Validation.

Generates synthetic Moral Foundations Questionnaire (MFQ) data based on 
Gervais et al. multivariate normal distributions.

Prerequisites:
    - state/mdes_report.yaml must exist (generated by T045)
    - data/config/gervais_norms.yaml must exist (generated by T007b)

Deliverable:
    - data/processed/synthetic_mfq.csv with columns:
      participant_id, care, fairness, loyalty, authority, purity, total_score
"""
