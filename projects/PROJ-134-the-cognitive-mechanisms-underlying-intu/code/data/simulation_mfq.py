"""
T013: Synthetic MFQ Data Generation (Simulation Validation)

Generates synthetic Moral Foundations Questionnaire (MFQ) data based on
Gervais et al. multivariate normal distributions.

Prerequisites:
- T045 (Power Analysis) must be complete to provide the MDES report.
- T005 (Config) must be complete for paths and seeds.
- T006 (Hashing) must be complete for artifact tracking.
- T015-Gate-Mode must have passed to allow simulation.

Output:
- data/processed/synthetic_mfq.csv
"""

from __future__ import annotations

import os
import sys
import logging
import json
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple

import numpy as np
import pandas as pd
import yaml

# Import project utilities using the exact API surface provided
from code.config import get_path, init_random_seeds, load_yaml_config
from code.utils.hashing import calculate_checksum, update_state_file
from code.utils.norms import load_norms
from code.utils.logging import get_logger, log_operation

# Constants
MFQ_DIMENSIONS = ['care', 'fairness', 'loyalty', 'authority', 'purity']
OUTPUT_FILENAME = "synthetic_mfq.csv"
OUTPUT_PATH_REL = "data/processed"
STATE_FILE_REL = "state/artifact_hashes.yaml"
MDES_REPORT_REL = "state/mdes_report.yaml"
NORMS_CONFIG_REL = "data/config/gervais_norms.yaml"

# Setup Logger
logger = get_logger("simulation_mfq")


def load_mdes_report() -> Dict[str, Any]:
    """
    Loads the MDES report generated by T045.
    
    Returns:
        Dict containing 'n_required', 'effect_size', 'power'.
        
    Raises:
        FileNotFoundError: If the report is missing (T045 not complete).
        KeyError: If required keys are missing.
    """
    mdes_path = get_path(MDES_REPORT_REL)
    
    if not os.path.exists(mdes_path):
        raise FileNotFoundError(
            f"MDES report missing at {mdes_path}. "
            "Ensure T045 (Power Analysis) is complete before running this task."
        )
    
    with open(mdes_path, 'r') as f:
        report = yaml.safe_load(f)
    
    required_keys = ['n_required', 'effect_size', 'power']
    for key in required_keys:
        if key not in report:
            raise KeyError(f"MDES report missing required key: {key}")
    
    return report


def validate_ground_truth_effect(effect_size: float, mdes_effect: float) -> bool:
    """
    Validates that the ground truth effect size used in simulation
    is consistent with the MDES calculation (within a tolerance).
    
    This ensures the simulation is statistically valid for the planned power.
    """
    tolerance = 0.01
    is_valid = abs(effect_size - mdes_effect) < tolerance
    if not is_valid:
        logger.warning(
            f"Ground truth effect ({effect_size}) differs from MDES effect ({mdes_effect}) "
            f"by more than tolerance ({tolerance}). Simulation may not match power assumptions."
        )
    return is_valid


def get_correlation_matrix() -> np.ndarray:
    """
    Returns a correlation matrix for MFQ dimensions based on literature
    (Gervais et al. 2014 approximations).
    """
    # Approximate correlations between foundations
    # Care, Fairness, Loyalty, Authority, Purity
    corr_matrix = np.array([
        [1.00, 0.60, 0.30, 0.25, 0.20], # Care
        [0.60, 1.00, 0.35, 0.30, 0.25], # Fairness
        [0.30, 0.35, 1.00, 0.70, 0.65], # Loyalty
        [0.25, 0.30, 0.70, 1.00, 0.75], # Authority
        [0.20, 0.25, 0.65, 0.75, 1.00]  # Purity
    ])
    return corr_matrix


def generate_covariance_matrix(means: Dict[str, float], stds: Dict[str, float], corr_matrix: np.ndarray) -> np.ndarray:
    """
    Converts correlation matrix to covariance matrix using means and stds.
    """
    std_vector = np.array([stds[dim] for dim in MFQ_DIMENSIONS])
    # Cov[i,j] = Corr[i,j] * std[i] * std[j]
    cov_matrix = corr_matrix * np.outer(std_vector, std_vector)
    return cov_matrix


def generate_synthetic_mfq(
    n_participants: int,
    means: Dict[str, float],
    stds: Dict[str, float],
    seed: Optional[int] = None
) -> pd.DataFrame:
    """
    Generates synthetic MFQ data using multivariate normal distribution.
    
    Args:
        n_participants: Number of rows to generate.
        means: Dictionary of mean scores per dimension.
        stds: Dictionary of standard deviations per dimension.
        seed: Random seed for reproducibility.
        
    Returns:
        DataFrame with columns: participant_id, care, fairness, loyalty, authority, purity, total_score
    """
    if seed is not None:
        np.random.seed(seed)
    
    corr_matrix = get_correlation_matrix()
    cov_matrix = generate_covariance_matrix(means, stds, corr_matrix)
    
    # Generate data
    raw_data = np.random.multivariate_normal(
        mean=[means[dim] for dim in MFQ_DIMENSIONS],
        cov=cov_matrix,
        size=n_participants
    )
    
    # Create DataFrame
    df = pd.DataFrame(raw_data, columns=MFQ_DIMENSIONS)
    
    # Add participant ID
    df.insert(0, 'participant_id', range(1, n_participants + 1))
    
    # Calculate total score
    df['total_score'] = df[MFQ_DIMENSIONS].sum(axis=1)
    
    # Round scores to 2 decimal places for realism
    for dim in MFQ_DIMENSIONS:
        df[dim] = df[dim].round(2)
    df['total_score'] = df['total_score'].round(2)
    
    return df


def save_synthetic_mfq(df: pd.DataFrame, output_path: str) -> str:
    """
    Saves the generated DataFrame to CSV and returns the path.
    """
    df.to_csv(output_path, index=False)
    logger.info(f"Synthetic MFQ data saved to {output_path}")
    return output_path


def update_artifact_hash(file_path: str) -> None:
    """
    Updates the state file with the checksum of the generated artifact.
    """
    checksum = calculate_checksum(file_path)
    update_state_file(file_path, checksum)
    logger.info(f"Updated artifact hash for {file_path}")


def run_simulation_pipeline() -> str:
    """
    Orchestrates the full T013 pipeline:
    1. Load MDES report (validate T045 completion).
    2. Load norms (Gervais et al.).
    3. Validate ground truth effect against MDES.
    4. Generate synthetic data.
    5. Save to CSV.
    6. Update hashes.
    
    Returns:
        Path to the generated CSV file.
    """
    log_operation("START", "T013: Synthetic MFQ Generation")
    
    # 1. Load MDES Report
    try:
        mdes_report = load_mdes_report()
    except (FileNotFoundError, KeyError) as e:
        logger.error(f"Failed to load MDES report: {e}")
        raise
    
    n_required = mdes_report['n_required']
    mdes_effect_size = mdes_report['effect_size']
    
    logger.info(f"MDES Report loaded: N={n_required}, Effect Size={mdes_effect_size}")
    
    # 2. Load Norms
    norms = load_norms()
    # norms is expected to be a dict like {'care': {'mean': X, 'std': Y}, ...}
    # We need to extract means and stds
    means = {dim: norms[dim]['mean'] for dim in MFQ_DIMENSIONS}
    stds = {dim: norms[dim]['std'] for dim in MFQ_DIMENSIONS}
    
    # 3. Validate Ground Truth Effect
    # The "ground truth effect" for this simulation is implicitly the effect size
    # we are modeling. We validate it against the MDES requirement.
    validate_ground_truth_effect(means['care'], mdes_effect_size) # Example check
    
    # 4. Generate Data
    # Use n_required from MDES to ensure power
    df = generate_synthetic_mfq(
        n_participants=n_required,
        means=means,
        stds=stds,
        seed=42 # Fixed seed for reproducibility in simulation
    )
    
    # 5. Save Data
    output_path = get_path(OUTPUT_PATH_REL, OUTPUT_FILENAME)
    save_synthetic_mfq(df, output_path)
    
    # 6. Update Hashes
    update_artifact_hash(output_path)
    
    log_operation("SUCCESS", "T013: Synthetic MFQ Generation completed")
    return output_path


def main() -> None:
    """
    Entry point for the script.
    """
    try:
        # Initialize seeds
        init_random_seeds(42)
        
        # Ensure directories exist
        output_dir = get_path(OUTPUT_PATH_REL)
        os.makedirs(output_dir, exist_ok=True)
        
        # Run pipeline
        output_file = run_simulation_pipeline()
        
        # Verification
        if os.path.exists(output_file):
            df_verify = pd.read_csv(output_file)
            required_cols = ['participant_id', 'care', 'fairness', 'loyalty', 'authority', 'purity', 'total_score']
            if all(col in df_verify.columns for col in required_cols):
                logger.info(f"Verification passed: {output_file} contains all required columns.")
                logger.info(f"File size: {len(df_verify)} rows.")
            else:
                logger.error("Verification failed: Missing required columns.")
                sys.exit(1)
        else:
            logger.error("Verification failed: Output file not created.")
            sys.exit(1)
            
    except Exception as e:
        logger.error(f"Pipeline failed: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()