"""
Unity Simulation Fidelity Verification (T076).

Verifies that simulated blend-shape parameters match the reference
configuration (data/config/unity_blend_shapes.yaml) within acceptable tolerance.
Logs actual parameter sets used and updates artifact checksums.
"""
from __future__ import annotations

import json
import logging
import os
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

import yaml

# Import shared utilities from the project
from code.config import get_path, load_yaml_config
from code.utils.hashing import calculate_checksum, update_state_file
from code.utils.logging import get_logger, log_operation


# Constants
REFERENCE_CONFIG_PATH = "data/config/unity_blend_shapes.yaml"
OUTPUT_FIDELITY_PATH = "data/config/unity_simulation_fidelity.yaml"
LOG_PARAMS_PATH = "data/logs/simulation_params.log"
TOLERANCE = 1e-6  # Floating point tolerance for comparison

# Mock simulated parameters (in a real run, these would come from the simulation output)
# For this task, we assume the simulation has already run and written its parameters
# to a temporary file or we read them from the simulation output.
# Since T013/T014 are simulation tasks, we will simulate the "actual" parameters
# by reading them from a hypothetical simulation output file if it exists,
# or by using the reference values themselves if we are just verifying the logic.
# To satisfy the "real data" constraint for the VERIFICATION step, we will
# assume the simulation output is at data/processed/simulation_params.json (generated by T014).
SIMULATION_OUTPUT_PATH = "data/processed/simulation_params.json"


def load_reference_config() -> Dict[str, Any]:
    """Load the reference Unity blend shape configuration."""
    config_path = get_path(REFERENCE_CONFIG_PATH)
    if not os.path.exists(config_path):
        raise FileNotFoundError(f"Reference config not found: {config_path}")
    return load_yaml_config(config_path)


def load_simulated_params() -> Dict[str, Any]:
    """
    Load the actual parameters used in the simulation run.
    If the file doesn't exist, we cannot verify fidelity, so we raise an error.
    """
    sim_path = get_path(SIMULATION_OUTPUT_PATH)
    if not os.path.exists(sim_path):
        # If simulation output doesn't exist, we cannot verify.
        # This is a failure condition for the verification step.
        raise FileNotFoundError(
            f"Simulation parameters file not found: {sim_path}. "
            "Ensure T013/T014 (simulation) have run and written output."
        )
    with open(sim_path, 'r') as f:
        return json.load(f)


def validate_blend_shape_ranges(
    params: Dict[str, Any],
    min_val: float = 0.0,
    max_val: float = 1.0
) -> List[str]:
    """Validate that all blend shape parameters are within [min_val, max_val]."""
    errors = []
    for story_id, data in params.get("mappings", {}).items():
        if "blend_shape_params" in data:
            for key, val in data["blend_shape_params"].items():
                if not (min_val <= val <= max_val):
                    errors.append(
                        f"Parameter {key} for {story_id} is out of range: {val}"
                    )
    return errors


def validate_blend_shape_keys(
    simulated: Dict[str, Any],
    reference: Dict[str, Any]
) -> List[str]:
    """Ensure simulated parameters have the same keys as reference."""
    errors = []
    ref_keys = set()
    for story_id, data in reference.get("mappings", {}).items():
        if "blend_shape_params" in data:
            ref_keys.update(data["blend_shape_params"].keys())

    sim_keys = set()
    for story_id, data in simulated.get("mappings", {}).items():
        if "blend_shape_params" in data:
            sim_keys.update(data["blend_shape_params"].keys())

    missing = ref_keys - sim_keys
    extra = sim_keys - ref_keys
    if missing:
        errors.append(f"Missing keys in simulation: {missing}")
    if extra:
        errors.append(f"Extra keys in simulation: {extra}")
    return errors


def validate_salience_mapping(
    simulated: Dict[str, Any],
    reference: Dict[str, Any]
) -> List[str]:
    """Ensure salience levels match between simulation and reference."""
    errors = []
    for story_id, data in reference.get("mappings", {}).items():
        if story_id in simulated.get("mappings", {}):
            ref_level = data.get("salience_level")
            sim_level = simulated["mappings"][story_id].get("salience_level")
            if ref_level != sim_level:
                errors.append(
                    f"Salience mismatch for {story_id}: ref={ref_level}, sim={sim_level}"
                )
    return errors


def validate_metadata_consistency(
    simulated: Dict[str, Any],
    reference: Dict[str, Any]
) -> List[str]:
    """Validate that metadata counts match."""
    errors = []
    ref_meta = reference.get("metadata", {})
    sim_meta = simulated.get("metadata", {})

    ref_total = ref_meta.get("total_stories", 0)
    sim_total = sim_meta.get("total_stories", 0)
    if ref_total != sim_total:
        errors.append(
            f"Total stories mismatch: ref={ref_total}, sim={sim_total}"
        )
    return errors


def verify_fidelity_tolerance(
    simulated: Dict[str, Any],
    reference: Dict[str, Any],
    tolerance: float = TOLERANCE
) -> List[str]:
    """Check that parameter values match within tolerance."""
    errors = []
    for story_id, ref_data in reference.get("mappings", {}).items():
        if story_id not in simulated.get("mappings", {}):
            errors.append(f"Story {story_id} missing in simulation")
            continue

        sim_data = simulated["mappings"][story_id]
        ref_params = ref_data.get("blend_shape_params", {})
        sim_params = sim_data.get("blend_shape_params", {})

        for key, ref_val in ref_params.items():
            if key not in sim_params:
                errors.append(f"Parameter {key} missing for {story_id}")
                continue

            sim_val = sim_params[key]
            if abs(ref_val - sim_val) > tolerance:
                errors.append(
                    f"Parameter {key} for {story_id} differs: "
                    f"ref={ref_val}, sim={sim_val}, diff={abs(ref_val - sim_val)}"
                )
    return errors


def verify_simulation_fidelity() -> Dict[str, Any]:
    """
    Main verification logic.
    Returns a report dict with status and details.
    """
    logger = get_logger("unity_verification")
    log_operation("verify_fidelity", status="started")

    try:
        reference = load_reference_config()
        simulated = load_simulated_params()
    except FileNotFoundError as e:
        logger.error(str(e))
        return {
            "status": "fail",
            "details": [str(e)],
            "timestamp": log_operation("verify_fidelity", status="failed").timestamp
        }

    all_errors: List[str] = []

    # Run validations
    all_errors.extend(validate_blend_shape_ranges(simulated))
    all_errors.extend(validate_blend_shape_keys(simulated, reference))
    all_errors.extend(validate_salience_mapping(simulated, reference))
    all_errors.extend(validate_metadata_consistency(simulated, reference))
    all_errors.extend(verify_fidelity_tolerance(simulated, reference))

    if all_errors:
        status = "fail"
        details = all_errors
    else:
        status = "pass"
        details = ["All validations passed. Fidelity verified."]

    log_operation("verify_fidelity", status=status, errors=len(all_errors))

    return {
        "status": status,
        "details": details,
        "reference_config": REFERENCE_CONFIG_PATH,
        "simulated_params": SIMULATION_OUTPUT_PATH,
        "tolerance": TOLERANCE
    }


def save_verification_report(report: Dict[str, Any]) -> str:
    """Save the verification report to the output file."""
    output_path = get_path(OUTPUT_FIDELITY_PATH)
    with open(output_path, 'w') as f:
        yaml.dump(report, f, default_flow_style=False)
    return output_path


def log_actual_parameters(simulated: Dict[str, Any]) -> str:
    """
    Log the actual parameter sets used in the simulation run to a log file.
    This satisfies Constitution Principle VI.
    """
    log_path = get_path(LOG_PARAMS_PATH)
    with open(log_path, 'w') as f:
        f.write("# Simulation Parameters Log\n")
        f.write(f"# Generated at: {log_operation('log_params').timestamp}\n")
        f.write("# These are the actual parameters used in the simulation run.\n\n")
        f.write(json.dumps(simulated, indent=2))
    return log_path


def main() -> int:
    """Entry point for T076."""
    logger = get_logger("unity_verification_main")
    log_operation("main", status="started")

    try:
        # 1. Verify Fidelity
        report = verify_simulation_fidelity()

        # 2. Save Report
        report_path = save_verification_report(report)
        logger.info(f"Verification report written to: {report_path}")

        # 3. Load simulated params again to log them (or read from the same source)
        # We need to load them again to ensure we have the data for logging
        try:
            simulated_params = load_simulated_params()
            log_path = log_actual_parameters(simulated_params)
            logger.info(f"Simulation parameters logged to: {log_path}")
        except FileNotFoundError:
            logger.warning("Could not log parameters: file not found.")

        # 4. Update Checksums (Constitution Principle V)
        # We checksum the report and the log file
        for artifact in [report_path, get_path(LOG_PARAMS_PATH)]:
            if os.path.exists(artifact):
                checksum = calculate_checksum(artifact)
                update_state_file(artifact, checksum)
                logger.info(f"Checksum updated for {artifact}: {checksum}")

        # 5. Final Status
        if report["status"] == "pass":
            log_operation("main", status="completed", result="pass")
            return 0
        else:
            log_operation("main", status="completed", result="fail")
            # We still return 0 because the verification ran successfully,
            # even if the result is a "fail" (meaning fidelity check failed).
            # The task is to VERIFY, not to force pass.
            return 0

    except Exception as e:
        logger.exception(f"Verification failed with exception: {e}")
        log_operation("main", status="failed", error=str(e))
        return 1


if __name__ == "__main__":
    sys.exit(main())