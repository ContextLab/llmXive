def load_regression_pvalues() -> List[float]:
    """
    Load p-values from the regression results.
    Assumes T030 (regression.py) has written results to a known location.
    """
    # Look for regression results. T030 output is typically in data/results/ or similar.
    # Let's check common paths.
    possible_paths = [
        get_path("data", "results/regression_results.json"),
        get_path("data", "processed/regression_results.json"),
        get_path("state", "regression_results.json")
    ]
    
    for path in possible_paths:
        if os.path.exists(path):
            with open(path, 'r') as f:
                data = json.load(f)
                # Assume structure: {"p_values": [...]} or similar
                if "p_values" in data:
                    return data["p_values"]
                # Fallback: try to extract from a flat structure if possible
                # This is a heuristic; adjust based on actual T030 output.
                return [v for k, v in data.items() if isinstance(v, (int, float)) and 0 <= v <= 1]
    
    raise FileNotFoundError("Regression results not found. Ensure T030 is complete.")

def apply_bonferroni_correction(p_values: List[float], alpha: float = 0.05) -> Dict[str, Any]:
    """
    Apply Bonferroni correction to a list of p-values.
    
    Args:
        p_values: List of raw p-values.
        alpha: Significance level.
        
    Returns:
        Dictionary with corrected p-values and significance flags.
    """
    n_tests = len(p_values)
    if n_tests == 0:
        return {"adjusted_p_values": [], "significant": [], "alpha_threshold": alpha / n_tests if n_tests > 0 else 0}
    
    adjusted_p_values = [min(p * n_tests, 1.0) for p in p_values]
    significant = [p_adj < alpha for p_adj in adjusted_p_values]
    threshold = alpha / n_tests
    
    return {
        "adjusted_p_values": adjusted_p_values,
        "significant": significant,
        "alpha_threshold": threshold,
        "n_tests": n_tests
    }

def run_bonferroni_validation() -> Dict[str, Any]:
    """
    Run the full Bonferroni validation pipeline.
    """
    logger.info("Running Bonferroni correction...")
    try:
        p_values = load_regression_pvalues()
        result = apply_bonferroni_correction(p_values)
        
        # Save result
        output_path = get_path("data", "results/bonferroni_results.json")
        with open(output_path, 'w') as f:
            json.dump(result, f, indent=2)
        
        logger.info(f"Bonferroni results saved to {output_path}")
        return result
    except Exception as e:
        logger.error(f"Bonferroni validation failed: {str(e)}")
        return {"status": "failed", "error": str(e)}


