import logging
from pathlib import Path
from typing import List, Dict, Any, Optional
import sys
import os

# Ensure reportlab is available; if not, we fail loudly as per constraints
try:
    from reportlab.lib.pagesizes import letter
    from reportlab.lib import colors
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
    from reportlab.lib.units import inch
except ImportError:
    # This should not happen if requirements.txt is installed, but we fail loudly
    raise ImportError("reportlab is required for report generation. Please install it via requirements.txt")

from config import get_env_var, ensure_dirs
from logger import get_logger

logger = get_logger(__name__)

def load_search_results() -> Dict[str, Any]:
    """Load the categorization log generated by search.py"""
    log_path = Path("data/results/categorization_log.json")
    if not log_path.exists():
        raise FileNotFoundError(f"Categorization log not found at {log_path}. Run search.py first.")
    
    import json
    with open(log_path, "r") as f:
        return json.load(f)

def generate_negative_finding_report(data: Optional[Dict[str, Any]] = None) -> str:
    """
    Generate a PDF report for the negative finding scenario (no eligible datasets).
    Returns the path to the generated PDF.
    """
    ensure_dirs()
    
    if data is None:
        data = load_search_results()
    
    output_path = Path("data/results/negative_finding_report_v1.pdf")
    
    doc = SimpleDocTemplate(str(output_path), pagesize=letter)
    styles = getSampleStyleSheet()
    story = []
    
    # Title
    title_style = styles['Heading1']
    story.append(Paragraph("Negative Finding Report", title_style))
    story.append(Spacer(1, 0.2*inch))
    
    # Section: Search Summary
    story.append(Paragraph("1. Search Summary", styles['Heading2']))
    story.append(Paragraph(
        "This report documents the outcome of the automated dataset search for the project: "
        "\"The Influence of Simulated Social Validation on Neural Responses to Novel Information\". "
        "The search queried OpenNeuro, PhysioNet, and Zenodo for EEG datasets containing both "
        "social feedback manipulation and social anxiety measures.",
        styles['Normal']
    ))
    story.append(Spacer(1, 0.1*inch))
    
    # Section: Eligibility Criteria
    story.append(Paragraph("2. Eligibility Criteria", styles['Heading2']))
    story.append(Paragraph(
        "To be eligible, a dataset must contain: "
        "(a) EEG recordings, (b) a manipulation of social feedback (simulated or real), "
        "and (c) a validated measure of social anxiety (e.g., LSAS, SPIN).",
        styles['Normal']
    ))
    story.append(Spacer(1, 0.1*inch))
    
    # Section: Results
    story.append(Paragraph("3. Results (None Found)", styles['Heading2']))
    
    eligible = data.get("Eligible", [])
    sim_only = data.get("Sim-Only", [])
    real_only = data.get("Real-Only", [])
    none = data.get("None", [])
    
    if not eligible:
        story.append(Paragraph(
            "No single dataset meeting all eligibility criteria was found. "
            f"The search identified {len(eligible)} eligible datasets, {len(sim_only)} with simulated feedback only, "
            f"{len(real_only)} with real feedback only, and {len(none)} with no relevant keywords.",
            styles['Normal']
        ))
        
        # List some examples if available
        if sim_only:
            story.append(Paragraph("Simulated Feedback Only Examples:", styles['Heading3']))
            for ds in sim_only[:3]:
                story.append(Paragraph(f"- {ds['title']} ({ds['url']})", styles['Normal']))
                
        if real_only:
            story.append(Paragraph("Real Feedback Only Examples:", styles['Heading3']))
            for ds in real_only[:3]:
                story.append(Paragraph(f"- {ds['title']} ({ds['url']})", styles['Normal']))
    else:
        story.append(Paragraph("Unexpected: Eligible datasets were found but report was triggered.", styles['Normal']))
    
    story.append(Spacer(1, 0.1*inch))
    
    # Section: Conclusion
    story.append(Paragraph("4. Conclusion (Negative Finding)", styles['Heading2']))
    story.append(Paragraph(
        "Per the project plan, meta-analysis of separate datasets is scientifically invalid for this hypothesis. "
        "Since no single dataset containing both required components was found, the project must abort. "
        "This report serves as the formal record of the negative finding.",
        styles['Normal']
    ))
    
    # Build PDF
    doc.build(story)
    logger.info(f"Generated negative finding report at {output_path}")
    return str(output_path)

def main():
    """Entry point for generating the negative finding report"""
    try:
        data = load_search_results()
        generate_negative_finding_report(data)
        logger.info("Negative finding report generated successfully.")
    except Exception as e:
        logger.error(f"Failed to generate negative finding report: {e}")
        raise
