"""
Statistical Summary Generator (T035b)

Generates `results/statistical_summary.json` from the output of the statistical analysis.
Extracts p-values and significance flags derived from SC-001/SC-002 metrics.
No narrative text is included, only raw metrics.
"""
import json
import sys
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional

from utils.logger import get_logger, log_stage_start, log_stage_complete, log_stage_error

# Configure logging
logger = get_logger(__name__)

def load_statistical_results(input_path: Path) -> Dict[str, Any]:
    """
    Load the statistical analysis results generated by T032 (stats.py).
    Expected input: results/benchmark_stats.json (or similar path defined in runner).
    """
    if not input_path.exists():
        raise FileNotFoundError(f"Statistical results file not found: {input_path}")
    
    with open(input_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def extract_summary_data(stats_results: Dict[str, Any]) -> Dict[str, Any]:
    """
    Extract p-values and significance flags from the statistical results.
    Structure matches SC-001 (Performance) and SC-002 (Memory) requirements.
    """
    summary = {
        "metrics": {},
        "total_pairs_analyzed": 0,
        "significant_results": {
            "performance": 0,
            "memory": 0
        }
    }

    total_pairs = 0
    perf_sig_count = 0
    mem_sig_count = 0

    # The stats output is expected to be a list of pair results or a dict with a 'results' key
    results_list = stats_results.get("results", [])
    if not results_list and isinstance(stats_results, list):
        results_list = stats_results

    for pair_result in results_list:
        pair_id = pair_result.get("pair_id", "unknown")
        total_pairs += 1

        pair_summary = {}

        # Extract Performance (Time) metrics
        if "time" in pair_result:
            time_data = pair_result["time"]
            p_value_time = time_data.get("p_value")
            is_significant_time = time_data.get("is_significant", False)
            
            pair_summary["time"] = {
                "p_value": p_value_time,
                "is_significant": is_significant_time,
                "test_type": time_data.get("test_type", "unknown")
            }

            if is_significant_time:
                perf_sig_count += 1

        # Extract Memory metrics
        if "memory" in pair_result:
            mem_data = pair_result["memory"]
            p_value_mem = mem_data.get("p_value")
            is_significant_mem = mem_data.get("is_significant", False)
            
            pair_summary["memory"] = {
                "p_value": p_value_mem,
                "is_significant": is_significant_mem,
                "test_type": mem_data.get("test_type", "unknown")
            }

            if is_significant_mem:
                mem_sig_count += 1

        summary["metrics"][pair_id] = pair_summary

    summary["total_pairs_analyzed"] = total_pairs
    summary["significant_results"]["performance"] = perf_sig_count
    summary["significant_results"]["memory"] = mem_sig_count

    return summary

def save_statistical_summary(summary_data: Dict[str, Any], output_path: Path) -> None:
    """
    Save the extracted summary to the specified JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(summary_data, f, indent=2)
    logger.info(f"Statistical summary saved to {output_path}")

def run_summary_generation(input_path: Path, output_path: Path) -> Dict[str, Any]:
    """
    Main orchestration function for T035b.
    """
    log_stage_start(logger, "T035b", "Generating Statistical Summary")
    
    try:
        stats_results = load_statistical_results(input_path)
        summary_data = extract_summary_data(stats_results)
        save_statistical_summary(summary_data, output_path)
        
        log_stage_complete(logger, "T035b", f"Processed {summary_data['total_pairs_analyzed']} pairs")
        return summary_data
    
    except Exception as e:
        log_stage_error(logger, "T035b", str(e))
        raise

def main():
    """
    Entry point for the script.
    Expects input from the benchmark stats output and writes to results/statistical_summary.json.
    """
    # Default paths relative to project root
    # The stats output is typically generated by T032 into results/benchmark_stats.json
    input_file = Path("results/benchmark_stats.json")
    output_file = Path("results/statistical_summary.json")

    # Allow override via command line arguments
    if len(sys.argv) >= 2:
        input_file = Path(sys.argv[1])
    if len(sys.argv) >= 3:
        output_file = Path(sys.argv[2])

    try:
        run_summary_generation(input_file, output_file)
    except FileNotFoundError as e:
        logger.error(f"Input file missing: {e}. Ensure T032 has run successfully.")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Failed to generate summary: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()