"""
T034: Generate results/summary.csv with mean deltas, std, p-values, and significance flags.

This script loads the statistical analysis results generated by T032 (stats.py)
and formats them into a CSV file for the final research summary.

Input: results/statistical_analysis.json (output of main_statistical_summary.py or stats.py)
Output: results/summary.csv
"""
import json
import csv
import sys
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional

from utils.logger import get_logger, log_stage_start, log_stage_complete, log_stage_error

logger = get_logger(__name__)

def load_statistical_results(input_path: Path) -> List[Dict[str, Any]]:
    """Load the statistical analysis results from JSON."""
    if not input_path.exists():
        raise FileNotFoundError(f"Statistical results file not found: {input_path}")
    
    with open(input_path, 'r') as f:
        data = json.load(f)
    
    # The stats.py output structure typically contains a list of results under 'results'
    # or directly a list if the root is the list. Handle both.
    if isinstance(data, dict):
        return data.get('results', data.get('pairs', []))
    elif isinstance(data, list):
        return data
    else:
        raise ValueError(f"Unexpected data format in {input_path}: expected list or dict")

def extract_summary_data(results: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Extract the required fields for the summary CSV.
    
    Expected fields from statistical analysis:
    - pair_id or function_id
    - stratum
    - original_mean, original_std
    - simplified_mean, simplified_std
    - mean_delta (simplified - original)
    - p_value
    - significance (boolean or string)
    - test_type (t-test or wilcoxon)
    """
    summary_rows = []
    
    for res in results:
        # Safely extract values with defaults
        pair_id = res.get('pair_id', res.get('function_id', 'unknown'))
        stratum = res.get('stratum', 'unknown')
        
        orig_mean = res.get('original_mean', 0.0)
        orig_std = res.get('original_std', 0.0)
        simp_mean = res.get('simplified_mean', 0.0)
        simp_std = res.get('simplified_std', 0.0)
        
        # Calculate mean delta if not present
        mean_delta = res.get('mean_delta')
        if mean_delta is None:
            mean_delta = simp_mean - orig_mean
        
        p_value = res.get('p_value', 0.0)
        
        # Determine significance (p < 0.05)
        # Handle both boolean and string representations
        significance = res.get('significant')
        if significance is None:
            significance = p_value < 0.05
        elif isinstance(significance, str):
            significance = significance.lower() in ('true', 'yes', '1')
        
        test_type = res.get('test_type', 'unknown')
        
        summary_rows.append({
            'pair_id': pair_id,
            'stratum': stratum,
            'original_mean': orig_mean,
            'original_std': orig_std,
            'simplified_mean': simp_mean,
            'simplified_std': simp_std,
            'mean_delta': mean_delta,
            'p_value': p_value,
            'significant': significance,
            'test_type': test_type
        })
    
    return summary_rows

def save_statistical_summary(summary_data: List[Dict[str, Any]], output_path: Path) -> None:
    """Save the summary data to a CSV file."""
    if not summary_data:
        logger.warning("No summary data to write.")
        return
    
    # Define fieldnames
    fieldnames = [
        'pair_id', 'stratum', 
        'original_mean', 'original_std', 
        'simplified_mean', 'simplified_std', 
        'mean_delta', 
        'p_value', 'significant', 'test_type'
    ]
    
    with open(output_path, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(summary_data)
    
    logger.info(f"Summary CSV written to {output_path} with {len(summary_data)} rows.")

def run_summary_generation(input_path: Path, output_path: Path) -> None:
    """Orchestrate the summary generation pipeline."""
    log_stage_start("Summary Generation", input_path=input_path, output_path=output_path)
    
    try:
        results = load_statistical_results(input_path)
        summary_data = extract_summary_data(results)
        save_statistical_summary(summary_data, output_path)
        log_stage_complete("Summary Generation", output_path=output_path, rows=len(summary_data))
    except FileNotFoundError as e:
        log_stage_error("Summary Generation", str(e))
        raise
    except Exception as e:
        log_stage_error("Summary Generation", str(e))
        raise

def main():
    """Main entry point for T034."""
    # Define paths relative to project root
    project_root = Path(__file__).resolve().parent.parent
    input_file = project_root / "results" / "statistical_analysis.json"
    output_file = project_root / "results" / "summary.csv"
    
    # Ensure results directory exists
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
    
    logger.info("Starting T034: Generate summary.csv")
    run_summary_generation(input_file, output_file)
    logger.info("T034 completed successfully.")

if __name__ == "__main__":
    main()