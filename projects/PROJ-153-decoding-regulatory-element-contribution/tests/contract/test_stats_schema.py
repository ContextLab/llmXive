"""
Contract test for the statistical report schema (User Story 2).

This test validates that the statistical summary report generated by the pipeline
(specifically `results/Statistical_summary.pdf` or its underlying data sources)
conforms to the expected schema defined in the project specifications.

It checks for the presence of required sections, table headers, and data types
as mandated by FR-006, FR-005, and US2.

Expected artifacts to validate:
- results/Statistical_summary.pdf (if generated)
- results/permutation_pvalue.csv (source data for empirical p-values)
- results/CRE_ranked_<stress>.md (source for GLS coefficients)

Note: Since PDF parsing is brittle, this test primarily validates the
underlying CSV/TSV data sources that feed into the report generation
(T024, T022, T023), ensuring the schema is correct before rendering.
"""
import os
import csv
import re
import pytest
from pathlib import Path
from typing import List, Dict, Any

# Project root relative to tests/contract/
PROJECT_ROOT = Path(__file__).parent.parent.parent
RESULTS_DIR = PROJECT_ROOT / "results"

# Expected file names based on task descriptions
PERMUTATION_OUTPUT = RESULTS_DIR / "permutation_pvalue.csv"
GLS_OUTPUT_PATTERN = re.compile(r"CRE_ranked_(.+)\.md")

# Schema definitions
REQUIRED_PERMUTATION_COLUMNS = [
    "stress_condition",
    "cre_id",
    "observed_beta1",
    "empirical_p_value",
    "num_permutations",
    "block_size"
]

REQUIRED_GLs_COLUMNS = [
    "cre_id",
    "stress_condition",
    "tf_name",
    "log2fc",
    "beta1",
    "se_beta1",
    "p_value",
    "q_value",
    "significant"
]

def find_statistical_summary_pdf() -> Path:
    """Locate the generated Statistical_summary.pdf if it exists."""
    if RESULTS_DIR.exists():
        for f in RESULTS_DIR.iterdir():
            if f.name == "Statistical_summary.pdf":
                return f
    return None

def find_ranked_reports() -> List[Path]:
    """Find all CRE ranked markdown reports."""
    reports = []
    if RESULTS_DIR.exists():
        for f in RESULTS_DIR.iterdir():
            if GLS_OUTPUT_PATTERN.match(f.name):
                reports.append(f)
    return reports

@pytest.fixture
def permutation_data() -> Dict[str, Any]:
    """Load permutation test results if available."""
    if not PERMUTATION_OUTPUT.exists():
        pytest.skip(f"Permutation output not found: {PERMUTATION_OUTPUT}. "
                    "T022 (permutation test) may not have run yet.")
    
    with open(PERMUTATION_OUTPUT, "r") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
    
    if not rows:
        pytest.fail("Permutation output file is empty.")
    
    return {"rows": rows, "columns": reader.fieldnames}

@pytest.fixture
def gls_reports_data() -> List[Dict[str, Any]]:
    """Load data from all ranked CRE reports."""
    reports = find_ranked_reports()
    if not reports:
        pytest.skip("No CRE ranked reports found. T018 may not have run yet.")
    
    all_data = []
    for report_path in reports:
        with open(report_path, "r") as f:
            content = f.read()
            # Basic check for markdown table presence
            if "|" not in content:
                pytest.fail(f"Report {report_path} does not contain a markdown table.")
            
            # Simple parsing of the last table in the file
            # (Assumes the main result table is the last one or the only one)
            lines = content.split("\n")
            table_lines = []
            in_table = False
            for line in lines:
                if line.strip().startswith("|"):
                    in_table = True
                    table_lines.append(line)
                elif in_table and not line.strip():
                    in_table = False
            
            # Parse the table
            if table_lines:
                # Find header and separator
                header_line = None
                sep_line = None
                data_lines = []
                for i, line in enumerate(table_lines):
                    if "|" in line:
                        if header_line is None:
                            header_line = line
                        elif sep_line is None and not any(c.isdigit() for c in line.replace("|", "").strip()):
                            # Heuristic: separator usually has ---
                            if "---" in line:
                                sep_line = line
                            else:
                                # If no explicit separator, assume next line is data
                                pass
                        else:
                            data_lines.append(line)
                
                # If no explicit separator found, treat second line as separator if it looks like one
                if sep_line is None and len(table_lines) > 1:
                    second = table_lines[1]
                    if "---" in second:
                        sep_line = second
                    else:
                        # Fallback: assume header is first, rest are data
                        header_line = table_lines[0]
                        data_lines = table_lines[2:]
                
                if header_line:
                    headers = [h.strip() for h in header_line.split("|") if h.strip()]
                    # Clean headers
                    headers = [re.sub(r'\[.*?\]', '', h) for h in headers] # Remove footnotes like [1]
                    
                    for d_line in data_lines:
                        if not d_line.strip():
                            continue
                        row_vals = [v.strip() for v in d_line.split("|") if v.strip()]
                        if len(row_vals) == len(headers):
                            row_dict = dict(zip(headers, row_vals))
                            row_dict['_source_file'] = report_path.name
                            all_data.append(row_dict)
    
    if not all_data:
        pytest.fail("Could not parse any data rows from CRE ranked reports.")
    
    return all_data

class TestPermutationSchema:
    """Tests for the permutation test output schema (T022)."""

    def test_permutation_columns_present(self, permutation_data):
        """Verify all required columns exist in permutation output."""
        cols = permutation_data["columns"]
        missing = [c for c in REQUIRED_PERMUTATION_COLUMNS if c not in cols]
        assert not missing, f"Missing required columns in permutation output: {missing}"

    def test_permutation_data_types(self, permutation_data):
        """Verify numeric columns contain valid numbers."""
        numeric_cols = ["observed_beta1", "empirical_p_value", "num_permutations", "block_size"]
        for row in permutation_data["rows"]:
            for col in numeric_cols:
                try:
                    float(row[col])
                except ValueError:
                    pytest.fail(f"Column '{col}' contains non-numeric value: {row[col]}")

    def test_empirical_p_value_range(self, permutation_data):
        """Verify empirical p-values are between 0 and 1."""
        for row in permutation_data["rows"]:
            p_val = float(row["empirical_p_value"])
            assert 0.0 <= p_val <= 1.0, f"Empirical p-value out of range: {p_val}"

class TestGLSReportSchema:
    """Tests for the GLS ranked report schema (T018, T023)."""

    def test_gls_reports_exist(self, gls_reports_data):
        """Verify at least one ranked report exists."""
        assert len(gls_reports_data) > 0, "No GLS ranked reports found."

    def test_gls_columns_present(self, gls_reports_data):
        """Verify required columns exist in at least one report."""
        # Check the first report for required columns
        first_report = gls_reports_data[0]
        # Map expected columns to potential variations in the markdown table
        # e.g., "q-value" vs "q_value"
        required_map = {
            "cre_id": ["cre_id", "cre", "id"],
            "stress_condition": ["stress_condition", "stress", "condition"],
            "beta1": ["beta1", "beta_1", "coefficient"],
            "p_value": ["p_value", "p-value", "p"],
            "q_value": ["q_value", "q-value", "q", "adj_p"],
            "significant": ["significant", "sig", "is_significant"]
        }
        
        headers = list(first_report.keys())
        missing_groups = []
        
        for req_key, variations in required_map.items():
            found = False
            for var in variations:
                if var in headers:
                    found = True
                    break
            if not found:
                missing_groups.append(req_key)
        
        assert not missing_groups, f"Missing required column groups in GLS report: {missing_groups}"

    def test_significance_logic(self, gls_reports_data):
        """Verify that 'significant' flag aligns with q-value <= 0.05."""
        for row in gls_reports_data:
            q_val = None
            sig_flag = None
            
            # Find q-value column
            for key in row:
                if key.lower() in ["q_value", "q-value", "q"]:
                    try:
                        q_val = float(row[key])
                    except ValueError:
                        pass
                elif key.lower() in ["significant", "sig", "is_significant"]:
                    sig_flag = row[key].lower() in ["true", "yes", "1", "significant"]
            
            if q_val is not None and sig_flag is not None:
                expected_sig = q_val <= 0.05
                assert sig_flag == expected_sig, \
                    f"Mismatch in row: q={q_val}, sig={sig_flag}, expected={expected_sig}"

class TestReportIntegration:
    """Tests ensuring the Statistical Summary PDF can be generated from available data."""

    def test_statistical_summary_pdf_exists(self):
        """Check if the final statistical summary PDF exists."""
        pdf_path = find_statistical_summary_pdf()
        if pdf_path is None:
            # If it doesn't exist, we check if the prerequisite data exists
            # to ensure the test failure is due to T024/T028 not running, not a schema error.
            if PERMUTATION_OUTPUT.exists() and find_ranked_reports():
                pytest.skip("Statistical_summary.pdf not found, but prerequisite data exists. "
                          "T028 (Report Generation) may not have run yet.")
            else:
                pytest.fail("Statistical_summary.pdf missing and prerequisite data incomplete.")
        
        assert pdf_path.exists(), "Statistical_summary.pdf not found."

    def test_pdf_size_reasonable(self):
        """Ensure the PDF is not empty."""
        pdf_path = find_statistical_summary_pdf()
        if pdf_path:
            size = pdf_path.stat().st_size
            assert size > 1024, f"PDF file is too small ({size} bytes), likely empty or corrupted."