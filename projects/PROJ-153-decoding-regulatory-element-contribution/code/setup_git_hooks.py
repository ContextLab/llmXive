import os
import subprocess
import sys
from pathlib import Path

def run_command(cmd: list, cwd: Path = None) -> tuple:
    """Run a shell command and return (returncode, stdout, stderr)."""
    try:
        result = subprocess.run(
            cmd,
            cwd=cwd,
            capture_output=True,
            text=True,
            check=False
        )
        return result.returncode, result.stdout.strip(), result.stderr.strip()
    except Exception as e:
        return -1, "", str(e)

def check_git_lfs_installed() -> bool:
    """Check if git-lfs is installed on the system."""
    code, out, err = run_command(["git", "lfs", "version"])
    if code == 0:
        print(f"Git LFS found: {out}")
        return True
    else:
        print("Git LFS is not installed.")
        print("Please install it from: https://git-lfs.github.com/")
        return False

def install_git_lfs() -> bool:
    """Attempt to initialize git-lfs in the current repository."""
    code, out, err = run_command(["git", "lfs", "install"])
    if code == 0:
        print("Git LFS initialized successfully.")
        return True
    else:
        print(f"Failed to initialize Git LFS: {err}")
        return False

def setup_lfs_tracking() -> bool:
    """Create .gitattributes file to track large data files."""
    project_root = Path(__file__).parent.parent
    gitattributes_path = project_root / ".gitattributes"
    
    # Define patterns for files to track with LFS
    # Raw data (FASTQ, BAM, bigWig), intermediate large files, and results
    patterns = [
        "data/raw/**/*.fastq filter=lfs diff=lfs merge=lfs -text",
        "data/raw/**/*.fq filter=lfs diff=lfs merge=lfs -text",
        "data/raw/**/*.bam filter=lfs diff=lfs merge=lfs -text",
        "data/raw/**/*.bai filter=lfs diff=lfs merge=lfs -text",
        "data/processed/**/*.bed filter=lfs diff=lfs merge=lfs -text",
        "data/processed/**/*.tsv filter=lfs diff=lfs merge=lfs -text",
        "data/processed/**/*.csv filter=lfs diff=lfs merge=lfs -text",
        "results/**/*.md filter=lfs diff=lfs merge=lfs -text",
        "results/**/*.pdf filter=lfs diff=lfs merge=lfs -text",
        "results/**/*.csv filter=lfs diff=lfs merge=lfs -text",
        "tracks/**/*.bw filter=lfs diff=lfs merge=lfs -text",
        "tracks/**/*.bigWig filter=lfs diff=lfs merge=lfs -text",
    ]

    content = "# Git LFS tracking for large data files\n"
    content += "# Auto-generated by setup_git_hooks.py\n\n"
    content += "\n".join(patterns)
    content += "\n"

    try:
        with open(gitattributes_path, 'w') as f:
            f.write(content)
        print(f"Created .gitattributes with LFS tracking rules.")
        return True
    except Exception as e:
        print(f"Failed to create .gitattributes: {e}")
        return False

def create_pre_push_hook() -> bool:
    """Create a pre-push hook to warn if large files are being pushed without LFS."""
    project_root = Path(__file__).parent.parent
    hooks_dir = project_root / ".git" / "hooks"
    pre_push_hook = hooks_dir / "pre-push"

    hooks_dir.mkdir(parents=True, exist_ok=True)

    hook_script = '''#!/bin/bash
    # Pre-push hook to ensure large files are tracked by Git LFS

    # Check if git lfs is available
    if ! command -v git-lfs &> /dev/null; then
        echo "Error: git-lfs is not installed. Cannot push large files."
        exit 1
    fi

    # Check for files that should be tracked by LFS but aren't
    # This checks the staging area for common large file extensions
    LFS_PATTERNS="*.fastq *.fq *.bam *.bai *.bed *.tsv *.csv *.bw *.bigWig *.pdf"
    
    for pattern in $LFS_PATTERNS; do
        # Find staged files matching the pattern
        STAGED_FILES=$(git ls-files --cached --stage | grep "$pattern" | awk '{print $4}')
        for file in $STAGED_FILES; do
            # Check if the file is already tracked by LFS
            if ! git lfs ls-files | grep -q "$file"; then
                echo "Warning: Large file '$file' is staged but not tracked by Git LFS."
                echo "Please run 'git lfs track \"$pattern\"' and commit the .gitattributes file."
                # Uncomment the next line to block the push
                # exit 1
            fi
        done
    done

    echo "Pre-push hook completed."
    exit 0
    '''

    try:
        with open(pre_push_hook, 'w') as f:
            f.write(hook_script)
        os.chmod(pre_push_hook, 0o755)
        print(f"Created pre-push hook at {pre_push_hook}")
        return True
    except Exception as e:
        print(f"Failed to create pre-push hook: {e}")
        return False

def main():
    """Main entry point for setting up Git LFS hooks."""
    print("Setting up Git LFS for large file tracking...")
    
    # Check if we are in a git repository
    code, out, err = run_command(["git", "rev-parse", "--is-inside-work-tree"])
    if code != 0:
        print("Error: Not inside a git repository. Please initialize git first.")
        sys.exit(1)

    # Check for Git LFS
    if not check_git_lfs_installed():
        print("Cannot proceed without Git LFS. Please install it and try again.")
        sys.exit(1)

    # Initialize Git LFS
    if not install_git_lfs():
        print("Failed to initialize Git LFS.")
        sys.exit(1)

    # Setup .gitattributes
    if not setup_lfs_tracking():
        print("Failed to setup .gitattributes.")
        sys.exit(1)

    # Create pre-push hook
    if not create_pre_push_hook():
        print("Failed to create pre-push hook.")
        sys.exit(1)

    print("\nGit LFS setup complete.")
    print("Next steps:")
    print("  1. Review and commit the new .gitattributes file: git add .gitattributes")
    print("  2. Track existing large files with: git lfs migrate import --include=\"*.fastq,*.bam,*.bw,*.pdf\"")
    print("  3. Push the changes to enable LFS tracking on the remote.")

if __name__ == "__main__":
    main()
