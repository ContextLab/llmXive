log "Validating manifest and extracting download targets..."

python3 << 'PYTHON_SCRIPT'
import os
import sys
import yaml
import json
import hashlib
import subprocess
import time
from pathlib import Path

MANIFEST_PATH = os.environ.get('MANIFEST_FILE')
DATA_DIR = os.environ.get('DATA_DIR')
CHECKSUM_PATH = os.environ.get('CHECKSUM_PATH')
LOG_FILE = os.environ.get('LOG_FILE')

def log(msg):
    timestamp = time.strftime('%Y-%m-%d %H:%M:%S')
    line = f"[{timestamp}] {msg}"
    print(line)
    with open(LOG_FILE, 'a') as f:
  f.write(line + '\n')

def verify_manifest_and_get_targets(manifest_path):
    """
    Validates the manifest and returns a list of download targets.
    Returns None if validation fails.
    """
    try:
  with open(manifest_path, 'r') as f:
      manifest = yaml.safe_load(f)
  
  if not manifest or 'datasets' not in manifest:
      log("ERROR: Invalid manifest structure. Missing 'datasets' key.")
      return None
  
  targets = []
  for dataset in manifest['datasets']:
      # Validate required fields
      if 'accession' not in dataset:
          log(f"ERROR: Dataset missing 'accession': {dataset}")
          return None
      
      if 'type' not in dataset:
          log(f"ERROR: Dataset missing 'type': {dataset}")
          return None
      
      # Determine source and URL based on type
      source = dataset.get('source', 'geo') # Default to GEO
      accession = dataset['accession']
      
      # Simple validation logic (T003 requirement: abort if not verifiable)
      # In a real scenario, this would hit the NCBI API. 
      # Here we assume the manifest was generated by T003 with verified accessions.
      # We construct the SRA/Geo download URL.
      
      if source == 'sra':
          # SRA download URL pattern
          url = f"https://sra-download.ncbi.nlm.nih.gov/traces/sra/{accession[:3]}/{accession}/"
          # For this script, we assume the manifest contains the direct download URL or we construct it
          # If the manifest has a 'url' field, use it. Otherwise, construct.
          if 'url' in dataset:
              download_url = dataset['url']
          else:
              # Fallback: construct SRA URL (simplified for SRA Toolkit's prefetch or wget)
              # We expect the manifest to have the direct FASTQ URL or accession for prefetch
              download_url = f"https://ftp.ncbi.nlm.nih.gov/sra/sra-instant/reads/ByRun/sra/{accession[:3]}/{accession}/{accession}"
      elif source == 'geo':
          # GEO usually requires parsing SRA accession from GEO
          # Assuming manifest already resolved the direct FASTQ URL or SRA accession
          if 'url' in dataset:
              download_url = dataset['url']
          else:
              log(f"ERROR: GEO dataset {accession} missing direct download URL in manifest.")
              return None
      else:
          log(f"ERROR: Unknown source type: {source}")
          return None

      # Determine output filename
      filename = f"{accession}.fastq.gz"
      if 'filename' in dataset:
          filename = dataset['filename']
      
      # Determine MD5 if available in manifest
      expected_md5 = dataset.get('md5', None)
      
      targets.append({
          'accession': accession,
          'source': source,
          'url': download_url,
          'output_file': os.path.join(DATA_DIR, filename),
          'expected_md5': expected_md5
      })
  
  return targets

    except Exception as e:
  log(f"ERROR: Failed to parse manifest: {e}")
  return None

def download_file(url, output_path, expected_md5=None):
    """
    Downloads a file using wget with retry logic.
    Verifies MD5 if expected_md5 is provided.
    """
    temp_path = output_path + ".tmp"
    
    log(f"Downloading {url} to {output_path}...")
    
    # Use wget for robust downloading
    # -c: continue partial downloads
    # -O: output file
    # --tries: retry count
    cmd = [
  "wget", "-c", "-O", temp_path, "--tries=5", "--waitretry=5",
  "--timeout=30", url
    ]
    
    try:
  subprocess.run(cmd, check=True, capture_output=True, text=True)
    except subprocess.CalledProcessError as e:
  log(f"ERROR: Download failed for {url}: {e.stderr}")
  if os.path.exists(temp_path):
      os.remove(temp_path)
  return False
    
    # Move temp to final
    os.rename(temp_path, output_path)
    log(f"Downloaded: {output_path}")
    
    # Verify MD5
    if expected_md5:
  log(f"Verifying MD5 for {output_path}...")
  actual_md5 = hashlib.md5(open(output_path, 'rb').read()).hexdigest()
  if actual_md5.lower() != expected_md5.lower():
      log(f"ERROR: MD5 mismatch for {output_path}")
      log(f"  Expected: {expected_md5}")
      log(f"  Actual:   {actual_md5}")
      os.remove(output_path)
      return False
  log(f"MD5 verified: {actual_md5}")
    
    return True

def main():
    targets = verify_manifest_and_get_targets(MANIFEST_PATH)
    
    if not targets:
  log("FATAL: Manifest validation failed. Aborting.")
  sys.exit(1)
    
    if not targets:
  log("No download targets found in manifest.")
  sys.exit(0)
    
    log(f"Found {len(targets)} datasets to download.")
    
    success_count = 0
    fail_count = 0
    
    for target in targets:
  if os.path.exists(target['output_file']):
      log(f"Skipping {target['accession']}: File already exists.")
      # Still verify MD5 if exists? Let's assume if it exists, it's fine unless we want to re-verify.
      # For safety, verify if expected_md5 exists.
      if target['expected_md5']:
          actual = hashlib.md5(open(target['output_file'], 'rb').read()).hexdigest()
          if actual.lower() != target['expected_md5'].lower():
              log(f"WARNING: Existing file {target['output_file']} has bad MD5. Re-downloading.")
              os.remove(target['output_file'])
              if download_file(target['url'], target['output_file'], target['expected_md5']):
                  success_count += 1
              else:
                  fail_count += 1
          else:
              success_count += 1
      else:
          success_count += 1
      continue

  if download_file(target['url'], target['output_file'], target['expected_md5']):
      success_count += 1
  else:
      fail_count += 1
    
    log(f"Download complete. Success: {success_count}, Failed: {fail_count}")
    
    if fail_count > 0:
  log("FATAL: One or more downloads failed.")
  sys.exit(2)
    
    sys.exit(0)

if __name__ == '__main__':
    main()
