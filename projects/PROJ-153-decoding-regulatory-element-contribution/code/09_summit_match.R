#!/usr/bin/env Rscript

# 09_summit_match.R
# Task: T032 - Compute Spearman correlation between log2FC and bigWig signal
# and calculate summit match percentage for top-ranked CREs.

library(data.table)
library(rtracklayer)
library(dplyr)
library(readr)

# Configuration
args <- commandArgs(trailingOnly = TRUE)
if (length(args) < 3) {
  stop("Usage: Rscript 09_summit_match.R <ranked_report_path> <bigwig_path> <output_path>")
}

ranked_report_path <- args[1]
bigwig_path <- args[2]
output_path <- args[3]

# Ensure output directory exists
output_dir <- dirname(output_path)
if (!dir.exists(output_dir)) {
  dir.create(output_dir, recursive = TRUE)
}

message("Loading ranked CRE report: ", ranked_report_path)
# Load the ranked report (Markdown or TSV format, expecting tabular data)
# The file is expected to be generated by T018 (10_generate_reports.R)
# It should contain columns: cre_id, gene_id, log2FC, q_value, summit_pos, etc.
# We assume it's a tab-separated or space-separated table within the Markdown
# For robustness, we try to read the tabular part.

# Read the file content
lines <- readLines(ranked_report_path)

# Find the start of the table (line starting with |)
table_start <- which(grepl("^\\|", lines))[1]
if (is.na(table_start)) {
  stop("Could not find table in ranked report. Expected Markdown table format.")
}

# Extract table lines
table_lines <- lines[table_start:length(lines)]

# Remove header separator line (|---|---|...)
table_lines <- table_lines[!grepl("^\\|\\s*-+\\s*\\|", table_lines)]

# Parse the table
# Clean up lines: remove leading/trailing pipes and spaces
clean_lines <- gsub("^\\|\\s*|\\s*\\|$", "", table_lines)
clean_lines <- gsub("\\s*\\|\\s*", "\t", clean_lines)

# Read as TSV
df <- read.table(text = clean_lines, sep = "\t", header = TRUE, stringsAsFactors = FALSE, quote = "")

if (nrow(df) == 0) {
  stop("No data rows found in ranked report.")
}

message("Loaded ", nrow(df), " CREs from ranked report.")

# Filter for significant CREs (q <= 0.05)
# Check if q_value column exists, otherwise try q or fdr
q_col <- names(df)[grepl("q|fdr|q_value", tolower(names(df)))]
if (length(q_col) == 0) {
  stop("Could not find q-value column in ranked report.")
}
q_col <- q_col[1] # Take the first match

significant_df <- df[df[[q_col]] <= 0.05, ]
message("Filtered to ", nrow(significant_df), " significant CREs (q <= 0.05).")

if (nrow(significant_df) == 0) {
  warning("No significant CREs found. Outputting stats with NA values.")
  result <- data.frame(
    correlation_rho = NA,
    match_percentage = NA,
    exit_code = 0
  )
  write.table(result, output_path, sep = "\t", row.names = FALSE, quote = FALSE)
  quit(save = "no", status = 0)
}

# Extract coordinates and summit positions
# Expected columns: cre_id, chromosome, start, end, summit_pos (or similar)
# We need to map summit position to a genomic coordinate relative to the CRE
# Assuming summit_pos is an offset from start, or an absolute position.
# Let's assume summit_pos is an absolute genomic coordinate based on typical BED-like outputs.

# If summit_pos is relative, we need to adjust. 
# For this implementation, we assume the ranked report contains:
# cre_id, chr, start, end, summit_pos (absolute), log2FC

# Identify columns
chr_col <- names(df)[grepl("chr|chrom", tolower(names(df)))][1]
start_col <- names(df)[grepl("start", tolower(names(df)))][1]
end_col <- names(df)[grepl("end", tolower(names(df)))][1]
summit_col <- names(df)[grepl("summit", tolower(names(df)))][1]
log2fc_col <- names(df)[grepl("log2|log2fc", tolower(names(df)))][1]

if (is.null(chr_col) || is.null(start_col) || is.null(end_col) || is.null(summit_col) || is.null(log2fc_col)) {
  stop("Missing required columns in ranked report. Expected: chromosome, start, end, summit_pos, log2FC.")
}

significant_df <- significant_df %>%
  rename(chr = !!chr_col, start = !!start_col, end = !!end_col, summit = !!summit_col, log2FC = !!log2fc_col)

# Load BigWig signal at summit positions
message("Loading BigWig signal from: ", bigwig_path)

if (!file.exists(bigwig_path)) {
  stop("BigWig file not found: ", bigwig_path)
}

# Create GRanges for summit positions
# Summit is a single point, so width = 1
summit_gr <- GRanges(
  seqnames = significant_df$chr,
  ranges = IRanges(start = significant_df$summit, width = 1),
  log2FC = significant_df$log2FC,
  cre_id = significant_df$cre_id
)

# Import BigWig values
bw_signal <- import(bigwig_path, which = summit_gr)

# Match signals back to the dataframe
# import() returns a GRanges object with 'score' or 'signal'
signal_vals <- mcols(bw_signal)$score
if (is.null(signal_vals)) signal_vals <- mcols(bw_signal)$signal

if (is.null(signal_vals) || length(signal_vals) != length(summit_gr)) {
  warning("Could not extract signal values for all summits. Some may be missing.")
  signal_vals <- rep(NA, length(summit_gr))
}

significant_df$bigWig_signal <- signal_vals

# Remove rows with missing signal or log2FC
valid_df <- significant_df[!is.na(significant_df$bigWig_signal) & !is.na(significant_df$log2FC), ]

if (nrow(valid_df) < 2) {
  warning("Not enough valid data points for correlation. Outputting NA.")
  result <- data.frame(
    correlation_rho = NA,
    match_percentage = NA,
    exit_code = 0
  )
  write.table(result, output_path, sep = "\t", row.names = FALSE, quote = FALSE)
  quit(save = "no", status = 0)
}

# Calculate Spearman correlation
rho <- cor(valid_df$log2FC, valid_df$bigWig_signal, method = "spearman", use = "complete.obs")
message("Spearman correlation (rho): ", round(rho, 4))

# Calculate summit match percentage within ±5 bp
# We need a "true" summit position to compare against. 
# In the context of this task, the "summit" in the report IS the called summit.
# The task asks for "percentage of summit matches within ±5 bp".
# This implies comparing the called summit (from peak calling, stored in report) 
# against a reference summit (e.g., from a motif or a high-confidence peak).
# However, the task description says: "percentage of summit matches within ±5 bp for the top-ranked CREs".
# If we assume the "summit" in the report is the one we are validating against a "true" biological summit,
# we don't have a "true" summit in the input.
# Re-reading T032: "compute Spearman ρ between log₂FC and bigWig_signal ... and explicitly calculate the percentage of summit matches within ±5 bp".
# This phrasing is slightly ambiguous without a ground truth. 
# Interpretation: The "summit" in the ranked report is the peak summit. The "match" likely refers to 
# consistency between the peak summit and the max signal in the BigWig track at that location? 
# Or perhaps it implies the BigWig signal peak location vs the reported summit.
# Given the inputs (Report + BigWig), the most logical calculation is:
# 1. Extract signal profile around the reported summit (e.g., ±20bp).
# 2. Find the max signal position in that window in the BigWig.
# 3. Check if max signal position is within ±5bp of the reported summit.

# Let's implement this:
# For each CRE, extract a window around the reported summit from the BigWig, find the max signal pos, compare.

match_count <- 0
total_checked <- 0

# We need to scan the BigWig in windows to find the local max
# This is computationally intensive if done one by one, but necessary for accuracy.
# We'll use rtracklayer to query specific ranges.

window_size <- 20 # ±20bp window

for (i in 1:nrow(valid_df)) {
  row <- valid_df[i, ]
  chr <- as.character(row$chr)
  summit <- row$summit
  
  # Define window
  win_start <- max(1, summit - window_size)
  win_end <- summit + window_size
  
  # Query BigWig for this window
  win_gr <- GRanges(seqnames = chr, ranges = IRanges(start = win_start, end = win_end))
  win_signal <- import(bigwig_path, which = win_gr)
  
  if (length(win_signal) > 0) {
    # Find position of max signal
    max_idx <- which.max(mcols(win_signal)$score)
    max_pos <- start(win_signal)[max_idx]
    
    # Check if max_pos is within ±5bp of reported summit
    if (abs(max_pos - summit) <= 5) {
      match_count <- match_count + 1
    }
    total_checked <- total_checked + 1
  }
}

match_percentage <- if (total_checked > 0) (match_count / total_checked) * 100 else 0
message("Summit match percentage (±5bp): ", round(match_percentage, 2), "% (", match_count, "/", total_checked, ")")

# Log warning if match_percentage < 90%
if (match_percentage < 90) {
  warning("Low summit match percentage (", round(match_percentage, 2), "%). This is a data quality observation.")
}

# Prepare output
result <- data.frame(
  correlation_rho = rho,
  match_percentage = match_percentage,
  exit_code = 0
)

# Write output
write.table(result, output_path, sep = "\t", row.names = FALSE, quote = FALSE)
message("Summit match statistics written to: ", output_path)

# Exit with code 0 as per SC-005
quit(save = "no", status = 0)