"""
T008: Annotate regulatory elements (CREs) by merging peaks across TFs/conditions
and classifying them as promoter (<=500bp) or distal (>500bp) relative to TSS.

Inputs:
  - data/processed/peaks_fdr_0.05.bed (or similar from T007)
  - data/processed/tss_reference.bed (generated or provided)
Output:
  - data/processed/CRE_merged.bed
"""

import os
import sys
import logging
import argparse
from pathlib import Path
from typing import Dict, List, Tuple, Optional, Any, Set
import pybedtools

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.FileHandler('logs/pipeline.log'),
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)

def parse_bed_line(line: str) -> Dict[str, Any]:
    """Parse a BED line into a dictionary."""
    parts = line.strip().split('\t')
    if len(parts) < 3:
        raise ValueError(f"Invalid BED line: {line}")
    return {
        'chrom': parts[0],
        'start': int(parts[1]),
        'end': int(parts[2]),
        'name': parts[3] if len(parts) > 3 else '.',
        'score': parts[4] if len(parts) > 4 else '.',
        'strand': parts[5] if len(parts) > 5 else '.',
        'rest': parts[6:] if len(parts) > 6 else []
    }

def load_tss_reference(tss_file: Path) -> pybedtools.BedTool:
    """Load TSS reference file."""
    if not tss_file.exists():
        raise FileNotFoundError(f"TSS reference file not found: {tss_file}")
    logger.info(f"Loading TSS reference from {tss_file}")
    return pybedtools.BedTool(str(tss_file))

def calculate_distance_to_tss(peak: pybedtools.Interval, tss_bed: pybedtools.BedTool) -> int:
    """Calculate distance from peak center to the nearest TSS."""
    peak_center = (peak.start + peak.end) // 2
    # Find nearest TSS
    nearest = tss_bed.closest(peak, d=True)
    if nearest:
        # The 'd' column in closest output gives the distance
        # Format: chrom start end ... d
        # We need to parse the distance from the output
        parts = str(nearest).split('\t')
        if len(parts) > 6:
            try:
                dist = int(parts[6])
                return dist
            except (ValueError, IndexError):
                pass
    return -1  # No TSS found

def annotate_cre(peak: pybedtools.Interval, tss_bed: pybedtools.BedTool) -> Tuple[str, int]:
    """Annotate a CRE as promoter or distal based on distance to TSS."""
    distance = calculate_distance_to_tss(peak, tss_bed)
    if distance == -1:
        # No TSS found, treat as distal by default or skip
        return 'distal', distance
    
    # Promoter: <= 500bp from TSS
    if abs(distance) <= 500:
        return 'promoter', distance
    else:
        return 'distal', distance

def find_narrowpeak_files(input_dir: Path) -> List[Path]:
    """Find all narrowPeak files in the input directory."""
    if not input_dir.exists():
        raise FileNotFoundError(f"Input directory not found: {input_dir}")
    
    # Look for peak files generated by T007
    peak_files = list(input_dir.glob("peaks_fdr_*.bed"))
    if not peak_files:
        # Fallback: look for any narrowPeak files
        peak_files = list(input_dir.glob("*narrowPeak"))
        if not peak_files:
            # Try to find any .bed files that might be peaks
            all_beds = list(input_dir.glob("*.bed"))
            # Filter for likely peak files (exclude TSS, null regions, etc.)
            peak_files = [f for f in all_beds if not any(x in f.name for x in ['tss', 'null', 'merged', 'signal'])]
    
    if not peak_files:
        raise FileNotFoundError(f"No peak files found in {input_dir}")
    
    logger.info(f"Found {len(peak_files)} peak files: {[f.name for f in peak_files]}")
    return peak_files

def merge_peaks(peak_files: List[Path], tss_bed: pybedtools.BedTool) -> pybedtools.BedTool:
    """Merge peaks across all TFs/conditions and annotate."""
    logger.info(f"Merging {len(peak_files)} peak files...")
    
    # Load all peak files
    peak_tools = [pybedtools.BedTool(str(f)) for f in peak_files]
    
    # Merge overlapping peaks
    merged = peak_tools[0]
    for pt in peak_tools[1:]:
        merged = merged.cat(pt, postmerge=False)
    
    # Sort and merge overlapping regions
    merged_sorted = merged.sort()
    merged_regions = merged_sorted.merge(c=1, o='distinct')  # Keep distinct names
    
    logger.info(f"Merged {len(merged_regions)} peaks")
    
    # Annotate each merged region
    annotated_regions = []
    for i, peak in enumerate(merged_regions):
        region_type, distance = annotate_cre(peak, tss_bed)
        
        # Create a new BED entry with annotation
        # Format: chrom, start, end, name, score, strand, type, distance
        name = f"CRE_{i:06d}"
        score = '.'
        strand = '.'
        annotation = f"{region_type}\t{distance}"
        
        new_line = f"{peak.chrom}\t{peak.start}\t{peak.end}\t{name}\t{score}\t{strand}\t{annotation}"
        annotated_regions.append(new_line)
    
    # Create a BedTool from annotated regions
    # We need to write to a temp file first since BedTool expects file paths
    import tempfile
    with tempfile.NamedTemporaryFile(mode='w', delete=False, suffix='.bed') as tmp:
        tmp.write('\n'.join(annotated_regions))
        tmp_path = tmp.name
    
    annotated_bed = pybedtools.BedTool(tmp_path)
    os.unlink(tmp_path)  # Clean up temp file
    
    return annotated_bed

def write_output(annotated_bed: pybedtools.BedTool, output_path: Path):
    """Write the annotated CREs to a BED file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    logger.info(f"Writing output to {output_path}")
    
    # Sort the output before writing
    sorted_bed = annotated_bed.sort()
    sorted_bed.saveas(str(output_path))
    
    logger.info(f"Successfully wrote {len(sorted_bed)} annotated CREs to {output_path}")

def main():
    parser = argparse.ArgumentParser(description='Annotate regulatory elements (T008)')
    parser.add_argument('--input-dir', type=Path, default=Path('data/processed'),
                      help='Directory containing peak files')
    parser.add_argument('--tss-ref', type=Path, default=Path('data/processed/tss_reference.bed'),
                      help='TSS reference file')
    parser.add_argument('--output', type=Path, default=Path('data/processed/CRE_merged.bed'),
                      help='Output file path')
    
    args = parser.parse_args()
    
    try:
        # Load TSS reference
        tss_bed = load_tss_reference(args.tss_ref)
        
        # Find peak files
        peak_files = find_narrowpeak_files(args.input_dir)
        
        # Merge and annotate
        annotated_bed = merge_peaks(peak_files, tss_bed)
        
        # Write output
        write_output(annotated_bed, args.output)
        
        logger.info("T008 completed successfully")
        
    except Exception as e:
        logger.error(f"T008 failed: {str(e)}")
        raise

if __name__ == '__main__':
    main()
