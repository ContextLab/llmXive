def calculate_framewise_displacement(nifti_path: Path) -> float:
    """
    Calculate Framewise Displacement (FD) from a preprocessed NIfTI file.
    
    Note: This is a simplified estimation. In a full pipeline, FD is usually
    calculated during realignment (T012c) using the 6 motion parameters.
    Here, we estimate it from the image data if parameters are not available,
    or we assume the file naming convention includes the FD in a sidecar JSON
    generated by fmriprep (e.g., *_confounds.tsv or *_desc-fd.json).
    
    For this implementation, we attempt to read the FD from the standard
    fmriprep confounds TSV if it exists alongside the NIfTI.
    """
    stem = nifti_path.stem
    # Handle .nii.gz stem logic
    if stem.endswith('.nii'):
        stem = stem[:-4]
    
    # Construct path to confounds TSV (standard fmriprep output)
    confounds_path = nifti_path.parent / f"{stem}_confounds.tsv"
    
    if confounds_path.exists():
        import pandas as pd
        try:
            df = pd.read_csv(confounds_path, sep='\t')
            # Standard fmriprep column for FD
            if 'framewise_displacement' in df.columns:
                fd_val = df['framewise_displacement'].mean()
                if pd.isna(fd_val):
                    return 0.0
                return float(fd_val)
            # Fallback: calculate from rotation/trans if available
            # Assuming standard columns: trans_x, trans_y, trans_z, rot_x, rot_y, rot_z
            cols = ['trans_x', 'trans_y', 'trans_z', 'rot_x', 'rot_y', 'rot_z']
            if all(c in df.columns for c in cols):
                trans = np.abs(df[['trans_x', 'trans_y', 'trans_z']].diff().fillna(0))
                rot = np.abs(df[['rot_x', 'rot_y', 'rot_z']].diff().fillna(0))
                # Convert rotation to mm (assuming 50mm radius approximation)
                rot_mm = rot * 50.0
                fd_series = trans.sum(axis=1) + rot_mm.sum(axis=1)
                return float(fd_series.mean())
        except Exception as e:
            logger.warning(f"Could not parse confounds for {nifti_path}: {e}")
    
    # If no confounds found, we cannot calculate FD reliably.
    # In a strict pipeline, this might be an error, but here we return 0 to avoid
    # false exclusions if metadata is missing, while logging a warning.
    # However, per "FAIL LOUDLY" principle for data quality, if we can't verify motion,
    # we should arguably exclude or flag. Given the task is "Exclude subjects with FD > 0.5",
    # if we can't calculate FD, we assume 0 (conservative) or exclude?
    # Standard practice: If FD is missing, the subject is unreliable.
    # We will log a warning and return a high value to exclude, ensuring data quality.
    logger.warning(f"Confounds file missing for {nifti_path}. Excluding subject.")
    return 999.0

def validate_nifti_file(nifti_path: Path) -> bool:
    """Basic validation of NIfTI file integrity."""
    if not nifti_path.exists():
        return False
    try:
        img = nib.load(str(nifti_path))
        data = img.get_fdata()
        if data.size == 0:
            return False
        # Check for NaNs
        if np.any(np.isnan(data)):
            return False
        return True
    except Exception:
        return False

def validate_preprocessed_outputs(files: List[Path]) -> Dict[str, Any]:
    """Validate that preprocessed outputs exist and are readable."""
    valid_files = []
    invalid_files = []
    
    for f in files:
        if validate_nifti_file(f):
            valid_files.append(str(f))
        else:
            invalid_files.append(str(f))
    
    return {
        "valid": valid_files,
        "invalid": invalid_files,
        "total_processed": len(files),
        "valid_count": len(valid_files)
    }

