def exclude_high_motion_subjects(run_log_path: Path) -> Dict[str, Any]:
    """
    T012e Implementation: Exclude subjects with FD > 0.5 mm.
    Updates the run_log.json with excluded subject IDs.
    """
    log_step("Starting motion exclusion analysis (T012e)")
    
    # 1. Get input files (preprocessed NIfTIs)
    input_files = get_input_files()
    if not input_files:
        log_error("No preprocessed NIfTI files found for motion exclusion.")
        return {"excluded": [], "included": [], "status": "no_data"}
    
    # 2. Calculate FD for each subject
    subject_data = []
    for f in input_files:
        fd = calculate_framewise_displacement(f)
        # Extract subject ID from filename (e.g., sub-01_space-MNI_desc-preproc_bold.nii.gz)
        stem = f.stem
        sub_id = None
        if stem.startswith("sub-"):
            parts = stem.split("_")
            if len(parts) >= 1:
                sub_id = parts[0] # e.g., sub-01
        else:
            sub_id = stem # Fallback
        
        subject_data.append({
            "file": str(f),
            "subject_id": sub_id,
            "fd": fd
        })
    
    # 3. Filter based on threshold
    included = []
    excluded = []
    
    for s in subject_data:
        if s["fd"] > FD_THRESHOLD:
            excluded.append(s)
        else:
            included.append(s)
    
    log_step(f"Motion Exclusion Results: {len(excluded)} excluded, {len(included)} included")
    for ex in excluded:
        logger.warning(f"Excluding subject {ex['subject_id']} (FD={ex['fd']:.4f} > {FD_THRESHOLD})")
    
    # 4. Update run_log.json
    # Load existing log if present, otherwise create new
    log_data = {"motion_exclusion": {}}
    if run_log_path.exists():
        try:
            with open(run_log_path, 'r') as f:
                log_data = json.load(f)
        except json.JSONDecodeError:
            log_data = {"motion_exclusion": {}}
    
    log_data["motion_exclusion"] = {
        "threshold_mm": FD_THRESHOLD,
        "excluded_subjects": [s["subject_id"] for s in excluded],
        "excluded_details": excluded,
        "included_subjects": [s["subject_id"] for s in included],
        "included_details": included,
        "summary": {
            "total_subjects": len(input_files),
            "excluded_count": len(excluded),
            "included_count": len(included)
        }
    }
    
    # Write updated log
    with open(run_log_path, 'w') as f:
        json.dump(log_data, f, indent=2)
    
    return log_data["motion_exclusion"]

