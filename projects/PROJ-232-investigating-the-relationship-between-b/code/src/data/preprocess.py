# Constants
DEFAULT_FD_THRESHOLD = 0.5  # mm
RUN_LOG_PATH = Path("data/preprocessing/run_log.json")

def ensure_directories() -> None:
    """Ensure required output directories exist."""
    RUN_LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    Path("data/preprocessing").mkdir(parents=True, exist_ok=True)

def get_input_files(data_dir: Path) -> List[Path]:
    """
    Retrieve list of preprocessed NIfTI files expected from T012c/T012d.
    Assumes structure: data/preprocessing/sub-<id>/func/sub-<id>_task-rest_space-MNI_desc-preproc_bold.nii.gz
    """
    preproc_dir = data_dir / "preprocessing"
    if not preproc_dir.exists():
        return []
    
    nifti_files = []
    for sub_dir in preproc_dir.iterdir():
        if sub_dir.is_dir() and sub_dir.name.startswith("sub-"):
            func_dir = sub_dir / "func"
            if func_dir.exists():
                for nifti in func_dir.glob("*.nii.gz"):
                    nifti_files.append(nifti)
    return sorted(nifti_files)

def calculate_framewise_displacement(nifti_path: Path) -> float:
    """
    Calculate Framewise Displacement (FD) for a given NIfTI file.
    
    This implementation assumes the file has already been preprocessed (motion corrected).
    We estimate FD by analyzing the affine transformation matrices if available,
    or by calculating signal intensity changes if registration parameters are embedded.
    
    However, standard fMRIPrep outputs include a 'confounds.tsv' file with FD.
    We will look for that first. If not found, we fall back to a simple heuristic
    based on file size or dummy calculation if strictly necessary, but ideally
    we rely on the confounds file generated by the preprocessing step (T012c).
    
    Since T012c is the 'real' execution, we expect confounds.tsv to exist alongside the NIfTI.
    """
    parent_dir = nifti_path.parent
    confounds_file = parent_dir / "confounds.tsv"
    
    if confounds_file.exists():
        try:
            import pandas as pd
            df = pd.read_csv(confounds_file, sep='\t')
            if 'framewise_displacement' in df.columns:
                fd_values = df['framewise_displacement'].dropna()
                if len(fd_values) > 0:
                    # Return mean FD as the subject-level metric for exclusion
                    return float(fd_values.mean())
                else:
                    logger.warning(f"No FD values found in {confounds_file}")
                    return 0.0
            else:
                logger.warning(f"'framewise_displacement' column not found in {confounds_file}")
                # Fallback: try to calculate from rotation/translation if columns exist
                # Standard fMRIPrep columns: trans_x, trans_y, trans_z, rot_x, rot_y, rot_z
                cols = ['trans_x', 'trans_y', 'trans_z', 'rot_x', 'rot_y', 'rot_z']
                if all(c in df.columns for c in cols):
                    # FD = |dx| + |dy| + |dz| + |drot_x| + |drot_y| + |drot_z| (approx)
                    # We need to calculate differences between volumes
                    diffs = df[cols].diff().abs()
                    fd_series = diffs.sum(axis=1)
                    return float(fd_series.mean())
                return 0.0
        except Exception as e:
            logger.error(f"Error reading confounds for {nifti_path}: {e}")
            return 0.0
    
    # Fallback if confounds missing (should not happen if T012c ran correctly)
    logger.warning(f"Confounds file missing for {nifti_path}. Cannot calculate FD. Excluding subject.")
    return 999.0  # Return high value to trigger exclusion

def validate_nifti_file(nifti_path: Path) -> bool:
    """Basic validation that the NIfTI file exists and is not empty."""
    return nifti_path.exists() and nifti_path.stat().st_size > 0

def validate_preprocessed_outputs(data_dir: Path) -> Dict[str, Any]:
    """
    Validate that preprocessed outputs from T012c exist and are valid.
    Returns a status dict.
    """
    ensure_directories()
    input_files = get_input_files(data_dir)
    valid_count = 0
    invalid_files = []
    
    for f in input_files:
        if validate_nifti_file(f):
            valid_count += 1
        else:
            invalid_files.append(str(f))
    
    return {
        "total_files": len(input_files),
        "valid_files": valid_count,
        "invalid_files": invalid_files,
        "status": "pass" if len(invalid_files) == 0 else "fail"
    }

