def exclude_high_motion_subjects(
    data_dir: Path, 
    threshold: float = DEFAULT_FD_THRESHOLD,
    run_log_path: Optional[Path] = None
) -> Dict[str, Any]:
    """
    Exclude subjects with mean FD > threshold.
    Updates the run_log.json with excluded subject IDs.
    
    Args:
        data_dir: Base data directory.
        threshold: FD threshold (default 0.5 mm).
        run_log_path: Path to the run log JSON.
    
    Returns:
        Dict containing 'included_subjects', 'excluded_subjects', and 'fd_metrics'.
    """
    if run_log_path is None:
        run_log_path = RUN_LOG_PATH
    
    ensure_directories()
    input_files = get_input_files(data_dir)
    
    if not input_files:
        logger.warning("No preprocessed NIfTI files found. Cannot calculate FD.")
        return {
            "included_subjects": [],
            "excluded_subjects": [],
            "fd_metrics": {},
            "status": "no_data"
        }
    
    included = []
    excluded = []
    fd_metrics = {}
    
    for nifti_path in input_files:
        # Extract subject ID from path: .../sub-<id>/...
        sub_id = nifti_path.parent.parent.name  # e.g., "sub-01"
        
        fd = calculate_framewise_displacement(nifti_path)
        fd_metrics[sub_id] = fd
        
        if fd > threshold:
            excluded.append(sub_id)
            logger.info(f"Excluding {sub_id} (FD={fd:.4f} > {threshold})")
        else:
            included.append(sub_id)
            logger.info(f"Including {sub_id} (FD={fd:.4f})")
    
    # Load existing log or create new
    log_data = {"excluded_subjects": [], "included_subjects": [], "fd_metrics": {}}
    if run_log_path.exists():
        try:
            with open(run_log_path, 'r') as f:
                log_data = json.load(f)
        except json.JSONDecodeError:
            logger.warning("Existing run log is invalid. Overwriting.")
    
    # Update log data with current results
    # We append to the lists to keep history, or replace if this is a fresh run.
    # Given the task description "Update ... with excluded subject IDs", we assume
    # we are writing the current state of exclusion based on the current data.
    log_data["excluded_subjects"] = list(set(log_data.get("excluded_subjects", []) + excluded))
    log_data["included_subjects"] = list(set(log_data.get("included_subjects", []) + included))
    log_data["fd_metrics"] = fd_metrics
    log_data["last_run"] = str(Path(__file__).parent) # Placeholder for timestamp
    log_data["status"] = "complete"
    log_data["threshold"] = threshold
    
    # Write updated log
    with open(run_log_path, 'w') as f:
        json.dump(log_data, f, indent=2)
    
    logger.info(f"Updated run log at {run_log_path}")
    logger.info(f"Excluded {len(excluded)} subjects, Included {len(included)} subjects.")
    
    return {
        "included_subjects": included,
        "excluded_subjects": excluded,
        "fd_metrics": fd_metrics,
        "status": "complete"
    }

def save_run_log(log_data: Dict[str, Any], path: Path = RUN_LOG_PATH) -> None:
    """Save run log to JSON."""
    ensure_directories()
    with open(path, 'w') as f:
        json.dump(log_data, f, indent=2)

def main() -> int:
    """
    Main entry point for T012e.
    Executes motion exclusion logic.
    """
    data_dir = Path("data")
    threshold = 0.5
    
    logger.info(f"Starting motion exclusion (Threshold={threshold}mm)...")
    
    try:
        result = exclude_high_motion_subjects(data_dir, threshold)
        
        if result["status"] == "complete":
            logger.info(f"Success. Excluded: {result['excluded_subjects']}")
            return 0
        else:
            logger.error(f"Failed to process all subjects. Status: {result['status']}")
            return 1
    except Exception as e:
        logger.error(f"Motion exclusion failed: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
