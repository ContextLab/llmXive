# Current stable OpenNeuro API base (v1)
OPENNEURO_API_ROOT = "https://openneuro.org/api/v1/datasets"


def _fetch_dataset_file_index(dataset: str) -> List[Dict]:
    """
    Retrieve a list of file descriptors for a given OpenNeuro dataset using the v1 API.
    Each descriptor will contain at least:
        - 'path' : relative path inside the dataset
        - 'filename' : same as 'path' (kept for backward compatibility)
    """
    url = f"{OPENNEURO_API_ROOT}/{dataset}/files"
    logger.info(f"Fetching OpenNeuro file index from {url}")
    try:
        resp = requests.get(url, timeout=30)
        resp.raise_for_status()
        file_index = resp.json()
        if not isinstance(file_index, list):
            raise RuntimeError("Unexpected response format from OpenNeuro file index.")
        # Normalise keys: ensure each entry has 'filename' and 'download_url' for later use
        normalized = []
        for entry in file_index:
            path = entry.get("path") or entry.get("filename") or entry.get("name")
            if not path:
                continue
            normalized.append({
                "filename": path,
                "download_url": f"https://openneuro.org/crn/datasets/{dataset}/download/{path}?download=1"
            })
        return normalized
    except Exception as e:
        raise RuntimeError(f"Failed to retrieve file index for dataset {dataset}: {e}")


def _select_behavioral_file(file_index: List[Dict]) -> Tuple[str, str]:
    """
    Locate the behavioral (BMRQ) file within the dataset file index.
    Preference is given to files whose name contains 'bmrq' or 'beh' and ends
    with .tsv or .csv.
    Returns a tuple (filename, download_url).
    """
    for entry in file_index:
        filename = entry.get("filename")
        if not filename:
            continue
        lower = filename.lower()
        if ("bmrq" in lower or "beh" in lower) and (lower.endswith(".tsv") or lower.endswith(".csv")):
            return filename, entry["download_url"]
    raise FileNotFoundError("No behavioral BMRQ file found in the dataset.")


def _select_subject_func_files(file_index: List[Dict], subject_id: str) -> List[Tuple[str, str]]:
    """
    Return a list of (filename, download_url) for all functional NIfTI files
    belonging to the given subject.
    """
    prefix = f"sub-{subject_id}/func/"
    selected = []
    for entry in file_index:
        filename = entry.get("filename")
        if not filename:
            continue
        if filename.startswith(prefix) and filename.lower().endswith(".nii.gz"):
            selected.append((filename, entry["download_url"]))
    return selected


# ----------------------------------------------------------------------
# Public download functions
# ----------------------------------------------------------------------
def download_behavioral_data(data_dir: Path, dataset: str = "ds000233") -> Path:
    """
    Download the behavioral (BMRQ) file from OpenNeuro.
    Returns the local path to the downloaded CSV/TSV file.
    """
    data_dir.mkdir(parents=True, exist_ok=True)
    file_index = _fetch_dataset_file_index(dataset)
    filename, url = _select_behavioral_file(file_index)
    local_path = data_dir / Path(filename).name

    logger.info(f"Downloading behavioral file {filename} → {local_path}")
    try:
        with requests.get(url, stream=True, timeout=60) as r:
            r.raise_for_status()
            with open(local_path, "wb") as f:
                for chunk in r.iter_content(chunk_size=8192):
                    if chunk:
                        f.write(chunk)
    except Exception as e:
        raise RuntimeError(f"Failed to download behavioral file {filename}: {e}")

    return local_path


def download_subject_data(subject_id: str, dataset: str, raw_dir: Path) -> bool:
    """
    Download raw rs-fMRI NIfTI files for a given subject from OpenNeuro.
    Streams only the files belonging to the requested subject, computes SHA‑256 checksums,
    and writes a `checksums.sha256` file alongside the downloaded data.
    Returns True on success, False otherwise.
    """
    subj_dir = raw_dir / subject_id
    subj_dir.mkdir(parents=True, exist_ok=True)

    try:
        file_index = _fetch_dataset_file_index(dataset)
        subject_files = _select_subject_func_files(file_index, subject_id)

        if not subject_files:
            logger.warning(f"No functional NIfTI files found for subject {subject_id}")
            return False

        checksums: List[str] = []
        for remote_path, url in subject_files:
            local_file_path = subj_dir / Path(remote_path).name
            logger.info(f"Downloading {remote_path} → {local_file_path}")
            try:
                with requests.get(url, stream=True, timeout=120) as r:
                    r.raise_for_status()
                    with open(local_file_path, "wb") as f:
                        for chunk in r.iter_content(chunk_size=8192):
                            if chunk:
                                f.write(chunk)
            except Exception as e:
                logger.error(f"Failed to download {remote_path} for {subject_id}: {e}")
                return False

            sha = calculate_file_checksum(local_file_path)
            checksums.append(f"{sha}  {local_file_path.name}")

        checksum_file = subj_dir / "checksums.sha256"
        checksum_file.write_text("\n".join(checksums))
        return True
    except Exception as e:
        logger.error(f"Failed to download data for subject {subject_id}: {e}")
        return False


# ----------------------------------------------------------------------
# CLI entry point
# ----------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(description="Download and verify OpenNeuro ds000233 data")
    parser.add_argument("--subjects", type=int, help="Number of subjects to download")
    parser.add_argument("--simulate-missing-bmrq", action="store_true", help="Simulate missing BMRQ columns")
    parser.add_argument("--check-only", action="store_true", help="Only verify BMRQ availability")
    args = parser.parse_args()

    raw_data_dir = paths.data("raw")
    dataset_id = "ds000233"

    try:
        # --------------------------------------------------------------
        # Step 1: Obtain (or verify) the behavioral table
        # --------------------------------------------------------------
        beh_path = download_behavioral_data(raw_data_dir, dataset_id)

        # --------------------------------------------------------------
        # Step 2: Verify required BMRQ columns
        # --------------------------------------------------------------
        cols_to_check = REQUIRED_BMRQ_COLUMNS
        if args.simulate_missing_bmrq:
            cols_to_check = {"NON_EXISTENT_COLUMN"}

        all_present, missing = verify_bmrq_column(beh_path, required_columns=cols_to_check)
        if not all_present:
            generate_data_gap_report(missing, paths.data("data_gap_report.md"))
            sys.exit(1)

        if args.check_only:
            logger.info("BMRQ availability check completed successfully.")
            return

        # --------------------------------------------------------------
        # Step 3: Subject‑specific downloads (if requested)
        # --------------------------------------------------------------
        if args.subjects:
            import pandas as pd
            df = pd.read_csv(beh_path)
            # Determine which column holds the subject identifiers
            subj_col = "subject_id" if "subject_id" in df.columns else df.columns[0]
            subject_list = df[subj_col].head(args.subjects).astype(str).tolist()

            logger.info(f"Downloading raw data for {len(subject_list)} subjects...")
            success_count = 0
            for sid in subject_list:
                clean_sid = sid.replace("sub-", "")
                if download_subject_data(clean_sid, dataset_id, raw_data_dir):
                    success_count += 1

            logger.info(f"Successfully downloaded {success_count}/{len(subject_list)} subjects.")
            if success_count == 0 and len(subject_list) > 0:
                raise RuntimeError("Total failure: No subjects were successfully downloaded.")
        else:
            logger.info("No subject count specified. Only behavioral data downloaded.")

    except Exception as e:
        logger.error(f"Pipeline failed: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()