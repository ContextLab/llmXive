def stratified_sample_by_length(data: List[Dict], n: int, seed: int) -> List[Dict]:
    """
    Select the first N examples stratified by length (question length).
    This ensures the reference set covers a variety of problem complexities.
    """
    logger.info(f"Selecting {n} stratified examples by length (seed={seed})")
    np.random.seed(seed)
    
    # Calculate length (number of tokens or characters) for stratification
    # Using character length of 'question' as a proxy for complexity
    for i, item in enumerate(data):
        item['_length'] = len(item.get('question', ''))
    
    # Sort by length to facilitate stratified sampling
    sorted_data = sorted(data, key=lambda x: x['_length'])
    
    # Simple stratified sampling: divide into buckets and sample proportionally
    # Or simpler: take the first N from a sorted list if we want "first 50" strictly by some metric
    # The task says "first 50 examples (seed=42, stratified by length)"
    # Interpretation: Sort by length, then pick every Kth, or use a simple stratified split.
    # Given the small N=50, we will bin by length quartiles and sample from each.
    
    lengths = [x['_length'] for x in sorted_data]
    q1, q2, q3 = np.percentile(lengths, [25, 50, 75])
    
    buckets = {
        'low': [],
        'med_low': [],
        'med_high': [],
        'high': []
    }
    
    for item in sorted_data:
        l = item['_length']
        if l <= q1:
            buckets['low'].append(item)
        elif l <= q2:
            buckets['med_low'].append(item)
        elif l <= q3:
            buckets['med_high'].append(item)
        else:
            buckets['high'].append(item)
    
    # Sample proportionally
    sample_size = n
    bucket_sizes = {k: len(v) for k, v in buckets.items()}
    total_items = sum(bucket_sizes.values())
    
    sampled = []
    for k, v in buckets.items():
        if total_items == 0:
            continue
        # Calculate number to take from this bucket
        count = int((bucket_sizes[k] / total_items) * sample_size)
        # Ensure we don't take more than available
        count = min(count, len(v))
        if count > 0:
            # Shuffle within bucket to ensure randomness if needed, then take first
            np.random.shuffle(v)
            sampled.extend(v[:count])
    
    # If we didn't get enough (due to rounding), fill from the largest bucket
    if len(sampled) < sample_size:
        remaining = sample_size - len(sampled)
        # Find the bucket with the most remaining items
        for k in sorted(bucket_sizes, key=lambda x: bucket_sizes[x], reverse=True):
            if len(buckets[k]) > len(sampled) - sum(len(buckets[other]) for other in sampled if other in buckets[k]):
                # This logic is getting complex, simpler fallback:
                pass
        
        # Fallback: just take from the first bucket that has space
        for k in buckets:
            needed = sample_size - len(sampled)
            if needed <= 0:
                break
            available = [x for x in buckets[k] if x not in sampled]
            sampled.extend(available[:needed])
    
    # Clean up temporary length field
    for item in sampled:
        del item['_length']
        
    logger.info(f"Selected {len(sampled)} stratified examples.")
    return sampled

def extract_ngram_features(text: str, max_n: int = 3) -> Dict[str, float]:
    """
    Extract n-gram statistics from the text.
    Returns a fixed-size feature vector based on top n-grams.
    """
    tokens = text.lower().split()
    if not tokens:
        return {f"ngram_{i}": 0.0 for i in range(max_n * 10)} # Default zeros
    
    features = {}
    for n in range(1, max_n + 1):
        ngrams = [" ".join(tokens[i:i+n]) for i in range(len(tokens) - n + 1)]
        counts = Counter(ngrams)
        # Take top 10 most frequent n-grams of this order
        top_ngrams = [word for word, count in counts.most_common(10)]
        
        for i, ngram in enumerate(top_ngrams):
            # Hash the ngram to a fixed index to keep vector size manageable
            # Or just use the count directly if we map specific ngrams
            # For simplicity in a fixed vector, we'll use a hash-based approach for the vector
            # But since we need a consistent vector, let's just return counts of top ngrams
            # and let the model handle the rest, or pad with zeros.
            # Better: Use a fixed vocabulary of common ngrams? No, too complex.
            # Strategy: Return a dict, later we will convert to a fixed vector based on a global vocabulary or just use the top ones.
            # For this implementation, we will return the top 10 n-gram counts as features.
            features[f"{n}gram_{i}"] = counts[ngram]
    
    # Pad to ensure consistent size if we were using a fixed schema
    # Here we return a dict, and the final vectorization will handle it.
    return features

def extract_pos_features(text: str) -> List[str]:
    """
    Extract POS tags from the text.
    """
    nlp = load_nlp_model()
    doc = nlp(text)
    return [token.pos_ for token in doc]

def compute_semantic_similarity(
    query_text: str, 
    reference_texts: List[str], 
    model: SentenceTransformer
) -> float:
    """
    Compute the semantic similarity between the query and the most similar reference.
    Returns the maximum cosine similarity found.
    """
    if not reference_texts:
        return 0.0
    
    try:
        # Encode query and references
        query_embedding = model.encode([query_text], convert_to_numpy=True)
        ref_embeddings = model.encode(reference_texts, convert_to_numpy=True)
        
        # Compute cosine similarity
        # Normalize
        query_norm = query_embedding / (np.linalg.norm(query_embedding) + 1e-9)
        ref_norms = ref_embeddings / (np.linalg.norm(ref_embeddings, axis=1, keepdims=True) + 1e-9)
        
        similarities = np.dot(ref_norms, query_norm.T).flatten()
        return float(np.max(similarities))
    except Exception as e:
        logger.warning(f"Failed to compute semantic similarity: {e}")
        return 0.0

def extract_token_features(
    example: Dict[str, Any], 
    reference_texts: List[str], 
    nlp: spacy.language.Language, 
    model: SentenceTransformer
) -> List[Dict[str, Any]]:
    """
    Extract features for each token in the example's question.
    Returns a list of dicts: [token_id, feature_vector, ...]
    """
    question = example.get('question', '')
    # Tokenize using SpaCy
    doc = nlp(question)
    tokens = [token.text for token in doc]
    pos_tags = [token.pos_ for token in doc]
    
    # Pre-compute n-grams for the whole text
    # We'll use a simple bag-of-n-grams approach for the whole question as context
    # or per token? The task says "n-gram stats". Let's assume global stats for the question
    # plus local context.
    # To keep it simple and consistent:
    # 1. Global n-gram counts for the question
    # 2. POS tag of the token
    # 3. Semantic similarity of the token's context (or the whole question) to reference set.
    # Since semantic similarity is expensive, we compute it for the whole question once.
    
    global_ngram_features = extract_ngram_features(question)
    semantic_sim = compute_semantic_similarity(question, reference_texts, model)
    
    # Create feature vector for each token
    # We need a fixed size vector. Let's define a schema:
    # [ngram_count_top1, ngram_count_top2, ..., pos_one_hot, semantic_sim]
    # Since ngrams are dynamic, we will use a fixed set of top N ngrams from the entire dataset?
    # No, that's too heavy.
    # Alternative: Use the count of the token itself and its neighbors?
    # Let's simplify:
    # Features:
    # - Token length
    # - Is digit
    # - POS index (mapped to a small set)
    # - Semantic similarity (scalar)
    # - N-gram density (number of n-grams containing this token)
    
    pos_map = {
        'NOUN': 0, 'VERB': 1, 'ADJ': 2, 'ADV': 3, 'PRON': 4, 'DET': 5,
        'ADP': 6, 'NUM': 7, 'PUNCT': 8, 'SYM': 9, 'X': 10
    }
    
    features_list = []
    for i, token in enumerate(doc):
        # 1. Token length
        len_feat = len(token.text)
        # 2. Is digit
        is_digit = 1.0 if token.pos_ == 'NUM' or token.text.isdigit() else 0.0
        # 3. POS
        pos_idx = pos_map.get(token.pos_, 10)
        # 4. Semantic similarity (global for the question)
        sim_feat = semantic_sim
        
        # 5. N-gram density: how many n-grams (1-3) contain this token?
        # This is a proxy for "importance" or "frequency" in the context
        ngram_count = 0
        tokens_list = [t.text.lower() for t in doc]
        for n in range(1, 4):
            for j in range(len(tokens_list) - n + 1):
                if token.text.lower() in tokens_list[j:j+n]:
                    ngram_count += 1
        ngram_feat = float(ngram_count)
        
        # Construct feature vector (fixed size: 1 + 1 + 1 + 1 + 1 = 5)
        # [len, is_digit, pos_idx (normalized), sim, ngram_count]
        # Normalize pos_idx to [0, 1]
        pos_norm = pos_idx / 10.0
        # Normalize ngram_count? Max is roughly 3 * len(tokens). Let's just use raw or log.
        # For simplicity, raw float.
        
        feature_vector = [
            float(len_feat),
            float(is_digit),
            float(pos_norm),
            float(sim_feat),
            float(ngram_feat)
        ]
        
        features_list.append({
            "token_id": i,
            "token_text": token.text,
            "feature_vector": feature_vector,
            "example_id": example.get('id', 'unknown')
        })
    
    return features_list

def save_features(all_features: List[Dict[str, Any]], output_path: Path):
    """
    Save features to a Parquet file.
    """
    logger.info(f"Saving features to {output_path}")
    
    # Convert list of dicts to DataFrame
    # Flatten the feature vector into separate columns or keep as list?
    # Parquet supports lists, but for ML it's often better to flatten.
    # Let's keep the vector as a list column for flexibility, or expand.
    # The schema T005 expects [token_id, feature_vector].
    # We will store feature_vector as a list.
    
    df = pd.DataFrame(all_features)
    df.to_parquet(output_path, index=False)
    logger.info(f"Saved {len(df)} feature records.")

def validate_features(df: pd.DataFrame) -> bool:
    """
    Validate the output features against the schema constraints.
    - Check columns exist
    - Check feature_vector is a list of numbers
    - Check no NaNs in critical fields
    """
    required_cols = ['token_id', 'feature_vector', 'example_id']
    if not all(col in df.columns for col in required_cols):
        logger.error(f"Missing required columns. Expected: {required_cols}, Found: {df.columns.tolist()}")
        return False
    
    # Check for empty feature vectors
    if df['feature_vector'].isnull().any():
        logger.error("Found null feature vectors.")
        return False
    
    # Check for NaNs inside vectors
    for idx, row in df.iterrows():
        vec = row['feature_vector']
        if not isinstance(vec, list):
            logger.error(f"Feature vector at index {idx} is not a list.")
            return False
        if any(np.isnan(x) if isinstance(x, float) else False for x in vec):
            logger.error(f"Found NaN in feature vector at index {idx}.")
            return False
    
    logger.info("Feature validation passed.")
    return True

