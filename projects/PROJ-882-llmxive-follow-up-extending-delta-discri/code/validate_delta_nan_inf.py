"""
validate_delta_nan_inf.py

This script validates that the JSON file generated by the DelTA oracle
(`data/processed/delta_coefficients.json`) does not contain any NaN or Inf
values. It is intended to be run as a standalone validation step in the
pipeline.

The script performs the following actions:
  1. Loads the JSON file.
  2. Recursively scans all numeric values.
  3. Raises a ValueError if any NaN or infinite values are found.
  4. Logs a success message otherwise.

Usage:
    python -m code.validate_delta_nan_inf
"""
import json
import logging
import math
from pathlib import Path
from typing import Any

# Configure basic logging
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s",
)
logger = logging.getLogger(__name__)

# Path to the JSON file produced by the oracle step
DEFAULT_JSON_PATH = Path("data/processed/delta_coefficients.json")


def load_json_file(json_path: Path = DEFAULT_JSON_PATH) -> Any:
    """
    Load a JSON file from ``json_path`` and return the parsed Python object.

    Parameters
    ----------
    json_path: Path
        Path to the JSON file.

    Returns
    -------
    Any
        Parsed JSON content.

    Raises
    ------
    FileNotFoundError
        If the file does not exist.
    json.JSONDecodeError
        If the file is not valid JSON.
    """
    if not json_path.is_file():
        raise FileNotFoundError(f"JSON file not found: {json_path}")

    with json_path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    logger.debug("Loaded JSON file %s (size: %d bytes)", json_path, json_path.stat().st_size)
    return data


def _contains_invalid_number(obj: Any) -> bool:
    """
    Recursively check ``obj`` for NaN or infinite floating‑point numbers.

    Returns ``True`` if an invalid number is found, ``False`` otherwise.
    """
    if isinstance(obj, float):
        if math.isnan(obj) or math.isinf(obj):
            return True
        return False
    elif isinstance(obj, (list, tuple)):
        return any(_contains_invalid_number(item) for item in obj)
    elif isinstance(obj, dict):
        return any(_contains_invalid_number(value) for value in obj.values())
    # For all other types (int, str, bool, None) there is nothing to check.
    return False


def validate_no_nan_inf(data: Any) -> None:
    """
    Validate that *data* does not contain NaN or Inf values.

    Parameters
    ----------
    data: Any
        The JSON‑decoded data structure.

    Raises
    ------
    ValueError
        If any NaN or infinite value is present.
    """
    if _contains_invalid_number(data):
        raise ValueError("NaN or Inf value detected in delta_coefficients.json")
    logger.info("No NaN or Inf values found in delta_coefficients.json")


def main() -> None:
    """
    Entry point for the script. Loads the JSON file, validates it,
    and exits with an appropriate status code.
    """
    try:
        data = load_json_file()
        validate_no_nan_inf(data)
    except Exception as e:
        logger.error("Validation failed: %s", e)
        raise  # Re‑raise so the process exits with a non‑zero status


if __name__ == "__main__":
    main()
