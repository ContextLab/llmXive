"""
T042: Generate sensitivity analysis report in data/processed/sensitivity_report.md

This script reads the sensitivity analysis results generated by T039-T041
and formats them into a comprehensive markdown report.
"""
import json
import os
import sys
from pathlib import Path
from typing import Dict, Any, Optional
from datetime import datetime, timezone

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent))

from utils.logging import get_logger

logger = get_logger(__name__)

def load_sensitivity_results(results_path: Path) -> Optional[Dict[str, Any]]:
    """Load sensitivity analysis results from JSON file."""
    if not results_path.exists():
        logger.error(f"Sensitivity results file not found: {results_path}")
        return None
    
    try:
        with open(results_path, 'r', encoding='utf-8') as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse sensitivity results JSON: {e}")
        return None
    except Exception as e:
        logger.error(f"Unexpected error reading sensitivity results: {e}")
        return None

def format_correlation_section(results: Dict[str, Any]) -> str:
    """Format the correlation analysis section of the report."""
    lines = [
        "## Correlation Analysis",
        "",
        f"**Pearson Correlation Coefficient (r):** {results.get('pearson_correlation', 'N/A'):.4f}",
        "",
    ]
    
    r_value = results.get('pearson_correlation')
    if r_value is not None:
        if r_value >= 0.5:
            lines.append("**Status:** ✅ **Proxy Validated** (r ≥ 0.5)")
            lines.append("")
            lines.append("The State Coverage Vector scalar count shows a strong positive correlation")
            lines.append("with task success rates, validating it as a meaningful proxy for task difficulty.")
        elif r_value >= 0.3:
            lines.append("**Status:** ⚠️ **Moderate Proxy** (0.3 ≤ r < 0.5)")
            lines.append("")
            lines.append("The correlation is moderate. The State Coverage Vector may be a useful proxy")
            lines.append("but additional variables or refinements might improve predictive power.")
        else:
            lines.append("**Status:** ❌ **Invalid Proxy** (r < 0.3)")
            lines.append("")
            lines.append("The correlation is too weak to validate the State Coverage Vector as a proxy")
            lines.append("for task difficulty. **Recommendation:** Expand the variable set with additional")
            lines.append("semantic state proxies or re-evaluate the state transition detection logic.")
    
    lines.append("")
    return "\n".join(lines)

def format_statistics_section(results: Dict[str, Any]) -> str:
    """Format the descriptive statistics section of the report."""
    stats = results.get('statistics', {})
    if not stats:
        return ""
    
    lines = [
        "## Descriptive Statistics",
        "",
        "| Metric | Value |",
        "|--------|-------|",
    ]
    
    for key, value in stats.items():
        formatted_key = key.replace('_', ' ').title()
        if isinstance(value, float):
            lines.append(f"| {formatted_key} | {value:.4f} |")
        else:
            lines.append(f"| {formatted_key} | {value} |")
    
    lines.append("")
    return "\n".join(lines)

def format_sample_data_section(results: Dict[str, Any]) -> str:
    """Format the sample data preview section of the report."""
    sample = results.get('sample_data', [])
    if not sample:
        return ""
    
    lines = [
        "## Sample Data Preview",
        "",
        "| Sample ID | Vector Scalar | Success Rate |",
        "|-----------|---------------|--------------|",
    ]
    
    for row in sample[:10]:  # Show first 10 samples
        sample_id = row.get('sample_id', 'N/A')
        scalar = row.get('vector_scalar', 'N/A')
        success_rate = row.get('success_rate', 'N/A')
        
        if isinstance(scalar, float):
            scalar = f"{scalar:.2f}"
        if isinstance(success_rate, float):
            success_rate = f"{success_rate:.2f}"
        
        lines.append(f"| {sample_id} | {scalar} | {success_rate} |")
    
    lines.append("")
    lines.append("*Showing first 10 samples from the validation set*")
    lines.append("")
    return "\n".join(lines)

def format_metadata_section(results: Dict[str, Any]) -> str:
    """Format the metadata section of the report."""
    lines = [
        "## Metadata",
        "",
    ]
    
    metadata = results.get('metadata', {})
    
    if 'timestamp' in metadata:
        timestamp = metadata['timestamp']
        try:
            dt = datetime.fromisoformat(timestamp.replace('Z', '+00:00'))
            formatted_time = dt.strftime("%Y-%m-%d %H:%M:%S UTC")
            lines.append(f"**Generated:** {formatted_time}")
        except (ValueError, AttributeError):
            lines.append(f"**Generated:** {timestamp}")
        lines.append("")
    
    if 'config' in metadata:
        config = metadata['config']
        lines.append("**Configuration Parameters:**")
        lines.append("")
        for key, value in config.items():
            formatted_key = key.replace('_', ' ').title()
            lines.append(f"- **{formatted_key}:** {value}")
        lines.append("")
    
    if 'data_sources' in metadata:
        sources = metadata['data_sources']
        lines.append("**Data Sources:**")
        lines.append("")
        for source in sources:
            lines.append(f"- {source}")
        lines.append("")
    
    return "\n".join(lines)

def generate_markdown_report(results: Dict[str, Any]) -> str:
    """Generate the complete markdown report."""
    sections = []
    
    # Title
    sections.append("# Sensitivity Analysis Report")
    sections.append("")
    sections.append("**Task:** T042 - State-Guided Curriculum Sensitivity Analysis")
    sections.append("")
    sections.append("This report presents the results of the sensitivity analysis evaluating the")
    sections.append("correlation between State Coverage Vector scalar counts and task success rates.")
    sections.append("")
    
    # Correlation Analysis
    sections.append(format_correlation_section(results))
    
    # Descriptive Statistics
    sections.append(format_statistics_section(results))
    
    # Sample Data Preview
    sections.append(format_sample_data_section(results))
    
    # Metadata
    sections.append(format_metadata_section(results))
    
    # Footer
    sections.append("---")
    sections.append("")
    sections.append("*Report generated by llmXive automated science pipeline*")
    sections.append("")
    
    return "\n".join(sections)

def main():
    """Main entry point for generating the sensitivity report."""
    logger.info("Starting sensitivity report generation (T042)")
    
    # Define paths
    base_dir = Path(__file__).parent.parent.parent
    results_path = base_dir / "data" / "processed" / "sensitivity_results.json"
    output_path = base_dir / "data" / "processed" / "sensitivity_report.md"
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Load results
    results = load_sensitivity_results(results_path)
    if results is None:
        logger.error("Failed to load sensitivity results. Aborting report generation.")
        sys.exit(1)
    
    # Generate report
    logger.info("Generating markdown report")
    report_content = generate_markdown_report(results)
    
    # Write report
    try:
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(report_content)
        logger.info(f"Report successfully written to: {output_path}")
    except Exception as e:
        logger.error(f"Failed to write report: {e}")
        sys.exit(1)
    
    # Verify file was created
    if not output_path.exists():
        logger.error("Report file was not created despite successful write operation.")
        sys.exit(1)
    
    logger.info("Sensitivity report generation completed successfully")
    return 0

if __name__ == "__main__":
    sys.exit(main())
