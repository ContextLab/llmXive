"""
setup_project_structure.py

This script creates the required project directory hierarchy for the llmXive
follow‑up project and writes a manifest file listing the created directories.
It is invoked by the task T001 and can also be run manually.

The original implementation provided a ``main`` function that performed the
``mkdir -p`` calls.  Here we extend that implementation to also generate a
manifest file under ``data/results`` so that the verifier can confirm that
the directories exist.
"""

import os
from pathlib import Path
from llmxive_toolkit import paths, get_logger

# Obtain a logger – optional but useful for debugging
log = get_logger(__name__)

# ----------------------------------------------------------------------
# Directory specification (relative to the project root)
# ----------------------------------------------------------------------
REQUIRED_DIRS = [
    "src/features",
    "src/modeling",
    "src/intervention",
    "src/eval",
    "src/utils",
    "data/raw",
    "data/processed",
    "data/results",
    "data/models",
    "tests/unit",
    "tests/integration",
    "tests/contract",
]

def _create_directories(base_path: Path) -> None:
    """
    Create each directory in ``REQUIRED_DIRS`` relative to ``base_path``.
    ``exist_ok=True`` makes the operation idempotent.
    """
    for rel_dir in REQUIRED_DIRS:
        dir_path = base_path / rel_dir
        dir_path.mkdir(parents=True, exist_ok=True)
        log.debug(f"Created directory: {dir_path}")

def _write_manifest(base_path: Path) -> None:
    """
    Write a manifest file that lists all directories that should now exist.
    The manifest is written to ``data/results/project_structure_manifest.txt``.
    """
    manifest_path = paths.results("project_structure_manifest.txt")
    # Ensure the parent directory exists (data/results)
    manifest_path.parent.mkdir(parents=True, exist_ok=True)

    with manifest_path.open("w", encoding="utf-8") as f:
        f.write("Project structure manifest generated by setup_project_structure.py\\n")
        f.write("------------------------------------------------------------\\n")
        for rel_dir in sorted(REQUIRED_DIRS):
            f.write(f"{rel_dir}\\n")
    log.info(f"Manifest written to {manifest_path}")

def main() -> None:
    """
    Entry point for the script.

    1. Create the required directories.
    2. Write a manifest file listing the directories.
    """
    project_root = Path.cwd()
    log.info(f"Project root detected as: {project_root}")

    _create_directories(project_root)
    _write_manifest(project_root)

if __name__ == "__main__":
    # When executed directly ``python code/setup_project_structure.py``
    main()
