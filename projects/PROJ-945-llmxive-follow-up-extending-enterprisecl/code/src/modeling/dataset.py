# Constants
FEATURES_FILE = "data/processed/features.jsonl"
ORACLE_LABELS_FILE = "data/processed/oracle_labels.json"
OUTPUT_FILE = "data/processed/triplets.jsonl"
SCHEMA_FILE = "data/processed/error_schema.json"

def load_features_jsonl(path: str) -> List[Dict[str, Any]]:
    """Load features from the JSONL file generated by T017."""
    features = []
    if not os.path.exists(path):
        raise FileNotFoundError(f"Features file not found at {path}. Run T017 first.")
    
    with open(path, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f):
            line = line.strip()
            if not line:
                continue
            try:
                features.append(json.loads(line))
            except json.JSONDecodeError as e:
                raise ValueError(f"Invalid JSON on line {line_num} in {path}: {e}")
    return features

def load_oracle_labels_data(path: str) -> Dict[str, Any]:
    """Load the oracle labels derived in T021a/T021b."""
    if not os.path.exists(path):
        raise FileNotFoundError(f"Oracle labels file not found at {path}. Run T021a/T021b first.")
    
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # The oracle output typically contains a list of records with labels.
    # We expect a structure like: { "labels": [ { "trace_id": ..., "correctable": ... } ] }
    # or a flat list if the previous step saved it that way.
    if isinstance(data, dict) and "labels" in data:
        return data["labels"]
    elif isinstance(data, list):
        return data
    else:
        raise ValueError(f"Unexpected oracle labels format in {path}. Expected dict with 'labels' or list.")

def load_error_schema(path: str) -> Dict[str, Any]:
    """Load the error schema derived in T021a-1."""
    if not os.path.exists(path):
        raise FileNotFoundError(f"Error schema file not found at {path}. Run T021a-1 first.")
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)

def build_triplets(
    features: List[Dict[str, Any]], 
    oracle_labels: List[Dict[str, Any]]
) -> List[Dict[str, Any]]:
    """
    Construct triplets linking failed traces to successful corrections.
    
    Logic:
    1. Group features by a unique trace ID (e.g., 'trace_id' or 'session_id').
    2. Identify pairs where one is 'failed' and another is 'success' for the same context.
    3. Assign the feasibility label based on the oracle's 'correctable' status for the failed trace.
    
    Note: Since the exact linking key isn't specified in the prompt, we assume 
    'trace_id' is the primary key. If the dataset represents independent logs, 
    we may need to group by a 'session_id' or 'task_id'.
    
    For this implementation, we assume the features file contains records with:
    - 'trace_id': Unique identifier
    - 'status': 'success' or 'failure'
    - 'features': The feature vector
    
    And the oracle_labels contains:
    - 'trace_id': Unique identifier
    - 'correctable': Boolean
    
    We will pair a failed trace with a success trace from the same 'session_id' if available,
    or simply create a triplet (failed_features, success_features, label) where success_features
    is a placeholder or the nearest neighbor if strict pairing isn't possible.
    
    However, the task says "linking failed traces to successful corrections".
    In many log datasets, a correction is a subsequent log entry in the same session.
    We will assume a 'session_id' exists to group logs.
    """
    
    # Index features by session_id and status
    # Structure: { session_id: { 'failed': [...], 'success': [...] } }
    session_map = {}
    
    for feat in features:
        # Assume 'session_id' exists. If not, fall back to trace_id if it's a single log per session.
        session_id = feat.get('session_id') or feat.get('trace_id')
        status = feat.get('status', 'unknown')
        
        if session_id is None:
            # If no session ID, we cannot link failed to success meaningfully.
            # We will treat each failed trace as a standalone instance and 
            # pair it with a generic success or skip.
            # For robustness, we'll log a warning and skip pairing if strict.
            continue
        
        if session_id not in session_map:
            session_map[session_id] = {'failed': [], 'success': []}
        
        if status == 'failure' or status == 'failed':
            session_map[session_id]['failed'].append(feat)
        elif status == 'success':
            session_map[session_id]['success'].append(feat)
    
    # Index oracle labels by trace_id
    oracle_map = {label.get('trace_id'): label for label in oracle_labels}
    
    triplets = []
    skipped_count = 0
    
    for session_id, records in session_map.items():
        failed_traces = records['failed']
        success_traces = records['success']
        
        if not failed_traces or not success_traces:
            continue
        
        # For each failed trace in this session, try to pair with a success trace
        # If multiple successes exist, we might pair with the first one or all.
        # We'll pair with the first available success for simplicity.
        success_trace = success_traces[0] if success_traces else None
        
        for failed_trace in failed_traces:
            trace_id = failed_trace.get('trace_id')
            if trace_id not in oracle_map:
                # If we can't find an oracle label for this failed trace, skip it.
                # This ensures we only process traces where the feasibility is known.
                skipped_count += 1
                continue
            
            oracle_entry = oracle_map[trace_id]
            correctable = oracle_entry.get('correctable', False)
            
            # Construct the triplet
            # Format: { 'failed_features': ..., 'success_features': ..., 'feasibility_label': ... }
            triplet = {
                'failed_trace_id': trace_id,
                'success_trace_id': success_trace.get('trace_id') if success_trace else None,
                'session_id': session_id,
                'feasibility_label': 1 if correctable else 0, # 1 = correctable, 0 = unfixable
                'failed_features': failed_trace.get('features', {}),
                'success_features': success_trace.get('features', {}) if success_trace else {}
            }
            
            triplets.append(triplet)
    
    if skipped_count > 0:
        print(f"Warning: Skipped {skipped_count} failed traces due to missing oracle labels.")
    
    return triplets

def write_triplets_jsonl(triplets: List[Dict[str, Any]], output_path: str) -> None:
    """Write the constructed triplets to a JSONL file."""
    output_dir = os.path.dirname(output_path)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        for triplet in triplets:
            f.write(json.dumps(triplet) + '\n')

def run_triplet_construction() -> int:
    """
    Main entry point for T022.
    Loads features, oracle labels, and constructs triplets.
    Returns 0 on success, 1 on failure.
    """
    print("Starting Triplet Construction (T022)...")
    
    # Initialize resource monitor
    monitor = ResourceMonitor()
    monitor.start()
    
    try:
        # 1. Load Features
        print(f"Loading features from {FEATURES_FILE}...")
        features = load_features_jsonl(FEATURES_FILE)
        print(f"Loaded {len(features)} feature records.")
        
        # 2. Load Oracle Labels
        print(f"Loading oracle labels from {ORACLE_LABELS_FILE}...")
        oracle_labels = load_oracle_labels_data(ORACLE_LABELS_FILE)
        print(f"Loaded {len(oracle_labels)} oracle labels.")
        
        # 3. Load Error Schema (for validation/logging, though logic is in oracle)
        try:
            schema = load_error_schema(SCHEMA_FILE)
            print(f"Loaded error schema with {len(schema)} keys.")
        except FileNotFoundError:
            print("Warning: Error schema not found. Proceeding without schema validation.")
        
        # 4. Build Triplets
        print("Constructing triplets...")
        triplets = build_triplets(features, oracle_labels)
        print(f"Constructed {len(triplets)} triplets.")
        
        # 5. Write Output
        print(f"Writing triplets to {OUTPUT_FILE}...")
        write_triplets_jsonl(triplets, OUTPUT_FILE)
        print("Done.")
        
        # Check resource usage
        stats = monitor.stop()
        print(f"Peak Memory RSS: {stats['peak_rss_mb']:.2f} MB")
        if stats['peak_rss_mb'] > 7000:
            print("WARNING: Peak memory usage exceeded 7GB threshold.")
        
        return 0
        
    except FileNotFoundError as e:
        print(f"Error: Missing required input file. {e}")
        return 1
    except Exception as e:
        print(f"Error: {e}")
        return 1
    finally:
        # Ensure monitor is stopped if it was started
        if 'stats' not in locals():
            try:
                monitor.stop()
            except:
                pass

def main():
    sys.exit(run_triplet_construction())

if __name__ == "__main__":
    main()
