"""
Triplet Constructor for EnterpriseClawBench.

This module implements the logic to link failed traces to successful corrections
using the rule-based labels derived from the Semantic Outcome Oracle (T021a).

It generates triplets of the form:
(failed_trace_features, success_trace_features, feasibility_label)

where feasibility_label is derived from the oracle's 'correctable' status.
"""
