"""
Script to compute ACF, Hurst, and Spectral Density for synthetic series.

This script reads synthetic time series generated by T026/T027 from
data/processed/synthetic/, computes metrics using src.data.metrics,
and stores the results in data/processed/metrics_synthetic.json.

Dependency: T026 (generate_synthetic_series) must have run first.
"""
import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, List

# Add project root to path
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from src.data.metrics import compute_metrics_for_dataset, MetricsError
from src.utils.logging import setup_logger, log_info, log_error, log_warning
from src.utils.config import get_path

def find_synthetic_datasets(processed_dir: Path) -> List[Path]:
    """
    Find all synthetic dataset files in the processed directory.
    
    Args:
        processed_dir: Path to data/processed/ directory
        
    Returns:
        List of paths to synthetic dataset files (CSV or JSON)
    """
    synthetic_dir = processed_dir / "synthetic"
    if not synthetic_dir.exists():
        log_warning(f"Synthetic directory does not exist: {synthetic_dir}")
        return []
        
    datasets = []
    for ext in ["*.csv", "*.json"]:
        datasets.extend(synthetic_dir.glob(ext))
        
    log_info(f"Found {len(datasets)} synthetic datasets in {synthetic_dir}")
    return datasets

def compute_metrics_for_synthetic_datasets(dataset_paths: List[Path]) -> Dict[str, Any]:
    """
    Compute ACF, Hurst, and Spectral Density for all synthetic datasets.
    
    Args:
        dataset_paths: List of paths to synthetic dataset files
        
    Returns:
        Dictionary mapping dataset names to their computed metrics
    """
    results = {}
    
    for dataset_path in dataset_paths:
        try:
            log_info(f"Processing synthetic dataset: {dataset_path.name}")
            metrics = compute_metrics_for_dataset(dataset_path)
            results[dataset_path.stem] = metrics
            log_info(f"Successfully computed metrics for {dataset_path.name}")
            
        except MetricsError as e:
            log_error(f"Error computing metrics for {dataset_path.name}: {str(e)}")
            results[dataset_path.stem] = {"error": str(e)}
        except Exception as e:
            log_error(f"Unexpected error processing {dataset_path.name}: {str(e)}")
            results[dataset_path.stem] = {"error": f"Unexpected error: {str(e)}"}
            
    return results

def main():
    """Main entry point for synthetic metrics computation."""
    # Setup logging
    logger = setup_logger("run_metrics_synthetic", level=logging.INFO)
    
    log_info("Starting synthetic metrics computation (T010b)")
    
    # Get paths
    processed_dir = get_path("data_processed")
    output_path = get_path("data_processed") / "metrics_synthetic.json"
    
    log_info(f"Looking for synthetic datasets in: {processed_dir}")
    log_info(f"Output will be written to: {output_path}")
    
    # Find synthetic datasets
    dataset_paths = find_synthetic_datasets(processed_dir)
    
    if not dataset_paths:
        log_error("No synthetic datasets found. Please run T026/T027 first.")
        return 1
        
    # Compute metrics
    log_info(f"Computing metrics for {len(dataset_paths)} synthetic datasets...")
    metrics_results = compute_metrics_for_synthetic_datasets(dataset_paths)
    
    # Write results
    try:
        with open(output_path, 'w') as f:
            json.dump(metrics_results, f, indent=2)
        log_info(f"Successfully wrote metrics to {output_path}")
        
        # Summary
        successful = sum(1 for v in metrics_results.values() if "error" not in v)
        failed = len(metrics_results) - successful
        log_info(f"Metrics computation complete: {successful} successful, {failed} failed")
        
        return 0
        
    except Exception as e:
        log_error(f"Failed to write output file: {str(e)}")
        return 1

if __name__ == "__main__":
    sys.exit(main())
