"""
Synthetic Data Verification Module (T057)

This script validates the synthetic time series generated by the
`src.synthesis.generators` module (task T026). For each synthetic series,
it performs the following checks:

1. **Mean Check**: The empirical mean must be within ±0.01 of the target
   mean (which is defined to be 0 for all synthetic series).

2. **Kolmogorov‑Smirnov (KS) Test**: A KS test is performed against a
   normal distribution with mean 0 and the empirical standard deviation.
   If the KS test rejects the null hypothesis at α=0.05, the series is
   considered to have failed the distribution check.

3. **Hurst Exponent Check**: The empirical Hurst exponent is estimated
   via Detrended Fluctuation Analysis (DFA) using the implementation in
   `src.data.metrics.compute_dfa_hurst`. The estimated H must be within
   0.05 of the target Hurst exponent, which is encoded in the file name
   of the synthetic series (e.g. ``synthetic_H0.8_len1000.csv``).

The script aggregates the results and writes a verification report to
``data/results/synthetic_verification.json``. The report contains a
top‑level ``status`` field that is ``"PASS"`` only if **all** synthetic
series satisfy every check; otherwise ``"FAIL```` with detailed per‑file
diagnostics.

The module is intended to be invoked as part of the pipeline stage
``--stage synthesis`` (or directly via the quickstart) and must run
without interactive input.
"""

import json
import logging
import re
import sys
from pathlib import Path
from typing import List, Dict, Any

import numpy as np
import pandas as pd
from scipy import stats

# Project‑relative imports (the repository root is added to sys.path by the
# execution environment).  The metrics module provides the DFA Hurst
# estimator.
from src.data.metrics import compute_dfa_hurst
from src.utils.logging import setup_logger, log_info, log_warning, log_error, log_critical
from src.utils.config import get_path, ensure_dirs

# Initialise a module‑level logger.
logger = setup_logger("synthetic_verification")

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def _extract_target_hurst(filename: str) -> float:
    """
    Extract the target Hurst exponent from a synthetic file name.

    Expected pattern (case‑insensitive):
        *synthetic*_H<value>_*.csv*
    where <value> can be written with a decimal point or an underscore
    (e.g. ``H0.8`` or ``H0_8``).  The function returns the float value.

    Raises:
        ValueError: if the pattern cannot be found or conversion fails.
    """
    pattern = re.compile(r"H(?P<h>\d+(?:[._]\d+)?)", re.IGNORECASE)
    match = pattern.search(filename)
    if not match:
        raise ValueError(f"Unable to locate target Hurst exponent in filename '{filename}'.")
    h_str = match.group("h").replace("_", ".")
    try:
        return float(h_str)
    except ValueError as exc:
        raise ValueError(f"Failed to parse Hurst value '{h_str}' from filename '{filename}'.") from exc

def _load_series(csv_path: Path) -> pd.Series:
    """
    Load a synthetic series CSV file.

    The CSV is expected to contain a single column of numeric values.
    Header rows are allowed; the first column is used.

    Returns:
        pandas.Series of the numeric values.
    """
    df = pd.read_csv(csv_path, header=0 if pd.read_csv(csv_path, nrows=0).shape[1] > 0 else None)
    # If more than one column, take the first.
    series = df.iloc[:, 0].astype(float)
    return series

def _verify_series(series: pd.Series, target_hurst: float) -> Dict[str, Any]:
    """
    Perform the three verification checks on a single series.

    Returns a dictionary with the results and any error messages.
    """
    result: Dict[str, Any] = {
        "mean_check": None,
        "ks_test": None,
        "hurst_check": None,
        "errors": []
    }

    # ---- Mean check -------------------------------------------------
    empirical_mean = series.mean()
    if abs(empirical_mean) <= 0.01:
        result["mean_check"] = True
    else:
        result["mean_check"] = False
        result["errors"].append(f"Mean {empirical_mean:.5f} outside ±0.01 of 0.")

    # ---- KS test ----------------------------------------------------
    # Use a normal distribution with mean 0 and the empirical std.
    empirical_std = series.std(ddof=1)
    if empirical_std == 0:
        # Degenerate case – treat as failure.
        result["ks_test"] = False
        result["errors"].append("Standard deviation is zero; KS test not applicable.")
    else:
        ks_stat, ks_p = stats.kstest(series, "norm", args=(0, empirical_std))
        if ks_p >= 0.05:
            result["ks_test"] = True
        else:
            result["ks_test"] = False
            result["errors"].append(f"KS test p‑value {ks_p:.5f} < 0.05; distribution mismatch.")

    # ---- Hurst exponent check ---------------------------------------
    try:
        empirical_hurst = compute_dfa_hurst(series)
        if abs(empirical_hurst - target_hurst) <= 0.05:
            result["hurst_check"] = True
        else:
            result["hurst_check"] = False
            result["errors"].append(
                f"Empirical Hurst {empirical_hurst:.3f} differs from target {target_hurst:.3f} by >0.05."
            )
    except Exception as exc:
        result["hurst_check"] = False
        result["errors"].append(f"Hurst computation failed: {exc}")

    return result

# ----------------------------------------------------------------------
# Main verification routine
# ----------------------------------------------------------------------
def run_verification() -> Dict[str, Any]:
    """
    Scan the synthetic data directory, verify each series, and build a
    summary report.

    Returns:
        A dictionary suitable for JSON serialisation.
    """
    synthetic_dir = get_path("data/processed/synthetic")
    if not synthetic_dir.exists():
        raise FileNotFoundError(f"Synthetic data directory '{synthetic_dir}' does not exist.")

    csv_files = list(synthetic_dir.glob("*.csv"))
    if not csv_files:
        raise FileNotFoundError(f"No synthetic CSV files found in '{synthetic_dir}'.")

    report: Dict[str, Any] = {
        "status": "PASS",
        "total_series": len(csv_files),
        "passed_series": 0,
        "failed_series": 0,
        "details": []
    }

    for csv_path in csv_files:
        file_report: Dict[str, Any] = {
            "file": str(csv_path.relative_to(Path.cwd())),
            "checks": {},
            "errors": []
        }

        try:
            target_hurst = _extract_target_hurst(csv_path.name)
            series = _load_series(csv_path)
            checks = _verify_series(series, target_hurst)

            file_report["checks"] = {
                "mean": checks["mean_check"],
                "ks_test": checks["ks_test"],
                "hurst": checks["hurst_check"]
            }
            file_report["errors"] = checks["errors"]

            if all([checks["mean_check"], checks["ks_test"], checks["hurst_check"]]):
                report["passed_series"] += 1
            else:
                report["failed_series"] += 1
                report["status"] = "FAIL"

        except Exception as exc:
            # Any unexpected error counts as a failure for this file.
            log_error(f"Verification failed for {csv_path.name}: {exc}")
            file_report["errors"].append(str(exc))
            report["failed_series"] += 1
            report["status"] = "FAIL"

        report["details"].append(file_report)

    return report

# ----------------------------------------------------------------------
# Entry point
# ----------------------------------------------------------------------
def main() -> None:
    """
    Execute the verification and write the JSON report.

    The output file is ``data/results/synthetic_verification.json``.
    """
    log_info("Starting synthetic data verification (T057)...")

    # Ensure the output directory exists.
    output_dir = get_path("data/results")
    ensure_dirs(output_dir)

    try:
        verification_report = run_verification()
    except Exception as exc:
        log_critical(f"Synthetic verification aborted: {exc}")
        sys.exit(1)

    output_path = get_path("data/results/synthetic_verification.json")
    with open(output_path, "w") as f:
        json.dump(verification_report, f, indent=2)

    if verification_report["status"] == "PASS":
        log_info(f"Synthetic verification PASSED. Report written to {output_path}")
    else:
        log_warning(f"Synthetic verification FAILED. See {output_path} for details.")
        # Exit with non‑zero status to signal failure to downstream scripts.
        sys.exit(1)

if __name__ == "__main__":
    main()