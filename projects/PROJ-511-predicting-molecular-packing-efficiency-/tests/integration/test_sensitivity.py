"""
Integration test for threshold sweep (T032).
Verifies that code/sensitivity.py correctly sweeps thresholds {0.5, 0.6, 0.7},
computes metrics, applies Bonferroni correction, and writes results to disk.
"""
import os
import sys
import json
import subprocess
import pandas as pd
import numpy as np
from pathlib import Path

# Add project root to path to import local modules if needed for setup
PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT / "code"))

def run_sensitivity_script():
    """Execute the sensitivity analysis script."""
    script_path = PROJECT_ROOT / "code" / "sensitivity.py"
    if not script_path.exists():
        raise FileNotFoundError(f"Script not found: {script_path}")

    result = subprocess.run(
        [sys.executable, str(script_path)],
        cwd=PROJECT_ROOT,
        capture_output=True,
        text=True
    )

    if result.returncode != 0:
        print("STDOUT:", result.stdout)
        print("STDERR:", result.stderr)
        raise RuntimeError(f"Sensitivity script failed with code {result.returncode}")

    return result.stdout, result.stderr

def test_threshold_sweep_execution():
    """
    Test that the sensitivity script runs successfully and produces output.
    """
    # Ensure input data exists (generated by previous tasks)
    input_file = PROJECT_ROOT / "data" / "dataset.csv"
    if not input_file.exists():
        # Skip if dataset not generated yet, but in CI this should exist
        print(f"Skipping: Input file {input_file} not found. Run US1 tasks first.")
        return

    # Run the script
    stdout, stderr = run_sensitivity_script()

    # Verify output file exists
    output_file = PROJECT_ROOT / "results" / "sensitivity_sweep.csv"
    assert output_file.exists(), f"Output file {output_file} was not created."

    # Verify content structure
    df = pd.read_csv(output_file)
    required_columns = ["threshold", "r", "rho", "mae", "p_value", "bonferroni_corrected_p"]
    assert list(df.columns) == required_columns, f"Columns mismatch: {list(df.columns)} vs {required_columns}"

    # Verify specific thresholds
    thresholds = set(df["threshold"].tolist())
    expected_thresholds = {0.5, 0.6, 0.7}
    assert thresholds == expected_thresholds, f"Thresholds mismatch: {thresholds} vs {expected_thresholds}"

    # Verify numeric validity
    assert df["r"].notna().all(), "Column 'r' contains NaN"
    assert df["rho"].notna().all(), "Column 'rho' contains NaN"
    assert df["mae"].notna().all(), "Column 'mae' contains NaN"
    assert df["p_value"].notna().all(), "Column 'p_value' contains NaN"
    assert df["bonferroni_corrected_p"].notna().all(), "Column 'bonferroni_corrected_p' contains NaN"

    # Verify Bonferroni logic (corrected p >= raw p, capped at 1.0)
    raw_p = df["p_value"]
    corrected_p = df["bonferroni_corrected_p"]
    assert (corrected_p >= raw_p).all(), "Bonferroni corrected p should be >= raw p"
    assert (corrected_p <= 1.0).all(), "Bonferroni corrected p should be <= 1.0"

    print("Integration test passed: Sensitivity sweep executed successfully.")

if __name__ == "__main__":
    test_threshold_sweep_execution()