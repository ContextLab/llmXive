"""
Contract test for model output schema (T022).

Validates that the model output artifacts produced by the evaluation pipeline
conform to the schema defined in contracts/model.schema.yaml.

Dependencies:
  - T005: contracts/model.schema.yaml must exist
  - T026: evaluate.py must produce results/validation_report.json
"""
import json
import os
import sys
import unittest
from pathlib import Path
import yaml

# Add project root to path for imports if necessary
project_root = Path(__file__).parent.parent.parent
sys.path.insert(0, str(project_root))

class TestModelOutputSchema(unittest.TestCase):
    """
    Validates the structure and content of model output files against the
    contract schema.
    """

    @classmethod
    def setUpClass(cls):
        """
        Load the schema and locate the expected output files.
        """
        cls.project_root = Path(__file__).parent.parent.parent
        cls.contracts_dir = cls.project_root / "contracts"
        cls.results_dir = cls.project_root / "results"
        
        # Schema path
        cls.schema_path = cls.contracts_dir / "model.schema.yaml"
        
        # Expected output paths (generated by T026/T027/T029)
        cls.validation_report_path = cls.results_dir / "validation_report.json"
        
        # Check if files exist
        if not cls.schema_path.exists():
            raise FileNotFoundError(
                f"Schema file not found at {cls.schema_path}. "
                "Ensure T005 (Create model.schema.yaml) is completed."
            )
        
        with open(cls.schema_path, 'r', encoding='utf-8') as f:
            cls.schema = yaml.safe_load(f)
        
        # Flag if report exists for actual validation
        cls.report_exists = cls.validation_report_path.exists()

    def test_schema_file_structure(self):
        """
        Verify the schema file itself has the expected top-level keys.
        """
        required_keys = {"type", "properties"}
        self.assertTrue(
            required_keys.issubset(self.schema.keys()),
            f"Schema must contain keys: {required_keys}"
        )
        self.assertEqual(self.schema["type"], "object")

    def test_required_report_properties(self):
        """
        Verify the schema defines the required properties for the validation report.
        Based on FR-006, FR-015, FR-016, FR-009.
        """
        properties = self.schema.get("properties", {})
        required_fields = [
            "mae", "pearson_r", "spearman_rho", 
            "shapiro_wilk_p", "permutation_p_value",
            "model_type", "feature_set"
        ]
        
        for field in required_fields:
            self.assertIn(
                field, properties,
                f"Schema must define property '{field}' for the validation report."
            )

    def test_validation_report_exists(self):
        """
        Verify that the validation report file exists.
        (This test will fail if the pipeline hasn't been run yet, which is expected behavior).
        """
        self.assertTrue(
            self.report_exists,
            f"Validation report not found at {self.validation_report_path}. "
            "Run the evaluation pipeline (T026) to generate this file."
        )

    def test_validation_report_schema_compliance(self):
        """
        Validate the content of validation_report.json against the schema.
        Skipped if the file does not exist yet.
        """
        if not self.report_exists:
            self.skipTest("validation_report.json does not exist yet.")

        with open(self.validation_report_path, 'r', encoding='utf-8') as f:
            report = json.load(f)

        # Basic type check
        self.assertIsInstance(report, dict, "Validation report must be a JSON object.")

        # Check for required top-level fields defined in schema
        schema_props = self.schema.get("properties", {})
        for key in schema_props:
            self.assertIn(
                key, report,
                f"Report missing required field: {key}"
            )

        # Type validation for numeric fields
        numeric_fields = ["mae", "pearson_r", "spearman_rho", "shapiro_wilk_p", "permutation_p_value"]
        for field in numeric_fields:
            if field in report:
                self.assertIsInstance(
                    report[field], (int, float),
                    f"Field '{field}' must be numeric."
                )
                # Check for NaN or Inf if applicable
                import math
                if isinstance(report[field], float):
                    self.assertFalse(
                        math.isnan(report[field]) or math.isinf(report[field]),
                        f"Field '{field}' cannot be NaN or Infinity."
                    )

        # Check model metadata
        if "model_type" in report:
            valid_types = ["baseline", "control", "upper_bound", "baseline_physics"]
            self.assertIn(
                report["model_type"].lower(),
                [t.lower() for t in valid_types],
                f"model_type must be one of {valid_types}"
            )

    def test_model_checkpoint_exists(self):
        """
        Verify that model checkpoint files exist if a training run was completed.
        Expected paths: models/baseline_checkpoint.pt, etc.
        """
        models_dir = self.project_root / "models"
        expected_checkpoints = [
            "baseline_checkpoint.pt",
            "control_3d_checkpoint.pt",
            "upper_bound_checkpoint.pt"
        ]
        
        # Check if at least one checkpoint exists (indicates training happened)
        # We don't fail if none exist, as this might be before training, 
        # but we assert existence if the report claims a model was evaluated.
        if self.report_exists:
            with open(self.validation_report_path, 'r', encoding='utf-8') as f:
                report = json.load(f)
            
            model_type = report.get("model_type", "").lower()
            checkpoint_name = f"{model_type}_checkpoint.pt"
            
            # Fallback to standard names if specific mapping isn't in report
            if not checkpoint_name in [str(p.name) for p in models_dir.glob("*.pt")]:
                # Check for generic existence
                self.assertTrue(
                    any(models_dir.glob("*.pt")),
                    f"Model report exists for {model_type}, but no .pt files found in {models_dir}"
                )


if __name__ == "__main__":
    unittest.main()