"""
Preprocess MEG data: Part 2 - Compute Welch PSD and normalize.

This module extends the preprocessing pipeline to compute Power Spectral Density (PSD)
using Welch's method and normalize the results to unit area.

Dependencies:
  - T007: Requires `data/processed/meg_filtered.npy` generated by the bandpass filter step.
  - src/analysis/spectral.py: Uses `compute_welch_psd` and `normalize_psd_to_unit_area`.
"""

import os
import sys
import numpy as np
from pathlib import Path

# Add project root to path for imports if running as script
project_root = Path(__file__).resolve().parent.parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from src.analysis.spectral import compute_welch_psd, normalize_psd_to_unit_area


def process_meg_psd(input_path: str, output_path: str) -> None:
    """
    Load filtered MEG data, compute Welch PSD, zero-pad if necessary, and normalize to unit area.

    Args:
        input_path: Path to the input file (e.g., data/processed/meg_filtered.npy).
        output_path: Path to save the output normalized PSD (e.g., data/processed/meg_psd_normalized.npy).
    """
    input_file = Path(input_path)
    output_file = Path(output_path)

    if not input_file.exists():
        raise FileNotFoundError(
            f"Input file not found: {input_path}. "
            "Please ensure T007 (bandpass filtering) has been completed successfully."
        )

    # Load the filtered data
    print(f"Loading filtered data from {input_file}...")
    try:
        # Expected shape: (n_samples, n_channels) or (n_trials, n_samples, n_channels)
        # We assume 2D (n_samples, n_channels) for simplicity based on T007 output description
        data = np.load(input_file)
    except Exception as e:
        raise RuntimeError(f"Failed to load numpy file {input_file}: {e}")

    if data.ndim == 1:
        # Reshape to (n_samples, 1) if 1D
        data = data.reshape(-1, 1)
    elif data.ndim > 2:
        # If 3D (trials, samples, channels), we might need to aggregate or process per trial.
        # For this step, we assume we are processing the aggregated or single-trial data.
        # If it's 3D, we flatten trials into samples for spectral analysis or take mean.
        # Given T007 description, we expect 2D. If 3D, we take the mean across the first axis (trials)
        # to get a representative signal, or process the first trial.
        # Let's assume the input is (n_samples, n_channels) as per typical streaming aggregation.
        # If it is (n_trials, n_samples, n_channels), we average over trials to get a stable PSD.
        if data.shape[0] < 100: # Heuristic: if first dim is small, it might be trials
            print(f"Input shape {data.shape} detected. Averaging over first dimension (trials)...")
            data = np.mean(data, axis=0)
        else:
            raise ValueError(
                f"Unexpected input shape {data.shape}. Expected (n_samples, n_channels) or (n_trials, n_samples, n_channels)."
            )

    n_samples, n_channels = data.shape
    print(f"Data loaded: {n_samples} samples, {n_channels} channels.")

    # Configuration for Welch's method
    # Task requirement: Zero-pad to 512 if seq_len < 512
    # We assume a standard sampling rate for MEG (e.g., 1000Hz or similar).
    # If not provided, we assume a generic fs. The spectral module handles fs.
    # We'll assume fs=1000Hz as a default if not specified in the config,
    # but the spectral module should ideally take it from config.
    # For now, we pass fs=1000.0 as a reasonable default for MEG data.
    fs = 1000.0 
    nperseg = 256  # Standard segment size for Welch
    noverlap = 128 # 50% overlap

    psd_list = []
    freqs_list = []

    print("Computing Welch PSD for each channel...")
    for ch_idx in range(n_channels):
        signal = data[:, ch_idx]
        
        # Zero-pad logic: if sequence length < 512, pad to 512
        # Note: Welch's method uses nperseg segments. 
        # The task says "zero-pad to 512 if seq_len < 512".
        # This likely refers to the segment length or the total signal length for FFT.
        # We will pad the signal itself if it's shorter than 512 samples to ensure sufficient frequency resolution.
        if len(signal) < 512:
            pad_width = 512 - len(signal)
            signal = np.pad(signal, (0, pad_width), mode='constant')
            print(f"  Channel {ch_idx}: Padded from {len(signal)-pad_width} to {len(signal)} samples.")

        # Compute Welch PSD
        # compute_welch_psd is expected to return (frequencies, psd)
        try:
            freqs, psd = compute_welch_psd(signal, fs=fs, nperseg=nperseg, noverlap=noverlap)
        except Exception as e:
            raise RuntimeError(f"Failed to compute PSD for channel {ch_idx}: {e}")
        
        psd_list.append(psd)
        freqs_list.append(freqs)

    # Stack results: (n_channels, n_freqs)
    psd_matrix = np.vstack(psd_list)
    freqs = freqs_list[0] # All channels should have same freqs

    print(f"PSD computed: shape {psd_matrix.shape}.")

    # Normalize to unit area
    print("Normalizing PSD to unit area...")
    try:
        normalized_psd = normalize_psd_to_unit_area(psd_matrix)
    except Exception as e:
        raise RuntimeError(f"Failed to normalize PSD: {e}")

    # Save the result
    output_file.parent.mkdir(parents=True, exist_ok=True)
    np.save(output_file, normalized_psd)
    print(f"Saved normalized PSD to {output_file}")

    # Optional: Save frequencies for reference
    freq_file = output_file.with_suffix('.npy.freqs')
    np.save(str(freq_file), freqs)
    print(f"Saved frequencies to {freq_file}")


def main():
    """Entry point for the script."""
    # Define paths relative to project root
    project_root = Path(__file__).resolve().parent.parent.parent
    input_path = project_root / "data" / "processed" / "meg_filtered.npy"
    output_path = project_root / "data" / "processed" / "meg_psd_normalized.npy"

    if not input_path.exists():
        print(f"ERROR: Input file {input_path} not found.")
        print("Please run T007 (preprocess_meg.py Part 1) first to generate meg_filtered.npy.")
        sys.exit(1)

    try:
        process_meg_psd(str(input_path), str(output_path))
        print("T047 completed successfully.")
    except Exception as e:
        print(f"ERROR: T047 failed: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()
