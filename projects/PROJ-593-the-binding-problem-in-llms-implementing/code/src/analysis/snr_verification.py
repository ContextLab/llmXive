"""
SNR Verification Module for User Story 1.

This module implements the verification of Signal-to-Noise Ratio (SNR) for
oscillatory attention mechanisms. It calculates peak power in the target band
versus adjacent bands and asserts SNR >= 3.0 dB, utilizing control run data
generated by T021.

Dependencies:
  - T012: Spectral analysis functions (compute_welch_psd, calculate_snr)
  - T018: Activation time series extraction from oscillatory runs
  - T021: Control run comparison data (baseline vs oscillatory)
"""

import os
import json
import numpy as np
from pathlib import Path
from typing import Dict, Any, Tuple, Optional, List

# Import existing spectral analysis utilities
from src.analysis.spectral import compute_welch_psd, calculate_snr


def load_activation_time_series(file_path: str) -> np.ndarray:
    """
    Loads activation time series data from a .npy file.

    Args:
        file_path: Path to the numpy file containing activations.
                   Expected shape: (batch_size, seq_len, hidden_dim) or (seq_len, hidden_dim).

    Returns:
        numpy array of activations.
    """
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Activation time series file not found: {file_path}")
    
    data = np.load(file_path)
    return data


def load_control_run_comparison(file_path: str) -> Dict[str, Any]:
    """
    Loads the control run comparison data generated by T021.

    Args:
        file_path: Path to the JSON file containing control run data.

    Returns:
        Dictionary with keys: 'oscillatory_coherence', 'baseline_coherence', 'coherence_difference'.
    """
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Control run comparison file not found: {file_path}")
    
    with open(file_path, 'r') as f:
        return json.load(f)


def calculate_target_band_snr(
    activations: np.ndarray,
    sampling_rate: float = 100.0,
    target_band: Tuple[float, float] = (30.0, 50.0),
    adjacent_band_width: float = 10.0
) -> Tuple[float, Dict[str, float]]:
    """
    Calculates the SNR for a specific target frequency band compared to adjacent bands.

    This function computes the Welch Power Spectral Density (PSD), identifies the peak
    power within the target band, and compares it to the average power in the
    adjacent bands (below and above the target).

    Args:
        activations: Time series data (seq_len, hidden_dim) or (batch_size, seq_len, hidden_dim).
                    If batched, averages across batch and hidden_dim.
        sampling_rate: Sampling rate of the activations (in 'Hz' or cycles per sequence unit).
        target_band: Tuple (f_low, f_high) defining the target frequency range.
        adjacent_band_width: Width of the adjacent bands to use for noise estimation.

    Returns:
        Tuple containing:
            - snr_db: Calculated SNR in decibels.
            - metrics: Dictionary with 'peak_power', 'noise_power', 'target_freq'.
    """
    # Handle batched or multi-dimensional data by averaging to 1D signal
    # We assume the last dimension is features/heads and the second to last is time
    if activations.ndim > 2:
        # Average over batch and feature dimensions
        signal = np.mean(activations, axis=tuple(range(activations.ndim - 1)))
    else:
        signal = np.mean(activations, axis=0) if activations.ndim == 2 else activations
    
    # Ensure 1D signal
    signal = signal.flatten()

    if len(signal) == 0:
        raise ValueError("Signal is empty after averaging.")

    # Compute Welch PSD
    # Zero-pad to 512 if seq_len < 512 as per T047 requirements for consistency
    nfft = max(512, len(signal))
    f, psd = compute_welch_psd(signal, fs=sampling_rate, nfft=nfft)

    # Identify indices for target and adjacent bands
    target_low_idx = np.searchsorted(f, target_band[0])
    target_high_idx = np.searchsorted(f, target_band[1])
    
    # Define adjacent bands
    adj_low_start = max(0, target_low_idx - int(adjacent_band_width * (len(f) / (f[-1] - f[0]))))
    adj_low_end = target_low_idx
    
    adj_high_start = target_high_idx
    adj_high_end = min(len(f), target_high_idx + int(adjacent_band_width * (len(f) / (f[-1] - f[0]))))

    # Calculate powers
    target_power = np.mean(psd[target_low_idx:target_high_idx])
    
    # Noise power is average of lower and upper adjacent bands
    noise_power_lower = np.mean(psd[adj_low_start:adj_low_end]) if adj_low_end > adj_low_start else 0.0
    noise_power_upper = np.mean(psd[adj_high_start:adj_high_end]) if adj_high_end > adj_high_start else 0.0
    
    noise_power = (noise_power_lower + noise_power_upper) / 2.0 if (noise_power_lower + noise_power_upper) > 0 else 1e-9

    # Avoid division by zero
    if noise_power <= 0:
        noise_power = 1e-9

    # Calculate SNR in dB
    snr_db = 10 * np.log10(target_power / noise_power)

    # Find peak frequency in target band
    peak_idx = np.argmax(psd[target_low_idx:target_high_idx]) + target_low_idx
    peak_freq = f[peak_idx]
    peak_power = psd[peak_idx]

    metrics = {
        "peak_power": float(peak_power),
        "noise_power": float(noise_power),
        "target_freq": float(peak_freq),
        "target_band": list(target_band),
        "adjacent_band_width": adjacent_band_width
    }

    return snr_db, metrics


def verify_oscillatory_snr(
    oscillatory_activations_path: str,
    baseline_activations_path: Optional[str] = None,
    target_band: Tuple[float, float] = (30.0, 50.0),
    snr_threshold: float = 3.0,
    output_path: str = "data/final/snr_verification_results.json"
) -> Dict[str, Any]:
    """
    Performs the full SNR verification protocol.

    1. Loads oscillatory activations.
    2. Calculates SNR in the target band.
    3. Optionally compares with baseline SNR if provided.
    4. Asserts SNR >= threshold.
    5. Saves results to JSON.

    Args:
        oscillatory_activations_path: Path to the oscillatory run activations (.npy).
        baseline_activations_path: Optional path to baseline run activations (.npy) for comparison.
        target_band: Frequency band to check for oscillation (default 30-50Hz).
        snr_threshold: Minimum required SNR in dB.
        output_path: Path to save the verification results.

    Returns:
        Dictionary containing verification results and metrics.
    """
    # Load data
    oscillatory_activations = load_activation_time_series(oscillatory_activations_path)
    
    result = {
        "verification_status": "pending",
        "oscillatory": {
            "snr_db": None,
            "metrics": {}
        },
        "baseline": {
            "snr_db": None,
            "metrics": {},
            "available": False
        },
        "threshold": snr_threshold,
        "target_band": list(target_band)
    }

    # Calculate SNR for oscillatory run
    try:
        snr_db, metrics = calculate_target_band_snr(
            oscillatory_activations, 
            target_band=target_band
        )
        result["oscillatory"]["snr_db"] = snr_db
        result["oscillatory"]["metrics"] = metrics
        result["oscillatory"]["passes_threshold"] = snr_db >= snr_threshold
    except Exception as e:
        result["error"] = str(e)
        result["verification_status"] = "failed"
        # Save partial result before failing
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        with open(output_path, 'w') as f:
            json.dump(result, f, indent=2)
        raise

    # Calculate SNR for baseline if provided
    if baseline_activations_path and os.path.exists(baseline_activations_path):
        result["baseline"]["available"] = True
        try:
            baseline_activations = load_activation_time_series(baseline_activations_path)
            base_snr_db, base_metrics = calculate_target_band_snr(
                baseline_activations,
                target_band=target_band
            )
            result["baseline"]["snr_db"] = base_snr_db
            result["baseline"]["metrics"] = base_metrics
        except Exception as e:
            result["baseline_error"] = str(e)
            result["baseline"]["available"] = False

    # Verification Logic
    if result["oscillatory"]["passes_threshold"]:
        result["verification_status"] = "passed"
        print(f"✓ SNR Verification PASSED: {result['oscillatory']['snr_db']:.2f} dB >= {snr_threshold} dB")
    else:
        result["verification_status"] = "failed"
        print(f"✗ SNR Verification FAILED: {result['oscillatory']['snr_db']:.2f} dB < {snr_threshold} dB")
        # Do not raise here, just mark as failed, allowing the script to complete and log the failure
        # unless strict assertion is required by the pipeline. 
        # Per task description: "assert SNR >= 3.0 dB". We will raise if it fails to ensure the pipeline catches it.
        raise AssertionError(
            f"SNR verification failed. Expected >= {snr_threshold} dB, got {result['oscillatory']['snr_db']:.2f} dB."
        )

    # Save results
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(result, f, indent=2)
    
    print(f"Results saved to {output_path}")
    return result


def main():
    """
    Main entry point for SNR verification script.
    Reads paths from environment variables or defaults to standard project paths.
    """
    import argparse

    parser = argparse.ArgumentParser(description="Verify SNR of oscillatory attention mechanisms.")
    parser.add_argument(
        "--oscillatory-path",
        type=str,
        default="data/processed/oscillatory_activations.npy",
        help="Path to oscillatory activations file."
    )
    parser.add_argument(
        "--baseline-path",
        type=str,
        default="data/processed/baseline_activations.npy",
        help="Path to baseline activations file (optional)."
    )
    parser.add_argument(
        "--output",
        type=str,
        default="data/final/snr_verification_results.json",
        help="Path to output JSON file."
    )
    parser.add_argument(
        "--target-band-low",
        type=float,
        default=30.0,
        help="Lower bound of target frequency band."
    )
    parser.add_argument(
        "--target-band-high",
        type=float,
        default=50.0,
        help="Upper bound of target frequency band."
    )
    parser.add_argument(
        "--threshold",
        type=float,
        default=3.0,
        help="Minimum SNR threshold in dB."
    )

    args = parser.parse_args()

    target_band = (args.target_band_low, args.target_band_high)

    try:
        verify_oscillatory_snr(
            oscillatory_activations_path=args.oscillatory_path,
            baseline_activations_path=args.baseline_path,
            target_band=target_band,
            snr_threshold=args.threshold,
            output_path=args.output
        )
    except Exception as e:
        print(f"Verification process encountered an error: {e}")
        # Re-raise to ensure the pipeline knows the task failed
        raise e


if __name__ == "__main__":
    main()