import os
import json
import numpy as np
from pathlib import Path
from typing import Dict, Any, Tuple, Optional, List
from src.analysis.spectral import compute_welch_psd, calculate_snr

# Constants for the gamma band analysis
# Frequency definition is "cycles per sequence length" in this project context,
# but for SNR verification against physical MEG bands (38-42Hz), we assume
# a sampling rate context or a normalized frequency mapping if provided.
# Here we implement the calculation based on the spectral output structure.
TARGET_BAND_LOW = 38.0  # Hz
TARGET_BAND_HIGH = 42.0 # Hz
SNR_THRESHOLD_DB = 3.0

def load_activation_time_series(path: str) -> np.ndarray:
    """
    Loads activation time series from a .npy file.
    Expected shape: (num_sequences, sequence_length) or (sequence_length,).
    """
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"Activation time series file not found: {path}")
    data = np.load(p)
    if data.ndim == 1:
        data = data.reshape(1, -1)
    return data

def load_control_run_comparison(path: str) -> Dict[str, Any]:
    """
    Loads the control run comparison JSON generated by T021.
    """
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"Control run comparison file not found: {path}")
    with open(p, 'r') as f:
        return json.load(f)

def calculate_target_band_snr(psd: np.ndarray, freqs: np.ndarray) -> Tuple[float, float, float]:
    """
    Calculates the SNR for the target gamma band (38-42Hz) vs adjacent bands.
    
    Args:
        psd: Power Spectral Density array.
        freqs: Corresponding frequency array.
        
    Returns:
        Tuple of (target_band_power, adjacent_band_power, snr_db).
    """
    # Identify indices for target band
    target_mask = (freqs >= TARGET_BAND_LOW) & (freqs <= TARGET_BAND_HIGH)
    if not np.any(target_mask):
        raise ValueError(f"Target band {TARGET_BAND_LOW}-{TARGET_BAND_HIGH}Hz not found in frequency array.")
    
    target_power = np.mean(psd[target_mask])
    
    # Identify adjacent bands (e.g., 20-38Hz and 42-60Hz)
    # We'll take the immediate neighbors to avoid DC and very high noise
    adjacent_mask = ((freqs >= 20.0) & (freqs < TARGET_BAND_LOW)) | \
                    ((freqs > TARGET_BAND_HIGH) & (freqs <= 60.0))
    
    if not np.any(adjacent_mask):
        raise ValueError("Adjacent bands not found in frequency array.")
        
    adjacent_power = np.mean(psd[adjacent_mask])
    
    # Avoid division by zero
    if adjacent_power <= 0:
        adjacent_power = 1e-9
        
    snr_db = 10 * np.log10(target_power / adjacent_power)
    
    return target_power, adjacent_power, snr_db

def verify_oscillatory_snr(
    activation_path: str,
    control_path: str,
    fs: float = 1000.0,
    nperseg: int = 256
) -> Dict[str, Any]:
    """
    Main verification function.
    1. Loads oscillatory activations.
    2. Computes Welch PSD.
    3. Calculates SNR in the 38-42Hz band.
    4. Compares with control run data if available.
    5. Returns a report and asserts SNR >= threshold.
    """
    # Load data
    activations = load_activation_time_series(activation_path)
    control_data = load_control_run_comparison(control_path)
    
    # Compute PSD for the first sequence (or average if multiple)
    # Assuming activations shape: (batch, seq_len)
    # We compute PSD for each and average, or just take the first if single run
    seq_len = activations.shape[-1]
    
    # Adjust nperseg if sequence is short
    if seq_len < nperseg:
        nperseg = seq_len
        
    psds = []
    for seq in activations:
        freqs, psd = compute_welch_psd(seq, fs=fs, nperseg=nperseg)
        psds.append(psd)
    
    avg_psd = np.mean(psds, axis=0)
    
    # Calculate SNR
    try:
        target_p, adj_p, snr_db = calculate_target_band_snr(avg_psd, freqs)
    except ValueError as e:
        # If band not found, report failure
        return {
            "status": "failed",
            "reason": str(e),
            "snr_db": None
        }
    
    # Comparison with control
    baseline_snr = control_data.get("baseline_coherence", 0.0) # Using coherence as proxy if SNR not stored
    # Ideally, we would compute SNR for baseline too, but T021 output uses coherence.
    # We will report the calculated SNR and note the comparison.
    
    result = {
        "status": "passed" if snr_db >= SNR_THRESHOLD_DB else "failed",
        "target_band_power": float(target_p),
        "adjacent_band_power": float(adj_p),
        "snr_db": float(snr_db),
        "threshold_db": SNR_THRESHOLD_DB,
        "control_run_coherence": control_data.get("oscillatory_coherence", 0.0),
        "baseline_run_coherence": control_data.get("baseline_coherence", 0.0),
        "message": f"SNR is {snr_db:.2f} dB. Threshold is {SNR_THRESHOLD_DB} dB."
    }
    
    if result["status"] == "passed":
        result["message"] += " Requirement satisfied."
    else:
        result["message"] += " Requirement NOT satisfied."
        
    return result

def main():
    """
    Entry point to run SNR verification.
    Expects activation data at data/processed/activation_oscillatory.npy
    and control data at data/final/control_run_comparison.json
    """
    base_dir = Path(__file__).resolve().parent.parent.parent
    activation_path = base_dir / "data" / "processed" / "activation_oscillatory.npy"
    control_path = base_dir / "data" / "final" / "control_run_comparison.json"
    output_path = base_dir / "data" / "final" / "snr_verification_results.json"
    
    if not activation_path.exists():
        print(f"Error: Activation file not found at {activation_path}")
        print("Please ensure T018 has run and produced activation_oscillatory.npy")
        return
        
    if not control_path.exists():
        print(f"Error: Control run file not found at {control_path}")
        print("Please ensure T021 has run and produced control_run_comparison.json")
        return
        
    print(f"Running SNR verification on {activation_path}...")
    
    # Assuming a sampling rate of 1000Hz for the simulation of time steps
    # This maps sequence indices to time. If the model output is not time-sampled,
    # this is a proxy for "frequency per sequence".
    # Per project spec: Frequency is "cycles per sequence length".
    # To map to 38-42Hz, we assume a normalization where 1 cycle = 1 unit of time?
    # Actually, if we are looking for 40Hz, we need a sampling rate.
    # If the sequence length is N, and we have 40 cycles, fs = N * 40?
    # Let's assume the input is treated as a time series with fs=1000 for spectral analysis.
    # The user must ensure the data corresponds to the intended frequency band.
    
    result = verify_oscillatory_snr(str(activation_path), str(control_path), fs=1000.0)
    
    # Save results
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(result, f, indent=2)
        
    print(f"Results saved to {output_path}")
    print(f"Status: {result['status']}")
    print(f"Message: {result['message']}")
    
    if result['status'] == 'failed':
        # Do not raise exception to allow the pipeline to log the failure,
        # but clearly indicate the failure.
        print("WARNING: SNR verification failed. Check configuration or data.")
    else:
        print("SUCCESS: SNR verification passed.")

if __name__ == "__main__":
    main()
