"""
Discovery filtering module for T011.

This script reads the discovery results generated by T009
(`output/discovery_results.json`), filters the datasets by
allowed model organisms (mouse, C. elegans, Drosophila) and by
metadata completeness (presence of fluctuation timescale and
amplitude), and writes the filtered list to
`output/filtered_datasets.json`.

The functions are also importable by other modules:
  - filter_by_organism(datasets, allowed_organisms)
  - check_metadata_completeness(dataset)
  - run_discovery(search_keywords=None, allowed_organisms=None)

The script is deliberately side‑effect free apart from the
JSON output file, making it suitable for unit testing.
"""

import argparse
import json
import logging
from pathlib import Path
from typing import List, Dict, Optional

from llmxive_toolkit import paths, get_logger

# ----------------------------------------------------------------------
# Configuration
# ----------------------------------------------------------------------
LOG = get_logger(__name__)

# Default organism list (lower‑case substrings that may appear in GEO/ENCODE metadata)
DEFAULT_ORGANISMS = [
    "mouse",
    "c. elegans",
    "caenorhabditis elegans",
    "drosophila",
]

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def filter_by_organism(
    datasets: List[Dict],
    allowed_organisms: Optional[List[str]] = None,
) -> List[Dict]:
    """
    Keep only datasets whose ``organism`` field matches one of the
    ``allowed_organisms`` (case‑insensitive substring match).

    Parameters
    ----------
    datasets: List[Dict]
        Raw dataset dictionaries as produced by the discovery step.
    allowed_organisms: Optional[List[str]]
        List of organism identifiers. If ``None`` the default list
        (mouse, C. elegans, Drosophila) is used.

    Returns
    -------
    List[Dict]
        Sub‑set of ``datasets`` that belong to a supported model organism.
    """
    if allowed_organisms is None:
        allowed_organisms = DEFAULT_ORGANISMS

    # Normalise the allowed strings for case‑insensitive matching
    allowed_norm = [org.lower() for org in allowed_organisms]

    filtered = []
    for ds in datasets:
        organism_field = ds.get("organism", "")
        organism_norm = organism_field.lower()
        if any(org in organism_norm for org in allowed_norm):
            filtered.append(ds)
        else:
            LOG.debug(
                "Dataset %s excluded by organism filter (found: %s).",
                ds.get("accession", "UNKNOWN"),
                organism_field,
            )
    LOG.info(
        "Organism filter: %d of %d datasets retained.",
        len(filtered),
        len(datasets),
    )
    return filtered

def check_metadata_completeness(dataset: Dict) -> bool:
    """
    Determine whether a dataset contains the required metadata fields:
    ``fluctuation_timescale`` and ``fluctuation_amplitude`` (or
    equivalents). The presence of *any* of the following keys is
    considered sufficient:

    - ``fluctuation_timescale``
    - ``fluctuation_period``
    - ``env_period``          (alternative naming)

    and

    - ``fluctuation_amplitude``
    - ``amplitude``

    Returns ``True`` only if *both* a timescale and an amplitude entry
    exist and are not ``None``/empty.

    Parameters
    ----------
    dataset: Dict
        Single dataset dictionary.

    Returns
    -------
    bool
        ``True`` if the required metadata is present, ``False`` otherwise.
    """
    metadata = dataset.get("metadata", {})

    # Timescale keys (any one present is acceptable)
    timescale_keys = [
        "fluctuation_timescale",
        "fluctuation_period",
        "env_period",
    ]
    has_timescale = any(
        metadata.get(key) not in (None, "", []) for key in timescale_keys
    )

    # Amplitude keys (any one present is acceptable)
    amplitude_keys = ["fluctuation_amplitude", "amplitude"]
    has_amplitude = any(
        metadata.get(key) not in (None, "", []) for key in amplitude_keys
    )

    if not has_timescale or not has_amplitude:
        LOG.debug(
            "Dataset %s missing required metadata (timescale: %s, amplitude: %s).",
            dataset.get("accession", "UNKNOWN"),
            has_timescale,
            has_amplitude,
        )
    return has_timescale and has_amplitude

def run_discovery(
    search_keywords: Optional[List[str]] = None,
    allowed_organisms: Optional[List[str]] = None,
) -> List[Dict]:
    """
    Core filtering routine for T011.

    1. Load the raw discovery results produced by T009
       (`output/discovery_results.json`).
    2. Optionally filter by organism.
    3. Optionally retain only datasets with complete fluctuation
       metadata.
    4. Write the filtered list to ``output/filtered_datasets.json`` and
       return it.

    Parameters
    ----------
    search_keywords: Optional[List[str]]
        Unused in the current implementation – retained for API
        compatibility with earlier placeholder signatures.
    allowed_organisms: Optional[List[str]]
        List of organism identifiers to keep. If ``None`` the default
        model‑organism list is used.

    Returns
    -------
    List[Dict]
        The filtered dataset dictionaries.
    """
    # ------------------------------------------------------------------
    # Load raw discovery results
    # ------------------------------------------------------------------
    discovery_path = paths.outputs("discovery_results.json")
    if not discovery_path.is_file():
        raise FileNotFoundError(
            f"Discovery results not found at {discovery_path}. "
            "Run T009 before T011."
        )
    with discovery_path.open("r", encoding="utf-8") as f:
        raw_datasets = json.load(f)

    LOG.info("Loaded %d raw discovery entries.", len(raw_datasets))

    # ------------------------------------------------------------------
    # Apply organism filter
    # ------------------------------------------------------------------
    organism_filtered = filter_by_organism(
        raw_datasets, allowed_organisms=allowed_organisms
    )

    # ------------------------------------------------------------------
    # Apply metadata completeness filter
    # ------------------------------------------------------------------
    fully_filtered = [
        ds for ds in organism_filtered if check_metadata_completeness(ds)
    ]

    LOG.info(
        "After metadata completeness filter: %d of %d datasets retained.",
        len(fully_filtered),
        len(organism_filtered),
    )

    # ------------------------------------------------------------------
    # Persist filtered list
    # ------------------------------------------------------------------
    output_path = paths.outputs("filtered_datasets.json")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8") as f:
        json.dump(fully_filtered, f, indent=2)

    LOG.info("Filtered dataset list written to %s.", output_path)

    return fully_filtered

# ----------------------------------------------------------------------
# CLI entry point
# ----------------------------------------------------------------------
def main() -> None:
    """
    Command‑line interface for the filtering step.

    Optional arguments:
      --organisms  Comma‑separated list of organism identifiers to keep.
    """
    parser = argparse.ArgumentParser(
        description="Filter GEO/ENCODE discovery results for supported model organisms "
        "and required fluctuation metadata."
    )
    parser.add_argument(
        "--organisms",
        type=str,
        default=",".join(DEFAULT_ORGANISMS),
        help="Comma‑separated list of organism substrings to retain (default: mouse, C. elegans, Drosophila).",
    )
    args = parser.parse_args()

    organism_list = [org.strip() for org in args.organisms.split(",") if org.strip()]

    LOG.info("Starting T011 filtering with organisms: %s", organism_list)
    run_discovery(allowed_organisms=organism_list)

if __name__ == "__main__":
    main()
