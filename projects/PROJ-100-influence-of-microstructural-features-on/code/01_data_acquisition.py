def generate_synthetic_data(n_records: int = 150, seed: int = 42) -> Tuple[Dict[str, Any], str]:
    """
    Generate synthetic aluminum alloy fatigue data based on T008 schema.
    Returns (data_dict, source_type).
    """
    set_seed(seed)
    config = load_synthetic_config()
    
    logger = get_main_logger()
    logger.info(f"Generating {n_records} synthetic records with seed {seed}")
    
    # Extract parameters
    grain_mean = config.get('grain_size', {}).get('mean', 25.0)
    grain_std = config.get('grain_size', {}).get('std', 8.0)
    secondary_mean = config.get('secondary_phase', {}).get('mean', 5.0)
    secondary_std = config.get('secondary_phase', {}).get('std', 1.5)
    dislocation_mean = config.get('dislocation_proxy', {}).get('mean', 120.0)
    dislocation_std = config.get('dislocation_proxy', {}).get('std', 30.0)
    fatigue_mean = config.get('fatigue_life', {}).get('mean', 1e5)
    fatigue_std = config.get('fatigue_life', {}).get('std', 2e4)
    
    # Generate batches and groups
    n_batches = 10
    n_groups = 5
    batch_ids = [f"batch_{i:02d}" for i in range(n_batches)]
    group_ids = [f"group_{i:02d}" for i in range(n_groups)]
    
    data = {
        'sample_id': [],
        'alloy_batch_id': [],
        'heat_treatment_group': [],
        'grain_size_um': [],
        'secondary_phase_pct': [],
        'dislocation_density_proxy': [],
        'fatigue_life_cycles': []
    }
    
    for i in range(n_records):
        data['sample_id'].append(f"sample_{i:04d}")
        data['alloy_batch_id'].append(random.choice(batch_ids))
        data['heat_treatment_group'].append(random.choice(group_ids))
        data['grain_size_um'].append(max(0.1, random.gauss(grain_mean, grain_std)))
        data['secondary_phase_pct'].append(max(0.0, random.gauss(secondary_mean, secondary_std)))
        data['dislocation_density_proxy'].append(max(0.0, random.gauss(dislocation_mean, dislocation_std)))
        # Fatigue life is somewhat correlated with grain size (Hall-Petch effect approximation)
        fatigue_val = fatigue_mean * (1.0 - 0.02 * (data['grain_size_um'][-1] - grain_mean)) + random.gauss(0, fatigue_std)
        data['fatigue_life_cycles'].append(max(1000, fatigue_val))
        
    return data, "synthetic"

