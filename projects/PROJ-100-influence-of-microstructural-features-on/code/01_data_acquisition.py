def validate_data(data: Dict[str, Any], source_type: str) -> bool:
    """
    Validate that data meets statistical properties and column requirements.
    Logs percentage of missing microstructural features.
    """
    logger = get_main_logger()
    required_cols = ['sample_id', 'alloy_batch_id', 'heat_treatment_group', 
                     'grain_size_um', 'secondary_phase_pct', 'dislocation_density_proxy', 
                     'fatigue_life_cycles']
    
    # Check columns
    missing_cols = [c for c in required_cols if c not in data]
    if missing_cols:
        logger.error(f"Missing required columns: {missing_cols}")
        return False
        
    # Check row count
    n_rows = len(data['sample_id'])
    if n_rows < 100:
        logger.error(f"Insufficient records: {n_rows} < 100")
        return False
        
    # Check missing values in microstructural features
    micro_cols = ['grain_size_um', 'secondary_phase_pct', 'dislocation_density_proxy']
    total_cells = n_rows * len(micro_cols)
    missing_cells = 0
    for col in micro_cols:
        for val in data[col]:
            if val is None or (isinstance(val, float) and np.isnan(val)):
                missing_cells += 1
                
    missing_pct = (missing_cells / total_cells) * 100
    logger.info(f"Missing microstructural features: {missing_pct:.2f}%")
    
    if missing_pct >= 20:
        logger.warning(f"Missing features ({missing_pct:.2f}%) >= 20% threshold (FR-003)")
        # Not failing here, just logging. T014 handles exclusion.
        
    logger.info(f"Validation passed for {n_rows} records from {source_type}")
    return True

def clean_and_impute_data(data: Dict[str, Any]) -> Tuple[Dict[str, Any], str]:
    """
    Clean and impute data.
    - Remove records with missing fatigue cycles or unverified microstructure.
    - If missing microstructural features < 20% of remaining, impute with median.
    - Else exclude record.
    """
    logger = get_main_logger()
    exclusion_logger = get_exclusion_logger()
    
    # Convert to list of dicts for easier processing
    records = []
    keys = list(data.keys())
    for i in range(len(data['sample_id'])):
        record = {k: data[k][i] for k in keys}
        records.append(record)
        
    cleaned_records = []
    excluded_count = 0
    imputed_count = 0
    
    for i, record in enumerate(records):
        # Check for missing fatigue life
        if record['fatigue_life_cycles'] is None or (isinstance(record['fatigue_life_cycles'], float) and np.isnan(record['fatigue_life_cycles'])):
            exclusion_logger.warning(f"Excluding sample {record['sample_id']}: missing fatigue life")
            excluded_count += 1
            continue
            
        # Check microstructural features
        micro_cols = ['grain_size_um', 'secondary_phase_pct', 'dislocation_density_proxy']
        missing_micro = sum(1 for col in micro_cols if record[col] is None or (isinstance(record[col], float) and np.isnan(record[col])))
        
        if missing_micro == 3:
            exclusion_logger.warning(f"Excluding sample {record['sample_id']}: all microstructural features missing")
            excluded_count += 1
            continue
            
        if missing_micro > 0:
            # Impute missing values with median
            imputed_count += missing_micro
            for col in micro_cols:
                if record[col] is None or (isinstance(record[col], float) and np.isnan(record[col])):
                    # Calculate median from non-missing values
                    vals = [r[col] for r in records if r[col] is not None and not (isinstance(r[col], float) and np.isnan(r[col]))]
                    if vals:
                        record[col] = np.median(vals)
                    else:
                        # Fallback to 0 if no data (shouldn't happen if we have >=100 records)
                        record[col] = 0.0
                        
        cleaned_records.append(record)
        
    log_exclusion(f"Excluded {excluded_count} records, imputed {imputed_count} values")
    
    # Convert back to dict
    cleaned_data = {k: [r[k] for r in cleaned_records] for k in keys}
    return cleaned_data, f"Excluded {excluded_count}, Imputed {imputed_count}"

