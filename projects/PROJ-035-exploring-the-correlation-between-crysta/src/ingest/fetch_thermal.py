"""
Fetch thermal conductivity data for perovskites from verified peer-reviewed literature or NIST repositories.

This module implements T014b: Load thermal conductivity values exclusively from NIST Materials Data 
Repository or verified peer-reviewed literature CSVs. It MUST fail loudly if the source is unreachable 
or invalid; NO synthetic fallback is allowed.

Dependencies:
- T041 (Constitution alignment check)
- T005b (metadata generation)

Output: data/raw/thermal_raw.csv
"""
import os
import sys
import argparse
import logging
import json
from pathlib import Path
from typing import Optional, List, Dict, Any
import pandas as pd
import requests
import yaml

# Add project root to path for imports
project_root = Path(__file__).parent.parent.parent
sys.path.insert(0, str(project_root))

from src.config.env import load_api_key, setup_logger
from src.utils.validation import setup_logger as setup_validation_logger, handle_error
from src.utils.metadata import get_thermal_data_version
from src.ingest.verify_constitution_alignment import check_research_md

# Constants
NIST_DATA_URL = "https://materialsdata.nist.gov/bitstream/handle/11115/179/Thermal%20Conductivity%20of%20Perovskites.csv"
VERIFIED_LITERATURE_URL = "https://raw.githubusercontent.com/materialsproject/perovskite-thermal-data/main/thermal_conductivity_peer_reviewed.csv"
OUTPUT_PATH = project_root / "data" / "raw" / "thermal_raw.csv"
METADATA_PATH = project_root / "data" / "metadata.yaml"
RESEARCH_MD_PATH = project_root / "research.md"

logger = setup_validation_logger("fetch_thermal", logging.INFO)

def check_constitution_alignment() -> bool:
    """
    Verify that Constitution VII has been amended or aligned with FR-010.
    Calls T041 verification logic.
    
    Returns:
        bool: True if alignment is confirmed, False otherwise.
    """
    try:
        result = check_research_md(RESEARCH_MD_PATH)
        if result:
            logger.info("Constitution VII alignment verified in research.md")
            return True
        else:
            logger.error("Constitution VII alignment NOT found in research.md")
            return False
    except Exception as e:
        logger.error(f"Error checking Constitution alignment: {e}")
        return False

def check_metadata_generation() -> bool:
    """
    Verify that metadata.yaml has been generated by T005b.
    
    Returns:
        bool: True if metadata file exists and is valid, False otherwise.
    """
    if not METADATA_PATH.exists():
        logger.error(f"Metadata file not found at {METADATA_PATH}. Run T005b first.")
        return False
    
    try:
        with open(METADATA_PATH, 'r') as f:
            metadata = yaml.safe_load(f)
        if 'thermal_data' not in metadata:
            logger.error("Metadata file does not contain 'thermal_data' section.")
            return False
        logger.info("Metadata file verified successfully.")
        return True
    except Exception as e:
        logger.error(f"Error reading metadata file: {e}")
        return False

def fetch_from_nist() -> Optional[pd.DataFrame]:
    """
    Fetch thermal conductivity data from NIST Materials Data Repository.
    
    Returns:
        pd.DataFrame: DataFrame with thermal conductivity data, or None if fetch fails.
    """
    logger.info(f"Attempting to fetch data from NIST: {NIST_DATA_URL}")
    try:
        response = requests.get(NIST_DATA_URL, timeout=30)
        response.raise_for_status()
        df = pd.read_csv(pd.io.common.StringIO(response.text))
        logger.info(f"Successfully fetched {len(df)} rows from NIST")
        return df
    except requests.exceptions.RequestException as e:
        logger.error(f"Failed to fetch from NIST: {e}")
        return None
    except Exception as e:
        logger.error(f"Error processing NIST data: {e}")
        return None

def fetch_from_verified_literature() -> Optional[pd.DataFrame]:
    """
    Fetch thermal conductivity data from verified peer-reviewed literature CSV.
    
    Returns:
        pd.DataFrame: DataFrame with thermal conductivity data, or None if fetch fails.
    """
    logger.info(f"Attempting to fetch data from verified literature: {VERIFIED_LITERATURE_URL}")
    try:
        response = requests.get(VERIFIED_LITERATURE_URL, timeout=30)
        response.raise_for_status()
        df = pd.read_csv(pd.io.common.StringIO(response.text))
        logger.info(f"Successfully fetched {len(df)} rows from verified literature")
        return df
    except requests.exceptions.RequestException as e:
        logger.error(f"Failed to fetch from verified literature: {e}")
        return None
    except Exception as e:
        logger.error(f"Error processing verified literature data: {e}")
        return None

def validate_thermal_data(df: pd.DataFrame) -> bool:
    """
    Validate that the fetched thermal data has required columns and valid entries.
    
    Required columns: structure_id, thermal_conductivity, source_reference, chemistry_class, temperature
    
    Args:
        df: DataFrame to validate
        
    Returns:
        bool: True if valid, False otherwise.
    """
    required_columns = ['structure_id', 'thermal_conductivity', 'source_reference', 'chemistry_class', 'temperature']
    missing_columns = [col for col in required_columns if col not in df.columns]
    
    if missing_columns:
        logger.error(f"Missing required columns: {missing_columns}")
        return False
    
    # Check for null values in critical columns
    critical_nulls = df[['structure_id', 'thermal_conductivity', 'source_reference']].isnull().any().sum()
    if critical_nulls > 0:
        logger.warning(f"Found {critical_nulls} null values in critical columns")
    
    # Check for valid thermal conductivity values
    invalid_thermal = df[df['thermal_conductivity'] <= 0]
    if len(invalid_thermal) > 0:
        logger.warning(f"Found {len(invalid_thermal)} rows with non-positive thermal conductivity")
    
    return True

def load_thermal_data() -> pd.DataFrame:
    """
    Main function to load thermal conductivity data from verified sources.
    
    Tries sources in order: NIST, then verified literature.
    Fails loudly if all sources are unreachable or data is invalid.
    
    Returns:
        pd.DataFrame: Validated thermal conductivity data.
        
    Raises:
        RuntimeError: If no valid data source is available.
    """
    # Check prerequisites
    if not check_constitution_alignment():
        raise RuntimeError("Constitution VII alignment check failed. Cannot proceed.")
    
    if not check_metadata_generation():
        raise RuntimeError("Metadata generation check failed. Cannot proceed.")
    
    # Try NIST first
    df = fetch_from_nist()
    if df is not None and validate_thermal_data(df):
        logger.info("Using NIST data source")
        return df
    
    # Try verified literature
    df = fetch_from_verified_literature()
    if df is not None and validate_thermal_data(df):
        logger.info("Using verified literature data source")
        return df
    
    # If we get here, all sources failed
    raise RuntimeError("All thermal data sources failed. Cannot proceed without valid data.")

def fetch_perovskite_thermal_data(seed: Optional[int] = None) -> pd.DataFrame:
    """
    Main entry point for fetching perovskite thermal conductivity data.
    
    Args:
        seed: Random seed for deterministic operations (not used in this fetch, but required for API consistency)
        
    Returns:
        pd.DataFrame: Validated thermal conductivity data for perovskites.
    """
    if seed is not None:
        logger.info(f"Seed provided: {seed} (not used in data fetching)")
    
    df = load_thermal_data()
    
    # Add metadata columns
    df['source_reference'] = df['source_reference'].astype(str)
    df['data_version'] = get_thermal_data_version()
    df['fetch_timestamp'] = pd.Timestamp.now().isoformat()
    
    return df

def main():
    """Main execution function for the thermal data fetch script."""
    parser = argparse.ArgumentParser(description="Fetch thermal conductivity data for perovskites")
    parser.add_argument('--seed', type=int, default=42, help="Random seed for deterministic operations")
    parser.add_argument('--output', type=str, default=str(OUTPUT_PATH), help="Output file path")
    args = parser.parse_args()
    
    try:
        logger.info("Starting thermal conductivity data fetch")
        
        # Fetch data
        df = fetch_perovskite_thermal_data(seed=args.seed)
        
        # Ensure output directory exists
        output_path = Path(args.output)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        
        # Save to CSV
        df.to_csv(output_path, index=False)
        logger.info(f"Successfully saved {len(df)} rows to {output_path}")
        
        # Verify output
        if not output_path.exists():
            raise RuntimeError(f"Output file was not created at {output_path}")
        
        saved_df = pd.read_csv(output_path)
        if len(saved_df) == 0:
            raise RuntimeError("Output file is empty")
        
        logger.info("Data fetch and save completed successfully")
        return 0
        
    except Exception as e:
        logger.error(f"Fatal error: {e}")
        handle_error(e)
        return 1

if __name__ == "__main__":
    sys.exit(main())
