"""
Script to identify the optimal threshold from sensitivity analysis results
and generate the decision boundary model artifact.

This task (T030) reads the threshold sweep results generated by T031,
selects the optimal threshold based on the FNR constraint (<= 0.1%),
and saves the model weights and identified thresholds to models/decision_boundary.pkl.
"""

import os
import json
import pickle
import sys
from pathlib import Path
from typing import Dict, Any, Optional

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(project_root))

from scripts.train_model import load_features
from scripts.sensitivity_analysis import load_model_and_features


def load_threshold_sweep(sweep_path: Path) -> Dict[str, Any]:
    """Load the threshold sweep results from JSON."""
    if not sweep_path.exists():
        raise FileNotFoundError(f"Threshold sweep file not found: {sweep_path}")
    
    with open(sweep_path, 'r') as f:
        return json.load(f)


def identify_optimal_threshold(sweep_results: Dict[str, Any]) -> Optional[float]:
    """
    Identify the optimal threshold from the sweep results.
    
    Criteria:
    - Select the threshold with the lowest FNR that satisfies FNR <= 0.001 (0.1%)
    - If no threshold meets the constraint, select the one with the minimum achievable FNR
    """
    threshold_data = sweep_results.get("thresholds", {})
    if not threshold_data:
        raise ValueError("No threshold data found in sweep results")
    
    # Convert threshold keys to floats and sort by FNR
    sorted_thresholds = sorted(
        threshold_data.items(),
        key=lambda x: x[1].get("fnr", float('inf'))
    )
    
    optimal_threshold = None
    min_fnr = float('inf')
    
    for threshold_str, data in sorted_thresholds:
        try:
            threshold = float(threshold_str)
            fnr = data.get("fnr", float('inf'))
            
            # Check if this threshold meets the safety constraint
            if fnr <= 0.001:  # 0.1%
                optimal_threshold = threshold
                break
            else:
                # Track the minimum achievable FNR if constraint not met
                if fnr < min_fnr:
                    min_fnr = fnr
                    optimal_threshold = threshold
        except (ValueError, TypeError):
            continue
    
    return optimal_threshold


def save_decision_boundary(model_path: Path, optimal_threshold: float, 
                           sweep_results: Dict[str, Any]) -> None:
    """
    Save the decision boundary model artifact.
    
    The artifact contains:
    - Model weights (loaded from the trained model)
    - Identified optimal threshold
    - Safety status (safe/unsafe)
    - All threshold sweep data for reference
    """
    # Load the trained model (Random Forest is the primary model per T029)
    model, features = load_model_and_features()
    
    # Determine safety status
    min_fnr = sweep_results.get("min_achievable_fnr", float('inf'))
    is_safe = min_fnr <= 0.001
    
    decision_boundary = {
        "optimal_threshold": optimal_threshold,
        "safety_status": "safe" if is_safe else "unsafe",
        "min_achievable_fnr": min_fnr,
        "thresholds_evaluated": sweep_results.get("thresholds", {}),
        "model_type": type(model).__name__,
        "feature_columns": list(features.columns) if hasattr(features, 'columns') else [],
        "metadata": {
            "generated_at": "2024",
            "task_id": "T030",
            "description": "Decision boundary model with optimal threshold for static-only classification"
        }
    }
    
    # Ensure the models directory exists
    model_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Save the model artifact
    with open(model_path, 'wb') as f:
        pickle.dump(decision_boundary, f)
    
    print(f"Decision boundary saved to: {model_path}")
    print(f"Optimal threshold: {optimal_threshold}")
    print(f"Safety status: {decision_boundary['safety_status']}")
    if not is_safe:
        print(f"Warning: Minimum achievable FNR ({min_fnr:.4f}) exceeds 0.1% constraint")


def main():
    """Main entry point for T030."""
    project_root = Path(__file__).resolve().parent.parent.parent
    
    # Define paths
    sweep_path = project_root / "data" / "processed" / "threshold_sweep.json"
    model_path = project_root / "models" / "decision_boundary.pkl"
    
    print("Loading threshold sweep results...")
    sweep_results = load_threshold_sweep(sweep_path)
    
    print("Identifying optimal threshold...")
    optimal_threshold = identify_optimal_threshold(sweep_results)
    
    if optimal_threshold is None:
        print("Error: Could not identify an optimal threshold")
        sys.exit(1)
    
    print(f"Optimal threshold identified: {optimal_threshold}")
    
    print("Saving decision boundary model...")
    save_decision_boundary(model_path, optimal_threshold, sweep_results)
    
    print("Task T030 completed successfully.")


if __name__ == "__main__":
    main()
