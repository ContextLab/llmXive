from scripts.checksum_artifacts import calculate_sha256, verify_artifacts, write_checksum_manifest

def get_expected_artifacts() -> Dict[str, List[str]]:
    """
    Returns a mapping of directory roots to expected filenames based on task requirements.
    This ensures we verify the specific artifacts generated by T011, T013, T015, T019, T020, T028.
    """
    return {
        "data/processed": [
            "ground_truth.csv",
            "raw_outcomes.json",
            "features.csv",
            "threshold_sweep.json",
            "model_report.json"
        ],
        "data/graphs": [
            # We cannot list every task_id here, so we verify the directory is populated
            # The verification logic will check for existence of at least one .json file
            "*.json" 
        ],
        "models": [
            "logistic_regression.pkl",
            "random_forest.pkl",
            "decision_boundary.pkl"
        ]
    }

def verify_directory_populated(dir_path: Path, pattern: str) -> bool:
    """Check if a directory contains files matching a glob pattern."""
    if not dir_path.exists():
        return False
    files = list(dir_path.glob(pattern))
    return len(files) > 0

def main():
    """
    Main entry point for T038: Verify all artifacts are checksummed and stored.
    This script performs the verification and generates a manifest of checksums.
    """
    print("Starting Artifact Verification (T038)...")
    
    project_root = Path(__file__).resolve().parent.parent.parent
    expected = get_expected_artifacts()
    verification_results = {}
    all_valid = True

    # 1. Verify existence and calculate checksums for specific files
    for dir_name, file_names in expected.items():
        dir_path = project_root / dir_name
        
        if not dir_path.exists():
            print(f"ERROR: Directory {dir_path} does not exist.")
            all_valid = False
            continue

        for fname in file_names:
            if fname == "*.json":
                # Special handling for directories with dynamic filenames
                if verify_directory_populated(dir_path, "*.json"):
                    verification_results[f"{dir_name}/"] = {
                        "status": "populated",
                        "count": len(list(dir_path.glob("*.json"))),
                        "note": "Directory contains JSON artifacts"
                    }
                    print(f"  [OK] {dir_name}/ contains {len(list(dir_path.glob('*.json')))} JSON files")
                else:
                    print(f"  [FAIL] {dir_name}/ is empty or missing JSON files")
                    all_valid = False
            else:
                file_path = dir_path / fname
                if file_path.exists():
                    checksum = calculate_sha256(file_path)
                    verification_results[f"{dir_name}/{fname}"] = {
                        "status": "verified",
                        "checksum": checksum,
                        "size_bytes": file_path.stat().st_size
                    }
                    print(f"  [OK] {dir_name}/{fname} -> {checksum[:16]}...")
                else:
                    print(f"  [FAIL] Missing artifact: {file_path}")
                    all_valid = False

    # 2. Generate the checksum manifest if all critical checks passed
    if all_valid:
        manifest_path = project_root / "data" / "processed" / "checksum_manifest.json"
        write_checksum_manifest(verification_results, manifest_path)
        print(f"\nManifest written to: {manifest_path}")
        print("T038 Verification: PASSED")
    else:
        print("\nT038 Verification: FAILED - Missing or invalid artifacts detected.")
        sys.exit(1)

if __name__ == "__main__":
    main()
