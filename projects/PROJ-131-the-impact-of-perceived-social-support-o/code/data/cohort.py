import os
import logging
import sys
from pathlib import Path
from typing import Optional, Dict, Any, List
import pandas as pd
import numpy as np

from logger import get_logger
from data.preprocessing import run_preprocessing

# Ensure logging is configured
logger = get_logger(__name__)

def load_preprocessed_data() -> Optional[pd.DataFrame]:
    """
    Loads the preprocessed dataset from the intermediate file generated by preprocessing.py.
    Expected path: data/processed/preprocessed_data.csv
    """
    input_path = Path("data/processed/preprocessed_data.csv")
    if not input_path.exists():
        logger.error(f"E-FILE-NOT-FOUND: Preprocessed data file not found at {input_path}. "
                     "Please run preprocessing.py first.")
        return None
    
    try:
        df = pd.read_csv(input_path)
        logger.info(f"Loaded preprocessed data with {len(df)} rows and {len(df.columns)} columns.")
        return df
    except Exception as e:
        logger.error(f"E-LOAD-ERROR: Failed to load preprocessed data: {e}")
        return None

def filter_critical_missing(df: pd.DataFrame) -> pd.DataFrame:
    """
    Filters the dataset to remove rows with critical missing values.
    Critical variables: harassment_severity, social_support, and at least one mental health outcome
    (depression, anxiety, ptsd).
    """
    critical_cols = ['harassment_severity', 'social_support', 'depression', 'anxiety', 'ptsd']
    
    # Identify rows where at least one critical column is missing
    missing_mask = df[critical_cols].isnull().any(axis=1)
    n_missing = missing_mask.sum()
    
    if n_missing > 0:
        logger.warning(f"W-MISSING-CRITICAL: Dropping {n_missing} rows with missing values in "
                       f"critical variables ({', '.join(critical_cols)}).")
    
    filtered_df = df.dropna(subset=critical_cols)
    logger.info(f"Cohort filtered: {len(df)} -> {len(filtered_df)} rows.")
    return filtered_df

def check_harassment_variance(df: pd.DataFrame) -> bool:
    """
    Ensures harassment_severity has sufficient variance.
    Criteria: SD > 0.5 and N > 30.
    Returns True if criteria met, False otherwise.
    """
    col = 'harassment_severity'
    if col not in df.columns:
        logger.error(f"E-COL-MISSING: Column '{col}' not found in dataset.")
        return False
    
    n = df[col].count()
    std_val = df[col].std()
    
    logger.info(f"Harassment Severity Statistics: N={n}, SD={std_val:.4f}")
    
    if n <= 30:
        logger.error(f"E-LOW-VAR-001: Insufficient sample size for harassment_severity. "
                     f"Required N > 30, found {n}.")
        return False
    
    if std_val <= 0.5:
        logger.error(f"E-LOW-VAR-001: Insufficient variance for harassment_severity. "
                     f"Required SD > 0.5, found {std_val:.4f}.")
        return False
    
    logger.info("Harassment severity variance check passed.")
    return True

def construct_analysis_cohort(df: pd.DataFrame) -> pd.DataFrame:
    """
    Constructs the final analysis cohort by applying filters and checks.
    """
    # Step 1: Filter critical missing values
    cohort = filter_critical_missing(df)
    
    if len(cohort) == 0:
        logger.error("E-EMPTY-COHORT: No rows remaining after filtering critical missing values.")
        return cohort
    
    # Step 2: Check variance
    if not check_harassment_variance(cohort):
        logger.error("F-STOP-VAR: Cohort construction halted due to variance failure.")
        # Return empty or partial cohort to signal failure, but we halt logic upstream
        return cohort 
    
    # Step 3: Select relevant columns for output (optional, but good practice)
    # Keep all columns for now, but ensure we don't drop anything needed for downstream
    return cohort

def save_cohort(cohort: pd.DataFrame, output_path: str = "data/results/analysis_cohort.csv") -> None:
    """
    Saves the analysis cohort to the specified CSV path.
    """
    output_file = Path(output_path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    try:
        cohort.to_csv(output_file, index=False)
        logger.info(f"Analysis cohort saved to {output_file} ({len(cohort)} rows).")
    except Exception as e:
        logger.error(f"E-SAVE-ERROR: Failed to save analysis cohort: {e}")
        raise

def main() -> None:
    """
    Main entry point for cohort construction.
    """
    logger.info("Starting cohort construction (T014).")
    
    # Load preprocessed data
    df = load_preprocessed_data()
    if df is None:
        logger.error("Aborting cohort construction: No preprocessed data available.")
        sys.exit(1)
    
    # Construct cohort
    cohort = construct_analysis_cohort(df)
    
    if len(cohort) == 0:
        logger.error("Aborting: Resulting cohort is empty.")
        sys.exit(1)
    
    # Save the cohort
    output_path = "data/results/analysis_cohort.csv"
    save_cohort(cohort, output_path)
    
    logger.info("Cohort construction completed successfully.")

if __name__ == "__main__":
    main()