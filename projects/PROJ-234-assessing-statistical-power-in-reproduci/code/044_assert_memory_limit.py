"""
Task T044: Assert peak RSS < 7 GB using memory_profiler.

Reads the memory limit from `data/config.yaml` (defaulting to 7GB if not present).
Loads the performance metrics generated by T042 (`data/processed/performance_metrics.json`).
Asserts that the recorded peak RSS does not exceed the limit.
Fails with a clear message if the limit is exceeded.
"""
import json
import os
import sys
import logging
from pathlib import Path
from typing import Dict, Any, Optional

# Configure logging to match project standards
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s %(levelname)s %(name)s %(message)s'
)
logger = logging.getLogger(__name__)

def load_config(config_path: Path) -> Dict[str, Any]:
    """Load configuration from YAML or return defaults."""
    if config_path.exists():
        try:
            import yaml
            with open(config_path, 'r') as f:
                config = yaml.safe_load(f) or {}
            logger.info(f"Loaded config from {config_path}")
            return config
        except Exception as e:
            logger.warning(f"Failed to load config from {config_path}: {e}. Using defaults.")
    
    logger.info("Using default configuration (7GB limit).")
    return {}

def get_memory_limit_gb(config: Dict[str, Any]) -> float:
    """Extract memory limit in GB from config, defaulting to 7.0."""
    # Check nested path: specs -> assumptions -> max_memory_gb
    limit = config.get('specs', {}).get('assumptions', {}).get('max_memory_gb')
    
    if limit is None:
        # Check flat path: max_memory_gb
        limit = config.get('max_memory_gb')
    
    if limit is None:
        limit = 7.0
        logger.warning("No memory limit found in config; defaulting to 7.0 GB.")
    else:
        logger.info(f"Memory limit found in config: {limit} GB")
    
    return float(limit)

def load_performance_metrics(metrics_path: Path) -> Optional[Dict[str, Any]]:
    """Load performance metrics from T042 output."""
    if not metrics_path.exists():
        logger.error(f"Performance metrics file not found: {metrics_path}")
        return None
    
    try:
        with open(metrics_path, 'r') as f:
            data = json.load(f)
        logger.info(f"Loaded performance metrics from {metrics_path}")
        return data
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse JSON in {metrics_path}: {e}")
        return None
    except Exception as e:
        logger.error(f"Failed to read {metrics_path}: {e}")
        return None

def extract_peak_rss_gb(metrics: Dict[str, Any]) -> Optional[float]:
    """
    Extract peak RSS in GB from metrics.
    Handles various structures: raw 'peak_rss_gb', nested 'metrics', or raw bytes conversion.
    """
    # Strategy 1: Look for 'peak_rss_gb' directly
    if 'peak_rss_gb' in metrics:
        return float(metrics['peak_rss_gb'])
    
    # Strategy 2: Look for 'peak_rss' in a 'metrics' or 'results' key
    for key in ['metrics', 'results', 'data']:
        if key in metrics and isinstance(metrics[key], dict):
            val = metrics[key].get('peak_rss_gb')
            if val is not None:
                return float(val)
            # Check for bytes and convert
            val_bytes = metrics[key].get('peak_rss_bytes')
            if val_bytes is not None:
                return float(val_bytes) / (1024 ** 3)

    # Strategy 3: Look for 'peak_rss' directly (bytes)
    if 'peak_rss_bytes' in metrics:
        return float(metrics['peak_rss_bytes']) / (1024 ** 3)
    
    # Strategy 4: Look for 'peak_rss' (bytes) without suffix
    if 'peak_rss' in metrics:
        val = metrics['peak_rss']
        if isinstance(val, (int, float)):
            # Assume bytes if > 1000000 (1MB), otherwise assume GB
            if val > 1000000:
                return float(val) / (1024 ** 3)
            return float(val)

    logger.error("Could not find peak RSS in metrics structure.")
    return None

def main():
    """Main entry point for T044."""
    project_root = Path(__file__).resolve().parent.parent
    config_path = project_root / 'data' / 'config.yaml'
    metrics_path = project_root / 'data' / 'processed' / 'performance_metrics.json'

    logger.info("Starting T044: Memory Limit Assertion")

    # 1. Load Config
    config = load_config(config_path)
    limit_gb = get_memory_limit_gb(config)

    # 2. Load Metrics
    metrics = load_performance_metrics(metrics_path)
    if metrics is None:
        logger.critical("T044 FAILED: Cannot verify memory limit without performance metrics.")
        sys.exit(1)

    # 3. Extract Peak RSS
    peak_rss_gb = extract_peak_rss_gb(metrics)
    if peak_rss_gb is None:
        logger.critical("T044 FAILED: Could not extract peak RSS from performance metrics.")
        sys.exit(1)

    logger.info(f"Peak RSS observed: {peak_rss_gb:.4f} GB")
    logger.info(f"Limit defined: {limit_gb:.4f} GB")

    # 4. Assert
    if peak_rss_gb > limit_gb:
        msg = (
            f"T044 FAILED: Peak RSS ({peak_rss_gb:.4f} GB) exceeded limit ({limit_gb:.4f} GB). "
            f"The pipeline consumed too much memory."
        )
        logger.critical(msg)
        # Print a clear message to stdout as well for immediate visibility
        print(f"\n*** MEMORY LIMIT EXCEEDED ***")
        print(f"Peak RSS: {peak_rss_gb:.4f} GB")
        print(f"Limit:    {limit_gb:.4f} GB")
        print(msg)
        sys.exit(1)
    
    msg = f"T044 PASSED: Peak RSS ({peak_rss_gb:.4f} GB) is within limit ({limit_gb:.4f} GB)."
    logger.info(msg)
    print(f"\n*** MEMORY LIMIT CHECK PASSED ***")
    print(msg)
    sys.exit(0)

if __name__ == '__main__':
    main()
