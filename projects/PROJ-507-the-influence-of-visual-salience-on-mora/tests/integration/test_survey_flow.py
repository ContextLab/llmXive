class TestSurveyFlowIntegration(unittest.TestCase):
    """Integration test suite for the survey data collection pipeline."""

    @classmethod
    def setUpClass(cls):
        """Set up test fixtures."""
        seed_everything(42)
        cls.temp_dir = tempfile.mkdtemp()
        cls.test_stimuli_dir = Path(cls.temp_dir) / "processed"
        cls.test_survey_dir = Path(cls.temp_dir) / "survey"
        cls.test_synth_dir = Path(cls.temp_dir) / "synth"

        # Create directories
        cls.test_stimuli_dir.mkdir(parents=True)
        cls.test_survey_dir.mkdir(parents=True)
        cls.test_synth_dir.mkdir(parents=True)

        # Create mock CSV files for testing if real ones don't exist
        # We write them to the temp directory to avoid polluting the real project
        scenarios_file = cls.test_stimuli_dir / "valid_scenarios.csv"
        variants_file = cls.test_stimuli_dir / "stimulus_variants.csv"

        # Check if real data exists in the project, otherwise use mocks in temp dir
        if not (PROJECT_ROOT / "data" / "processed" / "valid_scenarios.csv").exists():
            # Write mocks to temp dir
            scenarios_file.write_text(MOCK_SCENARIO_CSV)
            variants_file.write_text(MOCK_VARIANTS_CSV)
            cls.use_mock_data = True
        else:
            # Use real data paths but copy to temp for isolation?
            # For this test, we will assume the real data exists or we use the mocks in temp
            # to ensure the logic works. We will point the test functions to the temp dir.
            scenarios_file.write_text(MOCK_SCENARIO_CSV)
            variants_file.write_text(MOCK_VARIANTS_CSV)
            cls.use_mock_data = True

        cls.scenarios_file = scenarios_file
        cls.variants_file = variants_file

    @classmethod
    def tearDownClass(cls):
        """Clean up test fixtures."""
        if os.path.exists(cls.temp_dir):
            shutil.rmtree(cls.temp_dir)

    def _load_sequences(self, sequences_file: Path) -> Dict:
        """Helper to load sequences from JSON."""
        with open(sequences_file, 'r') as f:
            return json.load(f)

    def _load_responses(self, responses_file: Path) -> List[Dict]:
        """Helper to load responses from CSV."""
        with open(responses_file, 'r') as f:
            reader = csv.DictReader(f)
            return list(reader)

    def test_01_load_stimuli(self):
        """Test 1: Verify that stimuli can be loaded from the data directory."""
        try:
            scenarios = load_scenarios(self.scenarios_file)
            variants = load_stimulus_variants(self.variants_file)
            self.assertGreater(len(scenarios), 0, "No scenarios loaded")
            self.assertGreater(len(variants), 0, "No variants loaded")
        except Exception as e:
            self.fail(f"Failed to load stimuli: {e}")

    def test_02_latin_square_generation(self):
        """Test 2: Verify Latin Square generation logic."""
        scenarios = load_scenarios(self.scenarios_file)
        variants = load_stimulus_variants(self.variants_file)
        variant_map = build_variant_map(variants)

        # Generate order for a single participant
        # We need at least 3 scenarios and 3 salience levels for a valid Latin Square
        unique_scenarios = list(scenarios.keys())
        if len(unique_scenarios) < 3:
            self.skipTest("Not enough scenarios for Latin Square test")

        # Generate a sequence
        sequence = generate_latin_square_order(unique_scenarios[:3], list(variant_map[unique_scenarios[0]].keys()))
        
        # Verify structure
        self.assertEqual(len(sequence), 3, "Sequence length should match number of scenarios")
        
        # Verify no duplicate salience levels in the sequence
        saliences = [item['salience_level'] for item in sequence]
        self.assertEqual(len(saliences), len(set(saliences)), "Duplicate salience levels found in sequence")

    def test_03_create_participant_sequences(self):
        """Test 3: Verify creation of sequences for multiple participants."""
        scenarios = load_scenarios(self.scenarios_file)
        variants = load_stimulus_variants(self.variants_file)
        variant_map = build_variant_map(variants)

        num_participants = 5
        participant_ids = [f"PID_{i:03d}" for i in range(num_participants)]

        sequences = create_participant_sequences(participant_ids, variant_map)

        self.assertEqual(len(sequences), num_participants, "Incorrect number of sequences generated")

        # Verify each participant has a unique sequence or valid Latin Square
        for pid, seq in sequences.items():
            self.assertEqual(len(seq), len(scenarios), f"Participant {pid} has incorrect sequence length")
            
            # Check for within-subject constraint
            seen_pairs = set()
            for item in seq:
                pair = (item['scenario_id'], item['salience_level'])
                self.assertNotIn(pair, seen_pairs, f"Participant {pid} has duplicate scenario/salience pair: {pair}")
                seen_pairs.add(pair)

    def test_04_save_sequences(self):
        """Test 4: Verify sequences are saved correctly to JSON."""
        scenarios = load_scenarios(self.scenarios_file)
        variants = load_stimulus_variants(self.variants_file)
        variant_map = build_variant_map(variants)

        participant_ids = ["PID_001", "PID_002"]
        sequences = create_participant_sequences(participant_ids, variant_map)

        output_file = self.test_survey_dir / "test_sequences.json"
        save_survey_sequences(sequences, output_file)

        self.assertTrue(output_file.exists(), "Sequences file not created")
        
        loaded = self._load_sequences(output_file)
        self.assertEqual(len(loaded), 2, "Incorrect number of sequences in saved file")

    def test_05_generate_responses(self):
        """Test 5: Verify synthetic response generation for pipeline validation."""
        scenarios = load_scenarios(self.scenarios_file)
        variants = load_stimulus_variants(self.variants_file)
        variant_map = build_variant_map(variants)

        participant_ids = ["PID_001"]
        sequences = create_participant_sequences(participant_ids, variant_map)
        
        # Generate responses
        responses = generate_synthetic_responses(sequences)
        
        self.assertEqual(len(responses), len(participant_ids) * len(scenarios), "Incorrect number of responses")
        
        # Verify schema
        required_cols = {'participant_id', 'scenario_id', 'salience_level', 'rating', 'timestamp'}
        if responses:
            self.assertTrue(required_cols.issubset(set(responses[0].keys())), "Missing required columns in responses")

    def test_06_save_responses(self):
        """Test 6: Verify responses are saved correctly to CSV."""
        scenarios = load_scenarios(self.scenarios_file)
        variants = load_stimulus_variants(self.variants_file)
        variant_map = build_variant_map(variants)

        participant_ids = ["PID_001"]
        sequences = create_participant_sequences(participant_ids, variant_map)
        responses = generate_synthetic_responses(sequences)

        output_file = self.test_synth_dir / "test_responses.csv"
        save_responses(responses, output_file)

        self.assertTrue(output_file.exists(), "Responses file not created")
        
        loaded = self._load_responses(output_file)
        self.assertEqual(len(loaded), len(responses), "Incorrect number of responses in saved file")

    def test_07_within_subject_constraint_enforcement(self):
        """Test 7: Comprehensive check of the 'never same one twice' constraint."""
        scenarios = load_scenarios(self.scenarios_file)
        variants = load_stimulus_variants(self.variants_file)
        variant_map = build_variant_map(variants)

        # Generate sequences for 10 participants
        participant_ids = [f"PID_{i:03d}" for i in range(10)]
        sequences = create_participant_sequences(participant_ids, variant_map)

        for pid, seq in sequences.items():
            # Check 1: No scenario appears more than once
            scenario_ids = [item['scenario_id'] for item in seq]
            self.assertEqual(len(scenario_ids), len(set(scenario_ids)), 
                             f"Participant {pid} has duplicate scenarios")
            
            # Check 2: No scenario appears with the same salience level twice
            for scenario_id in set(scenario_ids):
                scenario_items = [item for item in seq if item['scenario_id'] == scenario_id]
                saliences = [item['salience_level'] for item in scenario_items]
                self.assertEqual(len(saliences), len(set(saliences)), 
                                 f"Participant {pid} has same scenario {scenario_id} with duplicate salience levels")

    def test_08_data_separation_hygiene(self):
        """Test 8: Verify that synthetic data is stored in the correct directory."""
        # Ensure synthetic responses are in synth dir
        synth_file = self.test_synth_dir / "test_responses.csv"
        if synth_file.exists():
            # Verify it's not in survey dir
            survey_file = self.test_survey_dir / "test_responses.csv"
            self.assertFalse(survey_file.exists(), "Synthetic data found in survey directory")

        # Verify directory structure
        try:
            verify_data_separation(self.test_survey_dir, self.test_synth_dir)
        except DataHygieneError as e:
            self.fail(f"Data separation check failed: {e}")

    def test_09_full_flow_integration(self):
        """Test 9: End-to-end flow from stimuli to responses."""
        # 1. Load
        scenarios = load_scenarios(self.scenarios_file)
        variants = load_stimulus_variants(self.variants_file)
        variant_map = build_variant_map(variants)

        # 2. Generate Sequences
        pids = ["TEST_PID_001", "TEST_PID_002"]
        sequences = create_participant_sequences(pids, variant_map)
        
        # 3. Save Sequences
        seq_file = self.test_survey_dir / "integration_sequences.json"
        save_survey_sequences(sequences, seq_file)

        # 4. Generate Responses
        responses = generate_synthetic_responses(sequences)
        
        # 5. Save Responses
        resp_file = self.test_synth_dir / "integration_responses.csv"
        save_responses(responses, resp_file)

        # 6. Verify Outputs
        self.assertTrue(seq_file.exists(), "Sequences file missing")
        self.assertTrue(resp_file.exists(), "Responses file missing")

        # 7. Verify Content Integrity
        loaded_seqs = self._load_sequences(seq_file)
        loaded_resps = self._load_responses(resp_file)

        self.assertEqual(len(loaded_seqs), 2, "Incorrect sequence count")
        self.assertEqual(len(loaded_resps), 2 * len(scenarios), "Incorrect response count")

        # 8. Verify Constraint in Final Output
        for pid in pids:
            p_resps = [r for r in loaded_resps if r['participant_id'] == pid]
            scenario_salience_pairs = [(r['scenario_id'], r['salience_level']) for r in p_resps]
            self.assertEqual(len(scenario_salience_pairs), len(set(scenario_salience_pairs)),
                             f"Constraint violation in final output for {pid}")


