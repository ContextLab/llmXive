"""
Pipeline script for Task T003 – Process human coding and select ambiguous scenarios.

The script orchestrates the following steps:

1. Load all annotation CSV files produced by ``code/02_acquire_annotations.py``.
2. Compute per‑scenario mean ambiguity score and overall Fleiss' Kappa.
3. Apply the filtering criteria:
   * mean rating ≥ 3.5
   * kappa ≥ ``human_coding.KAPPA_THRESHOLD`` (0.6)
4. Cross‑reference the retained scenario IDs against the external MoralD
   benchmark (``data/external/morald_tags.json``) and write matches to
   ``ground_truth_match.csv``.
5. Join the retained IDs with the original candidate information
   (``candidates_filtered.csv``) to produce ``valid_scenarios.csv`` that
   conforms to ``contracts/dataset.schema.yaml``.

The script aborts with a clear error message if any required input file is
missing, ensuring that downstream steps cannot proceed with incomplete data.
"""

import argparse
import sys
import logging
from pathlib import Path

import pandas as pd

# Local helpers
from human_coding import (
    process_annotations,
    cross_reference_external_validation,
    MIN_ANNOTATORS,
    KAPPA_THRESHOLD,
)
from llmxive_toolkit import paths, get_logger

logger = get_logger(__name__)

def _load_annotation_files(annotations_dir: Path) -> pd.DataFrame:
    """
    Load every ``*.csv`` file inside ``annotations_dir`` and concatenate them
    into a single DataFrame.  The function raises ``FileNotFoundError`` if the
    directory does not exist or contains no CSV files.
    """
    if not annotations_dir.is_dir():
        raise FileNotFoundError(f"Annotations directory not found: {annotations_dir}")

    csv_files = list(annotations_dir.glob("*.csv"))
    if not csv_files:
        raise FileNotFoundError(f"No annotation CSV files found in {annotations_dir}")

    dfs = [pd.read_csv(p) for p in csv_files]
    combined = pd.concat(dfs, ignore_index=True)
    required = {"scenario_id", "annotator_id", "rating"}
    missing = required - set(combined.columns)
    if missing:
        raise ValueError(f"Annotation files are missing required columns: {missing}")
    return combined

def _load_candidates(candidates_path: Path) -> pd.DataFrame:
    """
    Load the candidate CSV generated by ``01_ingest_and_filter.py``.
    The file must contain at least ``scenario_id`` and ``original_image_path``.
    """
    if not candidates_path.is_file():
        raise FileNotFoundError(f"Candidates file not found: {candidates_path}")

    df = pd.read_csv(candidates_path)
    required = {"scenario_id", "original_image_path"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Candidates CSV missing required columns: {missing}")
    return df

def main():
    parser = argparse.ArgumentParser(
        description="Process human coding annotations and select ambiguous scenarios (Task T003)."
    )
    parser.add_argument(
        "--annotations-dir",
        type=str,
        required=True,
        help="Directory containing annotation CSV files produced by T002.",
    )
    parser.add_argument(
        "--candidates-csv",
        type=str,
        required=True,
        help="Path to the candidates CSV (output of T001).",
    )
    parser.add_argument(
        "--valid-output",
        type=str,
        required=True,
        help="Path where the filtered valid scenarios CSV will be written.",
    )
    parser.add_argument(
        "--ground-truth-output",
        type=str,
        required=True,
        help="Path where the ground‑truth match CSV will be written.",
    )
    args = parser.parse_args()

    # Resolve paths via llmxive_toolkit for consistency
    annotations_dir = Path(args.annotations_dir)
    candidates_path = Path(args.candidates_csv)
    valid_output_path = Path(args.valid_output)
    ground_truth_path = Path(args.ground_truth_output)

    # ------------------------------------------------------------------
    # 1. Load raw annotations
    # ------------------------------------------------------------------
    logger.info(f"Loading annotations from {annotations_dir}")
    annotations_df = _load_annotation_files(annotations_dir)

    # ------------------------------------------------------------------
    # 2. Process annotations (majority vote + kappa)
    # ------------------------------------------------------------------
    logger.info("Processing annotations (majority vote, annotator count checks)")
    processed_df, kappa = process_annotations(annotations_df)
    logger.info(f"Overall Fleiss' Kappa = {kappa:.3f}")

    if processed_df.empty:
        logger.error("No scenarios survived the annotation processing step.")
        sys.exit(1)

    # ------------------------------------------------------------------
    # 3. Compute per‑scenario mean rating (using *all* retained ratings)
    # ------------------------------------------------------------------
    # Merge the original (filtered‑by‑annotator‑count) annotations back
    # to compute the mean rating per scenario.
    sufficient_scenarios = processed_df["scenario_id"].unique()
    filtered_annotations = annotations_df[
        annotations_df["scenario_id"].isin(sufficient_scenarios)
    ]
    mean_ratings = (
        filtered_annotations.groupby("scenario_id")["rating"]
        .mean()
        .reset_index()
        .rename(columns={"rating": "mean_rating"})
    )

    # ------------------------------------------------------------------
    # 4. Apply the ambiguity thresholds
    # ------------------------------------------------------------------
    logger.info(
        f"Applying thresholds: mean rating >= 3.5 and kappa >= {KAPPA_THRESHOLD}"
    )
    if kappa < KAPPA_THRESHOLD:
        logger.error(
            f"Fleiss' Kappa ({kappa:.3f}) is below the required threshold "
            f"({KAPPA_THRESHOLD}). No scenarios will be retained."
        )
        sys.exit(1)

    retained = mean_ratings[mean_ratings["mean_rating"] >= 3.5]
    retained_ids = retained["scenario_id"].tolist()
    logger.info(f"{len(retained_ids)} scenarios passed the mean‑rating filter.")

    # ------------------------------------------------------------------
    # 5. Cross‑reference with external MoralD benchmark
    # ------------------------------------------------------------------
    external_json = Path("data/external/morald_tags.json")
    logger.info(f"Cross‑referencing with external benchmark {external_json}")
    ambiguous_ids = cross_reference_external_validation(
        retained_ids, str(external_json)
    )
    logger.info(
        f"{len(ambiguous_ids)} scenarios remain after external validation."
    )

    # ------------------------------------------------------------------
    # 6. Write ground‑truth match CSV
    # ------------------------------------------------------------------
    gt_df = pd.DataFrame({"scenario_id": ambiguous_ids})
    gt_df.to_csv(ground_truth_path, index=False)
    logger.info(f"Wrote ground‑truth matches to {ground_truth_path}")

    # ------------------------------------------------------------------
    # 7. Join with original candidate information and write valid CSV
    # ------------------------------------------------------------------
    candidates_df = _load_candidates(candidates_path)
    valid_df = candidates_df[
        candidates_df["scenario_id"].isin(ambiguous_ids)
    ].copy()
    if valid_df.empty:
        logger.error(
            "No valid scenarios left after all filtering steps. "
            "Check the thresholds and the external benchmark."
        )
        sys.exit(1)

    valid_df.to_csv(valid_output_path, index=False)
    logger.info(f"Wrote valid scenarios to {valid_output_path}")

if __name__ == "__main__":
    main()
