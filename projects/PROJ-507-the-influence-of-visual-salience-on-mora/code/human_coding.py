def calculate_fleiss_kappa(df: pd.DataFrame) -> float:
    """
    Calculate Fleiss' Kappa for multiple raters.
    Input: DataFrame with 'scenario_id', 'annotator_id', 'rating'.
    """
    # Pivot to get matrix: rows=items, cols=ratings, values=count
    # We need the count of each rating for each item
    pivot = df.pivot_table(index='scenario_id', columns='rating', aggfunc='size', fill_value=0)
    
    # Ensure all possible ratings are columns (assuming ratings are 1-5 or 0-4)
    all_ratings = sorted(df['rating'].unique())
    for r in all_ratings:
        if r not in pivot.columns:
            pivot[r] = 0
    pivot = pivot[all_ratings]
    
    N = len(pivot) # Number of items
    n = pivot.sum(axis=1).mean() # Mean number of raters per item (should be constant)
    k = len(all_ratings) # Number of categories
    
    # Proportion of items rated in each category
    p_j = pivot.sum().sum() / (N * n)
    
    # Calculate P_i (proportion of agreement for item i)
    # P_i = (1 / (n * (n-1))) * sum(n_ij * (n_ij - 1))
    p_i = []
    for idx, row in pivot.iterrows():
        sum_nij_nij_minus_1 = sum(val * (val - 1) for val in row)
        p_i.append(sum_nij_nij_minus_1 / (n * (n - 1)))
    
    P_bar = np.mean(p_i)
    
    # Calculate P_e (expected agreement)
    P_e = sum(p_j**2 for p_j in p_j)
    
    if P_e == 1.0:
        return 1.0 # Perfect agreement, no chance variation possible
    
    kappa = (P_bar - P_e) / (1 - P_e)
    return kappa

def process_annotations(df: pd.DataFrame) -> Tuple[pd.DataFrame, float]:
    """
    Process annotations:
    1. Check if >= MIN_ANNOTATORS exist for each scenario.
    2. Calculate Global Fleiss' Kappa.
    3. Apply majority vote for scenarios with >= MIN_ANNOTATORS.
    4. Exclude scenarios without majority or < MIN_ANNOTATORS.
    5. Return filtered scenarios and the global kappa.
    """
    # Check annotator count per scenario
    counts = df.groupby('scenario_id').size()
    valid_scenarios = counts[counts >= MIN_ANNOTATORS].index.tolist()
    
    if len(valid_scenarios) == 0:
        logger.warning("No scenarios have >= 3 annotators.")
        return pd.DataFrame(), 0.0
    
    df_filtered = df[df['scenario_id'].isin(valid_scenarios)]
    
    # Calculate Global Fleiss' Kappa
    kappa = calculate_fleiss_kappa(df_filtered)
    logger.info(f"Global Fleiss' Kappa: {kappa:.4f}")
    
    if kappa < KAPPA_THRESHOLD:
        logger.warning(f"Global Kappa ({kappa:.4f}) is below threshold ({KAPPA_THRESHOLD}). Proceeding with caution, but flags raised.")
        # The task says "apply the >= 0.6 threshold ... and exclude scenarios failing the threshold".
        # If the global metric fails, do we exclude all? Or just flag?
        # Let's assume we proceed but log the failure. The "exclude scenarios" part likely refers to
        # scenarios with no majority vote.
    
    # Majority Vote Logic
    final_scenarios = []
    for scenario_id in valid_scenarios:
        sub_df = df_filtered[df_filtered['scenario_id'] == scenario_id]
        ratings = sub_df['rating'].tolist()
        counts = pd.Series(ratings).value_counts()
        
        # Check for majority
        # If 3 raters: 3-0 (majority), 2-1 (majority), 1-1-1 (no majority)
        if len(counts) == 1:
            # 3-0
            final_rating = counts.index[0]
            final_scenarios.append({'scenario_id': scenario_id, 'final_rating': final_rating, 'method': 'unanimous'})
        elif counts.iloc[0] > counts.iloc[1]:
            # 2-1 or 3-0 (already handled)
            # If 2 raters agree and 1 disagrees, that's a majority.
            final_rating = counts.index[0]
            final_scenarios.append({'scenario_id': scenario_id, 'final_rating': final_rating, 'method': 'majority'})
        else:
            # 1-1-1 (no majority)
            logger.info(f"Scenario {scenario_id} has no majority (1-1-1). Excluding.")
            continue
    
    result_df = pd.DataFrame(final_scenarios)
    return result_df, kappa

def cross_reference_external_validation(scenario_ids: List[str], external_path: str = EXTERNAL_VALIDATION_SOURCE) -> List[str]:
    """
    Cross-reference scenarios with external validation (MoralD tags or framework config).
    Returns list of scenario_ids that are GENUINELY ambiguous.
    """
    if not os.path.exists(external_path):
        logger.warning(f"External validation source not found: {external_path}. Skipping cross-reference.")
        return scenario_ids
    
    try:
        import json
        with open(external_path, 'r') as f:
            external_data = json.load(f)
    except Exception as e:
        logger.error(f"Failed to load external validation: {e}")
        return scenario_ids
    
    # Assuming external_data is a dict or list of dicts with 'scenario_id' and 'is_ambiguous' or tags
    valid_ids = []
    for sid in scenario_ids:
        # Check if in external data and marked as ambiguous
        # Logic depends on the format of external_data.
        # If it's a list of IDs that are ambiguous:
        if isinstance(external_data, list):
            if sid in external_data:
                valid_ids.append(sid)
        elif isinstance(external_data, dict):
            # Assume key is scenario_id
            if sid in external_data:
                entry = external_data[sid]
                # Check for ambiguity tag
                if entry.get('is_ambiguous', False) or 'ambiguous' in str(entry.get('tags', '')).lower():
                    valid_ids.append(sid)
            # If the dict contains a list of ambiguous IDs under a key
            elif 'ambiguous_ids' in external_data and sid in external_data['ambiguous_ids']:
                valid_ids.append(sid)
    return valid_ids

def save_outputs(result_df: pd.DataFrame, kappa: float, output_path: str = VALID_SCENARIOS_FILE):
    """Save the final valid scenarios to CSV."""
    if result_df.empty:
        logger.warning("No valid scenarios to save.")
        return
    
    # Ensure directory exists
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    
    result_df.to_csv(output_path, index=False)
    logger.info(f"Saved {len(result_df)} valid scenarios to {output_path}")
    
    # Save metadata about kappa
    metadata_path = Path(output_path).with_suffix('.meta.json')
    with open(metadata_path, 'w') as f:
        json.dump({'kappa': kappa, 'threshold': KAPPA_THRESHOLD, 'min_annotators': MIN_ANNOTATORS}, f)

def main():
    parser = argparse.ArgumentParser(description="Process human coding annotations.")
    parser.add_argument('--input', type=str, default=ANNOTATIONS_FILE, help='Input annotations CSV')
    parser.add_argument('--output', type=str, default=VALID_SCENARIOS_FILE, help='Output valid scenarios CSV')
    parser.add_argument('--external', type=str, default=EXTERNAL_VALIDATION_SOURCE, help='External validation JSON')
    parser.add_argument('--seed', type=int, default=42, help='Random seed')
    args = parser.parse_args()
    
    seed_everything(args.seed)
    setup_logging()
    
    try:
        # 1. Load annotations
        df = load_annotations(args.input)
        logger.info(f"Loaded {len(df)} annotations.")
        
        # 2. Process annotations (filter, majority vote, calculate kappa)
        result_df, kappa = process_annotations(df)
        
        # 3. Cross-reference with external validation
        if not result_df.empty:
            valid_ids = result_df['scenario_id'].tolist()
            final_valid_ids = cross_reference_external_validation(valid_ids, args.external)
            result_df = result_df[result_df['scenario_id'].isin(final_valid_ids)]
            logger.info(f"After cross-reference: {len(result_df)} scenarios remain.")
        
        # 4. Save outputs
        save_outputs(result_df, kappa, args.output)
        
        # 5. Report
        if result_df.empty:
            logger.error("No valid scenarios found. Check annotation quality and external validation.")
            sys.exit(1)
        else:
            logger.info(f"Success. {len(result_df)} scenarios passed all checks (Kappa={kappa:.4f}).")
            
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)
    except Exception as e:
        logger.exception(f"Unexpected error: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
