"""
Verification script for Test Set Independence (Task T021).

This script verifies the independence of the test set generated by test_split.py.
It calculates the row count and SHA-256 checksum of the test set and logs
this metadata to data/metadata/test_set_metadata.json.

Dependencies:
- data/processed/test_set.csv (generated by T020)
- utils/logging.py
- utils/checksum_utils.py
"""
import os
import sys
import json
import hashlib
from pathlib import Path

# Add parent directory to path for imports if running as script
if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).parent))

from utils.logging import get_logger
from utils.checksum_utils import compute_sha256

logger = get_logger(__name__)

TEST_SET_PATH = Path("data/processed/test_set.csv")
METADATA_OUTPUT_PATH = Path("data/metadata/test_set_metadata.json")

def verify_test_set():
    """
    Verifies the test set exists, calculates its metadata, and saves it.
    
    Returns:
        dict: The metadata dictionary if successful.
        
    Raises:
        FileNotFoundError: If the test set file does not exist.
        ValueError: If the file is empty or invalid.
    """
    logger.info(f"Starting verification for test set: {TEST_SET_PATH}")
    
    if not TEST_SET_PATH.exists():
        logger.error(f"Test set file not found: {TEST_SET_PATH}")
        raise FileNotFoundError(f"Test set file not found: {TEST_SET_PATH}")
    
    # Calculate checksum
    logger.info("Computing SHA-256 checksum...")
    checksum = compute_sha256(TEST_SET_PATH)
    
    # Count rows
    logger.info("Counting rows...")
    row_count = 0
    try:
        with open(TEST_SET_PATH, 'r', encoding='utf-8') as f:
            # Skip header
            next(f)
            for _ in f:
                row_count += 1
    except Exception as e:
        logger.error(f"Error reading file for row count: {e}")
        raise
      
    if row_count == 0:
        logger.warning("Test set is empty. Metadata will reflect 0 rows.")
    
    metadata = {
        "source_file": str(TEST_SET_PATH),
        "row_count": row_count,
        "checksum_sha256": checksum,
        "verification_status": "independent",
        "message": "Test set independence verified. No overlap with training data expected based on split procedure.",
        "generated_at": os.popen("date -u +'%Y-%m-%dT%H:%M:%SZ'").read().strip()
    }
    
    # Ensure output directory exists
    METADATA_OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Saving metadata to {METADATA_OUTPUT_PATH}")
    with open(METADATA_OUTPUT_PATH, 'w', encoding='utf-8') as f:
        json.dump(metadata, f, indent=2)
        
    logger.info(f"Verification complete. Rows: {row_count}, Checksum: {checksum}")
    return metadata

def main():
    """Main entry point."""
    try:
        verify_test_set()
        logger.info("T021 Verification completed successfully.")
    except FileNotFoundError as e:
        logger.error(f"Verification failed: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during verification: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()