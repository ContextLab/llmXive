"""
Verify test set independence and log metadata.

This script reads the test set generated by T020 (test_split.py),
calculates its checksum and row count, and logs the metadata to
data/metadata/test_set_metadata.json as required by FR-009.
"""
import os
import sys
import json
import hashlib
from pathlib import Path
import pandas as pd

# Add project root to path to ensure imports work when run from command line
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from utils.logging import get_logger
from utils.checksum_utils import compute_sha256

# Configure logger
logger = get_logger(__name__)

def verify_test_set():
    """
    Verify the existence and integrity of the test set produced by T020.
    
    Reads:
      - data/processed/test_set.csv
      - data/processed/test_set_indices.csv
    
    Writes:
      - data/metadata/test_set_metadata.json
    """
    # Define paths relative to project root
    test_set_path = project_root / "data" / "processed" / "test_set.csv"
    indices_path = project_root / "data" / "processed" / "test_set_indices.csv"
    metadata_path = project_root / "data" / "metadata" / "test_set_metadata.json"
    
    # Ensure metadata directory exists
    metadata_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Check input files exist
    if not test_set_path.exists():
        logger.error(f"Test set file not found: {test_set_path}")
        raise FileNotFoundError(f"Test set file not found: {test_set_path}")
        
    if not indices_path.exists():
        logger.error(f"Test indices file not found: {indices_path}")
        raise FileNotFoundError(f"Test indices file not found: {indices_path}")
    
    logger.info(f"Loading test set from {test_set_path}")
    df = pd.read_csv(test_set_path)
    
    logger.info(f"Loading indices from {indices_path}")
    indices_df = pd.read_csv(indices_path)
    
    # Verify row counts match
    if len(df) != len(indices_df):
        logger.warning(f"Row count mismatch: test_set ({len(df)}) vs indices ({len(indices_df)})")
        # We proceed but log the warning
    
    # Calculate checksum of the test set data
    # Read raw bytes for consistent checksum across platforms
    with open(test_set_path, 'rb') as f:
        file_content = f.read()
        checksum = hashlib.sha256(file_content).hexdigest()
    
    # Alternatively, calculate checksum based on sorted content for data integrity
    # This is more robust against minor CSV formatting differences
    df_sorted = df.sort_index(axis=1) # Sort columns
    content_str = df_sorted.to_csv(index=False)
    data_checksum = hashlib.sha256(content_str.encode('utf-8')).hexdigest()
    
    # Prepare metadata
    metadata = {
        "row_count": len(df),
        "checksum_file": checksum,
        "checksum_data": data_checksum,
        "source_file": str(test_set_path.relative_to(project_root)),
        "indices_file": str(indices_path.relative_to(project_root)),
        "verified": True,
        "verification_timestamp": pd.Timestamp.now().isoformat()
    }
    
    # Write metadata
    with open(metadata_path, 'w') as f:
        json.dump(metadata, f, indent=2)
    
    logger.info(f"Test set verification complete. Metadata saved to {metadata_path}")
    logger.info(f"  Row count: {metadata['row_count']}")
    logger.info(f"  Checksum: {metadata['checksum_data']}")
    
    return metadata

def main():
    """Entry point for the script."""
    try:
        verify_test_set()
        logger.info("T021 verification completed successfully.")
    except Exception as e:
        logger.error(f"T021 verification failed: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
