import sys
from pathlib import Path

# Add project root to path to allow relative imports if run as script
project_root = Path(__file__).parent
sys.path.insert(0, str(project_root))

from utils.logging import get_logger
from utils.checksum_utils import generate_and_save_checksum

logger = get_logger(__name__)

def main():
    """
    T028: Save cleaned full pool to data/processed/full_pool_final.csv 
    with SHA-256 checksum generation.
    
    This script assumes the file 'data/processed/full_pool_final.csv' 
    has already been generated by T027 (impute_and_finalize).
    It verifies existence and generates the checksum file.
    """
    # Define paths relative to project root
    input_file = project_root / "data" / "processed" / "full_pool_final.csv"
    
    # Verify input file exists before proceeding
    if not input_file.exists():
        logger.error(f"Input file not found: {input_file}")
        logger.error("T027 (impute_and_finalize) must be run before T028.")
        sys.exit(1)
    
    logger.info(f"Processing checksum for: {input_file}")
    
    # Generate and save checksum
    # The utility function expects a Path object
    checksum_path = generate_and_save_checksum(input_file)
    
    logger.info(f"Checksum successfully generated and saved to: {checksum_path}")
    
    # Log success for the task requirement
    logger.info("T028 Task Complete: full_pool_final.csv checksum generated.")

if __name__ == "__main__":
    main()
