def load_metrics(metrics_path: Optional[str] = None) -> pd.DataFrame:
    """
    Load metrics from the CSV file generated by model_training.py.
    Default path: data/results/metrics.csv
    """
    if metrics_path is None:
        metrics_path = str(RESULTS_DIR / "metrics.csv")
    
    if not os.path.exists(metrics_path):
        raise FileNotFoundError(f"Metrics file not found at {metrics_path}")
    
    logger.info(f"Loading metrics from {metrics_path}")
    df = pd.read_csv(metrics_path)
    return df

def calculate_learning_curve_stats(metrics: pd.DataFrame) -> pd.DataFrame:
    """
    Calculate mean and std error for each sparsity level.
    """
    if 'sparsity_level' not in metrics.columns or 'rmse' not in metrics.columns:
        raise ValueError("Metrics DataFrame must contain 'sparsity_level' and 'rmse' columns")
    
    stats_df = metrics.groupby('sparsity_level')['rmse'].agg(['mean', 'std', 'count']).reset_index()
    stats_df.columns = ['sparsity_level', 'mean_rmse', 'std_rmse', 'n_samples']
    stats_df['stderr'] = stats_df['std_rmse'] / np.sqrt(stats_df['n_samples'])
    return stats_df

def plot_learning_curve(stats_df: pd.DataFrame, output_path: Optional[str] = None) -> str:
    """
    Generate learning curve plot: Error vs. Dataset Size (Sparsity Level).
    """
    if output_path is None:
        output_path = str(PLOTS_DIR / "learning_curve.png")
    
    PLOTS_DIR.mkdir(parents=True, exist_ok=True)
    
    plt.figure(figsize=(10, 6))
    sns.lineplot(
        data=stats_df, 
        x='sparsity_level', 
        y='mean_rmse', 
        yerr='stderr',
        marker='o',
        linewidth=2,
        markersize=8
    )
    plt.title('Learning Curve: RMSE vs. Dataset Sparsity Level', fontsize=14)
    plt.xlabel('Sparsity Level (%)', fontsize=12)
    plt.ylabel('RMSE (Formation Energy)', fontsize=12)
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(output_path, dpi=300)
    plt.close()
    
    logger.info(f"Learning curve saved to {output_path}")
    return output_path

def perform_lmm_analysis(metrics: pd.DataFrame) -> Any:
    """
    Perform Linear Mixed-Effects Modeling.
    Formula: error ~ sparsity_level + (1|seed)
    """
    try:
        import statsmodels.api as sm
        import statsmodels.formula.api as smf
    except ImportError:
        logger.error("statsmodels is required for LMM analysis. Install with: pip install statsmodels")
        raise

    # Ensure sparsity_level is numeric for the model
    if metrics['sparsity_level'].dtype == 'object':
        # Try to convert to numeric, assuming it represents percentage
        metrics['sparsity_level'] = pd.to_numeric(metrics['sparsity_level'], errors='coerce')
    
    # Drop rows with NaN in critical columns
    clean_data = metrics.dropna(subset=['rmse', 'sparsity_level', 'seed'])
    
    if len(clean_data) == 0:
        raise ValueError("No valid data rows for LMM analysis after cleaning.")

    logger.info(f"Running LMM on {len(clean_data)} samples...")
    
    # Fit model: error ~ sparsity_level + (1|seed)
    # Using 'rmse' as the dependent variable (error)
    model = smf.mixedlm("rmse ~ sparsity_level", clean_data, groups=clean_data["seed"])
    result = model.fit()
    
    logger.info(f"LMM Results:\n{result.summary()}")
    return result

def apply_tukey_posthoc(metrics: pd.DataFrame) -> pd.DataFrame:
    """
    Apply Tukey HSD post-hoc test to compare sparsity levels.
    Returns a DataFrame of pairwise comparisons with p-values.
    """
    try:
        from statsmodels.stats.multicomp import pairwise_tukeyhsd
    except ImportError:
        logger.error("statsmodels is required for Tukey post-hoc. Install with: pip install statsmodels")
        raise

    # Ensure sparsity_level is treated as categorical for Tukey
    tukey_data = metrics[['rmse', 'sparsity_level']].copy()
    tukey_data['sparsity_level'] = tukey_data['sparsity_level'].astype(str)
    
    if tukey_data['sparsity_level'].nunique() < 2:
        logger.warning("Need at least 2 sparsity levels for Tukey test.")
        return pd.DataFrame()

    tukey = pairwise_tukeyhsd(
        endog=tukey_data['rmse'],
        groups=tukey_data['sparsity_level'],
        alpha=0.05
    )
    
    # Convert result to DataFrame
    tukey_df = pd.DataFrame(tukey.summary_frame())
    logger.info("Tukey Post-hoc Test completed.")
    return tukey_df

def generate_summary_statistics(lmm_result: Any, tukey_df: pd.DataFrame) -> Dict[str, Any]:
    """
    Generate a summary dictionary of statistical findings.
    """
    summary = {
        "lmm_fixed_effects": {},
        "lmm_random_effects": {},
        "tukey_significant_pairs": []
    }
    
    if lmm_result is not None:
        # Extract fixed effects
        for name, param in lmm_result.params.items():
            summary["lmm_fixed_effects"][name] = float(param)
        # Extract random effects variance
        if hasattr(lmm_result, 'scale'):
            summary["lmm_random_effects"]["residual_variance"] = float(lmm_result.scale)
        if hasattr(lmm_result, 'cov_re'):
            summary["lmm_random_effects"]["group_variance"] = float(lmm_result.cov_re.iloc[0, 0]) if lmm_result.cov_re.size > 0 else 0.0

    if tukey_df is not None and not tukey_df.empty:
        sig_pairs = tukey_df[tukey_df['reject']]
        for _, row in sig_pairs.iterrows():
            summary["tukey_significant_pairs"].append({
                "group1": row['group1'],
                "group2": row['group2'],
                "diff": float(row['diff']),
                "p_adj": float(row['p-adj'])
            })
    
    return summary

def generate_calibration_plots(metrics: pd.DataFrame, output_dir: Optional[str] = None) -> Tuple[str, str]:
    """
    Generate uncertainty calibration plots:
    1. Calibration Slope: Predicted Variance vs. Squared Residuals
    2. Predicted vs. Squared Residuals scatter with regression line.
    
    Returns paths to the saved plots.
    """
    if output_dir is None:
        output_dir = str(CALIBRATION_DIR)
    
    CALIBRATION_DIR.mkdir(parents=True, exist_ok=True)
    
    # Ensure required columns exist
    required_cols = ['variance', 'rmse', 'sparsity_level']
    missing = [c for c in required_cols if c not in metrics.columns]
    if missing:
        raise ValueError(f"Metrics missing required columns for calibration: {missing}")
    
    # Calculate squared residuals (approximation if 'rmse' is per-sample, 
    # but here 'rmse' is likely an aggregate metric per run. 
    # However, for calibration slope, we need per-prediction variance and error.
    # Assuming the 'metrics.csv' contains per-run aggregates, we cannot do per-point calibration 
    # without the raw predictions. 
    # RE-INTERPRETATION: The task asks for "predicted vs squared residuals". 
    # If the metrics file only has aggregate RMSE, we must use the variance (uncertainty) 
    # of the model predictions (if available per sample) or use the run-level metrics 
    # to check if higher variance correlates with higher error across runs.
    # Given the schema 'metrics.csv' likely has: sparsity_level, model, seed, rmse, variance.
    # We will treat 'variance' as the average predictive variance for that run 
    # and 'rmse' as the error metric. We plot Variance vs RMSE^2 to check calibration.
    
    # Calculate squared error (using RMSE as proxy for error magnitude)
    # Note: Ideally we need per-point (prediction_variance, squared_residual).
    # If the data is aggregate, we plot (avg_variance, rmse^2).
    
    metrics['squared_rmse'] = metrics['rmse'] ** 2
    
    # 1. Calibration Slope Plot
    # We expect a linear relationship: Squared Error ≈ Slope * Variance + Intercept
    # Ideally Slope ≈ 1 for perfect calibration.
    
    plt.figure(figsize=(10, 6))
    
    # Scatter plot
    sns.scatterplot(
        data=metrics, 
        x='variance', 
        y='squared_rmse', 
        hue='sparsity_level', 
        alpha=0.7,
        s=100
    )
    
    # Fit regression line for the whole dataset (or per model if needed)
    # Using all points for a global calibration check
    slope, intercept, r_value, p_value, std_err = linregress(
        metrics['variance'].values, 
        metrics['squared_rmse'].values
    )
    
    x_line = np.linspace(metrics['variance'].min(), metrics['variance'].max(), 100)
    y_line = slope * x_line + intercept
    
    plt.plot(x_line, y_line, 'r--', label=f'Fit: Slope={slope:.2f}, R²={r_value**2:.2f}')
    
    # Ideal calibration line (Slope=1, Intercept=0)
    plt.plot(x_line, x_line, 'g:', label='Ideal (Slope=1)')
    
    plt.title('Uncertainty Calibration: Variance vs. Squared Error', fontsize=14)
    plt.xlabel('Predictive Variance', fontsize=12)
    plt.ylabel('Squared RMSE', fontsize=12)
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    
    plot_path_1 = str(Path(output_dir) / "calibration_slope.png")
    plt.savefig(plot_path_1, dpi=300)
    plt.close()
    logger.info(f"Calibration slope plot saved to {plot_path_1}")
    
    # 2. Predicted vs. Squared Residuals (Same as above but focusing on the relationship)
    # The previous plot IS the predicted vs squared residuals plot.
    # We can generate a second view if needed, e.g., binned averages.
    # Let's create a binned version to smooth noise.
    
    metrics_sorted = metrics.sort_values('variance')
    n_bins = 10
    if len(metrics) >= n_bins:
        metrics_sorted['bin'] = pd.qcut(metrics_sorted['variance'], q=n_bins, duplicates='drop')
        binned = metrics_sorted.groupby('bin').agg({
            'variance': 'mean',
            'squared_rmse': 'mean'
        }).reset_index()
        
        plt.figure(figsize=(10, 6))
        plt.errorbar(
            binned['variance'], 
            binned['squared_rmse'], 
            yerr=binned['squared_rmse'].std() / np.sqrt(binned['squared_rmse'].count()),
            fmt='o',
            capsize=5,
            label='Binned Mean'
        )
        plt.plot(x_line, y_line, 'r--', label=f'Global Fit Slope={slope:.2f}')
        plt.title('Calibration: Binned Variance vs. Mean Squared Error', fontsize=14)
        plt.xlabel('Mean Predictive Variance (Binned)', fontsize=12)
        plt.ylabel('Mean Squared RMSE', fontsize=12)
        plt.legend()
        plt.grid(True, alpha=0.3)
        plt.tight_layout()
        
        plot_path_2 = str(Path(output_dir) / "calibration_binned.png")
        plt.savefig(plot_path_2, dpi=300)
        plt.close()
        logger.info(f"Binned calibration plot saved to {plot_path_2}")
    else:
        # Fallback if not enough data for binning
        plot_path_2 = plot_path_1
        logger.warning("Not enough data points for binned calibration plot.")

    return plot_path_1, plot_path_2

def save_calibration_report(metrics: pd.DataFrame, output_dir: Optional[str] = None) -> str:
    """
    Save calibration report (slope, intercept, R²) to JSON.
    """
    if output_dir is None:
        output_dir = str(CALIBRATION_DIR)
    
    CALIBRATION_DIR.mkdir(parents=True, exist_ok=True)
    
    metrics['squared_rmse'] = metrics['rmse'] ** 2
    
    slope, intercept, r_value, p_value, std_err = linregress(
        metrics['variance'].values, 
        metrics['squared_rmse'].values
    )
    
    report = {
        "calibration_slope": float(slope),
        "intercept": float(intercept),
        "r_squared": float(r_value**2),
        "p_value": float(p_value),
        "std_error": float(std_err),
        "n_samples": len(metrics),
        "metrics_file": str(RESULTS_DIR / "metrics.csv")
    }
    
    report_path = str(Path(output_dir) / "calibration_report.json")
    with open(report_path, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Calibration report saved to {report_path}")
    return report_path

