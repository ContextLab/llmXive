import os
import sys
from pathlib import Path

def main():
    """
    Creates the project directory structure and generates a verification artifact.
    Implements Task T001: Create project structure.
    """
    # Define the required directory structure relative to the project root
    # Assuming this script runs from the project root or code/ directory.
    # We will resolve paths relative to the script's parent directory to ensure robustness.
    base_dir = Path(__file__).resolve().parent.parent

    required_dirs = [
        "code/utils",
        "data/raw",
        "data/processed",
        "data/results",
        "data/metadata",
        "tests/unit",
        "tests/integration",
        "docs"
    ]

    created_dirs = []
    failed_dirs = []

    print("Starting project structure creation...")

    for dir_path in required_dirs:
        full_path = base_dir / dir_path
        try:
            full_path.mkdir(parents=True, exist_ok=True)
            created_dirs.append(str(full_path))
            print(f"  Created: {full_path}")
        except OSError as e:
            failed_dirs.append((dir_path, str(e)))
            print(f"  Failed to create {dir_path}: {e}")

    if failed_dirs:
        print(f"\nWarning: {len(failed_dirs)} directories could not be created.")
        for d, err in failed_dirs:
            print(f"  - {d}: {err}")
        # We proceed to generate the report with what we have, but exit with error code if critical
        # However, for this task, we assume the structure is mostly created.

    # Generate the verification artifact: project_structure.txt
    # This file lists all created directories as requested.
    output_file = base_dir / "project_structure.txt"
    
    try:
        with open(output_file, "w") as f:
            f.write("Project Directory Structure Verification\n")
            f.write("=" * 40 + "\n")
            f.write(f"Generated by: code/setup_project.py\n")
            f.write(f"Base Directory: {base_dir}\n\n")
            f.write("Created Directories:\n")
            f.write("-" * 20 + "\n")
            for d in created_dirs:
                f.write(f"{d}\n")
            
            if failed_dirs:
                f.write("\nFailed Directories:\n")
                f.write("-" * 20 + "\n")
                for d, err in failed_dirs:
                    f.write(f"{d}: {err}\n")
            
            f.write("\nVerification Complete.\n")
        
        print(f"\nVerification artifact written to: {output_file}")
    except IOError as e:
        print(f"Error writing verification artifact: {e}")
        sys.exit(1)

    if failed_dirs:
        sys.exit(1)
    else:
        print("Project structure created successfully.")
        sys.exit(0)

if __name__ == "__main__":
    main()