logger = get_logger(__name__)

def load_otu_table(file_path: str) -> pd.DataFrame:
    """
    Load the OTU/ASV table from a CSV file.
    
    Expected format:
    - First column: 'SampleID' (or similar identifier)
    - Remaining columns: Taxon IDs (e.g., ASV_1, ASV_2, ...)
    - Rows: Samples
    
    Args:
        file_path: Path to the OTU table CSV.
        
    Returns:
        DataFrame with samples as rows and taxa as columns.
    """
    path = Path(file_path)
    if not path.exists():
        raise FileNotFoundError(f"OTU table not found at {file_path}. "
                                "Ensure T013/T014 data acquisition has completed.")
    
    logger.info(f"Loading OTU table from {file_path}")
    # Assume first column is the index/sample ID
    df = pd.read_csv(path, index_col=0)
    logger.info(f"Loaded OTU table: {df.shape[0]} samples, {df.shape[1]} taxa")
    return df

def filter_taxon_by_presence(
    otu_table: pd.DataFrame, 
    min_sample_fraction: float = 0.05
) -> pd.DataFrame:
    """
    Filter taxa to retain only those present in at least min_sample_fraction of samples.
    
    A taxon is considered 'present' if its count > 0 in a sample.
    
    Args:
        otu_table: DataFrame of OTU/ASV counts (samples x taxa).
        min_sample_fraction: Minimum fraction of samples a taxon must appear in.
        
    Returns:
        Filtered DataFrame containing only retained taxa.
    """
    if otu_table.empty:
        raise ValueError("OTU table is empty; cannot filter taxa.")
    
    total_samples = len(otu_table)
    min_samples_required = int(np.ceil(total_samples * min_sample_fraction))
    
    logger.info(f"Filtering taxa: retaining those present in >= {min_sample_fraction*100}% "
                f"of {total_samples} samples (min {min_samples_required} samples)")
    
    # Calculate presence (count > 0) for each taxon across samples
    presence_mask = otu_table > 0
    presence_counts = presence_mask.sum(axis=0)
    
    # Identify taxa to keep
    taxa_to_keep = presence_counts[presence_counts >= min_samples_required].index.tolist()
    taxa_removed = presence_counts[presence_counts < min_samples_required].index.tolist()
    
    logger.info(f"Retained {len(taxa_to_keep)} taxa, removed {len(taxa_removed)} taxa")
    
    if len(taxa_to_keep) == 0:
        logger.warning("No taxa met the presence threshold. Returning empty table.")
        return otu_table.iloc[:, :0] # Return empty dataframe with same index
    
    filtered_table = otu_table[taxa_to_keep]
    return filtered_table

def run_taxon_filtering(
    input_path: str, 
    output_path: str, 
    min_sample_fraction: float = 0.05
) -> Dict[str, Any]:
    """
    Main entry point for taxon filtering task (T017).
    
    Loads the OTU table, filters taxa based on presence, and saves the result.
    
    Args:
        input_path: Path to the input OTU table CSV (from T013/T014).
        output_path: Path to save the filtered OTU table CSV.
        min_sample_fraction: Minimum fraction of samples a taxon must appear in (default 0.05).
        
    Returns:
        Dictionary with filtering statistics.
    """
    logger.info(f"Starting taxon filtering: {input_path} -> {output_path}")
    
    # Load data
    otu_table = load_otu_table(input_path)
    
    # Filter
    filtered_table = filter_taxon_by_presence(otu_table, min_sample_fraction)
    
    # Ensure output directory exists
    out_path = Path(output_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Save
    filtered_table.to_csv(output_path)
    logger.info(f"Saved filtered OTU table to {output_path}")
    
    return {
        "input_samples": len(otu_table),
        "input_taxa": otu_table.shape[1],
        "output_samples": len(filtered_table),
        "output_taxa": filtered_table.shape[1],
        "min_sample_fraction": min_sample_fraction,
        "status": "completed"
    }

