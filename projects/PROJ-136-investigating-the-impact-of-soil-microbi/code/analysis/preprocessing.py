"""
Preprocessing module for Soil Microbiome Diversity project.

Implements taxon filtering (retain taxa present in >=5% of samples)
and rarefaction logic (stub for QIIME 2 integration).

Note: This module expects processed data from T016 (matched_samples.csv)
and the raw OTU/ASV table generated by T013/T014 data acquisition.
"""
import os
