# Constants
AMBIGUOUS_SIGNAL_THRESHOLD = 0.5  # Threshold for ambiguity in turn-taking signals
MIN_SAMPLE_SIZE = 1000  # Minimum sample size before failing (from T016 logic)

def load_counterfactual_indices(indices_path: str) -> Set[int]:
    """
    Load the counterfactual indices from the Parquet file generated by T047.
    Returns a set of frame indices that are forced to be skipped (randomized subset).
    """
    logger.info(f"Loading counterfactual indices from {indices_path}")
    if not os.path.exists(indices_path):
        raise FileNotFoundError(f"Counterfactual indices file not found: {indices_path}")
    
    df = pd.read_parquet(indices_path)
    # Assuming the column name is 'frame_index' or similar based on T047 generation
    if 'frame_index' in df.columns:
        return set(df['frame_index'].tolist())
    elif 'index' in df.columns:
        return set(df['index'].tolist())
    else:
        # Fallback: assume the dataframe index is the frame index
        return set(df.index.tolist())

def should_fallback(
    uncertainty_score: float,
    delta_magnitude: float,
    frame_index: int,
    counterfactual_indices: Set[int],
    turn_signal_confidence: float = 1.0
) -> Tuple[bool, str]:
    """
    Determine if a fallback to the full solver is required based on:
    1. Uncertainty score > 0.8
    2. Delta magnitude is high (threshold configurable, defaulting to high value)
    3. Ambiguous turn-taking signals (low confidence) -> Default to full solver
    4. Counterfactual intervention logic (T047/FR-008/FR-017):
       - If frame_index is in counterfactual_indices, force skip (do NOT fallback to full solver).
       - Otherwise, follow deterministic rules.
    
    Returns:
        Tuple[bool, reason_string]: True if fallback (full solver) is needed.
    """
    # FR-017: Randomized counterfactual intervention overrides deterministic fallback
    if frame_index in counterfactual_indices:
        logger.debug(f"Frame {frame_index} is in counterfactual set: FORCED SKIP (no fallback)")
        return False, "counterfactual_skip"

    # FR-014 / FR-023: Handle ambiguous turn-taking signals
    # If turn_signal_confidence is low (ambiguous), default to full solver (fallback)
    if turn_signal_confidence < AMBIGUOUS_SIGNAL_THRESHOLD:
        logger.debug(f"Frame {frame_index}: Ambiguous turn signal (conf={turn_signal_confidence}): FALLBACK to full solver")
        return True, "ambiguous_turn_signal"

    # Standard fallback logic: Uncertainty or Delta Magnitude
    if uncertainty_score > 0.8:
        logger.debug(f"Frame {frame_index}: High uncertainty ({uncertainty_score}): FALLBACK to full solver")
        return True, "high_uncertainty"

    # Assuming a high threshold for delta magnitude (e.g., 0.7 normalized)
    if delta_magnitude > 0.7:
        logger.debug(f"Frame {frame_index}: High delta magnitude ({delta_magnitude}): FALLBACK to full solver")
        return True, "high_delta_magnitude"

    return False, "no_fallback_needed"

def apply_fallback_logic(
    df: pd.DataFrame,
    counterfactual_indices_path: str,
    uncertainty_col: str = "uncertainty_score",
    delta_col: str = "latent_delta_magnitude",
    turn_confidence_col: str = "turn_signal_confidence",
    fallback_col: str = "requires_fallback",
    fallback_reason_col: str = "fallback_reason"
) -> pd.DataFrame:
    """
    Apply the fallback logic to a DataFrame of hybrid inference data.
    
    Handles the 'Power Limitation' error scenario explicitly:
    - If the number of frames requiring fallback exceeds a threshold that would
      cause power limits to be exceeded, it attempts to reduce the sample size
      using the `reduce_sample_size` module.
    - If reduction fails (MIN_SAMPLE_SIZE reached), it logs the error and exits gracefully
      with a 'Power Limitation' error message, as per FR-014 and FR-023.
    
    Args:
        df: Input DataFrame with inference results.
        counterfactual_indices_path: Path to the counterfactual indices Parquet file.
        uncertainty_col: Column name for uncertainty scores.
        delta_col: Column name for delta magnitudes.
        turn_confidence_col: Column name for turn signal confidence.
        fallback_col: Output column name for boolean fallback flag.
        fallback_reason_col: Output column name for string reason.
    
    Returns:
        DataFrame with new columns added.
    
    Raises:
        PowerLimitationError: If fallback demand is too high and sample size cannot be reduced further.
    """
    logger.info(f"Applying fallback logic to {len(df)} frames")
    
    try:
        counterfactual_indices = load_counterfactual_indices(counterfactual_indices_path)
    except FileNotFoundError as e:
        logger.error(f"Failed to load counterfactual indices: {e}")
        raise

    fallback_reasons = []
    fallback_flags = []

    for idx, row in df.iterrows():
        frame_idx = row.get('frame_index', idx)
        uncertainty = row.get(uncertainty_col, 0.0)
        delta_mag = row.get(delta_col, 0.0)
        turn_conf = row.get(turn_confidence_col, 1.0)
        
        needs_fallback, reason = should_fallback(
            uncertainty, delta_mag, frame_idx, counterfactual_indices, turn_conf
        )
        
        fallback_flags.append(needs_fallback)
        fallback_reasons.append(reason)

    df[fallback_col] = fallback_flags
    df[fallback_reason_col] = fallback_reasons

    fallback_count = sum(fallback_flags)
    total_count = len(df)
    fallback_ratio = fallback_count / total_count if total_count > 0 else 0.0

    logger.info(f"Fallback applied: {fallback_count}/{total_count} frames ({fallback_ratio:.2%})")

    # FR-014 / FR-023: Check for Power Limitation
    # If too many frames require fallback, it might exceed compute budget (e.g., > 50% fallback)
    # We define a heuristic threshold here, but the real check is if the fallback load is unsustainable.
    # For this task, we simulate the check: if fallback_ratio > 0.8, we trigger the reduction logic.
    if fallback_ratio > 0.8:
        logger.warning(f"High fallback ratio ({fallback_ratio:.2%}) detected. Checking power limits...")
        try:
            # Attempt to reduce sample size to handle the load
            # This is a simplified call; in a real scenario, we might pass more context
            new_df, reduced_count = reduce_sample_size(
                df, 
                target_size=int(total_count * 0.5), # Attempt to reduce by half
                min_size=MIN_SAMPLE_SIZE
            )
            logger.info(f"Sample size reduced from {total_count} to {len(new_df)} to handle fallback load.")
            return new_df
        except PowerLimitationError as e:
            error_msg = f"Power Limitation Error: {e}. Minimum sample size ({MIN_SAMPLE_SIZE}) reached. Exiting gracefully."
            logger.error(error_msg)
            # Explicitly exit or raise to signal the pipeline failure as per FR-023
            raise PowerLimitationError(error_msg) from e

    return df

def main():
    """
    Entry point for the fallback handler script.
    Expects command line arguments for input/output paths and configuration.
    """
    parser = argparse.ArgumentParser(description="Apply fallback logic to hybrid inference output.")
    parser.add_argument("--input", type=str, required=True, help="Path to input hybrid output parquet (from T050)")
    parser.add_argument("--counterfactual", type=str, required=True, help="Path to counterfactual indices parquet (from T047)")
    parser.add_argument("--output", type=str, required=True, help="Path to output parquet with fallback flags")
    args = parser.parse_args()

    try:
        df = pd.read_parquet(args.input)
        logger.info(f"Loaded input data: {len(df)} rows")

        result_df = apply_fallback_logic(
            df, 
            args.counterfactual,
            uncertainty_col="uncertainty_score",
            delta_col="latent_delta_magnitude",
            turn_confidence_col="turn_signal_confidence" # Assuming this column exists or is generated
        )

        result_df.to_parquet(args.output, index=False)
        logger.info(f"Saved output with fallback logic to {args.output}")

    except PowerLimitationError as e:
        logger.critical(f"Pipeline halted due to power limitation: {e}")
        sys.exit(1)
    except Exception as e:
        logger.critical(f"Unexpected error during fallback application: {e}")
        raise

if __name__ == "__main__":
    main()