"""
Module: validate_proxy_mos
Task: T044
Description: Calculate Pearson correlation between proxy MOS and human ratings (if available) to validate proxy.
Dependencies: T046 (check_human_ratings)
"""
import os
import sys
import json
import argparse
import logging
from pathlib import Path
from typing import Optional, Dict, Any

import numpy as np
import pandas as pd
from scipy.stats import pearsonr

# Project root handling
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
DATA_DIR = PROJECT_ROOT / "data"
METRICS_DIR = DATA_DIR / "metrics"
LOGS_DIR = DATA_DIR / "logs"
STATE_FILE = PROJECT_ROOT / "state.yaml"

# Ensure directories exist
METRICS_DIR.mkdir(parents=True, exist_ok=True)
LOGS_DIR.mkdir(parents=True, exist_ok=True)

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.FileHandler(LOGS_DIR / "validate_proxy_mos.log"),
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)

# Constants
CORRELATION_THRESHOLD = 0.8
HUMAN_RATINGS_PATH = DATA_DIR / "raw" / "human_ratings.json"
HUMAN_DATA_STATUS_PATH = METRICS_DIR / "human_data_status.json"
HYBRID_OUTPUT_METRICS_PATH = METRICS_DIR / "hybrid_output_metrics.json" # Assumes T028 output
MOS_VALIDATION_STATUS_PATH = METRICS_DIR / "mos_validation_status.json"


def load_hybrid_output_metrics() -> Optional[Dict[str, Any]]:
    """
    Loads the hybrid output metrics generated by T028 (compute_proxy_mos).
    Expected schema: {'proxy_mos': [...], 'frame_id': [...]}
    """
    if not HYBRID_OUTPUT_METRICS_PATH.exists():
        logger.warning(f"Hybrid output metrics not found at {HYBRID_OUTPUT_METRICS_PATH}. "
                       "Cannot calculate correlation without proxy MOS values.")
        return None

    with open(HYBRID_OUTPUT_METRICS_PATH, 'r') as f:
        return json.load(f)


def load_human_ratings() -> Optional[Dict[str, Any]]:
    """
    Loads human ratings from the raw data directory.
    Expected schema: {'ratings': [{'frame_id': int, 'mos': float}, ...]}
    """
    if not HUMAN_RATINGS_PATH.exists():
        logger.info(f"Human ratings file not found at {HUMAN_RATINGS_PATH}.")
        return None

    try:
        with open(HUMAN_RATINGS_PATH, 'r') as f:
            data = json.load(f)
        logger.info(f"Successfully loaded human ratings from {HUMAN_RATINGS_PATH}")
        return data
    except (json.JSONDecodeError, IOError) as e:
        logger.error(f"Failed to load human ratings: {e}")
        return None


def calculate_correlation(proxy_mos: list, human_mos: list) -> float:
    """
    Calculates Pearson correlation coefficient between proxy and human MOS.
    """
    if len(proxy_mos) != len(human_mos):
        raise ValueError("Proxy and Human MOS lists must be of equal length.")
    
    if len(proxy_mos) < 2:
        raise ValueError("Need at least 2 data points to calculate correlation.")

    try:
        corr, p_value = pearsonr(proxy_mos, human_mos)
        logger.info(f"Pearson Correlation Coefficient: {corr:.4f} (p-value: {p_value:.4f})")
        return float(corr)
    except Exception as e:
        logger.error(f"Error calculating correlation: {e}")
        raise


def update_state_yaml(status: str, reason: str, correlation: Optional[float] = None):
    """
    Updates state.yaml with the MOS validation status.
    """
    import yaml
    
    state_data = {}
    if STATE_FILE.exists():
        try:
            with open(STATE_FILE, 'r') as f:
                state_data = yaml.safe_load(f) or {}
        except Exception as e:
            logger.warning(f"Could not read existing state.yaml: {e}")

    state_data['mos_validation'] = status
    
    if status == 'passed':
        state_data['mos_validation_correlation'] = correlation
        state_data['mos_validation_threshold'] = CORRELATION_THRESHOLD
    elif status == 'failed':
        state_data['mos_validation_correlation'] = correlation
        state_data['mos_validation_threshold'] = CORRELATION_THRESHOLD
        state_data['mos_validation_reason'] = reason
    elif status == 'skipped':
        state_data['mos_validation_reason'] = reason

    try:
        with open(STATE_FILE, 'w') as f:
            yaml.dump(state_data, f, default_flow_style=False)
        logger.info(f"Updated state.yaml with mos_validation: {status}")
    except Exception as e:
        logger.error(f"Failed to update state.yaml: {e}")
        raise


def log_assumption_validated():
    """
    Logs that the assumption (no human data) was validated and continues execution.
    """
    log_path = LOGS_DIR / "mos_assumption_validated.log"
    with open(log_path, 'a') as f:
        f.write(f"{logging.Formatter().format(logging.LogRecord('', '', '', 0, '', (), None))} - Assumption Validated: No human data available, skipping validation.\n")
    logger.info("Assumption Validated: No human data available. Continuing pipeline.")


def validate_proxy_mos() -> bool:
    """
    Main logic for T044.
    1. Check human_data_status.json (produced by T046).
    2. If missing: Skip, write status JSON, update state.yaml, log assumption.
    3. If present: Load data, calculate correlation, assert >= 0.8, update state.yaml.
    """
    # Step 1: Check status from T046
    if not HUMAN_DATA_STATUS_PATH.exists():
        logger.error(f"Dependency missing: {HUMAN_DATA_STATUS_PATH} does not exist. "
                     "Ensure T046 (check_human_ratings) has run.")
        # Fallback to raw check if status file is missing but we want to be robust
        if not HUMAN_RATINGS_PATH.exists():
            logger.warning("Status file missing AND raw human ratings missing. Skipping.")
            status = "skipped"
            reason = "no_human_data (status file missing)"
            # Write status file for downstream tasks
            with open(MOS_VALIDATION_STATUS_PATH, 'w') as f:
                json.dump({"status": status, "reason": reason}, f, indent=2)
            update_state_yaml("skipped", reason)
            log_assumption_validated()
            return True # Not a failure, just a skip
        else:
            logger.warning("Status file missing but raw data exists. Proceeding to load.")
            # Continue to load logic below
    else:
        with open(HUMAN_DATA_STATUS_PATH, 'r') as f:
            status_data = json.load(f)
        
        if status_data.get('status') == 'missing':
            logger.info("Human data status is 'missing'. Skipping validation.")
            reason = "no_human_data"
            with open(MOS_VALIDATION_STATUS_PATH, 'w') as f:
                json.dump({"status": "skipped", "reason": reason}, f, indent=2)
            update_state_yaml("skipped", reason)
            log_assumption_validated()
            return True # Success (skipped gracefully)
        
        if status_data.get('status') != 'present':
            logger.warning(f"Unexpected status in human_data_status.json: {status_data.get('status')}. Skipping.")
            with open(MOS_VALIDATION_STATUS_PATH, 'w') as f:
                json.dump({"status": "skipped", "reason": "invalid_status"}, f, indent=2)
            update_state_yaml("skipped", "invalid_status_in_status_file")
            return True

    # Step 2: Load Data
    logger.info("Human data present. Loading datasets for correlation.")
    
    proxy_metrics = load_hybrid_output_metrics()
    if not proxy_metrics:
        logger.error("Could not load proxy MOS metrics. Cannot validate.")
        # Fail loudly if we expected data but don't have it
        raise FileNotFoundError(f"Required proxy metrics file not found: {HYBRID_OUTPUT_METRICS_PATH}")

    human_data = load_human_ratings()
    if not human_data:
        # This case should ideally be caught by the status check, but defensive coding
        logger.warning("Human ratings file missing despite status check. Skipping.")
        with open(MOS_VALIDATION_STATUS_PATH, 'w') as f:
            json.dump({"status": "skipped", "reason": "human_file_missing_runtime"}, f, indent=2)
        update_state_yaml("skipped", "human_file_missing_runtime")
        return True

    # Step 3: Align Data
    # Expected format for proxy: {'frame_id': [1, 2, ...], 'proxy_mos': [4.5, 3.2, ...]}
    # Expected format for human: {'ratings': [{'frame_id': 1, 'mos': 4.5}, ...]}
    
    proxy_frame_ids = proxy_metrics.get('frame_id', [])
    proxy_mos_values = proxy_metrics.get('proxy_mos', [])
    
    if not proxy_frame_ids or not proxy_mos_values:
        logger.error("Proxy MOS data is empty or malformed.")
        raise ValueError("Proxy MOS data is empty or malformed.")

    human_ratings_list = human_data.get('ratings', [])
    if not human_ratings_list:
        logger.error("Human ratings list is empty.")
        raise ValueError("Human ratings list is empty.")

    # Create a map for quick lookup
    human_map = {item['frame_id']: item['mos'] for item in human_ratings_list}
    
    # Filter proxy data to only include frames with human ratings
    aligned_proxy_mos = []
    aligned_human_mos = []
    matched_count = 0

    for fid, p_mos in zip(proxy_frame_ids, proxy_mos_values):
        if fid in human_map:
            aligned_proxy_mos.append(p_mos)
            aligned_human_mos.append(human_map[fid])
            matched_count += 1

    if matched_count == 0:
        logger.error("No overlapping frame IDs between proxy output and human ratings.")
        raise ValueError("No overlapping frame IDs between proxy output and human ratings.")

    logger.info(f"Aligned {matched_count} frames for correlation calculation.")

    # Step 4: Calculate Correlation
    try:
        correlation = calculate_correlation(aligned_proxy_mos, aligned_human_mos)
    except Exception as e:
        logger.error(f"Correlation calculation failed: {e}")
        # Fail the task if calculation fails
        raise

    # Step 5: Validate Threshold
    if correlation >= CORRELATION_THRESHOLD:
        logger.info(f"Validation PASSED: Correlation {correlation:.4f} >= {CORRELATION_THRESHOLD}")
        status = "passed"
        reason = "correlation_threshold_met"
        with open(MOS_VALIDATION_STATUS_PATH, 'w') as f:
            json.dump({
                "status": "passed", 
                "correlation": correlation, 
                "threshold": CORRELATION_THRESHOLD
            }, f, indent=2)
        update_state_yaml("passed", reason, correlation)
        return True
    else:
        logger.error(f"Validation FAILED: Correlation {correlation:.4f} < {CORRELATION_THRESHOLD}")
        status = "failed"
        reason = f"correlation_below_threshold (r={correlation:.4f})"
        with open(MOS_VALIDATION_STATUS_PATH, 'w') as f:
            json.dump({
                "status": "failed", 
                "correlation": correlation, 
                "threshold": CORRELATION_THRESHOLD,
                "reason": reason
            }, f, indent=2)
        update_state_yaml("failed", reason, correlation)
        return False # Indicate failure for the pipeline


def main():
    parser = argparse.ArgumentParser(description="Validate Proxy MOS against Human Ratings (T044)")
    args = parser.parse_args()

    try:
        success = validate_proxy_mos()
        if success:
            logger.info("T044 Validation completed successfully.")
            sys.exit(0)
        else:
            logger.error("T044 Validation failed (correlation too low).")
            sys.exit(1)
    except Exception as e:
        logger.critical(f"T044 Execution failed with exception: {e}")
        sys.exit(2)


if __name__ == "__main__":
    main()