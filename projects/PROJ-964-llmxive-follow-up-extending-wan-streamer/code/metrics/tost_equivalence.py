"""
T049: Implement Two One-Sided Tests (TOST) equivalence tests for quality metrics.

This module performs TOST equivalence tests (Δ=0.05) on quality metrics (FID, proxy MOS)
to validate that the hybrid inference quality degradation is within acceptable bounds.

Output: data/metrics/tost_results.csv
"""
