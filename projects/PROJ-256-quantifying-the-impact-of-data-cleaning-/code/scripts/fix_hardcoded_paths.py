"""
T1206: Refactor hardcoded paths to use config.py constants.
This script automatically replaces hardcoded paths with config references.
"""
import os
import re
import json
from pathlib import Path
from typing import Dict, List, Any

# Mapping of hardcoded paths to config variables
PATH_MAPPINGS = {
    'data/raw': 'config.RAW_DATA_PATH',
    'data/processed': 'config.PROCESSED_DATA_PATH',
    'output/figures': 'config.FIGURES_OUTPUT_PATH',
    'output/reports': 'config.REPORTS_OUTPUT_PATH',
    '"data/raw"': 'config.RAW_DATA_PATH',
    "'data/raw'": 'config.RAW_DATA_PATH',
    '"data/processed"': 'config.PROCESSED_DATA_PATH',
    "'data/processed'": 'config.PROCESSED_DATA_PATH',
    '"output/figures"': 'config.FIGURES_OUTPUT_PATH',
    "'output/figures'": 'config.FIGURES_OUTPUT_PATH',
    '"output/reports"': 'config.REPORTS_OUTPUT_PATH',
    "'output/reports'": 'config.REPORTS_OUTPUT_PATH',
}

def read_audit_report(audit_file: Path) -> Dict[str, Any]:
    """Read the audit report generated by audit_hardcoded_paths.py."""
    with open(audit_file, 'r', encoding='utf-8') as f:
        return json.load(f)

def fix_file(file_path: Path, findings: List[Dict[str, Any]]) -> bool:
    """Fix hardcoded paths in a single file."""
    if not file_path.exists():
        return False
    
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            content = f.read()
    except Exception as e:
        print(f"Error reading {file_path}: {e}")
        return False
    
    original_content = content
    file_findings = [f for f in findings if f['file'] == str(file_path)]
    
    if not file_findings:
        return False
    
    # Sort findings by line number in descending order to avoid offset issues
    file_findings.sort(key=lambda x: x['line'], reverse=True)
    
    lines = content.splitlines(keepends=True)
    
    for finding in file_findings:
        line_num = finding['line'] - 1  # Convert to 0-based index
        if line_num < 0 or line_num >= len(lines):
            continue
        
        line = lines[line_num]
        matched_string = finding['matched_string']
        
        # Find the config variable to use
        config_var = None
        for hardcoded, config in PATH_MAPPINGS.items():
            if hardcoded in matched_string:
                config_var = config
                break
        
        if config_var:
            # Replace the hardcoded path with config reference
            new_line = line.replace(matched_string, config_var)
            lines[line_num] = new_line
            print(f"Fixed: {file_path}:{line_num+1} - {matched_string} -> {config_var}")
    
    # Write back if changes were made
    new_content = ''.join(lines)
    if new_content != original_content:
        try:
            with open(file_path, 'w', encoding='utf-8') as f:
                f.write(new_content)
            return True
        except Exception as e:
            print(f"Error writing {file_path}: {e}")
            return False
    
    return False

def add_config_import(file_path: Path) -> bool:
    """Add config import to a file if not present."""
    if not file_path.exists():
        return False
    
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            content = f.read()
    except Exception as e:
        print(f"Error reading {file_path}: {e}")
        return False
    
    # Check if config import already exists
    if 'from config import' in content or 'import config' in content:
        return False
    
    # Add import after other imports
    lines = content.splitlines(keepends=True)
    insert_index = 0
    
    # Find where to insert (after other imports)
    for i, line in enumerate(lines):
        if line.startswith('import ') or line.startswith('from '):
            insert_index = i + 1
        elif line.strip() == '' and i > 0 and (lines[i-1].startswith('import ') or lines[i-1].startswith('from ')):
            insert_index = i
            break
        elif not line.startswith('import ') and not line.startswith('from ') and line.strip() != '' and i > 0:
            break
    
    # Insert the import
    import_line = "from config import Config, get_config, reload_config\n"
    lines.insert(insert_index, import_line)
    
    try:
        with open(file_path, 'w', encoding='utf-8') as f:
            f.writelines(lines)
        print(f"Added config import to: {file_path}")
        return True
    except Exception as e:
        print(f"Error writing {file_path}: {e}")
        return False

def main():
    """Main function to fix hardcoded paths."""
    project_root = Path(__file__).parent.parent.parent
    audit_file = project_root / 'data' / 'processed' / 'audit_hardcoded_paths.json'
    
    if not audit_file.exists():
        print(f"Error: Audit report not found at {audit_file}")
        print("Please run audit_hardcoded_paths.py first.")
        return
    
    report = read_audit_report(audit_file)
    
    if report['total_hardcoded_paths_found'] == 0:
        print("No hardcoded paths found. Nothing to fix.")
        return
    
    files_to_fix = set(f['file'] for f in report['findings'])
    
    print(f"Fixing hardcoded paths in {len(files_to_fix)} files...")
    
    fixed_files = 0
    for file_path_str in files_to_fix:
        file_path = Path(file_path_str)
        if fix_file(file_path, report['findings']):
            fixed_files += 1
            add_config_import(file_path)
    
    print(f"Fixed {fixed_files} files.")
    print("Please review the changes and test the affected scripts.")

if __name__ == '__main__':
    main()
