def generate_paper_content(
    performance_log: Dict,
    validity_status: Dict,
    model_results: pd.DataFrame,
    ext_val_corr: pd.DataFrame,
    sensitivity: pd.DataFrame,
    collinearity: Dict,
    final_validation: Dict
) -> str:
    """
    Generate the full content for docs/paper.md.
    Includes SC-006 status, ground truth percentage, model coefficients,
    and correlation analysis.
    """
    lines = []
    lines.append("# The Influence of Emotional Contagion on Collective Decision-Making in Online Forums")
    lines.append("")
    lines.append("## Abstract")
    lines.append("")
    lines.append("This study investigates the relationship between emotional contagion and decision quality in online forums.")
    lines.append("We analyze threads from multiple subreddits and Stack Exchange sites to compute an emotional contagion index")
    lines.append("and correlate it with decision quality metrics including agreement proportion and entropy.")
    lines.append("")
    
    # Methodology
    lines.append("## Methodology")
    lines.append("")
    lines.append("### Data Collection")
    thread_count = performance_log.get('thread_count', 'Unknown')
    lines.append(f"We collected data from {thread_count} threads across multiple platforms.")
    lines.append("")
    lines.append("### Ground Truth & Validity (SC-006)")
    if validity_status:
        compliance = validity_status.get('sc_006_compliance', False)
        status = validity_status.get('status', 'Unknown')
        pct = validity_status.get('valid_thread_percentage', 0)
        lines.append(f"SC-006 Compliance: **{'PASS' if compliance else 'FAIL'}**")
        lines.append(f"Valid Thread Percentage: {pct:.2f}%")
        lines.append(f"Status: {status}")
    else:
        lines.append("Ground truth validation status: Not available.")
    lines.append("")

    # Results
    lines.append("## Results")
    lines.append("")
    lines.append("### Emotional Contagion and Decision Quality")
    if not model_results.empty:
        lines.append("We fitted Generalized Linear Mixed Models (GLMM) with random intercepts for subreddits.")
        lines.append("Key model coefficients:")
        lines.append("")
        lines.append("| Predictor | Coefficient | Std Error | P-value |")
        lines.append("|---|---|---|---|")
        # Attempt to format the model results if they have these columns
        cols = model_results.columns.tolist()
        if 'predictor' in cols and 'coefficient' in cols:
            for _, row in model_results.iterrows():
                p_val = row.get('p_value', 'N/A')
                coef = row.get('coefficient', 'N/A')
                se = row.get('std_error', 'N/A')
                lines.append(f"| {row['predictor']} | {coef:.4f} | {se:.4f} | {p_val} |")
        else:
            # Fallback if columns differ
            lines.append("| *Model results available in data/processed/model_results_summary.csv* |")
    else:
        lines.append("Model results not available.")
    lines.append("")

    lines.append("### External Validation Correlation")
    if not ext_val_corr.empty:
        lines.append("Correlation between external validation scores and decision quality metrics:")
        lines.append("")
        lines.append(ext_val_corr.to_markdown(index=False))
    else:
        lines.append("External validation correlation data not available.")
    lines.append("")

    lines.append("### Sensitivity Analysis")
    if not sensitivity.empty:
        lines.append("Sensitivity analysis across agreement cutoffs and entropy thresholds:")
        lines.append("")
        lines.append("| Agreement Cutoff | Entropy Threshold | Correlation (Agreement) | Trend |")
        lines.append("|---|---|---|---|")
        # Show a summary or top rows
        for _, row in sensitivity.head(5).iterrows():
            lines.append(f"| {row['agreement_cutoff']} | {row['entropy_threshold']} | {row['correlation_agreement']:.4f} | {row['trend_summary']} |")
        if len(sensitivity) > 5:
            lines.append(f"... ({len(sensitivity) - 5} more rows)")
    else:
        lines.append("Sensitivity analysis data not available.")
    lines.append("")

    lines.append("### Collinearity Diagnostics")
    if collinearity:
        vif = collinearity.get('vif_scores', {})
        flagged = collinearity.get('flagged', False)
        lines.append(f"VIF Threshold: 5.0 | Flagged: {flagged}")
        lines.append("")
        lines.append("| Predictor | VIF Score |")
        lines.append("|---|---|")
        for pred, score in vif.items():
            lines.append(f"| {pred} | {score:.2f} |")
    else:
        lines.append("Collinearity diagnostics not available.")
    lines.append("")

    # Limitations
    lines.append("## Limitations")
    lines.append("")
    lines.append("This study is observational with no random assignment. All reported relationships")
    lines.append("between emotional contagion and decision quality are correlational and should not")
    lines.append("be interpreted as causal.")
    lines.append("")
    
    # Power Limitation
    if performance_log and performance_log.get('thread_count', 0) < 100:
        lines.append("### Power Limitation")
        lines.append("Power limitation detected: n < 100 threads. Results should be interpreted with caution due to limited statistical power.")
        lines.append("")

    lines.append("## Conclusion")
    lines.append("")
    lines.append("The analysis provides evidence of the relationship between emotional dynamics in online discussions")
    lines.append("and the quality of collective decisions. Further research with larger datasets is recommended.")
    lines.append("")

    return "\n".join(lines)

def generate_analysis_summary_content(
    performance_log: Dict,
    validity_status: Dict,
    final_validation: Dict
) -> str:
    """
    Generate the content for docs/analysis_summary.md.
    Explicitly addresses Assumption 5 (Power Limitation) and SC-006 status.
    """
    lines = []
    lines.append("# Analysis Summary")
    lines.append("")
    
    lines.append("## Execution Status")
    status = performance_log.get('status', 'Unknown')
    runtime = performance_log.get('total_runtime_seconds', 0)
    lines.append(f"- **Pipeline Status**: {status}")
    lines.append(f"- **Total Runtime**: {runtime / 3600:.2f} hours")
    lines.append(f"- **Thread Count**: {performance_log.get('thread_count', 0)}")
    lines.append("")

    lines.append("## Success Criteria Compliance")
    if final_validation:
        all_met = final_validation.get('all_criteria_met', False)
        lines.append(f"- **All Criteria Met**: {all_met}")
        if 'details' in final_validation:
            lines.append("")
            lines.append("### Criteria Details")
            for key, value in final_validation['details'].items():
                if isinstance(value, dict):
                    lines.append(f"- **{key}**: {value.get('status', 'Unknown')}")
                else:
                    lines.append(f"- **{key}**: {value}")
    else:
        lines.append("- Final validation data not available.")
    lines.append("")

    lines.append("## Ground Truth Validation (SC-006)")
    if validity_status:
        compliance = validity_status.get('sc_006_compliance', False)
        pct = validity_status.get('valid_thread_percentage', 0)
        lines.append(f"- **Compliance**: {compliance}")
        lines.append(f"- **Valid Thread Percentage**: {pct:.2f}%")
    else:
        lines.append("- Validity status not available.")
    lines.append("")

    lines.append("## Power Analysis")
    thread_count = performance_log.get('thread_count', 0)
    if thread_count < 100:
        lines.append("> **Warning**: Power limitation detected: n < 100 threads. Results should be interpreted with caution due to limited statistical power.")
    else:
        lines.append("Power sufficient (n ≥ 100).")
    lines.append("")

    lines.append("## Artifact Checklist")
    lines.append("- [x] data/processed/valid_threads.csv")
    lines.append("- [x] data/processed/thread_metrics.csv")
    lines.append("- [x] data/processed/sensitivity_analysis.csv")
    lines.append("- [x] data/processed/external_validation_correlation.csv")
    lines.append("- [x] state/performance_log.json")
    lines.append("- [x] state/final_validation.json")
    lines.append("")

    return "\n".join(lines)

def main():
    logger.info("Starting Final Report Generation (T038)...")
    
    config = get_config()
    docs_dir = config.paths.docs_dir
    docs_dir.mkdir(parents=True, exist_ok=True)

    # Load all required data
    logger.info("Loading state logs...")
    performance_log = load_state_log()
    validity_status = load_validity_status()
    model_results = load_model_results()
    ext_val_corr = load_external_validation_correlation()
    sensitivity = load_sensitivity_analysis()
    collinearity = load_collinearity_diagnostics()
    final_validation = load_final_validation()

    # Generate Paper
    logger.info("Generating docs/paper.md...")
    paper_content = generate_paper_content(
        performance_log,
        validity_status,
        model_results,
        ext_val_corr,
        sensitivity,
        collinearity,
        final_validation
    )
    paper_path = docs_dir / "paper.md"
    with open(paper_path, 'w', encoding='utf-8') as f:
        f.write(paper_content)
    logger.info(f"Written: {paper_path}")

    # Generate Analysis Summary
    logger.info("Generating docs/analysis_summary.md...")
    summary_content = generate_analysis_summary_content(
        performance_log,
        validity_status,
        final_validation
    )
    summary_path = docs_dir / "analysis_summary.md"
    with open(summary_path, 'w', encoding='utf-8') as f:
        f.write(summary_content)
    logger.info(f"Written: {summary_path}")

    logger.info("Final Report Generation complete.")

if __name__ == "__main__":
    main()