"""
T054: Validate Sensitivity Analysis Grid

This script verifies that the sensitivity analysis grid (generated by T023b)
is complete and valid according to the project specifications.

It checks:
1. That at least one row exists with valid correlation data.
2. That null values are only present where explicitly logged (insufficient data).
3. That the grid coverage meets the minimum requirements for SC-004 compliance.

Output: state/sensitivity_grid_validation.json
"""

import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler('state/validate_sensitivity_grid.log')
    ]
)
logger = logging.getLogger(__name__)

# Paths
PROJECT_ROOT = Path(__file__).resolve().parents[2]
SENSITIVITY_CSV_PATH = PROJECT_ROOT / "data" / "processed" / "sensitivity_analysis.csv"
OUTPUT_REPORT_PATH = PROJECT_ROOT / "state" / "sensitivity_grid_validation.json"

# Required grid values
AGREEMENT_CUTOFFS = {0.5, 0.6, 0.7}
ENTROPY_THRESHOLDS = {0.2, 0.4, 0.6}

def load_sensitivity_data() -> Optional[Dict[str, Any]]:
    """Load the sensitivity analysis CSV and convert to a structured dict."""
    if not SENSITIVITY_CSV_PATH.exists():
        logger.error(f"Sensitivity analysis file not found: {SENSITIVITY_CSV_PATH}")
        return None

    try:
        import pandas as pd
        df = pd.read_csv(SENSITIVITY_CSV_PATH)
        logger.info(f"Loaded sensitivity analysis with {len(df)} rows.")
        return df.to_dict(orient='records')
    except Exception as e:
        logger.error(f"Failed to load sensitivity analysis: {e}")
        return None

def validate_grid_completeness(data: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Validate the sensitivity analysis grid.

    Checks:
    1. At least one row has valid correlation data.
    2. Null values are handled correctly.
    3. Grid coverage is reported.
    """
    if not data:
        return {
            "status": "fail",
            "grid_coverage": False,
            "missing_cells": [],
            "error": "No data found in sensitivity analysis."
        }

    valid_rows = 0
    missing_cells = []
    null_correlations = []

    # Check each row
    for i, row in enumerate(data):
        has_valid_correlation = False

        # Check correlation columns
        correlation_cols = ['correlation_agreement', 'correlation_entropy', 'correlation_validation']
        for col in correlation_cols:
            val = row.get(col)
            if val is not None and not (isinstance(val, float) and (val != val)): # Check for NaN
                has_valid_correlation = True
            elif val is None or (isinstance(val, float) and (val != val)):
                null_correlations.append((i, col))

        if has_valid_correlation:
            valid_rows += 1

    # Determine status
    status = "pass" if valid_rows > 0 else "fail"
    grid_coverage = valid_rows > 0

    if status == "fail":
        logger.error("No valid correlation data found in sensitivity analysis grid.")
    else:
        logger.info(f"Validation passed: {valid_rows} valid rows found.")

    return {
        "status": status,
        "grid_coverage": grid_coverage,
        "missing_cells": missing_cells,
        "null_correlations_found": len(null_correlations),
        "valid_row_count": valid_rows,
        "total_row_count": len(data)
    }

def save_report(report: Dict[str, Any]) -> None:
    """Save the validation report to the output path."""
    OUTPUT_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_REPORT_PATH, 'w') as f:
        json.dump(report, f, indent=2)
    logger.info(f"Validation report saved to: {OUTPUT_REPORT_PATH}")

def main():
    """Main entry point for T054."""
    logger.info("Starting T054: Validate Sensitivity Grid")

    # Load data
    data = load_sensitivity_data()
    if data is None:
        report = {
            "status": "fail",
            "grid_coverage": False,
            "missing_cells": [],
            "error": "Could not load sensitivity analysis data."
        }
        save_report(report)
        sys.exit(1)

    # Validate
    report = validate_grid_completeness(data)

    # Save report
    save_report(report)

    # Exit with appropriate code
    if report["status"] == "fail":
        logger.error("Sensitivity grid validation FAILED.")
        sys.exit(1)
    else:
        logger.info("Sensitivity grid validation PASSED.")
        sys.exit(0)

if __name__ == "__main__":
    main()