"""
Statistical utilities for the Glass Forming Region prediction pipeline.

This module implements statistical correction methods for multiple hypothesis testing,
specifically the Bonferroni correction as required by FR-008.
"""

from typing import List, Tuple, Dict, Optional
import numpy as np


def bonferroni_correct(p_values: List[float], alpha: float = 0.05) -> Tuple[List[float], List[bool]]:
    """
    Apply Bonferroni correction to a list of p-values for multiple hypothesis testing.
    
    The Bonferroni correction adjusts the significance threshold to control the 
    family-wise error rate (FWER) when performing multiple statistical tests.
    
    Formula: p_adjusted = min(p * n, 1.0)
    where n is the number of tests.
    
    Args:
        p_values: List of raw p-values from hypothesis tests.
        alpha: Significance level (default 0.05).
    
    Returns:
        A tuple containing:
        - adjusted_p_values: List of Bonferroni-corrected p-values.
        - is_significant: List of booleans indicating if the corrected p-value 
          is less than alpha.
    
    Raises:
        ValueError: If p_values list is empty or contains invalid values.
        TypeError: If p_values is not a list of numbers.
    """
    if not p_values:
        raise ValueError("p_values list cannot be empty")
    
    if not all(isinstance(p, (int, float)) for p in p_values):
        raise TypeError("All p-values must be numeric")
    
    if any(not (0.0 <= p <= 1.0) for p in p_values):
        raise ValueError("All p-values must be between 0.0 and 1.0")
    
    n_tests = len(p_values)
    
    # Apply Bonferroni correction: p_adj = p * n
    adjusted_p_values = [min(p * n_tests, 1.0) for p in p_values]
    
    # Determine significance based on corrected threshold
    is_significant = [p < alpha for p in adjusted_p_values]
    
    return adjusted_p_values, is_significant


def bonferroni_threshold(n_tests: int, alpha: float = 0.05) -> float:
    """
    Calculate the Bonferroni-corrected significance threshold.
    
    This is the inverse operation of correction: instead of adjusting p-values,
    we adjust the significance threshold.
    
    Formula: alpha_corrected = alpha / n
    
    Args:
        n_tests: Number of hypothesis tests being performed.
        alpha: Original significance level (default 0.05).
    
    Returns:
        The adjusted significance threshold.
    """
    if n_tests <= 0:
        raise ValueError("n_tests must be positive")
    
    return alpha / n_tests


def apply_bonferroni_to_results(
    results: Dict, 
    p_value_keys: List[str], 
    alpha: float = 0.05
) -> Dict:
    """
    Apply Bonferroni correction to p-values in a results dictionary.
    
    This function is designed to work with the model performance metrics 
    structure generated by the training pipeline.
    
    Args:
        results: Dictionary containing model performance metrics with p-values.
        p_value_keys: List of keys in the results dict that contain p-values.
        alpha: Significance level (default 0.05).
    
    Returns:
        A new dictionary with added Bonferroni-corrected p-values and 
        significance flags. The original structure is preserved with 
        additional keys:
        - {key}_bonferroni: Corrected p-value
        - {key}_significant: Boolean indicating significance
    
    Example:
        Input: {"t_test_rf_vs_lr": 0.03, "t_test_xgb_vs_lr": 0.01}
        Output: {
            "t_test_rf_vs_lr": 0.03,
            "t_test_rf_vs_lr_bonferroni": 0.06,
            "t_test_rf_vs_lr_significant": False,
            ...
        }
    """
    if not results:
        return results.copy()
    
    import copy
    corrected_results = copy.deepcopy(results)
    
    # Collect all p-values to determine the number of tests
    all_p_values = []
    valid_keys = []
    
    for key in p_value_keys:
        if key in corrected_results:
            p_val = corrected_results[key]
            if isinstance(p_val, (int, float)):
                all_p_values.append(p_val)
                valid_keys.append(key)
    
    if not all_p_values:
        return corrected_results
    
    # Apply correction
    adjusted_p_values, significance_flags = bonferroni_correct(all_p_values, alpha)
    
    # Update results with corrected values
    for key, adj_p, is_sig in zip(valid_keys, adjusted_p_values, significance_flags):
        corrected_results[f"{key}_bonferroni"] = adj_p
        corrected_results[f"{key}_significant"] = is_sig
    
    return corrected_results