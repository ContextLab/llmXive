"""
Generate raw evaluation metrics (calibration error, sharpness, coverage error)
from the per-sample predictions produced by the thin pipeline.

This script is intended to be run after the thin pipeline has populated
``data/results/per_sample_errors.csv``.  It reads that file, computes the
three metrics for every (dataset, method) combination, and writes the
results to ``data/results/metrics_raw.csv`` conforming to the
``contracts/metrics.schema.yaml`` contract.
"""

import argparse
import json
import logging
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd
import yaml
from jsonschema import Draft7Validator, ValidationError

from llmxive_toolkit import paths, get_logger
from metrics.evaluation import (
    calculate_calibration_error,
    calculate_sharpness,
    calculate_interval_coverage,
)

logger = get_logger(__name__)

# ----------------------------------------------------------------------
# Helper functions
# ----------------------------------------------------------------------
def _load_per_sample_errors() -> pd.DataFrame:
    """Load the per‑sample errors CSV generated by the thin pipeline."""
    csv_path = paths.data("results", "per_sample_errors.csv")
    if not csv_path.is_file():
        raise FileNotFoundError(f"Per‑sample errors file not found: {csv_path}")
    df = pd.read_csv(csv_path)
    if df.empty:
        raise ValueError("Per‑sample errors file is empty – no predictions were generated.")
    required_cols = {
        "sample_id",
        "dataset",
        "method",
        "prediction",
        "lower_bound",
        "upper_bound",
        "ground_truth",
        "abs_error",
    }
    missing = required_cols - set(df.columns)
    if missing:
        raise ValueError(f"Missing required columns in per‑sample file: {missing}")
    return df

def _compute_metrics_for_group(group: pd.DataFrame) -> dict:
    """
    Compute calibration error, sharpness and coverage error for a single
    (dataset, method) group.

    Returns a dict with keys ``calibration_error``, ``sharpness``,
    ``coverage_error`` and ``nominal_coverage`` (the nominal level used for
    calibration – fixed at 0.9 for this study).
    """
    nominal = 0.9  # nominal coverage level used throughout the project

    preds = group["prediction"].to_numpy()
    intervals = group[["lower_bound", "upper_bound"]].to_numpy()
    gt = group["ground_truth"].to_numpy()

    # Observed coverage
    observed_cov = calculate_interval_coverage(intervals, gt)

    cal_error = calculate_calibration_error(preds, intervals, gt, nominal_level=nominal)
    sharp = calculate_sharpness(intervals)
    cov_error = abs(observed_cov - nominal)

    return {
        "calibration_error": cal_error,
        "sharpness": sharp,
        "coverage_error": cov_error,
        "nominal_coverage": nominal,
    }

def _write_metrics(df: pd.DataFrame) -> None:
    out_path = paths.data("results", "metrics_raw.csv")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_path, index=False)
    logger.info(f"Wrote metrics to {out_path}")

# ----------------------------------------------------------------------
# CLI
# ----------------------------------------------------------------------
def _parse_cli() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Compute calibration, sharpness and coverage metrics for each dataset‑method pair."
    )
    parser.add_argument(
        "--thin",
        action="store_true",
        help="Flag kept for compatibility with the quick‑start command; has no effect."
    )
    return parser.parse_args()

# ----------------------------------------------------------------------
# Main
# ----------------------------------------------------------------------
def main() -> None:
    _ = _parse_cli()  # currently unused but retained for future extensions

    # Load per‑sample predictions
    per_sample_df = _load_per_sample_errors()

    # Group by dataset & method
    results = []
    for (dataset_id, method_id), group in per_sample_df.groupby(["dataset", "method"]):
        metrics = _compute_metrics_for_group(group)

        timestamp = datetime.now(timezone.utc).isoformat()

        # One row per metric type
        for metric_type, value in [
            ("calibration_error", metrics["calibration_error"]),
            ("sharpness", metrics["sharpness"]),
            ("coverage_error", metrics["coverage_error"]),
        ]:
            results.append(
                {
                    "dataset_id": dataset_id,
                    "method_id": method_id,
                    "metric_type": metric_type,
                    "value": float(value),
                    "nominal_coverage": float(metrics["nominal_coverage"]),
                    "timestamp": timestamp,
                }
            )

    metrics_df = pd.DataFrame(results)

    # ------------------------------------------------------------------
    # Validate against the JSON‑Schema contract before writing
    # ------------------------------------------------------------------
    schema_path = Path(
        paths.root,
        "specs",
        "001-assessing-uncertainty-quantification-tec",
        "contracts",
        "metrics.schema.yaml",
    )
    with open(schema_path, "r", encoding="utf-8") as f:
        schema = yaml.safe_load(f)

    validator = Draft7Validator(schema)
    errors = sorted(validator.iter_errors(metrics_df.to_dict(orient="records")), key=lambda e: e.path)
    if errors:
        msgs = "\n".join([f"{list(e.path)}: {e.message}" for e in errors])
        raise ValidationError(f"Metrics CSV does not conform to schema:\n{msgs}")

    _write_metrics(metrics_df)

if __name__ == "__main__":
    main()
