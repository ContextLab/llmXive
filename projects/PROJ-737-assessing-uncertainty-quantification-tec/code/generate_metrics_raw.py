"""
Task T021: Generate results/metrics_raw.csv containing Calibration and Sharpness metrics.

This script reads the per-sample error predictions generated by the pipeline (T014),
calculates Calibration Error and Sharpness for each (dataset, method) pair using
the functions from code/metrics/evaluation.py, and writes the aggregated results
to results/metrics_raw.csv.

Output Schema:
- dataset: str
- method: str
- metric_type: str ('Calibration' or 'Sharpness')
- value: float
"""
import os
import logging
import pandas as pd
from pathlib import Path
from typing import List, Dict, Any

# Local imports matching existing API surface
from metrics.evaluation import (
    calculate_calibration_error,
    calculate_sharpness,
    calculate_interval_coverage,
    calculate_mean_interval_width
)
from utils.logger import get_logger

# Configure logger
logger = get_logger(__name__)

def load_per_sample_errors(input_path: Path) -> pd.DataFrame:
    """
    Load the per_sample_errors.csv generated by T014.
    
    Expected columns:
    sample_id, method, prediction, lower_bound, upper_bound, ground_truth, dataset
    """
    if not input_path.exists():
        raise FileNotFoundError(
            f"Input file not found: {input_path}. "
            "Ensure T014 (pipeline.py) has been run successfully."
        )
    
    df = pd.read_csv(input_path)
    required_cols = ['sample_id', 'method', 'prediction', 'lower_bound', 
                     'upper_bound', 'ground_truth', 'dataset']
    
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in {input_path}: {missing}")
    
    return df

def calculate_metrics_for_group(group_df: pd.DataFrame) -> Dict[str, float]:
    """
    Calculate Calibration Error and Sharpness for a single (dataset, method) group.
    
    Args:
        group_df: DataFrame subset for a specific dataset and method.
    
    Returns:
        Dictionary with 'Calibration' and 'Sharpness' values.
    """
    predictions = group_df['prediction'].values
    lower_bounds = group_df['lower_bound'].values
    upper_bounds = group_df['upper_bound'].values
    ground_truths = group_df['ground_truth'].values
    
    # Construct intervals as (lower, upper) tuples or arrays
    # The evaluation functions expect arrays for lower/upper bounds
    intervals_lower = lower_bounds
    intervals_upper = upper_bounds
    
    # Determine nominal level (e.g., 0.95 for 95% coverage)
    # Assuming the pipeline used a standard 95% confidence level.
    # If the pipeline used a different level, this should be configurable.
    nominal_level = 0.95
    
    # Calculate Calibration Error: |Observed Coverage - Nominal Level|
    # calculate_interval_coverage returns the observed coverage
    observed_coverage = calculate_interval_coverage(
        predictions, 
        (intervals_lower, intervals_upper), 
        ground_truths
    )
    calibration_error = abs(observed_coverage - nominal_level)
    
    # Calculate Sharpness: Mean Interval Width
    sharpness = calculate_mean_interval_width(
        (intervals_lower, intervals_upper)
    )
    
    return {
        'Calibration': calibration_error,
        'Sharpness': sharpness
    }

def main():
    """Main entry point for T021."""
    # Define paths relative to project root
    # Assuming script is run from project root or code directory
    project_root = Path(__file__).resolve().parent.parent
    input_file = project_root / "results" / "per_sample_errors.csv"
    output_file = project_root / "results" / "metrics_raw.csv"
    
    # Ensure output directory exists
    output_file.parent.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Loading per-sample errors from: {input_file}")
    try:
        df = load_per_sample_errors(input_file)
    except FileNotFoundError as e:
        logger.error(str(e))
        raise
    
    logger.info(f"Loaded {len(df)} records. Unique datasets: {df['dataset'].unique()}, "
                f"Unique methods: {df['method'].unique()}")
    
    results = []
    
    # Group by dataset and method
    group_keys = ['dataset', 'method']
    for name, group in df.groupby(group_keys):
        dataset_name, method_name = name
        logger.info(f"Processing: Dataset={dataset_name}, Method={method_name}")
        
        try:
            metrics = calculate_metrics_for_group(group)
            
            for metric_type, value in metrics.items():
                results.append({
                    'dataset': dataset_name,
                    'method': method_name,
                    'metric_type': metric_type,
                    'value': value
                })
        except Exception as e:
            logger.error(f"Failed to calculate metrics for {dataset_name}/{method_name}: {e}")
            # Continue to next group rather than failing the whole run
            continue
    
    if not results:
        logger.warning("No metrics were calculated. Check input data and logic.")
        # Create an empty file with the correct schema
        empty_df = pd.DataFrame(columns=['dataset', 'method', 'metric_type', 'value'])
        empty_df.to_csv(output_file, index=False)
    else:
        output_df = pd.DataFrame(results)
        # Sort for readability
        output_df = output_df.sort_values(by=['dataset', 'method', 'metric_type'])
        output_df.to_csv(output_file, index=False)
        logger.info(f"Successfully wrote metrics to: {output_file}")
        logger.info(f"Total rows written: {len(output_df)}")

if __name__ == "__main__":
    main()