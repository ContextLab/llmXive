def load_model_artifact(path: str) -> Any:
    """Load the trained model artifact from disk."""
    if not os.path.exists(path):
        raise FileNotFoundError(f"Model artifact not found at {path}. Ensure T029 has completed successfully.")
    with open(path, 'rb') as f:
        return pickle.load(f)

