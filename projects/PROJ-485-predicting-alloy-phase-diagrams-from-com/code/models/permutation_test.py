def run_permutation_test(
    rf_mae_list: List[float], 
    null_mae_list: List[float], 
    n_iterations: int = 10000, 
    random_seed: int = 42
) -> Dict[str, Any]:
    """
    Performs the permutation test on the fold-level MAE differences.
    
    Args:
        rf_mae_list: List of MAE values for the Random Forest model per fold.
        null_mae_list: List of MAE values for the Null model per fold.
        n_iterations: Number of permutations.
        random_seed: Random seed for reproducibility.
        
    Returns:
        Dictionary containing test statistics and p-value.
    """
    if len(rf_mae_list) != len(null_mae_list):
        raise ValueError("RF and Null MAE lists must have the same length (same folds).")
    
    np.random.seed(random_seed)
    
    # Calculate observed difference: Null MAE - RF MAE (Positive means RF is better)
    observed_diffs = np.array(null_mae_list) - np.array(rf_mae_list)
    observed_mean_diff = np.mean(observed_diffs)
    
    log_info(f"Observed Mean MAE Difference (Null - RF): {observed_mean_diff:.6f}")
    
    # Permutation logic:
    # Under H0, the label "which model produced this error" is exchangeable.
    # We have pairs of (null_mae, rf_mae). The difference is d_i = n_i - r_i.
    # If H0 is true, then d_i and -d_i are equally likely.
    # We can permute by randomly flipping the sign of each difference.
    
    n_folds = len(observed_diffs)
    permuted_means = np.zeros(n_iterations)
    
    log_info(f"Running {n_iterations} permutation iterations...")
    
    for i in range(n_iterations):
        # Randomly flip signs
        signs = np.random.choice([-1, 1], size=n_folds)
        permuted_diffs = observed_diffs * signs
        permuted_means[i] = np.mean(permuted_diffs)
    
    # Calculate p-value (one-tailed: is RF significantly better?)
    # p = P(permuted_mean >= observed_mean)
    p_value = np.sum(permuted_means >= observed_mean_diff) / n_iterations
    
    # Calculate effect size (Cohen's d equivalent for paired differences)
    std_diff = np.std(observed_diffs, ddof=1)
    if std_diff > 0:
        effect_size = observed_mean_diff / std_diff
    else:
        effect_size = 0.0
        
    return {
        "observed_mean_difference": float(observed_mean_diff),
        "p_value": float(p_value),
        "effect_size": float(effect_size),
        "n_folds": n_folds,
        "n_iterations": n_iterations,
        "significant": p_value < 0.05
    }

def main():
    """
    Main entry point for the permutation test.
    """
    parser = argparse.ArgumentParser(description="Run permutation test for model significance.")
    parser.add_argument("--iterations", type=int, default=10000, help="Number of permutation iterations")
    parser.add_argument("--seed", type=int, default=42, help="Random seed")
    args = parser.parse_args()
    
    log_info("Starting Permutation Test (T025)...")
    
    try:
        # 1. Load Results
        # We expect train.py and null_baseline.py to have generated these reports.
        # If they haven't, we raise an error to fail loudly (as per constraints).
        loso_report = load_loso_results()
        null_report = load_null_results()
        
        # Extract MAE lists
        # Assuming the reports have a structure like: {"folds": [{"mae": ...}, ...]}
        rf_mae_list = [fold["mae"] for fold in loso_report.get("folds", [])]
        null_mae_list = [fold["mae"] for fold in null_report.get("folds", [])]
        
        if not rf_mae_list or not null_mae_list:
            raise ValueError("Could not extract fold-level MAE lists from reports.")
        
        log_info(f"Loaded {len(rf_mae_list)} folds for comparison.")
        
        # 2. Run Test
        results = run_permutation_test(
            rf_mae_list, 
            null_mae_list, 
            n_iterations=args.iterations, 
            random_seed=args.seed
        )
        
        # 3. Save Results
        output_path = "state/PROJ-485/permutation_test_results.json"
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        
        with open(output_path, 'w') as f:
            json.dump(results, f, indent=2)
        
        log_info(f"Permutation test results saved to {output_path}")
        log_info(f"P-value: {results['p_value']:.6f}")
        log_info(f"Significant (p < 0.05): {results['significant']}")
        
        if results['significant']:
            log_info("Conclusion: The Random Forest model shows a statistically significant "
                     "reduction in MAE compared to the null baseline.")
        else:
            log_warning("Conclusion: The reduction in MAE is NOT statistically significant "
                        "(p >= 0.05). The model may not be better than the null baseline.")
        
        return 0
        
    except Exception as e:
        log_error(f"Permutation test failed: {str(e)}")
        # Fail loudly as per constraint: do not return success if it fails.
        return 1

if __name__ == "__main__":
    sys.exit(main())
