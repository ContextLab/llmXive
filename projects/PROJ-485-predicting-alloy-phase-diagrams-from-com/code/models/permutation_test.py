"""
Permutation Test for Model Significance (T025)

Implements a permutation test on fold-level MAE differences to verify that the
Random Forest model provides a statistically significant reduction in MAE 
compared to the null baseline (global mean).

Hypothesis:
  H0: The distribution of MAE differences (Null - RF) is symmetric around 0.
  H1: The RF model significantly reduces MAE (difference > 0).

Method:
  1. Calculate observed mean difference in MAE across LOSO folds.
  2. Permute the labels of the differences (or simply shuffle the assignment of 
     which model produced which error) to simulate the null hypothesis.
  3. Repeat N times to build a null distribution.
  4. Calculate p-value as the proportion of permuted means >= observed mean.
"""
