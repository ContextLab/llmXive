def load_processed_data() -> List[Dict[str, Any]]:
    """
    Load the processed descriptors from data/processed/descriptors.csv.
    Returns a list of dictionaries representing rows.
    """
    data_path = "data/processed/descriptors.csv"
    if not os.path.exists(data_path):
        raise FileNotFoundError(f"Processed data not found at {data_path}. Run T018 first.")
    
    data = []
    with open(data_path, 'r', encoding='utf-8') as f:
        # Assuming CSV with headers
        import csv
        reader = csv.DictReader(f)
        for row in reader:
            # Convert numeric strings to float
            processed_row = {}
            for k, v in row.items():
                try:
                    processed_row[k] = float(v)
                except (ValueError, TypeError):
                    processed_row[k] = v
            data.append(processed_row)
    
    logger.info(f"Loaded {len(data)} rows from {data_path}")
    return data

def load_loso_results() -> List[Dict[str, Any]]:
    """
    Load LOSO cross-validation results.
    Expected location: data/artifacts/loso_results.json (generated by T021/T026)
    Structure: [{'fold_id': str, 'mae': float, 'r2': float, ...}, ...]
    """
    results_path = "data/artifacts/loso_results.json"
    if not os.path.exists(results_path):
        raise FileNotFoundError(f"LOSO results not found at {results_path}. Run T021/T026 first.")
    
    with open(results_path, 'r', encoding='utf-8') as f:
        results = json.load(f)
    
    logger.info(f"Loaded {len(results)} LOSO fold results")
    return results

def load_null_results() -> List[Dict[str, Any]]:
    """
    Load Null Model baseline results.
    Expected location: data/artifacts/baseline_comparison.json (generated by T024)
    We need the fold-level MAE if available, or we reconstruct from global stats if only aggregate exists.
    However, T024 produces aggregate. For a robust permutation test, we ideally need fold-level null predictions.
    
    Assumption: The null model is the global mean of the training set.
    If the LOSO results contain 'null_mae' per fold (added by T024 logic), use that.
    If not, we must re-run the null prediction logic per fold.
    
    To ensure this task is self-contained and robust, we will attempt to load the detailed null results
    from a specific file generated by the null baseline logic if it exists, or reconstruct if possible.
    
    Given T024 produces `data/artifacts/baseline_comparison.json` (aggregate), we need fold-level data.
    Let's assume the `loso_results.json` from T021/T026 has been augmented by T024 to include 'null_mae' per fold,
    OR we re-calculate the null model MAE for each fold using the loaded data.
    
    Strategy: We will look for a file `data/artifacts/null_model_folds.json`. If not found, we compute it.
    """
    fold_null_path = "data/artifacts/null_model_folds.json"
    
    if os.path.exists(fold_null_path):
        with open(fold_null_path, 'r', encoding='utf-8') as f:
            null_folds = json.load(f)
        logger.info(f"Loaded {len(null_folds)} null model fold results from {fold_null_path}")
        return null_folds
    
    # Fallback: Re-compute if not found (requires re-running logic similar to T024)
    # This ensures the permutation test can run even if the intermediate file was missed,
    # provided the main data and LOSO split logic is deterministic or available.
    # However, to strictly follow "no synthetic", we must use the real data splits.
    # We will assume the LOSO results (from T021) contain the necessary split info or we re-split.
    # For simplicity in this task, we assume the 'loso_results' from T026 already has 'null_mae' if T024 ran correctly.
    # If not, we raise an error to force T024 to be re-run correctly to produce fold-level details.
    
    logger.error("Fold-level null model results not found. T024 must produce null_model_folds.json or augment loso_results.json.")
    raise FileNotFoundError("Missing fold-level null model data required for permutation test.")

def run_permutation_test(n_permutations: int = 10000, seed: int = 42) -> float:
    """
    Implement SC-008: Permutation Test on fold-level MAE differences.
    
    Null Hypothesis (H0): The difference in MAE between Random Forest and Null Model is due to chance.
    Alternative Hypothesis (H1): The Random Model performs significantly better (lower MAE).
    
    Steps:
    1. Calculate observed difference: mean(RF_MAE) - mean(Null_MAE) per fold.
    2. Permute the labels (which model produced which MAE) for each fold.
       Actually, since we have paired folds (same data split), we permute the sign of the difference
       or shuffle the assignment of 'RF' vs 'Null' to the observed MAE values within each fold.
       Standard approach for paired data: Permute the sign of the difference (d = RF - Null).
       If d < 0 (RF better), we want to see how often random permutations yield a mean difference <= observed.
    3. Calculate p-value = (count of permuted means <= observed mean + 1) / (n_permutations + 1).
    
    Returns:
        p_value (float): The calculated p-value.
    """
    try:
        loso_results = load_loso_results()
        null_results = load_null_results()
    except FileNotFoundError as e:
        log_error(f"Cannot run permutation test: {e}")
        raise

    # Extract fold-level MAEs
    # Assuming loso_results has 'mae' and null_results has 'mae' for the same fold order
    if len(loso_results) != len(null_results):
        raise ValueError("LOSO results and Null results must have the same number of folds.")

    rf_maes = [r['mae'] for r in loso_results]
    null_maes = [r['mae'] for r in null_results]

    # Calculate observed differences (RF - Null)
    # We expect RF < Null, so difference should be negative.
    diffs = [rf - null for rf, null in zip(rf_maes, null_maes)]
    observed_diff_mean = np.mean(diffs)
    
    log_info(f"Observed mean MAE difference (RF - Null): {observed_diff_mean:.6f}")
    
    # Permutation Test
    # We permute the signs of the differences to simulate the null hypothesis
    # where there is no systematic difference between the two models.
    np.random.seed(seed)
    count_extreme = 0
    
    # Pre-allocate array for speed if needed, but loop is fine for 10k
    for _ in range(n_permutations):
        # Randomly flip signs
        signs = np.random.choice([-1, 1], size=len(diffs))
        permuted_diffs = np.array(diffs) * signs
        permuted_mean = np.mean(permuted_diffs)
        
        # Check if permuted mean is as extreme or more extreme than observed
        # Since we expect RF to be better (negative diff), we count if permuted_mean <= observed_mean
        if permuted_mean <= observed_diff_mean:
            count_extreme += 1
    
    p_value = (count_extreme + 1) / (n_permutations + 1)
    
    log_info(f"Permutation test completed. P-value: {p_value:.6f}")
    return p_value

def main():
    """
    Main entry point for the permutation test task (T025).
    """
    parser = argparse.ArgumentParser(description="Run Permutation Test for Model Validation (SC-008)")
    parser.add_argument("--n-permutations", type=int, default=10000, help="Number of permutations")
    parser.add_argument("--seed", type=int, default=42, help="Random seed")
    parser.add_argument("--output", type=str, default="data/artifacts/permutation_pvalue.txt", help="Output file path")
    args = parser.parse_args()

    try:
        p_value = run_permutation_test(n_permutations=args.n_permutations, seed=args.seed)
        
        # Write output as raw float with 6 decimal places
        os.makedirs(os.path.dirname(args.output), exist_ok=True)
        with open(args.output, 'w', encoding='utf-8') as f:
            f.write(f"{p_value:.6f}")
        
        log_info(f"P-value written to {args.output}")
        
        # Verification
        if p_value < 0.05:
            log_info(f"Verification PASSED: p-value ({p_value:.6f}) < 0.05. Significant improvement confirmed.")
        else:
            log_warning(f"Verification FAILED: p-value ({p_value:.6f}) >= 0.05. Improvement not statistically significant.")
            
        return 0
    except Exception as e:
        log_error(f"Permutation test failed: {e}")
        raise

if __name__ == "__main__":
    sys.exit(main())
