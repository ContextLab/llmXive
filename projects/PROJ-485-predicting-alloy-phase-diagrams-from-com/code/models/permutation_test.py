def load_processed_data() -> Tuple[np.ndarray, np.ndarray]:
    """
    Loads the processed descriptor data and targets from data/processed/descriptors.csv.
    Returns X (features) and y (target).
    """
    import csv
    file_path = "data/processed/descriptors.csv"
    
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Processed data file not found: {file_path}. "
                                "Run T018 (generate_descriptors) first.")
    
    X_list = []
    y_list = []
    feature_cols = None

    with open(file_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            if feature_cols is None:
                # Identify feature columns (exclude metadata/target)
                feature_cols = [k for k in row.keys() if k not in ['system_id', 'composition', 'temperature', 'phase']]
                # Ensure we have numeric targets
            
            try:
                # Extract features
                features = [float(row[col]) for col in feature_cols]
                X_list.append(features)
                
                # Extract target (assuming 'temperature' is the target for phase boundary prediction in this context)
                # If 'temperature' is not the target, adjust based on actual schema
                target_key = 'temperature'
                if target_key in row:
                    y_list.append(float(row[target_key]))
                else:
                    # Fallback: assume last column is target if schema varies
                    # But strict adherence to schema suggests specific keys
                    raise ValueError(f"Target key '{target_key}' not found in row.")
            except (ValueError, KeyError) as e:
                log_warning(f"Skipping row due to parsing error: {e}")
                continue
    
    if len(X_list) == 0:
        raise ValueError("No valid data rows found in processed data.")
        
    return np.array(X_list), np.array(y_list)

