"""
T029: Save trained model artifact to data/artifacts/model.pkl with version hash.

This module implements the final step of User Story 2: persisting the trained
Random Forest model to disk with a version hash derived from the model's
training configuration and data checksum, ensuring traceability per Constitution Principle V.
"""
import os
import sys
import pickle
import json
import hashlib
import argparse
from datetime import datetime
from typing import Dict, Any, Optional

# Add project root to path for imports
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..')))

from utils.logging import get_logger, log_info, log_error, log_warning
from utils.checksum import compute_file_sha256

logger = get_logger(__name__)

# Constants
ARTIFACTS_DIR = "data/artifacts"
MODEL_FILENAME = "model.pkl"
METADATA_FILENAME = "model_metadata.json"
TRAINING_CONFIG_PATH = "state/PROJ-485/training_config.json"
DESCRIPTORS_PATH = "data/processed/descriptors.csv"
EVALUATION_REPORT_PATH = "data/artifacts/evaluation_report.json"


def load_training_config() -> Dict[str, Any]:
    """Load the training configuration from state directory."""
    if not os.path.exists(TRAINING_CONFIG_PATH):
        log_warning(f"Training config not found at {TRAINING_CONFIG_PATH}, using defaults")
        return {
            "model_type": "RandomForestRegressor",
            "n_estimators": 100,
            "max_depth": None,
            "random_state": 42,
            "cv_strategy": "LOSO"
        }
    
    with open(TRAINING_CONFIG_PATH, 'r') as f:
        return json.load(f)


def load_evaluation_report() -> Dict[str, Any]:
    """Load the evaluation report generated by train.py."""
    if not os.path.exists(EVALUATION_REPORT_PATH):
        log_warning(f"Evaluation report not found at {EVALUATION_REPORT_PATH}")
        return {}
    
    with open(EVALUATION_REPORT_PATH, 'r') as f:
        return json.load(f)


def compute_version_hash(config: Dict[str, Any], eval_report: Dict[str, Any]) -> str:
    """
    Compute a deterministic version hash based on training config and evaluation results.
    
    This ensures that the same model configuration and data produce the same version hash,
    satisfying Constitution Principle V (traceability).
    """
    hash_input = {
        "config": config,
        "metrics": {
            "aggregate_mae": eval_report.get("aggregate", {}).get("mae"),
            "aggregate_r2": eval_report.get("aggregate", {}).get("r2"),
            "num_folds": len(eval_report.get("folds", [])),
            "timestamp": datetime.now().isoformat()
        }
    }
    
    # Convert to sorted JSON string for deterministic hashing
    hash_str = json.dumps(hash_input, sort_keys=True, default=str)
    version_hash = hashlib.sha256(hash_str.encode('utf-8')).hexdigest()[:16]
    
    return version_hash


def save_model_artifact(model: Any, output_dir: str = ARTIFACTS_DIR) -> Dict[str, str]:
    """
    Save the trained model to disk with metadata and version hash.
    
    Args:
        model: The trained model object (e.g., RandomForestRegressor)
        output_dir: Directory where artifacts will be saved
        
    Returns:
        Dictionary containing paths to saved artifacts
    """
    os.makedirs(output_dir, exist_ok=True)
    
    # Load config and evaluation report
    config = load_training_config()
    eval_report = load_evaluation_report()
    
    # Compute version hash
    version_hash = compute_version_hash(config, eval_report)
    
    # Prepare metadata
    metadata = {
        "version_hash": version_hash,
        "model_type": config.get("model_type", "Unknown"),
        "training_config": config,
        "evaluation_summary": {
            "mae": eval_report.get("aggregate", {}).get("mae"),
            "r2": eval_report.get("aggregate", {}).get("r2"),
            "num_folds": len(eval_report.get("folds", []))
        },
        "created_at": datetime.now().isoformat(),
        "data_source_checksum": None
    }
    
    # Compute checksum of input data if it exists
    if os.path.exists(DESCRIPTORS_PATH):
        data_checksum = compute_file_sha256(DESCRIPTORS_PATH)
        metadata["data_source_checksum"] = data_checksum
        log_info(f"Data source checksum: {data_checksum}")
    
    # Save model
    model_path = os.path.join(output_dir, MODEL_FILENAME)
    with open(model_path, 'wb') as f:
        pickle.dump({
            "model": model,
            "version_hash": version_hash,
            "created_at": metadata["created_at"]
        }, f)
    
    log_info(f"Model saved to {model_path} with version hash: {version_hash}")
    
    # Save metadata
    metadata_path = os.path.join(output_dir, METADATA_FILENAME)
    with open(metadata_path, 'w') as f:
        json.dump(metadata, f, indent=2)
    
    log_info(f"Metadata saved to {metadata_path}")
    
    return {
        "model_path": model_path,
        "metadata_path": metadata_path,
        "version_hash": version_hash
    }


def load_model_artifact(model_path: str = None) -> Dict[str, Any]:
    """
    Load a previously saved model artifact.
    
    Args:
        model_path: Path to the model pickle file (defaults to ARTIFACTS_DIR/model.pkl)
        
    Returns:
        Dictionary containing the model and metadata
    """
    if model_path is None:
        model_path = os.path.join(ARTIFACTS_DIR, MODEL_FILENAME)
    
    if not os.path.exists(model_path):
        raise FileNotFoundError(f"Model artifact not found at {model_path}")
    
    with open(model_path, 'rb') as f:
        artifact = pickle.load(f)
    
    return artifact


def main():
    """
    Main entry point for saving the model artifact.
    
    This function is called by code/models/train.py after training completes.
    It loads the trained model from memory (passed as argument or loaded from
    a temporary state) and saves it to data/artifacts/model.pkl with version hash.
    """
    parser = argparse.ArgumentParser(description="Save trained model artifact with version hash")
    parser.add_argument("--model-path", type=str, default=None,
                      help="Path to temporary model pickle (if not in memory)")
    parser.add_argument("--output-dir", type=str, default=ARTIFACTS_DIR,
                      help="Output directory for artifacts")
    args = parser.parse_args()
    
    log_info("Starting model artifact save process...")
    
    # In a real pipeline, the model would be passed from train.py
    # For this standalone script, we expect the model to be loaded from a temp file
    # or we simulate loading it for demonstration (in actual use, train.py calls save_model directly)
    
    if args.model_path and os.path.exists(args.model_path):
        log_info(f"Loading model from {args.model_path}")
        with open(args.model_path, 'rb') as f:
            temp_artifact = pickle.load(f)
            model = temp_artifact.get("model")
    else:
        # This should not happen in normal pipeline execution
        # The model should be passed from train.py
        log_error("No model provided. This script should be called from train.py after training.")
        sys.exit(1)
    
    if model is None:
        log_error("Model is None. Cannot save artifact.")
        sys.exit(1)
    
    # Save the artifact
    result = save_model_artifact(model, args.output_dir)
    
    log_info(f"Model artifact successfully saved. Version: {result['version_hash']}")
    print(json.dumps(result, indent=2))
    
    return result


if __name__ == "__main__":
    main()