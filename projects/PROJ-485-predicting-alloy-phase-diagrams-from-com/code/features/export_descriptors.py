import os
import sys
import csv
import json
from typing import Dict, List, Any, Optional
from utils.logging import get_logger, log_info, log_error, log_warning
from utils.checksum import compute_file_sha256

# Ensure code/ is in path for imports if running as script
if 'code' not in sys.path:
    sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))

logger = get_logger(__name__)

INPUT_FILE = os.path.join('data', 'processed', 'descriptors_temp.csv')
OUTPUT_FILE = os.path.join('data', 'processed', 'descriptors.csv')

# Expected schema based on generate_descriptors.py output
REQUIRED_COLUMNS = [
    'system_id', 
    'composition', 
    'temperature', 
    'phase', 
    'mean_atomic_radius', 
    'electronegativity_variance', 
    'valence_electron_count', 
    'hume_rothery_concentration'
]

def load_processed_data(input_path: Optional[str] = None) -> List[Dict[str, Any]]:
    """
    Load processed data from the intermediate file generated by generate_descriptors.py.
    Validates that the file exists and has the expected schema.
    """
    path = input_path or INPUT_FILE
    
    if not os.path.exists(path):
        log_error(logger, f"Input file not found: {path}", "DATA_SOURCE_MISSING")
        raise FileNotFoundError(f"Processed descriptor file not found: {path}")

    data = []
    with open(path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        
        # Validate schema
        if reader.fieldnames is None:
            log_error(logger, "CSV file is empty or has no headers", "INVALID_DATA_SCHEMA")
            raise ValueError("Invalid CSV: No headers found")
        
        missing_cols = set(REQUIRED_COLUMNS) - set(reader.fieldnames)
        if missing_cols:
            log_error(logger, f"Missing required columns: {missing_cols}", "INVALID_DATA_SCHEMA")
            raise ValueError(f"Invalid CSV schema. Missing columns: {missing_cols}")

        for row in reader:
            # Convert numeric fields
            try:
                row['temperature'] = float(row['temperature'])
                row['mean_atomic_radius'] = float(row['mean_atomic_radius'])
                row['electronegativity_variance'] = float(row['electronegativity_variance'])
                row['valence_electron_count'] = float(row['valence_electron_count'])
                row['hume_rothery_concentration'] = float(row['hume_rothery_concentration'])
                data.append(row)
            except ValueError as e:
                log_error(logger, f"Failed to parse numeric values in row: {row}", "INVALID_DATA_SCHEMA")
                raise e

    log_info(logger, f"Loaded {len(data)} records from {path}")
    return data

def write_csv_output(data: List[Dict[str, Any]], output_path: Optional[str] = None) -> str:
    """
    Write the processed data to the final output CSV file with schema compliance.
    Returns the path to the written file.
    """
    path = output_path or OUTPUT_FILE
    
    # Ensure directory exists
    os.makedirs(os.path.dirname(path), exist_ok=True)

    with open(path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=REQUIRED_COLUMNS, extrasaction='ignore')
        writer.writeheader()
        writer.writerows(data)

    log_info(logger, f"Successfully wrote {len(data)} records to {path}")
    
    # Compute checksum for Constitution Principle III
    checksum = compute_file_sha256(path)
    log_info(logger, f"Checksum for {path}: {checksum}")
    
    return path

def main():
    """
    Main entry point for exporting descriptors to the final CSV.
    """
    try:
        log_info(logger, "Starting descriptor export process (T018)")
        
        # Load data from intermediate step
        data = load_processed_data()
        
        if not data:
            log_warning(logger, "No data to export. Exiting.")
            return 0

        # Write to final output location
        output_path = write_csv_output(data)
        
        # Verify the output file exists and is readable
        if not os.path.exists(output_path):
            log_error(logger, "Output file verification failed: File does not exist", "DATA_SOURCE_MISSING")
            return 1
        
        log_info(logger, f"T018 Completed: Data written to {output_path}")
        return 0

    except FileNotFoundError as e:
        log_error(logger, str(e), "DATA_SOURCE_MISSING")
        return 1
    except ValueError as e:
        log_error(logger, str(e), "INVALID_DATA_SCHEMA")
        return 1
    except Exception as e:
        log_error(logger, f"Unexpected error during export: {str(e)}", "INSUFFICIENT_POWER")
        return 1

if __name__ == '__main__':
    sys.exit(main())
