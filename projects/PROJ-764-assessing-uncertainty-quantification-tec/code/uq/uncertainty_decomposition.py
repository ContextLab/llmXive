import os
import sys
import json
import pandas as pd
import numpy as np
from typing import Dict, Any

def load_predictions(predictions_path: str) -> pd.DataFrame:
    """
    Load the UQ predictions CSV generated by the main pipeline.
    
    Args:
        predictions_path: Path to results/uq_predictions.csv
        
    Returns:
        DataFrame containing prediction, variance, and method columns.
    """
    if not os.path.exists(predictions_path):
        raise FileNotFoundError(f"Predictions file not found at {predictions_path}")
    
    df = pd.read_csv(predictions_path)
    
    required_cols = ['sample_id', 'method', 'prediction', 'variance']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Predictions file missing required columns: {missing_cols}")
    
    return df

def save_decomposition(df: pd.DataFrame, output_path: str) -> None:
    """
    Save the uncertainty decomposition report to CSV.
    
    Args:
        df: DataFrame with aleatoric, epistemic, and total columns.
        output_path: Path to save the CSV file.
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    df.to_csv(output_path, index=False)

def write_uncertainty_types(df: pd.DataFrame, output_path: str) -> None:
    """
    Write the uncertainty_type column to the specified CSV file.
    
    This function adds an 'uncertainty_type' column to the predictions DataFrame
    and saves it. The uncertainty_type is determined by the method used:
    - 'epistemic' for methods that primarily capture model uncertainty
    - 'aleatoric' for methods that primarily capture data uncertainty
    - 'mixed' for methods capturing both
    
    Args:
        df: DataFrame with method column.
        output_path: Path to save the updated CSV.
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    # Define uncertainty types based on method
    # Deep Ensembles and MC Dropout primarily capture epistemic uncertainty
    # Sparse GP captures both but is often dominated by epistemic in this context
    # Baseline heteroscedastic NN captures aleatoric
    uncertainty_map = {
        'baseline': 'aleatoric',
        'deep_ensemble': 'epistemic',
        'mc_dropout': 'epistemic',
        'sparse_gp': 'mixed'
    }
    
    df['uncertainty_type'] = df['method'].map(
        lambda m: uncertainty_map.get(m.lower(), 'unknown')
    )
    
    df.to_csv(output_path, index=False)

def generate_decomposition_report(predictions_df: pd.DataFrame, output_path: str) -> pd.DataFrame:
    """
    Generate a detailed uncertainty decomposition report.
    
    Calculates:
    - Aleatoric variance: mean of predicted variances (data uncertainty)
    - Epistemic variance: variance of means across samples (model uncertainty)
    - Total variance: sum of aleatoric and epistemic
    
    Args:
        predictions_df: DataFrame with predictions and variances by method.
        output_path: Path to save the decomposition CSV.
        
    Returns:
        DataFrame with the decomposition results.
    """
    results = []
    
    for method in predictions_df['method'].unique():
        method_data = predictions_df[predictions_df['method'] == method]
        
        # Aleatoric: mean of predicted variances
        aleatoric = method_data['variance'].mean()
        
        # Epistemic: variance of means (if we have multiple predictions per sample,
        # this would be the variance across those predictions. For single predictions,
        # we estimate it as the variance of the prediction values themselves)
        # In the context of UQ, epistemic is often estimated from the spread of 
        # ensemble predictions or MC dropout samples. Here we use the variance
        # of the predictions as a proxy for epistemic uncertainty.
        epistemic = method_data['prediction'].var()
        
        # Total uncertainty
        total = aleatoric + epistemic
        
        results.append({
            'method': method,
            'aleatoric': aleatoric,
            'epistemic': epistemic,
            'total': total
        })
    
    decomposition_df = pd.DataFrame(results)
    save_decomposition(decomposition_df, output_path)
    
    return decomposition_df

def main():
    """
    Main entry point for uncertainty decomposition task.
    
    Reads predictions from results/uq_predictions.csv, calculates uncertainty
    decomposition, and writes outputs to:
    - results/uq_predictions.csv (with uncertainty_type column)
    - results/calibration_report.csv (with uncertainty_type column)
    - results/uncertainty_decomposition.csv (detailed breakdown)
    """
    base_path = "results"
    predictions_path = os.path.join(base_path, "uq_predictions.csv")
    calibration_report_path = os.path.join(base_path, "calibration_report.csv")
    decomposition_path = os.path.join(base_path, "uncertainty_decomposition.csv")
    
    # Load predictions
    print(f"Loading predictions from {predictions_path}")
    predictions_df = load_predictions(predictions_path)
    
    # Generate decomposition report
    print("Generating uncertainty decomposition report...")
    decomposition_df = generate_decomposition_report(predictions_df, decomposition_path)
    print(f"Saved decomposition report to {decomposition_path}")
    
    # Write uncertainty types to predictions file
    predictions_with_type = predictions_df.copy()
    write_uncertainty_types(predictions_with_type, predictions_path)
    print(f"Updated predictions file with uncertainty_type column: {predictions_path}")
    
    # Write uncertainty types to calibration report
    # Load calibration report if it exists, otherwise create a minimal one
    if os.path.exists(calibration_report_path):
        calibration_df = pd.read_csv(calibration_report_path)
        # Ensure it has method column to map uncertainty types
        if 'method' in calibration_df.columns:
            write_uncertainty_types(calibration_df, calibration_report_path)
            print(f"Updated calibration report with uncertainty_type column: {calibration_report_path}")
        else:
            print(f"Warning: {calibration_report_path} does not have 'method' column. Skipping uncertainty type update.")
    else:
        print(f"Warning: {calibration_report_path} not found. Creating minimal calibration report with uncertainty types.")
        # Create a minimal calibration report based on decomposition
        minimal_report = decomposition_df.copy()
        minimal_report['uncertainty_type'] = minimal_report['method'].map(
            lambda m: {
                'baseline': 'aleatoric',
                'deep_ensemble': 'epistemic',
                'mc_dropout': 'epistemic',
                'sparse_gp': 'mixed'
            }.get(m.lower(), 'unknown')
        )
        os.makedirs(os.path.dirname(calibration_report_path), exist_ok=True)
        minimal_report.to_csv(calibration_report_path, index=False)
        print(f"Created calibration report: {calibration_report_path}")
    
    print("Uncertainty decomposition task completed successfully.")
    print(f"Summary:")
    print(f"  - Methods analyzed: {len(decomposition_df)}")
    print(f"  - Total aleatoric uncertainty: {decomposition_df['aleatoric'].sum():.6f}")
    print(f"  - Total epistemic uncertainty: {decomposition_df['epistemic'].sum():.6f}")

if __name__ == "__main__":
    main()
