from uq.metrics import expected_calibration_error, interval_score, sharpness

def setup_logger(name: str) -> logging.Logger:
    """Setup a logger for the module."""
    logger = logging.getLogger(name)
    logger.setLevel(logging.INFO)
    if not logger.handlers:
        handler = logging.StreamHandler(sys.stdout)
        formatter = logging.Formatter(
            '%(asctime)s - %(name)s - %(levelname)s - %(message)s'
        )
        handler.setFormatter(formatter)
        logger.addHandler(handler)
    return logger

logger = setup_logger("compute_calibration_report")

def load_predictions(base_path: str) -> pd.DataFrame:
    """
    Load the base predictions from the specified CSV file.
    Expects the file generated by T022b: results/uq_predictions.csv
    """
    if not os.path.exists(base_path):
        raise FileNotFoundError(f"Predictions file not found: {base_path}")
    
    df = pd.read_csv(base_path)
    
    required_cols = ['sample_id', 'method', 'prediction', 'variance', 
                     'lower_50', 'upper_50', 'lower_90', 'upper_90']
    
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns in predictions: {missing_cols}")
    
    return df

def compute_metrics_for_method(df: pd.DataFrame, method_name: str) -> Dict[str, float]:
    """
    Compute all calibration metrics for a specific method.
    
    Args:
        df: DataFrame containing predictions
        method_name: The method identifier to filter by
        
    Returns:
        Dictionary with metric names and values
    """
    method_df = df[df['method'] == method_name].copy()
    
    if method_df.empty:
        raise ValueError(f"No data found for method: {method_name}")
    
    # We need the ground truth to compute ECE and Coverage
    # Assuming the ground truth is available in the processed test set
    # or needs to be loaded from the original test split
    # For this implementation, we assume 'target' column exists or needs to be joined
    # Based on T022b, the input is results/uq_predictions.csv
    # We need to load the true values from the test set to compute coverage and ECE
    
    # Load true values from the processed test set
    test_data_path = "data/processed/raw_test.csv"
    if not os.path.exists(test_data_path):
        raise FileNotFoundError(f"Test data not found for metric computation: {test_data_path}")
    
    test_df = pd.read_csv(test_data_path)
    
    # Ensure sample_id matches
    if 'sample_id' not in test_df.columns:
        # Try to use index if sample_id is not present
        test_df = test_df.reset_index()
        test_df['sample_id'] = test_df['index']
    
    # Merge predictions with true values
    merged_df = method_df.merge(
        test_df[['sample_id', 'target']], 
        on='sample_id', 
        how='inner'
    )
    
    if merged_df.empty:
        raise ValueError("No matching samples found between predictions and test data")
    
    y_true = merged_df['target'].values
    y_pred = merged_df['prediction'].values
    variance = merged_df['variance'].values
    lower_50 = merged_df['lower_50'].values
    upper_50 = merged_df['upper_50'].values
    lower_90 = merged_df['lower_90'].values
    upper_90 = merged_df['upper_90'].values
    
    # Compute ECE
    ece = expected_calibration_error(y_true, y_pred, variance)
    
    # Compute Interval Score for 50% and 90% intervals
    # Using a weighted average or separate scores? 
    # Task schema asks for a single interval_score. We'll compute for 90% as standard
    # or average of both. Let's use 90% interval as it's more comprehensive.
    interval_score_90 = interval_score(y_true, lower_90, upper_90, alpha=0.1)
    
    # Compute Sharpness (mean width of 90% interval)
    sharp = sharpness(lower_90, upper_90)
    
    # Compute Coverage
    # 50% coverage: proportion of true values within [lower_50, upper_50]
    in_50 = (y_true >= lower_50) & (y_true <= upper_50)
    coverage_50 = float(np.mean(in_50))
    
    # 90% coverage: proportion of true values within [lower_90, upper_90]
    in_90 = (y_true >= lower_90) & (y_true <= upper_90)
    coverage_90 = float(np.mean(in_90))
    
    return {
        'method': method_name,
        'ece': float(ece),
        'interval_score': float(interval_score_90),
        'sharpness': float(sharp),
        'coverage_50': coverage_50,
        'coverage_90': coverage_90
    }

def main():
    """
    Main function to compute final metrics and save to results/calibration_report.csv.
    """
    # Define paths
    predictions_path = "results/uq_predictions.csv"
    output_path = "results/calibration_report.csv"
    
    # Ensure output directory exists
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    logger.info(f"Loading predictions from {predictions_path}")
    df = load_predictions(predictions_path)
    
    # Get unique methods
    methods = df['method'].unique().tolist()
    logger.info(f"Found methods: {methods}")
    
    # Compute metrics for each method
    results = []
    for method in methods:
        logger.info(f"Computing metrics for method: {method}")
        try:
            metrics = compute_metrics_for_method(df, method)
            results.append(metrics)
            logger.info(f"  ECE: {metrics['ece']:.4f}, Interval Score: {metrics['interval_score']:.4f}")
        except Exception as e:
            logger.error(f"Error computing metrics for {method}: {e}")
            # Still add a row with NaN for failed methods to maintain schema
            results.append({
                'method': method,
                'ece': np.nan,
                'interval_score': np.nan,
                'sharpness': np.nan,
                'coverage_50': np.nan,
                'coverage_90': np.nan
            })
    
    # Create DataFrame and save
    report_df = pd.DataFrame(results)
    
    # Ensure correct column order
    column_order = ['method', 'ece', 'interval_score', 'sharpness', 'coverage_50', 'coverage_90']
    report_df = report_df[column_order]
    
    # Save to CSV
    report_df.to_csv(output_path, index=False)
    logger.info(f"Calibration report saved to {output_path}")
    
    # Print summary
    print("\nCalibration Report Summary:")
    print(report_df.to_string(index=False))
    
    return report_df

if __name__ == "__main__":
    main()