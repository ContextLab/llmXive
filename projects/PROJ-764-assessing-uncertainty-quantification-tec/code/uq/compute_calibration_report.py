"""
Task T024: Compute final metrics and save to results/calibration_report.csv.

This script loads the uncertainty predictions from T022d (results/uq_predictions.csv),
groups them by method, and computes the following metrics for each method:
- ECE (Expected Calibration Error)
- Interval Score
- Sharpness
- Coverage_50 (empirical coverage of 50% interval)
- Coverage_90 (empirical coverage of 90% interval)

Output: results/calibration_report.csv with schema:
method, ece, interval_score, sharpness, coverage_50, coverage_90
"""
import os
import sys
import logging
import json
import pandas as pd
import numpy as np
from pathlib import Path
from typing import Dict, Any, Tuple

# Add project root to path for imports
project_root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(project_root / "code"))

from uq.metrics import expected_calibration_error, interval_score, sharpness

def setup_logger(name: str) -> logging.Logger:
    """Setup a logger for this module."""
    logger = logging.getLogger(name)
    logger.setLevel(logging.INFO)
    if not logger.handlers:
        handler = logging.StreamHandler(sys.stdout)
        formatter = logging.Formatter(
            '%(asctime)s - %(name)s - %(levelname)s - %(message)s'
        )
        handler.setFormatter(formatter)
        logger.addHandler(handler)
    return logger

logger = setup_logger("compute_calibration_report")

def load_predictions(input_path: str) -> pd.DataFrame:
    """
    Load the UQ predictions from the CSV generated by T022d.
    
    Expected columns: sample_id, method, prediction, variance, 
    lower_50, upper_50, lower_90, upper_90, aleatoric, epistemic, total, uncertainty_type
    """
    logger.info(f"Loading predictions from {input_path}")
    if not os.path.exists(input_path):
        raise FileNotFoundError(
            f"Input file not found: {input_path}. "
            "Ensure T022d has been executed successfully."
        )
    
    df = pd.read_csv(input_path)
    
    # Validate required columns
    required_cols = ['sample_id', 'method', 'prediction', 'variance', 
                    'lower_50', 'upper_50', 'lower_90', 'upper_90']
    missing = [col for col in required_cols if col not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns: {missing}")
    
    logger.info(f"Loaded {len(df)} predictions for methods: {df['method'].unique()}")
    return df

def compute_metrics_for_method(
    df: pd.DataFrame, 
    method: str,
    true_values: pd.Series
) -> Dict[str, float]:
    """
    Compute all calibration metrics for a single method.
    
    Args:
        df: Full predictions dataframe
        method: Method name to compute metrics for
        true_values: Series of true target values (formation energy)
    
    Returns:
        Dictionary with metrics: ece, interval_score, sharpness, coverage_50, coverage_90
    """
    method_df = df[df['method'] == method].copy()
    
    if len(method_df) == 0:
        logger.warning(f"No predictions found for method: {method}")
        return {
            'ece': np.nan,
            'interval_score': np.nan,
            'sharpness': np.nan,
            'coverage_50': np.nan,
            'coverage_90': np.nan
        }
    
    predictions = method_df['prediction'].values
    lower_50 = method_df['lower_50'].values
    upper_50 = method_df['upper_50'].values
    lower_90 = method_df['lower_90'].values
    upper_90 = method_df['upper_90'].values
    
    # Align true values with predictions
    # Assuming sample_id is consistent across the dataframe
    method_sample_ids = method_df['sample_id'].values
    method_true = true_values[true_values.index.isin(method_sample_ids)].values
    
    # Ensure alignment
    if len(method_true) != len(predictions):
        # Fallback: assume same order if sample_ids match
        if len(true_values) == len(predictions):
            method_true = true_values.values
        else:
            raise ValueError(
                f"True values length ({len(method_true)}) does not match "
                f"predictions length ({len(predictions)}) for method {method}"
            )
    
    # Compute ECE
    # ECE requires quantile bins. We'll use the provided intervals.
    ece_50 = expected_calibration_error(predictions, true_values, lower_50, upper_50, target_coverage=0.50)
    ece_90 = expected_calibration_error(predictions, true_values, lower_90, upper_90, target_coverage=0.90)
    ece = (ece_50 + ece_90) / 2.0
    
    # Compute Interval Score for both levels and average
    is_50 = interval_score(lower_50, upper_50, true_values, alpha=0.50)
    is_90 = interval_score(lower_90, upper_90, true_values, alpha=0.90)
    avg_interval_score = (is_50 + is_90) / 2.0
    
    # Compute Sharpness (average width of intervals)
    # Using the 90% interval as it's more informative
    avg_width_90 = np.mean(upper_90 - lower_90)
    avg_width_50 = np.mean(upper_50 - lower_50)
    # Report average of both widths
    avg_sharpness = (avg_width_50 + avg_width_90) / 2.0
    
    # Compute Coverage
    # 50% coverage: fraction of true values within [lower_50, upper_50]
    in_50 = (true_values >= lower_50) & (true_values <= upper_50)
    coverage_50 = np.mean(in_50)
    
    # 90% coverage: fraction of true values within [lower_90, upper_90]
    in_90 = (true_values >= lower_90) & (true_values <= upper_90)
    coverage_90 = np.mean(in_90)
    
    logger.info(
        f"Method {method}: ECE={ece:.4f}, IntervalScore={avg_interval_score:.4f}, "
        f"Sharpness={avg_sharpness:.4f}, Coverage50={coverage_50:.4f}, Coverage90={coverage_90:.4f}"
    )
    
    return {
        'ece': float(ece),
        'interval_score': float(avg_interval_score),
        'sharpness': float(avg_sharpness),
        'coverage_50': float(coverage_50),
        'coverage_90': float(coverage_90)
    }

def main():
    """Main entry point for T024."""
    logger.info("Starting T024: Compute Calibration Report")
    
    # Define paths
    input_path = project_root / "results" / "uq_predictions.csv"
    output_path = project_root / "results" / "calibration_report.csv"
    
    # Ensure results directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    try:
        # Load predictions
        df = load_predictions(str(input_path))
        
        # We need true values to compute metrics.
        # The uq_predictions.csv contains predictions on the test set.
        # We need to load the test set ground truth.
        # Based on T006a, the test set is at data/processed/raw_test.csv
        test_data_path = project_root / "data" / "processed" / "raw_test.csv"
        
        if not test_data_path.exists():
            raise FileNotFoundError(
                f"Test data not found at {test_data_path}. "
                "Please ensure T006a has been executed."
            )
        
        test_df = pd.read_csv(test_data_path)
        
        # The test data should have a target column (formation_energy) and sample_id
        if 'formation_energy' not in test_df.columns:
            # Try alternative column names
            target_col = None
            for col in ['formation_energy', 'target', 'energy', 'y']:
                if col in test_df.columns:
                    target_col = col
                    break
            if target_col is None:
                raise ValueError("Could not find target column in test data")
        else:
            target_col = 'formation_energy'
        
        # Create a mapping from sample_id to true value
        if 'sample_id' not in test_df.columns:
            # If no sample_id, assume order matches
            logger.warning("No sample_id in test data, assuming order matches predictions")
            true_values = test_df[target_col].values
            # Create a dummy index
            test_df['sample_id'] = range(len(test_df))
        else:
            true_values = test_df.set_index('sample_id')[target_col]
        
        # Get unique methods
        methods = df['method'].unique()
        logger.info(f"Computing metrics for methods: {methods}")
        
        results = []
        for method in methods:
            metrics = compute_metrics_for_method(df, method, true_values)
            metrics['method'] = method
            results.append(metrics)
        
        # Create output dataframe
        report_df = pd.DataFrame(results)
        
        # Ensure column order matches specification
        column_order = ['method', 'ece', 'interval_score', 'sharpness', 'coverage_50', 'coverage_90']
        report_df = report_df[column_order]
        
        # Save to CSV
        report_df.to_csv(output_path, index=False)
        logger.info(f"Saved calibration report to {output_path}")
        logger.info(f"Report contents:\n{report_df.to_string(index=False)}")
        
        return 0
        
    except Exception as e:
        logger.error(f"Error computing calibration report: {e}")
        raise

if __name__ == "__main__":
    sys.exit(main())
