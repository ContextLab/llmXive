"""
Compute final calibration metrics and save to results/calibration_report.csv.

This script consumes results/uq_predictions.csv (generated by T016/T022b)
and computes ECE, Interval Score, and Sharpness for each UQ method.
It outputs a summary CSV: results/calibration_report.csv.

Dependencies:
  - results/uq_predictions.csv must exist with columns:
    sample_id, method, prediction, variance, lower_50, upper_50, lower_90, upper_90, actual
"""

import os
import sys
import logging
import json
import pandas as pd
import numpy as np
from pathlib import Path

# Add project root to path for imports
project_root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(project_root))

from code.uq.metrics import expected_calibration_error, interval_score, sharpness

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)


def load_predictions(input_path: str) -> pd.DataFrame:
    """
    Load the UQ predictions CSV.
    Validates that required columns are present.
    """
    if not os.path.exists(input_path):
        raise FileNotFoundError(
            f"Input file not found: {input_path}. "
            "Please ensure T016/T022b have generated results/uq_predictions.csv."
        )

    df = pd.read_csv(input_path)
    required_cols = [
        'sample_id', 'method', 'prediction', 'variance',
        'lower_50', 'upper_50', 'lower_90', 'upper_90', 'actual'
    ]
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(
            f"Missing required columns in {input_path}: {missing}"
        )
    return df


def compute_metrics_for_method(
    df: pd.DataFrame,
    method_name: str
) -> dict:
    """
    Compute ECE, Interval Score, and Sharpness for a specific method.
    """
    subset = df[df['method'] == method_name].copy()

    if subset.empty:
        logger.warning(f"No data found for method: {method_name}")
        return {
            'method': method_name,
            'ece': np.nan,
            'interval_score_50': np.nan,
            'interval_score_90': np.nan,
            'sharpness': np.nan
        }

    y_true = subset['actual'].values
    y_pred = subset['prediction'].values
    variance = subset['variance'].values
    lower_50 = subset['lower_50'].values
    upper_50 = subset['upper_50'].values
    lower_90 = subset['lower_90'].values
    upper_90 = subset['upper_90'].values

    # ECE calculation (using 10 bins by default)
    ece = expected_calibration_error(y_true, y_pred, lower_90, upper_90, n_bins=10)

    # Interval Score for 50% and 90% intervals
    # Interval Score formula: (upper - lower) + 2/alpha * max(0, lower - y) + 2/alpha * max(0, y - upper)
    # alpha = 1 - confidence
    # For 50%: alpha = 0.5
    # For 90%: alpha = 0.1
    is_50 = interval_score(y_true, lower_50, upper_50, alpha=0.5)
    is_90 = interval_score(y_true, lower_90, upper_90, alpha=0.1)

    # Sharpness: mean width of the 90% interval
    sharp = sharpness(lower_90, upper_90)

    return {
        'method': method_name,
        'ece': ece,
        'interval_score_50': is_50,
        'interval_score_90': is_90,
        'sharpness': sharp
    }


def main():
    """
    Main entry point: load predictions, compute metrics per method, save report.
    """
    input_path = project_root / "results" / "uq_predictions.csv"
    output_path = project_root / "results" / "calibration_report.csv"

    # Ensure results directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    logger.info(f"Loading predictions from {input_path}")
    df = load_predictions(str(input_path))

    methods = df['method'].unique()
    logger.info(f"Found methods: {list(methods)}")

    results = []
    for method in methods:
        logger.info(f"Computing metrics for method: {method}")
        metrics = compute_metrics_for_method(df, method)
        results.append(metrics)

    report_df = pd.DataFrame(results)

    # Sort by ECE (lower is better)
    report_df = report_df.sort_values(by='ece', ascending=True)

    logger.info(f"Saving calibration report to {output_path}")
    report_df.to_csv(output_path, index=False)

    logger.info("Calibration report generation complete.")
    logger.info(f"Report contents:\n{report_df.to_string()}")

    return report_df


if __name__ == "__main__":
    main()