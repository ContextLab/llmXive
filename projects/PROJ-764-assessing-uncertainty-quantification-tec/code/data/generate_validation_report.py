import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any

# Add parent directory to path to allow imports from code/
project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from utils.logging_config import setup_logging

def setup_logger(name: str, log_file: str) -> logging.Logger:
    """Set up a logger that writes to a file and stdout."""
    logger = setup_logging(name, log_file)
    return logger

def load_exclusion_log(exclusion_log_path: Path) -> Dict[str, Any]:
    """
    Load the exclusion log JSON file generated by T006b2.
    
    Args:
        exclusion_log_path: Path to the exclusion_log.json file.
        
    Returns:
        Dictionary containing exclusion count and missing columns.
        
    Raises:
        FileNotFoundError: If the exclusion log file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    if not exclusion_log_path.exists():
        raise FileNotFoundError(
            f"Exclusion log file not found at {exclusion_log_path}. "
            "Ensure T006b2 (preprocess exclusion) has completed successfully."
        )
    
    with open(exclusion_log_path, 'r') as f:
        data = json.load(f)
        
    # Validate schema
    if 'excluded_count' not in data or 'missing_columns' not in data:
        raise ValueError(
            f"Invalid schema in {exclusion_log_path}. "
            "Expected keys: 'excluded_count', 'missing_columns'."
        )
        
    return data

def generate_validation_report(
    exclusion_data: Dict[str, Any],
    output_path: Path
) -> Dict[str, Any]:
    """
    Generate the validation report JSON file adhering to FR-010 schema.
    
    This function consumes the exclusion log data and writes a validation
    report with the count of excluded rows and list of missing variables.
    
    Args:
        exclusion_data: Dictionary from load_exclusion_log containing
                        'excluded_count' and 'missing_columns'.
        output_path: Path where the validation_report.json will be written.
                        
    Returns:
        The validation report dictionary that was written.
    """
    # Construct the validation report adhering to FR-010 schema
    validation_report = {
        "excluded_count": exclusion_data["excluded_count"],
        "missing_columns": exclusion_data["missing_columns"]
    }
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Write the report to disk
    with open(output_path, 'w') as f:
        json.dump(validation_report, f, indent=2)
        
    return validation_report

def main():
    """
    Main entry point for generating the validation report.
    
    Reads: data/processed/exclusion_log.json (from T006b3)
    Writes: data/validation_report.json (FR-010 compliant)
    """
    # Setup logging
    log_file = str(project_root / "logs" / "validation_report.log")
    logger = setup_logger("validation_report", log_file)
    
    logger.info("Starting validation report generation (T007)")
    
    # Define paths
    exclusion_log_path = project_root / "data" / "processed" / "exclusion_log.json"
    output_path = project_root / "data" / "validation_report.json"
    
    try:
        # Load exclusion data
        logger.info(f"Loading exclusion log from {exclusion_log_path}")
        exclusion_data = load_exclusion_log(exclusion_log_path)
        logger.info(f"Found {exclusion_data['excluded_count']} excluded rows")
        logger.info(f"Missing columns: {exclusion_data['missing_columns']}")
        
        # Generate validation report
        logger.info(f"Generating validation report at {output_path}")
        report = generate_validation_report(exclusion_data, output_path)
        
        logger.info("Validation report generation completed successfully")
        logger.info(f"Report content: {json.dumps(report)}")
        
        # Exit with success
        sys.exit(0)
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(1)
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in exclusion log: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Schema validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during validation report generation: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()