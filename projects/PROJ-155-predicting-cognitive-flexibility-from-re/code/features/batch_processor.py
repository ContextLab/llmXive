"""
Batch processing logic for User Story 2 to handle memory constraints.

This module implements a generator-based approach to process subjects in batches,
ensuring peak RAM usage stays below 7GB as required by the project constraints.
It integrates with the existing connectivity pipeline to process cohorts efficiently.
"""
import os
import gc
import logging
from typing import List, Dict, Generator, Optional, Any, Tuple
import numpy as np
import pandas as pd
from code.config import get_config
from code.data.paths import get_processed_path, get_raw_path, ensure_dir
from code.features.connectivity import extract_subject_connectivity_metrics
from code.utils.logging import log_warning, log_error

logger = logging.getLogger(__name__)

def get_valid_subject_list() -> List[str]:
    """
    Retrieve list of subjects that have passed US1 filtering (motion and behavioral).
    
    Reads from the final processed CSV generated by US1 pipeline.
    Returns a list of valid Subject IDs.
    """
    config = get_config()
    processed_path = get_processed_path()
    final_results_path = os.path.join(processed_path, "final_results.csv")
    
    if not os.path.exists(final_results_path):
        # Fallback: check if we can get from exclusion log or raw manifest
        # For now, raise error as US1 must be complete before US2
        raise FileNotFoundError(
            f"US1 output not found at {final_results_path}. "
            "Please complete User Story 1 (T015, T017) before running US2 batch processing."
        )
    
    df = pd.read_csv(final_results_path)
    # Ensure Subject_ID column exists
    if 'Subject_ID' not in df.columns:
        raise ValueError(f"Expected 'Subject_ID' column in {final_results_path}")
    
    return df['Subject_ID'].tolist()

def load_subject_timeseries(subject_id: str) -> Optional[np.ndarray]:
    """
    Load preprocessed ROI time series for a single subject.
    
    Args:
        subject_id: The subject identifier string.
        
    Returns:
        numpy array of shape (timepoints, rois) or None if not found.
    """
    processed_path = get_processed_path()
    # Assuming US1 preprocessing saves time series in a standard location
    # Path convention: data/processed/timeseries/{subject_id}.npy
    timeseries_path = os.path.join(
        processed_path, 
        "timeseries", 
        f"{subject_id}.npy"
    )
    
    if not os.path.exists(timeseries_path):
        logger.warning(f"Timeseries file not found for subject {subject_id} at {timeseries_path}")
        return None
    
    try:
        data = np.load(timeseries_path)
        return data
    except Exception as e:
        log_error(f"Failed to load timeseries for {subject_id}: {e}")
        return None

def process_subject_batch(
    subject_ids: List[str], 
    batch_size: int = 50
) -> Generator[Dict[str, Any], None, None]:
    """
    Process subjects in batches to manage memory usage.
    
    This generator yields results for each subject as they are processed,
    allowing for incremental saving and preventing memory accumulation.
    
    Args:
        subject_ids: List of subject IDs to process.
        batch_size: Number of subjects to process before forcing garbage collection.
        
    Yields:
        Dictionary containing subject metrics (Subject_ID, Variability_Metric, Entropy).
    """
    config = get_config()
    processed_count = 0
    
    logger.info(f"Starting batch processing for {len(subject_ids)} subjects with batch_size={batch_size}")
    
    for i in range(0, len(subject_ids), batch_size):
        batch_subjects = subject_ids[i:i + batch_size]
        logger.info(f"Processing batch {i//batch_size + 1}: subjects {i+1} to {min(i+batch_size, len(subject_ids))}")
        
        batch_results = []
        
        for subject_id in batch_subjects:
            try:
                # Load data for this subject
                timeseries = load_subject_timeseries(subject_id)
                
                if timeseries is None:
                    log_warning(f"Skipping {subject_id}: timeseries not found")
                    continue
                
                # Extract connectivity metrics (this is the memory-intensive part)
                # The function returns a dict with the metrics
                metrics = extract_subject_connectivity_metrics(timeseries, subject_id)
                
                if metrics:
                    batch_results.append(metrics)
                    processed_count += 1
                
                # Explicitly delete large arrays after processing
                del timeseries
                
            except Exception as e:
                log_error(f"Error processing subject {subject_id}: {e}")
                # Continue with next subject
                continue
        
        # Yield all results from this batch
        for result in batch_results:
            yield result
        
        # Force garbage collection after each batch to free memory
        gc.collect()
        
        # Log progress
        logger.info(f"Batch complete. Processed {processed_count} subjects so far.")
    
    logger.info(f"Batch processing complete. Total subjects processed: {processed_count}")

def run_batch_processing_pipeline(
    output_path: Optional[str] = None,
    batch_size: int = 50
) -> str:
    """
    Run the full batch processing pipeline for US2.
    
    This function orchestrates the batch processing of all valid subjects,
    computes connectivity metrics, and saves the intermediate results to CSV.
    
    Args:
        output_path: Optional path for the output metrics CSV. If None, uses default.
        batch_size: Number of subjects per batch (default 50).
        
    Returns:
        Path to the generated metrics CSV file.
    """
    config = get_config()
    
    if output_path is None:
        processed_path = get_processed_path()
        output_path = os.path.join(processed_path, "metrics.csv")
    
    ensure_dir(os.path.dirname(output_path))
    
    # Get list of valid subjects from US1
    subject_ids = get_valid_subject_list()
    
    if not subject_ids:
        raise ValueError("No valid subjects found. US1 pipeline may not have completed successfully.")
    
    logger.info(f"Found {len(subject_ids)} valid subjects to process")
    
    # Collect results from generator
    all_metrics = []
    
    for metrics in process_subject_batch(subject_ids, batch_size):
        all_metrics.append(metrics)
    
    # Create DataFrame and save
    if all_metrics:
        df = pd.DataFrame(all_metrics)
        
        # Ensure required columns exist
        required_cols = ['Subject_ID', 'Variability_Metric', 'Entropy']
        for col in required_cols:
            if col not in df.columns:
                raise ValueError(f"Missing required column: {col}")
        
        # Save to CSV
        df.to_csv(output_path, index=False)
        logger.info(f"Saved metrics for {len(df)} subjects to {output_path}")
    else:
        # Create empty DataFrame with correct schema
        df = pd.DataFrame(columns=required_cols)
        df.to_csv(output_path, index=False)
        logger.warning(f"No metrics generated. Created empty file at {output_path}")
    
    return output_path

def main():
    """Entry point for batch processing pipeline."""
    import argparse
    
    parser = argparse.ArgumentParser(description="Batch process US2 connectivity metrics")
    parser.add_argument("--batch-size", type=int, default=50, help="Number of subjects per batch")
    parser.add_argument("--output", type=str, default=None, help="Output file path for metrics CSV")
    
    args = parser.parse_args()
    
    try:
        result_path = run_batch_processing_pipeline(
            output_path=args.output,
            batch_size=args.batch_size
        )
        print(f"Batch processing complete. Results saved to: {result_path}")
    except Exception as e:
        log_error(f"Batch processing failed: {e}")
        raise

if __name__ == "__main__":
    main()