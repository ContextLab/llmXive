"""
Connectivity features computation for resting-state fMRI.

Implements sliding-window correlation, edge-wise metrics (SD, entropy),
and PCA dimensionality reduction to produce subject-level connectivity
metrics.

The pipeline reads ROI time‑series CSV files generated by the
preprocessing step (``data/processed/parcellated/<subject>_timeseries.csv``),
computes edge‑wise standard deviations across sliding windows, reduces the
high‑dimensional edge‑wise variability matrix with PCA, and writes the top
10 principal components to ``data/processed/metrics.csv``.
"""

import logging
import os
from collections.abc import Generator
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from sklearn.decomposition import PCA

from code.config import get_config
from code.data.paths import ensure_dir, get_processed_path

logger = logging.getLogger(__name__)


# ----------------------------------------------------------------------
# Helper functions for sliding‑window processing
# ----------------------------------------------------------------------

def _get_window_indices(
    n_timepoints: int,
    window_size: int,
    step_size: int
) -> Generator[tuple[int, int], None, None]:
    """
    Yield start/end indices for each sliding window.

    Parameters
    ----------
    n_timepoints : int
        Total number of time points in the time‑series.
    window_size : int
        Window length in *time points*.
    step_size : int
        Step length in *time points*.

    Yields
    ------
    tuple[int, int]
        (start_index, end_index) for each window.
    """
    start = 0
    while start + window_size <= n_timepoints:
        end = start + window_size
        yield start, end
        start += step_size


def compute_sliding_window_correlation(
    timeseries: np.ndarray,
    window_size: int,
    step_size: int
) -> Generator[np.ndarray, None, None]:
    """
    Generate Pearson correlation matrices for each sliding window.

    Parameters
    ----------
    timeseries : np.ndarray, shape (n_timepoints, n_rois)
        ROI time‑series.
    window_size : int
        Window length in time points.
    step_size : int
        Step length in time points.

    Yields
    ------
    np.ndarray, shape (n_rois, n_rois)
        Correlation matrix for the current window.
    """
    n_timepoints, n_rois = timeseries.shape

    if n_timepoints < window_size:
        logger.warning(
            f"Time series too short ({n_timepoints} < {window_size}); "
            "no windows will be generated."
        )
        return

    for start, end in _get_window_indices(n_timepoints, window_size, step_size):
        window_data = timeseries[start:end, :]
        # np.corrcoef expects variables in rows; we have timepoints x rois,
        # so transpose to rois x timepoints.
        corr_matrix = np.corrcoef(window_data.T)
        # Replace NaNs (possible if a ROI is constant) with zeros.
        corr_matrix = np.nan_to_num(corr_matrix, nan=0.0)
        yield corr_matrix


# ----------------------------------------------------------------------
# Edge‑wise metric computation
# ----------------------------------------------------------------------

def compute_edge_metrics(
    correlation_matrices: Generator[np.ndarray, None, None],
    n_rois: int
) -> tuple[np.ndarray, float]:
    """
    Compute edge‑wise standard deviation and Shannon entropy from a
    generator of correlation matrices.

    Parameters
    ----------
    correlation_matrices : generator
        Yields correlation matrices of shape (n_rois, n_rois).
    n_rois : int
        Number of ROIs (regions of interest).

    Returns
    -------
    edge_sd : np.ndarray, shape (n_edges,)
        Standard deviation for each unique edge (upper‑triangle, incl. diag).
    entropy : float
        Shannon entropy of the edge‑wise SD distribution.
    """
    # Accumulators for online mean / variance computation.
    edge_sums = np.zeros(n_rois * n_rois, dtype=np.float64)
    edge_sq_sums = np.zeros(n_rois * n_rois, dtype=np.float64)
    n_windows = 0

    for corr_matrix in correlation_matrices:
        if corr_matrix.shape != (n_rois, n_rois):
            logger.warning(f"Unexpected matrix shape: {corr_matrix.shape}")
            continue

        # Upper‑triangle (including diagonal) gives each edge once.
        upper_tri_idx = np.triu_indices(n_rois)
        edge_vals = corr_matrix[upper_tri_idx]

        edge_sums += edge_vals
        edge_sq_sums += edge_vals ** 2
        n_windows += 1

    if n_windows == 0:
        logger.error("No windows were processed; returning empty metrics.")
        return np.array([]), 0.0

    edge_means = edge_sums / n_windows
    edge_vars = (edge_sq_sums / n_windows) - (edge_means ** 2)
    edge_vars = np.maximum(edge_vars, 0.0)  # Numerical safety
    edge_sd = np.sqrt(edge_vars)

    # Shannon entropy of the non‑zero SD values.
    nonzero = edge_sd[edge_sd > 0]
    if nonzero.size == 0:
        entropy = 0.0
    else:
        prob = nonzero / nonzero.sum()
        prob = prob[prob > 0]
        entropy = -np.sum(prob * np.log2(prob))

    return edge_sd, entropy


# ----------------------------------------------------------------------
# Subject‑level extraction
# ----------------------------------------------------------------------

def extract_subject_connectivity_metrics(
    subject_id: str,
    timeseries: np.ndarray,
    window_size: int,
    step_size: int
) -> dict[str, Any]:
    """
    Compute edge‑wise variability metrics for a single subject.

    Returns a dictionary containing the raw edge‑wise SD vector (needed for
    later PCA) together with a scalar variability metric (mean SD) and the
    entropy of the SD distribution.
    """
    n_rois = timeseries.shape[1]

    corr_gen = compute_sliding_window_correlation(
        timeseries,
        window_size=window_size,
        step_size=step_size
    )

    edge_sd, entropy = compute_edge_metrics(corr_gen, n_rois)

    if edge_sd.size == 0:
        # Propagate NaNs so downstream steps can handle missing data.
        return {
            "Subject_ID": subject_id,
            "edge_sd": np.array([]),
            "Variability_Metric": np.nan,
            "Entropy": np.nan,
            "n_windows": 0,
        }

    variability_metric = float(np.mean(edge_sd))
    n_windows = int(np.sum(
        1 for _ in compute_sliding_window_correlation(
            timeseries,
            window_size=window_size,
            step_size=step_size
        )
    ))

    return {
        "Subject_ID": subject_id,
        "edge_sd": edge_sd,
        "Variability_Metric": variability_metric,
        "Entropy": entropy,
        "n_windows": n_windows,
    }


# ----------------------------------------------------------------------
# PCA reduction and CSV export
# ----------------------------------------------------------------------

def _run_pca_on_edge_sd(
    edge_sd_matrix: np.ndarray,
    n_components: int = 10
) -> np.ndarray:
    """
    Apply PCA to the edge‑wise SD matrix (subjects × edges) and return the
    projection onto the top ``n_components`` components.
    """
    pca = PCA(n_components=n_components, svd_solver="full")
    transformed = pca.fit_transform(edge_sd_matrix)
    logger.info(
        f"PCA completed: retained {n_components} components, explained variance "
        f"{np.sum(pca.explained_variance_ratio_):.4f}"
    )
    return transformed


def run_connectivity_pipeline(
    input_data: list[dict[str, Any]],
    output_path: str = None,
    n_pca_components: int = 10
) -> pd.DataFrame:
    """
    End‑to‑end pipeline for a list of subjects.

    Parameters
    ----------
    input_data : list of dict
        Each dict must contain ``Subject_ID`` and ``timeseries`` (numpy array).
    output_path : str, optional
        Where to write ``metrics.csv``. If ``None`` the file is not written.
    n_pca_components : int, default 10
        Number of PCA components to retain.

    Returns
    -------
    pd.DataFrame
        DataFrame with columns ``Subject_ID`` and ``PCA_Component_i``.
    """
    config = get_config()
    # Convert seconds to time points using the TR defined in the config.
    tr = config.get("tr", 0.72)
    window_sec = config.get("window_seconds", 60)
    step_sec = config.get("step_seconds", 1)
    window_size = int(window_sec / tr)
    step_size = int(step_sec / tr)

    subject_results = []
    edge_sd_list = []
    subject_ids = []

    for subj in input_data:
        sid = subj["Subject_ID"]
        ts = subj["timeseries"]
        logger.info(f"Processing subject {sid}")

        metrics = extract_subject_connectivity_metrics(
            subject_id=sid,
            timeseries=ts,
            window_size=window_size,
            step_size=step_size,
        )

        if metrics["edge_sd"].size == 0:
            logger.warning(f"No edge metrics for subject {sid}; skipping PCA entry.")
            continue

        subject_ids.append(sid)
        edge_sd_list.append(metrics["edge_sd"])
        subject_results.append(metrics)

    if not edge_sd_list:
        raise RuntimeError("No subjects produced edge‑wise SD vectors; cannot run PCA.")

    edge_sd_matrix = np.vstack(edge_sd_list)  # shape: (n_subjects, n_edges)
    pca_features = _run_pca_on_edge_sd(edge_sd_matrix, n_components=n_pca_components)

    # Build final DataFrame.
    pca_columns = [f"PCA_Component_{i+1}" for i in range(n_pca_components)]
    df = pd.DataFrame(pca_features, columns=pca_columns)
    df.insert(0, "Subject_ID", subject_ids)

    if output_path:
        ensure_dir(os.path.dirname(output_path))
        df.to_csv(output_path, index=False)
        logger.info(f"Metrics saved to {output_path}")

    return df


# ----------------------------------------------------------------------
# CLI entry point – discovers parcellated CSVs automatically
# ----------------------------------------------------------------------

def _load_parcellated_timeseries(csv_path: Path) -> tuple[str, np.ndarray]:
    """
    Load a single parcellated CSV produced by ``preprocess_subject``.

    Returns
    -------
    subject_id : str
        Identifier extracted from the filename (everything before the first
        underscore).
    timeseries : np.ndarray, shape (n_timepoints, n_rois)
    """
    df = pd.read_csv(csv_path)
    # The first column is ``Subject_ID`` (repeated for every row) – drop it.
    if "Subject_ID" in df.columns:
        df = df.drop(columns=["Subject_ID"])
    # ``Timepoint`` column is also not part of the ROI data.
    if "Timepoint" in df.columns:
        df = df.drop(columns=["Timepoint"])
    timeseries = df.values.astype(np.float32)
    subject_id = csv_path.stem.replace("_timeseries", "")
    return subject_id, timeseries


def main() -> int:
    """
    CLI driver used by ``python -m code.features.connectivity``.

    It scans ``data/processed/parcellated`` for ``*_timeseries.csv`` files,
    runs the connectivity pipeline, and writes the result to
    ``data/processed/metrics.csv``.
    """
    logging.basicConfig(level=logging.INFO)
    logger.info("Starting connectivity feature extraction...")

    parcellated_dir = Path(get_processed_path()) / "parcellated"
    if not parcellated_dir.is_dir():
        logger.error(f"Parcellated directory not found: {parcellated_dir}")
        return 1

    csv_files = sorted(parcellated_dir.glob("*_timeseries.csv"))
    if not csv_files:
        logger.error(f"No parcellated time‑series CSVs found in {parcellated_dir}")
        return 1

    input_data = []
    for csv_path in csv_files:
        try:
            subject_id, ts = _load_parcellated_timeseries(csv_path)
            input_data.append({"Subject_ID": subject_id, "timeseries": ts})
        except Exception as e:
            logger.warning(f"Failed to load {csv_path}: {e}")
            continue

    if not input_data:
        logger.error("No valid subject data could be loaded.")
        return 1

    output_path = os.path.join(get_processed_path(), "metrics.csv")
    try:
        run_connectivity_pipeline(
            input_data,
            output_path=output_path,
            n_pca_components=10,
        )
    except Exception as e:
        logger.error(f"Connectivity pipeline failed: {e}")
        return 1

    logger.info("Connectivity feature extraction completed successfully.")
    return 0


if __name__ == "__main__":
    exit(main())
