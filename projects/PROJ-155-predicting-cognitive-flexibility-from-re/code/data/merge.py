"""
Merge module for combining neuroimaging features with behavioral data.

This module implements the merging logic for User Story 1, specifically:
- Loading neuroimaging features (parcellated time-series statistics)
- Loading behavioral scores (NIH Toolbox DCCS scores)
- Merging datasets on Subject_ID
- Validating the merged dataset schema
"""

import os
import logging
import pandas as pd
from typing import Optional, Tuple, List, Dict, Any

from code.data.paths import get_processed_path, get_raw_path, ensure_dir
from code.utils.logging import log_error, log_warning, init_logging, log_exclusion
from code.data.behavioral_validator import load_behavioral_scores

# Initialize logging
logger = logging.getLogger(__name__)

def load_neuro_features(processed_path: Optional[str] = None) -> pd.DataFrame:
    """
    Load neuroimaging features from processed data.
    
    This function reads the parcellated time-series statistics or connectivity
    metrics that have been computed in previous pipeline stages.
    
    Args:
        processed_path: Optional path to processed data directory. If None,
                      uses the path from configuration.
                      
    Returns:
        pd.DataFrame: DataFrame containing neuroimaging features with at least
                     'Subject_ID' column.
                     
    Raises:
        FileNotFoundError: If the expected neuro features file is not found.
        ValueError: If the file exists but cannot be read as CSV.
    """
    if processed_path is None:
        processed_path = get_processed_path()
        
    # Look for the metrics file generated by US2 (T026) or intermediate features
    metrics_file = os.path.join(processed_path, "metrics.csv")
    features_file = os.path.join(processed_path, "features.csv")
    time_series_stats_file = os.path.join(processed_path, "time_series_stats.csv")
    
    # Priority order for loading neuro features
    possible_files = [metrics_file, features_file, time_series_stats_file]
    
    for file_path in possible_files:
        if os.path.exists(file_path):
            try:
                df = pd.read_csv(file_path)
                if 'Subject_ID' in df.columns:
                    logger.info(f"Loaded neuro features from {file_path} with {len(df)} subjects")
                    return df
                else:
                    logger.warning(f"File {file_path} exists but missing 'Subject_ID' column. Skipping.")
            except Exception as e:
                logger.error(f"Error reading {file_path}: {e}")
    
    # If no processed features exist, try to load raw parcellated data
    # This is a fallback for early pipeline stages
    raw_path = get_raw_path()
    parcellated_dir = os.path.join(raw_path, "parcellated")
    
    if os.path.exists(parcellated_dir):
        # Try to find any CSV with subject data
        csv_files = [f for f in os.listdir(parcellated_dir) if f.endswith('.csv')]
        if csv_files:
            # Load the first available file (should be consistent format)
            sample_file = os.path.join(parcellated_dir, csv_files[0])
            try:
                df = pd.read_csv(sample_file)
                if 'Subject_ID' in df.columns:
                    logger.info(f"Loaded raw parcellated data from {sample_file}")
                    return df
            except Exception as e:
                logger.error(f"Error reading raw parcellated data: {e}")
    
    # If still no data, check if we have the final results from a previous run
    final_results_file = os.path.join(processed_path, "final_results.csv")
    if os.path.exists(final_results_file):
        try:
            df = pd.read_csv(final_results_file)
            if 'Subject_ID' in df.columns:
                logger.info(f"Loaded final results as neuro features from {final_results_file}")
                return df
        except Exception as e:
            logger.error(f"Error reading final results: {e}")
    
    raise FileNotFoundError(
        "No neuroimaging features found. Expected one of: "
        f"{', '.join(possible_files)}. "
        "Ensure US2 (connectivity metrics) or US1 preprocessing has been completed."
    )

def load_behavioral_scores(raw_path: Optional[str] = None) -> pd.DataFrame:
    """
    Load behavioral scores from the NIH Toolbox data.
    
    This function uses the behavioral_validator module to load the DCCS scores
    (Dimensional Change Card Sort) which measure cognitive flexibility.
    
    Args:
        raw_path: Optional path to raw data directory. If None, uses the
                 path from configuration.
                 
    Returns:
        pd.DataFrame: DataFrame containing behavioral scores with columns:
                     - Subject_ID
                     - Flexibility_Score (DCCS score)
                     - Age
                     - Sex
    """
    return load_behavioral_scores(raw_path)

def merge_datasets(
    neuro_df: pd.DataFrame,
    behavioral_df: pd.DataFrame,
    on: str = "Subject_ID"
) -> pd.DataFrame:
    """
    Merge neuroimaging and behavioral datasets.
    
    Performs an inner join to keep only subjects present in both datasets.
    
    Args:
        neuro_df: DataFrame with neuroimaging features.
        behavioral_df: DataFrame with behavioral scores.
        on: Column name to join on (default: "Subject_ID").
            
    Returns:
        pd.DataFrame: Merged DataFrame with columns from both datasets.
    """
    if on not in neuro_df.columns:
        raise ValueError(f"Column '{on}' not found in neuro DataFrame. "
                       f"Available columns: {neuro_df.columns.tolist()}")
    
    if on not in behavioral_df.columns:
        raise ValueError(f"Column '{on}' not found in behavioral DataFrame. "
                       f"Available columns: {behavioral_df.columns.tolist()}")
    
    # Normalize subject IDs to string for consistent merging
    neuro_df = neuro_df.copy()
    behavioral_df = behavioral_df.copy()
    neuro_df[on] = neuro_df[on].astype(str).str.strip()
    behavioral_df[on] = behavioral_df[on].astype(str).str.strip()
    
    merged = pd.merge(
        neuro_df,
        behavioral_df,
        on=on,
        how='inner'
    )
    
    logger.info(f"Merged {len(neuro_df)} neuro and {len(behavioral_df)} behavioral "
               f"records into {len(merged)} subjects")
    
    return merged

def validate_merged_schema(df: pd.DataFrame) -> Tuple[bool, List[str]]:
    """
    Validate that the merged DataFrame has the required schema.
    
    Required columns for US1 completion:
    - Subject_ID (str)
    - Mean_FD (float) - from motion preprocessing
    - Age (int) - from behavioral data
    - Sex (str) - from behavioral data
    - Flexibility_Score (float) - DCCS score from behavioral data
    
    Args:
        df: Merged DataFrame to validate.
        
    Returns:
        Tuple[bool, List[str]]: (is_valid, list_of_missing_columns)
    """
    required_columns = {
        'Subject_ID': str,
        'Mean_FD': float,
        'Age': int,
        'Sex': str,
        'Flexibility_Score': float
    }
    
    missing_columns = []
    type_mismatches = []
    
    for col, expected_type in required_columns.items():
        if col not in df.columns:
            missing_columns.append(col)
        else:
            # Check if column can be cast to expected type
            try:
                if expected_type == int:
                    pd.to_numeric(df[col], errors='raise')
                elif expected_type == float:
                    pd.to_numeric(df[col], errors='raise')
            except (ValueError, TypeError):
                type_mismatches.append(f"{col} (expected {expected_type.__name__})")
    
    is_valid = len(missing_columns) == 0 and len(type_mismatches) == 0
    
    if not is_valid:
        error_msg = []
        if missing_columns:
            error_msg.append(f"Missing columns: {missing_columns}")
        if type_mismatches:
            error_msg.append(f"Type mismatches: {type_mismatches}")
        logger.error("Schema validation failed: " + "; ".join(error_msg))
    
    return is_valid, missing_columns + type_mismatches

def run_merge_pipeline(
    output_filename: str = "merged_data.csv",
    validate: bool = True
) -> Tuple[pd.DataFrame, Optional[str]]:
    """
    Run the complete merge pipeline.
    
    1. Load neuroimaging features
    2. Load behavioral scores
    3. Merge datasets
    4. Validate schema (optional)
    5. Save to processed directory
    
    Args:
        output_filename: Name of the output CSV file.
        validate: Whether to validate the merged schema before saving.
                
    Returns:
        Tuple[pd.DataFrame, Optional[str]]: (merged_dataframe, error_message)
        If successful, error_message is None.
        If failed, returns None for dataframe and error message string.
    """
    try:
        # Initialize logging
        init_logging()
        
        processed_path = get_processed_path()
        ensure_dir(processed_path)
        
        # Step 1: Load neuro features
        logger.info("Loading neuroimaging features...")
        neuro_df = load_neuro_features(processed_path)
        
        # Step 2: Load behavioral scores
        logger.info("Loading behavioral scores...")
        behavioral_df = load_behavioral_scores()
        
        # Step 3: Merge datasets
        logger.info("Merging datasets...")
        merged_df = merge_datasets(neuro_df, behavioral_df)
        
        if merged_df.empty:
            error_msg = "Merge resulted in empty DataFrame. No subjects found in both datasets."
            logger.error(error_msg)
            return None, error_msg
        
        # Step 4: Validate schema
        if validate:
            logger.info("Validating merged schema...")
            is_valid, issues = validate_merged_schema(merged_df)
            
            if not is_valid:
                error_msg = f"Schema validation failed: {issues}"
                logger.error(error_msg)
                return None, error_msg
            
            logger.info("Schema validation passed.")
        
        # Step 5: Save to file
        output_path = os.path.join(processed_path, output_filename)
        merged_df.to_csv(output_path, index=False)
        logger.info(f"Saved merged data to {output_path} with {len(merged_df)} subjects")
        
        return merged_df, None
        
    except FileNotFoundError as e:
        error_msg = f"Data file not found: {e}"
        logger.error(error_msg)
        return None, error_msg
    except Exception as e:
        error_msg = f"Unexpected error during merge pipeline: {e}"
        logger.error(error_msg, exc_info=True)
        return None, error_msg

def main():
    """
    Main entry point for running the merge pipeline from command line.
    """
    import argparse
    
    parser = argparse.ArgumentParser(
        description="Merge neuroimaging features with behavioral data"
    )
    parser.add_argument(
        "--output",
        type=str,
        default="merged_data.csv",
        help="Output filename (default: merged_data.csv)"
    )
    parser.add_argument(
        "--no-validate",
        action="store_true",
        help="Skip schema validation"
    )
    
    args = parser.parse_args()
    
    merged_df, error = run_merge_pipeline(
        output_filename=args.output,
        validate=not args.no_validate
    )
    
    if error:
        print(f"Merge failed: {error}")
        exit(1)
    else:
        print(f"Merge successful. Output saved to data/processed/{args.output}")
        print(f"Subjects merged: {len(merged_df)}")
        exit(0)

if __name__ == "__main__":
    main()