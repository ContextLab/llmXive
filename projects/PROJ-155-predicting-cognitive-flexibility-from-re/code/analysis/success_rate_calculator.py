"""
Success Rate Calculator (T015a)

Calculates the final success rate (SC-001) by:
1. Reading final_results.csv to count successfully processed subjects.
2. Reading exclusion_log.csv to count excluded subjects.
3. Reading the manifest (or total input count) to determine the denominator.
4. Computing pro_processed = Total_Processed / Total_Input.
5. Updating data/results/regression_summary.json with the new metric.
"""
import os
import json
import logging
from typing import Dict, Any, Optional, Tuple
import pandas as pd

from code.data.paths import get_processed_path, get_results_path, get_raw_path, ensure_dir
from code.utils.logging import log_error, log_warning, init_logging

logger = logging.getLogger(__name__)

def load_final_results() -> pd.DataFrame:
    """Load the final results CSV generated by T036."""
    results_path = get_processed_path()
    file_path = os.path.join(results_path, "final_results.csv")
    
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"final_results.csv not found at {file_path}. "
                                "Ensure T036 has been completed successfully.")
    
    df = pd.read_csv(file_path)
    logger.info(f"Loaded {len(df)} subjects from final_results.csv")
    return df

def load_exclusion_log() -> pd.DataFrame:
    """Load the exclusion log CSV generated by T015/T017."""
    processed_path = get_processed_path()
    file_path = os.path.join(processed_path, "exclusion_log.csv")
    
    if not os.path.exists(file_path):
        # If the file doesn't exist, it might mean no exclusions were logged,
        # or a previous step failed. We treat this as 0 exclusions for the calculation
        # but log a warning.
        logger.warning(f"exclusion_log.csv not found at {file_path}. Assuming 0 exclusions.")
        return pd.DataFrame(columns=["Subject_ID", "Exclusion_Reason", "Mean_FD"])
    
    df = pd.read_csv(file_path)
    logger.info(f"Loaded {len(df)} exclusions from exclusion_log.csv")
    return df

def get_total_input_count() -> int:
    """
    Determine the total number of input subjects.
    
    We look for a manifest file or a count file in data/raw/ that indicates
    the total number of subjects attempted. If not found, we derive it from
    the sum of processed + excluded, assuming the pipeline attempted all subjects.
    """
    raw_path = get_raw_path()
    manifest_path = os.path.join(raw_path, "manifest.json")
    count_path = os.path.join(raw_path, "subject_count.txt")
    
    # Try to load from manifest if it exists
    if os.path.exists(manifest_path):
        try:
            with open(manifest_path, 'r') as f:
                manifest = json.load(f)
                # Assuming manifest has a 'subjects' list or 'total_count'
                if 'total_count' in manifest:
                    return int(manifest['total_count'])
                elif 'subjects' in manifest:
                    return len(manifest['subjects'])
        except (json.JSONDecodeError, KeyError) as e:
            logger.warning(f"Could not parse manifest for count: {e}")
    
    # Try count file
    if os.path.exists(count_path):
        try:
            with open(count_path, 'r') as f:
                return int(f.read().strip())
        except ValueError:
            logger.warning("Could not parse subject_count.txt")

    # Fallback: Derive from processed + excluded
    # This assumes the pipeline attempted to process every subject it had access to.
    logger.info("Deriving total input count from processed and excluded counts.")
    return -1 # Placeholder to force derivation below

def calculate_success_rate(processed_count: int, excluded_count: int, total_input: int) -> float:
    """Calculate the proportion of processed subjects."""
    if total_input <= 0:
        # If we couldn't get a total input, we calculate based on what we have
        # This is a fallback for when the manifest is missing
        total_input = processed_count + excluded_count
        
    if total_input == 0:
        return 0.0
    
    return processed_count / total_input

def update_regression_summary(pro_processed: float) -> None:
    """Update the regression_summary.json with the new success rate metric."""
    results_path = get_results_path()
    file_path = os.path.join(results_path, "regression_summary.json")
    
    if not os.path.exists(file_path):
        # If the summary doesn't exist, create a new one with just this metric
        logger.warning("regression_summary.json not found. Creating new file.")
        summary_data = {
            "pro_processed": pro_processed,
            "message": "Success rate calculated. Other regression metrics missing."
        }
    else:
        with open(file_path, 'r') as f:
            summary_data = json.load(f)
        
        summary_data["pro_processed"] = pro_processed
        logger.info(f"Updated regression_summary.json with pro_processed: {pro_processed}")
    
    ensure_dir(file_path)
    with open(file_path, 'w') as f:
        json.dump(summary_data, f, indent=2)

def run_success_rate_pipeline() -> Dict[str, Any]:
    """
    Main pipeline function for T015a.
    
    1. Loads final_results.csv
    2. Loads exclusion_log.csv
    3. Determines total input count
    4. Calculates pro_processed
    5. Updates regression_summary.json
    """
    init_logging()
    logger.info("Starting Success Rate Calculation (T015a)...")
    
    # 1. Load processed data
    final_results = load_final_results()
    processed_count = len(final_results)
    
    # 2. Load exclusions
    exclusion_log = load_exclusion_log()
    excluded_count = len(exclusion_log)
    
    # 3. Get total input
    total_input = get_total_input_count()
    if total_input == -1:
        total_input = processed_count + excluded_count
        logger.info(f"Using derived total input: {total_input}")
    
    # 4. Calculate success rate
    pro_processed = calculate_success_rate(processed_count, excluded_count, total_input)
    
    logger.info(f"Success Rate Calculation Results:")
    logger.info(f"  Processed: {processed_count}")
    logger.info(f"  Excluded: {excluded_count}")
    logger.info(f"  Total Input: {total_input}")
    logger.info(f"  pro_processed: {pro_processed:.4f}")
    
    # 5. Update summary
    update_regression_summary(pro_processed)
    
    return {
        "processed_count": processed_count,
        "excluded_count": excluded_count,
        "total_input": total_input,
        "pro_processed": pro_processed
    }

def main():
    """Entry point for command line execution."""
    try:
        result = run_success_rate_pipeline()
        print(f"Success rate calculation complete. pro_processed = {result['pro_processed']:.4f}")
    except Exception as e:
        log_error(f"Failed to calculate success rate: {e}")
        raise

if __name__ == "__main__":
    main()