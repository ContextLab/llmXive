"""
Integration test for permutation test logic in User Story 3.

This test verifies the permutation test implementation in code/analysis/permutation.py.
It generates a small mock dataset (real data simulation) and ensures:
1. The permutation test runs without error.
2. The observed statistic is calculated correctly.
3. The null distribution is generated by shuffling labels.
4. The p-value is calculated correctly (proportion of null stats >= observed stat).
5. The output format matches the expected schema.

Note: This is an integration test. It does not test the full HCP dataset but
verifies the logic against a controlled, small dataset that mimics the structure
of the real processed data.
"""
