def test_permutation_test_null_hypothesis():
    """
    Test that when there is NO relationship (pure noise), the p-value is not significant.
    This validates that the test doesn't produce false positives.
    """
    set_seed(999)
    n_subjects = 30
    
    # Create data with NO correlation between Variability and Flexibility
    df = pd.DataFrame({
        'Subject_ID': [f'SUBJ_{i:04d}' for i in range(n_subjects)],
        'Variability_Metric': np.random.normal(0.05, 0.01, n_subjects),
        'Flexibility_Score': np.random.normal(100, 15, n_subjects),  # Independent noise
        'Age': np.random.randint(18, 80, n_subjects),
        'Sex': np.random.randint(0, 2, n_subjects),
        'Mean_FD': np.random.normal(0.15, 0.05, n_subjects)
    })
    
    # Run permutation test with many iterations for stability
    result = run_permutation_test(
        df=df,
        target_col='Flexibility_Score',
        predictor_col='Variability_Metric',
        covariate_cols=['Age', 'Sex', 'Mean_FD'],
        n_permutations=500,
        random_seed=42
    )
    
    # With no true relationship, the observed statistic should be near 0
    # and the p-value should be high (not significant) most of the time.
    # We assert that it's not significant at alpha=0.05 (which is expected for null data)
    # Note: Due to randomness, it *could* be significant by chance (Type I error),
    # but with 500 permutations and no true effect, it's highly likely to be non-significant.
    # We check that the observed statistic is small relative to the null distribution spread.
    
    std_null = np.std(result['null_distribution'])
    # Observed stat should be within ~2 standard deviations of the null mean (which is ~0)
    # This is a soft check to ensure the test is behaving correctly under the null
    assert abs(result['observed_statistic']) < 2.5 * std_null, "Observed stat should be consistent with null distribution under H0"


def test_permutation_test_with_realistic_correlation():
    """
    Test that the permutation test detects a strong correlation if one exists.
    We inject a strong correlation and expect a low p-value.
    """
    set_seed(777)
    n_subjects = 50
    
    variability = np.random.normal(0.05, 0.01, n_subjects)
    # Strong positive correlation
    flexibility = 200 * variability + np.random.normal(100, 5, n_subjects)
    
    df = pd.DataFrame({
        'Subject_ID': [f'SUBJ_{i:04d}' for i in range(n_subjects)],
        'Variability_Metric': variability,
        'Flexibility_Score': flexibility,
        'Age': np.random.randint(18, 80, n_subjects),
        'Sex': np.random.randint(0, 2, n_subjects),
        'Mean_FD': np.random.normal(0.15, 0.05, n_subjects)
    })
    
    result = run_permutation_test(
        df=df,
        target_col='Flexibility_Score',
        predictor_col='Variability_Metric',
        covariate_cols=['Age', 'Sex', 'Mean_FD'],
        n_permutations=1000,
        random_seed=42
    )
    
    # With strong correlation, observed stat should be large
    # and p-value should be very small (< 0.05)
    assert result['p_value'] < 0.05, "Strong correlation should yield significant p-value"
    assert result['is_significant'] == True, "is_significant flag should be True"
    # The observed statistic should be larger than most of the null distribution
    assert result['observed_statistic'] > np.percentile(result['null_distribution'], 95), "Observed stat should be in top 5% of null"


