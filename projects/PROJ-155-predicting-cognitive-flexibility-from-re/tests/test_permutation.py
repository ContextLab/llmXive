def create_mock_processed_data(n_subjects: int = 50, random_seed: int = 42) -> pd.DataFrame:
    """
    Creates a mock DataFrame mimicking data/processed/metrics.csv merged with covariates.
    This simulates the input for the regression/permutation test without needing real HCP data.
    
    Columns expected by permutation logic:
    - Subject_ID
    - Variability_Metric
    - Flexibility_Score (target)
    - Age
    - Sex (encoded as 0/1)
    - Mean_FD (covariate)
    """
    set_seed(random_seed)
    
    data = {
        'Subject_ID': [f'SUBJ_{i:04d}' for i in range(n_subjects)],
        'Variability_Metric': np.random.normal(loc=0.05, scale=0.01, size=n_subjects),
        'Flexibility_Score': np.random.normal(loc=100.0, scale=15.0, size=n_subjects),
        'Age': np.random.randint(18, 80, size=n_subjects),
        'Sex': np.random.randint(0, 2, size=n_subjects),
        'Mean_FD': np.random.normal(loc=0.15, scale=0.05, size=n_subjects)
    }
    
    # Introduce a weak positive correlation for Variability_Metric and Flexibility_Score
    # to ensure the test has something to detect (observed stat != 0)
    data['Flexibility_Score'] += 50 * (data['Variability_Metric'] - 0.05)
    
    df = pd.DataFrame(data)
    return df


def test_calculate_test_statistic():
    """Test that the test statistic (slope of variability) is calculated correctly."""
    df = create_mock_processed_data(n_subjects=20, random_seed=42)
    
    # The function should return the slope coefficient for Variability_Metric
    # from a linear model: Flexibility ~ Variability + Age + Sex + FD
    stat = calculate_test_statistic(df, target_col='Flexibility_Score', 
                                    predictor_col='Variability_Metric', 
                                    covariate_cols=['Age', 'Sex', 'Mean_FD'])
    
    assert isinstance(stat, float), "Test statistic must be a float"
    assert not np.isnan(stat), "Test statistic must not be NaN"
    # With the mock data correlation, we expect a non-zero slope
    # The exact value depends on the random seed, but it should be positive
    assert stat > 0.0, "Expected positive slope in mock data with injected correlation"


def test_run_permutation_test_basic():
    """Test the full permutation test pipeline with a small number of iterations."""
    df = create_mock_processed_data(n_subjects=30, random_seed=42)
    
    n_permutations = 100  # Small number for fast testing
    
    result = run_permutation_test(
        df=df,
        target_col='Flexibility_Score',
        predictor_col='Variability_Metric',
        covariate_cols=['Age', 'Sex', 'Mean_FD'],
        n_permutations=n_permutations,
        random_seed=42
    )
    
    # Verify output structure
    assert isinstance(result, dict), "Result must be a dictionary"
    assert 'observed_statistic' in result, "Result must contain 'observed_statistic'"
    assert 'p_value' in result, "Result must contain 'p_value'"
    assert 'null_distribution' in result, "Result must contain 'null_distribution'"
    assert 'is_significant' in result, "Result must contain 'is_significant'"
    
    # Verify types
    assert isinstance(result['observed_statistic'], float)
    assert isinstance(result['p_value'], float)
    assert isinstance(result['null_distribution'], np.ndarray)
    assert isinstance(result['is_significant'], bool)
    
    # Verify dimensions
    assert len(result['null_distribution']) == n_permutations, "Null distribution size must match n_permutations"
    
    # Verify p-value calculation
    # p-value = (count(null >= observed) + 1) / (n_permutations + 1)
    # We can't check exact value without knowing the distribution, but we can check range
    assert 0.0 <= result['p_value'] <= 1.0, "P-value must be between 0 and 1"


