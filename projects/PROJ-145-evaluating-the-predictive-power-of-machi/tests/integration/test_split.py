"""
Integration test for dataset split logic (T011).
Verifies no overlap between train, holdout, and novel sets.

This test assumes the following artifacts have been generated by code/data_ingestion.py:
- data/processed/heas_train.csv
- data/processed/holdout_known.csv
- data/processed/true_novel.csv

It verifies:
1. All three files exist.
2. The 'composition_string' column exists in all files.
3. There is no overlap between the sets (disjoint).
4. The holdout set contains entries that would be 'known' (exists in source index logic implied by generation).
5. The novel set contains entries that are 'unknown' (not in source index logic implied by generation).

Note: Since T012-T015 (generation scripts) are not yet implemented in this specific task context,
this test is written to be runnable once those scripts produce the data.
"""
import os
import pandas as pd
import pytest
from pathlib import Path

# Project root relative to this file
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
DATA_PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"

TRAIN_FILE = DATA_PROCESSED_DIR / "heas_train.csv"
HOLDOUT_FILE = DATA_PROCESSED_DIR / "holdout_known.csv"
NOVEL_FILE = DATA_PROCESSED_DIR / "true_novel.csv"

REQUIRED_COLUMNS = ["composition_string"]

def get_composition_set(file_path: Path) -> set:
    """Load a CSV and return a set of composition strings."""
    if not file_path.exists():
        raise FileNotFoundError(f"Expected dataset file not found: {file_path}")
    
    df = pd.read_csv(file_path)
    
    for col in REQUIRED_COLUMNS:
        if col not in df.columns:
            raise ValueError(f"Missing required column '{col}' in {file_path}")
    
    # Clean and convert to set
    compositions = set(df["composition_string"].astype(str).str.strip())
    
    if len(compositions) != len(df):
        # Check for duplicates in the source file itself
        duplicates = len(df) - len(df["composition_string"].astype(str).str.strip().unique())
        pytest.fail(f"Found {duplicates} duplicate composition strings in {file_path}")
        
    return compositions

def test_files_exist():
    """Verify all expected output files exist."""
    assert TRAIN_FILE.exists(), f"Training file missing: {TRAIN_FILE}"
    assert HOLDOUT_FILE.exists(), f"Holdout file missing: {HOLDOUT_FILE}"
    assert NOVEL_FILE.exists(), f"Novel file missing: {NOVEL_FILE}"

def test_no_overlap_train_holdout():
    """Verify no overlap between training and holdout sets."""
    train_set = get_composition_set(TRAIN_FILE)
    holdout_set = get_composition_set(HOLDOUT_FILE)
    
    intersection = train_set.intersection(holdout_set)
    assert len(intersection) == 0, (
        f"Overlap detected between train and holdout: {len(intersection)} items. "
        f"Sample: {list(intersection)[:5]}"
    )

def test_no_overlap_train_novel():
    """Verify no overlap between training and novel sets."""
    train_set = get_composition_set(TRAIN_FILE)
    novel_set = get_composition_set(NOVEL_FILE)
    
    intersection = train_set.intersection(novel_set)
    assert len(intersection) == 0, (
        f"Overlap detected between train and novel: {len(intersection)} items. "
        f"Sample: {list(intersection)[:5]}"
    )

def test_no_overlap_holdout_novel():
    """Verify no overlap between holdout and novel sets."""
    holdout_set = get_composition_set(HOLDOUT_FILE)
    novel_set = get_composition_set(NOVEL_FILE)
    
    intersection = holdout_set.intersection(novel_set)
    assert len(intersection) == 0, (
        f"Overlap detected between holdout and novel: {len(intersection)} items. "
        f"Sample: {list(intersection)[:5]}"
    )

def test_expected_sample_sizes():
    """Verify that the datasets have the expected approximate sizes (5000 for generated sets)."""
    # Note: Train size depends on the source data, but holdout and novel should be exactly 5000
    # based on task T014 and T015 requirements.
    
    holdout_df = pd.read_csv(HOLDOUT_FILE)
    novel_df = pd.read_csv(NOVEL_FILE)
    
    # Allow a small margin for error in sampling logic if needed, but strict 5000 is the goal
    assert len(holdout_df) == 5000, f"Holdout set size is {len(holdout_df)}, expected 5000"
    assert len(novel_df) == 5000, f"Novel set size is {len(novel_df)}, expected 5000"

def test_train_has_data():
    """Verify that the training set is not empty."""
    train_df = pd.read_csv(TRAIN_FILE)
    assert len(train_df) > 0, "Training set is empty"