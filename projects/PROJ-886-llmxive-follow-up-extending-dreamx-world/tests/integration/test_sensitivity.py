"""
Integration test for sensitivity sweep (T028).

This test verifies the sensitivity analysis pipeline by:
1. Loading the metrics CSV generated by T026.
2. Running the sensitivity sweep across thresholds {0.01, 0.05, 0.1}.
3. Verifying that the output contains success rates for each threshold.
4. Ensuring the results are written to the expected JSON file.

Dependencies:
- T026 (metrics.csv generation)
- T031 (sensitivity.py implementation)
"""

import os
import json
import pytest
import sys
from pathlib import Path

# Add project root to path for imports
project_root = Path(__file__).parent.parent.parent
sys.path.insert(0, str(project_root))

from code.analysis.sensitivity import run_sensitivity_sweep
from code.utils.config import ensure_directories


@pytest.mark.integration
def test_sensitivity_sweep_end_to_end():
    """
    End-to-end integration test for sensitivity analysis.

    Validates that:
    1. The sensitivity sweep runs without errors on the metrics CSV.
    2. The output JSON contains the required thresholds {0.01, 0.05, 0.1}.
    3. Success rates are computed and are numeric values.
    4. The output file is written to the correct location.
    """
    # Define paths relative to project root
    metrics_csv_path = project_root / "data" / "derived" / "metrics.csv"
    output_json_path = project_root / "data" / "derived" / "sensitivity_results.json"

    # Ensure output directory exists
    ensure_directories([output_json_path.parent])

    # Check if metrics.csv exists (dependency T026)
    if not metrics_csv_path.exists():
        pytest.skip(
            f"Metrics file not found at {metrics_csv_path}. "
            "Run T026 first to generate metrics.csv."
        )

    # Define thresholds as per spec FR-006 & SC-003
    thresholds = [0.01, 0.05, 0.1]

    # Run the sensitivity sweep
    try:
        results = run_sensitivity_sweep(
            metrics_path=str(metrics_csv_path),
            thresholds=thresholds,
            output_path=str(output_json_path)
        )
    except Exception as e:
        pytest.fail(f"Sensitivity sweep failed: {str(e)}")

    # Verify output file was created
    assert output_json_path.exists(), "Output JSON file was not created."

    # Load and verify JSON structure
    with open(output_json_path, "r") as f:
        data = json.load(f)

    # Verify required keys exist
    assert "thresholds" in data, "Missing 'thresholds' key in output."
    assert "success_rates" in data, "Missing 'success_rates' key in output."
    assert "summary" in data, "Missing 'summary' key in output."

    # Verify thresholds match expected values
    assert set(data["thresholds"]) == set(thresholds), "Thresholds do not match expected values."

    # Verify success rates are computed for each threshold
    success_rates = data["success_rates"]
    assert isinstance(success_rates, dict), "Success rates should be a dictionary."

    for threshold in thresholds:
        key = str(threshold)
        assert key in success_rates, f"Missing success rate for threshold {threshold}."
        rate = success_rates[key]
        assert isinstance(rate, (int, float)), f"Success rate for {threshold} must be numeric."
        assert 0.0 <= rate <= 1.0, f"Success rate for {threshold} must be between 0 and 1."

    # Verify summary contains aggregate information
    summary = data["summary"]
    assert "total_trajectories" in summary, "Missing 'total_trajectories' in summary."
    assert "converged_trajectories" in summary, "Missing 'converged_trajectories' in summary."

    # Print results for manual inspection
    print(f"Sensitivity Sweep Results: {json.dumps(data, indent=2)}")

if __name__ == "__main__":
    test_sensitivity_sweep_end_to_end()
    print("Integration test passed.")
