"""
Sensitivity Analysis for DreamX-Lite Evaluation.

This module implements the threshold sensitivity sweep as per Spec FR-006 and SC-003.
It reads the metrics CSV generated by the evaluation pipeline, applies specific
consistency thresholds, and computes success rates for both the Baseline and DreamX-Lite models.

Thresholds to sweep: {0.01, 0.05, 0.1}
"""

import os
import json
import logging
import pandas as pd
import numpy as np
from typing import List, Dict, Tuple, Optional, Any
from pathlib import Path

# Import shared utilities
from utils.config import ensure_directories, get_env_config
from analysis.metrics_writer import load_metrics_csv

logger = logging.getLogger(__name__)

# Defined thresholds per Spec FR-006 & SC-003
SENSITIVITY_THRESHOLDS = [0.01, 0.05, 0.1]

def compute_success_rate_at_threshold(
    df: pd.DataFrame,
    model_name: str,
    threshold: float,
    metric_column: str = "mae_position",
    success_column: str = "convergence"
) -> Tuple[float, int, int]:
    """
    Computes the success rate for a specific model at a given threshold.

    A trajectory is considered a 'success' if:
    1. It converged (convergence == True)
    2. Its metric value (e.g., MAE) is <= threshold

    Args:
        df: DataFrame containing metrics
        model_name: Name of the model to filter (e.g., 'DreamX-Lite', 'Baseline')
        threshold: The consistency threshold to apply
        metric_column: Column name for the metric (default: 'mae_position')
        success_column: Column name for convergence flag (default: 'convergence')

    Returns:
        Tuple of (success_rate, count_success, count_total_valid)
    """
    # Filter for specific model
    model_df = df[df["model_name"] == model_name]

    if model_df.empty:
        logger.warning(f"No data found for model: {model_name}")
        return 0.0, 0, 0

    # Filter for converged trajectories only (convergence == True)
    # Non-converged trajectories are excluded from the success rate calculation
    # as they represent a fundamental failure to reconstruct, not a precision issue.
    converged_df = model_df[
        (model_df[success_column] == True) & (model_df[metric_column].notna())
    ]

    total_valid = len(converged_df)

    if total_valid == 0:
        logger.info(f"No converged valid trajectories for {model_name} at threshold {threshold}")
        return 0.0, 0, 0

    # Count successes where metric <= threshold
    successes = converged_df[converged_df[metric_column] <= threshold]
    count_success = len(successes)

    success_rate = count_success / total_valid

    return success_rate, count_success, total_valid


def run_sensitivity_analysis(
    metrics_path: Optional[str] = None,
    output_path: Optional[str] = None
) -> Dict[str, Any]:
    """
    Runs the full sensitivity analysis sweep.

    Reads metrics, iterates through SENSITIVITY_THRESHOLDS, and computes
    success rates for both Baseline and DreamX-Lite models.

    Args:
        metrics_path: Path to the metrics CSV. If None, uses default derived path.
        output_path: Path to save the JSON results. If None, uses default derived path.

    Returns:
        Dictionary containing the sensitivity analysis results.
    """
    config = get_env_config()
    project_root = config.get("project_root", Path.cwd())

    # Default paths if not provided
    if metrics_path is None:
        metrics_path = project_root / "data" / "derived" / "metrics.csv"
    else:
        metrics_path = Path(metrics_path)

    if output_path is None:
        output_path = project_root / "data" / "derived" / "sensitivity_analysis.json"
    else:
        output_path = Path(output_path)

    ensure_directories([output_path])

    logger.info(f"Loading metrics from {metrics_path}")
    if not metrics_path.exists():
        raise FileNotFoundError(
            f"Metrics file not found at {metrics_path}. "
            "Please run the evaluation pipeline (T021-T026) first."
        )

    df = load_metrics_csv(metrics_path)

    if df.empty:
        raise ValueError("Metrics CSV is empty. Cannot perform analysis.")

    results = {
        "task_id": "T031",
        "description": "Sensitivity Analysis of Consistency Thresholds",
        "thresholds_tested": SENSITIVITY_THRESHOLDS,
        "metric_used": "mae_position",
        "models": {
            "Baseline": [],
            "DreamX-Lite": []
        },
        "summary": {}
    }

    logger.info(f"Running sensitivity sweep for thresholds: {SENSITIVITY_THRESHOLDS}")

    for threshold in SENSITIVITY_THRESHOLDS:
        logger.info(f"Processing threshold: {threshold}")
        threshold_results = {
            "threshold": threshold,
            "Baseline": {},
            "DreamX-Lite": {}
        }

        for model in ["Baseline", "DreamX-Lite"]:
            success_rate, count_success, count_total = compute_success_rate_at_threshold(
                df, model, threshold
            )

            threshold_results[model] = {
                "success_rate": float(success_rate),
                "count_success": int(count_success),
                "count_total_converged": int(count_total),
                "threshold": threshold
            }

        results["models"]["Baseline"].append(threshold_results["Baseline"])
        results["models"]["DreamX-Lite"].append(threshold_results["DreamX-Lite"])

    # Compute summary: Improvement at each threshold
    summary = []
    for t_res in results["models"]["DreamX-Lite"]:
        threshold = t_res["threshold"]
        baseline_res = next(
            (r for r in results["models"]["Baseline"] if r["threshold"] == threshold),
            None
        )

        if baseline_res:
            dl_rate = t_res["success_rate"]
            bl_rate = baseline_res["success_rate"]
            improvement = dl_rate - bl_rate
            summary.append({
                "threshold": threshold,
                "dreamx_lite_rate": dl_rate,
                "baseline_rate": bl_rate,
                "improvement": improvement
            })

    results["summary"] = summary

    # Save results
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)

    logger.info(f"Sensitivity analysis results saved to {output_path}")

    return results


def main():
    """
    Entry point for the sensitivity analysis script.
    """
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
    )

    try:
        results = run_sensitivity_analysis()
        print(json.dumps(results, indent=2))
    except Exception as e:
        logger.error(f"Failed to run sensitivity analysis: {e}", exc_info=True)
        raise


if __name__ == "__main__":
    main()