"""
Contract test for statistical analysis output format.

This test verifies that the statistical report generated by the pipeline
contains all required fields as defined in the specification:
- p-value
- test_type
- method_comparison

The test fails loudly if the file is missing or if the required fields
are not present in the expected format.
"""
import os
import re
import pytest
from pathlib import Path

# Expected report path relative to project root
REPORT_PATH = Path("data/results/statistical_report.txt")

# Required fields that must appear in the report
REQUIRED_FIELDS = [
    "p-value",
    "test_type",
    "method_comparison"
]

# Regex patterns to match field presence (case-insensitive)
FIELD_PATTERNS = {
    "p-value": re.compile(r"p-value[:\s]+[\d\.eE+-]+", re.IGNORECASE),
    "test_type": re.compile(r"test_type[:\s]+[A-Za-z0-9_]+", re.IGNORECASE),
    "method_comparison": re.compile(r"method_comparison[:\s]+.+?", re.IGNORECASE)
}

@pytest.fixture
def project_root():
    """Get the project root directory (parent of 'tests' directory)."""
    return Path(__file__).parent.parent.parent

def test_statistical_report_exists(project_root):
    """Assert that the statistical report file exists."""
    full_path = project_root / REPORT_PATH
    assert full_path.exists(), (
        f"Statistical report not found at {full_path}. "
        "The evaluation pipeline (T029/T030) must be executed to generate this file."
    )

def test_statistical_report_is_non_empty(project_root):
    """Assert that the statistical report file is not empty."""
    full_path = project_root / REPORT_PATH
    assert full_path.stat().st_size > 0, (
        f"Statistical report at {full_path} is empty. "
        "The evaluation pipeline must generate content."
    )

@pytest.mark.parametrize("field", REQUIRED_FIELDS)
def test_required_field_present(project_root, field):
    """
    Assert that each required field is present in the report.
    
    This test scans the report content and verifies that the field name
    appears followed by a value, matching the expected pattern.
    """
    full_path = project_root / REPORT_PATH
    content = full_path.read_text(encoding="utf-8")
    
    pattern = FIELD_PATTERNS.get(field)
    if not pattern:
        pytest.fail(f"No pattern defined for required field: {field}")
    
    match = pattern.search(content)
    assert match is not None, (
        f"Required field '{field}' not found in {full_path}. "
        "The statistical analysis script (T029) or report generator (T030) "
        "must output this field with a valid value."
    )

def test_report_contains_valid_pvalue(project_root):
    """
    Assert that the report contains a syntactically valid p-value.
    
    A valid p-value should be a number between 0 and 1 (inclusive),
    possibly in scientific notation.
    """
    full_path = project_root / REPORT_PATH
    content = full_path.read_text(encoding="utf-8")
    
    # Look for p-value patterns
    pvalue_pattern = re.compile(
        r"p-value[:\s]+([01](\.[0-9]+)?([eE][+-]?[0-9]+)?)",
        re.IGNORECASE
    )
    
    matches = pvalue_pattern.findall(content)
    assert len(matches) > 0, (
        "No valid p-value found in the report. "
        "The statistical test must output a numeric p-value."
    )
    
    # Validate that at least one match is a valid float between 0 and 1
    valid_found = False
    for match in matches:
        try:
            val = float(match[0])
            if 0.0 <= val <= 1.0:
                valid_found = True
                break
        except ValueError:
            continue
    
    assert valid_found, (
        "Found p-value patterns but none are valid floats between 0 and 1. "
        "The statistical analysis must compute a valid p-value."
    )

def test_report_contains_test_type(project_root):
    """
    Assert that the report specifies the type of statistical test used.
    
    Expected values include: 'paired_t_test', 'wilcoxon', 'mann_whitney', etc.
    """
    full_path = project_root / REPORT_PATH
    content = full_path.read_text(encoding="utf-8")
    
    test_type_pattern = re.compile(
        r"test_type[:\s]+([A-Za-z0-9_]+)",
        re.IGNORECASE
    )
    
    match = test_type_pattern.search(content)
    assert match is not None, (
        "test_type field not found or empty in the report. "
        "The statistical analysis must specify which test was performed."
    )
    
    test_type_value = match.group(1).lower()
    valid_test_types = [
        "paired_t_test",
        "wilcoxon",
        "mann_whitney",
        "ttest_rel",
        "wilcoxon_signed_rank"
    ]
    
    assert any(valid in test_type_value for valid in valid_test_types), (
        f"Invalid test_type '{test_type_value}' found. "
        f"Expected one of: {valid_test_types}"
    )

def test_report_contains_method_comparison(project_root):
    """
    Assert that the report includes a comparison of methods being tested.
    
    This should describe which methods are being compared (e.g., 
    'Static Heuristic vs Learned Sparse (RTPurbo)').
    """
    full_path = project_root / REPORT_PATH
    content = full_path.read_text(encoding="utf-8")
    
    comparison_pattern = re.compile(
        r"method_comparison[:\s]+(.+?)(?:\n|$)",
        re.IGNORECASE
    )
    
    match = comparison_pattern.search(content)
    assert match is not None, (
        "method_comparison field not found or empty in the report. "
        "The report must describe which methods are being compared."
    )
    
    comparison_text = match.group(1).strip()
    assert len(comparison_text) > 10, (
        f"method_comparison value '{comparison_text}' is too short. "
        "Expected a descriptive comparison of the methods."
    )