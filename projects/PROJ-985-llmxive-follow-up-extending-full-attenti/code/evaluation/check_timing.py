"""
Post-execution check script for T032b.

Reads the timing report generated by T032, asserts the total pipeline duration
is within the 6-hour (21600 seconds) budget, and logs the result back to the
timing report file.
"""
import os
import json
import logging
import sys
from datetime import datetime
from typing import Dict, Any, Optional

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler('data/logs/timing_check.log')
    ]
)
logger = logging.getLogger(__name__)

TIMING_REPORT_PATH = "data/results/timing_report.json"
MAX_DURATION_SECONDS = 21600  # 6 hours

def load_timing_report(path: str) -> Optional[Dict[str, Any]]:
    """Load the timing report JSON file."""
    if not os.path.exists(path):
        logger.error(f"Timing report not found at {path}")
        return None

    try:
        with open(path, 'r', encoding='utf-8') as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse timing report JSON: {e}")
        return None
    except Exception as e:
        logger.error(f"Unexpected error reading timing report: {e}")
        return None

def calculate_total_duration(report: Dict[str, Any]) -> float:
    """
    Calculate total pipeline duration in seconds.
    
    Expects the report to have 'start_time' and 'end_time' in ISO format.
    If 'stages' are present, it sums their durations as a sanity check.
    """
    start_str = report.get('start_time')
    end_str = report.get('end_time')

    if not start_str or not end_str:
        logger.warning("Missing start_time or end_time in report. Calculating from stages if available.")
        stages = report.get('stages', [])
        if stages:
            total = sum(s.get('duration_seconds', 0) for s in stages)
            return float(total)
        return 0.0

    try:
        start = datetime.fromisoformat(start_str.replace('Z', '+00:00'))
        end = datetime.fromisoformat(end_str.replace('Z', '+00:00'))
        return (end - start).total_seconds()
    except ValueError as e:
        logger.error(f"Failed to parse timestamps: {e}")
        return 0.0

def check_duration(duration: float, max_duration: float) -> bool:
    """Check if duration is within the allowed limit."""
    return duration <= max_duration

def update_report_with_check(
    report: Dict[str, Any], 
    duration: float, 
    passed: bool, 
    output_path: str
) -> None:
    """Update the timing report with the check results and save."""
    report['timing_check'] = {
        'timestamp': datetime.utcnow().isoformat() + 'Z',
        'total_duration_seconds': duration,
        'max_allowed_seconds': MAX_DURATION_SECONDS,
        'passed': passed,
        'message': "Pipeline completed within time budget." if passed else f"Pipeline exceeded time budget by {duration - max_duration:.2f} seconds."
    }

    # Ensure directory exists
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)

    logger.info(f"Updated timing report saved to {output_path}")

def main():
    logger.info("Starting post-execution timing check (T032b)...")
    
    # Load report
    report = load_timing_report(TIMING_REPORT_PATH)
    if report is None:
        logger.critical("Cannot proceed: Timing report missing or invalid.")
        # Create a failure report if it doesn't exist or is empty
        error_report = {
            'error': 'Timing report not found or invalid',
            'timing_check': {
                'timestamp': datetime.utcnow().isoformat() + 'Z',
                'total_duration_seconds': 0,
                'max_allowed_seconds': MAX_DURATION_SECONDS,
                'passed': False,
                'message': 'Could not read timing report to perform check.'
            }
        }
        os.makedirs(os.path.dirname(TIMING_REPORT_PATH), exist_ok=True)
        with open(TIMING_REPORT_PATH, 'w', encoding='utf-8') as f:
            json.dump(error_report, f, indent=2)
        sys.exit(1)

    # Calculate duration
    duration = calculate_total_duration(report)
    logger.info(f"Calculated total pipeline duration: {duration:.2f} seconds")

    # Perform check
    passed = check_duration(duration, MAX_DURATION_SECONDS)
    status = "PASSED" if passed else "FAILED"
    logger.info(f"Timing check {status}: {duration:.2f}s <= {MAX_DURATION_SECONDS}s")

    # Update report
    update_report_with_check(report, duration, passed, TIMING_REPORT_PATH)

    if not passed:
        logger.warning("Pipeline exceeded the 6-hour time limit.")
        # We do not exit with error code here as the check itself succeeded in identifying the issue,
        # but the task requirement is to log the result.
    
    logger.info("Post-execution check complete.")

if __name__ == "__main__":
    main()