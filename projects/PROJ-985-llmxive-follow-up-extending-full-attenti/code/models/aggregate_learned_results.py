"""
Aggregate results from multiple random seeds of the learned sparse baseline (RTPurbo).

This script computes mean, standard deviation, and variance of metrics across seeds.
It reads per-document JSON files generated by T026a (run_learned_baseline) and
aggregates them into a single summary file.

Output Schema:
{
  "mean_metric": float,
  "std_metric": float,
  "variance_metric": float,
  "n_seeds": int,
  "seed_values": [float, ...]
}
"""
import os
import json
import logging
import argparse
from typing import Dict, Any, List, Optional
import numpy as np

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def get_project_root() -> str:
    """Get the project root directory (parent of 'code')."""
    return os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))

def load_eval_scores(input_dir: str, metric_name: str = "perplexity") -> List[float]:
    """
    Load evaluation scores from all seed files in the input directory.
    
    Args:
        input_dir: Path to directory containing seed_{seed}_per_doc.json files
        metric_name: The specific metric to aggregate (e.g., 'perplexity', 'exact_match')
        
    Returns:
        List of aggregated scores (one per seed, computed as mean over documents)
    """
    seed_values = []
    seed_files = sorted([f for f in os.listdir(input_dir) if f.startswith('seed_') and f.endswith('_per_doc.json')])
    
    if not seed_files:
        raise FileNotFoundError(f"No seed files found in {input_dir}")
    
    logger.info(f"Found {len(seed_files)} seed files to aggregate")
    
    for seed_file in seed_files:
        file_path = os.path.join(input_dir, seed_file)
        try:
            with open(file_path, 'r') as f:
                data = json.load(f)
            
            # Extract the specific metric values for this seed
            # Data structure: [{document_id, metric_name, value}, ...]
            metric_values = [item['value'] for item in data if item.get('metric_name') == metric_name]
            
            if not metric_values:
                logger.warning(f"No {metric_name} values found in {seed_file}")
                continue
            
            # Aggregate per-document scores to a single score per seed (mean)
            seed_mean = float(np.mean(metric_values))
            seed_values.append(seed_mean)
            logger.info(f"Seed {seed_file}: mean {metric_name} = {seed_mean:.4f}")
            
        except Exception as e:
            logger.error(f"Error processing {seed_file}: {e}")
            raise
    
    return seed_values

def aggregate_metrics(seed_values: List[float]) -> Dict[str, Any]:
    """
    Compute aggregate statistics from a list of seed values.
    
    Args:
        seed_values: List of metric values (one per seed)
        
    Returns:
        Dictionary with mean, std, variance, n_seeds, and raw seed values
    """
    if not seed_values:
        raise ValueError("seed_values list is empty")
    
    arr = np.array(seed_values)
    
    result = {
        "mean_metric": float(np.mean(arr)),
        "std_metric": float(np.std(arr)),
        "variance_metric": float(np.var(arr)),
        "n_seeds": len(seed_values),
        "seed_values": [float(v) for v in seed_values]
    }
    
    return result

def save_aggregated_results(result: Dict[str, Any], output_path: str) -> None:
    """Save the aggregated results to a JSON file."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(result, f, indent=2)
    
    logger.info(f"Aggregated results saved to {output_path}")

def main():
    """Main entry point for the aggregation script."""
    parser = argparse.ArgumentParser(description="Aggregate learned baseline results across seeds")
    parser.add_argument(
        '--input-dir',
        type=str,
        default=os.path.join(get_project_root(), 'data', 'intermediate', 'baseline_seeds'),
        help='Directory containing per-document seed result files'
    )
    parser.add_argument(
        '--output-path',
        type=str,
        default=os.path.join(get_project_root(), 'data', 'results', 'baseline_aggregated.json'),
        help='Path to save the aggregated results JSON'
    )
    parser.add_argument(
        '--metric',
        type=str,
        default='perplexity',
        help='Metric to aggregate (default: perplexity)'
    )
    
    args = parser.parse_args()
    
    logger.info(f"Loading seed results from {args.input_dir}")
    logger.info(f"Aggregating metric: {args.metric}")
    
    try:
        # Load scores from all seeds
        seed_values = load_eval_scores(args.input_dir, args.metric)
        
        if not seed_values:
            raise ValueError("No valid seed values found to aggregate")
        
        # Compute aggregates
        result = aggregate_metrics(seed_values)
        
        # Save results
        save_aggregated_results(result, args.output_path)
        
        logger.info(f"Aggregation complete. Mean: {result['mean_metric']:.4f}, "
                    f"Std: {result['std_metric']:.4f}, Variance: {result['variance_metric']:.6f}")
        
    except Exception as e:
        logger.error(f"Aggregation failed: {e}")
        raise

if __name__ == "__main__":
    main()
