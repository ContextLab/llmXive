import os
import csv
import logging
import argparse
import h5py
import pandas as pd
from typing import List, Dict, Any, Optional

from lib.logging_config import get_logger, log_stage_start, log_stage_end, get_anomalies_path
from lib.data_loader import get_current_memory_gb

logger = get_logger(__name__)

def load_ground_truth_labels(h5_path: str) -> pd.DataFrame:
    """
    Load ground truth labels (RTPurbo indices and attention maps metadata) from HDF5.
    
    Args:
        h5_path: Path to the attention_maps.h5 file generated by extract_ground_truth.py
        
    Returns:
        DataFrame with columns: doc_id, token_idx, is_rtpurbo, attention_score
    """
    if not os.path.exists(h5_path):
        raise FileNotFoundError(f"Ground truth HDF5 file not found: {h5_path}")
    
    logger.info(f"Loading ground truth labels from {h5_path}")
    
    data = []
    with h5py.File(h5_path, 'r') as f:
        # Expecting structure: /docs/{doc_id}/tokens/{token_idx}/rtpurbo
        # and /docs/{doc_id}/tokens/{token_idx}/attention_score
        if 'docs' not in f:
            raise ValueError(f"HDF5 file {h5_path} missing 'docs' group")
        
        for doc_id in f['docs'].keys():
            doc_group = f['docs'][doc_id]
            if 'tokens' not in doc_group:
                logger.warning(f"Doc {doc_id} has no tokens group, skipping")
                continue
            
            for token_idx_str in doc_group['tokens'].keys():
                token_idx = int(token_idx_str)
                token_group = doc_group['tokens'][token_idx]
                
                is_rtpurbo = int(token_group['is_rtpurbo'][()])
                attention_score = float(token_group['attention_score'][()])
                
                data.append({
                    'doc_id': doc_id,
                    'token_idx': token_idx,
                    'is_rtpurbo': is_rtpurbo,
                    'attention_score': attention_score
                })
    
    df = pd.DataFrame(data)
    logger.info(f"Loaded {len(df)} ground truth records")
    return df

def load_static_features(csv_path: str) -> pd.DataFrame:
    """
    Load static features computed by compute_features.py.
    
    Args:
        csv_path: Path to the features CSV file
        
    Returns:
        DataFrame with feature columns and label column if present
    """
    if not os.path.exists(csv_path):
        raise FileNotFoundError(f"Static features file not found: {csv_path}")
    
    logger.info(f"Loading static features from {csv_path}")
    df = pd.read_csv(csv_path)
    
    required_cols = ['doc_id', 'token_idx', 'entropy', 'pos_tag', 'kenlm_perplexity']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Static features file missing required columns: {missing_cols}")
    
    logger.info(f"Loaded {len(df)} static feature records")
    return df

def load_anomalies() -> pd.DataFrame:
    """
    Load anomalies detected during ground truth extraction.
    
    Returns:
        DataFrame of anomalous documents to exclude
    """
    anomalies_path = get_anomalies_path()
    if not os.path.exists(anomalies_path):
        logger.info("No anomalies file found, returning empty DataFrame")
        return pd.DataFrame(columns=['doc_id', 'reason'])
    
    logger.info(f"Loading anomalies from {anomalies_path}")
    df = pd.read_csv(anomalies_path)
    return df

def merge_datasets(gt_df: pd.DataFrame, features_df: pd.DataFrame, anomalies_df: pd.DataFrame) -> pd.DataFrame:
    """
    Merge ground truth labels with static features, excluding anomalous documents.
    
    Args:
        gt_df: Ground truth DataFrame (doc_id, token_idx, is_rtpurbo, attention_score)
        features_df: Static features DataFrame (doc_id, token_idx, entropy, pos_tag, kenlm_perplexity, ...)
        anomalies_df: Anomalies DataFrame (doc_id, reason)
        
    Returns:
        Merged DataFrame with all columns
    """
    logger.info("Starting dataset merge")
    logger.info(f"  Ground truth records: {len(gt_df)}")
    logger.info(f"  Static feature records: {len(features_df)}")
    logger.info(f"  Anomalous documents to exclude: {len(anomalies_df)}")
    
    # Exclude anomalous documents
    if not anomalies_df.empty:
        anomalous_doc_ids = set(anomalies_df['doc_id'].unique())
        gt_df = gt_df[~gt_df['doc_id'].isin(anomalous_doc_ids)]
        features_df = features_df[~features_df['doc_id'].isin(anomalous_doc_ids)]
        logger.info(f"  Excluded {len(anomalous_doc_ids)} anomalous documents")
    
    # Merge on doc_id and token_idx
    merged_df = pd.merge(
        gt_df,
        features_df,
        on=['doc_id', 'token_idx'],
        how='inner'
    )
    
    logger.info(f"  Final merged records: {len(merged_df)}")
    
    # Verify no anomalies slipped through
    if not anomalies_df.empty:
        remaining_anomalies = merged_df[merged_df['doc_id'].isin(anomalous_doc_ids)]
        if not remaining_anomalies.empty:
            raise RuntimeError(
                f"Anomalies detected in merged dataset: {remaining_anomalies['doc_id'].unique()}"
            )
    
    return merged_df

def save_merged_dataset(df: pd.DataFrame, output_path: str) -> None:
    """
    Save merged dataset to CSV.
    
    Args:
        df: Merged DataFrame
        output_path: Output path for the CSV file
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    df.to_csv(output_path, index=False)
    logger.info(f"Saved merged dataset to {output_path} with {len(df)} records")

def main():
    """
    Main entry point for merging ground truth and static features.
    """
    log_stage_start("T014: Merge Datasets")
    
    # Parse arguments
    parser = argparse.ArgumentParser(description="Merge ground truth and static features")
    parser.add_argument(
        "--gt-path",
        type=str,
        default="data/intermediate/attention_maps.h5",
        help="Path to ground truth HDF5 file"
    )
    parser.add_argument(
        "--features-path",
        type=str,
        default="data/intermediate/static_features.csv",
        help="Path to static features CSV file"
    )
    parser.add_argument(
        "--output-path",
        type=str,
        default="data/intermediate/merged_dataset.csv",
        help="Path to output merged dataset CSV"
    )
    args = parser.parse_args()
    
    try:
        # Load data
        gt_df = load_ground_truth_labels(args.gt_path)
        features_df = load_static_features(args.features_path)
        anomalies_df = load_anomalies()
        
        # Merge
        merged_df = merge_datasets(gt_df, features_df, anomalies_df)
        
        # Save
        save_merged_dataset(merged_df, args.output_path)
        
        # Log memory usage
        mem_gb = get_current_memory_gb()
        logger.info(f"Peak memory usage during merge: {mem_gb:.2f} GB")
        
        log_stage_end("T014: Merge Datasets", success=True)
        
    except FileNotFoundError as e:
        logger.error(f"Input file not found: {e}")
        log_stage_end("T014: Merge Datasets", success=False, error=str(e))
        raise
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        log_stage_end("T014: Merge Datasets", success=False, error=str(e))
        raise
    except Exception as e:
        logger.error(f"Unexpected error during merge: {e}")
        log_stage_end("T014: Merge Datasets", success=False, error=str(e))
        raise

if __name__ == "__main__":
    main()
