"""
Full Pipeline Runner for Calibration of Predictive Intervals.

This script orchestrates the end-to-end evaluation across pre-sampled series
from M4 and UCI datasets. It handles streaming, aggregation, and result persistence.

Error Handling Strategy:
- Per-series model failures (e.g., LSTM non-convergence) are caught, logged,
  and the series is skipped without halting the pipeline.
- Global data validation errors (from T006c) propagate and halt execution.
"""

import os
import sys
import argparse
import traceback
from pathlib import Path
from typing import Dict, Any, List, Optional
import pandas as pd
import numpy as np

# Project imports
from config import ensure_dirs, PROJECT_ROOT, RESULTS_DIR, DATA_DIR
from utils.logger import get_logger
from utils.exceptions import DataValidationError, ModelConvergenceError
from data_loader import fetch_data, load_m4_hourly, load_uci_electricity, split_series, standardize
from data.sampler import stratified_sampler
from models.arima_model import ARIMAModel
from models.prophet_model import ProphetModel
from models.lstm_model import LSTMModel
from metrics.coverage import compute_coverage, aggregate_coverage_results, coverage_to_dataframe
from metrics.pit import calculate_pit, ljung_box_test, compute_pit_metrics, pit_metrics_to_dataframe
from metrics.crps import compute_crps, aggregate_crps_results, crps_to_dataframe
from utils.checksum import verify_checksums

logger = get_logger(__name__)

# Constants
MODELS = {
    "arima": ARIMAModel,
    "prophet": ProphetModel,
    "lstm": LSTMModel
}

NOMINAL_LEVELS = [0.80, 0.95]


def load_sample_metadata() -> List[Dict[str, Any]]:
    """
    Loads the sample metadata generated by T006b (stratified_sampler).
    Returns a list of dicts containing series_id, dataset, frequency, and split info.
    """
    meta_path = DATA_DIR / "sample_metadata.csv"
    if not meta_path.exists():
        logger.error(f"Sample metadata not found at {meta_path}. Run T006b first.")
        raise FileNotFoundError(f"Missing sample metadata: {meta_path}")
    
    df = pd.read_csv(meta_path)
    return df.to_dict(orient='records')


def process_single_series(
    series_config: Dict[str, Any],
    model_type: str,
    config: Dict[str, Any]
) -> Optional[Dict[str, Any]]:
    """
    Processes a single time series with a specific model.
    
    Args:
        series_config: Dict with series_id, dataset, frequency, train_idx, test_idx, etc.
        model_type: One of 'arima', 'prophet', 'lstm'.
        config: Global configuration dict.
        
    Returns:
        Dict with metrics or None if the series failed.
    """
    series_id = series_config.get('series_id')
    dataset_name = series_config.get('dataset')
    
    try:
        # 1. Load Data
        # We assume data_loader handles the fetching based on dataset_name
        # If the data isn't local, fetch_data will raise an error (Global validation)
        logger.info(f"Loading data for {series_id} from {dataset_name}")
        
        # Attempt to load the full dataset or stream the specific series
        # Using fetch_data which handles M4/UCI logic
        raw_data = fetch_data(dataset_name, series_id=series_id)
        
        if raw_data is None:
            raise DataValidationError(f"Failed to fetch data for {series_id}")
        
        # 2. Preprocess
        # Apply standardization and splitting as per config
        train_data, test_data = split_series(
            raw_data, 
            train_end=series_config.get('train_end'), 
            test_start=series_config.get('test_start')
        )
        
        # Standardize if configured
        if config.get('standardize', False):
            train_data, scaler = standardize(train_data)
            test_data = (test_data - scaler.mean_) / scaler.scale_
        
        # 3. Initialize and Fit Model
        logger.info(f"Fitting {model_type.upper()} model for {series_id}")
        model_cls = MODELS[model_type]
        model = model_cls(config=config)
        
        try:
            model.fit(train_data)
        except Exception as e:
            # Specific handling for model convergence issues (Per-series failure)
            logger.warning(f"Model {model_type} failed to converge for {series_id}: {str(e)}")
            raise ModelConvergenceError(f"Model {model_type} non-convergence for {series_id}") from e
        
        # 4. Generate Forecasts and Intervals
        forecasts, intervals = model.predict(test_data, nominal_levels=NOMINAL_LEVELS)
        
        if forecasts is None or intervals is None:
            raise ModelConvergenceError(f"Model {model_type} produced no output for {series_id}")
        
        # 5. Compute Metrics
        results = {
            "series_id": series_id,
            "model": model_type,
            "dataset": dataset_name
        }
        
        # Coverage
        coverage_results = []
        for level in NOMINAL_LEVELS:
            cov = compute_coverage(test_data, forecasts, intervals, level=level)
            deviation = cov - level
            coverage_results.append({
                "nominal_level": level,
                "empirical_coverage": cov,
                "deviation": deviation
            })
        results["coverage"] = coverage_results
        
        # PIT
        pit_values = calculate_pit(test_data, forecasts, intervals)
        pit_metrics = compute_pit_metrics(pit_values)
        results["pit_p_value"] = pit_metrics.get('ljung_box_p_value')
        
        # CRPS
        crps_val = compute_crps(test_data, forecasts, intervals)
        results["crps"] = crps_val
        
        logger.info(f"Successfully processed {series_id} with {model_type}")
        return results
        
    except DataValidationError:
        # Global error: propagate immediately
        raise
    except ModelConvergenceError as e:
        # Per-series error: log and return None
        logger.error(f"Skipping {series_id} due to {model_type} failure: {e}")
        # Log to skipped_series.log as per T015 requirement (extended here)
        skipped_log = RESULTS_DIR / "skipped_series.log"
        with open(skipped_log, 'a') as f:
            f.write(f"{series_id},{model_type},{str(e)}\n")
        return None
    except Exception as e:
        # Unexpected error: log and return None
        logger.error(f"Unexpected error processing {series_id} with {model_type}: {traceback.format_exc()}")
        return None


def run_evaluation(config_path: str) -> None:
    """
    Runs the full evaluation pipeline.
    
    Args:
        config_path: Path to the configuration file (JSON/YAML).
    """
    logger.info(f"Starting full evaluation pipeline with config: {config_path}")
    
    # Load config
    config = {}
    if os.path.exists(config_path):
        # Simple JSON loader for config
        import json
        with open(config_path, 'r') as f:
            config = json.load(f)
    else:
        logger.warning(f"Config file {config_path} not found. Using defaults.")
    
    # Ensure directories exist
    ensure_dirs()
    
    # Verify data integrity if checksums exist
    if verify_checksums(DATA_DIR):
        logger.info("Data checksums verified.")
    else:
        logger.warning("Data checksums missing or invalid. Proceeding with caution.")
    
    # Load sample metadata
    sample_list = load_sample_metadata()
    logger.info(f"Loaded {len(sample_list)} series from metadata.")
    
    all_results = []
    
    # Iterate over models and series
    models_to_run = config.get('models', list(MODELS.keys()))
    
    for model_type in models_to_run:
        if model_type not in MODELS:
            logger.warning(f"Unknown model type {model_type} in config, skipping.")
            continue
        
        logger.info(f"Running pipeline for model: {model_type}")
        
        for series_cfg in sample_list:
            result = process_single_series(series_cfg, model_type, config)
            if result:
                all_results.append(result)
    
    if not all_results:
        logger.error("No results generated. Check logs for errors.")
        return
    
    # Aggregate and Save
    aggregate_and_save_results(all_results)
    logger.info("Evaluation pipeline completed successfully.")


def aggregate_and_save_results(results: List[Dict[str, Any]]) -> None:
    """
    Aggregates results from individual series into DataFrames and saves to CSV.
    
    Output Files:
    - results/coverage.csv
    - results/distributional_metrics.csv
    """
    if not results:
        return
    
    # Flatten coverage results
    coverage_rows = []
    dist_rows = []
    
    for res in results:
        series_id = res['series_id']
        model = res['model']
        
        for cov in res.get('coverage', []):
            coverage_rows.append({
                'series_id': series_id,
                'model': model,
                'nominal_level': cov['nominal_level'],
                'empirical_coverage': cov['empirical_coverage'],
                'deviation': cov['deviation']
            })
        
        dist_rows.append({
            'series_id': series_id,
            'model': model,
            'pit_p_value': res.get('pit_p_value'),
            'crps': res.get('crps')
        })
    
    # Create DataFrames
    df_coverage = pd.DataFrame(coverage_rows)
    df_dist = pd.DataFrame(dist_rows)
    
    # Save
    coverage_path = RESULTS_DIR / "coverage.csv"
    dist_path = RESULTS_DIR / "distributional_metrics.csv"
    
    df_coverage.to_csv(coverage_path, index=False)
    df_dist.to_csv(dist_path, index=False)
    
    logger.info(f"Saved coverage results to {coverage_path}")
    logger.info(f"Saved distributional metrics to {dist_path}")


def main():
    parser = argparse.ArgumentParser(description="Run full calibration evaluation pipeline.")
    parser.add_argument(
        "--config", 
        type=str, 
        default="config.json",
        help="Path to the configuration file."
    )
    args = parser.parse_args()
    
    try:
        run_evaluation(args.config)
    except DataValidationError as e:
        logger.critical(f"Global data validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.critical(f"Pipeline failed with unexpected error: {traceback.format_exc()}")
        sys.exit(1)


if __name__ == "__main__":
    main()