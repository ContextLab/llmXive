def load_coverage_results(config: Config) -> pd.DataFrame:
    """
    Load the coverage results generated by runner.py (T018).
    Expected file: results/coverage.csv
    Columns: series_id, model, nominal_level, empirical_coverage, deviation, pit_p_value, crps
    """
    input_path = config.paths.results / "coverage.csv"
    if not input_path.exists():
        raise DataValidationError(
            f"Required input file not found: {input_path}. "
            "Ensure T018 (runner.py) has been executed successfully."
        )
    
    df = pd.read_csv(input_path)
    logger.info(f"Loaded coverage results: {len(df)} rows from {input_path}")
    
    # Validate essential columns
    required_cols = ['series_id', 'model', 'nominal_level', 'empirical_coverage', 'deviation']
    missing = set(required_cols) - set(df.columns)
    if missing:
        raise DataValidationError(f"Missing required columns in coverage.csv: {missing}")
    
    return df


