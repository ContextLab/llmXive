def run_bootstrap_analysis(
    coverage_df: pd.DataFrame,
    config: Config
) -> pd.DataFrame:
    """
    Execute the paired bootstrap test on coverage deviations.
    
    Logic:
    1. Identify unique models in the coverage_df.
    2. Perform pairwise comparisons (e.g., ARIMA vs Prophet).
    3. Aggregate results into the required schema:
       model_a, model_b, metric, p_value, significant
    """
    models = coverage_df['model'].unique()
    if len(models) < 2:
        logger.warning("Less than 2 models found in coverage data. Skipping bootstrap test.")
        return pd.DataFrame(columns=['model_a', 'model_b', 'metric', 'p_value', 'significant'])

    logger.info(f"Running bootstrap analysis for models: {list(models)}")
    
    # We need to compare coverage deviations. 
    # The bootstrap_test module expects data structured for comparison.
    # We will use the run_all_pairwise_comparisons helper which likely handles the grouping.
    
    # Prepare data: Ensure we have deviation per series per model
    # Pivot to wide format if necessary, or pass as is if the function handles long format.
    # Based on typical usage, we pass the dataframe and the metric column name.
    
    # We focus on 'deviation' from coverage as the primary metric for significance.
    # We can also run on 'crps' if available in coverage_df or distributional_metrics.
    
    results_list = []
    
    # Run pairwise comparisons for coverage deviation
    # The helper `run_all_pairwise_comparisons` is designed for this.
    # We assume it returns a structure we can aggregate.
    
    # If the helper requires a specific input format, we might need to transform.
    # Let's assume we can pass the dataframe and the metric column.
    
    try:
        # Attempt to run comparisons for 'deviation'
        bootstrap_results = run_all_pairwise_comparisons(
            data=coverage_df,
            metric_col='deviation',
            series_col='series_id',
            model_col='model',
            config=config
        )
        
        # Aggregate results into the final format
        # Expected output from aggregate_bootstrap_results: list of dicts or DataFrame
        final_df = aggregate_bootstrap_results(bootstrap_results)
        
        # Ensure columns match the spec: model_a, model_b, metric, p_value, significant
        if 'metric' not in final_df.columns:
            final_df['metric'] = 'coverage_deviation'
        
        # Convert significant boolean if needed
        if 'significant' not in final_df.columns:
            # Default threshold 0.05
            final_df['significant'] = final_df['p_value'] < 0.05
            
        return final_df
        
    except Exception as e:
        logger.error(f"Bootstrap analysis failed: {e}")
        logger.error(traceback.format_exc())
        # Return empty DF with correct schema instead of crashing
        return pd.DataFrame(columns=['model_a', 'model_b', 'metric', 'p_value', 'significant'])


