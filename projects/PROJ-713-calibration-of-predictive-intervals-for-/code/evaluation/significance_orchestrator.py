"""
Significance Orchestrator for User Story 3.

This script reads completed evaluation results (coverage and distributional metrics),
executes the bootstrap significance tests and conformal calibration, and writes
the final aggregated results to CSV files.

It is a standalone script and does not modify runner.py.
"""
import os
import sys
import argparse
import traceback
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

import pandas as pd
from utils.logger import get_logger
from config import RESULTS_DIR

# Import orchestrator functions from sub-modules
from evaluation.bootstrap_test import (
    run_all_pairwise_comparisons,
    aggregate_bootstrap_results,
)
from calibration.conformal_orchestrator import (
    process_all_series,
    save_conformal_results,
)

logger = get_logger("significance_orchestrator")


def load_coverage_results() -> pd.DataFrame:
    """
    Load the coverage results generated by runner.py.

    Returns:
        DataFrame with columns: series_id, model, nominal_level, empirical_coverage, deviation, etc.
    """
    path = RESULTS_DIR / "coverage.csv"
    if not path.exists():
        raise FileNotFoundError(
            f"Required file not found: {path}. "
            "Please run the evaluation pipeline (runner.py) first."
        )
    logger.info(f"Loading coverage results from {path}")
    return pd.read_csv(path)


def load_distributional_metrics() -> pd.DataFrame:
    """
    Load the distributional metrics (PIT, CRPS, etc.) generated by runner.py.

    Returns:
        DataFrame with columns: series_id, model, pit_p_value, crps, etc.
    """
    path = RESULTS_DIR / "distributional_metrics.csv"
    if not path.exists():
        raise FileNotFoundError(
            f"Required file not found: {path}. "
            "Please run the evaluation pipeline (runner.py) first."
        )
    logger.info(f"Loading distributional metrics from {path}")
    return pd.read_csv(path)


def run_bootstrap_analysis(
    coverage_df: pd.DataFrame, dist_df: pd.DataFrame
) -> pd.DataFrame:
    """
    Execute the paired bootstrap tests for all model pairs.

    Args:
        coverage_df: DataFrame from load_coverage_results()
        dist_df: DataFrame from load_distributional_metrics()

    Returns:
        DataFrame of aggregated bootstrap results.
    """
    logger.info("Starting bootstrap significance analysis...")
    
    # We assume the bootstrap logic needs the raw coverage deviations per series/model
    # run_all_pairwise_comparisons expects the coverage dataframe
    try:
        comparison_results = run_all_pairwise_comparisons(coverage_df)
        aggregated = aggregate_bootstrap_results(comparison_results)
        logger.info(f"Bootstrap analysis complete. Found {len(aggregated)} comparisons.")
        return aggregated
    except Exception as e:
        logger.error(f"Bootstrap analysis failed: {e}")
        raise


def run_conformal_analysis(
    coverage_df: pd.DataFrame, dist_df: pd.DataFrame
) -> pd.DataFrame:
    """
    Execute the self-calibrating conformal prediction wrapper for all series.

    Args:
        coverage_df: DataFrame from load_coverage_results()
        dist_df: DataFrame from load_distributional_metrics()

    Returns:
        DataFrame of conformal results.
    """
    logger.info("Starting conformal calibration analysis...")
    
    try:
        # process_all_series handles the logic of loading series data and running conformal
        # It returns a list of result dicts or a DataFrame depending on implementation
        # Based on the API surface, it likely returns the data ready to be saved
        results = process_all_series(coverage_df, dist_df)
        
        if isinstance(results, list):
            results_df = pd.DataFrame(results)
        else:
            results_df = results
        
        logger.info(f"Conformal analysis complete. Processed {len(results_df)} series.")
        return results_df
    except Exception as e:
        logger.error(f"Conformal analysis failed: {e}")
        raise


def save_significance_results(df: pd.DataFrame) -> str:
    """
    Save the bootstrap significance results to CSV.

    Args:
        df: DataFrame of aggregated bootstrap results.

    Returns:
        Path to the saved file.
    """
    output_path = RESULTS_DIR / "significance_test.csv"
    df.to_csv(output_path, index=False)
    logger.info(f"Significance results saved to {output_path}")
    return str(output_path)


def save_conformal_results(df: pd.DataFrame) -> str:
    """
    Save the conformal calibration results to CSV.

    Args:
        df: DataFrame of conformal results.

    Returns:
        Path to the saved file.
    """
    output_path = RESULTS_DIR / "conformal_results.csv"
    df.to_csv(output_path, index=False)
    logger.info(f"Conformal results saved to {output_path}")
    return str(output_path)


def main():
    """
    Main entry point for the significance orchestrator.
    
    1. Loads coverage.csv and distributional_metrics.csv
    2. Runs bootstrap tests
    3. Runs conformal calibration
    4. Saves significance_test.csv and conformal_results.csv
    """
    parser = argparse.ArgumentParser(
        description="Run significance tests and conformal calibration on evaluation results."
    )
    parser.add_argument(
        "--config",
        type=str,
        default=None,
        help="Path to config file (optional, uses defaults if not provided)",
    )
    args = parser.parse_args()

    try:
        logger.info("=== Significance Orchestrator Starting ===")

        # 1. Load Input Data
        coverage_df = load_coverage_results()
        dist_df = load_distributional_metrics()

        # 2. Run Bootstrap Analysis
        bootstrap_results = run_bootstrap_analysis(coverage_df, dist_df)
        save_significance_results(bootstrap_results)

        # 3. Run Conformal Analysis
        conformal_results = run_conformal_analysis(coverage_df, dist_df)
        save_conformal_results(conformal_results)

        logger.info("=== Significance Orchestrator Complete ===")
        logger.info(f"Output files: {RESULTS_DIR}/significance_test.csv, {RESULTS_DIR}/conformal_results.csv")

    except FileNotFoundError as fnf:
        logger.error(f"Missing required input file: {fnf}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Orchestrator failed with unexpected error: {e}")
        traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()