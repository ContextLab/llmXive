"""
Script to export and aggregate final significance and conformal prediction results.

This script loads intermediate results generated by the bootstrap tests and conformal
calibration steps, aggregates them into a final summary format, and saves them to
the results directory as specified in T032.

Output Files:
- results/significance_test.csv: Aggregated pairwise comparison results (p-values, deviations)
- results/conformal_results.csv: Baseline vs. Conformal coverage comparison
"""

import os
import sys
import argparse
from pathlib import Path
from typing import Dict, Any, List, Optional

import pandas as pd
import numpy as np

# Add project root to path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from config import RESULTS_DIR
from utils.logger import get_logger

logger = get_logger(__name__)


def load_and_aggregate_significance_results(
    results_dir: Optional[Path] = None
) -> pd.DataFrame:
    """
    Load and aggregate bootstrap test results from individual series files.
    
    Expects files matching pattern: results/bootstrap_{model1}_{model2}_*.csv
    or a single aggregated file if T029 produced one.
    
    Returns:
        DataFrame with columns: model_a, model_b, metric, deviation, p_value, significant
    """
    if results_dir is None:
        results_dir = RESULTS_DIR
    
    logger.info(f"Loading significance results from {results_dir}")
    
    # Try to find aggregated results first (from T029 aggregate_bootstrap_results)
    aggregated_path = results_dir / "bootstrap_aggregated.csv"
    
    if aggregated_path.exists():
        logger.info(f"Found aggregated bootstrap results at {aggregated_path}")
        df = pd.read_csv(aggregated_path)
        # Ensure standard column names
        required_cols = ['model_a', 'model_b', 'metric', 'deviation', 'p_value']
        for col in required_cols:
            if col not in df.columns:
                raise ValueError(f"Expected column '{col}' not found in {aggregated_path}")
        
        # Add significance flag
        df['significant'] = df['p_value'] < 0.05
        return df
    
    # Otherwise, scan for individual result files
    pattern = "bootstrap_*.csv"
    result_files = list(results_dir.glob(pattern))
    
    if not result_files:
        logger.warning(f"No bootstrap result files found in {results_dir}. Returning empty DataFrame.")
        return pd.DataFrame(columns=['model_a', 'model_b', 'metric', 'deviation', 'p_value', 'significant'])
    
    all_results = []
    
    for file_path in result_files:
        try:
            logger.info(f"Processing {file_path.name}")
            df_chunk = pd.read_csv(file_path)
            
            # Standardize columns if needed
            if 'model_a' not in df_chunk.columns:
                # Try to infer from filename
                parts = file_path.stem.replace("bootstrap_", "").split("_")
                if len(parts) >= 2:
                    df_chunk['model_a'] = parts[0]
                    df_chunk['model_b'] = parts[1] if len(parts) > 1 else "unknown"
            
            if 'significant' not in df_chunk.columns:
                df_chunk['significant'] = df_chunk.get('p_value', 1.0) < 0.05
            
            all_results.append(df_chunk)
            
        except Exception as e:
            logger.error(f"Failed to process {file_path}: {e}")
            continue
    
    if not all_results:
        logger.warning("No valid data found in bootstrap result files.")
        return pd.DataFrame(columns=['model_a', 'model_b', 'metric', 'deviation', 'p_value', 'significant'])
    
    final_df = pd.concat(all_results, ignore_index=True)
    
    # Ensure required columns exist
    for col in ['model_a', 'model_b', 'metric', 'deviation', 'p_value']:
        if col not in final_df.columns:
            final_df[col] = np.nan
    
    if 'significant' not in final_df.columns:
        final_df['significant'] = final_df['p_value'] < 0.05
    
    return final_df


def load_and_aggregate_conformal_results(
    results_dir: Optional[Path] = None
) -> pd.DataFrame:
    """
    Load and aggregate conformal prediction comparison results.
    
    Expects files matching pattern: results/conformal_*.csv
    or a single aggregated file if T030 produced one.
    
    Returns:
        DataFrame with columns: model, series_id, nominal_coverage, baseline_empirical, conformal_empirical, improvement
    """
    if results_dir is None:
        results_dir = RESULTS_DIR
    
    logger.info(f"Loading conformal results from {results_dir}")
    
    # Try to find aggregated results first (from T030 aggregate_conformal_results)
    aggregated_path = results_dir / "conformal_aggregated.csv"
    
    if aggregated_path.exists():
        logger.info(f"Found aggregated conformal results at {aggregated_path}")
        df = pd.read_csv(aggregated_path)
        # Ensure standard column names
        required_cols = ['model', 'series_id', 'nominal_coverage', 'baseline_empirical', 'conformal_empirical']
        for col in required_cols:
            if col not in df.columns:
                raise ValueError(f"Expected column '{col}' not found in {aggregated_path}")
        
        # Calculate improvement
        df['improvement'] = df['conformal_empirical'] - df['baseline_empirical']
        return df
    
    # Otherwise, scan for individual result files
    pattern = "conformal_*.csv"
    result_files = list(results_dir.glob(pattern))
    
    if not result_files:
        logger.warning(f"No conformal result files found in {results_dir}. Returning empty DataFrame.")
        return pd.DataFrame(columns=['model', 'series_id', 'nominal_coverage', 'baseline_empirical', 'conformal_empirical', 'improvement'])
    
    all_results = []
    
    for file_path in result_files:
        try:
            logger.info(f"Processing {file_path.name}")
            df_chunk = pd.read_csv(file_path)
            
            # Standardize columns if needed
            if 'improvement' not in df_chunk.columns:
                if 'conformal_empirical' in df_chunk.columns and 'baseline_empirical' in df_chunk.columns:
                    df_chunk['improvement'] = df_chunk['conformal_empirical'] - df_chunk['baseline_empirical']
            
            all_results.append(df_chunk)
            
        except Exception as e:
            logger.error(f"Failed to process {file_path}: {e}")
            continue
    
    if not all_results:
        logger.warning("No valid data found in conformal result files.")
        return pd.DataFrame(columns=['model', 'series_id', 'nominal_coverage', 'baseline_empirical', 'conformal_empirical', 'improvement'])
    
    final_df = pd.concat(all_results, ignore_index=True)
    
    # Ensure required columns exist
    for col in ['model', 'series_id', 'nominal_coverage', 'baseline_empirical', 'conformal_empirical']:
        if col not in final_df.columns:
            final_df[col] = np.nan
    
    if 'improvement' not in final_df.columns:
        final_df['improvement'] = final_df['conformal_empirical'] - final_df['baseline_empirical']
    
    return final_df


def export_results(
    significance_df: pd.DataFrame,
    conformal_df: pd.DataFrame,
    output_dir: Optional[Path] = None
) -> Dict[str, Path]:
    """
    Save aggregated results to the results directory.
    
    Args:
        significance_df: DataFrame with bootstrap test results
        conformal_df: DataFrame with conformal prediction results
        output_dir: Directory to save results (default: RESULTS_DIR)
    
    Returns:
        Dictionary mapping result type to output file path
    """
    if output_dir is None:
        output_dir = RESULTS_DIR
    
    # Ensure output directory exists
    output_dir.mkdir(parents=True, exist_ok=True)
    
    output_paths = {}
    
    # Save significance results
    significance_path = output_dir / "significance_test.csv"
    significance_df.to_csv(significance_path, index=False)
    output_paths['significance'] = significance_path
    logger.info(f"Saved significance results to {significance_path}")
    
    # Save conformal results
    conformal_path = output_dir / "conformal_results.csv"
    conformal_df.to_csv(conformal_path, index=False)
    output_paths['conformal'] = conformal_path
    logger.info(f"Saved conformal results to {conformal_path}")
    
    return output_paths


def main():
    """Main entry point for exporting results."""
    parser = argparse.ArgumentParser(
        description="Export and aggregate significance and conformal prediction results."
    )
    parser.add_argument(
        "--results-dir",
        type=str,
        default=None,
        help="Path to results directory (default: from config)"
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Path to output directory (default: results/)"
    )
    
    args = parser.parse_args()
    
    results_dir = Path(args.results_dir) if args.results_dir else RESULTS_DIR
    output_dir = Path(args.output_dir) if args.output_dir else RESULTS_DIR
    
    logger.info("Starting result export...")
    
    try:
        # Load and aggregate results
        significance_df = load_and_aggregate_significance_results(results_dir)
        conformal_df = load_and_aggregate_conformal_results(results_dir)
        
        logger.info(f"Loaded {len(significance_df)} significance records")
        logger.info(f"Loaded {len(conformal_df)} conformal records")
        
        # Export to final CSV files
        output_paths = export_results(significance_df, conformal_df, output_dir)
        
        logger.info("Result export completed successfully.")
        logger.info(f"Significance results: {output_paths['significance']}")
        logger.info(f"Conformal results: {output_paths['conformal']}")
        
        # Print summary
        if len(significance_df) > 0:
            logger.info("Significance Summary:")
            logger.info(f"  Total comparisons: {len(significance_df)}")
            logger.info(f"  Significant results (p < 0.05): {significance_df['significant'].sum()}")
        
        if len(conformal_df) > 0:
            logger.info("Conformal Summary:")
            logger.info(f"  Total comparisons: {len(conformal_df)}")
            avg_improvement = conformal_df['improvement'].mean()
            logger.info(f"  Average coverage improvement: {avg_improvement:.4f}")
        
        return 0
        
    except Exception as e:
        logger.error(f"Failed to export results: {e}", exc_info=True)
        return 1


if __name__ == "__main__":
    sys.exit(main())