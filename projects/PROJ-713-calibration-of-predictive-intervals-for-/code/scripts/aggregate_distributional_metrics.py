"""
Script to aggregate PIT and CRPS results into a single CSV file.

This script reads the individual result files generated by the evaluation runner
(which computes PIT and CRPS metrics) and aggregates them into a consolidated
results file for downstream analysis.

Output: results/distributional_metrics.csv
"""
import os
import sys
import argparse
from pathlib import Path
from typing import Optional, List, Dict, Any

import pandas as pd

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from config import RESULTS_DIR
from utils.logger import get_logger
from utils.exceptions import DataValidationError

logger = get_logger(__name__)


def load_coverage_results() -> pd.DataFrame:
    """Load coverage results from results/coverage.csv."""
    coverage_path = RESULTS_DIR / "coverage.csv"
    if not coverage_path.exists():
        raise DataValidationError(
            f"Coverage results file not found at {coverage_path}. "
            "Run the evaluation pipeline first."
        )
    
    logger.info(f"Loading coverage results from {coverage_path}")
    df = pd.read_csv(coverage_path)
    return df


def load_pit_results() -> pd.DataFrame:
    """Load PIT results from results/pit_metrics.csv."""
    pit_path = RESULTS_DIR / "pit_metrics.csv"
    if not pit_path.exists():
        raise DataValidationError(
            f"PIT results file not found at {pit_path}. "
            "Run the evaluation pipeline first."
        )
    
    logger.info(f"Loading PIT results from {pit_path}")
    df = pd.read_csv(pit_path)
    return df


def load_crps_results() -> pd.DataFrame:
    """Load CRPS results from results/crps_metrics.csv."""
    crps_path = RESULTS_DIR / "crps_metrics.csv"
    if not crps_path.exists():
        raise DataValidationError(
            f"CRPS results file not found at {crps_path}. "
            "Run the evaluation pipeline first."
        )
    
    logger.info(f"Loading CRPS results from {crps_path}")
    df = pd.read_csv(crps_path)
    return df


def aggregate_distributional_metrics(
    coverage_df: pd.DataFrame,
    pit_df: pd.DataFrame,
    crps_df: pd.DataFrame
) -> pd.DataFrame:
    """
    Aggregate coverage, PIT, and CRPS results into a single DataFrame.
    
    Args:
        coverage_df: DataFrame with coverage metrics
        pit_df: DataFrame with PIT metrics
        crps_df: DataFrame with CRPS metrics
        
    Returns:
        Combined DataFrame with all distributional metrics
    """
    # Standardize column names for merging
    # Expected keys: dataset, series_id, model, horizon
    
    # Merge coverage and PIT
    merged = pd.merge(
        coverage_df,
        pit_df,
        on=['dataset', 'series_id', 'model', 'horizon'],
        how='outer',
        suffixes=('_coverage', '_pit')
    )
    
    # Merge with CRPS
    merged = pd.merge(
        merged,
        crps_df,
        on=['dataset', 'series_id', 'model', 'horizon'],
        how='outer'
    )
    
    logger.info(f"Aggregated {len(merged)} records from coverage, PIT, and CRPS results")
    
    return merged


def save_aggregated_results(df: pd.DataFrame, output_path: Optional[Path] = None) -> None:
    """Save aggregated results to CSV."""
    if output_path is None:
        output_path = RESULTS_DIR / "distributional_metrics.csv"
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    df.to_csv(output_path, index=False)
    logger.info(f"Saved aggregated distributional metrics to {output_path}")
    logger.info(f"Output shape: {df.shape}")
    logger.info(f"Columns: {list(df.columns)}")


def main(args: Optional[List[str]] = None) -> None:
    """Main entry point for aggregation script."""
    parser = argparse.ArgumentParser(
        description="Aggregate PIT and CRPS results into distributional_metrics.csv"
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Custom output path (default: results/distributional_metrics.csv)"
    )
    parser.add_argument(
        "--coverage",
        type=str,
        default=None,
        help="Override coverage results path"
    )
    parser.add_argument(
        "--pit",
        type=str,
        default=None,
        help="Override PIT results path"
    )
    parser.add_argument(
        "--crps",
        type=str,
        default=None,
        help="Override CRPS results path"
    )
    
    parsed_args = parser.parse_args(args)
    
    try:
        # Load individual result files
        coverage_df = load_coverage_results() if not parsed_args.coverage else pd.read_csv(parsed_args.coverage)
        pit_df = load_pit_results() if not parsed_args.pit else pd.read_csv(parsed_args.pit)
        crps_df = load_crps_results() if not parsed_args.crps else pd.read_csv(parsed_args.crps)
        
        # Aggregate results
        aggregated_df = aggregate_distributional_metrics(coverage_df, pit_df, crps_df)
        
        # Save to output
        output_path = Path(parsed_args.output) if parsed_args.output else None
        save_aggregated_results(aggregated_df, output_path)
        
        logger.info("Aggregation completed successfully")
        
    except DataValidationError as e:
        logger.error(f"Data validation error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during aggregation: {e}")
        raise


if __name__ == "__main__":
    main()
