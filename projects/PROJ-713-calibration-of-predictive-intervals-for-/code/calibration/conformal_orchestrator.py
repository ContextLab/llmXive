"""
Self-Calibrating Conformal Prediction Orchestrator.

This module implements the orchestration logic for applying Self-Calibrating
Conformal Prediction wrappers to existing model forecasts. It reads evaluation
results from `results/coverage.csv`, applies the conformal correction using
the `SelfCalibratingConformalWrapper` from `code/calibration/conformal.py`,
and writes the comparative results to `results/conformal_results.csv`.

Dependency: Must run after T018 (runner.py) completes to ensure
`results/coverage.csv` exists.
"""
import os
import sys
import argparse
import traceback
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple

import pandas as pd
import numpy as np

# Project imports based on provided API surface
from config import Config, ensure_dirs
from utils.logger import get_logger
from utils.exceptions import CalibrationError, DataValidationError
from calibration.conformal import (
    SelfCalibratingConformalWrapper,
    compare_baseline_vs_conformal,
    aggregate_conformal_results,
    conformal_results_to_dataframe
)

logger = get_logger(__name__)


def load_evaluation_results(config: Config) -> pd.DataFrame:
    """
    Load the evaluation results from the coverage CSV generated by T018.

    Args:
        config: The project configuration object containing path constants.

    Returns:
        pd.DataFrame: The coverage results dataframe.

    Raises:
        DataValidationError: If the file does not exist or is empty.
    """
    input_path = config.paths.results / "coverage.csv"

    if not input_path.exists():
        raise DataValidationError(
            f"Input file not found: {input_path}. "
            "Ensure T018 (runner.py) has completed successfully."
        )

    df = pd.read_csv(input_path)

    if df.empty:
        raise DataValidationError(
            f"Input file {input_path} is empty. "
            "Cannot proceed with conformal calibration."
        )

    required_cols = ["series_id", "model", "nominal_level", "empirical_coverage"]
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise DataValidationError(
            f"Input file missing required columns: {missing_cols}"
        )

    logger.info(f"Loaded evaluation results from {input_path} ({len(df)} rows)")
    return df


def run_conformal_calibration(
    coverage_df: pd.DataFrame,
    config: Config
) -> pd.DataFrame:
    """
    Apply Self-Calibrating Conformal Prediction to each series/model combination
    in the coverage dataframe.

    This function:
    1. Iterates over unique series_id and model combinations.
    2. Instantiates the SelfCalibratingConformalWrapper.
    3. Computes the baseline coverage deviation.
    4. Applies the conformal correction.
    5. Calculates the improvement delta.

    Args:
        coverage_df: The dataframe containing coverage metrics.
        config: The project configuration.

    Returns:
        pd.DataFrame: A dataframe with conformal calibration results.
    """
    results = []
    wrapper = SelfCalibratingConformalWrapper(config=config)

    # Group by series and model to process each unique forecast scenario
    group_keys = coverage_df.groupby(["series_id", "model"]).groups.keys()

    for series_id, model in group_keys:
        logger.info(f"Processing Conformal Calibration for {series_id} ({model})")
        try:
            # Filter data for this specific series and model
            subset = coverage_df[
                (coverage_df["series_id"] == series_id) &
                (coverage_df["model"] == model)
            ]

            # We expect one row per nominal level per series/model,
            # but we aggregate or pick the primary level (e.g., 0.95) for the wrapper.
            # For this implementation, we assume the wrapper handles the level internally
            # or we process the 0.95 level as the primary calibration target.
            # If multiple levels exist, we process the highest confidence level (0.95)
            # as the representative baseline.
            target_level = 0.95
            if 0.95 not in subset["nominal_level"].values:
                # Fallback to max available level if 0.95 missing
                target_level = subset["nominal_level"].max()

            target_row = subset[subset["nominal_level"] == target_level].iloc[0]

            baseline_coverage = target_row["empirical_coverage"]
            nominal_level = target_row["nominal_level"]

            # Calculate the deviation from nominal (baseline metric)
            baseline_deviation = abs(baseline_coverage - nominal_level)

            # Apply conformal wrapper logic
            # The wrapper typically takes the original forecasts/residuals
            # and the nominal level to compute a corrected interval.
            # Here we simulate the wrapper's effect on the coverage metric
            # based on the 'compare_baseline_vs_conformal' utility.
            # In a full implementation, the wrapper would need the actual
            # forecast distribution or residuals, which we assume are
            # reconstructed or passed via the wrapper's internal state
            # derived from the coverage context.

            # Since we only have summary stats here, we use the wrapper
            # to estimate the corrected coverage based on the baseline deviation.
            # The 'compare_baseline_vs_conformal' function is expected to
            # perform the statistical adjustment.
            conformal_result = wrapper.calibrate_and_evaluate(
                series_id=series_id,
                model_name=model,
                baseline_coverage=baseline_coverage,
                nominal_level=nominal_level
            )

            conformal_coverage = conformal_result["conformal_coverage"]
            conformal_deviation = conformal_result["conformal_deviation"]

            # Calculate improvement
            improvement = baseline_deviation - conformal_deviation

            results.append({
                "series_id": series_id,
                "model": model,
                "calibration_metric": "absolute_deviation",
                "baseline_value": baseline_deviation,
                "conformal_value": conformal_deviation,
                "improvement_delta": improvement
            })

        except Exception as e:
            logger.error(f"Failed to calibrate {series_id} ({model}): {str(e)}")
            # Log the error but continue processing other series
            results.append({
                "series_id": series_id,
                "model": model,
                "calibration_metric": "absolute_deviation",
                "baseline_value": np.nan,
                "conformal_value": np.nan,
                "improvement_delta": np.nan
            })

    return pd.DataFrame(results)


def process_all_series(
    coverage_df: pd.DataFrame,
    config: Config
) -> pd.DataFrame:
    """
    Main processing loop for all series in the coverage dataframe.

    Args:
        coverage_df: Input coverage dataframe.
        config: Project configuration.

    Returns:
        pd.DataFrame: Processed conformal results.
    """
    return run_conformal_calibration(coverage_df, config)


def save_conformal_results(results_df: pd.DataFrame, config: Config) -> str:
    """
    Save the conformal results to the specified output file.

    Args:
        results_df: The dataframe containing conformal results.
        config: Project configuration.

    Returns:
        str: The path to the saved file.
    """
    output_path = config.paths.results / "conformal_results.csv"

    # Ensure directory exists
    ensure_dirs(config)

    results_df.to_csv(output_path, index=False)
    logger.info(f"Saved conformal results to {output_path}")
    return str(output_path)


def main():
    """
    Entry point for the conformal orchestrator script.
    """
    parser = argparse.ArgumentParser(
        description="Run Self-Calibrating Conformal Prediction on evaluation results."
    )
    parser.add_argument(
        "--config",
        type=str,
        default="code/config.yaml",
        help="Path to the configuration file."
    )
    args = parser.parse_args()

    try:
        # Initialize configuration
        config = Config(args.config)
        ensure_dirs(config)

        # Load evaluation results
        logger.info("Loading evaluation results...")
        coverage_df = load_evaluation_results(config)

        # Process conformal calibration
        logger.info("Running conformal calibration...")
        results_df = process_all_series(coverage_df, config)

        # Save results
        output_path = save_conformal_results(results_df, config)

        # Verification
        if results_df.empty:
            logger.warning("No results generated. Check logs for errors.")
        else:
            logger.info(f"Successfully processed {len(results_df)} series.")
            logger.info(f"Output written to: {output_path}")

            # Basic validation of output schema
            expected_cols = [
                "series_id", "model", "calibration_metric",
                "baseline_value", "conformal_value", "improvement_delta"
            ]
            if not all(col in results_df.columns for col in expected_cols):
                raise DataValidationError(
                    f"Output missing expected columns. Found: {results_df.columns.tolist()}"
                )

    except Exception as e:
        logger.critical(f"Orchestrator failed: {str(e)}")
        traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()
