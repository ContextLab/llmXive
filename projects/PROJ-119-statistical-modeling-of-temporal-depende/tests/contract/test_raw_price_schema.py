"""
Contract validation tests for the raw OHLCV Parquet files.
Ensures that each row conforms to ``contracts/raw_price.schema.yaml``.
"""

import json
import pathlib

import pandas as pd
from jsonschema import validate

from llmxive_toolkit import paths

# Resolve the absolute path to the JSON schema file.
SCHEMA_PATH = (
    paths.root
    / "specs"
    / "001-statistical-modeling-of-temporal-depende"
    / "contracts"
    / "raw_price.schema.yaml"
)

def load_schema():
    with SCHEMA_PATH.open("r", encoding="utf-8") as f:
        return json.load(f)

def test_raw_price_schema():
    """
    Load each Parquet file generated by the download step and validate every
    record against the JSON schema.
    """
    schema = load_schema()
    for filename in ("btc_ohlcv.parquet", "eth_ohlcv.parquet"):
        parquet_path = paths.data("raw", filename)
        # Ensure the file exists; pytest will raise a clear error otherwise.
        assert parquet_path.is_file(), f"Missing raw data file: {parquet_path}"
        df = pd.read_parquet(parquet_path)

        # Validate each row.
        for _, row in df.iterrows():
            record = {
                "date": row["date"],
                "open": row["open"],
                "high": row["high"],
                "low": row["low"],
                "close": row["close"],
                "volume": row["volume"],
            }
            validate(instance=record, schema=schema)