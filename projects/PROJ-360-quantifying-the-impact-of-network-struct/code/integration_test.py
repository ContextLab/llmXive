"""
Integration Test Script for the Thermal Conductivity Pipeline.

Executes the full pipeline sequence:
1. code/download.py
2. code/construct_network.py
3. code/compute_metrics.py
4. code/analyze.py
5. code/report.py

Verifies that all declared artifacts are generated and checksums match.
"""
import os
import sys
import time
import logging
import json
import subprocess
import hashlib
from pathlib import Path

# Add project root to path for imports
project_root = Path(__file__).parent.parent
code_dir = project_root / "code"
data_dir = project_root / "data"
results_dir = project_root / "results"
models_dir = project_root / "models"

sys.path.insert(0, str(project_root))

from config import Config, initialize_environment

def setup_integration_logger():
    logger = logging.getLogger("integration_test")
    logger.setLevel(logging.INFO)
    if not logger.handlers:
        handler = logging.StreamHandler(sys.stdout)
        handler.setFormatter(logging.Formatter(
            '%(asctime)s - %(name)s - %(levelname)s - %(message)s'
        ))
        logger.addHandler(handler)
    return logger

def check_artifacts_exist(logger):
    """Verify all required artifacts exist before running the pipeline."""
    required_files = [
        data_dir / "raw" / "cif",  # Directory
        data_dir / "processed" / "networks",  # Directory
        data_dir / "processed" / "metrics.csv",
        data_dir / "processed" / "filtered_features.csv",
        results_dir / "correlations.json",
        models_dir / "thermal_predictor.pkl",
        results_dir / "model_performance.json",
        results_dir / "final_report.md"
    ]

    missing = []
    for f in required_files:
        if not f.exists():
            missing.append(str(f))
        else:
            logger.info(f"Found artifact: {f}")

    if missing:
        logger.warning(f"Missing artifacts before pipeline run: {missing}")
        # Note: We do not fail here if they are supposed to be generated by the pipeline
        # unless the task implies they must exist BEFORE the run (which they don't for a fresh run)
        # However, for T027, we are running the pipeline to generate them.
        # So we proceed.
    return len(missing) == 0

def run_pipeline_step(step_name, script_name, args=None, logger=None):
    """Execute a single pipeline step."""
    logger = logger or logging.getLogger("integration_test")
    script_path = code_dir / script_name
    
    if not script_path.exists():
        logger.error(f"Script not found: {script_path}")
        return False

    cmd = [sys.executable, str(script_path)]
    if args:
        cmd.extend(args)

    logger.info(f"Running: {' '.join(cmd)}")
    start_time = time.time()
    
    try:
        result = subprocess.run(
            cmd,
            cwd=project_root,
            capture_output=True,
            text=True,
            timeout=300  # 5 minutes timeout per step
        )
        elapsed = time.time() - start_time
        
        if result.returncode == 0:
            logger.info(f"Step '{step_name}' completed in {elapsed:.2f}s")
            if result.stdout:
                logger.debug(result.stdout)
            return True
        else:
            logger.error(f"Step '{step_name}' failed with return code {result.returncode}")
            logger.error(f"STDOUT: {result.stdout}")
            logger.error(f"STDERR: {result.stderr}")
            return False
    except subprocess.TimeoutExpired:
        logger.error(f"Step '{step_name}' timed out after 300s")
        return False
    except Exception as e:
        logger.error(f"Step '{step_name}' raised exception: {e}")
        return False

def verify_artifacts_post_run(logger):
    """Verify all declared artifacts exist after the pipeline run."""
    required_files = [
        data_dir / "raw" / "cif",
        data_dir / "processed" / "networks",
        data_dir / "processed" / "metrics.csv",
        data_dir / "processed" / "filtered_features.csv",
        results_dir / "correlations.json",
        models_dir / "thermal_predictor.pkl",
        results_dir / "model_performance.json",
        results_dir / "final_report.md"
    ]

    missing = []
    for f in required_files:
        if not f.exists():
            missing.append(str(f))
            logger.error(f"MISSING: {f}")
        else:
            logger.info(f"VERIFIED: {f}")

    if missing:
        logger.error(f"Integration test FAILED: Missing artifacts: {missing}")
        return False
    return True

def verify_checksums(logger):
    """Verify checksums match the recorded values in checksums.json."""
    checksums_file = data_dir / "processed" / "checksums.json"
    if not checksums_file.exists():
        logger.warning("Checksums file not found, skipping verification.")
        return True

    with open(checksums_file, 'r') as f:
        recorded_checksums = json.load(f)

    for rel_path, recorded_hash in recorded_checksums.items():
        full_path = project_root / rel_path
        if not full_path.exists():
            logger.warning(f"Checksum verification skipped for missing file: {rel_path}")
            continue

        # Compute SHA256
        sha256_hash = hashlib.sha256()
        with open(full_path, "rb") as f:
            for byte_block in iter(lambda: f.read(4096), b""):
                sha256_hash.update(byte_block)
        computed_hash = sha256_hash.hexdigest()

        if computed_hash == recorded_hash:
            logger.info(f"Checksum OK: {rel_path}")
        else:
            logger.error(f"Checksum MISMATCH: {rel_path}")
            logger.error(f"  Recorded: {recorded_hash}")
            logger.error(f"  Computed: {computed_hash}")
            return False
    return True

def main():
    logger = setup_integration_logger()
    logger.info("Starting Integration Test for PROJ-360")

    # Initialize environment (for API keys, etc.)
    initialize_environment()

    # Check pre-conditions (optional, as pipeline might generate them)
    check_artifacts_exist(logger)

    # Define pipeline steps
    steps = [
        ("Download CIFs", "download.py", ["--limit", "50", "--output", str(data_dir / "raw" / "cif")]),
        ("Construct Networks", "construct_network.py", ["--input", str(data_dir / "raw" / "cif"), "--output", str(data_dir / "processed" / "networks")]),
        ("Compute Metrics", "compute_metrics.py", ["--input", str(data_dir / "processed" / "networks"), "--output", str(data_dir / "processed" / "metrics.csv")]),
        ("Analyze (VIF, Correlations)", "analyze.py", ["--input", str(data_dir / "processed" / "metrics.csv"), "--output", str(results_dir / "correlations.json")]),
        ("Train Model", "train_model.py", ["--input", str(data_dir / "processed" / "filtered_features.csv"), "--output", str(models_dir / "thermal_predictor.pkl")]),
        ("Stratified CV", "stratified_cv.py", ["--model", str(models_dir / "thermal_predictor.pkl"), "--data", str(data_dir / "processed" / "filtered_features.csv"), "--output", str(results_dir / "model_performance.json")]),
        ("Generate Report", "report.py", ["--performance", str(results_dir / "model_performance.json"), "--output", str(results_dir / "final_report.md")]),
        ("Save Checksums", "save_checksums_to_manifest.py", [])
    ]

    success = True
    for name, script, args in steps:
        if not run_pipeline_step(name, script, args, logger):
            logger.error(f"Pipeline failed at step: {name}")
            success = False
            break

    if not success:
        logger.error("Integration Test FAILED: Pipeline execution error.")
        sys.exit(1)

    # Post-run verification
    if not verify_artifacts_post_run(logger):
        logger.error("Integration Test FAILED: Missing artifacts.")
        sys.exit(1)

    if not verify_checksums(logger):
        logger.error("Integration Test FAILED: Checksum mismatch.")
        sys.exit(1)

    logger.info("Integration Test PASSED: All artifacts generated and verified.")
    sys.exit(0)

if __name__ == "__main__":
    main()