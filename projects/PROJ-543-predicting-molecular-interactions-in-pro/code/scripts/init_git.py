"""
Script to initialize a Git repository and configure .gitignore for the project.
This script is designed to be run from the project root or the code directory.
It creates the .gitignore file in the project root if it doesn't exist.
"""
import os
import subprocess
import sys
from pathlib import Path

def main():
    # Determine the project root based on the script location
    # The script is expected to be in: projects/PROJ-543-predicting-molecular-interactions-in-pro/code/scripts/
    # So the project root is two levels up.
    script_path = Path(__file__).resolve()
    current_dir = script_path.parent
    code_dir = current_dir
    project_root = code_dir.parent

    print(f"Project root identified as: {project_root}")

    # 1. Initialize Git repository if not already initialized
    git_dir = project_root / ".git"
    if not git_dir.exists():
        print("Initializing Git repository...")
        try:
            subprocess.run(["git", "init"], cwd=project_root, check=True)
            print("Git repository initialized successfully.")
        except subprocess.CalledProcessError as e:
            print(f"Error initializing Git repository: {e}", file=sys.stderr)
            sys.exit(1)
    else:
        print("Git repository already initialized.")

    # 2. Configure .gitignore
    gitignore_path = project_root / ".gitignore"
    gitignore_content = """# Byte-compiled / optimized / DLL files
__pycache__/
*.py[cod]
*$py.class

# C extensions
*.so

# Distribution / packaging
.Python
build/
develop-eggs/
dist/
downloads/
eggs/
.eggs/
lib/
lib64/
parts/
sdist/
var/
wheels/
*.egg-info/
.installed.cfg
*.egg

# PyInstaller
*.manifest
*.spec

# Installer logs
pip-log.txt
pip-delete-this-directory.txt

# Unit test / coverage reports
htmlcov/
.coverage
.coverage.*
.nosercache
nosetests.xml
coverage.xml
*.cover
.hypothesis/
.pytest_cache/

# Translations
*.mo
*.pot

# Jupyter Notebook
.ipynb_checkpoints

# pyenv
.python-version

# Environments
.env
.venv
venv/
ENV/
env/
.venv/

# mypy
.mypy_cache/
.dmypy.json
dmypy.json

# Pyre type checker
.pyre/

# Project specific: Data artifacts (Raw, Processed, Results)
# These are large binary/text data files generated by the pipeline.
data/raw/
data/processed/
data/results/
data/reference/
data/checksums.yaml

# Logs
logs/
*.log

# IDEs and editors
.idea/
.vscode/
*.swp
*.swo
*~

# OS generated files
.DS_Store
.DS_Store?
._*
.Spotlight-V100
.Trashes
ehthumbs.db
Thumbs.db

# Temporary files
tmp/
temp/
*.tmp

# Model checkpoints (large binary files)
data/processed/*.pt
data/processed/*.pth
data/results/*.pt
data/results/*.pth

# Configuration overrides
config.local.yaml
.secrets
.env.local
"""

    if not gitignore_path.exists():
        print(f"Creating .gitignore at {gitignore_path}...")
        try:
            with open(gitignore_path, "w", encoding="utf-8") as f:
                f.write(gitignore_content)
            print(".gitignore created successfully.")
        except IOError as e:
            print(f"Error creating .gitignore: {e}", file=sys.stderr)
            sys.exit(1)
    else:
        print(".gitignore already exists. Skipping creation.")

    # 3. Add .gitignore to git (optional, but good practice)
    try:
        subprocess.run(["git", "add", ".gitignore"], cwd=project_root, check=True)
        print("Added .gitignore to git staging area.")
    except subprocess.CalledProcessError:
        # This might fail if git is not configured or no changes, which is okay
        print("Could not add .gitignore to git (may already be tracked or git not configured).")

    print("Git initialization and .gitignore configuration complete.")

if __name__ == "__main__":
    main()