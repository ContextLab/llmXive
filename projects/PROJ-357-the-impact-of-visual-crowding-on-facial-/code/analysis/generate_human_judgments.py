"""
Generate the final human_judgments.csv dataset for Task T030.

This script consumes:
  1. data/interim/stimuli_manifest.json (Stimuli metadata: emotion, flanker_count, eccentricity)
  2. data/processed/human_judgments_raw.csv (Raw synthetic responses from T027/T029)

It produces:
  data/processed/human_judgments.csv
    With required fields:
    participant_id, stimulus_id, emotion_label, response_label, accuracy, flanker_count, eccentricity

The script assumes the raw judgments have been generated by the pilot_runner (T027) and
aggregated/validated by the data_loader (T028/T029). It performs the final join and formatting.
"""
import os
import sys
import json
import logging
import argparse
from pathlib import Path
import pandas as pd

# Setup logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout)
    ]
)
logger = logging.getLogger(__name__)

def load_manifest(manifest_path: Path) -> dict:
    """Load the stimuli manifest."""
    if not manifest_path.exists():
        raise FileNotFoundError(f"Manifest not found at {manifest_path}")
    
    with open(manifest_path, 'r') as f:
        return json.load(f)

def load_raw_judgments(raw_path: Path) -> pd.DataFrame:
    """Load the raw synthetic judgments CSV."""
    if not raw_path.exists():
        raise FileNotFoundError(f"Raw judgments not found at {raw_path}")
    
    df = pd.read_csv(raw_path)
    
    # Ensure required columns exist
    required_cols = ['participant_id', 'stimulus_id', 'true_label', 'response_label']
    missing = [col for col in required_cols if col not in df.columns]
    if missing:
        raise ValueError(f"Raw judgments missing required columns: {missing}")
    
    return df

def main():
    parser = argparse.ArgumentParser(description="Generate final human_judgments.csv")
    parser.add_argument(
        "--manifest", 
        type=str, 
        default="data/interim/stimuli_manifest.json",
        help="Path to stimuli manifest"
    )
    parser.add_argument(
        "--raw-judgments", 
        type=str, 
        default="data/processed/human_judgments_raw.csv",
        help="Path to raw synthetic judgments CSV"
    )
    parser.add_argument(
        "--output", 
        type=str, 
        default="data/processed/human_judgments.csv",
        help="Path for output CSV"
    )
    
    args = parser.parse_args()
    
    manifest_path = Path(args.manifest)
    raw_path = Path(args.raw_judgments)
    output_path = Path(args.output)
    
    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Loading manifest from {manifest_path}")
    manifest = load_manifest(manifest_path)
    
    # Convert manifest to DataFrame for easier joining
    # The manifest structure is typically a list of dicts or a dict of dicts
    # Assuming list of dicts based on standard practices in this project
    if isinstance(manifest, dict):
        # If it's a dict where keys are stimulus_ids, convert to list
        if manifest and isinstance(list(manifest.values())[0], dict):
            manifest_list = []
            for stim_id, data in manifest.items():
                data['stimulus_id'] = stim_id
                manifest_list.append(data)
            manifest_df = pd.DataFrame(manifest_list)
        else:
            # Fallback: try to load as is
            manifest_df = pd.DataFrame([manifest])
    else:
        manifest_df = pd.DataFrame(manifest)
    
    logger.info(f"Manifest loaded with {len(manifest_df)} entries")
    
    # Verify required metadata columns exist in manifest
    meta_required = ['stimulus_id', 'emotion_label', 'flanker_count', 'eccentricity']
    # Handle potential naming variations
    if 'emotion' in manifest_df.columns and 'emotion_label' not in manifest_df.columns:
        manifest_df['emotion_label'] = manifest_df['emotion']
    if 'flankers' in manifest_df.columns and 'flanker_count' not in manifest_df.columns:
        manifest_df['flanker_count'] = manifest_df['flankers']
        
    missing_meta = [col for col in meta_required if col not in manifest_df.columns]
    if missing_meta:
        logger.warning(f"Manifest missing some metadata columns: {missing_meta}. Attempting to proceed with available columns.")
    
    logger.info(f"Loading raw judgments from {raw_path}")
    raw_df = load_raw_judgments(raw_path)
    
    # Compute accuracy (1 if response matches true label, 0 otherwise)
    raw_df['accuracy'] = (raw_df['response_label'] == raw_df['true_label']).astype(int)
    
    # Merge with manifest to get stimulus metadata
    # Join on stimulus_id
    if 'stimulus_id' not in manifest_df.columns:
        # Try to infer ID column if it exists
        id_cols = [c for c in manifest_df.columns if 'id' in c.lower()]
        if id_cols:
            manifest_df = manifest_df.rename(columns={id_cols[0]: 'stimulus_id'})
        else:
            raise ValueError("Cannot merge: manifest lacks stimulus_id column")
    
    final_df = raw_df.merge(
        manifest_df[['stimulus_id', 'emotion_label', 'flanker_count', 'eccentricity']],
        on='stimulus_id',
        how='left'
    )
    
    # Check for missing metadata in the merge
    missing_meta_count = final_df[['emotion_label', 'flanker_count', 'eccentricity']].isnull().sum().sum()
    if missing_meta_count > 0:
        logger.warning(f"Found {missing_meta_count} rows with missing metadata after merge. These rows will be dropped.")
        final_df = final_df.dropna(subset=['emotion_label', 'flanker_count', 'eccentricity'])
    
    # Select and order final columns as required
    final_columns = [
        'participant_id', 
        'stimulus_id', 
        'emotion_label', 
        'response_label', 
        'accuracy', 
        'flanker_count', 
        'eccentricity'
    ]
    
    # Ensure all required columns are present
    missing_final = [col for col in final_columns if col not in final_df.columns]
    if missing_final:
        raise ValueError(f"Final dataset missing required columns: {missing_final}")
    
    final_df = final_df[final_columns]
    
    # Save to CSV
    logger.info(f"Writing final dataset to {output_path} ({len(final_df)} rows)")
    final_df.to_csv(output_path, index=False)
    
    # Log summary statistics
    logger.info("Summary Statistics:")
    logger.info(f"  Total Responses: {len(final_df)}")
    logger.info(f"  Unique Participants: {final_df['participant_id'].nunique()}")
    logger.info(f"  Unique Stimuli: {final_df['stimulus_id'].nunique()}")
    logger.info(f"  Overall Accuracy: {final_df['accuracy'].mean():.2%}")
    
    logger.info("Task T030 completed successfully.")

if __name__ == "__main__":
    main()