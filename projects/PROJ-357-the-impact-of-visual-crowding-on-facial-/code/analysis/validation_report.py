"""
T023: Mandatory Validation for User Story 2.

Generates data/processed/validation_report.json confirming that clutter metrics
(specifically spatial_frequency_energy) correlate with flanker count (p < 0.05).

This script reads the clutter metrics CSV generated by T022 and performs a
statistical test (Pearson correlation) to validate the hypothesis that
increased flanker count leads to increased visual clutter (spatial frequency energy).
"""
import os
import json
import logging
import pandas as pd
import numpy as np
from scipy import stats
from pathlib import Path
from config import set_all_seeds, get_seed, ensure_directories

# Setup logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Paths relative to project root
PROJECT_ROOT = Path(__file__).resolve().parents[2]
METRICS_CSV_PATH = PROJECT_ROOT / "data" / "processed" / "clutter_metrics.csv"
REPORT_OUTPUT_PATH = PROJECT_ROOT / "data" / "processed" / "validation_report.json"

def load_metrics():
    """Load the clutter metrics CSV generated by T022."""
    if not METRICS_CSV_PATH.exists():
        raise FileNotFoundError(
            f"Required input file not found: {METRICS_CSV_PATH}. "
            "Ensure T022 (clutter_metrics.py) has been executed successfully."
        )
    
    df = pd.read_csv(METRICS_CSV_PATH)
    
    required_cols = ['flanker_count', 'spatial_frequency_energy']
    missing_cols = [col for col in required_cols if col not in df.columns]
    if missing_cols:
        raise ValueError(
            f"Missing required columns in {METRICS_CSV_PATH}: {missing_cols}"
        )
    
    # Drop rows with missing values in critical columns
    df = df.dropna(subset=required_cols)
    
    if df.empty:
        raise ValueError("No valid data rows found after cleaning.")
        
    logger.info(f"Loaded {len(df)} valid records from {METRICS_CSV_PATH}")
    return df

def validate_correlation(df):
    """
    Perform Pearson correlation test between flanker_count and spatial_frequency_energy.
    
    Returns:
        dict: Test results including correlation coefficient, p-value, and pass/fail status.
    """
    x = df['flanker_count'].values
    y = df['spatial_frequency_energy'].values

    # Calculate Pearson correlation
    corr_coef, p_value = stats.pearsonr(x, y)
    
    # Determine significance (alpha = 0.05)
    is_significant = p_value < 0.05
    
    # Check direction: we expect positive correlation (more flankers = more energy)
    direction_correct = corr_coef > 0

    result = {
        "test_type": "pearson_correlation",
        "variables": {
            "independent": "flanker_count",
            "dependent": "spatial_frequency_energy"
        },
        "statistics": {
            "correlation_coefficient": float(corr_coef),
            "p_value": float(p_value),
            "sample_size": int(len(df))
        },
        "threshold": 0.05,
        "is_significant": bool(is_significant),
        "direction_correct": bool(direction_correct),
        "validation_passed": bool(is_significant and direction_correct)
    }

    logger.info(f"Correlation Coefficient: {corr_coef:.4f}")
    logger.info(f"P-value: {p_value:.4f}")
    logger.info(f"Significant (p < 0.05): {is_significant}")
    logger.info(f"Validation Passed: {result['validation_passed']}")

    return result

def main():
    """Main entry point for T023."""
    logger.info("Starting T023: Mandatory Validation Report Generation")
    
    # Ensure seed for reproducibility (though correlation is deterministic)
    set_all_seeds(get_seed())
    
    # Ensure output directory exists
    ensure_directories([str(REPORT_OUTPUT_PATH.parent)])

    try:
        # 1. Load Data
        df = load_metrics()
        
        # 2. Validate Correlation
        validation_results = validate_correlation(df)
        
        # 3. Construct Final Report
        report = {
            "task_id": "T023",
            "description": "Mandatory Validation: Correlation between clutter metrics and flanker count",
            "status": "completed" if validation_results["validation_passed"] else "failed",
            "timestamp": pd.Timestamp.now().isoformat(),
            "input_file": str(METRICS_CSV_PATH.relative_to(PROJECT_ROOT)),
            "output_file": str(REPORT_OUTPUT_PATH.relative_to(PROJECT_ROOT)),
            "results": validation_results,
            "conclusion": (
                "The clutter metrics (spatial_frequency_energy) significantly correlate with "
                "flanker count (p < 0.05)." if validation_results["validation_passed"] else
                "The clutter metrics (spatial_frequency_energy) do NOT significantly correlate "
                "with flanker count (p >= 0.05) or correlation direction is unexpected."
            )
        }

        # 4. Write Report to Disk
        with open(REPORT_OUTPUT_PATH, 'w') as f:
            json.dump(report, f, indent=2)
        
        logger.info(f"Validation report written to {REPORT_OUTPUT_PATH}")
        
        # Exit with error code if validation failed to block pipeline
        if not validation_results["validation_passed"]:
            logger.error("Validation failed. Blocking further phases.")
            return 1
            
        return 0

    except FileNotFoundError as e:
        logger.error(f"Input data missing: {e}")
        return 1
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        return 1
    except Exception as e:
        logger.exception(f"Unexpected error during validation: {e}")
        return 1

if __name__ == "__main__":
    exit_code = main()
    exit(exit_code)