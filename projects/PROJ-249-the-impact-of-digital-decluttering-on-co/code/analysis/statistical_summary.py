def aggregate_results() -> List[Dict[str, Any]]:
    """
    Aggregates all intermediate results into a unified statistical summary.
    """
    try:
        raw_p_values = load_p_values_from_json()
        corrected_p_values = load_corrected_p_values()
        change_scores = load_change_scores_summary()
        effect_sizes = load_effect_size_summary()
    except FileNotFoundError as e:
        logger.error(str(e))
        raise

    summary_metrics = []
    metrics = set(change_scores.keys()) | set(effect_sizes.keys())

    for metric in sorted(metrics):
        change_data = change_scores.get(metric, {})
        effect_data = effect_sizes.get(metric, {})
        
        mean_change = change_data.get('mean_change', 0.0)
        ci_lower = change_data.get('ci_lower', 0.0)
        ci_upper = change_data.get('ci_upper', 0.0)
        
        raw_p = raw_p_values.get(metric, 1.0)
        corrected_p = corrected_p_values.get(metric, 1.0)
        
        cohens_d = effect_data.get('cohens_d', 0.0)
        d_ci_lower = effect_data.get('d_ci_lower', 0.0)
        d_ci_upper = effect_data.get('d_ci_upper', 0.0)
        
        is_significant = corrected_p < 0.05
        
        # Determine direction based on hypothesis logic
        # SART: lower is better (decrease)
        # Ospan, PSS, PANAS: higher/lower depends on scale, but usually:
        # Ospan: higher is better
        # PSS: lower is better (stress reduction)
        # PANAS (Positive): higher is better
        direction = "neutral"
        if mean_change < 0:
            direction = "decrease"
        elif mean_change > 0:
            direction = "increase"

        summary_metrics.append({
            "metric": metric,
            "mean_change": round(mean_change, 4),
            "ci_95": [round(ci_lower, 4), round(ci_upper, 4)],
            "raw_p_value": round(raw_p, 6),
            "corrected_p_value": round(corrected_p, 6),
            "is_significant": is_significant,
            "effect_size": {
                "cohens_d": round(cohens_d, 4),
                "ci_95": [round(d_ci_lower, 4), round(d_ci_upper, 4)]
            },
            "direction": direction
        })

    return summary_metrics

def write_summary(summary: List[Dict[str, Any]], output_path: Optional[Path] = None):
    """
    Writes the statistical summary to a JSON file.
    """
    if output_path is None:
        results_dir = get_path('results')
        output_path = Path(results_dir) / 'statistical_summary.json'
    
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    report = {
        "generated_at": "T040 Statistical Summary",
        "description": "Aggregated results including mean changes, CIs, and corrected p-values",
        "success_criteria_check": {
            "SC-001": "Mean changes calculated",
            "SC-002": "95% CIs included",
            "SC-003": "Holm-Bonferroni corrected p-values included",
            "SC-004": "Effect sizes (Cohen's d) included",
            "SC-005": "Significance status determined"
        },
        "metrics": summary
    }

    with open(output_path, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Statistical summary written to {output_path}")

def main():
    """
    Entry point for T040.
    """
    logger.info("Starting T040: Statistical Summary Generation")
    try:
        summary = aggregate_results()
        write_summary(summary)
        logger.info("T040 completed successfully.")
    except Exception as e:
        logger.error(f"T040 failed: {e}")
        raise

if __name__ == "__main__":
    main()
