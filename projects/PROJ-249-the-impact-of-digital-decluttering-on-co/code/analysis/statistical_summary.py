"""
Statistical Summary Generator (Task T040)

Generates `results/statistical_summary.json` containing:
- Mean change scores for all metrics
- 95% Confidence Intervals (from bootstrap)
- Corrected p-values (Holm-Bonferroni)
- Effect sizes (Cohen's d)
- Significance status per metric

Adheres to Success Criteria SC-001 to SC-005.
"""
import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional
from dataclasses import dataclass, asdict

# Local imports from project structure
from config.env_config import get_path, get_config
from analysis.holm_bonferroni import load_p_values_from_json
from analysis.change_scores import load_merged_data, calculate_change_scores_for_participant
from analysis.effect_sizes import calculate_effect_sizes_for_metric, load_merged_data_for_metric

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

@dataclass
class MetricSummary:
    metric_name: str
    mean_change: float
    ci_lower: float
    ci_upper: float
    raw_p_value: float
    corrected_p_value: float
    cohens_d: float
    d_ci_lower: float
    d_ci_upper: float
    is_significant: bool
    direction: str  # 'increase', 'decrease', 'neutral'

def load_p_values_from_json() -> Dict[str, float]:
    """
    Loads raw p-values from the Holm-Bonferroni intermediate output.
    Expects `results/holm_bonferroni_raw_pvalues.json` generated by T038.
    """
    # Determine path based on config or default
    results_dir = get_path('results')
    input_file = Path(results_dir) / 'holm_bonferroni_raw_pvalues.json'
    
    if not input_file.exists():
        # Fallback: try to find in a standard location if config is not set
        base = Path(__file__).parent.parent.parent
        input_file = base / 'results' / 'holm_bonferroni_raw_pvalues.json'
    
    if not input_file.exists():
        raise FileNotFoundError(f"Raw p-values file not found at {input_file}. "
                                "Run T038 (holm_bonferroni) before T040.")

    with open(input_file, 'r') as f:
        data = json.load(f)
    
    # Handle potential structure variations
    if 'results' in data:
        return {k: v['raw_p'] for k, v in data['results'].items()}
    return data

