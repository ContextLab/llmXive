def load_synthetic_baseline_data() -> List[Dict[str, Any]]:
    """
    Loads synthetic baseline data generated by T017.
    Returns a list of dictionaries with keys: participant_id, metric_type, value.
    """
    base_path = get_path("data_raw")
    file_path = os.path.join(base_path, "synthetic_baseline.csv")
    
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Synthetic baseline data not found at {file_path}. "
                                "Please run T017 (collect_baseline) first.")

    data = []
    with open(file_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            data.append({
                'participant_id': row['participant_id'],
                'metric_type': row['metric_type'],
                'value': float(row['value'])
            })
    
    logger.info(f"Loaded {len(data)} records from synthetic baseline.")
    return data

def simulate_post_intervention(baseline_values: List[float], 
                               effect_size: float, 
                               std_dev: float, 
                               rng: np.random.Generator) -> List[float]:
    """
    Simulates post-intervention values based on baseline values and a desired effect size (Cohen's d).
    
    Cohen's d = (Mean_post - Mean_baseline) / Std_dev
    => Mean_post = Mean_baseline + (d * Std_dev)
    
    We shift the mean of the baseline distribution by the effect size.
    """
    if not baseline_values:
        return []
    
    mean_baseline = np.mean(baseline_values)
    # Generate post values with shifted mean
    # We assume the variance remains similar for the simulation
    post_values = rng.normal(loc=mean_baseline + (effect_size * std_dev), 
                             scale=std_dev, 
                             size=len(baseline_values))
    return post_values.tolist()

