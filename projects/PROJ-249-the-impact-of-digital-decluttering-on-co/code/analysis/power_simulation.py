"""
Monte Carlo Power Simulation for Digital Decluttering Study.

This module implements a Monte Carlo simulation to estimate statistical power
for detecting an effect size of d=0.5 using the Holm-Bonferroni correction.
It relies on synthetic baseline data generated by T009 to simulate post-intervention
outcomes and determine the proportion of iterations where the null hypothesis
is correctly rejected.
"""

import os
import json
import csv
import logging
import numpy as np
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple

# Import from sibling modules as per API surface
from code.utils.random_seed import get_seed, get_rng
from code.analysis.holm_bonferroni import calculate_holm_bonferroni

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Constants
EFFECT_SIZE_TARGET = 0.5
DEFAULT_ITERATIONS = 1000
DEFAULT_ALPHA = 0.05
NUM_METRICS = 4  # SART, Ospan, PSS-10, PANAS

def load_synthetic_baseline_data(
    input_path: str = "data/raw/synthetic_baseline.csv"
) -> Dict[str, List[float]]:
    """
    Load synthetic baseline data and group it by metric type.

    Args:
        input_path: Path to the synthetic baseline CSV file.

    Returns:
        Dictionary mapping metric names to lists of values.

    Raises:
        FileNotFoundError: If the input file does not exist.
        ValueError: If the file is empty or malformed.
    """
    file_path = Path(input_path)
    if not file_path.exists():
        raise FileNotFoundError(f"Synthetic baseline data not found at {input_path}")

    data: Dict[str, List[float]] = {}

    with open(file_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            metric = row.get('metric_type')
            value_str = row.get('value')

            if not metric or value_str is None:
                continue

            try:
                value = float(value_str)
                if metric not in data:
                    data[metric] = []
                data[metric].append(value)
            except ValueError:
                logger.warning(f"Skipping non-numeric value for metric {metric}: {value_str}")

    if not data:
        raise ValueError("No valid data found in synthetic baseline file.")

    logger.info(f"Loaded {sum(len(v) for v in data.values())} records across {len(data)} metrics.")
    return data

def simulate_post_intervention(
    baseline_data: Dict[str, List[float]],
    effect_size: float,
    rng: np.random.Generator
) -> Dict[str, List[float]]:
    """
    Simulate post-intervention data based on baseline data and a target effect size.

    This function applies a Cohen's d shift to the baseline distribution to
    generate the post-intervention distribution.

    Args:
        baseline_data: Dictionary of baseline values by metric.
        effect_size: Target Cohen's d effect size.
        rng: NumPy random generator instance.

    Returns:
        Dictionary mapping metric names to simulated post-intervention values.
    """
    post_data: Dict[str, List[float]] = {}

    for metric, values in baseline_data.items():
        if not values:
            continue

        baseline_mean = np.mean(values)
        baseline_std = np.std(values, ddof=1)

        if baseline_std == 0:
            baseline_std = 1.0  # Avoid division by zero, though unlikely in synthetic data

        # Calculate the shift in raw units: Delta = d * sigma
        shift = effect_size * baseline_std

        # Generate post-intervention values: X_post ~ N(mu_base + shift, sigma_base)
        # We assume the standard deviation remains roughly constant.
        n_samples = len(values)
        simulated_values = rng.normal(
            loc=baseline_mean + shift,
            scale=baseline_std,
            size=n_samples
        )

        post_data[metric] = simulated_values.tolist()

    return post_data

def run_power_simulation_iteration(
    baseline_data: Dict[str, List[float]],
    effect_size: float,
    alpha: float,
    rng: np.random.Generator
) -> Tuple[bool, Dict[str, float]]:
    """
    Run a single iteration of the power simulation.

    1. Simulate post-intervention data with the target effect size.
    2. Perform a paired t-test (simulated via independent t-test on paired structure
       for simplicity in this Monte Carlo context, or strictly paired if data structure allows).
       *Correction*: Since we are simulating from the same participants (paired design),
       we simulate the difference directly or correlate the samples.
       For this implementation, we will simulate the difference scores directly to ensure
       the paired nature is respected and power is accurately estimated for a within-subjects design.

    3. Apply Holm-Bonferroni correction to the p-values.
    4. Return True if at least one hypothesis is rejected after correction.

    Args:
        baseline_data: Baseline values.
        effect_size: Target effect size.
        alpha: Significance level.
        rng: Random generator.

    Returns:
        Tuple of (is_significant, p_values_dict).
    """
    # For a within-subjects design, the power depends on the correlation between
    # baseline and post. However, for a standard power simulation of d=0.5,
    # we often simulate the difference scores directly.
    # Difference ~ N(d * sigma, sigma_diff).
    # If we assume correlation r=0.5, sigma_diff = sigma * sqrt(2*(1-r)) = sigma.
    # So we can simulate differences directly with mean = d * sigma and std = sigma.

    p_values = {}
    rejected_count = 0

    for metric, values in baseline_data.items():
        if not values:
            continue

        n = len(values)
        baseline_mean = np.mean(values)
        baseline_std = np.std(values, ddof=1)
        if baseline_std == 0: baseline_std = 1.0

        # Simulate difference scores: D ~ N(mu_diff, sigma_diff)
        # Under H1: mu_diff = effect_size * sigma
        # We assume sigma_diff approx sigma for simplicity in this generic simulation
        # unless specific correlation data is available.
        diff_mean = effect_size * baseline_std
        diff_std = baseline_std  # Assumption: sigma_diff ~ sigma

        differences = rng.normal(loc=diff_mean, scale=diff_std, size=n)

        # Perform one-sample t-test on differences against 0
        t_stat = np.mean(differences) / (np.std(differences, ddof=1) / np.sqrt(n))
        # Two-tailed p-value approximation using t-distribution
        # Using scipy for accurate p-value would be better, but to minimize deps if not strictly needed:
        # However, scipy is listed in requirements.
        try:
            from scipy import stats
            # df = n - 1
            p_val = 2 * stats.t.sf(np.abs(t_stat), df=n-1)
        except ImportError:
            # Fallback to normal approximation if scipy missing (less accurate for small n)
            p_val = 2 * (1 - stats.norm.cdf(np.abs(t_stat)))

        p_values[metric] = p_val

    # Apply Holm-Bonferroni
    holm_result = calculate_holm_bonferroni(p_values, alpha)

    # Check if any are significant after correction
    for metric, corrected_p in holm_result['adjusted_p_values'].items():
        if corrected_p < alpha:
            rejected_count += 1

    is_significant = rejected_count > 0
    return is_significant, p_values

def run_power_simulation(
    input_path: str = "data/raw/synthetic_baseline.csv",
    output_path: str = "results/power_analysis.json",
    iterations: int = DEFAULT_ITERATIONS,
    effect_size: float = EFFECT_SIZE_TARGET,
    alpha: float = DEFAULT_ALPHA
) -> Dict[str, Any]:
    """
    Execute the full Monte Carlo power simulation.

    Args:
        input_path: Path to synthetic baseline data.
        output_path: Path to write results.
        iterations: Number of Monte Carlo iterations.
        effect_size: Target effect size (Cohen's d).
        alpha: Significance threshold.

    Returns:
        Dictionary containing power analysis results.
    """
    logger.info(f"Starting Power Simulation: {iterations} iterations, d={effect_size}")

    # Load data
    baseline_data = load_synthetic_baseline_data(input_path)
    logger.info(f"Loaded data for metrics: {list(baseline_data.keys())}")

    # Initialize RNG
    seed = get_seed()
    rng = get_rng(seed)

    significant_count = 0

    for i in range(iterations):
        is_sig, _ = run_power_simulation_iteration(
            baseline_data, effect_size, alpha, rng
        )
        if is_sig:
            significant_count += 1

        if (i + 1) % 100 == 0:
            logger.info(f"Iteration {i+1}/{iterations} complete.")

    power_estimate = significant_count / iterations

    results = {
        "power_estimate": float(power_estimate),
        "iterations": iterations,
        "effect_size": effect_size,
        "alpha": alpha,
        "significant_iterations": significant_count,
        "method": "Monte Carlo with Holm-Bonferroni correction",
        "seed": seed
    }

    # Ensure output directory exists
    output_dir = Path(output_path).parent
    output_dir.mkdir(parents=True, exist_ok=True)

    # Write results
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(results, f, indent=2)

    logger.info(f"Power simulation complete. Estimated Power: {power_estimate:.4f}")
    logger.info(f"Results written to {output_path}")

    return results

def write_power_results(results: Dict[str, Any], output_path: str) -> None:
    """
    Write power simulation results to a JSON file.

    Args:
        results: Dictionary of results.
        output_path: Path to output file.
    """
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(results, f, indent=2)

def main():
    """Main entry point for the power simulation script."""
    # Default paths relative to project root
    input_file = "data/raw/synthetic_baseline.csv"
    output_file = "results/power_analysis.json"

    # Check if input exists (fail loudly if not)
    if not os.path.exists(input_file):
        raise FileNotFoundError(
            f"Input file {input_file} not found. "
            "Please run T009 (synthetic baseline generation) first."
        )

    try:
        results = run_power_simulation(
            input_path=input_file,
            output_path=output_file,
            iterations=1000,
            effect_size=0.5
        )
        print(f"Power Estimate: {results['power_estimate']:.4f}")
        print(f"Output saved to: {output_file}")
    except Exception as e:
        logger.error(f"Power simulation failed: {e}")
        raise

if __name__ == "__main__":
    main()