"""
produce_smoke_results.py

This script runs a lightweight "smoke" analysis on the simulated dataset
produced by task T003a. It computes, for each metric, the mean change
(post - baseline), a bootstrap confidence interval, an uncorrected p‑value,
a Holm‑Bonferroni corrected p‑value, and Cohen's d effect size. The
results are written to ``data/results/smoke_results.json`` in a format that
conforms to ``contracts/analysis.schema.yaml``.
"""

