"""
Validation script to check results against success criteria (SC-001 to SC-005).

This script loads the statistical summary generated by the analysis pipeline,
validates that results meet the predefined success criteria, and generates
a validation report.

Success Criteria:
- SC-001: SART commission errors show significant reduction (p < 0.05) with negative change
- SC-002: Ospan scores show significant improvement (p < 0.05) with positive change
- SC-003: PSS-10 scores show significant reduction (p < 0.05) with negative change
- SC-004: PANAS Positive Affect shows significant increase (p < 0.05) with positive change
- SC-005: PANAS Negative Affect shows significant reduction (p < 0.05) with negative change
"""

import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Tuple, Optional
from dataclasses import dataclass, field

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

@dataclass
class SuccessCriterion:
    """Represents a single success criterion."""
    id: str
    metric: str
    hypothesis_direction: str  # 'negative' for reduction, 'positive' for increase
    p_threshold: float
    d_threshold: float
    description: str

@dataclass
class ValidationResult:
    """Result of checking a single criterion."""
    criterion_id: str
    metric: str
    passed: bool
    p_value: Optional[float] = None
    effect_size: Optional[float] = None
    observed_change: Optional[float] = None
    observed_direction: Optional[str] = None
    reason: str = ""

@dataclass
class ValidationReport:
    """Complete validation report."""
    timestamp: str
    all_criteria_passed: bool
    results: List[ValidationResult]
    summary: Dict[str, Any]
    raw_summary_path: str
    validation_details: str

def get_metric_key(metric_name: str) -> str:
    """Normalize metric names to match keys in statistical_summary.json."""
    # Map common metric names to their keys in the summary
    metric_mapping = {
        'SART': 'SART_commission_errors',
        'SART_commission_errors': 'SART_commission_errors',
        'Ospan': 'Ospan_total_correct',
        'Ospan_total_correct': 'Ospan_total_correct',
        'PSS-10': 'PSS10_total',
        'PSS10': 'PSS10_total',
        'PSS10_total': 'PSS10_total',
        'PANAS_Positive': 'PANAS_positive_affect',
        'PANAS_positive_affect': 'PANAS_positive_affect',
        'PANAS_Negative': 'PANAS_negative_affect',
        'PANAS_negative_affect': 'PANAS_negative_affect',
    }
    return metric_mapping.get(metric_name, metric_name)

def load_statistical_summary(summary_path: str) -> Dict[str, Any]:
    """Load the statistical summary JSON file."""
    path = Path(summary_path)
    if not path.exists():
        raise FileNotFoundError(f"Statistical summary file not found: {summary_path}")
    
    with open(path, 'r') as f:
        summary = json.load(f)
    
    logger.info(f"Loaded statistical summary from {summary_path}")
    return summary

def check_criterion(
    criterion: SuccessCriterion,
    summary_data: Dict[str, Any]
) -> ValidationResult:
    """Check a single success criterion against the summary data."""
    metric_key = get_metric_key(criterion.metric)
    
    # Find the metric in the summary
    metric_data = None
    if isinstance(summary_data, dict):
        metric_data = summary_data.get(metric_key)
        # If not found at top level, search in 'results' or similar
        if metric_data is None and 'results' in summary_data:
            for item in summary_data['results']:
                if item.get('metric') == metric_key or item.get('metric_name') == metric_key:
                    metric_data = item
                    break
    
    if metric_data is None:
        return ValidationResult(
            criterion_id=criterion.id,
            metric=criterion.metric,
            passed=False,
            reason=f"Metric '{metric_key}' not found in statistical summary"
        )
    
    # Extract values
    p_value = metric_data.get('p_value') or metric_data.get('p_corrected')
    effect_size = metric_data.get('effect_size') or metric_data.get('cohens_d')
    change_score = metric_data.get('mean_change')
    
    if p_value is None:
        return ValidationResult(
            criterion_id=criterion.id,
            metric=criterion.metric,
            passed=False,
            reason="p-value not found in summary data"
        )
    
    # Check significance
    is_significant = p_value < criterion.p_threshold
    
    # Check direction
    observed_direction = None
    if change_score is not None:
        if change_score < 0:
            observed_direction = 'negative'
        elif change_score > 0:
            observed_direction = 'positive'
        else:
            observed_direction = 'zero'
    
    direction_matches = (observed_direction == criterion.hypothesis_direction)
    
    # Check effect size (if threshold specified)
    effect_size_pass = True
    if criterion.d_threshold is not None and effect_size is not None:
        effect_size_pass = abs(effect_size) >= criterion.d_threshold
    
    # Overall pass
    passed = is_significant and direction_matches and effect_size_pass
    
    reason_parts = []
    if not is_significant:
        reason_parts.append(f"p={p_value:.4f} >= {criterion.p_threshold}")
    if not direction_matches:
        reason_parts.append(f"direction mismatch: expected {criterion.hypothesis_direction}, got {observed_direction}")
    if not effect_size_pass and effect_size is not None:
        reason_parts.append(f"effect size {effect_size:.4f} < {criterion.d_threshold}")
    
    return ValidationResult(
        criterion_id=criterion.id,
        metric=criterion.metric,
        passed=passed,
        p_value=p_value,
        effect_size=effect_size,
        observed_change=change_score,
        observed_direction=observed_direction,
        reason="; ".join(reason_parts) if reason_parts else "All checks passed"
    )

def check_all_significant_criteria(
    criteria: List[SuccessCriterion],
    summary_data: Dict[str, Any]
) -> List[ValidationResult]:
    """Check all success criteria against the summary data."""
    results = []
    for criterion in criteria:
        result = check_criterion(criterion, summary_data)
        results.append(result)
    return results

def validate_success_criteria(
    summary_path: str,
    output_path: Optional[str] = None
) -> ValidationReport:
    """
    Validate all success criteria against the statistical summary.
    
    Args:
        summary_path: Path to the statistical_summary.json file
        output_path: Optional path to write the validation report (JSON)
    
    Returns:
        ValidationReport object with all results
    """
    from datetime import datetime
    
    # Define success criteria (SC-001 to SC-005)
    criteria = [
        SuccessCriterion(
            id="SC-001",
            metric="SART_commission_errors",
            hypothesis_direction="negative",  # Reduction expected
            p_threshold=0.05,
            d_threshold=0.2,
            description="SART commission errors show significant reduction"
        ),
        SuccessCriterion(
            id="SC-002",
            metric="Ospan_total_correct",
            hypothesis_direction="positive",  # Improvement expected
            p_threshold=0.05,
            d_threshold=0.2,
            description="Ospan scores show significant improvement"
        ),
        SuccessCriterion(
            id="SC-003",
            metric="PSS10_total",
            hypothesis_direction="negative",  # Reduction expected
            p_threshold=0.05,
            d_threshold=0.2,
            description="PSS-10 scores show significant reduction (less stress)"
        ),
        SuccessCriterion(
            id="SC-004",
            metric="PANAS_positive_affect",
            hypothesis_direction="positive",  # Increase expected
            p_threshold=0.05,
            d_threshold=0.2,
            description="PANAS Positive Affect shows significant increase"
        ),
        SuccessCriterion(
            id="SC-005",
            metric="PANAS_negative_affect",
            hypothesis_direction="negative",  # Reduction expected
            p_threshold=0.05,
            d_threshold=0.2,
            description="PANAS Negative Affect shows significant reduction"
        ),
    ]
    
    # Load summary data
    try:
        summary_data = load_statistical_summary(summary_path)
    except FileNotFoundError as e:
        logger.error(str(e))
        raise
    
    # Check all criteria
    results = check_all_significant_criteria(criteria, summary_data)
    
    # Determine overall pass
    all_passed = all(r.passed for r in results)
    
    # Build summary
    summary = {
        "total_criteria": len(criteria),
        "passed_criteria": sum(1 for r in results if r.passed),
        "failed_criteria": sum(1 for r in results if not r.passed),
        "all_passed": all_passed,
        "criteria_breakdown": {
            r.criterion_id: {
                "passed": r.passed,
                "metric": r.metric,
                "p_value": r.p_value,
                "effect_size": r.effect_size,
                "observed_direction": r.observed_direction,
                "reason": r.reason
            }
            for r in results
        }
    }
    
    # Generate detailed text report
    details_lines = [
        "=" * 70,
        "SUCCESS CRITERIA VALIDATION REPORT",
        "=" * 70,
        f"Timestamp: {datetime.now().isoformat()}",
        f"Source: {summary_path}",
        f"Overall Status: {'PASSED' if all_passed else 'FAILED'}",
        "",
        "Criteria Results:",
        "-" * 70,
    ]
    
    for r in results:
        status = "✓ PASS" if r.passed else "✗ FAIL"
        details_lines.append(f"\n{r.criterion_id}: {r.metric}")
        details_lines.append(f"  Status: {status}")
        details_lines.append(f"  Hypothesis: {r.criterion_id.split('-')[0]} expected {r.hypothesis_direction} change")
        if r.p_value is not None:
            details_lines.append(f"  p-value: {r.p_value:.4f} (threshold: < 0.05)")
        if r.effect_size is not None:
            details_lines.append(f"  Effect Size (Cohen's d): {r.effect_size:.4f} (threshold: >= 0.2)")
        if r.observed_change is not None:
            details_lines.append(f"  Observed Change: {r.observed_change:.4f}")
        if r.observed_direction is not None:
            details_lines.append(f"  Observed Direction: {r.observed_direction}")
        details_lines.append(f"  Reason: {r.reason}")
    
    details_lines.extend([
        "",
        "-" * 70,
        "SUMMARY",
        "-" * 70,
        f"Total Criteria: {summary['total_criteria']}",
        f"Passed: {summary['passed_criteria']}",
        f"Failed: {summary['failed_criteria']}",
        "",
        "CONCLUSION",
        "-" * 70,
    ])
    
    if all_passed:
        details_lines.append(
            "All success criteria have been met. The intervention demonstrates "
            "statistically significant effects in the hypothesized directions with "
            "effect sizes meeting the minimum threshold."
        )
    else:
        failed_ids = [r.criterion_id for r in results if not r.passed]
        details_lines.append(
            f"The following criteria were NOT met: {', '.join(failed_ids)}. "
            "The intervention does not fully satisfy all success criteria."
        )
    
    details_lines.append("=" * 70)
    
    report = ValidationReport(
        timestamp=datetime.now().isoformat(),
        all_criteria_passed=all_passed,
        results=results,
        summary=summary,
        raw_summary_path=summary_path,
        validation_details="\n".join(details_lines)
    )
    
    # Write report to file if output path provided
    if output_path:
        write_validation_report(report, output_path)
    
    return report

def write_validation_report(report: ValidationReport, output_path: str) -> None:
    """Write the validation report to a JSON file and a text file."""
    # Write JSON report
    json_path = Path(output_path)
    if not json_path.suffix:
        json_path = json_path.with_suffix('.json')
    
    with open(json_path, 'w') as f:
        json.dump(report.summary, f, indent=2)
    
    # Write text report
    txt_path = json_path.with_suffix('.txt')
    with open(txt_path, 'w') as f:
        f.write(report.validation_details)
    
    logger.info(f"Validation report written to {json_path} and {txt_path}")

def main():
    """Main entry point for the validation script."""
    import argparse
    
    parser = argparse.ArgumentParser(
        description="Validate success criteria against statistical summary"
    )
    parser.add_argument(
        "--summary",
        type=str,
        default="results/statistical_summary.json",
        help="Path to the statistical summary JSON file"
    )
    parser.add_argument(
        "--output",
        type=str,
        default="results/validation_report.json",
        help="Path to write the validation report"
    )
    
    args = parser.parse_args()
    
    try:
        report = validate_success_criteria(args.summary, args.output)
        
        # Print summary to console
        print("\n" + report.validation_details)
        
        # Exit with appropriate code
        sys.exit(0 if report.all_criteria_passed else 1)
        
    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        sys.exit(2)
    except json.JSONDecodeError as e:
        logger.error(f"Invalid JSON in summary file: {e}")
        sys.exit(3)
    except Exception as e:
        logger.error(f"Validation failed: {e}")
        sys.exit(4)

if __name__ == "__main__":
    main()