    def test_ospan_against_osf_reference_pattern(self, synthetic_ospan_data):
        """
        Test that scoring follows OSF reference patterns (v2.1+).
        
        This test verifies that the scoring logic matches the expected
        behavior from the OSF reference implementation, including:
        - Correct handling of operation-word pairs
        - Proper accuracy rate calculation
        - Consistent span score computation
        """
        grouped = group_data_by_participant(synthetic_ospan_data)
        
        # Test a representative sample of participants
        sample_size = min(5, len(grouped))
        sample_participants = list(grouped.keys())[:sample_size]
        
        for pid in sample_participants:
            trials = grouped[pid]
            result = score_ospan_session(trials)
            
            # Verify basic OSF reference patterns
            assert result['total_correct'] <= result['total_trials']
            assert result['accuracy_rate'] == result['total_correct'] / result['total_trials']
            
            # Span score should be non-negative
            assert result['span_score'] >= 0
            
            # If all trials are correct, span score equals total trials
            if result['total_correct'] == result['total_trials']:
                assert result['span_score'] == result['total_trials']
    
