class TestOspanScoringLogic:
    """Tests for Ospan scoring logic against OSF reference standards."""

    def test_score_ospan_trial_correct_recall(self):
        """
        Test that a single trial with correct recall returns accuracy=1.
        OSF Reference: Correct recall = 1 point.
        """
        trial_input = {
            'stimulus': 'The cat sat on the mat',
            'recall': 'The cat sat on the mat',
            'accuracy': True
        }
        result = score_ospan_trial(trial_input)
        
        assert result is not None
        assert result['accuracy'] == 1
        assert result['recall_correct'] == True

    def test_score_ospan_trial_incorrect_recall(self):
        """
        Test that a single trial with incorrect recall returns accuracy=0.
        OSF Reference: Incorrect recall = 0 points.
        """
        trial_input = {
            'stimulus': 'The cat sat on the mat',
            'recall': 'The dog sat on the mat', # Different
            'accuracy': False
        }
        result = score_ospan_trial(trial_input)
        
        assert result is not None
        assert result['accuracy'] == 0
        assert result['recall_correct'] == False

