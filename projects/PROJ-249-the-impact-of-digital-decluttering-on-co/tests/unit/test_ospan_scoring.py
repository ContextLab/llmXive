SYNTHETIC_DATA_PATH = "data/raw/synthetic_baseline.csv"
OSF_REFERENCE_VERSION = "v2.1"
EXPECTED_SPAN_RANGE = (0, 128)  # Typical Ospan span range
EXPECTED_TOTAL_CORRECT_RANGE = (0, 64)  # Max trials per session


def load_synthetic_ospan_data() -> List[Dict[str, Any]]:
    """
    Load Ospan data from the synthetic baseline dataset generated by T013.
    
    Returns:
        List of dictionaries containing Ospan trial data with keys:
        - participant_id
        - metric_type (should be 'ospan')
        - stimulus
        - recall
        - accuracy
        - timestamp
        
    Raises:
        FileNotFoundError: If synthetic_baseline.csv does not exist
        ValueError: If no Ospan data is found in the file
    """
    data_path = Path(__file__).parent.parent.parent / SYNTHETIC_DATA_PATH
    
    if not data_path.exists():
        raise FileNotFoundError(
            f"Synthetic baseline data not found at {data_path}. "
            "Please run T013 (synthetic_baseline.py) first to generate test data."
        )
    
    ospan_data = []
    
    with open(data_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            if row.get('metric_type') == 'ospan':
                # Convert string values to appropriate types
                trial_data = {
                    'participant_id': row['participant_id'],
                    'stimulus': row['stimulus'],
                    'recall': row['recall'],
                    'accuracy': row['accuracy'].lower() == 'true',
                    'timestamp': row['timestamp']
                }
                ospan_data.append(trial_data)
    
    if not ospan_data:
        raise ValueError(
            "No Ospan data found in synthetic_baseline.csv. "
            "The synthetic data generator (T013) must include Ospan trials."
        )
    
    return ospan_data


def group_data_by_participant(ospan_data: List[Dict[str, Any]]) -> Dict[str, List[Dict[str, Any]]]:
    """
    Group Ospan trials by participant ID.
    
    Args:
        ospan_data: List of Ospan trial dictionaries
        
    Returns:
        Dictionary mapping participant_id to list of their trials
    """
    grouped = {}
    for trial in ospan_data:
        pid = trial['participant_id']
        if pid not in grouped:
            grouped[pid] = []
        grouped[pid].append(trial)
    return grouped


