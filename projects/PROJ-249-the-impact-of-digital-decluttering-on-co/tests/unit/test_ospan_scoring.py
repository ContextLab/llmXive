class TestOspanIntegration:
    """Integration tests for Ospan scoring with full pipeline."""
    
    def test_end_to_end_with_synthetic_data(self):
        """Test end-to-end scoring with synthetic baseline data."""
        try:
            synthetic_data = load_synthetic_ospan_data()
            grouped = group_data_by_participant(synthetic_data)
            
            # Score all participants
            all_results = {}
            for pid, trials in grouped.items():
                all_results[pid] = score_ospan_session(trials)
            
            # Verify we have results for all participants
            assert len(all_results) == len(grouped)
            
            # Verify basic statistics
            total_participants = len(all_results)
            avg_span = sum(r['span_score'] for r in all_results.values()) / total_participants
            avg_accuracy = sum(r['accuracy_rate'] for r in all_results.values()) / total_participants
            
            # Sanity checks
            assert avg_span >= 0
            assert 0 <= avg_accuracy <= 1
            
        except FileNotFoundError as e:
            pytest.skip(f"Synthetic data not available: {e}")
    
    def test_ospan_data_integrity(self):
        """Test that Ospan data maintains integrity through scoring."""
        try:
            synthetic_data = load_synthetic_ospan_data()
            
            # Count total trials in raw data
            raw_trial_count = len(synthetic_data)
            
            # Group and score
            grouped = group_data_by_participant(synthetic_data)
            
            total_scored_trials = sum(
                score_ospan_session(trials)['total_trials']
                for trials in grouped.values()
            )
            
            # Verify no data loss
            assert total_scored_trials == raw_trial_count
            
        except FileNotFoundError as e:
            pytest.skip(f"Synthetic data not available: {e}")


