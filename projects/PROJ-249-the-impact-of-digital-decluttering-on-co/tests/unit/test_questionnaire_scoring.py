"""
Unit tests for PSS-10 and PANAS scoring functions.

This test suite validates the scoring logic for the Perceived Stress Scale (PSS-10)
and the Positive and Negative Affect Schedule (PANAS) questionnaires.

The tests run against synthetic baseline data generated by T017 to ensure
the scoring functions correctly process the data format and produce valid
ranges.

Requirements:
- PSS-10: Sum of 10 items (0-4 scale), with 4 reverse-scored items.
  Expected range: 0-40.
- PANAS: Two scales (Positive Affect, Negative Affect), 10 items each (1-5 scale).
  Expected ranges: 10-50 for each scale.
"""

