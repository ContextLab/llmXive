class TestPSS10Scoring:
    """Tests for PSS-10 scoring logic."""

    def test_pss10_valid_session(self):
        """Test scoring of a valid PSS-10 session with all items."""
        # PSS-10 has 10 items, each scored 0-4
        # Items 4, 5, 7, 8 are positively worded and reverse-scored
        responses = [
            {"item": "1", "value": 2},  # Neutral
            {"item": "2", "value": 3},  # Fairly often
            {"item": "3", "value": 1},  # Occasionally
            {"item": "4", "value": 0},  # Never (reverse: 4)
            {"item": "5", "value": 1},  # Occasionally (reverse: 3)
            {"item": "6", "value": 2},  # Neutral
            {"item": "7", "value": 0},  # Never (reverse: 4)
            {"item": "8", "value": 1},  # Occasionally (reverse: 3)
            {"item": "9", "value": 3},  # Fairly often
            {"item": "10", "value": 2}  # Neutral
        ]

        result = score_pss10_session(responses)

        # Calculate expected score manually
        # Non-reverse items (1,2,3,6,9,10): 2+3+1+2+3+2 = 13
        # Reverse items (4,5,7,8): (4-0)+(4-1)+(4-0)+(4-1) = 4+3+4+3 = 14
        # Total = 27
        expected_total = 27
        expected_count = 10

        assert result["total_score"] == expected_total
        assert result["item_count"] == expected_count
        assert result["mean_score"] == 2.7
        assert result["participant_id"] is None

    def test_pss10_missing_items(self):
        """Test scoring when some items are missing."""
        responses = [
            {"item": "1", "value": 2},
            {"item": "2", "value": 3},
            {"item": "3", "value": 1},
            # Missing items 4-10
        ]

        result = score_pss10_session(responses)

        assert result["item_count"] == 3
        assert result["total_score"] == 6  # 2+3+1
        assert result["mean_score"] == 2.0

    def test_pss10_empty_session(self):
        """Test scoring with empty response list."""
        result = score_pss10_session([])

        assert result["total_score"] == 0
        assert result["item_count"] == 0
        assert result["mean_score"] == 0.0

    def test_pss10_invalid_values(self):
        """Test that invalid values (outside 0-4 range) are handled."""
        responses = [
            {"item": "1", "value": 2},
            {"item": "2", "value": 5},  # Invalid: > 4
            {"item": "3", "value": -1}, # Invalid: < 0
            {"item": "4", "value": 3},
        ]

        # Should still score valid items and skip invalid ones
        result = score_pss10_session(responses)

        # Only items 1 and 4 should be counted: 2 + 3 = 5
        assert result["item_count"] == 2
        assert result["total_score"] == 5

    def test_pss10_with_participant_id(self):
        """Test scoring with participant_id included."""
        responses = [
            {"item": "1", "value": 2},
            {"item": "2", "value": 3},
            {"item": "3", "value": 1},
            {"item": "4", "value": 0},
            {"item": "5", "value": 1},
            {"item": "6", "value": 2},
            {"item": "7", "value": 0},
            {"item": "8", "value": 1},
            {"item": "9", "value": 3},
            {"item": "10", "value": 2}
        ]

        result = score_pss10_session(responses, participant_id="P001")

        assert result["participant_id"] == "P001"
        assert result["total_score"] == 27

    def test_pss10_range_validation(self):
        """Test that PSS-10 scores fall within expected range (0-40)."""
        # Minimum possible score: all 0s
        min_responses = [{"item": str(i), "value": 0} for i in range(1, 11)]
        min_result = score_pss10_session(min_responses)
        assert min_result["total_score"] == 0

        # Maximum possible score: all 4s
        max_responses = [{"item": str(i), "value": 4} for i in range(1, 11)]
        max_result = score_pss10_session(max_responses)
        assert max_result["total_score"] == 40


class TestPANASscoring:
    """Tests for PANAS scoring logic."""

    def test_panas_valid_session(self):
        """Test scoring of a valid PANAS session with all 20 items."""
        # PANAS has 20 items: 10 positive, 10 negative
        # Positive affect items: 1, 3, 5, 9, 10, 12, 14, 16, 17, 19
        # Negative affect items: 2, 4, 6, 7, 8, 11, 13, 15, 18, 20
        responses = []
        for i in range(1, 21):
            responses.append({"item": str(i), "value": 2})  # All neutral

        result = score_panas_session(responses)

        # Each item scored 2, so PA = 10*2 = 20, NA = 10*2 = 20
        assert result["positive_affect"] == 20
        assert result["negative_affect"] == 20
        assert result["total_items"] == 20
        assert result["participant_id"] is None

    def test_panas_partial_session(self):
        """Test scoring with partial responses."""
        responses = [
            {"item": "1", "value": 3},  # Positive
            {"item": "2", "value": 1},  # Negative
            {"item": "3", "value": 4},  # Positive
        ]

        result = score_panas_session(responses)

        # PA: items 1, 3 = 3 + 4 = 7
        # NA: item 2 = 1
        assert result["positive_affect"] == 7
        assert result["negative_affect"] == 1
        assert result["total_items"] == 3

    def test_panas_empty_session(self):
        """Test scoring with empty response list."""
        result = score_panas_session([])

        assert result["positive_affect"] == 0
        assert result["negative_affect"] == 0
