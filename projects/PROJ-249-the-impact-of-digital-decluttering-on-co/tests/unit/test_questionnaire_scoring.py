class TestSyntheticDataIntegration:
    """Integration tests using synthetic baseline data from T013."""

    @pytest.fixture
    def synthetic_baseline_path(self):
        """Path to synthetic baseline data generated by T013."""
        return project_root / "data" / "raw" / "synthetic_baseline.csv"

    def test_load_and_score_from_synthetic_file(self, synthetic_baseline_path):
        """Test loading synthetic data and scoring questionnaire entries."""
        if not synthetic_baseline_path.exists():
            pytest.skip("Synthetic baseline data not found. Run T013 first.")

        # Read synthetic data
        with open(synthetic_baseline_path, 'r', newline='') as f:
            reader = csv.DictReader(f)
            rows = list(reader)

        # Filter for questionnaire data
        pss10_rows = [r for r in rows if r.get("metric_type") == "PSS-10"]
        panas_rows = [r for r in rows if r.get("metric_type") == "PANAS"]

        # Group by participant
        pss10_by_participant = {}
        for row in pss10_rows:
            pid = row["participant_id"]
            if pid not in pss10_by_participant:
                pss10_by_participant[pid] = []
            pss10_by_participant[pid].append({
                "item": row["item_index"],
                "value": int(row["value"])
            })

        # Score each participant's PSS-10
        for pid, responses in pss10_by_participant.items():
            result = score_pss10_session(responses, participant_id=pid)
            assert 0 <= result["total_score"] <= 40
            assert result["item_count"] <= 10

        # Similar test for PANAS
        panas_by_participant = {}
        for row in panas_rows:
            pid = row["participant_id"]
            if pid not in panas_by_participant:
                panas_by_participant[pid] = []
            panas_by_participant[pid].append({
                "item": row["item_index"],
                "value": int(row["value"])
            })

        for pid, responses in panas_by_participant.items():
            result = score_panas_session(responses, participant_id=pid)
            assert 10 <= result["positive_affect"] <= 50
            assert 10 <= result["negative_affect"] <= 50

    def test_score_ranges_in_synthetic_data(self, synthetic_baseline_path):
        """Verify that synthetic data produces scores within expected ranges."""
        if not synthetic_baseline_path.exists():
            pytest.skip("Synthetic baseline data not found. Run T013 first.")

        with open(synthetic_baseline_path, 'r', newline='') as f:
            reader = csv.DictReader(f)
            rows = list(reader)

        pss10_rows = [r for r in rows if r.get("metric_type") == "PSS-10"]
        panas_rows = [r for r in rows if r.get("metric_type") == "PANAS"]

        # Group and score
        pss10_scores = []
        pss10_by_participant = {}
        for row in pss10_rows:
            pid = row["participant_id"]
            if pid not in pss10_by_participant:
                pss10_by_participant[pid] = []
            pss10_by_participant[pid].append({
                "item": row["item_index"],
                "value": int(row["value"])
            })

        for pid, responses in pss10_by_participant.items():
            result = score_pss10_session(responses)
            pss10_scores.append(result["total_score"])

        assert all(0 <= s <= 40 for s in pss10_scores)

        panas_scores = {"PA": [], "NA": []}
        panas_by_participant = {}
        for row in panas_rows:
            pid = row["participant_id"]
            if pid not in panas_by_participant:
                panas_by_participant[pid] = []
            panas_by_participant[pid].append({
                "item": row["item_index"],
                "value": int(row["value"])
            })

        for pid, responses in panas_by_participant.items():
            result = score_panas_session(responses)
            panas_scores["PA"].append(result["positive_affect"])
            panas_scores["NA"].append(result["negative_affect"])

        assert all(10 <= s <= 50 for s in panas_scores["PA"])
        assert all(10 <= s <= 50 for s in panas_scores["NA"])