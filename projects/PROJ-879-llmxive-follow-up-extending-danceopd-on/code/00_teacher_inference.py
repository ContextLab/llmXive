# --- Timeout Handling (Shared with other pipeline scripts) ---
class TimeoutError(Exception):
    pass

def timeout_handler(signum, frame):
    raise TimeoutError("Operation timed out")

def setup_timeout(seconds: int):
    if os.name != 'nt':  # Unix only
        signal.signal(signal.SIGALRM, timeout_handler)
        signal.alarm(seconds)
    else:
        # Fallback for Windows if needed, though signal.alarm not supported
        pass

def cancel_timeout():
    if os.name != 'nt':
        signal.alarm(0)

