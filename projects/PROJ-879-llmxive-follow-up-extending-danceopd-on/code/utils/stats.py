# Constants
BOOTSTRAP_ITERATIONS = 1000
CONFIDENCE_LEVEL = 0.95
ALTERNATIVE = "two-sided"

def load_fidelity_results(input_path: str) -> pd.DataFrame:
    """
    Load the fidelity metrics CSV generated by T030d.

    Expected columns: 'fid_score', 'clip_score', 'routing_match', 'sample_id'
    """
    path = Path(input_path)
    if not path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")

    df = pd.read_csv(path)

    # Validate required columns
    required_cols = ['fid_score', 'clip_score']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in {input_path}: {missing}")

    return df

def calculate_effect_size(group1: np.ndarray, group2: np.ndarray) -> float:
    """
    Calculate Cohen's d effect size between two groups.
    """
    mean1, mean2 = np.mean(group1), np.mean(group2)
    std1, std2 = np.std(group1), np.std(group2)
    n1, n2 = len(group1), len(group2)

    # Pooled standard deviation
    pooled_std = np.sqrt(((n1 - 1) * std1**2 + (n2 - 1) * std2**2) / (n1 + n2 - 2))

    if pooled_std == 0:
        return 0.0

    return (mean1 - mean2) / pooled_std

def run_bootstrap_test(
    group1: np.ndarray,
    group2: np.ndarray,
    n_iterations: int = BOOTSTRAP_ITERATIONS,
    confidence_level: float = CONFIDENCE_LEVEL
) -> Dict[str, Any]:
    """
    Perform a bootstrap test to compare the means of two groups.

    Returns:
        Dictionary with bootstrap statistics and confidence intervals.
    """
    n1, n2 = len(group1), len(group2)
    mean_diffs = []

    for _ in range(n_iterations):
        # Resample with replacement
        resample1 = np.random.choice(group1, size=n1, replace=True)
        resample2 = np.random.choice(group2, size=n2, replace=True)

        diff = np.mean(resample1) - np.mean(resample2)
        mean_diffs.append(diff)

    mean_diffs = np.array(mean_diffs)
    lower_bound = np.percentile(mean_diffs, (1 - confidence_level) / 2 * 100)
    upper_bound = np.percentile(mean_diffs, (1 + confidence_level) / 2 * 100)

    return {
        "mean_difference": float(np.mean(mean_diffs)),
        "std_error": float(np.std(mean_diffs)),
        "confidence_interval": [float(lower_bound), float(upper_bound)],
        "bootstrap_iterations": n_iterations
    }

def run_ttest(
    group1: np.ndarray,
    group2: np.ndarray,
    paired: bool = True
) -> Dict[str, float]:
    """
    Perform a t-test to compare two groups.

    Args:
        group1: Array of values for group 1 (e.g., Teacher metrics)
        group2: Array of values for group 2 (e.g., Tree metrics)
        paired: If True, use paired t-test (samples are matched)

    Returns:
        Dictionary with t-statistic and p-value.
    """
    if paired:
        # Paired t-test: compare differences directly
        t_stat, p_val = stats.ttest_rel(group1, group2)
    else:
        # Independent t-test
        t_stat, p_val = stats.ttest_ind(group1, group2)

    return {
        "t_statistic": float(t_stat),
        "p_value": float(p_val)
    }

def save_statistical_tests(output_path: str, results: Dict[str, Any]) -> None:
    """
    Save the statistical test results to a JSON file.
    """
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    with open(path, 'w') as f:
        json.dump(results, f, indent=2)

def perform_statistical_tests(
    input_path: str,
    output_path: str,
    status: str = "complete"
) -> Dict[str, Any]:
    """
    Main function to perform statistical tests on fidelity metrics.

    This function:
    1. Loads the fidelity metrics (Teacher vs Tree).
    2. Performs paired t-tests on FID and CLIP scores.
    3. Performs bootstrap analysis for robustness.
    4. Saves results to JSON.

    Args:
        input_path: Path to the fidelity metrics CSV.
        output_path: Path to save the statistical test results JSON.
        status: "complete" or "partial" (if timeout occurred).

    Returns:
        Dictionary containing the test results.
    """
    # Load data
    df = load_fidelity_results(input_path)

    # Separate Teacher and Tree metrics
    # Assuming the CSV has columns: 'teacher_fid', 'tree_fid', 'teacher_clip', 'tree_clip'
    # or similar paired structure. If the CSV format is different (e.g., long format),
    # we need to adapt. Based on T030d output description, it likely has paired columns.
    # Let's assume the standard output from T030d is:
    # sample_id, teacher_fid, tree_fid, teacher_clip, tree_clip, routing_match

    required_cols = ['teacher_fid', 'tree_fid', 'teacher_clip', 'tree_clip']
    available_cols = df.columns.tolist()

    # Fallback if columns are named differently (e.g., fid_score, clip_score with a 'source' column)
    if 'teacher_fid' not in available_cols and 'fid_score' in available_cols:
        # Try to pivot or assume specific structure
        # For this implementation, we assume the CSV from T030d has explicit paired columns.
        # If not, we raise an error to force data schema alignment.
        raise ValueError(
            f"Input CSV must contain paired columns: {required_cols}. "
            f"Found: {available_cols}. Please ensure T030d outputs paired metrics."
        )

    teacher_fid = df['teacher_fid'].values
    tree_fid = df['tree_fid'].values
    teacher_clip = df['teacher_clip'].values
    tree_clip = df['tree_clip'].values

    # Remove NaNs
    valid_mask_fid = ~(np.isnan(teacher_fid) | np.isnan(tree_fid))
    valid_mask_clip = ~(np.isnan(teacher_clip) | np.isnan(tree_clip))

    fid_teacher = teacher_fid[valid_mask_fid]
    fid_tree = tree_fid[valid_mask_fid]
    clip_teacher = teacher_clip[valid_mask_clip]
    clip_tree = tree_clip[valid_mask_clip]

    n_fid = len(fid_teacher)
    n_clip = len(clip_teacher)

    results = {
        "status": status,
        "n_samples": {"fid": n_fid, "clip": n_clip},
        "p_value_fid": None,
        "p_value_clip": None,
        "t_statistic_fid": None,
        "t_statistic_clip": None,
        "effect_size_fid": None,
        "effect_size_clip": None,
        "bootstrap_fid": None,
        "bootstrap_clip": None,
        "conclusion": ""
    }

    if n_fid > 1:
        # FID Test
        t_res_fid = run_ttest(fid_teacher, fid_tree, paired=True)
        eff_fid = calculate_effect_size(fid_teacher, fid_tree)
        boot_fid = run_bootstrap_test(fid_teacher, fid_tree)

        results["p_value_fid"] = t_res_fid["p_value"]
        results["t_statistic_fid"] = t_res_fid["t_statistic"]
        results["effect_size_fid"] = eff_fid
        results["bootstrap_fid"] = boot_fid

    if n_clip > 1:
        # CLIP Test
        t_res_clip = run_ttest(clip_teacher, clip_tree, paired=True)
        eff_clip = calculate_effect_size(clip_teacher, clip_tree)
        boot_clip = run_bootstrap_test(clip_teacher, clip_tree)

        results["p_value_clip"] = t_res_clip["p_value"]
        results["t_statistic_clip"] = t_res_clip["t_statistic"]
        results["effect_size_clip"] = eff_clip
        results["bootstrap_clip"] = boot_clip

    # Formulate conclusion
    alpha = 0.05
    conclusions = []
    if results["p_value_fid"] is not None:
        if results["p_value_fid"] < alpha:
            conclusions.append(f"FID difference is statistically significant (p={results['p_value_fid']:.4f}).")
        else:
            conclusions.append(f"FID difference is NOT statistically significant (p={results['p_value_fid']:.4f}).")

    if results["p_value_clip"] is not None:
        if results["p_value_clip"] < alpha:
            conclusions.append(f"CLIP difference is statistically significant (p={results['p_value_clip']:.4f}).")
        else:
            conclusions.append(f"CLIP difference is NOT statistically significant (p={results['p_value_clip']:.4f}).")

    results["conclusion"] = " ".join(conclusions)

    # Save results
    save_statistical_tests(output_path, results)

    return results

def main():
    """
    CLI entry point for T030e.
    """
    parser = argparse.ArgumentParser(description="Perform statistical tests on fidelity metrics (T030e)")
    parser.add_argument("--input", type=str, required=True, help="Path to fidelity metrics CSV (T030d output)")
    parser.add_argument("--output", type=str, required=True, help="Path to save statistical test results JSON")
    parser.add_argument("--timeout", type=float, default=None, help="Timeout in seconds (optional)")

    args = parser.parse_args()

    try:
        if args.timeout:
            setup_timeout(args.timeout)

        results = perform_statistical_tests(args.input, args.output)

        print(f"Statistical tests completed. Results saved to: {args.output}")
        print(f"Conclusion: {results['conclusion']}")

        if args.timeout:
            cancel_timeout()

        sys.exit(0)

    except TimeoutError:
        print("Timeout exceeded. Saving partial results...")
        # Attempt to save partial results if possible, though perform_statistical_tests
        # might have already saved a partial state if it was interrupted during loop.
        # For simplicity, we re-run with status='partial' if we can load partial data,
        # but typically the script exits here.
        # We assume the calling script (T028b/T033b) handles the partial save of the INPUT data.
        # We just log the timeout.
        sys.exit(1)

    except Exception as e:
        print(f"Error during statistical analysis: {e}")
        # Try to save a failure status
        failure_results = {
            "status": "failed",
            "error": str(e),
            "conclusion": "Analysis failed due to error."
        }
        save_statistical_tests(args.output, failure_results)
        sys.exit(1)

if __name__ == "__main__":
    main()