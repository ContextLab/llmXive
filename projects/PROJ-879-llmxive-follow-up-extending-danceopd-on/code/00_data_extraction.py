"""
Data Extraction Module for DanceOPD Teacher Ground Truth.

This module implements the logic to extract features (prompt_embedding, noise_level,
routing_label, velocity_vector) from the teacher inference outputs and stream them
to a Parquet file.

It depends on the output of T013a (teacher_ground_truth.parquet) or a fallback dataset.
"""
