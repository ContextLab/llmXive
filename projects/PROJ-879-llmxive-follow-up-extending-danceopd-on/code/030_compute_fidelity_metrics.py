"""
Task T030: Compute FID and CLIP Score on the entire dataset comparing
Tree-Generated images vs. Teacher-Baseline images.

This script loads the fidelity evaluation results generated by T028,
computes aggregate metrics (mean FID, mean CLIP, degradation deltas),
and writes the results to data/results/fidelity_metrics.csv.

It handles partial results and ensures robustness against missing files.
"""
import argparse
import json
import os
import sys
import signal
from pathlib import Path
from typing import Dict, Any, List, Optional

import pandas as pd
import numpy as np

# Import project utilities
from utils.config import get_config, get_path
from utils.metrics import calculate_fid, calculate_clip_score
from utils.statistics import save_partial_results

# Timeout handling
class TimeoutError(Exception):
    pass

def timeout_handler(signum, frame):
    raise TimeoutError("6-hour timeout exceeded")

def setup_timeout(seconds: int):
    signal.signal(signal.SIGALRM, timeout_handler)
    signal.alarm(seconds)

def cancel_timeout():
    signal.alarm(0)

# Constants
RESULTS_DIR = "data/results"
METRICS_OUTPUT = "data/results/fidelity_metrics.csv"
PARTIAL_OUTPUT = "data/results/partial_results.json"
T28_REPORT = "data/results/fidelity_evaluation_report.json"

def load_fidelity_report() -> Optional[Dict[str, Any]]:
    """Load the report generated by T028 (02_evaluate_fidelity.py)."""
    report_path = Path(RESULTS_DIR) / T28_REPORT
    if not report_path.exists():
        print(f"Error: Fidelity evaluation report not found at {report_path}")
        return None
    
    with open(report_path, 'r') as f:
        return json.load(f)

def compute_metrics_for_depth(
    depth: int, 
    report: Dict[str, Any]
) -> Dict[str, float]:
    """
    Compute aggregate FID and CLIP metrics for a specific tree depth.
    
    Args:
        depth: The max_depth of the decision tree used.
        report: The fidelity evaluation report containing image paths and metrics.
        
    Returns:
        Dictionary with computed metrics.
    """
    # Extract image lists for this depth
    tree_images = report.get(f"tree_depth{depth}_images", [])
    teacher_images = report.get(f"teacher_baseline_images", [])
    
    if not tree_images or not teacher_images:
        print(f"Warning: No images found for depth {depth}. Skipping.")
        return {}

    if len(tree_images) != len(teacher_images):
        print(f"Warning: Mismatch in image counts for depth {depth}. "
              f"Tree: {len(tree_images)}, Teacher: {len(teacher_images)}. "
              "Truncating to minimum length.")
        min_len = min(len(tree_images), len(teacher_images))
        tree_images = tree_images[:min_len]
        teacher_images = teacher_images[:min_len]

    # Calculate FID
    # Note: calculate_fid expects two paths to directories or lists of files.
    # Since T028 saves individual files, we pass the lists directly if supported,
    # or create temp directories. The API surface says calculate_fid(image_path_1, image_path_2).
    # We assume the implementation in T005b handles lists or we aggregate manually.
    # Given the constraint to use existing API, we assume calculate_fid can handle 
    # the two lists of file paths as arguments, or we compute per-sample and average.
    # However, FID is typically dataset-level. We will pass the full lists.
    
    # Attempt to calculate FID for the full set
    try:
        fid_tree = calculate_fid(tree_images, teacher_images)
    except Exception as e:
        print(f"Error calculating FID for depth {depth}: {e}")
        fid_tree = float('nan')

    # Calculate CLIP Score
    # CLIP Score is typically image-text or image-image similarity. 
    # Here we compare the generated image to the teacher baseline image.
    # We compute per-pair and average.
    clip_scores = []
    for t_img, te_img in zip(tree_images, teacher_images):
        try:
            score = calculate_clip_score(t_img, te_img)
            clip_scores.append(score)
        except Exception as e:
            print(f"Error calculating CLIP for pair: {e}")
            continue
    
    clip_tree = np.mean(clip_scores) if clip_scores else float('nan')

    # Calculate degradation deltas
    # Since we are comparing Tree vs Teacher directly, the "Teacher" metric 
    # in the context of degradation is effectively the baseline (0 degradation).
    # However, the task asks for: fid_teacher, fid_tree. 
    # In this specific comparison (Tree vs Teacher), the "Teacher" FID 
    # relative to itself is 0 (or undefined if comparing to a reference).
    # The task description implies: 
    # "comparing Tree-Generated images vs. Teacher-Baseline images"
    # So the "Teacher" column in the CSV likely refers to the baseline metric 
    # (which is 0 degradation) or the FID of the Teacher-Baseline images 
    # against the ground truth (which we don't have here, only the comparison).
    # Interpreting the requirement strictly:
    # fid_teacher: The FID of the Teacher-Baseline set (against a reference?).
    # Since we are doing a pairwise comparison, we treat the Teacher-Baseline 
    # as the reference. Thus, fid_teacher = 0.0 (perfect match to itself).
    # Or, if the requirement implies comparing both to a ground truth, 
    # we cannot do that without the ground truth images.
    # Given the context of "degradation", we report the difference.
    # Let's assume the CSV columns are:
    # depth, fid_teacher (baseline), fid_tree (current), clip_teacher (baseline), clip_tree (current)
    # Since the baseline is the reference, fid_teacher = 0.0, clip_teacher = 1.0 (or max score).
    # However, to be safe and follow the "derivation" instruction:
    # "Derive total degradation metrics (ΔFID, ΔCLIP)"
    # We will set fid_teacher to the FID of the teacher set against itself (0.0)
    # and clip_teacher to 1.0 (perfect similarity).
    
    fid_teacher = 0.0
    clip_teacher = 1.0

    delta_fid = fid_tree - fid_teacher
    delta_clip = clip_tree - clip_teacher

    return {
        "depth": depth,
        "fid_teacher": fid_teacher,
        "fid_tree": fid_tree,
        "clip_teacher": clip_teacher,
        "clip_tree": clip_tree,
        "delta_fid": delta_fid,
        "delta_clip": delta_clip,
        "n_samples": len(tree_images)
    }

def save_results(results: List[Dict[str, Any]]):
    """Save the computed metrics to CSV."""
    if not results:
        print("No results to save.")
        return

    df = pd.DataFrame(results)
    output_path = Path(METRICS_OUTPUT)
    df.to_csv(output_path, index=False)
    print(f"Results saved to {output_path}")

def save_partial(results: List[Dict[str, Any]], reason: str):
    """Save partial results if the process was interrupted."""
    output_path = Path(PARTIAL_OUTPUT)
    data = {
        "status": "partial",
        "reason": reason,
        "results": results
    }
    with open(output_path, 'w') as f:
        json.dump(data, f, indent=2)
    print(f"Partial results saved to {output_path}")

def run_fidelity_metrics_computation(timeout_seconds: int = 21600):
    """Main execution function."""
    setup_timeout(timeout_seconds)
    
    try:
        print("Loading fidelity evaluation report...")
        report = load_fidelity_report()
        if not report:
            print("Failed to load report. Aborting.")
            sys.exit(1)

        # Extract unique depths from the report
        # The report keys should be like "tree_depth2_images", "tree_depth5_images", etc.
        depths = set()
        for key in report.keys():
            if key.startswith("tree_depth") and key.endswith("_images"):
                try:
                    depth = int(key.replace("tree_depth", "").replace("_images", ""))
                    depths.add(depth)
                except ValueError:
                    continue

        if not depths:
            print("No tree depths found in the report.")
            sys.exit(1)

        print(f"Found depths to process: {sorted(depths)}")

        all_results = []
        processed_count = 0

        for depth in sorted(depths):
            print(f"Processing depth {depth}...")
            metrics = compute_metrics_for_depth(depth, report)
            if metrics:
                all_results.append(metrics)
                processed_count += 1
            else:
                print(f"Skipped depth {depth} due to missing data.")

        if processed_count == 0:
            print("No metrics computed. Aborting.")
            sys.exit(1)

        save_results(all_results)
        print("Fidelity metrics computation completed successfully.")

    except TimeoutError:
        print("Timeout exceeded. Saving partial results...")
        # We might have partial results in all_results
        save_partial(all_results, "Timeout exceeded")
        sys.exit(1)
    except Exception as e:
        print(f"Unexpected error: {e}")
        save_partial(all_results, f"Error: {str(e)}")
        sys.exit(1)
    finally:
        cancel_timeout()

def main():
    parser = argparse.ArgumentParser(description="Compute FID and CLIP metrics for T030")
    parser.add_argument("--timeout", type=int, default=21600, help="Timeout in seconds (default: 6 hours)")
    args = parser.parse_args()

    run_fidelity_metrics_computation(timeout_seconds=args.timeout)

if __name__ == "__main__":
    main()