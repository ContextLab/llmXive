import os
import logging
import pandas as pd
import numpy as np
from pathlib import Path
from typing import List, Dict, Optional, Any

from utils import get_logger, ensure_directory

def load_residual_stats(filepath: str) -> pd.DataFrame:
    """
    Load the residual statistics CSV generated by T034.
    Expects columns including 'model', 'p_value' (or similar).
    """
    path = Path(filepath)
    if not path.exists():
        raise FileNotFoundError(f"Residual stats file not found: {filepath}")
    
    df = pd.read_csv(path)
    
    # Ensure we have the necessary columns
    required_cols = ['model', 'p_value']
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in {filepath}: {missing}")
    
    return df

def evaluate_verdict(p_value: float) -> str:
    """
    Apply the logic specified in T036:
    - If p < 0.05: "MOND preferred"
    - Else if p > 0.95: "NFW preferred"
    - Else: "No significant difference"
    
    Note: The logic assumes 'p_value' represents the probability of the 
    null hypothesis (or a specific test statistic derived from the bootstrap).
    Based on the task description:
    "If p < 0.05, output 'MOND preferred'; else if p > 0.95, output 'NFW preferred'..."
    
    This implies a specific directional test where low p favors MOND and high p favors NFW.
    """
    if p_value < 0.05:
        return "MOND preferred"
    elif p_value > 0.95:
        return "NFW preferred"
    else:
        return "No significant difference"

def generate_verdict_report(stats_df: pd.DataFrame, output_path: str) -> str:
    """
    Generate the analysis_verdict.md file based on the residual stats.
    The report summarizes the verdicts for each galaxy or an aggregate if the data is aggregated.
    """
    ensure_directory(output_path)
    
    lines = []
    lines.append("# Analysis Verdict Report")
    lines.append("")
    lines.append("## Methodology")
    lines.append("This report applies the statistical verdict logic to the residual analysis results.")
    lines.append("Criteria:")
    lines.append("- **MOND preferred**: p-value < 0.05")
    lines.append("- **NFW preferred**: p-value > 0.95")
    lines.append("- **No significant difference**: 0.05 <= p-value <= 0.95")
    lines.append("")
    lines.append("## Results")
    lines.append("")
    
    # Assuming the stats_df contains one row per galaxy or an aggregate summary.
    # We iterate through the rows to generate the verdict.
    verdicts = []
    
    for index, row in stats_df.iterrows():
        model = row['model']
        p_val = row['p_value']
        verdict = evaluate_verdict(p_val)
        verdicts.append(verdict)
        
        # Format the row entry
        lines.append(f"### Model: {model}")
        lines.append(f"- **P-value**: {p_val:.4f}")
        lines.append(f"- **Verdict**: {verdict}")
        lines.append("")
    
    # Aggregate summary if multiple rows exist
    if len(verdicts) > 1:
        lines.append("## Summary")
        counts = {v: verdicts.count(v) for v in set(verdicts)}
        lines.append("Overall Verdict Distribution:")
        for v, count in counts.items():
            lines.append(f"- {v}: {count}")
        lines.append("")
        
        # Determine overall conclusion based on majority or specific logic if needed
        # For now, just listing the distribution satisfies the "Generate" requirement.
    
    report_content = "\n".join(lines)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(report_content)
    
    return report_content

def main():
    logger = get_logger(__name__)
    
    # Define paths relative to project root
    # Assuming the script is run from the project root or we handle paths carefully
    base_dir = Path(__file__).resolve().parent.parent
    input_file = base_dir / "results" / "residual_stats.csv"
    output_file = base_dir / "results" / "analysis_verdict.md"
    
    logger.info(f"Loading residual stats from {input_file}")
    
    try:
        stats_df = load_residual_stats(str(input_file))
        logger.info(f"Loaded {len(stats_df)} records.")
        
        logger.info(f"Generating verdict report at {output_file}")
        report = generate_verdict_report(stats_df, str(output_file))
        
        logger.info("Verdict report generation complete.")
        print(report)
        
    except FileNotFoundError as e:
        logger.error(f"Input file not found: {e}")
        raise
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during verdict generation: {e}")
        raise

if __name__ == "__main__":
    main()