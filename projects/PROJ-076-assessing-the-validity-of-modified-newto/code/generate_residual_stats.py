"""
Task T034: Generate `results/residual_stats.csv` with mean, median, std, p-values per model.

Dependencies:
  - T031 (calculate_residuals)
  - T032 (block_bootstrap_permutation_test)
  - T033 (holm_bonferroni_correction)

This script reads the fit results (produced by T025), computes residuals,
runs the statistical tests, and outputs the aggregated statistics to CSV.
"""
import os
import logging
import pandas as pd
import numpy as np
from pathlib import Path
from typing import List, Dict, Optional, Any

# Import from project modules (matching API surface)
from residuals import (
    calculate_residuals,
    block_bootstrap_permutation_test,
    holm_bonferroni_correction,
    generate_residual_stats
)
from utils import get_logger, ensure_directory
from config import get_config

logger = get_logger(__name__)

def load_fit_results(results_dir: Path) -> pd.DataFrame:
    """
    Load the fit_summary.csv generated by T025.
    Expected columns include: galaxy_id, model, reduced_chi2, ...
    """
    fit_summary_path = results_dir / "fit_summary.csv"
    if not fit_summary_path.exists():
        raise FileNotFoundError(
            f"Fit summary file not found at {fit_summary_path}. "
            "Ensure T025 has been executed successfully."
        )
    logger.info(f"Loading fit results from {fit_summary_path}")
    return pd.read_csv(fit_summary_path)

def load_filtered_data(data_dir: Path) -> pd.DataFrame:
    """
    Load the filtered_galaxies.csv generated by T015 to access raw data for residual calculation.
    """
    filtered_path = data_dir / "processed" / "filtered_galaxies.csv"
    if not filtered_path.exists():
        raise FileNotFoundError(
            f"Filtered data file not found at {filtered_path}. "
            "Ensure T015 has been executed successfully."
        )
    logger.info(f"Loading filtered galaxy data from {filtered_path}")
    return pd.read_csv(filtered_path)

def aggregate_residual_stats(
    fit_results: pd.DataFrame,
    raw_data: pd.DataFrame
) -> pd.DataFrame:
    """
    Iterate over galaxies and models, calculate residuals, run permutation tests,
    apply corrections, and aggregate statistics.
    """
    stats_rows = []
    galaxies = fit_results['galaxy_id'].unique()
    models = ['mond', 'nfw']

    logger.info(f"Processing {len(galaxies)} galaxies for {len(models)} models...")

    for galaxy_id in galaxies:
        galaxy_data = raw_data[raw_data['galaxy_id'] == galaxy_id]
        if galaxy_data.empty:
            logger.warning(f"No raw data found for galaxy {galaxy_id}, skipping.")
            continue

        for model in models:
            # Get fit parameters for this galaxy/model from fit_results
            # Assuming fit_results has columns: galaxy_id, model, and parameter columns
            # We need to extract the predicted velocities to compute residuals
            # Since residuals.py expects specific inputs, we simulate the call structure
            # based on the dependency on T031/T032/T033.

            # In a real pipeline, we would retrieve the fitted parameters here.
            # For this task, we assume the residuals.py module has a helper to
            # reconstruct predictions or the fit_results contains enough info.
            # However, to be robust, we rely on the `calculate_residuals` function
            # which likely takes the raw data and the model type.

            try:
                # Calculate residuals
                # This function is expected to return a dict or Series with observed vs predicted
                residuals = calculate_residuals(galaxy_data, model, fit_results)

                # Run block-bootstrap permutation test
                # Returns p-value for the null hypothesis that distributions are equal
                p_value = block_bootstrap_permutation_test(residuals)

                # Store raw stats for later correction
                stats_rows.append({
                    'galaxy_id': galaxy_id,
                    'model': model,
                    'mean_residual': residuals.get('mean', np.nan),
                    'median_residual': residuals.get('median', np.nan),
                    'std_residual': residuals.get('std', np.nan),
                    'raw_p_value': p_value
                })

            except Exception as e:
                logger.error(f"Error processing {galaxy_id} with {model}: {e}")
                # Continue to next, but log the failure
                continue

    if not stats_rows:
        logger.warning("No statistics generated. Check if data or fit results are empty.")
        return pd.DataFrame()

    df_stats = pd.DataFrame(stats_rows)

    # Apply Holm-Bonferroni correction across all tests (or per galaxy? Spec implies global)
    # T033 implements the correction. We pass the dataframe of raw p-values.
    # The function returns the dataframe with corrected p-values.
    if 'raw_p_value' in df_stats.columns:
        df_stats = holm_bonferroni_correction(df_stats)
    else:
        logger.warning("No raw_p_value column found to apply Holm-Bonferroni correction.")

    return df_stats

def main():
    """Main entry point for T034."""
    config = get_config()
    project_root = Path(config.get('project_root', '.'))
    results_dir = project_root / "results"
    data_dir = project_root / "data"

    ensure_directory(results_dir)

    logger.info("Starting T034: Generate Residual Statistics")

    try:
        # 1. Load inputs
        fit_results = load_fit_results(results_dir)
        raw_data = load_filtered_data(data_dir)

        # 2. Compute statistics
        stats_df = aggregate_residual_stats(fit_results, raw_data)

        if stats_df.empty:
            logger.error("Failed to generate any statistics. Exiting.")
            return

        # 3. Write output
        output_path = results_dir / "residual_stats.csv"
        stats_df.to_csv(output_path, index=False)
        logger.info(f"Successfully wrote residual statistics to {output_path}")

    except FileNotFoundError as e:
        logger.error(f"Missing required input file: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during T034 execution: {e}")
        raise

if __name__ == "__main__":
    main()