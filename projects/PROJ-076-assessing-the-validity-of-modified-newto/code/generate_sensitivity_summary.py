"""
Generate a text-based summary of sensitivity sweep results.

This script reads the sensitivity analysis data generated by T026
(results/sensitivity_data.csv) and produces a human-readable summary
report (results/sensitivity_summary.txt) containing pass rates per threshold.

Dependency: T026 must complete first to produce the input CSV.
"""

import os
import logging
import pandas as pd
import numpy as np
from pathlib import Path
from typing import List, Dict, Optional, Any

# Import project utilities
from utils import get_logger, ensure_directory, format_number
from utils.helpers import ensure_directory as ensure_dir_helper

# Constants
INPUT_PATH = Path("results/sensitivity_data.csv")
OUTPUT_PATH = Path("results/sensitivity_summary.txt")
THRESHOLD_SET = [1.0, 1.25, 1.5, 1.75]

def load_sensitivity_data(input_path: Path) -> pd.DataFrame:
    """Load the sensitivity analysis data from CSV."""
    if not input_path.exists():
        raise FileNotFoundError(
            f"Sensitivity data file not found: {input_path}. "
            "Ensure T026 has completed successfully."
        )
    
    df = pd.read_csv(input_path)
    required_cols = {'threshold', 'galaxy_id', 'model', 'passed'}
    if not required_cols.issubset(df.columns):
        missing = required_cols - set(df.columns)
        raise ValueError(
            f"Sensitivity data missing required columns: {missing}. "
            f"Found columns: {list(df.columns)}"
        )
    return df

def compute_summary_stats(df: pd.DataFrame) -> pd.DataFrame:
    """
    Compute pass rates per threshold and model.
    
    Returns a DataFrame with columns:
    - threshold: the chi2 threshold value
    - model: 'MOND' or 'NFW'
    - total_galaxies: count of galaxies at this threshold/model
    - passed_galaxies: count of galaxies that passed the threshold
    - pass_rate: fraction of galaxies that passed (0.0 to 1.0)
    """
    if df.empty:
        logging.warning("Sensitivity data is empty; summary will be empty.")
        return pd.DataFrame(columns=['threshold', 'model', 'total_galaxies', 
                                    'passed_galaxies', 'pass_rate'])

    # Group by threshold and model
    summary = df.groupby(['threshold', 'model']).agg(
        total_galaxies=('galaxy_id', 'count'),
        passed_galaxies=('passed', 'sum')
    ).reset_index()

    # Calculate pass rate
    summary['pass_rate'] = summary.apply(
        lambda row: row['passed_galaxies'] / row['total_galaxies'] 
        if row['total_galaxies'] > 0 else 0.0,
        axis=1
    )

    # Ensure thresholds are sorted
    summary = summary.sort_values(['threshold', 'model'])
    
    return summary

def generate_summary_text(summary_df: pd.DataFrame, input_path: Path) -> str:
    """
    Generate a human-readable text summary of the sensitivity analysis.
    
    Format:
    - Header with generation timestamp and input source
    - Summary of the sensitivity sweep parameters
    - Table of pass rates per threshold and model
    - Interpretation of results
    """
    lines = []
    
    # Header
    lines.append("=" * 70)
    lines.append("SENSITIVITY ANALYSIS SUMMARY REPORT")
    lines.append("=" * 70)
    lines.append("")
    lines.append(f"Generated: {pd.Timestamp.now().strftime('%Y-%m-%d %H:%M:%S')}")
    lines.append(f"Input Data: {input_path}")
    lines.append("")
    
    # Parameters section
    lines.append("-" * 70)
    lines.append("ANALYSIS PARAMETERS")
    lines.append("-" * 70)
    lines.append(f"Chi-squared Thresholds Tested: {THRESHOLD_SET}")
    lines.append(f"Models Evaluated: ['MOND', 'NFW']")
    lines.append(f"Pass Criteria: reduced_χ² <= threshold")
    lines.append("")
    
    # Results section
    lines.append("-" * 70)
    lines.append("PASS RATES BY THRESHOLD AND MODEL")
    lines.append("-" * 70)
    
    if summary_df.empty:
        lines.append("No data available for summary.")
        lines.append("Ensure sensitivity analysis (T026) has completed successfully.")
    else:
        # Create a formatted table
        lines.append("")
        lines.append(f"{'Threshold':<12} {'Model':<10} {'Total':<8} {'Passed':<8} {'Pass Rate':<12}")
        lines.append("-" * 50)
        
        for _, row in summary_df.iterrows():
            lines.append(
                f"{row['threshold']:<12.2f} "
                f"{row['model']:<10} "
                f"{int(row['total_galaxies']):<8} "
                f"{int(row['passed_galaxies']):<8} "
                f"{row['pass_rate']:<12.4f}"
            )
        
        lines.append("")
        
        # Model comparison summary
        lines.append("-" * 70)
        lines.append("MODEL COMPARISON SUMMARY")
        lines.append("-" * 70)
        
        mond_data = summary_df[summary_df['model'] == 'MOND']
        nfw_data = summary_df[summary_df['model'] == 'NFW']
        
        if not mond_data.empty and not nfw_data.empty:
            for threshold in THRESHOLD_SET:
                mond_rate = mond_data[mond_data['threshold'] == threshold]['pass_rate'].values
                nfw_rate = nfw_data[nfw_data['threshold'] == threshold]['pass_rate'].values
                
                if len(mond_rate) > 0 and len(nfw_rate) > 0:
                    mond_val = mond_rate[0]
                    nfw_val = nfw_rate[0]
                    diff = mond_val - nfw_val
                    
                    if diff > 0.01:
                        winner = "MOND"
                    elif diff < -0.01:
                        winner = "NFW"
                    else:
                        winner = "Tie"
                    
                    lines.append(
                        f"Threshold {threshold:<4.2f}: "
                        f"MOND={mond_val:.4f}, NFW={nfw_val:.4f} "
                        f"(Diff={diff:+.4f}, Winner={winner})"
                    )
        else:
            lines.append("Insufficient data for model comparison.")
        
        lines.append("")
        lines.append("-" * 70)
        lines.append("INTERPRETATION")
        lines.append("-" * 70)
        
        # High-level interpretation
        if not summary_df.empty:
            best_mond = mond_data['pass_rate'].max() if not mond_data.empty else 0
            best_nfw = nfw_data['pass_rate'].max() if not nfw_data.empty else 0
            
            lines.append(f"Highest MOND pass rate: {best_mond:.4f}")
            lines.append(f"Highest NFW pass rate: {best_nfw:.4f}")
            
            if best_mond > best_nfw + 0.05:
                lines.append("Conclusion: MOND shows significantly better fit quality across thresholds.")
            elif best_nfw > best_mond + 0.05:
                lines.append("Conclusion: NFW shows significantly better fit quality across thresholds.")
            else:
                lines.append("Conclusion: Both models show comparable fit quality; no clear preference.")
        else:
            lines.append("No conclusions can be drawn from empty data.")
    
    lines.append("")
    lines.append("=" * 70)
    lines.append("END OF REPORT")
    lines.append("=" * 70)
    
    return "\n".join(lines)

def write_summary(summary_text: str, output_path: Path) -> None:
    """Write the summary text to the output file."""
    ensure_directory(output_path)
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(summary_text)
    logging.info(f"Sensitivity summary written to: {output_path}")

def main():
    """Main entry point for generating sensitivity summary."""
    # Setup logging
    logger = get_logger(__name__)
    logger.info("Starting sensitivity summary generation (T035)")
    
    try:
        # Load data
        logger.info(f"Loading sensitivity data from: {INPUT_PATH}")
        df = load_sensitivity_data(INPUT_PATH)
        logger.info(f"Loaded {len(df)} records")
        
        # Compute summary statistics
        logger.info("Computing pass rates per threshold and model")
        summary_df = compute_summary_stats(df)
        
        # Generate text report
        logger.info("Generating human-readable summary report")
        summary_text = generate_summary_text(summary_df, INPUT_PATH)
        
        # Write output
        logger.info(f"Writing summary to: {OUTPUT_PATH}")
        write_summary(summary_text, OUTPUT_PATH)
        
        logger.info("Sensitivity summary generation completed successfully")
        
    except FileNotFoundError as e:
        logger.error(f"Data file not found: {e}")
        raise
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during summary generation: {e}")
        raise

if __name__ == "__main__":
    main()