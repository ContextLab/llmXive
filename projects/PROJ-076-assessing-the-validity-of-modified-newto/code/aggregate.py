"""
Aggregate parsed and filtered galaxy data into a single CSV and update metadata.

This script:
1. Reads the preprocessed/filtered galaxy data (assumed to be generated by preprocess.py).
2. Writes a consolidated `data/processed/filtered_galaxies.csv`.
3. Updates `data/metadata.yaml` with the download timestamp and version.
"""
import os
import logging
import pandas as pd
import yaml
from pathlib import Path
from datetime import datetime

# Import utilities from the project
from utils import get_logger, ensure_directory, get_timestamp
from config import load_config, create_default_metadata

logger = get_logger(__name__)

def load_filtered_data(processed_dir: Path) -> pd.DataFrame:
    """
    Load the filtered galaxy data.
    Assumes preprocess.py has written intermediate files or a combined file.
    For this pipeline, we assume `preprocess.py` produces a combined file
    or we aggregate individual galaxy files.

    Strategy: Look for `data/processed/intermediate_*.csv` or a single
    `data/processed/filtered_galaxies.csv` if it already exists (idempotent).
    If not, we assume the pipeline expects us to read the source raw files
    again? No, the task implies we are the final step of US1.
    
    Correction: T013/T014 (preprocess) should have produced the data.
    Since T013/T014 are marked complete, we assume they wrote to a temporary
    location or we need to re-run the logic? 
    
    Actually, looking at the task flow:
    T013: Parse rotation curves.
    T014: Apply filters.
    T015: Create final CSV and metadata.
    
    To ensure T015 works without re-parsing everything (or relying on side effects),
    we will re-invoke the parsing/filtering logic if the final file doesn't exist,
    OR we assume the previous steps wrote to a specific intermediate location.
    
    Given the constraint "Extend, don't re-author", and that T013/T014 are done,
    we assume `preprocess.main()` (or similar) was run and produced data.
    However, to be safe and self-contained for this specific task artifact:
    We will import the functions from `preprocess` and run the pipeline if the output is missing.
    """
    final_path = processed_dir / "filtered_galaxies.csv"
    
    if final_path.exists():
        logger.info(f"Loading existing filtered data from {final_path}")
        return pd.read_csv(final_path)

    # If not found, we must run the preprocessing logic to generate it.
    # This ensures T015 is self-sufficient for the "Create" requirement.
    logger.info("Final filtered data not found. Running preprocessing pipeline...")
    
    # Import here to avoid circular dependencies if any, though unlikely
    from preprocess import parse_galaxy_directory, apply_quality_filters, extract_rotation_curves
    from download import download_sparc_data
    
    config = load_config()
    raw_data_path = Path(config['paths']['raw_data'])
    
    if not raw_data_path.exists():
        logger.error(f"Raw data not found at {raw_data_path}. Cannot aggregate.")
        raise FileNotFoundError(f"Raw data missing: {raw_data_path}")
    
    # Re-run the pipeline logic
    # 1. Parse
    galaxies = parse_galaxy_directory(raw_data_path.parent) # Assuming structure
    
    # 2. Extract curves
    curves_data = extract_rotation_curves(galaxies)
    
    # 3. Filter
    filtered_data = apply_quality_filters(curves_data)
    
    if filtered_data.empty:
        logger.warning("No galaxies passed the quality filters.")
        # Create empty DF with correct columns to avoid schema errors
        filtered_data = pd.DataFrame(columns=['galaxy_id', 'r', 'v', 'sigma_v', 'inclination', 'inclination_uncertainty'])
    
    return filtered_data

def update_metadata(config: dict, output_path: Path) -> None:
    """
    Update data/metadata.yaml with the current timestamp and version.
    """
    logger.info(f"Updating metadata at {output_path}")
    
    # Load current config (which is the metadata)
    # We need to update the 'data' section
    if 'data' not in config:
        config['data'] = {}
    
    config['data']['download_timestamp'] = datetime.utcnow().isoformat() + "Z"
    # Ensure version is set if missing
    if 'version' not in config['data']:
        config['data']['version'] = "1.0"
    
    # Write back
    with open(output_path, 'w') as f:
        yaml.dump(config, f, default_flow_style=False, sort_keys=False)
    
    logger.info("Metadata updated successfully.")

def main():
    logger.info("Starting aggregation task (T015)...")
    
    config = load_config()
    processed_dir = Path(config['paths']['processed_data']).parent
    metadata_path = Path("data/metadata.yaml")
    
    ensure_directory(processed_dir)
    
    # 1. Load/Generate Filtered Data
    try:
        df = load_filtered_data(processed_dir)
    except Exception as e:
        logger.critical(f"Failed to load or generate filtered data: {e}")
        raise
    
    # 2. Write Final CSV
    final_csv_path = Path(config['paths']['processed_data'])
    logger.info(f"Writing {len(df)} galaxies to {final_csv_path}")
    df.to_csv(final_csv_path, index=False)
    
    # 3. Update Metadata
    update_metadata(config, metadata_path)
    
    logger.info("Task T015 completed successfully.")

if __name__ == "__main__":
    main()
