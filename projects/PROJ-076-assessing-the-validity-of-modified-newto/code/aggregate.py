def load_filtered_data(input_path: str) -> pd.DataFrame:
    """
    Load the preprocessed and filtered galaxy data from the CSV file generated by T014.
    
    Args:
        input_path: Path to the filtered galaxies CSV file.
        
    Returns:
        pandas DataFrame containing the filtered galaxy data.
        
    Raises:
        FileNotFoundError: If the input file does not exist.
        ValueError: If the file is empty or contains no valid data rows.
    """
    logger.info(f"Loading filtered data from {input_path}")
    
    if not os.path.exists(input_path):
        logger.error(f"Upstream artifact missing: {input_path}")
        raise FileNotFoundError(f"Required upstream artifact not found: {input_path}")
    
    try:
        df = pd.read_csv(input_path)
    except Exception as e:
        logger.error(f"Failed to read CSV file {input_path}: {e}")
        raise
    
    if df.empty:
        logger.error(f"Upstream artifact is empty: {input_path}")
        raise ValueError(f"Loaded data is empty: {input_path}")
    
    logger.info(f"Successfully loaded {len(df)} galaxies from {input_path}")
    return df

def update_metadata(metadata_path: str, output_path: str, timestamp: str, version: str = "1.1"):
    """
    Update the project metadata.yaml file with the download timestamp and version.
    
    Args:
        metadata_path: Path to the existing metadata.yaml file.
        output_path: Path where the updated metadata.yaml will be written.
        timestamp: ISO format timestamp string to record.
        version: Version string for the processed data.
    """
    logger.info(f"Updating metadata at {metadata_path}")
    
    if not os.path.exists(metadata_path):
        logger.error(f"Metadata file not found: {metadata_path}")
        raise FileNotFoundError(f"Metadata file not found: {metadata_path}")
    
    try:
        with open(metadata_path, 'r') as f:
            metadata = yaml.safe_load(f)
    except Exception as e:
        logger.error(f"Failed to parse YAML file {metadata_path}: {e}")
        raise
    
    # Update the data section
    if 'data' not in metadata:
        metadata['data'] = {}
    
    metadata['data']['download_timestamp'] = timestamp
    metadata['data']['version'] = version
    
    # Ensure output directory exists
    ensure_directory(output_path)
    
    try:
        with open(output_path, 'w') as f:
            yaml.dump(metadata, f, default_flow_style=False, sort_keys=False)
        logger.info(f"Successfully updated metadata with timestamp {timestamp} and version {version}")
    except Exception as e:
        logger.error(f"Failed to write updated metadata to {output_path}: {e}")
        raise

