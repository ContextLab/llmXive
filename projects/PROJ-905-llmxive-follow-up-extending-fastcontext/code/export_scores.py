import csv
import sys
from pathlib import Path
from typing import List, Dict, Any, Optional

from config import get_path, ensure_directories
from stratification import load_scores_from_csv


def export_scores_to_csv(
    scores: List[Dict[str, Any]],
    output_filename: str = "regularity_scores.csv",
) -> Path:
    """
    Write repository regularity scores to a CSV file in the processed data directory.

    Args:
        scores: List of dicts containing at least 'repo_id' and 'regularity_score'.
        output_filename: Name of the output CSV file (default: regularity_scores.csv).

    Returns:
        Path to the written CSV file.

    Raises:
        FileNotFoundError: If the input scores list is empty or missing required fields.
        IOError: If the file cannot be written.
    """
    if not scores:
        raise FileNotFoundError("No scores provided to export.")

    # Ensure all required fields are present
    required_fields = {"repo_id", "regularity_score"}
    for i, score_entry in enumerate(scores):
        if not required_fields.issubset(score_entry.keys()):
            missing = required_fields - set(score_entry.keys())
            raise ValueError(
                f"Score entry {i} missing required fields: {missing}. "
                f"Found keys: {list(score_entry.keys())}"
            )

    # Ensure output directory exists
    output_path = get_path("data/processed", output_filename)
    ensure_directories(output_path)

    # Write to CSV
    try:
        with open(output_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=["repo_id", "regularity_score"])
            writer.writeheader()
            for entry in scores:
                writer.writerow({
                    "repo_id": entry["repo_id"],
                    "regularity_score": entry["regularity_score"],
                })
    except IOError as e:
        raise IOError(f"Failed to write scores to {output_path}: {e}") from e

    return output_path


def main() -> int:
    """
    Entry point for exporting regularity scores.

    Reads scores from the internal stratification format (or a temporary in-memory
    structure if generated by static_analysis) and writes them to the processed CSV.

    Returns:
        0 on success, 1 on failure.
    """
    try:
        # Load scores from the intermediate CSV generated by static_analysis/stratification
        # The stratification module saves scores to data/processed/scores_intermediate.csv
        # We load them back to export in the final format.
        scores_path = get_path("data/processed", "scores_intermediate.csv")
        if not scores_path.exists():
            # Fallback: if the intermediate file doesn't exist, try to load from the
            # standard location where static_analysis might have written directly.
            # However, per task T013, stratification.py handles the split.
            # We assume T013 produces a file we can read.
            print(f"Error: Intermediate scores file not found at {scores_path}")
            print("Please ensure T013 (stratification) has run successfully.")
            return 1

        scores = load_scores_from_csv(scores_path)

        if not scores:
            print("Warning: No scores found in the intermediate file.")
            return 0

        output_path = export_scores_to_csv(scores)
        print(f"Successfully exported {len(scores)} scores to {output_path}")
        return 0

    except Exception as e:
        print(f"Error during export: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())