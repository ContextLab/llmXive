import os
import sys
import json
import logging
import random
from typing import List, Dict, Any, Optional, Tuple
from collections import defaultdict

from config import get_config
from logging_config import get_comparison_log_path

logger = logging.getLogger(__name__)

def load_comparison_logs(log_path: Optional[str] = None) -> List[Dict[str, Any]]:
    """
    Load the full comparison log (JSONL format).
    Falls back to the default path if none provided.
    """
    if log_path is None:
        log_path = get_comparison_log_path()
    
    if not os.path.exists(log_path):
        raise FileNotFoundError(f"Comparison log not found at {log_path}. "
                                "Ensure T014-Baseline has been executed.")
    
    logs = []
    with open(log_path, 'r', encoding='utf-8') as f:
        for line_num, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                logs.append(json.loads(line))
            except json.JSONDecodeError as e:
                logger.warning(f"Skipping invalid JSON at line {line_num}: {e}")
    return logs

def filter_wasted_calls(logs: List[Dict[str, Any]], threshold: float = 0.95) -> List[Dict[str, Any]]:
    """
    Filter logs to keep only pairs where cosine_sim > threshold.
    These are the 'flagged' or 'wasted' pairs.
    """
    return [log for log in logs if log.get('cosine_sim', 0.0) > threshold]

def load_sample_config(config_path: str = "data/results/sample_config.json") -> Dict[str, Any]:
    """
    Load the sample configuration generated by T013b.
    """
    if not os.path.exists(config_path):
        raise FileNotFoundError(f"Sample config not found at {config_path}. "
                                "Ensure T013b has been executed.")
    
    with open(config_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def select_simple_random_sample(
    items: List[Dict[str, Any]], 
    sample_size: int, 
    seed: int
) -> Tuple[List[Dict[str, Any]], List[int]]:
    """
    Select a simple random sample from the list of items.
    Returns the sampled items and their original indices.
    """
    if not items:
        return [], []
    
    if sample_size >= len(items):
        # If sample size is larger than population, return all
        return items, list(range(len(items)))
    
    # Use the provided seed for reproducibility
    rng = random.Random(seed)
    indices = rng.sample(range(len(items)), sample_size)
    
    sampled_items = [items[i] for i in indices]
    return sampled_items, indices

def run_sampling_pipeline(
    log_path: Optional[str] = None,
    config_path: str = "data/results/sample_config.json",
    output_path: str = "data/results/consensus_sample.json"
) -> Dict[str, Any]:
    """
    Main pipeline for T013c:
    1. Load comparison logs.
    2. Filter for flagged pairs (cosine_sim > 0.95).
    3. Load sample config to get sample_size.
    4. Select a simple random sample using RANDOM_SEED from config.
    5. Write the sample indices to consensus_sample.json.
    
    Returns a status dict with execution details.
    """
    logger.info("Starting T013c sampling pipeline...")
    
    # 1. Load logs
    try:
        logs = load_comparison_logs(log_path)
        logger.info(f"Loaded {len(logs)} comparison records.")
    except FileNotFoundError as e:
        logger.error(f"Failed to load logs: {e}")
        raise
    
    # 2. Filter flagged pairs
    flagged_pairs = filter_wasted_calls(logs, threshold=0.95)
    logger.info(f"Found {len(flagged_pairs)} flagged pairs (cosine_sim > 0.95).")
    
    if not flagged_pairs:
        logger.warning("No flagged pairs found. Writing empty sample.")
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump([], f, indent=2)
        return {
            "status": "completed",
            "total_flagged": 0,
            "sample_size": 0,
            "output_path": output_path,
            "message": "No flagged pairs found."
        }
    
    # 3. Load sample config
    try:
        config = load_sample_config(config_path)
        sample_size = config.get("sample_size", 0)
        skip_validation = config.get("skip_validation", False)
    except FileNotFoundError as e:
        logger.error(f"Failed to load sample config: {e}")
        raise
    
    if skip_validation or sample_size == 0:
        logger.info("Validation skipped per sample config.")
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump([], f, indent=2)
        return {
            "status": "skipped",
            "reason": "skip_validation flag or sample_size=0",
            "output_path": output_path
        }
    
    # 4. Select simple random sample
    # Retrieve RANDOM_SEED from global config
    global_config = get_config()
    seed = global_config.get("RANDOM_SEED", 42)
    
    sampled_items, indices = select_simple_random_sample(
        flagged_pairs, 
        sample_size, 
        seed
    )
    
    logger.info(f"Selected {len(sampled_items)} items from {len(flagged_pairs)} candidates (seed={seed}).")
    
    # 5. Write output
    # The schema requires a list of indices. 
    # We store the indices relative to the FLAGGED list for reproducibility,
    # but also include the original pair_ids for clarity in downstream steps.
    output_data = {
        "sample_indices": indices,
        "sample_size": len(sampled_items),
        "total_flagged_pool": len(flagged_pairs),
        "seed_used": seed,
        "pair_ids": [item.get("pair_id") for item in sampled_items]
    }
    
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(output_data, f, indent=2)
    
    logger.info(f"Sample written to {output_path}")
    
    return {
        "status": "completed",
        "sample_size": len(sampled_items),
        "total_flagged": len(flagged_pairs),
        "indices": indices,
        "output_path": output_path
    }

def main():
    """Entry point for script execution."""
    logging.basicConfig(
        level=logging.INFO,
        format='%(asctime)s - %(levelname)s - %(message)s'
    )
    
    try:
        result = run_sampling_pipeline()
        print(json.dumps(result, indent=2))
        sys.exit(0)
    except Exception as e:
        logger.error(f"Pipeline failed: {e}")
        print(json.dumps({"status": "failed", "error": str(e)}), file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()
