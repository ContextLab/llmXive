"""
T013a: Post-Execution Budget Aggregation

Reads the comparison log generated by T014 (run_baseline_active_ranker) and
counts the actual number of LLM calls executed. Writes the result to
data/results/budget_config.json.

Schema:
{
  "actual_budget": int,       # Count of lines in comparison_log.json
  "configured_budget": int,   # Read from config (default or explicit)
  "budget_type": "LLM_calls"
}
"""
import os
import sys
import json
import logging
from pathlib import Path

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from config import get_config
from logging_config import get_comparison_log_path

logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

def main():
    """Execute T013a: Aggregate actual budget from comparison log."""
    logger.info("Starting T013a: Post-Execution Budget Aggregation")

    # 1. Load configuration for the configured budget
    try:
        config = get_config()
        # The config might have a budget setting if passed via CLI, 
        # otherwise we default to a high number or read from a specific key if defined.
        # Based on task description, we need the "configured_budget".
        # We assume the config object has a budget attribute or we default to a safe high number 
        # if the pipeline didn't enforce a hard limit during the run.
        # However, T013a specifically says: "If the pipeline terminated early, this task records the ACTUAL count... not the configured limit."
        # We need to know what the configured limit WAS.
        
        # Attempt to read from config. If not present, we might need to infer or use a default.
        # Looking at typical usage, budget is often passed to run_pipeline. 
        # We will try to access a 'budget' or 'max_calls' attribute.
        configured_budget = getattr(config, 'budget', None)
        
        if configured_budget is None:
            # If not explicitly set in config, we assume a high default or try to read from environment
            # For the purpose of this task, we will log a warning and use a placeholder 
            # if the specific budget wasn't captured in config, but the primary goal is actual_budget.
            # However, the task requires the field. We will assume a default of 1000 if not found 
            # and log that it's a fallback, OR we check if the config has a specific key.
            # Let's assume the config has a 'budget' key from the CLI parsing in run_pipeline.
            # If run_pipeline didn't set it, we might need to look at the command line args 
            # or a state file. For now, we default to a large number if not found.
            configured_budget = 10000 
            logger.warning(f"Configured budget not found in config, using default: {configured_budget}")
        else:
            logger.info(f"Configured budget from config: {configured_budget}")
            
    except Exception as e:
        logger.error(f"Failed to load configuration: {e}")
        # Fallback
        configured_budget = 10000

    # 2. Read the comparison log to get actual count
    log_path = get_comparison_log_path()
    
    if not os.path.exists(log_path):
        logger.error(f"Comparison log not found at {log_path}. "
                     f"T014 (Baseline Ranker) must run before T013a.")
        # Create an empty result to indicate failure state clearly
        result = {
            "actual_budget": 0,
            "configured_budget": configured_budget,
            "budget_type": "LLM_calls",
            "status": "missing_log_file"
        }
        output_dir = Path("data/results")
        output_dir.mkdir(parents=True, exist_ok=True)
        output_path = output_dir / "budget_config.json"
        with open(output_path, 'w') as f:
            json.dump(result, f, indent=2)
        sys.exit(1)

    actual_count = 0
    try:
        with open(log_path, 'r') as f:
            for line in f:
                line = line.strip()
                if line:
                    # Validate it's a JSON line to be safe
                    try:
                        json.loads(line)
                        actual_count += 1
                    except json.JSONDecodeError:
                        logger.warning(f"Skipping malformed JSON line in log: {line[:50]}...")
                        continue
    except Exception as e:
        logger.error(f"Failed to read comparison log: {e}")
        sys.exit(1)

    logger.info(f"Counted {actual_count} comparison events in {log_path}")

    # 3. Construct result
    result = {
        "actual_budget": actual_count,
        "configured_budget": configured_budget,
        "budget_type": "LLM_calls"
    }

    # 4. Write output
    output_dir = Path("data/results")
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "budget_config.json"

    with open(output_path, 'w') as f:
        json.dump(result, f, indent=2)

    logger.info(f"T013a complete. Wrote budget artifact to {output_path}")
    return 0

if __name__ == "__main__":
    sys.exit(main())