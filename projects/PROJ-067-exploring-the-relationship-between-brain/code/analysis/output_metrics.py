logger = logging.getLogger(__name__)

def load_subject_metrics_from_cache(subject_id: str, metrics_dir: Path) -> Optional[Dict[str, Any]]:
    """
    Load pre-calculated metrics for a subject from cache files.
    In a real pipeline, these would be generated by T029/T030 (flexibility/stability scripts).
    """
    flex_file = metrics_dir / f"{subject_id}_flexibility.json"
    stab_file = metrics_dir / f"{subject_id}_stability.json"
    
    if not flex_file.exists() or not stab_file.exists():
        logger.warning(f"Cache files missing for {subject_id}. Skipping.")
        return None

    try:
        with open(flex_file, 'r') as f:
            flex_data = json.load(f)
        with open(stab_file, 'r') as f:
            stab_data = json.load(f)
        
        # Merge data
        metrics = {
            "subject_id": subject_id,
            "flexibility_DMN": flex_data.get("DMN", {}).get("flexibility"),
            "flexibility_Salience": flex_data.get("Salience", {}).get("flexibility"),
            "flexibility_Hippocampal": flex_data.get("Hippocampal-Memory", {}).get("flexibility"),
            "stability_DMN": stab_data.get("DMN", {}).get("stability"),
            "stability_Salience": stab_data.get("Salience", {}).get("stability"),
            "stability_Hippocampal": stab_data.get("Hippocampal-Memory", {}).get("stability"),
        }
        
        # Validate not None
        if any(v is None for k, v in metrics.items() if k != "subject_id"):
            logger.warning(f"Incomplete metrics for {subject_id}. Skipping.")
            return None

        return metrics
    except (json.JSONDecodeError, KeyError) as e:
        logger.error(f"Error loading cache for {subject_id}: {e}")
        return None

def aggregate_metrics(metrics_dir: Path, output_path: Path, valid_subjects: List[str]) -> int:
    """
    Aggregate metrics from individual subject caches into a single CSV.
    """
    check_memory_limit() # Ensure we are under 7GB before processing
    
    all_metrics = []
    skipped = 0
    
    for subj in valid_subjects:
        metrics = load_subject_metrics_from_cache(subj, metrics_dir)
        if metrics:
            all_metrics.append(metrics)
        else:
            skipped += 1
    
    if not all_metrics:
        raise RuntimeError("No valid metrics found to aggregate. Check preprocessing steps.")
    
    # Sort by subject_id to ensure deterministic output
    all_metrics.sort(key=lambda x: x["subject_id"])
    
    # Write CSV
    fieldnames = [
        "subject_id", 
        "flexibility_DMN", "flexibility_Salience", "flexibility_Hippocampal",
        "stability_DMN", "stability_Salience", "stability_Hippocampal"
    ]
    
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', newline='') as csvfile:
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(all_metrics)
    
    logger.info(f"Wrote {len(all_metrics)} subjects to {output_path}. Skipped {skipped}.")
    return len(all_metrics)

def validate_schema(input_path: Path) -> bool:
    """
    Validate the generated CSV against the subject_metrics schema.
    """
    try:
        # Import validator dynamically or use a simple check
        # Assuming schema validator exists as per T008/T022
        from contracts.schema_validators import validate_subject_metrics_schema
        if validate_subject_metrics_schema(str(input_path)):
            logger.info("Schema validation passed.")
            return True
        else:
            logger.error("Schema validation failed.")
            return False
    except ImportError:
        logger.warning("Schema validator not found, skipping validation.")
        return True

def main():
    """
    Main entry point for T031: Output subject-level metrics to CSV.
    """
    logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
    
    config = get_config_summary()
    metrics_dir = Path("data/metrics") # Where individual JSONs are stored
    output_file = Path("data/metrics/subject_metrics.csv")
    
    # Load valid subjects list (from T015)
    valid_subjects_path = Path("data/raw/valid_subjects.json")
    if not valid_subjects_path.exists():
        raise FileNotFoundError(f"Required input file missing: {valid_subjects_path}")
    
    with open(valid_subjects_path, 'r') as f:
        valid_subjects = json.load(f)
    
    logger.info(f"Starting aggregation for {len(valid_subjects)} subjects.")
    
    count = aggregate_metrics(metrics_dir, output_file, valid_subjects)
    
    if not validate_schema(output_file):
        raise RuntimeError("Generated metrics file failed schema validation.")
    
    logger.info("T031 completed successfully.")
    return 0

if __name__ == "__main__":
    sys.exit(main())
