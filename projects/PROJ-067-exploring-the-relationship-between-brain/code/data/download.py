    """
    Download NIfTI files for a single subject using the OpenNeuro CLI.
    
    The OpenNeuro CLI (openneuro) is the recommended way to download datasets.
    Command: openneuro download --dataset ds000228 --version 1.0.0 --subject sub-01 --output output_dir
    
    Args:
        subject_id: Subject ID (e.g., 'sub-01')
        output_dir: Directory to save the downloaded files
        version: Dataset version
        
    Returns:
        True if download successful, False otherwise
    """
    output_dir = Path(output_dir)
