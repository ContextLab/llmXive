def download_and_extract_subjects(subject_ids: List[str], output_base: Path) -> Dict[str, bool]:
    """
    Iterate over subject IDs and download their NIfTI files.
    
    Args:
        subject_ids: List of subject IDs
        output_base: Base directory for downloads (e.g., data/raw)
        
    Returns:
        Dictionary mapping subject_id to success status
    """
    results = {}
    
    for i, subject_id in enumerate(subject_ids):
        logger.info(f"Processing subject {i+1}/{len(subject_ids)}: {subject_id}")
        
        subject_output_dir = output_base / subject_id
        
        success = download_subject_nifti(subject_id, subject_output_dir)
        results[subject_id] = success
        
        if success:
            # Verify files exist
            nifti_files = list(subject_output_dir.glob("*.nii.gz"))
            if not nifti_files:
                logger.warning(f"No .nii.gz files found for {subject_id} after download.")
                results[subject_id] = False
            else:
                logger.info(f"Found {len(nifti_files)} NIfTI files for {subject_id}")
        else:
            logger.error(f"Skipping {subject_id} due to download failure.")
        
        # Rate limiting to avoid overwhelming the server
        if i < len(subject_ids) - 1:
            time.sleep(2)
    
    return results

def save_download_log(results: Dict[str, bool], log_file: Path) -> None:
    """
    Save the download results to a JSON log file.
    
    Args:
        results: Dictionary of subject_id -> success
        log_file: Path to the log file
    """
    log_file.parent.mkdir(parents=True, exist_ok=True)
    with open(log_file, 'w') as f:
        json.dump(results, f, indent=2)
    logger.info(f"Download log saved to {log_file}")

def main() -> int:
    """
    Main entry point for the download script.
    
    1. Load valid subjects from data/raw/valid_subjects.json
    2. Download NIfTI files for each subject to data/raw/
    3. Save download log to data/raw/download_log.json
    
    Returns:
        0 on success, 1 on failure
    """
    logger.info("Starting download pipeline for ds000228")
    
    # Paths
    subjects_file = Path(project_root) / "data" / "raw" / "valid_subjects.json"
    output_base = Path(project_root) / "data" / "raw"
    log_file = Path(project_root) / "data" / "raw" / "download_log.json"
    
    # Check prerequisites
    if not subjects_file.exists():
        logger.error(f"Prerequisite file missing: {subjects_file}")
        logger.error("Run T015 (filter_subjects.py) first to generate valid_subjects.json")
        return 1
    
    try:
        subject_ids = load_valid_subjects(subjects_file)
    except (FileNotFoundError, ValueError) as e:
        logger.error(f"Failed to load subjects: {e}")
        return 1
    
    if not subject_ids:
        logger.error("No subjects to download.")
        return 1
    
    # Perform downloads
    results = download_and_extract_subjects(subject_ids, output_base)
    
    # Save log
    save_download_log(results, log_file)
    
    # Summary
    success_count = sum(1 for v in results.values() if v)
    total_count = len(results)
    logger.info(f"Download complete: {success_count}/{total_count} subjects successful")
    
    if success_count == 0:
        logger.error("No subjects were successfully downloaded. Exiting.")
        return 1
        
    return 0

if __name__ == "__main__":
    sys.exit(main())