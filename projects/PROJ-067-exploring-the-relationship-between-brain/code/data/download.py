def load_valid_subjects(subjects_file: Path) -> List[str]:
    """
    Load list of valid subject IDs from the JSON file generated by T015.
    
    Args:
        subjects_file: Path to data/raw/valid_subjects.json
        
    Returns:
        List of subject IDs (e.g., ['sub-01', 'sub-02', ...])
        
    Raises:
        FileNotFoundError: If the subjects file does not exist
        ValueError: If the file is empty or malformed
    """
    if not subjects_file.exists():
        raise FileNotFoundError(f"Valid subjects file not found: {subjects_file}")
    
    with open(subjects_file, 'r') as f:
        data = json.load(f)
    
    if not isinstance(data, list) or len(data) == 0:
        raise ValueError(f"Valid subjects file is empty or malformed: {subjects_file}")
    
    # Extract subject IDs (assuming data is a list of dicts with 'subject_id' or just strings)
    subject_ids = []
    for item in data:
        if isinstance(item, dict):
            if 'subject_id' in item:
                subject_ids.append(item['subject_id'])
            elif 'id' in item:
                subject_ids.append(item['id'])
            else:
                raise ValueError(f"Invalid subject entry format: {item}")
        elif isinstance(item, str):
            subject_ids.append(item)
        else:
            raise ValueError(f"Invalid subject entry type: {type(item)}")
    
    logger.info(f"Loaded {len(subject_ids)} valid subjects from {subjects_file}")
    return subject_ids

