        # This is a heuristic; OpenNeuro might require the full dataset download then extraction
        # For robustness, we assume the CLI is required for partial downloads.
        # If CLI is missing, we fail loudly as per requirements (no synthetic, no fake).
        
        logger.error(f"Cannot download {subject_id}: OpenNeuro CLI is required for partial subject downloads.")
        logger.error("Please install openneuro-cli: npm install -g @openneuro/cli")
