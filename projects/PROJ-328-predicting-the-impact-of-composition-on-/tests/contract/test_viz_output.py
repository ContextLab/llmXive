    def test_fr007_warning_injected(self, output_dir: Path):
        """
        Contract: FR-007 associational warning must be present in all outputs.

        This test verifies that the warning injection mechanism (T031) has
        been applied to visualization outputs.
        """
        # Check metadata files for warning
        metadata_files = list(output_dir.glob("*_metadata.json"))
        
        if len(metadata_files) == 0:
            pytest.skip("No metadata files found to check for FR-007 warning")
        
        warning_found = False
        for meta_file in metadata_files:
            with open(meta_file, 'r') as f:
                metadata = json.load(f)
            
            if "warning" in metadata:
                warning_text = metadata["warning"]
                assert isinstance(warning_text, str), "Warning must be a string"
                assert len(warning_text) > 0, "Warning cannot be empty"
                assert "associational" in warning_text.lower() or \
                       "causation" in warning_text.lower(), \
                       f"Warning should mention associational/causation: {warning_text}"
                warning_found = True
                break  # Found at least one with warning
        
        if not warning_found:
            pytest.fail("FR-007 associational warning not found in any visualization metadata")

