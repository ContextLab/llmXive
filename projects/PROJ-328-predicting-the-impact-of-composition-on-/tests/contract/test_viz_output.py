    def test_scatter_plot_metadata_exists(self, output_dir: Path):
        """
        Contract: Scatter plot metadata file must exist with required schema.

        Expected file: data/outputs/scatter_plot_metadata.json
        Required fields:
          - plot_type: "scatter"
          - x_label: string
          - y_label: string
          - units: object with x and y units
          - data_points: integer >= 100
          - ci_level: float (e.g., 0.95)
          - generated_at: ISO timestamp
          - warning: optional string (FR-007 associational warning)
        """
        metadata_path = output_dir / "scatter_plot_metadata.json"
        
        # Note: This test passes if the file doesn't exist yet (task not completed)
        # Once T034 is implemented, this will validate the schema
        if not metadata_path.exists():
            pytest.skip("Scatter plot metadata not yet generated (T034 pending)")
        
        with open(metadata_path, 'r') as f:
            metadata = json.load(f)
        
        # Validate required fields
        assert "plot_type" in metadata, "Missing required field: plot_type"
        assert metadata["plot_type"] == "scatter", f"Invalid plot_type: {metadata['plot_type']}"
        
        assert "x_label" in metadata, "Missing required field: x_label"
        assert isinstance(metadata["x_label"], str), "x_label must be a string"
        
        assert "y_label" in metadata, "Missing required field: y_label"
        assert isinstance(metadata["y_label"], str), "y_label must be a string"
        
        assert "units" in metadata, "Missing required field: units"
        assert isinstance(metadata["units"], dict), "units must be an object"
        assert "x" in metadata["units"], "Missing x units"
        assert "y" in metadata["units"], "Missing y units"
        
        assert "data_points" in metadata, "Missing required field: data_points"
        assert isinstance(metadata["data_points"], int), "data_points must be an integer"
        assert metadata["data_points"] >= 100, f"Insufficient data points: {metadata['data_points']}"
        
        assert "ci_level" in metadata, "Missing required field: ci_level"
        assert isinstance(metadata["ci_level"], (int, float)), "ci_level must be numeric"
        assert 0 < metadata["ci_level"] < 1, f"Invalid CI level: {metadata['ci_level']}"
        
        assert "generated_at" in metadata, "Missing required field: generated_at"
        
        # FR-007: Associational warning should be present
        if "warning" not in metadata:
            pytest.fail("Missing FR-007 associational warning in scatter plot metadata")

