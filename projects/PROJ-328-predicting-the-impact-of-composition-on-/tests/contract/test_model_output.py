def _validate_dict_against_schema(data: Dict[str, Any], schema: Dict[str, Any], context: str = "") -> List[str]:
    """
    Validates a dictionary against a schema definition.
    
    Args:
        data: The dictionary to validate.
        schema: The schema definition.
        context: Context string for error messages.
        
    Returns:
        List of error messages (empty if valid).
    """
    errors = []
    
    if not isinstance(data, dict):
        return [f"{context}: Expected dictionary, got {type(data).__name__}"]
    
    # Check required keys
    required_keys = schema.get("required_keys", [])
    for key in required_keys:
        if key not in data:
            errors.append(f"{context}: Missing required key '{key}'")
    
    # Check nested schemas if data exists
    if "fold_metrics_schema" in schema and "fold_metrics" in data:
        if not isinstance(data["fold_metrics"], list):
            errors.append(f"{context}/fold_metrics: Expected list, got {type(data['fold_metrics']).__name__}")
        else:
            for i, fold in enumerate(data["fold_metrics"]):
                fold_errors = _validate_dict_against_schema(
                    fold, 
                    schema["fold_metrics_schema"], 
                    f"{context}/fold_metrics[{i}]"
                )
                errors.extend(fold_errors)
    
    if "metrics_schema" in schema:
        for key in ["metrics_a", "metrics_b"]:
            if key in data:
                nested_errors = _validate_dict_against_schema(
                    data[key],
                    schema["metrics_schema"],
                    f"{context}/{key}"
                )
                errors.extend(nested_errors)
    
    if "comparison_schema" in schema and "comparison" in data:
        comp_errors = _validate_dict_against_schema(
            data["comparison"],
            schema["comparison_schema"],
            f"{context}/comparison"
        )
        errors.extend(comp_errors)
        
    if "results_schema" in schema and "results" in data:
        if not isinstance(data["results"], list):
            errors.append(f"{context}/results: Expected list, got {type(data['results']).__name__}")
        else:
            for i, res in enumerate(data["results"]):
                res_errors = _validate_dict_against_schema(
                    res,
                    schema["results_schema"],
                    f"{context}/results[{i}]"
                )
                errors.extend(res_errors)
    
    if "top_features_schema" in schema and "top_features" in data:
        if not isinstance(data["top_features"], list):
            errors.append(f"{context}/top_features: Expected list, got {type(data['top_features']).__name__}")
        else:
            for i, feat in enumerate(data["top_features"]):
                feat_errors = _validate_dict_against_schema(
                    feat,
                    schema["top_features_schema"],
                    f"{context}/top_features[{i}]"
                )
                errors.extend(feat_errors)
    
    return errors

def _load_json_file(file_path: Path) -> Dict[str, Any]:
    """Load and parse a JSON file."""
    if not file_path.exists():
        raise FileNotFoundError(f"File not found: {file_path}")
    
    with open(file_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def _load_yaml_file(file_path: Path) -> Dict[str, Any]:
    """Load and parse a YAML file."""
    if not file_path.exists():
        raise FileNotFoundError(f"File not found: {file_path}")
    
    with open(file_path, 'r', encoding='utf-8') as f:
        return yaml.safe_load(f)

