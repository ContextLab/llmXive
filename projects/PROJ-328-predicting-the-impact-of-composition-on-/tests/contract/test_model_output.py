def test_all_model_output_contracts():
    """
    Integration test that verifies all model output contracts are satisfied.
    This test is run by the CI pipeline to ensure data integrity.
    """
    logger.info("Running all model output contract tests...")
    
    test_classes = [
        TestCVResultsContract,
        TestBootstrapComparisonContract,
        TestSensitivityAnalysisContract,
        TestSHAPAnalysisContract,
        TestModelArtifactContract,
        TestVIFReportContract
    ]
    
    all_passed = True
    failed_tests = []
    
    for test_class in test_classes:
        instance = test_class()
        for method_name in dir(instance):
            if method_name.startswith("test_"):
                try:
                    method = getattr(instance, method_name)
                    # Skip if decorated with skipif and condition is met
                    if hasattr(method, "pytestmark"):
                        skip_condition = any(
                            hasattr(mark, "args") and mark.args[0] 
                            for mark in method.pytestmark 
                            if mark.name == "skipif"
                        )
                        if skip_condition:
                            continue
                    
                    method()
                    logger.info(f"  ✓ {test_class.__name__}.{method_name}")
                except Exception as e:
                    all_passed = False
                    failed_tests.append(f"{test_class.__name__}.{method_name}: {str(e)}")
                    logger.error(f"  ✗ {test_class.__name__}.{method_name}: {str(e)}")
    
    if all_passed:
        logger.info("All contract tests passed!")
    else:
        raise AssertionError(
            f"{len(failed_tests)} contract tests failed:\n" + 
            "\n".join(failed_tests)
        )