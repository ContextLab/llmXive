def load_top_features_from_shap(shap_summary_path: Optional[Path] = None) -> List[str]:
    """
    Loads the top 3 feature names from the SHAP analysis summary.

    The SHAP summary is expected to be a JSON file containing a list of
    top features, typically generated by `code/evaluation/shap_analysis.py`.

    Args:
        shap_summary_path: Path to the SHAP summary JSON file.
                           Defaults to models/shap_summary.json.

    Returns:
        List of top 3 feature names (strings).

    Raises:
        FileNotFoundError: If the SHAP summary file is not found.
        ValueError: If fewer than 3 features are found in the summary.
    """
    if shap_summary_path is None:
        shap_summary_path = get_models_dir() / "shap_summary.json"

    if not shap_summary_path.exists():
        raise FileNotFoundError(f"SHAP summary file not found at {shap_summary_path}")

    import json
    with open(shap_summary_path, 'r') as f:
        shap_data = json.load(f)

    # Expected structure: {"top_features": ["feat1", "feat2", "feat3", ...], ...}
    # or similar structure depending on shap_analysis.py output.
    # We assume the key is 'top_features' or 'feature_importance' list.
    top_features = shap_data.get("top_features", [])

    if not top_features:
        # Fallback: try to find 'feature_importance' list if structure differs
        if "feature_importance" in shap_data:
            top_features = [item["feature"] for item in shap_data["feature_importance"]]

    if len(top_features) < 3:
        raise ValueError(f"Expected at least 3 features in SHAP summary, found {len(top_features)}")

    logger.info(f"Loaded top 3 features from SHAP: {top_features[:3]}")
    return top_features[:3]


def load_model_and_data(
    model_path: Optional[Path] = None,
    data_path: Optional[Path] = None
) -> Tuple[Any, pd.DataFrame]:
    """
    Loads the trained XGBoost model and the validated dataset.

    Args:
        model_path: Path to the saved model pickle file.
                    Defaults to models/xgboost_model.pkl.
        data_path: Path to the validated CSV dataset.
                   Defaults to data/processed/solder_hardness_validated.csv.

    Returns:
        Tuple of (trained_model, feature_dataframe).
    """
    if model_path is None:
        model_path = get_models_dir() / "xgboost_model.pkl"

    if data_path is None:
        data_path = get_data_processed_dir() / "solder_hardness_validated.csv"

    if not model_path.exists():
        raise FileNotFoundError(f"Model file not found at {model_path}")

    if not data_path.exists():
        raise FileNotFoundError(f"Validated data file not found at {data_path}")

    # Load model
    with open(model_path, 'rb') as f:
        model = pickle.load(f)

    # Load data
    df = pd.read_csv(data_path)

    # Identify feature columns (exclude target and non-feature columns)
    # Assuming 'Vickers_Hardness' is the target column based on standard naming
    target_col = 'Vickers_Hardness'
    if target_col in df.columns:
        feature_cols = [c for c in df.columns if c != target_col]
        X = df[feature_cols]
    else:
        # Fallback: assume first numeric column is target if named differently
        # or raise error if structure is unknown
        raise ValueError(f"Target column '{target_col}' not found in dataset. Columns: {df.columns.tolist()}")

    logger.info(f"Loaded model from {model_path} and data from {data_path}")
    logger.info(f"Dataset shape: {X.shape}, Features: {X.columns.tolist()}")

    return model, X


def generate_partial_dependence_plots(
    model: Any,
    X: pd.DataFrame,
    features: List[str],
    output_dir: Optional[Path] = None
) -> List[Path]:
    """
    Generates Partial Dependence Plots for the specified features.

    Args:
        model: The trained sklearn/xgboost compatible model.
        X: The feature DataFrame.
        features: List of feature names to plot (top 3).
        output_dir: Directory to save the plots.
                    Defaults to data/outputs/.

    Returns:
        List of paths to the generated plot files.
    """
    if output_dir is None:
        output_dir = get_data_outputs_dir()

    output_dir.mkdir(parents=True, exist_ok=True)

    # Filter features to those present in X
    valid_features = [f for f in features if f in X.columns]
    if len(valid_features) != len(features):
        missing = set(features) - set(valid_features)
        logger.warning(f"Features not found in data and skipped: {missing}")
    
    if len(valid_features) == 0:
        raise ValueError("No valid features found for plotting.")

    plot_paths = []
    n_features = len(valid_features)

    # Create a figure with subplots
    fig, axes = plt.subplots(1, n_features, figsize=(5 * n_features, 5), dpi=150)
    if n_features == 1:
        axes = [axes] # Ensure axes is iterable

    # Generate PDP for each feature
    for i, feature in enumerate(valid_features):
        ax = axes[i]
        
        # Create PDP display
        # Note: PartialDependenceDisplay.from_estimator is the modern API
        try:
            disp = PartialDependenceDisplay.from_estimator(
                model,
                X,
                features=[feature],
                ax=ax,
                kind='average' # Show average partial dependence
            )
            ax.set_title(f"Partial Dependence: {feature}", fontsize=14, fontweight='bold')
            ax.set_xlabel(f"{feature} (Normalized/Transformed)")
            ax.set_ylabel("Partial Dependence on Vickers Hardness")
            ax.grid(True, alpha=0.3)
        except Exception as e:
            logger.error(f"Error generating PDP for {feature}: {e}")
            # Fallback: manual plot if library fails (rare)
            ax.text(0.5, 0.5, f"Error plotting {feature}", transform=ax.transAxes, ha='center')
            ax.set_title(f"Error: {feature}")

    plt.suptitle("Partial Dependence Plots (Top 3 Features)", fontsize=16, fontweight='bold', y=1.02)
    plt.tight_layout()

    # Save the combined figure
    output_file = output_dir / "partial_dependence_top3.png"
    plt.savefig(output_file, bbox_inches='tight', dpi=300)
    plt.close(fig)
    
    plot_paths.append(output_file)
    logger.info(f"Saved partial dependence plots to {output_file}")

    # Also save individual plots if needed (optional, but good for detail)
    # For this task, we save one combined image as per standard practice
    
    return plot_paths


def save_pdp_metadata(
    features: List[str],
    output_path: Optional[Path] = None
) -> Path:
    """
    Saves metadata about the PDP generation (features used, timestamp, etc.)
    and injects the FR-007 associational warning.

    Args:
        features: List of feature names plotted.
        output_path: Path to the metadata file.
                     Defaults to data/outputs/pdp_metadata.json.

    Returns:
        Path to the saved metadata file.
    """
    if output_path is None:
        output_path = get_data_outputs_dir() / "pdp_metadata.json"
    
    import json
    from datetime import datetime

    metadata = {
        "task_id": "T035",
        "task_description": "Partial Dependence Plot Generation",
        "generated_at": datetime.now().isoformat(),
        "features_plotted": features,
        "plot_file": "partial_dependence_top3.png",
        "warning": "Associational findings only. No causal inference."
    }

    with open(output_path, 'w') as f:
        json.dump(metadata, f, indent=2)

    # Inject FR-007 warning text into the file if it's a text-based format
    # For JSON, we already added it, but we can also add a text note file
    text_note_path = get_data_outputs_dir() / "pdp_warning_note.txt"
    add_warning_to_text_file(text_note_path, "Partial Dependence Plots")
    
    logger.info(f"Saved PDP metadata to {output_path} and warning note to {text_note_path}")
    return output_path


def main():
    """
    Main entry point for the Partial Dependence Plot generation.
    
    This function orchestrates the loading of the model, data, and SHAP results,
    generates the plots, and saves the outputs.
    """
    # Initialize reproducibility
    init_reproducibility()
    
    logger.info("Starting Partial Dependence Plot generation (T035)...")
    
    try:
        # 1. Load Top 3 Features from SHAP analysis
        shap_summary_path = get_models_dir() / "shap_summary.json"
        if not shap_summary_path.exists():
            # If SHAP summary doesn't exist, we might need to run SHAP analysis first
            # But per task dependencies, T028 (SHAP) should have run.
            # We raise an error to fail loudly if dependencies are missing.
            raise FileNotFoundError(
                f"SHAP summary not found at {shap_summary_path}. "
                "Please ensure T028 (SHAP Analysis) has been completed."
            )
        
        top_features = load_top_features_from_shap(shap_summary_path)
        
        # 2. Load Model and Data
        model_path = get_models_dir() / "xgboost_model.pkl"
        data_path = get_data_processed_dir() / "solder_hardness_validated.csv"
        
        model, X = load_model_and_data(model_path, data_path)
        
        # 3. Generate Plots
        output_dir = get_data_outputs_dir()
        plot_paths = generate_partial_dependence_plots(model, X, top_features, output_dir)
        
        # 4. Save Metadata
        save_pdp_metadata(top_features)
        
        logger.info("Partial Dependence Plot generation completed successfully.")
        logger.info(f"Output files: {plot_paths}")
        
    except FileNotFoundError as e:
        logger.error(f"Required file missing: {e}")
        sys.exit(1)
    except ValueError as e:
        logger.error(f"Configuration or data error: {e}")
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during PDP generation: {e}", exc_info=True)
        sys.exit(1)

if __name__ == "__main__":
    main()