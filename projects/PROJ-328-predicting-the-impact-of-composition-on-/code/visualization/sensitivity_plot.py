"""
Sensitivity Analysis Plot Generator for Solder Hardness Prediction.

This module generates a visualization of the sensitivity analysis results,
showing the fraction of bootstrap samples exceeding specific R² thresholds.
It reads the sensitivity analysis data generated by `code/evaluation/sensitivity.py`
and produces a bar chart saved to `data/outputs/sensitivity_analysis_plot.png`.

The plot visualizes model robustness across different performance thresholds.
"""

import os
import sys
import logging
import yaml
from pathlib import Path
from typing import Dict, Any, List, Optional

import numpy as np
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches

# Project imports
from config import get_data_processed_dir, get_data_outputs_dir, get_r2_sensitivity_thresholds
from utils.logging_config import get_logger
from utils.fr007_warnings import add_warning_to_text_file

logger = get_logger(__name__)


def load_sensitivity_results() -> Dict[str, Any]:
    """
    Load sensitivity analysis results from the YAML file generated by sensitivity.py.

    Returns:
        Dict containing threshold keys and their corresponding fractions.

    Raises:
        FileNotFoundError: If the sensitivity results file does not exist.
        ValueError: If the file format is incorrect.
    """
    processed_dir = get_data_processed_dir()
    input_path = processed_dir / "sensitivity_analysis.yaml"

    if not input_path.exists():
        raise FileNotFoundError(
            f"Sensitivity analysis results not found at {input_path}. "
            "Please run `code/evaluation/sensitivity.py` first to generate this file."
        )

    with open(input_path, 'r') as f:
        data = yaml.safe_load(f)

    if not isinstance(data, dict):
        raise ValueError(f"Expected sensitivity_analysis.yaml to be a dict, got {type(data)}")

    # Expected structure: {"thresholds": {0.3: 0.85, 0.5: 0.60, ...}, "metadata": {...}}
    if "thresholds" not in data:
        raise ValueError("sensitivity_analysis.yaml missing 'thresholds' key")

    return data["thresholds"]


def plot_sensitivity_analysis(
    thresholds: Dict[float, float],
    output_path: Path,
    title: str = "Model Sensitivity to R² Thresholds",
    xlabel: str = "R² Threshold",
    ylabel: str = "Fraction of Bootstrap Samples Exceeding Threshold"
) -> None:
    """
    Generate a bar chart showing the fraction of bootstrap samples exceeding R² thresholds.

    Args:
        thresholds: Dictionary mapping R² thresholds to fractions (0.0 to 1.0).
        output_path: Path where the plot will be saved.
        title: Plot title.
        xlabel: X-axis label.
        ylabel: Y-axis label.
    """
    if not thresholds:
        raise ValueError("No threshold data provided for plotting.")

    # Sort thresholds for consistent plotting
    sorted_keys = sorted(thresholds.keys())
    sorted_values = [thresholds[k] for k in sorted_keys]

    # Create figure
    fig, ax = plt.subplots(figsize=(10, 6))

    # Create bars
    colors = plt.cm.Blues(np.linspace(0.4, 0.9, len(sorted_keys)))
    bars = ax.bar(
        [str(k) for k in sorted_keys],
        sorted_values,
        color=colors,
        edgecolor='black',
        linewidth=1.2
    )

    # Add value labels on top of bars
    for bar, val in zip(bars, sorted_values):
        height = bar.get_height()
        ax.text(
            bar.get_x() + bar.get_width() / 2.,
            height,
            f'{val:.2f}',
            ha='center',
            va='bottom',
            fontsize=10,
            fontweight='bold'
        )

    # Styling
    ax.set_title(title, fontsize=14, fontweight='bold', pad=15)
    ax.set_xlabel(xlabel, fontsize=12, fontweight='medium')
    ax.set_ylabel(ylabel, fontsize=12, fontweight='medium')
    ax.set_ylim(0, max(1.0, max(sorted_values) * 1.1))
    ax.grid(axis='y', linestyle='--', alpha=0.7)

    # Ensure output directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Save plot
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    plt.close(fig)

    logger.info(f"Sensitivity analysis plot saved to: {output_path}")


def generate_sensitivity_report(
    thresholds: Dict[float, float],
    output_dir: Path
) -> None:
    """
    Generate a text summary report alongside the plot.

    Args:
        thresholds: Dictionary of threshold results.
        output_dir: Directory to save the report.
    """
    report_path = output_dir / "sensitivity_analysis_report.txt"

    lines = [
        "Sensitivity Analysis Report",
        "=" * 40,
        "",
        "This report summarizes the robustness of the model predictions",
        "across different R² performance thresholds based on bootstrap resampling.",
        "",
        "Results:"
    ]

    for threshold in sorted(thresholds.keys()):
        fraction = thresholds[threshold]
        lines.append(f"  R² > {threshold:.2f}: {fraction:.2%} of samples")

    lines.extend([
        "",
        "Interpretation:",
        "  Higher fractions indicate greater model stability and robustness",
        "  at that performance level.",
        ""
    ])

    with open(report_path, 'w') as f:
        f.write('\n'.join(lines))

    # Inject associational framing warning as per FR-007
    add_warning_to_text_file(report_path)
    logger.info(f"Sensitivity analysis report saved to: {report_path}")


def main() -> int:
    """
    Main entry point for the sensitivity plot generator.

    Loads sensitivity analysis data, generates the plot and report,
    and saves them to the outputs directory.

    Returns:
        0 on success, 1 on failure.
    """
    try:
        logger.info("Starting sensitivity analysis plot generation...")

        # Load data
        thresholds = load_sensitivity_results()
        logger.info(f"Loaded {len(thresholds)} threshold results.")

        # Setup output paths
        output_dir = get_data_outputs_dir()
        plot_path = output_dir / "sensitivity_analysis_plot.png"
        logger.info(f"Target output directory: {output_dir}")

        # Generate plot
        plot_sensitivity_analysis(
            thresholds=thresholds,
            output_path=plot_path,
            title="Sensitivity of Solder Hardness Model to R² Thresholds",
            xlabel="R² Threshold",
            ylabel="Fraction of Bootstrap Samples Exceeding Threshold"
        )

        # Generate report
        generate_sensitivity_report(thresholds, output_dir)

        logger.info("Sensitivity analysis visualization complete.")
        return 0

    except FileNotFoundError as e:
        logger.error(f"Data file missing: {e}")
        logger.error("Ensure `code/evaluation/sensitivity.py` has been run first.")
        return 1
    except Exception as e:
        logger.error(f"Error generating sensitivity plot: {e}", exc_info=True)
        return 1


if __name__ == "__main__":
    sys.exit(main())