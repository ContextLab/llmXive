import os
import sys
import logging
from pathlib import Path
from utils.reference_validator import validate_research_md, ConstitutionError
from utils.logging_config import get_logger

def main():
    """
    Executes the Reference-Validator Agent on the draft research.md generated by T008a.
    It verifies URLs, citation formats, and source validity.
    On success, it writes a cleaned `research_verified.md` to the specs directory.
    On failure, it raises an error and halts the pipeline.
    """
    logger = get_logger(__name__)
    
    # Determine paths relative to project root
    project_root = Path(__file__).resolve().parent.parent.parent
    specs_dir = project_root / "specs" / "001-predict-solder-hardness"
    draft_path = specs_dir / "research.md"
    verified_path = specs_dir / "research_verified.md"

    # Ensure specs directory exists
    specs_dir.mkdir(parents=True, exist_ok=True)

    logger.info(f"Starting reference validation for: {draft_path}")
    
    if not draft_path.exists():
        logger.error(f"Draft research file not found: {draft_path}")
        logger.error("Task T008a (Generate Research Sources) must complete before T008b.")
        raise FileNotFoundError(f"Draft research file missing: {draft_path}")

    try:
        # Run the validation logic which returns a list of verified entries
        # and writes the verified content to the output file
        verified_entries = validate_research_md(
            input_path=draft_path,
            output_path=verified_path
        )

        if not verified_entries:
            logger.warning("No valid references found in the draft. Halting pipeline.")
            raise ConstitutionError("Validation failed: No verified sources found.")
        
        logger.info(f"Validation successful. Verified {len(verified_entries)} sources.")
        logger.info(f"Output written to: {verified_path}")
        
        # Explicitly print success for the pipeline runner
        print(f"T008B_SUCCESS: Verified {len(verified_entries)} sources at {verified_path}")
        return 0

    except ConstitutionError as e:
        logger.error(f"Validation failed with ConstitutionError: {e}")
        # If verification fails, the pipeline halts as per requirements
        sys.exit(1)
    except Exception as e:
        logger.error(f"Unexpected error during validation: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
