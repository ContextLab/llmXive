"""
Populate sources.yaml from research_verified.md.

This script reads the verified research sources generated by T008b
and creates a structured YAML configuration file for data ingestion.
"""
import os
import sys
import logging
import yaml
import re
from pathlib import Path
from typing import Dict, Any, List, Optional

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from utils.logging_config import get_logger
from utils.error_handlers import ConfigurationError

logger = get_logger(__name__)


def parse_verified_sources(verified_md_path: Path) -> Dict[str, Any]:
    """
    Parse research_verified.md and extract verified URLs and endpoints.
    
    Args:
        verified_md_path: Path to the verified research markdown file
        
    Returns:
        Dictionary containing structured source information
        
    Raises:
        ConfigurationError: If the verified file doesn't exist or is malformed
    """
    if not verified_md_path.exists():
        raise ConfigurationError(
            f"Verified research file not found: {verified_md_path}. "
            "Run T008b first to generate research_verified.md."
        )
    
    sources_config = {
        "materials_project": {
            "name": "Materials Project",
            "type": "api",
            "url": "https://api.materialsproject.org",
            "api_key_env": "MP_API_KEY",
            "endpoint": "/materials",
            "description": "High-throughput DFT calculations for materials properties"
        },
        "nist_uci": {
            "name": "NIST/UCI Repository",
            "type": "repository",
            "url": "https://archive.ics.uci.edu/ml/datasets.php",
            "dataset_id": "solder_alloys",
            "description": "Standardized alloy composition and property datasets"
        },
        "openalloy": {
            "name": "OpenAlloy Database",
            "type": "api",
            "url": "https://openalloy.org/api/v1",
            "endpoint": "/compositions",
            "description": "Open source alloy composition database"
        },
        "literature_pdfs": []
    }
    
    with open(verified_md_path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Extract verified URLs from the markdown
    # Expected format in research_verified.md:
    # - [Source Name](https://verified-url.com) - Description
    url_pattern = r'-\s*\[([^\]]+)\]\((https?://[^\)]+)\)\s*[-–]\s*(.*)'
    matches = re.findall(url_pattern, content)
    
    for name, url, description in matches:
        # Determine source type based on URL pattern
        if 'materialsproject.org' in url.lower():
            sources_config["materials_project"]["url"] = url
            sources_config["materials_project"]["description"] = description
        elif 'archive.ics.uci.edu' in url.lower() or 'nist' in url.lower():
            sources_config["nist_uci"]["url"] = url
            sources_config["nist_uci"]["description"] = description
        elif 'openalloy' in url.lower():
            sources_config["openalloy"]["url"] = url
            sources_config["openalloy"]["description"] = description
        elif url.endswith('.pdf') or 'doi.org' in url.lower():
            # Add to literature PDFs
            literature_entry = {
                "name": name,
                "url": url,
                "format": "pdf",
                "scraping_method": "pdfplumber",
                "description": description.strip()
            }
            sources_config["literature_pdfs"].append(literature_entry)
        else:
            # Add as generic literature source
            literature_entry = {
                "name": name,
                "url": url,
                "format": "unknown",
                "scraping_method": "requests",
                "description": description.strip()
            }
            sources_config["literature_pdfs"].append(literature_entry)
    
    # Validate that we found at least some sources
    if not sources_config["literature_pdfs"] and \
       sources_config["materials_project"]["url"] == "https://api.materialsproject.org":
        logger.warning(
            "No verified URLs found in research_verified.md. "
            "Using default placeholder configuration."
        )
    
    return sources_config


def save_sources_yaml(sources_config: Dict[str, Any], output_path: Path) -> None:
    """
    Save the sources configuration to a YAML file.
    
    Args:
        sources_config: Dictionary containing source configuration
        output_path: Path to the output YAML file
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        yaml.dump(
            sources_config,
            f,
            default_flow_style=False,
            allow_unicode=True,
            sort_keys=False,
            indent=2
        )
    
    logger.info(f"Successfully saved sources configuration to {output_path}")


def main() -> int:
    """
    Main entry point for populating sources.yaml.
    
    Returns:
        0 on success, 1 on failure
    """
    try:
        # Define paths
        verified_md_path = PROJECT_ROOT / "specs" / "001-predict-solder-hardness" / "research_verified.md"
        output_path = PROJECT_ROOT / "data" / "config" / "sources.yaml"
        
        logger.info(f"Reading verified sources from: {verified_md_path}")
        
        # Parse verified sources
        sources_config = parse_verified_sources(verified_md_path)
        
        # Save to YAML
        save_sources_yaml(sources_config, output_path)
        
        # Log summary
        num_pdfs = len(sources_config.get("literature_pdfs", []))
        logger.info(f"Populated sources.yaml with {num_pdfs} literature sources and 3 API/repository sources")
        
        return 0
        
    except ConfigurationError as e:
        logger.error(f"Configuration error: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error: {e}", exc_info=True)
        return 1


if __name__ == "__main__":
    sys.exit(main())
