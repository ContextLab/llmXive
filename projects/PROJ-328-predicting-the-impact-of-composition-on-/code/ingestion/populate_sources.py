"""
Task T009c: Populate sources.yaml from verified research.

Reads the verified research file (research_verified.md) generated by T008b,
extracts valid URLs and API endpoints, and populates data/config/sources.yaml
with the specific, verified information.
"""
import os
import sys
import logging
import yaml
import re
from pathlib import Path
from typing import Dict, List, Any, Optional, Tuple

# Add project root to path if running as script
if __name__ == "__main__":
    project_root = Path(__file__).resolve().parent.parent.parent
    sys.path.insert(0, str(project_root))

from utils.logging_config import get_logger
from utils.error_handlers import ConfigurationError

logger = get_logger(__name__)

# Constants for file paths
RESEARCH_VERIFIED_PATH = Path("specs/001-predict-solder-hardness/research_verified.md")
SOURCES_YAML_PATH = Path("data/config/sources.yaml")


def parse_verified_sources(verified_md_path: Path) -> Dict[str, Any]:
    """
    Parse the verified research markdown file to extract sources.

    Args:
        verified_md_path: Path to the research_verified.md file

    Returns:
        Dictionary containing parsed source information

    Raises:
        ConfigurationError: If the file does not exist or contains no valid sources
    """
    if not verified_md_path.exists():
        raise ConfigurationError(
            f"Verified research file not found: {verified_md_path}. "
            "Ensure T008b has completed successfully."
        )

    sources = {
        "materials_project": {},
        "nist_uci": {},
        "openalloy": {},
        "literature_pdfs": []
    }

    with open(verified_md_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Regex patterns to extract URLs and citations
    # Pattern for URLs in markdown links or plain text
    url_pattern = r'(https?://[^\s<>"{}|\\^`\[\]]+|https?://[^\s<>"{}|\\^`\[\]]+\.[a-z]+)'
    # Pattern for DOI
    doi_pattern = r'(10\.\d{4,9}/[-._;()/:A-Z0-9]+)'

    lines = content.split('\n')
    current_section = None
    current_source = None

    for line in lines:
        line = line.strip()
        
        # Detect sections
        if line.startswith('#') or line.startswith('##'):
            section_lower = line.lower()
            if 'materials project' in section_lower:
                current_section = 'materials_project'
            elif 'nist' in section_lower or 'uci' in section_lower:
                current_section = 'nist_uci'
            elif 'openalloy' in section_lower:
                current_section = 'openalloy'
            elif 'literature' in section_lower or 'pdf' in section_lower:
                current_section = 'literature'
            continue

        # Extract URLs
        urls = re.findall(url_pattern, line)
        dois = re.findall(doi_pattern, line, re.IGNORECASE)

        if current_section == 'materials_project' and urls:
            sources['materials_project']['url'] = urls[0]
            sources['materials_project']['verified'] = True
            logger.info(f"Extracted Materials Project URL: {urls[0]}")
        
        elif current_section == 'nist_uci' and urls:
            sources['nist_uci']['url'] = urls[0]
            sources['nist_uci']['verified'] = True
            logger.info(f"Extracted NIST/UCI URL: {urls[0]}")
        
        elif current_section == 'openalloy' and urls:
            sources['openalloy']['url'] = urls[0]
            sources['openalloy']['verified'] = True
            logger.info(f"Extracted OpenAlloy URL: {urls[0]}")
        
        elif current_section == 'literature':
            # Look for title and URL together
            title_match = re.search(r'\*\*(.*?)\*\*', line)
            title = title_match.group(1) if title_match else None
            
            if urls or dois:
                url = urls[0] if urls else f"https://doi.org/{dois[0]}"
                source_entry = {
                    "name": title or f"Source {len(sources['literature_pdfs']) + 1}",
                    "url": url,
                    "format": "pdf",
                    "scraping_method": "pdfplumber",
                    "verified": True
                }
                sources['literature_pdfs'].append(source_entry)
                logger.info(f"Extracted literature source: {source_entry['name']} -> {url}")

    # Validate that we found at least some sources
    has_sources = (
        sources['materials_project'].get('url') or
        sources['nist_uci'].get('url') or
        sources['openalloy'].get('url') or
        len(sources['literature_pdfs']) > 0
    )

    if not has_sources:
        raise ConfigurationError(
            "No valid sources found in research_verified.md. "
            "Please ensure the verification step (T008b) populated the file with actual URLs."
        )

    return sources


def save_sources_yaml(sources: Dict[str, Any], output_path: Path) -> None:
    """
    Save the extracted sources to a YAML file.

    Args:
        sources: Dictionary of source information
        output_path: Path to write the YAML file
    """
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Prepare the output structure with metadata
    output_data = {
        "#": "Verified data sources for solder hardness dataset",
        "#": "Populated from research_verified.md (T008b) by T009c",
        "#": "Generated automatically - do not edit manually",
        "generated_from": str(RESEARCH_VERIFIED_PATH),
        "materials_project": {
            "name": "Materials Project",
            "type": "api",
            "url": sources['materials_project'].get('url', ''),
            "api_key_env": "MP_API_KEY",
            "endpoint": "/materials",
            "description": "High-throughput DFT calculations for materials properties",
            "verified": sources['materials_project'].get('verified', False)
        },
        "nist_uci": {
            "name": "NIST/UCI Repository",
            "type": "repository",
            "url": sources['nist_uci'].get('url', ''),
            "dataset_id": "solder_alloys",
            "description": "Standardized alloy composition and property datasets",
            "verified": sources['nist_uci'].get('verified', False)
        },
        "openalloy": {
            "name": "OpenAlloy Database",
            "type": "api",
            "url": sources['openalloy'].get('url', ''),
            "endpoint": "/compositions",
            "description": "Open source alloy composition database",
            "verified": sources['openalloy'].get('verified', False)
        },
        "literature_pdfs": sources['literature_pdfs']
    }

    with open(output_path, 'w', encoding='utf-8') as f:
        # Write header comments manually to preserve formatting
        f.write("# Verified data sources for solder hardness dataset\n")
        f.write("# Populated from research_verified.md (T008b) by T009c\n")
        f.write("# Generated automatically - do not edit manually\n")
        f.write(f"generated_from: {RESEARCH_VERIFIED_PATH}\n\n")
        
        # Write the rest using yaml.dump
        # We need to handle the structure carefully
        yaml_content = yaml.dump(
            {
                "materials_project": output_data["materials_project"],
                "nist_uci": output_data["nist_uci"],
                "openalloy": output_data["openalloy"],
                "literature_pdfs": output_data["literature_pdfs"]
            },
            f,
            default_flow_style=False,
            sort_keys=False,
            allow_unicode=True
        )

    logger.info(f"Successfully populated {output_path} with verified sources")


def main() -> int:
    """
    Main entry point for T009c.

    Returns:
        0 on success, 1 on failure
    """
    try:
        logger.info("Starting T009c: Populate sources.yaml from verified research")
        
        # Validate input file exists
        if not RESEARCH_VERIFIED_PATH.exists():
            raise ConfigurationError(
                f"Required file not found: {RESEARCH_VERIFIED_PATH}. "
                "Task T008b must complete first."
            )

        # Parse verified sources
        logger.info(f"Parsing verified sources from {RESEARCH_VERIFIED_PATH}")
        sources = parse_verified_sources(RESEARCH_VERIFIED_PATH)

        # Save to YAML
        logger.info(f"Writing verified sources to {SOURCES_YAML_PATH}")
        save_sources_yaml(sources, SOURCES_YAML_PATH)

        # Verify the output
        if not SOURCES_YAML_PATH.exists():
            raise ConfigurationError("Failed to write sources.yaml file")

        logger.info("T009c completed successfully")
        return 0

    except ConfigurationError as e:
        logger.error(f"Configuration error: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error: {e}", exc_info=True)
        return 1


if __name__ == "__main__":
    sys.exit(main())
