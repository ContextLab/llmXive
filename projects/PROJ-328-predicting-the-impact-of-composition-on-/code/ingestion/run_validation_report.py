"""
T019: Execute Validation Report Generation.

This script runs the validation report generation process defined in T016b.
It reads the ingestion status from data/processed/.ingestion_status.json
and generates the final validation report at data/processed/validation_report.yaml.

Dependencies:
- T014 must have completed successfully to ensure .ingestion_status.json exists.
"""
import os
import sys
import logging
import json
import yaml
from pathlib import Path

# Add the code directory to the path to allow imports from sibling modules
code_dir = Path(__file__).resolve().parent.parent
if str(code_dir) not in sys.path:
    sys.path.insert(0, str(code_dir))

from ingestion.generate_validation_report import load_ingestion_status, generate_validation_report, save_report
from utils.logging_config import get_logger

def main():
    logger = get_logger("T019_Report_Executor")
    logger.info("Starting T019: Executing Validation Report Generation.")

    # Define paths relative to project root
    project_root = code_dir.parent
    status_path = project_root / "data" / "processed" / ".ingestion_status.json"
    report_path = project_root / "data" / "processed" / "validation_report.yaml"

    # Check if the status file exists (dependency on T014)
    if not status_path.exists():
        logger.error(f"Dependency failed: {status_path} does not exist. "
                     "T014 (Validator) must be run first to generate the status file.")
        raise FileNotFoundError(f"Missing ingestion status file: {status_path}. "
                                "Ensure T014 has been executed successfully.")

    try:
        # Load the status generated by T014
        status_data = load_ingestion_status(status_path)
        logger.info(f"Loaded ingestion status: N={status_data.get('total_records', 0)}, "
                    f"Status={status_data.get('threshold_status', 'UNKNOWN')}")

        # Generate the report content
        report_content = generate_validation_report(status_data)

        # Save the report to the specified location
        save_report(report_content, report_path)
        logger.info(f"Successfully generated validation report at: {report_path}")

        # Verify the file was written
        if report_path.exists():
            logger.info("Verification: Report file exists and is non-empty.")
            with open(report_path, 'r') as f:
                size = len(f.read())
                logger.info(f"Report size: {size} bytes")
        else:
            logger.error("Verification failed: Report file was not created.")
            sys.exit(1)

    except Exception as e:
        logger.error(f"Failed to generate validation report: {e}", exc_info=True)
        sys.exit(1)

    logger.info("T019 completed successfully.")

if __name__ == "__main__":
    main()