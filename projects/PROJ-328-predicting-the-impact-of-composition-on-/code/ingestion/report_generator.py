import os
import sys
import logging
import json
import yaml
from pathlib import Path
from typing import Dict, Any, Optional

# Add project root to path if running as script
if "CODE_DIR" not in os.environ:
    code_dir = Path(__file__).parent.parent
    if (code_dir / "config.py").exists():
        sys.path.insert(0, str(code_dir))
    
from config import get_data_processed_dir
from utils.logging_config import get_logger

logger = get_logger(__name__)

STATUS_FILE_NAME = ".ingestion_status.json"
REPORT_FILE_NAME = "validation_report.yaml"

def load_ingestion_status(status_path: Optional[Path] = None) -> Dict[str, Any]:
    """
    Load the ingestion status from the JSON state file generated by T013/T014.
    
    Args:
        status_path: Optional path to the status file. If None, uses default location.
        
    Returns:
        Dictionary containing threshold_status, warning_text, total_n, etc.
        
    Raises:
        FileNotFoundError: If the status file does not exist.
        json.JSONDecodeError: If the status file is corrupted.
    """
    if status_path is None:
        processed_dir = get_data_processed_dir()
        status_path = Path(processed_dir) / STATUS_FILE_NAME
    
    if not status_path.exists():
        raise FileNotFoundError(
            f"Ingestion status file not found at {status_path}. "
            f"Please ensure T013 and T014 have completed successfully."
        )
    
    with open(status_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def generate_validation_report(status: Dict[str, Any], output_path: Optional[Path] = None) -> Dict[str, Any]:
    """
    Generate the validation report based on the ingestion status.
    
    Args:
        status: The ingestion status dictionary containing N counts and thresholds.
        output_path: Optional path for the output report. If None, uses default location.
        
    Returns:
        The generated report dictionary.
    """
    total_n = status.get("total_n", 0)
    threshold_status = status.get("threshold_status", "unknown")
    warning_text = status.get("warning_text", "")
    
    # Determine if N >= 100
    is_sufficient = total_n >= 100
    
    report = {
        "task_id": "T016b",
        "report_type": "validation_report",
        "generated_from_status_file": STATUS_FILE_NAME,
        "data_summary": {
            "total_unique_compositions": total_n,
            "is_dataset_sufficient_for_mvp": is_sufficient,
            "threshold_status": threshold_status
        },
        "statistical_power": {
            "meets_minimum_threshold_100": is_sufficient,
            "warning_required": not is_sufficient,
            "warning_text": warning_text if not is_sufficient else None
        },
        "status_details": {
            "n_ge_100": total_n >= 100,
            "n_between_50_and_100": 50 <= total_n < 100,
            "n_less_than_50": total_n < 50
        }
    }
    
    if output_path is None:
        processed_dir = get_data_processed_dir()
        output_path = Path(processed_dir) / REPORT_FILE_NAME
    
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    # Write report
    with open(output_path, 'w', encoding='utf-8') as f:
        yaml.dump(report, f, default_flow_style=False, sort_keys=False, allow_unicode=True)
    
    logger.info(f"Validation report generated successfully at {output_path}")
    return report

def main():
    """Main entry point for the report generation script."""
    logger.info("Starting validation report generation (T016b)...")
    
    try:
        status = load_ingestion_status()
        logger.info(f"Loaded ingestion status: N={status.get('total_n')}, Status={status.get('threshold_status')}")
        
        report = generate_validation_report(status)
        
        logger.info("Validation report generation completed successfully.")
        logger.info(f"Report summary: N={report['data_summary']['total_unique_compositions']}, "
                    f"Sufficient={report['data_summary']['is_dataset_sufficient_for_mvp']}")
        
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"Status file not found: {e}")
        logger.error("Ensure T013 (cleaner) and T014 (validator) have run and written .ingestion_status.json")
        return 1
    except json.JSONDecodeError as e:
        logger.error(f"Corrupted status file: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error generating report: {e}")
        raise

if __name__ == "__main__":
    sys.exit(main())