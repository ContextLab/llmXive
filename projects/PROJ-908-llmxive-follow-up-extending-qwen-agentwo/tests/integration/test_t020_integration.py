"""
Integration test for T020: Load LLM CoT traces.

This test verifies that the trace loader correctly handles the file
generated by T018 (data/raw/cot_traces.json).
"""

import json
import tempfile
from pathlib import Path

import pytest

from rules.trace_loader import load_traces_for_extraction
from utils.loaders import load_cot_traces

@pytest.fixture
def sample_traces_file(tmp_path):
    """Create a sample cot_traces.json file."""
    traces = [
        {
            "task_id": "task_001",
            "steps": [
                {"step": 1, "thought": "I need to go to the kitchen.", "action": "move", "target": "kitchen"},
                {"step": 2, "thought": "I found the key.", "action": "pick", "target": "key"}
            ],
            "success": True
        },
        {
            "task_id": "task_002",
            "steps": [
                {"step": 1, "thought": "I need to open the door.", "action": "move", "target": "door"}
            ],
            "success": False
        }
    ]
    file_path = tmp_path / "cot_traces.json"
    with open(file_path, 'w') as f:
        json.dump(traces, f, indent=2)
    return file_path

def test_integration_load_real_traces(sample_traces_file):
    """Integration test: Load the generated traces file."""
    traces = load_traces_for_extraction(str(sample_traces_file))
    
    assert len(traces) == 2
    assert traces[0]["task_id"] == "task_001"
    assert traces[1]["success"] is False

def test_integration_missing_file_fails_loudly(tmp_path):
    """Integration test: Ensure missing file fails loudly."""
    # Point to a non-existent file in the temp directory
    fake_path = tmp_path / "data" / "raw" / "cot_traces.json"
    
    with pytest.raises(FileNotFoundError) as e:
        load_traces_for_extraction(str(fake_path))
    
    assert "not found" in str(e.value).lower()
    assert "T018" in str(e.value) or "trace generation" in str(e.value).lower()
