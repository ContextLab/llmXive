"""
Test suite for the environment provisioning task (T000).

It verifies two things:
1. The ``scripts/verify_env.sh`` script runs without error and produces a
   non‑empty log file containing the pip installation output.
2. The ``src.utils.checksums`` module can recompute SHA‑256 checksums for
   every file under ``data/`` and that the generated ``checksums.txt``
   matches those recomputed values.
"""

import subprocess
from pathlib import Path

import pytest

from src.utils import checksums


@pytest.fixture(scope="session")
def project_root(tmp_path_factory):
    """Return the root directory of the project (where this file lives)."""
    # The test file resides in ``tests/``; the project root is its parent.
    return Path(__file__).resolve().parent.parent


def test_verify_env_script(project_root):
    """Run the verification shell script and check its log output."""
    script_path = project_root / "scripts" / "verify_env.sh"
    assert script_path.is_file(), "verify_env.sh script missing"

    # Execute the script; capture the return code.
    result = subprocess.run(
        ["bash", str(script_path)],
        cwd=project_root,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    assert result.returncode == 0, f"Script failed with {result.returncode}: {result.stderr}"

    log_path = project_root / "data" / "env_evidence" / "pip_install.log"
    assert log_path.is_file(), "pip_install.log was not created"
    # The log should contain at least one line indicating pip processed the file.
    content = log_path.read_text(encoding="utf-8")
    assert content.strip(), "pip_install.log is empty"
    # Look for a common success phrase.
    assert "Successfully installed" in content or "Requirement already satisfied" in content, (
        "pip_install.log does not appear to contain a successful installation message"
    )


def _recompute_checksums(root: Path):
    """Return a dict mapping relative file paths to their SHA‑256 checksum."""
    checksums_dict = {}
    for file_path in root.rglob("*"):
        if file_path.is_file() and file_path.name != "checksums.txt":
            rel = file_path.relative_to(root)
            checksums_dict[str(rel)] = checksums._sha256_file(file_path)
    return checksums_dict


def test_checksums_match(project_root):
    """
    Re‑compute all checksums under ``data/`` and ensure they match the
    contents of ``data/checksums.txt`` generated by ``src.utils.checksums.main``.
    """
    data_dir = project_root / "data"

    # (Re)generate the checksums file using the module's CLI entry point.
    checksums.main()

    checksum_file = data_dir / "checksums.txt"
    assert checksum_file.is_file(), "checksums.txt was not created by checksums.main()"

    # Load the file produced by the module.
    recorded = {}
    for line in checksum_file.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        parts = line.split(maxsplit=1)
        assert len(parts) == 2, f"Malformed line in checksums.txt: {line!r}"
        recorded[parts[1]] = parts[0]

    # Compute expected checksums directly.
    expected = _recompute_checksums(data_dir)

    # The two dictionaries should be identical.
    assert recorded == expected, "Computed checksums do not match the recorded checksums.txt"