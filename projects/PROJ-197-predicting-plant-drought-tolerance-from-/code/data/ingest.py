"""
Data Ingestion Module for Drought Tolerance Prediction Pipeline.

Handles loading, merging, and imputing trait and genomic data.
Implements Phylogenetic MICE when tree is available, otherwise Median Substitution.
"""
import os
import sys
import json
import logging
import pandas as pd
import numpy as np
from pathlib import Path
from typing import Tuple, List, Optional, Dict, Any

# Add parent directory to path for imports
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from config import get_config, ensure_directories, VALIDATION_MODE
from utils.logging import DataPipelineLog
from utils.imputation import apply_phylogenetic_mice

# Configure logger
logger = logging.getLogger(__name__)
log_handler = DataPipelineLog()

# Constants
REAL_PHYLO_PATH = Path("data/processed/real_phylo_matrix.npy")
SYNTHETIC_GENOMICS_PATH = Path("data/processed/synthetic_genomics.csv")
MERGED_OUTPUT_PATH = Path("data/processed/merged_dataset_imputed.csv")
METRICS_LOG_PATH = Path("data/logs/metrics.json")

def load_try_data() -> pd.DataFrame:
    """
    Load TRY database traits from the raw data directory.
    Expects data/raw/try_traits.csv (generated by T011a).
    """
    try:
        # Check if the file exists first
        try_path = Path("data/raw/try_traits.csv")
        if not try_path.exists():
            # Fallback for testing if raw data isn't strictly present yet in this env
            # In a real run, this should be provided by T011a
            logger.log_event("data_missing", "TRY traits file not found", {"path": str(try_path)})
            raise FileNotFoundError(f"TRY traits file not found at {try_path}")
        
        df = pd.read_csv(try_path)
        logger.log_event("data_loaded", "TRY traits loaded", {"rows": len(df), "columns": list(df.columns)})
        return df
    except FileNotFoundError as e:
        logger.log_event("error", str(e))
        raise

def load_synthetic_genomics() -> pd.DataFrame:
    """
    Load synthetic genomic features generated by T012.
    """
    if not SYNTHETIC_GENOMICS_PATH.exists():
        raise FileNotFoundError(f"Synthetic genomics file not found at {SYNTHETIC_GENOMICS_PATH}")
    
    df = pd.read_csv(SYNTHETIC_GENOMICS_PATH)
    logger.log_event("data_loaded", "Synthetic genomics loaded", {"rows": len(df), "columns": list(df.columns)})
    return df

def merge_datasets(try_df: pd.DataFrame, genomic_df: pd.DataFrame) -> pd.DataFrame:
    """
    Merge TRY traits and genomic data by species_id.
    Logs excluded species that are in TRY but missing genomic data.
    """
    # Ensure species_id is the join key in both
    if 'species_id' not in try_df.columns or 'species_id' not in genomic_df.columns:
        raise ValueError("Both DataFrames must contain 'species_id' column")

    # Perform inner join to keep only species present in both
    merged_df = pd.merge(try_df, genomic_df, on='species_id', how='inner')

    # Identify excluded species (in TRY but not in genomic)
    try_species = set(try_df['species_id'].unique())
    genomic_species = set(genomic_df['species_id'].unique())
    excluded_species = list(try_species - genomic_species)

    if excluded_species:
        logger.log_event("excluded_species", f"Found {len(excluded_species)} species missing genomic data", {"species": excluded_species})
        # Save to metrics log
        metrics = {}
        if METRICS_LOG_PATH.exists():
            with open(METRICS_LOG_PATH, 'r') as f:
                metrics = json.load(f)
        
        metrics['excluded_species'] = excluded_species
        metrics['excluded_species_count'] = len(excluded_species)
        
        with open(METRICS_LOG_PATH, 'w') as f:
            json.dump(metrics, f, indent=2)
    else:
        logger.log_event("merge_success", "All species matched", {"count": len(merged_df)})

    return merged_df

def apply_mice_imputation(df: pd.DataFrame) -> pd.DataFrame:
    """
    Handle missing continuous traits.
    
    Logic:
    1. Check if real phylogenetic tree exists (data/processed/real_phylo_matrix.npy).
    2. If EXISTS: Apply Phylogenetic MICE (primary path).
    3. If NOT EXISTS:
       - If VALIDATION_MODE is False: Raise critical error (Constitution VI violation).
       - If VALIDATION_MODE is True: Apply Median Substitution and log waiver.
    
    Imputes columns defined in SpeciesRecord (continuous traits).
    """
    logger.log_event("imputation_start", "Starting imputation logic")
    
    # Identify continuous trait columns to impute
    # Based on SpeciesRecord definition in entities.py: root_depth, leaf_area, stomatal_conductance
    # We assume these are the numeric columns that might have NaNs
    numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
    # Filter out the label column if it exists
    target_cols = [col for col in numeric_cols if col != 'label']
    
    if not target_cols:
        logger.log_event("imputation_skip", "No numeric columns found to impute")
        return df

    # Check for real phylogenetic matrix
    tree_exists = REAL_PHYLO_PATH.exists()
    
    if tree_exists:
        logger.log_event("imputation_method", "Phylogenetic MICE", {"tree": str(REAL_PHYLO_PATH)})
        try:
            # Apply Phylogenetic MICE
            # This requires the tree matrix and the dataframe with species_id
            imputed_df = apply_phylogenetic_mice(df, target_cols, REAL_PHYLO_PATH)
            logger.log_event("imputation_complete", "Phylogenetic MICE successful")
            return imputed_df
        except Exception as e:
            logger.log_event("imputation_error", f"Phylogenetic MICE failed: {str(e)}")
            # If Phylo MICE fails, we might fall back or error depending on mode
            if not VALIDATION_MODE:
                raise RuntimeError(f"Constitution VI Violation: Phylogenetic MICE failed and not in validation mode. Error: {e}")
            else:
                logger.log_event("fallback", "Phylo MICE failed, switching to Median Substitution")
                # Fall through to median imputation
    else:
        # Tree does not exist
        if not VALIDATION_MODE:
            error_msg = "CONSTITUTION VI VIOLATION: Phylogenetic MICE required but tree missing. Halting execution."
            logger.log_event("critical_error", error_msg)
            raise RuntimeError(error_msg)
        else:
            logger.log_event("waiver", "Phylogenetic MICE unavailable (tree missing). Using Median Substitution. Waiver of FR-002 logged.")
            logger.log_event("imputation_method", "Median Substitution (Synthetic Path)")

    # Fallback to Median Substitution (SimpleImputer)
    from sklearn.impute import SimpleImputer
    imputer = SimpleImputer(strategy='median')
    
    # Create a copy to avoid modifying original
    df_imputed = df.copy()
    
    # Only impute columns that have missing values
    cols_with_na = [col for col in target_cols if df_imputed[col].isna().any()]
    
    if cols_with_na:
        logger.log_event("imputation_details", f"Imputing {len(cols_with_na)} columns with median", {"cols": cols_with_na})
        df_imputed[cols_with_na] = imputer.fit_transform(df_imputed[cols_with_na])
    else:
        logger.log_event("imputation_details", "No missing values found in target columns")

    return df_imputed

def save_excluded_species_log(excluded_species: List[str]) -> None:
    """
    Explicitly log the excluded species IDs to data/logs/metrics.json.
    This is a helper function, though the logic is integrated in merge_datasets.
    """
    metrics = {}
    if METRICS_LOG_PATH.exists():
        with open(METRICS_LOG_PATH, 'r') as f:
            metrics = json.load(f)
    
    metrics['excluded_species'] = excluded_species
    metrics['excluded_species_count'] = len(excluded_species)
    
    with open(METRICS_LOG_PATH, 'w') as f:
        json.dump(metrics, f, indent=2)
    logger.log_event("excluded_species_saved", f"Saved {len(excluded_species)} excluded species")

def main():
    """
    Main execution function for the ingestion pipeline.
    """
    logger.log_event("pipeline_start", "Starting Data Ingestion Pipeline (T014a)")
    
    # Ensure directories exist
    ensure_directories([Path("data/processed"), Path("data/logs")])
    
    try:
        # 1. Load TRY data
        logger.info("Loading TRY data...")
        try_df = load_try_data()
        
        # 2. Load Genomic data (Synthetic or Real depending on T011b/T012 outcome)
        # We assume the merged input for this step is the synthetic one if T011b failed
        # The task description says: "Input: Output from T011b if SUCCESS, OR T012 if T011b FAILED"
        # Since T012 generates synthetic_genomics.csv, we load that.
        logger.info("Loading genomic data...")
        genomic_df = load_synthetic_genomics()
        
        # 3. Merge datasets
        logger.info("Merging datasets...")
        merged_df = merge_datasets(try_df, genomic_df)
        
        # 4. Impute missing values (T014a Core Logic)
        logger.info("Applying imputation...")
        imputed_df = apply_mice_imputation(merged_df)
        
        # 5. Save output
        logger.info(f"Saving imputed dataset to {MERGED_OUTPUT_PATH}")
        imputed_df.to_csv(MERGED_OUTPUT_PATH, index=False)
        
        logger.log_event("pipeline_complete", "Data Ingestion Pipeline finished successfully")
        return imputed_df
        
    except Exception as e:
        logger.log_event("pipeline_error", str(e))
        raise

if __name__ == "__main__":
    main()
