    def test_synthetic_data_structure(self):
        """Verify that generated data contains all required columns."""
        n_samples = 500
        df = generate_synthetic_data(n_samples=n_samples)

        required_columns = [
            "participant_id",
            "age",
            "gender",
            "offline_relationships",
            "intrinsic_traits",
            "engagement_count",
            "comment_sentiment",
            "self_perception_score",
            "psv_score",
            "timestamp_engagement",
            "timestamp_self_report"
        ]

        assert isinstance(df, pd.DataFrame)
        assert len(df) == n_samples
        for col in required_columns:
            assert col in df.columns, f"Missing required column: {col}"

    def test_sem_parameter_convergence(self):
        """
        Verify that the synthetic data recovers the target SEM parameters.
        
        This test generates a large sample to ensure the observed correlations
        converge to the theoretical parameters defined in the model.
        """
        n_samples = 2000  # Large sample for convergence
        df = generate_synthetic_data(n_samples=n_samples)
        
        # Verify the data is valid
        assert df["self_perception_score"].notna().all()
        assert df["engagement_count"].notna().all()
        assert df["psv_score"].notna().all()

        # Run the verification logic explicitly
        # This function returns a dict with recovery metrics
        recovery_results = verify_association_recovery(df, n_samples)
        
        # Assertions on recovery results
        assert "observed_correlation_engagement" in recovery_results
        assert "observed_correlation_psv" in recovery_results
        assert "target_psv_weight_engagement" in recovery_results
        
        # Check that the observed correlations are within a reasonable tolerance
        # of the target weights (allowing for sampling error in SEM)
        # The target weights are defined in constants.py
        psv_weights = get_psv_weights()
        target_engagement_weight = psv_weights.get("engagement", 0.0)
        
        observed_corr = recovery_results["observed_correlation_engagement"]
        target_corr = target_engagement_weight # Simplified check for correlation magnitude
        
        # We expect the observed correlation to be statistically significant
        # and reasonably close to the structural parameter.
        # Allow a tolerance of 0.15 due to measurement error and sampling variance
        tolerance = 0.15
        assert abs(observed_corr - target_corr) < tolerance, \
            f"Observed correlation {observed_corr:.4f} deviates too much from target {target_corr:.4f}"

        # Verify the significance level
        assert recovery_results.get("is_significant", False), \
            "The primary association should be statistically significant in synthetic data"

    def test_longitudinal_ordering(self):
        """Verify that timestamps are correctly ordered."""
        n_samples = 100
        df = generate_synthetic_data(n_samples=n_samples)
        
        # Convert to datetime if they aren't already (generator returns strings or objects)
        # Assuming generator returns datetime objects or comparable strings
        # If strings, we might need to parse, but generator usually handles this.
        # Checking the raw values first.
        
        # Ensure no engagement timestamp is after self-report timestamp
        # The generator should enforce this.
        # We check that for every row, engagement < self_report
        # If they are strings, convert to datetime
        try:
            eng_times = pd.to_datetime(df["timestamp_engagement"])
            report_times = pd.to_datetime(df["timestamp_self_report"])
            assert (eng_times < report_times).all(), \
                "Longitudinal ordering violation: engagement must precede self-report"
        except Exception:
            # If the generator returns numeric timestamps (e.g., seconds), compare directly
            assert (df["timestamp_engagement"] < df["timestamp_self_report"]).all(), \
                "Longitudinal ordering violation: engagement must precede self-report"

    def test_psv_calculation_convergence(self):
        """
        Verify that the derived PSV score converges to the formula defined in constants.
        """
        n_samples = 2000
        df = generate_synthetic_data(n_samples=n_samples)
        
        psv_weights = get_psv_weights()
        w_eng = psv_weights.get("engagement", 0.0)
        w_sent = psv_weights.get("sentiment", 0.0)
        
        # The PSV score should be a weighted combination of engagement and sentiment
        # We verify the correlation structure matches the weights
        # Correlation of PSV with Engagement should be high if w_eng is high
        corr_eng_psv = df["engagement_count"].corr(df["psv_score"])
        corr_sent_psv = df["comment_sentiment"].corr(df["psv_score"])
        
        # Both should be positive and significant
        assert corr_eng_psv > 0.3, "PSV should be positively correlated with engagement"
        assert corr_sent_psv > 0.3, "PSV should be positively correlated with sentiment"

    def test_verify_association_recovery_output(self):
        """
        Test that verify_association_recovery returns the expected dictionary structure.
        """
        n_samples = 500
        df = generate_synthetic_data(n_samples=n_samples)
        
        result = verify_association_recovery(df, n_samples)
        
        expected_keys = [
            "observed_correlation_engagement",
            "observed_correlation_psv",
            "target_psv_weight_engagement",
            "target_psv_weight_sentiment",
            "p_value_engagement",
            "is_significant",
            "sample_size"
        ]
        
        for key in expected_keys:
            assert key in result, f"Missing key in recovery results: {key}"
        
        assert result["sample_size"] == n_samples

