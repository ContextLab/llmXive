logger = get_logger(__name__)


def load_selection_frequency(file_path: Optional[str] = None) -> pd.DataFrame:
    """
    Loads the selection frequency CSV generated by T016.

    Args:
        file_path: Optional override for file path. Defaults to artifacts/reports/selection_frequency.csv.

    Returns:
        DataFrame with columns: feature_id, threshold, frequency.
    """
    if file_path is None:
        file_path = str(get_artifacts_path() / "reports" / "selection_frequency.csv")

    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Selection frequency file not found: {file_path}")

    df = pd.read_csv(file_path)
    required_cols = {'feature_id', 'threshold', 'frequency'}
    if not required_cols.issubset(df.columns):
        raise ValueError(f"Selection frequency file missing required columns. Found: {df.columns.tolist()}, Expected: {required_cols}")

    logger.info(f"Loaded selection frequency from {file_path} with {len(df)} rows")
    return df


def load_effect_sizes(file_path: Optional[str] = None) -> pd.DataFrame:
    """
    Loads the effect sizes CSV generated by T026.

    Args:
        file_path: Optional override for file path. Defaults to artifacts/reports/effect_sizes.csv.

    Returns:
        DataFrame with columns: feature_id, effect_size, modality.
    """
    if file_path is None:
        # Assuming effect sizes are saved in the same reports directory or processed data
        # Based on T026 description, it likely outputs to artifacts/reports or data/processed
        # We check common locations. T026 description says "calculate effect-size coefficients".
        # Let's assume it saves to artifacts/reports/effect_sizes.csv or similar.
        # If not found, we might need to look in data/processed.
        potential_paths = [
            str(get_artifacts_path() / "reports" / "effect_sizes.csv"),
            str(get_artifacts_path() / "reports" / "feature_effect_sizes.csv"),
            str(get_artifacts_path() / "processed" / "effect_sizes.csv")
        ]

        for path in potential_paths:
            if os.path.exists(path):
                file_path = path
                break

        if file_path is None and not any(os.path.exists(p) for p in potential_paths):
            # Fallback: try to infer from feature_selection.py if it saves there
            # If T026 hasn't run, this will fail, which is correct (fail loudly).
            raise FileNotFoundError(
                "Effect sizes file not found. Ensure T026 (feature_selection.py extension) has run. "
                "Searched in: " + ", ".join(potential_paths)
            )

    df = pd.read_csv(file_path)
    required_cols = {'feature_id', 'effect_size'}
    if not required_cols.issubset(df.columns):
        # Try to find a column with 'effect' in the name
        effect_cols = [c for c in df.columns if 'effect' in c.lower()]
        if effect_cols:
            df = df.rename(columns={effect_cols[0]: 'effect_size'})
        else:
            raise ValueError(f"Effect sizes file missing 'effect_size' column. Found: {df.columns.tolist()}")

    # Ensure modality exists, default to 'unknown' if missing
    if 'modality' not in df.columns:
        logger.warning("Effect sizes file missing 'modality' column. Assuming 'unknown'.")
        df['modality'] = 'unknown'

    logger.info(f"Loaded effect sizes from {file_path} with {len(df)} rows")
    return df


def calculate_aggregated_metrics(freq_df: pd.DataFrame, threshold: float = 0.5) -> pd.DataFrame:
    """
    Aggregates selection frequency data to determine the final selection frequency
    for each feature across thresholds, or for a specific threshold.

    Args:
        freq_df: DataFrame from load_selection_frequency.
        threshold: The frequency threshold to consider a feature "selected".

    Returns:
        DataFrame with feature_id and aggregated selection frequency (max or mean across thresholds).
        We will use the MAX frequency across thresholds for the final report as per "intersection" logic in T028b context,
        but for the report, we usually want the frequency at the most stringent threshold or the overall stability.
        Let's calculate the mean frequency across all thresholds for robustness.
    """
    # Group by feature_id and calculate mean frequency across thresholds
    # This gives a stability score.
    agg_df = freq_df.groupby('feature_id')['frequency'].mean().reset_index()
    agg_df.rename(columns={'frequency': 'mean_frequency'}, inplace=True)

    # Also get max frequency
    max_df = freq_df.groupby('feature_id')['frequency'].max().reset_index()
    max_df.rename(columns={'frequency': 'max_frequency'}, inplace=True)

    result = agg_df.merge(max_df, on='feature_id')
    return result


def apply_significance_filter(freq_df: pd.DataFrame, effect_df: pd.DataFrame, p_value_threshold: float = 0.05) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Filters features based on selection frequency and calculates BH-adjusted p-values.

    This function assumes that effect_df contains raw p-values or will calculate them
    if the model provides them. However, the task description for T027 says "p-values and effect sizes".
    T026 calculates effect sizes. T012 has BH correction.
    We need a source of raw p-values. If the modeling step (T017) didn't output p-values directly,
    we might need to approximate or assume the 'effect_size' is significant enough if frequency is high.
    BUT, the task explicitly asks for p-values.
    Let's assume the `effect_sizes.csv` from T026 includes a `p_value` column if available,
    or we calculate them if we have the model coefficients and standard errors (not available here).
    Alternative: Use the selection frequency as a proxy for significance if p-values are not available,
    but the task requires p-values.

    Let's check the API surface of T026 again: "calculate effect-size coefficients".
    If T026 doesn't output p-values, we must generate them or fail.
    However, in many pipelines, p-values come from the model summary (e.g., linear regression).
    If we are using ElasticNet or GradientBoosting, standard p-values are not directly available.
    We might need to perform a t-test or use permutation p-values for features.
    Given the constraints, let's assume the `effect_sizes.csv` contains a `p_value` column.
    If not, we will generate a placeholder or raise an error.
    Actually, T012 provides `benjamini_hochberg`. We need raw p-values to apply it.
    Let's assume the modeling step saved `model_p_values.csv` or similar.
    If not, we will try to derive from effect sizes if standard errors are present.

    For this implementation, we will look for a `p_value` column in `effect_df`.
    If missing, we will raise an error stating that p-values are required for T027.
    """
    if 'p_value' not in effect_df.columns:
        # Try to find a column with 'pvalue' or 'p_val'
        p_cols = [c for c in effect_df.columns if 'pval' in c.lower() or 'p_value' in c.lower()]
        if p_cols:
            effect_df = effect_df.rename(columns={p_cols[0]: 'p_value'})
        else:
            raise ValueError(
                "Effect sizes file must contain a 'p_value' column to apply significance filtering. "
                "T026 must be updated to output p-values (e.g., from model summary or permutation)."
            )

    # Apply Benjamini-Hochberg correction
    # Sort by p-value
    effect_df = effect_df.sort_values('p_value').reset_index(drop=True)
    effect_df['adj_p_value'] = benjamini_hochberg(effect_df['p_value'].values)

    # Filter by adjusted p-value
    significant_features = effect_df[effect_df['adj_p_value'] <= p_value_threshold]

    logger.info(f"Found {len(significant_features)} significant features at adj_p <= {p_value_threshold}")

    return significant_features, effect_df


def rank_and_sort(features_df: pd.DataFrame, freq_df: pd.DataFrame) -> pd.DataFrame:
    """
    Ranks features based on selection frequency and effect size magnitude.

    Args:
        features_df: DataFrame of significant features with effect sizes and p-values.
        freq_df: DataFrame of selection frequencies.

    Returns:
        Ranked DataFrame.
    """
    # Merge with frequency data
    ranked_df = features_df.merge(freq_df, on='feature_id', how='left')

    # Fill missing frequencies with 0
    ranked_df['mean_frequency'] = ranked_df['mean_frequency'].fillna(0)
    ranked_df['max_frequency'] = ranked_df['max_frequency'].fillna(0)

    # Sort by selection frequency (descending) and then by effect size magnitude (descending)
    # We use mean_frequency as the primary stability metric
    ranked_df['abs_effect'] = ranked_df['effect_size'].abs()
    ranked_df = ranked_df.sort_values(
        by=['mean_frequency', 'abs_effect'],
        ascending=[False, False]
    ).reset_index(drop=True)

    # Add rank column
    ranked_df['rank'] = range(1, len(ranked_df) + 1)

    logger.info(f"Ranked {len(ranked_df)} features")
    return ranked_df


def generate_biomarker_report(output_path: Optional[str] = None) -> str:
    """
    Main function to generate the top_features.csv report.

    Steps:
    1. Load selection frequency.
    2. Load effect sizes (and p-values).
    3. Apply significance filter (BH-adjusted p < 0.05).
    4. Rank features by frequency and effect size.
    5. Save to CSV.

    Args:
        output_path: Optional override for output path.

    Returns:
        Path to the generated report.
    """
    if output_path is None:
        output_path = str(get_artifacts_path() / "reports" / "top_features.csv")

    # Ensure output directory exists
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    logger.info("Starting biomarker report generation...")

    # 1. Load data
    freq_df = load_selection_frequency()
    effect_df = load_effect_sizes()

    # 2. Aggregate frequency metrics
    agg_freq = calculate_aggregated_metrics(freq_df)

    # 3. Apply significance filter (requires p-values in effect_df)
    try:
        significant_features, _ = apply_significance_filter(freq_df, effect_df, p_value_threshold=0.05)
    except ValueError as e:
        logger.error(f"Significance filtering failed: {e}")
        raise

    # 4. Merge with aggregated frequency
    final_df = significant_features.merge(agg_freq, on='feature_id', how='left')

    # 5. Rank and sort
    ranked_df = rank_and_sort(final_df, agg_freq)

    # 6. Select columns for output
    output_cols = [
        'rank', 'feature_id', 'modality', 'effect_size',
        'p_value', 'adj_p_value', 'mean_frequency', 'max_frequency'
    ]
    # Ensure all columns exist
    available_cols = [c for c in output_cols if c in ranked_df.columns]
    # Add any missing columns with default values if necessary, but ideally they exist
    for col in output_cols:
        if col not in ranked_df.columns:
            if col == 'modality':
                ranked_df[col] = 'unknown'
            elif col in ['p_value', 'adj_p_value']:
                ranked_df[col] = np.nan
            elif col in ['mean_frequency', 'max_frequency']:
                ranked_df[col] = 0.0

    final_output = ranked_df[output_cols]

    # 7. Save to CSV
    final_output.to_csv(output_path, index=False)
    logger.info(f"Biomarker report saved to {output_path}")

    return output_path


def main():
    """
    Entry point for the biomarker report generation.
    """
    logger.info("Running biomarker report generation pipeline...")
    try:
        output_file = generate_biomarker_report()
        logger.info(f"SUCCESS: Report generated at {output_file}")
    except FileNotFoundError as e:
        logger.error(f"DATA MISSING: {e}")
        raise
    except ValueError as e:
        logger.error(f"DATA INVALID: {e}")
        raise
    except Exception as e:
        logger.error(f"ERROR: {e}")
        raise


if __name__ == "__main__":
    main()