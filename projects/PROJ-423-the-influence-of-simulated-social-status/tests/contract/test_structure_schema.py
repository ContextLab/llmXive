"""
Contract tests for structure_config.json schema validation.
Validates that T020a's output matches contracts/structure_schema.yaml.
"""
import json
import os
import pytest
import yaml
from pathlib import Path

# Ensure we can import from the code directory
CODE_DIR = Path(__file__).parent.parent.parent / "code"
CONTRACTS_DIR = Path(__file__).parent.parent.parent / "contracts"
DATA_DIR = Path(__file__).parent.parent.parent / "data" / "processed"

SCHEMA_PATH = CONTRACTS_DIR / "structure_schema.yaml"
CONFIG_PATH = DATA_DIR / "structure_config.json"

@pytest.fixture
def schema():
    """Load the JSON schema from the YAML file."""
    if not SCHEMA_PATH.exists():
        pytest.fail(f"Schema file not found: {SCHEMA_PATH}")
    with open(SCHEMA_PATH, "r") as f:
        return yaml.safe_load(f)

@pytest.fixture
def config_data():
    """Load the actual structure_config.json generated by T020a."""
    if not CONFIG_PATH.exists():
        pytest.fail(f"Config file not found: {CONFIG_PATH}. Run T020a first.")
    with open(CONFIG_PATH, "r") as f:
        return json.load(f)

def test_schema_file_exists(schema):
    """Verify the schema file is valid YAML and loads correctly."""
    assert schema is not None
    assert "properties" in schema
    assert "required" in schema

def test_required_keys_present(config_data, schema):
    """Verify all required keys are present in the config."""
    required_keys = schema.get("required", [])
    for key in required_keys:
        assert key in config_data, f"Missing required key: {key}"

def test_type_is_valid_string_and_enum(config_data):
    """Verify 'type' is a string and matches allowed enum values."""
    assert "type" in config_data
    assert isinstance(config_data["type"], str)
    allowed_types = schema["properties"]["type"]["enum"]
    assert config_data["type"] in allowed_types, \
        f"Invalid type '{config_data['type']}'. Must be one of {allowed_types}"

def test_n_subjects_is_integer(config_data):
    """Verify 'n_subjects' is an integer."""
    assert "n_subjects" in config_data
    assert isinstance(config_data["n_subjects"], int)
    assert config_data["n_subjects"] >= 1

def test_model_type_is_valid_string_and_enum(config_data):
    """Verify 'model_type' is a string and matches allowed enum values."""
    assert "model_type" in config_data
    assert isinstance(config_data["model_type"], str)
    allowed_models = schema["properties"]["model_type"]["enum"]
    assert config_data["model_type"] in allowed_models, \
        f"Invalid model_type '{config_data['model_type']}'. Must be one of {allowed_models}"

def test_no_additional_properties(config_data, schema):
    """Verify the config does not contain properties not defined in the schema."""
    allowed_keys = set(schema["properties"].keys())
    actual_keys = set(config_data.keys())
    extra_keys = actual_keys - allowed_keys
    assert len(extra_keys) == 0, f"Schema violation: Extra keys found: {extra_keys}"

def test_semantic_consistency(config_data):
    """
    Verify semantic consistency between 'type' and 'model_type'.
    - within-subjects should map to mixed_effects
    - between-subjects should map to fixed_effects
    """
    type_val = config_data.get("type")
    model_val = config_data.get("model_type")

    if type_val == "within-subjects":
        assert model_val == "mixed_effects", \
            "Semantic error: within-subjects data must use mixed_effects model."
    elif type_val == "between-subjects":
        assert model_val == "fixed_effects", \
            "Semantic error: between-subjects data must use fixed_effects model."