"""
Data Ingestion Module for the Metaphorical Framing Experiment.

This module handles the loading of vignette templates from the raw data directory
and real participant survey data. It adheres to the project's schema contracts
and implements strict validation to ensure data integrity.
"""

import json
import os
import csv
from typing import List, Dict, Any, Optional
from datetime import datetime


class DataIngestionError(Exception):
    """Custom exception for data ingestion failures."""
    pass


def load_vignette_templates(raw_data_dir: str = "data/raw/vignettes") -> Dict[str, str]:
    """
    Loads vignette text templates for the three experimental conditions.

    Expected file structure:
    - data/raw/vignettes/battle_vignette.txt
    - data/raw/vignettes/journey_vignette.txt
    - data/raw/vignettes/medical_vignette.txt

    Args:
        raw_data_dir: Path to the directory containing vignette text files.

    Returns:
        A dictionary mapping condition names ('battle', 'journey', 'medical')
        to their respective vignette text strings.

    Raises:
        DataIngestionError: If the directory is missing, files are missing,
        or files are empty.
    """
    if not os.path.exists(raw_data_dir):
        raise DataIngestionError(
            f"Vignette directory not found: {raw_data_dir}. "
            "Please ensure the directory structure exists and contains the required .txt files."
        )

    conditions = ["battle", "journey", "medical"]
    templates = {}

    for condition in conditions:
        file_path = os.path.join(raw_data_dir, f"{condition}_vignette.txt")
        
        if not os.path.exists(file_path):
            raise DataIngestionError(
                f"Missing vignette file for condition '{condition}': {file_path}"
            )

        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                text = f.read().strip()
            
            if not text:
                raise DataIngestionError(
                    f"Vignette file for condition '{condition}' is empty: {file_path}"
                )
            
            templates[condition] = text
        
        except IOError as e:
            raise DataIngestionError(f"Error reading vignette file {file_path}: {e}")

    return templates


def load_real_participant_data(json_path: str = "data/raw/survey_responses.json") -> List[Dict[str, Any]]:
    """
    Loads real participant data from a JSON file generated by the survey interface.

    Expected schema:
    [
      {
        "participant_id": "uuid-string",
        "condition": "battle|journey|medical",
        "timestamp": "ISO-8601-string",
        "raw_responses": {
          "cami_1": 1,
          "cami_2": 2,
          ...
          "help_seeking": 5
        }
      },
      ...
    ]

    Args:
        json_path: Path to the JSON file containing survey responses.

    Returns:
        A list of dictionaries, each representing a participant's response data.

    Raises:
        DataIngestionError: If the file is missing, invalid JSON, or schema validation fails.
    """
    if not os.path.exists(json_path):
        raise DataIngestionError(
            f"Survey response file not found: {json_path}. "
            "Ensure participants have completed the survey or run the survey simulation."
        )

    try:
        with open(json_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
    except json.JSONDecodeError as e:
        raise DataIngestionError(f"Invalid JSON in survey response file: {e}")
    
    if not isinstance(data, list):
        raise DataIngestionError(
            "Expected survey responses to be a JSON list of participant objects."
        )

    if len(data) == 0:
        raise DataIngestionError("Survey response file is empty. No data to process.")

    # Basic schema validation
    required_keys = {"participant_id", "condition", "raw_responses"}
    for i, record in enumerate(data):
        if not isinstance(record, dict):
            raise DataIngestionError(f"Record at index {i} is not a dictionary.")
        
        missing_keys = required_keys - set(record.keys())
        if missing_keys:
            raise DataIngestionError(
                f"Record at index {i} missing required keys: {missing_keys}"
            )
        
        if record["condition"] not in ["battle", "journey", "medical"]:
            raise DataIngestionError(
                f"Record at index {i} has invalid condition: {record['condition']}"
            )

    return data


def load_assignments(csv_path: str = "data/processed/experimental_assignments.csv") -> List[Dict[str, Any]]:
    """
    Loads experimental assignments from a CSV file.

    Expected schema:
    participant_id, condition, assignment_timestamp

    Args:
        csv_path: Path to the CSV file containing assignments.

    Returns:
        A list of dictionaries representing assignment records.

    Raises:
        DataIngestionError: If the file is missing or invalid.
    """
    if not os.path.exists(csv_path):
        raise DataIngestionError(
            f"Experimental assignments file not found: {csv_path}. "
            "Run the experiment runner first to generate assignments."
        )

    assignments = []
    try:
        with open(csv_path, 'r', encoding='utf-8') as f:
            reader = csv.DictReader(f)
            for row in reader:
                assignments.append(row)
    except Exception as e:
        raise DataIngestionError(f"Error reading assignments file: {e}")

    if not assignments:
        raise DataIngestionError("No assignments found in the CSV file.")

    return assignments


def main():
    """
    CLI entry point for testing data ingestion capabilities.
    """
    import argparse

    parser = argparse.ArgumentParser(description="Data Ingestion Module CLI")
    parser.add_argument(
        "--mode",
        choices=["vignettes", "participants", "assignments"],
        required=True,
        help="Which data source to load and validate."
    )
    parser.add_argument(
        "--vignette-dir",
        default="data/raw/vignettes",
        help="Path to vignette templates."
    )
    parser.add_argument(
        "--survey-json",
        default="data/raw/survey_responses.json",
        help="Path to survey responses."
    )
    parser.add_argument(
        "--assignments-csv",
        default="data/processed/experimental_assignments.csv",
        help="Path to assignments file."
    )

    args = parser.parse_args()

    try:
        if args.mode == "vignettes":
            templates = load_vignette_templates(args.vignette_dir)
            print(f"Successfully loaded {len(templates)} vignette templates.")
            for cond, text in templates.items():
                print(f"  - {cond}: {len(text)} chars")
        
        elif args.mode == "participants":
            data = load_real_participant_data(args.survey_json)
            print(f"Successfully loaded {len(data)} participant records.")
            # Show first record summary
            if data:
                print(f"  Sample ID: {data[0]['participant_id']}")
                print(f"  Sample Condition: {data[0]['condition']}")

        elif args.mode == "assignments":
            assignments = load_assignments(args.assignments_csv)
            print(f"Successfully loaded {len(assignments)} assignment records.")
            if assignments:
                print(f"  Sample ID: {assignments[0].get('participant_id')}")
                print(f"  Sample Condition: {assignments[0].get('condition')}")

        print("Data ingestion validation PASSED.")

    except DataIngestionError as e:
        print(f"Data Ingestion Error: {e}")
        exit(1)
    except Exception as e:
        print(f"Unexpected Error: {e}")
        exit(1)


if __name__ == "__main__":
    main()