"""
Serialization module for stimulus complexity metrics.

Reads raw complexity scores, applies categorization logic, and saves
the final processed CSV file.
"""
import os
import logging
import pandas as pd
from pathlib import Path
from typing import List, Dict, Any, Optional
from config import get_project_root, get_data_path

logger = logging.getLogger(__name__)

def load_raw_complexity_scores(raw_path: Optional[str] = None) -> pd.DataFrame:
    """
    Load the raw complexity scores CSV generated by T017a.
    
    Args:
        raw_path: Optional path to the raw CSV. If None, uses default path.
    
    Returns:
        DataFrame with columns: filename, edge_density, entropy, fractal_dim, status
    
    Raises:
        FileNotFoundError: If the raw CSV does not exist.
        ValueError: If required columns are missing.
    """
    if raw_path is None:
        data_root = get_data_path()
        raw_path = os.path.join(data_root, "processed", "complexity_scores_raw.csv")
    
    path_obj = Path(raw_path)
    if not path_obj.exists():
        raise FileNotFoundError(f"Raw complexity scores file not found at: {raw_path}")
    
    df = pd.read_csv(path_obj)
    
    required_cols = {"filename", "edge_density", "entropy", "fractal_dim", "status"}
    if not required_cols.issubset(df.columns):
        missing = required_cols - set(df.columns)
        raise ValueError(f"Raw CSV missing required columns: {missing}")
    
    logger.info(f"Loaded {len(df)} rows from {raw_path}")
    return df

def apply_categorization(df: pd.DataFrame) -> pd.DataFrame:
    """
    Apply complexity categorization logic to the DataFrame.
    
    Logic (from T018):
      - Calculate median of the complexity score (using edge_density as the primary metric).
      - Map scores <= median to 'Low' complexity.
      - Map scores > median to 'High' complexity.
      - Skipped images (status='skipped') are assigned 'N/A' or kept as 'Low' depending on 
        interpretation, but typically excluded from analysis. Here we assign 'N/A' to skipped.
    
    Args:
        df: DataFrame with raw metrics.
    
    Returns:
        DataFrame with added 'complexity_category' column.
    """
    if df.empty:
        logger.warning("Empty DataFrame provided to categorization.")
        df['complexity_category'] = 'N/A'
        return df

    # Create a copy to avoid SettingWithCopyWarning
    result_df = df.copy()

    # Filter valid images for median calculation
    valid_mask = result_df['status'] == 'valid'
    if not valid_mask.any():
        logger.warning("No valid images found for median calculation.")
        result_df['complexity_category'] = 'N/A'
        return result_df

    # Calculate median of edge_density for valid images
    median_score = result_df.loc[valid_mask, 'edge_density'].median()
    logger.info(f"Calculated median complexity threshold (edge_density): {median_score:.6f}")
    
    # Log the threshold to a file for reproducibility (T018 requirement)
    log_root = get_project_root() / "logs"
    log_root.mkdir(parents=True, exist_ok=True)
    log_file = log_root / "categorization_threshold.log"
    with open(log_file, "w") as f:
        f.write(f"Median Complexity Threshold (edge_density): {median_score}\n")
        f.write(f"Timestamp: {pd.Timestamp.now()}\n")
        f.write(f"Source file: complexity_scores_raw.csv\n")
    
    # Apply categorization
    def categorize(row):
        if row['status'] != 'valid':
            return 'N/A'
        if row['edge_density'] <= median_score:
            return 'Low'
        else:
            return 'High'

    result_df['complexity_category'] = result_df.apply(categorize, axis=1)
    
    logger.info(f"Categorization complete. Distribution: {result_df['complexity_category'].value_counts().to_dict()}")
    return result_df

def save_final_csv(df: pd.DataFrame, output_path: Optional[str] = None) -> str:
    """
    Save the final processed CSV with complexity categories.
    
    Args:
        df: DataFrame with categorization applied.
        output_path: Optional output path. If None, uses default path.
    
    Returns:
        Path to the saved file.
    
    Raises:
        ValueError: If required columns are missing.
    """
    if output_path is None:
        data_root = get_data_path()
        output_path = os.path.join(data_root, "processed", "complexity_scores.csv")
    
    required_cols = {"filename", "edge_density", "entropy", "fractal_dim", "complexity_category", "status"}
    if not required_cols.issubset(df.columns):
        missing = required_cols - set(df.columns)
        raise ValueError(f"DataFrame missing required columns for final output: {missing}")
    
    # Ensure output directory exists
    output_dir = os.path.dirname(output_path)
    os.makedirs(output_dir, exist_ok=True)
    
    # Save to CSV
    df.to_csv(output_path, index=False)
    logger.info(f"Saved final complexity scores to: {output_path}")
    
    return output_path

def main():
    """
    Main entry point for T017c: CSV serialization and categorization.
    
    Reads complexity_scores_raw.csv, applies categorization, and writes
    complexity_scores.csv.
    """
    # Setup logging if not already done
    log_level = os.getenv("LOG_LEVEL", "INFO").upper()
    logging.basicConfig(
        level=getattr(logging, log_level),
        format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
        handlers=[
            logging.StreamHandler(),
            logging.FileHandler(os.path.join(get_project_root(), "logs", "app.log"))
        ]
    )
    
    logger.info("Starting T017c: CSV Serialization and Categorization")
    
    try:
        # 1. Load raw scores
        raw_df = load_raw_complexity_scores()
        
        # 2. Apply categorization
        final_df = apply_categorization(raw_df)
        
        # 3. Save final CSV
        output_file = save_final_csv(final_df)
        
        logger.info(f"T017c completed successfully. Output: {output_file}")
        
        # Verify output
        if os.path.exists(output_file):
            logger.info(f"Verification: Output file exists at {output_file}")
        else:
            raise RuntimeError("Output file verification failed: file does not exist.")
            
    except FileNotFoundError as e:
        logger.error(f"Input file not found: {e}")
        raise
    except ValueError as e:
        logger.error(f"Data validation error: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during serialization: {e}")
        raise

if __name__ == "__main__":
    main()