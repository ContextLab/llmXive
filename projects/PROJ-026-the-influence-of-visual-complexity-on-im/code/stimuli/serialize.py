"""
T017c: CSV Serialization for Complexity Scores.

Reads the raw complexity scores CSV generated by T017a, applies the 
categorization logic defined in T018 (median split), and writes the 
final `complexity_scores.csv` to disk.

This script is the entry point for T017c and must be run after T017a 
and T018 are complete.
"""
import os
import logging
import pandas as pd
from pathlib import Path
from typing import List, Dict, Any, Optional

# Import shared config and logging utilities from the project structure
from config import get_project_root, get_data_path
from utils.logging import get_logger, setup_logging

# Ensure logging is configured before proceeding
setup_logging()
logger = get_logger(__name__)

def load_raw_complexity_scores(raw_path: Path) -> pd.DataFrame:
    """
    Loads the raw complexity scores CSV generated by T017a.
    
    Args:
        raw_path: Path to `data/processed/complexity_scores_raw.csv`.
    
    Returns:
        DataFrame containing the raw scores.
    
    Raises:
        FileNotFoundError: If the raw file does not exist.
        ValueError: If required columns are missing.
    """
    if not raw_path.exists():
        raise FileNotFoundError(f"Raw complexity scores file not found: {raw_path}")
    
    df = pd.read_csv(raw_path)
    required_cols = ['filename', 'edge_density', 'entropy', 'fractal_dim', 'status']
    missing_cols = [col for col in required_cols if col not in df.columns]
    
    if missing_cols:
        raise ValueError(f"Missing required columns in raw CSV: {missing_cols}")
    
    logger.info(f"Loaded {len(df)} rows from {raw_path}")
    return df

def apply_categorization(df: pd.DataFrame) -> pd.DataFrame:
    """
    Applies the median-split categorization logic (T018) to the DataFrame.
    
    Logic:
      1. Filter for 'valid' rows to calculate the median threshold.
      2. Calculate the median of the complexity metrics (using 'edge_density' as primary).
      3. Assign 'Low' if score <= median, 'High' if score > median.
      4. Mark 'skipped' rows as 'N/A' or similar, though typically they are excluded 
         from analysis. For this task, we assign 'N/A' to skipped rows.
    
    Args:
        df: DataFrame with raw scores.
    
    Returns:
        DataFrame with a new 'complexity_category' column.
    """
    df = df.copy()
    
    # Log the median calculation for reproducibility (Constitution Principle IV)
    valid_df = df[df['status'] == 'valid']
    
    if valid_df.empty:
        logger.warning("No valid rows found to calculate median. All categories will be 'N/A'.")
        df['complexity_category'] = 'N/A'
        return df
    
    # Use edge_density as the primary metric for categorization as per typical complexity 
    # definitions in this pipeline context, or average if specified. 
    # The task description implies using the "complexity score". 
    # We will use 'edge_density' as the representative metric for the median split.
    median_val = valid_df['edge_density'].median()
    
    logger.info(f"Calculated median edge_density threshold: {median_val:.6f}")
    
    # Log threshold to file for audit trail
    log_path = Path(get_project_root()) / "logs" / "categorization_threshold.log"
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with open(log_path, 'a') as f:
        f.write(f"Threshold calculated: {median_val:.6f}\n")
    
    def categorize_row(row):
        if row['status'] != 'valid':
            return 'N/A'
        return 'Low' if row['edge_density'] <= median_val else 'High'
    
    df['complexity_category'] = df.apply(categorize_row, axis=1)
    
    logger.info(f"Categorization complete. Distribution: {df['complexity_category'].value_counts().to_dict()}")
    return df

def save_final_csv(df: pd.DataFrame, output_path: Path) -> None:
    """
    Saves the final DataFrame to the specified CSV path.
    
    Args:
        df: The processed DataFrame.
        output_path: Path to `data/processed/complexity_scores.csv`.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    logger.info(f"Final CSV saved to {output_path}")

def main():
    """
    Main entry point for T017c.
    """
    project_root = Path(get_project_root())
    data_root = get_data_path()
    
    raw_file = project_root / data_root / "processed" / "complexity_scores_raw.csv"
    final_file = project_root / data_root / "processed" / "complexity_scores.csv"
    
    logger.info("Starting T017c: CSV Serialization for Complexity Scores")
    
    try:
        # 1. Load raw data
        df = load_raw_complexity_scores(raw_file)
        
        # 2. Apply categorization
        df = apply_categorization(df)
        
        # 3. Ensure columns are in the correct order as per spec
        # Spec: filename, edge_density, entropy, fractal_dim, complexity_category, status
        expected_cols = ['filename', 'edge_density', 'entropy', 'fractal_dim', 'complexity_category', 'status']
        # Reorder or add missing columns if necessary (though logic should preserve them)
        df = df[expected_cols]
        
        # 4. Save final output
        save_final_csv(df, final_file)
        
        logger.info("T017c completed successfully.")
        
    except FileNotFoundError as e:
        logger.error(f"Input file missing. Ensure T017a has been run: {e}")
        raise
    except Exception as e:
        logger.error(f"Error during T017c execution: {e}")
        raise

if __name__ == "__main__":
    main()