"""
Helper script to execute ruff and black checks against the codebase.
This script is generated by setup_linting.py but provided here for immediate use.
"""
import subprocess
import sys
from pathlib import Path

def run_command(cmd: list[str], description: str) -> bool:
    print(f"Running: {description}")
    print(f"Command: {' '.join(cmd)}")
    try:
        result = subprocess.run(cmd, check=True, capture_output=True, text=True)
        if result.stdout:
            print(result.stdout)
        if result.stderr:
            print(result.stderr)
        print(f"✓ {description} passed")
        return True
    except subprocess.CalledProcessError as e:
        print(f"✗ {description} failed")
        if e.stdout:
            print(e.stdout)
        if e.stderr:
            print(e.stderr)
        return False

def main():
    root = Path(__file__).parent.parent
    code_dir = root / "code"
    
    # Check if tools are installed
    try:
        import ruff
        import black
    except ImportError:
        print("Error: 'ruff' or 'black' not installed. Please run: pip install ruff black")
        sys.exit(1)

    success = True

    # Run Ruff Check (Linting)
    success &= run_command(
        [sys.executable, "-m", "ruff", "check", str(code_dir)],
        "Ruff Check"
    )

    # Run Black Check (Formatting - check only, no write)
    success &= run_command(
        [sys.executable, "-m", "black", "--check", "--diff", str(code_dir)],
        "Black Check"
    )

    if success:
        print("\nAll linting and formatting checks passed.")
        sys.exit(0)
    else:
        print("\nSome checks failed.")
        sys.exit(1)

if __name__ == "__main__":
    main()