"""
Verification script for T032: Ensure stats_report.json contains required fields.

This script validates that the statistical report generated by run_stats.py
contains the mandatory fields: p-value, t-statistic, Cohen's d, and 95% CI.
"""
import os
import sys
import json
import argparse

# Add project root to path for imports
project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
if project_root not in sys.path:
    sys.path.insert(0, project_root)

REQUIRED_FIELDS = {
    'p_value': 'p-value',
    't_statistic': 't-statistic',
    'cohens_d': "Cohen's d",
    'ci_95_lower': '95% CI lower',
    'ci_95_upper': '95% CI upper'
}

def verify_report(report_path: str) -> bool:
    """
    Verify that the stats report contains all required statistical fields.
    
    Args:
        report_path: Path to the stats_report.json file
        
    Returns:
        True if all required fields are present and valid, False otherwise
    """
    if not os.path.exists(report_path):
        print(f"ERROR: Report file not found: {report_path}")
        return False

    try:
        with open(report_path, 'r') as f:
            report = json.load(f)
    except json.JSONDecodeError as e:
        print(f"ERROR: Invalid JSON in report file: {e}")
        return False

    missing_fields = []
    invalid_fields = []

    # Check for required fields
    for key, display_name in REQUIRED_FIELDS.items():
        if key not in report:
            missing_fields.append(display_name)
        else:
            value = report[key]
            # Verify the value is a number
            if not isinstance(value, (int, float)):
                invalid_fields.append(f"{display_name} (expected number, got {type(value).__name__})")

    if missing_fields:
        print(f"ERROR: Missing required fields: {', '.join(missing_fields)}")
        return False

    if invalid_fields:
        print(f"ERROR: Invalid field values: {', '.join(invalid_fields)}")
        return False

    # Additional validation: p-value should be in [0, 1]
    if not (0 <= report['p_value'] <= 1):
        print(f"ERROR: p-value {report['p_value']} is not in range [0, 1]")
        return False

    print("SUCCESS: stats_report.json contains all required fields:")
    print(f"  - p-value: {report['p_value']}")
    print(f"  - t-statistic: {report['t_statistic']}")
    print(f"  - Cohen's d: {report['cohens_d']}")
    print(f"  - 95% CI: [{report['ci_95_lower']}, {report['ci_95_upper']}]")
    return True

def main():
    parser = argparse.ArgumentParser(
        description='Verify stats_report.json contains required statistical fields'
    )
    parser.add_argument(
        '--report-path',
        type=str,
        default='projects/PROJ-594-quantum-cognition-in-llms-superposition/data/results/stats_report.json',
        help='Path to the stats report JSON file'
    )
    args = parser.parse_args()

    success = verify_report(args.report_path)
    sys.exit(0 if success else 1)

if __name__ == '__main__':
    main()
