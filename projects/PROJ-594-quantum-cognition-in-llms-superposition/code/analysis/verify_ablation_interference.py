"""
T038: Verify that interference cross-term assumption (negative values for ambiguity) holds in ablation results.

This script loads the ablation metrics generated by T037 (ablation_metrics.json)
and the interference validation data (if available) to verify the core hypothesis:
that the interference cross-term is negatively correlated with ambiguity scores.

It outputs a verification report to data/results/ablation_interference_verification.json.
"""
import os
import sys
import json
import argparse
import torch
import numpy as np
from scipy.stats import spearmanr

# Ensure project root is in path
PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from utils.logging import detect_nan_inf

def load_ablation_metrics(path: str) -> dict:
    """Load the ablation metrics JSON file."""
    if not os.path.exists(path):
        raise FileNotFoundError(f"Ablation metrics file not found: {path}")
    with open(path, 'r') as f:
        return json.load(f)

def verify_cross_term_assumption(ablation_data: dict) -> dict:
    """
    Verify the assumption that interference cross-term values are negative for ambiguous inputs.
    
    The ablation_metrics.json should contain a section 'interference_validation' or similar
    that includes cross_term values and ambiguity scores.
    
    Returns a dictionary with verification results.
    """
    results = {
        "assumption_verified": False,
        "details": {},
        "statistics": {}
    }

    # Check if interference validation data exists
    if "interference_validation" not in ablation_data:
        results["details"]["error"] = "No interference_validation data found in ablation_metrics.json"
        return results

    validation_data = ablation_data["interference_validation"]
    
    # Extract cross_term values and ambiguity scores
    cross_terms = validation_data.get("cross_term_values", [])
    ambiguity_scores = validation_data.get("ambiguity_scores", [])

    if not cross_terms or not ambiguity_scores:
        results["details"]["error"] = "Missing cross_term_values or ambiguity_scores in validation data"
        return results

    # Convert to numpy arrays
    cross_terms = np.array(cross_terms)
    ambiguity_scores = np.array(ambiguity_scores)

    # Check for NaN/Inf
    if detect_nan_inf(torch.tensor(cross_terms)):
        results["details"]["warning"] = "NaN or Inf detected in cross_term values"
    
    if detect_nan_inf(torch.tensor(ambiguity_scores)):
        results["details"]["warning"] = "NaN or Inf detected in ambiguity scores"

    # 1. Check if cross-terms are negative for high ambiguity samples
    # Define "high ambiguity" as scores > 0.5 (assuming normalized 0-1 scale)
    high_ambiguity_mask = ambiguity_scores > 0.5
    if np.any(high_ambiguity_mask):
        high_ambiguity_cross_terms = cross_terms[high_ambiguity_mask]
        negative_ratio = np.mean(high_ambiguity_cross_terms < 0)
        
        results["statistics"]["high_ambiguity_negative_ratio"] = float(negative_ratio)
        results["statistics"]["high_ambiguity_mean_cross_term"] = float(np.mean(high_ambiguity_cross_terms))
        
        # Assumption: At least 80% of high-ambiguity samples should have negative cross-terms
        if negative_ratio >= 0.8:
            results["assumption_verified"] = True
            results["details"]["high_ambiguity_check"] = f"PASS: {negative_ratio:.2%} of high-ambiguity samples have negative cross-terms"
        else:
            results["details"]["high_ambiguity_check"] = f"FAIL: Only {negative_ratio:.2%} of high-ambiguity samples have negative cross-terms"
    else:
        results["details"]["error"] = "No high-ambiguity samples found in data"

    # 2. Check Spearman correlation between ambiguity and cross-term
    # Expect negative correlation: higher ambiguity -> more negative cross-term
    if len(cross_terms) > 1:
        corr, p_value = spearmanr(ambiguity_scores, cross_terms)
        results["statistics"]["spearman_correlation"] = float(corr)
        results["statistics"]["spearman_p_value"] = float(p_value)
        
        if corr < 0 and p_value < 0.05:
            results["details"]["correlation_check"] = f"PASS: Significant negative correlation (r={corr:.3f}, p={p_value:.3f})"
            if not results["assumption_verified"]:
                results["assumption_verified"] = True
        elif corr < 0:
            results["details"]["correlation_check"] = f"INFO: Negative correlation (r={corr:.3f}) but not statistically significant (p={p_value:.3f})"
        else:
            results["details"]["correlation_check"] = f"FAIL: Positive or zero correlation (r={corr:.3f})"

    # 3. Summary statistics
    results["statistics"]["total_samples"] = len(cross_terms)
    results["statistics"]["cross_term_mean"] = float(np.mean(cross_terms))
    results["statistics"]["cross_term_std"] = float(np.std(cross_terms))
    results["statistics"]["cross_term_min"] = float(np.min(cross_terms))
    results["statistics"]["cross_term_max"] = float(np.max(cross_terms))

    return results

def save_results(results: dict, output_path: str):
    """Save the verification results to a JSON file."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    print(f"Verification results saved to: {output_path}")

def main():
    parser = argparse.ArgumentParser(description="Verify interference cross-term assumption in ablation results")
    parser.add_argument("--input", type=str, default="data/results/ablation_metrics.json",
                      help="Path to ablation_metrics.json")
    parser.add_argument("--output", type=str, default="data/results/ablation_interference_verification.json",
                      help="Path for output verification report")
    args = parser.parse_args()

    print(f"Loading ablation metrics from: {args.input}")
    try:
        ablation_data = load_ablation_metrics(args.input)
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        sys.exit(1)

    print("Verifying interference cross-term assumption...")
    verification_results = verify_cross_term_assumption(ablation_data)

    save_results(verification_results, args.output)

    # Print summary
    print("\n" + "="*60)
    print("VERIFICATION SUMMARY")
    print("="*60)
    if verification_results["assumption_verified"]:
        print("✓ ASSUMPTION VERIFIED: Interference cross-term is negatively correlated with ambiguity")
    else:
        print("✗ ASSUMPTION NOT VERIFIED: Check details for failures")
    
    print(f"\nDetails:")
    for key, value in verification_results["details"].items():
        print(f"  {key}: {value}")
    
    print(f"\nStatistics:")
    for key, value in verification_results["statistics"].items():
        print(f"  {key}: {value}")
    
    print("="*60)

    # Exit with error code if assumption not verified (for CI/CD)
    if not verification_results["assumption_verified"]:
        sys.exit(1)

if __name__ == "__main__":
    main()