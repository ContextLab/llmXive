def load_schema(schema_path: str) -> Dict[str, Any]:
    """Loads a JSON/YAML schema file."""
    with open(schema_path, 'r') as f:
        return yaml.safe_load(f)

def validate_dataframe_against_schema(df: pd.DataFrame, schema: Dict[str, Any]) -> List[str]:
    """
    Validates a DataFrame against a schema definition.
    Returns a list of error messages. Empty list means valid.
    """
    errors = []
    required_fields = schema.get('required', [])
    properties = schema.get('properties', {})

    # Check for required columns
    missing_cols = set(required_fields) - set(df.columns)
    if missing_cols:
        errors.append(f"Missing required columns: {missing_cols}")

    # Check for null values in required fields
    for col in required_fields:
        if col in df.columns:
            if df[col].isnull().any():
                errors.append(f"Column '{col}' contains null values")

    # Basic type checks if defined (simplified for this task)
    # In a full implementation, we would check types per property definition
    if 'properties' in schema:
        for col_name, prop_def in schema['properties'].items():
            if col_name in df.columns:
                expected_type = prop_def.get('type')
                if expected_type:
                    # Map JSON schema types to pandas dtypes roughly
                    if expected_type == 'string':
                        if not df[col_name].apply(lambda x: isinstance(x, str) or pd.isna(x)).all():
                            errors.append(f"Column '{col_name}' should be string type")
                    elif expected_type == 'number':
                        if not pd.api.types.is_numeric_dtype(df[col_name]):
                            errors.append(f"Column '{col_name}' should be numeric type")

    return errors

def write_processed_data(df: pd.DataFrame, output_path: str, state_file_path: str, schema_path: str) -> None:
    """
    Writes the processed DataFrame to a CSV file, validates it against a schema,
    and updates the state file with the file hash.

    Args:
        df (pd.DataFrame): The processed DataFrame.
        output_path (str): The path to the output CSV file.
        state_file_path (str): The path to the state YAML file.
        schema_path (str): The path to the validation schema file.
    """
    # Ensure output directory exists
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    # 1. Validate against schema
    logger.info(f"Validating data against schema: {schema_path}")
    try:
        schema = load_schema(schema_path)
    except FileNotFoundError:
        logger.error(f"Schema file not found: {schema_path}")
        raise
    
    validation_errors = validate_dataframe_against_schema(df, schema)
    if validation_errors:
        error_msg = "Validation failed:\n" + "\n".join(validation_errors)
        logger.error(error_msg)
        raise ValueError(error_msg)
    
    logger.info("Validation passed.")

    # 2. Write to CSV
    df.to_csv(output_path, index=False)
    logger.info(f"Processed data written to {output_path}")

    # 3. Compute hash and update state
    file_hash = compute_file_hash(output_path)
    logger.info(f"File hash for {output_path}: {file_hash}")

    # Use the update_state helper to record the artifact
    update_state(state_file_path, {output_path: file_hash})
    logger.info(f"State file updated with hash for {output_path}")

