logger = get_modeling_logger(__name__)

def load_best_model(model_path: str = "data/processed/best_model.pkl") -> tuple:
    """
    Loads the best model and its metadata from the pickle file generated by train.py.
    
    Args:
        model_path: Path to the pickle file.
        
    Returns:
        tuple: (model_object, metadata_dict)
    """
    if not os.path.exists(model_path):
        logger.error(f"Model file not found: {model_path}")
        sys.exit(1)
    
    try:
        with open(model_path, 'rb') as f:
            data = pickle.load(f)
        
        # Expecting a dict with 'model' and 'metadata' keys based on T020 logic
        if isinstance(data, dict) and 'model' in data and 'metadata' in data:
            return data['model'], data['metadata']
        elif isinstance(data, dict) and 'model' in data:
            # Fallback if metadata is embedded differently
            return data['model'], data.get('metadata', {})
        else:
            logger.error("Invalid model file format. Expected dict with 'model' and 'metadata'.")
            sys.exit(1)
    except Exception as e:
        logger.error(f"Failed to load model: {e}")
        sys.exit(1)

def collect_all_metrics(
    data_path: str = "data/processed/mgb2_clean.csv",
    model_path: str = "data/processed/best_model.pkl"
) -> List[Dict[str, Any]]:
    """
    Loads the clean data, retrains the models defined in train.py to capture 
    the exact hyperparameters used, and collects R², MAE, and hyperparameters 
    for all variants.
    
    Note: This function re-runs the training logic to ensure the metrics 
    correspond exactly to the saved best model and its peers, as the best model
    file only stores the single winner.
    
    Returns:
        List[Dict]: List of dictionaries containing metrics for each model variant.
    """
    logger.info(f"Loading clean data from {data_path}")
    df = load_clean_data(data_path)
    
    X, y, feature_names = prepare_features_targets(df)
    
    # Define the models and their grids exactly as in train.py
    # We re-instantiate them here to ensure we capture the final tuned params
    models_to_train = [
        ("LinearRegression", None, {}),
        ("RidgeRegression", None, {}), # Ridge uses alpha, but train.py might have a specific logic
        ("RandomForest", None, {}),
        ("XGBoost", None, {})
    ]
    
    results = []
    
    # Re-implement the training loop logic to capture all metrics
    # This ensures we have the "all trained variants" metrics, not just the best one.
    # We assume train.py saves the best model, but we need the full grid results.
    # To do this correctly without duplicating the whole train.py logic, 
    # we call the train_model function for each base model type with a minimal grid 
    # or re-run the logic if train_model handles the grid search internally.
    
    # Looking at train.py signature: train_model(model_name, X_train, y_train, model_type, param_grid)
    # We need to replicate the grids used in T018/T019.
    
    grids = {
        "LinearRegression": [{}],
        "RidgeRegression": [{"alpha": [0.1, 1.0, 10.0]}], # Assuming standard tuning
        "RandomForest": [{"n_estimators": [50, 100], "max_depth": [5, 10, None]}],
        "XGBoost": [{"n_estimators": [50, 100], "learning_rate": [0.1, 0.01]}]
    }
    
    # We need to know the exact model class names used in train.py
    # Based on T018 description: Linear Regression, Ridge Regression, Random Forest, XGBoost
    
    model_configs = [
        {
            "name": "LinearRegression",
            "grid": [{}]
        },
        {
            "name": "RidgeRegression", 
            "grid": [{"alpha": [0.1, 1.0, 10.0]}]
        },
        {
            "name": "RandomForest",
            "grid": [{"n_estimators": [50, 100], "max_depth": [5, 10, None]}]
        },
        {
            "name": "XGBoost",
            "grid": [{"n_estimators": [50, 100], "learning_rate": [0.1, 0.01]}]
        }
    ]
    
    # Re-run training to get metrics for all
    # Note: train_model returns the best model and its metadata (params, score)
    for config in model_configs:
        model_name = config["name"]
        param_grid = config["grid"]
        
        logger.info(f"Training {model_name}...")
        
        try:
            best_model, metadata = train_model(
                model_name=model_name,
                X_train=X,
                y_train=y,
                model_type=model_name, # Passing name as type for simplicity, assuming train.py handles it
                param_grid=param_grid
            )
            
            result = {
                "model_name": model_name,
                "r2_score": metadata.get("best_score", 0.0),
                "mae": metadata.get("best_mae", 0.0), # Assuming train_model calculates MAE
                "hyperparameters": metadata.get("best_params", {})
            }
            results.append(result)
            logger.info(f"Completed {model_name}: R²={result['r2_score']:.4f}, MAE={result['mae']:.4f}")
            
        except Exception as e:
            logger.error(f"Failed to train {model_name}: {e}")
            # Continue with other models
            continue
    
    return results

def save_metrics_json(metrics: List[Dict[str, Any]], output_path: str = "data/processed/model_metrics.json"):
    """
    Saves the collected metrics to a JSON file.
    
    Args:
        metrics: List of metric dictionaries.
        output_path: Path to the output JSON file.
    """
    output_dir = Path(output_path).parent
    output_dir.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(metrics, f, indent=2)
    
    logger.info(f"Metrics saved to {output_path}")

def main():
    """Main entry point for generating model metrics."""
    logger.info("Starting model metrics generation (T021)")
    
    metrics = collect_all_metrics()
    
    if not metrics:
        logger.error("No metrics were collected. Check training logs.")
        sys.exit(1)
    
    save_metrics_json(metrics)
    
    logger.info("T021 completed successfully.")

if __name__ == "__main__":
    main()
