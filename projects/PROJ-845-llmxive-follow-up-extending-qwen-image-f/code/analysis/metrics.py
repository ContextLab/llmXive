def compute_entropy(probs: List[float]) -> float:
    """
    Compute Shannon entropy of a probability distribution.
    H(X) = - sum(p(x) * log2(p(x)))
    
    Args:
        probs: List of probabilities that sum to 1.0
        
    Returns:
        Entropy value in bits
    """
    if not probs:
        return 0.0
    
    # Filter out zeros to avoid log(0)
    non_zero_probs = [p for p in probs if p > 0]
    
    if not non_zero_probs:
        return 0.0
        
    entropy = 0.0
    for p in non_zero_probs:
        entropy -= p * math.log2(p)
        
    return entropy

def compute_trace_entropy(problem: SyntheticProblem, trace: List[str]) -> float:
    """
    Compute Shannon entropy of token-level probabilities from the teacher trace.
    
    This function measures the uncertainty/complexity of the reasoning steps
    generated by the teacher model for a given problem. It uses the token-level
    probability distributions provided in the trace.
    
    Args:
        problem: The SyntheticProblem instance
        trace: List of trace steps, where each step is a dict or object containing
               'token_probs' or similar probability distribution for that step
               
    Returns:
        Average Shannon entropy across all steps in the trace (float)
        
    Raises:
        ValueError: If trace is empty or contains invalid data
        TypeError: If trace format is unexpected
    """
    if not trace:
        logger.warning(f"Empty trace for problem {problem.id}, returning 0.0 entropy")
        return 0.0
    
    entropies = []
    
    for i, step in enumerate(trace):
        try:
            # Handle different possible trace formats
            if isinstance(step, dict):
                # Expected format: {'token_probs': [float, ...], 'text': str, ...}
                if 'token_probs' in step:
                    probs = step['token_probs']
                elif 'probs' in step:
                    probs = step['probs']
                elif 'logits' in step:
                    # Convert logits to probabilities via softmax if needed
                    logits = step['logits']
                    # Simple softmax
                    max_logit = max(logits)
                    exp_logits = [math.exp(l - max_logit) for l in logits]
                    sum_exp = sum(exp_logits)
                    probs = [e / sum_exp for e in exp_logits]
                else:
                    logger.warning(f"Step {i} in trace for problem {problem.id} has no probability data")
                    continue
            elif hasattr(step, 'token_probs'):
                probs = step.token_probs
            else:
                logger.warning(f"Step {i} in trace for problem {problem.id} has unexpected format: {type(step)}")
                continue
            
            if not isinstance(probs, (list, tuple)):
                logger.warning(f"Step {i} probabilities are not a list: {type(probs)}")
                continue
            
            if len(probs) == 0:
                logger.warning(f"Step {i} has empty probability distribution")
                continue
            
            step_entropy = compute_entropy(list(probs))
            entropies.append(step_entropy)
            
        except (KeyError, TypeError, ValueError) as e:
            logger.warning(f"Error processing step {i} for problem {problem.id}: {e}")
            continue
    
    if not entropies:
        logger.warning(f"No valid entropy values computed for trace of problem {problem.id}")
        return 0.0
    
    avg_entropy = sum(entropies) / len(entropies)
    logger.debug(f"Trace entropy for problem {problem.id}: {avg_entropy:.4f} (from {len(entropies)} steps)")
    return avg_entropy

def compute_problem_entropy(problem: SyntheticProblem) -> float:
    """
    Compute the entropy of a problem based on its structural elements (premises/operators).
    
    This measures the combinatorial complexity of the problem definition itself,
    distinct from the trace entropy which measures the reasoning process.
    
    Args:
        problem: The SyntheticProblem instance
        
    Returns:
        Entropy value representing problem complexity
    """
    # Combine premises and operators into a single sequence for analysis
    elements = problem.premises + problem.operators
    
    if not elements:
        return 0.0
    
    # Count frequency of each element
    counts = Counter(elements)
    total = len(elements)
    
    # Calculate probabilities
    probs = [count / total for count in counts.values()]
    
    return compute_entropy(probs)

def load_problems_from_csv(filepath: str) -> List[SyntheticProblem]:
    """
    Load problems from a CSV file and return as list of SyntheticProblem objects.
    
    Args:
        filepath: Path to the CSV file
        
    Returns:
        List of SyntheticProblem instances
    """
    problems = []
    
    if not os.path.exists(filepath):
        logger.error(f"File not found: {filepath}")
        return problems
    
    with open(filepath, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                # Parse list fields from JSON strings
                premises = json.loads(row.get('premises', '[]'))
                operators = json.loads(row.get('operators', '[]'))
                metadata = json.loads(row.get('metadata', '{}'))
                
                problem = SyntheticProblem(
                    id=row['id'],
                    premises=premises,
                    operators=operators,
                    solution=row.get('solution', ''),
                    entropy_level=row.get('entropy_level', 'unknown'),
                    metadata=metadata
                )
                problems.append(problem)
            except (json.JSONDecodeError, KeyError) as e:
                logger.warning(f"Skipping malformed row in {filepath}: {e}")
                continue
    
    logger.info(f"Loaded {len(problems)} problems from {filepath}")
    return problems

def compute_entropy_statistics(problems: List[SyntheticProblem]) -> Dict[str, Any]:
    """
    Calculate per-sample entropy scores and perform statistical comparisons.
    
    Args:
        problems: List of SyntheticProblem instances
        
    Returns:
        Dictionary containing:
        - mean_entropy: float
        - std_entropy: float
        - entropy_by_level: Dict[str, List[float]]
        - t_test_result: Dict (if comparing two groups)
    """
    if not problems:
        return {
            'mean_entropy': 0.0,
            'std_entropy': 0.0,
            'entropy_by_level': {},
            't_test_result': None,
            'p_value': None
        }
    
    entropies = []
    entropy_by_level: Dict[str, List[float]] = {}
    
    for problem in problems:
        entropy = compute_problem_entropy(problem)
        entropies.append(entropy)
        
        level = problem.entropy_level
        if level not in entropy_by_level:
            entropy_by_level[level] = []
        entropy_by_level[level].append(entropy)
    
    mean_entropy = sum(entropies) / len(entropies)
    variance = sum((e - mean_entropy) ** 2 for e in entropies) / len(entropies)
    std_entropy = math.sqrt(variance) if variance > 0 else 0.0
    
    result = {
        'mean_entropy': mean_entropy,
        'std_entropy': std_entropy,
        'entropy_by_level': entropy_by_level,
        't_test_result': None,
        'p_value': None,
        'sample_size': len(problems)
    }
    
    # Perform t-test if we have at least two groups with sufficient samples
    if len(entropy_by_level) >= 2:
        levels = list(entropy_by_level.keys())
        group1 = entropy_by_level[levels[0]]
        group2 = entropy_by_level[levels[1]]
        
        if len(group1) >= 2 and len(group2) >= 2:
            t_stat, p_val = two_sample_t_test(group1, group2)
            result['t_test_result'] = {
                'group1': levels[0],
                'group2': levels[1],
                't_statistic': t_stat,
                'p_value': p_val
            }
            result['p_value'] = p_val
    
    return result

def two_sample_t_test(group1: List[float], group2: List[float]) -> Tuple[float, float]:
    """
    Perform an independent two-sample t-test.
    
    Args:
        group1: First sample
        group2: Second sample
        
    Returns:
        Tuple of (t_statistic, p_value)
    """
    n1, n2 = len(group1), len(group2)
    mean1 = sum(group1) / n1
    mean2 = sum(group2) / n2
    
    var1 = sum((x - mean1) ** 2 for x in group1) / (n1 - 1)
    var2 = sum((x - mean2) ** 2 for x in group2) / (n2 - 1)
    
    # Pooled standard error
    se = math.sqrt(var1/n1 + var2/n2)
    
    if se == 0:
        return 0.0, 1.0
        
    t_stat = (mean1 - mean2) / se
    
    # Approximate p-value using normal distribution for large samples
    # For small samples, degrees of freedom calculation would be needed
    # Using a simplified approximation here
    df = n1 + n2 - 2
    p_value = 2 * (1 - normal_cdf(abs(t_stat)))
    
    return t_stat, p_value

def normal_cdf(x: float) -> float:
    """Approximate standard normal CDF."""
    return 0.5 * (1 + math.erf(x / math.sqrt(2)))

def validate_trace_consistency(problems: List[SyntheticProblem], traces: Dict[str, List[str]]) -> Dict[str, Any]:
    """
    Validate that trace entropy matches problem entropy expectations.
    
    This function checks the qualitative relationship between problem entropy levels
    and their corresponding trace entropies, satisfying FR-009.
    
    Args:
        problems: List of SyntheticProblem instances
        traces: Dictionary mapping problem ID to its trace (list of steps)
        
    Returns:
        Dictionary with validation results:
        - total_samples: int
        - consistent_samples: int
        - inconsistent_samples: int
        - per_level_stats: Dict[str, Dict]
        - overall_consistent: bool
    """
    if not problems:
        return {
            'total_samples': 0,
            'consistent_samples': 0,
            'inconsistent_samples': 0,
            'per_level_stats': {},
            'overall_consistent': True
        }
    
    consistent_count = 0
    inconsistent_count = 0
    per_level_stats: Dict[str, Dict] = {}
    
    for problem in problems:
        problem_id = problem.id
        if problem_id not in traces:
            logger.warning(f"No trace found for problem {problem_id}")
            continue
        
        trace = traces[problem_id]
        trace_entropy = compute_trace_entropy(problem, trace)
        problem_entropy = compute_problem_entropy(problem)
        
        level = problem.entropy_level
        if level not in per_level_stats:
            per_level_stats[level] = {
                'count': 0,
                'trace_entropies': [],
                'problem_entropies': [],
                'consistent': 0,
                'inconsistent': 0
            }
        
        per_level_stats[level]['count'] += 1
        per_level_stats[level]['trace_entropies'].append(trace_entropy)
        per_level_stats[level]['problem_entropies'].append(problem_entropy)
        
        # Qualitative consistency check:
        # Low entropy problems should have relatively lower trace entropy
        # High entropy problems should have relatively higher trace entropy
        # We use a simple threshold-based approach relative to the dataset
        
        # Calculate global median for reference
        all_trace_entropies = []
        for p in problems:
            if p.id in traces:
                all_trace_entropies.append(compute_trace_entropy(p, traces[p.id]))
        
        if all_trace_entropies:
            all_trace_entropies.sort()
            median_entropy = all_trace_entropies[len(all_trace_entropies) // 2]
            
            # Define consistency based on relative position
            if level == 'low':
                is_consistent = trace_entropy <= median_entropy
            elif level == 'high':
                is_consistent = trace_entropy > median_entropy
            else:  # target
                is_consistent = True  # Target is flexible
            
            if is_consistent:
                consistent_count += 1
                per_level_stats[level]['consistent'] += 1
            else:
                inconsistent_count += 1
                per_level_stats[level]['inconsistent'] += 1
        
        logger.debug(f"Problem {problem_id} ({level}): trace_entropy={trace_entropy:.4f}, consistent={is_consistent}")
    
    total = consistent_count + inconsistent_count
    overall_consistent = (inconsistent_count / total) < 0.1 if total > 0 else True
    
    # Calculate averages for reporting
    for level, stats in per_level_stats.items():
        if stats['trace_entropies']:
            stats['avg_trace_entropy'] = sum(stats['trace_entropies']) / len(stats['trace_entropies'])
            stats['avg_problem_entropy'] = sum(stats['problem_entropies']) / len(stats['problem_entropies'])
        else:
            stats['avg_trace_entropy'] = 0.0
            stats['avg_problem_entropy'] = 0.0
        del stats['trace_entropies']
        del stats['problem_entropies']
    
    return {
        'total_samples': total,
        'consistent_samples': consistent_count,
        'inconsistent_samples': inconsistent_count,
        'per_level_stats': per_level_stats,
        'overall_consistent': overall_consistent
    }

