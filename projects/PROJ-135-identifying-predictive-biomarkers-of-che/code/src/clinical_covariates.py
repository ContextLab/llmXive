"""
Clinical Covariate Extraction (T039b)

Extracts, cleans, and formats clinical covariates (age, stage) from raw metadata.
Imputes missing age with median, missing stage with mode.
Drops samples with missing response labels.
"""
import os
import sys
import json
import logging
import pandas as pd
import numpy as np
from pathlib import Path
from typing import Dict, Any, List, Optional

# Import project utilities
from src.config import get_project_root, ensure_directories
from src.utils import setup_logging

def load_raw_clinical_metadata(raw_dir: Path) -> pd.DataFrame:
    """
    Load raw clinical metadata from data/raw/.
    Merges multiple JSON/CSV files if present, or loads a specific merged file.
    """
    raw_path = raw_dir
    if not raw_path.exists():
        raise FileNotFoundError(f"Raw data directory not found: {raw_path}")

    # Look for common clinical metadata files generated by T013a
    # Expected files: GSEXXXXX_clinical.json, GSEXXXXX_clinical.csv, or a merged file
    clinical_files = list(raw_path.glob("*clinical*"))
    if not clinical_files:
        # Fallback: try to find any JSON/CSV that might contain clinical info
        clinical_files = list(raw_path.glob("*.json")) + list(raw_path.glob("*.csv"))

    if not clinical_files:
        raise FileNotFoundError("No clinical metadata files found in data/raw/")

    dfs = []
    for file in clinical_files:
        try:
            if file.suffix == '.json':
                with open(file, 'r') as f:
                    data = json.load(f)
                    if isinstance(data, list):
                        df = pd.DataFrame(data)
                    else:
                        df = pd.DataFrame([data])
            elif file.suffix == '.csv':
                df = pd.read_csv(file)
            else:
                continue
            
            # Ensure sample_id exists, otherwise try to infer
            if 'sample_id' not in df.columns:
                if 'samples' in df.columns:
                    df['sample_id'] = df['samples']
                elif 'sample' in df.columns:
                    df['sample_id'] = df['sample']
                else:
                    # Skip if no identifier found
                    logging.warning(f"Skipping {file}: No sample identifier column found.")
                    continue

            # Standardize column names to lowercase
            df.columns = df.columns.str.lower().str.replace(' ', '_')
            dfs.append(df)
        except Exception as e:
            logging.warning(f"Failed to load {file}: {e}")
            continue

    if not dfs:
        raise ValueError("No valid clinical metadata could be parsed.")

    # Concatenate all found clinical data
    combined_df = pd.concat(dfs, ignore_index=True)
    return combined_df

def clean_and_format_covariates(df: pd.DataFrame) -> pd.DataFrame:
    """
    Clean and format clinical covariates.
    - Ensure required columns: sample_id, age, stage, response_label
    - Impute missing age with median.
    - Impute missing stage with mode.
    - Drop samples with missing response_label.
    """
    # Standardize column names
    df = df.copy()
    df.columns = df.columns.str.lower().str.replace(' ', '_')

    # Map potential column names to standard names
    col_map = {}
    if 'age' in df.columns:
        col_map['age'] = 'age'
    elif 'patient_age' in df.columns:
        col_map['patient_age'] = 'age'
    
    if 'stage' in df.columns:
        col_map['stage'] = 'stage'
    elif 'tumor_stage' in df.columns:
        col_map['tumor_stage'] = 'stage'
    elif 'clinical_stage' in df.columns:
        col_map['clinical_stage'] = 'stage'

    if 'response' in df.columns:
        col_map['response'] = 'response_label'
    elif 'response_label' in df.columns:
        col_map['response_label'] = 'response_label'
    elif 'outcome' in df.columns:
        col_map['outcome'] = 'response_label'

    if 'sample_id' in df.columns:
        col_map['sample_id'] = 'sample_id'

    # Rename columns
    if col_map:
        df = df.rename(columns=col_map)

    required_cols = ['sample_id', 'age', 'stage', 'response_label']
    missing_cols = [c for c in required_cols if c not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns after mapping: {missing_cols}")

    # Clean response_label: drop rows with missing response
    initial_count = len(df)
    df = df.dropna(subset=['response_label'])
    dropped_response = initial_count - len(df)
    if dropped_response > 0:
        logging.info(f"Dropped {dropped_response} samples with missing response_label.")

    # Clean Age: Impute missing with median
    initial_count = len(df)
    if df['age'].isna().any():
        median_age = df['age'].median()
        if pd.isna(median_age):
            # Fallback if all ages are missing (unlikely but possible)
            median_age = 50.0 
        df['age'] = df['age'].fillna(median_age)
        logging.info(f"Imputed {initial_count - len(df[df['age'].notna()])} missing ages with median {median_age}.")

    # Clean Stage: Impute missing with mode
    initial_count = len(df)
    if df['stage'].isna().any():
        mode_val = df['stage'].mode()
        if not mode_val.empty:
            mode_stage = mode_val[0]
            df['stage'] = df['stage'].fillna(mode_stage)
            logging.info(f"Imputed {initial_count - len(df[df['stage'].notna()])} missing stages with mode '{mode_stage}'.")
        else:
            # If no mode exists (all NaN), fill with 'Unknown'
            df['stage'] = df['stage'].fillna('Unknown')
            logging.warning("All stage values were missing; filled with 'Unknown'.")

    # Select and sort columns
    result = df[['sample_id', 'age', 'stage', 'response_label']]
    result = result.sort_values('sample_id').reset_index(drop=True)

    # Ensure types
    result['sample_id'] = result['sample_id'].astype(str)
    result['age'] = result['age'].astype(float)
    result['stage'] = result['stage'].astype(str)
    result['response_label'] = result['response_label'].astype(str)

    return result

def write_covariates_to_csv(df: pd.DataFrame, output_path: Path) -> None:
    """Write the cleaned covariate dataframe to CSV."""
    df.to_csv(output_path, index=False)
    logging.info(f"Wrote {len(df)} samples to {output_path}")

def main() -> int:
    """Main entry point for T039b."""
    setup_logging()
    root = get_project_root()
    raw_dir = root / "data" / "raw"
    processed_dir = root / "data" / "processed"
    
    ensure_directories(processed_dir)
    
    output_file = processed_dir / "clinical_covariates.csv"

    try:
        logging.info("Loading raw clinical metadata...")
        df_raw = load_raw_clinical_metadata(raw_dir)
        
        logging.info("Cleaning and formatting covariates...")
        df_clean = clean_and_format_covariates(df_raw)
        
        logging.info(f"Writing output to {output_file}...")
        write_covariates_to_csv(df_clean, output_file)
        
        logging.info("T039b completed successfully.")
        return 0
    except Exception as e:
        logging.error(f"T039b failed: {e}")
        return 1

if __name__ == '__main__':
    sys.exit(main())
