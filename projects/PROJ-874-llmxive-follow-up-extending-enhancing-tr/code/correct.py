def get_naive_baseline_paths(config) -> list:
    """
    Retrieve paths to all naive baseline videos generated by T013.
    """
    raw_dir = get_raw_dir(config)
    naive_dir = raw_dir / "naive_baseline"
    
    if not naive_dir.exists():
        raise DatasetNotFoundError(f"Naive baseline directory not found: {naive_dir}")
    
    video_files = [f for f in naive_dir.iterdir() if f.suffix.lower() in ['.mp4', '.avi', '.mov']]
    if not video_files:
        raise DatasetNotFoundError(f"No naive baseline videos found in {naive_dir}")
    
    logger.info(f"Found {len(video_files)} naive baseline videos.")
    return sorted(video_files)

def verify_naive_baselines_exist(config) -> bool:
    """
    Verify that naive baseline videos exist before proceeding.
    """
    try:
        paths = get_naive_baseline_paths(config)
        logger.info(f"Verified existence of {len(paths)} naive baseline videos.")
        return True
    except DatasetNotFoundError as e:
        logger.error(f"Missing naive baseline videos: {e}")
        return False

def get_flow_field_paths(config) -> dict:
    """
    Map video IDs to their corresponding flow field JSON files generated by T021.
    """
    results_dir = get_results_dir(config)
    flow_dir = results_dir / "flow_fields"
    
    if not flow_dir.exists():
        raise DatasetNotFoundError(f"Flow field directory not found: {flow_dir}")
    
    flow_files = [f for f in flow_dir.iterdir() if f.suffix == '.json']
    flow_map = {}
    for f in flow_files:
        video_id = f.stem
        flow_map[video_id] = f
    
    if not flow_map:
        raise DatasetNotFoundError(f"No flow field files found in {flow_dir}")
    
    logger.info(f"Found {len(flow_map)} flow field files.")
    return flow_map

def verify_flow_fields_exist(config) -> dict:
    """
    Verify that flow fields exist for all naive baseline videos.
    Aborts with error if any are missing.
    """
    naive_paths = get_naive_baseline_paths(config)
    flow_map = get_flow_field_paths(config)
    
    missing = []
    for path in naive_paths:
        video_id = path.stem
        if video_id not in flow_map:
            missing.append(video_id)
    
    if missing:
        error_msg = f"Missing flow fields for {len(missing)} videos: {missing}. " \
                    f"Ensure T021 (process_video_flow) has completed successfully."
        logger.error(error_msg)
        raise DatasetNotFoundError(error_msg)
    
    logger.info(f"Verified flow fields for all {len(naive_paths)} videos.")
    return flow_map

def warp_frame(frame, flow, prev_frame=None):
    """
    Perform non-differentiable warping of a frame using optical flow.
    
    Args:
        frame: Current frame (numpy array)
        flow: Optical flow field (numpy array, shape HxWx2)
        prev_frame: Previous frame (optional, for reference)
    
    Returns:
        Warped frame (numpy array)
    """
    if flow is None or not is_flow_valid(flow):
        logger.warning("Invalid flow field detected, skipping warp.")
        return frame
    
    # Use cv2.remap for warping
    # Flow vectors represent displacement from current to next frame
    # We need to invert for warping current to match next, or next to match current
    # Assuming flow[i, j] = (u, v) is the displacement of pixel (i, j) in frame t to t+1
    # To warp frame t+1 back to t, we use negative flow
    
    h, w = flow.shape[:2]
    map_x = np.zeros((h, w), dtype=np.float32)
    map_y = np.zeros((h, w), dtype=np.float32)
    
    # Create coordinate grids
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    
    # Apply flow to create remap maps
    # Standard remap: dst(x, y) = src(x + u, y + v)
    # Here we want to correct frame t+1 to align with t, so we use negative flow
    map_x = x - flow[:, :, 0]
    map_y = y - flow[:, :, 1]
    
    try:
        warped = cv2.remap(frame, map_x, map_y, interpolation=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REPLICATE)
        return warped
    except Exception as e:
        logger.error(f"Error during warping: {e}")
        return frame

def smooth_frames(frames, window_size=3):
    """
    Apply temporal smoothing to a sequence of frames.
    
    Args:
        frames: List of frame arrays
        window_size: Smoothing window size (odd number)
    
    Returns:
        Smoothed list of frames
    """
    if len(frames) < window_size:
        logger.warning(f"Frame sequence too short ({len(frames)}) for smoothing window {window_size}. Skipping.")
        return frames
    
    smoothed = []
    half_window = window_size // 2
    
    for i, frame in enumerate(frames):
        start_idx = max(0, i - half_window)
        end_idx = min(len(frames), i + half_window + 1)
        
        window_frames = frames[start_idx:end_idx]
        # Simple averaging
        stack = np.stack(window_frames, axis=0)
        avg_frame = np.mean(stack, axis=0).astype(frame.dtype)
        smoothed.append(avg_frame)
    
    return smoothed

def process_video_flow(config, video_path, flow_path, output_dir):
    """
    Process a single video: warp frames using flow and apply smoothing.
    
    Args:
        config: Configuration object
        video_path: Path to naive baseline video
        flow_path: Path to corresponding flow field JSON
        output_dir: Directory to write corrected video
    
    Returns:
        Path to output video
    """
    logger.info(f"Processing video: {video_path.name}")
    
    # Extract frames
    frames = extract_frames(video_path)
    if not frames:
        raise ValueError(f"No frames extracted from {video_path}")
    
    # Load flow fields
    with open(flow_path, 'r') as f:
        flow_data = json.load(f)
    
    # Flow data structure: list of dicts with 'frame_idx', 'flow' (base64 or raw)
    # Assuming flow_data is a list of flow arrays (decoded)
    # For this implementation, we assume flow_data is a list of numpy arrays saved as lists
    # In a real scenario, we might need to decode base64 or load binary
    
    # Reconstruct flow list
    flow_list = []
    for item in flow_data:
        if 'flow' in item:
            flow_arr = np.array(item['flow'])
            flow_list.append(flow_arr)
        else:
            flow_list.append(None)
    
    # Warp frames
    warped_frames = []
    for i, frame in enumerate(frames):
        flow = flow_list[i] if i < len(flow_list) else None
        warped = warp_frame(frame, flow)
        warped_frames.append(warped)
    
    # Apply smoothing
    smoothed_frames = smooth_frames(warped_frames, window_size=3)
    
    # Write output video
    output_path = output_dir / f"{video_path.stem}_corrected.mp4"
    write_video(smoothed_frames, output_path, fps=24) # Assuming 24fps, adjust if needed
    
    logger.info(f"Corrected video written to: {output_path}")
    return output_path

def main():
    """
    Main entry point for flow correction pipeline (T022).
    """
    parser = argparse.ArgumentParser(description="Generate Condition C outputs via warping and smoothing.")
    parser.add_argument('--config', type=str, default='config.json', help='Path to config file')
    args = parser.parse_args()
    
    try:
        config = get_config(args.config)
    except Exception as e:
        logger.error(f"Failed to load config: {e}")
        sys.exit(1)
    
    # Step 1: Verify naive baselines exist
    if not verify_naive_baselines_exist(config):
        logger.critical("Naive baseline videos missing. Aborting.")
        sys.exit(1)
    
    # Step 2: Verify flow fields exist (T021 output)
    try:
        flow_map = verify_flow_fields_exist(config)
    except DatasetNotFoundError as e:
        logger.critical(str(e))
        sys.exit(1)
    
    # Step 3: Prepare output directory
    output_dir = get_results_dir(config) / "condition_c"
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Step 4: Process all videos
    naive_paths = get_naive_baseline_paths(config)
    success_count = 0
    fail_count = 0
    
    for video_path in naive_paths:
        video_id = video_path.stem
        if video_id not in flow_map:
            logger.error(f"Flow field missing for {video_id}, skipping.")
            fail_count += 1
            continue
        
        try:
            process_video_flow(config, video_path, flow_map[video_id], output_dir)
            success_count += 1
        except Exception as e:
            logger.error(f"Failed to process {video_path}: {e}")
            fail_count += 1
    
    logger.info(f"Processing complete. Success: {success_count}, Failed: {fail_count}")
    
    if fail_count > 0:
        sys.exit(1)

if __name__ == "__main__":
    main()
