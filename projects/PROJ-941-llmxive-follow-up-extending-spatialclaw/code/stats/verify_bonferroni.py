"""
verify_bonferroni.py

Implements verification of Bonferroni-corrected p-values from the statistical report.
This task manually recalculates the correction to ensure the logic in T048/T029 was sound.
"""

import os
import re
import json
import logging
import argparse
from typing import Dict, List, Any, Optional, Tuple
from pathlib import Path

# Import shared utilities if needed, or define minimal helpers here
# We rely on the output of T048 (final_statistical_report.md)

logger = logging.getLogger(__name__)

# Paths
PROJECT_ROOT = Path(__file__).resolve().parents[2]
REPORT_PATH = PROJECT_ROOT / "results" / "analysis" / "final_statistical_report.md"
OUTPUT_PATH = PROJECT_ROOT / "results" / "analysis" / "bonferroni_verification.txt"
RAW_RESULTS_PATH = PROJECT_ROOT / "results" / "analysis" / "paired_comparison.csv"

def load_markdown_report(path: Path) -> str:
    """Read the statistical report markdown."""
    if not path.exists():
        raise FileNotFoundError(f"Statistical report not found at {path}")
    with open(path, "r", encoding="utf-8") as f:
        return f.read()

def parse_markdown_report(content: str) -> Dict[str, Dict[str, float]]:
    """
    Parse the markdown report to extract raw p-values and corrected p-values.
    Expected format in report (generated by T048/T029):
    | Task Type | Test | Statistic | Raw P-value | Bonferroni Corrected P-value |
    """
    results = {}
    lines = content.split("\n")
    
    # Simple regex to find table rows with p-values
    # Looking for lines that contain "Task Type" headers or data rows
    # We expect a structure like:
    # | occlusion | Wilcoxon | 12.5 | 0.03 | 0.09 |
    
    # Pattern: | <type> | <test> | <stat> | <raw_p> | <corr_p> |
    # We need to be careful with Markdown table formatting
    
    p_pattern = re.compile(
        r"^\s*\|\s*([a-zA-Z_]+)\s*\|\s*([a-zA-Z_]+)\s*\|\s*[\d.-]+\s*\|\s*([\d.eE+-]+)\s*\|\s*([\d.eE+-]+)\s*\|",
        re.IGNORECASE
    )

    for line in lines:
        match = p_pattern.match(line)
        if match:
            task_type = match.group(1).lower()
            # raw_p = float(match.group(3)) # Not strictly needed for verification if we trust the input, but good for logging
            reported_corr_p = float(match.group(4))
            
            # We will re-calculate and compare
            results[task_type] = {
                "reported_corrected_p": reported_corr_p,
                # We need the raw p-value to verify. 
                # If the regex captures it, we use it. If the table format is different, we might need to adjust.
                # Assuming the 3rd number group is raw p-value based on typical table structures.
                "raw_p": float(match.group(3)) 
            }
    
    if not results:
        logger.warning("No p-value rows found in markdown report. Attempting fallback parsing.")
        # Fallback: maybe the table headers are different or spacing varies.
        # For now, if we found nothing, we assume the report format might be slightly different.
        # But based on T029/T048 spec, it should be standard.
        pass

    return results

def apply_bonferroni_correction(raw_p: float, n_tests: int) -> float:
    """
    Manually calculate Bonferroni correction.
    corrected_p = min(raw_p * n_tests, 1.0)
    """
    corrected = raw_p * n_tests
    return min(corrected, 1.0)

def verify_bonferroni_correction(parsed_results: Dict[str, Dict[str, float]]) -> Tuple[bool, List[str]]:
    """
    Verify that the reported corrected p-values match the manual calculation.
    Returns (is_valid, list_of_messages)
    """
    messages = []
    all_valid = True
    
    # We expect 3 task types: occlusion, depth, relative
    # So n_tests = 3
    n_tests = 3
    
    for task_type, data in parsed_results.items():
        raw_p = data["raw_p"]
        reported_corr = data["reported_corrected_p"]
        
        calculated_corr = apply_bonferroni_correction(raw_p, n_tests)
        
        # Allow small floating point tolerance
        tolerance = 1e-6
        if abs(calculated_corr - reported_corr) > tolerance:
            all_valid = False
            msg = (
                f"MISMATCH for {task_type}: "
                f"Raw={raw_p:.6f}, Reported_Corr={reported_corr:.6f}, "
                f"Calculated_Corr={calculated_corr:.6f}"
            )
            messages.append(msg)
        else:
            msg = f"PASS for {task_type}: Raw={raw_p:.6f} -> Corrected={calculated_corr:.6f} (matches reported)"
            messages.append(msg)
    
    if not parsed_results:
        messages.append("ERROR: No data found to verify.")
        all_valid = False
        
    return all_valid, messages

def generate_verification_report(is_valid: bool, messages: List[str]) -> str:
    """Generate the text content for the verification report."""
    lines = [
        "Bonferroni Correction Verification Report",
        "=" * 50,
        f"Status: {'PASSED' if is_valid else 'FAILED'}",
        f"Number of tests corrected (n): 3",
        "Correction Method: min(raw_p * n, 1.0)",
        "",
        "Detailed Verification Results:",
        "-" * 50
    ]
    lines.extend(messages)
    lines.append("")
    lines.append("-" * 50)
    if is_valid:
        lines.append("CONCLUSION: The Bonferroni correction logic in the statistical report is sound.")
    else:
        lines.append("CONCLUSION: Discrepancies found. The correction logic may be incorrect or the report parsing failed.")
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(description="Verify Bonferroni correction in statistical report.")
    parser.add_argument("--report", type=str, default=str(REPORT_PATH), help="Path to final_statistical_report.md")
    parser.add_argument("--output", type=str, default=str(OUTPUT_PATH), help="Path to output verification file")
    args = parser.parse_args()

    # Ensure output directory exists
    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    try:
        logger.info(f"Loading report from {args.report}")
        content = load_markdown_report(Path(args.report))
        
        logger.info("Parsing p-values from report...")
        parsed_results = parse_markdown_report(content)
        
        if not parsed_results:
            # If parsing failed, write a report indicating failure
            report_content = generate_verification_report(False, ["No p-values found in report. Check format."])
            with open(output_path, "w", encoding="utf-8") as f:
                f.write(report_content)
            logger.error("Verification failed: No data parsed.")
            return 1

        logger.info(f"Verifying {len(parsed_results)} task types...")
        is_valid, messages = verify_bonferroni_correction(parsed_results)
        
        report_content = generate_verification_report(is_valid, messages)
        
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(report_content)
        
        logger.info(f"Verification report written to {output_path}")
        return 0 if is_valid else 1

    except FileNotFoundError as e:
        logger.error(f"File not found: {e}")
        return 1
    except Exception as e:
        logger.error(f"Verification failed with error: {e}")
        return 1

if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    exit(main())
