"""
Utility module to verify that the planned experiment fits within the allocated budget.
Reads the power configuration and the power analysis summary to ensure the estimated
runtime does not exceed the allowed budget (max_runtime_hours).
"""

import os
import yaml
import json
from typing import Any, Dict

def _load_power_config(config_path: str) -> Dict[str, Any]:
    """Load the power configuration YAML."""
    if not os.path.exists(config_path):
        raise FileNotFoundError(f"Power config file not found: {config_path}")
    with open(config_path, "r") as f:
        return yaml.safe_load(f)

def _load_power_analysis_summary() -> Dict[str, Any]:
    """Load the power analysis summary generated by T035c."""
    summary_path = os.path.join(
        "results", "analysis", "power_analysis_summary.json"
    )
    if not os.path.exists(summary_path):
        raise FileNotFoundError(
            f"Power analysis summary not found at {summary_path}"
        )
    with open(summary_path, "r") as f:
        return json.load(f)

def check_budget(config_path: str = "data/power_config.yaml") -> None:
    """
    Verify that the estimated runtime from the power analysis does not exceed the
    maximum runtime defined in the power configuration.

    Raises:
        RuntimeError: If the estimated runtime exceeds the allowed budget.
    """
    cfg = _load_power_config(config_path)
    max_hours = cfg.get("max_runtime_hours")
    if max_hours is None:
        raise ValueError("max_runtime_hours not defined in power config")

    max_seconds = max_hours * 3600.0

    analysis = _load_power_analysis_summary()
    estimated_runtime = analysis.get("estimated_runtime")
    if estimated_runtime is None:
        raise ValueError("estimated_runtime missing in power analysis summary")

    if estimated_runtime > max_seconds:
        raise RuntimeError(
            f"Estimated runtime {estimated_runtime}s exceeds budget of {max_seconds}s"
        )
    # If we reach here, the budget is satisfied.
