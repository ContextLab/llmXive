import json
import csv
import logging
import sys
from pathlib import Path
from typing import List, Dict, Any

from code.config import PROCESSED_DIR, RANDOM_SEED
from code.graph_builder import load_graphs, build_graphs_for_corpus, save_graphs, extract_features_for_csv

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
    handlers=[logging.StreamHandler(sys.stdout)]
)
logger = logging.getLogger("pipeline_writer")

def load_graphs_from_builder() -> List[Dict[str, Any]]:
    """
    Load the graphs generated by the graph_builder module.
    This expects the graphs to be saved in data/processed/graphs.json by the builder.
    """
    graphs_path = PROCESSED_DIR / "graphs.json"
    if not graphs_path.exists():
        raise FileNotFoundError(f"Graphs file not found at {graphs_path}. "
                                "Ensure graph_builder has been run successfully.")
    
    with open(graphs_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def load_features_from_extractor() -> List[Dict[str, Any]]:
    """
    Load the topological features extracted by the topology_extractor module.
    This expects the features to be saved in data/processed/features.csv by the extractor.
    """
    features_path = PROCESSED_DIR / "features.csv"
    if not features_path.exists():
        raise FileNotFoundError(f"Features file not found at {features_path}. "
                                "Ensure topology_extractor has been run successfully.")
    
    with open(features_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        return list(reader)

def write_final_graphs_json(graphs: List[Dict[str, Any]]) -> None:
    """
    Write the final graph artifacts to data/processed/graphs.json.
    This ensures the data is persisted in the correct location for downstream tasks.
    """
    output_path = PROCESSED_DIR / "graphs.json"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(graphs, f, indent=2, default=str)
    
    logger.info(f"Successfully wrote {len(graphs)} graphs to {output_path}")

def write_final_features_csv(features: List[Dict[str, Any]]) -> None:
    """
    Write the final feature vectors to data/processed/features.csv.
    This ensures the data is persisted in the correct location for downstream tasks.
    """
    output_path = PROCESSED_DIR / "features.csv"
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    if not features:
        logger.warning("No features to write.")
        # Write an empty file with headers if possible, or just return
        # We need headers to be valid CSV even if empty
        with open(output_path, 'w', newline='', encoding='utf-8') as f:
            # Determine headers from the first item if available, otherwise use defaults
            headers = ["doc_id", "modularity", "avg_path_length", "avg_degree", "avg_betweenness"]
            f.write(",".join(headers) + "\n")
        return

    # Ensure consistent headers
    fieldnames = list(features[0].keys())
    
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(features)
    
    logger.info(f"Successfully wrote {len(features)} feature rows to {output_path}")

def run_pipeline():
    """
    Main pipeline execution for T016.
    1. Load graphs from the builder output.
    2. Load features from the extractor output.
    3. Write them to the final destinations (overwriting if necessary to ensure freshness).
    """
    try:
        logger.info("Starting T016 pipeline: Writing graph artifacts and feature vectors.")
        
        # Load intermediate artifacts
        graphs = load_graphs_from_builder()
        features = load_features_from_extractor()
        
        # Write final artifacts
        write_final_graphs_json(graphs)
        write_final_features_csv(features)
        
        logger.info("T016 pipeline completed successfully.")
        return True
        
    except Exception as e:
        logger.error(f"T016 pipeline failed with error: {e}", exc_info=True)
        return False

def main():
    success = run_pipeline()
    sys.exit(0 if success else 1)

if __name__ == "__main__":
    main()