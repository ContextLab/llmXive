    def test_06_end_to_end_data_flow(self):
        """Test that the entire statistical validation flow produces consistent results."""
        # 1. Load raw data
        retrieval_scores = load_retrieval_scores()
        retrieved_features = load_retrieved_features()
        
        # 2. Verify data counts match
        score_queries = set(s['query_id'] for s in retrieval_scores)
        feature_queries = set(f['query_id'] for f in retrieved_features)
        
        # Queries should align (or be a subset if some were dropped)
        assert score_queries.issubset(feature_queries) or feature_queries.issubset(score_queries), \
            "Query sets between scores and features are disjoint"
        
        # 3. Load computed metrics
        metrics_path = RESULTS_DIR / "metrics.json"
        with open(metrics_path, 'r') as f:
            metrics = json.load(f)
        
        # 4. Verify Recall@10 values are present and non-trivial
        recall_graph = float(metrics['recall_graph_at_10'])
        recall_neural = float(metrics['recall_neural_at_10'])
        
        assert 0.0 <= recall_graph <= 1.0, f"Graph Recall@10 out of range: {recall_graph}"
        assert 0.0 <= recall_neural <= 1.0, f"Neural Recall@10 out of range: {recall_neural}"
        
        # 5. Verify ratio matches the individual recalls
        computed_ratio = recall_graph / recall_neural if recall_neural > 0 else 0.0
        stored_ratio = float(metrics['ratio_graph_neural'])
        
        # Allow small floating point tolerance
        assert abs(computed_ratio - stored_ratio) < 1e-5, \
            f"Ratio mismatch: computed {computed_ratio}, stored {stored_ratio}"

