        """Ensure required artifacts exist before running tests."""
        # Check that prerequisite files exist (generated by T016, T022, T024, T028, T029)
        assert (PROCESSED_DIR / "features.csv").exists(), "Prerequisite: data/processed/features.csv missing"
        assert (RESULTS_DIR / "retrieval_scores.csv").exists(), "Prerequisite: data/results/retrieval_scores.csv missing"
