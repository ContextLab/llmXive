    def test_01_spearman_correlation_computation(self):
        """Test that Spearman correlation is correctly computed and stored."""
        # Load the correlation results (expected to be generated by T028/evaluator)
        # We verify the file exists and contains valid numeric data
        corr_csv_path = RESULTS_DIR / "correlation.csv"
        
        with open(corr_csv_path, 'r') as f:
            reader = csv.DictReader(f)
            rows = list(reader)
        
        assert len(rows) > 0, "Correlation CSV is empty"
        
        # Verify required columns exist
        required_cols = {'feature_name', 'spearman_r', 'p_value', 'n_samples'}
        assert required_cols.issubset(set(rows[0].keys())), f"Missing required columns in correlation.csv. Found: {rows[0].keys()}"
        
        # Verify numeric values are parseable and within expected ranges
        for row in rows:
            r_val = float(row['spearman_r'])
            p_val = float(row['p_value'])
            n_val = int(row['n_samples'])
            
            assert -1.0 <= r_val <= 1.0, f"Spearman r out of range: {r_val}"
            assert 0.0 <= p_val <= 1.0, f"P-value out of range: {p_val}"
            assert n_val > 0, f"Sample size must be positive: {n_val}"

