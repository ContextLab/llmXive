"""
Combine extracted ROI timecourses from T014, T015, T016 into a single CSV file.

This script loads the NumPy arrays generated by the previous extraction tasks
(roi_left_hipp.npy, roi_right_hipp.npy, roi_dlpfc.npy) and combines them into
a long-format CSV with columns: subject_id, roi, timepoint, signal.

Requires:
  - T014: data/processed/roi_left_hipp.npy
  - T015: data/processed/roi_right_hipp.npy
  - T016: data/processed/roi_dlpfc.npy
"""
import os
import sys
import json
import numpy as np
import pandas as pd
from pathlib import Path

# Add project root to path if running as script
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from utils.logging_config import get_logger, error, info, warning
from config import get_config

logger = get_logger(__name__)

def load_roi_timecourse(file_path: Path, roi_name: str) -> pd.DataFrame:
    """
    Load a single ROI timecourse NumPy array and convert to DataFrame.
    
    Args:
        file_path: Path to the .npy file
        roi_name: Name of the ROI (e.g., 'left_hipp', 'right_hipp', 'dlpfc')
        
    Returns:
        DataFrame with columns: subject_id, roi, timepoint, signal
        
    Raises:
        FileNotFoundError: If the file does not exist
        ValueError: If the data is empty or malformed
    """
    if not file_path.exists():
        logger.error(f"ROI timecourse file not found: {file_path}")
        raise FileNotFoundError(f"ROI timecourse file not found: {file_path}")
    
    logger.info(f"Loading {roi_name} timecourse from {file_path}")
    
    data = np.load(file_path)
    
    if data.size == 0:
        logger.error(f"ROI timecourse is empty: {file_path}")
        raise ValueError(f"ROI timecourse is empty: {file_path}")
    
    # Expected shape: (num_subjects, num_timepoints)
    # If 1D, reshape to (1, num_timepoints)
    if data.ndim == 1:
        data = data.reshape(1, -1)
    
    num_subjects, num_timepoints = data.shape
    logger.info(f"{roi_name}: {num_subjects} subjects, {num_timepoints} timepoints")
    
    # Generate subject IDs (sub-01 to sub-05 based on T014-T016 specs)
    subject_ids = [f"sub-{i:02d}" for i in range(1, num_subjects + 1)]
    
    # Create long-format DataFrame
    records = []
    for subj_idx, subj_id in enumerate(subject_ids):
        for timepoint in range(num_timepoints):
            signal = float(data[subj_idx, timepoint])
            records.append({
                'subject_id': subj_id,
                'roi': roi_name,
                'timepoint': timepoint,
                'signal': signal
            })
    
    df = pd.DataFrame(records)
    return df

def combine_roi_timecourses() -> pd.DataFrame:
    """
    Combine all ROI timecourses into a single DataFrame.
    
    Returns:
        Combined DataFrame with all ROIs
        
    Raises:
        FileNotFoundError: If any required input file is missing
        ValueError: If any input data is empty
    """
    config = get_config()
    processed_dir = project_root / "data" / "processed"
    
    roi_files = [
        (processed_dir / "roi_left_hipp.npy", "left_hipp"),
        (processed_dir / "roi_right_hipp.npy", "right_hipp"),
        (processed_dir / "roi_dlpfc.npy", "dlpfc"),
    ]
    
    dfs = []
    for file_path, roi_name in roi_files:
        df = load_roi_timecourse(file_path, roi_name)
        dfs.append(df)
    
    combined_df = pd.concat(dfs, ignore_index=True)
    
    # Sort by subject_id, then roi, then timepoint
    combined_df = combined_df.sort_values(
        by=['subject_id', 'roi', 'timepoint']
    ).reset_index(drop=True)
    
    logger.info(f"Combined {len(combined_df)} rows across {len(dfs)} ROIs")
    return combined_df

def main():
    """
    Main entry point for combining ROI timecourses.
    
    Outputs:
        data/processed/roi_timecourses.csv
    """
    try:
        logger.info("Starting ROI timecourse combination")
        
        combined_df = combine_roi_timecourses()
        
        output_path = project_root / "data" / "processed" / "roi_timecourses.csv"
        
        logger.info(f"Saving combined timecourses to {output_path}")
        combined_df.to_csv(output_path, index=False)
        
        logger.info(f"Successfully wrote {len(combined_df)} rows to {output_path}")
        
        # Verify output
        if output_path.exists():
            logger.info(f"Output file verified: {output_path}")
            info = output_path.stat()
            logger.info(f"File size: {info.st_size} bytes")
        else:
            logger.error("Output file was not created")
            raise RuntimeError("Output file was not created")
        
        return True
        
    except FileNotFoundError as e:
        logger.error(f"Missing required input file: {e}")
        raise
    except ValueError as e:
        logger.error(f"Invalid data: {e}")
        raise
    except Exception as e:
        logger.error(f"Unexpected error during combination: {e}")
        raise

if __name__ == "__main__":
    main()