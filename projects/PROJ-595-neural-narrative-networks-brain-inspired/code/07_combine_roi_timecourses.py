"""
Task T017: Combine extracted timecourses into a single CSV.

Reads the ROI timecourse files generated by T014, T015, and T016
(roi_left_hipp.npy, roi_right_hipp.npy, roi_dlpfc.npy) and combines them
into a single long-format CSV: data/processed/roi_timecourses.csv.

Columns: subject_id, roi, timepoint, signal
"""
import os
import sys
import json
import numpy as np
import pandas as pd
from pathlib import Path

# Ensure code directory is in path for relative imports if run as script
code_dir = Path(__file__).resolve().parent
if str(code_dir) not in sys.path:
    sys.path.insert(0, str(code_dir))

from utils.logging_config import get_logger, error, info, warning
from config import get_config

logger = get_logger(__name__)
config = get_config()

# Define expected input paths relative to project root
# Assuming the script is run from the project root or code_dir logic handles paths
PROJECT_ROOT = code_dir.parent
DATA_PROCESSED = PROJECT_ROOT / "data" / "processed"

INPUT_FILES = {
    "left_hipp": DATA_PROCESSED / "roi_left_hipp.npy",
    "right_hipp": DATA_PROCESSED / "roi_right_hipp.npy",
    "dlpfc": DATA_PROCESSED / "roi_dlpfc.npy",
}

OUTPUT_FILE = DATA_PROCESSED / "roi_timecourses.csv"

# ROI labels for the CSV
ROI_LABELS = {
    "left_hipp": "left_hippocampus",
    "right_hipp": "right_hippocampus",
    "dlpfc": "dlpfc",
}

def load_roi_timecourse(filepath: Path) -> np.ndarray:
    """
    Load a .npy file containing timecourse data.
    Expected shape: (n_subjects, n_timepoints) or (n_timepoints,) for single subject.
    We assume shape (n_subjects, n_timepoints) based on pipeline design.
    """
    if not filepath.exists():
        raise FileNotFoundError(f"Required input file missing: {filepath}")

    logger.info(f"Loading timecourse from {filepath}")
    data = np.load(filepath)

    if data.ndim == 1:
        # If 1D, assume it's a single subject. Reshape to (1, n_timepoints)
        logger.warning(f"Loaded 1D array from {filepath}. Reshaping to (1, n_timepoints).")
        data = data.reshape(1, -1)
    elif data.ndim != 2:
        raise ValueError(f"Unexpected array dimensions for {filepath}: {data.shape}. Expected (subjects, timepoints).")

    return data

def extract_subject_ids(n_subjects: int) -> list:
    """
    Generate subject IDs.
    Since the raw data loading (T012) and extraction (T014-T016) logic isn't fully
    visible here, we infer subject IDs based on the number of rows in the loaded arrays.
    In a real scenario, these might come from a manifest or be parsed from filenames.
    We'll use a generic 'sub-XXX' format.
    """
    return [f"sub-{str(i+1).zfill(3)}" for i in range(n_subjects)]

def combine_roi_timecourses():
    """
    Main logic for T017: Combine timecourses into a single CSV.
    """
    logger.info("Starting T017: Combine ROI timecourses.")

    # Check for existence of all required inputs
    missing_files = [k for k, v in INPUT_FILES.items() if not v.exists()]
    if missing_files:
        error_str = f"Missing required input files for T017: {missing_files}. " \
                    "Ensure T014, T015, and T016 have completed successfully."
        logger.error(error_str)
        raise RuntimeError(error_str)

    # Load data
    data_left = load_roi_timecourse(INPUT_FILES["left_hipp"])
    data_right = load_roi_timecourse(INPUT_FILES["right_hipp"])
    data_dlpfc = load_roi_timecourse(INPUT_FILES["dlpfc"])

    # Verify dimensions match
    if not (data_left.shape == data_right.shape == data_dlpfc.shape):
        raise ValueError(
            f"Dimension mismatch in loaded timecourses. "
            f"Left Hipp: {data_left.shape}, Right Hipp: {data_right.shape}, DLPFC: {data_dlpfc.shape}. "
            "All ROIs must have the same number of subjects and timepoints."
        )

    n_subjects, n_timepoints = data_left.shape
    logger.info(f"Loaded data: {n_subjects} subjects, {n_timepoints} timepoints.")

    subject_ids = extract_subject_ids(n_subjects)

    # Build the long-format list
    rows = []
    for s_idx, sub_id in enumerate(subject_ids):
        for t_idx in range(n_timepoints):
            # Left Hippocampus
            rows.append({
                "subject_id": sub_id,
                "roi": ROI_LABELS["left_hipp"],
                "timepoint": t_idx,
                "signal": float(data_left[s_idx, t_idx])
            })
            # Right Hippocampus
            rows.append({
                "subject_id": sub_id,
                "roi": ROI_LABELS["right_hipp"],
                "timepoint": t_idx,
                "signal": float(data_right[s_idx, t_idx])
            })
            # DLPFC
            rows.append({
                "subject_id": sub_id,
                "roi": ROI_LABELS["dlpfc"],
                "timepoint": t_idx,
                "signal": float(data_dlpfc[s_idx, t_idx])
            })

    # Create DataFrame
    df = pd.DataFrame(rows, columns=["subject_id", "roi", "timepoint", "signal"])

    # Ensure output directory exists
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)

    # Save to CSV
    logger.info(f"Saving combined timecourses to {OUTPUT_FILE}")
    df.to_csv(OUTPUT_FILE, index=False)

    logger.info(f"T017 complete. Output saved to {OUTPUT_FILE}")
    return OUTPUT_FILE

def main():
    """Entry point for script execution."""
    try:
        combine_roi_timecourses()
        logger.info("T017 execution successful.")
    except Exception as e:
        logger.error(f"T017 execution failed: {str(e)}")
        sys.exit(1)

if __name__ == "__main__":
    main()
