"""
T016: Extract BOLD timecourses for DLPFC from OpenNeuro ds001495.

This script processes ALL available subjects found in data/raw/openneuro_ds001495/,
extracts the DLPFC timecourse using masks defined in T013, and saves the result
to data/processed/roi_dlpfc.npy.

Dependencies:
  - T012: Raw data must exist at data/raw/openneuro_ds001495/
  - T013: Mask paths must be defined in data/processed/mask_paths.json
"""
import os
import sys
import glob
import json
import numpy as np
import nibabel as nib
from pathlib import Path

# Project root relative to this script (assumed to be run from project root)
PROJECT_ROOT = Path(__file__).resolve().parent.parent

# Constants
DATA_RAW_DIR = PROJECT_ROOT / "data" / "raw" / "openneuro_ds001495"
MASK_PATHS_FILE = PROJECT_ROOT / "data" / "processed" / "mask_paths.json"
OUTPUT_FILE = PROJECT_ROOT / "data" / "processed" / "roi_dlpfc.npy"

# Error codes from logging_config
ERROR_E001 = "E001"  # Data corruption/missing files
ERROR_E002 = "E002"  # Empty timepoints/data

def log_error(code: str, message: str):
    """Print error to stderr and exit."""
    sys.stderr.write(f"{code}: {message}\n")
    sys.exit(1)

def natural_sort_key(s: str):
    """
    Generate a key for natural sorting (e.g., 'sub-01' < 'sub-02' < 'sub-10').
    """
    import re
    return [int(c) if c.isdigit() else c.lower() for c in re.split(r'(\d+)', s)]

def load_mask_from_json():
    """
    Load the DLPFC mask path from the JSON file generated by T013.
    """
    if not MASK_PATHS_FILE.exists():
        log_error(ERROR_E001, f"Mask paths file not found: {MASK_PATHS_FILE}")

    with open(MASK_PATHS_FILE, 'r') as f:
        mask_data = json.load(f)

    if 'dlpfc' not in mask_data:
        log_error(ERROR_E001, "DLPFC mask path not found in mask_paths.json")

    mask_path = PROJECT_ROOT / mask_data['dlpfc']
    if not mask_path.exists():
        log_error(ERROR_E001, f"DLPFC mask file not found: {mask_path}")

    return mask_path

def find_functional_runs(subject_dir: Path) -> list:
    """
    Find all functional NIfTI files matching the task-narratives pattern.
    """
    pattern = subject_dir / "func" / "*task-narratives_bold.nii.gz"
    files = sorted(glob.glob(str(pattern)))
    return files

def extract_roi_timecourse(nifti_path: Path, mask_path: Path) -> np.ndarray:
    """
    Load a NIfTI file, apply the mask, and average voxels across time.

    Returns:
        1D numpy array of mean BOLD signal over time.
    """
    # Load image and mask
    img = nib.load(str(nifti_path))
    mask = nib.load(str(mask_path))

    # Ensure data and mask are aligned (same affine and shape)
    # Nifti1Image.get_fdata() returns float64
    data = img.get_fdata()
    mask_data = mask.get_fdata()

    # If shapes don't match, we might need to resample, but for now assume alignment
    # as per T013 generation logic (same MNI space, 2mm isotropic)
    if data.shape[:3] != mask_data.shape[:3]:
        log_error(ERROR_E001, f"Shape mismatch: NIfTI {data.shape[:3]} vs Mask {mask_data.shape[:3]}")

    # Apply mask: keep only voxels where mask > 0
    # Flatten the spatial dimensions
    n_voxels = data.shape[0] * data.shape[1] * data.shape[2]
    n_timepoints = data.shape[3]

    # Reshape to (n_voxels, n_timepoints)
    data_flat = data.reshape(n_voxels, n_timepoints)
    mask_flat = mask_data.flatten()

    # Select voxels where mask is non-zero
    valid_voxels = mask_flat > 0
    if not np.any(valid_voxels):
        log_error(ERROR_E002, f"No valid voxels found in mask for {nifti_path}")

    # Average signal across valid voxels for each timepoint
    roi_signal = data_flat[valid_voxels, :].mean(axis=0)

    return roi_signal

def process_subject(subject_dir: Path, mask_path: Path) -> tuple:
    """
    Process a single subject: find runs, extract timecourse, return (subject_id, timecourse).
    """
    subject_id = subject_dir.name

    func_files = find_functional_runs(subject_dir)
    if not func_files:
        # If no functional runs found for this subject, skip or warn?
        # The task says "Process ALL available subjects found", implying we process
        # what exists. If a subject has no data, we might skip or raise E002.
        # Let's log a warning but continue if other subjects exist.
        # However, strict interpretation: if a subject is found but has no data, it's E002.
        # For robustness, we'll skip subjects with no functional runs but log it.
        # But the task says "If timecourses empty, halt with E002".
        # So if we find a subject dir but no files, we might have an issue.
        # Let's assume the subject dir implies data exists. If not, we raise E002.
        log_error(ERROR_E002, f"No functional runs found for subject {subject_id}")

    # Combine multiple runs if present (concatenate timecourses)
    all_timecourses = []
    for f in func_files:
        try:
            tc = extract_roi_timecourse(f, mask_path)
            all_timecourses.append(tc)
        except Exception as e:
            log_error(ERROR_E001, f"Failed to process {f}: {e}")

    if not all_timecourses:
        log_error(ERROR_E002, f"No timecourses extracted for subject {subject_id}")

    # Concatenate runs
    combined_tc = np.concatenate(all_timecourses)
    return subject_id, combined_tc

def main():
    """Main entry point for T016."""
    # 1. Check T012 artifacts (Raw data directory)
    if not DATA_RAW_DIR.exists():
        log_error(ERROR_E001, f"Raw data directory not found: {DATA_RAW_DIR}")

    # 2. Load T013 mask
    mask_path = load_mask_from_json()

    # 3. Discover all subjects
    # Pattern: data/raw/openneuro_ds001495/sub-*/
    subject_pattern = DATA_RAW_DIR / "sub-*"
    subject_dirs = sorted(glob.glob(str(subject_pattern)), key=natural_sort_key)

    if not subject_dirs:
        log_error(ERROR_E001, f"No subjects found in {DATA_RAW_DIR}")

    # 4. Process each subject
    results = []
    for subj_dir in subject_dirs:
        subj_path = Path(subj_dir)
        try:
            subj_id, timecourse = process_subject(subj_path, mask_path)
            results.append((subj_id, timecourse))
        except SystemExit:
            raise
        except Exception as e:
            log_error(ERROR_E001, f"Unexpected error processing {subj_path}: {e}")

    # 5. Verify results are not empty
    if not results:
        log_error(ERROR_E002, "No timecourses extracted for any subject.")

    # 6. Save results
    # Format: List of tuples (subject_id, timecourse_array)
    # We save as a structured array or a list of objects?
    # The task says "Save to data/processed/roi_dlpfc.npy".
    # T014/T015 likely save similar structures. Let's save as a dict or list of tuples.
    # To be consistent with numpy saving, we can save a list of (id, array) or a structured array.
    # Given the varying lengths of timecourses (if runs differ), a list of tuples is safer.
    # Or we can pad them. The task doesn't specify padding here, that's T019.
    # So we save the raw extracted arrays.
    output_data = {
        'subject_ids': [r[0] for r in results],
        'timecourses': [r[1] for r in results]
    }

    # Ensure output directory exists
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)

    np.save(str(OUTPUT_FILE), output_data, allow_pickle=True)

    print(f"T016 Complete: Saved DLPFC timecourses for {len(results)} subjects to {OUTPUT_FILE}")

if __name__ == "__main__":
    main()