"""
T033: Run utils/checksums.py after generation and update state file.

This script computes checksums for all generated story artifacts (brain_stories.jsonl
and baseline_stories.jsonl) and updates the project state file to record the
derivation chain for User Story 2 outputs.

Outputs:
    - Updates state/state.json with new checksums for generated files.
    - Logs operation to logs/pipeline.log.
"""

import os
import sys
from pathlib import Path

# Add project root to path if running as script
if __name__ == "__main__":
    project_root = Path(__file__).resolve().parent.parent
    sys.path.insert(0, str(project_root))

from utils.checksums import compute_directory_checksums, update_state_file, load_state_file
from utils.logging_config import get_logger, info, error, warning
from config import get_config


def main():
    """
    Compute checksums for generation outputs and update state file.
    """
    config = get_config()
    logger = get_logger()

    info("T033: Starting checksum update for generation outputs")

    # Define paths relative to project root
    project_root = Path(__file__).resolve().parent.parent
    results_dir = project_root / "data" / "results"
    state_file_path = project_root / "state" / "state.json"

    # Ensure results directory exists
    if not results_dir.exists():
        error(f"Results directory not found: {results_dir}")
        sys.exit(1)

    # Files to checksum (generated by T030 and T031)
    generation_files = [
        "brain_stories.jsonl",
        "baseline_stories.jsonl"
    ]

    # Check if files exist
    missing_files = []
    existing_files = []

    for filename in generation_files:
        filepath = results_dir / filename
        if filepath.exists():
            existing_files.append(filepath)
            info(f"Found generation output: {filepath}")
        else:
            missing_files.append(filename)
            warning(f"Generation output missing (expected): {filepath}")

    if not existing_files:
        error("No generation outputs found. T030 and T031 must complete first.")
        sys.exit(1)

    if missing_files:
        warning(f"Missing expected outputs: {missing_files}. Proceeding with available files.")

    # Compute checksums for existing files
    try:
        checksums = compute_directory_checksums(results_dir, patterns=["*.jsonl"])
        info(f"Computed checksums for {len(checksums)} files in {results_dir}")
    except Exception as e:
        error(f"Failed to compute checksums: {e}")
        sys.exit(1)

    # Update state file
    try:
        if state_file_path.exists():
            state = load_state_file(state_file_path)
            info(f"Loaded existing state file: {state_file_path}")
        else:
            state = {
                "project": "PROJ-595-neural-narrative-networks-brain-inspired",
                "version": "1.0.0",
                "checksums": {}
            }
            info(f"Created new state file: {state_file_path}")

        # Update checksums in state
        state["checksums"].update(checksums)
        state["last_updated"] = "T033: Generation checksums updated"

        update_state_file(state_file_path, state)
        info(f"Updated state file: {state_file_path}")

    except Exception as e:
        error(f"Failed to update state file: {e}")
        sys.exit(1)

    info("T033: Checksum update completed successfully")
    return 0


if __name__ == "__main__":
    sys.exit(main())