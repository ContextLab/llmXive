logger = get_logger(__name__)

def load_mask_from_json(mask_json_path: str, roi_name: str) -> np.ndarray:
    """
    Load ROI mask from the mask_paths.json file generated by T013.
    """
    if not os.path.exists(mask_json_path):
        raise FileNotFoundError(f"Mask configuration file not found: {mask_json_path}")

    with open(mask_json_path, 'r') as f:
        mask_config = json.load(f)

    if roi_name not in mask_config:
        raise KeyError(f"ROI '{roi_name}' not found in mask configuration. Available: {list(mask_config.keys())}")

    mask_path = mask_config[roi_name]
    if not os.path.exists(mask_path):
        raise FileNotFoundError(f"Mask file referenced in config not found: {mask_path}")

    logger.info(f"Loading mask for {roi_name} from {mask_path}")
    mask_img = nib.load(mask_path)
    mask_data = mask_img.get_fdata()
    return mask_data

def find_functional_runs(subject_dir: Path) -> list:
    """
    Find all functional runs matching the task-narratives pattern.
    """
    func_dir = subject_dir / "func"
    if not func_dir.exists():
        return []

    pattern = "*task-narratives*.nii.gz"
    runs = sorted(func_dir.glob(pattern))
    return runs

def extract_roi_timecourse(nifti_path: str, mask_data: np.ndarray) -> np.ndarray:
    """
    Extract mean BOLD timecourse from a 4D NIfTI file using a binary mask.
    Returns a 1D array of shape (timepoints,).
    """
    logger.debug(f"Processing volume: {nifti_path}")
    img = nib.load(nifti_path)
    data = img.get_fdata()

    if data.ndim != 4:
        raise ValueError(f"Expected 4D data, got {data.ndim}D from {nifti_path}")

    # Ensure mask matches spatial dimensions
    if mask_data.shape != data.shape[:3]:
        # Attempt to resample or raise error. For robustness, we check if mask is 3D and data is 4D.
        # If mask is smaller, we might need to handle it, but typically masks match the EPI resolution.
        # If strictly mismatched, we cannot proceed safely without resampling.
        raise ValueError(f"Mask shape {mask_data.shape} does not match data spatial shape {data.shape[:3]}")

    timepoints = data.shape[3]
    timecourse = np.zeros(timepoints, dtype=np.float32)

    # Apply mask and compute mean across voxels for each timepoint
    # Vectorized operation: mask_data is (X, Y, Z), data is (X, Y, Z, T)
    # We want mean of data[mask_data > 0] for each t
    masked_data = data[mask_data > 0] # This flattens spatial dims where mask is active
    
    # Reshape masked_data to (num_voxels, timepoints) if possible, or iterate
    # Better approach: reshape data to (num_voxels, timepoints)
    num_voxels = np.sum(mask_data > 0)
    if num_voxels == 0:
        logger.warning(f"No voxels active in mask for {nifti_path}. Returning zeros.")
        return timecourse

    # Reshape data to (num_voxels, timepoints)
    # We need to select only the voxels where mask > 0
    # Using advanced indexing
    voxels = data[mask_data > 0]
    # voxels shape: (num_voxels, timepoints)
    timecourse = np.mean(voxels, axis=0)

    return timecourse

def process_subject(subject_id: str, data_root: Path, mask_data: np.ndarray) -> tuple:
    """
    Process a single subject: find runs, extract timecourses, concatenate.
    Returns (subject_id, timecourse_array) or (subject_id, None) if failure.
    """
    subject_dir = data_root / subject_id
    if not subject_dir.exists():
        logger.warning(f"Subject directory not found: {subject_dir}")
        return subject_id, None

    runs = find_functional_runs(subject_dir)
    if not runs:
        logger.warning(f"No functional runs found for {subject_id} matching task-narratives")
        return subject_id, None

    all_timecourses = []
    for run_path in runs:
        try:
            tc = extract_roi_timecourse(str(run_path), mask_data)
            if tc.size > 0:
                all_timecourses.append(tc)
            else:
                logger.warning(f"Empty timecourse for run {run_path}")
        except Exception as e:
            logger.error(f"Failed to process run {run_path} for {subject_id}: {e}")
            raise e

    if not all_timecourses:
        return subject_id, None

    # Concatenate timecourses from all runs
    combined_tc = np.concatenate(all_timecourses)
    return subject_id, combined_tc

def main():
    """
    Main entry point for T016: Extract DLPFC timecourses.
    """
    config = get_config()
    data_root = Path("data/raw/openneuro_ds001495")
    mask_json_path = "data/processed/mask_paths.json"
    output_path = "data/processed/roi_dlpfc.npy"
    roi_name = "dlpfc"

    # Check prerequisites
    if not data_root.exists():
        error("E001", f"Data root directory not found: {data_root}. T012 artifacts missing.")
        sys.exit(1)

    if not os.path.exists(mask_json_path):
        error("E001", f"Mask configuration not found: {mask_json_path}. T013 artifacts missing.")
        sys.exit(1)

    logger.info(f"Starting DLPFC timecourse extraction for subjects sub-01 to sub-05")

    try:
        mask_data = load_mask_from_json(mask_json_path, roi_name)
    except (FileNotFoundError, KeyError) as e:
        error("E001", f"Failed to load mask: {e}")
        sys.exit(1)

    subjects = [f"sub-{i:02d}" for i in range(1, 6)]
    results = {}
    valid_count = 0

    for sub_id in subjects:
        try:
            sub_id_clean, tc = process_subject(sub_id, data_root, mask_data)
            if tc is not None:
                results[sub_id_clean] = tc
                valid_count += 1
                logger.info(f"Processed {sub_id_clean}: {tc.size} timepoints")
            else:
                logger.warning(f"Skipping {sub_id_clean}: No data extracted")
        except Exception as e:
            logger.error(f"Critical error processing {sub_id}: {e}")
            error("E001", f"Data processing failed for {sub_id}: {e}")
            sys.exit(1)

    if valid_count == 0:
        error("E002", "No valid timecourses extracted for any subject. Data may be empty or corrupted.")
        sys.exit(1)

    # Save results
    # Structure: Dictionary of {subject_id: np.array}
    # Or a stacked array if shapes are uniform? The task says "Save to ...npy".
    # To be safe and preserve subject info, we save a dict or a list of arrays.
    # Given T017a expects to combine them, saving a dict with subject keys is robust.
    output_dir = Path(output_path).parent
    output_dir.mkdir(parents=True, exist_ok=True)

    logger.info(f"Saving DLPFC timecourses to {output_path}")
    np.save(output_path, results)

    logger.info(f"Successfully extracted DLPFC timecourses for {valid_count}/{len(subjects)} subjects.")

if __name__ == "__main__":
    main()