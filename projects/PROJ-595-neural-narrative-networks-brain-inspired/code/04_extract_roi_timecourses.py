"""
Extract ROI timecourses from fMRI data for a specific region of interest.
This module is generic and can be used for Left Hippocampus, Right Hippocampus, or DLPFC
by specifying the ROI name and mask path.
"""
import os
import sys
import json
import glob
import numpy as np
import nibabel as nib
from pathlib import Path
from typing import Dict, List, Any, Optional, Tuple

# Import project configuration and utilities
from config import get_config
from utils.logging_config import get_logger, error, info, warning, critical
from utils.checksums import compute_sha256

# Error codes
E001 = "E001"  # Data corruption/missing files
E002 = "E002"  # Empty timepoints/data

def natural_sort_key(s: str) -> List:
    """
    Generate a key for natural sorting of subject IDs (e.g., 'sub-01', 'sub-02', ... 'sub-10').
    """
    import re
    return [int(text) if text.isdigit() else text.lower()
            for text in re.split('([0-9]+)', s)]

def load_mask_from_json(mask_json_path: str) -> Tuple[nib.Nifti1Image, str]:
    """
    Load ROI mask paths from the JSON file generated by T013.
    Returns the mask image and the specific mask path used.
    """
    if not os.path.exists(mask_json_path):
        error(f"{E001}: Mask JSON file not found: {mask_json_path}")
        sys.exit(1)

    with open(mask_json_path, 'r') as f:
        mask_data = json.load(f)

    # Determine which mask to load based on the ROI name (passed via environment or hardcoded for this task)
    # For T015, we specifically need 'right_hipp'
    roi_key = 'right_hipp'
    if roi_key not in mask_data:
        error(f"{E001}: ROI key '{roi_key}' not found in mask JSON. Available keys: {list(mask_data.keys())}")
        sys.exit(1)

    mask_path = mask_data[roi_key]
    if not os.path.exists(mask_path):
        error(f"{E001}: Mask file not found at path: {mask_path}")
        sys.exit(1)

    mask_img = nib.load(mask_path)
    info(f"Loaded mask for {roi_key} from {mask_path}")
    return mask_img, mask_path

def find_functional_runs(subject_dir: Path) -> List[Path]:
    """
    Find all functional NIfTI files matching the task-narratives pattern.
    Input Pattern: sub-*/func/*task-narratives_bold.nii.gz
    """
    func_pattern = str(subject_dir / "func" / "*task-narratives_bold.nii.gz")
    runs = glob.glob(func_pattern)
    if not runs:
        # Try .nii extension as well
        func_pattern_nii = str(subject_dir / "func" / "*task-narratives_bold.nii")
        runs = glob.glob(func_pattern_nii)
    
    return [Path(r) for r in runs]

def extract_roi_timecourse(nifti_path: Path, mask_img: nib.Nifti1Image) -> Optional[np.ndarray]:
    """
    Extract average BOLD timecourse for the ROI from a single NIfTI file.
    """
    try:
        func_img = nib.load(str(nifti_path))
    except Exception as e:
        warning(f"Failed to load NIfTI {nifti_path}: {e}")
        return None

    # Ensure mask and functional image are in the same space (basic check)
    # In a robust pipeline, we would resample, but for this task we assume alignment
    # as per T013 mask generation logic.
    
    # Get data arrays
    func_data = func_img.get_fdata()
    mask_data = mask_img.get_fdata()

    # Check for empty data
    if func_data.size == 0:
        return None

    # Reshape to (x, y, z, t) if necessary
    if len(func_data.shape) == 3:
        # Single volume? Not expected for fMRI time series, but handle gracefully
        func_data = func_data[..., np.newaxis]
    
    if len(func_data.shape) != 4:
        warning(f"Unexpected data shape for {nifti_path}: {func_data.shape}")
        return None

    # Apply mask: average over voxels where mask > 0
    # Ensure mask is boolean or > 0
    mask_bool = mask_data > 0
    
    # Reshape to (V, T) where V is number of voxels
    voxels = func_data[mask_bool]
    if voxels.ndim == 1:
        # If only one timepoint or one voxel, reshape to (1, T) or (V, 1)
        # We expect (V, T)
        # If voxels is 1D, it might be (V,) or (T,) depending on how numpy indexed
        # Standard masking on (X,Y,Z,T) -> (V, T) if mask is (X,Y,Z)
        # Let's assume standard: mask is 3D, func is 4D.
        # np.where on 3D mask returns indices.
        # func_data[mask_bool] flattens the spatial dims, keeping time?
        # Actually: func_data[mask_bool] where mask_bool is 3D and func is 4D
        # This returns a 2D array of shape (num_voxels, time) if mask is broadcast correctly?
        # No, standard numpy indexing: func_data[mask_bool] will flatten spatial and time if mask is 4D?
        # mask_data is 3D. func_data is 4D.
        # We need to apply the mask to the first 3 dimensions.
        
        # Correct approach:
        # 1. Reshape func to (V, T) where V = X*Y*Z
        # 2. Apply mask to select rows
        x, y, z, t = func_data.shape
        func_flat = func_data.reshape(x*y*z, t)
        mask_flat = mask_data.flatten()
        roi_data = func_flat[mask_flat > 0]
        
        if roi_data.size == 0:
            return None
        
        # Average over voxels
        mean_timecourse = np.mean(roi_data, axis=0)
        return mean_timecourse
    
    # Fallback for the 2D case (V, T)
    if voxels.ndim == 2:
        return np.mean(voxels, axis=0)
    
    return None

def process_subject(subject_dir: Path, mask_img: nib.Nifti1Image, output_times: List, subject_ids: List):
    """
    Process a single subject directory: find runs, extract timecourses, and aggregate.
    """
    runs = find_functional_runs(subject_dir)
    if not runs:
        warning(f"No functional runs found for subject: {subject_dir}")
        return

    # Extract timecourse for each run and concatenate (or average if multiple runs)
    # For simplicity in this task, we assume one run or concatenate them.
    # The task says "Average Voxels, Save NPY". We will concatenate timepoints from all runs.
    
    all_run_data = []
    for run_path in runs:
        data = extract_roi_timecourse(run_path, mask_img)
        if data is not None:
            all_run_data.append(data)
    
    if not all_run_data:
        warning(f"No valid timecourse data extracted for subject: {subject_dir}")
        return

    # Concatenate timecourses along the time axis
    combined_timecourse = np.concatenate(all_run_data, axis=0)

    if combined_timecourse.size == 0:
        error(f"{E002}: Extracted timecourse is empty for subject: {subject_dir}")
        sys.exit(1)

    subject_id = subject_dir.name
    output_times.append(combined_timecourse)
    subject_ids.append(subject_id)
    info(f"Processed subject {subject_id}: {len(combined_timecourse)} timepoints")

def main():
    """
    Main entry point for extracting Right Hippocampus timecourses.
    """
    config = get_config()
    logger = get_logger()
    
    # Paths
    raw_data_dir = Path("data/raw/openneuro_ds001495")
    mask_json_path = Path("data/processed/mask_paths.json")
    output_path = Path("data/processed/roi_right_hipp.npy")
    
    # Verify T012 artifacts (Raw data directory)
    if not raw_data_dir.exists():
        error(f"{E001}: Raw data directory not found: {raw_data_dir}")
        sys.exit(1)
    
    # Verify T013 artifacts (Mask JSON)
    if not mask_json_path.exists():
        error(f"{E001}: Mask JSON file not found: {mask_json_path}. Ensure T013 is complete.")
        sys.exit(1)

    # Load mask
    mask_img, _ = load_mask_from_json(str(mask_json_path))

    # Discover subjects
    # Pattern: sub-*/func/...
    subjects = sorted(glob.glob(str(raw_data_dir / "sub-*")), key=natural_sort_key)
    
    if not subjects:
        error(f"{E001}: No subject directories found in {raw_data_dir}")
        sys.exit(1)

    # Limit to first 10 subjects or all if < 10
    subjects_to_process = subjects[:10] if len(subjects) >= 10 else subjects
    info(f"Processing {len(subjects_to_process)} subjects (Total found: {len(subjects)})")

    all_timecourses = []
    all_subject_ids = []

    for subj_path in subjects_to_process:
        process_subject(Path(subj_path), mask_img, all_timecourses, all_subject_ids)

    if not all_timecourses:
        error(f"{E002}: No timecourse data extracted. Check input data and masks.")
        sys.exit(1)

    # Determine max timepoints to pad to (for array creation)
    # Or store as object array if lengths vary significantly
    # For simplicity, we assume similar lengths or pad with NaN
    max_len = max(len(tc) for tc in all_timecourses)
    
    # Create output array: shape (num_subjects, max_timepoints)
    # If lengths vary, we pad with NaN
    output_array = np.full((len(all_timecourses), max_len), np.nan, dtype=np.float32)
    
    for i, tc in enumerate(all_timecourses):
        output_array[i, :len(tc)] = tc

    # Save
    output_path.parent.mkdir(parents=True, exist_ok=True)
    np.save(str(output_path), output_array)
    
    # Save subject IDs separately for reference
    subject_ids_path = Path("data/processed/roi_right_hipp_subject_ids.npy")
    np.save(str(subject_ids_path), np.array(all_subject_ids))

    info(f"Successfully saved Right Hippocampus timecourses to {output_path}")
    info(f"Shape: {output_array.shape}, Subjects: {len(all_subject_ids)}")

    # Compute checksum for integrity
    checksum = compute_sha256(str(output_path))
    info(f"Checksum: {checksum}")

if __name__ == "__main__":
    main()