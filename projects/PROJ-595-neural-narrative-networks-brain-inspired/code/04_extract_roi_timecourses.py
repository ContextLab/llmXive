import os
import sys
import json
import glob
import numpy as np
import nibabel as nib
from pathlib import Path
from utils.logging_config import get_logger, error, info, warning, critical
from config import get_config

def natural_sort_key(s):
    """
    Generate a sort key for natural sorting strings containing numbers.
    E.g., 'sub-01', 'sub-02', 'sub-10' -> ['sub-', 1, '', 2] vs ['sub-', 10, '', '']
    """
    import re
    return [int(text) if text.isdigit() else text.lower()
            for text in re.split('([0-9]+)', s)]

def load_mask_from_json(mask_json_path, roi_name):
    """
    Load mask paths from the JSON file generated by T013.
    Returns the path to the specific ROI mask.
    """
    try:
        with open(mask_json_path, 'r') as f:
            mask_data = json.load(f)
        
        if roi_name not in mask_data:
            error(f"ROI '{roi_name}' not found in mask JSON at {mask_json_path}")
            return None
        
        return mask_data[roi_name]
    except Exception as e:
        error(f"Failed to load mask JSON: {e}")
        return None

def find_functional_runs(subject_dir):
    """
    Find all functional NIfTI files matching the task-narratives pattern.
    Returns a sorted list of file paths.
    """
    func_pattern = os.path.join(subject_dir, 'func', '*task-narratives_bold.nii.gz')
    files = glob.glob(func_pattern)
    if not files:
        # Try .nii if .nii.gz not found
        func_pattern = os.path.join(subject_dir, 'func', '*task-narratives_bold.nii')
        files = glob.glob(func_pattern)
    
    return sorted(files, key=natural_sort_key)

def extract_roi_timecourse(nifti_path, mask_path):
    """
    Load NIfTI image, apply mask, and average voxels across time.
    Returns a 1D numpy array of timepoints.
    """
    try:
        # Load image and mask
        img = nib.load(nifti_path)
        mask = nib.load(mask_path)
        
        data = img.get_fdata()
        mask_data = mask.get_fdata()
        
        # Ensure mask is binary
        mask_binary = mask_data > 0
        
        # Check if mask has any valid voxels
        if not np.any(mask_binary):
            warning(f"Mask for {nifti_path} is empty after loading.")
            return None
        
        # Average across masked voxels for each timepoint
        # data shape: (x, y, z, time)
        if data.ndim == 4:
            time_series = data[mask_binary]
            if time_series.size == 0:
                warning(f"No valid voxels in mask for {nifti_path}")
                return None
            
            # Average across voxels (axis 1) to get time series (time,)
            mean_time_series = np.mean(time_series, axis=1)
            return mean_time_series
        else:
            error(f"Unexpected NIfTI dimensions: {data.ndim}D. Expected 4D.")
            return None
            
    except Exception as e:
        error(f"Failed to extract timecourse from {nifti_path}: {e}")
        return None

def process_subject(subject_dir, mask_path, output_list):
    """
    Process a single subject directory.
    Finds all functional runs, extracts timecourse for each, and appends to output_list.
    """
    subject_id = os.path.basename(subject_dir)
    info(f"Processing subject: {subject_id}")
    
    runs = find_functional_runs(subject_dir)
    if not runs:
        warning(f"No functional runs found for subject {subject_id}")
        return False
    
    all_timepoints = []
    for run_path in runs:
        ts = extract_roi_timecourse(run_path, mask_path)
        if ts is not None:
            all_timepoints.append(ts)
        else:
            warning(f"Skipping run {run_path} due to extraction failure")
    
    if not all_timepoints:
        error(f"No valid timepoints extracted for subject {subject_id}")
        return False
    
    # Concatenate all runs for this subject
    combined_ts = np.concatenate(all_timepoints)
    
    if len(combined_ts) == 0:
        error(f"Combined timecourse is empty for subject {subject_id}")
        return False
    
    # Store as tuple (subject_id, timepoints_array)
    output_list.append((subject_id, combined_ts))
    info(f"Successfully processed subject {subject_id}: {len(combined_ts)} timepoints")
    return True

def main():
    """
    Main entry point for T014: Extract BOLD timecourses for Left Hippocampus.
    """
    config = get_config()
    logger = get_logger()
    
    # Paths
    raw_data_dir = Path("data/raw/openneuro_ds001495")
    mask_json_path = Path("data/processed/mask_paths.json")
    output_path = Path("data/processed/roi_left_hipp.npy")
    
    # Check prerequisites (T012 artifacts)
    if not raw_data_dir.exists():
        error("E001: Raw data directory 'data/raw/openneuro_ds001495' not found. T012 may have failed.")
        sys.exit(1)
    
    # Check mask file (T013 artifacts)
    if not mask_json_path.exists():
        error("E001: Mask paths file 'data/processed/mask_paths.json' not found. T013 may have failed.")
        sys.exit(1)
    
    # Load mask path for Left Hippocampus
    mask_path = load_mask_from_json(str(mask_json_path), "left_hipp")
    if not mask_path or not os.path.exists(mask_path):
        error(f"E001: Left Hippocampus mask not found at {mask_path}. T013 may have failed.")
        sys.exit(1)
    
    # Discover all subject directories
    subject_pattern = os.path.join(str(raw_data_dir), 'sub-*')
    subjects = glob.glob(subject_pattern)
    
    if not subjects:
        error("E001: No subject directories (sub-*) found in raw data directory.")
        sys.exit(1)
    
    # Sort subjects using natural sort
    subjects = sorted(subjects, key=lambda x: natural_sort_key(os.path.basename(x)))
    
    info(f"Found {len(subjects)} subjects to process.")
    
    # Process all subjects
    results = []
    for subj_dir in subjects:
        success = process_subject(subj_dir, mask_path, results)
        if not success:
            warning(f"Subject {os.path.basename(subj_dir)} failed processing but continuing...")
    
    # Check if we have any valid results
    if not results:
        error("E002: No valid timecourses extracted. All subjects failed or produced empty data.")
        sys.exit(1)
    
    # Sort results by subject ID to ensure consistent order
    results.sort(key=lambda x: natural_sort_key(x[0]))
    
    # Create structured array for output
    # We need to handle variable length timecourses.
    # Strategy: Pad all to the maximum length found, or store as object array.
    # The task says "Save NPY". A 2D array (subjects, timepoints) is standard.
    # We will pad with NaN for subjects with fewer timepoints.
    
    max_len = max(len(ts) for _, ts in results)
    subject_ids = [s[0] for s in results]
    
    # Create output array: shape (num_subjects, max_len)
    # dtype: object to store strings for IDs? Or separate array for IDs?
    # The task says "Save NPY". Usually this implies the data array.
    # Let's create a structured array or a dict-like approach if needed.
    # However, standard practice for timecourse comparison is a 2D float array.
    # We will save the timecourse matrix and a separate file for subject IDs if needed,
    # OR save a structured array if the schema requires it.
    # Given the next task (T019) expects a structured array with subject_id, roi, timepoint, signal,
    # we should probably save the raw matrix here and let T019 handle the structuring,
    # OR save a structured array here.
    # Let's save a 2D float array (padded) and a separate list of IDs in the same .npz or just the array.
    # The task specifically says "Save NPY". Let's save the 2D array.
    
    timecourse_matrix = np.full((len(results), max_len), np.nan, dtype=np.float32)
    for i, (sid, ts) in enumerate(results):
        timecourse_matrix[i, :len(ts)] = ts.astype(np.float32)
    
    # Save the matrix
    np.save(output_path, timecourse_matrix)
    
    # Also save subject IDs to a companion file for reference
    ids_path = output_path.with_suffix('.ids.json')
    with open(ids_path, 'w') as f:
        json.dump(subject_ids, f)
    
    info(f"Successfully saved Left Hippocampus timecourses to {output_path}")
    info(f"Shape: {timecourse_matrix.shape}, Subjects: {len(subject_ids)}")
    
    # Verify file exists
    if not output_path.exists():
        error("E002: Output file was not created.")
        sys.exit(1)
    
    # Verify not empty (checked by shape > 0)
    if timecourse_matrix.size == 0:
        error("E002: Output array is empty.")
        sys.exit(1)

if __name__ == "__main__":
    main()
