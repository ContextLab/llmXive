"""
Baseline Variance Calculation Module (Task T014).

Reads synthetic clean data generated by T012 (data/raw/synthetic_clean_*.csv),
computes sample variance for each continuous variable, and saves the results
to data/results/baseline_metrics.json.

This script depends on T012 having successfully generated the clean data files
and the ground truth parameters in state/synthetic_params.json.
"""

import json
import logging
import os
import sys
from pathlib import Path
from typing import Dict, Any, List

import numpy as np
import pandas as pd

# Add project root to path to allow relative imports if running as script
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.logger import get_logger, configure_logger
from src.setup_dirs import setup_directories

logger = get_logger(__name__)


def load_clean_data_files(data_dir: Path) -> List[Path]:
    """
    Locate all synthetic clean CSV files generated in T012.
    
    Args:
        data_dir: Path to the data/raw directory.
        
    Returns:
        List of paths to synthetic_clean_*.csv files.
    """
    pattern = "synthetic_clean_*.csv"
    files = list(data_dir.glob(pattern))
    if not files:
        raise FileNotFoundError(
            f"No files matching '{pattern}' found in {data_dir}. "
            "Ensure T012 (data generation) has completed successfully."
        )
    logger.info(f"Found {len(files)} synthetic clean data files: {[f.name for f in files]}")
    return sorted(files)


def calculate_baseline_metrics(
    data_files: List[Path], 
    ground_truth_file: Path
) -> Dict[str, Any]:
    """
    Calculate sample variance for each variable in the clean datasets.
    
    Args:
        data_files: List of paths to clean CSV files.
        ground_truth_file: Path to state/synthetic_params.json for ground truth comparison.
        
    Returns:
        Dictionary containing baseline metrics and ground truth comparison.
    """
    results = {
        "datasets": {},
        "ground_truth_comparison": {},
        "summary": {}
    }
    
    # Load ground truth parameters if available
    ground_truth = {}
    if ground_truth_file.exists():
        with open(ground_truth_file, 'r') as f:
            ground_truth = json.load(f)
        logger.info(f"Loaded ground truth parameters from {ground_truth_file}")
    else:
        logger.warning(f"Ground truth file not found: {ground_truth_file}. Skipping comparison.")
    
    total_variance_diff = 0.0
    count_comparisons = 0
    
    for file_path in data_files:
        dataset_name = file_path.stem.replace("synthetic_clean_", "")
        logger.info(f"Processing dataset: {dataset_name}")
        
        try:
            df = pd.read_csv(file_path)
            numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
            
            if not numeric_cols:
                logger.warning(f"No numeric columns found in {file_path}")
                continue
            
            dataset_metrics = {}
            
            for col in numeric_cols:
                # Calculate sample variance (ddof=1)
                sample_variance = df[col].var(ddof=1)
                dataset_metrics[col] = {
                    "sample_variance": float(sample_variance),
                    "count": int(df[col].count()),
                    "mean": float(df[col].mean())
                }
                
                # Compare with ground truth if available
                if dataset_name in ground_truth and col in ground_truth[dataset_name]:
                    true_variance = ground_truth[dataset_name][col].get("true_variance")
                    if true_variance is not None:
                        diff = abs(sample_variance - true_variance)
                        relative_error = diff / true_variance if true_variance > 0 else float('inf')
                        dataset_metrics[col]["ground_truth_variance"] = float(true_variance)
                        dataset_metrics[col]["absolute_error"] = float(diff)
                        dataset_metrics[col]["relative_error"] = float(relative_error)
                        
                        total_variance_diff += diff
                        count_comparisons += 1
                
            results["datasets"][dataset_name] = {
                "file": str(file_path),
                "metrics": dataset_metrics
            }
            
        except Exception as e:
            logger.error(f"Error processing {file_path}: {e}")
            raise
    
    # Calculate summary statistics
    if count_comparisons > 0:
        results["summary"]["mean_absolute_error"] = float(total_variance_diff / count_comparisons)
        results["summary"]["total_comparisons"] = count_comparisons
        results["summary"]["ground_truth_available"] = True
    else:
        results["summary"]["ground_truth_available"] = False
    
    results["summary"]["datasets_processed"] = len(results["datasets"])
    
    return results


def save_baseline_metrics(results: Dict[str, Any], output_path: Path) -> None:
    """
    Save the baseline metrics to a JSON file.
    
    Args:
        results: The metrics dictionary to save.
        output_path: Path to the output JSON file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        json.dump(results, f, indent=2)
    
    logger.info(f"Baseline metrics saved to {output_path}")


def main() -> None:
    """
    Main entry point for baseline variance calculation.
    """
    # Setup directories
    setup_directories()
    
    # Configure logger
    configure_logger(level=logging.INFO)
    
    logger.info("Starting baseline variance calculation (T014)...")
    
    # Define paths
    data_raw_dir = PROJECT_ROOT / "data" / "raw"
    state_dir = PROJECT_ROOT / "state"
    results_dir = PROJECT_ROOT / "data" / "results"
    
    ground_truth_file = state_dir / "synthetic_params.json"
    output_file = results_dir / "baseline_metrics.json"
    
    # Load clean data files
    clean_files = load_clean_data_files(data_raw_dir)
    
    # Calculate metrics
    metrics = calculate_baseline_metrics(clean_files, ground_truth_file)
    
    # Save results
    save_baseline_metrics(metrics, output_file)
    
    logger.info("Baseline variance calculation completed successfully.")
    print(f"Results saved to: {output_file}")


if __name__ == "__main__":
    main()