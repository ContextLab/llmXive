import os
import hashlib
from pathlib import Path

# Ensure we can import from the project root if run as a module
try:
    from config import Config
except ImportError:
    # Fallback if run directly without package structure
    import sys
    sys.path.insert(0, str(Path(__file__).parent))
    from config import Config


def ensure_directory(path: Path) -> None:
    """Create a directory if it does not exist."""
    if not path.exists():
        path.mkdir(parents=True, exist_ok=True)
        print(f"Created directory: {path}")
    else:
        if not path.is_dir():
            raise RuntimeError(f"Path exists but is not a directory: {path}")


def initialize_checksums_file(checksums_path: Path) -> None:
    """
    Initialize the checksums file if it does not exist.
    If it exists, leave it untouched to preserve history.
    """
    if not checksums_path.exists():
        checksums_path.parent.mkdir(parents=True, exist_ok=True)
        with open(checksums_path, 'w', encoding='utf-8') as f:
            f.write("# Data Checksums for PROJ-334\n")
            f.write("# Format: SHA256  relative_path\n")
            f.write("# Generated by data_setup.py\n")
            f.write("\n")
        print(f"Initialized checksums file: {checksums_path}")
    else:
        print(f"Checksums file already exists: {checksums_path}")


def main() -> None:
    """
    Main entry point for T004: Setup data directory structure.
    Creates data/raw/, data/processed/ and initializes data/checksums.txt.
    """
    config = Config()
    
    # Define paths
    data_root = config.DATA_ROOT
    raw_dir = data_root / "raw"
    processed_dir = data_root / "processed"
    checksums_file = data_root / "checksums.txt"

    # Ensure directories exist
    ensure_directory(raw_dir)
    ensure_directory(processed_dir)

    # Initialize checksums file
    initialize_checksums_file(checksums_file)

    print("Data directory structure setup complete.")
    print(f"  - Raw data: {raw_dir}")
    print(f"  - Processed data: {processed_dir}")
    print(f"  - Checksums: {checksums_file}")


if __name__ == "__main__":
    main()
