import os
import sys
import csv
import logging
from pathlib import Path
from datetime import datetime

# Add project root to path to allow imports from utils
project_root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(project_root))

from utils.config import get_data_dir, get_processed_dir, get_raw_data_dir, get_metadata_file
from utils.provenance import load_metadata_config, save_metadata_config

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def load_metadata():
    """Load the metadata configuration file."""
    metadata_path = get_metadata_file()
    if not metadata_path.exists():
        logger.error(f"Metadata file not found at {metadata_path}")
        raise FileNotFoundError(f"Metadata file not found at {metadata_path}")
    return load_metadata_config(metadata_path)

def save_metadata(metadata):
    """Save the updated metadata configuration file."""
    metadata_path = get_metadata_file()
    save_metadata_config(metadata_path, metadata)

def load_guild_source():
    """
    Load the guild source CSV generated by T008a.
    Expects columns: species_id, foraging_guild, source_citation (and potentially others).
    """
    raw_dir = get_raw_data_dir()
    guild_source_path = raw_dir / "guild_source.csv"
    
    if not guild_source_path.exists():
        logger.error(f"Guild source file not found at {guild_source_path}. "
                     "Please ensure T008a (download_guild_source.py) has been run successfully.")
        raise FileNotFoundError(f"Guild source file not found at {guild_source_path}")

    logger.info(f"Loading guild source from {guild_source_path}")
    
    data = []
    with open(guild_source_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Validate required columns exist
            if 'species_id' not in row or 'foraging_guild' not in row:
                logger.warning(f"Skipping row missing required columns: {row}")
                continue
            data.append(row)
    
    if not data:
        logger.error("No valid data rows found in guild source file.")
        raise ValueError("No valid data rows found in guild source file.")
    
    logger.info(f"Loaded {len(data)} species records from guild source.")
    return data

def validate_schema(data):
    """
    Validate that the loaded data conforms to the expected schema for processing.
    Checks for presence of required fields.
    """
    required_fields = ['species_id', 'foraging_guild']
    for i, row in enumerate(data):
        for field in required_fields:
            if field not in row:
                raise ValueError(f"Row {i} missing required field: {field}")
            if not row[field] or str(row[field]).strip() == "":
                raise ValueError(f"Row {i} has empty value for required field: {field}")
    logger.info("Schema validation passed.")
    return True

def save_mapping(data, metadata):
    """
    Save the processed guild mapping to the processed directory.
    Output columns: species_id, foraging_guild, source_citation, extraction_date.
    """
    processed_dir = get_processed_dir()
    output_path = processed_dir / "guild_mapping.csv"
    
    # Ensure directory exists
    processed_dir.mkdir(parents=True, exist_ok=True)
    
    extraction_date = datetime.now().strftime("%Y-%m-%d")
    
    logger.info(f"Saving guild mapping to {output_path}")
    
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        fieldnames = ['species_id', 'foraging_guild', 'source_citation', 'extraction_date']
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        
        for row in data:
            # Extract required fields, handling potential missing citation gracefully
            species_id = row.get('species_id', '').strip()
            foraging_guild = row.get('foraging_guild', '').strip()
            source_citation = row.get('source_citation', 'Unknown').strip()
            if not source_citation:
                source_citation = 'Unknown'
            
            writer.writerow({
                'species_id': species_id,
                'foraging_guild': foraging_guild,
                'source_citation': source_citation,
                'extraction_date': extraction_date
            })
    
    logger.info(f"Successfully saved {len(data)} records to {output_path}")
    return output_path

def record_provenance_in_metadata(metadata, source_path, output_path):
    """
    Update the metadata.yaml with provenance information for this step.
    """
    step_name = "generate_guild_mapping"
    now = datetime.now().isoformat()
    
    provenance_record = {
        "step": step_name,
        "input_file": str(source_path),
        "output_file": str(output_path),
        "timestamp": now,
        "description": "Extracted species_id and foraging_guild from guild_source.csv and added extraction_date."
    }
    
    if "provenance" not in metadata:
        metadata["provenance"] = []
    
    metadata["provenance"].append(provenance_record)
    return metadata

def main():
    """Main entry point for the guild mapping generation script."""
    try:
        # 1. Load Metadata
        metadata = load_metadata()
        
        # 2. Load Guild Source
        raw_data = load_guild_source()
        
        # 3. Validate Schema
        validate_schema(raw_data)
        
        # 4. Save Mapping
        output_path = save_mapping(raw_data, metadata)
        
        # 5. Update Metadata Provenance
        metadata = record_provenance_in_metadata(metadata, "data/raw/guild_source.csv", output_path)
        save_metadata(metadata)
        
        logger.info("Task T008b completed successfully.")
        return 0
        
    except FileNotFoundError as e:
        logger.error(f"File not found error: {e}")
        return 1
    except ValueError as e:
        logger.error(f"Validation error: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error: {e}", exc_info=True)
        return 1

if __name__ == "__main__":
    sys.exit(main())
