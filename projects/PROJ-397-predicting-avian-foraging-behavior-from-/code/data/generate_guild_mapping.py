import os
import sys
import csv
import logging
from pathlib import Path
from datetime import datetime
from typing import List, Dict, Any, Optional
import hashlib
import yaml

# Import project utilities
sys.path.insert(0, str(Path(__file__).parent.parent))
from utils.config import get_data_dir, get_raw_data_dir, get_processed_dir
from utils.provenance import compute_file_hash, generate_provenance_record, save_provenance_record

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

def load_metadata(metadata_path: Path) -> Dict[str, Any]:
    """Load existing metadata or return empty dict if not found."""
    if metadata_path.exists():
        with open(metadata_path, 'r') as f:
            return yaml.safe_load(f) or {}
    return {}

def save_metadata(metadata: Dict[str, Any], metadata_path: Path) -> None:
    """Save metadata to YAML file."""
    with open(metadata_path, 'w') as f:
        yaml.dump(metadata, f, default_flow_style=False)

def load_guild_source(source_path: Path) -> List[Dict[str, Any]]:
    """
    Load the guild source CSV generated by T008a.
    Expected columns: species_id, foraging_guild, (and potentially others).
    """
    if not source_path.exists():
        raise FileNotFoundError(f"Guild source file not found: {source_path}. "
                                "Ensure T008a (download_guild_source.py) has completed successfully.")
    
    rows = []
    with open(source_path, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            rows.append(row)
    
    if not rows:
        raise ValueError(f"Guild source file {source_path} is empty or has no data rows.")
    
    # Validate expected columns
    required_cols = {'species_id', 'foraging_guild'}
    if not required_cols.issubset(set(rows[0].keys())):
        missing = required_cols - set(rows[0].keys())
        raise ValueError(f"Guild source file missing required columns: {missing}. "
                         f"Found columns: {list(rows[0].keys())}")
        
    return rows

def validate_schema(data: List[Dict[str, Any]]) -> bool:
    """
    Validate that the data has the required structure for the mapping.
    Returns True if valid. Raises ValueError if invalid.
    """
    if not data:
        raise ValueError("Data list is empty.")
    
    required_keys = {'species_id', 'foraging_guild', 'source_citation', 'extraction_date'}
    first_row_keys = set(data[0].keys())
    
    missing = required_keys - first_row_keys
    if missing:
        raise ValueError(f"Data missing required keys: {missing}")
    
    # Basic type/value checks
    for i, row in enumerate(data):
        if not row['species_id']:
            raise ValueError(f"Row {i} has empty species_id")
        if not row['foraging_guild']:
            raise ValueError(f"Row {i} has empty foraging_guild")
        
    return True

def save_mapping(data: List[Dict[str, Any]], output_path: Path) -> None:
    """Save the processed guild mapping to a CSV file."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    fieldnames = ['species_id', 'foraging_guild', 'source_citation', 'extraction_date']
    
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(data)
    
    logger.info(f"Saved guild mapping to {output_path} with {len(data)} rows.")

def record_provenance_in_metadata(metadata: Dict[str, Any], source_path: Path, output_path: Path) -> Dict[str, Any]:
    """
    Update metadata with provenance information for this step.
    """
    step_name = "generate_guild_mapping"
    timestamp = datetime.now().isoformat()
    
    # Compute hash of input
    input_hash = compute_file_hash(source_path)
    
    # Compute hash of output
    output_hash = compute_file_hash(output_path)
    
    # Record
    if 'steps' not in metadata:
        metadata['steps'] = []
    
    record = {
        'step': step_name,
        'timestamp': timestamp,
        'input_file': str(source_path),
        'input_hash': input_hash,
        'output_file': str(output_path),
        'output_hash': output_hash,
        'row_count': len(open(output_path, 'r')) - 1 # -1 for header
    }
    
    metadata['steps'].append(record)
    return metadata

def main():
    """Main entry point for generating the guild mapping."""
    # Define paths relative to project root
    data_dir = get_data_dir()
    raw_dir = get_raw_data_dir()
    processed_dir = get_processed_dir()
    
    source_file = raw_dir / "guild_source.csv"
    output_file = processed_dir / "guild_mapping.csv"
    metadata_file = data_dir / "metadata.yaml"
    
    logger.info(f"Starting guild mapping generation.")
    logger.info(f"Source: {source_file}")
    logger.info(f"Output: {output_file}")
    
    # Ensure directories exist
    processed_dir.mkdir(parents=True, exist_ok=True)
    
    # Load source data
    try:
        source_data = load_guild_source(source_file)
        logger.info(f"Loaded {len(source_data)} rows from source.")
    except (FileNotFoundError, ValueError) as e:
        logger.error(f"Failed to load source data: {e}")
        raise

    # Prepare output data with provenance fields
    extraction_date = datetime.now().strftime("%Y-%m-%d")
    source_citation = "Cornell Lab of Ornithology. Birds of the World. (Accessed via download_guild_source.py)"
    
    processed_data = []
    for row in source_data:
        processed_row = {
            'species_id': row['species_id'],
            'foraging_guild': row['foraging_guild'],
            'source_citation': source_citation,
            'extraction_date': extraction_date
        }
        processed_data.append(processed_row)
    
    # Validate schema
    try:
        validate_schema(processed_data)
        logger.info("Schema validation passed.")
    except ValueError as e:
        logger.error(f"Schema validation failed: {e}")
        raise

    # Save mapping
    save_mapping(processed_data, output_file)
    
    # Update metadata
    metadata = load_metadata(metadata_file)
    metadata = record_provenance_in_metadata(metadata, source_file, output_file)
    save_metadata(metadata, metadata_file)
    
    logger.info("Guild mapping generation completed successfully.")
    return output_file

if __name__ == "__main__":
    main()
