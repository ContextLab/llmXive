"""
Uncertainty Flagger Module

Implements logic to flag entries using the default ±10°C uncertainty bound
and save the flags to data/raw/uncertainty_flags.json.
"""
import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional

from data_ingestion_metadata import parse_uncertainty, extract_instrument_model

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger(__name__)

DEFAULT_UNCERTAINTY_COVERAGE: float = 10.0
OUTPUT_FILE: Path = Path("data/raw/uncertainty_flags.json")


def load_metadata(metadata_path: Path) -> List[Dict[str, Any]]:
    """
    Load the parsed metadata from the JSON file generated by T013b.

    Args:
        metadata_path: Path to the metadata JSON file.

    Returns:
        List of metadata entries.

    Raises:
        FileNotFoundError: If the metadata file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    logger.info(f"Loading metadata from {metadata_path}")
    with open(metadata_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # Ensure we are working with a list
    if isinstance(data, dict) and 'entries' in data:
        return data['entries']
    elif isinstance(data, list):
        return data
    else:
        raise ValueError("Metadata file must contain a list of entries or a dict with 'entries' key.")


def flag_default_uncertainty_entries(metadata_entries: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Iterate through metadata entries and flag those that use the default uncertainty.

    Logic:
    1. Parse the uncertainty string (e.g., "±5°C", "±10°C", "5") using existing helper.
    2. If parsing fails (missing data) OR the parsed value equals the default (10.0),
       flag the entry as using the default bound.
    3. Record the source of the uncertainty (parsed vs default).

    Args:
        metadata_entries: List of metadata dictionaries containing 'entry_id', 'uncertainty_raw', etc.

    Returns:
        List of flag objects with 'entry_id', 'is_default_uncertainty', 'uncertainty_value', 'source'.
    """
    flags = []
    
    for entry in metadata_entries:
        entry_id = entry.get('entry_id')
        uncertainty_raw = entry.get('uncertainty_raw')
        
        is_default = False
        uncertainty_value = None
        source = "unknown"

        if uncertainty_raw is None:
            # No uncertainty provided -> must use default
            is_default = True
            uncertainty_value = DEFAULT_UNCERTAINTY_COVERAGE
            source = "missing_data_default"
        else:
            # Try to parse the raw string
            parsed_val = parse_uncertainty(uncertainty_raw)
            
            if parsed_val is None:
                # Parsing failed (e.g., malformed string) -> fall back to default
                is_default = True
                uncertainty_value = DEFAULT_UNCERTAINTY_COVERAGE
                source = "parse_failure_default"
            else:
                # Parsed successfully
                uncertainty_value = parsed_val
                if abs(uncertainty_value - DEFAULT_UNCERTAINTAINTY_COVERAGE) < 1e-6:
                    is_default = True
                    source = "explicit_default"
                else:
                    is_default = False
                    source = "explicit_custom"

        flags.append({
            "entry_id": entry_id,
            "is_default_uncertainty": is_default,
            "uncertainty_value": uncertainty_value,
            "source": source,
            "raw_uncertainty": uncertainty_raw
        })

    logger.info(f"Flagged {len(flags)} entries. Default uncertainty count: {sum(1 for f in flags if f['is_default_uncertainty'])}")
    return flags


def save_flags(flags: List[Dict[str, Any]], output_path: Path) -> None:
    """
    Save the uncertainty flags to a JSON file.

    Args:
        flags: List of flag dictionaries.
        output_path: Destination path for the JSON file.
    """
    # Ensure directory exists
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    logger.info(f"Saving uncertainty flags to {output_path}")
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(flags, f, indent=2)


def main() -> None:
    """
    Main entry point for the uncertainty flagging process.
    """
    # Define paths relative to project root
    project_root = Path(__file__).resolve().parent.parent
    metadata_path = project_root / "data" / "raw" / "metadata.json"
    
    if not metadata_path.exists():
        logger.error(f"Metadata file not found at {metadata_path}. Run T013b first.")
        raise FileNotFoundError(f"Metadata file not found: {metadata_path}")

    try:
        entries = load_metadata(metadata_path)
        flags = flag_default_uncertainty_entries(entries)
        save_flags(flags, OUTPUT_FILE)
        logger.info("Uncertainty flagging completed successfully.")
    except Exception as e:
        logger.error(f"Error during uncertainty flagging: {e}", exc_info=True)
        raise


if __name__ == "__main__":
    main()
