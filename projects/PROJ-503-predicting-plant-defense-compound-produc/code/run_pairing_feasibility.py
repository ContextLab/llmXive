"""
T014: Verify sample-level pairing feasibility (>=95% match rate per FR-009).

This script loads the GEO and Metabolomics Workbench search results generated
by T011, T012, and T013. It extracts biological sample identifiers (biosample_accession)
from both datasets and calculates the intersection rate.

If the pairing rate is >= 95%, it logs success. If < 95%, it logs the failure
and prepares the data for T016b (fallback to condition-level aggregation).

Output:
  - logs/pairing_feasibility_report.json: Detailed statistics on the pairing attempt.
"""
import json
import logging
import os
import sys
from pathlib import Path
from typing import Dict, Any, List, Tuple, Set

# Ensure the project root is in the path to import sibling modules
# The script is expected to run from the project root or code/ directory
PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from exceptions import E_PAIRING

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s',
    handlers=[
        logging.StreamHandler(sys.stdout),
        logging.FileHandler(PROJECT_ROOT / 'logs' / 'pairing_feasibility.log')
    ]
)
logger = logging.getLogger(__name__)

# Paths to search results (generated by T011, T012, T013)
GEO_ARABIDOPSIS_RESULTS = PROJECT_ROOT / 'data' / 'raw' / 'geo_arabidopsis_search.json'
GEO_SOLANUM_RESULTS = PROJECT_ROOT / 'data' / 'raw' / 'geo_solanum_search.json'
MW_RESULTS = PROJECT_ROOT / 'data' / 'raw' / 'metabolomics_workbench_search.json'

OUTPUT_REPORT = PROJECT_ROOT / 'logs' / 'pairing_feasibility_report.json'

def load_json_safe(path: Path) -> Dict[str, Any]:
    """Load JSON file safely, returning empty dict if not found."""
    if not path.exists():
        logger.warning(f"File not found: {path}")
        return {}
    try:
        with open(path, 'r') as f:
            return json.load(f)
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse JSON in {path}: {e}")
        return {}

def load_geo_search_results(geo_arab_path: Path, geo_solanum_path: Path) -> Dict[str, Any]:
    """
    Load GEO search results and structure them by organism.
    Returns a dict: { "Arabidopsis": [list of study dicts], "Solanum": [list of study dicts] }
    """
    results = {}
    
    arab_data = load_json_safe(geo_arab_path)
    if arab_data:
        # Normalize structure if it's a list or a dict with a key
        studies = arab_data.get('studies', []) if isinstance(arab_data, dict) else arab_data
        results['Arabidopsis'] = studies if studies else []
    
    solanum_data = load_json_safe(geo_solanum_path)
    if solanum_data:
        studies = solanum_data.get('studies', []) if isinstance(solanum_data, dict) else solanum_data
        results['Solanum'] = studies if studies else []
        
    return results

def load_mw_search_results(mw_path: Path) -> List[Dict[str, Any]]:
    """Load Metabolomics Workbench search results."""
    data = load_json_safe(mw_path)
    if not data:
        return []
    return data.get('experiments', []) if isinstance(data, dict) else data

def extract_geo_biosample_ids(geo_results: Dict[str, Any]) -> Tuple[Set[str], int]:
    """
    Extract unique biological sample IDs from GEO results.
    Returns: (set of biosample_ids, total_sample_count)
    """
    biosample_ids = set()
    total_samples = 0
    
    for organism, studies in geo_results.items():
        if not studies:
            continue
        for study in studies:
            # GEO series often contain GSM samples. We need to look for biosample accessions.
            # In a real scenario, we'd parse the 'samples' list within the study.
            samples = study.get('samples', [])
            for sample in samples:
                total_samples += 1
                # Look for biosample accession (e.g., GSMxxxx -> GSMxxxx_biosample or direct biosample field)
                # Assuming the search result includes a 'biosample_accession' or 'geo_biosample' field
                # If the raw download was done by T021, it might be in a 'metadata' block.
                # Here we assume the search result T011/T012 produced a structured list with biosample info.
                bid = sample.get('biosample_accession') or sample.get('geo_biosample') or sample.get('sample_id')
                if bid:
                    biosample_ids.add(bid)
                
    return biosample_ids, total_samples

def extract_mw_biosample_ids(mw_results: List[Dict[str, Any]]) -> Tuple[Set[str], int]:
    """
    Extract unique biological sample IDs from Metabolomics Workbench results.
    Returns: (set of biosample_ids, total_sample_count)
    """
    biosample_ids = set()
    total_samples = 0
    
    for exp in mw_results:
        # MW experiments have 'samples' or 'analyses' with sample info
        samples = exp.get('samples', [])
        if not samples:
            # Sometimes samples are nested in analyses
            analyses = exp.get('analyses', [])
            for analysis in analyses:
                samples.extend(analysis.get('samples', []))
        
        for sample in samples:
            total_samples += 1
            # MW typically uses 'sample_name' or 'biosample_id'
            bid = sample.get('biosample_id') or sample.get('sample_name') or sample.get('external_id')
            if bid:
                biosample_ids.add(bid)
                
    return biosample_ids, total_samples

def run_pairing_feasibility(geo_results: Dict[str, Any], mw_results: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Compare biosample IDs between GEO (Expression) and MW (Metabolites).
    Calculates the pairing rate.
    """
    geo_ids, geo_total = extract_geo_biosample_ids(geo_results)
    mw_ids, mw_total = extract_mw_biosample_ids(mw_results)
    
    logger.info(f"Found {len(geo_ids)} unique biosamples in GEO (Total samples: {geo_total})")
    logger.info(f"Found {len(mw_ids)} unique biosamples in MW (Total samples: {mw_total})")
    
    if not geo_ids or not mw_ids:
        logger.error("One or both datasets have no biosample IDs. Cannot calculate pairing rate.")
        return {
            "status": "failed",
            "reason": "missing_biosample_ids",
            "geo_ids_count": len(geo_ids),
            "mw_ids_count": len(mw_ids)
        }
    
    # Calculate intersection
    matched_ids = geo_ids.intersection(mw_ids)
    match_count = len(matched_ids)
    
    # Pairing rate is defined as: (matched samples) / (total expression samples)
    # per FR-009: "≥95% match rate" implies we need 95% of our expression samples to have a metabolite match.
    pairing_rate = match_count / geo_total if geo_total > 0 else 0.0
    
    logger.info(f"Matched biosamples: {match_count}")
    logger.info(f"Pairing rate: {pairing_rate:.2%}")
    
    report = {
        "status": "success" if pairing_rate >= 0.95 else "failed",
        "pairing_rate": pairing_rate,
        "threshold": 0.95,
        "geo_unique_biosamples": len(geo_ids),
        "mw_unique_biosamples": len(mw_ids),
        "matched_biosamples_count": match_count,
        "matched_ids": list(matched_ids), # Limited to first 100 for readability in log, full list in file if needed
        "total_expression_samples": geo_total,
        "total_metabolite_samples": mw_total,
        "recommendation": "PROCEED" if pairing_rate >= 0.95 else "TRIGGER_FALLBACK_T016b"
    }
    
    if pairing_rate < 0.95:
        report["matched_ids"] = list(matched_ids)[:100] # Truncate for report brevity
        report["message"] = f"Pairing rate {pairing_rate:.2%} is below 95%. Fallback to condition-level aggregation (T016b) required."
        # Raise E_PAIRING to signal the pipeline to stop or switch mode
        # Note: In a script, we log and return the report. The caller (main.py) handles the exit.
        logger.error(f"Pairing feasibility failed: {report['message']}")
        # We do not raise an exception here to allow the report to be written, 
        # but we mark the status so the main pipeline can act.
    
    return report

def main():
    logger.info("Starting T014: Verify sample-level pairing feasibility")
    
    # 1. Load Search Results
    geo_results = load_geo_search_results(GEO_ARABIDOPSIS_RESULTS, GEO_SOLANUM_RESULTS)
    mw_results = load_mw_search_results(MW_RESULTS)
    
    if not geo_results.get('Arabidopsis') and not geo_results.get('Solanum'):
        logger.error("No GEO search results found. Cannot proceed.")
        sys.exit(1)
    
    if not mw_results:
        logger.error("No Metabolomics Workbench search results found. Cannot proceed.")
        sys.exit(1)
    
    # 2. Run Feasibility Analysis
    report = run_pairing_feasibility(geo_results, mw_results)
    
    # 3. Write Report
    OUTPUT_REPORT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_REPORT, 'w') as f:
        json.dump(report, f, indent=2)
    
    logger.info(f"Pairing feasibility report written to {OUTPUT_REPORT}")
    
    # 4. Exit with appropriate code if pairing fails (to trigger T016b or abort)
    if report["status"] == "failed":
        logger.critical("Pairing rate insufficient. Pipeline requires fallback or abort.")
        # We exit with code 2 to indicate a specific failure condition distinct from runtime error
        sys.exit(2) 
        
    logger.info("T014 completed successfully. Proceeding to T021/T024.")
    sys.exit(0)

if __name__ == "__main__":
    main()
