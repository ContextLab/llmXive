"""
Verify checksums for downloaded data files (T001, T002).

This script verifies that the SHA-256 checksums of the downloaded files
match the expected values stored in data/raw/checksums.json.

SC-004 Compliance:
- Downloaded files from GEO and Metabolomics Workbench must match expected 
  checksums (SHA-256) for ≥99% of requested experiment IDs.
- Abort with E-DATASET if <99% match.

Dependencies:
- T001: Download gene expression matrices from GEO
- T002: Download metabolite data from Metabolomics Workbench
- T022: Checksum validation utility (utils/checksum.py)
"""

import json
import logging
import sys
from pathlib import Path
from typing import Dict, List, Tuple

# Add project root to path for imports
project_root = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(project_root))

from code.utils.checksum import validate_checksum, load_checksums
from code.exceptions import E_DATASET

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger(__name__)

# Project paths
RAW_DATA_DIR = project_root / "data" / "raw"
CHECKSUM_MANIFEST_PATH = RAW_DATA_DIR / "checksums.json"

# Files to verify (generated by T001 and T002)
FILES_TO_VERIFY = [
    "geo_expression_matrix.csv",
    "metabolite_matrix.csv"
]

def verify_single_checksum(file_path: Path, expected_hash: str) -> Tuple[bool, str]:
    """
    Verify a single file's checksum against the expected value.
    
    Args:
        file_path: Path to the file to verify
        expected_hash: Expected SHA-256 hash
      
    Returns:
        Tuple of (success: bool, message: str)
    """
    if not file_path.exists():
        return False, f"File not found: {file_path}"
    
    is_valid, actual_hash = validate_checksum(str(file_path), expected_hash)
    
    if is_valid:
        return True, f"Checksum verified for {file_path.name}"
    else:
        return False, f"Checksum mismatch for {file_path.name}: expected {expected_hash}, got {actual_hash}"

def verify_all_checksums(manifest_path: Path) -> Tuple[bool, Dict[str, str]]:
    """
    Verify all checksums in the manifest.
    
    Args:
        manifest_path: Path to the checksum manifest JSON file
    
    Returns:
        Tuple of (all_passed: bool, results: Dict[file_path -> status_message])
    """
    if not manifest_path.exists():
        raise E_DATASET(f"Checksum manifest not found: {manifest_path}")
    
    checksums = load_checksums(str(manifest_path))
    results = {}
    passed_count = 0
    total_count = 0
    
    for file_name, expected_hash in checksums.items():
        file_path = RAW_DATA_DIR / file_name
        total_count += 1
        
        success, message = verify_single_checksum(file_path, expected_hash)
        results[file_name] = message
        
        if success:
            passed_count += 1
            logger.info(f"✓ {message}")
        else:
            logger.error(f"✗ {message}")
    
    # Calculate pass rate
    pass_rate = (passed_count / total_count * 100) if total_count > 0 else 0.0
    
    logger.info(f"\nChecksum verification complete: {passed_count}/{total_count} files passed ({pass_rate:.1f}%)")
    
    # SC-004: Abort if <99% match
    if pass_rate < 99.0:
        raise E_DATASET(
            f"Checksum verification failed: {pass_rate:.1f}% < 99% threshold. "
            f"{total_count - passed_count} file(s) did not match expected checksums."
        )
    
    all_passed = pass_rate >= 99.0
    return all_passed, results

def main():
    """
    Main entry point for checksum verification.
    """
    logger.info("Starting checksum verification for downloaded data files...")
    
    # Ensure raw data directory exists
    if not RAW_DATA_DIR.exists():
        raise E_DATASET(f"Raw data directory not found: {RAW_DATA_DIR}")
    
    # Verify all checksums
    try:
        all_passed, results = verify_all_checksums(CHECKSUM_MANIFEST_PATH)
        
        if all_passed:
            logger.info("✓ All checksums verified successfully (≥99% match)")
            return 0
        else:
            # This should not happen due to the abort in verify_all_checksums
            logger.error("✗ Checksum verification failed")
            return 1
            
    except E_DATASET as e:
        logger.error(f"E-DATASET: {e}")
        return 1
    except Exception as e:
        logger.error(f"Unexpected error during checksum verification: {e}")
        return 1

if __name__ == "__main__":
    sys.exit(main())