"""
Integration test for the agent comparison pipeline (US3).

This test verifies the end-to-end execution of the benchmark pipeline:
1. Loads the held-out traces.
2. Loads the global rule set (generated by T026b).
3. Executes the Baseline Agent and Compressed Agent on the held-out traces.
4. Aggregates metrics (Edit Accuracy, Retrieval Latency).
5. Validates the output against the benchmark results schema.
6. Ensures the output file `data/processed/benchmark_results.json` is created and valid.
"""

import json
import os
import sys
import time
import unittest
from pathlib import Path
from typing import Dict, Any, List, Optional

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "code"))

from evaluation.benchmark import BenchmarkRunner, BenchmarkError
from utils.validators import BenchmarkValidator
from config import get_config, reset_config


class TestAgentBenchmarkPipeline(unittest.TestCase):
    """
    Integration test suite for the agent comparison pipeline.
    """

    def setUp(self):
        """
        Set up test fixtures.
        """
        # Reset configuration to ensure clean state
        reset_config()
        self.config = get_config()
        
        # Define paths
        self.held_out_dir = self.config.get("path_held_out")
        self.global_rules_path = self.config.get("path_global_rules")
        self.output_path = self.config.get("path_benchmark_results")
        
        # Ensure output directory exists
        Path(self.output_path).parent.mkdir(parents=True, exist_ok=True)

    def _load_held_out_traces(self) -> List[Dict[str, Any]]:
        """
        Helper to load held-out traces from the directory.
        """
        traces = []
        if not os.path.exists(self.held_out_dir):
            raise FileNotFoundError(f"Held-out directory not found: {self.held_out_dir}")
        
        for filename in os.listdir(self.held_out_dir):
            if filename.endswith(".json"):
                filepath = os.path.join(self.held_out_dir, filename)
                with open(filepath, "r") as f:
                    trace_data = json.load(f)
                    # Ensure trace_id is present
                    if "trace_id" not in trace_data:
                        trace_data["trace_id"] = filename.replace(".json", "")
                    traces.append(trace_data)
        
        if not traces:
            raise ValueError(f"No traces found in {self.held_out_dir}")
        
        return traces

    def _load_global_rules(self) -> Optional[Dict[str, Any]]:
        """
        Helper to load global rules.
        """
        if not os.path.exists(self.global_rules_path):
            # If rules don't exist, the test should fail loudly rather than skip
            raise FileNotFoundError(f"Global rules file not found: {self.global_rules_path}")
        
        with open(self.global_rules_path, "r") as f:
            return json.load(f)

    def test_pipeline_execution_and_output_generation(self):
        """
        Test the full pipeline execution:
        1. Loads data.
        2. Runs both agents.
        3. Generates the benchmark results file.
        4. Validates the output schema.
        """
        # 1. Load Data
        print("Loading held-out traces...")
        held_out_traces = self._load_held_out_traces()
        print(f"Loaded {len(held_out_traces)} traces.")

        print("Loading global rules...")
        global_rules = self._load_global_rules()
        print(f"Loaded global rules with {len(global_rules.get('rules', []))} rules.")

        # 2. Initialize and Run Benchmark
        print("Initializing BenchmarkRunner...")
        runner = BenchmarkRunner(
            held_out_traces=held_out_traces,
            global_rules=global_rules,
            fidelity_tolerance=self.config.get("fidelity_tolerance", 0.90),
            seed=self.config.get("random_seed", 42)
        )

        print("Running benchmark pipeline...")
        try:
            results = runner.run()
        except BenchmarkError as e:
            self.fail(f"Benchmark execution failed: {e}")

        # 3. Verify Output File Creation
        print(f"Checking output file: {self.output_path}")
        self.assertTrue(
            os.path.exists(self.output_path),
            f"Output file {self.output_path} was not generated."
        )

        # 4. Validate Output Content
        with open(self.output_path, "r") as f:
            saved_results = json.load(f)

        # Validate structure
        self.assertIsInstance(saved_results, list, "Benchmark results must be a list.")
        self.assertGreater(len(saved_results), 0, "Benchmark results list is empty.")

        # Validate schema for each result
        validator = BenchmarkValidator()
        for i, result in enumerate(saved_results):
            validation_errors = validator.validate(result)
            if validation_errors:
                self.fail(f"Result at index {i} failed schema validation: {validation_errors}")

            # Specific checks based on task requirements (T032b, T062)
            required_keys = [
                "trace_id", "baseline_edit_accuracy", "compressed_edit_accuracy",
                "baseline_retrieval_latency", "compressed_retrieval_latency",
                "latency_std_dev", "latency_p95"
            ]
            
            for key in required_keys:
                self.assertIn(key, result, f"Missing required key '{key}' in result {i}")

            # Verify numeric types
            self.assertIsInstance(result["baseline_edit_accuracy"], (int, float))
            self.assertIsInstance(result["compressed_edit_accuracy"], (int, float))
            self.assertIsInstance(result["baseline_retrieval_latency"], (int, float))
            self.assertIsInstance(result["compressed_retrieval_latency"], (int, float))

            # Verify latency variance metrics (T062)
            self.assertIsInstance(result["latency_std_dev"], (int, float))
            self.assertIsInstance(result["latency_p95"], (int, float))

        print("All validations passed.")

    def test_compressed_agent_performance(self):
        """
        Integration check: Ensure the compressed agent actually runs and produces
        results distinct from a naive failure (e.g., not all NaNs or errors).
        """
        held_out_traces = self._load_held_out_traces()
        global_rules = self._load_global_rules()

        runner = BenchmarkRunner(
            held_out_traces=held_out_traces,
            global_rules=global_rules,
            fidelity_tolerance=0.90,
            seed=42
        )

        results = runner.run()

        # Check that we got results for all traces
        self.assertEqual(len(results), len(held_out_traces))

        # Check that at least some compressed accuracy is non-zero (if rules exist)
        # Note: It's possible accuracy is 0 if rules are bad, but it shouldn't be missing
        compressed_accuracies = [r["compressed_edit_accuracy"] for r in results]
        baseline_accuracies = [r["baseline_edit_accuracy"] for r in results]

        # Assert no NaNs (handled by runner logic, but good to check)
        for acc in compressed_accuracies + baseline_accuracies:
            self.assertFalse(isinstance(acc, float) and acc != acc, "Found NaN in accuracy metrics")

        # Assert latencies are positive
        for r in results:
            self.assertGreaterEqual(r["baseline_retrieval_latency"], 0.0)
            self.assertGreaterEqual(r["compressed_retrieval_latency"], 0.0)


if __name__ == "__main__":
    unittest.main()