def main():
    """
    Main entry point for T037.
    Performs sensitivity analysis sweeping the compression threshold.
    """
    project_root = Path(__file__).resolve().parent.parent.parent
    data_root = project_root / "data"
    
    sweep_config_path = data_root / "processed" / "sweep_config.json"
    sweeps_dir = data_root / "processed" / "rules" / "sweeps"
    held_out_dir = data_root / "held_out"
    output_path = data_root / "processed" / "sensitivity_sweep.csv"

    if not sweep_config_path.exists():
        raise SensitivityAnalysisError(f"Sweep config not found at {sweep_config_path}. "
                                       "Please run sweep_thresholds.py first.")

    print("Loading sweep configuration...")
    sweep_config = load_sweep_config(sweep_config_path)
    
    print("Loading held-out traces...")
    held_out_traces = load_held_out_traces(held_out_dir)
    
    print(f"Running sensitivity sweep on {len(held_out_traces)} traces...")
    results = run_sensitivity_sweep(sweep_config, held_out_traces, sweeps_dir, output_path)
    
    print(f"Sensitivity sweep completed. Results saved to {output_path}")
    print(f"Generated {len(results)} data points.")
    
    return 0

if __name__ == "__main__":
    sys.exit(main())
