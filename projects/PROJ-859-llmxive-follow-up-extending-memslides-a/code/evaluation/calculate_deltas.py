"""
Calculate Edit Accuracy Deltas between Baseline and Compressed agents.

This module computes the difference in Edit Accuracy for each trace in the
held-out set: `delta_acc = baseline_acc - compressed_acc`.

It reads benchmark results from the standard output location and writes
the deltas to `data/processed/accuracy_deltas.csv`.
"""

import json
import os
import sys
import csv
from pathlib import Path
from typing import Dict, Any, List, Tuple, Optional

# Add project root to path for imports
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from config import get_config
from utils.validators import BenchmarkValidator


class DeltaCalculationError(Exception):
    """Custom exception for errors during delta calculation."""
    pass


def load_benchmark_results(results_path: Path) -> List[Dict[str, Any]]:
    """
    Load benchmark results from the JSON file generated by benchmark.py.

    Args:
        results_path: Path to the benchmark_results.json file.

    Returns:
        List of result dictionaries.

    Raises:
        DeltaCalculationError: If the file is missing, empty, or invalid.
    """
    if not results_path.exists():
        raise DeltaCalculationError(
            f"Benchmark results file not found: {results_path}. "
            "Ensure benchmark.py has been executed successfully."
        )

    try:
        with open(results_path, 'r', encoding='utf-8') as f:
            data = json.load(f)
    except json.JSONDecodeError as e:
        raise DeltaCalculationError(f"Invalid JSON in benchmark results: {e}")

    if not isinstance(data, list):
        # Handle case where JSON might be a single object wrapped or different structure
        # Assuming standard output is a list of trace results
        if isinstance(data, dict) and 'results' in data:
            data = data['results']
        else:
            raise DeltaCalculationError(
                f"Expected a list of results in {results_path}, got {type(data)}"
            )

    if len(data) == 0:
        raise DeltaCalculationError(
            f"Benchmark results file {results_path} is empty."
        )

    # Validate structure
    validator = BenchmarkValidator()
    for i, item in enumerate(data):
        if not validator.validate_result(item):
            raise DeltaCalculationError(
                f"Invalid result structure at index {i}: {item}"
            )

    return data


def calculate_deltas(benchmark_results: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Calculate the Edit Accuracy Difference for each trace.

    Formula: delta_acc = baseline_acc - compressed_acc

    Args:
        benchmark_results: List of benchmark result dictionaries.

    Returns:
        List of dictionaries containing trace_id, baseline_acc, compressed_acc, delta_acc.
    """
    deltas = []
    for result in benchmark_results:
        trace_id = result.get('trace_id')
        baseline_acc = result.get('baseline_edit_accuracy')
        compressed_acc = result.get('compressed_edit_accuracy')

        if trace_id is None:
            raise DeltaCalculationError("Result missing 'trace_id'")
        if baseline_acc is None:
            raise DeltaCalculationError(f"Result for {trace_id} missing 'baseline_edit_accuracy'")
        if compressed_acc is None:
            raise DeltaCalculationError(f"Result for {trace_id} missing 'compressed_edit_accuracy'")

        delta_acc = baseline_acc - compressed_acc

        deltas.append({
            'trace_id': trace_id,
            'baseline_acc': baseline_acc,
            'compressed_acc': compressed_acc,
            'delta_acc': delta_acc
        })

    return deltas


def save_deltas(deltas: List[Dict[str, Any]], output_path: Path) -> None:
    """
    Save the calculated deltas to a CSV file.

    Args:
        deltas: List of delta dictionaries.
        output_path: Path to the output CSV file.
    """
    if not deltas:
        raise DeltaCalculationError("No deltas to save.")

    output_path.parent.mkdir(parents=True, exist_ok=True)

    fieldnames = ['trace_id', 'baseline_acc', 'compressed_acc', 'delta_acc']

    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(deltas)


def run_delta_calculation(results_path: Optional[Path] = None, output_path: Optional[Path] = None) -> Path:
    """
    Main entry point to run the delta calculation pipeline.

    Args:
        results_path: Optional path to benchmark results. Defaults to config.
        output_path: Optional path to output CSV. Defaults to config.

    Returns:
        Path to the generated CSV file.
    """
    config = get_config()

    if results_path is None:
        results_path = config['paths']['benchmark_results']
    
    if output_path is None:
        output_path = config['paths']['accuracy_deltas']

    print(f"Loading benchmark results from: {results_path}")
    results = load_benchmark_results(results_path)
    print(f"Loaded {len(results)} benchmark results.")

    print("Calculating accuracy deltas...")
    deltas = calculate_deltas(results)
    print(f"Calculated deltas for {len(deltas)} traces.")

    print(f"Saving deltas to: {output_path}")
    save_deltas(deltas, output_path)
    print("Delta calculation complete.")

    return output_path


def main():
    """CLI entry point."""
    try:
        output_file = run_delta_calculation()
        print(f"Success: Deltas saved to {output_file}")
    except DeltaCalculationError as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f"Unexpected error: {e}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()