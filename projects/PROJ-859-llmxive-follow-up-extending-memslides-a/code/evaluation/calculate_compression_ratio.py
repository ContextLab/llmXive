import csv
import json
import os
import sys
import time
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple

# Import from existing API surface
from config import get_config
from agents.baseline import BaselineAgent
from agents.compressed import CompressedAgent
from utils.loaders import TraceLoader

class CompressionRatioCalculatorError(Exception):
    """Custom exception for compression ratio calculation errors."""
    pass

class CompressionRatioCalculator:
    """
    Calculates compression ratios and fidelity losses for trade-off curve generation.
    
    This class iterates through compressed rule sets generated by T027a (sweep_thresholds.py),
    runs them against a sample of traces, and measures the trade-off between compression
    and performance (fidelity loss).
    """
    
    def __init__(self, config: Dict[str, Any]):
        self.config = config
        self.base_dir = Path(config.get('base_dir', '.'))
        self.data_dir = self.base_dir / 'data'
        self.processed_dir = self.data_dir / 'processed'
        self.rules_dir = self.processed_dir / 'rules'
        self.sweeps_dir = self.rules_dir / 'sweeps'
        
        # Ensure output directories exist
        self.processed_dir.mkdir(parents=True, exist_ok=True)
        self.rules_dir.mkdir(parents=True, exist_ok=True)
        self.sweeps_dir.mkdir(parents=True, exist_ok=True)
        
        # Load held-out traces for evaluation
        self.held_out_dir = self.data_dir / 'held_out'
        if not self.held_out_dir.exists():
            raise CompressionRatioCalculatorError(
                f"Held-out data directory not found: {self.held_out_dir}"
            )
        
        self.trace_loader = TraceLoader()
        self.traces = list(self.trace_loader.load_all_traces(self.held_out_dir))
        
        if not self.traces:
            raise CompressionRatioCalculatorError(
                f"No traces found in {self.held_out_dir}"
            )
    
    def _load_rule_set(self, rule_file_path: Path) -> Dict[str, Any]:
        """Load a compressed rule set from a JSON file."""
        if not rule_file_path.exists():
            raise CompressionRatioCalculatorError(
                f"Rule set file not found: {rule_file_path}"
            )
        
        with open(rule_file_path, 'r') as f:
            return json.load(f)
    
    def _calculate_compression_ratio(
        self, 
        original_rules_path: Path, 
        compressed_rules_path: Path
    ) -> float:
        """
        Calculate compression ratio as: len(compressed_rules) / len(original_rules).
        
        A lower ratio indicates higher compression.
        """
        try:
            with open(original_rules_path, 'r') as f:
                original_rules = json.load(f)
            with open(compressed_rules_path, 'r') as f:
                compressed_rules = json.load(f)
            
            original_count = len(original_rules.get('rules', []))
            compressed_count = len(compressed_rules.get('rules', []))
            
            if original_count == 0:
                return 1.0  # No compression possible if original is empty
            
            return compressed_count / original_count
        except (json.JSONDecodeError, KeyError) as e:
            raise CompressionRatioCalculatorError(
                f"Failed to calculate compression ratio: {e}"
            )
    
    def _calculate_fidelity_loss(
        self, 
        baseline_agent: BaselineAgent, 
        compressed_agent: CompressedAgent, 
        traces: List[Dict[str, Any]]
    ) -> float:
        """
        Calculate fidelity loss as the average accuracy drop between baseline and compressed agents.
        
        Fidelity Loss = 1 - (Compressed Accuracy / Baseline Accuracy)
        """
        if not traces:
            return 0.0
        
        # Sample a subset of traces for efficiency if dataset is large
        sample_size = min(len(traces), self.config.get('evaluation_sample_size', 100))
        sample_traces = traces[:sample_size]
        
        baseline_correct = 0
        compressed_correct = 0
        
        for trace in sample_traces:
            # Extract input and expected output from trace
            # Assuming trace structure has 'input' and 'expected_output' or 'ground_truth'
            trace_input = trace.get('input', trace.get('session_input', {}))
            expected_output = trace.get('expected_output', trace.get('ground_truth', {}))
            
            if not trace_input or not expected_output:
                continue
            
            # Run baseline agent
            try:
                baseline_result = baseline_agent.run(trace_input)
                baseline_output = baseline_result.get('output', baseline_result)
                
                # Simple exact match for edit accuracy (can be extended for fuzzy matching)
                if baseline_output == expected_output:
                    baseline_correct += 1
            except Exception:
                # Baseline failed, skip this trace
                pass
            
            # Run compressed agent
            try:
                compressed_result = compressed_agent.run(trace_input)
                compressed_output = compressed_result.get('output', compressed_result)
                
                if compressed_output == expected_output:
                    compressed_correct += 1
            except Exception:
                # Compressed agent failed, count as incorrect
                pass
        
        total_evaluated = baseline_correct + (sample_size - baseline_correct)
        if total_evaluated == 0:
            return 1.0  # Complete failure
        
        baseline_accuracy = baseline_correct / total_evaluated
        compressed_accuracy = compressed_correct / total_evaluated
        
        if baseline_accuracy == 0:
            return 1.0  # No baseline performance to compare
        
        fidelity_loss = 1.0 - (compressed_accuracy / baseline_accuracy)
        return max(0.0, min(1.0, fidelity_loss))  # Clamp to [0, 1]
    
    def calculate_trade_off_curve(
        self, 
        original_rules_path: Optional[Path] = None,
        sweep_dir: Optional[Path] = None
    ) -> List[Dict[str, Any]]:
        """
        Calculate the trade-off curve by evaluating each compressed rule set.
        
        Args:
            original_rules_path: Path to the original global rules (for compression ratio calculation)
            sweep_dir: Directory containing compressed rule sets from sweep_thresholds.py
        
        Returns:
            List of dictionaries containing threshold, compression_ratio, and fidelity_loss
        """
        # Default paths
        if original_rules_path is None:
            original_rules_path = self.rules_dir / 'global_rules.json'
        
        if sweep_dir is None:
            sweep_dir = self.sweeps_dir
        
        if not sweep_dir.exists():
            raise CompressionRatioCalculatorError(
                f"Sweep directory not found: {sweep_dir}. "
                "Please run sweep_thresholds.py (T027a) first."
            )
        
        if not original_rules_path.exists():
            raise CompressionRatioCalculatorError(
                f"Original rules file not found: {original_rules_path}. "
                "Please ensure global_rules.json exists (T026b)."
            )
        
        # Initialize agents
        baseline_agent = BaselineAgent(self.config)
        compressed_agent = CompressedAgent(self.config)
        
        # Collect all rule set files
        rule_files = sorted(sweep_dir.glob('rules_*.json'))
        
        if not rule_files:
            raise CompressionRatioCalculatorError(
                f"No rule set files found in {sweep_dir}. "
                "Run sweep_thresholds.py (T027a) to generate compressed rule sets."
            )
        
        trade_off_data = []
        
        for rule_file in rule_files:
            try:
                # Extract threshold from filename (e.g., rules_min_support_0.5.json)
                # Assuming filename format: rules_{metric}_{value}.json
                filename = rule_file.stem
                parts = filename.split('_')
                threshold_value = float(parts[-1]) if len(parts) > 1 else 0.0
                
                # Load compressed rules
                compressed_rules = self._load_rule_set(rule_file)
                
                # Set rules for compressed agent
                compressed_agent.rules = compressed_rules.get('rules', [])
                
                # Calculate compression ratio
                compression_ratio = self._calculate_compression_ratio(
                    original_rules_path, rule_file
                )
                
                # Calculate fidelity loss
                fidelity_loss = self._calculate_fidelity_loss(
                    baseline_agent, compressed_agent, self.traces
                )
                
                trade_off_data.append({
                    'threshold': threshold_value,
                    'compression_ratio': compression_ratio,
                    'fidelity_loss': fidelity_loss
                })
                
            except Exception as e:
                # Log error but continue processing other rule sets
                print(f"Error processing {rule_file}: {e}", file=sys.stderr)
                continue
        
        return trade_off_data
    
    def save_trade_off_curve(
        self, 
        trade_off_data: List[Dict[str, Any]], 
        output_path: Optional[Path] = None
    ) -> Path:
        """
        Save the trade-off curve data to a CSV file.
        
        Args:
            trade_off_data: List of dictionaries with threshold, compression_ratio, fidelity_loss
            output_path: Optional custom output path
        
        Returns:
            Path to the saved CSV file
        """
        if output_path is None:
            output_path = self.processed_dir / 'trade_off_curve.csv'
        
        if not trade_off_data:
            raise CompressionRatioCalculatorError(
                "No trade-off data to save. Ensure rule sets were processed successfully."
            )
        
        with open(output_path, 'w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=['threshold', 'compression_ratio', 'fidelity_loss'])
            writer.writeheader()
            writer.writerows(trade_off_data)
        
        print(f"Trade-off curve saved to {output_path}")
        return output_path


def calculate_compression_ratios(
    config: Dict[str, Any],
    original_rules_path: Optional[Path] = None,
    sweep_dir: Optional[Path] = None,
    output_path: Optional[Path] = None
) -> Path:
    """
    Main function to calculate compression ratios and fidelity losses.
    
    This function orchestrates the calculation of the trade-off curve by:
    1. Loading compressed rule sets from sweep_thresholds.py output
    2. Evaluating each rule set against held-out traces
    3. Calculating compression ratios and fidelity losses
    4. Saving results to a CSV file
    
    Args:
        config: Configuration dictionary
        original_rules_path: Path to original global rules
        sweep_dir: Directory containing compressed rule sets
        output_path: Path for the output CSV file
    
    Returns:
        Path to the saved trade-off curve CSV file
    """
    calculator = CompressionRatioCalculator(config)
    trade_off_data = calculator.calculate_trade_off_curve(
        original_rules_path=original_rules_path,
        sweep_dir=sweep_dir
    )
    return calculator.save_trade_off_curve(trade_off_data, output_path)


def main():
    """Entry point for the compression ratio calculation script."""
    try:
        config = get_config()
        print("Starting compression ratio calculation...")
        print(f"Config loaded: {config.get('base_dir', 'default')}")
        
        # Define paths based on config
        base_dir = Path(config.get('base_dir', '.'))
        rules_dir = base_dir / 'data' / 'processed' / 'rules'
        sweeps_dir = rules_dir / 'sweeps'
        original_rules_path = rules_dir / 'global_rules.json'
        output_path = base_dir / 'data' / 'processed' / 'trade_off_curve.csv'
        
        # Execute calculation
        result_path = calculate_compression_ratios(
            config=config,
            original_rules_path=original_rules_path,
            sweep_dir=sweeps_dir,
            output_path=output_path
        )
        
        print(f"Successfully generated trade-off curve at: {result_path}")
        
        # Print summary
        if result_path.exists():
            with open(result_path, 'r') as f:
                reader = csv.DictReader(f)
                rows = list(reader)
                print(f"\nSummary:")
                print(f"  Total data points: {len(rows)}")
                if rows:
                    avg_compression = sum(float(r['compression_ratio']) for r in rows) / len(rows)
                    avg_fidelity_loss = sum(float(r['fidelity_loss']) for r in rows) / len(rows)
                    print(f"  Avg Compression Ratio: {avg_compression:.4f}")
                    print(f"  Avg Fidelity Loss: {avg_fidelity_loss:.4f}")
        
    except CompressionRatioCalculatorError as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f"Unexpected error: {e}", file=sys.stderr)
        import traceback
        traceback.print_exc()
        sys.exit(1)


if __name__ == '__main__':
    main()
