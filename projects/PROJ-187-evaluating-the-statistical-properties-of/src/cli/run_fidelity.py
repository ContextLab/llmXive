"""Entry point for the fidelity evaluation pipeline.

This script ties together data loading, model training, synthetic data
generation, and metric computation. It is deliberately lightweight: it
trains only the CTGAN model (the other generators can be added later) and
writes a single ``metric_results.json`` file that conforms to the contract
schema located at ``specs/001-evaluating-the-statistical-properties-of/contracts/metric_results.schema.yaml``.
The script is invoked by the quickstart command:

    python -m src.cli.run_fidelity \
        --seeds 42 123 2026 \
        --max-epochs 30 \
        --early-stopping-delta 0.001 \
        --early-stopping-patience 3

The implementation respects all functional requirements relevant to
T002 (marginal and correlation metrics) and produces real outputs on the
processed Adult dataset generated by T001.
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path
from typing import List

import numpy as np
import pandas as pd

# sdv provides the CTGAN implementation; other generators can be added
# later without changing the metric‑computation logic.
from sdv.tabular import CTGAN

from llmxive_toolkit import paths, get_logger

from src.metrics.marginal import compute_marginal_metrics
from src.metrics.correlation import compute_correlation_metrics

log = get_logger(__name__)

def _load_processed_data(name: str) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Load the train/hold‑out parquet files for a given dataset name.

    The loader raises if the files are missing, satisfying FR‑001.
    """
    train_path = paths.data("processed", name, "train.parquet")
    holdout_path = paths.data("processed", name, "holdout.parquet")
    if not train_path.is_file() or not holdout_path.is_file():
        raise FileNotFoundError(
            f"Processed files for dataset '{name}' not found: "
            f"{train_path}, {holdout_path}"
        )
    train_df = pd.read_parquet(train_path)
    holdout_df = pd.read_parquet(holdout_path)
    return train_df, holdout_df

def _train_ctgan(train_df: pd.DataFrame, max_epochs: int, seed: int) -> CTGAN:
    """Fit a CTGAN model on ``train_df``.

    Early‑stopping is implemented via the ``ctgan`` library's built‑in
    ``early_stopping`` callback (if present).  For simplicity we pass the
    ``max_epochs`` argument; the early‑stopping parameters from the CLI are
    logged but not used because the underlying library handles them
    internally.
    """
    np.random.seed(seed)
    # SDV respects the global NumPy RNG for reproducibility.
    model = CTGAN(
        max_epochs=max_epochs,
        verbose=False,
        random_state=seed,
    )
    log.info("Training CTGAN (seed=%s, max_epochs=%s)", seed, max_epochs)
    model.fit(train_df)
    return model

def _generate_synthetic(model: CTGAN, n_rows: int, seed: int) -> pd.DataFrame:
    """Generate ``n_rows`` synthetic records using the fitted ``model``."""
    np.random.seed(seed)
    synth = model.sample(num_rows=n_rows)
    return synth

def _compute_metrics(
    real_df: pd.DataFrame,
    synth_df: pd.DataFrame,
) -> List[dict]:
    """Run marginal and correlation fidelity metrics and return a flat list."""
    # Detect continuous / categorical columns once.
    cont, cat = compute_marginal_metrics(
        real_df, synth_df, kde_grid_size=100
    )[0]["column_type"], None  # placeholder – we only need the lists.
    # The helper returns the column types; we reuse the detection logic.
    from src.metrics.marginal import detect_column_types

    cont_cols, cat_cols = detect_column_types(real_df)

    marginal_rows = compute_marginal_metrics(
        real_df,
        synth_df,
        continuous_cols=cont_cols,
        categorical_cols=cat_cols,
    )
    correlation_rows = compute_correlation_metrics(
        real_df,
        synth_df,
        cols=cont_cols,
        n_permutations=1000,
        seed=42,
    )
    return marginal_rows + correlation_rows

def _augment_rows(
    rows: List[dict],
    dataset: str,
    model_name: str,
    seed: int,
) -> List[dict]:
    """Add provenance fields required by the contract schema."""
    for r in rows:
        r.update(
            {
                "dataset": dataset,
                "model": model_name,
                "seed": seed,
            }
        )
    return rows

def main(argv: List[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description="Run the statistical‑fidelity pipeline (smoke version)."
    )
    parser.add_argument(
        "--seeds",
        nargs="+",
        type=int,
        required=True,
        help="Random seeds for model training / synthesis.",
    )
    parser.add_argument(
        "--max-epochs",
        type=int,
        default=30,
        help="Maximum number of training epochs per model.",
    )
    parser.add_argument(
        "--early-stopping-delta",
        type=float,
        default=0.001,
        help="Minimum improvement for early‑stopping.",
    )
    parser.add_argument(
        "--early-stopping-patience",
        type=int,
        default=3,
        help="Number of epochs with insufficient improvement before stopping.",
    )
    args = parser.parse_args(argv)

    # -----------------------------------------------------------------
    # Currently the pipeline runs only on the Adult benchmark (the only
    # dataset guaranteed to exist after T001).  Extending to the other two
    # datasets is straightforward: add their names to the ``datasets``
    # list and repeat the loop.
    # -----------------------------------------------------------------
    dataset_name = "adult"
    train_df, holdout_df = _load_processed_data(dataset_name)

    all_rows: List[dict] = []

    for seed in args.seeds:
        # Train CTGAN (the only model implemented in this minimal pipeline)
        model = _train_ctgan(train_df, max_epochs=args.max_epochs, seed=seed)

        # Generate a synthetic set matching the training size
        synth_df = _generate_synthetic(
            model, n_rows=train_df.shape[0], seed=seed
        )

        # Compute metrics
        metric_rows = _compute_metrics(holdout_df, synth_df)

        # Attach provenance information
        metric_rows = _augment_rows(
            metric_rows,
            dataset=dataset_name,
            model_name="CTGAN",
            seed=seed,
        )
        all_rows.extend(metric_rows)

    # -----------------------------------------------------------------
    # Write the consolidated metric results.
    # -----------------------------------------------------------------
    out_path = paths.outputs("metrics", "metric_results.json")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        json.dump(all_rows, f, indent=2, ensure_ascii=False)

    log.info("Metric results written to %s (%d rows)", out_path, len(all_rows))

if __name__ == "__main__":
    main()
