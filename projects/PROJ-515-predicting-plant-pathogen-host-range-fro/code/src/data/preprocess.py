# --- Helper Functions (from T010C context) ---

def load_interactions(data_dir: str) -> pd.DataFrame:
    """
    Load the merged interaction table from data/raw/interactions_merged.csv.
    """
    path = Path(data_dir) / "raw" / "interactions_merged.csv"
    if not path.exists():
        raise FileNotFoundError(f"Interaction file not found: {path}")
    
    df = pd.read_csv(path)
    # Ensure required columns exist
    required_cols = ['pathogen_id', 'host_id', 'interaction_type']
    for col in required_cols:
        if col not in df.columns:
            raise ValueError(f"Missing required column in interactions: {col}")
    
    return df

def filter_unknown_labels(df: pd.DataFrame) -> pd.DataFrame:
    """
    Filter out rows where interaction_type is 'unknown'.
    These are treated as missing data and excluded from training labels.
    """
    initial_count = len(df)
    df_clean = df[df['interaction_type'] != 'unknown'].copy()
    final_count = len(df_clean)
    logger.info(f"Filtered {initial_count - final_count} unknown interaction labels.")
    return df_clean

def load_valid_pathogens(data_dir: str) -> List[str]:
    """
    Load the list of valid pathogens from data/processed/valid_pathogens.json.
    This file is generated by T010C (Zero Interaction check).
    """
    path = Path(data_dir) / "processed" / "valid_pathogens.json"
    if not path.exists():
        # Fallback for testing if file doesn't exist yet, though task says it must exist
        logger.warning(f"valid_pathogens.json not found at {path}. Returning empty list.")
        return []
    
    with open(path, 'r') as f:
        valid_list = json.load(f)
    
    logger.info(f"Loaded {len(valid_list)} valid pathogens.")
    return valid_list

# --- Core Task T013 Implementation ---

def split_pathogen_stratified(
    interactions_df: pd.DataFrame,
    valid_pathogens: List[str],
    data_dir: str,
    train_ratio: float = 0.7,
    val_ratio: float = 0.15,
    holdout_ratio: float = 0.15, # 10 pathogens holdout logic handled below
    seed: int = 42
) -> Tuple[Dict, Dict]:
    """
    Implement pathogen-stratified Train/Val/Holdout split.
    
    Logic:
    1. Aggregate interactions per pathogen to determine host diversity (stratification variable).
       Since we are splitting pathogens, we need a metric to stratify by. 
       Common metric: Number of unique hosts or total interaction count.
       We will use 'unique_host_count' as the stratification variable.
    
    2. Reserve a 10-pathogen hold-out set for independent validation (FR-012).
       We select 10 pathogens that are representative of the distribution.
    
    3. Split the remaining pathogens into Train and Val sets based on the ratios.
    
    Returns:
        train_val_split: Dict with 'train_indices', 'val_indices' (pathogen IDs)
        holdout_set: Dict with 'holdout_indices' (pathogen IDs)
    """
    np.random.seed(seed)
    
    # Filter interactions to only valid pathogens
    interactions_df = interactions_df[interactions_df['pathogen_id'].isin(valid_pathogens)].copy()
    
    if len(interactions_df) == 0:
        raise ValueError("No interactions found for valid pathogens. Cannot split.")

    # Calculate stratification metric: unique hosts per pathogen
    pathogen_stats = interactions_df.groupby('pathogen_id').agg(
        unique_host_count=('host_id', 'nunique'),
        interaction_count=('host_id', 'size')
    ).reset_index()

    # Ensure we have enough pathogens for the split
    total_pathogens = len(pathogen_stats)
    holdout_size = 10
    
    if total_pathogens < holdout_size + 2: # Need at least 1 train, 1 val, 10 holdout
        raise ValueError(f"Insufficient pathogens ({total_pathogens}) for splitting. Need at least {holdout_size + 2}.")

    # Sort by unique_host_count to facilitate stratified sampling
    # We want to ensure the distribution of host diversity is similar across splits.
    # Simple approach: Sort and slice, or use sklearn's StratifiedShuffleSplit if we bin the counts.
    # Given the small dataset size (50 pathogens), we will use a deterministic sort and slice approach
    # or a simple stratified shuffle if we bin the counts.
    
    # Bin the unique_host_count into 4 bins for stratification
    pathogen_stats['host_diversity_bin'] = pd.qcut(
        pathogen_stats['unique_host_count'], 
        q=4, 
        labels=False, 
        duplicates='drop'
    )
    
    # If qcut fails (too few unique values), fallback to simple sort
    if len(pathogen_stats['host_diversity_bin'].unique()) < 2:
        pathogen_stats = pathogen_stats.sort_values('unique_host_count')
        pathogen_stats['host_diversity_bin'] = 0
    
    # Shuffle within bins
    pathogen_stats = pathogen_stats.groupby('host_diversity_bin', group_keys=False).apply(
        lambda x: x.sample(frac=1, random_state=seed)
    ).reset_index(drop=True)

    # 1. Select Holdout Set (10 pathogens)
    # Take the first 10 from the stratified shuffle
    holdout_pathogens = pathogen_stats.head(holdout_size)['pathogen_id'].tolist()
    
    # 2. Split remaining into Train and Val
    remaining_pathogens = pathogen_stats.iloc[holdout_size:]
    remaining_count = len(remaining_pathogens)
    
    train_count = int(remaining_count * (train_ratio / (train_ratio + val_ratio)))
    # Ensure we don't take more than available
    train_count = min(train_count, remaining_count - 1) 
    if train_count == 0:
        train_count = 1 # Ensure at least one train
        
    val_count = remaining_count - train_count
    
    train_pathogens = remaining_pathogens.head(train_count)['pathogen_id'].tolist()
    val_pathogens = remaining_pathogens.tail(val_count)['pathogen_id'].tolist()
    
    logger.info(f"Split complete: Train={len(train_pathogens)}, Val={len(val_pathogens)}, Holdout={len(holdout_pathogens)}")
    
    train_val_split = {
        "train_indices": train_pathogens,
        "val_indices": val_pathogens
    }
    
    holdout_set = {
        "holdout_indices": holdout_pathogens
    }
    
    return train_val_split, holdout_set

def save_split_metadata(
    train_val_split: Dict,
    holdout_set: Dict,
    output_dir: str
):
    """
    Save the split metadata to JSON files in data/processed/.
    """
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)
    
    # Save Train/Val split
    train_val_path = output_path / "train_val_split.json"
    with open(train_val_path, 'w') as f:
        json.dump(train_val_split, f, indent=2)
    logger.info(f"Saved train/val split to {train_val_path}")
    
    # Save Holdout set
    holdout_path = output_path / "holdout_set.json"
    with open(holdout_path, 'w') as f:
        json.dump(holdout_set, f, indent=2)
    logger.info(f"Saved holdout set to {holdout_path}")

def run_preprocessing_pipeline(data_dir: str, output_dir: str, seed: int = 42):
    """
    Orchestrates the full preprocessing pipeline:
    1. Load interactions
    2. Filter unknowns
    3. Load valid pathogens
    4. Perform pathogen-stratified split (T013)
    5. Save metadata
    """
    logger.info("Starting preprocessing pipeline...")
    
    # 1. Load
    interactions_df = load_interactions(data_dir)
    valid_pathogens = load_valid_pathogens(data_dir)
    
    # 2. Filter
    interactions_df = filter_unknown_labels(interactions_df)
    
    # 3. Split (T013)
    train_val_split, holdout_set = split_pathogen_stratified(
        interactions_df, 
        valid_pathogens, 
        data_dir, 
        seed=seed
    )
    
    # 4. Save
    save_split_metadata(train_val_split, holdout_set, output_dir)
    
    logger.info("Preprocessing pipeline completed.")
    return train_val_split, holdout_set

def main():
    """
    CLI entry point for preprocessing.
    """
    import argparse
    
    parser = argparse.ArgumentParser(description="Preprocessing Pipeline")
    parser.add_argument("--data-dir", type=str, default="data", help="Base data directory")
    parser.add_argument("--output-dir", type=str, default="data/processed", help="Output directory for splits")
    parser.add_argument("--seed", type=int, default=42, help="Random seed")
    
    args = parser.parse_args()
    
    run_preprocessing_pipeline(args.data_dir, args.output_dir, args.seed)

if __name__ == "__main__":
    main()
