    # 5. Calculate Correlation
    r, p = calculate_correlation(pilot_results, manual_scores)
    logger.info(f"Pilot Correlation (r): {r:.4f}, p-value: {p:.4f}")
    
    # 6. Enforce Halt Logic (FR-009)
    threshold = 0.7
    if r < threshold:
        logger.error(f"CRITICAL: Correlation r={r:.4f} is below threshold {threshold}. HALTING.")
