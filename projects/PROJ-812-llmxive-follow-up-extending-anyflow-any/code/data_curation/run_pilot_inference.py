def load_pilot_ids() -> List[str]:
    """Load pilot subset IDs from data/raw/pilot_subset_ids.csv."""
    path = Path("data/raw/pilot_subset_ids.csv")
    if not path.exists():
        logger.error(f"Pilot subset file not found: {path}")
        sys.exit(1)
    
    ids = []
    with open(path, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            ids.append(row['video_id'])
    return ids

def load_manual_scores(pilot_ids: List[str]) -> Dict[str, float]:
    """Load manual scores from data/raw/calibration_scores.csv for pilot IDs."""
    path = Path("data/raw/calibration_scores.csv")
    if not path.exists():
        logger.error(f"Calibration scores file not found: {path}")
        sys.exit(1)
    
    scores = {}
    with open(path, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            vid = row['video_id']
            if vid in pilot_ids:
                # Average if multiple annotators
                score = float(row['score'])
                if vid in scores:
                    scores[vid] = (scores[vid] + score) / 2.0
                else:
                    scores[vid] = score
    return scores

