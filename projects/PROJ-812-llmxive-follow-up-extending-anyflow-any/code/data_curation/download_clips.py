"""
T009: Download and stratify clips from Kinetics and UCF101 based on manual verification pool.

This script reads `data/raw/manually_verified_pool.csv` (generated by T008a),
performs stratified sampling to ensure equal proportions of 'continuous' and 'cut'
clips, and downloads the corresponding video segments to `data/raw/clips/`.

Dependencies:
    - datasets (for Kinetics)
    - ucimlrepo (for UCF101)
    - pandas
    - opencv-python-headless

Output:
    - data/raw/clips/<video_id>.mp4 (downloaded clips)
    - data/raw/clips/sampling_manifest.json (metadata of selected clips)
"""

import os
import json
import shutil
import tempfile
from pathlib import Path
from typing import List, Dict, Any, Tuple
import hashlib

import pandas as pd
import cv2
import numpy as np

# External dataset libraries
from datasets import load_dataset
from ucimlrepo import fetch_ucirepo

# Project internal imports
from utils.logging import get_logger
from utils.memory_utils import clear_memory
from utils.hash_utils import compute_sha256

logger = get_logger(__name__)

# Configuration
INPUT_POOL_PATH = Path("data/raw/manually_verified_pool.csv")
OUTPUT_DIR = Path("data/raw/clips")
MANIFEST_PATH = OUTPUT_DIR / "sampling_manifest.json"
CLIP_DURATION_SECONDS = 5.0  # Standard clip duration for analysis
TARGET_SAMPLE_SIZE = 100  # Total clips to download (50 continuous, 50 cut)
FRAMES_PER_SECOND = 25

def load_verification_pool() -> pd.DataFrame:
    """
    Load the manually verified pool from CSV.
    Expects columns: 'video_id', 'source_dataset', 'label' (continuous/cut), 'path' (optional)
    """
    if not INPUT_POOL_PATH.exists():
        raise FileNotFoundError(
            f"Verification pool not found at {INPUT_POOL_PATH}. "
            "Ensure T008a (annotation_tool.py) has been run successfully."
        )
    
    df = pd.read_csv(INPUT_POOL_PATH)
    
    # Validate required columns
    required_cols = ['video_id', 'source_dataset', 'label']
    missing = [col for col in required_cols if col not in df.columns]
    if missing:
        raise ValueError(f"Verification pool missing required columns: {missing}")
    
    # Normalize labels
    df['label'] = df['label'].astype(str).str.lower().str.strip()
    
    logger.info(f"Loaded {len(df)} clips from verification pool.")
    logger.info(f"Label distribution:\n{df['label'].value_counts()}")
    
    return df

def stratified_sample(df: pd.DataFrame, target_size: int) -> pd.DataFrame:
    """
    Perform stratified sampling to ensure equal representation of 'continuous' and 'cut'.
    """
    # Check if we have enough samples in each class
    label_counts = df['label'].value_counts()
    if 'continuous' not in label_counts or 'cut' not in label_counts:
        raise ValueError(
            "Verification pool must contain both 'continuous' and 'cut' labels "
            "for stratified sampling."
        )
    
    min_count = min(label_counts['continuous'], label_counts['cut'])
    samples_per_class = min(target_size // 2, min_count)
    
    if samples_per_class < 1:
        raise ValueError(
            f"Insufficient samples in verification pool to create a balanced set of {target_size}. "
            f"Found {min_count} in the minority class."
        )
    
    sampled_continuous = df[df['label'] == 'continuous'].sample(
        n=samples_per_class, random_state=42
    )
    sampled_cut = df[df['label'] == 'cut'].sample(
        n=samples_per_class, random_state=42
    )
    
    sample_df = pd.concat([sampled_continuous, sampled_cut])
    logger.info(f"Stratified sampling selected {len(sample_df)} clips "
                f"({samples_per_class} continuous, {samples_per_class} cut).")
    
    return sample_df

def extract_clip_from_frames(frames: List[np.ndarray], output_path: Path) -> bool:
    """
    Extract a clip from a list of frames and save as MP4.
    """
    if not frames:
        return False
    
    # Ensure frames are uint8
    frames = [f.astype(np.uint8) for f in frames]
    height, width = frames[0].shape[:2]
    
    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    out = cv2.VideoWriter(
        str(output_path), 
        fourcc, 
        FRAMES_PER_SECOND, 
        (width, height)
    )
    
    for frame in frames:
        out.write(frame)
    
    out.release()
    return output_path.exists() and output_path.stat().st_size > 0

def download_kinetics_clip(video_id: str, target_path: Path) -> bool:
    """
    Download a clip from Kinetics dataset.
    Kinetics uses 'source_dataset' column to identify subset (e.g., 'kinetics400').
    We assume the video_id corresponds to the Kinetics ID format.
    """
    logger.info(f"Attempting to download Kinetics clip: {video_id}")
    
    try:
        # Load Kinetics dataset (streaming to save memory)
        # Note: Kinetics is large, so we use streaming=True
        dataset = load_dataset(
            "kinetics-400", 
            split="train", 
            streaming=True
        )
        
        found = False
        frames = []
        
        # Iterate through dataset to find the specific video
        # This is inefficient for large datasets but necessary for specific ID lookup
        # In a production pipeline, we would pre-index the dataset.
        for item in dataset:
            if item['id'] == video_id:
                found = True
                video_bytes = item['video'].read()
                
                # Decode video to frames
                nparr = np.frombuffer(video_bytes, np.uint8)
                cap = cv2.imdecode(nparr, cv2.IMREAD_COLOR) # This might fail for video bytes
                
                # If direct decode fails, we might need to save to temp and read with VideoCapture
                # However, kinetics-400 usually returns bytes that need decoding.
                # Let's try to write to a temp file first to be safe.
                with tempfile.NamedTemporaryFile(suffix='.mp4', delete=False) as tmp:
                    tmp.write(video_bytes)
                    tmp_path = tmp.name
                
                cap = cv2.VideoCapture(tmp_path)
                
                if not cap.isOpened():
                    logger.error(f"Failed to open video for {video_id}")
                    os.unlink(tmp_path)
                    return False
                
                frame_count = 0
                target_frames = int(FRAMES_PER_SECOND * CLIP_DURATION_SECONDS)
                
                while True:
                    ret, frame = cap.read()
                    if not ret:
                        break
                    frames.append(frame)
                    frame_count += 1
                    if frame_count >= target_frames:
                        break
                
                cap.release()
                os.unlink(tmp_path)
                
                if frames:
                    return extract_clip_from_frames(frames, target_path)
                else:
                    logger.warning(f"No frames extracted for {video_id}")
                    return False
        
        if not found:
            logger.warning(f"Video ID {video_id} not found in Kinetics train split.")
            return False
            
    except Exception as e:
        logger.error(f"Error downloading Kinetics clip {video_id}: {e}", exc_info=True)
        return False
    
    return False

def download_ucf101_clip(video_id: str, target_path: Path) -> bool:
    """
    Download a clip from UCF101 using ucimlrepo.
    UCF101 IDs are typically class-specific (e.g., 'ApplyEyeMakeup/v_ApplyEyeMakeup_g01_c01').
    """
    logger.info(f"Attempting to download UCF101 clip: {video_id}")
    
    try:
        # Fetch UCF101 dataset
        ucf101 = fetch_ucirepo(id=287) # UCF101 ID is 287
        video_files = ucf101.files
        
        # The ucimlrepo returns a list of file URLs or paths.
        # We need to map the video_id to the correct file.
        # UCF101 file names usually match the video_id pattern.
        
        # Check if the file exists in the list
        file_url = None
        for f in video_files:
            if video_id in f['name']:
                file_url = f['url']
                break
        
        if not file_url:
            logger.warning(f"Video ID {video_id} not found in UCF101 file list.")
            return False
        
        # Download the file
        with tempfile.NamedTemporaryFile(suffix='.mp4', delete=False) as tmp:
            # Use requests or urllib to download if ucimlrepo doesn't handle it directly
            # Assuming ucimlrepo provides a way to get the path or we download via URL
            import urllib.request
            urllib.request.urlretrieve(file_url, tmp.name)
            tmp_path = tmp.name
        
        # Extract frames
        cap = cv2.VideoCapture(tmp_path)
        if not cap.isOpened():
            os.unlink(tmp_path)
            return False
        
        frames = []
        target_frames = int(FRAMES_PER_SECOND * CLIP_DURATION_SECONDS)
        
        while True:
            ret, frame = cap.read()
            if not ret:
                break
            frames.append(frame)
            if len(frames) >= target_frames:
                break
        
        cap.release()
        os.unlink(tmp_path)
        
        if frames:
            return extract_clip_from_frames(frames, target_path)
        else:
            logger.warning(f"No frames extracted for UCF101 {video_id}")
            return False
            
    except Exception as e:
        logger.error(f"Error downloading UCF101 clip {video_id}: {e}", exc_info=True)
        return False

def main():
    """
    Main entry point for T009.
    1. Load verification pool.
    2. Stratified sample.
    3. Download clips to data/raw/clips/.
    4. Generate manifest with checksums.
    """
    # Ensure output directory exists
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    
    # Load and sample
    logger.info("Loading verification pool...")
    pool_df = load_verification_pool()
    
    logger.info("Performing stratified sampling...")
    sample_df = stratified_sample(pool_df, TARGET_SAMPLE_SIZE)
    
    success_count = 0
    failed_ids = []
    manifest_data = []
    
    for idx, row in sample_df.iterrows():
        video_id = row['video_id']
        source = row['source_dataset']
        label = row['label']
        
        output_path = OUTPUT_DIR / f"{video_id}.mp4"
        
        # Skip if already exists
        if output_path.exists():
            logger.info(f"Skipping {video_id}: already exists.")
            success_count += 1
            continue
        
        success = False
        if source.lower() == 'kinetics':
            success = download_kinetics_clip(video_id, output_path)
        elif source.lower() == 'ucf101':
            success = download_ucf101_clip(video_id, output_path)
        else:
            logger.error(f"Unknown source dataset: {source} for {video_id}")
        
        if success:
            success_count += 1
            # Compute hash
            file_hash = compute_sha256(output_path)
            manifest_data.append({
                "video_id": video_id,
                "source": source,
                "label": label,
                "file_path": str(output_path),
                "sha256": file_hash,
                "status": "downloaded"
            })
            logger.info(f"Successfully downloaded {video_id} ({source}) -> {output_path.name}")
        else:
            failed_ids.append(video_id)
            manifest_data.append({
                "video_id": video_id,
                "source": source,
                "label": label,
                "file_path": str(output_path),
                "sha256": None,
                "status": "failed"
            })
            logger.warning(f"Failed to download {video_id} ({source})")
        
        # Clear memory periodically
        if idx % 10 == 0:
            clear_memory()
    
    # Write manifest
    with open(MANIFEST_PATH, 'w') as f:
        json.dump({
            "total_requested": len(sample_df),
            "successful": success_count,
            "failed": len(failed_ids),
            "failed_ids": failed_ids,
            "clips": manifest_data
        }, f, indent=2)
    
    logger.info(f"Download complete. Success: {success_count}/{len(sample_df)}")
    if failed_ids:
        logger.warning(f"Failed downloads: {failed_ids}")
    
    # Final memory cleanup
    clear_memory()
    
    return success_count == len(sample_df)

if __name__ == "__main__":
    success = main()
    exit(0 if success else 1)
