"""
Task T011b: Validate Annotation Agreement (Cohen's Kappa)

Reads `data/raw/calibration_scores.csv` (generated by T011a), calculates
Cohen's Kappa for dual-annotator agreement, and generates `data/processed/kappa_report.json`.

HARD HALT: If Kappa < 0.81, exits with code 1 and prints "Insufficient Annotation Agreement".
"""
import os
import sys
import json
import csv
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional
from collections import defaultdict

# Project imports
from utils.logging import get_logger

# Constants
KAPPA_THRESHOLD = 0.81
INPUT_FILE = "data/raw/calibration_scores.csv"
OUTPUT_FILE = "data/processed/kappa_report.json"

logger = get_logger(__name__)


def load_calibration_scores(file_path: str) -> List[Dict[str, Any]]:
    """
    Loads the calibration scores CSV.
    Expected columns: video_id, annotator_id, score
    """
    scores = []
    path = Path(file_path)
    if not path.exists():
        logger.error(f"Input file not found: {file_path}")
        raise FileNotFoundError(f"Input file not found: {file_path}")

    with open(path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            scores.append({
                "video_id": row["video_id"],
                "annotator_id": row["annotator_id"],
                "score": float(row["score"])
            })
    return scores


def binarize_score(score: float, threshold: float = 0.5) -> int:
    """
    Binarizes the continuous score [0.0, 1.0] into a discrete class.
    < 0.5 -> 0 (Continuous)
    >= 0.5 -> 1 (Discontinuous/Cut)
    This is required for Cohen's Kappa which operates on categorical data.
    """
    return 1 if score >= threshold else 0


def calculate_cohens_kappa(
    ratings: List[tuple],
    categories: int = 2
) -> float:
    """
    Calculates Cohen's Kappa for a list of (rater1, rater2) tuples.
    """
    if not ratings:
        return 0.0

    n = len(ratings)
    # Count agreements and total counts per category
    # Observed Agreement (Po)
    agreements = sum(1 for r1, r2 in ratings if r1 == r2)
    po = agreements / n

    # Expected Agreement (Pe)
    # Count occurrences for each rater
    r1_counts = defaultdict(int)
    r2_counts = defaultdict(int)

    for r1, r2 in ratings:
        r1_counts[r1] += 1
        r2_counts[r2] += 1

    pe = 0.0
    for cat in range(categories):
        p1 = r1_counts[cat] / n
        p2 = r2_counts[cat] / n
        pe += p1 * p2

    if pe == 1.0:
        # Perfect agreement expected by chance (e.g., all same class)
        return 1.0

    kappa = (po - pe) / (1 - pe)
    return kappa


def validate_kappa():
    """
    Main entry point for T011b.
    Reads scores, calculates Kappa, writes report, and enforces the hard halt.
    """
    logger.info("Starting Kappa validation (T011b)...")

    # Ensure output directory exists
    output_path = Path(OUTPUT_FILE)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    try:
        scores = load_calibration_scores(INPUT_FILE)
    except FileNotFoundError as e:
        logger.error(str(e))
        sys.exit(1)

    if len(scores) < 2:
        logger.error("Insufficient data to calculate Kappa (need at least 2 rows).")
        sys.exit(1)

    # Group scores by video_id to pair annotators
    # Expected format: video_id -> {annotator_id: score}
    video_ratings = defaultdict(dict)
    for item in scores:
        video_ratings[item["video_id"]][item["annotator_id"]] = item["score"]

    # Prepare pairs for Kappa calculation
    # We assume exactly 2 annotators per video for the pilot as per T011a spec
    kappa_pairs = []
    valid_videos = []
    skipped_videos = []

    for vid, annotator_scores in video_ratings.items():
        if len(annotator_scores) != 2:
            skipped_videos.append(vid)
            logger.warning(f"Skipping video {vid}: Expected 2 annotators, found {len(annotator_scores)}")
            continue

        # Extract the two scores
        vals = list(annotator_scores.values())
        s1 = binarize_score(vals[0])
        s2 = binarize_score(vals[1])
        kappa_pairs.append((s1, s2))
        valid_videos.append(vid)

    if len(kappa_pairs) == 0:
        logger.error("No valid video pairs found for Kappa calculation.")
        sys.exit(1)

    # Calculate Kappa
    kappa_value = calculate_cohens_kappa(kappa_pairs)

    logger.info(f"Calculated Cohen's Kappa: {kappa_value:.4f} (Threshold: {KAPPA_THRESHOLD})")

    # Prepare report
    report = {
        "task_id": "T011b",
        "status": "completed" if kappa_value >= KAPPA_THRESHOLD else "failed",
        "kappa_value": round(kappa_value, 4),
        "threshold": KAPPA_THRESHOLD,
        "total_videos_pilot": len(video_ratings),
        "valid_pairs_analyzed": len(kappa_pairs),
        "skipped_videos": skipped_videos,
        "message": "Annotation agreement sufficient." if kappa_value >= KAPPA_THRESHOLD else "Insufficient Annotation Agreement"
    }

    # Write report
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)

    logger.info(f"Kappa report written to {OUTPUT_FILE}")

    # HARD HALT LOGIC
    if kappa_value < KAPPA_THRESHOLD:
        print("Insufficient Annotation Agreement")
        sys.exit(1)

    sys.exit(0)


if __name__ == "__main__":
    validate_kappa()
