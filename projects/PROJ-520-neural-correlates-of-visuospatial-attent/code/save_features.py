def save_feature_matrix(features: pd.DataFrame, output_path: str):
    """
    Save the feature matrix to a CSV file.
    Ensures the file is written to disk.
    """
    if features is None or features.empty:
        raise ValueError("Feature matrix is empty or None.")

    # Ensure output directory exists
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)

    features.to_csv(output_path, index=False)
    logger.info(f"Feature matrix saved to {output_path} with shape {features.shape}")

    # Verify file exists and has content
    if not os.path.exists(output_path):
        raise FileNotFoundError(f"Failed to create file at {output_path}")
    
    # Check file size
    if os.path.getsize(output_path) == 0:
        raise RuntimeError(f"File {output_path} was created but is empty.")

def save_feature_metadata(metadata: Dict[str, Any], output_path: str):
    """
    Save feature metadata to a JSON file.
    """
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w') as f:
        json.dump(metadata, f, indent=2)
    logger.info(f"Feature metadata saved to {output_path}")

