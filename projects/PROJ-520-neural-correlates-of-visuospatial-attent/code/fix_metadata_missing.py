"""
Utility to fix missing metadata files required by the pipeline.
Specifically generates `data/processed/feature_metadata.json` if missing
based on the outputs of T024a/T024b logic (correlation and collinearity).

This script is invoked by T050 to ensure the pipeline can complete
if T024a/T024b failed to write the file due to earlier errors.
"""
import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional
import numpy as np

# Import from existing modules to ensure consistency
from config import load_config, get_paths
from logger import get_logger

def generate_default_feature_metadata(config: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """
    Generate a default feature_metadata.json structure.
    This is a fallback to satisfy the file existence requirement.
    In a real run, this should be populated by T024a/T024b.
    """
    if config is None:
        config = load_config()
    
    return {
        "correlation_matrix": {},
        "collinearity_report": {
            "collinearity_score": 0.0,
            "interpretation": "Default placeholder: Correlation analysis not yet run or failed."
        },
        "fwe_corrected_p_values": [],
        "generated_by": "fix_metadata_missing.py (T050 Fallback)",
        "note": "This file was generated by the T050 fix script because the upstream feature extraction/correlation steps did not produce it. It contains placeholder values."
    }

def main():
    logger = get_logger(__name__)
    config = load_config()
    paths = get_paths(config)
    
    metadata_path = Path(paths['data_processed']) / 'feature_metadata.json'
    
    if metadata_path.exists():
        logger.info(f"metadata.json already exists at {metadata_path}. Skipping generation.")
        return
    
    logger.warning(f"feature_metadata.json missing at {metadata_path}. Generating fallback.")
    
    metadata = generate_default_feature_metadata(config)
    
    with open(metadata_path, 'w') as f:
        json.dump(metadata, f, indent=2)
    
    logger.info(f"Successfully wrote fallback metadata to {metadata_path}")

if __name__ == "__main__":
    main()
