"""
T024: Document electrode collinearity and correlation structure.

This script computes the correlation matrix and collinearity diagnostics (VIF)
for the feature matrix generated by T023. It outputs a JSON metadata file
documenting the correlation structure to `data/processed/feature_metadata.json`.
"""
import os
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional
import numpy as np
import pandas as pd
from scipy import stats

# Import project utilities
from config import get_paths, get_seed
from logging_config import get_pipeline_logger, log_stage_start, log_stage_end

# Constants
VIF_THRESHOLD = 5.0  # Common threshold for multicollinearity concern

def load_feature_matrix(csv_path: Path) -> pd.DataFrame:
    """Load the feature matrix from CSV."""
    if not csv_path.exists():
        raise FileNotFoundError(f"Feature matrix not found at {csv_path}")
    df = pd.read_csv(csv_path)
    # Ensure numeric columns are float
    numeric_cols = df.select_dtypes(include=[np.number]).columns
    df[numeric_cols] = df[numeric_cols].astype(np.float64)
    return df

def compute_correlation_matrix(df: pd.DataFrame) -> Dict[str, Any]:
    """Compute Pearson correlation matrix for numeric columns."""
    numeric_df = df.select_dtypes(include=[np.number])
    if numeric_df.empty:
        return {"error": "No numeric columns found"}
    
    corr_matrix = numeric_df.corr(method='pearson')
    
    # Convert to serializable format
    corr_dict = corr_matrix.to_dict()
    
    # Identify high correlations (absolute value > 0.8)
    high_corr_pairs = []
    cols = corr_matrix.columns
    for i in range(len(cols)):
        for j in range(i + 1, len(cols)):
            val = corr_matrix.iloc[i, j]
            if abs(val) > 0.8:
                high_corr_pairs.append({
                    "feature_1": cols[i],
                    "feature_2": cols[j],
                    "correlation": float(val),
                    "strength": "high" if abs(val) > 0.9 else "moderate"
                })
    
    return {
        "correlation_matrix": corr_dict,
        "high_correlation_pairs": high_corr_pairs,
        "matrix_shape": list(corr_matrix.shape)
    }

def compute_variance_inflation_factors(df: pd.DataFrame) -> Dict[str, Any]:
    """
    Compute Variance Inflation Factors (VIF) for each feature.
    VIF > 5 indicates potential multicollinearity.
    """
    numeric_df = df.select_dtypes(include=[np.number])
    if numeric_df.empty:
        return {"error": "No numeric columns found"}
    
    # Add intercept for VIF calculation
    X = numeric_df.values
    if X.shape[0] < X.shape[1] + 1:
        return {"error": "Not enough samples to compute VIF"}
    
    vif_data = []
    for i in range(X.shape[1]):
        # Calculate VIF for feature i
        # VIF = 1 / (1 - R^2) where R^2 is from regression of feature i on all others
        y = X[:, i]
        X_other = np.delete(X, i, axis=1)
        
        # Add intercept
        X_with_intercept = np.column_stack([np.ones(X_other.shape[0]), X_other])
        
        try:
            # OLS regression
            coeffs, residuals, rank, s = np.linalg.lstsq(X_with_intercept, y, rcond=None)
            
            # Calculate R-squared
            y_pred = X_with_intercept @ coeffs
            ss_res = np.sum((y - y_pred) ** 2)
            ss_tot = np.sum((y - np.mean(y)) ** 2)
            
            if ss_tot == 0:
                r_squared = 0
            else:
                r_squared = 1 - (ss_res / ss_tot)
            
            vif = 1 / (1 - r_squared) if r_squared < 1 else np.inf
        except np.linalg.LinAlgError:
            vif = np.inf
        
        vif_data.append({
            "feature": numeric_df.columns[i],
            "vif": float(vif) if np.isfinite(vif) else None,
            "concern": "high" if vif > VIF_THRESHOLD else "low"
        })
    
    # Sort by VIF descending
    vif_data.sort(key=lambda x: x["vif"] if x["vif"] is not None else 0, reverse=True)
    
    high_vif_features = [f for f in vif_data if f["concern"] == "high"]
    
    return {
        "vif_scores": vif_data,
        "high_vif_features": high_vif_features,
        "threshold": VIF_THRESHOLD
    }

def compute_feature_stats(df: pd.DataFrame) -> Dict[str, Any]:
    """Compute basic statistics for each feature."""
    numeric_df = df.select_dtypes(include=[np.number])
    stats_dict = {}
    
    for col in numeric_df.columns:
        stats_dict[col] = {
            "mean": float(numeric_df[col].mean()),
            "std": float(numeric_df[col].std()),
            "min": float(numeric_df[col].min()),
            "max": float(numeric_df[col].max()),
            "median": float(numeric_df[col].median()),
            "skewness": float(stats.skew(numeric_df[col])),
            "kurtosis": float(stats.kurtosis(numeric_df[col]))
        }
    
    return stats_dict

def run_correlation_analysis(
    input_csv: Path,
    output_json: Path,
    seed: int = 42
) -> Dict[str, Any]:
    """
    Main function to run correlation analysis and generate metadata.
    """
    log_stage_start("T024", "Correlation Analysis")
    
    try:
        # Load data
        logger = logging.getLogger("T024")
        logger.info(f"Loading feature matrix from {input_csv}")
        df = load_feature_matrix(input_csv)
        
        logger.info(f"Loaded {len(df)} epochs with {len(df.columns)} features")
        
        # Compute metrics
        corr_results = compute_correlation_matrix(df)
        vif_results = compute_variance_inflation_factors(df)
        feature_stats = compute_feature_stats(df)
        
        # Compile metadata
        metadata = {
            "task_id": "T024",
            "description": "Electrode collinearity and correlation structure documentation",
            "input_file": str(input_csv),
            "epoch_count": len(df),
            "feature_count": len(df.columns),
            "seed": seed,
            "correlation_analysis": corr_results,
            "collinearity_analysis": vif_results,
            "feature_statistics": feature_stats,
            "summary": {
                "high_correlation_pairs_count": len(corr_results.get("high_correlation_pairs", [])),
                "high_vif_features_count": len(vif_results.get("high_vif_features", [])),
                "max_correlation": max(
                    [abs(p["correlation"]) for p in corr_results.get("high_correlation_pairs", [])] or [0]
                ),
                "max_vif": max(
                    [f["vif"] for f in vif_results.get("vif_scores", []) if f["vif"] is not None] or [0]
                )
            }
        }
        
        # Ensure output directory exists
        output_json.parent.mkdir(parents=True, exist_ok=True)
        
        # Save metadata
        logger.info(f"Writing metadata to {output_json}")
        with open(output_json, 'w') as f:
            json.dump(metadata, f, indent=2)
        
        log_stage_end("T024", "Success")
        return metadata
        
    except Exception as e:
        log_stage_end("T024", "Failed", error=str(e))
        raise

def main():
    """Entry point for the script."""
    paths = get_paths()
    seed = get_seed()
    
    input_csv = paths["data_processed"] / "features_matrix.csv"
    output_json = paths["data_processed"] / "feature_metadata.json"
    
    # Ensure output directory exists
    output_json.parent.mkdir(parents=True, exist_ok=True)
    
    run_correlation_analysis(input_csv, output_json, seed)
    
    print(f"Correlation analysis complete. Metadata saved to {output_json}")

if __name__ == "__main__":
    main()
