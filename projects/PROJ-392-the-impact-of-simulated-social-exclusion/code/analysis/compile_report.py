def load_summary_stats(filepath: Path) -> List[Dict[str, Any]]:
    """Load summary statistics from CSV generated by summary_statistics task."""
    if not filepath.exists():
        raise FileNotFoundError(f"Summary statistics file not found: {filepath}")
    
    stats = []
    with open(filepath, 'r', newline='', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            stats.append(row)
    return stats

def load_ttest_results(filepath: Path) -> Dict[str, Any]:
    """Load t-test results from JSON generated by group_analysis task."""
    if not filepath.exists():
        raise FileNotFoundError(f"T-test results file not found: {filepath}")
    
    with open(filepath, 'r', encoding='utf-8') as f:
        return json.load(f)

def load_preprocessing_metrics(filepath: Path) -> Dict[str, Any]:
    """Load preprocessing metrics from JSON."""
    if not filepath.exists():
        logger.warning(f"Preprocessing metrics file not found: {filepath}")
        return {"completion_rate": 0.0, "total_subjects": 0, "processed_subjects": 0}
    
    with open(filepath, 'r', encoding='utf-8') as f:
        return json.load(f)

