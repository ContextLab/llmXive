"""
Contract test for metric output schema (User Story 2).

This test verifies that the output of the metric computation pipeline
strictly adheres to the defined schema for centrality and synchrony metrics.
It ensures that required fields, data types, and structural constraints
are met before the data is passed to the analysis stage (US3).
"""

import os
import json
import pytest
import pandas as pd
import numpy as np
from pathlib import Path

# Project root for relative path resolution
PROJECT_ROOT = Path(__file__).parent.parent.parent
DATA_DIR = PROJECT_ROOT / "data"
PROCESSED_DIR = DATA_DIR / "processed"

# Expected schema definitions based on specs/001-impact-of-network-centrality-on-neural-synchrony/contracts/analysis-results.schema.yaml
# and the requirements of US2 (T020-T023)
CENTRILITY_SCHEMA_REQUIRED_FIELDS = [
    "subject_id",
    "node_id",
    "degree_centrality",
    "betweenness_centrality",
    "eigenvector_centrality"
]

SYNCHRONY_SCHEMA_REQUIRED_FIELDS = [
    "subject_id",
    "node_id",
    "mean_abs_correlation"
]

def _validate_schema(df: pd.DataFrame, schema_fields: list, file_name: str):
    """
    Validates that a DataFrame contains all required fields and correct types.

    Args:
        df: The DataFrame to validate.
        schema_fields: List of required column names.
        file_name: Name of the file being validated (for error messages).
    """
    # Check columns
    missing_cols = set(schema_fields) - set(df.columns)
    assert not missing_cols, f"Schema violation in {file_name}: Missing columns {missing_cols}"

    # Check data types for numeric fields
    numeric_fields = [f for f in schema_fields if f != "subject_id" and f != "node_id"]
    for field in numeric_fields:
        if not np.issubdtype(df[field].dtype, np.number):
            # Allow object if it can be converted, but strictly prefer numeric
            try:
                df[field] = pd.to_numeric(df[field], errors='raise')
            except (ValueError, TypeError):
                raise AssertionError(
                    f"Schema violation in {file_name}: Column '{field}' is not numeric. "
                    f"Found dtype: {df[field].dtype}"
                )

    # Check for NaN values in critical numeric columns
    for field in numeric_fields:
        if df[field].isna().any():
            raise AssertionError(
                f"Schema violation in {file_name}: Column '{field}' contains NaN values."
            )

@pytest.mark.contract
def test_metric_schema():
    """
    Contract test: Verifies that all generated metric CSV files in data/processed
    conform to the expected schema.

    This test iterates through:
    1. centrality_<subject_id>.csv
    2. synchrony_<subject_id>.csv

    It asserts that:
    - Files exist (if data has been generated by US1/US2).
    - Required columns are present.
    - Numeric data is valid (no NaNs, correct types).
    - Subject IDs are consistent.
    """
    if not PROCESSED_DIR.exists():
        # If the directory doesn't exist yet, we skip or fail depending on pipeline state.
        # For a contract test in a CI/CD pipeline, if the previous stage (US2) is expected
        # to have run, this should be a hard failure.
        pytest.fail("Processed data directory does not exist. US2 (Metric Computation) has not run.")

    centrality_files = list(PROCESSED_DIR.glob("centrality_*.csv"))
    synchrony_files = list(PROCESSED_DIR.glob("synchrony_*.csv"))

    # We expect at least one file if the pipeline has run, but the task description
    # implies we are testing the schema of the *output* of US2.
    # If no files exist, it means US2 hasn't produced output yet.
    if not centrality_files and not synchrony_files:
        pytest.skip("No metric files found. US2 output not yet generated.")

    # Validate Centrality Files
    for file_path in centrality_files:
        try:
            df = pd.read_csv(file_path)
            _validate_schema(df, CENTRILITY_SCHEMA_REQUIRED_FIELDS, file_path.name)
            
            # Additional contract checks
            assert df["node_id"].notna().all(), f"node_id cannot be null in {file_path.name}"
            assert df["subject_id"].notna().all(), f"subject_id cannot be null in {file_path.name}"
            
            # Verify centrality ranges (0 to 1 for normalized, or >= 0)
            # Degree centrality is often normalized to [0, 1] in networkx
            if "degree_centrality" in df.columns:
                assert (df["degree_centrality"] >= 0).all(), "Degree centrality must be non-negative"
            
            # Betweenness is >= 0
            if "betweenness_centrality" in df.columns:
                assert (df["betweenness_centrality"] >= 0).all(), "Betweenness centrality must be non-negative"

        except Exception as e:
            pytest.fail(f"Contract test failed for {file_path.name}: {str(e)}")

    # Validate Synchrony Files
    for file_path in synchrony_files:
        try:
            df = pd.read_csv(file_path)
            _validate_schema(df, SYNCHRONY_SCHEMA_REQUIRED_FIELDS, file_path.name)

            # Verify synchrony range (Correlation absolute value is [0, 1])
            assert (df["mean_abs_correlation"] >= 0).all(), "Mean absolute correlation must be non-negative"
            assert (df["mean_abs_correlation"] <= 1).all(), "Mean absolute correlation cannot exceed 1"

        except Exception as e:
            pytest.fail(f"Contract test failed for {file_path.name}: {str(e)}")

    # If we reach here, all existing files passed the schema contract.
    assert True, "All metric output files passed schema validation."