"""Static enforcement guard tests (spec 026, Slice 8 task 1; hardened post-review).

``enforcement.py`` is the guard that must be in place BEFORE the legacy pin
tables (``DEFAULT_MODEL`` / ``MODEL_FALLBACKS`` / ``PAID_FALLBACK_MODELS`` /
``KNOWN_FREE_MODELS``) are deleted, so a regression is caught by a failing
test rather than by their absence. It has two independent checks:

1. A **pin scan** — reuses ``inventory.py``'s AST detector (no second
   detector; Constitution I) and flags EVERY production ``migration_target``
   entry on the live tree, unconditionally. Sanction can ONLY come from a
   reviewed code allowlist (``inventory._CANONICAL_FILES`` /
   ``_CANONICAL_SYMBOLS``) — never from the committed manifest, which is a
   GENERATED artifact regenerated by the SAME detector this scan calls. An
   earlier version of this guard treated manifest membership as sanction,
   which is circular: landing a pin and then running
   ``python -m llmxive.model_selection.inventory`` (the documented, required
   post-move workflow) made the pin its own permission slip. See
   ``test_pin_survives_manifest_regeneration_the_laundering_bypass_is_closed``
   for the reproduction + regression guard.
2. A **retired-symbol-reference scan** — the Slice-7 gate historically missed
   ``from llmxive.backends.router import DEFAULT_MODEL`` because it only
   looked for literal pins, not references. This flags any production import,
   Name/Attribute *usage* (Load context), or Name/Attribute *assignment*
   (Store context — e.g. ``DEFAULT_MODEL = _choose_at_runtime()``) of one of
   the four retired symbol names, in EVERY production file. An earlier
   version exempted ``backends/router.py`` / ``backends/dartmouth.py`` as the
   symbols' "owner files" — correct while those files defined the symbols,
   but a blind spot once S8-T2/T3 deleted the definitions: those are now the
   two files most likely to regrow a pin, and the exemption would have hidden
   exactly that. The exemption is gone; every production file is scanned.
"""

from __future__ import annotations

import json
from pathlib import Path
from textwrap import dedent

import pytest

from llmxive.model_selection.enforcement import (
    RETIRED_PIN_SYMBOLS,
    find_pin_violations,
    find_retired_symbol_references,
    find_violations,
)
from llmxive.model_selection.inventory import MANIFEST_JSON, write_manifest

REPO_ROOT = Path(__file__).resolve().parents[2]


def _write(path: Path, body: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dedent(body).lstrip("\n"))
    return path


# --- real-repo gate --------------------------------------------------------


def test_zero_unsanctioned_pins_on_the_real_tree():
    """The gate itself: on the current, real tree there must be zero pin
    violations and zero retired-symbol-reference violations. This must stay
    green through Slice 8 and only shrink further as pins are deleted."""
    violations = find_violations(REPO_ROOT)
    assert violations == []


def test_real_manifest_exists_but_is_not_consulted_for_suppression():
    """The committed manifest is a real, checked artifact (regenerated by the
    documented ``python -m llmxive.model_selection.inventory`` workflow) —
    but ``find_pin_violations`` must give the identical answer on the real
    tree whether or not that file happens to exist, because it is never
    read as a sanction source any more."""
    assert (REPO_ROOT / MANIFEST_JSON).exists()
    assert find_pin_violations(REPO_ROOT) == []


# --- proof the scanner can actually fail (planted violations) --------------


def test_find_pin_violations_catches_a_planted_literal_pin(tmp_path):
    """A brand-new production file that pins a raw model id must be
    reported. Proves the pin-literal path of the scanner is live, not a
    rubber stamp."""
    _write(
        tmp_path / "src/llmxive/pipeline/rogue.py",
        '''
        def summarize(text):
            return chat(text, model="qwen.qwen3.5-122b")
        ''',
    )

    violations = find_pin_violations(tmp_path)

    assert len(violations) == 1
    (v,) = violations
    assert v["file"] == "src/llmxive/pipeline/rogue.py"
    assert v["models"] == ["qwen.qwen3.5-122b"]


def test_pin_survives_manifest_regeneration_the_laundering_bypass_is_closed(tmp_path):
    """THE Finding-1 blocker, reproduced and closed.

    Pre-fix behaviour: a planted pin was reported BEFORE
    ``python -m llmxive.model_selection.inventory`` regenerated the manifest,
    but AFTER regeneration the pin was silently laundered (0 violations) —
    because the (now-regenerated) manifest containing the pin was itself
    treated as the pin's sanction. That is exactly backwards: the manifest is
    GENERATED from the live tree, so a pin can never be excused by its own
    presence in a freshly-regenerated copy of the tree it came from.

    Post-fix: the violation must be reported identically before AND after
    the documented regeneration workflow runs.
    """
    _write(
        tmp_path / "src/llmxive/pipeline/rogue.py",
        '''
        def summarize(text):
            return chat(text, model="qwen.qwen3.5-122b")
        ''',
    )

    before = find_pin_violations(tmp_path)
    assert len(before) == 1
    assert before[0]["file"] == "src/llmxive/pipeline/rogue.py"

    # Exactly the documented post-pin-move workflow: regenerate the manifest.
    (tmp_path / Path(MANIFEST_JSON).parent).mkdir(parents=True, exist_ok=True)
    write_manifest(tmp_path)
    regenerated = json.loads((tmp_path / MANIFEST_JSON).read_text())
    # Sanity: the regenerated manifest DOES now carry the pin as a
    # migration_target row — this is the row that used to launder the
    # violation away.
    assert any(
        e["file"] == "src/llmxive/pipeline/rogue.py" and e["category"] == "migration_target"
        for e in regenerated["entries"]
    )

    after = find_pin_violations(tmp_path)
    assert len(after) == 1
    assert after[0]["file"] == "src/llmxive/pipeline/rogue.py"


def test_find_retired_symbol_references_catches_a_planted_import(tmp_path):
    """This is the Slice-7 regression itself, replayed: a production module
    imports ``DEFAULT_MODEL`` from the (still-existing) router module. A
    literal-only scanner reports zero rows for this file; the reference scan
    must not."""
    _write(
        tmp_path / "src/llmxive/backends/router.py",
        '''
        DEFAULT_MODEL: str = "qwen.qwen3.5-122b"
        ''',
    )
    _write(
        tmp_path / "src/llmxive/convergence/reviewspecs.py",
        '''
        from llmxive.backends.router import DEFAULT_MODEL


        def build(model=DEFAULT_MODEL):
            return model
        ''',
    )

    refs = find_retired_symbol_references(tmp_path)

    assert any(
        r["file"] == "src/llmxive/convergence/reviewspecs.py"
        and r["symbol"] == "DEFAULT_MODEL"
        and r["kind"] == "retired_symbol_import"
        for r in refs
    )
    assert any(
        r["file"] == "src/llmxive/convergence/reviewspecs.py"
        and r["symbol"] == "DEFAULT_MODEL"
        and r["kind"] == "retired_symbol_reference"
        for r in refs
    )


def test_find_retired_symbol_references_catches_a_planted_assignment_in_router(tmp_path):
    """The second Finding-1 hole, reproduced and closed: S8-T2/T3 already
    deleted the retired-pin DEFINITIONS from ``router.py`` / ``dartmouth.py``,
    so those files are no longer exempt (the old
    ``_RETIRED_SYMBOL_OWNER_FILES`` blind spot is deleted). A retired name
    REGROWN there via a plain assignment — not an import, so the import-only
    scan would miss it — must be caught."""
    _write(
        tmp_path / "src/llmxive/backends/router.py",
        '''
        def _choose_at_runtime():
            return "openai.gpt-oss-120b"


        DEFAULT_MODEL = _choose_at_runtime()
        ''',
    )

    refs = find_retired_symbol_references(tmp_path)

    assert any(
        r["file"] == "src/llmxive/backends/router.py"
        and r["symbol"] == "DEFAULT_MODEL"
        and r["kind"] == "retired_symbol_assignment"
        for r in refs
    )


